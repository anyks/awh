/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/toml/writer.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция сборки текста настроек заданными настройками записи
 *
 * @param title    название набора настроек записи
 * @param settings настройки записи текста настроек
 *
 */
static void build(const string & title, const codec::toml::writer_t::settings_t & settings) noexcept {
	// Создаём объект записи текста настроек
	codec::toml::writer_t writer(::logger(), settings);
	// Выполняем запись примечания
	writer.comment("собрано приложением");
	// Выполняем запись имени ключа пары верхнего уровня
	writer.key("title");
	// Выполняем запись строкового значения пары
	writer.text("пример");
	// Выполняем запись объявления таблицы
	writer.table("server");
	// Выполняем запись имени ключа пары с обозначением узла
	writer.key("host");
	// Выполняем запись строкового значения пары
	writer.text("127.0.0.1");
	// Выполняем запись имени ключа пары
	writer.key("port");
	// Выполняем запись целого числа
	writer.integer(8080);
	// Выполняем дописывание примечания к записанной строке
	writer.trailing("порт службы");
	// Выполняем запись имени ключа пары
	writer.key("mask");
	/**
	 * Выполняем запись целого числа шестнадцатеричной системой счисления
	 *
	 * @note Система счисления сохраняется записью: выбрана она человеком
	 */
	writer.integer(255, codec::toml::radix_t::HEX);
	// Выполняем запись имени ключа пары
	writer.key("path");
	/**
	 * Выполняем запись строкового значения дословной оградой
	 *
	 * @note Ограда эта управляющих последовательностей не признаёт, и обратная
	 *       косая черта записывается собою
	 */
	writer.text("C:\\путь\\без\\ограды", codec::toml::string_t::LITERAL);
	// Выполняем запись имени ключа пары
	writer.key("hosts");
	// Выполняем запись начала перечня значений несколькими строками
	writer.arrayOpen(true);
	// Выполняем запись первого значения перечня
	writer.text("первый");
	// Выполняем запись второго значения перечня
	writer.text("второй");
	// Выполняем запись конца перечня значений
	writer.arrayClose();
	// Выполняем запись имени ключа пары
	writer.key("point");
	// Выполняем запись начала встроенной таблицы
	writer.inlineOpen();
	// Выполняем запись имени ключа пары встроенной таблицы
	writer.key("x");
	// Выполняем запись значения пары встроенной таблицы
	writer.integer(1);
	// Выполняем запись имени ключа пары встроенной таблицы
	writer.key("y");
	// Выполняем запись значения пары встроенной таблицы
	writer.integer(2);
	// Выполняем запись конца встроенной таблицы
	writer.inlineClose();
	// Выполняем запись объявления очередной таблицы набора таблиц
	writer.arrayTable("products");
	// Выполняем запись имени ключа пары
	writer.key("name");
	// Выполняем запись значения пары
	writer.text("гвоздь");
	// Выводим название набора настроек записи
	cout << "== " << title << " ==" << endl;
	/**
	 * Если сборка текста настроек завершилась ошибкой
	 */
	if(writer.error() != codec::toml::error_t::NONE)
		// Выводим сведения об обнаруженной ошибке записи
		cout << "ошибка: " << codec::toml::message(writer.error()) << endl;
	// Выводим собранный текст настроек
	else cout << writer.text();
	// Выводим знак конца строки
	cout << endl;
}
/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Выполняем сборку текста настроек настройками по умолчанию
	::build("настройки по умолчанию", codec::toml::writer_t::settings_t());
	// Собираемые настройки записи текста настроек
	codec::toml::writer_t::settings_t settings;
	// Задаём запись отступа перед парами таблицы
	settings.indent = true;
	// Отменяем запись пустой строки перед объявлением таблицы
	settings.separated = false;
	// Выполняем сборку текста настроек с отступами
	::build("отступы без пустых строк", settings);
	// Создаём объект записи текста настроек
	codec::toml::writer_t writer(::logger());
	// Выполняем запись имени ключа пары
	writer.key("value");
	/**
	 * Если запись отрицательного числа шестнадцатеричной системой отвергнута
	 *
	 * @note Описание отводит знак числа лишь десятичной записи, и сменить систему
	 *       счисления молча запись не вправе
	 */
	if(!writer.integer(-1, codec::toml::radix_t::HEX))
		// Выводим сведения об обнаруженной ошибке записи
		cout << "число отвергнуто: " << codec::toml::message(writer.error()) << endl;
	// Выполняем сброс записи в исходное состояние
	writer.clear();
	// Задаём запрет смены ограды имени и значения
	settings = codec::toml::writer_t::settings_t();
	// Запрещаем смену ограды имени и значения
	settings.promote = false;
	// Выполняем установку настроек записи текста настроек
	writer.settings(settings);
	// Выполняем запись имени ключа пары
	writer.key("value");
	/**
	 * Если запись значения с одинарной кавычкой дословной оградой отвергнута
	 *
	 * @note Дословная ограда одинарной кавычки не несёт: при дозволенной смене
	 *       ограды запись взяла бы основную, а при запрещённой отвечает отказом
	 */
	if(!writer.text("it's", codec::toml::string_t::LITERAL))
		// Выводим сведения об обнаруженной ошибке записи
		cout << "значение отвергнуто: " << codec::toml::message(writer.error()) << endl;
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
