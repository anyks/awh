/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/xml/document.hpp>

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция вывода итога разбора числа
 *
 * @tparam T тип числа результата разбора
 *
 * @param title   название разбираемого значения
 * @param success признак успешного разбора
 * @param value   разобранное число
 *
 */
template <typename T>
static void print(const string & title, const bool success, const T value) noexcept {
	// Выводим название разбираемого значения
	cout << title << ": ";
	/**
	 * Если разбор выполнить удалось
	 */
	if(success)
		// Выводим разобранное число
		cout << value << endl << flush;
	// Выводим сообщение об отказе разбора
	else cout << "отказ" << endl << flush;
}
/**
 * @brief Главная функция приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]){
	// Ответ службы, каким его отдаёт устройство по договору UPnP
	const string data =
		"<?xml version=\"1.0\"?>"
		"<mapping index=\"3\" enabled=\"1\">"
		"<NewExternalPort>8080</NewExternalPort>"
		"<NewInternalPort>  8080  </NewInternalPort>"
		"<NewLeaseDuration>0</NewLeaseDuration>"
		"<NewEnabled>true</NewEnabled>"
		"<Load>54.33</Load>"
		"<Uptime>1.5e3</Uptime>"
		"<Bytes>-42</Bytes>"
		"<Description>Сервер ANYKS</Description>"
		"<Overflow>70000</Overflow>"
		"<Tail>8080/tcp</Tail>"
		"</mapping>";
	// Создаём объект дерева разметки
	codec::xml::document_t document;
	/**
	 * Если разбор ответа службы выполнить не удалось
	 */
	if(!document.parse(data)){
		// Выводим сообщение об ошибке разбора с местом её обнаружения
		cout << "Ошибка: " << codec::xml::message(document.error())
			 << " (строка " << document.errorLocation().line
			 << ", столбец " << document.errorLocation().column << ")" << endl << flush;
		// Выводим результат работы приложения
		return EXIT_FAILURE;
	}
	// Получаем корневой узел дерева разметки
	const codec::xml::node_t root = document.element();
	// Печатаем заголовок разбора содержимого узлов числами
	cout << " ======== Содержимое узлов числами ======== " << endl << flush;
	/**
	 * Выполняем разбор содержимого узлов числами
	 *
	 * @note Тип разбора определяется типом запрошенного значения, отдельного указания
	 *       не требуя: целое со знаком, целое без знака, число с плавающей точкой и
	 *       логическое значение разбираются одним и тем же способом
	 */
	{
		// Значение внешнего порта перенаправления
		uint16_t port = 0;
		// Выполняем разбор внешнего порта перенаправления
		::print("Внешний порт", root.child("NewExternalPort").value(port), port);
		/**
		 * Выполняем разбор внутреннего порта перенаправления
		 *
		 * @note Пробельная обвязка отбрасывается: при записи с отступами она в
		 *       содержимом появляется сама собой
		 */
		::print("Внутренний порт (с обвязкой)", root.child("NewInternalPort").value(port), port);
		// Значение занятости устройства
		double load = 0.;
		// Выполняем разбор занятости устройства
		::print("Занятость", root.child("Load").value(load), load);
		// Выполняем разбор срока работы устройства в показательной записи
		::print("Срок работы", root.child("Uptime").value(load), load);
		// Значение счётчика с отрицательным числом
		int32_t bytes = 0;
		// Выполняем разбор счётчика с отрицательным числом
		::print("Счётчик", root.child("Bytes").value(bytes), bytes);
		// Значение признака включения перенаправления
		bool enabled = false;
		/**
		 * Выполняем разбор признака включения перенаправления
		 *
		 * @note Признаётся запись по договору XSD: «true», «false», «1» и «0»
		 */
		::print("Включено", root.child("NewEnabled").value(enabled), enabled);
	}
	// Выводим пустую строку
	cout << endl << flush;
	// Печатаем заголовок разбора значений атрибутов числами
	cout << " ======== Значения атрибутов числами ======== " << endl << flush;
	/**
	 * Выполняем разбор значений атрибутов числами
	 */
	{
		// Значение порядкового номера перенаправления
		uint32_t index = 0;
		// Выполняем разбор порядкового номера перенаправления
		::print("Номер", root.value(index, "index"), index);
		// Значение признака включения перенаправления
		bool enabled = false;
		// Выполняем разбор признака включения перенаправления
		::print("Признак включения", root.value(enabled, "enabled"), enabled);
	}
	// Выводим пустую строку
	cout << endl << flush;
	// Печатаем заголовок отклонения неправильно построенного содержимого
	cout << " ======== Отклонение неправильно построенного содержимого ======== " << endl << flush;
	/**
	 * Выполняем проверку отклонения неправильно построенного содержимого
	 *
	 * @note Признаком успеха служит выданное значение, а не разобранное число: без
	 *       этого содержимое «abc» не отличалось бы от содержимого с числом нуль, а
	 *       ошибка в чужом ответе прошла бы незамеченной
	 */
	{
		// Значение разбираемого целого числа
		int32_t value = 0;
		// Выполняем разбор содержимого, числом не являющегося
		::print("Описание числом", root.child("Description").value(value), value);
		// Выполняем разбор содержимого с остатком за числом
		::print("Остаток за числом", root.child("Tail").value(value), value);
		// Выполняем разбор содержимого отсутствующего узла
		::print("Отсутствующий узел", root.child("Missing").value(value), value);
		// Выполняем разбор значения отсутствующего атрибута
		::print("Отсутствующий атрибут", root.value(value, "missing"), value);
		// Значение разбираемого целого числа малой разрядности
		uint16_t port = 0;
		/**
		 * Выполняем разбор числа, в запрошенный тип не помещающегося
		 *
		 * @note Усечение здесь недопустимо: 70000 в двухоктетное поле не помещается,
		 *       и приведение такого числа к 4464 скрыло бы ошибку в исходном тексте
		 */
		::print("Выход за пределы типа", root.child("Overflow").value(port), port);
		// Значение разбираемого целого числа большей разрядности
		uint32_t wide = 0;
		// Выполняем разбор того же числа в тип большей разрядности
		::print("То же число в тип пошире", root.child("Overflow").value(wide), wide);
	}
	// Выводим пустую строку
	cout << endl << flush;
	// Печатаем заголовок разбора со значением по умолчанию
	cout << " ======== Разбор со значением по умолчанию ======== " << endl << flush;
	/**
	 * Выполняем разбор со значением по умолчанию
	 *
	 * @note Способ предназначен для необязательных полей, где отсутствие значения и
	 *       есть умолчание: проверять итог разбора там незачем
	 */
	{
		// Выводим разобранный срок действия перенаправления
		cout << "Срок действия: " << root.child("NewLeaseDuration").number <uint32_t> (3600) << endl << flush;
		// Выводим значение по умолчанию для отсутствующего узла
		cout << "Отсутствующий узел: " << root.child("Missing").number <uint32_t> (3600) << endl << flush;
		// Выводим разобранное значение атрибута
		cout << "Номер из атрибута: " << root.number <uint32_t> ("index", 0) << endl << flush;
		// Выводим значение по умолчанию для отсутствующего атрибута
		cout << "Отсутствующий атрибут: " << root.number <uint32_t> ("missing", 1) << endl << flush;
	}
	// Выводим результат работы приложения
	return EXIT_SUCCESS;
}
