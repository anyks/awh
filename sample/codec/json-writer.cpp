/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <sys/log.hpp>
#include <codec/json/json.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён контейнеров данных
 */
using namespace awh::codec;

/**
 * @brief Метод сборки текста документа
 *
 * @details Документ собирается значение за значением, дерева при этом не заводится
 *          вовсе: писателю довольно знать, что открыто, а что закрыто
 *
 * @param writer объект записи текста документа
 *
 */
static void assemble(json::writer_t & writer) noexcept {
	// Выполняем открытие объекта документа
	writer.object();
	// Записываем имя поля службы
	writer.key("служба");
	// Записываем название службы
	writer.value("заказы");
	// Записываем имя поля версии
	writer.key("версия");
	// Записываем версию службы
	writer.value(static_cast <int64_t> (3));
	// Записываем имя поля предела
	writer.key("предел");
	/**
	 * Записываем предел службы
	 *
	 * @note Число с плавающей запятой записывается кратчайшей записью, читающейся
	 *       обратно тем же самым числом: подбора точности пробами не ведётся
	 */
	writer.value(12.5);
	// Записываем имя поля опознавателя
	writer.key("опознаватель");
	/**
	 * Записываем опознаватель записи
	 *
	 * @note Целое записывается целым и не теряет точности за пределом 2^53, где и
	 *       живут опознаватели записей: запись их видом с плавающей запятой округлила
	 *       бы их молча
	 */
	writer.value(static_cast <int64_t> (9007199254740993LL));
	// Записываем имя поля примечания
	writer.key("примечание");
	/**
	 * Записываем содержимое примечания
	 *
	 * @note Знаки, стандартом отменяемые, писатель отменяет сам: кавычки, обратную
	 *       косую черту, перевод строки и управляющие знаки
	 */
	writer.value("строка с \"кавычками\",\nпереводом строки и знаком \\");
	// Записываем имя поля узлов
	writer.key("узлы");
	// Выполняем открытие массива узлов
	writer.array();
	/**
	 * Выполняем сборку узлов службы
	 */
	for(int64_t i = 0; i < 3; i++){
		// Выполняем открытие объекта узла
		writer.object();
		// Записываем имя поля имени узла
		writer.key("имя");
		// Записываем имя узла
		writer.value(string("узел-").append(to_string(i + 1)));
		// Записываем имя поля порта узла
		writer.key("порт");
		// Записываем порт узла
		writer.value(static_cast <int64_t> (8080 + i));
		// Записываем имя поля признака включения узла
		writer.key("включён");
		// Записываем признак включения узла
		writer.value(i != 2);
		// Выполняем закрытие объекта узла
		writer.close();
	}
	// Выполняем закрытие массива узлов
	writer.close();
	// Записываем имя поля пустого значения
	writer.key("владелец");
	// Записываем пустое значение
	writer.null();
	// Выполняем закрытие объекта документа
	writer.close();
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	(void) argv;
	// Объект записи текста документа
	json::writer_t writer(::logger());
	// Выполняем сборку текста документа
	::assemble(writer);
	// Выводим заголовок сжатой записи
	cout << "Сжатая запись:" << endl;
	// Выводим собранный текст документа
	cout << writer.text() << endl;
	// Выполняем сброс записи текста документа
	writer.clear();
	// Получаем настройки записи текста документа
	json::writer_t::settings_t settings = writer.settings();
	/**
	 * Устанавливаем человекочитаемый вид записи
	 *
	 * @note Вид переключается настройкой, а не отдельным способом записи: собирающий
	 *       документ код от вида записи не зависит вовсе
	 */
	settings.format = json::format_t::PRETTY;
	// Устанавливаем величину отступа в знаках
	settings.indent = 2;
	// Выполняем установку настроек записи текста документа
	writer.settings(settings);
	// Выполняем сборку текста документа заново
	::assemble(writer);
	// Выводим заголовок человекочитаемой записи
	cout << endl << "Человекочитаемая запись:" << endl;
	// Выводим собранный текст документа
	cout << writer.text() << endl;
	// Выполняем сброс записи текста документа
	writer.clear();
	/**
	 * Устанавливаем сжатый вид записи
	 */
	settings.format = json::format_t::COMPACT;
	/**
	 * Разрешаем запись потока документов
	 *
	 * @note Без дозволения писатель отвергает второе значение верхнего уровня: текст
	 *       из нескольких документов подряд стандарту не отвечает, и записывается он
	 *       лишь по указанию потребителя
	 */
	settings.stream = true;
	// Выполняем установку настроек записи текста документа
	writer.settings(settings);
	/**
	 * Выполняем запись потока документов
	 */
	for(int64_t i = 1; i <= 3; i++){
		// Выполняем открытие объекта документа
		writer.object();
		// Записываем имя поля номера документа
		writer.key("номер");
		// Записываем номер документа
		writer.value(i);
		// Выполняем закрытие объекта документа
		writer.close();
		/**
		 * Выполняем завершение документа потока
		 *
		 * @note Завершение обязательно, а не удобства ради: оно и разделитель документов
		 *       записывает, и удостоверяет, что все вместилища закрыты. Без него запись
		 *       второго документа отвергается - два документа склеились бы в один текст
		 */
		writer.finish();
	}
	// Выводим заголовок записи потока документов
	cout << endl << "Поток документов NDJSON:" << endl;
	/**
	 * Выводим собранный поток документов
	 *
	 * @note Запись забирается переносом, а не копией: собранный текст переезжает к
	 *       вызывающему целиком, и писатель остаётся пустым
	 */
	cout << writer.take() << endl;
	// Выходим из приложения
	return EXIT_SUCCESS;
}
