/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/csv/writer.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция построения текста таблицы заданными настройками
 *
 * @param title    название разбираемого случая
 * @param settings настройки записи текста таблицы
 *
 */
static void build(const string & title, const codec::csv::writer_t::settings_t & settings) noexcept {
	// Объект записи текста таблицы
	codec::csv::writer_t writer(::logger(), settings);
	// Выполняем запись записи заголовка целиком
	writer.record(vector <string> {"имя", "цена", "описание"});
	// Выполняем запись поля записи
	writer.field("гвоздь");
	// Выполняем запись целого числа полем записи
	writer.number(static_cast <int64_t> (10));
	// Выполняем запись поля записи
	writer.field("обычный");
	// Выполняем завершение записи
	writer.record();
	/**
	 * Выполняем запись записи, поле которой несёт знак-разделитель
	 *
	 * @note Обрамление кавычками ставится по правилу настроек: правило `MINIMAL` берёт
	 *       в кавычки лишь поля, несущие разделитель, кавычку либо перевод строки
	 */
	writer.record(vector <string> {"молоток", "250", "с ручкой, деревянной"});
	// Выполняем запись записи, поле которой несёт перевод строки
	writer.record(vector <string> {"отвёртка", "120", "первая строка\nвторая строка"});
	// Выводим название разобранного случая
	cout << "== " << title << " ==" << endl;
	// Выводим записанный текст таблицы
	cout << writer.take();
	// Выводим отделитель разобранных случаев
	cout << endl;
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Настройки записи текста таблицы
	codec::csv::writer_t::settings_t settings;
	/**
	 * Задаём перевод строки, принятый в системах семейства UNIX
	 *
	 * @note Умолчанием взят возврат каретки с переводом строки, как велит RFC 4180
	 */
	settings.newline = codec::csv::newline_t::LF;
	// Выполняем построение текста таблицы правилом обрамления по надобности
	::build("кавычки по надобности", settings);
	// Задаём обрамление кавычками всех полей без разбора
	settings.quoting = codec::csv::quoting_t::ALL;
	// Выполняем построение текста таблицы обрамлением всех полей
	::build("кавычки у всех полей", settings);
	// Задаём обрамление кавычками всех полей, кроме записанных числом
	settings.quoting = codec::csv::quoting_t::NONNUMERIC;
	// Задаём знаком-разделителем точку с запятой
	settings.separator = ';';
	// Выполняем построение текста таблицы обрамлением полей нечисловых
	::build("кавычки у полей нечисловых, разделитель — точка с запятой", settings);
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
