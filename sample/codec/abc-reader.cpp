using namespace awh::codec;

/**
 * @brief Метод сборки разбираемой записи
 *
 * @param writer объект сборки бинарной записи
 * @return       признак успешной сборки записи
 *
 */
static bool assemble(abc::writer_t & writer) noexcept {
	// Выполняем открытие отображения записи
	if(!writer.mapBegin(static_cast <uint64_t> (3)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля службы
	if(!writer.text("служба"))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем название службы
	if(!writer.text("заказы"))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля груза
	if(!writer.text("груз"))
		// Выходим из метода: сборка отказала
		return false;
	// Выполняем открытие массива груза
	if(!writer.arrayBegin(static_cast <uint64_t> (4)))
		// Выходим из метода: сборка отказала
		return false;
	/**
	 * Перебираем значения груза
	 */
	for(uint64_t i = 1; i <= 4; i++){
		// Укладываем очередное значение груза
		if(!writer.number(i * 100))
			// Выходим из метода: сборка отказала
			return false;
	}
	// Выполняем закрытие массива груза
	if(!writer.arrayEnd())
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля отметки времени
	if(!writer.text("отметка"))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем отметку времени
	if(!writer.timestamp(static_cast <int64_t> (1755500000)))
		// Выходим из метода: сборка отказала
		return false;
	// Выполняем закрытие отображения записи
	return writer.mapEnd();
}
/**
 * @brief Метод вывода очередного события разбора
 *
 * @param reader объект чтения бинарной записи
 * @param depth  глубина вложенности события
 *
 */
static void report(const abc::reader_t & reader, const size_t depth) noexcept {
	// Выполняем получение значения текущего события
	const abc::reader_t::value_t value = reader.value();
	/**
	 * Выполняем отступ по глубине вложенности
	 */
	for(size_t i = 0; i < depth; i++)
		// Выводим отступ очередного уровня
		cout << "  ";
	/**
	 * Определяем вид текущего события разбора
	 */
	switch(static_cast <uint8_t> (reader.event())){
		// Если событием является имя поля отображения
		case static_cast <uint8_t> (abc::event_t::KEY):
			// Выводим имя поля отображения
			cout << "поле " << string(value.data) << ":" << endl;
		break;
		// Если событием является строка
		case static_cast <uint8_t> (abc::event_t::STRING):
			// Выводим содержимое строки
			cout << "строка \"" << string(value.data) << "\"" << endl;
		break;
		// Если событием является число
		case static_cast <uint8_t> (abc::event_t::NUMBER):
			// Выводим величину числа
			cout << "число " << value.number << endl;
		break;
		/**
		 * Если событием является отметка времени
		 *
		 * @note Вид этот приходит отдельным событием, а не числом: читающему не нужно
		 *       гадать, время перед ним либо просто целое
		 */
		case static_cast <uint8_t> (abc::event_t::TIME):
			// Выводим отметку времени
			cout << "время " << value.integer << endl;
		break;
		// Если событием является начало массива
		case static_cast <uint8_t> (abc::event_t::ARRAY_BEGIN):
			// Выводим начало массива с объявленным количеством значений
			cout << "массив из " << value.count << " знач." << endl;
		break;
		// Если событием является начало отображения
		case static_cast <uint8_t> (abc::event_t::MAP_BEGIN):
			// Выводим начало отображения с объявленным количеством пар
			cout << "отображение из " << value.count << " пар" << endl;
		break;
	}
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	(void) argv;
	// Объект сборки разбираемой записи
	abc::writer_t writer(::logger());
	// Получаем настройки сборки бинарной записи
	abc::writer_t::settings_t settings = writer.settings();
	/**
	 * Устанавливаем порог объявления размаха вместимого
	 *
	 * @note Настройка эта нужна ради пропуска: без метки размаха чтение обязано обойти
	 *       вместимое значение за значением, и пропуск отвечает отказом. Порог задаётся
	 *       в ЗНАЧЕНИЯХ, а не в октетах: размах в октетах при открытии вместимого ещё
	 *       не известен, а количество значений строгий вид записи объявляет наперёд
	 *
	 * @note По умолчанию настройка СНЯТА намеренно: метка размаха есть расширение
	 *       проволочной записи, и чтение, о ней не знающее, такую запись не разберёт
	 */
	settings.spanned = 2;
	// Выполняем установку настроек сборки бинарной записи
	writer.settings(settings);
	// Выполняем сборку разбираемой записи
	if(!::assemble(writer)){
		// Выводим сообщение об отказе сборки
		cout << "Сборка записи отказала: " << abc::message(writer.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Собранная запись
	const vector <uint8_t> & record = writer.record();
	// Объект чтения бинарной записи
	abc::reader_t reader(::logger());
	// Выводим заголовок разбора записи целиком
	cout << "Разбор записи целиком:" << endl;
	// Выполняем подачу записи разбирателю целиком
	if(!reader.feed(record.data(), record.size(), true)){
		// Выводим сообщение об отказе разбора
		cout << "Разбор записи отказал: " << abc::message(reader.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Глубина вложенности разбора
	size_t depth = 0;
	/**
	 * Снимаем события разбора с очереди выдачи
	 */
	while(reader.next()){
		// Если событием является конец вместимого
		if((reader.event() == abc::event_t::ARRAY_END) ||
		   (reader.event() == abc::event_t::MAP_END)){
			// Уменьшаем глубину вложенности разбора
			if(depth > 0)
				// Выполняем выход на уровень выше
				depth--;
			// Переходим к следующему событию разбора
			continue;
		}
		// Выводим очередное событие разбора
		::report(reader, depth);
		// Если событием является начало вместимого
		if((reader.event() == abc::event_t::ARRAY_BEGIN) ||
		   (reader.event() == abc::event_t::MAP_BEGIN))
			// Увеличиваем глубину вложенности разбора
			depth++;
	}
	// Выполняем сброс чтения бинарной записи
	reader.reset();
	/**
	 * Выполняем подачу той же записи кусками по три октета
	 *
	 * @note Разбор от нарезки на куски не зависит вовсе: события выходят те же и в том
	 *       же порядке, куда бы граница куска ни легла - хоть посреди строки, хоть
	 *       посреди объявления ширины числа
	 */
	cout << endl << "Разбор той же записи кусками по три октета:" << endl;
	// Количество событий, вышедших при подаче кусками
	size_t taken = 0;
	/**
	 * Перебираем куски записи
	 */
	for(size_t offset = 0; offset < record.size(); offset += 3){
		// Определяем размер очередного куска
		const size_t size = ((offset + 3) <= record.size() ? 3 : (record.size() - offset));
		// Определяем признак последнего куска записи
		const bool last = ((offset + size) >= record.size());
		// Выполняем подачу очередного куска разбирателю
		if(!reader.feed(record.data() + offset, size, last)){
			// Выводим сообщение об отказе разбора
			cout << "Разбор куска отказал: " << abc::message(reader.error()) << endl;
			// Выходим из приложения
			return EXIT_FAILURE;
		}
		/**
		 * Снимаем накопившиеся события разбора
		 */
		while(reader.next())
			// Выполняем учёт очередного события разбора
			taken++;
	}
	// Выводим количество вышедших событий разбора
	cout << "Событий вышло: " << taken << endl;
	// Выполняем сброс чтения бинарной записи
	reader.reset();
	/**
	 * @brief Опора прямой выдачи событий разбора
	 *
	 * @details Пропуск зовётся ТОЛЬКО из обработчика прямой выдачи, и это не удобство,
	 *          а необходимость: события копятся очередью, и к моменту снятия события с
	 *          неё разбор уходит вперёд - пропускать к тому времени уже нечего
	 *
	 */
	struct Sink {
		// Количество снятых событий разбора
		size_t counted = 0;
		// Количество состоявшихся пропусков
		size_t skipped = 0;
		// Количество снятых чисел записи
		size_t numbers = 0;
	} sink;
	// Выводим заголовок разбора с пропуском поддерева
	cout << endl << "Разбор с пропуском массива груза:" << endl;
	// Выполняем установку обработчика прямой выдачи событий разбора
	reader.handler([](void * context, abc::reader_t & reader, const abc::event_t event) noexcept -> void {
		// Выполняем получение опоры прямой выдачи событий
		Sink * sink = reinterpret_cast <Sink *> (context);
		// Выполняем учёт снятого события разбора
		sink->counted++;
		// Если снято число записи
		if(event == abc::event_t::NUMBER)
			// Выполняем учёт снятого числа записи
			sink->numbers++;
		// Если снято событие начала массива
		else if(event == abc::event_t::ARRAY_BEGIN){
			/**
			 * Выполняем пропуск массива целиком
			 *
			 * @note Пропуск снимает вместимое ОДНИМ сложением, не выдавая ни одного его
			 *       значения: читающему, какому нужны лишь два поля из тридцати, незачем
			 *       платить за разбор остальных
			 */
			if(reader.skip())
				// Выполняем учёт состоявшегося пропуска
				sink->skipped++;
		}
	}, & sink);
	// Выполняем подачу записи разбирателю целиком
	if(!reader.feed(record.data(), record.size(), true)){
		// Выводим сообщение об отказе разбора
		cout << "Разбор записи отказал: " << abc::message(reader.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Выводим количество снятых событий разбора
	cout << "  событий снято: " << sink.counted << endl;
	// Выводим количество состоявшихся пропусков
	cout << "  пропусков состоялось: " << sink.skipped << endl;
	/**
	 * Выводим количество снятых чисел записи
	 *
	 * @note Числа лежат внутри пропущенного массива, и до них разбор не дошёл вовсе:
	 *       нуль здесь и есть доказательство того, что пропуск состоялся, а не просто
	 *       ответил успехом
	 */
	cout << "  чисел снято: " << sink.numbers << " (все они лежали внутри массива)" << endl;
	// Выходим из приложения
	return EXIT_SUCCESS;
}
