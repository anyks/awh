/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/yaml/writer.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция построения текста документа заданными настройками
 *
 * @param title    название разбираемого случая
 * @param settings настройки записи текста документа
 *
 */
static void build(const string & title, const codec::yaml::writer_t::settings_t & settings) noexcept {
	// Объект записи текста документа
	codec::yaml::writer_t writer(::logger(), settings);
	// Выполняем открытие записываемого документа
	writer.document();
	// Выполняем примечание, документу предпосланное
	writer.comment("настройки службы");
	// Выполняем открытие отображения верхнего уровня
	writer.mapping();
	// Выполняем запись имени пары
	writer.key("title");
	// Выполняем запись содержимого пары
	writer.value("пример");
	// Выполняем запись имени пары вложенного отображения
	writer.key("server");
	/**
	 * Выполняем объявление метки вложенному отображению
	 *
	 * @note Метка ставится перед построением, а не после: она принадлежит значению
	 *       целиком, а не первой записи его
	 */
	writer.anchor("основной");
	// Выполняем открытие вложенного отображения
	writer.mapping();
	// Выполняем запись имени пары
	writer.key("host");
	// Выполняем запись содержимого пары
	writer.value("локальный");
	// Выполняем примечание в конце строки
	writer.trailing("хозяин");
	// Выполняем запись имени пары
	writer.key("port");
	// Выполняем объявление метки типа значению
	writer.tag("!!int");
	// Выполняем запись целого числа значением пары
	writer.value(static_cast <int64_t> (8080));
	// Выполняем запись имени пары перечня значений
	writer.key("hosts");
	/**
	 * Выполняем открытие перечня значений поточным построением
	 *
	 * @note Построение задаётся на месте: перечень коротких значений в строку читается
	 *       легче, нежели столбцом
	 */
	writer.sequence(codec::yaml::layout_t::FLOW);
	// Выполняем запись первого значения перечня
	writer.value("первый");
	// Выполняем запись второго значения перечня
	writer.value("второй");
	// Выполняем закрытие перечня значений
	writer.close();
	// Выполняем запись имени пары блочного значения
	writer.key("greeting");
	/**
	 * Выполняем запись блочного значения дословным оформлением
	 *
	 * @note Правило усечения `KEEP` переводы строк в конце содержимого сохраняет, а
	 *       правила `CLIP` и `STRIP` их теряют
	 */
	writer.block("первая строка\nвторая строка\n", codec::yaml::style_t::LITERAL, codec::yaml::chomp_t::CLIP);
	// Выполняем закрытие вложенного отображения
	writer.close();
	// Выполняем запись имени пары
	writer.key("запасной");
	// Выполняем запись ссылки на объявленную метку
	writer.alias("основной");
	// Выполняем закрытие отображения верхнего уровня
	writer.close();
	/**
	 * Выполняем завершение записи документа
	 *
	 * @note Запись отказы выдаёт возвратом самих способов, а не кодом: отказать она
	 *       вправе лишь построению неверному - имени без вместилища, закрытию
	 *       незакрытого, - и потребителю о том знать надобно сразу, на месте
	 */
	const bool done = writer.finish();
	// Выводим название разобранного случая
	cout << "== " << title << " ==" << endl;
	/**
	 * Если запись текста документа завершилась отказом
	 */
	if(!done)
		// Выводим сообщение об отказе записи
		cout << "запись отвергнута" << endl;
	// Выводим записанный текст документа
	else cout << writer.take();
	// Выводим отделитель разобранных случаев
	cout << endl;
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Выполняем построение текста документа настройками по умолчанию
	::build("настройки по умолчанию", codec::yaml::writer_t::settings_t());
	// Настройки записи текста документа
	codec::yaml::writer_t::settings_t settings;
	// Задаём отступ вложенности в четыре пробела
	settings.indent = 4;
	// Выполняем построение текста документа отступом в четыре пробела
	::build("отступ в четыре пробела", settings);
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
