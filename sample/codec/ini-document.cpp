/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/ini/document.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Разбираемый текст настроек
	const string text =
		"; настройки службы\n"
		"; правились вручную\n"
		"\n"
		"[paths]\n"
		"root = /opt/awh\n"
		"logs = ${root}/logs\n"
		"\n"
		"[server]\n"
		"host = 127.0.0.1\n"
		"port = 8080\n"
		"listen = ::1\n"
		"listen = 0.0.0.0\n";
	// Настройки дерева настроек
	codec::ini::document_t::settings_t settings;
	/**
	 * Устанавливаем построение обращения к значению другого свойства
	 *
	 * @note Подстановка выполняется один раз, сразу после разбора: значение, на
	 *       которое ссылаются, вправе стоять ниже по тексту, и разрешить обращение
	 *       можно лишь тогда, когда текст разобран целиком
	 */
	settings.references = codec::ini::reference_t::SHELL;
	// Создаём дерево настроек
	codec::ini::document_t document(::logger());
	/**
	 * Если разбор текста настроек выполнить не удалось
	 */
	if(!document.parse(text, settings)){
		// Выводим сведения об обнаруженной ошибке разбора
		cout << "ошибка: " << codec::ini::message(document.error())
		     << " в строке " << document.errorLocation().line << endl;
		// Выводим код ошибочного выхода из приложения
		return EXIT_FAILURE;
	}
	// Выводим количество объявленных разделов
	cout << "разделов: " << document.size() << endl;
	/**
	 * Выполняем перебор всех объявленных разделов
	 */
	for(auto & section : document.sections()){
		// Выводим имя объявленного раздела
		cout << "[" << section.section << "]" << endl;
		/**
		 * Выполняем перебор всех имён свойств раздела
		 */
		for(auto & key : document.keys(section.section))
			// Выводим имя и значение очередного свойства раздела
			cout << "  " << key << " = " << document.get(key, section.section) << endl;
	}
	// Выводим значение с разрешённым обращением к другому значению
	cout << endl << "путь к записям: " << document.get("logs", "paths") << endl;
	/**
	 * Выводим перечень значений повторного свойства
	 *
	 * @note Повторное объявление свойства перечень задаёт намеренно: таково
	 *       обращение наречий Git и systemd, и терять его при разборе нельзя
	 */
	cout << "перечень обозначений для прослушивания:" << endl;
	/**
	 * Выполняем перебор всех значений повторного свойства
	 */
	for(auto & value : document.values("listen", "server"))
		// Выводим очередное значение повторного свойства
		cout << "  " << value << endl;
	// Значение номера порта
	uint16_t port = 0;
	/**
	 * Если значение свойства разобрано числом
	 */
	if(document.value(port, "port", "server"))
		// Выводим разобранный номер порта
		cout << "номер порта числом: " << port << endl;
	// Выполняем правку значения объявленного свойства
	document.set("port", "9090", "server");
	// Выполняем добавление свойства в объявленный раздел
	document.set("timeout", "30", "server");
	// Выполняем добавление свойства в необъявленный раздел
	document.set("level", "debug", "logging");
	// Выполняем удаление свойства раздела
	document.erase("listen", "server");
	/**
	 * Выводим текст настроек, собранный из дерева
	 *
	 * @note Примечания, пустые строки и порядок записей сохранены: правка меняет
	 *       лишь то, что ей велено, а прочее остаётся, как было записано человеком
	 */
	cout << endl << "правленый текст настроек:" << endl << endl << document.text();
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
