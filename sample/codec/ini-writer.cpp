/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/ini/writer.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция сборки текста настроек заданным наречием записи
 *
 * @param title    название наречия записи
 * @param settings настройки записи текста настроек
 *
 */
static void build(const string & title, const codec::ini::writer_t::settings_t & settings) noexcept {
	// Создаём объект записи текста настроек
	codec::ini::writer_t writer(::logger(), settings);
	// Выполняем запись примечания
	writer.comment("собрано приложением");
	// Выполняем запись объявления раздела
	writer.section("server");
	// Выполняем запись свойства с обозначением узла
	writer.property("host", "127.0.0.1");
	// Выполняем запись свойства с номером порта
	writer.number("port", 8080);
	// Выполняем запись свойства с признаком защищённого соединения
	writer.number("secure", true);
	// Выполняем запись объявления раздела
	writer.section("paths");
	/**
	 * Выполняем запись свойства со значением, требующим ограждения
	 *
	 * @note Значение несёт пробельную обвязку, и без кавычек разбор прочитал бы
	 *       его иначе: обвязка при чтении отбрасывается
	 */
	writer.property("prefix", " /opt/awh ");
	// Выводим название наречия записи
	cout << "== " << title << " ==" << endl;
	/**
	 * Если сборка текста настроек завершилась ошибкой
	 */
	if(writer.error() != codec::ini::error_t::NONE)
		// Выводим сведения об обнаруженной ошибке записи
		cout << "ошибка: " << codec::ini::message(writer.error()) << endl;
	// Выводим собранный текст настроек
	else cout << writer.text();
	// Выводим знак конца строки
	cout << endl;
}
/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Выполняем сборку текста настроек наречием по умолчанию
	::build("наречие по умолчанию", codec::ini::writer_t::settings_t());
	// Выполняем сборку текста настроек наречием настроек Git
	::build("наречие настроек Git", codec::ini::writer_t::settings_t::git());
	/**
	 * Выполняем сборку текста настроек наречием MS Windows
	 *
	 * @note Наречие это кавычек при чтении не снимает, и ограждать ими значение
	 *       нельзя: запись отвечает отказом вместо того, чтобы выдать текст,
	 *       читаемый обратно неверно
	 */
	::build("наречие MS Windows", codec::ini::writer_t::settings_t::windows());
	// Создаём объект записи текста настроек
	codec::ini::writer_t writer(::logger());
	/**
	 * Если запись свойства с недопустимым именем отвергнута
	 */
	if(!writer.property("имя = со знаком равенства", "значение"))
		// Выводим сведения об обнаруженной ошибке записи
		cout << "имя свойства отвергнуто: " << codec::ini::message(writer.error()) << endl;
	// Выполняем сброс записи в исходное состояние
	writer.clear();
	/**
	 * Если запись значения со знаком конца строки отвергнута
	 */
	if(!writer.property("key", "первая строка\nвторая строка"))
		// Выводим сведения об обнаруженной ошибке записи
		cout << "значение отвергнуто: " << codec::ini::message(writer.error()) << endl;
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
