/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/json/json.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён контейнеров данных
 */
using namespace awh::codec;

/**
 * @brief Метод обхода дерева документа
 *
 * @details Дерево обходится ссылками на значения: ссылка знает своё место в дереве и
 *          переходит к соседу за одно действие, ибо дети лежат сразу за родителем
 *
 * @param value обходимое значение документа
 * @param depth глубина вложенности обходимого значения
 *
 */
static void walk(const json::document_t::value_t & value, const size_t depth = 0) noexcept {
	// Выполняем отступ по глубине вложенности
	const string indent(depth * 2, ' ');
	/**
	 * Если значение является полем объекта
	 */
	if(!value.name().empty())
		// Выводим имя поля объекта
		cout << indent << "поле «" << value.name() << "»: ";
	// Выводим отступ значения, имени не имеющего
	else cout << indent;
	/**
	 * Определяем вид обходимого значения
	 */
	switch(static_cast <uint8_t> (value.kind())){
		// Если значение является пустым
		case static_cast <uint8_t> (json::kind_t::NUL):
			// Выводим пустое значение
			cout << "пусто" << endl;
		break;
		/**
		 * Если значение является логическим
		 */
		case static_cast <uint8_t> (json::kind_t::BOOL): {
			// Извлекаемое логическое значение
			bool state = false;
			// Выполняем извлечение логического значения
			value.value(state);
			// Выводим логическое значение
			cout << (state ? "истина" : "ложь") << endl;
		} break;
		/**
		 * Если значение является числом
		 *
		 * @note Вид числа известен разбору точно, и спрашивать его надлежит вопросом
		 *       `is()`, а не пробою извлечения: извлечение отказом не отвечает, ибо вид
		 *       хранения ему не указ, - `12.5` извлекается целым видом как `12`
		 *
		 * @note Целое извлекается целым и не теряет точности за пределом 2^53, где живут
		 *       опознаватели записей, - вид `UINT64` разбор определяет сам
		 */
		case static_cast <uint8_t> (json::kind_t::NUMBER): {
			/**
			 * Если число является целым любой ширины и любой знаковости
			 */
			if(value.is(json::type_t::INT)){
				// Извлекаемое целое число
				int64_t number = 0;
				// Выполняем извлечение целого числа
				value.value(number);
				// Выводим целое число вместе с точным видом его
				cout << "целое " << number << " (вид " << json::name(value.type()) << ")" << endl;
			/**
			 * Если число является дробным любой точности
			 */
			} else if(value.is(json::type_t::REAL)) {
				// Извлекаемое число с плавающей запятой
				double real = 0.;
				// Выполняем извлечение числа с плавающей запятой
				value.value(real);
				// Выводим число с плавающей запятой вместе с точным видом его
				cout << "дробное " << real << " (вид " << json::name(value.type()) << ")" << endl;
			/**
			 * Если число не вместилось ни в один родной вид
			 */
			} else cout << "число вне родных видов (запись «" << value.raw() << "»)" << endl;
		} break;
		/**
		 * Если значение является строкой
		 *
		 * @note Содержимое строки отдаётся отрезком без копии: экранирование с него уже
		 *       снято разбором, и знаки лежат готовыми в хранилище документа
		 */
		case static_cast <uint8_t> (json::kind_t::STRING):
			// Выводим содержимое строки
			cout << "строка «" << value.text() << "»" << endl;
		break;
		/**
		 * Если значение является вместилищем
		 */
		case static_cast <uint8_t> (json::kind_t::ARRAY):
		case static_cast <uint8_t> (json::kind_t::OBJECT): {
			// Выводим вид вместилища вместе с количеством детей
			cout << ((value.kind() == json::kind_t::ARRAY) ? "массив" : "объект")
			     << " из " << value.size() << " значений" << endl;
			/**
			 * Выполняем перебор всех значений вместилища
			 */
			for(json::document_t::value_t item = value.begin(); item.valid(); item = item.next())
				// Выполняем обход очередного значения вместилища
				::walk(item, (depth + 1));
		} break;
	}
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	(void) argv;
	// Разбираемый текст документа
	const string text = R"({
		"служба": "заказы",
		"версия": 3,
		"включена": true,
		"предел": 12.5,
		"опознаватель": 9007199254740993,
		"узлы": [
			{"имя": "первый",  "порт": 8080, "вес": 1.5},
			{"имя": "второй",  "порт": 8081, "вес": 2.0},
			{"имя": "третий",  "порт": 8082, "вес": null}
		]
	})";
	// Объект дерева документа
	json::document_t document;
	/**
	 * Если разбор текста документа завершился отказом
	 *
	 * @note Отказ несёт не только причину, но и место её в исходном тексте: строку,
	 *       положение в строке и смещение от начала
	 */
	if(!document.parse(text)){
		// Выводим причину отказа разбора вместе с местом её
		cerr << "Разбор отвергнут: " << json::message(document.error())
		     << " (строка " << document.location().line
		     << ", знак " << document.location().column << ")" << endl;
		// Выходим из приложения с кодом ошибки
		return EXIT_FAILURE;
	}
	// Извлекаемое имя службы
	string name;
	// Извлекаемая версия службы
	int64_t version = 0;
	// Выполняем извлечение имени службы
	document["служба"].value(name);
	// Выполняем извлечение версии службы
	document["версия"].value(version);
	// Выводим извлечённые значения
	cout << "Служба «" << name << "» версии " << version << endl;
	/**
	 * Выполняем обращение к значению по номеру
	 *
	 * @note Обращение по номеру идёт за одно действие: дети лежат сплошным перечнем
	 *       сразу за родителем, и указаний на них узел не хранит вовсе
	 */
	cout << "Второй узел: " << document["узлы"][static_cast <size_t> (1)]["имя"].text() << endl;
	/**
	 * Выполняем обращение указателем JSON Pointer
	 *
	 * @note Указатель отвечает договору RFC 6901 вместе с отменой знаков «~» и «/»
	 */
	cout << "Порт третьего узла: " << document.at("/узлы/2/порт").raw() << endl;
	/**
	 * Выводим точный вид опознавателя записи
	 *
	 * @note Вид определяется разбором и хранится узлом: повторного разбора записи при
	 *       извлечении не бывает вовсе, а потребитель вправе выбрать по нему хранилище
	 */
	cout << "Вид опознавателя: " << json::name(document["опознаватель"].type()) << endl;
	/**
	 * Если поле в документе отсутствует
	 *
	 * @note Обращение к отсутствующему полю отказом не является: оно отдаёт
	 *       недействительную ссылку, и проверять её надлежит вызовом `valid()`
	 */
	if(!document["отсутствует"].valid())
		// Выводим сообщение об отсутствии поля
		cout << "Поля «отсутствует» в документе нет" << endl;
	// Выводим заголовок обхода дерева документа
	cout << endl << "Обход дерева целиком:" << endl;
	// Выполняем обход дерева документа
	::walk(document.root());
	// Выводим заголовок записи дерева документа
	cout << endl << "Запись дерева в человекочитаемом виде:" << endl;
	/**
	 * Выводим запись дерева документа
	 *
	 * @note Вид записи выбирается настройкой: сжатая запись идёт без единого лишнего
	 *       знака, а человекочитаемая - с отступами и переводами строк
	 */
	cout << document.dump(json::format_t::PRETTY) << endl;
	// Выходим из приложения
	return EXIT_SUCCESS;
}
