/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/csv/document.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Разбираемый текст таблицы
 *
 */
static const char * TEXT =
 "имя,цена,описание\n"
 "гвоздь,10,обычный\n"
 "молоток,250,\"с ручкой, деревянной\"\n"
 "отвёртка,120,крестовая\n";

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Настройки дерева таблицы
	codec::csv::document_t::settings_t settings;
	// Признаём первую строку записью заголовка
	settings.reader.header = codec::csv::header_t::PRESENT;
	// Создаём объект дерева таблицы
	codec::csv::document_t document(::logger(), settings);
	/**
	 * Если разбор текста таблицы не удался
	 */
	if(!document.parse(TEXT)){
		// Выводим сведения об обнаруженной ошибке разбора
		cout << "ошибка: " << codec::csv::message(document.error()) << endl;
		// Выводим код выхода из приложения с ошибкой
		return EXIT_FAILURE;
	}
	// Выводим размеры разобранной таблицы
	cout << "записей: " << document.rows() << ", полей: " << document.cols() << endl;
	/**
	 * Выполняем перебор всех записей таблицы
	 */
	for(size_t row = 0; row < document.rows(); row++){
		// Выводим содержимое поля по номеру его
		cout << "  " << document.get(row, static_cast <size_t> (0));
		/**
		 * Выводим содержимое поля по имени его
		 *
		 * @note Обращение по имени возможно лишь при записи заголовка: имена берутся
		 *       из неё, а без заголовка полям остаются одни номера
		 */
		cout << " — " << document.get(row, "описание");
		// Целое число значения поля
		int64_t price = 0;
		/**
		 * Если извлечение числа из поля удалось
		 */
		if(document.numeric(row, static_cast <size_t> (1), price))
			// Выводим извлечённое число
			cout << " (" << price << ")";
		// Выводим перевод строки
		cout << endl;
	}
	// Выполняем заведение записи в конце таблицы
	document.append(vector <string> {"пила", "480", "ножовка"});
	// Выводим обозначение перезаписи таблицы
	cout << endl << "== перезапись ==" << endl;
	// Выводим перезапись таблицы
	cout << document.text();
	// Объект дерева таблицы для потокового разбора
	codec::csv::document_t stream(::logger(), settings);
	// Выводим обозначение потокового разбора отбором записей
	cout << endl << "== отбор записей потоковым разбором ==" << endl;
	/**
	 * Выполняем потоковый разбор текста таблицы отбором записей
	 *
	 * @note Разбор этот дерева не собирает: записи выдаются по одной, и текст любого
	 *       размера обходится памятью одной записи
	 */
	stream.parse(TEXT, [](const vector <string_view> & fields) noexcept -> bool {
		/**
		 * Если запись несёт менее двух полей
		 */
		if(fields.size() < 2)
			// Продолжаем разбор текста таблицы
			return true;
		/**
		 * Если поле цены записи превышает сотню
		 *
		 * @note Сличение ведётся по длине записи числа: образцу довольно и этого, а
		 *       извлечение числа показано выше
		 */
		if(fields.at(1).size() > 2)
			// Выводим отобранную запись таблицы
			cout << "  " << fields.at(0) << " = " << fields.at(1) << endl;
		// Продолжаем разбор текста таблицы
		return true;
	});
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
