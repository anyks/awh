/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/csv/reader.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Разбираемый текст таблицы
 *
 * @note Знак-разделитель нарочно взят точкой с запятой: он не задаётся настройкою, а
 *       опознаётся самим чтением по первым строкам текста
 *
 */
static const char * TEXT =
 "# перечень товаров\n"
 "имя;цена;описание\n"
 "гвоздь;10;обычный\n"
 "молоток;250;\"с ручкой,\nдеревянной\"\n"
 "отвёртка;120;\"кавычка \"\" внутри\"\n";

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Настройки разбора текста таблицы
	codec::csv::reader_t::settings_t settings;
	// Признаём первую строку записью заголовка
	settings.header = codec::csv::header_t::PRESENT;
	// Задаём знак начала строки примечания
	settings.comment = '#';
	// Просим выдачи строк примечаний отдельными событиями
	settings.emitComments = true;
	/**
	 * Просим опознания знака-разделителя по содержимому
	 *
	 * @note Умолчанием взята запятая, названная описанием. Ноль велит опознавать
	 *       разделитель самому чтению: выдача откладывается, покуда он не опознан
	 */
	settings.separator = 0;
	// Создаём объект потокового чтения текста таблицы
	codec::csv::reader_t reader(::logger(), settings);
	// Разбираемый текст таблицы
	const string text = TEXT;
	/**
	 * Выполняем подачу текста таблицы кусками
	 *
	 * @note Размер куска взят нарочно малым и на границы полей не смотрит: разбор от
	 *       нарезки не зависит, и события выдаются те же, что при подаче целиком
	 */
	for(size_t offset = 0; offset < text.size();){
		// Размер подаваемого куска текста таблицы
		const size_t size = ((text.size() - offset) < 5 ? (text.size() - offset) : 5);
		// Признак того, что подаётся последний кусок текста таблицы
		const bool last = ((offset + size) >= text.size());
		/**
		 * Если подача очередного куска текста таблицы не удалась
		 */
		if(!reader.feed(text.data() + offset, size, last))
			// Выходим из цикла подачи текста таблицы
			break;
		// Выполняем смещение начала очередного куска подачи
		offset += size;
		/**
		 * Выполняем чтение всех выданных разбором событий
		 */
		while(reader.next()){
			/**
			 * Определяем разновидность выданного события
			 */
			switch(static_cast <uint8_t> (reader.event())){
				// Если выдано поле записи заголовка
				case static_cast <uint8_t> (codec::csv::event_t::HEADER):
					// Выводим содержимое поля заголовка
					cout << "заголовок «" << reader.field().value << "»" << endl;
				break;
				// Если выдано поле записи
				case static_cast <uint8_t> (codec::csv::event_t::FIELD): {
					// Выводим содержимое поля записи
					cout << "  поле «" << reader.field().value << "»";
					/**
					 * Если поле записано в кавычках
					 */
					if(reader.field().quoted)
						// Выводим признак поля, записанного в кавычках
						cout << " (в кавычках)";
					/**
					 * Если имя поля взято из записи заголовка
					 */
					if(!reader.field().name.empty())
						// Выводим имя поля из записи заголовка
						cout << " имя=" << reader.field().name;
					// Выводим перевод строки
					cout << endl;
				} break;
				// Если запись окончена
				case static_cast <uint8_t> (codec::csv::event_t::RECORD):
					// Выводим обозначение конца записи
					cout << "запись окончена" << endl;
				break;
				// Если выдана строка примечания
				case static_cast <uint8_t> (codec::csv::event_t::COMMENT):
					// Выводим содержимое строки примечания
					cout << "примечание «" << reader.field().value << "»" << endl;
				break;
			}
		}
	}
	/**
	 * Если разбор текста таблицы завершился отказом
	 */
	if(reader.error() != codec::csv::error_t::NONE)
		// Выводим сведения об обнаруженной ошибке разбора
		cout << "ошибка: " << codec::csv::message(reader.error()) << endl;
	// Выводим опознанный знак-разделитель полей
	else cout << endl << "знак-разделитель: «" << reader.separator() << "»" << endl;
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
