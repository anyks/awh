/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <sys/log.hpp>
#include <codec/abc/abc.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
	/**
	 * @brief Функция сборки одной записи контейнера
	 *
	 * @param number номер собираемой записи
	 * @param text   содержимое собираемой записи
	 * @return       собранная бинарная запись
	 *
	 */
	std::vector <uint8_t> record(const uint64_t number, const std::string & text) noexcept {
		// Объект сборки бинарной записи
		awh::codec::abc::writer_t writer(::logger());
		// Выполняем сборку записи из двух полей
		if(writer.mapBegin(static_cast <uint64_t> (2)) &&
		   writer.text("номер") && writer.number(number) &&
		   writer.text("текст") && writer.text(text) &&
		   writer.mapEnd())
			// Выводим собранную запись
			return writer.record();
		// Выводим пустую запись: сборка отказала
		return std::vector <uint8_t> ();
	}
}

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подписываемся на пространство имён контейнеров данных
 */
using namespace awh::codec;

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	(void) argv;
	// Сборщик контейнера
	abc::assembler_t assembler(::logger());
	// Количество вносимых записей
	const uint64_t count = 5;
	/**
	 * Выполняем внесение записей в собираемый контейнер
	 */
	for(uint64_t i = 0; i < count; i++){
		// Выполняем сборку очередной записи
		const vector <uint8_t> item = ::record(i, "запись номер " + to_string(i));
		/**
		 * Выполняем внесение очередной записи в собираемый контейнер
		 *
		 * @note Вид груза объявляется при внесении: он ведёт выбор способа сжатия
		 *       кадра, а не хранится украшением
		 */
		if(!assembler.append(item.data(), item.size(), abc::payload_t::TEXT)){
			// Выводим сообщение об отказе внесения записи
			cout << "Внесение записи отказало: " << abc::message(assembler.error()) << endl;
			// Выходим из приложения
			return EXIT_FAILURE;
		}
	}
	// Буфер собранного контейнера
	vector <uint8_t> buffer;
	/**
	 * Выполняем завершение сборки контейнера
	 *
	 * @note Завершение дописывает оглавление и подпись: без него контейнер несёт лишь
	 *       тело, и выборка по номеру работать не будет вовсе
	 */
	if(!assembler.complete(buffer)){
		// Выводим сообщение об отказе завершения сборки
		cout << "Завершение сборки отказало: " << abc::message(assembler.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Выводим размер собранного контейнера
	cout << "Контейнер собран: " << buffer.size() << " окт., записей " << count << endl;
	/**
	 * Выполняем опознание собранного контейнера
	 *
	 * @note Опознание идёт по заголовку и тела не читает вовсе: им отличают наш
	 *       контейнер от чужого файла прежде, чем браться за содержимое
	 */
	cout << "Опознан как контейнер ABC: "
	     << (abc::probe(buffer.data(), buffer.size()) ? "да" : "нет") << endl;
	// Сниматель контейнера
	abc::loader_t loader(::logger());
	// Выполняем подачу собранного контейнера снимателю
	if(!loader.feed(buffer.data(), buffer.size())){
		// Выводим сообщение об отказе подачи контейнера
		cout << "Подача контейнера отказала: " << abc::message(loader.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Выводим заголовок потокового снятия кадров
	cout << endl << "Потоковое снятие кадров:" << endl;
	// Количество снятых кадров контейнера
	size_t frames = 0;
	// Общий размер снятого содержимого
	size_t taken = 0;
	// Буфер содержимого очередного кадра
	vector <uint8_t> payload;
	/**
	 * Приметы снятого кадра
	 *
	 * @note Кадр выдаётся вместе со своими приметами: способом сжатия, длиною до и
	 *       после сжатия и номером. Знать их полезно и потребителю - по ним видно,
	 *       сжался ли груз вообще
	 */
	abc::chunk_t chunk;
	/**
	 * Снимаем кадры контейнера один за другим
	 */
	while(loader.next(payload, chunk)){
		// Выполняем учёт снятого кадра
		frames++;
		// Выполняем учёт снятого содержимого
		taken += payload.size();
	}
	// Выводим количество снятых кадров и размер содержимого
	cout << "  кадров снято: " << frames << ", содержимого: " << taken << " окт." << endl;
	// Выводим количество записей, объявленное заголовком контейнера
	cout << "  записей по заголовку: " << loader.header().records << endl;
	// Выводим длину тела контейнера, объявленную заголовком
	cout << "  длина тела: " << loader.header().length << " окт." << endl;
	/**
	 * Выполняем выборку записи по номеру
	 *
	 * @details Выборщик читает контейнер отданной ему работой чтения, а не держит его
	 *          в памяти целиком: оглавление даёт смещение кадра, где запись лежит, и
	 *          читается ровно этот кадр. Тем контейнер и годен файлу на диске, какой в
	 *          память не помещается вовсе
	 */
	cout << endl << "Выборка записей по номеру:" << endl;
	// Выборщик записей контейнера
	abc::fetcher_t fetcher(::logger());
	/**
	 * Выполняем открытие контейнера отданной работой чтения
	 *
	 * @note Работа чтения здесь берёт октеты из памяти, а в приложении брала бы их
	 *       из файла: выборщику всё равно, откуда они приходят
	 */
	if(!fetcher.open([&buffer](const uint64_t offset, const size_t size, vector <uint8_t> & result) noexcept -> bool {
		// Если затребованный отрезок за пределы контейнера не выходит
		if((offset + static_cast <uint64_t> (size)) <= static_cast <uint64_t> (buffer.size())){
			// Выполняем выдачу затребованных октетов контейнера
			result.assign(buffer.begin() + static_cast <ptrdiff_t> (offset),
			              buffer.begin() + static_cast <ptrdiff_t> (offset + size));
			// Выводим признак успешного чтения
			return true;
		}
		// Выводим признак отказа чтения
		return false;
	})){
		// Выводим сообщение об отказе открытия контейнера
		cout << "Открытие контейнера отказало: " << abc::message(fetcher.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Выводим количество записей открытого контейнера
	cout << "  записей в оглавлении: " << fetcher.records() << endl;
	/**
	 * Выполняем выборку записей вразнобой, от конца к началу
	 *
	 * @note Порядок здесь обратный намеренно: выборка по порядку прошла бы и при
	 *       простом чтении подряд, а обратная показывает, что оглавление и вправду
	 *       даёт доступ по номеру
	 */
	for(uint64_t i = fetcher.records(); i > 0; i--){
		// Буфер выбранной записи контейнера
		vector <uint8_t> item;
		// Выполняем выборку очередной записи контейнера по номеру
		if(!fetcher.record(i - 1, item)){
			// Выводим сообщение об отказе выборки записи
			cout << "  выборка записи " << (i - 1) << " отказала: "
			     << abc::message(fetcher.error()) << endl;
			// Выходим из приложения
			return EXIT_FAILURE;
		}
		// Объект дерева документа выбранной записи
		abc::document_t document(::logger());
		// Выполняем разбор выбранной записи в дерево документа
		if(document.parse(item.data(), item.size()))
			// Выводим содержимое выбранной записи
			cout << "  запись " << (i - 1) << ": "
			     << string(document.root().get("текст").data()) << endl;
	}
	// Выходим из приложения
	return EXIT_SUCCESS;
}
