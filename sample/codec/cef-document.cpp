/**
 * Стандартные модули
 */
#include <iostream>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/cef/document.hpp>
#include <sys/log.hpp>

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * @brief Функция получения объекта фреймворка
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца работало с одним и тем же фреймворком
	 *
	 * @return объект фреймворка
	 *
	 */
	const awh::fmk_t * framework() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Выводим объект фреймворка
		return &fmk;
	}
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект для работы с логами
		static awh::log_t log(::framework());
		// Выводим объект для работы с логами
		return &log;
	}
}

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Разбираемая запись события
 *
 * @details Запись несёт приставку syslog, метку имени поля (cs1Label), пустое значение,
 *          адреса сети и метку времени с долей секунды
 *
 */
static const char * TEXT =
	"Feb 17 15:30:15 vnetids emerg CEF:0|InfoTeCS|IDS|2.4.3|1:905590:7|RDP connection|1|"
	"cat=1 src=192.168.59.39 spt=8082 dst=10.0.0.1 dmac=b0:01:86:30:90:05 "
	"cs1=not-suspicious cs1Label=IDSClass cs2= cs2Label=CVEID "
	"rt=Feb 17 2023 23:30:15.734 YEKT";

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Блокируем неиспользуемую переменную
	(void) argc;
	// Блокируем неиспользуемую переменную
	(void) argv;
	// Создаём объект события CEF
	codec::cef::document_t document(::framework(), ::logger());
	// Настройки укладки записей в дерево
	codec::cef::reader_t::settings_t settings;
	/**
	 * Устанавливаем сличение имён ключей и всех видов значений со словарём
	 *
	 * @note Без сличения значения кладутся в дерево последовательностями знаков, как в
	 *       записи и стоят: ни числом, ни адресом, ни меткой времени они не становятся.
	 *       Сличение стоит около процента времени разбора и включается настройкой
	 *
	 */
	settings.mode = codec::cef::mode_t::STRONG;
	// Устанавливаем настройки укладки записей в дерево
	document.settings(settings);
	/**
	 * Если укладка записи в дерево не удалась
	 */
	if(!document.parse(TEXT)){
		// Выводим сведения об обнаруженной ошибке разбора
		cout << "ошибка: " << codec::cef::message(document.error())
		     << " в " << document.errorPosition().line << ":" << document.errorPosition().column << endl;
		// Выводим код выхода из приложения с ошибкой
		return EXIT_FAILURE;
	}
	/**
	 * Выводим поля заголовка записи по указателю
	 *
	 * @note Заголовок лежит отдельным вместилищем «/header» и полей несёт ровно семь:
	 *       version, vendor, product, release, signature, name, severity
	 */
	cout << "поставщик: " << document.at("/header/vendor").text() << endl;
	cout << "изделие:   " << document.at("/header/product").text() << endl;
	cout << "событие:   " << document.at("/header/name").text() << endl;
	/**
	 * Выводим важность события числом
	 *
	 * @note Важность в дереве лежит числом, а не знаками: описание ArcSight назначает
	 *       ей значения от нуля до десяти, и разбор её ведётся всегда, сличения не
	 *       дожидаясь
	 */
	int64_t severity = 0;
	// Если извлечение важности события удалось
	if(document.at("/header/severity").value(severity))
		// Выводим важность события числом
		cout << "важность:  " << severity << endl;
	// Выводим приставку syslog, записи предшествовавшую
	cout << "syslog:    " << document.at("/syslog").text() << endl;
	/**
	 * Выводим значение расширения по ПОЛНОМУ имени, словарём заданному
	 *
	 * @note Ход field() ищет пару расширения человеческим именем словаря, а не ключом
	 *       записи: «sourceAddress» отдаёт значение ключа «src». Живые устройства пишут
	 *       ключи сокращениями, а разбирающему их запоминать незачем
	 */
	cout << "источник:  " << document.field("sourceAddress").text() << endl;
	// Выводим обозначение перебора пар расширения
	cout << endl << "== расширение (" << document.size() << " пар) ==" << endl;
	/**
	 * Выполняем перебор всех имён пар расширения
	 *
	 * @note Обход выдаёт СЫРЫЕ имена ключей, как они в записи и стоят: сведённое имя
	 *       берётся отдельным ходом, ибо словарь не всякий ключ знает, а живые
	 *       устройства пишут и свои
	 */
	for(auto & key : document.keys("/extension")){
		// Сведённое словарём имя ключа расширения
		const string & label = document.label(key);
		// Значение пары расширения, деревом удерживаемое
		const codec::abc::value_t & value = document.at("/extension/" + key);
		// Выводим сырое имя ключа пары расширения
		cout << "  " << key << " = ";
		/**
		 * Выводим значение пары расширения видом его
		 *
		 * @note При строгом сличении значения лежат в дереве видами, словарём заданными,
		 *       а не знаками: спрос text() у числа отдаёт пустоту, и читать его надлежит
		 *       ходом извлечения того вида, каким оно и уложено
		 */
		if(value.type() == codec::abc::type_t::STRING)
			// Выводим значение пары расширения знаками
			cout << value.text();
		// Если значение пары расширения знаками не является
		else {
			// Целое число значения пары расширения
			int64_t number = 0;
			// Если извлечение целого числа удалось
			if(value.value(number))
				// Выводим значение пары расширения числом
				cout << number;
			// Выводим обозначение вида значения, знаками не выражаемого
			else cout << "<вид " << static_cast <uint16_t> (value.type()) << ">";
		}
		// Если сведённое имя ключа от сырого отличается
		if(!label.empty() && (label != key))
			// Выводим сведённое словарём имя ключа
			cout << "   (" << label << ")";
		// Переводим строку вывода
		cout << endl;
	}
	// Выводим обозначение видов значений
	cout << endl << "== виды значений ==" << endl;
	/**
	 * Выводим вид значения, словарём назначенный
	 *
	 * @note Вид берётся из словаря, а не угадывается по самому значению: «cat=1» есть
	 *       строка описанием, хотя на вид и число
	 */
	cout << "  src:  вид " << static_cast <uint16_t> (document.type("src")) << endl;
	cout << "  spt:  вид " << static_cast <uint16_t> (document.type("spt")) << endl;
	cout << "  dmac: вид " << static_cast <uint16_t> (document.type("dmac")) << endl;
	cout << "  rt:   вид " << static_cast <uint16_t> (document.type("rt")) << endl;
	/**
	 * Выводим метку времени, записью переданную
	 *
	 * @note Запись метки берётся по самой метке: живые устройства пишут её и с долей
	 *       секунды, и без неё, а одна запись обоих видов не покрывает
	 */
	cout << "  rt:   " << document.timestamp("rt") << endl;
	// Выполняем заведение отсутствующей пары расширения
	document.set("/extension/msg", codec::abc::value_t(string("connection dropped")));
	// Выполняем удаление объявленной пары расширения
	document.erase("/extension/cat");
	// Выводим обозначение обратной сборки записи
	cout << endl << "== обратная сборка ==" << endl;
	// Собранная заново запись события
	const string & record = document.dump();
	/**
	 * Если обратная сборка записи отказом завершилась
	 *
	 * @note Сборка отказом отвечает на дереве, записи CEF не поддающемся: имя ключа с
	 *       пробелом внутри записать нельзя, ибо пробел пары и разделяет
	 */
	if(record.empty()){
		// Выводим сведения об обнаруженной ошибке сборки
		cout << "ошибка: " << codec::cef::message(document.error()) << endl;
		// Выводим код выхода из приложения с ошибкой
		return EXIT_FAILURE;
	}
	// Выводим собранную заново запись события
	cout << record << endl;
	// Выводим код успешного выхода из приложения
	return EXIT_SUCCESS;
}
