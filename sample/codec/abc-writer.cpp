using namespace awh::codec;

/**
 * @brief Метод сборки записи ответа службы
 *
 * @details Запись собирается значение за значением, дерева при этом не заводится
 *          вовсе: сборке довольно знать, что открыто, а что закрыто
 *
 * @param writer объект сборки бинарной записи
 * @return       признак успешной сборки записи
 *
 */
static bool assemble(abc::writer_t & writer) noexcept {
	/**
	 * Выполняем открытие отображения с объявлением количества пар
	 *
	 * @note Количество объявляется наперёд, и это строгий вид записи: чтение знает
	 *       размер вместимого прежде, чем возьмётся за его значения
	 */
	if(!writer.mapBegin(static_cast <uint64_t> (7)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля службы
	if(!writer.text("служба"))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем название службы
	if(!writer.text("заказы"))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля версии
	if(!writer.text("версия"))
		// Выходим из метода: сборка отказала
		return false;
	/**
	 * Укладываем версию службы
	 *
	 * @note Ширина хранения выбирается по величине, а не по виду довода: тройка
	 *       ляжет в один октет, и восьмиоктетного целого в записи не появится
	 */
	if(!writer.number(static_cast <uint64_t> (3)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля отметки времени
	if(!writer.text("отметка"))
		// Выходим из метода: сборка отказала
		return false;
	/**
	 * Укладываем отметку времени
	 *
	 * @note Вид этот текстовым кодекам недоступен вовсе: JSON и YAML пишут время
	 *       строкою либо числом, и читающий обязан догадываться, что перед ним
	 */
	if(!writer.timestamp(static_cast <int64_t> (1755500000)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля опознавателя
	if(!writer.text("опознаватель"))
		// Выходим из метода: сборка отказала
		return false;
	// Опознаватель записи шириною в шестнадцать октетов
	const uint8_t identifier[16] = {
		0x55, 0x0E, 0x84, 0x00, 0xE2, 0x9B, 0x41, 0xD4,
		0xA7, 0x16, 0x44, 0x66, 0x55, 0x44, 0x00, 0x00
	};
	/**
	 * Укладываем опознаватель записи
	 *
	 * @note Опознаватель ложится шестнадцатью октетами, а не строкою в тридцать шесть
	 *       знаков: запись его вдвое короче текстовой, и вид его читающему известен
	 */
	if(!writer.uuid(identifier, sizeof(identifier)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля цены
	if(!writer.text("цена"))
		// Выходим из метода: сборка отказала
		return false;
	// Величина цены: 12345 при разряде -2 даёт 123.45
	const uint8_t price[2] = {0x30, 0x39};
	/**
	 * Укладываем цену десятичным видом
	 *
	 * @note Вид этот держит дробный разряд ТОЧНО, тогда как двоичное дробное число
	 *       представить 123.45 не в силах вовсе. Для денег это не удобство, а
	 *       обязанность: округление двоичного вида уводит копейки
	 */
	if(!writer.decimal(price, sizeof(price), false, static_cast <int64_t> (-2)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля груза
	if(!writer.text("груз"))
		// Выходим из метода: сборка отказала
		return false;
	// Содержимое груза
	const uint8_t payload[8] = {0x00, 0x01, 0x02, 0x03, 0xFC, 0xFD, 0xFE, 0xFF};
	/**
	 * Укладываем груз двоичными данными
	 *
	 * @note Двоичное значение ложится как есть, без перекодировки: текстовые кодеки
	 *       вынуждены гнать его через base64 и растить на треть
	 */
	if(!writer.blob(payload, sizeof(payload)))
		// Выходим из метода: сборка отказала
		return false;
	// Укладываем имя поля узлов
	if(!writer.text("узлы"))
		// Выходим из метода: сборка отказала
		return false;
	/**
	 * Выполняем открытие массива неопределённой длины
	 *
	 * @note Длина объявляется не всегда: когда количество наперёд неизвестно -
	 *       значения идут потоком, а вместимое закрывается меткою конца. Это тот
	 *       случай, ради какого потоковая сборка и заводится
	 */
	if(!writer.arrayBegin())
		// Выходим из метода: сборка отказала
		return false;
	/**
	 * Перебираем узлы службы
	 */
	for(uint64_t i = 1; i <= 3; i++){
		// Укладываем очередной номер узла
		if(!writer.number(i))
			// Выходим из метода: сборка отказала
			return false;
	}
	// Выполняем закрытие массива узлов
	if(!writer.arrayEnd())
		// Выходим из метода: сборка отказала
		return false;
	// Выполняем закрытие отображения
	return writer.mapEnd();
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Не используем параметры приложения
	(void) argc;
	(void) argv;
	// Объект сборки бинарной записи
	abc::writer_t writer(::logger());
	// Выполняем сборку записи ответа службы
	if(!::assemble(writer)){
		// Выводим сообщение об отказе сборки
		cout << "Сборка записи отказала: " << abc::message(writer.error()) << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	/**
	 * Выполняем проверку завершённости записи
	 *
	 * @note Проверка эта не лишняя: незакрытое вместимое отдаёт запись, какую чтение
	 *       считает оборванной и будет ждать продолжения. Отвечает за закрытие тот,
	 *       кто собирает, - сборка сама вместимых не закрывает
	 */
	if(!writer.complete()){
		// Выводим сообщение о незавершённости записи
		cout << "Запись не завершена: остались незакрытые вместимые" << endl;
		// Выходим из приложения
		return EXIT_FAILURE;
	}
	// Выводим собранную запись
	::dump("Запись ответа службы", writer.record());
	// Выполняем сброс сборки бинарной записи
	writer.reset();
	// Содержимое, живущее дольше выдачи записи
	static const uint8_t attachment[64] = {0};
	// Получаем настройки сборки бинарной записи
	abc::writer_t::settings_t settings = writer.settings();
	/**
	 * Устанавливаем порог укладки содержимого ссылкой
	 *
	 * @note Настройка эта по умолчанию снята намеренно: содержимое, уложенное ссылкой,
	 *       обязано пережить выдачу записи, и обязанность эта ложится на потребителя.
	 *       Здесь она соблюдена статикою местною
	 */
	settings.reference = 32;
	// Выполняем установку настроек сборки бинарной записи
	writer.settings(settings);
	/**
	 * Выполняем укладку крупного содержимого
	 */
	if(writer.blob(attachment, sizeof(attachment)))
		// Выводим собранную запись
		::dump("Запись с укладкой ссылкой", writer.record());
	/**
	 * Выполняем сборку многих записей ОДНОЙ сборкой
	 *
	 * @details Собирающему записи потоком надлежит держать одну сборку и звать сброс, а
	 *          не заводить сборку на всякую запись: сброс опустошает вместилища,
	 *          сохраняя их запас, и выдача памяти со всякой записи снимается вовсе
	 *
	 * @note Замер 23.08.2026, малая запись, 200 000 кругов: своя сборка на всякую запись
	 *       идёт 0.17 мкс, одна сборка со сбросом - 0.04 мкс. Рычаг этот вчетверо, и
	 *       стоит он одной строки
	 */
	cout << endl << "Сборка потока записей одной сборкой:" << endl;
	// Общий размер собранных записей
	size_t total = 0;
	/**
	 * Перебираем собираемые записи потока
	 */
	for(uint64_t i = 1; i <= 5; i++){
		// Выполняем сброс состояния сборки, сохраняющий запас вместилищ
		writer.reset();
		// Выполняем сборку очередной записи потока
		if(writer.mapBegin(static_cast <uint64_t> (1)) &&
		   writer.text("номер") && writer.number(i) && writer.mapEnd())
			// Выполняем учёт размера собранной записи
			total += writer.record().size();
	}
	// Выводим итог сборки потока записей
	cout << "  собрано 5 записей, всего " << total << " окт." << endl;
	// Выходим из приложения
	return EXIT_SUCCESS;
}
