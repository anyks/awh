namespace {
	/**
	 * @brief Функция получения объекта для работы с логами
	 *
	 * @details Кодек связку берёт конструктором, а построения образца стоят и вне
	 *          main(): объект заводится статикою местною, дабы всякое построение
	 *          образца писало сообщения в один и тот же журнал
	 *
	 * @return объект для работы с логами
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект фреймворка
		static awh::fmk_t fmk;
		// Объект для работы с логами
		static awh::log_t log(&fmk);
		// Выводим объект для работы с логами
		return &log;
	}
	/**
	 * @brief Функция вывода записи шестнадцатеричным видом
	 *
	 * @details Запись двоичная, и глазами она читается лишь по октетам: вывод её как
	 *          строки оборвался бы на первом же нулевом октете
	 *
	 * @param title   заголовок вывода
	 * @param record  выводимая запись
	 *
	 */
	void dump(const char * title, const std::vector <uint8_t> & record) noexcept {
		// Выводим заголовок вывода
		std::cout << title << " (" << record.size() << " окт.):" << std::endl;
		/**
		 * Перебираем октеты записи
		 */
		for(size_t i = 0; i < record.size(); i++){
			// Выводим очередной октет записи
			std::printf("%02X ", record.at(i));
			// Переводим строку каждые шестнадцать октетов
			if(((i + 1) % 16) == 0)
				// Выполняем перевод строки
				std::printf("\n");
		}
		// Завершаем вывод переводом строки
		std::printf("\n");
	}
}

