/**
 * @brief Ход отправки файла
 *
 */
typedef struct Sending {
	// Признак отправки с сохранением границ записи
	bool bounds;
	// Признак потокового вида сокета
	bool stream;
	// Признак того, что весь файл принят к отправке
	bool queued;
	// Размер одного куска отправки
	size_t chunk;
	// Смещение неотправленного остатка в файле
	size_t offset;
	// Свободное место очереди при пустой очереди
	size_t capacity;
	// Содержимое отправляемого файла
	vector <uint8_t> payload;
	/**
	 * @brief Конструктор
	 *
	 */
	Sending() noexcept :
	 bounds(false), stream(true), queued(false),
	 chunk(0), offset(0), capacity(0) {}
} sending_t;

// Ход отправки файла
static sending_t __sending__;

/**
 * Признак завершения работы
 *
 * @note Цикл событий останавливается признаком, а не вызовом изнутри отклика:
 *       очистка движка из его же отклика цикл не прерывает
 */
static bool __done__ = false;

// Идентификатор события отправки
static event::id_t __event__ = 0;

/**
 * Выдержка перед закрытием подключения в миллисекундах
 *
 * @note Опустевшая очередь движка не значит доставленных данных: они лежат ещё в
 *       буфере ядра, и закрытие тут же обрывало бы хвост. Вежливого закрытия с
 *       досылкой в API нет, оттого выдержка и задаётся доводом запуска
 */
static uint32_t __linger__ = 3000;

/**
 * @brief Функция подсчёта контрольной суммы
 *
 * @details Считается FNV-1a - тем же способом, что и у принимающей стороны
 *
 * @param buffer буфер данных
 * @param size   размер буфера данных
 * @return       значение контрольной суммы
 *
 */
static uint64_t digest(const uint8_t * buffer, const size_t size) noexcept {
	// Начальное значение контрольной суммы
	uint64_t result = 0xCBF29CE484222325ULL;
	/**
	 * Перебираем все октеты буфера данных
	 */
	for(size_t i = 0; i < size; i++){
		// Подмешиваем очередной октет
		result ^= static_cast <uint64_t> (buffer[i]);
		// Домножаем на простое число FNV
		result *= 0x100000001B3ULL;
	}
	// Выводим значение контрольной суммы
	return result;
}

/**
 * @brief Функция чтения файла целиком
 *
 * @param filename адрес файла
 * @param result   буфер для содержимого файла
 * @return         результат работы функции
 *
 */
static bool load(const string & filename, vector <uint8_t> & result) noexcept {
	// Выполняем открытие файла на чтение
	FILE * file = ::fopen(filename.c_str(), "rb");
	// Если файл открыть не удалось
	if(file == nullptr)
		// Выводим отрицательный результат
		return false;
	// Буфер чтения файла
	uint8_t buffer[65536];
	// Количество прочитанных октетов
	size_t bytes = 0;
	/**
	 * Читаем файл до конца
	 */
	while((bytes = ::fread(buffer, 1, sizeof(buffer), file)) > 0)
		// Добавляем прочитанное в буфер содержимого
		result.insert(result.end(), buffer, buffer + bytes);
	// Выполняем закрытие файла
	::fclose(file);
	// Выводим положительный результат
	return true;
}

/**
 * @brief Функция проверки завершения отправки
 *
 * @details Опустевшей очередь считается по возврату свободного места к тому, каким
 *          оно было до первой отправки: всё, что было в очереди, ушло ядру, а его
 *          буфер дошлёт закрытие подключения
 *
 * @warning Проверять это откликом освобождения очереди НЕЛЬЗЯ: он приходит лишь
 *          вслед за переполнением, а короткий файл очередь не переполняет вовсе -
 *          отправка тогда завершалась бы, но никто бы об этом не узнал
 *
 * @param io  объект работы с асинхронными событиями
 * @param eid идентификатор события
 * @return    результат проверки
 *
 */
static bool complete(engine::io_t & io, const event::id_t eid) noexcept {
	// Выводим результат проверки
	return (__sending__.queued && (io.available(eid) >= __sending__.capacity));
}

/**
 * @brief Функция досылки остатка файла
 *
 * @details Зовётся и при подключении, и по освобождению места в очереди. Всякий
 *          вид отправки укладывается здесь по-своему, но правило одно: принято
 *          столько, сколько вернула очередь, и остаток ждёт следующего вызова
 *
 * @param io   объект работы с асинхронными событиями
 * @param sctp объект работы с протоколом SCTP
 * @param log  объект работы с логами
 * @param eid  идентификатор события
 *
 */
static void feed(engine::io_t & io, engine::sctp_t & sctp, const log_t & log, const event::id_t eid) noexcept {
	// Если весь файл уже принят к отправке
	if(__sending__.queued)
		// Выходим из функции
		return;
	// Общий размер отправляемого файла
	const size_t total = __sending__.payload.size();
	/**
	 * Досылаем остаток, пока очередь принимает
	 */
	while(__sending__.offset < total){
		// Указатель на неотправленный остаток
		const uint8_t * buffer = (__sending__.payload.data() + __sending__.offset);
		// Размер неотправленного остатка
		const size_t rest = (total - __sending__.offset);
		// Количество принятых к отправке октетов
		size_t accepted = 0;
		/**
		 * Если сокет упорядоченных сообщений либо потоковый с границами записи
		 */
		if(!__sending__.stream || __sending__.bounds){
			// Размер очередного куска отправки
			const size_t length = ((rest < __sending__.chunk) ? rest : __sending__.chunk);
			// Признак завершения сообщения на этом куске
			const bool end = (!__sending__.stream || ((__sending__.offset + length) >= total));
			// Метаданные отправляемого сообщения
			net::sctp::minfo_t info;
			// Выполняем отправку куска вместе с метаданными
			accepted = sctp.send(eid, buffer, length, info, end);
		// Иначе отправляем остаток целиком: очередь возьмёт сколько влезет
		} else accepted = io.send(eid, buffer, rest);
		// Если очередь не приняла ничего, ждём её освобождения
		if(accepted == 0)
			// Выходим из функции
			return;
		// Сдвигаем смещение неотправленного остатка
		__sending__.offset += accepted;
	}
	// Запоминаем, что весь файл принят к отправке
	__sending__.queued = true;
	// Выводим сообщение о том, что файл принят к отправке целиком
	log.print("Файл принят к отправке целиком: %zu октетов", log_t::flag_t::INFO, total);
}

/**
 * @brief Исполняемая функция приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]){
	// Если вид сокета либо адрес файла не названы
	if(argc < 3){
		// Выводим порядок запуска
		cout << " Запуск: " << argv[0] << " <STREAM|SEQPACKET> <файл> <границы: on|off> [адрес] [порт] [размер куска] [выдержка мс]" << endl;
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Определяем вид сокета
	__sending__.stream = (::strcasecmp(argv[1], "SEQPACKET") != 0);
	// Определяем признак сохранения границ записи
	__sending__.bounds = ((argc > 3) && (::strcasecmp(argv[3], "on") == 0));
	// Определяем адрес удалённого сервера
	const string target = ((argc > 4) ? argv[4] : "127.0.0.1");
	// Определяем порт удалённого сервера
	const uint16_t port = static_cast <uint16_t> ((argc > 5) ? ::atoi(argv[5]) : 2222);
	// Определяем размер одного куска отправки
	__sending__.chunk = static_cast <size_t> ((argc > 6) ? ::atol(argv[6]) : 4096);
	// Определяем выдержку перед закрытием подключения
	__linger__ = static_cast <uint32_t> ((argc > 7) ? ::atol(argv[7]) : 3000);
	/**
	 * У сокета упорядоченных сообщений границы записи заложены самим видом сокета
	 *
	 * @note Признак этот там ничего не меняет, и назвавшему его следует об этом сказать:
	 *       молчаливое пропускание довода выглядело бы так, будто он учтён
	 */
	if(!__sending__.stream && __sending__.bounds)
		// Выводим предупреждение
		cout << " Признак границ записи у сокета упорядоченных сообщений не значит ничего: границы там заложены видом сокета" << endl;
	// Объект фреймворка
	fmk_t fmk;
	// Объект работы с логами
	log_t log(&fmk);
	// Устанавливаем объект работы с логами
	fmk.setLogger(&log);
	// Если прочитать отправляемый файл не удалось
	if(!load(argv[2], __sending__.payload) || __sending__.payload.empty()){
		// Выводим сообщение об ошибке
		log.print("Файл прочитать не удалось либо он пуст: %s", log_t::flag_t::CRITICAL, argv[2]);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Общий размер отправляемого файла
	const size_t total = __sending__.payload.size();
	/**
	 * Считаем ожидаемое число записей у принимающей стороны
	 *
	 * @note У потокового сокета без границ записей нет вовсе, и ждать их неоткуда;
	 *       с границами весь файл обязан прийти одной записью; у сокета упорядоченных
	 *       сообщений записей столько, на сколько кусков файл нарезан
	 */
	const size_t records = (__sending__.stream
		? (__sending__.bounds ? 1 : 0)
		: ((total + __sending__.chunk - 1) / __sending__.chunk));
	// Выводим сведения об отправляемом файле
	log.print("ФАЙЛ: октетов=%zu записей=%zu сумма=%016llX", log_t::flag_t::INFO,
		total, records, static_cast <unsigned long long> (digest(__sending__.payload.data(), total)));
	// Объект асинхронного движка ввода-вывода
	engine::io_t io(&fmk, &log);
	// Объект работы с протоколом SCTP
	engine::sctp_t sctp(&fmk, &log);
	// Создаём событие клиента
	event::id_t eid = io.event(
		event::node_t::CLIENT, event::family_t::IPV4,
		(__sending__.stream ? event::type_t::STREAM : event::type_t::SEQPACKET),
		event::protocol_t::SCTP
	);
	// Устанавливаем порт удалённого сервера
	io.setTargetPort(eid, port);
	// Если завести движок не удалось
	if(!io.initialize()){
		// Выводим сообщение об ошибке
		log.print("Движок завести не удалось", log_t::flag_t::CRITICAL);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Устанавливаем опции события клиента
	io.setOptions(eid,
		event::options::NO_SIGILL | event::options::NO_SIGPIPE |
		event::options::NO_IO_BLOCK | event::options::CLOSE_ON_EXEC
	);
	// Если установить локальный адрес не удалось
	if(!io.setAddress(eid, event::address_t::IPV4, "0.0.0.0")){
		// Выводим сообщение об ошибке
		log.print("Локальный адрес установить не удалось", log_t::flag_t::CRITICAL);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Если установить адрес удалённого сервера не удалось
	if(!io.setTarget(eid, target)){
		// Выводим сообщение об ошибке
		log.print("Адрес удалённого сервера установить не удалось: %s", log_t::flag_t::CRITICAL, target.c_str());
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Устанавливаем отклик подключения
	io.on(eid, static_cast <engine::callback::connect_t> ([&io, &sctp, &log](const event::id_t eid, const bool ok) noexcept -> void {
		// Если подключиться не удалось
		if(!ok){
			// Выводим сообщение об ошибке
			log.print("Подключиться к серверу не удалось", log_t::flag_t::CRITICAL);
			// Выходим из функции
			return;
		}
		// Выводим сообщение об установленном подключении
		log.print("Подключение установлено", log_t::flag_t::INFO);
		/**
		 * Если границы записи затребованы, а система их не несёт - об этом надо сказать
		 *
		 * @note Отправка по частям опирается на режим явной границы записи, и без него
		 *       файл ушёл бы вереницей отдельных сообщений вместо одной записи. Молчать
		 *       об этом нельзя: итог сличения сторон стал бы необъяснимым
		 */
		if(__sending__.stream && __sending__.bounds && !sctp.partialSupported(eid))
			// Выводим предупреждение
			log.print("Границы записи система не поддерживает: файл уйдёт несколькими записями", log_t::flag_t::WARNING);
		// Запоминаем свободное место очереди при пустой очереди
		__sending__.capacity = io.available(eid);
		// Запоминаем идентификатор события отправки
		__event__ = eid;
		// Выполняем отправку файла
		feed(io, sctp, log, eid);
	}));
	// Устанавливаем отклик состояния события
	io.on(eid, [&io, &sctp, &log](const event::id_t eid, const event::status_t status) noexcept -> void {
		/**
		 * Определяем состояние события
		 */
		switch(static_cast <uint8_t> (status)){
			// Если очередь отправки переполнилась
			case static_cast <uint8_t> (event::status_t::QUEUE_OVERFLOW):
				// Выводим сообщение о переполнении очереди
				log.print("Очередь отправки переполнена: отправлено %zu из %zu", log_t::flag_t::INFO,
					__sending__.offset, __sending__.payload.size());
			break;
			// Если в очереди отправки освободилось место
			case static_cast <uint8_t> (event::status_t::QUEUE_AVAILABLE):
				// Досылаем остаток файла
				feed(io, sctp, log, eid);
			break;
		}
	});
	// Если зафиксировать настройки события не удалось
	if(!io.commit(eid)){
		// Выводим сообщение об ошибке
		log.print("Настройки события зафиксировать не удалось", log_t::flag_t::CRITICAL);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Если подключиться к серверу не удалось
	if(!io.connect(eid)){
		// Выводим сообщение об ошибке
		log.print("Подключение к серверу выполнить не удалось", log_t::flag_t::CRITICAL);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	// Если запустить событие не удалось
	if(!io.launch(eid)){
		// Выводим сообщение об ошибке
		log.print("Событие запустить не удалось", log_t::flag_t::CRITICAL);
		// Выходим с ошибкой
		return EXIT_FAILURE;
	}
	/**
	 * Крутим цикл событий, проверяя завершение отправки на всяком обороте
	 *
	 * @note Проверка стоит в цикле, а не в отклике: отклик освобождения очереди
	 *       приходит лишь вслед за её переполнением, а короткие файлы её не переполняют
	 */
	while(io.poll(100) && !__done__){
		// Если отправка ещё не завершена
		if((__event__ == 0) || !complete(io, __event__))
			// Продолжаем оборот цикла
			continue;
		// Выводим сообщение о завершении отправки
		log.print("Отправка завершена, выдерживаем %u мс перед закрытием", log_t::flag_t::INFO, __linger__);
		/**
		 * Выдерживаем время перед закрытием подключения
		 *
		 * @note Цикл событий продолжает крутиться: закрытие тут же оборвало бы хвост,
		 *       ещё лежащий в буфере ядра
		 */
		for(uint32_t i = 0; (i < __linger__) && io.poll(100); i += 100);
		// Устанавливаем признак завершения работы
		__done__ = true;
	}
	// Выполняем очистку движка, закрывая подключение
	io.clear();
	// Выходим успешно
	return EXIT_SUCCESS;
}

