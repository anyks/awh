/**
 * @brief Метод печати расхода памяти
 *
 * @param title заголовок печатаемого свода
 *
 */
static void consumption(const char * title) noexcept {
	// Печатаем заголовок свода
	::printf("\n%s\n", title);
	/**
	 * Опрашиваем все шесть величин расхода
	 *
	 * Занятое прикладным кодом и взятое у системы - величины РАЗНЫЕ: первое считает то,
	 * что запросило приложение, второе - то, что распределитель взял у системы под кучу
	 */
	::printf("  занято прикладным кодом: %zu байт\n", alloc::Allocator::property(alloc::property_t::ALLOCATED));
	::printf("  наибольшее за время работы: %zu байт\n", alloc::Allocator::property(alloc::property_t::PEAK));
	::printf("  взято у системы под кучу: %zu байт\n", alloc::Allocator::property(alloc::property_t::HEAP));
	::printf("  свободно в кэшах потоков: %zu байт\n", alloc::Allocator::property(alloc::property_t::CACHED));
	::printf("  свободно в куче: %zu байт\n", alloc::Allocator::property(alloc::property_t::PAGEFREE));
	::printf("  отдано системе обратно: %zu байт\n", alloc::Allocator::property(alloc::property_t::UNMAPPED));
}
/**
 * @brief Метод печати разбора адреса обращения
 *
 * @param title заголовок разбора
 * @param addr  разбираемый адрес
 *
 */
static void diagnose(const char * title, const void * addr) noexcept {
	// Разбираем адрес обращения
	const alloc::region_t region = alloc::Allocator::resolve(addr);
	// Название происхождения адреса
	const char * origin = "разобрать не удалось";
	/**
	 * Переводим происхождение адреса в понятное человеку
	 */
	switch(static_cast <uint8_t> (region.origin)){
		// Память нам не принадлежит вовсе
		case static_cast <uint8_t> (alloc::origin_t::FOREIGN): origin = "чужая память"; break;
		// Разыменование нулевого указателя
		case static_cast <uint8_t> (alloc::origin_t::NULLPAGE): origin = "нулевая страница"; break;
		// Живой выданный блок
		case static_cast <uint8_t> (alloc::origin_t::LIVE): origin = "живой выданный блок"; break;
		// Блок освобождён, но ещё под карантином
		case static_cast <uint8_t> (alloc::origin_t::FREED): origin = "освобождённый блок под карантином"; break;
		// Адрес за концом блока
		case static_cast <uint8_t> (alloc::origin_t::OVERRUN): origin = "обращение ЗА КОНЕЦ блока"; break;
		// Адрес перед началом блока
		case static_cast <uint8_t> (alloc::origin_t::UNDERRUN): origin = "обращение ПЕРЕД началом блока"; break;
	}
	// Печатаем разбор адреса
	::printf("  %-34s -> %s", title, origin);
	// Если блок опознан
	if(region.begin != nullptr)
		// Печатаем границы и смещение внутри блока
		::printf(" (начало %p, размер %zu, смещение %ld)",
		 region.begin, region.size, static_cast <long> (region.offset));
	// Переводим строку
	::printf("\n");
}
/**
 * @brief Главная функция приложения
 *
 * @return код выхода из приложения
 *
 */
int32_t main() noexcept {
	/**
	 * Заводим фреймворк
	 *
	 * Захват выдачи памяти процесса делает САМ конструктор фреймворка, единожды за
	 * процесс. Отдельно звать `capture` приложению незачем
	 */
	fmk_t fmk;
	// Заводим объект работы с журналом
	log_t log(&fmk, AWH_SHORT_NAME);
	// Печатаем расход сразу за заведением
	::consumption("Расход памяти сразу за заведением фреймворка");
	/**
	 * Задаём порядок работы распределителя
	 *
	 * Настройки задаются ВЫЗОВОМ, а не переменной окружения: управление памятью
	 * принадлежит приложению, а не окружению, в каком его запустили
	 */
	{
		// Берём действующие настройки, чтобы не затереть заданное прежде
		alloc::options_t options = alloc::Allocator::options();
		/**
		 * Отдаём память системе лишь по просьбе
		 *
		 * Сервер, отдающий страницы посреди наплыва запросов, платит за это задержкой:
		 * когда отдавать - решает приложение
		 */
		options.purgeMode = alloc::purge_t::MANUAL;
		// Просим засевать освобождаемое заметным образом
		options.fill = alloc::fill_t::JUNK;
		// Берём под заслоны каждую двадцатую выдачу
		options.guardRate = 20;
		// Берём под учёт места выдачи каждую пятую выдачу
		options.profileRate = 5;
		// Докладываем о всякой выдаче свыше мегабайта
		options.reportLarge = (1024 * 1024);
		/**
		 * Удерживаем освобождённое карантином
		 *
		 * Без карантина освобождённый блок тут же уходит в списки свободных, и обращение
		 * по висячему указателю неотличимо от обращения к живому: разбор ответит «живой
		 * блок», потому что блок этот уже принадлежит новому владельцу
		 */
		options.quarantine = (1024 * 1024);
		// Задаём требуемые настройки
		alloc::Allocator::options(options);
	}
	/**
	 * Ставим отклик доклада о крупной выдаче
	 *
	 * Ищет того, кто просит помногу: адрес и размер выдачи приходят сюда
	 */
	alloc::Allocator::onLarge([&log](const void * addr, const size_t size) noexcept -> void {
		// Записываем доклад о крупной выдаче в журнал
		log.print("Крупная выдача: %zu байт по адресу %p", log_t::flag_t::INFO, size, addr);
	});
	/**
	 * Ставим отклик упора в потолок кучи
	 *
	 * Зовётся, когда куче запрещено брать у системы сверх заданного
	 */
	alloc::Allocator::onLimit([&log](const size_t taken) noexcept -> void {
		// Записываем доклад об упоре в потолок в журнал
		log.print("Куча упёрлась в потолок: взято %zu байт", log_t::flag_t::WARNING, taken);
	});
	/**
	 * Занимаем память и смотрим, как меняется расход
	 */
	std::vector <void *> blocks;
	// Отводим место под перечень блоков заранее
	blocks.reserve(4096);
	/**
	 * Перебираем занимаемые блоки
	 */
	for(size_t i = 0; i < 4096; i++)
		// Занимаем очередной блок
		blocks.push_back(::malloc(64 + (i % 512)));
	/**
	 * Занимаем крупный блок
	 *
	 * Размер взят выше порога крупной выдачи (кусок кучи 4 МБ) и НЕ кратен странице:
	 * такой блок обслуживает отдельный слой, и затребованный размер он помнит - оттого
	 * хвост до границы страницы опознаётся переполнением, а не живой памятью
	 */
	const size_t enormous = ((5 * 1024 * 1024) + 100);
	// Занимаем крупный блок: он вызовет и доклад о крупной выдаче
	void * huge = ::malloc(enormous);
	// Печатаем расход под нагрузкой
	::consumption("Расход памяти под нагрузкой");
	/**
	 * Разбираем адреса обращения
	 *
	 * Это и есть разбор сбоя: получив адрес из обработчика сбоя, приложение узнаёт,
	 * что именно случилось, - а не гадает по снимку памяти
	 */
	::printf("\nРазбор адресов обращения\n");
	// Разбираем нулевой указатель со смещением
	::diagnose("разыменование нуля со смещением", reinterpret_cast <const void *> (0x20));
	// Разбираем адрес на стеке
	::diagnose("адрес на стеке", &blocks);
	// Разбираем живой блок
	::diagnose("живой выданный блок", blocks[100]);
	/**
	 * Разбираем адрес за концом крупной выдачи
	 *
	 * Берём крупный блок, а не блок разряда: разряд округляет размер вверх, и запас
	 * внутри разряда принадлежит тому же блоку - обращение туда числится живым, а не
	 * переполнением. У крупной же выдачи область приведена к границе страницы, и хвост
	 * за концом затребованного - наш, оттого переполнение там видно
	 */
	::diagnose("адрес за концом крупной выдачи",
	 reinterpret_cast <const uint8_t *> (huge) + enormous + 8);
	/**
	 * Разбираем освобождённый блок, удерживаемый карантином
	 *
	 * Карантин удерживает освобождённое, чтобы обращение по висячему указателю
	 * опозналось, а не досталось новому владельцу
	 */
	{
		// Запоминаем адрес возвращаемого блока
		void * dangling = blocks[200];
		// Освобождаем блок
		::free(dangling);
		// Снимаем блок с учёта: он уже возвращён
		blocks[200] = nullptr;
		// Разбираем адрес освобождённого блока
		::diagnose("висячий указатель", dangling);
	}
	/**
	 * Обходим удерживаемое, взятое под учёт мест выдачи
	 *
	 * Учёт выборочный: под него попадает каждая пятая выдача, как задано выше. Обход
	 * прекращается ответом `false`
	 */
	::printf("\nУдерживаемое под учётом мест выдачи\n");
	// Число напечатанных записей
	size_t printed = 0;
	/**
	 * Обходим удерживаемое ЦЕЛИКОМ, печатая лишь первые записи
	 *
	 * Обход прекращается ответом `false`, но тогда и ответ метода - число ПРОЙДЕННЫХ
	 * записей, а не всех удерживаемых. Прекрати мы обход после третьей печати - метод
	 * ответил бы «четыре», и подпись под сводом лгала бы
	 */
	const size_t held = alloc::Allocator::holdings([&printed](const alloc::holding_t & holding) noexcept -> bool {
		// Если печатать больше не нужно
		if(printed < 3){
			// Считаем напечатанную запись
			printed++;
			// Печатаем запись об удерживаемом блоке
			::printf("  блок %p, затребовано %zu байт, глубина стека %zu\n",
			 holding.block, holding.size, holding.depth);
		}
		// Продолжаем обход
		return true;
	});
	// Печатаем число удерживаемых блоков
	::printf("  всего под учётом: %zu блоков из 4096 выданных\n", held);
	/**
	 * Освобождаем занятое и отдаём память системе
	 */
	for(void * block : blocks){
		// Если блок уже возвращён
		if(block == nullptr)
			// Возвращать нечего
			continue;
		// Освобождаем очередной блок
		::free(block);
	}
	// Освобождаем крупный блок
	::free(huge);
	// Печатаем расход до отдачи системе
	::consumption("Расход памяти после освобождения, но ДО отдачи системе");
	/**
	 * Просим отдать память системе
	 *
	 * Способ отдачи задан выше как `MANUAL`: без этой просьбы освобождённое осталось бы
	 * лежать в куче нашим
	 */
	const size_t given = alloc::Allocator::purge();
	// Печатаем объём отданного системе
	::printf("\nОтдано системе по просьбе: %zu байт\n", given);
	// Печатаем расход после отдачи
	::consumption("Расход памяти ПОСЛЕ отдачи системе");
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
