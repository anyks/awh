/**
 * @brief Метод печати состоявшейся защиты блока
 *
 * @param title   заголовок печатаемого свода
 * @param shelter сведения о защите выданного блока
 *
 */
static void protection(const char * title, const alloc::shelter_t & shelter) noexcept {
	/**
	 * Печатаем то, что состоялось НА ДЕЛЕ, а не то, о чём просили
	 *
	 * Укрытия от снимка памяти нет у Linux, macOS и NetBSD, а запрет подкачки требует
	 * прав у illumos и ограничен пределом у всех систем. Молчаливое понижение защиты
	 * хуже честного отказа: годится ли она, решает звавший, а не распределитель
	 */
	::printf("%s\n", title);
	::printf("  укрыт от снимка памяти: %s\n", (shelter.hidden ? "да" : "НЕТ"));
	::printf("  запрещена подкачка: %s\n", (shelter.wired ? "да" : "НЕТ"));
}
/**
 * @brief Метод, показывающий прямую выдачу укрытой памяти
 *
 */
static void direct() noexcept {
	// Сведения о состоявшейся защите
	alloc::shelter_t shelter;
	/**
	 * Просим укрытую память под опознаватель сеанса
	 *
	 * Выдача идёт СТРАНИЦАМИ: укрытие и запрет подкачки система выдаёт не мельче
	 * страницы, оттого сорок восемь байт обойдутся в целую страницу. Держать здесь
	 * мелочь россыпью расточительно - место это заведено под ключи и пароли
	 */
	void * secret = alloc::Allocator::secure(48, &shelter);
	// Если выдать укрытую память не вышло
	if(secret == nullptr){
		// Сообщаем о неудаче
		::printf("Укрытую память выдать не удалось\n");
		// Выходим из метода
		return;
	}
	// Заполняем выданное содержимым
	::memcpy(secret, "0123456789abcdef0123456789abcdef0123456789abcde", 48);
	// Печатаем состоявшуюся защиту
	::protection("\nПрямая выдача укрытой памяти под опознаватель сеанса", shelter);
	/**
	 * Спрашиваем распределитель, чем он считает выданный адрес
	 *
	 * Укрытая выдача - такой же наш блок, как и обычный: разбор адреса узнаёт её
	 */
	const alloc::region_t region = alloc::Allocator::resolve(secret);
	// Печатаем то, чем распределитель считает выданный адрес
	::printf("  разбор адреса: %s, размер %zu байт\n",
	 ((region.origin == alloc::origin_t::LIVE) ? "живой выданный блок" : "НЕ живой блок"), region.size);
	/**
	 * Возвращаем укрытую память через `release`, а НЕ через `free`
	 *
	 * Совпадают они лишь там, где захват выдачи памяти процесса состоялся: у macOS и
	 * MS Windows без захвата `free` принадлежит системе и нашу область не узнаёт - она
	 * валит программу отказом «pointer being freed was not allocated»
	 *
	 * Затирать содержимое перед возвратом не нужно: затирание обещано самой укрытой
	 * выдачей - распределитель обнуляет область прежде, чем вернуть её системе
	 */
	alloc::Allocator::release(secret);
	// Сообщаем о возврате
	::printf("  память возвращена через release, содержимое затёрто распределителем\n");
}
/**
 * @brief Метод, показывающий хранилища языка на укрытой памяти
 *
 */
static void containers() noexcept {
	// Тип строки, содержимое которой лежит в укрытой памяти
	typedef std::basic_string <char, std::char_traits <char>, alloc::Keeper <char>> secret_t;
	// Тип перечня байтов, лежащего в укрытой памяти
	typedef std::vector <uint8_t, alloc::Keeper <uint8_t>> key_t;
	/**
	 * Тип отображения имени на ключ
	 *
	 * Распределитель здесь задан для пары, а на узлы дерева его переносит `rebind`:
	 * хранилищу узлов не видно, чем выдаётся память самой пары
	 */
	typedef std::map <secret_t, key_t, std::less <secret_t>,
	 alloc::Keeper <std::pair <const secret_t, key_t>>> store_t;
	/**
	 * Строка берётся ДЛИННАЯ намеренно
	 *
	 * Короткая строка живёт внутри самого объекта - хранилище языка держит запас на
	 * месте и к распределителю не обращается вовсе. Пароль на десяток знаков, положенный
	 * в такую строку, укрытым НЕ станет, и это свойство языка, а не наш пробел
	 */
	secret_t password("пароль, что длиннее внутреннего запаса строки и оттого лежит в укрытой памяти");
	// Заводим ключ на укрытой памяти
	key_t key(64, 0xA5);
	// Заводим хранилище ключей на укрытой памяти
	store_t store;
	// Кладём ключ в хранилище
	store.emplace(password, key);
	// Печатаем свод по хранилищам
	::printf("\nХранилища языка на укрытой памяти\n");
	::printf("  длина пароля: %zu знаков\n", password.size());
	::printf("  длина ключа: %zu байт\n", key.size());
	::printf("  записей в хранилище: %zu\n", store.size());
	/**
	 * Спрашиваем распределитель, чем он считает содержимое строки
	 *
	 * Адрес этот выдан `Keeper`-ом, стало быть укрытой выдачей: разбор обязан узнать в
	 * нём живой блок. Если бы строка оказалась короткой, разбор ответил бы «чужая
	 * память» - содержимое лежало бы на стеке внутри самого объекта
	 */
	const alloc::region_t region = alloc::Allocator::resolve(password.data());
	// Печатаем то, чем распределитель считает содержимое строки
	::printf("  содержимое строки: %s\n",
	 ((region.origin == alloc::origin_t::LIVE) ? "лежит в укрытой памяти" : "лежит ВНУТРИ объекта (запас строки)"));
	/**
	 * Хранилища освобождать вручную не нужно
	 *
	 * Уходя, они зовут `deallocate` распределителя, а тот - `release`. Затирание
	 * содержимого обещано самой укрытой выдачей
	 */
}
/**
 * @brief Метод, показывающий цену страничной выдачи
 *
 */
static void expense() noexcept {
	// Число выдач, на которых показываем цену
	const size_t count = 16;
	// Перечень выданных блоков
	void * blocks[count];
	// Запоминаем расход до выдачи
	const size_t before = alloc::Allocator::property(alloc::property_t::HEAP);
	// Выполняем перебор выдач
	for(size_t i = 0; i < count; i++)
		// Просим по шестнадцать байт укрытой памяти
		blocks[i] = alloc::Allocator::secure(16, nullptr);
	// Запоминаем расход после выдачи
	const size_t after = alloc::Allocator::property(alloc::property_t::HEAP);
	/**
	 * Печатаем цену выдачи россыпью
	 *
	 * Просили 256 байт, а взято у системы кратно странице на КАЖДУЮ выдачу: мельче
	 * страницы система укрытие не выдаёт
	 */
	::printf("\nЦена страничной выдачи\n");
	::printf("  запрошено: %zu байт (%zu выдач по 16)\n", (count * 16), count);
	::printf("  взято у системы: %zu байт\n", ((after > before) ? (after - before) : 0));
	// Выполняем перебор выданных блоков
	for(size_t i = 0; i < count; i++){
		// Если блок выдан
		if(blocks[i] != nullptr)
			// Возвращаем блок распределителю
			alloc::Allocator::release(blocks[i]);
	}
}
/**
 * @brief Функция входа в приложение
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Параметры приложения здесь не нужны
	static_cast <void> (argc);
	static_cast <void> (argv);
	// Создаём объект фреймворка
	fmk_t fmk;
	// Создаём объект журнала
	log_t log(&fmk);
	// Устанавливаем название приложения журналу
	log.name(AWH_SHORT_NAME);
	// Показываем прямую выдачу укрытой памяти
	::direct();
	// Показываем хранилища языка на укрытой памяти
	::containers();
	// Показываем цену страничной выдачи
	::expense();
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
