#include <vector>

/**
 * Разбор искажённых имён
 *
 * Собиратель искажает имена функций, вплетая в них пространства имён и виды доводов, и
 * средства связывания отдают их такими, как есть: `_ZL7leakingmm` вместо
 * `leaking(unsigned long, unsigned long)`. Разбор их даёт сама библиотека времени
 * исполнения C++, и звать его прикладному коду можно свободно - он выделяет память, а мы
 * стоим вне всякой выдачи
 *
 * У MSVC заголовка этого нет, но и сборка под него не поддерживается: «Windows» здесь
 * означает MinGW, а тот тем же средством и пользуется
 */
#if !defined(_MSC_VER)
	#define AWH_SAMPLE_DEMANGLE 1
	#include <cxxabi.h>
#endif

/**
 * Используем пространство имён AWH
 */
using namespace awh;

/**
 * @brief Метод печати места выдачи блока
 *
 * @param holding сведения об удерживаемом блоке
 *
 */
static void origin(const alloc::holding_t & holding) noexcept {
	// Печатаем сам блок
	::printf("  блок %p, %zu байт\n", holding.block, holding.size);
	/**
	 * Перебираем уровни стека вызовов места выдачи
	 *
	 * Стек начинается с того, кто позвал выдачу, и ближние уровни приходятся на сам
	 * распределитель да на стандартную библиотеку: сколько их - зависит от подстановки
	 * у собирателя, и обрезать их числом наперёд значило бы обрезать наугад. Оттого
	 * печатаются все, а разбирает их глаз
	 */
	for(size_t i = 0; i < holding.depth; i++){
		// Сведения о разобранном адресе
		alloc::symbol_t symbol;
		/**
		 * Обращаем адрес стека в имя
		 *
		 * Имени у статической функции может не быть вовсе - она не лежит в таблице имён
		 * образа, - и тогда место называет одно лишь смещение от начала образа
		 */
		if(!alloc::Allocator::symbol(holding.frames[i], symbol)){
			// Печатаем неразобранный уровень
			::printf("    #%zu %p\n", i, holding.frames[i]);
			// Переходим к следующему уровню
			continue;
		}
		// Название функции, годное к печати
		const char * name = ((symbol.name != nullptr) ? symbol.name : "<без имени>");
		/**
		 * Разбираем искажённое имя, если оно есть
		 */
		#if defined(AWH_SAMPLE_DEMANGLE)
			// Итог разбора искажённого имени
			int32_t status = 0;
			// Разобранное имя функции, выданное разбором
			char * plain = ((symbol.name != nullptr) ? ::abi::__cxa_demangle(symbol.name, nullptr, nullptr, &status) : nullptr);
			// Если имя разобрано
			if((plain != nullptr) && (status == 0))
				// Печатаем разобранное имя
				name = plain;
		#endif
		// Печатаем разобранный уровень стека вызовов
		::printf("    #%zu %p %s+0x%zx (%s)\n", i, holding.frames[i], name,
		 static_cast <size_t> (symbol.offset),
		 ((symbol.image != nullptr) ? symbol.image : "<без образа>"));
		/**
		 * Отдаём память разобранного имени
		 *
		 * Выдаёт её сам разбор, а освободить обязан звавший: договор этот записан у
		 * `__cxa_demangle`
		 */
		#if defined(AWH_SAMPLE_DEMANGLE)
			// Если разбор выдал память
			if(plain != nullptr)
				// Отдаём память разобранного имени
				::free(plain);
		#endif
	}
}
/**
 * @brief Метод, теряющий память намеренно
 *
 * @note Заведён отдельной функцией, чтобы имя его встало в стеке места выдачи: ровно
 *       так течь и разыскивается - по имени того, кто просил
 *
 * @param count число теряемых блоков
 * @param size  размер теряемого блока в байтах
 *
 */
static void leaking(const size_t count, const size_t size) noexcept {
	/**
	 * Перебираем теряемые блоки
	 */
	for(size_t i = 0; i < count; i++){
		// Занимаем очередной блок
		void * block = ::malloc(size);
		// Если блок не выдан
		if(block == nullptr)
			// Терять нечего
			return;
		// Записываем в блок узнаваемое содержимое
		::memset(block, 0x5A, size);
	}
	/**
	 * Блоки не освобождаются НАМЕРЕННО: это и есть разыскиваемая течь
	 */
}
/**
 * @brief Главная функция приложения
 *
 * @return код выхода из приложения
 *
 */
int32_t main() noexcept {
	/**
	 * Заводим фреймворк
	 *
	 * Захват выдачи памяти процесса делает САМ конструктор фреймворка, единожды за
	 * процесс
	 */
	fmk_t fmk;
	// Заводим объект работы с журналом
	log_t log(&fmk, AWH_SHORT_NAME);
	/**
	 * Спрашиваем, состоялся ли захват
	 *
	 * Спросить стоит прежде всего прочего: под санитайзерами захват НЕ состоится - те
	 * подменяют распределитель собою и уступить его не могут, - и все средства разбора
	 * ниже промолчат. Молчание это неотличимо от чистого прогона, и различить их можно
	 * лишь здесь
	 */
	if(!alloc::Allocator::captured()){
		// Записываем отказ захвата в журнал
		log.print("Выдача памяти процесса не захвачена: средства разбора недоступны", log_t::flag_t::WARNING);
		// Выводим успешный код выхода: это не дефект приложения
		return EXIT_SUCCESS;
	}
	/**
	 * Включаем средства разбора
	 */
	{
		// Берём действующие настройки, чтобы не затереть заданное прежде
		alloc::options_t options = alloc::Allocator::options();
		/**
		 * Удерживаем освобождённое карантином и засеваем его
		 *
		 * Пара эта неразделима: карантин держит освобождённый блок у себя, а засев
		 * делает всякую запись в него заметной. Без засева карантин ловит лишь
		 * обращение по висячему указателю разбором адреса, но не запись
		 */
		options.quarantine = (1024 * 1024);
		// Просим засевать освобождаемое заметным образом
		options.fill = alloc::fill_t::JUNK;
		/**
		 * Берём под учёт КАЖДУЮ выдачу
		 *
		 * Доля выборки - размен точности на скорость: при поиске течи важнее увидеть
		 * всех просящих, а не уложиться в такты. В бою доля ставится крупнее
		 */
		options.profileRate = 1;
		// Задаём требуемые настройки
		alloc::Allocator::options(options);
	}
	/**
	 * Совершаем запись по освобождённому указателю
	 *
	 * Дефект этот тем и опасен, что молчит: блок уходит в списки свободных, достаётся
	 * новому владельцу, и запись портит ЕГО данные - а падение случается позже и в
	 * другом месте
	 */
	{
		// Занимаем блок под будущий дефект
		void * dangling = ::malloc(4096);
		// Если блок выдан
		if(dangling != nullptr){
			// Освобождаем блок
			::free(dangling);
			/**
			 * Пишем по уже освобождённому указателю
			 *
			 * Блок лежит под карантином и засеян: запись эта засев и портит
			 */
			::memset(dangling, 0x11, 4096);
		}
	}
	/**
	 * Гоняем выдачу и возврат, чтобы карантин дошёл до испорченного блока
	 *
	 * Сличение засева идёт при ИЗЪЯТИИ блока из карантина, а изымается он лишь тогда,
	 * когда удерживаемое перевалило за потолок: без нагрузки блок лежал бы в кольце до
	 * конца работы, и дефект остался бы неназванным
	 */
	{
		// Сток, не дающий собирателю выбросить холостую пару выдачи и возврата
		static volatile uint8_t sink = 0;
		/**
		 * Перебираем блоки нагрузки
		 */
		for(size_t i = 0; i < 8192; i++){
			// Занимаем очередной блок нагрузки
			uint8_t * block = reinterpret_cast <uint8_t *> (::malloc(4096));
			// Если блок не выдан
			if(block == nullptr)
				// Гонять больше нечего
				break;
			// Записываем в блок узнаваемое содержимое
			block[0] = static_cast <uint8_t> (i);
			// Читаем записанное в сток
			sink = static_cast <uint8_t> (sink + block[0]);
			// Освобождаем очередной блок нагрузки
			::free(block);
		}
	}
	/**
	 * Спрашиваем карантин о записях по освобождённому
	 */
	{
		// Адрес первого испорченного блока
		const void * culprit = nullptr;
		// Смещение первой порчи от начала блока
		size_t offset = 0;
		// Опрашиваем число испорченных блоков
		const size_t spoiled = alloc::Allocator::spoiled(&culprit, &offset);
		// Печатаем заголовок свода
		::printf("\nЗаписи по освобождённым блокам\n");
		// Если испорченные блоки нашлись
		if(spoiled > 0)
			// Печатаем сведения о порче
			::printf("  найдено блоков: %zu, первый по адресу %p со смещением %zu\n", spoiled, culprit, offset);
		// Иначе записей по освобождённому не нашлось
		else ::printf("  не найдено ни одной\n");
	}
	/**
	 * Теряем память намеренно и разыскиваем течь
	 */
	::leaking(3, (64 * 1024));
	{
		// Печатаем заголовок свода
		::printf("\nМеста выдачи удерживаемой памяти\n");
		// Число напечатанных мест выдачи
		size_t printed = 0;
		/**
		 * Перебираем удерживаемое прикладным кодом
		 *
		 * Порядок обхода не обещан ничем, и полагаться на него нельзя: отбирает нужное
		 * сам отклик - здесь по размеру блока
		 */
		const size_t held = alloc::Allocator::holdings([&printed](const alloc::holding_t & holding) noexcept -> bool {
			/**
			 * Отбираем блоки крупнее тридцати двух килобайт
			 *
			 * Отбор нужен: под учётом лежит и память самого фреймворка, а разыскивается
			 * течь приложения. Мера отбора - дело разыскивающего
			 */
			if(holding.size < (32 * 1024))
				// Продолжаем обход
				return true;
			// Печатаем место выдачи блока
			::origin(holding);
			// Увеличиваем число напечатанных мест выдачи
			printed++;
			// Прекращаем обход, напечатав первые пять
			return (printed < 5);
		});
		// Печатаем число блоков под учётом
		::printf("  всего под учётом блоков: %zu, напечатано мест: %zu\n", held, printed);
	}
	/**
	 * Снимаем захват выдачи памяти процесса
	 *
	 * @warning Снятие это - работа НЕОБЫЧНАЯ, и здесь оно показано лишь ради полноты
	 *          договора. Память, выданная нами до снятия, освобождается после него
	 *          прежним распределителем - тем, который её не выдавал. Приложению,
	 *          снявшему захват посреди работы, придётся отвечать за все такие блоки
	 *          самому; обычный же порядок - не снимать его вовсе до конца процесса
	 */
	// Печатаем захваченность до снятия
	::printf("\nЗахват выдачи памяти: %s\n", (alloc::Allocator::captured() ? "состоялся" : "снят"));
	// Снимаем захват выдачи памяти процесса
	alloc::Allocator::surrender();
	// Печатаем захваченность после снятия
	::printf("Захват выдачи памяти: %s\n", (alloc::Allocator::captured() ? "состоялся" : "снят"));
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
