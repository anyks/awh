/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * Размер неподвижной области в байтах
	 *
	 * Область лежит в самой программе, а не берётся у системы: в том и весь смысл
	 * образца. Тридцать два мегабайта - число для примера; настоящему приложению его
	 * задаёт наибольший расход, какой оно себе позволяет
	 */
	static constexpr size_t ARENA = (32u * 1024u * 1024u);
	/**
	 * Размер страницы источника в байтах
	 *
	 * Величина эта - договор с куче: та кроит область кусками, кратными ей. Берём
	 * привычные четыре килобайта, не спрашивая систему: источник наш системе ничего не
	 * должен
	 */
	static constexpr size_t GRAIN = 4096u;
	/**
	 * Сама неподвижная область
	 *
	 * `alignas` на области ЭТОГО размера НЕ РАБОТАЕТ, и работать не может
	 *
	 * Просить у собирателя выравнивание по размеру куска (четыре мегабайта) бесполезно:
	 * связыватель macOS урезает его до предела раздела - «reducing alignment of section
	 * __DATA,__bss from 0x400000 to 0x4000», - а собиратель об этом не узнаёт и по-прежнему
	 * верит обещанию. Проверено опытом: `(uintptr_t) arena % CHUNK` он свернул в НОЛЬ
	 * прямо в машинном коде, тогда как настоящий остаток на трёх запусках выходил
	 * 3 440 640, 540 672 и 1 818 624 байта. Ложь эта тихая: программа считает область
	 * выровненной и ошибается на мегабайты
	 *
	 * Оттого место берётся с запасом на кусок, а начало приводится к границе НА ХОДУ:
	 * настоящее выравнивание известно лишь во время работы
	 */
	static uint8_t __awh_arena__[ARENA + alloc::Pages::CHUNK];
	/**
	 * @brief Метод получения начала выровненной области
	 *
	 * @return начало области, приведённое к границе куска страничной кучи
	 *
	 */
	static uint8_t * base() noexcept {
		// Определяем адрес отведённого места
		const uintptr_t place = reinterpret_cast <uintptr_t> (::__awh_arena__);
		// Приводим адрес к границе куска страничной кучи
		return reinterpret_cast <uint8_t *> ((place + (alloc::Pages::CHUNK - 1)) & ~static_cast <uintptr_t> (alloc::Pages::CHUNK - 1));
	}
	/**
	 * \~russian
	 * @brief Класс источника страниц поверх неподвижной области
	 *
	 * @details Отдавать источнику нечего: область неподвижна, и всё, что у неё взято,
	 *          остаётся взятым до конца работы программы. Оттого `purge` и `release`
	 *          отвечают отказом, а не молчаливым успехом: отказ означает «не умею», и
	 *          учёт отданного системе честно останется нулём
	 *
	 * @details Выдача идёт сдвигом черты, без списков свободного: списки свободных
	 *          областей ведёт слой выше - страничная куча, - и заводить их ещё и здесь
	 *          значило бы вести один и тот же учёт дважды
	 *
	 */
	typedef class ArenaSource : public alloc::Source {
		private:
			// Черта занятого в области
			size_t _taken;
			/**
			 * Наибольший пропуск, оставленный подгонкой под выравнивание
			 *
			 * Без него сдвиг черты теряет на подгонке ПОЛОВИНУ области: куски страничной
			 * кучи выровнены по своему размеру, и между концом одного куска и началом
			 * следующего ложится пропуск почти в целый кусок. Замерено на этом самом
			 * образце - шестнадцать мегабайт области под восемь мегабайт кусков, ровно
			 * вдвое. С возвратом пропуска то же самое укладывается в двенадцать
			 *
			 * Помнится ОДИН пропуск, наибольший: настоящий учёт свободного ведёт слой
			 * выше, а здесь он был бы тем же учётом во второй раз. Оттого четыре мегабайта
			 * всё же теряются - это цена простоты источника, и она названа, а не скрыта
			 */
			// Начало наибольшего пропуска
			size_t _gap;
			// Конец наибольшего пропуска
			size_t _gapEnd;
		public:
			/**
			 * @brief Метод выдачи области страниц
			 *
			 * @param size      требуемый размер в байтах
			 * @param alignment требуемое выравнивание в байтах
			 * @param actual    действительно выданный размер
			 * @return          адрес выданной области либо nullptr
			 *
			 */
			void * alloc(const size_t size, const size_t alignment, size_t & actual) noexcept override {
				// Обнуляем действительно выданный размер
				actual = 0;
				// Если выдавать нечего
				if(size == 0)
					// Выдавать нечего
					return nullptr;
				// Приводим требуемое выравнивание к размеру страницы источника
				const size_t align = ((alignment > GRAIN) ? alignment : GRAIN);
				// Если выравнивание не является степенью двойки
				if((align & (align - 1)) != 0)
					// Выравнивать нечем
					return nullptr;
				// Определяем начало выровненной области
				const uintptr_t base = reinterpret_cast <uintptr_t> (::base());
				// Приводим черту занятого к границе выравнивания
				const uintptr_t begin = (((base + this->_taken) + (align - 1)) & ~static_cast <uintptr_t> (align - 1));
				// Приводим требуемый размер к границе страницы источника
				const size_t whole = ((size + (GRAIN - 1)) & ~static_cast <size_t> (GRAIN - 1));
				/**
				 * Пробуем выдать из пропуска, прежде чем двигать черту
				 *
				 * Пропуск оставлен подгонкой прошлой выдачи, и лежит он ПОЗАДИ черты:
				 * не отдай мы его - он пропал бы навсегда
				 */
				{
					// Приводим начало пропуска к границе выравнивания
					const uintptr_t taken = (((base + this->_gap) + (align - 1)) & ~static_cast <uintptr_t> (align - 1));
					// Если требуемое помещается в пропуск
					if(((taken - base) + whole) <= this->_gapEnd){
						// Сдвигаем начало пропуска за выданное
						this->_gap = ((taken - base) + whole);
						// Запоминаем действительно выданный размер
						actual = whole;
						// Выводим выданную область
						return reinterpret_cast <void *> (taken);
					}
				}
				/**
				 * Отвечаем отказом, если в области больше нет места
				 *
				 * Отказ этот - обычный исход, а не сбой: приложение само задало предел,
				 * отведя область такого размера. Наверх он уходит пустотой от `malloc`
				 */
				if(((begin - base) + whole) > ARENA)
					// Выдавать нечего
					return nullptr;
				/**
				 * Запоминаем пропуск, оставленный подгонкой
				 *
				 * Помним лишь наибольший: мелкие пропуски не окупают своего учёта
				 */
				if(((begin - base) - this->_taken) > (this->_gapEnd - this->_gap)){
					// Запоминаем начало пропуска
					this->_gap = this->_taken;
					// Запоминаем конец пропуска
					this->_gapEnd = (begin - base);
				}
				// Сдвигаем черту занятого за выданную область
				this->_taken = ((begin - base) + whole);
				// Запоминаем действительно выданный размер
				actual = whole;
				// Выводим выданную область
				return reinterpret_cast <void *> (begin);
			}
			/**
			 * @brief Метод отдачи содержимого страниц системе
			 *
			 * @param addr адрес отдаваемой области
			 * @param size размер отдаваемой области
			 * @return     признак выполнения операции
			 *
			 */
			bool purge(void * addr, const size_t size) noexcept override {
				// Отдавать нечего: область неподвижна и системе не принадлежит
				(void) addr; (void) size;
				// Отвечаем отказом: отдачи у этого источника нет
				return false;
			}
			/**
			 * @brief Метод отдачи области системе целиком
			 *
			 * @param addr адрес отдаваемой области
			 * @param size размер отдаваемой области
			 * @return     признак выполнения операции
			 *
			 */
			bool release(void * addr, const size_t size) noexcept override {
				// Отдавать нечего: область неподвижна и системе не принадлежит
				(void) addr; (void) size;
				// Отвечаем отказом: отдачи у этого источника нет
				return false;
			}
		public:
			/**
			 * @brief Метод получения размера страницы источника
			 *
			 * @return размер страницы в байтах
			 *
			 */
			size_t granularity() const noexcept override {
				// Выводим размер страницы источника
				return GRAIN;
			}
		public:
			/**
			 * @brief Метод получения занятого в области
			 *
			 * @return занятое в области в байтах
			 *
			 */
			size_t taken() const noexcept {
				// Выводим занятое в области
				return this->_taken;
			}
		public:
			/**
			 * @brief Конструктор
			 *
			 */
			ArenaSource() noexcept : _taken(0), _gap(0), _gapEnd(0) {}
	} arena_source_t;
	/**
	 * Сам источник страниц поверх неподвижной области
	 *
	 * Заводится переменной процесса, а не в теле `main`: подмена источника случается
	 * прежде первой выдачи, и источник обязан пережить всякую память, какую он выдал -
	 * включая ту, что освобождается уже после выхода из `main`
	 */
	static arena_source_t __awh_source__;
	/**
	 * @brief Метод печати расхода памяти
	 *
	 * @param title заголовок печатаемого свода
	 *
	 */
	static void consumption(const char * title) noexcept {
		// Печатаем заголовок свода
		::printf("\n%s\n", title);
		// Печатаем занятое прикладным кодом
		::printf("  занято прикладным кодом: %zu байт\n", alloc::Allocator::property(alloc::property_t::ALLOCATED));
		// Печатаем взятое у источника
		::printf("  взято у источника: %zu байт\n", alloc::Allocator::property(alloc::property_t::HEAP));
		// Печатаем свободное в кэшах потоков
		::printf("  свободно в кэшах потоков: %zu байт\n", alloc::Allocator::property(alloc::property_t::CACHED));
		// Печатаем свободное в страничной куче
		::printf("  свободно в страничной куче: %zu байт\n", alloc::Allocator::property(alloc::property_t::PAGEFREE));
		/**
		 * Печатаем отданное источнику
		 *
		 * У этого источника оно останется нулём при любой нагрузке: отдачи он не умеет и
		 * отвечает отказом, а учёт считает лишь СОСТОЯВШУЮСЯ отдачу
		 */
		::printf("  отдано источнику: %zu байт\n", alloc::Allocator::property(alloc::property_t::UNMAPPED));
		// Печатаем занятое в самой неподвижной области
		::printf("  занято в неподвижной области: %zu из %zu байт\n", ::__awh_source__.taken(), ARENA);
	}
};

/**
 * @brief Главная функция приложения
 *
 * @return код выхода из приложения
 *
 */
int32_t main() noexcept {
	/**
	 * Подменяем источник страниц ПРЕЖДЕ всякой выдачи
	 *
	 * Ответ метода обязан быть проверен, а не предположен: подмена состоится лишь тогда,
	 * когда до неё никто не просил памяти через нас. Зависит это не от системы, а от
	 * того, что успело случиться в процессе, - у части систем куча заводится ещё при
	 * заведении переменных процесса, прежде первой строки `main`
	 */
	if(!alloc::Allocator::source(&::__awh_source__)){
		// Сообщаем об отказе подмены
		::printf("Подменить источник страниц не удалось: память уже бралась через нас\n");
		/**
		 * Уходим с успехом, а не с отказом
		 *
		 * Это не сбой образца, а свойство окружения, в каком его запустили: приложению,
		 * которому свой источник нужен непременно, следует ставить его первым же
		 * действием и собираться так, чтобы до него ничего не выделялось
		 */
		return EXIT_SUCCESS;
	}
	// Сообщаем о состоявшейся подмене
	::printf("Источник страниц подменён: память берётся из неподвижной области\n");
	/**
	 * Задаём порядок работы распределителя
	 */
	{
		// Берём действующие настройки, чтобы не затереть заданное прежде
		alloc::options_t options = alloc::Allocator::options();
		/**
		 * Запрещаем обращаться к системе сверх взятого
		 *
		 * Один этот признак и обращает распределитель в замкнутый: не выдай источник
		 * очередную область - куча не пойдёт искать её у системы, а ответит отказом
		 */
		options.confined = true;
		/**
		 * Отдачу памяти отключаем вовсе
		 *
		 * Отдавать некому: источник наш отвечает на неё отказом. Просьбы отдачи стоили бы
		 * обходов кучи впустую
		 */
		options.purgeMode = alloc::purge_t::MANUAL;
		// Задаём требуемые настройки
		alloc::Allocator::options(options);
	}
	/**
	 * Захватываем выдачу памяти процесса
	 *
	 * Журнал не задаём: образец печатает всё сам, а распределителю в замкнутом режиме
	 * докладывать не о чем
	 */
	if(!alloc::Allocator::capture(alloc::Allocator::options(), nullptr)){
		// Сообщаем об отказе захвата
		::printf("Захватить выдачу памяти не удалось\n");
		// Выводим неуспешный код выхода
		return EXIT_FAILURE;
	}
	// Печатаем расход сразу за захватом
	::consumption("Расход памяти сразу за захватом");
	/**
	 * Занимаем память и смотрим, как убывает неподвижная область
	 */
	std::vector <void *> blocks;
	// Отводим место под перечень блоков заранее
	blocks.reserve(8192);
	/**
	 * Перебираем занимаемые блоки
	 */
	for(size_t i = 0; i < 8192; i++){
		// Занимаем очередной блок
		void * block = ::malloc(128 + (i % 1024));
		// Если блок не выдан
		if(block == nullptr)
			// Занимать больше нечего
			break;
		// Запоминаем занятый блок
		blocks.push_back(block);
	}
	// Печатаем число занятых блоков
	::printf("\nЗанято блоков: %zu\n", blocks.size());
	// Печатаем расход под нагрузкой
	::consumption("Расход памяти под нагрузкой");
	/**
	 * Упираемся в предел области намеренно
	 *
	 * Просим больше, чем в области вообще есть: отказ здесь - ПРАВИЛЬНЫЙ ответ, и
	 * приложение, работающее на своей области, обязано его разбирать. Замкнутому
	 * распределителю пойти за памятью больше некуда
	 */
	{
		// Просим область заведомо больше всей неподвижной
		void * excessive = ::malloc(ARENA * 2u);
		// Печатаем исход заведомо неисполнимого запроса
		::printf("\nЗапрос сверх всей области: %s\n", ((excessive == nullptr) ? "ОТКАЗ - как и должно" : "выдан, чего быть не может"));
		// Если запрос всё же был выдан
		if(excessive != nullptr)
			// Печатаем, лежит ли выданное в неподвижной области
			::printf("  выдано по адресу %p, область %p..%p\n", excessive,
			 static_cast <const void *> (::base()), static_cast <const void *> (::base() + ARENA));
		// Если запрос всё же был выдан
		if(excessive != nullptr)
			// Освобождаем выданное
			::free(excessive);
	}
	/**
	 * Освобождаем занятое
	 */
	for(void * block : blocks)
		// Освобождаем очередной блок
		::free(block);
	// Очищаем перечень блоков
	blocks.clear();
	// Освобождаем место, отведённое под перечень
	blocks.shrink_to_fit();
	/**
	 * Печатаем расход после освобождения
	 *
	 * Взятое у источника при этом НЕ убудет: замкнутый распределитель держит область за
	 * собою и раздаёт её заново. Это и есть его свойство - память берётся однажды
	 */
	::consumption("Расход памяти после освобождения");
	/**
	 * Просим отдать память источнику
	 *
	 * Просьба эта пройдёт весь путь отдачи и не отдаст ничего: источник отвечает отказом,
	 * а учёт считает лишь состоявшееся. Ноль здесь - честный ответ, а не пропуск
	 */
	::printf("\nОтдано источнику по просьбе: %zu байт\n", alloc::Allocator::purge());
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
