using namespace awh;

/**
 * @brief Пространство имён образца
 *
 */
namespace {
	/**
	 * Число блоков, удерживаемых нагрузкой разом
	 *
	 * Нагрузка НАБИРАЕТ блоки, а не гоняет один и тот же: выдача с немедленным возвратом
	 * не набивает ни кэша, ни кучи - она возвращает тот же самый блок, и всякий рычаг,
	 * трогающий объём удерживаемого, на ней не виден вовсе
	 */
	static constexpr size_t HELD = 8192;
	// Число оборотов нагрузки
	static constexpr size_t ROUNDS = 32;
	// Число потоков многопоточной нагрузки
	static constexpr size_t THREADS = 4;
	/**
	 * @brief Исход прогона нагрузки
	 *
	 */
	typedef struct Outcome {
		// Цена одного действия в наносекундах
		double cost;
		// Взято у системы на пике, в байтах
		size_t heap;
		// Число отказов выдачи
		size_t refused;
		/**
		 * @brief Конструктор
		 *
		 */
		Outcome() noexcept : cost(0.0), heap(0), refused(0) {}
	} outcome_t;
	/**
	 * @brief Метод прогона нагрузки одним потоком
	 *
	 * @param seed  зерно разброса размеров
	 * @param count число действий, выполненных потоком
	 * @return      число отказов выдачи
	 *
	 */
	static size_t toil(const size_t seed, size_t & count) noexcept {
		// Число отказов выдачи
		size_t refused = 0;
		// Удерживаемые блоки
		std::vector <void *> blocks;
		// Отводим место под удерживаемые блоки заранее
		blocks.resize(HELD, nullptr);
		// Состояние разброса размеров
		size_t state = (seed | 1u);
		/**
		 * Перебираем обороты нагрузки
		 */
		for(size_t round = 0; round < ROUNDS; round++){
			/**
			 * Перебираем места удерживаемых блоков
			 */
			for(size_t i = 0; i < HELD; i++){
				// Сдвигаем состояние разброса размеров
				state = ((state * 1103515245u) + 12345u);
				/**
				 * Разброс размеров взят широким НАМЕРЕННО
				 *
				 * Однородный размер меряет один разряд, а не работу распределителя: рычаг
				 * границы разрядов на нём не виден вовсе, потому что за границу ничего не
				 * выходит
				 */
				// Определяем размер очередного блока
				const size_t size = (16u + ((state >> 8) % (4u * 1024u)));
				// Если место занято прежним блоком
				if(blocks[i] != nullptr)
					// Освобождаем прежний блок
					::free(blocks[i]);
				// Выдаём очередной блок
				blocks[i] = ::malloc(size);
				// Если блок выдан
				if(blocks[i] != nullptr){
					/**
					 * Трогаем выданное, а не только берём
					 *
					 * Нетронутая память системой не отдаётся вовсе: отказ страницы приходит
					 * при первом обращении, и замер без обращения мерил бы одну лишь
					 * бухгалтерию распределителя
					 */
					// Записываем начало выданного блока
					::memset(blocks[i], static_cast <int> (i & 0xFF), ((size < 64u) ? size : 64u));
				// Если блок не выдан
				} else refused++;
				// Считаем выполненное действие
				count++;
			}
		}
		/**
		 * Освобождаем удерживаемое
		 */
		for(void * block : blocks){
			// Если блок удерживается
			if(block != nullptr)
				// Освобождаем блок
				::free(block);
		}
		// Выводим число отказов выдачи
		return refused;
	}
	/**
	 * @brief Метод прогона нагрузки с замером
	 *
	 * @param threads число потоков нагрузки
	 * @return        исход прогона
	 *
	 */
	static outcome_t measure(const size_t threads) noexcept {
		// Исход прогона
		outcome_t result;
		// Число выполненных действий по потокам
		std::vector <size_t> counts(threads, 0);
		// Число отказов выдачи по потокам
		std::vector <size_t> refusals(threads, 0);
		// Работники нагрузки
		std::vector <std::thread> workers;
		// Отводим место под работников заранее
		workers.reserve(threads);
		/**
		 * Прогреваем кучу ПРЕЖДЕ замера, и прогреваем её каждому прогону
		 *
		 * Приведение к исходному состоянию отдаёт страницы системе, и следующий прогон
		 * платит за них отказом страницы при первом обращении - платит столько, что цена
		 * рычага в этом тонет целиком. Замерено на этом самом образце: без прогрева всякий
		 * прогон, кроме первого, давал ровно 800 нс на действие независимо от настройки,
		 * тогда как первый - 194. Мерился отказ страницы, а не распределитель
		 *
		 * Прогревочный проход выбрасывается: он платит за страницы, а замеряемый работает
		 * уже по прогретой куче - и так у ВСЕХ настроек одинаково
		 */
		{
			// Число действий прогревочного прохода
			std::vector <size_t> spare(threads, 0);
			// Число отказов прогревочного прохода
			std::vector <size_t> lost(threads, 0);
			/**
			 * Заводим работников прогрева
			 */
			for(size_t i = 0; i < threads; i++)
				// Заводим очередного работника прогрева
				workers.emplace_back([i, &spare, &lost]() noexcept -> void {
					// Прогоняем нагрузку одним потоком
					lost[i] = ::toil((i + 1u) * 2654435761u, spare[i]);
				});
			/**
			 * Дожидаемся работников прогрева
			 */
			for(std::thread & worker : workers)
				// Дожидаемся очередного работника прогрева
				worker.join();
			// Очищаем перечень работников под замеряемый проход
			workers.clear();
		}
		// Запоминаем время начала прогона
		const auto begin = std::chrono::steady_clock::now();
		/**
		 * Заводим работников нагрузки
		 */
		for(size_t i = 0; i < threads; i++)
			// Заводим очередного работника
			workers.emplace_back([i, &counts, &refusals]() noexcept -> void {
				// Прогоняем нагрузку одним потоком
				refusals[i] = ::toil((i + 1u) * 2654435761u, counts[i]);
			});
		/**
		 * Дожидаемся работников
		 */
		for(std::thread & worker : workers)
			// Дожидаемся очередного работника
			worker.join();
		// Определяем длительность прогона в наносекундах
		const double spent = static_cast <double> (std::chrono::duration_cast <std::chrono::nanoseconds> (
		 std::chrono::steady_clock::now() - begin).count());
		// Число выполненных действий
		size_t done = 0;
		/**
		 * Складываем выполненное работниками
		 */
		for(size_t i = 0; i < threads; i++){
			// Складываем выполненные действия
			done += counts[i];
			// Складываем отказы выдачи
			result.refused += refusals[i];
		}
		/**
		 * Цена действия считается по ЧИСЛУ ДЕЙСТВИЙ, а не по времени на поток
		 *
		 * Делить время на число потоков нельзя: работники живут не поровну, и деление
		 * приписало бы отставшему чужую скорость
		 */
		// Определяем цену одного действия
		result.cost = ((done > 0) ? (spent / static_cast <double> (done)) : 0.0);
		// Запоминаем взятое у системы
		result.heap = alloc::Allocator::property(alloc::property_t::HEAP);

		// Выводим исход прогона
		return result;
	}
	/**
	 * @brief Метод печати строки свода
	 *
	 * @param title   название настройки
	 * @param outcome исход прогона
	 *
	 */
	static void report(const char * title, const outcome_t & outcome) noexcept {
		/**
		 * Ширина поля отсчитывается по ЗНАКАМ, а не по октетам
		 *
		 * Подстановка `%-34s` считает октеты, а буква кириллицы в UTF-8 занимает их два:
		 * свод разъезжается тем сильнее, чем длиннее название. Считаем знаки сами -
		 * продолжения многооктетной последовательности узнаются по старшим разрядам
		 */
		// Число знаков в названии настройки
		size_t glyphs = 0;
		// Перебираем октеты названия
		for(const char * probe = title; (* probe) != '\0'; probe++){
			// Если октет не является продолжением многооктетной последовательности
			if((static_cast <uint8_t> (* probe) & 0xC0u) != 0x80u)
				// Считаем знак названия
				glyphs++;
		}
		// Печатаем название настройки
		::printf("  %s", title);
		// Добиваем поле пробелами до нужной ширины
		for(size_t i = glyphs; i < 36; i++)
			// Печатаем добивающий пробел
			::printf(" ");
		// Печатаем замеренное
		::printf("%8.2f  %9zu", outcome.cost, (outcome.heap / 1024u));
		/**
		 * Об отказах выдачи говорим ГРОМКО, а не столбцом нулей
		 *
		 * Отказ означает, что замер шёл на неполной нагрузке, и число рядом с ним сравнивать
		 * с прочими нельзя. Молчаливый ноль в столбце такого не скажет
		 */
		// Если выдача отказывала
		if(outcome.refused > 0)
			// Печатаем предупреждение об отказах выдачи
			::printf("   ОТКАЗОВ ВЫДАЧИ: %zu - замер шёл на неполной нагрузке", outcome.refused);
		// Переводим строку
		::printf("\n");
	}
	/**
	 * @brief Метод приведения распределителя к исходному состоянию
	 *
	 * @details Между прогонами память отдаётся системе, иначе рычаг мерился бы поверх
	 *          того, что оставил предыдущий: куча, набранная прошлым прогоном, достаётся
	 *          следующему даром, и тот выглядит бережливее, чем есть
	 *
	 */
	static void settle() noexcept {
		// Берём действующие настройки
		alloc::options_t options = alloc::Allocator::options();
		// Задаём отдачу по просьбе приложения
		options.purgeMode = alloc::purge_t::MANUAL;
		// Снимаем отсрочку отдачи
		options.purgeDelay = 0;
		// Снимаем порог куска
		options.purgeBlock = 0;
		// Снимаем порог свободного
		options.purgeFree = 0;
		// Снимаем потолок кучи
		options.heapLimit = 0;
		// Возвращаем пределы на усмотрение модуля
		options.cacheLimit = 0;
		// Возвращаем границу разрядов на усмотрение модуля
		options.classLimit = 0;
		// Применяем настройки
		alloc::Allocator::options(options);
		// Отдаём свободное системе
		static_cast <void> (alloc::Allocator::purge());
	}
};

/**
 * @brief Главная функция приложения
 *
 * @return код выхода из приложения
 *
 */
int32_t main() noexcept {
	/**
	 * Захватываем выдачу памяти процесса
	 */
	if(!alloc::Allocator::capture(alloc::Allocator::options(), nullptr)){
		// Сообщаем об отказе захвата
		::printf("Захватить выдачу памяти не удалось\n");
		// Выводим неуспешный код выхода
		return EXIT_FAILURE;
	}
	// Печатаем заголовок свода
	::printf("Нагрузка: %zu блоков разом, %zu оборотов, размеры от 16 байт до 4 КБ\n\n", HELD, ROUNDS);
	// Печатаем шапку свода
	::printf("  настройка                            %8s  %9s\n", "нс/оп", "куча,КБ");
	// Печатаем черту свода
	::printf("  %s\n", "-------------------------------------------------------");
	/**
	 * Прогоняем нагрузку на умолчаниях
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Печатаем исход прогона на умолчаниях
		::report("по умолчанию", ::measure(1));
	}
	/**
	 * Опускаем предел кэшей потоков
	 *
	 * Рычаг памяти: кэш держит освобождённое у потока, не отдавая его вниз. Опущенный
	 * предел возвращает освобождённое в общие списки раньше - памяти удерживается меньше,
	 * но за всякий возврат платится обращением к слою ниже
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Берём действующие настройки
		alloc::options_t options = alloc::Allocator::options();
		// Опускаем предел кэшей потоков
		options.cacheLimit = (256u * 1024u);
		// Применяем настройки
		alloc::Allocator::options(options);
		// Печатаем исход прогона с опущенным пределом кэшей
		::report("предел кэшей 256 КБ", ::measure(1));
	}
	/**
	 * Поднимаем границу разрядов
	 *
	 * Рычаг скорости на крупных запросах: всё, что за границей, обслуживается страничной
	 * кучей под общим замком, а всё, что в пределах - разрядами из кэша своего потока.
	 * Платится памятью: разрядов становится больше, и округление размера вверх удерживает
	 * больше неиспользуемого
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Берём действующие настройки
		alloc::options_t options = alloc::Allocator::options();
		// Поднимаем границу разрядов до ёмкости таблиц поиска
		options.classLimit = (128u * 1024u);
		// Применяем настройки
		alloc::Allocator::options(options);
		// Печатаем исход прогона с поднятой границей разрядов
		::report("граница разрядов 128 КБ", ::measure(1));
	}
	/**
	 * Прогоняем нагрузку несколькими потоками
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Печатаем исход многопоточного прогона на умолчаниях
		::report("четыре потока, по умолчанию", ::measure(THREADS));
	}
	/**
	 * Прогоняем нагрузку несколькими потоками с опущенным пределом кэшей
	 *
	 * Здесь рычаг кэшей и виден по-настоящему: общий запас делится между потоками, и
	 * тесный предел обращает всякий возврат в поход к общим спискам под замком
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Берём действующие настройки
		alloc::options_t options = alloc::Allocator::options();
		// Опускаем предел кэшей потоков
		options.cacheLimit = (256u * 1024u);
		// Применяем настройки
		alloc::Allocator::options(options);
		// Печатаем исход многопоточного прогона с опущенным пределом кэшей
		::report("четыре потока, предел кэшей 256 КБ", ::measure(THREADS));
	}
	// Приводим распределитель к исходному состоянию
	::settle();
	/**
	 * Показываем рычаг отдачи по освобождению ОТДЕЛЬНОЙ нагрузкой
	 *
	 * На нагрузке выше он не виден вовсе, и это не пропуск, а свойство самой нагрузки:
	 * блоки её мельче границы разрядов, освобождённое ложится в общие списки, а область
	 * страничной кучи остаётся нарезанной - отдавать системе нечего. Виден рычаг там, где
	 * освобождение отпускает область ЦЕЛИКОМ, то есть на блоках крупнее разрядов
	 */
	{
		// Размер блока, заведомо крупнее границы разрядов
		static constexpr size_t BULKY = (2u * 1024u * 1024u);
		// Число оборотов нагрузки крупными блоками
		static constexpr size_t BULK = 64;
		// Приёмник выданного, закрывающий собирателю выброс пары выдачи и возврата
		static void * volatile sink = nullptr;
		// Печатаем заголовок раздела
		::printf("\n  Отдача по освобождению, нагрузка блоками по %zu КБ:\n", (BULKY / 1024u));
		/**
		 * Перебираем способы отдачи
		 */
		for(size_t pass = 0; pass < 2; pass++){
			// Приводим распределитель к исходному состоянию
			::settle();
			// Берём действующие настройки
			alloc::options_t options = alloc::Allocator::options();
			// Задаём способ отдачи: сперва по просьбе, затем на каждом освобождении
			options.purgeMode = ((pass == 0) ? alloc::purge_t::MANUAL : alloc::purge_t::ONFREE);
			/**
			 * Придержку крупных областей снимаем ВОВСЕ
			 *
			 * Иначе освобождённая область остаётся придержанной слоем крупных выдач и до
			 * системы не доходит: отдача честно показывает НОЛЬ при любом способе, а
			 * рычаг выглядит неработающим. Придержка тут не мешает - она другой рычаг, и
			 * меряется отдельно
			 */
			// Снимаем потолок придержанных крупных областей
			options.hugeCache = 0;
			// Применяем настройки
			alloc::Allocator::options(options);
			// Запоминаем отданное системе до нагрузки
			const size_t before = alloc::Allocator::property(alloc::property_t::UNMAPPED);
			// Запоминаем время начала нагрузки
			const auto begin = std::chrono::steady_clock::now();
			/**
			 * Перебираем обороты нагрузки
			 */
			for(size_t i = 0; i < BULK; i++){
				/**
				 * Выданное уводится через ИЗМЕНЧИВЫЙ приёмник
				 *
				 * Пару «выдал и тут же освободил» собиратель вправе выбросить целиком, и
				 * он это делает: первый прогон этого самого раздела показал ОДНУ
				 * наносекунду на оборот с блоком в два мегабайта и ноль отданного - то
				 * есть замерялся пустой цикл, а не распределитель
				 */
				// Выдаём крупный блок
				sink = ::malloc(BULKY);
				// Если блок выдан
				if(sink != nullptr){
					// Трогаем выданное: нетронутая память системой не отдаётся
					::memset(sink, 0x5A, 4096);
					// Освобождаем блок
					::free(sink);
				}
			}
			// Определяем длительность нагрузки в наносекундах
			const double spent = static_cast <double> (std::chrono::duration_cast <std::chrono::nanoseconds> (
			 std::chrono::steady_clock::now() - begin).count());
			// Определяем отданное системе за нагрузку
			const size_t after = alloc::Allocator::property(alloc::property_t::UNMAPPED);
			/**
			 * Действие рычага видно по СВОБОДНОМУ В КУЧЕ, а не по счётчику отданного
			 *
			 * Счётчик отданного показывает ноль у обоих способов, и это верно: область
			 * была возвращена системе ещё приведением к исходному состоянию, а дважды её
			 * не отдают - страница, уже отданная, помечена, и обход её пропускает. Работа
			 * же рычага видна прямо: по просьбе освобождённая область остаётся лежать в
			 * куче свободной, а на каждом освобождении куча остаётся пустой
			 */
			// Убираем неиспользуемое: счётчик отданного здесь ничего не показывает
			(void) before; (void) after;
			// Печатаем исход прогона
			::printf("    %-22s %9.0f нс на оборот, свободно в куче %zu КБ\n",
			 ((pass == 0) ? "по просьбе (MANUAL)" : "на каждом (ONFREE)"),
			 (spent / static_cast <double> (BULK)),
			 (alloc::Allocator::property(alloc::property_t::PAGEFREE) / 1024u));
		}
	}
	/**
	 * Показываем рычаг потолка кучи ОТДЕЛЬНОЙ нагрузкой
	 *
	 * На нагрузке выше он не виден: куча набирается однажды и дальше не растёт, а потолок
	 * запрещает именно РОСТ сверх заданного. Виден он там, где приложение просит больше,
	 * чем себе позволило, - и получает ОТКАЗ вместо роста
	 */
	{
		// Приводим распределитель к исходному состоянию
		::settle();
		// Размер блока прощупывания потолка
		static constexpr size_t PROBE = (1u * 1024u * 1024u);
		// Запас, какой потолок оставляет сверх уже взятого
		static constexpr size_t ROOM = (8u * 1024u * 1024u);
		// Запоминаем взятое у системы до потолка
		const size_t taken = alloc::Allocator::property(alloc::property_t::HEAP);
		// Берём действующие настройки
		alloc::options_t options = alloc::Allocator::options();
		/**
		 * Потолок задаётся ОТ УЖЕ ВЗЯТОГО, а не числом из головы
		 *
		 * Потолок ниже уже взятого не отнимает ничего - он запрещает лишь брать дальше, -
		 * и образец с числом из головы показывал бы ноль отказов на машине, где куча
		 * успела набрать больше. Замерено: с потолком в 16 МБ при куче в 24 отказов не
		 * было ни одного, и рычаг выглядел неработающим
		 */
		// Задаём потолок кучи с запасом сверх уже взятого
		options.heapLimit = (taken + ROOM);
		// Применяем настройки
		alloc::Allocator::options(options);
		// Удерживаемые блоки прощупывания
		std::vector <void *> probes;
		// Число отказов выдачи
		size_t refused = 0;
		/**
		 * Просим память, пока не упрёмся в потолок
		 */
		for(size_t i = 0; i < 64; i++){
			// Выдаём очередной блок прощупывания
			void * block = ::malloc(PROBE);
			// Если блок не выдан
			if(block == nullptr){
				// Считаем отказ выдачи
				refused++;
				// Прощупывать больше нечего
				break;
			}
			// Трогаем выданное
			::memset(block, 0x33, 4096);
			// Запоминаем блок прощупывания
			probes.push_back(block);
		}
		// Печатаем заголовок раздела
		::printf("\n  Потолок кучи, запас %zu МБ сверх взятого (%zu КБ):\n", (ROOM / (1024u * 1024u)), (taken / 1024u));
		// Печатаем исход прощупывания
		::printf("    выдано %zu блоков по %zu КБ, отказов %zu, куча %zu КБ\n",
		 probes.size(), (PROBE / 1024u), refused,
		 (alloc::Allocator::property(alloc::property_t::HEAP) / 1024u));
		/**
		 * Освобождаем блоки прощупывания
		 */
		for(void * block : probes)
			// Освобождаем очередной блок
			::free(block);
	}
	// Приводим распределитель к исходному состоянию
	::settle();
	/**
	 * Печатаем предупреждение о переносимости чисел
	 *
	 * Числа эти - НЕ показатели модуля, а показ действия рычагов на одной машине под
	 * одной нагрузкой. Всякая другая нагрузка расставит их иначе, и выбирать настройки
	 * следует замером СВОЕЙ работы, а не переписыванием чужой таблицы
	 */
	::printf("\n  Числа сняты на одной машине под одной нагрузкой и переносу НЕ подлежат.\n");
	::printf("  Настройки выбираются замером своей работы, а не переписыванием этой таблицы.\n");
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
