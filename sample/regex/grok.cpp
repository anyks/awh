/**
 * @brief Пример извлечения полей встроенными шаблонами
 *
 * @param grok объект разбора текста по шаблонам Grok
 *
 */
static void builtin(const grok_t & grok) noexcept {
	// Выводим заголовок примера
	cout << "== Встроенные шаблоны" << endl;
	// Запись журнала веб-сервера, подлежащая разбору
	const string text = "127.0.0.1 - frank [10/Oct/2000:13:55:36 -0700] \"GET /apache_pb.gif HTTP/1.0\" 200 2326";
	/**
	 * Выполняем сборку шаблона Grok
	 *
	 * @details Ссылка вида «%{NAME}» разворачивается текстом шаблона реестра,
	 *          а вид «%{NAME:поле}» вдобавок даёт захвату название
	 *
	 */
	const auto exp = grok.build("%{COMMONAPACHELOG}");
	/**
	 * Если сборка шаблона Grok не выполнена
	 */
	if(!exp){
		// Выводим код ошибки сборки шаблона
		cout << "шаблон не собран, код " << static_cast <uint32_t> (grok.error()) << endl;
		// Выходим из примера
		return;
	}
	// Набор извлечённых значений полей
	unordered_map <string, string> values;
	/**
	 * Если извлечение полей выполнено
	 */
	if(grok.exec(text, exp, values)){
		/**
		 * Выполняем перебор набора полей шаблона
		 *
		 * @details Перебор ведётся набором полей, а не набором извлечённых
		 *          значений: он хранит порядок объявления полей, тогда как
		 *          отображение значений порядка не хранит вовсе
		 *
		 */
		for(const auto & field : grok.fields(exp))
			// Выводим название поля и извлечённое по нему значение
			cout << field.name << ": " << values[field.name] << endl;
	}
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример объявления шаблонов своих
 *
 * @param grok объект разбора текста по шаблонам Grok
 *
 */
static void custom(grok_t & grok) noexcept {
	// Выводим заголовок примера
	cout << "== Свои шаблоны" << endl;
	/**
	 * Выполняем наполнение реестра набором шаблонов из текста
	 *
	 * @details Набор записывается построчно видом «НАЗВАНИЕ выражение», и
	 *          шаблон вправе ссылаться на шаблоны, объявленные и выше, и ниже
	 *
	 */
	const size_t accepted = grok.read(
		"UNIT (?:байт|КБ|МБ|ГБ)\n"
		"VOLUME %{NUMBER:размер:float} ?%{UNIT:единица}\n"
	);
	// Выводим количество шаблонов, принятых реестром
	cout << "принято шаблонов: " << accepted << endl;
	// Выводим результат проверки наличия шаблона в реестре
	cout << "шаблон VOLUME известен: " << (grok.has("VOLUME") ? "да" : "нет") << endl;
	// Выводим текст шаблона реестра
	cout << "текст VOLUME: " << grok.pattern("VOLUME") << endl;
	// Выполняем сборку шаблона Grok со ссылкой на объявленный шаблон
	const auto exp = grok.build("передано %{VOLUME} за %{NUMBER:секунды:float} с");
	/**
	 * Если сборка шаблона Grok не выполнена
	 */
	if(!exp){
		// Выводим код ошибки сборки шаблона
		cout << "шаблон не собран, код " << static_cast <uint32_t> (grok.error()) << endl;
		// Выходим из примера
		return;
	}
	// Набор извлечённых значений полей
	vector <grok::value_t> values;
	/**
	 * Если извлечение полей выполнено
	 *
	 * @details Извлечение набором значений хранит вид поля, объявленный третьей
	 *          частью ссылки: «%{NUMBER:размер:float}». Приведением значения
	 *          модуль не занимается - захват выдаётся текстом всегда, а вид
	 *          нужен потребителю для выбора представления
	 *
	 */
	if(grok.exec("передано 12.5 МБ за 3.2 с", exp, values)){
		/**
		 * Выполняем перебор набора извлечённых значений
		 */
		for(const auto & value : values){
			// Выводим название поля, вид его и извлечённое значение
			cout << value.name << " (" << (value.kind == grok::kind_t::FLOATING ? "дробное" :
			 (value.kind == grok::kind_t::INTEGER ? "целое" : "текст")) << "): " << value.value << endl;
		}
	}
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример вывода разобранного текста кодеком JSON
 *
 * @param grok объект разбора текста по шаблонам Grok
 *
 */
static void encoding(const grok_t & grok) noexcept {
	// Выводим заголовок примера
	cout << "== Вывод кодеком JSON" << endl;
	// Выполняем сборку шаблона Grok
	const auto exp = grok.build("%{IP:client} %{WORD:method} %{URIPATHPARAM:request} %{INT:code:int}");
	/**
	 * Если сборка шаблона Grok не выполнена
	 */
	if(!exp)
		// Выходим из примера
		return;
	// Разобранный текст значением кодека JSON
	awh::grok::json_t result;
	/**
	 * Если разбор текста выполнен
	 *
	 * @details Вид поля определяет представление значения: поле вида «int»
	 *          выводится числом, а не строкой. Надстройка отдаёт значение
	 *          кодека, а не текст: из значения доступен и точный вид данных,
	 *          и вывод текстом любого облика.
	 *
	 */
	if(grok.json("10.0.0.7 GET /index.html?a=1 200", exp, result))
		// Выводим разобранный текст в виде JSON
		cout << result.dump(awh::codec::json::format_t::PRETTY) << endl;
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример записи собранных шаблонов и восстановления их из записи
 *
 * @param grok объект разбора текста по шаблонам Grok
 *
 */
static void storing(const grok_t & grok) noexcept {
	// Выводим заголовок примера
	cout << "== Запись собранных шаблонов" << endl;
	// Запись собранных шаблонов
	string record;
	/**
	 * Если запись собранных шаблонов выполнена
	 *
	 * @details Запись несёт и собранные выражения, и описания полей, отчего
	 *          восстановление из неё избавляет от разбора текста шаблонов
	 *          и от разворачивания ссылок
	 *
	 */
	if(grok.save({"%{IP:client} %{WORD:method}", "%{TIMESTAMP_ISO8601:время}"}, record)){
		// Выводим размер полученной записи
		cout << "размер записи " << record.size() << " байт" << endl;
		// Набор восстановленных шаблонов
		vector <grok_t::exp_t> restored;
		/**
		 * Если восстановление собранных шаблонов выполнено
		 */
		if(grok.load(record, restored)){
			// Выводим количество восстановленных шаблонов
			cout << "восстановлено шаблонов " << restored.size() << endl;
			// Набор извлечённых значений полей
			unordered_map <string, string> values;
			/**
			 * Если извлечение полей восстановленным шаблоном выполнено
			 */
			if(grok.exec("10.0.0.7 POST", restored.front(), values))
				// Выводим значения полей, извлечённые восстановленным шаблоном
				cout << "client: " << values["client"] << ", method: " << values["method"] << endl;
		// Если восстановление собранных шаблонов не выполнено
		} else
			// Выводим код ошибки восстановления записи
			cout << "запись не восстановлена, код " << static_cast <uint32_t> (grok.error()) << endl;
	}
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Главная функция приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]){
	// Создаём объект разбора текста по шаблонам Grok
	grok_t grok(::logger());
	/**
	 * Выполняем включение согласования доступа потоков исполнения
	 *
	 * @details Согласование нужно реестру шаблонов и сборке: собранный шаблон
	 *          разделяется потоками без согласования, поскольку после сборки
	 *          не изменяется
	 *
	 */
	grok.threadSafety(true);
	// Выводим количество шаблонов реестра
	cout << "шаблонов в реестре: " << grok.patterns().size() << endl << endl;
	// Выполняем пример извлечения полей встроенными шаблонами
	builtin(grok);
	// Выполняем пример объявления шаблонов своих
	custom(grok);
	// Выполняем пример вывода разобранного текста кодеком JSON
	encoding(grok);
	// Выполняем пример записи собранных шаблонов
	storing(grok);
	/**
	 * Выполняем возврат реестра к набору встроенных шаблонов
	 *
	 * @details Сброс убирает шаблоны, объявленные потребителем, а очистка
	 *          методом «clear» опорожняет реестр целиком
	 *
	 */
	grok.reset();
	// Выводим количество шаблонов реестра по возвращении его к набору встроенных
	cout << "шаблонов после сброса: " << grok.patterns().size() << endl;
	// Выводим результат работы приложения
	return EXIT_SUCCESS;
}
