/**
 * @brief Пример проверки соответствия текста выражению
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void matching(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Проверка соответствия" << endl;
	// Выполняем сборку регулярного выражения
	const auto exp = regexp.build("^\\d{1,3}(\\.\\d{1,3}){3}$");
	/**
	 * Если сборка регулярного выражения не выполнена
	 */
	if(!exp){
		// Выводим сообщение об ошибке сборки
		cout << "Выражение не собрано: " << regexp.message() << endl;
		// Выходим из примера
		return;
	}
	/**
	 * Выполняем перебор проверяемых текстов
	 */
	for(const auto & text : {"192.168.0.1", "1200.1.1.1", "не адрес"})
		// Выводим результат проверки соответствия текста выражению
		cout << text << " -> " << (regexp.test(text, exp) ? "соответствует" : "не соответствует") << endl;
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример извлечения границ совпадения и захваченных групп
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void capturing(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Границы и захваченные группы" << endl;
	// Текст, по какому ведётся сопоставление
	const string text = "заказ 4815 от 16.08.2026 на сумму 2342 рубля";
	// Выполняем сборку регулярного выражения
	const auto exp = regexp.build("(\\d{2})\\.(\\d{2})\\.(\\d{4})");
	/**
	 * Если сборка регулярного выражения не выполнена
	 */
	if(!exp)
		// Выходим из примера
		return;
	// Набор границ совпадения и захваченных групп
	vector <pair <size_t, size_t>> bounds;
	/**
	 * Если совпадение обнаружено
	 *
	 * @details Первая пара границ - совпадение целиком, последующие -
	 *          захваченные группы в порядке открывающих скобок
	 */
	if(regexp.match(text, exp, bounds)){
		/**
		 * Выполняем перебор набора границ совпадения
		 */
		for(size_t i = 0; i < bounds.size(); i++){
			// Выводим номер границы и извлечённый по ней отрезок текста
			cout << (i == 0 ? "совпадение" : "группа " + to_string(i)) << ": "
			     << text.substr(bounds.at(i).first, bounds.at(i).second - bounds.at(i).first) << endl;
		}
	}
	// Выполняем извлечение захваченных групп текстом
	const auto captures = regexp.exec(text, exp);
	// Выводим количество извлечённых значений
	cout << "извлечено значений: " << captures.size() << endl;
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример обращения к захваченным группам по названию
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void naming(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Именованные группы" << endl;
	// Текст, по какому ведётся сопоставление
	const string text = "пишите на forman@anyks.com сегодня";
	// Выполняем сборку регулярного выражения
	const auto exp = regexp.build("(?<user>[a-z]+)@(?<host>[a-z.]+)");
	/**
	 * Если сборка регулярного выражения не выполнена
	 */
	if(!exp)
		// Выходим из примера
		return;
	// Набор извлечённых значений именованных групп
	unordered_map <string, string> values;
	/**
	 * Если извлечение именованных групп выполнено
	 */
	if(regexp.exec(text, exp, values)){
		// Выводим извлечённое имя пользователя
		cout << "user: " << values["user"] << endl;
		// Выводим извлечённое имя узла
		cout << "host: " << values["host"] << endl;
	}
	// Набор границ совпадения и захваченных групп
	vector <pair <size_t, size_t>> bounds;
	/**
	 * Если совпадение обнаружено
	 *
	 * @details Извлечение отрезком текста избавляет от копирования: выдаётся
	 *          вид на исходный текст, а не его копия
	 */
	if(regexp.match(text, exp, bounds))
		// Выводим отрезок текста, захваченный группой по её названию
		cout << "capture(host): " << regexp.capture(text, bounds, exp, "host") << endl;
	// Выводим номер группы захвата по её названию
	cout << "номер группы user: " << regexp.group(exp, "user") << endl;
	// Выводим количество захватывающих групп выражения
	cout << "групп захвата: " << regexp.captures(exp) << endl;
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример режимов компиляции выражения
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void modes(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Режимы компиляции" << endl;
	// Выполняем сборку выражения без учёта регистра символов
	const auto careless = regexp.build("привет", {regexp_t::flag_t::CASELESS, regexp_t::flag_t::UTF, regexp_t::flag_t::UCP});
	/**
	 * Если сборка выражения выполнена
	 */
	if(careless)
		// Выводим результат сопоставления текста в ином регистре
		cout << "CASELESS: " << (regexp.test("ПРИВЕТ", careless) ? "совпало" : "не совпало") << endl;
	// Выполняем сборку выражения с привязками к границам строк
	const auto lines = regexp.build("^вторая$", {regexp_t::flag_t::MULTILINE});
	/**
	 * Если сборка выражения выполнена
	 */
	if(lines)
		// Выводим результат сопоставления многострочного текста
		cout << "MULTILINE: " << (regexp.test("первая\nвторая\nтретья", lines) ? "совпало" : "не совпало") << endl;
	/**
	 * Выполняем сборку выражения с порождением машинного кода
	 *
	 * @details Порождение машинного кода ускоряет сопоставление в разы, а на
	 *          выражениях с захватом - на порядок. Поведение выражения от режима
	 *          этого не зависит: сопоставитель порождённый и сопоставитель
	 *          программный выдают одно и то же.
	 *
	 */
	const auto machine = regexp.build("([a-z]+)=([0-9]+)", {regexp_t::flag_t::JIT});
	/**
	 * Если сборка выражения выполнена
	 */
	if(machine)
		// Выводим результат сопоставления выражением с порождённым кодом
		cout << "JIT: извлечено значений " << regexp.exec("count=42", machine).size() << endl;
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример разбора ошибки сборки выражения
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void failure(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Ошибка сборки" << endl;
	// Выполняем сборку заведомо неверного регулярного выражения
	const auto exp = regexp.build("(?<name>[a-z]+");
	/**
	 * Если сборка регулярного выражения не выполнена
	 */
	if(!exp){
		// Выводим описание ошибки сборки выражения
		cout << "сообщение: " << regexp.message() << endl;
		// Выводим положение ошибки в тексте выражения
		cout << "положение: " << regexp.offset() << endl;
		// Выводим код ошибки сборки выражения
		cout << "код: " << static_cast <uint32_t> (regexp.error()) << endl;
	}
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Пример записи собранных выражений и восстановления их из записи
 *
 * @param regexp объект работы с регулярными выражениями
 *
 */
static void storing(const regexp_t & regexp) noexcept {
	// Выводим заголовок примера
	cout << "== Хранилище собранных выражений" << endl;
	// Создаём объект хранилища собранных выражений
	const regex::storage_t storage;
	// Набор собираемых выражений
	vector <regex::storage_t::exp_t> expressions;
	/**
	 * Выполняем перебор набора текстов выражений
	 */
	for(const auto & pattern : {"(?<user>[a-z]+)@(?<host>[a-z.]+)", "\\b\\d{4}-\\d{2}-\\d{2}\\b", "^[A-Z][a-z]+$"}){
		// Выполняем сборку очередного регулярного выражения
		const auto exp = regexp.build(pattern);
		/**
		 * Если сборка регулярного выражения выполнена
		 */
		if(exp)
			// Выполняем добавление собранного выражения в набор
			expressions.push_back(exp);
	}
	// Запись хранилища собранных выражений
	string record;
	/**
	 * Если запись собранных выражений выполнена
	 *
	 * @details Запись избавляет от повторной сборки выражений при следующем
	 *          запуске: восстановление из неё обходится в разы дешевле разбора
	 *          текста выражения
	 *
	 */
	if(storage.save(expressions, record)){
		// Выводим размер полученной записи
		cout << "записано выражений " << expressions.size() << ", размер записи " << record.size() << " байт" << endl;
		// Набор восстановленных выражений
		vector <regex::storage_t::exp_t> restored;
		/**
		 * Если восстановление собранных выражений выполнено
		 */
		if(storage.load(record, restored)){
			// Выводим количество восстановленных выражений
			cout << "восстановлено выражений " << restored.size() << endl;
			// Выводим результат сопоставления восстановленным выражением
			cout << "сопоставление восстановленным: "
			     << (regexp.test("forman@anyks.com", restored.front()) ? "совпало" : "не совпало") << endl;
		// Если восстановление собранных выражений не выполнено
		} else
			// Выводим код ошибки восстановления записи
			cout << "запись не восстановлена, код " << static_cast <uint32_t> (storage.error()) << endl;
	}
	// Выводим разделитель примеров
	cout << endl;
}
/**
 * @brief Главная функция приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char * argv[]){
	// Создаём объект работы с регулярными выражениями
	regexp_t regexp;
	/**
	 * Выполняем включение согласования доступа потоков исполнения
	 *
	 * @details Согласование нужно лишь сборке выражений: собранное выражение
	 *          разделяется потоками без согласования, поскольку после сборки
	 *          не изменяется
	 *
	 */
	regexp.threadSafety(true);
	// Выполняем пример проверки соответствия текста выражению
	matching(regexp);
	// Выполняем пример извлечения границ совпадения и захваченных групп
	capturing(regexp);
	// Выполняем пример обращения к захваченным группам по названию
	naming(regexp);
	// Выполняем пример режимов компиляции выражения
	modes(regexp);
	// Выполняем пример разбора ошибки сборки выражения
	failure(regexp);
	// Выполняем пример записи собранных выражений
	storing(regexp);
	// Выполняем очистку памяти собранных выражений
	regexp.clear();
	// Выводим результат работы приложения
	return EXIT_SUCCESS;
}
