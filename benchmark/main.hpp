#ifndef __AWH_BENCHMARK__
#define __AWH_BENCHMARK__

/**
 * Стандартные заголовочные файлы
 */
#include <string>
#include <vector>
#include <cstddef>
#include <cstdint>
#include <functional>

/**
 * Подключаем заголовочный файл двоичного контракта счётчика системных вызовов
 */
#include <syscount.h>

/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 * @details Бенчмарк - это сценарий, измеряющий одну характеристику и
	 *          сравнивающий её с порогом. Отклонение от порога завершает запуск
	 *          с ненулевым кодом, поэтому набор бенчмарков пригоден как шаг
	 *          сборки: регрессия производительности останавливает конвейер.
	 *          Сценарии регистрируются статически, поэтому добавление нового
	 *          бенчмарка сводится к добавлению файла с его реализацией
	 *
	 * @warning Показатели снимать **единственно сборкой Release**. Пороги задавались
	 *          по ней, и отладочная сборка медленнее примерно **вдесятеро** - замер
	 *          на ней не «чуть ниже», а на порядок ниже, и уверенно изображает
	 *          регрессию там, где её нет. Сбивает с толку и то, что под порог уходят
	 *          при этом не все сценарии разом, а лишь те, у кого запас над порогом
	 *          меньше самого замедления: выглядит это как проседание одного
	 *          отдельного пути, хотя замедление равномерное. Проверено сличением
	 *          двух сборок на одной машине: чтение атрибутов дало 19 МБ/с при пороге
	 *          в 21 отладочной сборкой и 211-225 МБ/с сборкой Release
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Направление сравнения измеренного значения с порогом
		 *
		 */
		enum class bound_t : uint8_t {
			MINIMUM = 0x00, // Значение не должно опускаться ниже порога
			MAXIMUM = 0x01  // Значение не должно превышать порог
		};

		/**
		 * @brief Структура результата измерения
		 *
		 */
		typedef struct Result {
			/**
			 * Признак того, что измерение не выполнялось. Часть показателей
			 * снимается внешней оснасткой, которой в обычном прогоне нет:
			 * такое измерение не является ни успешным, ни провалившимся, и
			 * приравнивать его к любому из двух означало бы либо ложную
			 * тревогу, либо ложное спокойствие
			 */
			bool skipped;
			/**
			 * Признак того, что измерение НЕДЕЙСТВИТЕЛЬНО: сценарий не выполнил
			 * ни одной операции, и характеристика посчитана не по чему
			 *
			 * @note Отдельный признак заведён оттого, что молчание сценария иначе
			 *       отчитывается УСПЕХОМ. Показатель вида "на одну операцию"
			 *       считается делением на количество операций, при нуле операций
			 *       выдаёт ноль, а ноль укладывается в любой порог с границей
			 *       MAXIMUM. Движок, не сделавший ничего, выходил зелёным
			 */
			bool invalid;
			// Измеренное значение характеристики
			double value;
			// Причина, по которой измерение не выполнялось
			std::string reason;
			// Дополнительные сведения о прогоне для вывода
			std::string details;
			/**
			 * @brief Конструктор
			 *
			 */
			explicit Result() noexcept;
		} result_t;

		/**
		 * @brief Структура описания сценария бенчмарка
		 *
		 */
		typedef struct Scenario {
			// Название сценария
			std::string name;
			// Единица измерения характеристики
			std::string units;
			// Пороговое значение характеристики
			double threshold;
			// Направление сравнения с порогом
			bound_t bound;
			// Функция выполнения сценария
			std::function <result_t ()> run;
			/**
			 * @brief Конструктор
			 *
			 */
			explicit Scenario() noexcept;
		} scenario_t;

		/**
		 * @brief Функция регистрации сценария бенчмарка
		 *
		 * @note Вызывается из статического инициализатора файла сценария:
		 *       собранные сценарии выполняются точкой входа в порядке регистрации
		 *
		 * @param name      название сценария
		 * @param units     единица измерения характеристики
		 * @param threshold пороговое значение характеристики
		 * @param bound     направление сравнения с порогом
		 * @param run       функция выполнения сценария
		 * @return          признак успешной регистрации (для статической инициализации)
		 *
		 */
		bool add(const std::string & name, const std::string & units, const double threshold, const bound_t bound, std::function <result_t ()> run) noexcept;

		/**
		 * @brief Функция управления учётом выделений памяти
		 *
		 * @note Учёт ведётся перегруженными операторами выделения памяти точки
		 *       входа набора бенчмарков и охватывает весь процесс целиком,
		 *       поэтому включать его следует непосредственно вокруг замера
		 *
		 * @param mode режим учёта выделений памяти
		 *
		 */
		void counting(const bool mode) noexcept;

		/**
		 * @brief Функция получения статистики выделений памяти
		 *
		 * @param count количество выполненных выделений
		 * @param bytes суммарный объём выделенной памяти в октетах
		 *
		 */
		void allocations(size_t & count, size_t & bytes) noexcept;

		/**
		 * @brief Функция получения списка зарегистрированных сценариев
		 *
		 * @return список зарегистрированных сценариев
		 *
		 */
		const std::vector <scenario_t> & scenarios() noexcept;

		/**
		 * @brief Пространство имён учёта системных вызовов
		 *
		 * @details Количество системных вызовов на одну операцию - показатель,
		 *          пригодный в порог куда больше, чем время: он детерминирован.
		 *          Время на незанятой машине расходится между прогонами на
		 *          единицы процентов, на рабочей - на десятки, и порог по времени
		 *          приходится задавать с многократным запасом, из-за чего он
		 *          пропускает всё, кроме катастрофы. Счётчик вызовов на той же
		 *          нагрузке совпадает от прогона к прогону вплоть до единиц,
		 *          поэтому лишнее обращение к ядру он замечает в тот же день,
		 *          когда оно появилось.
		 *
		 *          Учёт ведёт подставная библиотека, внедряемая загрузчиком, -
		 *          её сборка и внедрение описаны в
		 *          `tools/benchmark/syscount/README.md`. В обычном прогоне
		 *          библиотеки нет, и показатели, снятые с её помощью,
		 *          выводятся как пропущенные
		 *
		 */
		namespace syscall {
			/**
			 * @brief Функция проверки доступности учёта системных вызовов
			 *
			 * @return признак внедрения подставной библиотеки счётчика
			 *
			 */
			bool available() noexcept;

			/**
			 * @brief Функция управления учётом системных вызовов
			 *
			 * @note Счётчик видит вызовы всего процесса целиком, поэтому включать
			 *       его следует непосредственно вокруг замера - так же, как учёт
			 *       выделений памяти
			 *
			 * @param mode режим учёта системных вызовов
			 *
			 */
			void counting(const bool mode) noexcept;

			/**
			 * @brief Функция получения суммарного количества системных вызовов
			 *
			 * @note Обращения ко времени в сумму не входят: на части платформ они
			 *       обслуживаются без перехода в ядро
			 *
			 * @return суммарное количество выполненных системных вызовов
			 *
			 */
			size_t total() noexcept;

			/**
			 * @brief Функция получения количества вызовов одной разновидности
			 *
			 * @param kind разновидность вызовов
			 * @return     количество выполненных вызовов
			 *
			 */
			size_t calls(const awh_syscount_kind_t kind) noexcept;

			/**
			 * @brief Функция получения времени, проведённого в вызовах одной разновидности
			 *
			 * @param kind разновидность вызовов
			 * @return     затраченное время в секундах
			 *
			 */
			double seconds(const awh_syscount_kind_t kind) noexcept;

			/**
			 * @brief Функция получения количества изменений подписки, переданных ядру
			 *
			 * @return суммарное количество переданных изменений подписки
			 *
			 */
			size_t changes() noexcept;

			/**
			 * @brief Функция получения наибольшего пакета изменений подписки
			 *
			 * @details Размер пакета показывает, во что обходится отложенная
			 *          регистрация событий: пакет в сто тысяч записей означает и
			 *          линейный поиск по нему на каждой постановке, и мебибайты
			 *          памяти под него
			 *
			 * @return наибольшее количество изменений подписки за один вызов
			 *
			 */
			size_t peak() noexcept;

			/**
			 * @brief Функция формирования сводки по системным вызовам
			 *
			 * @param operations количество выполненных операций
			 * @return           сводка для вывода либо пустая строка при недоступности учёта
			 *
			 */
			std::string summary(const size_t operations) noexcept;

			/**
			 * @brief Функция получения причины недоступности учёта системных вызовов
			 *
			 * @return описание причины для вывода в качестве пропущенного измерения
			 *
			 */
			std::string reason() noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK__
