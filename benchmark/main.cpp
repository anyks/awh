/**
 * @brief Функция регистрации сценария бенчмарка
 *
 * @param name      название сценария
 * @param units     единица измерения характеристики
 * @param threshold пороговое значение характеристики
 * @param bound     направление сравнения с порогом
 * @param run       функция выполнения сценария
 * @return          признак успешной регистрации (для статической инициализации)
 *
 */
bool awh::benchmark::add(const std::string & name, const std::string & units, const double threshold, const bound_t bound, std::function <result_t ()> run) noexcept {
	// Формируем описание сценария бенчмарка
	scenario_t scenario;
	// Устанавливаем название сценария
	scenario.name = name;
	// Устанавливаем единицу измерения характеристики
	scenario.units = units;
	// Устанавливаем пороговое значение характеристики
	scenario.threshold = threshold;
	// Устанавливаем направление сравнения с порогом
	scenario.bound = bound;
	// Устанавливаем функцию выполнения сценария
	scenario.run = run;
	// Добавляем сценарий в список зарегистрированных
	::registry().push_back(scenario);
	// Выводим признак успешной регистрации
	return true;
}
/**
 * @brief Функция получения списка зарегистрированных сценариев
 *
 * @return список зарегистрированных сценариев
 *
 */
const std::vector <awh::benchmark::scenario_t> & awh::benchmark::scenarios() noexcept {
	// Выводим список зарегистрированных сценариев
	return ::registry();
}
/**
 * @brief Главная функция приложения бенчмарков
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char ** argv){
	// Фильтр названий выполняемых сценариев
	const char * filter = nullptr;
	// Флаг игнорирования порогов
	bool relaxed = false;
	/**
	 * Количество повторов измерения
	 *
	 * @details Разброс между прогонами на одной машине доходит до десятой доли,
	 * и одиночное значение доводом служить не может: соседние прогоны одного и
	 * того же кода перекрываются. При нескольких повторах выводится середина
	 * ряда, а рядом - границы разброса, чтобы видно было, чего стоит вывод
	 */
	size_t repeat = 1;
	/**
	 * Перебираем параметры запуска приложения
	 */
	for(int32_t i = 1; i < argc; i++){
		// Если задан фильтр названий выполняемых сценариев
		if((::strncmp(argv[i], "--filter=", 9) == 0))
			// Устанавливаем фильтр названий сценариев
			filter = (argv[i] + 9);
		// Если задано количество повторов измерения
		else if((::strncmp(argv[i], "--repeat=", 9) == 0)){
			// Получаем количество повторов измерения
			const int32_t value = ::atoi(argv[i] + 9);
			// Устанавливаем количество повторов измерения
			repeat = ((value > 0) ? static_cast <size_t> (value) : 1);
		// Если задано игнорирование порогов
		} else if(::strcmp(argv[i], "--relaxed") == 0)
			// Устанавливаем флаг игнорирования порогов
			relaxed = true;
		// Если запрошена справка по параметрам запуска
		else if((::strcmp(argv[i], "--help") == 0) || (::strcmp(argv[i], "-h") == 0)){
			// Выводим справку по параметрам запуска
			::printf(
				"Использование: %s [параметры]\n\n"
				"  --filter=ПОДСТРОКА  выполнить только сценарии с подстрокой в названии\n"
				"  --relaxed           выполнить измерения без проверки порогов\n"
				"  --repeat=ЧИСЛО      повторить каждое измерение и вывести середину ряда\n"
				"                      (часть сценариев считает итог однажды за процесс -\n"
				"                      им повтор ничего не даёт, нужен перезапуск процесса)\n"
				"  --help              вывести эту справку\n\n"
				"Показатели по количеству обращений к ядру требуют внедрённого счётчика\n"
				"системных вызовов и без него выводятся как пропущенные. Счётчик: %s\n"
				"Устройство и приёмы работы: tools/benchmark/syscount/README.md\n",
				argv[0], (awh::benchmark::syscall::available() ? "внедрён" : "не внедрён")
			);
			// Выводим успешный код выхода
			return 0;
		}
	}
	// Количество выполненных сценариев
	size_t executed = 0;
	// Количество сценариев, не уложившихся в порог
	size_t failed = 0;
	// Количество пропущенных сценариев
	size_t skipped = 0;
	/**
	 * Выводим заголовок таблицы результатов: ширина поля форматирования считается
	 * в октетах, а кириллица в UTF-8 занимает по два октета на символ, поэтому
	 * выравнивание задаётся пробелами явно
	 */
	::printf("СЦЕНАРИЙ                               ИЗМЕРЕНО          ПОРОГ   РЕЗУЛЬТАТ\n");
	/**
	 * Перебираем список зарегистрированных сценариев
	 */
	for(auto & scenario : awh::benchmark::scenarios()){
		// Если название сценария не соответствует фильтру
		if((filter != nullptr) && (scenario.name.find(filter) == std::string::npos))
			// Переходим к следующему сценарию
			continue;
		// Список исходов повторных измерений
		std::vector <awh::benchmark::result_t> outcomes;
		// Резервируем память под исходы повторных измерений
		outcomes.reserve(repeat);
		/**
		 * Выполняем измерение заданное количество раз
		 */
		for(size_t attempt = 0; attempt < repeat; attempt++){
			// Выполняем сценарий бенчмарка
			outcomes.push_back(scenario.run());
			// Если сценарий пропущен, повторять его незачем
			if(outcomes.back().skipped)
				// Прекращаем повторы измерения
				break;
		}
		/**
		 * Упорядочиваем исходы по измеренному значению
		 *
		 * @note Середина ряда берётся именно по значению, а не среднее: одиночный
		 * выброс - обыкновенно первый прогон, идущий на непрогретой машине, -
		 * среднее утягивает, а середину ряда не трогает
		 */
		std::sort(outcomes.begin(), outcomes.end(), [](const auto & left, const auto & right) noexcept -> bool {
			// Сравниваем измеренные значения
			return (left.value < right.value);
		});
		// Получаем исход, оказавшийся серединой ряда
		const awh::benchmark::result_t & result = outcomes[outcomes.size() / 2];
		/**
		 * Если измерение не выполнялось из-за отсутствия внешней оснастки, оно не
		 * является ни успешным, ни провалившимся: порог к нему не применяется, а
		 * код выхода набора от него не зависит
		 */
		if(result.skipped){
			// Считаем пропущенный сценарий
			skipped++;
			// Выводим сведения о пропущенном сценарии
			::printf(
				"%-32s %14s %14.2f   %s  (%s)\n",
				scenario.name.c_str(), "-", scenario.threshold,
				"ПРОПУСК", scenario.units.c_str()
			);
			// Если сценарий сообщил причину пропуска
			if(!result.reason.empty())
				// Выводим причину пропуска сценария
				::printf("%34s%s\n", "", result.reason.c_str());
			// Переходим к следующему сценарию
			continue;
		}
		// Считаем выполненный сценарий
		executed++;
		/**
		 * Определяем соответствие измеренного значения порогу
		 *
		 * @note Недействительное измерение порогу не подлежит вовсе и послаблением
		 *       не покрывается: послабление снимает требование УЛОЖИТЬСЯ в порог, а
		 *       здесь сценарий не выполнил ни одной операции, и укладываться нечему.
		 *       Показатель вида "на одну операцию" выдал бы при этом ноль и улёгся
		 *       бы в границу MAXIMUM сам собой - молчащий движок отчитался бы зелёным
		 */
		const bool passed = (!result.invalid && (relaxed || ((scenario.bound == awh::benchmark::bound_t::MINIMUM) ?
		 (result.value >= scenario.threshold) : (result.value <= scenario.threshold))));
		// Если измеренное значение не уложилось в порог
		if(!passed)
			// Считаем сценарий, не уложившийся в порог
			failed++;
		// Выводим результат выполнения сценария
		::printf(
			"%-32s %14.2f %14.2f   %s  (%s)\n",
			scenario.name.c_str(), result.value, scenario.threshold,
			(passed ? "OK  " : "ХУЖЕ"), scenario.units.c_str()
		);
		// Если измерение оказалось недействительным, сообщаем чем именно
		if(result.invalid && !result.reason.empty())
			// Выводим причину недействительности измерения
			::printf("%34s%s\n", "", result.reason.c_str());
		/**
		 * Если измерение повторялось, выводим границы разброса
		 *
		 * @note Часть сценариев считает итог ОДНАЖДЫ ЗА ПРОЦЕСС и держит его в
		 * постоянной величине - так соседние показатели (выделения памяти,
		 * обращения к ядру) считаются по одному прогону, а не по разным. Для них
		 * повтор внутри процесса даёт тот же самый исход, и объявлять это нулевым
		 * разбросом нельзя: честный повтор такого сценария - перезапуск процесса
		 */
		if(outcomes.size() > 1){
			// Если все повторы дали в точности один исход
			if(outcomes.front().value == outcomes.back().value)
				// Сообщаем, что сценарий считает итог однажды за процесс
				::printf(
					"%34sповторов: %zu, исход один и тот же - сценарий считает его однажды\n"
					"%34sза процесс; для разброса перезапускать процесс\n",
					"", outcomes.size(), ""
				);
			// Если исходы повторов различаются
			else ::printf(
				"%34sповторов: %zu, разброс: %.2f - %.2f (%.1f %%)\n", "",
				outcomes.size(), outcomes.front().value, outcomes.back().value,
				((outcomes.front().value > 0.0) ?
				 (((outcomes.back().value - outcomes.front().value) / outcomes.front().value) * 100.0) : 0.0)
			);
		}
		// Если сценарий сообщил дополнительные сведения
		if(!result.details.empty())
			// Выводим дополнительные сведения о прогоне
			::printf("%34s%s\n", "", result.details.c_str());
	}
	// Если ни один сценарий не выполнялся
	if((executed == 0) && (skipped == 0)){
		// Выводим сообщение об отсутствии подходящих сценариев
		::printf("\nСценарии не найдены\n");
		// Выводим код выхода с ошибкой
		return 1;
	}
	// Если все сценарии уложились в пороги
	if(failed == 0)
		// Выводим итоговое сообщение об успехе
		::printf("\nВыполнено сценариев: %zu, все уложились в пороги\n", executed);
	// Если часть сценариев не уложилась в пороги
	else ::printf("\nВыполнено сценариев: %zu, не уложились в пороги: %zu\n", executed, failed);
	// Если часть сценариев пропущена
	if(skipped > 0)
		// Выводим сведения о пропущенных сценариях
		::printf("Пропущено сценариев: %zu\n", skipped);
	// Выводим код выхода по результатам проверки порогов
	return ((failed == 0) ? 0 : 1);
}
