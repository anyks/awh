# @brief Раскладка отдельных стендов замеров кодеков по машинам и снятие показателей
#
# @details Раскладка эта устроена ИНАЧЕ, нежели раскладка проверок, и отличие тут не
#          украшение. Проверки идут на всех машинах разом: исход их от загрузки машины
#          не зависит, и одновременность лишь ускоряет прогон. Показатель же времени
#          зависит от загрузки целиком, и машина, занятая сборкой соседа, покажет
#          вдвое-втрое меньше без всякой регрессии. Оттого машины обходятся ПО ОЧЕРЕДИ,
#          а на каждой снимается несколько прогонов, и в свод идёт НАИХУДШИЙ из них
#
# @note Наихудший, а не средний: порог обязан пропускать всякий честный прогон, и
#       сглаженное среднее прячет как раз тот прогон, на каком порог отказал бы
#
# @warning Несколько прогонов заводятся отдельными процессами, а не ключом `--repeat`:
#          повтор внутри процесса меряет ту же прогретую память тем же разложением
#          кучи, и расхождение между прогонами занижается. Ровно этим прежде
#          изображалась воспроизводимость, какой нет
#
# @warning Запускать раскладку на машинах, занятых чужой работой, бессмысленно: числа
#          выйдут заниженными, и заметить это по самой выдаче нельзя вовсе. Стенды
#          суть общий припас, и занимать их следует уговором
#
# @copyright Copyright © 2026
#
# Вызов:
#   benchmark/codec/stands.sh [перечень стендов]
#
# Перечень стендов задаётся путями от корня дерева и по умолчанию таков:
#   benchmark/codec/xml/stand.sh benchmark/codec/json/stand.sh
#
# Переменные окружения:
#   AWH_STANDS  — перечень машин видом «доступ|краткое имя»
#   AWH_ROOT    — корень дерева исходных текстов, по умолчанию каталог сценария
#   AWH_PASSES  — число прогонов на машину, по умолчанию 3
#   AWH_FILTER  — отбор сценариев по подстроке имени, по умолчанию все
#

# Прекращаем работу при первом же отказе разбора доводов
set -u

# Получаем корень дерева исходных текстов
ROOT="${AWH_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"

# Получаем перечень прогоняемых стендов замеров
STANDS="${*:-benchmark/codec/xml/stand.sh benchmark/codec/json/stand.sh}"

# Получаем число прогонов, снимаемых на каждой машине
PASSES="${AWH_PASSES:-3}"

# Получаем отбор сценариев по подстроке имени
FILTER="${AWH_FILTER:-}"

#
# Перечень машин, по каким ведётся раскладка
#
# @note Строка машины устроена видом «доступ|краткое имя|собиратель|ключи», и два
#       последних поля пустуют у всех, кроме DragonFly: основной `c++` там от 2019 года
#       и наш код им не собрать вовсе, тогда как рядом стоит `g++14` из портов
#
# @warning DragonFly требует ещё и `-static-libstdc++`: собранное `g++14` при запуске
#          подхватывает `libstdc++` от gcc11 из `/usr/local/lib/gcc11` и падает с
#          «version CXXABI_1.3.15 required ... not found». Сборка при этом проходит
#          успешно, и отказ виден лишь при запуске
#
# @warning FreeBSD берётся МЕСТНЫЙ (10.100.1.207), а не anyks.com: тот рвёт длинный
#          сеанс ssh посреди прогона - трижды подряд ровно на 56-й строке вывода, - а
#          после череды таких обрывов перестаёт принимать подключения вовсе, отвечая
#          «Connection closed» уже на передаче свёртка. Машина эта публичная и служит
#          не только замерам, продавливать её повторами нельзя
#
# @warning Дно, по какому назначаются пороги, берут РАЗНЫЕ машины у разных сценариев,
#          и оттого перечень этот обязан быть полным. Снятое по семи машинам из
#          двенадцати есть дно СЕМИ машин, а не дно вообще: у соседнего набора замеров
#          дно записи числовых полей держал MS Windows - вдвое ниже самого медленного
#          из Linux, - и порог, снятый без него, оказался вчетверо завышен
#
MACHINES="${AWH_STANDS:-
forman@10.100.1.207|freebsd||
forman@10.100.1.200|netbsd||
forman@10.100.1.145|openbsd||
forman@10.100.1.155|dragonfly|g++14|-static-libstdc++ -static-libgcc
forman@10.100.1.105|solaris||
forman@10.100.1.159|openindiana||
forman@10.100.1.250|debian||
forman@10.100.1.209|ubuntu||
forman@10.100.1.249|fedora||
forman@10.100.1.109|opensuse||
forman@10.100.1.172|alt||
forman@10.100.1.245|alpine||
}"

#
# Метка прогона, разводящая рабочие каталоги на машинах
#
# @warning Метка обязательна: сценарий начинает работу сносом рабочего каталога, и при
#          имени общем снос одного прогона приходится на сборку другого
#
STAMP="${AWH_STAMP:-$$}"

# Собираемый свёрток исходных текстов
BUNDLE="/tmp/awh-bench-stands-$STAMP.tgz"

# Выводим сообщение о сборке свёртка
echo "Собираем свёрток: $BUNDLE"

#
# Выполняем сборку свёртка исходных текстов
#
# @note Свёрток собирается видом `ustar` с погашенными довесками файловой системы
#       Apple: `bsdtar` у FreeBSD отвергает их отказом «Special header too large»
#
( cd "$ROOT" && COPYFILE_DISABLE=1 tar --format=ustar -czf "$BUNDLE" \
	include src/codec src/num/lexical/table.cpp benchmark tools/benchmark/syscount ) || exit 1

# Собираемый сценарий прогона на стороне машины
RUNNER="/tmp/awh-bench-runner-$STAMP.sh"

#
# Выполняем сборку сценария прогона на стороне машины
#
# @note Сценарий передаётся файлом, а не строкою вызова `ssh`: строка проходит две
#       оболочки подряд, и всякая отмена в ней отменяется дважды
#
cat > "$RUNNER" <<'RUN'
#!/bin/sh
# Прогон отдельных стендов замеров на стороне машины
set -u
# Выполняем перебор всех прогоняемых стендов замеров
for SCRIPT in $AWH_SCRIPTS; do
	# Если сценария стенда в свёртке нет, пропускаем его
	if [ ! -f "$SCRIPT" ]; then
		echo "$SCRIPT: сценария нет в свёртке"
		continue
	fi
	# Разрешаем исполнение сценария стенда
	chmod +x "$SCRIPT"
	# Получаем краткое имя стенда по каталогу его
	NAME=$(basename "$(dirname "$SCRIPT")")
	# Выполняем сборку очередного стенда замеров
	if ! "./$SCRIPT" . "/tmp/awh-bench-$AWH_STAMP-$NAME" > "/tmp/awh-bench-$AWH_STAMP-$NAME.log" 2>&1; then
		#
		# Выводим сообщение об отказе сборки стенда
		#
		# @note Метка `!!!` опознаётся стороной вызывающей: отказ сборки неотличим от
		#       прохождения, если смотреть на один лишь поток вывода, а замеры при том
		#       не снимались ни разу
		#
		echo "!!! СБОРКА $NAME ОТКАЗАЛА"
		# Выводим первые строки отказа сборки
		grep -i error "/tmp/awh-bench-$AWH_STAMP-$NAME.log" | head -5
		# Выполняем переход к следующему стенду
		continue
	fi
	# Выполняем перебор всех снимаемых прогонов
	I=1
	while [ "$I" -le "$AWH_PASSES" ]; do
		# Выполняем перебор всех собранных двоичных файлов стенда
		for BINARY in "/tmp/awh-bench-$AWH_STAMP-$NAME"/*-bench "/tmp/awh-bench-$AWH_STAMP-$NAME"/*-bench.exe; do
			#
			# Выполняем прогон очередного двоичного файла стенда
			#
			# @note Показатели печатаются с меткою прогона: свод на стороне вызывающей
			#       берёт наихудший из них, и различить прогоны ему нужно
			#
				#
			# @warning Отбор строк обязан пропускать НЕ ТОЛЬКО показатели: замер, не
			#          запустившийся вовсе, пишет причину видом, ни на что тут не
			#          похожим, и прежний отбор её проглатывал. DragonFly отчитался
			#          пустотою, неотличимой от успеха, тогда как двоичный файл падал
			#          при запуске на нехватке CXXABI. Оттого счёт показателей ведётся
			#          явно, и прогон, не давший ни одного, объявляется отказавшим
			#          вместе с причиной
			#
			[ -x "$BINARY" ] || continue
			"$BINARY" ${AWH_FILTER:+--filter="$AWH_FILTER"} > "/tmp/awh-bench-out-$AWH_STAMP" 2>&1
			CODE=$?
			COUNT=0
			while IFS= read -r OUTPUT; do
				# Определяем строку показателя замера
				case "$OUTPUT" in
					"codec/"*) echo "прогон $I | $OUTPUT"; COUNT=$((COUNT + 1)) ;;
					*"ОТКАЗ"*) echo "прогон $I | $OUTPUT" ;;
				esac
			done < "/tmp/awh-bench-out-$AWH_STAMP"
			# Если замер не дал ни одного показателя, объявляем прогон отказавшим
			if [ "$COUNT" -eq 0 ]; then
				echo "!!! ЗАМЕР $NAME НЕ ДАЛ ПОКАЗАТЕЛЕЙ (код $CODE)"
				head -5 "/tmp/awh-bench-out-$AWH_STAMP"
			fi
			rm -f "/tmp/awh-bench-out-$AWH_STAMP"
		done
		# Выполняем переход к следующему прогону
		I=$((I + 1))
	done
done
# Выполняем уборку за собою
cd /tmp && rm -rf "/tmp/awh-bench-$AWH_STAMP-"*
RUN

# Выполняем перебор всех машин раскладки
echo "$MACHINES" | while IFS='|' read -r HOST TAG COMPILER BUILDFLAGS; do
	# Пропускаем пустые строки перечня машин
	[ -n "${HOST:-}" ] || continue
	#
	# Выводим сообщение о начале прогона на очередной машине с отметкой времени
	#
	# @note Отметки времени тут не украшение: числа, снятые на занятой машине, занижены,
	#       а по самой выдаче отличить это нельзя вовсе. Пересечение двух раскладок
	#       доказывается СЛИЧЕНИЕМ отметок, и без них разбор упирается в догадки с обеих
	#       сторон - однажды так и вышло: показатель, вдесятеро худший прочих, объясняли
	#       по переписке то ценою перехода в ядро, то чужой сборкою, тогда как машины
	#       попросту делили двое
	#
	echo "=== $TAG ($HOST) начат $(date '+%Y-%m-%d %H:%M:%S') ==="
	#
	# Выполняем передачу свёртка и сценария прогона на очередную машину
	#
	# @note Отказ передачи прогон не прекращает: недоступная машина - это отсутствие
	#       сведений о ней, а не отказ прочих
	#
	if ! scp -q -o BatchMode=yes -o StrictHostKeyChecking=no "$BUNDLE" "$RUNNER" "$HOST:/tmp/"; then
		# Выводим сообщение о недоступности машины
		echo "МАШИНА НЕДОСТУПНА"
		# Выполняем переход к следующей машине
		continue
	fi
	#
	# Выполняем прогон стендов замеров на очередной машине
	#
	# @note Свёрток разворачивается через `gzip -dc`: родной `tar` у систем Sun не
	#       понимает ключа `-z` вовсе
	#
	# @warning Ключ `-n` обязателен и держится тут не для красоты: перечень машин
	#          читается перебором из стандартного ввода, а `ssh` без `-n` вычитывает
	#          этот самый ввод себе целиком. Обход оттого кончается на ПЕРВОЙ же
	#          машине, и выглядит это не отказом разбора, а обрывом связи посреди
	#          прогона - «Connection closed by remote host», - то есть виновною
	#          кажется машина. Наступал на это, переписывая раскладку с проверок,
	#          где ключ этот стоит
	#
	ssh -n -o BatchMode=yes -o StrictHostKeyChecking=no "$HOST" "
		set -u
		rm -rf /tmp/awh-bench-tree-$STAMP
		mkdir -p /tmp/awh-bench-tree-$STAMP
		cd /tmp/awh-bench-tree-$STAMP || exit 1
		gzip -dc /tmp/$(basename "$BUNDLE") | tar -xf - || exit 1
		chmod +x /tmp/$(basename "$RUNNER")
		AWH_SCRIPTS='$STANDS' AWH_STAMP='$STAMP' AWH_PASSES='$PASSES' AWH_FILTER='$FILTER' \
			${COMPILER:+CXX='$COMPILER'} ${BUILDFLAGS:+FLAGS='$BUILDFLAGS'} \
			sh /tmp/$(basename "$RUNNER")
		cd /tmp && rm -rf /tmp/awh-bench-tree-$STAMP /tmp/$(basename "$BUNDLE") /tmp/$(basename "$RUNNER")
	" 2>&1 || echo "ПРОГОН ОТКАЗАЛ"
	# Выводим сообщение об окончании прогона на очередной машине с отметкой времени
	echo "--- $TAG окончен $(date '+%Y-%m-%d %H:%M:%S')"
done

# Выводим сообщение об окончании раскладки
echo "=== РАСКЛАДКА ОКОНЧЕНА ==="
