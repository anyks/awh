/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков контейнера CSV
		 *
		 * @note Пространство имён названо по содержимому, а не по модулю: имя codec
		 *       внутри пространства имён бенчмарков перекрыло бы пространство имён
		 *       самого модуля awh::codec, а имя csv - пространство имён контейнера
		 *
		 */
		namespace table {
			/**
			 * @brief Структура итогов прогона сценария
			 *
			 */
			typedef struct Outcome {
				// Количество разобранных октетов исходного текста
				size_t bytes;
				// Количество выполненных операций
				size_t operations;
				// Затраченное время в секундах
				double seconds;
				// Количество выполненных выделений памяти
				size_t allocations;
				// Суммарный объём выделенной памяти в октетах
				size_t allocated;
				/**
				 * @brief Конструктор
				 *
				 */
				explicit Outcome() noexcept :
				 bytes(0), operations(0), seconds(0.0), allocations(0), allocated(0) {}
			} outcome_t;
			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 * @param output итоги прогона сценария
			 * @return       сведения о прогоне для вывода
			 *
			 */
			std::string details(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения пропускной способности разбора
			 *
			 * @param output итоги прогона сценария
			 * @return       пропускная способность в мегабайтах в секунду
			 *
			 */
			double perSecond(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества выделений памяти на одну таблицу
			 *
			 * @param output итоги прогона сценария
			 * @return       количество выделений памяти на одну таблицу
			 *
			 */
			double perDocument(const outcome_t & output) noexcept;
	/**
	 * @brief Функция проверки работоспособности учёта выделений памяти
	 *
	 * @details Показатель «не более» при молчащем счётчике отчитывается «уложился»
	 *          всегда: нулевой расход меньше всякого порога. Проверка эта отделяет
	 *          исправный модуль от неработающего учёта
	 *
	 * @warning Сторожит поломку, уже случавшуюся: у MinGW стандартная библиотека
	 *          подключается отдельной библиотекой, и выделения, выполненные внутри
	 *          неё, замене оператора в самом исполняемом файле не видны. Учёт
	 *          недосчитывал втрое, а на записи отчитывался нулём - и все три сценария
	 *          выделений отчитывались «уложился». Лечится связыванием со статической
	 *          стандартной библиотекой
	 *
	 * @param output итоги прогона сценария
	 * @param result заполняемый результат измерения
	 * @return       признак работоспособности учёта
	 *
	 */
	bool counted(const outcome_t & output, awh::benchmark::result_t & result) noexcept;
			/**
			 * @brief Функция извлечения задержки обработки одной таблицы
			 *
			 * @details Показатель этот назначен мелким таблицам, где решает не пропускная
			 *          способность, а постоянные издержки на заведение разбора: ответ
			 *          службы идёт сотнями байтов, и заметная доля времени уходит на
			 *          заведение хранилищ, а не на сам разбор
			 *
			 * @param output итоги прогона сценария
			 * @return       задержка обработки одной таблицы в микросекундах
			 *
			 */
			double perLatency(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения объёма выделенной памяти на одну запись таблицы
			 *
			 * @details Показатель назначен потоковой выдаче записей обработчику: путь
			 *          этот заведён ради таблиц, в память не помещающихся, и объём,
			 *          приходящийся на одну запись, от размера таблицы зависеть не должен
			 *          вовсе
			 *
			 * @note Оснастка набора бенчмарков считает выделения за всё время замера, а
			 *       не удержанное разом: сравнивать здесь следует объём на одну запись, а
			 *       не итог по таблице. Итог по таблице растёт с её размером всегда - и
			 *       у пути, ничего в памяти не удерживающего, тоже
			 *
			 * @param output  итоги прогона сценария
			 * @param records количество обработанных записей за весь прогон
			 * @return        объём выделенной памяти на одну запись в октетах
			 *
			 */
			double perRecord(const outcome_t & output, const size_t records) noexcept;
			/**
			 * @brief Функция получения контрольной суммы прогонов
			 *
			 * @note Накопление итогов разбора в контрольную сумму обязательно: без
			 *       потребителя результата компилятор вправе устранить измеряемый
			 *       разбор целиком, и замерялась бы стоимость пустого цикла
			 *
			 * @return ссылка на контрольную сумму прогонов
			 *
			 */
			volatile uint64_t & checksum() noexcept;
			/**
			 * @brief Шаблон типа измеряемого сценария
			 *
			 * @tparam CALLBACK тип функции обработки одной таблицы
			 *
			 */
			template <typename CALLBACK>
			/**
			 * @brief Функция проведения замера сценария
			 *
			 * @details Замеру предшествует прогрев: первый разбор выводит на рабочий
			 *          режим кэш процессора и распределитель памяти, и его стоимость
			 *          к установившемуся режиму отношения не имеет
			 *
			 * @param bytes    размер разбираемой таблицы в октетах
			 * @param rounds   количество разбираемых таблиц
			 * @param callback функция обработки одной таблицы
			 * @return         итоги прогона сценария
			 *
			 */
			inline outcome_t measure(const size_t bytes, const size_t rounds, CALLBACK callback) noexcept {
				// Выполняем прогрев измеряемого разбора
				checksum() += static_cast <uint64_t> (callback());
				// Включаем учёт выделений памяти
				awh::benchmark::counting(true);
				// Запоминаем момент начала измерения
				const auto start = std::chrono::steady_clock::now();
				// Накопитель итогов разбора
				uint64_t accumulator = 0;
				/**
				 * Выполняем обработку требуемого количества таблиц
				 */
				for(size_t i = 0; i < rounds; i++)
					// Выполняем обработку очередной таблицы
					accumulator += static_cast <uint64_t> (callback());
				// Запоминаем момент окончания измерения
				const auto finish = std::chrono::steady_clock::now();
				// Отключаем учёт выделений памяти
				awh::benchmark::counting(false);
				// Накапливаем контрольную сумму прогона
				checksum() += accumulator;
				// Итоги прогона сценария
				outcome_t result;
				// Устанавливаем количество разобранных октетов
				result.bytes = (bytes * rounds);
				// Устанавливаем количество выполненных операций
				result.operations = rounds;
				// Устанавливаем затраченное время
				result.seconds = std::chrono::duration <double> (finish - start).count();
				// Получаем статистику выделений памяти
				awh::benchmark::allocations(result.allocations, result.allocated);
				// Выводим итоги прогона сценария
				return result;
			}
			/**
			 * @brief Функция получения эталонной таблицы ответа службы
			 *
			 * @details Все эталонные таблицы возвращаются объектом строки и разбираются
			 *          по указателям на её данные: сборка таблицы внутри измеряемого
			 *          цикла выделяла бы память и вносила бы в замер стоимость работы
			 *          со строкой вместо стоимости разбора
			 *
			 * @note Таблица размером с ответ службы - случай не редкий, а обыкновенный:
			 *       выдача по договору HTTP идёт сотнями байтов, и на ней решают не
			 *       мегабайты в секунду, а постоянные издержки на заведение разбора
			 *
			 * @return эталонный текст таблицы
			 *
			 */
			const std::string & service() noexcept;
			/**
			 * @brief Функция получения эталонной крупной таблицы
			 *
			 * @details Размер выбран заведомо превосходящим кэш последнего уровня:
			 *          разбор текста, целиком укладывающегося в кэш, показывает скорость
			 *          работы с кэшем, а не установившуюся пропускную способность
			 *
			 * @return эталонный текст таблицы
			 *
			 */
			const std::string & large() noexcept;
			/**
			 * @brief Функция получения эталонной широкой таблицы
			 *
			 * @details Немного записей о многих столбцах: работа здесь приходится на
			 *          разделители и завершение полей, а не на содержимое
			 *
			 * @return эталонный текст таблицы
			 *
			 */
			const std::string & wide() noexcept;
			/**
			 * @brief Функция получения эталонной таблицы с преобладанием кавычек
			 *
			 * @details Всякое поле заключено в кавычки, а часть их содержит и разделитель,
			 *          и удвоенную кавычку: путь этот у разбора отдельный, и снятие
			 *          отмены кавычек нагружает его сильнее прочих
			 *
			 * @return эталонный текст таблицы
			 *
			 */
			const std::string & quoted() noexcept;
			/**
			 * @brief Функция получения эталонной таблицы с многострочными полями
			 *
			 * @details Поля содержат переводы строк внутри кавычек: записи занимают по
			 *          нескольку строк, и путь этот отличает договор RFC 4180 от разбора
			 *          по строкам
			 *
			 * @return эталонный текст таблицы
			 *
			 */
			const std::string & multiline() noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK_CODEC_CSV__
