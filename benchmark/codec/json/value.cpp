	/**
	 * @brief Замер платы на одну установку поля владеющего значения вызовами
	 *
	 * @return результат измерения
	 *
	 */
	static awh::benchmark::result_t buildCallsLatency() noexcept {
		// Результат измерения
		awh::benchmark::result_t result;
		//
		// Собираемые имена полей отображения
		//
		// @note Имена собираются ОДИН раз и вынесены наружу нарочно: собирай их замер
		//       заново на каждом круге, он мерил бы сборку строк наравне с поиском поля
		//
		static vector <string> names;
		/**
		 * Если имена полей отображения ещё не собраны
		 */
		if(names.empty()){
			// Выполняем заведение места под имена полей отображения
			names.reserve(BUILD_CALLS_FIELDS);
			/**
			 * Выполняем сборку имён полей отображения
			 */
			for(uint32_t i = 0; i < BUILD_CALLS_FIELDS; i++)
				// Выполняем добавление очередного имени поля отображения
				names.push_back("field" + std::to_string(i));
		}
		// Выполняем прогон измеряемой операции
		const outcome_t outcome = measure(BUILD_CALLS_FIELDS, 1, []() noexcept -> uint64_t {
			// Собираемое владеющее значение
			awh::codec::json::value_t value;
			/**
			 * Выполняем перебор всех собираемых полей отображения
			 */
			for(uint32_t i = 0; i < BUILD_CALLS_FIELDS; i++)
				// Выполняем установку очередного поля отображения
				value[names.at(i)] = static_cast <int64_t> (i);
			// Выводим число собранных полей отображения
			return static_cast <uint64_t> (value.size());
		});
		//
		// Устанавливаем измеренное значение
		//
		// @warning Делить приходится САМИМ: `perLatency` относит время к числу КРУГОВ, а
		//          круг тут один и вмещает все установки разом. Без деления показатель
		//          вышел бы временем всего круга - 412599 мкс вместо 20, - и порог,
		//          снятый с него, не значил бы ничего
		//
		result.value = ((perLatency(outcome) * 1000.0) / static_cast <double> (BUILD_CALLS_FIELDS));
		// Устанавливаем сведения о прогоне
		result.details = details(outcome);
		// Выводим результат измерения
		return result;
	}
	/**
	 * @brief Замер платы на одно обращение к полю владеющего значения по имени
	 *
	 * @return результат измерения
	 *
	 */
	static awh::benchmark::result_t lookupCallsLatency() noexcept {
		// Результат измерения
		awh::benchmark::result_t result;
		// Собираемые имена полей отображения
		static vector <string> names;
		// Собираемое владеющее значение
		static awh::codec::json::value_t value;
		/**
		 * Если отображение ещё не собрано
		 */
		if(names.empty()){
			// Выполняем заведение места под имена полей отображения
			names.reserve(BUILD_CALLS_FIELDS);
			/**
			 * Выполняем сборку отображения с именами полей
			 */
			for(uint32_t i = 0; i < BUILD_CALLS_FIELDS; i++){
				// Выполняем добавление очередного имени поля отображения
				names.push_back("field" + std::to_string(i));
				// Выполняем установку очередного поля отображения
				value[names.back()] = static_cast <int64_t> (i);
			}
		}
		// Выполняем прогон измеряемой операции
		const outcome_t outcome = measure(BUILD_CALLS_FIELDS, 1, []() noexcept -> uint64_t {
			// Сумма разысканных значений полей отображения
			uint64_t result = 0;
			/**
			 * Выполняем перебор всех разыскиваемых полей отображения
			 */
			for(uint32_t i = 0; i < BUILD_CALLS_FIELDS; i++){
				// Извлекаемое значение поля отображения
				int64_t item = 0;
				/**
				 * Если значение поля отображения извлечь удалось
				 */
				if(value[names.at(i)].value(item))
					// Выполняем учёт извлечённого значения поля отображения
					result += static_cast <uint64_t> (item);
			}
			// Выводим сумму разысканных значений полей отображения
			return result;
		});
		// Устанавливаем измеренное значение, отнесённое к одному обращению
		result.value = ((perLatency(outcome) * 1000.0) / static_cast <double> (BUILD_CALLS_FIELDS));
		// Устанавливаем сведения о прогоне
		result.details = details(outcome);
		// Выводим результат измерения
		return result;
	}
