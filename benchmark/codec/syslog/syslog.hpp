namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков контейнера SysLog
		 *
		 * @note Пространство имён названо по содержимому, а не по модулю: имя syslog
		 *       внутри пространства имён бенчмарков перекрыло бы пространство имён
		 *       самого контейнера, а сверх того имя это занято системным макросом
		 *
		 */
		namespace journal {
			/**
			 * @brief Структура итогов прогона сценария
			 *
			 */
			typedef struct Outcome {
				// Количество разобранных октетов исходного текста
				size_t bytes;
				// Количество выполненных операций
				size_t operations;
				// Затраченное время в секундах
				double seconds;
				// Количество выполненных выделений памяти
				size_t allocations;
				/**
				 * @brief Итог измеряемой работы, кругами накопленный
				 *
				 * @details Итог этот сторожит меру: числитель берётся длиной ЭТАЛОНА,
				 *          помноженной на число кругов, и при отказе работы сценарий
				 *          отчитался бы тем БЫСТРЕЕ, чем раньше отказ наступил. Здоровый
				 *          круг отдаёт хотя бы единицу, оттого итог МЕНЬШЕ числа кругов
				 *          означает отказ хотя бы одного круга - в том числе частичный,
				 *          какой поверка одним кругом до замера не ловит
				 *
				 */
				size_t produced;
				// Суммарный объём выделенной памяти в октетах
				size_t allocated;
				/**
				 * @brief Конструктор
				 *
				 */
				explicit Outcome() noexcept :
				 bytes(0), operations(0), seconds(0.0), allocations(0), produced(0), allocated(0) {}
			} outcome_t;
			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 * @param output итоги прогона сценария
			 * @return       сведения о прогоне для вывода
			 *
			 */
			std::string details(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения пропускной способности разбора
			 *
			 * @param output итоги прогона сценария
			 * @return       пропускная способность в мегабайтах в секунду
			 *
			 */
			double perSecond(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества разобранных записей в секунду
			 *
			 * @details Показатель этот и есть тот самый EPS, каким мерится работа
			 *          сборщика журналов: он принимает поток событий от многих
			 *          устройств, и решает у него не пропускная способность в
			 *          мегабайтах, а число событий, какое он успевает разобрать
			 *
			 * @param output итоги прогона сценария
			 * @return       количество разобранных записей в секунду
			 *
			 */
			double perEvents(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества выделений памяти на одну запись
			 *
			 * @param output итоги прогона сценария
			 * @return       количество выделений памяти на одну запись
			 *
			 */
			double perRecord(const outcome_t & output) noexcept;
			/**
			 * @brief Функция проверки работоспособности учёта выделений памяти
			 *
			 * @details Показатель «не более» при молчащем счётчике отчитывается «уложился»
			 *          всегда: нулевой расход меньше всякого порога. Проверка эта отделяет
			 *          исправный модуль от неработающего учёта
			 *
			 * @param output итоги прогона сценария
			 * @param result заполняемый результат измерения
			 * @return       признак работоспособности учёта
			 *
			 */
			bool counted(const outcome_t & output, awh::benchmark::result_t & result) noexcept;
			/**
			 * @brief Функция поверки того, что измеряемая работа кругами состоялась
			 *
			 * @details Здоровый круг отдаёт хотя бы единицу итога, оттого итог МЕНЬШЕ
			 *          числа кругов означает отказ хотя бы одного из них. Поверка эта
			 *          строже поверки одним кругом до замера: та ловит эталон, негодный
			 *          изначально, а эта - и отказ, наступивший посреди прогона
			 *
			 * @param output итоги прогона сценария
			 * @param result заполняемый результат измерения
			 * @return       признак того, что работа кругами состоялась
			 *
			 */
			bool worked(const outcome_t & output, awh::benchmark::result_t & result) noexcept;
			/**
			 * @brief Функция извлечения задержки обработки одной записи
			 *
			 * @param output итоги прогона сценария
			 * @return       задержка обработки одной записи в микросекундах
			 *
			 */
			double perLatency(const outcome_t & output) noexcept;
			/**
			 * @brief Функция получения контрольной суммы прогонов
			 *
			 * @note Накопление итогов разбора в контрольную сумму обязательно: без
			 *       потребителя результата компилятор вправе устранить измеряемый
			 *       разбор целиком, и замерялась бы стоимость пустого цикла
			 *
			 * @return ссылка на контрольную сумму прогонов
			 *
			 */
			volatile uint64_t & checksum() noexcept;
			/**
			 * @brief Шаблон типа измеряемого сценария
			 *
			 * @tparam CALLBACK тип функции обработки одной записи
			 *
			 */
			template <typename CALLBACK>
			/**
			 * @brief Функция проведения замера сценария
			 *
			 * @details Замеру предшествует прогрев: первый разбор выводит на рабочий
			 *          режим кэш процессора и распределитель памяти, и его стоимость
			 *          к установившемуся режиму отношения не имеет
			 *
			 * @param bytes    размер разбираемой записи в октетах
			 * @param rounds   количество разбираемых записей
			 * @param callback функция обработки одной записи
			 * @return         итоги прогона сценария
			 *
			 */
			inline outcome_t measure(const size_t bytes, const size_t rounds, CALLBACK callback) noexcept {
				// Выполняем прогрев измеряемого разбора
				checksum() += static_cast <uint64_t> (callback());
				// Включаем учёт выделений памяти
				awh::benchmark::counting(true);
				// Запоминаем момент начала измерения
				const auto start = std::chrono::steady_clock::now();
				// Накопитель итогов разбора
				uint64_t accumulator = 0;
				/**
				 * Выполняем обработку требуемого количества записей
				 */
				for(size_t i = 0; i < rounds; i++)
					// Выполняем обработку очередной записи
					accumulator += static_cast <uint64_t> (callback());
				// Запоминаем момент окончания измерения
				const auto finish = std::chrono::steady_clock::now();
				// Отключаем учёт выделений памяти
				awh::benchmark::counting(false);
				// Накапливаем контрольную сумму прогона
				checksum() += accumulator;
				// Итоги прогона сценария
				outcome_t result;
				// Устанавливаем количество разобранных октетов
				result.bytes = (bytes * rounds);
				// Устанавливаем количество выполненных операций
				result.operations = rounds;
				// Устанавливаем итог измеряемой работы, кругами накопленный
				result.produced = static_cast <size_t> (accumulator);
				// Устанавливаем затраченное время
				result.seconds = std::chrono::duration <double> (finish - start).count();
				// Получаем статистику выделений памяти
				awh::benchmark::allocations(result.allocations, result.allocated);
				// Выводим итоги прогона сценария
				return result;
			}
			/**
			 * @brief Функция получения эталонной записи устаревшего описания
			 *
			 * @details Запись эта взята из живого журнала FreeBSD и несёт всё, чем
			 *          запись RFC 3164 нагружает разбор: приставку приоритета, дату вида
			 *          BSD, имя узла точками, метку приложения с опознавателем работы и
			 *          свободный текст
			 *
			 * @note Все эталонные записи возвращаются объектом строки и разбираются по
			 *       указателям на её данные: сборка текста внутри измеряемого цикла
			 *       выделяла бы память и вносила бы в замер стоимость работы со строкой
			 *       вместо стоимости разбора
			 *
			 * @return эталонная запись устаревшего описания
			 *
			 */
			const std::string & legacy() noexcept;
			/**
			 * @brief Функция получения эталонной записи нынешнего описания
			 *
			 * @details Запись эта нагружает разбор полным заголовком из шести полей и
			 *          одним блоком структурированных данных - тем самым видом, каким
			 *          пишут сборщики журналов нынешнего поколения
			 *
			 * @return эталонная запись нынешнего описания
			 *
			 */
			const std::string & modern() noexcept;
			/**
			 * @brief Функция получения эталонной записи со многими блоками данных
			 *
			 * @details Запись эта самая тяжёлая: восемь блоков структурированных данных
			 *          с отменой знаков в значениях. Разбор блоков и есть та работа,
			 *          какой запись RFC 5424 отличается от устаревшей
			 *
			 * @return эталонная запись со многими блоками данных
			 *
			 */
			const std::string & structured() noexcept;
			/**
			 * @brief Функция получения эталонной записи наименьшей длины
			 *
			 * @details Запись без текста и без данных - одна приставка и заголовок:
			 *          показатель задержки назначен именно ей, ибо у коротких записей
			 *          решают постоянные издержки на заведение хранилищ разбора
			 *
			 * @return эталонная запись наименьшей длины
			 *
			 */
			const std::string & minimal() noexcept;
			/**
			 * @brief Функция получения эталонного потока записей
			 *
			 * @details Поток из многих записей подряд, обоих описаний вперемешку:
			 *          сборщик журналов принимает именно такой поток - от устройств
			 *          разных поколений разом, - а не одиночную запись
			 *
			 * @return эталонный поток записей
			 *
			 */
			const std::string & stream() noexcept;
			/**
			 * @brief Функция получения количества записей эталонного потока
			 *
			 * @details Число это берётся ходом, а не постоянной у сценария: постоянная,
			 *          от самого потока оторванная, разошлась бы с ним при первой же
			 *          правке эталона - и показатель числа записей в секунду соврал бы
			 *          молча
			 *
			 * @return количество записей эталонного потока
			 *
			 */
			size_t records() noexcept;
		};
	};
};

