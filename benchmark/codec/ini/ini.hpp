namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков контейнера INI
		 *
		 * @note Пространство имён названо по содержимому, а не по модулю: имя codec
		 *       внутри пространства имён бенчмарков перекрыло бы пространство имён
		 *       самого модуля awh::codec, а имя ini - пространство имён контейнера
		 *
		 */
		namespace config {
			/**
			 * @brief Структура итогов прогона сценария
			 *
			 */
			typedef struct Outcome {
				// Количество разобранных октетов исходного текста
				size_t bytes;
				// Количество выполненных операций
				size_t operations;
				// Затраченное время в секундах
				double seconds;
				// Количество выполненных выделений памяти
				size_t allocations;
				// Суммарный объём выделенной памяти в октетах
				size_t allocated;
				/**
				 * @brief Конструктор
				 *
				 */
				explicit Outcome() noexcept :
				 bytes(0), operations(0), seconds(0.0), allocations(0), allocated(0) {}
			} outcome_t;
			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 * @param output итоги прогона сценария
			 * @return       сведения о прогоне для вывода
			 *
			 */
			std::string details(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения пропускной способности разбора
			 *
			 * @param output итоги прогона сценария
			 * @return       пропускная способность в мегабайтах в секунду
			 *
			 */
			double perSecond(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества выделений памяти на один файл
			 *
			 * @param output итоги прогона сценария
			 * @return       количество выделений памяти на один файл настроек
			 *
			 */
			double perDocument(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения задержки обработки одного файла настроек
			 *
			 * @details Показатель этот назначен мелким файлам, где решает не пропускная
			 *          способность, а постоянные издержки на запуск: файл настроек
			 *          приложения идёт по одному-два килобайта и читается однажды при
			 *          запуске, так что заметная доля времени уходит на заведение
			 *          хранилищ разбора, а не на сам разбор
			 *
			 * @param output итоги прогона сценария
			 * @return       задержка обработки одного файла в микросекундах
			 *
			 */
			double perLatency(const outcome_t & output) noexcept;
			/**
			 * @brief Функция получения контрольной суммы прогонов
			 *
			 * @note Накопление итогов разбора в контрольную сумму обязательно: без
			 *       потребителя результата компилятор вправе устранить измеряемый
			 *       разбор целиком, и замерялась бы стоимость пустого цикла
			 *
			 * @return ссылка на контрольную сумму прогонов
			 *
			 */
			volatile uint64_t & checksum() noexcept;
			/**
			 * @brief Шаблон типа измеряемого сценария
			 *
			 * @tparam CALLBACK тип функции обработки одного файла настроек
			 *
			 */
			template <typename CALLBACK>
			/**
			 * @brief Функция проведения замера сценария
			 *
			 * @details Замеру предшествует прогрев: первый разбор выводит на рабочий
			 *          режим кэш процессора и распределитель памяти, и его стоимость
			 *          к установившемуся режиму отношения не имеет
			 *
			 * @param bytes    размер разбираемого текста настроек в октетах
			 * @param rounds   количество разбираемых файлов настроек
			 * @param callback функция обработки одного файла настроек
			 * @return         итоги прогона сценария
			 *
			 */
			inline outcome_t measure(const size_t bytes, const size_t rounds, CALLBACK callback) noexcept {
				// Выполняем прогрев измеряемого разбора
				checksum() += static_cast <uint64_t> (callback());
				// Включаем учёт выделений памяти
				awh::benchmark::counting(true);
				// Запоминаем момент начала измерения
				const auto start = std::chrono::steady_clock::now();
				// Накопитель итогов разбора
				uint64_t accumulator = 0;
				/**
				 * Выполняем обработку требуемого количества файлов настроек
				 */
				for(size_t i = 0; i < rounds; i++)
					// Выполняем обработку очередного файла настроек
					accumulator += static_cast <uint64_t> (callback());
				// Запоминаем момент окончания измерения
				const auto finish = std::chrono::steady_clock::now();
				// Отключаем учёт выделений памяти
				awh::benchmark::counting(false);
				// Накапливаем контрольную сумму прогона
				checksum() += accumulator;
				// Итоги прогона сценария
				outcome_t result;
				// Устанавливаем количество разобранных октетов
				result.bytes = (bytes * rounds);
				// Устанавливаем количество выполненных операций
				result.operations = rounds;
				// Устанавливаем затраченное время
				result.seconds = std::chrono::duration <double> (finish - start).count();
				// Получаем статистику выделений памяти
				awh::benchmark::allocations(result.allocations, result.allocated);
				// Выводим итоги прогона сценария
				return result;
			}
			/**
			 * @brief Функция получения эталонного файла настроек приложения
			 *
			 * @details Все эталонные тексты возвращаются объектом строки и разбираются
			 *          по указателям на её данные: сборка текста внутри измеряемого
			 *          цикла выделяла бы память и вносила бы в замер стоимость работы
			 *          со строкой вместо стоимости разбора
			 *
			 * @note Файл настроек приложения - тот самый случай, ради которого контейнер
			 *       и написан: пара килобайт с примечаниями, читаемая однажды при запуске
			 *
			 * @return эталонный текст настроек
			 *
			 */
			const std::string & service() noexcept;
			/**
			 * @brief Функция получения эталонного файла настроек по образцу Git
			 *
			 * @details Наречие это нагружает разбор сильнее прочих: подраздел в кавычках,
			 *          примечание в конце строки, управляющие последовательности и
			 *          свойство без значения - всё сразу
			 *
			 * @return эталонный текст настроек
			 *
			 */
			const std::string & repository() noexcept;
			/**
			 * @brief Функция получения эталонного крупного файла настроек
			 *
			 * @details Размер выбран заведомо превосходящим кэш последнего уровня:
			 *          разбор текста, целиком укладывающегося в кэш, показывает скорость
			 *          работы с кэшем, а не установившуюся пропускную способность
			 *
			 * @return эталонный текст настроек
			 *
			 */
			const std::string & large() noexcept;
			/**
			 * @brief Функция получения эталонного текста с преобладанием примечаний
			 *
			 * @details Файл настроек, писанный человеком, наполовину состоит из
			 *          примечаний, и путь их разбора нагружается наравне с разбором
			 *          свойств
			 *
			 * @return эталонный текст настроек
			 *
			 */
			const std::string & annotated() noexcept;
			/**
			 * @brief Функция получения эталонного текста со множеством разделов
			 *
			 * @details Множество разделов нагружает поиск и указатели дерева: поиск
			 *          раздела попарным сличением имён обращает разбор в квадратичный
			 *
			 * @return эталонный текст настроек
			 *
			 */
			const std::string & sections() noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK_CODEC_INI__
