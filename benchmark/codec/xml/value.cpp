	static const bool TAKE_ALLOCATIONS_REGISTERED = awh::benchmark::add(
		"codec/xml: выделения на снятие значения", "выд./док.", TAKE_ALLOCATIONS_THRESHOLD,
		awh::benchmark::bound_t::MAXIMUM, takeAllocations
	);
	/**
	 * @brief Замер платы на одну выдачу совпавших узлов у широкого узла разметки
	 *
	 * @return результат измерения
	 *
	 */
	static awh::benchmark::result_t wideChildrenLatency() noexcept {
		// Результат измерения
		awh::benchmark::result_t result;
		// Собираемые имена вложенных узлов
		static vector <string> names;
		// Собираемый узел разметки
		static awh::codec::xml::value_t value(string("root"));
		/**
		 * Если узел разметки ещё не собран
		 */
		if(names.empty()){
			// Выполняем заведение места под имена вложенных узлов
			names.reserve(WIDE_NODE_CHILDREN);
			/**
			 * Выполняем сборку узла разметки с вложенными узлами
			 */
			for(uint32_t i = 0; i < WIDE_NODE_CHILDREN; i++){
				// Выполняем добавление очередного имени вложенного узла
				names.push_back("item" + std::to_string(i));
				// Выполняем заведение очередного вложенного узла
				value[names.back()];
			}
		}
		// Выполняем прогон измеряемой операции
		const outcome_t outcome = measure(WIDE_NODE_CHILDREN, 1, []() noexcept -> uint64_t {
			// Число выданных узлов разметки
			uint64_t result = 0;
			//
			// Получаем ссылку на узел разметки только для чтения
			//
			// @warning Ссылка эта обязательна: обращение по имени у ИЗМЕНЯЕМОГО узла
			//          недостающий узел заводит, а выдача совпавших у него сбрасывает
			//          отображение - замер мерил бы перестроение вместо выдачи
			//
			const awh::codec::xml::value_t & ro = value;
			/**
			 * Выполняем перебор всех разыскиваемых вложенных узлов
			 */
			for(uint32_t i = 0; i < WIDE_NODE_CHILDREN; i++)
				// Выполняем учёт выданных узлов разметки
				result += static_cast <uint64_t> (ro.children(names.at(i)).size());
			// Выводим число выданных узлов разметки
			return result;
		});
		// Устанавливаем измеренное значение
		result.value = ((perLatency(outcome) * 1000.0) / static_cast <double> (WIDE_NODE_CHILDREN));
		// Устанавливаем сведения о прогоне
		result.details = details(outcome);
		// Выводим результат измерения
		return result;
	}
	/**
	 * Выполняем регистрацию сценария заведения вложенных узлов у широкого узла разметки
	 */
	static const bool WIDE_BUILD_REGISTERED = awh::benchmark::add(
		"codec/xml: заведение узлов широкого узла", "нс/узел", WIDE_BUILD_THRESHOLD,
		awh::benchmark::bound_t::MAXIMUM, wideBuildLatency
	);
	/**
	 * Выполняем регистрацию сценария розыска вложенного узла по имени
	 */
	static const bool WIDE_LOOKUP_REGISTERED = awh::benchmark::add(
		"codec/xml: розыск узла широкого узла по имени", "нс/обр.", WIDE_LOOKUP_THRESHOLD,
		awh::benchmark::bound_t::MAXIMUM, wideLookupLatency
	);
	/**
	 * Выполняем регистрацию сценария выдачи совпавших узлов у широкого узла разметки
	 */
	static const bool WIDE_CHILDREN_REGISTERED = awh::benchmark::add(
		"codec/xml: выдача совпавших у широкого узла", "нс/обр.", WIDE_CHILDREN_THRESHOLD,
		awh::benchmark::bound_t::MAXIMUM, wideChildrenLatency
	);
