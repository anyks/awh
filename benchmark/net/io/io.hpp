#ifndef __AWH_BENCHMARK_NET_IO__
#define __AWH_BENCHMARK_NET_IO__

/**
 * Стандартные заголовочные файлы
 */
#include <string>
#include <cstddef>
#include <cstdint>

/**
 * Подключаем заголовочные файлы проекта
 */
#include "../../main.hpp"
#include "../../../include/net/io.hpp"

/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков сетевого движка
		 *
		 * @details Сценарии измеряют движок `awh::engine::io_t` на петлевом
		 *          интерфейсе: обе стороны обмена живут в одном процессе и
		 *          обслуживаются одним циклом событий. Такой прогон измеряет
		 *          стоимость самого цикла - подписки, доставки готовности,
		 *          чтения и постановки в очередь на отправку, - а не сети.
		 *          Набор параметров нагрузки совпадает с эталонными
		 *          реализациями конкурентов из каталога `tools/benchmark`,
		 *          поэтому показатели сопоставимы напрямую
		 *
		 */
		namespace io {
			/**
			 * @brief Размер полезной нагрузки одного обмена в октетах
			 *
			 * @details Обмен короткими сообщениями измеряет постоянные накладные
			 *          расходы цикла событий: на 64 октетах стоимость копирования
			 *          данных пренебрежима, и показатель определяется доставкой
			 *          готовности и вызовом функций обратного вызова
			 *
			 */
			static constexpr size_t ECHO_PAYLOAD = 64;
			/**
			 * @brief Количество обменов сценария эха на одном подключении
			 *
			 */
			static constexpr size_t ECHO_SINGLE_ROUNDS = 100000;
			/**
			 * @brief Количество одновременных подключений сценария эха на множестве подключений
			 *
			 */
			static constexpr size_t ECHO_MULTI_CONNECTIONS = 500;
			/**
			 * @brief Количество обменов сценария эха на множестве подключений
			 *
			 */
			static constexpr size_t ECHO_MULTI_ROUNDS = 100000;
			/**
			 * @brief Размер блока постановки в очередь сценария пропускной способности в октетах
			 *
			 */
			static constexpr size_t STREAM_CHUNK = 65536;
			/**
			 * @brief Объём передачи сценария пропускной способности в октетах
			 *
			 */
			static constexpr size_t STREAM_VOLUME = (512 * 1024 * 1024);
			/**
			 * @brief Количество циклов подключения сценария установления соединений
			 *
			 * @details Количество ограничено сверху диапазоном динамических портов
			 *          операционной системы: закрытая сторона подключения удерживает
			 *          порт в состоянии TIME_WAIT, и прогон на 16 тысячах циклов
			 *          упирается в исчерпание диапазона, а не в цикл событий -
			 *          показатель падает при этом на порядок и измеряет уже перебор
			 *          занятых портов ядром
			 *
			 */
			static constexpr size_t ACCEPT_ROUNDS = 4000;
			/**
			 * @brief Количество таймеров сценария измерения таймеров
			 *
			 */
			static constexpr size_t TIMER_COUNT = 50000;
			/**
			 * @brief Разброс срабатывания таймеров в миллисекундах
			 *
			 * @details Одинаковый дедлайн у всех таймеров выродил бы структуру
			 *          хранения в очередь с единственным ключом, поэтому дедлайны
			 *          разносятся: вставка и извлечение идут по всей её глубине
			 *
			 */
			static constexpr uint32_t TIMER_SPREAD = 8;
			/**
			 * @brief Глубина очереди принятия входящих соединений
			 *
			 */
			static constexpr uint32_t BACKLOG = 1024;
			/**
			 * @brief Структура итогов прогона сценария
			 *
			 */
			typedef struct Outcome {
				// Количество выполненных операций
				size_t operations;
				// Объём переданных данных в октетах
				size_t bytes;
				// Затраченное время в секундах
				double seconds;
				// Количество выполненных выделений памяти
				size_t allocations;
				// Суммарный объём выделенной памяти в октетах
				size_t allocated;
				// Пиковый объём занятой процессом памяти в октетах
				size_t footprint;
				/**
				 * @brief Конструктор
				 *
				 */
				explicit Outcome() noexcept :
				 operations(0), bytes(0), seconds(0.0),
				 allocations(0), allocated(0), footprint(0) {}
			} outcome_t;
			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 * @param output итоги прогона сценария
			 * @return       сведения о прогоне для вывода
			 *
			 */
			std::string details(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества операций в секунду
			 *
			 * @param output итоги прогона сценария
			 * @return       количество операций в секунду
			 *
			 */
			double perSecond(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения пропускной способности в мебибайтах в секунду
			 *
			 * @param output итоги прогона сценария
			 * @return       пропускная способность
			 *
			 */
			double megabytes(const outcome_t & output) noexcept;
			/**
			 * @brief Функция извлечения количества выделений памяти на одну операцию
			 *
			 * @param output итоги прогона сценария
			 * @return       количество выделений памяти на одну операцию
			 *
			 */
			double perOperation(const outcome_t & output) noexcept;
			/**
			 * @brief Функция получения пикового объёма занятой процессом памяти
			 *
			 * @return пиковый объём занятой процессом памяти в октетах
			 *
			 */
			size_t footprint() noexcept;
			/**
			 * @brief Функция получения свободного порта петлевого интерфейса
			 *
			 * @note Порт занимается временным сокетом и сразу освобождается: движок
			 *       привязывается к нему следующим действием сценария, поэтому
			 *       перехват порта посторонним процессом в этом промежутке
			 *       маловероятен, а фиксированный порт ломал бы повторный прогон
			 *
			 * @return номер свободного порта
			 *
			 */
			uint16_t port() noexcept;
			/**
			 * @brief Функция получения набора опций события сценариев
			 *
			 * @details Набор совпадает с опциями эталонных реализаций конкурентов:
			 *          неблокирующий ввод-вывод, отключённый алгоритм Нейгла и
			 *          переиспользование адреса. Алгоритм Нейгла обязателен к
			 *          отключению: с ним обмен короткими сообщениями измерял бы
			 *          задержку подтверждения TCP, а не цикл событий
			 *
			 * @return набор опций события
			 *
			 */
			uint16_t options() noexcept;
			/**
			 * @brief Функция получения объекта фреймворка сценариев
			 *
			 * @return объект фреймворка
			 *
			 */
			const awh::fmk_t * framework() noexcept;
			/**
			 * @brief Функция получения объекта логирования сценариев
			 *
			 * @note Логирование отключено: вывод в поток из функции обратного
			 *       вызова стоит дороже самой измеряемой операции
			 *
			 * @return объект логирования
			 *
			 */
			const awh::log_t * logger() noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK_NET_IO__
