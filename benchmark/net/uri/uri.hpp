/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков модуля работы с идентификаторами ресурсов
		 *
		 * @details Модуль разбирает строку URI на составляющие, собирает её обратно и
		 *          выполняет процентное кодирование её частей. Обращения к нему идут с
		 *          каждого запроса протокола HTTP - и на стороне клиента, где адрес
		 *          запроса собирается перед отправкой, и на стороне сервера, где он
		 *          разбирается после приёма. Стоимость этих операций входит в стоимость
		 *          запроса, но в замерах протокола отдельно не видна: там она измеряется
		 *          вперемешку с разбором заголовков и работой соединения.
		 *
		 *          Сценарии ниже меряют модуль в отрыве от протокола. Показатель у них
		 *          двойной: операций в секунду и выделений памяти на операцию. Второй
		 *          важнее первого - разбор строки на представления её частей выделять
		 *          память не обязан вовсе, а сборка обязана ровно настолько, насколько
		 *          этого требует возвращаемая наружу строка. Всё, что сверх того, есть
		 *          работа, которой можно не делать
		 *
		 */
		namespace uri {
			/**
			 * @brief Количество повторений сценариев разбора и сборки URI
			 *
			 * @details Одна операция обходится в единицы микросекунд, и на меньшем
			 *          количестве повторений замер измерял бы разрешение часов
			 *
			 */
			static constexpr size_t URI_ROUNDS = 100000;
			/**
			 * @brief Количество повторений сценариев хэширования и сравнения
			 *
			 * @details Обе операции на порядок дешевле разбора: на общем количестве
			 *          повторений показатель определялся бы накладными расходами
			 *          самого цикла замера, а не измеряемой операцией
			 *
			 */
			static constexpr size_t LIGHT_ROUNDS = 500000;
			/**
			 * @brief Количество повторений прогрева сценариев
			 *
			 * @details Первые обращения к модулю выходят на установившийся режим:
			 *          распределитель памяти выходит на рабочий объём, а внутренние
			 *          накопители объекта набирают ёмкость
			 *
			 */
			static constexpr size_t URI_WARMUP = 5000;

			/**
			 * @brief Структура итогов прогона сценария
			 *
			 * @note Оснастка замера общая с бенчмарками сетевого движка: к вводу-выводу
			 *       она не привязана ничем, снимает выделения памяти, обращения к ядру и
			 *       объём занятой процессом памяти. Заводить ей вторую копию значило бы
			 *       разойтись с ней при первой же правке
			 *
			 */
			typedef io::outcome_t outcome_t;

			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 */
			using io::details;
			/**
			 * @brief Функция извлечения количества операций в секунду
			 *
			 */
			using io::perSecond;
			/**
			 * @brief Функция извлечения количества выделений памяти на одну операцию
			 *
			 */
			using io::perOperation;
			/**
			 * @brief Функция извлечения количества системных вызовов на одну операцию
			 *
			 */
			using io::perSyscall;
			/**
			 * @brief Функция снятия показателей окружения по итогам замера
			 *
			 */
			using io::collect;
			/**
			 * @brief Функция получения объекта фреймворка сценариев
			 *
			 */
			using io::framework;
			/**
			 * @brief Функция получения объекта логирования сценариев
			 *
			 */
			using io::logger;

			/**
			 * @brief Функция получения контрольной суммы прогонов
			 *
			 * @note Накопление результатов операций в контрольную сумму обязательно:
			 *       без потребителя результата компилятор вправе устранить измеряемое
			 *       вычисление целиком, и замерялась бы стоимость пустого цикла
			 *
			 * @return ссылка на контрольную сумму прогонов
			 *
			 */
			volatile uint64_t & checksum() noexcept;

			/**
			 * @brief Шаблон типа измеряемого сценария
			 *
			 * @tparam CALLBACK тип функции выполнения одной операции
			 *
			 */
			template <typename CALLBACK>
			/**
			 * @brief Функция проведения замера сценария
			 *
			 * @details Замеру предшествует прогрев: первые операции выводят внутренние
			 *          буферы модуля и распределитель памяти на рабочий объём, и их
			 *          выделения памяти к установившемуся режиму отношения не имеют
			 *
			 * @note Функции выполнения операции передаётся номер круга. Методы модуля
			 *       побочных действий не имеют, и вызов с одними и теми же доводами
			 *       оптимизирующий компилятор вправе вынести из цикла целиком -
			 *       измерялась бы тогда стоимость пустого цикла, причём только в
			 *       оптимизированной сборке, где показатель и важен. Номер круга даёт
			 *       сценарию способ менять довод от круга к кругу, а результат каждого
			 *       круга обязан накапливаться внутри самого круга: присваивание
			 *       переменной, читаемой только после цикла, компилятор устраняет как
			 *       запись, которую следующий круг всё равно перезапишет
			 *
			 * @param rounds   количество выполняемых операций
			 * @param callback функция выполнения одной операции
			 * @return         итоги прогона сценария
			 *
			 */
			inline outcome_t measure(const size_t rounds, CALLBACK callback) noexcept {
				/**
				 * Выполняем прогрев измеряемой операции
				 */
				for(size_t i = 0; i < URI_WARMUP; i++)
					// Выполняем очередную операцию прогрева
					callback(i);
				// Включаем учёт выделений памяти
				awh::benchmark::counting(true);
				// Включаем учёт системных вызовов
				awh::benchmark::syscall::counting(true);
				// Запоминаем момент начала измерения
				const auto start = std::chrono::steady_clock::now();
				/**
				 * Выполняем измеряемую операцию требуемое количество раз
				 */
				for(size_t i = 0; i < rounds; i++){
					// Выполняем очередную измеряемую операцию
					callback(i);
					/**
					 * Ставим барьер оптимизации между кругами.
					 *
					 * Часть измеряемых методов доводов не принимает вовсе -
					 * извлечение хоста, сборка строки, сравнение, - и от круга к
					 * кругу вызывается с одним и тем же состоянием объекта.
					 * Оптимизирующий компилятор вправе счесть такой вызов не
					 * имеющим побочных действий и вынести его из цикла целиком:
					 * первый замер извлечения доменного имени показал миллиард
					 * операций в секунду, то есть по одной наносекунде на
					 * возвращаемую наружу строку, чего не бывает.
					 *
					 * Барьер обязывает компилятор считать состояние памяти
					 * изменившимся, поэтому вызов, читающий её, остаётся внутри
					 * круга. Машинных команд барьер не порождает: замер он не
					 * удорожает, а лишь запрещает выносить измеряемое из цикла
					 */
					std::atomic_signal_fence(std::memory_order_acq_rel);
				}
				// Запоминаем момент окончания измерения
				const auto finish = std::chrono::steady_clock::now();
				// Закрываем окно замера: счётчики обязаны остановиться там же, где часы
				awh::benchmark::counting(false);
				awh::benchmark::syscall::counting(false);
				// Итоги прогона сценария
				outcome_t result;
				// Устанавливаем количество выполненных операций
				result.operations = rounds;
				// Устанавливаем затраченное время
				result.seconds = std::chrono::duration <double> (finish - start).count();
				// Снимаем показатели окружения по итогам замера
				collect(result);
				// Выводим итоги прогона сценария
				return result;
			}
			/**
			 * @brief Макрос объявления пары сценариев скорости и выделений памяти
			 *
			 * @details Каждая измеряемая операция даёт два показателя: сколько операций
			 *          в секунду и сколько выделений памяти на операцию. Оба снимаются
			 *          с одного и того же прогона, поэтому итоги прогона кэшируются, а
			 *          объявления сценариев выписываются макросом: иначе один и тот же
			 *          текст повторялся бы для каждой измеряемой операции набора
			 *
			 * @param SUFFIX  окончание имён объявляемых функций
			 * @param OUTCOME функция получения итогов прогона сценария
			 *
			 */
			#define AWH_URI_SCENARIO(SUFFIX, OUTCOME)                               \
				static awh::benchmark::result_t speed ## SUFFIX() noexcept {        \
					awh::benchmark::result_t result;                                \
					const outcome_t & outcome = OUTCOME();                          \
					result.value = perSecond(outcome);                              \
					result.details = details(outcome);                              \
					return result;                                                  \
				}                                                                   \
				static awh::benchmark::result_t memory ## SUFFIX() noexcept {       \
					awh::benchmark::result_t result;                                \
					const outcome_t & outcome = OUTCOME();                          \
					result.value = perOperation(outcome);                           \
					result.details = details(outcome);                              \
					return result;                                                  \
				}
		};
	};
};

#endif // __AWH_BENCHMARK_NET_URI__
