#ifndef __AWH_BENCHMARK_NET_ADDR__
#define __AWH_BENCHMARK_NET_ADDR__

/**
 * Стандартные заголовочные файлы
 */
#include <string>
#include <cstddef>
#include <cstdint>

/**
 * Подключаем заголовочные файлы проекта
 */
#include "../io/io.hpp"
#include "../../../include/net/addr.hpp"

/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков модуля работы с адресами
		 *
		 * @details Модуль разбирает и печатает адреса, определяет их принадлежность
		 *          сети и переводит маски в префиксы. Сетевой движок обращается к
		 *          нему на каждом создании события и на каждом принятом подключении,
		 *          поэтому стоимость этих операций входит в показатели движка, но
		 *          отдельно там не видна: замер движка меряет их вперемешку с
		 *          работой цикла событий.
		 *
		 *          Сценарии ниже меряют модуль в отрыве от движка. Показатель у них
		 *          двойной: операций в секунду и выделений памяти на операцию.
		 *          Второй важнее первого - разбор адреса выделять память не обязан
		 *          вовсе, и всякое выделение здесь есть работа, которой можно не
		 *          делать
		 *
		 */
		namespace addr {
			/**
			 * @brief Количество повторений сценариев разбора и печати
			 *
			 * @details Одна операция обходится в сотни наносекунд, и на меньшем
			 *          количестве повторений замер измерял бы разрешение часов
			 *
			 */
			static constexpr size_t ADDR_ROUNDS = 200000;
			/**
			 * @brief Количество повторений сценариев принадлежности сети
			 *
			 */
			static constexpr size_t NETWORK_ROUNDS = 100000;
			/**
			 * @brief Количество повторений прогрева сценариев
			 *
			 * @details Первые обращения к модулю выходят на установившийся режим:
			 *          заполняются накопители реестра локальных сетей, а
			 *          распределитель памяти выходит на рабочий объём
			 *
			 */
			static constexpr size_t ADDR_WARMUP = 10000;

			/**
			 * @brief Структура итогов прогона сценария
			 *
			 * @note Оснастка замера общая с бенчмарками сетевого движка: к вводу-
			 *       выводу она не привязана ничем, снимает выделения памяти,
			 *       обращения к ядру и объём занятой процессом памяти. Заводить ей
			 *       вторую копию значило бы разойтись с ней при первой же правке
			 *
			 */
			typedef io::outcome_t outcome_t;

			/**
			 * @brief Функция формирования сведений о прогоне сценария
			 *
			 */
			using io::details;
			/**
			 * @brief Функция извлечения количества операций в секунду
			 *
			 */
			using io::perSecond;
			/**
			 * @brief Функция извлечения количества выделений памяти на одну операцию
			 *
			 */
			using io::perOperation;
			/**
			 * @brief Функция извлечения количества системных вызовов на одну операцию
			 *
			 */
			using io::perSyscall;
			/**
			 * @brief Функция снятия показателей окружения по итогам замера
			 *
			 */
			using io::collect;
			/**
			 * @brief Функция получения объекта фреймворка сценариев
			 *
			 */
			using io::framework;
			/**
			 * @brief Функция получения объекта логирования сценариев
			 *
			 */
			using io::logger;
		};
	};
};

#endif // __AWH_BENCHMARK_NET_ADDR__
