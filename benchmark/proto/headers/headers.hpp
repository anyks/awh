/**
 * @brief Пространство имён библиотеки
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков контейнера HTTP-заголовков
		 *
		 * @details Контейнер стоит на пути каждого сообщения обоих направлений: поля
		 *          складываются в него при сборке запроса либо ответа и вычитываются
		 *          из него при разборе принятого. Стоимость этих обращений входит
		 *          в стоимость запроса, но в замерах протокола отдельно не видна -
		 *          там она измеряется вперемешку с кадрированием и работой соединения.
		 *
		 *          Сценарии ниже меряют контейнер в отрыве от протокола. Показатель
		 *          у них двойной: операций в секунду и выделений памяти на операцию.
		 *          Второй важнее первого - поиск поля не обязан выделять памяти вовсе,
		 *          а наполнение обязано ровно настолько, насколько этого требуют сами
		 *          хранимые строки. Всё, что сверх того, есть работа, которой можно
		 *          не делать.
		 *
		 * @note Те же сценарии сняты с соперников отдельными стендами в
		 *       tools/benchmark/headers: Boost.Beast и мультикарта стандартной
		 *       библиотеки. Здесь стоят пороги, там - доли от соперника. Порог ловит
		 *       обвал, доля ловит отставание, которое порогу незаметно
		 *
		 */
		namespace headers {
			/**
			 * @brief Количество повторений сценариев наполнения и сборки сообщения
			 *
			 * @details Одна операция обходится в сотни наносекунд, и на меньшем
			 *          количестве повторений замер измерял бы разрешение часов
			 *
			 */
			static constexpr size_t ROUNDS = 200000;
			/**
			 * @brief Количество повторений сценариев поиска и замены
			 *
			 * @details Обе операции на порядок дешевле наполнения: на общем количестве
			 *          повторений показатель определялся бы накладными расходами самого
			 *          цикла замера, а не измеряемой операцией
			 *
			 */
			static constexpr size_t LIGHT_ROUNDS = 1000000;
			/**
			 * @brief Количество повторений прогрева сценариев
			 *
			 * @details Первые обращения выходят на установившийся режим: распределитель
			 *          памяти набирает рабочий объём, а внутренние накопители контейнера -
			 *          ёмкость. Замер с холодного старта мерил бы разгон, а не скорость
			 *
			 */
			static constexpr size_t WARMUP = 10000;
			/**
			 * @brief Количество полей образца
			 *
			 */
			static constexpr size_t FIELDS = 10;

			/**
			 * @brief Функция получения объекта фреймворка сценариев
			 *
			 * @return объект фреймворка сценариев
			 *
			 */
			const fmk_t * framework() noexcept;
			/**
			 * @brief Функция получения объекта логирования сценариев
			 *
			 * @return объект логирования сценариев
			 *
			 */
			const log_t * logger() noexcept;
			/**
			 * @brief Функция получения накопителя итогов работы сценариев
			 *
			 * @details Итог каждой операции накапливается: без этого оптимизатор вправе
			 *          убрать измеряемую работу целиком, и стенд мерил бы пустой цикл
			 *
			 * @return ссылка на накопитель итогов
			 *
			 */
			uint64_t & checksum() noexcept;
			/**
			 * @brief Функция наполнения контейнера полями образца
			 *
			 * @param object наполняемый контейнер заголовков
			 *
			 */
			void fill(http::headers_t & object) noexcept;
			/**
			 * @brief Функция получения названия поля образца
			 *
			 * @param index порядковый номер поля образца
			 * @return      название поля образца
			 *
			 */
			const char * name(const size_t index) noexcept;
			/**
			 * @brief Функция получения значения поля образца
			 *
			 * @param index порядковый номер поля образца
			 * @return      значение поля образца
			 *
			 */
			const char * value(const size_t index) noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK_HTTP_HEADERS__
