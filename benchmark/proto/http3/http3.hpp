#ifndef __AWH_BENCHMARK_HTTP3__
#define __AWH_BENCHMARK_HTTP3__

/**
 * Стандартные заголовочные файлы
 */
#include <string>
#include <vector>
#include <cstddef>
#include <cstdint>

/**
 * Подключаем заголовочные файлы проекта
 */
#include "../../main.hpp"
#include "../../../include/proto/http/parser/http3/http.hpp"

/**
 * @brief основное пространство имён
 *
 */
namespace awh {
	/**
	 * @brief Пространство имён бенчмарков
	 *
	 */
	namespace benchmark {
		/**
		 * @brief Пространство имён бенчмарков протокола HTTP/3
		 *
		 * @details Наборы полей и тело намеренно совпадают с бенчмарками HTTP/2:
		 *          показатели двух протоколов имеет смысл сравнивать только на одной
		 *          и той же нагрузке. Различия при этом остаются существенными:
		 *          QPACK выносит изменения таблицы в отдельный поток, кадры кодируются
		 *          целыми переменной длины, а окон управления потоком у HTTP/3 нет
		 *          вовсе - их ведёт транспорт
		 *
		 */
		namespace http3 {
			/**
			 * @brief Идентификатор управляющего потока клиента (RFC 9000 §2.1)
			 *
			 */
			static constexpr uint64_t CONTROL_STREAM = 2;
			/**
			 * @brief Идентификатор потока инструкций кодера клиента
			 *
			 */
			static constexpr uint64_t ENCODER_STREAM = 6;
			/**
			 * @brief Идентификатор потока инструкций декодера клиента
			 *
			 */
			static constexpr uint64_t DECODER_STREAM = 10;

			/**
			 * @brief Функция получения объекта фреймворка окружения бенчмарка
			 *
			 * @note Объекты окружения создаются при первом обращении: порядок
			 *       статической инициализации между единицами трансляции не
			 *       определён, а фреймворк зависит от таблиц чужих модулей
			 *
			 * @return объект фреймворка
			 *
			 */
			const fmk_t * fmk() noexcept;
			/**
			 * @brief Функция получения объекта логирования окружения бенчмарка
			 *
			 * @return объект логирования
			 *
			 */
			const log_t * log() noexcept;
			/**
			 * @brief Функция получения эталонного набора полей запроса браузера
			 *
			 * @details Набор повторяет запрос настоящего браузера: псевдо-поля,
			 *          длинный user-agent, cookie и переменная часть в виде пути.
			 *          Именно на таком наборе имеет смысл измерять сжатие QPACK -
			 *          на постоянной части выигрыш даёт статическая таблица,
			 *          на повторяющейся переменной динамическая
			 *
			 * @param index номер запроса в последовательности
			 * @return      набор полей запроса
			 *
			 */
			std::vector <awh::http::h3::qpack::field_t> request(const size_t index) noexcept;
			/**
			 * @brief Функция получения эталонного набора полей ответа сервера
			 *
			 * @param index номер ответа в последовательности
			 * @return      набор полей ответа
			 *
			 */
			std::vector <awh::http::h3::qpack::field_t> response(const size_t index) noexcept;
			/**
			 * @brief Функция получения эталонного тела ответа
			 *
			 * @note Объявленная в полях длина обязана совпадать с фактической:
			 *       расхождение - малформированное сообщение (RFC 9114 §4.1.2),
			 *       и парсер справедливо оборвёт поток
			 *
			 * @return тело ответа
			 *
			 */
			const std::string & payload() noexcept;
			/**
			 * @brief Функция подсчёта размера набора полей до сжатия
			 *
			 * @note Считается по сумме длин названий и значений, без надбавки
			 *       в 32 октета на запись: сравнивать сжатую секцию нужно с объёмом
			 *       самих данных, а не с оценкой памяти под них
			 *
			 * @param fields набор полей
			 * @return       размер набора полей в октетах
			 *
			 */
			size_t length(const std::vector <awh::http::h3::qpack::field_t> & fields) noexcept;
			/**
			 * @brief Функция кодирования целого переменной длины QUIC (RFC 9000 §16)
			 *
			 * @param value кодируемое значение
			 * @return      закодированное значение
			 *
			 */
			std::string varint(const uint64_t value) noexcept;
			/**
			 * @brief Функция сборки кадра HTTP/3
			 *
			 * @param type    тип кадра
			 * @param payload полезная нагрузка кадра
			 * @return        собранный кадр
			 *
			 */
			std::string frame(const uint64_t type, const std::string & payload) noexcept;
			/**
			 * @brief Функция сборки инструкции подтверждения секции полей (RFC 9204 §4.4.1)
			 *
			 * @details Без подтверждений кодер не вправе ссылаться на записи динамической
			 *          таблицы: пока декодер не сообщил, что вставку принял, ссылка на неё
			 *          заблокировала бы поток. Кодер честно отказывается от таблицы, как
			 *          только исчерпан лимит блокируемых потоков, и сжатие вырождается
			 *          в статическую таблицу с литералами. Поэтому сценарии, измеряющие
			 *          установившийся режим, обязаны подтверждения выдавать - иначе они
			 *          измеряли бы холостой путь, а не тот, что работает на соединении
			 *
			 * @param sid идентификатор потока, чья секция подтверждается
			 * @return    собранная инструкция потока декодера
			 *
			 */
			std::string acknowledge(const uint64_t sid) noexcept;
			/**
			 * @brief Функция сборки байтов управляющего потока пира
			 *
			 * @details Соединение HTTP/3 начинается не преамбулой, как в HTTP/2, а
			 *          открытием однонаправленных потоков: управляющего и двух потоков
			 *          инструкций QPACK. Первым кадром управляющего потока обязан идти
			 *          SETTINGS (RFC 9114 §6.2.1)
			 *
			 * @return байты управляющего потока: тип потока и кадр SETTINGS
			 *
			 */
			std::string control() noexcept;
		};
	};
};

#endif // __AWH_BENCHMARK_HTTP3__
