/**
 * @brief Проверка заведения захвата выдачи памяти конструктором фреймворка
 *
 * @note Закрепляет решение, а не поведение системы: захват у macOS и MS Windows
 *       выборочен, и приложение, взявшее AWH, получало бы там системный
 *       распределитель, пока не позовёт `capture` вручную. У систем ELF захват
 *       случается самим связыванием, и проверка эта там утверждает то же самое
 *       иным путём
 *
 * @warning Что проверка эта доказать НЕ может: захват в этом двоичном файле уже
 *          заведён общей средой набора (tests/alloc/capture.cpp), и утверждение
 *          `captured()` прошло бы и с пустым конструктором. Она стережёт от обратного -
 *          от того, чтобы заведение фреймворка захват СЛОМАЛО, и от того, чтобы выдача
 *          пошла мимо нас. Решающее доказательство даёт отдельная программа, где
 *          `capture` не зовётся ни разу: до заведения фреймворка `captured()` отвечает
 *          «нет», после - «да» (проверено 22.08.2026)
 *
 */
TEST(FrameworkFixture, ConstructorSeizesAllocator){
	/**
	 * Под санитайзером выдача памяти принадлежит ему, и захват отвечает отказом
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "выдача памяти принадлежит санитайзеру";
	#else
		/**
		 * Со снятым при сборке распределителем захвата нет ни на одной системе
		 */
		#if defined(AWH_ALLOC_DISABLED)
			GTEST_SKIP() << "распределитель снят ключом сборки";
		#else
			// Заводим фреймворк: захват обязан состояться его конструктором
			const awh::Framework fmk;
			// Обращаемся к объекту, чтобы собиратель не счёл его лишним
			static_cast <void> (fmk);
			// Утверждаем состоявшийся захват
			ASSERT_TRUE(awh::alloc::Allocator::captured())
			 << "конструктор фреймворка не завёл распределитель";
			// Берём память средствами языка
			void * block = ::malloc(4096);
			ASSERT_NE(block, nullptr);
			// Утверждаем, что выдача пришла от нас
			const awh::alloc::region_t region = awh::alloc::Allocator::resolve(block);
			ASSERT_NE(region.origin, awh::alloc::origin_t::UNKNOWN)
			 << "выдача памяти прошла мимо распределителя";
			// Возвращаем взятую память
			::free(block);
		#endif
	#endif
}
