/**
 * Подключаем заголовочный файл главного модуля тестов
 */
#include "../main.hpp"
#include <sys/log.hpp>
#include <alloc/alloc.hpp>

/**
 * @brief Метод печати сообщения журнала
 *
 * @note Тело пустое намеренно: стенд собирается без библиотеки, а связывание требует
 *       определения
 *
 * @note Заглушка стоит ПОСЛЕ подключений, а не перед ними: объявление её живёт в
 *       `sys/log.hpp`, и определение без него собиратель читал как новое имя в
 *       пространстве, какого ещё нет вовсе
 *
 */
void awh::log::print(std::string_view, awh::log::flag_t, ...) noexcept {}

/**
 * @brief Главная функция стенда
 *
 * @note Своя, а не общая из `tests/main.cpp`: та заводит ещё и Google Mock, какого у
 *       части систем нет вовсе - у OpenIndiana стоит один Google Test. Набор
 *       распределителя подделок не использует, и требовать их значило бы закрыть себе
 *       стенд без всякой нужды
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char ** argv){
	/**
	 * Выполняем захват выдачи памяти первым делом
	 *
	 * @note Захват обязан идти ДО всякой выдачи и ДО порождения потоков
	 *
	 * @note Зовётся распределитель НАПРЯМУЮ, а не через заведение ядра: заведение это
	 *       живёт в самой библиотеке, а стенд собирается без неё - тем он и стенд
	 */
	awh::alloc::allocator_t::capture(awh::alloc::allocator_t::options());
	// Заводим Google Test
	::testing::InitGoogleTest(&argc, argv);
	// Запускаем все проверки
	return RUN_ALL_TESTS();
}
