/**
 * @brief Тест накопления мест выдачи
 *
 * @note Учёт ведёт ЖИВЫЕ блоки: спроси его после нагрузки, где всё освобождено, он
 *       ответит пустотой - и проверка доложила бы о молчащем учёте там, где учитывать
 *       нечего. Оттого блоки держатся живыми на время опроса
 *
 */
TEST_F(AllocFixture, ProfileCollectsHoldings){
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём учёту мест выдачи долю выборки
	options.profileRate = 64;
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	// Выданные блоки
	std::vector <void *> alive;
	/**
	 * Перебираем блоки нагрузки
	 */
	for(size_t i = 0; i < 4096; i++){
		// Выдаём блок изменчивого размера
		void * block = ::malloc(64 + (i % 4000));
		// Запоминаем выданный блок
		if(block != nullptr)
			// Добавляем блок в список живых
			alive.push_back(block);
	}
	// Число учтённых мест выдачи
	size_t seen = 0;
	// Число мест выдачи со снятым стеком
	size_t deep = 0;
	// Объём учтённого
	size_t bytes = 0;
	// Опрашиваем учёт мест выдачи
	awh::alloc::Allocator::holdings([&seen, &deep, &bytes](const awh::alloc::holding_t & holding) noexcept -> bool {
		// Считаем учтённое место выдачи
		seen++;
		// Копим объём учтённого
		bytes += holding.size;
		// Если стек вызовов снят
		if((holding.frames != nullptr) && (holding.depth > 0))
			// Считаем место выдачи со снятым стеком
			deep++;
		// Продолжаем обход
		return true;
	});
	// Учёт обязан что-то накопить
	EXPECT_GT(seen, static_cast <size_t> (0));
	// Объём учтённого обязан быть ненулевым
	EXPECT_GT(bytes, static_cast <size_t> (0));
	/**
	 * Записи без стека допускаются, но их обязано быть мало
	 *
	 * Раскрутка у части систем сама просит памяти (у OpenBSD это наблюдалось), и
	 * вложенный съём законно отдаёт пустоту: сторож возвратности его обрывает.
	 * Требовать стек у КАЖДОЙ записи значило бы объявить дефектом устройство сторожа
	 */
	EXPECT_GE(deep, ((seen * 9) / 10));
	/**
	 * Перебираем живые блоки
	 */
	for(void * block : alive)
		// Освобождаем блок
		::free(block);
}
/**
 * @brief Тест прекращения обхода мест выдачи
 *
 * @note Обход обязан слушаться отклика: отказ продолжать - способ забрать первые записи,
 *       не платя за обход всего учёта
 *
 */
TEST_F(AllocFixture, HoldingsWalkStopsOnRequest){
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём учёту мест выдачи долю выборки
	options.profileRate = 1;
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	// Выданные блоки
	std::vector <void *> alive;
	/**
	 * Перебираем блоки нагрузки
	 */
	for(size_t i = 0; i < 256; i++){
		// Выдаём блок
		void * block = ::malloc(1024);
		// Запоминаем выданный блок
		if(block != nullptr)
			// Добавляем блок в список живых
			alive.push_back(block);
	}
	// Число обойдённых мест выдачи
	size_t seen = 0;
	// Опрашиваем учёт, прекращая обход на первой же записи
	awh::alloc::Allocator::holdings([&seen](const awh::alloc::holding_t &) noexcept -> bool {
		// Считаем обойдённое место выдачи
		seen++;
		// Прекращаем обход
		return false;
	});
	/**
	 * Обойдено обязано быть РОВНО одно место, а не «не больше одного»
	 *
	 * Порог «не больше» проходит и при нуле, то есть при учёте, не удержавшем ни одной
	 * записи вовсе, - а тогда прекращать было нечего, и проверка ничего не утверждает.
	 * Равенство же требует и того и другого разом: запись была, и обход прекратился на
	 * ней, не пойдя дальше
	 */
	// Обход обязан прекратиться на первой записи, а не пройти учёт целиком
	EXPECT_EQ(seen, static_cast <size_t> (1));
	/**
	 * Перебираем живые блоки
	 */
	for(void * block : alive)
		// Освобождаем блок
		::free(block);
}

/**
 * @brief Тест съёма стека при ключах с большими номерами
 *
 * @details Заводит ключи, съедающие первый уровень места под значения, и лишь затем
 *          включает учёт мест выдачи: ключ съёма достаётся тогда номер большой. У
 *          glibc первая отметка такого ключа заводит второй уровень ВЫЗОВОМ `calloc`,
 *          а тот приходит обратно в нашу выдачу - и если признак нахождения внутри
 *          съёма хранится тем же ключом, отметка не поспевает лечь, поток отмечается
 *          снова и срывает стек
 *
 * @note Проверка эта закрепляет НАМЕРЕННОЕ решение: признак хранится средствами
 *       собирателя всюду, где обращение к месту потока памяти не просит, и ключом
 *       системы лишь у macOS и OpenBSD, где просит наоборот. Прежний код валился здесь
 *       в SIGSEGV на Debian, glibc 2.36
 *
 */
/**
 * @brief Тест обращения адреса в имя
 *
 * @details Обращение это - половина пользы от учёта мест выдачи: без имён приложение
 *          получает столбец адресов, а не место, откуда пришёл запрос
 *
 * @note Проверка мерялась покрытием: `Allocator::symbol` и `Trace::resolve` не звались
 *       набором НИ РАЗУ. Сам учёт мест выдачи поверялся, а обращение адреса в имя -
 *       нет, хотя оно выставлено наружу и приложение зовёт именно его
 *
 * @warning Имена спрашиваются у средств связывания, и полнота их зависит от сборки:
 *          у статической программы да со снятой таблицей имён отвечать нечем. Оттого
 *          отсутствие имени здесь НЕ отказ - утверждается лишь то, что разбор не лжёт:
 *          ответил успехом - обязан отдать хоть что-то, отвечать пустотой при успехе
 *          нельзя
 *
 */
TEST_F(AllocFixture, SymbolResolutionIsHonest){
	// Сведения об адресе стека вызовов
	awh::alloc::symbol_t symbol;
	/**
	 * Разбираем адрес заведомо известной функции
	 *
	 * Берём выдачу памяти: она лежит в нашем же образе и заведомо не выброшена
	 * собирателем - её зовёт весь набор
	 */
	// Определяем адрес разбираемой функции
	void * frame = reinterpret_cast <void *> (&::malloc);
	// Разбираем адрес обращения
	const bool resolved = awh::alloc::Allocator::symbol(frame, symbol);
	// Если разбор состоялся
	if(resolved){
		/**
		 * Успех обязан нести хоть одно имя
		 *
		 * Разбор, ответивший успехом и не отдавший ни имени образа, ни имени функции,
		 * лжёт: звавший решит по ответу, что имя есть, и напечатает пустоту
		 */
		EXPECT_TRUE((symbol.image != nullptr) || (symbol.name != nullptr))
		 << "разбор ответил успехом, не отдав ни имени образа, ни имени функции";
		// Если начало функции определено
		if(symbol.begin != nullptr)
			// Смещение обязано быть неотрицательным: адрес лежит ЗА началом функции
			EXPECT_GE(symbol.offset, static_cast <ptrdiff_t> (0));
	// Если разбор не состоялся
	} else {
		/**
		 * Отказ обязан оставить сведения пустыми
		 *
		 * Заполненные наполовину сведения при отказе хуже отказа: звавший, не глядящий
		 * на ответ метода, напечатал бы мусор
		 */
		EXPECT_EQ(symbol.image, nullptr);
		// Имя функции обязано остаться пустым
		EXPECT_EQ(symbol.name, nullptr);
	}
	/**
	 * Заведомо негодный адрес обязан отвечать отказом
	 *
	 * Разбор зовётся из разбора сбоя, куда адрес приходит какой угодно
	 */
	// Сведения о негодном адресе
	awh::alloc::symbol_t nothing;
	// Разбираем заведомо негодный адрес
	EXPECT_FALSE(awh::alloc::Allocator::symbol(reinterpret_cast <const void *> (0x20), nothing));
}

TEST_F(AllocFixture, TraceSurvivesHighNumberedKeys){
	// Ключи, съедающие первый уровень места под значения
	pthread_key_t eaten[64];
	/**
	 * Перебираем заводимые ключи
	 */
	for(size_t i = 0; i < 64; i++)
		// Заводим ключ, съедающий место
		ASSERT_EQ(::pthread_key_create(&eaten[i], nullptr), 0) << "ключ " << i << " не заведён";
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём учёту мест выдачи долю выборки
	options.profileRate = 1;
	// Применяем настройки: ключ съёма заведётся ПОСЛЕ съеденных
	awh::alloc::Allocator::options(options);
	// Признак прохождения нагрузки свежим потоком
	std::atomic <bool> passed(false);
	/**
	 * Гоняем нагрузку СВЕЖИМ потоком: отметка съёма ставится там впервые
	 */
	std::thread worker([&passed]() noexcept -> void {
		/**
		 * Перебираем блоки нагрузки
		 */
		for(size_t i = 0; i < 4096; i++){
			// Выдаём блок
			void * block = ::malloc(64 + (i % 512));
			// Если блок выдан
			if(block != nullptr)
				// Освобождаем блок
				::free(block);
		}
		// Отмечаем нагрузку пройденной
		passed.store(true, std::memory_order_release);
	});
	// Дожидаемся потока нагрузки
	worker.join();
	// Нагрузка обязана пройти целиком, а не сорвать стек
	EXPECT_TRUE(passed.load(std::memory_order_acquire));
	// Выключаем учёт мест выдачи
	options.profileRate = 0;
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	/**
	 * Перебираем заведённые ключи
	 */
	for(size_t i = 0; i < 64; i++)
		// Снимаем ключ, съедавший место
		::pthread_key_delete(eaten[i]);
}

/**
 * @brief Проверка повторного учёта того же адреса
 *
 * @details Освобождение вправе пройти МИМО снятия блока с учёта: возможности выключены
 *          между выдачей и освобождением, а после включены снова - ровно так работает
 *          образец, меряющий рычаги по очереди. Адрес при этом достаётся новой выдаче, и
 *          учёт получает его вторично. Прежняя запись обязана уступить место свежей
 *
 * @note Прежде внесение в таблицу отвечало на это УСПЕХОМ, ничего не внося: запись
 *       оставалась старая, со старым размером и старым стеком, а свежая - выданная под
 *       неё память - терялась насовсем. Счётчики же росли, будто внесение состоялось.
 *       Щупом отмерено: живых числилось ДВА при одном блоке, октетов 384 при блоке в
 *       256, а после снятия с учёта счёт застревал на единице и 256 октетах НАВСЕГДА
 *
 * @note Смещение это накапливается, и дойди счёт живых до предела - учёт перестал бы
 *       принимать что-либо вовсе, и опять молча. Оттого проверка сличает счёт и ПОСЛЕ
 *       снятия: одно лишь сличение после повторного учёта пропустило бы застревание
 *
 * @note Слой берётся отдельным, а не тот, что стоит в распределителе процесса: учёт там
 *       ведётся по настоящим выдачам соседних проверок, и счёт живых блоков не был бы
 *       нашим. Адреса здесь вымышленные - слой памяти по ним не читает, а ведёт запись
 *
 */
TEST(AllocProfileTest, RepeatedEnrollmentReplacesRecord){
	// Источник страниц системы
	awh::alloc::SystemSource system;
	// Съём стека вызовов, без какого учёт не заводится
	awh::alloc::trace_t trace;
	// Слой обмера под проверку
	awh::alloc::profile_t profile;
	// Заводим слой обмера
	ASSERT_TRUE(profile.init(&system, &trace));
	// Вымышленный, но правдоподобный адрес блока
	const void * block = reinterpret_cast <const void *> (static_cast <uintptr_t> (0x40000));
	// Ставим блок на учёт
	ASSERT_TRUE(profile.enroll(block, 128, 1, 0)) << "первый учёт отвергнут";
	// Живым обязан числиться один блок
	ASSERT_EQ(profile.state().live, static_cast <size_t> (1));
	// Объём обязан равняться размеру блока
	ASSERT_EQ(profile.state().bytes, static_cast <size_t> (128));
	// Ставим ТОТ ЖЕ адрес на учёт вторично, не снимая прежнего
	EXPECT_TRUE(profile.enroll(block, 256, 2, 0)) << "повторный учёт отвергнут";
	// Живым по-прежнему обязан числиться ОДИН блок: адрес-то один
	EXPECT_EQ(profile.state().live, static_cast <size_t> (1))
	 << "учёт удвоил один блок: живых " << profile.state().live;
	// Объём обязан равняться НОВОМУ размеру, а не сумме двух
	EXPECT_EQ(profile.state().bytes, static_cast <size_t> (256))
	 << "учёт сложил старый размер с новым: " << profile.state().bytes << " окт.";
	// Снимаем блок с учёта
	EXPECT_TRUE(profile.expel(block)) << "блок под учётом не найден";
	/**
	 * После снятия учёт обязан быть ПУСТ
	 *
	 * Сличение это и ловит застревание: удвоенный счёт снятие уменьшает лишь на единицу,
	 * и остаток лежит в учёте до конца работы
	 */
	EXPECT_EQ(profile.state().live, static_cast <size_t> (0))
	 << "после снятия в учёте осталось живых: " << profile.state().live;
	// Объёма после снятия остаться не должно
	EXPECT_EQ(profile.state().bytes, static_cast <size_t> (0))
	 << "после снятия в учёте осталось октетов: " << profile.state().bytes;
	// Повторное снятие обязано отвечать отказом: блок уже снят
	EXPECT_FALSE(profile.expel(block)) << "учёт снял с учёта уже снятый блок";
	// Снимаем слой обмера
	profile.reset();
}

/**
 * @brief Тест взятия выровненной выдачи под учёт места выдачи
 *
 * @note Выравнивающая выдача расходится по трём ветвям: разряды, страничная куча и слой
 *       крупных выдач. Учёт мест выдачи обязан брать блок у ВСЕХ трёх - иначе блок,
 *       выданный одной из них, пропадает для обхода `holdings` молча, и течь памяти
 *       через выровненные выдачи искать было бы нечем
 *
 */
TEST_F(AllocFixture, AlignedAllocationEntersProfile){
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём учёту мест выдачи долю выборки
	options.profileRate = 1;
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	// Блок, выданный страничной кучей: выравнивание в страницу кучи при малом размере
	void * paged = nullptr;
	// Блок, выданный слоем крупных выдач: выравнивание сверх страницы кучи
	void * enormous = nullptr;
	/**
	 * Величины выравнивания взяты числами, а не от `Pages::PAGE`
	 *
	 * Слой страниц наружу не выставлен, а проверке довольно того, что 8192 - это ровно
	 * страница кучи, а 65536 - заведомо больше неё
	 */
	/**
	 * Способ выровненной выдачи берётся свой на систему
	 *
	 * `posix_memalign` у MinGW не объявлен вовсе - набор проверок там НЕ СОБИРАЛСЯ, -
	 * а родной способ MSVCRT зовётся `_aligned_malloc`, и порядок доводов у него
	 * обратный: размер первым, выравнивание вторым
	 */
	#if defined(_WIN32) || defined(_WIN64)
		// Выдаём блок с выравниванием в страницу кучи
		paged = ::_aligned_malloc(64, 8192u);
		// Выдача обязана удаться
		ASSERT_NE(paged, nullptr);
		// Выдаём блок с выравниванием сверх страницы кучи
		enormous = ::_aligned_malloc(64, 65536u);
		// Выдача обязана удаться
		ASSERT_NE(enormous, nullptr);
		/**
		 * Разбираем, выдан ли блок НАШИМ откликом
		 *
		 * Выровненная семья перехватывается не у всякой библиотеки времени исполнения:
		 * у `msvcrt.dll` на x86-64 вход `_aligned_malloc` - это три октета да
		 * ОТНОСИТЕЛЬНЫЙ переход, а такой перенести в мостик нельзя, не пересчитав
		 * смещение; у `ucrtbase.dll` на ARM64 входы начинаются настоящими командами
		 * (`pacibsp`, `cbz x0`), а не горячей заплаткой Microsoft. В обоих случаях
		 * семья законно не берётся
		 *
		 * Признак берётся НАЧАЛО блока, а не принадлежность: не встань наш отклик,
		 * `_aligned_malloc` библиотеки зовёт наш же перехваченный `malloc` и сам
		 * выравнивает внутри выданного - блок оттого числится нашим и ЖИВЫМ, но
		 * выданный адрес приходится СЕРЕДИНОЙ нашего блока, а учёт хранит его начало.
		 * Спроси мы принадлежность - проверка падала бы там, где всё верно; измерено
		 * щупом: `_aligned_malloc(64, 8192)` отдавал адрес со смещением 0x2000 внутри
		 * блока на 9216 октетов
		 *
		 * Молчаливого пропуска здесь нет: встань наш отклик - начало совпадёт с
		 * выданным адресом, и проверка дойдёт до утверждений об учёте
		 */
		if(awh::alloc::Allocator::resolve(paged).begin != paged){
			// Освобождаем выданное прежним распределителем
			::_aligned_free(paged);
			// Освобождаем выданное прежним распределителем
			::_aligned_free(enormous);
			// Проверять нечего: семья не перехвачена
			GTEST_SKIP() << "выровненная семья библиотекой времени исполнения к подмене не отдана: "
			 << "выдачу ведёт она сама поверх нашего `malloc`";
		}
	#else
		// Выдаём блок с выравниванием в страницу кучи
		ASSERT_EQ(::posix_memalign(&paged, 8192u, 64), 0);
		// Выдаём блок с выравниванием сверх страницы кучи
		ASSERT_EQ(::posix_memalign(&enormous, 65536u, 64), 0);
	#endif
	// Признаки найденных под учётом блоков
	bool seenPaged = false, seenEnormous = false;
	// Опрашиваем учёт мест выдачи
	awh::alloc::Allocator::holdings([&](const awh::alloc::holding_t & holding) noexcept -> bool {
		// Отмечаем найденный блок страничной кучи
		if(holding.block == paged)
			// Блок страничной кучи под учётом
			seenPaged = true;
		// Отмечаем найденный блок крупной выдачи
		if(holding.block == enormous)
			// Блок крупной выдачи под учётом
			seenEnormous = true;
		// Продолжаем обход
		return true;
	});
	/**
	 * Утверждаем ОБА блока, а не один
	 *
	 * Ветвь крупных выдач блок под учёт брала и прежде, и утверждение её здесь -
	 * доказательство того, что учёт вообще жив и выборка взведена: не будь его, отказ
	 * по страничной ветви был бы неотличим от выключенного учёта
	 */
	// Блок крупной выдачи обязан быть под учётом
	EXPECT_TRUE(seenEnormous) << "учёт не взял блок, выданный слоем крупных выдач";
	// Блок страничной кучи обязан быть под учётом
	EXPECT_TRUE(seenPaged) << "учёт не взял блок, выданный страничной кучей";
	/**
	 * Освобождаем тем же путём, каким выдавали
	 *
	 * Блок `_aligned_malloc` обязан уходить в `_aligned_free`: у MSVCRT пути эти
	 * разные, и обычное освобождение его не берёт
	 */
	#if defined(_WIN32) || defined(_WIN64)
		// Освобождаем блок страничной кучи
		::_aligned_free(paged);
		// Освобождаем блок крупной выдачи
		::_aligned_free(enormous);
	#else
		// Освобождаем блок страничной кучи
		::free(paged);
		// Освобождаем блок крупной выдачи
		::free(enormous);
	#endif
}

/**
 * @brief Тест повторного заведения и снятия съёма стека вызовов
 *
 * @note Проверка сторожит повторный вход в заведение, съём стека и снятие готовности -
 *       и НИЧЕГО не говорит о гонке двух потоков за ключ признака: ту она поймать не
 *       может вовсе. Проверено изъяном: путь проигравшего неделимую подмену обращён в
 *       отказ, а проверка прошла - в один поток до него не доходит, ибо повторное
 *       заведение выходит раньше, по признаку прогретости. Гонка эта закрыта устройством
 *       и записана в `include/alloc/README.md` как незакрытая проверкой
 *
 */
TEST(AllocProfileTest, RepeatedTraceArmingKeepsCaptureWorking){
	// Съём стека вызовов под проверку
	awh::alloc::trace_t trace;
	// Заводим съём впервые
	ASSERT_TRUE(trace.init()) << "съём не завёлся";
	// Съём обязан числиться готовым
	ASSERT_TRUE(trace.ready()) << "съём завёлся, но готовым не числится";
	// Массив под адреса стека вызовов
	const void * frames[16];
	// Обнуляем массив под адреса
	::memset(frames, 0, sizeof(frames));
	// Снимаем стек вызовов
	const size_t before = trace.capture(frames, 16, 0);
	// Стек обязан сниматься
	ASSERT_GT(before, static_cast <size_t> (0)) << "съём не снял ни одного уровня";
	/**
	 * Заводим съём ещё трижды
	 *
	 * Повторный вход обязан отвечать успехом и ничего не портить
	 */
	for(size_t i = 0; i < 3; i++)
		// Заводим съём повторно
		EXPECT_TRUE(trace.init()) << "повторное заведение съёма ответило отказом";
	// Обнуляем массив под адреса
	::memset(frames, 0, sizeof(frames));
	// Снимаем стек вызовов после повторных заведений
	const size_t after = trace.capture(frames, 16, 0);
	// Стек обязан сниматься по-прежнему
	EXPECT_GT(after, static_cast <size_t> (0)) << "после повторного заведения съём перестал снимать";
	/**
	 * Разбор адреса обязан работать после повторных заведений
	 *
	 * Он же и единственный путь, каким название образа читает прикладной код
	 */
	// Сведения о разобранном адресе
	awh::alloc::symbol_t symbol;
	// Разбираем ближний уровень стека
	if(trace.resolve(frames[0], symbol))
		// Название образа обязано быть завершённой строкой
		EXPECT_NE(symbol.image, nullptr) << "разбор удался, а названия образа нет";
	// Снимаем съём стека вызовов
	trace.reset();
	// После снятия съём готовым числиться не должен
	EXPECT_FALSE(trace.ready()) << "снятый съём числится готовым";
}

/**
 * @brief Тест возвратного обращения к учёту из отклика перебора
 *
 * @note Перебор мест выдачи затевается ради ПОИСКА ТЕЧИ, то есть ради доклада, а всякий
 *       доклад просит памяти: сложение строки, разбор искажённого имени, дописывание в
 *       список. Выдача же памяти при взведённой выборке идёт во внесение записи - к тому
 *       самому учёту, какой сейчас перебирается. Держи перебор замок, поток встал бы
 *       намертво на своём же замке
 *
 * @note Отказ здесь выглядел бы ЗАВИСАНИЕМ, а зависание от отказа неотличимо. Оттого
 *       перебор идёт отдельным потоком, а проверка ждёт его сроком и утверждает
 *       завершённость: так дефект валит проверку, а не набор
 *
 */
TEST(AllocProfileTest, WalkCallbackMayEnterProfileAgain){
	// Источник страниц системы
	awh::alloc::SystemSource system;
	// Съём стека вызовов, без какого учёт не заводится
	awh::alloc::trace_t trace;
	// Учёт мест выдачи под проверку
	awh::alloc::profile_t profile;
	// Заводим учёт мест выдачи
	ASSERT_TRUE(profile.init(&system, &trace));
	// Берём под учёт каждую выдачу
	profile.rate(1);
	// Поле, с какого берутся учитываемые блоки
	std::vector <uint8_t> field(64u * 1024u, 0);
	/**
	 * Вносим под учёт несколько блоков
	 */
	for(size_t i = 0; i < 8; i++)
		// Вносим очередной блок под учёт
		ASSERT_TRUE(profile.enroll((field.data() + (i * 1024u)), 1024u, 0, 0));
	// Признак завершённого перебора
	std::atomic <bool> finished(false);
	// Число блоков, внесённых из отклика
	std::atomic <size_t> added(0);
	/**
	 * Перебираем учёт отдельным потоком
	 *
	 * Поток намеренно отвязывается: зависни он на дефекте - проверка обязана упасть по
	 * сроку, а не ждать его вечно вместе с ним
	 */
	std::thread walker([&profile, &field, &finished, &added](){
		// Предмет, отдаваемый отклику перебора
		struct context_t {
			// Учёт мест выдачи
			awh::alloc::profile_t * profile;
			// Поле, с какого берутся вносимые блоки
			std::vector <uint8_t> * field;
			// Число блоков, внесённых из отклика
			std::atomic <size_t> * added;
		} context = {&profile, &field, &added};
		// Перебираем учёт, обращаясь к нему же из отклика
		profile.walk([](const awh::alloc::holding_t &, void * arg) noexcept -> bool {
			// Получаем предмет перебора
			context_t * context = reinterpret_cast <context_t *> (arg);
			/**
			 * Обращаемся к тому же учёту ИЗНУТРИ отклика
			 *
			 * Ровно это и делает всякая выдача памяти, случившаяся в отклике: доклад
			 * просит памяти, а выдача идёт во внесение записи
			 */
			const size_t number = context->added->fetch_add(1);
			// Вносим под учёт очередной блок из второй половины поля
			static_cast <void> (context->profile->enroll((context->field->data() + (32u * 1024u) + (number * 1024u)), 1024u, 0, 0));
			// Продолжаем обход
			return true;
		}, &context);
		// Отмечаем перебор завершённым
		finished.store(true);
	});
	// Отвязываем поток перебора
	walker.detach();
	/**
	 * Ждём завершения перебора сроком
	 */
	for(size_t i = 0; (i < 200) && !finished.load(); i++)
		// Ждём завершения перебора
		std::this_thread::sleep_for(std::chrono::milliseconds(10));
	// Перебор обязан завершиться, а не встать на своём же замке
	ASSERT_TRUE(finished.load()) << "перебор мест выдачи встал: отклик обратился к учёту и не вернулся";
	// Из отклика обязано быть внесено хоть что-то, иначе возвратности не было вовсе
	EXPECT_GT(added.load(), static_cast <size_t> (0)) << "отклик не обратился к учёту ни разу";
	// Снимаем учёт мест выдачи
	profile.reset();
	// Снимаем съём стека вызовов
	trace.reset();
}

