/**
 * @brief Тест выдачи с требуемым выравниванием
 *
 */
TEST(AllocContractTest, AlignedAllocationIsAligned){
	/**
	 * Выдаём память с выравниванием средствами ЯЗЫКА, а не POSIX
	 *
	 * `posix_memalign` есть не везде: у MinGW его нет вовсе, и проверка, написанная на
	 * нём, закрывала себе Windows целиком. Выровненная выдача языка ведёт к тому же
	 * нашему пути, но пишется одинаково для всех систем
	 */
	void * block = ::operator new (8192, std::align_val_t(4096));
	ASSERT_NE(block, nullptr);
	// Выравнивание обязано быть соблюдено
	EXPECT_EQ((reinterpret_cast <uintptr_t> (block) % 4096), static_cast <uintptr_t> (0));
	// Блок обязан быть пригоден к записи целиком
	::memset(block, 0x77, 8192);
	EXPECT_EQ(reinterpret_cast <const uint8_t *> (block)[8191], static_cast <uint8_t> (0x77));
	// Освобождаем выданное
	::operator delete (block, std::align_val_t(4096));
	/**
	 * Негодное выравнивание обязано быть отвергнуто кодом, а не падением
	 *
	 * Проверяется лишь у систем POSIX: у MinGW `posix_memalign` нет вовсе. Под
	 * санитайзером край не проверяется и там: он валит процесс на негодном
	 * выравнивании сам, по своей политике
	 */
	#if !defined(_WIN32) && !defined(_WIN64) && !AWH_ALLOC_SANITIZED
		void * refused = nullptr;
		EXPECT_NE(::posix_memalign(&refused, 3, 128), 0);
	#endif
}
/**
 * @brief Тест разбора выданного адреса
 *
 */
TEST(AllocContractTest, ResolveKnowsOwnBlocks){
	// Выдаём память
	void * block = ::malloc(1000);
	ASSERT_NE(block, nullptr);
	/**
	 * Разбор своего блока обязан дать размер не меньше запрошенного
	 *
	 * Под санитайзером всё наоборот: выдача идёт мимо нас, и разбор обязан отвечать
	 * нулём - иначе распределитель врёт о принадлежности чужой памяти
	 */
	#if AWH_ALLOC_SANITIZED
		EXPECT_EQ(awh::alloc::Allocator::resolve(block).size, static_cast <size_t> (0));
	#else
		EXPECT_GE(awh::alloc::Allocator::resolve(block).size, static_cast <size_t> (1000));
	#endif
	// Освобождаем выданное
	::free(block);
	// Место на стеке распределителю не принадлежит
	const uint64_t anchor = 0;
	EXPECT_EQ(awh::alloc::Allocator::resolve(&anchor).size, static_cast <size_t> (0));
	// Пустой указатель разбирается нулём
	EXPECT_EQ(awh::alloc::Allocator::resolve(nullptr).size, static_cast <size_t> (0));
}
/**
 * @brief Тест сплошного покрытия размеров разрядами
 *
 * @details Проходит ВСЕ размеры до порога разрядов подряд и сверяет три обещания:
 *          выданный блок вмещает запрошенное, потеря на округлении держится в
 *          обещанных пределах, а размер выдачи с ростом запроса не убывает
 *
 * @note Проверка сплошная намеренно. Таблицы разрядов строятся расчётом, и все три
 *       правки их истории - провал между последним мелким разрядом и первым крупным,
 *       разряд не кратный шагу таблицы и перескок порога - были дырами в ОТДЕЛЬНЫХ
 *       размерах, каких выборка не увидела бы вовсе
 *
 */
TEST(AllocContractTest, EverySizeIsServedByAClass){
	/**
	 * Под санитайзером проверять здесь нечего
	 *
	 * Захват там не состоится, выдача идёт мимо наших разрядов, и разбор адреса
	 * отвечает нулём о всяком блоке: сверять было бы нечего с чем
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "захват под санитайзером не состоится";
	#endif
	// Наибольший размер, обслуживаемый разрядами
	const size_t maximum = (32u * 1024u);
	// Размер выдачи на предыдущем шаге
	size_t previous = 0;
	// Наибольшая замеченная потеря на округлении в сотых долях
	size_t worst = 0;
	// Размер, на котором замечена наибольшая потеря
	size_t culprit = 0;
	/**
	 * Перебираем все размеры до порога разрядов
	 */
	for(size_t size = 1; size <= maximum; size++){
		// Выдаём блок требуемого размера
		void * block = ::malloc(size);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr) << "выдача отказала на размере " << size;
		// Определяем размер выданного блока
		const size_t served = awh::alloc::Allocator::resolve(block).size;
		// Выданный блок обязан вмещать запрошенное
		ASSERT_GE(served, size) << "блок мельче запроса на размере " << size;
		/**
		 * Размер выдачи обязан не убывать с ростом запроса
		 *
		 * Убывание означало бы, что таблица поиска отвечает разрядом, который мельче
		 * отвеченного на меньший запрос, - то есть перескок разряда
		 */
		ASSERT_GE(served, previous) << "размер выдачи убыл на размере " << size;
		// Запоминаем размер выдачи
		previous = served;
		/**
		 * Считаем потерю лишь у запросов от ста двадцати восьми байт
		 *
		 * Обещание в восьмую долю дано ШАГОМ разрядов, а у самых мелких запросов сверх
		 * него действует выравнивание в шестнадцать байт: запрос в один байт получает
		 * блок в шестнадцать и теряет 94 %, ничего о шаге не говоря. Сверять предел на
		 * таких запросах значило бы сверять его с числом, к устройству отношения не
		 * имеющим
		 */
		if(size < 128)
			// Потерю на мелочи не считаем
			continue;
		// Определяем потерю на округлении в сотых долях
		const size_t waste = (((served - size) * 100u) / served);
		// Если потеря оказалась наибольшей
		if(waste > worst){
			// Запоминаем наибольшую потерю
			worst = waste;
			// Запоминаем размер, на котором она замечена
			culprit = size;
		}
		// Освобождаем блок
		::free(block);
	}
	/**
	 * Потеря на округлении обязана держаться в обещанной восьмой доле
	 *
	 * Шаг разрядов берётся восьмой долей размера, что даёт 12,5 %. Предел здесь стоит
	 * ЖЁСТКИЙ намеренно: просторный предел прошёл бы и при развалившихся таблицах, а
	 * ради этого обещания разряды и строятся расчётом
	 */
	EXPECT_LE(worst, static_cast <size_t> (13)) << "наибольшая потеря на размере " << culprit;
}

/**
 * @brief Тест действия настройки границы разрядов
 *
 * @details Граница разрядов - размен, и обе его стороны отмерены у `Classes::DEFAULT`:
 *          выше границы блок обслуживается областью страниц, умеющей расти на месте,
 *          ниже - разрядом с кэшем потока, растить какой нельзя. Оттого граница задаётся
 *          приложением, а не выбирается за него навсегда
 *
 * @note Закрепляет ДЕЙСТВИЕ настройки, а не скорость: сличать наносекунды в проверке
 *       нельзя - они зависят от занятости машины. Сличается опознание блока: блок выше
 *       границы распределитель числит областью, ниже - блоком разряда, и говорит это
 *       разбором адреса
 *
 */
TEST(ClassLimitFixture, ClassBoundaryIsConfigurable){
	/**
	 * Под санитайзером захвата нет, а без захвата проверять нечего
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "захват под санитайзером не состоится";
	#else
		// Разряды размеров
		awh::alloc::classes_t classes;
		// Строим разряды по умолчанию
		ASSERT_GT(classes.init(), static_cast <size_t> (0));
		// Граница по умолчанию обязана быть заявленной
		EXPECT_EQ(classes.maximum(), awh::alloc::Classes::DEFAULT);
		// Размер сверх границы разрядами не обслуживается
		EXPECT_GE(classes.index(awh::alloc::Classes::DEFAULT + 1), classes.count())
		 << "размер сверх границы получил разряд";
		// Размер по границе разрядами обслуживается
		EXPECT_LT(classes.index(awh::alloc::Classes::DEFAULT), classes.count())
		 << "размер по границе разряда не получил";
		/**
		 * Строим разряды с поднятой границей
		 */
		{
			// Разряды с поднятой границей
			awh::alloc::classes_t raised;
			// Строим разряды до ёмкости таблиц поиска
			ASSERT_GT(raised.init(awh::alloc::Classes::MAXIMUM), static_cast <size_t> (0));
			// Поднятая граница обязана действовать
			EXPECT_EQ(raised.maximum(), awh::alloc::Classes::MAXIMUM);
			/**
			 * Размер, бывший сверх границы, обязан получить разряд
			 *
			 * Вот это и есть доказываемое: та же величина при разных настройках уходит
			 * разными путями
			 */
			EXPECT_LT(raised.index(awh::alloc::Classes::DEFAULT + 1), raised.count())
			 << "поднятая граница не подействовала";
		}
		/**
		 * Граница выше ёмкости таблиц поиска обязана быть опущена до неё
		 *
		 * Иначе поиск читал бы за концом массива - и читал бы мусор, а не отказывал
		 */
		{
			// Разряды с непомерной границей
			awh::alloc::classes_t excess;
			// Строим разряды с границей вдесятеро выше ёмкости
			ASSERT_GT(excess.init(awh::alloc::Classes::MAXIMUM * 10u), static_cast <size_t> (0));
			// Граница обязана быть опущена до ёмкости таблиц
			EXPECT_EQ(excess.maximum(), awh::alloc::Classes::MAXIMUM)
			 << "непомерная граница не опущена до ёмкости таблиц поиска";
		}
	#endif
}

/**
 * @brief Тест согласия прямого чтения места потока с чтением ключа
 *
 * @details Быстрый путь у macOS читает место потока НАПРЯМУЮ, минуя вызов: чтение ключа
 *          вызовом стоит 1.502 наносекунды против 0.351 у прямого обращения, а дороже
 *          самой разницы обходится вызов как таковой - живые значения приходится держать
 *          в сохраняемых регистрах
 *
 * @details Устройство места потока у macOS договором НЕ объявлено: ни то, что значения
 *          ключей лежат в нём по своим номерам, ни то, что основание берётся из
 *          `tpidrro_el0`. Оттого прямой путь заводится лишь по опыту - метка кладётся
 *          обычным средством и читается прямым обращением. Проверка эта стережёт то же
 *          самое, но уже под нагрузкой набора: устройство могло совпасть на пустом
 *          потоке и разойтись на рабочем
 *
 */
TEST(ContractFixture, DirectSlotAgreesWithKey){
	/**
	 * Прямого чтения нет ни у одной системы, кроме macOS
	 */
	#if !defined(AWH_ALLOC_TSD) || AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "прямого чтения места потока у этой сборки нет";
	#else
		// Читаем номер места потока для прямого чтения
		const size_t slot = awh::alloc::__awh_alloc_direct__.load(std::memory_order_relaxed);
		// Если прямое чтение не заведено
		if(slot == awh::alloc::AWH_ALLOC_NOSLOT)
			// Проверять нечего: сторож не пустил, и это законный исход
			GTEST_SKIP() << "прямое чтение не заведено: устройство места потока не сошлось";
		// Получаем основание места потока
		void ** slots = awh::alloc::__awh_alloc_slots__();
		// Основание обязано быть получено: иначе прямое чтение не завелось бы
		ASSERT_NE(slots, nullptr);
		/**
		 * Сличаем оба чтения на РАБОТАЮЩЕМ потоке
		 *
		 * Заведение кэша уже случилось - набор к этому времени выдал памяти вдоволь, - и
		 * место потока заполнено настоящим значением, а не меткой проверки
		 */
		// Читаем значение ключа обычным средством
		void * const byKey = ::pthread_getspecific(awh::alloc::__awh_alloc_tsd__);
		// Читаем значение места потока прямым обращением
		void * const direct = slots[slot];
		// Оба чтения обязаны дать одно и то же
		EXPECT_EQ(direct, byKey)
		 << "прямое чтение места потока разошлось с чтением ключа: " << direct << " против " << byKey;
		/**
		 * Сличаем ещё раз, поставив своё значение
		 *
		 * Совпадение на готовом значении могло быть случайным: место могло оказаться
		 * пустым у обоих чтений. Ставим метку и сличаем снова
		 */
		{
			// Значение ключа, какое было до проверки
			void * const kept = byKey;
			// Метка, по какой сличаются чтения
			void * const mark = reinterpret_cast <void *> (static_cast <uintptr_t> (0x7E57C0DEull));
			// Кладём метку обычным средством
			ASSERT_EQ(::pthread_setspecific(awh::alloc::__awh_alloc_tsd__, mark), 0);
			// Прямое чтение обязано увидеть метку
			EXPECT_EQ(slots[slot], mark) << "прямое чтение не увидело поставленной метки";
			// Возвращаем значение ключа на место
			ASSERT_EQ(::pthread_setspecific(awh::alloc::__awh_alloc_tsd__, kept), 0);
		}
	#endif
}

/**
 * @brief Проверка настройки «обнулять выдаваемое» на ВСЕХ путях выдачи
 *
 * @details Настройка обещает нули всякой выдаче, а не одной лишь `malloc`: договор её
 *          гласит «незаданный указатель читается нулём». Путей выдачи три - обычная,
 *          выдача через изменение размера при пустом прежнем блоке и прибавка при росте
 *
 * @note Прежде обнуление стояло ЛИШЬ в `malloc`, а `realloc` его не знал вовсе - ни при
 *       выдаче нового блока, ни при росте прежнего. Настройка эта не покрывалась
 *       проверками совсем, оттого пробел и уцелел
 *
 * @note Щупом отмечено, ЧТО именно доставалось прикладному коду в хвосте выросшего
 *       блока: перемешанный указатель нашего же списка свободных - худшее, чем случайный
 *       мусор. Развести чужой мусор приёмника и перечитывание за концом источника помогли
 *       разные образцы: соседи источника метились своим знаком, приёмник - своим
 *
 * @note Куча пачкается намеренно: свежая страница приходит от системы обнулённой, и на
 *       чистой куче проверка прошла бы при выключенном обнулении
 *
 */
TEST_F(AllocFixture, ZeroFillCoversEveryAllocationPath){
	// Если распределитель захвата не производил
	if(!awh::alloc::Allocator::captured())
		// Пропускаем проверку: захват под санитайзером не состоится
		GTEST_SKIP() << "захват под санитайзером не состоится";
	// Размер блока-источника и блока-приёмника
	static constexpr size_t SMALL = 64, BIG = 512;
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Просим обнулять выдаваемое
	options.fill = awh::alloc::fill_t::ZERO;
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	/**
	 * Метод пачканья разряда заданным образцом
	 */
	auto soil = [](const size_t size, const int32_t mark) noexcept -> void {
		// Испачканные блоки
		std::vector <void *> blocks;
		/**
		 * Набираем блоки разряда и метим их содержимое
		 */
		for(size_t i = 0; i < 512; i++){
			// Выдаём блок разряда
			void * block = ::malloc(size);
			// Если выдавать больше нечего
			if(block == nullptr)
				// Прекращаем набор
				break;
			// Метим содержимое блока
			::memset(block, mark, size);
			// Запоминаем испачканный блок
			blocks.push_back(block);
		}
		/**
		 * Перебираем испачканные блоки
		 */
		for(void * block : blocks)
			// Освобождаем испачканный блок
			::free(block);
	};
	/**
	 * Метод счёта нулевых октетов подряд
	 */
	auto nulled = [](const void * block, const size_t from, const size_t size) noexcept -> size_t {
		// Приводим блок к байтовому виду
		const uint8_t * bytes = reinterpret_cast <const uint8_t *> (block);
		// Число нулевых октетов подряд
		size_t result = 0;
		/**
		 * Перебираем октеты области
		 */
		for(size_t i = from; i < size; i++){
			// Если октет не нулевой
			if(bytes[i] != 0)
				// Сличать дальше незачем
				break;
			// Считаем нулевой октет
			result++;
		}
		// Выводим число нулевых октетов подряд
		return result;
	};
	// Пачкаем разряд приёмника
	soil(BIG, 0xAA);
	/**
	 * Путь первый: обычная выдача
	 */
	{
		// Выдаём блок
		void * block = ::malloc(BIG);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr);
		// Выданное обязано быть обнулено целиком
		EXPECT_EQ(nulled(block, 0, BIG), BIG) << "обычная выдача пришла не обнулённой";
		// Освобождаем блок
		::free(block);
	}
	// Пачкаем разряд приёмника снова
	soil(BIG, 0xAA);
	/**
	 * Путь второй: изменение размера при пустом прежнем блоке
	 *
	 * Договор языка велит считать его тем же самым, что и обычная выдача
	 */
	{
		// Выдаём блок изменением размера пустого
		void * block = ::realloc(nullptr, BIG);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr);
		// Выданное обязано быть обнулено целиком
		EXPECT_EQ(nulled(block, 0, BIG), BIG) << "выдача через изменение размера пришла не обнулённой";
		// Освобождаем блок
		::free(block);
	}
	// Пачкаем разряд приёмника снова
	soil(BIG, 0xAA);
	/**
	 * Путь третий: прибавка при росте блока
	 */
	{
		// Выдаём блок-источник
		void * block = ::malloc(SMALL);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr);
		// Метим содержимое источника своим образцом
		::memset(block, 0x11, SMALL);
		// Растим блок
		void * grown = ::realloc(block, BIG);
		// Рост обязан состояться
		ASSERT_NE(grown, nullptr);
		// Перенесённое содержимое обязано уцелеть
		EXPECT_EQ((* reinterpret_cast <uint8_t *> (grown)), static_cast <uint8_t> (0x11))
		 << "рост блока потерял перенесённое содержимое";
		// Число нулевых октетов прибавки
		const size_t zeroed = nulled(grown, SMALL, BIG);
		// Прибавка обязана быть обнулена целиком
		EXPECT_EQ(zeroed, (BIG - SMALL))
		 << "прибавка при росте пришла не обнулённой: первый ненулевой октет "
		 << static_cast <uint32_t> (reinterpret_cast <uint8_t *> (grown)[SMALL + zeroed]);
		// Освобождаем выросший блок
		::free(grown);
	}
}
