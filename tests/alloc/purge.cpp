/**
 * Проверки ниже стоят ВНЕ охраны санитайзеров намеренно
 *
 * Захват им не нужен вовсе: слои заводятся здесь напрямую, поверх своего источника, и
 * работают одинаково, кто бы ни владел `malloc` процесса. Под санитайзером они тем
 * ценнее - утечку и обращение за концом области он поймает сам
 */
/**
 * @brief Пространство имён источника, отказывающего по счёту
 *
 * @note Пространство безымянное намеренно: проверки всех слоёв собираются в ОДНУ
 *       программу, и тип с внешней связью столкнулся бы с одноимённым из соседнего
 *       файла - порчей кучи вдали от места
 *
 */
namespace {
	/**
	 * @brief Источник страниц, отказывающий после заданного числа выдач
	 *
	 */
	class Stingy : public awh::alloc::Source {
		private:
			// Источник, к какому обращаемся за настоящей памятью
			awh::alloc::SystemSource _system;
			// Остаток разрешённых выдач
			size_t _allowed;
			// Число состоявшихся выдач
			size_t _given;
			// Число состоявшихся возвратов
			size_t _returned;
			// Объём выданного источником в байтах
			size_t _takenBytes;
			// Объём возвращённого источнику в байтах
			size_t _givenBytes;
		public:
			/**
			 * @brief Конструктор
			 *
			 * @param allowed число разрешённых выдач
			 *
			 */
			Stingy(const size_t allowed) noexcept :
			 _system(), _allowed(allowed), _given(0), _returned(0), _takenBytes(0), _givenBytes(0) {}
		public:
			/**
			 * @brief Метод получения числа невозвращённых выдач
			 *
			 * @return число невозвращённых выдач
			 *
			 */
			int64_t outstanding() const noexcept {
				// Выводим число невозвращённых выдач
				return (static_cast <int64_t> (this->_given) - static_cast <int64_t> (this->_returned));
			}
			/**
			 * @brief Метод получения объёма невозвращённой памяти
			 *
			 * @return объём невозвращённой памяти в байтах
			 *
			 */
			/**
			 * Объём считается ОТДЕЛЬНО от числа выдач, и вот отчего
			 *
			 * Счёт выдач ловит утечку области целиком, но слеп к расхождению размеров:
			 * область, взятая страницей, а отданная запрошенными двумя килобайтами,
			 * пройдёт по счёту выдач ровно. Источник же ведёт учёт взятого у системы
			 * именно объёмом, и такое расхождение уводит счёт вверх на каждом
			 * перестроении, отчего заказанный приложением потолок закрывает выдачу тем
			 * раньше, чем дольше работа
			 */
			int64_t leftover() const noexcept {
				// Выводим объём невозвращённой памяти
				return (static_cast <int64_t> (this->_takenBytes) - static_cast <int64_t> (this->_givenBytes));
			}
		public:
			/**
			 * @brief Метод выдачи области памяти
			 *
			 * @param size      требуемый размер области
			 * @param alignment требуемое выравнивание области
			 * @param actual    выданный размер области
			 * @return          адрес выданной области либо nullptr
			 *
			 */
			void * alloc(const size_t size, const size_t alignment, size_t & actual) noexcept override {
				// Если разрешённые выдачи исчерпаны
				if(this->_allowed == 0){
					// Обнуляем выданный размер
					actual = 0;
					// Отвечаем отказом
					return nullptr;
				}
				// Берём область у настоящего источника
				void * result = this->_system.alloc(size, alignment, actual);
				// Если область выдана
				if(result != nullptr){
					// Уменьшаем остаток разрешённых выдач
					this->_allowed--;
					// Считаем состоявшуюся выдачу
					this->_given++;
					// Считаем объём выданного: именно ВЫДАННЫЙ, а не запрошенный
					this->_takenBytes += actual;
				}
				// Выводим адрес выданной области
				return result;
			}
			/**
			 * @brief Метод сброса содержимого области памяти
			 *
			 * @param addr адрес области
			 * @param size размер области
			 * @return     признак сброса содержимого
			 *
			 */
			bool purge(void * addr, const size_t size) noexcept override {
				// Сбрасываем содержимое области настоящим источником
				return this->_system.purge(addr, size);
			}
			/**
			 * @brief Метод возврата области памяти
			 *
			 * @param addr адрес области
			 * @param size размер области
			 * @return     признак возврата области
			 *
			 */
			bool release(void * addr, const size_t size) noexcept override {
				// Считаем состоявшийся возврат
				this->_returned++;
				// Считаем объём возвращённого
				this->_givenBytes += size;
				// Возвращаем область настоящему источнику
				return this->_system.release(addr, size);
			}
			/**
			 * @brief Метод смены доступности области
			 *
			 * @param addr   адрес области
			 * @param size   размер области
			 * @param opened признак открытой области
			 * @return       признак смены доступности
			 *
			 */
			/**
			 * Переложить смену доступности на настоящий источник ОБЯЗАТЕЛЬНО
			 *
			 * Умолчание отвечает отказом - источник страницами системы не владеет, - а
			 * заслоны на отказ закрыть заслон отвечают выключением выборки насовсем.
			 * Оставь мы умолчание, всякая заслонённая выдача отвечала бы пустотой
			 */
			bool protect(void * addr, const size_t size, const bool opened) noexcept override {
				// Меняем доступность области настоящим источником
				return this->_system.protect(addr, size, opened);
			}
			/**
			 * @brief Метод получения зерна выдачи источника
			 *
			 * @return зерно выдачи источника
			 *
			 */
			size_t granularity() const noexcept override {
				// Выводим зерно выдачи настоящего источника
				return this->_system.granularity();
			}
	};
};

/**
 * @brief Тест отката занятого при отказе заведения кучи
 *
 * @details Куча заводится с занимаемой областью, какой источник заведомо не выдаст
 *          целиком: часть кусков он отдаёт, а на следующем отказывает. Заведение
 *          обязано ответить отказом и вернуть источнику ВСЁ, что успело взять
 *
 * @note Проверка закрепляет откат, а не отказ. Отказ без отката оставляет взятое за
 *       нами навсегда: звавший заводит кучу заново, запись о прежде взятом теряется, а
 *       память у системы остаётся занятой и не выражается больше ничем
 *
 */
TEST(AllocPurgeTest, HeapInitRollsBackTakenOnFailure){
	// Источник, отдающий лишь два куска
	Stingy stingy(2);
	// Страничная куча под проверку
	awh::alloc::pages_t pages;
	/**
	 * Заводим кучу с занимаемой областью в восемь кусков
	 *
	 * Размер куска - свойство кучи, и берётся он отсюда же: проси мы область числом
	 * байт наугад, проверка сломалась бы от всякой правки размера
	 */
	const bool heaped = pages.init(&stingy, (8u * awh::alloc::Pages::CHUNK), false);
	// Заведение обязано ответить отказом: источник заказанного не выдал
	EXPECT_FALSE(heaped);
	// Взятое у источника обязано быть возвращено целиком
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0))
	 << "источнику не возвращено выдач: " << stingy.outstanding();
	// Возвращено обязано быть и ровно столько ЖЕ памяти, сколько выдано
	EXPECT_EQ(stingy.leftover(), static_cast <int64_t> (0))
	 << "источнику не возвращено памяти: " << stingy.leftover() << " окт.";
	// Разрушаем кучу: после отката разрушать нечего, и повтор обязан быть безвредным
	pages.destroy();
	// Повторное разрушение ничего не меняет
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0));
}

/**
 * @brief Тест неизменности учёта при отказе выдачи
 *
 * @details Просит у источника заведомо неподъёмную область и сверяет, что отказ не
 *          сдвинул счёт взятого у системы ни на байт
 *
 * @note Проверка эта нашла дефект в ветви MS Windows: там условие «область отведена»
 *       не имело скобок, и счёт взятого рос ВСЯКИЙ раз - в том числе при отказе. Растёт
 *       он молча, а расплата двойная: доклад о занятом врёт, а с заданным потолком
 *       занятого отказы копятся, пока потолок не окажется выбран отказавшими выдачами,
 *       и выдавать не станет вовсе. Замечено чтением, подтверждено собирателем на стенде
 *       MSYS2 (`-Wmisleading-indentation` у g++ 16.1), закреплено здесь
 *
 */
TEST(AllocPurgeTest, RefusedRequestLeavesAccountingIntact){
	// Источник страниц под проверку
	awh::alloc::SystemSource source;
	// Запоминаем счёт взятого у системы до отказа
	const size_t before = source.taken();
	// Действительно выданный размер
	size_t actual = 0;
	/**
	 * Просим заведомо неподъёмную область
	 *
	 * Размер взят таким, чтобы, с одной стороны, ни одна система его не выдала, а с
	 * другой - округление его по зерну выдачи не переполнило разрядность
	 */
	void * block = source.alloc((static_cast <size_t> (1) << 62), 0, actual);
	// Если выдача всё же состоялась, проверять нечего: возвращаем её и уходим
	if(block != nullptr){
		// Возвращаем выданное источнику
		source.release(block, actual);
		// Пропускаем проверку: неподъёмного размера для этой системы не нашлось
		GTEST_SKIP() << "система выдала область в четыре экзабайта";
	}
	// Отказ обязан обнулить выданный размер
	EXPECT_EQ(actual, static_cast <size_t> (0));
	// Отказ обязан оставить счёт взятого нетронутым
	EXPECT_EQ(source.taken(), before)
	 << "отказ сдвинул счёт взятого на " << (static_cast <int64_t> (source.taken()) - static_cast <int64_t> (before)) << " байт";
}

/**
 * @brief Тест возврата памяти учёта слоем крупных выдач
 *
 * @details Слой ведёт учётные записи в кусках, взятых у источника отдельно от самих
 *          выдач. Снятие слоя обязано вернуть источнику ВСЁ - и области выдач, и
 *          таблицу поиска, и куски под учётные записи
 *
 * @note Прежде куски под учётные записи не отдавались вовсе, а в файле стояло, что
 *       связать их списком нельзя: дескать, первые байты куска уже отданы под записи.
 *       Довод этот неверен - страничная куча ведёт свой такой же список ровно этим
 *       приёмом, отводя под записи кусок ЗА заголовком
 *
 */
TEST(AllocPurgeTest, HugeLayerReturnsBookkeepingMemory){
	// Источник, выдач не считающий: отказывать здесь незачем
	Stingy stingy(std::numeric_limits <size_t>::max());
	// Слой крупных выдач под проверку
	awh::alloc::huge_t huge;
	// Заводим слой крупных выдач
	ASSERT_TRUE(huge.init(&stingy));
	/**
	 * Придерживать области НЕ даём
	 *
	 * Придержанное отдаётся при снятии слоя тоже, но проверка мерит возврат учёта, а не
	 * придержанного: пусть каждая выдача уходит источнику сразу
	 */
	huge.ceiling(0);
	// Выданные области
	std::vector <void *> alive;
	/**
	 * Перебираем крупные выдачи
	 *
	 * Берём их с запасом: одна запись учёта куска под записи не заполнит, а проверка
	 * мерит именно возврат таких кусков
	 */
	for(size_t i = 0; i < 256; i++){
		// Выдаём крупную область
		void * block = huge.alloc((1u * 1024u * 1024u) + (i * 4096u), 0);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr) << "крупная выдача отказала на шаге " << i;
		// Запоминаем выданную область
		alive.push_back(block);
	}
	/**
	 * Перебираем выданные области
	 */
	for(void * block : alive)
		// Освобождаем крупную область
		huge.free(block);
	// Снимаем слой крупных выдач
	huge.reset();
	// Взятое у источника обязано быть возвращено целиком
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0))
	 << "источнику не возвращено выдач: " << stingy.outstanding();
	// Возвращено обязано быть и ровно столько ЖЕ памяти, сколько выдано
	EXPECT_EQ(stingy.leftover(), static_cast <int64_t> (0))
	 << "источнику не возвращено памяти: " << stingy.leftover() << " окт.";
}

/**
 * @brief Проверка возврата памяти учёта слоем заслонов
 *
 * Заслоны ведут таблицу поиска и куски памяти под учётные записи, и то и другое
 * берётся у источника напрямую. Прежде куски под записи не отдавались вовсе - за то
 * стояло, что связать их списком нельзя, ибо первые байты куска уже отданы под
 * записи, - и всякий подъём заслонов терял по куску на каждую тысячу с лишним
 * заслонённых блоков. Слой крупных выдач ведёт свой такой же список, отводя под
 * заголовок начало куска, и довод этот опровергает
 *
 * Таблица же отдавалась ЗАПРОШЕННЫМ размером, а не выданным: начальная просит 2048
 * байт, а получает страницу целиком, - и счёт взятого у системы уползал вверх на
 * каждом перестроении, отчего заказанный приложением потолок закрывал бы выдачу
 * тем раньше, чем дольше работа
 *
 */
TEST(AllocPurgeTest, GuardLayerReturnsBookkeepingMemory){
	// Источник, выдач не считающий: отказывать здесь незачем
	Stingy stingy(std::numeric_limits <size_t>::max());
	// Слой заслонов под проверку
	awh::alloc::guard_t guard;
	// Заводим слой заслонов
	ASSERT_TRUE(guard.init(&stingy));
	// Выданные области
	std::vector <void *> alive;
	/**
	 * Перебираем заслонённые выдачи
	 *
	 * Берём их с запасом и НЕ освобождаем по дороге: освобождённая запись уходит в
	 * список повторно используемых и нового куска не просит, - а проверка мерит
	 * именно возврат таких кусков. Полутора тысяч довольно на два куска и на
	 * несколько перестроений таблицы поиска
	 */
	for(size_t i = 0; i < 1500; i++){
		// Выдаём заслонённую область
		void * block = guard.alloc(16);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr) << "заслонённая выдача отказала на шаге " << i;
		// Запоминаем выданную область
		alive.push_back(block);
	}
	// Снимаем слой заслонов
	guard.reset();
	// Взятое у источника обязано быть возвращено целиком
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0))
	 << "источнику не возвращено выдач: " << stingy.outstanding();
	// Возвращено обязано быть и ровно столько ЖЕ памяти, сколько выдано
	EXPECT_EQ(stingy.leftover(), static_cast <int64_t> (0))
	 << "источнику не возвращено памяти: " << stingy.leftover() << " окт.";
}

