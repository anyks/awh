/**
 * @brief Проверка возврата памяти при вытеснении закрытых областей заслонами
 *
 * Освобождённая заслонённая область не отдаётся системе сразу: она закрывается целиком
 * и ждёт в очереди, чтобы обращение по висячему указателю валило работу в точке
 * дефекта. Отдаётся она вытеснением, когда очередь перебирает границу по счёту либо по
 * объёму, - и путь этот, в отличие от снятия слоя, ничем прежде не был покрыт
 *
 * @note Проверка НЕ закрепляет учёт надгробий в таблице поиска. Щуп показал, что в этом
 *       расположении их не возникает вовсе: система выдаёт под новую область тот же
 *       адрес, что отдан вытеснением, место в таблице берётся то же самое, и надгробие
 *       занимается живой записью тут же. Заявлять здесь охват учёта надгробий значило
 *       бы отчитаться о непроверенном
 *
 */
TEST(AllocPurgeTest, GuardEvictionReturnsMemoryToSource){
	// Источник, выдач не считающий: отказывать здесь незачем
	Stingy stingy(std::numeric_limits <size_t>::max());
	// Слой заслонов под проверку
	awh::alloc::guard_t guard;
	// Заводим слой заслонов
	ASSERT_TRUE(guard.init(&stingy));
	// Выданные области, ожидающие освобождения
	std::vector <void *> alive;
	/**
	 * Вращаем заслонённые выдачи, держа живыми лишь несколько
	 *
	 * Освобождённая область уходит в очередь закрытых и ждёт там вытеснения. Оборотов
	 * берём с запасом на то, чтобы очередь эта перебрала границу по объёму и вытеснение
	 * пошло одно за другим: держи мы обороты в границе - путь этот не был бы пройден
	 * вовсе, и проверка мерила бы одно снятие слоя
	 */
	for(size_t i = 0; i < 6000; i++){
		// Выдаём заслонённую область
		void * block = guard.alloc(16);
		// Выдача обязана состояться
		ASSERT_NE(block, nullptr) << "заслонённая выдача отказала на обороте " << i;
		// Запоминаем выданную область
		alive.push_back(block);
		// Если живых областей набралось довольно
		if(alive.size() > 8){
			// Признак принадлежности области заслонам
			bool mine = false;
			// Освобождаем старейшую живую область
			guard.free(alive.front(), &mine);
			// Область обязана принадлежать заслонам
			ASSERT_TRUE(mine) << "заслоны не признали своей область оборота " << i;
			// Убираем область из числа живых
			alive.erase(alive.begin());
		}
	}
	// Снимаем слой заслонов
	guard.reset();
	// Взятое у источника обязано быть возвращено целиком
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0))
	 << "источнику не возвращено выдач: " << stingy.outstanding();
	// Возвращено обязано быть и ровно столько ЖЕ памяти, сколько выдано
	EXPECT_EQ(stingy.leftover(), static_cast <int64_t> (0))
	 << "источнику не возвращено памяти: " << stingy.leftover() << " окт.";
}

/**
 * @brief Проверка снятия метки разряда при возврате области куче
 *
 * @details Метка разряда - быстрый путь освобождения: `classify` отвечает по ней одним
 *          чтением, не трогая ни указателей страниц, ни учётной записи области. Нуль по
 *          договору означает «страница разряду не отдана». Область, возвращённая куче,
 *          разряду не отдана - и метки нести не вправе
 *
 * @note Освобождение метки НЕ снимало, и договор держался лишь тем, что нарезанные
 *       разрядам области куче не возвращаются вовсе: единственный путь к возврату идёт
 *       от выдач сверх разрядов, а у тех метки нет. Заслонки на то не было ни одной, и
 *       заведись такой возврат - `classify` относила бы свободную страницу к прежнему её
 *       разряду, а освобождение по ней уводило бы чужой блок в чужой список
 *
 * @note Сличение в самом освобождении холостое: у выдач сверх разрядов метка нулевая, и
 *       обход страниц не идёт вовсе
 *
 */
TEST(AllocPurgeTest, ReturnedSpanDropsClassTag){
	// Источник страниц системы
	awh::alloc::SystemSource system;
	// Страничная куча под проверку
	awh::alloc::pages_t pages;
	// Заводим страничную кучу
	ASSERT_TRUE(pages.init(&system, 0, false));
	// Действительно выданное число страниц
	size_t served = 0;
	// Берём у кучи область в четыре страницы
	void * base = pages.alloc(4, &served);
	// Выдача обязана состояться
	ASSERT_NE(base, nullptr) << "куча не выдала области";
	// Метим область разрядом: метка на единицу больше его номера
	ASSERT_TRUE(pages.tag(base, 7)) << "метка разряда не поставлена";
	// Метка обязана читаться быстрым путём
	ASSERT_EQ(pages.classify(base), static_cast <uint8_t> (7))
	 << "быстрый путь не увидел поставленной метки";
	// Возвращаем область куче
	ASSERT_TRUE(pages.free(base, 1)) << "куча не приняла области обратно";
	// Возвращённая область разряду не отдана: метки у неё быть не может
	EXPECT_EQ(pages.classify(base), static_cast <uint8_t> (0))
	 << "возвращённая куче страница числится за разрядом "
	 << static_cast <uint32_t> (pages.classify(base));
}

/**
 * @brief Источник, отказывающий в памяти под учётные записи кучи
 *
 * @details Куски кучи выдаёт как обычно, а запрос под учётные записи отвергает, начиная
 *          со второго. Так деление свободной области остаётся без записи остатка, и куча
 *          идёт ветвью «не делим и выдаём целиком»
 *
 */
namespace {
	class Grudging : public awh::alloc::Source {
		private:
			// Источник, к какому обращаемся за настоящей памятью
			awh::alloc::SystemSource _system;
			// Число состоявшихся запросов под учётные записи
			size_t _metas;
		public:
			/**
			 * @brief Конструктор
			 *
			 */
			Grudging() noexcept : _system(), _metas(0) {}
		public:
			/**
			 * @brief Метод выдачи области памяти
			 *
			 * @param size      требуемый размер области
			 * @param alignment требуемое выравнивание области
			 * @param actual    выданный размер области
			 * @return          адрес выданной области либо nullptr
			 *
			 */
			void * alloc(const size_t size, const size_t alignment, size_t & actual) noexcept override {
				// Если просят память под учётные записи кучи
				if(size == META){
					// Считаем запрос под учётные записи
					this->_metas++;
					// Со второго запроса отвечаем отказом
					if(this->_metas > 1){
						// Обнуляем выданный размер
						actual = 0;
						// Отвечаем отказом
						return nullptr;
					}
				}
				// Выдаём область настоящим источником
				return this->_system.alloc(size, alignment, actual);
			}
			/**
			 * @brief Метод возврата области памяти
			 *
			 */
			bool release(void * addr, const size_t size) noexcept override {
				// Возвращаем область настоящему источнику
				return this->_system.release(addr, size);
			}
			/**
			 * @brief Метод отдачи содержимого области системе
			 *
			 */
			bool purge(void * addr, const size_t size) noexcept override {
				// Отдаём содержимое области настоящему источнику
				return this->_system.purge(addr, size);
			}
			/**
			 * @brief Метод получения зернистости выдачи
			 *
			 */
			size_t granularity() const noexcept override {
				// Выводим зернистость настоящего источника
				return this->_system.granularity();
			}
		public:
			// Размер куска кучи под учётные записи
			static constexpr size_t META = (256u * 1024u);
	};
};

/**
 * @brief Проверка учёта отданного системе при выдаче неделимой области
 *
 * @details Куча делит свободную область, если та крупнее запрошенного, а под запись
 *          остатка просит памяти. Не выдайся память - область выдаётся ЦЕЛИКОМ, не
 *          делясь: потерять при этом можно лишь неиспользованный хвост, тогда как отказ
 *          пришлось бы дать при наличии памяти. Ветвь эта обязана снимать область с
 *          учёта отданного системе ровно так же, как и обычная выдача
 *
 * @note Прежде на ней стояло голое снятие признака - без вычитания байтов из учёта.
 *       Учёт застревал навсегда: страницы уходили наружу, а числились отданными системе,
 *       и вычесть их было уже некому. Щупом поймано на самой ветви: куча доложила 171
 *       страницу отданной системе при 31 свободной - больше, чем у неё вообще было
 *       свободного. Число это приложение читает опросом состояния и решает по нему,
 *       нужна ли отдача памяти
 *
 * @note Ветвь достижима лишь ОТКАЗОМ источника ровно на границе куска учётных записей:
 *       при выдаче по одной странице записи и страницы иссякают ноздря в ноздрю, и куча
 *       упирается в отказ роста прежде, чем в нехватку записи. Оттого выдача идёт по три
 *       страницы - так записи кончаются посреди куска, когда свободные страницы ещё есть
 *
 */
TEST(AllocPurgeTest, UndividedSpanLeavesPurgedAccounting){
	// Источник, отказывающий в памяти под учётные записи
	Grudging grudging;
	// Страничная куча под проверку
	awh::alloc::pages_t pages;
	// Заводим страничную кучу
	ASSERT_TRUE(pages.init(&grudging, 0, false));
	// Отдаём системе без отсрочки и без наименьшего отдаваемого куска
	pages.policy(0, 0);
	// Действительно выданное число страниц
	size_t served = 0;
	// Берём три страницы: кусок заводится, остаток уходит в свободные
	ASSERT_NE(pages.alloc(3, &served), nullptr) << "первая выдача отказала";
	// Отдаём системе всё свободное: остаток куска метится отданным
	pages.purge(1, true);
	// Отданное системе обязано появиться, иначе проверять нечего
	ASSERT_GT(pages.state().purged, static_cast <size_t> (0))
	 << "куча не отдала системе ничего: проверять нечего";
	// Признак прохождения ветви неделимой выдачи
	bool undivided = false;
	/**
	 * Просим страницы, пока кусок под учётные записи не иссякнет
	 */
	for(size_t i = 0; i < 100000; i++){
		/**
		 * Отдаём системе свободный остаток куска ПЕРЕД каждой выдачей
		 *
		 * Освобождать здесь нечего - ни один блок куче не возвращается, - оттого слияние
		 * не идёт вовсе и список повторно используемых записей остаётся пустым. Остаток
		 * же метится отданным, и делить придётся именно ОТДАННУЮ область
		 */
		pages.purge(1, true);
		// Запоминаем учёт отданного ДО очередной выдачи
		const size_t before = pages.state().purged;
		// Просим три страницы
		void * block = pages.alloc(3, &served);
		// Если выдавать стало нечего
		if(block == nullptr)
			// Куча упёрлась в отказ роста: ветвь пройти не успели
			break;
		// Если область выдана по запросу, деление состоялось
		if(served <= 3)
			// Переходим к следующей выдаче
			continue;
		// Отмечаем ветвь неделимой выдачи пройденной
		undivided = true;
		/**
		 * Область выдана наружу целиком: отданной системе она больше не значится
		 */
		EXPECT_LT(pages.state().purged, before)
		 << "выдача " << served << " страниц не сняла их с учёта отданного: "
		 << before << " окт. до выдачи, " << pages.state().purged << " окт. после";
		/**
		 * Отданного системе не бывает больше, чем свободного
		 *
		 * Отдаётся лишь содержимое СВОБОДНЫХ областей, и всякая выдача наружу снимает
		 * область с этого учёта. Учёт, переросший свободное, означает застрявшие в нём
		 * байты - ровно тот дефект, ради какого проверка и написана
		 */
		EXPECT_LE(pages.state().purged, pages.state().free)
		 << "отданного системе больше, чем свободного: " << pages.state().purged
		 << " окт. против " << pages.state().free << " окт.";
		// Разбирать больше нечего
		break;
	}
	// Ветвь неделимой выдачи обязана быть пройдена, иначе проверка молчит впустую
	EXPECT_TRUE(undivided) << "ветвь неделимой выдачи не пройдена ни разу";
}

/**
 * @brief Проверка возврата памяти кольца карантином
 *
 * @details Карантин ведёт кольцо мест, взятое у источника отдельно от удерживаемых
 *          блоков. Снятие карантина обязано вернуть источнику это кольцо - тем же
 *          размером, каким оно у него взято
 *
 * @note Снятие это было ЕДИНСТВЕННЫМ из четырёх слоёв, не покрытым проверкой вовсе:
 *       возврат памяти сличался у крупных выдач, у заслонов и у обмера, а карантин
 *       не звался ни отсюда, ни из самого модуля. Непокрытая отдача памяти молчит
 *       ровно так же, как исправная
 *
 * @note Удерживаемые блоки карантин при снятии НЕ возвращает - и не обязан: слои,
 *       которым они принадлежат, к этому мигу уже сняты. Оттого блоки здесь берутся
 *       не у распределителя, а с местного поля: возвращать их некому по устройству,
 *       и проверка мерит ровно то, что карантин отдать обязан
 *
 */
/**
 * @brief Тест невиновности блоков, удержанных до включения засева
 *
 * @note Сличение засева идёт при изъятии блока из кольца, и незасеянный блок оно
 *       назвало бы испорченным - то есть обвинило бы прикладной код в записи по
 *       освобождённому указателю там, где тот ничего не делал. Обвинение это уходит в
 *       журнал уровнем CRITICAL и называет невиновный адрес
 *
 */
TEST(AllocPurgeTest, QuarantineSeedsHeldBlocksWhenJunkEnabled){
	// Источник, выдач не считающий
	Stingy stingy(std::numeric_limits <size_t>::max());
	// Карантин под проверку
	awh::alloc::quarantine_t quarantine;
	/**
	 * Потолок берём малым намеренно
	 *
	 * Изъятие идёт лишь тогда, когда удерживаемое перевалило за потолок: не будь он
	 * мал, блоки лежали бы в кольце до конца проверки и сличения не прошли бы вовсе
	 */
	ASSERT_TRUE(quarantine.init(&stingy, (16u * 1024u)));
	// Засев ВЫКЛЮЧЕН: блоки лягут в кольцо незасеянными
	quarantine.junk(false);
	// Поле, с какого берутся удерживаемые блоки
	std::vector <uint8_t> field(256u * 1024u, 0);
	/**
	 * Заполняем карантин блоками, записав в них своё
	 *
	 * Запись эта - обычная работа прикладного кода ДО освобождения, и обвинять её не в
	 * чем: блок был жив, когда в него писали
	 */
	size_t held = 0;
	for(size_t i = 0; i < 16; i++){
		// Определяем адрес очередного удерживаемого блока
		uint8_t * block = (field.data() + (i * 512u));
		// Записываем в блок узнаваемое содержимое
		::memset(block, 0x11, 512u);
		// Удерживаем блок карантином
		if(!quarantine.hold(block, 512u, 0))
			// Кольцо заполнилось: удерживать больше нечего
			break;
		// Увеличиваем число удержанных блоков
		held++;
	}
	// Блоки обязаны быть приняты, иначе проверять нечего
	ASSERT_GT(held, static_cast <size_t> (0)) << "карантин не принял ни одного блока";
	// Испорченных до включения засева быть не должно
	ASSERT_EQ(quarantine.state().spoiled, static_cast <size_t> (0));
	// Включаем засев В РАБОТЕ
	quarantine.junk(true);
	/**
	 * Выдавливаем удержанное новыми блоками
	 *
	 * Блоки эти берутся из второй половины поля, чтобы не задеть удержанных
	 */
	for(size_t i = 0; i < 128; i++){
		// Определяем адрес очередного вытесняющего блока
		uint8_t * block = (field.data() + (128u * 1024u) + (i * 512u));
		// Удерживаем блок карантином
		if(!quarantine.hold(block, 512u, 0))
			// Кольцо заполнилось: удерживать больше нечего
			break;
		// Размер изъятого блока
		size_t size = 0;
		// Номер разряда изъятого блока
		size_t index = 0;
		/**
		 * Изымаем всё, что карантин отдаёт
		 */
		while(quarantine.release(&size, &index) != nullptr)
			// Изымать продолжаем, пока карантин отдаёт
			continue;
	}
	// Блоки, удержанные до включения засева, обязаны пройти сличение чистыми
	EXPECT_EQ(quarantine.state().spoiled, static_cast <size_t> (0))
	 << "карантин обвинил в порче " << quarantine.state().spoiled
	 << " блок(ов), удержанных до включения засева";
	// Снимаем карантин
	quarantine.reset();
}

