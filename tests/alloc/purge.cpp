/**
 * @brief Проверка возврата памяти страничной кучей при снятии
 *
 * Куча ведёт таблицу поиска куска по адресу и перестраивает её вдвое, когда та тесна.
 * Прежние таблицы источнику при перестроении НЕ отдаются намеренно - читатель разбирает
 * адрес без замка и волен быть внутри прежней прямо сейчас, - и отдаются они все разом
 * при снятии кучи. Отдавала же их куча ЗАПРОШЕННЫМ размером: таблица в 1024 места
 * просит 8192 байта, а у систем со страницей в 16384 получает вдвое больше, и счёт
 * взятого у системы уползал вверх на каждом перестроении
 *
 * @note Проверка мерит объём, а не число выдач: по числу выдач такое расхождение
 *       проходит ровно - область взята однажды и отдана однажды
 *
 */
TEST(AllocPurgeTest, HeapReturnsTableMemoryOnDestroy){
	// Источник, выдач не считающий: отказывать здесь незачем
	Stingy stingy(std::numeric_limits <size_t>::max());
	// Страничная куча под проверку
	awh::alloc::pages_t pages;
	/**
	 * Заводим кучу с занимаемой областью во множество кусков
	 *
	 * Кусков берём столько, чтобы таблица поиска перестроилась не единожды: проверка
	 * закрепляет возврат ИМЕННО прежних таблиц, а при одной таблице возвращать нечего
	 */
	// Объём области, потребной проверке
	const size_t needed = (2048u * awh::alloc::Pages::CHUNK);
	/**
	 * Спрашиваем у системы предел данных ПРЕЖДЕ заведения
	 *
	 * Область эта лишь ЗАНИМАЕТСЯ, память под неё не берётся, - но предел данных
	 * считает и занятое. У OpenBSD он по умолчанию полтора гигабайта, восьми же
	 * гигабайт проверки система не даёт вовсе, и заведение отвечает отказом ЗАКОННО:
	 * куча ведёт себя верно, а проверка засчитывала это поломкой модуля
	 *
	 * Спрашиваем предел, а не глотаем всякий отказ: откажи заведение там, где предела
	 * ДОСТАЁТ, - проверка обязана пасть, и она падёт. Пропуск же по неведомой причине
	 * был бы молчаливым отключением
	 */
	#if !defined(_WIN32) && !defined(_WIN64)
	{
		// Предел объёма данных процесса
		struct rlimit bound;
		// Если предел спрошен и он проверке не по росту
		if((::getrlimit(RLIMIT_DATA, &bound) == 0) && (bound.rlim_cur != RLIM_INFINITY) && (bound.rlim_cur < needed))
			// Проверять нечего: система такой области не даст
			GTEST_SKIP() << "предел данных системы " << static_cast <size_t> (bound.rlim_cur)
			 << " окт. меньше потребных проверке " << needed << " окт.";
	}
	#endif
	ASSERT_TRUE(pages.init(&stingy, needed, false))
	 << "куча не завелась";
	// Снимаем кучу
	pages.destroy();
	// Взятое у источника обязано быть возвращено целиком
	EXPECT_EQ(stingy.outstanding(), static_cast <int64_t> (0))
	 << "источнику не возвращено выдач: " << stingy.outstanding();
	// Возвращено обязано быть и ровно столько ЖЕ памяти, сколько выдано
	EXPECT_EQ(stingy.leftover(), static_cast <int64_t> (0))
	 << "источнику не возвращено памяти: " << stingy.leftover() << " окт.";
}

/**
 * @brief Тест исполнения просьбы опустошиться на освобождении, а не только на выдаче
 *
 * @details Просьбу опустошиться ставит ЧУЖОЙ поток - отдача памяти системе, - а исполнить
 *          её вправе лишь хозяин кэша: чужой кэш замком не защищён, и правка его под
 *          руками работающего хозяина клала бы живой блок приложения в список свободных.
 *          Читается просьба в двух местах: при пополнении кэша и при освобождении блока
 *
 * @note Проверка закрепляет ИМЕННО второе место. Поток, который только освобождает и
 *       больше ничего не просит, до пополнения не доходит ни разу - и, читайся просьба
 *       лишь там, держал бы свои блоки до самого конца работы, а отдача памяти системе
 *       обходила бы его молча. Подменой доказано, что прежде путь этот не был покрыт
 *       ничем: выключение чтения просьбы в освобождении набор проверок не замечал
 *
 */
TEST_F(AllocFixture, YieldRequestIsHonouredOnFree){
	/**
	 * Под санитайзером кэшей потоков нет: захват не состоится
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "захват под санитайзером не состоится";
	#endif
	// Признак готовности работника
	std::atomic <bool> filled(false);
	// Признак поставленной работнику просьбы
	std::atomic <bool> asked(false);
	// Признак окончания работы
	std::atomic <bool> done(false);
	// Объём, лежавший в кэшах до исполнения просьбы
	std::atomic <size_t> before(0);
	// Объём, лежащий в кэшах после исполнения просьбы
	std::atomic <size_t> after(0);
	/**
	 * Заводим работника, набивающего свой кэш
	 */
	std::thread worker([&filled, &asked, &done, &before, &after](){
		// Блоки, удерживаемые до самого конца
		std::vector <void *> held;
		// Отводим место под удерживаемые блоки заранее
		held.reserve(64);
		/**
		 * Набираем блоки, НЕ освобождая их по дороге
		 *
		 * Выдача с немедленным возвратом кэш не набивает вовсе: она гоняет один и тот же
		 * блок туда-обратно, и лежащего в кэше остаётся с горстку. Набивается он лишь
		 * тем, что взято разом, а возвращено потом
		 */
		// Набираемые блоки
		std::vector <void *> batch;
		// Отводим место под набираемые блоки заранее
		batch.reserve(65536);
		/**
		 * Набираем блоков заведомо больше предела кэша
		 */
		for(size_t i = 0; i < 65536; i++){
			// Выдаём блок
			void * block = ::malloc(128);
			// Если блок выдан
			if(block != nullptr)
				// Запоминаем набранный блок
				batch.push_back(block);
		}
		/**
		 * Придерживаем горстку блоков на потом
		 *
		 * Освобождать их будем ПОСЛЕ просьбы, ничего не выдавая: только так проверяется
		 * чтение просьбы именно в освобождении
		 */
		while((batch.size() > 64) && (held.size() < 64)){
			// Забираем блок из набранных в удерживаемые
			held.push_back(batch.back());
			// Убираем блок из набранных
			batch.pop_back();
		}
		/**
		 * Возвращаем набранное: вот теперь кэш набивается
		 */
		for(void * block : batch)
			// Возвращаем набранный блок
			::free(block);
		// Отмечаем кэш набитым
		filled.store(true, std::memory_order_release);
		/**
		 * Дожидаемся поставленной просьбы
		 */
		while(!asked.load(std::memory_order_acquire))
			// Уступаем время
			std::this_thread::yield();
		// Запоминаем лежащее в кэшах до исполнения просьбы
		before.store(awh::alloc::Allocator::property(awh::alloc::property_t::CACHED), std::memory_order_relaxed);
		/**
		 * Освобождаем удерживаемые блоки, НИЧЕГО не выдавая
		 */
		for(void * block : held)
			// Освобождаем удерживаемый блок
			::free(block);
		// Запоминаем лежащее в кэшах после исполнения просьбы
		after.store(awh::alloc::Allocator::property(awh::alloc::property_t::CACHED), std::memory_order_relaxed);
		// Отмечаем работу оконченной
		done.store(true, std::memory_order_release);
	});
	/**
	 * Дожидаемся набитого кэша работника
	 */
	while(!filled.load(std::memory_order_acquire))
		// Уступаем время
		std::this_thread::yield();
	// Ставим просьбу опустошиться всем чужим кэшам
	awh::alloc::Allocator::purge();
	// Отмечаем просьбу поставленной
	asked.store(true, std::memory_order_release);
	// Дожидаемся работника
	worker.join();
	// Работа обязана окончиться
	ASSERT_TRUE(done.load(std::memory_order_acquire));
	// Кэш работника до исполнения просьбы обязан быть непустым
	ASSERT_GT(before.load(std::memory_order_relaxed), static_cast <size_t> (0))
	 << "кэш работника пуст ещё до просьбы: проверять нечего";
	/**
	 * Освобождение обязано исполнить просьбу и опустошить кэш
	 *
	 * Сличаем с ЧЕТВЕРТЬЮ прежнего, а не с нулём: исполнив просьбу, работник тут же
	 * складывает в кэш остаток удерживаемых блоков, и пустым тот не остаётся
	 */
	EXPECT_LT(after.load(std::memory_order_relaxed), (before.load(std::memory_order_relaxed) / 4u))
	 << "лежало " << before.load(std::memory_order_relaxed)
	 << ", осталось " << after.load(std::memory_order_relaxed) << " - просьба не исполнена";
}

/**
 * @brief Тест честности учёта отданного системе при отказе источника
 *
 * @details Отдача содержимого страниц системе отказом отвечать вправе: у части систем
 *          средства отдачи нет вовсе, а у прочих оно волен отказать по своим причинам.
 *          Учёт отданного обязан считать лишь то, что система ПРИНЯЛА
 *
 * @note Проверка закрывает не саму отдачу, а её учёт: отдача наружу выражена лишь
 *       расходом памяти по отчётам системы, и подменой это доказано - выключение
 *       самого `madvise` набор проверок не замечает и заметить не может. А вот ложь
 *       учёта заметить можно, и она хуже: приложение, глядящее на отданное, решало бы
 *       по ней, что память возвращена, тогда как она занята по-прежнему
 *
 */
TEST(AllocPurgeTest, RefusedPurgeIsNotCountedAsGiven){
	/**
	 * @brief Источник, отказывающий в отдаче содержимого страниц
	 *
	 */
	class Stubborn : public awh::alloc::Source {
		private:
			// Источник, к какому обращаемся за настоящей памятью
			awh::alloc::SystemSource _system;
		public:
			/**
			 * @brief Метод выдачи области памяти
			 *
			 * @param size      требуемый размер области
			 * @param alignment требуемое выравнивание области
			 * @param actual    выданный размер области
			 * @return          адрес выданной области либо nullptr
			 *
			 */
			void * alloc(const size_t size, const size_t alignment, size_t & actual) noexcept override {
				// Берём область у настоящего источника
				return this->_system.alloc(size, alignment, actual);
			}
			/**
			 * @brief Метод сброса содержимого области памяти
			 *
			 * @return признак сброса содержимого
			 *
			 */
			bool purge(void *, const size_t) noexcept override {
				// Отвечаем отказом: система содержимого не приняла
				return false;
			}
			/**
			 * @brief Метод возврата области памяти
			 *
			 * @param addr адрес области
			 * @param size размер области
			 * @return     признак возврата области
			 *
			 */
			bool release(void * addr, const size_t size) noexcept override {
				// Возвращаем область настоящему источнику
				return this->_system.release(addr, size);
			}
			/**
			 * @brief Метод получения зерна выдачи источника
			 *
			 * @return зерно выдачи источника
			 *
			 */
			size_t granularity() const noexcept override {
				// Выводим зерно выдачи настоящего источника
				return this->_system.granularity();
			}
	};
	// Источник, отказывающий в отдаче содержимого
	Stubborn stubborn;
	// Страничная куча под проверку
	awh::alloc::pages_t pages;
	// Заводим кучу
	ASSERT_TRUE(pages.init(&stubborn, (8u * awh::alloc::Pages::CHUNK), false));
	// Отдаём системе всё свободное, не глядя на отсрочку
	const size_t given = pages.purge(0, true);
	// Отданным не может считаться ничто: источник отказал
	EXPECT_EQ(given, static_cast <size_t> (0))
	 << "учёт засчитал отданными " << given << " окт., в каких система отказала";
	// Учёт отданного обязан остаться нулевым
	EXPECT_EQ(pages.state().purged, static_cast <size_t> (0))
	 << "в учёте кучи значится отданным " << pages.state().purged << " окт.";
	// Снимаем кучу
	pages.destroy();
}

/**
 * @brief Тест работоспособности кэша потока после отдачи памяти системе
 *
 * @details Отдача памяти системе ставит чужим кэшам просьбу опустошиться и опускает им
 *          рабочий предел до нуля: тем просьба и замечается на первом же освобождении.
 *          Предел обязан вернуться на место, едва просьба исполнена, - иначе кэш с
 *          нулевым пределом опустошается на КАЖДОМ освобождении и не держит НИЧЕГО
 *
 * @note Закрывает поведение, а не саму гонку: рычаг остаётся опущенным лишь тогда, когда
 *       просьбу снимает пополнение разряда между двумя записями ставящего, а окно это
 *       извне не воспроизвести. Что происходит при опущенном рычаге, доказано подменой:
 *       чужой поток опускал рычаг, не ставя просьбы вовсе, - в точности исход проигранной
 *       гонки. Без возврата предела работник давал 92.57 нс/оп и НУЛЬ байт в кэше, с
 *       возвратом - 9.15 нс/оп и 32768 байт. Замедление вдесятеро, и навсегда
 *
 * @note Сличается СОСТОЯНИЕ, а не время: показатель по времени зависит от занятости
 *       машины, а лежащее в кэше - нет
 *
 */
TEST_F(AllocFixture, CacheWorksAfterPurge){
	/**
	 * Под санитайзером кэшей потоков нет: захват не состоится
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "захват под санитайзером не состоится";
	#endif
	// Признак набитого кэша работника
	std::atomic <bool> filled(false);
	// Признак поставленной просьбы
	std::atomic <bool> asked(false);
	// Лежащее в кэшах после исполнения просьбы и повторного набора
	std::atomic <size_t> cached(0);
	/**
	 * Заводим работника, набивающего свой кэш дважды
	 */
	std::thread worker([&filled, &asked, &cached](){
		// Блоки первого набора
		void * batch[256];
		/**
		 * Набиваем кэш первый раз
		 */
		for(size_t i = 0; i < 256; i++)
			// Выдаём блок
			batch[i] = ::malloc(128);
		/**
		 * Возвращаем набранное: кэш набит
		 */
		for(size_t i = 0; i < 256; i++)
			// Возвращаем блок
			::free(batch[i]);
		// Отмечаем кэш набитым
		filled.store(true, std::memory_order_release);
		/**
		 * Дожидаемся поставленной просьбы
		 */
		while(!asked.load(std::memory_order_acquire))
			// Уступаем время
			std::this_thread::yield();
		/**
		 * Набиваем кэш ВТОРОЙ раз, уже после исполнения просьбы
		 */
		for(size_t i = 0; i < 256; i++)
			// Выдаём блок
			batch[i] = ::malloc(128);
		/**
		 * Возвращаем набранное
		 */
		for(size_t i = 0; i < 256; i++)
			// Возвращаем блок
			::free(batch[i]);
		// Запоминаем лежащее в кэшах
		cached.store(awh::alloc::Allocator::property(awh::alloc::property_t::CACHED), std::memory_order_relaxed);
	});
	/**
	 * Дожидаемся набитого кэша работника
	 */
	while(!filled.load(std::memory_order_acquire))
		// Уступаем время
		std::this_thread::yield();
	// Отдаём память системе: кэшу работника ставится просьба
	awh::alloc::Allocator::purge();
	// Отмечаем просьбу поставленной
	asked.store(true, std::memory_order_release);
	// Дожидаемся работника
	worker.join();
	/**
	 * Кэш обязан держать набранное вторым набором
	 *
	 * При опущенном рычаге здесь стоял бы НУЛЬ: каждое освобождение опустошало бы кэш
	 * целиком
	 */
	EXPECT_GT(cached.load(std::memory_order_relaxed), static_cast <size_t> (0))
	 << "кэш пуст после отдачи памяти системе: рабочий предел не вернулся на место";
}
/**
 * @brief Тест соблюдения потолка взятого у системы при некратном потолке
 *
 * @note Потолок здесь НЕ кратен зернистости выдачи намеренно: у кратного разницы не
 *       видно вовсе - последняя выдача доводит взятое ровно до потолка и на нём
 *       останавливается. Прежде сверка шла с ЗАТРЕБОВАННЫМ размером, а к взятому
 *       прибавлялась целая страница, и потолок перебирался молча
 *
 */
TEST(AllocSourceTest, CeilingHoldsWithUnalignedLimit){
	// Объект выдачи памяти системой
	awh::alloc::SystemSource source;
	// Получаем зернистость выдачи системы
	const size_t grain = source.granularity();
	// Если зернистости у системы не спросить
	if(grain == 0)
		// Проверять нечего
		GTEST_SKIP() << "зернистость выдачи системы не определена";
	// Ставим потолок, НЕ кратный зернистости выдачи
	const size_t limit = ((4u * grain) - 1000u);
	// Задаём потолок взятого у системы
	source.ceiling(limit);
	// Действительно выданный размер области
	size_t served = 0;
	/**
	 * Берём у системы области по одному байту, покуда даёт
	 */
	for(size_t i = 0; i < 8; i++){
		// Берём у системы область в один байт
		if(source.alloc(1, 0, served) == nullptr)
			// Прекращаем набор: потолок исчерпан
			break;
	}
	// Взятое у системы обязано остаться под потолком
	EXPECT_LE(source.taken(), limit);
}
/**
 * @brief Тест неизменности настроек, действующих лишь при заведении
 *
 * @note Утверждается здесь ЧЕСТНОСТЬ ОТВЕТА, а не поведение слоёв: размер занимаемой
 *       области, запрет обращаться к системе и граница разрядов задним числом не
 *       двигаются, и `options()` обязан отдавать действующее значение, а не
 *       затребованное. Приложение, читающее оттуда границу разрядов, иначе получало бы
 *       своё число при действующем прежнем
 *
 */
TEST_F(AllocFixture, StartupOnlySettingsAreNotOverwritten){
	// Снимаем действующие настройки
	const awh::alloc::options_t before = awh::alloc::Allocator::options();
	// Собираем настройки, где все три задаются заново
	awh::alloc::options_t options = before;
	// Задаём иной размер занимаемой области
	options.arena = (before.arena + (16u * 1024u * 1024u));
	// Задаём запрет обращаться к системе
	options.confined = !before.confined;
	// Задаём иную границу разрядов
	options.classLimit = ((before.classLimit > 0) ? (before.classLimit / 2u) : (64u * 1024u));
	// Применяем настройки на ходу
	awh::alloc::Allocator::options(options);
	// Снимаем настройки заново
	const awh::alloc::options_t after = awh::alloc::Allocator::options();
	// Все три обязаны остаться прежними
	EXPECT_EQ(after.arena, before.arena);
	EXPECT_EQ(after.confined, before.confined);
	EXPECT_EQ(after.classLimit, before.classLimit);
}
