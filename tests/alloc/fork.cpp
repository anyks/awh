namespace {
	/**
	 * @brief Метод работы потомка после ветвления
	 *
	 * @note Ответ идёт КОДОМ ВОЗВРАТА, а не печатью: буфер печати достаётся потомку по
	 *       наследству и при `_exit` выбрасывается несброшенным - потомок, печатавший
	 *       ответ, выглядит молчащим
	 *
	 * @return код возврата потомка
	 *
	 */
	static int descendant() noexcept {
		// Выданные блоки
		std::vector <void *> alive;
		/**
		 * Перебираем блоки нагрузки
		 */
		for(size_t i = 0; i < 4096; i++){
			// Выдаём блок изменчивого размера
			void * block = ::malloc(64 + (i % 1024));
			// Если выдать память не вышло
			if(block == nullptr)
				// Отвечаем отказом выдачи
				return 2;
			// Записываем блок
			::memset(block, static_cast <int> (i & 0xFF), 64);
			// Запоминаем выданный блок
			alive.push_back(block);
		}
		/**
		 * Перебираем выданные блоки
		 */
		for(size_t i = 0; i < alive.size(); i++){
			// Получаем содержимое блока
			const uint8_t * bytes = reinterpret_cast <const uint8_t *> (alive[i]);
			// Содержимое обязано уцелеть
			if(bytes[0] != static_cast <uint8_t> (i & 0xFF))
				// Отвечаем порчей содержимого
				return 3;
			// Освобождаем блок
			::free(alive[i]);
		}
		// Отвечаем успехом
		return 0;
	}
	/**
	 * @brief Метод ожидания потомка
	 *
	 * @param pid    номер процесса потомка
	 * @param status код возврата потомка
	 * @return       признак дождавшегося родителя
	 *
	 */
	static bool await(const pid_t pid, int32_t & status) noexcept {
		// Выводим признак дождавшегося родителя
		return (::waitpid(pid, &status, 0) == pid);
	}
};

/**
 * @brief Тест выдачи памяти потомком после ветвления
 *
 * @note Ветвление переносит СОСТОЯНИЕ, но не ПОТОКИ: замок, захваченный не пережившим
 *       ветвление потоком, остался бы захваченным навсегда, и первая же выдача памяти
 *       у потомка встала бы намертво. Оттого зависание здесь обязано кончаться отказом
 *       проверки, а не вечным ожиданием - его обрывает будильник потомка
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterFork){
	// Ветвим процесс
	const pid_t pid = ::fork();
	// Ветвление обязано удаться
	ASSERT_NE(pid, -1);
	// Если это потомок
	if(pid == 0){
		/**
		 * Заводим будильник
		 *
		 * Заклинивший замок вешает потомка навсегда, и родитель ждал бы его вечно:
		 * будильник обращает зависание в отказ проверки
		 */
		::alarm(30);
		// Отвечаем родителю кодом возврата
		::_exit(::descendant());
	}
	// Код возврата потомка
	int32_t status = 0;
	// Родитель обязан дождаться потомка
	ASSERT_TRUE(::await(pid, status));
	// Потомок обязан завершиться сам, а не быть снятым сигналом
	ASSERT_TRUE(WIFEXITED(status)) << "потомок снят сигналом " << WTERMSIG(status) << ": зависание либо падение";
	// Потомок обязан ответить успехом
	EXPECT_EQ(WEXITSTATUS(status), 0);
}
/**
 * @brief Тест ветвления при работающих потоках
 *
 * @note Случай этот и есть опасный: потоки, бравшие замки распределителя прямо в миг
 *       ветвления, потомку не достаются, а взятые ими замки - достаются
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterForkUnderLoad){
	// Признак работы потоков нагрузки
	std::atomic <bool> running(true);
	// Потоки нагрузки
	std::vector <std::thread> workers;
	/**
	 * Заводим потоки нагрузки
	 */
	for(size_t i = 0; i < 4; i++){
		// Заводим поток нагрузки
		workers.emplace_back([&running]() noexcept {
			/**
			 * Держим выдачу памяти занятой, пока родитель ветвится
			 */
			while(running.load(std::memory_order_relaxed)){
				// Выдаём блок
				void * block = ::malloc(4096);
				// Освобождаем блок
				::free(block);
			}
		});
	}
	// Ветвим процесс под нагрузкой
	const pid_t pid = ::fork();
	// Если это потомок
	if(pid == 0){
		// Заводим будильник: заклинивший замок иначе вешает потомка навсегда
		::alarm(30);
		// Отвечаем родителю кодом возврата
		::_exit((pid == -1) ? 4 : ::descendant());
	}
	// Останавливаем потоки нагрузки
	running.store(false, std::memory_order_relaxed);
	/**
	 * Перебираем потоки нагрузки
	 */
	for(auto & worker : workers)
		// Дожидаемся потока нагрузки
		worker.join();
	// Ветвление обязано удаться
	ASSERT_NE(pid, -1);
	// Код возврата потомка
	int32_t status = 0;
	// Родитель обязан дождаться потомка
	ASSERT_TRUE(::await(pid, status));
	// Потомок обязан завершиться сам, а не быть снятым сигналом
	ASSERT_TRUE(WIFEXITED(status)) << "потомок снят сигналом " << WTERMSIG(status) << ": замок пережил ветвление захваченным";
	// Потомок обязан ответить успехом
	EXPECT_EQ(WEXITSTATUS(status), 0);
}

/**
 * @brief Тест ветвления В ОБХОД откликов: потомок обязан не ВИСНУТЬ
 *
 * @details Ветвление, о каком распределителю НЕ сообщили: обращение к системе идёт
 *          напрямую, минуя и `pthread_atfork`, и отклики зоны у macOS
 *
 * @warning Обещание здесь УЖЕ, чем у соседних проверок, и это не упущение, а предел
 *          самого пути. Отклик ветвления берёт замки распределителя ДО ветвления, и
 *          прочие потоки успевают выйти из своих участков - потомку достаётся целое
 *          состояние. Запасный же путь обнаруживает ветвление ПОСЛЕ, когда замки уже
 *          достались захваченными, и умеет он одно: расклинить их. Состояние под
 *          расклиненным замком осталось от потока, снятого посреди правки, и целым
 *          оно не бывает - доказано щупом: потомок валится на чтении связи свободного
 *          блока внутри выдачи сверх разрядов, то есть в куче, снятой посреди правки
 *
 * @note Оттого проверка сторожит ровно то, что запасный путь и обещает: потомок
 *       обязан ЗАВЕРШИТЬСЯ - работой либо сбоем, - но не встать намертво. Зависание и
 *       есть то единственное, чего без запасного пути не миновать, и его ловит будильник
 *
 * @note Случай этот не выдуман. Отклики ветвления не срабатывают у `vfork`, у
 *       `posix_spawn` до подмены образа и у всякого обращения к системе напрямую -
 *       а замки при этом достаются потомку ровно так же захваченными. Распределитель
 *       держит на такой случай запасный путь: замок, не отпущенный тысячу уступок
 *       времени подряд, спрашивает номер процесса, и сменившийся номер означает, что
 *       мы и есть потомок, а держат замок потоки, каких здесь нет
 *
 * @note Проверка эта единственная, что доходит до запасного пути: обе соседние ветвят
 *       через `fork`, и там отклики срабатывают, а запасный путь остаётся нетронутым
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterUnannouncedFork){
	/**
	 * Обращения к системе за ветвлением есть не везде
	 *
	 * У Linux на ARM64 его нет вовсе - там ветвление выражается через `clone`. У
	 * OpenBSD же нет самого `syscall(2)`: система убрала его насовсем, и обратиться
	 * напрямую нельзя ни к какому вызову, хотя номер `SYS_fork` в заголовочном файле
	 * лежит по-прежнему - проверять надо ОБА условия, иначе сборка валится там, где
	 * номер есть, а звать его нечем. Запасный путь от этого никуда не девается, но
	 * проверить его здесь нечем
	 */
	#if !defined(SYS_fork) || defined(__OpenBSD__)
		GTEST_SKIP() << "обращения к системе за ветвлением у этой системы нет";
	/**
	 * У macOS проверить запасный путь нечем, и это свойство СИСТЕМЫ
	 *
	 * Стандартная библиотека там держит номер процесса в памяти и обновляет его в
	 * СВОЕЙ обёртке ветвления. Потомок, обошедший обёртку, читает номер родителя:
	 * замерено щупом - настоящий номер 78851, а `getpid` отвечает 78850, тогда как
	 * обращение к системе напрямую отвечает верно. Запасный путь опознаёт ветвление
	 * сменою номера процесса, и опознать это ветвление он не может вовсе
	 *
	 * Дырой в защите это не является: обходят обёртку `vfork`, где выдавать память
	 * запрещено договором, и обращение к системе напрямую, какое у macOS объявлено
	 * неподдерживаемым в заголовочном файле. У Linux же и BSD номер процесса в памяти
	 * не держится (glibc перестал с 2.25, musl не держал вовсе), и путь этот там
	 * работает - проверка его и сторожит
	 */
	#elif defined(__APPLE__) || defined(__MACH__)
		GTEST_SKIP() << "у macOS номер процесса держится в памяти: ветвление в обход обёртки неотличимо";
	#else
		// Признак работы потоков нагрузки
		std::atomic <bool> running(true);
		// Потоки нагрузки
		std::vector <std::thread> workers;
		/**
		 * Заводим потоки нагрузки
		 *
		 * Нагрузка здесь обязательна: без неё замки в миг ветвления свободны, потомок
		 * не заклинивает вовсе и запасный путь не заводится
		 */
		for(size_t i = 0; i < 4; i++){
			// Заводим поток нагрузки
			workers.emplace_back([&running]() noexcept {
				/**
				 * Держим выдачу памяти занятой, пока родитель ветвится
				 */
				while(running.load(std::memory_order_relaxed)){
					// Выдаём блок сверх разрядов: он идёт под замок кучи, а не в кэш потока
					void * block = ::malloc(64u * 1024u);
					// Освобождаем блок
					::free(block);
				}
			});
		}
		/**
		 * Запоминаем номер СВОЕГО процесса прежде ветвления
		 *
		 * Опознавать потомка ответом обращения к системе НЕЛЬЗЯ: у систем BSD и macOS
		 * обращение это отвечает потомку номером РОДИТЕЛЯ, а нуль подставляет обёртка
		 * стандартной библиотеки, какую мы здесь намеренно обходим. Проверка на нуль
		 * дала бы две ветви, обе считающие себя родителем, - проверено, обе повисли
		 */
		const pid_t before = ::getpid();
		// Ветвим процесс В ОБХОД откликов, обращением к системе напрямую
		const pid_t pid = static_cast <pid_t> (::syscall(SYS_fork));
		// Если это потомок: номер своего процесса сменился
		if((pid != -1) && (::getpid() != before)){
			// Заводим будильник: незамеченное ветвление иначе вешает потомка навсегда
			::alarm(30);
			// Отвечаем родителю кодом возврата
			::_exit(::descendant());
		}
		// Останавливаем потоки нагрузки
		running.store(false, std::memory_order_relaxed);
		/**
		 * Перебираем потоки нагрузки
		 */
		for(auto & worker : workers)
			// Дожидаемся потока нагрузки
			worker.join();
		// Ветвление обязано удаться
		ASSERT_NE(pid, -1);
		// Код возврата потомка
		int32_t status = 0;
		// Родитель обязан дождаться потомка
		ASSERT_TRUE(::await(pid, status));
		/**
		 * Потомок обязан не виснуть
		 *
		 * Зависание кончается будильником, то есть снятием по `SIGALRM`: именно его
		 * здесь и ловим. Сбой же на разорванном состоянии - исход хоть и негодный, но
		 * ЗАКОННЫЙ: расклинить замок запасный путь умеет, а собрать заново то, что
		 * снятый посреди правки поток оставил недописанным, не умеет никто
		 */
		if(!WIFEXITED(status))
			// Снятие будильником означает зависание: запасный путь не сработал
			EXPECT_NE(WTERMSIG(status), SIGALRM) << "потомок повис: запасный путь опознания ветвления не сработал";
	#endif
}

