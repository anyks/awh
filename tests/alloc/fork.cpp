/**
 * @brief Пространство имён вспомогательных средств
 *
 */
namespace {
	/**
	 * @brief Метод работы потомка после ветвления
	 *
	 * @note Ответ идёт КОДОМ ВОЗВРАТА, а не печатью: буфер печати достаётся потомку по
	 *       наследству и при `_exit` выбрасывается несброшенным - потомок, печатавший
	 *       ответ, выглядит молчащим
	 *
	 * @return код возврата потомка
	 *
	 */
	static int descendant() noexcept {
		// Выданные блоки
		std::vector <void *> alive;
		/**
		 * Перебираем блоки нагрузки
		 */
		for(size_t i = 0; i < 4096; i++){
			// Выдаём блок изменчивого размера
			void * block = ::malloc(64 + (i % 1024));
			// Если выдать память не вышло
			if(block == nullptr)
				// Отвечаем отказом выдачи
				return 2;
			// Записываем блок
			::memset(block, static_cast <int> (i & 0xFF), 64);
			// Запоминаем выданный блок
			alive.push_back(block);
		}
		/**
		 * Перебираем выданные блоки
		 */
		for(size_t i = 0; i < alive.size(); i++){
			// Получаем содержимое блока
			const uint8_t * bytes = reinterpret_cast <const uint8_t *> (alive[i]);
			// Содержимое обязано уцелеть
			if(bytes[0] != static_cast <uint8_t> (i & 0xFF))
				// Отвечаем порчей содержимого
				return 3;
			// Освобождаем блок
			::free(alive[i]);
		}
		// Отвечаем успехом
		return 0;
	}
	/**
	 * @brief Метод ожидания потомка
	 *
	 * @param pid    номер процесса потомка
	 * @param status код возврата потомка
	 * @return       признак дождавшегося родителя
	 *
	 */
	/**
	 * Ждём потомка СРОКОМ, а не вечно, и сторожим его отсюда, а не изнутри
	 *
	 * Будильник, заводимый потомком, спасает лишь от того зависания, какое случится
	 * ПОСЛЕ него. А самое опасное случается раньше: обработчик ветвления, приводящий
	 * распределитель в порядок у потомка, исполняется ВНУТРИ самого `fork` - и, встань
	 * он на захваченном замке, потомок не дойдёт даже до первой своей команды.
	 * Будильник при этом не заведётся никогда
	 *
	 * Доказано подменой: у потомка отняли освобождение замков центральных списков, и
	 * набор ПОВИС - на четыре с лишним минуты и дальше. Щуп, поставленный самым первым
	 * действием потомка, следа в файле не оставил: туда попросту не дошли
	 *
	 * Оттого сторож стоит у РОДИТЕЛЯ: тот жив, работоспособен и волен снять зависшего
	 * потомка силой. Так зависание обращается в отказ проверки, откуда бы оно ни взялось,
	 * - а зависший набор от исправного неотличим и останавливает работу молча
	 */
	static bool await(const pid_t pid, int32_t & status) noexcept {
		// Предельный срок ожидания потомка в десятых долях секунды
		const size_t deadline = (60u * 10u);
		/**
		 * Опрашиваем потомка, не засыпая на нём насовсем
		 */
		for(size_t i = 0; i < deadline; i++){
			// Опрашиваем потомка, не блокируясь
			const pid_t answered = ::waitpid(pid, &status, WNOHANG);
			// Если потомок ответил
			if(answered == pid)
				// Родитель дождался потомка
				return true;
			// Если опрос отказал вовсе
			if(answered == -1)
				// Ждать больше некого
				return false;
			// Ждём десятую долю секунды
			::usleep(100000);
		}
		/**
		 * Снимаем зависшего потомка силой
		 *
		 * Снимаем ОБЯЗАТЕЛЬНО: оставленный жить, он держал бы за собою память и
		 * дескрипторы до конца прогона, а следующая проверка ветвления встретила бы его
		 * соседом
		 */
		// Снимаем потомка силой
		static_cast <void> (::kill(pid, SIGKILL));
		// Подбираем снятого потомка
		static_cast <void> (::waitpid(pid, &status, 0));
		// Родитель потомка не дождался
		return false;
	}
};

/**
 * @brief Тест выдачи памяти потомком после ветвления
 *
 * @note Ветвление переносит СОСТОЯНИЕ, но не ПОТОКИ: замок, захваченный не пережившим
 *       ветвление потоком, остался бы захваченным навсегда, и первая же выдача памяти
 *       у потомка встала бы намертво. Оттого зависание здесь обязано кончаться отказом
 *       проверки, а не вечным ожиданием - его обрывает будильник потомка
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterFork){
	// Ветвим процесс
	const pid_t pid = ::fork();
	// Ветвление обязано удаться
	ASSERT_NE(pid, -1);
	// Если это потомок
	if(pid == 0){
		/**
		 * Заводим будильник
		 *
		 * Заклинивший замок вешает потомка навсегда, и родитель ждал бы его вечно:
		 * будильник обращает зависание в отказ проверки
		 */
		::alarm(30);
		// Отвечаем родителю кодом возврата
		::_exit(::descendant());
	}
	// Код возврата потомка
	int32_t status = 0;
	// Родитель обязан дождаться потомка
	ASSERT_TRUE(::await(pid, status)) << "потомок не ответил за отведённый срок: зависание";
	// Потомок обязан завершиться сам, а не быть снятым сигналом
	ASSERT_TRUE(WIFEXITED(status)) << "потомок снят сигналом " << WTERMSIG(status) << ": зависание либо падение";
	// Потомок обязан ответить успехом
	EXPECT_EQ(WEXITSTATUS(status), 0);
}
/**
 * @brief Тест ветвления при работающих потоках
 *
 * @note Случай этот и есть опасный: потоки, бравшие замки распределителя прямо в миг
 *       ветвления, потомку не достаются, а взятые ими замки - достаются
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterForkUnderLoad){
	// Признак работы потоков нагрузки
	std::atomic <bool> running(true);
	// Потоки нагрузки
	std::vector <std::thread> workers;
	/**
	 * Заводим потоки нагрузки
	 */
	for(size_t i = 0; i < 4; i++){
		// Заводим поток нагрузки
		workers.emplace_back([&running]() noexcept {
			/**
			 * Держим выдачу памяти занятой, пока родитель ветвится
			 */
			while(running.load(std::memory_order_relaxed)){
				// Выдаём блок
				void * block = ::malloc(4096);
				// Освобождаем блок
				::free(block);
			}
		});
	}
	// Ветвим процесс под нагрузкой
	const pid_t pid = ::fork();
	// Если это потомок
	if(pid == 0){
		// Заводим будильник: заклинивший замок иначе вешает потомка навсегда
		::alarm(30);
		// Отвечаем родителю кодом возврата
		::_exit((pid == -1) ? 4 : ::descendant());
	}
	// Останавливаем потоки нагрузки
	running.store(false, std::memory_order_relaxed);
	/**
	 * Перебираем потоки нагрузки
	 */
	for(auto & worker : workers)
		// Дожидаемся потока нагрузки
		worker.join();
	// Ветвление обязано удаться
	ASSERT_NE(pid, -1);
	// Код возврата потомка
	int32_t status = 0;
	// Родитель обязан дождаться потомка
	ASSERT_TRUE(::await(pid, status)) << "потомок не ответил за отведённый срок: зависание";
	// Потомок обязан завершиться сам, а не быть снятым сигналом
	ASSERT_TRUE(WIFEXITED(status)) << "потомок снят сигналом " << WTERMSIG(status) << ": замок пережил ветвление захваченным";
	// Потомок обязан ответить успехом
	EXPECT_EQ(WEXITSTATUS(status), 0);
}

/**
 * @brief Тест ветвления при переписываемых откликах доклада
 *
 * @details Отклики доклада хранятся в `std::function`, и присваивание им идёт через
 *          выдачу памяти. Ветвление посреди присваивания обязано оставлять потомку
 *          отклик ЦЕЛЫМ - иначе разрушение его у потомка уйдёт по дикому адресу
 *
 * @note Прежде замок откликов перед ветвлением НЕ захватывался, тогда как соседний
 *       замок кольца докладов захватывался. У потомка он приводился в порядок - и в
 *       этом была вся беда: приведение замка в порядок ничего не говорит о ДАННЫХ под
 *       ним. Щупом отмерено: поток без устали переписывает отклик, а главный ветвится
 *       три тысячи раз и снимает отклик у потомка - пала ТРЕТЬ потомков, 1056 из 3000,
 *       все по SIGSEGV. С захватом замка - ни одного, и так три прогона подряд
 *
 * @note Соседняя проверка под нагрузкой ветвит при занятой ВЫДАЧЕ памяти, а эта - при
 *       занятых ОТКЛИКАХ: пути это разные, и второй не покрывался ничем
 *
 * @note Ветвлений здесь немного: окно широкое, и при прежнем коде первый павший потомок
 *       приходился на восьмой оборот. Держать их тысячами значило бы платить временем
 *       набора за уже доказанное
 *
 */
TEST_F(AllocFixture, DescendantSurvivesForkWhileCallbacksChange){
	// Признак работы потока, переписывающего отклик
	std::atomic <bool> running(true);
	/**
	 * Заводим поток, без устали переписывающий отклик
	 *
	 * Отклик захватывает крупный груз намеренно: так он не помещается в собственный
	 * запас `std::function`, присваивание уходит в выдачу памяти, и окно, в каком отклик
	 * лежит недописанным, становится шире
	 */
	std::thread setter([&running]() noexcept {
		// Номер оборота, он же груз отклика
		size_t round = 0;
		/**
		 * Переписываем отклик, пока родитель не остановит
		 */
		while(running.load(std::memory_order_relaxed)){
			// Груз отклика: семь чисел не помещаются в запас std::function
			const size_t a = round, b = (round + 1), c = (round + 2), d = (round + 3);
			const size_t e = (round + 4), f = (round + 5), g = (round + 6);
			// Ставим отклик на крупное выделение
			awh::alloc::Allocator::onLarge([a, b, c, d, e, f, g](const void *, const size_t) noexcept {
				// Груз обязан быть употреблён, иначе собиратель выбросит его вместе с выдачей
				volatile size_t sum = (a + b + c + d + e + f + g);
				// Употребляем сумму
				static_cast <void> (sum);
			});
			// Переходим к следующему обороту
			round++;
		}
	});
	// Число павших потомков
	size_t broken = 0;
	// Сигнал, каким снят первый павший потомок
	int32_t signalled = 0;
	// Оборот, на каком пал первый потомок
	size_t culprit = 0;
	/**
	 * Ветвимся раз за разом, разбирая отклик у потомка
	 */
	for(size_t i = 0; i < 48; i++){
		// Ветвим процесс
		const pid_t pid = ::fork();
		// Если ветвление отказало
		if(pid == -1)
			// Ветвиться больше нечем
			break;
		// Если это потомок
		if(pid == 0){
			// Заводим будильник: заклинивший замок иначе вешает потомка навсегда
			::alarm(30);
			/**
			 * Снимаем отклик
			 *
			 * Снятие РАЗРУШАЕТ прежний `std::function`. Достанься тот недописанным -
			 * разрушение уйдёт по дикому адресу
			 */
			awh::alloc::Allocator::onLarge(nullptr);
			// Отвечаем родителю работой с памятью
			::_exit(::descendant());
		}
		// Код возврата потомка
		int32_t status = 0;
		// Родитель обязан дождаться потомка
		if(!::await(pid, status)){
			// Считаем потомка павшим: не ответил за отведённый срок
			broken++;
			// Переходим к следующему обороту
			continue;
		}
		// Если потомок завершился сам и ответил успехом
		if(WIFEXITED(status) && (WEXITSTATUS(status) == 0))
			// Переходим к следующему обороту
			continue;
		// Если павший потомок первый
		if(broken == 0){
			// Запоминаем сигнал, каким он снят
			signalled = (WIFSIGNALED(status) ? WTERMSIG(status) : 0);
			// Запоминаем оборот, на каком он пал
			culprit = i;
		}
		// Считаем потомка павшим
		broken++;
	}
	// Останавливаем поток, переписывающий отклик
	running.store(false, std::memory_order_relaxed);
	// Дожидаемся потока
	setter.join();
	// Снимаем отклик у родителя: он ставился потоком и живёт дольше проверки
	awh::alloc::Allocator::onLarge(nullptr);
	// Ни один потомок пасть не обязан
	EXPECT_EQ(broken, static_cast <size_t> (0))
	 << "пало потомков: " << broken << " из 48; первый на обороте " << culprit
	 << ", снят сигналом " << signalled << " - отклик достался ему недописанным";
}

/**
 * @brief Тест ветвления В ОБХОД откликов: потомок обязан не ВИСНУТЬ
 *
 * @details Ветвление, о каком распределителю НЕ сообщили: обращение к системе идёт
 *          напрямую, минуя и `pthread_atfork`, и отклики зоны у macOS
 *
 * @warning Обещание здесь УЖЕ, чем у соседних проверок, и это не упущение, а предел
 *          самого пути. Отклик ветвления берёт замки распределителя ДО ветвления, и
 *          прочие потоки успевают выйти из своих участков - потомку достаётся целое
 *          состояние. Запасный же путь обнаруживает ветвление ПОСЛЕ, когда замки уже
 *          достались захваченными, и умеет он одно: расклинить их. Состояние под
 *          расклиненным замком осталось от потока, снятого посреди правки, и целым
 *          оно не бывает - доказано щупом: потомок валится на чтении связи свободного
 *          блока внутри выдачи сверх разрядов, то есть в куче, снятой посреди правки
 *
 * @note Оттого проверка сторожит ровно то, что запасный путь и обещает: потомок
 *       обязан ЗАВЕРШИТЬСЯ - работой либо сбоем, - но не встать намертво. Зависание и
 *       есть то единственное, чего без запасного пути не миновать, и его ловит будильник
 *
 * @note Случай этот не выдуман. Отклики ветвления не срабатывают у `vfork`, у
 *       `posix_spawn` до подмены образа и у всякого обращения к системе напрямую -
 *       а замки при этом достаются потомку ровно так же захваченными. Распределитель
 *       держит на такой случай запасный путь: замок, не отпущенный тысячу уступок
 *       времени подряд, спрашивает номер процесса, и сменившийся номер означает, что
 *       мы и есть потомок, а держат замок потоки, каких здесь нет
 *
 * @note Проверка эта единственная, что доходит до запасного пути: обе соседние ветвят
 *       через `fork`, и там отклики срабатывают, а запасный путь остаётся нетронутым
 *
 */
TEST_F(AllocFixture, DescendantAllocatesAfterUnannouncedFork){
	/**
	 * Обращения к системе за ветвлением есть не везде
	 *
	 * У Linux на ARM64 его нет вовсе - там ветвление выражается через `clone`. У
	 * OpenBSD же нет самого `syscall(2)`: система убрала его насовсем, и обратиться
	 * напрямую нельзя ни к какому вызову, хотя номер `SYS_fork` в заголовочном файле
	 * лежит по-прежнему - проверять надо ОБА условия, иначе сборка валится там, где
	 * номер есть, а звать его нечем. Запасный путь от этого никуда не девается, но
	 * проверить его здесь нечем
	 */
	#if !defined(SYS_fork) || defined(__OpenBSD__)
		GTEST_SKIP() << "обращения к системе за ветвлением у этой системы нет";
	/**
	 * У macOS проверить запасный путь нечем, и это свойство СИСТЕМЫ
	 *
	 * Стандартная библиотека там держит номер процесса в памяти и обновляет его в
	 * СВОЕЙ обёртке ветвления. Потомок, обошедший обёртку, читает номер родителя:
	 * замерено щупом - настоящий номер 78851, а `getpid` отвечает 78850, тогда как
	 * обращение к системе напрямую отвечает верно. Запасный путь опознаёт ветвление
	 * сменою номера процесса, и опознать это ветвление он не может вовсе
	 *
	 * Дырой в защите это не является: обходят обёртку `vfork`, где выдавать память
	 * запрещено договором, и обращение к системе напрямую, какое у macOS объявлено
	 * неподдерживаемым в заголовочном файле. У Linux же и BSD номер процесса в памяти
	 * не держится (glibc перестал с 2.25, musl не держал вовсе), и путь этот там
	 * работает - проверка его и сторожит
	 */
	#elif defined(__APPLE__) || defined(__MACH__)
		GTEST_SKIP() << "у macOS номер процесса держится в памяти: ветвление в обход обёртки неотличимо";
	#else
		// Признак работы потоков нагрузки
		std::atomic <bool> running(true);
		// Потоки нагрузки
		std::vector <std::thread> workers;
		/**
		 * Заводим потоки нагрузки
		 *
		 * Нагрузка здесь обязательна: без неё замки в миг ветвления свободны, потомок
		 * не заклинивает вовсе и запасный путь не заводится
		 */
		for(size_t i = 0; i < 4; i++){
			// Заводим поток нагрузки
			workers.emplace_back([&running]() noexcept {
				/**
				 * Держим выдачу памяти занятой, пока родитель ветвится
				 */
				while(running.load(std::memory_order_relaxed)){
					// Выдаём блок сверх разрядов: он идёт под замок кучи, а не в кэш потока
					void * block = ::malloc(64u * 1024u);
					// Освобождаем блок
					::free(block);
				}
			});
		}
		/**
		 * Запоминаем номер СВОЕГО процесса прежде ветвления
		 *
		 * Опознавать потомка ответом обращения к системе НЕЛЬЗЯ: у систем BSD и macOS
		 * обращение это отвечает потомку номером РОДИТЕЛЯ, а нуль подставляет обёртка
		 * стандартной библиотеки, какую мы здесь намеренно обходим. Проверка на нуль
		 * дала бы две ветви, обе считающие себя родителем, - проверено, обе повисли
		 */
		const pid_t before = ::getpid();
		// Ветвим процесс В ОБХОД откликов, обращением к системе напрямую
		const pid_t pid = static_cast <pid_t> (::syscall(SYS_fork));
		// Если это потомок: номер своего процесса сменился
		if((pid != -1) && (::getpid() != before)){
			// Заводим будильник: незамеченное ветвление иначе вешает потомка навсегда
			::alarm(30);
			// Отвечаем родителю кодом возврата
			::_exit(::descendant());
		}
		// Останавливаем потоки нагрузки
		running.store(false, std::memory_order_relaxed);
		/**
		 * Перебираем потоки нагрузки
		 */
		for(auto & worker : workers)
			// Дожидаемся потока нагрузки
			worker.join();
		// Ветвление обязано удаться
		ASSERT_NE(pid, -1);
		// Код возврата потомка
		int32_t status = 0;
		// Родитель обязан дождаться потомка
		ASSERT_TRUE(::await(pid, status)) << "потомок не ответил за отведённый срок: зависание";
		/**
		 * Потомок обязан не виснуть
		 *
		 * Зависание кончается будильником, то есть снятием по `SIGALRM`: именно его
		 * здесь и ловим. Сбой же на разорванном состоянии - исход хоть и негодный, но
		 * ЗАКОННЫЙ: расклинить замок запасный путь умеет, а собрать заново то, что
		 * снятый посреди правки поток оставил недописанным, не умеет никто
		 */
		if(!WIFEXITED(status))
			// Снятие будильником означает зависание: запасный путь не сработал
			EXPECT_NE(WTERMSIG(status), SIGALRM) << "потомок повис: запасный путь опознания ветвления не сработал";
	#endif
}

/**
 * @brief Тест выживания при отказе системы завести поток обслуживания
 *
 * @details Поток обслуживания заводится распределителем при постановке отклика да при
 *          правке настроек, и заводится вызовом `new std::thread`. Конструктор потока
 *          БРОСАЕТ исключение, когда система в потоке отказывает, - а метод заведения
 *          объявлен `noexcept`. Распределитель убивал этим процесс целиком
 *
 * @details Найдено щупом, исчерпавшим запас потоков системы: 12287 заведённых потоков,
 *          затем `Allocator::onLimit` - и `libc++abi: terminating due to uncaught
 *          exception ... Resource temporarily unavailable`, код возврата 134.
 *          Распределитель памяти обязан переживать нехватку средств системы, а не
 *          гибнуть от неё: это ровно то положение, ради которого он и нужен
 *
 * @note Идём ветвлением и пределом числа потоков, а не заведением двенадцати тысяч
 *       потоков: предел стоит одного вызова, а потомок уносит его с собою и не задевает
 *       ни прогона, ни соседних проверок
 *
 */
TEST(ForkFixture, SurvivesThreadStarvation){
	/**
	 * Под санитайзером захвата нет, а без захвата проверять нечего
	 */
	#if AWH_ALLOC_SANITIZED
		GTEST_SKIP() << "захват под санитайзером не состоится";
	#else
		// Ветвим процесс
		const pid_t pid = ::fork();
		// Ветвление обязано состояться
		ASSERT_NE(pid, -1);
		/**
		 * Работа потомка
		 */
		if(pid == 0){
			/**
			 * Запрещаем потомку заводить потоки вовсе
			 *
			 * Предел в один поток означает, что заведение откажет наверняка: так отказ
			 * системы получается одним вызовом, а не исчерпанием запаса. Исчерпание
			 * запаса тоже работает - щуп доводил его до 12287 потоков, - но стоит оно
			 * шести секунд и полутора тысяч процентов ядра, а проверки идут и на стендах
			 *
			 * Предел берётся свой на систему: у NetBSD и OpenBSD потоки считает
			 * `RLIMIT_NTHR`, у Linux - `RLIMIT_NPROC`, а у macOS и FreeBSD предела по
			 * потокам нет вовсе. Проверено щупом здесь же: при `RLIMIT_NPROC` в единицу
			 * поток у macOS заводится как ни в чём не бывало
			 */
			#if defined(RLIMIT_NTHR)
				// Предел числа потоков процесса
				const int32_t what = RLIMIT_NTHR;
			#else
				// Предел числа процессов пользователя
				const int32_t what = RLIMIT_NPROC;
			#endif
			// Предел, ограничивающий заведение потоков
			struct rlimit bound;
			// Спрашиваем действующий предел
			if(::getrlimit(what, &bound) == 0){
				// Опускаем мягкий предел до одного
				bound.rlim_cur = 1;
				// Ставим опущенный предел
				static_cast <void> (::setrlimit(what, &bound));
			}
			/**
			 * Сверяем, что предел И ВПРЯМЬ кусается
			 *
			 * Иначе проверка прошла бы и на негодном коде: подмена, снявшая готовность к
			 * отказу, у macOS проходила её как ни в чём не бывало - предел там по потокам
			 * не считает вовсе. Пропуск честнее ложного успеха
			 */
			{
				// Признак заведённого пробного потока
				bool started = false;
				/**
				 * Пробуем завести поток сами
				 */
				try {
					// Заводим пробный поток
					std::thread probe([](){});
					// Дожидаемся пробного потока
					probe.join();
					// Отмечаем пробный поток заведённым
					started = true;
				// Если система отказала в заведении потока
				} catch(...) {
					// Отказ и требуется: предел кусается
					started = false;
				}
				// Если предел по потокам система не считает
				if(started)
					// Выходим с признаком непригодности системы
					::_exit(42);
			}
			/**
			 * Просим распределитель завести поток обслуживания
			 *
			 * Отказ системы обязан обернуться отказом заведения, а не гибелью процесса
			 */
			awh::alloc::Allocator::onLimit([](const size_t){});
			/**
			 * Выдача памяти обязана работать и после отказа
			 */
			// Выдаём блок памяти
			void * block = ::malloc(4096);
			// Если блок не выдан
			if(block == nullptr)
				// Выходим с признаком отказа выдачи
				::_exit(3);
			// Возвращаем выданный блок
			::free(block);
			// Выходим с признаком успеха
			::_exit(0);
		}
		// Код возврата потомка
		int32_t status = 0;
		// Родитель обязан дождаться потомка
		ASSERT_TRUE(::await(pid, status)) << "потомок не ответил за отведённый срок: зависание";
		/**
		 * Потомок обязан выйти сам, а не быть снятым
		 *
		 * Необработанное исключение из `noexcept` кончается `std::terminate`, то есть
		 * снятием по `SIGABRT`: именно его здесь и ловим
		 */
		ASSERT_TRUE(WIFEXITED(status))
		 << "потомок снят сигналом " << (WIFSIGNALED(status) ? WTERMSIG(status) : 0)
		 << ": отказ системы завести поток убил процесс";
		// Если система предела по потокам не считает
		if(WEXITSTATUS(status) == 42)
			// Пропускаем проверку: отказ заведения здесь не подстроить
			GTEST_SKIP() << "система не ограничивает число потоков: отказ заведения здесь не подстроить";
		// Потомок обязан отчитаться успехом
		EXPECT_EQ(WEXITSTATUS(status), 0) << "потомок отчитался кодом " << WEXITSTATUS(status);
	#endif
}

