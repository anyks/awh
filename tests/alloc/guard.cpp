/**
 * @brief Тест действующих заслонов
 *
 * @note Заслон кладёт блок вплотную к концу страницы, а следующую страницу закрывает:
 *       запись за конец блока валит программу немедля, а не портит соседа. Проверяется
 *       это по СЛЕДУ - концу блока на границе страницы, - а не по признаку настройки:
 *       заслон, взятый и не поставленный, признаком от рабочего не отличить
 *
 * @warning След берётся по ПРИВЕДЁННОМУ размеру и по НАСТОЯЩЕЙ странице системы, а
 *          порог сличается с числом, какое велит выборка. Прежде проверка сличала
 *          заказанный размер с постоянной 4096, и обе ошибки складывались в
 *          бессмыслицу: заслон кладёт блок по границе приведённого к шестнадцати
 *          размера, оттого признак ловил лишь одну заслонённую выдачу из шестнадцати,
 *          а страница у macOS вчетверо шире 4096, оттого в счёт попадали и обычные
 *          блоки. Подмена доказала цену прежней проверки числом: с работающими
 *          заслонами 11 из 4096, с выключенными - 12. Порог «хоть один» проходил и
 *          при заслонах, выключенных насовсем
 *
 */
TEST_F(AllocFixture, GuardsAreActuallyPlaced){
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём выборку заслонов: один блок из шестнадцати
	options.guardRate = 16;
	// Задаём объём карантина
	options.quarantine = (256u * 1024u);
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	// Выданные блоки
	std::vector <void *> alive;
	/**
	 * Выдаём вдоволь: выборка берёт одну выдачу из шестнадцати
	 */
	for(size_t i = 0; i < 4096; i++){
		// Выдаём блок изменчивого размера
		void * block = ::malloc(64 + (i % 512));
		// Запоминаем выданный блок
		if(block != nullptr)
			// Добавляем блок в список живых
			alive.push_back(block);
	}
	// Число заслонённых блоков
	size_t sealed = 0;
	/**
	 * Спрашиваем зернистость У САМОГО ИСТОЧНИКА, а не у системы
	 *
	 * @note Заслон кладёт блок по границе, какую даёт `granularity()` источника, - и
	 *       сличать надо ровно с нею. Спроси проверка систему напрямую, она бы у MS
	 *       Windows разошлась с заслоном вчетверо с лишним: `GetSystemInfo` отвечает
	 *       там `dwPageSize` в 4 КБ, тогда как выдача идёт зернистостью
	 *       `dwAllocationGranularity` в 64 КБ, и её-то источник и выводит. Расхождение
	 *       это ослабляет проверку молча - под признак попадают блоки, заслонёнными не
	 *       являющиеся
	 *
	 * @note Заодно уходит и ветвление по системам: у MinGW `sysconf` не объявлен вовсе,
	 *       и одна эта строка прежде не давала собраться ВСЕМУ набору
	 */
	// Получаем действующий источник страниц
	awh::alloc::source_t * source = awh::alloc::Allocator::source();
	// Источник обязан быть заведён: без него сличать не с чем
	ASSERT_NE(source, nullptr);
	// Получаем зернистость выдачи источника
	const size_t page = source->granularity();
	// Зернистость обязана быть определена: без неё сличать не с чем
	ASSERT_GT(page, static_cast <size_t> (0));
	/**
	 * Перебираем живые блоки
	 */
	for(void * block : alive){
		// Разбираем адрес блока
		const awh::alloc::region_t region = awh::alloc::Allocator::resolve(block);
		// Если блок не опознан
		if(region.size == 0)
			// Переходим к следующему блоку
			continue;
		// Приводим размер к границе выравнивания: заслон кладёт блок именно по ней
		const size_t aligned = ((region.size + 15u) & ~static_cast <size_t> (15u));
		// У заслонённого блока конец совпадает с границей страницы системы
		if(((reinterpret_cast <uintptr_t> (block) + aligned) % page) == 0)
			// Считаем заслонённый блок
			sealed++;
	}
	/**
	 * Заслонённых блоков обязано быть столько, сколько велит выборка
	 *
	 * Порог берётся вдвое ниже ожидаемого - выборка идёт по счётчику, а не по числу
	 * дошедших до неё выдач, - но НАМНОГО выше случайных совпадений: обычный блок
	 * оканчивается ровно на границе страницы изредка. Порогом «хоть один» проверка
	 * проходила и при заслонах, выключенных насовсем
	 */
	EXPECT_GT(sealed, (alive.size() / 32u))
	 << "заслонено " << sealed << " из " << alive.size() << " при выборке одного из 16";
	/**
	 * Перебираем живые блоки
	 */
	for(void * block : alive)
		// Освобождаем блок
		::free(block);
}
/**
 * @brief Тест опознания освобождённого блока
 *
 * @note Карантин держит освобождённое некоторое время, и разбор адреса обязан назвать
 *       такой блок освобождённым: ровно это отличает висячий указатель от чужой памяти
 *
 */
TEST_F(AllocFixture, FreedBlockIsRecognized){
	// Получаем действующие настройки
	awh::alloc::options_t options = awh::alloc::Allocator::options();
	// Задаём выборку заслонов
	options.guardRate = 1;
	// Задаём объём карантина
	options.quarantine = (256u * 1024u);
	// Применяем настройки
	awh::alloc::Allocator::options(options);
	// Выдаём блок
	void * block = ::malloc(512);
	ASSERT_NE(block, nullptr);
	// Записываем блок целиком
	::memset(block, 0x77, 512);
	// Живой блок обязан опознаваться живым
	EXPECT_EQ(awh::alloc::Allocator::resolve(block).origin, awh::alloc::origin_t::LIVE);
	// Освобождаем блок
	::free(block);
	// Освобождённый блок обязан опознаваться освобождённым
	EXPECT_EQ(awh::alloc::Allocator::resolve(block).origin, awh::alloc::origin_t::FREED);
}
