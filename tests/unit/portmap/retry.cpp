#include "igd.hpp"
#include "portmap.hpp"

/**
 * @brief Срок ожидания ответа маршрутизатора в тестах в миллисекундах
 *
 * @note Срок берётся коротким намеренно: проверка ждёт его столько раз, сколько
 *       задано попыток, и длинный превратил бы набор в испытание терпения
 *
 */
static constexpr uint32_t TEST_DELAY = 200;

/**
 * @brief Порт дейтаграммных договоров перенаправления портов
 *
 */
static constexpr uint16_t DATAGRAM_PORT = 5351;

/**
 * @brief Внутренние средства проверки повторных обращений
 *
 */
namespace {
	/**
	 * @brief Молчащий приёмник просьб
	 *
	 * @details Отвечать он не умеет вовсе - в том и смысл: модуль обязан повторить
	 *          просьбу столько раз, сколько задано настройкой, а приёмник их считает.
	 *          Прежде проверка слала просьбы в сеть, отведённую договором RFC 5737 под
	 *          примеры, и считать их было некому - оттого попытки и мерялись временем
	 *
	 * @note Гнездо слушает любой адрес машины, а не одну лишь петлю: модуль заводит
	 *       на каждую попытку новое гнездо, и повторная просьба уходит уже с иного
	 *       местного адреса
	 *
	 */
	class SilentRouter {
		private:
			// Гнездо приёма просьб
			int _socket;
			// Признак того, что приём ведётся
			std::atomic <bool> _working;
			// Количество принятых просьб
			std::atomic <int32_t> _requests;
			// Поток приёма просьб
			std::thread _thread;
		public:
			/**
			 * @brief Метод получения признака готовности приёмника
			 *
			 * @return готов ли приёмник принимать просьбы
			 *
			 */
			bool ready() const noexcept {
				// Выводим признак готовности приёмника
				return (this->_socket >= 0);
			}
			/**
			 * @brief Метод получения количества принятых просьб
			 *
			 * @return количество принятых просьб
			 *
			 */
			int32_t requests() const noexcept {
				// Выводим количество принятых просьб
				return this->_requests.load();
			}
			/**
			 * @brief Метод запуска приёма просьб
			 *
			 */
			void start() noexcept {
				// Если приёмник не готов, приём не начинаем
				if(!this->ready()) return;
				// Запоминаем, что приём ведётся
				this->_working.store(true);
				// Выполняем запуск потока приёма просьб
				this->_thread = std::thread([this]() noexcept -> void {
					// Место под принятую просьбу
					uint8_t buffer[256] = {0};
					/**
					 * Выполняем приём, пока работа не прекращена
					 */
					while(this->_working.load()){
						// Выполняем чтение очередной просьбы
						const ssize_t size = ::recvfrom(this->_socket, reinterpret_cast <char *> (buffer), sizeof(buffer), 0, nullptr, nullptr);
						// Если просьба принята, запоминаем её
						if(size > 0) this->_requests.fetch_add(1);
					}
				});
			}
			/**
			 * @brief Метод остановки приёма просьб
			 *
			 */
			void stop() noexcept {
				// Если приём не ведётся, останавливать нечего
				if(!this->_working.exchange(false)) return;
				// Выполняем ожидание завершения потока приёма просьб
				if(this->_thread.joinable()) this->_thread.join();
			}
		public:
			/**
			 * @brief Конструктор
			 *
			 */
			SilentRouter() noexcept : _socket(-1), _working(false), _requests(0) {
				// Выполняем заведение гнезда приёма просьб
				this->_socket = ::socket(AF_INET, SOCK_DGRAM, 0);
				// Если гнездо приёма просьб завести не удалось, приёмник негоден
				if(this->_socket < 0) return;
				/**
				 * Устанавливаем срок ожидания приёма просьбы
				 *
				 * @note Срок обязателен: без него поток приёма спит до первой просьбы, и
				 *       закрытие гнезда из другого потока его не будит - остановка приёмника
				 *       повисла бы навсегда
				 */
				::setReceiveTimeout(this->_socket, 100);
				// Отключаем отчёт о недоступности получателя, теряющий дейтаграммы
				::disableConnectionReset(this->_socket);
				// Адрес приёмника просьб
				struct sockaddr_in address;
				// Выполняем очистку адреса приёмника просьб
				::memset(&address, 0, sizeof(address));
				// Устанавливаем разновидность сети
				address.sin_family = AF_INET;
				// Устанавливаем порт дейтаграммных договоров
				address.sin_port = htons(DATAGRAM_PORT);
				// Устанавливаем любой адрес машины
				address.sin_addr.s_addr = htonl(INADDR_ANY);
				/**
				 * Если привязать гнездо к порту договора не удалось
				 *
				 * @note Порт бывает занят настоящей службой перенаправления, и тогда
				 *       испытание не проводится, а не объявляется неудачным
				 */
				if(::bind(this->_socket, reinterpret_cast <struct sockaddr *> (&address), sizeof(address)) != 0){
					// Выполняем закрытие гнезда приёма просьб
					::closesocket(this->_socket);
					// Сбрасываем дескриптор гнезда приёма просьб
					this->_socket = -1;
				}
			}
			/**
			 * @brief Деструктор
			 *
			 */
			~SilentRouter() noexcept {
				// Выполняем остановку приёма просьб
				this->stop();
				// Если гнездо приёма просьб заведено, выполняем его закрытие
				if(this->_socket >= 0) ::closesocket(this->_socket);
			}
	};
}


/**
 * @brief Проверка счёта попыток обращения по дейтаграммному договору
 *
 * @details Маршрутизатор молчит, и модуль обязан повторить просьбу столько раз,
 *          сколько задано настройкой. Сличается **число дошедших просьб**, какое
 *          считает молчащий приёмник этой же машины
 *
 * @note Прежде проверка мерила потраченное время и сличала его с произведением
 *       срока на попытки. Замена эта подвела: время зависит от зерна таймера
 *       системы, а число попыток - нет. У MS Windows зерно 15.6 мс, и ожидание в
 *       200 мс кончалось через 199, отчего проверка падала на целой миллисекунде,
 *       не найдя в работе модуля ни единого изъяна
 *
 */
TEST_F(PortmapUnitFixture, PortmapDatagramAttempts) {
	/**
	 * Выполняем перебор проверяемых количеств попыток
	 */
	for(const uint8_t attempts : {static_cast <uint8_t> (1), static_cast <uint8_t> (3)}){
		// Создаём молчащий приёмник просьб, считающий их за маршрутизатора
		SilentRouter router;
		// Если порт договора занят, испытание не проводится
		if(!router.ready()) GTEST_SKIP() << "порт дейтаграммного договора занят";
		// Выполняем запуск молчащего приёмника просьб
		router.start();
		// Создаём объект модуля перенаправления портов
		awh::unit::portmap_t portmap(this->_fmk.get(), this->_log.get());
		// Устанавливаем вид опроса маршрутизатора
		portmap.setType(awh::unit::portmap_t::type_t::NAT_PMP);
		// Устанавливаем адрес молчащего приёмника просьб
		portmap.setRouter("127.0.0.1");
		// Устанавливаем срок ожидания ответа маршрутизатора
		portmap.setTimeout(TEST_DELAY);
		// Устанавливаем количество попыток обращения к маршрутизатору
		portmap.setAttempts(attempts);
		// Выполняем ожидание итога обращения к маршрутизатору
		const outcome_t outcome = this->await(portmap, awh::unit::portmap_t::action_t::OPEN);
		// Выполняем остановку молчащего приёмника просьб
		router.stop();
		// Выполняем проверку того, что маршрутизатор не ответил
		ASSERT_FALSE(outcome.answered);
		// Выполняем проверку того, что обращение завершилось отказом
		ASSERT_TRUE(outcome.failed);
		// Выполняем проверку кода причины отказа перенаправления
		ASSERT_EQ(outcome.error, awh::unit::portmap_t::error_t::NO_RESPONSE);
		// Выполняем проверку договора, по которому получен итог
		ASSERT_EQ(outcome.type, awh::unit::portmap_t::type_t::NAT_PMP);
		/**
		 * Выполняем проверку того, что попыток выполнено столько, сколько задано
		 *
		 * @note Сличается число дошедших просьб, а не потраченное время: время зависит
		 *       от зерна таймера системы, а счёт просьб от него свободен
		 */
		ASSERT_EQ(router.requests(), static_cast <int32_t> (attempts));
	}
}

/**
 * @brief Проверка повторной рассылки обнаружения устройства UPnP
 *
 * @details Ветвь эта повторяет не просьбу маршрутизатору, а рассылку: просьбы
 *          собирает кодек договора, а у UPnP на шаге обнаружения просьбы нет вовсе.
 *          Повтор ей нужен не меньше прочих - рассылка дейтаграммная и групповая,
 *          и теряется она проще всего
 *
 * @note Обмен ведётся сетью IPv6 по устройству петли: групповой адрес там
 *       принадлежит связи, и указанная зона удерживает рассылку внутри машины.
 *       В сети IPv4 рассылка ушла бы наружу и получила ответ настоящего устройства
 *
 * @warning Проверка эта заведена по случаю: ветвь повтора не исполнялась ни разу,
 *          потому что на отладочной машине устройство отвечало с первой попытки, а
 *          повтор вёл к сборке просьбы, которой у этого договора не бывает
 *
 */
TEST_F(PortmapUnitFixture, PortmapDiscoveryAttempts) {
	/**
	 * Устройство, каким ведётся рассылка обнаружения
	 *
	 * @details Рассылка на групповой адрес связи требует, чтобы устройство несло адрес
	 *          связи (RFC 4291): по нему собирается отправитель, и без него ядро
	 *          отвечает «сеть недостижима» - проверено опытом
	 *
	 *          Прежде рассылка велась устройством петли, лишь бы не ушла наружу, и
	 *          проверка пропускалась всюду, где петля адреса связи не несёт: Linux
	 *          держит там один лишь `::1/128` с областью узла, MS Windows - тоже.
	 *          Теперь наружу её не пускает нулевой предел числа переходов, а идёт она
	 *          устройством местной сети, какое адрес связи несёт всегда
	 *
	 * @note Пропуск остаётся лишь для машины без местной сети вовсе: рассылать тогда
	 *       нечем, и проверять нечего
	 *
	 */
	const std::string device = FakeIGD::deviceName();
	// Если устройства местной сети у машины нет, проверка неисполнима
	if(device.empty())
		// Выводим причину, по которой проверка не выполнялась
		GTEST_SKIP() << "у машины нет устройства местной сети: рассылку обнаружения вести нечем";
	/**
	 * Выполняем перебор проверяемых количеств попыток
	 */
	for(const uint8_t attempts : {static_cast <uint8_t> (1), static_cast <uint8_t> (3)}){
		// Создаём объект модуля перенаправления портов
		awh::unit::portmap_t portmap(this->_fmk.get(), this->_log.get());
		// Устанавливаем вид опроса маршрутизатора
		portmap.setType(awh::unit::portmap_t::type_t::UPNP);
		// Устанавливаем разновидность сети, в которой ведётся обмен
		portmap.setFamily(awh::unit::portmap_t::family_t::IPV6);
		// Устанавливаем сетевое устройство, которым ведётся рассылка
		portmap.setIface(device);
		/**
		 * Запрещаем рассылке обнаружения покидать машину
		 *
		 * @note Это и держит проверку честной: отвечать на рассылку некому - поддельного
		 *       шлюза здесь нет вовсе, - а живой маршрутизатор сети её не увидит, и счёт
		 *       попыток измеряет упорство модуля, а не поведение чужого прибора
		 */
		portmap.setHops(awh::event::hops_t::LOOPBACK);
		// Устанавливаем срок ожидания ответа маршрутизатора
		portmap.setTimeout(TEST_DELAY);
		// Устанавливаем количество попыток обращения к маршрутизатору
		portmap.setAttempts(attempts);
		// Выполняем ожидание итога обращения к маршрутизатору
		const outcome_t outcome = this->await(portmap, awh::unit::portmap_t::action_t::EXTERNAL);
		// Выполняем проверку того, что устройство не ответило
		ASSERT_FALSE(outcome.answered);
		// Выполняем проверку того, что обращение завершилось отказом
		ASSERT_TRUE(outcome.failed);
		// Выполняем проверку кода причины отказа перенаправления
		ASSERT_EQ(outcome.error, awh::unit::portmap_t::error_t::NO_RESPONSE);
		// Выполняем проверку договора, по которому получен итог
		ASSERT_EQ(outcome.type, awh::unit::portmap_t::type_t::UPNP);
		/**
		 * Выполняем проверку того, что рассылка выполнена столько раз, сколько задано
		 *
		 * @note Сличается нижняя граница: рассылка, выполненная единожды, уложилась бы
		 *       в один срок ожидания и проверку бы не прошла
		 */
		ASSERT_GE(outcome.spent, static_cast <int64_t> (TEST_DELAY) * static_cast <int64_t> (attempts));
	}
}
