/**
 * Подключаем заголовочный файлы проекта
 */
#include "portmap.hpp"

/**
 * @brief Срок ожидания ответа маршрутизатора в тестах в миллисекундах
 *
 * @note Срок берётся коротким намеренно: проверка ждёт его столько раз, сколько
 *       задано попыток, и длинный превратил бы набор в испытание терпения
 *
 */
static constexpr uint32_t TEST_DELAY = 200;

/**
 * @brief Адрес маршрутизатора, с которого ответ прийти не может
 *
 * @details Сеть эта отведена договором RFC 5737 под примеры в описаниях и в
 *          движении не встречается: обращение к ней истекает по сроку всегда и
 *          везде, а не по стечению обстоятельств у испытывающего
 *
 */
static constexpr const char * BLACKHOLE_ROUTER = "192.0.2.1";


/**
 * @brief Проверка счёта попыток обращения по дейтаграммному договору
 *
 * @details Маршрутизатор не отвечает, и обращение обязано завершиться отказом не
 *          раньше, чем истечёт срок ожидания у каждой из заданных попыток.
 *          Проверка сличает потраченное время с произведением срока на попытки
 *
 */
TEST_F(PortmapUnitFixture, PortmapDatagramAttempts) {
	/**
	 * Выполняем перебор проверяемых количеств попыток
	 */
	for(const uint8_t attempts : {static_cast <uint8_t> (1), static_cast <uint8_t> (3)}){
		// Создаём объект модуля перенаправления портов
		awh::unit::portmap_t portmap(this->_fmk.get(), this->_log.get());
		// Устанавливаем вид опроса маршрутизатора
		portmap.setType(awh::unit::portmap_t::type_t::NAT_PMP);
		// Устанавливаем адрес маршрутизатора, с которого ответ прийти не может
		portmap.setRouter(BLACKHOLE_ROUTER);
		// Устанавливаем срок ожидания ответа маршрутизатора
		portmap.setTimeout(TEST_DELAY);
		// Устанавливаем количество попыток обращения к маршрутизатору
		portmap.setAttempts(attempts);
		// Выполняем ожидание итога обращения к маршрутизатору
		const outcome_t outcome = this->await(portmap, awh::unit::portmap_t::action_t::OPEN);
		// Выполняем проверку того, что маршрутизатор не ответил
		ASSERT_FALSE(outcome.answered);
		// Выполняем проверку того, что обращение завершилось отказом
		ASSERT_TRUE(outcome.failed);
		// Выполняем проверку кода причины отказа перенаправления
		ASSERT_EQ(outcome.error, awh::unit::portmap_t::error_t::NO_RESPONSE);
		// Выполняем проверку договора, по которому получен итог
		ASSERT_EQ(outcome.type, awh::unit::portmap_t::type_t::NAT_PMP);
		/**
		 * Выполняем проверку того, что попыток выполнено столько, сколько задано
		 *
		 * @note Сличается нижняя граница, а не точное время: срок отсчитывает движок,
		 *       и оказаться он вправе лишь не меньше заданного
		 */
		ASSERT_GE(outcome.spent, static_cast <int64_t> (TEST_DELAY) * static_cast <int64_t> (attempts));
	}
}

/**
 * @brief Проверка повторной рассылки обнаружения устройства UPnP
 *
 * @details Ветвь эта повторяет не просьбу маршрутизатору, а рассылку: просьбы
 *          собирает кодек договора, а у UPnP на шаге обнаружения просьбы нет вовсе.
 *          Повтор ей нужен не меньше прочих - рассылка дейтаграммная и групповая,
 *          и теряется она проще всего
 *
 * @note Обмен ведётся сетью IPv6 по устройству петли: групповой адрес там
 *       принадлежит связи, и указанная зона удерживает рассылку внутри машины.
 *       В сети IPv4 рассылка ушла бы наружу и получила ответ настоящего устройства
 *
 * @warning Проверка эта заведена по случаю: ветвь повтора не исполнялась ни разу,
 *          потому что на отладочной машине устройство отвечало с первой попытки, а
 *          повтор вёл к сборке просьбы, которой у этого договора не бывает
 *
 */
TEST_F(PortmapUnitFixture, PortmapDiscoveryAttempts) {
	/**
	 * Если устройство петли групповую рассылку IPv6 не несёт, проверка неисполнима
	 *
	 * @details Рассылка на групповой адрес связи требует, чтобы устройство несло адрес
	 *          связи (RFC 4291): по нему собирается отправитель, и без него ядро
	 *          отвечает «сеть недостижима» - проверено опытом
	 *
	 *          Адрес этот на устройстве петли не у всех систем: macOS держит там
	 *          `fe80::1%lo0`, а Linux - один лишь `::1/128` с областью узла, и маршрут
	 *          групповой рассылки заведён у него не на петле, а на устройстве доступа
	 *          в сеть. Рассылать через него нельзя: она ушла бы наружу, чего проверка
	 *          и добивается не допустить
	 *
	 * @note Сличается сам факт, а не название системы: несёт ли устройство петли адрес
	 *       связи - настройка машины, и Linux с таким адресом на петле проверку эту
	 *       пройдёт наравне с прочими
	 *
	 */
	{
		// Перечень сетевых устройств машины
		struct ifaddrs * list = nullptr;
		// Признак того, что устройство петли несёт адрес связи
		bool linkLocal = false;
		/**
		 * Если перечень сетевых устройств машины получен
		 */
		if(::getifaddrs(&list) == 0){
			/**
			 * Выполняем перебор всех сетевых устройств машины
			 */
			for(struct ifaddrs * item = list; item != nullptr; item = item->ifa_next){
				// Если устройство адреса сети IPv6 не имеет либо петлёй не является, пропускаем его
				if((item->ifa_addr == nullptr) || (item->ifa_addr->sa_family != AF_INET6) ||
				   (item->ifa_name == nullptr) || (::strcmp(item->ifa_name, LOOPBACK_IFACE) != 0)) continue;
				// Если адрес устройства принадлежит связи, запоминаем это и выходим из перебора
				if(IN6_IS_ADDR_LINKLOCAL(&reinterpret_cast <struct sockaddr_in6 *> (item->ifa_addr)->sin6_addr)){
					// Запоминаем, что устройство петли несёт адрес связи
					linkLocal = true;
					// Выходим из перебора сетевых устройств
					break;
				}
			}
			// Выполняем освобождение перечня сетевых устройств
			::freeifaddrs(list);
		}
		// Если устройство петли адреса связи не несёт, пропускаем проверку
		if(!linkLocal)
			// Выводим причину, по которой проверка не выполнялась
			GTEST_SKIP() << "устройство петли \"" << LOOPBACK_IFACE << "\" адреса связи IPv6 не несёт: групповая рассылка через него неисполнима";
	}
	/**
	 * Выполняем перебор проверяемых количеств попыток
	 */
	for(const uint8_t attempts : {static_cast <uint8_t> (1), static_cast <uint8_t> (3)}){
		// Создаём объект модуля перенаправления портов
		awh::unit::portmap_t portmap(this->_fmk.get(), this->_log.get());
		// Устанавливаем вид опроса маршрутизатора
		portmap.setType(awh::unit::portmap_t::type_t::UPNP);
		// Устанавливаем разновидность сети, в которой ведётся обмен
		portmap.setFamily(awh::unit::portmap_t::family_t::IPV6);
		// Устанавливаем сетевое устройство, дальше которого рассылка не уходит
		portmap.setIface(LOOPBACK_IFACE);
		// Устанавливаем срок ожидания ответа маршрутизатора
		portmap.setTimeout(TEST_DELAY);
		// Устанавливаем количество попыток обращения к маршрутизатору
		portmap.setAttempts(attempts);
		// Выполняем ожидание итога обращения к маршрутизатору
		const outcome_t outcome = this->await(portmap, awh::unit::portmap_t::action_t::EXTERNAL);
		// Выполняем проверку того, что устройство не ответило
		ASSERT_FALSE(outcome.answered);
		// Выполняем проверку того, что обращение завершилось отказом
		ASSERT_TRUE(outcome.failed);
		// Выполняем проверку кода причины отказа перенаправления
		ASSERT_EQ(outcome.error, awh::unit::portmap_t::error_t::NO_RESPONSE);
		// Выполняем проверку договора, по которому получен итог
		ASSERT_EQ(outcome.type, awh::unit::portmap_t::type_t::UPNP);
		/**
		 * Выполняем проверку того, что рассылка выполнена столько раз, сколько задано
		 *
		 * @note Сличается нижняя граница: рассылка, выполненная единожды, уложилась бы
		 *       в один срок ожидания и проверку бы не прошла
		 */
		ASSERT_GE(outcome.spent, static_cast <int64_t> (TEST_DELAY) * static_cast <int64_t> (attempts));
	}
}
