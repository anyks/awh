/**
 * @brief Тест правил округления значения вещественного числа
 *
 */
TEST_F(BigNumFixture, RoundModeBigNumTest){
	// Проверяем что половина округляется от нуля по правилу к ближайшему
	ASSERT_EQ(awh::real64_t("2.5").round(0).print(), "3");
	// Проверяем что половина отрицательного числа округляется от нуля
	ASSERT_EQ(awh::real64_t("-2.5").round(0).print(), "-3");
	// Проверяем что половина округляется к чётному по банковскому правилу
	ASSERT_EQ(awh::real64_t("2.5").round(0, awh::bignum::round_t::EVEN).print(), "2");
	// Проверяем что половина округляется к чётному в сторону увеличения
	ASSERT_EQ(awh::real64_t("3.5").round(0, awh::bignum::round_t::EVEN).print(), "4");
	// Проверяем банковское округление дробной части
	ASSERT_EQ(awh::real64_t("0.125").round(2, awh::bignum::round_t::EVEN).print(), "0.12");
	// Проверяем банковское округление дробной части в сторону увеличения
	ASSERT_EQ(awh::real64_t("0.135").round(2, awh::bignum::round_t::EVEN).print(), "0.14");
	// Проверяем округление в сторону минус бесконечности по правилу
	ASSERT_EQ(awh::real64_t("2.9").round(0, awh::bignum::round_t::DOWN).print(), "2");
	// Проверяем округление в сторону плюс бесконечности по правилу
	ASSERT_EQ(awh::real64_t("2.1").round(0, awh::bignum::round_t::UP).print(), "3");
	// Проверяем округление в сторону нуля по правилу
	ASSERT_EQ(awh::real64_t("-2.9").round(0, awh::bignum::round_t::ZERO).print(), "-2");
}

