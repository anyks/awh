/**
 * Подключаем заголовочный файл главного модуля тестов
 */
#include "main.hpp"
#include <sys/fmk.hpp>
#include <sys/log.hpp>

/**
 * @brief Сторож состояния журнала работы
 *
 * @details Журнал един на процесс, и всё, что проверка ему назначила, доживает до
 *          следующей: уровень, виды вывода, а главное - подписка. Подписка эта,
 *          как правило, захватывает local проверки; переживая её, она указывает
 *          на снятую с места память, и первая же запись соседней проверки пишет
 *          в чужое. Отсюда сброс состояния ПОСЛЕ каждой проверки, а не по вере
 *          в то, что всякая проверка приберёт за собою сама
 *
 * @note Заведено по отказу, ловившемуся лишь соседством: набор кодеков валился с
 *       порчей кучи на проверке, отстоящей от виновной на полтора десятка других
 *
 */
class LogGuard : public ::testing::EmptyTestEventListener {
	/**
	 * @brief Метод оповещения об окончании проверки
	 *
	 * @param info сведения о завершившейся проверке
	 *
	 */
	void OnTestEnd(const ::testing::TestInfo & info) override {
		// Снимаем подписку на записи журнала
		awh::log::subscribe(nullptr);
		// Возвращаем виды вывода записей к заведомому состоянию
		awh::log::mode({awh::log::mode_t::CONSOLE});
		// Возвращаем уровень записей к заведомому состоянию
		awh::log::level(awh::log::level_t::ALL);
		// Снимаем неиспользуемые сведения о проверке
		(void) info;
	}
};

/**
 * @brief Главная функция тестового приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int32_t main(int32_t argc, char ** argv){
	/**
	 * Выполняем заведение модуля ядра первым делом
	 *
	 * @note Заведение это захватывает выдачу памяти процесса, и выполнять его нужно
	 *       ДО всякой выдачи и ДО порождения потоков. Прежде его выполнял конструктор
	 *       объекта фреймворка, заводившийся первым в точке входа; объекта не стало,
	 *       и мгновение заведения назначается здесь явно
	 */
	awh::fmk::initialize();
	// Инициализируем Google Test и Google Mock
	::testing::InitGoogleTest(&argc, argv);
	::testing::InitGoogleMock(&argc, argv);
	// Ставим сторожа состояния журнала работы
	::testing::UnitTest::GetInstance()->listeners().Append(new LogGuard());

	// Запускаем все тесты
	return RUN_ALL_TESTS();
}
