static constexpr const char * TUNNEL_LOCAL = "10.77.0.1";
static constexpr const char * TUNNEL_PEER  = "10.77.0.2";

/**
 * @brief Генерация случайного порта в диапазоне 49152-65535
 *
 * @note Помощник этот повторяет соседний из static.cpp намеренно: связывание у него
 *       внутреннее, и общего состояния между файлами не возникает
 *
 * @return случайный порт
 *
 */
static uint16_t tunnelPort() noexcept {
	// Нижняя и верхняя границы разряда портов, отведённого под временные
	constexpr uint16_t BEGIN = 49152, END = 65535;
	// Счётчик выданных портов
	static uint16_t count = 0;
	// Выводим следующий порт разряда
	return static_cast <uint16_t> (BEGIN + ((static_cast <uint32_t> (::getpid()) + (count++) * 7) % (END - BEGIN)));
}


/**
 * @brief Функция проверки надзорных прав у текущего процесса
 *
 * @details Заведение туннельного устройства требует надзорных прав на ВСЕХ системах, и
 *          это единственная причина отказа, какую проверка вправе принять за негодность
 *          окружения. Всё прочее - отсутствие драйвера, неверная настройка, дефект
 *          движка - от проверки не скрывается: она объявляет отказ и называет обе
 *          возможные причины
 *
 * @warning Прежде проверки пропускались по одному лишь пустому опознавателю события, а
 *          он пуст при ЛЮБОЙ причине. Обратный опыт это и вскрыл: возвращённый в код
 *          дефект настройки драйвера обратил обе проверки в ПРОПУСК вместо отказа.
 *          Пропуск - это молчаливое отключение, и стеречь проверка в таком виде не
 *          стерегла ничего
 *
 * @warning Заводить устройство пробой напрямую, минуя движок, для этого НЕ ГОДИТСЯ, и
 *          это тоже установлено обратным опытом: проба шла бы тем же кодом заведения,
 *          что и движок, и на том же дефекте отвечала бы тем же отказом. Проба обязана
 *          спрашивать окружение, а не разбираемый код
 *
 * @return признак наличия надзорных прав
 *
 */
static bool tunnelPrivileged() noexcept {
	/**
	 * Для операционной системы MS Windows
	 */
	#if _WIN32 || _WIN64
		// Описатель маркера доступа текущего процесса
		HANDLE token = nullptr;
		// Если маркер доступа текущего процесса получить не удалось
		if(!::OpenProcessToken(::GetCurrentProcess(), TOKEN_QUERY, &token))
			// Выводим отсутствие надзорных прав
			return false;
		// Сведения о повышении прав процесса
		TOKEN_ELEVATION elevation{};
		// Размер полученных сведений
		DWORD size = static_cast <DWORD> (sizeof(elevation));
		// Признак наличия надзорных прав
		bool result = false;
		// Если сведения о повышении прав получены
		if(::GetTokenInformation(token, TokenElevation, &elevation, sizeof(elevation), &size))
			// Запоминаем признак наличия надзорных прав
			result = (elevation.TokenIsElevated != 0);
		// Выполняем закрытие маркера доступа
		::CloseHandle(token);
		// Выводим признак наличия надзорных прав
		return result;
	/**
	 * Для всех остальных операционных систем
	 */
	#else
		// Выводим признак работы от имени надзорного пользователя
		return (::geteuid() == 0);
	#endif
}

/**
 * @brief Охранник узла туннеля: снос обязан пройти при любом исходе
 *
 * @details Утверждение, не оправдавшееся посреди проверки, возвращает управление
 *          немедленно, и снос узла, стоящий ниже по телу, не исполняется вовсе.
 *          У систем, где устройство переживает процесс (MS Windows, системы Sun),
 *          на нём остаётся назначенный адрес - и СЛЕДУЮЩИЙ прогон получает
 *          устройство занятым
 *
 * @warning Беда эта САМОВОСПРОИЗВОДЯЩАЯСЯ: отказ оставляет остаток, остаток
 *          обеспечивает отказ, и набор из круга сам не выходит. Установлено на
 *          стенде Windows 21.08.2026 - три прогона подряд красными по одной
 *          причине, каждый готовил её следующему
 *
 * @note Разрушение охранника происходит и при обычном выходе, и при отказе
 *       утверждения: снос узла в обоих случаях один и тот же, а повторный снос
 *       движок принимает без последствий
 *
 */
struct TunnelGuard {
	// Объект движка событий
	awh::engine::io_t * io;
	// Идентификатор узла туннеля
	awh::event::id_t id;
	/**
	 * @brief Конструктор охранника узла туннеля
	 *
	 * @param io объект движка событий
	 * @param id идентификатор узла туннеля
	 *
	 */
	TunnelGuard(awh::engine::io_t * io, const awh::event::id_t id) noexcept : io(io), id(id) {}
	/**
	 * @brief Деструктор охранника узла туннеля
	 *
	 */
	~TunnelGuard() noexcept {
		// Если узел туннеля заведён
		if((this->io != nullptr) && (this->id > 0))
			// Сносим узел туннеля вместе с его настройкой
			this->io->destroy(this->id);
	}
};

/**
 * @brief Функция имени подготовленного туннельного устройства
 *
 * @details Системы Sun устройств уровня IP не заводят вовсе: там связь заводится
 *          административно (`dladm create-vnic` поверх etherstub), и движку
 *          полагается имя УЖЕ ГОТОВОЙ связи, а не право завести её самому. Прочие
 *          системы заводят устройство сами, и имя им не нужно
 *
 * @warning Отсутствие подготовленной связи у систем Sun - негодность окружения, а не
 *          дефект движка: завести её проверка не вправе, это настройка стенда.
 *          Спрашивается она у самой системы, а не у разбираемого кода
 *
 * @return имя подготовленного устройства либо пустая строка
 *
 */
static std::string tunnelDevice() noexcept {
	/**
	 * Для операционных систем Sun
	 */
	#if __sun__
		// Выводим имя связи, заведённой для проверок по описанию стенда
		return "awhtun0";
	/**
	 * Для всех остальных операционных систем
	 */
	#else
		// Устройство заводит сам движок, имя ему не нужно
		return "";
	#endif
}

/**
 * @brief Тест полного оборота жизни туннельного устройства
 *
 * @details Оборот проходится ДВАЖДЫ подряд одним и тем же движком, и это
 *          существенно. Половина дефектов, вскрытых работами по переносу, выдавала
 *          себя не первым заведением, а вторым: дескриптор, не снятый с учёта при
 *          сносе, оставлял за собой запись, и следующее устройство получало отказ
 *          привязки к очереди событий
 *
 * @note Проверяется здесь именно СОГЛАСИЕ движка на каждом шаге, а не обмен: обмен
 *       требует встречной стороны, и разбирается он проверкой соседней
 *
 */
TEST_F(IoFixture, IoTunnelLifecycleTest){
	// Если надзорных прав у процесса нет
	if(!tunnelPrivileged())
		// Пропускаем проверку
		GTEST_SKIP() << "заведение туннельного устройства требует надзорных прав";
	// Выполняем инициализацию движка
	ASSERT_TRUE(this->_io->initialize());
	/**
	 * Проходим оборот жизни устройства дважды
	 */
	for(uint8_t round = 0; round < 2; round++){
		// Роспись оборота для сообщений об отказе
		const std::string sign = std::string("оборот=") + std::to_string(round + 1);
		/**
		 * Заводим событие туннеля
		 *
		 * @note Здесь заводится ТОЛЬКО узел: само устройство движок заводит фиксацией
		 *       настроек, когда имя ему уже названо. Пустой опознаватель означает, что
		 *       движок не записал узла, а отказ заведения устройства спрашивается ниже,
		 *       у commit
		 */
		const awh::event::id_t tid = this->_io->event(awh::event::node_t::TUNNEL, awh::event::family_t::IPV4);
		// Ставим охранника узла: снос обязан пройти и при отказе утверждения
		const TunnelGuard guard(this->_io.get(), tid);
		/**
		 * Называем движку подготовленное устройство там, где система требует имени
		 */
		if(!tunnelDevice().empty())
			// Устанавливаем имя подготовленного туннельного устройства
			ASSERT_TRUE(this->_io->setIface(tid, tunnelDevice()));
		// Узел обязан завестись: устройство заводится позже, фиксацией настроек
		ASSERT_GT(tid, 0u) << sign << ": движок не записал узел туннеля";
		/**
		 * Устанавливаем опции события туннеля
		 *
		 * @details Отказ здесь был дефектом движка: разбор опций у туннеля шёл общим
		 *          путём с каталогами, файлами и каналами, а тот отвечал отказом
		 *          10038 - «дескриптор не является сокетом». Туннель им и не является
		 */
		ASSERT_TRUE(this->_io->setOptions(tid, awh::event::options::NO_IO_BLOCK | awh::event::options::CLOSE_ON_EXEC)) << sign;
		// Устанавливаем адреса концов туннеля
		ASSERT_TRUE(this->_io->setAddress(tid, awh::event::address_t::IPV4, TUNNEL_LOCAL)) << sign;
		ASSERT_TRUE(this->_io->setTarget(tid, TUNNEL_PEER)) << sign;
		// Фиксируем событие туннеля
		// Устройство заводится фиксацией настроек: годность окружения проверена выше пробой
		ASSERT_TRUE(this->_io->commit(tid)) << sign << ": права есть, а устройство не заведено - нет драйвера туннельных устройств либо дефект движка";
		// Запускаем событие туннеля
		ASSERT_TRUE(this->_io->launch(tid)) << sign;
		/**
		 * Спрашиваем адрес У САМОЙ СИСТЕМЫ, а не у согласия движка
		 *
		 * @details Утверждение ASSERT_TRUE(setAddress(...)) говорит лишь то, что вызов
		 *          ответил согласием. Дошёл ли адрес до устройства, оно НЕ говорит вовсе,
		 *          и проверка остаётся зелёной при устройстве без адреса
		 *
		 * @warning Внутримашинная проверка эту разницу увидеть НЕ МОЖЕТ: оба конца - одно
		 *          и то же устройство, и обмен через него идёт даже тогда, когда адреса
		 *          на нём нет. Вскрылось это первой же попыткой свести две машины
		 *
		 * @note Разницу нашёл агент стороны Windows 21.08.2026: там за все 3.8 секунды
		 *       жизни устройства запрошенный адрес не появлялся НИ РАЗУ, а проверка
		 *       проходила. У систем POSIX адрес ставится честно - проверено слежением на
		 *       стенде Alpine, - но утверждать это обязана сама проверка, а не мы
		 */
		{
			// Получаем название заведённого устройства туннеля
			const std::string iface = this->_io->getIface(tid);
			// Название устройства обязано быть известно
			ASSERT_FALSE(iface.empty()) << sign;
			// Создаём объект работы с сетью
			awh::eth_t eth(this->_fmk.get(), this->_log.get());
			/**
			 * Спрашиваем, чьим стал НАШ адрес, а не какой адрес у устройства
			 *
			 * @details Опрос адреса устройства отдаёт ПЕРВЫЙ из его адресов, и на
			 *          системах, где устройство постоянно, первым легко оказывается
			 *          чужой - остаток прежнего прогона. Сличение первого адреса с
			 *          запрошенным обвиняло тогда движок в том, чего он не делал
			 *
			 * @warning У систем POSIX эта разница НЕ ВИДНА вовсе: устройство уходит
			 *          вместе с процессом, адрес у него всегда один, и сличение
			 *          первого выглядит безупречным. Вскрылось на MS Windows, где
			 *          переходник tap-windows6 переживает прогон и несёт несколько
			 *          адресов разом (нашёл агент стороны Windows 21.08.2026)
			 *
			 * @note Обратный вопрос свободен от этой слепоты: он ищет НАШ адрес среди
			 *       всех адресов машины и отвечает, какому устройству тот принадлежит.
			 *       Лишние адреса на устройстве ответу не мешают
			 */
			// Объект разбора запрошенного адреса устройства
			awh::net_addr_t expected(this->_fmk.get(), this->_log.get());
			// Разбираем запрошенный адрес устройства
			ASSERT_TRUE(expected.parse(TUNNEL_LOCAL)) << sign;
			// Объект запрошенного адреса устройства
			std::unique_ptr <awh::net::addr_t> address = std::make_unique <awh::net::addr_net_ipv4_t> ();
			/**
			 * Переносим разобранный адрес в объект нужного вида
			 *
			 * @note Порядок октетов взят LITTLE намеренно: он совпадает с тем, каким
			 *       адрес лежит в структурах системы, и годен для прямого сличения
			 */
			awh_cast <awh::net::addr_net_ipv4_t *> (address.get())->address = expected.v4(awh::net_addr_t::endian_t::LITTLE);
			// Спрашиваем, какому устройству принадлежит запрошенный адрес
			const std::string owner = eth.iface.name(address.get());
			// Запрошенный адрес обязан принадлежать заведённому устройству
			ASSERT_EQ(owner, iface)
				<< sign << ": движок согласился поставить адрес " << TUNNEL_LOCAL
				<< ", а система числит его "
				<< (owner.empty() ? std::string("ни за одним устройством") : (std::string("за устройством \"") + owner + "\""));
		}
		/**
		 * Крутим опрос недолго
		 *
		 * @details Обороты эти нужны не ради пакетов, а ради самой привязки: отказ
		 *          привязки устройства к очереди событий выдавал себя именно здесь -
		 *          опрос возвращал отказ с кодом 6, «неверный описатель»
		 */
		const auto start = std::chrono::steady_clock::now();
		while((std::chrono::duration_cast <std::chrono::milliseconds> (std::chrono::steady_clock::now() - start).count() < 300))
			ASSERT_TRUE(this->_io->poll(50)) << sign;
		// Снимаем событие туннеля
		ASSERT_TRUE(this->_io->destroy(tid)) << sign;
	}
	// Сворачиваем движок
	ASSERT_TRUE(this->_io->deinitialize());
}

/**
 * @brief Тест переноса пакета из туннеля наружу
 *
 * @details Проверяется весь путь целиком: пакет, посланный на адрес встречной стороны
 *          туннеля, забирается системой в устройство, читается движком, заворачивается
 *          посредником и уходит несущей связью - той самой, на другом конце которой
 *          стоит сервер этой же проверки. Дошедшее сличается с пакетом IPv4
 *
 * @details Проверка эта закрывает дефект настройки драйвера у MS Windows: драйвер
 *          tap-windows6 в режиме переноса пакетов сетевого уровня отбирает их по
 *          настроенной сети, а настраивался он числами, зашитыми в коде. Обмен по
 *          IPv4 через устройство не шёл ВОВСЕ, и выдавала себя беда лишь молчанием
 *          туннеля - ни отказа, ни записи в журнале. Установлено щупом на стенде
 *          Windows ARM64 20.08.2026
 *
 * @note Несущая связь заведена на петле: проверке нужен не обмен между машинами, а
 *       доказательство того, что пакет через туннель ПРОШЁЛ
 *
 */
TEST_F(IoFixture, IoTunnelCarriesPacketTest){
	// Счётчик пакетов, дошедших несущей связью
	uint16_t carried = 0;
	// Код отказа отправки дейтаграммы в устройство
	int32_t failure = 0;
	// Признак того, что дошедшее оказалось пакетом IPv4
	bool addressed = false;
	// Порт несущей связи
	const uint16_t bearer = tunnelPort();
	// Если надзорных прав у процесса нет
	if(!tunnelPrivileged())
		// Пропускаем проверку
		GTEST_SKIP() << "заведение туннельного устройства требует надзорных прав";
	// Выполняем инициализацию движка
	ASSERT_TRUE(this->_io->initialize());
	/**
	 * Заводим событие туннеля
	 *
	 * @note Здесь заводится ТОЛЬКО узел: устройство движок заводит фиксацией
	 *       настроек. Пустой опознаватель означает, что движок не записал
	 *       узла, а отказ заведения устройства спрашивается ниже, у commit
	 */
	const awh::event::id_t tid = this->_io->event(awh::event::node_t::TUNNEL, awh::event::family_t::IPV4);
	// Ставим охранника узла: снос обязан пройти и при отказе утверждения
	const TunnelGuard guard(this->_io.get(), tid);
		/**
		 * Называем движку подготовленное устройство там, где система требует имени
		 */
		if(!tunnelDevice().empty())
			// Устанавливаем имя подготовленного туннельного устройства
			ASSERT_TRUE(this->_io->setIface(tid, tunnelDevice()));
	// Узел обязан завестись: устройство заводится позже, фиксацией настроек
	ASSERT_GT(tid, 0u) << "движок не записал узел туннеля";
	// Заводим событие посредника
	const awh::event::id_t mid = this->_io->event(awh::event::node_t::MEDIATOR, awh::event::family_t::IPV4);
	ASSERT_GT(mid, 0u);
	// Заводим событие сервера несущей связи
	const awh::event::id_t sid = this->_io->event(
		awh::event::node_t::SERVER, awh::event::family_t::IPV4,
		awh::event::type_t::DATAGRAM, awh::event::protocol_t::UDP
	);
	ASSERT_GT(sid, 0u);
	// Заводим событие клиента несущей связи
	const awh::event::id_t cid = this->_io->event(
		awh::event::node_t::CLIENT, awh::event::family_t::IPV4,
		awh::event::type_t::DATAGRAM, awh::event::protocol_t::UDP
	);
	ASSERT_GT(cid, 0u);
	// Устанавливаем опции событий
	ASSERT_TRUE(this->_io->setOptions(tid, awh::event::options::NO_IO_BLOCK | awh::event::options::CLOSE_ON_EXEC));
	ASSERT_TRUE(this->_io->setOptions(sid, awh::event::options::NO_SIGPIPE | awh::event::options::REUSE_ADDR | awh::event::options::NO_IO_BLOCK));
	ASSERT_TRUE(this->_io->setOptions(cid, awh::event::options::NO_SIGPIPE | awh::event::options::NO_IO_BLOCK));
	// Устанавливаем адреса концов туннеля
	ASSERT_TRUE(this->_io->setAddress(tid, awh::event::address_t::IPV4, TUNNEL_LOCAL));
	ASSERT_TRUE(this->_io->setTarget(tid, TUNNEL_PEER));
	// Устанавливаем встречную сторону посреднику
	ASSERT_TRUE(this->_io->setTarget(mid, TUNNEL_PEER));
	// Устанавливаем адрес и порт несущей связи
	ASSERT_TRUE(this->_io->setAddress(sid, awh::event::address_t::IPV4, "127.0.0.1"));
	ASSERT_TRUE(this->_io->setSourcePort(sid, bearer));
	ASSERT_TRUE(this->_io->setTarget(cid, "127.0.0.1"));
	ASSERT_TRUE(this->_io->setTargetPort(cid, bearer));
	// Связываем посредника с клиентом несущей связи
	ASSERT_TRUE(this->_io->splice(mid, cid));
	/**
	 * Считаем прочитанное посредником
	 *
	 * @note Отклик чтения ставится ПОСРЕДНИКУ, а не серверу несущей связи: у события
	 *       сервера отклик этот не заводится вовсе - тот отвечает отказом «отклик чтения
	 *       данных этому виду события задать нельзя», - а посредник как раз и держит то,
	 *       что прочитано из туннеля
	 *
	 * @note Сличается именно ВИД прочитанного, а не его размер: пакет собирает система, и
	 *       утверждать его длину значило бы утверждать поведение системы
	 */
	this->_io->on(mid, static_cast <awh::engine::callback::read_t> (
		[&carried, &addressed]([[maybe_unused]] const awh::event::id_t mid, const uint8_t * data, const size_t size) noexcept -> void {
			// Считаем дошедший пакет
			carried++;
			// Если дошедшее оказалось пакетом IPv4
			if((data != nullptr) && (size > 0) && ((data[0] >> 4) == 4))
				// Запоминаем опознание пакета IPv4
				addressed = true;
		}
	));
	// Фиксируем события
	// Устройство заводится фиксацией настроек: годность окружения проверена выше пробой
	ASSERT_TRUE(this->_io->commit(tid)) << "права есть, а устройство не заведено - нет драйвера туннельных устройств либо дефект движка";
	ASSERT_TRUE(this->_io->commit(sid));
	ASSERT_TRUE(this->_io->commit(cid));
	ASSERT_TRUE(this->_io->commit(mid));
	/**
	 * Подключаем несущую связь к своему же серверу
	 *
	 * @note Без этого дейтаграммный сокет несущей связи остаётся без встречной стороны:
	 *       очередь принимает данные и отчитывается об отправке, а наружу не уходит
	 *       ничего
	 */
	ASSERT_TRUE(this->_io->connect(cid));
	/**
	 * Запускаем события
	 *
	 * @note Посредник запуску вручную НЕ подлежит и отвечает на него отказом: ведёт его
	 *       та связь, с которой он соединён, и своей жизни у него нет
	 */
	ASSERT_TRUE(this->_io->launch(sid));
	ASSERT_TRUE(this->_io->launch(cid));
	ASSERT_TRUE(this->_io->launch(tid));
	/**
	 * Поднимаем устройство туннеля
	 *
	 * @details Движок устройство заводит и адреса ему назначает, но признака UP не
	 *          ставит: без него устройство остаётся опущенным, маршрута через него
	 *          нет и пакету идти некуда. У MS Windows драйвер поднимает устройство
	 *          сам, оттого проверка там проходила и без этого; у систем POSIX пакет
	 *          не доходил вовсе, и выдавала себя беда только счётчиком «дошло=0»
	 */
	{
		// Получаем название устройства туннеля
		const std::string iface = this->_io->getIface(tid);
		// Название устройства обязано быть известно
		ASSERT_FALSE(iface.empty());
		// Создаём объект работы с сетью
		awh::eth_t eth(this->_fmk.get(), this->_log.get());
		// Поднимаем устройство туннеля
		ASSERT_TRUE(eth.iface.flag(iface, awh::event::eth_flag_t::UP, awh::event::mode_t::ENABLED));
	}
	/**
	 * Шлём дейтаграмму на адрес встречной стороны туннеля
	 *
	 * @details Обмен ведётся сокетом системы, а не движком: проверке нужен пакет,
	 *          пришедший В туннель извне движка, - иначе она проверяла бы движок
	 *          сам собою
	 */
	awh::net::socket_t fd = static_cast <awh::net::socket_t> (::socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP));
	ASSERT_NE(fd, awh::net::invalid_socket_t);
	// Адрес встречной стороны туннеля
	struct sockaddr_in peer{};
	// Устанавливаем семейство адреса встречной стороны
	peer.sin_family = AF_INET;
	// Устанавливаем порт встречной стороны
	peer.sin_port = htons(9);
	// Устанавливаем адрес встречной стороны
	peer.sin_addr.s_addr = ::inet_addr(TUNNEL_PEER);
	// Полезная нагрузка отправляемой дейтаграммы
	const char payload[] = "AWH-TUNNEL-PROBE";
	// Отсчёт времени ожидания
	const auto start = std::chrono::steady_clock::now();
	/**
	 * Крутим опрос, подсылая дейтаграммы
	 */
	while((std::chrono::duration_cast <std::chrono::milliseconds> (std::chrono::steady_clock::now() - start).count() < 3000) && (carried == 0)){
		// Отправляем дейтаграмму на адрес встречной стороны туннеля
		/**
		 * Отказ отправки запоминаем
		 *
		 * @warning Прежде итог отправки не смотрели вовсе, и это скрывало причину: при
		 *          недоступном маршруте система отвечает отказом сразу, а проверка
		 *          отчитывалась одним лишь «дошло=0» - неотличимо от беды в переносе
		 */
		if(::sendto(fd, payload, sizeof(payload) - 1, 0, reinterpret_cast <struct sockaddr *> (&peer), sizeof(peer)) < 0)
			// Запоминаем код отказа отправки
			failure = errno;
		// Выполняем оборот опроса
		ASSERT_TRUE(this->_io->poll(100));
	}
	// Закрываем сокет отправки
	::closesocket(fd);
	// Роспись итога для сообщений об отказе
	const std::string sign = std::string("дошло=") + std::to_string(carried) + " опознано=" + (addressed ? "да" : "нет") +
	                         " отказ отправки=" + ((failure != 0) ? ::strerror(failure) : "нет");
	/**
	 * Отказ отправки означает негодное окружение, а не дефект движка
	 *
	 * @details Пакет к встречной стороне туннеля идёт через устройство, и пакетный
	 *          фильтр системы вправе его не пустить: у стенда FreeBSD правила ipfw
	 *          разрешают обмен лишь сетевой связью и петлёй, а всё прочее отвергают
	 *          отказом «Permission denied» ещё на отправке. Пакет тогда не доходит
	 *          даже до устройства, и проверять движку нечего
	 *
	 * @warning Пробой окружения здесь служит errno самой системы, а не поведение
	 *          разбираемого кода: спрашивается тот, кто отказ и вынес. Правила
	 *          заслона проверка не трогает и трогать не вправе - они принадлежат
	 *          хозяину стенда
	 */
	/**
	 * Негодностью окружения признаются ТОЛЬКО запрет и недостижимость
	 *
	 * @warning Прежде сюда попадал всякий код отказа, и это прятало дефект: у драйвера
	 *          Wintron под MS Windows отправка отвечает `EAGAIN` три секунды подряд,
	 *          потому что система держит её в ожидании разрешения адреса встречной
	 *          стороны, а дать его некому - устройство там чисто сетевого уровня, и
	 *          маршрут на встречную сторону движок не заводит. «Пока не могу» - это
	 *          незавершённая настройка, то есть ровно то, что проверка обязана ловить,
	 *          а не «мне не разрешили»
	 *
	 * @note Установлено Андреем на стенде Windows ARM64 20.08.2026 сличением двух
	 *       драйверов: под tap-windows6 отправка проходит, под Wintun отказывает
	 */
	const bool forbidden = ((failure == EACCES) || (failure == EPERM) ||
	                        (failure == ENETUNREACH) || (failure == EHOSTUNREACH));
	// Если пакет не дошёл, а система назвала запрет либо недостижимость
	if((carried == 0) && forbidden){
		// Сворачиваем движок
		this->_io->deinitialize();
		// Пропускаем проверку
		GTEST_SKIP() << "система запретила пакету идти в устройство туннеля (" << ::strerror(failure) << "): заслон либо отсутствие маршрута";
	}
	// Через туннель обязан пройти хотя бы один пакет
	ASSERT_GE(carried, 1) << sign;
	// Дошедшее обязано оказаться пакетом IPv4
	ASSERT_TRUE(addressed) << sign;
	// Сворачиваем движок
	ASSERT_TRUE(this->_io->deinitialize());
}

/**
 * @brief Адреса концов испытуемого туннеля IPv6
 *
 * @details Берутся они из блока местных адресов (ULA, RFC 4193) и берутся нарочно
 *          НЕ из тех, какими пользуются соседние проверки: устройство туннеля
 *          заводится на всю машину, и совпадение адресов столкнуло бы проверки
 *          между собой через таблицу маршрутов
 *
 */
static constexpr const char * TUNNEL_LOCAL6 = "fd77:aa::1";
static constexpr const char * TUNNEL_PEER6  = "fd77:aa::2";

/**
 * @brief Тест служебного обмена узла на устройстве IPv6
 *
 * @details Ядро на ВСЯКОМ поднятом устройстве IPv6 заводит адрес связи (FE80::/10)
 *          и само шлёт с него оповещения групповым адресам (FF00::/8) - разрешение
 *          соседей, оповещения слушателей, поиск маршрутизатора. Источник таких
 *          пакетов не совпадает с настройками туннеля, и движок объявлял их
 *          подменой адреса: «Attacker replaced the network interface's IP address».
 *          Туннель IPv6 разваливался сам собою, без всякого нападения и без единого
 *          пакета извне
 *
 * @details Проверке оттого не нужно ничего подсылать: обмен этот возникает сам,
 *          стоит устройству подняться. Довольно поднять его и убедиться, что
 *          отклика ошибки за отведённое время НЕ пришло
 *
 * @note Оборот проходится дважды по той же причине, что и в проверке жизненного
 *       цикла: половина дефектов туннелей выдавала себя не первым заведением, а
 *       вторым
 *
 */
TEST_F(IoFixture, IoTunnelIPv6HousekeepingTest){
	// Счётчик откликов ошибки и счётчик объявлений подмены адреса
	uint16_t errors = 0, attacks = 0;
	// Текст первого отказа, снятый для росписи итога
	std::string reason;
	// Миг работы, на котором пришёл отказ
	std::string stage("заведение");
	// Если надзорных прав у процесса нет
	if(!tunnelPrivileged())
		// Пропускаем проверку
		GTEST_SKIP() << "заведение туннельного устройства требует надзорных прав";
	// Выполняем инициализацию движка
	ASSERT_TRUE(this->_io->initialize());
	/**
	 * Проходим оборот жизни устройства дважды
	 */
	for(uint8_t round = 0; round < 2; round++){
		// Роспись оборота для сообщений об отказе
		const std::string sign = std::string("оборот=") + std::to_string(round + 1);
		/**
		 * Заводим событие туннеля семейства IPv6
		 *
		 * @note Здесь заводится ТОЛЬКО узел: устройство движок заводит фиксацией
		 *       настроек. Пустой опознаватель означает, что движок не записал
		 *       узла, а отказ заведения устройства спрашивается ниже, у commit
		 */
		const awh::event::id_t tid = this->_io->event(awh::event::node_t::TUNNEL, awh::event::family_t::IPV6);
		// Ставим охранника узла: снос обязан пройти и при отказе утверждения
		const TunnelGuard guard(this->_io.get(), tid);
		/**
		 * Называем движку подготовленное устройство там, где система требует имени
		 */
		if(!tunnelDevice().empty())
			// Устанавливаем имя подготовленного туннельного устройства
			ASSERT_TRUE(this->_io->setIface(tid, tunnelDevice()));
		// Узел обязан завестись: устройство заводится позже, фиксацией настроек
		ASSERT_GT(tid, 0u) << sign << ": движок не записал узел туннеля";
		// Устанавливаем опции события туннеля
		ASSERT_TRUE(this->_io->setOptions(tid, awh::event::options::NO_IO_BLOCK | awh::event::options::CLOSE_ON_EXEC)) << sign;
		// Устанавливаем адреса концов туннеля
		ASSERT_TRUE(this->_io->setAddress(tid, awh::event::address_t::IPV6, TUNNEL_LOCAL6)) << sign;
		ASSERT_TRUE(this->_io->setTarget(tid, TUNNEL_PEER6)) << sign;
		/**
		 * Считаем отклики ошибки, отдельно отмечая объявления подмены адреса
		 */
		this->_io->on(tid, static_cast <awh::engine::callback::error_t> (
			[&errors, &attacks, &reason, &stage]([[maybe_unused]] const awh::event::id_t tid, const awh::event::error_t code, const std::string & text) noexcept -> void {
				// Считаем отклик ошибки
				errors++;
				// Запоминаем текст первого отказа вместе с его разновидностью и мигом прихода
				if(reason.empty())
					// Устанавливаем причину первого отказа
					reason = (std::string("вид=") + std::to_string(static_cast <uint16_t> (code)) + " «" + text + "» миг=" + stage);
				// Если движок объявил подмену адреса
				if(text.find("Attacker replaced") != std::string::npos)
					// Считаем объявление подмены адреса
					attacks++;
			}
		));
		// Фиксируем настройки события туннеля
		// Устройство заводится фиксацией настроек: годность окружения проверена выше пробой
		ASSERT_TRUE(this->_io->commit(tid)) << sign << ": права есть, а устройство не заведено - нет драйвера туннельных устройств либо дефект движка";
		// Запускаем событие туннеля
		ASSERT_TRUE(this->_io->launch(tid)) << sign;
		/**
		 * Поднимаем устройство туннеля
		 *
		 * @note Без признака UP служебного обмена не возникает вовсе: ядро заводит
		 *       адрес связи и начинает оповещения лишь на поднятом устройстве. Опыт
		 *       на опущенном устройстве не поставить - там тихо всегда
		 */
		const std::string iface = this->_io->getIface(tid);
		ASSERT_FALSE(iface.empty()) << sign;
		{
			// Создаём объект работы с сетью
			awh::eth_t eth(this->_fmk.get(), this->_log.get());
			// Поднимаем устройство туннеля
			ASSERT_TRUE(eth.iface.flag(iface, awh::event::eth_flag_t::UP, awh::event::mode_t::ENABLED)) << sign;
		}
		/**
		 * Крутим опрос, покуда ядро ведёт служебный обмен
		 *
		 * @note Полторы секунды взяты с запасом: разрешение соседа и оповещение
		 *       слушателей ядро шлёт сразу за подъёмом устройства, а проверка
		 *       неповторимости адреса занимает у систем до секунды
		 */
		// Отмечаем миг работы: устройство поднято, идёт опрос
		stage = "опрос";
		const auto start = std::chrono::steady_clock::now();
		while((std::chrono::duration_cast <std::chrono::milliseconds> (std::chrono::steady_clock::now() - start).count() < 1500))
			ASSERT_TRUE(this->_io->poll(50)) << sign;
		// Отмечаем миг работы: снятие узла
		stage = "снятие";
		// Снимаем событие туннеля
		ASSERT_TRUE(this->_io->destroy(tid)) << sign;
	}
	// Роспись итога для сообщений об отказе
	const std::string sign = std::string("отказов=") + std::to_string(errors) + " подмен=" + std::to_string(attacks) +
	                         ((errors > 0) ? (" первый отказ: " + reason) : std::string(""));
	/**
	 * Снятое число печатается ВСЕГДА, даже при нуле
	 *
	 * @warning Нуль тут двусмыслен: он значит либо что мерка отбирает служебный обмен,
	 *          либо что обмена на этой машине не возникло вовсе. Различает их только
	 *          число, снятое ДО правки. Без печати проверка молча проходила бы там, где
	 *          обмена нет, не проверив ничего - тот же вид молчаливого отключения, что
	 *          и пропуск по признаку, пустому при любой причине
	 */
	std::cout << "служебный обмен IPv6: " << sign << std::endl;
	// Служебный обмен узла подменой адреса объявлен быть не может
	ASSERT_EQ(attacks, 0) << sign;
	// Отказов при служебном обмене не возникает вовсе
	ASSERT_EQ(errors, 0) << sign;
	// Сворачиваем движок
	ASSERT_TRUE(this->_io->deinitialize());
}

/**
 * @brief Тест служебного обмена узла на устройстве IPv4
 *
 * @details Устроена проверка ровно как её двойник по IPv6 и по той же причине: ядро
 *          на поднятом устройстве ведёт свой обмен, источник которого с настройками
 *          туннеля не совпадает, а движок объявляет такой пакет подменой адреса
 *          устройства. У IPv4 состав обмена иной - оповещение слушателей и разрешение
 *          имён в сегменте идут групповым адресам 224.0.0.0/4, выдача адреса уходит с
 *          ПУСТОГО источника 0.0.0.0 на широковещательный 255.255.255.255, канальные
 *          адреса берутся из 169.254.0.0/16
 *
 * @note Состав служебного обмена IPv4 от системы ЗАВИСИТ сильнее, чем у IPv6: у одной
 *       машины он возникает сам, у другой требует настройки. Оттого проверка при нуле
 *       откликов не отчитывается «прошла молча», а печатает снятое число - иначе она
 *       проходила бы и на машине, где обмена не возникает вовсе, ничего не проверив
 *
 * @warning Сличать признаки полагается ОКТЕТАМИ пакета, а не старшими байтами числа:
 *          адрес приходит в разбор сырым из буфера, без обращения порядка, и на
 *          обратнопорядковой машине сравнение со старшим байтом молча перестанет
 *          ловить
 *
 */
TEST_F(IoFixture, IoTunnelIPv4HousekeepingTest){
	// Счётчик откликов ошибки и счётчик объявлений подмены адреса
	uint16_t errors = 0, attacks = 0;
	// Текст первого отказа, снятый для росписи итога
	std::string reason;
	// Миг работы, на котором пришёл отказ
	std::string stage("заведение");
	// Если надзорных прав у процесса нет
	if(!tunnelPrivileged())
		// Пропускаем проверку
		GTEST_SKIP() << "заведение туннельного устройства требует надзорных прав";
	// Выполняем инициализацию движка
	ASSERT_TRUE(this->_io->initialize());
	/**
	 * Проходим оборот жизни устройства дважды
	 */
	for(uint8_t round = 0; round < 2; round++){
		// Роспись оборота для сообщений об отказе
		const std::string sign = std::string("оборот=") + std::to_string(round + 1);
		/**
		 * Заводим событие туннеля семейства IPv4
		 *
		 * @note Здесь заводится ТОЛЬКО узел: устройство движок заводит фиксацией
		 *       настроек. Пустой опознаватель означает, что движок не записал
		 *       узла, а отказ заведения устройства спрашивается ниже, у commit
		 */
		const awh::event::id_t tid = this->_io->event(awh::event::node_t::TUNNEL, awh::event::family_t::IPV4);
		// Ставим охранника узла: снос обязан пройти и при отказе утверждения
		const TunnelGuard guard(this->_io.get(), tid);
		/**
		 * Называем движку подготовленное устройство там, где система требует имени
		 */
		if(!tunnelDevice().empty())
			// Устанавливаем имя подготовленного туннельного устройства
			ASSERT_TRUE(this->_io->setIface(tid, tunnelDevice()));
		// Узел обязан завестись: устройство заводится позже, фиксацией настроек
		ASSERT_GT(tid, 0u) << sign << ": движок не записал узел туннеля";
		// Устанавливаем опции события туннеля
		ASSERT_TRUE(this->_io->setOptions(tid, awh::event::options::NO_IO_BLOCK | awh::event::options::CLOSE_ON_EXEC)) << sign;
		// Устанавливаем адреса концов туннеля
		ASSERT_TRUE(this->_io->setAddress(tid, awh::event::address_t::IPV4, TUNNEL_LOCAL)) << sign;
		ASSERT_TRUE(this->_io->setTarget(tid, TUNNEL_PEER)) << sign;
		/**
		 * Считаем отклики ошибки, отдельно отмечая объявления подмены адреса
		 */
		this->_io->on(tid, static_cast <awh::engine::callback::error_t> (
			[&errors, &attacks, &reason, &stage]([[maybe_unused]] const awh::event::id_t tid, const awh::event::error_t code, const std::string & text) noexcept -> void {
				// Считаем отклик ошибки
				errors++;
				// Запоминаем текст первого отказа вместе с его разновидностью и мигом прихода
				if(reason.empty())
					// Устанавливаем причину первого отказа
					reason = (std::string("вид=") + std::to_string(static_cast <uint16_t> (code)) + " «" + text + "» миг=" + stage);
				// Если движок объявил подмену адреса
				if(text.find("Attacker replaced") != std::string::npos)
					// Считаем объявление подмены адреса
					attacks++;
			}
		));
		// Фиксируем настройки события туннеля
		// Устройство заводится фиксацией настроек: годность окружения проверена выше пробой
		ASSERT_TRUE(this->_io->commit(tid)) << sign << ": права есть, а устройство не заведено - нет драйвера туннельных устройств либо дефект движка";
		// Запускаем событие туннеля
		ASSERT_TRUE(this->_io->launch(tid)) << sign;
		/**
		 * Поднимаем устройство туннеля
		 *
		 * @note Без признака UP служебного обмена не возникает вовсе: ядро заводит
		 *       адреса и начинает оповещения лишь на поднятом устройстве
		 */
		const std::string iface = this->_io->getIface(tid);
		ASSERT_FALSE(iface.empty()) << sign;
		{
			// Создаём объект работы с сетью
			awh::eth_t eth(this->_fmk.get(), this->_log.get());
			// Поднимаем устройство туннеля
			ASSERT_TRUE(eth.iface.flag(iface, awh::event::eth_flag_t::UP, awh::event::mode_t::ENABLED)) << sign;
		}
		/**
		 * Крутим опрос, покуда ядро ведёт служебный обмен
		 */
		// Отмечаем миг работы: устройство поднято, идёт опрос
		stage = "опрос";
		const auto start = std::chrono::steady_clock::now();
		while((std::chrono::duration_cast <std::chrono::milliseconds> (std::chrono::steady_clock::now() - start).count() < 1500))
			ASSERT_TRUE(this->_io->poll(50)) << sign;
		// Отмечаем миг работы: снятие узла
		stage = "снятие";
		// Снимаем событие туннеля
		ASSERT_TRUE(this->_io->destroy(tid)) << sign;
	}
	// Роспись итога для сообщений об отказе
	const std::string sign = std::string("отказов=") + std::to_string(errors) + " подмен=" + std::to_string(attacks) +
	                         ((errors > 0) ? (" первый отказ: " + reason) : std::string(""));
	/**
	 * Печатаем снятое число всегда
	 *
	 * @note Нуль здесь двусмыслен: он значит либо что мерка служебный обмен отбирает,
	 *       либо что обмена на этой машине не возникло вовсе. Различает их только
	 *       снятое ДО правки число, оттого оно и печатается
	 */
	std::cout << "служебный обмен IPv4: " << sign << std::endl;
	// Служебный обмен узла подменой адреса объявлен быть не может
	ASSERT_EQ(attacks, 0) << sign;
	// Отказов при служебном обмене не возникает вовсе
	ASSERT_EQ(errors, 0) << sign;
	// Сворачиваем движок
	ASSERT_TRUE(this->_io->deinitialize());
}

