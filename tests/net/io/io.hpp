/**
 * @brief Наибольший срок одного оборота опроса в проверках, в миллисекундах
 *
 * @details Циклы ожидания в проверках сторожатся сроком: `while(!stop && (now <
 *          deadline) && io.poll(...))`. Срок этот работает лишь тогда, когда опрос
 *          УПРАВЛЕНИЕ ВОЗВРАЩАЕТ
 *
 * @warning Умолчанием `poll()` ждёт БЕЗ ПРЕДЕЛА, и с ним сторож не срабатывает вовсе:
 *          условие цикла до следующей проверки не доходит, потому что первый же вызов
 *          не возвращается. Проверка тогда не отказывает, а ВИСИТ, и висит молча -
 *          неотличимо от долгой работы. Установлено дорого: набор под `io_uring`
 *          молчал четырнадцать минут, и место назвал лишь образец стека -
 *          `IoTCPTest` спала в `io_uring_enter`, дожидаясь завершения, какое движок
 *          сам же и выбросил (см. правку разбора завершений в io_uring.cpp)
 *
 * @note Оборот без единого события договором объявлен обычным успехом, оттого
 *       ограниченный срок цикл не рвёт: опрос отвечает удачей, цикл сверяет сторож и
 *       идёт дальше. Плата - пробуждение раз в долю секунды на время ожидания
 *
 */
static constexpr int32_t __AWH_TEST_POLL_SLICE__ = 100;

/**
 * @brief Функция снятия кода последнего отказа системы
 *
 * @details Утверждение, печатающее один лишь итог вызова, отказ НЕ ОБЪЯСНЯЕТ: «-1»
 *          одинаково у занятого порта, у запрещённого и у любой иной беды, а лечатся
 *          они по-разному. Замер Андрея от 29.08.2026 встал ровно на этом - отказ
 *          привязки был, а по чему судить о нём, не было
 *
 * @note У MS Windows гнёзда отчитываются своим кодом, а не `errno`: `errno` там при
 *       отказе привязки не выставляется вовсе
 *
 * @return код последнего отказа системы
 *
 */
static inline int32_t __awh_last_error__() noexcept {
	/**
	 * Если операционной системой является MS Windows
	 */
	#if defined(_WIN32) || defined(_WIN64)
		// Выводим код последнего отказа гнёзд
		return static_cast <int32_t> (::WSAGetLastError());
	/**
	 * Если операционной системой является не MS Windows
	 */
	#else
		// Выводим код последнего отказа
		return static_cast <int32_t> (errno);
	#endif
}
/**
 * @brief Функция снятия разряда временных портов, каким распоряжается система
 *
 * @details Разряд этот у каждой системы свой, и спрашивается он у неё самой, а не
 *          берётся зашитым числом: у Linux и FreeBSD он правится `sysctl`, и на
 *          машине с изменённой настройкой зашитое число разошлось бы с
 *          действительностью МОЛЧА
 *
 * @note Замерено 29.08.2026 на стендах: macOS 49152-65535, Linux 32768-60999,
 *       FreeBSD 10000-65535, OpenBSD 1024-49151, NetBSD 49152-65535,
 *       MS Windows 49152-65535
 *
 * @param first нижняя граница разряда временных портов системы
 * @param last  верхняя граница разряда временных портов системы
 * @return      признак того, что разряд снять удалось
 *
 */
static inline bool __awh_system_ephemeral__(uint16_t & first, uint16_t & last) noexcept {
	/**
	 * Если операционной системой является Linux
	 */
	#if __linux__
		// Открываем настройку разряда временных портов ядра
		FILE * file = ::fopen("/proc/sys/net/ipv4/ip_local_port_range", "r");
		// Если настройку открыть не удалось, разряд системы неизвестен
		if(file == nullptr)
			// Выводим признак неудачи
			return false;
		// Снимаемые границы разряда
		uint32_t begin = 0, end = 0;
		// Выполняем чтение границ разряда
		const bool result = (::fscanf(file, "%u %u", &begin, &end) == 2);
		// Закрываем настройку разряда
		::fclose(file);
		// Если границы разряда прочитаны и они осмысленны
		if(result && (begin > 0) && (end >= begin) && (end <= 65535)){
			// Запоминаем нижнюю границу разряда
			first = static_cast <uint16_t> (begin);
			// Запоминаем верхнюю границу разряда
			last = static_cast <uint16_t> (end);
			// Выводим признак удачи
			return true;
		}
		// Выводим признак неудачи
		return false;
	/**
	 * Если операционной системой является MS Windows
	 *
	 * @note Открытого способа спросить разряд у системы нет: `iphlpapi` его не
	 *       выдаёт, а разбирать вывод `netsh` нельзя - он идёт на языке машины.
	 *       Берётся значение, установленное системой с Vista, и оно же выдаётся
	 *       самой `netsh` на стенде
	 */
	#elif defined(_WIN32) || defined(_WIN64)
		// Запоминаем нижнюю границу разряда
		first = 49152;
		// Запоминаем верхнюю границу разряда
		last = 65535;
		// Выводим признак удачи
		return true;
	/**
	 * Если операционной системой является Solaris либо illumos
	 *
	 * @note Разряд там держится настройкой `ipadm`, и спросить его иначе как
	 *       вызовом нечем. Отказ вызова не беда: ниже стоит значение по умолчанию
	 */
	#elif __sun
		// Снимаемые границы разряда
		uint32_t begin = 32768, end = 65535;
		// Открываем поток вызова снятия нижней границы разряда
		FILE * pipe = ::popen("ipadm show-prop -p smallest_anon_port -co current tcp 2>/dev/null", "r");
		// Если поток вызова открыть удалось
		if(pipe != nullptr){
			// Выполняем чтение нижней границы разряда
			static_cast <void> (::fscanf(pipe, "%u", &begin));
			// Закрываем поток вызова
			::pclose(pipe);
		}
		// Открываем поток вызова снятия верхней границы разряда
		pipe = ::popen("ipadm show-prop -p largest_anon_port -co current tcp 2>/dev/null", "r");
		// Если поток вызова открыть удалось
		if(pipe != nullptr){
			// Выполняем чтение верхней границы разряда
			static_cast <void> (::fscanf(pipe, "%u", &end));
			// Закрываем поток вызова
			::pclose(pipe);
		}
		// Если снятые границы разряда осмысленны
		if((begin > 0) && (end >= begin) && (end <= 65535)){
			// Запоминаем нижнюю границу разряда
			first = static_cast <uint16_t> (begin);
			// Запоминаем верхнюю границу разряда
			last = static_cast <uint16_t> (end);
			// Выводим признак удачи
			return true;
		}
		// Выводим признак неудачи
		return false;
	/**
	 * Если операционной системой является macOS, FreeBSD, DragonFly, NetBSD либо OpenBSD
	 *
	 * @warning Имена настроек у этих систем РАЗНЫЕ, и это не мелочь: у macOS,
	 *          FreeBSD и DragonFly разряд зовётся `net.inet.ip.portrange.first`
	 *          и `.last`, у NetBSD - `net.inet.ip.anonportmin` и `anonportmax`,
	 *          у OpenBSD - `net.inet.ip.portfirst` и `portlast`. Спрошенное
	 *          чужим именем отвечает отказом, и разряд остался бы неизвестен
	 */
	#else
		// Снимаемые границы разряда
		int32_t begin = 0, end = 0;
		// Размер снимаемой границы разряда
		size_t length = sizeof(int32_t);
		/**
		 * Если операционной системой является OpenBSD
		 */
		#if __OpenBSD__
			// Ветвь снятия нижней границы разряда
			int32_t lower[] = {CTL_NET, PF_INET, IPPROTO_IP, IPCTL_IPPORT_FIRSTAUTO};
			// Ветвь снятия верхней границы разряда
			int32_t upper[] = {CTL_NET, PF_INET, IPPROTO_IP, IPCTL_IPPORT_LASTAUTO};
			// Если нижнюю границу разряда снять не удалось
			if(::sysctl(lower, 4, &begin, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
			// Восстанавливаем размер снимаемой границы
			length = sizeof(int32_t);
			// Если верхнюю границу разряда снять не удалось
			if(::sysctl(upper, 4, &end, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
		/**
		 * Если операционной системой является NetBSD
		 */
		#elif __NetBSD__
			// Если нижнюю границу разряда снять не удалось
			if(::sysctlbyname("net.inet.ip.anonportmin", &begin, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
			// Восстанавливаем размер снимаемой границы
			length = sizeof(int32_t);
			// Если верхнюю границу разряда снять не удалось
			if(::sysctlbyname("net.inet.ip.anonportmax", &end, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
		/**
		 * Если операционной системой является macOS, FreeBSD либо DragonFly
		 */
		#else
			// Если нижнюю границу разряда снять не удалось
			if(::sysctlbyname("net.inet.ip.portrange.first", &begin, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
			// Восстанавливаем размер снимаемой границы
			length = sizeof(int32_t);
			// Если верхнюю границу разряда снять не удалось
			if(::sysctlbyname("net.inet.ip.portrange.last", &end, &length, nullptr, 0) != 0)
				// Выводим признак неудачи
				return false;
		#endif
		// Если снятые границы разряда осмысленны
		if((begin > 0) && (end >= begin) && (end <= 65535)){
			// Запоминаем нижнюю границу разряда
			first = static_cast <uint16_t> (begin);
			// Запоминаем верхнюю границу разряда
			last = static_cast <uint16_t> (end);
			// Выводим признак удачи
			return true;
		}
		// Выводим признак неудачи
		return false;
	#endif
}
/**
 * @brief Функция выбора разряда портов для проверок ВНЕ разряда системы
 *
 * @details Раздатчик портов проверок черпал из разряда 49152-65535 - того самого,
 *          из которого система выдаёт временные порты сокетам, привязанным к порту
 *          нуль. Состязание это проба привязкой НЕ снимает: она закрывает занятость
 *          лишь на миг проверки, а между её закрытием и привязкой потребителя ядро
 *          вправе выдать тот же номер любому сокету. У MS Windows это давало
 *          плавающий WSAEACCES примерно раз на восемь полных прогонов набора
 *          (замер Андрея от 29.08.2026), причём место в ряду плавало, что отвечает
 *          гонке, а не наследству от соседей
 *
 * @warning Взять просто «числа поменьше» НЕЛЬЗЯ: единого свободного разряда у всех
 *          систем нет вовсе. Предложенный было 20000-40000 свободен лишь у MS
 *          Windows и macOS: у Linux он задевает 32768-40000, у FreeBSD (10000-65535)
 *          и OpenBSD (1024-49151) перекрыт целиком. Оттого разряд не назначается, а
 *          ВЫЧИСЛЯЕТСЯ: берётся более широкая из двух полос, остающихся по краям от
 *          разряда системы
 *
 * @param begin нижняя граница разряда, отводимого проверкам
 * @param end   верхняя граница разряда, отводимого проверкам
 *
 */
static inline void __awh_test_port_range__(uint16_t & begin, uint16_t & end) noexcept {
	// Наименьшая ширина полосы, какую есть смысл отводить проверкам
	constexpr uint16_t NARROWEST = 1024;
	/**
	 * Желаемый пол полосы: выше общеизвестных служб
	 *
	 * @warning Полоса, начинающаяся с 1024, задевает НАСТОЯЩИЕ службы машины: у MS
	 *          Windows там живут mDNS 5353, SSDP 1900, WS-Discovery 3702, LLMNR 5355 и
	 *          прочие. Замер Андрея от 29.08.2026 это и показал: состязание с ядром
	 *          ушло (29 прогонов из 30 чисты против 1 отказа на 8 прежде), но взамен
	 *          пришёл редкий отказ прямой привязки в проверке. Пол в десять тысяч
	 *          уводит полосу выше почти всех таких служб
	 *
	 * @note Пол этот ЖЕЛАЕМЫЙ, а не обязательный: у FreeBSD ядро занимает 10000-65535,
	 *       и вся свободная полоса там лежит НИЖЕ пола. Требуй мы его - выбирать стало
	 *       бы не из чего, оттого пол берётся лишь когда полоса от него остаётся
	 *       достаточной
	 */
	constexpr uint16_t PREFERRED = 10000;
	// Границы разряда, каким распоряжается система
	uint16_t first = 0, last = 0;
	// Отводим разряд по умолчанию: он же остаётся, когда систему спросить не вышло
	begin = 49152;
	// Устанавливаем верхнюю границу разряда по умолчанию
	end = 65535;
	// Если разряд системы снять не удалось, остаёмся при разряде по умолчанию
	if(!__awh_system_ephemeral__(first, last))
		// Выходим из функции
		return;
	// Ширина полосы, остающейся НИЖЕ разряда системы
	const uint32_t lower = ((first > (NARROWEST + 1024)) ? (static_cast <uint32_t> (first) - 1024) : 0);
	// Ширина полосы, остающейся ВЫШЕ разряда системы
	const uint32_t upper = ((last < (65535 - NARROWEST)) ? (65535 - static_cast <uint32_t> (last)) : 0);
	// Если обе полосы слишком узки, остаёмся при разряде по умолчанию
	if((lower == 0) && (upper == 0))
		// Выходим из функции
		return;
	// Если полоса ниже разряда системы шире
	if(lower >= upper){
		/**
		 * Отводим проверкам полосу ниже разряда системы, начиная её по возможности с
		 * желаемого пола: остаётся от него достаточно - берём пол, нет - берём 1024
		 */
		begin = ((first > (PREFERRED + NARROWEST)) ? PREFERRED : static_cast <uint16_t> (1024));
		// Устанавливаем верхнюю границу отводимой полосы
		end = static_cast <uint16_t> (first - 1);
	// Если шире полоса выше разряда системы
	} else {
		// Отводим проверкам полосу выше разряда системы
		begin = static_cast <uint16_t> (last + 1);
		// Устанавливаем верхнюю границу отводимой полосы
		end = 65535;
	}
}
