/**
 * @brief Тест совпадения разновидности хоста с полным перебором разновидностей
 *
 * @details Установка хоста URI отбирает разновидность сетевого адреса по алфавиту
 *          строки, а из восьми разновидностей хоста спрашивает у модуля адресов
 *          только принадлежность к путям файловой системы. И то и другое обязано
 *          давать тот же ответ, что и полный перебор разновидностей: алфавит - как
 *          надмножество алфавитов разбора адреса, сокращённый вопрос - как
 *          совпадающий с полным на всех достижимых строках.
 *
 *          Свойство это на отдельных образцах не проверяется - его надо проверять
 *          сличением, поэтому ответ модуля сличается с ответом полного перебора на
 *          наборе образцов, покрывающем все разновидности и их пограничные случаи
 *
 */
TEST_F(UriFixture, HostKindMatchesFullScanTest){
	// Набор образцов строк хоста, покрывающий все разновидности и их пограничные случаи
	const std::vector <std::string> samples = {
		// Сетевые адреса IPv4 в обычной и устаревших записях
		"192.168.1.100", "8.8.8.8", "0.0.0.0", "255.255.255.255", "127.0.0.1",
		"0x7f.0.0.1", "0177.0.0.1", "192.168.1", "16909060",
		// Сетевые адреса IPv4 с пробелами вокруг: разбор адреса их обрезает
		" 192.168.1.100", "192.168.1.100 ", "\t192.168.1.100\r\n",
		// Сетевые адреса IPv6, в том числе в скобках, как они приходят из URI
		"::1", "::", "2001:db8::1", "[::1]", "[2001:db8:85a3::8a2e:370:7334]",
		"::ffff:192.168.1.1", "fe80::1%lo0", "fd00::1", "2606:4700:4700::1111",
		// Аппаратные адреса: разбором принимаются, атрибутов сетевого адреса не получают
		"02:42:9b:9e:f9:ae", "0242 9b9ef9ae", "ff:ff:ff:ff:ff:ff",
		// Доменные имена
		"example.com", "www.example.com", "localhost", "a.b.c.d.e.f.g",
		"xn--80aswg.xn--p1ai", "sub-domain.example.co.uk", "ABCDEF",
		// Доменные имена из алфавита сетевых адресов: разбором отвергаются
		"abc.def", "aaaa", "fade.cafe", "dead:beef", "0xzz.1",
		// Пути файловой системы во всех признаваемых записях
		"/var/run/socket.sock", "/tmp/x", "~/socket", "./relative.sock",
		"../up.sock", ".example.com", "\\\\host\\share", "C:\\path\\file",
		"D:/path/file",
		// Сети, URL-адреса и прочие строки, разновидностью хоста не являющиеся
		"192.168.0.0/24", "2001:db8::/32", "http://example.com/x",
		"https://example.com", "example.com:8080", "",
		// Пограничные случаи из одиночных символов
		"/", ".", "~", ":", "[", "]", "x", "0", "-"
	};
	// Набор образцов строк хоста, дополненный случайными строками
	std::vector <std::string> corpus = samples;
	/**
	 * Дополняем набор случайными строками из алфавита, на символах которого отбор
	 * разновидности и принимает решения: одних отобранных вручную образцов для
	 * проверки надмножества недостаточно - недостающий в алфавите символ проявился
	 * бы только на той строке, о которой не подумали
	 */
	{
		// Алфавит случайных строк: символы, на которых отбор принимает решения
		static const std::string alphabet = "09afxAFX.:/%[]-~htpsHTPS\\ \t";
		// Датчик случайных чисел с постоянным зерном: набор обязан быть повторяемым
		std::mt19937 generator(20260729);
		// Распределение длины случайной строки
		std::uniform_int_distribution <size_t> length(1, 20);
		// Распределение положения символа в алфавите
		std::uniform_int_distribution <size_t> letter(0, alphabet.size() - 1);
		// Резервируем память под случайные строки
		corpus.reserve(corpus.size() + 20000);
		/**
		 * Вырабатываем случайные строки хоста
		 */
		for(size_t i = 0; i < 20000; i++){
			// Вырабатываемая случайная строка
			std::string sample;
			// Определяем длину вырабатываемой строки
			const size_t size = length(generator);
			// Резервируем память под вырабатываемую строку
			sample.reserve(size);
			/**
			 * Наполняем строку символами алфавита
			 */
			for(size_t j = 0; j < size; j++)
				// Добавляем очередной символ алфавита
				sample.append(1, alphabet[letter(generator)]);
			// Добавляем выработанную строку в набор образцов
			corpus.push_back(std::move(sample));
		}
	}
	// Объект работы с сетевыми адресами для полного перебора разновидностей
	awh::net_addr_t reference(this->_fmk.get(), this->_log.get());
	/**
	 * Перебираем все образцы строк хоста
	 */
	for(const auto & sample : corpus){
		// Пропускаем пустую строку: установка хоста её не обрабатывает
		if(sample.empty())
			// Переходим к следующему образцу
			continue;
		// Выполняем полный разбор образца как сетевого адреса
		const bool address = reference.parse(sample);
		// Извлекаем разновидность разобранного сетевого адреса
		const awh::net_addr_t::type_t parsed = (address ? reference.type() : awh::net_addr_t::type_t::NONE);
		// Выполняем полный перебор разновидностей хоста
		const awh::net_addr_t::type_t scanned = reference.host(sample);
		// Ожидаемая разновидность атрибутов URI
		awh::net::type_t expected = awh::net::type_t::FQDN;
		// Если образец разобран как IPv4-адрес
		if(parsed == awh::net_addr_t::type_t::IPV4)
			// Ожидаем атрибуты IPv4-адреса
			expected = awh::net::type_t::IPV4;
		// Если образец разобран как IPv6-адрес
		else if(parsed == awh::net_addr_t::type_t::IPV6)
			// Ожидаем атрибуты IPv6-адреса
			expected = awh::net::type_t::IPV6;
		// Если полный перебор отнёс образец к путям файловой системы
		else if(scanned == awh::net_addr_t::type_t::FS)
			// Ожидаем атрибуты доменного сокета
			expected = awh::net::type_t::FS;
		// Создаём отдельный объект работы с URI под каждый образец
		awh::uri_t uri(this->_fmk.get(), this->_log.get());
		// Устанавливаем хост URI
		uri.host(sample);
		// Проверяем, что атрибуты URI заведены
		ASSERT_TRUE(uri.attr() != nullptr) << "образец: " << sample;
		// Проверяем совпадение разновидности атрибутов с ответом полного перебора
		ASSERT_EQ(expected, uri.attr()->type) << "образец: " << sample;
	}
}

/**
 * @brief Тест наборов символов, не подлежащих процентному кодированию, по элементам URI
 *
 * @note Набор разрешённых символов у пути и у параметров запроса различается, и
 *       различие это существенно: символ "&" в пути допустим, а в значении параметра
 *       обязан кодироваться, иначе он разделит пару надвое; символ "/" наоборот
 *
 */
TEST_F(UriFixture, EncodePerElementSetsTest){
	// Выполняем очистку объекта работы с URI
	this->_uri->clear();
	// Выполняем разбор URI, задающего тип и хост
	ASSERT_EQ(awh::uri_t::type_t::HTTP, this->_uri->parse("http://example.com/"));
	// Устанавливаем путь URI, сегменты которого содержат знаки препинания
	this->_uri->path({"a&b", "c=d", "e/f", "g?h", "i#j"});
	/**
	 * В пути символы "&", "=" допустимы и кодированию не подлежат,
	 * а "/", "?" и "#" обязаны кодироваться: первый разделил бы сегменты,
	 * остальные оборвали бы путь
	 */
	ASSERT_EQ("/a&b/c=d/e%2Ff/g%3Fh/i%23j", this->_uri->print(awh::uri_t::item_t::PATH));
	// Устанавливаем единственный параметр URI, значение которого содержит знаки препинания
	this->_uri->query({{"k", "a&b=c/d?e#f"}});
	/**
	 * В параметрах символ "/" допустим и кодированию не подлежит,
	 * а "&", "=", "?" и "#" обязаны кодироваться
	 */
	ASSERT_EQ("k=a%26b%3Dc/d%3Fe%23f", this->_uri->print(awh::uri_t::item_t::QUERY));
}

