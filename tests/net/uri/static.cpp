/**
 * @brief Тест разрешения ссылки относительно базового адреса
 *
 * @details Сервер отдаёт в заголовке Location ссылку, которая может быть и
 *          полным адресом, и одним лишь путём, и даже одними параметрами, а
 *          идти дальше нужно по адресу, собранному из неё и из текущего.
 *          Порядок разрешения расписан в RFC 3986 5.2.2, а образцы для проверки
 *          даны там же, в 5.4, - ими тест и проверяется.
 *
 *          Прежде разрешался один случай из шести: ссылка с путём от корня.
 *          Относительный путь с базовым не складывался, обозначения каталогов
 *          становились хостом, а ссылка сетевого пути хост не меняла
 *
 */
TEST_F(UriFixture, ReferenceResolutionTest){
	// Базовый адрес из RFC 3986 5.4
	const std::string base = "http://a.example.com/b/c/d;p?q";
	// Образцы ссылок и ожидаемых от них адресов
	const std::vector <std::pair <std::string, std::string>> samples = {
		// Ссылка с путём от корня замещает путь целиком
		{"/new_addr", "http://a.example.com/new_addr"},
		// Относительная ссылка складывается с базовым путём
		{"g", "http://a.example.com/b/c/g"},
		// Обозначение текущего каталога снимается
		{"./g", "http://a.example.com/b/c/g"},
		// Обозначение родительского каталога снимает предшествующий сегмент
		{"../g", "http://a.example.com/b/g"},
		// Ссылка с путём замещает и параметры
		{"g?y", "http://a.example.com/b/c/g?y"},
		// Ссылка из одного якоря путь и параметры оставляет
		{"#frag", "http://a.example.com/b/c/d;p?q#frag"},
		// Ссылка из одних параметров путь оставляет, а параметры замещает
		{"?y", "http://a.example.com/b/c/d;p?y"},
		// Ссылка сетевого пути замещает авторити, а схему оставляет
		{"//other.example.com/g", "http://other.example.com/g"},
		// Ссылка со схемой замещает собой всё
		{"https://other.com/g", "https://other.com/g"},
		// Выйти выше корня разрешение не может
		{"../../../g", "http://a.example.com/g"}
	};
	/**
	 * Перебираем все образцы ссылок
	 */
	for(auto & sample : samples){
		// Выполняем очистку объекта работы с URI
		this->_uri->clear();
		// Выполняем разбор базового адреса
		this->_uri->parse(base);
		// Выполняем разрешение ссылки относительно базового адреса
		this->_uri->parse(sample.first);
		// Проверяем собранный адрес
		ASSERT_EQ(sample.second, this->_uri->print(awh::uri_t::item_t::URI)) << "ссылка: " << sample.first;
	}
}

