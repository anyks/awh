/**
 * @brief Тест сохранения зоны IPv6-адреса за записью
 *
 */
TEST_F(UriFixture, ZoneBelongsToRecordTest){
	/**
	 * Зона обозначает область действия адреса локальной связи и частью хоста
	 * является наравне с самим адресом (RFC 6874). Атрибуты сетевого адреса,
	 * однако, несут одни лишь октеты адреса, и зона оставалась лежать в объекте
	 * работы с сетевыми адресами - общем на весь модуль и переживающем разбор.
	 * Оттого доставалась она следующему разобранному адресу: хост "127.0.0.1",
	 * разобранный вслед за "[fe80::1%25eth0]", печатался как "127.0.0.1%eth0"
	 */
	// Выполняем разбор записи с зоной IPv6-адреса
	this->_uri->parse("http://[fe80::1%25eth0]/a");
	// Проверяем хост, извлечённый из записи
	ASSERT_EQ("FE80::1%eth0", this->_uri->host());
	// Проверяем строку, собранную из записи
	ASSERT_EQ("http://[FE80::1%25eth0]/a", this->_uri->print(awh::uri_t::item_t::URI));
	// Выполняем разбор записи с адресом IPv4 тем же объектом
	this->_uri->clear();
	// Выполняем разбор записи, зоны не несущей
	this->_uri->parse("http://127.0.0.1/a");
	// Зона прежней записи новой достаться не должна
	ASSERT_EQ("127.0.0.1", this->_uri->host());
	// Проверяем строку, собранную из записи
	ASSERT_EQ("http://127.0.0.1/a", this->_uri->print(awh::uri_t::item_t::URI));
	// Выполняем разбор записи с доменным именем тем же объектом
	this->_uri->clear();
	// Выполняем разбор записи с доменным именем
	this->_uri->parse("http://example.com/a");
	// Проверяем хост, извлечённый из записи
	ASSERT_EQ("example.com", this->_uri->host());
	/**
	 * Установка хоста извне зону тоже сменяет: снятый с прежнего адреса объект
	 * иначе уносил бы её с собой
	 */
	// Выполняем разбор записи с зоной IPv6-адреса
	this->_uri->clear();
	// Выполняем разбор записи с зоной IPv6-адреса
	this->_uri->parse("http://[fe80::1%25en0]/a");
	// Выполняем установку адреса IPv4 в качестве хоста
	this->_uri->host("10.0.0.1");
	// Проверяем хост, установленный извне
	ASSERT_EQ("10.0.0.1", this->_uri->host());
	// Записи с разными зонами равными считаться не должны
	awh::uri_t first(this->_fmk.get(), this->_log.get());
	// Выполняем разбор первой записи
	first.parse("http://[fe80::1%25eth0]/a");
	// Второй объект сличения
	awh::uri_t second(this->_fmk.get(), this->_log.get());
	// Выполняем разбор второй записи
	second.parse("http://[fe80::1%25en0]/a");
	// Записи эти равными считаться не должны
	ASSERT_FALSE(first == second);
	// Неравенство обязано согласоваться с равенством
	ASSERT_TRUE(first != second);
	// Копия записи обязана нести зону оригинала
	awh::uri_t copy = first;
	// Проверяем хост копии записи
	ASSERT_EQ("FE80::1%eth0", copy.host());
	// Копия обязана считаться равной оригиналу
	ASSERT_TRUE(copy == first);
}

