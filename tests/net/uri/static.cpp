	built.path({"x"});
	// Строки обоих объектов обязаны совпасть
	ASSERT_EQ(this->_uri->print(awh::uri_t::item_t::URI), built.print(awh::uri_t::item_t::URI));
	// Объекты обязаны считаться равными
