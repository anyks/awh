/**
 * Подключаем заголовочный файлы проекта
 */
#include "nwt.hpp"

/**
 * @brief Итог разбора на уровне файла, закрепляющий порядок построения статических объектов
 *
 * @details Разбор выполняется ДО входа в `main`, а не для удобства. Списки доменных зон
 *          модуля прежде были объектами пространства имён, и объект модуля, объявленный
 *          потребителем на уровне файла, строился РАНЬШЕ них: конструктор трогал
 *          недостроенные наборы, поля их несли мусор, коэффициент загрузки выходил `inf`,
 *          и приложение падало ДО входа в `main` с необработанным
 *          `std::overflow_error: __next_prime overflow`. Списки переведены на
 *          функционально-статические — построение первым же обращением, в каком бы
 *          порядке оно ни пришло
 *
 * @warning Возврат прежнего устройства валит ВЕСЬ набор проверок до входа в `main`, ещё
 *          до вывода списка проверок. Это и есть закрепление: молча дефект не вернётся
 *
 * @note Санитайзеры этот класс дефектов НЕ ловят: под `-fsanitize=address` подмена выдачи
 *       памяти идёт мимо нашего распределителя, и падения не случается вовсе. Ловится
 *       только обычной сборкой
 *
 */
static const awh::nwt::url_t __awh_static_url__ = awh::nwt::parse("https://example.com/path");

/**
 * @brief Тест разбора на уровне файла
 *
 * @details Закрепляет порядок построения статических объектов: разбор выше выполнен ДО
 *          входа в `main`, и здесь проверяется, что он не просто пережил построение, а
 *          работоспособен — списки доменных зон заполнены и разбор ими пользуется
 *
 */
TEST_F(NwtFixture, StaticStorageNwtTest){
	// Проверяем, что разобранная на уровне файла запись опознана адресом
	ASSERT_EQ(__awh_static_url__.type, awh::nwt::types_t::URL);
	// Проверяем, что доменная зона выделена, то есть списки зон заполнены
	ASSERT_STREQ(__awh_static_url__.domain.c_str(), "com");
}
