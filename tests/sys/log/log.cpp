#include "log.hpp"

/**
 * Подключаем заголовочный файлы проекта
 */

/**
 * @brief Метод настройки тестового окружения
 *
 * @details Состояние журнала единственно на процесс, и настройка, сделанная одной
 *          проверкой, доходит до следующей. Опора потому возвращает журнал к
 *          заведомому состоянию перед КАЖДОЙ проверкой: иначе уровень или режим,
 *          выставленный соседкой, молча отменял бы утверждения
 *
 */
void LogFixture::SetUp(){
	// Возвращаем разрешение на вывод всех видов записей
	awh::log::level(awh::log::level_t::ALL);
	// Возвращаем название службы, заведённое по умолчанию
	awh::log::name(AWH_SHORT_NAME);
	// Снимаем перехват записей, оставленный соседней проверкой
	awh::log::subscribe(nullptr);
	// Возвращаем набор приёмников вывода, заведённый по умолчанию
	awh::log::mode({awh::log::mode_t::CONSOLE});
}

/**
 * @brief Метод очистки тестового окружения
 *
 * @details Перехват записей снимается и по завершении: он держит ссылки на
 *          переменные проверки, и оставленный - пережил бы их
 *
 */
void LogFixture::TearDown() {
	// Снимаем перехват записей, заведённый проверкой
	awh::log::subscribe(nullptr);
	// Возвращаем разрешение на вывод всех видов записей
	awh::log::level(awh::log::level_t::ALL);
}
