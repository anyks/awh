/**
 * @brief Наибольший штамп времени, представимый модулем
 *
 */
static constexpr uint64_t REFERENCE_LAST = 253402300799999ULL;

/**
 * @brief Шаг перебора в сутках
 *
 * @details Шаг взят взаимно простым с длиной недели, года и високосного круга, чтобы
 *          выборка не выстраивалась по одним и тем же дням. Сплошной перебор по каждым
 *          суткам той же проверкой пройден отдельно и расхождений не дал, но занимает
 *          минуты и в набор не выносится
 *
 */
static constexpr uint64_t REFERENCE_STEP = 97;

/**
 * @brief Переменные формата, определённые и POSIX, и модулем
 *
 * @details Переменные \%G, \%g, \%o, \%i, \%s и \%Z в перечень не входят: первые две
 *          модуль намеренно считает синонимами \%Y и \%y, остальные - его собственные
 *          расширения, эталона для которых в POSIX нет
 *
 */
static const char * REFERENCE_SPECS[] = {
	"%Y", "%m", "%d", "%H", "%M", "%S", "%j", "%u", "%w", "%a", "%A", "%b", "%B",
	"%C", "%e", "%I", "%p", "%U", "%W", "%y", "%D", "%F", "%T", "%R", "%n", "%t", "%%"
};

/**
 * @brief Записи, разбираемые и системой, и модулем
 *
 * @details Записи с двузначным обозначением года в перечень не входят: модуль
 *          раскрывает его скользящим окном по RFC 9110 (§5.6.7), а POSIX - жёстким
 *          правилом, и расхождение здесь намеренное. Записи с \%C двузначный год
 *          несут, но век задаёт его полностью, и окно в дело не вступает
 *
 */
static const char * REFERENCE_FORMATS[] = {
	"%Y-%m-%dT%H:%M:%S", "%Y%m%d%H%M%S", "%d/%b/%Y:%H:%M:%S",
	"%a, %d %b %Y %H:%M:%S", "%A %B %d %Y %H:%M:%S", "%Y-%j %H:%M:%S",
	"%d %m %Y %I:%M:%S %p", "%F %T", "%C%y-%m-%d %H:%M:%S", "%C %y %m %d %T",
	"%Y %m %d %H:%M:%S", "%B %e %Y %T"
};

/**
 * @brief Функция проверки, что переменная формата известна системному эталону
 *
 * @param spec проверяемая переменная формата
 * @return     признак того, что системный эталон переменную эту знает
 *
 * @details Проверка нужна оттого, что состав переменных, известных strftime, у систем
 *          разнится. Библиотека времени исполнения MinGW не знает девяти переменных
 *          перечня - \%u, \%C, \%e, \%D, \%F, \%T, \%R, \%n и \%t, - отвечая на каждую
 *          пустотой. Модуль же их знает и отвечает верно, отчего сверка с эталоном
 *          расходилась там, где расходиться нечему: подводил эталон, а не модуль
 *
 *          Отбор ведётся опытом, а не записанным списком: список пришлось бы держать
 *          для каждой библиотеки времени исполнения порознь и править его всякий раз,
 *          когда та меняется, а опыт спрашивает у самой системы то, что нужно знать
 *
 * @note Ни одна переменная перечня пустоты не даёт по существу: даже \%n и \%t
 *       выводят по одному символу. Оттого пустой ответ и годится приметой незнания
 *
 */
static bool known(const char * spec) noexcept {
	// Момент времени, на котором ведётся проверка
	const time_t seconds = 1234567890;
	// Структура времени системного эталона
	struct tm tm;
	// Если системный эталон момент времени не принял - считаем переменную неизвестной
	if(::gmtime_r(&seconds, &tm) == nullptr)
		// Выводим признак незнания
		return false;
	// Буфер записи системного эталона
	char buffer[256];
	// Выполняем обнуление буфера записи системного эталона
	::memset(buffer, 0, sizeof(buffer));
	// Проверяем что системный эталон переменную формата знает
	return (::strftime(buffer, sizeof(buffer), spec, &tm) > 0);
}

/**
 * @brief Структура параметров сверки с системным эталоном
 *
 */
struct ReferenceFixture : public ChronoFixture {
	/**
	 * @brief Метод получения момента времени по номеру суток
	 *
	 * @param day номер суток от начала промежутка
	 * @return    штамп времени в миллисекундах
	 *
	 */
	static uint64_t stamp(const uint64_t day) noexcept {
		// Формируем момент времени внутри суток
		return ((day * 86400000ULL)
			+ (((day * 7ULL) % 24ULL) * 3600000ULL)
			+ (((day * 13ULL) % 60ULL) * 60000ULL)
			+ (((day * 29ULL) % 60ULL) * 1000ULL));
	}
};

/**
 * @brief Тест соответствия записи системному strftime
 *
 * @details Каждая переменная формата сверяется со своим системным ответом на всём
 *          промежутке. Проверка ловит ошибки календаря, не видимые изнутри модуля:
 *          именно так обнаружился неверный день недели для всех дат от 2100 года,
 *          дававший 2 520 173 неверных суток из 2 932 897
 *
 */
TEST_F(ReferenceFixture, ExecutionReferenceFormatChronoTest){
	// Перечень переменных формата, сверяемых с системным эталоном
	std::vector <const char *> specs;
	// Перечень переменных формата, системному эталону не известных
	std::string skipped = "";
	/**
	 * Выполняем отбор переменных формата, известных системному эталону
	 */
	for(const char * spec : REFERENCE_SPECS){
		// Если системный эталон переменную формата знает
		if(known(spec))
			// Дополняем перечень сверяемых переменных формата
			specs.push_back(spec);
		// Если системный эталон переменную формата не знает
		else skipped.append(skipped.empty() ? "" : " ").append(spec);
	}
	/**
	 * Отброшенное выводится намеренно: сверка без части переменных слабее заявленной,
	 * и молчать о том, чего она не проверила, она не вправе
	 */
	// Если часть переменных формата системному эталону не известна
	if(!skipped.empty())
		// Выводим перечень переменных формата, сверкой не охваченных
		std::cout << "[   INFO   ] Системный эталон не знает переменных формата: " << skipped << std::endl;
	// Проверяем что сверять есть с чем
	ASSERT_FALSE(specs.empty());
	// Выполняем перебор суток по всему представимому промежутку
	for(uint64_t day = 0; (day * 86400000ULL) <= REFERENCE_LAST; day += REFERENCE_STEP){
		// Получаем момент времени текущих суток
		const uint64_t date = ReferenceFixture::stamp(day);
		// Если момент времени вышел за пределы представимого промежутка
		if(date > REFERENCE_LAST)
			// Завершаем перебор
			break;
		// Получаем момент времени в единицах системного эталона
		const time_t seconds = static_cast <time_t> (date / 1000ULL);
		// Структура времени системного эталона
		struct tm tm;
		// Если системный эталон момент времени не принял
		if(::gmtime_r(&seconds, &tm) == nullptr)
			// Переходим к следующим суткам
			continue;
		// Выполняем перебор всех переменных формата
		for(const char * spec : specs){
			// Буфер записи системного эталона
			char buffer[256];
			// Выполняем обнуление буфера записи системного эталона
			::memset(buffer, 0, sizeof(buffer));
			// Выполняем формирование записи системным эталоном
			::strftime(buffer, sizeof(buffer), spec, &tm);
			// Выполняем проверку соответствия записи модуля системному эталону
			ASSERT_EQ(this->_chrono->format(date, 0, spec), std::string(buffer))
				<< spec << " " << this->_chrono->format(date, 0, "%Y-%m-%dT%H:%M:%S");
		}
	}
}

/**
 * @brief Тест соответствия разбора системному strptime
 *
 * @details Запись формируется системой, а читается модулем: разбор проверяется на
 *          записи, к появлению которой модуль отношения не имеет
 *
 */
TEST_F(ReferenceFixture, ExecutionReferenceParseChronoTest){
	// Перечень записей, сверяемых с системным эталоном
	std::vector <const char *> formats;
	// Перечень записей, системному эталону не посильных
	std::string skipped = "";
	/**
	 * Запись отбрасывается целиком, стоит ей нести хоть одну неизвестную эталону
	 * переменную: эталон вывел бы её пустотой, и модулю подавалась бы на разбор
	 * запись, ни одной системой не порождаемая
	 */
	for(const char * format : REFERENCE_FORMATS){
		// Признак того, что запись системному эталону посильна целиком
		bool supported = true;
		/**
		 * Выполняем перебор всех переменных формата записи
		 */
		for(const char * i = format; (i[0] != '\0') && supported; i++){
			// Если найдена не переменная формата - переходим к следующему символу
			if((i[0] != '%') || (i[1] == '\0'))
				// Переходим к следующему символу записи
				continue;
			// Переменная формата, вычлененная из записи
			const char spec[3] = {i[0], i[1], '\0'};
			// Проверяем что системный эталон переменную формата знает
			supported = known(spec);
			// Пропускаем разобранную переменную формата
			i++;
		}
		// Если запись системному эталону посильна
		if(supported)
			// Дополняем перечень сверяемых записей
			formats.push_back(format);
		// Если запись системному эталону не посильна
		else skipped.append(skipped.empty() ? "" : ", ").append(format);
	}
	// Если часть записей системному эталону не посильна
	if(!skipped.empty())
		// Выводим перечень записей, сверкой не охваченных
		std::cout << "[   INFO   ] Системный эталон не осилил записей: " << skipped << std::endl;
	// Проверяем что сверять есть с чем
	ASSERT_FALSE(formats.empty());
	// Выполняем перебор суток по всему представимому промежутку
	for(uint64_t day = 0; (day * 86400000ULL) <= REFERENCE_LAST; day += REFERENCE_STEP){
		// Получаем момент времени текущих суток
		const uint64_t date = ReferenceFixture::stamp(day);
		// Если момент времени вышел за пределы представимого промежутка
		if(date > REFERENCE_LAST)
			// Завершаем перебор
			break;
		// Получаем момент времени в единицах системного эталона
		const time_t seconds = static_cast <time_t> (date / 1000ULL);
		// Структура времени системного эталона
		struct tm tm;
		// Если системный эталон момент времени не принял
		if(::gmtime_r(&seconds, &tm) == nullptr)
			// Переходим к следующим суткам
			continue;
		// Выполняем перебор всех записей
		for(const char * format : formats){
			// Буфер записи системного эталона
			char buffer[256];
			// Выполняем обнуление буфера записи системного эталона
			::memset(buffer, 0, sizeof(buffer));
			// Выполняем формирование записи системным эталоном
			::strftime(buffer, sizeof(buffer), format, &tm);
			// Выполняем проверку разбора записи, сформированной системным эталоном
			ASSERT_EQ(this->_chrono->parse(buffer, format), date) << format << " [" << buffer << "]";
		}
	}
}

/**
 * @brief Сводные временные зоны Северной Америки и их системные соответствия
 *
 */
static const struct ReferenceZone {
	// Сводная временная зона модуля
	awh::chrono_t::zone_t zone;
	// Название зоны в базе временных зон системы
	const char * name;
	// Запись зоны в виде POSIX, базы временных зон не требующем
	const char * rule;
	// Год, с которого зона следует общему правилу перехода
	uint16_t since;
} REFERENCE_ZONES[] = {
	{awh::chrono_t::zone_t::ET, "America/New_York",    "EST5EDT",    2007},
	{awh::chrono_t::zone_t::CT, "America/Chicago",     "CST6CDT",    2007},
	{awh::chrono_t::zone_t::MT, "America/Denver",      "MST7MDT",    2007},
	{awh::chrono_t::zone_t::PT, "America/Los_Angeles", "PST8PDT",    2007},
	{awh::chrono_t::zone_t::AT, "America/Halifax",     "AST4ADT",    2007},
	/**
	 * Ньюфаундленд до 2012 года переходил на летнее время в 00:01 местного, а не в
	 * 02:00 общего правила, которому следует модуль: 18 переходов 2007-2011 годов
	 * расходятся с базой временных зон системы намеренно
	 */
	{awh::chrono_t::zone_t::NT, "America/St_Johns",    "NST3:30NDT", 2012}
};

/**
 * @brief Обозначение зоны, подаваемое переменной окружения TZ
 *
 * @details У операционных систем POSIX подаётся название из базы временных зон: она
 *          несёт настоящую летопись правил перехода и как эталон сильнее
 *
 *          У MS Windows базы этой нет вовсе, а её название библиотека времени
 *          исполнения разбирает по правилам записи POSIX и получает бессмыслицу.
 *          Проверено опытом на стенде: с «America/New_York» момент 2020-07-01T12:00:00Z
 *          выходил местным временем 13:00 вместо 08:00 - смещение не то и знаком, и
 *          величиной. Оттого там подаётся запись POSIX, база зон которой не нужна
 *
 * @note Записи эти проверены опытом на всех шести зонах - на зиме, на лете и на самих
 *       мгновениях перехода, включая переходы Галифакса и Ньюфаундленда, приходящиеся
 *       на иные часы всемирного времени. Правила перехода США после 2007 года
 *       библиотека времени исполнения MS Windows держит встроенными, а Канада следует
 *       им же, отчего замена и годится на всём промежутке проверки
 *
 */
#if _WIN32 || _WIN64
	#define REFERENCE_ZONE_NAME(zone) (zone).rule
#else
	#define REFERENCE_ZONE_NAME(zone) (zone).name
#endif

/**
 * @brief Тест соответствия сводных зон Северной Америки системному календарю
 *
 * @details Сводные зоны вроде zone_t::ET обозначают то стандартное время, то летнее, и
 *          выбор между ними зависит от самого момента. Прежде выбор делался по
 *          текущему моменту, каким бы ни была записываемая дата, а признак летнего
 *          времени снимался со всемирных полей вместо местных. Проверка перебирает оба
 *          перехода по часам за 2007-2035 годы, сверяя смещение с базой временных зон
 *          системы: она и ловила расхождение в час на осеннем переходе
 *
 */
TEST_F(ReferenceFixture, ExecutionReferenceDaylightChronoTest){
	/**
	 * Для операционной системы MS Windows
	 *
	 * @details Сверка эта опирается на то, что система - эталон надёжный. У MS Windows
	 *          посылка эта не держится: библиотека времени исполнения раскладывает
	 *          момент по записи POSIX вроде «EST5EDT» противоречиво - выставляет
	 *          признак летнего времени и вместе с ним выдаёт стандартные часы. Для мига
	 *          2007-03-11T07:00:00Z, когда летнее время США 2007 года и начинается, она
	 *          отвечает то 03:00 (верно), то 02:00 при том же признаке (невозможно),
	 *          причём ответ разнится между запусками одного и того же двоичного файла
	 *          без единой правки. Модуль во всех замеченных случаях отвечал верно -
	 *          расходился именно эталон
	 *
	 * @note Прежде чем отступиться, отвергнуты опытом четыре объяснения: устаревшие
	 *       правила перехода у библиотеки времени исполнения, порча состояния перебором
	 *       strftime, порча его самим модулем и порядок исполнения тестов. Ни одно не
	 *       подтвердилось; отравление пустой переменной TZ подтвердилось и закрыто
	 *       отдельно - разборкой фикстуры, - но плавающего расхождения не объясняет
	 *
	 * @warning Отложено это, а не отменено: сверку надлежит вернуть, как только
	 *          отыщется на MS Windows источник правил перехода, отвечающий устойчиво.
	 *          Своих правил у набора нет и заводить их незачем - тем он
	 *          проверял бы себя самого
	 *
	 */
	#if _WIN32 || _WIN64
		// Пропускаем сверку с ненадёжным эталоном
		GTEST_SKIP() << "библиотека времени исполнения MS Windows эталоном перехода на летнее время служить не может";
	#endif
	// Выполняем перебор всех сводных временных зон
	for(const ReferenceZone & zone : REFERENCE_ZONES){
		// Перечень проверяемых моментов времени
		std::vector <uint64_t> dates;
		// Выполняем перебор годов, в которые действует текущее правило перехода
		for(uint16_t year = zone.since; year <= 2035; year++){
			// Выполняем перебор месяцев, в которые происходит переход
			for(const uint8_t month : {static_cast <uint8_t> (3), static_cast <uint8_t> (11)}){
				// Выполняем перебор первых двух недель месяца
				for(uint8_t day = 1; day < 15; day++){
					// Выполняем перебор всех часов суток
					for(uint8_t hour = 0; hour < 24; hour++){
						// Структура времени системного эталона
						struct tm tm;
						// Выполняем обнуление структуры времени системного эталона
						::memset(&tm, 0, sizeof(tm));
						// Заполняем структуру времени системного эталона
						tm.tm_year = (year - 1900);
						tm.tm_mon = (month - 1);
						tm.tm_mday = day;
						tm.tm_hour = hour;
						// Запоминаем проверяемый момент времени
						dates.push_back(static_cast <uint64_t> (::timegm(&tm)) * 1000ULL);
					}
				}
			}
		}
		// Перечень смещений временной зоны, снятых системным эталоном
		std::vector <int32_t> offsets;
		// Резервируем место под смещения временной зоны
		offsets.reserve(dates.size());
		/**
		 * Временная зона окружения выставляется однажды на всю зону, а не на каждый
		 * момент: применение её обходится дороже самой проверки
		 */
		// Выставляем временную зону окружения в проверяемую
		::setenv("TZ", REFERENCE_ZONE_NAME(zone), 1);
		// Применяем выставленную временную зону окружения
		::tzset();
		// Выполняем перебор всех проверяемых моментов времени
		for(const uint64_t date : dates){
			// Получаем момент времени в единицах системного эталона
			const time_t seconds = static_cast <time_t> (date / 1000ULL);
			// Запоминаем смещение временной зоны системного эталона
			offsets.push_back(::systemTimeZoneOffset(seconds));
		}
		// Восстанавливаем временную зону окружения, закреплённую фикстурой
		::setenv("TZ", "UTC", 1);
		// Применяем восстановленную временную зону окружения
		::tzset();
		// Выполняем перебор всех проверяемых моментов времени
		for(size_t i = 0; i < dates.size(); i++)
			// Выполняем проверку соответствия смещения зоны системному эталону
			ASSERT_EQ(this->_chrono->getTimeZone(this->_chrono->format(dates[i], zone.zone, "%z")), offsets[i])
				<< zone.name << " " << this->_chrono->format(dates[i], 0, "%Y-%m-%dT%H:%M:%SZ");
	}
}
