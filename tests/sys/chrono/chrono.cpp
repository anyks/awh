#include "chrono.hpp"


/**
 * @brief Метод настройки тестовой фикстуры
 *
 */
void ChronoFixture::SetUp(){
	// Получаем временную зону, установленную в окружении
	const char * zone = ::getenv("TZ");
	// Запоминаем признак наличия временной зоны в окружении
	this->_restore = (zone != nullptr);
	// Если временная зона в окружении установлена
	if(this->_restore)
		// Запоминаем временную зону окружения
		this->_zone.assign(zone);
	/**
	 * Закрепляем временную зону процесса на UTC: методы модуля берут смещение зоны
	 * из окружения всюду, где формат его не задаёт, и без закрепления ожидаемые
	 * значения набора зависели бы от настроек машины
	 */
	::setenv("TZ", "UTC", 1);
	// Применяем установленную временную зону
	::tzset();
	// Создаём объект фреймворка
	this->_fmk = std::make_unique <awh::fmk_t> ();
	// Создаём объект логгера
	this->_log = std::make_unique <awh::log_t> (this->_fmk.get());
	// Создаём объект модуля работы с датой и временем
	this->_chrono = std::make_unique <awh::chrono_t> (this->_fmk.get(), this->_log.get());
}

/**
 * @brief Метод очистки тестовой фикстуры
 *
 */
void ChronoFixture::TearDown(){
	// Если временная зона в окружении была установлена до начала теста
	if(this->_restore)
		// Восстанавливаем временную зону окружения
		::setenv("TZ", this->_zone.c_str(), 1);
	/**
	 * Для операционной системы MS Windows
	 *
	 * @details Снимать переменную окружения TZ здесь нельзя: библиотека времени
	 *          исполнения MS Windows после снятия её необратимо теряет правила перехода
	 *          на летнее время. Стоит единожды вызвать tzset при пустой либо снятой TZ,
	 *          и всякая последующая зона раскладывается противоречиво - для
	 *          «EST5EDT» на миг 2007-03-11T07:00:00Z выходит 02:00 при признаке
	 *          летнего времени, тогда как летнее время там начинается ровно в этот миг
	 *          и верное местное время равно 03:00. Состояние это внутри процесса не
	 *          лечится ничем: ни повторным tzset, ни заходом через иную зону, ни
	 *          повторной установкой той же самой
	 *
	 * @note Найдено сверкой с системным эталоном: тест перехода на летнее время
	 *       проходил в одиночку и падал следом за любым иным тестом фикстуры - тот
	 *       успевал снять переменную своей разборкой. Отравление воспроизведено
	 *       отдельной пробой на чистой библиотеке времени исполнения, без участия AWH
	 *
	 * @warning Обход этот - свойство испытательной оснастки, а не библиотеки: сам
	 *          модуль переменную окружения не трогает вовсе
	 *
	 */
	// Если временной зоны в окружении не было
	else {
		#if _WIN32 || _WIN64
			// Закрепляем временную зону окружения на UTC вместо снятия её
			::setenv("TZ", "UTC", 1);
		/**
		 * Для операционной системы не являющейся MS Windows
		 */
		#else
			// Снимаем временную зону окружения
			::unsetenv("TZ");
		#endif
	}
	// Применяем восстановленную временную зону
	::tzset();
}
