/**
 * @brief Функция получения смещения временной зоны системным эталоном
 *
 * @details Смещение выводится разностью местного и всемирного разложений одного и того
 *          же мига, а не берётся у поля tm_gmtoff. Поле это заведено договорами BSD и
 *          GNU, у Solaris и illumos его нет вовсе
 *
 * @note Подставлять сюда пару timezone и altzone, какой пользуется сама реализация,
 *       нельзя: набор сличал бы её вывод с её же формулой и ошибку в ней пропустил бы.
 *       Разность разложений выводится из иного источника - двух вызовов самой системы, -
 *       и остаётся сличением настоящим. Заодно исчезает разделение по системам: путь
 *       один на всякой из них
 *
 * @param value момент времени, для которого выводится смещение
 * @return      смещение временной зоны окружения в секундах
 *
 */
inline int32_t systemTimeZoneOffset(const time_t value) noexcept {
	// Разложения проверяемого мига по местной и всемирной временным зонам
	std::tm local = {}, utc = {};
	// Выполняем разложение времени по местной временной зоне
	::localtime_r(&value, &local);
	// Выполняем разложение того же времени по всемирной временной зоне
	::gmtime_r(&value, &utc);
	// Собираем разность разложений в пределах суток
	int32_t result = static_cast <int32_t> (
		((local.tm_hour - utc.tm_hour) * 3600) +
		((local.tm_min - utc.tm_min) * 60) +
		(local.tm_sec - utc.tm_sec)
	);
	/**
	 * Накладываем переход через границу суток
	 *
	 * @note Смещение зоны меньше суток, поэтому разложения расходятся не более чем на
	 *       одни сутки. Через границу года разность дней года обращается, и там
	 *       направление берётся у самого года
	 */
	if(local.tm_year != utc.tm_year)
		// Накладываем сутки в сторону большего года
		result += ((local.tm_year > utc.tm_year) ? 86400 : -86400);
	// Если разложения разошлись днём года, накладываем эту разность
	else if(local.tm_yday != utc.tm_yday)
		// Накладываем сутки в сторону большего дня года
		result += ((local.tm_yday > utc.tm_yday) ? 86400 : -86400);
	// Выводим собранное смещение временной зоны окружения
	return result;
}

