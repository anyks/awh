/**
 * @brief Тест инкремента и декремента длинного числа
 *
 */
TEST_F(BigNumFixture, IncrementBigNumTest){
	// Создаём число на границе переноса разряда
	awh::uint128_t number("18446744073709551615");

	// Выполняем префиксный инкремент числа
	++number;
	// Проверяем перенос разряда при инкременте
	ASSERT_EQ(number.print(), "18446744073709551616");

	// Выполняем префиксный декремент числа
	--number;
	// Проверяем заём разряда при декременте
	ASSERT_EQ(number.print(), "18446744073709551615");

	// Проверяем что постфиксный инкремент возвращает исходное значение
	ASSERT_EQ((number++).print(), "18446744073709551615");
	// Проверяем что значение числа увеличилось
	ASSERT_EQ(number.print(), "18446744073709551616");
	// Проверяем что постфиксный декремент возвращает исходное значение
	ASSERT_EQ((number--).print(), "18446744073709551616");
	// Проверяем что значение числа уменьшилось
	ASSERT_EQ(number.print(), "18446744073709551615");

	// Проверяем что унарный плюс не меняет значение числа
	ASSERT_EQ((+number).print(), "18446744073709551615");
}

