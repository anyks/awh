/**
 * @brief Тест беззнаковой целочисленной арифметики
 *
 */
TEST_F(BigNumFixture, UnsignedArithmeticBigNumTest){
	// Устанавливаем значение числа из 64-битного целого
	(* this->_natural) = 12345678901234567890ull;
	// Проверяем строковое представление числа
	ASSERT_EQ(this->_natural->print(), "12345678901234567890");

	// Проверяем возведение в степень на границе разрядности
	ASSERT_EQ(awh::uint128_t(2).pow(127).print(), "170141183460469231731687303715884105728");
	// Проверяем сдвиг на половину разрядной сетки
	ASSERT_EQ((awh::uint128_t(1) << 64).print(), "18446744073709551616");
	// Проверяем усечение результата по модулю разрядной сетки
	ASSERT_EQ(((awh::uint128_t(1) << 64) * (awh::uint128_t(1) << 64)).print(), "0");
	// Проверяем максимальное значение разрядности
	ASSERT_EQ(awh::uint128_t::maximum().print(), "340282366920938463463374607431768211455");
	// Проверяем минимальное значение беззнаковой разрядности
	ASSERT_EQ(awh::uint128_t::minimum().print(), "0");

	// Создаём число для проверки деления
	awh::uint128_t number("123456789012345678901234567890");

	// Проверяем результат деления
	ASSERT_EQ((number / 1000000007ull).print(), "123456788148148161864");
	// Проверяем результат взятия остатка
	ASSERT_EQ((number % 1000000007ull).print(), "197434842");
	// Проверяем тождество делимого через частное, делитель и остаток
	ASSERT_TRUE((((number / 1000000007ull) * 1000000007ull) + (number % 1000000007ull)) == number);

	// Проверяем извлечение целочисленного корня
	ASSERT_EQ(awh::uint128_t("1000000000000000000000000000000").sqrt().print(), "1000000000000000");
	// Проверяем извлечение корня из неполного квадрата
	ASSERT_EQ(awh::uint128_t(1000).sqrt().print(), "31");
}

