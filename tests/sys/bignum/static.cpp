	// Проверяем что остаток от деления на нуль даёт нуль
	ASSERT_EQ((awh::int128_t(5) % 0).print(), "0");
	// Проверяем что модуль минимального значения усекается по разрядной сетке
	ASSERT_EQ(awh::int128_t::minimum().abs().print(), awh::int128_t::minimum().print());

