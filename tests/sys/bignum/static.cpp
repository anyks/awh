/**
 * @brief Тест побитовых операций длинного числа
 *
 */
TEST_F(BigNumFixture, BitwiseBigNumTest){
	// Проверяем побитовое отрицание
	ASSERT_EQ((~awh::uint128_t(0)).print(), "340282366920938463463374607431768211455");
	// Проверяем побитовое И
	ASSERT_EQ((awh::uint128_t(0xF0) & awh::uint128_t(0x3C)).print(), "48");
	// Проверяем побитовое ИЛИ
	ASSERT_EQ((awh::uint128_t(0xF0) | awh::uint128_t(0x0F)).print(), "255");
	// Проверяем побитовое исключающее ИЛИ
	ASSERT_EQ((awh::uint128_t(0xFF) ^ awh::uint128_t(0x0F)).print(), "240");

	// Создаём число для проверки доступа к отдельным разрядам
	awh::uint128_t number;

	// Устанавливаем сотый разряд числа
	number.bit(100, true);

	// Проверяем что установленный разряд считывается
	ASSERT_TRUE(number.bit(100));
	// Проверяем что соседний разряд не установлен
	ASSERT_FALSE(number.bit(99));
	// Проверяем количество значащих разрядов числа
	ASSERT_EQ(number.bits(), 101);

	// Сбрасываем сотый разряд числа
	number.bit(100, false);

	// Проверяем что разряд сброшен
	ASSERT_FALSE(number.bit(100));
	// Проверяем что число обнулилось
	ASSERT_TRUE(number.zero());

	// Проверяем логическое отрицание нулевого числа
	ASSERT_TRUE(!number);
	// Проверяем логическое отрицание ненулевого числа
	ASSERT_FALSE(!awh::uint128_t(1));
}

