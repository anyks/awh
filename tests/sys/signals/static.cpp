/**
 * @brief Тест идемпотентности повторного запуска отслеживания
 *
 */
TEST_F(SignalsFixture, DoubleStartTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);

	// Создаём мьютекс для блокировки потока
	std::mutex mtx;
	// Создаём условную переменную
	std::condition_variable cv;
	// Количество полученных сигналов
	int32_t count = 0;

	/**
	 * Устанавливаем обработчик сигнала
	 */
	this->_signals->on([&](const int32_t){
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Увеличиваем счётчик полученных сигналов
		++count;
		// Пробуждаем ожидающий поток
		cv.notify_one();
	});

	// Запускаем отслеживание дважды подряд
	this->_signals->start();
	// Повторный запуск должен быть проигнорирован
	this->_signals->start();

	// Отправляем сигнал
	std::raise(SIGINT);

	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем получения сигнала с таймаутом
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return (count >= 1);}));
	}
}

/**
 * @brief Тест повторной доставки сигнала после перезапуска отслеживания
 *
 */
TEST_F(SignalsFixture, RestartDeliveryTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);

	// Создаём мьютекс для блокировки потока
	std::mutex mtx;
	// Создаём условную переменную
	std::condition_variable cv;
	// Количество полученных сигналов
	int32_t count = 0;
	// Последний полученный сигнал
	int32_t last = 0;

	/**
	 * Устанавливаем обработчик сигнала
	 */
	this->_signals->on([&](const int32_t sig){
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Запоминаем последний полученный сигнал
		last = sig;
		// Увеличиваем счётчик полученных сигналов
		++count;
		// Пробуждаем ожидающий поток
		cv.notify_one();
	});

	// Запускаем первый цикл отслеживания
	this->_signals->start();
	// Отправляем сигнал
	std::raise(SIGINT);
	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем получения первого сигнала
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return (count >= 1);}));
	}

	// Останавливаем отслеживание
	this->_signals->stop();

	// Запускаем второй цикл отслеживания с переустановкой обработчиков
	this->_signals->start();
	// Повторно отправляем сигнал
	std::raise(SIGINT);
	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем получения второго сигнала
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return (count >= 2);}));
	}

	// Проверяем корректность последнего полученного сигнала
	ASSERT_EQ(SIGINT, last);
	/**
	 * Сигналов ровно два, а не «хотя бы два»
	 *
	 * @warning Условие `count >= 2` проходило бы и при подложном сигнале, доставшемся
	 *          от прежнего подъёма ВМЕСТО настоящего: счёт добрал бы двойку и без
	 *          второго `raise`. Точное равенство эту подмену и отсекает
	 *
	 */
	ASSERT_EQ(2, count);
}

/**
 * @brief Проверка отсутствия подложного сигнала после повторного подъёма
 *
 * @details Самопайп остановку ПЕРЕЖИВАЕТ, и всё, что осталось в нём от прежнего
 *          подъёма, новый рабочий поток вычитал бы первым же чтением. Выглядело бы
 *          это самопроизвольным сигналом на ровном месте, а не изъяном устройства
 *
 * @warning Путь сюда ровно один, и он неочевиден. Обычная остановка НИЧЕГО в
 *          самопайпе не оставляет: служебную нагрузку пробуждения рабочий поток
 *          успевает вычитать прежде выхода. Остаётся она лишь тогда, когда поток
 *          вышел САМ - по остановке из функции обратного вызова, - и повторная
 *          остановка пишет пробуждение уже некому. Первая редакция этой проверки
 *          шла обычным путём и оставалась зелёной ДАЖЕ СО СНЯТЫМИ заслонами;
 *          покраснеть она была неспособна вовсе
 *
 */
TEST_F(SignalsFixture, RestartNoPhantomTest){
	// Счётчик полученных сигналов
	std::atomic_uint32_t count{0};
	// Признак остановки, выполненной из функции обратного вызова
	std::atomic_bool stopped{false};
	// Устанавливаем функцию обратного вызова на получение сигнала
	this->_signals->on([&](const int32_t){
		// Увеличиваем счётчик полученных сигналов
		++count;
		// Останавливаем отслеживание ИЗ рабочего потока: поток выйдет сам
		this->_signals->stop();
		// Отмечаем выполненную остановку
		stopped.store(true);
	});
	// Запускаем первый цикл отслеживания
	this->_signals->start();
	// Отправляем сигнал
	std::raise(SIGINT);
	/**
	 * Дожидаемся получения сигнала и остановки из функции обратного вызова
	 */
	for(uint16_t i = 0; (i < 200) && !stopped.load(); i++)
		// Выдерживаем малый срок между опросами признака
		std::this_thread::sleep_for(std::chrono::milliseconds(10));
	// Убеждаемся, что первый подъём сигнал получил и остановка состоялась
	ASSERT_TRUE(stopped.load());
	// Убеждаемся, что сигнал получен ровно один
	ASSERT_EQ(1u, count.load());
	/**
	 * Останавливаем ещё раз, уже из своего потока
	 *
	 * @note Рабочий поток к этому мигу вышел сам, и служебная нагрузка пробуждения,
	 *       которую пишет эта остановка, остаётся в самопайпе непрочитанной. Ради
	 *       неё проверка и заведена
	 */
	this->_signals->stop();
	// Запускаем второй цикл отслеживания
	this->_signals->start();
	/**
	 * Выдерживаем срок, заведомо достаточный для доставки подложного сигнала
	 *
	 * @note Ожидание здесь по сроку намеренно: доказывается ОТСУТСТВИЕ события, а
	 *       ждать отсутствия по условию нельзя - условие не наступит никогда
	 */
	std::this_thread::sleep_for(std::chrono::milliseconds(300));
	// Подложного сигнала быть не должно: второй подъём не получал ничего
	ASSERT_EQ(1u, count.load()) << "после повторного подъёма пришёл остаток прежнего";
}

