/**
 * @brief Тест возврата прежнего расположения сигнала SIGPIPE
 *
 * @details Запуск отслеживания заглушает `SIGPIPE`: разрыв встречной стороной обязан
 *          приходить кодом отказа, а не убивать процесс. Настройка эта ОБЩАЯ НА
 *          ПРОЦЕСС, и прежде она переживала остановку - чужой код того же процесса
 *          получал изменённое поведение и о том не знал
 *
 *          Правило: остановили сигналы - значит модуль больше
 *          не работает, и оставлять за собой изменённое поведение незачем
 *
 * @note Проверка сличает расположение ТРИЖДЫ: до запуска, при работе и после
 *       остановки. Без первого замера последний ничего не стоил бы - совпасть с
 *       умолчанием он мог бы и по случайности
 *
 * @note Прежнее расположение ставится намеренно НЕ умолчанием, а заглушением: так
 *       видно, что возвращается именно прежнее, а не `SIG_DFL` вслепую
 *
 */
TEST_F(SignalsFixture, PipeSignalDispositionRestoredTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);
	/**
	 * Для операционной системы не являющейся MS Windows
	 */
	#if !defined(_WIN32) && !defined(_WIN64)
		/**
		 * Расположение, заводимое до запуска чужим кодом того же процесса
		 *
		 * @warning Обработчик здесь СВОЙ, а не `SIG_IGN`, и это условие обязательное.
		 *          С заглушением проверка не различала бы возврат: запуск ставит то
		 *          же самое `SIG_IGN`, и без возврата расположение после остановки
		 *          совпало бы с прежним по случайности. Замерено: с `SIG_IGN` проверка
		 *          проходила и при СНЯТОМ возврате
		 */
		struct sigaction foreign{};
		// Заполняем структуру нулями
		::memset(&foreign, 0, sizeof(foreign));
		// Ставим свой обработчик, отличимый и от заглушения, и от умолчания
		foreign.sa_handler = &::pipeSignalMarker;
		// Очищаем маску перехвата
		sigemptyset(&foreign.sa_mask);
		// Расположение, стоявшее до нашего вмешательства
		struct sigaction saved{};
		// Заводим своё расположение, запоминая прежнее
		ASSERT_EQ(::sigaction(SIGPIPE, &foreign, &saved), 0);
		// Расположение, читаемое замерами
		struct sigaction current{};
		// Запускаем отслеживание сигналов
		this->_signals->start();
		// Читаем расположение при работе
		ASSERT_EQ(::sigaction(SIGPIPE, nullptr, &current), 0);
		// При работе сигнал обязан быть заглушён
		ASSERT_EQ(current.sa_handler, SIG_IGN) << "запуск не заглушил SIGPIPE";
		// Останавливаем отслеживание сигналов
		this->_signals->stop();
		// Читаем расположение после остановки
		ASSERT_EQ(::sigaction(SIGPIPE, nullptr, &current), 0);
		// После остановки обязано стоять расположение, заведённое ДО запуска
		ASSERT_EQ(current.sa_handler, foreign.sa_handler) << "остановка не вернула прежнее расположение SIGPIPE";
		// Возвращаем расположение, стоявшее до проверки
		ASSERT_EQ(::sigaction(SIGPIPE, &saved, nullptr), 0);
	/**
	 * Для операционной системы MS Windows
	 */
	#else
		// Сигнала этого у MS Windows нет вовсе
		GTEST_SKIP() << "сигнала SIGPIPE у MS Windows не существует";
	#endif
}

TEST_F(SignalsFixture, StopFromCallbackTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);

	// Создаём мьютекс для блокировки потока
	std::mutex mtx;
	// Создаём условную переменную
	std::condition_variable cv;
	// Флаг завершения обработки колбэка
	bool done = false;

	/**
	 * Устанавливаем обработчик сигнала, который останавливает отслеживание из самого колбэка.
	 * Проверяется отсутствие самоблокировки при вызове stop() из рабочего потока.
	 */
	this->_signals->on([&](const int32_t){
		// Останавливаем отслеживание из контекста рабочего потока
		this->_signals->stop();
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Устанавливаем флаг завершения
		done = true;
		// Пробуждаем ожидающий поток
		cv.notify_one();
	});

	// Запускаем отслеживание
	this->_signals->start();

	// Отправляем сигнал
	std::raise(SIGINT);

	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем завершения обработки колбэка без самоблокировки
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return done;}));
	}
}

/**
 * @brief Тест повторного запуска после остановки ИЗ функции обратного вызова
 *
 * @details Остановка, зовущаяся из самого отклика, идёт в рабочем потоке и потому не
 *          вправе его присоединить - поток остаётся живым и присоединяемым. Убрать
 *          его обязан следующий запуск: он взводит признак выхода, будит поток
 *          служебной записью в самотрубу и присоединяет его, и лишь затем поднимает
 *          отслеживание заново
 *
 * @warning Путь этот прочими проверками набора не проходится НИ РАЗУ. Замерено
 *          покрытием: без этой проверки набор `sys` заходит в начало запуска 17 раз, а
 *          в разбор оставшегося потока - НОЛЬ; с нею - один раз, вплоть до
 *          присоединения. Ошибка в нём - присоединение потока к самому себе либо
 *          потерянный поток - выглядит зависанием или утечкой, а не отказом
 *
 * @note Точками останова путь этот померить НЕЛЬЗЯ: остановка идёт в рабочем потоке, а
 *       счётчик заходов `lldb` его не видит - на этом же месте он показывает ноль и
 *       для давно живущей `StopFromCallbackTest`, вся суть которой в таком вызове
 *
 * @note Доказательством служит не сам факт возврата из запуска, а ДОСТАВКА сигнала
 *       после него: поднявшееся отслеживание, сигналов не приносящее, вернуло бы
 *       управление точно так же
 *
 */
TEST_F(SignalsFixture, RestartAfterStopFromCallbackTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);

	// Создаём мьютекс для блокировки потока
	std::mutex mtx;
	// Создаём условную переменную
	std::condition_variable cv;
	// Счётчик доставленных сигналов
	uint16_t count = 0;
	// Признак того, что отклик отработал
	bool done = false;

	/**
	 * Устанавливаем обработчик, останавливающий отслеживание из самого отклика
	 */
	this->_signals->on([&](const int32_t){
		// Останавливаем отслеживание из контекста рабочего потока
		this->_signals->stop();
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Увеличиваем счётчик доставленных сигналов
		count++;
		// Устанавливаем признак того, что отклик отработал
		done = true;
		// Пробуждаем ожидающий поток
		cv.notify_one();
	});

	// Запускаем отслеживание
	this->_signals->start();
	// Отправляем сигнал
	std::raise(SIGINT);
	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем отработки отклика
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return done;}));
		// Сбрасываем признак отработки отклика перед вторым кругом
		done = false;
	}

	/**
	 * Поднимаем отслеживание заново - здесь и убирается поток, оставшийся от остановки
	 */
	this->_signals->start();
	// Отправляем сигнал повторно
	std::raise(SIGINT);
	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Второй сигнал обязан дойти: отслеживание поднялось по-настоящему
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return done;})) << "после повторного подъёма сигнал не пришёл";
	}
	// Сигналов обязано быть ровно два - по одному на круг
	ASSERT_EQ(count, static_cast <uint16_t> (2));
	// Останавливаем отслеживание из своего потока, прибирая за собой
	this->_signals->stop();
}

/**
 * @brief Тест передачи корректного номера сигнала в функцию обратного вызова
 *
 */
TEST_F(SignalsFixture, CallbackSignalValueTest){
	// Проверяем создание объекта
	ASSERT_TRUE(this->_signals != nullptr);

	// Создаём мьютекс для блокировки потока
	std::mutex mtx;
	// Создаём условную переменную
	std::condition_variable cv;
	// Полученный сигнал
	int32_t signal = 0;
	// Флаг получения сигнала
	bool signaled = false;

	/**
	 * Устанавливаем обработчик сигнала
	 */
	this->_signals->on([&](const int32_t sig){
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Запоминаем полученный сигнал
		signal = sig;
		// Устанавливаем флаг получения сигнала
		signaled = true;
		// Пробуждаем ожидающий поток
		cv.notify_one();
	});

	// Запускаем отслеживание
	this->_signals->start();

	// Отправляем сигнал завершения работы
	std::raise(SIGTERM);

	{
		// Формируем блокировку потока
		std::unique_lock <std::mutex> lock(mtx);
		// Ожидаем получения сигнала
		ASSERT_TRUE(cv.wait_for(lock, std::chrono::seconds(2), [&]{return signaled;}));
		// Проверяем корректность номера полученного сигнала
		ASSERT_EQ(SIGTERM, signal);
	}
}

