/**
 * @brief Проверка кавычек, необходимых по содержимому, при правиле «все, кроме чисел»
 *
 * @details Необходимость кавычек считается прежде правила и правилу не подчиняется: поле,
 * содержащее разделитель либо знак конца строки, без кавычек разрывает запись, и никакое
 * правило записи этого не отменяет. Прежде правило отвечало прежде такой проверки, и поле
 * вида «\t\r\n0», приведением к числу признанное числом, записывалось без кавычек -
 * разрывая запись надвое. Обнаружено фаззингом
 *
 */
TEST(CodecCsvWriter, QuotingNonNumericNecessary) {
	// Настройки записи текста таблицы
	csv::writer_t::settings_t settings;
	// Устанавливаем правило заключения поля в кавычки
	settings.quoting = csv::quoting_t::NONNUMERIC;
	// Объект записи текста таблицы
	csv::writer_t writer(::logger(), settings);
	// Выполняем запись целой записи полем за полем
	writer.record(vector <string> {"\t\r\n0", "1", " 2 ", "3,4"});
	// Выполняем проверку того, что поля с опасным содержимым взяты в кавычки
	ASSERT_EQ(writer.text(), "\"\t\r\n0\",1,\" 2 \",\"3,4\"\r\n");
	// Выполняем разбор записанного текста таблицы
	const auto & records = ::parse(writer.text());
	// Выполняем проверку количества полученных обратно записей
	ASSERT_EQ(records.size(), 1u);
	// Выполняем проверку того, что запись получена обратно неизменной
	ASSERT_EQ(records.front(), (vector <string> {"\t\r\n0", "1", " 2 ", "3,4"}));
}
/**
 * @brief Проверка кавычек вокруг поля, начинающего запись знаком примечания
 *
 * @details Разбор признаёт примечанием строку, знаком примечания начатую, и поле такое
 * без кавычек унесло бы за собою всю запись. Знак этот - настройка разбора, а не часть
 * договора, и записи он сообщается затем, чтобы записанное читалось обратно теми же
 * настройками. Обнаружено фаззингом
 *
 */
TEST(CodecCsvWriter, Comment) {
	// Настройки записи текста таблицы
	csv::writer_t::settings_t settings;
	// Устанавливаем знак начала строки примечания, признаваемый разбором
	settings.comment = '#';
	// Объект записи текста таблицы
	csv::writer_t writer(::logger(), settings);
	// Выполняем запись первой записи таблицы
	writer.record(vector <string> {"#значение", "#прочее"});
	// Выполняем проверку того, что в кавычки взято лишь поле, начинающее запись
	ASSERT_EQ(writer.text(), "\"#значение\",#прочее\r\n");
	// Настройки разбора текста таблицы
	csv::reader_t::settings_t reading;
	// Устанавливаем знак начала строки примечания
	reading.comment = '#';
	// Выполняем разбор записанного текста таблицы
	const auto & records = ::parse(writer.text(), reading);
	// Выполняем проверку того, что запись примечанием не поглощена
	ASSERT_EQ(records.size(), 1u);
	// Выполняем проверку того, что запись получена обратно неизменной
	ASSERT_EQ(records.front(), (vector <string> {"#значение", "#прочее"}));
	// Объект записи текста таблицы без знака примечания
	csv::writer_t plain(::logger());
	// Выполняем запись первой записи таблицы
	plain.record(vector <string> {"#значение"});
	// Выполняем проверку того, что без объявленного знака кавычки не ставятся
	ASSERT_EQ(plain.text(), "#значение\r\n");
}
/**
 * @brief Проверка записи знаков конца строки
 *
 */
TEST(CodecCsvWriter, Newline) {
	/**
	 * Перечень проверяемых знаков конца строки и их записи
	 */
	const struct {
		// Проверяемый знак конца строки
		csv::newline_t newline;
		// Ожидаемая запись знака конца строки
		const char * expected;
	} cases[] = {
		{csv::newline_t::CRLF, "a\r\n"},
		{csv::newline_t::LF, "a\n"},
		{csv::newline_t::CR, "a\r"}
	};
	/**
	 * Выполняем перебор проверяемых знаков конца строки
	 */
	for(auto & item : cases){
		// Настройки записи текста таблицы
		csv::writer_t::settings_t settings;
		// Устанавливаем знак конца строки
		settings.newline = item.newline;
		// Объект записи текста таблицы
		csv::writer_t writer(::logger(), settings);
		// Выполняем запись целой записи полем за полем
		writer.record(vector <string> {"a"});
		// Выполняем проверку собранного текста
		ASSERT_EQ(writer.text(), item.expected);
	}
}

