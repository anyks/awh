		ASSERT_TRUE(doc.parse("имя,возраст\n", [](const vector <string_view> &) noexcept -> bool {
			// Записей у такой таблицы нет вовсе
			ADD_FAILURE() << "запись выдана у таблицы из одного заголовка";
			// Выводим признак продолжения разбора
			return true;
		}));
