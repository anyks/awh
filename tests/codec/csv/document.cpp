/**
 * @brief Проверка верности сборки исходному тексту
 *
 * @details Сличается собранное с ИСХОДНЫМ текстом, а не со вторым разбором. Разница
 * существенна: второй разбор выведен из того же читателя, и утрату, читателем внесённую,
 * он повторит - оба снимка сойдутся, и проверка зазеленеет на потерянном. Проверка
 * неподвижности обхода, стоящая отдельно, доказывает лишь неподвижность; верность
 * доказывает только сличение с тем, что подано
 *
 * @note Тексты подобраны каноническими: пара знаков конца строки, обрамление лишь по
 *       необходимости - то есть ровно такими, какими их собирает запись при настройках
 *       по умолчанию. Текст, обрамлённый сверх необходимости, сюда не годится: сборка
 *       приведёт его к необходимому, и расхождение будет законным
 *
 */
TEST(CodecCsvDocument, AssemblyMatchesTheSourceText) {
	// Перечень канонических текстов таблицы и наличия у них заголовка
	const vector <pair <string, csv::header_t>> samples = {
		{"имя,возраст\r\nБорис,41\r\nАнна,30\r\n", csv::header_t::PRESENT},
		{"a,b\r\nc,d\r\n", csv::header_t::NONE},
		{"a,,c\r\n,,\r\n", csv::header_t::NONE},
		{"\"a,b\",c\r\n", csv::header_t::NONE},
		{"\"a\"\"b\",c\r\n", csv::header_t::NONE},
		{"\"a\r\nb\",c\r\n", csv::header_t::NONE},
		{"\" a \",\" b \"\r\n", csv::header_t::NONE},
		{"a\r\n", csv::header_t::NONE},
		{"\"\"\"\"\r\n", csv::header_t::NONE},
		{"имя,город\r\nБорис,Москва\r\n", csv::header_t::PRESENT},
		{"a,b,c\r\nd,e\r\nf\r\n", csv::header_t::NONE},
		{"\"и,мя\",возраст\r\n1,2\r\n", csv::header_t::PRESENT},
		{"a,b,c\r\n", csv::header_t::PRESENT},
		{"\" \",a\r\n", csv::header_t::NONE},
		{"\"\"\r\n", csv::header_t::NONE}
	};
	/**
	 * Выполняем перебор всех канонических текстов таблицы
	 */
	for(const auto & sample : samples){
		// Настройки контейнера таблицы
		csv::document_t::settings_t settings;
		// Запоминаем наличие заголовка у текста
		settings.reader.header = sample.second;
		// Контейнер таблицы
		csv::document_t doc(::logger());
		// Устанавливаем настройки контейнера
		doc.settings(settings);
		// Выполняем проверку принятия текста разбором
		ASSERT_TRUE(doc.parse(sample.first)) << csv::message(doc.error());
		// Выполняем проверку совпадения собранного с исходным текстом
		ASSERT_EQ(doc.text(), sample.first);
	}
	/**
	 * Выполняем проверку единственного законного приведения
	 *
	 * @details Пустое поле, обрамлённое в исходном тексте, собирается голым: кавычки ему
	 * не необходимы, а запись обрамляет лишь по необходимости. Смысл при этом уцелевает
	 * целиком - поле остаётся пустым полем, - и потому приведение законно
	 *
	 * @warning Случай, где кавычки у пустого поля НЕОБХОДИМЫ, стоит отдельно и приведению
	 *          не подлежит: запись из одного пустого поля, собранная голой, обратилась бы
	 *          пустою строкою, а это уже не запись. Половина эта закрепляет именно её
	 */
	{
		// Настройки контейнера таблицы
		csv::document_t::settings_t settings;
		// Отключаем ожидание заголовка
		settings.reader.header = csv::header_t::NONE;
		// Контейнер таблицы
		csv::document_t doc(::logger());
		// Устанавливаем настройки контейнера
		doc.settings(settings);
		// Выполняем разбор текста с обрамлённым пустым полем среди прочих
		ASSERT_TRUE(doc.parse("\"\",a\r\n"));
		// Выполняем проверку приведения обрамления к необходимому
		ASSERT_EQ(doc.text(), ",a\r\n");
		/**
		 * Выполняем проверку сохранности смысла при приведении
		 */
		{
			// Контейнер таблицы для повторного разбора
			csv::document_t back(::logger());
			// Устанавливаем настройки контейнера
			back.settings(settings);
			// Выполняем разбор собранного текста
			ASSERT_TRUE(back.parse(doc.text()));
			// Выполняем проверку сохранности числа полей записи
			ASSERT_EQ(back.size(0), static_cast <size_t> (2));
			// Выполняем проверку пустоты первого поля записи
			ASSERT_TRUE(back.get(0, 0).empty());
		}
	}
}

/**
 * @brief Проверка согласия четырёх путей подачи текста
 *
 * @details Обещание одно: приговор о годности текста от способа подачи не зависит.
 * Путей у таблицы четыре - разбор текста, разбор с выдачей записями, чтение файла
 * целиком и чтение файла с выдачей записями, - и сличается здесь КОД отказа, а не
 * самый факт его. Факт достать удобнее, но обещано не это: отказ по иной причине
 * прошёл бы проверку на один лишь факт, и подмена причины осталась бы незамеченной
 *
 * @note Годный текст стоит в перечне намеренно: сличение одних отказов прошло бы и
 *       при путях, отвергающих всё подряд
 *
 */
TEST(CodecCsvDocument, FeedingPathsAgreeOnTheVerdict) {
	// Адрес временного файла таблицы
	// Сторож временного файла проверки
	const Scratch scratch_filename("csv-paths-agreement.csv");
	// Путь к временному файлу проверки
	const string & filename = scratch_filename.path();
	/**
	 * @brief Метод сличения приговоров всех четырёх путей подачи
	 *
	 * @param text     подаваемый текст таблицы
	 * @param settings настройки контейнера таблицы
	 *
	 */
	const auto compare = [&filename](const string & text, const csv::document_t::settings_t & settings) noexcept {
		/**
		 * Выполняем запись подаваемого текста в файл
		 */
		{
			// Поток записи файла таблицы
			ofstream file(filename, ios::binary);
			// Выполняем запись текста таблицы в файл
			file << text;
		}
		// Обработчик очередной записи таблицы
		const auto callback = [](const vector <string_view> &) noexcept -> bool { return true; };
		// Приговоры и коды отказа всех четырёх путей подачи
		bool accepted[4]; csv::error_t codes[4];
		/**
		 * Выполняем подачу текста всеми четырьмя путями
		 */
		for(size_t path = 0; path < 4; path++){
			// Контейнер таблицы
			csv::document_t doc(::logger());
			// Устанавливаем настройки контейнера
			doc.settings(settings);
			// Выполняем подачу текста очередным путём
			accepted[path] = ((path == 0) ? doc.parse(text) :
			                 ((path == 1) ? doc.parse(text, callback) :
			                 ((path == 2) ? doc.load(filename) : doc.read(filename, callback))));
			// Запоминаем код отказа очередного пути
			codes[path] = doc.error();
		}
		// Выполняем удаление временного файла таблицы
		::remove(filename.c_str());
		/**
		 * Выполняем сличение приговоров всех путей с приговором разбора текста
		 */
		for(size_t path = 1; path < 4; path++){
			// Выполняем проверку совпадения приговора о годности
			ASSERT_EQ(accepted[path], accepted[0]) << path << ": " << text;
			// Выполняем проверку совпадения кода отказа
			ASSERT_EQ(codes[path], codes[0]) << path << ": " << text;
		}
	};
	// Настройки контейнера таблицы, общие всем пробам
	csv::document_t::settings_t base;
	// Запоминаем наличие заголовка у текста
	base.reader.header = csv::header_t::PRESENT;
	// Выполняем проверку согласия путей на годном тексте
	compare("а,б\r\n1,2\r\n", base);
	// Выполняем проверку согласия путей на незакрытых кавычках
	compare("а,б\r\n\"вг,д\r\n", base);
	// Выполняем проверку согласия путей на повторе имени столбца
	compare("а,а\r\n1,2\r\n", base);
	// Выполняем проверку согласия путей на пустом имени столбца
	compare("а,\r\n1,2\r\n", base);
	/**
	 * Выполняем проверку согласия путей на пределе длины поля
	 */
	{
		// Настройки контейнера с пределом длины поля
		csv::document_t::settings_t settings = base;
		// Выполняем указание предела длины поля таблицы
		settings.reader.maxField = 8;
		// Выполняем сличение приговоров путей
		compare("аб,вг\r\nслишком длинное поле,вг\r\n", settings);
	}
	/**
	 * Выполняем проверку согласия путей при строгом разборе
	 */
	{
		// Настройки контейнера со строгим разбором
		csv::document_t::settings_t settings = base;
		// Включаем строгий разбор текста
		settings.reader.strict = true;
		// Выполняем сличение приговоров на одиноком переводе строки
		compare("а,б\nв,г\n", settings);
		// Выполняем сличение приговоров на одиноком возврате каретки
		compare("а,б\rв,г\r", settings);
		// Выполняем сличение приговоров на кавычке в голом поле
		compare("а,б\r\nв\"г,д\r\n", settings);
	}
	/**
	 * Выполняем проверку согласия путей на рваной записи при строгом обращении
	 */
	{
		// Настройки контейнера со строгим обращением с рваной записью
		csv::document_t::settings_t settings = base;
		// Устанавливаем прекращение разбора при расхождении числа полей
		settings.reader.ragged = csv::ragged_t::ERROR;
		// Выполняем сличение приговоров путей
		compare("а,б,в\r\n1,2\r\n", settings);
	}
	/**
	 * Выполняем проверку согласия путей на пределе числа полей
	 */
	{
		// Настройки контейнера с пределом числа полей
		csv::document_t::settings_t settings = base;
		// Выполняем указание предела числа полей записи
		settings.reader.maxFields = 2;
		// Выполняем сличение приговоров путей
		compare("а,б,в\r\n1,2,3\r\n", settings);
	}
	/**
	 * Выполняем проверку согласия путей на пределе длины записи
	 */
	{
		// Настройки контейнера с пределом длины записи
		csv::document_t::settings_t settings = base;
		// Выполняем указание предела длины записи таблицы
		settings.reader.maxRecord = 10;
		// Выполняем сличение приговоров путей
		compare("а,б\r\nочень длинная запись,вторая\r\n", settings);
	}
}


/**
 * @brief Проверка неприкосновенности приёмника на всяком пути отказа извлечения
 *
 * @details Договор извлечения о судьбе переменной-приёмника при отказе МОЛЧАЛ, а путей
 *          отказа у неё пять, и три из них заведены сторожами от 31.08.2026. Всякий
 *          новый ранний выход есть новый путь отказа, и на нём приёмник обязан остаться
 *          цел: потребитель, признака успеха не проверивший, обязан увидеть СВОЁ прежнее
 *          значение, а не полуснятое
 *
 * @note Замер 01.09.2026 по двадцати путям отказа трёх кодеков: приёмник цел всюду.
 *       Приём взят у соседа по рамке - сторож, добавленный правкою, обязан заставить
 *       пересмотреть всё, что написано ВЫШЕ него
 *
 */
TEST(CodecCsvDocument, ReceiverIsUntouchedOnEveryRefusal) {
	// Документ таблицы для проверки извлечения чисел
	csv::document_t document(::logger());
	/**
	 * Разбираемый текст таблицы со всеми написаниями, отказ вызывающими
	 *
	 * @note Написания «300», «300.0» и «1e-320» отсюда изъяты решением владельца от
	 *       01.09.2026: числами они быть не перестают и отказом более не отвечают.
	 *       Взамен взяты записи, отвергаемые составом
	 */
	const string text = "не число\r\n0x10\r\n1.2.3\r\nnan\r\ninf\r\n+42\r\n1e\r\n";
	// Выполняем разбор текста таблицы
	document.parse(text);
	// Выполняем перебор всех записей разобранной таблицы
	for(size_t i = 0; i < document.rows(); i++){
		// Приёмник наименьшего целого вида с опознавательным значением
		uint8_t small = 77;
		// Приёмник наибольшего целого вида с опознавательным значением
		uint64_t big = 12345;
		/**
		 * Выполняем проверку сохранности приёмника наименьшего целого вида
		 *
		 * @note Вид этот отвергает ВСЕ записи: числом не является ни одна из них
		 */
		EXPECT_FALSE(document.numeric <uint8_t> (i, 0, small));
		// Выполняем проверку неприкосновенности приёмника при отказе
		EXPECT_EQ(small, 77u);
		// Приёмник целого вида СО ЗНАКОМ с опознавательным значением
		int64_t signedBig = -777;
		// Приёмник логического вида с опознавательным значением
		bool flag = true;
		/**
		 * Выполняем проверку отказа ЛОГИЧЕСКИМ видом
		 *
		 * @note Логический вид берётся отдельной ветвью, прежде целых: язык причисляет
		 *       его к целым, и без неё «true» отвергалось бы. Ветвь эта такой же путь
		 *       отказа, как знаковая и беззнаковая, и покрыта быть обязана
		 */
		EXPECT_FALSE(document.numeric <bool> (i, 0, flag));
		// Выполняем проверку неприкосновенности приёмника при отказе
		EXPECT_TRUE(flag);
		/**
		 * Если запись извлечению целым без знака не поддалась
		 */
		if(!document.numeric <uint64_t> (i, 0, big))
			// Выполняем проверку неприкосновенности приёмника при отказе
			EXPECT_EQ(big, 12345u);
		/**
		 * Если запись извлечению целым со знаком не поддалась
		 *
		 * @note Вид со знаком берётся отдельной ветвью извлечения, и без него проверка
		 *       слепа к половине путей отказа: проба зрячести 01.09.2026 записью в
		 *       приёмник ВНУТРИ знаковой ветви оставалась зелёной
		 */
		if(!document.numeric <int64_t> (i, 0, signedBig))
			// Выполняем проверку неприкосновенности приёмника при отказе
			EXPECT_EQ(signedBig, -777);
	}
}



