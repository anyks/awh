	csv::reader_t reader(::logger(), settings);
	// Выполняем подачу текста целиком
	reader.feed("a,b\r\nccccccccc\r\n");
	// Выполняем получение первого события разбора
	ASSERT_TRUE(reader.next());
	// Выполняем проверку места первого поля первой записи
	ASSERT_EQ(reader.location().line, 1u);
	// Выполняем проверку положения первого поля в строке
	ASSERT_EQ(reader.location().column, 1u);
	// Выполняем проверку номера первого поля в записи
	ASSERT_EQ(reader.location().field, 0u);
	// Выполняем получение второго события разбора
	ASSERT_TRUE(reader.next());
	// Выполняем проверку места второго поля первой записи
	ASSERT_EQ(reader.location().column, 3u);
	// Выполняем проверку номера второго поля в записи
	ASSERT_EQ(reader.location().field, 1u);
