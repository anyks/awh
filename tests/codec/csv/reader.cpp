/**
 * @brief Проверка независимости выдачи от нарезки текста на куски
 *
 * @details Договор этот проверяется при всяком разборе выше, а здесь - на тексте,
 * собравшем все знаки, чьё значение зависит от следующего за ними: возврат каретки
 * перед переводом строки, кавычка перед кавычкой и кавычка перед разделителем.
 * Нарезка ровно между ними и есть тот случай, что нарушает договор
 *
 */
TEST(CodecCsvReader, ChunkIndependence) {
	// Текст, собравший все опасные для нарезки места
	const string text = "a,\"b\"\"c\",\"d\r\ne\"\r\n\"\",f\r\n#g\r\n\"h\"i,j\r\n";
	// Настройки разбора текста
	csv::reader_t::settings_t settings;
	// Включаем выдачу событий пустых строк
	settings.emitBlanks = true;
	// Получаем выдачу разбора текста, поданного целиком
	const string result = ::dump(text, 0, settings);
	/**
	 * Получаем подробную выдачу разбора текста, поданного целиком
	 *
	 * @note Сличается и она: договор о независимости от нарезки распространяется на
	 *       СОБЫТИЕ целиком - вместе с положением в тексте, признаком кавычек и
	 *       признаком правки, - а сличение по одному содержимому полей оставляло всё
	 *       это незакреплённым. Замер 02.09.2026 картой мутантов: потеря `_modified`,
	 *       `_record` и `_line` на границе куска меняла наблюдаемую выдачу и не красила
	 *       НИ ОДНОЙ проверки набора
	 */
	const string standard = ::detailed(text, 0, settings);
	/**
	 * Выполняем перебор всех размеров куска подачи
	 */
	for(size_t chunk = 1; chunk <= text.size(); chunk++){
		// Выполняем проверку совпадения выдачи при нарезке с выдачей текста целиком
		ASSERT_EQ(::dump(text, chunk, settings), result) << "размер куска: " << chunk;
		// Выполняем проверку совпадения подробной выдачи при нарезке
		ASSERT_EQ(::detailed(text, chunk, settings), standard) << "размер куска: " << chunk;
	}
}
