/**
 * @brief Проверка неприкосновенности выходной переменной при отказе приведения
 *
 * @details Разбор числа вёлся ПРЯМО в выходную переменную, а отказ выносился уже после
 * него: отвергнутое «1e3» оставляло у звучащего единицу вместо нетронутого значения, и
 * ошибка обращения оборачивалась правдоподобным числом. Звучащий, итог приведения не
 * проверивший, получал не умолчание своё, а обломок разбора
 */
TEST(CodecCsvCommon, RefusedConversionLeavesResultUntouched){
	// Значения, целым числом не являющиеся, но числом начинающиеся
	const vector <string> corpus = {"1e3", "52abc", "12,5", "3.14.15", "0x10"};
	// Значения, дробным числом не являющиеся, но числом начинающиеся
	const vector <string> reals = {"52abc", "12,5", "3.14.15"};
	/**
	 * Выполняем перебор всех проверяемых значений
	 */
	for(const string & text : corpus){
		// Выходное значение целого числа со знаком
		int64_t signedNumber = -777;
		// Выполняем проверку отказа приведения к целому со знаком
		ASSERT_FALSE(csv::integer(text, signedNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(signedNumber, static_cast <int64_t> (-777)) << text;
		// Выходное значение целого числа без знака
		uint64_t unsignedNumber = 777;
		// Выполняем проверку отказа приведения к целому без знака
		ASSERT_FALSE(csv::integer(text, unsignedNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(unsignedNumber, static_cast <uint64_t> (777)) << text;
	}
	/**
	 * Приведение, отказом не оканчивающееся
	 */
	{
		// Выходное значение целого числа со знаком
		int64_t number = -777;
		// Выполняем проверку успеха приведения
		ASSERT_TRUE(csv::integer("42", number));
		// Выполняем проверку разобранного значения
		ASSERT_EQ(number, static_cast <int64_t> (42));
	}
	/**
	 * Выполняем перебор значений, дробным числом не являющихся
	 */
	for(const string & text : reals){
		// Выходное значение числа с плавающей точкой
		double realNumber = -0.5;
		// Выполняем проверку отказа приведения к числу с плавающей точкой
		ASSERT_FALSE(csv::real(text, realNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(realNumber, -0.5) << text;
	}
}



/**
 * @brief Проверка величин, составляющих договор кодека с потребителем
 *
 * @details Величины эти суть ПРЕДЕЛЫ УМОЛЧАНИЯ: они решают, какой текст кодек примет без
 *          всяких настроек. Смена любой из них меняет видимое поведение - текст, прежде
 *          разбиравшийся, начинает отвергаться, - и потому смена обязана быть решением
 *          осознанным
 *
 * @warning Сличать величину С ЕЁ ЖЕ ИМЕНЕМ бесполезно: обе стороны сличения двигаются
 *          вместе, и утверждение остаётся истинным при любом значении. Замер 01.09.2026
 *          по трём кодекам: из десяти мест, где пределы умолчания поминались в
 *          утверждениях, ЛИТЕРАЛА не стояло ни в одном. Оттого здесь величины сличаются
 *          с числами записанными, а не с именами
 *
 * @note Сличается и то, что умолчание настроек эти величины ДЕЙСТВИТЕЛЬНО несёт: величина
 *       верная при умолчании, её не берущем, ничего не значит
 *
 */
TEST(CodecCsvCommon, DefaultLimitsAreWrittenTwice) {
	/**
	 * Выполняем проверку самих величин по записанным числам
	 */
	{
		// Выполняем проверку предела длины поля в один мегабайт
		ASSERT_EQ(csv::MAX_FIELD, 0x100000u);
		// Выполняем проверку предела длины записи в шестнадцать мегабайтов
		ASSERT_EQ(csv::MAX_RECORD, 0x1000000u);
		// Выполняем проверку предела количества полей в записи
		ASSERT_EQ(csv::MAX_FIELDS, 0x10000u);
		// Выполняем проверку количества записей, по которым определяется разделитель
		ASSERT_EQ(csv::DETECT_RECORDS, 32u);
		/**
		 * Выполняем проверку признаков отсутствия
		 *
		 * @note Величины эти сличением закреплены не были, и вскрылось это сличением
		 *       состава постоянных с закреплёнными. Они ОТКРЫТЫ потребителю: розыск
		 *       столбца отвечает `NO_INDEX` при отсутствии, и перемена их обратила бы
		 *       отсутствие в номер столбца первого - молча
		 */
		ASSERT_EQ(csv::NO_OFFSET, static_cast <uint64_t> (~0ull));
		// Выполняем проверку признака отсутствия номера
		ASSERT_EQ(csv::NO_INDEX, static_cast <uint32_t> (~0u));
		/**
		 * Выполняем проверку наибольшего кодового значения знака
		 *
		 * @note Величина эта не наша, а Юникода, и меняться не может вовсе: она стоит
		 *       здесь затем, чтобы правка её была замечена немедленно
		 */
		ASSERT_EQ(csv::MAX_CODEPOINT, 0x10FFFFu);
		/**
		 * Выполняем проверку признака негодного кодового значения знака
		 *
		 * @details Величина эта есть ДОГОВОР С ПОТРЕБИТЕЛЕМ, а не внутреннее удобство:
		 *          ею отвечает перекодировка на последовательность, кодировке не
		 *          отвечающую, и потребитель сличает с нею итог. Перемени её - и
		 *          сличение у потребителя, собранного прежде, перестанет узнавать
		 *          отказ, приняв его за кодовое значение знака
		 *
		 * @note Пробел вскрыт сличением ПОЛНОГО состава постоянных с закреплённым, а не
		 *       подменою: подмена спрашивает «стережёт ли эту величину хоть кто-нибудь»,
		 *       а сличение состава - «не забыта ли она вовсе», и перебирать подменою
		 *       можно лишь то, что назвал. Приём этот пришёл от Геннадия
		 */
		ASSERT_EQ(csv::INVALID_CODEPOINT, static_cast <uint32_t> (~0u));
	}
	/**
	 * Выполняем проверку того, что умолчание настроек величины эти несёт
	 */
	{
		// Умолчательные настройки разбора текста таблицы
		const csv::reader_t::settings_t settings;
		// Выполняем проверку предела длины поля у умолчания
		ASSERT_EQ(settings.maxField, csv::MAX_FIELD);
		// Выполняем проверку предела длины записи у умолчания
		ASSERT_EQ(settings.maxRecord, csv::MAX_RECORD);
		// Выполняем проверку предела количества полей у умолчания
		ASSERT_EQ(settings.maxFields, csv::MAX_FIELDS);
		// Выполняем проверку количества записей определения разделителя у умолчания
		ASSERT_EQ(settings.detect, csv::DETECT_RECORDS);
		/**
		 * Выполняем проверку прочих умолчаний, видимое поведение задающих
		 *
		 * @note Разделитель, кавычка и уклад отмены суть тот же договор: текст,
		 *       разделённый запятой, обязан разбираться без всяких настроек
		 */
		ASSERT_EQ(settings.separator, ',');
		// Выполняем проверку знака кавычек у умолчания
		ASSERT_EQ(settings.quote, '"');
		// Выполняем проверку отсутствия знака примечания у умолчания
		ASSERT_EQ(settings.comment, '\0');
		// Выполняем проверку отсутствия ожидания заголовка у умолчания
		ASSERT_EQ(settings.header, csv::header_t::NONE);
		// Выполняем проверку нестрогого разбора у умолчания
		ASSERT_FALSE(settings.strict);
	}
}
