/**
 * @brief Проверка описаний кодов ошибок
 *
 * @details Описание обязано быть у всякого кода: без него отказ разбора доходит до
 * потребителя одним числом
 *
 */
TEST(CodecCsvCommon, Messages) {
	/**
	 * Выполняем перебор всех кодов отказа, договором отведённых
	 *
	 * @note Перебор ведётся числом от нуля до последнего кода перечня: список кодов,
	 *       выписанный рукою, от перечня отстаёт молча - именно так коды, заведённые
	 *       последними, не сличались вовсе
	 */
	// Свод описаний кодов отказа для сличения их на различимость
	set <string> distinct;
	for(uint32_t code = 0; code <= static_cast <uint32_t> (csv::error_t::STORAGE_EXHAUSTED); code++){
		// Получаем описание очередного кода отказа
		const char * message = csv::message(static_cast <csv::error_t> (code));
		// Выполняем проверку наличия описания кода отказа
		ASSERT_NE(message, nullptr) << code;
		// Выполняем проверку того, что описание кода отказа не пусто
		ASSERT_GT(::strlen(message), 0u) << code;
		// Выполняем проверку того, что код отказа описанием ОПОЗНАН
		ASSERT_STRNE(message, "unknown error") << code;
		/**
		 * Выполняем занесение описания в свод описаний
		 *
		 * @note Свод собирается затем, чтобы сличить описания на РАЗЛИЧИМОСТЬ: сличение
		 *       «описание непусто» переживает кодек, отдающий одно и то же описание на
		 *       все коды, а описка-двойник в перечне проходит молча. Наименьшее число,
		 *       обращающее утверждение в ложь, есть здесь ДВА одинаковых описания
		 */
		distinct.insert(string(message));
	}
	/**
	 * Выполняем проверку различимости описаний всех кодов отказа
	 *
	 * @note Замер 01.09.2026 по трём кодекам: 106 кодов и 106 различных описаний
	 */
	ASSERT_EQ(distinct.size(), 22u);
	/**
	 * Выполняем проверку того, что перечень кодов на том и оканчивается
	 *
	 * @note Сличение это отмечает конец перечня, а сторожем НЕ является: код, дописанный
	 *       без описания, оно пропускает - именно его отсутствие оно и сличает. Проверено
	 *       щупом: дописанный код отказа проверку не уронил. Сторожем тут выступает
	 *       собиратель - смотри примечание у самой выдачи описаний
	 */
	ASSERT_STREQ(csv::message(static_cast <csv::error_t> (static_cast <uint32_t> (csv::error_t::STORAGE_EXHAUSTED) + 1)), "unknown error");
	// Выполняем проверку описания кода, договором не отведённого
	ASSERT_STREQ(csv::message(static_cast <csv::error_t> (0xFF)), "unknown error");
}
