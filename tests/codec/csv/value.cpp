/**
 * @brief Проверка того, что сохранение не губит прежний файл при отказе записи
 *
 * @details Прямая запись в целевой файл усекает его ПЕРВЫМ ЖЕ действием, и отказ на
 *          середине - место кончилось, предел размера достигнут, работа прервана -
 *          оставляет потребителя без прежнего содержимого и без нового разом
 *
 * @note Отказ записи наводится пределом `RLIMIT_FSIZE`: он ставится ПОСЛЕ записи
 *       прежнего содержимого и с запасом на него, иначе усечённой оказывалась бы
 *       сама цель, и проверка мерила бы собственную подготовку вместо сохранения
 *
 * @warning Сигнал `SIGXFSZ` глушится намеренно: без глушения превышение предела
 * валит весь набор проверок, а не отвечает отказом записи
 */
TEST(CodecCsvValue, SavingKeepsThePreviousFileOnWriteFailure) {
	/**
	 * Проверка эта требует пределов ресурсов процесса, каких у MS Windows нет
	 */
	#if defined(_WIN32) || defined(_WIN64)
		// Выполняем пропуск проверки на системах без пределов ресурсов
		GTEST_SKIP() << "Пределы ресурсов процесса у этой системы отсутствуют";
	#else
		// Адрес временного файла проверки
		const string filename = ::unique("./csv-value-save.csv");
		// Прежнее содержимое целевого файла
		const string previous = "прежнее,содержимое\r\nцелое,невредимое\r\n";
		// Сторож временного файла проверки
		struct Guard {
			// Адрес стерегомого файла
			string filename;
			// Деструктор сторожа
			~Guard() noexcept {
				// Выполняем снос целевого файла проверки
				::remove(this->filename.c_str());
				// Выполняем снос временного файла записи
				::remove((this->filename + ".awh-tmp").c_str());
			}
		} guard{filename};
		// Выполняем снос файлов, переживших прошлый прогон
		::remove(filename.c_str());
		{
			// Объект файла для записи прежнего содержимого
			ofstream file(filename, ios::binary | ios::trunc);
			// Выполняем проверку того, что файл записи открылся
			ASSERT_TRUE(file.is_open());
			// Выполняем запись прежнего содержимого в файл
			file << previous;
		}
		// Собираемое значение таблицы
		csv::value_t value(csv::value_t::type_t::TABLE);
		// Выполняем установку имён столбцов таблицы
		ASSERT_TRUE(value.header(vector <string> {"новое", "содержимое"}));
		/**
		 * Выполняем сборку записей, предел размера заведомо перерастающих
		 */
		for(size_t i = 0; i < 20000; i++){
			// Собираемая запись таблицы
			csv::value_t record(csv::value_t::type_t::RECORD);
			// Выполняем добавление первого поля записи
			ASSERT_TRUE(record.push(csv::value_t(string("значение-достаточно-длинное-") + std::to_string(i))));
			// Выполняем добавление второго поля записи
			ASSERT_TRUE(record.push(csv::value_t(std::to_string(i))));
			// Выполняем добавление записи в таблицу
			ASSERT_TRUE(value.push(record));
		}
		/**
		 * @brief Хранитель предела размера файла и обработчика сигнала
		 *
		 * @details Возврат ведётся ДЕСТРУКТОРОМ, а не строкою после замера, ибо всякий
		 *          «ASSERT_*» уходит из проверки ВОЗВРАТОМ, и строка эта при отказе не
		 *          исполнилась бы вовсе
		 *
		 * @warning Утечка предела роняла бы СОСЕДНИЕ проверки: набор кодеков собран одной
		 * программою, предел живёт у всего процесса, и отказ вышел бы вдали от места
		 * своей причины
		 */
		struct Limit {
			// Прежний предел размера файла
			struct rlimit previous;
			// Прежний обработчик сигнала превышения предела
			void (* handler)(int);
			// Конструктор хранителя предела
			Limit(const size_t size) noexcept {
				// Выполняем глушение сигнала превышения предела размера файла
				this->handler = ::signal(SIGXFSZ, SIG_IGN);
				// Выполняем получение прежнего предела размера файла
				::getrlimit(RLIMIT_FSIZE, &this->previous);
				// Устанавливаемый предел размера файла
				struct rlimit limit = this->previous;
				// Выполняем установку предела с запасом на прежнее содержимое
				limit.rlim_cur = size;
				// Выполняем установку предела размера файла
				::setrlimit(RLIMIT_FSIZE, &limit);
			}
			// Деструктор хранителя предела
			~Limit() noexcept {
				// Выполняем возврат прежнего предела размера файла
				::setrlimit(RLIMIT_FSIZE, &this->previous);
				// Выполняем возврат прежнего обработчика сигнала
				::signal(SIGXFSZ, this->handler);
			}
		};
		// Признак успешности сохранения таблицы в файл
		bool saved = true;
		{
			// Хранитель предела размера файла
			Limit limit(previous.size() + 1024);
			// Выполняем сохранение таблицы в файл
			saved = value.save(filename);
		}
		// Выполняем проверку отказа сохранения по превышению предела
		ASSERT_FALSE(saved);
		/**
		 * Выполняем проверку кода отказа сохранения
		 *
		 * @note Замерено щупом по местам отказа 04.09.2026: сам признак отказа кода не
		 *       свидетельствует, и подмена кода в месте отказа записи не красила ничего.
		 *       Отказ, назвавший причину неверно, отличить снаружи нельзя ничем - а
		 *       звучащий по коду и судит, что делать: перезаписать, сменить путь или
		 *       отступиться
		 */
		ASSERT_EQ(value.error(), csv::error_t::FILE_NOT_WRITTEN);
		// Читаемое содержимое целевого файла
		string content;
		{
			// Объект файла для чтения содержимого
			ifstream file(filename, ios::binary);
			// Выполняем проверку того, что целевой файл на месте
			ASSERT_TRUE(file.is_open());
			// Выполняем чтение содержимого целевого файла
			content.assign((istreambuf_iterator <char> (file)), istreambuf_iterator <char> ());
		}
		/**
		 * Выполняем проверку сохранности прежнего содержимого целевого файла
		 */
		ASSERT_EQ(content, previous);
	#endif
}

/**
 * @brief Проверка того, что сохранение и выдача называют причину отказа
 *
 * @details Отказ сохранения имеет ТРИ разных причины, и различить их звучащий может
 *          лишь по коду: имя файла не указано вовсе, файл открыть не удалось, запись
 *          не легла. Дороги эти ведут к разным решениям потребителя - исправить довод,
 *          завести каталог, отступиться, - и один общий признак «не вышло» не годится
 *
 * @note Замерено щупом по местам отказа 04.09.2026: из восьми мест отказа владеющего
 *       значения таблицы ПЯТЬ не сличал никто. Проверки сохранения были, и верные, но
 *       все они спрашивали лишь признак успеха, а код отказа оставляли без внимания -
 *       та же односторонность, что нашлась у метки порядка байтов и у вида кодировки:
 *       мы сличаем, ЧТО вышло, и забываем сличить, ЧТО кодек про это говорит
 *
 * @note Половина про выдачу закрывает шестое место: выдача текста у значения, таблицею
 *       не являющегося, отвечает пустым текстом и кодом внутренней ошибки. Код взят
 *       тот же, каким отвечает выдача у владеющего значения JSON, и согласие это
 *       держится здесь, а не в доводе
 *
 * @warning Сброс кода при НОВОЙ работе проверяется отдельно и обязателен: значение,
 *          сохранившее код прежнего отказа, отвечало бы отказом на удавшуюся работу
 *
 */
TEST(CodecCsvValue, SavingAndDumpingNameTheirCause) {
	// Владеющее значение таблицы
	csv::value_t value;
	// Выполняем разбор текста таблицы
	ASSERT_TRUE(value.parse("имя,возраст\r\nАня,7\r\n"));
	/**
	 * Выполняем проверку отказа сохранения при неуказанном имени файла
	 */
	{
		// Выполняем проверку отказа сохранения таблицы
		ASSERT_FALSE(value.save(""));
		// Выполняем проверку кода отказа сохранения
		ASSERT_EQ(value.error(), csv::error_t::FILE_NOT_OPENED);
	}
	/**
	 * Выполняем проверку отказа сохранения в несуществующий каталог
	 *
	 * @note Причина здесь ИНАЯ, чем выше, а код тот же: имя указано, но открыть файл
	 *       не удалось. Оба места живут порознь, и подмена кода у второго молчала
	 */
	{
		// Выполняем проверку отказа сохранения таблицы
		ASSERT_FALSE(value.save("./нет-такого-каталога/таблица.csv"));
		// Выполняем проверку кода отказа сохранения
		ASSERT_EQ(value.error(), csv::error_t::FILE_NOT_OPENED);
	}
	/**
	 * Выполняем проверку СБРОСА кода отказа удавшимся сохранением
	 */
	{
		// Адрес временного файла проверки
		const string filename = ::unique("./csv-value-cause.csv");
		// Выполняем проверку успешности сохранения таблицы
		ASSERT_TRUE(value.save(filename));
		// Выполняем проверку того, что код прежнего отказа снят
		ASSERT_EQ(value.error(), csv::error_t::NONE);
		// Выполняем снос временного файла проверки
		::remove(filename.c_str());
	}
	/**
	 * Выполняем проверку выдачи текста у значения, записать какое нельзя
	 *
	 * @details Прививка к таблице удаётся, а САМА ЗАПИСЬ отказывает: поле несёт знак,
	 *          разбором не признаваемый. Донесение об отказе лежит у таблицы, и значение
	 *          обязано его перенять - иначе отвечает пустым текстом при коде «нет
	 *          ошибки», а пустой текст неотличим от таблицы пустой
	 *
	 * @note Найдено по наблюдению Генри у кодека CEF: там запись при отказе отдавала
	 *       частично собранный текст, здесь - пустой, а причина одна - итог записи не
	 *       проверялся вовсе. Половина эта закрывает ту сторону выдачи, где отказ
	 *       выносит не значение, а таблица под ним
	 */
	{
		// Владеющее значение таблицы
		csv::value_t table(csv::value_t::type_t::TABLE);
		// Владеющее значение записи таблицы
		csv::value_t record(csv::value_t::type_t::RECORD);
		// Содержимое поля с управляющим знаком, разбором не признаваемым
		string content("значение");
		// Дописываем управляющий знак к содержимому поля
		content.push_back(static_cast <char> (0x01));
		// Выполняем добавление поля к записи таблицы
		record.push(csv::value_t(content));
		// Выполняем добавление записи к таблице
		table.push(record);
		// Выполняем проверку того, что выдача текста отвечает пустотою
		ASSERT_TRUE(table.dump().empty());
		// Выполняем проверку того, что код отказа перенят у таблицы
		ASSERT_EQ(table.error(), csv::error_t::UNWRITABLE_FIELD);
		// Адрес временного файла проверки
		const string filename = ::unique("./csv-value-unwritable.csv");
		/**
		 * Выполняем снос файла, прежним прогоном оставленного
		 *
		 * @note Снос обязателен: проверка судит об отказе ПО ОТСУТСТВИЮ файла, и файл,
		 *       оставшийся от прогона прежнего, дал бы отказ вечный. Замерено на себе -
		 *       первый же прогон до починки оставил файл, и проверка после починки
		 *       краснела уже не по делу
		 */
		::remove(filename.c_str());
		// Выполняем проверку отказа сохранения таблицы в файл
		ASSERT_FALSE(table.save(filename));
		// Выполняем проверку того, что причина отказа названа та же
		ASSERT_EQ(table.error(), csv::error_t::UNWRITABLE_FIELD);
		// Выполняем проверку того, что файл записан не был
		ASSERT_FALSE(::std::ifstream(filename).is_open());
	}
	/**
	 * Выполняем проверку выдачи текста у значения, таблицею не являющегося
	 */
	{
		// Владеющее значение отдельного поля таблицы
		csv::value_t field("значение");
		// Выполняем проверку того, что выдача текста отвечает пустотою
		ASSERT_TRUE(field.dump().empty());
		/**
		 * Выполняем проверку кода отказа выдачи
		 *
		 * @note Причина названа ПО СУЩЕСТВУ: простое значение таблицею не является, и это
		 *       не сбой кодека. Прежде здесь стоял `INTERNAL` - «внутренний сбой разбора»,
		 *       - и проверка закрепляла ложь: ни разбора, ни сбоя тут нет, а значение
		 *       исправно. Найдено сличением шести кодеков рамки владельцем INI, TOML и
		 *       YAML 15.09.2026
		 */
		ASSERT_EQ(field.error(), csv::error_t::UNREPRESENTABLE_VALUE);
		// Выполняем проверку того, что описание причины кодек САМ КОДЕК не винит
		ASSERT_EQ(string(csv::message(field.error())).find("internal"), string::npos) << csv::message(field.error());
	}
}

