	ASSERT_TRUE(builder.field(std::numeric_limits <double>::infinity()));
	// Выполняем подачу поля бесконечностью отрицательной
	ASSERT_TRUE(builder.field(-std::numeric_limits <double>::infinity()));
	// Выполняем подачу поля не-числом
	ASSERT_TRUE(builder.field(std::numeric_limits <double>::quiet_NaN()));
	// Выполняем завершение записи
	ASSERT_TRUE(builder.close());
	// Собранное значение таблицы
	const csv::value_t table = builder.finish();
	// Выполняем проверку количества полей собранной записи
