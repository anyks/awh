/**
 * @brief Проверка того, что снятое значение переживает переезд хранилища таблицы
 *
 * @details Довод к заведению самого типа: всякое `get`, `row` и `header` у таблицы
 *          отдаёт вид в общее хранилище знаков, а хранилище это ПЕРЕЕЗЖАЕТ при
 *          росте. Вид, переживший добавление записи, читает чужое содержимое -
 *          молча, не падая и не подавая знака
 *
 * @note Замер до заведения типа: вид, взятый до роста таблицы на пять тысяч записей,
 *       после роста отдавал мусор, тогда как снятое значение отдавало «Аня». Без
 *       роста порок не воспроизводится вовсе - хранилищу незачем переезжать
 *
 * @warning Проверка НЕ сличает содержимое вида после роста: чтение чужой памяти есть
 * поведение неопределённое, и закреплять его значило бы требовать от порока
 * постоянства. Закрепляется лишь то, что значение осталось верным
 */
TEST(CodecCsvValue, TakenValueSurvivesTheStorageMove) {
	// Объект таблицы
	csv::document_t document = ::make("имя,возраст\r\nАня,30\r\nБорис,41\r\n");
	// Владеющее значение, снятое с таблицы
	const csv::value_t value(document);
	/**
	 * Выполняем рост таблицы, переезд хранилища знаков вызывающий
	 */
	for(size_t i = 0; i < 5000; i++)
		// Выполняем добавление очередной записи в таблицу
		document.append(vector <string> {string("длинное-имя-номер-") + std::to_string(i), std::to_string(i)});
	// Выполняем проверку сохранности содержимого снятого значения
	ASSERT_EQ(value.at("/0/имя").text(), "Аня");
	// Выполняем проверку сохранности содержимого последней записи
	ASSERT_EQ(value.at("/1/имя").text(), "Борис");
	// Выполняем проверку того, что счёт записей значения от роста таблицы не изменился
	ASSERT_EQ(value.size(), static_cast <size_t> (2));
}

