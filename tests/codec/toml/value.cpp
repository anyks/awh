/**
 * @brief Проверка дыр внутри составных значений
 *
 * @details Обращение к паре либо к значению перечня заводит место под него сразу, а
 * значения в том месте ещё нет: выходит дыра. Дыра внутри встроенной таблицы снятию
 * не мешает - она пропускается, - а вот дыра внутри перечня отвергает и снятие, и
 * перенос: у перечня имени нет, и пропуск значения сдвинул бы все следующие
 *
 * @note Обращение за край перечня наращивает его до затребованного номера: перечень
 *       из одного значения после обращения к третьему становится длиною в четыре
 *
 */
TEST(CodecTomlValue, HolesInsideComposite) {
	/**
	 * Выполняем проверку пропуска дыры внутри встроенной таблицы
	 */
	{
		// Встроенная таблица с дырою
		toml::value_t inner(toml::type_t::TABLE);
		// Запоминаем пару встроенной таблицы
		inner["пара"] = static_cast <int64_t> (1);
		// Выполняем обращение к паре с именем пустым, дыру заводящее
		inner[""];
		// Перечень со встроенной таблицей внутри
		toml::value_t outer(toml::type_t::ARRAY);
		// Выполняем дописывание встроенной таблицы в перечень
		ASSERT_TRUE(outer.push(inner));
		// Значение с перечнем внутри
		toml::value_t root(toml::type_t::TABLE);
		// Запоминаем перечень парой значения
		root["перечень"] = outer;
		// Выполняем проверку того, что дыра снятию не помешала
		ASSERT_EQ(root.dump(), string("\"перечень\" = [{ \"пара\" = 1 }]\n"));
		// Объект дерева настроек
		toml::document_t document(::logger());
		// Выполняем проверку того, что дыра не помешала и переносу в дерево
		ASSERT_TRUE(root.graft(document, {}));
		// Выполняем проверку перенесённого содержимого
		ASSERT_TRUE(document.has({"перечень"}));
	}
	/**
	 * Выполняем проверку отказа переноса перечня, дыру несущего
	 */
	{
		// Перечень значений
		toml::value_t list(toml::type_t::ARRAY);
		// Выполняем дописывание значения перечня
		ASSERT_TRUE(list.push(toml::value_t(static_cast <int64_t> (1))));
		// Выполняем обращение к значению перечня за краем, дыры заводящее
		list[static_cast <size_t> (3)];
		// Выполняем проверку того, что перечень нарос до затребованного номера
		ASSERT_EQ(list.size(), static_cast <size_t> (4));
		// Значение с перечнем внутри
		toml::value_t root(toml::type_t::TABLE);
		// Запоминаем перечень с дырою парой значения
		root["дырявый"] = list;
		// Объект дерева настроек
		toml::document_t document(::logger());
		// Выполняем проверку отказа переноса перечня с дырою
		ASSERT_FALSE(root.graft(document, {}));
		// Выполняем проверку выданного кода отказа дерева настроек
		ASSERT_EQ(document.error(), toml::error_t::INVALID_VALUE);
	}
}
