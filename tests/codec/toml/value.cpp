/**
 * @brief Проверка отказов потоковой сборки
 *
 */
TEST(CodecTomlValue, BuildingRefusals) {
	// Потоковая сборка владеющего значения
	toml::builder_t builder;
	/**
	 * Выполняем проверку отказа назначения имени до открытия вместилища
	 *
	 * @note Имя, назначенное до открытия корня, положить некуда - вместилища, какому
	 *       оно принадлежало бы, ещё нет
	 */
	ASSERT_FALSE(builder.key("title"));
	// Выполняем проверку отказа записи значения до открытия вместилища
	ASSERT_FALSE(builder.value(static_cast <int64_t> (1)));
	// Выполняем проверку отказа закрытия вместилища, не открытого вовсе
	ASSERT_FALSE(builder.close());
	// Выполняем открытие корневой таблицы
	ASSERT_TRUE(builder.table());
	// Выполняем проверку отказа записи значения в таблицу без имени
	ASSERT_FALSE(builder.value(static_cast <int64_t> (1)));
	// Выполняем проверку отказа назначения пустого имени
	ASSERT_FALSE(builder.key(""));
	// Выполняем назначение имени пары таблицы
	ASSERT_TRUE(builder.key("title"));
	/**
	 * Выполняем проверку отказа назначения имени дважды подряд
	 *
	 * @note Имя, назначенное дважды подряд, есть ошибка у потребителя, и молчаливое
	 *       приятие её увело бы значение не туда
	 */
	ASSERT_FALSE(builder.key("other"));
	/**
	 * Выполняем проверку отказа закрытия вместилища при имени без значения
	 *
	 * @note Имя без значения есть незавершённая пара, и закрытие вместилища на ней
	 *       потеряло бы имя молча
	 */
	ASSERT_FALSE(builder.close());
	// Выполняем запись значения пары таблицы
	ASSERT_TRUE(builder.value(static_cast <int64_t> (1)));
	// Выполняем закрытие корневой таблицы
	ASSERT_TRUE(builder.close());
	// Выполняем проверку отказа записи значения после завершения сборки
	ASSERT_FALSE(builder.value(static_cast <int64_t> (2)));
	// Выполняем сброс сборки в исходное состояние
	builder.reset();
	// Выполняем проверку того, что сброшенная сборка вновь принимает открытие
	ASSERT_TRUE(builder.table());
}

