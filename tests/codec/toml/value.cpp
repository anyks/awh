	uint8_t fifth = 0;
	// Извлекаемое число видом в два байта без знака
	uint16_t sixth = 0;
	// Извлекаемое число видом в четыре байта без знака
	uint32_t seventh = 0;
	// Извлекаемое число видом в восемь байтов без знака
	uint64_t eighth = 0;
