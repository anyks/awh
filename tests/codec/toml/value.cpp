/**
 * @brief Проверка сборки дерева из значений языка
 *
 * @details Проверка эта закрепляет главное, ради чего владеющее значение и заведено:
 *          дерево собирается из ничего, тогда как дерево настроек заводится лишь
 *          разбором текста
 *
 */
TEST(CodecTomlValue, Assembling) {
	// Собираемое владеющее значение
	toml::value_t value;
	// Выполняем проверку того, что вновь заведённое значение не определено
	ASSERT_FALSE(value.valid());
	// Выполняем установку строкового значения пары
	ASSERT_TRUE(value.insert("title", toml::value_t("пример")));
	// Выполняем проверку того, что значение стало таблицей
	ASSERT_TRUE(value.is(toml::type_t::TABLE));
	// Выполняем установку целого числа пары
	ASSERT_TRUE(value.insert("port", toml::value_t(static_cast <int64_t> (8080))));
	// Выполняем установку логического значения пары
	ASSERT_TRUE(value.insert("debug", toml::value_t(false)));
	// Выполняем проверку количества пар таблицы
	ASSERT_EQ(value.size(), 3u);
	// Выполняем проверку наличия пары по имени
	ASSERT_TRUE(value.contains("port"));
	// Выполняем проверку отсутствия пары, не заведённой вовсе
	ASSERT_FALSE(value.contains("missing"));
	// Извлекаемое содержимое строкового значения
	string text;
	// Выполняем проверку успешности извлечения строкового значения
	ASSERT_TRUE(value["title"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "пример");
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку успешности извлечения целого числа
	ASSERT_TRUE(value["port"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 8080);
	/**
	 * Выполняем проверку установки пары с пустым именем
	 *
	 * @note Прежде здесь закреплялся ОТКАЗ, и это было неверно: наречие TOML имя пустое
	 *       дозволяет оградою - запись `"" = 1` законна по стандарту, чтение её
	 *       принимает, запись выдаёт, а дерево держит. Отказ оставлял владеющее значение
	 *       в состоянии, снятием с дерева достижимом, а руками невоспроизводимом
	 */
	ASSERT_TRUE(value.insert("", toml::value_t(true)));
	// Выполняем проверку того, что количество пар возросло
	ASSERT_EQ(value.size(), 4u);
	// Выполняем проверку того, что пара с пустым именем записана оградою
	ASSERT_NE(value.dump().find("\"\" = true"), string::npos);
}

/**
 * @brief Проверка перезаписи занятого имени на прежнем месте
 *
 * @details Порядок пар задан потребителем, и перестановка их при перезаписи меняла бы
 *          вид записанного текста без его на то воли
 *
 */
TEST(CodecTomlValue, Overwriting) {
	// Собираемое владеющее значение
	toml::value_t value;
	// Выполняем установку первой пары таблицы
	ASSERT_TRUE(value.insert("first", toml::value_t(static_cast <int64_t> (1))));
	// Выполняем установку второй пары таблицы
	ASSERT_TRUE(value.insert("second", toml::value_t(static_cast <int64_t> (2))));
	// Выполняем установку третьей пары таблицы
	ASSERT_TRUE(value.insert("third", toml::value_t(static_cast <int64_t> (3))));
	// Выполняем перезапись значения первой пары таблицы
	ASSERT_TRUE(value.insert("first", toml::value_t(static_cast <int64_t> (100))));
	// Выполняем проверку того, что количество пар не изменилось
	ASSERT_EQ(value.size(), 3u);
	// Выполняем проверку того, что перезаписанная пара осталась на прежнем месте
	ASSERT_EQ(value.key(0), "first");
	// Выполняем проверку того, что соседние пары не сдвинулись
	ASSERT_EQ(value.key(1), "second");
	// Выполняем проверку того, что соседние пары не сдвинулись
	ASSERT_EQ(value.key(2), "third");
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку успешности извлечения перезаписанного числа
	ASSERT_TRUE(value["first"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 100);
	/**
	 * Выполняем проверку отказа добавления занятого имени
	 *
	 * @note Добавление есть заявление о новизне имени, и молчаливая перезапись
	 *       противоречила бы ему
	 */
	ASSERT_FALSE(value.append("first", toml::value_t(static_cast <int64_t> (7))));
	// Выполняем проверку успешности добавления имени незанятого
	ASSERT_TRUE(value.append("fourth", toml::value_t(static_cast <int64_t> (4))));
	// Выполняем проверку количества пар таблицы
	ASSERT_EQ(value.size(), 4u);
}

/**
 * @brief Проверка обращения к вложенным значениям по пути
 *
 */
TEST(CodecTomlValue, Routing) {
	// Собираемое владеющее значение
	toml::value_t value;
	// Выполняем заведение вложенного значения по пути
	value.place("/server/host") = toml::value_t("localhost");
	// Выполняем заведение вложенного значения перечня по пути
	value.place("/server/ports/0") = toml::value_t(static_cast <int64_t> (80));
	// Выполняем заведение второго значения перечня по пути
	value.place("/server/ports/1") = toml::value_t(static_cast <int64_t> (443));
	// Извлекаемое содержимое строкового значения
	string text;
	// Выполняем проверку успешности обращения по пути
	ASSERT_TRUE(value.at("/server/host").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "localhost");
	// Выполняем проверку того, что часть пути числовая завела перечень
	ASSERT_TRUE(value.at("/server/ports").is(toml::type_t::ARRAY));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value.at("/server/ports").size(), 2u);
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку успешности обращения к значению перечня по номеру
	ASSERT_TRUE(value.at("/server/ports/1").value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 443);
	/**
	 * Выполняем проверку того, что обращение к отсутствующему пути отказом не является
	 *
	 * @note Обращение к отсутствующему есть отсутствие значения, и проверять его
	 *       надлежит через valid()
	 */
	ASSERT_FALSE(value.at("/server/missing").valid());
	// Выполняем проверку того, что обращение к отсутствующему пути не завело значения
	ASSERT_FALSE(value.at("/server").contains("missing"));
	// Выполняем проверку того, что путь пустой выдаёт само значение
	ASSERT_TRUE(value.at("").is(toml::type_t::TABLE));
}

/**
 * @brief Проверка удаления значений вместилища
 *
 */
TEST(CodecTomlValue, Removing) {
	// Собираемое владеющее значение
	toml::value_t value;
	// Выполняем установку первой пары таблицы
	ASSERT_TRUE(value.insert("first", toml::value_t(static_cast <int64_t> (1))));
	// Выполняем установку второй пары таблицы
	ASSERT_TRUE(value.insert("second", toml::value_t(static_cast <int64_t> (2))));
	// Выполняем установку третьей пары таблицы
	ASSERT_TRUE(value.insert("third", toml::value_t(static_cast <int64_t> (3))));
	// Выполняем удаление пары таблицы по имени
	ASSERT_TRUE(value.erase("second"));
	// Выполняем проверку количества пар таблицы
	ASSERT_EQ(value.size(), 2u);
	/**
	 * Выполняем проверку того, что имя удалено вместе со значением
	 *
	 * @note Перечни имён и значений идут рядом, и рассогласование их сдвинуло бы все
	 *       имена за удалённым на единицу
	 */
	ASSERT_EQ(value.key(1), "third");
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку того, что значение соседа осталось своим
	ASSERT_TRUE(value["third"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 3);
	// Выполняем проверку отказа удаления имени, не заведённого вовсе
	ASSERT_FALSE(value.erase("missing"));
	// Выполняем проверку удаления значения вместилища по номеру
	ASSERT_TRUE(value.erase(static_cast <size_t> (0)));
	// Выполняем проверку количества пар таблицы
	ASSERT_EQ(value.size(), 1u);
	// Выполняем проверку того, что оставшейся парой стала третья
	ASSERT_EQ(value.key(0), "third");
	// Выполняем проверку отказа удаления по номеру за пределами вместилища
	ASSERT_FALSE(value.erase(static_cast <size_t> (5)));
}

/**
 * @brief Проверка перечня значений
 *
 */
TEST(CodecTomlValue, Listing) {
	// Собираемое владеющее значение перечня
	toml::value_t value(toml::type_t::ARRAY);
	// Выполняем проверку того, что перечень значением определённым является
	ASSERT_TRUE(value.valid());
	// Выполняем проверку пустоты перечня
	ASSERT_TRUE(value.empty());
	// Выполняем добавление первого значения перечня
	ASSERT_TRUE(value.push(toml::value_t(static_cast <int64_t> (1))));
	// Выполняем добавление второго значения перечня
	ASSERT_TRUE(value.push(toml::value_t("два")));
	// Выполняем добавление третьего значения перечня
	ASSERT_TRUE(value.push(toml::value_t(true)));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value.size(), 3u);
	// Извлекаемое содержимое строкового значения
	string text;
	// Выполняем проверку успешности извлечения значения перечня по номеру
	ASSERT_TRUE(value[static_cast <size_t> (1)].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "два");
	/**
	 * Выполняем проверку отказа добавления без имени в таблицу
	 *
	 * @note Добавление без имени в таблицу положить некуда, а подставлять имя пустое
	 *       значило бы завести пару, записи не подлежащую
	 */
	toml::value_t table(toml::type_t::TABLE);
	// Выполняем проверку отказа добавления значения в таблицу
	ASSERT_FALSE(table.push(toml::value_t(static_cast <int64_t> (1))));
}

/**
 * @brief Проверка снятия значения с дерева настроек и правил извлечения
 *
 */
TEST(CodecTomlValue, Extraction) {
	// Прочитанное значение
	toml::value_t value;
	// Выполняем разбор текста настроек во владеющее значение
	ASSERT_TRUE(value.parse(
		"title = \"пример\"\n"
		"port = 8080\n"
		"mask = 0x1F\n"
		"ratio = 0.25\n"
		"debug = false\n"
		"flags = [true, false]\n"
		"[server]\n"
		"host = \"localhost\"\n"
		"deep = { a = 1, b = \"два\" }\n"
	));
	// Выполняем проверку того, что корнем стала таблица
	ASSERT_TRUE(value.is(toml::type_t::TABLE));
	// Извлекаемое содержимое строкового значения
	string text;
	// Выполняем проверку успешности извлечения строкового значения
	ASSERT_TRUE(value["title"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "пример");
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку успешности извлечения целого числа
	ASSERT_TRUE(value["port"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 8080);
	/**
	 * Выполняем проверку сохранения системы счисления записи целого числа
	 *
	 * @note Система счисления хранится рядом с числом, а не вместо него: запись `0x1F`
	 *       обязана вернуться записью `0x1F`, а извлечение числа обязано выдать 31
	 */
	ASSERT_EQ(value["mask"].radix(), toml::radix_t::HEX);
	// Выполняем проверку успешности извлечения числа шестнадцатеричной записи
	ASSERT_TRUE(value["mask"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 31);
	// Извлекаемое дробное число
	double real = 0.;
	// Выполняем проверку успешности извлечения дробного числа
	ASSERT_TRUE(value["ratio"].value(real));
	// Выполняем проверку извлечённого дробного числа
	ASSERT_DOUBLE_EQ(real, 0.25);
	// Извлекаемое логическое значение
	bool flag = true;
	// Выполняем проверку успешности извлечения логического значения
	ASSERT_TRUE(value["debug"].value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_FALSE(flag);
	// Выполняем проверку снятия перечня значений
	ASSERT_TRUE(value["flags"].is(toml::type_t::ARRAY));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value["flags"].size(), 2u);
	// Выполняем проверку снятия объявленной таблицы
	ASSERT_TRUE(value.at("/server/host").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "localhost");
	/**
	 * Выполняем проверку снятия встроенной таблицы
	 *
	 * @note Пары встроенной таблицы дерево настроек в перечне дочерних имён не выдавало
	 *       вовсе, тогда как получение значения по такому имени их отдавало исправно.
	 *       Согласовано 20.08.2026 вместе с заведением владеющего значения
	 */
	ASSERT_TRUE(value.at("/server/deep").is(toml::type_t::TABLE));
	// Выполняем проверку успешности обращения к паре встроенной таблицы
	ASSERT_TRUE(value.at("/server/deep/b").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "два");
	// Выполняем проверку отказа извлечения записи у значения нестрокового
	ASSERT_FALSE(value["port"].value(text));
	// Выполняем проверку отказа извлечения числа у значения строкового
	ASSERT_FALSE(value["title"].value(number));
	// Выполняем проверку отказа извлечения логического значения у числа
	ASSERT_FALSE(value["port"].value(flag));
}

/**
 * @brief Проверка договора извлечения числа
 *
 * @details Отказом извлечение завершается лишь тогда, когда значение числом не является
 * вовсе: вид хранения ему не указ, а дробное, извлекаемое целым видом, округляется по
 * правилам математики с уводом половины от нуля
 *
 * @note Договор этот общий у всех пяти кодеков рамки, и сличает их между собою
 *       `CodecContract.NumberExtraction`
 *
 */
TEST(CodecTomlValue, Rounding) {
	// Прочитанное значение
	toml::value_t value;
	// Выполняем разбор текста настроек во владеющее значение
	ASSERT_TRUE(value.parse(
		"half = 1.5\nback = -1.5\ndown = 1.4\nup = 1.6\neven = 2.5\n"
		"far = 1e300\nnear = 1e-3\nport = 8080\n"
	));
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку увода половины от нуля при извлечении целым видом
	ASSERT_TRUE(value["half"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 2);
	// Выполняем проверку увода половины от нуля в отрицательную сторону
	ASSERT_TRUE(value["back"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, -2);
	// Выполняем проверку округления вниз
	ASSERT_TRUE(value["down"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 1);
	// Выполняем проверку округления вверх
	ASSERT_TRUE(value["up"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 2);
	/**
	 * Выполняем проверку увода половины от нуля, а не к ближайшему чётному
	 *
	 * @note Случай этот отделяет `round` от `rint`: округление к ближайшему чётному
	 *       отдало бы здесь двойку, а увод половины от нуля даёт тройку
	 */
	ASSERT_TRUE(value["even"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 3);
	/**
	 * Выполняем проверку выдачи предела вида при числе вне его пределов
	 *
	 * @note Взято `1e300`, а не `1e400`: разбор наречия TOML запись за пределом дробного
	 *       вида не принимает вовсе, и проверялся бы разбор, а не договор извлечения.
	 *       Целого вида `1e300` не отвечает ровно так же, и зажим до предела виден
	 */
	ASSERT_TRUE(value["far"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 9223372036854775807LL);
	// Выполняем проверку округления числа, меньшего половины, к нулю
	ASSERT_TRUE(value["near"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 0);
	// Извлекаемое целое число малой разрядности
	int8_t narrow = 0;
	/**
	 * Выполняем проверку переноса младшими разрядами целого вне предела вида
	 *
	 * @note Запись «8080» переносится младшими разрядами: младший байт её есть `0x90`,
	 *       а знаковым однобайтовым видом он читается как `-112`
	 */
	ASSERT_TRUE(value["port"].value(narrow));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(narrow, -112);
	// Извлекаемое дробное число
	double real = 0.;
	// Выполняем проверку извлечения целого числа дробным видом
	ASSERT_TRUE(value["port"].value(real));
	// Выполняем проверку извлечённого дробного числа
	ASSERT_DOUBLE_EQ(real, 8080.);
}

/**
 * @brief Проверка правил сличения значений
 *
 * @details Сличается суть значения, а не запись его: система счисления, запись строки и
 *          расстановка строк перечня сличению не подлежат
 *
 */
TEST(CodecTomlValue, Comparison) {
	// Первое сличаемое значение
	toml::value_t first;
	// Второе сличаемое значение
	toml::value_t second;
	// Выполняем разбор первого сличаемого значения
	ASSERT_TRUE(first.parse("mask = 0x1F\ntitle = \"текст\"\n"));
	// Выполняем разбор второго сличаемого значения
	ASSERT_TRUE(second.parse("title = 'текст'\nmask = 31\n"));
	/**
	 * Выполняем проверку совпадения значений
	 *
	 * @note Порядок пар таблицы сличению НЕ подлежит: таблица есть отображение имён на
	 *       значения, и порядок записи её значением не является. Запись строки и
	 *       система счисления сличению не подлежат тоже
	 */
	ASSERT_TRUE(first == second);
	// Выполняем проверку отсутствия расхождения значений
	ASSERT_FALSE(first != second);
	// Третье сличаемое значение
	toml::value_t third;
	// Выполняем разбор третьего сличаемого значения
	ASSERT_TRUE(third.parse("first = [1, 2]\n"));
	// Четвёртое сличаемое значение
	toml::value_t fourth;
	// Выполняем разбор четвёртого сличаемого значения
	ASSERT_TRUE(fourth.parse("first = [2, 1]\n"));
	/**
	 * Выполняем проверку расхождения значений
	 *
	 * @note Порядок значений перечня сличению подлежит: перечень есть
	 *       последовательность, и порядок её значением является
	 */
	ASSERT_TRUE(third != fourth);
	// Выполняем проверку совпадения целого числа с дробным той же величины
	ASSERT_TRUE(toml::value_t(static_cast <int64_t> (1)) == toml::value_t(1.));
	// Выполняем проверку расхождения значений разных типов
	ASSERT_TRUE(toml::value_t(static_cast <int64_t> (1)) != toml::value_t(true));
	// Выполняем проверку совпадения неопределённых значений
	ASSERT_TRUE(toml::value_t() == toml::value_t());
}

