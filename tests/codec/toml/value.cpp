/**
 * @brief Проверка отказов сборщика: закрытие незакрываемого, глубина и сборка завершённая
 *
 * @details Сборщик обязан отвечать отказом на три случая: закрытие, когда закрывать
 *          нечего; открытие вместилища глубже предела вложенности; и всякое действие
 *          после завершения сборки. Без первого отказа сборщик молча принимал бы
 *          лишнее закрытие, без второго - строил дерево, записать какое нельзя, без
 *          третьего - правил бы уже отданное значение
 *
 * @note Места эти лежали в стороне от всех трёх прогонов сразу у всех трёх кодеков
 *       рамки: устройство сборщика у них общее, и слепые места - тоже
 *
 * @warning Предел вложенности взят ГРАНИЦЕЮ: вместилища открываются числом ровно в
 *          предел, и лишь потом делается попытка открыть ещё одно
 *
 */
TEST(CodecTomlValue, BuilderRefusals) {
	/**
	 * Выполняем проверку отказа закрытия, когда закрывать нечего
	 */
	{
		// Потоковая сборка владеющего значения
		toml::builder_t builder;
		// Выполняем проверку отказа закрытия у сборки пустой
		ASSERT_FALSE(builder.close());
	}
	/**
	 * Выполняем проверку отказа открытия вместилища глубже предела вложенности
	 */
	{
		// Потоковая сборка владеющего значения
		toml::builder_t builder;
		// Количество вместилищ, открыть какие удалось
		uint32_t opened = 0;
		/**
		 * Выполняем открытие вместилищ до первого отказа
		 */
		for(uint32_t i = 0; i < (toml::MAX_DEPTH + 2); i++){
			/**
			 * Если вместилище не корневое
			 */
			if(i > 0)
				// Выполняем назначение имени вместилища вложенного
				ASSERT_TRUE(builder.key("имя" + std::to_string(i))) << "уровень " << i;
			/**
			 * Если открыть очередное вместилище не удалось
			 */
			if(!builder.table())
				// Выходим из перебора уровней вложенности
				break;
			// Увеличиваем количество открытых вместилищ
			opened++;
		}
		/**
		 * Выполняем проверку числа открытых вместилищ
		 *
		 * @note Корень в счёт глубины не идёт: открыть удаётся корень да предел
		 *       вложенных, а следующее вместилище отвергается
		 */
		ASSERT_EQ(opened, (toml::MAX_DEPTH + 1));
	}
	/**
	 * Выполняем проверку отказов сборки завершённой
	 *
	 * @note Завершает сборку ЗАКРЫТИЕ корня, а не выдача собранного: выдача значения
	 *       сборку не запирает вовсе, и ожидание запирания ею оказалось моим, а не
	 *       кодека
	 */
	{
		// Потоковая сборка владеющего значения
		toml::builder_t builder;
		// Выполняем открытие корневого вместилища
		ASSERT_TRUE(builder.table());
		// Выполняем назначение имени свойства
		ASSERT_TRUE(builder.key("a"));
		// Выполняем запись значения свойства
		ASSERT_TRUE(builder.value(static_cast <int64_t> (1)));
		// Выполняем закрытие корневого вместилища, сборку завершающее
		ASSERT_TRUE(builder.close());
		// Выполняем проверку отказа открытия вместилища у сборки завершённой
		ASSERT_FALSE(builder.table());
		// Выполняем проверку отказа закрытия у сборки завершённой
		ASSERT_FALSE(builder.close());
		// Выполняем проверку того, что собранное значение выдаётся и по завершении
		ASSERT_EQ(builder.finish().size(), static_cast <size_t> (1));
	}
}
/**
 * @brief Проверка перенятия журнала присваиванием значения
 *
 * @details Значение, журнала за собою не имеющее, перенимает его у значения
 *          присваиваемого - и копированием, и переносом: журнал этот достаётся дереву,
 *          разбором собираемому, и без перенятия причина отказа разбора уходила бы в
 *          пустоту. Обе строки перенятия пересечение трёх прогонов числило слепыми
 *
 * @note Назначенный журнал при этом не перезаписывается: присваивание меняет значение,
 *       а не приёмник вывода, и это проверяется рядом вторым журналом
 *
 */
TEST(CodecTomlValue, LoggerAdoptedOnAssignment) {
	// Собираемые сообщения первого журнала
	vector <string> messages;
	// Объект журнала с перехватом вывода
	awh::log_t log(&Silent::framework());
	// Выполняем назначение приёмника вывода в функцию обратного вызова
	log.mode({awh::log_t::mode_t::DEFERRED});
	// Выполняем назначение перехвата сообщений журнала
	log.subscribe([&messages](const awh::log_t::flag_t, string_view text) noexcept -> void {
		// Выполняем сбор очередного сообщения журнала
		messages.push_back(string(text));
	});
	// Текст настроек, разбору не поддающийся
	const string broken = "[раздел\n";
	/**
	 * Выполняем проверку перенятия журнала копированием
	 */
	{
		// Значение, журнал за собою несущее
		toml::value_t source;
		// Выполняем назначение приёмника вывода журнала значению
		source.setLogger(&log);
		// Значение, журнала за собою не имеющее
		toml::value_t target;
		// Выполняем присваивание значения копированием
		target = source;
		// Выполняем проверку отказа разбора негодного текста
		ASSERT_FALSE(target.parse(broken));
		// Выполняем проверку того, что отказ разбора в перенятый журнал ушёл
		ASSERT_FALSE(messages.empty());
	}
	// Запоминаем счёт сообщений, копированием собранный
	const size_t copied = messages.size();
	/**
	 * Выполняем проверку перенятия журнала переносом
	 */
	{
		// Значение, журнал за собою несущее
		toml::value_t source;
		// Выполняем назначение приёмника вывода журнала значению
		source.setLogger(&log);
		// Значение, журнала за собою не имеющее
		toml::value_t target;
		// Выполняем присваивание значения переносом
		target = std::move(source);
		// Выполняем проверку отказа разбора негодного текста
		ASSERT_FALSE(target.parse(broken));
		// Выполняем проверку того, что отказ разбора в перенятый журнал ушёл
		ASSERT_GT(messages.size(), copied);
	}
	// Запоминаем счёт сообщений, переносом собранный
	const size_t moved = messages.size();
	/**
	 * Выполняем проверку того, что назначенный журнал присваиванием не перезаписывается
	 */
	{
		// Собираемые сообщения второго журнала
		vector <string> own;
		// Объект второго журнала с перехватом вывода
		awh::log_t other(&Silent::framework());
		// Выполняем назначение приёмника вывода в функцию обратного вызова
		other.mode({awh::log_t::mode_t::DEFERRED});
		// Выполняем назначение перехвата сообщений второго журнала
		other.subscribe([&own](const awh::log_t::flag_t, string_view text) noexcept -> void {
			// Выполняем сбор очередного сообщения второго журнала
			own.push_back(string(text));
		});
		// Значение, первый журнал за собою несущее
		toml::value_t source;
		// Выполняем назначение приёмника вывода первого журнала значению
		source.setLogger(&log);
		// Значение, второй журнал за собою несущее
		toml::value_t target;
		// Выполняем назначение приёмника вывода второго журнала значению
		target.setLogger(&other);
		// Выполняем присваивание значения копированием
		target = source;
		// Выполняем проверку отказа разбора негодного текста
		ASSERT_FALSE(target.parse(broken));
		// Выполняем проверку того, что отказ ушёл в свой журнал, а не в перенятый
		ASSERT_FALSE(own.empty());
		// Выполняем проверку того, что первый журнал отказа не получил
		ASSERT_EQ(messages.size(), moved);
	}
}
