/**
 * @brief Проверка сохранности пары с пустым именем при снятии и перезаписи
 *
 * @details Наречие TOML имя пустое дозволяет оградою: запись `"" = 1` законна по
 * стандарту. Чтение её принимает, запись выдаёт, дерево держит - а обход перезаписи
 * владеющего значения ронял такую пару МОЛЧА вместе со всем её поддеревом: условие
 * пропуска стояло одною половиною, по имени, тогда как у пяти остальных обходов того
 * же файла оно стоит двумя - пропускается пара, наросшая по номеру, а не всякая
 * безымянная
 *
 * @note Молчаливость и есть тут главное: отказа записи не выдавалось, выдавался текст
 *       усечённый, и потребитель узнал бы о потере лишь по недостаче настроек
 *
 */
TEST(CodecTomlValue, EmptyNameSurvives) {
	// Разбираемый текст настроек с объявлением, пустое имя несущим
	const string text = "[name.\"\".c]\nk = 1\n";
	// Собираемое дерево настроек
	toml::document_t document(::logger());
	// Выполняем проверку успешности разбора текста настроек
	ASSERT_TRUE(document.parse(text));
	// Выполняем проверку дословности перезаписи дерева настроек
	ASSERT_EQ(document.text(), text);
	// Значение, с дерева настроек снятое
	const toml::value_t lifted(document);
	// Перезапись снятого значения настройками наречия разбора
	const string written = lifted.dump(document.writing());
	// Выполняем проверку того, что перезапись пару с пустым именем сохранила
	ASSERT_NE(written.find("\"\""), string::npos) << written;
	// Собираемое дерево настроек перезаписи снятого значения
	toml::document_t rebuilt(::logger());
	// Выполняем проверку успешности разбора перезаписи снятого значения
	ASSERT_TRUE(rebuilt.parse(written)) << written;
	// Выполняем проверку сохранности значения по составному имени
	ASSERT_TRUE(rebuilt.has({"name", "", "c", "k"})) << written;
	// Выполняем проверку кругового хода снятого значения через перезапись
	ASSERT_TRUE(toml::value_t(rebuilt) == lifted) << written;
}
