		ASSERT_TRUE(value["small"].value(third));
		ASSERT_EQ(third, 8080);
		// Выполняем проверку извлечения числа видом в восемь байтов со знаком
		ASSERT_TRUE(value["small"].value(fourth));
		ASSERT_EQ(fourth, 8080);
