/**
 * @brief Проверка набора знаков имени ключа без кавычек
 *
 * @details Набор задан описанием и знаками US-ASCII ограничен: всё прочее в имени без
 * кавычек недопустимо и требует ограждения
 *
 */
TEST(CodecTomlCommon, BareKeys) {
	/**
	 * Выполняем перебор всех значений байта
	 */
	for(uint32_t code = 0; code < 0x100; code++){
		// Получаем очередной проверяемый знак
		const char letter = static_cast <char> (code);
		// Получаем ожидаемый признак допустимости знака в имени без кавычек
		const bool expected = (((code >= 'a') && (code <= 'z')) || ((code >= 'A') && (code <= 'Z')) ||
		                       ((code >= '0') && (code <= '9')) || (code == '_') || (code == '-'));
		// Выполняем проверку признака допустимости знака в имени без кавычек
		ASSERT_EQ(toml::bare(letter), expected) << code;
	}
	// Выполняем проверку недопустимости точки в имени без кавычек
	ASSERT_FALSE(toml::bare('.'));
	// Выполняем проверку недопустимости пробела в имени без кавычек
	ASSERT_FALSE(toml::bare(' '));
	// Выполняем проверку недопустимости кавычки в имени без кавычек
	ASSERT_FALSE(toml::bare('"'));
}
/**
 * @brief Проверка умолчаний структур модуля
 *
 * @details Умолчания эти значащи: отметка времени без смещения отличается от отметки со
 * смещением в ноль, и различить их можно лишь по обозначению отсутствия смещения
 *
 */
TEST(CodecTomlCommon, Defaults) {
	// Объект положения в исходном тексте
	const toml::location_t location;
	// Выполняем проверку того, что смещение неизвестно
	ASSERT_EQ(location.offset, toml::NO_OFFSET);
	// Выполняем проверку того, что номер строки не установлен
	ASSERT_EQ(location.line, 0u);
	// Выполняем проверку того, что положение в строке не установлено
	ASSERT_EQ(location.column, 0u);
	// Объект отметки времени
	const toml::stamp_t stamp;
	/**
	 * Выполняем проверку отсутствия смещения часового пояса
	 *
	 * @note Ноль обозначением отсутствия быть не может: он означает часовой пояс UTC
	 */
	ASSERT_EQ(stamp.offset, toml::NO_TIMEZONE);
	// Выполняем проверку того, что обозначение отсутствия смещения нулём не является
	ASSERT_NE(toml::NO_TIMEZONE, 0);
	// Объект значения текста настроек
	const toml::content_t value;
	// Выполняем проверку того, что тип значения не определён
	ASSERT_EQ(value.type, toml::type_t::NONE);
	// Объект составной части имени ключа
	const toml::part_t part;
	// Выполняем проверку того, что запись имени части взята без кавычек
	ASSERT_EQ(part.naming, toml::naming_t::BARE);
}
/**
 * @brief Проверка способов наружу, отдельными объявленных
 *
 * @details Признание знака имени голого, поверка даты по календарю, длина
 *          последовательности UTF-8 по ведущему байту и разбор последовательности
 *          объявлены наружу отдельными способами: потребитель рамки вправе звать их, не
 *          заводя ни чтения, ни дерева
 *
 * @note Ни один из четырёх набором проверок не звался - розыск по объявленным наружу
 *       отдельным способам не дал ни одного случая
 *
 * @warning Поверка даты взята ГРАНИЦАМИ: високосность решается тремя правилами разом -
 *          делимостью на четыре, на сто и на четыреста, - и всякое из них проверяется
 *          парою соседних годов. Карта охвата этого не берёт: строка сравнения
 *          исполняется при всяком годе подряд
 *
 * @note Порчею доказаны два места: сдвиг края набора знаков имени на единицу и снятие
 *       правил ста и четырёхсот у високосности - всякое проверку валит. Прочие места
 *       того же вида и держатся утверждениями теми же
 *
 */
TEST(CodecTomlCommon, ExportedHelpers) {
	/**
	 * Выполняем проверку признания знака имени голого
	 */
	{
		/**
		 * Проверяемые кодовые значения вместе с ожиданием признания
		 *
		 * @note Знаки US-ASCII способ этот не берёт вовсе: буквы, цифры, подчёркивание и
		 *       черту разбирает само чтение, а способ держит наборы Юникода сверх них.
		 *       Оттого взяты тут ГРАНИЦЫ наборов - знак перед набором, края его и знак
		 *       за ним
		 */
		const pair <uint32_t, bool> letters[] = {
			// Буква латинская способом этим не признаётся
			{static_cast <uint32_t> ('a'), false},
			// Знак перед первым набором не признаётся
			{0x00B1, false},
			// Начало первого набора признаётся
			{0x00B2, true},
			// Конец первого набора признаётся
			{0x00B3, true},
			// Знак за первым набором не признаётся
			{0x00B4, false},
			// Конец набора перед изъятием признаётся
			{0x00D6, true},
			// Изъятый знак между наборами не признаётся
			{0x00D7, false},
			// Начало набора за изъятием признаётся
			{0x00D8, true},
			// Конец набора перед изъятием знака признаётся
			{0x037D, true},
			// Изъятый знак не признаётся
			{0x037E, false},
			// Начало набора за изъятым знаком признаётся
			{0x037F, true},
			// Знак перед отрезком суррогатов признаётся
			{0xD7FF, true},
			// Первый суррогат не признаётся
			{0xD800, false},
			// Начало набора таблиц сверх основной признаётся
			{0x10000, true},
			// Конец набора таблиц сверх основной признаётся
			{0xEFFFF, true},
			// Знак за последним набором не признаётся
			{0xF0000, false}
		};
		/**
		 * Выполняем перебор проверяемых кодовых значений
		 */
		for(auto & letter : letters){
			// Выполняем проверку признания знака имени голого
			ASSERT_EQ(toml::named(letter.first), letter.second)
			 << "знак " << std::hex << letter.first;
		}
	}
	/**
	 * Проверяемые даты вместе с ожиданием годности
	 */
	const struct {
		// Год проверяемой даты
		uint16_t year;
		// Месяц проверяемой даты
		uint8_t month;
		// День проверяемой даты
		uint8_t day;
		// Ожидание годности проверяемой даты
		bool valid;
	} dates[] = {
		// Первый день года годен
		{2026, 1, 1, true},
		// Последний день года годен
		{2026, 12, 31, true},
		// Месяц нулевой негоден
		{2026, 0, 1, false},
		// Месяц тринадцатый негоден
		{2026, 13, 1, false},
		// День нулевой негоден
		{2026, 1, 0, false},
		// Тридцать второй день месяца негоден
		{2026, 1, 32, false},
		// Тридцать первое апреля негодно: в апреле тридцать дней
		{2026, 4, 31, false},
		// Тридцатое апреля годно
		{2026, 4, 30, true},
		// Двадцать девятое февраля года, на четыре не делящегося, негодно
		{2026, 2, 29, false},
		// Двадцать восьмое февраля того же года годно
		{2026, 2, 28, true},
		// Двадцать девятое февраля года, на четыре делящегося, годно
		{2024, 2, 29, true},
		// Двадцать девятое февраля года, на сто делящегося, негодно
		{1900, 2, 29, false},
		// Двадцать девятое февраля года, на четыреста делящегося, годно
		{2000, 2, 29, true}
	};
	/**
	 * Выполняем перебор проверяемых дат
	 */
	for(auto & date : dates){
		// Выполняем проверку годности даты по календарю
		ASSERT_EQ(toml::calendar(date.year, date.month, date.day), date.valid)
		 << date.year << "-" << static_cast <unsigned> (date.month)
		 << "-" << static_cast <unsigned> (date.day);
	}
	/**
	 * Выполняем проверку длины последовательности по ведущему байту
	 */
	{
		// Выполняем проверку длины последовательности знака US-ASCII
		ASSERT_EQ(toml::sequence(0x41), static_cast <size_t> (1));
		// Выполняем проверку длины последовательности о двух байтах
		ASSERT_EQ(toml::sequence(0xD0), static_cast <size_t> (2));
		// Выполняем проверку длины последовательности о трёх байтах
		ASSERT_EQ(toml::sequence(0xE0), static_cast <size_t> (3));
		// Выполняем проверку длины последовательности о четырёх байтах
		ASSERT_EQ(toml::sequence(0xF0), static_cast <size_t> (4));
		// Выполняем проверку того, что продолжающий байт ведущим не является
		ASSERT_EQ(toml::sequence(0x80), static_cast <size_t> (0));
	}
	/**
	 * Выполняем проверку разбора последовательности UTF-8
	 */
	{
		// Разобранное кодовое значение знака
		uint32_t code = 0;
		// Длина разобранной последовательности
		size_t length = 0;
		// Выполняем проверку разбора последовательности годной
		ASSERT_EQ(toml::inspect("привет", 0, code, length), toml::utf8_t::VALID);
		// Выполняем проверку разобранного кодового значения
		ASSERT_EQ(code, static_cast <uint32_t> (0x043F));
		// Выполняем проверку длины разобранной последовательности
		ASSERT_EQ(length, static_cast <size_t> (2));
		// Выполняем проверку разбора последовательности, концом текста оборванной
		ASSERT_EQ(toml::inspect(string_view("\xD0", 1), 0, code, length), toml::utf8_t::TRUNCATED);
		// Выполняем проверку разбора последовательности построения ошибочного
		ASSERT_EQ(toml::inspect(string_view("\xD0\x41", 2), 0, code, length), toml::utf8_t::BROKEN);
	}
}
/**
 * @brief Проверка границ разбора последовательности UTF-8
 *
 * @details Разбор отвергает запись длиннее необходимой, суррогаты и всё, что за предел
 *          Юникода выходит. Границы решают тут трижды: наименьшее значение, записи данной
 *          длины отведённое, края отрезка суррогатов и последний знак Юникода
 *
 * @note Запись длиннее необходимой есть знак иной, нежели тот, что она изображает:
 *       признать её значило бы принять два написания одного имени. Отсюда и требование
 *       наименьшего значения на всякую длину записи
 *
 * @warning Границы эти картою охвата не берутся: строки сравнения исполняются при всякой
 *          записи подряд. Взяты они парами соседних значений - наименьшее дозволенное и
 *          предшествующее ему, край отрезка суррогатов и знак за ним
 *
 * @note Порчею доказаны две границы: сдвиг наименьшего значения записи о двух байтах на
 *       единицу и подмена «не меньше 0xD800» на «больше 0xD800» валят проверку всякая
 *       сама по себе. Прочие границы того же вида и держатся утверждениями теми же
 *
 */
TEST(CodecTomlCommon, InspectBoundaries) {
	/**
	 * Проверяемые записи последовательностей вместе с ожиданием разбора
	 */
	const struct {
		// Разбираемая запись последовательности
		const char * bytes;
		// Длина разбираемой записи
		size_t size;
		// Ожидаемый исход разбора
		toml::utf8_t outcome;
		// Ожидаемое кодовое значение при разборе успешном
		uint32_t code;
	} samples[] = {
		// Наименьший знак записи о двух байтах дозволен
		{"\xC2\x80", 2, toml::utf8_t::VALID, 0x80},
		// Знак записи о двух байтах ниже наименьшего есть запись длиннее необходимой
		{"\xC1\xBF", 2, toml::utf8_t::BROKEN, 0},
		// Пустой знак записью о двух байтах есть запись длиннее необходимой
		{"\xC0\x80", 2, toml::utf8_t::BROKEN, 0},
		// Наименьший знак записи о трёх байтах дозволен
		{"\xE0\xA0\x80", 3, toml::utf8_t::VALID, 0x800},
		// Знак записи о трёх байтах ниже наименьшего есть запись длиннее необходимой
		{"\xE0\x9F\xBF", 3, toml::utf8_t::BROKEN, 0},
		// Знак перед отрезком суррогатов дозволен
		{"\xED\x9F\xBF", 3, toml::utf8_t::VALID, 0xD7FF},
		// Первый суррогат не дозволен
		{"\xED\xA0\x80", 3, toml::utf8_t::BROKEN, 0},
		// Последний суррогат не дозволен
		{"\xED\xBF\xBF", 3, toml::utf8_t::BROKEN, 0},
		// Знак за отрезком суррогатов дозволен
		{"\xEE\x80\x80", 3, toml::utf8_t::VALID, 0xE000},
		// Наименьший знак записи о четырёх байтах дозволен
		{"\xF0\x90\x80\x80", 4, toml::utf8_t::VALID, 0x10000},
		// Знак записи о четырёх байтах ниже наименьшего есть запись длиннее необходимой
		{"\xF0\x8F\xBF\xBF", 4, toml::utf8_t::BROKEN, 0},
		// Последний знак Юникода дозволен
		{"\xF4\x8F\xBF\xBF", 4, toml::utf8_t::VALID, 0x10FFFF},
		// Знак за пределом Юникода не дозволен
		{"\xF4\x90\x80\x80", 4, toml::utf8_t::BROKEN, 0}
	};
	/**
	 * Выполняем перебор проверяемых записей последовательностей
	 */
	for(auto & sample : samples){
		// Разобранное кодовое значение знака
		uint32_t code = 0;
		// Длина разобранной последовательности
		size_t length = 0;
		// Выполняем проверку исхода разбора последовательности
		ASSERT_EQ(toml::inspect(string_view(sample.bytes, sample.size), 0, code, length), sample.outcome)
		 << "запись " << std::hex << static_cast <unsigned> (static_cast <uint8_t> (sample.bytes[0]));
		/**
		 * Если разбор успехом окончился
		 */
		if(sample.outcome == toml::utf8_t::VALID){
			// Выполняем проверку разобранного кодового значения
			ASSERT_EQ(code, sample.code) << "запись " << std::hex << sample.code;
			// Выполняем проверку длины разобранной последовательности
			ASSERT_EQ(length, sample.size) << "запись " << std::hex << sample.code;
		}
	}
}
/**
 * @brief Проверка чтения знака Юникода из оборванной последовательности
 *
 * @details Чтение знака выдаёт количество байтов его, а ноль означает знак битый
 * либо оборванный. Путь этот покрытием не задевался: чтение зовётся лишь именами
 * ключей, а имя с битым знаком отвергается разбором прежде
 *
 */
TEST(CodecTomlCommon, DecodeBrokenSequence) {
	// Прочитанный знак Юникода
	uint32_t code = 0;
	// Выполняем проверку чтения знака из оборванной последовательности
	ASSERT_EQ(toml::decode(string_view("\xD0", 1), 0, code), static_cast <size_t> (0));
	// Выполняем проверку чтения знака из последовательности, построенной ошибочно
	ASSERT_EQ(toml::decode(string_view("\x80\x80", 2), 0, code), static_cast <size_t> (0));
	/**
	 * Выполняем проверку чтения знака из последовательности годной
	 *
	 * @note Заход этот стоит рядом нарочно: ноль, приходящий на всякую
	 *       последовательность, отвечал бы тому же ожиданию
	 */
	ASSERT_EQ(toml::decode(string_view("\xD0\xB0", 2), 0, code), static_cast <size_t> (2));
	// Выполняем проверку прочитанного знака Юникода
	ASSERT_EQ(code, static_cast <uint32_t> (0x430));
}
