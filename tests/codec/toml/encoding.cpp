/**
 * @brief Метод приведения текста кусками заданного размера
 *
 * @param text     приводимый текст
 * @param chunk    размер куска подачи, ноль означает подачу целиком
 * @param encoding навязываемая кодировка исходного текста
 * @param result   приведённый текст
 * @return         результат приведения
 *
 */
static bool convert(const string & text, const size_t chunk, const toml::encoding_t encoding, string & result) noexcept {
	// Объект приведения исходного текста к кодировке UTF-8
	toml::decoder_t decoder;
	// Выполняем очистку приведённого текста
	result.clear();
	// Выполняем установку навязываемой кодировки исходного текста
	decoder.encoding(encoding);
	// Позиция чтения приводимого текста
	size_t offset = 0;
	/**
	 * Выполняем подачу приводимого текста кусками
	 */
	do {
		// Получаем размер очередного куска подачи
		const size_t length = ((chunk == 0) ? text.size() : min(chunk, (text.size() - offset)));
		// Получаем признак того, что кусок является последним
		const bool end = ((offset + length) >= text.size());
		/**
		 * Если приведение очередного куска не удалось
		 */
		if(!decoder.convert(text.data() + offset, length, end, result))
			// Выводим отрицательный результат приведения
			return false;
		// Выполняем переход к следующему куску подачи
		offset += length;
		/**
		 * Если кусок оказался последним
		 */
		if(end)
			// Выходим из цикла подачи приводимого текста
			break;
	} while(offset <= text.size());
	// Выводим положительный результат приведения
	return true;
}

/**
 * @brief Проверка допустимости знаков в тексте настроек
 *
 * @details Описание отвергает управляющие знаки области C0 сырыми, дозволяя из них
 * табуляцию, перевод строки и возврат каретки, и отвергает забой. Область C1 при этом
 * дозволена, и это отличие от записи INI закреплено здесь намеренно
 *
 */
TEST(CodecTomlEncoding, AllowedCharacters) {
	// Выполняем проверку допустимости горизонтальной табуляции
	ASSERT_TRUE(toml::isChar(0x09));
	// Выполняем проверку допустимости перевода строки
	ASSERT_TRUE(toml::isChar(0x0A));
	// Выполняем проверку допустимости возврата каретки
	ASSERT_TRUE(toml::isChar(0x0D));
	/**
	 * Выполняем перебор управляющих знаков области C0
	 */
	for(uint32_t code = 0; code < 0x20; code++){
		/**
		 * Если знак дозволен описанием
		 */
		if((code == 0x09) || (code == 0x0A) || (code == 0x0D))
			// Переходим к следующему знаку области
			continue;
		// Выполняем проверку недопустимости управляющего знака области C0
		ASSERT_FALSE(toml::isChar(code)) << code;
	}
	// Выполняем проверку недопустимости знака забоя
	ASSERT_FALSE(toml::isChar(0x7F));
	/**
	 * Выполняем перебор управляющих знаков области C1
	 */
	for(uint32_t code = 0x80; code <= 0x9F; code++)
		// Выполняем проверку допустимости знака области C1
		ASSERT_TRUE(toml::isChar(code)) << code;
	/**
	 * Выполняем перебор суррогатных кодовых значений
	 */
	for(uint32_t code = 0xD800; code <= 0xDFFF; code += 0x100)
		// Выполняем проверку недопустимости суррогатного кодового значения
		ASSERT_FALSE(toml::isChar(code)) << code;
	// Выполняем проверку допустимости наибольшего кодового значения Юникода
	ASSERT_TRUE(toml::isChar(toml::MAX_CODEPOINT));
	// Выполняем проверку недопустимости кодового значения за пределами Юникода
	ASSERT_FALSE(toml::isChar(toml::MAX_CODEPOINT + 1));
}
/**
 * @brief Проверка чтения и записи знаков Юникода
 *
 */
TEST(CodecTomlEncoding, Codepoints) {
	// Проверяемые кодовые значения знаков
	const vector <uint32_t> codes = {0x00, 0x41, 0x7F, 0x80, 0x416, 0x7FF, 0x800, 0x2028, 0xFFFD, 0x10000, 0x1F600, toml::MAX_CODEPOINT};
	/**
	 * Выполняем перебор проверяемых кодовых значений
	 */
	for(auto code : codes){
		// Собираемый текст записи знака
		string text;
		// Выполняем проверку того, что запись знака удалась
		ASSERT_TRUE(toml::encode(code, text)) << code;
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение записанного знака обратно
		ASSERT_EQ(toml::decode(text.data(), text.size(), length), code) << code;
		// Выполняем проверку того, что прочитана вся запись знака
		ASSERT_EQ(length, text.size()) << code;
	}
	/**
	 * Выполняем перебор суррогатных кодовых значений
	 */
	{
		// Собираемый текст записи знака
		string text;
		// Выполняем проверку отказа записи суррогатного кодового значения
		ASSERT_FALSE(toml::encode(0xD800, text));
		// Выполняем проверку отказа записи кодового значения за пределами Юникода
		ASSERT_FALSE(toml::encode(toml::MAX_CODEPOINT + 1, text));
	}
	/**
	 * Выполняем проверку отказа чтения избыточно длинных записей
	 *
	 * @note Одно и то же кодовое значение допускает лишь единственную запись:
	 *       избыточно длинные записи служат обходом проверок содержимого
	 */
	{
		// Избыточно длинные записи знаков
		const vector <string> overlong = {string("\xC0\x80", 2), string("\xE0\x80\x80", 3), string("\xF0\x80\x80\x80", 4)};
		/**
		 * Выполняем перебор избыточно длинных записей знаков
		 */
		for(auto & text : overlong){
			// Длина прочитанной последовательности знака
			size_t length = 0;
			// Выполняем проверку отказа чтения избыточно длинной записи
			ASSERT_EQ(toml::decode(text.data(), text.size(), length), toml::INVALID_CODEPOINT) << text.size();
		}
	}
}
/**
 * @brief Проверка приведения текста в кодировке UTF-8
 *
 */
TEST(CodecTomlEncoding, Utf8) {
	// Приведённый текст настроек
	string result;
	// Выполняем проверку того, что приведение текста удалось
	ASSERT_TRUE(convert("ключ = \"значение\"\n", 0, toml::encoding_t::NONE, result));
	// Выполняем проверку сохранности приведённого текста
	ASSERT_EQ(result, "ключ = \"значение\"\n");
	// Выполняем проверку отказа приведения текста с управляющим знаком
	ASSERT_FALSE(convert(string("k = \"a\x01\"\n"), 0, toml::encoding_t::NONE, result));
	// Выполняем проверку приведения текста со знаком области C1
	ASSERT_TRUE(convert(string("k = \"\xC2\x85\"\n"), 0, toml::encoding_t::NONE, result));
}
/**
 * @brief Проверка определения кодировки по метке порядка байтов
 *
 */
TEST(CodecTomlEncoding, Signature) {
	// Приведённый текст настроек
	string result;
	// Объект приведения исходного текста к кодировке UTF-8
	toml::decoder_t decoder;
	// Текст настроек с меткой порядка байтов кодировки UTF-8
	const string text = string("\xEF\xBB\xBF") + "k = 1\n";
	// Выполняем проверку того, что приведение текста удалось
	ASSERT_TRUE(decoder.convert(text.data(), text.size(), true, result));
	// Выполняем проверку того, что метка порядка байтов обнаружена
	ASSERT_TRUE(decoder.signature());
	// Выполняем проверку определённой кодировки исходного текста
	ASSERT_EQ(decoder.encoding(), toml::encoding_t::UTF8);
	// Выполняем проверку того, что метка порядка байтов снята с приведённого текста
	ASSERT_EQ(result, "k = 1\n");
	/**
	 * Выполняем проверку отказа приведения текста в кодировке UTF-32
	 *
	 * @note Метка её начинается с метки UTF-16, и без проверки следующих байтов текст
	 *       разбирался бы как UTF-16 с пустыми знаками между настоящими
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		toml::decoder_t reader;
		// Текст настроек с меткой порядка байтов кодировки UTF-32
		const string source = string("\xFF\xFE\x00\x00", 4) + string("k", 1);
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения текста
		ASSERT_FALSE(reader.convert(source.data(), source.size(), true, result));
		// Выполняем проверку выданного кода ошибки приведения
		ASSERT_EQ(reader.error(), toml::error_t::UNSUPPORTED_ENCODING);
	}
}
/**
 * @brief Проверка независимости приведения от нарезки текста на куски
 *
 * @details Договор этот у всякого потокового разбора AWH один: выдача не зависит от
 * того, как исходный текст нарезан. Проверяется он подачей по одному байту - границы
 * ложатся посреди последовательностей знаков и посреди суррогатных пар
 *
 */
TEST(CodecTomlEncoding, ChunkIndependence) {
	// Проверяемые тексты настроек
	const vector <string> texts = {
		"ключ = \"значение\"\n",
		"emoji = \"\xF0\x9F\x98\x80\"\n",
		"[таблица]\nчисло = 42\n",
		string("\xEF\xBB\xBF") + "k = 1\n"
	};
	/**
	 * Выполняем перебор проверяемых текстов настроек
	 */
	for(auto & text : texts){
		// Приведённый подачей целиком текст настроек
		string whole;
		// Выполняем проверку того, что приведение подачей целиком удалось
		ASSERT_TRUE(convert(text, 0, toml::encoding_t::NONE, whole)) << text;
		/**
		 * Выполняем перебор размеров куска подачи
		 */
		for(size_t chunk = 1; chunk <= 5; chunk++){
			// Приведённый подачей кусками текст настроек
			string chunked;
			// Выполняем проверку того, что приведение подачей кусками удалось
			ASSERT_TRUE(convert(text, chunk, toml::encoding_t::NONE, chunked)) << text << " " << chunk;
			// Выполняем проверку совпадения приведённого с поданным целиком
			ASSERT_EQ(chunked, whole) << text << " " << chunk;
		}
	}
}
/**
 * @brief Проверка приведения текста в кодировке UTF-16
 *
 * @details Описание отводит записи TOML кодировку UTF-8, но файл, полученный от чужой
 * оснастки, бывает записан иначе: кодировка принимается опознанной по метке порядка
 * байтов либо навязанной извне, и выдача её обязана совпасть с выдачей UTF-8
 *
 */
TEST(CodecTomlEncoding, Utf16) {
	// Исходный текст настроек в кодировке UTF-8
	const string source = "ключ = \"значение \xF0\x9F\x98\x80\"\n";
	/**
	 * Выполняем перебор порядков байтов кодировки UTF-16
	 */
	for(uint32_t order = 0; order < 2; order++){
		// Получаем признак прямого порядка байтов кодировки
		const bool big = (order == 1);
		// Собираемый текст настроек в кодировке UTF-16
		string text;
		/**
		 * Выполняем перебор знаков исходного текста настроек
		 */
		for(size_t i = 0; i < source.size();){
			// Длина прочитанной последовательности знака
			size_t length = 0;
			// Выполняем чтение очередного знака исходного текста
			const uint32_t code = toml::decode(source.data() + i, (source.size() - i), length);
			// Выполняем проверку того, что чтение знака удалось
			ASSERT_NE(code, toml::INVALID_CODEPOINT) << i;
			// Выполняем переход к следующему знаку исходного текста
			i += length;
			// Собираемые половины суррогатной пары знака
			uint16_t units[2] = {0, 0};
			// Количество собранных половин суррогатной пары
			size_t count = 1;
			/**
			 * Если знак записывается суррогатной парой
			 */
			if(code >= 0x10000){
				// Запоминаем старшую половину суррогатной пары
				units[0] = static_cast <uint16_t> (0xD800 + ((code - 0x10000) >> 10));
				// Запоминаем младшую половину суррогатной пары
				units[1] = static_cast <uint16_t> (0xDC00 + ((code - 0x10000) & 0x3FF));
				// Запоминаем количество собранных половин суррогатной пары
				count = 2;
			// Запоминаем значение пары байтов знака
			} else units[0] = static_cast <uint16_t> (code);
			/**
			 * Выполняем запись собранных пар байтов знака
			 */
			for(size_t j = 0; j < count; j++){
				// Выполняем запись старшего либо младшего байта пары
				text.push_back(static_cast <char> (big ? (units[j] >> 8) : (units[j] & 0xFF)));
				// Выполняем запись оставшегося байта пары
				text.push_back(static_cast <char> (big ? (units[j] & 0xFF) : (units[j] >> 8)));
			}
		}
		/**
		 * Выполняем перебор размеров куска подачи
		 */
		for(size_t chunk = 0; chunk <= 3; chunk++){
			// Приведённый текст настроек
			string result;
			// Получаем навязываемую кодировку исходного текста
			const toml::encoding_t encoding = (big ? toml::encoding_t::UTF16BE : toml::encoding_t::UTF16LE);
			// Выполняем проверку того, что приведение текста удалось
			ASSERT_TRUE(convert(text, chunk, encoding, result)) << order << " " << chunk;
			/**
			 * Выполняем проверку совпадения приведённого текста с исходным
			 *
			 * @note Совпадать обязано знак в знак: приведение к общей кодировке ведётся
			 *       до разбора, и текст, записанный иначе, обязан дать ту же выдачу
			 */
			ASSERT_EQ(result, source) << order << " " << chunk;
		}
	}
}
