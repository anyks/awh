# @brief Щуп зрячести стенда ABC: перебирает величины кодека подменами и печатает
#        ИМЕНА проверок, всякой подменою покрасневших
#
# @details Щуп заведён оттого, что правило, живущее в доводе проверки, читают ПОСЛЕ
# работы, а не перед нею, - и пишут проверки мимо него. За два дня так вышло трижды.
# Правило, обязательное к памяти перед письмом, должно жить в щупе, ловящем его
# нарушение, а не в записи о нём
#
# @details Печатаются ИМЕНА, а не число: проверка, сличающая величину с литералом,
# краснеет от всякой подмены и о поведении не свидетельствует ничем, - оттого она из
# выдачи вычитается, и остаются сторожа ПОВЕДЕНИЯ
#
# @note Подмены здесь ГРУБЫЕ - до заведомо достижимой малости, а не на единицу. Сдвиг на
#       единицу слеп ко всякому пределу, у какого нет проверки ровно на границе, и
#       молчание его означает «на границе никто не стоит», а вовсе не «предел не
#       стережётся». Величины же вида записи двигаются на единицу: у них всякий сдвиг
#       равно порочен
#
# @note Пустая выдача разбирается ТРЕМЯ случаями, и путать их нельзя:
#       - величина применяется лишь умолчанием настраиваемого поля, а проверки ставят
#         предел свой - законно, и закрепление литералом есть весь её сторож;
#       - величина стоит заслоном напрямую, а сторожа нет - НАХОДКА;
#       - величина стоит потолком последней руки («настройка в ноль либо сверх потолка
#         берёт потолок модуля») - НАХОДКА, и самая тихая из трёх, ибо оба заслона видны
#         одним и тем же поиском, а отличает их лишь то, ГДЕ смотреть. У ABC потолок
#         глубины живёт в пяти местах: четыре у разбора со сборкой, одно у владеющего
#         значения. Третий случай назван владельцем JSON/XML/CSV 04.09.2026 после того,
#         как он час отрицал его у себя, глядя прямо в код
#
# @note Как ЧИТАТЬ выдачу: проверка, ставящая настройку сама, при подмене умолчания не
#       краснеет никогда, - значит покрасневшие и суть те, что идут ПО УМОЛЧАНИЮ
#
# @note Пустая выдача у знака вида записи законна особо: обе стороны его двигаются
#       согласно, круговой ход сойдётся при любом знаке, и поведением он не проверяем
#       вовсе
#
# @copyright Copyright © 2026
#

# Корень дерева исходных текстов
ROOT="${1:-$(cd "$(dirname "$0")/../../.." && pwd)}"
# Каталог сборки стенда
OUTPUT="${2:-/tmp/awh-abc-mutate}"
# Проверка, закрепляющая величины литералами
PINNING="CodecAbcCommon.WireConstants"

# Перечень подмен: файл:строка:старое:новое
MUTATIONS="
common.hpp:MAX_DEPTH = 0x400:MAX_DEPTH = 4
common.hpp:MAX_NODES = 0x4000000:MAX_NODES = 4
common.hpp:INDEX_THRESHOLD = 16:INDEX_THRESHOLD = 1
common.hpp:INLINE_LIMIT = 0x17:INLINE_LIMIT = 0x16
common.hpp:SPAN_LENGTH = 8:SPAN_LENGTH = 7
encoding.hpp:TIME_WIDTH = 8:TIME_WIDTH = 7
encoding.hpp:UUID_WIDTH = 16:UUID_WIDTH = 15
header.hpp:VERSION_MAJOR = 1:VERSION_MAJOR = 2
header.hpp:VERSION_MINOR = 0:VERSION_MINOR = 1
"

# Признак обнаружения хотя бы одной величины без сторожей
NAKED=0

echo "Щуп зрячести стенда ABC: подмены величин кодека"
echo

# Выполняем перебор всех объявленных подмен
echo "$MUTATIONS" | while read -r LINE; do
	# Если строка перечня пуста
	[ -z "$LINE" ] && continue
	# Имя файла заголовка, величину несущего
	FILE="$ROOT/include/codec/abc/$(echo "$LINE" | cut -d: -f1)"
	# Прежнее написание величины
	FROM=$(echo "$LINE" | cut -d: -f2)
	# Подменённое написание величины
	INTO=$(echo "$LINE" | cut -d: -f3)
	# Если файла заголовка не существует
	if [ ! -f "$FILE" ]; then
		echo "ОТКАЗ: нет файла $FILE"
		exit 1
	fi
	# Выполняем снятие эталона файла заголовка
	cp "$FILE" "$FILE.mutate-backup"
	# Выполняем подмену величины
	sed -i.tmp "s/$FROM/$INTO/" "$FILE" && rm -f "$FILE.tmp"
	# Если подмена ничего не изменила
	if cmp -s "$FILE" "$FILE.mutate-backup"; then
		# Выполняем возврат эталона файла заголовка
		mv "$FILE.mutate-backup" "$FILE"
		echo "ОТКАЗ: подмена «$FROM» ничего не изменила - написание разошлось"
		exit 1
	fi
	# Выполняем сборку стенда с подменённой величиной
	sh "$ROOT/tests/codec/abc/stand.sh" "$ROOT" "$OUTPUT" > "$OUTPUT.log" 2>&1
	# Исход сборки стенда
	BUILD=$?
	# Выполняем возврат эталона файла заголовка
	mv "$FILE.mutate-backup" "$FILE"
	# Если сборка стенда не удалась
	if [ $BUILD -ne 0 ]; then
		# Первая строка отказа сборки, имя виновного файла несущая
		REASON=$(grep -m 1 -E "error:|ошибка:" "$OUTPUT.log")
		#
		# Печатается ПЕРВАЯ СТРОКА отказа целиком, а не одно слово «отказ»
		#
		# @warning Щуп правит три заголовка кодека и только числами. Оттого имя файла в
		# строке отказа отвечает на вопрос «чьё» сразу: отказ в чужом файле есть правка
		# соседа, пришедшая в середину прогона, и круги эти сгорели впустую, а не нашли
		# что-либо. Без печати имени своя порча неотличима от чужой, и щуп молчит о том,
		# что мерил не то. Приём взят у владельца JSON/XML/CSV 04.09.2026, у какого так
		# сгорело семь кругов подряд. НЕ УБИРАТЬ как многословие
		#
		echo "$FROM -> ОТКАЗ СБОРКИ :: ${REASON:-причина не названа, см. $OUTPUT.log}"
		continue
	fi
	# Имена покрасневших проверок за вычетом закрепителя величин
	NAMES=$("$OUTPUT/abc-tests" 2>&1 | grep -E "^\[  FAILED  \] [A-Za-z].*\(" |
	 sed 's/.*] //; s/ (.*//' | sort -u | grep -v "$PINNING" | tr '\n' ' ')
	# Если сторожей поведения у величины не нашлось
	if [ -z "$NAMES" ]; then
		# Выводим находку особо
		echo "$FROM -> СТОРОЖЕЙ ПОВЕДЕНИЯ НЕТ"
	# Иначе выводим имена сторожей поведения
	else echo "$FROM -> $NAMES"; fi
done

# Выполняем пересборку стенда эталоном дерева
#
# @warning Без пересборки в каталоге остаётся двоичный файл ПОСЛЕДНЕЙ подмены, и
# следующий, кто запустит стенд не пересобрав его, получит зелень мутанта. Ловушка
# старого двоичного файла - см. записи о щупах
sh "$ROOT/tests/codec/abc/stand.sh" "$ROOT" "$OUTPUT" > "$OUTPUT.log" 2>&1
# Исход пересборки стенда эталоном
FINAL=$?

echo
# Если пересборка стенда эталоном не удалась
if [ $FINAL -ne 0 ]; then
	echo "ОТКАЗ: стенд эталоном не пересобран, двоичный файл несёт последнюю подмену"
	exit 1
fi
echo "Стенд пересобран эталоном дерева"
echo "Пусто у ПРЕДЕЛА либо ПОТОЛКА есть находка; у знака вида записи оно законно"
