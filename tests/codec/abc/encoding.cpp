/**
 * @brief Проверка неопределённой длины вместимого
 *
 * @details Неопределённая длина дозволена лишь вместимому: у строки и у числа она
 * означала бы запись, чей конец опознать нечем
 *
 */
TEST(CodecAbcEncoding, IndefiniteLength) {
	/**
	 * Крупные виды, вместимыми являющиеся
	 */
	const vector <abc::group_t> containers = {
		abc::group_t::ARRAY, abc::group_t::MAP, abc::group_t::STRING, abc::group_t::BLOB
	};
	/**
	 * Выполняем перебор всех вместимых крупных видов
	 */
	for(const abc::group_t group : containers){
		// Буфер собираемой записи
		vector <uint8_t> result;
		// Выполняем укладку метки неопределённой длины
		abc::mark(result, group, static_cast <uint8_t> (abc::single_t::BREAK));
		// Смещение, с какого следует снимать единицу
		size_t offset = 0;
		// Снятая единица проволочной записи
		abc::item_t item;
		// Код отказа снятия единицы
		abc::error_t error = abc::error_t::NONE;
		// Выполняем снятие единицы проволочной записи
		ASSERT_TRUE(abc::take(result.data(), result.size(), offset, item, error))
			<< "крупный вид: " << static_cast <uint32_t> (group);
		// Выполняем проверку признака неопределённой длины вместимого
		ASSERT_TRUE(item.indefinite) << "крупный вид: " << static_cast <uint32_t> (group);
	}
	/**
	 * Крупные виды, неопределённой длины не допускающие
	 *
	 * @details Строка и двоичные данные её допускают: собираются они кусками, когда
	 *          длина наперёд неизвестна. Число же кусками не собирается - величина его
	 *          цельна, и делить её на куски значило бы толковать запись двояко
	 */
	const vector <abc::group_t> plains = {
		abc::group_t::UNSIGNED, abc::group_t::NEGATIVE
	};
	/**
	 * Выполняем перебор всех невместимых крупных видов
	 */
	for(const abc::group_t group : plains){
		// Буфер собираемой записи
		vector <uint8_t> result;
		// Выполняем укладку метки неопределённой длины
		abc::mark(result, group, static_cast <uint8_t> (abc::single_t::BREAK));
		// Смещение, с какого следует снимать единицу
		size_t offset = 0;
		// Снятая единица проволочной записи
		abc::item_t item;
		// Код отказа снятия единицы
		abc::error_t error = abc::error_t::NONE;
		// Выполняем проверку отказа снятия единицы
		ASSERT_FALSE(abc::take(result.data(), result.size(), offset, item, error))
			<< "крупный вид: " << static_cast <uint32_t> (group);
		// Выполняем проверку кода отказа
		ASSERT_EQ(error, abc::error_t::UNKNOWN_TAG) << "крупный вид: " << static_cast <uint32_t> (group);
	}
}
/**
 * @brief Проверка независимости снятия от нарезки записи на куски
 *
 * @details Единица, поданная не целиком, обязана оставлять смещение нетронутым: подача
 * следующего куска продолжит разбор с того же места. Сдвиг смещения у наполовину снятой
 * единицы обратил бы разбор в зависимый от того, как запись нарезана
 *
 */
TEST(CodecAbcEncoding, ChunkIndependence) {
	// Буфер собираемой записи
	vector <uint8_t> result;
	// Выполняем укладку значения, ведущего запись в восемь октетов
	abc::put(result, abc::group_t::UNSIGNED, numeric_limits <uint64_t>::max());
	// Выполняем проверку длины собранной записи
	ASSERT_EQ(result.size(), 9u);
	/**
	 * Выполняем перебор всех неполных подач записи
	 */
	for(size_t size = 0; size < result.size(); size++){
		// Смещение, с какого следует снимать единицу
		size_t offset = 0;
		// Снятая единица проволочной записи
		abc::item_t item;
		// Код отказа снятия единицы
		abc::error_t error = abc::error_t::NONE;
		// Выполняем проверку отказа снятия единицы
		ASSERT_FALSE(abc::take(result.data(), size, offset, item, error)) << "подано октетов: " << size;
		// Выполняем проверку кода отказа
		ASSERT_EQ(error, abc::error_t::UNEXPECTED_EOF) << "подано октетов: " << size;
		// Выполняем проверку, что смещение осталось нетронутым
		ASSERT_EQ(offset, 0u) << "подано октетов: " << size;
	}
	// Смещение, с какого следует снимать единицу
	size_t offset = 0;
	// Снятая единица проволочной записи
	abc::item_t item;
	// Код отказа снятия единицы
	abc::error_t error = abc::error_t::NONE;
	// Выполняем снятие единицы проволочной записи, поданной целиком
	ASSERT_TRUE(abc::take(result.data(), result.size(), offset, item, error));
	// Выполняем проверку значения снятой единицы
	ASSERT_EQ(item.value, numeric_limits <uint64_t>::max());
}
/**
 * @brief Проверка строк на соответствие кодировке UTF-8
 *
 */
TEST(CodecAbcEncoding, Utf8Validation) {
	/**
	 * Годные строки
	 */
	const vector <string> valid = {
		"", "hello", "Привет", "\xE6\x97\xA5\xE6\x9C\xAC", "\xF0\x9F\x98\x80",
		string("\x00", 1), "\x7F", "\xC2\x80", "\xDF\xBF", "\xE0\xA0\x80", "\xF4\x8F\xBF\xBF"
	};
	// Смещение первой негодной последовательности
	size_t position = 0;
	/**
	 * Выполняем перебор всех годных строк
	 */
	for(const string & text : valid)
		// Выполняем проверку соответствия строки кодировке
		ASSERT_TRUE(abc::utf8(reinterpret_cast <const uint8_t *> (text.data()), text.size(), position))
			<< "строка отвергнута на смещении: " << position;
	/**
	 * Негодные строки
	 */
	const vector <string> invalid = {
		"\x80",                 // Продолжающий октет ведущим не является
		"\xC2",                 // Продолжающего октета недостаёт
		"\xC2\x20",             // Продолжающий октет продолжающим не является
		"\xC0\x80",             // Запись длиннее необходимого
		"\xE0\x80\x80",         // Запись длиннее необходимого
		"\xED\xA0\x80",         // Кодовая точка является суррогатом
		"\xF4\x90\x80\x80",     // Кодовая точка выходит за предел Юникода
		"\xF8\x88\x80\x80\x80", // Ведущий октет пятиоктетной записи
		"\xFE",                 // Октет, ведущим не являющийся вовсе
		"hello\xC2"             // Запись обрывается посреди кодовой точки
	};
	/**
	 * Выполняем перебор всех негодных строк
	 */
	for(const string & text : invalid)
		// Выполняем проверку отказа строке, кодировке не отвечающей
		ASSERT_FALSE(abc::utf8(reinterpret_cast <const uint8_t *> (text.data()), text.size(), position))
			<< "строка принята: " << text;
	// Выполняем проверку смещения негодной последовательности у последней строки
	ASSERT_EQ(position, 5u);
}
/**
 * @brief Проверка исправления строки, не отвечающей кодировке UTF-8
 *
 * @details Замена ведётся НАИБОЛЬШЕЙ ОСМЫСЛЕННОЙ ЧАСТЬЮ, как то предписано Юникодом
 *          (раздел 3.9): негодная последовательность заменяется ОДНИМ знаком U+FFFD,
 *          сколько бы октетов она ни заняла. Правило это не украшение: замена октета за
 *          октетом дала бы на усечённой четырёхоктетной точке три знака вместо одного,
 *          и строка, испорченная обрывом связи, обратилась бы в строку, испорченную втрое
 *
 * @note Образцы взяты из самого стандарта, а не сочинены: первый из них есть тот самый
 *       ряд, каким Юникод правило это и поясняет
 *
 */
TEST(CodecAbcEncoding, Utf8Repair){
	/**
	 * Работа исправления строки
	 *
	 * @param source исправляемые октеты строки
	 * @return       исправленные октеты строки
	 */
	auto patch = [](const vector <uint8_t> & source) noexcept -> vector <uint8_t> {
		// Исправленные октеты строки
		vector <uint8_t> result;
		// Выполняем исправление строки знаком замены
		abc::repair(source.data(), source.size(), result);
		// Выводим исправленные октеты строки
		return result;
	};
	// Октеты знака замены U+FFFD
	const vector <uint8_t> mark = {0xEF, 0xBF, 0xBD};
	/**
	 * Собирает ожидаемую строку из частей, где пустая часть означает знак замены
	 *
	 * @param parts части ожидаемой строки
	 * @return      ожидаемые октеты строки
	 */
	auto expect = [&mark](const vector <vector <uint8_t>> & parts) noexcept -> vector <uint8_t> {
		// Ожидаемые октеты строки
		vector <uint8_t> result;
		// Выполняем обход всех частей ожидаемой строки
		for(auto & part : parts)
			// Выполняем перенос части в ожидаемую строку
			result.insert(result.end(), (part.empty() ? mark.begin() : part.begin()),
			 (part.empty() ? mark.end() : part.end()));
		// Выводим ожидаемые октеты строки
		return result;
	};
	/**
	 * Строка, годная кодировке, не трогается вовсе
	 */
	{
		// Годная строка из знаков разной ширины: латиница, кириллица и знак вне плоскости
		const vector <uint8_t> source = {'a', 0xD0, 0xB1, 0xE2, 0x82, 0xAC, 0xF0, 0x9F, 0x98, 0x80};
		// Выполняем проверку того, что годная строка осталась неизменной
		ASSERT_EQ(patch(source), source);
	}
	/**
	 * Ряд из самого стандарта: три усечённые точки, годные знаки и одинокие продолжающие
	 *
	 * @details Усечённая четырёхоктетная точка `F1 80 80` есть ОДНА негодная
	 * последовательность, а не три негодных октета, и знак замены ей положен один
	 */
	{
		// Ряд образца: 61 F1 80 80 E1 80 C2 62 80 63 80 BF 64
		const vector <uint8_t> source = {
			0x61, 0xF1, 0x80, 0x80, 0xE1, 0x80, 0xC2, 0x62, 0x80, 0x63, 0x80, 0xBF, 0x64
		};
		// Выполняем проверку того, что замен вышло ровно шесть, а годные знаки уцелели
		ASSERT_EQ(patch(source), expect({{0x61}, {}, {}, {}, {0x62}, {}, {0x63}, {}, {}, {0x64}}));
	}
	/**
	 * Точка, записанная длиннее необходимого, отсеивается ведущим октетом
	 *
	 * @note Октет `C0` ведущим не является ВОВСЕ - он объявлял бы точку, какую надлежит
	 * писать одним октетом, - оттого замен здесь две, а не одна: ведущему да продолжающему
	 */
	{
		// Косая черта, писанная двумя октетами вместо одного
		const vector <uint8_t> source = {0xC0, 0xAF};
		// Выполняем проверку того, что оба октета заменены по отдельности
		ASSERT_EQ(patch(source), expect({{}, {}}));
	}
	/**
	 * Суррогат отсеивается ВТОРЫМ октетом, а не после сборки всей точки
	 *
	 * @details Ведущему `ED` положен предел продолжающего `80…9F`, а стоит за ним `A0` -
	 * и наибольшая осмысленная часть тем самым равна одному ведущему октету. Считай
	 * поверка предел общим, часть эта вышла бы длиною в три октета, и один знак замены
	 * проглотил бы два годных продолжающих
	 */
	{
		// Суррогат U+D800, кодировке недопустимый
		const vector <uint8_t> source = {0xED, 0xA0, 0x80};
		// Выполняем проверку того, что все три октета заменены по отдельности
		ASSERT_EQ(patch(source), expect({{}, {}, {}}));
	}
	/**
	 * Точка свыше предела Юникода отсеивается вторым октетом тем же порядком
	 */
	{
		// Кодовая точка U+110000, за пределом Юникода стоящая
		const vector <uint8_t> source = {0xF4, 0x90, 0x80, 0x80};
		// Выполняем проверку того, что все четыре октета заменены по отдельности
		ASSERT_EQ(patch(source), expect({{}, {}, {}, {}}));
	}
	/**
	 * Обрыв строки на середине точки даёт ОДИН знак замены
	 *
	 * @note Случай этот и есть ходовой: строка, усечённая по длине, теряет хвост точки
	 */
	{
		// Знак вне плоскости, усечённый на последнем октете
		const vector <uint8_t> source = {0xF0, 0x9F, 0x98};
		// Выполняем проверку того, что усечённая точка заменена одним знаком
		ASSERT_EQ(patch(source), expect({{}}));
	}
	/**
	 * Пустая строка исправления не требует
	 */
	{
		// Выполняем проверку того, что пустая строка осталась пустой
		ASSERT_TRUE(patch(vector <uint8_t> ()).empty());
	}
}
/**
 * @brief Проверка согласия поверки кодировки с исправлением её
 *
 * @details Поверка `utf8` и исправление `repair` суть ДВА СУДЬИ ОБ ОДНОМ ПРАВИЛЕ, и
 *          сличать их надобно перебором: описка в единственной ветви разводит их на одной
 *          лишь последовательности, а горстка образцов такую описку не поймает. Договор
 *          их прост и поверяем целиком: последовательность годна ТОГДА И ТОЛЬКО ТОГДА,
 *          когда исправление оставляет её нетронутой
 *
 * @note Расхождение здесь молчаливо вдвойне: при правиле `malformed_t::PATCH` разбор зовёт
 *       исправление, а при `REFUSE` - поверку, и разойдись они, одна и та же запись
 *       читалась бы годной одним правилом и негодной другим, без всякого отказа
 *
 * @note Перебор берёт ВСЕ одно- и двухоктетные последовательности (65 792 штуки) и пять
 *       семейств трёхоктетных по ведущему октету: `0xE0` ловит переудлинение, `0xED` -
 *       суррогаты, `0xEF` - незнаки, `0xF0` и `0xF4` - края четырёхоктетных, поданные
 *       усечёнными. Замер 01.09.2026: 86 272 последовательности, расхождений ноль
 *
 */
TEST(CodecAbcEncoding, ValidationAgreesWithRepair) {
	// Количество найденных расхождений двух судей
	size_t divergences = 0;
	/**
	 * @brief Функция сличения приговоров поверки и исправления
	 *
	 * @param sequence сличаемая последовательность октетов
	 *
	 */
	auto compare = [&divergences](const vector <uint8_t> & sequence) noexcept -> void {
		// Смещение первой негодной последовательности
		size_t position = 0;
		// Выполняем снятие приговора поверки кодировки
		const bool valid = abc::utf8(sequence.data(), sequence.size(), position);
		// Исправленная последовательность октетов
		vector <uint8_t> patched;
		// Выполняем исправление последовательности октетов
		abc::repair(sequence.data(), sequence.size(), patched);
		// Если приговоры двух судей разошлись
		if(valid != (patched == sequence))
			// Выполняем учёт найденного расхождения
			divergences++;
	};
	/**
	 * Выполняем перебор всех однооктетных последовательностей
	 */
	for(size_t first = 0; first < 256; first++)
		// Выполняем сличение приговоров об однооктетной последовательности
		compare({static_cast <uint8_t> (first)});
	/**
	 * Выполняем перебор всех двухоктетных последовательностей
	 */
	for(size_t first = 0; first < 256; first++){
		/**
		 * Выполняем перебор вторых октетов последовательности
		 */
		for(size_t second = 0; second < 256; second++)
			// Выполняем сличение приговоров о двухоктетной последовательности
			compare({static_cast <uint8_t> (first), static_cast <uint8_t> (second)});
	}
	/**
	 * Выполняем перебор семейств трёхоктетных последовательностей по ведущему октету
	 */
	for(const uint8_t lead : {0xE0, 0xED, 0xEF, 0xF0, 0xF4}){
		/**
		 * Выполняем перебор вторых октетов последовательности
		 */
		for(size_t second = 0x80; second < 0x100; second++){
			/**
			 * Выполняем перебор третьих октетов последовательности
			 */
			for(size_t third = 0x80; third < 0x100; third++)
				// Выполняем сличение приговоров о трёхоктетной последовательности
				compare({lead, static_cast <uint8_t> (second), static_cast <uint8_t> (third)});
		}
	}
	// Приговоры двух судей обязаны сходиться на всём переборе
	ASSERT_EQ(divergences, 0ul) << "расхождений найдено: " << divergences;
}
/**
 * @brief Проверка довода о совпадении порядка октетов с родным порядком машины
 *
 * @details Порядок октетов записи объявлен решением намеренным: «от младшего к старшему,
 *          и он совпадает с родным порядком у всех целевых машин, оттого перестановка на
 *          них не стоит ничего». ПОВЕДЕНИЕ этого решения закреплено давно - укладка и
 *          снятие сличаются по всему полю величин. А вот ДОВОД его - что перестановки
 *          нет ВОВСЕ, - не закреплён был ничем: круговой ход укладки со снятием переживёт
 *          и перестановку, буде она станет на обеих сторонах
 *
 * @note Проверка ведёт ДВЕ стороны разом. Первая: запись обязана быть уложена от
 *       младшего октета к старшему ВСЕГДА, каков бы ни был порядок у машины, - это
 *       договор с носителем, и он от машины не зависит. Вторая: на машине с родным
 *       порядком от младшего к старшему запись обязана совпадать с прямым переносом
 *       октетов величины, сиречь перестановки нет вовсе
 *
 * @note Порядок машины снимается ЗАМЕРОМ, а не признаком сборки: признак объявляет
 *       намерение собирателя, а замер - устройство машины. На машине от старшего к
 *       младшему проверка потребует РАСХОЖДЕНИЯ прямого переноса с записью: договор
 *       остаётся тем же, а довод про «не стоит ничего» там неверен - и обязан быть виден
 *
 */
TEST(CodecAbcEncoding, ByteOrderMatchesNativeOnTargets) {
	// Величина с различимыми октетами: всякий октет свой
	const uint64_t value = 0x0102030405060708ull;
	// Буфер уложенной величины
	vector <uint8_t> record;
	// Выполняем укладку величины восемью октетами
	abc::fixed(record, value, 8);
	// Уложенная запись обязана занять восемь октетов
	ASSERT_EQ(record.size(), 8u);
	/**
	 * Выполняем проверку укладки от МЛАДШЕГО октета к старшему: договор этот с
	 * носителем, и порядка машины он не касается вовсе
	 */
	for(size_t i = 0; i < 8; i++)
		// Очередной октет записи обязан нести соответствующий разряд величины
		EXPECT_EQ(record.at(i), static_cast <uint8_t> ((value >> (i * 8)) & 0xFF))
			<< "смещение октета: " << i;
	// Октеты величины, снятые прямым переносом из памяти машины
	vector <uint8_t> native(8, 0x00);
	// Выполняем прямой перенос октетов величины из памяти машины
	::memcpy(native.data(), &value, 8);
	// Признак того, что машина ведёт октеты от младшего к старшему
	const bool little = (native.at(0) == 0x08);
	/**
	 * Если машина ведёт октеты от младшего к старшему, довод обязан сходиться: запись
	 * совпадает с прямым переносом, и перестановки нет вовсе
	 */
	if(little)
		// Запись обязана совпадать с прямым переносом октетов величины
		EXPECT_EQ(record, native) << "порядок машины от младшего к старшему";
	/**
	 * Если же машина ведёт октеты от старшего к младшему, договор остаётся тем же, а
	 * довод про даровую перестановку на ней неверен - и обязан быть ВИДЕН расхождением
	 */
	else EXPECT_NE(record, native) << "порядок машины от старшего к младшему";
}
