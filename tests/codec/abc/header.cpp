namespace {
	/**
	 * @brief Функция извлечения объекта журнала проверок
	 *
	 * @details Журнал заводится единожды на весь набор и гасится: проверки отказов
	 *          выводили бы записью всякий свой отказ, а их тут большинство. Гашение
	 *          это - настройка журнала, а не молчание модуля: модуль доносит как
	 *          обычно, а показывать ли - решает журнал
	 *
	 * @return объект журнала проверок
	 *
	 */
	[[maybe_unused]] const log_t * logger() noexcept {
		// Объект фреймворка проверок
		static fmk_t fmk;
		// Объект журнала проверок
		static log_t log(& fmk);
		// Признак выполненной настройки журнала
		static const bool ready = [](){
			// Выполняем гашение вывода журнала проверок
			log.level(log_t::level_t::NONE);
			// Выводим признак выполненной настройки
			return true;
		}();
		// Снимаем неиспользуемый признак настройки
		(void) ready;
		// Выводим объект журнала проверок
		return & log;
	}
	/**
	 * @brief Функция сборки заголовка для проверок
	 *
	 * @return собранный заголовок опознания
	 *
	 */
	abc::header_t assemble() noexcept {
		// Собираемый заголовок опознания
		abc::header_t header;
		// Выполняем установку вида содержимого контейнера
		header.content = 0x11223344;
		// Выполняем установку длины тела контейнера
		header.length = 0x0102030405060708ull;
		// Выполняем установку количества записей в теле
		header.records = 4242;
		// Выполняем установку смещения оглавления
		header.index = 777;
		// Выполняем установку смещения подписи
		header.signature = 888;
		/**
		 * Выполняем установку признака владельца контейнера
		 */
		for(size_t i = 0; i < abc::OWNER_LENGTH; i++)
			// Выполняем установку очередного октета признака владельца
			header.owner[i] = static_cast <uint8_t> (0xA0 + i);
		/**
		 * Выполняем установку отпечатка открытого ключа
		 */
		for(size_t i = 0; i < abc::FINGERPRINT_LENGTH; i++)
			// Выполняем установку очередного октета отпечатка
			header.fingerprint[i] = static_cast <uint8_t> (0x50 + i);
		// Выполняем объявление строгого вида записи тела
		header.set(abc::flag_t::CANONICAL, true);
		// Выполняем объявление сжатия тела
		header.set(abc::flag_t::COMPRESSED, true);
		// Выводим собранный заголовок опознания
		return header;
	}
};

/**
 * @brief Проверка кругового обхода укладки заголовка
 *
 */
TEST(CodecAbcHeader, Roundtrip) {
	/**
	 * Собранный заголовок опознания
	 *
	 * @warning Длина кадра оглавления и клеймо поколения ставятся здесь ОТДЕЛЬНО, ибо
	 *          сборщик образца их не трогает и оставляет нулями. Сличай проверка нуль с
	 *          нулём - и всякая подмена, теряющая эти поля при снятии, проходила бы
	 *          незамеченной: верный ответ совпал бы с неверным по постороннему
	 *          обстоятельству
	 */
	abc::header_t header = assemble();
	// Выполняем установку длины кадра оглавления, от нуля отличной
	header.extent = 0x55667788u;
	// Выполняем установку клейма поколения, от нуля отличного
	header.generation = 0x4142434445464748ull;
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	// Выполняем проверку длины уложенного заголовка
	ASSERT_EQ(record.size(), abc::HEADER_LENGTH);
	// Снимаемый заголовок опознания
	abc::header_t restored;
	// Код отказа снятия заголовка
	abc::error_t error = abc::error_t::NONE;
	// Выполняем снятие заголовка с октетов
	ASSERT_TRUE(restored.unpack(record.data(), record.size(), error))
		<< "код отказа: " << abc::message(error);
	// Выполняем проверку старшей версии вида записи
	ASSERT_EQ(restored.version, abc::VERSION_MAJOR);
	// Выполняем проверку младшей версии вида записи
	ASSERT_EQ(restored.revision, abc::VERSION_MINOR);
	// Выполняем проверку разрядов свойств контейнера
	ASSERT_EQ(restored.flags, header.flags);
	// Выполняем проверку вида содержимого контейнера
	ASSERT_EQ(restored.content, header.content);
	// Выполняем проверку длины тела контейнера
	ASSERT_EQ(restored.length, header.length);
	// Выполняем проверку количества записей в теле
	ASSERT_EQ(restored.records, header.records);
	// Выполняем проверку смещения оглавления
	ASSERT_EQ(restored.index, header.index);
	// Выполняем проверку смещения подписи
	ASSERT_EQ(restored.signature, header.signature);
	/**
	 * Выполняем проверку сохранности длины кадра оглавления и клейма поколения
	 *
	 * @warning Поля эти сличались прежде ЛИШЬ письмом: проверка раскладки поверяет, что
	 *          они легли на свои смещения, а вот СНЯТИЕ их обратно в поля заголовка не
	 *          поверялось ничем. Подмена, снимавшая `extent` нулём, проходила стенд
	 *          целиком - 169 проверок из 169, - и ловилась одним лишь файловым слоем, в
	 *          стенд не входящим. Стенд же катается по семи системам ровно ради порядка
	 *          октетов да выравнивания, то есть ради того самого, что здесь и снимается
	 */
	ASSERT_EQ(restored.extent, header.extent);
	ASSERT_EQ(restored.generation, header.generation);
	// Выполняем проверку признака владельца контейнера
	ASSERT_EQ(::memcmp(restored.owner, header.owner, abc::OWNER_LENGTH), 0);
	// Выполняем проверку отпечатка открытого ключа
	ASSERT_EQ(::memcmp(restored.fingerprint, header.fingerprint, abc::FINGERPRINT_LENGTH), 0);
	// Выполняем проверку объявленного строгого вида записи
	ASSERT_TRUE(restored.is(abc::flag_t::CANONICAL));
	// Выполняем проверку объявленного сжатия тела
	ASSERT_TRUE(restored.is(abc::flag_t::COMPRESSED));
	// Выполняем проверку того, что шифрование не объявлено
	ASSERT_FALSE(restored.is(abc::flag_t::ENCRYPTED));
}
/**
 * @brief Проверка объявления и снятия свойств контейнера
 *
 */
TEST(CodecAbcHeader, Flags) {
	// Заголовок опознания
	abc::header_t header;
	// Выполняем проверку того, что свойств не объявлено
	ASSERT_EQ(header.flags, static_cast <uint16_t> (abc::flag_t::NONE));
	// Выполняем объявление шифрования тела
	header.set(abc::flag_t::ENCRYPTED, true);
	// Выполняем объявление подписи контейнера
	header.set(abc::flag_t::SIGNED, true);
	// Выполняем проверку объявленного шифрования тела
	ASSERT_TRUE(header.is(abc::flag_t::ENCRYPTED));
	// Выполняем проверку объявленной подписи контейнера
	ASSERT_TRUE(header.is(abc::flag_t::SIGNED));
	// Выполняем снятие объявленного шифрования тела
	header.set(abc::flag_t::ENCRYPTED, false);
	// Выполняем проверку снятого шифрования тела
	ASSERT_FALSE(header.is(abc::flag_t::ENCRYPTED));
	// Выполняем проверку того, что подпись осталась объявленной
	ASSERT_TRUE(header.is(abc::flag_t::SIGNED));
}
/**
 * @brief Проверка опознания контейнера до загрузки
 *
 */
TEST(CodecAbcHeader, Probe) {
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	// Выполняем добавление тела за заголовком
	record.insert(record.end(), {0x01, 0x02, 0x03});
	// Выполняем проверку опознания контейнера
	ASSERT_TRUE(abc::probe(record.data(), record.size()));
	// Выполняем проверку опознания по одному лишь заголовку
	ASSERT_TRUE(abc::probe(record.data(), abc::HEADER_LENGTH));
	// Выполняем проверку отказа опознания при недостаче октетов
	ASSERT_FALSE(abc::probe(record.data(), abc::HEADER_LENGTH - 1));
	// Выполняем проверку отказа опознания пустого буфера
	ASSERT_FALSE(abc::probe(nullptr, 0));
	// Буфер чужой записи
	const vector <uint8_t> foreign(abc::HEADER_LENGTH, 0x00);
	// Выполняем проверку отказа опознания чужой записи
	ASSERT_FALSE(abc::probe(foreign.data(), foreign.size()));
	// Буфер записи JSON
	const string json = "{\"кто\": \"не контейнер\", \"а\": \"текст в кодировке UTF-8\"}";
	// Выполняем проверку отказа опознания записи JSON
	ASSERT_FALSE(abc::probe(json.data(), json.size()));
}
/**
 * @brief Проверка стойкости заголовка к порче
 *
 * @details Порча любого октета заголовка обязана быть замечена: смещения из
 * повреждённого заголовка увели бы чтение в произвольное место записи
 *
 */
TEST(CodecAbcHeader, Corruption) {
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	/**
	 * Выполняем перебор всех октетов уложенного заголовка
	 */
	for(size_t i = 0; i < record.size(); i++){
		// Буфер повреждаемого заголовка
		vector <uint8_t> damaged = record;
		// Выполняем порчу очередного октета заголовка
		damaged.at(i) = static_cast <uint8_t> (damaged.at(i) ^ 0x01);
		// Снимаемый заголовок опознания
		abc::header_t restored;
		// Код отказа снятия заголовка
		abc::error_t error = abc::error_t::NONE;
		// Выполняем проверку отказа снятия повреждённого заголовка
		ASSERT_FALSE(restored.unpack(damaged.data(), damaged.size(), error)) << "испорчен октет: " << i;
		// Если испорчена опознавательная запись контейнера
		if(i < 4)
			// Выполняем проверку кода отказа опознания
			ASSERT_EQ(error, abc::error_t::INVALID_MAGIC) << "испорчен октет: " << i;
		// Выполняем проверку кода отказа контрольной суммы
		else ASSERT_EQ(error, abc::error_t::INVALID_CHECKSUM) << "испорчен октет: " << i;
		// Выполняем проверку отказа опознания повреждённого заголовка
		ASSERT_FALSE(abc::probe(damaged.data(), damaged.size())) << "испорчен октет: " << i;
	}
}
/**
 * @brief Проверка отказов снятия заголовка
 *
 */
TEST(CodecAbcHeader, Failures) {
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	// Снимаемый заголовок опознания
	abc::header_t restored;
	// Код отказа снятия заголовка
	abc::error_t error = abc::error_t::NONE;
	// Выполняем проверку отказа снятия оборванного заголовка
	ASSERT_FALSE(restored.unpack(record.data(), abc::HEADER_LENGTH - 1, error));
	// Выполняем проверку кода отказа
	ASSERT_EQ(error, abc::error_t::TRUNCATED_HEADER);
	// Выполняем проверку отказа снятия отсутствующего заголовка
	ASSERT_FALSE(restored.unpack(nullptr, abc::HEADER_LENGTH, error));
	// Выполняем проверку кода отказа
	ASSERT_EQ(error, abc::error_t::INTERNAL);
	/**
	 * Выполняем проверку отказа на неподдерживаемый вид записи
	 */
	{
		// Заголовок опознания иного вида записи
		abc::header_t future = assemble();
		// Выполняем установку старшей версии вида записи из будущего
		future.version = static_cast <uint8_t> (abc::VERSION_MAJOR + 1);
		// Буфер уложенного заголовка
		vector <uint8_t> record;
		// Выполняем укладку заголовка в октеты
		future.pack(record);
		// Выполняем проверку того, что контейнер опознаётся как наш
		ASSERT_TRUE(abc::probe(record.data(), record.size()));
		// Выполняем проверку отказа снятия заголовка иного вида записи
		ASSERT_FALSE(restored.unpack(record.data(), record.size(), error));
		// Выполняем проверку кода отказа
		ASSERT_EQ(error, abc::error_t::INVALID_VERSION);
	}
}
/**
 * @brief Проверка закрепления раскладки октетов заголовка
 *
 * @details Раскладка эта есть договор с носителем: смена её обратила бы прежние
 * контейнеры в нечитаемые, и оттого всякое её изменение обязано быть намеренным
 *
 */
TEST(CodecAbcHeader, Layout) {
	// Выполняем проверку длины заголовка опознания
	ASSERT_EQ(abc::HEADER_LENGTH, 96u);
	// Выполняем проверку длины признака владельца контейнера
	ASSERT_EQ(abc::OWNER_LENGTH, 16u);
	// Выполняем проверку длины отпечатка открытого ключа
	ASSERT_EQ(abc::FINGERPRINT_LENGTH, 16u);
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	// Выполняем проверку опознавательной записи контейнера
	ASSERT_EQ(record.at(0), 'A');
	// Выполняем проверку второго октета опознавательной записи
	ASSERT_EQ(record.at(1), 'B');
	// Выполняем проверку третьего октета опознавательной записи
	ASSERT_EQ(record.at(2), 'C');
	// Выполняем проверку четвёртого октета опознавательной записи
	ASSERT_EQ(record.at(3), 0x00);
	// Выполняем проверку места старшей версии вида записи
	ASSERT_EQ(record.at(4), abc::VERSION_MAJOR);
	// Выполняем проверку места младшей версии вида записи
	ASSERT_EQ(record.at(5), abc::VERSION_MINOR);
	// Выполняем проверку места разрядов свойств контейнера
	ASSERT_EQ(record.at(6), static_cast <uint8_t> (header.flags & 0xFF));
	// Выполняем проверку места признака владельца контейнера
	ASSERT_EQ(record.at(8), header.owner[0]);
	// Выполняем проверку места вида содержимого контейнера
	ASSERT_EQ(record.at(24), static_cast <uint8_t> (header.content & 0xFF));
	// Выполняем проверку места длины тела контейнера
	ASSERT_EQ(record.at(32), static_cast <uint8_t> (header.length & 0xFF));
	// Выполняем проверку места количества записей в теле
	ASSERT_EQ(record.at(40), static_cast <uint8_t> (header.records & 0xFF));
	// Выполняем проверку места смещения оглавления
	ASSERT_EQ(record.at(48), static_cast <uint8_t> (header.index & 0xFF));
	// Выполняем проверку места смещения подписи
	ASSERT_EQ(record.at(56), static_cast <uint8_t> (header.signature & 0xFF));
	// Выполняем проверку места отпечатка открытого ключа
	ASSERT_EQ(record.at(64), header.fingerprint[0]);
	/**
	 * Выполняем проверку того, что отведённые под будущее октеты обнулены: занять их
	 * однажды можно будет лишь тогда, когда прежние контейнеры несут в них нули
	 */
	for(size_t i = 80; i < 88; i++)
		// Выполняем проверку обнуления очередного отведённого октета
		ASSERT_EQ(record.at(i), 0x00) << "отведённый октет: " << i;
}
/**
 * @brief Проверка раскладки заголовка опознания по октетам
 *
 * @details Раскладка объявлена в «header.hpp» таблицею смещений, и объявление это есть
 *          обещание ВНЕШНЕЕ: заголовок читается прежде тела всяким, кто держит контейнер
 *          в руках, а потребитель, пишущий разбор на ином языке, иного источника не имеет
 *
 * @note Проверка заведена 01.09.2026 вместе с самой записью раскладки. Прежде раскладка
 *       жила лишь в реализации, и правка укладки разошлась бы с обещанием МОЛЧА
 *
 * @note Всякое поле сличается СВОИМ смещением, а не заголовок целиком: сличение целиком
 *       назвало бы «заголовок не тот», тогда как искать надо ПОЛЕ. Величины взяты
 *       различимыми между собою, иначе перестановка двух полей прошла бы зелёной
 */
TEST(CodecAbcHeader, WireLayout){
	/**
	 * @brief Работа снятия целого установленной ширины от младшего октета к старшему
	 *
	 * @param octets октеты уложенного заголовка
	 * @param offset смещение снимаемого поля
	 * @param width  ширина снимаемого поля в октетах
	 * @return       снятая величина поля
	 */
	auto taken = [](const vector <uint8_t> & octets, const size_t offset, const size_t width) noexcept -> uint64_t {
		// Снимаемая величина поля
		uint64_t result = 0;
		/**
		 * Выполняем перебор октетов поля от младшего к старшему
		 */
		for(size_t i = 0; i < width; i++)
			// Выполняем накопление очередного октета величины
			result |= (static_cast <uint64_t> (octets.at(offset + i)) << (8 * i));
		// Выводим снятую величину поля
		return result;
	};
	// Заголовок опознания контейнера
	abc::header_t header;
	// Выполняем установку разрядов свойств контейнера
	header.set(abc::flag_t::CANONICAL, true);
	// Выполняем установку признака шифрования содержимого
	header.set(abc::flag_t::ENCRYPTED, true);
	// Выполняем установку вида содержимого контейнера
	header.content = 0x11223344u;
	// Выполняем установку длины содержимого кадра оглавления
	header.extent = 0x55667788u;
	// Выполняем установку длины тела контейнера
	header.length = 0x0102030405060708ull;
	// Выполняем установку количества записей в теле контейнера
	header.records = 0x1112131415161718ull;
	// Выполняем установку смещения оглавления
	header.index = 0x2122232425262728ull;
	// Выполняем установку смещения подписи
	header.signature = 0x3132333435363738ull;
	// Выполняем установку поколения записи контейнера
	header.generation = 0x4142434445464748ull;
	// Буфер уложенного заголовка
	vector <uint8_t> octets;
	// Выполняем укладку заголовка в октеты
	header.pack(octets);
	// Длина уложенного заголовка обязана отвечать объявленной
	ASSERT_EQ(octets.size(), abc::HEADER_LENGTH);
	// Опознавательная запись обязана стоять первыми четырьмя октетами
	ASSERT_EQ(octets.at(0), static_cast <uint8_t> ('A'));
	// Второй октет опознавательной записи
	ASSERT_EQ(octets.at(1), static_cast <uint8_t> ('B'));
	// Третий октет опознавательной записи
	ASSERT_EQ(octets.at(2), static_cast <uint8_t> ('C'));
	// Четвёртый октет опознавательной записи
	ASSERT_EQ(octets.at(3), static_cast <uint8_t> (0x00));
	// Старшая версия вида записи обязана стоять пятым октетом
	ASSERT_EQ(octets.at(4), abc::VERSION_MAJOR);
	// Младшая версия вида записи обязана стоять шестым октетом
	ASSERT_EQ(octets.at(5), abc::VERSION_MINOR);
	// Разряды свойств контейнера обязаны стоять по смещению шесть
	ASSERT_EQ(taken(octets, 6, 2), static_cast <uint64_t> (
	 static_cast <uint16_t> (abc::flag_t::CANONICAL) | static_cast <uint16_t> (abc::flag_t::ENCRYPTED)));
	// Вид содержимого контейнера обязан стоять по смещению двадцать четыре
	ASSERT_EQ(taken(octets, 24, 4), 0x11223344ull);
	// Длина содержимого кадра оглавления обязана стоять по смещению двадцать восемь
	ASSERT_EQ(taken(octets, 28, 4), 0x55667788ull);
	// Длина тела контейнера обязана стоять по смещению тридцать два
	ASSERT_EQ(taken(octets, 32, 8), 0x0102030405060708ull);
	// Количество записей обязано стоять по смещению сорок
	ASSERT_EQ(taken(octets, 40, 8), 0x1112131415161718ull);
	// Смещение оглавления обязано стоять по смещению сорок восемь
	ASSERT_EQ(taken(octets, 48, 8), 0x2122232425262728ull);
	// Смещение подписи обязано стоять по смещению пятьдесят шесть
	ASSERT_EQ(taken(octets, 56, 8), 0x3132333435363738ull);
	// Поколение записи контейнера обязано стоять по смещению восемьдесят
	ASSERT_EQ(taken(octets, 80, 8), 0x4142434445464748ull);
	/**
	 * Свёртка обязана стоять последними восемью октетами и покрывать первые 88
	 *
	 * @note Сличается не сама величина свёртки, а ЕЁ ЗАВИСИМОСТЬ от покрываемого:
	 *       правка любого октета из первых 88 обязана менять свёртку, а сличение с
	 *       постоянной закрепило бы вдобавок и выбор самой работы свёртки
	 */
	{
		// Свёртка, снятая с уложенного заголовка
		const uint64_t digest = taken(octets, abc::HEADER_LENGTH - 8, 8);
		// Свёртка обязана быть ненулевой
		ASSERT_NE(digest, 0ull);
		// Заголовок с правленым полем
		abc::header_t altered = header;
		// Выполняем правку поколения записи контейнера
		altered.generation = (header.generation + 1);
		// Буфер уложенного правленого заголовка
		vector <uint8_t> changed;
		// Выполняем укладку правленого заголовка в октеты
		altered.pack(changed);
		// Свёртка правленого заголовка обязана разойтись с прежней
		ASSERT_NE(taken(changed, abc::HEADER_LENGTH - 8, 8), digest);
	}
}
/**
 * @brief Проверка отказа снятия заголовка с неведомыми разрядами свойств
 *
 * @details Разряды свойств контейнера объявлены `flag_t`, и занято их шесть из
 *          шестнадцати. Неведомый разряд отвечается отказом вида записи: поле приходит с
 *          провода и обязано быть опознано, а принятое молча увело бы толкование тела
 *          мимо объявленного - необъявленная зашифрованность прочлась бы сырыми октетами
 *
 * @note Требование это равняется на сличение разрядов кадра и на сличение свойств строки
 *       оглавления: у обоих оно стояло, а у заголовка контейнера не стояло вовсе
 *
 * @note Свёртка заголовка здесь пересобирается намеренно: без того отказ пришёл бы о
 *       несошедшейся свёртке, и проверка закрепляла бы свёртку, а не опознание разрядов
 *
 */
TEST(CodecAbcHeader, UnknownFlagsRefused) {
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	/**
	 * Выполняем перебор всех незанятых разрядов свойств контейнера: занято шесть
	 * младших, незанятых десять, и всякий из них обязан отвечаться отказом
	 */
	for(size_t index = 6; index < 16; index++){
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);

	// Код отказа снятия заголовка
	abc::error_t error = abc::error_t::NONE;
	// Снимаемый заголовок опознания
	abc::header_t taken;
	// Целый заголовок обязан сниматься без отказа
	ASSERT_TRUE(taken.unpack(record.data(), record.size(), error));
	/**
	 * Выполняем занятие незанятого разряда свойств контейнера.
	 *
	 * @note Перебор идёт ОБОИМИ октетами поля намеренно: незанятые разряды есть и в
	 *       младшем октете (`0x0040`, `0x0080`), и во всём старшем. Проба на одном
	 *       октете ничего не сказала бы о другом - сторож, писанный по старшему,
	 *       прошёл бы её зелёным
	 */
	record.at(6 + (index / 8)) = static_cast <uint8_t> (record.at(6 + (index / 8)) | (1u << (index % 8)));
	/**
	 * Выполняем пересборку свёртки заголовка по объявленному правилу: свёртка кроет
	 * первые восемьдесят восемь октетов с зерном своим, а сама в них не входит
	 */
	const uint64_t checksum = hashing::generate(record.data(), abc::HEADER_LENGTH - 8, 0x4142433130303031ull);
	/**
	 * Выполняем укладку пересобранной свёртки на её место
	 */
	for(size_t i = 0; i < 8; i++)
		// Выполняем укладку очередного октета свёртки от младшего к старшему
		record.at((abc::HEADER_LENGTH - 8) + i) = static_cast <uint8_t> ((checksum >> (i * 8)) & 0xFF);
	/**
	 * Заголовок, каким поверяется нетронутость отвергнутого: величины его заведомо
	 * иные, нежели у уложенного, и всякое снятое поле было бы видно
	 */
	abc::header_t untouched;
	// Выполняем установку различимой младшей версии вида записи
	untouched.revision = 0xEE;
	// Выполняем установку различимых разрядов свойств контейнера
	untouched.flags = static_cast <uint16_t> (abc::flag_t::PAGED);
	// Неведомый разряд свойств обязан отвечаться отказом вида записи
	EXPECT_FALSE(untouched.unpack(record.data(), record.size(), error)) << "разряд: " << index;
	// Отказ обязан быть именно о виде записи, а не о свёртке
	EXPECT_EQ(error, abc::error_t::INVALID_VERSION) << "разряд: " << index;
	/**
	 * Заголовок, отвергнутый на полпути, обязан остаться нетронутым целиком:
	 * поле, снятое до отказа, выдало бы отвергнутое за принятое
	 */
	EXPECT_EQ(untouched.revision, 0xEE) << "разряд: " << index;
	// Разряды свойств контейнера обязаны остаться прежними
	EXPECT_EQ(untouched.flags, static_cast <uint16_t> (abc::flag_t::PAGED)) << "разряд: " << index;
	}
}
/**
 * @brief Проверка того, что быстрое опознание не обещает удачного снятия
 *
 * @details Опознание судит о двух вещах - опознавательной записи и свёртке, - а снятие
 *          сличает пять, и расхождение это НАМЕРЕННО: чужое поколение надобно опознать
 *          прежде, чем объявить о нём. Проверка закрепляет обе стороны разом: опознание
 *          отвечает истиной там, где снятие отвечает отказом
 *
 * @note Проверка эта стережёт СБЛИЖЕНИЕ двух посредников, судящих об одном: доведи
 *       опознание до полноты снятия - и оно перестанет опознавать чужое поколение;
 *       ослабь снятие до двух сличений - и вернутся дефекты, ради коих сторожа стоят
 *
 */
TEST(CodecAbcHeader, ProbeDoesNotPromiseUnpack) {
	// Собранный заголовок опознания
	const abc::header_t header = assemble();
	// Буфер уложенного заголовка
	vector <uint8_t> record;
	// Выполняем укладку заголовка в октеты
	header.pack(record);
	// Целый заголовок обязан опознаваться контейнером
	ASSERT_TRUE(abc::probe(record.data(), record.size()));
	// Выполняем занятие незанятого разряда свойств контейнера
	record.at(7) = static_cast <uint8_t> (record.at(7) | 0x80);
	// Выполняем пересборку свёртки заголовка по объявленному правилу
	const uint64_t checksum = hashing::generate(record.data(), abc::HEADER_LENGTH - 8, 0x4142433130303031ull);
	/**
	 * Выполняем укладку пересобранной свёртки на её место
	 */
	for(size_t i = 0; i < 8; i++)
		// Выполняем укладку очередного октета свёртки от младшего к старшему
		record.at((abc::HEADER_LENGTH - 8) + i) = static_cast <uint8_t> ((checksum >> (i * 8)) & 0xFF);
	// Опознание обязано отвечать истиной: запись и свёртка сошлись
	ASSERT_TRUE(abc::probe(record.data(), record.size()));
	// Код отказа снятия заголовка
	abc::error_t error = abc::error_t::NONE;
	// Снимаемый заголовок опознания
	abc::header_t taken;
	// Снятие же обязано отвечать отказом: разряды свойств несут неведомое
	ASSERT_FALSE(taken.unpack(record.data(), record.size(), error));
	// Отказ обязан быть именно о виде записи
	ASSERT_EQ(error, abc::error_t::INVALID_VERSION);
	// Выполняем подмену старшей версии вида записи на заведомо чужую
	record.at(4) = static_cast <uint8_t> (abc::VERSION_MAJOR + 1);
	// Выполняем пересборку свёртки заголовка по правленой версии
	const uint64_t next = hashing::generate(record.data(), abc::HEADER_LENGTH - 8, 0x4142433130303031ull);
	/**
	 * Выполняем укладку пересобранной свёртки на её место
	 */
	for(size_t i = 0; i < 8; i++)
		// Выполняем укладку очередного октета свёртки от младшего к старшему
		record.at((abc::HEADER_LENGTH - 8) + i) = static_cast <uint8_t> ((next >> (i * 8)) & 0xFF);
	// Чужое поколение обязано опознаваться контейнером, иначе объявить о нём нечем
	ASSERT_TRUE(abc::probe(record.data(), record.size()));
	// Снятие же обязано отвечать отказом вида записи
	ASSERT_FALSE(taken.unpack(record.data(), record.size(), error));
	// Отказ обязан быть именно о виде записи
	ASSERT_EQ(error, abc::error_t::INVALID_VERSION);
}
/**
 * @brief Проверка отказа снятия заголовка со смещениями внутри самого заголовка
 *
 * @details Ноль у смещений оглавления и подписи означает отсутствие, и годится он
 *          признаком по доводу: заголовок занимает первые `HEADER_LENGTH` октетов, и
 *          меньшим смещение быть не может. Довод этот поверялся НИЧЕМ, а поле приходит с
 *          провода: объявленное смещение внутри заголовка уводило бы чтение кадра на сам
 *          заголовок
 *
 * @note Проверки, стоящие в наборе выше, сличают место подписи С НУЛЁМ - «объявлено ли».
 *       Сличение это переживает всякое смещение от единицы и выше, сиречь ровно ту
 *       невозможную величину, ради какой довод и написан
 *
 * @note Случаи перебираются столбцами: оглавление, подпись и оба разом, а следом - края
 *       годные: ноль у обоих и ровно `HEADER_LENGTH` у обоих. Без последних сторож мог бы
 *       обернуться отказом на отсутствие подписи
 *
 */
TEST(CodecAbcHeader, OffsetsInsideHeaderRefused) {
	/**
	 * @brief Функция сборки заголовка с заданными смещениями и пересобранной свёрткой
	 *
	 * @param index     смещение оглавления
	 * @param signature смещение подписи
	 * @return          собранные октеты заголовка
	 *
	 */
	auto assembled = [](const uint64_t index, const uint64_t signature) noexcept -> vector <uint8_t> {
		// Собранный заголовок опознания
		abc::header_t header = assemble();
		// Выполняем установку смещения оглавления
		header.index = index;
		// Выполняем установку смещения подписи
		header.signature = signature;
		// Буфер уложенного заголовка
		vector <uint8_t> result;
		// Выполняем укладку заголовка в октеты
		header.pack(result);
		// Выводим собранные октеты заголовка
		return result;
	};
	/**
	 * @brief Структура поверяемого случая смещений заголовка
	 *
	 */
	struct probe_t {
		// Смещение оглавления
		uint64_t index;
		// Смещение подписи
		uint64_t signature;
		// Признак того, что заголовок обязан сниматься без отказа
		bool accept;
		// Имя поверяемого случая
		const char * name;
	};
	// Перечень поверяемых случаев смещений заголовка
	const vector <probe_t> probes = {
		{0, 0, true, "1: оба смещения объявлены отсутствующими"},
		{abc::HEADER_LENGTH, abc::HEADER_LENGTH, true, "2: оба смещения стоят сразу за заголовком"},
		{1, 0, false, "3: оглавление объявлено внутри заголовка"},
		{0, 1, false, "4: подпись объявлена внутри заголовка"},
		{abc::HEADER_LENGTH - 1, 0, false, "5: оглавление на октет внутри заголовка"},
		{0, abc::HEADER_LENGTH - 1, false, "6: подпись на октет внутри заголовка"},
		{1, 1, false, "7: оба смещения внутри заголовка"}
	};
	/**
	 * Выполняем перебор поверяемых случаев смещений заголовка
	 */
	for(auto & probe : probes){
		// Собранные октеты заголовка
		const vector <uint8_t> record = assembled(probe.index, probe.signature);
		// Код отказа снятия заголовка
		abc::error_t error = abc::error_t::NONE;
		// Снимаемый заголовок опознания
		abc::header_t taken;
		// Заголовок обязан сниматься согласно годности объявленных смещений
		EXPECT_EQ(taken.unpack(record.data(), record.size(), error), probe.accept) << probe.name;
		/**
		 * Если заголовок обязан отвечаться отказом
		 *
		 * @note Скобки обязательны, а не украшают: утверждение развёртывается в `if` со
		 *       своим `else`, и без скобок он повисает на этом условии. Нынешнему коду
		 *       вреда нет, но `else`, дописанный сюда потом, привяжется НЕ К ЭТОМУ `if`.
		 *       Ловится собирателем GNU (`-Wdangling-else`), собиратель clang молчит
		 */
		if(!probe.accept){
			// Отказ обязан быть именно о виде записи
			EXPECT_EQ(error, abc::error_t::INVALID_VERSION) << probe.name;
		}
	}
}
