		ASSERT_TRUE(document.parse(record.data(), record.size()))
			<< "вид: " << static_cast <uint16_t> (kind)
			<< ", код отказа: " << abc::message(document.error());
		/**
		 * Выполняем укладку значения ВНУТРИ отображения
		 *
		 * @details Поверка эта и есть довод: узел, уложить какой нечем, губит не себя, а
		 * всё дерево, - и увидеть это можно лишь тогда, когда он лежит не корнем
		 */
