/**
 * @brief Проверка сборки значения из ничего и кругового обхода записи
 *
 */
TEST(CodecAbcValue, BuildAndRoundtrip) {
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем заведение поля строки
	value["имя"] = abc::value_t("Юрий");
	// Выполняем заведение поля числа
	value["лет"] = abc::value_t(static_cast <uint64_t> (42));
	// Выполняем заведение поля логического значения
	value["годен"] = abc::value_t(true);
	// Выполняем заведение поля перечня
	value["метки"].push(abc::value_t("первая"));
	// Выполняем добавление второго значения перечня
	value["метки"].push(abc::value_t("вторая"));
	// Выполняем проверку вида собранного значения
	ASSERT_EQ(value.type(), abc::type_t::MAP);
	// Выполняем проверку количества полей собранного значения
	ASSERT_EQ(value.size(), 4u);
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value["метки"].size(), 2u);
	// Выполняем сборку записи из владеющего значения
	const vector <uint8_t> record = value.dump();
	// Выполняем проверку того, что запись собрана
	ASSERT_FALSE(record.empty());
	// Значение, разобранное из собранной записи
	abc::value_t restored;
	// Выполняем разбор собранной записи во владеющее значение
	ASSERT_TRUE(restored.parse(record.data(), record.size()));
	// Выполняем проверку равенства разобранного значения собранному
	ASSERT_EQ(restored, value);
	// Выполняем проверку содержимого поля строки
	ASSERT_EQ(restored["имя"].text(), "Юрий");
	// Извлекаемое целое без знака
	uint64_t number = 0;
	// Выполняем извлечение поля числа
	ASSERT_TRUE(restored["лет"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 42u);
}
