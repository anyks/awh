/**
 * @brief Проверка потоковой сборки владеющего значения
 *
 * @details Сборка ведёт вместилища сама, и потребителю не нужно ни обходить дерево, ни
 *          держать ссылок на вложенные значения. Договор здесь тот же, что у сборок
 *          прочих кодеков
 *
 */
TEST(CodecAbcValue, BuilderAssembly) {
	// Потоковая сборка владеющего значения
	abc::builder_t builder;
	// Выполняем открытие корневого отображения
	ASSERT_TRUE(builder.map());
	// Выполняем проверку глубины открытых вместилищ
	ASSERT_EQ(builder.depth(), 1u);
	// Выполняем запись строкового поля отображения
	ASSERT_TRUE(builder.key("имя") && builder.value(string("Юрий")));
	// Выполняем запись целого поля отображения
	ASSERT_TRUE(builder.key("лет") && builder.value(static_cast <uint64_t> (42)));
	// Выполняем запись пустого поля отображения
	ASSERT_TRUE(builder.key("примечание") && builder.nul());
	// Выполняем открытие вложенного перечня значений
	ASSERT_TRUE(builder.key("метки") && builder.array());
	// Выполняем проверку глубины открытых вместилищ
	ASSERT_EQ(builder.depth(), 2u);
	// Выполняем запись значений перечня
	ASSERT_TRUE(builder.value(string("один")) && builder.value(string("два")));
	// Выполняем закрытие перечня значений
	ASSERT_TRUE(builder.close());
	// Выполняем закрытие корневого отображения
	ASSERT_TRUE(builder.close());
	// Выполняем изъятие собранного значения
	const abc::value_t value = builder.finish();
	// Выполняем проверку количества полей собранного отображения
	ASSERT_EQ(value.size(), 4u);
	// Выполняем проверку содержимого строкового поля
	ASSERT_EQ(value["имя"].text(), "Юрий");
	// Извлекаемое целое без знака
	uint64_t number = 0;
	// Выполняем извлечение целого поля
	ASSERT_TRUE(value["лет"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 42u);
	// Выполняем проверку вида пустого поля
	ASSERT_TRUE(value["примечание"].is(abc::type_t::NUL));
	// Выполняем проверку количества значений вложенного перечня
	ASSERT_EQ(value["метки"].size(), 2u);
	// Выполняем проверку содержимого вложенного перечня
	ASSERT_EQ(value["метки"][static_cast <size_t> (1)].text(), "два");
	// Выполняем проверку того, что сборка сброшена изъятием
	ASSERT_EQ(builder.depth(), 0u);
}
/**
 * @brief Проверка отказов потоковой сборки
 *
 * @details Отказы здесь намеренные, и всякий стережёт свою беду: имя без значения
 *          теряется молча при закрытии вместилища, значение без имени в отображении
 *          встало бы полем без имени, а имя до открытия корня класть некуда вовсе
 *
 */
TEST(CodecAbcValue, BuilderRefusals) {
	// Потоковая сборка владеющего значения
	abc::builder_t builder;
	/**
	 * Выполняем проверку отказа назначения имени до открытия вместилища
	 *
	 * @note Запись значения до открытия вместилища отказом БОЛЕЕ НЕ отвечает: одиночное
	 *       значение вправе стоять корнем записи, и случай этот проверяется отдельно
	 *       проверкой `BuilderScalarRoot`
	 */
	ASSERT_FALSE(builder.key("имя"));
	// Выполняем проверку отказа закрытия неоткрытого вместилища
	ASSERT_FALSE(builder.close());
	// Выполняем открытие корневого отображения
	ASSERT_TRUE(builder.map());
	// Выполняем проверку отказа записи значения без имени в отображении
	ASSERT_FALSE(builder.value(static_cast <uint64_t> (1)));
	// Выполняем проверку отказа назначения пустого имени
	ASSERT_FALSE(builder.key(""));
	// Выполняем назначение имени поля отображения
	ASSERT_TRUE(builder.key("имя"));
	// Выполняем проверку отказа повторного назначения имени
	ASSERT_FALSE(builder.key("другое"));
	// Выполняем проверку отказа закрытия вместилища на незавершённой паре
	ASSERT_FALSE(builder.close());
	// Выполняем запись значения назначенному имени
	ASSERT_TRUE(builder.value(string("Юрий")));
	// Выполняем закрытие корневого отображения
	ASSERT_TRUE(builder.close());
	// Выполняем проверку отказа записи в завершённую сборку
	ASSERT_FALSE(builder.value(static_cast <uint64_t> (1)));
	// Выполняем проверку отказа открытия вместилища в завершённой сборке
	ASSERT_FALSE(builder.map());
	// Выполняем изъятие собранного значения
	const abc::value_t value = builder.finish();
	// Выполняем проверку того, что собрано лишь завершённое
	ASSERT_EQ(value.size(), 1u);
	ASSERT_EQ(value["имя"].text(), "Юрий");
}
/**
 * @brief Проверка имени поля отображения любого вида
 *
 * @details Запись ABC дозволяет именем поля всякое НЕВМЕСТИМОЕ значение, и владеющее
 * значение вместе с потоковой сборкой обязаны выражать то же, что кодек читает и пишет:
 * иначе разобранную запись нельзя было бы собрать наново
 *
 */
TEST(CodecAbcValue, NonStringKeys) {
	// Владеющее значение отображения
	abc::value_t value;
	// Выполняем заведение поля с целым именем
	ASSERT_TRUE(value.insert(abc::value_t(static_cast <uint64_t> (42)), abc::value_t(string{"сорок два"})));
	// Выполняем заведение поля с логическим именем
	ASSERT_TRUE(value.insert(abc::value_t(true), abc::value_t(string{"истина"})));
	// Выполняем заведение поля со строковым именем
	ASSERT_TRUE(value.insert("строка", abc::value_t(string{"значение"})));
	// Выполняем проверку количества полей отображения
	ASSERT_EQ(value.size(), 3ul);
	/**
	 * Выполняем проверку отказа заведения поля с вместимым именем: розыск по такому
	 * имени требовал бы сличения поддеревьев
	 */
	abc::value_t holder;
	// Выполняем заведение вместимого значения массивом
	(void) holder.push(abc::value_t(string{"звено"}));
	// Выполняем проверку отказа заведения поля с вместимым именем
	ASSERT_FALSE(value.insert(holder, abc::value_t(string{"нельзя"})));
	// Выполняем проверку того, что отказ поля не завёл
	ASSERT_EQ(value.size(), 3ul);
	/**
	 * Выполняем проверку перезаписи занятого имени: сличение идёт значением, а не
	 * видом хранения, и `UINT8(42)` обязано найти заведённое как `UINT64(42)`
	 */
	ASSERT_TRUE(value.insert(abc::value_t(static_cast <uint64_t> (42)), abc::value_t(string{"иное"})));
	// Выполняем проверку того, что перезапись поля не завела
	ASSERT_EQ(value.size(), 3ul);
	// Октеты записи отображения
	const vector <uint8_t> buffer = value.dump();
	// Выполняем проверку того, что запись отображения вышла
	ASSERT_FALSE(buffer.empty());
	// Владеющее значение, разобранное из записи
	abc::value_t parsed;
	// Выполняем разбор записи отображения
	ASSERT_TRUE(parsed.parse(buffer.data(), buffer.size()));
	// Выполняем проверку того, что круговой ход записи сошёлся
	ASSERT_EQ(parsed, value);
	// Потоковая сборка значения
	abc::builder_t builder;
	// Выполняем заведение отображения потоковой сборкой
	ASSERT_TRUE(builder.map());
	/**
	 * Выполняем перебор всех полей разобранного отображения
	 */
	for(size_t i = 0; i < parsed.size(); i++){
		// Выполняем назначение имени очередного поля отображения
		ASSERT_TRUE(builder.key(parsed.key(i)));
		// Выполняем запись значения очередного поля отображения
		ASSERT_TRUE(builder.value(parsed[i]));
	}
	// Выполняем закрытие отображения потоковой сборкой
	ASSERT_TRUE(builder.close());
	/**
	 * Выполняем проверку того, что потоковая сборка выразила разобранное целиком:
	 * без имени любого вида часть записей ей была бы недоступна
	 */
	ASSERT_EQ(builder.finish(), parsed);
	// Потоковая сборка с вместимым именем поля
	abc::builder_t refused;
	// Выполняем заведение отображения потоковой сборкой
	ASSERT_TRUE(refused.map());
	// Выполняем проверку отказа назначения вместимого имени поля
	ASSERT_FALSE(refused.key(holder));
	// Выполняем проверку отказа назначения несуществующего имени поля
	ASSERT_FALSE(refused.key(static_cast <const char *> (nullptr)));
	// Выполняем проверку отказа назначения пустого имени поля
	ASSERT_FALSE(refused.key(string{}));
}

/**
 * @brief Проверка указателя поиска поля отображения по имени
 *
 * @details Указатель заводится по превышении `INDEX_THRESHOLD` полей и ведётся
 *          приращением. Проверка стережёт не скорость, а СОГЛАСОВАННОСТЬ: поле,
 *          заведённое после указателя, обязано разыскиваться, а удаление обязано
 *          сносить указатель целиком - номера всех полей после удалённого сдвигаются,
 *          и уцелевший указатель отдавал бы соседнее значение
 *
 */
TEST(CodecAbcValue, NameIndexConsistency) {
	// Количество полей отображения, заведомо превышающее порог заведения указателя
	const size_t count = (static_cast <size_t> (awh::codec::abc::INDEX_THRESHOLD) * 4);
	// Собираемое владеющее значение
	abc::value_t value;
	/**
	 * Выполняем сборку отображения
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем установку очередного поля отображения
		value["поле" + to_string(i)] = abc::value_t(static_cast <uint64_t> (i));
	// Извлекаемое целое без знака
	uint64_t number = 0;
	/**
	 * Выполняем перебор всех полей отображения
	 */
	for(size_t i = 0; i < count; i++){
		// Выполняем извлечение очередного поля отображения
		ASSERT_TRUE(value["поле" + to_string(i)].value(number)) << "поле " << i << " не разыскано";
		// Выполняем проверку того, что имени досталось его собственное значение
		ASSERT_EQ(number, i);
	}
	// Выполняем заведение поля ПОСЛЕ того, как указатель заведён поиском
	value["добавленное"] = abc::value_t(static_cast <uint64_t> (777));
	// Выполняем проверку того, что заведённое поле разыскивается
	ASSERT_TRUE(value.contains("добавленное"));
	// Выполняем извлечение заведённого поля
	ASSERT_TRUE(value["добавленное"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 777u);
	// Выполняем удаление поля из середины отображения
	ASSERT_TRUE(value.erase("поле0"));
	// Выполняем проверку того, что удалённое поле более не разыскивается
	ASSERT_FALSE(value.contains("поле0"));
	/**
	 * Выполняем перебор всех уцелевших полей отображения
	 */
	for(size_t i = 1; i < count; i++){
		// Выполняем извлечение очередного поля отображения
		ASSERT_TRUE(value["поле" + to_string(i)].value(number)) << "поле " << i << " потеряно удалением";
		// Выполняем проверку того, что значение осталось своим
		ASSERT_EQ(number, i);
	}
	// Выполняем проверку сохранности поля, заведённого после указателя
	ASSERT_TRUE(value["добавленное"].value(number));
	ASSERT_EQ(number, 777u);
	// Копия собранного отображения
	const abc::value_t copy = value;
	// Выполняем проверку того, что копия разыскивает поля своим указателем
	ASSERT_TRUE(copy["поле5"].value(number));
	ASSERT_EQ(number, 5u);
	// Выполняем проверку того, что удалённого поля нет и у копии
	ASSERT_FALSE(copy.contains("поле0"));
}
/**
 * @brief Проверка переноса владеющего значения в дерево документа
 *
 * @details Перенос закрепляется КРУГОВЫМ ходом: значение переносится в дерево, дерево
 * поднимается обратно в значение и сличается с исходным. Проверка эта у соседних
 * кодеков сразу вскрывала неверную укладку, и договор у ABC общий с ними
 *
 */
TEST(CodecAbcValue, GraftRoundTrip) {
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем установку строкового поля отображения
	value["строка"] = abc::value_t(string{"текст"});
	// Выполняем установку целого поля отображения
	value["целое"] = abc::value_t(static_cast <uint64_t> (42));
	// Выполняем установку дробного поля отображения
	value["дробное"] = abc::value_t(1.5);
	// Выполняем установку логического поля отображения
	value["признак"] = abc::value_t(true);
	// Собираемый перечень значений
	abc::value_t list;
	/**
	 * Выполняем сборку перечня значений
	 */
	for(uint64_t i = 0; i < 4; i++)
		// Выполняем долив очередного значения перечня
		ASSERT_TRUE(list.push(abc::value_t(i)));
	// Выполняем установку перечня полем отображения
	value["перечень"] = list;
	// Выполняем установку поля с именем любого вида
	ASSERT_TRUE(value.insert(abc::value_t(static_cast <uint64_t> (7)), abc::value_t(string{"семь"})));
	// Дерево документа, куда переносится значение
	abc::document_t document;
	// Выполняем перенос владеющего значения в дерево документа
	ASSERT_TRUE(value.graft(document)) << "код отказа: " << abc::message(document.error());
	// Выполняем подъём дерева документа обратно во владеющее значение
	const abc::value_t raised(document.root());
	/**
	 * Выполняем проверку того, что круговой ход сошёлся: перенос обязан сохранить
	 * значение целиком, включая имя поля невместимого вида
	 */
	ASSERT_EQ(raised, value);
	/**
	 * Выполняем проверку того, что перенос ЗАМЕНЯЕТ дерево, а не доливает к нему
	 */
	abc::value_t other;
	// Выполняем установку единственного поля второго значения
	other["иное"] = abc::value_t(string{"значение"});
	// Выполняем перенос второго значения в то же дерево документа
	ASSERT_TRUE(other.graft(document)) << "код отказа: " << abc::message(document.error());
	// Выполняем подъём дерева документа обратно во владеющее значение
	const abc::value_t second(document.root());
	// Выполняем проверку того, что дерево несёт второе значение целиком
	ASSERT_EQ(second, other);
	// Выполняем проверку того, что от первого значения в дереве не осталось ничего
	ASSERT_EQ(second.size(), 1ul);
	/**
	 * Выполняем проверку переноса пустого значения.
	 *
	 * Отказом он не отвечается: неопределённое значение укладывается записью, а
	 * запись эта есть законный документ - договор общий с прочими кодеками
	 */
	abc::value_t empty;
	// Дерево документа, куда переносится пустое значение
	abc::document_t plain;
	// Выполняем перенос пустого значения в дерево документа
	ASSERT_TRUE(empty.graft(plain)) << "код отказа: " << abc::message(plain.error());
	// Выполняем подъём дерева документа обратно во владеющее значение
	const abc::value_t nothing(plain.root());
	/**
	 * Выполняем проверку того, что неопределённое значение обратилось ПУСТЫМ.
	 *
	 * Круговой ход здесь сходится не тождеством: неопределённости в проволочной
	 * записи нет вовсе, и уложить её нечем. Укладка обращает её в пустое значение,
	 * и обращение это односторонне - оговорено намеренно, дабы не искали дефекта
	 */
	ASSERT_TRUE(nothing.is(abc::type_t::NUL));
	// Выполняем проверку того, что исходное значение осталось неопределённым
	ASSERT_FALSE(empty.valid());
}
/**
 * @brief Проверка перезаполнения указателя имён полей отображения
 *
 * @details Проверка согласованности, наполняющая вместилище ОДИН раз, сломанного
 * сброса указателя не ловит: у второго наполнения имена ложатся по тем же положениям,
 * и устаревший указатель отвечает верно по случаю. Ловится оно лишь тогда, когда
 * второй круг идёт именами ДРУГИМИ и поверяются обе стороны: новые обязаны
 * разыскиваться, а старые обязаны НЕ разыскиваться
 *
 * @note Довод этот выведен соседней сессией на кодеках TOML, INI и YAML; заход у
 * ABC тот же, оттого проверка заведена и здесь
 *
 */
TEST(CodecAbcValue, NameIndexRefill) {
	// Количество полей отображения, заведомо превышающее порог заведения указателя
	const size_t count = (static_cast <size_t> (awh::codec::abc::INDEX_THRESHOLD) * 4);
	// Собираемое владеющее значение
	abc::value_t value;
	/**
	 * Выполняем сборку отображения первыми именами
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем установку очередного поля отображения
		value["первое" + to_string(i)] = abc::value_t(static_cast <uint64_t> (i));
	// Извлекаемое целое без знака
	uint64_t number = 0;
	/**
	 * Выполняем розыск всех первых имён: розыск и заводит указатель
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем извлечение очередного поля отображения
		ASSERT_TRUE(value["первое" + to_string(i)].value(number)) << "поле " << i << " не разыскано";
	// Выполняем очистку отображения вместе с указателем имён
	value.clear();
	/**
	 * Выполняем сборку отображения ДРУГИМИ именами, тем же числом и по тем же местам
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем установку очередного поля отображения
		value["второе" + to_string(i)] = abc::value_t(static_cast <uint64_t> (i * 2));
	/**
	 * Выполняем поверку обеих сторон: новые имена обязаны разыскиваться со своими
	 * значениями, старые - не разыскиваться вовсе
	 */
	for(size_t i = 0; i < count; i++){
		// Выполняем извлечение очередного поля отображения
		ASSERT_TRUE(value["второе" + to_string(i)].value(number)) << "новое поле " << i << " не разыскано";
		// Выполняем проверку того, что имени досталось его собственное значение
		ASSERT_EQ(number, (i * 2)) << "новому полю " << i << " досталось чужое значение";
		// Выполняем проверку того, что старое имя более не разыскивается
		ASSERT_FALSE(value.contains("первое" + to_string(i))) << "старое поле " << i << " уцелело в указателе";
	}
	// Выполняем проверку количества полей отображения
	ASSERT_EQ(value.size(), count);
}

/**
 * @brief Проверка одиночного значения корнем потоковой сборки
 *
 * @details Корнем записи одиночное значение стоять вправе: проволочная запись такова, и
 *          разбор её принимает, и `parse` собирает из неё значение одиночное. Сборка же
 *          корень одиночный прежде отвергала, отчего расходилась с разбирателем на
 *          записи, какую тот считает законной
 *
 */
TEST(CodecAbcValue, BuilderScalarRoot) {
	// Потоковая сборка владеющего значения
	abc::builder_t builder;
	// Выполняем запись одиночного значения корнем сборки
	ASSERT_TRUE(builder.value(string("одиночное")));
	// Выполняем проверку отказа записи второго значения: корень одиночный вместить не может
	ASSERT_FALSE(builder.value(static_cast <uint64_t> (1)));
	// Выполняем проверку отказа открытия вместилища в завершённой сборке
	ASSERT_FALSE(builder.map());
	// Выполняем изъятие собранного значения
	const abc::value_t value = builder.finish();
	// Выполняем проверку вида собранного значения
	ASSERT_TRUE(value.is(abc::type_t::STRING));
	// Выполняем проверку содержимого собранного значения
	ASSERT_EQ(value.text(), string("одиночное"));
	// Октеты записи, собранной из одиночного корня
	const vector <uint8_t> record = value.dump();
	// Выполняем проверку того, что запись собралась
	ASSERT_FALSE(record.empty());
	// Значение, собранное разбором записи
	abc::value_t parsed;
	/**
	 * Выполняем проверку того, что разбиратель запись эту принимает: расхождение сборки
	 * с разбирателем и было тем недосмотром, ради какого проверка заведена
	 */
	ASSERT_TRUE(parsed.parse(record.data(), record.size()));
	// Выполняем проверку равенства разобранного собранному
	ASSERT_EQ(parsed, value);
	// Потоковая сборка с назначенным именем до открытия вместилища
	abc::builder_t named;
	// Выполняем проверку отказа назначения имени до открытия вместилища
	ASSERT_FALSE(named.key("имя"));
	// Выполняем проверку того, что одиночный корень после этого записывается
	ASSERT_TRUE(named.value(static_cast <uint64_t> (42)));
}
