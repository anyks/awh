/**
 * @brief Проверка приведения дробного значения к целому виду при извлечении
 *
 * @details Договор извлечения общий у кодеков рамки: `NaN` даёт нуль, число за пределами
 * затребованного вида даёт предел, а дробная часть округляется по правилам математики с
 * уводом половины ОТ НУЛЯ. Проверка закрепляет договор у ABC, чьё владеющее значение
 * прежде отвечало на такое извлечение отказом
 *
 * @note Проверка эта нужна оттого, что ABC не участвует в наборе `CodecContract`, где
 *       договор сличается у пяти прочих кодеков: запись там подаётся текстом, а у ABC
 *       она двоичная
 *
 */
TEST(CodecAbcValue, RealToWholeContract) {
	// Извлекаемое целое со знаком
	int64_t signedValue = 0;
	// Извлекаемое целое без знака
	uint64_t unsignedValue = 0;
	/**
	 * Выполняем проверку округления половины с уводом от нуля
	 */
	{
		// Значение с дробной частью
		const abc::value_t value(1.5);
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(value.value(signedValue));
		// Выполняем проверку округления половины вверх
		ASSERT_EQ(signedValue, 2);
		// Значение с дробной частью, меньшее нуля
		const abc::value_t negative(-1.5);
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(negative.value(signedValue));
		// Выполняем проверку округления половины вниз
		ASSERT_EQ(signedValue, -2);
		// Значение с дробной частью ниже половины
		const abc::value_t lower(1.4);
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(lower.value(signedValue));
		// Выполняем проверку округления к ближайшему
		ASSERT_EQ(signedValue, 1);
	}
	/**
	 * Выполняем проверку выдачи нуля для значения, числом не являющегося
	 */
	{
		// Значение, числом не являющееся
		const abc::value_t value(numeric_limits <double>::quiet_NaN());
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(value.value(signedValue));
		// Выполняем проверку выдачи нуля
		ASSERT_EQ(signedValue, 0);
	}
	/**
	 * Выполняем проверку выдачи предела для значения вне отрезка вида
	 */
	{
		// Значение выше предела вида
		const abc::value_t above(1e300);
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(above.value(signedValue));
		// Выполняем проверку выдачи верхнего предела вида
		ASSERT_EQ(signedValue, numeric_limits <int64_t>::max());
		// Значение ниже предела вида
		const abc::value_t below(-1e300);
		// Выполняем проверку извлечения значения видом целого
		ASSERT_TRUE(below.value(signedValue));
		// Выполняем проверку выдачи нижнего предела вида
		ASSERT_EQ(signedValue, numeric_limits <int64_t>::lowest());
		// Выполняем проверку извлечения значения ниже нуля видом без знака
		ASSERT_TRUE(below.value(unsignedValue));
		// Выполняем проверку выдачи нижнего предела вида без знака
		ASSERT_EQ(unsignedValue, 0u);
	}
	/**
	 * Выполняем проверку переноса целого младшими разрядами
	 */
	{
		// Наибольшее целое без знака
		const abc::value_t natural(numeric_limits <uint64_t>::max());
		// Выполняем проверку извлечения значения видом со знаком
		ASSERT_TRUE(natural.value(signedValue));
		// Выполняем проверку переноса младшими разрядами
		ASSERT_EQ(signedValue, -1);
		// Отрицательное целое
		const abc::value_t negative(static_cast <int64_t> (-1));
		// Выполняем проверку извлечения значения видом без знака
		ASSERT_TRUE(negative.value(unsignedValue));
		// Выполняем проверку переноса младшими разрядами
		ASSERT_EQ(unsignedValue, numeric_limits <uint64_t>::max());
	}
	/**
	 * Выполняем проверку того, что нечисло числом всё же не считается
	 */
	{
		// Значение строкой
		const abc::value_t value(string("не число"));
		// Выполняем проверку отказа извлечения строки видом целого
		ASSERT_FALSE(value.value(signedValue));
	}
}

/**
 * @brief Проверка стойкости снятия значения к усечению и порче записи
 *
 * @details Владеющее значение заводит память по объявленному размеру вместимого, и
 *          запись, объявляющая тысячи значений при считанных октетах содержимого, была
 *          бы способом исчерпать память подачей двух десятков октетов. Проверка
 *          закрепляет, что объявленный размер держится содержимым: усечённая запись
 *          отвергается вся, а порча одного октета вместимое сверх записи не растит
 *
 */
TEST(CodecAbcValue, TruncationAndCorruption) {
	// Сборка образцовой записи
	abc::writer_t writer(::logger());
	// Выполняем сборку записи отображения
	ASSERT_TRUE(writer.mapBegin(static_cast <uint64_t> (2)));
	ASSERT_TRUE(writer.text("имя") && writer.text("Юрий"));
	ASSERT_TRUE(writer.text("лет") && writer.number(static_cast <uint64_t> (42)));
	ASSERT_TRUE(writer.mapEnd());
	// Собранная образцовая запись
	const vector <uint8_t> record(writer.record().begin(), writer.record().end());
	// Выполняем проверку того, что образцовая запись собрана
	ASSERT_FALSE(record.empty());
	/**
	 * Выполняем разбор всякого начального куска записи
	 */
	for(size_t i = 0; i < record.size(); i++){
		// Снимаемое владеющее значение
		abc::value_t value;
		// Выполняем проверку отказа разбора усечённой записи
		ASSERT_FALSE(value.parse(record.data(), i)) << "усечение до " << i << " октетов принято";
	}
	// Наибольший объявленный размер вместимого, встреченный при порче
	size_t largest = 0;
	/**
	 * Выполняем перебор всех октетов записи
	 */
	for(size_t i = 0; i < record.size(); i++){
		/**
		 * Выполняем перебор всех значений очередного октета
		 */
		for(size_t b = 0; b < 256; b++){
			// Порченая запись
			vector <uint8_t> copy = record;
			// Выполняем порчу очередного октета записи
			copy.at(i) = static_cast <uint8_t> (b);
			// Снимаемое владеющее значение
			abc::value_t value;
			// Если разбор порченой записи отвечен отказом, переходим к следующей
			if(!value.parse(copy.data(), copy.size()))
				continue;
			// Запоминаем наибольший объявленный размер вместимого
			largest = (value.size() > largest ? value.size() : largest);
		}
	}
	// Выполняем проверку того, что объявленный размер держится содержимым записи
	ASSERT_LE(largest, record.size());
	// Выполняем проверку того, что образцовая запись разбирается целой
	abc::value_t value;
	ASSERT_TRUE(value.parse(record.data(), record.size()));
	ASSERT_EQ(value.size(), 2u);
}

/**
 * @brief Проверка удаления значения вместимого по номеру
 *
 * @details Имена полей отображения держатся перечнем, стоящим рядом с перечнем
 *          значений, и удаление по номеру обязано снимать оба разом. Снятие одного
 *          лишь значения сдвинуло бы имена на единицу и отдавало бы соседнее имя всякому
 *          полю после удалённого - беда, по выдаче неотличимая от исправной работы
 *
 */
TEST(CodecAbcValue, EraseByIndex) {
	// Собираемое владеющее значение
	abc::value_t value;
	/**
	 * Выполняем сборку отображения
	 */
	for(size_t i = 0; i < 4; i++)
		// Выполняем установку очередного поля отображения
		value["поле" + to_string(i)] = abc::value_t(static_cast <uint64_t> (i));
	// Выполняем проверку количества полей отображения
	ASSERT_EQ(value.size(), 4u);
	// Выполняем удаление второго поля отображения по номеру
	ASSERT_TRUE(value.erase(static_cast <size_t> (1)));
	// Выполняем проверку количества полей после удаления
	ASSERT_EQ(value.size(), 3u);
	// Выполняем проверку того, что имена сдвинулись вместе со значениями
	ASSERT_EQ(value.key(0).text(), "поле0");
	ASSERT_EQ(value.key(1).text(), "поле2");
	ASSERT_EQ(value.key(2).text(), "поле3");
	// Извлекаемое целое без знака
	uint64_t number = 0;
	// Выполняем извлечение значения, вставшего на место удалённого
	ASSERT_TRUE(value["поле2"].value(number));
	// Выполняем проверку того, что имени досталось его собственное значение
	ASSERT_EQ(number, 2u);
	// Выполняем проверку отказа удаления за границей вместимого
	ASSERT_FALSE(value.erase(static_cast <size_t> (3)));
	// Выполняем проверку того, что удалённого поля не осталось
	ASSERT_FALSE(value.contains("поле1"));
}
