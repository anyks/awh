/**
 * @brief Проверка обращения по пути
 *
 */
TEST(CodecAbcValue, Paths) {
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем заведение значения по пути
	value.place("/дом/комнаты/0/имя") = abc::value_t("кухня");
	// Выполняем заведение второго значения по пути
	value.place("/дом/комнаты/1/имя") = abc::value_t("спальня");
	// Выполняем проверку количества комнат
	ASSERT_EQ(value.at("/дом/комнаты").size(), 2u);
	// Выполняем проверку содержимого первой комнаты
	ASSERT_EQ(value.at("/дом/комнаты/0/имя").text(), "кухня");
	// Выполняем проверку содержимого второй комнаты
	ASSERT_EQ(value.at("/дом/комнаты/1/имя").text(), "спальня");
	// Выполняем проверку недействительности пути, какого нет
	ASSERT_FALSE(value.at("/дом/этажи").valid());
	// Выполняем проверку недействительности номера, какого нет
	ASSERT_FALSE(value.at("/дом/комнаты/9").valid());
}
/**
 * @brief Проверка разбора звена пути на номер значения
 *
 * @details Запись номера, переполняющая счёт, отвергается целиком и становится именем
 * поля. Приведение её к пределу выдало бы значение с иным номером: путь на `2^64 + 1`
 * заворачивался бы в единицу, и обращение молча отдавало бы чужое значение
 *
 */
TEST(CodecAbcValue, IndexOverflow) {
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем заведение перечня из двух значений
	value.place("/список/0") = abc::value_t(static_cast <uint64_t> (10));
	// Выполняем заведение второго значения перечня
	value.place("/список/1") = abc::value_t(static_cast <uint64_t> (20));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value.at("/список").size(), 2u);
	// Выполняем заведение значения по пути, счёт переполняющему
	value.place("/18446744073709551617") = abc::value_t(static_cast <uint64_t> (99));
	// Выполняем проверку того, что переполняющая запись стала именем поля
	ASSERT_TRUE(value.contains("18446744073709551617"));
	// Выполняем проверку того, что перечень не подменён
	ASSERT_EQ(value.at("/список").size(), 2u);
	// Извлекаемое целое без знака
	uint64_t number = 0;
	// Выполняем проверку того, что первое значение перечня не подменено
	ASSERT_TRUE(value.at("/список/0").value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 10u);
	/**
	 * Выполняем проверку правила ведущего нуля: запись с ним номером не является,
	 * а является именем поля, иначе `01` и `1` означали бы одно и то же
	 */
	value.place("/01") = abc::value_t(static_cast <uint64_t> (7));
	// Выполняем проверку того, что запись с ведущим нулём стала именем поля
	ASSERT_TRUE(value.contains("01"));
}
/**
 * @brief Проверка предела роста вместимого обращением по номеру
 *
 * @details Номер приходит извне, и вместимое затребованной длины съело бы память
 * целиком. Предел ограждает один лишь рост по номеру, а не разбор записи
 *
 */
TEST(CodecAbcValue, GrowthLimit) {
	// Выполняем получение прежнего предела роста вместимого
	const size_t previous = abc::value_t::limit();
	// Выполняем установку предела роста вместимого
	abc::value_t::limit(16);
	// Выполняем проверку установленного предела
	ASSERT_EQ(abc::value_t::limit(), 16u);
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем заведение значения в пределах допустимого
	value[static_cast <size_t> (15)] = abc::value_t(static_cast <uint64_t> (1));
	// Выполняем проверку количества заведённых значений
	ASSERT_EQ(value.size(), 16u);
	// Выполняем обращение по номеру, предел превышающему
	value[static_cast <size_t> (1000000)] = abc::value_t(static_cast <uint64_t> (2));
	// Выполняем проверку того, что вместимое не выросло
	ASSERT_EQ(value.size(), 16u);
	// Выполняем проверку того, что предел не мешает добавлению в конец
	ASSERT_TRUE(value.push(abc::value_t(static_cast <uint64_t> (3))));
	// Выполняем проверку количества значений после добавления в конец
	ASSERT_EQ(value.size(), 17u);
	// Выполняем снятие предела роста вместимого
	abc::value_t::limit(0);
	// Собираемое без предела значение
	abc::value_t free;
	// Выполняем заведение значения по номеру, прежний предел превышающему
	free[static_cast <size_t> (99)] = abc::value_t(static_cast <uint64_t> (4));
	// Выполняем проверку количества заведённых значений
	ASSERT_EQ(free.size(), 100u);
	// Выполняем возврат прежнего предела роста вместимого
	abc::value_t::limit(previous);
	// Выполняем проверку возвращённого предела
	ASSERT_EQ(abc::value_t::limit(), previous);
}
/**
 * @brief Проверка сличения значений
 *
 * @details Сличение отображений порядка полей не учитывает, а сличение перечней -
 * учитывает
 *
 */
TEST(CodecAbcValue, Comparison) {
	// Первое сличаемое отображение
	abc::value_t first;
	// Выполняем заведение полей первого отображения
	first["а"] = abc::value_t(static_cast <uint64_t> (1));
	// Выполняем заведение второго поля первого отображения
	first["б"] = abc::value_t(static_cast <uint64_t> (2));
	// Второе сличаемое отображение
	abc::value_t second;
	// Выполняем заведение полей второго отображения в обратном порядке
	second["б"] = abc::value_t(static_cast <uint64_t> (2));
	// Выполняем заведение второго поля второго отображения
	second["а"] = abc::value_t(static_cast <uint64_t> (1));
	// Выполняем проверку равенства отображений с разным порядком полей
	ASSERT_EQ(first, second);
	// Выполняем изменение значения поля второго отображения
	second["а"] = abc::value_t(static_cast <uint64_t> (9));
	// Выполняем проверку неравенства отображений с разными значениями
	ASSERT_NE(first, second);
	// Первый сличаемый перечень
	abc::value_t list;
	// Выполняем заведение значений первого перечня
	list.push(abc::value_t(static_cast <uint64_t> (1)));
	// Выполняем заведение второго значения первого перечня
	list.push(abc::value_t(static_cast <uint64_t> (2)));
	// Второй сличаемый перечень
	abc::value_t reversed;
	// Выполняем заведение значений второго перечня в обратном порядке
	reversed.push(abc::value_t(static_cast <uint64_t> (2)));
	// Выполняем заведение второго значения второго перечня
	reversed.push(abc::value_t(static_cast <uint64_t> (1)));
	// Выполняем проверку неравенства перечней с разным порядком значений
	ASSERT_NE(list, reversed);
	// Выполняем проверку неравенства значений разных видов
	ASSERT_NE(first, list);
}
/**
 * @brief Проверка перезаписи занятого имени на прежнем его месте
 *
 * @details Перенос поля в конец менял бы порядок записи, а порядок этот у ABC есть
 * часть её: строгий вид записи ведёт имена по возрастанию
 *
 */
TEST(CodecAbcValue, InsertKeepsOrder) {
	// Собираемое владеющее значение
	abc::value_t value;
	// Выполняем заведение первого поля отображения
	ASSERT_TRUE(value.insert("первое", abc::value_t(static_cast <uint64_t> (1))));
	// Выполняем заведение второго поля отображения
	ASSERT_TRUE(value.insert("второе", abc::value_t(static_cast <uint64_t> (2))));
	// Выполняем заведение третьего поля отображения
	ASSERT_TRUE(value.insert("третье", abc::value_t(static_cast <uint64_t> (3))));
	// Выполняем перезапись занятого имени поля отображения
	ASSERT_TRUE(value.insert("первое", abc::value_t(static_cast <uint64_t> (9))));
	// Выполняем проверку количества полей отображения
	ASSERT_EQ(value.size(), 3u);
	// Выполняем проверку того, что перезаписанное имя осталось на прежнем месте
	ASSERT_EQ(value.key(0).text(), "первое");
	// Выполняем проверку того, что порядок прочих полей сохранён
	ASSERT_EQ(value.key(2).text(), "третье");
	// Извлекаемое целое без знака
	uint64_t number = 0;
	// Выполняем извлечение перезаписанного значения
	ASSERT_TRUE(value["первое"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 9u);
	// Выполняем удаление поля отображения по имени
	ASSERT_TRUE(value.erase("второе"));
	// Выполняем проверку количества полей после удаления
	ASSERT_EQ(value.size(), 2u);
	// Выполняем проверку того, что имя удалённого поля снято вместе со значением
	ASSERT_EQ(value.key(1).text(), "третье");
}
/**
 * @brief Проверка разрушения глубокого дерева без возвратности
 *
 * @details Значение, собранное вручную, предела глубины не имеет вовсе. Возвратное
 * разрушение сорвало бы стек уже на десятках тысяч уровней, и падение это пришлось бы
 * не на сборку дерева, а на выход из работы
 *
 */
TEST(CodecAbcValue, DeepTeardown) {
	// Глубина собираемого дерева
	const size_t depth = 40000;
	// Собираемое владеющее значение
	abc::value_t value;
	// Обходимое значение собираемого дерева
	abc::value_t * current = &value;
	/**
	 * Выполняем сборку глубокого дерева
	 */
	for(size_t i = 0; i < depth; i++){
		// Выполняем заведение вложенного значения
		ASSERT_TRUE(current->push(abc::value_t()));
		// Выполняем переход к заведённому вложенному значению
		current = &(* current)[static_cast <size_t> (0)];
	}
	// Выполняем проверку количества значений корня дерева
	ASSERT_EQ(value.size(), 1u);
	// Выполняем очистку собранного дерева
	value.clear();
	// Выполняем проверку того, что дерево очищено
	ASSERT_EQ(value.size(), 0u);
	// Выполняем проверку недействительности очищенного значения
	ASSERT_FALSE(value.valid());
}
/**
 * @brief Проверка перенесения значения из дерева документа
 *
 */
TEST(CodecAbcValue, AbsorbFromDocument) {
	// Октеты величины числа
	const vector <uint8_t> magnitude = {0x39, 0x30, 0x01};
	// Сборщик бинарной записи
	abc::writer_t writer;
	// Выполняем укладку отображения из двух пар
	ASSERT_TRUE(writer.mapBegin(2));
	// Выполняем укладку имени поля числа неограниченной ширины
	ASSERT_TRUE(writer.text("большое"));
	// Выполняем укладку числа неограниченной ширины
	ASSERT_TRUE(writer.bignum(magnitude.data(), magnitude.size(), true));
	// Выполняем укладку имени поля отметки времени
	ASSERT_TRUE(writer.text("время"));
	// Выполняем укладку отметки времени
	ASSERT_TRUE(writer.timestamp(1755500000));
	// Выполняем укладку конца отображения
	ASSERT_TRUE(writer.mapEnd());
	// Дерево документа
	abc::document_t document;
	// Выполняем разбор записи в дерево документа
	ASSERT_TRUE(document.parse(writer.record().data(), writer.record().size()));
	// Владеющее значение, перенесённое из дерева документа
	const abc::value_t value(document.root());
	// Выполняем проверку количества полей перенесённого значения
	ASSERT_EQ(value.size(), 2u);
	// Выполняем проверку вида поля числа неограниченной ширины
	ASSERT_EQ(value["большое"].type(), abc::type_t::EXTENDED);
	// Выполняем проверку признака отрицательности величины
	ASSERT_TRUE(value["большое"].negative());
	// Выполняем проверку длины октетов величины
	ASSERT_EQ(value["большое"].text().size(), magnitude.size());
	// Извлекаемая отметка времени
	int64_t stamp = 0;
	// Выполняем извлечение отметки времени
	ASSERT_TRUE(value["время"].value(stamp));
	// Выполняем проверку извлечённой отметки времени
	ASSERT_EQ(stamp, 1755500000);
	// Выполняем сборку записи из перенесённого значения
	const vector <uint8_t> record = value.dump();
	// Выполняем проверку совпадения собранной записи с исходной
	ASSERT_EQ(record, writer.record());
}
/**
 * @brief Проверка сличения чисел разных видов хранения
 *
 * @details Вид хранения при пересборке записи сужается, и сличение по нему объявляло бы
 * равные числа разными. Сличается значение, а не вид хранения
 *
 */
TEST(CodecAbcValue, NumericComparison) {
	// Выполняем проверку равенства целых разной знаковости
	ASSERT_EQ(abc::value_t(static_cast <uint64_t> (42)), abc::value_t(static_cast <int64_t> (42)));
	// Выполняем проверку равенства целого и дробного одного значения
	ASSERT_EQ(abc::value_t(static_cast <uint64_t> (2)), abc::value_t(2.0));
	// Выполняем проверку неравенства целого и дробного разных значений
	ASSERT_NE(abc::value_t(static_cast <uint64_t> (2)), abc::value_t(2.5));
	// Выполняем проверку неравенства отрицательного числа и наибольшего беззнакового
	ASSERT_NE(abc::value_t(static_cast <int64_t> (-1)), abc::value_t(numeric_limits <uint64_t>::max()));
	// Выполняем проверку неравенства числа и строки
	ASSERT_NE(abc::value_t(static_cast <uint64_t> (1)), abc::value_t("1"));
	// Выполняем проверку неравенства логического значения и числа
	ASSERT_NE(abc::value_t(true), abc::value_t(static_cast <uint64_t> (1)));
}

/**
 * @brief Проверка равенства нечисла самому себе
 *
 * @details Нечисло само себе не равно по правилу арифметики, но правило это о
 *          вычислениях, а не о тождестве записи: значение обязано быть равно самому себе,
 *          иначе круговой ход записи недоказуем вовсе
 *
 */
TEST(CodecAbcValue, NotANumberEquality) {
	// Значение, несущее нечисло
	abc::value_t value(numeric_limits <double>::quiet_NaN());
	// Выполняем проверку равенства нечисла самому себе
	ASSERT_TRUE(value == value);
	// Выполняем перезапись значения
	const vector <uint8_t> record = value.dump();
	// Значение, собранное из перезаписи
	abc::value_t repeated;
	// Выполняем разбор перезаписи
	ASSERT_TRUE(repeated.parse(record.data(), record.size()));
	// Выполняем проверку кругового хода записи нечисла
	ASSERT_TRUE(repeated == value);
	// Значение, несущее бесконечность
	abc::value_t infinity(numeric_limits <double>::infinity());
	/**
	 * Выполняем проверку того, что нечисло с бесконечностью не сошлись: равенство
	 * записей не означает равенства всякой пары величин
	 */
	ASSERT_FALSE(infinity == value);
}
