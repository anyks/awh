/**
 * @brief Проверка звена пути числового
 *
 * @details Звено числовое обращением неизменяемым недостающего НЕ ЗАВОДИТ, тогда как
 * обращением изменяемым перечень растёт до затребованного номера. Довод у правила
 * свой: перечень с дырою перечнем не является, и рост дыру заполняет, а чтение
 * заводить значение по недостающему номеру не вправе вовсе
 *
 * @note Звено числовое ходит по номеру лишь у перечня: у отображения вид вместилища
 *       решает раньше вида записи, и поле числовое разыскивается именем своим
 *
 */
TEST(CodecYamlValue, NumericLink) {
	// Собираемое значение перечня
	yaml::value_t value;
	// Выполняем занесение значений перечня
	value.push(yaml::value_t("первое"));
	// Выполняем занесение значений перечня
	value.push(yaml::value_t("второе"));
	// Получаем неизменяемую ссылку на собранное значение
	const yaml::value_t & taken = value;
	// Выполняем проверку разыскания значения по номеру звеном числовым
	ASSERT_STREQ(taken.at("/1").text().c_str(), "второе");
	// Выполняем проверку отказа разыскания значения за пределом перечня
	ASSERT_FALSE(taken.at("/5").valid());
	// Выполняем проверку того, что чтение перечня не нарастило
	ASSERT_EQ(taken.size(), 2u);
	/**
	 * Выполняем проверку роста перечня обращением изменяемым
	 *
	 * @note Здесь правило обратное намеренно: запись по номеру заведение значения
	 *       и означает, а дыры заполняются значениями пустыми
	 */
	value[4] = yaml::value_t("пятое");
	// Выполняем проверку роста перечня до затребованного номера
	ASSERT_EQ(value.size(), 5u);
	// Выполняем проверку того, что дыра заполнена значением пустым
	ASSERT_FALSE(value[3].valid());
	/**
	 * Выполняем проверку разыскания поля числового у отображения пар
	 *
	 * @note Вид вместилища решает раньше вида записи: у отображения звено числовое
	 *       именем поля является, а не номером значения
	 */
	yaml::value_t mapping;
	// Выполняем занесение поля с именем числовым
	mapping["2"] = yaml::value_t("поле");
	// Получаем неизменяемую ссылку на собранное отображение
	const yaml::value_t & named = mapping;
	// Выполняем проверку разыскания поля числового именем его
	ASSERT_STREQ(named.at("/2").text().c_str(), "поле");
	// Выполняем проверку того, что чтение отображения не нарастило
	ASSERT_EQ(named.size(), 1u);
	/**
	 * Выполняем проверку звена числового у пути заводящего
	 *
	 * @note Путь заводящий звеном числовым перечень заводит и наращивает, тогда как
	 *       путь разыскивающий того не делает вовсе: разница здесь та же, что между
	 *       обращением изменяемым и неизменяемым, и она намеренна
	 */
	yaml::value_t placed;
	// Выполняем заведение значения путём числовым
	placed.place("/список/2") = yaml::value_t("третье");
	// Выполняем проверку заведения перечня звеном числовым
	ASSERT_EQ(placed["список"].size(), 3u);
	// Выполняем проверку заведённого значения
	ASSERT_STREQ(placed.at("/список/2").text().c_str(), "третье");
	// Выполняем проверку того, что дыры заполнены значениями пустыми
	ASSERT_FALSE(placed.at("/список/0").valid());
	/**
	 * Выполняем проверку записи дерева, дыры несущего
	 *
	 * @details Заполнение дыр значением пустым тем и оправдано, что записи такое дерево
	 * подлежит целиком: пустое есть законное значение YAML и записывается пустотою за
	 * знаком двоеточия. Дерево, записи не подлежащее, отвечало бы пустою выдачей, а
	 * отличить её от отказа записи потребителю нечем
	 *
	 * @note Замечание это пришло от сессии кодека XML, где заведённые ростом узлы вида
	 *       не имели и всё дерево записи не подлежало молча
	 *
	 */
	// Собранный текст дерева, дыры несущего
	const string text = placed.dump();
	// Выполняем проверку того, что дерево записи подлежит
	ASSERT_FALSE(text.empty());
	// Выполняем проверку того, что заведённое значение записано
	ASSERT_NE(text.find("третье"), string::npos);
	// Выполняем проверку записи перечня, дыры несущего
	ASSERT_TRUE(value.dump().find("пятое") != string::npos);
	/**
	 * Выполняем проверку кругового хода дерева, дыры несущего
	 *
	 * @note Записываемость дерева ещё не значит годности записанного: дыра пишется
	 *       одним лишь чёрточным знаком, и разбор обязан вернуть перечень той же
	 *       длины, а не короче. Свойства эти разные, и второе ломается там, где
	 *       первое держится
	 *
	 * @warning Круговой ход дыру не сохраняет, а обращает её значением пустым, и это
	 *          неизбежно: дыра означает «значения нет вовсе», а описание языка такого
	 *          написания не имеет - чёрточный знак без содержимого есть значение
	 *          пустое, и разбор читает его верно. Расхождение это законно и стоит
	 *          здесь закреплённым нарочно, чтобы его не приняли впредь за потерю
	 */
	yaml::value_t circle;
	// Выполняем разбор собранного текста обратно в значение
	ASSERT_TRUE(circle.parse(value.dump()));
	// Выполняем проверку длины перечня, круговым ходом полученного
	ASSERT_EQ(circle.size(), value.size());
	// Выполняем проверку того, что дыра круговым ходом удержана пустою
	ASSERT_TRUE(circle[3].is(yaml::type_t::NUL));
	// Выполняем проверку того, что значение круговым ходом удержано
	ASSERT_STREQ(circle[4].text().c_str(), "пятое");
}
/**
 * @brief Проверка предела роста вместилища обращением по номеру
 *
 * @details Номер, пришедший извне, обращается требованием памяти по нему, и предел этот
 * рост стережёт. Ставится он пользователем рамки, а нуль снимает его вовсе: сколько
 * памяти есть у приложения, ведомо ему одному
 *
 * @note Пришло это находкою сессии владеющих значений JSON и XML, проверенной затем у себя
 *
 */
TEST(CodecYamlValue, GrowthLimit) {
	/**
	 * Выполняем проверку того, что номер за пределом разрядности номером не является
	 *
	 * @details Разбор беззнаковый заворачивается переполнением: запись
	 * `18446744073709551617` обращалась бы единицей, и обращение по такому пути отдавало
	 * бы соседнее значение молча. Ныне запись такая разыскивается именем поля
	 */
	yaml::value_t wrapped;
	// Выполняем обращение по пути с номером за пределом разрядности
	wrapped.place("/18446744073709551617") = yaml::value_t("завёрнутое");
	// Выполняем проверку того, что заведено отображение, а не перечень
	ASSERT_EQ(wrapped.kind(), yaml::kind_t::MAPPING);
	// Выполняем проверку того, что запись легла именем поля
	ASSERT_EQ(wrapped.at("/18446744073709551617").text(), "завёрнутое");
	/**
	 * Выполняем проверку предела по умолчанию
	 */
	ASSERT_EQ(yaml::value_t::limit(), 0x10000);
	// Объект значения, растимого за пределом
	yaml::value_t beyond;
	// Выполняем обращение по номеру за поставленным пределом
	beyond.place("/100000") = yaml::value_t("за пределом");
	// Выполняем проверку того, что вместилище не выросло вовсе
	ASSERT_EQ(beyond.size(), 0);
	/**
	 * Выполняем проверку роста в пределах дозволенного
	 */
	yaml::value_t within;
	// Выполняем обращение по номеру в пределах дозволенного
	within.place("/10") = yaml::value_t("в пределах");
	// Выполняем проверку выросшего вместилища
	ASSERT_EQ(within.size(), 11);
	// Выполняем проверку поставленного значения
	ASSERT_EQ(within[static_cast <size_t> (10)].text(), "в пределах");
	/**
	 * Выполняем проверку снятия предела пользователем
	 */
	yaml::value_t::limit(0);
	// Объект значения, растимого без предела
	yaml::value_t unbounded;
	// Выполняем обращение по номеру при снятом пределе
	unbounded.place("/100000") = yaml::value_t("предел снят");
	// Выполняем проверку выросшего вместилища
	ASSERT_EQ(unbounded.size(), 100001);
	/**
	 * Выполняем возврат предела к значению по умолчанию
	 *
	 * @note Предел хранится переменной процесса, и проверка, его сменившая, обязана
	 *       вернуть прежний: соседка иначе получила бы чужую настройку
	 */
	yaml::value_t::limit(0x10000);
	// Выполняем проверку возвращённого предела
	ASSERT_EQ(yaml::value_t::limit(), 0x10000);
}

