/**
 * @brief Проверка отказа записи и переноса значения свыше предела вложенности
 *
 */
TEST(CodecYamlValue, DepthBeyondLimitRefused) {
	// Собираемое значение, предел вложенности превышающее
	yaml::value_t node("лист");
	/**
	 * Выполняем наращивание вложенности собираемого значения
	 *
	 * @note Значение собирается снизу вверх, а не путём: разбор пути свою поверку
	 *       вложенности ведёт и до записи такое значение не допустил бы вовсе
	 */
	for(size_t i = 0; i < static_cast <size_t> (yaml::MAX_DEPTH) + 8; i++){
		// Заводимое вместилище очередного уровня вложенности
		yaml::value_t holder;
		// Выполняем занесение собранного значения во вместилище
		holder["у"] = node;
		// Запоминаем вместилище собранным значением
		node = holder;
	}
	// Выполняем проверку отказа записи значения свыше предела вложенности
	ASSERT_TRUE(node.dump().empty());
	// Объект дерева настроек, куда ведётся перенос
	yaml::document_t document(::logger());
	// Выполняем проверку отказа переноса значения свыше предела вложенности
	ASSERT_FALSE(node.graft(document, {}));
	/**
	 * Выполняем проверку отказа записи и переноса перечня свыше предела вложенности
	 *
	 * @note Заход этот стоит рядом нарочно: перечень значений открывается своим вызовом,
	 *       отдельным от отображения пар, и порча одного из двух осталась бы незамечена
	 */
	{
		// Собираемый перечень, предел вложенности превышающий
		yaml::value_t item("лист");
		/**
		 * Выполняем наращивание вложенности собираемого перечня
		 */
		for(size_t i = 0; i < static_cast <size_t> (yaml::MAX_DEPTH) + 8; i++){
			// Заводимый перечень очередного уровня вложенности
			yaml::value_t holder(yaml::kind_t::SEQUENCE);
			// Выполняем дописывание собранного значения к перечню
			holder.push(item);
			// Запоминаем перечень собранным значением
			item = holder;
		}
		// Выполняем проверку отказа записи перечня свыше предела вложенности
		ASSERT_TRUE(item.dump().empty());
		// Объект дерева настроек, куда ведётся перенос
		yaml::document_t document(::logger());
		// Выполняем проверку отказа переноса перечня свыше предела вложенности
		ASSERT_FALSE(item.graft(document, {}));
	}
}
