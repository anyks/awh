/**
 * @brief Проверка обращения к паре по имени, знаком записанному
 *
 * @details Написание знака есть ТЕКСТ, а не число: обращение `value['z']` прежде
 * уходило к номеру 122 МОЛЧА - доведение знака до числа языком дозволено, а до
 * строки требует заводителя, - и потребитель получал бы пустоту вместо значения,
 * отказа не видя вовсе. Различие с `value["z"]` было в одну кавычку
 *
 * @warning Обращение по номеру голому проверяется здесь же: оператор знака без
 *          ограды на ТОЧНОЕ совпадение делает `value[0]` двусмысленным - доведение
 *          `int` до `size_t` и до `char` суть приведения одного разряда. Правка,
 *          одну двусмысленность снимающая, вводила бы другую, худшую
 *
 */
TEST(CodecYamlValue, CharNameIsText) {
	// Значение с парою таблицы
	yaml::value_t value(yaml::kind_t::MAPPING);
	// Запоминаем пару таблицы, именем из одного знака названную
	value["z"] = static_cast <int64_t> (42);
	// Получаем постоянную ссылку на значение
	const yaml::value_t & fixed = value;
	// Выполняем проверку обращения к паре по имени строкою
	ASSERT_EQ(fixed["z"].kind(), yaml::kind_t::NUMBER);
	// Выполняем проверку обращения к паре по имени знаком
	ASSERT_EQ(fixed['z'].kind(), yaml::kind_t::NUMBER);
	// Полученное целое число значения
	int64_t number = 0;
	// Выполняем получение целого числа значения по имени знаком
	ASSERT_TRUE(fixed['z'].value(number));
	// Выполняем проверку полученного целого числа значения
	ASSERT_EQ(number, static_cast <int64_t> (42));
	// Выполняем заведение пары по имени знаком
	value['y'] = static_cast <int64_t> (7);
	// Выполняем проверку того, что заведена пара, а не значение по номеру
	ASSERT_EQ(fixed["y"].kind(), yaml::kind_t::NUMBER);
	// Перечень значений
	yaml::value_t list(yaml::kind_t::SEQUENCE);
	// Выполняем дописывание значения перечня
	ASSERT_TRUE(list.push(yaml::value_t(static_cast <int64_t> (7))));
	// Получаем постоянную ссылку на перечень значений
	const yaml::value_t & fixedList = list;
	/**
	 * Выполняем проверку обращения по номеру, голым числом записанному
	 *
	 * @note Заход этот стоит рядом нарочно: оператор знака без ограды делал бы это
	 *       обращение двусмысленным, и сборка валилась бы у потребителя, а не здесь
	 */
	ASSERT_EQ(fixedList[0].kind(), yaml::kind_t::NUMBER);
	// Выполняем проверку обращения по номеру, размером записанному
	ASSERT_EQ(fixedList[static_cast <size_t> (0)].kind(), yaml::kind_t::NUMBER);
}
/**
 * @brief Проверка снятия владеющего значения со ссылки на узел дерева
 *
 * @details Снятие берёт ссылку на узел дерева, а ссылка вправе оказаться недействительной:
 * дерево, перестроенное разбором поверх, прежние ссылки обрывает клеймом поколения. Снятие
 * с такой ссылки обязано отдать значение пустое, а не содержимое узла чужого
 *
 * @warning Закрепляются ОБЕ половины договора: снятие с ссылки годной отдаёт содержимое,
 *          а с оборванной - пустоту. Одна лишь вторая половина проходила бы и при вовсе
 *          неработающем снятии - пустоту оно отдавало бы всегда. Поправка эта пришла от
 *          соседнего кодека, где проверка сперва завелась одною половиной
 *
 * @note Заход этот стал достижим лишь с заведением клейма поколения: прежде оборванная
 *       ссылка отвечала действительностью и подменялась чужим узлом молча
 *
 * @warning Проверка стережёт ДОГОВОР СНАРУЖИ, а не сторож внутри снятия: сам сторож
 *          `if(!value.valid()) return;` есть застава - свойства ссылки отвергают
 *          недействительную у себя, и снятие с подорванным сторожем всё равно отдаёт
 *          пустоту. Замерено срывом: с заходом снесённым проверка не падает
 *
 */
TEST(CodecYamlValue, AbsorbFromStaleReference) {
	// Объект дерева документа
	yaml::document_t doc(::logger());
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse("первый: значение\nвторой: иное\n"));
	// Снимаем ссылку на узел дерева
	const yaml::document_t::value_t node = doc.root().at("/первый");
	// Выполняем проверку того, что ссылка действительна
	ASSERT_TRUE(node.valid());
	/**
	 * Выполняем проверку снятия значения со ссылки годной
	 */
	{
		// Собираемое владеющее значение, ссылкою заводимое
		const yaml::value_t value(node);
		// Выполняем проверку вида снятого значения
		ASSERT_EQ(value.kind(), yaml::kind_t::STRING);
		// Полученное содержимое снятого значения
		string text;
		// Выполняем получение содержимого снятого значения
		ASSERT_TRUE(value.value(text));
		// Выполняем проверку содержимого снятого значения
		ASSERT_EQ(text, "значение");
	}
	// Выполняем разбор поверх совсем другого текста
	ASSERT_TRUE(doc.parse("совсем: другое\nтретий: третье\nчетвёртый: ещё\n"));
	// Выполняем проверку того, что ссылка перестроение не пережила
	ASSERT_FALSE(node.valid());
	/**
	 * Выполняем проверку снятия значения со ссылки оборванной
	 */
	{
		// Собираемое владеющее значение, ссылкою оборванной заводимое
		const yaml::value_t value(node);
		// Выполняем проверку того, что снятое значение пусто
		ASSERT_EQ(value.kind(), yaml::kind_t::NONE);
	}
}
