		value.chomp(yaml::chomp_t::STRIP);
		// Выполняем проверку выдачи установленного обхождения
		ASSERT_EQ(value.chomp(), yaml::chomp_t::STRIP);
		// Выполняем проверку того, что перезапись установленное обхождение взяла
		ASSERT_NE(value.dump().find("|-"), string::npos);
