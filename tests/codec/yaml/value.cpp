	const yaml::value_t & nested = value.at("a");
	// Выполняем проверку того, что вместилище вложенное собрано перечнем
	ASSERT_EQ(nested.kind(), yaml::kind_t::SEQUENCE);
	// Выполняем проверку того, что якорь корня вложенному не достался
