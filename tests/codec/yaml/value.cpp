/**
 * @brief Проверка кругового хода владеющего значения через файл
 *
 * @details Запись значения в файл и чтение его обратно суть зеркальная пара, и
 *          значение, круг переживший, обязано совпасть с исходным
 *
 * @note Отказ открытия записываемого файла проверяется здесь же: чтение значения из
 *       файла ведётся деревом документа, и об отказе открытия оно сообщает. Молчание
 *       записи оставляло бы потребителя с признаком отказа без причины его
 *
 */
TEST(CodecYamlValue, FileRoundTrip) {
	// Адрес файла, в какой записывается владеющее значение
	const string filename = "./awh_yaml_value.yaml";
	// Владеющее значение, в файл записываемое
	yaml::value_t value;
	// Выполняем назначение поля отображения простым значением
	value["host"] = yaml::value_t("alpha");
	// Выполняем назначение поля отображения числом
	value["port"] = yaml::value_t(static_cast <int64_t> (8080));
	// Выполняем проверку успешности записи владеющего значения в файл
	ASSERT_TRUE(value.save(filename));
	/**
	 * Выполняем проверку того, что записанное совпадает с собранным текстом дословно
	 *
	 * @note Половина эта обязательна: круговой ход через разбор потери хвостового
	 *       перевода строки НЕ замечает - разбор даёт то же значение, а запись перевод
	 *       возвращает, - и усечение записи прошло бы сличение значений молча
	 */
	{
		// Поток чтения записанного файла значения
		ifstream file(filename, ios::binary);
		// Выполняем проверку того, что записанный файл открывается
		ASSERT_TRUE(file.is_open());
		// Считываем содержимое записанного файла целиком
		const string written((istreambuf_iterator <char> (file)), istreambuf_iterator <char> ());
		// Выполняем проверку дословного совпадения записанного с собранным
		ASSERT_EQ(written, value.dump());
	}
	// Владеющее значение, из файла читаемое
	yaml::value_t restored;
	// Выполняем проверку успешности чтения владеющего значения из файла
	ASSERT_TRUE(restored.load(filename));
	// Выполняем проверку того, что значение круговой ход через файл пережило
	ASSERT_TRUE(restored == value);
	// Выполняем проверку содержимого значения, круг пережившего
	ASSERT_EQ(restored["host"].text(), "alpha");
	// Выполняем удаление записанного временного файла значения
	::remove(filename.c_str());
	/**
	 * Выполняем проверку отказа записи в неоткрываемый файл
	 */
	{
		// Собираемые сообщения журнала
		vector <string> messages;
		// Объект журнала с перехватом вывода
		awh::log_t log(&Silent::framework());
		// Выполняем назначение приёмника вывода в функцию обратного вызова
		log.mode({awh::log_t::mode_t::DEFERRED});
		// Выполняем назначение перехвата сообщений журнала
		log.subscribe([&messages](const awh::log_t::flag_t, string_view text) noexcept -> void {
			// Выполняем сбор очередного сообщения журнала
			messages.push_back(string(text));
		});
		// Владеющее значение, откуда ведётся запись
		yaml::value_t refused;
		// Выполняем назначение приёмника вывода журнала записываемому значению
		refused.setLogger(&log);
		// Выполняем назначение поля отображения простым значением
		refused["ключ"] = yaml::value_t("значение");
		// Выполняем проверку отказа записи в путь, каталогом не существующий
		ASSERT_FALSE(refused.save("./awh_yaml_нет_такого_каталога/файл.yaml"));
		// Выполняем проверку того, что отказ записи в журнал ушёл
		ASSERT_EQ(messages.size(), 1u);
		// Выполняем проверку того, что причина отказа названа
		ASSERT_NE(messages.front().find(yaml::message(yaml::error_t::FILE_NOT_OPENED)), string::npos);
	}
}
/**
 * @brief Проверка отказов обращения к значению вида неподходящего
 *
 * @details Обращения отображения - розыск имени, снятие по имени, занесение пары и
 *          снятие пары - к значению иного вида неприложимы вовсе, и отвечают они
 *          отказом да значением неопределённым. Путь пустой отсылает к самому значению,
 *          а путь глубже предела вложенности - к значению мусорному: завести дерево,
 *          записать какое нельзя, незачем
 *
 * @note Отказы эти не проверялись ничем: ни набором проверок, ни корпусом
 *       yaml-test-suite, ни ворошителем - все трое ходят по дереву разобранному, где
 *       вид значения обращению отвечает всегда. Берутся они здесь обращением прямым:
 *       владеющее значение объявлено наружу, и звать его вправе кто угодно
 *
 * @warning Порчею доказаны шесть стражей из восьми: снятие проверки вида у снятия по
 *          имени, у обращения по номеру, у занесения пары, снятие выхода по пути
 *          пустому - оба, и снятие предела вложенности - проверку валят всякий сам
 *          по себе. Два стража порчею НЕ доказаны: розыск имени и снятие пары по
 *          имени. Причина у обоих одна и дефектом не является: без проверки вида
 *          обращение уходит в розыск по перечню имён, а у значения вида иного имён
 *          нет вовсе, и ответ выходит тот же самый отказ. Стражи эти сокращают путь,
 *          а поведения собою не задают - надзирать над ними нечем
 *
 */
TEST(CodecYamlValue, MisuseRefusals) {
	/**
	 * Выполняем проверку отказов обращений отображения к перечню значений
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем занесение значения перечня
		value.push(static_cast <int64_t> (1));
		// Выполняем проверку того, что значение перечнем и стало
		ASSERT_EQ(value.kind(), yaml::kind_t::SEQUENCE);
		// Выполняем проверку отказа розыска имени у перечня значений
		ASSERT_FALSE(value.contains("a"));
		// Выполняем проверку неопределённости значения, по имени с перечня снятого
		ASSERT_FALSE(const_cast <const yaml::value_t &> (value)["a"].valid());
		// Выполняем проверку отказа занесения пары в перечень значений
		ASSERT_FALSE(value.append("a", yaml::value_t()));
		// Выполняем проверку отказа снятия пары с перечня значений
		ASSERT_FALSE(value.erase("a"));
		// Выполняем проверку того, что перечень отказами не тронут
		ASSERT_EQ(value.size(), static_cast <size_t> (1));
	}
	/**
	 * Выполняем проверку обращения по номеру к значению, вместилищем не бывшему
	 *
	 * @note Обращение по номеру вместилища требует, и значение скалярное обращается
	 *       перечнем: иначе записать по номеру было бы некуда
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем запись скалярного значения
		value = static_cast <int64_t> (7);
		// Выполняем проверку того, что значение числом и стало
		ASSERT_EQ(value.kind(), yaml::kind_t::NUMBER);
		// Выполняем запись значения по номеру
		value[static_cast <size_t> (0)] = static_cast <int64_t> (9);
		// Выполняем проверку того, что значение перечнем обратилось
		ASSERT_EQ(value.kind(), yaml::kind_t::SEQUENCE);
		// Выполняем проверку того, что прежнее скалярное значение снято
		ASSERT_EQ(value.size(), static_cast <size_t> (1));
	}
	/**
	 * Выполняем проверку пути пустого, к самому значению отсылающего
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем занесение пары отображения
		value.append("a", yaml::value_t(static_cast <int64_t> (1)));
		// Выполняем проверку того, что путь пустой отсылает к самому значению
		ASSERT_EQ(&const_cast <const yaml::value_t &> (value).at(""), &value);
		// Выполняем проверку того, что путь из одного разделителя отсылает туда же
		ASSERT_EQ(&const_cast <const yaml::value_t &> (value).at("/"), &value);
		// Выполняем проверку того, что заведение по пути пустому отсылает к самому значению
		ASSERT_EQ(&value.place(""), &value);
		// Выполняем проверку того, что заведение по одному разделителю отсылает туда же
		ASSERT_EQ(&value.place("/"), &value);
	}
	/**
	 * Выполняем проверку отказа заведения по пути глубже предела вложенности
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Путь глубиною ровно в предел вложенности
		string route;
		/**
		 * Выполняем сборку пути глубиною ровно в предел вложенности
		 */
		for(size_t i = 0; i < static_cast <size_t> (yaml::MAX_DEPTH); i++){
			/**
			 * Если звено пути не первое
			 */
			if(!route.empty())
				// Выполняем добавление разделителя звеньев пути
				route.append(1, '/');
			// Выполняем добавление очередного звена пути
			route.append("a");
		}
		// Выполняем проверку того, что путь глубиною в предел заводится
		ASSERT_TRUE(&value.place(route) != &yaml::value_t::scrap());
		// Выполняем проверку отказа заведения по пути глубже предела на одно звено
		ASSERT_EQ(&value.place(route + "/a"), &yaml::value_t::scrap());
	}
}
/**
 * @brief Проверка присваивания значения самому себе и записи чисел особых
 *
 * @details Присваивание значения самому себе обязано оставить его целым: снятие
 *          прежнего содержимого прежде переноса нового сгубило бы его вовсе, ибо
 *          прежнее и новое здесь одно и то же. Числа же особые - не-число и
 *          бесконечности - записываются наречием YAML, а не выдачей библиотеки языка
 *
 * @note Места эти лежали в стороне от всех трёх прогонов сразу: набор проверок
 *       присваивал значения разные, корпус yaml-test-suite владеющего значения не
 *       берёт вовсе, а ворошитель собирает дерево из чисел годных
 *
 * @warning Порчею доказаны страж переноса значения в себя же и запись не-числа:
 *          снятие всякого из них проверку валит. Страж присваивания копией порчею НЕ
 *          доказан - снятие его исхода не меняет, ибо тело присваивания и без него
 *          самому себе не вредит. Держится он там опережением работы напрасной, а не
 *          целости значения, и проверка стережёт здесь ответ, а не страж
 *
 */
TEST(CodecYamlValue, SelfAssignmentAndSpecialNumbers) {
	/**
	 * Выполняем проверку присваивания значения самому себе
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем занесение пары отображения
		value.append("a", yaml::value_t(static_cast <int64_t> (1)));
		// Получаем ссылку на значение под иным именем
		yaml::value_t & same = value;
		// Выполняем присваивание значения самому себе
		value = same;
		// Выполняем проверку того, что значение осталось целым
		ASSERT_EQ(value.kind(), yaml::kind_t::MAPPING);
		// Выполняем проверку того, что пара отображения на месте
		ASSERT_TRUE(value.contains("a"));
		// Выполняем перенос значения в себя же
		value = std::move(same);
		// Выполняем проверку того, что значение осталось целым и по переносе
		ASSERT_EQ(value.kind(), yaml::kind_t::MAPPING);
		// Выполняем проверку того, что пара отображения на месте и по переносе
		ASSERT_TRUE(value.contains("a"));
	}
	/**
	 * Выполняем проверку записи чисел особых
	 *
	 * @note Записи эти берутся описанием наречия: выдача библиотеки языка дала бы
	 *       `nan` и `inf`, а описание требует `.nan` и `.inf`
	 */
	{
		// Извлекаемая запись значения
		string record;
		// Собираемое значение не-числа
		const yaml::value_t nothing(std::numeric_limits <double>::quiet_NaN());
		// Выполняем проверку извлечения записи не-числа
		ASSERT_TRUE(nothing.value(record));
		// Выполняем проверку записи не-числа
		ASSERT_EQ(record, ".nan");
		// Собираемое значение бесконечности со знаком плюс
		const yaml::value_t endless(std::numeric_limits <double>::infinity());
		// Выполняем проверку извлечения записи бесконечности
		ASSERT_TRUE(endless.value(record));
		// Выполняем проверку записи бесконечности
		ASSERT_EQ(record, ".inf");
		// Собираемое значение бесконечности со знаком минус
		const yaml::value_t reversed(-std::numeric_limits <double>::infinity());
		// Выполняем проверку извлечения записи бесконечности со знаком минус
		ASSERT_TRUE(reversed.value(record));
		// Выполняем проверку записи бесконечности со знаком минус
		ASSERT_EQ(record, "-.inf");
	}
	/**
	 * Выполняем проверку заведения значения видом своим
	 */
	{
		// Виды значений, заведению подлежащие, вместе с видами хранения их
		const pair <yaml::kind_t, yaml::type_t> kinds[] = {
			// Пустое значение заводится видом хранения пустого
			{yaml::kind_t::NUL, yaml::type_t::NUL},
			// Логическое значение заводится видом хранения логического
			{yaml::kind_t::BOOL, yaml::type_t::BOOL},
			// Строковое значение заводится видом хранения строки
			{yaml::kind_t::STRING, yaml::type_t::STRING}
		};
		/**
		 * Выполняем перебор видов значений, заведению подлежащих
		 */
		for(auto & item : kinds){
			// Собираемое значение вида заданного
			const yaml::value_t value(item.first);
			// Выполняем проверку вида заведённого значения
			ASSERT_EQ(value.kind(), item.first);
			// Выполняем проверку вида хранения заведённого значения
			ASSERT_TRUE(value.is(item.second));
		}
	}
}
/**
 * @brief Проверка розыска пары по имени и предела роста вместилища
 *
 * @details Розыск выдаёт номер пары, а при отсутствии её - размер вместилища: тем он и
 *          годен для обхода без исключений. Предел же роста стережёт обращение по
 *          номеру, извне пришедшему: номер обращается требованием памяти по нему
 *
 * @note Оба способа не звались набором проверок ни разу - розыск по объявленным наружу
 *       не дал ни одного случая
 *
 * @warning Предел роста хранится величиною процесса, общей на все проверки: ставится он
 *          здесь на время и возвращается к умолчанию тут же, иначе соседние проверки
 *          получили бы его в наследство
 *
 */
TEST(CodecYamlValue, SearchAndGrowthLimit) {
	/**
	 * Выполняем проверку розыска пары по имени
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем занесение первой пары отображения
		value.append("первое", yaml::value_t(static_cast <int64_t> (1)));
		// Выполняем занесение второй пары отображения
		value.append("второе", yaml::value_t(static_cast <int64_t> (2)));
		// Выполняем проверку номера первой пары
		ASSERT_EQ(value.search("первое"), static_cast <size_t> (0));
		// Выполняем проверку номера второй пары
		ASSERT_EQ(value.search("второе"), static_cast <size_t> (1));
		// Выполняем проверку выдачи размера вместилища при отсутствии пары
		ASSERT_EQ(value.search("третье"), value.size());
	}
	/**
	 * Выполняем проверку предела роста вместилища
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		// Выполняем установку предела роста вместилища
		yaml::value_t::limit(4);
		// Выполняем обращение по номеру, пределу отвечающему
		value[static_cast <size_t> (3)] = static_cast <int64_t> (1);
		// Выполняем проверку того, что вместилище выросло до затребованного номера
		ASSERT_EQ(value.size(), static_cast <size_t> (4));
		// Выполняем проверку того, что обращение за предел выдаёт значение мусорное
		ASSERT_EQ(&value[static_cast <size_t> (4)], &yaml::value_t::scrap());
		// Выполняем проверку того, что вместилище отказом не выросло
		ASSERT_EQ(value.size(), static_cast <size_t> (4));
		// Выполняем возврат предела роста к умолчанию рамки
		yaml::value_t::limit(0x10000);
	}
}
/**
 * @brief Проверка ведения указателя имён при заведении пар
 *
 * @details Розыск пары ведётся перебором, покуда пар меньше порога, а за порогом
 *          заводится указатель имён. Заводят пары два способа - занесение и вставка, - и
 *          всякий обязан вести указатель приращением: иначе заведённая пара стала бы
 *          невидимой розыску, оставаясь в самом вместилище
 *
 * @note Оба места лежали в стороне от всех трёх прогонов сразу: набор собирал отображения
 *       малые, корпус yaml-test-suite владеющего значения не берёт вовсе, а ворошитель
 *       собирает дерево разбором
 *
 * @warning Порог взят ГРАНИЦЕЮ: пары заводятся числом ровно в порог, розыск заводит
 *          указатель, и лишь потом заводится пара за порогом. Собери проверка сразу
 *          двадцать пар - указатель завёлся бы разом на все, и приращение его осталось
 *          бы нетронутым
 *
 */
TEST(CodecYamlValue, NameIndexGrowsWithAppendAndInsert) {
	/**
	 * Выполняем проверку ведения указателя имён при занесении пары
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		/**
		 * Выполняем занесение пар числом ровно в порог заведения указателя
		 */
		for(uint32_t i = 0; i < yaml::INDEX_THRESHOLD; i++)
			// Выполняем занесение очередной пары отображения
			ASSERT_TRUE(value.append("имя" + std::to_string(i), yaml::value_t(static_cast <int64_t> (i))))
			 << "пара " << i;
		// Выполняем розыск пары, указатель имён заводящий
		ASSERT_EQ(value.search("имя0"), static_cast <size_t> (0));
		// Выполняем занесение пары за порогом заведения указателя
		ASSERT_TRUE(value.append("долитое", yaml::value_t(static_cast <int64_t> (99))));
		// Выполняем проверку того, что долитая пара указателю ведома
		ASSERT_EQ(value.search("долитое"), static_cast <size_t> (yaml::INDEX_THRESHOLD));
		// Извлекаемое значение долитой пары
		int64_t number = 0;
		// Выполняем проверку извлечения значения долитой пары по имени
		ASSERT_TRUE(value["долитое"].value(number));
		// Выполняем проверку извлечённого значения долитой пары
		ASSERT_EQ(number, static_cast <int64_t> (99));
	}
	/**
	 * Выполняем проверку ведения указателя имён при вставке пары
	 *
	 * @note Вставка отличается от занесения перезаписью занятого имени: имя незанятое
	 *       она заводит тем же порядком, и указатель вести обязана тоже
	 */
	{
		// Собираемое владеющее значение
		yaml::value_t value;
		/**
		 * Выполняем занесение пар числом ровно в порог заведения указателя
		 */
		for(uint32_t i = 0; i < yaml::INDEX_THRESHOLD; i++)
			// Выполняем занесение очередной пары отображения
			ASSERT_TRUE(value.append("имя" + std::to_string(i), yaml::value_t(static_cast <int64_t> (i))))
			 << "пара " << i;
		// Выполняем розыск пары, указатель имён заводящий
		ASSERT_EQ(value.search("имя0"), static_cast <size_t> (0));
		// Выполняем вставку пары за порогом заведения указателя
		ASSERT_TRUE(value.insert("вставленное", yaml::value_t(static_cast <int64_t> (77))));
		// Выполняем проверку того, что вставленная пара указателю ведома
		ASSERT_EQ(value.search("вставленное"), static_cast <size_t> (yaml::INDEX_THRESHOLD));
		// Извлекаемое значение вставленной пары
		int64_t number = 0;
		// Выполняем проверку извлечения значения вставленной пары по имени
		ASSERT_TRUE(value["вставленное"].value(number));
		// Выполняем проверку извлечённого значения вставленной пары
		ASSERT_EQ(number, static_cast <int64_t> (77));
	}
}
