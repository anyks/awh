	ASSERT_EQ(value[1].text(), "18446744073709551615");
	// Выполняем проверку записи дробного числа
	ASSERT_EQ(value[2].text(), "3.5");
	// Выполняем проверку записи пустого значения
	ASSERT_TRUE(value[3].text().empty());
