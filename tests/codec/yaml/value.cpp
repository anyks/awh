/**
 * @brief Проверка сборки отображения с повторяющимися именами полей
 *
 * @details Признак добавления принадлежит имени, а не сборке: без сброса одно
 *          добавление сделало бы добавлениями все поля до конца сборки. Указание же на
 *          добавленное поле берётся по номеру, а не розыском по имени - иначе
 *          вместилище, за добавлением открытое, собиралось бы в поле первое
 *
 */
TEST(CodecYamlValue, BuilderAppend) {
	// Объект потоковой сборки значения
	yaml::builder_t builder;
	// Выполняем открытие отображения пар
	ASSERT_TRUE(builder.mapping());
	// Выполняем назначение имени первого поля отображения
	ASSERT_TRUE(builder.key("a"));
	// Выполняем запись значения первого поля отображения
	ASSERT_TRUE(builder.value(static_cast <int64_t> (1)));
	// Выполняем назначение имени поля, рядом с одноимённым кладомого
	ASSERT_TRUE(builder.append("a"));
	// Выполняем открытие отображения пар внутри добавленного поля
	ASSERT_TRUE(builder.mapping());
	// Выполняем назначение имени поля вложенного отображения
	ASSERT_TRUE(builder.key("вложенное"));
	// Выполняем запись значения поля вложенного отображения
	ASSERT_TRUE(builder.value(static_cast <int64_t> (2)));
	// Выполняем закрытие вложенного отображения пар
	ASSERT_TRUE(builder.close());
	// Выполняем назначение имени третьего поля отображения
	ASSERT_TRUE(builder.key("b"));
	// Выполняем запись значения третьего поля отображения
	ASSERT_TRUE(builder.value(static_cast <int64_t> (3)));
	// Выполняем назначение имени четвёртого поля отображения тем же именем
	ASSERT_TRUE(builder.key("b"));
	// Выполняем запись значения четвёртого поля отображения
	ASSERT_TRUE(builder.value(static_cast <int64_t> (4)));
	// Выполняем закрытие отображения пар
	ASSERT_TRUE(builder.close());
	// Получаем собранное владеющее значение
	const yaml::value_t value = builder.finish();
	// Выполняем проверку количества полей собранного отображения
	ASSERT_EQ(value.size(), 3);
	// Выполняем проверку того, что первое вхождение имени не тронуто
	ASSERT_EQ(value[0].text(), "1");
	// Выполняем проверку того, что вложенное отображение легло в поле добавленное
	ASSERT_EQ(value[1].size(), 1);
	// Выполняем проверку значения поля вложенного отображения
	ASSERT_EQ(value[1]["вложенное"].text(), "2");
	// Выполняем проверку того, что имя обычное поле своё перезаписало
	ASSERT_EQ(value["b"].text(), "4");
}
/**
 * @brief Проверка кругового хода отображения с повторяющимися именами полей
 *
 * @details Дерево, разбором с настройкой `duplicate_t::KEEP` собранное, обязано
 *          воспроизводиться потоковой сборкой полностью
 *
 */
TEST(CodecYamlValue, AppendRoundtrip) {
	// Настройки разбора дерева с удержанием повторяющихся имён
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание всех вхождений повторяющегося имени
	settings.duplicates = yaml::duplicate_t::KEEP;
	// Объект дерева документа
	yaml::document_t doc(::logger(), settings);
	// Выполняем разбор текста с повторяющимися именами полей
	ASSERT_TRUE(doc.parse("имя: 1\nимя: 2\nиное: 3\n"));
	// Владеющее значение, с дерева документа снятое
	const yaml::value_t taken(doc.root());
	// Выполняем проверку того, что оба вхождения имени удержаны
	ASSERT_EQ(taken.size(), 3);
	// Объект потоковой сборки значения
	yaml::builder_t builder;
	// Выполняем открытие отображения пар
	ASSERT_TRUE(builder.mapping());
	/**
	 * Выполняем перебор всех полей снятого отображения
	 */
	for(size_t i = 0; i < taken.size(); i++){
		// Выполняем назначение имени очередного поля отображения
		ASSERT_TRUE(builder.append(taken.key(i)));
		// Выполняем запись значения очередного поля отображения
		ASSERT_TRUE(builder.value(taken[i].text()));
	}
	// Выполняем закрытие отображения пар
	ASSERT_TRUE(builder.close());
	// Получаем собранное владеющее значение
	const yaml::value_t built = builder.finish();
	// Выполняем проверку количества полей собранного отображения
	ASSERT_EQ(built.size(), taken.size());
	/**
	 * Выполняем перебор всех полей собранного отображения
	 */
	for(size_t i = 0; i < built.size(); i++){
		// Выполняем проверку имени очередного поля отображения
		ASSERT_EQ(built.key(i), taken.key(i));
		// Выполняем проверку значения очередного поля отображения
		ASSERT_EQ(built[i].text(), taken[i].text());
	}
}
/**
 * @brief Проверка кругового хода числа, ни в один родной вид не вместимого
 *
 * @details Такое число хранится записью своей, а выдаётся дробным приближением: запись
 *          `12345678901234567890123456789` описанием вернулась бы приближением, и
 *          круговой ход потерял бы число. Ловушку эту сличение не ловило вовсе - обе
 *          стороны округлялись одинаково. Указал на неё ведущий кодеков JSON и XML
 *
 */
TEST(CodecYamlValue, ExtendedNumbers) {
	// Записи чисел, ни в один родной вид не вместимых
	const vector <string> records = {
		"1e400", "-1e400", "1e-400", "12345678901234567890123456789",
		"170141183460469231731687303715884105729"
	};
	/**
	 * Выполняем перебор всех записей чисел
	 */
	for(const string & record : records){
		// Владеющее значение, запись числа несущее
		yaml::value_t value;
		// Выполняем разбор записи числа во владеющее значение
		ASSERT_TRUE(value.parse(string("x: ") + record + "\n")) << record;
		// Выполняем проверку того, что число родным видом не признано
		ASSERT_TRUE(value["x"].is(yaml::type_t::EXTENDED)) << record;
		// Получаем перезапись снятого значения
		const string out = value.dump();
		// Выполняем проверку того, что запись числа перенесена дословно
		ASSERT_NE(out.find(record), string::npos) << record << " → " << out;
		// Прочитанное обратно владеющее значение
		yaml::value_t circled;
		// Выполняем чтение перезаписи обратно
		ASSERT_TRUE(circled.parse(out)) << record;
		// Выполняем проверку кругового хода снятого значения
		ASSERT_TRUE(circled == value) << record;
		// Выполняем проверку того, что запись числа круговым ходом сохранена
		ASSERT_EQ(circled["x"].text(), record);
	}
	// Настройки разбора дерева с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Объект дерева документа
	yaml::document_t doc(::logger(), settings);
	// Выполняем разбор записей чисел поднормальных
	ASSERT_TRUE(doc.parse("a: 1e-320\nb: 5e-324\nc: 1e-400\n"));
	/**
	 * Выполняем перебор записей поднормальных чисел
	 *
	 * @details Признак выхода за предел стоит у них наравне с потерею значимости, и
	 *          сличается оттого сам исход разбора. Вид же их от машины зависит прямо:
	 *          где поднормальные числа поддержаны, запись `1e-320` даёт дробное, а где
	 *          нет - вид, ни в один родной вид не вместимый. Обе выдачи верны, и
	 *          закреплять одну из них значило бы закреплять свойство машины
	 *
	 * @note Проверяется потому не вид, а само обещание: число не теряется. Дробным
	 *       оно выходит лишь тогда, когда машина его несёт, а иначе хранится записью.
	 *       Расхождение это вскрыл стенд NetBSD/aarch64: `strtod` там обращает в нуль
	 *       всякое поднормальное число
	 */
	for(const char * path : {"/a", "/b"}){
		// Собираемое дробное значение записи
		double real = 0.;
		/**
		 * Если запись прочитана дробным числом
		 */
		if(doc.root().at(path).type() == yaml::type_t::DOUBLE){
			// Выполняем извлечение дробного значения записи
			ASSERT_TRUE(doc.root().at(path).value(real)) << path;
			// Выполняем проверку того, что число нулём не обратилось
			ASSERT_NE(real, 0.) << path;
		/**
		 * Если запись прочитана видом, ни в один родной вид не вместимым
		 */
		} else {
			// Выполняем проверку вида прочитанной записи
			ASSERT_TRUE(doc.root().at(path).is(yaml::type_t::EXTENDED)) << path;
			// Выполняем проверку того, что запись числа удержана дословно
			ASSERT_FALSE(doc.root().at(path).text().empty()) << path;
		}
	}
	// Выполняем проверку того, что потеря значимости родным видом не признана
	ASSERT_TRUE(doc.root().at("/c").is(yaml::type_t::EXTENDED));
}
