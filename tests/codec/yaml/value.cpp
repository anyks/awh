/**
 * @brief Проверка того, что отказ переноса называет свою причину
 *
 * @details `graft()` берёт причину отказа у копии дерева и передаёт её дереву
 *          исходному - без того потребитель остался бы с отказом без причины. Два
 *          отказа самой укладки причины не называли вовсе, и `error()` отвечал
 *          «ошибок не обнаружено» при истинном отказе: ложь хуже молчания, ибо
 *          потребитель по ней заключил бы об удаче
 *
 * @note Оба отказа намеренны и описаны при самом методе: имя, косую черту несущее,
 *       путём указывало бы на узел чужой, а имя, вторично встреченное, путём не
 *       выражается вовсе - путь ведёт к первому вхождению всегда
 *
 */
TEST(CodecYamlValue, GraftRefusalNamesItsCause) {
	{
		// Настройки дерева документа
		yaml::document_t::settings_t settings;
		// Удерживаем все пары с повторяющимся именем
		settings.duplicates = yaml::duplicate_t::KEEP;
		// Дерево документа
		yaml::document_t document(::logger());
		// Выполняем установку настроек дерева документа
		document.settings(settings);
		// Выполняем проверку успешности разбора текста документа
		ASSERT_TRUE(document.parse("b: 1\nb: 2\n"));
		// Дерево документа, куда переносится значение
		yaml::document_t target(::logger());
		// Выполняем установку настроек дерева переноса
		target.settings(settings);
		// Выполняем проверку успешности разбора пустого отображения
		ASSERT_TRUE(target.parse("{}"));
		// Выполняем проверку отказа переноса значения с повторяющимся именем
		ASSERT_FALSE(yaml::value_t(document.root()).graft(target));
		// Выполняем проверку того, что причина отказа названа
		ASSERT_EQ(target.error(), yaml::error_t::DUPLICATE_KEY);
	}{
		// Дерево документа
		yaml::document_t document(::logger());
		// Выполняем проверку успешности разбора текста документа
		ASSERT_TRUE(document.parse("\"\": 1\n"));
		// Дерево документа, куда переносится значение
		yaml::document_t target(::logger());
		// Выполняем проверку успешности разбора пустого отображения
		ASSERT_TRUE(target.parse("{}"));
		/**
		 * Выполняем проверку отказа переноса значения с пустым именем
		 *
		 * @note Прежде здесь стояло имя с косою чертой: ныне оно путём выражается
		 *       отменяющей записью и переносу не мешает, а негодным осталось имя пустое
		 */
		ASSERT_FALSE(yaml::value_t(document.root()).graft(target));
		// Выполняем проверку того, что причина отказа названа
		ASSERT_EQ(target.error(), yaml::error_t::INVALID_PATH);
	}{
		// Дерево документа
		yaml::document_t document(::logger());
		// Выполняем проверку успешности разбора текста документа
		ASSERT_TRUE(document.parse("a: 1\n"));
		// Дерево документа, куда переносится значение
		yaml::document_t target(::logger());
		// Выполняем проверку успешности разбора пустого отображения
		ASSERT_TRUE(target.parse("{}"));
		// Выполняем проверку успешности переноса годного значения
		ASSERT_TRUE(yaml::value_t(document.root()).graft(target));
		// Выполняем проверку того, что удача причины не называет
		ASSERT_EQ(target.error(), yaml::error_t::NONE);
	}
}

/**
 * @brief Проверка того, что отказ записи владеющего значения называет причину
 *
 * @details Запись отвечает ТЕКСТОМ, и пустой текст означал разом две разные вещи: значение
 *          пустое и отказ записи. Различить их потребителю было нечем вовсе - ни кода, ни
 *          сообщения в журнал отказ не давал, и потребитель сохранял бы пустой файл вместо
 *          своего документа
 *
 * @note Причину поток записи ЗНАЛ и выбрасывал: сборка записи признака не отдаёт, а объект
 *       записи живёт внутри одного вызова. Найдено разбором, а не отказом
 */
TEST(CodecYamlValue, RefusedWritingNamesItsCause){
	// Владеющее значение, глубину записи превышающее
	yaml::value_t deep(string("дно"));
	/**
	 * Выполняем сборку дерева глубиною свыше предела записи
	 */
	for(size_t i = 0; i < 2000; i++){
		// Заводимое вместилище очередного уровня
		yaml::value_t outer(yaml::kind_t::SEQUENCE);
		// Выполняем укладку прежнего дерева внутрь вместилища
		ASSERT_TRUE(outer.push(deep));
		// Запоминаем собранное дерево очередного уровня
		deep = outer;
	}
	// Выполняем проверку того, что запись такого дерева пуста
	ASSERT_TRUE(deep.dump().empty());
	/**
	 * Выполняем проверку того, что отказ записи назвал свою причину
	 */
	ASSERT_EQ(deep.error(), yaml::error_t::DEPTH_EXCEEDED);
	/**
	 * Выполняем проверку того, что удачная запись следом код отказа СБРАСЫВАЕТ
	 *
	 * @note Код держится от последней работы, а не от последней неудачной: правило это
	 *       одно у дерева и у значения
	 */
	yaml::value_t plain(string("простое"));
	// Выполняем проверку того, что запись простого значения удалась
	ASSERT_FALSE(plain.dump().empty());
	// Выполняем проверку того, что удачная запись кода отказа не поставила
	ASSERT_EQ(plain.error(), yaml::error_t::NONE);
}

/**
 * @brief Проверка розыска имени, ростом вместилища по номеру заведённого
 *
 * @details Рост отображения по номеру заводит поля с именем-номером, а указатель
 * поиска, прежде заведённый, о них не знает. Розыск тогда отвечал по числу полей, а не
 * по содержимому: до порога заведения указателя поле находилось, а за порогом пропадало
 *
 */
TEST(CodecYamlValue, GrowthByIndexKeepsTheSearchTrue){
	/**
	 * Выполняем перебор числа полей по обе стороны порога заведения указателя
	 */
	for(const size_t count : {static_cast <size_t> (4), static_cast <size_t> (20)}){
		// Значение отображения пар
		yaml::value_t mapping;
		/**
		 * Выполняем заведение затребованного числа полей отображения
		 */
		for(size_t i = 0; i < count; i++)
			// Выполняем установку очередного поля отображения
			ASSERT_TRUE(mapping.insert("k" + std::to_string(i), yaml::value_t(static_cast <int64_t> (i))));
		// Выполняем понуждение к заведению указателя поиска
		ASSERT_TRUE(mapping.contains("k0"));
		// Выполняем рост отображения по номеру, имена полей номерами заводящий
		mapping[count + 1] = yaml::value_t(static_cast <int64_t> (777));
		// Выполняем проверку того, что поле с именем-номером разыскивается
		ASSERT_TRUE(mapping.contains(std::to_string(count))) << count;
	}
}
