	writer.key("пусто");
	// Выполняем открытие пустого отображения
	writer.mapping();
	// Выполняем закрытие пустого отображения
	writer.close();
	// Выполняем запись имени пары пустого перечня
	writer.key("перечень");
	// Выполняем открытие пустого перечня
	writer.sequence();
	// Выполняем закрытие пустого перечня
	writer.close();
	// Выполняем запись имени пары за пустыми вместилищами
