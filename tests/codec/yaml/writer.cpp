/**
 * @brief Проверка записи блочного значения со свёрткой строк
 *
 * @details Свёртка при обратном чтении складывает строки пробелом, а пробег переводов
 *          уменьшает на один. Оттого записывать содержимое строка на строку нельзя:
 *          всякий пробег переводов надлежит нарастить на один перевод, а содержимое,
 *          свёрткою не передаваемое, записать видом дословным
 *
 * @note Нашёл это ворошитель сличением перезаписи: содержимое, перевод несущее,
 *       записывалось строка на строку и обратным чтением складывалось в одну строку.
 *       Утрата шла молча, и перезапись перезаписи выдавала уже иной текст
 *
 */
TEST(CodecYamlWriter, FoldedRewrite) {
	/**
	 * Выполняем проверку наращивания одного перевода строки пустою строкой
	 */
	{
		// Объект записи текста
		yaml::writer_t writer;
		// Выполняем запись блочного значения со свёрткой
		ASSERT_TRUE(writer.block("одна\nдве\n", yaml::style_t::FOLDED, yaml::chomp_t::CLIP));
		// Выполняем завершение записи текста
		writer.finish();
		// Выполняем проверку собранного текста
		ASSERT_EQ(writer.text(), ">\n  одна\n\n  две\n");
		// Выполняем проверку кругового хода записи с чтением
		ASSERT_EQ(roundtrip(writer.text()),
			"STREAM_START\nDOCUMENT_START\nSCALAR «одна\nдве\n»\nDOCUMENT_END\nSTREAM_END\n");
	}
	/**
	 * Выполняем проверку наращивания пробега из двух переводов строк
	 */
	{
		// Объект записи текста
		yaml::writer_t writer;
		// Выполняем запись блочного значения со свёрткой
		ASSERT_TRUE(writer.block("одна\n\nдве\n", yaml::style_t::FOLDED, yaml::chomp_t::CLIP));
		// Выполняем завершение записи текста
		writer.finish();
		// Выполняем проверку собранного текста
		ASSERT_EQ(writer.text(), ">\n  одна\n\n\n  две\n");
		// Выполняем проверку кругового хода записи с чтением
		ASSERT_EQ(roundtrip(writer.text()),
			"STREAM_START\nDOCUMENT_START\nSCALAR «одна\n\nдве\n»\nDOCUMENT_END\nSTREAM_END\n");
	}
	/**
	 * Выполняем проверку записи видом дословным содержимого, свёрткою не передаваемого
	 *
	 * @note Строка, пробелом открытая, чтением принимается стоящею глубже отступа
	 *       содержимого, и переводы вокруг неё сохраняются как есть: наращивание их
	 *       выдало бы переводов больше записанного
	 */
	{
		// Объект записи текста
		yaml::writer_t writer;
		// Выполняем запись блочного значения со свёрткой
		ASSERT_TRUE(writer.block("одна\n  две\n", yaml::style_t::FOLDED, yaml::chomp_t::CLIP));
		// Выполняем завершение записи текста
		writer.finish();
		// Выполняем проверку записи содержимого видом дословным
		ASSERT_EQ(writer.text(), "|\n  одна\n    две\n");
		// Выполняем проверку кругового хода записи с чтением
		ASSERT_EQ(roundtrip(writer.text()),
			"STREAM_START\nDOCUMENT_START\nSCALAR «одна\n  две\n»\nDOCUMENT_END\nSTREAM_END\n");
	}
	/**
	 * Выполняем проверку сохранения концевых переводов строк
	 *
	 * @note Правило усечения применяется после свёртки, и концевые переводы наращивания
	 *       не требуют: записываются они тем же порядком, каким записывает их вид дословный
	 */
	{
		// Объект записи текста
		yaml::writer_t writer;
		// Выполняем запись блочного значения со свёрткой
		ASSERT_TRUE(writer.block("одна\n\n", yaml::style_t::FOLDED, yaml::chomp_t::KEEP));
		// Выполняем завершение записи текста
		writer.finish();
		// Выполняем проверку собранного текста
		ASSERT_EQ(writer.text(), ">+\n  одна\n\n");
		// Выполняем проверку кругового хода записи с чтением
		ASSERT_EQ(roundtrip(writer.text()),
			"STREAM_START\nDOCUMENT_START\nSCALAR «одна\n\n»\nDOCUMENT_END\nSTREAM_END\n");
	}
}
/**
 * @brief Проверка отмены непечатных знаков Юникода
 *
 * @details Описанием текст печатными знаками и ограничен, и знак иной записывается лишь
 *          отменяющей последовательностью. Отмена идёт по знаку Юникода, а не по байту:
 *          знак `U+0081` записан байтами `C2 81`, из коих управляющим не является ни один
 *
 * @note Нашёл это ворошитель сличением перезаписи: знак проходил записью насквозь, а
 *       обратное чтение отвергало его недопустимым
 *
 */
TEST(CodecYamlWriter, Unprintable) {
	// Объект записи текста
	yaml::writer_t writer;
	// Выполняем запись значения со знаком области управления C1
	ASSERT_TRUE(writer.value(string("a\xC2\x81") + "b", yaml::style_t::DOUBLE));
	// Выполняем завершение записи текста
	ASSERT_TRUE(writer.finish());
	// Выполняем проверку отмены непечатного знака записью его кода
	ASSERT_EQ(writer.text(), "\"a\\x81b\"\n");
	// Выполняем проверку выбора двойной ограды по непечатному знаку
	ASSERT_EQ(yaml::quoting(string("a\xC2\x81") + "b", yaml::schema_t::CORE, false), yaml::style_t::DOUBLE);
}
