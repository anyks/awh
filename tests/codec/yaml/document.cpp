/**
 * @brief Проверка хвоста блочного значения при перезаписи удержанного текста
 *
 * @details Блок с сохранением хвоста несёт пустые строки за собою значением своим, и
 *          отдавать их записи соседа снизу нельзя: вместилище, по частям собираемое,
 *          выписывало их дважды - предисловием соседа и содержимым блока, - и значение
 *          блока читалось обратно на перевод строки длиннее
 *
 * @note Дословный перенос целым пролётом порока этого не открывает: пустая строка уходит в
 *       него ровно однажды. Оттого нужен снос, части вместилища по отдельности собирающий.
 *       Нашёл это ворошитель правкой дерева
 *
 */
TEST(CodecYamlDocument, RetainedEditKeepsHangingBlock) {
	// Настройки разбора текста с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Объект документа текста
	yaml::document_t document(::logger(), settings);
	// Выполняем проверку разбора записи текста
	ASSERT_TRUE(document.parse("- a\n- \n  - >+\n\n  - \n    - x\n  - y\n"));
	// Собираемое значение блока с сохранением хвоста
	string blocked;
	// Выполняем проверку извлечения значения блока
	ASSERT_TRUE(yaml::value_t(document.root()).at("/1/0").value(blocked));
	// Выполняем проверку того, что блок несёт один перевод строки
	ASSERT_EQ(blocked.size(), static_cast <size_t> (1));
	// Выполняем снос последней записи вложенного перечня
	ASSERT_TRUE(document.erase("/1/2"));
	// Получаем собранную запись текста
	const string result = document.dump();
	// Объект документа, перезапись читающий обратно
	yaml::document_t back(::logger(), settings);
	// Выполняем проверку разбора собранной записи текста
	ASSERT_TRUE(back.parse(result));
	// Значение блока, из перезаписи прочитанное
	string restored;
	// Выполняем проверку извлечения значения блока из перезаписи
	ASSERT_TRUE(yaml::value_t(back.root()).at("/1/0").value(restored));
	// Выполняем проверку того, что хвост блока перевода строки не приобрёл
	ASSERT_EQ(restored, blocked);
	// Выполняем проверку того, что дерево перезаписи прежнему равно
	ASSERT_TRUE(yaml::value_t(document.root()) == yaml::value_t(back.root()));
}

/**
 * @brief Проверка уровня вложенности при перезаписи текста с отброшенным повторным именем
 *
 * @details Отброшенное повторное имя пары строк своих из текста не убирает, а записью узла
 *          они уже не являются: граница записи соседа сверху перескакивала тогда разом и
 *          через них, и через черту записи следующей. Запись, значение какой стоит строкою
 *          ниже черты, лишалась её вовсе - и дословный перенос терял целый уровень
 *          вложенности: перечень о единственной записи обращался в само значение её
 *
 * @note Правило повторных имён обязано отбрасывать пару, а не отвергать текст: при отказе
 *       дерева не строится вовсе. Правка нужна лишь для того, чтобы вместилище собиралось
 *       по частям. Нашёл это ворошитель правкой дерева
 *
 */
TEST(CodecYamlDocument, RetainedRewriteKeepsLevelAfterDuplicate) {
	// Настройки разбора текста с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Устанавливаем правило, первое из повторных имён берущее
	settings.duplicates = yaml::duplicate_t::FIRST;
	// Объект документа текста
	yaml::document_t document(::logger(), settings);
	// Выполняем проверку разбора записи текста
	ASSERT_TRUE(document.parse("- [ 1\n ]\n- \n  k: false\n  k: |+\n- \n  - >-\n"));
	// Выполняем проверку того, что третья запись несёт перечень
	ASSERT_EQ(yaml::value_t(document.root()).at("/2").kind(), yaml::kind_t::SEQUENCE);
	// Выполняем снос значения из поточного построения первой записи
	ASSERT_TRUE(document.erase("/0/0"));
	// Получаем собранную запись текста
	const string result = document.dump();
	// Объект документа, перезапись читающий обратно
	yaml::document_t back(::logger(), settings);
	// Выполняем проверку разбора собранной записи текста
	ASSERT_TRUE(back.parse(result));
	// Выполняем проверку того, что третья запись перечня своего не лишилась
	ASSERT_EQ(yaml::value_t(back.root()).at("/2").kind(), yaml::kind_t::SEQUENCE);
	// Выполняем проверку того, что дерево перезаписи прежнему равно
	ASSERT_TRUE(yaml::value_t(document.root()) == yaml::value_t(back.root()));
}
