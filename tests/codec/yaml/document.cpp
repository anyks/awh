/**
 * @brief Проверка выбора признака обхождения с хвостом блочного значения
 *
 * @details Признак берётся тем, при каком содержимое возвращается тем же: отсекающий,
 * коль скоро переводом строки содержимое не оканчивается, простой - коль скоро
 * оканчивается ровно одним, и сохраняющий - коль скоро переводов в хвосте несколько либо
 * значение из них и составлено. Прежде сохраняющий брался при всяком переводе в хвосте, и
 * строка пустая, за блоком стоявшая, становилась содержимым его при обратном чтении -
 * блок забирал предисловие соседа снизу
 *
 * @note Значение, из одних переводов составленное, требует признака сохраняющего: простой
 *       обращает его в пустоту целиком, ибо усечение снимает хвост, коли снимать больше
 *       нечего. Нашёл это ворошитель круговым ходом снятого значения - и лишь по
 *       пересборке начисто: старый объектный файл нёс прежнее правило
 *
 */
TEST(CodecYamlDocument, BlockChompingChoice) {
	/**
	 * Выполняем перебор четырёх видов хвоста блочного значения
	 */
	for(const string & text : {string("a: |-\n  x\n"), string("a: |\n  x\n"),
	 string("a: |+\n  x\n\n"), string("a: |+\n  \n")}) {
		// Дерево документа с блочным значением
		yaml::document_t document(::logger());
		// Выполняем разбор текста с блочным значением
		ASSERT_TRUE(document.parse(text)) << "текст " << text;
		/**
		 * Если содержимое блока не одними переводами строк составлено
		 *
		 * @note Значение из одних переводов записывается строкою пустою без отступа:
		 *       отступ пустой строке безразличен, и запись выходит короче исходной. Байты
		 *       сличаются оттого лишь у записей канонических, а содержимое - у всех
		 */
		if(text.find("  \n") == string::npos)
			// Выполняем проверку того, что круговой ход запись сохраняет побайтово
			ASSERT_EQ(document.dump(), text) << "запись переменилась: " << document.dump();
		// Дерево документа, записанный текст разбирающее
		yaml::document_t back(::logger());
		// Выполняем разбор записанного текста
		ASSERT_TRUE(back.parse(document.dump())) << "текст " << text;
		// Выполняем проверку того, что содержимое блока круговой ход пережило
		ASSERT_EQ(back.root().at("/a").text(), document.root().at("/a").text())
			<< "содержимое блока переменилось: " << document.dump();
	}
}
