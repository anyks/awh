/**
 * @brief Проверка постройки дерева и обхода узлов его
 *
 */
TEST(CodecYamlDocument, Building) {
	// Объект дерева документа
	yaml::document_t doc;
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse("server:\n  host: alpha\n  ports:\n  - 80\n  - 443\nlevel: debug\n"));
	// Выполняем проверку количества документов текста
	ASSERT_EQ(doc.documents(), 1u);
	// Выполняем проверку вида корня документа
	ASSERT_EQ(doc.root().kind(), yaml::kind_t::MAPPING);
	// Выполняем проверку количества детей корня
	ASSERT_EQ(doc.root().size(), 2u);
	// Выполняем проверку вида вложенного отображения
	ASSERT_EQ(doc.root()["server"].kind(), yaml::kind_t::MAPPING);
	// Выполняем проверку вида вложенного перечня
	ASSERT_EQ(doc.root()["server"]["ports"].kind(), yaml::kind_t::SEQUENCE);
	// Выполняем проверку количества значений вложенного перечня
	ASSERT_EQ(doc.root()["server"]["ports"].size(), 2u);
	// Выполняем проверку записи первого значения перечня
	ASSERT_EQ(doc.root()["server"]["ports"][0].text(), "80");
	// Выполняем проверку записи второго значения перечня
	ASSERT_EQ(doc.root()["server"]["ports"][1].text(), "443");
	/**
	 * Выполняем проверку обхода детей вместилища соседями
	 *
	 * @note Указаний на родителя узел не несёт, а переход к соседу останавливается на
	 *       границе своего вместилища: без границы обход перечня продолжился бы соседом
	 *       родителя, и потребитель получил бы чужих детей своими
	 */
	{
		// Собираемый перечень имён детей корня
		string names;
		/**
		 * Выполняем перебор всех детей корня документа
		 */
		for(yaml::document_t::value_t child = doc.root().begin(); child.valid(); child = child.next()){
			/**
			 * Если имя ребёнка не первое
			 */
			if(!names.empty())
				// Выполняем добавление разделителя имён
				names.append(",");
			// Выполняем добавление имени очередного ребёнка
			names.append(child.name());
		}
		// Выполняем проверку собранного перечня имён детей корня
		ASSERT_EQ(names, "server,level");
	}
	// Выполняем проверку пути к узлу дерева
	ASSERT_EQ(doc.root().at("/server/host").text(), "alpha");
	// Выполняем проверку пути к значению перечня по номеру его
	ASSERT_EQ(doc.root().at("/server/ports/1").text(), "443");
	// Выполняем проверку недействительности ссылки на несуществующий узел
	ASSERT_FALSE(doc.root().at("/server/нет").valid());
	// Выполняем проверку недействительности ссылки на значение перечня за пределом
	ASSERT_FALSE(doc.root().at("/server/ports/9").valid());
}
/**
 * @brief Проверка извлечения значений затребованным видом
 *
 * @details Договор извлечения перенят у контейнера JSON дословно: ширина хранения
 * указанием не является, отказ приходит лишь на значение, числом не являющееся, а
 * сужение идёт приведением языка
 *
 */
TEST(CodecYamlDocument, Extraction) {
	// Объект дерева документа
	yaml::document_t doc;
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse(
		"порт: 8080\n"
		"отрицательное: -1250\n"
		"дробное: 0.5\n"
		"строка: значение\n"
		"признак: true\n"
		"пусто:\n"
		"большое: 99999999999999999999999999\n"
		"нечисло: .nan\n"));
	/**
	 * Выполняем проверку извлечения числа видами всех ширин
	 *
	 * @note Ширина хранения указанием не является: число, в два байта вместившееся,
	 *       извлекается и восемью байтами, и дробным видом
	 */
	{
		// Извлекаемое число восемью байтами
		int64_t wide = 0;
		// Выполняем проверку извлечения числа восемью байтами
		ASSERT_TRUE(doc.root()["порт"].value(wide));
		// Выполняем проверку извлечённого числа
		ASSERT_EQ(wide, 8080);
		// Извлекаемое число дробным видом
		double real = 0.;
		// Выполняем проверку извлечения числа дробным видом
		ASSERT_TRUE(doc.root()["порт"].value(real));
		// Выполняем проверку извлечённого числа
		ASSERT_DOUBLE_EQ(real, 8080.);
		/**
		 * Выполняем проверку сужения числа приведением языка
		 *
		 * @note Сужение идёт приведением языка, а не отказом: число 8080 в один байт не
		 *       вмещается, и приведение отсекает старшие разряды его. Тем договор этот от
		 *       строгого и разнится, и таков он у контейнера JSON
		 */
		uint8_t narrow = 0;
		// Выполняем проверку извлечения числа одним байтом
		ASSERT_TRUE(doc.root()["порт"].value(narrow));
		// Выполняем проверку суженного числа
		ASSERT_EQ(narrow, static_cast <uint8_t> (8080));
	}
	/**
	 * Выполняем проверку извлечения числа со знаком
	 */
	{
		// Извлекаемое число со знаком
		int32_t signed_ = 0;
		// Выполняем проверку извлечения числа со знаком
		ASSERT_TRUE(doc.root()["отрицательное"].value(signed_));
		// Выполняем проверку извлечённого числа со знаком
		ASSERT_EQ(signed_, -1250);
	}
	/**
	 * Выполняем проверку извлечения дробного числа
	 */
	{
		// Извлекаемое дробное число
		double real = 0.;
		// Выполняем проверку извлечения дробного числа
		ASSERT_TRUE(doc.root()["дробное"].value(real));
		// Выполняем проверку извлечённого дробного числа
		ASSERT_DOUBLE_EQ(real, 0.5);
	}
	/**
	 * Выполняем проверку извлечения числа, ни в один родной вид не вместимого
	 *
	 * @note Число такое хранится записью своей и выдаётся дробным приближением
	 */
	{
		// Извлекаемое дробное число
		double real = 0.;
		// Выполняем проверку вида числа, ни в один родной вид не вместимого
		ASSERT_EQ(doc.root()["большое"].type(), yaml::type_t::EXTENDED);
		// Выполняем проверку извлечения числа дробным приближением
		ASSERT_TRUE(doc.root()["большое"].value(real));
		// Выполняем проверку извлечённого дробного приближения
		ASSERT_DOUBLE_EQ(real, 1e26);
	}
	/**
	 * Выполняем проверку извлечения нечисловой величины целым видом
	 *
	 * @details Приведение `NaN` к целому есть неопределённое поведение при любом пределе:
	 * x86-64 выдаёт наименьшее целое, ARM64 - ноль. Выдаётся ноль, и выдаётся он успехом,
	 * а не отказом: `.nan` есть число по описанию, и отвергать его извлечением значило бы
	 * разойтись с контейнером JSON, где решено так же
	 */
	{
		// Извлекаемое целое число
		int32_t integer = 12345;
		// Выполняем проверку извлечения нечисловой величины целым видом
		ASSERT_TRUE(doc.root()["нечисло"].value(integer));
		// Выполняем проверку извлечённого нуля вместо нечисловой величины
		ASSERT_EQ(integer, 0);
		// Извлекаемое дробное число
		double real = 0.;
		// Выполняем проверку извлечения нечисловой величины дробным видом
		ASSERT_TRUE(doc.root()["нечисло"].value(real));
		// Выполняем проверку извлечённой нечисловой величины
		ASSERT_TRUE(::isnan(real));
	}
	/**
	 * Выполняем проверку извлечения логического значения
	 */
	{
		// Извлекаемое логическое значение
		bool truth = false;
		// Выполняем проверку извлечения логического значения
		ASSERT_TRUE(doc.root()["признак"].value(truth));
		// Выполняем проверку извлечённого логического значения
		ASSERT_TRUE(truth);
	}
	/**
	 * Выполняем проверку извлечения строкового значения
	 */
	{
		// Извлекаемое строковое значение
		string text;
		// Выполняем проверку извлечения строкового значения
		ASSERT_TRUE(doc.root()["строка"].value(text));
		// Выполняем проверку извлечённого строкового значения
		ASSERT_EQ(text, "значение");
	}
	/**
	 * Выполняем проверку отказов извлечения
	 *
	 * @note Отказ приходит лишь на значение, затребованным видом не являющееся: строка
	 *       числом не выдаётся, а вместилище строкою не выдаётся тоже
	 */
	{
		// Извлекаемое целое число
		int32_t integer = 0;
		// Выполняем проверку отказа извлечения строки числом
		ASSERT_FALSE(doc.root()["строка"].value(integer));
		// Выполняем проверку отказа извлечения пустого значения числом
		ASSERT_FALSE(doc.root()["пусто"].value(integer));
		// Извлекаемое логическое значение
		bool truth = false;
		// Выполняем проверку отказа извлечения числа логическим значением
		ASSERT_FALSE(doc.root()["порт"].value(truth));
		// Извлекаемое строковое значение
		string text;
		// Выполняем проверку отказа извлечения вместилища строкою
		ASSERT_FALSE(doc.root().value(text));
	}
}
/**
 * @brief Проверка сохранения записи значения, исходным текстом данной
 *
 * @details Запись числа удерживается узлом всегда, даже у числа, разобранного в родной
 * вид: перезапись обязана вернуть `0x1F` записью его, а не числом 31, и без записи
 * вернуть её было бы неоткуда
 *
 */
TEST(CodecYamlDocument, Records) {
	// Объект дерева документа
	yaml::document_t doc;
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse("шестнадцатеричное: 0x1F\nпоказательное: -2.5e-13\nдробное: 1.0\n"));
	// Выполняем проверку записи шестнадцатеричного числа
	ASSERT_EQ(doc.root()["шестнадцатеричное"].text(), "0x1F");
	// Выполняем проверку вида шестнадцатеричного числа
	ASSERT_EQ(doc.root()["шестнадцатеричное"].type(), yaml::type_t::UINT8);
	/**
	 * Выполняем проверку разобранного шестнадцатеричного числа
	 */
	{
		// Извлекаемое целое число
		int32_t integer = 0;
		// Выполняем проверку извлечения шестнадцатеричного числа
		ASSERT_TRUE(doc.root()["шестнадцатеричное"].value(integer));
		// Выполняем проверку извлечённого шестнадцатеричного числа
		ASSERT_EQ(integer, 31);
	}
	// Выполняем проверку перезаписи дерева документа
	ASSERT_EQ(doc.dump(), "шестнадцатеричное: 0x1F\nпоказательное: -2.5e-13\nдробное: 1.0\n");
}
/**
 * @brief Проверка раскрытия ссылок на объявленные метки
 *
 * @details Потоковое чтение ссылок не раскрывает вовсе, и раскрывает их дерево: там
 * поддерево метки уже удерживается, и раскрытие есть перенос узлов её
 *
 */
TEST(CodecYamlDocument, Aliases) {
	/**
	 * Выполняем проверку раскрытия ссылки на поддерево
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("основа: &я\n  host: alpha\n  port: 80\nвторой: *я\n"));
		// Выполняем проверку имени метки помеченного узла
		ASSERT_EQ(doc.root()["основа"].anchor(), "я");
		// Выполняем проверку вида раскрытого узла
		ASSERT_EQ(doc.root()["второй"].kind(), yaml::kind_t::MAPPING);
		// Выполняем проверку количества детей раскрытого узла
		ASSERT_EQ(doc.root()["второй"].size(), 2u);
		// Выполняем проверку содержимого раскрытого поддерева
		ASSERT_EQ(doc.root()["второй"]["host"].text(), "alpha");
		// Выполняем проверку второго значения раскрытого поддерева
		ASSERT_EQ(doc.root()["второй"]["port"].text(), "80");
		/**
		 * Выполняем проверку обхода за раскрытым поддеревом
		 *
		 * @note Размах поддерева раскрытия учтён объемлющим вместилищем, и переход к
		 *       соседу через раскрытие обязан вести к следующей паре, а не внутрь его
		 */
		ASSERT_FALSE(doc.root()["второй"].next().valid());
	}
	/**
	 * Выполняем проверку раскрытия ссылки на скалярное значение
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("основа: &я значение\nвторой: *я\n"));
		// Выполняем проверку содержимого раскрытого узла
		ASSERT_EQ(doc.root()["второй"].text(), "значение");
		// Выполняем проверку вида раскрытого узла
		ASSERT_EQ(doc.root()["второй"].type(), yaml::type_t::STRING);
	}
	/**
	 * Выполняем проверку предела количества узлов раскрытия
	 *
	 * @details Предел этот стережёт от беды, известной под именем миллиарда смешков:
	 * девять меток, каждая из которых десятикратно повторяет предыдущую, раскрываются в
	 * миллиард узлов из текста в двести байт
	 */
	{
		// Настройки разбора документа
		yaml::document_t::settings_t settings;
		// Устанавливаем наибольшее допустимое количество узлов раскрытия
		settings.expansion = 32;
		// Объект дерева документа
		yaml::document_t doc(settings);
		// Собираемый текст беды миллиарда смешков
		string text("первый: &a [x, x, x, x]\n");
		// Выполняем добавление второй метки, первую четырёхкратно повторяющей
		text.append("второй: &b [*a, *a, *a, *a]\n");
		// Выполняем добавление третьей метки, вторую четырёхкратно повторяющей
		text.append("третий: &c [*b, *b, *b, *b]\n");
		// Выполняем проверку отказа разбора беды миллиарда смешков
		ASSERT_FALSE(doc.parse(text));
		// Выполняем проверку кода ошибки разбора
		ASSERT_EQ(doc.error(), yaml::error_t::EXPANSION_EXCEEDED);
	}
}
/**
 * @brief Проверка потока документов текста
 *
 */
TEST(CodecYamlDocument, Documents) {
	// Объект дерева документа
	yaml::document_t doc;
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse("---\na: 1\n---\nb: 2\n---\n...\n"));
	/**
	 * Выполняем проверку количества документов текста
	 *
	 * @note Документ пустой описанием дозволен, и корень ему положен всё равно: без него
	 *       счёт документов разошёлся бы с числом их в тексте
	 */
	ASSERT_EQ(doc.documents(), 3u);
	// Выполняем проверку содержимого первого документа
	ASSERT_EQ(doc.root(0)["a"].text(), "1");
	// Выполняем проверку содержимого второго документа
	ASSERT_EQ(doc.root(1)["b"].text(), "2");
	// Выполняем проверку вида третьего документа
	ASSERT_EQ(doc.root(2).kind(), yaml::kind_t::NUL);
	// Выполняем проверку недействительности ссылки на несуществующий документ
	ASSERT_FALSE(doc.root(3).valid());
}
/**
 * @brief Проверка перезаписи дерева документа
 *
 */
TEST(CodecYamlDocument, Rewrite) {
	/**
	 * Выполняем проверку перезаписи вложенных построений
	 */
	{
		// Разбираемый текст документа
		const string text("server:\n  host: alpha\n  ports:\n  - 80\n  - 443\nlevel: debug\n");
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse(text));
		// Выполняем проверку перезаписи дерева документа
		ASSERT_EQ(doc.dump(), text);
	}
	/**
	 * Выполняем проверку перезаписи блочного значения
	 *
	 * @note Блочное значение записывается обратно блочным: ограда двойная передала бы
	 *       многострочный текст отменяющими последовательностями, и читающий человек в
	 *       записи той ничего бы не разобрал
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("текст: |\n  первая\n  вторая\n"));
		// Выполняем проверку перезаписи блочного значения
		ASSERT_EQ(doc.dump(), "текст: |+\n  первая\n  вторая\n");
	}
	/**
	 * Выполняем проверку перезаписи меток типов
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("строкой: !!str 12\nсвоя: !mine x\n"));
		// Выполняем проверку перезаписи меток типов
		ASSERT_EQ(doc.dump(), "строкой: !!str '12'\nсвоя: !mine x\n");
	}
	/**
	 * Выполняем проверку перезаписи пустых вместилищ
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("пусто: {}\nперечень: []\n"));
		// Выполняем проверку перезаписи пустых вместилищ
		ASSERT_EQ(doc.dump(), "пусто: {}\nперечень: []\n");
	}
	/**
	 * Выполняем проверку кругового хода перезаписи
	 *
	 * @details Перезаписанное разбирается вновь, и дерево второе сличается с первым:
	 * сличать один лишь текст мало - он подтвердил бы вид, но не читаемость
	 */
	{
		// Объект дерева первого разбора
		yaml::document_t first;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(first.parse("a: [1, два, {k: v}]\nb: &я значение\nc: *я\n"));
		// Объект дерева второго разбора
		yaml::document_t second;
		// Выполняем разбор перезаписанного текста в дерево документа
		ASSERT_TRUE(second.parse(first.dump()));
		// Выполняем проверку совпадения перезаписей обоих деревьев
		ASSERT_EQ(first.dump(), second.dump());
		// Выполняем проверку совпадения количества узлов обоих деревьев
		ASSERT_EQ(first.size(), second.size());
	}
}
/**
 * @brief Проверка отказов разбора дерева документа
 *
 */
TEST(CodecYamlDocument, Refusals) {
	/**
	 * Выполняем проверку отказа разбора текста
	 *
	 * @note Дерево строится настолько, насколько текст прочитан: потребителю оно скажет
	 *       больше, чем пустота, а положение отказа снимается с чтения тотчас
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем проверку отказа разбора незакрытой ограды
		ASSERT_FALSE(doc.parse("a: 1\nb: 'не закрыта\n"));
		// Выполняем проверку кода ошибки разбора
		ASSERT_EQ(doc.error(), yaml::error_t::UNTERMINATED_SCALAR);
		// Выполняем проверку строки, где отказ произошёл
		ASSERT_EQ(doc.location().line, 2u);
	}
	/**
	 * Выполняем проверку сброса дерева документа
	 */
	{
		// Объект дерева документа
		yaml::document_t doc;
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("a: 1\n"));
		// Выполняем проверку непустоты дерева документа
		ASSERT_FALSE(doc.empty());
		// Выполняем сброс дерева документа
		doc.clear();
		// Выполняем проверку пустоты сброшенного дерева
		ASSERT_TRUE(doc.empty());
		// Выполняем проверку количества документов сброшенного дерева
		ASSERT_EQ(doc.documents(), 0u);
		// Выполняем проверку недействительности ссылки на корень
		ASSERT_FALSE(doc.root().valid());
	}
}
