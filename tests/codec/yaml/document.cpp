/**
 * @brief Проверка предела количества узлов дерева
 *
 * @details Предел этот стережёт разрядность номера узла, а достижим он не длиною текста,
 *          а раскрытием ссылок: девять меток, каждая из которых десятикратно повторяет
 *          предыдущую, раскрываются в миллиард узлов из текста в двести байт. Беда эта
 *          известна под именем миллиарда смешков
 *
 * @note Проверка эта заведена оттого, что код отказа объявлен был, сообщением снабжён,
 *       а достижимость его не сличалась ничем: молчание неотличимо от согласия
 *
 */
TEST(CodecYamlDocument, NodeCountGuard) {
	// Собираемый текст, ссылками размножаемый
	string text("основа: &m0 [x, x, x, x, x, x, x, x, x, x]\n");
	/**
	 * Выполняем сборку меток, каждая из которых предыдущую десятикратно повторяет
	 *
	 * @note Восьми уровней довольно: они дают сто миллионов узлов при пределе в
	 *       шестьдесят семь миллионов, а текста занимают менее полукилобайта
	 */
	for(uint8_t i = 0; i < 8; i++){
		// Добавляем метку, предыдущую десятикратно повторяющую
		text.append("уровень" + std::to_string(i) + ": &m" + std::to_string(i + 1) + " [");
		/**
		 * Выполняем сборку десятикратного повторения предыдущей метки
		 */
		for(uint8_t j = 0; j < 10; j++)
			// Добавляем ссылку на предыдущую метку
			text.append((j > 0 ? ", *m" : "*m") + std::to_string(i));
		// Завершаем построение уровня
		text.append("]\n");
	}
	// Объект дерева документа
	yaml::document_t doc(::logger());
	/**
	 * Выполняем проверку отказа раскрытия ссылок пределом собственным
	 *
	 * @note Пределов здесь два, и они стоят порознь: раскрытие ограждается своим
	 *       пределом, настройкою поднимаемым, а предел количества узлов оградою
	 *       последней стоит на случай поднятия того предела выше него
	 */
	ASSERT_FALSE(doc.parse(text));
	// Выполняем проверку причины отказа разбора
	ASSERT_EQ(doc.error(), yaml::error_t::EXPANSION_EXCEEDED);
	/**
	 * @warning Ограда последняя - предел количества узлов - здесь НЕ сличается, и
	 *          говорится это прямо: достижима она лишь при пределе раскрытия, настройкою
	 *          выше неё поднятом, а дойти до неё значит завести шестьдесят семь миллионов
	 *          узлов взаправду. Проверка такая просит гигабайты памяти: на рабочей машине
	 *          она проходила, а у OpenBSD валилась нехваткой памяти. Молчаливо закрытое
	 *          неотличимо от проверенного, оттого несличаемое и объявлено здесь
	 */
	/**
	 * Выполняем проверку прохождения текста, ссылками умеренно размноженного
	 *
	 * @note Край сличается с обеих сторон: отказ, приходящий на всякий текст со
	 *       ссылками, был бы неотличим от отказа верного
	 */
	ASSERT_TRUE(doc.parse(
		"основа: &m [x, x, x]\n"
		"первый: [*m, *m, *m]\n"));
	// Выполняем проверку раскрытия ссылок в дереве
	ASSERT_EQ(doc.root()["первый"][0].size(), 3);
}

/**
 * @brief Проверка указателя имён пар отображения
 *
 * @details Отображению, у какого пар больше `INDEX_THRESHOLD`, при первом обращении по
 *          имени заводится указатель имён: без него обход отображения по именам
 *          квадратичен - замером на восьми тысячах пар он стоил девяти микросекунд на
 *          пару против одной на тысяче. Имена держатся в указателе видами на хранилище, и
 *          всякая правка дерева его обесценивает: перенос записи вправе переселить
 *          хранилище целиком, а вставка узла и снос его сдвигают номера. Проверка держит
 *          обе стороны - и розыск по указателю, и сброс его правкою
 *
 */
TEST(CodecYamlDocument, NamingIndex) {
	// Количество пар отображения, порог заведения указателя превышающее
	const size_t count = (static_cast <size_t> (yaml::INDEX_THRESHOLD) * 4);
	// Собираемый текст отображения
	string text;
	/**
	 * Выполняем сборку текста отображения
	 */
	for(size_t i = 0; i < count; i++)
		// Добавляем очередную пару отображения
		text.append("имя" + std::to_string(i) + ": " + std::to_string(i) + "\n");
	// Объект дерева документа
	yaml::document_t doc(::logger());
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse(text));
	/**
	 * Выполняем перебор всех пар отображения
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем проверку розыска очередной пары по имени её
		ASSERT_EQ(doc.root()["имя" + std::to_string(i)].text(), std::to_string(i)) << "пара " << i;
	// Выполняем проверку того, что имени небывалого не разыскивается
	ASSERT_FALSE(doc.root()["имя" + std::to_string(count)].valid());
	/**
	 * Выполняем проверку сброса указателя сносом узла, правке предшествующим
	 *
	 * @details Порядок здесь значим: правка значения сбрасывает указатель своим заходом,
	 *          и снос, за нею идущий, застаёт указатель уже пустым - сброс сносом
	 *          управления не получает вовсе. Проверяется он потому первым, покуда
	 *          указатель заведён розыском выше
	 *
	 * @note Снос сдвигает номера всех узлов за снесённым, а указатель держит именно номера
	 */
	{
		// Объект дерева документа, снос переживающего
		yaml::document_t pruned(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(pruned.parse(text));
		// Выполняем розыск пары по имени её, указатель заводящий
		ASSERT_EQ(pruned.root()["имя9"].text(), "9");
		// Выполняем снос пары отображения, указатель сбрасывающий
		ASSERT_TRUE(pruned.erase("/имя2"));
		// Выполняем проверку того, что снесённая пара не разыскивается
		ASSERT_FALSE(pruned.root()["имя2"].valid());
		// Выполняем проверку того, что пара за снесённою разыскивается верно
		ASSERT_EQ(pruned.root()["имя9"].text(), "9");
		// Выполняем проверку того, что пара до снесённой разыскивается верно
		ASSERT_EQ(pruned.root()["имя1"].text(), "1");
	}
	/**
	 * Выполняем проверку сброса указателя переносом записи в хранилище
	 *
	 * @note Правка значения переносит запись в хранилище, и то вправе переселиться целиком:
	 *       виды указателя обратились бы в висячие, а розыск по ним - в чтение чужой памяти
	 */
	ASSERT_TRUE(doc.set("/имя5", string_view("новое")));
	// Выполняем проверку розыска правленой пары по имени её
	ASSERT_EQ(doc.root()["имя5"].text(), "новое");
	// Выполняем проверку розыска соседней пары по имени её
	ASSERT_EQ(doc.root()["имя7"].text(), "7");
	/**
	 * Выполняем проверку сброса указателя сносом узла
	 *
	 * @note Снос сдвигает номера всех узлов за снесённым, а указатель держит именно номера
	 */
	ASSERT_TRUE(doc.erase("/имя3"));
	// Выполняем проверку того, что снесённая пара не разыскивается
	ASSERT_FALSE(doc.root()["имя3"].valid());
	/**
	 * Выполняем перебор всех пар отображения, снос переживших
	 */
	for(size_t i = 0; i < count; i++){
		// Пропускаем снесённую пару отображения
		if(i == 3)
			// Выполняем переход к следующей паре отображения
			continue;
		// Получаем ожидаемую запись значения очередной пары
		const string value((i == 5) ? "новое" : std::to_string(i));
		// Выполняем проверку розыска очередной пары по имени её
		ASSERT_EQ(doc.root()["имя" + std::to_string(i)].text(), value) << "пара " << i;
	}
	/**
	 * Выполняем проверку того, что указатель отвечает перебору один в один
	 *
	 * @note Сличается розыск выше порога с розыском ниже его: отображение то же самое,
	 *       и разница ответов означала бы, что указатель отдаёт не то, что перебор
	 */
	{
		// Собираемый текст отображения ниже порога заведения указателя
		string little;
		/**
		 * Выполняем сборку текста отображения ниже порога
		 */
		for(size_t i = 0; i < (static_cast <size_t> (yaml::INDEX_THRESHOLD) - 1); i++)
			// Добавляем очередную пару отображения
			little.append("имя" + std::to_string(i) + ": " + std::to_string(i) + "\n");
		// Объект дерева документа ниже порога заведения указателя
		yaml::document_t small(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(small.parse(little));
		/**
		 * Выполняем перебор всех пар отображения
		 */
		for(size_t i = 0; i < (static_cast <size_t> (yaml::INDEX_THRESHOLD) - 1); i++){
			/**
			 * Пропускаем пары, правкою выше тронутые
			 *
			 * @note Сличается способ розыска, а не содержимое: пары снесённая и правленая
			 *       разнятся у двух деревьев по существу, и разница та ни о чём не говорит
			 */
			if((i == 3) || (i == 5))
				// Выполняем переход к следующей паре отображения
				continue;
			// Выполняем проверку того, что перебор отвечает указателю
			ASSERT_EQ(small.root()["имя" + std::to_string(i)].text(), doc.root()["имя" + std::to_string(i)].text())
				<< "пара " << i;
		}
	}
}

/**
 * @brief Проверка записи числа, длиною всякий разумный предел превышающей
 *
 * @details Описание YAML длину записи числа не ограничивает вовсе, и запись в тысячи
 *          разрядов законна: удерживается она дословно видом EXTENDED. Предел, отдельно
 *          числу отведённый, отверг бы законный текст, а отвергнув его лишь при записи, а
 *          не при чтении, ещё и потерял бы значение при дословной перезаписи. Проверка
 *          закрепляет решение не заводить такого предела: длина записи числа стережётся
 *          общим пределом длины скалярного значения и только им
 *
 */
TEST(CodecYamlDocument, LongNumberRecord) {
	// Запись числа длиною в две тысячи разрядов
	string digits(2000, '7');
	// Настройки разбора дерева с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Объект дерева документа
	yaml::document_t doc(::logger(), settings);
	// Разбираемый текст с записью числа небывалой длины
	const string text = ("число: " + digits + "\n");
	// Выполняем разбор текста в дерево документа
	ASSERT_TRUE(doc.parse(text));
	// Выполняем проверку того, что число удержано видом расширенным
	ASSERT_EQ(doc.root()["число"].type(), yaml::type_t::EXTENDED);
	// Выполняем проверку того, что запись числа удержана дословно
	ASSERT_EQ(doc.root()["число"].text(), digits);
	// Выполняем проверку дословной перезаписи текста нетронутого
	ASSERT_EQ(doc.dump(), text);
	/**
	 * Выполняем проверку сборки текста заново, без удержания исходного
	 *
	 * @note Сборка заново идёт писателем, а не вырезкою из удержанного текста: предел,
	 *       записи числа отведённый, сказался бы именно здесь
	 */
	{
		// Объект дерева документа без удержания исходного текста
		yaml::document_t plain(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(plain.parse(text));
		// Выполняем проверку сборки текста по дереву
		ASSERT_EQ(plain.dump(), text);
	}
}

/**
 * @brief Проверка записи дерева при сносе повторной пары и удержании текста
 *
 * @details Правило «побеждает последняя» сносит пару прежнюю, а удержание исходного
 * текста переносит нетронутые узлы дословными пролётами. Граница записи узла кладётся
 * началом записи следующего, и пролёт узла, снесённой паре предшествующего, накрывал её
 * хвостом своим: дерево держало одно, а записывало другое - снесённая пара возвращалась
 * в текст
 *
 * @note Нашёл это ворошитель длинным прогоном. Правка дерева была ни при чём: хватало
 *       одной перезаписи разобранного
 *
 */
TEST(CodecYamlDocument, DuplicateRemovalUnderRetention) {
	// Настройки разбора с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Назначаем правило удержания последней пары отображения
	settings.duplicates = yaml::duplicate_t::LAST;
	// Дерево документа с повторяющимся именем пары
	yaml::document_t document(::logger());
	// Выполняем назначение настроек разбора
	document.settings(settings);
	// Выполняем разбор текста с повторяющимся именем пары
	ASSERT_TRUE(document.parse("0:\n- a\nname: b\nname: c\n"));
	// Выполняем проверку количества полей дерева
	ASSERT_EQ(document.root().size(), 2);
	// Выполняем проверку того, что удержана последняя пара
	ASSERT_EQ(document.root().at("/name").text(), "c");
	// Записанный текст дерева документа
	const string text = document.dump();
	/**
	 * Выполняем проверку того, что снесённая пара в текст не вернулась
	 *
	 * @note Ровно это и терялось: запись выдавала обе пары, тогда как дерево держало одну
	 */
	ASSERT_EQ(text.find("name: b"), string::npos) << "снесённая пара вернулась в текст: " << text;
	// Выполняем проверку того, что удержанная пара в тексте осталась
	ASSERT_NE(text.find("name: c"), string::npos);
	// Дерево документа, записанный текст разбирающее
	yaml::document_t back(::logger());
	// Выполняем назначение тех же настроек разбора
	back.settings(settings);
	// Выполняем разбор записанного текста
	ASSERT_TRUE(back.parse(text));
	// Выполняем проверку того, что чтение записи совпало с чтением дерева
	ASSERT_EQ(back.root().size(), document.root().size());
}
/**
 * @brief Проверка записи дерева при сносе среднего узла и удержании текста
 *
 * @details Того же рода, что и снос повторной пары, но приходит он не разбором, а
 * потребителем: снос узла из середины вместилища оставлял узел в тексте, а `erase`
 * притом отвечал успехом. Первый узел вместилища да последний проходили - границы их
 * записей упираются в края вместилища, - а средний накрывался хвостом соседа своего
 *
 * @note Нашёл это разбор кода, а не ворошитель: тот сличал лишь то, что правленый текст
 *       читается обратно, но не то, что правка в него попала. Поверка сноса в ворошитель
 *       добавлена
 *
 */
TEST(CodecYamlDocument, MiddleRemovalUnderRetention) {
	// Настройки разбора с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Дерево документа отображения о трёх парах
	yaml::document_t mapping(::logger());
	// Выполняем назначение настроек разбора
	mapping.settings(settings);
	// Выполняем разбор текста отображения о трёх парах
	ASSERT_TRUE(mapping.parse("one: 1\ntwo: 2\nthree: 3\n"));
	// Выполняем снос средней пары отображения
	ASSERT_TRUE(mapping.erase("/two"));
	// Записанный текст дерева отображения
	const string written = mapping.dump();
	/**
	 * Выполняем проверку того, что снесённая пара в текст не попала
	 *
	 * @note Ровно это и терялось: снос отвечал успехом, а пара оставалась в записи
	 */
	ASSERT_EQ(written.find("two: 2"), string::npos) << "снесённая пара осталась в тексте: " << written;
	// Выполняем проверку того, что соседи снесённой пары в тексте остались
	ASSERT_NE(written.find("one: 1"), string::npos);
	// Выполняем проверку того, что последняя пара в тексте осталась
	ASSERT_NE(written.find("three: 3"), string::npos);
	// Дерево документа перечня о трёх записях
	yaml::document_t sequence(::logger());
	// Выполняем назначение настроек разбора
	sequence.settings(settings);
	// Выполняем разбор текста перечня о трёх записях
	ASSERT_TRUE(sequence.parse("list:\n- a\n- b\n- c\nnext: 1\n"));
	// Выполняем снос средней записи перечня
	ASSERT_TRUE(sequence.erase("/list/1"));
	// Записанный текст дерева перечня
	const string listed = sequence.dump();
	// Выполняем проверку того, что снесённая запись в текст не попала
	ASSERT_EQ(listed.find("- b"), string::npos) << "снесённая запись осталась в тексте: " << listed;
	// Выполняем проверку того, что соседи снесённой записи в тексте остались
	ASSERT_NE(listed.find("- a"), string::npos);
	// Выполняем проверку того, что последняя запись перечня в тексте осталась
	ASSERT_NE(listed.find("- c"), string::npos);
	// Дерево документа, записанный текст перечня разбирающее
	yaml::document_t back(::logger());
	// Выполняем назначение тех же настроек разбора
	back.settings(settings);
	// Выполняем разбор записанного текста перечня
	ASSERT_TRUE(back.parse(listed));
	// Выполняем проверку количества записей перечня в прочитанном тексте
	ASSERT_EQ(back.root().at("/list").size(), 2);
}
/**
 * @brief Проверка записи дерева при сносе корня и удержании текста
 *
 * @details Удержанный текст выдаётся записью целиком, когда документов он не несёт:
 * текст, одни директивы да примечания несущий, документа не открывает вовсе, и собирать
 * по дереву нечего. Снос же последнего корня перечень корней опустошает по причине
 * совсем иной - и текст возвращался целиком, из дерева снесённый: дерево пустело, а
 * запись выдавала прежний текст дословно
 *
 * @note Нашёл это ворошитель поверкою состоявшегося сноса, длинным прогоном
 *
 */
TEST(CodecYamlDocument, RootRemovalUnderRetention) {
	// Настройки разбора с удержанием исходного текста
	yaml::document_t::settings_t settings;
	// Устанавливаем удержание исходного текста
	settings.retain = true;
	// Дерево документа отображения о двух парах
	yaml::document_t mapping(::logger());
	// Выполняем назначение настроек разбора
	mapping.settings(settings);
	// Выполняем разбор текста отображения о двух парах
	ASSERT_TRUE(mapping.parse("a: 1\nb: 2\n"));
	// Выполняем снос корня документа
	ASSERT_TRUE(mapping.erase("/"));
	// Выполняем проверку того, что дерево опустело
	ASSERT_EQ(mapping.root().size(), 0);
	/**
	 * Выполняем проверку того, что запись опустела вместе с деревом
	 *
	 * @note Ровно это и терялось: дерево пустело, а запись выдавала прежний текст целиком
	 */
	ASSERT_TRUE(mapping.dump().empty()) << "снесённый документ остался в тексте: " << mapping.dump();
	// Дерево документа перечня о двух записях
	yaml::document_t sequence(::logger());
	// Выполняем назначение настроек разбора
	sequence.settings(settings);
	// Выполняем разбор текста перечня о двух записях
	ASSERT_TRUE(sequence.parse("- x\n- y\n"));
	// Выполняем снос корня документа
	ASSERT_TRUE(sequence.erase("/"));
	// Выполняем проверку того, что запись опустела вместе с деревом
	ASSERT_TRUE(sequence.dump().empty()) << "снесённый документ остался в тексте: " << sequence.dump();
	// Дерево документа, одни примечания несущего
	yaml::document_t bare(::logger());
	// Выполняем назначение настроек разбора
	bare.settings(settings);
	/**
	 * Выполняем разбор текста, документа не открывающего
	 *
	 * @note Текст этот записью выдаётся дословно, и снос корня его не касается: корня у
	 *       него нет вовсе, а удержанные байты его - всё, что запись имеет сказать
	 */
	ASSERT_TRUE(bare.parse("# одно примечание\n"));
	// Выполняем проверку того, что текст без документов записью удержан
	ASSERT_EQ(bare.dump(), "# одно примечание\n");
}
/**
 * @brief Проверка снятия метки типа при установке значения
 *
 * @details Метка описывает значение прежнее, а его потребитель заменил своим и метки не
 * подавал. Держать её значит лгать: запись `!!str` да метка неопределённая `!`
 * разрешение по содержимому запрещают, и поставленное число обратным чтением
 * возвращалось строкою - дерево держало число, а текст говорил строку
 *
 * @note Якорь при этом остаётся: его зовут ссылки иных узлов, и снятие его порвало бы их
 *
 */
TEST(CodecYamlDocument, TagDroppedOnAssignment) {
	/**
	 * Выполняем перебор трёх меток, установке значения противоречащих
	 */
	for(const string & tag : {string("!"), string("!!str")}) {
		// Дерево документа с меткою типа у пары
		yaml::document_t document(::logger());
		/**
		 * Выполняем разбор текста с меткою типа у пары
		 *
		 * @note Метка `!!int` сюда не берётся: записи `x` она противоречит, и разбор
		 *       отвергает такой текст сам - проверять на нём нечего
		 */
		ASSERT_TRUE(document.parse("a: " + tag + " x\n")) << "метка " << tag;
		// Выполняем установку целого значения по пути к паре
		ASSERT_TRUE(document.set("/a", static_cast <int64_t> (-1250))) << "метка " << tag;
		// Дерево документа, записанный текст разбирающее
		yaml::document_t back(::logger());
		// Выполняем разбор записанного текста
		ASSERT_TRUE(back.parse(document.dump())) << "метка " << tag;
		/**
		 * Выполняем проверку того, что обратное чтение число числом и вернуло
		 *
		 * @note Ровно это и терялось: метка переживала правку, и число возвращалось строкою
		 */
		ASSERT_EQ(back.root().at("/a").kind(), yaml::kind_t::NUMBER)
			<< "метка " << tag << " пережила правку: " << document.dump();
	}
	// Дерево документа с якорем и меткою типа у пары
	yaml::document_t anchored(::logger());
	// Выполняем разбор текста с якорем, меткою и ссылкою на якорь
	ASSERT_TRUE(anchored.parse("a: &якорь !!str x\nb: *якорь\n"));
	// Выполняем установку целого значения по пути к паре с якорем
	ASSERT_TRUE(anchored.set("/a", static_cast <int64_t> (7)));
	// Записанный текст дерева документа
	const string written = anchored.dump();
	// Выполняем проверку того, что метка типа с узла снята
	ASSERT_EQ(written.find("!!str"), string::npos) << "метка пережила правку: " << written;
	/**
	 * Выполняем проверку того, что якорь узла остался
	 *
	 * @note Снятие якоря порвало бы ссылку на него, стоящую ниже
	 */
	ASSERT_NE(written.find("&якорь"), string::npos) << "якорь снят вместе с меткою: " << written;
	// Дерево документа, объявляемое вместилищем поверх метки
	yaml::document_t arranged(::logger());
	// Выполняем разбор текста с меткою типа у пары
	ASSERT_TRUE(arranged.parse("a: !!str x\n"));
	// Выполняем объявление узла отображением пар
	ASSERT_TRUE(arranged.arrange("/a"));
	// Выполняем проверку того, что метка типа с объявленного вместилища снята
	ASSERT_EQ(arranged.dump().find("!!str"), string::npos)
		<< "метка пережила объявление вместилища: " << arranged.dump();
}
