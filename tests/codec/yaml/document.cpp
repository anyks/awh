/**
 * @brief Проверка того, что ссылка на узел перестроения дерева не переживает
 *
 * @details Ссылка на узел держит НОМЕР его в перечне узлов, а разбор, чтение, очистка и
 * правка номера смещают. Ссылка, перестроение пережившая, указывала бы на совсем другой
 * узел нового дерева - и отвечала бы ГОДНОЙ, отдавая правдоподобное чужое содержимое
 *
 * @details Беда эта худшего вида: ни кода отказа, ни падения, ни признака. Замерено до
 * правки: узел «первый», снятый до повторного разбора, отвечал годным и отдавал
 * содержимое «другое» - значение совсем иного документа
 *
 * @note Лечится клеймом поколения: дерево растит счёт при всякой работе, перечень узлов
 *       перестраивающей, ссылка снимает клеймо при заведении, а действительность
 *       сличает. Клеймо снимается В САМОМ ЗАВОДИТЕЛЕ ссылки, оттого ни одно из мест её
 *       заведения править не пришлось
 *
 * @warning Беду эту нашёл Василий у кодеков JSON и XML и передал соседям
 *
 */
TEST(CodecYamlDocument, ReferenceDoesNotSurviveRebuild) {
	/**
	 * Выполняем проверку того, что повторный разбор ссылку обрывает
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("первый: значение\nвторой: иное\n"));
		// Снимаем ссылку на узел дерева
		const yaml::document_t::value_t node = doc.root().at("/первый");
		// Выполняем проверку того, что ссылка действительна
		ASSERT_TRUE(node.valid());
		// Выполняем проверку содержимого узла
		ASSERT_EQ(node.text(), "значение");
		// Выполняем разбор поверх совсем другого текста
		ASSERT_TRUE(doc.parse("совсем: другое\nтретий: третье\nчетвёртый: ещё\n"));
		/**
		 * Выполняем проверку того, что ссылка перестроение не пережила
		 *
		 * @note Номер её остался в пределах перечня - узлов в новом дереве больше, - и
		 *       без клейма она отвечала бы годной, отдавая содержимое «другое»
		 */
		ASSERT_FALSE(node.valid());
	}
	/**
	 * Выполняем проверку того, что очистка ссылку обрывает
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("а: 1\nб: 2\nв: 3\n"));
		// Снимаем ссылку на узел дерева
		const yaml::document_t::value_t node = doc.root().at("/в");
		// Выполняем проверку того, что ссылка действительна
		ASSERT_TRUE(node.valid());
		// Выполняем очистку дерева документа
		doc.clear();
		// Выполняем проверку того, что ссылка очистку не пережила
		ASSERT_FALSE(node.valid());
	}
	/**
	 * Выполняем проверку того, что правка дерева ссылку обрывает
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("а: 1\nб: 2\n"));
		// Снимаем ссылку на узел дерева
		const yaml::document_t::value_t node = doc.root().at("/б");
		// Выполняем проверку того, что ссылка действительна
		ASSERT_TRUE(node.valid());
		// Выполняем заведение недостающей пары отображения
		ASSERT_TRUE(doc.set("/в", static_cast <int64_t> (3)));
		// Выполняем проверку того, что ссылка правку не пережила
		ASSERT_FALSE(node.valid());
	}
	/**
	 * Выполняем проверку того, что прививка значения ссылку обрывает
	 *
	 * @warning Прививку клеймить надлежит ОТДЕЛЬНО: у соседних кодеков она через очистку
	 *          не проходит, а нумерацию правит. У YAML она клеймо задевает - замерено
	 *          щупом на дереве, прививкой УВЕЛИЧЕННОМ: без клейма номер остался бы в
	 *          пределах перечня, и ссылка отвечала бы годной
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("а: 1\nб: 2\n"));
		// Снимаем ссылку на узел дерева
		const yaml::document_t::value_t node = doc.root().at("/б");
		// Выполняем проверку того, что ссылка действительна
		ASSERT_TRUE(node.valid());
		// Владеющее значение, прививаемое к дереву
		yaml::value_t value;
		// Выполняем разбор текста в владеющее значение
		ASSERT_TRUE(value.parse("совсем: другое\nещё: третье\nчетыре: пять\n"));
		// Выполняем прививку значения к дереву документа
		ASSERT_TRUE(value.graft(doc));
		// Выполняем проверку того, что ссылка прививку не пережила
		ASSERT_FALSE(node.valid());
	}
	/**
	 * Выполняем проверку того, что пометка узла правленым ссылку НЕ обрывает
	 *
	 * @note Работа эта перечня узлов не перестраивает, и клейма не трогает: ссылка
	 *       приходит к ней доводом, и обрыв обесценил бы её же
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("а: 1\nб: 2\n"));
		// Снимаем ссылку на узел дерева
		const yaml::document_t::value_t node = doc.root().at("/б");
		// Выполняем пометку узла правленым
		ASSERT_TRUE(doc.touch(node));
		// Выполняем проверку того, что ссылка пометку пережила
		ASSERT_TRUE(node.valid());
	}
}
