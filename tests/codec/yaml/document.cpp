/**
 * @brief Проверка перезаписи дерева документа
 *
 */
TEST(CodecYamlDocument, Rewrite) {
	/**
	 * Выполняем проверку перезаписи вложенных построений
	 */
	{
		// Разбираемый текст документа
		const string text("server:\n  host: alpha\n  ports:\n  - 80\n  - 443\nlevel: debug\n");
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse(text));
		// Выполняем проверку перезаписи дерева документа
		ASSERT_EQ(doc.dump(), text);
	}
	/**
	 * Выполняем проверку перезаписи блочного значения
	 *
	 * @note Блочное значение записывается обратно блочным: ограда двойная передала бы
	 *       многострочный текст отменяющими последовательностями, и читающий человек в
	 *       записи той ничего бы не разобрал
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("текст: |\n  первая\n  вторая\n"));
		/**
		 * Выполняем проверку перезаписи блочного значения
		 *
		 * @note Ожидалась здесь прежде запись с признаком сохранения хвоста - `|+`, -
		 *       и договор с той поры ужесточён: признак берётся ныне по числу переводов
		 *       строки в хвосте значения, а один перевод даёт признак простой. Прежнее
		 *       правило брало сохраняющий при всяком переводе, и строка пустая, за блоком
		 *       стоявшая, становилась содержимым его при обратном чтении - блок забирал
		 *       предисловие соседа снизу. Круговой ход притом запись менял, а ныне
		 *       сохраняет её побайтово
		 */
		ASSERT_EQ(doc.dump(), "текст: |\n  первая\n  вторая\n");
	}
	/**
	 * Выполняем проверку перезаписи меток типов
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("строкой: !!str 12\nсвоя: !mine x\n"));
		// Выполняем проверку перезаписи меток типов
		ASSERT_EQ(doc.dump(), "строкой: !!str '12'\nсвоя: !mine x\n");
	}
	/**
	 * Выполняем проверку перезаписи пустых вместилищ
	 */
	{
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(doc.parse("пусто: {}\nперечень: []\n"));
		// Выполняем проверку перезаписи пустых вместилищ
		ASSERT_EQ(doc.dump(), "пусто: {}\nперечень: []\n");
	}
	/**
	 * Выполняем проверку кругового хода перезаписи
	 *
	 * @details Перезаписанное разбирается вновь, и дерево второе сличается с первым:
	 * сличать один лишь текст мало - он подтвердил бы вид, но не читаемость
	 */
	{
		// Объект дерева первого разбора
		yaml::document_t first(::logger());
		// Выполняем разбор текста в дерево документа
		ASSERT_TRUE(first.parse("a: [1, два, {k: v}]\nb: &я значение\nc: *я\n"));
		// Объект дерева второго разбора
		yaml::document_t second(::logger());
		// Выполняем разбор перезаписанного текста в дерево документа
		ASSERT_TRUE(second.parse(first.dump()));
		// Выполняем проверку совпадения перезаписей обоих деревьев
		ASSERT_EQ(first.dump(), second.dump());
		// Выполняем проверку совпадения количества узлов обоих деревьев
		ASSERT_EQ(first.size(), second.size());
	}
}
