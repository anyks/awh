/**
 * @brief Проверка возврата директивы наречия каждому документу потока
 *
 * @details Директива есть принадлежность документа, а не потока, и стоять она обязана
 *          перед каждою чертою начала своею. Прежде перезапись возвращала её лишь
 *          потоку об одном документе, а поток из нескольких терял её вовсе: записи
 *          вроде `on` возвращались тогда строками, и перезапись меняла смысл документа
 *
 */
TEST(CodecYamlDocument, StreamDirectives) {
	// Разбираемые тексты потоков, директивы наречия несущие
	const vector <string> records = {
		"%YAML 1.1\n---\nx: on\n...\n%YAML 1.2\n---\ny: on\n...\n",
		"%YAML 1.1\n---\nx: on\n...\n---\ny: on\n...\n",
		"---\nx: on\n...\n%YAML 1.1\n---\ny: on\n...\n"
	};
	/**
	 * Выполняем перебор всех разбираемых текстов
	 */
	for(const string & record : records){
		// Объект дерева документа
		yaml::document_t doc(::logger());
		// Выполняем разбор потока в дерево документа
		ASSERT_TRUE(doc.parse(record)) << record;
		// Выполняем проверку количества документов потока
		ASSERT_EQ(doc.documents(), 2) << record;
		// Получаем перезапись дерева документа
		const string out = doc.dump();
		// Объект дерева перезаписанного потока
		yaml::document_t back(::logger());
		// Выполняем проверку того, что перезапись читается обратно
		ASSERT_TRUE(back.parse(out)) << out << " ← " << record;
		// Выполняем проверку сохранения количества документов потока
		ASSERT_EQ(back.documents(), 2) << out;
		/**
		 * Выполняем перебор всех документов потока
		 */
		for(size_t i = 0; i < doc.documents(); i++){
			/**
			 * Выполняем перебор всех полей очередного документа
			 */
			for(size_t j = 0; j < doc.root(i).size(); j++)
				// Выполняем проверку того, что вид значения круговым ходом сохранён
				ASSERT_EQ(doc.root(i)[j].type(), back.root(i)[j].type()) << out;
		}
	}
	// Объект дерева документа
	yaml::document_t doc(::logger());
	// Выполняем разбор потока, наречие 1.1 второму документу объявляющего
	ASSERT_TRUE(doc.parse("---\nx: on\n...\n%YAML 1.1\n---\ny: on\n...\n"));
	// Получаем перезапись дерева документа
	const string out = doc.dump();
	// Выполняем проверку того, что директива стоит у документа второго
	ASSERT_NE(out.find("%YAML 1.1"), string::npos) << out;
	/**
	 * Выполняем проверку того, что документ первый директивы не получил
	 *
	 * @note Навязывать директиву тексту, её не имевшему, значило бы менять написание
	 *       там, где потребитель ничего не менял
	 */
	ASSERT_EQ(out.find("%YAML"), out.rfind("%YAML")) << out;
	/**
	 * Выполняем проверку того, что документ прежний закрыт чертою конца
	 *
	 * @note Директива, за содержимым документа прежнего стоящая, читается отказом:
	 *       конец потока директив помечает черта `...`
	 */
	ASSERT_LT(out.find("...\n"), out.find("%YAML 1.1")) << out;
}
