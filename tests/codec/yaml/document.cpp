/**
 * @brief Проверка границы предела раскрытия ссылок на метку узла
 *
 * @details Предел раскрытия стережёт от беды, известной под именем миллиарда смешков,
 *          и сличение ведёт строгое: раскрытие принимается, покуда сумма узлов с
 *          протяжённостью раскрываемого предела НЕ ПРЕВЫШАЕТ. Граница эта охватом не
 *          видна вовсе - охват строгое сравнение от нестрогого отличить не в силах, -
 *          и подмена «>» на «>=» набор проверок не роняла: она отняла бы у потребителя
 *          ровно одно раскрытие из дозволенных, а текст, пределом отмеренный впритык,
 *          стал бы отвергаться
 *
 * @note Число девять взято замером: текст этот раскрывается ровно в девять узлов, и
 *       записано оно здесь ЧИСЛОМ, а не розыском наименьшего годного предела. Розыск
 *       сдвинулся бы вместе с правкой сличения и границы не стерёг бы вовсе
 *
 */
TEST(CodecYamlDocument, ExpansionLimitBoundary) {
	// Разбираемый текст с меткою узла и ссылкою на неё
	const string text = "a: &я [1, 2, 3]\nb: *я\n";
	// Предел раскрытия, тексту этому потребный
	const size_t needed = 9;
	/**
	 * Выполняем проверку разбора при пределе, потребному равном
	 */
	{
		// Настройки дерева документа
		yaml::document_t::settings_t settings;
		// Задаём предел раскрытия, потребному равный
		settings.maxExpansion = needed;
		// Объект дерева документа
		yaml::document_t document(::logger());
		// Выполняем установку настроек дерева документа
		document.settings(settings);
		// Выполняем проверку того, что предел, потребному равный, разбор принимает
		ASSERT_TRUE(document.parse(text));
		// Выполняем проверку того, что ссылка раскрыта перечнем
		ASSERT_EQ(document.root()["b"].kind(), yaml::kind_t::SEQUENCE);
	}
	/**
	 * Выполняем проверку отказа при пределе, потребного на единицу меньшем
	 */
	{
		// Настройки дерева документа
		yaml::document_t::settings_t settings;
		// Задаём предел раскрытия, потребного на единицу меньший
		settings.maxExpansion = (needed - 1);
		// Объект дерева документа
		yaml::document_t document(::logger());
		// Выполняем установку настроек дерева документа
		document.settings(settings);
		// Выполняем проверку отказа разбора текста
		ASSERT_FALSE(document.parse(text));
		// Выполняем проверку выданного кода ошибки разбора
		ASSERT_EQ(document.error(), yaml::error_t::EXPANSION_EXCEEDED);
	}
}
