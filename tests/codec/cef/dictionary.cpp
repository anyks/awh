/**
 * @brief Проверка полноты пар «ключ - метка» у настраиваемых полей
 *
 * @details Настраиваемые поля - «cs», «cn», «cfp», «c6a» - объявляются парою: сам ключ и
 *          метка его человеческого имени. Пропуск метки тише всего прочего: словарь на
 *          175 записей глазом не сличишь, а розыск по недостающему ключу отвечает
 *          отсутствием - ровно так же, как по ключу выдуманному
 *
 * @warning Аудит 14.09.2026 нашёл счётом ДВЕ беды разом, обе в парах: метки «c6a2Label»
 *          не было вовсе при налицо метках 1, 3 и 4; а полное имя «cfp2Label» несло
 *          лишний пробел - «deviceCustomFloatingPoint2 Label», - отчего розыск по
 *          полному имени его не находил. Опечатка эта живёт и в самом описании ArcSight,
 *          но сторонние разборщики её исправляют, и мы вслед за ними
 *
 * @note Полное имя метки обязано быть именем ключа с приставкою «Label» - тем самым
 *       проверяется и пропуск, и опечатка одним правилом
 *
 */
TEST(CodecCefDictionary, LabelPairsAreComplete) {
	/**
	 * Выполняем перебор всех записей словаря расширений
	 */
	for(size_t i = 0; i < cef::dictionary::size(); i++){
		// Получаем очередную запись словаря расширений
		const cef::entry_t * entry = cef::dictionary::at(i);
		// Получаем ключ очередной записи словаря
		const string key(entry->key);
		// Если ключ меткой является
		if(key.size() > 5 && (key.compare(key.size() - 5, 5, "Label") == 0))
			// Переходим к следующей записи словаря
			continue;
		// Если ключ настраиваемым полем не является
		if(key.empty() || (key.back() < '1') || (key.back() > '9'))
			// Переходим к следующей записи словаря
			continue;
		// Получаем основание ключа настраиваемого поля
		const string base = key.substr(0, key.size() - 1);
		// Если основание ключа настраиваемым полем не является
		if((base != "cs") && (base != "cn") && (base != "cfp") && (base != "c6a"))
			// Переходим к следующей записи словаря
			continue;
		// Выполняем розыск метки настраиваемого поля
		const cef::entry_t * label = cef::dictionary::find(key + "Label");
		// Выполняем проверку наличия метки у настраиваемого поля
		ASSERT_NE(label, nullptr) << "у ключа \"" << key << "\" нет метки \"" << key << "Label\"";
		// Выполняем проверку того, что полное имя метки есть имя ключа с приставкой
		EXPECT_EQ(string(label->name), string(entry->name) + "Label")
			<< "полное имя метки \"" << key << "Label\" расходится с именем ключа";
	}
}
