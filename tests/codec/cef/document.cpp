	ASSERT_TRUE(document.parse("CEF:0|security|threatmanager|1.0|100|detected|10|cn1=42 cfp1=0.5 src=10.0.0.1"))
		<< static_cast <uint32_t> (document.error());
	// Целое значение, деревом объявленное
	int64_t integer = 0;
	// Выполняем извлечение целого значения из дерева
	ASSERT_TRUE(document.at("/extension/cn1").value(integer));
	// Выполняем проверку того, что целое значение прочтено числом
	EXPECT_EQ(integer, static_cast <int64_t> (42));
	// Дробное значение, деревом объявленное
	double number = 0.;
	// Выполняем извлечение дробного значения из дерева
	ASSERT_TRUE(document.at("/extension/cfp1").value(number));
