/**
 * @brief Проверка того, что объявленные коды отказа выставляются на деле
 *
 * @details Код отказа, перечнем объявленный и нигде не выставляемый, есть мёртвое
 *          обещание: потребитель пишет его разбор впустую, а поверить того нечем.
 *          Проверка эта держит три таких кода живыми
 *
 */
TEST(CodecCefDocument, DeclaredRefusalsAreActuallyRaised) {
	// Объект события CEF
	cef::document_t doc;
	// Настройки укладки записей в дерево
	cef::reader_t::settings_t settings;
	// Устанавливаем сличение имён ключей и всех видов значений
	settings.mode = cef::mode_t::STRONG;
	// Устанавливаем настройки укладки записей в дерево
	ASSERT_TRUE(doc.settings(settings));
	/**
	 * Редакция описания, разбору неведомая, отвергается, а не разбирается на удачу
	 */
	EXPECT_FALSE(doc.parse("CEF:9|A|B|1|sig|name|5|src=1.2.3.4"));
	// Выполняем проверку кода отказа неподдерживаемой редакцией
	EXPECT_EQ(doc.error(), cef::error_t::UNSUPPORTED_VERSION);
	/**
	 * Обязательное поле заголовка пустым быть не может при сличении
	 */
	EXPECT_FALSE(doc.parse("CEF:0|A||1|sig|name|5|src=1.2.3.4"));
	// Выполняем проверку кода отказа пустым полем заголовка
	EXPECT_EQ(doc.error(), cef::error_t::EMPTY_HEADER_FIELD);
	/**
	 * Метка имени без самого поля есть беспризорная метка
	 */
	EXPECT_FALSE(doc.parse("CEF:0|A|B|1|sig|name|5|cs1Label=IDSClass src=1.2.3.4"));
	// Выполняем проверку кода отказа беспризорной меткой
	EXPECT_EQ(doc.error(), cef::error_t::DANGLING_LABEL);
	/**
	 * Метка вместе со своим полем беспризорной не является
	 */
	EXPECT_TRUE(doc.parse("CEF:0|A|B|1|sig|name|5|cs1=x cs1Label=IDSClass src=1.2.3.4"));
	/**
	 * Выполняем установку отказа от сличения со словарём
	 *
	 * @note Без сличения журнал берётся КАК ЕСТЬ: живые устройства пишут и пустые поля
	 *       заголовка, и беспризорные метки, и отвергать такую запись было бы отказом
	 *       в работе, ради которой настройка эта и заведена
	 */
	settings.mode = cef::mode_t::NONE;
	// Устанавливаем настройки укладки записей в дерево
	ASSERT_TRUE(doc.settings(settings));
	// Выполняем проверку приёма записи с пустым полем заголовка
	EXPECT_TRUE(doc.parse("CEF:0|A||1|sig|name|5|src=1.2.3.4"));
	// Выполняем проверку приёма записи с беспризорной меткой
	EXPECT_TRUE(doc.parse("CEF:0|A|B|1|sig|name|5|cs1Label=IDSClass src=1.2.3.4"));
	/**
	 * Редакция же отвергается ВСЕГДА: устройство заголовка ею и задаётся, и разбирать
	 * неведомую редакцию было бы гаданием, а не снисходительностью
	 */
	EXPECT_FALSE(doc.parse("CEF:9|A|B|1|sig|name|5|src=1.2.3.4"));
	// Выполняем проверку кода отказа неподдерживаемой редакцией
	EXPECT_EQ(doc.error(), cef::error_t::UNSUPPORTED_VERSION);
}

/**
 * @brief Проверка того, что каталог, поданный вместо файла, отвергается
 *
 * @details Каталог на POSIX открывается потоком УСПЕШНО и читается признаками конца -
 *          теми же, какими отзывается пустой файл. Кодек, каталога не распознавший,
 *          принимает его за файл пустой и отвечает ИСТИНОЙ с пустым деревом: ложный
 *          успех вместо отказа, отличить какой потребителю нечем
 *
 * @note Проверка стоит ЗДЕСЬ, а не только в наборе сличения кодеков: набор тот требует
 *       собранной третьей стороны и на отладочных машинах неприменим вовсе - отдаёт код
 *       77, - а поведение это от системы ЗАВИСИТ: у MS Windows каталог потоком не
 *       открывается, и заслон, поставленный после открытия, был бы там мёртв. Восемь
 *       систем раскладки поверяют его отсюда
 *
 * @note Половина проверки отдана обратному: годный файл обязан читаться по-прежнему. Без
 *       неё «отказ на каталоге» достигался бы отказом на всяком пути вовсе
 *
 */
TEST(CodecCefDocument, DirectoryIsRefused) {
	// Адрес заводимого каталога подачи
	const string directory = "./cef-directory-probe";
	// Выполняем снос каталога от прежнего прогона
	::rmdir(directory.c_str());
	// Выполняем заведение каталога подачи
	ASSERT_EQ(::mkdir(directory.c_str(), 0755), 0);
	// Объект события CEF
	cef::document_t document;
	// Выполняем проверку отказа чтения каталога, поданного вместо файла
	EXPECT_FALSE(document.load(directory));
	// Выполняем проверку того, что отказ назван кодом чтения файла
	EXPECT_EQ(document.error(), cef::error_t::FILE_NOT_READ);
	// Выполняем снос заведённого каталога
	::rmdir(directory.c_str());
	// Адрес заводимого файла записи событий безопасности
	const string filename = "./cef-directory-probe.log";
	// Объект события CEF для записи в файл
	cef::document_t source;
	// Выполняем чтение записи событий безопасности деревом события
	ASSERT_TRUE(source.parse("CEF:0|security|threatmanager|1.0|100|detected|10|src=10.0.0.1"));
	// Выполняем запись события в файл
	ASSERT_TRUE(source.save(filename));
	// Объект события CEF для чтения из файла
	cef::document_t target;
	// Выполняем проверку успешности чтения годного файла
	ASSERT_TRUE(target.load(filename)) << static_cast <uint32_t> (target.error());
	// Выполняем проверку того, что производитель записи из файла прочтён
	EXPECT_EQ(target.at("/header/vendor").text(), string("security"));
	// Выполняем снос заведённого файла
	::remove(filename.c_str());
}

/**
 * @brief Проверка того, что номер значения перечня, счёт переполняющий, отвергается
 *
 * @details Звено пути обращается в номер значения перечня посчётно, и счёт этот
 *          беззнаковый: переполнение его заворачивается по кругу МОЛЧА. Звено
 *          «18446744073709551616» - это 2^64 - обратилось бы нулём, и обращение к
 *          несуществующему номеру отдавало бы ПЕРВОЕ значение перечня, отдавая его
 *          годным. Ложный успех вместо отказа, отличить какой потребителю нечем
 *
 * @note Сторож стоит в кодеке ДВАЖДЫ - у выдачи значения по пути и у сноса его, - и
 *       проверка берёт оба хода: заслон, поставленный у одного, о втором не говорит
 *       ничего
 *
 * @warning Заведено 09.09.2026 сличением наборов двух кодеков между собою:
 *          сторож поставлен ОБОИМ кодекам, а проверка стояла лишь у syslog, и
 *          у CEF она отсутствовала вовсе - при том что мест здесь вдвое больше. Довод
 *          честен, обход мест не сделан
 *
 */
TEST(CodecCefDocument, OversizedPathIndexIsRefused) {
	// Объект события CEF
	cef::document_t document;
	// Перечень из двух значений, в дерево ставимый
	abc::value_t list(abc::kind_t::ARRAY);
	// Ставим первое значение в перечень
	ASSERT_TRUE(list.push(abc::value_t(string("первое"))));
	// Ставим второе значение в перечень
	ASSERT_TRUE(list.push(abc::value_t(string("второе"))));
	// Выполняем постановку перечня в дерево события
	ASSERT_TRUE(document.set("/list", list));
	// Значение, по пути извлекаемое
	string text = "";
	// Выполняем проверку того, что номер, в счёт помещающийся, разыскивается
	ASSERT_TRUE(document.at("/list/0").valid());
	// Выполняем извлечение значения по помещающемуся номеру
	ASSERT_TRUE(document.at("/list/0").value(text));
	// Выполняем проверку того, что по номеру выдано то самое значение
	EXPECT_EQ(text, "первое");
	// Выполняем проверку того, что номер, в счёт помещающийся, за пределами перечня негоден
	EXPECT_FALSE(document.at("/list/5").valid());
	/**
	 * Выполняем перебор номеров, размер счёта переполняющих
	 *
	 * @note Первый заворачивается нулём, второй - единицею, третий - произвольно: все
	 *       три указывают на значения, в перечне СУЩЕСТВУЮЩИЕ, и потому молчаливое
	 *       переполнение отвечало бы успехом
	 */
	for(const char * path : {"/list/18446744073709551616", "/list/18446744073709551617", "/list/99999999999999999999999999"}){
		// Выполняем проверку негодности значения по переполняющему номеру
		EXPECT_FALSE(document.at(path).valid()) << path;
		/**
		 * Выполняем проверку отказа СНОСА значения по переполняющему номеру
		 *
		 * @note Ход сноса несёт свой сторож, отдельный от сторожа выдачи: снос по
		 *       завернувшемуся номеру убрал бы существующее значение перечня, о каком
		 *       зовущий не просил вовсе
		 */
		EXPECT_FALSE(document.erase(path)) << path;
	}
	// Выполняем проверку того, что перечень сносом не тронут
	ASSERT_TRUE(document.at("/list/0").value(text));
	// Выполняем проверку того, что первое значение перечня на месте
	EXPECT_EQ(text, "первое");
	// Выполняем проверку того, что второе значение перечня на месте
	ASSERT_TRUE(document.at("/list/1").value(text));
	// Выполняем проверку того, что второе значение перечня не тронуто
	EXPECT_EQ(text, "второе");
}

