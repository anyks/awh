#!/bin/sh
#
# Щуп подмены постоянных у кодеков JSON, XML и CSV
#
# Отвечает на вопрос «стережёт ли величину хоть кто-нибудь»: подменяет её в заголовке,
# пересобирает набор и печатает ИМЕНА покрасневших проверок, вычитая закрепитель числа.
#
# Устройство щупа держится на трёх правилах, купленных замерами, - читай их, прежде чем
# толковать выдачу:
#
# 1. Подмена ГРУБАЯ, а не на единицу. Сдвиг на единицу отвечает не «предел не
#    стережётся», а «на границе умолчания никто не стоит», и слеп ко всякому пределу,
#    у какого проверки на границе нет и быть не может: у предела в 16 МБ или в 67
#    миллионов узлов она неподъёмна по памяти. Замер 04.09.2026 сдвигом на единицу дал
#    ноль сторожей у шестнадцати постоянных из семнадцати - и все шестнадцать оказались
#    покрыты, когда подмену сделали грубой.
#
# 2. Закрепитель числа ВЫЧИТАЕТСЯ. Проверка «DefaultLimitsAreWrittenTwice» краснеет от
#    всякой подмены и о поведении не свидетельствует ничем. Прежний счёт «две красных
#    почти везде» был иллюзией: GTest печатает отказ дважды, а считались строки.
#
# 3. Пустая выдача есть ВОПРОС, а не приговор, и разбирать её надо устройством:
#    - величина применяется ТОЛЬКО умолчанием настраиваемого поля, а проверки ставят
#      предел свой - это законно, и закрепитель числа есть весь её сторож;
#    - величина применяется ЗАСЛОНОМ напрямую, а сторожа нет - это находка;
#    - величина применяется потолком последней руки («настройка в ноль либо сверх
#      потолка берёт потолок модуля») - тоже находка, и самая тихая из всех;
#    - величина есть ПОРОГ между двумя дорогами, отвечающими одно (INDEX_THRESHOLD:
#      до него розыск идёт перебором, с него - указателем). Сдвиг такого порога лишь
#      переносит границу дорог, а итог у обеих один, и молчание щупа тут законно.
#      Стережёт его не подмена, а проверка СОГЛАСИЯ дорог по обе стороны порога -
#      CodecContract.LookupAgreesOnBothSidesOfTheIndexThreshold. Замерено у обоих
#      кодеков, JSON и XML: подмена порога красит ноль проверок, и это верно.
#    Проверка, ставящая настройку сама, при подмене умолчания не краснеет никогда, -
#    значит покрасневшие и суть те, что идут ПО УМОЛЧАНИЮ.
#
# ВНИМАНИЕ. Щуп делает общий набор красным на всё время работы, а сосед, запустивший
# набор в этот час, отличить подмену от беды не может. Предупреждай соседей.
#
# ВНИМАНИЕ. Не правь файлы проверок и исходников, покуда щуп идёт: числа выйдут ложными,
# а собранный при стоящей подмене двоичный файл лжёт и после её снятия.
#
# Пример вызова: sh tests/codec/mutate.sh /Users/forman/Work/GIT/anyks/awh
#
ROOT="${1:-.}"
# Журнал сборки: держится вне дерева проекта, следов после щупа не остаётся
LOG="${TMPDIR:-/tmp}/awh-mutate-build.log"
# Каталог эталонных копий: вне дерева проекта, ибо дерево могут закоммитить в любой час
BACKUP_DIR="${TMPDIR:-/tmp}/awh-mutate-backup"
mkdir -p "$BACKUP_DIR"

#
# Заслон коммита на время работы щупа
#
# Щуп портит рабочее дерево - в том его суть, - и всякий, кто закоммитит дерево в этот
# час, унесёт подмену в историю. Замер 04.09.2026: владелец коммитил ровно в ту минуту,
# когда стоял круг MAX_NODES, и в коммит 9dd46bbc6 ушёл предел узлов документа JSON,
# равный ВОСЬМИ. Дерево у щупа при этом честное - эталон он вернул, - и заметить порчу
# можно было лишь сличением с HEAD, каким никто не занимается.
#
# Уклад «беру набор - отдаю набор», о каком мы сговорились с соседом, здесь бессилен:
# владелец в наших договорённостях не участвует и участвовать не должен. Оттого заслон
# ставится машиною, а не памятью, и снимается в хвосте вместе с эталоном.
#
# Чужой заслон, если он есть, НЕ трогается вовсе: щуп тогда отступает и говорит об этом
#
# Число кругов щупа: замок обязан сказать, сколько ждать
TOTAL=17
HOOK="$ROOT/.git/hooks/pre-commit"
HOOK_SET=""
if [ -d "$ROOT/.git/hooks" ]; then
	if [ -e "$HOOK" ]; then
		echo "Заслон коммита уже стоит и чужой - щуп его не трогает."
		echo "Коммит на время работы щупа опасен: подмена уйдёт в историю."
	else
		#
		# Замок ОБЯЗАН называть себя
		#
		# @note Замер 04.09.2026: владелец наткнулся на замок, читающий «ОТКАЗ: идёт
		#       щуп», и спрашивал всех подряд, чей он. Замок, себя не называющий,
		#       переносит работу с машины на людей - ровно то же, что делала строка
		#       «СБОРКА НЕ УДАЛАСЬ» без имени файла
		#
		printf '%s\n' '#!/bin/sh' \
		 "echo \"ОТКАЗ КОММИТА: по дереву идёт щуп подмен постоянных.\"" \
		 "echo \"  щуп:    tests/codec/mutate.sh\"" \
		 "echo \"  завёл:  Василий (кодеки JSON, XML, CSV)\"" \
		 "echo \"  начат:  $(date '+%Y-%m-%d %H:%M:%S')\"" \
		 "echo \"  кругов: $TOTAL, каждый около полутора минут\"" \
		 'echo ""' \
		 'echo "Постоянные кодеков сейчас подменены НАРОЧНО: коммит унёс бы в историю"' \
		 'echo "число, выглядящее настоящей настройкой, - порчу ТИХУЮ, какая собирается"' \
		 'echo "и молчит. Такое уже случилось однажды: коммит 9dd46bbc6."' \
		 'echo ""' \
		 'echo "Дождись строки «ЩУП ОКОНЧЕН» - замок снимется сам."' \
		 'echo "Если щуп убит и замок осиротел, сноси руками: rm .git/hooks/pre-commit"' \
		 'exit 1' > "$HOOK"
		chmod +x "$HOOK"
		HOOK_SET="да"
	fi
fi

#
# Снятие заслона и возврат эталона на ВСЯКОМ исходе, прерывание щупа включая
#
# @note Без этого прерванный щуп оставлял бы дерево подменённым, а коммит запертым, и
#       следующий не понял бы ни того, ни другого
#
cleanup() {
	for CODEC in json xml csv; do
		if [ -e "$BACKUP_DIR/$CODEC-common.hpp" ]; then
			cp "$BACKUP_DIR/$CODEC-common.hpp" "$ROOT/include/codec/$CODEC/common.hpp"
			# Сверяем возврат и здесь: прерванный щуп оставляет дерево без присмотра
			if cmp -s "$BACKUP_DIR/$CODEC-common.hpp" "$ROOT/include/codec/$CODEC/common.hpp"; then
				rm -f "$BACKUP_DIR/$CODEC-common.hpp"
			else
				echo "ТРЕВОГА: эталон $CODEC НЕ восстановлен, копия оставлена в $BACKUP_DIR"
			fi
		fi
	done
	if [ -n "$HOOK_SET" ]; then
		rm -f "$HOOK"
	fi
	rm -f "$LOG"
}
trap 'cleanup; echo "ЩУП ПРЕРВАН, эталон возвращён и заслон снят"; exit 130' INT TERM
if [ ! -d "$ROOT/build" ]; then
	echo "Каталог сборки не найден: $ROOT/build"
	exit 1
fi
# Величины вместе с грубой подменою каждой
for entry in \
  "json:MAX_STRING:8" "json:MAX_NUMBER:4" "json:MAX_DEPTH:4" "json:MAX_NODES:8" \
  "json:INDEX_THRESHOLD:1" \
  "xml:MAX_DEPTH:4" "xml:MAX_NAME:4" "xml:MAX_ATTRIBUTES:2" "xml:MAX_ENTITY_DEPTH:4" \
  "xml:MAX_ENTITY_COUNT:4" "xml:MAX_ENTITY_EXPANSION:64" "xml:MAX_EVENT:64" \
  "xml:INDEX_THRESHOLD:1" \
  "csv:MAX_FIELD:4" "csv:MAX_RECORD:8" "csv:MAX_FIELDS:2" "csv:DETECT_RECORDS:1"; do
	CODEC=$(echo "$entry" | cut -d: -f1)
	NAME=$(echo "$entry" | cut -d: -f2)
	VALUE=$(echo "$entry" | cut -d: -f3)
	FILE="$ROOT/include/codec/$CODEC/common.hpp"
	#
	# Снимаем эталон копией ВНЕ дерева проекта
	#
	# @warning Копия рядом с исходным файлом уже стоила беды: 04.09.2026 владелец
	#          закоммитил дерево во время прогона, и в коммит 9dd46bbc6 ушли ОБА следа
	#          щупа - подменённый предел узлов и лишний файл `common.hpp.mutate-backup`
	#          на тысячу строк. Артефактов щупа в дереве оставаться не должно ни на
	#          минуту: дерево читают не только те, кто знает про щуп
	#
	cp "$FILE" "$BACKUP_DIR/$CODEC-common.hpp" || exit 1
	perl -0pi -e "s/(constexpr\s+\w+\s+\Q$NAME\E\s*=\s*)[^;]+;/\${1}$VALUE;/" "$FILE"
	# Исход сборки снимается в переменную, а не в конвейер: иначе он теряется молча
	(cd "$ROOT/build" && make awh_UNITTEST_codec -j8 > "$LOG" 2>&1)
	ERRORS=$(grep -cE "error:" "$LOG")
	if [ "$ERRORS" != "0" ]; then
		#
		# Первый отказ печатается ЦЕЛИКОМ, и это обязательно: отказ сборки бывает не
		# только своим. Замер 04.09.2026 - семь кругов щупа сгорели впустую на правке
		# СОСЕДА, пришедшей в середине прогона, а щуп сказал лишь «СБОРКА НЕ УДАЛАСЬ»,
		# и своя порча от чужой была неотличима. Имя файла в строке отказа отвечает на
		# это сразу: щуп правит ТОЛЬКО include/codec/{json,xml,csv}/common.hpp и только
		# числами, и всякий отказ в ином файле - чужой
		#
		echo "$CODEC::$NAME=$VALUE -> СБОРКА НЕ УДАЛАСЬ: $(grep -m 1 -E "error:" "$LOG")"
	else
		RED=$(cd "$ROOT/build" && ./unit-tests/codec 2>/dev/null \
		 | grep -E "^\[  FAILED  \] Codec(Json|Xml|Csv|Contract)" \
		 | sed 's/^\[  FAILED  \] //' | awk '{print $1}' | sort -u \
		 | grep -v "DefaultLimitsAreWrittenTwice" | tr '\n' ' ')
		#
		# Малую выдачу ПОДТВЕРЖДАЕМ поштучным прогоном при той же подмене
		#
		# Замер 04.09.2026: щуп соседа шёл по тому же дереву одновременно с моим, и в
		# выдачу трёх кругов сели ЧУЖИЕ красные - проверка, к подменённой величине
		# отношения не имеющая вовсе. Отказ сборки от соседа виден сразу, а ложная
		# краснота неотличима от находки: она называет настоящее имя настоящей
		# проверки. Поштучный прогон её снимает - при стоящей подмене настоящий сторож
		# краснеет и в одиночку, а чужая беда зеленеет.
		#
		# Подтверждаем лишь малую выдачу: ложь опасна там, где красных одна-две и
		# каждая читается как вывод. При семидесяти красных ложное имя ничего не меняет
		#
		COUNT=$(echo "$RED" | wc -w | tr -d ' ')
		if [ "$COUNT" != "0" ] && [ "$COUNT" -le 3 ]; then
			CONFIRMED=""
			for TEST in $RED; do
				if (cd "$ROOT/build" && ./unit-tests/codec --gtest_filter="$TEST" 2>/dev/null | grep -q "^\[  FAILED  \]"); then
					CONFIRMED="$CONFIRMED$TEST "
				else
					echo "$CODEC::$NAME=$VALUE -> ОТСЕЯНО как чужое: $TEST краснеет в наборе, но не в одиночку"
				fi
			done
			RED="$CONFIRMED"
		fi
		if [ -z "$RED" ]; then
			echo "$CODEC::$NAME=$VALUE -> СТОРОЖЕЙ ПОВЕДЕНИЯ НЕТ (разбери устройство по правилу 3)"
		else
			echo "$CODEC::$NAME=$VALUE -> $RED"
		fi
	fi
	#
	# Возвращаем эталон и СВЕРЯЕМ, что возврат лёг
	#
	# @warning Правки назад мало - нужно доказательство, что она легла. Замер
	#          04.09.2026: подмена ушла в коммит 9dd46bbc6 при том, что щуп эталон
	#          вернул исправно; вернул он его ПОСЛЕ коммита. Сверка того случая не
	#          предотвратила бы, но всякий иной - предотвратит: отказ копирования,
	#          нехватку места, снесённую кем-то копию. Порча числом ТИХА - она
	#          собирается и молчит, «MAX_NODES = 8» выглядит настоящей настройкой, -
	#          и потому доказательство возврата обязано быть, а не подразумеваться
	#
	cp "$BACKUP_DIR/$CODEC-common.hpp" "$FILE"
	if ! cmp -s "$BACKUP_DIR/$CODEC-common.hpp" "$FILE"; then
		echo "ТРЕВОГА: эталон $FILE НЕ восстановлен, дерево испорчено подменою!"
		echo "Копия эталона лежит здесь: $BACKUP_DIR/$CODEC-common.hpp"
		echo "Верни его руками и НЕ коммить дерево до того."
		exit 1
	fi
	rm -f "$BACKUP_DIR/$CODEC-common.hpp"
done
# Пересобираем набор эталоном: иначе останется двоичный файл последней подмены
(cd "$ROOT/build" && make awh_UNITTEST_codec -j8 > /dev/null 2>&1)
cleanup
echo "ЩУП ОКОНЧЕН, эталон возвращён, заслон снят, набор пересобран"
