/**
 * @brief Проверка описания всех кодов ошибок разбора
 *
 */
TEST(CodecXmlCommon, Messages) {
	/**
	 * Выполняем перебор всех кодов отказа, договором отведённых
	 *
	 * @note Перебор ведётся числом от нуля до последнего кода перечня: список кодов,
	 *       выписанный рукою, от перечня отстаёт молча - именно так коды, заведённые
	 *       последними, не сличались вовсе
	 */
	// Свод описаний кодов отказа для сличения их на различимость
	set <string> distinct;
	/**
	 * @warning Границею перебора стоит ПОСЛЕДНИЙ код перечня, а не последний, какой был
	 *          последним прежде. Замер 01.09.2026: граница отставала на `FILE_NOT_READ`,
	 *          и код `INVALID_NODE`, дописанный за ним, не сличался ни разу - ровно та
	 *          беда, о какой предупреждает записка ниже, случившаяся с нею же самой
	 */
	for(uint32_t code = 0; code <= static_cast <uint32_t> (xml::error_t::INVALID_NODE); code++){
		// Получаем описание очередного кода отказа
		const char * message = xml::message(static_cast <xml::error_t> (code));
		// Выполняем проверку наличия описания кода отказа
		ASSERT_NE(message, nullptr) << code;
		// Выполняем проверку того, что описание кода отказа не пусто
		ASSERT_GT(::strlen(message), 0u) << code;
		// Выполняем проверку того, что код отказа описанием ОПОЗНАН
		ASSERT_STRNE(message, "unknown error") << code;
		/**
		 * Выполняем занесение описания в свод описаний
		 *
		 * @note Свод собирается ради сличения описаний на РАЗЛИЧИМОСТЬ: утверждение
		 *       «описание непусто» переживает кодек, отдающий одно описание на все коды,
		 *       и описка-двойник в перечне проходит молча
		 */
		distinct.insert(string(message));
	}
	/**
	 * Выполняем проверку различимости описаний всех кодов отказа
	 *
	 * @note Замер 01.09.2026 по трём кодекам: 106 кодов и 106 различных описаний
	 */
	ASSERT_EQ(distinct.size(), 47u);
	/**
	 * Выполняем проверку того, что перечень кодов на том и оканчивается
	 *
	 * @note Сличение это отмечает конец перечня, а сторожем НЕ является: код, дописанный
	 *       без описания, оно пропускает - именно его отсутствие оно и сличает. Проверено
	 *       щупом: дописанный код отказа проверку не уронил. Сторожем тут выступает
	 *       собиратель - смотри примечание у самой выдачи описаний
	 */
	ASSERT_STREQ(xml::message(static_cast <xml::error_t> (static_cast <uint32_t> (xml::error_t::INVALID_NODE) + 1)), "unknown error");
	// Выполняем проверку описания кода, договором не отведённого
	ASSERT_STREQ(xml::message(static_cast <xml::error_t> (0xFF)), "unknown error");
}
/**
 * @brief Проверка названий кодировок исходного текста
 *
 */
TEST(CodecXmlCommon, Encodings) {
	/**
	 * Выполняем проверку названия неопределённой кодировки
	 *
	 * @note Неопределённой кодировке отвечает название, а не пустой указатель: выдача
	 *       его читающему безопасна и печатается без отдельной проверки
	 *
	 * @note Прежде здесь утверждалась ПУСТОТА названия, доводом же при ней стояло лишь
	 *       «не пустой указатель» - самой пустоты не обосновывал никто. Пустотою же
	 *       отвечала и кодировка, перечню не принадлежащая: два разных случая были
	 *       неотличимы, а звучащий, вписывающий название в журнал, получал дыру в
	 *       сообщении. Кодеки документа и таблицы зовут эти случаи «none» и «unknown»,
	 *       и разметка приведена к тому же. Несущей пустота не была: имя кодировки в
	 *       самом кодеке не звучит нигде, а объявление пишет «encoding="UTF-8"» дословно
	 */
	ASSERT_NE(xml::name(xml::encoding_t::NONE), nullptr);
	ASSERT_EQ(string(xml::name(xml::encoding_t::NONE)), "none");
	// Выполняем проверку названия кодировки UTF-8
	ASSERT_EQ(string(xml::name(xml::encoding_t::UTF8)), "UTF-8");
	// Выполняем проверку названия кодировки UTF-16 с обратным порядком байтов
	ASSERT_EQ(string(xml::name(xml::encoding_t::UTF16LE)), "UTF-16LE");
	// Выполняем проверку названия кодировки UTF-16 с прямым порядком байтов
	ASSERT_EQ(string(xml::name(xml::encoding_t::UTF16BE)), "UTF-16BE");
	// Выполняем проверку названия кодировки ISO-8859-1
	ASSERT_EQ(string(xml::name(xml::encoding_t::LATIN1)), "ISO-8859-1");
	// Выполняем проверку названия кодировки US-ASCII
	ASSERT_EQ(string(xml::name(xml::encoding_t::ASCII)), "US-ASCII");
	/**
	 * Выполняем проверку названия НЕОПРЕДЕЛЁННОЙ кодировки
	 *
	 * @note Утверждение это заведено взамен прежнего «имя не есть ноль»: имя пустое ему
	 *       отвечало, а пустотою же звалась и кодировка, перечню не принадлежащая - два
	 *       разных случая были неотличимы, и проверка того не замечала
	 */
	ASSERT_EQ(string(xml::name(xml::encoding_t::NONE)), "none");
	// Выполняем проверку названия кодировки, договором не отведённой
	ASSERT_EQ(string(xml::name(static_cast <xml::encoding_t> (0xFF))), "unknown");
	// Выполняем проверку того, что два эти случая различимы
	ASSERT_STRNE(xml::name(xml::encoding_t::NONE), xml::name(static_cast <xml::encoding_t> (0xFF)));
	// Выполняем проверку разбора названий кодировок обратно
	ASSERT_EQ(xml::encoding("UTF-8"), xml::encoding_t::UTF8);
	// Выполняем проверку разбора названия кодировки в другом написании
	ASSERT_EQ(xml::encoding("utf-16le"), xml::encoding_t::UTF16LE);
	// Выполняем проверку разбора названия кодировки ISO-8859-1
	ASSERT_EQ(xml::encoding("ISO-8859-1"), xml::encoding_t::LATIN1);
	// Выполняем проверку разбора неизвестного названия кодировки
	ASSERT_EQ(xml::encoding("КОИ-8"), xml::encoding_t::NONE);
}
/**
 * @brief Проверка сличения имён с учётом пространства имён
 *
 */
TEST(CodecXmlCommon, Names) {
	// Имя узла с пространством имён
	xml::name_t first;
	// Устанавливаем префикс имени узла
	first.prefix = "ns";
	// Устанавливаем местное имя узла
	first.local = "item";
	// Устанавливаем обозначение пространства имён узла
	first.uri = "urn:example";
	// Имя узла, записанное другим префиксом того же пространства имён
	xml::name_t second;
	// Устанавливаем другой префикс имени узла
	second.prefix = "other";
	// Устанавливаем то же местное имя узла
	second.local = "item";
	// Устанавливаем то же обозначение пространства имён узла
	second.uri = "urn:example";
	/**
	 * Выполняем проверку совпадения имён, записанных разными префиксами
	 *
	 * @note Сличение ведётся по паре из обозначения пространства имён и местного
	 *       имени: префикс написанием разнится, а имя обозначает одно и то же
	 */
	ASSERT_TRUE(first == second);
	// Выполняем проверку отрицания совпадения имён
	ASSERT_FALSE(first != second);
	// Выполняем проверку совпадения имени с заданной парой
	ASSERT_TRUE(first.is("urn:example", "item"));
	// Выполняем проверку несовпадения имени с чужим пространством имён
	ASSERT_FALSE(first.is("urn:other", "item"));
	// Выполняем проверку несовпадения имени с чужим местным именем
	ASSERT_FALSE(first.is("urn:example", "other"));
	// Устанавливаем другое местное имя узла
	second.local = "other";
	// Выполняем проверку несовпадения имён с разными местными именами
	ASSERT_TRUE(first != second);
	// Выполняем проверку отрицания несовпадения имён
	ASSERT_FALSE(first == second);
}
/**
 * @brief Проверка допустимости знаков разметки
 *
 */
TEST(CodecXmlCommon, Characters) {
	// Выполняем проверку допустимости знака табуляции
	ASSERT_TRUE(xml::isChar(0x09));
	// Выполняем проверку допустимости перевода строки
	ASSERT_TRUE(xml::isChar(0x0A));
	// Выполняем проверку допустимости обычного знака
	ASSERT_TRUE(xml::isChar('a'));
	// Выполняем проверку недопустимости управляющего знака
	ASSERT_FALSE(xml::isChar(0x01));
	// Выполняем проверку недопустимости половины суррогатной пары
	ASSERT_FALSE(xml::isChar(0xD800));
	// Выполняем проверку недопустимости значения, отведённого под неназначенное
	ASSERT_FALSE(xml::isChar(0xFFFE));
	// Выполняем проверку допустимости знака за пределами основного набора
	ASSERT_TRUE(xml::isChar(0x10000));
	// Выполняем проверку недопустимости значения сверх всеобщей кодировки
	ASSERT_FALSE(xml::isChar(0x110000));
	// Выполняем проверку пробельности пробела
	ASSERT_TRUE(xml::isSpace(0x20));
	// Выполняем проверку пробельности знака табуляции
	ASSERT_TRUE(xml::isSpace(0x09));
	// Выполняем проверку пробельности перевода строки
	ASSERT_TRUE(xml::isSpace(0x0A));
	// Выполняем проверку пробельности возврата каретки
	ASSERT_TRUE(xml::isSpace(0x0D));
	// Выполняем проверку того, что обычный знак пробельным не считается
	ASSERT_FALSE(xml::isSpace('a'));
	/**
	 * Выполняем проверку того, что неразрывный пробел пробельным не считается
	 *
	 * @note Договор относит к пробельным ровно четыре знака, и неразрывный
	 *       пробел в их число не входит
	 */
	ASSERT_FALSE(xml::isSpace(0xA0));
}
/**
 * @brief Проверка выдачи сведений о разобранном тексте разметки
 *
 * @details Проверяются обращения, которыми пользуется читающий по ходу разбора:
 *          настройки, глубина вложенности, признак самозакрывающейся метки,
 *          обращение с пробельным содержимым, определённая кодировка, объявленное
 *          издание, признак самодостаточности, поиск атрибута и разрешение
 *          префикса пространства имён
 *
 */
TEST(CodecXmlCommon, Inspection) {
	// Настройки разбора текста разметки
	xml::reader_t::settings_t settings;
	// Выполняем включение отделения незначимого пробельного содержимого
	settings.separateSpaces = true;
	// Объект потокового чтения текста разметки
	xml::reader_t reader(::logger());
	// Выполняем установку настроек разбора текста разметки
	reader.settings(settings);
	// Выполняем проверку того, что установленные настройки приняты
	ASSERT_TRUE(reader.settings().separateSpaces);
	// Разбираемый текст разметки
	const string text(
		"<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>"
		"<r xmlns:ns=\"urn:example\" xml:space=\"preserve\">"
		"<ns:item ns:code=\"42\" plain=\"текст\"/> </r>"
	);
	// Выполняем передачу текста разметки целиком
	ASSERT_TRUE(reader.feed(text));
	// Признак того, что вложенный узел проверен
	bool checked = false;
	/**
	 * Выполняем перебор всех событий разбора
	 */
	while(reader.next()){
		/**
		 * Если получено начало вложенного узла разметки
		 */
		if((reader.event() == xml::event_t::ELEMENT_OPEN) && (reader.depth() > 0)){
			// Выполняем проверку глубины вложенности узла
			ASSERT_EQ(reader.depth(), 1u);
			// Выполняем проверку признака узла, записанного самозакрывающейся меткой
			ASSERT_TRUE(reader.empty());
			// Выполняем проверку обращения с пробельным содержимым, унаследованного узлом
			ASSERT_EQ(reader.space(), xml::space_t::PRESERVE);
			// Выполняем проверку имени узла с учётом пространства имён
			ASSERT_TRUE(reader.name().is("urn:example", "item"));
			// Выполняем проверку наличия атрибута с пространством имён
			ASSERT_TRUE(reader.has("code", "urn:example"));
			// Выполняем проверку наличия атрибута без пространства имён
			ASSERT_TRUE(reader.has("plain"));
			/**
			 * Выполняем проверку отсутствия атрибута без пространства имён
			 *
			 * @note Атрибуты объявлению пространства имён по умолчанию не подчиняются,
			 *       и атрибут с префиксом по местному имени без обозначения не ищется
			 */
			ASSERT_FALSE(reader.has("code"));
			// Значение атрибута, полученное числом
			int64_t number = 0;
			// Выполняем разбор значения атрибута числом
			ASSERT_TRUE(reader.value(number, "code", "urn:example"));
			// Выполняем проверку разобранного значения атрибута
			ASSERT_EQ(number, 42);
			// Выполняем проверку разрешения префикса пространства имён
			ASSERT_EQ(reader.resolve("ns"), "urn:example");
			// Выполняем проверку разрешения отведённого договором префикса
			ASSERT_FALSE(reader.resolve("xml").empty());
			// Выполняем проверку разрешения необъявленного префикса
			ASSERT_TRUE(reader.resolve("nope").empty());
			// Запоминаем, что вложенный узел проверен
			checked = true;
		}
	}
	// Выполняем проверку того, что разбор завершён удачно
	ASSERT_EQ(reader.state(), xml::state_t::FINISHED);
	// Выполняем проверку того, что вложенный узел встречен разбором
	ASSERT_TRUE(checked);
	// Выполняем проверку определённой кодировки исходного текста
	ASSERT_EQ(reader.encoding(), xml::encoding_t::UTF8);
	// Выполняем проверку объявленного издания разметки
	ASSERT_EQ(reader.version(), "1.0");
	// Выполняем проверку объявленного признака самодостаточности текста
	ASSERT_EQ(reader.standalone(), xml::standalone_t::YES);
	// Выполняем проверку отсутствия ошибок разбора
	ASSERT_EQ(reader.error(), xml::error_t::NONE);
}

/**
 * @brief Проверка разборщиков содержимого узла по видам значений
 *
 * @details Разборщики эти общи всему кодеку и разбирают содержимое узла целым, дробным
 *          либо истинностным значением. Пробельная обвязка снимается ими самими: содержимое
 *          узла приходит из текста разметки, где отступы законны
 *
 * @note Отказ на пустом содержимом отыскан по карте покрытия: набор подавал разборщикам
 *       что угодно, кроме пустоты и одних лишь пробелов
 *
 */
TEST(CodecXmlCommon, Converters) {
	/**
	 * Пустое содержимое разбору не подлежит ни одним видом
	 */
	{
		// Выполняем перебор содержимого, значения не несущего
		for(auto & text : vector <string> {"", " ", "\t\r\n "}){
			// Разбираемое целое число со знаком
			int64_t number = -1;
			// Выполняем проверку отказа разбора целым видом
			ASSERT_FALSE(xml::integer(text, number)) << "[" << text << "]";
			// Разбираемое целое число без знака
			uint64_t count = 1;
			// Выполняем проверку отказа разбора беззнаковым видом
			ASSERT_FALSE(xml::integer(text, count)) << "[" << text << "]";
			// Разбираемое дробное число
			double real = -1.;
			// Выполняем проверку отказа разбора дробным видом
			ASSERT_FALSE(xml::real(text, real)) << "[" << text << "]";
			// Разбираемое истинностное значение
			bool flag = true;
			// Выполняем проверку отказа разбора истинностным видом
			ASSERT_FALSE(xml::boolean(text, flag)) << "[" << text << "]";
		}
	}
	/**
	 * Пробельная обвязка содержимого разбору не мешает
	 */
	{
		// Разбираемое целое число со знаком
		int64_t number = 0;
		// Выполняем разбор целого числа с пробельной обвязкой
		ASSERT_TRUE(xml::integer(" -42\n", number));
		// Выполняем проверку разобранного целого числа
		ASSERT_EQ(number, static_cast <int64_t> (-42));
		// Разбираемое дробное число
		double real = 0.;
		// Выполняем разбор дробного числа с пробельной обвязкой
		ASSERT_TRUE(xml::real("\t1.5 ", real));
		// Выполняем проверку разобранного дробного числа
		ASSERT_NEAR(real, 1.5, 1e-12);
		// Разбираемое истинностное значение
		bool flag = false;
		// Выполняем разбор истинностного значения с пробельной обвязкой
		ASSERT_TRUE(xml::boolean(" true ", flag));
		// Выполняем проверку разобранного истинностного значения
		ASSERT_TRUE(flag);
	}
}
/**
 * @brief Проверка неприкосновенности выходной переменной при отказе приведения
 *
 * @details Довод тот же, что и у таблицы: разбор числа вёлся прямо в выходную переменную,
 * и отвергнутое «1e3» оставляло у звучащего единицу вместо нетронутого значения
 */
TEST(CodecXmlCommon, RefusedConversionLeavesResultUntouched){
	// Значения, целым числом не являющиеся, но числом начинающиеся
	const vector <string> corpus = {"1e3", "52abc", "3.14.15", "0x10"};
	// Значения, дробным числом не являющиеся, но числом начинающиеся
	const vector <string> reals = {"52abc", "3.14.15"};
	/**
	 * Выполняем перебор всех проверяемых значений
	 */
	for(const string & text : corpus){
		// Выходное значение целого числа со знаком
		int64_t signedNumber = -777;
		// Выполняем проверку отказа приведения к целому со знаком
		ASSERT_FALSE(xml::integer(text, signedNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(signedNumber, static_cast <int64_t> (-777)) << text;
		// Выходное значение целого числа без знака
		uint64_t unsignedNumber = 777;
		// Выполняем проверку отказа приведения к целому без знака
		ASSERT_FALSE(xml::integer(text, unsignedNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(unsignedNumber, static_cast <uint64_t> (777)) << text;
	}
	/**
	 * Выполняем перебор значений, дробным числом не являющихся
	 */
	for(const string & text : reals){
		// Выходное значение числа с плавающей точкой
		double realNumber = -0.5;
		// Выполняем проверку отказа приведения к числу с плавающей точкой
		ASSERT_FALSE(xml::real(text, realNumber)) << text;
		// Выполняем проверку неприкосновенности выходного значения
		ASSERT_EQ(realNumber, -0.5) << text;
	}
}


/**
 * @brief Проверка величин, составляющих договор кодека с потребителем
 *
 * @details Пределы умолчания решают, какую разметку кодек примет без всяких настроек.
 *          Сличать величину с её же именем бесполезно: обе стороны двигаются вместе
 *
 * @note Здесь сличаются и три СОГЛАСИЯ между величинами: предел глубины сущностей меньше
 *       предела вложенности узлов, предел количества сущностей не больше предела
 *       количества атрибутов, а предел разрастания сущности меньше предела объёма
 *       события. Согласия эти не случайны - разрастание, предел события перебравшее,
 *       отвергалось бы кодом объёма, а не кодом сущности
 *
 */
TEST(CodecXmlCommon, DefaultLimitsAreWrittenTwice) {
	/**
	 * Выполняем проверку самих величин по записанным числам
	 */
	{
		// Выполняем проверку предела глубины вложенности узлов
		ASSERT_EQ(xml::MAX_DEPTH, 1024u);
		// Выполняем проверку предела длины имени
		ASSERT_EQ(xml::MAX_NAME, 8192u);
		// Выполняем проверку предела количества атрибутов у узла
		ASSERT_EQ(xml::MAX_ATTRIBUTES, 4096u);
		// Выполняем проверку предела глубины вложенности сущностей
		ASSERT_EQ(xml::MAX_ENTITY_DEPTH, 32u);
		// Выполняем проверку предела количества объявленных сущностей
		ASSERT_EQ(xml::MAX_ENTITY_COUNT, 4096u);
		// Выполняем проверку предела разрастания сущности
		ASSERT_EQ(xml::MAX_ENTITY_EXPANSION, 0x100000u);
		// Выполняем проверку предела объёма одного события
		ASSERT_EQ(xml::MAX_EVENT, 0x1000000u);
		// Выполняем проверку наибольшего кодового значения знака
		ASSERT_EQ(xml::MAX_CODEPOINT, 0x10FFFFu);
	}
	/**
	 * Выполняем проверку того, что умолчание настроек величины эти несёт
	 */
	{
		// Умолчательные настройки разбора текста разметки
		const xml::reader_t::settings_t settings;
		// Выполняем проверку предела глубины вложенности у умолчания
		ASSERT_EQ(settings.maxDepth, xml::MAX_DEPTH);
		// Выполняем проверку предела длины имени у умолчания
		ASSERT_EQ(settings.maxName, xml::MAX_NAME);
		// Выполняем проверку предела количества атрибутов у умолчания
		ASSERT_EQ(settings.maxAttributes, xml::MAX_ATTRIBUTES);
		// Выполняем проверку предела количества сущностей у умолчания
		ASSERT_EQ(settings.maxEntities, xml::MAX_ENTITY_COUNT);
		// Выполняем проверку предела разрастания сущности у умолчания
		ASSERT_EQ(settings.maxExpansion, xml::MAX_ENTITY_EXPANSION);
		// Выполняем проверку предела объёма события у умолчания
		ASSERT_EQ(settings.maxEvent, xml::MAX_EVENT);
		/**
		 * Выполняем проверку прочих умолчаний, видимое поведение задающих
		 *
		 * @note Незагрузка внешних сущностей стоит здесь наравне с пределами: это
		 *       решение об охране, и опущенным оно быть обязано
		 */
		ASSERT_FALSE(settings.externals);
		// Выполняем проверку применения договора о пространствах имён умолчанием
		ASSERT_TRUE(settings.namespaces);
		// Выполняем проверку подстановки сущностей умолчанием
		ASSERT_TRUE(settings.entities);
	}
	/**
	 * Выполняем проверку согласий между величинами
	 */
	{
		// Выполняем проверку того, что глубина сущностей меньше глубины узлов
		ASSERT_LT(xml::MAX_ENTITY_DEPTH, xml::MAX_DEPTH);
		// Выполняем проверку того, что количество сущностей не больше количества атрибутов
		ASSERT_LE(xml::MAX_ENTITY_COUNT, xml::MAX_ATTRIBUTES);
		// Выполняем проверку того, что разрастание сущности меньше объёма события
		ASSERT_LT(xml::MAX_ENTITY_EXPANSION, xml::MAX_EVENT);
	}
}
