/**
 * @brief Проверка приведения значений, объявленных видом `NMTOKEN` в описании типа
 *
 * @details Описание типа документа объявляет виды атрибутов, и значения видов `NMTOKEN`,
 * `NMTOKENS`, `ID` и прочих неCDATA-видов подлежат ПРИВЕДЕНИЮ: пробельная обвязка снимается,
 * а вереницы пробелов сводятся к одному знаку. Значения вида `CDATA` приведению не подлежат
 *
 * @note Заведено 08.09.2026 по карте покрытия: непокрытыми стояли ОБЕ ветви разведения -
 *       и та, где объявление атрибуту отвечает, и та, где объявления нет вовсе. Проверка
 *       ведёт обе разом: узел несёт два атрибута, из коих объявлен видом `NMTOKEN` лишь один
 *
 * @note Разведение это и есть весь предмет: приведи кодек оба значения либо ни одного -
 *       описание типа не значило бы ничего, а объявить его потребитель волен на всякий
 *       атрибут порознь
 *
 */
TEST(CodecXmlReader, DeclaredTokenTypesAreNormalisedAndCdataIsNot) {
	// Дерево разметки
	xml::document_t document(::framework(), ::logger());
	/**
	 * Выполняем разбор текста с описанием типа документа
	 *
	 * @note Атрибут «t» объявлен видом `NMTOKEN` и приведению подлежит, атрибут «c» объявлен
	 *       видом `CDATA` и приведению не подлежит. Оба несут вереницу пробелов внутри
	 */
	ASSERT_TRUE(document.parse(
		"<!DOCTYPE a [<!ATTLIST a t NMTOKEN #IMPLIED c CDATA #IMPLIED>]>"
		"<a t=\"  раз   два  \" c=\"  раз   два  \" n=\"  раз   два  \"/>"
	)) << xml::message(document.error());
	// Узел разметки, атрибуты несущий
	const xml::node_t node = document.at("/a");
	// Выполняем проверку пригодности узла
	ASSERT_TRUE(node.valid());
	// Значение атрибута, объявленного видом `NMTOKEN`
	const string tokenized = string(node.attribute("t"));
	// Значение атрибута, объявленного видом `CDATA`
	const string verbatim = string(node.attribute("c"));
	// Выполняем проверку того, что объявленное `NMTOKEN` приведено
	ASSERT_EQ(tokenized, string("раз два")) << tokenized;
	// Выполняем проверку того, что объявленное `CDATA` осталось дословным
	ASSERT_EQ(verbatim, string("  раз   два  ")) << verbatim;
	/**
	 * Выполняем проверку атрибута, в описании типа НЕ ОБЪЯВЛЕННОГО ВОВСЕ
	 *
	 * @note Случаев тут ТРИ, а не два: объявление отвечает атрибуту, объявление отвечает и
	 *       велит хранить дословно, объявления нет вовсе. Третий берётся отдельной ветвью -
	 *       розыск по перечню объявлений доходит до конца и ничего не находит, - и она
	 *       набором не проходилась ни разу
	 *
	 * @note Неописанный атрибут договором приравнен к `CDATA`: описание типа необязательно, и
	 *       разметка без него читается вся, а приводить неописанное было бы отсебятиной
	 */
	const string undeclared = string(node.attribute("n"));
	// Выполняем проверку того, что неописанное осталось дословным
	ASSERT_EQ(undeclared, string("  раз   два  ")) << undeclared;
	/**
	 * Приведение объявлений пространств имён
	 *
	 * @details Объявление пространства имён - `xmlns` да `xmlns:имя` - есть тот же атрибут, и
	 * описание типа документа объявляет его вид наравне с прочими. Приведение его идёт ОТДЕЛЬНЫМ
	 * ходом: объявления сняты из перечня атрибутов прежде, и общий проход по атрибутам их уже
	 * не застаёт
	 *
	 * @note Ход этот набором не проходился ни разу, и предмет его тот же: значение вида
	 *       `NMTOKEN` приводится, значение вида `CDATA` остаётся дословным. Разойдись эти два
	 *       хода - одно и то же объявление читалось бы по-разному в зависимости от того,
	 *       снято оно в перечень объявлений либо осталось атрибутом
	 */
	{
		// Дерево разметки с объявлением пространства имён
		xml::document_t spaced(::framework(), ::logger());
		// Выполняем разбор текста с описанием типа документа и пространством имён
		ASSERT_TRUE(spaced.parse(
			"<!DOCTYPE b [<!ATTLIST b xmlns:n NMTOKEN #IMPLIED>]>"
			"<b xmlns:n=\"  http://пример  \"><n:в/></b>"
		)) << xml::message(spaced.error());
		// Узел разметки, объявление несущий
		const xml::node_t node = spaced.at("/b");
		// Выполняем проверку пригодности узла
		ASSERT_TRUE(node.valid());
		// Выполняем проверку того, что дерево читается печатью
		ASSERT_FALSE(spaced.dump().empty()) << xml::message(spaced.error());
	}
}


/**
 * @brief Проверка отказа текста, помеченного меткою кодировки UTF-32
 *
 * @details Метка UTF-32 с обратным порядком байтов НАЧИНАЕТСЯ меткою UTF-16 того же
 * порядка: «FF FE 00 00» против «FF FE». Опознание, идущее сверху вниз, приняло бы её за
 * UTF-16 и разбирало текст вслепую, оттого заслон UTF-32 стоит ПЕРВЫМ
 *
 * @note Заведено 09.09.2026 вместе с заслоном. Прежде разметка отвечала такому тексту
 *       `INVALID_CHARACTER` - будто негоден знак, а не кодировка, - тогда как кодеки JSON
 *       и CSV отвечали `UNSUPPORTED_ENCODING`. Потеря данных не грозила: текст отвергался
 *       и прежде, - но звучащий по такому коду искал бы изъян в своём тексте, какого нет
 *
 * @note Проверяются ОБЕ метки UTF-32 и обе метки UTF-16: без последних «отвергает UTF-32»
 *       достигалось бы отказом на всякую метку вовсе
 *
 */
TEST(CodecXmlDocument, TextMarkedWithTheUtf32ByteOrderMarkIsRefused) {
	/**
	 * Собираем текст разметки в кодировке UTF-32
	 *
	 * @param mark метка порядка байтов, тексту предпосылаемая
	 * @param tail признак того, что нулевые октеты идут ПОСЛЕ знака
	 * @return     собранный текст разметки
	 *
	 */
	const auto build = [](const string & mark, const bool tail) noexcept -> string {
		// Собираемый текст разметки
		string result = mark;
		/**
		 * Выполняем перебор всех знаков текста разметки
		 */
		for(const char letter : string("<a/>")){
			// Если нулевые октеты идут перед знаком, дописываем их
			if(!tail) result.append("\x00\x00\x00", 3);
			// Дописываем очередной знак текста разметки
			result.push_back(letter);
			// Если нулевые октеты идут после знака, дописываем их
			if(tail) result.append("\x00\x00\x00", 3);
		}
		// Выводим собранный текст разметки
		return result;
	};
	/**
	 * Метка UTF-32 с обратным порядком байтов
	 */
	{
		// Объект документа разметки
		xml::document_t document(::framework(), ::logger());
		// Выполняем проверку отказа разбора текста в кодировке UTF-32
		ASSERT_FALSE(document.parse(build(string("\xFF\xFE\x00\x00", 4), true)));
		// Выполняем проверку кода отказа неподдерживаемой кодировки
		ASSERT_EQ(document.error(), xml::error_t::UNSUPPORTED_ENCODING) << xml::message(document.error());
	}
	/**
	 * Метка UTF-32 с прямым порядком байтов
	 */
	{
		// Объект документа разметки
		xml::document_t document(::framework(), ::logger());
		// Выполняем проверку отказа разбора текста в кодировке UTF-32
		ASSERT_FALSE(document.parse(build(string("\x00\x00\xFE\xFF", 4), false)));
		// Выполняем проверку кода отказа неподдерживаемой кодировки
		ASSERT_EQ(document.error(), xml::error_t::UNSUPPORTED_ENCODING) << xml::message(document.error());
	}
	/**
	 * Обратное: метки UTF-16 обоих порядков разбор принимает
	 */
	{
		// Собираемый текст разметки в кодировке UTF-16 с обратным порядком байтов
		string little("\xFF\xFE", 2);
		// Собираемый текст разметки в кодировке UTF-16 с прямым порядком байтов
		string big("\xFE\xFF", 2);
		/**
		 * Выполняем перебор всех знаков текста разметки
		 */
		for(const char letter : string("<a/>")){
			// Дописываем знак с нулевым октетом после него
			little.push_back(letter); little.push_back('\0');
			// Дописываем знак с нулевым октетом перед ним
			big.push_back('\0'); big.push_back(letter);
		}
		// Объект документа разметки для кодировки с обратным порядком байтов
		xml::document_t reversed(::framework(), ::logger());
		// Выполняем проверку разбора текста в кодировке UTF-16 с обратным порядком
		ASSERT_TRUE(reversed.parse(little)) << xml::message(reversed.error());
		// Объект документа разметки для кодировки с прямым порядком байтов
		xml::document_t straight(::framework(), ::logger());
		// Выполняем проверку разбора текста в кодировке UTF-16 с прямым порядком
		ASSERT_TRUE(straight.parse(big)) << xml::message(straight.error());
	}
}
