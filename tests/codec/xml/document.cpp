/**
 * @brief Проверка замены корня у дерева, несущего соседей по верхнему уровню
 *
 * @details У разметки корневой элемент один, а вот узлов ВЕРХНЕГО УРОВНЯ бывает несколько:
 * примечания и указания обработчику стоят до корня и после него. Замена корня в таком дереве
 * идёт по четырём ветвям перевязки - предыдущий сосед есть либо его нет, следующий сосед есть
 * либо его нет, - и всякая из них правит цепочку соседства
 *
 * @note Заведено 08.09.2026 по карте покрытия: две ветви из четырёх, «сосед есть», набором не
 *       проходились - прежняя проверка прививки брала дерево, где корень был ОДИН, и обе
 *       ветви обходились стороною. Ошибка перевязки тут рвёт обход верхнего уровня МОЛЧА:
 *       узлы остаются в арене, а печать теряет их без всякого признака отказа
 *
 * @note Оттого и утверждается ПЕЧАТЬ, а не успех прививки: соседи обязаны уцелеть в тексте
 *       по обе стороны нового корня. Успех без печати оставил бы порванную цепочку
 *       незамеченной - ровно то, чем эта беда опасна
 *
 */
TEST(CodecXmlDocument, ReplacingTheRootKeepsTheTopLevelNeighbours) {
	// Дерево разметки
	xml::document_t document(::framework(), ::logger());
	/**
	 * Выполняем разбор текста с примечаниями по обе стороны корня
	 *
	 * @note Примечания эти и есть соседи корня по верхнему уровню: первое даёт ветвь
	 *       «предыдущий сосед есть», второе - ветвь «следующий сосед есть»
	 */
	ASSERT_TRUE(document.parse("<!--до--><прежний/><!--после-->")) << xml::message(document.error());
	// Прививаемое значение узла разметки
	xml::value_t value(xml::kind_t::ELEMENT);
	// Устанавливаем имя прививаемого узла
	value.name("новый");
	// Выполняем прививку значения в корень дерева, прежний корень заменяющую
	ASSERT_TRUE(document.set("", value)) << xml::message(document.error());
	// Выполняем проверку того, что привитый узел разыскивается по пути
	ASSERT_TRUE(document.has("/новый"));
	// Выполняем проверку того, что прежний корень заменён
	ASSERT_FALSE(document.has("/прежний"));
	// Печать дерева после замены корня
	const string text = document.dump();
	// Выполняем проверку того, что печать не пуста
	ASSERT_FALSE(text.empty()) << xml::message(document.error());
	// Выполняем проверку того, что сосед ДО корня уцелел
	ASSERT_NE(text.find("до"), string::npos) << text;
	// Выполняем проверку того, что сосед ПОСЛЕ корня уцелел
	ASSERT_NE(text.find("после"), string::npos) << text;
	// Выполняем проверку того, что новый корень в печати есть
	ASSERT_NE(text.find("новый"), string::npos) << text;
}

