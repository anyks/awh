/**
 * @brief Ответ по договору SOAP, как его отдаёт устройство по договору UPnP
 *
 */
static constexpr const char * SOAP =
	"<?xml version=\"1.0\"?>\n"
	"<s:Envelope xmlns:s=\"http://schemas.xmlsoap.org/soap/envelope/\""
	" s:encodingStyle=\"http://schemas.xmlsoap.org/soap/encoding/\">\n"
	"  <s:Body>\n"
	"    <u:GetExternalIPAddressResponse xmlns:u=\"urn:schemas-upnp-org:service:WANIPConnection:1\">\n"
	"      <NewExternalIPAddress>203.0.113.7</NewExternalIPAddress>\n"
	"    </u:GetExternalIPAddressResponse>\n"
	"  </s:Body>\n"
	"</s:Envelope>";

/**
 * @brief Проверка разбора ответа по договору SOAP
 *
 */
TEST(CodecXmlDocument, Soap) {
	// Объект дерева разметки
	xml::document_t document(::framework(), ::logger());
	// Выполняем разбор ответа по договору SOAP
	ASSERT_TRUE(document.parse(SOAP)) << xml::message(document.error());
	// Получаем корневой узел разметки
	const xml::node_t root = document.element();
	// Выполняем проверку пригодности корневого узла
	ASSERT_TRUE(root.valid());
	// Выполняем проверку имени корневого узла
	ASSERT_TRUE(root.name().is("http://schemas.xmlsoap.org/soap/envelope/", "Envelope"));
	// Выполняем поиск узла вглубь дерева
	const xml::node_t address = root.find("NewExternalIPAddress");
	// Выполняем проверку обнаружения узла
	ASSERT_TRUE(address.valid());
	// Выполняем проверку содержимого обнаруженного узла
	ASSERT_EQ(address.text(), "203.0.113.7");
	// Выполняем поиск узла среди непосредственно вложенных
	const xml::node_t body = root.child("Body", "http://schemas.xmlsoap.org/soap/envelope/");
	// Выполняем проверку обнаружения узла
	ASSERT_TRUE(body.valid());
	// Выполняем проверку того, что поиск учитывает пространство имён
	ASSERT_FALSE(root.child("Body").valid());
	// Выполняем проверку значения атрибута с префиксом
	ASSERT_EQ(root.attribute("encodingStyle", "http://schemas.xmlsoap.org/soap/envelope/"), "http://schemas.xmlsoap.org/soap/encoding/");
	// Выполняем проверку обхода дерева вверх
	ASSERT_TRUE(address.parent().parent() == body);
}
/**
 * @brief Проверка сохранения записи имён при обратной записи дерева
 *
 * @details Смысл имени задаёт обозначение пространства имён, а не префикс, и запись
 *          вправе назначать префиксы сама. Но договор о подписи XML сличает документы
 *          знак в знак, и переназначенный префикс подпись ломает: дерево удерживает
 *          объявления узлов, а запись их применяет
 *
 */
TEST(CodecXmlDocument, Bindings) {
	/**
	 * @brief Метод разбора текста разметки и обратной его записи
	 *
	 * @param text разбираемый текст разметки
	 * @return     записанный обратно текст разметки
	 *
	 */
	const auto walk = [](const string & text) noexcept -> string {
		// Объект дерева разметки
		xml::document_t document(::framework(), ::logger());
		// Настройки разбора текста разметки
		xml::reader_t::settings_t settings;
		// Выполняем отключение выдачи примечаний отдельным событием
		settings.emitComments = false;
		// Выполняем отключение выдачи указаний обработчику отдельным событием
		settings.emitProcessing = false;
		// Если разбор текста разметки выполнить не удалось, выводим отказ
		if(!document.parse(text, settings)) return string("ОТКАЗ РАЗБОРА");
		// Объект записи текста разметки
		xml::writer_t writer(::logger());
		// Если обратную запись дерева выполнить не удалось, выводим отказ
		if(!writer.element(document.root())) return string("ОТКАЗ ЗАПИСИ");
		// Выводим записанный обратно текст разметки
		return writer.text();
	};
	/**
	 * @brief Перечень текстов разметки, обязанных пережить обратную запись знак в знак
	 *
	 * @note Здесь собраны все виды объявления пространства имён: под префиксом, по
	 *       умолчанию, с отменой объявления по умолчанию, с перекрытием префикса
	 *       вложенным узлом и с двумя префиксами разом
	 */
	static constexpr const char * TEXTS[] = {
		"<s:Envelope xmlns:s=\"http://x/env\"><s:Body><u:Get xmlns:u=\"urn:svc\"><Arg>1</Arg></u:Get></s:Body></s:Envelope>",
		"<a xmlns=\"urn:one\"><b><c/></b></a>",
		"<a xmlns=\"urn:one\"><b xmlns=\"\"><c/></b></a>",
		"<p:a xmlns:p=\"u1\"><p:b xmlns:p=\"u2\"><p:c/></p:b></p:a>",
		"<a xmlns:p=\"u\" p:k=\"v\"/>",
		"<a xmlns:p=\"u\" xmlns:q=\"w\"><p:b/><q:c/></a>",
		"<a xmlns=\"u\"><p:b xmlns:p=\"u\"><c/></p:b></a>",
		"<a><b x=\"1\">t</b></a>"
	};
	/**
	 * Выполняем перебор всех текстов разметки
	 */
	for(const char * text : TEXTS)
		// Выполняем проверку того, что текст пережил обратную запись знак в знак
		ASSERT_EQ(walk(string(text)), string(text));
	// Объект дерева разметки
	xml::document_t document(::framework(), ::logger());
	// Выполняем разбор текста разметки с объявлениями на разных уровнях
	ASSERT_TRUE(document.parse("<a xmlns=\"u1\" xmlns:p=\"u2\"><p:b><c xmlns:q=\"u3\"/></p:b></a>"));
	// Получаем корневой узел разметки
	const xml::node_t root = document.element();
	// Выполняем проверку количества объявлений корневого узла
	ASSERT_EQ(root.bindings().size(), static_cast <size_t> (2));
	/**
	 * Выполняем проверку того, что объявления выдаются те, что записаны при самом узле
	 *
	 * @note Объявленное родителем действует и во вложенном узле, но принадлежит родителю:
	 *       узел «b» своих объявлений не имеет, а узел «c» имеет единственное
	 */
	ASSERT_TRUE(root.child("b", "u2").bindings().empty());
	// Выполняем проверку количества объявлений вложенного узла
	ASSERT_EQ(root.find("c", "u1").bindings().size(), static_cast <size_t> (1));
	// Выполняем проверку префикса объявления вложенного узла
	ASSERT_EQ(root.find("c", "u1").bindings().front().prefix, string_view("q"));
	// Выполняем проверку обозначения объявления вложенного узла
	ASSERT_EQ(root.find("c", "u1").bindings().front().uri, string_view("u3"));
}
/**
 * @brief Проверка сведения повторяющихся обозначений пространств имён
 *
 * @details Дерево сводит повторяющиеся обозначения пространств имён к единственному
 *          размещению в хранилище знаков. Проверяется, что сведение не путает узлы
 *          разных пространств имён и что каждому выдаётся своё обозначение
 *
 */
TEST(CodecXmlDocument, Interned) {
	/**
	 * Собираемый текст разметки со множеством одинаково названных узлов
	 *
	 * @note Узлов здесь заведомо больше порога, за которым дерево сводит повторяющиеся
	 *       обозначения пространств имён к единственному размещению: проверяется, что
	 *       сведение имён узлов не путает и обозначения выдаются каждому своё
	 */
	string text("<r xmlns=\"urn:first\" xmlns:s=\"urn:second\">");
	/**
	 * Выполняем запись узлов разметки в двух пространствах имён вперемешку
	 */
	for(size_t i = 0; i < 500; i++)
		// Выполняем добавление пары узлов разных пространств имён
		text.append("<item k=\"v\"/><s:item s:k=\"w\"/>");
	// Выполняем добавление закрывающей метки корневого узла
	text.append("</r>");
	// Объект дерева разметки
	xml::document_t document(::framework(), ::logger());
	// Выполняем разбор собранного текста разметки
	ASSERT_TRUE(document.parse(text));
	// Количество узлов первого пространства имён
	size_t first = 0;
	// Количество узлов второго пространства имён
	size_t second = 0;
	/**
	 * Выполняем перебор всех вложенных узлов корневого узла
	 */
	for(xml::node_t node = document.element().first(); node.valid(); node = node.next()){
		/**
		 * Если обнаружен узел первого пространства имён
		 */
		if(node.name().is("urn:first", "item")){
			// Выполняем проверку значения атрибута узла
			ASSERT_EQ(node.attribute("k"), string_view("v"));
			// Выполняем подсчёт узлов первого пространства имён
			first++;
		/**
		 * Если обнаружен узел второго пространства имён
		 */
		} else if(node.name().is("urn:second", "item")) {
			// Выполняем проверку значения атрибута узла
			ASSERT_EQ(node.attribute("k", "urn:second"), string_view("w"));
			// Выполняем подсчёт узлов второго пространства имён
			second++;
		// Выполняем прекращение проверки на непредусмотренном узле
		} else FAIL() << "непредусмотренное имя узла";
	}
	// Выполняем проверку количества узлов первого пространства имён
	ASSERT_EQ(first, static_cast <size_t> (500));
	// Выполняем проверку количества узлов второго пространства имён
	ASSERT_EQ(second, static_cast <size_t> (500));
}
