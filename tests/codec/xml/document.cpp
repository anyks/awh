/**
 * @brief Проверка обращения к непригодному узлу дерева
 *
 * @details Обход дерева нередко приводит к непригодному узлу - скажем, при поиске
 *          того, чего в дереве нет. Обращение к такому узлу обязано выдавать пустые
 *          значения, а не приводить к обвалу
 *
 */
TEST(CodecXmlDocument, Invalid) {
	// Непригодный узел дерева разметки
	const xml::node_t node;
	// Выполняем проверку непригодности узла
	ASSERT_FALSE(node.valid());
	// Выполняем проверку вида непригодного узла
	ASSERT_EQ(node.kind(), xml::kind_t::NONE);
	// Выполняем проверку содержимого непригодного узла
	ASSERT_TRUE(node.text().empty());
	// Выполняем проверку обхода от непригодного узла
	ASSERT_FALSE(node.parent().valid());
	// Выполняем проверку поиска от непригодного узла
	ASSERT_FALSE(node.find("x").valid());
	// Выполняем проверку обращения к атрибутам непригодного узла
	ASSERT_TRUE(node.attribute("x").empty());
}
/**
 * @brief Проверка сборки дерева большого текста разметки
 *
 */
TEST(CodecXmlDocument, Huge) {
	// Собираемый текст разметки
	string text = "<r>";
	/**
	 * Выполняем сборку текста разметки
	 */
	for(uint32_t i = 0; i < 20000; i++)
		// Выполняем добавление очередного узла разметки
		text.append("<i n='").append(to_string(i)).append("'>значение</i>");
	// Выполняем завершение текста разметки
	text.append("</r>");
	// Объект дерева разметки
	xml::document_t document;
	// Выполняем разбор собранного текста разметки
	ASSERT_TRUE(document.parse(text)) << xml::message(document.error());
	// Выполняем проверку количества узлов дерева
	ASSERT_EQ(document.size(), static_cast <size_t> ((20000 * 2) + 2));
	// Выполняем проверку значения атрибута последнего узла
	ASSERT_EQ(document.element().last().attribute("n"), "19999");
}
/**
 * @brief Проверка получения содержимого и атрибутов узлов числом
 *
 * @details Разбор чисел ведётся по правилам местности «C» без выделения памяти и
 *          без выбрасывания исключений. Признаком успеха служит выданное значение,
 *          а не разобранное число: содержимое, числом не являющееся, обязано
 *          отличаться от содержимого с числом нуль
 *
 */
TEST(CodecXmlDocument, Numeric) {
	// Объект дерева разметки
	xml::document_t document;
	// Выполняем разбор текста разметки с числовым содержимым
	ASSERT_TRUE(document.parse(
		"<r>"
		"<port id='255'>52</port>"
		"<rate>54.33</rate>"
		"<pad>  128  </pad>"
		"<sign>-42</sign>"
		"<exp>1.5e3</exp>"
		"<yes>true</yes>"
		"<no>0</no>"
		"<text>abc</text>"
		"<zero>0</zero>"
		"<tail>52abc</tail>"
		"<huge>70000</huge>"
		"<inner>5 2</inner>"
		"<empty></empty>"
		"</r>"
	)) << xml::message(document.error());
	// Получаем корневой узел дерева разметки
	const xml::node_t root = document.element();
	// Значение разбираемого целого числа
	uint16_t port = 0;
	// Выполняем разбор содержимого узла целым числом
	ASSERT_TRUE(root.child("port").value(port));
	// Выполняем проверку разобранного целого числа
	ASSERT_EQ(port, 52);
	// Выполняем разбор значения атрибута узла целым числом
	ASSERT_TRUE(root.child("port").value(port, "id"));
	// Выполняем проверку разобранного целого числа
	ASSERT_EQ(port, 255);
	// Значение разбираемого числа с плавающей точкой
	double rate = 0.;
	// Выполняем разбор содержимого узла числом с плавающей точкой
	ASSERT_TRUE(root.child("rate").value(rate));
	// Выполняем проверку разобранного числа с плавающей точкой
	ASSERT_DOUBLE_EQ(rate, 54.33);
	/**
	 * Выполняем разбор содержимого узла с пробельной обвязкой
	 *
	 * @note Обвязка появляется сама собой при записи с отступами, поэтому
	 *       отбрасывать её обязательно
	 */
	ASSERT_TRUE(root.child("pad").value(port));
	// Выполняем проверку разобранного целого числа
	ASSERT_EQ(port, 128);
	// Значение разбираемого целого числа со знаком
	int32_t sign = 0;
	// Выполняем разбор содержимого узла целым числом со знаком
	ASSERT_TRUE(root.child("sign").value(sign));
	// Выполняем проверку разобранного целого числа со знаком
	ASSERT_EQ(sign, -42);
	// Выполняем разбор содержимого узла в показательной записи
	ASSERT_TRUE(root.child("exp").value(rate));
	// Выполняем проверку разобранного числа с плавающей точкой
	ASSERT_DOUBLE_EQ(rate, 1500.);
	// Значение разбираемого логического значения
	bool flag = false;
	// Выполняем разбор содержимого узла логическим значением
	ASSERT_TRUE(root.child("yes").value(flag));
	// Выполняем проверку разобранного логического значения
	ASSERT_TRUE(flag);
	// Выполняем разбор содержимого узла логическим значением
	ASSERT_TRUE(root.child("no").value(flag));
	// Выполняем проверку разобранного логического значения
	ASSERT_FALSE(flag);
	/**
	 * Выполняем проверку отличия отказа от разобранного нуля
	 */
	{
		// Значение разбираемого целого числа
		int32_t value = -1;
		// Выполняем проверку отклонения содержимого, числом не являющегося
		ASSERT_FALSE(root.child("text").value(value));
		// Выполняем проверку сохранения значения при отказе разбора
		ASSERT_EQ(value, -1);
		// Выполняем проверку разбора содержимого с числом нуль
		ASSERT_TRUE(root.child("zero").value(value));
		// Выполняем проверку разобранного целого числа
		ASSERT_EQ(value, 0);
	}
	/**
	 * Выполняем проверку отклонения неправильно построенного содержимого
	 */
	{
		// Значение разбираемого целого числа
		int32_t value = 0;
		// Выполняем проверку отклонения остатка за числом
		ASSERT_FALSE(root.child("tail").value(value));
		// Выполняем проверку отклонения пробельного знака внутри числа
		ASSERT_FALSE(root.child("inner").value(value));
		// Выполняем проверку отклонения пустого содержимого
		ASSERT_FALSE(root.child("empty").value(value));
		// Выполняем проверку отклонения отсутствующего узла
		ASSERT_FALSE(root.child("missing").value(value));
		// Выполняем проверку отклонения отсутствующего атрибута
		ASSERT_FALSE(root.child("port").value(value, "missing"));
		// Выполняем проверку отклонения логического значения в чужой записи
		ASSERT_FALSE(root.child("text").value(flag));
	}
	/**
	 * Выполняем проверку отклонения выхода за пределы запрошенного типа
	 *
	 * @note Усечение здесь недопустимо: число, в тип не помещающееся, обязано
	 *       быть отвергнуто, а не приведено к остатку от деления
	 */
	{
		// Выполняем проверку отклонения числа, в тип не помещающегося
		ASSERT_FALSE(root.child("huge").value(port));
		// Значение разбираемого целого числа большей разрядности
		uint32_t value = 0;
		// Выполняем проверку разбора того же числа в тип большей разрядности
		ASSERT_TRUE(root.child("huge").value(value));
		// Выполняем проверку разобранного целого числа
		ASSERT_EQ(value, static_cast <uint32_t> (70000));
		// Выполняем проверку отклонения числа со знаком в тип без знака
		ASSERT_FALSE(root.child("sign").value(value));
	}
	/**
	 * Выполняем проверку разбора со значением по умолчанию
	 */
	{
		// Выполняем проверку выдачи разобранного числа
		ASSERT_EQ(root.child("port").number <uint16_t> (0), 52);
		// Выполняем проверку выдачи значения по умолчанию при отказе разбора
		ASSERT_EQ(root.child("text").number <uint16_t> (7), 7);
		// Выполняем проверку выдачи значения по умолчанию для отсутствующего узла
		ASSERT_EQ(root.child("missing").number <uint16_t> (7), 7);
		// Выполняем проверку выдачи разобранного значения атрибута
		ASSERT_EQ(root.child("port").number <uint16_t> ("id", 0), 255);
		// Выполняем проверку выдачи значения по умолчанию для отсутствующего атрибута
		ASSERT_EQ(root.child("port").number <uint16_t> ("missing", 9), 9);
	}
}
/**
 * @brief Проверка отделения незначимого пробельного содержимого в дереве разметки
 *
 * @details Отступы записи в дереве неотличимы от значащих пробелов, пока разбору не
 *          указано их разделять. С включённой настройкой дерево кладёт их отдельным
 *          видом узла, а содержимое узла и его обратная запись от этого не меняются
 *
 */
TEST(CodecXmlDocument, SpaceNodes) {
	// Разбираемый текст разметки с отступами записи
	const string text = "<r>\n\t<a>x</a>\n\t<b> y </b>\n</r>";
	/**
	 * Выполняем проверку разбора без отделения пробельного содержимого
	 */
	{
		// Объект дерева разметки
		xml::document_t document;
		// Выполняем разбор текста разметки
		ASSERT_TRUE(document.parse(text));
		// Количество обнаруженных узлов пробельного содержимого
		size_t spaces = 0;
		/**
		 * Выполняем перебор всех вложенных узлов корня дерева
		 */
		for(xml::node_t node = document.root().first().first(); node.valid(); node = node.next()){
			// Если обнаружен узел пробельного содержимого, увеличиваем счётчик
			if(node.kind() == xml::kind_t::SPACE) spaces++;
		}
		// Выполняем проверку того, что пробельное содержимое отдельным видом не выделено
		ASSERT_EQ(spaces, static_cast <size_t> (0));
		// Выполняем проверку того, что содержимое корня собрано целиком
		ASSERT_EQ(document.root().first().text(), string("\n\tx\n\t y \n"));
	}
	/**
	 * Выполняем проверку разбора с отделением пробельного содержимого
	 */
	{
		// Объект дерева разметки
		xml::document_t document;
		// Настройки разбора текста разметки
		xml::reader_t::settings_t settings;
		// Выполняем включение отделения незначимого пробельного содержимого
		settings.separateSpaces = true;
		// Выполняем разбор текста разметки
		ASSERT_TRUE(document.parse(text, settings));
		// Количество обнаруженных узлов пробельного содержимого
		size_t spaces = 0;
		/**
		 * Выполняем перебор всех вложенных узлов корня дерева
		 */
		for(xml::node_t node = document.root().first().first(); node.valid(); node = node.next()){
			// Если обнаружен узел пробельного содержимого, увеличиваем счётчик
			if(node.kind() == xml::kind_t::SPACE) spaces++;
		}
		// Выполняем проверку того, что отступы записи выделены отдельным видом узла
		ASSERT_EQ(spaces, static_cast <size_t> (3));
		/**
		 * Выполняем проверку неизменности содержимого узла
		 *
		 * @note Настройка разбора отбирает вид узла, а содержимое узла разметки
		 *       обязано остаться тем же самым
		 */
		ASSERT_EQ(document.root().first().text(), string("\n\tx\n\t y \n"));
		/**
		 * Выполняем проверку того, что значащие пробелы отдельным видом не выделены
		 */
		ASSERT_EQ(document.root().first().child("b").first().kind(), xml::kind_t::TEXT);
		// Объект записи текста разметки
		xml::writer_t writer;
		// Выполняем запись собранного дерева разметки
		ASSERT_TRUE(writer.element(document.root()));
		// Выполняем проверку того, что запись дерева воспроизводит исходный текст
		ASSERT_EQ(writer.text(), text);
	}
}
/**
 * @brief Проверка обратной записи дерева, разобранного без пространств имён
 *
 * @details Разбор без пространств имён кладёт имя в дерево целиком, вместе с
 *          разделителем префикса, а объявления пространств имён считает обычными
 *          атрибутами. Такой текст правильно построен по договору разметки, и запись
 *          обязана его воспроизводить: подбирать префиксы там не по чему и незачем
 *
 */
/**
 * @brief Проверка наличия атрибута узла с учётом пространства имён
 *
 * @details Замер охвата показал, что до этого хода не доходило ни одно испытание.
 *          Проверяется прежде всего то, что пустое обозначение означает отсутствие
 *          пространства имён, а не «любое»: имя с префиксом по нему находиться
 *          не должно
 *
 */
TEST(CodecXmlDocument, AttributeLookup) {
	// Объект дерева разметки
	xml::document_t document;
	// Выполняем разбор текста разметки с атрибутом в пространстве имён
	ASSERT_TRUE(document.parse("<a xmlns:p=\"urn:p\" p:k=\"1\" m=\"2\"/>")) << xml::message(document.error());
	// Получаем корневой узел разметки
	const xml::node_t node = document.element();
	// Выполняем проверку наличия атрибута в объявленном пространстве имён
	ASSERT_TRUE(node.has("k", "urn:p"));
	// Выполняем проверку отсутствия того же имени вне пространства имён
	ASSERT_FALSE(node.has("k", ""));
	// Выполняем проверку отсутствия того же имени в чужом пространстве имён
	ASSERT_FALSE(node.has("k", "urn:z"));
	// Выполняем проверку наличия атрибута без пространства имён
	ASSERT_TRUE(node.has("m", ""));
	/**
	 * Выполняем проверку того, что атрибут без префикса пространство имён узла не получает
	 *
	 * @note Договор об именах прямо велит не распространять объявленное по умолчанию
	 *       пространство имён на имена атрибутов
	 */
	ASSERT_TRUE(node.has("m"));
	// Выполняем проверку отсутствия незаписанного атрибута
	ASSERT_FALSE(node.has("z", ""));
	// Выполняем проверку того, что непригодный узел атрибутов не имеет
	ASSERT_FALSE(xml::node_t().has("m", ""));
}
TEST(CodecXmlDocument, VerbatimNames) {
	/**
	 * @brief Метод кругового хода текста разметки через дерево
	 *
	 * @param text разбираемый текст разметки
	 * @param ns   признак разбора с учётом пространств имён
	 * @return     текст, записанный обратно по собранному дереву
	 *
	 */
	const auto walk = [](const string & text, const bool ns) noexcept -> string {
		// Объект дерева разметки
		xml::document_t document;
		// Настройки разбора текста разметки
		xml::reader_t::settings_t settings;
		// Устанавливаем признак разбора с учётом пространств имён
		settings.namespaces = ns;
		// Если разбор текста разметки выполнить не удалось, выводим признак отказа
		if(!document.parse(text, settings)) return string("ОТКАЗ РАЗБОРА");
		// Объект записи текста разметки
		xml::writer_t writer;
		// Если запись собранного дерева выполнить не удалось, выводим признак отказа
		if(!writer.element(document.root())) return string("ОТКАЗ ЗАПИСИ");
		// Выводим записанный текст разметки
		return writer.text();
	};
	/**
	 * Выполняем перебор всех проверяемых текстов разметки
	 */
	for(const char * text : {
		"<a x=\"1\">t</a>",
		"<p:a p:x=\"1\">t</p:a>",
		"<p:a xmlns:p=\"u\">t</p:a>",
		"<a xmlns=\"u\"><b/></a>",
		"<a xmlns=\"u\" xmlns:p=\"v\"><p:b p:y=\"2\"/></a>",
		"<a:b:c/>"
	}){
		/**
		 * Выполняем проверку воспроизведения текста разбором без пространств имён
		 *
		 * @note Имена воспроизводятся знак в знак: делить их не на что, и запись
		 *       выводит их такими, какими они в дереве и лежат
		 */
		ASSERT_EQ(walk(text, false), string(text));
	}
	/**
	 * Выполняем проверку того, что разбор с пространствами имён поведения не сменил
	 */
	{
		// Выполняем проверку воспроизведения имени с префиксом
		ASSERT_EQ(walk("<p:a xmlns:p=\"u\">t</p:a>", true), string("<p:a xmlns:p=\"u\">t</p:a>"));
		// Выполняем проверку воспроизведения отмены объявления по умолчанию
		ASSERT_EQ(walk("<a xmlns=\"u\"><b xmlns=\"\"/></a>", true), string("<a xmlns=\"u\"><b xmlns=\"\"/></a>"));
		/**
		 * Выполняем проверку отклонения имени с разделителем при пространствах имён
		 *
		 * @note Разделитель в имени разбор с пространствами имён делит, и в дерево он
		 *       не попадает вовсе; попавший туда иначе означал бы имя, договору о
		 *       пространствах имён не отвечающее
		 */
		ASSERT_EQ(walk("<a:b:c/>", true), string("ОТКАЗ РАЗБОРА"));
	}
}
/**
 * @brief Проверка устойчивости перехода текст→дерево→текст
 *
 * @details Дерево, собранное разбором записанного текста, записанным обязано дать
 *          тот же самый текст знак в знак: расхождение означает, что переход теряет
 *          либо добавляет содержимое. Проверяется он на плотной записи - нарядная
 *          отступает от уже записанных отступов и повторяться знак в знак не обязана
 *
 * @note Найдено ворошителем `tools/fuzz/xml.cpp`: ссылка на сущность с пустым
 *       значением давала дереву пустой узел содержимого, из-за которого запись
 *       узла переставала складываться самозакрывающейся меткой
 *
 */
TEST(CodecXmlDocument, RewriteStability) {
	/**
	 * @brief Метод записи дерева разметки, собранного разбором текста
	 *
	 * @param text разбираемый текст разметки
	 * @return     записанный текст разметки либо признак отказа
	 *
	 */
	const auto rewrite = [](const string & text) noexcept -> string {
		// Настройки разбора текста разметки
		xml::reader_t::settings_t settings;
		// Выполняем включение подстановки ссылок на объявленные сущности
		settings.entities = true;
		// Выполняем склеивание подряд идущих кусков содержимого
		settings.mergeText = true;
		// Дерево разметки, собираемое разбором текста
		xml::document_t document;
		// Если разбор текста разметки выполнить не удалось, выводим признак отказа
		if(!document.parse(text, settings)) return "ОТКАЗ РАЗБОРА";
		// Настройки записи текста разметки
		xml::writer_t::settings_t options;
		// Выполняем установку плотного вида записи собираемого текста
		options.format = xml::format_t::COMPACT;
		// Объект записи текста разметки
		xml::writer_t writer(options);
		// Если запись дерева разметки выполнить не удалось, выводим признак отказа
		if(!writer.element(document.root()) || !writer.complete()) return "ОТКАЗ ЗАПИСИ";
		// Выводим записанный текст разметки
		return writer.text();
	};
	/**
	 * @brief Тексты разметки, устойчивость перезаписи которых проверяется
	 *
	 */
	const char * items[] = {
		"<!DOCTYPE a [<!ENTITY e \"\">]><a><c>&e;</c></a>",
		"<a><c></c><d>текст</d><e/></a>",
		"<a><![CDATA[ x < y ]]><!-- примечание --><?цель данные?></a>",
		"<a xmlns:ns=\"urn:named\"><ns:b ns:p=\"v\">содержимое</ns:b></a>",
		"<a> <b/> </a>"
	};
	/**
	 * Выполняем перебор всех проверяемых текстов разметки
	 */
	for(const char * item : items){
		// Выполняем первую перезапись дерева разметки
		const string first = rewrite(item);
		// Выполняем проверку того, что перезапись дерева разметки удалась
		ASSERT_EQ(first.rfind("ОТКАЗ", 0), string::npos) << item;
		// Выполняем повторную перезапись дерева разметки
		const string second = rewrite(first);
		// Выполняем проверку устойчивости перезаписи дерева разметки
		ASSERT_EQ(first, second) << item;
	}
}
/**
 * @brief Проверка перемещения по дереву разметки и мест его узлов
 *
 * @details Проверяются обращения, которыми пользуется обходящий дерево: движение к
 *          соседям в обе стороны, приведение узла к признаку пригодности, место узла
 *          в исходном тексте и место обнаруженной разбором ошибки
 *
 */
TEST(CodecXmlDocument, Navigation) {
	// Дерево разметки, собираемое разбором текста
	xml::document_t document;
	// Выполняем разбор текста разметки, записанного тремя строками
	ASSERT_TRUE(document.parse("<r>\n\t<a/>\n\t<b/>\n\t<c/>\n</r>"));
	// Выполняем проверку непустоты собранного дерева разметки
	ASSERT_FALSE(document.empty());
	// Выполняем проверку количества узлов собранного дерева разметки
	ASSERT_GT(document.size(), 3u);
	// Получаем корневой узел разметки
	const xml::node_t root = document.element();
	// Выполняем проверку пригодности корневого узла разметки
	ASSERT_TRUE(static_cast <bool> (root));
	// Выполняем проверку непригодности узла, полученного по умолчанию
	ASSERT_FALSE(static_cast <bool> (xml::node_t()));
	// Получаем последний вложенный узел корневого узла
	const xml::node_t last = root.child("c");
	// Выполняем проверку пригодности найденного узла
	ASSERT_TRUE(last.valid());
	// Выполняем проверку места найденного узла в исходном тексте
	ASSERT_EQ(last.location().line, 4u);
	// Собираемая запись обхода вложенных узлов в обратную сторону
	string result;
	/**
	 * Выполняем перебор всех вложенных узлов от последнего к первому
	 */
	for(xml::node_t node = last; node.valid(); node = node.prev()){
		// Если очередной узел является узлом разметки
		if(node.kind() == xml::kind_t::ELEMENT)
			// Выполняем добавление имени очередного узла к записи обхода
			result.append(node.name().local);
	}
	// Выполняем проверку порядка обхода вложенных узлов в обратную сторону
	ASSERT_EQ(result, "cba");
	// Выполняем проверку непригодности узла перед первым вложенным
	ASSERT_FALSE(root.first().prev().valid());
	// Выполняем проверку непригодности соседа за последним вложенным узлом
	ASSERT_FALSE(root.last().next().valid());
	// Дерево разметки, собираемое разбором ошибочного текста
	xml::document_t broken;
	// Выполняем разбор текста разметки с незакрытым узлом
	ASSERT_FALSE(broken.parse("<r>\n\t<a>\n</r>"));
	// Выполняем проверку кода ошибки разбора текста разметки
	ASSERT_EQ(broken.error(), xml::error_t::MISMATCHED_TAG);
	// Выполняем проверку строки, в которой обнаружена ошибка разбора
	ASSERT_EQ(broken.errorLocation().line, 3u);
	// Выполняем проверку пустоты дерева, собранного разбором с ошибкой
	ASSERT_TRUE(broken.empty());
	/**
	 * Выполняем проверку обращений к непригодному узлу дерева
	 *
	 * @note Обращения к нему обязаны отвечать пустым, а не рушить обход: узел
	 *       непригодный получается всяким движением за край дерева, и проверять
	 *       его пригодность перед каждым обращением обходящему несподручно
	 */
	{
		// Непригодный узел дерева разметки
		const xml::node_t node;
		// Выполняем проверку вида непригодного узла дерева
		ASSERT_EQ(node.kind(), xml::kind_t::NONE);
		// Выполняем проверку имени непригодного узла дерева
		ASSERT_TRUE(node.name().local.empty());
		// Выполняем проверку содержимого непригодного узла дерева
		ASSERT_TRUE(node.text().empty());
		// Выполняем проверку места непригодного узла в исходном тексте
		ASSERT_EQ(node.location().line, 0u);
		// Выполняем проверку перечня атрибутов непригодного узла
		ASSERT_TRUE(node.attributes().empty());
		// Выполняем проверку перечня объявлений пространств имён непригодного узла
		ASSERT_TRUE(node.bindings().empty());
		// Выполняем проверку значения атрибута непригодного узла
		ASSERT_TRUE(node.attribute("k").empty());
		// Выполняем проверку признака наличия атрибута у непригодного узла
		ASSERT_FALSE(node.has("k"));
		// Выполняем проверку обращения к родителю непригодного узла
		ASSERT_FALSE(node.parent().valid());
		// Выполняем проверку обращения к вложенным узлам непригодного узла
		ASSERT_FALSE(node.first().valid());
		ASSERT_FALSE(node.last().valid());
		// Выполняем проверку обращения к соседям непригодного узла
		ASSERT_FALSE(node.next().valid());
		ASSERT_FALSE(node.prev().valid());
		// Выполняем проверку поиска вложенного узла у непригодного узла
		ASSERT_FALSE(node.child("a").valid());
		ASSERT_FALSE(node.find("a").valid());
		// Выполняем проверку перечня вложенных узлов непригодного узла
		ASSERT_TRUE(node.children("a").empty());
		// Выполняем проверку сличения непригодных узлов между собой
		ASSERT_TRUE(node == xml::node_t());
		// Выполняем проверку несовпадения непригодного узла с пригодным
		ASSERT_TRUE(node != document.element());
		// Число, полученное разбором содержимого непригодного узла
		int64_t number = 0;
		// Выполняем проверку разбора содержимого непригодного узла числом
		ASSERT_FALSE(node.value(number));
		// Выполняем проверку выдачи запасного значения непригодным узлом
		ASSERT_EQ(node.number <int64_t> (-1), -1);
	}
}
/**
 * @brief Проверка отказа приведения кодировки при передаче исходного текста
 *
 * @details Отказы разбора приходят двумя путями: из передачи исходного текста и из
 *          выдачи события. Карта покрытия показала первый путь нетронутым, а он не
 *          тождествен второму: приведение кодировки ведётся при передаче, и отказ его
 *          выносится до того, как разбор начался вовсе
 *
 * @note Сличается и очистка дерева: сведения об отказе снимаются ДО очистки, потому
 *       что очистка их сбрасывает. Проверка кода отказа после разбора и держит этот
 *       порядок - переставь его, и потребитель получил бы отказ без кода
 *
 */
TEST(CodecXmlDocument, EncodingRefusalOnFeed) {
	// Объект дерева разметки
	xml::document_t document;
	// Выполняем разбор текста с объявлением двухбайтовой кодировки при однобайтовой записи
	ASSERT_FALSE(document.parse("<?xml version='1.0' encoding='UTF-16'?><a/>"));
	// Выполняем проверку кода отказа разбора
	ASSERT_EQ(document.error(), xml::error_t::INVALID_ENCODING);
	// Выполняем проверку того, что дерево осталось пустым
	ASSERT_EQ(document.element().kind(), xml::kind_t::NONE);
	// Выполняем разбор текста с объявлением, расходящимся с меткой порядка байтов
	ASSERT_FALSE(document.parse("\xEF\xBB\xBF<?xml version='1.0' encoding='ISO-8859-1'?><a/>"));
	// Выполняем проверку кода отказа разбора
	ASSERT_EQ(document.error(), xml::error_t::INVALID_ENCODING);
	// Выполняем проверку того, что годный текст после отказа разбирается
	ASSERT_TRUE(document.parse("<a>з</a>")) << xml::message(document.error());
	// Выполняем проверку разобранного содержимого узла
	ASSERT_EQ(document.element().text(), "з");
}
