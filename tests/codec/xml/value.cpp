/**
 * @brief Проверка согласия двух путей записи разметки
 *
 * @details Запись разметки существует в двух исполнениях - обходом дерева документа и
 *          потоковой записью владеющего значения, - а правила у них общие: сохранение
 *          пробелов по `xml:space`, значимость раздела дословного текста, заслон
 *          смешанного содержимого. Правила эти живут порознь, и заведённое в одном
 *          пути легко забыть во втором
 *
 * @note Дефекты найдены сличением обоих путей на корпусе соответствия: 442 расхождения
 *       из 1946 сличений, все при нарядной записи
 *
 */
TEST(CodecXmlValue, WritingPathsAgree) {
	// Настройки нарядной записи текста разметки
	xml::writer_t::settings_t settings;
	// Устанавливаем нарядный вид записи
	settings.format = xml::format_t::PRETTY;
	// Сличаемые тексты разметки
	const vector <string> samples = {
		// Узел, которому договором предписано хранить пробельное содержимое
		"<a xml:space=\"preserve\"><b>  два  пробела  </b>\n\n<c/></a>",
		// Узел с разделом дословного текста, значимым сам по себе
		"<a><b/><![CDATA[]]><b/></a>",
		// Узел со смешанным содержимым
		"<a>перед<b/>после</a>",
		// Узел с прежними пробельными узлами, какие нарядная запись сворачивает
		"<a>\n\t<b/>   <b/>\n\n</a>"
	};
	/**
	 * Выполняем перебор всех сличаемых текстов разметки
	 */
	for(const string & sample : samples){
		// Объект документа разметки
		xml::document_t document(::logger());
		// Выполняем разбор текста разметки документом
		ASSERT_TRUE(document.parse(sample)) << sample;
		// Объект записи текста разметки
		xml::writer_t writer(::logger());
		// Устанавливаем настройки записи текста разметки
		writer.settings(settings);
		// Выполняем запись дерева документа обходом
		ASSERT_TRUE(writer.element(document.root())) << sample;
		// Завершаем запись текста разметки
		ASSERT_TRUE(writer.complete()) << sample;
		// Владеющее значение разметки
		xml::value_t value;
		// Выполняем разбор того же текста разметки значением
		ASSERT_TRUE(value.parse(sample)) << sample;
		// Проверяем совпадение записи обоими путями
		ASSERT_EQ(writer.text(), value.dump(settings)) << sample;
	}
}

