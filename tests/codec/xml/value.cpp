/**
 * @brief Безымянное пространство имён вспомогательных объявлений проверок
 *
 * @note Пространство это безымянно намеренно: проверки всех кодеков собираются одной
 *       программой, и вынесенное наружу имя столкнулось бы с таким же именем соседа
 *
 */
namespace {
	/**
	 * @brief Функция, возвращающая значение наружу, как это делал бы модуль
	 *
	 * @return собранное значение
	 *
	 */
	static xml::value_t produce() noexcept {
		// Собираемый узел разметки
		xml::value_t result("Envelope");
		// Выполняем заведение вложенного узла разметки с содержимым
		result["Body"]["Ping"].text("привет");
		// Выполняем заведение свойства вложенного узла разметки
		result["Body"]["Ping"].attribute("id", "7");
		// Выводим собранный узел разметки
		return result;
	}
}

/**
 * @brief Проверка заведения поддерева из ничего
 *
 */
TEST(CodecXmlValue, Assemble) {
	// Собираемое значение
	xml::value_t value;
	// Выполняем проверку неопределённости пустого значения
	ASSERT_FALSE(value.valid());
	// Выполняем проверку вида пустого значения
	ASSERT_EQ(value.kind(), xml::kind_t::NONE);
	// Выполняем заведение вложенного узла разметки
	value["root"].text("содержимое");
	// Выполняем проверку перерождения значения узлом разметки
	ASSERT_EQ(value.kind(), xml::kind_t::ELEMENT);
	// Выполняем проверку количества вложенных узлов
	ASSERT_EQ(value.size(), static_cast <size_t> (1));
	// Выполняем проверку имени заведённого узла
	ASSERT_STREQ(value[static_cast <size_t> (0)].local().c_str(), "root");
	// Выполняем проверку содержимого заведённого узла
	ASSERT_STREQ(value["root"].text().c_str(), "содержимое");
}

/**
 * @brief Проверка передачи значения наружу итогом метода
 *
 * @note Проверка эта и есть та самая, ради какой тип заведён: узел дерева разметки
 *       наружу передан быть не может вовсе
 *
 */
TEST(CodecXmlValue, Produce) {
	// Получаем значение, собранное и выданное наружу
	const xml::value_t value = ::produce();
	// Выполняем проверку записи собранного значения
	ASSERT_STREQ(value.dump().c_str(), "<Envelope><Body><Ping id=\"7\">привет</Ping></Body></Envelope>");
	// Выполняем проверку обращения по пути
	ASSERT_STREQ(value.at("/Body/Ping").text().c_str(), "привет");
	// Выполняем проверку извлечения свойства узла разметки
	ASSERT_STREQ(value.at("/Body/Ping").attribute("id").c_str(), "7");
	// Выполняем проверку наличия свойства узла разметки
	ASSERT_TRUE(value.at("/Body/Ping").has("id"));
	// Выполняем проверку отсутствия незаведённого свойства
	ASSERT_FALSE(value.at("/Body/Ping").has("нет"));
}

/**
 * @brief Проверка складываемости значения во вместилища языка
 *
 */
TEST(CodecXmlValue, Storable) {
	// Вместилище языка, куда складываются значения
	vector <xml::value_t> items;
	// Выполняем добавление собранного значения во вместилище
	items.push_back(::produce());
	// Выполняем проверку сохранности собранного значения
	ASSERT_STREQ(items.at(0)["Body"]["Ping"].text().c_str(), "привет");
	// Выполняем копирование значения
	const xml::value_t copy = items.at(0);
	// Выполняем очистку вместилища языка
	items.clear();
	// Выполняем проверку сохранности копии после гибели исходного значения
	ASSERT_STREQ(copy["Body"]["Ping"].text().c_str(), "привет");
}

