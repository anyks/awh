/**
 * @brief Проверка совпадения двух путей записи разметки
 *
 * @details Записать разбор можно двумя путями: самим деревом и снятым с него владеющим
 * значением. Пути эти обязаны давать текст один в один при всяком содержимом
 *
 * @note Проверка эта нашла дефект в день своего написания: значение объявляло
 *       связывания префиксов **после** открытия узла, отчего поток записи успевал
 *       назначить префикс сам, и запись выходила с двумя объявлениями одного и того же
 *       пространства имён
 *
 */
TEST(CodecXmlValue, Differential) {
	/**
	 * Разбираемые тексты разметки, взятые по краям видов узлов и строения
	 */
	const vector <string> samples = {
		"<root/>", "<root>текст</root>", "<root a=\"1\"/>",
		"<root a=\"1\" b=\"2\"><child/></root>", "<root><a/><b/><a/></root>",
		"<root>первый<em>второй</em>третий</root>", "<root><![CDATA[дословно]]></root>",
		"<root><!--примечание--></root>", "<root><?цель содержимое?></root>",
		"<s:Envelope xmlns:s=\"http://soap\"><s:Body/></s:Envelope>",
		"<root xmlns=\"http://по-умолчанию\"><child/></root>",
		"<root xmlns:a=\"http://один\" xmlns:b=\"http://два\"><a:x b:y=\"1\"/></root>",
		"<root a=\"&lt;&amp;&gt;\">&lt;текст&gt;</root>",
		"<root><вглубь><ещё><и><ещё/></и></ещё></вглубь></root>",
		"<root a=\"строка с пробелами\"/>", "<root>  пробелы  </root>",
		"<root><a>1</a><a>2</a><a>3</a></root>", "<корень свойство=\"значение\">содержимое</корень>",
		"<root><child/>хвост</root>"
	};
	/**
	 * Выполняем перебор всех разбираемых текстов разметки
	 */
	for(auto & sample : samples){
		// Дерево разметки, разбирающее текст
		xml::document_t document;
		// Выполняем разбор текста разметки
		ASSERT_TRUE(document.parse(sample)) << sample;
		// Поток записи текста разметки
		xml::writer_t writer;
		// Выполняем запись дерева разметки напрямую
		ASSERT_TRUE(writer.element(document.element())) << sample;
		// Снятое с дерева значение
		const xml::value_t taken(document.element());
		// Выполняем проверку совпадения записей обоих путей
		ASSERT_EQ(writer.text(), taken.dump()) << sample;
		// Дерево разметки, разбирающее запись снятого значения
		xml::document_t twin;
		// Выполняем разбор записи снятого значения
		ASSERT_TRUE(twin.parse(taken.dump())) << taken.dump();
		// Выполняем проверку совпадения значения с прошедшим круговой ход
		ASSERT_TRUE(xml::value_t(twin.element()) == taken) << taken.dump();
	}
}

