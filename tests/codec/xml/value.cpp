/**
 * @brief Проверка правки свойств широкого узла разметки
 *
 * @note Отображение свойств заводится по требованию и обязано сбрасываться на всяком
 *       пути правки перечня свойств. Пути эти разные: перезапись значения на своём
 *       месте, снятие свойства из середины перечня и очистка узла целиком
 * @warning Снятие свойства сдвигает номера ВСЕХ свойств, следующих за снятым, и без
 *          сброса отображение указывало бы мимо - выдавая значение чужого свойства.
 *          Оттого сличается именно значение, а не одно лишь наличие
 */
TEST(CodecXmlValue, WidePropertyMutators){
	// Количество заводимых свойств узла разметки
	const size_t count = (xml::INDEX_THRESHOLD * 8);
	// Собираемый узел разметки
	xml::value_t root(string("root"));
	/**
	 * Выполняем заведение свойств узла разметки
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем установку очередного свойства узла
		ASSERT_TRUE(root.attribute("k" + to_string(i), "v" + to_string(i)));
	// Получаем неизменяемую ссылку на собранный узел разметки
	const xml::value_t & fixed = root;
	// Выполняем заведение отображения свойств розыском
	ASSERT_EQ(fixed.attribute("k0"), "v0");
	// Выполняем перезапись значения свойства на своём месте
	ASSERT_TRUE(root.attribute("k0", "иное"));
	// Выполняем проверку того, что перезапись видна розыском
	ASSERT_EQ(fixed.attribute("k0"), "иное");
	/**
	 * Выполняем снятие свойства из середины перечня
	 */
	ASSERT_TRUE(root.detach("k0"));
	// Выполняем проверку того, что снятое свойство более не разыскивается
	ASSERT_FALSE(fixed.has("k0"));
	/**
	 * Выполняем перебор всех оставшихся свойств узла
	 *
	 * @note Здесь и виден сдвиг номеров: без сброса отображения свойство `k1` выдавало
	 *       бы значение соседа, ибо номер его после снятия уменьшился на единицу
	 */
	for(size_t i = 1; i < count; i++)
		// Выполняем проверку значения оставшегося свойства узла
		ASSERT_EQ(fixed.attribute("k" + to_string(i)), "v" + to_string(i));
	// Выполняем заведение свойства взамен снятого
	ASSERT_TRUE(root.attribute("k0", "новое"));
	// Выполняем проверку того, что заведённое свойство разыскивается
	ASSERT_EQ(fixed.attribute("k0"), "новое");
	/**
	 * Выполняем очистку узла разметки целиком
	 */
	root.clear();
	// Выполняем проверку того, что свойства очищенного узла не разыскиваются
	ASSERT_FALSE(fixed.has("k1"));
	/**
	 * Выполняем повторное заведение свойств очищенного узла
	 *
	 * @warning Долив этот обязателен, и без него проверка забытый сброс НЕ ЛОВИТ: у
	 *          очищенного узла свойств ноль, розыск уходит в ветвь перебора и до
	 *          отображения не доходит вовсе. Отображение обязано вновь стать негодным -
	 *          то есть узел обязан вновь стать ШИРЕ порога
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем установку очередного свойства узла
		ASSERT_TRUE(root.attribute("n" + to_string(i), "w" + to_string(i)));
	/**
	 * Выполняем перебор всех заведённых заново свойств узла
	 *
	 * @note Здесь и виден забытый сброс: отображение, пережившее очистку, указывало бы
	 *       номерами прежних свойств, и значения выходили бы чужими
	 */
	for(size_t i = 0; i < count; i++)
		// Выполняем проверку значения заведённого заново свойства узла
		ASSERT_EQ(fixed.attribute("n" + to_string(i)), "w" + to_string(i));
	// Выполняем проверку того, что прежние свойства не разыскиваются
	ASSERT_FALSE(fixed.has("k1"));
}
