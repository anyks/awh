/**
 * @brief Проверка сохранности дерева разметки после прививки
 *
 */
TEST(CodecXmlValue, GraftIntegrity) {
	// Дерево разметки, принимающее прививку
	xml::document_t document;
	// Выполняем разбор текста разметки
	ASSERT_TRUE(document.parse("<a><b/><c/><d/></a>"));
	// Прививаемое значение
	const xml::value_t value(string("z"));
	// Выполняем прививку значения на место среднего вложенного узла
	ASSERT_TRUE(document.graft("/a/c", value));
	// Получаем корневой узел разметки
	const xml::node_t element = document.element();
	// Собираемый перечень имён вложенных узлов
	string names;
	/**
	 * Выполняем перебор всех вложенных узлов движением вперёд
	 */
	for(xml::node_t child = element.first(); child.valid(); child = child.next())
		// Выполняем добавление местного имени вложенного узла к перечню
		names.append(child.name().local);
	// Выполняем проверку порядка вложенных узлов движением вперёд
	ASSERT_EQ(names, "bzd");
	// Выполняем очистку собираемого перечня имён вложенных узлов
	names.clear();
	/**
	 * Выполняем перебор всех вложенных узлов движением назад
	 *
	 * @note Связность проверяется в обе стороны намеренно: прививка правит ссылки
	 *       соседей по отдельности, и односторонний обход разрыва не заметил бы
	 */
	for(xml::node_t child = element.last(); child.valid(); child = child.prev())
		// Выполняем добавление местного имени вложенного узла к перечню
		names.append(child.name().local);
	// Выполняем проверку порядка вложенных узлов движением назад
	ASSERT_EQ(names, "dzb");
	// Выполняем проверку того, что привитый узел числит своим родителем корневой
	ASSERT_TRUE(element.first().next().parent() == element);
}

/**
 * @brief Проверка обращения прививки с значением, несущим корень дерева
 *
 * @details Корень вмещает содержимое текста целиком и узлом разметки не является вовсе:
 *          родителя он не имеет по устройству, и стать ребёнком ему неоткуда. Корень с
 *          единственным узлом прививается узлом этим - разбор текста во владеющее значение
 *          корень заводит всегда, - а корень с иным числом узлов отвергается: одним узлом
 *          ему не стать, а прививка заменяет узел узлом
 *
 * @note Записи изъян этот не торчал вовсе: запись корень пропускает, выводя одно
 *       содержимое его, отчего текст выходил правильным при испорченном дереве
 *
 */
TEST(CodecXmlValue, GraftDocumentKind) {
	// Дерево разметки, куда прививается значение
	xml::document_t document;
	// Выполняем разбор текста разметки дерева
	ASSERT_TRUE(document.parse("<a><b/></a>"));
	// Прививаемое значение, разобранное из текста единственного узла
	xml::value_t single;
	// Выполняем разбор текста разметки прививаемого значения
	ASSERT_TRUE(single.parse("<x/>"));
	// Выполняем проверку того, что разбор завёл корень дерева
	ASSERT_EQ(single.kind(), xml::kind_t::DOCUMENT);
	ASSERT_EQ(single.size(), static_cast <size_t> (1));
	// Выполняем проверку того, что прививка корня с единственным узлом проходит
	ASSERT_TRUE(document.graft("/a/b", single));
	// Прививаемое значение, разобранное из текста нескольких узлов
	xml::value_t several;
	// Выполняем разбор текста разметки с примечанием над узлом разметки
	ASSERT_TRUE(several.parse("<!-- c --><y/>"));
	// Выполняем проверку того, что корень заведён с двумя узлами
	ASSERT_EQ(several.size(), static_cast <size_t> (2));
	// Выполняем проверку того, что прививка корня с несколькими узлами отвергается
	ASSERT_FALSE(document.graft("/a/x", several));
	// Поток записи текста разметки
	xml::writer_t writer;
	// Выполняем запись дерева разметки
	ASSERT_TRUE(writer.element(document.element()));
	// Выполняем завершение записи текста разметки
	ASSERT_TRUE(writer.complete());
	// Выполняем проверку того, что дерево несёт один лишь узел привитый
	ASSERT_EQ(writer.text(), "<a><x/></a>");
}

