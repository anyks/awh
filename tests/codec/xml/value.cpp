/**
 * @brief Проверка того, что файловый вход слушает настройки разбора наравне с текстовым
 *
 * @details Вход файловый и вход текстовый суть два входа к ОДНОМУ разбору, и пределы,
 *          его оберегающие, обязаны быть достижимы с обоих. Замер 01.09.2026 вскрыл, что
 *          у разметки достижимы они были лишь с текстового: `load` настроек не принимал
 *          вовсе и разбирал умолчаниями. Заведена перегрузка `load(файл, настройки)` -
 *          по укладу соседних кодеков рамки, где перегрузка эта была изначально
 *
 * @warning Недостижимость эта была не в удобстве, а в охране: умолчаниями снимались
 *          пределы имени, глубины вложенности и количества объявленных сущностей, то
 *          есть ровно те, что оберегают разбор от разрастания поданного извне текста
 *
 * @note Проверка держит ТРИ входа разом: текстовый с пределом, файловый с пределом и
 *       файловый умолчаниями. Третий стоит здесь затем, чтобы перегрузка не превратилась
 *       в предел, наложенный на всех: умолчаниями текст обязан приниматься
 *
 */
TEST(CodecXmlValue, FileInputObeysTheSettings) {
	// Разбираемый текст разметки с именем длиннее предела
	const string text = "<аааааааааааа/>";
	// Адрес временного файла разметки
	/**
	 * Временный файл проверки
	 *
	 * @note Сторож берётся вместо голого пути со сносом в конце: снос, стоящий одним
	 *       лишь хвостом тела, не снимает файла за прогоном, прерванным отказом
	 *       утверждения, а переживший файл обращает проверку записи в ложное зелёное
	 */
	const Scratch scratch_path("awh-xml-settings-input.xml");
	// Путь к временному файлу проверки
	const string & path = scratch_path.path();
	/**
	 * Выполняем запись разбираемого текста во временный файл
	 */
	{
		// Открываем временный файл разметки на запись
		FILE * file = ::fopen(path.c_str(), "wb");
		// Выполняем проверку открытия временного файла
		ASSERT_NE(file, nullptr);
		// Выполняем запись текста разметки в файл
		ASSERT_EQ(::fwrite(text.data(), 1, text.size(), file), text.size());
		// Выполняем закрытие временного файла разметки
		::fclose(file);
	}
	// Настройки разбора с пределом длины имени
	xml::reader_t::settings_t settings;
	// Выполняем указание предела длины имени
	settings.maxName = 3;
	/**
	 * Выполняем проверку отказа на входе текстовом
	 */
	{
		// Значение разметки, разбираемое из текста
		xml::value_t value;
		// Выполняем проверку отказа разбора текста
		EXPECT_FALSE(value.parse(text, settings));
		// Выполняем проверку кода отказа разбора
		EXPECT_EQ(value.error(), xml::error_t::NAME_TOO_LONG);
	}
	/**
	 * Выполняем проверку отказа на входе файловом
	 */
	{
		// Значение разметки, разбираемое из файла
		xml::value_t value;
		// Выполняем проверку отказа разбора файла
		EXPECT_FALSE(value.load(path, settings));
		// Выполняем проверку совпадения кода отказа с текстовым входом
		EXPECT_EQ(value.error(), xml::error_t::NAME_TOO_LONG);
	}
	/**
	 * Выполняем проверку принятия на входе файловом умолчаниями
	 */
	{
		// Значение разметки, разбираемое из файла умолчаниями
		xml::value_t value;
		// Выполняем проверку принятия текста умолчательными настройками
		EXPECT_TRUE(value.load(path));
		// Выполняем проверку отсутствия отказа разбора
		EXPECT_EQ(value.error(), xml::error_t::NONE);
	}
}

/**
 * @brief Проверка того, что дверь записи в файл принимает настройки сборки
 *
 * @details Выдача текста и запись в файл суть две двери к ОДНОЙ сборке. Замер 01.09.2026:
 *          дверь файловая принимала лишь ВИД оформления, а прочие настройки сборки на ней
 *          были недостижимы. Заведена перегрузка `save(файл, настройки)` по образцу
 *          имеющейся `dump(настройки)`
 *
 * @note Третий случай - запись УМОЛЧАНИЯМИ после записи с настройками - стоит здесь
 *       затем, чтобы перегрузка не обернулась настройкою, осевшей в значении
 *
 */
TEST(CodecXmlValue, FileOutputObeysTheSettings) {
	// Адрес временного файла разметки
	/**
	 * Временный файл проверки
	 *
	 * @note Сторож берётся вместо голого пути со сносом в конце: снос, стоящий одним
	 *       лишь хвостом тела, не снимает файла за прогоном, прерванным отказом
	 *       утверждения, а переживший файл обращает проверку записи в ложное зелёное
	 */
	const Scratch scratch_path("awh-xml-doors-test.xml");
	// Путь к временному файлу проверки
	const string & path = scratch_path.path();
	/**
	 * @brief Метод чтения содержимого временного файла
	 *
	 * @param filename адрес читаемого файла
	 * @return         прочитанное содержимое файла
	 *
	 */
	const auto read = [](const string & filename) noexcept -> string {
		// Открываем читаемый файл на чтение
		ifstream file(filename, ios::binary);
		// Выводим прочитанное содержимое файла целиком
		return string((istreambuf_iterator <char> (file)), istreambuf_iterator <char> ());
	};
	// Значение разметки с вложенным узлом
	xml::value_t value;
	// Выполняем разбор текста разметки
	ASSERT_TRUE(value.parse("<a><b>текст</b></a>"));
	// Настройки сборки с оформлением отступами
	xml::writer_t::settings_t settings;
	// Выполняем указание вида оформления с отступами
	settings.format = xml::format_t::PRETTY;
	// Выполняем проверку записи в файл с настройками
	ASSERT_TRUE(value.save(path, settings));
	// Выполняем проверку совпадения записанного текста с выданным
	EXPECT_EQ(read(path), value.dump(settings));
	// Выполняем проверку того, что оформление отступами до файла дошло
	EXPECT_NE(read(path).find('\n'), string::npos);
	// Выполняем проверку записи в файл умолчаниями
	ASSERT_TRUE(value.save(path));
	// Выполняем проверку того, что настройки в значении не осели
	EXPECT_EQ(read(path).find('\n'), string::npos);
}
/**
 * @brief Проверка согласия числа одноимённых узлов с их действительным числом
 *
 * @details Отображение имён хранит номер первого узла и ЧИСЛО одноимённых, и число это
 * решает, пойдёт ли выборка быстрым путём: при единственном одноимённом узел выдаётся
 * без перебора вовсе. Число это заводят четыре пути записи, а поверялось оно ничем
 *
 * @note Замер 01.09.2026: ветвь правки отображения при снятии узла достигается за весь
 *       набор проверок ОДИН раз, а изъятие её не краснит ни одной из двухсот восьмидесяти
 *       одной. Занижение же числа краснит выборку - и вот его проверка и стережёт
 *
 * @warning Условий достижения этой ветви ЧЕТЫРЕ, и ни одно не очевидно: узлов у родителя
 *          должно быть больше порога отображения (иначе розыск идёт перебором и
 *          отображения не строит вовсе), снимаемый узел обязан быть ПОСЛЕДНИМ в перечне
 *          (снятие из середины сдвигает номера и отображение сбрасывается целиком), узлом
 *          РАЗМЕТКИ и не первым вхождением своего имени. Первая редакция щупа держала
 *          четырёх детей и последним - узел иного имени, и до ветви не доходила НИ РАЗУ
 */
TEST(CodecXmlValue, NamesakeCountAgreesWithTheActualChildren) {
	/**
	 * @brief Честный пересчёт одноимённых узлов перебором по местам
	 *
	 * @param  node  осматриваемый узел разметки
	 * @param  local разыскиваемое местное имя
	 * @return       число вложенных узлов с этим именем
	 *
	 */
	const auto count = [](const xml::value_t & node, const string & local) noexcept -> size_t {
		// Число разысканных одноимённых узлов
		size_t result = 0;
		/**
		 * Выполняем перебор всех вложенных узлов
		 */
		for(size_t i = 0; i < node.size(); i++){
			/**
			 * Если вложенный узел несёт разыскиваемое имя
			 */
			if(node[i].valid() && (node[i].name().local.compare(local) == 0))
				// Выполняем учёт разысканного одноимённого узла
				result++;
		}
		// Выводим число разысканных одноимённых узлов
		return result;
	};
	/**
	 * Имена вложенных узлов: пятнадцать чужих ради перехода порога отображения, затем
	 * одноимённые, ПОСЛЕДНИМ из которых стоит узел разыскиваемого имени
	 */
	const char * names[] = {
		"z", "z", "z", "z", "z", "z", "z", "z", "z", "z", "z", "z", "z", "z", "z",
		"a", "b", "a", "a"
	};
	/**
	 * Выполняем перебор мест снятия среди одноимённых узлов
	 */
	for(size_t place = 15; place < 19; place++){
		// Узел разметки, вмещающий проверяемые вложенные узлы
		xml::value_t root("r");
		/**
		 * Выполняем наполнение узла разметки вложенными узлами
		 */
		for(const char * name : names){
			// Заводимый вложенный узел разметки
			xml::value_t child{string(name)};
			// Выполняем добавление вложенного узла
			root.push(child);
		}
		// Выполняем проверку согласия числа одноимённых до снятия
		ASSERT_EQ(root.children("a").size(), count(root, "a"));
		// Выполняем проверку того, что порог отображения перейдён
		ASSERT_GT(root.size(), static_cast <size_t> (xml::INDEX_THRESHOLD));
		// Выполняем снятие вложенного узла по месту
		ASSERT_TRUE(root.erase(place));
		// Выполняем проверку согласия числа одноимённых после снятия
		EXPECT_EQ(root.children("a").size(), count(root, "a")) << "снято место " << place;
	}
}
