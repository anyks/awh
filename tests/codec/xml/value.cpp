		for(size_t i = 0; i < count; i++)
			// Устанавливаем содержимое очередного вложенного узла
			ASSERT_TRUE(root["node_" + to_string(i)].text("re" + to_string(i)));
		/**
		 * Выполняем перебор всех заведённых заново вложенных узлов
		 */
