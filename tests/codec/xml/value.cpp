	xml::value_t value;
	// Выполняем назначение журнала значению разметки
	value.setLogger(::logger());
	// Собираемый текст разметки
	string text = "<r>";
	/**
	 * Выполняем сбор вложенных узлов сверх порога заведения отображения
	 */
