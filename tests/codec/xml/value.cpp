	ASSERT_EQ(root["a"].text(), "один");
	/**
	 * Выполняем заведение соседей числом, вместилище перевыделяющим
	 */
	for(size_t i = 0; i < 64; i++)
		// Выполняем установку содержимого очередного соседа
		root["s" + to_string(i)].text("знач");
	// Выполняем проверку того, что узел, снятый по пути заново, содержимое сохранил
	ASSERT_EQ(value[0]["a"].text(), "один");
