/**
 * @brief Проверка согласия извлечения чисел с договором кодеков
 *
 * @details Договор извлечения общий у кодеков рамки, и запись, в родной вид не вместимая,
 *          числом быть не перестаёт: `strtod` отвечает ей бесконечностью либо нулём, и тем
 *          же самым отвечают JSON и YAML. Разметка отвечала на такую запись отказом, отчего
 *          один и тот же текст извлекался у кодеков по-разному
 *
 * @note Отказ по нехватке разрядности отличим от отказа по составу записи кодом причины
 *       разбора, и различать их обязательно: первое значит «число, да велико», второе -
 *       «не число вовсе». Оттого проверка держит обе стороны разом
 *
 */
TEST(CodecXmlValue, ExtractionContract) {
	// Дерево разметки, с какого снимается значение
	xml::document_t document;
	// Извлекаемое из узла разметки дробное число
	double real = 0.;
	// Выполняем разбор записи числа, целым не вместимой
	ASSERT_TRUE(document.parse("<a>123456789012345678901234567890</a>"));
	// Выполняем проверку того, что запись извлекается дробным приближением
	ASSERT_TRUE(xml::value_t(document.element()).value(real));
	ASSERT_DOUBLE_EQ(real, 1.2345678901234568e+29);
	// Выполняем разбор записи числа за пределом дробного
	ASSERT_TRUE(document.parse("<a>1e400</a>"));
	// Выполняем проверку того, что запись извлекается бесконечностью
	ASSERT_TRUE(xml::value_t(document.element()).value(real));
	ASSERT_TRUE(std::isinf(real));
	// Выполняем разбор записи числа мельче наименьшего дробного
	ASSERT_TRUE(document.parse("<a>1e-400</a>"));
	// Выполняем проверку того, что запись извлекается нулём
	ASSERT_TRUE(xml::value_t(document.element()).value(real));
	ASSERT_DOUBLE_EQ(real, 0.);
	/**
	 * Выполняем перебор записей, числами не являющихся вовсе
	 */
	for(const char * record : {"<a>текст</a>", "<a>12abc</a>", "<a>1e</a>", "<a>--5</a>", "<a>0x10</a>"}){
		// Выполняем разбор очередной записи
		ASSERT_TRUE(document.parse(record));
		// Выполняем проверку того, что запись числом не извлекается
		ASSERT_FALSE(xml::value_t(document.element()).value(real));
	}
}

