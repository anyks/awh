	xml::value_t value;
	// Выполняем разбор текста разметки с одноимёнными узлами из разных пространств
	ASSERT_TRUE(value.parse("<a xmlns:p='urn:p'><b>1</b><p:b>2</p:b><b>3</b><c/></a>"));
