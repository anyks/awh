	ASSERT_TRUE(value.parse("<a><b>1</b><c>2</c><d>3</d></a>"));
	// Получаем корневой узел разобранной разметки
	xml::value_t & root = value[static_cast <size_t> (0)];
	// Выполняем проверку числа вложенных узлов
	ASSERT_EQ(root.size(), static_cast <size_t> (3));
	/**
	 * Получаем неизменяемое значение разметки
	 *
	 * @note Обращение по пути ведётся неизменяемым значением: изменяемое заводит
	 *       недостающие узлы именным звеном, и отличие звеньев стало бы невидимо
	 */
	const xml::value_t & tree = value;
	// Выполняем проверку обращения к вложенному узлу по номеру
	ASSERT_EQ(tree.at("/0/1").text(), "2");
	// Выполняем проверку обращения к последнему вложенному узлу по номеру
	ASSERT_EQ(tree.at("/0/2").text(), "3");
