/**
 * @brief Проверка договора извлечения значений
 *
 * @note Своих видов у разметки нет вовсе, всякое содержимое её есть текст, а договор
 *       извлечения при том общий у всех кодеков рамки
 *
 */
TEST(CodecXmlValue, Extract) {
	// Разбираемое значение
	xml::value_t value;
	// Выполняем разбор текста разметки
	ASSERT_TRUE(value.parse("<root><целое>42</целое><знак>-1</знак><дробное>1.5</дробное>"
		"<да>true</да><нет>0</нет><текст>строка</текст></root>"));
	// Получаем ссылку на корневой узел разметки
	const xml::value_t & root = value["root"];
	// Извлекаемое дробное значение
	double real = 0.;
	// Выполняем извлечение целого числа дробным видом
	ASSERT_TRUE(root["целое"].value(real));
	// Выполняем проверку извлечённого дробного значения
	ASSERT_DOUBLE_EQ(real, 42.);
	// Извлекаемое целое значение
	int64_t number = 0;
	// Выполняем извлечение дробного числа целым видом
	ASSERT_TRUE(root["дробное"].value(number));
	// Выполняем проверку округления дробной части с уводом половины от нуля
	ASSERT_EQ(number, static_cast <int64_t> (2));
	// Выполняем извлечение целого числа со знаком
	ASSERT_TRUE(root["знак"].value(number));
	// Выполняем проверку извлечённого целого числа со знаком
	ASSERT_EQ(number, static_cast <int64_t> (-1));
	// Выполняем проверку отказа извлечения числа из строки
	ASSERT_FALSE(root["текст"].value(number));
	// Извлекаемое логическое значение
	bool flag = false;
	// Выполняем извлечение логического значения, записанного словом
	ASSERT_TRUE(root["да"].value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем извлечение логического значения, записанного цифрой
	ASSERT_TRUE(root["нет"].value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_FALSE(flag);
	// Выполняем проверку отказа извлечения логического значения из строки
	ASSERT_FALSE(root["текст"].value(flag));
	// Извлекаемое строковое значение
	string text;
	// Выполняем извлечение строкового значения
	ASSERT_TRUE(root["текст"].value(text));
	// Выполняем проверку извлечённого строкового значения
	ASSERT_STREQ(text.c_str(), "строка");
}

/**
 * @brief Проверка извлечения значений, приведению не подлежащих
 *
 */
TEST(CodecXmlValue, ExtractLimits) {
	// Значение, заведённое дробным числом за пределом целого вида
	const xml::value_t huge(xml::kind_t::TEXT, "1e300");
	// Извлекаемое целое значение
	int32_t number = 0;
	// Выполняем извлечение дробного числа целым видом
	ASSERT_TRUE(huge.value(number));
	/**
	 * Выполняем проверку выдачи предела затребованного вида
	 *
	 * @note Договор этот общий у всех кодеков рамки: неопределённого поведения при
	 *       приведении дробного к целому не будет ни у одного из них
	 */
	ASSERT_EQ(number, ::std::numeric_limits <int32_t>::max());
	/**
	 * Значение, заведённое дробным числом за нижним пределом целого вида
	 *
	 * @note Огранение сличается ОБОИМИ краями: проверка одного лишь верхнего прошла бы
	 *       и при нижнем крае, забытом вовсе, - а забытый край это уже неопределённое
	 *       поведение, ради изгнания которого огранение и заведено
	 */
	const xml::value_t least(xml::kind_t::TEXT, "-1e300");
	// Выполняем сброс извлекаемого целого значения
	number = 0;
	// Выполняем извлечение дробного числа целым видом
	ASSERT_TRUE(least.value(number));
	// Выполняем проверку выдачи нижнего предела затребованного вида
	ASSERT_EQ(number, ::std::numeric_limits <int32_t>::lowest());
	/**
	 * Значение, заведённое целым числом за пределом узкого вида
	 *
	 * @note Целое ЗАВОРАЧИВАЕТСЯ приведением языка, а не огранивается: приведение это
	 *       языком определено, и выдумывать поверх него нечего. Огранение заведено
	 *       лишь у дробного, и заведено по необходимости
	 */
	const xml::value_t wide(xml::kind_t::TEXT, "8080");
	// Извлекаемое число видом в один байт без знака
	uint8_t byte = 0;
	// Выполняем извлечение целого числа узким видом
	ASSERT_TRUE(wide.value(byte));
	// Выполняем проверку заворота непомещающегося числа
	ASSERT_EQ(byte, static_cast <uint8_t> (8080));
	// Значение, заведённое числом, числом не являющимся
	const xml::value_t nan(xml::kind_t::TEXT, "nan");
	// Выполняем сброс извлекаемого целого значения
	number = 7;
	/**
	 * Выполняем проверку отказа извлечения записи, числом не являющейся
	 *
	 * @note Слова `nan` и `inf` описания разметки числами не считают, и разбор их
	 *       завершается отказом, а не выдачей нуля
	 */
	ASSERT_FALSE(nan.value(number));
	// Выполняем проверку того, что переменная отказом не тронута
	ASSERT_EQ(number, static_cast <int32_t> (7));
}

