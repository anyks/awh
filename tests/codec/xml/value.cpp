/**
 * @brief Проверка договора извлечения значений
 *
 * @note Своих видов у разметки нет вовсе, всякое содержимое её есть текст, а договор
 *       извлечения при том общий у всех кодеков рамки
 *
 */
TEST(CodecXmlValue, Extract) {
	// Разбираемое значение
	xml::value_t value;
	// Выполняем разбор текста разметки
	ASSERT_TRUE(value.parse("<root><целое>42</целое><знак>-1</знак><дробное>1.5</дробное>"
		"<да>true</да><нет>0</нет><текст>строка</текст></root>"));
	// Получаем ссылку на корневой узел разметки
	const xml::value_t & root = value["root"];
	// Извлекаемое дробное значение
	double real = 0.;
	// Выполняем извлечение целого числа дробным видом
	ASSERT_TRUE(root["целое"].value(real));
	// Выполняем проверку извлечённого дробного значения
	ASSERT_DOUBLE_EQ(real, 42.);
	// Извлекаемое целое значение
	int64_t number = 0;
	// Выполняем извлечение дробного числа целым видом
	ASSERT_TRUE(root["дробное"].value(number));
	// Выполняем проверку усечения дробной части к нулю
	ASSERT_EQ(number, static_cast <int64_t> (1));
	// Выполняем извлечение целого числа со знаком
	ASSERT_TRUE(root["знак"].value(number));
	// Выполняем проверку извлечённого целого числа со знаком
	ASSERT_EQ(number, static_cast <int64_t> (-1));
	// Выполняем проверку отказа извлечения числа из строки
	ASSERT_FALSE(root["текст"].value(number));
	// Извлекаемое логическое значение
	bool flag = false;
	// Выполняем извлечение логического значения, записанного словом
	ASSERT_TRUE(root["да"].value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем извлечение логического значения, записанного цифрой
	ASSERT_TRUE(root["нет"].value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_FALSE(flag);
	// Выполняем проверку отказа извлечения логического значения из строки
	ASSERT_FALSE(root["текст"].value(flag));
	// Извлекаемое строковое значение
	string text;
	// Выполняем извлечение строкового значения
	ASSERT_TRUE(root["текст"].value(text));
	// Выполняем проверку извлечённого строкового значения
	ASSERT_STREQ(text.c_str(), "строка");
}

/**
 * @brief Проверка извлечения значений, приведению не подлежащих
 *
 */
TEST(CodecXmlValue, ExtractLimits) {
	// Значение, заведённое дробным числом за пределом целого вида
	const xml::value_t huge(xml::kind_t::TEXT, "1e300");
	// Извлекаемое целое значение
	int32_t number = 0;
	// Выполняем извлечение дробного числа целым видом
	ASSERT_TRUE(huge.value(number));
	/**
	 * Выполняем проверку выдачи предела затребованного вида
	 *
	 * @note Договор этот общий у всех кодеков рамки: неопределённого поведения при
	 *       приведении дробного к целому не будет ни у одного из них
	 */
	ASSERT_EQ(number, ::std::numeric_limits <int32_t>::max());
	// Значение, заведённое числом, числом не являющимся
	const xml::value_t nan(xml::kind_t::TEXT, "nan");
	// Выполняем сброс извлекаемого целого значения
	number = 7;
	/**
	 * Выполняем проверку отказа извлечения записи, числом не являющейся
	 *
	 * @note Слова `nan` и `inf` описания разметки числами не считают, и разбор их
	 *       завершается отказом, а не выдачей нуля
	 */
	ASSERT_FALSE(nan.value(number));
	// Выполняем проверку того, что переменная отказом не тронута
	ASSERT_EQ(number, static_cast <int32_t> (7));
}

/**
 * @brief Проверка собирания содержимого вложенных узлов
 *
 * @note Правило это взято у узла дерева знак в знак: у узла разметки собственного
 *       содержимого нет вовсе, а выдаётся содержимое всех вложенных текстовых узлов
 *       подряд
 *
 */
TEST(CodecXmlValue, Gather) {
	// Разбираемое значение
	xml::value_t value;
	// Выполняем разбор текста разметки с перемежающимся содержимым
	ASSERT_TRUE(value.parse("<root>первый<em>второй</em>третий</root>"));
	// Выполняем проверку собранного содержимого узла разметки
	ASSERT_STREQ(value["root"].text().c_str(), "первыйвторойтретий");
	// Выполняем проверку количества вложенных узлов
	ASSERT_EQ(value["root"].size(), static_cast <size_t> (3));
	// Выполняем проверку вида первого вложенного узла
	ASSERT_EQ(value["root"][static_cast <size_t> (0)].kind(), xml::kind_t::TEXT);
	// Выполняем проверку вида второго вложенного узла
	ASSERT_EQ(value["root"][static_cast <size_t> (1)].kind(), xml::kind_t::ELEMENT);
}

/**
 * @brief Проверка сличения значений
 *
 */
TEST(CodecXmlValue, Compare) {
	// Первое сличаемое значение
	xml::value_t left;
	// Второе сличаемое значение
	xml::value_t right;
	// Выполняем разбор текста первого значения
	ASSERT_TRUE(left.parse("<root a=\"1\" b=\"2\"><child/></root>"));
	// Выполняем разбор текста второго значения, разнящегося лишь порядком свойств
	ASSERT_TRUE(right.parse("<root b=\"2\" a=\"1\"><child/></root>"));
	/**
	 * Выполняем проверку совпадения значений
	 *
	 * @note Порядок свойств сличению не подлежит: свойства узла суть набор
	 */
	ASSERT_TRUE(left == right);
	// Выполняем разбор текста второго значения, разнящегося значением свойства
	ASSERT_TRUE(right.parse("<root a=\"9\" b=\"2\"><child/></root>"));
	// Выполняем проверку несовпадения значений
	ASSERT_TRUE(left != right);
	// Выполняем разбор текста первого значения с двумя вложенными узлами
	ASSERT_TRUE(left.parse("<root><a/><b/></root>"));
	// Выполняем разбор текста второго значения с теми же узлами в ином порядке
	ASSERT_TRUE(right.parse("<root><b/><a/></root>"));
	/**
	 * Выполняем проверку несовпадения значений
	 *
	 * @note Порядок вложенных узлов сличению подлежит: содержимое разметки определено
	 *       порядком своим, и в этом разметка расходится с объектом JSON намеренно
	 */
	ASSERT_TRUE(left != right);
}

/**
 * @brief Проверка записи значения с отступами
 *
 */
TEST(CodecXmlValue, Format) {
	// Записываемое значение
	xml::value_t value;
	// Выполняем разбор текста разметки
	ASSERT_TRUE(value.parse("<root><a>1</a><b>2</b></root>"));
	// Выполняем запись значения с отступами
	const string text = value.dump(xml::format_t::PRETTY);
	// Выполняем проверку наличия переводов строк в записи
	ASSERT_NE(text.find('\n'), string::npos);
	// Значение, разобранное из записи с отступами
	xml::value_t twin;
	// Выполняем разбор записи с отступами
	ASSERT_TRUE(twin.parse(text)) << text;
	// Выполняем проверку совпадения содержимого вложенного узла
	ASSERT_STREQ(twin.at("/root/a").text().c_str(), "1");
}

