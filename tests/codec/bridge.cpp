/**
 * @brief Проверка перевода записи JSON в дерево ABC
 *
 */
TEST(CodecBridge, DecodeJSON) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Собираемое дерево значений контейнера ABC
	abc::value_t value;
	// Выполняем перевод записи JSON в дерево значений
	ASSERT_TRUE(bridge.decode("{\"name\":\"value\",\"count\":17,\"rate\":1.5,\"flag\":true,\"empty\":null,\"list\":[1,2,3],\"nested\":{\"port\":8080}}", value));
	// Выполняем проверку заведения корня отображением
	ASSERT_TRUE(value.is(abc::type_t::MAP));
	// Выполняем проверку числа полей отображения
	ASSERT_EQ(value.size(), 7);
	// Извлекаемая последовательность знаков
	string text = "";
	// Выполняем извлечение последовательности знаков
	ASSERT_TRUE(value.at("name").value(text));
	// Выполняем проверку извлечённой последовательности знаков
	ASSERT_EQ(text, "value");
	// Извлекаемое число целое без знака
	uint64_t number = 0;
	// Выполняем извлечение числа целого без знака
	ASSERT_TRUE(value.at("count").value(number));
	// Выполняем проверку извлечённого числа целого
	ASSERT_EQ(number, 17);
	// Извлекаемое число дробное
	double real = 0.;
	// Выполняем извлечение числа дробного
	ASSERT_TRUE(value.at("rate").value(real));
	// Выполняем проверку извлечённого числа дробного
	ASSERT_DOUBLE_EQ(real, 1.5);
	// Извлекаемое логическое значение
	bool flag = false;
	// Выполняем извлечение логического значения
	ASSERT_TRUE(value.at("flag").value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем проверку укладки пустого значения
	ASSERT_TRUE(value.at("empty").is(abc::type_t::NUL));
	// Выполняем проверку заведения вместимого
	ASSERT_TRUE(value.at("list").is(abc::type_t::ARRAY));
	// Выполняем проверку числа значений вместимого
	ASSERT_EQ(value.at("list").size(), 3);
	// Выполняем проверку укладки значения по вложенному пути
	ASSERT_TRUE(value.at("nested/port").value(number));
	// Выполняем проверку извлечённого значения по вложенному пути
	ASSERT_EQ(number, 8080);
}

