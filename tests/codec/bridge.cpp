/**
 * @brief Проверка нормализации записи кодеком при переводе
 *
 */
TEST(CodecBridge, Normalisation) {
	// Создаём объект работы с логами
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge;
	// Получаем настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем вид оформления собираемой записи без отступов
	settings.format = json::format_t::COMPACT;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	/**
	 * Образцы записи JSON вместе с ожидаемым видом её после перевода.
	 *
	 * @warning Дословного совпадения запись НЕ ОБЕЩАЕТ, и это записанный договор
	 *          кодека, а не дефект моста: разбор хранит число, а не знаки его, строки
	 *          хранятся раскодированными, а запись экранирует лишь обязательное.
	 *          Ожидаемый вид закреплён здесь явно, чтобы перемена его не прошла молча
	 */
	const pair <const char *, const char *> samples[] = {
		// Число, в родной вид вместившееся, выдаётся тем же значением
		{"{\"a\":9007199254740993}", "{\"a\":9007199254740993}"},
		// Дробное число выдаётся кратчайшею записью того же значения
		{"{\"a\":0.1}", "{\"a\":0.1}"},
		// Знак отрицательного нуля сохраняется
		{"{\"a\":-0.0}", "{\"a\":-0.0}"},
		// Порядок числа раскрывается: значение то же, знаки иные
		{"{\"a\":1E2}", "{\"a\":100.0}"},
		// Незначащий разряд дробного числа снимается
		{"{\"a\":1.50}", "{\"a\":1.5}"},
		// Экранирование раскрывается, суррогатная пара обращается знаком
		{"{\"\\u0431\":\"A\\ud83d\\ude00\"}", "{\"\xd0\xb1\":\"A\xf0\x9f\x98\x80\"}"},
		// Лишнее экранирование снимается: косая черта его не требует
		{"{\"a\":\"\\/\"}", "{\"a\":\"/\"}"},
		/**
		 * Число сверх родных видов выдаётся последовательностью знаков: величину его
		 * сам JSON держит записью знаков, а не октетами, и собрать вид `EXTENDED`
		 * контейнера ABC мосту нечем, не разбирая десятичную запись самому
		 */
		{"{\"a\":1e400}", "{\"a\":\"1e400\"}"},
		{"{\"a\":123456789012345678901234567890}", "{\"a\":\"123456789012345678901234567890\"}"},
		/**
		 * Переполнение порядка и исчезновение его дают вид `EXTENDED` тоже: это и есть
		 * места, где он возникает, - замерено. А вот длинное дробное разрядами его НЕ
		 * даёт: оно ложится дробным двойной точности и нормализуется кратчайшею
		 * записью того же значения
		 */
		{"{\"a\":1.7976931348623157e309}", "{\"a\":\"1.7976931348623157e309\"}"},
		{"{\"a\":0.1e-400}", "{\"a\":\"0.1e-400\"}"},
		{"{\"a\":0.30000000000000004440892098500626}", "{\"a\":0.30000000000000004}"},
		{"{\"a\":0.1000000000000000055511151231257827}", "{\"a\":0.1}"}
	};
	// Выполняем перебор всех образцов записи JSON
	for(const auto & sample : samples){
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Выполняем перевод образца записи JSON в дерево значений
		ASSERT_TRUE(bridge.decode(sample.first, value, bridge_t::format_t::JSON)) << sample.first;
		// Собираемая запись JSON
		string text = "";
		// Выполняем перевод дерева значений обратно в запись JSON
		ASSERT_TRUE(bridge.encode(value, text, bridge_t::format_t::JSON)) << sample.first;
		// Выполняем проверку совпадения записи с ожидаемым её видом
		ASSERT_EQ(text, sample.second) << sample.first;
	}
}

