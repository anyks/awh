/**
 * @brief Проверка сохранности значений при переводе дерева ABC в запись JSON
 *
 */
TEST(CodecBridge, RoundTripValues) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Получаем настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем вид оформления собираемой записи без отступов
	settings.format = json::format_t::COMPACT;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	/**
	 * Образцы записи JSON для перевода.
	 *
	 * @warning Взяты они местами, где запись НОРМАЛИЗУЕТСЯ: порядок числа, лишнее
	 *          экранирование, суррогатная пара и число сверх родных видов. Сличение
	 *          текстов на них законно расходится, оттого сличаются ЗНАЧЕНИЯ: мост
	 *          обязан сохранять их, а вид записи - дело писателя кодека
	 *
	 * @warning Проверка эта обещает УСТОЙЧИВОСТЬ перевода со второго прохода, а не
	 *          сохранность вида, поданного исходной записью: сличаются деревья ПОСЛЕ
	 *          первого прохода и после второго. Иначе она красилась бы на числе сверх
	 *          родных видов, которое ложится знаками намеренно. Вид узла в сличении
	 *          УЧАСТВУЕТ - замерено: `STRING("17")` и `UINT(17)` не равны, - оттого
	 *          подмену вида одним лишь совпадением значений она не пропустит
	 */
	const char * samples[] = {
		"{\"a\":9007199254740993}",
		"{\"a\":1e400}",
		"{\"a\":123456789012345678901234567890}",
		"{\"a\":0.1}",
		"{\"a\":-0.0}",
		"{\"a\":1E2}",
		"{\"a\":1.50}",
		"{\"a\":1.7976931348623157e309}",
		"{\"a\":0.1e-400}",
		"{\"a\":0.30000000000000004440892098500626}",
		"{\"a\":0.1000000000000000055511151231257827}",
		"{\"\\u0431\":\"A\\ud83d\\ude00\"}",
		"{\"a\":\"\\/\"}",
		"{\"name\":\"value\",\"count\":17,\"rate\":1.5,\"flag\":true,\"empty\":null,\"list\":[1,2,3],\"nested\":{\"port\":8080}}"
	};
	// Выполняем перебор всех образцов записи JSON
	for(const char * sample : samples){
		// Дерево значений, собранное первым переводом
		abc::value_t first;
		// Выполняем перевод образца записи JSON в дерево значений
		ASSERT_TRUE(bridge.decode(sample, first)) << sample;
		// Собираемая запись JSON
		string text = "";
		// Выполняем перевод дерева значений обратно в запись JSON
		ASSERT_TRUE(bridge.encode(first, text)) << sample;
		// Дерево значений, собранное вторым переводом
		abc::value_t second;
		// Выполняем перевод собранной записи JSON в дерево значений
		ASSERT_TRUE(bridge.decode(text, second)) << sample;
		/**
		 * Выполняем проверку СОВПАДЕНИЯ ДЕРЕВЬЕВ, а не текстов: значение, прошедшее
		 * мостом, обязано остаться тем же самым
		 */
		ASSERT_TRUE(first == second) << sample << " -> " << text;
	}
}

/**
 * @brief Проверка сохранности числа, ни в один родной вид не вместимого
 *
 */
TEST(CodecBridge, ExtendedNumber) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Собираемое дерево значений контейнера ABC
	abc::value_t value;
	// Выполняем перевод записи JSON с числом сверх родных видов
	ASSERT_TRUE(bridge.decode("{\"a\":123456789012345678901234567890}", value));
	// Извлекаемая запись числа
	string text = "";
	// Выполняем извлечение записи числа
	ASSERT_TRUE(value.at("a").value(text));
	/**
	 * Выполняем проверку СОХРАННОСТИ записи числа целиком.
	 *
	 * @warning Проверка эта закрепляет замеренный срыв: запись числа бралась ходом
	 *          «text()», а тот выдаёт содержимое лишь у строковых узлов и у числа
	 *          отвечает пустотой - значение терялось целиком, а перевод при этом
	 *          отвечал успехом. Ход «raw()» выдаёт запись числа
	 */
	ASSERT_EQ(text, "123456789012345678901234567890");
}

/**
 * @brief Проверка нормализации записи кодеком при переводе
 *
 */
TEST(CodecBridge, Normalisation) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Получаем настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем вид оформления собираемой записи без отступов
	settings.format = json::format_t::COMPACT;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	/**
	 * Образцы записи JSON вместе с ожидаемым видом её после перевода.
	 *
	 * @warning Дословного совпадения запись НЕ ОБЕЩАЕТ, и это записанный договор
	 *          кодека, а не дефект моста: разбор хранит число, а не знаки его, строки
	 *          хранятся раскодированными, а запись экранирует лишь обязательное.
	 *          Ожидаемый вид закреплён здесь явно, чтобы перемена его не прошла молча
	 */
	const pair <const char *, const char *> samples[] = {
		// Число, в родной вид вместившееся, выдаётся тем же значением
		{"{\"a\":9007199254740993}", "{\"a\":9007199254740993}"},
		// Дробное число выдаётся кратчайшею записью того же значения
		{"{\"a\":0.1}", "{\"a\":0.1}"},
		// Знак отрицательного нуля сохраняется
		{"{\"a\":-0.0}", "{\"a\":-0.0}"},
		// Порядок числа раскрывается: значение то же, знаки иные
		{"{\"a\":1E2}", "{\"a\":100.0}"},
		// Незначащий разряд дробного числа снимается
		{"{\"a\":1.50}", "{\"a\":1.5}"},
		// Экранирование раскрывается, суррогатная пара обращается знаком
		{"{\"\\u0431\":\"A\\ud83d\\ude00\"}", "{\"\xd0\xb1\":\"A\xf0\x9f\x98\x80\"}"},
		// Лишнее экранирование снимается: косая черта его не требует
		{"{\"a\":\"\\/\"}", "{\"a\":\"/\"}"},
		/**
		 * Число сверх родных видов выдаётся последовательностью знаков: величину его
		 * сам JSON держит записью знаков, а не октетами, и собрать вид `EXTENDED`
		 * контейнера ABC мосту нечем, не разбирая десятичную запись самому
		 */
		{"{\"a\":1e400}", "{\"a\":\"1e400\"}"},
		{"{\"a\":123456789012345678901234567890}", "{\"a\":\"123456789012345678901234567890\"}"},
		/**
		 * Переполнение порядка и исчезновение его дают вид `EXTENDED` тоже: это и есть
		 * места, где он возникает, - замерено. А вот длинное дробное разрядами его НЕ
		 * даёт: оно ложится дробным двойной точности и нормализуется кратчайшею
		 * записью того же значения
		 */
		{"{\"a\":1.7976931348623157e309}", "{\"a\":\"1.7976931348623157e309\"}"},
		{"{\"a\":0.1e-400}", "{\"a\":\"0.1e-400\"}"},
		{"{\"a\":0.30000000000000004440892098500626}", "{\"a\":0.30000000000000004}"},
		{"{\"a\":0.1000000000000000055511151231257827}", "{\"a\":0.1}"}
	};
	// Выполняем перебор всех образцов записи JSON
	for(const auto & sample : samples){
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Выполняем перевод образца записи JSON в дерево значений
		ASSERT_TRUE(bridge.decode(sample.first, value)) << sample.first;
		// Собираемая запись JSON
		string text = "";
		// Выполняем перевод дерева значений обратно в запись JSON
		ASSERT_TRUE(bridge.encode(value, text)) << sample.first;
		// Выполняем проверку совпадения записи с ожидаемым её видом
		ASSERT_EQ(text, sample.second) << sample.first;
	}
}

/**
 * @brief Проверка перевода дерева ABC, собранного вручную, в запись JSON
 *
 */
TEST(CodecBridge, EncodeBuilt) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Получаем настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем вид оформления собираемой записи без отступов
	settings.format = json::format_t::COMPACT;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	// Собираемое дерево значений контейнера ABC
	abc::value_t value(abc::kind_t::MAP);
	// Выполняем укладку значения последовательностью знаков
	value["name"] = abc::value_t(string("value"));
	// Выполняем укладку значения числом целым
	value["count"] = abc::value_t(static_cast <uint64_t> (17));
	// Выполняем укладку значения по вложенному пути
	value.place("nested/port") = abc::value_t(static_cast <uint64_t> (8080));
	// Собираемая запись JSON
	string result = "";
	// Выполняем перевод дерева значений в запись JSON
	ASSERT_TRUE(bridge.encode(value, result));
	// Выполняем проверку собранной записи JSON
	ASSERT_EQ(result, "{\"name\":\"value\",\"count\":17,\"nested\":{\"port\":8080}}");
}

/**
 * @brief Проверка обращения с видами, записи кодека неведомыми
 *
 */
TEST(CodecBridge, NarrowingRules) {
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&log);
	// Собираемое дерево значений контейнера ABC
	abc::value_t value(abc::kind_t::MAP);
	// Выполняем заведение значения вида, записи JSON неведомого
	value["blob"] = abc::value_t(abc::kind_t::BLOB);
	// Получаем настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем вид оформления собираемой записи без отступов
	settings.format = json::format_t::COMPACT;
	// Устанавливаем правило отказа на вид, записи кодека неведомый
	settings.narrow = bridge_t::narrow_t::STRICT;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	// Собираемая запись JSON
	string result = "";
	/**
	 * Выполняем проверку ОТКАЗА перевода: молчаливая порча оставляла бы потребителя
	 * с записью, которая разбирается, но означает иное
	 */
	ASSERT_FALSE(bridge.encode(value, result));
	// Выполняем проверку кода отказа перевода
	ASSERT_EQ(bridge.error(), bridge_t::error_t::UNSUPPORTED);
	// Устанавливаем правило пропуска вида, записи кодека неведомого
	settings.narrow = bridge_t::narrow_t::SKIP;
	// Устанавливаем настройки перевода
	bridge.settings(settings);
	// Выполняем перевод дерева значений в запись JSON
	ASSERT_TRUE(bridge.encode(value, result));
	// Выполняем проверку укладки пропущенного значения пустым
	ASSERT_EQ(result, "{\"blob\":null}");
}
