/**
 * @brief Проверка сохранности отметки времени при чтении записи TOML
 *
 * @warning Проверка эта ловит МОЛЧАЛИВОЕ УНИЧТОЖЕНИЕ значения. У дерева TOML
 *          величины хранятся видом РОДНЫМ, а не записью их, и ход `text()`
 *          отвечает содержимым лишь у значений строковых - отметке же он отдаёт
 *          пустую строку, от строки пустой неотличимую, и кода отказа при том не
 *          ставит. Все четыре вида времени уходили оттого в дерево пустою
 *          записью, и круг стоял неподвижно лишь потому, что пустоту свою
 *          воспроизводил исправно. Ловушка эта описана у самого хода `text()`
 *          кодека и там же названа: «мост, значения между кодеками переносящий,
 *          на ней терял отметку времени». Замерено 15.09.2026 аудитом
 *
 * @note Начертание собирается ПИСАТЕЛЕМ кодека, а не мостом: правила записи
 *       четырёх видов времени живут у него
 *
 */
TEST(CodecBridge, TOMLTimestampsSurviveTheReading) {
	// Перечень записей с отметками времени всех четырёх видов
	const string records[] = {
		string("k = 1979-05-27T07:32:00Z"),
		string("k = 1979-05-27T07:32:00"),
		string("k = 1979-05-27"),
		string("k = 07:32:00")
	};
	// Перечень начертаний, кои обязаны уцелеть
	const string values[] = {
		string("1979-05-27T07:32:00Z"),
		string("1979-05-27T07:32:00"),
		string("1979-05-27"),
		string("07:32:00")
	};
	// Выполняем перебор всех записей
	for(uint8_t i = 0; i < 4; i++){
		// Создаём мост между контейнером ABC и текстовыми кодеками
		bridge_t bridge;
		// Собираемое дерево значений контейнера ABC
		abc::value_t tree;
		// Выполняем чтение записи TOML
		ASSERT_TRUE(bridge.decode(records[i], tree, bridge_t::format_t::TOML)) << "чтение записи TOML отвечено отказом; запись: " << records[i];
		// Выполняем проверку сохранности начертания отметки времени
		ASSERT_EQ(string(tree["k"].text()), values[i]) << "отметка времени уничтожена чтением; запись: " << records[i];
		// Собираемая запись второго прохода
		string second = "", third = "";
		// Собираемое дерево третьего прохода
		abc::value_t again;
		// Выполняем перевод прочитанного дерева обратно в запись
		ASSERT_TRUE(bridge.encode(tree, second, bridge_t::format_t::TOML)) << "перевод прочитанного дерева отвечен отказом; запись: " << records[i];
		// Выполняем проверку того, что начертание уцелело и в записи
		ASSERT_NE(second.find(values[i]), string::npos) << "отметка времени утрачена записью; собрано: " << second;
		// Выполняем проверку неподвижности круга
		ASSERT_TRUE(bridge.decode(second, again, bridge_t::format_t::TOML) && bridge.encode(again, third, bridge_t::format_t::TOML)) << "третий проход отвечен отказом";
		// Выполняем сличение второго прохода с третьим
		ASSERT_EQ(second, third) << "круг сдвинулся на третьем проходе; было: " << second << " стало: " << third;
	}
}

