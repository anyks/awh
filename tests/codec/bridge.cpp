/**
 * @brief Проверка правил сочленения, образцами владельца вскрытых
 *
 * @details Правила эти сняты с восьми образцов, где одна и та же запись дана
 * разом в JSON и в XML и обязана сличаться сама с собою. Каждое из них
 * закрепляет ТИХУЮ потерю: запись оставалась годной, а содержимое менялось
 *
 */
TEST(CodecBridge, MarkupJointEdges){
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&fmk, &log);
	/**
	 * Выполняем проверку укладки пустого узла разметки
	 *
	 * @note Умолчанием взята логическая истина: у настроек узел этот означает
	 *       «включено». Правило вынесено настройкою `empty`, ибо согласия в мире нет
	 */
	{
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Выполняем разбор записи с пустым узлом
		ASSERT_TRUE(bridge.decode(string("<config><Correlation/></config>"), value, bridge_t::format_t::XML));
		// Выполняем проверку укладки пустого узла логическою истиной
		ASSERT_TRUE(value["config"]["Correlation"].is(abc::type_t::BOOL)) << "пустой узел уложен не по настройке";
	}
	/**
	 * Выполняем проверку записи числа дробного
	 *
	 * @warning Утверждение это ловит ОКРУГЛЕНИЕ: извлечение целого из дробного
	 *          значения отвечает успехом и округляет по договору приведения, отчего
	 *          `0.25` ложилось в запись нулём, а `1.5` двойкой
	 */
	{
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Устанавливаем дробное значение полем дерева
		value["amount"] = abc::value_t(0.25);
		// Устанавливаем дробное значение с нулевою дробной частью
		value["price"] = abc::value_t(3000.0);
		// Собираемая запись разметки
		string text = "";
		// Выполняем перевод дерева значений в запись разметки
		ASSERT_TRUE(bridge.encode(value, text, bridge_t::format_t::XML));
		// Выполняем проверку сохранности дробной части
		ASSERT_NE(text.find("amount=\"0.25\""), string::npos) << "дробная часть округлена; собрано: " << text;
		/**
		 * Выполняем проверку значащего нуля дробной части
		 *
		 * @warning Точка с нулём остаётся НАМЕРЕННО: своей системы видов у разметки
		 *          нет, и вид числа несёт лишь сама запись. Без нуля обратное чтение
		 *          вернуло бы целое, и круг размыкался бы на всяком дробном с нулевою
		 *          дробной частью
		 */
		ASSERT_NE(text.find("price=\"3000.0\""), string::npos) << "значащий нуль дробной части снят; собрано: " << text;
	}
	/**
	 * Выполняем проверку столкновения текста узла с одноимённым свойством
	 *
	 * @warning Утверждение это ловит ПОТЕРЮ текста: беря первое же поле, чьё имя
	 *          после снятия приставок совпадает с настройкою, мост укладывал текстом
	 *          свойство, а текст терял вовсе
	 */
	{
		// Разбираемая запись разметки
		const string text = "<config><Data value=\"Goga\">содержимое</Data></config>";
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Выполняем разбор записи разметки
		ASSERT_TRUE(bridge.decode(text, value, bridge_t::format_t::XML));
		// Выполняем проверку сохранности свойства узла
		ASSERT_EQ(value["config"]["Data"]["value"].text(), "Goga");
		// Выполняем проверку сохранности текста узла
		ASSERT_EQ(value["config"]["Data"]["_value"].text(), "содержимое");
		// Собираемая запись обратного хода
		string back = "";
		// Выполняем перевод дерева значений обратно в запись разметки
		ASSERT_TRUE(bridge.encode(value, back, bridge_t::format_t::XML));
		// Выполняем проверку замкнутости круга по обоим полям
		ASSERT_EQ(back, text) << "круг разомкнут на столкновении текста со свойством";
	}
	/**
	 * Выполняем проверку перечня безымянного
	 *
	 * @warning Перечень у разметки выражается ПОВТОРОМ одноимённых узлов, и повтор
	 *          этот годен лишь при двух звеньях и более. Перечень из одного звена и
	 *          перечень внутри перечня повтора не дают вовсе - их несёт пометка
	 */
	{
		// Собираемый перечень вложенный
		abc::value_t inner;
		// Выполняем сборку вложенного перечня
		inner.push(abc::value_t(string("год")));
		inner.push(abc::value_t(string("название")));
		// Собираемый перечень внешний
		abc::value_t outer;
		// Выполняем сборку внешнего перечня
		outer.push(inner);
		outer.push(inner);
		// Собираемая запись разметки
		string text = "";
		// Выполняем перевод перечня верхнего уровня в запись разметки
		ASSERT_TRUE(bridge.encode(outer, text, bridge_t::format_t::XML)) << "перечень верхнего уровня переводу не поддался";
		// Собираемое дерево значений обратного хода
		abc::value_t back;
		// Выполняем разбор собранной записи разметки
		ASSERT_TRUE(bridge.decode(text, back, bridge_t::format_t::XML)) << "собрано: " << text;
		/**
		 * Выполняем проверку обратного чтения перечня
		 *
		 * @note Имя корневого узла перечень получает настройкою: у документа разметки
		 *       ровно один корень, и безымянным он быть не может. Круг замыкается со
		 *       ВТОРОГО прохода, а первый даёт имя
		 */
		ASSERT_TRUE(back["config"].is(abc::type_t::ARRAY)) << "перечень обратным чтением не признан; собрано: " << text;
		ASSERT_EQ(back["config"].size(), 2u) << "собрано: " << text;
		ASSERT_TRUE(back["config"][0].is(abc::type_t::ARRAY)) << "вложенный перечень обратным чтением не признан; собрано: " << text;
		ASSERT_EQ(back["config"][0][1].text(), "название") << "собрано: " << text;
		// Собираемая запись второго прохода
		string twice = "";
		// Выполняем перевод дерева обратного хода в запись разметки
		ASSERT_TRUE(bridge.encode(back, twice, bridge_t::format_t::XML));
		// Выполняем проверку неподвижности круга со второго прохода
		ASSERT_EQ(text, twice) << "круг перевода ползёт";
	}
}

/**
 * @brief Проверка записи предела разрядности целого без знака
 *
 * @warning Проверка эта закрепляет ПОРЯДОК спроса вида: извлечение целого со
 *          знаком из значения без знака отвечает УСПЕХОМ и заворачивает
 *          величину по договору приведения. Найдено ворошителем 04.09.2026 -
 *          предел разрядности ложился в запись YAML числом `-1`, и запись
 *          оставалась годной
 *
 */
TEST(CodecBridge, UnsignedLimitSurvivesEveryFormat){
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&fmk, &log);
	/**
	 * Перечень видов записи, целое без знака несущих
	 *
	 * @warning Вид TOML сюда НЕ входит: описание его знает целое лишь СО ЗНАКОМ
	 *          шириною в восемь октетов, и предел разрядности без знака записи
	 *          этой неведом вовсе. Он проверяется отдельно ниже - величина эта
	 *          обязана уходить правилом сужения, а не ложиться числом `-1`
	 */
	const bridge_t::format_t formats[] = {
		bridge_t::format_t::JSON, bridge_t::format_t::YAML
	};
	// Выполняем перебор всех видов записи
	for(const bridge_t::format_t format : formats){
		// Собираемое дерево значений контейнера ABC
		abc::value_t value;
		// Устанавливаем предел разрядности целого без знака полем дерева
		value["top"] = abc::value_t(static_cast <uint64_t> (18446744073709551615ULL));
		// Собираемая запись перевода
		string text = "";
		// Выполняем перевод дерева значений в запись
		ASSERT_TRUE(bridge.encode(value, text, format));
		// Выполняем проверку записи предела разрядности
		ASSERT_NE(text.find("18446744073709551615"), string::npos) << "предел разрядности завёрнут при записи; собрано: " << text;
		// Собираемое дерево значений обратного хода
		abc::value_t back;
		// Выполняем разбор собранной записи
		ASSERT_TRUE(bridge.decode(text, back, format)) << "собрано: " << text;
		// Извлекаемое целое без знака
		uint64_t number = 0;
		// Выполняем проверку сохранности значения
		ASSERT_TRUE(back["top"].value(number)) << "собрано: " << text;
		ASSERT_EQ(number, 18446744073709551615ULL) << "собрано: " << text;
	}
	// Собираемое дерево значений контейнера ABC
	abc::value_t value;
	// Устанавливаем предел разрядности целого без знака полем дерева
	value["top"] = abc::value_t(static_cast <uint64_t> (18446744073709551615ULL));
	// Собираемая запись перевода
	string text = "";
	// Выполняем перевод дерева значений в запись TOML
	ASSERT_TRUE(bridge.encode(value, text, bridge_t::format_t::TOML));
	/**
	 * Выполняем проверку записи величины, TOML неведомой
	 *
	 * @warning Утверждение это ловит ЗАВОРАЧИВАНИЕ: запись `top = -1` годна по
	 *          виду, разбирается без отказа и неверна по величине
	 */
	ASSERT_EQ(text.find("-1"), string::npos) << "предел разрядности завёрнут при записи; собрано: " << text;
	ASSERT_NE(text.find("18446744073709551615"), string::npos) << "величина потеряна; собрано: " << text;
	// Настройки перевода моста
	bridge_t::settings_t settings;
	// Устанавливаем правило сужения отказом
	settings.narrow = bridge_t::narrow_t::STRICT;
	// Выполняем установку настроек перевода
	bridge.settings(settings);
	// Собираемая запись строгого перевода
	string strict = "";
	// Выполняем проверку отказа при строгом правиле сужения
	ASSERT_FALSE(bridge.encode(value, strict, bridge_t::format_t::TOML)) << "величина, записи неведомая, принята при строгом правиле; собрано: " << strict;
	/**
	 * Выполняем проверку наибольшей ДОПУСТИМОЙ величины
	 *
	 * @warning Заслон сторожит границу с ОБЕИХ сторон: отказ, на единицу шире
	 *          положенного поставленный, отнял бы у записи наибольшее допустимое
	 *          число, и потеря эта была бы столь же тихой, сколь заворачивание.
	 *          Довод принят от владельца кодека TOML
	 */
	abc::value_t edge;
	// Устанавливаем наибольшую допустимую величину полем дерева
	edge["top"] = abc::value_t(static_cast <uint64_t> (9223372036854775807ULL));
	// Собираемая запись предельного перевода
	string limit = "";
	// Выполняем перевод дерева значений в запись TOML при строгом правиле
	ASSERT_TRUE(bridge.encode(edge, limit, bridge_t::format_t::TOML)) << "наибольшая допустимая величина отвергнута";
	// Выполняем проверку записи наибольшей допустимой величины
	ASSERT_NE(limit.find("= 9223372036854775807"), string::npos) << "наибольшая допустимая величина легла не числом; собрано: " << limit;
}

