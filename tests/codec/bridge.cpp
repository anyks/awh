/**
 * @brief Пустой узел ЗВЕНОМ ПЕРЕЧНЯ и пустой узел ПОЛЕМ отображения
 *
 * @details Одна и та же запись `<item></item>` значит разное по месту своему.
 *          Полем отображения она означает НАЛИЧИЕ без значения — `<NewEnabled/>`
 *          у настроек читается «включено», — а звеном перечня наличием быть не
 *          может вовсе: место своё звено не выбирает, и пусто в нём именно
 *          значение. Оттого настройка `empty` до звена не достаёт
 *
 * @note Решение владельца от 06.09.2026. Правило мирит два его же образца,
 *       требовавших умолчаний ПРОТИВОПОЛОЖНЫХ: журнал событий Windows кладёт
 *       `<Correlation/>` истиной, а перечень восьмого образца — пустою строкою
 */
TEST(CodecBridge, EmptyArraySlotIsEmptyString){
	// Создаём объект работы с логами
	// Создаём объект моста
	bridge_t bridge;
	// Собираемое дерево значений контейнера ABC
	abc::value_t value;
	// Выполняем разбор записи с пустым звеном перечня и пустым полем отображения
	ASSERT_TRUE(bridge.decode(string("<config><list><item>раз</item><item></item><item>три</item></list><flag/></config>"), value, bridge_t::format_t::XML));
	// Выполняем проверку того, что перечень собран целиком
	ASSERT_EQ(value["config"]["list"]["item"].kind(), abc::kind_t::ARRAY);
	ASSERT_EQ(value["config"]["list"]["item"].size(), static_cast <size_t> (3)) << "звено перечня потеряно";
	// Выполняем проверку укладки пустого ЗВЕНА пустою строкою
	ASSERT_TRUE(value["config"]["list"]["item"][static_cast <size_t> (1)].is(abc::type_t::STRING)) << "пустое звено перечня уложено не строкою";
	ASSERT_TRUE(value["config"]["list"]["item"][static_cast <size_t> (1)].text().empty()) << "пустое звено перечня уложено строкою непустою";
	/**
	 * Выполняем проверку укладки пустого ПОЛЯ логическою истиной
	 *
	 * @warning Утверждение это стережёт САМО РАЗЛИЧИЕ: без него правило можно было бы
	 *          «упростить» до одной трактовки на оба места, и один из двух образцов
	 *          владельца развалился бы молча
	 */
	ASSERT_TRUE(value["config"]["flag"].is(abc::type_t::BOOL)) << "пустое поле отображения уложено не по настройке";
	// Собираемые настройки перевода
	bridge_t::settings_t settings = bridge.settings();
	// Устанавливаем укладку пустого узла пустым значением
	settings.empty = bridge_t::empty_t::NONE;
	// Выполняем установку настроек перевода
	bridge.settings(settings);
	// Собираемое дерево значений при изменённой настройке
	abc::value_t second;
	// Выполняем разбор той же записи
	ASSERT_TRUE(bridge.decode(string("<config><list><item>раз</item><item></item><item>три</item></list><flag/></config>"), second, bridge_t::format_t::XML));
	/**
	 * Выполняем проверку того, что настройка достаёт до ПОЛЯ, но не до ЗВЕНА
	 *
	 * @details Вот граница правила, и она стережётся с обеих сторон разом
	 */
	ASSERT_TRUE(second["config"]["flag"].is(abc::type_t::NUL)) << "настройка не достала до поля отображения";
	ASSERT_TRUE(second["config"]["list"]["item"][static_cast <size_t> (1)].is(abc::type_t::STRING)) << "настройка достала до звена перечня, а не должна";
}

