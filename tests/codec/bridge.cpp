/**
 * @brief Проверка согласия дорог на видах, кодекам неведомых
 *
 * @warning Проверка эта ловит РАСХОЖДЕНИЕ ДОРОГ: у моста пять дорог записи, и
 *          всякая из них обращается с неведомым видом сама. Замерено
 *          04.09.2026 - отметка времени уходила в записи JSON и INI числом, а
 *          в записи YAML и TOML пустою строкою, ибо две дороги брали запись
 *          ходом `text()`, пустым у нестроковых значений, минуя общий `record()`
 *
 * @note Довод способа принят от владельца кодека YAML: искать надо ход,
 *       общую запись обходящий, будучи одним из нескольких
 *
 */
TEST(CodecBridge, EveryRoadAgreesOnUnknownKinds){
	// Создаём объект фреймворка
	const fmk_t fmk;
	// Создаём объект работы с логами
	const log_t log(&fmk);
	// Создаём мост между контейнером ABC и текстовыми кодеками
	bridge_t bridge(&fmk, &log);
	// Перечень видов записи, мостом переводимых
	const bridge_t::format_t formats[] = {
		bridge_t::format_t::JSON, bridge_t::format_t::YAML,
		bridge_t::format_t::XML, bridge_t::format_t::TOML, bridge_t::format_t::INI
	};
	// Собираемое дерево значений контейнера ABC
	abc::value_t value;
	// Устанавливаем отметку времени полем дерева
	value["stamp"] = abc::value_t(abc::kind_t::TIME);
	// Выполняем перебор всех видов записи
	for(const bridge_t::format_t format : formats){
		// Собираемая запись перевода
		string text = "";
		// Выполняем перевод дерева значений в запись
		ASSERT_TRUE(bridge.encode(value, text, format)) << "перевод отметки времени отвечен отказом";
		// Собираемое дерево значений обратного хода
		abc::value_t back;
		// Выполняем разбор собранной записи
		ASSERT_TRUE(bridge.decode(text, back, format)) << "собрано: " << text;
		/**
		 * Выполняем поиск значения обратного хода
		 *
		 * @note Записи разметки корень нужен, оттого значение её лежит уровнем глубже
		 */
		const abc::value_t & item = (back.contains("stamp") ? back["stamp"] : back["config"]["stamp"]);
		// Выполняем проверку укладки отметки времени числом
		ASSERT_TRUE(item.is(abc::type_t::NUMBER)) << "отметка времени легла не числом; собрано: " << text;
		// Извлекаемая отметка времени
		int64_t stamp = -1;
		// Выполняем проверку сохранности величины отметки времени
		ASSERT_TRUE(item.value(stamp)) << "собрано: " << text;
		ASSERT_EQ(stamp, 0) << "собрано: " << text;
	}
}
