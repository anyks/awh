/**
 * Экранируем повторную инициализацию модуля
 */
#pragma once

/**
 * Подключаем внешние заголовочные файлы
 */
#include <gtest/gtest.h>

/**
 * Подключаем заголовочные файлы фреймворка
 */
#include <sys/log.hpp>

/**
 * @brief Пространство имён безымянное
 *
 * @details Проверки всех семи кодеков собираются в ОДНУ программу, и тип, из заголовка
 *          пришедший, лежал бы в ней в стольких видах, сколько единиц трансляции его
 *          подключили. Безымянное пространство даёт каждой свой, и правило одного
 *          определения держится
 *
 */
namespace {
	/**
	 * @brief Глушитель вывода журнала, возобновляемый перед каждой проверкой
	 *
	 * @details Отказы разбора проверки наводят НАМЕРЕННО, и вывод журнала засорял бы
	 *          выдачу: настоящий отказ теряется среди сотен наведённых строк
	 *
	 * @warning Глушение стоит в `OnTestStart`, а НЕ разовым зовом при заведении
	 *          переменных: общий сторож `LogGuard` из `tests/main.cpp` возвращает виды
	 *          вывода к `CONSOLE` после КАЖДОЙ проверки, и разовое глушение живёт ровно
	 *          до конца первой из них. Одиночный прогон при этом молчит, а набор шумит
	 *          со второй проверки - оттого разовое глушение и выглядит работающим
	 *
	 * @note Порядок надёжен: `OnTestEnd` стража предыдущей проверки отрабатывает РАНЬШЕ,
	 *       чем `OnTestStart` следующей, и последнее слово остаётся за глушителем
	 *
	 */
	class Silencer : public ::testing::EmptyTestEventListener {
		/**
		 * @brief Метод оповещения о начале проверки
		 *
		 * @param info сведения о начинающейся проверке
		 *
		 */
		void OnTestStart(const ::testing::TestInfo & info) override {
			// Выполняем отключение вывода записей журнала
			awh::log::mode({});
			// Снимаем неиспользуемые сведения о проверке
			(void) info;
		}
	};
	/**
	 * @brief Заводитель глушителя вывода журнала
	 *
	 * @details Слушатель заводится при заведении переменных, до входа в программу:
	 *          хранилище слушателей у сборщика проверок единственно на процесс и
	 *          `InitGoogleTest` его не опустошает
	 *
	 */
	struct SilencerSetup {
		/**
		 * @brief Конструктор
		 *
		 */
		SilencerSetup() noexcept {
			// Выполняем отключение вывода записей журнала на случай отчётов до первой проверки
			awh::log::mode({});
			// Выполняем заведение глушителя вывода журнала
			::testing::UnitTest::GetInstance()->listeners().Append(new Silencer());
		}
	};
	// Объект заводителя глушителя вывода журнала
	const SilencerSetup silencer;
}
