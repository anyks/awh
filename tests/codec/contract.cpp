		ASSERT_EQ(doc.error(), xml::error_t::MISSING_ROOT);
		// Выполняем снос узла разметки по пути
		ASSERT_TRUE(doc.erase("/b"));
		// Выполняем проверку сброса кода отказа удавшимся сносом
