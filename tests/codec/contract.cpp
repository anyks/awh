using namespace std;
using namespace awh;
using namespace awh::codec;

/**
 * @brief Безымянное пространство имён вспомогательных объявлений проверок
 *
 * @note Пространство это безымянно намеренно: проверки всех кодеков собираются одной
 *       программой, и вынесенное наружу имя столкнулось бы с таким же именем соседа
 *
 */
namespace {
	/**
	 * @brief Итог извлечения числа из записи
	 *
	 */
	struct outcome_t {
		bool extracted;   // Признак успешности извлечения
		double real;      // Извлечённое дробное число
		bool wholed;      // Признак успешности извлечения целого числа
		int64_t whole;    // Извлечённое целое число со знаком
		/**
		 * @brief Конструктор
		 *
		 */
		outcome_t() noexcept : extracted(false), real(0.), wholed(false), whole(0) {}
	};
	/**
	 * @brief Метод сличения двух итогов извлечения
	 *
	 * @details Бесконечности сличаются признаком, а не равенством: равенства
	 * бесконечностей язык не обещает, тогда как договор велит им совпасть
	 *
	 * @param left  первый сличаемый итог
	 * @param right второй сличаемый итог
	 * @return      признак совпадения итогов
	 *
	 */
	static bool same(const outcome_t & left, const outcome_t & right) noexcept {
		/**
		 * Если признаки успешности извлечения разнятся
		 */
		if((left.extracted != right.extracted) || (left.wholed != right.wholed))
			// Выводим признак несовпадения итогов
			return false;
		/**
		 * Если извлечение записи числом дробным не удалось у обоих
		 */
		if(!left.extracted)
			// Выводим признак совпадения итогов
			return true;
		/**
		 * Если извлечённые дробные числа бесконечны у обоих
		 */
		if(::std::isinf(left.real) && ::std::isinf(right.real)){
			/**
			 * Если знаки бесконечностей разнятся
			 */
			if(::std::signbit(left.real) != ::std::signbit(right.real))
				// Выводим признак несовпадения итогов
				return false;
		/**
		 * Если извлечённые дробные числа бесконечны не у обоих
		 */
		} else if(left.real != right.real)
			// Выводим признак несовпадения итогов
			return false;
		// Выводим признак совпадения извлечённых целых чисел
		return (!left.wholed || (left.whole == right.whole));
	}
	/**
	 * @brief Метод извлечения числа из записи кодеком JSON
	 *
	 * @param record  подаваемая запись числа
	 * @param outcome собираемый итог извлечения
	 * @return        признак того, что запись кодеком разобрана
	 *
	 */
	static bool viaJson(const string & record, outcome_t & outcome) noexcept {
		// Дерево документа JSON
		json::document_t document;
		/**
		 * Если разбор записи завершился отказом
		 */
		if(!document.parse(record))
			// Выводим признак того, что запись кодеком не разобрана
			return false;
		// Снятое с дерева документа владеющее значение
		const json::value_t value(document.root());
		// Выполняем извлечение записи числом дробным
		outcome.extracted = value.value(outcome.real);
		// Выполняем извлечение записи числом целым
		outcome.wholed = value.value(outcome.whole);
		// Выводим признак того, что запись кодеком разобрана
		return true;
	}
	/**
	 * @brief Метод извлечения числа из записи кодеком XML
	 *
	 * @note Своих видов у разметки нет вовсе: запись кладётся содержимым узла, и
	 *       вид её решается самой записью при извлечении
	 *
	 * @param record  подаваемая запись числа
	 * @param outcome собираемый итог извлечения
	 * @return        признак того, что запись кодеком разобрана
	 *
	 */
	static bool viaXml(const string & record, outcome_t & outcome) noexcept {
		// Собираемый текст разметки
		const string text = ("<a>" + record + "</a>");
		// Дерево разметки XML
		xml::document_t document;
		/**
		 * Если разбор записи завершился отказом
		 */
		if(!document.parse(text))
			// Выводим признак того, что запись кодеком не разобрана
			return false;
		// Снятое с дерева разметки владеющее значение
		const xml::value_t value(document.element());
		// Выполняем извлечение записи числом дробным
		outcome.extracted = value.value(outcome.real);
		// Выполняем извлечение записи числом целым
		outcome.wholed = value.value(outcome.whole);
		// Выводим признак того, что запись кодеком разобрана
		return true;
	}
	/**
	 * @brief Метод извлечения числа из записи кодеком YAML
	 *
	 * @param record  подаваемая запись числа
	 * @param outcome собираемый итог извлечения
	 * @return        признак того, что запись кодеком разобрана
	 *
	 */
	static bool viaYaml(const string & record, outcome_t & outcome) noexcept {
		// Собираемый текст документа
		const string text = ("value: " + record + "\n");
		// Дерево документа YAML
		yaml::document_t document;
		/**
		 * Если разбор записи завершился отказом
		 */
		if(!document.parse(text))
			// Выводим признак того, что запись кодеком не разобрана
			return false;
		// Снятое с дерева документа владеющее значение
		const yaml::value_t value(document.root());
		// Выполняем извлечение записи числом дробным
		outcome.extracted = value.at("/value").value(outcome.real);
		// Выполняем извлечение записи числом целым
		outcome.wholed = value.at("/value").value(outcome.whole);
		// Выводим признак того, что запись кодеком разобрана
		return true;
	}
};

/**
 * @brief Проверка согласия договора извлечения у кодеков рамки
 *
 * @details Всякая запись подаётся кодекам JSON, XML и YAML, и итоги извлечения из неё
 *          сличаются между собой. Кодек, записи не разобравший вовсе, из сличения
 *          выбывает: разбор — дело договора своего у всякого кодека, а сличается здесь
 *          один лишь договор извлечения, общий у них по устройству
 *
 * @note Записи взяты по краям видов: за пределом дробного и мельче наименьшего его, за
 *       пределом целого обоих знаков, ровно на пределе, а также обычные числа - ими
 *       проверяется, что сличение не пропускает всё подряд
 *
 */
TEST(CodecContract, NumberExtraction) {
	// Перечень записей, подаваемых кодекам
	const vector <string> records = {
		"0", "1", "-1", "1.5", "-1.5", "0.0", "1e3", "1E3", "1e-3",
		"9223372036854775807", "-9223372036854775808",
		"18446744073709551615", "18446744073709551616",
		"123456789012345678901234567890", "-123456789012345678901234567890",
		"1e400", "-1e400", "1e-400", "1.7976931348623157e309",
		"0.1234567890123456789012345678901234567890"
	};
	// Перечень кодеков, чьи договоры сличаются
	const vector <pair <string, function <bool (const string &, outcome_t &)>>> codecs = {
		{"JSON", viaJson}, {"XML", viaXml}, {"YAML", viaYaml}
	};
	/**
	 * Выполняем перебор всех подаваемых записей
	 */
	for(auto & record : records){
		// Название кодека, чей итог взят образцом
		string origin;
		// Итог извлечения, взятый образцом сличения
		outcome_t sample;
		// Признак того, что образец сличения снят
		bool sampled = false;
		/**
		 * Выполняем перебор всех сличаемых кодеков
		 */
		for(auto & codec : codecs){
			// Собираемый итог извлечения очередного кодека
			outcome_t outcome;
			/**
			 * Если запись кодеком не разобрана вовсе
			 */
			if(!codec.second(record, outcome))
				// Выполняем переход к следующему кодеку
				continue;
			/**
			 * Если образец сличения ещё не снят
			 */
			if(!sampled){
				// Запоминаем снятый образец сличения
				sample = outcome;
				// Запоминаем название кодека, чей итог взят образцом
				origin = codec.first;
				// Запоминаем, что образец сличения снят
				sampled = true;
				// Выполняем переход к следующему кодеку
				continue;
			}
			// Выполняем проверку совпадения итога извлечения с образцом
			ASSERT_TRUE(same(sample, outcome))
				<< "запись [" << record << "] извлекается кодеками по-разному: "
				<< origin << " даёт " << (sample.extracted ? "" : "отказ ") << sample.real
				<< ", а " << codec.first << " даёт " << (outcome.extracted ? "" : "отказ ") << outcome.real;
		}
		// Выполняем проверку того, что запись разобрана хоть одним кодеком
		ASSERT_TRUE(sampled) << "запись [" << record << "] не разобрана ни одним кодеком";
	}
}

/**
 * @brief Проверка согласия кодеков в отказе записям, числами не являющимся
 *
 * @details Запись, числом не являющаяся, обязана отвергаться извлечением у всякого
 *          кодека, её разобравшего. Проверка эта держит вторую сторону договора: свести
 *          кодеки к согласию можно и дозволив им всё подряд, и тогда сличение итогов
 *          проходило бы, ничего не проверяя
 *
 */
TEST(CodecContract, NumberRefusal) {
	// Перечень записей, числами не являющихся ни по одному из стандартов
	const vector <string> records = {
		"текст", "12abc", "abc12", "1e", "--5", "5.5.5", "0b101", "nan"
	};
	// Перечень кодеков, чьи договоры сличаются
	const vector <pair <string, function <bool (const string &, outcome_t &)>>> codecs = {
		{"JSON", viaJson}, {"XML", viaXml}, {"YAML", viaYaml}
	};
	/**
	 * Выполняем перебор всех подаваемых записей
	 */
	for(auto & record : records){
		/**
		 * Выполняем перебор всех сличаемых кодеков
		 */
		for(auto & codec : codecs){
			// Собираемый итог извлечения очередного кодека
			outcome_t outcome;
			/**
			 * Если запись кодеком не разобрана вовсе
			 */
			if(!codec.second(record, outcome))
				// Выполняем переход к следующему кодеку
				continue;
			// Выполняем проверку того, что запись числом не извлекается
			ASSERT_FALSE(outcome.extracted)
				<< "запись [" << record << "] числом не является, а кодек " << codec.first
				<< " извлёк из неё " << outcome.real;
		}
	}
}

/**
 * @brief Проверка расхождений кодеков, стандартами их заданных
 *
 * @details Согласие договора извлечения не означает согласия в том, ЧТО СЧИТАТЬ ЧИСЛОМ:
 *          это решает стандарт всякого кодека, и решает по-разному. YAML знает записи
 *          шестнадцатеричные и восьмеричные, знак плюса и `.inf`; JSON не знает ни
 *          одной из них и отвергает такую запись ещё разбором; разметка своих видов не
 *          имеет вовсе, оттого запись `.5` ей годится наравне с `0.5`, как годится она
 *          и описанию видов XSD
 *
 * @note Проверка эта заведена НЕ ради согласия, а ради несогласия: сведи кто-нибудь
 *       кодеки к одному виду записи ради стройности - и стандарты окажутся нарушены.
 *       Расхождения эти намеренны, и проверка их закрепляет
 *
 */
TEST(CodecContract, StandardDivergence) {
	// Собираемый итог извлечения
	outcome_t outcome;
	/**
	 * Выполняем перебор записей, числами являющихся у одного лишь YAML
	 *
	 * @note Записи эти заданы стандартом YAML: шестнадцатеричная, восьмеричная, знак
	 *       плюса и бесконечность
	 */
	for(auto & item : vector <pair <string, double>> {{"0x10", 16.}, {"0o17", 15.}, {"+5", 5.}}){
		// Собираемый итог извлечения кодеком YAML
		outcome_t taken;
		// Выполняем проверку того, что запись кодеком YAML разобрана и извлечена
		ASSERT_TRUE(viaYaml(item.first, taken)) << "запись [" << item.first << "]";
		ASSERT_TRUE(taken.extracted) << "запись [" << item.first << "]";
		ASSERT_DOUBLE_EQ(taken.real, item.second);
		// Выполняем проверку того, что кодек JSON записи такой не разбирает вовсе
		ASSERT_FALSE(viaJson(item.first, outcome)) << "запись [" << item.first << "]";
	}
	// Собираемый итог извлечения записи бесконечности
	outcome_t boundless;
	// Выполняем проверку того, что кодек YAML знает запись бесконечности
	ASSERT_TRUE(viaYaml(".inf", boundless));
	ASSERT_TRUE(boundless.extracted);
	ASSERT_TRUE(::std::isinf(boundless.real));
	/**
	 * Выполняем перебор записей, числами являющихся у разметки и у YAML
	 *
	 * @note Записи эти стандарт JSON отвергает разбором: цифра перед точкой и после неё
	 *       обязательна у него, тогда как описание видов XSD такие записи дозволяет
	 */
	for(auto & item : vector <pair <string, double>> {{".5", 0.5}, {"5.", 5.}}){
		// Собираемый итог извлечения кодеком XML
		outcome_t taken;
		// Выполняем проверку того, что запись разметкой извлекается
		ASSERT_TRUE(viaXml(item.first, taken)) << "запись [" << item.first << "]";
		ASSERT_TRUE(taken.extracted) << "запись [" << item.first << "]";
		ASSERT_DOUBLE_EQ(taken.real, item.second);
		// Выполняем проверку того, что кодек JSON записи такой не разбирает вовсе
		ASSERT_FALSE(viaJson(item.first, outcome)) << "запись [" << item.first << "]";
	}
}
