/**
 * @brief Проверка согласия кодеков по разбору пустого текста
 *
 * @details Оборотная сторона записи пустого документа: там расходятся ходы `dump()`,
 * здесь - ход `parse()`. Расхождение то же самое и по той же причине, и записано оно
 * здесь затем, чтобы оба конца договора стояли рядом
 *
 * @note Пустой текст не является ни документом JSON, ни разметкой XML: первый обязан
 *       нести одно значение, вторая - ровно один корневой узел. Оба отвечают ОТКАЗОМ,
 *       и коды их суть те же, какими они отвечают на запись пустого дерева. Таблица же
 *       пустой текст принимает УСПЕХОМ, обращая его в таблицу без записей
 *
 * @note Текст из одних ПРОБЕЛОВ у таблицы пустым не считается вовсе: пробел есть
 *       значимое содержимое поля, и `«   \\r\\n »` даёт две записи об одном поле
 *       каждая. У документа и разметки пробельный текст неотличим от пустого - оба
 *       отвергают его тем же кодом
 *
 */
TEST(CodecContract, EmptyTextParsingDivergesByStandard) {
	/**
	 * Выполняем перебор пустого текста и текста из одних пробелов
	 */
	for(const string & text : {string(""), string("   \r\n ")}){
		/**
		 * Разбор пустого текста документом JSON
		 */
		{
			// Объект документа
			json::document_t doc(::logger());
			// Выполняем проверку отказа разбора пустого текста
			ASSERT_FALSE(doc.parse(text)) << text;
			// Выполняем проверку кода отказа разбора текста без значения
			ASSERT_EQ(doc.error(), json::error_t::EMPTY_TEXT) << json::message(doc.error());
		}
		/**
		 * Разбор пустого текста деревом разметки
		 */
		{
			// Объект дерева разметки
			xml::document_t doc(::logger());
			// Выполняем проверку отказа разбора пустого текста
			ASSERT_FALSE(doc.parse(text)) << text;
			// Выполняем проверку кода отказа разбора текста без корневого узла
			ASSERT_EQ(doc.error(), xml::error_t::MISSING_ROOT) << xml::message(doc.error());
		}
		/**
		 * Разбор пустого текста таблицей
		 */
		{
			// Объект таблицы
			csv::document_t doc(::logger());
			// Выполняем проверку успешности разбора пустого текста
			ASSERT_TRUE(doc.parse(text)) << text;
			// Выполняем проверку отсутствия отказа разбора пустого текста
			ASSERT_EQ(doc.error(), csv::error_t::NONE) << csv::message(doc.error());
		}
	}
	/**
	 * Выполняем проверку различения пустого текста и текста из пробелов таблицей
	 *
	 * @note Оба текста таблица принимает, но обращает в РАЗНОЕ: пустой даёт таблицу без
	 *       записей, а пробельный - две записи об одном поле каждая. Пробел есть
	 *       значимое содержимое поля, и отбрасывать его таблица не смеет
	 */
	{
		// Объект таблицы, разбирающей пустой текст
		csv::document_t empty(::logger());
		// Выполняем разбор пустого текста таблицы
		ASSERT_TRUE(empty.parse(""));
		// Выполняем проверку пустоты таблицы, собранной из пустого текста
		ASSERT_TRUE(empty.empty());
		// Выполняем проверку отсутствия записей у таблицы из пустого текста
		ASSERT_EQ(empty.rows(), static_cast <size_t> (0));
		// Объект таблицы, разбирающей текст из одних пробелов
		csv::document_t spaced(::logger());
		// Выполняем разбор текста таблицы из одних пробелов
		ASSERT_TRUE(spaced.parse("   \r\n "));
		// Выполняем проверку того, что таблица из пробелов пустой не является
		ASSERT_FALSE(spaced.empty());
		// Выполняем проверку числа записей таблицы из пробелов
		ASSERT_EQ(spaced.rows(), static_cast <size_t> (2));
		// Выполняем проверку сохранности пробелов записью таблицы
		ASSERT_EQ(spaced.dump(), "\"   \"\r\n\" \"\r\n");
	}
}
