/**
 * @brief Проверка моста от документа к владению
 *
 * @note Проверка эта закрепляет главное свойство обёртки: снятое поддерево переживает
 *       документ, с какого оно снято
 *
 */
TEST(CodecJsonValue, Bridge) {
	// Документ, разбирающий текст
	json::document_t document(::logger());
	// Выполняем разбор текста документа
	ASSERT_TRUE(document.parse("{\"вложенный\":{\"ключ\":[1,2,3]}}"));
	// Выполняем снятие поддерева документа собственной памятью
	const json::value_t taken(document["вложенный"]);
	// Выполняем очистку документа, чтобы снятое значение осталось одно
	document.clear();
	// Выполняем разбор иного текста документа
	ASSERT_TRUE(document.parse("{\"иное\":0}"));
	// Выполняем проверку сохранности снятого поддерева
	ASSERT_STREQ(taken.dump().c_str(), "{\"ключ\":[1,2,3]}");
}

/**
 * @brief Проверка правки дерева
 *
 */
TEST(CodecJsonValue, Modify) {
	// Правимое значение
	json::value_t value;
	// Выполняем разбор текста документа
	ASSERT_TRUE(value.parse("{\"a\":1,\"b\":2,\"c\":3}"));
	// Выполняем перезапись значения занятого поля объекта
	ASSERT_TRUE(value.insert("b", json::value_t("иное")));
	/**
	 * Выполняем проверку того, что поле осталось на своём месте
	 *
	 * @note Правило это взято у JavaScript: присвоение уже заведённому полю меняет
	 *       значение его, а места не меняет
	 */
	ASSERT_STREQ(value.dump().c_str(), "{\"a\":1,\"b\":\"иное\",\"c\":3}");
	// Выполняем снятие поля объекта
	ASSERT_TRUE(value.erase("a"));
	// Выполняем проверку записи после снятия поля
	ASSERT_STREQ(value.dump().c_str(), "{\"b\":\"иное\",\"c\":3}");
	// Выполняем проверку отказа снятия несуществующего поля
	ASSERT_FALSE(value.erase("нет"));
	// Собираемый массив
	json::value_t list(json::kind_t::ARRAY);
	// Выполняем добавление первого значения в массив
	ASSERT_TRUE(list.push(json::value_t(static_cast <int64_t> (1))));
	// Выполняем добавление второго значения в массив
	ASSERT_TRUE(list.push(json::value_t(static_cast <int64_t> (2))));
	// Выполняем снятие значения массива по номеру
	ASSERT_TRUE(list.erase(static_cast <size_t> (0)));
	// Выполняем проверку записи массива после снятия значения
	ASSERT_STREQ(list.dump().c_str(), "[2]");
	// Выполняем проверку отказа добавления значения в объект
	ASSERT_FALSE(value.push(json::value_t(true)));
}

/**
 * @brief Проверка обращения к значению только для чтения и на запись
 *
 */
TEST(CodecJsonValue, Access) {
	// Правимое значение
	json::value_t source;
	// Выполняем разбор текста документа
	ASSERT_TRUE(source.parse("{\"a\":1}"));
	// Получаем ссылку на значение только для чтения
	const json::value_t & value = source;
	// Выполняем проверку того, что обращение только для чтения ничего не заводит
	ASSERT_FALSE(value["нет"].valid());
	// Выполняем проверку количества полей объекта после обращения
	ASSERT_EQ(value.size(), static_cast <size_t> (1));
	// Выполняем проверку отказа обращения по пути мимо дерева
	ASSERT_FALSE(value.at("/a/b/c").valid());
	/**
	 * Выполняем проверку того, что обращение изменяемое поле заводит
	 *
	 * @note Поведение это взято у `nlohmann::json` намеренно: потребитель, привыкший к
	 *       нему, обязан получить у нас то же самое
	 */
	ASSERT_FALSE(source["нет"].valid());
	// Выполняем проверку количества полей объекта после изменяемого обращения
	ASSERT_EQ(source.size(), static_cast <size_t> (2));
	// Выполняем проверку записи заведённого поля пустым значением
	ASSERT_STREQ(source.dump().c_str(), "{\"a\":1,\"нет\":null}");
}

/**
 * @brief Проверка заведения значений по пути
 *
 */
TEST(CodecJsonValue, Place) {
	// Собираемое значение
	json::value_t value;
	// Выполняем заведение значения вглубь по пути
	value.place("/a/b/2") = json::value_t(static_cast <int64_t> (7));
	/**
	 * Выполняем проверку заведения недостающих вместилищ
	 *
	 * @note Звено пути числовое заводит массив, а прочие - объект, и рост массива до
	 *       затребованного номера ведётся значениями неопределёнными
	 */
	ASSERT_STREQ(value.dump().c_str(), "{\"a\":{\"b\":[null,null,7]}}");
	// Выполняем проверку снятия отменяющих записей указателя
	value.place("/a~1b") = json::value_t(true);
	// Выполняем проверку обращения к полю с косой чертой в имени
	ASSERT_TRUE(value.at("/a~1b").valid());
	// Выполняем проверку того, что пустой путь отдаёт само значение
	ASSERT_TRUE(value.at("").kind() == json::kind_t::OBJECT);
}

/**
 * @brief Проверка потоковой сборки значения
 *
 * @note Договор сборки повторяет договор потока записи слово в слово намеренно: у
 *       потребителя «пишу текстом» и «строю дерево» обязаны отличаться одной буквой
 *
 */
TEST(CodecJsonValue, Builder) {
	// Объект потоковой сборки значения
	json::builder_t builder(::logger());
	// Выполняем открытие объекта
	ASSERT_TRUE(builder.object());
	// Выполняем запись имени поля объекта
	ASSERT_TRUE(builder.key("статус"));
	// Выполняем запись строкового значения
	ASSERT_TRUE(builder.value("успех"));
	// Выполняем запись имени поля объекта
	ASSERT_TRUE(builder.key("коды"));
	// Выполняем открытие массива
	ASSERT_TRUE(builder.array());
	// Выполняем запись первого значения массива
	ASSERT_TRUE(builder.value(static_cast <int64_t> (200)));
	// Выполняем запись второго значения массива
	ASSERT_TRUE(builder.value(static_cast <int64_t> (204)));
	// Выполняем проверку глубины вложенности
	ASSERT_EQ(builder.depth(), static_cast <size_t> (2));
	// Выполняем закрытие массива
	ASSERT_TRUE(builder.close());
	// Выполняем запись имени поля объекта
	ASSERT_TRUE(builder.key("итого"));
	// Выполняем запись числового значения без знака
	ASSERT_TRUE(builder.value(static_cast <uint64_t> (2)));
	// Выполняем закрытие объекта
	ASSERT_TRUE(builder.close());
	// Изымаем собранное значение
	const json::value_t value = builder.finish();
	// Выполняем проверку записи собранного значения
	ASSERT_STREQ(value.dump().c_str(), "{\"статус\":\"успех\",\"коды\":[200,204],\"итого\":2}");
	// Выполняем проверку сброса состояния сборки после изъятия значения
	ASSERT_EQ(builder.depth(), static_cast <size_t> (0));
}

