/**
 * @brief Проверка сноса поля объекта за порогом заведения отображения
 *
 * @details Снятие поля сдвигает номера всех следующих за ним, и отображение, пережившее
 *          сдвиг, отвечало бы номером соседа. Проверка эта то и стережёт: после снятия
 *          поля из середины все оставшиеся обязаны отвечать своими собственными значениями
 *
 * @note Снятие проверяется обоими путями - по имени и по номеру: сброс отображения нужен
 *       и там, и там, а забыть его можно порознь
 */
TEST(CodecJsonValue, IndexedObjectErase){
	// Количество полей объекта, заведомо превышающее порог заведения отображения
	const size_t count = 64;
	/**
	 * Выполняем перебор двух путей снятия поля объекта
	 */
	for(uint8_t kind = 0; kind < 2; kind++){
		// Заводимое значение объекта
		json::value_t root;
		/**
		 * Выполняем заведение полей объекта
		 */
		for(size_t i = 0; i < count; i++)
			// Заводим очередное поле объекта
			root["field_" + to_string(i)] = static_cast <int64_t> (i);
		/**
		 * Выполняем розыск поля объекта, дабы отображение оказалось заведено
		 *
		 * @note Обращение это обязательно: без него отображение завелось бы уже ПОСЛЕ
		 *       снятия, и проверка сброса не стерегла бы ничего
		 */
		ASSERT_TRUE(root.contains("field_0"));
		/**
		 * Если поле объекта снимается по имени
		 */
		if(kind == 0)
			// Выполняем снятие поля объекта из середины по имени
			ASSERT_TRUE(root.erase(string("field_10")));
		// Если поле объекта снимается по номеру
		else ASSERT_TRUE(root.erase(static_cast <size_t> (10)));
		// Выполняем проверку количества оставшихся полей объекта
		ASSERT_EQ(root.size(), count - 1);
		// Выполняем проверку отсутствия снятого поля объекта
		ASSERT_FALSE(root.contains("field_10"));
		/**
		 * Выполняем перебор всех оставшихся полей объекта
		 */
		for(size_t i = 0; i < count; i++){
			/**
			 * Если поле объекта было снято
			 */
			if(i == 10)
				// Выполняем переход к следующему полю объекта
				continue;
			// Извлекаемое значение поля объекта
			int64_t value = -1;
			// Выполняем извлечение значения поля объекта
			ASSERT_TRUE(root["field_" + to_string(i)].value(value));
			// Выполняем проверку извлечённого значения поля объекта
			ASSERT_EQ(value, static_cast <int64_t> (i));
		}
	}
}
