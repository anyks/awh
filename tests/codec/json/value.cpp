/**
 * @brief Проверка совпадения правки значения с его перезаписью
 *
 * @details Значение читается ДВАЖДЫ - напрямую и через запись его в текст с последующим
 * разбором. Расхождение означает, что значение держит одно, а записывает другое: правка
 * до текста не дошла либо дошла искажённой
 *
 * @note Приём сличения подсказан владельцем модуля YAML, где нашёл девять дефектов
 *       одного рода. У XML он нашёл один - пустое содержимое заводило узел текста, записи
 *       у которого нет никакой, - а у JSON не нашёл ни одного. Проверка стоит здесь
 *       СТОРОЖЕМ на будущее, а не итогом розыска
 * @warning Сличения ДВА, и второе не заменяется первым: запись против переписи ловит
 *          искажение вида и строения, но слепа к потере, случающейся на обоих путях
 *          одинаково - усечённая строка усеклась бы дважды и записи совпали бы. Оттого
 *          содержимое строк сличается отдельно, длиною в том числе
 */
TEST(CodecJsonValue, MutationSurvivesRewrite){
	/**
	 * Выполняем перебор всех сличаемых правок значения
	 */
	for(auto & item : vector <pair <string, function <void (json::value_t &)>>> {
		{"установка поля строкой", [](json::value_t & value){ value["k"] = json::value_t(string("значение")); }},
		{"установка поля числом", [](json::value_t & value){ value["k"] = json::value_t(static_cast <int64_t> (42)); }},
		{"установка поля дробным", [](json::value_t & value){ value["k"] = json::value_t(static_cast <double> (3.14159265358979)); }},
		{"перезапись поля", [](json::value_t & value){ value["k"] = json::value_t(static_cast <int64_t> (1)); value["k"] = json::value_t(string("иное")); }},
		{"снятие поля", [](json::value_t & value){ value["a"] = json::value_t(static_cast <int64_t> (1)); value["b"] = json::value_t(static_cast <int64_t> (2)); value.erase("a"); }},
		{"наибольшее целое", [](json::value_t & value){ value["k"] = json::value_t(static_cast <int64_t> (9223372036854775807LL)); }},
		{"наименьшее целое", [](json::value_t & value){ value["k"] = json::value_t(static_cast <int64_t> (-9223372036854775807LL - 1)); }},
		{"наибольшее беззнаковое", [](json::value_t & value){ value["k"] = json::value_t(static_cast <uint64_t> (18446744073709551615ULL)); }},
		{"дробное очень малое", [](json::value_t & value){ value["k"] = json::value_t(static_cast <double> (1e-300)); }},
		{"дробное очень большое", [](json::value_t & value){ value["k"] = json::value_t(static_cast <double> (1e300)); }},
		{"дробное с потерей точности", [](json::value_t & value){ value["k"] = json::value_t(static_cast <double> (0.1 + 0.2)); }},
		{"пустое имя поля", [](json::value_t & value){ value[""] = json::value_t(static_cast <int64_t> (1)); }},
		{"вложенность объектов", [](json::value_t & value){ value["a"]["b"]["c"] = json::value_t(static_cast <int64_t> (1)); }},
		{"снятие из перечня", [](json::value_t & value){
			for(int64_t i = 0; i < 5; i++) value["k"].push(json::value_t(i));
			value["k"].erase(static_cast <size_t> (2));
		}},
		{"очистка и заполнение заново", [](json::value_t & value){
			value["a"] = json::value_t(static_cast <int64_t> (1));
			value.clear();
			value["b"] = json::value_t(static_cast <int64_t> (2));
		}},
		{"широкое значение: снятие и заведение поля", [](json::value_t & value){
			for(int64_t i = 0; i < 64; i++) value["k" + to_string(i)] = json::value_t(i);
			value.erase("k7");
			value["k7"] = json::value_t(string("новое"));
		}}
	}) {
		// Собираемое значение
		json::value_t value;
		// Выполняем правку значения
		item.second(value);
		// Выполняем запись значения в текст
		const string text = value.dump();
		// Разобранное обратно значение
		json::value_t back;
		// Выполняем разбор записанного текста
		ASSERT_TRUE(back.parse(text)) << item.first << ": " << text;
		// Выполняем сличение записи исходного значения с записью разобранного
		ASSERT_EQ(back.dump(), text) << item.first;
	}
	/**
	 * Выполняем перебор всех строк, сохранность которых сличается
	 *
	 * @note Строки взяты ГОДНЫМИ по кодировке намеренно: одиночный октет 0x80 годной
	 *       записи не образует, и запись подменяет его знаком замены по правилу
	 *       восстановления UTF-8. Подмена эта верна, и сличать по ней сохранность нельзя
	 */
	for(auto & item : vector <string> {
		string("a\0b", 3), string("a\x01\x1f" "b"), "a\r\tb", "a\"b\\c", "по-русски",
		"\xF0\x9F\x98\x80", string("a\x7f" "b"), ""
	}) {
		// Собираемое значение
		json::value_t value;
		// Выполняем установку строки полем значения
		value["k"] = json::value_t(item);
		// Разобранное обратно значение
		json::value_t back;
		// Выполняем разбор записанного текста
		ASSERT_TRUE(back.parse(value.dump()));
		// Выполняем сличение длины строки, пережившей перезапись
		ASSERT_EQ(back["k"].text().size(), item.size()) << value.dump();
		// Выполняем сличение содержимого строки, пережившего перезапись
		ASSERT_EQ(back["k"].text(), item) << value.dump();
	}
}

/**
 * @brief Проверка сообщения об отказах кодека в журнал работы
 *
 * @details Кодек сообщает об отказах своих в журнал фреймворка, и записи эти собираются
 * перехватом в функцию обратного вызова: вид вывода `DEFERRED` уводит их туда целиком,
 * не трогая ни файлов, ни вывода на пульт
 *
 * @note Проверяются ОБЕ половины: отказ обязан давать запись, а успех обязан НЕ давать
 * @warning У записи JSON поля кода отказа НЕТ вовсе, и наружу идёт голая ложь: журнал
 *          здесь единственный способ узнать, чем запись не устроила. Оттого сличается и
 *          содержимое записи, а не одно лишь её наличие
 */
TEST(CodecJsonValue, LoggerReportsFailures){
	// Объект фреймворка
	fmk_t fmk;
	// Объект ведения журнала работы
	log_t log(&fmk);
	// Уводим записи журнала целиком в функцию обратного вызова
	log.mode({log_t::mode_t::DEFERRED});
	// Собираемые перехваченные записи журнала
	vector <pair <log_t::flag_t, string>> caught;
	// Выполняем подписку на записи журнала работы
	log.subscribe([&caught](const log_t::flag_t flag, string_view text) noexcept {
		// Выполняем сбор очередной перехваченной записи
		caught.emplace_back(flag, string(text));
	});
	/**
	 * Выполняем проверку сообщения об отказе разбора
	 */
	{
		// Собираемое значение
		json::value_t value;
		// Выполняем установку объекта ведения журнала работы
		value.setLogger(&log);
		// Выполняем разбор негодного текста
		ASSERT_FALSE(value.parse("{\"a\": }"));
		// Выполняем проверку того, что запись об отказе сделана
		ASSERT_EQ(caught.size(), static_cast <size_t> (1));
		// Выполняем проверку важности записи об отказе разбора
		ASSERT_EQ(caught.front().first, log_t::flag_t::WARNING);
		/**
		 * Выполняем проверку того, что запись несёт место отказа
		 *
		 * @note Запись без места бесполезна: разбирается текст в мегабайты, и «разбор
		 *       отказал» без строки и столбца читающему журнал не говорит ничего
		 */
		ASSERT_NE(caught.front().second.find("line"), string::npos) << caught.front().second;
	}
	// Выполняем очистку собранных записей журнала
	caught.clear();
	/**
	 * Выполняем проверку молчания при успешном разборе
	 */
	{
		// Собираемое значение
		json::value_t value;
		// Выполняем установку объекта ведения журнала работы
		value.setLogger(&log);
		// Выполняем разбор годного текста
		ASSERT_TRUE(value.parse("{\"a\": 1}"));
		// Выполняем проверку того, что записей об успешном разборе не сделано
		ASSERT_TRUE(caught.empty()) << caught.front().second;
	}
	/**
	 * Выполняем проверку работы без объекта ведения журнала
	 */
	{
		// Собираемое значение
		json::value_t value;
		// Выполняем разбор негодного текста без журнала
		ASSERT_FALSE(value.parse("{\"a\": }"));
	}
	// Выполняем очистку собранных записей журнала
	caught.clear();
	/**
	 * Выполняем проверку сообщения об отказе записи
	 */
	{
		// Объект записи текста
		json::writer_t writer(&log);
		/**
		 * Выполняем запись имени поля вне объекта
		 *
		 * @note Отказ этот беда СВОЯ: записывается то, что собрало приложение
		 */
		ASSERT_FALSE(writer.key("поле"));
		// Выполняем проверку того, что запись об отказе сделана
		ASSERT_FALSE(caught.empty());
		// Выполняем проверку важности записи об отказе записи
		ASSERT_EQ(caught.front().first, log_t::flag_t::CRITICAL) << caught.front().second;
		/**
		 * Выполняем проверку того, что запись несёт ДОВОД отказа
		 *
		 * @warning Здесь это существеннее, чем у разбора: кода отказа у записи нет, и
		 *          запись без довода не оставила бы потребителю ничего вовсе
		 */
		ASSERT_NE(caught.front().second.find("object"), string::npos) << caught.front().second;
	}
}

/**
 * @brief Проверка достижимости настроек разбора у владеющего значения
 *
 * @details Разбор обрывка во владеющее значение ведётся тем же документом, и настройки
 * обязаны быть достижимы и оттуда. Прежде довода настроек у него не было вовсе, и ни одна
 * из них не действовала: обрывок разбирался одними умолчаниями
 *
 * @warning Проверка сличает ДЕЙСТВИЕ настройки, а не приём её доводом: довод, принятый и
 *          отброшенный, сличением подписи не ловится никак
 */
TEST(CodecJsonValue, ParseHonoursSettings){
	// Собираемое владеющее значение JSON
	json::value_t value;
	// Разбираемый текст JSON с повторяющимся именем поля
	const string text(R"({"a":1,"a":2})");
	/**
	 * Выполняем проверку отказа при умолчаниях настроек
	 *
	 * @note Договор повтора имён не запрещает, а наше правило по умолчанию его отвергает
	 */
	ASSERT_FALSE(value.parse(text));
	// Настройки разбора текста JSON
	json::document_t::settings_t settings;
	// Устанавливаем удержание повторяющихся имён полей
	settings.duplicates = json::duplicate_t::KEEP;
	// Выполняем разбор текста JSON с удержанием повторов
	ASSERT_TRUE(value.parse(text, settings));
	// Выполняем проверку удержания обоих полей
	ASSERT_EQ(value.size(), static_cast <size_t> (2)) << value.dump();
}
