		// Выполняем разбор текста второго значения
		ASSERT_TRUE(second.parse(probe.second)) << probe.second;
		// Выполняем проверку того, что значения равны
		ASSERT_TRUE(first == second) << probe.first << " против " << probe.second;
		// Выполняем проверку того, что записи их различны
