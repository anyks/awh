/**
 * @brief Проверка сличения значений
 *
 */
TEST(CodecJsonValue, Compare) {
	// Значение, заведённое целым числом со знаком
	const json::value_t first(static_cast <int64_t> (7));
	// Значение, заведённое целым числом без знака
	const json::value_t second(static_cast <uint64_t> (7));
	/**
	 * Выполняем проверку совпадения чисел разной знаковости
	 *
	 * @note Числа сличаются величиной своей, а не видом хранения
	 */
	ASSERT_TRUE(first == second);
	// Выполняем проверку совпадения целого числа с дробным той же величины
	ASSERT_TRUE(first == json::value_t(7.));
	// Первое сличаемое значение
	json::value_t left;
	// Второе сличаемое значение
	json::value_t right;
	// Выполняем разбор текста первого значения
	ASSERT_TRUE(left.parse("{\"a\":1,\"b\":2}"));
	// Выполняем разбор текста второго значения, разнящегося лишь порядком полей
	ASSERT_TRUE(right.parse("{\"b\":2,\"a\":1}"));
	/**
	 * Выполняем проверку совпадения объектов, разнящихся порядком полей
	 *
	 * @note Стандарт порядка полей не предписывает вовсе, и два объекта, разнящиеся лишь
	 *       порядком, одинаковы по сути своей
	 */
	ASSERT_TRUE(left == right);
	// Выполняем разбор текста второго значения, разнящегося величиной поля
	ASSERT_TRUE(right.parse("{\"b\":2,\"a\":9}"));
	// Выполняем проверку несовпадения значений
	ASSERT_TRUE(left != right);
	// Выполняем проверку несовпадения значений разного вида
	ASSERT_TRUE(json::value_t("1") != json::value_t(static_cast <int64_t> (1)));
}

/**
 * @brief Проверка совпадения извлечения из значения и из узла документа
 *
 * @note Проверка эта закрепляет то, что расходиться двум путям извлечения нельзя:
 *       приведение дробного к целому у них одно на двоих
 *
 */
TEST(CodecJsonValue, Consistency) {
	/**
	 * Разбираемый текст документа
	 *
	 * @note Записи взяты по краям видов хранения намеренно: `18446744073709551615`
	 *       занимает все разряды целого без знака, старший в том числе, и знаковое
	 *       чтение такого числа выдало бы `-1`; `-0.0` теряет знак нуля молча, коль
	 *       скоро запись где-то пересобирается
	 */
	const string text =
		"{\"a\":1e300,\"b\":-1.5,\"c\":9007199254740993,\"d\":0.1,"
		"\"e\":18446744073709551615,\"f\":-9223372036854775808,"
		"\"g\":-0.0,\"h\":255,\"i\":-128,\"j\":1e400}";
	// Документ, разбирающий текст
	json::document_t document(::logger());
	// Выполняем разбор текста документа
	ASSERT_TRUE(document.parse(text));
	// Снятое с документа значение
	const json::value_t value(document.root());
	/**
	 * Выполняем перебор всех полей документа
	 */
	for(const char * name : {"a", "b", "c", "d", "e", "f", "g", "h", "i", "j"}){
		// Выполняем проверку совпадения видов хранения
		ASSERT_EQ(document[name].type(), value[name].type()) << name;
		// Извлекаемое из узла документа целое значение
		int32_t first = 0;
		// Извлекаемое из владеющего значения целое значение
		int32_t second = 0;
		// Выполняем извлечение целого значения из узла документа
		ASSERT_EQ(document[name].value(first), value[name].value(second)) << name;
		// Выполняем проверку совпадения извлечённых значений
		ASSERT_EQ(first, second) << name;
		// Извлекаемое из узла документа целое значение без знака
		uint64_t third = 0;
		// Извлекаемое из владеющего значения целое значение без знака
		uint64_t fourth = 0;
		// Выполняем извлечение целого значения без знака из узла документа
		ASSERT_EQ(document[name].value(third), value[name].value(fourth)) << name;
		// Выполняем проверку совпадения извлечённых значений без знака
		ASSERT_EQ(third, fourth) << name;
		// Извлекаемое из узла документа дробное значение
		double fifth = 0.;
		// Извлекаемое из владеющего значения дробное значение
		double sixth = 0.;
		/**
		 * Выполняем извлечение дробного значения обоими путями
		 *
		 * @note Дробным видом и всплывает расхождение знаковости: целыми видами разряды
		 *       у обеих знаковостей одни и те же, и промах остаётся невидим
		 */
		ASSERT_EQ(document[name].value(fifth), value[name].value(sixth)) << name;
		// Выполняем проверку совпадения извлечённых дробных значений
		ASSERT_DOUBLE_EQ(fifth, sixth) << name;
		// Выполняем проверку совпадения знака нуля
		ASSERT_EQ(::std::signbit(fifth), ::std::signbit(sixth)) << name;
	}
	// Выполняем проверку совпадения записи документа и записи снятого значения
	ASSERT_STREQ(document.dump().c_str(), value.dump().c_str());
}

