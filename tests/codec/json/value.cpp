/**
 * @brief Безымянное пространство имён вспомогательных объявлений проверок
 *
 * @note Пространство это безымянно намеренно: проверки всех кодеков собираются одной
 *       программой, и вынесенное наружу имя столкнулось бы с таким же именем соседа
 *
 */
namespace {
	/**
	 * @brief Функция, возвращающая значение наружу, как это делал бы модуль
	 *
	 * @return собранное значение
	 *
	 */
	static json::value_t produce() noexcept {
		// Собираемое значение
		json::value_t result;
		// Выполняем заведение строкового поля
		result["имя"] = json::value_t("сервер");
		// Выполняем заведение числового поля
		result["порт"] = json::value_t(static_cast <uint64_t> (8080));
		// Выполняем заведение значений вглубь по пути
		result.place("/сеть/адреса/0") = json::value_t("127.0.0.1");
		// Выполняем заведение второго значения вглубь по пути
		result.place("/сеть/адреса/1") = json::value_t("::1");
		// Выводим собранное значение
		return result;
	}
}

/**
 * @brief Проверка заведения дерева из ничего
 *
 */
TEST(CodecJsonValue, Assemble) {
	// Собираемое значение
	json::value_t value;
	// Выполняем проверку неопределённости пустого значения
	ASSERT_FALSE(value.valid());
	// Выполняем проверку вида пустого значения
	ASSERT_EQ(value.kind(), json::kind_t::NONE);
	// Выполняем проверку вида хранения пустого значения
	ASSERT_TRUE(value.is(json::type_t::UNDEFINED));
	// Выполняем заведение строкового поля
	value["имя"] = json::value_t("сервер");
	// Выполняем проверку перерождения значения объектом
	ASSERT_EQ(value.kind(), json::kind_t::OBJECT);
	// Выполняем проверку количества полей объекта
	ASSERT_EQ(value.size(), static_cast <size_t> (1));
	// Выполняем проверку имени заведённого поля объекта
	ASSERT_STREQ(value.key(0).c_str(), "имя");
	// Выполняем проверку записи собранного значения
	ASSERT_STREQ(value.dump().c_str(), "{\"имя\":\"сервер\"}");
}

/**
 * @brief Проверка передачи значения наружу итогом метода
 *
 * @note Проверка эта и есть та самая, ради какой тип заведён: ссылка на узел документа
 *       наружу передана быть не может вовсе
 *
 */
TEST(CodecJsonValue, Produce) {
	// Получаем значение, собранное и выданное наружу
	const json::value_t value = ::produce();
	// Извлекаемое строковое значение
	string name;
	// Выполняем извлечение строкового поля
	ASSERT_TRUE(value["имя"].value(name));
	// Выполняем проверку извлечённого строкового значения
	ASSERT_STREQ(name.c_str(), "сервер");
	// Извлекаемое числовое значение
	uint64_t port = 0;
	// Выполняем извлечение числового поля
	ASSERT_TRUE(value["порт"].value(port));
	// Выполняем проверку извлечённого числового значения
	ASSERT_EQ(port, static_cast <uint64_t> (8080));
	// Выполняем проверку обращения по пути
	ASSERT_STREQ(value.at("/сеть/адреса/1").text().c_str(), "::1");
	// Выполняем проверку записи собранного значения
	ASSERT_STREQ(value.dump().c_str(), "{\"имя\":\"сервер\",\"порт\":8080,\"сеть\":{\"адреса\":[\"127.0.0.1\",\"::1\"]}}");
}

/**
 * @brief Проверка складываемости значения во вместилища языка
 *
 */
TEST(CodecJsonValue, Storable) {
	// Вместилище языка, куда складываются значения
	vector <json::value_t> items;
	// Выполняем добавление собранного значения во вместилище
	items.push_back(::produce());
	// Выполняем добавление числового значения во вместилище
	items.push_back(json::value_t(static_cast <int64_t> (-42)));
	// Выполняем проверку сохранности собранного значения
	ASSERT_STREQ(items.at(0)["имя"].text().c_str(), "сервер");
	// Извлекаемое числовое значение
	int64_t number = 0;
	// Выполняем извлечение числового значения
	ASSERT_TRUE(items.at(1).value(number));
	// Выполняем проверку извлечённого числового значения
	ASSERT_EQ(number, static_cast <int64_t> (-42));
	// Выполняем копирование значения
	const json::value_t copy = items.at(0);
	// Выполняем очистку вместилища языка
	items.clear();
	// Выполняем проверку сохранности копии после гибели исходного значения
	ASSERT_STREQ(copy["имя"].text().c_str(), "сервер");
}

