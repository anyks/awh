/**
 * @brief Проверка прививки владеющего значения в дерево документа
 *
 * @note Прививка есть путь, обратный снятию: снятое, изменённое и собранное заново
 *       значение возвращается на своё место в дереве, а прочее дерево остаётся
 *       нетронутым
 *
 */
TEST(CodecJsonValue, Graft) {
	// Документ, разбирающий текст
	json::document_t document(::logger());
	// Выполняем разбор текста документа
	ASSERT_TRUE(document.parse("{\"a\":1,\"b\":{\"c\":[1,2,3]},\"d\":\"хвост\"}"));
	// Прививаемое значение
	json::value_t value;
	// Выполняем сборку прививаемого значения
	value["новое"] = json::value_t(static_cast <int64_t> (7));
	// Выполняем прививку значения на место вложенного объекта
	ASSERT_TRUE(document.graft("/b", value));
	/**
	 * Выполняем проверку перезаписи документа после прививки
	 *
	 * @note Имя поля при прививке сохраняется: прививается значение, а не поле
	 */
	ASSERT_STREQ(document.dump().c_str(), "{\"a\":1,\"b\":{\"новое\":7},\"d\":\"хвост\"}");
	// Выполняем проверку обхода дерева после прививки
	ASSERT_STREQ(document.at("/b/новое").raw().c_str(), "7");
	/**
	 * Выполняем проверку сохранности соседних полей
	 *
	 * @note Сличается строковый вид содержимого, а не указание его: содержимое узла
	 *       лежит в общем хранилище знаков и нулём не завершается вовсе
	 */
	ASSERT_EQ(document["d"].text(), string_view("хвост"));
}

