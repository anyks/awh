	const size_t count = 64;
	// Заводимое значение объекта
	json::value_t root;
	/**
	 * Выполняем заведение полей объекта
	 */
	for(size_t i = 0; i < count; i++)
		// Заводим очередное поле объекта
		root["field_" + to_string(i)] = static_cast <int64_t> (i);
