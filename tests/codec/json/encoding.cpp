/**
 * @brief Проверка удержания знака между кусками при приведении текста
 *
 * @note Приведение удерживает начало текста до определения кодировки, и знак,
 *       разорванный границей куска, попадает в буфер удержанных байтов лишь ПОСЛЕ
 *       того, как кодировка определена. Оттого куски здесь длиннее метки порядка
 *       байтов - иначе проверялось бы удержание начала, а не удержание знака
 * @warning Собранный из кусков знак обязан выходить тем же, что и поданный целиком:
 *          иначе нарезка текста на куски меняла бы приведённый текст, см. правило
 *          независимости разбора от нарезки
 */
TEST(CodecJsonEncoding, HeldSequence) {
	/**
	 * Знак из трёх байтов, разорванный надвое
	 */
	{
		// Выполняем создание объекта приведения текста
		json::decoder_t decoder(::logger());
		// Текст, к которому приводится исходный
		string result = "";
		// Выполняем подачу куска, оборванного посреди знака
		ASSERT_TRUE(decoder.convert("\"abc\xE2\x82", 6, false, result));
		// Выполняем подачу недостающего байта знака и завершения текста
		ASSERT_TRUE(decoder.convert("\xAC\"", 2, true, result));
		// Выполняем проверку кода ошибки приведения
		ASSERT_EQ(decoder.error(), json::error_t::NONE);
		// Выполняем проверку полученного текста
		ASSERT_EQ(result, "\"abc\xE2\x82\xAC\"");
	}
	/**
	 * Знак из четырёх байтов, разорванный натрое
	 *
	 * @note Добор идёт по одному байту за кусок: удержание обязано переживать
	 *       несколько подач подряд, а не только одну
	 */
	{
		// Выполняем создание объекта приведения текста
		json::decoder_t decoder(::logger());
		// Текст, к которому приводится исходный
		string result = "";
		// Выполняем подачу куска, оборванного посреди знака
		ASSERT_TRUE(decoder.convert("\"abc\xF0\x9F", 6, false, result));
		// Выполняем подачу третьего байта последовательности знака
		ASSERT_TRUE(decoder.convert("\x98", 1, false, result));
		// Выполняем подачу четвёртого байта знака и завершения текста
		ASSERT_TRUE(decoder.convert("\x81\"", 2, true, result));
		// Выполняем проверку кода ошибки приведения
		ASSERT_EQ(decoder.error(), json::error_t::NONE);
		// Выполняем проверку полученного текста
		ASSERT_EQ(result, "\"abc\xF0\x9F\x98\x81\"");
	}
	/**
	 * Удержанный знак остался недобранным к концу текста
	 */
	{
		// Выполняем создание объекта приведения текста
		json::decoder_t decoder(::logger());
		// Текст, к которому приводится исходный
		string result = "";
		// Выполняем подачу куска, оборванного посреди знака
		ASSERT_TRUE(decoder.convert("\"abc\xE2\x82", 6, false, result));
		// Выполняем подачу пустого последнего куска
		ASSERT_FALSE(decoder.convert(nullptr, 0, true, result));
		// Выполняем проверку кода ошибки приведения
		ASSERT_EQ(decoder.error(), json::error_t::INVALID_ENCODING);
	}
	/**
	 * Удержанный знак добран байтом, последовательности не принадлежащим
	 */
	{
		// Выполняем создание объекта приведения текста
		json::decoder_t decoder(::logger());
		// Текст, к которому приводится исходный
		string result = "";
		// Выполняем подачу куска, оборванного посреди знака
		ASSERT_TRUE(decoder.convert("\"abc\xE2\x82", 6, false, result));
		// Выполняем подачу байта, хвостовым для знака не являющегося
		ASSERT_FALSE(decoder.convert("\x28\"", 2, true, result));
		// Выполняем проверку кода ошибки приведения
		ASSERT_EQ(decoder.error(), json::error_t::INVALID_ENCODING);
	}
}
/**
 * @brief Проверка отказов проверки текста на месте единственным куском
 *
 * @note Дорога проверки на месте разбирает текст ПРЯМО ИЗ БУФЕРА потребителя,
 *       ничего никуда не перенося, и оттого проходится почти всяким разбором.
 *       Здесь текст подаётся ЦЕЛИКОМ, последним куском сразу: отказы обязаны
 *       выноситься и без удержания байтов между подачами
 */
TEST(CodecJsonEncoding, DirectRefusals) {
	/**
	 * Способ подачи текста проверке на месте единственным куском
	 *
	 * @param text проверяемый текст исходного вида
	 * @return     код ошибки проверки текста
	 */
	auto once = [](const string & text) noexcept -> json::error_t {
		// Выполняем создание объекта приведения текста
		json::decoder_t decoder(::logger());
		// Кусок проверенного текста
		json::decoder_t::chunk_t chunk;
		// Выполняем подачу текста единственным куском
		decoder.verify(text.data(), text.size(), true, chunk);
		// Выводим код ошибки проверки текста
		return decoder.error();
	};
	// Выполняем проверку отклонения текста, оборванного посреди знака
	ASSERT_EQ(once(string("\"\xE2\x82", 3)), json::error_t::INVALID_ENCODING);
	// Выполняем проверку отклонения суррогата, записанного в кодировке UTF-8
	ASSERT_EQ(once(string("\"\xED\xA0\x80\"", 5)), json::error_t::INVALID_ENCODING);
	// Выполняем проверку отклонения кодового значения за пределами Юникода
	ASSERT_EQ(once(string("\"\xF5\x80\x80\x80\"", 6)), json::error_t::INVALID_ENCODING);
	// Выполняем проверку отклонения хвостового байта без ведущего
	ASSERT_EQ(once(string("\"\x82\"", 3)), json::error_t::INVALID_ENCODING);
	// Выполняем проверку принятия годного текста
	ASSERT_EQ(once(string("\"\xE2\x82\xAC\"", 5)), json::error_t::NONE);
}

/**
 * @brief Проверка удержания недочитанной пары байтов UTF-16 между кусками
 *
 * @details Пара байтов кодировки UTF-16 вправе разорваться границей куска, и приведение
 *          удерживает нечётный байт до прихода следующего. Кусок же, пришедший следом,
 *          вправе оказаться ПУСТЫМ - подающая сторона не обязана знать, чего приведению
 *          недостаёт, - и удержанный байт обязан пережить такой кусок нетронутым
 *
 * @note Место это отыскано по карте покрытия: набор пустых кусков посреди текста не подавал
 *       вовсе, и удержание через них не проверялось ни разу
 *
 */
TEST(CodecJsonEncoding, Utf16PendingAcrossChunks) {
	// Метка порядка байтов кодировки UTF-16 с обратным порядком
	const string bom("\xFF\xFE", 2);
	// Тело текста в кодировке UTF-16 с обратным порядком байтов
	const string body("\x22\x00\x61\x00\x22\x00", 6);
	/**
	 * Выполняем перебор видов куска, подаваемого следом за нечётным
	 */
	for(uint32_t kind = 0; kind < 3; kind++){
		// Объект приведения кодировки исходного текста
		json::decoder_t decoder(::logger());
		// Приведённый текст
		string result;
		// Собираем первый кусок, оборванный посреди пары байтов
		const string head = (bom + body.substr(0, 3));
		// Выполняем подачу первого куска
		ASSERT_TRUE(decoder.convert(head.data(), head.size(), false, result)) << kind;
		/**
		 * Определяем вид куска, подаваемого следом
		 */
		switch(kind){
			// Подаём пустой кусок
			case 0: ASSERT_TRUE(decoder.convert("", 0, false, result)) << kind; break;
			// Подаём пустой указатель
			case 1: ASSERT_TRUE(decoder.convert(nullptr, 0, false, result)) << kind; break;
			// Подаём один байт, пару байтов завершающий
			case 2: ASSERT_TRUE(decoder.convert(body.data() + 3, 1, false, result)) << kind; break;
		}
		// Выполняем подачу остатка текста
		ASSERT_TRUE(decoder.convert(body.data() + ((kind == 2) ? 4 : 3), ((kind == 2) ? 2 : 3), true, result)) << kind;
		// Выполняем проверку отсутствия ошибки приведения
		ASSERT_EQ(decoder.error(), json::error_t::NONE) << kind;
		// Выполняем проверку приведённого текста
		ASSERT_EQ(result, "\"a\"") << kind;
	}
}

/**
 * @brief Проверка признака возможности проверки текста на месте
 *
 * @details Признак этот выбирает СПОСОБ ЧТЕНИЯ: при нём поднятом чтение проверяет знаки
 * прямо в поданном буфере, не перенося ни байта в отдельное хранилище, а при снятом текст
 * приводится переносом. Ошибись он - разбор молча уйдёт не тем ходом
 *
 * @warning Проверка сличает не один лишь признак, но и РАВЕНСТВО ОБОИХ ПУТЕЙ на одном и
 *          том же содержимом: признак, выдающий верное значение, но уводящий разбор к
 *          иной выдаче, сличением одного лишь признака не ловится никак
 */
TEST(CodecJsonEncoding, DirectPathSelection){
	/**
	 * Выполняем проверку признака у нетронутого объекта приведения
	 *
	 * @note Кодировка ещё не определена, и проверять на месте нечего: способ чтения
	 *       выбирается лишь после того, как кодировка стала известна
	 */
	{
		// Объект приведения исходного текста
		json::decoder_t decoder(::logger());
		// Выполняем проверку того, что кодировка не определена
		ASSERT_EQ(decoder.encoding(), json::encoding_t::NONE);
	}
	/**
	 * Выполняем проверку поднятия признака у текста в кодировке UTF-8
	 */
	{
		// Объект приведения исходного текста
		json::decoder_t decoder(::logger());
		// Результат приведения исходного текста
		string result;
		// Выполняем приведение текста в кодировке UTF-8
		ASSERT_TRUE(decoder.convert("{\"ключ\":1}", 15, true, result));
		// Выполняем проверку определённой кодировки исходного текста
		ASSERT_EQ(decoder.encoding(), json::encoding_t::UTF8);
		// Выполняем проверку того, что проверка на месте возможна
		ASSERT_TRUE(decoder.direct());
	}
	/**
	 * Выполняем проверку снятия признака у текста в кодировке UTF-16
	 *
	 * @note Приводить тут есть что, и читать на месте нельзя: способ чтения обязан быть
	 *       иным
	 */
	{
		// Объект приведения исходного текста
		json::decoder_t decoder(::logger());
		// Результат приведения исходного текста
		string result;
		/**
		 * Разбираемый текст в кодировке UTF-16 с меткой порядка байтов
		 *
		 * @note Длина берётся у самой строки, а не числом: запись `{"a":1}` занимает семь
		 *       знаков, то есть четырнадцать байтов, и метка два - число это легко
		 *       ошибиться, а чтение за концом литерала санитайзер ловит, но лишь под ним
		 */
		const string wide("\xFF\xFE" "{\0\"\0a\0\"\0:\0" "1\0}\0", 16);
		// Выполняем приведение текста в кодировке UTF-16
		ASSERT_TRUE(decoder.convert(wide.data(), wide.size(), true, result));
		// Выполняем проверку определённой кодировки исходного текста
		ASSERT_NE(decoder.encoding(), json::encoding_t::UTF8);
		// Выполняем проверку того, что проверка на месте невозможна
		ASSERT_FALSE(decoder.direct());
	}
	/**
	 * Выполняем сличение выдачи разбора обоими способами чтения
	 *
	 * @details Один и тот же документ подаётся в двух кодировках: в UTF-8, где чтение идёт
	 * на месте, и в UTF-16, где текст приводится переносом. Выдача обязана совпасть
	 * дословно - иначе способ чтения меняет прочитанное, а не одну лишь дорогу к нему
	 */
	{
		// Разбираемый документ в кодировке UTF-8
		const string sample("{\"имя\":\"значение\",\"число\":42,\"перечень\":[1,2,3]}");
		// Собираемый документ в кодировке UTF-16 с меткой порядка байтов
		string wide("\xFF\xFE", 2);
		/**
		 * Выполняем перевод документа в кодировку UTF-16
		 *
		 * @note Перевод ведётся по знакам Юникода, а не по байтам: за пределом US-ASCII
		 *       знак занимает в UTF-8 несколько байтов, и побайтовый перевод дал бы иной
		 *       текст
		 */
		for(size_t i = 0; i < sample.size();){
			// Разбираемый знак Юникода
			uint32_t letter = static_cast <uint8_t> (sample[i]);
			// Количество байтов, занимаемых знаком Юникода
			size_t count = 1;
			/**
			 * Определяем количество байтов, занимаемых знаком Юникода
			 */
			if((letter & 0xE0) == 0xC0){
				// Запоминаем количество байтов знака Юникода
				count = 2;
				// Запоминаем значащие разряды ведущего байта
				letter &= 0x1F;
			} else if((letter & 0xF0) == 0xE0){
				// Запоминаем количество байтов знака Юникода
				count = 3;
				// Запоминаем значащие разряды ведущего байта
				letter &= 0x0F;
			}
			/**
			 * Выполняем перебор всех продолжающих байтов знака Юникода
			 */
			for(size_t j = 1; j < count; j++)
				// Выполняем добавление разрядов продолжающего байта
				letter = ((letter << 6) | (static_cast <uint8_t> (sample[i + j]) & 0x3F));
			// Выполняем добавление младшего байта знака Юникода
			wide.push_back(static_cast <char> (letter & 0xFF));
			// Выполняем добавление старшего байта знака Юникода
			wide.push_back(static_cast <char> ((letter >> 8) & 0xFF));
			// Выполняем переход к следующему знаку Юникода
			i += count;
		}
		// Код ошибки разбора
		json::error_t error = json::error_t::NONE;
		// Дерево документа, разбирающее текст в кодировке UTF-8
		json::document_t narrow(::logger());
		// Выполняем разбор документа в кодировке UTF-8
		ASSERT_TRUE(narrow.parse(sample)) << json::message(narrow.error());
		// Дерево документа, разбирающее текст в кодировке UTF-16
		json::document_t broad(::logger());
		// Выполняем разбор документа в кодировке UTF-16
		ASSERT_TRUE(broad.parse(wide)) << json::message(broad.error());
		// Выполняем сличение выдачи обоих способов чтения
		ASSERT_EQ(narrow.dump(), broad.dump()) << json::message(error);
		// Выполняем сличение выдачи с исходным документом
		ASSERT_EQ(narrow.dump(), sample);
	}
}
