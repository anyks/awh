/**
 * @brief Проверка сброса приведения в исходное состояние
 *
 */
TEST(CodecJsonEncoding, Reset) {
	// Результат приведения исходного текста
	string result = "";
	// Объект приведения исходного текста
	json::decoder_t decoder;
	// Выполняем приведение текста с меткой порядка байтов
	ASSERT_TRUE(decoder.convert(string("\xFF\xFE" "a\0", 4).data(), 4, true, result));
	// Выполняем проверку определённой кодировки исходного текста
	ASSERT_EQ(decoder.encoding(), json::encoding_t::UTF16LE);
	// Выполняем сброс приведения в исходное состояние
	decoder.reset();
	// Выполняем проверку сброса определённой кодировки исходного текста
	ASSERT_EQ(decoder.encoding(), json::encoding_t::NONE);
	// Выполняем проверку сброса признака обнаружения метки порядка байтов
	ASSERT_FALSE(decoder.signature());
	// Очищаем результат приведения исходного текста
	result.clear();
	// Выполняем приведение текста без метки порядка байтов
	ASSERT_TRUE(decoder.convert("b", 1, true, result));
	// Выполняем проверку того, что кодировка определена заново
	ASSERT_EQ(decoder.encoding(), json::encoding_t::UTF8);
	// Выполняем проверку приведённого текста
	ASSERT_EQ(result, "b");
}
/**
 * @brief Проверка правильности построения последовательностей UTF-8
 *
 * @details Проверка кодировки идёт на месте, без приведения текста копией, и
 * двухбайтовые последовательности берутся отдельным быстрым путём. Путь этот обязан
 * отвергать в точности то же, что отвергает общий: избыточную запись, недостачу
 * продолжающих байтов, одинокий продолжающий байт и суррогатные значения
 *
 * @note Всякий случай прогоняется при восьми размерах куска: проверка кодировки
 *       чувствительна к нарезке текста, а быстрый путь двухбайтовых последовательностей
 *       обрывается границей куска особо
 *
 */
TEST(CodecJsonEncoding, Utf8Sequences) {
	/**
	 * Разбираемые тексты вместе с ожидаемым исходом разбора
	 */
	const vector <pair <string, bool>> samples = {
		{"[\"привет мир\"]", true},
		{string("[\"") + "\xD0\xB0\xD0\xB1\xD0\xB2" + "\"]", true},
		{string("[\"") + "\xE2\x82\xAC" + "\"]", true},
		{string("[\"") + "\xF0\x9F\x98\x80" + "\"]", true},
		{string("[\"") + "\xC0\x80" + "\"]", false},
		{string("[\"") + "\xC1\xBF" + "\"]", false},
		{string("[\"") + "\xD0" + "a\"]", false},
		{string("[\"") + "\x80" + "\"]", false},
		{string("[\"") + "\xD0", false},
		{string("[\"") + "\xED\xA0\x80" + "\"]", false},
		{string("[\"") + "\xF5\x80\x80\x80" + "\"]", false}
	};
	/**
	 * Выполняем перебор всех разбираемых текстов
	 */
	for(const auto & sample : samples){
		/**
		 * Выполняем перебор всех размеров подаваемого куска
		 */
		for(size_t chunk = 1; chunk <= 8; chunk++){
			// Объект потокового чтения текста
			json::reader_t reader;
			// Признак успешности разбора текста
			bool result = true;
			/**
			 * Выполняем подачу текста кусками
			 */
			for(size_t offset = 0; offset < sample.first.size(); offset += chunk){
				// Получаем размер очередного подаваемого куска
				const size_t length = (((offset + chunk) < sample.first.size()) ? chunk : (sample.first.size() - offset));
				/**
				 * Если подача очередного куска текста завершилась отказом
				 */
				if(!reader.feed(sample.first.data() + offset, length, ((offset + length) >= sample.first.size()))){
					// Запоминаем признак неудачного разбора
					result = false;
					// Прекращаем подачу текста
					break;
				}
			}
			// Выполняем проверку совпадения исхода разбора с ожидаемым
			ASSERT_EQ(result, sample.second) << "кусок " << chunk;
		}
	}
}

/**
 * @brief Проверка отказа тексту, оборванному посреди знака, и разбора в US-ASCII
 *
 * @details Карта покрытия 19.08.2026 показала, что оба этих пути отказа не звались ни
 *          одной проверкой. Текст, оборвавшийся посреди последовательности знака UTF-8,
 *          обязан быть отвергнут именно на последнем куске: до него обрыв неотличим от
 *          знака, чей хвост ещё не подан, и отвергать его нельзя
 *
 * @note Кодировка, навязанная настройками, обязана и отвергать выходящее за неё: разбор
 *       в US-ASCII текста с кириллицей проходить не должен
 *
 */
TEST(CodecJsonEncoding, TruncatedAndAscii) {
	// Собираемый текст документа с оборванным знаком в конце
	string text = "{\"a\":\"";
	// Добавляем знак кириллицы целиком
	text.append("\xD0\xB0");
	// Добавляем начало знака кириллицы без хвоста его
	text.push_back('\xD0');
	// Дерево документа JSON
	json::document_t document;
	// Выполняем проверку того, что текст с оборванным знаком отвергается
	ASSERT_FALSE(document.parse(text));
	// Выполняем проверку того, что отказ вынесен по кодировке
	ASSERT_EQ(document.error(), json::error_t::INVALID_ENCODING);
	// Дерево документа, разбираемого в US-ASCII
	json::document_t ascii;
	// Получаем настройки дерева документа
	json::document_t::settings_t settings = ascii.settings();
	// Устанавливаем кодировку исходного текста US-ASCII
	settings.reader.encoding = json::encoding_t::ASCII;
	// Выполняем установку настроек дерева документа
	ascii.settings(settings);
	// Выполняем проверку того, что текст латиницей разбирается
	ASSERT_TRUE(ascii.parse("{\"a\":\"b\"}"));
	// Дерево документа с текстом, за US-ASCII выходящим
	json::document_t beyond;
	// Выполняем установку настроек дерева документа
	beyond.settings(settings);
	// Выполняем проверку того, что текст с кириллицей отвергается
	ASSERT_FALSE(beyond.parse("{\"a\":\"б\"}"));
}
/**
 * @brief Проверка отказов приведения двухбайтовых кодировок
 *
 * @details Отказы приведения - это первая преграда на пути недоверенного текста, и
 *          карта покрытия показала нетронутыми почти все из них у кодировок UTF-16 и
 *          UTF-32: набор проверял лишь ошибочную запись UTF-8. Всякая запись здесь
 *          ломает текст своим порядком - одиноким суррогатом, оборванной парой,
 *          нечётной длиной, кодовым значением за пределами Юникода и знаком,
 *          недопустимым в тексте
 *
 * @note Сличение ведётся при всяком размере подаваемого куска: ошибочная
 *       последовательность, разорванная границей куска, обязана отвергаться так же,
 *       как поданная целиком. Размер куска отказа не меняет ни разу
 *
 */
TEST(CodecJsonEncoding, MalformedUnits) {
	/**
	 * @brief Разбираемый текст и ожидаемый код ошибки приведения
	 *
	 */
	const struct {
		// Разбираемый текст с меткой порядка байтов
		string text;
		// Ожидаемый код ошибки приведения
		json::error_t error;
	} items[] = {
		// Одинокий верхний суррогат в кодировке UTF-16 прямого порядка
		{string("\xFF\xFE""\x00\xD8""\x41\x00", 6),                     json::error_t::INVALID_ENCODING},
		// Одинокий нижний суррогат в кодировке UTF-16 прямого порядка
		{string("\xFF\xFE""\x00\xDC""\x41\x00", 6),                     json::error_t::INVALID_ENCODING},
		// Оборванная суррогатная пара в конце текста
		{string("\xFF\xFE""\x00\xD8", 4),                               json::error_t::INVALID_ENCODING},
		// Нечётная длина текста в кодировке UTF-16 прямого порядка
		{string("\xFF\xFE""\x41\x00""\x41", 5),                         json::error_t::INVALID_ENCODING},
		// Одинокий верхний суррогат в кодировке UTF-16 обратного порядка
		{string("\xFE\xFF""\xD8\x00""\x00\x41", 6),                     json::error_t::INVALID_ENCODING},
		// Нечётная длина текста в кодировке UTF-16 обратного порядка
		{string("\xFE\xFF""\x00\x41""\x00", 5),                         json::error_t::INVALID_ENCODING}
	};
	/**
	 * Выполняем перебор всех разбираемых текстов
	 */
	for(auto & item : items){
		/**
		 * Выполняем перебор всех размеров подаваемого куска
		 */
		for(size_t chunk = 1; chunk <= item.text.size(); chunk++){
			// Код ошибки приведения исходного текста
			json::error_t error = json::error_t::NONE;
			// Выполняем приведение разбираемого текста
			::convert(item.text, chunk, error);
			// Выполняем проверку кода ошибки приведения
			ASSERT_EQ(error, item.error) << "кусок " << chunk << " из " << item.text.size();
		}
	}
}
/**
 * @brief Проверка приведения из навязанных однобайтовых кодировок
 *
 * @details Кодировки однобайтовые метки порядка байтов не имеют и определению не
 *          поддаются: навязать их вправе лишь потребитель, знающий кодировку из
 *          внешнего источника. Карта покрытия показала все три дороги приведения
 *          нетронутыми, кроме удачной у ISO-8859-1
 *
 * @note Отказы у них РАЗНЫЕ по поводу, и путать их нельзя: у US-ASCII старший байт есть
 *       нарушение самой кодировки, а у Windows-1252 неопределённый байт есть отсутствие
 *       знака - кодировка эта покрывает не все двести пятьдесят шесть значений
 *
 * @warning Управляющие знаки приведением НЕ отвергаются ни в одной из кодировок, и это
 *          намеренно: договор запрещает их лишь внутри строкового значения, а не в
 *          тексте вообще. Отвергает их чтение, и закрепляет это отдельная проверка -
 *          свести их сюда значило бы отвергать законные тексты
 *
 */
TEST(CodecJsonEncoding, ForcedSingleByte) {
	/**
	 * @brief Метод приведения текста из навязанной кодировки
	 *
	 * @param encoding навязываемая кодировка исходного текста
	 * @param text     приводимый текст
	 * @param result   приведённый текст
	 * @param error    код ошибки приведения
	 * @return         результат выполнения приведения
	 *
	 */
	auto forced = [](const json::encoding_t encoding, const string & text, string & result, json::error_t & error) noexcept -> bool {
		// Объект приведения исходного текста
		json::decoder_t decoder;
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем навязывание кодировки исходного текста
		if(!decoder.encoding(encoding)) return false;
		// Выполняем приведение текста в навязанной кодировке
		const bool outcome = decoder.convert(text.data(), text.size(), true, result);
		// Запоминаем код ошибки приведения
		error = decoder.error();
		// Выводим результат выполнения приведения
		return outcome;
	};
	// Приведённый текст
	string result;
	// Код ошибки приведения
	json::error_t error = json::error_t::NONE;
	// Выполняем проверку приведения годного текста из кодировки US-ASCII
	ASSERT_TRUE(forced(json::encoding_t::ASCII, "[1,2]", result, error));
	// Выполняем проверку того, что текст US-ASCII приведением не тронут
	ASSERT_EQ(result, "[1,2]");
	// Выполняем проверку отклонения старшего байта в кодировке US-ASCII
	ASSERT_FALSE(forced(json::encoding_t::ASCII, string("[\xE9]"), result, error));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, json::error_t::INVALID_ENCODING);
	// Выполняем проверку приведения годного текста из кодировки Windows-1252
	ASSERT_TRUE(forced(json::encoding_t::CP1252, string("[\x93\x94]"), result, error));
	// Выполняем проверку того, что кавычки-лапки приведены знаками Юникода
	ASSERT_EQ(result, "[\xE2\x80\x9C\xE2\x80\x9D]");
	// Выполняем проверку отклонения неопределённого байта кодировки Windows-1252
	ASSERT_FALSE(forced(json::encoding_t::CP1252, string("[\x81]"), result, error));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, json::error_t::INVALID_CHARACTER);
	// Выполняем проверку приведения годного текста из кодировки ISO-8859-1
	ASSERT_TRUE(forced(json::encoding_t::LATIN1, string("[\xE9]"), result, error));
	// Выполняем проверку приведения старшего байта знаком Юникода
	ASSERT_EQ(result, "[\xC3\xA9]");
	/**
	 * Выполняем проверку принятия управляющего знака всеми кодировками
	 *
	 * @note Отвергает его чтение внутри строкового значения, а не приведение: приведение
	 *       обязано отдать байты как есть, иначе законный текст с управляющим знаком вне
	 *       строки был бы отвергнут
	 */
	for(const json::encoding_t encoding : {json::encoding_t::ASCII, json::encoding_t::LATIN1, json::encoding_t::CP1252}){
		// Выполняем приведение текста с управляющим знаком
		ASSERT_TRUE(forced(encoding, string("[\x01]"), result, error)) << static_cast <int> (encoding);
		/**
		 * Выполняем приведение текста с нулевым байтом
		 *
		 * @note Нулевой байт три однобайтовые дороги принимают ОДИНАКОВО. Прежде его
		 *       отвергала одна Windows-1252: нулевое кодовое значение означает там знак,
		 *       кодировкой не определённый, но лишь в области перекодировочной таблицы, а
		 *       оговорки той не было. Расходились дороги на одном и том же тексте
		 */
		ASSERT_TRUE(forced(encoding, string("[\x00]", 4), result, error)) << static_cast <int> (encoding);
	}
	// Выполняем проверку отклонения оборванной пары байтов в навязанной кодировке UTF-16
	ASSERT_FALSE(forced(json::encoding_t::UTF16LE, string("\x5B\x00\x31", 3), result, error));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, json::error_t::INVALID_ENCODING);
	// Выполняем проверку отклонения одинокого суррогата в навязанной кодировке UTF-16
	ASSERT_FALSE(forced(json::encoding_t::UTF16LE, string("\x00\xD8\x41\x00", 4), result, error));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, json::error_t::INVALID_ENCODING);
}
