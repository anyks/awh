/**
 * @brief Проверка расхождения записи и разбора по повторному имени поля
 *
 * @details Запись повтор имени НЕ стережёт, а разбор его по умолчанию отвергает: текст
 * `{"имя":1,"имя":2}`, записью выданный без единого возражения, собственным разбором при
 * настройках по умолчанию не принимается вовсе. Круговой ход при умолчаниях с обеих
 * сторон рвётся
 *
 * @note Проверка закрепляет РАСХОЖДЕНИЕ, а не согласие: заслон у записи стоил бы
 *       хранилища имён под каждый открытый объект на горячем пути, и решение о нём за
 *       владельцем. Пока его нет, край этот описан договором и держится проверкой -
 *       иначе следующий, кто сюда придёт, решит заново и вправе решить иначе
 *
 * @note Запись разметки XML тот же вопрос решает иначе: повтор свойства узла она
 *       стережёт и отвергает кодом `DUPLICATE_ATTRIBUTE`
 *
 */
TEST(CodecJsonWriter, DuplicateKeyPassesWritingButNotParsing){
	// Объект записи текста документа
	json::writer_t writer(::logger());
	// Выполняем открытие объекта
	ASSERT_TRUE(writer.object());
	// Выполняем запись первого поля объекта
	ASSERT_TRUE(writer.key("имя"));
	ASSERT_TRUE(writer.value(static_cast <int64_t> (1)));
	// Выполняем проверку того, что повторное имя записью принимается
	ASSERT_TRUE(writer.key("имя"));
	ASSERT_TRUE(writer.value(static_cast <int64_t> (2)));
	// Выполняем закрытие объекта
	ASSERT_TRUE(writer.close());
	// Выполняем проверку того, что запись отказа не выдала
	ASSERT_EQ(writer.error(), json::error_t::NONE);
	// Получаем собранный текст документа
	const string text = writer.take();
	// Выполняем проверку того, что повтор в текст записан
	ASSERT_EQ(text, "{\"имя\":1,\"имя\":2}");
	/**
	 * Разбор умолчанием такой текст отвергает
	 */
	{
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем проверку отказа разбора текста с повторным именем
		ASSERT_FALSE(doc.parse(text));
		// Выполняем проверку кода отказа разбора
		ASSERT_EQ(doc.error(), json::error_t::DUPLICATE_KEY);
	}
	/**
	 * Прочие правила обращения с повтором его принимают
	 */
	{
		// Правила обращения с повтором и ожидаемая ими запись
		const vector <pair <json::duplicate_t, string>> rules = {
			{json::duplicate_t::FIRST, "{\"имя\":1}"},
			{json::duplicate_t::LAST,  "{\"имя\":2}"},
			{json::duplicate_t::KEEP,  "{\"имя\":1,\"имя\":2}"}
		};
		/**
		 * Выполняем перебор всех правил обращения с повтором
		 */
		for(auto & rule : rules){
			// Настройки документа
			json::document_t::settings_t settings;
			// Устанавливаем правило обращения с повтором имени поля
			settings.duplicates = rule.first;
			// Объект документа
			json::document_t doc(::logger());
			// Выполняем установку настроек документа
			doc.settings(settings);
			// Выполняем проверку успеха разбора текста с повторным именем
			ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
			// Выполняем проверку записи, правилом оставленной
			ASSERT_EQ(doc.dump(), rule.second);
		}
	}
}
/**
 * @brief Проверка того, что заслон склейки судит по написанному, а не по настройке
 *
 * @details Документы потока NDJSON разделяются переводом строки, а пишет разделитель
 * завершение ПЕРВОГО документа. Заслон же против склейки спрашивал настройку потока в
 * миг начала ВТОРОГО: включение потока после завершения первого документа заслон
 * проходило, разделителя в тексте не было, и два документа склеивались в текст, разбор
 * какого распадается на границе между ними
 *
 * @note Замер до правки: `{"a":1}{` при успехе записи и пустом коде отказа
 */
TEST(CodecJsonWriter, StreamSeparatorJudgedByWhatWasWritten){
	/**
	 * Проверяем, что поток верным ходом разделяет документы
	 */
	{
		// Запись текста документа
		json::writer_t writer(::logger());
		// Настройки записи текста документа
		json::writer_t::settings_t settings = writer.settings();
		// Выполняем установку признака разделения документов
		settings.stream = true;
		// Выполняем установку настроек записи
		writer.settings(settings);
		// Выполняем запись первого документа
		ASSERT_TRUE(writer.object() && writer.key("a") && writer.value(static_cast <int64_t> (1)) && writer.close());
		// Выполняем завершение первого документа
		ASSERT_TRUE(writer.finish());
		// Выполняем запись второго документа
		ASSERT_TRUE(writer.object() && writer.key("b") && writer.value(static_cast <int64_t> (2)) && writer.close());
		// Выполняем завершение второго документа
		ASSERT_TRUE(writer.finish());
		// Выполняем проверку собранного текста
		ASSERT_EQ(writer.take(), "{\"a\":1}\n{\"b\":2}\n");
	}
	/**
	 * Проверяем, что включение потока ПОСЛЕ первого документа отвергается
	 */
	{
		// Запись текста документа
		json::writer_t writer(::logger());
		// Настройки записи текста документа
		json::writer_t::settings_t settings = writer.settings();
		// Выполняем запись первого документа без разделения
		ASSERT_TRUE(writer.object() && writer.key("a") && writer.value(static_cast <int64_t> (1)) && writer.close());
		// Выполняем завершение первого документа
		ASSERT_TRUE(writer.finish());
		// Выполняем включение разделения документов после завершения первого
		settings.stream = true;
		// Выполняем установку настроек записи
		writer.settings(settings);
		/**
		 * Выполняем проверку того, что второй документ отвергается
		 *
		 * @note Разделитель пишется завершением первого документа, а к тому мигу поток
		 *       включён не был: писать второй документ некуда, и отказ здесь честнее
		 *       склейки
		 */
		ASSERT_FALSE(writer.object());
		// Выполняем проверку кода отказа записи
		ASSERT_EQ(writer.error(), json::error_t::TEXT_ALREADY_ENDED);
		// Выполняем проверку того, что текст первого документа цел
		ASSERT_EQ(writer.take(), "{\"a\":1}");
	}
}
/**
 * @brief Проверка того, что дробное число переживает оборот до последнего разряда
 *
 * @details Запись числа, прочитанная обратно, обязана дать ТО ЖЕ САМОЕ значение -
 *          сличаемое разрядами, а не печатью. Недостача значащих цифр у записи теряет
 *          значение молча: «0.1» и соседнее с ним число печатаются одинаково, а
 *          разрядами различны
 *
 * @note Сличение ведётся разрядами через `memcpy`, а не сравнением `double`: сравнение
 *       уравняло бы `0` и `-0`, тогда как разрядами они различны, и утрата знака у нуля
 *       осталась бы незамеченной
 *
 * @note Замерено 31.08.2026 щупом на 20 002 числах, из них 20 000 - случайные разрядные
 *       наборы, просеянные от `NaN` и бесконечностей: порч НОЛЬ у JSON и CSV. Здесь
 *       закреплены приметные числа, ибо двадцать тысяч в набор не поставишь
 *
 */
TEST(CodecJsonWriter, DoubleSurvivesRoundTripBitForBit){
	// Сличает число с ним же, прошедшим оборот записи и разбора
	const auto оборот = [](const double число) noexcept -> bool {
		// Объект записи текста документа
		json::writer_t writer(::logger());
		/**
		 * Если запись числа не удалась
		 */
		if(!writer.value(число))
			// Выводим признак неудачного оборота
			return false;
		// Объект владеющего значения
		json::value_t value;
		// Выполняем установку журнала значения
		value.setLogger(::logger());
		/**
		 * Если обратный разбор записанного текста не удался
		 */
		if(!value.parse(writer.text()))
			// Выводим признак неудачного оборота
			return false;
		// Извлекаемое дробное число
		double назад = 0.;
		/**
		 * Если извлечение числа не удалось
		 */
		if(!value.value(назад))
			// Выводим признак неудачного оборота
			return false;
		// Разряды исходного и вернувшегося числа
		uint64_t первые = 0, вторые = 0;
		// Снимаем разряды исходного числа
		::memcpy(&первые, &число, sizeof(первые));
		// Снимаем разряды вернувшегося числа
		::memcpy(&вторые, &назад, sizeof(вторые));
		// Выводим признак совпадения разрядов
		return (первые == вторые);
	};
	/**
	 * Выполняем проверку оборота приметных чисел
	 */
	{
		// Выполняем проверку оборота нуля и минус нуля
		ASSERT_TRUE(оборот(0.));
		ASSERT_TRUE(оборот(-0.));
		// Выполняем проверку оборота чисел, десятичной записи не имеющих
		ASSERT_TRUE(оборот(0.1));
		ASSERT_TRUE(оборот(0.3));
		ASSERT_TRUE(оборот(2. / 3.));
		// Выполняем проверку оборота у границ разрядности
		ASSERT_TRUE(оборот(std::numeric_limits <double>::min()));
		ASSERT_TRUE(оборот(std::numeric_limits <double>::max()));
		ASSERT_TRUE(оборот(std::numeric_limits <double>::denorm_min()));
		ASSERT_TRUE(оборот(std::numeric_limits <double>::epsilon()));
		// Выполняем проверку оборота у предела точного представления целых
		ASSERT_TRUE(оборот(9007199254740992.));
		ASSERT_TRUE(оборот(9007199254740993.));
		// Выполняем проверку оборота приметных постоянных
		ASSERT_TRUE(оборот(3.141592653589793));
		ASSERT_TRUE(оборот(2.718281828459045));
		// Выполняем проверку оборота у краёв области значений
		ASSERT_TRUE(оборот(1e-300));
		ASSERT_TRUE(оборот(1e300));
	}
}
