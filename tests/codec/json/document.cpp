	ASSERT_FALSE(doc["неведомое"].valid());
	// Выполняем проверку безопасности цепочки обращений к отсутствующему полю
	ASSERT_FALSE(doc["неведомое"]["ещё"][static_cast <size_t> (3)].valid());
