/**
 * @brief Проверка правил преобразования чисел при разборе
 *
 */
TEST(CodecJsonDocument, Numbers) {
	// Объект документа
	json::document_t doc(::logger());
	// Получаем настройки документа
	json::document_t::settings_t settings = doc.settings();
	// Выполняем проверку разбора числа, не представимого видом с плавающей запятой
	ASSERT_TRUE(doc.parse("[1e400]")) << json::message(doc.error());
	// Выполняем проверку сохранности записи числа при отложенном преобразовании
	ASSERT_EQ(doc[static_cast <size_t> (0)].raw(), "1e400");
	// Устанавливаем преобразование числа с проверкой представимости
	settings.numbers = json::number_t::CHECK;
	// Выполняем установку настроек документа
	doc.settings(settings);
	// Выполняем проверку отклонения числа, не представимого видом с плавающей запятой
	ASSERT_FALSE(doc.parse("[1e400]"));
	// Выполняем проверку кода отказа разбора
	ASSERT_EQ(doc.error(), json::error_t::NUMBER_OUT_OF_RANGE);
	// Выполняем проверку разбора представимого числа при проверке представимости
	ASSERT_TRUE(doc.parse("[1e308]")) << json::message(doc.error());
	/**
	 * Выполняем проверку отклонения непредставимого числа, оканчивающего текст
	 *
	 * @note Число - единственное значение, у какого нет закрывающего знака: окончанием
	 *       его служит конец текста, и событие его выдаётся уже разбором конца текста.
	 *       Отказ сборки дерева на этом событии прекращает разбор так же, как и на
	 *       всяком другом, - без проверки разбор отчитался бы успехом о пустом дереве
	 */
	ASSERT_FALSE(doc.parse("1e400"));
	// Выполняем проверку кода отказа разбора
	ASSERT_EQ(doc.error(), json::error_t::NUMBER_OUT_OF_RANGE);
	// Устанавливаем преобразование числа без проверки представимости
	settings.numbers = json::number_t::NATIVE;
	// Выполняем установку настроек документа
	doc.settings(settings);
	/**
	 * Выполняем проверку принятия непредставимого числа при хранении записью
	 *
	 * @note Правило `NATIVE` непредставимое число не отвергает: оно получает вид
	 *       `EXTENDED` и хранится записью своей, оттого точность его не теряется
	 */
	ASSERT_TRUE(doc.parse("1e400")) << json::message(doc.error());
	// Выполняем проверку вида непредставимого числа
	ASSERT_TRUE(doc.root().is(json::type_t::EXTENDED));
	// Выполняем проверку сохранности записи непредставимого числа
	ASSERT_EQ(doc.root().raw(), "1e400");
}
