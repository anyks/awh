/**
 * @brief Проверка повтора ключа во вместилище сверх порога отображения
 *
 * @details Поиск повтора ведётся двумя способами: у малых вместилищ перебором собранных
 *          имён, у больших - отображением. Порог между ними задан числом полей, и дорога
 *          отображения набором не проходилась ни разу
 *
 * @warning Число полей здесь заведомо больше порога, и в этом весь смысл проверки: сократи
 *          его - и разбор уйдёт на дорогу перебора, ничем себя не выдав
 *
 */
TEST(CodecJsonDocument, DuplicateKeyBeyondIndexThreshold) {
	/**
	 * Выполняем перебор правил обхождения с повтором ключа
	 */
	for(auto & rule : vector <pair <json::duplicate_t, string>> {
		// Берётся последнее встреченное значение
		{json::duplicate_t::LAST, "99"},
		// Берётся первое встреченное значение
		{json::duplicate_t::FIRST, "3"}
	}){
		// Собираемый текст документа
		string text("{");
		/**
		 * Выполняем сборку вместилища, превышающего порог отображения имён
		 */
		for(uint32_t i = 0; i < 24; i++){
			// Выполняем добавление отделителя полей
			if(i > 0)
				// Выполняем добавление запятой
				text.append(",");
			// Выполняем добавление очередного поля вместилища
			text.append("\"k").append(to_string(i)).append("\":").append(to_string(i));
		}
		// Выполняем добавление поля, имя какого уже занято
		text.append(",\"k3\":99}");
		// Объект дерева документа
		json::document_t document(::logger());
		// Настройки дерева документа
		json::document_t::settings_t settings;
		// Устанавливаем правило обхождения с повтором ключа
		settings.duplicates = rule.first;
		// Устанавливаем настройки дерева документа
		document.settings(settings);
		// Выполняем разбор текста документа
		ASSERT_TRUE(document.parse(text)) << rule.second;
		// Выполняем проверку числа полей вместилища без повтора
		ASSERT_EQ(document.root().size(), static_cast <size_t> (24)) << rule.second;
		// Выполняем проверку выбранного правилом значения
		ASSERT_EQ(document.root().at("/k3").raw(), rule.second) << rule.second;
	}
	/**
	 * Повтор ключа отвергается правилом по умолчанию
	 */
	{
		// Объект дерева документа
		json::document_t document(::logger());
		// Выполняем проверку отказа разбора текста с повтором ключа
		ASSERT_FALSE(document.parse("{\"a\":1,\"a\":2}"));
	}
}

