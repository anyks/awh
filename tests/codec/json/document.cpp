/**
 * @brief Проверка независимости оборота числа от режима округления
 *
 * @details Режим округления ставит ПОТРЕБИТЕЛЬ библиотеки, и кодек обязан отдавать один
 * итог при любом из четырёх: библиотека не вправе молча требовать себе умолчательного
 * режима. Довод этот отдельной проверки прежде не имел, а проверять его попутно нечем -
 * весь набор гоняется в одном режиме, и зависимость прошла бы незамеченной
 *
 * @note Замер 01.09.2026 по шести числам и четырём режимам: разбор и запись дают один
 *       текст всюду. Проверка закрепляет измеренное
 *
 * @warning Проба ЗРЯЧЕСТИ обязательна и стоит внутри перебора: режим, не легший, дал бы
 *          то же зелёное, ничего не измерив. Контрольное число «1e-50» видом одинарной
 *          точности при округлении ВВЕРХ уцелевает, а при прочих режимах исчезает, - им
 *          и доказывается, что настройка легла
 */
TEST(CodecJsonDocument, NumberRoundTripIsDeafToTheRoundingMode) {
	/**
	 * @brief Сторож режима округления
	 *
	 * @details Режим округления - настройка ПРОЦЕССА, и снимать её обязательно: всякий
	 * «ASSERT_*» уходит из проверки возвратом, и строка возврата режима в конце тела не
	 * исполнилась бы вовсе. Отказ здесь отравил бы ОСТАТОК прогона, а отказы те легли бы
	 * на проверки соседние, ни в чём не повинные
	 *
	 * @note Довод и устройство взяты у сторожа предела размера файла в этом же наборе:
	 *       правило одно на всякую настройку процесса, какой проверка касается
	 *
	 */
	struct Guard {
		// Прежний режим округления
		int mode;
		/**
		 * @brief Конструктор
		 *
		 */
		Guard() noexcept : mode(::fegetround()) {}
		/**
		 * @brief Деструктор
		 *
		 */
		~Guard() noexcept {
			// Выполняем возврат прежнего режима округления
			::fesetround(this->mode);
		}
	} guard;
	// Проверяемые режимы округления
	const int modes[] = {FE_TONEAREST, FE_UPWARD, FE_DOWNWARD, FE_TOWARDZERO};
	// Разбираемый текст документа с числами, к округлению чувствительными
	const string text = "[0.1,1e300,1e-300,9007199254740993,3.141592653589793,2.2250738585072014e-308]";
	// Эталонный текст, снятый умолчательным режимом округления
	string standard = "";
	// Признак того, что хотя бы один режим изменил исход контрольного числа
	bool sighted = false;
	/**
	 * Выполняем перебор всех проверяемых режимов округления
	 */
	for(const int mode : modes){
		// Выполняем установку очередного режима округления
		::fesetround(mode);
		// Выполняем проверку того, что режим округления лёг
		ASSERT_EQ(::fegetround(), mode);
		// Контрольное число, к режиму округления чувствительное
		volatile double control = 1e-50;
		/**
		 * Если контрольное число видом одинарной точности уцелело
		 */
		if(static_cast <float> (control) != 0.f)
			// Запоминаем признак того, что режим исход меняет
			sighted = true;
		// Документ дерева для разбора текста
		json::document_t document(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(document.parse(text));
		// Получаем текст записи разобранного документа
		const string result = document.dump();
		/**
		 * Если эталонный текст ещё не снят
		 */
		if(standard.empty())
			// Запоминаем эталонный текст записи
			standard = result;
		// Выполняем сличение текста записи с эталонным
		else EXPECT_EQ(result, standard);
	}
	// Выполняем проверку зрячести: хотя бы один режим обязан менять исход
	ASSERT_TRUE(sighted) << "ни один режим округления исхода не изменил: замер пуст";
}
/**
 * @brief Проверка согласия размаха поддерева со сносом повторяющихся полей
 *
 * @details Размах поддерева вместилища связан с числом узлов под ним, и связь эту заводят
 * НЕСКОЛЬКО путей записи: сборка дерева разбором, снос повторяющегося поля объекта и
 * пересадка значения. Снос уменьшает размах лишь у НЕПОСРЕДСТВЕННОГО родителя, а не у
 * всех предков выше, - и это верно ровно потому, что идёт он при закрытии самого объекта,
 * когда предки ещё открыты: размах их выставится позже, а номер заводимого узла берётся
 * от «_nodes.size()» заново на каждом событии, и снос его уже уменьшил
 *
 * @note Довод этот держится ПОРЯДКОМ событий, а не свойством кода на месте, и оттого
 *       хрупок: снос, перенесённый к концу разбора либо к отдельному проходу, оставил бы
 *       предкам размах завышенный, и обход захватил бы чужие узлы. Проверка эта стоит
 *       здесь ради такой будущей правки, а не ради нынешнего состояния
 *
 * @warning Сличается с ЛИТЕРАЛОМ, а не с итогом второго разбора: сличение оборота с самим
 *          собою прошло бы и у дерева, испорченного одинаково на обоих концах
 */
TEST(CodecJsonDocument, SubtreeExtentSurvivesDuplicateRemovalAtEveryDepth) {
	/**
	 * @brief Разбор текста с заданным правилом обращения с повторами
	 *
	 * @param text  разбираемый текст документа
	 * @param rule  правило обращения с повторяющимся именем поля
	 * @return      текст записи разобранного документа
	 *
	 */
	const auto rewrite = [](const string & text, const json::duplicate_t rule) noexcept -> string {
		// Документ дерева для разбора текста
		json::document_t document(::logger());
		// Получаем настройки документа
		auto settings = document.settings();
		// Устанавливаем правило обращения с повторяющимся именем поля
		settings.duplicates = rule;
		// Устанавливаем настройки документа
		document.settings(settings);
		/**
		 * Если разбор текста документа не удался
		 */
		if(!document.parse(text))
			// Выводим признак неудачного разбора
			return "<не разобрано>";
		// Выводим текст записи разобранного документа
		return document.dump();
	};
	/**
	 * Выполняем проверку сноса повтора у объекта верхнего уровня
	 */
	{
		// Выполняем проверку удержания первого поля объекта
		EXPECT_EQ(rewrite("{\"x\":1,\"x\":2}", json::duplicate_t::FIRST), "{\"x\":1}");
		// Выполняем проверку удержания последнего поля объекта
		EXPECT_EQ(rewrite("{\"x\":1,\"x\":2}", json::duplicate_t::LAST), "{\"x\":2}");
	}
	/**
	 * Выполняем проверку сноса повтора у объекта, вложенного в объект
	 *
	 * @note Половина существенная: снос идёт у внутреннего объекта, а размах внешнего
	 *       выставляется ПОСЛЕ него, и завышение его вылезло бы полем «b», из записи
	 *       пропавшим либо задвоенным
	 */
	{
		// Выполняем проверку удержания первого поля вложенного объекта
		EXPECT_EQ(rewrite("{\"a\":{\"x\":1,\"x\":2},\"b\":3}", json::duplicate_t::FIRST), "{\"a\":{\"x\":1},\"b\":3}");
		// Выполняем проверку удержания последнего поля вложенного объекта
		EXPECT_EQ(rewrite("{\"a\":{\"x\":1,\"x\":2},\"b\":3}", json::duplicate_t::LAST), "{\"a\":{\"x\":2},\"b\":3}");
	}
	/**
	 * Выполняем проверку сноса повтора у объекта, вложенного в массив
	 */
	{
		// Выполняем проверку удержания первого поля объекта внутри массива
		EXPECT_EQ(rewrite("[{\"x\":1,\"x\":2},7]", json::duplicate_t::FIRST), "[{\"x\":1},7]");
		// Выполняем проверку удержания последнего поля объекта внутри массива
		EXPECT_EQ(rewrite("[{\"x\":1,\"x\":2},7]", json::duplicate_t::LAST), "[{\"x\":2},7]");
	}
	/**
	 * Выполняем проверку сноса повтора на глубине двух вместилищ
	 *
	 * @note Глубина здесь и проверяется: размах правится у одного предка, а выставляется
	 *       у двух, и ошибка на одном уровне вылезла бы полем «c»
	 */
	{
		// Выполняем проверку удержания первого поля объекта на глубине двух вместилищ
		EXPECT_EQ(rewrite("{\"a\":{\"b\":{\"x\":1,\"x\":2}},\"c\":9}", json::duplicate_t::FIRST), "{\"a\":{\"b\":{\"x\":1}},\"c\":9}");
		// Выполняем проверку удержания последнего поля объекта на глубине двух вместилищ
		EXPECT_EQ(rewrite("{\"a\":{\"b\":{\"x\":1,\"x\":2}},\"c\":9}", json::duplicate_t::LAST), "{\"a\":{\"b\":{\"x\":2}},\"c\":9}");
	}
	/**
	 * Выполняем проверку сноса повтора у объекта внутри массива внутри объекта
	 */
	{
		// Выполняем проверку удержания первого поля объекта внутри массива внутри объекта
		EXPECT_EQ(rewrite("{\"a\":[{\"x\":1,\"x\":2}],\"b\":3}", json::duplicate_t::FIRST), "{\"a\":[{\"x\":1}],\"b\":3}");
		// Выполняем проверку удержания последнего поля объекта внутри массива внутри объекта
		EXPECT_EQ(rewrite("{\"a\":[{\"x\":1,\"x\":2}],\"b\":3}", json::duplicate_t::LAST), "{\"a\":[{\"x\":2}],\"b\":3}");
	}
	/**
	 * Выполняем проверку сноса нескольких повторов подряд у одного объекта
	 *
	 * @note Снос идёт с конца перечня к началу, и размах правится на каждом шаге; ошибка
	 *       накопления вылезла бы лишь при более чем одном сносе
	 */
	{
		// Выполняем проверку удержания первого поля объекта при трёх повторах
		EXPECT_EQ(rewrite("{\"a\":{\"x\":1,\"x\":2,\"x\":3},\"b\":4}", json::duplicate_t::FIRST), "{\"a\":{\"x\":1},\"b\":4}");
		// Выполняем проверку удержания последнего поля объекта при трёх повторах
		EXPECT_EQ(rewrite("{\"a\":{\"x\":1,\"x\":2,\"x\":3},\"b\":4}", json::duplicate_t::LAST), "{\"a\":{\"x\":3},\"b\":4}");
	}
	/**
	 * Выполняем проверку сноса повтора, самого бывшего вместилищем
	 *
	 * @note Размах сносимого поддерева здесь больше единицы, и уменьшение размаха родителя
	 *       на единицу вместо размаха вылезло бы именно тут
	 */
	{
		/**
		 * @warning Порядок написаний здесь ОБРАТНЫЙ тому, какой просится: сносимым обязано
		 *          быть именно ВМЕСТИЛИЩЕ, а правило удержания сносит противоположный конец.
		 *          Первая редакция проверки держала массив и сносила скаляр обоими
		 *          правилами, и щуп, уменьшавший размах на единицу вместо размаха
		 *          поддерева, не покрасил НИЧЕГО из шестнадцати сличений
		 */
		// Выполняем проверку сноса поля-вместилища при удержании первого поля
		EXPECT_EQ(rewrite("{\"a\":{\"x\":9,\"x\":[1,2,3]},\"b\":5}", json::duplicate_t::FIRST), "{\"a\":{\"x\":9},\"b\":5}");
		// Выполняем проверку сноса поля-вместилища при удержании последнего поля
		EXPECT_EQ(rewrite("{\"a\":{\"x\":[1,2,3],\"x\":9},\"b\":5}", json::duplicate_t::LAST), "{\"a\":{\"x\":9},\"b\":5}");
		// Выполняем проверку сноса поля-вместилища, вложенного глубже одного уровня
		EXPECT_EQ(rewrite("{\"a\":{\"x\":{\"y\":[1,2]},\"x\":9},\"b\":5}", json::duplicate_t::LAST), "{\"a\":{\"x\":9},\"b\":5}");
	}
}
/**
 * @brief Проверка правки дерева документа по указателю
 *
 * @details Ходы `set()`, `erase()` и `reset()` заведены общим набором у всех кодеков
 * рамки по заказу владельца о согласовании их между собой. Вид пути остаётся своим у
 * каждого кодека: у документа это указатель RFC 6901
 *
 * @note Проверка закрепляет и то, ради чего розыск вынесен в общее место: правка, снос
 *       и обращение к значению обязаны разыскивать по указателю ОДИНАКОВО. Прежде
 *       розыск жил у правки своим списком правил, а у обращения - своим, и сличены они
 *       не были ничем
 *
 * @note Сброс от сноса отличается сохранением МЕСТА: `null` есть законное значение
 *       стандарта, и отсутствию поля он не равен
 *
 */
TEST(CodecJsonDocument, PointerEditingSharesTheSearchWithLookup) {
	// Исходный текст документа
	const string text = "{\"a\":{\"b\":[10,20,30]},\"c\":1,\"d\":[{\"x\":1}]}";
	/**
	 * Указатели вместе с ожидаемыми записями после сноса значения
	 */
	const vector <pair <string, string>> removals = {
		{"/a/b/1", "{\"a\":{\"b\":[10,30]},\"c\":1,\"d\":[{\"x\":1}]}"},
		{"/c", "{\"a\":{\"b\":[10,20,30]},\"d\":[{\"x\":1}]}"},
		{"/a", "{\"c\":1,\"d\":[{\"x\":1}]}"},
		{"/d/0", "{\"a\":{\"b\":[10,20,30]},\"c\":1,\"d\":[]}"},
		{"/d/0/x", "{\"a\":{\"b\":[10,20,30]},\"c\":1,\"d\":[{}]}"}
	};
	/**
	 * Выполняем перебор всех сносимых указателей
	 */
	for(const auto & sample : removals){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Получаем счёт детей корня документа до сноса значения
		const size_t before = doc.root().size();
		// Выполняем снос значения по указателю
		ASSERT_TRUE(doc.erase(sample.first)) << sample.first;
		// Выполняем проверку записи документа после сноса значения
		ASSERT_EQ(doc.dump(), sample.second) << sample.first;
		/**
		 * Выполняем проверку счёта детей корня после сноса значения
		 *
		 * @note Счёт сличается ОТДЕЛЬНО от записи: обход детей идёт по размаху, а не по
		 *       счёту, и подмена, снявшая убавление счёта при сносе, записи не меняет
		 *       вовсе. Замер щупом: массив о двух значениях отчитывался тремя, а объект
		 *       о нуле полей - одним, тогда как запись обоих была верна
		 */
		ASSERT_EQ(doc.root().size(), (sample.first.find('/', 1) == string::npos) ? (before - 1) : before) << sample.first;
	}
	/**
	 * Выполняем проверку счёта детей вместилища после сноса значения из него
	 *
	 * @note Убавляется счёт лишь у НЕПОСРЕДСТВЕННОГО родителя: у предков дальше по
	 *       цепочке число детей не меняется, а размах меняется у всех
	 */
	{
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Выполняем проверку счёта значений массива до сноса
		ASSERT_EQ(doc.at("/a/b").size(), static_cast <size_t> (3));
		// Выполняем снос значения массива по указателю
		ASSERT_TRUE(doc.erase("/a/b/1"));
		// Выполняем проверку убавления счёта значений массива после сноса
		ASSERT_EQ(doc.at("/a/b").size(), static_cast <size_t> (2));
		// Выполняем проверку неизменности счёта детей у предка через уровень
		ASSERT_EQ(doc.at("/a").size(), static_cast <size_t> (1));
		// Выполняем проверку неизменности счёта детей корня документа
		ASSERT_EQ(doc.root().size(), static_cast <size_t> (3));
	}
	/**
	 * Указатели вместе с ожидаемыми записями после сброса значения
	 */
	const vector <pair <string, string>> resets = {
		{"/a/b/1", "{\"a\":{\"b\":[10,null,30]},\"c\":1,\"d\":[{\"x\":1}]}"},
		{"/c", "{\"a\":{\"b\":[10,20,30]},\"c\":null,\"d\":[{\"x\":1}]}"},
		{"/a", "{\"a\":null,\"c\":1,\"d\":[{\"x\":1}]}"},
		{"/d/0", "{\"a\":{\"b\":[10,20,30]},\"c\":1,\"d\":[null]}"},
		{"", "null"}
	};
	/**
	 * Выполняем перебор всех сбрасываемых указателей
	 */
	for(const auto & sample : resets){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Выполняем сброс значения по указателю
		ASSERT_TRUE(doc.reset(sample.first)) << sample.first;
		// Выполняем проверку записи документа после сброса значения
		ASSERT_EQ(doc.dump(), sample.second) << sample.first;
	}
	/**
	 * Выполняем проверку отказа сноса корня дерева документа
	 *
	 * @note Снос корня отвергается, а сброс его дозволен: дерево без корня значением не
	 *       является вовсе, тогда как `null` - значение законное. Различие это намеренное
	 */
	{
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Выполняем проверку отказа сноса корня дерева документа
		ASSERT_FALSE(doc.erase(""));
		// Выполняем проверку неизменности документа после отказа сноса
		ASSERT_EQ(doc.dump(), text);
	}
	/**
	 * Выполняем сличение розыска правкой, сносом и обращением к значению
	 *
	 * @note Сличаются ТРИ хода на одних и тех же указателях: расхождение розысков
	 *       невидимо изнутри всякого из них, и увидеть его можно лишь сличением
	 */
	{
		// Указатели, к значениям документа не ведущие
		const vector <string> absent = {
			"/a/b/3", "/a/b/-", "/a/b/00", "/a/b/+1", "/c~d", "/нет", "/a/нет", "a", "/a/b/0/x"
		};
		/**
		 * Выполняем перебор всех указателей, к значениям не ведущих
		 */
		for(const auto & pointer : absent){
			// Объект документа
			json::document_t doc(::logger());
			// Выполняем разбор текста документа
			ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
			// Владеющее значение, устанавливаемое правкой
			json::value_t value(static_cast <int64_t> (7));
			// Выполняем проверку непригодности значения, разысканного обращением
			ASSERT_FALSE(doc.at(pointer).valid()) << pointer;
			// Выполняем проверку отказа правки по указателю
			ASSERT_FALSE(doc.set(pointer, value)) << pointer;
			// Выполняем проверку отказа сноса по указателю
			ASSERT_FALSE(doc.erase(pointer)) << pointer;
			// Выполняем проверку отказа сброса по указателю
			ASSERT_FALSE(doc.reset(pointer)) << pointer;
		}
		/**
		 * Указатели, к значениям документа ведущие
		 */
		const vector <string> present = {"/a", "/a/b", "/a/b/0", "/a/b/2", "/c", "/d/0/x"};
		/**
		 * Выполняем перебор всех указателей, к значениям ведущих
		 */
		for(const auto & pointer : present){
			// Объект документа
			json::document_t doc(::logger());
			// Выполняем разбор текста документа
			ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
			// Выполняем проверку пригодности значения, разысканного обращением
			ASSERT_TRUE(doc.at(pointer).valid()) << pointer;
			// Выполняем проверку успешности сброса по указателю
			ASSERT_TRUE(doc.reset(pointer)) << pointer;
			// Объект документа для сноса значения
			json::document_t removed(::logger());
			// Выполняем разбор текста документа
			ASSERT_TRUE(removed.parse(text)) << json::message(removed.error());
			// Выполняем проверку успешности сноса по указателю
			ASSERT_TRUE(removed.erase(pointer)) << pointer;
		}
	}
	/**
	 * Выполняем проверку того, что устаревшее имя правки осталось посредником
	 *
	 * @note Имя `graft` оставлено ради потребителей, написанных прежде согласования
	 *       кодеков рамки между собой, и обязано вести к той же самой работе
	 */
	{
		// Объект документа, правимого устаревшим именем
		json::document_t deprecated(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(deprecated.parse(text)) << json::message(deprecated.error());
		// Владеющее значение, устанавливаемое правкой
		json::value_t value(static_cast <int64_t> (7));
		// Выполняем правку дерева устаревшим именем
		ASSERT_TRUE(deprecated.graft("/c", value));
		// Объект документа, правимого общим именем
		json::document_t renamed(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(renamed.parse(text)) << json::message(renamed.error());
		// Выполняем правку дерева общим именем
		ASSERT_TRUE(renamed.set("/c", value));
		// Выполняем проверку совпадения записей обоих документов
		ASSERT_EQ(deprecated.dump(), renamed.dump());
	}
}
/**
 * @brief Проверка обесценивания отображения имён полей правкой дерева
 *
 * @details Розыск поля объекта по имени идёт перебором, покуда полей немного, а свыше
 * порога заводится отображение имён в номера узлов. Отображение это правку дерева
 * пережить не может: снос и правка сдвигают номера узлов и хранилище знаков, и
 * пережившее их отображение отвечало бы номером чужого узла
 *
 * @note Проверка ведётся на объекте о ДВАДЦАТИ полях намеренно: при меньшем числе
 *       отображение не заводится вовсе, и всякая подмена его сброса выходит безвредной.
 *       Замер щупом: на объекте о трёх полях снятие сброса исход НЕ меняло, и проверка
 *       по такому объекту сторожила бы пустоту
 *
 * @note Отображение заводится ЛЕНИВО, первым же розыском по имени, - оттого проверка
 *       и прогревает его розыском до правки. Без прогрева отображения нет, и сбрасывать
 *       нечего
 *
 */
TEST(CodecJsonDocument, NameIndexDoesNotSurviveTreeEditing) {
	/**
	 * Собираем текст документа с объектом свыше порога заведения отображения
	 */
	string text = "{";
	/**
	 * Выполняем перебор всех заводимых полей объекта
	 */
	for(uint32_t i = 0; i < 20; i++){
		// Добавляем разделитель полей объекта
		if(i > 0)
			// Выполняем добавление разделителя полей объекта
			text.append(1, ',');
		// Добавляем очередное поле объекта
		text.append("\"k").append(std::to_string(i)).append("\":").append(std::to_string(i));
	}
	// Завершаем текст документа
	text.append(1, '}');
	/**
	 * Снимаемые имена полей объекта: первое, среднее и последнее
	 */
	for(const string & name : {string("k0"), string("k5"), string("k19")}){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		/**
		 * Выполняем прогрев отображения имён полей объекта
		 *
		 * @note Прогрев обязателен: отображение заводится лишь первым розыском по имени,
		 *       и без него сбрасывать было бы нечего
		 */
		ASSERT_TRUE(doc.root()["k7"].valid());
		// Выполняем снос поля объекта по указателю
		ASSERT_TRUE(doc.erase("/" + name)) << name;
		// Выполняем проверку убавления счёта полей объекта
		ASSERT_EQ(doc.root().size(), static_cast <size_t> (19)) << name;
		// Выполняем проверку отсутствия снесённого поля розыском по имени
		ASSERT_FALSE(doc.root()[name].valid()) << name;
		// Выполняем проверку отсутствия снесённого поля розыском по указателю
		ASSERT_FALSE(doc.has("/" + name)) << name;
		// Выполняем проверку сохранности уцелевшего поля розыском по имени
		ASSERT_TRUE(doc.root()["k7"].valid()) << name;
	}
	/**
	 * Выполняем проверку обесценивания отображения правкой значения
	 */
	{
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Выполняем прогрев отображения имён полей объекта
		ASSERT_TRUE(doc.root()["k7"].valid());
		/**
		 * Владеющее значение, устанавливаемое правкой
		 *
		 * @note Ставится ВМЕСТИЛИЩЕ, а не число: правка скаляра скаляром размаха
		 *       поддерева не меняет, номера узлов за ним остаются прежними, и
		 *       отображение имён переживает такую правку без вреда. Замер щупом:
		 *       подмена сброса отображения при правке числом на число НЕ ловилась
		 */
		json::value_t value(::logger());
		// Выполняем разбор текста устанавливаемого значения
		ASSERT_TRUE(value.parse("[1,2,3,4,5]")) << json::message(value.error());
		// Выполняем правку значения поля объекта по указателю
		ASSERT_TRUE(doc.set("/k7", value));
		/**
		 * Выполняем перебор всех полей объекта, лежащих за правленым
		 *
		 * @note Сличаются поля ЗА правленым: правка сдвинула номера узлов ровно им, и
		 *       пережившее её отображение отвечало бы номером чужого узла
		 */
		for(uint32_t i = 8; i < 20; i++){
			// Получаем имя очередного поля объекта
			const string name = (string("k") + std::to_string(i));
			// Извлекаемое значение поля объекта
			int64_t result = 0;
			// Выполняем извлечение значения поля розыском по имени
			ASSERT_TRUE(doc.root()[name].value(result)) << name;
			// Выполняем проверку совпадения извлечённого значения с исходным
			ASSERT_EQ(result, static_cast <int64_t> (i)) << name;
		}
		// Выполняем проверку счёта значений правленого поля розыском по имени
		ASSERT_EQ(doc.root()["k7"].size(), static_cast <size_t> (5));
	}
}
/**
 * @brief Проверка обесценивания снятых значений всякой правкой дерева
 *
 * @details Значение, снятое с дерева до правки, обязано обращаться в НЕПРИГОДНОЕ:
 * правка сдвигает нумерацию узлов и пополняет хранилище знаков, и значение прежнего
 * поколения отдавало бы содержимое чужого узла. Стережёт это клеймо поколения дерева
 *
 * @note Договор записан в заголовке при всякой правке, а сторожим был лишь у одной:
 *       снятие наращивания клейма у `erase` набор пропускал МОЛЧА, у `set` ловил.
 *       Вскрыто подменою 03.09.2026
 *
 * @warning Значение берётся у СОСЕДА правимого места: снесённое непригодно и без
 *          клейма, и проверка по нему сторожила бы пустоту
 *
 */
TEST(CodecJsonDocument, EditingInvalidatesTheValuesTakenBefore) {
	// Исходный текст документа
	const string text = "{\"a\":\"первое\",\"b\":1}";
	/**
	 * Выполняем перебор всех правок дерева документа
	 */
	for(uint8_t operation = 0; operation < 3; operation++){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(text)) << json::message(doc.error());
		// Снимаем значение соседа правимого места
		const json::document_t::value_t value = doc.at("/a");
		// Выполняем проверку пригодности снятого значения до правки
		ASSERT_TRUE(value.valid()) << static_cast <uint32_t> (operation);
		// Выполняем правку дерева документа выбранным ходом
		switch(operation){
			/**
			 * Выполняем правку значения по указателю
			 */
			case 0: {
				// Владеющее значение, устанавливаемое правкой
				json::value_t replacement(static_cast <int64_t> (7));
				// Выполняем правку дерева документа по указателю
				ASSERT_TRUE(doc.set("/b", replacement));
			} break;
			// Выполняем снос значения по указателю
			case 1: ASSERT_TRUE(doc.erase("/b")); break;
			// Выполняем сброс значения по указателю
			case 2: ASSERT_TRUE(doc.reset("/b")); break;
		}
		// Выполняем проверку обесценивания снятого значения правкой
		ASSERT_FALSE(value.valid()) << static_cast <uint32_t> (operation);
	}
}
