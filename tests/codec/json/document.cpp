/**
 * @brief Проверка границы вида `EXTENDED`
 *
 * @details Невместимость числа в родной вид решается ВЕЛИЧИНОЙ его, а не длиной записи:
 * переполнение порядка да исчезновение его дают `EXTENDED`, а длинное дробное величиною
 * в двойную точность укладывается и получает вид `DOUBLE`, теряя лишние разряды.
 * Длина записи не решает и того, дробным какой точности хранить: `1.0000000000000000000000000000001`
 * значением своим есть ровно единица и хранится одинарной точностью
 *
 * @note Проверка эта заведена оттого, что описание вида обещало `EXTENDED` всякой записи
 *       «с точностью выше `double`», чего код не делал вовсе. Описание исправлено, а
 *       проверка не даёт обещанию разойтись с поведением заново
 *
 */
TEST(CodecJsonDocument, ExtendedIsDecidedByMagnitudeNotByLength) {
	/**
	 * Записи, невместимые в родной вид по величине своей
	 */
	const vector <string> extended = {
		"1e400", "-1e400", "1.7976931348623157e309", "0.1e-400",
		"18446744073709551616", "123456789012345678901234567890",
		"-9223372036854775809"
	};
	/**
	 * Выполняем перебор всех записей, невместимых по величине
	 */
	for(const auto & sample : extended){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(sample)) << sample << ": " << json::message(doc.error());
		// Выполняем проверку получения видом невместимого числа
		ASSERT_EQ(doc.root().type(), json::type_t::EXTENDED) << sample << ": " << json::name(doc.root().type());
	}
	/**
	 * Длинные дробные записи вместе с выдачей их после разбора
	 *
	 * @note Ожидаемая выдача записана литералом: она есть кратчайшая запись того же
	 *       значения двойной точности, и лишние разряды подачи в ней отсутствуют
	 */
	const vector <pair <string, string>> shortened = {
		{"0.30000000000000004440892098500626", "0.30000000000000004"},
		{"0.1000000000000000055511151231257827", "0.1"},
		{"2.7182818284590452353602874713527", "2.718281828459045"}
	};
	/**
	 * Выполняем перебор всех длинных дробных записей
	 */
	for(const auto & sample : shortened){
		// Объект документа
		json::document_t doc(::logger());
		// Выполняем разбор текста документа
		ASSERT_TRUE(doc.parse(sample.first)) << sample.first << ": " << json::message(doc.error());
		// Выполняем проверку укладывания длинного дробного в двойную точность
		ASSERT_EQ(doc.root().type(), json::type_t::DOUBLE) << sample.first << ": " << json::name(doc.root().type());
		// Выполняем проверку потери лишних разрядов подачи
		ASSERT_EQ(doc.dump(), sample.second) << sample.first;
	}
}
