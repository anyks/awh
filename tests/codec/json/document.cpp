/**
 * @brief Проверка потоковой выдачи значений разбираемого текста
 *
 * @details Документ при этом не заполняется вовсе: обработчику выдаётся очередное
 * значение верхнего уровня, а память под него переиспользуется
 *
 */
TEST(CodecJsonDocument, Streaming) {
	// Объект документа
	json::document_t doc(::logger());
	// Получаем настройки документа
	json::document_t::settings_t settings = doc.settings();
	// Разрешаем разбор потока документов
	settings.reader.stream = true;
	// Выполняем установку настроек документа
	doc.settings(settings);
	// Собранные виды корневых значений потока
	vector <string> kinds;
	// Выполняем потоковую выдачу значений разбираемого текста
	ASSERT_TRUE(doc.parse("{\"a\":1}\n[2,3]\n\"хвост\"", [&kinds](const json::document_t::value_t & value) noexcept -> bool {
		// Выполняем добавление вида очередного корневого значения к собранным
		kinds.push_back(json::name(value.kind()));
		// Выводим признак продолжения разбора
		return true;
	})) << json::message(doc.error());
	// Выполняем проверку количества выданных корневых значений
	ASSERT_EQ(kinds.size(), 3u);
	// Выполняем проверку вида первого выданного корневого значения
	ASSERT_EQ(kinds[0], "object");
	// Выполняем проверку вида второго выданного корневого значения
	ASSERT_EQ(kinds[1], "array");
	// Выполняем проверку вида третьего выданного корневого значения
	ASSERT_EQ(kinds[2], "string");
	// Выполняем проверку того, что документ потоком не заполнялся
	ASSERT_TRUE(doc.empty());
	// Количество выданных обработчику корневых значений
	size_t count = 0;
	// Выполняем потоковую выдачу значений с прекращением разбора обработчиком
	ASSERT_FALSE(doc.parse("{\"a\":1}\n[2,3]\n\"хвост\"", [&count](const json::document_t::value_t &) noexcept -> bool {
		// Увеличиваем количество выданных корневых значений
		count++;
		// Выводим признак прекращения разбора
		return false;
	}));
	// Выполняем проверку прекращения разбора первым же значением
	ASSERT_EQ(count, 1u);
}
