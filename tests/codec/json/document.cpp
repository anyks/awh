/**
 * @brief Проверка извлечения числа всяким видом независимо от вида хранения
 *
 * @details Вид хранения извлечению не указ: число, хранимое видом `INT8`, извлекается
 * и как `double`, и как `uint64_t`. Отказом извлечение завершается лишь тогда, когда
 * узел числом не является вовсе
 *
 * @note Проверка эта закрепляет намеренное решение не отвергать извлечение по
 *       непомещаемости: отказ по величине заставлял бы потребителя гадать вид, а
 *       падение на нём - и вовсе недопустимо
 *
 */
TEST(CodecJsonDocument, ValueConversions) {
	// Объект документа
	json::document_t doc(::logger());
	// Выполняем разбор текста документа
	ASSERT_TRUE(doc.parse("[7,-7,3502.3453,1e300,\"текст\"]")) << json::message(doc.error());
	// Извлекаемое число видом в один байт со знаком
	int8_t small = 0;
	// Извлекаемое число видом в восемь байтов без знака
	uint64_t large = 0;
	// Извлекаемое дробное число
	double real = 0.;
	// Выполняем проверку извлечения числа вида `UINT8` видом `int8_t`
	ASSERT_TRUE(doc[static_cast <size_t> (0)].value(small));
	// Выполняем проверку извлечённого значения
	ASSERT_EQ(small, static_cast <int8_t> (7));
	// Выполняем проверку извлечения числа вида `UINT8` дробным видом
	ASSERT_TRUE(doc[static_cast <size_t> (0)].value(real));
	// Выполняем проверку извлечённого значения
	ASSERT_DOUBLE_EQ(real, 7.);
	// Выполняем проверку извлечения числа вида `INT8` видом без знака
	ASSERT_TRUE(doc[static_cast <size_t> (1)].value(large));
	// Выполняем проверку приведения отрицательного числа к виду без знака
	ASSERT_EQ(large, static_cast <uint64_t> (static_cast <int64_t> (-7)));
	// Извлекаемое число видом в два байта со знаком
	int16_t medium = 0;
	/**
	 * Выполняем проверку извлечения дробного числа целым видом в два байта
	 *
	 * @note Число `3502.3453` в два байта помещается: усекается лишь дробная часть
	 */
	ASSERT_TRUE(doc[static_cast <size_t> (2)].value(medium));
	// Выполняем проверку усечения дробной части числа
	ASSERT_EQ(medium, static_cast <int16_t> (3502));
	// Извлекаемое число видом в четыре байта со знаком
	int32_t wide = 0;
	/**
	 * Выполняем проверку извлечения дробного числа, в целый вид не вмещающегося
	 *
	 * @note Стандарт зовёт такое приведение неопределённым поведением, а мы выдаём
	 *       предел затребованного вида: неопределённого поведения в кодеке не будет
	 */
	ASSERT_TRUE(doc[static_cast <size_t> (3)].value(wide));
	// Выполняем проверку насыщения пределом затребованного вида
	ASSERT_EQ(wide, ::std::numeric_limits <int32_t>::max());
	// Выполняем проверку отказа извлечения строки числовым видом
	ASSERT_FALSE(doc[static_cast <size_t> (4)].value(large));
}
