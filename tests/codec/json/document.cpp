/**
 * @brief Проверка правила отклонения чисел, родным видом не представимых
 *
 * @details Правило `CHECK` отвергает всякое число, не вместившееся ни в один родной
 * вид, - и переполнившее двойную точность, и исчерпавшее её снизу, и целое свыше
 * `2^64`. Правило `NATIVE` принимает их все, храня записью
 *
 * @note Проверка эта закрепляет намеренное решение: правило это отвечает на вопрос
 *       «представимо ли всякое число документа родным видом», а не на вопрос
 *       «конечно ли оно». Потребитель, кладущий числа в родные хранилища, обязан
 *       узнать о непредставимом числе при разборе, а не при извлечении
 *
 */
TEST(CodecJsonDocument, NumberCheckRule) {
	/**
	 * Записи чисел, родным видом не представимых
	 */
	const vector <string> samples = {
		"[1e400]", "[-1e400]", "[1e-400]", "[18446744073709551616]", "[-18446744073709551617]"
	};
	/**
	 * Выполняем перебор всех записей чисел
	 */
	for(const auto & sample : samples){
		// Объект документа
		json::document_t doc(::logger());
		// Получаем настройки документа
		json::document_t::settings_t settings = doc.settings();
		// Устанавливаем правило отклонения чисел, родным видом не представимых
		settings.numbers = json::number_t::CHECK;
		// Выполняем установку настроек документа
		doc.settings(settings);
		// Выполняем проверку отклонения числа, родным видом не представимого
		ASSERT_FALSE(doc.parse(sample)) << sample;
		// Выполняем проверку кода отказа разбора
		ASSERT_EQ(doc.error(), json::error_t::NUMBER_OUT_OF_RANGE) << sample;
		// Устанавливаем правило хранения таких чисел записью
		settings.numbers = json::number_t::NATIVE;
		// Выполняем установку настроек документа
		doc.settings(settings);
		// Выполняем проверку принятия числа при хранении записью
		ASSERT_TRUE(doc.parse(sample)) << sample << ": " << json::message(doc.error());
		// Выполняем проверку вида принятого числа
		ASSERT_TRUE(doc[static_cast <size_t> (0)].is(json::type_t::EXTENDED)) << sample;
		// Выполняем проверку сохранности записи числа
		ASSERT_EQ(doc.dump(), sample) << sample;
	}
	/**
	 * Записи чисел, родным видом представимых
	 */
	const vector <string> allowed = {"[1e308]", "[-1e308]", "[0.1]", "[18446744073709551615]"};
	/**
	 * Выполняем перебор всех записей чисел
	 */
	for(const auto & sample : allowed){
		// Объект документа
		json::document_t doc(::logger());
		// Получаем настройки документа
		json::document_t::settings_t settings = doc.settings();
		// Устанавливаем правило отклонения чисел, родным видом не представимых
		settings.numbers = json::number_t::CHECK;
		// Выполняем установку настроек документа
		doc.settings(settings);
		// Выполняем проверку принятия представимого числа
		ASSERT_TRUE(doc.parse(sample)) << sample << ": " << json::message(doc.error());
	}
}
