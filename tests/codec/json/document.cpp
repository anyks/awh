/**
 * @brief Проверка доклада об отказе записи файла документа
 *
 * @details Поток сбрасывает свой буфер разрушением своим, то есть уже после вычисления
 * возвращаемого значения: текст, целиком уместившийся в буфер, уходил отказом сброса
 * молча, а вызов отчитывался успехом. Запись обязана закрывать файл ЯВНО и отчитываться
 * по исходу закрытия
 *
 * @note Код отказа уходит в журнал, а не в `error()`: запись объявлена `const`, и
 *       селить в ней код отказа некуда
 *
 */
TEST(CodecJsonDocument, WriteFailureIsNotSuccess) {
	// Собираемые сообщения журнала
	vector <string> messages;
	// Объект журнала с перехватом вывода
	awh::log_t log(&Silent::framework());
	// Выполняем назначение приёмника вывода в функцию обратного вызова
	log.mode({awh::log_t::mode_t::DEFERRED});
	// Выполняем назначение перехвата сообщений журнала
	log.subscribe([&messages](const awh::log_t::flag_t, string_view text) noexcept -> void {
		// Выполняем сбор очередного сообщения журнала
		messages.push_back(string(text));
	});
	// Собираемый текст документа
	string text("[");
	/**
	 * Выполняем сборку текста документа крупнее допустимого предела
	 */
	for(uint16_t i = 0; i < 100; i++){
		// Если значение документа не первое, добавляем разделитель значений
		if(i > 0)
			// Добавляем разделитель значений документа
			text.append(",");
		// Добавляем очередное значение документа
		text.append("1234567890");
	}
	// Завершаем сборку текста документа
	text.append("]");
	// Дерево значений документа
	json::document_t document(&log);
	// Выполняем проверку разбора собранного текста документа
	ASSERT_TRUE(document.parse(text));
/**
 * Для систем, не являющихся MS Windows
 */
#if !defined(_WIN32) && !defined(_WIN64)
	/**
	 * @brief Сторож предельного размера файла процесса
	 *
	 * @note Предел этот - настройка ПРОЦЕССА, и снимать её обязательно: оставленная,
	 *       она валила бы соседние проверки, пишущие файлы
	 *
	 */
	struct Guard {
		// Прежний предел размера файла процесса
		struct rlimit limit;
		// Прежний обработчик сигнала превышения предела
		void (* handler)(int32_t);
		/**
		 * @brief Конструктор
		 *
		 */
		Guard() noexcept {
			// Выполняем снятие прежнего предела размера файла
			::getrlimit(RLIMIT_FSIZE, &this->limit);
			// Выполняем отключение сигнала превышения предела
			this->handler = ::signal(SIGXFSZ, SIG_IGN);
			// Предел размера файла, заведомо меньший текста документа
			struct rlimit bound = this->limit;
			// Выполняем установку предела размера файла
			bound.rlim_cur = 512;
			// Выполняем назначение предела размера файла процессу
			::setrlimit(RLIMIT_FSIZE, &bound);
		}
		/**
		 * @brief Деструктор
		 *
		 */
		~Guard() noexcept {
			// Выполняем возврат прежнего предела размера файла
			::setrlimit(RLIMIT_FSIZE, &this->limit);
			// Выполняем возврат прежнего обработчика сигнала
			::signal(SIGXFSZ, this->handler);
		}
	} guard;
	// Адрес файла, в который ведётся запись документа
	const string filename = "./awh-codec-json-write-failure.json";
/**
 * Для операционной системы MS Windows
 */
#else
	/**
	 * Отказ записи добывается НЕПРИГОДНЫМ ПУТЁМ, а не пределом размера файла
	 *
	 * @details Предела `RLIMIT_FSIZE` у MS Windows нет вовсе, и повторить им усечённую
	 *          запись нельзя. Отступить же здесь молча означало бы отменить проверку:
	 *          отступающая проверка выглядит пройденной. Оттого берётся путь в
	 *          несуществующем каталоге - запись по нему отвечает отказом достоверно,
	 *          и оглашение отказа в журнале проверяется тем же утверждением
	 *
	 * @warning Проверяется при этом ИНОЙ путь отказа: у POSIX запись начинается и
	 *          обрывается пределом, здесь же не удаётся само заведение файла. Общим
	 *          остаётся требуемое - отказ обязан быть оглашён, а не проглочен
	 */
	const string filename = "./awh-nonexistent-directory/write-failure.json";
#endif
	// Выполняем снос прежнего файла документа
	::remove(filename.c_str());
	// Выполняем проверку отказа записи усечённого файла документа
	ASSERT_FALSE(document.save(filename));
	// Выполняем проверку оглашения отказа в журнале
	ASSERT_FALSE(messages.empty());
	/**
	 * Выполняем проверку упоминания причины отказа в сообщении
	 *
	 * @note Код причины у систем РАЗНЫЙ, и это не послабление: у POSIX запись
	 *       начинается и обрывается пределом размера файла, оттого причиной служит
	 *       FILE_NOT_WRITTEN; у MS Windows предела такого нет, отказ добывается
	 *       непригодным путём, и не удаётся само заведение файла - FILE_NOT_OPENED.
	 *       Требуемое же у обеих систем одно и то же и проверяется одинаково строго:
	 *       отказ обязан быть ОГЛАШЁН, а не проглочен молча
	 */
	#if !defined(_WIN32) && !defined(_WIN64)
		// Выполняем проверку упоминания причины обрыва записи
		ASSERT_NE(messages.back().find(json::message(json::error_t::FILE_NOT_WRITTEN)), string::npos) << messages.back();
	#else
		// Выполняем проверку упоминания причины невозможности завести файл
		ASSERT_NE(messages.back().find(json::message(json::error_t::FILE_NOT_OPENED)), string::npos) << messages.back();
	#endif
	// Выполняем снос усечённого файла документа
	::remove(filename.c_str());
}

/**
 * @brief Проверка кругового хода дерева, разобранного с удержанием повторов
 *
 * @details Дерево, разобранное правилом `KEEP`, записывается повторами, а умолчательное
 * правило `ERROR` такой текст отвергает: круговой ход через умолчания на нём рвётся.
 * Проверка закрепляет обе половины - и что повторы в записи сохраняются, и что читать
 * их надлежит правилом, повторы допускающим
 *
 */
TEST(CodecJsonDocument, KeptDuplicatesNeedMatchingRule) {
	// Разбираемый текст документа с повторяющимся именем поля
	const string text = "{\"a\":1,\"a\":2}";
	// Дерево значений документа, удерживающее повторы
	json::document_t keeping(::logger());
	// Настройки разбора с удержанием повторов
	json::document_t::settings_t settings = keeping.settings();
	// Устанавливаем правило удержания повторяющихся имён
	settings.duplicates = json::duplicate_t::KEEP;
	// Выполняем установку настроек разбора
	keeping.settings(settings);
	// Выполняем проверку разбора текста с удержанием повторов
	ASSERT_TRUE(keeping.parse(text));
	// Записанный текст документа с удержанными повторами
	const string written = keeping.dump();
	// Выполняем проверку сохранности повторов в записи
	ASSERT_EQ(written, text);
	/**
	 * Выполняем проверку отказа чтения записанного текста умолчательным правилом
	 */
	{
		// Дерево значений документа с умолчательными настройками
		json::document_t plain(::logger());
		// Выполняем проверку отказа разбора записанного текста
		ASSERT_FALSE(plain.parse(written));
		// Выполняем проверку кода отказа разбора
		ASSERT_EQ(plain.error(), json::error_t::DUPLICATE_KEY);
	}
	/**
	 * Выполняем проверку чтения записанного текста правилом, повторы допускающим
	 */
	{
		// Дерево значений документа, удерживающее повторы
		json::document_t again(::logger());
		// Выполняем установку настроек разбора с удержанием повторов
		again.settings(settings);
		// Выполняем проверку разбора записанного текста
		ASSERT_TRUE(again.parse(written));
		// Выполняем проверку сохранности всех полей корневого объекта
		ASSERT_EQ(again.root().size(), 2u);
	}
}

/**
 * @brief Проверка правила отказа числам, в родной вид не вместимым
 *
 * @details Правило `CHECK` отвергает число по ВЕЛИЧИНЕ его, а не по точности записи:
 * целое за пределами родных видов и дробное, вышедшее за пределы `double` вверх либо
 * вниз, отвергаются, а запись, лишь более точная, округляется, как округлил бы её язык.
 * Прежде описание правила обещало отказ всякой записи «точнее double», чего разбор не
 * делал и делать не должен: отвергалось бы и `0.1`, записанное двадцатью знаками
 *
 */
TEST(CodecJsonDocument, NumberCheckJudgesMagnitudeNotPrecision) {
	/**
	 * @brief Разбираемый текст с ожидаемым исходом
	 *
	 */
	struct Probe {
		// Разбираемый текст документа
		const char * text;
		// Признак ожидаемого отказа разбора правилом CHECK
		bool refused;
	};
	// Перечень разбираемых текстов с ожидаемым исходом
	const vector <Probe> probes = {
		{"[18446744073709551615]", false},                // ровно предел uint64_t
		{"[18446744073709551616]", true},                 // целое за пределом
		{"[-9223372036854775809]", true},                 // целое за пределом снизу
		{"[1e309]", true},                                // дробное за пределом вверх
		{"[-1e400]", true},                               // то же со знаком
		{"[1e-400]", true},                               // дробное, обратившееся в нуль
		{"[0.1234567890123456789012345]", false},         // запись точнее double
		{"[0.10000000000000000000001]", false}            // обычное число длинной записью
	};
	/**
	 * Выполняем перебор всех разбираемых текстов
	 */
	for(const Probe & probe : probes){
		// Дерево значений документа
		json::document_t document(::logger());
		// Настройки разбора с отказом числам, в родной вид не вместимым
		json::document_t::settings_t settings = document.settings();
		// Устанавливаем правило отказа числам, в родной вид не вместимым
		settings.numbers = json::number_t::CHECK;
		// Выполняем установку настроек разбора
		document.settings(settings);
		// Выполняем разбор очередного текста документа
		const bool parsed = document.parse(probe.text);
		// Выполняем проверку исхода разбора
		ASSERT_EQ(parsed, !probe.refused) << probe.text;
		/**
		 * Если разбор завершился отказом
		 */
		if(probe.refused)
			// Выполняем проверку кода отказа разбора
			ASSERT_EQ(document.error(), json::error_t::NUMBER_OUT_OF_RANGE) << probe.text;
	}
	/**
	 * Выполняем проверку округления записи, более точной, чем double
	 */
	{
		// Дерево значений документа
		json::document_t document(::logger());
		// Выполняем проверку разбора записи, более точной, чем double
		ASSERT_TRUE(document.parse("[0.1234567890123456789012345]"));
		// Выполняем проверку округления записи по правилам самого языка
		ASSERT_EQ(document.dump(), "[0.12345678901234568]");
	}
}
