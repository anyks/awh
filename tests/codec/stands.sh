# @brief Раскладка отдельных стендов кодеков по машинам и прогон их там
#
# @details Отдельный стенд собирает кодек без библиотеки целиком, и оттого гоняется на
#          всякой машине без сборки дерева. Раскладка ставит его на все машины разом:
#          свойство доказывается лишь там, где оно способно НЕ выполниться, и
#          переносимость на одной библиотеке сломаться неспособна
#
# @note Стенд, устроенный ради переносимости и запускаемый на одной машине,
#       переносимости не проверяет вовсе - он проверяет сборку без CMake, а это иное
#       свойство. Так был упущен вызов `std::sort` без заголовка `<algorithm>`:
#       собиралось у libc++ и отказывало у libstdc++ и у библиотеки Sun, пять машин из
#       семи
#
# @warning Правки по итогам раскладки делает ВЛАДЕЛЕЦ отказавшего кодека, а не тот, кто
#          раскладку запустил: подпёртый в чужом дереве дефект расходится двумя
#          редакциями, и всплыть у владельца ему уже нечем
#
# @copyright Copyright © 2026
#
# Вызов:
#   tests/codec/stands.sh [перечень стендов]
#
# Перечень стендов задаётся путями от корня дерева и по умолчанию таков:
#   tests/codec/xml/stand.sh tests/codec/json/stand.sh tests/codec/stand.sh
#
# Переменные окружения:
#   AWH_STANDS — перечень машин видом «доступ|корень GoogleTest|краткое имя»
#   AWH_ROOT   — корень дерева исходных текстов, по умолчанию каталог сценария
#

# Прекращаем работу при первом же отказе разбора доводов
set -u

# Получаем корень дерева исходных текстов
ROOT="${AWH_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"

# Получаем перечень прогоняемых стендов
STANDS="${*:-tests/codec/xml/stand.sh tests/codec/json/stand.sh tests/codec/stand.sh}"

# Получаем перечень машин, по каким ведётся раскладка
MACHINES="${AWH_STANDS:-
anyks@anyks.com|/usr/local|freebsd
forman@10.100.1.200|/usr/pkg|netbsd
forman@10.100.1.145|/usr/local|openbsd
forman@10.100.1.105|/usr/local|solaris
forman@10.100.1.159|/usr|openindiana
forman@10.100.1.250|/usr|debian
forman@10.100.1.245|/usr|alpine
}"

# Собираемый свёрток исходных текстов
BUNDLE="/tmp/awh-codec-stands.tgz"

# Выводим сообщение о сборке свёртка
echo "Собираем свёрток: $BUNDLE"

#
# Выполняем сборку свёртка исходных текстов
#
# @note Свёрток собирается видом `ustar` с погашенными довесками файловой системы
#       Apple: `bsdtar` у FreeBSD отвергает их отказом «Special header too large», а
#       весу они прибавляют вчетверо
#
( cd "$ROOT" && COPYFILE_DISABLE=1 tar --format=ustar -czf "$BUNDLE" \
	include src/codec src/num/lexical/table.cpp tests/main.hpp tests/codec tools/verify ) || exit 1

# Собираемый сценарий прогона на стороне машины
RUNNER="/tmp/awh-codec-runner.sh"

#
# Выполняем сборку сценария прогона на стороне машины
#
# @note Сценарий передаётся файлом, а не строкою вызова `ssh`: строка проходит две
#       оболочки подряд, и всякая отмена в ней отменяется дважды. Отменённое не туда
#       съедало доводы вызова стенда молча - стенд собирался с корнем дерева, взятым по
#       умолчанию, и не находил заголовков
#
cat > "$RUNNER" <<'RUN'
#!/bin/sh
# Прогон отдельных стендов кодеков на стороне машины
set -u
# Выполняем перебор всех прогоняемых стендов
for SCRIPT in $AWH_SCRIPTS; do
	# Если сценария стенда в свёртке нет, пропускаем его
	if [ ! -f "$SCRIPT" ]; then
		echo "$SCRIPT: сценария нет в свёртке"
		continue
	fi
	# Разрешаем исполнение сценария стенда
	chmod +x "$SCRIPT"
	# Получаем краткое имя стенда по каталогу его
	NAME=$(basename "$(dirname "$SCRIPT")")
	# Выводим сообщение о начале прогона очередного стенда
	echo "--- $SCRIPT ---"
	# Выполняем сборку очередного стенда
	if ! "./$SCRIPT" . "/tmp/awh-stand-$NAME" > "/tmp/awh-stand-$NAME.log" 2>&1; then
		# Выводим сообщение об отказе сборки стенда
		echo 'СБОРКА ОТКАЗАЛА'
		# Выводим первые строки отказа сборки
		grep -i error "/tmp/awh-stand-$NAME.log" | head -5
		# Выполняем переход к следующему стенду
		continue
	fi
	# Выполняем перебор всех собранных двоичных файлов стенда
	for BINARY in "/tmp/awh-stand-$NAME"/*-tests "/tmp/awh-stand-$NAME"/*-tests.exe; do
		# Выполняем прогон очередного двоичного файла стенда
		[ -x "$BINARY" ] && "$BINARY" 2>&1 | tail -2
	done
done
RUN

# Выполняем перебор всех машин раскладки
echo "$MACHINES" | while IFS='|' read -r HOST GTEST TAG; do
	# Пропускаем пустые строки перечня машин
	[ -n "${HOST:-}" ] || continue
	# Выводим сообщение о начале прогона на очередной машине
	echo "=== $TAG ($HOST) ==="
	#
	# Выполняем передачу свёртка и сценария прогона на очередную машину
	#
	# @note Отказ передачи прогон не прекращает: недоступная машина - это отсутствие
	#       сведений о ней, а не отказ прочих
	#
	if ! scp -q -o BatchMode=yes -o StrictHostKeyChecking=no "$BUNDLE" "$RUNNER" "$HOST:/tmp/"; then
		# Выводим сообщение о недоступности машины
		echo "$TAG: передача не удалась, машина пропущена"
		# Выполняем переход к следующей машине
		continue
	fi
	#
	# Выполняем сборку и прогон стендов на очередной машине
	#
	# @warning Ключ `-n` обязателен: без него `ssh` вычитывает поток ввода целиком и
	#          съедает остаток перечня машин, отчего раскладка молча обрывается на
	#          первой же из них
	#
	ssh -n -o BatchMode=yes -o StrictHostKeyChecking=no "$HOST" \
		"rm -rf ~/codec-stands && mkdir -p ~/codec-stands && cd ~/codec-stands &&
		 tar xzf /tmp/awh-codec-stands.tgz &&
		 GTEST_ROOT='$GTEST' AWH_SCRIPTS='$STANDS' sh /tmp/awh-codec-runner.sh"
done

# Выводим сообщение об окончании раскладки
echo "=== РАСКЛАДКА ОКОНЧЕНА ==="
