#
# @author Yuriy Lobarev
#
# @brief Раскладка отдельных стендов кодеков по машинам и прогон их там
#
# @details Отдельный стенд собирает кодек без библиотеки целиком, и оттого гоняется на
#          всякой машине без сборки дерева. Раскладка ставит его на все машины разом:
#          свойство доказывается лишь там, где оно способно НЕ выполниться, и
#          переносимость на одной библиотеке сломаться неспособна
#
# @note Стенд, устроенный ради переносимости и запускаемый на одной машине,
#       переносимости не проверяет вовсе - он проверяет сборку без CMake, а это иное
#       свойство. Так был упущен вызов `std::sort` без заголовка `<algorithm>`:
#       собиралось у libc++ и отказывало у libstdc++ и у библиотеки Sun, пять машин из
#       семи
#
# @warning Правки по итогам раскладки делает тот, кто ВЕДЁТ отказавший кодек, а не тот,
#          кто раскладку запустил: подпёртый в чужом дереве дефект расходится двумя
#          редакциями, и всплыть по месту ему уже нечем
#
# @warning Всё, что исполняется НА СТОРОНЕ МАШИНЫ, обязано обходиться средствами POSIX:
#          у систем Sun они вида SVR4, и привычные ключи там неизвестны. Родной `tar` не
#          понимает `-z`, родной `grep` не знает `-E`. Свёрток оттого разворачивается
#          через `gzip -dc`, а отбор строк ведётся оболочкою
#
# @copyright Copyright © 2026
#
# Вызов:
#   tests/codec/stands.sh [перечень стендов]
#
# Перечень стендов задаётся путями от корня дерева и по умолчанию таков:
#   tests/codec/xml/stand.sh tests/codec/json/stand.sh tests/codec/syslog/stand.sh
#   tests/codec/cef/stand.sh tests/codec/yaml/stand.sh tests/codec/ini/stand.sh
#   tests/codec/toml/stand.sh tests/codec/csv/stand.sh tests/codec/abc/stand.sh
#   tests/codec/stand.sh
#
# Переменные окружения:
#   AWH_STANDS — перечень машин видом «доступ|корень GoogleTest|краткое имя|собиратель»
#   AWH_ROOT   — корень дерева исходных текстов, по умолчанию каталог сценария
#

# Прекращаем работу при первом же отказе разбора доводов
set -u

# Получаем корень дерева исходных текстов
ROOT="${AWH_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"

# Получаем перечень прогоняемых стендов
#
# @note Перечень внесён ЦЕЛИКОМ 09.09.2026, и стенды YAML, INI и TOML взяты в него
#       наравне с прочими. Раскладка от того станет красной -
#       INI и TOML на двух машинах Sun не собираются, - и красное это верное: отложи
#       внесение до починки, и поверка держалась бы на том, что кто-то вспомнит гонять
#       их руками. Поверка, на памяти держащаяся, поверкой не является
#
# @note Стенд CSV внесён тем же днём и прогнан перед тем начисто: 248 проверок, шесть
#       наборов
#
# @note Стенд ABC внесён тем же днём и прогнан перед тем начисто: 200 проверок в девяти
#       наборах, третьей стороны нет вовсе
#       (проверено `otool -L`, а не доводом «так задумано»). Тем перечень закрыт целиком:
#       всякий кодек рамки, стенд имеющий, раскладкою гоняется
#
STANDS="${*:-tests/codec/xml/stand.sh tests/codec/json/stand.sh tests/codec/syslog/stand.sh tests/codec/cef/stand.sh tests/codec/yaml/stand.sh tests/codec/ini/stand.sh tests/codec/toml/stand.sh tests/codec/csv/stand.sh tests/codec/abc/stand.sh tests/codec/stand.sh}"

# Получаем перечень машин, по каким ведётся раскладка
#
# Перечень машин, по каким ведётся раскладка
#
# @note Строка машины устроена видом «доступ|корень GoogleTest|краткое имя|собиратель»,
#       и четвёртое поле пустует у всех, кроме DragonFly: основной `c++` там от 2019
#       года и наш код им не собрать вовсе, тогда как рядом стоит `g++14` из портов.
#       Без поля этого DragonFly в раскладке не участвовала никак, а отказ её выглядел
#       обычной «СБОРКА ОТКАЗАЛА» - то есть машина числилась опрошенной и отвергнутой,
#       тогда как опросить её было попросту нечем
#
# @warning FreeBSD берётся МЕСТНАЯ (192.168.53.172), а не anyks.com: та рвёт длинный
#          сеанс ssh посреди прогона, а после череды обрывов перестаёт принимать
#          подключения вовсе. Машина публичная и служит не одним проверкам
#
##
# Добавочные ключи сборки, стендам передаваемые
#
# @details Переменная эта уходит на машину и подаётся стендам как есть. Ею гонится
# раскладка под надзирателями:
#
#     FLAGS="-fsanitize=address,undefined" ./tests/codec/stands.sh
#
# @note Части распределителя памяти стенды собирают без инструментации сами - отключать
#       распределитель ключом «AWH_ALLOC_DISABLED» НЕ нужно: под надзирателем выдачу
#       памяти ведёт он, а надзиратель следит за кодеками. Заведено 15.09.2026
##
FLAGS="${FLAGS:-}"

MACHINES="${AWH_STANDS:-
forman@192.168.53.172|/usr/local|freebsd|
forman@192.168.53.173|/usr/pkg|netbsd|
forman@192.168.53.175|/usr/local|openbsd|
forman@192.168.53.153|/usr/local|dragonfly|g++14
forman@192.168.53.104|/usr/local|solaris|
forman@192.168.53.158|/usr|openindiana|
forman@192.168.53.247|/usr|debian|
forman@192.168.53.163|/usr|alpine|
}"

#
# Метка прогона, разводящая рабочие каталоги на машинах
#
# @details Номер запустившего прогон дознавателя своим прогонам не повторяется, а
# работают на одних и тех же машинах несколько работников разом
#
# @warning Метка эта не украшение: сценарий начинает работу СНОСОМ рабочего каталога, и
#          при имени общем снос одного прогона приходится на сборку другого. Отказ
#          выглядит при этом порчей передачи - «нет такого файла» на файле, который
#          лежит и в свёртке, и на машине, - и доказать причину со своей стороны
#          нельзя вовсе: со стороны сносящего видна порченая строка, со стороны
#          собирающего пропавший файл, и оба объяснения правдоподобны и неверны
#
STAMP="${AWH_STAMP:-$$}"

#
# @note Убирается за собою прогон ВСЕГДА, отказавший в том числе: место на машинах
#       считанное, у OpenBSD свободного чуть больше гигабайта, а дерево с собранными
#       стендами весит немало. Записи отказов сборки при уборке сохраняются - они и есть
#       единственное, ради чего стоило бы дерево оставлять
#

# Собираемый свёрток исходных текстов
BUNDLE="/tmp/awh-codec-stands-$STAMP.tgz"

#
# Перечень машин, где сборка стенда отказала
#
# @note Ведётся он файлом, а не переменной: перебор машин идёт внутри конвейера, и
#       переменная, в подоболочке заполненная, наружу не возвращается вовсе
#
BROKEN="/tmp/awh-codec-broken-$STAMP.lst"

#
# Счёт машин, где каждый стенд СОБРАЛСЯ и прогнался
#
# @details Ведётся строками вида «<стенд> <машина>» и служит своду по стендам: кодек,
# собирающийся на шести машинах из восьми, по итоговому счёту неотличим от кодека,
# собирающегося на всех восьми, - а это разные вещи. Отказ сборки раскладка печатает
# честно, но заметить его можно лишь читая журнал целиком, тогда как итог читают всегда
#
# @note Заведено 09.09.2026 по случаю стендов INI и TOML, молча не
#       собиравшихся на Solaris и OpenIndiana: «ld: fatal: symbol referencing errors»
#
PASSES="/tmp/awh-codec-passes-$STAMP.lst"
##
# Перечень стендов, объявивших себя неприменимыми
#
# @details Пропуск не есть ни успех, ни отказ, и третьего перечня ему прежде не было:
#          машина, пропустившая стенд, не попадала НИ в счёт прошедших, НИ в перечень
#          отказавших - и розыск молчащих объявлял её «ответа не давшей». Прогон стенда
#          договора 15.09.2026 показал это на всех восьми машинах разом: стенд честно
#          пропустился всюду, а свод солгал, будто связь оборвалась со всеми
##
SKIPPED="/tmp/awh-codec-skipped-$STAMP.lst"

##
# Перечень стендов, ПРОГНАВШИХСЯ С ОТКАЗОМ проверок
#
# @details Свод обязан говорить об ИСХОДЕ прогона, а не о доставке стенда на машину.
# Набор gtest печатает строку «[  PASSED  ] N tests.» И ПРИ КРАСНЫХ проверках - счёт
# прошедших там верен, но успехом прогона он не является, - и свод, на неё одну
# опиравшийся, зачислял такую машину в прошедшие молча
#
# @note Найдено 16.09.2026: NetBSD дала 221 проверку из 222, одна красная, а свод
#       объявил «8 из 8» без единой пометки. Красная проверка в своде не видна была
#       вовсе, и нашлась лишь чтением выдачи целиком
#
# @note Довод тот же, каким заведён перечень несобравшегося: отказ, в итоговой строке
#       неотличимый от прохождения, есть отказ потерянный
##
FAILED="/tmp/awh-codec-failed-$STAMP.lst"

# Выполняем снос перечней от прежнего прогона
rm -f "$BROKEN" "$PASSES" "$SKIPPED" "$FAILED"

#
# Выполняем поверку самого перечня стендов
#
# @details Перечень по умолчанию ведётся ПОИМЁННО, а не обходом дерева, и кодек, чей
# стенд в него не внесён, из раскладки выпадает МОЛЧА: зелень на одной рабочей машине
# выглядит ровно так же, как зелень на восьми, - отсутствие поверки неотличимо от
# поверки пройденной
#
# @warning Так и вышло с кодеком CEF: своего стенда у него не было вовсе, а договор
#          кодеков на отладочных машинах неприменим (код 77), и весь кодек не
#          проверялся по системам НИКОГДА. Найдено 09.09.2026 разбором чужого отказа,
#          а не самой раскладкой - она молчала
#
# @note Поверка эта лишь ПРЕДУПРЕЖДАЕТ, а не прекращает работу: раскладку зовут и с
#       перечнем в доводах, где сужение намеренно, - оборвись она на том, гонять один
#       стенд было бы нельзя вовсе
#
if [ $# -eq 0 ]; then
	# Выполняем перебор всех стендов, в дереве проверок лежащих
	for FOUND in "$ROOT"/tests/codec/*/stand.sh; do
		# Пропускаем неразвёрнутый образец пути, коль скоро стендов нет вовсе
		[ -f "$FOUND" ] || continue
		# Получаем путь стенда от корня дерева
		FOUND="tests/codec/$(basename "$(dirname "$FOUND")")/stand.sh"
		# Если стенд в перечне раскладки по умолчанию не значится
		case " $STANDS " in
			*" $FOUND "*) ;;
			*) echo "!!! СТЕНД ВНЕ РАСКЛАДКИ: $FOUND - кодек по машинам НЕ ПРОВЕРЯЕТСЯ" ;;
		esac
	done
fi

# Выводим сообщение о сборке свёртка
echo "Собираем свёрток: $BUNDLE"

#
# Выполняем сборку свёртка исходных текстов
#
# @note Свёрток собирается видом `ustar` с погашенными довесками файловой системы
#       Apple: `bsdtar` у FreeBSD отвергает их отказом «Special header too large», а
#       весу они прибавляют вчетверо
#
#
# @warning Перечень этот ведётся ВРУЧНУЮ и обязан отвечать тому, что зовут САМИ стенды.
#          Разойдись они - раскладка печатает «СБОРКА ОТКАЗАЛА» на всех машинах разом, и
#          отказ выглядит бедою кодека, тогда как беда в свёртке. Так и вышло 07.09.2026:
#          стенды давно тянут ведение журнала со всеми его опорами - часами, оснасткою,
#          кодировками, выделением памяти, - а свёрток нёс по-прежнему один «src/codec»,
#          и восемь машин отказали разом на «./src/sys/log.cpp: нет такого файла»
#
# @note Каталоги берутся ЦЕЛИКОМ - «src/sys», «src/net», «src/cryptography», - а не
#       поимённо. Поимённый перечень отставал дважды за сутки: сперва на опорах журнала,
#       затем на «./src/cryptography/crypto.cpp», какой потянул обновлённый стенд
#       сличения. Каталог целиком стоит десятка лишних килобайт в свёртке и снимает
#       разряд отставания вовсе
#
( cd "$ROOT" && COPYFILE_DISABLE=1 tar --format=ustar -czf "$BUNDLE" \
	include src/codec src/num src/sys src/net src/encoding src/alloc \
	src/compressor src/cryptography submodules/zlib tests/main.hpp tests/codec tools/verify ) || exit 1

# Собираемый сценарий прогона на стороне машины
RUNNER="/tmp/awh-codec-runner-$STAMP.sh"

#
# Выполняем сборку сценария прогона на стороне машины
#
# @note Сценарий передаётся файлом, а не строкою вызова `ssh`: строка проходит две
#       оболочки подряд, и всякая отмена в ней отменяется дважды. Отменённое не туда
#       съедало доводы вызова стенда молча - стенд собирался с корнем дерева, взятым по
#       умолчанию, и не находил заголовков
#
cat > "$RUNNER" <<'RUN'
#!/bin/sh
# Прогон отдельных стендов кодеков на стороне машины
set -u
##
# Выполняем розыск постоянного клона дерева с собранною третьей стороной
#
# @details Свёрток третьей стороны не несёт - она весит десятки мегабайт и у каждой машины
#          своя. Зато машины несут постоянные клоны, где дерево собрано целиком, и стенду
#          сличения довольно взять набор и заголовки оттуда. Прочим стендам они не нужны
#          вовсе: они для того и заводились, чтобы третью сторону обойти
#
# @note Розыск молчалив по замыслу: не нашлось - стенд сличения объявит себя неприменимым
#       кодом 77, как и прежде, а восемь отдельных стендов пройдут как ни в чём не бывало
##
for CLONE in "$HOME/awh" "$HOME/awh-v5" "$HOME/awh5"; do
	# Если в очередном клоне собранный набор третьей стороны отыскался
	if [ -f "$CLONE/third_party/lib/libdependence.a" ] && [ -d "$CLONE/third_party/include" ]; then
		# Запоминаем размещение собранного набора третьей стороны
		DEPEND="$CLONE/third_party/lib/libdependence.a"
		# Запоминаем размещение заголовков третьей стороны
		AWH_THIRD="$CLONE/third_party/include"
		# Вывозим размещение третьей стороны стенду сличения
		export DEPEND AWH_THIRD
		# Выводим сообщение о найденной третьей стороне
		echo "--- третья сторона взята из клона: $CLONE"
		# Прекращаем розыск на первом же найденном клоне
		break
	fi
done
# Выполняем перебор всех прогоняемых стендов
for SCRIPT in $AWH_SCRIPTS; do
	# Если сценария стенда в свёртке нет, пропускаем его
	if [ ! -f "$SCRIPT" ]; then
		echo "$SCRIPT: сценария нет в свёртке"
		continue
	fi
	# Разрешаем исполнение сценария стенда
	chmod +x "$SCRIPT"
	# Получаем краткое имя стенда по каталогу его
	NAME=$(basename "$(dirname "$SCRIPT")")
	# Выводим сообщение о начале прогона очередного стенда
	echo "--- $SCRIPT ---"
	# Выполняем сборку очередного стенда
	"./$SCRIPT" . "/tmp/awh-stand-$AWH_STAMP-$NAME" > "/tmp/awh-stand-$AWH_STAMP-$NAME.log" 2>&1
	# Запоминаем код возврата сборки очередного стенда
	CODE=$?
	#
	# Если стенд объявил себя неприменимым на этой машине
	#
	# @details Код 77 взят у GNU Automake, где означает ровно пропуск проверки, и отдаёт
	# его стенд сличения: ему нужен собранный набор третьей стороны со всеми заголовками,
	# а отладочные машины его не несут - ради обхода третьей стороны отдельные стенды и
	# заводились. Это НЕ отказ сборки и не беда кодека
	#
	# @warning Прежде код этот от отказа не отличался, и раскладка печатала по нему
	#          «СБОРКА ОТКАЗАЛА», занося машину в перечень несобравшегося. Ложная тревога
	#          та стояла на всех восьми машинах разом и приучала читать отчёт по
	#          диагонали - ровно то, чего перечень несобравшегося и заведён не допускать.
	#          Замерено 09.09.2026
	#
	if [ "$CODE" -eq 77 ]; then
		# Выводим сообщение о неприменимости стенда на этой машине
		echo "--- стенд здесь неприменим, пропущен"
		# Выполняем переход к следующему стенду
		continue
	fi
	# Если сборка очередного стенда отказом завершилась
	if [ "$CODE" -ne 0 ]; then
		#
		# Выводим сообщение об отказе сборки стенда
		#
		# @note Метка `!!!` опознаётся стороной вызывающей и собирается в перечень
		#       несобравшегося: отказ сборки неотличим от прохождения, если смотреть на
		#       один лишь поток вывода, а проверки при том не прогонялись ни разу
		#
		echo '!!! СБОРКА ОТКАЗАЛА'
		#
		# Выводим первые строки отказа сборки
		#
		# @warning Отбор по слову «error» причину теряет МОЛЧА, и отказ печатается
		#          одним заголовком без единой строки под ним. Слова этого не несут
		#          отказы, каких на стендах больше всего: нехватка места на разделе,
		#          «No such file or directory» у отсутствующего исходника, собиратель,
		#          убитый по памяти («Killed»), недостача заголовков GoogleTest.
		#          Замерено 09.09.2026: общий стенд отказал на FreeBSD, и раскладка
		#          отчиталась отказом БЕЗ причины - разбирать пришлось вручную
		#
		REASON=$(grep -i error "/tmp/awh-stand-$AWH_STAMP-$NAME.log" | head -5)
		# Если строки отказа со словом «error» в журнале сборки отыскались
		if [ -n "$REASON" ]; then
			# Выводим первые строки отказа сборки
			echo "$REASON"
			#
			# Выводим хвост журнала сборки ВСЛЕД за строками отказа
			#
			# @warning Строк со словом «error» мало и они не всегда те: у связывания
			#          Solaris печатает «ld: fatal: symbol referencing errors», а САМО
			#          ИМЯ нехватающего символа стоит ВЫШЕ, отдельной строкою под шапкою
			#          «Undefined first referenced», и слова «error» не несёт. Отбор
			#          выдавал приговор без причины, и разбирать приходилось вручную на
			#          самой машине
			#
			# @note Замерено 09.09.2026: стенд CEF не собрался на OpenIndiana, раскладка
			#       напечатала две строки про «symbol referencing errors», а имена
			#       `if_indextoname` и `if_nametoindex` остались за кадром
			#
			echo "(хвост журнала сборки)"
			# Выводим хвост журнала сборки стенда
			tail -8 "/tmp/awh-stand-$AWH_STAMP-$NAME.log"
		#
		# Если строк со словом «error» журнал сборки не несёт
		#
		# @note Выводится ХВОСТ журнала, а не голова его: сборка печатает ход сверху
		#       вниз, и причина остановки стоит последней. Голова же несёт заголовок
		#       стенда, одинаковый у всякого прогона
		#
		else
			# Выводим сообщение об отсутствии строк отказа со словом «error»
			echo '(строк со словом error в журнале нет, хвост журнала сборки)'
			# Выводим хвост журнала сборки стенда
			tail -5 "/tmp/awh-stand-$AWH_STAMP-$NAME.log"
		fi
		# Выполняем переход к следующему стенду
		continue
	fi
	# Выполняем перебор всех собранных двоичных файлов стенда
	for BINARY in "/tmp/awh-stand-$AWH_STAMP-$NAME"/*-tests "/tmp/awh-stand-$AWH_STAMP-$NAME"/*-tests.exe; do
		#
		# Выполняем прогон очередного двоичного файла стенда
		#
		# @note Выбираются строки итога поимённо, а не хвостом выдачи: пропуск проверки
		#       печатается ПОСЛЕ итога, и хвост из двух строк показывал перечень
		#       пропущенных вместо счёта прошедших. Отказ при том не терялся - он
		#       печатается ещё ниже, - но узнать, сколько проверок прошло, было нельзя
		#       вовсе, а пропуск есть молчаливое отключение и виден быть обязан
		#
		#
		# @note Отбор ведётся оболочкою, а не `grep -E`: родной `grep` у систем Sun
		#       расширенных выражений не знает вовсе и отвечает «illegal option -- E»,
		#       после чего итог прогона пропадает целиком. Наступал на это дважды за день
		#
		#
		# Счётчик строк довода отказа, за строкою «Failure» печатаемых
		#
		# @details Отбор оставляет строки ИТОГА, и довод отказа - «Value of», «Actual»,
		#          «Expected» и сообщение проверки - в них не попадал вовсе: раскладка
		#          сообщала, КАКАЯ проверка упала, и умалчивала ПОЧЕМУ. Узнать довод
		#          можно было лишь сборкою стенда на самой машине руками
		#
		# @note Заведено 16.09.2026 по следу разбора красной проверки на NetBSD.
		#       На исправном прогоне строк этих нет вовсе, и молчание отбора ничего не
		#       стоило; на красном они и есть вся польза
		#
		# @note Окно в ПЯТЬ строк: довод gtest укладывается в три - «Value of», «Actual»,
		#       «Expected», - а сообщение самой проверки, через «<<» поданное, идёт ЗА
		#       ними и при окне в три строки обрезалось. Проверено нарочно красной
		#       проверкой 16.09.2026: довод дошёл, а сообщение пропало
		#
		CONTEXT=0
		[ -x "$BINARY" ] && "$BINARY" 2>&1 | while IFS= read -r OUTPUT; do
			# Определяем строку итога прогона
			case "$OUTPUT" in
				*"tests from"*"ran."*) echo "$OUTPUT" ;;
				*"test from"*"ran."*) echo "$OUTPUT" ;;
				"[  PASSED  ]"*) echo "$OUTPUT" ;;
				"[  FAILED  ]"*) echo "$OUTPUT" ;;
				"[  SKIPPED ]"*) echo "$OUTPUT" ;;
				#
				# Строка отказа проверки, набором gtest печатаемая
				#
				# @warning Образец ТОЧЕН - «<путь>:<строка>: Failure», - а не «*Failure*»:
				#          широкий образец ловил ИМЕНА проверок, слово это несущие
				#          («Failures», «FailurePaths», «SaveFailureIsReported»), и
				#          открывал окно печати на ровном месте, выпуская пять строк
				#          чужого вывода на каждую такую проверку. Поймано своею же
				#          поверкою 16.09.2026 на первом прогоне
				#
				*": Failure")
					# Выводим строку отказа проверки
					echo "$OUTPUT"
					# Открываем окно печати довода отказа
					CONTEXT=5
				;;
				*)
					# Если окно печати довода отказа открыто
					if [ "$CONTEXT" -gt 0 ]; then
						# Выводим очередную строку довода отказа
						echo "$OUTPUT"
						# Сужаем окно печати довода отказа
						CONTEXT=$((CONTEXT - 1))
					fi
				;;
			esac
		done
	done
done
RUN

# Выполняем перебор всех машин раскладки
echo "$MACHINES" | while IFS='|' read -r HOST GTEST TAG COMPILER; do
	# Пропускаем пустые строки перечня машин
	[ -n "${HOST:-}" ] || continue
	# Выводим сообщение о начале прогона на очередной машине
	echo "=== $TAG ($HOST) ==="
	#
	# Выполняем передачу свёртка и сценария прогона на очередную машину
	#
	# @note Отказ передачи прогон не прекращает: недоступная машина - это отсутствие
	#       сведений о ней, а не отказ прочих
	#
	if ! scp -q -o BatchMode=yes -o StrictHostKeyChecking=no \
		-o ConnectTimeout=20 -o ServerAliveInterval=30 -o ServerAliveCountMax=10 "$BUNDLE" "$RUNNER" "$HOST:/tmp/"; then
		# Выводим сообщение о недоступности машины
		echo "$TAG: передача не удалась, машина пропущена"
		# Выполняем переход к следующей машине
		continue
	fi
	#
	# Выполняем сборку и прогон стендов на очередной машине
	#
	# @warning Ключ `-n` обязателен: без него `ssh` вычитывает поток ввода целиком и
	#          съедает остаток перечня машин, отчего раскладка молча обрывается на
	#          первой же из них
	#
	#
	# @warning Сроки связи обязательны: без них полуоткрытая связь вешает раскладку
	#          НАВСЕГДА и МОЛЧА. Замерено 16.09.2026 - прогон на OpenIndiana стоял час
	#          при пустой машине: работа там кончилась, ход прогона снёс за собой и
	#          свёрток, и сценарий, а `ssh` о том не узнал, ибо встречный FIN не дошёл.
	#          Связь числилась ESTABLISHED, load average держался нулём, а раскладка
	#          ждала. `ServerAliveInterval` шлёт опрос каждые 30 секунд и рвёт связь
	#          после десяти безответных - сиречь через пять минут молчания, чего на
	#          сборку стенда с запасом хватает, ибо опрос идёт и во время работы
	#
	ssh -n -o BatchMode=yes -o StrictHostKeyChecking=no \
		-o ConnectTimeout=20 -o ServerAliveInterval=30 -o ServerAliveCountMax=10 "$HOST" \
		"rm -rf ~/codec-stands-$STAMP && mkdir -p ~/codec-stands-$STAMP && cd ~/codec-stands-$STAMP &&
		 gzip -dc /tmp/awh-codec-stands-$STAMP.tgz | tar -xf - &&
		 GTEST_ROOT='$GTEST' AWH_SCRIPTS='$STANDS' AWH_STAMP='$STAMP' ${FLAGS:+FLAGS='$FLAGS'} ${COMPILER:+CXX='$COMPILER'} sh /tmp/awh-codec-runner-$STAMP.sh;
		 cd ~ && rm -rf ~/codec-stands-$STAMP /tmp/awh-codec-stands-$STAMP.tgz /tmp/awh-codec-runner-$STAMP.sh /tmp/awh-stand-$STAMP-*[!g]" |
	#
	# Выполняем отбор отказов сборки в перечень несобравшегося
	#
	# @note Поток при этом проходит насквозь: отбор ведётся попутно, дабы вывод машины
	#       оставался виден целиком
	#
	while IFS= read -r LINE; do
		# Выводим прочитанную строку вывода машины
		echo "$LINE"
		#
		# Определяем строку итога очередного стенда на машине
		#
		# @note Имя стенда берётся из строки «--- <путь> ---», какую печатает сторона
		#       машины перед сборкою: отказ и итог прогона идут ЗА нею, и связать их со
		#       стендом иначе нечем
		#
		case "$LINE" in
			'--- tests/'*' ---')
				# Запоминаем стенд, к какому относятся следующие строки
				CURRENT=$(echo "$LINE" | sed 's/^--- //; s/ ---$//')
			;;
			'!!! СБОРКА ОТКАЗАЛА')
				# Заносим машину в перечень несобравшегося вместе со стендом
				echo "$TAG (${CURRENT:-стенд неизвестен})" >> "$BROKEN"
			;;
			'[  PASSED  ]'*)
				# Заносим стенд в счёт машин, где он собрался и прогнался
				echo "${CURRENT:-стенд неизвестен} $TAG" >> "$PASSES"
			;;
			'[  FAILED  ]'*)
				#
				# Заносим стенд в перечень прогнавшихся с отказом проверок
				#
				# @note Строка эта у gtest печатается дважды и более - перечнем
				#       красных проверок, - и повторы снимаются счётом уникальных
				#       строк ниже, а не здесь: отбор идёт потоком и памяти не держит
				#
				echo "${CURRENT:-стенд неизвестен} $TAG" >> "$FAILED"
			;;
			'--- стенд здесь неприменим, пропущен')
				# Заносим стенд в перечень пропущенных: пропуск не есть ни успех, ни отказ
				echo "${CURRENT:-стенд неизвестен} $TAG" >> "$SKIPPED"
			;;
		esac
	done
done

#
# Выводим свод по стендам: на сколько машин лёг каждый
#
# @details Итог обязан говорить не «сколько проверок прошло», а «на сколько машин стенд
# ЛЁГ»: стенд, не собравшийся на машине, проверок там не прогонял вовсе, и зелень по
# шести машинам из восьми выглядит в точности как зелень по восьми
#
# @note Число машин берётся из самого перечня, а не постоянной: раскладку зовут и с
#       AWH_STANDS на одну машину, и свод обязан говорить о том прогоне, какой был
#
echo "=== СТЕНДЫ ПО МАШИНАМ ==="
# Считаем число машин, раскладкою опрошенных
TOTAL=$(echo "$MACHINES" | grep -c '@')
# Выполняем перебор всех стендов, раскладкою прогнанных
for SCRIPT in $STANDS; do
	# Считаем машины, где очередной стенд собрался и прогнался
	#
	# Счёт машин, где стенд лёг
	#
	# @warning Запасной ход пишется ОТДЕЛЬНОЙ строкой, а не через «|| echo 0»: `grep -c`
	#          при нуле совпадений печатает «0» И отвечает кодом 1 разом, оттого «||»
	#          дописывал второй нуль, и сличение получало «0\n0» вместо числа. Отказ
	#          вида «integer expression expected» вылезал ровно тогда, когда стенд не лёг
	#          НИ НА ОДНУ машину, - то есть в единственном случае, ради какого свод и
	#          заведён: строка «НЕ ЛЁГ НА ВСЕ МАШИНЫ» не печаталась вовсе
	#
	# @note Найдено 09.09.2026 первым же прогоном, где стенд договора пропустился всюду
	#
	COUNT=$(grep -c "^$SCRIPT " "$PASSES" 2>/dev/null) || COUNT=0
	# Считаем машины, где стенд объявил себя неприменимым
	SKIPS=$(grep -c "^$SCRIPT " "$SKIPPED" 2>/dev/null) || SKIPS=0
	#
	# Считаем машины, где стенд прогнался С ОТКАЗОМ проверок
	#
	# @note Счёт ведётся по УНИКАЛЬНЫМ строкам: gtest печатает «[  FAILED  ]» перечнем,
	#       по строке на каждую красную проверку, и прямой счёт строк дал бы машин
	#       больше, чем их есть
	#
	REDS=$(grep "^$SCRIPT " "$FAILED" 2>/dev/null | sort -u | grep -c . ) || REDS=0
	#
	# Изымаем машины с красными проверками из числа прошедших
	#
	# @details Машина, где стенд собрался и прогнался, но проверку завалил, стендом НЕ
	# пройдена: доставка состоялась, а исход отрицателен. Считать её прошедшей значило бы
	# показывать «8 из 8» при красной проверке - ровно та ложь, ради какой свод заведён
	#
	if [ "$REDS" -gt 0 ]; then
		# Вычитаем машины с красными проверками из числа прошедших
		COUNT=$((COUNT - REDS))
		# Если вычитание ушло ниже нуля, обнуляем счёт прошедших
		[ "$COUNT" -lt 0 ] && COUNT=0
		#
		# Выводим СОСТАВ машин с красными проверками, а не один их счёт
		#
		# @note Счёт отвечает «сколько», а чинить надо «где»: состав отказавших машин
		#       называет систему, и по ней уже видно, свойство это её или беда кодека
		#
		echo "$SCRIPT: !!! ПРОВЕРКИ КРАСНЫЕ на машинах: $(grep "^$SCRIPT " "$FAILED" 2>/dev/null | sort -u | awk '{print $2}' | tr '\n' ' ')"
	fi
	##
	# Если стенд пропущен всюду, где не лёг
	#
	# @details Пропуск - не беда кодека: стенд сам объявил себя неприменимым к этой
	#          машине. Но и успехом он не является, оттого счёт его печатается ОТДЕЛЬНО,
	#          а не приплюсовывается к прошедшим: «8 из 8» при восьми пропусках было бы
	#          ложью ровно того рода, ради какой свод и заведён
	##
	if [ "$COUNT" -eq 0 ] && [ "$SKIPS" -gt 0 ]; then
		# Выводим строку стенда, пропущенного всюду
		echo "$SCRIPT: 0 из $TOTAL   !!! ПРОПУЩЕН ВЕЗДЕ ($SKIPS машин): стенд неприменим ни к одной"
	# Если стенд лёг не на все машины раскладки
	elif [ "$((COUNT + SKIPS))" -lt "$TOTAL" ]; then
		# Выводим строку стенда с пометкой о недостаче машин
		echo "$SCRIPT: $COUNT из $TOTAL   !!! НЕ ЛЁГ НА ВСЕ МАШИНЫ${SKIPS:+ (пропущено: $SKIPS)}"
	# Если стенд где-то пропущен, а прочее прошёл
	elif [ "$SKIPS" -gt 0 ]; then
		# Выводим строку стенда с пометкой о пропусках
		echo "$SCRIPT: $COUNT из $TOTAL, пропущено $SKIPS"
	else
		# Выводим строку стенда, легшего на все машины
		echo "$SCRIPT: $COUNT из $TOTAL"
	fi
done

#
# Выполняем розыск машин, ответа не давших вовсе
#
# @details Машина, оборвавшая связь посреди работы, не попадает НИ в счёт прошедших, ни
# в перечень отказавших: свод ловит её лишь недостачею в «N из M», а причина - обрыв, а
# не отказ сборки - из итога не видна вовсе. Разница существенная: отказ сборки правится
# кодом, обрыв связи - машиной, и путать их значит искать беду не там
#
# @note Найдено 10.09.2026: OpenBSD ответила «Connection reset by peer» посреди сборки, и
#       свод показал «1 из 8», ни словом не обмолвившись, что одна машина попросту
#       замолчала
#
for MACHINE in $MACHINES; do
	# Получаем краткое имя очередной машины
	NAME=$(echo "$MACHINE" | cut -d'|' -f3)
	# Если краткое имя машины пусто
	[ -n "$NAME" ] || continue
	# Считаем ответы машины, успешные и отказавшие
	SPOKEN=$(grep -c "^$NAME " "$BROKEN" 2>/dev/null) || SPOKEN=0
	# Считаем стенды, на машине прогнанные
	PASSED=$(grep -c " $NAME$" "$PASSES" 2>/dev/null) || PASSED=0
	##
	# Считаем стенды, на машине пропущенные
	#
	# @note Пропуск есть ОТВЕТ машины, а не молчание её: стенд дошёл, собрался настолько,
	#       чтобы себя оценить, и объявил неприменимость. Без этого счёта раскладка
	#       стенда договора 15.09.2026 объявила «ответа не дали» все восемь машин разом,
	#       тогда как ответили они все восемь
	##
	SKIPS=$(grep -c " $NAME$" "$SKIPPED" 2>/dev/null) || SKIPS=0
	# Если машина не ответила ни успехом, ни отказом, ни пропуском
	if [ "$((SPOKEN + PASSED + SKIPS))" -eq 0 ]; then
		# Выводим строку машины, ответа не давшей
		echo "!!! МАШИНА ОТВЕТА НЕ ДАЛА: $NAME - связь оборвана либо прогон не начался"
	fi
done

#
# Если сборка стенда отказала хоть на одной машине
#
# @details Отказ сборки прогон не прекращает - неготовая машина есть отсутствие сведений
#          о ней, а не отказ прочих. Но и потеряться ему нельзя: стенд, не собравшийся на
#          машине, проверок там не прогонял ВОВСЕ, и молчание это неотличимо от
#          прохождения. Так внесение TOML и INI в щуп сличения оставило его несобираемым,
#          а раскладка о том лишь обмолвилась строкою посреди потока
#
if [ -s "$BROKEN" ]; then
	# Выводим заголовок перечня несобравшегося
	echo "=== РАСКЛАДКА ОКОНЧЕНА, НО СБОРКА ОТКАЗАЛА:"
	# Выводим перечень машин, где сборка отказала
	sort -u "$BROKEN" | sed 's/^/    /'
	# Выполняем снос перечней раскладки
	rm -f "$BROKEN" "$PASSES" "$SKIPPED" "$FAILED"
	# Выводим признак неудачной раскладки
	exit 1
fi

# Выполняем снос перечней раскладки
rm -f "$BROKEN" "$PASSES" "$SKIPPED" "$FAILED"

# Выводим сообщение об окончании раскладки
echo "=== РАСКЛАДКА ОКОНЧЕНА ==="
