/**
 * @brief Проверка переноса перечня значений в дерево настроек
 *
 * @note Перечень записи INI есть последовательность одноимённых свойств, и переносится
 *       он повтором имени: первое значение установкой, прочие доливом
 *
 */
TEST(CodecIniValue, GraftingList) {
	// Собираемое владеющее значение
	ini::value_t value;
	// Выполняем заведение перечня значений верхнего уровня
	value.place("/tags/0") = ini::value_t("one");
	// Выполняем добавление второго значения перечня
	value.place("/tags/1") = ini::value_t("two");
	// Выполняем добавление третьего значения перечня
	value.place("/tags/2") = ini::value_t("three");
	// Выполняем заведение перечня значений раздела
	value.place("/server/port/0") = ini::value_t("80");
	// Выполняем добавление второго значения перечня раздела
	value.place("/server/port/1") = ini::value_t("443");
	// Дерево настроек, куда переносится значение
	ini::document_t document(::logger());
	// Выполняем разбор пустого текста настроек
	ASSERT_TRUE(document.parse(""));
	// Выполняем перенос владеющего значения в дерево настроек
	ASSERT_TRUE(value.graft(document));
	// Выполняем проверку перечня значений верхнего уровня
	ASSERT_EQ(document.values("tags"), (vector <string_view> {"one", "two", "three"}));
	// Выполняем проверку перечня значений раздела
	ASSERT_EQ(document.values("port", "server"), (vector <string_view> {"80", "443"}));
	/**
	 * Выполняем повторный перенос того же значения
	 *
	 * @note Перенос поверх готового дерева перечня не наращивает: объявления,
	 *       в разделе уже имеющиеся, сносятся, а значения доливаются заново
	 */
	ASSERT_TRUE(value.graft(document));
	// Выполняем проверку того, что перечень верхнего уровня не удвоился
	ASSERT_EQ(document.values("tags").size(), 3);
	// Выполняем проверку того, что перечень раздела не удвоился
	ASSERT_EQ(document.values("port", "server").size(), 2);
	// Выполняем проверку того, что перечень уходит в текст настроек повтором имени
	ASSERT_NE(document.text().find("tags = one"), string::npos);
	// Выполняем проверку того, что второе значение перечня записано тем же именем
	ASSERT_NE(document.text().find("tags = two"), string::npos);
	/**
	 * Выполняем проверку отказа переноса перечня со вложенным значением
	 *
	 * @note Перечень записи INI несёт лишь простые значения: вложенности запись не
	 *       имеет, и молчаливый пропуск оставил бы потребителя с деревом без части
	 *       его значения
	 */
	ini::value_t nested;
	// Выполняем заведение перечня со вложенным вместилищем внутри
	nested.place("/list/0/key") = ini::value_t("значение");
	// Выполняем проверку отказа переноса значения с вложенностью внутри перечня
	ASSERT_FALSE(nested.graft(document));
}

