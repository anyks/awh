/**
 * @brief Проверка сборки дерева из значений языка
 *
 */
TEST(CodecIniValue, Assembling) {
	// Собираемое владеющее значение
	ini::value_t value;
	// Выполняем проверку того, что вновь заведённое значение не определено
	ASSERT_FALSE(value.valid());
	// Выполняем установку простого значения свойства
	ASSERT_TRUE(value.insert("title", ini::value_t("пример")));
	// Выполняем проверку того, что значение стало вместилищем пар
	ASSERT_TRUE(value.is(ini::type_t::TABLE));
	// Выполняем установку второго свойства
	ASSERT_TRUE(value.insert("port", ini::value_t("8080")));
	// Выполняем проверку количества пар вместилища
	ASSERT_EQ(value.size(), 2u);
	// Выполняем проверку наличия пары по имени
	ASSERT_TRUE(value.contains("port"));
	// Выполняем проверку отсутствия пары, не заведённой вовсе
	ASSERT_FALSE(value.contains("missing"));
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку успешности извлечения содержимого
	ASSERT_TRUE(value["title"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "пример");
	/**
	 * Выполняем проверку отказа установки пары с пустым именем
	 *
	 * @note Свойство без имени записано быть не может, и молчаливая подстановка имени
	 *       скрыла бы ошибку у потребителя
	 */
	ASSERT_FALSE(value.insert("", ini::value_t("значение")));
	// Выполняем проверку того, что количество пар не изменилось
	ASSERT_EQ(value.size(), 2u);
	// Выполняем сброс значения в исходное состояние
	value.clear();
	// Выполняем проверку того, что сброшенное значение не определено
	ASSERT_FALSE(value.valid());
}

/**
 * @brief Проверка перезаписи занятого имени на прежнем месте
 *
 */
TEST(CodecIniValue, Overwriting) {
	// Собираемое владеющее значение
	ini::value_t value;
	// Выполняем установку первой пары вместилища
	ASSERT_TRUE(value.insert("first", ini::value_t("1")));
	// Выполняем установку второй пары вместилища
	ASSERT_TRUE(value.insert("second", ini::value_t("2")));
	// Выполняем установку третьей пары вместилища
	ASSERT_TRUE(value.insert("third", ini::value_t("3")));
	// Выполняем перезапись значения первой пары вместилища
	ASSERT_TRUE(value.insert("first", ini::value_t("100")));
	// Выполняем проверку того, что количество пар не изменилось
	ASSERT_EQ(value.size(), 3u);
	// Выполняем проверку того, что перезаписанная пара осталась на прежнем месте
	ASSERT_EQ(value.key(0), "first");
	// Выполняем проверку того, что соседние пары не сдвинулись
	ASSERT_EQ(value.key(2), "third");
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку успешности извлечения перезаписанного содержимого
	ASSERT_TRUE(value["first"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "100");
	// Выполняем проверку отказа добавления занятого имени
	ASSERT_FALSE(value.append("first", ini::value_t("7")));
	// Выполняем проверку успешности добавления имени незанятого
	ASSERT_TRUE(value.append("fourth", ini::value_t("4")));
	// Выполняем проверку количества пар вместилища
	ASSERT_EQ(value.size(), 4u);
}

/**
 * @brief Проверка обращения к вложенным значениям по пути
 *
 */
TEST(CodecIniValue, Routing) {
	// Собираемое владеющее значение
	ini::value_t value;
	// Выполняем заведение вложенного значения по пути
	value.place("/server/host") = ini::value_t("localhost");
	// Выполняем заведение вложенного значения перечня по пути
	value.place("/server/tags/0") = ini::value_t("one");
	// Выполняем заведение второго значения перечня по пути
	value.place("/server/tags/1") = ini::value_t("two");
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку успешности обращения по пути
	ASSERT_TRUE(value.at("/server/host").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "localhost");
	// Выполняем проверку того, что часть пути числовая завела перечень
	ASSERT_TRUE(value.at("/server/tags").is(ini::type_t::ARRAY));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value.at("/server/tags").size(), 2u);
	// Выполняем проверку успешности обращения к значению перечня по номеру
	ASSERT_TRUE(value.at("/server/tags/1").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "two");
	// Выполняем проверку того, что обращение к отсутствующему пути отказом не является
	ASSERT_FALSE(value.at("/server/missing").valid());
	// Выполняем проверку того, что обращение к отсутствующему пути не завело значения
	ASSERT_FALSE(value.at("/server").contains("missing"));
	// Выполняем проверку того, что путь пустой выдаёт само значение
	ASSERT_TRUE(value.at("").is(ini::type_t::TABLE));
}

/**
 * @brief Проверка удаления значений вместилища
 *
 */
TEST(CodecIniValue, Removing) {
	// Собираемое владеющее значение
	ini::value_t value;
	// Выполняем установку первой пары вместилища
	ASSERT_TRUE(value.insert("first", ini::value_t("1")));
	// Выполняем установку второй пары вместилища
	ASSERT_TRUE(value.insert("second", ini::value_t("2")));
	// Выполняем установку третьей пары вместилища
	ASSERT_TRUE(value.insert("third", ini::value_t("3")));
	// Выполняем удаление пары вместилища по имени
	ASSERT_TRUE(value.erase("second"));
	// Выполняем проверку количества пар вместилища
	ASSERT_EQ(value.size(), 2u);
	/**
	 * Выполняем проверку того, что имя удалено вместе со значением
	 *
	 * @note Перечни имён и значений идут рядом, и рассогласование их сдвинуло бы все
	 *       имена за удалённым на единицу
	 */
	ASSERT_EQ(value.key(1), "third");
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку того, что значение соседа осталось своим
	ASSERT_TRUE(value["third"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "3");
	// Выполняем проверку отказа удаления имени, не заведённого вовсе
	ASSERT_FALSE(value.erase("missing"));
	// Выполняем проверку удаления значения вместилища по номеру
	ASSERT_TRUE(value.erase(static_cast <size_t> (0)));
	// Выполняем проверку количества пар вместилища
	ASSERT_EQ(value.size(), 1u);
	// Выполняем проверку того, что оставшейся парой стала третья
	ASSERT_EQ(value.key(0), "third");
	// Выполняем проверку отказа удаления по номеру за пределами вместилища
	ASSERT_FALSE(value.erase(static_cast <size_t> (5)));
}

/**
 * @brief Проверка перечня значений одноимённого свойства
 *
 */
TEST(CodecIniValue, Listing) {
	// Прочитанное значение
	ini::value_t value;
	// Выполняем разбор текста настроек с повтором имени свойства
	ASSERT_TRUE(value.parse("tag = one\ntag = two\nsingle = alone\n"));
	/**
	 * Выполняем проверку того, что повтор имени лёг перечнем
	 *
	 * @note Свойство, объявленное однажды, есть значение простое, и обёртка перечнем
	 *       заставляла бы потребителя различать эти два случая при всяком обращении
	 */
	ASSERT_TRUE(value["tag"].is(ini::type_t::ARRAY));
	// Выполняем проверку количества значений перечня
	ASSERT_EQ(value["tag"].size(), 2u);
	// Выполняем проверку того, что свойство единственное перечнем не стало
	ASSERT_TRUE(value["single"].is(ini::type_t::STRING));
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку успешности извлечения значения перечня по номеру
	ASSERT_TRUE(value["tag"][static_cast <size_t> (0)].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "one");
	// Выполняем проверку успешности извлечения второго значения перечня
	ASSERT_TRUE(value["tag"][static_cast <size_t> (1)].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "two");
	// Выполняем проверку отказа извлечения содержимого у перечня
	ASSERT_FALSE(value["tag"].value(text));
	/**
	 * Выполняем проверку отказа добавления без имени во вместилище пар
	 */
	ini::value_t table(ini::type_t::TABLE);
	// Выполняем проверку отказа добавления значения во вместилище пар
	ASSERT_FALSE(table.push(ini::value_t("1")));
}

/**
 * @brief Проверка снятия значения с дерева настроек
 *
 */
TEST(CodecIniValue, Extraction) {
	// Прочитанное значение
	ini::value_t value;
	// Выполняем разбор текста настроек во владеющее значение
	ASSERT_TRUE(value.parse(
		"title = пример\n"
		"port = 8080\n"
		"[server]\n"
		"host = localhost\n"
		"enabled = yes\n"
	));
	// Выполняем проверку того, что корнем стало вместилище пар
	ASSERT_TRUE(value.is(ini::type_t::TABLE));
	// Извлекаемое содержимое простого значения
	string text;
	// Выполняем проверку успешности извлечения свойства верхнего уровня
	ASSERT_TRUE(value["title"].value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "пример");
	// Извлекаемое целое число
	int64_t number = 0;
	/**
	 * Выполняем проверку успешности извлечения числа из записи
	 *
	 * @note Своих видов значения у наречия INI нет вовсе: значение свойства есть
	 *       последовательность знаков, а число ли это - решает извлечение
	 */
	ASSERT_TRUE(value["port"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 8080);
	// Выполняем проверку снятия раздела вместилищем пар
	ASSERT_TRUE(value["server"].is(ini::type_t::TABLE));
	// Выполняем проверку успешности обращения к свойству раздела по пути
	ASSERT_TRUE(value.at("/server/host").value(text));
	// Выполняем проверку извлечённого содержимого
	ASSERT_EQ(text, "localhost");
	// Извлекаемое логическое значение
	bool flag = false;
	/**
	 * Выполняем проверку успешности извлечения логического значения
	 *
	 * @note Разбор ведётся расширенным видом записи: «yes» есть истина наравне с «true»
	 */
	ASSERT_TRUE(value.at("/server/enabled").value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем проверку отказа извлечения числа из записи, числом не являющейся
	ASSERT_FALSE(value["title"].value(number));
	// Выполняем проверку отказа извлечения содержимого у вместилища пар
	ASSERT_FALSE(value["server"].value(text));
}

/**
 * @brief Проверка следования настройке выделения подраздела
 *
 * @details Выделяется ли подраздел вовсе - решает настройка разбора, и снятое значение
 *          ей следует. Расхождения тут нет: владеющее значение показывает то, что
 *          разобрало дерево
 *
 */
TEST(CodecIniValue, Subsections) {
	// Прочитанное значение при умолчании настройки
	ini::value_t plain;
	// Выполняем разбор текста настроек при умолчании настройки
	ASSERT_TRUE(plain.parse("[server.tls]\nenabled = yes\n"));
	// Извлекаемое логическое значение
	bool flag = false;
	/**
	 * Выполняем проверку того, что имя раздела взято целиком
	 *
	 * @note Умолчанием стоит `subsection_t::NONE`, и «[server.tls]» ложится одной парой
	 */
	ASSERT_TRUE(plain.at("/server.tls/enabled").value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем проверку того, что двумя уровнями значение не легло
	ASSERT_FALSE(plain.at("/server/tls/enabled").valid());
	// Настройки разбора с выделением подраздела
	ini::document_t::settings_t settings;
	// Выполняем установку выделения подраздела знаком-разделителем
	settings.reader.subsections = ini::subsection_t::DELIMITED;
	// Прочитанное значение при выделении подраздела
	ini::value_t split;
	// Выполняем разбор текста настроек при выделении подраздела
	ASSERT_TRUE(split.parse("[server.tls]\nenabled = yes\n", settings));
	// Выполняем проверку того, что значение легло двумя уровнями
	ASSERT_TRUE(split.at("/server/tls/enabled").value(flag));
	// Выполняем проверку извлечённого логического значения
	ASSERT_TRUE(flag);
	// Выполняем проверку того, что одной парой значение не легло
	ASSERT_FALSE(split.at("/server.tls/enabled").valid());
}

/**
 * @brief Проверка договора извлечения числа
 *
 * @details Отказом извлечение завершается лишь тогда, когда запись числом не является
 * вовсе, а дробное, извлекаемое целым видом, округляется по правилам математики с
 * уводом половины от нуля
 *
 * @note Договор этот общий у всех пяти кодеков рамки, и сличает их между собою
 *       `CodecContract.NumberExtraction`
 *
 */
TEST(CodecIniValue, Rounding) {
	// Прочитанное значение
	ini::value_t value;
	// Выполняем разбор текста настроек во владеющее значение
	ASSERT_TRUE(value.parse(
		"half = 1.5\nback = -1.5\ndown = 1.4\neven = 2.5\n"
		"far = 1e400\nnear = 1e-3\nport = 8080\nname = текст\n"
	));
	// Извлекаемое целое число
	int64_t number = 0;
	// Выполняем проверку увода половины от нуля при извлечении целым видом
	ASSERT_TRUE(value["half"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 2);
	// Выполняем проверку увода половины от нуля в отрицательную сторону
	ASSERT_TRUE(value["back"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, -2);
	// Выполняем проверку округления вниз
	ASSERT_TRUE(value["down"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 1);
	/**
	 * Выполняем проверку увода половины от нуля, а не к ближайшему чётному
	 *
	 * @note Случай этот отделяет `round` от `rint`: округление к ближайшему чётному
	 *       отдало бы здесь двойку, а увод половины от нуля даёт тройку
	 */
	ASSERT_TRUE(value["even"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 3);
	/**
	 * Выполняем проверку выдачи предела вида при числе вне его пределов
	 *
	 * @note Запись «1e400» разбирается бесконечностью, а не отвергается: она есть число,
	 *       и отвергать её значило бы разойтись с прочими кодеками рамки
	 */
	ASSERT_TRUE(value["far"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 9223372036854775807LL);
	// Выполняем проверку округления числа, меньшего половины, к нулю
	ASSERT_TRUE(value["near"].value(number));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(number, 0);
	// Извлекаемое целое число малой разрядности
	int8_t narrow = 0;
	// Выполняем проверку переноса младшими разрядами целого вне предела вида
	ASSERT_TRUE(value["port"].value(narrow));
	// Выполняем проверку извлечённого числа
	ASSERT_EQ(narrow, -112);
	// Выполняем проверку отказа извлечения числа из записи, числом не являющейся
	ASSERT_FALSE(value["name"].value(number));
}

/**
 * @brief Проверка правил сличения значений
 *
 */
TEST(CodecIniValue, Comparison) {
	// Первое сличаемое значение
	ini::value_t first;
	// Второе сличаемое значение
	ini::value_t second;
	// Выполняем разбор первого сличаемого значения
	ASSERT_TRUE(first.parse("alpha = 1\nbeta = 2\n"));
	// Выполняем разбор второго сличаемого значения
	ASSERT_TRUE(second.parse("beta = 2\nalpha = 1\n"));
	/**
	 * Выполняем проверку совпадения значений
	 *
	 * @note Порядок пар вместилища сличению НЕ подлежит: вместилище есть отображение
	 *       имён на значения, и порядок записи его значением не является
	 */
	ASSERT_TRUE(first == second);
	// Выполняем проверку отсутствия расхождения значений
	ASSERT_FALSE(first != second);
	// Третье сличаемое значение
	ini::value_t third;
	// Выполняем разбор третьего сличаемого значения
	ASSERT_TRUE(third.parse("tag = one\ntag = two\n"));
	// Четвёртое сличаемое значение
	ini::value_t fourth;
	// Выполняем разбор четвёртого сличаемого значения
	ASSERT_TRUE(fourth.parse("tag = two\ntag = one\n"));
	/**
	 * Выполняем проверку расхождения значений
	 *
	 * @note Порядок значений перечня сличению подлежит: перечень одноимённых значений
	 *       есть последовательность, и порядок объявления её значим
	 */
	ASSERT_TRUE(third != fourth);
	/**
	 * Выполняем проверку совпадения значений, записанных по-разному
	 *
	 * @note Признак записи в кавычках сличению не подлежит: кавычки суть оформление
	 *       записи, а не содержимое её
	 */
	ASSERT_TRUE(ini::value_t("текст", true) == ini::value_t("текст", false));
	// Выполняем проверку расхождения значений разных типов
	ASSERT_TRUE(ini::value_t("1") != ini::value_t(ini::type_t::ARRAY));
	// Выполняем проверку совпадения неопределённых значений
	ASSERT_TRUE(ini::value_t() == ini::value_t());
}

