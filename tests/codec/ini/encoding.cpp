/**
 * @brief Проверка кодировки Windows-1252
 *
 * @note Кодировка эта с ISO-8859-1 не совпадает: там, где у той управляющие знаки
 *       области C1, у неё знаки печатные
 *
 */
TEST(CodecIniEncoding, Windows1252) {
	// Выполняем проверку разбора названия кодировки
	ASSERT_EQ(ini::encoding("CP1252"), ini::encoding_t::CP1252);
	// Выполняем проверку разбора названия кодировки ISO-8859-1
	ASSERT_EQ(ini::encoding("ISO-8859-1"), ini::encoding_t::LATIN1);
	// Выполняем проверку названия кодировки
	ASSERT_EQ(string(ini::name(ini::encoding_t::CP1252)), "WINDOWS-1252");
	// Собираемые настройки разбора текста настроек
	ini::reader_t::settings_t settings;
	// Устанавливаем кодировку исходного текста
	settings.encoding = ini::encoding_t::CP1252;
	// Объект потокового чтения текста настроек
	ini::reader_t reader(::logger(), settings);
	// Собираемый текст настроек
	string text = "[a]\nk = ";
	// Выполняем добавление денежного знака евро
	text.push_back(static_cast <char> (0x80));
	// Выполняем добавление знака конца строки
	text.append(1, '\n');
	// Выполняем передачу текста настроек
	ASSERT_TRUE(reader.feed(text));
	// Признак получения свойства со значением
	bool received = false;
	/**
	 * Выполняем перебор всех событий разбора
	 */
	while(reader.next()){
		/**
		 * Если получено свойство со значением
		 */
		if(reader.event() == ini::event_t::PROPERTY){
			// Запоминаем признак получения свойства со значением
			received = true;
			// Выполняем проверку приведения знака к кодировке UTF-8
			ASSERT_EQ(reader.text(), "\u20ac");
		}
	}
	// Выполняем проверку получения свойства со значением
	ASSERT_TRUE(received);
	{
		// Объект потокового чтения текста настроек
		ini::reader_t reader(::logger(), settings);
		// Собираемый текст настроек
		string text = "[a]\nk = ";
		// Выполняем добавление неопределённого в кодировке значения
		text.push_back(static_cast <char> (0x81));
		// Выполняем добавление знака конца строки
		text.append(1, '\n');
		// Выполняем передачу текста настроек
		reader.feed(text);
		/**
		 * Выполняем перебор всех событий разбора
		 */
		while(reader.next());
		// Выполняем проверку отклонения неопределённого значения
		ASSERT_EQ(reader.error(), ini::error_t::INVALID_CHARACTER);
	}
}
/**
 * @brief Проверка приведения текста однобайтовыми кодировками
 *
 * @details Ветвь кодировки US-ASCII не исполнялась покрытием ни разу - ни на годном
 * тексте, ни на отказе, - а ветвь неисполненная обещания своего не даёт вовсе.
 * Отказы кодировок ISO-8859-1 и Windows-1252 не задевались ими же: у первой это
 * знак, тексту настроек не дозволенный, у второй - байт, кодировкой не определённый
 *
 * @note Кодировка навязывается объекту приведения настройкою: меткою порядка байтов
 *       однобайтовые кодировки не опознаются вовсе, и без навязывания разбор пошёл бы
 *       путём UTF-8
 *
 */
TEST(CodecIniEncoding, SingleByte) {
	// Приведённый текст настроек
	string result;
	/**
	 * Выполняем проверку приведения текста кодировкой US-ASCII
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем навязывание кодировки исходного текста
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::ASCII));
		// Выполняем проверку того, что приведение годного текста удалось
		ASSERT_TRUE(decoder.convert("key = value\n", 12, true, result));
		// Выполняем проверку сохранности приведённого текста
		ASSERT_EQ(result, "key = value\n");
	}
	/**
	 * Выполняем проверку отказа кодировки US-ASCII на байте за её пределами
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем навязывание кодировки исходного текста
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::ASCII));
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения текста с байтом за пределами кодировки
		ASSERT_FALSE(decoder.convert("k = \xC3\xA9\n", 7, true, result));
		// Выполняем проверку выданного кода ошибки приведения
		ASSERT_EQ(decoder.error(), ini::error_t::INVALID_ENCODING);
	}
	/**
	 * Выполняем проверку отказа кодировки US-ASCII на недозволенном знаке
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем навязывание кодировки исходного текста
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::ASCII));
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения текста с недозволенным знаком
		ASSERT_FALSE(decoder.convert("k = a\x01\n", 7, true, result));
		// Выполняем проверку выданного кода ошибки приведения
		ASSERT_EQ(decoder.error(), ini::error_t::INVALID_CHARACTER);
	}
	/**
	 * Выполняем проверку отказа кодировки ISO-8859-1 на недозволенном знаке
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем навязывание кодировки исходного текста
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::LATIN1));
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения текста с недозволенным знаком
		ASSERT_FALSE(decoder.convert("k = a\x01\n", 7, true, result));
		// Выполняем проверку выданного кода ошибки приведения
		ASSERT_EQ(decoder.error(), ini::error_t::INVALID_CHARACTER);
	}
	/**
	 * Выполняем проверку отказа кодировки Windows-1252 на неопределённом байте
	 *
	 * @note Байты 0x81, 0x8D, 0x8F, 0x90 и 0x9D кодировкою Windows-1252 не определены
	 *       вовсе: знака за ними нет, и приведение обязано отвечать отказом, а не
	 *       выдавать на их месте пустое значение
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем навязывание кодировки исходного текста
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::CP1252));
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения текста с неопределённым байтом
		ASSERT_FALSE(decoder.convert("k = \x81\n", 6, true, result));
		// Выполняем проверку выданного кода ошибки приведения
		ASSERT_EQ(decoder.error(), ini::error_t::INVALID_CHARACTER);
	}
}
/**
 * @brief Проверка отказа приведения текста, кодировкой UTF-16 построенного ошибочно
 *
 * @details Суррогатная пара это единственное место кодировки UTF-16, где негодность
 * узнаётся не по одному значению, а по двум подряд. Пути отказа эти покрытием не
 * задевались ни разу, а стало быть, и обещание отказа ничем не подтверждалось
 *
 * @note Всякий случай подаётся ДВАЖДЫ - целиком да по одному байту: пара, границей
 *       куска разорванная, собирается своим путём через удержанный байт
 *
 */
TEST(CodecIniEncoding, BrokenSurrogates) {
	// Приведённый текст настроек
	string result;
	/**
	 * Негодные последовательности значений, отказ приведения обязанные вызвать
	 */
	const vector <pair <string, string>> broken = {
		// Старший суррогат, младшим не продолженный
		{string("\xD8\x00\x00\x6B", 4),        "старший суррогат без младшего"},
		// Младший суррогат, старшим не предварённый
		{string("\xDC\x00", 2),                "младший суррогат без старшего"},
		// Старший суррогат, концом текста оборванный
		{string("\xD8\x00", 2),                "старший суррогат в конце текста"},
		// Одиночный байт, пары не составляющий
		{string("\x00\x6B\x00", 3),            "одиночный байт в конце текста"},
		// Управляющий знак, текстом настроек не дозволенный
		{string("\x00\x6B\x00\x01", 4),        "управляющий знак"}
	};
	/**
	 * Выполняем перебор негодных последовательностей значений
	 */
	for(const auto & item : broken){
		/**
		 * Выполняем перебор размеров куска подачи
		 */
		for(const size_t chunk : {static_cast <size_t> (0), static_cast <size_t> (1)}){
			// Объект приведения исходного текста к кодировке UTF-8
			ini::decoder_t decoder(::logger());
			// Выполняем навязывание кодировки исходного текста
			ASSERT_TRUE(decoder.encoding(ini::encoding_t::UTF16BE)) << item.second;
			// Признак успеха приведения негодного текста
			bool passed = true;
			// Выполняем очистку приведённого текста
			result.clear();
			// Получаем размер куска подачи исходного текста
			const size_t step = ((chunk == 0) ? item.first.size() : chunk);
			/**
			 * Выполняем подачу негодного текста кусками выбранного размера
			 */
			for(size_t i = 0; passed && (i < item.first.size()); i += step){
				// Получаем размер очередного куска исходного текста
				const size_t size = (((i + step) > item.first.size()) ? (item.first.size() - i) : step);
				// Выполняем приведение очередного куска исходного текста
				passed = decoder.convert(item.first.data() + i, size, ((i + size) >= item.first.size()), result);
			}
			// Выполняем проверку отказа приведения негодного текста
			ASSERT_FALSE(passed) << item.second << ", кусок " << chunk;
		}
	}
}
/**
 * @brief Проверка договора объекта приведения текста к кодировке UTF-8
 *
 * @details Объект приведения несёт обещания сверх самого приведения: он отвечает,
 * обнаружена ли метка порядка байтов, отказ его прилипает и повторной подачи не
 * принимает, а навязать кодировку дозволено лишь до начала приведения. Ни одно из
 * трёх покрытием не задевалось: выдача признака метки исполнялась ровно ноль раз
 *
 * @note Прилипание отказа поверяется подачей текста ГОДНОГО следом за негодным:
 *       прими объект её как ни в чём не бывало - и приведённый текст собрался бы из
 *       кусков по обе стороны пропущенного, а потребитель узнал бы о том лишь по коду
 *
 */
TEST(CodecIniEncoding, DecoderContract) {
	// Приведённый текст настроек
	string result;
	/**
	 * Выполняем проверку выдачи признака обнаружения метки порядка байтов
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Текст настроек с меткой порядка байтов кодировки UTF-8
		const string text = string("\xEF\xBB\xBF") + "k = 1\n";
		// Выполняем проверку того, что приведение текста удалось
		ASSERT_TRUE(decoder.convert(text.data(), text.size(), true, result));
		// Выполняем проверку того, что метка порядка байтов обнаружена
		ASSERT_TRUE(decoder.signature());
		// Выполняем проверку того, что метка порядка байтов снята с приведённого текста
		ASSERT_EQ(result, "k = 1\n");
	}
	/**
	 * Выполняем проверку того, что метка порядка байтов в тексте не обнаружена
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку того, что приведение текста удалось
		ASSERT_TRUE(decoder.convert("k = 1\n", 6, true, result));
		// Выполняем проверку того, что метка порядка байтов не обнаружена
		ASSERT_FALSE(decoder.signature());
	}
	/**
	 * Выполняем проверку прилипания отказа приведения
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку отказа приведения негодного текста
		ASSERT_FALSE(decoder.convert("\x80\x80\x80\x80", 4, false, result));
		// Выполняем проверку отказа повторной подачи текста годного
		ASSERT_FALSE(decoder.convert("k = 1\n", 6, true, result));
	}
	/**
	 * Выполняем проверку запрета навязывания кодировки после начала приведения
	 */
	{
		// Объект приведения исходного текста к кодировке UTF-8
		ini::decoder_t decoder(::logger());
		// Выполняем очистку приведённого текста
		result.clear();
		// Выполняем проверку того, что кодировка навязана до начала приведения
		ASSERT_TRUE(decoder.encoding(ini::encoding_t::UTF8));
		// Выполняем проверку того, что приведение текста удалось
		ASSERT_TRUE(decoder.convert("k = 1\n", 6, false, result));
		// Выполняем проверку отказа навязывания кодировки после начала приведения
		ASSERT_FALSE(decoder.encoding(ini::encoding_t::UTF16BE));
		// Выполняем проверку того, что навязанная прежде кодировка сохранена
		ASSERT_EQ(decoder.encoding(), ini::encoding_t::UTF8);
	}
}
