/**
 * @brief Проверка приведения текста в кодировке UTF-32
 *
 * @details Метка порядка байтов кодировки UTF-32 с обратным порядком открывается теми
 * же двумя байтами, что и метка UTF-16, и сличаться обязана прежде неё: иначе текст
 * читался бы парами байтов вместо четвёрок - с пустыми знаками между настоящими
 *
 * @note Нарезка перебирается от одного байта до семи намеренно: четвёрка байтов знака
 *       рвётся всякой из них по-своему, и удержание обрывка между кусками проверяется
 *       только так
 *
 */
TEST(CodecIniEncoding, Utf32) {
	// Приведённый к кодировке UTF-8 текст
	string result;
	// Код ошибки приведения
	ini::error_t error = ini::error_t::NONE;
	// Определённая кодировка исходного текста
	ini::encoding_t encoding = ini::encoding_t::NONE;
	/**
	 * Выполняем перебор порядков байтов кодировки
	 */
	for(uint8_t order = 0; order < 2; order++){
		// Получаем признак прямого порядка байтов кодировки
		const bool big = (order == 1);
		// Исходный текст в кодировке UTF-32
		const string input = (big ?
			string("\x00\x00\xFE\xFF" "\x00\x00\x00k" "\x00\x00\x00=" "\x00\x00\x04\x30", 16) :
			string("\xFF\xFE\x00\x00" "k\x00\x00\x00" "=\x00\x00\x00" "\x30\x04\x00\x00", 16)
		);
		/**
		 * Выполняем перебор размеров куска подаваемого текста
		 */
		for(size_t step = 1; step < 8; step++){
			// Выполняем приведение текста в кодировке UTF-32
			ASSERT_TRUE(::convert(input, step, result, error, encoding)) << big << " " << step;
			// Выполняем проверку приведённого текста
			ASSERT_EQ(result, "k=\xD0\xB0") << big << " " << step;
			// Выполняем проверку определённой кодировки исходного текста
			ASSERT_EQ(encoding, (big ? ini::encoding_t::UTF32BE : ini::encoding_t::UTF32LE)) << big << " " << step;
		}
	}
	// Исходный текст, оборванный посреди четвёрки байтов
	const string torn("\x00\x00\xFE\xFF" "\x00\x00\x00", 7);
	// Выполняем приведение текста, оборванного посреди четвёрки байтов
	ASSERT_FALSE(::convert(torn, 64, result, error, encoding));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, ini::error_t::INVALID_ENCODING);
	// Исходный текст с суррогатным кодовым значением
	const string surrogate("\x00\x00\xFE\xFF" "\x00\x00\xD8\x00", 8);
	// Выполняем приведение текста с суррогатным кодовым значением
	ASSERT_FALSE(::convert(surrogate, 64, result, error, encoding));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, ini::error_t::INVALID_ENCODING);
	// Исходный текст с кодовым значением свыше предела Юникода
	const string beyond("\x00\x00\xFE\xFF" "\x00\x11\x00\x00", 8);
	// Выполняем приведение текста с кодовым значением свыше предела Юникода
	ASSERT_FALSE(::convert(beyond, 64, result, error, encoding));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, ini::error_t::INVALID_ENCODING);
}
/**
 * @brief Проверка отказа знака, тексту настроек недопустимого, в кодировке UTF-32
 *
 * @details Кодовое значение, Юникоду принадлежащее, тексту настроек годится не всякое:
 * управляющие знаки областей C0 и C1 в нём незримы, и появление их означает либо
 * испорченный файл, либо попытку скрыть содержимое от читающего глазами. Отказ этот
 * отличен от отказа кодировки: байты прочитаны верно, ошибка не в них
 *
 * @note Строку эту пересечение трёх прогонов числило слепой: проверка UTF-32 подавала
 *       лишь суррогаты да значения свыше предела, а те отвергаются кодом кодировки
 *
 */
TEST(CodecIniEncoding, Utf32ForbiddenCharacter) {
	// Приведённый к кодировке UTF-8 текст
	string result;
	// Код ошибки приведения
	ini::error_t error = ini::error_t::NONE;
	// Определённая кодировка исходного текста
	ini::encoding_t encoding = ini::encoding_t::NONE;
	// Исходный текст с управляющим знаком области C1
	ASSERT_FALSE(::convert(string("\x00\x00\xFE\xFF" "\x00\x00\x00\x85", 8), 64, result, error, encoding));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, ini::error_t::INVALID_CHARACTER);
	// Исходный текст со знаком забоя
	ASSERT_FALSE(::convert(string("\x00\x00\xFE\xFF" "\x00\x00\x00\x7F", 8), 64, result, error, encoding));
	// Выполняем проверку кода ошибки приведения
	ASSERT_EQ(error, ini::error_t::INVALID_CHARACTER);
	/**
	 * Выполняем проверку того, что знак дозволенный принимается
	 *
	 * @note Заход этот стоит рядом нарочно: отказ, приходящий на всякий знак, отвечал бы
	 *       тому же ожиданию, и порча поверки осталась бы незамечена
	 */
	ASSERT_TRUE(::convert(string("\x00\x00\xFE\xFF" "\x00\x00\x00\x6B", 8), 64, result, error, encoding));
	// Выполняем проверку приведённого текста
	ASSERT_EQ(result, "k");
}
/**
 * @brief Проверка удержания непарного байта при пустом следующем куске
 *
 * @details Кусок исходного текста вправе прийти пустым - подачею без содержимого либо
 * пустым указателем, - и удержанный от прошлого куска байт пары обязан такой кусок
 * пережить: приведение его к паре с пустотою дало бы знак, которого в тексте нет
 *
 * @warning Заход этот замерен отладчиком, а не догадкой. Первая попытка подать три
 *          байта, затем пустой кусок, СТРОКУ НЕ ЗАДЕЛА: до опознания метки порядка
 *          байтов куски копятся, покуда их не наберётся четыре, и разбор получил все
 *          четыре разом - удержанного байта не осталось. Остановом видно было
 *          `_length == 0` при `size == 4`. Оттого первый кусок здесь пятибайтовый:
 *          опознание он проходит и один байт оставляет
 *
 */
TEST(CodecIniEncoding, HeldByteSurvivesEmptyChunk) {
	// Объект приведения исходного текста к кодировке UTF-8
	ini::decoder_t decoder(::logger());
	// Приведённый к кодировке UTF-8 текст
	string result;
	// Выполняем навязывание кодировки исходного текста
	ASSERT_TRUE(decoder.encoding(ini::encoding_t::UTF16BE));
	// Выполняем приведение пяти байтов: две пары и один удержанный
	ASSERT_TRUE(decoder.convert("\x00k\x00=\x00", 5, false, result));
	// Выполняем проверку того, что приведены обе полные пары
	ASSERT_EQ(result, "k=");
	// Выполняем приведение пустого куска
	ASSERT_TRUE(decoder.convert(nullptr, 0, false, result));
	// Выполняем проверку того, что пустой кусок приведённого текста не тронул
	ASSERT_EQ(result, "k=");
	// Выполняем приведение куска, удержанный байт достраивающего
	ASSERT_TRUE(decoder.convert("v", 1, true, result));
	// Выполняем проверку того, что удержанный байт пустой кусок пережил
	ASSERT_EQ(result, "k=v");
}
