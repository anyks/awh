/**
 * @brief Проверка описания всех кодов ошибок разбора
 *
 */
TEST(CodecIniCommon, Messages) {
	/**
	 * Выполняем перебор всех кодов ошибок разбора
	 */
	for(uint8_t i = 0; i <= static_cast <uint8_t> (ini::error_t::OVERFLOW_LIMIT); i++){
		// Получаем описание очередного кода ошибки разбора
		const char * message = ini::message(static_cast <ini::error_t> (i));
		// Выполняем проверку наличия описания кода ошибки
		ASSERT_NE(message, nullptr);
		// Выполняем проверку того, что описание кода ошибки не пусто
		ASSERT_FALSE(string(message).empty());
	}
}

/**
 * @brief Проверка названий кодировок и их обратного разбора
 *
 */
TEST(CodecIniCommon, Encodings) {
	/**
	 * Выполняем перебор всех поддерживаемых кодировок
	 */
	for(uint8_t i = static_cast <uint8_t> (ini::encoding_t::UTF8); i <= static_cast <uint8_t> (ini::encoding_t::CP1252); i++){
		// Получаем название очередной кодировки
		const string name(ini::name(static_cast <ini::encoding_t> (i)));
		// Выполняем проверку того, что название кодировки не пусто
		ASSERT_FALSE(name.empty());
		// Выполняем проверку обратного разбора названия кодировки
		ASSERT_EQ(ini::encoding(name), static_cast <ini::encoding_t> (i));
	}
	// Выполняем проверку разбора названия кодировки без учёта регистра
	ASSERT_EQ(ini::encoding("utf-8"), ini::encoding_t::UTF8);
	// Выполняем проверку разбора неизвестного названия кодировки
	ASSERT_EQ(ini::encoding("koi8-r"), ini::encoding_t::NONE);
	// Выполняем проверку разбора пустого названия кодировки
	ASSERT_EQ(ini::encoding(""), ini::encoding_t::NONE);
}

/**
 * @brief Проверка сличения имён разделов
 *
 */
TEST(CodecIniCommon, Names) {
	// Собираемое имя раздела
	ini::name_t first;
	// Устанавливаем имя раздела
	first.section = "server";
	// Устанавливаем имя подраздела
	first.subsection = "http";
	// Собираемое имя раздела для сличения
	ini::name_t second;
	// Устанавливаем имя раздела
	second.section = "server";
	// Устанавливаем имя подраздела
	second.subsection = "http";
	// Выполняем проверку совпадения имён разделов
	ASSERT_TRUE(first == second);
	// Выполняем проверку отсутствия расхождения имён разделов
	ASSERT_FALSE(first != second);
	// Выполняем проверку совпадения имени раздела с переданной парой
	ASSERT_TRUE(first.is("server", "http"));
	// Выполняем проверку расхождения имени раздела с иным именем подраздела
	ASSERT_FALSE(first.is("server", "tcp"));
	// Устанавливаем иное имя подраздела
	second.subsection = "tcp";
	// Выполняем проверку расхождения имён разделов
	ASSERT_TRUE(first != second);
	// Выполняем проверку отсутствия совпадения имён разделов
	ASSERT_FALSE(first == second);
}

/**
 * @brief Проверка разбора значений всех числовых видов
 *
 */
TEST(CodecIniCommon, Numeric) {
	// Разбираемое значение знакового однобайтового целого
	int8_t i8 = 0;
	// Выполняем проверку разбора знакового однобайтового целого
	ASSERT_TRUE(ini::numeric("-128", i8));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i8, -128);
	// Выполняем проверку отказа разбора при переполнении вида
	ASSERT_FALSE(ini::numeric("128", i8));
	// Разбираемое значение беззнакового однобайтового целого
	uint8_t u8 = 0;
	// Выполняем проверку разбора беззнакового однобайтового целого
	ASSERT_TRUE(ini::numeric("255", u8));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(u8, 255);
	// Выполняем проверку отказа разбора отрицательного значения
	ASSERT_FALSE(ini::numeric("-1", u8));
	// Разбираемое значение знакового двухбайтового целого
	int16_t i16 = 0;
	// Выполняем проверку разбора знакового двухбайтового целого
	ASSERT_TRUE(ini::numeric("-32768", i16));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i16, -32768);
	// Разбираемое значение беззнакового двухбайтового целого
	uint16_t u16 = 0;
	// Выполняем проверку разбора беззнакового двухбайтового целого
	ASSERT_TRUE(ini::numeric("65535", u16));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(u16, 65535);
	// Разбираемое значение знакового четырёхбайтового целого
	int32_t i32 = 0;
	// Выполняем проверку разбора знакового четырёхбайтового целого
	ASSERT_TRUE(ini::numeric("-2147483648", i32));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i32, -2147483648LL);
	// Разбираемое значение беззнакового четырёхбайтового целого
	uint32_t u32 = 0;
	// Выполняем проверку разбора беззнакового четырёхбайтового целого
	ASSERT_TRUE(ini::numeric("4294967295", u32));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(u32, 4294967295U);
	// Разбираемое значение знакового восьмибайтового целого
	int64_t i64 = 0;
	// Выполняем проверку разбора знакового восьмибайтового целого
	ASSERT_TRUE(ini::numeric("-9007199254740993", i64));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i64, -9007199254740993LL);
	// Разбираемое значение беззнакового восьмибайтового целого
	uint64_t u64 = 0;
	// Выполняем проверку разбора беззнакового восьмибайтового целого
	ASSERT_TRUE(ini::numeric("18446744073709551615", u64));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(u64, 18446744073709551615ULL);
	// Разбираемое значение числа с плавающей точкой одинарной точности
	float single = 0.f;
	// Выполняем проверку разбора числа с плавающей точкой одинарной точности
	ASSERT_TRUE(ini::numeric("0.5", single));
	// Выполняем проверку разобранного значения
	ASSERT_FLOAT_EQ(single, 0.5f);
	// Разбираемое значение числа с плавающей точкой двойной точности
	double couple = 0.;
	// Выполняем проверку разбора числа с плавающей точкой двойной точности
	ASSERT_TRUE(ini::numeric("-1.25e3", couple));
	// Выполняем проверку разобранного значения
	ASSERT_DOUBLE_EQ(couple, -1250.);
	// Выполняем проверку отказа разбора пустого значения
	ASSERT_FALSE(ini::numeric("", i32));
	// Выполняем проверку отказа разбора значения с хвостом
	ASSERT_FALSE(ini::numeric("12ab", i32));
}

/**
 * @brief Проверка разбора логических значений
 *
 */
TEST(CodecIniCommon, Boolean) {
	// Разбираемое логическое значение
	bool value = false;
	// Выполняем проверку разбора расширенных видов записи истины
	for(const string & text : {"true", "TRUE", "yes", "on", "1"}){
		// Выполняем проверку разбора очередной записи истины
		ASSERT_TRUE(ini::numeric(text, value));
		// Выполняем проверку разобранного значения
		ASSERT_TRUE(value);
	}
	// Выполняем проверку разбора расширенных видов записи лжи
	for(const string & text : {"false", "FALSE", "no", "off", "0"}){
		// Выполняем проверку разбора очередной записи лжи
		ASSERT_TRUE(ini::numeric(text, value));
		// Выполняем проверку разобранного значения
		ASSERT_FALSE(value);
	}
	// Выполняем проверку отказа разбора при строгом виде записи
	ASSERT_FALSE(ini::numeric("yes", value, ini::boolean_t::STRICT));
	// Выполняем проверку разбора истины при строгом виде записи
	ASSERT_TRUE(ini::numeric("true", value, ini::boolean_t::STRICT));
	// Выполняем проверку разобранного значения
	ASSERT_TRUE(value);
	// Выполняем проверку отказа разбора неизвестной записи
	ASSERT_FALSE(ini::numeric("maybe", value));
}
