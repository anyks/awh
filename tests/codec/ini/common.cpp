	ASSERT_EQ(i32, 2);
	// Выполняем проверку округления отрицательной дробной записи
	ASSERT_TRUE(ini::numeric("-1.5", i32));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i32, -2);
	// Выполняем проверку округления дробной записи вниз
	ASSERT_TRUE(ini::numeric("1.4", i32));
	// Выполняем проверку разобранного значения
	ASSERT_EQ(i32, 1);
