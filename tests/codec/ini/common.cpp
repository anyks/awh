/**
 * @brief Проверка описания всех кодов ошибок разбора
 *
 */
TEST(CodecIniCommon, Messages) {
	/**
	 * Выполняем перебор всех кодов ошибок разбора
	 *
	 * @warning Верхний предел перебора берётся ПОСЛЕДНИМ членом перечня, а не тем, что
	 *          стоял последним в день написания: перебор до OVERFLOW_LIMIT оставлял за
	 *          собою коды, заведённые после него, и описания их никем не проверялись
	 */
	for(uint8_t i = 0; i <= static_cast <uint8_t> (ini::error_t::STORAGE_EXHAUSTED); i++){
		// Получаем описание очередного кода ошибки разбора
		const char * message = ini::message(static_cast <ini::error_t> (i));
		// Выполняем проверку наличия описания кода ошибки
		ASSERT_NE(message, nullptr);
		// Выполняем проверку того, что описание кода ошибки не пусто
		ASSERT_FALSE(string(message).empty()) << static_cast <uint32_t> (i);
		/**
		 * Выполняем проверку того, что описание коду ОТВЕДЕНО, а не подставлено общим
		 *
		 * @warning Поверка эта обязательна: выдача описаний отвечает на код неизвестный
		 *          строкою «unknown error», и она не пуста - перебор, одну лишь пустоту
		 *          отвергающий, проходил бы и для кода, описания не имеющего вовсе.
		 *          Замерено срывом: со снесённым описанием STORAGE_EXHAUSTED прежний
		 *          перебор не падал, а у TOML и YAML тот же срыв проверку ронял
		 */
		ASSERT_STRNE(message, "unknown error") << static_cast <uint32_t> (i);
	}
}

/**
 * @brief Проверка названий кодировок и их обратного разбора
 *
 * @details Кодек, кодировку принимающий, обязан уметь и назвать её, и опознать по
 * названию: иначе потребитель, взявший название из настроек, обратить его в кодировку
 * ничем не может. Договор этот один у INI, TOML и YAML
 *
 * @warning Границей перебора стоит ПОСЛЕДНИЙ член перечня, а не имя кодировки, некогда
 *          бывшее последним: заведённая следом кодировка выпала бы из перебора молча.
 *          На этом проверка и попалась - UTF-32, приписанный за CP1252, не спрашивался
 *
 */
TEST(CodecIniCommon, Encodings) {
	/**
	 * Выполняем перебор всех поддерживаемых кодировок
	 */
	for(uint8_t i = static_cast <uint8_t> (ini::encoding_t::UTF8); i <= static_cast <uint8_t> (ini::encoding_t::UTF32BE); i++){
		// Получаем название очередной кодировки
		const string name(ini::name(static_cast <ini::encoding_t> (i)));
		// Выполняем проверку того, что название кодировки не пусто
		ASSERT_FALSE(name.empty());
		// Выполняем проверку обратного разбора названия кодировки
		ASSERT_EQ(ini::encoding(name), static_cast <ini::encoding_t> (i));
	}
	// Выполняем проверку разбора названия кодировки без учёта регистра
	ASSERT_EQ(ini::encoding("utf-8"), ini::encoding_t::UTF8);
	/**
	 * Выполняем проверку разбора названия кодировки без указания порядка байтов
	 *
	 * @note Порядок байтов в таком случае определяется меткой в начале текста, и
	 *       название разбирается в кодировку с прямым порядком лишь как основание
	 *       по умолчанию. Строку эту пересечение трёх прогонов числило слепой -
	 *       названия подавались лишь с порядком байтов
	 */
	ASSERT_EQ(ini::encoding("UTF-16"), ini::encoding_t::UTF16BE);
	// Выполняем проверку разбора названия кодировки UTF-32 без указания порядка байтов
	ASSERT_EQ(ini::encoding("UTF-32"), ini::encoding_t::UTF32BE);
	// Выполняем проверку разбора обиходного названия кодировки ISO-8859-1
	ASSERT_EQ(ini::encoding("latin1"), ini::encoding_t::LATIN1);
	// Выполняем проверку разбора неизвестного названия кодировки
	ASSERT_EQ(ini::encoding("koi8-r"), ini::encoding_t::NONE);
	// Выполняем проверку разбора пустого названия кодировки
	ASSERT_EQ(ini::encoding(""), ini::encoding_t::NONE);
}

/**
 * @brief Проверка сличения имён разделов
 *
 */
TEST(CodecIniCommon, Names) {
	// Собираемое имя раздела
	ini::name_t first;
	// Устанавливаем имя раздела
	first.section = "server";
	// Устанавливаем имя подраздела
	first.subsection = "http";
	// Собираемое имя раздела для сличения
	ini::name_t second;
	// Устанавливаем имя раздела
	second.section = "server";
	// Устанавливаем имя подраздела
	second.subsection = "http";
	// Выполняем проверку совпадения имён разделов
	ASSERT_TRUE(first == second);
	// Выполняем проверку отсутствия расхождения имён разделов
	ASSERT_FALSE(first != second);
	// Выполняем проверку совпадения имени раздела с переданной парой
	ASSERT_TRUE(first.is("server", "http"));
	// Выполняем проверку расхождения имени раздела с иным именем подраздела
	ASSERT_FALSE(first.is("server", "tcp"));
	// Устанавливаем иное имя подраздела
	second.subsection = "tcp";
	// Выполняем проверку расхождения имён разделов
	ASSERT_TRUE(first != second);
	// Выполняем проверку отсутствия совпадения имён разделов
	ASSERT_FALSE(first == second);
}

