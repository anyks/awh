		ini::writer_t writer(::logger(), writing);
		// Выполняем объявление раздела текста настроек
		ASSERT_TRUE(writer.section("раздел"));
		// Выполняем запись свойства со значением
		ASSERT_TRUE(writer.property("ключ", "значение"));
		// Выполняем дописывание примечания к строке свойства
		ASSERT_TRUE(writer.trailing("хвост"));
		// Выполняем проверку того, что примечание ушло отдельной строкой
		ASSERT_EQ(writer.text(), "[раздел]\nключ = значение\n; хвост\n") << writer.text();
