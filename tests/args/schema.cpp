	ASSERT_FALSE(schema.add("eq", '=', schema_t::value_t::NONE)) << "знак равенства принят коротким именем";
	ASSERT_FALSE(schema.add("dash", '-', schema_t::value_t::NONE)) << "тире принято коротким именем";
	ASSERT_FALSE(schema.add("space", ' ', schema_t::value_t::NONE)) << "пробел принят коротким именем";
	ASSERT_FALSE(schema.add("feed", '\n', schema_t::value_t::NONE)) << "перевод строки принят коротким именем";
