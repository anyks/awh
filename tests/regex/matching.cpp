/**
 * @brief Проверка отнесения выражений к нерегулярному подмножеству
 *
 */
TEST(Regex, Unsupported) {
	// Создаём набор выражений, требующих исполнения с возвратом
	const vector <const char *> items = {
		"(a)\\1", "(?=a)b", "(?<=a)b", "(?>a)b", "a++", "(?R)", "(a)(?1)",
		"(a)?(?(1)b|c)", "a\\Kb", "\\X", "(a*)*", "(|a)*"
	};
	/**
	 * Выполняем проверку отнесения выражений к нерегулярному подмножеству
	 */
	for(const auto & item : items) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parser.parse(item, 0)) << "Шаблон: " << item;
		// Создаём объект компиляции регулярного выражения
		regex::compiler_t compiler;
		// Создаём компилируемую программу регулярного выражения
		regex::program_t program;
		// Выполняем проверку отказа компиляции выражения
		EXPECT_FALSE(compiler.compile(parser, program)) << "Шаблон: " << item;
		// Выполняем проверку кода ошибки компиляции
		EXPECT_EQ(compiler.error(), regex::error_t::UNSUPPORTED) << "Шаблон: " << item;
	}
}

/**
 * @brief Проверка формирования предварительного отбора позиций
 *
 */
TEST(Regex, Prefilter) {
	/**
	 * @brief Проверяемый шаблон и ожидаемый предварительный отбор
	 *
	 */
	struct Item {
		// Текст проверяемого регулярного выражения
		const char * pattern;
		// Ожидаемый обязательный литерал совпадения
		const char * literal;
		// Ожидаемый флаг применимости набора допустимых байтов
		bool active;
		// Байты, обязанные присутствовать в наборе допустимых
		const char * allowed;
		// Байты, обязанные отсутствовать в наборе допустимых
		const char * denied;
	};
	// Создаём набор проверяемых шаблонов
	const vector <Item> items = {
		// Литерал извлекается из последовательности символов
		{"abc", "abc", true, "a", "bcz"},
		// Литерал извлекается из середины выражения
		{"\\w+@\\w+", "@", true, "az09_", "@ ."},
		// Литерал извлекается из обязательного повторения
		{"[0-9]+end", "end", true, "0459", "aez "},
		// Литерал не извлекается из необязательного повторения
		{"(abc)?xyz", "xyz", true, "ax", "bcyz"},
		// Литерал не извлекается из выбора одной из ветвей
		{"cat|dog", "", true, "cd", "atog"},
		// Сопоставление без учёта регистра исключает литерал
		{"(?i)abc", "", true, "aA", "bBcC"},
		// Класс символов задаёт набор допустимых байтов
		{"[xyz]+", "", true, "xyz", "abw0"},
		// Выражение с совпадением нулевой длины отбор не допускает
		{"a*", "", false, "", ""},
		// Выражение с необязательным началом отбор не допускает
		{"(abc)?", "", false, "", ""}
	};
	/**
	 * Выполняем проверку предварительного отбора для каждого шаблона
	 */
	for(const auto & item : items) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parser.parse(item.pattern, 0)) << "Шаблон: " << item.pattern;
		// Создаём объект компиляции регулярного выражения
		regex::compiler_t compiler;
		// Создаём компилируемую программу регулярного выражения
		regex::program_t program;
		// Выполняем компиляцию регулярного выражения
		ASSERT_TRUE(compiler.compile(parser, program)) << "Шаблон: " << item.pattern;
		// Выполняем проверку обязательного литерала совпадения
		EXPECT_EQ(program.prefilter.literal, string(item.literal)) << "Шаблон: " << item.pattern;
		// Выполняем проверку применимости набора допустимых байтов
		EXPECT_EQ(program.prefilter.active, item.active) << "Шаблон: " << item.pattern;
		/**
		 * Выполняем проверку присутствия байтов в наборе допустимых
		 */
		for(const char * letter = item.allowed; *letter != '\0'; letter++)
			// Выполняем проверку допустимости очередного байта
			EXPECT_TRUE(program.prefilter.bytes[static_cast <uint8_t> (*letter)])
				<< "Шаблон: " << item.pattern << ", байт: " << *letter;
		/**
		 * Выполняем проверку отсутствия байтов в наборе допустимых
		 */
		for(const char * letter = item.denied; *letter != '\0'; letter++)
			// Выполняем проверку недопустимости очередного байта
			EXPECT_FALSE(program.prefilter.bytes[static_cast <uint8_t> (*letter)])
				<< "Шаблон: " << item.pattern << ", байт: " << *letter;
	}
}

/**
 * @brief Проверка поиска последовательности у границ оборота вектора
 *
 * @details Проход текста ведётся вектором по тридцати двум байтам за оборот,
 *          а остаток короче того - средствами обычными. Границы эти
 *          и проверяются: текст короче оборота, текст ровно в оборот, остаток
 *          всякой длины от нуля до тридцати одного байта. Сличение с эталонным
 *          набором стенда сюда не годится - тексты его все длиннее сорока восьми
 *          килобайтов, и путь короткого текста там не исполняется вовсе.
 *
 */
TEST(Regex, PrefilterSeekBoundaries) {
	// Создаём набор искомых последовательностей
	const vector <string> needles = {
		"a", "ab", "abc", "abcd", "abcde", "abcdef", "abcdefg", "abcdefgh",
		"aab", "aaab", "ba", "bba", "abababab", "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaab"
	};
	// Количество выполненных сличений поиска
	size_t checks = 0;
	/**
	 * Выполняем обход длин текста сопоставления
	 *
	 * @details Длины покрывают оборот вектора целиком и с избытком: от текста
	 *          пустого до трёх оборотов с остатком.
	 *
	 */
	for(size_t length = 0; length <= 100; length++) {
		// Формируемый текст сопоставления
		string text;
		/**
		 * Выполняем наполнение текста сопоставления
		 *
		 * @details Наполнение ведётся двумя байтами: набор узкий даёт ложные
		 *          встречи пары байтов на всякой позиции, чем разбор встреч
		 *          и нагружается.
		 *
		 */
		for(size_t i = 0; i < length; i++)
			// Выполняем добавление очередного байта текста
			text.append(1, ((i % 3) == 0 ? 'b' : 'a'));
		/**
		 * Выполняем обход искомых последовательностей
		 */
		for(const auto & needle : needles) {
			/**
			 * Выполняем обход положений вставки искомой последовательности
			 *
			 * @details Положение, равное длине текста, означает текст
			 *          без вставки вовсе.
			 *
			 */
			for(size_t place = 0; place <= length; place++) {
				// Формируемый текст сопоставления со вставкой
				string body = text;
				/**
				 * Если искомая последовательность в текст помещается
				 */
				if((place < length) && ((place + needle.size()) <= length))
					// Выполняем вставку искомой последовательности в текст
					body.replace(place, needle.size(), needle);
				/**
				 * Выполняем обход позиций начала поиска
				 */
				for(size_t pos = 0; pos <= (length + 1); pos++) {
					// Выполняем поиск последовательности отбором позиций
					const size_t obtained = regex::seek(body, needle, pos);
					// Выполняем поиск последовательности средствами обычными
					const size_t expected = ((pos > body.size()) ?
					 string_view::npos : string_view(body).find(needle, pos));
					// Выполняем проверку совпадения итога поиска с эталонным
					ASSERT_EQ(obtained, expected) << "текст «" << body << "», искомое «"
					 << needle << "», позиция " << pos;
					// Увеличиваем количество выполненных сличений поиска
					checks++;
				}
			}
		}
	}
	// Выполняем проверку выполнения сличений поиска
	ASSERT_GT(checks, static_cast <size_t> (100000));
}
/**
 * @brief Проверка удаления обязательного литерала от начала совпадения
 *
 * @details Удаление есть наибольшее число байтов, какое способно предшествовать
 *          обязательному литералу внутри совпадения, и служит позиционному
 *          употреблению литерала: позиции до «вхождение минус удаление»
 *          пропускаются разом. Занижение удаления отвергло бы совпадения
 *          настоящие, отчего проверка сличает значения точно, а не пределом.
 *
 */
TEST(Regex, PrefilterDistance) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Набор выражений и ожидаемых удалений
	 *
	 */
	struct Item {
		// Текст проверяемого регулярного выражения
		const char * pattern;
		// Ожидаемый обязательный литерал совпадения
		const char * literal;
		// Ожидаемое удаление литерала от начала совпадения
		size_t distance;
	};
	// Создаём набор проверяемых выражений
	const vector <Item> items = {
		// Литерал в начале совпадения: удаление нулевое
		{"HTTP/", "HTTP/", 0}, {"^needle", "needle", 0}, {"needle$", "needle", 0},
		{"(?:foo)+bar", "foo", 0},
		// Литерал за узлами постоянной длины
		{"(?:HT|TP)/", "/", 2}, {"(?:HT|TPX)/", "/", 3}, {"a.c/def", "c/def", 2},
		{"(a)(b)needle", "needle", 2}, {"(?:x|yy)(?:z|ww)LIT", "LIT", 4},
		// Литерал за повторением с верхним пределом
		{"x{3}needle", "needle", 3}, {"x{0,5}needle", "needle", 5},
		{"a?b?c?TAIL", "TAIL", 3}, {"[0-9]{2,4}-KEY", "-KEY", 4},
		// Литерал за узлом неограниченной длины: удаление неограниченно
		{".*needle", "needle", string_view::npos},
		{"\\w+@\\w+\\.com", ".com", string_view::npos},
		{"(?:ab|cde)+z", "z", string_view::npos},
		{"(?:foo)*bar", "bar", string_view::npos}
	};
	/**
	 * Выполняем проверку каждого выражения набора
	 */
	for(const auto & item : items) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(item.pattern, 0, expression)) << item.pattern;
		// Получаем предварительный отбор позиций сопоставления
		const auto & prefilter = expression.forward.prefilter;
		// Выполняем проверку обязательного литерала совпадения
		ASSERT_EQ(prefilter.literal, string(item.literal)) << item.pattern;
		// Выполняем проверку удаления литерала от начала совпадения
		ASSERT_EQ(prefilter.distance, item.distance) << item.pattern;
	}
}
/**
 * @brief Проверка отбора позиции начала попытки по обязательному литералу
 *
 * @details Отбор отводит начало совпадения не далее чем за удаление до вхождения
 *          литерала. Проверка сличает границы, отбором полученные, с границами
 *          исполнения программы: пропуск позиции, совпадение несущей, вышел бы
 *          расхождением, а не замедлением, и замером его не обнаружить.
 *
 */
TEST(Regex, PrefilterBounded) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Набор выражений, отбору поддающихся
	 *
	 */
	const char * patterns[] = {
		"(?:HT|TP)/", "(?:HT|TPX)/", "a.c/def", "(a)(b)needle", "x{0,5}needle",
		"[0-9]{2,4}-KEY", "(?:x|yy)(?:z|ww)LIT", "HTTP/", "(?:foo)+bar",
		// Выражения, отбору не поддающиеся: удаление неограниченно либо литерала нет
		".*needle", "\\w+@\\w+\\.com", "(?:HT|TP)[0-9]", "(?i)needle"
	};
	/**
	 * @brief Набор текстов сопоставления
	 *
	 */
	const char * texts[] = {
		"", "/", "HT/", "TP/", "HTTP/1.1", "HTHTHTHT/", "HTHTHTHTHTHTHTHT/ 20",
		"zzz", "abc/def ghi", "aabbneedle", "xxxneedle", "needle", "42-KEY",
		"1234-KEY tail", "yyzLIT", "xwwLIT", "foobar", "foofoobar",
		"the quick brown fox needle jumps", "user@host.com", "HT7 tail", "/ HT/"
	};
	/**
	 * Выполняем проверку каждого выражения набора
	 */
	for(const char * pattern : patterns) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen(::logger());
		/**
		 * Если порождение сопоставителя выражения не выполнено
		 */
		if(expression.forward.plain || !codegen.compile(expression.forward))
			// Выполняем переход к выражению следующему
			continue;
		/**
		 * Выполняем проверку каждого текста сопоставления
		 */
		for(const char * value : texts) {
			// Получаем текст сопоставления регулярного выражения
			const string text(value);
			/**
			 * Выполняем обход позиций начала поиска совпадения
			 *
			 * @details Позиция начала поиска отбором обязана соблюдаться:
			 *          отбор вправе позиции пропускать, но не вправе
			 *          возвращать сопоставление к позициям, поиску
			 *          предшествующим.
			 *
			 */
			for(size_t start = 0; start <= text.size(); start++) {
				// Создаём набор границ совпадения порождённого сопоставителя
				vector <pair <size_t, size_t>> received;
				// Создаём набор границ совпадения исполнения программы
				vector <pair <size_t, size_t>> expected;
				// Признак отказа порождённого сопоставителя от сопоставления
				bool refusing = false;
				// Выполняем сопоставление текста порождённым машинным кодом
				const bool obtained = codegen.exec(text, start, received, refusing);
				/**
				 * Если порождённый сопоставитель от сопоставления отказался
				 */
				if(refusing)
					// Выполняем переход к позиции следующей
					continue;
				// Выполняем проверку совпадения итога с исполнением программы
				ASSERT_EQ(obtained, engine.exec(expression, text, start, expected))
					<< pattern << " по тексту «" << text << "» с позиции " << start;
				// Выполняем проверку совпадения границ с исполнением программы
				ASSERT_EQ(received, expected)
					<< pattern << " по тексту «" << text << "» с позиции " << start;
			}
		}
	}
}
/**
 * @brief Проверка позиционного отбора по обязательному литералу
 *
 * @details Разбор программы отбирает позиции начала попытки по обязательному
 *          литералу: совпадение обязано его содержать, и начало его не может
 *          лежать раньше, чем за удаление до ближайшего вхождения. Проверка
 *          закрепляет две стороны отбора разом.
 *
 *          Первая - что отбор совпадений НЕ ТЕРЯЕТ: границы совпадения обязаны
 *          быть теми же, какими они выходят у выражения, отбору не поддающегося.
 *
 *          Ловит она, однако, лишь потерю совпадения ПОЛНУЮ: отказ разбора
 *          программы подхватывает запасной путь исполнения, и вердикт с границами
 *          выходят верными даже при отборе испорченном - проверено порчей, ставившей
 *          в ветку отбора безусловный отказ. Договор самого отбора закрепляют
 *          проверки «PrefilterBounded» и «PrefilterDistance», зовущие его прямо.
 *
 *          Вторая - что выражение БЕЗ обязательного литерала отбором не задето.
 *          Удаление такому выражению достаётся нулевым, и отбор, на нуль
 *          положившийся, обрывал попытку в позиции конца текста - ту самую,
 *          где совпадение пустое и законно. Расхождение это вышло сличением
 *          с эталоном на выражении «\\Z[0-9]*?(?!\\d)», и здесь оно закреплено
 *          прямо, ибо сличение собирается не на всякой машине.
 *
 */
TEST(Regex, PrefilterBoundedPositional) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Совпадение пустое у конца текста
	 *
	 */
	{
		// Набор выражений, обязательного литерала не имеющих
		const char * patterns[] = {"\\Z[0-9]*?(?!\\d)", "$b*b?[0-9]*(?!\\d)", "[0-9]*", "b*b?"};
		/**
		 * Выполняем проверку каждого выражения набора
		 */
		for(const char * pattern : patterns) {
			// Создаём собираемое регулярное выражение
			regex::expression_t expression;
			// Выполняем сборку регулярного выражения
			ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
			// Создаём текст сопоставления
			const string text("0c1\nzyx");
			// Создаём набор границ обнаруженного совпадения
			vector <pair <size_t, size_t>> bounds;
			// Выполняем проверку обнаружения совпадения пустого
			ASSERT_TRUE(engine.exec(expression, text, 0, bounds)) << pattern;
		}
	}
	/**
	 * @brief Границы совпадения при отборе позиционном
	 *
	 * @details Текст несёт вхождения байтов начальных РАНЬШЕ совпадения:
	 *          отбор, литерал употребляющий, обязан их пропустить, а границы
	 *          вывести те же, что и перебор по одной позиции.
	 *
	 */
	{
		// Создаём собираемое выражение, отбору поддающееся
		regex::expression_t bounded;
		// Выполняем сборку выражения с обязательным литералом на удалении
		ASSERT_TRUE(engine.build("(?:HT|TP)/1", 0, bounded));
		/**
		 * @brief Набор текстов сопоставления
		 *
		 */
		const char * texts[] = {
			"GET /index.html HTTP/1.1", "TTTTTTHT/1", "HHHH TP/1 tail",
			"HT HT HT HT/1", "no match here", "TP/1", "HT/1"
		};
		/**
		 * Выполняем проверку каждого текста сопоставления
		 */
		for(const char * value : texts) {
			// Получаем текст сопоставления регулярного выражения
			const string text(value);
			/**
			 * Выполняем обход позиций начала поиска совпадения
			 */
			for(size_t start = 0; start <= text.size(); start++) {
				// Создаём набор границ обнаруженного совпадения
				vector <pair <size_t, size_t>> bounds;
				// Выполняем поиск совпадения выражением, отбору поддающимся
				const bool obtained = engine.exec(bounded, text, start, bounds);
				// Получаем положение совпадения поиском последовательностей
				const size_t first = text.find("HT/1", start);
				// Получаем положение совпадения второй ветви выражения
				const size_t second = text.find("TP/1", start);
				// Получаем ближайшее из положений обеих ветвей
				const size_t nearest = ((first < second) ? first : second);
				// Выполняем проверку вердикта сопоставления
				ASSERT_EQ(obtained, (nearest != string::npos))
					<< "«" << text << "» с позиции " << start;
				/**
				 * Если совпадение в тексте обнаружено
				 */
				if(obtained)
					// Выполняем проверку положения обнаруженного совпадения
					ASSERT_EQ(bounds.front().first, nearest)
						<< "«" << text << "» с позиции " << start;
			}
		}
	}
}
/**
 * @brief Проверка поиска ведущего литерала на текстах вырожденных
 *
 * @details Окно поиска проходится поиском байта первого с проверкой остатка
 *          в каждой находке, а вырождение его опознаётся счётом отвергнутых
 *          отборов и уступает поиску якорному. Проверка закрепляет верность
 *          обоих путей: положение совпадения обязано быть одним и тем же
 *          независимо от того, каким путём оно найдено. Числа замера
 *          закреплению не подлежат - их несёт отчёт сличения, - а закрепляется
 *          то, что переход на путь якорный совпадения не теряет.
 *
 */
TEST(Regex, PrefilterDegenerate) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Проверяемое выражение, наполнитель текста и положение совпадения
	 *
	 */
	struct Item {
		// Текст проверяемого регулярного выражения
		const char * pattern;
		// Байт, текстом заполняемый
		char filler;
		// Положение помещаемого совпадения
		size_t offset;
	};
	/**
	 * Набор проверяемых случаев
	 *
	 * @details Наполнитель, байту первому литерала равный, вырождает окно:
	 *          отбор срабатывает в каждой позиции и отвергается сличением
	 *          остатка. Положения взяты по обе стороны предела отвергнутых
	 *          отборов и по обе стороны окна.
	 *
	 */
	const vector <Item> items = {
		{"needle", '~', 0}, {"needle", '~', 40}, {"needle", '~', 1023},
		{"needle", '~', 1024}, {"needle", '~', 9000},
		{"needle", 'n', 0}, {"needle", 'n', 3}, {"needle", 'n', 40},
		{"needle", 'n', 1023}, {"needle", 'n', 1024}, {"needle", 'n', 9000},
		{"HTTP/", 'H', 0}, {"HTTP/", 'H', 12}, {"HTTP/", 'H', 5000}
	};
	/**
	 * Выполняем проверку поиска литерала для каждого случая
	 */
	for(const auto & item : items) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(item.pattern, 0, expression)) << item.pattern;
		// Получаем длину искомой последовательности
		const size_t length = ::strlen(item.pattern);
		// Создаём текст сопоставления длиною свыше окна поиска
		string text(10000, item.filler);
		// Выполняем помещение совпадения в текст сопоставления
		text.replace(item.offset, length, item.pattern);
		// Создаём набор границ обнаруженного совпадения
		vector <pair <size_t, size_t>> bounds;
		// Выполняем проверку обнаружения совпадения в тексте
		ASSERT_TRUE(engine.exec(expression, text, 0, bounds))
			<< item.pattern << " по тексту из «" << item.filler << "» на байте " << item.offset;
		/**
		 * Выполняем проверку положения обнаруженного совпадения
		 *
		 * @details Наполнитель, байту первому литерала равный, даёт совпадения
		 *          и прежде помещённого - «nnnneedle» несёт «needle» со второго
		 *          байта, - отчего сличается не положение помещения, а положение
		 *          первого совпадения, поиском по тексту выведенное.
		 *
		 */
		ASSERT_EQ(bounds.front().first, text.find(item.pattern))
			<< item.pattern << " по тексту из «" << item.filler << "» на байте " << item.offset;
	}
	/**
	 * @brief Поиск по обе стороны точки перехода на поиск якорный
	 *
	 * @details Окно проходится всегда, а порог решает лишь, окупает ли остаток
	 *          текста переход на поиск якорный. Точек перехода две - по счёту
	 *          отвергнутых отборов внутри окна и по исчерпании окна, - и обе
	 *          обязаны выдавать то же положение, что и поиск сплошной. Длины
	 *          взяты по обе стороны окна и порога, а положения совпадения -
	 *          внутри окна, на его границе и далеко за нею.
	 *
	 */
	{
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build("needle", 0, expression));
		/**
		 * Выполняем обход длин текста сопоставления
		 */
		for(const size_t length : {size_t(300), size_t(900), size_t(1100), size_t(2200), size_t(4400)}) {
			/**
			 * Выполняем обход положений помещаемого совпадения
			 */
			for(const size_t offset : {size_t(0), size_t(40), size_t(1000), size_t(1024), size_t(2048), size_t(4000)}) {
				/**
				 * Если положение совпадения тексту не принадлежит
				 */
				if((offset + 6) > length)
					// Выполняем переход к положению следующему
					continue;
				// Создаём текст сопоставления с частым первым байтом литерала
				string text;
				/**
				 * Выполняем наполнение текста сопоставления
				 */
				while(text.size() < length)
					// Выполняем добавление очередного участка текста
					text.append("the quick brown fox jumps over the lazy dog 1234 ");
				// Выполняем усечение текста до заданной длины
				text.resize(length);
				// Выполняем помещение совпадения в текст сопоставления
				text.replace(offset, 6, "needle");
				// Создаём набор границ обнаруженного совпадения
				vector <pair <size_t, size_t>> bounds;
				// Выполняем проверку обнаружения совпадения в тексте
				ASSERT_TRUE(engine.exec(expression, text, 0, bounds))
					<< "длина " << length << ", положение " << offset;
				// Выполняем проверку положения обнаруженного совпадения
				ASSERT_EQ(bounds.front().first, text.find("needle"))
					<< "длина " << length << ", положение " << offset;
			}
		}
	}
	/**
	 * @brief Литерал, текста длиннее
	 *
	 * @details Предел положения начала совпадения выводится вычитанием длины
	 *          искомого из длины текста, и литерал, текста длиннее, переполнил бы
	 *          его вниз: сличение остатка вышло бы за пределы текста.
	 *
	 */
	{
		// Создаём собираемое выражение с литералом, текста длиннее
		regex::expression_t lengthy;
		// Создаём образец выражения с литералом длинным
		const string pattern(6000, 'q');
		// Выполняем сборку выражения с литералом, текста длиннее
		ASSERT_TRUE(engine.build(pattern, 0, lengthy));
		// Создаём текст сопоставления, литерала короче
		const string text(5000, 'q');
		// Создаём набор границ обнаруженного совпадения
		vector <pair <size_t, size_t>> bounds;
		// Выполняем проверку отсутствия совпадения в тексте
		ASSERT_FALSE(engine.exec(lengthy, text, 0, bounds));
	}
}

/**
 * @brief Проверка свёртки ветвей выбора в один класс символов
 *
 * @details Выбор из одиночных символов и классов - «(?:\\w|-)» - есть тот же класс,
 *          объединением ветвей составленный. Свёрткой он в него и обращается:
 *          порождение иначе идёт дорогим путём записи прохода вместо дешёвого
 *          прохода ряда по таблице принадлежности байтов.
 *
 *          Закрепляются две стороны. Первая - что свёртка ПРОИСХОДИТ: программа
 *          свёрнутого выбора обязана совпасть с программой класса равносильного
 *          длиною. Вторая - что она НЕ ПРОИСХОДИТ там, где неверна: у ветви
 *          отрицательной, у ветви с захватом, у ветви из нескольких узлов и
 *          в режиме без учёта регистра символов.
 *
 */
TEST(Regex, AlternateFolding) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Пары выражений, свёртке подлежащих
	 *
	 */
	const pair <const char *, const char *> folded[] = {
		{"(?:a|b)+",      "[ab]+"},
		{"(?:\\w|-)+",     "[\\w-]+"},
		{"(?:[a-b]|c)+",  "[a-bc]+"},
		{"(?:a|b|c)z",    "[abc]z"},
		{"(?:a|b){2,3}",  "[ab]{2,3}"},
		/**
		 * Ветвь отрицательная: объединение её с положительной есть отрицание разности
		 *
		 * @details «¬A ∪ B = ¬(A \\ B)»: буква «a» из отрицаемого набора вычитается,
		 *          а буква, в нём и не стоявшая, оставляет набор прежним
		 */
		{"(?:a|[^ab])+",  "[^b]+"},
		{"(?:z|[^ab])+",  "[^ab]+"},
		{"(?:[^b]|b)+",   "[\\x00-\\x{10FFFF}]+"},
		{"(?:[a-f]|[^a-z])+", "[^g-z]+"}
	};
	/**
	 * Выполняем проверку каждой пары выражений
	 */
	for(const auto & item : folded) {
		// Создаём собираемое выражение со свёрткой ветвей
		regex::expression_t choice;
		// Создаём собираемое выражение класса равносильного
		regex::expression_t charclass;
		// Выполняем сборку выражения со свёрткой ветвей
		ASSERT_TRUE(engine.build(item.first, 0, choice)) << item.first;
		// Выполняем сборку выражения класса равносильного
		ASSERT_TRUE(engine.build(item.second, 0, charclass)) << item.second;
		// Выполняем проверку совпадения длины программ обоих выражений
		ASSERT_EQ(choice.forward.instructions.size(), charclass.forward.instructions.size())
			<< item.first << " против " << item.second;
	}
	/**
	 * @brief Набор выражений, свёртке НЕ подлежащих
	 *
	 */
	const pair <const char *, const char *> kept[] = {
		// Ветви отрицательные обе: отрицание объединения есть отрицание пересечения
		{"(?:[^a]|[^b])+", "[^a]+"},
		// Ветвь отрицательная со свойством Юникода: свойство вычитанию не подлежит
		{"(?:a|[^\\p{L}])+", "[^a]+"},
		// Ветвь с захватом: границы группы свёртка потеряла бы
		{"(?:(a)|b)+",    "[ab]+"},
		// Ветвь из нескольких узлов: одиночным символом она не является
		{"(?:ab|c)+",     "[abc]+"},
		// Режим без учёта регистра символов: множества ветвей выходят иными
		{"(?i)(?:a|B)+",  "[aB]+"}
	};
	/**
	 * Выполняем проверку каждого выражения набора
	 */
	for(const auto & item : kept) {
		// Создаём собираемое выражение выбора ветвей
		regex::expression_t choice;
		// Создаём собираемое выражение класса равносильного
		regex::expression_t charclass;
		// Выполняем сборку выражения выбора ветвей
		ASSERT_TRUE(engine.build(item.first, 0, choice)) << item.first;
		// Выполняем сборку выражения класса равносильного
		ASSERT_TRUE(engine.build(item.second, 0, charclass)) << item.second;
		// Выполняем проверку сохранения ветвей выбора в программе
		ASSERT_GT(choice.forward.instructions.size(), charclass.forward.instructions.size())
			<< item.first << " свёрнуто, а не должно";
	}
	/**
	 * @brief Набор текстов сопоставления
	 *
	 */
	const char * texts[] = {
		"", "a", "b", "c", "ab", "ba", "abc", "cba", "aabb", "-a-b-",
		"zzz", "a-b", "A", "B", "aB", "Ba", "abz", "cz", "abab"
	};
	/**
	 * Выполняем проверку совпадения итогов свёрнутого выбора и класса
	 */
	for(const auto & item : folded) {
		// Создаём собираемое выражение со свёрткой ветвей
		regex::expression_t choice;
		// Создаём собираемое выражение класса равносильного
		regex::expression_t charclass;
		// Выполняем сборку выражения со свёрткой ветвей
		ASSERT_TRUE(engine.build(item.first, 0, choice)) << item.first;
		// Выполняем сборку выражения класса равносильного
		ASSERT_TRUE(engine.build(item.second, 0, charclass)) << item.second;
		/**
		 * Выполняем проверку каждого текста сопоставления
		 */
		for(const char * value : texts) {
			// Получаем текст сопоставления регулярного выражения
			const string text(value);
			// Создаём набор границ совпадения свёрнутого выбора
			vector <pair <size_t, size_t>> received;
			// Создаём набор границ совпадения класса равносильного
			vector <pair <size_t, size_t>> expected;
			// Выполняем проверку совпадения вердикта сопоставления
			ASSERT_EQ(engine.exec(choice, text, 0, received), engine.exec(charclass, text, 0, expected))
				<< item.first << " по тексту «" << text << "»";
			/**
			 * Если совпадение в тексте обнаружено
			 */
			if(!received.empty() && !expected.empty())
				// Выполняем проверку совпадения границ совпадения
				ASSERT_EQ(received.front(), expected.front())
					<< item.first << " по тексту «" << text << "»";
		}
	}
}
