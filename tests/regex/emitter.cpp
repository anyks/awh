using namespace std;
using namespace awh;

/**
 * @brief Пространство имён вспомогательных значений проверки
 *
 */
namespace {
	/**
	 * @brief Тип вызова порождённого сопоставителя
	 *
	 * @details Соглашение о вызове порождённого кода: адрес текста, размер текста,
	 *          позиция начала попытки, адрес набора границ и адрес таблицы адресов
	 *          обстановки исполнения.
	 *
	 */
	typedef bool (* matcher_t) (const char *, size_t, size_t, size_t *, const void *);

	/**
	 * @brief Тип вызова порождённого вычислителя постоянных
	 *
	 */
	typedef uint64_t (* constant_t) ();

	/**
	 * @brief Функция порождения сопоставителя ряда байтов, принадлежащих таблице
	 *
	 * @details Порождаемый сопоставитель отыскивает первый байт, принадлежащий
	 *          таблице обстановки, и проходит ряд таких байтов до конца. Таблица
	 *          достигается смещением от регистра обстановки, чем и проверяется
	 *          перемещаемость порождённого кода.
	 *
	 * @param emitter объект порождения машинного кода
	 *
	 */
	void generate(regex::emitter_t & emitter) noexcept {
		// Подписываемся на перечисление регистров соглашения о вызове
		using reg_t = regex::emitter_t::reg_t;
		// Подписываемся на перечисление условий выполнения перехода
		using cond_t = regex::emitter_t::cond_t;
		// Заводим метку начала поиска первого подходящего байта
		const size_t search = emitter.label();
		// Заводим метку обнаружения первого подходящего байта
		const size_t found = emitter.label();
		// Заводим метку прохода ряда подходящих байтов
		const size_t scan = emitter.label();
		// Заводим метку завершения прохода ряда
		const size_t done = emitter.label();
		// Заводим метку отсутствия подходящего байта в тексте
		const size_t none = emitter.label();
		/**
		 * Выполняем размещение входа в порождаемый сопоставитель
		 *
		 * @details Сопоставитель занимает регистр второго промежуточного
		 *          значения, а тот в наборе команд x86-64 отведён регистру,
		 *          сохранность какого соглашение о вызове возлагает на сторону
		 *          вызываемую. Кадр вызова при этом не отводится - положений
		 *          отступления сопоставитель не ведёт, - отчего размер его
		 *          нулевой, но сохранение регистров нужно и при нём.
		 *
		 */
		emitter.prologue(0);
		// Выполняем установку позиции сопоставления в позицию начала попытки
		emitter.move(reg_t::CURSOR, reg_t::START);
		// Выполняем чтение адреса таблицы принадлежности байтов из обстановки
		emitter.context(reg_t::SCRATCH, 0);
		// Выполняем расстановку метки начала поиска
		emitter.place(search);
		// Выполняем сравнение позиции сопоставления с размером текста
		emitter.compare(reg_t::CURSOR, reg_t::SIZE);
		// Выполняем переход к отсутствию совпадения при достижении конца текста
		emitter.branch(cond_t::ABOVE, none);
		// Выполняем чтение байта текста в позиции сопоставления
		emitter.load(reg_t::LETTER, reg_t::TEXT, reg_t::CURSOR);
		// Выполняем чтение принадлежности байта таблице обстановки
		emitter.load(reg_t::SPARE, reg_t::SCRATCH, reg_t::LETTER);
		// Выполняем сравнение принадлежности байта с нулём
		emitter.compare(reg_t::SPARE, static_cast <uint32_t> (0));
		// Выполняем переход к обнаружению при принадлежности байта таблице
		emitter.branch(cond_t::NOTEQUAL, found);
		// Переходим к следующей позиции текста сопоставления
		emitter.add(reg_t::CURSOR, reg_t::CURSOR, 1);
		// Выполняем переход к продолжению поиска
		emitter.jump(search);
		// Выполняем расстановку метки обнаружения первого подходящего байта
		emitter.place(found);
		// Выполняем установку позиции начала обнаруженного совпадения
		emitter.move(reg_t::BEGIN, reg_t::CURSOR);
		// Выполняем расстановку метки прохода ряда подходящих байтов
		emitter.place(scan);
		// Переходим к следующей позиции текста сопоставления
		emitter.add(reg_t::CURSOR, reg_t::CURSOR, 1);
		// Выполняем сравнение позиции сопоставления с размером текста
		emitter.compare(reg_t::CURSOR, reg_t::SIZE);
		// Выполняем переход к завершению прохода при достижении конца текста
		emitter.branch(cond_t::ABOVE, done);
		// Выполняем чтение байта текста в позиции сопоставления
		emitter.load(reg_t::LETTER, reg_t::TEXT, reg_t::CURSOR);
		// Выполняем чтение принадлежности байта таблице обстановки
		emitter.load(reg_t::SPARE, reg_t::SCRATCH, reg_t::LETTER);
		// Выполняем сравнение принадлежности байта с нулём
		emitter.compare(reg_t::SPARE, static_cast <uint32_t> (0));
		// Выполняем переход к продолжению прохода при принадлежности байта таблице
		emitter.branch(cond_t::NOTEQUAL, scan);
		// Выполняем расстановку метки завершения прохода ряда
		emitter.place(done);
		// Выполняем запись начальной границы обнаруженного совпадения
		emitter.store(reg_t::BEGIN, reg_t::BOUNDS, 0);
		// Выполняем запись конечной границы обнаруженного совпадения
		emitter.store(reg_t::CURSOR, reg_t::BOUNDS, 1);
		// Выполняем размещение выхода из порождаемого сопоставителя
		emitter.epilogue(0);
		// Выполняем установку результата обнаружения совпадения
		emitter.move(reg_t::RESULT, static_cast <uint64_t> (1));
		// Выполняем размещение завершения вызова
		emitter.ret();
		// Выполняем расстановку метки отсутствия подходящего байта
		emitter.place(none);
		// Выполняем размещение выхода из порождаемого сопоставителя
		emitter.epilogue(0);
		// Выполняем установку результата отсутствия совпадения
		emitter.move(reg_t::RESULT, static_cast <uint64_t> (0));
		// Выполняем размещение завершения вызова
		emitter.ret();
	}
};

/**
 * @brief Проверка исполнения порождённого сопоставителя
 *
 * @details Проверка порождает сопоставитель ряда десятичных цифр, размещает его
 *          в исполняемой памяти и сличает установленные им границы с ожидаемыми.
 *          Таблица принадлежности байтов достигается смещением от регистра
 *          обстановки, поэтому проверка заодно подтверждает перемещаемость кода.
 *
 */
TEST(Regex, EmitterMatcher) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::assembly_t::available() || !regex::emitter_t::available())
		// Выходим из проверки исполнения порождённого сопоставителя
		GTEST_SKIP() << "порождение машинного кода сборкой не поддерживается";
	// Создаём объект порождения машинного кода
	regex::emitter_t emitter(::logger());
	// Выполняем порождение сопоставителя
	generate(emitter);
	// Выполняем проверку разрешения отложенных переходов
	ASSERT_TRUE(emitter.resolve());
	// Выполняем проверку отсутствия отказа порождения машинного кода
	ASSERT_FALSE(emitter.failed());
	// Создаём объект исполняемой памяти кодогенерации
	regex::assembly_t assembly(::logger());
	// Выполняем проверку размещения участка исполняемой памяти
	ASSERT_TRUE(assembly.allocate(emitter.length()));
	// Выполняем проверку наполнения участка порождённым машинным кодом
	ASSERT_TRUE(assembly.fill(emitter.code().data(), emitter.length()));
	// Выполняем проверку разрешения исполнения участка памяти
	ASSERT_TRUE(assembly.commit());
	// Создаём таблицу принадлежности значений байта десятичным цифрам
	uint8_t members[0x100];
	// Выполняем сброс таблицы принадлежности значений байта
	::memset(members, 0, sizeof(members));
	/**
	 * Выполняем наполнение таблицы принадлежности десятичными цифрами
	 */
	for(uint32_t i = 0x30; i <= 0x39; i++)
		// Выполняем установку принадлежности значения байта
		members[i] = 1;
	/**
	 * Создаём таблицу адресов обстановки исполнения
	 *
	 * @details Обстановка состоит из единственного адреса: порождённый код
	 *          прямых адресов не содержит и достигает таблицу через неё.
	 *
	 */
	const void * context[1] = {members};
	// Получаем вызов порождённого сопоставителя
	const matcher_t matcher = reinterpret_cast <matcher_t> (const_cast <void *> (assembly.entry()));
	/**
	 * @brief Набор текстов сопоставления и ожидаемых границ
	 *
	 */
	const struct {
		// Текст сопоставления
		const char * text;
		// Ожидаемый вердикт сопоставления
		bool matches;
		// Ожидаемая начальная граница совпадения
		size_t begin;
		// Ожидаемая конечная граница совпадения
		size_t finish;
	} samples[] = {
		// Ряд цифр в середине текста
		{"abc 12345 def", true, 4, 9},
		// Ряд цифр в начале текста
		{"42abc", true, 0, 2},
		// Ряд цифр в конце текста
		{"abc42", true, 3, 5},
		// Единственная цифра
		{"9", true, 0, 1},
		// Текст без цифр
		{"нет цифр", false, 0, 0},
		// Пустой текст
		{"", false, 0, 0}
	};
	/**
	 * Выполняем обход набора текстов сопоставления
	 */
	for(auto & sample : samples) {
		// Создаём набор границ обнаруженного совпадения
		size_t bounds[2] = {0, 0};
		// Выполняем сопоставление порождённым машинным кодом
		const bool result = matcher(sample.text, ::strlen(sample.text), 0, bounds, context);
		// Выполняем проверку вердикта сопоставления
		ASSERT_EQ(result, sample.matches) << sample.text;
		/**
		 * Если совпадение в тексте обнаружено
		 */
		if(sample.matches) {
			// Выполняем проверку начальной границы совпадения
			EXPECT_EQ(bounds[0], sample.begin) << sample.text;
			// Выполняем проверку конечной границы совпадения
			EXPECT_EQ(bounds[1], sample.finish) << sample.text;
		}
	}
	/**
	 * Выполняем проверку сопоставления с позиции, начало текста миновавшей
	 */
	size_t bounds[2] = {0, 0};
	// Выполняем сопоставление порождённым машинным кодом
	ASSERT_TRUE(matcher("12 34", 5, 2, bounds, context));
	// Выполняем проверку начальной границы совпадения
	EXPECT_EQ(bounds[0], static_cast <size_t> (3));
	// Выполняем проверку конечной границы совпадения
	EXPECT_EQ(bounds[1], static_cast <size_t> (5));
}
/**
 * @brief Проверка записи чисел в регистр порождённым кодом
 *
 * @details Число записывается по шестнадцать разрядов, отчего запись его зависит
 *          от величины: малое число размещается одной командой, а число, занимающее
 *          все разряды, - четырьмя. Проверка сличает выданное число с записанным.
 *
 */
TEST(Regex, EmitterConstants) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::assembly_t::available() || !regex::emitter_t::available())
		// Выходим из проверки записи чисел в регистр
		GTEST_SKIP() << "порождение машинного кода сборкой не поддерживается";
	/**
	 * @brief Набор проверяемых чисел
	 *
	 */
	const uint64_t samples[] = {
		// Числа, размещаемые единственной командой
		0ull, 1ull, 0xFFFFull,
		// Числа, требующие записи старших разрядов
		0x10000ull, 0xFFFF0000ull, 0x1234FFFFull,
		// Числа, занимающие все разряды регистра
		0xFFFFFFFFFFFFFFFFull, 0x0123456789ABCDEFull,
		// Число, содержащее нулевую часть посередине
		0xFFFF00000000FFFFull
	};
	/**
	 * Выполняем обход набора проверяемых чисел
	 */
	for(auto & sample : samples) {
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		/**
		 * Выполняем размещение входа в порождаемый код
		 *
		 * @note Вход нужен ради метки цели перехода, какую он размещает: управление
		 *       порождённому коду передаётся по адресу из регистра, а OpenBSD на ARM64
		 *       блюдёт расширение BTI и переход без метки валит отказом «Illegal
		 *       instruction». Кадр вызова коду этому не требуется, оттого он нулевой
		 */
		emitter.prologue(0);
		// Выполняем размещение записи числа в регистр итога
		emitter.move(regex::emitter_t::reg_t::RESULT, sample);
		/**
		 * Выполняем размещение выхода из порождённого кода
		 *
		 * @note Выход обязан быть парен входу, и нулевой кадр вызова от этого не
		 *       освобождает. У набора команд ARM64 вход при нулевом кадре размещает
		 *       одну лишь метку цели перехода, отчего непарный выход там ничем себя
		 *       не проявлял. У набора x86-64 вход сохраняет регистры, вызываемой
		 *       стороне доверенные, - пять у Windows и три у прочих систем, - и
		 *       завершение вызова без парного выхода снимало со стека сохранённый
		 *       регистр вместо адреса возврата, передавая управление в стек.
		 *       Обнаружено обрушением на стенде MS Windows x86-64
		 *
		 */
		emitter.epilogue(0);
		// Выполняем размещение завершения вызова
		emitter.ret();
		// Выполняем проверку разрешения отложенных переходов
		ASSERT_TRUE(emitter.resolve()) << sample;
		// Создаём объект исполняемой памяти кодогенерации
		regex::assembly_t assembly(::logger());
		// Выполняем проверку размещения участка исполняемой памяти
		ASSERT_TRUE(assembly.allocate(emitter.length())) << sample;
		// Выполняем проверку наполнения участка порождённым машинным кодом
		ASSERT_TRUE(assembly.fill(emitter.code().data(), emitter.length())) << sample;
		// Выполняем проверку разрешения исполнения участка памяти
		ASSERT_TRUE(assembly.commit()) << sample;
		// Получаем вызов порождённого вычислителя постоянных
		const constant_t constant = reinterpret_cast <constant_t> (const_cast <void *> (assembly.entry()));
		// Выполняем проверку выданного порождённым кодом числа
		EXPECT_EQ(constant(), sample);
	}
}
/**
 * @brief Проверка отказа порождения машинного кода
 *
 * @details Отказ обязан устанавливаться, а не обрезать довод: обрез смещения
 *          перехода дал бы переход в середину чужой команды - отказ, неотличимый
 *          от порчи памяти, а обрез числа дал бы неверное сопоставление.
 *
 */
TEST(Regex, EmitterFailure) {
	// Подписываемся на перечисление регистров соглашения о вызове
	using reg_t = regex::emitter_t::reg_t;
	// Подписываемся на перечисление условий выполнения перехода
	using cond_t = regex::emitter_t::cond_t;
	/**
	 * @brief Число, в поле команды не помещающееся
	 *
	 * @details Ширина поля - свойство набора команд, а не порождателя: в ARM64
	 *          число занимает двенадцать разрядов, а в x86-64 - тридцать два,
	 *          отчего число, первому не помещающееся, второму помещается
	 *          свободно. Проверка отказа обязана подавать число, полю
	 *          действующего набора команд не помещающееся, иначе она закрепляет
	 *          предел набора чужого - и на своём отказывает сама.
	 *
	 */
	#if defined(__x86_64__) || defined(_M_X64)
		// Число, полю команды набора x86-64 не помещающееся
		constexpr uint32_t OVERSIZE = 0x80000000u;
		// Номер места, полю смещения набора x86-64 не помещающийся
		constexpr uint32_t OVERINDEX = 0x10000000u;
	#else
		/**
		 * Число, командами набора ARM64 не укладываемое
		 *
		 * @details Величина свыше поля в двенадцать разрядов укладывается парой
		 *          команд: разряд сдвига несёт двенадцать старших разрядов её,
		 *          поле - двенадцать младших. Отказу подлежит потому лишь число
		 *          свыше двадцати четырёх разрядов - кадр в шестнадцать
		 *          мегабайтов стеку машины и без того непосилен.
		 *
		 */
		constexpr uint32_t OVERSIZE = 0x1000000u;
		// Номер места, полю смещения набора ARM64 не помещающийся
		constexpr uint32_t OVERINDEX = 0x1000u;
	#endif
	/**
	 * Выполняем проверку отказа на нерасставленной метке перехода
	 */
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Заводим метку перехода, положения не получающую
		const size_t label = emitter.label();
		// Выполняем размещение перехода к нерасставленной метке
		emitter.jump(label);
		// Выполняем размещение завершения вызова
		emitter.ret();
		// Выполняем проверку отказа разрешения отложенных переходов
		ASSERT_FALSE(emitter.resolve());
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	/**
	 * Выполняем проверку отказа на незаведённой метке перехода
	 */
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение перехода к незаведённой метке
		emitter.jump(0);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
		// Выполняем проверку отказа разрешения отложенных переходов
		ASSERT_FALSE(emitter.resolve());
	}
	/**
	 * Выполняем проверку отказа на незаведённой метке перехода по условию
	 */
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение перехода по условию к незаведённой метке
		emitter.branch(cond_t::EQUAL, 7);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	/**
	 * Выполняем проверку укладки величины крупной парой команд
	 *
	 * @details Величина свыше поля команды у ARM64 укладывается разрядом сдвига
	 *          и полем: старшие двенадцать разрядов уходят в первую команду,
	 *          младшие - во вторую. Проверка исполняет порождённое, а не сличает
	 *          слова команд: сличение закрепляло бы кодировку, тогда как
	 *          требуется от неё верный итог. Кадр в 7792 байта - тот самый,
	 *          какого требует образец адреса IPv6, и при пределе прежнем
	 *          он порождению не давался вовсе.
	 *
	 */
	if(regex::assembly_t::available() && regex::emitter_t::available()) {
		// Величины, полю команды не помещающиеся, но парой команд укладываемые
		const uint32_t values[] = {0x1000u, 0x1E70u, 0x2000u, 0xFFFFFu, 0xFFF000u};
		/**
		 * Выполняем обход укладываемых величин
		 */
		for(const uint32_t value : values) {
			// Создаём объект порождения машинного кода
			regex::emitter_t emitter(::logger());
			// Выполняем размещение входа в порождаемую подпрограмму
			emitter.prologue(0);
			// Выполняем размещение сложения довода вызова с крупной величиной
			emitter.add(reg_t::RESULT, reg_t::TEXT, value);
			// Выполняем размещение выхода из порождаемой подпрограммы
			emitter.epilogue(0);
			// Выполняем размещение завершения вызова
			emitter.ret();
			// Выполняем проверку отсутствия отказа порождения машинного кода
			ASSERT_FALSE(emitter.failed()) << "величина " << value;
			// Выполняем проверку разрешения отложенных переходов
			ASSERT_TRUE(emitter.resolve()) << "величина " << value;
			// Создаём объект исполняемой памяти кодогенерации
			regex::assembly_t assembly(::logger());
			// Выполняем проверку размещения участка исполняемой памяти
			ASSERT_TRUE(assembly.allocate(emitter.length())) << "величина " << value;
			// Выполняем проверку наполнения участка порождённым машинным кодом
			ASSERT_TRUE(assembly.fill(emitter.code().data(), emitter.length())) << "величина " << value;
			// Выполняем проверку разрешения исполнения участка памяти
			ASSERT_TRUE(assembly.commit()) << "величина " << value;
			// Получаем адрес порождённой подпрограммы сложения
			const auto adding = reinterpret_cast <size_t (*) (size_t)> (const_cast <void *> (assembly.entry()));
			// Выполняем проверку верности итога сложения
			ASSERT_EQ(adding(1000), (1000 + static_cast <size_t> (value))) << "величина " << value;
		}
	}
	/**
	 * Выполняем проверку отказа на доводах, в поля команд не помещающихся
	 */
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение сложения с числом, в поле команды не помещающимся
		emitter.add(reg_t::CURSOR, reg_t::CURSOR, OVERSIZE);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение вычитания числа, в поле команды не помещающегося
		emitter.sub(reg_t::CURSOR, reg_t::CURSOR, OVERSIZE);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение сравнения с числом, в поле команды не помещающимся
		emitter.compare(reg_t::CURSOR, OVERSIZE);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение чтения обстановки по номеру, в поле не помещающемуся
		emitter.context(reg_t::SCRATCH, OVERINDEX);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Выполняем размещение записи по номеру, в поле команды не помещающемуся
		emitter.store(reg_t::BEGIN, reg_t::BOUNDS, OVERINDEX);
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	/**
	 * Выполняем проверку отказа на смещении перехода, поле команды превышающем
	 *
	 * @details Условный переход набора ARM64 несёт девятнадцать разрядов
	 *          смещения, поэтому отказ вызывается кодом длиннее достижимого им.
	 *          Набор x86-64 несёт тридцать два разряда, и код такой длины
	 *          порождению в проверке не подлежит - он занял бы два гигабайта, -
	 *          отчего проверка эта ведётся лишь на ARM64.
	 *
	 */
	#if !defined(__x86_64__) && !defined(_M_X64)
	{
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter(::logger());
		// Заводим метку перехода за пределами достижимости
		const size_t label = emitter.label();
		// Выполняем размещение перехода по условию к далёкой метке
		emitter.branch(cond_t::EQUAL, label);
		/**
		 * Выполняем размещение кода, отдаляющего метку за пределы достижимости
		 */
		for(size_t i = 0; i < 0x40001; i++)
			// Выполняем размещение переноса значения регистра
			emitter.move(reg_t::CURSOR, reg_t::CURSOR);
		// Выполняем расстановку метки перехода
		emitter.place(label);
		// Выполняем размещение завершения вызова
		emitter.ret();
		// Выполняем проверку отказа разрешения отложенных переходов
		ASSERT_FALSE(emitter.resolve());
		// Выполняем проверку установки флага отказа порождения
		ASSERT_TRUE(emitter.failed());
	}
	#endif
}
/**
 * @brief Проверка очистки порождаемой последовательности команд
 *
 * @details Очистка обязана снимать и флаг отказа: иначе объект, однажды отказавший,
 *          оставался бы непригодным навсегда.
 *
 */
TEST(Regex, EmitterReuse) {
	// Создаём объект порождения машинного кода
	regex::emitter_t emitter(::logger());
	// Выполняем размещение перехода к незаведённой метке
	emitter.jump(0);
	// Выполняем проверку установки флага отказа порождения
	ASSERT_TRUE(emitter.failed());
	// Выполняем очистку порождаемой последовательности команд
	emitter.clear();
	// Выполняем проверку снятия флага отказа порождения
	ASSERT_FALSE(emitter.failed());
	// Выполняем проверку очистки порождённой последовательности команд
	ASSERT_EQ(emitter.length(), static_cast <size_t> (0));
	// Заводим метку завершения вызова
	const size_t label = emitter.label();
	// Выполняем размещение перехода к метке завершения вызова
	emitter.jump(label);
	// Выполняем расстановку метки завершения вызова
	emitter.place(label);
	// Выполняем размещение завершения вызова
	emitter.ret();
	// Выполняем проверку разрешения отложенных переходов
	ASSERT_TRUE(emitter.resolve());
	// Выполняем проверку отсутствия отказа порождения машинного кода
	ASSERT_FALSE(emitter.failed());
}

/**
 * @brief Проверка выдачи изъяна порождения в журнал событий
 *
 * @details Переход к метке, заведению не подвергшейся, означает несогласованность
 *          самого порождения, а не свойство выражения: наружу он выходит
 *          неотличимым от отказа законного - от числа, в поле команды
 *          не помещающегося, - и потребитель получил бы «кодогенерация
 *          неприменима» там, где на деле изъян. Проверка закрепляет, что
 *          беда эта журналом сообщается, а порождение без журнала молчит
 *
 */
TEST(RegexEmitter, DefectReachesTheLog) {
	// Объект фреймворка
	awh::fmk_t fmk;
	// Объект журнала с перехватом сообщений
	awh::log_t log(&fmk);
	// Перехваченное сообщение об изъяне
	string caught;
	// Перехваченный вид сообщения
	awh::log_t::flag_t flag = awh::log_t::flag_t::NONE;
	// Выполняем разрешение выдачи логов в функцию обратного вызова
	log.mode({awh::log_t::mode_t::DEFERRED});
	// Выполняем установку функции перехвата сообщений журнала
	log.subscribe([&caught, &flag](const awh::log_t::flag_t received, string_view text) noexcept -> void {
		// Запоминаем вид полученного сообщения
		flag = received;
		// Запоминаем полученное сообщение
		caught.assign(text.begin(), text.end());
	});
	/**
	 * Выполняем проверку выдачи изъяна порождением с журналом
	 */
	{
		// Создаём объект порождения машинного кода с журналом
		regex::emitter_t emitter(&log);
		// Выполняем размещение перехода к метке, заведению не подвергшейся
		emitter.jump(7);
		// Выполняем проверку установки признака отказа порождения
		ASSERT_TRUE(emitter.failed());
		// Выполняем проверку получения сообщения журналом
		ASSERT_FALSE(caught.empty());
		// Выполняем проверку вида полученного сообщения
		ASSERT_EQ(flag, awh::log_t::flag_t::CRITICAL);
		// Выполняем проверку упоминания номера метки в сообщении
		ASSERT_NE(caught.find("7"), string::npos) << caught;
	}
	// Выполняем очистку перехваченного сообщения
	caught.clear();
	/**
	 * Выполняем проверку молчания порождения без журнала
	 *
	 * @details Журнал модулю не навязывается: потребитель вправе его не заводить,
	 *          и порождение при этом обязано работать молча, а не падать
	 *
	 */
	{
		// Создаём объект порождения машинного кода без журнала
		regex::emitter_t emitter(nullptr);
		// Выполняем размещение перехода к метке, заведению не подвергшейся
		emitter.jump(7);
		// Выполняем проверку установки признака отказа порождения
		ASSERT_TRUE(emitter.failed());
		// Выполняем проверку молчания порождения без журнала
		ASSERT_TRUE(caught.empty()) << caught;
	}
}
