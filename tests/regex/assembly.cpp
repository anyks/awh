/**
 * @brief Пространство имён проверок этого файла
 *
 * @note Держится оно безымянным намеренно: проверки кодеков собираются одной
 *       программою, и одноимённые построения разных файлов иначе сходятся в
 *       одно, порождая порчу вдали от места её причины
 *
 */
namespace {
	/**
	 * @brief Объект журнала проверок с отключённым выводом
	 *
	 * @details Вывод отключается назначением пустого перечня приёмников: отказы
	 *          разбора проверки наводят намеренно, и журнал их засорял бы выдачу
	 *
	 */
	struct Silent {
		/**
		 * @brief Функция получения объекта фреймворка проверок
		 *
		 * @details Объект заводится статикою местною, а не общею файла: заведение его
		 *          порядком построения статики оканчивается падением ещё до входа в
		 *          проверки, ибо фреймворк сам опирается на статику из библиотеки
		 *
		 * @return объект фреймворка проверок
		 *
		 */
		static const awh::fmk_t & framework() noexcept {
			// Объект фреймворка проверок
			static awh::fmk_t fmk;
			// Выводим объект фреймворка проверок
			return fmk;
		}
		// Объект журнала проверок
		awh::log_t log;
		/**
		 * @brief Конструктор
		 *
		 */
		Silent() noexcept : log(&Silent::framework()) {
			// Выполняем отключение вывода логов
			this->log.mode({});
		}
	};
	/**
	 * @brief Функция получения объекта журнала проверок
	 *
	 * @return объект журнала проверок
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект журнала проверок
		static Silent silent;
		// Выводим объект журнала проверок
		return &silent.log;
	}
}

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Пространство имён вспомогательных значений проверки
 *
 */
namespace {
	/**
	 * @brief Тип вызова порождённого машинного кода
	 *
	 */
	typedef uint64_t (* adder_t) (uint64_t, uint64_t);

	/**
	 * @brief Машинный код сложения двух значений
	 *
	 * @details Код складывает первые два переданных значения и завершает вызов.
	 *          Проверка исполняет именно сложение затем, что итог его известен
	 *          заранее и не зависит ни от памяти, ни от состояния процессора.
	 *          Код приведён для каждого поддерживаемого набора команд отдельно:
	 *          средства размещения исполняемой памяти от набора команд не зависят
	 *          и подлежат проверке на всякой платформе, а не только на той,
	 *          что получила порождение машинного кода.
	 *
	 */
	#if defined(__aarch64__) || defined(_M_ARM64)
		/**
		 * Машинный код сложения набора команд ARM64
		 *
		 * @note Метка цели перехода «bti c» стоит впереди намеренно. Управление коду
		 *       этому передаётся по адресу из регистра, а расширение BTI требует, чтобы
		 *       такой переход приходил именно на метку. OpenBSD правило блюдёт и для
		 *       участков памяти, порождённым кодом занятых: без метки вызов валится
		 *       отказом «Illegal instruction», тогда как macOS, FreeBSD и NetBSD того
		 *       не требуют. Порождающий код метку размещает сам в Emitter::prologue,
		 *       а заглушка эта писана вручную - оттого и ставится здесь
		 *
		 * @warning Команда числится подсказкой и процессорами без BTI исполняется как
		 *          пустая, потому размещается всегда, а не под условием системы
		 *
		 */
		constexpr uint8_t ADDER[] = {
			0x5F, 0x24, 0x03, 0xD5, // bti c
			0x00, 0x00, 0x01, 0x8B, // add x0, x0, x1
			0xC0, 0x03, 0x5F, 0xD6  // ret
		};
	#elif defined(__x86_64__) || defined(_M_X64)
		/**
		 * Машинный код сложения набора команд x86-64
		 *
		 * @details Код приведён для каждого соглашения о вызове отдельно: набор команд
		 *          у систем один, а вот регистры, через которые передаются доводы, у
		 *          MS Windows и у остальных систем разные. Собери код для чужого
		 *          соглашения - он и выполнится, и вернёт значение, только сложит не
		 *          то, что передали, а содержимое посторонних регистров
		 *
		 */
		#if _WIN32 || _WIN64
			/**
			 * Машинный код сложения для соглашения о вызове MS Windows x64
			 *
			 * @details Первые два довода передаются в регистрах «rcx» и «rdx»,
			 *          а итог принимается в «rax»
			 *
			 */
			constexpr uint8_t ADDER[] = {
				0x48, 0x8D, 0x04, 0x11, // lea rax, [rcx + rdx]
				0xC3                    // ret
			};
		#else
			/**
			 * Машинный код сложения для соглашения о вызове System V
			 *
			 * @details Первые два довода передаются в регистрах «rdi» и «rsi»,
			 *          а итог принимается в «rax»
			 *
			 */
			constexpr uint8_t ADDER[] = {
				0x48, 0x8D, 0x04, 0x37, // lea rax, [rdi + rsi]
				0xC3                    // ret
			};
		#endif
	#else
		/**
		 * Машинный код сложения для прочих наборов команд отсутствует
		 *
		 */
		constexpr uint8_t ADDER[] = {0x00};
	#endif

	/**
	 * @brief Функция проверки наличия машинного кода набора команд
	 *
	 * @return результат проверки наличия машинного кода набора команд
	 *
	 */
	constexpr bool runnable() noexcept {
		/**
		 * Если сборка выполняется для поддерживаемого проверкой набора команд
		 */
		#if defined(__aarch64__) || defined(_M_ARM64) || defined(__x86_64__) || defined(_M_X64)
			// Выводим наличие машинного кода набора команд
			return true;
		/**
		 * Если сборка выполняется для прочих наборов команд
		 */
		#else
			// Выводим отсутствие машинного кода набора команд
			return false;
		#endif
	}
};

/**
 * @brief Проверка передачи управления порождённому машинному коду
 *
 * @details Проверка выполняется лишь на сборках, поддерживающих кодогенерацию:
 *          отсутствие поддержки изъяном не является и проверке не подлежит.
 *
 */
TEST(Regex, AssemblyExecution) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::assembly_t::available() || !runnable())
		// Выходим из проверки передачи управления
		GTEST_SKIP() << "исполняемая память сборкой не поддерживается";
	// Создаём объект исполняемой памяти кодогенерации
	regex::assembly_t assembly(::logger());
	// Выполняем проверку размещения участка исполняемой памяти
	ASSERT_TRUE(assembly.allocate(sizeof(ADDER)));
	/**
	 * Выполняем проверку запрета исполнения размещённого участка
	 *
	 * @details Участок, порождённым кодом не наполненный, исполнению не подлежит,
	 *          и адрес входа в него не выдаётся.
	 *
	 */
	ASSERT_FALSE(assembly.executable());
	ASSERT_EQ(assembly.entry(), nullptr);
	// Выполняем проверку наполнения участка порождённым машинным кодом
	ASSERT_TRUE(assembly.fill(ADDER, sizeof(ADDER)));
	// Выполняем проверку разрешения исполнения участка памяти
	ASSERT_TRUE(assembly.commit());
	// Выполняем проверку разрешения исполнения участка памяти
	ASSERT_TRUE(assembly.executable());
	// Выполняем проверку размера порождённого машинного кода
	ASSERT_EQ(assembly.length(), sizeof(ADDER));
	// Выполняем проверку выдачи адреса порождённого машинного кода
	ASSERT_NE(assembly.entry(), nullptr);
	// Получаем вызов порождённого машинного кода
	const adder_t adder = reinterpret_cast <adder_t> (const_cast <void *> (assembly.entry()));
	// Выполняем проверку итога порождённого машинного кода
	EXPECT_EQ(adder(40, 2), static_cast <uint64_t> (42));
	// Выполняем проверку итога порождённого машинного кода
	EXPECT_EQ(adder(1000, 337), static_cast <uint64_t> (1337));
	// Выполняем проверку итога порождённого машинного кода
	EXPECT_EQ(adder(0, 0), static_cast <uint64_t> (0));
}
/**
 * @brief Проверка раздельности записи и исполнения участка памяти
 *
 * @details Наполнение участка, исполнение какого разрешено, недопустимо: иначе
 *          порождённый код подменялся бы в памяти, которой уже передаётся управление.
 *
 */
TEST(Regex, AssemblyProtection) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::assembly_t::available() || !runnable())
		// Выходим из проверки раздельности записи и исполнения
		GTEST_SKIP() << "исполняемая память сборкой не поддерживается";
	// Создаём объект исполняемой памяти кодогенерации
	regex::assembly_t assembly(::logger());
	/**
	 * Выполняем проверку отказа наполнения неразмещённого участка
	 */
	ASSERT_FALSE(assembly.fill(ADDER, sizeof(ADDER)));
	// Выполняем проверку отказа разрешения исполнения неразмещённого участка
	ASSERT_FALSE(assembly.commit());
	// Выполняем проверку размещения участка исполняемой памяти
	ASSERT_TRUE(assembly.allocate(sizeof(ADDER)));
	/**
	 * Выполняем проверку отказа разрешения исполнения ненаполненного участка
	 */
	ASSERT_FALSE(assembly.commit());
	/**
	 * Выполняем проверку отказа наполнения кодом, участку не соразмерным
	 *
	 * @details Размер участка округляется до страницы памяти, поэтому предел
	 *          проверяется размером заведомо большим страницы.
	 *
	 */
	ASSERT_FALSE(assembly.fill(ADDER, 0x100000));
	// Выполняем проверку отказа наполнения пустым кодом
	ASSERT_FALSE(assembly.fill(ADDER, 0));
	// Выполняем проверку отказа наполнения отсутствующим кодом
	ASSERT_FALSE(assembly.fill(nullptr, sizeof(ADDER)));
	// Выполняем проверку наполнения участка порождённым машинным кодом
	ASSERT_TRUE(assembly.fill(ADDER, sizeof(ADDER)));
	// Выполняем проверку разрешения исполнения участка памяти
	ASSERT_TRUE(assembly.commit());
	/**
	 * Выполняем проверку отказа наполнения исполняемого участка
	 */
	ASSERT_FALSE(assembly.fill(ADDER, sizeof(ADDER)));
	/**
	 * Выполняем проверку повторного разрешения исполнения
	 *
	 * @details Повторное разрешение отказом не является: состояние участка
	 *          от него не изменяется.
	 *
	 */
	ASSERT_TRUE(assembly.commit());
	// Выполняем освобождение участка исполняемой памяти
	assembly.release();
	// Выполняем проверку запрета исполнения освобождённого участка
	ASSERT_FALSE(assembly.executable());
	// Выполняем проверку отсутствия адреса освобождённого участка
	ASSERT_EQ(assembly.entry(), nullptr);
}
/**
 * @brief Проверка передачи владения участком памяти при перемещении
 *
 * @details Владение участком единоличное, поэтому перемещение обязано оставить
 *          источник без участка: иначе участок освобождался бы дважды.
 *
 */
TEST(Regex, AssemblyOwnership) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::assembly_t::available() || !runnable())
		// Выходим из проверки передачи владения участком памяти
		GTEST_SKIP() << "исполняемая память сборкой не поддерживается";
	// Создаём объект исполняемой памяти кодогенерации
	regex::assembly_t source(::logger());
	// Выполняем проверку размещения участка исполняемой памяти
	ASSERT_TRUE(source.allocate(sizeof(ADDER)));
	// Выполняем проверку наполнения участка порождённым машинным кодом
	ASSERT_TRUE(source.fill(ADDER, sizeof(ADDER)));
	// Выполняем проверку разрешения исполнения участка памяти
	ASSERT_TRUE(source.commit());
	// Получаем адрес порождённого машинного кода
	const void * address = source.entry();
	// Выполняем перемещение объекта исполняемой памяти
	regex::assembly_t target(std::move(source));
	// Выполняем проверку сохранения адреса порождённого кода приёмником
	ASSERT_EQ(target.entry(), address);
	// Выполняем проверку утраты участка памяти источником
	ASSERT_EQ(source.entry(), nullptr);
	// Выполняем проверку утраты размера порождённого кода источником
	ASSERT_EQ(source.length(), static_cast <size_t> (0));
	// Выполняем проверку исполнимости перемещённого участка памяти
	EXPECT_EQ(reinterpret_cast <adder_t> (const_cast <void *> (target.entry()))(5, 7), static_cast <uint64_t> (12));
	// Создаём объект исполняемой памяти для проверки оператора перемещения
	regex::assembly_t moved(::logger());
	// Выполняем проверку размещения участка исполняемой памяти
	ASSERT_TRUE(moved.allocate(sizeof(ADDER)));
	// Выполняем перемещение объекта исполняемой памяти оператором
	moved = std::move(target);
	// Выполняем проверку сохранения адреса порождённого кода приёмником
	ASSERT_EQ(moved.entry(), address);
	// Выполняем проверку утраты участка памяти источником
	ASSERT_EQ(target.entry(), nullptr);
	// Выполняем проверку исполнимости перемещённого участка памяти
	EXPECT_EQ(reinterpret_cast <adder_t> (const_cast <void *> (moved.entry()))(11, 31), static_cast <uint64_t> (42));
}
