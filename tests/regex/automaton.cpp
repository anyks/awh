/**
 * @brief Проверка сохранения вердикта при повторном исполнении программы
 *
 */
TEST(Regex, AutomatonCache) {
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	// Выполняем разбор регулярного выражения
	ASSERT_TRUE(parser.parse("^[a-z]+[0-9]{2,4}$", 0));
	// Создаём объект компиляции регулярного выражения
	regex::compiler_t compiler;
	// Создаём компилируемую программу регулярного выражения
	regex::program_t program;
	// Выполняем компиляцию регулярного выражения
	ASSERT_TRUE(compiler.compile(parser, program));
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	/**
	 * Выполняем многократное исполнение программы на различных текстах
	 *
	 * @details Кэш состояний сохраняется между вызовами, поэтому повторное
	 *          исполнение обязано давать тот же вердикт, что и первое.
	 *
	 */
	for(size_t i = 0; i < 4; i++) {
		// Выполняем проверку вердикта на соответствующем тексте
		EXPECT_TRUE(dfa.test(program, "abc123", 0));
		// Выполняем проверку вердикта на тексте с недостаточным числом цифр
		EXPECT_FALSE(dfa.test(program, "abc1", 0));
		// Выполняем проверку вердикта на тексте с избыточным числом цифр
		EXPECT_FALSE(dfa.test(program, "abc123456", 0));
		// Выполняем проверку вердикта на тексте без букв
		EXPECT_FALSE(dfa.test(program, "123", 0));
	}
}

/**
 * @brief Проверка обновления арены узлов при смене объекта разбора
 *
 * @details Построитель сберегает арену узлов синтаксического дерева указателем,
 *          чтобы извлечение узла по индексу встраивалось на месте обращения.
 *          Указатель этот обязан обновляться при каждой компиляции: один и тот
 *          же построитель принимает объекты разбора разные, и арена, оставшаяся
 *          от разбора предыдущего, дала бы программу чужого выражения. Проверка
 *          ведёт компиляцию поочерёдно тремя объектами разбора одним построителем
 *          и сличает вердикт каждой программы с её собственным выражением.
 *
 */
TEST(Regex, AutomatonArena) {
	/**
	 * @brief Набор выражений с текстами совпадающими и несовпадающими
	 *
	 */
	static const struct {
		// Регулярное выражение, подлежащее компиляции
		const char * pattern;
		// Текст, выражению соответствующий
		const char * matched;
		// Текст, выражению не соответствующий
		const char * missed;
	} SAMPLES[] = {
		{"^(?:[a-z]+[0-9]{2,4}[._-])+end$", "abc123.def45-end", "abc1end"},
		{"^[0-9]+$", "90210", "90210a"},
		{"^(?:aa|bb|cc)+$", "aabbcc", "aabbc"}
	};
	// Создаём объект компиляции регулярного выражения
	regex::compiler_t compiler;
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	/**
	 * Заводим набор объектов разбора, живущих одновременно
	 *
	 * @details Объекты разбора заводятся все разом намеренно: объект,
	 *          заведённый на время одного витка обхода, занял бы по
	 *          освобождении своём место объекта следующего, и арена,
	 *          от разбора предыдущего оставшаяся, оказалась бы ареной
	 *          верной по случайности размещения.
	 *
	 */
	vector <unique_ptr <regex::parser_t>> parsers;
	/**
	 * Выполняем разбор всех выражений набора
	 */
	for(auto & sample : SAMPLES) {
		// Выполняем добавление объекта разбора в набор
		parsers.push_back(unique_ptr <regex::parser_t> (new regex::parser_t));
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parsers.back()->parse(sample.pattern, 0)) << sample.pattern;
	}
	/**
	 * Выполняем компиляцию всех выражений набора одним построителем
	 */
	for(size_t i = 0; i < parsers.size(); i++) {
		// Создаём компилируемую программу регулярного выражения
		regex::program_t program;
		// Выполняем компиляцию регулярного выражения
		ASSERT_TRUE(compiler.compile(* parsers.at(i), program)) << SAMPLES[i].pattern;
		// Выполняем проверку вердикта на соответствующем тексте
		EXPECT_TRUE(dfa.test(program, SAMPLES[i].matched, 0)) << SAMPLES[i].pattern;
		// Выполняем проверку вердикта на тексте несоответствующем
		EXPECT_FALSE(dfa.test(program, SAMPLES[i].missed, 0)) << SAMPLES[i].pattern;
	}
}

/**
 * @brief Проверка независимости выданной программы от сберегательной
 *
 * @details Построение ведётся над программой сберегательной, построителю
 *          принадлежащей, а вызывающей стороне итог достаётся присвоением.
 *          Программа, единожды выданная, обязана пережить всякое построение
 *          последующее: наборы её содержимым владеют сами и участков
 *          сберегательной программы не обозревают. Проверка строит выражения
 *          одно за другим одним построителем и сличает вердикт всякой ранее
 *          выданной программы после каждого построения нового.
 *
 */
TEST(Regex, AutomatonScratch) {
	/**
	 * @brief Набор выражений с текстами совпадающими и несовпадающими
	 *
	 */
	static const struct {
		// Регулярное выражение, подлежащее компиляции
		const char * pattern;
		// Текст, выражению соответствующий
		const char * matched;
		// Текст, выражению не соответствующий
		const char * missed;
	} SAMPLES[] = {
		{"^[0-9]+$", "90210", "90210a"},
		{"^(?:[a-z]+[0-9]{2,8}[._-]){2,}end$", "abc123.def45678-end", "abc12.end"},
		{"^(?:aa|bb|cc)+$", "aabbcc", "aabbc"},
		{"^[\\w.-]+@[\\w-]+\\.[a-z]{2,4}$", "forman@anyks.com", "forman@anyks"}
	};
	// Создаём объект компиляции регулярного выражения
	regex::compiler_t compiler;
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	// Заводим набор выданных построителем программ
	vector <regex::program_t> programs;
	/**
	 * Выполняем обход набора выражений
	 */
	for(size_t i = 0; i < (sizeof(SAMPLES) / sizeof(SAMPLES[0])); i++) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parser.parse(SAMPLES[i].pattern, 0)) << SAMPLES[i].pattern;
		// Заводим место под выдаваемую программу
		programs.resize(i + 1);
		// Выполняем компиляцию регулярного выражения
		ASSERT_TRUE(compiler.compile(parser, programs.at(i))) << SAMPLES[i].pattern;
		/**
		 * Выполняем сличение вердиктов всех выданных ранее программ
		 *
		 * @details Программы сличаются после каждого построения нового:
		 *          построение, участки сберегательной программы выдавшее,
		 *          сорвало бы вердикт программы, выданной прежде.
		 *
		 */
		for(size_t j = 0; j <= i; j++) {
			// Выполняем проверку вердикта на соответствующем тексте
			EXPECT_TRUE(dfa.test(programs.at(j), SAMPLES[j].matched, 0)) << SAMPLES[j].pattern;
			// Выполняем проверку вердикта на тексте несоответствующем
			EXPECT_FALSE(dfa.test(programs.at(j), SAMPLES[j].missed, 0)) << SAMPLES[j].pattern;
		}
	}
}

/**
 * @brief Проверка отказа автомата от программ, ему неприменимых
 *
 * @details Детерминированное исполнение работает над байтами и потому неприменимо
 *          к выражениям режима разбора UTF-8 и к классам со свойствами Юникода:
 *          там один символ занимает несколько байтов, а принадлежность его классу
 *          побайтно не решается. Заслон применимости - сторож правильности,
 *          а не ускоритель: без него проход выдал бы вердикт, разбору символов
 *          не отвечающий.
 *
 *          Проба гашения показала, что снятие заслона не срывало ни одной
 *          проверки набора: движок сам зовёт автомат лишь для программ годных,
 *          и заслон стерёг обращение стороннее - то самое, каким пользуется
 *          потребитель библиотеки.
 *
 */
TEST(Regex, AutomatonRefusal) {
	/**
	 * @brief Набор выражений, детерминированному исполнению неприменимых
	 *
	 */
	static const struct {
		// Регулярное выражение, подлежащее сборке
		const char * pattern;
		// Набор режимов сборки регулярного выражения
		const uint32_t flags;
		// Текст, выражению соответствующий
		const char * text;
	} SAMPLES[] = {
		{"[а-я]+",   static_cast <uint32_t> (regex::flag_t::UTF), "русский"},
		{"[a-z]+",   static_cast <uint32_t> (regex::flag_t::UTF), "latin"},
		{"\\p{L}+",  static_cast <uint32_t> (regex::flag_t::UTF), "буквы"}
	};
	// Создаём объект журнала событий
	log_t log(nullptr);
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(&log);
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	// Количество выражений, заслоном отвергнутых
	size_t refused = 0;
	/**
	 * Выполняем обход набора выражений
	 */
	for(auto & sample : SAMPLES) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		/**
		 * Если сборка регулярного выражения не выполнена
		 */
		if(!engine.build(sample.pattern, sample.flags, expression))
			// Переходим к следующему выражению набора
			continue;
		// Выполняем проверку неприменимости детерминированного исполнения
		ASSERT_FALSE(dfa.available(expression.forward)) << sample.pattern;
		// Выполняем учёт выражения, заслоном отвергнутого
		refused++;
		/**
		 * Выполняем проверку отказа прохода по тексту
		 *
		 * @details Текст выражению отвечает, и проход, заслона лишённый, выдал бы
		 *          наличие совпадения: отказ здесь и есть предмет проверки.
		 *
		 */
		EXPECT_FALSE(dfa.test(expression.forward, sample.text, 0)) << sample.pattern;
		// Позиция завершения обнаруженного совпадения
		size_t finish = 0;
		// Выполняем проверку отказа поиска совпадения
		EXPECT_FALSE(dfa.search(expression.forward, sample.text, 0, finish)) << sample.pattern;
	}
	/**
	 * Выполняем проверку охвата набора выражений
	 *
	 * @details Проверка охвата обязательна: сборка, всякому выражению отказавшая,
	 *          оставила бы проверку пройденной, заслона не тронув вовсе.
	 *
	 */
	ASSERT_EQ(refused, (sizeof(SAMPLES) / sizeof(SAMPLES[0])));
}

/**
 * @brief Проверка различимости байтов классами эквивалентности
 *
 * @details Переходы состояний размещены по классам эквивалентности байтов, отчего
 *          байты, объединённые в один класс, проходятся автоматом неразличимо.
 *          Привязки к позиции в тексте различают байты помимо инструкций программы,
 *          поэтому классы дробятся принадлежностью байтов символам слова и
 *          соответствием переводу строки. Отказ от такого дробления оставляет
 *          выражения этого теста без верного вердикта.
 *
 */
TEST(Regex, AutomatonAlphabet) {
	/**
	 * @brief Набор выражений, различающих байты помимо инструкций программы
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Набор режимов компиляции регулярного выражения
		uint32_t flags;
		// Текст, содержащий совпадение
		const char * accepted;
		// Текст, совпадения не содержащий
		const char * rejected;
	} samples[] = {
		// Привязка к границе слова различает байты по принадлежности символам слова
		{"\\bqq\\b",     0, "a qq a",  "aqqa"},
		// Привязка к положению вне границы слова различает их же
		{"\\Bqq\\B",     0, "aqqa",    "a qq a"},
		/**
		 * Привязка к границе слова различает байты, инструкциями не различаемые
		 *
		 * @details Ни одна инструкция выражения не отделяет знак подчёркивания
		 *          от знака переноса, и без дробления классов принадлежностью
		 *          символам слова оба байта проходятся автоматом неразличимо.
		 *
		 */
		{".+\\b\\D.?",    0, "A_B-C",   ""},
		/**
		 * Привязка к границе строки различает перевод строки
		 *
		 * @details Выражение состоит из одних привязок, отчего инструкций,
		 *          дробящих классы, не содержит вовсе.
		 *
		 */
		{"^\\b",         0, "ab\ncd",  " ab"}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parser.parse(sample.pattern, sample.flags));
		// Создаём объект компиляции регулярного выражения
		regex::compiler_t compiler;
		// Создаём компилируемую программу регулярного выражения
		regex::program_t program;
		// Выполняем компиляцию регулярного выражения
		ASSERT_TRUE(compiler.compile(parser, program));
		// Создаём объект детерминированного исполнения
		regex::dfa_t dfa;
		// Выполняем проверку вердикта на тексте, содержащем совпадение
		EXPECT_TRUE(dfa.test(program, sample.accepted, 0)) << sample.pattern;
		// Выполняем проверку вердикта на тексте, совпадения не содержащем
		EXPECT_FALSE(dfa.test(program, sample.rejected, 0)) << sample.pattern;
	}
}

/**
 * @brief Проверка вывода ведущего литерала совпадения
 *
 * @details Ведущим литералом называется последовательность символов, с которой
 *          начинается всякое совпадение выражения. Литерал отыскивает позиции
 *          возможного начала совпадения поиском последовательности и определяет
 *          выбор способа сопоставления, поэтому вывод его закреплён отдельно:
 *          замером он не покрыт, поскольку среди выражений сравнения нет
 *          начинающихся текстом с последующей группой.
 *
 */
TEST(Regex, AutomatonLeading) {
	/**
	 * @brief Набор выражений и выводимых из них ведущих литералов
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Ожидаемый ведущий литерал совпадения
		const char * leading;
	} samples[] = {
		/**
		 * Ведущий литерал продолжается литералом тела группы
		 *
		 * @details Группа границ совпадения не смещает, поэтому накопленный
		 *          до неё литерал сохраняется, а литерал её тела его продолжает.
		 *
		 */
		{"GET /(\\S+) HTTP/(\\d)", "GET /"},
		{"needle (\\S+)",          "needle "},
		{"(GET) /",                "GET"},
		// Привязка к позиции в тексте ведущий литерал не прерывает
		{"^GET /\\S+",             "GET /"},
		// Класс символов в начале выражения ведущего литерала не даёт
		{"([A-Za-z]+): (.+)",      ""},
		// Выбор одной из ветвей ведущего литерала не даёт
		{"^(GET|POST) /",          ""},
		// Сброс начала совпадения ведущий литерал отменяет
		{"GET \\K/path",           ""}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample.pattern, 0, expression)) << sample.pattern;
		// Выполняем проверку выведенного ведущего литерала совпадения
		EXPECT_EQ(expression.forward.prefilter.leading, string(sample.leading)) << sample.pattern;
	}
}
/**
 * @brief Проверка сброса кэша состояний по достижении предела
 *
 * @details Кэш состояний автомата ограничен пределом, и по достижении его
 *          кэш сбрасывается, а текущее состояние заводится заново набором
 *          адресов своих инструкций. Путь этот не исполнялся ни одной
 *          проверкой: выражения набора состояний столько не порождают,
 *          а выражение, порождающее их, требует прохода текста целиком,
 *          то есть отсутствия совпадения. Ошибка восстановления текущего
 *          состояния после сброса вердикт исказила бы молча.
 *
 */
TEST(Regex, AutomatonOverflow) {
	// Создаём порождатель случайных значений с постоянным зерном
	mt19937 generator(20260903);
	// Текст прохода автомата
	string text;
	// Выполняем размещение текста прохода автомата
	text.reserve(300000);
	/**
	 * Выполняем порождение текста прохода автомата
	 *
	 * @details Текст состоит из двух букв, отчего состояние автомата несёт
	 *          набор положений буквы «a» в последних шестнадцати знаках,
	 *          а количество наборов таких предел кэша превышает.
	 *
	 */
	for(size_t i = 0; i < 300000; i++)
		// Выполняем добавление очередного знака текста
		text.append(1, static_cast <char> ('a' + (generator() % 2)));
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	// Выполняем разбор регулярного выражения
	ASSERT_TRUE(parser.parse("a.{15}z", 0));
	// Создаём объект компиляции регулярного выражения
	regex::compiler_t compiler;
	// Создаём компилируемую программу регулярного выражения
	regex::program_t program;
	// Выполняем компиляцию регулярного выражения
	ASSERT_TRUE(compiler.compile(parser, program));
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	/**
	 * Выполняем проверку отсутствия совпадения в тексте
	 *
	 * @details Знака «z» текст не несёт вовсе, отчего проход ведётся по тексту
	 *          целиком, и кэш состояний за время его сбрасывается многократно.
	 *
	 */
	EXPECT_FALSE(dfa.test(program, text, 0));
	// Выполняем добавление совпадения в конец текста
	text.append("a" + string(15, 'b') + "z");
	// Позиция завершения обнаруженного совпадения
	size_t finish = string_view::npos;
	/**
	 * Выполняем проверку обнаружения совпадения за пределом сбросов кэша
	 *
	 * @details Совпадение стоит в конце текста, отчего обнаружение его
	 *          удостоверяет правильность состояния автомата после сбросов,
	 *          а не одну лишь их безвредность.
	 *
	 */
	EXPECT_TRUE(dfa.search(program, text, 0, finish));
	// Выполняем проверку позиции завершения обнаруженного совпадения
	EXPECT_EQ(finish, text.size());
	/**
	 * Выполняем повторный проход по тексту тем же объектом
	 *
	 * @details Кэш сохраняется между вызовами, отчего повторный проход ведётся
	 *          состояниями, сбросами уже перестроенными.
	 *
	 */
	finish = string_view::npos;
	// Выполняем проверку повторного обнаружения совпадения
	EXPECT_TRUE(dfa.search(program, text, 0, finish));
	// Выполняем проверку позиции завершения обнаруженного совпадения
	EXPECT_EQ(finish, text.size());
}
