/**
 * @brief Проверка сохранения вердикта при повторном исполнении программы
 *
 */
TEST(Regex, AutomatonCache) {
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	// Выполняем разбор регулярного выражения
	ASSERT_TRUE(parser.parse("^[a-z]+[0-9]{2,4}$", 0));
	// Создаём объект компиляции регулярного выражения
	regex::compiler_t compiler;
	// Создаём компилируемую программу регулярного выражения
	regex::program_t program;
	// Выполняем компиляцию регулярного выражения
	ASSERT_TRUE(compiler.compile(parser, program));
	// Создаём объект детерминированного исполнения
	regex::dfa_t dfa;
	/**
	 * Выполняем многократное исполнение программы на различных текстах
	 *
	 * @details Кэш состояний сохраняется между вызовами, поэтому повторное
	 *          исполнение обязано давать тот же вердикт, что и первое.
	 *
	 */
	for(size_t i = 0; i < 4; i++) {
		// Выполняем проверку вердикта на соответствующем тексте
		EXPECT_TRUE(dfa.test(program, "abc123", 0));
		// Выполняем проверку вердикта на тексте с недостаточным числом цифр
		EXPECT_FALSE(dfa.test(program, "abc1", 0));
		// Выполняем проверку вердикта на тексте с избыточным числом цифр
		EXPECT_FALSE(dfa.test(program, "abc123456", 0));
		// Выполняем проверку вердикта на тексте без букв
		EXPECT_FALSE(dfa.test(program, "123", 0));
	}
}

/**
 * @brief Проверка различимости байтов классами эквивалентности
 *
 * @details Переходы состояний размещены по классам эквивалентности байтов, отчего
 *          байты, объединённые в один класс, проходятся автоматом неразличимо.
 *          Привязки к позиции в тексте различают байты помимо инструкций программы,
 *          поэтому классы дробятся принадлежностью байтов символам слова и
 *          соответствием переводу строки. Отказ от такого дробления оставляет
 *          выражения этого теста без верного вердикта.
 *
 */
TEST(Regex, AutomatonAlphabet) {
	/**
	 * @brief Набор выражений, различающих байты помимо инструкций программы
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Набор режимов компиляции регулярного выражения
		uint32_t flags;
		// Текст, содержащий совпадение
		const char * accepted;
		// Текст, совпадения не содержащий
		const char * rejected;
	} samples[] = {
		// Привязка к границе слова различает байты по принадлежности символам слова
		{"\\bqq\\b",     0, "a qq a",  "aqqa"},
		// Привязка к положению вне границы слова различает их же
		{"\\Bqq\\B",     0, "aqqa",    "a qq a"},
		/**
		 * Привязка к границе слова различает байты, инструкциями не различаемые
		 *
		 * @details Ни одна инструкция выражения не отделяет знак подчёркивания
		 *          от знака переноса, и без дробления классов принадлежностью
		 *          символам слова оба байта проходятся автоматом неразличимо.
		 *
		 */
		{".+\\b\\D.?",    0, "A_B-C",   ""},
		/**
		 * Привязка к границе строки различает перевод строки
		 *
		 * @details Выражение состоит из одних привязок, отчего инструкций,
		 *          дробящих классы, не содержит вовсе.
		 *
		 */
		{"^\\b",         0, "ab\ncd",  " ab"}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Выполняем разбор регулярного выражения
		ASSERT_TRUE(parser.parse(sample.pattern, sample.flags));
		// Создаём объект компиляции регулярного выражения
		regex::compiler_t compiler;
		// Создаём компилируемую программу регулярного выражения
		regex::program_t program;
		// Выполняем компиляцию регулярного выражения
		ASSERT_TRUE(compiler.compile(parser, program));
		// Создаём объект детерминированного исполнения
		regex::dfa_t dfa;
		// Выполняем проверку вердикта на тексте, содержащем совпадение
		EXPECT_TRUE(dfa.test(program, sample.accepted, 0)) << sample.pattern;
		// Выполняем проверку вердикта на тексте, совпадения не содержащем
		EXPECT_FALSE(dfa.test(program, sample.rejected, 0)) << sample.pattern;
	}
}

/**
 * @brief Проверка вывода ведущего литерала совпадения
 *
 * @details Ведущим литералом называется последовательность символов, с которой
 *          начинается всякое совпадение выражения. Литерал отыскивает позиции
 *          возможного начала совпадения поиском последовательности и определяет
 *          выбор способа сопоставления, поэтому вывод его закреплён отдельно:
 *          замером он не покрыт, поскольку среди выражений сравнения нет
 *          начинающихся текстом с последующей группой.
 *
 */
TEST(Regex, AutomatonLeading) {
	/**
	 * @brief Набор выражений и выводимых из них ведущих литералов
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Ожидаемый ведущий литерал совпадения
		const char * leading;
	} samples[] = {
		/**
		 * Ведущий литерал продолжается литералом тела группы
		 *
		 * @details Группа границ совпадения не смещает, поэтому накопленный
		 *          до неё литерал сохраняется, а литерал её тела его продолжает.
		 *
		 */
		{"GET /(\\S+) HTTP/(\\d)", "GET /"},
		{"needle (\\S+)",          "needle "},
		{"(GET) /",                "GET"},
		// Привязка к позиции в тексте ведущий литерал не прерывает
		{"^GET /\\S+",             "GET /"},
		// Класс символов в начале выражения ведущего литерала не даёт
		{"([A-Za-z]+): (.+)",      ""},
		// Выбор одной из ветвей ведущего литерала не даёт
		{"^(GET|POST) /",          ""},
		// Сброс начала совпадения ведущий литерал отменяет
		{"GET \\K/path",           ""}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample.pattern, 0, expression)) << sample.pattern;
		// Выполняем проверку выведенного ведущего литерала совпадения
		EXPECT_EQ(expression.forward.prefilter.leading, string(sample.leading)) << sample.pattern;
	}
}
