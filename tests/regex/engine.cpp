/**
 * @brief Проверка предела глубины рекурсивных вызовов
 *
 * @details Глубина рекурсии ограничена намеренно: вызов, вошедший глубже
 *          предела, отвергается ошибкой превышения объёма работы. До правки
 *          сжатия отменяемых изменений предел этот недостижим был вовсе -
 *          объём работы исчерпывался много раньше, на глубине двадцати трёх.
 *
 */
TEST(Regex, MatchingRecursionDepth) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine;
	// Создаём собираемое регулярное выражение с рекурсивным вызовом
	regex::expression_t expression;
	// Выполняем сборку регулярного выражения
	ASSERT_TRUE(engine.build("^(?<r>a(?&r)?b)$", 0, expression));
	// Выполняем снятие предела допустимого объёма работы
	engine.limit(0);
	/**
	 * @brief Функция сопоставления текста заданной глубины
	 *
	 * @param depth глубина рекурсии сопоставляемого текста
	 * @return      результат сопоставления текста
	 *
	 */
	auto matched = [&](const size_t depth) noexcept -> bool {
		// Набор установленных границ захвата
		vector <pair <size_t, size_t>> captures;
		// Создаём текст сопоставления заданной глубины
		const string text = (string(depth, 'a') + string(depth, 'b'));
		// Выводим результат сопоставления текста
		return engine.exec(expression, text, 0, captures);
	};
	/**
	 * Выполняем проверку глубины умолчания
	 *
	 * @details Умолчанием служит тысяча вызовов - столько же берёт и эталон.
	 *          Граница проверяется с обеих сторон: одна лишь проверка отказа
	 *          прошла бы и при глубине, вдесятеро меньшей.
	 *
	 */
	{
		// Выполняем проверку сопоставления при глубине умолчания
		EXPECT_TRUE(matched(1000));
		// Выполняем проверку отсутствия ошибки сопоставления
		EXPECT_EQ(engine.error(), regex::error_t::NONE);
		// Выполняем проверку отказа сопоставления при глубине сверх умолчания
		EXPECT_FALSE(matched(1001));
		// Выполняем проверку установки ошибки превышения объёма работы
		EXPECT_EQ(engine.error(), regex::error_t::BUDGET_EXCEEDED);
	}
	/**
	 * Выполняем проверку глубины установленной
	 */
	{
		// Выполняем установку наибольшей допустимой глубины вызовов
		engine.nesting(64);
		// Выполняем проверку сопоставления при глубине установленной
		EXPECT_TRUE(matched(64));
		// Выполняем проверку отказа сопоставления при глубине сверх установленной
		EXPECT_FALSE(matched(65));
		// Выполняем проверку установки ошибки превышения объёма работы
		EXPECT_EQ(engine.error(), regex::error_t::BUDGET_EXCEEDED);
	}
	/**
	 * Выполняем проверку восстановления глубины умолчания
	 *
	 * @details Нуль глубину не снимает, а восстанавливает умолчание: снятие
	 *          её вовсе оставило бы память под кадры вызовов без предела.
	 *
	 */
	{
		// Выполняем восстановление наибольшей допустимой глубины вызовов
		engine.nesting(0);
		// Выполняем проверку сопоставления при глубине умолчания
		EXPECT_TRUE(matched(500));
	}
	/**
	 * Выполняем проверку передачи отказа из проверки окружения
	 *
	 * @details Отказ по объёму работы, случившийся в теле проверки окружения,
	 *          обязан выходить наружу отказом сопоставления, а не считаться
	 *          непройденной проверкой: последнее обратило бы исчерпание
	 *          предела в итог сопоставления, от предела зависящий.
	 *
	 */
	{
		// Создаём собираемое регулярное выражение с проверкой окружения
		regex::expression_t nested;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build("^(?=(?<r>a(?&r)?b))a", 0, nested));
		// Выполняем установку наибольшей допустимой глубины вызовов
		engine.nesting(64);
		// Набор установленных границ захвата
		vector <pair <size_t, size_t>> captures;
		// Создаём текст сопоставления глубины сверх предельной
		const string text = (string(300, 'a') + string(300, 'b'));
		// Выполняем проверку отказа сопоставления при глубине сверх предела
		EXPECT_FALSE(engine.exec(nested, text, 0, captures));
		// Выполняем проверку установки ошибки превышения объёма работы
		EXPECT_EQ(engine.error(), regex::error_t::BUDGET_EXCEEDED);
	}
}

/**
 * @brief Проверка предела вложенности исполнений программы
 *
 * @details Тело проверки окружения исполняется вложенным исполнением, и
 *          программа, тело проверки какой указывает на неё же, уводила бы
 *          исполнение в рекурсию бесконечную по стеку машины: падение при
 *          этом наступало прежде всякого предела, ибо стек не сопоставлению
 *          принадлежит. Сборщик такой программы не порождает, а поддельная
 *          запись хранилища - вполне, отчего заслон обязан стоять
 *          в исполнении, а не в разборе записи.
 *
 */
TEST(Regex, MatchingNestedGuard) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine;
	// Создаём собираемое регулярное выражение с проверкой окружения
	regex::expression_t expression;
	// Выполняем сборку регулярного выражения
	ASSERT_TRUE(engine.build("(?=ab)a", 0, expression));
	// Количество завёрнутых на себя проверок окружения
	size_t twisted = 0;
	/**
	 * Выполняем обход указаний собранной программы
	 */
	for(size_t i = 0; i < expression.forward.instructions.size(); i++) {
		// Получаем очередное указание собранной программы
		auto & instruction = expression.forward.instructions[i];
		/**
		 * Если указание выполняет проверку окружения
		 */
		if(instruction.type == regex::opcode_t::LOOK) {
			// Выполняем заворот тела проверки окружения на неё же
			instruction.look.body = static_cast <uint32_t> (i);
			// Увеличиваем количество завёрнутых проверок окружения
			twisted++;
		}
	}
	/**
	 * Выполняем проверку наличия завёрнутой проверки окружения
	 *
	 * @details Без неё испытание проходило бы и при заслоне снятом: программа
	 *          без проверок окружения вложенного исполнения не заводит вовсе.
	 *
	 */
	ASSERT_EQ(twisted, static_cast <size_t> (1));
	// Набор установленных границ захвата
	vector <pair <size_t, size_t>> captures;
	// Выполняем проверку отказа сопоставления завёрнутой программой
	EXPECT_FALSE(engine.exec(expression, "abab", 0, captures));
	// Выполняем проверку установки ошибки превышения объёма работы
	EXPECT_EQ(engine.error(), regex::error_t::BUDGET_EXCEEDED);
}

/**
 * @brief Функция обхода подделок указаний программы
 *
 * @details Программа приходит исполнению не только от сборки, но и от
 *          восстановления записи, а запись бывает поддельною. Исполнение
 *          обязано отказать либо отыскать совпадение, но не выйти за пределы
 *          и не пасть: проверка правильности программы отвергает несообразное
 *          не всякое, и заслоны исполнения стоят за нею.
 *
 *          Предел объёма работы ставится нарочно малым: программа испорченная
 *          даёт связки указаний, обхода не завершающие, и без предела обход
 *          шёл бы неограниченно долго.
 *
 * @param thorough признак обхода по всем выражениям набора
 *
 */
static void mutating(const bool thorough) noexcept {
	/**
	 * @brief Набор выражений, устройством программы различающихся
	 *
	 */
	static const char * SAMPLES[] = {
		"[a-z]+", "(\\w+)@(\\w+)", "^(?:GET|POST) /[a-z]*$",
		"(?>a+)b", "(?=ab)a", "(?<name>a)\\k<name>", "(?<r>a(?&r)?b)",
		"(a)\\1", "(?(1)a|b)(x)", "(a*)*b", "(?<=ab)c"
	};
	/**
	 * @brief Набор текстов сопоставления
	 *
	 */
	static const char * TEXTS[] = {"abab", "user@host aab"};
	// Создаём объект хранилища собранных выражений
	const regex::storage_t storage;
	// Количество записей, разбором принятых и отвергнутых
	size_t accepted = 0, rejected = 0;
	/**
	 * Выполняем обход набора выражений
	 */
	for(const char * pattern : SAMPLES) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		// Выполняем установку предела допустимого объёма работы
		engine.limit(500);
		// Получаем количество указаний собранной программы
		const size_t count = expression.forward.instructions.size();
		/**
		 * Выполняем обход указаний собранной программы
		 */
		for(size_t i = 0; i < count; i++) {
			/**
			 * Выполняем перебор четырёхбайтовых полей указания
			 */
			for(size_t shift = 0; (shift + sizeof(uint32_t)) <= sizeof(regex::instruction_t); shift += sizeof(uint32_t)) {
				/**
				 * @brief Набор подменяемых значений поля указания
				 *
				 */
				const uint32_t narrow[] = {
					0, static_cast <uint32_t> (count), 0xFFFFFFFF
				};
				/**
				 * @brief Набор подменяемых значений поля указания, полный
				 *
				 */
				const uint32_t widened[] = {
					0, 1, static_cast <uint32_t> (count),
					static_cast <uint32_t> (count + 1), 0x7FFFFFFF, 0xFFFFFFFF
				};
				// Получаем набор подменяемых значений поля указания
				const uint32_t * values = (thorough ? widened : narrow);
				// Получаем количество подменяемых значений поля указания
				const size_t amount = (thorough ?
				 (sizeof(widened) / sizeof(widened[0])) : (sizeof(narrow) / sizeof(narrow[0])));
				/**
				 * Выполняем перебор подмен значения поля указания
				 */
				for(size_t index = 0; index < amount; index++) {
					// Получаем очередное подменяемое значение поля указания
					const uint32_t value = values[index];
					// Создаём подделываемое выражение
					auto twisted = make_shared <regex::expression_t> (expression);
					// Получаем адрес подделываемого указания программы
					char * target = reinterpret_cast <char *> (&twisted->forward.instructions[i]);
					// Выполняем подмену очередного поля указания
					::memcpy((target + shift), &value, sizeof(value));
					// Запись хранилища подделанного выражения
					string record;
					/**
					 * Если запись подделанного выражения не выполнена
					 */
					if(!storage.save({twisted}, record))
						// Переходим к следующей подмене значения поля
						continue;
					// Набор восстановленных выражений
					vector <regex::storage_t::exp_t> restored;
					/**
					 * Если запись подделанная разбором отвергнута
					 *
					 * @details Испорченная программа, разбором отвергнутая,
					 *          исполнению не подаётся вовсе: движки вправе
					 *          полагаться на программу проверенную, и подача
					 *          им непроверенной мерила бы договор, какого нет.
					 *
					 */
					if(!storage.load(record, restored)) {
						// Увеличиваем количество записей отвергнутых
						rejected++;
						// Переходим к следующей подмене значения поля
						continue;
					}
					// Увеличиваем количество записей принятых
					accepted++;
					/**
					 * Выполняем обход восстановленных выражений
					 */
					for(const auto & expression : restored) {
						/**
						 * Выполняем обход текстов сопоставления
						 */
						for(const char * text : TEXTS) {
							// Набор установленных границ захвата
							vector <pair <size_t, size_t>> captures;
							// Выполняем сопоставление восстановленным выражением
							engine.exec(* expression, text, 0, captures);
						}
					}
				}
			}
		}
	}
	/**
	 * Выполняем проверку прохождения набора подделок
	 *
	 * @details Утверждается достижение конца обхода: падение либо выход
	 *          за пределы прекратил бы прогон, и проверка до этого места
	 *          не дошла бы вовсе.
	 *
	 *          Утверждается и наличие записей, разбором принятых: подделка,
	 *          отвергаемая разбором целиком, исполнения не достигала бы вовсе,
	 *          и проверка мерила бы один лишь разбор.
	 *
	 */
	EXPECT_GT(accepted, static_cast <size_t> (100))
	 << "принято " << accepted << ", отвергнуто " << rejected;
}
