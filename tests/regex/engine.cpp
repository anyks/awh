/**
 * @brief Проверка привязки исполнения с возвратом к позиции начала поиска
 *
 * @details Выражение, привязанное к началу текста, совпадения правее позиции начала
 *          поиска не образует, поэтому исполнение с возвратом попытки в прочих позициях
 *          не повторяет. Проверка ограничивает объём работы величиной, достаточной
 *          для единственной попытки и недостаточной для обхода текста: повторение
 *          попыток исчерпало бы объём и обратило отказ в ошибку.
 *
 */
TEST(Regex, EngineAnchoredAttempt) {
	/**
	 * @brief Набор проверяемых выражений
	 *
	 */
	const char * samples[] = {
		// Привязанные выражения, исполняемые только с возвратом
		"^(?>\\w+) (\\d+)",
		"^(\\w+) \\1\\1",
		"\\A(\\w+(?= ))\\d",
		"^(?:(a)|(b)) \\1\\1"
	};
	/**
	 * Формируем текст сопоставления, выражению не отвечающий
	 *
	 * @details Текст состоит из символов слова, отчего предварительный отбор позиций
	 *          ни одной позиции не отсекает, а обязательный литерал в нём присутствует,
	 *          отчего без учёта привязки попытка повторялась бы в каждой позиции текста.
	 *
	 */
	string text;
	/**
	 * Выполняем наполнение текста сопоставления
	 */
	for(size_t i = 0; i < 8000; i++)
		// Выполняем добавление очередного участка текста
		text.append("ab ");
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample, 0, expression)) << sample;
		// Выполняем проверку признака привязки к позиции начала поиска
		ASSERT_TRUE(expression.forward.anchored) << sample;
		// Выполняем проверку исполнения выражения с возвратом
		ASSERT_TRUE(expression.backtracking) << sample;
		// Создаём объект исполнения с возвратом
		regex::backtrack_t backtrack;
		// Создаём набор границ совпадения
		vector <pair <size_t, size_t>> captures;
		/**
		 * Выполняем установку объёма работы, достаточного для единственной попытки
		 *
		 * @details Единственная попытка обрывается на первом же несопоставленном
		 *          символе и укладывается в десятки шагов, тогда как повторение попытки
		 *          в каждой позиции текста расходует шаги соразмерно его длине,
		 *          даже когда привязка обрывает каждую попытку сразу.
		 *
		 */
		backtrack.budget(0x400);
		// Выполняем проверку отсутствия совпадения в тексте
		EXPECT_FALSE(backtrack.exec(expression.forward, text, 0, captures)) << sample;
		// Выполняем проверку установления отказа без исчерпания объёма работы
		EXPECT_NE(backtrack.error(), regex::error_t::BUDGET_EXCEEDED) << sample;
	}
}

