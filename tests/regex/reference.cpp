/**
 * @brief Функция сличения приведения регистра Юникода с эталонной реализацией
 *
 * @details Признак «CASELESS» сличался прежде на знаках ASCII, а режим UTF-8 -
 *          без него: приведение регистра по таблицам Юникода с эталоном
 *          не сличалось ни разу. Пропуск этот укрыл разряды свойств:
 *          без учёта регистра эталон считает разряды букв прописных, строчных
 *          и с заглавной первой частью взаимозаменяемыми, модуль же сличал
 *          разряд буквально.
 *
 * @param samples количество сличаемых образцов
 * @param seed    зерно порождения образцов сличения
 *
 */
void folding([[maybe_unused]] const size_t samples, [[maybe_unused]] const uint32_t seed) noexcept(false) {
	/**
	 * Если сборка выполняется со сличением с эталонной реализацией
	 */
	#if defined(AWH_TEST_PCRE2)
		/**
		 * @brief Набор составных частей порождаемого выражения
		 *
		 */
		static const char * PARTS[] = {
			"а", "Б", "в", "Ω", "ς", "σ", "Σ", "ı", "I", "İ", "ẞ", "ß", "ﬁ", "K",
			"\\w", "\\d", "\\s", "\\b", ".", "[а-я]", "[А-Я]", "[\\p{L}]", "[\\p{Lu}]",
			"\\p{L}", "\\p{Ll}", "\\p{Lt}", "\\p{Lm}", "\\P{Lu}", "\\p{Cyrillic}", "\\p{Greek}",
			"(а)", "(?:Б)", "|", "a", "Z", "[a-z]", "*", "+", "?", "{1,2}", "^", "$"
		};
		/**
		 * @brief Набор текстов сопоставления
		 *
		 * @details Тексты подобраны по трудностям приведения регистра: сигма
		 *          конечная, точка над «i» у турецкого письма, лигатура «ﬁ»,
		 *          острая «s» и знак Кельвина.
		 *
		 */
		static const char * TEXTS[] = {
			"аБв", "АБВ", "ΩΣς", "ωσς", "ıI", "İi", "ßẞ", "ﬁfi", "KK", "Kelvin",
			"абв где", "ABC abc", "", "\n", "Ёё", "ЙЦУКЕН", "straße", "STRASSE"
		};
		// Получаем количества частей и текстов сличения
		const size_t count = (sizeof(PARTS) / sizeof(PARTS[0]));
		const size_t texts = (sizeof(TEXTS) / sizeof(TEXTS[0]));
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём генератор порождения образцов сличения
		mt19937 gen(seed);
		// Количество сличённых образцов
		size_t checked = 0;
		/**
		 * Выполняем обход набора образцов сличения
		 */
		for(size_t sample = 0; sample < samples; sample++) {
			// Порождаемое регулярное выражение
			string pattern;
			// Получаем количество составных частей выражения
			const size_t parts = (1 + (gen() % 3));
			/**
			 * Выполняем сборку выражения из составных частей
			 */
			for(size_t part = 0; part < parts; part++)
				// Выполняем добавление очередной составной части выражения
				pattern.append(PARTS[gen() % count]);
			// Получаем признак сопоставления без учёта регистра символов
			const bool caseless = ((gen() % 2) == 0);
			// Получаем признак сборки с порождением машинного кода
			const bool jit = ((gen() % 2) == 0);
			// Собираем наборы признаков сборки модуля и эталона
			uint32_t mine = (static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::UCP));
			uint32_t theirs = (PCRE2_UTF | PCRE2_UCP);
			/**
			 * Если сопоставление ведётся без учёта регистра символов
			 */
			if(caseless) {
				// Выполняем установку признака сборки модуля
				mine |= static_cast <uint32_t> (regex::flag_t::CASELESS);
				// Выполняем установку признака сборки эталона
				theirs |= PCRE2_CASELESS;
			}
			/**
			 * Если выражение собирается с порождением машинного кода
			 */
			if(jit)
				// Выполняем установку признака порождения машинного кода
				mine |= static_cast <uint32_t> (regex::flag_t::JIT);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 pattern.size(), theirs, &code, &spot, nullptr);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Получаем вердикт сборки регулярного выражения движком
			const bool built = engine.build(pattern, mine, compiled);
			/**
			 * Если выражение собрано не обеими сторонами
			 */
			if((reference == nullptr) || !built) {
				/**
				 * Если эталонное регулярное выражение собрано
				 */
				if(reference != nullptr)
					// Выполняем освобождение эталонного регулярного выражения
					::pcre2_code_free(reference);
				// Переходим к следующему образцу сличения
				continue;
			}
			// Получаем текст сопоставления образца
			const string text = TEXTS[gen() % texts];
			// Выполняем размещение набора границ эталонного совпадения
			pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
			// Выполняем сопоставление эталонного регулярного выражения
			const int result = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
			// Получаем набор границ эталонного совпадения
			PCRE2_SIZE * bounds = ::pcre2_get_ovector_pointer(data);
			// Получаем вердикт эталонного сопоставления
			const bool expected = (result > 0);
			// Получаем границы эталонного совпадения
			const size_t begin = (expected ? static_cast <size_t> (bounds[0]) : 0);
			const size_t finish = (expected ? static_cast <size_t> (bounds[1]) : 0);
			// Выполняем освобождение набора границ эталонного совпадения
			::pcre2_match_data_free(data);
			// Выполняем освобождение эталонного регулярного выражения
			::pcre2_code_free(reference);
			// Набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> captures;
			// Получаем вердикт сопоставления движком
			const bool obtained = engine.exec(compiled, text, 0, captures);
			// Увеличиваем количество сличённых образцов
			checked++;
			// Выполняем сличение вердиктов сопоставления
			ASSERT_EQ(obtained, expected) << "«" << pattern << "» на «" << text << "»"
			 << (caseless ? ", без учёта регистра" : "") << (jit ? ", машинный код" : "");
			/**
			 * Если совпадение обеими сторонами найдено
			 */
			if(expected) {
				// Выполняем сличение начальной границы совпадения
				ASSERT_EQ(captures.front().first, begin) << "«" << pattern << "» на «" << text << "»"
				 << (caseless ? ", без учёта регистра" : "") << (jit ? ", машинный код" : "");
				// Выполняем сличение конечной границы совпадения
				ASSERT_EQ(captures.front().second, finish) << "«" << pattern << "» на «" << text << "»"
				 << (caseless ? ", без учёта регистра" : "") << (jit ? ", машинный код" : "");
			}
		}
		// Выполняем проверку сличения образцов
		EXPECT_GT(checked, (samples / 2));
	#endif
}
