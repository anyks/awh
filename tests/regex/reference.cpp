	compare(THOROUGH, 24, 1, false);
	// Выполняем сличение на текстах, вынуждающих проход по их длине
	compare((THOROUGH / 4), 400, 7, false);
	// Выполняем сличение на текстах, соразмерных сетевому сообщению
	compare((THOROUGH / 10), 4000, 99, false);
