namespace {
	/**
	 * @brief Количество образцов сличения обычного прогона
	 *
	 * @details Прогон входит в набор автоматических тестов, поэтому количество
	 *          образцов выбрано соразмерным прочим тестам набора. Исчерпывающее
	 *          сличение выполняется отключённым тестом, запускаемым отдельно
	 *
	 */
	constexpr size_t SAMPLES = 20000;

	/**
	 * @brief Количество образцов сличения исчерпывающего прогона
	 *
	 */
	constexpr size_t THOROUGH = 500000;

	/**
	 * @brief Части, из каких собираются порождаемые выражения
	 *
	 * @details Набор покрывает одиночные символы, классы символов и их отрицания,
	 *          сокращённые классы и точку: именно ими различаются пути исполнения
	 *
	 */
	const char * ATOMS[] = {
		"a", "b", "0", "[0-9]", "[a-z]", "\\d", "\\w",
		"\\s", ".", "[^0-9]", "x", "\\n", "[abc]", "[^a-c]"
	};

	/**
	 * @brief Кванторы повторения, приписываемые частям выражения
	 *
	 */
	const char * REPEATS[] = {"", "*", "+", "?", "{2}", "{1,3}", "*?", "+?", "??"};

	/**
	 * @brief Привязки к позиции в тексте, приписываемые выражению
	 *
	 */
	const char * ANCHORS[] = {
		"", "^", "\\b", "\\B", "$", "\\A",
		"\\G", "\\K", "(?m)^", "(?m)", "\\z", "\\Z"
	};

	/**
	 * @brief Конструкции, требующие исполнения с возвратом
	 *
	 * @details Опережающие и ретроспективные проверки, обратные ссылки и атомарные
	 *          группы выводят выражение из регулярного подмножества, отчего оно
	 *          исполняется иным способом и подлежит сличению отдельно
	 *
	 */
	const char * EXTRAS[] = {
		"(?=\\w)", "(?!\\d)", "(?<=a)", "(?<!b)",
		"(\\w)\\1", "(?>\\w+)", "(?:(a)|(b))\\1?"
	};

	/**
	 * @brief Символы текста сопоставления вне режима разбора UTF-8
	 *
	 */
	const char * PLAIN[] = {"a", "b", "0", " ", "\n", "x", "y", "z", "c", "1", "9", "_"};

	/**
	 * @brief Символы текста сопоставления в режиме разбора UTF-8
	 *
	 */
	const char * WIDE[] = {"a", "д", "0", "ю", " ", "\n", "x", "я", "ц", "1", "€", "_"};

	/**
	 * @brief Функция порождения выражения сличения
	 *
	 * @param gen источник псевдослучайных значений
	 * @return    порождённое регулярное выражение
	 *
	 */
	string pattern(mt19937 & gen) noexcept {
		// Формируем порождаемое регулярное выражение
		string result(ANCHORS[gen() % 12]);
		// Получаем количество частей порождаемого выражения
		const size_t parts = (1 + (gen() % 3));
		/**
		 * Выполняем наполнение порождаемого выражения
		 */
		for(size_t i = 0; i < parts; i++) {
			// Выполняем добавление очередной части выражения
			result.append(ATOMS[gen() % 14]);
			// Выполняем добавление квантора повторения части
			result.append(REPEATS[gen() % 9]);
		}
		/**
		 * Если выражению приписывается конструкция, требующая возврата
		 */
		if((gen() % 6) == 0)
			// Выполняем добавление конструкции, требующей возврата
			result.append(EXTRAS[gen() % 7]);
		/**
		 * Если выражению приписывается завершающая привязка
		 */
		if((gen() % 4) == 0)
			// Выполняем добавление завершающей привязки
			result.append(ANCHORS[gen() % 12]);
		/**
		 * Если выражение предваряется выбором одной из ветвей
		 *
		 * @details Ветви получают привязки по отдельности: признак привязки
		 *          выражения обязан требовать её от всех ветвей сразу
		 *
		 */
		if((gen() % 5) == 0) {
			/**
			 * Получаем части выражения ветвей по отдельности
			 *
			 * @details Извлечение выполняется отдельными действиями намеренно:
			 *          порядок вычисления доводов сложения стандартом не определён,
			 *          и несколько обращений к источнику в одном выражении дали бы
			 *          разные образцы на разных компиляторах. Расхождение это
			 *          обнаружено сличением сумм, снятых компиляторами GCC и Clang.
			 *
			 */
			const string first(ANCHORS[gen() % 12]);
			// Получаем часть выражения ветви с наибольшим приоритетом
			const string second(ATOMS[gen() % 14]);
			// Получаем привязку ветви с наименьшим приоритетом
			const string third(ANCHORS[gen() % 12]);
			// Получаем часть выражения ветви с наименьшим приоритетом
			const string fourth(ATOMS[gen() % 14]);
			// Формируем предваряющий выражение выбор одной из ветвей
			string branches("(?:");
			// Выполняем добавление привязки ветви с наибольшим приоритетом
			branches.append(first);
			// Выполняем добавление части выражения ветви с наибольшим приоритетом
			branches.append(second);
			// Выполняем добавление разделителя ветвей выражения
			branches.append("|");
			// Выполняем добавление привязки ветви с наименьшим приоритетом
			branches.append(third);
			// Выполняем добавление части выражения ветви с наименьшим приоритетом
			branches.append(fourth);
			// Выполняем завершение выбора одной из ветвей
			branches.append(")");
			/**
			 * Если выбор ветвей получает квантор повторения
			 *
			 * @details Повторение над областью инструкций - устройство, отдельное
			 *          от повторения одиночного символа: тело его проходится
			 *          целиком, а отступление ведёт внутрь прохода прежнего.
			 *          Без квантора здесь выборка таких выражений не порождала
			 *          бы вовсе, и сличение их ничего бы не проверяло.
			 *
			 */
			if((gen() % 2) == 0)
				// Выполняем добавление квантора повторения выбора ветвей
				branches.append(REPEATS[gen() % 9]);
			// Выполняем добавление накопленного выражения
			branches.append(result);
			// Выполняем предварение выражения выбором одной из ветвей
			result = branches;
		}
		// Выводим порождённое регулярное выражение
		return result;
	}
	/**
	 * @brief Функция порождения текста сопоставления
	 *
	 * @param gen    источник псевдослучайных значений
	 * @param length наибольшая длина порождаемого текста в символах
	 * @param utf    флаг порождения текста в режиме разбора UTF-8
	 * @return       порождённый текст сопоставления
	 *
	 */
	string subject(mt19937 & gen, const size_t length, const bool utf) noexcept {
		// Формируем порождаемый текст сопоставления
		string result;
		// Получаем длину порождаемого текста в символах
		const size_t size = (gen() % length);
		/**
		 * Выполняем наполнение порождаемого текста сопоставления
		 */
		for(size_t i = 0; i < size; i++)
			// Выполняем добавление очередного символа текста
			result.append(utf ? WIDE[gen() % 12] : PLAIN[gen() % 12]);
		// Выводим порождённый текст сопоставления
		return result;
	}
	/**
	 * @brief Функция сличения одного заданного образца с эталонной реализацией
	 *
	 * @details Образец задаётся, а не порождается: путь исполнения, случайностью
	 *          достигаемый редко, требует условий заданных. Проход в обратном
	 *          направлении - как раз таков: движок берёт его лишь тогда, когда
	 *          выражение ведущего литерала не несёт, а совпадение завершается
	 *          дальше предела исполнения с возвратом. Выражения же порождаемые
	 *          сходятся близ начала текста, отчего путь этот случайными образцами
	 *          не достигался вовсе - вскрыто порчей, смещавшей найденное начало
	 *          на байт: исчерпывающий прогон её ловил, а быстрый пропускал.
	 *
	 * @param pattern регулярное выражение сличения
	 * @param text    текст сопоставления
	 * @param jit     флаг сличения сопоставителя в виде порождённого машинного кода
	 *
	 */
	void verify([[maybe_unused]] const string & pattern, [[maybe_unused]] const string & text,
	 [[maybe_unused]] const bool jit) noexcept(false) {
		/**
		 * Если сборка выполняется со сличением с эталонной реализацией
		 */
		#if defined(AWH_TEST_PCRE2)
			// Создаём объект движка регулярных выражений
			regex::engine_t engine(::logger());
			// Получаем набор режимов сопоставления движком
			const uint32_t flags = (jit ? static_cast <uint32_t> (regex::flag_t::JIT) : 0);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 PCRE2_ZERO_TERMINATED, 0, &code, &spot, nullptr);
			// Выполняем проверку сборки эталонного регулярного выражения
			ASSERT_NE(reference, nullptr) << "эталон не собрал «" << pattern << "»";
			// Выполняем размещение набора границ эталонного совпадения
			pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
			// Выполняем сопоставление эталонного регулярного выражения
			const int count = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
			// Получаем набор границ эталонного совпадения
			PCRE2_SIZE * bounds = ::pcre2_get_ovector_pointer(data);
			// Получаем вердикт эталонного сопоставления
			const bool expected = (count > 0);
			// Получаем начальную границу эталонного совпадения
			const size_t begin = (expected ? static_cast <size_t> (bounds[0]) : 0);
			// Получаем конечную границу эталонного совпадения
			const size_t finish = (expected ? static_cast <size_t> (bounds[1]) : 0);
			// Выполняем освобождение набора границ эталонного совпадения
			::pcre2_match_data_free(data);
			// Выполняем освобождение эталонного регулярного выражения
			::pcre2_code_free(reference);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Выполняем проверку сборки регулярного выражения движком
			ASSERT_TRUE(engine.build(pattern, flags, compiled)) << "не собрано «" << pattern << "»";
			// Создаём набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> captures;
			// Выполняем сопоставление регулярного выражения движком
			const bool obtained = engine.exec(compiled, text, 0, captures);
			// Выполняем проверку совпадения вердикта сопоставления
			ASSERT_EQ(obtained, expected) << "«" << pattern << "» на тексте в " << text.size() << " байтов";
			/**
			 * Если совпадение в тексте обнаружено
			 */
			if(expected) {
				// Выполняем проверку начальной границы совпадения
				ASSERT_EQ(captures.front().first, begin) << "«" << pattern << "» на тексте в " << text.size() << " байтов";
				// Выполняем проверку конечной границы совпадения
				ASSERT_EQ(captures.front().second, finish) << "«" << pattern << "» на тексте в " << text.size() << " байтов";
			}
			// Выполняем проверку совпадения вердикта проверки наличия
			ASSERT_EQ(engine.test(compiled, text, 0), expected) << "проверка наличия: «" << pattern << "»";
		#else
			// Выходим из сличения с эталонной реализацией
			GTEST_SKIP() << "эталонная реализация PCRE2 сборке недоступна";
		#endif
	}
	/**
	 * @brief Функция сличения границ совпадения с эталонной реализацией
	 *
	 * @param samples количество порождаемых образцов сличения
	 * @param length  наибольшая длина текста сопоставления в символах
	 * @param seed    начальное значение источника псевдослучайных значений
	 * @param utf     флаг порождения образцов в режиме разбора UTF-8
	 * @param jit     флаг сличения сопоставителя в виде порождённого машинного кода
	 * @param kept    флаг сличения выражения, сохранение и восстановление прошедшего
	 *
	 */
	void compare([[maybe_unused]] const size_t samples, [[maybe_unused]] const size_t length,
	 [[maybe_unused]] const uint32_t seed, [[maybe_unused]] const bool utf,
	 [[maybe_unused]] const bool jit = false, [[maybe_unused]] const bool kept = false) noexcept(false) {
		/**
		 * Если сборка выполняется со сличением с эталонной реализацией
		 */
		#if defined(AWH_TEST_PCRE2)
			// Создаём источник псевдослучайных значений
			mt19937 gen(seed);
			// Создаём объект движка регулярных выражений
			regex::engine_t engine(::logger());
			// Создаём объект хранилища собранных выражений
			const regex::storage_t storage(::logger());
			// Получаем набор режимов сопоставления движком
			const uint32_t flags = ((utf ? (static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::UCP)) : 0) |
			 (jit ? static_cast <uint32_t> (regex::flag_t::JIT) : 0));
			// Получаем набор режимов сопоставления эталонной реализацией
			const uint32_t modes = (utf ? (PCRE2_UTF | PCRE2_UCP) : 0);
			// Количество выполненных сличений
			size_t checked = 0;
			// Количество образцов, ни одной из сторон не решённых
			size_t exhausted = 0;
			// Количество образцов, сопоставитель машинным кодом получивших
			size_t generated = 0;
			// Количество сличений вердикта проверки наличия совпадения
			size_t verdicts = 0;
			/**
			 * Выполняем обход порождаемых образцов сличения
			 */
			for(size_t sample = 0; sample < samples; sample++) {
				// Получаем порождённое регулярное выражение
				const string expression = pattern(gen);
				// Получаем порождённый текст сопоставления
				const string text = subject(gen, length, utf);
				// Код ошибки сборки эталонного регулярного выражения
				int code = 0;
				// Положение ошибки сборки эталонного регулярного выражения
				PCRE2_SIZE offset = 0;
				// Выполняем сборку эталонного регулярного выражения
				pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (expression.c_str()), expression.size(), modes, &code, &offset, nullptr);
				/**
				 * Если сборка эталонного регулярного выражения не выполнена
				 */
				if(reference == nullptr)
					// Переходим к следующему образцу сличения
					continue;
				// Выполняем размещение набора границ эталонного совпадения
				pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
				/**
				 * Получаем позицию начала поиска совпадения
				 *
				 * @details Сличение шло прежде от нуля всегда, тогда как позиция
				 *          начала есть довод открытого API и смысл выражения
				 *          меняет: «\G» привязывается к ней самой, «\A» и «^» -
				 *          по-прежнему к началу текста. Треть образцов берёт
				 *          позицию ненулевую: обе стороны получают её одну и ту же,
				 *          и расхождение договора вышло бы расхождением вердикта.
				 *
				 */
				const size_t start = (((sample % 3) == 0) ? (gen() % (text.size() + 1)) : 0);
				// Выполняем сопоставление эталонного регулярного выражения
				const int count = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), start, 0, data, nullptr);
				/**
				 * Если эталон предел возврата исчерпал
				 *
				 * @details Отказ по пределу вердиктом «совпадения нет» НЕ является:
				 *          эталон вопроса не решил вовсе. Прежде код отказа не
				 *          отделялся от отсутствия совпадения, и всякое исчерпание
				 *          выходило расхождением с нами - мы совпадение находили,
				 *          ибо предел у нас свой и иной. Ложное расхождение это
				 *          выходило на образцах ворошителя длиною от двух десятков
				 *          байтов, например «(?:\B.|[^0-9])+?\Z\s??\s+?».
				 *
				 *          Отказ иной, нежели отсутствие совпадения, столь же
				 *          негоден к сличению: эталон ответа не дал.
				 *
				 */
				if((count < 0) && (count != PCRE2_ERROR_NOMATCH)) {
					// Выполняем освобождение набора границ эталонного совпадения
					::pcre2_match_data_free(data);
					// Выполняем освобождение эталонного регулярного выражения
					::pcre2_code_free(reference);
					// Увеличиваем количество образцов, эталоном не решённых
					exhausted++;
					// Переходим к следующему образцу сличения
					continue;
				}
				// Получаем набор границ эталонного совпадения
				PCRE2_SIZE * bounds = ::pcre2_get_ovector_pointer(data);
				// Получаем вердикт эталонного сопоставления
				const bool expected = (count > 0);
				// Получаем начальную границу эталонного совпадения
				const size_t begin = (expected ? static_cast <size_t> (bounds[0]) : 0);
				// Получаем конечную границу эталонного совпадения
				const size_t finish = (expected ? static_cast <size_t> (bounds[1]) : 0);
				// Создаём набор границ захваченных групп эталона
				vector <pair <size_t, size_t>> expects;
				/**
				 * Выполняем снятие границ захваченных групп эталона
				 *
				 * @details Набор снимается копией: границы живут в наборе эталона,
				 *          а тот освобождается прежде самого сопоставления нашего.
				 *          Число пар берётся вердиктом, а не количеством групп
				 *          выражения: эталон обрывает набор на последней группе
				 *          захваченной, и пары за нею содержания не несут.
				 *
				 */
				for(int index = 0; expected && (index < count); index++)
					// Выполняем снятие границ очередной группы эталона
					expects.emplace_back(static_cast <size_t> (bounds[index * 2]), static_cast <size_t> (bounds[(index * 2) + 1]));
				// Выполняем освобождение набора границ эталонного совпадения
				::pcre2_match_data_free(data);
				// Выполняем освобождение эталонного регулярного выражения
				::pcre2_code_free(reference);
				// Создаём собираемое регулярное выражение
				regex::expression_t compiled;
				/**
				 * Если сборка регулярного выражения не выполнена
				 */
				if(!engine.build(expression, flags, compiled))
					// Переходим к следующему образцу сличения
					continue;
				/**
				 * Если выражение получило сопоставитель в виде порождённого машинного кода
				 */
				if(compiled.machine != nullptr)
					// Увеличиваем количество образцов, машинным кодом сопоставляемых
					generated++;
				/**
				 * Если выражение сличается по прохождении хранилища
				 *
				 * @details Выражение сохраняется и восстанавливается перед самим
				 *          сопоставлением, отчего сличению подлежит уже оно -
				 *          восстановленное. Дефект укладки или разбора записи
				 *          выйдет расхождением вердикта либо границ, а не молчаливым
				 *          отличием, какого проверки хранилища на образцах заданных
				 *          могут и не задеть.
				 *
				 */
				if(kept) {
					// Создаём запись хранилища собранных выражений
					string record;
					// Создаём набор восстановленных выражений
					vector <regex::storage_t::exp_t> restored;
					// Выполняем сохранение собранного выражения в записи хранилища
					ASSERT_TRUE(storage.save({make_shared <const regex::expression_t> (compiled)}, record))
						<< "не сохранено «" << expression << "», код " << static_cast <uint32_t> (storage.error());
					// Выполняем восстановление выражения из записи хранилища
					ASSERT_TRUE(storage.load(record, restored))
						<< "не восстановлено «" << expression << "», код " << static_cast <uint32_t> (storage.error());
					// Выполняем проверку количества восстановленных выражений
					ASSERT_EQ(restored.size(), static_cast <size_t> (1)) << "«" << expression << "»";
					// Выполняем установку восстановленного выражения сличаемым
					compiled = (* restored.front());
				}
				// Создаём набор границ совпадения и захваченных групп
				vector <pair <size_t, size_t>> captures;
				// Выполняем сопоставление регулярного выражения движком
				const bool obtained = engine.exec(compiled, text, start, captures);
				/**
				 * Если допустимый объём работы сопоставления исчерпан
				 *
				 * @details Исчерпание предела вердиктом «совпадения нет» не является
				 *          и у нас: вопрос не решён, и сличать нечего. Предел этот
				 *          свойство реализации, а не языка выражений, и у эталона
				 *          он свой - оттого пропуск ведётся с обеих сторон и обе
				 *          стороны считаются. Образец, к тому приводящий, -
				 *          «(?:(?m)\w|\K\w)*\b[0-9]b» на тексте в два десятка байтов.
				 *
				 */
				if(!obtained && (engine.error() == regex::error_t::BUDGET_EXCEEDED)) {
					// Увеличиваем количество образцов, нами не решённых
					exhausted++;
					// Переходим к следующему образцу сличения
					continue;
				}
				// Увеличиваем количество выполненных сличений
				checked++;
				// Выполняем проверку совпадения вердикта сопоставления
				ASSERT_EQ(obtained, expected) << "«" << expression << "» на тексте «" << text << "» с позиции " << start;
				/**
				 * Если совпадение в тексте обнаружено
				 */
				if(expected) {
					// Выполняем проверку начальной границы совпадения
					ASSERT_EQ(captures.front().first, begin) << "«" << expression << "» на тексте «" << text << "» с позиции " << start;
					// Выполняем проверку конечной границы совпадения
					ASSERT_EQ(captures.front().second, finish) << "«" << expression << "» на тексте «" << text << "» с позиции " << start;
					/**
					 * Выполняем проверку достаточности набора границ
					 *
					 * @details Набор наш обязан нести всякую группу, эталоном
					 *          захваченную: недостача означала бы группу потерянную,
					 *          а сличение одних лишь границ совпадения её не видит.
					 *
					 */
					ASSERT_GE(captures.size(), expects.size()) << "«" << expression << "» на тексте «" << text << "» с позиции " << start;
					/**
					 * Выполняем обход границ захваченных групп эталона
					 */
					for(size_t index = 1; index < expects.size(); index++) {
						// Выполняем проверку начальной границы захваченной группы
						ASSERT_EQ(captures.at(index).first, expects.at(index).first)
							<< "группа " << index << ": «" << expression << "» на тексте «" << text << "»";
						// Выполняем проверку конечной границы захваченной группы
						ASSERT_EQ(captures.at(index).second, expects.at(index).second)
							<< "группа " << index << ": «" << expression << "» на тексте «" << text << "»";
					}
					/**
					 * Выполняем обход границ групп, эталоном не захваченных
					 *
					 * @details Эталон обрывает набор на последней группе захваченной,
					 *          отчего группы за нею числятся незахваченными - и наш
					 *          набор обязан отвечать тем же. Проверка эта ловит
					 *          группу, нами захваченную ошибочно там, где эталон
					 *          её не захватил вовсе.
					 *
					 */
					for(size_t index = expects.size(); index < captures.size(); index++) {
						// Выполняем проверку отсутствия захвата группы
						ASSERT_EQ(captures.at(index).first, string::npos)
							<< "группа " << index << " захвачена лишней: «" << expression << "» на тексте «" << text << "»";
					}
				}
				/**
				 * Получаем вердикт проверки наличия совпадения в тексте
				 *
				 * @details Проверка наличия идёт путём своим: границ она не выдаёт,
				 *          отчего движок берёт для неё детерминированное исполнение
				 *          либо обход Пайка там, где сопоставление шло исполнением
				 *          с возвратом. Путь этот образцами порождаемыми не сличался
				 *          вовсе - его держала одна лишь проверка ручная о сотне пар.
				 *
				 */
				const bool verdict = engine.test(compiled, text, start);
				/**
				 * Если допустимый объём работы проверки наличия исчерпан
				 */
				if(!verdict && (engine.error() == regex::error_t::BUDGET_EXCEEDED))
					// Переходим к следующему образцу сличения
					continue;
				// Увеличиваем количество выполненных сличений вердикта наличия
				verdicts++;
				// Выполняем проверку совпадения вердикта наличия с эталоном
				ASSERT_EQ(verdict, expected) << "проверка наличия: «" << expression << "» на тексте «" << text << "» с позиции " << start;
			}
			/**
			 * Если ни одного сличения не выполнено
			 *
			 * @details Отсутствие сличений означает, что образцы не порождаются
			 *          либо отвергаются сборкой, и прогон при этом ничего не проверяет.
			 *
			 */
			ASSERT_GT(checked, static_cast <size_t> (0));
			/**
			 * Если образцов, эталоном не решённых, оказалось большинство
			 *
			 * @details Пропуск таких образцов молчаливым быть не должен: эталон,
			 *          предел исчерпывающий на большинстве образцов, сличения
			 *          собою уже не составляет, и прогон, зелёным остающийся,
			 *          изображал бы охват, какого нет.
			 *
			 */
			ASSERT_GT(checked, exhausted)
				<< "не решено " << exhausted << " образцов из " << (checked + exhausted);
			/**
			 * Если сличений вердикта проверки наличия не выполнено вовсе
			 *
			 * @details Проверка наличия идёт путём, от сопоставления отдельным,
			 *          и пропуск её обязан быть слышным: молчаливое исчерпание
			 *          предела у всех образцов оставило бы прогон зелёным при
			 *          пути, не проверенном ни разу.
			 *
			 */
			ASSERT_GT(verdicts, static_cast <size_t> (0));
			/**
			 * Если сличается сопоставитель в виде порождённого машинного кода
			 *
			 * @details Кодогенерацию получает лишь подмножество выражений, а прочие
			 *          сопоставляются толкователем и при заказанном режиме «JIT».
			 *          Оттого прогон обязан утверждать, что код и вправду порождался:
			 *          иначе сужение подмножества - или отказ кодогенерации целиком -
			 *          оставило бы прогон зелёным, сличая толкователь сам с собою
			 *          вторично. Доля берётся десятой частью: подмножеству отвечает
			 *          около половины порождаемых образцов, и запас здесь на разброс
			 *          источника псевдослучайных значений, а не на сужение охвата.
			 *
			 */
			if(jit)
				// Выполняем проверку порождения машинного кода у части образцов
				ASSERT_GT((generated * 10), checked)
					<< "машинный код порождён у " << generated << " образцов из " << checked;
		#else
			// Выходим из сличения с эталонной реализацией
			GTEST_SKIP() << "эталонная реализация PCRE2 сборке недоступна";
		#endif
	}
};

/**
 * @brief Функция сличения вердикта сборки с эталонной реализацией
 *
 * @details Сличение границ совпадения выражения, эталоном отвергнутые,
 *          пропускает вовсе, и точно так же пропускает отвергнутые модулем:
 *          расхождение отказов сборки не сличалось им никогда. Сличение это
 *          ведётся отдельно и на своём наборе образцов, складываемом
 *          из составных частей выражения.
 *
 * @param samples количество сличаемых образцов
 * @param seed    зерно порождения образцов сличения
 *
 */
void refusals([[maybe_unused]] const size_t samples, [[maybe_unused]] const uint32_t seed) noexcept(false) {
	/**
	 * Если сборка выполняется со сличением с эталонной реализацией
	 */
	#if defined(AWH_TEST_PCRE2)
		/**
		 * @brief Набор составных частей порождаемого выражения
		 *
		 */
		static const char * PARTS[] = {
			"a", "b", "z", ".", "\\d", "\\w", "\\s", "\\S", "\\b", "\\B", "\\A", "\\z", "\\Z", "\\G",
			"[a-z]", "[^a-z]", "[a-]", "[-a]", "[]a]", "[^]a]", "[[:alpha:]]", "[\\d\\s]",
			"(a)", "(?:a)", "(?<n>a)", "(?'m'a)", "(?P<p>a)", "(?>a)", "(?=a)", "(?!a)",
			"(?<=a)", "(?<!a)", "\\1", "\\2", "\\k<n>", "\\g{1}", "\\g<1>", "(?1)", "(?&n)",
			"(?R)", "(?(1)a|b)", "(?(<n>)a|b)", "(?(R)a|b)", "(?(R1)a|b)",
			"(?(DEFINE)(?<d>a))", "(?(?=a)b|c)", "[\\Q-\\E]", "[a-\\x7f]",
			"[\\p{L}]", "[^\\p{Nd}]", "[[:^digit:]]", "\\Q\\E", "\\E",
			"\\g{-1}", "(?P>n)", "(?J)", "(?U)", "{0}", "\\0",
			"*", "+", "?", "{2}", "{2,}", "{2,4}", "*?", "+?", "??", "*+", "++", "?+",
			"|", "^", "$", "(?i)", "(?-i)", "(?i:a)", "(?x)", "(?s)", "(?m)",
			"\\Qa+b\\E", "\\x41", "\\x{41}", "\\o{101}", "\\101", "\\n", "\\t", "\\p{L}",
			"\\P{L}", "\\h", "\\v", "\\R", "\\N", "\\K", "(?#c)", "(?|(a)|(b))"
		};
		/**
		 * @brief Набор обёрток порождаемого выражения
		 *
		 * @details Расхождения договора вскрываются не частями самими, а их
		 *          сочетанием: часть, внутрь обёртки помещённая, разбирается
		 *          правилами иными - проверкою окружения, классом символов
		 *          либо ветвью условия. Обёртка налагается дважды с вероятностью
		 *          в треть, отчего набор несёт и выражения простые, и вложенные.
		 *
		 */
		static const char * WRAPS[] = {
			"(%s)", "(?:%s)", "(?<n>%s)", "(?>%s)", "(?=%s)", "(?!%s)",
			"(?<=%s)", "(?<!%s)", "(?i:%s)", "(?|%s)", "%s|%s",
			"(?:%s)*", "(?:%s)?", "[%s]", "(?(1)%s|b)(x)"
		};
		// Получаем количество составных частей порождаемого выражения
		const size_t count = (sizeof(PARTS) / sizeof(PARTS[0]));
		// Получаем количество обёрток порождаемого выражения
		const size_t wraps = (sizeof(WRAPS) / sizeof(WRAPS[0]));
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём генератор порождения образцов сличения
		mt19937 gen(seed);
		// Количество образцов, обеими сторонами принятых и отвергнутых
		size_t accepted = 0, refused = 0;
		/**
		 * Выполняем обход набора образцов сличения
		 */
		for(size_t sample = 0; sample < samples; sample++) {
			// Порождаемое регулярное выражение
			string pattern;
			// Получаем количество составных частей выражения
			const size_t parts = (1 + (gen() % 5));
			/**
			 * Выполняем сборку выражения из составных частей
			 */
			for(size_t part = 0; part < parts; part++)
				// Выполняем добавление очередной составной части выражения
				pattern.append(PARTS[gen() % count]);
			/**
			 * Выполняем наложение обёрток порождаемого выражения
			 */
			for(size_t depth = 0; depth < 2; depth++) {
				/**
				 * Если обёртка на этом уровне не налагается
				 */
				if((gen() % 3) != 0)
					// Переходим к следующему уровню наложения обёртки
					continue;
				// Получаем очередную обёртку порождаемого выражения
				const string wrap = WRAPS[gen() % wraps];
				// Собираемое выражение с наложенной обёрткой
				string wrapped;
				/**
				 * Выполняем подстановку выражения в обёртку
				 */
				for(size_t i = 0; i < wrap.size(); i++) {
					/**
					 * Если обёртка содержит место подстановки выражения
					 */
					if((wrap.at(i) == '%') && ((i + 1) < wrap.size()) && (wrap.at(i + 1) == 's')) {
						// Выполняем подстановку выражения в обёртку
						wrapped.append(pattern);
						// Пропускаем обозначение места подстановки
						i++;
					// Выполняем добавление очередного символа обёртки
					} else wrapped.push_back(wrap.at(i));
				}
				// Выполняем замену выражения обёрнутым
				pattern = ::move(wrapped);
			}
			// Получаем режим разбора выражения как последовательности UTF-8
			const bool utf = ((gen() % 4) == 0);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 pattern.size(), (utf ? PCRE2_UTF : 0), &code, &spot, nullptr);
			// Получаем вердикт сборки эталонного регулярного выражения
			const bool expected = (reference != nullptr);
			/**
			 * Если сборка эталонного регулярного выражения выполнена
			 */
			if(reference != nullptr)
				// Выполняем освобождение эталонного регулярного выражения
				::pcre2_code_free(reference);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Получаем вердикт сборки регулярного выражения движком
			const bool obtained = engine.build(pattern,
			 (utf ? static_cast <uint32_t> (regex::flag_t::UTF) : 0), compiled);
			/**
			 * Если вердикты сборки разошлись
			 *
			 * @details Расхождение вердиктов означает договор различный: модуль
			 *          принимает выражение, эталоном отвергаемое, либо отвергает
			 *          принимаемое им, - и потребитель, эталоном ведомый,
			 *          получает не то, чего ждёт. Два расхождения при этом
			 *          допущены намеренно, и оба о длине ретроспективной проверки.
			 *
			 *          Первое: эталон требует от ветви проверки ретроспективной
			 *          длины строгой и отвергает как квантор неограниченный,
			 *          так и длину переменную - «(?<!\\s?+)» ему негоден. Модуль
			 *          же считает длину наименьшую и наибольшую и проверку
			 *          сопоставляет по ним, отчего принимает и длину переменную,
			 *          и квантор неограниченный над телом нулевой длины. Это
			 *          возможность сверх эталона, а не расхождение договора:
			 *          выражения эти эталоном не собираются вовсе, и сличать
			 *          сопоставление их не с чем.
			 *
			 *          Четвёртое: проверки окружения неатомарные «(?*...)»
			 *          и «(?<*...)» модулем не поддерживаются. Подменить их
			 *          проверками обыкновенными нельзя: отличие их в том и
			 *          состоит, что возврат внутрь проверки допускается,
			 *          и захваты её при возврате переизбираются. Поддержка
			 *          требует работы во всех путях сопоставления, а не
			 *          в разборе одном, и решается отдельно.
			 *
			 *          Третье: расширенные классы символов «(?[...]) » заведены
			 *          эталоном изданием 10.48, и модуль их не поддерживает.
			 *          Поддержка требует алгебры множеств над классом, а класс
			 *          несёт не одни диапазоны, но и ссылки на свойства Юникода:
			 *          свойства эти символьны и в диапазоны не разворачиваются,
			 *          отчего пересечение и разность с ними требуют устройства
			 *          класса иного. Это работа по охвату, а не правка,
			 *          и решается она отдельно.
			 *
			 *          Второе: эталон принимает ссылку на группу внутри проверки
			 *          ретроспективной, а модуль отвергает. Проверка эта
			 *          сопоставляется отступом назад на длину проверяемого,
			 *          а длина ссылки до сопоставления неизвестна; поддержка её
			 *          требует иного способа сопоставления и решается отдельно.
			 *
			 */
			if(obtained != expected) {
				// Текст ошибки сборки эталонного регулярного выражения
				PCRE2_UCHAR buffer[256];
				// Выполняем извлечение текста ошибки сборки эталона
				::pcre2_get_error_message(code, buffer, sizeof(buffer));
				// Получаем текст повода отказа эталона
				const string cause(reinterpret_cast <char *> (buffer));
				// Флаг допущения расхождения вердиктов сборки
				const bool allowed = (obtained ?
				 ((cause == "length of lookbehind assertion is not limited") ||
				  (cause == "lookbehind assertion is not fixed length")) :
				 ((engine.error() == regex::error_t::LOOKBEHIND_INVALID) ||
				  (pattern.find("(?[") != string::npos) ||
				  (pattern.find("(?*") != string::npos) ||
				  (pattern.find("(?<*") != string::npos)));
				/**
				 * Если расхождение вердиктов допущению не отвечает
				 */
				ASSERT_TRUE(allowed) << "«" << pattern << "»: модуль "
				 << (obtained ? "принял" : "отверг") << ", эталон "
				 << (expected ? "принял" : "отверг") << "; режим "
				 << (utf ? "UTF-8" : "обычный") << "; модуль: "
				 << engine.message() << "; эталон: " << cause;
				// Переходим к следующему образцу сличения
				continue;
			}
			/**
			 * Если выражение принято обеими сторонами
			 */
			if(obtained)
				// Увеличиваем количество образцов принятых
				accepted++;
			// Увеличиваем количество образцов отвергнутых
			else refused++;
		}
		/**
		 * Выполняем проверку разнообразия набора образцов сличения
		 *
		 * @details Набор, целиком принимаемый либо целиком отвергаемый, сличения
		 *          не ведёт вовсе: расхождение договора он показать не в силах.
		 *
		 */
		EXPECT_GT(accepted, (samples / 10));
		// Выполняем проверку наличия образцов отвергнутых
		EXPECT_GT(refused, (samples / 10));
	#endif
}
