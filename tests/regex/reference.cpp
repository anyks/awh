/**
 * @brief Функция сличения захватов при возврате с эталонной реализацией
 *
 * @details Порождение основного сличения рекурсии, условий, кванторов
 *          собственнических и групп со сбросом нумерации не даёт вовсе:
 *          устройства эти нагружают движок возврата и наборы захватов,
 *          а сличались лишь границы совпадения общего у выражений простых.
 *          Сличение ведёт набор захватов целиком, а не одни границы.
 *
 * @param samples количество сличаемых образцов
 * @param seed    зерно порождения образцов сличения
 *
 */
void captures([[maybe_unused]] const size_t samples, [[maybe_unused]] const uint32_t seed) noexcept(false) {
	/**
	 * Если сборка выполняется со сличением с эталонной реализацией
	 */
	#if defined(AWH_TEST_PCRE2)
		/**
		 * @brief Набор оснований порождаемого выражения
		 *
		 */
		static const char * BODIES[] = {
			"(a)", "(a|b)", "(?<n>a)", "(a)(b)", "(?:(a)|(b))", "(?|(a)|(b))",
			"(a*)", "(a+?)", "(a??)", "([ab]*)", "(a)(?:b)?", "((a)(b))"
		};
		/**
		 * @brief Набор продолжений порождаемого выражения
		 *
		 */
		static const char * TAILS[] = {
			"\\1", "\\1?", "\\1*", "\\k<n>?", "(?1)", "(?1)?", "(?R)?", "(?&n)?",
			"(?(1)a|b)", "(?(1)(c)|d)", "(?(<n>)a|b)", "a*+", "a++", "[ab]*+",
			"(?>a*)", "(?>[ab]+)b", "b", "", "\\g{-1}?", "(?(R)a|b)"
		};
		/**
		 * @brief Набор обёрток порождаемого выражения
		 *
		 */
		static const char * WRAPS[] = {
			"(%s)", "(?:%s)*", "(?>%s)", "(?<n2>%s)?", "(%s|b)", "(?:%s)?b"
		};
		/**
		 * @brief Набор текстов сопоставления
		 *
		 */
		static const char * TEXTS[] = {
			"a", "b", "ab", "aa", "aab", "abab", "aaab", "", "ba", "abc", "aabb", "cab",
			"aaaabbbb", "abababab", "aabbaabb", "ccc", "aaaaaaaaab", "bbbbbbbbba"
		};
		// Получаем количества оснований, продолжений, обёрток и текстов
		const size_t bodies = (sizeof(BODIES) / sizeof(BODIES[0]));
		const size_t tails = (sizeof(TAILS) / sizeof(TAILS[0]));
		const size_t wraps = (sizeof(WRAPS) / sizeof(WRAPS[0]));
		const size_t texts = (sizeof(TEXTS) / sizeof(TEXTS[0]));
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём генератор порождения образцов сличения
		mt19937 gen(seed);
		// Количество сличённых образцов
		size_t checked = 0;
		/**
		 * Выполняем обход набора образцов сличения
		 */
		for(size_t sample = 0; sample < samples; sample++) {
			// Порождаемое регулярное выражение
			string pattern(BODIES[gen() % bodies]);
			// Выполняем добавление продолжения выражения
			pattern.append(TAILS[gen() % tails]);
			/**
			 * Если выражению отводится продолжение второе
			 */
			if((gen() % 3) == 0)
				// Выполняем добавление продолжения второго
				pattern.append(TAILS[gen() % tails]);
			/**
			 * Если выражению отводится обёртка
			 */
			if((gen() % 3) == 0) {
				// Получаем очередную обёртку порождаемого выражения
				const string wrap = WRAPS[gen() % wraps];
				// Собираемое выражение с наложенной обёрткой
				string wrapped;
				/**
				 * Выполняем подстановку выражения в обёртку
				 */
				for(size_t i = 0; i < wrap.size(); i++) {
					/**
					 * Если обёртка содержит место подстановки выражения
					 */
					if((wrap.at(i) == '%') && ((i + 1) < wrap.size()) && (wrap.at(i + 1) == 's')) {
						// Выполняем подстановку выражения в обёртку
						wrapped.append(pattern);
						// Пропускаем обозначение места подстановки
						i++;
					// Выполняем добавление очередного символа обёртки
					} else wrapped.push_back(wrap.at(i));
				}
				// Выполняем замену выражения обёрнутым
				pattern = ::move(wrapped);
			}
			// Получаем признак сборки с порождением машинного кода
			const bool jit = ((gen() % 2) == 0);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 pattern.size(), PCRE2_NO_AUTO_POSSESS, &code, &spot, nullptr);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Получаем вердикт сборки регулярного выражения движком
			const bool built = engine.build(pattern,
			 (jit ? static_cast <uint32_t> (regex::flag_t::JIT) : 0), compiled);
			/**
			 * Если выражение собрано не обеими сторонами
			 */
			if((reference == nullptr) || !built) {
				/**
				 * Если эталонное регулярное выражение собрано
				 */
				if(reference != nullptr)
					// Выполняем освобождение эталонного регулярного выражения
					::pcre2_code_free(reference);
				// Переходим к следующему образцу сличения
				continue;
			}
			// Получаем текст сопоставления образца
			const string text = TEXTS[gen() % texts];
			// Выполняем размещение набора границ эталонного совпадения
			pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
			// Выполняем сопоставление эталонного регулярного выражения
			const int result = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
			// Получаем набор границ эталонного совпадения
			PCRE2_SIZE * bounds = ::pcre2_get_ovector_pointer(data);
			// Получаем вердикт эталонного сопоставления
			const bool expected = (result > 0);
			// Набор границ эталонных захватов
			vector <pair <size_t, size_t>> expects;
			/**
			 * Если совпадение эталоном найдено
			 */
			if(expected) {
				/**
				 * Выполняем обход набора границ эталонных захватов
				 */
				for(int index = 0; index < result; index++) {
					/**
					 * Если захват эталоном не установлен
					 */
					if(bounds[2 * index] == PCRE2_UNSET)
						// Выполняем добавление отсутствующего захвата
						expects.emplace_back(string::npos, string::npos);
					// Выполняем добавление границ установленного захвата
					else expects.emplace_back(static_cast <size_t> (bounds[2 * index]),
					 static_cast <size_t> (bounds[(2 * index) + 1]));
				}
			}
			// Выполняем освобождение набора границ эталонного совпадения
			::pcre2_match_data_free(data);
			// Выполняем освобождение эталонного регулярного выражения
			::pcre2_code_free(reference);
			// Набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> captures;
			// Получаем вердикт сопоставления движком
			const bool obtained = engine.exec(compiled, text, 0, captures);
			// Увеличиваем количество сличённых образцов
			checked++;
			// Выполняем сличение вердиктов сопоставления
			ASSERT_EQ(obtained, expected) << "«" << pattern << "» на «" << text << "»"
			 << (jit ? ", машинный код" : "");
			/**
			 * Если совпадение обеими сторонами найдено
			 */
			if(expected) {
				// Выполняем проверку количества захватов
				ASSERT_GE(captures.size(), expects.size()) << "«" << pattern << "» на «" << text << "»"
				 << (jit ? ", машинный код" : "");
				/**
				 * Выполняем обход набора границ эталонных захватов
				 */
				for(size_t index = 0; index < expects.size(); index++) {
					// Выполняем сличение начальной границы захвата
					ASSERT_EQ(captures.at(index).first, expects.at(index).first)
					 << "«" << pattern << "» на «" << text << "», захват " << index
					 << (jit ? ", машинный код" : "");
					// Выполняем сличение конечной границы захвата
					ASSERT_EQ(captures.at(index).second, expects.at(index).second)
					 << "«" << pattern << "» на «" << text << "», захват " << index
					 << (jit ? ", машинный код" : "");
				}
			}
		}
		// Выполняем проверку сличения образцов
		EXPECT_GT(checked, (samples / 2));
	#endif
}
/**
 * @brief Функция сличения переводов строки с эталонной реализацией
 *
 * @details Последовательности «\\R», «\\N» и «\\X» на текстах с переводом
 *          строки возврата каретки с эталоном не сличались: тексты сличения
 *          несли перевод строки одиночный, а пары «CRLF» не несли вовсе.
 *          Пропуск этот укрыл неатомарность «\\R».
 *
 *          Эталон собирается здесь с отменою самовозведения кванторов
 *          в собственнические: оптимизация эта у него меняет исход там,
 *          где «\\R» и «\\N» пересекаются знаком возврата каретки, - «\\R*\\N»
 *          на тексте «CRLF» она обращает в отказ, тогда как отступление
 *          квантора даёт совпадение. Опыт: с отменою оптимизации эталон
 *          согласен с модулем во всех таких образцах.
 *
 * @param samples количество сличаемых образцов
 * @param seed    зерно порождения образцов сличения
 *
 */
void breaks([[maybe_unused]] const size_t samples, [[maybe_unused]] const uint32_t seed) noexcept(false) {
	/**
	 * Если сборка выполняется со сличением с эталонной реализацией
	 */
	#if defined(AWH_TEST_PCRE2)
		/**
		 * @brief Набор составных частей порождаемого выражения
		 *
		 */
		static const char * PARTS[] = {
			"\\R", "\\X", "\\N", ".", "\\v", "\\h", "\\n", "\\r", "a", "b",
			"\\R+", "\\X+", "\\N+", ".+", "\\R*", "\\X*", "^", "$", "\\Z", "\\z", "\\A",
			"[\\r\\n]", "[^\\n]", "(\\R)", "(?:\\X)", "\\r\\n", "|", "\\b", "\u00e9"
		};
		/**
		 * @brief Набор текстов сопоставления
		 *
		 * @details Тексты несут пару возврата каретки с переводом строки,
		 *          одиночный возврат каретки, пару обратного порядка и знак
		 *          с надстрочным сочетанием: без них «\\R» и «\\X» сличать
		 *          не на чем.
		 *
		 */
		static const char * TEXTS[] = {
			"a\r\nb", "a\nb", "a\rb", "\r\n", "\n\r", "ab", "a b", "abc", "",
			"\r", "\n", "a\r\n\r\nb", "\u00e9x", "e\u0301x"
		};
		// Получаем количества частей и текстов сличения
		const size_t count = (sizeof(PARTS) / sizeof(PARTS[0]));
		const size_t texts = (sizeof(TEXTS) / sizeof(TEXTS[0]));
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём генератор порождения образцов сличения
		mt19937 gen(seed);
		// Количество сличённых образцов
		size_t checked = 0;
		/**
		 * Выполняем обход набора образцов сличения
		 */
		for(size_t sample = 0; sample < samples; sample++) {
			// Порождаемое регулярное выражение
			string pattern;
			// Получаем количество составных частей выражения
			const size_t parts = (1 + (gen() % 3));
			/**
			 * Выполняем сборку выражения из составных частей
			 */
			for(size_t part = 0; part < parts; part++)
				// Выполняем добавление очередной составной части выражения
				pattern.append(PARTS[gen() % count]);
			// Получаем режимы сборки образца сличения
			const bool utf = ((gen() % 2) == 0);
			const bool dotall = ((gen() % 3) == 0);
			const bool multi = ((gen() % 3) == 0);
			const bool jit = ((gen() % 2) == 0);
			// Собираем наборы признаков сборки модуля и эталона
			uint32_t mine = 0, theirs = PCRE2_NO_AUTO_POSSESS;
			/**
			 * Если разбор ведётся как последовательность UTF-8
			 */
			if(utf) {
				// Выполняем установку признаков сборки модуля
				mine |= (static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::UCP));
				// Выполняем установку признаков сборки эталона
				theirs |= (PCRE2_UTF | PCRE2_UCP);
			}
			/**
			 * Если точка отвечает и переводу строки
			 */
			if(dotall) {
				// Выполняем установку признака сборки модуля
				mine |= static_cast <uint32_t> (regex::flag_t::DOTALL);
				// Выполняем установку признака сборки эталона
				theirs |= PCRE2_DOTALL;
			}
			/**
			 * Если привязки отвечают границам строк
			 */
			if(multi) {
				// Выполняем установку признака сборки модуля
				mine |= static_cast <uint32_t> (regex::flag_t::MULTILINE);
				// Выполняем установку признака сборки эталона
				theirs |= PCRE2_MULTILINE;
			}
			/**
			 * Если выражение собирается с порождением машинного кода
			 */
			if(jit)
				// Выполняем установку признака порождения машинного кода
				mine |= static_cast <uint32_t> (regex::flag_t::JIT);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 pattern.size(), theirs, &code, &spot, nullptr);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Получаем вердикт сборки регулярного выражения движком
			const bool built = engine.build(pattern, mine, compiled);
			/**
			 * Если выражение собрано не обеими сторонами
			 */
			if((reference == nullptr) || !built) {
				/**
				 * Если эталонное регулярное выражение собрано
				 */
				if(reference != nullptr)
					// Выполняем освобождение эталонного регулярного выражения
					::pcre2_code_free(reference);
				// Переходим к следующему образцу сличения
				continue;
			}
			// Получаем текст сопоставления образца
			const string text = TEXTS[gen() % texts];
			// Выполняем размещение набора границ эталонного совпадения
			pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
			// Выполняем сопоставление эталонного регулярного выражения
			const int result = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
			// Получаем набор границ эталонного совпадения
			PCRE2_SIZE * bounds = ::pcre2_get_ovector_pointer(data);
			// Получаем вердикт эталонного сопоставления
			const bool expected = (result > 0);
			// Получаем границы эталонного совпадения
			const size_t begin = (expected ? static_cast <size_t> (bounds[0]) : 0);
			const size_t finish = (expected ? static_cast <size_t> (bounds[1]) : 0);
			// Выполняем освобождение набора границ эталонного совпадения
			::pcre2_match_data_free(data);
			// Выполняем освобождение эталонного регулярного выражения
			::pcre2_code_free(reference);
			// Набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> captures;
			// Получаем вердикт сопоставления движком
			const bool obtained = engine.exec(compiled, text, 0, captures);
			// Увеличиваем количество сличённых образцов
			checked++;
			// Выполняем сличение вердиктов сопоставления
			ASSERT_EQ(obtained, expected) << "«" << pattern << "» на тексте длиной " << text.size()
			 << (utf ? ", UTF-8" : "") << (jit ? ", машинный код" : "");
			/**
			 * Если совпадение обеими сторонами найдено
			 */
			if(expected) {
				// Выполняем сличение начальной границы совпадения
				ASSERT_EQ(captures.front().first, begin) << "«" << pattern << "» на тексте длиной " << text.size()
				 << (utf ? ", UTF-8" : "") << (jit ? ", машинный код" : "");
				// Выполняем сличение конечной границы совпадения
				ASSERT_EQ(captures.front().second, finish) << "«" << pattern << "» на тексте длиной " << text.size()
				 << (utf ? ", UTF-8" : "") << (jit ? ", машинный код" : "");
			}
		}
		// Выполняем проверку сличения образцов
		EXPECT_GT(checked, (samples / 2));
	#endif
}
/**
 * @brief Функция сличения имён захватывающих групп с эталонной реализацией
 *
 * @details Основное сличение ведёт границы совпадения и захватов, тогда как
 *          имена групп не проверяло вовсе: порождаемые им выражения именованных
 *          групп не несут. Сличение это ведёт соответствие имён наборам номеров,
 *          количество захватывающих групп и текст, извлекаемый по имени,
 *          в том числе в режиме «DUPNAMES», где одно имя объявлено несколькими
 *          группами и захват выполняет одна из них.
 *
 * @param samples количество сличаемых образцов
 * @param seed    зерно порождения образцов сличения
 *
 */
void naming([[maybe_unused]] const size_t samples, [[maybe_unused]] const uint32_t seed) noexcept(false) {
	/**
	 * Если сборка выполняется со сличением с эталонной реализацией
	 */
	#if defined(AWH_TEST_PCRE2)
		/**
		 * @brief Набор имён, объявляемых группами порождаемого выражения
		 *
		 * @details Имена берутся из набора малого умышленно: так одно имя
		 *          объявляется несколькими группами и режим «DUPNAMES»
		 *          получает нагрузку.
		 *
		 */
		static const char * NAMES[] = {"n", "x1", "_v", "name"};
		/**
		 * @brief Набор тел, заключаемых в порождаемые группы
		 *
		 */
		static const char * BODIES[] = {
			"a", "b+", "c?", "(?:d)", "\\d", "(x)", "[ab]", "a|b", "", "(?<inner>z)",
			"(?|(?<same>a)|(?<same>b))"
		};
		/**
		 * @brief Набор частей выражения вне именованных групп
		 *
		 */
		static const char * PARTS[] = {"", "|", "a", "\\d*", "(?:b)?", "(y)", "[abc]*"};
		/**
		 * @brief Набор частей, ссылающихся на имя группы
		 *
		 * @details Части эти несут обратные ссылки по имени, вызовы
		 *          именованных групп и условия по выполненности захвата
		 *          именем: имя, объявленное позже ссылки либо не объявленное
		 *          вовсе, разводит стороны по вердикту сборки.
		 *
		 */
		static const char * REFERENCES[] = {
			"\\k<@>", "\\k'@'", "\\k{@}", "(?P=@)", "\\g{@}",
			"(?&@)", "(?P>@)", "(?(<@>)a|b)", "(?('@')a)", "(?(@)a|b)"
		};
		/**
		 * @brief Набор текстов сопоставления
		 *
		 */
		static const char * TEXTS[] = {"", "a", "b", "ab", "abc", "xyz", "a1b2", "dz", "zzz", "cab"};
		// Получаем количества имён, тел, частей и текстов сличения
		const size_t names = (sizeof(NAMES) / sizeof(NAMES[0]));
		const size_t bodies = (sizeof(BODIES) / sizeof(BODIES[0]));
		const size_t parts = (sizeof(PARTS) / sizeof(PARTS[0]));
		const size_t references = (sizeof(REFERENCES) / sizeof(REFERENCES[0]));
		const size_t texts = (sizeof(TEXTS) / sizeof(TEXTS[0]));
		// Создаём объект работы с регулярными выражениями
		regexp_t regexp(::logger());
		// Создаём генератор порождения образцов сличения
		mt19937 gen(seed);
		// Количество сличённых образцов
		size_t checked = 0;
		/**
		 * Количества образцов, несущих одно имя у нескольких групп,
		 * и захватов по имени, не выполненных вовсе
		 *
		 * @details Счётчики эти доказывают, что сличение случаи эти проходит:
		 *          сличение, ни разу их не встретившее, проходило бы и при
		 *          движке, имён групп не ведущем вовсе.
		 *
		 */
		size_t duplicated = 0, unperformed = 0;
		/**
		 * Выполняем обход набора образцов сличения
		 */
		for(size_t sample = 0; sample < samples; sample++) {
			// Порождаемое регулярное выражение
			string pattern;
			// Получаем количество составных частей выражения
			const size_t count = (1 + (gen() % 4));
			/**
			 * Выполняем сборку выражения из составных частей
			 */
			for(size_t part = 0; part < count; part++) {
				/**
				 * Если очередной частью выражения выступает именованная группа
				 */
				if((gen() % 3) > 0) {
					// Получаем способ объявления имени группы
					const uint32_t kind = (gen() % 3);
					// Выполняем добавление открывающей части именованной группы
					pattern.append((kind == 0) ? "(?<" : ((kind == 1) ? "(?P<" : "(?'"));
					// Выполняем добавление имени объявляемой группы
					pattern.append(NAMES[gen() % names]);
					// Выполняем добавление закрывающей части имени группы
					pattern.append((kind == 2) ? "'" : ">");
					// Выполняем добавление тела объявляемой группы
					pattern.append(BODIES[gen() % bodies]);
					// Выполняем добавление закрывающей части именованной группы
					pattern.append(1, ')');
					/**
					 * Если к именованной группе приписывается квантор
					 */
					if((gen() % 4) == 0)
						// Выполняем добавление квантора именованной группы
						pattern.append(1, "?*+"[gen() % 3]);
				/**
				 * Иначе если очередной частью выступает ссылка на имя группы
				 */
				} else if((gen() % 2) == 0) {
					// Получаем очередную часть выражения, ссылающуюся на имя
					const string_view reference = REFERENCES[gen() % references];
					// Получаем имя группы, на какое ссылается часть выражения
					const string_view name = NAMES[gen() % names];
					// Получаем положение подстановки имени группы в части
					const size_t spot = reference.find('@');
					// Выполняем добавление части выражения с подставленным именем
					pattern.append(reference.substr(0, spot)).append(name).append(reference.substr(spot + 1));
				// Иначе выполняем добавление очередной части выражения
				} else pattern.append(PARTS[gen() % parts]);
			}
			// Получаем режимы сборки образца сличения
			const bool duplicates = ((gen() % 2) == 0);
			const bool jit = ((gen() % 2) == 0);
			// Собираем наборы признаков сборки модуля и эталона
			uint32_t mine = 0, theirs = 0;
			/**
			 * Если имена групп допускается объявлять повторно
			 */
			if(duplicates) {
				// Выполняем установку признака сборки модуля
				mine |= static_cast <uint32_t> (regex::flag_t::DUPNAMES);
				// Выполняем установку признака сборки эталона
				theirs |= PCRE2_DUPNAMES;
			}
			/**
			 * Если выражение собирается с порождением машинного кода
			 */
			if(jit)
				// Выполняем установку признака порождения машинного кода
				mine |= static_cast <uint32_t> (regex::flag_t::JIT);
			// Код ошибки сборки эталонного регулярного выражения
			int code = 0;
			// Смещение ошибки сборки эталонного регулярного выражения
			PCRE2_SIZE spot = 0;
			// Выполняем сборку эталонного регулярного выражения
			pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (pattern.c_str()),
			 pattern.size(), theirs, &code, &spot, nullptr);
			// Выполняем сборку регулярного выражения движком
			const auto expression = regexp.build(pattern, mine);
			// Получаем вердикт сборки регулярного выражения движком
			const bool built = static_cast <bool> (expression);
			// Выполняем сличение вердиктов сборки выражения
			ASSERT_EQ(built, (reference != nullptr)) << "«" << pattern << "»" << (duplicates ? ", DUPNAMES" : "");
			/**
			 * Если выражение собрано не обеими сторонами
			 */
			if(!built)
				// Переходим к следующему образцу сличения
				continue;
			// Количество имён, размер записи и адрес таблицы имён эталона
			uint32_t entries = 0, size = 0, groups = 0;
			// Адрес таблицы имён эталонного регулярного выражения
			PCRE2_SPTR table = nullptr;
			// Выполняем извлечение сведений об именах эталонного выражения
			::pcre2_pattern_info(reference, PCRE2_INFO_NAMECOUNT, &entries);
			::pcre2_pattern_info(reference, PCRE2_INFO_NAMEENTRYSIZE, &size);
			::pcre2_pattern_info(reference, PCRE2_INFO_NAMETABLE, &table);
			::pcre2_pattern_info(reference, PCRE2_INFO_CAPTURECOUNT, &groups);
			// Соответствие имён групп наборам их номеров эталона
			map <string, vector <uint32_t>> expected;
			/**
			 * Выполняем обход таблицы имён эталонного регулярного выражения
			 */
			for(uint32_t entry = 0; entry < entries; entry++) {
				// Получаем адрес очередной записи таблицы имён
				const PCRE2_SPTR record = (table + (static_cast <size_t> (entry) * size));
				// Получаем номер именованной группы записи
				const uint32_t number = ((static_cast <uint32_t> (record[0]) << 8) | static_cast <uint32_t> (record[1]));
				// Выполняем добавление номера группы в набор её имени
				expected[string(reinterpret_cast <const char *> (record + 2))].push_back(number);
			}
			/**
			 * Выполняем обход соответствия имён групп эталона
			 */
			for(auto & item : expected) {
				/**
				 * Если одно имя объявлено несколькими группами
				 */
				if(item.second.size() > 1) {
					// Увеличиваем количество образцов с одноимёнными группами
					duplicated++;
					// Выходим из обхода соответствия имён групп
					break;
				}
			}
			// Соответствие имён групп наборам их номеров движка
			map <string, vector <uint32_t>> obtained;
			/**
			 * Выполняем обход соответствия имён групп движка
			 */
			for(auto & item : regexp.groups(expression))
				// Выполняем добавление набора номеров имени группы
				obtained.emplace(item.first, item.second);
			// Выполняем сличение соответствий имён групп наборам их номеров
			ASSERT_EQ(obtained.size(), expected.size()) << "«" << pattern << "»" << (duplicates ? ", DUPNAMES" : "");
			/**
			 * Выполняем обход соответствия имён групп эталона
			 */
			for(auto & item : expected) {
				// Выполняем поиск имени группы в соответствии движка
				auto i = obtained.find(item.first);
				// Выполняем проверку обнаружения имени группы движком
				ASSERT_NE(i, obtained.end()) << "«" << pattern << "», имя «" << item.first << "»";
				// Выполняем сличение наборов номеров именованной группы
				ASSERT_EQ(i->second, item.second) << "«" << pattern << "», имя «" << item.first << "»";
				// Выполняем сличение номера, выводимого по имени группы
				ASSERT_EQ(regexp.group(expression, item.first), item.second.front())
				 << "«" << pattern << "», имя «" << item.first << "»";
			}
			// Выполняем сличение количества захватывающих групп выражения
			ASSERT_EQ(regexp.captures(expression), groups) << "«" << pattern << "»";
			// Выполняем проверку отсутствия имени группы, не объявленного вовсе
			ASSERT_EQ(regexp.group(expression, "absent"), static_cast <uint32_t> (0)) << "«" << pattern << "»";
			// Получаем текст сопоставления образца
			const string text = TEXTS[gen() % texts];
			// Выполняем размещение набора границ эталонного совпадения
			pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
			// Выполняем сопоставление эталонного регулярного выражения
			const int result = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
			// Набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> bounds;
			// Получаем вердикт сопоставления движком
			const bool matched = regexp.match(text, expression, bounds);
			// Увеличиваем количество сличённых образцов
			checked++;
			// Выполняем сличение вердиктов сопоставления
			ASSERT_EQ(matched, (result > 0)) << "«" << pattern << "» на тексте «" << text << "»"
			 << (duplicates ? ", DUPNAMES" : "") << (jit ? ", машинный код" : "");
			/**
			 * Если совпадение обеими сторонами найдено
			 */
			if(matched) {
				/**
				 * Выполняем обход соответствия имён групп эталона
				 */
				for(auto & item : expected) {
					// Адрес текста, извлечённого эталоном по имени группы
					PCRE2_UCHAR * buffer = nullptr;
					// Длина текста, извлечённого эталоном по имени группы
					PCRE2_SIZE length = 0;
					// Выполняем извлечение эталоном текста по имени группы
					const int status = ::pcre2_substring_get_byname(data,
					 reinterpret_cast <PCRE2_SPTR> (item.first.c_str()), &buffer, &length);
					// Выполняем извлечение движком текста по имени группы
					const string_view captured = regexp.capture(text, bounds, expression, item.first);
					/**
					 * Если захват именованной группой эталоном выполнен
					 */
					if(status == 0) {
						// Выполняем сличение текста, захваченного именованной группой
						ASSERT_EQ(captured, string_view(reinterpret_cast <const char *> (buffer), length))
						 << "«" << pattern << "» на тексте «" << text << "», имя «" << item.first << "»"
						 << (duplicates ? ", DUPNAMES" : "") << (jit ? ", машинный код" : "");
						// Выполняем проверку принадлежности захвата тексту сопоставления
						ASSERT_NE(captured.data(), nullptr)
						 << "«" << pattern << "» на тексте «" << text << "», имя «" << item.first << "»";
						// Выполняем освобождение текста, извлечённого эталоном
						::pcre2_substring_free(buffer);
					/**
					 * Иначе захват именованной группой не выполнен вовсе
					 */
					} else {
						// Увеличиваем количество захватов, не выполненных вовсе
						unperformed++;
						// Выполняем проверку невыполнения захвата движком
						ASSERT_EQ(captured.data(), nullptr)
						 << "«" << pattern << "» на тексте «" << text << "», имя «" << item.first << "»"
						 << (duplicates ? ", DUPNAMES" : "") << (jit ? ", машинный код" : "");
					}
				}
			}
			// Выполняем освобождение набора границ эталонного совпадения
			::pcre2_match_data_free(data);
			// Выполняем освобождение эталонного регулярного выражения
			::pcre2_code_free(reference);
		}
		// Выполняем проверку сличения образцов
		EXPECT_GT(checked, (samples / 4));
		// Выполняем проверку прохождения образцов с одноимёнными группами
		EXPECT_GT(duplicated, (samples / 100));
		// Выполняем проверку прохождения захватов, не выполненных вовсе
		EXPECT_GT(unperformed, (samples / 100));
	#endif
}
