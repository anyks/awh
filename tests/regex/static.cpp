/**
 * @brief Проверка копирования набора записей, места отведённого не занявшего
 *
 * @details Набор, место однажды отведший, а после сброшенный, записей не несёт,
 *          но местом владеет. Копирование такого набора перенимало прежде обзор
 *          места копируемого и обращало обзор во владение, запрашивая место
 *          под ноль записей: набор-копия оказывался владеющим местом, ему
 *          ненужным, а до обращения - обозревающим место чужое. Проверка
 *          сличает состав копии и её независимость от набора исходного.
 *
 */
TEST(Regex, StaticSequenceEmptyCopy) {
	// Заводим набор записей, место отводящий
	regex::Sequence <uint32_t> source;
	/**
	 * Выполняем наполнение набора записей
	 */
	for(uint32_t i = 0; i < 64; i++)
		// Выполняем добавление очередной записи набора
		source.push_back(i);
	// Выполняем проверку наполнения набора записей
	ASSERT_EQ(source.size(), static_cast <size_t> (64));
	// Выполняем сброс набора записей с сохранением размещения
	source.reset();
	// Выполняем проверку опустошения набора записей
	ASSERT_TRUE(source.empty());
	// Выполняем проверку сохранения места, набором отведённого
	ASSERT_TRUE(source.owned());
	// Выполняем копирование набора записей конструктором
	regex::Sequence <uint32_t> copied(source);
	// Выполняем проверку опустошения набора-копии
	EXPECT_TRUE(copied.empty());
	// Выполняем проверку отсутствия места, набором-копией отведённого
	EXPECT_FALSE(copied.owned());
	// Выполняем проверку отсутствия обзора места набора исходного
	EXPECT_EQ(copied.data(), static_cast <const uint32_t *> (nullptr));
	// Заводим набор записей, копию присваиванием принимающий
	regex::Sequence <uint32_t> assigned;
	/**
	 * Выполняем наполнение набора записей
	 */
	for(uint32_t i = 0; i < 8; i++)
		// Выполняем добавление очередной записи набора
		assigned.push_back(i);
	// Выполняем присваивание набора записей копированием
	assigned = source;
	// Выполняем проверку опустошения набора-копии
	EXPECT_TRUE(assigned.empty());
	// Выполняем проверку отсутствия места, набором-копией отведённого
	EXPECT_FALSE(assigned.owned());
	// Выполняем проверку отсутствия обзора места набора исходного
	EXPECT_EQ(assigned.data(), static_cast <const uint32_t *> (nullptr));
	/**
	 * Выполняем наполнение набора-копии после присваивания
	 *
	 * @details Наполнение ведётся затем, что набор-копия обязан оставаться
	 *          пригодным: сброс места его не отменяет пользования им.
	 *
	 */
	for(uint32_t i = 0; i < 16; i++)
		// Выполняем добавление очередной записи набора
		assigned.push_back(i * 3);
	// Выполняем проверку наполнения набора-копии
	ASSERT_EQ(assigned.size(), static_cast <size_t> (16));
	/**
	 * Выполняем сличение состава набора-копии
	 */
	for(uint32_t i = 0; i < 16; i++)
		// Выполняем проверку очередной записи набора-копии
		EXPECT_EQ(assigned.at(i), (i * 3));
}
/**
 * @brief Проверка путей размещения записи в конце набора
 *
 * @details Размещение записи ведётся быстрым путём, подставленным телом
 *          вызывающего, и медленным, вынесенным: быстрый берётся одним
 *          сравнением места с количеством. Условие это обязано уводить
 *          на путь медленный и набор обозревающий - места у него нет, а
 *          записи чужие, - и набор полный. Ошибка условия пишет запись
 *          в участок, набором обозреваемый, либо за пределы места набора,
 *          и проверка сличает оба случая: неприкосновенность участка
 *          обозреваемого и переезд записей набора полного.
 *
 */
TEST(Regex, StaticSequenceAppendPaths) {
	// Заводим участок записей, обозреваемый наборами
	uint32_t source[4] = {7, 8, 9, 0xDEADBEEF};
	// Заводим набор записей, обозревающий участок из трёх записей
	regex::Sequence <uint32_t> viewing;
	// Выполняем установку обзора участка записей
	viewing.attach(source, 3);
	// Выполняем проверку обзора участка, местом не владеющего
	ASSERT_FALSE(viewing.owned());
	// Выполняем добавление записи в набор обозревающий
	viewing.push_back(10);
	// Выполняем проверку обращения набора обозревающего во владеющий
	EXPECT_TRUE(viewing.owned());
	// Выполняем проверку ухода набора с участка обозреваемого
	EXPECT_NE(viewing.data(), static_cast <const uint32_t *> (source));
	// Выполняем проверку количества записей набора
	ASSERT_EQ(viewing.size(), static_cast <size_t> (4));
	// Выполняем проверку состава набора
	EXPECT_EQ(viewing.at(0), 7u);
	EXPECT_EQ(viewing.at(1), 8u);
	EXPECT_EQ(viewing.at(2), 9u);
	EXPECT_EQ(viewing.at(3), 10u);
	// Выполняем проверку неприкосновенности участка обозреваемого
	EXPECT_EQ(source[3], 0xDEADBEEF);
	/**
	 * Заводим набор, обозревающий участок пустой
	 *
	 * @details Набор этот - случай для условия быстрого пути крайний: место
	 *          и количество у него равны нулю оба, и сравнение строгое сочло
	 *          бы место достаточным, записав запись в участок обозреваемый.
	 *
	 */
	regex::Sequence <uint32_t> empty;
	// Выполняем установку обзора участка пустого
	empty.attach(source, 0);
	// Выполняем размещение записи в наборе, обозревающем участок пустой
	uint32_t * const placed = empty.emplace_back(11u);
	// Выполняем проверку указания, выданного медленным путём размещения
	ASSERT_NE(placed, static_cast <uint32_t *> (nullptr));
	// Выполняем проверку указания на запись, размещённую последней
	EXPECT_EQ(placed, &empty.back());
	// Выполняем проверку обращения набора обозревающего во владеющий
	EXPECT_TRUE(empty.owned());
	// Выполняем проверку ухода набора с участка обозреваемого
	EXPECT_NE(empty.data(), static_cast <const uint32_t *> (source));
	// Выполняем проверку количества записей набора
	ASSERT_EQ(empty.size(), static_cast <size_t> (1));
	// Выполняем проверку добавленной записи набора
	EXPECT_EQ(empty.at(0), 11u);
	// Выполняем проверку неприкосновенности первой записи участка
	EXPECT_EQ(source[0], 7u);
	// Заводим набор записей, место отводящий
	regex::Sequence <uint32_t> filled;
	// Выполняем добавление первой записи набора
	filled.push_back(0);
	// Получаем указание на место, отведённое первой записью
	const uint32_t * const first = filled.data();
	// Количество записей, помещающихся в место, отведённое первой записью
	size_t room = 1;
	/**
	 * Выполняем наполнение набора до переезда записей
	 *
	 * @details Размер первого отведённого места проверка не предполагает:
	 *          он узнаётся переездом записей, и запись, переезд вызвавшая,
	 *          обязана была его вызвать - в месте прежнем её не помещалось.
	 *
	 */
	while(filled.data() == first){
		// Выполняем проверку предела наполнения набора
		ASSERT_LT(room, static_cast <size_t> (1024));
		// Выполняем добавление очередной записи набора
		filled.push_back(static_cast <uint32_t> (room));
		// Выполняем учёт записей, в место прежнее поместившихся
		room += ((filled.data() == first) ? 1 : 0);
	}
	// Выполняем проверку количества записей: переезд вызван записью сверх места прежнего
	ASSERT_EQ(filled.size(), (room + 1));
	/**
	 * Выполняем сличение состава набора после переезда записей
	 */
	for(size_t i = 0; i < filled.size(); i++)
		// Выполняем проверку очередной записи набора
		EXPECT_EQ(filled.at(i), static_cast <uint32_t> (i));
	// Получаем указание на место после переезда записей
	const uint32_t * const moved = filled.data();
	// Выполняем сброс набора записей с сохранением размещения
	filled.reset();
	/**
	 * Выполняем наполнение сброшенного набора в пределах места прежнего
	 *
	 * @details Набор сброшенный место удерживает, и наполнение его в пределах
	 *          места прежнего идёт путём быстрым - записи не переезжают.
	 *
	 */
	for(size_t i = 0; i <= room; i++)
		// Выполняем добавление очередной записи набора
		filled.push_back(static_cast <uint32_t> (i * 5));
	// Выполняем проверку удержания места сброшенным набором
	EXPECT_EQ(filled.data(), moved);
	// Выполняем проверку количества записей набора
	ASSERT_EQ(filled.size(), (room + 1));
	/**
	 * Выполняем сличение состава сброшенного и вновь наполненного набора
	 */
	for(size_t i = 0; i <= room; i++)
		// Выполняем проверку очередной записи набора
		EXPECT_EQ(filled.at(i), static_cast <uint32_t> (i * 5));
	/**
	 * Выполняем размещение записи быстрым путём
	 *
	 * @details Сборка программы пишет поля инструкции через указание,
	 *          размещением выданное: указание обязано вести на запись,
	 *          размещённую последней, а не на иную запись набора.
	 *
	 */
	uint32_t * const fast = filled.emplace_back(77u);
	// Выполняем проверку указания, выданного быстрым путём размещения
	ASSERT_NE(fast, static_cast <uint32_t *> (nullptr));
	// Выполняем проверку указания на запись, размещённую последней
	EXPECT_EQ(fast, &filled.back());
	// Выполняем проверку размещённой записи
	EXPECT_EQ((* fast), 77u);
	// Выполняем проверку удержания места набором при размещении быстрым путём
	EXPECT_EQ(filled.data(), moved);
	// Выполняем проверку количества записей набора
	EXPECT_EQ(filled.size(), (room + 2));
}

/**
 * @brief Проверка разрешения ссылок и определения количества захватывающих групп
 *
 */
TEST(Regex, Captures) {
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	// Выполняем разбор регулярного выражения с захватывающими группами
	ASSERT_TRUE(parser.parse("(a)(?:b)(?<name>c)(d)", 0));
	// Выполняем проверку количества захватывающих групп
	EXPECT_EQ(parser.captures(), 3u);
	// Выполняем разбор регулярного выражения со сбросом нумерации ветвей
	ASSERT_TRUE(parser.parse("(?|(a)|(b)(c))", 0));
	// Выполняем проверку количества захватывающих групп
	EXPECT_EQ(parser.captures(), 2u);
	// Выполняем разбор регулярного выражения с опережающей ссылкой на группу
	ASSERT_TRUE(parser.parse("(?&name)(?<name>a)", 0));
	// Выполняем проверку разбора регулярного выражения с неразрешимой ссылкой
	EXPECT_FALSE(parser.parse("(?&missing)(?<name>a)", 0));
	// Выполняем проверку кода ошибки разбора
	EXPECT_EQ(parser.error(), regex::error_t::BAD_BACKREFERENCE);
}

/**
 * @brief Проверка хранилища классов символов, переживающего разборы
 *
 * @details Проверка закрепляет намеренное решение: сброс разбора записей
 *          хранилища классов не уничтожает, и класс разбора следующего
 *          формируется в записи прежней, место её рядов наследуя. Запись
 *          обязана очищаться получением: отрицание, диапазоны и свойства
 *          класса прежнего в класс новый не переходят, как не переходят
 *          и остатки класса, формирование которого прервано ошибкой разбора.
 *          Количество классов считается разбором текущим, а не записями
 *          хранилища, и запись за счётом классом не выдаётся.
 *
 */
TEST(Regex, StaticParserClassStorage) {
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	// Выполняем разбор выражения с классом отрицающим о восьми диапазонах и классом свойства
	ASSERT_TRUE(parser.parse("[^a-bd-eg-hj-km-np-qs-tv-w]\\p{Lu}", 0));
	// Выполняем проверку количества классов символов
	ASSERT_EQ(parser.classes(), 2u);
	// Выполняем проверку отрицания первого класса
	EXPECT_TRUE(parser.charClass(0).negative);
	// Выполняем проверку количества диапазонов первого класса
	EXPECT_EQ(parser.charClass(0).ranges.size(), static_cast <size_t> (8));
	// Выполняем проверку свойства второго класса
	EXPECT_EQ(parser.charClass(1).properties.size(), static_cast <size_t> (1));
	// Выполняем разбор выражения с классом о двух диапазонах и сокращённым классом
	ASSERT_TRUE(parser.parse("[bq]c\\d", 0));
	// Выполняем проверку количества классов символов
	ASSERT_EQ(parser.classes(), 2u);
	// Получаем первый класс разбора текущего
	const regex::class_t & first = parser.charClass(0);
	// Выполняем проверку снятия отрицания класса прежнего
	EXPECT_FALSE(first.negative);
	// Выполняем проверку количества диапазонов первого класса
	ASSERT_EQ(first.ranges.size(), static_cast <size_t> (2));
	// Выполняем проверку диапазонов первого класса
	EXPECT_EQ(first.ranges.at(0).begin, static_cast <uint32_t> ('b'));
	EXPECT_EQ(first.ranges.at(0).end, static_cast <uint32_t> ('b'));
	EXPECT_EQ(first.ranges.at(1).begin, static_cast <uint32_t> ('q'));
	EXPECT_EQ(first.ranges.at(1).end, static_cast <uint32_t> ('q'));
	// Выполняем проверку отсутствия свойств у первого класса
	EXPECT_TRUE(first.properties.empty());
	/**
	 * Выполняем проверку наследования места рядов записью прежней
	 *
	 * @details Два диапазона собственного места на восемь не отводят: место
	 *          о восьми диапазонах есть место класса прежнего, записью
	 *          сохранённое.
	 *
	 */
	EXPECT_GE(first.ranges.capacity(), static_cast <size_t> (8));
	// Получаем второй класс разбора текущего
	const regex::class_t & second = parser.charClass(1);
	// Выполняем проверку отрицания второго класса
	EXPECT_FALSE(second.negative);
	// Выполняем проверку количества диапазонов второго класса
	ASSERT_EQ(second.ranges.size(), static_cast <size_t> (1));
	// Выполняем проверку диапазона десятичных цифр второго класса
	EXPECT_EQ(second.ranges.at(0).begin, static_cast <uint32_t> ('0'));
	EXPECT_EQ(second.ranges.at(0).end, static_cast <uint32_t> ('9'));
	// Выполняем проверку снятия свойства класса прежнего
	EXPECT_TRUE(second.properties.empty());
	// Выполняем проверку отказа разбора класса незавершённого
	EXPECT_FALSE(parser.parse("[^k-m", 0));
	// Выполняем проверку отсутствия классов у разбора, прерванного ошибкой
	EXPECT_EQ(parser.classes(), 0u);
	// Выполняем разбор выражения с классом о двух диапазонах
	ASSERT_TRUE(parser.parse("[np]", 0));
	// Выполняем проверку количества классов символов
	ASSERT_EQ(parser.classes(), 1u);
	// Получаем класс разбора текущего
	const regex::class_t & third = parser.charClass(0);
	// Выполняем проверку снятия отрицания класса незавершённого
	EXPECT_FALSE(third.negative);
	// Выполняем проверку количества диапазонов класса
	ASSERT_EQ(third.ranges.size(), static_cast <size_t> (2));
	// Выполняем проверку диапазонов класса без остатков класса незавершённого
	EXPECT_EQ(third.ranges.at(0).begin, static_cast <uint32_t> ('n'));
	EXPECT_EQ(third.ranges.at(0).end, static_cast <uint32_t> ('n'));
	EXPECT_EQ(third.ranges.at(1).begin, static_cast <uint32_t> ('p'));
	EXPECT_EQ(third.ranges.at(1).end, static_cast <uint32_t> ('p'));
	// Выполняем разбор выражения без классов символов
	ASSERT_TRUE(parser.parse("x", 0));
	// Выполняем проверку отсутствия классов у разбора текущего
	EXPECT_EQ(parser.classes(), 0u);
	// Выполняем проверку выдачи записи за счётом пустым классом
	EXPECT_TRUE(parser.charClass(0).ranges.empty());
	EXPECT_FALSE(parser.charClass(0).negative);
}

/**
 * @brief Проверка работы разбора по требованию
 *
 * @details Проверка закрепляет намеренное решение: разбор не делает работы, итог
 *          какой выражению не нужен. Предварительный проход, считающий группы,
 *          ведётся лишь ссылкой с номером от десяти и однажды на разбор; пропуск
 *          пробелов - лишь в режиме «EXTENDED»; разбор кванторов - лишь за
 *          элементом, за каким следует знак квантора, либо в режиме «EXTENDED»;
 *          разрешение ссылок обходит узлы лишь того вида, какой разбор заводил.
 *          Всякая такая работа отмечается своим путём исполнения: разбор, звавший
 *          работу всякому выражению, дал бы отметки там, где их быть не должно.
 *          Разбор же, работу ошибочно снявший, выносит иной исход: число групп
 *          различает ссылку «\10» с восьмеричной последовательностью, режим
 *          «EXTENDED» отделяет квантор от элемента пробелом, а обход узлов
 *          находит ссылки, вызовы и условия на группы несуществующие.
 *
 */
TEST(Regex, StaticParserOnDemand) {
	/**
	 * Выполняем проверку заведения учёта путей исполнения
	 *
	 * @details Отказ здесь намеренный: набор проверок собирается с признаком
	 *          «AWH_REGEX_PROBING» всегда, и молчаливый пропуск проверки равен
	 *          молчаливому отключению того, что она стережёт.
	 *
	 */
	ASSERT_TRUE(regex::probe_t::enabled()) << "набор собран без учёта путей исполнения";
	// Получаем режим игнорирования пробельных символов
	const uint32_t extended = static_cast <uint32_t> (regex::flag_t::EXTENDED);
	// Число отметок, какое лишь больше нуля и точным не сличается
	const int64_t some = -1;
	/**
	 * @brief Ожидания исхода разбора и отметок путей исполнения
	 *
	 * @details Разборы кванторов в режиме «EXTENDED» идут за всяким элементом,
	 *          и число их сличается пределом снизу, а не точно.
	 *
	 */
	const struct {
		// Разбираемое регулярное выражение
		const char * pattern;
		// Режим разбора регулярного выражения
		uint32_t flags;
		// Ожидаемый исход разбора
		bool parsed;
		// Ожидаемое число предварительных проходов
		int64_t prescanning;
		// Ожидаемое число пропусков пробельных символов в режиме «EXTENDED»
		int64_t spacing;
		// Ожидаемое число разборов кванторов
		int64_t quantifying;
		// Ожидаемое число обходов узлов разрешением ссылок
		int64_t resolving;
	} samples[] = {
		{"abc(d)e", 0, true, 0, 0, 0, 0},
		{"a+b?c{2}", 0, true, 0, 0, 3, 0},
		{"a{x", 0, true, 0, 0, 1, 0},
		{"(a)\\1", 0, true, 0, 0, 0, 1},
		{"(a)\\10\\11", 0, true, 1, 0, 0, 0},
		{"(a)(b)(c)(d)(e)(f)(g)(h)(i)(j)\\10", 0, true, 1, 0, 0, 1},
		{"(a)(?1)", 0, true, 0, 0, 0, 1},
		{"(a)(?(1)b|c)", 0, true, 0, 0, 0, 1},
		{"(a)(?(1)\\1|c)", 0, true, 0, 0, 0, 2},
		{"(?x)a +b", 0, true, 0, some, some, 0},
		{"a +b", extended, true, 0, some, some, 0},
		{"(a)\\2", 0, false, 0, 0, 0, 1},
		{"(a)(?2)", 0, false, 0, 0, 0, 1},
		{"(a)(?(2)b|c)", 0, false, 0, 0, 0, 1}
	};
	// Создаём объект разбора регулярного выражения
	regex::parser_t parser;
	/**
	 * Выполняем обход ожиданий
	 */
	for(const auto & sample : samples){
		// Выполняем сброс счётчиков путей исполнения
		regex::probe_t::reset();
		// Выполняем проверку исхода разбора регулярного выражения
		ASSERT_EQ(parser.parse(sample.pattern, sample.flags), sample.parsed) << sample.pattern;
		/**
		 * Если разбор выражения отвергнут
		 */
		if(!sample.parsed){
			// Выполняем проверку кода отказа ссылкой на группу несуществующую
			EXPECT_EQ(parser.error(), regex::error_t::BAD_BACKREFERENCE) << sample.pattern;
		}
		/**
		 * @brief Сличение числа отметок пути с ожиданием
		 *
		 * @details Ожидание «some» требует отметок больше нуля, прочие - числа точного.
		 *
		 */
		auto expect = [&sample](const regex::path_t path, const int64_t wanted, const char * name) noexcept -> void {
			// Получаем число отметок пути исполнения
			const uint64_t count = regex::probe_t::count(path);
			/**
			 * Если ожидание требует отметок больше нуля
			 */
			if(wanted < 0){
				// Выполняем проверку наличия отметок
				EXPECT_GT(count, static_cast <uint64_t> (0)) << name << ": " << sample.pattern;
			/**
			 * Если ожидание требует числа отметок точного
			 */
			} else {
				// Выполняем проверку точного числа отметок
				EXPECT_EQ(count, static_cast <uint64_t> (wanted)) << name << ": " << sample.pattern;
			}
		};
		// Выполняем сличение отметок путей разбора
		expect(regex::path_t::PRESCANNING, sample.prescanning, "PRESCANNING");
		expect(regex::path_t::SPACING, sample.spacing, "SPACING");
		expect(regex::path_t::QUANTIFYING, sample.quantifying, "QUANTIFYING");
		expect(regex::path_t::RESOLVING, sample.resolving, "RESOLVING");
	}
}

/**
 * @brief Проверка отказа привязки к позиции за пределами текста
 *
 * @details Проверка закрепляет намеренное решение: позиция за размером текста
 *          привязке не отвечает ни при каком её виде, и отказ выносится единым
 *          образом. Часть видов привязки обращается к тексту напрямую, часть -
 *          разбором символа, и без единой проверки первые бросили бы исключение
 *          из функции, объявленной noexcept, тогда как вторые ответили бы
 *          отказом молча. Путь этот вызывающими ныне не достигается, однако
 *          держится он соглашением вызывающих, а не проверкой.
 *
 */
TEST(Regex, StaticAssertionBounds) {
	/**
	 * @brief Набор проверяемых видов привязки к позиции в тексте
	 *
	 */
	const vector <regex::anchor_t> anchors = {
		regex::anchor_t::TEXT_BEGIN,
		regex::anchor_t::TEXT_END,
		regex::anchor_t::TEXT_FINISH,
		regex::anchor_t::LINE_BEGIN,
		regex::anchor_t::LINE_END,
		regex::anchor_t::WORD_EDGE,
		regex::anchor_t::WORD_INNER,
		regex::anchor_t::SEARCH_HEAD,
		regex::anchor_t::KEEP_OUT
	};
	/**
	 * @brief Набор проверяемых наборов режимов компиляции
	 *
	 */
	const vector <uint32_t> modes = {
		0,
		static_cast <uint32_t> (regex::flag_t::MULTILINE),
		static_cast <uint32_t> (regex::flag_t::UTF),
		(static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::UCP)),
		(static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::MULTILINE))
	};
	/**
	 * @brief Набор проверяемых текстов сопоставления
	 *
	 */
	const vector <string> texts = {"", "a\n", "узел", "слово\nстрока"};
	/**
	 * Выполняем перебор набора текстов сопоставления
	 */
	for(const auto & text : texts){
		/**
		 * Выполняем перебор набора видов привязки к позиции в тексте
		 */
		for(const auto anchor : anchors){
			/**
			 * Выполняем перебор набора наборов режимов компиляции
			 */
			for(const auto flags : modes){
				/**
				 * Выполняем перебор позиций за пределами текста
				 */
				for(size_t offset = 1; offset < 5; offset++)
					// Выполняем проверку отказа привязки к позиции за пределами текста
					EXPECT_FALSE(regex::assertion(text, 0, anchor, flags, text.size() + offset));
				// Выполняем проверку отказа привязки к предельной позиции
				EXPECT_FALSE(regex::assertion(text, 0, anchor, flags, string::npos));
			}
		}
	}
}

/**
 * @brief Проверка поиска последовательности в тексте по якорному байту
 *
 * @details Поиск отыскивает в тексте не первый байт искомого, а байт, пробой
 *          текста признанный редчайшим: байт первый разборчивостью не отличается
 *          и обрывает поиск непрестанно. Проверка сличает итог с поиском
 *          средствами стандартными - совпадать они обязаны в точности,
 *          и совпадать при всяком тексте, ибо якорь выбирается самим текстом.
 *
 *          Путь этот включается лишь при остатке текста от четырёх килобайтов,
 *          отчего тексты проверки заведомо длиннее: на текстах коротких проверка
 *          мерила бы поиск обычный и правки не касалась бы вовсе.
 *
 */
TEST(Regex, StaticSeekAnchor) {
	/**
	 * @brief Набор текстов, поиск в каких выполняется
	 *
	 */
	vector <string> texts;
	// Создаём связный текст со знаками препинания, редкими в нём
	{
		// Создаём наполняемый текст сопоставления
		string text;
		// Выполняем размещение текста сопоставления
		text.reserve(0x10000);
		/**
		 * Выполняем наполнение текста сопоставления
		 */
		while(text.size() < 0xC000)
			// Выполняем добавление очередного участка текста
			text.append("the quick brown fox jumps over the lazy dog 1234 ");
		// Выполняем добавление искомых последовательностей у конца текста
		text.append("needle-in-haystack foxtrot forman@anyks.com needle 4096 ");
		// Выполняем добавление текста в набор
		texts.push_back(std::move(text));
	}
	// Создаём текст, знаками препинания насыщенный
	{
		// Создаём наполняемый текст сопоставления
		string text;
		// Выполняем размещение текста сопоставления
		text.reserve(0x10000);
		/**
		 * Выполняем наполнение текста сопоставления
		 */
		while(text.size() < 0xC000)
			// Выполняем добавление очередного участка текста
			text.append("{\"a-b\":[1,2],\"c@d\":\"e.f\"}\n");
		// Выполняем добавление искомых последовательностей у конца текста
		text.append("needle-in-haystack forman@anyks.com zzz");
		// Выполняем добавление текста в набор
		texts.push_back(std::move(text));
	}
	// Создаём текст из одного повторяющегося байта
	texts.push_back(string(0xC000, 'a') + "aab");
	// Создаём источник псевдослучайных значений
	mt19937 gen(20260816);
	// Создаём текст случайных байтов
	{
		// Создаём наполняемый текст сопоставления
		string text;
		// Выполняем размещение текста сопоставления
		text.reserve(0xC000);
		/**
		 * Выполняем наполнение текста сопоставления
		 */
		while(text.size() < 0xC000)
			// Выполняем добавление очередного байта текста
			text.append(1, static_cast <char> (gen() & 0xFF));
		// Выполняем добавление текста в набор
		texts.push_back(std::move(text));
	}
	/**
	 * @brief Набор искомых последовательностей
	 *
	 */
	const char * const NEEDLES[] = {
		"needle-in-haystack", "forman@anyks.com", "foxtrot", "needle",
		"the quick", "no-such-sequence-here", "zzz", "aab", "a", "ab",
		"dog 1234", "\"c@d\"", "}\n{", "", "over the lazy"
	};
	/**
	 * Выполняем перебор набора текстов поиска
	 */
	for(const auto & text : texts){
		// Получаем размер текста поиска
		const size_t size = text.size();
		/**
		 * Выполняем перебор набора искомых последовательностей
		 */
		for(const char * item : NEEDLES){
			// Получаем искомую последовательность
			const string_view what(item);
			/**
			 * Выполняем перебор позиций начала поиска
			 *
			 * @details Позиции берутся и нулевая, и произвольные, и предельные:
			 *          выбор якоря ведётся пробой остатка текста, а не текста
			 *          целиком, отчего от позиции начала поиска он и зависит.
			 *
			 */
			for(const size_t pos : {size_t(0), size_t(1), size_t(7), (size / 3), (size - 0x1000),
			 (size - 0x0800), (size - 1), size, (size + 1), string_view::npos}){
				/**
				 * Если позиция начала поиска за пределы текста выходит
				 */
				if(pos > size){
					// Выполняем проверку отказа поиска за пределами текста
					EXPECT_EQ(regex::seek(text, what, pos), string_view::npos) << item;
					// Переходим к следующей позиции начала поиска
					continue;
				}
				// Выполняем проверку совпадения итога поиска с поиском обычным
				EXPECT_EQ(regex::seek(text, what, pos), string_view(text).find(what, pos))
				 << "искомое «" << item << "» с позиции " << pos;
			}
		}
	}
}
/**
 * @brief Проверка поиска последовательности по одиночному редкому байту
 *
 * @details Байт искомого, в пробе текста не встреченный, отдаёт поиск
 *          средствам библиотеки С, и путь этот быстрейший из трёх. Ни одна
 *          проверка его не исполняла: тексты набора несут байты искомых
 *          своих в первых же шестидесяти четырёх знаках, отчего выбор
 *          одиночного байта отказывал всегда, и поиск шёл отбором по паре.
 *          Смещение выбранного байта в искомом при том участвует в счёте
 *          адресов, и ошибка его дала бы совпадения смещённые либо потерю
 *          совпадения у самого предела текста.
 *
 */
TEST(Regex, StaticSeekSolitary) {
	/**
	 * @brief Набор текстов, поиск в каких выполняется
	 *
	 */
	vector <string> texts;
	// Создаём текст из двух букв с искомыми последовательностями у конца
	{
		// Создаём наполняемый текст сопоставления
		string text;
		// Выполняем размещение текста сопоставления
		text.reserve(0x10000);
		/**
		 * Выполняем наполнение текста сопоставления
		 */
		while(text.size() < 0xC000)
			// Выполняем добавление очередного участка текста
			text.append("abababbaabbabaab");
		// Выполняем добавление искомых последовательностей у конца текста
		text.append("abqab qab bqa q");
		// Выполняем добавление текста в набор
		texts.push_back(std::move(text));
	}
	/**
	 * Создаём текст из двух букв, редкого байта не несущий вовсе
	 *
	 * @details Отсутствие байта в тексте целиком проверяет отказ поиска,
	 *          а не одно лишь обнаружение совпадения.
	 *
	 */
	texts.push_back(string(0xC000, 'a') + string(0x100, 'b'));
	/**
	 * Создаём текст, редкий байт в самом конце несущий
	 *
	 * @details Совпадение у предела текста проверяет счёт предела поиска:
	 *          смещение байта выбранного из предела вычитается, и ошибка
	 *          счёта того совпадение последнее теряет.
	 *
	 */
	texts.push_back(string(0xC000, 'a') + "abq");
	/**
	 * Создаём текст, пару искомого в окне частым, а байт его за окном редким
	 *
	 * @details Пути отбора по паре и поиска по байту одиночному сходятся лишь
	 *          здесь: пара выбирается пробою окна, а байт - пробою остатка
	 *          за окном, отчего частая пара «az» окна даёт кандидатов ложных
	 *          в изобилии, а байт «z», в шестидесяти четырёх знаках остатка
	 *          не встреченный, отдаёт поиск средствам библиотеки.
	 *
	 *          Граница области «az» берётся ровно по размеру окна: проба
	 *          остатка ведётся с позиции за окном, и область, окно
	 *          пережившая, байт искомого в пробу возвращает, отчего
	 *          выбор одиночного байта отказывает вновь.
	 *
	 */
	{
		// Создаём наполняемый текст сопоставления
		string text;
		// Выполняем размещение текста сопоставления
		text.reserve(0x10000);
		/**
		 * Выполняем наполнение окна текста парою искомого
		 */
		while(text.size() < 0x0400)
			// Выполняем добавление очередного участка окна
			text.append("az");
		// Выполняем добавление остатка текста, байта искомого не несущего
		text.append(string(0x8000, 'a'));
		// Выполняем добавление искомой последовательности у конца текста
		text.append("aazz");
		// Выполняем добавление текста в набор
		texts.push_back(std::move(text));
	}
	/**
	 * @brief Набор искомых последовательностей
	 *
	 */
	const char * const NEEDLES[] = {
		"q", "abq", "qab", "bqa", "abqab", "zzz", "qq", "aq", "ba", "abab",
		/**
		 * Искомые, отбор по паре изматывающие
		 *
		 * @details Якорный поиск включается лишь обилием кандидатов ложных
		 *          в окне, отчего искомое обязано нести начало частое: искомое,
		 *          редким байтом начинающееся, кандидатов не даёт вовсе,
		 *          и поиск ведётся отбором по паре, байта одиночного
		 *          не спрашивая.
		 *
		 */
		"ababq", "abababq", "abababbaabbabaabq", "ababababq", "aabbq", "ababzz",
		"azz", "azza", "zaz", "az", "aazz", "aaz"
	};
	/**
	 * Выполняем перебор набора текстов поиска
	 */
	for(const auto & text : texts){
		// Получаем размер текста поиска
		const size_t size = text.size();
		/**
		 * Выполняем перебор набора искомых последовательностей
		 */
		for(const char * item : NEEDLES){
			// Получаем искомую последовательность
			const string_view what(item);
			/**
			 * Выполняем перебор позиций начала поиска
			 */
			for(const size_t pos : {size_t(0), size_t(1), size_t(63), size_t(64), size_t(65),
			 (size / 3), (size - 0x1000), (size - 0x0800), (size - 4), (size - 1), size}) {
				/**
				 * Если позиция начала поиска за пределы текста выходит
				 */
				if(pos > size)
					// Переходим к следующей позиции начала поиска
					continue;
				// Выполняем проверку совпадения итога поиска с поиском обычным
				EXPECT_EQ(regex::seek(text, what, pos), string_view(text).find(what, pos))
				 << "искомое «" << item << "» с позиции " << pos << " в тексте размером " << size;
			}
		}
	}
}
