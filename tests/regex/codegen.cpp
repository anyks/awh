/**
 * @brief Проверка прохода повторения ленивого без записи кадра
 *
 * @details Повторение ленивое проходов вспять не отдаёт: проходы совершаются
 *          лишь по отказу продолжения, а отказ тела уводит наружу целиком.
 *          Оттого запись на проход ему не нужна вовсе - ни при теле постоянной
 *          длины, ни при переменном, - и ведёт оно проходы двумя местами кадра.
 *          Единственное, чем запись остаётся необходима, суть записи в ячейки
 *          внутри тела: границы групп захвата и ячейка сторожа прохода пустого
 *          живут самой записью, отчего тело, их пишущее, записи и требует.
 *          Проверка закрепляет решение это границами совпадения: разойдись
 *          порождение с разбором - и молчаливой правкой отделаться не выйдет.
 *
 */
TEST(Regex, CodegenLazyFrameless) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки прохода повторения ленивого без записи
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений, ленивое повторение над областью несущих
	 *
	 * @details Первые выражения тело постоянной длины несут - им запись
	 *          прохода и снимается, - а последние тело переменной длины
	 *          либо границы групп пишущее, и запись за ними остаётся.
	 *          Проверяются те и другие: правка обязана отличать их.
	 *
	 */
	static const char * const PATTERNS[] = {
		"(?:HT|TP)+?/", "(?:ab|cd)+?z", "(?:\\w\\w)+? 4096", "(?:ab|cd)*?z",
		"(?:HT|TP)+?/1", "x(?:ab|cd)+?z", "(?:[a-z]+ )+?dog", "(?:([a-z])[a-z])+?z",
		"(?:[a-z]* ?)*?dog", "\\((?:[^()]|\\([^()]*\\))*?\\)",
		"(?:ab|cd)+?z(?:HT|TP)+/", "(?:ab|cd)+?x(?:xy|zw)+?q",
		"(?:ab|cd)+?z(?:[a-z]+ )+dog", "([a-z])(?:ab|cd)+?z([0-9])",
		"(?:ab|cd)+?zx", "(?:HT|TP)+?/12", "(?:ab|cd)+?zzq",
		"(?:[a-z]+ )+?dog", "(?:[a-z]+/)+?v1", "\\((?:[^()]|\\([^()]*\\))*?\\)",
		"(?:[a-z]+ )+?dogs", "(?:\\w+@)+?com", "(?:[a-z]+,)+?z9",
		"(?:[a-z]* ?)*?dog", "(?:([a-z])+ )+?dog"
	};
	/**
	 * @brief Набор текстов сопоставления
	 */
	static const char * const TEXTS[] = {
		"HTTP/1.1 200 OK", "TPHT/", "HT", "abcdz", "cdabz", "zz", "",
		"\\w\\w 4096", "size 4096 bytes", "the lazy dog runs", "a b c dog",
		"abz", "xabcdz", "(inner (deep) tail)", "()",
		"abzHTTP/", "cdzTPHT/", "abxxyzwq", "abzcd xy dog", "qabz7", "zabz0",
		"abzyabzx", "abzqcdzx", "HT/2HTTP/12", "TP/1HT/12", "abzzabzzq", "cdzzq",
		"the lazy dog runs", "a b c dogs and dog", "api/v1 path", "usr/local/v1",
		"a@b@com", "one,two,z9", "lazy dog", "(inner (deep) tail)"
	};
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(const auto * pattern : PATTERNS) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку выражения из текста
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen(::logger());
		/**
		 * Если порождение сопоставителя выражения не выполнено
		 *
		 * @details Выражение с захватом внутри тела кодогенерации
		 *          не получает вовсе, и отказ его есть поведение
		 *          ожидаемое, а не изъян.
		 *
		 */
		if(!codegen.compile(expression.forward))
			// Переходим к выражению следующему набора
			continue;
		/**
		 * Выполняем обход набора текстов сопоставления
		 */
		for(const auto * text : TEXTS) {
			// Создаём набор границ совпадения разбора программы
			vector <pair <size_t, size_t>> expected;
			// Создаём набор границ совпадения порождённого сопоставителя
			vector <pair <size_t, size_t>> actual;
			// Выполняем сопоставление текста разбором программы
			const bool walking = engine.exec(expression, text, 0, expected);
			// Выполняем сопоставление текста порождённым машинным кодом
			const bool machine = codegen.exec(text, 0, actual);
			// Выполняем проверку схождения вердиктов обоих путей
			ASSERT_EQ(walking, machine) << pattern << " на тексте «" << text << "»";
			/**
			 * Если совпадение в тексте обнаружено
			 */
			if(walking) {
				// Выполняем проверку схождения числа границ обоих путей
				ASSERT_EQ(expected.size(), actual.size()) << pattern << " на тексте «" << text << "»";
				// Выполняем проверку схождения самих границ обоих путей
				ASSERT_EQ(expected, actual) << pattern << " на тексте «" << text << "»";
			}
		}
	}
}
TEST(Regex, CodegenSealed) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки прохода ряда без отдачи
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Набор выражений и текстов сопоставления
	 *
	 * @details Пары подобраны так, чтобы соседние выражения различались лишь
	 *          пересечением наборов: «a[0-9]*b» проход без отдачи получает,
	 *          а «a[0-9b]*b» - нет, ибо «b» принадлежит обоим наборам.
	 *
	 */
	struct Item {
		// Текст проверяемого регулярного выражения
		const char * pattern;
		// Текст сопоставления регулярного выражения
		const char * text;
	};
	// Создаём набор проверяемых выражений
	const vector <Item> items = {
		// Наборы не пересекаются: проход ведётся без отдачи
		{"a[0-9]*b", "a123b"}, {"a[0-9]*b", "a123c a45b"}, {"a[0-9]*b", "ab"},
		{"a[0-9]*b", "a999999999"}, {"\\w+@\\w+", "user@host tail"},
		{"\\((?:[^()]|\\([^()]*\\))*\\)", "(nested (parenthesis) done) tail"},
		{"(?:(\\w+) )+forman", "lorem ipsum dolor forman tail"},
		{"(?:(\\w+) )+forman", "lorem ipsum dolor tail"},
		// Наборы пересекаются: проход ведётся с отдачей
		{"a[0-9b]*b", "a123b"}, {"a[0-9b]*b", "a1b2b3b"}, {"a[0-9b]*b", "abbb"},
		{"[a-z]*a", "zzzaaa"}, {"[a-z]*a", "zzz"},
		// Ряд, всякий байт принимающий, продолжению не уступает никогда
		{".*b", "aaabaaab"}, {".*", "abc"},
		// Ряд ленивый отдачи не ведёт вовсе
		{"a[0-9]*?b", "a123b"}, {"a[0-9b]*?b", "a1b2b"}
	};
	/**
	 * Выполняем проверку каждого выражения набора
	 */
	for(const auto & item : items) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(item.pattern, 0, expression)) << item.pattern;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen(::logger());
		/**
		 * Если порождение сопоставителя выражения не выполнено
		 */
		if(!codegen.compile(expression.forward))
			// Выполняем переход к выражению следующему
			continue;
		// Создаём набор границ совпадения порождённого сопоставителя
		vector <pair <size_t, size_t>> received;
		// Создаём набор границ совпадения исполнения программы
		vector <pair <size_t, size_t>> expected;
		// Признак отказа порождённого сопоставителя от сопоставления
		bool refusing = false;
		// Выполняем сопоставление текста порождённым машинным кодом
		const bool obtained = codegen.exec(item.text, 0, received, refusing);
		/**
		 * Если порождённый сопоставитель от сопоставления отказался
		 */
		if(refusing)
			// Выполняем переход к выражению следующему
			continue;
		// Выполняем проверку совпадения итога с исполнением программы
		ASSERT_EQ(obtained, engine.exec(expression, item.text, 0, expected))
			<< item.pattern << " по тексту «" << item.text << "»";
		// Выполняем проверку совпадения границ с исполнением программы
		ASSERT_EQ(received, expected) << item.pattern << " по тексту «" << item.text << "»";
	}
}
/**
 * @brief Проверка ряда проходов ведущей ветви выбора
 *
 * @details Повторение над выбором отводит запись кадра на всякий проход, тогда как
 *          ряд повторения одиночного символа идёт вовсе без записи. Ветвь ведущая,
 *          одиночный символ сопоставляющая, позволяет соединить оба: проходы её
 *          образуют ряд позиций подряд, и положение всякого восстанавливается
 *          убавлением, а не записью. Годится это лишь при НЕПЕРЕСЕЧЕНИИ набора
 *          байтов ветви ведущей с первыми байтами ветвей прочих: иначе внутри ряда
 *          нашлись бы позиции, где пробовать надо и ветвь иную.
 *
 * @note Порождение ряда напрямую не наблюдаемо, отчего проверка сличает итог
 *       порождённого кода с исполнением программы: порча ряда меняет и границы
 *       совпадения, и сам вердикт
 *
 */
TEST(Regex, CodegenLeadingRun) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки ряда проходов ведущей ветви
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Набор выражений, ряду ведущей ветви подлежащих и не подлежащих
	 *
	 */
	const char * patterns[] = {
		// Наборы ветвей не пересекаются: ряд ведущей ветви порождается
		"\\((?:[^()]|\\([^()]*\\))*\\)",
		"(?:[^ab]|ab)*",
		"^(?:[^ab]|ab)*$",
		"(?:[a-y]|zz)+",
		"x(?:[^ab]|ab|aa)*y",
		/**
		 * Ветвь прочая есть рекурсивный вызов: первый байт берётся у тела его
		 *
		 * @details Тело выражения начинается скобкою, скобок же ведущая ветвь
		 *          не берёт - условие непересечения держится через вызов
		 */
		"\\((?:[^()]|(?R))*\\)",
		/**
		 * Наборы ветвей пересекаются: ряд неприменим, проход идёт записью
		 *
		 * @details Ветвь прочая берёт байт, ведущей недоступный: «(?:a|ab)» на
		 *          тексте «aab» обязана взять «a» и «ab», тогда как ряд ведущей
		 *          ветви остановился бы на «b» и попытки ветви второй внутри ряда
		 *          не дал бы. Образцы эти держат проверку непересечения: без неё
		 *          выходит 756 расхождений на 136 717 образцах перебора.
		 *
		 */
		"^(?:a|ab)*$", "^(?:a|ab)+$", "(?:a|ab)*c", "^(?:[ab]|bc)*$", "^(?:a|ax)*$",
		"\\((?:[^()]|zz)*\\)",
		// Пересечение через вызов: тело вызываемого ведущей ветви принадлежит
		"a(?:[a-z]|(?R))*z",
		"(?:[a-z]|zz)+",
		// Ветвь прочая совпадение пустое даёт: первого байта у неё нет вовсе
		"(?:[^ab]|a?)*b",
		// Повторение ленивое ряда проходов не образует
		"(?:[^ab]|ab)*?z"
	};
	// Азбука текстов перебора
	const string alphabet = "abcxz()";
	/**
	 * Выполняем проверку каждого выражения набора
	 */
	for(const char * pattern : patterns) {
		// Создаём собираемое выражение с порождением машинного кода
		regex::expression_t machine;
		// Создаём собираемое выражение исполнения программы
		regex::expression_t plain;
		// Выполняем сборку выражения с порождением машинного кода
		ASSERT_TRUE(engine.build(pattern, static_cast <uint32_t> (regex::flag_t::JIT), machine)) << pattern;
		// Выполняем сборку выражения исполнения программы
		ASSERT_TRUE(engine.build(pattern, 0, plain)) << pattern;
		/**
		 * Выполняем перебор текстов сопоставления по длинам до четырёх
		 */
		for(size_t length = 0; length <= 4; length++) {
			// Создаём набор положений букв азбуки в тексте
			vector <size_t> index(length, 0);
			/**
			 * Выполняем обход текстов сопоставления очередной длины
			 */
			for(;;) {
				// Создаём текст сопоставления очередной
				string text;
				/**
				 * Выполняем составление текста сопоставления из букв азбуки
				 */
				for(size_t i = 0; i < length; i++)
					// Выполняем добавление очередной буквы азбуки в текст
					text.push_back(alphabet.at(index.at(i)));
				// Создаём набор границ совпадения порождённого сопоставителя
				vector <pair <size_t, size_t>> received;
				// Создаём набор границ совпадения исполнения программы
				vector <pair <size_t, size_t>> expected;
				// Выполняем сопоставление текста порождённым машинным кодом
				const bool obtained = engine.exec(machine, text, 0, received);
				// Выполняем проверку совпадения итога с исполнением программы
				ASSERT_EQ(obtained, engine.exec(plain, text, 0, expected))
					<< pattern << " по тексту «" << text << "»";
				// Выполняем проверку совпадения границ с исполнением программы
				ASSERT_EQ(received, expected) << pattern << " по тексту «" << text << "»";
				// Получаем положение буквы, подлежащей смене
				size_t position = length;
				/**
				 * Выполняем переход к тексту следующему
				 */
				while(position > 0) {
					/**
					 * Если буква азбуки не последняя
					 */
					if(++index.at(position - 1) < alphabet.size())
						// Выходим из перехода к тексту следующему
						break;
					// Выполняем сброс буквы азбуки в первую
					index.at(position - 1) = 0;
					// Переходим к букве предыдущей
					position--;
				}
				/**
				 * Если тексты очередной длины исчерпаны
				 */
				if(position == 0)
					// Выходим из обхода текстов сопоставления
					break;
			}
		}
	}
}
TEST(Regex, CodegenEngine) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки встраивания порождённого кода
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений, встраивание проверяющих
	 *
	 */
	const char * patterns[] = {
		"\\w+@\\w+", "[0-9]+", "a|b", "GET|POST|PUT", "ab?c", "x?y?z",
		"(\\w+)@(\\w+)", "(?m)^(\\w+): (.+)$", "\\bneedle\\b", "^needle",
		"needle$", "[0-9]{3,5}", ".*needle", "\\w+(ing|ed)\\b", "(?i)needle",
		"\\w+(?=@)", "\\w+(?!@)",
		// Выражения, кодогенерации не получающие
		"needle", "(\\w)\\1", "(?<=@)\\w+", "(a)?b"
	};
	// Создаём источник псевдослучайных значений
	mt19937 gen(20260803);
	// Создаём набор текстов сопоставления
	vector <string> texts;
	// Получаем набор символов порождаемых текстов
	const string alphabet = "abcdefghijklmnopqrstuvwxyz0123456789 .@-:\n";
	/**
	 * Выполняем наполнение набора текстов сопоставления
	 */
	for(size_t i = 0; i < 200; i++) {
		// Формируем очередной текст сопоставления
		string text;
		// Получаем длину порождаемого текста в символах
		const size_t length = (gen() % 120);
		/**
		 * Выполняем наполнение порождаемого текста сопоставления
		 */
		for(size_t j = 0; j < length; j++)
			// Выполняем добавление очередного символа текста
			text.append(1, alphabet[gen() % alphabet.size()]);
		/**
		 * Выполняем добавление искомых последовательностей в текст
		 */
		if((gen() % 3) == 0) text.append("needle");
		if((gen() % 3) == 0) text.append("user@host");
		if((gen() % 4) == 0) text.append("\nHost: local\n");
		if((gen() % 4) == 0) text.append("walked");
		// Выполняем добавление порождённого текста сопоставления
		texts.push_back(text);
	}
	// Количество выражений, порождённый код получивших
	size_t machined = 0;
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & pattern : patterns) {
		// Создаём движок сопоставления исполнением программы
		regex::engine_t plain(::logger());
		// Создаём движок сопоставления порождённым машинным кодом
		regex::engine_t machine(::logger());
		// Создаём выражение, исполнением программы сопоставляемое
		regex::expression_t first;
		// Создаём выражение, порождённым машинным кодом сопоставляемое
		regex::expression_t second;
		// Выполняем сборку выражения без порождения машинного кода
		ASSERT_TRUE(plain.build(pattern, 0, first)) << pattern;
		// Выполняем сборку выражения с порождением машинного кода
		ASSERT_TRUE(machine.build(pattern, static_cast <uint32_t> (regex::flag_t::JIT), second)) << pattern;
		/**
		 * Если выражение порождённый код получило
		 */
		if(second.machine)
			// Увеличиваем количество выражений, порождённый код получивших
			machined++;
		/**
		 * Выполняем обход набора текстов сопоставления
		 */
		for(auto & text : texts) {
			// Создаём набор границ, исполнением программы установленных
			vector <pair <size_t, size_t>> expected;
			// Создаём набор границ, порождённым кодом установленных
			vector <pair <size_t, size_t>> received;
			// Выполняем сопоставление выражения исполнением программы
			const bool result = plain.exec(first, text, 0, expected);
			// Выполняем проверку совпадения вердикта сопоставления
			ASSERT_EQ(machine.exec(second, text, 0, received), result) << pattern << " на тексте «" << text << "»";
			/**
			 * Если совпадение в тексте обнаружено
			 */
			if(result) {
				// Выполняем проверку количества установленных границ
				ASSERT_EQ(received.size(), expected.size()) << pattern << " на тексте «" << text << "»";
				/**
				 * Выполняем обход границ совпадения и захваченных групп
				 */
				for(size_t i = 0; i < received.size(); i++)
					// Выполняем проверку установленных границ
					ASSERT_EQ(received.at(i), expected.at(i)) << pattern << " на тексте «" << text << "», граница " << i;
			}
		}
	}
	/**
	 * Выполняем проверку порождения кода хотя бы части выражений
	 *
	 * @details Отсутствие порождённого кода означает, что сличение ничего
	 *          не проверяет: встраивание перестало работать вовсе.
	 *
	 */
	ASSERT_GT(machined, static_cast <size_t> (10));
	/**
	 * Выполняем проверку отмены порождения режимами, им не соблюдаемыми
	 */
	{
		// Создаём движок регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку выражения с сопоставлением лишь с начала текста
		ASSERT_TRUE(engine.build("[0-9]+", (static_cast <uint32_t> (regex::flag_t::JIT) |
		 static_cast <uint32_t> (regex::flag_t::ANCHORED)), expression));
		// Выполняем проверку отмены порождения машинного кода
		EXPECT_FALSE(static_cast <bool> (expression.machine));
	}
	/**
	 * Выполняем проверку отмены порождения отказом от пустого совпадения
	 */
	{
		// Создаём движок регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку выражения с отказом от пустого совпадения
		ASSERT_TRUE(engine.build("a*", (static_cast <uint32_t> (regex::flag_t::JIT) |
		 static_cast <uint32_t> (regex::flag_t::NOTEMPTY)), expression));
		/**
		 * Выполняем проверку отмены порождения машинного кода
		 *
		 * @details Отказ от пустого совпадения порождённым кодом не соблюдается,
		 *          отчего порождение им и отменяется. Само же соблюдение этого
		 *          режима исполнением программы здесь не проверяется: оно к
		 *          встраиванию порождённого кода отношения не имеет.
		 *
		 */
		EXPECT_FALSE(static_cast <bool> (expression.machine));
	}
}
/**
 * @brief Тест записи и восстановления порождённого сопоставителя
 *
 * @details Восстановленный сопоставитель сличается с порождённым начисто по
 *          границам захвата на наборе текстов: совпадение устройства записи
 *          проверяется поведением, а не сличением полей.
 *
 */
TEST(Regex, CodegenStorage) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки записи порождённого сопоставителя
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Набор выражений проверки записи порождённого сопоставителя
	 *
	 */
	const char * const patterns[] = {
		"[a-z]+", "[0-9]{3,5}", "a[b-d]x", "\\w+@\\w+", "(?i)abc+",
		"[0-9]{1,3}(?:\\.[0-9]{1,3}){3}", "([a-z]+)-([0-9]+)", ".*needle"
	};
	/**
	 * @brief Набор текстов сличения поведения сопоставителей
	 *
	 */
	const char * const subjects[] = {
		"", "abc", "192.168.5.150", "forman@anyks.com", "index-4711",
		"ABCCC", "4711", "сено needle игла", "a b c", "x"
	};
	/**
	 * Выполняем перебор набора выражений проверки
	 */
	for(const char * pattern : patterns) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		// Получаем программу сопоставления в прямом направлении
		const regex::program_t & program = expression.forward;
		// Создаём порождаемый сопоставитель выражения
		regex::codegen_t fresh(::logger());
		/**
		 * Если кодогенерация к выражению неприменима
		 */
		if(!fresh.compile(program))
			// Переходим к следующему выражению набора
			continue;
		// Запись порождённого сопоставителя выражения
		string record;
		// Выполняем запись порождённого сопоставителя
		ASSERT_TRUE(fresh.save(record)) << pattern;
		// Выполняем проверку непустоты записи сопоставителя
		ASSERT_FALSE(record.empty()) << pattern;
		// Создаём восстанавливаемый сопоставитель выражения
		regex::codegen_t restored(::logger());
		// Позиция чтения записи порождённого сопоставителя
		size_t offset = 0;
		// Выполняем восстановление порождённого сопоставителя
		ASSERT_TRUE(restored.restore(record, offset, program)) << pattern;
		// Выполняем проверку прочтения записи до конца
		EXPECT_EQ(offset, record.size()) << pattern;
		// Выполняем проверку готовности восстановленного сопоставителя
		ASSERT_TRUE(restored.ready()) << pattern;
		// Выполняем сличение опознания программы сопоставителя
		EXPECT_EQ(restored.identity(), fresh.identity()) << pattern;
		/**
		 * Выполняем перебор набора текстов сличения
		 */
		for(const char * subject : subjects) {
			// Границы захвата, выданные сопоставителями
			vector <pair <size_t, size_t>> first, second;
			// Выполняем сопоставление порождённым начисто сопоставителем
			const bool former = fresh.exec(subject, 0, first);
			// Выполняем сопоставление восстановленным сопоставителем
			const bool latter = restored.exec(subject, 0, second);
			// Выполняем сличение наличия совпадения
			ASSERT_EQ(former, latter) << "выражение \"" << pattern << "\" на тексте \"" << subject << "\"";
			// Выполняем сличение границ захвата
			EXPECT_EQ(first, second) << "выражение \"" << pattern << "\" на тексте \"" << subject << "\"";
		}
	}
}
/**
 * @brief Тест отказа восстановления сопоставителя набора команд иного
 *
 * @details Порождённый код годен лишь набору команд, для какого порождён,
 *          поэтому запись несёт его опознание первым же байтом. Подмена
 *          опознания обязана обернуться отказом, а не исполнением чужих
 *          команд: вызывающая сторона порождает сопоставитель заново.
 *
 */
TEST(Regex, CodegenStorageForeign) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки отказа восстановления
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	// Создаём собираемое регулярное выражение
	regex::expression_t expression;
	// Выполняем сборку регулярного выражения
	ASSERT_TRUE(engine.build("[a-z]+[0-9]{2,4}", 0, expression));
	// Получаем программу сопоставления в прямом направлении
	const regex::program_t & program = expression.forward;
	// Создаём порождаемый сопоставитель выражения
	regex::codegen_t fresh(::logger());
	// Выполняем порождение сопоставителя выражения
	ASSERT_TRUE(fresh.compile(program));
	// Запись порождённого сопоставителя выражения
	string record;
	// Выполняем запись порождённого сопоставителя
	ASSERT_TRUE(fresh.save(record));
	// Выполняем проверку непустоты записи сопоставителя
	ASSERT_GT(record.size(), 1);
	/**
	 * Выполняем проверку отказа восстановления записи набора команд иного
	 */
	{
		// Получаем запись с подменённым опознанием набора команд
		string foreign = record;
		// Выполняем подмену опознания набора команд
		foreign[0] = static_cast <char> (0x5A);
		// Создаём восстанавливаемый сопоставитель выражения
		regex::codegen_t restored(::logger());
		// Позиция чтения записи порождённого сопоставителя
		size_t offset = 0;
		// Выполняем проверку отказа восстановления сопоставителя
		EXPECT_FALSE(restored.restore(foreign, offset, program));
		// Выполняем проверку неготовности сопоставителя
		EXPECT_FALSE(restored.ready());
	}
	/**
	 * Выполняем проверку отказа восстановления записи оборванной
	 *
	 * @details Обрыв проверяется на всякой длине: отказ обязан быть при всяком,
	 *          а падения быть не обязано ни при каком.
	 *
	 */
	for(size_t i = 0; i < record.size(); i++) {
		// Получаем оборванную запись порождённого сопоставителя
		const string cut = record.substr(0, i);
		// Создаём восстанавливаемый сопоставитель выражения
		regex::codegen_t restored(::logger());
		// Позиция чтения записи порождённого сопоставителя
		size_t offset = 0;
		// Выполняем проверку отказа восстановления сопоставителя
		EXPECT_FALSE(restored.restore(cut, offset, program)) << "оборвано на " << i;
	}
	// Создаём восстанавливаемый сопоставитель выражения
	regex::codegen_t restored(::logger());
	// Позиция чтения записи порождённого сопоставителя
	size_t offset = 0;
	// Выполняем проверку восстановления записи нетронутой
	EXPECT_TRUE(restored.restore(record, offset, program));
}

/**
 * @brief Проверка отказа порождения от программ, ему непригодных
 *
 * @details Порождение машинного кода охватывает не всякую программу: рекурсивный
 *          вызов, расширенный графемный кластер и условное выражение исполняются
 *          лишь разбором программы. Заслон пригодности - сторож правильности,
 *          а не ускоритель: порождение, к непригодной программе применённое,
 *          выдало бы сопоставитель, программе не отвечающий.
 *
 *          Проба гашения показала, что снятие заслона не срывало ни одной
 *          проверки набора: движок сам порождения таким выражениям не просит,
 *          и заслон стерёг обращение стороннее - то самое, каким пользуется
 *          потребитель библиотеки.
 *
 */
TEST(Regex, CodegenRefusal) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки отказа порождения
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений, порождению машинного кода непригодных
	 *
	 */
	static const char * SAMPLES[] = {
		"(?R)|a", "\\X+", "(?(1)a|b)(x)"
	};
	// Количество выражений, заслоном отвергнутых
	size_t refused = 0;
	/**
	 * Выполняем обход набора выражений
	 */
	for(const char * pattern : SAMPLES) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		// Выполняем проверку непригодности программы порождению
		EXPECT_FALSE(regex::codegen_t::applicable(expression.forward)) << pattern;
		// Создаём объект порождения машинного кода
		regex::codegen_t codegen(::logger());
		// Выполняем проверку отказа порождения сопоставителя
		EXPECT_FALSE(codegen.compile(expression.forward)) << pattern;
		// Выполняем проверку отсутствия порождённого сопоставителя
		EXPECT_FALSE(codegen.ready()) << pattern;
		// Выполняем учёт выражения, заслоном отвергнутого
		refused++;
	}
	/**
	 * Выполняем проверку охвата набора выражений
	 *
	 * @details Проверка охвата обязательна: сборка, всякому выражению отказавшая,
	 *          оставила бы проверку пройденной, заслона не тронув вовсе.
	 *
	 */
	ASSERT_EQ(refused, (sizeof(SAMPLES) / sizeof(SAMPLES[0])));
}

/**
 * @brief Проверка избрания способа отбора позиций порождённым кодом
 *
 * @details Отбор позиций начала попытки сопоставления ведётся в порождённом коде
 *          четырьмя способами, и способ избирается по составу выражения. Отбор
 *          есть ускоритель чистый: гашение всякого из способов вердикта не меняет,
 *          а лишь заставляет проходить текст попыткой в каждой позиции. Сплошная
 *          проба гашения показала, что все четыре способа гасились, не сорвав
 *          ни одной проверки набора, - оттого способ и опознаётся здесь прямо.
 *
 */
TEST(Regex, CodegenFilter) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки избрания способа отбора позиций
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений с ожидаемым способом отбора позиций
	 *
	 */
	static const struct {
		// Регулярное выражение, подлежащее порождению
		const char * pattern;
		// Набор режимов сборки регулярного выражения
		const uint32_t flags;
		// Ожидаемый способ отбора позиций начала попытки
		const regex::filter_t filter;
		// Ожидаемый признак проверки возможности совпадения
		const bool feasibility;
		// Ожидаемый признак отодвигания начала поиска
		const bool skipping;
	} SAMPLES[] = {
		{"HTTP/1\\.[01]",  0,                                              regex::filter_t::SEEK,      false, false},
		{"[a-z]+/v1",      0,                                              regex::filter_t::NONE,      true,  false},
		{"^[a-z]+[0-9]",   static_cast <uint32_t> (regex::flag_t::MULTILINE), regex::filter_t::LINING,  false, false},
		{"(?:aa|bb|cc) ",  0,                                              regex::filter_t::SIFTING,   true,  true},
		{"(?:HT|TP)/1",    0,                                              regex::filter_t::SIFTING,   true,  true},
		{"\\w+@\\w+",      0,                                              regex::filter_t::SIFTING,   true,  false},
		{"(?:fox|dog)trot",0,                                              regex::filter_t::NARROWING, false, false},
		{"^abc",           0,                                              regex::filter_t::NONE,      false, false}
	};
	// Количество выражений, порождением проверенных
	size_t machined = 0;
	// Количество сопоставителей, восстановление прошедших
	size_t restoring = 0;
	/**
	 * Выполняем обход набора выражений
	 */
	for(auto & sample : SAMPLES) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample.pattern, sample.flags, expression)) << sample.pattern;
		// Создаём объект порождения машинного кода
		regex::codegen_t codegen(::logger());
		/**
		 * Если порождение сопоставителя выражения не выполнено
		 */
		if(!codegen.compile(expression.forward)) {
			// Выполняем проверку неприменимости порождения к программе
			ASSERT_FALSE(regex::codegen_t::applicable(expression.forward)) << sample.pattern;
			// Переходим к следующему выражению набора
			continue;
		}
		// Выполняем учёт выражения, порождением проверенного
		machined++;
		// Выполняем проверку избранного способа отбора позиций
		EXPECT_EQ(codegen.filter(), sample.filter) << sample.pattern << " -> "
		 << static_cast <uint32_t> (codegen.filter());
		/**
		 * Выполняем проверку признаков проверки возможности и отодвигания
		 *
		 * @details Признаки эти ускорители такие же чистые, как и самый отбор:
		 *          проба гашения показала, что гашение проверки возможности
		 *          не срывало ни одной проверки набора, а с нею гасло
		 *          и отодвигание начала поиска, от неё зависящее.
		 *
		 */
		EXPECT_EQ(codegen.feasibility(), sample.feasibility) << sample.pattern;
		// Выполняем проверку признака отодвигания начала поиска
		EXPECT_EQ(codegen.skipping(), sample.skipping) << sample.pattern;
		// Заводим запись сохранения порождённого сопоставителя
		string record;
		// Выполняем сохранение порождённого сопоставителя
		ASSERT_TRUE(codegen.save(record)) << sample.pattern;
		// Создаём объект порождения, запись принимающий
		regex::codegen_t restored(::logger());
		// Смещение чтения записи сохранения
		size_t offset = 0;
		/**
		 * Если восстановление порождённого сопоставителя выполнено
		 *
		 * @details Способ отбора вложен в самый код и оттуда не читается,
		 *          оттого он и пишется записью: сопоставитель восстановленный
		 *          обязан отвечать о своём отборе тем же способом.
		 *
		 */
		if(restored.restore(record, offset, expression.forward)) {
			// Выполняем учёт сопоставителя, восстановление прошедшего
			restoring++;
			// Выполняем проверку способа отбора у сопоставителя восстановленного
			EXPECT_EQ(restored.filter(), sample.filter) << sample.pattern;
			// Выполняем проверку признака проверки возможности у восстановленного
			EXPECT_EQ(restored.feasibility(), sample.feasibility) << sample.pattern;
			// Выполняем проверку признака отодвигания у восстановленного
			EXPECT_EQ(restored.skipping(), sample.skipping) << sample.pattern;
		}
	}
	/**
	 * Выполняем проверку охвата набора выражений
	 *
	 * @details Проверка охвата обязательна: порождение, всякому выражению
	 *          отказавшее, оставило бы проверку пройденной, ни одного способа
	 *          отбора не сличив.
	 *
	 */
	ASSERT_EQ(machined, (sizeof(SAMPLES) / sizeof(SAMPLES[0])));
	// Выполняем проверку охвата восстановлением записи
	ASSERT_EQ(restoring, machined);
}


/**
 * @brief Тест отбора позиций начала попытки по обязательному литералу
 *
 * @details Отбор этот порождается лишь у выражений, чей обязательный литерал
 *          длиною от двух байтов, а набор допустимых первых байтов при том
 *          непуст: до заведения порога просеивание набором байтов отменяло
 *          отбор всегда, и путь этот такими выражениями не проходился вовсе.
 *
 *          Проверка сличает границы совпадения порождённого кода с исполнением
 *          программы на текстах, где допустимых первых байтов множество,
 *          а литерал встречается однажды и у самого конца: путь отбора там
 *          и работает, а расхождение означало бы, что пропуск участков
 *          пропускает и совпадение.
 *
 *          Сличение ведётся с нескольких позиций начала поиска: отбор ведёт
 *          поиск от позиции переданной, и ошибка на границе её вышла бы
 *          пропуском совпадения, начинающегося ровно с неё.
 *
 */
TEST(Regex, CodegenNarrowing) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки отбора позиций по обязательному литералу
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений, отбору по обязательному литералу подлежащих
	 *
	 */
	const char * patterns[] = {
		"(?:fox|dog)trot", "(?:fox|dog)tr", "(?:aa|bb)cd",
		"(?:fox|dog)trap", "(?:[fd]o[xg])trot", "(?:fox|dog)tr[oa]t"
	};
	// Количество выражений, порождением проверенных
	size_t machined = 0;
	// Количество сличений, совпадение обнаруживших
	size_t matched = 0;
	/**
	 * Выполняем обход выражений набора
	 */
	for(const char * pattern : patterns) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		/**
		 * Создаём выражение эталонное, порождения машинного кода лишённое
		 *
		 * @details Эталон собирается отдельно намеренно: сопоставление
		 *          выражением, машинный код получившим, идёт этим самым кодом,
		 *          и сличение его с собою прошло бы при любой порче. Изъян
		 *          этот был живым: проверка сличала две одинаковых дороги
		 *          и порождённый отбор, на байт ошибающийся, пропускала.
		 *
		 */
		regex::expression_t reference;
		// Выполняем сборку выражения эталонного исполнением программы
		ASSERT_TRUE(engine.build(pattern, 0, reference)) << pattern;
		// Выполняем проверку отсутствия машинного кода у выражения эталонного
		ASSERT_FALSE(static_cast <bool> (reference.machine)) << pattern;
		// Выполняем сборку регулярного выражения с порождением машинного кода
		ASSERT_TRUE(engine.build(pattern, static_cast <uint32_t> (regex::flag_t::JIT), expression)) << pattern;
		/**
		 * Если порождение машинного кода выражению не выполнено
		 */
		if(!expression.machine)
			// Переходим к выражению следующему набора
			continue;
		// Увеличиваем количество выражений, порождением проверенных
		machined++;
		/**
		 * Выполняем обход длин текстов сличения
		 *
		 * @details Длины взяты разные намеренно: отбор пропускает участки
		 *          разом, и ошибка его на тексте коротком способна не выйти
		 *          наружу вовсе - пропускать там нечего.
		 *
		 */
		for(const size_t length : {64ul, 512ul, 4096ul, 40960ul}) {
			// Собираемый текст сличения
			string text;
			/**
			 * Выполняем наполнение текста допустимыми первыми байтами
			 */
			while(text.size() < length)
				// Выполняем добавление очередного участка текста
				text.append("the quick brown fox jumps over the lazy dog 1234 ");
			// Выполняем усечение текста до заданной длины
			text.resize(length);
			// Выполняем добавление искомой последовательности у конца текста
			text.append("foxtrot dogtrap aacd ");
			/**
			 * Выполняем обход позиций начала поиска совпадения
			 */
			for(const size_t start : {static_cast <size_t> (0), (length / 2), (length - 1), length}) {
				// Набор границ захвата исполнения программы
				vector <pair <size_t, size_t>> plain;
				// Набор границ захвата порождённого машинного кода
				vector <pair <size_t, size_t>> machine;
				// Выполняем сопоставление исполнением программы
				const bool one = engine.exec(reference, text, start, plain);
				// Выполняем сопоставление порождённым машинным кодом
				const bool two = expression.machine->exec(text, start, machine);
				// Выполняем проверку совпадения вердиктов обеих дорог
				ASSERT_EQ(one, two) << pattern << ", длина " << length << ", позиция " << start;
				/**
				 * Если совпадение обеими дорогами обнаружено
				 */
				if(one && !plain.empty() && !machine.empty()) {
					// Увеличиваем количество сличений, совпадение обнаруживших
					matched++;
					// Выполняем проверку совпадения начальной границы
					ASSERT_EQ(plain.front().first, machine.front().first)
					 << pattern << ", длина " << length << ", позиция " << start;
					// Выполняем проверку совпадения конечной границы
					ASSERT_EQ(plain.front().second, machine.front().second)
					 << pattern << ", длина " << length << ", позиция " << start;
				}
			}
		}
	}
	/**
	 * Выполняем проверку прохождения проверкою порождённого кода
	 *
	 * @details Отсутствие порождённого кода означает, что сличение ничего
	 *          не проверяет: путь отбора перестал порождаться вовсе.
	 *
	 */
	ASSERT_GT(machined, static_cast <size_t> (3));
	/**
	 * Выполняем проверку того, что сличению было что сличать
	 *
	 * @details Сличение двух отказов проходит и при отборе, совпадение
	 *          пропускающем: проверка, совпадений не нашедшая, молчаливо
	 *          выключена. Оттого число найденных и утверждается.
	 *
	 */
	ASSERT_GT(matched, static_cast <size_t> (20));
}

/**
 * @brief Тест опережающего отказа выражениям вне регулярного подмножества
 *
 * @details Построение подмножества регулярного отвергает узлы, исполнением
 *          детерминированным не воспроизводимые, и отказ этот прежде выходил
 *          наружу лишь посреди построения - выражение с возвратом строилось
 *          дважды. Ныне отказ выносится обходом дерева до построения.
 *
 *          Проверка держит границу с обеих сторон, и вторая сторона важнее
 *          первой: отказ выражению, подмножеству принадлежащему, отнял бы
 *          у него исполнение детерминированное - потеря молчаливая,
 *          правильности не нарушающая и оттого проверками прочими
 *          не улавливаемая вовсе.
 *
 */
TEST(Regex, CompilerSubsetRefusal) {
	// Создаём объект движка регулярных выражений
	regex::engine_t engine(::logger());
	/**
	 * @brief Выражения, регулярному подмножеству не принадлежащие
	 *
	 */
	const char * foreign[] = {
		"(a)\\1",              // ссылка обратная
		"(?=abc)abc",          // просмотр вперёд
		"(?<=abc)def",         // просмотр назад
		"(?>[0-9]+)a",         // группа атомарная
		"[0-9]++",             // квантор захватывающий
		"\\((?:[^()]|(?R))*\\)", // вызов рекурсивный
		"abc\\Kdef",           // сброс начала совпадения
		"(a)(?(1)b|c)"         // условие
	};
	/**
	 * @brief Выражения, регулярному подмножеству принадлежащие
	 *
	 */
	const char * native[] = {
		"[0-9]+", "a|b", "(?:ab)*c", "(a)(b)(c)", "^[a-z]+$",
		"[0-9]{2,4}", "a+?b", "(?i)[a-z]+", "(?m)^abc$", "\\bword\\b",
		"(?:fox|dog)trot", "[^abc]+", "\\d{1,3}\\.\\d{1,3}"
	};
	/**
	 * Выполняем обход выражений, подмножеству не принадлежащих
	 */
	for(const char * pattern : foreign) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем проверку выполнения сборки регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		/**
		 * Выполняем проверку исполнения выражения с возвратом
		 *
		 * @details Признак этот и означает, что подмножество регулярное
		 *          выражению отказало, - неважно, до построения либо посреди.
		 *
		 */
		ASSERT_TRUE(expression.backtracking) << pattern;
	}
	/**
	 * Выполняем обход выражений, подмножеству принадлежащих
	 */
	for(const char * pattern : native) {
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем проверку выполнения сборки регулярного выражения
		ASSERT_TRUE(engine.build(pattern, 0, expression)) << pattern;
		/**
		 * Выполняем проверку исполнения выражения без возврата
		 *
		 * @details Отказ здесь означал бы, что опережающая проверка отсеяла
		 *          лишнее: выражение исполнялось бы возвратом там, где ему
		 *          доступно исполнение детерминированное.
		 *
		 */
		ASSERT_FALSE(expression.backtracking) << pattern;
	}
}

/**
 * @brief Тест отодвигания начала поиска обязательным литералом
 *
 * @details Поиск обязательного литерала называет и позицию, раньше какой
 *          совпадение начаться не может, и участок до неё пропускается разом.
 *
 *          Отодвигание отменяется привязкой к началу попытки поиска: привязка
 *          эта равняется на позицию, сопоставителю переданную, и отодвигание
 *          её сдвинуло бы саму привязку, обратив отказ в мнимое совпадение.
 *          Изъян этот был живым и пойман сличением с эталоном; проверка держит
 *          его отдельно затем, чтобы место отказа лежало при причине, а не
 *          в случайном образце перебора.
 *
 */
TEST(Regex, CodegenSkipping) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки отодвигания начала поиска
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Выражения, привязку к началу попытки поиска несущие
	 *
	 */
	const char * headed[] = {
		"(?:\\b[0-9]|\\G\\w)(?m)a+.+", "\\Gabc", "(?:x|\\G)abc", "\\G[a-z]+9"
	};
	/**
	 * @brief Выражения, привязки к началу попытки поиска лишённые
	 *
	 */
	const char * plain[] = {
		"(?:HT|TP)/1", "[a-z]+/v1", "(?:fox|dog)trot", "\\w+@[a-z]+\\.com"
	};
	// Количество выражений, порождением проверенных
	size_t machined = 0;
	// Количество сличений, совпадение обнаруживших
	size_t matched = 0;
	/**
	 * @brief Тексты сличения обеих сторон границы
	 *
	 */
	const string texts[] = {
		string("GET /index.html HTTP/1.1 abc x y99a99c1a_bb foxtrot forman@anyks.com path/v19"),
		(string(600, 'q') + " HTTP/1.1 abc a99c1a_bb foxtrot forman@anyks.com path/v19"),
		string("abc"), string("x\n ya99c1a_bb \ncy01z_z1"), string()
	};
	/**
	 * Выполняем обход выражений обеих сторон границы
	 */
	for(const char * pattern : {headed[0], headed[1], headed[2], headed[3],
	 plain[0], plain[1], plain[2], plain[3]}) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine(::logger());
		// Создаём выражение эталонное, порождения машинного кода лишённое
		regex::expression_t reference;
		// Выполняем проверку сборки выражения эталонного
		ASSERT_TRUE(engine.build(pattern, 0, reference)) << pattern;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем проверку сборки выражения с порождением машинного кода
		ASSERT_TRUE(engine.build(pattern, static_cast <uint32_t> (regex::flag_t::JIT), expression)) << pattern;
		/**
		 * Если порождение машинного кода выражению не выполнено
		 */
		if(!expression.machine)
			// Переходим к выражению следующему набора
			continue;
		// Увеличиваем количество выражений, порождением проверенных
		machined++;
		/**
		 * Выполняем обход текстов сличения
		 */
		for(const string & text : texts) {
			/**
			 * Выполняем обход позиций начала поиска совпадения
			 */
			for(const size_t start : {static_cast <size_t> (0), (text.size() / 3), text.size()}) {
				// Набор границ захвата исполнения программы
				vector <pair <size_t, size_t>> plainly;
				// Набор границ захвата порождённого машинного кода
				vector <pair <size_t, size_t>> machine;
				// Выполняем сопоставление исполнением программы
				const bool one = engine.exec(reference, text, start, plainly);
				// Выполняем сопоставление порождённым машинным кодом
				const bool two = expression.machine->exec(text, start, machine);
				// Выполняем проверку совпадения вердиктов обеих дорог
				ASSERT_EQ(one, two) << pattern << " на «" << text << "» с позиции " << start;
				/**
				 * Если совпадение обеими дорогами обнаружено
				 */
				if(one && !plainly.empty() && !machine.empty()) {
					// Увеличиваем количество сличений, совпадение обнаруживших
					matched++;
					// Выполняем проверку совпадения начальной границы
					ASSERT_EQ(plainly.front().first, machine.front().first)
					 << pattern << " на «" << text << "» с позиции " << start;
					// Выполняем проверку совпадения конечной границы
					ASSERT_EQ(plainly.front().second, machine.front().second)
					 << pattern << " на «" << text << "» с позиции " << start;
				}
			}
		}
	}
	/**
	 * Выполняем проверку прохождения проверкою порождённого кода
	 */
	ASSERT_GT(machined, static_cast <size_t> (4));
	/**
	 * Выполняем проверку того, что сличению было что сличать
	 */
	ASSERT_GT(matched, static_cast <size_t> (5));
}
