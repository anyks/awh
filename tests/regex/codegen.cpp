/**
 * @brief Проверка состава подмножества, получающего кодогенерацию
 *
 * @details Кодогенерация принимает подмножество программ, а не всякую программу.
 *          Проверка закрепляет состав подмножества: расширение его - работа
 *          последующая, но сужение означало бы утрату уже достигнутого.
 *
 */
