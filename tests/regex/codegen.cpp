/**
 * @brief Пространство имён вспомогательных значений проверки
 *
 */
namespace {
	/**
	 * @brief Части, из каких собираются порождаемые выражения
	 *
	 */
	const char * ATOMS[] = {
		"a", "b", "0", "[0-9]", "[a-z]", "\\d", "\\w",
		"\\s", ".", "[^0-9]", "x", "\\n", "[abc]", "[^a-c]"
	};

	/**
	 * @brief Кванторы повторения, приписываемые частям выражения
	 *
	 */
	const char * REPEATS[] = {"", "*", "+", "?", "{2}", "{1,3}", "*?", "+?", "??"};

	/**
	 * @brief Символы текста сопоставления
	 *
	 */
	const char * LETTERS[] = {"a", "b", "0", " ", "\n", "x", "y", "z", "c", "1", "9", "_"};
};

/**
 * @brief Проверка состава подмножества, получающего кодогенерацию
 *
 * @details Кодогенерация принимает подмножество программ, а не всякую программу.
 *          Проверка закрепляет состав подмножества: расширение его - работа
 *          последующая, но сужение означало бы утрату уже достигнутого.
 *
 */
TEST(Regex, CodegenSubset) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки состава подмножества
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений и ожидаемой применимости кодогенерации
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Набор режимов компиляции регулярного выражения
		uint32_t flags;
		// Ожидаемая применимость кодогенерации к выражению
		bool applicable;
	} samples[] = {
		// Последовательности одиночных символов и классов символов
		{"needle",          0, true},
		{"[0-9]",           0, true},
		{"a[b-d]x",         0, true},
		// Неограниченные жадные повторения одиночного символа
		{"[0-9]+",          0, true},
		{"a*b",             0, true},
		{"\\w+@\\w+",       0, true},
		{".*needle",        0, true},
		// Повторение без учёта регистра символов
		{"(?i)abc+",        0, true},
		// Ограниченные повторения разворачиваются в переходы, рядом не являющиеся
		{"[0-9]{3,5}",      0, false},
		// Ленивое повторение проходом ряда не описывается
		{"[0-9]+?",         0, false},
		// Захват групп порождаемым кодом не выполняется
		{"(\\w+)@(\\w+)",   0, false},
		// Привязки к позиции в тексте кодогенерации пока не получают
		{"^needle",         0, false},
		{"\\bneedle",       0, false},
		// Выбор одной из ветвей проходом ряда не описывается
		{"a|b",             0, false},
		// Обратные ссылки и проверки окружения требуют исполнения с возвратом
		{"(\\w)\\1",        0, false},
		{"\\w+(?=@)",       0, false},
		// Режим разбора UTF-8 сопоставляет символы целиком, а не байты
		{"[0-9]+",          static_cast <uint32_t> (regex::flag_t::UTF), false}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample.pattern, sample.flags, expression)) << sample.pattern;
		// Выполняем проверку применимости кодогенерации к выражению
		ASSERT_EQ(regex::codegen_t::applicable(expression.forward), sample.applicable) << sample.pattern;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen;
		// Выполняем проверку порождения сопоставителя выражения
		ASSERT_EQ(codegen.compile(expression.forward), sample.applicable) << sample.pattern;
		// Выполняем проверку готовности порождённого сопоставителя
		ASSERT_EQ(codegen.ready(), sample.applicable) << sample.pattern;
	}
}
/**
 * @brief Проверка границ совпадения, установленных порождённым кодом
 *
 * @details Проверка сличает границы, установленные порождённым кодом, с границами,
 *          установленными исполнением программы. Набор образцов покрывает отступление
 *          вглубь ряда повторения и отступление сквозь несколько рядов подряд:
 *          именно им порождённый код заменяет набор точек возврата.
 *
 */
TEST(Regex, CodegenBounds) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из проверки границ совпадения
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	/**
	 * @brief Набор выражений и текстов сопоставления
	 *
	 */
	const struct {
		// Текст регулярного выражения
		const char * pattern;
		// Текст сопоставления регулярного выражения
		const char * text;
	} samples[] = {
		// Ряд повторения, отступающий к последующему сопоставлению
		{"\\w+@\\w+",      "почта forman@anyks здесь"},
		{"\\d+x",          "999x!"},
		{"a*b",            "aaab"},
		// Ряд повторения, поглощающий текст до конца
		{"[0-9]+",         "abc 12345 def"},
		{".*needle",       "head needle tail needle end"},
		// Отступление сквозь несколько рядов подряд
		{"\\w+ \\w+z",     "alpha bravo charliez tail"},
		{"a+b+c",          "aaabbbc"},
		{"[a-z]+[0-9]+x",  "abc123x"},
		// Ряд, отступающий до нулевой длины
		{"a*ab",           "aaab"},
		{"\\w*\\w\\w",     "abc"},
		// Совпадение, отсутствующее в тексте
		{"[0-9]+zzz",      "abc 12345 def"},
		{"a+b",            "aaaa"},
		// Совпадение в самом начале и в самом конце текста
		{"a+",             "aaa"},
		{"\\d+",           "abc9"},
		// Пустой текст сопоставления
		{"a*",             ""},
		{"a+",             ""},
		/**
		 * Отбор позиции начала попытки сопоставления
		 *
		 * @details Отбор по ведущему литералу заменяет сопоставление его символов
		 *          продвижением позиции, отбор по единственному допустимому байту
		 *          его не заменяет, а обязательный литерал прекращает поиск вовсе.
		 *          Вызов подпрограммы отбора затирает регистры, сохранности каких
		 *          соглашение о вызове не обещает, отчего образцы эти закрепляют
		 *          заодно и сохранение их в кадре вызова.
		 *
		 */
		{"needle",         "hay hay needle hay"},
		{"needle",         "hay hay noodle hay"},
		{"needle+",        "hay needlee hay"},
		{"n[aeiou]+dle",   "hay nuedle hay"},
		{"xyz[0-9]+",      "aaa xyz123 bbb"},
		{"xyz[0-9]+",      "aaa xyz bbb"},
		{"\\w+@\\w+",      "no address here"},
		{".*needle",       "no such sequence"}
	};
	/**
	 * Выполняем обход набора проверяемых выражений
	 */
	for(auto & sample : samples) {
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		// Выполняем сборку регулярного выражения
		ASSERT_TRUE(engine.build(sample.pattern, 0, expression)) << sample.pattern;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen;
		// Выполняем проверку порождения сопоставителя выражения
		ASSERT_TRUE(codegen.compile(expression.forward)) << sample.pattern;
		// Создаём набор границ, установленных порождённым кодом
		vector <pair <size_t, size_t>> received;
		// Создаём набор границ, установленных исполнением программы
		vector <pair <size_t, size_t>> expected;
		// Выполняем сопоставление регулярного выражения порождённым кодом
		const bool result = codegen.exec(sample.text, 0, received);
		// Выполняем проверку совпадения вердикта сопоставления
		ASSERT_EQ(result, engine.exec(expression, sample.text, 0, expected)) << sample.pattern << " на тексте «" << sample.text << "»";
		/**
		 * Если совпадение в тексте обнаружено
		 */
		if(result) {
			// Выполняем проверку начальной границы совпадения
			EXPECT_EQ(received.front().first, expected.front().first) << sample.pattern << " на тексте «" << sample.text << "»";
			// Выполняем проверку конечной границы совпадения
			EXPECT_EQ(received.front().second, expected.front().second) << sample.pattern << " на тексте «" << sample.text << "»";
		}
	}
}
/**
 * @brief Сличение порождённого кода с исполнением программы на порождаемых образцах
 *
 * @details Проверка порождает выражения и тексты сопоставления и сличает границы
 *          на всяком выражении, кодогенерацию получившем. Исполнение программы
 *          служит здесь образцом: правильность его самого установлена сличением
 *          с эталонной реализацией PCRE2.
 *
 */
TEST(Regex, CodegenMatching) {
	/**
	 * Если кодогенерация сборкой не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available())
		// Выходим из сличения порождённого кода
		GTEST_SKIP() << "кодогенерация сборкой не поддерживается";
	// Создаём источник псевдослучайных значений
	mt19937 gen(20260802);
	// Создаём объект движка регулярных выражений
	regex::engine_t engine;
	// Количество выражений, получивших кодогенерацию
	size_t accepted = 0;
	/**
	 * Выполняем обход порождаемых образцов сличения
	 */
	for(size_t sample = 0; sample < 20000; sample++) {
		// Формируем порождаемое регулярное выражение
		string pattern;
		// Получаем количество частей порождаемого выражения
		const size_t parts = (1 + (gen() % 4));
		/**
		 * Выполняем наполнение порождаемого выражения
		 */
		for(size_t i = 0; i < parts; i++) {
			// Выполняем добавление очередной части выражения
			pattern.append(ATOMS[gen() % 14]);
			// Выполняем добавление квантора повторения части
			pattern.append(REPEATS[gen() % 9]);
		}
		// Формируем порождаемый текст сопоставления
		string text;
		// Получаем длину порождаемого текста в символах
		const size_t length = (gen() % 24);
		/**
		 * Выполняем наполнение порождаемого текста сопоставления
		 */
		for(size_t i = 0; i < length; i++)
			// Выполняем добавление очередного символа текста
			text.append(LETTERS[gen() % 12]);
		// Создаём собираемое регулярное выражение
		regex::expression_t expression;
		/**
		 * Если сборка регулярного выражения не выполнена
		 */
		if(!engine.build(pattern, 0, expression))
			// Переходим к следующему образцу сличения
			continue;
		// Создаём объект преобразования программы в машинный код
		regex::codegen_t codegen;
		/**
		 * Если кодогенерация к выражению неприменима
		 */
		if(!codegen.compile(expression.forward))
			// Переходим к следующему образцу сличения
			continue;
		// Увеличиваем количество выражений, получивших кодогенерацию
		accepted++;
		// Создаём набор границ, установленных порождённым кодом
		vector <pair <size_t, size_t>> received;
		// Создаём набор границ, установленных исполнением программы
		vector <pair <size_t, size_t>> expected;
		// Выполняем сопоставление регулярного выражения порождённым кодом
		const bool result = codegen.exec(text, 0, received);
		// Выполняем проверку совпадения вердикта сопоставления
		ASSERT_EQ(result, engine.exec(expression, text, 0, expected)) << "«" << pattern << "» на тексте «" << text << "»";
		/**
		 * Если совпадение в тексте обнаружено
		 */
		if(result) {
			// Выполняем проверку начальной границы совпадения
			ASSERT_EQ(received.front().first, expected.front().first) << "«" << pattern << "» на тексте «" << text << "»";
			// Выполняем проверку конечной границы совпадения
			ASSERT_EQ(received.front().second, expected.front().second) << "«" << pattern << "» на тексте «" << text << "»";
		}
	}
	/**
	 * Выполняем проверку принятия кодогенерацией хотя бы части выражений
	 *
	 * @details Отсутствие принятых выражений означает, что сличение ничего
	 *          не проверяет: подмножество кодогенерации сузилось до пустого.
	 *
	 */
	ASSERT_GT(accepted, static_cast <size_t> (1000));
}
