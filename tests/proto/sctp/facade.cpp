/**
 * Инкапсулируем тестовое окружение в безымянное пространство имён
 *
 * @note Пространство имён безымянное намеренно: набор проверок собирается одной
 *       программой, и одноимённые типы разных файлов сливались бы правилом единого
 *       определения, порождая порчу кучи вдали от места ошибки
 *
 */
namespace {
	// Сторожевой предел ожидания обмена, в миллисекундах
	static constexpr uint32_t WATCHDOG_TIMEOUT = 30000;
	// Предел ожидания завершения фонового потока цикла событий, в секундах
	static constexpr uint32_t SHUTDOWN_TIMEOUT = 5;

	/**
	 * @brief Структура принятого сообщения
	 *
	 */
	struct message_t {
		// Данные принятого сообщения
		std::string data;
		// Метаданные принятого сообщения
		net::sctp::rinfo_t info;
		/**
		 * @brief Конструктор
		 *
		 */
		message_t() noexcept {}
	};

	/**
	 * @brief Класс стенда сквозного обмена по протоколу SCTP
	 *
	 * @details Сервер и клиент живут в одном процессе на общем цикле событий: узлы
	 *          движка ведутся хранилищем процесса, и завести две базы событий в одной
	 *          программе нельзя. Цикл крутится в стороннем потоке, а проверка ждёт
	 *          его завершения сторожевым пределом
	 *
	 */
	class Harness {
		public:
			/**
			 * @brief Структура настроек прогона
			 *
			 */
			struct config_t {
				// Признак выдачи данных вместе с метаданными
				bool metadata;
				// Признак отправки сообщения по частям
				bool partial;
				/**
				 * Признак отражения принятых сообщений обратно клиенту
				 *
				 * @note Отражение ведётся обычной отправкой, а она сообщение крупнее
				 *       очереди не принимает вовсе. Для сообщений такого размера
				 *       отражение отключается, и проверяется приёмная сторона
				 */
				bool echo;
				// Размеры отправляемых сообщений
				std::vector <size_t> sizes;
				// Номер потока отправляемых сообщений
				uint16_t stream;
				// Количество кусков, на какие делится сообщение при отправке по частям
				size_t chunks;
				/**
				 * @brief Конструктор
				 *
				 */
				config_t() noexcept :
				 metadata(false), partial(false),
				 echo(true), stream(0), chunks(0) {}
			};
			/**
			 * @brief Структура итогов прогона
			 *
			 */
			struct result_t {
				// Признак прерывания прогона сторожевым пределом
				bool timedOut;
				// Признак неостановимого цикла событий
				bool unstoppable;
				// Признак отказа заведения стенда
				bool broken;
				// Количество отправленных сообщений
				size_t sent;
				// Принятые сервером сообщения
				std::vector <message_t> received;
				// Принятые клиентом отражённые сообщения
				std::vector <std::string> echoed;
				// Отправленные клиентом сообщения
				std::vector <std::string> transmitted;
				// Количество кусков, какими пришло каждое сообщение
				std::vector <size_t> pieces;
				// Количество ожиданий освобождения очереди отправки
				size_t overflows;
				// Количество отправленных октетов текущего сообщения
				size_t progress;
				// Количество принятых октетов незавершённого сообщения
				size_t assembled;
				/**
				 * Признак поддержки системой явной границы записи
				 *
				 * @note Спрашивается у самого движка, а не выводится из исхода обмена:
				 *       без явной границы записи система закрывает запись НА КАЖДОЙ
				 *       отправке сама, и отправка по частям отказом не отвечает - она
				 *       молча превращает каждый кусок в отдельное сообщение
				 *
				 */
				bool partial;
				/**
				 * @brief Конструктор
				 *
				 */
				result_t() noexcept :
				 timedOut(false), unstoppable(false),
				 broken(false), sent(0), overflows(0),
				 progress(0), assembled(0), partial(false) {}
			};
		private:
			// Объект фреймворка
			fmk_t * _fmk;
			// Объект работы с логами
			log_t * _log;
		private:
			// Настройки прогона
			config_t _config;
			// Итоги прогона
			result_t _result;
		private:
			// Порт прослушивания сервера на локальной петле
			uint16_t _port;
		private:
			// Идентификатор события сервера
			event::id_t _sid;
			// Идентификатор события клиента
			event::id_t _cid;
			// Идентификатор события принятого сервером узла
			event::id_t _pid;
		private:
			// Порядковый номер отправляемого сообщения
			size_t _index;
			// Место отправки текущего сообщения
			size_t _offset;
			/**
			 * Признак завершения прогона
			 *
			 * @note Цикл событий завершается признаком, а не сносом событий: снос из
			 *       отклика цикл не останавливает - проверено щупом, обмен там проходил
			 *       целиком, а опрос продолжался до сторожевого предела
			 */
			bool _done;
		private:
			// Собираемое сервером сообщение
			std::string _pending;
			// Количество кусков собираемого сообщения
			size_t _pieces;
			// Собираемое клиентом отражённое сообщение
			std::string _echo;
			// Общее количество принятых сервером октетов
			size_t _received;
		private:
			// Объект асинхронного движка ввода-вывода
			std::unique_ptr <engine::io_t> _io;
			// Объект управления протоколом SCTP
			std::unique_ptr <engine::sctp_t> _sctp;
		private:
			/**
			 * @brief Метод порождения данных сообщения
			 *
			 * @details Содержимое рознится от места к месту и от сообщения к сообщению:
			 *          однородная набивка скрыла бы и потерю куска, и его повтор, и
			 *          перестановку двух кусков местами
			 *
			 * @param size  размер порождаемого сообщения
			 * @param index порядковый номер порождаемого сообщения
			 * @return      данные порождённого сообщения
			 *
			 */
			std::string generate(const size_t size, const size_t index) const noexcept {
				// Данные порождаемого сообщения
				std::string result(size, '\0');
				// Выполняем набивку сообщения
				for(size_t i = 0; i < size; i++)
					// Устанавливаем очередной октет сообщения
					result[i] = static_cast <char> ((i * 31 + index * 17 + (i >> 8)) & 0xFF);
				// Выводим данные порождённого сообщения
				return result;
			}
			/**
			 * @brief Метод отправки очередного сообщения
			 *
			 * @return результат отправки
			 *
			 */
			bool transmit() noexcept {
				// Если все сообщения уже отправлены
				if(this->_index >= this->_config.sizes.size())
					// Выводим отрицательный результат: отправлять больше нечего
					return false;
				// Если отправка очередного сообщения ещё не начиналась
				if(this->_offset == 0)
					// Порождаем данные очередного сообщения
					this->_result.transmitted.push_back(this->generate(this->_config.sizes.at(this->_index), this->_index));
				// Получаем данные отправляемого сообщения
				const std::string & data = this->_result.transmitted.back();
				/**
				 * Если сообщение отправляется по частям
				 *
				 * @details Отправка ведётся с места остановки: очередь границ сообщений
				 *          запись не делит, и переполнившись отвечает нулём. Дождавшись
				 *          освобождения места, отправка продолжается тем же куском, а
				 *          сообщение остаётся одним - границу записи несёт лишь последний
				 */
				if(this->_config.partial && (this->_config.chunks > 1)){
					// Метаданные отправляемого сообщения
					net::sctp::minfo_t info;
					// Устанавливаем номер потока отправляемого сообщения
					info.num = this->_config.stream;
					// Размер одного куска сообщения
					const size_t chunk = ((data.size() + this->_config.chunks - 1) / this->_config.chunks);
					/**
					 * Выполняем отправку сообщения по частям
					 */
					while(this->_offset < data.size()){
						// Размер отправляемого куска сообщения
						const size_t length = std::min(chunk, (data.size() - this->_offset));
						// Признак завершения сообщения на этом куске
						const bool end = ((this->_offset + length) >= data.size());
						// Выполняем отправку куска сообщения
						const size_t accepted = this->_sctp->send(this->_cid, data.data() + this->_offset, length, info, end);
						/**
						 * Если кусок сообщения к отправке не принят
						 *
						 * @note Ноль означает переполнение очереди, а не отказ: отправка
						 *       продолжится по извещению о освобождении места
						 */
						if(accepted == 0){
							// Увеличиваем количество ожиданий освобождения очереди
							this->_result.overflows++;
							// Выводим отрицательный результат: ждём освобождения очереди
							return false;
						}
						// Сдвигаем место отправки сообщения
						this->_offset += accepted;
						// Запоминаем количество отправленных октетов текущего сообщения
						this->_result.progress = this->_offset;
					}
				/**
				 * Если сообщение отправляется целиком
				 */
				} else if(this->_config.metadata) {
					// Метаданные отправляемого сообщения
					net::sctp::minfo_t info;
					// Устанавливаем номер потока отправляемого сообщения
					info.num = this->_config.stream;
					// Выполняем отправку сообщения вместе с метаданными
					if(this->_sctp->send(this->_cid, data.data(), data.size(), info) != data.size())
						// Выводим отрицательный результат: сообщение не принято к отправке
						return false;
				/**
				 * Если сообщение отправляется обычным способом
				 *
				 * @details Потоковая отправка принимает данные частями: сколько влезло в
				 *          очередь, столько и принято. Остаток уходит по извещению о
				 *          освобождении места, и затыков тут быть не должно - проверка
				 *          эта на то и заведена
				 */
				} else {
					/**
					 * Выполняем отправку сообщения с места остановки
					 */
					while(this->_offset < data.size()){
						// Выполняем отправку остатка сообщения
						const size_t accepted = this->_io->send(this->_cid, data.data() + this->_offset, (data.size() - this->_offset));
						// Если к отправке не принято ничего
						if(accepted == 0){
							// Увеличиваем количество ожиданий освобождения очереди
							this->_result.overflows++;
							// Выводим отрицательный результат: ждём освобождения очереди
							return false;
						}
						// Сдвигаем место отправки сообщения
						this->_offset += accepted;
						// Запоминаем количество отправленных октетов текущего сообщения
						this->_result.progress = this->_offset;
					}
				}
				// Сбрасываем место отправки сообщения
				this->_offset = 0;
				// Увеличиваем порядковый номер отправляемого сообщения
				this->_index++;
				// Увеличиваем количество отправленных сообщений
				this->_result.sent++;
				// Выводим положительный результат
				return true;
			}
			/**
			 * @brief Метод завершения прогона
			 *
			 * @note Цикл событий завершается сам, когда событий не остаётся: своего
			 *       способа остановки у движка нет, и снос событий им же и служит
			 *
			 */
			void finish() noexcept {
				// Поднимаем признак завершения прогона
				this->_done = true;
			}
		public:
			/**
			 * @brief Метод проведения прогона
			 *
			 * @param timeout сторожевой предел ожидания обмена, в миллисекундах
			 * @return        итоги прогона
			 *
			 */
			result_t run(const uint32_t timeout = WATCHDOG_TIMEOUT) noexcept {
				// Создаём объект асинхронного движка ввода-вывода
				this->_io = std::make_unique <engine::io_t> (this->_fmk, this->_log);
				// Создаём объект управления протоколом SCTP
				this->_sctp = std::make_unique <engine::sctp_t> (this->_fmk, this->_log);
				// Создаём событие сервера SCTP
				this->_sid = this->_io->event(event::node_t::SERVER, event::family_t::IPV4, event::type_t::STREAM, event::protocol_t::SCTP);
				// Устанавливаем порт прослушивания сервера
				this->_io->setSourcePort(this->_sid, this->_port);
				// Если завести движок не удалось
				if(!this->_io->initialize()){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Устанавливаем опции события сервера
				this->_io->setOptions(this->_sid, event::options::NO_SIGILL | event::options::NO_SIGPIPE | event::options::REUSE_ADDR | event::options::REUSE_PORT | event::options::NO_IO_BLOCK | event::options::CLOSE_ON_EXEC);
				// Если адрес прослушивания сервера установить не удалось
				if(!this->_io->setAddress(this->_sid, event::address_t::IPV4, "127.0.0.1")){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Устанавливаем функцию обратного вызова на принятие подключения
				this->_io->on(this->_sid, static_cast <engine::callback::accept_t> ([this](const event::id_t sid, const event::id_t cid) noexcept -> void {
					// Запоминаем идентификатор события принятого узла
					this->_pid = cid;
					// Устанавливаем опции события принятого узла
					this->_io->setOptions(cid, event::options::NO_SIGILL | event::options::NO_SIGPIPE | event::options::NO_IO_BLOCK | event::options::CLOSE_ON_EXEC);
					/**
					 * Если данные выдаются вместе с метаданными
					 */
					if(this->_config.metadata || this->_config.partial){
						// Устанавливаем функцию обратного вызова на чтение данных вместе с метаданными
						this->_sctp->on(cid, static_cast <engine::callback::sctp::message_t> ([this](const event::id_t eid, const uint8_t * data, const size_t size, const net::sctp::rinfo_t & info) noexcept -> void {
							// Выполняем приём сообщения сервером
							this->receive(eid, data, size, &info);
						}));
					// Устанавливаем функцию обратного вызова на чтение данных
					} else this->_io->on(cid, [this](const event::id_t eid, const uint8_t * data, const size_t size) noexcept -> void {
						// Выполняем приём сообщения сервером
						this->receive(eid, data, size, nullptr);
					});
				}));
				// Если зафиксировать настройки события сервера не удалось
				if(!this->_io->commit(this->_sid) || !this->_io->listen(this->_sid, 16) || !this->_io->launch(this->_sid)){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Создаём событие клиента SCTP
				this->_cid = this->_io->event(event::node_t::CLIENT, event::family_t::IPV4, event::type_t::STREAM, event::protocol_t::SCTP);
				// Запоминаем, несёт ли система явную границу записи при отправке по частям
				this->_result.partial = this->_sctp->partialSupported(this->_cid);
				// Устанавливаем порт удалённого сервера
				this->_io->setTargetPort(this->_cid, this->_port);
				// Если локальный адрес клиента установить не удалось
				if(!this->_io->setAddress(this->_cid, event::address_t::IPV4, "0.0.0.0")){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Устанавливаем опции события клиента
				this->_io->setOptions(this->_cid, event::options::NO_SIGILL | event::options::NO_SIGPIPE | event::options::NO_IO_BLOCK | event::options::CLOSE_ON_EXEC);
				// Если адрес удалённого сервера установить не удалось
				if(!this->_io->setTarget(this->_cid, "127.0.0.1")){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Устанавливаем функцию обратного вызова на изменение статуса клиента
				this->_io->on(this->_cid, [this](const event::id_t eid, const event::status_t status) noexcept -> void {
					// Если очередь отправки освободилась
					if(status == event::status_t::QUEUE_AVAILABLE)
						// Продолжаем отправку сообщения с места остановки
						this->transmit();
				});
				// Устанавливаем функцию обратного вызова на подключение к серверу
				this->_io->on(this->_cid, static_cast <engine::callback::connect_t> ([this](const event::id_t eid, const bool ok) noexcept -> void {
					// Если подключение к серверу не удалось
					if(!ok){
						// Помечаем отказ заведения стенда
						this->_result.broken = true;
						// Выполняем завершение прогона
						this->finish();
						// Выходим из функции
						return;
					}
					// Выполняем отправку первого сообщения
					this->transmit();
				}));
				// Устанавливаем функцию обратного вызова на чтение отражённых сервером данных
				this->_io->on(this->_cid, [this](const event::id_t eid, const uint8_t * data, const size_t size) noexcept -> void {
					// Дописываем принятый кусок в собираемое отражённое сообщение
					this->_echo.append(reinterpret_cast <const char *> (data), size);
					/**
					 * Если отражённое сообщение собрано не целиком
					 *
					 * @note Клиент собирает отражённое сообщение по ожидаемому размеру, а не
					 *       по признаку границы записи: отклик с метаданными занят проверкой
					 *       приёмной стороны сервера, а держать оба на одном обмене незачем
					 */
					if(this->_echo.size() < this->_result.transmitted.at(this->_result.echoed.size()).size())
						// Выходим, ожидая следующего куска
						return;
					// Запоминаем принятое клиентом отражённое сообщение
					this->_result.echoed.push_back(::move(this->_echo));
					// Сбрасываем собираемое отражённое сообщение
					this->_echo.clear();
					// Если отражены все отправленные сообщения
					if(this->_result.echoed.size() >= this->_config.sizes.size())
						// Выполняем завершение прогона
						this->finish();
					// Выполняем отправку очередного сообщения
					else this->transmit();
				});
				// Если зафиксировать настройки события клиента не удалось
				if(!this->_io->commit(this->_cid) || !this->_io->connect(this->_cid) || !this->_io->launch(this->_cid)){
					// Помечаем отказ заведения стенда
					this->_result.broken = true;
					// Выводим итоги прогона
					return this->_result;
				}
				// Обещание завершения работы фонового потока цикла событий
				std::promise <void> finished;
				// Ожидание завершения работы фонового потока цикла событий
				std::future <void> waiter = finished.get_future();
				// Запускаем цикл событий в фоновом потоке
				std::thread worker([this, &finished]() noexcept {
					// Выполняем опрос событий до завершения прогона
					while(this->_io->poll(100) && !this->_done);
					// Выполняем снос всех событий движка
					this->_io->clear();
					// Сигнализируем завершение работы фонового потока
					finished.set_value();
				});
				/**
				 * Если обмен не уложился в сторожевой предел
				 */
				if(waiter.wait_for(std::chrono::milliseconds(timeout)) == std::future_status::timeout){
					// Помечаем прерывание прогона сторожевым пределом
					this->_result.timedOut = true;
					// Поднимаем признак завершения прогона
					this->_done = true;
					/**
					 * Ожидаем завершения работы фонового потока, но не бесконечно
					 *
					 * @note Не дождавшись, поток намеренно оставляется жить до конца работы
					 *       процесса: разрушать движок под работающим потоком нельзя, а
					 *       безусловное ожидание превратило бы сторожевой предел в вечное
					 *       зависание всего набора проверок
					 */
					if(waiter.wait_for(std::chrono::seconds(SHUTDOWN_TIMEOUT)) == std::future_status::timeout){
						// Помечаем неостановимый цикл событий
						this->_result.unstoppable = true;
						// Отпускаем фоновый поток, не дожидаясь его завершения
						worker.detach();
						// Продлеваем жизнь движка до конца работы процесса
						this->_io.release();
						// Продлеваем жизнь объекта управления протоколом до конца работы процесса
						this->_sctp.release();
						// Выводим итоги прогона
						return this->_result;
					}
				}
				// Дожидаемся завершения фонового потока
				worker.join();
				// Выводим итоги прогона
				return this->_result;
			}
		private:
			/**
			 * @brief Метод приёма сообщения сервером
			 *
			 * @param eid  идентификатор события
			 * @param data данные принятого сообщения
			 * @param size размер данных принятого сообщения
			 * @param info метаданные принятого сообщения
			 *
			 */
			void receive(const event::id_t eid, const uint8_t * data, const size_t size, const net::sctp::rinfo_t * info) noexcept {
				// Дописываем принятый кусок в собираемое сообщение
				this->_pending.append(reinterpret_cast <const char *> (data), size);
				// Увеличиваем количество кусков собираемого сообщения
				this->_pieces++;
				// Увеличиваем общее количество принятых сервером октетов
				this->_received += size;
				// Запоминаем количество принятых октетов незавершённого сообщения
				this->_result.assembled = this->_received;
				/**
				 * Признак завершения сообщения на этом куске
				 *
				 * @note Сообщение, превышающее буфер приёма, выдаётся несколькими кусками,
				 *       и границу его несёт признак записи у последнего из них. Считать
				 *       сообщением всякий кусок нельзя: проверено щупом, сообщение в
				 *       128 КБ приходит двумя кусками по 64 КБ
				 */
				bool end = true;
				// Если метаданные принятого сообщения переданы
				if(info != nullptr)
					// Устанавливаем признак завершения сообщения по признаку границы записи
					end = (info->flags.find(net::sctp::receipt_t::END_OF_RECORD) != info->flags.end());
				// Если сообщение собрано не целиком
				if(!end)
					// Выходим, ожидая следующего куска
					return;
				// Объект принятого сообщения
				message_t message;
				// Устанавливаем данные принятого сообщения
				message.data = ::move(this->_pending);
				// Если метаданные принятого сообщения переданы
				if(info != nullptr)
					// Устанавливаем метаданные принятого сообщения
					message.info = (* info);
				// Запоминаем количество кусков, какими пришло сообщение
				this->_result.pieces.push_back(this->_pieces);
				// Сбрасываем количество кусков собираемого сообщения
				this->_pieces = 0;
				// Сбрасываем собираемое сообщение
				this->_pending.clear();
				// Запоминаем принятое сообщение
				this->_result.received.push_back(message);
				/**
				 * Если отражение принятых сообщений отключено
				 */
				if(!this->_config.echo){
					// Ожидаемое общее количество октетов обмена
					size_t expected = 0;
					// Выполняем подсчёт ожидаемого общего количества октетов
					for(auto & size : this->_config.sizes)
						// Увеличиваем ожидаемое общее количество октетов
						expected += size;
					// Если сервер принял весь объём обмена
					if(this->_received >= expected)
						// Выполняем завершение прогона
						this->finish();
					// Выполняем отправку очередного сообщения
					else this->transmit();
					// Выходим из функции
					return;
				}
				// Выполняем отражение принятого сообщения обратно клиенту
				this->_io->send(eid, message.data.data(), message.data.size());
			}
		public:
			/**
			 * @brief Конструктор
			 *
			 * @param config настройки прогона
			 * @param port   порт прослушивания сервера на локальной петле
			 * @param fmk    объект фреймворка
			 * @param log    объект работы с логами
			 *
			 */
			Harness(const config_t & config, const uint16_t port, fmk_t * fmk, log_t * log) noexcept :
			 _fmk(fmk), _log(log), _config(config), _port(port),
			 _sid(0), _cid(0), _pid(0), _index(0), _offset(0), _done(false), _pieces(0), _received(0) {}
	};
};

