/**
 * @brief Проверка сборки сообщения, отправленного по частям
 *
 * @details Куски уходят отдельными вызовами, и лишь последний несёт признак
 *          завершения. Приёмной стороне сообщение обязано прийти ОДНИМ куском:
 *          не дойди признак завершения до самой отправки - каждый кусок стал бы
 *          отдельным сообщением, и проверка эта ловит именно такой исход
 *
 * @note Отправка по частям требует от системы явного режима границы записи, и есть
 *       он не всюду: у Linux его нет вовсе, и там проверка пропускается
 *
 */
TEST_F(SctpFacadeTest, PartialMessageAssemblesIntoOne){
	// Настройки прогона
	Harness::config_t config;
	// Включаем отправку сообщения по частям
	config.partial = true;
	// Устанавливаем количество кусков, на какие делится сообщение
	config.chunks = 4;
	// Устанавливаем номер потока отправляемых сообщений
	config.stream = 1;
	// Устанавливаем размеры отправляемых сообщений
	config.sizes = {40000};
	// Заводим стенд сквозного обмена
	Harness harness(config, this->pickPort(), this->_fmk.get(), this->_log.get());
	// Выполняем прогон обмена
	const Harness::result_t result = harness.run();
	/**
	 * Если система не несёт явного режима границы записи
	 *
	 * @note Пропуск здесь честнее отказа: возможности этой у системы нет, и
	 *       спрашивать её не с кого. Молчаливым он при этом не остаётся
	 *
	 * @warning Спрашивается ВОЗМОЖНОСТЬ, а не исход обмена. Прежде здесь стояло
	 *          условие «стенд отказал и не отправлено ничего», и оно НЕ РАБОТАЛО:
	 *          без явной границы записи отправка по частям отказом не отвечает
	 *          вовсе - система закрывает запись на каждой отправке сама, и каждый
	 *          кусок уходит отдельным сообщением. Стенд при этом целёхонек, а
	 *          проверка отказывала числом принятых сообщений. Установлено на musl
	 *          (OpenWRT, ядро 6.12): принято ровно 4 сообщения при 4 кусках
	 */
	if(!result.partial){
		// Выводим сообщение о пропуске проверки
		GTEST_SKIP() << "Отправка сообщения по частям системой не поддерживается";
		// Выходим из проверки
		return;
	}
	// Проверяем, что обмен уложился в сторожевой предел
	ASSERT_FALSE(result.timedOut) << "Обмен не уложился в сторожевой предел";
	// Проверяем, что сервер принял ровно одно сообщение
	ASSERT_EQ(result.received.size(), 1u) << "Сообщение, отправленное по частям, пришло несколькими";
	// Проверяем, что размер принятого сообщения совпадает с отправленным
	ASSERT_EQ(result.received.front().data.size(), config.sizes.front()) << "Размер собранного сообщения не совпадает";
	// Проверяем, что собранное сообщение несёт признак границы записи
	EXPECT_TRUE(result.received.front().info.flags.find(net::sctp::receipt_t::END_OF_RECORD) != result.received.front().info.flags.end()) << "У собранного сообщения нет признака границы записи";
	// Проверяем, что клиент принял отражённое сообщение целиком
	ASSERT_EQ(result.echoed.size(), 1u) << "Отражённое собранное сообщение пришло разрезанным";
	// Проверяем, что содержимое отражённого сообщения совпадает с принятым сервером
	EXPECT_EQ(result.echoed.front(), result.received.front().data) << "Содержимое собранного сообщения не совпадает";
}

/**
 * @brief Проверка отправки сообщения, заведомо превышающего очередь отправки
 *
 * @details Целым такое сообщение не отправить: очередь границ сообщений запись не
 *          делит, и сообщение крупнее её буфера отправка честно не принимает вовсе.
 *          По частям же оно уходит любым размером - куски ложатся в очередь порознь,
 *          переполнение разбирается извещением о освобождении места, а приёмной
 *          стороне сообщение приходит ОДНИМ: границу записи несёт лишь последний кусок
 *
 * @note Проверка эта отвечает на вопрос, снимается ли потолок размера сообщения
 *       разбором переполнения очереди. Снимается - но лишь отправкой по частям
 *
 */
TEST_F(SctpFacadeTest, HugeMessageViaPartialSending){
	// Настройки прогона
	Harness::config_t config;
	// Включаем отправку сообщения по частям
	config.partial = true;
	// Устанавливаем количество кусков, на какие делится сообщение
	config.chunks = 128;
	// Устанавливаем номер потока отправляемых сообщений
	config.stream = 4;
	// Отключаем отражение принятых сообщений обратно клиенту
	config.echo = false;
	// Устанавливаем размер отправляемого сообщения
	config.sizes = {(4 * 1024 * 1024)};
	// Заводим стенд сквозного обмена
	Harness harness(config, this->pickPort(), this->_fmk.get(), this->_log.get());
	// Выполняем прогон обмена
	const Harness::result_t result = harness.run();
	/**
	 * Если система не несёт явного режима границы записи
	 *
	 * @note Проверка эта СТОИТ на отправке по частям: без явной границы записи каждый
	 *       кусок ушёл бы отдельным сообщением, и проверять было бы нечего. Пропуск
	 *       здесь честнее отказа - возможности у системы нет, и спрашивать её не с кого
	 */
	if(!result.partial){
		// Выводим сообщение о пропуске проверки
		GTEST_SKIP() << "Отправка сообщения по частям системой не поддерживается";
		// Выходим из проверки
		return;
	}
	// Проверяем, что стенд завёлся
	ASSERT_FALSE(result.broken) << "Стенд обмена завести не удалось";
	// Проверяем, что обмен уложился в сторожевой предел
	ASSERT_FALSE(result.timedOut) << "Обмен не уложился в сторожевой предел: отправлено " << result.progress
		<< " октетов, принято " << result.assembled << ", ожиданий освобождения очереди " << result.overflows;
	// Проверяем, что сообщение отправлено целиком
	ASSERT_EQ(result.sent, 1u) << "Сообщение отправлено не было";
	// Проверяем, что сервер собрал ровно одно сообщение
	ASSERT_EQ(result.received.size(), 1u) << "Сообщение собралось не в одно";
	// Проверяем, что размер собранного сообщения совпадает с отправленным
	ASSERT_EQ(result.received.front().data.size(), config.sizes.front()) << "Размер собранного сообщения не совпадает";
	// Проверяем, что собранное сообщение совпадает с отправленным до октета
	EXPECT_EQ(result.received.front().data, result.transmitted.front()) << "Содержимое сообщения не совпадает с отправленным";
	// Проверяем, что сообщение и вправду пришло несколькими кусками
	EXPECT_GT(result.pieces.front(), 1u) << "Сообщение пришло одним куском - дробление не проверено";
	// Проверяем, что переполнение очереди отправки и вправду случалось
	EXPECT_GT(result.overflows, 0u) << "Очередь отправки не переполнялась - разбор переполнения не проверен";
}

/**
 * @brief Проверка потоковой отправки крупного объёма обычным способом
 *
 * @details Отправка ведётся одним вызовом на все четыре мегабайта, без деления на
 *          куски приложением. Очередь принимает столько, сколько влезло, остаток
 *          уходит по извещению о освобождении места, и так до последнего октета.
 *          Затыков быть не должно: потоковая отправка вправе принять часть, но не
 *          вправе отказать целиком, когда место в очереди есть
 *
 * @note Границы сообщений здесь не проверяются намеренно: обычная отправка потоком
 *       их и не обещает - кому нужны границы, тот задаёт их признаком конца либо
 *       берёт событие с сохранением границ. Проверяется целость и порядок октетов
 *
 */
TEST_F(SctpFacadeTest, StreamSendAcceptsPartiallyWithoutStall){
	// Настройки прогона
	Harness::config_t config;
	// Отключаем отражение принятых сообщений обратно клиенту
	config.echo = false;
	// Устанавливаем размер отправляемого объёма
	config.sizes = {(4 * 1024 * 1024)};
	// Заводим стенд сквозного обмена
	Harness harness(config, this->pickPort(), this->_fmk.get(), this->_log.get());
	// Выполняем прогон обмена
	const Harness::result_t result = harness.run();
	// Проверяем, что стенд завёлся
	ASSERT_FALSE(result.broken) << "Стенд обмена завести не удалось";
	// Проверяем, что обмен уложился в сторожевой предел
	ASSERT_FALSE(result.timedOut) << "Обмен не уложился в сторожевой предел: отправлено " << result.progress
		<< " октетов, принято " << result.assembled << ", ожиданий освобождения очереди " << result.overflows;
	// Проверяем, что объём отправлен целиком
	ASSERT_EQ(result.progress, config.sizes.front()) << "Объём отправлен не целиком";
	// Проверяем, что очередь отправки и вправду переполнялась
	EXPECT_GT(result.overflows, 0u) << "Очередь отправки не переполнялась - разбор переполнения не проверен";
	// Собранный сервером объём обмена
	std::string assembled;
	// Выполняем сборку принятого сервером объёма обмена
	for(auto & message : result.received)
		// Дописываем принятое сообщение в собранный объём
		assembled.append(message.data);
	// Проверяем, что сервер принял весь объём обмена
	ASSERT_EQ(assembled.size(), config.sizes.front()) << "Сервер принял не весь объём обмена";
	// Проверяем, что принятый объём совпадает с отправленным до октета
	EXPECT_EQ(assembled, result.transmitted.front()) << "Принятый объём не совпадает с отправленным";
}

