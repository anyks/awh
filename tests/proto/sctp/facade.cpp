	ASSERT_EQ(result.received.size(), 1u) << "Большое сообщение собралось не в одно";
	// Проверяем, что размер собранного сообщения совпадает с отправленным
	ASSERT_EQ(result.received.front().data.size(), config.sizes.front()) << "Размер собранного сообщения не совпадает";
	// Проверяем, что собранное сообщение совпадает с отправленным до октета
	EXPECT_EQ(result.received.front().data, result.transmitted.front()) << "Содержимое собранного сообщения не совпадает с отправленным";
