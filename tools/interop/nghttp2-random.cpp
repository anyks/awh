/**
 * Пробник: сверка на случайных наборах. Штатная сверка `nghttp2-hpack.cpp` гоняет
 * фиксированную последовательность блоков, и решения кодера об индексации на ней
 * повторяются от прогона к прогону. Эта сверка выводит кодер на пути, которых
 * фиксированная нагрузка не достаёт: таблица то переполняется, то опустошается
 * сменой размера, значения то повторяются, то уникальны, часть заголовков
 * чувствительна и в таблицу попадать не должна вовсе.
 *
 * Проверяется главное свойство кодера: что бы он ни выбрал - представление
 * с индексацией, без неё или never indexed, - декодер пира обязан получить
 * ровно тот список заголовков, который был отправлен, а его динамическая
 * таблица обязана остаться синхронной с нашей.
 */

#include <string>
#include <vector>
#include <random>
#include <cstdint>
#include <cstdio>

#include <nghttp2/nghttp2.h>

#include <proto/http/parser/http2/hpack.hpp>

using namespace awh;
using namespace awh::http;

/**
 * @brief Количество сверяемых блоков заголовков
 *
 */
static constexpr size_t BLOCK_ROUNDS = 30000;
/**
 * @brief Зерно генератора псевдослучайной последовательности
 *
 * @details Зерно фиксировано намеренно: прогон обязан быть воспроизводимым,
 *          иначе найденное расхождение не повторить
 *
 */
static constexpr uint32_t RANDOM_SEED = 20260727;
/**
 * @brief Периодичность смены размера динамической таблицы в блоках
 *
 */
static constexpr size_t RESIZE_PERIOD = 500;

/**
 * @brief Функция входа в пробник
 *
 * @return код выхода из пробника
 *
 */
int32_t main() noexcept {
	// Генератор псевдослучайной последовательности
	std::mt19937 gen(RANDOM_SEED);
	// Объект кодера заголовков библиотеки
	h2::hpack::encoder_t encoder;
	/**
	 * Отключаем автоматическое определение чувствительных заголовков: признак
	 * задаётся нагрузкой явно, иначе часть наборов кодировалась бы иначе,
	 * чем задумано сверкой
	 */
	encoder.sensitiveHeuristic(false);
	// Объект декодера заголовков эталонной реализации
	nghttp2_hd_inflater * inflater = nullptr;
	// Создаём декодер эталонной реализации
	if(::nghttp2_hd_inflate_new(&inflater) != 0){
		// Выводим сообщение о неудачном создании декодера
		::printf("декодер эталонной реализации не создан\n");
		// Выходим с ошибкой
		return 1;
	}
	// Количество сверенных блоков заголовков
	size_t blocks = 0;
	// Количество сверенных заголовков
	size_t headers = 0;
	// Количество обнаруженных расхождений
	size_t failures = 0;
	/**
	 * Выполняем прогон всех блоков заголовков сверки
	 */
	for(size_t round = 0; round < BLOCK_ROUNDS; round++){
		/**
		 * Изредка меняем размер динамической таблицы, как это делает пир своими
		 * SETTINGS: кодер обязан просигнализировать изменение в начале блока,
		 * а декодер пира - принять сигнал и вытеснить лишние записи
		 */
		if((gen() % RESIZE_PERIOD) == 0){
			// Выбираем новый размер динамической таблицы
			const uint32_t size = (gen() % 8192);
			// Применяем новый размер к кодеру библиотеки
			encoder.setMaxTableSize(size);
			// Применяем новый размер к декодеру эталонной реализации
			::nghttp2_hd_inflate_change_table_size(inflater, size);
		}
		// Набор заголовков блока
		std::vector <h2::hpack::field_t> fields;
		// Количество заголовков блока
		const size_t count = (1 + (gen() % 12));
		/**
		 * Выполняем формирование всех заголовков набора
		 */
		for(size_t i = 0; i < count; i++){
			/**
			 * Название берём то из статической таблицы, то уникальное: первое даёт
			 * ссылку на название, второе заставляет кодировать название строкой
			 */
			const std::string name = (((gen() % 3) == 0)
				? ("x-" + std::to_string(gen() % 2000))
				: std::string(h2::hpack::staticTable(1 + (gen() % h2::hpack::STATIC_TABLE_SIZE))->name));
			// Формируем значение заголовка переменной длины
			const std::string value(1 + (gen() % 300), static_cast <char> ('a' + (gen() % 26)));
			// Дописываем заголовок с признаком чувствительности
			fields.emplace_back(name, value, ((gen() % 8) == 0));
		}
		// Буфер закодированного блока заголовков
		std::string block;
		// Кодируем блок заголовков, чередуя Huffman-кодирование
		encoder.encode(fields, block, ((gen() % 4) != 0));
		// Указатель на неразобранный остаток блока заголовков
		const uint8_t * data = reinterpret_cast <const uint8_t *> (block.data());
		// Размер неразобранного остатка блока заголовков
		size_t size = block.size();
		// Номер сверяемого заголовка блока
		size_t index = 0;
		/**
		 * Выполняем декодирование блока эталонной реализацией
		 */
		for(;;){
			// Декодированный заголовок
			nghttp2_nv nv;
			// Флаги результата декодирования
			int32_t flags = 0;
			// Выполняем декодирование очередного заголовка блока
			const nghttp2_ssize used = ::nghttp2_hd_inflate_hd3(inflater, &nv, &flags, data, size, 1);
			// Если декодирование не удалось
			if(used < 0){
				// Выводим описание отказа эталонной реализации
				::printf("блок %zu: эталон не смог разобрать блок: %s\n", round, ::nghttp2_strerror(static_cast <int32_t> (used)));
				// Считаем обнаруженное расхождение
				failures++;
				// Прекращаем разбор блока
				break;
			}
			// Продвигаем указатель на неразобранный остаток блока
			data += used;
			// Уменьшаем размер неразобранного остатка блока
			size -= static_cast <size_t> (used);
			// Если декодирован очередной заголовок
			if(flags & NGHTTP2_HD_INFLATE_EMIT){
				// Если заголовков декодировано больше отправленного
				if(index >= fields.size()){
					// Выводим описание расхождения
					::printf("блок %zu: эталон выдал лишний заголовок\n", round);
					// Считаем обнаруженное расхождение
					failures++;
					// Прекращаем разбор блока
					break;
				}
				// Получаем название декодированного заголовка
				const std::string name(reinterpret_cast <const char *> (nv.name), nv.namelen);
				// Получаем значение декодированного заголовка
				const std::string value(reinterpret_cast <const char *> (nv.value), nv.valuelen);
				// Если название либо значение заголовка разошлись
				if((name != fields[index].name) || (value != fields[index].value)){
					// Выводим описание расхождения
					::printf(
						"блок %zu, заголовок %zu: отправлено [%s] = [%.24s], получено [%s] = [%.24s]\n",
						round, index, fields[index].name.c_str(), fields[index].value.c_str(),
						name.c_str(), value.c_str()
					);
					// Считаем обнаруженное расхождение
					failures++;
				}
				// Считаем сверенный заголовок
				headers++;
				// Переходим к следующему заголовку блока
				index++;
			}
			// Если блок заголовков разобран целиком
			if(flags & NGHTTP2_HD_INFLATE_FINAL){
				// Завершаем разбор блока заголовков
				::nghttp2_hd_inflate_end_headers(inflater);
				// Прекращаем разбор блока
				break;
			}
			// Если неразобранный остаток блока исчерпан
			if((used == 0) && (size == 0))
				// Прекращаем разбор блока
				break;
		}
		// Если декодировано меньше заголовков, чем отправлено
		if(index != fields.size()){
			// Выводим описание расхождения
			::printf("блок %zu: отправлено %zu заголовков, получено %zu\n", round, fields.size(), index);
			// Считаем обнаруженное расхождение
			failures++;
		}
		// Считаем сверенный блок заголовков
		blocks++;
	}
	// Удаляем декодер эталонной реализации
	::nghttp2_hd_inflate_del(inflater);
	// Выводим итог сверки
	::printf("сверено блоков: %zu, заголовков: %zu, расхождений: %zu\n", blocks, headers, failures);
	// Выводим код выхода по итогу сверки
	return (failures > 0 ? 1 : 0);
}
