/**
 * @brief Функция получения вердикта эталонной реализации
 *
 * @param pattern текст проверяемого регулярного выражения
 * @param flags   набор режимов компиляции эталонной реализации
 * @return        результат компиляции регулярного выражения
 *
 */
static bool reference(const string & pattern, const uint32_t flags) noexcept {
	// Код ошибки компиляции регулярного выражения
	int32_t code = 0;
	// Смещение ошибки компиляции регулярного выражения
	PCRE2_SIZE offset = 0;
	// Выполняем компиляцию регулярного выражения эталонной реализацией
	pcre2_code * result = ::pcre2_compile(
		reinterpret_cast <PCRE2_SPTR> (pattern.c_str()), pattern.size(),
		flags, &code, &offset, nullptr
	);
	/**
	 * Если компиляция регулярного выражения выполнена
	 */
	if(result != nullptr) {
		// Выполняем освобождение скомпилированного регулярного выражения
		::pcre2_code_free(result);
		// Выводим результат компиляции регулярного выражения
		return true;
	}
	// Выводим результат компиляции регулярного выражения
	return false;
}
/**
 * @brief Функция приведения режимов эталонной реализации к режимам разбора
 *
 * @param flags набор режимов компиляции эталонной реализации
 * @return      набор режимов компиляции модуля разбора
 *
 */
static uint32_t convert(const uint32_t flags) noexcept {
	// Набор режимов компиляции модуля разбора
	uint32_t result = 0;
	/**
	 * Если установлен режим разбора последовательностей UTF-8
	 */
	if((flags & PCRE2_UTF) != 0)
		// Выполняем установку режима разбора последовательностей UTF-8
		result |= static_cast <uint32_t> (regex::flag_t::UTF);
	/**
	 * Если установлен режим учёта свойств Юникода
	 */
	if((flags & PCRE2_UCP) != 0)
		// Выполняем установку режима учёта свойств Юникода
		result |= static_cast <uint32_t> (regex::flag_t::UCP);
	// Выводим набор режимов компиляции модуля разбора
	return result;
}

/**
 * @brief Проверка сличения вердиктов разбора конструкций синтаксиса PCRE
 *
 */
TEST(Regex, Syntax) {
	/**
	 * @brief Проверяемый шаблон регулярного выражения
	 *
	 */
	struct Item {
		// Текст проверяемого регулярного выражения
		const char * pattern;
		// Набор режимов компиляции эталонной реализации
		uint32_t flags;
	};
	// Создаём набор проверяемых шаблонов регулярных выражений
	const vector <Item> items = {
		// Литералы, классы символов и кванторы повторения
		{"abc", 0}, {"a|b", 0}, {"a*b+c?", 0}, {"a{2,5}", 0}, {"a{2,}", 0}, {"a{3}", 0},
		{"a{,5}", 0}, {"a{,}", 0}, {"a*?b+?c??", 0}, {"a*+b++c?+", 0}, {"[abc]", 0},
		{"[^abc]", 0}, {"[a-z0-9_]", 0}, {"[]]", 0}, {"[^]]", 0}, {"[a-]", 0}, {"[-a]", 0},
		{"[\\]]", 0}, {"[\\d\\s\\w]", 0}, {"[\\D\\S\\W]", 0}, {"[[:alpha:][:digit:]]", 0},
		{"[[:^alpha:]]", 0}, {"[\\Ea]", 0}, {"[a\\E]", 0}, {"[\\Qa-b\\E]", 0}, {"\\d+", 0},
		{"\\h\\v\\H\\V", 0}, {".", 0}, {"a.b", 0}, {"\\C", 0}, {"\\X", 0},
		// Привязки к позиции в тексте
		{"^abc$", 0}, {"\\Aabc\\z", 0}, {"\\bword\\B", 0}, {"\\Gabc", 0}, {"a\\Kb", 0},
		// Группы регулярного выражения
		{"(abc)", 0}, {"(?:abc)", 0}, {"(?>abc)", 0}, {"(?<name>abc)", 0}, {"(?'name'abc)", 0},
		{"(?P<name>abc)", 0}, {"(?|(a)|(b))", 0}, {"((a)(b))", 0}, {"(?)", 0},
		// Проверки окружения
		{"(?=abc)", 0}, {"(?!abc)", 0}, {"(?<=abc)", 0}, {"(?<!abc)", 0}, {"a(?=b)c", 0},
		{"(?<=a|bc)", 0}, {"(?<=a{1,3})", 0}, {"(?=a)*", 0},
		// Ссылки на захваченные группы
		{"(a)\\1", 0}, {"(?<n>a)\\k<n>", 0}, {"(?<n>a)\\k'n'", 0}, {"(?<n>a)\\k{n}", 0},
		{"(?P<n>a)(?P=n)", 0}, {"(a)\\g1", 0}, {"(a)\\g{1}", 0}, {"(a)\\g{-1}", 0},
		// Рекурсивные вызовы
		{"(?R)", 0}, {"(?0)", 0}, {"(a)(?1)", 0}, {"(a)(?-1)", 0}, {"(?<n>a)(?&n)", 0},
		{"(?P<n>a)(?P>n)", 0}, {"\\((?:[^()]|(?R))*\\)", 0},
		// Условные выражения
		{"(a)?(?(1)b|c)", 0}, {"(?<n>a)?(?(<n>)b|c)", 0}, {"(a)(?(1)b)", 0},
		{"(?(?=a)b|c)", 0}, {"(?(DEFINE)(?<n>a))(?&n)", 0},
		// Встроенные опции регулярного выражения
		{"(?i)abc", 0}, {"(?i:abc)", 0}, {"(?-i)abc", 0}, {"(?im-sx:abc)", 0},
		{"(?x) a b c", 0}, {"(?#comment)abc", 0}, {"a(?#comment)*", 0}, {"a\\E*", 0},
		{"(?n)(a)", 0}, {"(?a)\\d", 0}, {"(?r)abc", 0}, {"(?aP)\\w", 0}, {"(?a-i:x)", 0},
		// Экранированные последовательности
		{"\\n\\r\\t\\f\\a\\e", 0}, {"\\x41", 0}, {"\\x{1F600}", PCRE2_UTF}, {"\\101", 0},
		{"\\o{101}", 0}, {"\\cA", 0}, {"\\Qa.b*c\\E", 0}, {"\\Qabc", 0}, {"a\\-b", 0},
		{"\\R", 0}, {"\\N", 0}, {"\\N{2,5}", 0},
		// Свойства Юникода
		{"\\p{L}", PCRE2_UTF | PCRE2_UCP}, {"\\pL", PCRE2_UTF | PCRE2_UCP},
		{"\\P{Nd}", PCRE2_UTF | PCRE2_UCP}, {"[\\p{Lu}\\p{Ll}]", PCRE2_UTF | PCRE2_UCP},
		{"\\p{^L}", PCRE2_UTF | PCRE2_UCP}, {"\\p{lu}", PCRE2_UTF | PCRE2_UCP},
		{"\\pz", PCRE2_UTF | PCRE2_UCP},
		// Шаблоны, отклоняемые обеими реализациями
		{"(", 0}, {")", 0}, {"[abc", 0}, {"a**", 0}, {"*a", 0}, {"+a", 0}, {"?a", 0},
		{"a{2,1}", 0}, {"[z-a]", 0}, {"\\", 0}, {"(?<n>a)(?<n>b)", 0}, {"\\k<>", 0},
		{"(?P<n>a)(?P<n>b)", 0}, {"\\p{Nonexistent}", PCRE2_UTF | PCRE2_UCP},
		{"[[:nosuch:]]", 0}, {"(?&nosuch)", 0}, {"\\k<nosuch>", 0}, {"(?y)", 0},
		{"\\x{110000}", PCRE2_UTF}, {"a{99999999}", 0}, {"(?<1n>a)", 0}, {"{2,}", 0},
		{"a{2}{3}", 0}, {"\\x", 0}, {"\\x{}", 0}, {"[\\E]", 0}, {"[\\W-*]", 0}, {"[\\d-z]", 0},
		{"[:alpha:]", 0}, {"\\N{U+0041}", 0}, {"(?2)", 0}, {"\\2", 0}, {"(?(?+1)b)", 0},
		{"(?=a)(?<!\\K)", 0}, {"(?<=a+)", 0}, {"(?i)*", 0}, {"(?<>)", 0},
		// Шаблоны, встречающиеся при разборе протоколов
		{"^([A-Za-z0-9-]+)\\s*:\\s*(.+)$", 0},
		{"^(GET|POST|PUT|DELETE)\\s+(\\S+)\\s+HTTP/(\\d)\\.(\\d)$", 0},
		{"([a-z]+)://([^/:]+)(?::(\\d+))?(/[^?#]*)?(?:\\?([^#]*))?(?:#(.*))?", 0},
		{"^\\s*([^=;]+)=([^;]*)(?:;\\s*(.*))?$", 0}
	};
	/**
	 * Выполняем сличение вердиктов разбора для каждого шаблона
	 */
	for(const auto & item : items) {
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Получаем вердикт разбора модулем регулярных выражений
		const bool actual = parser.parse(item.pattern, convert(item.flags));
		// Получаем вердикт компиляции эталонной реализацией
		const bool expected = reference(item.pattern, item.flags);
		// Выполняем сличение вердиктов разбора
		EXPECT_EQ(actual, expected)
			<< "Шаблон: " << item.pattern
			<< ", текст ошибки разбора: " << parser.message();
	}
}

/**
 * @brief Проверка разрешения ссылок и определения количества захватывающих групп
 *
 */
/**
 * @brief Проверка сличения вердиктов разбора порождаемых шаблонов
 *
 */
TEST(Regex, Fuzzing) {
	// Создаём генератор псевдослучайных чисел с фиксированным зерном
	mt19937 engine(20260731);
	// Создаём набор фрагментов, из которых собираются шаблоны
	const vector <string> pieces = {
		"a", "b", "z", "0", "9", ".", "^", "$", "|", "*", "+", "?", "-", ":", "=", "!", ",",
		"(", ")", "[", "]", "{", "}", "<", ">", "'", "&", "#", "\\", "/",
		"\\d", "\\w", "\\s", "\\D", "\\W", "\\S", "\\b", "\\B", "\\A", "\\z", "\\Z", "\\G",
		"\\K", "\\R", "\\N", "\\Q", "\\E", "\\1", "\\2", "\\g", "\\k", "\\p", "\\P", "\\x",
		"\\o", "\\c", "\\n", "\\t", "\\0", "\\C", "\\X",
		"(?", "(?:", "(?>", "(?=", "(?!", "(?<", "(?<=", "(?<!", "(?'", "(?|", "(?#", "(?P",
		"(?R)", "(?1)", "(?-1)", "(?+1)", "(?&", "(?(", "(?i)", "(?-i)", "(?i:", "(?im-sx:",
		"{2}", "{2,}", "{2,5}", "{,5}", "{}", "[a-z]", "[^a]", "[[:alpha:]]", "[[:^x:]]",
		"\\p{L}", "\\p{Nd}", "\\x{41}", "\\k<n>", "\\g{1}", "\\g<n>", "n", ">", "abc", "DEFINE"
	};
	// Создаём распределение количества фрагментов в шаблоне
	uniform_int_distribution <size_t> lengths(1, 8);
	// Создаём распределение индексов фрагментов
	uniform_int_distribution <size_t> indexes(0, pieces.size() - 1);
	// Счётчик расхождений вердиктов разбора
	size_t diverged = 0;
	/**
	 * Выполняем порождение и сличение вердиктов разбора шаблонов
	 */
	for(size_t i = 0; i < 100000; i++) {
		// Текст порождаемого регулярного выражения
		string pattern;
		// Получаем количество фрагментов очередного шаблона
		const size_t count = lengths(engine);
		/**
		 * Выполняем сборку шаблона из фрагментов
		 */
		for(size_t j = 0; j < count; j++)
			// Выполняем добавление очередного фрагмента шаблона
			pattern.append(pieces.at(indexes(engine)));
		/**
		 * Пропускаем шаблоны с конструкцией сканирования подстроки
		 *
		 * @details Конструкция вида «(?*...)» является расширением эталонной реализации,
		 *          не описанным синтаксисом PCRE, и модулем не поддерживается.
		 *
		 */
		if(pattern.find("(?*") != string::npos)
			// Переходим к следующему порождаемому шаблону
			continue;
		/**
		 * Пропускаем шаблоны с конструкцией сканирования подстроки за проверкой окружения
		 */
		if(pattern.find("(?<*") != string::npos)
			// Переходим к следующему порождаемому шаблону
			continue;
		// Создаём объект разбора регулярного выражения
		regex::parser_t parser;
		// Получаем вердикт разбора модулем регулярных выражений
		const bool actual = parser.parse(pattern, 0);
		// Получаем вердикт компиляции эталонной реализацией
		const bool expected = reference(pattern, 0);
		/**
		 * Если вердикты разбора разошлись
		 */
		if(actual != expected) {
			// Увеличиваем счётчик расхождений вердиктов
			diverged++;
			// Выводим сообщение о расхождении вердиктов разбора
			ADD_FAILURE()
				<< "Шаблон: " << pattern
				<< ", вердикт модуля: " << (actual ? "принят" : "отклонён")
				<< ", вердикт эталона: " << (expected ? "принят" : "отклонён")
				<< ", текст ошибки разбора: " << parser.message();
			/**
			 * Если количество выведенных расхождений достигло предела
			 */
			if(diverged >= 10)
				// Выходим из цикла сличения вердиктов разбора
				break;
		}
	}
	// Выполняем проверку отсутствия расхождений вердиктов разбора
	EXPECT_EQ(diverged, 0u);
}

