#pragma once

/**
 * Подключаем заголовочные файлы фреймворка
 */
#include <sys/log.hpp>

/**
 * verify пространство имён оснастки сверки
 */
namespace verify {
	/**
	 * @brief Функция отключения вывода журнала работы стенда
	 *
	 * @details Журнал един на процесс, и глушение это держится до конца стенда
	 */
	static inline void silence() noexcept {
		// Выполняем отключение вывода журнала
		awh::log::mode({});
	}
}
