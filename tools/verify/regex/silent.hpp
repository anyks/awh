#ifndef __AWH_VERIFY_REGEX_SILENT__
#define __AWH_VERIFY_REGEX_SILENT__

/**
 * Подключаем заголовочные файлы фреймворка
 */
#include <sys/log.hpp>
#include <sys/fmk.hpp>

/**
 * verify пространство имён оснастки сверки
 */
namespace verify {
	/**
	 * @brief Молчащий журнал работы стенда сверки
	 */
	struct Silent {
		/**
		 * @brief Функция получения объекта фреймворка стенда
		 *
		 * @details Объект заводится статикою местною, а не общею файла: заведение его
		 *          порядком построения статики оканчивается падением ещё до входа в
		 *          стенд, ибо фреймворк сам опирается на статику из библиотеки
		 *
		 * @return объект фреймворка стенда
		 */
		static const awh::fmk_t & framework() noexcept {
			// Объект фреймворка стенда
			static awh::fmk_t fmk;
			// Выводим объект фреймворка стенда
			return fmk;
		}
		// Объект журнала стенда
		awh::log_t log;
		/**
		 * @brief Конструктор
		 */
		Silent() noexcept : log(&Silent::framework()) {
			// Выполняем отключение вывода журнала
			this->log.mode({});
		}
	};
	/**
	 * @brief Функция получения объекта журнала стенда
	 *
	 * @return объект журнала стенда
	 */
	static const awh::log_t * logger() noexcept {
		// Объект журнала стенда
		static Silent silent;
		// Выводим объект журнала стенда
		return &silent.log;
	}
}

#endif // __AWH_VERIFY_REGEX_SILENT__
