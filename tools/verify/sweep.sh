#
# @brief Разбор всех исходных текстов дерева ОДНИМ собирателем без сборки и связывания
#
# @details Помехи сборки, видные лишь ИНОМУ собирателю, доходят до людей потому, что
#          дерево собирают одним. Замер 06.09.2026: четыре помехи под MinGW пришли
#          четырьмя разными коммитами за ТРИ ДНЯ, и каждая валила цель проверок кодеков
#          целиком - они собираются одной программой. Ни одну из них не показал clang
#          рабочей машины
#
# @note Сценарий этот НЕ собирает и НЕ связывает: он лишь разбирает каждый файл
#       (`-fsyntax-only`). Оттого ему не нужны ни gtest, ни собранные зависимости, и
#       прогон целого дерева проверок занимает у стенда около двадцати минут
#
# @warning Пути к сторонним заголовкам подавать ОБЯЗАТЕЛЬНО. Без них отказывают файлы,
#          с собирателем не связанные вовсе, и отказ выдаётся за находку: у меня так
#          вышло дважды, и оба раза виноваты были доводы сценария, а не дерево
#
# @warning По каталогу «src» отбор SKIP почти ОБЯЗАТЕЛЕН: там лежат движки ВСЕХ систем,
#          и на Linux девять частей win, семь bsd и шесть sun отвечают отказом по
#          нехватке чужих заголовков — это окружение, а не дефекты. Туда же попадает
#          «io_uring», собираемый лишь по признаку AWH_ENGINE_IO_URING и требующий
#          заголовков ядра свежее стендовых. Замер 07.09.2026: на Linux 23 отказа из
#          219 файлов, на macOS 9 из 196, и ни один не был дефектом
#
# @note Отбор ЗАВИСИТ ОТ ХОЗЯЙСКОЙ СИСТЕМЫ и одинаковым быть не может: родной движок
#       Linux — «gnu», macOS и BSD — «bsd», Solaris — «sun», а чужие отвечают отказом
#       по нехватке заголовков. По каталогу «tests» отбор не нужен вовсе
#
# @warning Дерево обходится КАК ЕСТЬ, вместе с чужою работой в ходу. Правка соседа,
#          начатая минуту назад, отвечает отказом разбора наравне с настоящей помехой,
#          и отличить их сценарий не может. Проверено на опыте: первый же прогон целого
#          набора выдал отказом файл, правленный шестью минутами ранее и объектного
#          файла не имевший вовсе. Оттого перед докладом ОБЯЗАТЕЛЬНО сличать перечень
#          отказавших с `git status --short`: помеченное изменённым — чужая работа, а
#          не находка. Для проверки перед выкладкой брать СВЕЖИЙ клон, а не рабочее дерево
#
# @copyright Copyright © 2026
#
# Вызов:
#   tools/verify/sweep.sh [каталог обхода] [корень дерева]
#
# Переменные окружения:
#   CXX     — собиратель, по умолчанию «c++»
#   SKIP    — образец путей, обходимых стороной (для «grep -E»); по умолчанию пусто
#   THIRD   — корень сторонних заголовков, по умолчанию «<корень>/third_party/include»
#   FLAGS   — добавочные ключи разбора
#
# Примеры:
#   tools/verify/sweep.sh tests            # весь набор проверок
#   CXX=g++ tools/verify/sweep.sh src      # тело фреймворка вторым собирателем
#
#   # тело фреймворка на Linux: прочь движки ЧУЖИХ систем и кольца, признаком огороженные
#   SKIP='backend/(win|bsd|sun)|io_uring' CXX=g++ tools/verify/sweep.sh src
#
#   # то же на macOS: родной там «bsd», а чужие «gnu», «win» и «sun»; плюс «sys/fs.cpp»,
#   # какому нужен режим Objective-C++, и «bsd/sctp.cpp» — протокола SCTP у macOS нет
#   SKIP='backend/(win|gnu|sun)|io_uring|sys/fs|bsd/sctp' tools/verify/sweep.sh src
#

# Прекращаем работу при отказе, кода возврата не имеющем
set -u

# Получаем каталог обхода
SCAN="${1:-tests}"

# Получаем корень дерева исходных текстов
ROOT="${2:-$(cd "$(dirname "$0")/../.." && pwd)}"

# Получаем собиратель
COMPILER="${CXX:-c++}"

# Получаем корень сторонних заголовков
THIRD="${THIRD:-$ROOT/third_party/include}"

# Собираемые доводы путей к заголовкам
INCLUDES="-I$ROOT/include"

# Если корень сторонних заголовков заведён
if [ -d "$THIRD" ]; then
	# Добавляем общий корень сторонних заголовков
	INCLUDES="$INCLUDES -I$THIRD"
	##
	# Добавляем каталоги отдельных библиотек ПОИМЁННО
	#
	# @warning Перебором «$THIRD/*» их брать НЕЛЬЗЯ: перебор кладёт на путь и
	#          «openssl», а он несёт свой «time.h» - собиратель берёт его вместо
	#          системного, и разбор валится внутри стандартной библиотеки
	##
	for DIR in lz4 bz2 zstd lzma zlib brotli snappy lizard density; do
		# Если каталог заголовков очередной библиотеки заведён, подаём его
		[ -d "$THIRD/$DIR" ] && INCLUDES="$INCLUDES -I$THIRD/$DIR"
	done
fi

# Если каталог обхода не заведён
if [ ! -d "$ROOT/$SCAN" ]; then
	# Выводим сообщение о нехватке каталога обхода
	echo "Каталога обхода «$ROOT/${SCAN}» не имеется" >&2
	# Выходим с ошибкой
	exit 1
fi

##
# Отбираем средство просеивания путей
#
# @warning Родной «grep» у Solaris — вида SVR4, и довода «-E» он не знает вовсе:
#          отбор молча не применяется, обход идёт по ВСЕМУ дереву, и отказы чужих
#          движков выдаются за находки. Замер 07.09.2026: 31 отказ там, где их 7.
#          Оттого средство отбирается ПРОБОЮ, а не по имени системы
##
SIEVE="grep -E"

# Если привычный отбор пробы не проходит
if ! echo "проба" | grep -E "проба" > /dev/null 2>&1; then
	# Выполняем переход на отдельное средство отбора
	SIEVE="egrep"
fi

# Выводим сообщение о начале разбора
echo "Разбираем «${SCAN}» собирателем: $COMPILER"

# Счёт разобранных файлов и отказавших из них
COUNT=0
FAILED=0

# Выполняем перебор всех исходных текстов каталога обхода
for FILE in $(cd "$ROOT" && find "$SCAN" -name "*.cpp" | sort | { [ -n "${SKIP:-}" ] && $SIEVE -v "${SKIP}" || cat; }); do
	# Увеличиваем счёт разобранных файлов
	COUNT=$((COUNT + 1))
	# Если разбор очередного файла отвечен отказом
	if ! (cd "$ROOT" && $COMPILER -std=c++20 -fsyntax-only $INCLUDES ${FLAGS:-} "$FILE") > "/tmp/awh-sweep.log" 2>&1; then
		# Увеличиваем счёт отказавших файлов
		FAILED=$((FAILED + 1))
		# Выводим имя отказавшего файла вместе с первой строкою отказа
		echo "ОТКАЗ: $FILE"
		##
		# Выводим первую строку отказа
		#
		# @warning Довода «-m1» родной «grep» у Solaris тоже не знает, и строка отказа
		#          выходила там мусором вида «grep: illegal option -- m» вместо самой
		#          помехи. Оттого отбирается тем же средством, а первая строка берётся
		#          отдельным «head»
		##
		echo "       $($SIEVE 'error:' "/tmp/awh-sweep.log" | head -1 | cut -c1-120)"
	fi
done

# Выводим итог разбора
echo "ФАЙЛОВ=$COUNT ОТКАЗОВ=$FAILED"

# Выводим код выхода по наличию отказов
[ "$FAILED" -eq 0 ]
