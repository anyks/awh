using namespace std;
using namespace awh;
using namespace awh::codec;

/**
 * @brief Пространство имён вспомогательных построений стенда
 *
 */
namespace {
	// Размеры подаваемого куска, при которых сличается исход разбора
	static constexpr size_t CHUNKS[] = {1, 2, 3, 7};
	/**
	 * @brief Функция записи знака в строение дерева с уходом служебных знаков
	 *
	 * @details Уход обязателен: значения атрибутов и содержимое узлов вольны нести и
	 *          разделители полей выдачи, и переводы строк, а разбор выдачи построчный
	 *
	 * @param text  записываемый текст
	 * @param result собираемое строение дерева
	 *
	 */
	static void escape(const string_view text, string & result) noexcept {
		/**
		 * Выполняем перебор всех знаков записываемого текста
		 */
		for(const char letter : text){
			/**
			 * Определяем вид очередного знака записываемого текста
			 */
			switch(letter){
				// Если знак является обратной косой чертой
				case '\\': result.append("\\\\"); break;
				// Если знак является разделителем полей выдачи
				case '\t': result.append("\\t"); break;
				// Если знак является переводом строки
				case '\n': result.append("\\n"); break;
				// Если знак является возвратом каретки
				case '\r': result.append("\\r"); break;
				// Если знак записывается как есть
				default: result.append(1, letter);
			}
		}
	}
	/**
	 * @brief Функция разбора текста разметки с заданным размером куска
	 *
	 * @details Строение дерева собирается потоком событий, а не обходом собранного
	 * дерева: сличается оно с выдачей `expat`, работающего тем же порядком
	 *
	 * @note Объявления пространств имён выдаются чтением отдельно от атрибутов, а `expat`
	 *       при отключённом разборе пространств имён отдаёт их атрибутами наравне с
	 *       прочими. Стенд возвращает их в перечень атрибутов, иначе сличение показывало
	 *       бы расхождение на всяком тексте с пространством имён
	 *
	 * @param text   разбираемый текст разметки
	 * @param chunk  размер подаваемого куска, ноль означает подачу целиком
	 * @param result собираемое строение дерева разметки
	 * @param reason собираемое пояснение отказа разбора
	 * @return       признак успешности разбора
	 *
	 */
	static bool digest(const string & text, const size_t chunk, string & result, string & reason) noexcept {
		// Объект чтения текста разметки
		xml::reader_t reader(::logger());
		// Получаем размер подаваемого куска
		const size_t length = ((chunk > 0) ? chunk : (text.size() + 1));
		// Положение подачи в разбираемом тексте
		size_t offset = 0;
		/**
		 * Признак того, что разбор дошёл до конца текста
		 *
		 * @warning Приговор снимается ПО НЕМУ и по коду отказа, а не по возврату подачи:
		 *          подача отвечает истиной и тогда, когда разбор оборвался на негодном
		 *          построении, - без этой проверки стенд принимал 951 заведомо негодный
		 *          текст и молчал о том
		 */
		bool finished = false;
		/**
		 * Выполняем подачу текста разметки кусками
		 */
		for(;;){
			// Получаем размер очередного подаваемого куска
			const size_t size = (((offset + length) > text.size()) ? (text.size() - offset) : length);
			// Получаем признак последнего подаваемого куска
			const bool last = ((offset + size) >= text.size());
			/**
			 * Если подача очередного куска текста разметки завершилась отказом
			 */
			if(!reader.feed(text.data() + offset, size, last)){
				// Собираем пояснение отказа разбора
				reason.assign(xml::message(reader.error()));
				// Выводим признак неудачного разбора
				return false;
			}
			// Выполняем переход к следующему куску текста разметки
			offset += size;
			/**
			 * Выполняем перебор всех выданных событий разбора
			 */
			while(reader.next()){
				/**
				 * Определяем вид полученного события разбора
				 */
				switch(static_cast <uint8_t> (reader.event())){
					// Если получено начало узла разметки
					case static_cast <uint8_t> (xml::event_t::ELEMENT_OPEN): {
						// Собираемый перечень записей атрибутов узла
						vector <string> items;
						/**
						 * Выполняем перебор всех объявлений пространств имён узла
						 */
						for(const xml::binding_t & binding : reader.bindings()){
							// Собираемая запись объявления пространства имён
							string item("xmlns");
							/**
							 * Если объявление несёт приставку
							 */
							if(!binding.prefix.empty())
								// Выполняем добавление приставки к записи объявления
								item.append(":").append(binding.prefix);
							// Выполняем добавление значения к записи объявления
							item.append("=");
							// Выполняем добавление обозначения пространства имён
							::escape(binding.uri, item);
							// Добавляем собранную запись к перечню записей атрибутов
							items.push_back(::std::move(item));
						}
						/**
						 * Выполняем перебор всех атрибутов узла разметки
						 */
						for(const xml::attribute_t & attribute : reader.attributes()){
							// Собираемая запись атрибута узла
							string item;
							/**
							 * Если атрибут несёт приставку
							 */
							if(!attribute.name.prefix.empty())
								// Выполняем добавление приставки к записи атрибута
								item.append(attribute.name.prefix).append(":");
							// Выполняем добавление имени атрибута
							item.append(attribute.name.local).append("=");
							// Выполняем добавление значения атрибута
							::escape(attribute.value, item);
							// Добавляем собранную запись к перечню записей атрибутов
							items.push_back(::std::move(item));
						}
						/**
						 * Выполняем упорядочение записей атрибутов узла
						 *
						 * @note Договор порядка атрибутов не устанавливает, и сличать их
						 *       порядком значило бы вменять в отказ то, что отказом не
						 *       является
						 */
						sort(items.begin(), items.end());
						// Выполняем добавление начала узла разметки
						result.append("<");
						/**
						 * Если узел несёт приставку
						 */
						if(!reader.name().prefix.empty())
							// Выполняем добавление приставки к имени узла
							result.append(reader.name().prefix).append(":");
						// Выполняем добавление имени узла разметки
						result.append(reader.name().local);
						/**
						 * Выполняем перебор всех собранных записей атрибутов
						 */
						for(const string & item : items)
							// Выполняем добавление записи атрибута
							result.append(" ").append(item);
						// Выполняем завершение начала узла разметки
						result.append(">");
					} break;
					// Если получен конец узла разметки
					case static_cast <uint8_t> (xml::event_t::ELEMENT_CLOSE):
						// Выполняем добавление конца узла разметки
						result.append("</>");
					break;
					/**
					 * Если получено содержимое узла разметки
					 *
					 * @note Дословный текст и пробельное содержимое от обычного содержимого
					 *       не отделяются: `expat` выдаёт их знаками наравне с прочими, и
					 *       разделение показывало бы расхождение там, где его нет
					 */
					case static_cast <uint8_t> (xml::event_t::TEXT):
					case static_cast <uint8_t> (xml::event_t::CDATA):
					case static_cast <uint8_t> (xml::event_t::SPACE):
						/**
						 * Выполняем добавление содержимого узла разметки
						 *
						 * @note Соседние куски содержимого сливаются: потоковый разбор волен
						 *       дробить их по границам подачи, и `expat` дробит их тоже, а
						 *       договор дробления не устанавливает вовсе
						 */
						::escape(reader.text(), result);
					break;
					// Если текст разметки разобран до конца
					case static_cast <uint8_t> (xml::event_t::FINISH):
						// Запоминаем достижение конца текста разметки
						finished = true;
					break;
				}
			}
			/**
			 * Если текст разметки исчерпан
			 */
			if(last)
				// Прекращаем подачу текста разметки
				break;
		}
		/**
		 * Если разбор до конца текста не дошёл либо завершился отказом
		 */
		if(!finished || (reader.error() != xml::error_t::NONE)){
			// Собираем пояснение отказа разбора
			reason.assign(finished ? xml::message(reader.error()) : "разбор не дошёл до конца текста");
			// Выводим признак неудачного разбора
			return false;
		}
		// Выводим признак успешного разбора
		return true;
	}
}

/**
 * @brief Функция запуска приложения
 *
 * @param argc длина массива параметров
 * @param argv массив параметров
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	/**
	 * Если корень корпуса не передан
	 */
	if(argc < 2){
		// Выводим порядок вызова стенда
		cerr << "Вызов: verify <корень корпуса> < <перечень путей>" << endl;
		// Выходим из приложения с кодом ошибки
		return EXIT_FAILURE;
	}
	// Корень корпуса разбираемых текстов
	const string root(argv[1]);
	// Разбираемый путь очередного текста корпуса
	string path;
	/**
	 * Выполняем перебор всех поданных путей текстов корпуса
	 */
	while(getline(cin, path)){
		/**
		 * Если поданный путь пуст
		 */
		if(path.empty())
			// Выполняем переход к следующему пути
			continue;
		// Открываем файл очередного текста корпуса
		ifstream file(root + "/" + path, ios::binary);
		/**
		 * Если файл открыть не удалось
		 */
		if(!file.is_open()){
			// Выводим сообщение об отсутствии текста корпуса
			cout << path << "\tmissing\tmissing\t\t" << endl;
			// Выполняем переход к следующему пути
			continue;
		}
		// Читаем содержимое файла целиком
		const string text((istreambuf_iterator <char> (file)), istreambuf_iterator <char> ());
		// Собираемое строение дерева разметки
		string result;
		// Собираемое пояснение отказа разбора
		string reason;
		// Выполняем разбор текста, поданного целиком
		const bool whole = ::digest(text, 0, result, reason);
		// Признак совпадения исхода при всякой нарезке текста
		bool stable = true;
		/**
		 * Выполняем перебор всех сличаемых размеров подаваемого куска
		 */
		for(const size_t chunk : ::CHUNKS){
			// Собираемое строение дерева при подаче кусками
			string chunked;
			// Отбрасываемое пояснение отказа разбора
			string ignored;
			/**
			 * Выполняем сличение исхода и строения дерева с подачею текста целиком
			 *
			 * @note Сличается не один лишь приговор, но и само строение: разбор, при
			 *       нарезке принимающий текст, но теряющий содержимое, приговором не
			 *       отличается от исправного никак
			 */
			/**
			 * @note Строение сличается лишь у ПРИНЯТЫХ текстов: сколько событий разбор
			 *       успел выдать прежде отказа, договором не установлено, и вменять
			 *       расхождение в этом значило бы объявлять отказом то, что им не является
			 */
			stable = (stable && (::digest(text, chunk, chunked, ignored) == whole) && (!whole || (chunked == result)));
		}
		// Выводим исход разбора очередного текста корпуса
		cout << path << '\t'
		     << (whole ? "accept" : "reject") << '\t'
		     << (stable ? "stable" : "unstable") << '\t'
		     << result << '\t'
		     << reason << endl;
	}
	// Выходим из приложения
	return EXIT_SUCCESS;
}
