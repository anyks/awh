# @brief Выключатель хода кодека для замера его доли: сборка опыта, пересвязка стенда, возврат дерева
#
# @details Долю чужого хода профилем не снимают: профиль ловит лишь то, что успело попасть в вершину
#         стека, тогда как тяжёлый ход виден только выключением. Этот сценарий заводит ровно тот
#         порядок, какой держится ручными правками: копия файла, выключатель на месте вызова,
#          сборка библиотеки, пересвязка стенда в ОТДЕЛЬНЫЙ каталог, возврат файла из копии и
#          пересборка. Базисный бинарник при этом обязан быть собран из того же дерева БЕЗ правки,
#          иначе рядом встанут две несравненные библиотеки
#
# @warning Сценарий НЕ принимает правку в дерево и не считает отношение: он доводит дело до двух
#          бинарников — базового и опытного, — а гонять их следует вперемешку, кругами, с медианой
#          отношений. Правка, оставленная в дереве этим сценарием, считается забытой: возврат файла
#          стоит последним действием и в успехе, и в отказе сборки
#
# @warning Меряется ВЕРХНЯЯ граница доли: выключается ход целиком, вместе с работой неотъемлемой.
#          Число, снятое этим порядком, не обещание правки, а потолок, и называть его в отчёте
#          следует потолком
#
# @copyright Copyright © 2026
#
# Вызов:
#   tools/benchmark/ablate.sh <кодекс> <файл> <метка> <строки-выключателя> [стенд]
#
# Доводы:
#   кодекс  — имя кодека (json, yaml, csv, ini, toml, xml, abc, cef, syslog)
#   файл    — путь к правимому файлу от корня дерева
#   метка   — строка, по которой сценарий находит место выключателя в файле (подстрока строки объявления)
#   тело    — одна строка выключателя, вставляемая ПОСЛЕ строки объявления (отступ ставится сам);
#             несколько действий разом оформляются фигурными скобками на той же строке
#   стенд   — путь к стенду сличения (по умолчанию tools/benchmark/<кодекс>/awh.cpp);
#             набор проверок и внутренних замеров стендом не считается
#
# Переменные окружения:
#   AWH_ROOT   — корень дерева, по умолчанию каталог выше этого сценария
#   AWHLIB     — библиотека базиса, по умолчанию build-release/libawh.a
#   OUT        — каталог опытного бинарника, по умолчанию /tmp/awh-ablate
#   CXX        — собиратель, по умолчанию «c++»
#

# Прекращаем работу при первом же отказе разбора доводов
set -u

# Получаем корень дерева исходных текстов
ROOT="${AWH_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"

# Разбираем доводы вызова
CODEC="${1:?имя кодека}"
TARGET="${2:?файл для правки}"
MARK="${3:?метка места выключателя}"
BODY="${4:?тело выключателя}"
STAND="${5:-tools/benchmark/${CODEC}/awh.cpp}"

# Получаем библиотеку базиса и каталог вывода
BASE="${AWHLIB:-$ROOT/build-release/libawh.a}"
OUTPUT="${OUT:-/tmp/awh-ablate}"
COMPILER="${CXX:-c++}"

# библиотека обязана существовать до начала: без неё нечем связывать базисный бинарник
if [ ! -f "$BASE" ]; then
	echo "Нет библиотеки базиса: $BASE (соберите Release заранее)" >&2
	exit 1
fi

# Заводим каталоги базиса и опыта раздельно, дабы пересвязка не переставляла готовый бинарник
mkdir -p "$OUTPUT/base" "$OUTPUT/exp"

# Запоминаем копию правимого файла: возврат дерева обязан удасться и при отказе сборки
cp "$ROOT/$TARGET" "$OUTPUT/source.orig"

# Пересвязываем базисный бинарник текущей библиотекой — она отвечает дереву БЕЗ правки
$COMPILER -O3 -DNDEBUG -std=c++17 -I"$ROOT/include" "$ROOT/$STAND" "$BASE" \
	$(uname -s | grep -q Darwin && echo "-framework Foundation") -o "$OUTPUT/base/stand" || {
	echo "Базисный бинарник не собрался: $STAND" >&2
	exit 1
}

# Вставляем выключатель сразу за строкой, названной меткой
awk -v mark="$MARK" -v body="$BODY" '
{
	print
	if(index($0, mark) > 0 && !done){
		done = 1
		printf "\t%s\n", body
	}
}' "$ROOT/$TARGET" > "$OUTPUT/source.ablated"

# Отказ вставки считаем поломкой замера: молча неизменённый файл дал бы отношение ровно единица
if ! cmp -s "$OUTPUT/source.ablated" "$ROOT/$TARGET"; then
	# Ставим опыт на место правки и пересобираем библиотеку
	cp "$OUTPUT/source.ablated" "$ROOT/$TARGET"
else
	cp "$OUTPUT/source.orig" "$ROOT/$TARGET"
	echo "Метка не найдена: выключатель не вставлен («$MARK»)" >&2
	exit 1
fi

# Возврат дерева стоит безусловно: что бы ни случилось со сборкой, правка не остаётся в дереве
restore() {
	cp "$OUTPUT/source.orig" "$ROOT/$TARGET"
	cmake --build "$(dirname "$BASE")" --target awh -j 8 > "$OUTPUT/build.restore.log" 2>&1 || \
		echo "Возврат дерева собран с отказом — проверьте $OUTPUT/build.restore.log" >&2
}

# Собираем опыт; отказ сборки не оставляет правку в дереве
if cmake --build "$(dirname "$BASE")" --target awh -j 8 > "$OUTPUT/build.exp.log" 2>&1; then
	$COMPILER -O3 -DNDEBUG -std=c++17 -I"$ROOT/include" "$ROOT/$STAND" "$BASE" \
		$(uname -s | grep -q Darwin && echo "-framework Foundation") -o "$OUTPUT/exp/stand" \
		|| echo "Опытный бинарник не собрался: $STAND" >&2
else
	echo "Сборка опыта отказала: $OUTPUT/build.exp.log" >&2
fi

# Возвращаем дерево и пересобираем библиотеку принятым кодом
restore

# Докладываем, чем мерить: два бинарника одного дерева, различающиеся одной библиотекой
echo "базис: $OUTPUT/base/stand"
echo "опыт:  $OUTPUT/exp/stand"
echo "дерево возвращено: $(cd "$ROOT" && git diff --name-only -- "$TARGET" | wc -l | tr -d ' ') изменённых файлов по $TARGET"
echo "Гонять вперемешку, три круга, медиана отношений; выключенный ход даёт потолок доли, а не правку"
