#!/usr/bin/env bash

# Получаем корневую дирректорию репозитория (каталог скрипта на три уровня ниже)
readonly ROOT=$(cd "$(dirname "$0")/../../.." && pwd)

# Каталог исходных текстов сравниваемых реализаций
readonly VENDOR="$ROOT/third_party/rival/yaml"

# Выпуск исходных текстов реализации rapidyaml
#
# Реализация эта единственная из пяти, чьи исходные тексты подмодулем не берутся:
# она опирается на стороннюю библиотеку c4core, а та в подмодуле не выложена вовсе -
# дерево `ext/c4core` пусто, и сборка требует отдельной выкладки её. Выпуск же несёт
# одиночный заголовочный файл, c4core в себя вобравший
readonly RAPIDYAML_RELEASE="v0.16.0"

# Название одиночного заголовочного файла выпуска реализации rapidyaml
readonly RAPIDYAML_HEADER="rapidyaml.v0.16.0.singlehdr.hpp"

##
# Функция получения одного файла
#
# @param $1 адрес файла
# @param $2 название файла в каталоге исходных текстов
#
obtain(){
	# Если файл уже получен
	if [ -f "$VENDOR/$2" ]; then
		# Выводим сообщение о пропуске файла
		echo "Skip \"$2\""
		# Выходим без получения файла
		return 0
	fi

	# Выводим сообщение о получении файла
	echo "Fetch \"$2\""

	# Выполняем создание каталога размещения файла
	mkdir -p "$(dirname "$VENDOR/$2")"

	# Выполняем получение файла
	curl -fsSL --max-time 300 -o "$VENDOR/$2" "$1" || exit 1
}

# Выполняем создание каталога исходных текстов
mkdir -p "$VENDOR"

# Выполняем получение исходных текстов реализации rapidyaml
obtain "https://github.com/biojppm/rapidyaml/releases/download/$RAPIDYAML_RELEASE/$RAPIDYAML_HEADER" "rapidyaml/ryml_all.hpp"

# Выводим сообщение о завершении получения исходных текстов
echo "Done: $VENDOR"
