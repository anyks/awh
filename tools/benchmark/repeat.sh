#!/bin/sh
#
# @file: repeat.sh
# @brief Повторный прогон сценария замера с выводом середины ряда и разброса
#
# @details Сценарии набора считают итог ОДНАЖДЫ ЗА ПРОЦЕСС и держат его в
#          постоянной величине - так соседние показатели (выделения памяти,
#          обращения к ядру) считаются по одному прогону, а не по разным.
#          Оттого довод `--repeat` самого набора честного разброса не даёт:
#          повторять нужно процесс целиком, чем этот сценарий и занят
#
# @note Одиночное значение доводом служить не может: разброс между прогонами
#       на одной машине доходит до десятой доли, и соседние прогоны одного и
#       того же кода перекрываются. Сравнивать две сборки допустимо лишь по
#       середине ряда, снятой на одной машине подряд
#
# @usage tools/benchmark/repeat.sh <бинарь> <сценарий> [повторов]
#
# @example tools/benchmark/repeat.sh ./benchmarks/net net/io/accept/connections 7
#
# @author Forman <forman@anyks.com>
# @copyright © 2025 anyks.com
#

# Проверяем количество переданных доводов
if [ "$#" -lt 2 ]; then
	# Выводим подсказку по применению
	echo "Использование: $0 <бинарь> <сценарий> [повторов]" >&2
	# Выходим с признаком ошибки
	exit 1
fi

# Бинарь набора замеров
binary="$1"
# Название сценария замера
scenario="$2"
# Количество повторов прогона
count="${3:-5}"

# Проверяем наличие бинаря набора замеров
if [ ! -x "$binary" ]; then
	# Сообщаем об отсутствии бинаря набора замеров
	echo "Набор замеров \"$binary\" не найден или не исполняем" >&2
	# Выходим с признаком ошибки
	exit 1
fi

# Файл накопления измеренных значений
values=$(mktemp)
# Снимаем накопитель при любом выходе
trap 'rm -f "$values"' EXIT INT TERM

# Выполняем заданное количество прогонов
i=1
while [ "$i" -le "$count" ]; do
	# Прогоняем сценарий и забираем измеренное значение
	"$binary" --filter="$scenario" --relaxed 2>/dev/null \
		| awk -v name="$scenario" '$1 == name { print $2 }' >> "$values"
	# Переходим к следующему прогону
	i=$((i + 1))
done

# Проверяем, что хоть один прогон дал значение
if [ ! -s "$values" ]; then
	# Сообщаем об отсутствии измеренных значений
	echo "Сценарий \"$scenario\" не дал ни одного значения" >&2
	# Выходим с признаком ошибки
	exit 1
fi

# Выводим середину ряда и границы разброса
sort -g "$values" | awk -v name="$scenario" '
	{ value[NR] = $1 }
	END {
		# Середина ряда: при чётном числе прогонов берётся верхняя из двух средних
		middle = value[int((NR + 1) / 2)];
		# Границы разброса измеренных значений
		low = value[1]; high = value[NR];
		# Разброс в сотых долях от наименьшего значения
		spread = (low > 0) ? ((high - low) / low) * 100 : 0;
		# Печатаем итог прогонов
		printf("%s\n  прогонов: %d, середина ряда: %.2f, разброс: %.2f - %.2f (%.1f %%)\n",
		       name, NR, middle, low, high, spread);
	}
'
