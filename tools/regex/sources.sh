#!/bin/sh
# Состав набора, раскладываемого на стенды модуля регулярных выражений.
#
# Файл этот сам ничего не делает: он подключается стендами tools/regex/stand.sh,
# tools/regex/stand-windows.sh и tools/regex/stand-embedded.sh и задаёт им общий
# состав набора.
#
# Заведён он потому, что состав, перечисленный в каждом стенде отдельно,
# устаревает молча. Перекладка дерева исходных текстов ломает перечень, а
# заметно это становится лишь на машине, где прежней раскладки не осталось:
# на машинах, стенд прежде видевших, сборка идёт по файлам, лежащим там
# с прошлого раза, и отказа не даёт.

# Заголовочные файлы
#
# Передаётся дерево заголовочных файлов целиком, а не отобранные из него.
# Отбор был бы точнее, однако вывести его нельзя: часть подключений скрыта
# за условиями системы, и набор, потребный Windows, отличается от набора,
# потребного системам семейства UNIX. Вывод состава на рабочей машине дал бы
# состав её одной. Дерево целиком весит менее мегабайта в сжатом виде, и
# передача его по сети занимает меньше, чем разбирательство с недостачей.
STAND_HEADERS="include"

# Исходные тексты
#
# Перечисляются каталоги, а не файлы: состав каталога стенд разбирает у себя
# поиском, поэтому добавление файла в модуль перечня не касается
# Кодек JSON и разбор чисел перечислены оттого, что надстройка Grok выдаёт
# извлечённые поля значением кодека, а не текстом, собранным вручную: договор
# на выдачу общий у пяти кодеков, и своя запись JSON у Grok была бы шестым.
# Разбор чисел нужен уже кодеку JSON, а не Grok
STAND_SOURCES="src/regex src/encoding/unicode src/codec/json src/num/lexical"

# Исходные тексты переносимой проверки
STAND_TOOLS="tools/regex/conformance.cpp tools/regex/conformance.hpp"
