#include <cstdio>
#include <string>
#include <vector>
#include <random>
#include <chrono>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <grok/table.hpp>
#include <regex/regex.hpp>
#include <regex/storage.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Количество порождаемых выражений пробы
 *
 */
static constexpr size_t SAMPLES = 3000;

/**
 * @brief Количество прогонов замера
 *
 * @details Замер берётся наименьшим из прогонов: наименьший отвечает прогону,
 *          менее прочих потревоженному сторонней работой машины, тогда как
 *          среднее по прогонам несёт помеху тем большую, чем машина занятее.
 *
 */
static constexpr size_t PASSES = 5;

/**
 * @brief Функция извлечения показания часов в миллисекундах
 *
 * @return показание часов в миллисекундах
 *
 */
static double clocking() noexcept {
	// Выводим показание часов в миллисекундах
	return (static_cast <double> (chrono::duration_cast <chrono::nanoseconds> (
	 chrono::steady_clock::now().time_since_epoch()).count()) / 1000000.0);
}
/**
 * @brief Функция порождения набора текстов выражений пробы
 *
 * @return набор текстов выражений пробы
 *
 * @details Набор складывается из шаблонов Grok, каковы суть выражения
 *          настоящие и немалые, и из выражений порождённых, каковы покрывают
 *          построения, шаблонам не свойственные.
 *
 */
static vector <string> patterns() noexcept {
	// Набор текстов выражений пробы
	vector <string> result;
	/**
	 * @brief Набор составляющих порождаемого выражения
	 *
	 */
	const char * atoms[] = {
		"a", "[a-z]", "\\d", "\\w", ".", "x", "(?:ab|cd)", "[^q]", "\\s",
		"(?<name>z)", "(?=a)", "(?<!b)", "\\bq", "(?>a|b)", "[[:alpha:]]"
	};
	/**
	 * @brief Набор кванторов повторения порождаемого выражения
	 *
	 */
	const char * repeats[] = {"", "*", "+", "?", "{2,4}", "*?", "+?", "{1,3}?", "*+"};
	/**
	 * Выполняем перебор набора шаблонов Grok
	 */
	for(size_t i = 0; i < grok::PATTERNS_COUNT; i++)
		// Выполняем добавление текста шаблона в набор
		result.push_back(grok::PATTERNS[i].body);
	// Создаём порождатель случайных значений с постоянным зерном
	mt19937 generator(20260804);
	/**
	 * Выполняем порождение набора выражений
	 */
	for(size_t i = 0; i < SAMPLES; i++) {
		// Текст порождаемого выражения
		string pattern;
		// Получаем количество составляющих порождаемого выражения
		const size_t length = (1 + (generator() % 5));
		/**
		 * Выполняем порождение составляющих выражения
		 */
		for(size_t j = 0; j < length; j++) {
			// Выполняем добавление составляющей выражения
			pattern.append(atoms[generator() % 15]);
			// Выполняем добавление квантора повторения
			pattern.append(repeats[generator() % 9]);
		}
		/**
		 * Если выражение получает захватывающую группу со ссылкой
		 */
		if((generator() % 4) == 0)
			// Выполняем оборачивание выражения захватывающей группой
			pattern = ("(" + pattern + ")\\1?");
		// Выполняем добавление текста выражения в набор
		result.push_back(::move(pattern));
	}
	// Выводим набор текстов выражений пробы
	return result;
}
/**
 * @brief Функция входа в пробу хранилища собранных выражений
 *
 * @return результат исполнения пробы
 *
 */
int main() {
	// Создаём объект работы с регулярными выражениями
	const regexp_t regexp;
	// Создаём объект хранилища собранных выражений
	const regex::storage_t storage;
	// Получаем набор текстов выражений пробы
	const auto texts = patterns();
	// Набор собранных начисто выражений
	vector <regex::storage_t::exp_t> fresh;
	// Набор текстов выражений, сборке поддавшихся
	vector <string> accepted;
	// Расход сборки выражений из текста
	double building = 0.0;
	/**
	 * Выполняем сборку набора выражений
	 *
	 * @details Замер сборки берётся единственным прогоном: сборка выражения
	 *          уже собранного выдаётся кэшем и расхода разбора не несёт вовсе,
	 *          отчего прогон повторный замерял бы не сборку, а выдачу кэша.
	 *
	 */
	for(size_t pass = 0; pass < 1; pass++) {
		// Набор собранных выражений очередного прогона
		vector <regex::storage_t::exp_t> records;
		// Набор текстов выражений очередного прогона
		vector <string> taken;
		// Выполняем размещение набора собранных выражений
		records.reserve(texts.size());
		// Получаем показание часов на входе в сборку
		const double started = clocking();
		/**
		 * Выполняем перебор набора текстов выражений
		 */
		for(const auto & text : texts) {
			// Выполняем сборку регулярного выражения
			const auto exp = regexp.build(text, {regexp_t::flag_t::DUPNAMES});
			/**
			 * Если сборка регулярного выражения выполнена
			 */
			if(exp) {
				// Выполняем добавление собранного выражения в набор
				records.push_back(exp);
				// Выполняем добавление текста выражения в набор
				taken.push_back(text);
			}
		}
		// Получаем расход сборки набора выражений
		const double spent = (clocking() - started);
		/**
		 * Если расход сборки прогона наименьший
		 */
		if((pass == 0) || (spent < building))
			// Выполняем установку расхода сборки выражений
			building = spent;
		// Выполняем сохранение набора собранных выражений
		fresh = ::move(records);
		// Выполняем сохранение набора текстов выражений
		accepted = ::move(taken);
	}
	// Выводим количество собранных выражений и расход сборки
	::printf("выражений собрано: %zu из %zu\n", fresh.size(), texts.size());
	::printf("сборка из текста: %.1f мс\n", building);
	// Запись хранилища собранных выражений
	string record;
	// Расход записи собранных выражений
	double writing = 0.0;
	/**
	 * Выполняем перебор прогонов замера записи выражений
	 */
	for(size_t pass = 0; pass < PASSES; pass++) {
		// Записываемая запись хранилища очередного прогона
		string current;
		// Получаем показание часов на входе в запись
		const double started = clocking();
		/**
		 * Если запись собранных выражений не выполнена
		 */
		if(!storage.save(fresh, current)) {
			// Выводим сообщение об отказе записи собранных выражений
			::printf("запись собранных выражений отказана, код %u\n", static_cast <uint32_t> (storage.error()));
			// Выводим результат исполнения пробы
			return 1;
		}
		// Получаем расход записи набора выражений
		const double spent = (clocking() - started);
		/**
		 * Если расход записи прогона наименьший
		 */
		if((pass == 0) || (spent < writing))
			// Выполняем установку расхода записи выражений
			writing = spent;
		// Выполняем сохранение записи хранилища
		record = ::move(current);
	}
	// Выводим расход записи и размер записи хранилища
	::printf("запись: %.1f мс, %zu Кбайт\n", writing, (record.size() / 1024));
	// Набор восстановленных выражений
	vector <regex::storage_t::exp_t> restored;
	// Расход восстановления собранных выражений
	double reading = 0.0;
	/**
	 * Выполняем перебор прогонов замера восстановления выражений
	 */
	for(size_t pass = 0; pass < PASSES; pass++) {
		// Набор восстановленных выражений очередного прогона
		vector <regex::storage_t::exp_t> records;
		// Получаем копию записи хранилища, передаваемую во владение
		string current = record;
		// Получаем показание часов на входе в восстановление
		const double started = clocking();
		/**
		 * Если восстановление собранных выражений не выполнено
		 */
		if(!storage.adopt(::move(current), records)) {
			// Выводим сообщение об отказе восстановления собранных выражений
			::printf("восстановление собранных выражений отказано, код %u\n", static_cast <uint32_t> (storage.error()));
			// Выводим результат исполнения пробы
			return 1;
		}
		// Получаем расход восстановления набора выражений
		const double spent = (clocking() - started);
		/**
		 * Если расход восстановления прогона наименьший
		 */
		if((pass == 0) || (spent < reading))
			// Выполняем установку расхода восстановления выражений
			reading = spent;
		// Выполняем сохранение набора восстановленных выражений
		restored = ::move(records);
	}
	// Выводим расход восстановления и выигрыш против сборки
	::printf("восстановление: %.1f мс, выигрыш %.1fx\n", reading, (building / reading));
	/**
	 * Если количество восстановленных выражений набору не отвечает
	 */
	if(restored.size() != fresh.size()) {
		// Выводим сообщение о расхождении количества выражений
		::printf("восстановлено %zu выражений вместо %zu\n", restored.size(), fresh.size());
		// Выводим результат исполнения пробы
		return 1;
	}
	/**
	 * @brief Набор текстов сличения поведения выражений
	 *
	 */
	const vector <string> subjects = {
		"", "a", "abc", "aaa 123 zzz", "x b00_\nb0", "qqqqqqqqqq", "abababab",
		"z", "-42.5e3", "\tмного текста\n", "AZaz09", "  ", "b", "cdcdcd",
		"2026-08-04T12:30:00Z", "192.168.5.150:8080", "forman@anyks.com",
		"GET /index.html HTTP/1.1", "user-agent: awh/5.0", "0x1F2E3D4C"
	};
	// Количество выполненных сличений и обнаруженных расхождений
	size_t comparisons = 0, divergences = 0;
	/**
	 * Выполняем перебор набора восстановленных выражений
	 */
	for(size_t i = 0; i < fresh.size(); i++) {
		/**
		 * Выполняем перебор набора текстов сличения
		 */
		for(const auto & subject : subjects) {
			// Выполняем увеличение количества выполненных сличений
			comparisons++;
			/**
			 * Если границы совпадения выражений расходятся
			 */
			if(regexp.match(subject, fresh.at(i)) != regexp.match(subject, restored.at(i))) {
				// Выполняем увеличение количества обнаруженных расхождений
				divergences++;
				/**
				 * Если расхождение обнаружено впервые
				 */
				if(divergences <= 5)
					// Выводим сообщение об обнаруженном расхождении
					::printf("расхождение: выражение \"%s\" на тексте \"%s\"\n",
					 accepted.at(i).c_str(), subject.c_str());
			}
		}
	}
	// Выводим количество выполненных сличений и обнаруженных расхождений
	::printf("сличений %zu, расхождений %zu\n", comparisons, divergences);
	// Выводим результат исполнения пробы
	return (divergences > 0 ? 1 : 0);
}
