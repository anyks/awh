/**
 * Подключаем заголовочные файлы проекта
 */
#include <regex/regex.hpp>
#include <regex/storage.hpp>

/**
 * Стандартные заголовочные файлы
 */
#include <cstdio>
#include <cstdint>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Функция запуска приложения
 *
 * @return код выхода из приложения
 *
 */
int32_t main() noexcept {
	// Создаём объект работы с регулярными выражениями
	const regexp_t regexp;
	// Создаём объект хранилища собранных выражений
	const regex::storage_t storage;
	/**
	 * Выполняем сборку регулярного выражения из символов различных
	 *
	 * @details Обратная ссылка уводит сопоставление в исполнение с возвратом:
	 *          исполнение детерминированное пометки ряда не читает вовсе,
	 *          и подделка на нём вреда не даёт.
	 *
	 */
	const auto exp = regexp.build("^(\\d)abc\\1$");
	/**
	 * Если сборка регулярного выражения не удалась
	 */
	if(!exp) {
		// Выводим сообщение об отказе сборки выражения
		::printf("сборка выражения не удалась\n");
		// Выходим из приложения с кодом отказа
		return 1;
	}
	// Выполняем проверку сопоставления выражением собранным
	::printf("собранное:    «1abc1» → %s, «1aaa1» → %s\n",
	 (regexp.test("1abc1", exp) ? "да" : "нет"),
	 (regexp.test("1aaa1", exp) ? "да" : "нет"));
	// Создаём подделываемое собранное выражение
	auto twisted = make_shared <regex::expression_t> (* exp);
	/**
	 * Выполняем обход указаний собранной программы
	 */
	for(size_t i = 0; i < twisted->forward.instructions.size(); i++) {
		// Получаем очередное указание собранной программы
		auto & instruction = twisted->forward.instructions[i];
		/**
		 * Если указание сопоставляет одиночный символ
		 */
		if(instruction.type == regex::opcode_t::CHAR) {
			// Выполняем подделку пометки ряда у символов различных
			instruction.repeat = 3;
			// Выходим из обхода указаний собранной программы
			break;
		}
	}
	// Запись хранилища подделанного выражения
	string record;
	/**
	 * Если запись подделанного выражения не удалась
	 */
	if(!storage.save({twisted}, record)) {
		// Выводим сообщение об отказе записи выражения
		::printf("запись подделанного выражения не удалась\n");
		// Выходим из приложения с кодом отказа
		return 1;
	}
	// Набор восстановленных выражений
	vector <regex::storage_t::exp_t> restored;
	/**
	 * Если восстановление записи подделанной отвергнуто
	 */
	if(!storage.load(record, restored)) {
		// Выводим сообщение об отказе восстановления записи
		::printf("подделанное: ОТВЕРГНУТО поверкой, код %u — заслон на месте\n",
		 static_cast <uint32_t> (storage.error()));
		// Выходим из приложения с кодом успеха
		return 0;
	}
	// Выполняем проверку сопоставления выражением подделанным
	::printf("подделанное:  «1abc1» → %s, «1aaa1» → %s\n",
	 (regexp.test("1abc1", restored.at(0)) ? "да" : "нет"),
	 (regexp.test("1aaa1", restored.at(0)) ? "да" : "нет"));
	/**
	 * Если подделанное выражение сопоставилось текстом посторонним
	 */
	if(regexp.test("1aaa1", restored.at(0)))
		// Выводим сообщение о ложном совпадении подделанного выражения
		::printf("ВРЕД: «1aaa1» совпало с «^(\\d)abc\\1$» — пометка ряда перешагнула две инструкции\n");
	// Выходим из приложения с кодом успеха
	return 0;
}
