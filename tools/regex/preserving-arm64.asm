;
; Обёртка вызова порождённого кода, приметы в оберегаемые регистры укладывающая.
;
; Файл заведён ради связки вооружения Visual Studio: вставок на языке ассемблера
; она на наборе ARM64 не имеет вовсе - ни в виде «__asm__», ни в виде «__asm», -
; отчего проверка сохранности регистров там отчитывалась пропуском. Заменить
; обёртку кодом на языке C нельзя: она обязана занять оберегаемые регистры перед
; самым вызовом и снять их сразу по возвращении, а распределитель регистров
; такого не обещает.
;
; Тело обёртки повторяет вставку, в tools/regex/conformance.cpp размещённую:
; приметы укладываются в x19 - x23, а выдаётся сумма их по исключающему или,
; снятая по возвращении. Совпадение суммы с суммой укладываемых примет означает
; сохранность всех оберегаемых регистров, расхождение - затирание хотя бы одного.
;
; Регистр x18 не занимается вовсе: Windows держит в нём указатель на данные потока.
;
	AREA	|.text|, CODE, READONLY

	EXPORT	awh_regex_preserving

awh_regex_preserving PROC
	stp	x29, x30, [sp, #-96]!
	mov	x29, sp
	stp	x19, x20, [sp, #16]
	stp	x21, x22, [sp, #32]
	str	x23, [sp, #48]
	mov	x8, x0
	mov	x0, x1
	mov	x1, x2
	mov	x2, x3
	mov	x3, x4
	mov	x4, x5
	movz	x19, #0x7788
	movk	x19, #0x5566, lsl #16
	movk	x19, #0x3344, lsl #32
	movk	x19, #0x1122, lsl #48
	movz	x20, #0xFF00
	movk	x20, #0xDDEE, lsl #16
	movk	x20, #0xBBCC, lsl #32
	movk	x20, #0x99AA, lsl #48
	movz	x21, #0x6978
	movk	x21, #0x4B5A, lsl #16
	movk	x21, #0x2D3C, lsl #32
	movk	x21, #0x0F1E, lsl #48
	movz	x22, #0x9BDF
	movk	x22, #0x1357, lsl #16
	movk	x22, #0xACE0, lsl #32
	movk	x22, #0x2468, lsl #48
	movz	x23, #0xBA98
	movk	x23, #0xFEDC, lsl #16
	movk	x23, #0x3210, lsl #32
	movk	x23, #0x7654, lsl #48
	blr	x8
	mov	x0, x19
	eor	x0, x0, x20
	eor	x0, x0, x21
	eor	x0, x0, x22
	eor	x0, x0, x23
	ldr	x23, [sp, #48]
	ldp	x21, x22, [sp, #32]
	ldp	x19, x20, [sp, #16]
	ldp	x29, x30, [sp], #96
	ret
	ENDP

	END
