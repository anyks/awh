/**
 * Стандартные заголовочные файлы
 */
#include <cstdio>
#include <string>
#include <vector>
#include <chrono>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <regex/grok/grok.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Количество прогонов замера
 *
 */
static constexpr size_t PASSES = 5;

/**
 * @brief Набор текстов сличения поведения шаблонов
 *
 */
static const char * const SUBJECTS[] = {
	"192.168.5.150", "forman@anyks.com", "2026-08-04T12:30:00Z",
	"GET /index.html HTTP/1.1", "-42.5e3", "слово", "ERROR", "anyks.com",
	"0x1F2E3D4C", "192.168.5.150 - forman [04/Aug/2026:12:30:00] 200 4711", ""
};

/**
 * @brief Функция извлечения показания часов в миллисекундах
 *
 * @return показание часов в миллисекундах
 *
 */
static double clocking() noexcept {
	// Выводим показание часов в миллисекундах
	return (static_cast <double> (chrono::duration_cast <chrono::nanoseconds> (
	 chrono::steady_clock::now().time_since_epoch()).count()) / 1000000.0);
}
/**
 * @brief Функция входа в пробу записи собранных шаблонов Grok
 *
 * @return результат исполнения пробы
 *
 */
int main() {
	// Создаём объект разбора текста по шаблонам Grok
	const Grok grok;
	// Набор текстов шаблонов пробы
	vector <string> patterns;
	/**
	 * Выполняем перебор названий шаблонов реестра
	 *
	 * @details Пробе подлежит весь встроенный набор целиком: шаблоны его суть
	 *          выражения настоящие и немалые, а самый тяжёлый из них
	 *          разворачивается в девять тысяч байтов.
	 */
	for(const auto & name : grok.patterns())
		// Выполняем добавление ссылки на шаблон в набор
		patterns.push_back("%{" + name + "}");
	/**
	 * Если набор текстов шаблонов пуст
	 */
	if(patterns.empty()) {
		// Выводим сообщение об отсутствии шаблонов реестра
		::printf("реестр шаблонов пуст\n");
		// Выводим результат исполнения пробы
		return 1;
	}
	// Выводим количество шаблонов набора пробы
	::printf("шаблонов набора: %zu\n", patterns.size());
	// Набор шаблонов, сборке поддавшихся
	vector <string> accepted;
	// Набор собранных начисто шаблонов
	vector <Grok::exp_t> fresh;
	/**
	 * Выполняем сборку набора шаблонов начисто
	 *
	 * @details Замер сборки берётся единственным прогоном: сборка шаблона уже
	 *          собранного выдаётся кэшем и расхода разворота с компиляцией
	 *          не несёт вовсе, отчего прогон повторный замерял бы выдачу кэша.
	 */
	const double started = clocking();
	/**
	 * Выполняем перебор набора текстов шаблонов
	 */
	for(const auto & pattern : patterns) {
		// Выполняем сборку шаблона Grok
		const auto exp = grok.build(pattern);
		/**
		 * Если сборка шаблона Grok выполнена
		 */
		if(exp) {
			// Выполняем добавление собранного шаблона в набор
			fresh.push_back(exp);
			// Выполняем добавление текста шаблона в набор
			accepted.push_back(pattern);
		}
	}
	// Получаем расход сборки набора шаблонов начисто
	const double building = (clocking() - started);
	// Выводим количество собранных шаблонов и расход сборки
	::printf("собрано начисто: %zu шаблонов за %.1f мс\n", fresh.size(), building);
	// Запись собранных шаблонов Grok
	string record;
	// Расход записи собранных шаблонов
	double writing = 0.0;
	/**
	 * Выполняем перебор прогонов замера записи шаблонов
	 */
	for(size_t pass = 0; pass < 3; pass++) {
		// Записываемая запись очередного прогона
		string current;
		// Получаем показание часов на входе в запись
		const double mark = clocking();
		/**
		 * Если запись собранных шаблонов не выполнена
		 */
		if(!grok.save(accepted, current)) {
			// Выводим сообщение об отказе записи собранных шаблонов
			::printf("запись собранных шаблонов отказана, код %u\n", static_cast <uint32_t> (grok.error()));
			// Выводим результат исполнения пробы
			return 1;
		}
		// Получаем расход записи набора шаблонов
		const double spent = (clocking() - mark);
		/**
		 * Если расход записи прогона наименьший
		 */
		if((pass == 0) || (spent < writing))
			// Выполняем установку расхода записи шаблонов
			writing = spent;
		// Выполняем сохранение записи собранных шаблонов
		record = ::move(current);
	}
	// Выводим расход записи и размер записи собранных шаблонов
	::printf("запись: %.1f мс, %zu Кбайт\n", writing, (record.size() / 1024));
	// Создаём объект восстановления шаблонов Grok
	Grok loader;
	// Набор восстановленных шаблонов Grok
	vector <Grok::exp_t> restored;
	// Расход восстановления собранных шаблонов
	double reading = 0.0;
	/**
	 * Выполняем перебор прогонов замера восстановления шаблонов
	 */
	for(size_t pass = 0; pass < PASSES; pass++) {
		// Набор восстановленных шаблонов очередного прогона
		vector <Grok::exp_t> records;
		// Получаем показание часов на входе в восстановление
		const double mark = clocking();
		/**
		 * Если восстановление собранных шаблонов не выполнено
		 */
		if(!loader.load(record, records)) {
			// Выводим сообщение об отказе восстановления шаблонов
			::printf("восстановление собранных шаблонов отказано, код %u\n", static_cast <uint32_t> (loader.error()));
			// Выводим результат исполнения пробы
			return 1;
		}
		// Получаем расход восстановления набора шаблонов
		const double spent = (clocking() - mark);
		/**
		 * Если расход восстановления прогона наименьший
		 */
		if((pass == 0) || (spent < reading))
			// Выполняем установку расхода восстановления шаблонов
			reading = spent;
		// Выполняем сохранение набора восстановленных шаблонов
		restored = ::move(records);
	}
	// Выводим расход восстановления и выигрыш против сборки
	::printf("восстановление: %.1f мс, выигрыш %.0fx\n", reading, (building / reading));
	/**
	 * Если количество восстановленных шаблонов набору не отвечает
	 */
	if(restored.size() != fresh.size()) {
		// Выводим сообщение о расхождении количества шаблонов
		::printf("восстановлено %zu шаблонов вместо %zu\n", restored.size(), fresh.size());
		// Выводим результат исполнения пробы
		return 1;
	}
	// Количество выполненных сличений и обнаруженных расхождений
	size_t comparisons = 0, divergences = 0;
	/**
	 * Выполняем перебор набора восстановленных шаблонов
	 */
	for(size_t i = 0; i < fresh.size(); i++) {
		/**
		 * Если развёрнутый текст шаблона расходится
		 */
		if(restored.at(i)->expression != fresh.at(i)->expression) {
			// Выполняем увеличение количества обнаруженных расхождений
			divergences++;
			// Выводим сообщение о расхождении развёрнутого текста
			::printf("расхождение текста: шаблон \"%s\"\n", accepted.at(i).c_str());
		}
		/**
		 * Выполняем перебор набора текстов сличения
		 */
		for(const char * subject : SUBJECTS) {
			// Выполняем увеличение количества выполненных сличений
			comparisons++;
			// Значения полей, извлечённые шаблонами
			string first, second;
			// Выполняем извлечение значений полей собранным шаблоном
			grok.json(subject, fresh.at(i), first);
			// Выполняем извлечение значений полей восстановленным шаблоном
			loader.json(subject, restored.at(i), second);
			/**
			 * Если извлечённые значения полей расходятся
			 */
			if(first != second) {
				// Выполняем увеличение количества обнаруженных расхождений
				divergences++;
				/**
				 * Если расхождение обнаружено в числе первых
				 */
				if(divergences <= 5)
					// Выводим сообщение об обнаруженном расхождении
					::printf("расхождение: шаблон \"%s\" на тексте \"%s\"\n",
					 accepted.at(i).c_str(), subject);
			}
		}
	}
	// Выводим количество выполненных сличений и обнаруженных расхождений
	::printf("сличений %zu, расхождений %zu\n", comparisons, divergences);
	// Выводим результат исполнения пробы
	return (divergences > 0 ? 1 : 0);
}
