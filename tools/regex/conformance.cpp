/**
 * @brief Пространство имён порождения образцов сличения
 *
 */
namespace {
	/**
	 * @brief Части, из каких собираются порождаемые выражения
	 *
	 */
	const char * ATOMS[] = {
		"a", "b", "0", "[0-9]", "[a-z]", "\\d", "\\w",
		"\\s", ".", "[^0-9]", "x", "\\n", "[abc]", "[^a-c]"
	};

	/**
	 * @brief Кванторы повторения, приписываемые частям выражения
	 *
	 */
	const char * REPEATS[] = {"", "*", "+", "?", "{2}", "{1,3}", "*?", "+?", "??"};

	/**
	 * @brief Привязки к позиции в тексте, приписываемые выражению
	 *
	 */
	const char * ANCHORS[] = {
		"", "^", "\\b", "\\B", "$", "\\A",
		"\\G", "\\K", "(?m)^", "(?m)", "\\z", "\\Z"
	};

	/**
	 * @brief Конструкции, требующие исполнения с возвратом
	 *
	 */
	const char * EXTRAS[] = {
		"(?=\\w)", "(?!\\d)", "(?<=a)", "(?<!b)",
		"(\\w)\\1", "(?>\\w+)", "(?:(a)|(b))\\1?"
	};

	/**
	 * @brief Символы текста сопоставления вне режима разбора UTF-8
	 *
	 */
	const char * PLAIN[] = {"a", "b", "0", " ", "\n", "x", "y", "z", "c", "1", "9", "_"};

	/**
	 * @brief Символы текста сопоставления в режиме разбора UTF-8
	 *
	 */
	const char * WIDE[] = {"a", "\xd0\xb4", "0", "\xd1\x8e", " ", "\n", "x", "\xd1\x8f", "\xd1\x86", "1", "\xe2\x82\xac", "_"};

	/**
	 * @brief Функция порождения выражения сличения
	 *
	 * @param gen источник псевдослучайных значений
	 * @return    порождённое регулярное выражение
	 *
	 */
	string pattern(mt19937 & gen) noexcept {
		// Формируем порождаемое регулярное выражение
		string result(ANCHORS[gen() % 12]);
		// Получаем количество частей порождаемого выражения
		const size_t parts = (1 + (gen() % 3));
		/**
		 * Выполняем наполнение порождаемого выражения
		 */
		for(size_t i = 0; i < parts; i++) {
			// Выполняем добавление очередной части выражения
			result.append(ATOMS[gen() % 14]);
			// Выполняем добавление квантора повторения части
			result.append(REPEATS[gen() % 9]);
		}
		/**
		 * Если выражению приписывается конструкция, требующая возврата
		 */
		if((gen() % 6) == 0)
			// Выполняем добавление конструкции, требующей возврата
			result.append(EXTRAS[gen() % 7]);
		/**
		 * Если выражению приписывается завершающая привязка
		 */
		if((gen() % 4) == 0)
			// Выполняем добавление завершающей привязки
			result.append(ANCHORS[gen() % 12]);
		/**
		 * Если выражение предваряется выбором одной из ветвей
		 */
		if((gen() % 5) == 0) {
			/**
			 * Получаем части выражения ветвей по отдельности
			 *
			 * @details Извлечение выполняется отдельными действиями намеренно:
			 *          порядок вычисления доводов сложения стандартом не определён,
			 *          и несколько обращений к источнику в одном выражении дали бы
			 *          разные образцы на разных компиляторах. Расхождение это
			 *          обнаружено сличением сумм, снятых компиляторами GCC и Clang.
			 *
			 */
			const string first(ANCHORS[gen() % 12]);
			// Получаем часть выражения ветви с наибольшим приоритетом
			const string second(ATOMS[gen() % 14]);
			// Получаем привязку ветви с наименьшим приоритетом
			const string third(ANCHORS[gen() % 12]);
			// Получаем часть выражения ветви с наименьшим приоритетом
			const string fourth(ATOMS[gen() % 14]);
			// Формируем предваряющий выражение выбор одной из ветвей
			string branches("(?:");
			// Выполняем добавление привязки ветви с наибольшим приоритетом
			branches.append(first);
			// Выполняем добавление части выражения ветви с наибольшим приоритетом
			branches.append(second);
			// Выполняем добавление разделителя ветвей выражения
			branches.append("|");
			// Выполняем добавление привязки ветви с наименьшим приоритетом
			branches.append(third);
			// Выполняем добавление части выражения ветви с наименьшим приоритетом
			branches.append(fourth);
			// Выполняем завершение выбора одной из ветвей
			branches.append(")");
			// Выполняем добавление накопленного выражения
			branches.append(result);
			// Выполняем предварение выражения выбором одной из ветвей
			result = branches;
		}
		// Выводим порождённое регулярное выражение
		return result;
	}
	/**
	 * @brief Функция порождения текста сопоставления
	 *
	 * @param gen    источник псевдослучайных значений
	 * @param length наибольшая длина порождаемого текста в символах
	 * @param utf    флаг порождения текста в режиме разбора UTF-8
	 * @return       порождённый текст сопоставления
	 *
	 */
	string subject(mt19937 & gen, const size_t length, const bool utf) noexcept {
		// Формируем порождаемый текст сопоставления
		string result;
		// Получаем длину порождаемого текста в символах
		const size_t size = (gen() % length);
		/**
		 * Выполняем наполнение порождаемого текста сопоставления
		 */
		for(size_t i = 0; i < size; i++)
			// Выполняем добавление очередного символа текста
			result.append(utf ? WIDE[gen() % 12] : PLAIN[gen() % 12]);
		// Выводим порождённый текст сопоставления
		return result;
	}
	/**
	 * @brief Функция накопления суммы по итогу сопоставления
	 *
	 * @details Сумма накапливается умножением на нечётное число с последующим
	 *          сложением: перестановка образцов при этом сумму изменяет,
	 *          что и требуется от неё.
	 *
	 * @param sum   накопленная сумма
	 * @param value добавляемое значение
	 * @return      накопленная сумма
	 *
	 */
	inline uint64_t accumulate(const uint64_t sum, const uint64_t value) noexcept {
		// Выводим накопленную сумму
		return (((sum * 0x100000001B3ull) ^ value) + 0x9E3779B97F4A7C15ull);
	}
	/**
	 * @brief Функция сличения блока образцов с записанным образцом
	 *
	 * @param block   описание блока образцов сличения
	 * @param verbose флаг вывода итога сопоставления каждого образца
	 * @return        результат сличения блока образцов
	 *
	 */
	bool verify(const block_t & block, const bool verbose) noexcept {
		// Создаём источник псевдослучайных значений
		mt19937 gen(block.seed);
		// Создаём объект движка регулярных выражений
		regex::engine_t engine;
		// Получаем набор режимов сопоставления движком
		const uint32_t flags = (block.utf ? (static_cast <uint32_t> (regex::flag_t::UTF) | static_cast <uint32_t> (regex::flag_t::UCP)) : 0);
		// Накапливаемая сумма по итогам сопоставления блока
		uint64_t sum = 0;
		// Количество выполненных сопоставлений блока
		size_t checked = 0;
		// Количество расхождений с эталонной реализацией
		size_t divergences = 0;
		/**
		 * Выполняем обход образцов блока сличения
		 */
		for(size_t sample = 0; sample < block.samples; sample++) {
			// Получаем порождённое регулярное выражение
			const string expression = pattern(gen);
			// Получаем порождённый текст сопоставления
			const string text = subject(gen, block.length, block.utf);
			// Создаём собираемое регулярное выражение
			regex::expression_t compiled;
			// Выполняем сборку регулярного выражения
			const bool built = engine.build(expression, flags, compiled);
			// Создаём набор границ совпадения и захваченных групп
			vector <pair <size_t, size_t>> captures;
			// Выполняем сопоставление регулярного выражения движком
			const bool matched = (built ? engine.exec(compiled, text, 0, captures) : false);
			// Получаем начальную границу обнаруженного совпадения
			const size_t begin = (matched ? captures.front().first : 0);
			// Получаем конечную границу обнаруженного совпадения
			const size_t finish = (matched ? captures.front().second : 0);
			// Выполняем накопление суммы признаком выполненной сборки
			sum = accumulate(sum, (built ? 1ull : 0ull));
			// Выполняем накопление суммы вердиктом сопоставления
			sum = accumulate(sum, (matched ? 1ull : 0ull));
			// Выполняем накопление суммы начальной границей совпадения
			sum = accumulate(sum, static_cast <uint64_t> (begin));
			// Выполняем накопление суммы конечной границей совпадения
			sum = accumulate(sum, static_cast <uint64_t> (finish));
			// Увеличиваем количество выполненных сопоставлений
			checked++;
			/**
			 * Если стенд собран со сличением с эталонной реализацией
			 */
			#if defined(AWH_TOOLS_PCRE2)
				/**
				 * Если сборка регулярного выражения выполнена
				 */
				if(built) {
					// Код ошибки сборки эталонного регулярного выражения
					int code = 0;
					// Положение ошибки сборки эталонного регулярного выражения
					PCRE2_SIZE offset = 0;
					// Получаем набор режимов сопоставления эталонной реализацией
					const uint32_t modes = (block.utf ? (PCRE2_UTF | PCRE2_UCP) : 0);
					// Выполняем сборку эталонного регулярного выражения
					pcre2_code * reference = ::pcre2_compile(reinterpret_cast <PCRE2_SPTR> (expression.c_str()), expression.size(), modes, &code, &offset, nullptr);
					/**
					 * Если сборка эталонного регулярного выражения выполнена
					 */
					if(reference != nullptr) {
						// Выполняем размещение набора границ эталонного совпадения
						pcre2_match_data * data = ::pcre2_match_data_create_from_pattern(reference, nullptr);
						// Выполняем сопоставление эталонного регулярного выражения
						const int count = ::pcre2_match(reference, reinterpret_cast <PCRE2_SPTR> (text.c_str()), text.size(), 0, 0, data, nullptr);
						// Получаем набор границ эталонного совпадения
						PCRE2_SIZE * ovector = ::pcre2_get_ovector_pointer(data);
						// Получаем вердикт эталонного сопоставления
						const bool expected = (count > 0);
						/**
						 * Если вердикт либо границы совпадения эталону не отвечают
						 */
						if((matched != expected) || (expected && ((begin != static_cast <size_t> (ovector[0])) || (finish != static_cast <size_t> (ovector[1]))))) {
							// Увеличиваем количество расхождений с эталонной реализацией
							divergences++;
							/**
							 * Если расхождений выведено не более десяти
							 */
							if(divergences <= 10)
								// Выполняем вывод расхождения с эталонной реализацией
								::printf("    расхождение: «%s» текст «%s» эталон=%d[%zu,%zu] модуль=%d[%zu,%zu]\n",
								 expression.c_str(), text.c_str(), (int) expected,
								 (expected ? static_cast <size_t> (ovector[0]) : 0), (expected ? static_cast <size_t> (ovector[1]) : 0),
								 (int) matched, begin, finish);
						}
						// Выполняем освобождение набора границ эталонного совпадения
						::pcre2_match_data_free(data);
						// Выполняем освобождение эталонного регулярного выражения
						::pcre2_code_free(reference);
					}
				}
			#endif
			/**
			 * Если требуется вывод итога сопоставления каждого образца
			 */
			if(verbose)
				// Выполняем вывод итога сопоставления образца
				::printf("  %-6zu «%s» сборка=%d вердикт=%d [%zu,%zu]\n", sample, expression.c_str(), (int) built, (int) matched, begin, finish);
		}
		/**
		 * Если стенд собран со сличением с эталонной реализацией
		 */
		#if defined(AWH_TOOLS_PCRE2)
			// Выполняем вывод итога сличения блока с эталонной реализацией
			::printf("  %-22s образцов %-7zu расхождений с эталоном %-6zu сумма %016llx\n",
			 block.name, checked, divergences, static_cast <unsigned long long> (sum));
			// Выводим результат сличения блока образцов с эталонной реализацией
			return (divergences == 0);
		#endif
		/**
		 * Если накопленная сумма записанному образцу отвечает
		 */
		if(sum == block.checksum) {
			// Выполняем вывод итога сличения блока образцов
			::printf("  %-22s образцов %-7zu сумма совпала\n", block.name, checked);
			// Выводим результат сличения блока образцов
			return true;
		}
		// Выполняем вывод расхождения с записанным образцом
		::printf("  %-22s образцов %-7zu РАСХОЖДЕНИЕ: получено %016llx, записано %016llx\n",
		 block.name, checked, static_cast <unsigned long long> (sum), static_cast <unsigned long long> (block.checksum));
		// Выводим результат сличения блока образцов
		return false;
	}
	/**
	 * @brief Функция проверки средств размещения исполняемой памяти
	 *
	 * @return результат проверки средств размещения исполняемой памяти
	 *
	 */
	bool executable() noexcept {
		/**
		 * Если сборка выполняется для набора команд ARM64
		 */
		#if defined(__aarch64__) || defined(_M_ARM64)
			/**
			 * Машинный код сложения набора команд ARM64
			 *
			 * @details Заглушка открывается меткой цели перехода «bti c»:
			 *          расширение BTI требует, чтобы переход по адресу из
			 *          регистра приходил на метку, и OpenBSD правило это
			 *          для порождённого кода блюдёт - вход без метки валит
			 *          работу отказом «Illegal instruction». Процессоры,
			 *          расширения лишённые, исполняют команду как пустую.
			 *
			 */
			const uint8_t code[] = {0x5F, 0x24, 0x03, 0xD5, 0x00, 0x00, 0x01, 0x8B, 0xC0, 0x03, 0x5F, 0xD6};
		/**
		 * Если сборка выполняется для набора команд x86-64
		 */
		#elif defined(__x86_64__) || defined(_M_X64)
			/**
			 * Если соглашение о вызове принято системой Windows
			 *
			 * Набор команд один, а соглашения о вызове разные: Windows
			 * передаёт доводы целочисленные в rcx и rdx, а System V - в
			 * rdi и rsi, поэтому заглушка сложения пишется под каждое своя
			 */
			#if defined(_WIN32) || defined(_WIN64)
				// Машинный код сложения набора команд x86-64 соглашения Windows
				const uint8_t code[] = {0x48, 0x8D, 0x04, 0x11, 0xC3};
			/**
			 * Если соглашение о вызове принято System V
			 */
			#else
				// Машинный код сложения набора команд x86-64 соглашения System V
				const uint8_t code[] = {0x48, 0x8D, 0x04, 0x37, 0xC3};
			#endif
		/**
		 * Если сборка выполняется для прочих наборов команд
		 */
		#else
			// Выполняем вывод отсутствия машинного кода набора команд
			::printf("  исполняемая память     набор команд стенду неизвестен, проверка пропущена\n");
			// Выводим результат проверки средств размещения
			return true;
		#endif
		/**
		 * Если размещение исполняемой памяти сборкой не поддерживается
		 */
		#if defined(__aarch64__) || defined(_M_ARM64) || defined(__x86_64__) || defined(_M_X64)
			/**
			 * Если размещение исполняемой памяти сборкой не поддерживается
			 */
			if(!regex::assembly_t::available()) {
				// Выполняем вывод отсутствия поддержки исполняемой памяти
				::printf("  исполняемая память     сборкой не поддерживается, проверка пропущена\n");
				// Выводим результат проверки средств размещения
				return true;
			}
			// Создаём объект исполняемой памяти кодогенерации
			regex::assembly_t assembly;
			/**
			 * Если размещение участка исполняемой памяти не выполнено
			 */
			if(!assembly.allocate(sizeof(code))) {
				// Выполняем вывод отказа размещения участка памяти
				::printf("  исполняемая память     ОТКАЗ размещения участка\n");
				// Выводим результат проверки средств размещения
				return false;
			}
			/**
			 * Если наполнение участка машинным кодом не выполнено
			 */
			if(!assembly.fill(code, sizeof(code))) {
				// Выполняем вывод отказа наполнения участка памяти
				::printf("  исполняемая память     ОТКАЗ наполнения участка\n");
				// Выводим результат проверки средств размещения
				return false;
			}
			/**
			 * Если разрешение исполнения участка не выполнено
			 */
			if(!assembly.commit()) {
				// Выполняем вывод отказа разрешения исполнения
				::printf("  исполняемая память     ОТКАЗ разрешения исполнения\n");
				// Выводим результат проверки средств размещения
				return false;
			}
			// Получаем вызов размещённого машинного кода
			uint64_t (* const adder) (uint64_t, uint64_t) = reinterpret_cast <uint64_t (*) (uint64_t, uint64_t)> (const_cast <void *> (assembly.entry()));
			// Получаем итог исполнения размещённого машинного кода
			const uint64_t result = adder(40, 2);
			/**
			 * Если итог исполнения ожидаемому не отвечает
			 */
			if(result != 42) {
				// Выполняем вывод расхождения итога исполнения
				::printf("  исполняемая память     РАСХОЖДЕНИЕ итога: получено %llu, ожидалось 42\n", static_cast <unsigned long long> (result));
				// Выводим результат проверки средств размещения
				return false;
			}
			// Выполняем вывод итога проверки средств размещения
			::printf("  исполняемая память     размещение, наполнение и исполнение выполнены\n");
			// Выводим результат проверки средств размещения
			return true;
		#endif
	}
	/**
	 * @brief Функция проверки порождения машинного кода
	 *
	 * @return результат проверки порождения машинного кода
	 *
	 */
	bool generation() noexcept {
		/**
		 * Если порождение машинного кода сборкой не поддерживается
		 */
		if(!regex::emitter_t::available() || !regex::assembly_t::available()) {
			// Выполняем вывод отсутствия поддержки порождения машинного кода
			::printf("  порождение кода        набором команд не поддерживается, проверка пропущена\n");
			// Выводим результат проверки порождения машинного кода
			return true;
		}
		// Подписываемся на перечисление регистров соглашения о вызове
		using reg_t = regex::emitter_t::reg_t;
		// Создаём объект порождения машинного кода
		regex::emitter_t emitter;
		/**
		 * Выполняем размещение входа в порождаемую подпрограмму
		 *
		 * @details Вход обязателен, хотя ни кадр вызова, ни оберегаемые регистры
		 *          заглушке этой не нужны: набор команд ARM64 размещает входом
		 *          метку цели перехода, без какой система OpenBSD исполнять
		 *          порождённый код отказывается.
		 *
		 */
		emitter.prologue(0);
		// Выполняем размещение записи числа в регистр итога
		emitter.move(reg_t::RESULT, static_cast <uint64_t> (0x0123456789ABCDEFull));
		// Выполняем размещение выхода из порождаемой подпрограммы
		emitter.epilogue(0);
		// Выполняем размещение завершения вызова
		emitter.ret();
		/**
		 * Если разрешение отложенных переходов не выполнено
		 */
		if(!emitter.resolve()) {
			// Выполняем вывод отказа разрешения отложенных переходов
			::printf("  порождение кода        ОТКАЗ разрешения переходов\n");
			// Выводим результат проверки порождения машинного кода
			return false;
		}
		// Создаём объект исполняемой памяти кодогенерации
		regex::assembly_t assembly;
		/**
		 * Если размещение порождённого кода не выполнено
		 */
		if(!assembly.allocate(emitter.length()) || !assembly.fill(emitter.code().data(), emitter.length()) || !assembly.commit()) {
			// Выполняем вывод отказа размещения порождённого кода
			::printf("  порождение кода        ОТКАЗ размещения порождённого кода\n");
			// Выводим результат проверки порождения машинного кода
			return false;
		}
		// Получаем вызов порождённого машинного кода
		uint64_t (* const constant) () = reinterpret_cast <uint64_t (*) ()> (const_cast <void *> (assembly.entry()));
		// Получаем итог исполнения порождённого машинного кода
		const uint64_t result = constant();
		/**
		 * Если итог исполнения ожидаемому не отвечает
		 */
		if(result != 0x0123456789ABCDEFull) {
			// Выполняем вывод расхождения итога исполнения
			::printf("  порождение кода        РАСХОЖДЕНИЕ итога: получено %016llx\n", static_cast <unsigned long long> (result));
			// Выводим результат проверки порождения машинного кода
			return false;
		}
		// Выполняем вывод итога проверки порождения машинного кода
		::printf("  порождение кода        порождение и исполнение выполнены\n");
		// Выводим результат проверки порождения машинного кода
		return true;
	}
	/**
	 * @brief Функция проверки сохранности регистров, соглашением оберегаемых
	 *
	 * @details Порождаемый сопоставитель занимает регистры, сохранность каких
	 *          соглашение о вызове возлагает на сторону вызываемую, а сохраняет
	 *          их вход в сопоставитель. Набор этих регистров у каждого набора
	 *          команд свой: отображение ARM64 обходится регистрами, оберегаемыми
	 *          вызывающим, и сохранять входу там нечего вовсе, тогда как
	 *          в x86-64 доводы вызова занимают почти все такие, и второе
	 *          промежуточное значение, значение сохраняемое и адрес возврата
	 *          отведены оберегаемым вызываемым. Оттого недостача сохранения
	 *          на машине ARM64 не наблюдаема вовсе, а на машине x86-64 сносит
	 *          вызывающую сторону, и то не всякий раз - смотря какой регистр
	 *          вызывающему понадобился.
	 *
	 * @return результат проверки сохранности регистров
	 *
	 */
	bool preservation() noexcept {
		#if !defined(__x86_64__) && !defined(_M_X64)
			// Выполняем вывод неприменимости проверки сохранности регистров
			::printf("  сохранность регистров  отображение регистров оберегаемых не занимает, проверка неприменима\n");
			// Выводим результат проверки сохранности регистров
			return true;
		#else
			/**
			 * Если порождение машинного кода набором команд не поддерживается
			 */
			if(!regex::emitter_t::available() || !regex::assembly_t::available()) {
				// Выполняем вывод пропуска проверки сохранности регистров
				::printf("  сохранность регистров  набором команд не поддерживается, проверка пропущена\n");
				// Выводим результат проверки сохранности регистров
				return true;
			}
			// Подписываемся на перечисление регистров соглашения о вызове
			using reg_t = regex::emitter_t::reg_t;
			// Создаём объект порождения машинного кода
			regex::emitter_t emitter;
			// Выполняем размещение входа в порождаемый сопоставитель
			emitter.prologue(0);
			/**
			 * Выполняем занятие регистров, сопоставителю отведённых
			 *
			 * @details Занимаются в точности те регистры, какие занимает
			 *          порождение сопоставителя выражения: второе промежуточное
			 *          значение, значение сохраняемое и адрес возврата.
			 *
			 */
			emitter.move(reg_t::SPARE, static_cast <uint64_t> (0xA1A1A1A1A1A1A1A1ull));
			emitter.move(reg_t::KEEPER, static_cast <uint64_t> (0xB2B2B2B2B2B2B2B2ull));
			emitter.move(reg_t::LINK, static_cast <uint64_t> (0xC3C3C3C3C3C3C3C3ull));
			// Выполняем размещение выхода из порождаемого сопоставителя
			emitter.epilogue(0);
			// Выполняем установку итога исполнения порождённого кода
			emitter.move(reg_t::RESULT, static_cast <uint64_t> (0));
			// Выполняем размещение завершения вызова
			emitter.ret();
			/**
			 * Если порождение машинного кода не выполнено
			 */
			if(!emitter.resolve() || emitter.failed()) {
				// Выполняем вывод отказа порождения машинного кода
				::printf("  сохранность регистров  ОТКАЗ порождения машинного кода\n");
				// Выводим результат проверки сохранности регистров
				return false;
			}
			// Создаём объект исполняемой памяти кодогенерации
			regex::assembly_t assembly;
			/**
			 * Если размещение порождённого кода не выполнено
			 */
			if(!assembly.allocate(emitter.length()) || !assembly.fill(emitter.code().data(), emitter.length()) || !assembly.commit()) {
				// Выполняем вывод отказа размещения порождённого кода
				::printf("  сохранность регистров  ОТКАЗ размещения порождённого кода\n");
				// Выводим результат проверки сохранности регистров
				return false;
			}
			// Создаём набор границ совпадения порождённого сопоставителя
			size_t bounds[2] = {0, 0};
			// Создаём таблицу адресов обстановки исполнения
			const void * context[1] = {nullptr};
			// Получаем сумму примет оберегаемых регистров по возвращении
			const uint64_t received = awh_regex_preserving(assembly.entry(), "", 0, 0, bounds, context);
			/**
			 * Получаем сумму примет, в оберегаемые регистры укладываемых
			 */
			#if defined(_WIN32)
				const uint64_t expected = (0x1122334455667788ull ^ 0x99AABBCCDDEEFF00ull ^
				 0x0F1E2D3C4B5A6978ull ^ 0x2468ACE013579BDFull ^ 0x76543210FEDCBA98ull);
			#else
				const uint64_t expected = (0x1122334455667788ull ^ 0x99AABBCCDDEEFF00ull ^ 0x0F1E2D3C4B5A6978ull);
			#endif
			/**
			 * Если сумма примет оберегаемых регистров не совпала
			 */
			if(received != expected) {
				// Выполняем вывод затирания оберегаемых регистров
				::printf("  сохранность регистров  ЗАТЁРТЫ: ожидалось %016llx, получено %016llx\n",
				 static_cast <unsigned long long> (expected), static_cast <unsigned long long> (received));
				// Выводим результат проверки сохранности регистров
				return false;
			}
			// Выполняем вывод итога проверки сохранности регистров
			::printf("  сохранность регистров  оберегаемые вызовом регистры сохранены\n");
			// Выводим результат проверки сохранности регистров
			return true;
		#endif
	}
};

/**
 * @brief Точка входа переносимого стенда проверки
 *
 * @param argc количество доводов командной строки
 * @param argv набор доводов командной строки
 * @return     код завершения стенда проверки
 *
 */
/**
 * @brief Функция сличения порождённого машинного кода с исполнением программы
 *
 * @details Дымовая проверка порождения доказывает работоспособность связки
 *          «порождатель - исполняемая память - вызов», но самого сопоставителя
 *          не проверяет вовсе. Сличение порождает выражения и тексты и сверяет
 *          границы, порождённым кодом установленные, с границами исполнения
 *          программы: расхождение означает, что порождение на этой платформе
 *          неверно, тогда как записанных сумм такая проверка не требует -
 *          обе стороны сличения исполняются на самой платформе.
 *
 * @return результат сличения порождённого машинного кода
 *
 */
bool matching(const bool utf) noexcept {
	/**
	 * Если порождение машинного кода набором команд не поддерживается
	 */
	if(!regex::emitter_t::available() || !regex::assembly_t::available()) {
		// Выполняем вывод пропуска сличения порождённого кода
		::printf("  сличение сопоставителя набором команд не поддерживается, проверка пропущена\n");
		// Выводим результат сличения порождённого машинного кода
		return true;
	}
	// Создаём источник псевдослучайных значений
	mt19937 gen(20260807);
	// Создаём объект движка регулярных выражений
	regex::engine_t engine;
	// Количество выражений, кодогенерацию получивших
	size_t accepted = 0;
	// Количество выполненных сличений границ совпадения
	size_t compared = 0;
	// Количество расхождений порождённого кода с исполнением программы
	size_t divergences = 0;
	/**
	 * Выполняем обход порождаемых образцов сличения
	 */
	for(size_t sample = 0; sample < 4000; sample++) {
		// Получаем порождённое регулярное выражение
		const string expression = pattern(gen);
		// Создаём собираемое регулярное выражение
		regex::expression_t compiled;
		/**
		 * Если сборка регулярного выражения не выполнена
		 */
		if(!engine.build(expression, (utf ? static_cast <uint32_t> (regex::flag_t::UTF) : 0), compiled))
			// Переходим к образцу следующему
			continue;
		// Создаём объект порождения машинного кода выражения
		regex::codegen_t codegen;
		/**
		 * Если порождение машинного кода выражения не выполнено
		 */
		if(!codegen.compile(compiled.forward))
			// Переходим к образцу следующему
			continue;
		// Увеличиваем количество выражений, кодогенерацию получивших
		accepted++;
		/**
		 * Выполняем обход текстов сопоставления образца
		 */
		for(size_t attempt = 0; attempt < 8; attempt++) {
			// Получаем порождённый текст сопоставления
			const string text = subject(gen, 64, utf);
			// Создаём набор границ, порождённым кодом установленных
			vector <pair <size_t, size_t>> received;
			// Создаём набор границ, исполнением программы установленных
			vector <pair <size_t, size_t>> expected;
			// Выполняем сопоставление порождённым машинным кодом
			const bool one = codegen.exec(text, 0, received);
			// Выполняем сопоставление исполнением программы
			const bool two = engine.exec(compiled, text, 0, expected);
			// Увеличиваем количество выполненных сличений
			compared++;
			/**
			 * Если вердикты сопоставления расходятся
			 */
			if(one != two) {
				// Увеличиваем количество обнаруженных расхождений
				divergences++;
				// Переходим к тексту следующему
				continue;
			}
			/**
			 * Если совпадение обнаружено обеими сторонами сличения
			 */
			if(one && (received != expected))
				// Увеличиваем количество обнаруженных расхождений
				divergences++;
		}
	}
	/**
	 * Если расхождения порождённого кода с исполнением программы обнаружены
	 */
	if(divergences > 0) {
		// Выполняем вывод количества обнаруженных расхождений
		::printf("  сличение сопоставителя%s РАСХОЖДЕНИЙ %zu из %zu сличений\n", (utf ? " UTF-8" : ""), divergences, compared);
		// Выводим результат сличения порождённого машинного кода
		return false;
	}
	// Выполняем вывод итога сличения порождённого машинного кода
	::printf("  сличение сопоставителя%s выражений %zu, сличений %zu, расхождений нет\n", (utf ? " UTF-8" : ""), accepted, compared);
	// Выводим результат сличения порождённого машинного кода
	return true;
}
/**
 * @brief Набор выражений проверки хранилища собранных выражений
 *
 * @details Набор покрывает построения, отличающиеся устройством записи:
 *          классы символов, свойства Юникода, ссылки на захваченные группы,
 *          проверки окружения, атомарные группы и рекурсивные вызовы.
 *
 */
static const char * const STORED[] = {
	"[a-z]+", "[^0-9]{2,5}", "\\p{L}+", "\\d{1,3}(?:\\.\\d{1,3}){3}",
	"(?<word>[a-z]+) \\k<word>", "(?=[a-z])[a-z0-9]+", "(?<![0-9])[a-z]+",
	"(?>a+)b", "\\b[A-Z][a-z]+\\b", "^(?:GET|POST) /[a-z/]*$",
	"([a-z]+)@([a-z]+)\\.[a-z]{2,4}", "\\((?:[^()]++|(?R))*\\)",
	"[[:alpha:]][[:alnum:]]*", "(?i)\\p{Cyrillic}+", "a*?b+?c??"
};

/**
 * @brief Набор текстов сличения выражений хранилища
 *
 */
static const char * const SUBJECTS[] = {
	"", "a", "abc", "aaa 123 zzz", "GET /index", "POST /a/b", "forman@anyks.com",
	"192.168.5.150", "Слово слово", "word word", "(вложено (ещё) раз)",
	"AZaz09", "Заголовок", "aaab", "   ", "-42.5e3"
};

/**
 * @brief Функция сборки набора выражений проверки хранилища
 *
 * @param regexp объект работы с регулярными выражениями
 * @param result набор собранных выражений
 *
 */
static void collect(const awh::regexp_t & regexp, std::vector <awh::regex::storage_t::exp_t> & result) noexcept {
	/**
	 * Выполняем перебор набора выражений проверки хранилища
	 */
	for(const char * pattern : STORED) {
		// Выполняем сборку регулярного выражения
		/**
		 * Выполняем сборку регулярного выражения
		 *
		 * @details Режим разбора UTF-8 набору не назначается намеренно:
		 *          порождение машинного кода к нему неприменимо, поскольку
		 *          порождаемый код сопоставляет байты, а под этим режимом
		 *          программа сопоставляет символы целиком. Без режима же набор
		 *          покрывает и запись свойств Юникода, и запись порождённого
		 *          кода разом.
		 */
		const auto exp = regexp.build(pattern, {awh::regexp_t::flag_t::DUPNAMES, awh::regexp_t::flag_t::JIT});
		/**
		 * Если сборка регулярного выражения выполнена
		 */
		if(exp)
			// Выполняем добавление собранного выражения в набор
			result.push_back(exp);
	}
}
/**
 * @brief Функция подсчёта выражений с готовым порождённым сопоставителем
 *
 * @param expressions набор собранных выражений
 * @return            количество выражений с готовым сопоставителем
 *
 */
static size_t machined(const std::vector <awh::regex::storage_t::exp_t> & expressions) noexcept {
	// Количество выражений с готовым порождённым сопоставителем
	size_t result = 0;
	/**
	 * Выполняем перебор набора собранных выражений
	 */
	for(const auto & expression : expressions) {
		/**
		 * Если порождённый сопоставитель выражения готов
		 */
		if(expression && expression->machine && expression->machine->ready())
			// Выполняем увеличение количества выражений с сопоставителем
			result++;
	}
	// Выводим количество выражений с готовым сопоставителем
	return result;
}
/**
 * @brief Функция сличения поведения набора выражений
 *
 * @param regexp   объект работы с регулярными выражениями
 * @param fresh    набор выражений, собранных начисто
 * @param restored набор выражений, восстановленных из записи
 * @return         количество обнаруженных расхождений
 *
 */
static size_t compare(const awh::regexp_t & regexp, const std::vector <awh::regex::storage_t::exp_t> & fresh,
 const std::vector <awh::regex::storage_t::exp_t> & restored) noexcept {
	// Количество обнаруженных расхождений
	size_t result = 0;
	/**
	 * Выполняем перебор набора восстановленных выражений
	 */
	for(size_t i = 0; i < fresh.size(); i++) {
		/**
		 * Выполняем перебор набора текстов сличения
		 */
		for(const char * subject : SUBJECTS) {
			/**
			 * Если границы совпадения выражений расходятся
			 */
			if(regexp.match(subject, fresh.at(i)) != regexp.match(subject, restored.at(i))) {
				// Выполняем увеличение количества обнаруженных расхождений
				result++;
				// Выполняем вывод сообщения об обнаруженном расхождении
				::printf("  хранилище выражений    РАСХОЖДЕНИЕ: \"%s\" на тексте \"%s\"\n", STORED[i], subject);
			}
		}
	}
	// Выводим количество обнаруженных расхождений
	return result;
}
/**
 * @brief Функция проверки хранилища собранных выражений
 *
 * @param write путь записи хранилища, порождаемой стендом
 * @param read  путь записи хранилища, порождённой иной машиной
 * @return      результат проверки хранилища собранных выражений
 *
 * @details Наборы программы пишутся образом памяти, поэтому запись зависит
 *          от порядка байтов машины и размещения полей структур. Проверка
 *          удостоверяет, что запись, порождённая машиной стенда, ею же и
 *          восстанавливается, а запись, порождённая машиной иной, либо
 *          восстанавливается в точности, либо отвергается опознанием
 *          устройства - но не читается неверно.
 *
 */
static bool storing(const char * write, const char * read) noexcept {
	// Создаём объект работы с регулярными выражениями
	const awh::regexp_t regexp;
	// Создаём объект хранилища собранных выражений
	awh::regex::storage_t storage;
	/**
	 * Выполняем установку доверия порождённому коду записи
	 *
	 * @details Порождённый машинный код записи исполняется, а не разбирается,
	 *          отчего берётся он лишь при установленном признаке доверия,
	 *          снятом по умолчанию: без него восстановление порождает код
	 *          заново, и путь восстановления его из записи проверка не
	 *          проходила бы вовсе. Запись здесь изготовлена самой проверкой,
	 *          поэтому доверие ей правомерно.
	 *
	 */
	storage.trusted(true);
	// Набор собранных начисто выражений
	std::vector <awh::regex::storage_t::exp_t> fresh;
	// Выполняем сборку набора выражений проверки хранилища
	collect(regexp, fresh);
	/**
	 * Если сборка набора выражений не выполнена
	 */
	if(fresh.empty()) {
		// Выполняем вывод сообщения об отказе сборки набора выражений
		::printf("  хранилище выражений    ОТКАЗ сборки набора выражений\n");
		// Выводим результат проверки хранилища
		return false;
	}
	// Запись хранилища собранных выражений
	std::string record;
	/**
	 * Если запись собранных выражений не выполнена
	 */
	if(!storage.save(fresh, record)) {
		// Выполняем вывод сообщения об отказе записи собранных выражений
		::printf("  хранилище выражений    ОТКАЗ записи, код %u\n", static_cast <uint32_t> (storage.error()));
		// Выводим результат проверки хранилища
		return false;
	}
	/**
	 * Если запись подлежит сохранению в файл
	 */
	if(write != nullptr) {
		// Выполняем открытие файла записи хранилища
		FILE * file = ::fopen(write, "wb");
		/**
		 * Если открытие файла записи хранилища не выполнено
		 */
		if(file == nullptr) {
			// Выполняем вывод сообщения об отказе открытия файла записи
			::printf("  хранилище выражений    ОТКАЗ открытия файла \"%s\"\n", write);
			// Выводим результат проверки хранилища
			return false;
		}
		// Выполняем запись хранилища в файл
		const size_t written = ::fwrite(record.data(), 1, record.size(), file);
		// Выполняем закрытие файла записи хранилища
		::fclose(file);
		// Выполняем вывод итога сохранения записи хранилища
		::printf("  хранилище выражений    записано %zu байт в \"%s\"\n", written, write);
		// Выводим результат проверки хранилища
		return (written == record.size());
	}
	// Набор восстановленных выражений
	std::vector <awh::regex::storage_t::exp_t> restored;
	/**
	 * Если восстановление собранных выражений не выполнено
	 */
	if(!storage.load(record, restored)) {
		// Выполняем вывод сообщения об отказе восстановления выражений
		::printf("  хранилище выражений    ОТКАЗ восстановления, код %u\n", static_cast <uint32_t> (storage.error()));
		// Выводим результат проверки хранилища
		return false;
	}
	/**
	 * Если количество восстановленных выражений набору не отвечает
	 */
	if(restored.size() != fresh.size()) {
		// Выполняем вывод сообщения о расхождении количества выражений
		::printf("  хранилище выражений    восстановлено %zu выражений вместо %zu\n", restored.size(), fresh.size());
		// Выводим результат проверки хранилища
		return false;
	}
	// Выполняем сличение поведения восстановленных выражений
	const size_t divergences = compare(regexp, fresh, restored);
	/**
	 * Если сличение поведения расхождения обнаружило
	 */
	if(divergences > 0) {
		// Выполняем вывод итога сличения восстановленных выражений
		::printf("  хранилище выражений    РАСХОЖДЕНИЙ %zu\n", divergences);
		// Выводим результат проверки хранилища
		return false;
	}
	// Выполняем вывод итога проверки записи, порождённой стендом
	::printf("  хранилище выражений    %zu выражений, %zu байт, восстановление точное\n",
	 fresh.size(), record.size());
	/**
	 * Выполняем вывод итога восстановления порождённого машинного кода
	 *
	 * @details Код записывается вместе с выражениями и восстанавливается как
	 *          есть, минуя порождение заново. Количество восстановленных
	 *          сопоставителей обязано совпадать с количеством порождённых:
	 *          запись порождена той же машиной, набор команд её тот же.
	 *
	 */
	::printf("  порождённый код записи %zu сопоставителей порождено, %zu восстановлено\n",
	 machined(fresh), machined(restored));
	/**
	 * Если запись иной машины проверке не подлежит
	 */
	if(read == nullptr)
		// Выводим результат проверки хранилища
		return true;
	// Выполняем открытие файла записи иной машины
	FILE * file = ::fopen(read, "rb");
	/**
	 * Если открытие файла записи иной машины не выполнено
	 */
	if(file == nullptr) {
		// Выполняем вывод сообщения об отсутствии записи иной машины
		::printf("  запись иной машины     файл \"%s\" не открыт, проверка пропущена\n", read);
		// Выводим результат проверки хранилища
		return true;
	}
	// Содержимое записи иной машины
	std::string foreign;
	// Участок чтения содержимого записи
	char buffer[4096];
	// Количество прочитанных байтов участка
	size_t taken = 0;
	/**
	 * Выполняем чтение содержимого записи иной машины
	 */
	while((taken = ::fread(buffer, 1, sizeof(buffer), file)) > 0)
		// Выполняем добавление прочитанного участка
		foreign.append(buffer, taken);
	// Выполняем закрытие файла записи иной машины
	::fclose(file);
	// Набор выражений, восстановленных из записи иной машины
	std::vector <awh::regex::storage_t::exp_t> imported;
	/**
	 * Если восстановление записи иной машины не выполнено
	 */
	if(!storage.load(foreign, imported)) {
		/**
		 * Если запись отвергнута опознанием устройства машины
		 */
		if(storage.error() == awh::regex::storage_error_t::BAD_PLATFORM) {
			// Выполняем вывод итога проверки записи иной машины
			::printf("  запись иной машины     отвергнута опознанием устройства, как и положено\n");
			// Выводим результат проверки хранилища
			return true;
		}
		// Выполняем вывод сообщения об отказе восстановления записи
		::printf("  запись иной машины     ОТКАЗ восстановления, код %u\n", static_cast <uint32_t> (storage.error()));
		// Выводим результат проверки хранилища
		return false;
	}
	/**
	 * Если количество восстановленных выражений набору не отвечает
	 */
	if(imported.size() != fresh.size()) {
		// Выполняем вывод сообщения о расхождении количества выражений
		::printf("  запись иной машины     восстановлено %zu выражений вместо %zu\n", imported.size(), fresh.size());
		// Выводим результат проверки хранилища
		return false;
	}
	/**
	 * Если сличение поведения расхождения обнаружило
	 */
	if(compare(regexp, fresh, imported) > 0) {
		// Выполняем вывод итога сличения выражений записи иной машины
		::printf("  запись иной машины     РАСХОЖДЕНИЯ поведения\n");
		// Выводим результат проверки хранилища
		return false;
	}
	/**
	 * Выполняем вывод итога восстановления кода записи иной машины
	 *
	 * @details Порождённый код годен лишь набору команд, для какого порождён.
	 *          Запись машины с набором иным кода не отдаёт, и сопоставитель
	 *          порождается заново, - поэтому количество восстановленных
	 *          сопоставителей значения не имеет, а имеет значение точность
	 *          сопоставления, сличённая выше.
	 *
	 */
	::printf("  запись иной машины     %zu байт, восстановление точное, сопоставителей %zu\n",
	 foreign.size(), machined(imported));
	// Выводим результат проверки хранилища
	return true;
}
int main(int argc, char ** argv) {
	/**
	 * Выполняем отмену буферизации вывода стенда
	 *
	 * @details Вывод, направленный не на терминал, буферизуется целиком и при
	 *          падении теряется весь: стенд, оборвавшийся на середине, выводит
	 *          пустоту взамен указания на место обрыва. Отмена буферизации
	 *          стоит вывода посимвольно, а стенд выводит две дюжины строк.
	 *
	 */
	::setvbuf(stdout, nullptr, _IONBF, 0);
	// Название блока образцов, подлежащего подробному выводу
	const char * verbose = nullptr;
	// Путь записи хранилища, порождаемой стендом, и путь записи иной машины
	const char * write = nullptr, * read = nullptr;
	/**
	 * Выполняем разбор параметров запуска стенда проверки
	 */
	for(int i = 1; i < argc; i++) {
		/**
		 * Если параметр задаёт путь записи, порождаемой стендом
		 */
		if(::strncmp(argv[i], "--write=", 8) == 0)
			// Выполняем установку пути записи, порождаемой стендом
			write = (argv[i] + 8);
		/**
		 * Если параметр задаёт путь записи иной машины
		 */
		else if(::strncmp(argv[i], "--read=", 7) == 0)
			// Выполняем установку пути записи иной машины
			read = (argv[i] + 7);
		// Выполняем установку названия блока подробного вывода
		else verbose = argv[i];
	}
	/**
	 * Если стенд запущен ради порождения записи хранилища
	 */
	if(write != nullptr)
		// Выводим результат порождения записи хранилища
		return (storing(write, nullptr) ? 0 : 1);
	// Выполняем вывод заголовка стенда проверки
	::printf("Переносимый стенд проверки модуля регулярных выражений\n\n");
	// Выполняем вывод разрядности указателя платформы
	::printf("  разрядность указателя  %zu разрядов\n", (sizeof(void *) * 8));
	// Выполняем вывод порядка байтов платформы
	::printf("  порядок байтов         %s\n", ((*reinterpret_cast <const uint16_t *> ("\x01\x02") == 0x0201) ? "младший впереди" : "старший впереди"));
	// Выполняем вывод знаковости обычного символа
	::printf("  обычный символ         %s\n\n", ((static_cast <int> (static_cast <char> (0x80)) < 0) ? "знаковый" : "беззнаковый"));
	// Флаг успешного прохождения стенда проверки
	bool passed = true;
	/**
	 * Выполняем обход блоков образцов сличения
	 */
	for(auto & block : BLOCKS) {
		/**
		 * Если блок образцов подлежит подробному выводу
		 */
		const bool detailed = ((verbose != nullptr) && (::strcmp(verbose, block.name) == 0));
		/**
		 * Если сличение блока образцов расхождение обнаружило
		 */
		if(!verify(block, detailed))
			// Выполняем сброс флага успешного прохождения стенда
			passed = false;
	}
	// Выполняем вывод разделителя разделов стенда проверки
	::printf("\n");
	/**
	 * Если проверка средств размещения исполняемой памяти не пройдена
	 */
	if(!executable())
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	/**
	 * Если проверка порождения машинного кода не пройдена
	 */
	if(!matching(false))
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	/**
	 * Если сличение порождённого кода в режиме разбора UTF-8 не пройдено
	 *
	 * @details Режим этот порождает последовательности команд, режиму обычному
	 *          не свойственные: выход позиции начала попытки на границу символа.
	 *          Ведётся сличение по текстам с символами вне ASCII - на текстах
	 *          одних лишь символов ASCII последовательности эти ходу не имеют.
	 *
	 */
	if(!matching(true))
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	/**
	 * Если проверка порождения машинного кода не пройдена
	 */
	if(!generation())
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	/**
	 * Если проверка сохранности оберегаемых регистров не пройдена
	 */
	if(!preservation())
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	/**
	 * Если проверка хранилища собранных выражений не пройдена
	 */
	if(!storing(nullptr, read))
		// Выполняем сброс флага успешного прохождения стенда
		passed = false;
	// Выполняем вывод итога стенда проверки
	::printf("\n%s\n", (passed ? "Стенд пройден" : "Стенд НЕ пройден"));
	// Выводим код завершения стенда проверки
	return (passed ? 0 : 1);
}
