/**
 * @brief Пространство имён проверок этого файла
 *
 * @note Держится оно безымянным намеренно: проверки кодеков собираются одной
 *       программою, и одноимённые построения разных файлов иначе сходятся в
 *       одно, порождая порчу вдали от места её причины
 *
 */
namespace {
	/**
	 * @brief Объект журнала проверок с отключённым выводом
	 *
	 * @details Вывод отключается назначением пустого перечня приёмников: отказы
	 *          разбора проверки наводят намеренно, и журнал их засорял бы выдачу
	 *
	 */
	struct Silent {
		/**
		 * @brief Функция получения объекта фреймворка проверок
		 *
		 * @details Объект заводится статикою местною, а не общею файла: заведение его
		 *          порядком построения статики оканчивается падением ещё до входа в
		 *          проверки, ибо фреймворк сам опирается на статику из библиотеки
		 *
		 * @return объект фреймворка проверок
		 *
		 */
		static const awh::fmk_t & framework() noexcept {
			// Объект фреймворка проверок
			static awh::fmk_t fmk;
			// Выводим объект фреймворка проверок
			return fmk;
		}
		// Объект журнала проверок
		awh::log_t log;
		/**
		 * @brief Конструктор
		 *
		 */
		Silent() noexcept : log(&Silent::framework()) {
			// Выполняем отключение вывода логов
			this->log.mode({});
		}
	};
	/**
	 * @brief Функция получения объекта журнала проверок
	 *
	 * @return объект журнала проверок
	 *
	 */
	const awh::log_t * logger() noexcept {
		// Объект журнала проверок
		static Silent silent;
		// Выводим объект журнала проверок
		return &silent.log;
	}
}

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Количество прогонов замера
 *
 */
static constexpr size_t PASSES = 5;

/**
 * @brief Описание сценария замера пропускной способности
 *
 */
typedef struct Sample {
	// Название сценария замера
	const char * name;
	// Текст регулярного выражения сценария
	const char * pattern;
	// Повторяемая часть текста сопоставления
	const char * chunk;
	// Количество повторений части текста сопоставления
	size_t repeats;
} sample_t;

/**
 * @brief Набор сценариев замера пропускной способности
 *
 */
static const sample_t SAMPLES[] = {
	{"класс-простой",   "[a-z]+",                          "GET /index-4711 abc user_name value ", 20000},
	{"класс-широкий",   "[a-zA-Z0-9_.:-]+",                "GET /index-4711 abc user_name value ", 20000},
	{"число-длинное",   "[0-9]{3,8}",                      "код 4711 размер 819200 время 42 ",     20000},
	{"чередование",     "(?:GET|POST|PUT|DELETE) /[a-z/]+", "POST /api/v2/records HTTP/1.1 ",       20000},
	{"захват-пары",     "([a-z]+)-([0-9]+)",               "поле index-4711 поле code-200 ",        20000},
	{"привязка-строки", "^[A-Z][a-z]+ [0-9]+$",            "Record 4711\n",                         20000},
	{"адрес-сети",      "[0-9]{1,3}(?:\\.[0-9]{1,3}){3}",  "узел 192.168.5.150 отвечает ",          20000},
	{"ленивый-ряд",     "\"[^\"]*?\"",                     "поле \"значение поля\" далее ",         20000}
};

/**
 * @brief Функция извлечения показания часов в миллисекундах
 *
 * @return показание часов в миллисекундах
 *
 */
static double clocking() noexcept {
	// Выводим показание часов в миллисекундах
	return (static_cast <double> (chrono::duration_cast <chrono::nanoseconds> (
	 chrono::steady_clock::now().time_since_epoch()).count()) / 1000000.0);
}
/**
 * @brief Функция замера прохода текста повторными сопоставлениями
 *
 * @param regexp объект работы с регулярными выражениями
 * @param exp    собранное регулярное выражение
 * @param text   текст сопоставления
 * @param found  количество обнаруженных совпадений
 * @return       наименьший расход прохода текста в миллисекундах
 *
 * @details Текст проходится повторными вызовами от очередной позиции - так
 *          устроен разбор журналов, - а замер берётся наименьшим из прогонов.
 *
 */
static double sweep(const regexp_t & regexp, const regexp_t::exp_t & exp, const string & text, size_t & found) noexcept {
	// Наименьший расход прохода текста
	double result = 0.0;
	/**
	 * Выполняем перебор прогонов замера прохода текста
	 */
	for(size_t pass = 0; pass < PASSES; pass++) {
		// Количество обнаруженных совпадений очередного прогона
		size_t count = 0;
		// Позиция очередного сопоставления в тексте
		size_t pos = 0;
		// Получаем показание часов на входе в проход текста
		const double started = clocking();
		/**
		 * Выполняем проход текста повторными сопоставлениями
		 */
		while(pos < text.size()) {
			// Выполняем сопоставление остатка текста
			const auto bounds = regexp.match(string_view(text).substr(pos), exp);
			/**
			 * Если совпадение в остатке текста не обнаружено
			 */
			if(bounds.empty())
				// Прекращаем проход текста сопоставления
				break;
			// Выполняем увеличение количества обнаруженных совпадений
			count++;
			/**
			 * Переходим за обнаруженное совпадение
			 *
			 * @details Совпадение пустое положения не изменяет, поэтому проход
			 *          продвигается на знак принудительно: иначе он не завершился бы.
			 */
			pos += ((bounds.front().second > bounds.front().first) ?
			 bounds.front().second : (bounds.front().first + 1));
		}
		// Получаем расход прохода текста
		const double spent = (clocking() - started);
		/**
		 * Если расход прохода прогона наименьший
		 */
		if((pass == 0) || (spent < result))
			// Выполняем установку наименьшего расхода прохода
			result = spent;
		// Выполняем установку количества обнаруженных совпадений
		found = count;
	}
	// Выводим наименьший расход прохода текста
	return result;
}
/**
 * @brief Функция входа в пробу выигрыша порождения машинного кода
 *
 * @return результат исполнения пробы
 *
 */
int main() {
	// Создаём объект работы с регулярными выражениями
	const regexp_t regexp(::logger());
	/**
	 * Если порождение машинного кода сборкой не поддерживается
	 */
	if(!regex::Emitter::available()) {
		// Выводим сообщение об отсутствии поддержки порождения кода
		::printf("порождение машинного кода набором команд не поддерживается\n");
		// Выводим результат исполнения пробы
		return 0;
	}
	// Выводим заголовок таблицы замера
	::printf("%-16s %14s %14s %8s %10s\n", "сценарий", "программа", "машинный код", "доля", "расхожд.");
	// Количество сценариев, порождения кода не получивших
	size_t declined = 0, divergences = 0;
	/**
	 * Выполняем перебор набора сценариев замера
	 */
	for(const auto & sample : SAMPLES) {
		// Текст сопоставления сценария
		string text;
		/**
		 * Выполняем сборку текста сопоставления сценария
		 */
		for(size_t i = 0; i < sample.repeats; i++)
			// Выполняем добавление повторяемой части текста
			text.append(sample.chunk);
		// Выполняем сборку выражения для исполнения программы
		const auto plain = regexp.build(sample.pattern, {});
		// Выполняем сборку выражения для порождения машинного кода
		const auto coded = regexp.build(sample.pattern, {regexp_t::flag_t::JIT});
		/**
		 * Если сборка выражений не выполнена
		 */
		if(!plain || !coded) {
			// Выводим сообщение об отказе сборки выражения сценария
			::printf("%-16s ОТКАЗ сборки выражения\n", sample.name);
			// Переходим к следующему сценарию замера
			continue;
		}
		// Количества совпадений, обнаруженных способами сопоставления
		size_t first = 0, second = 0;
		// Выполняем замер прохода текста исполнением программы
		const double interpreted = sweep(regexp, plain, text, first);
		// Выполняем замер прохода текста порождённым машинным кодом
		const double compiled = sweep(regexp, coded, text, second);
		/**
		 * Если количества обнаруженных совпадений расходятся
		 */
		if(first != second) {
			// Выполняем увеличение количества обнаруженных расхождений
			divergences++;
			// Выводим сообщение об обнаруженном расхождении
			::printf("%-16s РАСХОЖДЕНИЕ: совпадений %zu против %zu\n", sample.name, first, second);
			// Переходим к следующему сценарию замера
			continue;
		}
		/**
		 * Если выигрыша порождение кода не дало вовсе
		 *
		 * @details Кодогенерацию получает подмножество выражений, а не всякое
		 *          выражение: непринятое сопоставляется исполнением программы,
		 *          отчего показатели совпадают в пределах помехи.
		 *
		 */
		if((interpreted > 0.0) && (compiled > 0.0) && ((interpreted / compiled) < 1.1))
			// Выполняем увеличение количества сценариев без выигрыша
			declined++;
		// Выводим итог замера сценария
		::printf("%-16s %11.2f мс %11.2f мс %7.2fx %10s\n", sample.name, interpreted, compiled,
		 ((compiled > 0.0) ? (interpreted / compiled) : 0.0), "0");
	}
	// Выводим количество сценариев без выигрыша и обнаруженных расхождений
	::printf("\nсценариев без выигрыша: %zu, расхождений: %zu\n", declined, divergences);
	// Выводим результат исполнения пробы
	return (divergences > 0 ? 1 : 0);
}
