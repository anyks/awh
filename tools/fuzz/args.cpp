/**
 * @brief Учёт проделанной работы
 *
 */
typedef struct Statistic {
	// Число выполненных разборов
	uint64_t parsed;
	// Число разборов, отвеченных отказом
	uint64_t refused;
	// Число проверок честности отказа
	uint64_t honest;
	// Число проверок неподвижности круга
	uint64_t stable;
	// Число проверок старшинства источника
	uint64_t seniority;
	// Число проверок строгости разбора
	uint64_t strictness;
	// Число проверок согласия двух наречий подачи
	uint64_t streamed;
	// Число найденных расхождений
	uint64_t findings;
	/**
	 * @brief Конструктор
	 *
	 */
	Statistic() noexcept :
	 parsed(0), refused(0), honest(0), stable(0),
	 seniority(0), strictness(0), streamed(0), findings(0) {}
} stat_t;

/**
 * Виды записи настроек, какими выдаётся собранное дерево
 */
static const codec::Bridge::format_t FORMATS[] = {
	codec::Bridge::format_t::JSON, codec::Bridge::format_t::YAML,
	codec::Bridge::format_t::TOML, codec::Bridge::format_t::XML,
	codec::Bridge::format_t::INI
};

/**
 * Названия видов записи, на числе которых стоит ширина учёта
 */
static const char * const NAMES[] = {"JSON", "YAML", "TOML", "XML", "INI"};

/**
 * Число видов записи, договором связанное с перечнем названий
 *
 * @warning Ширина берётся ОТ ПЕРЕЧНЯ НАЗВАНИЙ, а не числом: вид, названия не
 *          получивший, ломает сборку, а не печатает пустую строку. Тот же довод
 *          стоит у ворошителя моста, где перечень причин отказа однажды отстал
 *          от перечня кодов и одна причина пропала из отчёта молча
 */
static constexpr size_t FORMATS_COUNT = (sizeof(NAMES) / sizeof(NAMES[0]));

/**
 * @brief Метод порождения случайного имени параметра
 *
 * @param engine источник случайных чисел
 * @return       порождённое имя
 *
 */
static string name(mt19937_64 & engine) noexcept {
	// Собираемое имя параметра
	string result = "";
	// Число звеньев имени
	const size_t links = (1 + (engine() % 3));
	// Выполняем перебор всех звеньев имени
	for(size_t i = 0; i < links; i++){
		// Если звено не первое, ставим разделитель
		if(i > 0)
			// Выполняем добавление разделителя звеньев
			result.append(1, '.');
		// Длина звена имени
		const size_t length = (1 + (engine() % 6));
		// Выполняем перебор всех знаков звена
		for(size_t j = 0; j < length; j++){
			/**
			 * Знаки имени берутся из набора, доводу запуска годного, но
			 * НЕ безобидного: тильда и косая черта суть знаки отменяющей записи
			 * оси хранения, и имя, их несущее, стережёт перевод имени в путь
			 */
			static const char LETTERS[] = "abcdefghijklmnopqrstuvwxyz~/_-";
			// Выполняем добавление знака имени
			result.append(1, LETTERS[engine() % (sizeof(LETTERS) - 1)]);
		}
	}
	// Выводим порождённое имя параметра
	return result;
}

/**
 * @brief Метод порождения случайного значения параметра
 *
 * @param engine источник случайных чисел
 * @return       порождённое значение
 *
 */
static string value(mt19937_64 & engine) noexcept {
	// Определяем вид порождаемого значения
	switch(engine() % 8){
		// Если значением порождается целое число
		case 0: return std::to_string(static_cast <int64_t> (engine() % 100000) - 50000);
		// Если значением порождается число дробное
		case 1: return "0.25";
		// Если значением порождается логическая истина
		case 2: return "true";
		// Если значением порождается логическая ложь
		case 3: return "false";
		// Если значением порождается запись с ведущим нулём
		case 4: return "007";
		// Если значением порождается запись с обвязкой пробелами
		case 5: return " 42 ";
		// Если значением порождается запись со знаком конца строки
		case 6: return "первая\nвторая";
		// Если значением порождается последовательность знаков
		default: {
			// Собираемое значение параметра
			string result = "";
			// Длина значения параметра
			const size_t length = (1 + (engine() % 10));
			// Выполняем перебор всех знаков значения
			for(size_t i = 0; i < length; i++){
				// Набор знаков значения параметра
				static const char LETTERS[] = "abcXYZ0123 =:\"'\\~/.";
				// Выполняем добавление знака значения
				result.append(1, LETTERS[engine() % (sizeof(LETTERS) - 1)]);
			}
			// Выводим порождённое значение параметра
			return result;
		}
	}
}

/**
 * @brief Метод сличения двух деревьев записью JSON
 *
 * @param bridge мост перевода записей
 * @param first  первое дерево значений
 * @param second второе дерево значений
 * @param record собранная запись первого дерева
 * @return       признак равенства деревьев
 *
 */
static bool same(codec::Bridge & bridge, const codec::abc::value_t & first,
 const codec::abc::value_t & second, string & record) noexcept {
	// Собираемая запись второго дерева
	string other = "";
	// Выполняем выдачу обоих деревьев записью JSON
	if(!bridge.encode(first, record, codec::Bridge::format_t::JSON))
		// Выводим равенство: сличать нечем, дерево записью не выражается
		return true;
	// Если второе дерево записью не выражается
	if(!bridge.encode(second, other, codec::Bridge::format_t::JSON))
		// Выводим равенство: сличать нечем
		return true;
	// Выводим признак равенства записей обоих деревьев
	return (record == other);
}

/**
 * @brief Метод запуска ворошителя
 *
 * @param argc количество поданных доводов
 * @param argv поданные доводы
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	/**
	 * Выполняем заведение модуля ядра первым делом
	 *
	 * @note Заведение захватывает выдачу памяти процесса и обязано идти
	 *       ДО всякой выдачи и ДО порождения потоков
	 */
	awh::fmk::initialize();
	// Получаем количество проходов генератора
	const uint64_t count = ((argc > 1) ? static_cast <uint64_t> (::atoll(argv[1])) : 2000);
	// Получаем зерно источника случайных чисел
	const uint64_t seed = ((argc > 2) ? static_cast <uint64_t> (::atoll(argv[2])) : 20260916);
	// Признак остановки на первой же находке
	const bool halt = ((argc > 3) ? (::atoll(argv[3]) != 0) : true);
	// Источник случайных чисел
	mt19937_64 engine(seed);
	// Учёт проделанной работы
	stat_t totals;
	// Выполняем перебор всех проходов ворошителя
	for(uint64_t pass = 0; pass < count; pass++){
		// Создаём объект сбора доводов запуска
		args::args_t args;
		// Получаем настройки разбора доводов
		args::args_t::settings_t settings = args.settings();
		// Устанавливаем признак вывода вида значения из его записи
		settings.typed = ((engine() % 4) > 0);
		// Устанавливаем признак сбора повторов перечнем
		settings.multiple = ((engine() % 2) > 0);
		// Устанавливаем признак строгости разбора
		settings.strict = ((engine() % 3) == 0);
		// Выполняем установку настроек разбора
		args.settings(settings);
		// Число подаваемых параметров
		const size_t total = (1 + (engine() % 6));
		// Собираемые имена поданных параметров
		vector <string> names;
		// Собираемый набор доводов запуска
		vector <string> items;
		// Выполняем перебор всех подаваемых параметров
		for(size_t i = 0; i < total; i++){
			// Порождаем имя параметра
			const string key = ::name(engine);
			// Запоминаем имя поданного параметра
			names.push_back(key);
			// Определяем наречие подачи параметра
			switch(engine() % 3){
				// Если параметр подаётся вместе со значением через знак равенства
				case 0: items.push_back(string("--").append(key).append("=").append(::value(engine))); break;
				// Если параметр подаётся значением отдельным доводом
				case 1: {
					// Выполняем добавление имени параметра
					items.push_back(string("--").append(key));
					// Выполняем добавление значения параметра
					items.push_back(::value(engine));
				} break;
				// Если параметр подаётся признаком без значения
				default: items.push_back(string("--").append(key));
			}
		}
		/**
		 * Если описание ожидаемых параметров взводится
		 *
		 * @note Описание заводится НЕ ВСЕГДА: без него разбор принимает всякое имя,
		 *       и оба уклада обязаны проверяться
		 */
		const bool described = ((engine() % 3) == 0);
		// Если описание ожидаемых параметров взводится
		if(described){
			// Выполняем перебор всех поданных имён
			for(auto & key : names){
				// Собираемое описание ожидаемого параметра
				args::schema_t::param_t param;
				// Устанавливаем длинное имя параметра
				param.name = key;
				// Устанавливаем потребность параметра в значении
				param.value = args::schema_t::value_t::OPTIONAL;
				// Дозволяем повторную подачу параметра
				param.multiple = true;
				// Выполняем заведение описания ожидаемого параметра
				static_cast <void> (args.schema().add(param));
			}
		}
		// Выполняем разбор собранного набора доводов
		const bool parsed = args.parse(items);
		// Увеличиваем счёт выполненных разборов
		totals.parsed++;
		/**
		 * ДОГОВОР 1: отказ обязан нести причину
		 *
		 * @warning Разбор, отвеченный отказом, обязан оставить извещение об отказе:
		 *          отказ без причины неотличим для потребителя от отказа без повода,
		 *          и чинить его не за что
		 */
		if(!parsed){
			// Увеличиваем счёт разборов, отвеченных отказом
			totals.refused++;
			// Увеличиваем счёт проверок честности отказа
			totals.honest++;
			// Если извещений об отказе разбор не оставил
			if(args.errors().empty()){
				// Увеличиваем счёт найденных расхождений
				totals.findings++;
				// Выводим сообщение об отказе без причины
				::fprintf(stderr, "НАХОДКА: разбор отвечен отказом без причины\n  доводы:");
				// Выполняем перебор всех поданных доводов
				for(auto & item : items)
					// Выводим поданный довод запуска
					::fprintf(stderr, " «%s»", item.c_str());
				// Выводим перевод строки отчёта
				::fprintf(stderr, "\n");
				// Если ворошителю велено встать на первой находке
				if(halt) return EXIT_FAILURE;
			}
			// Продолжаем перебор проходов дальше
			continue;
		}
		// Создаём мост перевода записей настроек
		codec::Bridge bridge;
		/**
		 * ДОГОВОР 2: круг выдачи и чтения неподвижен со второго прохода
		 */
		for(size_t i = 0; i < FORMATS_COUNT; i++){
			// Собираемая запись настроек первого прохода
			string first = "";
			// Если выдача записи отвечена отказом, вид дереву не годится
			if(!args.dump(first, FORMATS[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Создаём объект чтения записи настроек
			args::args_t back;
			// Выполняем установку тех же настроек разбора
			back.settings(settings);
			// Если чтение собранной записи отвечено отказом
			if(!back.config(first, FORMATS[i])){
				// Увеличиваем счёт найденных расхождений
				totals.findings++;
				// Выводим сообщение о записи, своим же чтением не принятой
				::fprintf(stderr, "НАХОДКА %s: своя же запись чтением не принята\n  запись: «%s»\n", NAMES[i], first.c_str());
				// Если ворошителю велено встать на первой находке
				if(halt) return EXIT_FAILURE;
				// Продолжаем перебор видов записи дальше
				continue;
			}
			// Собираемая запись настроек второго прохода
			string second = "";
			// Если выдача записи второго прохода отвечена отказом
			if(!back.dump(second, FORMATS[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Создаём объект чтения записи второго прохода
			args::args_t last;
			// Выполняем установку тех же настроек разбора
			last.settings(settings);
			// Если чтение записи второго прохода отвечено отказом
			if(!last.config(second, FORMATS[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Собираемая запись настроек третьего прохода
			string third = "";
			// Если выдача записи третьего прохода отвечена отказом
			if(!last.dump(third, FORMATS[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Увеличиваем счёт проверок неподвижности круга
			totals.stable++;
			/**
			 * Если запись третьего прохода разошлась с записью второго
			 *
			 * @warning Расхождение это означает, что круг ПОЛЗЁТ: запись остаётся
			 *          читаемой, а содержимое её меняется всяким проходом, и порок
			 *          оттого тих
			 */
			if(second != third){
				// Увеличиваем счёт найденных расхождений
				totals.findings++;
				// Выводим сообщение о ползущем круге
				::fprintf(stderr, "НАХОДКА %s: круг ползёт\n  второй проход: «%s»\n  третий проход: «%s»\n", NAMES[i], second.c_str(), third.c_str());
				// Если ворошителю велено встать на первой находке
				if(halt) return EXIT_FAILURE;
			}
		}
		/**
		 * ДОГОВОР 3: довод запуска старше записи настроек
		 *
		 * @warning Старшинство стережётся ОБОИМИ порядками подачи: дефект,
		 *          пропускающий один из них, при другом невидим
		 */
		{
			// Имя параметра, подаваемого двумя источниками
			const string key = ::name(engine);
			// Создаём объект сбора доводов запуска
			args::args_t senior;
			// Собираемый набор доводов запуска со значением старшего источника
			const vector <string> cli = {string("--").append(key).append("=старший")};
			// Собираемая запись настроек со значением младшего источника
			string record = "";
			// Создаём дерево значений записи настроек
			codec::abc::value_t tree;
			// Выполняем укладку значения младшего источника
			tree[senior.settings().delimiter == '.' ? key : key] = codec::abc::value_t(string("младший"));
			// Если запись настроек собрать не удалось
			if(bridge.encode(tree, record, codec::Bridge::format_t::JSON)){
				// Выполняем подачу записи настроек первой
				if(senior.config(record, codec::Bridge::format_t::JSON) && senior.parse(cli)){
					// Увеличиваем счёт проверок старшинства источника
					totals.seniority++;
					// Если значение старшего источника не пересилило младшего
					if(senior.has(key) && (senior.get <string> (key) != "старший")){
						// Увеличиваем счёт найденных расхождений
						totals.findings++;
						// Выводим сообщение о нарушении старшинства
						::fprintf(stderr, "НАХОДКА: довод запуска не пересилил запись настроек\n  имя: «%s», значение: «%s»\n", key.c_str(), senior.get <string> (key).c_str());
						// Если ворошителю велено встать на первой находке
						if(halt) return EXIT_FAILURE;
					}
				}
				// Создаём объект сбора доводов обратного порядка подачи
				args::args_t reverse;
				// Выполняем подачу довода запуска первым
				if(reverse.parse(cli) && reverse.config(record, codec::Bridge::format_t::JSON)){
					// Увеличиваем счёт проверок старшинства источника
					totals.seniority++;
					// Если значение младшего источника пересилило старшего
					if(reverse.has(key) && (reverse.get <string> (key) != "старший")){
						// Увеличиваем счёт найденных расхождений
						totals.findings++;
						// Выводим сообщение о нарушении старшинства обратным порядком
						::fprintf(stderr, "НАХОДКА: запись настроек пересилила довод запуска обратным порядком\n  имя: «%s», значение: «%s»\n", key.c_str(), reverse.get <string> (key).c_str());
						// Если ворошителю велено встать на первой находке
						if(halt) return EXIT_FAILURE;
					}
				}
			}
		}
		/**
		 * ДОГОВОР 5: набор доводов и та же подача ОДНОЮ СТРОКОЙ дают одно дерево
		 *
		 * @warning Ход `text()` отведён вводу с клавиатуры и подаче настроек одною
		 *          строкой, а разбирает он ТОТ ЖЕ лексер. Значит, набор доводов и
		 *          тот же набор, сцепленный пробелами, обязаны давать одно и то же
		 *          дерево - расхождение означало бы, что два наречия одного модуля
		 *          толкуют одну подачу по-разному
		 *
		 * @note Сличение идёт лишь у доводов, пробелов и кавычек НЕ несущих: сцепка
		 *       пробелом у прочих меняет саму подачу, и расхождение там законно
		 */
		{
			/**
			 * Собираемая строка подачи
			 *
			 * @details Всякий довод берётся в двойные кавычки, а сами кавычки,
			 * косая черта и знак конца строки внутри отменяются косой: ровно так
			 * велит разрез строки, и ровно этот разрез договор и стережёт
			 *
			 * @warning Прежде доводы с пробелом либо кавычкой из сличения
			 *          ИСКЛЮЧАЛИСЬ, и договор стерёг лишь простые слова - то есть
			 *          ровно то, ради чего разреза не надо вовсе. Проверка,
			 *          сработать не могущая, не стережёт ничего
			 */
			string line = "";
			// Выполняем перебор всех поданных доводов
			for(auto & item : items){
				// Если строка подачи не пуста, ставим разделитель
				if(!line.empty())
					// Выполняем добавление разделителя доводов
					line.append(1, ' ');
				// Выполняем добавление открывающей кавычки
				line.append(1, '"');
				// Выполняем перебор всех знаков довода
				for(auto & letter : item){
					// Если знак требует отмены косой чертой
					if((letter == '"') || (letter == '\\'))
						// Выполняем добавление знака отмены
						line.append(1, '\\');
					// Выполняем добавление знака довода
					line.append(1, letter);
				}
				// Выполняем добавление закрывающей кавычки
				line.append(1, '"');
			}
			// Создаём объект разбора строки подачи
			args::args_t stream;
			// Выполняем установку тех же настроек разбора
			stream.settings(settings);
			// Если описание ожидаемых параметров взводилось
			if(described){
				// Выполняем перебор всех поданных имён
				for(auto & key : names){
					// Собираемое описание ожидаемого параметра
					args::schema_t::param_t param;
					// Устанавливаем длинное имя параметра
					param.name = key;
					// Устанавливаем потребность параметра в значении
					param.value = args::schema_t::value_t::OPTIONAL;
					// Дозволяем повторную подачу параметра
					param.multiple = true;
					// Выполняем заведение описания ожидаемого параметра
					static_cast <void> (stream.schema().add(param));
				}
			}
			// Если разбор строки подачи выполнен
			if(stream.text(line)){
				// Увеличиваем счёт проверок согласия двух наречий подачи
				totals.streamed++;
				// Собираемая запись дерева набора доводов
				string record = "";
				// Если деревья обоих наречий разошлись
				if(!::same(bridge, args.root(), stream.root(), record)){
					// Собираемая запись дерева строки подачи
					string other = "";
					// Выполняем выдачу дерева строки подачи записью
					static_cast <void> (bridge.encode(stream.root(), other, codec::Bridge::format_t::JSON));
					// Увеличиваем счёт найденных расхождений
					totals.findings++;
					// Выводим сообщение о расхождении двух наречий подачи
					::fprintf(stderr, "НАХОДКА: набор доводов и та же подача строкой дали разные деревья\n  строка: «%s»\n  набором: «%s»\n  строкой: «%s»\n", line.c_str(), record.c_str(), other.c_str());
					// Если ворошителю велено встать на первой находке
					if(halt) return EXIT_FAILURE;
				}
			}
		}
		/**
		 * ДОГОВОР 6: старшинство блюдётся ВСЕЮ лестницей источников
		 *
		 * @details Лестница такова: DEFAULT < FILE < ENV < TEXT < CLI. Стеречь одну
		 * лишь верхнюю ступень мало: дефект, путающий середину лестницы, при сличении
		 * крайних ступеней невидим
		 *
		 * @warning Подача идёт в порядке ОБРАТНОМ старшинству - сперва старший, после
		 *          младшие, - и это не прихоть: уложить младшее поверх старшего проще
		 *          всего именно так, и порядок этот ловит дефект, где укладка глядит
		 *          на время подачи вместо старшинства
		 */
		{
			// Имя параметра, подаваемого всею лестницей источников
			const string key = ::name(engine);
			// Создаём объект сбора доводов запуска
			args::args_t ladder;
			// Устанавливаем начало имён переменных окружения
			ladder.prefix("AWHFUZZ");
			// Выполняем подачу значения набором доводов запуска - старшим источником
			if(ladder.parse(vector <string> {string("--").append(key).append("=старший")})){
				// Собираемая запись настроек младшего источника
				string record = "";
				// Создаём дерево значений записи настроек
				codec::abc::value_t tree;
				// Выполняем укладку значения записи настроек
				tree[key] = codec::abc::value_t(string("запись"));
				// Если запись настроек собрана
				if(bridge.encode(tree, record, codec::Bridge::format_t::JSON)){
					// Выполняем подачу записи настроек - источника младшего
					static_cast <void> (ladder.config(record, codec::Bridge::format_t::JSON));
					// Выполняем подачу текстового потока - источника среднего
					static_cast <void> (ladder.text(string("--").append(key).append("=поток")));
					// Увеличиваем счёт проверок старшинства источника
					totals.seniority++;
					// Если значение старшего источника не удержалось
					if(ladder.has(key) && (ladder.get <string> (key) != "старший")){
						// Увеличиваем счёт найденных расхождений
						totals.findings++;
						// Выводим сообщение о нарушении лестницы старшинства
						::fprintf(stderr, "НАХОДКА: лестница старшинства нарушена\n  имя: «%s», удержалось: «%s», ожидалось «старший»\n", key.c_str(), ladder.get <string> (key).c_str());
						// Если ворошителю велено встать на первой находке
						if(halt) return EXIT_FAILURE;
					}
				}
			}
			// Создаём объект сбора без довода запуска: там старшим станет поток
			args::args_t middle;
			// Выполняем подачу текстового потока - источника среднего
			if(middle.text(string("--").append(key).append("=поток"))){
				// Собираемая запись настроек младшего источника
				string record = "";
				// Создаём дерево значений записи настроек
				codec::abc::value_t tree;
				// Выполняем укладку значения записи настроек
				tree[key] = codec::abc::value_t(string("запись"));
				// Если запись настроек собрана
				if(bridge.encode(tree, record, codec::Bridge::format_t::JSON)){
					// Выполняем подачу записи настроек - источника младшего
					static_cast <void> (middle.config(record, codec::Bridge::format_t::JSON));
					// Увеличиваем счёт проверок старшинства источника
					totals.seniority++;
					// Если запись настроек пересилила текстовый поток
					if(middle.has(key) && (middle.get <string> (key) != "поток")){
						// Увеличиваем счёт найденных расхождений
						totals.findings++;
						// Выводим сообщение о нарушении середины лестницы
						::fprintf(stderr, "НАХОДКА: запись настроек пересилила текстовый поток\n  имя: «%s», удержалось: «%s»\n", key.c_str(), middle.get <string> (key).c_str());
						// Если ворошителю велено встать на первой находке
						if(halt) return EXIT_FAILURE;
					}
				}
			}
		}
		/**
		 * ДОГОВОР 4: строгость отвечает отказом на имя, описанию неизвестное
		 */
		{
			// Создаём объект сбора доводов запуска
			args::args_t strict;
			// Получаем настройки разбора доводов
			args::args_t::settings_t rules = strict.settings();
			// Взводим строгость разбора
			rules.strict = true;
			// Выполняем установку настроек разбора
			strict.settings(rules);
			// Выполняем заведение описания единственного ожидаемого параметра
			if(strict.schema().add("known", 0, args::schema_t::value_t::OPTIONAL)){
				// Увеличиваем счёт проверок строгости разбора
				totals.strictness++;
				// Если имя, описанию неизвестное, принято разбором
				if(strict.parse(vector <string> {"--unknown=значение"})){
					// Увеличиваем счёт найденных расхождений
					totals.findings++;
					// Выводим сообщение о строгости, отказа не давшей
					::fprintf(stderr, "НАХОДКА: строгий разбор принял имя, описанию неизвестное\n");
					// Если ворошителю велено встать на первой находке
					if(halt) return EXIT_FAILURE;
				}
			}
		}
	}
	// Выводим заголовок отчёта о проделанной работе
	::fprintf(stdout, "  разборов выполнено: %llu, из них отвечено отказом: %llu\n",
	 static_cast <unsigned long long> (totals.parsed), static_cast <unsigned long long> (totals.refused));
	// Выводим счёт проверок честности отказа
	::fprintf(stdout, "  проверок честности отказа: %llu\n", static_cast <unsigned long long> (totals.honest));
	// Выводим счёт проверок неподвижности круга
	::fprintf(stdout, "  проверок неподвижности круга: %llu\n", static_cast <unsigned long long> (totals.stable));
	// Выводим счёт проверок старшинства источника
	::fprintf(stdout, "  проверок старшинства источника: %llu\n", static_cast <unsigned long long> (totals.seniority));
	// Выводим счёт проверок строгости разбора
	::fprintf(stdout, "  проверок строгости разбора: %llu\n", static_cast <unsigned long long> (totals.strictness));
	// Выводим счёт проверок согласия двух наречий подачи
	::fprintf(stdout, "  проверок согласия набора со строкой: %llu\n", static_cast <unsigned long long> (totals.streamed));
	// Выводим счёт найденных расхождений
	::fprintf(stdout, "  найдено расхождений: %llu\n", static_cast <unsigned long long> (totals.findings));
	// Выводим результат работы ворошителя
	return (totals.findings > 0 ? EXIT_FAILURE : EXIT_SUCCESS);
}
