/**
 * @brief Средства построения деревьев значений (внутренняя компоновка)
 *
 */
namespace {
	/**
	 * @brief Учёт проделанной работы
	 *
	 */
	struct Statistic {
		// Число построенных деревьев значений
		uint64_t trees = 0;
		// Число выполненных переводов дерева в запись
		uint64_t encodes = 0;
		// Число переводов, отвеченных отказом
		uint64_t refusals = 0;
		// Число выполненных проверок честности отказа
		uint64_t honesty = 0;
		// Число выполненных проверок разбираемости собранного
		uint64_t parsed = 0;
		// Число выполненных проверок неподвижности круга
		uint64_t stable = 0;
		// Число выполненных проверок равенства исходному дереву
		uint64_t equal = 0;
		// Число выполненных проверок переезда дерева между видами записи
		uint64_t moved = 0;
		// Число найденных нарушений договора
		uint64_t findings = 0;
		// Число переводов, отвеченных отказом, по видам записи
		uint64_t refused[5] = {0, 0, 0, 0, 0};
		// Число переводов, отвеченных отказом, по причинам отказа
		uint64_t reasons[5] = {0, 0, 0, 0, 0};
	};
	/**
	 * @brief Функция построения имени поля отображения
	 *
	 * @param engine источник случайных чисел
	 * @return       собранное имя поля
	 *
	 * @note Имена строятся обычными и неудобными вперемешку: неудобное имя проверяет
	 *       не выразимость его, а ЧЕСТНОСТЬ отказа на нём
	 *
	 */
	string buildName(mt19937_64 & engine) noexcept {
		/**
		 * Если выпало имя, у моста особое значение имеющее
		 *
		 * @details Имена эти ворошитель прежде не строил вовсе, а на них держатся
		 * целые правила: `value` есть имя поля, текст узла несущего, и столкновение
		 * его с одноимённым свойством разбирается отдельным ходом; `item` есть имя
		 * обноса перечня; `array` есть имя пометки; `3` правится приставкой, а
		 * `Item3` с этой правкою СТАЛКИВАЕТСЯ. Прогон, таких имён не строящий,
		 * выглядит покрытием, не будучи им
		 *
		 * @note Довод способа принят от владельца кодека YAML: набор, где значение
		 *       до места правила не доходит, покрытием не является
		 */
		if((engine() % 10) == 0){
			// Перечень имён, у моста особое значение имеющих
			static const char * special[] = {"value", "_value", "__value", "item", "array", "3", "Item3", "config"};
			// Выводим одно из имён перечня
			return string(special[engine() % (sizeof(special) / sizeof(special[0]))]);
		}
		// Собираемое имя поля отображения
		string result = "";
		// Получаем длину собираемого имени поля
		const size_t length = 1 + (engine() % 6);
		// Выполняем сборку имени поля отображения
		for(size_t i = 0; i < length; i++)
			// Добавляем очередной знак имени поля
			result.append(1, static_cast <char> ('a' + (engine() % 26)));
		// Определяем добавку, имя неудобным делающую
		switch(engine() % 12){
			// Добавляем точку, разделителем пути служащую
			case 0: result.append(1, '.'); break;
			// Добавляем пробел
			case 1: result.append(1, ' '); break;
			// Добавляем знак равенства
			case 2: result.append(1, '='); break;
			// Добавляем кавычку
			case 3: result.append(1, '"'); break;
			// Добавляем косую черту, разделителем ссылки служащую
			case 4: result.append(1, '/'); break;
			// Ставим ведущую цифру, разметке негодную
			case 5: result.insert(result.begin(), static_cast <char> ('0' + (engine() % 10))); break;
			// Ставим ведущую тильду, ссылке негодную
			case 6: result.insert(result.begin(), '~'); break;
		}
		// Выводим собранное имя поля отображения
		return result;
	}
	/**
	 * @brief Функция построения простого значения
	 *
	 * @param engine источник случайных чисел
	 * @return       собранное значение контейнера ABC
	 *
	 */
	codec::abc::value_t buildScalar(mt19937_64 & engine) noexcept {
		/**
		 * Если выпал вид, текстовым кодекам неведомый
		 *
		 * @details Виды эти - двоичные данные, отметка времени и опознаватель - у
		 * текстовых кодеков отсутствуют, и всякая из пяти дорог записи обращается с
		 * ними по правилу сужения. Правило одно, а мест его написания пять, и
		 * расхождение между ними ворошителю без таких значений НЕВИДИМО: замер
		 * 04.09.2026 показал, что отметка времени уходила у двух дорог из пяти
		 * пустою строкою, а прежние прогоны на 300 000 деревьев того не поймали,
		 * ибо значений таких не строили вовсе
		 *
		 * @warning Доля их держится низкой намеренно: значения эти проверяют ОДНО
		 *          правило, и большая доля лишь разбавила бы прочие проверки
		 */
		if((engine() % 16) == 0){
			// Определяем вид собираемого значения
			switch(engine() % 3){
				// Выводим значение отметкою времени
				case 0: return codec::abc::value_t(codec::abc::kind_t::TIME);
				// Выводим значение опознавателем
				case 1: return codec::abc::value_t(codec::abc::kind_t::UUID);
				// Выводим значение двоичными данными
				default: return codec::abc::value_t(codec::abc::kind_t::BLOB);
			}
		}
		// Определяем вид собираемого значения
		switch(engine() % 12){
			// Выводим значение логическою истиной
			case 0: return codec::abc::value_t(true);
			// Выводим значение логическою ложью
			case 1: return codec::abc::value_t(false);
			// Выводим значение целым без знака
			case 2: return codec::abc::value_t(static_cast <uint64_t> (engine() % 100000));
			// Выводим значение пределом разрядности целого без знака
			case 3: return codec::abc::value_t(static_cast <uint64_t> (18446744073709551615ULL));
			// Выводим значение целым со знаком
			case 4: return codec::abc::value_t(- static_cast <int64_t> (engine() % 100000));
			// Выводим значение числом дробным
			case 5: return codec::abc::value_t(static_cast <double> (engine() % 1000) / 8.);
			// Выводим значение записью пустою
			case 6: return codec::abc::value_t(string(""));
			// Выводим значение записью числа, числом НЕ являющегося
			case 7: return codec::abc::value_t(string("007"));
			// Выводим значение записью с кавычками и переводом строки
			case 8: return codec::abc::value_t(string("а\"б\nв"));
			// Выводим значение записью, логическое напоминающей
			case 9: return codec::abc::value_t(string("true"));
			// Выводим значение записью многоязычной
			case 10: return codec::abc::value_t(string("значение"));
			// Выводим значение пустым
			default: return codec::abc::value_t();
		}
	}
	/**
	 * @brief Функция построения дерева значений
	 *
	 * @param engine источник случайных чисел
	 * @param result собираемое дерево значений
	 * @param depth  оставшаяся глубина построения
	 *
	 */
	void buildTree(mt19937_64 & engine, codec::abc::value_t & result, const uint32_t depth) noexcept {
		// Получаем число полей собираемого отображения
		const size_t length = (engine() % 5);
		// Выполняем сборку полей отображения
		for(size_t i = 0; i < length; i++){
			// Получаем имя очередного поля отображения
			const string name = ::buildName(engine);
			// Если глубина построения исчерпана либо выпало простое значение
			if((depth == 0) || ((engine() % 3) != 0)){
				// Устанавливаем простое значение полем отображения
				result[name] = ::buildScalar(engine);
				// Продолжаем сборку полей отображения дальше
				continue;
			}
			// Если выпал перечень значений
			if((engine() % 2) == 0){
				// Собираемый перечень значений
				codec::abc::value_t items;
				// Получаем число звеньев собираемого перечня
				const size_t count = (engine() % 4);
				// Выполняем сборку звеньев перечня
				for(size_t j = 0; j < count; j++){
					// Если звеном перечня выпало вместилище
					if((engine() % 4) == 0){
						// Собираемое вместилище звена перечня
						codec::abc::value_t nested;
						// Выполняем сборку вместилища звена перечня
						::buildTree(engine, nested, depth - 1);
						// Добавляем собранное вместилище звеном перечня
						items.push(nested);
					// Если звеном перечня выпало простое значение
					} else items.push(::buildScalar(engine));
				}
				// Устанавливаем собранный перечень полем отображения
				result[name] = items;
				// Продолжаем сборку полей отображения дальше
				continue;
			}
			// Собираемое вложенное отображение
			codec::abc::value_t nested;
			// Выполняем сборку вложенного отображения
			::buildTree(engine, nested, depth - 1);
			// Устанавливаем собранное отображение полем отображения
			result[name] = nested;
		}
	}
}

/**
 * @brief Точка входа в приложение
 *
 * @param argc количество доводов запуска
 * @param argv набор доводов запуска
 * @return     код выхода из приложения
 *
 */
int main(int argc, char * argv[]) noexcept {
	// Получаем количество проходов генератора
	const uint64_t count = ((argc > 1) ? static_cast <uint64_t> (::atoll(argv[1])) : 3000);
	// Получаем зерно источника случайных чисел
	const uint64_t seed = ((argc > 2) ? static_cast <uint64_t> (::atoll(argv[2])) : 20260904);
	// Получаем предельную глубину строимых деревьев
	const uint32_t deep = ((argc > 3) ? static_cast <uint32_t> (::atoll(argv[3])) : 3);
	// Признак остановки на первой же находке
	const bool halt = ((argc > 4) ? (::atoll(argv[4]) != 0) : true);
	// Источник случайных чисел
	mt19937_64 engine(seed);
	// Учёт проделанной работы
	Statistic totals;
	// Создаём мост между контейнером ABC и текстовыми кодеками
	codec::bridge_t bridge(::framework(), ::logger());
	// Перечень видов записи, мостом переводимых
	const codec::bridge_t::format_t formats[] = {
		codec::bridge_t::format_t::JSON, codec::bridge_t::format_t::YAML,
		codec::bridge_t::format_t::XML, codec::bridge_t::format_t::TOML,
		codec::bridge_t::format_t::INI
	};
	// Названия видов записи, мостом переводимых
	const char * names[] = {"JSON", "YAML", "XML", "TOML", "INI"};
	/**
	 * Выполняем проходы генератора
	 */
	for(uint64_t pass = 0; pass < count; pass++){
		// Собираемое дерево значений контейнера ABC
		codec::abc::value_t value;
		// Выполняем сборку дерева значений
		::buildTree(engine, value, deep);
		// Увеличиваем счёт построенных деревьев значений
		totals.trees++;
		/**
		 * Выполняем смену настроек перевода
		 *
		 * @details Настройки эти суть ВЕТВИ кода, и ворошитель, гоняющий одни лишь
		 * умолчания, их не проходит вовсе: правило сужения написано пятью местами, а
		 * умолчание берёт у каждого лишь одну ветвь из трёх. Правило укладки пустого
		 * узла - то же самое, четыре ветви при одном умолчании
		 *
		 * @warning Договоры равенства и переезда при правиле `SKIP` НЕ поверяются:
		 *          пропуск значения теряет его законно, и расхождение деревьев там
		 *          есть исход ожидаемый, а не находка
		 */
		codec::bridge_t::settings_t settings = bridge.settings();
		// Определяем правило обращения с видом, записи кодека неведомым
		switch(engine() % 3){
			// Устанавливаем обращение вида в последовательность знаков
			case 0: settings.narrow = codec::bridge_t::narrow_t::TEXT; break;
			// Устанавливаем ответ отказом на вид, записи неведомый
			case 1: settings.narrow = codec::bridge_t::narrow_t::STRICT; break;
			// Устанавливаем пропуск вида, записи неведомого
			default: settings.narrow = codec::bridge_t::narrow_t::SKIP; break;
		}
		// Определяем правило укладки пустого узла разметки
		switch(engine() % 4){
			// Устанавливаем укладку пустого узла логическою истиной
			case 0: settings.empty = codec::bridge_t::empty_t::BOOLEAN; break;
			// Устанавливаем укладку пустого узла пустым значением
			case 1: settings.empty = codec::bridge_t::empty_t::NONE; break;
			// Устанавливаем укладку пустого узла пустою записью
			case 2: settings.empty = codec::bridge_t::empty_t::STRING; break;
			// Устанавливаем укладку пустого узла пустым отображением
			default: settings.empty = codec::bridge_t::empty_t::OBJECT; break;
		}
		// Определяем разрешение пометки перечня
		settings.array = (((engine() % 8) == 0) ? string("") : string("array"));
		/**
		 * Определяем предел глубины перевода
		 *
		 * @warning Заслон глубины прежде не срабатывал НИ РАЗУ: умолчание его - 512
		 *          уровней, а деревья строятся глубиною в единицы. Ветвь эта стояла
		 *          непройденной, и отказ по глубине не был проверен вовсе
		 */
		settings.depth = (((engine() % 16) == 0) ? 2 : 512);
		// Выполняем установку настроек перевода
		bridge.settings(settings);
		// Признак законной потери значений при переводе
		const bool lossy = (settings.narrow == codec::bridge_t::narrow_t::SKIP);
		/**
		 * Выполняем проверку ПЕРЕЕЗДА дерева между видами записи
		 *
		 * @details Ради переезда мост и писан: дерево, из записи одного вида
		 * собранное, обязано лечь записью другого вида и вернуться собою. Круг
		 * внутри одного вида этого не поверяет вовсе - он стережёт согласие кодека
		 * с самим собою, а переезд стережёт согласие ДВУХ кодеков через общую ось
		 *
		 * @warning Оба конца берутся у видов, свою систему видов несущих: у разметки
		 *          и у INI сужение вида законно, и расхождение на них было бы
		 *          свойством формата, а не находкой
		 */
		{
			// Собираемая запись первого вида
			string first = "";
			// Если дерево переводится в запись JSON
			if(!lossy && bridge.encode(value, first, codec::bridge_t::format_t::JSON)){
				// Собираемое дерево, из записи JSON собранное
				codec::abc::value_t moved;
				// Собираемая запись второго вида
				string second = "";
				// Собираемое дерево, из записи YAML собранное
				codec::abc::value_t back;
				/**
				 * Если дерево переехало в запись YAML и вернулось
				 */
				if(bridge.decode(first, moved, codec::bridge_t::format_t::JSON) &&
				   bridge.encode(moved, second, codec::bridge_t::format_t::YAML) &&
				   bridge.decode(second, back, codec::bridge_t::format_t::YAML)){
					// Собираемые записи обоих деревьев
					string before = "", after = "";
					// Если оба дерева переводятся в запись JSON
					if(bridge.encode(moved, before, codec::bridge_t::format_t::JSON) &&
					   bridge.encode(back, after, codec::bridge_t::format_t::JSON)){
						// Увеличиваем счёт выполненных проверок переезда
						totals.moved++;
						// Если дерево переезда исходному не равно
						if(before != after){
							// Увеличиваем счёт найденных нарушений договора
							totals.findings++;
							// Выводим сообщение о нарушении переезда дерева
							::fprintf(stderr, "НАХОДКА JSON→YAML: переезд вернул иное дерево\n  было: «%s»\n  стало: «%s»\n  запись: «%s»\n", before.c_str(), after.c_str(), second.c_str());
							// Если остановка на первой находке затребована
							if(halt)
								// Выходим из приложения с признаком находки
								return 1;
						}
					}
				}
			}
		}
		// Выполняем перебор всех видов записи
		for(size_t i = 0; i < (sizeof(formats) / sizeof(formats[0])); i++){
			// Собираемая запись первого прохода
			string first = "";
			// Выполняем перевод дерева значений в запись
			const bool done = bridge.encode(value, first, formats[i]);
			// Увеличиваем счёт выполненных переводов
			totals.encodes++;
			// Увеличиваем счёт выполненных проверок честности отказа
			totals.honesty++;
			/**
			 * Если перевод отвечен отказом
			 */
			if(!done){
				// Увеличиваем счёт переводов, отвеченных отказом
				totals.refusals++;
				// Увеличиваем счёт отказов по виду записи
				totals.refused[i]++;
				/**
				 * Увеличиваем счёт отказов по причине отказа
				 *
				 * @note Разбор причин показывает, ЧЕМ вызван отказ: сужением вида,
				 *       отказом собирателя записи либо глубиной дерева. Без него доля
				 *       отказов читается как «ворошитель половину работы не делает»,
				 *       тогда как отказ на невыразимом имени есть законный исход
				 */
				if(static_cast <size_t> (bridge.error()) < 5)
					// Увеличиваем счёт отказов по причине
					totals.reasons[static_cast <size_t> (bridge.error())]++;
				/**
				 * Если отказ пришёл без причины
				 *
				 * @warning Отказ с кодом `NONE` оставляет потребителя без ответа на
				 *          вопрос «почему» и неотличим для него от отказа без причины
				 */
				if(bridge.error() == codec::bridge_t::error_t::NONE){
					// Увеличиваем счёт найденных нарушений договора
					totals.findings++;
					// Выводим сообщение об отказе без причины
					::fprintf(stderr, "НАХОДКА %s: отказ пришёл без причины\n", names[i]);
					// Если остановка на первой находке затребована
					if(halt)
						// Выходим из приложения с признаком находки
						return 1;
				}
				/**
				 * Если причина отказа дороге не принадлежит
				 *
				 * @details Ход записи отказать может по четырём причинам - собиратель
				 * записи, вид значения, устройство записи и глубина дерева, - а
				 * причина «разбор записи» ему не принадлежит вовсе: разбирать ему
				 * нечего. Подмена кода по дороге наверх выглядит отказом здоровым и
				 * от договора наличия причины ускользает
				 *
				 * @note Довод принят от владельца кодека XML: у него отказ приходит от
				 *       трёх слоёв, и код по дороге дважды перекладывается из рук в
				 *       руки. Проверяется здесь ПРИНАДЛЕЖНОСТЬ кода дороге, а не
				 *       догадка о его величине: догадка повторяла бы правила моста и
				 *       расходилась бы с ними при всякой правке
				 */
				if(bridge.error() == codec::bridge_t::error_t::PARSING){
					// Увеличиваем счёт найденных нарушений договора
					totals.findings++;
					// Выводим сообщение о причине, дороге не принадлежащей
					::fprintf(stderr, "НАХОДКА %s: запись отвечена отказом с причиной «разбор записи»\n", names[i]);
					// Если остановка на первой находке затребована
					if(halt)
						// Выходим из приложения с признаком находки
						return 1;
				}
				// Если запись при отказе осталась непустой
				if(!first.empty()){
					// Увеличиваем счёт найденных нарушений договора
					totals.findings++;
					// Выводим сообщение о нарушении честности отказа
					::fprintf(stderr, "НАХОДКА %s: отказ оставил запись непустой: «%s»\n", names[i], first.c_str());
					// Если остановка на первой находке затребована
					if(halt)
						// Выходим из приложения с признаком находки
						return 1;
				}
				// Продолжаем перебор видов записи дальше
				continue;
			}
			// Собираемое дерево значений второго прохода
			codec::abc::value_t second;
			// Увеличиваем счёт выполненных проверок разбираемости собранного
			totals.parsed++;
			/**
			 * Если собранная запись разбору не поддалась
			 *
			 * @warning Находка это тяжёлая: собиратель и разборщик у кодека одни, и
			 *          запись, им собранная, обязана им же разбираться
			 */
			if(!bridge.decode(first, second, formats[i])){
				// Увеличиваем счёт найденных нарушений договора
				totals.findings++;
				/**
				 * Если отказ разбора пришёл без причины
				 *
				 * @note Договор этот тот же, что и у отказа записи: отказ, кода не
				 *       несущий, неотличим для потребителя от отказа без причины.
				 *       Довод стороны обратной принят от владельца кодека XML -
				 *       очистка на пути возврата стирала код, и наружу выходил
				 *       отказ с кодом «отказа не произошло»
				 */
				if(bridge.error() == codec::bridge_t::error_t::NONE)
					// Выводим сообщение об отказе разбора без причины
					::fprintf(stderr, "НАХОДКА %s: отказ разбора пришёл без причины\n", names[i]);
				/**
				 * Если причина отказа разбору не принадлежит
				 *
				 * @note Ход разбора отказать может лишь разбором записи да глубиной
				 *       дерева: собирать ему нечего, и правила сужения он не знает
				 *       вовсе
				 */
				if((bridge.error() != codec::bridge_t::error_t::PARSING) &&
				   (bridge.error() != codec::bridge_t::error_t::DEEP_TREE) &&
				   (bridge.error() != codec::bridge_t::error_t::NONE))
					// Выводим сообщение о причине, разбору не принадлежащей
					::fprintf(stderr, "НАХОДКА %s: разбор отвечен отказом с причиной записи (%u)\n", names[i], static_cast <uint32_t> (bridge.error()));
				// Выводим сообщение о нарушении разбираемости собранного
				/**
				 * Выполняем сохранение записи, разбору не поддавшейся
				 *
				 * @note Запись сохраняется ОКТЕТ В ОКТЕТ: доклад через поток вывода
				 *       теряет незримые знаки, и запись, в докладе годная, при
				 *       повторе разбирается
				 */
				{
					// Открываем файл записи находки
					FILE * file = ::fopen("/tmp/bridge-finding.txt", "wb");
					// Если файл записи открыт
					if(file != nullptr){
						// Выполняем запись находки в файл
						static_cast <void> (::fwrite(first.data(), 1, first.size(), file));
						// Выполняем закрытие файла записи
						::fclose(file);
					}
				}
				// Собираемая запись дерева ради доклада
				string dump = "";
				// Выполняем перевод дерева значений в запись JSON
				static_cast <void> (bridge.encode(value, dump, codec::bridge_t::format_t::JSON));
				::fprintf(stderr, "НАХОДКА %s: собранная запись разбору не поддалась: «%s»\n  дерево: «%s»\n  сужение: %u, пустой узел: %u, пометка: «%s», глубина: %u\n", names[i], first.c_str(), dump.c_str(), static_cast <uint32_t> (bridge.settings().narrow), static_cast <uint32_t> (bridge.settings().empty), bridge.settings().array.c_str(), bridge.settings().depth);
				// Если остановка на первой находке затребована
				if(halt)
					// Выходим из приложения с признаком находки
					return 1;
				// Продолжаем перебор видов записи дальше
				continue;
			}
			/**
			 * Выполняем проверку равенства дерева исходному
			 *
			 * @details Виды JSON и YAML несут свою систему видов целиком, и круг
			 * перевода на них обязан возвращать ТО ЖЕ САМОЕ дерево, а не просто
			 * запись, себе равную. Сличение с признаком успеха здесь бессильно:
			 * потеря выходит наружу успешным переводом с изменившимся содержимым
			 *
			 * @warning Виды XML, TOML и INI сюда НЕ входят: у разметки и у INI своей
			 *          системы видов нет вовсе, и сужение вида там законно. Их
			 *          стережёт неподвижность круга ниже
			 */
			if(!lossy && ((formats[i] == codec::bridge_t::format_t::JSON) || (formats[i] == codec::bridge_t::format_t::YAML))){
				// Собираемая запись исходного дерева
				string before = "";
				// Собираемая запись дерева обратного хода
				string after = "";
				// Если оба дерева переводятся в запись JSON
				if(bridge.encode(value, before, codec::bridge_t::format_t::JSON) &&
				   bridge.encode(second, after, codec::bridge_t::format_t::JSON)){
					// Увеличиваем счёт выполненных проверок равенства
					totals.equal++;
					// Если дерево обратного хода исходному не равно
					if(before != after){
						// Увеличиваем счёт найденных нарушений договора
						totals.findings++;
						// Выводим сообщение о нарушении равенства исходному дереву
						::fprintf(stderr, "НАХОДКА %s: круг вернул иное дерево\n  было: «%s»\n  стало: «%s»\n  запись: «%s»\n", names[i], before.c_str(), after.c_str(), first.c_str());
						// Если остановка на первой находке затребована
						if(halt)
							// Выходим из приложения с признаком находки
							return 1;
					}
				}
			}
			// Собираемая запись второго прохода
			string next = "";
			// Если перевод дерева второго прохода отвечен отказом
			if(!bridge.encode(second, next, formats[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Собираемое дерево значений третьего прохода
			codec::abc::value_t third;
			// Если разбор записи второго прохода отвечен отказом
			if(!bridge.decode(next, third, formats[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Собираемая запись третьего прохода
			string last = "";
			// Если перевод дерева третьего прохода отвечен отказом
			if(!bridge.encode(third, last, formats[i]))
				// Продолжаем перебор видов записи дальше
				continue;
			// Увеличиваем счёт выполненных проверок неподвижности круга
			totals.stable++;
			/**
			 * Если записи второго и третьего проходов разошлись
			 *
			 * @warning Расхождение это означает, что круг перевода ПОЛЗЁТ: дерево,
			 *          сквозь формат прошедшее, обязано давать ту же самую запись
			 *          сколько угодно раз. Ползущий круг остаётся разбираемым, и
			 *          оттого порок его тих
			 */
			if(next != last){
				// Увеличиваем счёт найденных нарушений договора
				totals.findings++;
				// Выводим сообщение о нарушении неподвижности круга
				::fprintf(stderr, "НАХОДКА %s: круг ползёт\n  второй проход: «%s»\n  третий проход: «%s»\n  первый проход: «%s»\n  дерево: «%s»\n  сужение: %u, пустой узел: %u, пометка: «%s», глубина: %u\n", names[i], next.c_str(), last.c_str(), first.c_str(), [&]{ string dump = ""; static_cast <void> (bridge.encode(value, dump, codec::bridge_t::format_t::JSON)); return dump; }().c_str(), static_cast <uint32_t> (bridge.settings().narrow), static_cast <uint32_t> (bridge.settings().empty), bridge.settings().array.c_str(), bridge.settings().depth);
				// Если остановка на первой находке затребована
				if(halt)
					// Выходим из приложения с признаком находки
					return 1;
			}
		}
	}
	// Выводим итог проделанной работы
	::fprintf(stdout, "ЗЕРНО=%llu ПРОХОДОВ=%llu ГЛУБИНА=%u\n", static_cast <unsigned long long> (seed), static_cast <unsigned long long> (count), deep);
	::fprintf(stdout, "  деревьев построено: %llu\n", static_cast <unsigned long long> (totals.trees));
	::fprintf(stdout, "  находок договора: %llu\n", static_cast <unsigned long long> (totals.findings));
	::fprintf(stdout, "  переводов выполнено: %llu, из них отвечено отказом: %llu\n", static_cast <unsigned long long> (totals.encodes), static_cast <unsigned long long> (totals.refusals));
	::fprintf(stdout, "  проверок честности отказа: %llu\n", static_cast <unsigned long long> (totals.honesty));
	::fprintf(stdout, "  проверок разбираемости собранного: %llu\n", static_cast <unsigned long long> (totals.parsed));
	::fprintf(stdout, "  проверок неподвижности круга: %llu\n", static_cast <unsigned long long> (totals.stable));
	::fprintf(stdout, "  проверок равенства исходному дереву: %llu\n", static_cast <unsigned long long> (totals.equal));
	::fprintf(stdout, "  проверок переезда JSON в YAML: %llu\n", static_cast <unsigned long long> (totals.moved));
	// Выполняем перебор всех видов записи
	for(size_t i = 0; i < (sizeof(formats) / sizeof(formats[0])); i++)
		// Выводим счёт отказов по очередному виду записи
		::fprintf(stdout, "  отказов %s: %llu\n", names[i], static_cast <unsigned long long> (totals.refused[i]));
	// Названия причин отказа перевода
	const char * reasons[] = {"нет отказа", "разбор", "запись", "вид неведом", "глубина"};
	// Выполняем перебор всех причин отказа
	for(size_t i = 0; i < (sizeof(reasons) / sizeof(reasons[0])); i++)
		// Выводим счёт отказов по очередной причине
		::fprintf(stdout, "  по причине «%s»: %llu\n", reasons[i], static_cast <unsigned long long> (totals.reasons[i]));
	// Выводим код выхода по наличию находок
	return ((totals.findings > 0) ? 1 : 0);
}
