/**
 * @brief Внутренние вспомогательные функции генератора (внутренняя компоновка)
 *
 */
namespace {
	/**
	 * @brief Функция кодирования целого переменной длины QUIC (RFC 9000 §16)
	 *
	 * @param value кодируемое значение
	 * @return      закодированное значение
	 *
	 */
	string varint(const uint64_t value) noexcept {
		// Результат работы функции - закодированное значение
		string result;
		// Если значение помещается в один октет
		if(value <= 0x3F)
			// Дописываем однооктетное представление
			result.push_back(static_cast <char> (value & 0xFF));
		// Если значение помещается в два октета
		else if(value <= 0x3FFF) {
			// Дописываем старший октет с признаком длины
			result.push_back(static_cast <char> (0x40 | ((value >> 8) & 0x3F)));
			// Дописываем младший октет значения
			result.push_back(static_cast <char> (value & 0xFF));
		// Если значение помещается в четыре октета
		} else if(value <= 0x3FFFFFFF) {
			// Дописываем старший октет с признаком длины
			result.push_back(static_cast <char> (0x80 | ((value >> 24) & 0x3F)));
			/**
			 * Выполняем дозапись оставшихся октетов значения
			 */
			for(int32_t shift = 16; shift >= 0; shift -= 8)
				// Дописываем очередной октет значения
				result.push_back(static_cast <char> ((value >> shift) & 0xFF));
		// Если значение требует восьми октетов
		} else {
			// Дописываем старший октет с признаком длины
			result.push_back(static_cast <char> (0xC0 | ((value >> 56) & 0x3F)));
			/**
			 * Выполняем дозапись оставшихся октетов значения
			 */
			for(int32_t shift = 48; shift >= 0; shift -= 8)
				// Дописываем очередной октет значения
				result.push_back(static_cast <char> ((value >> shift) & 0xFF));
		}
		// Выводим закодированное значение
		return result;
	}
	/**
	 * @brief Функция сборки кадра HTTP/3
	 *
	 * @param type    тип кадра
	 * @param payload полезная нагрузка кадра
	 * @return        собранный кадр
	 *
	 */
	string frame(const uint64_t type, const string & payload) noexcept {
		// Выводим собранный кадр
		return (::varint(type) + ::varint(payload.size()) + payload);
	}
};

/**
 * @brief Функция генератора нештатного трафика HTTP/3
 *
 * @details Генератор структурный: потоки формируются валидными для текущего состояния
 *          соединения (управляющий поток начинается с SETTINGS, потоки инструкций QPACK
 *          несут настоящие инструкции кодера, секции полей кодируются настоящим кодером
 *          с динамической таблицей), и лишь часть кадров портится точечной заменой байта.
 *          Без этого разбор обрывался бы на первом же кадре и глубокие состояния сессии
 *          не достигались.
 *
 *          Главное отличие от генератора HTTP/2 - чередование потоков. В HTTP/2 весь
 *          обмен идёт одним потоком байт, а в HTTP/3 каждый поток QUIC доставляется
 *          независимо, поэтому порядок прихода кусков разных потоков произволен.
 *          Генератор именно его и перебирает: куски всех потоков перемешиваются
 *          с сохранением порядка внутри каждого потока. Так достигаются состояния,
 *          недостижимые последовательной подачей: секция полей приходит раньше вставок
 *          в таблицу QPACK, поток блокируется и разблокируется, инструкции декодера
 *          обгоняют собственные секции.
 *
 *          Пользовательские функции обратного вызова намеренно ведут себя враждебно:
 *          изредка требуют сбросить поток и вызывают reset()/clear() прямо из обработчика.
 *          Именно этот класс реентрантности дважды давал дефекты работы с памятью
 *          в парсере HTTP/2.
 *
 * @param argc количество параметров командной строки
 * @param argv параметры командной строки
 * @return     код выхода процесса
 *
 */
int32_t main(int32_t argc, char * argv[]) noexcept {
	// Количество итераций генератора (по две сессии на итерацию - клиент и сервер)
	const int32_t count = ((argc > 1) ? ::atoi(argv[1]) : 3000);
	// Создаём объект фреймворка
	unique_ptr <awh::fmk_t> fmk(new awh::fmk_t());
	// Создаём объект для работы с логами
	unique_ptr <awh::log_t> log(new awh::log_t(fmk.get()));
	// Отключаем вывод логов: генератор намеренно создаёт ошибочный трафик
	log->level(awh::log_t::level_t::NONE);
	// Инициализируем генератор псевдослучайных чисел фиксированным зерном (воспроизводимость)
	mt19937 rng(20260727);
	// Количество выполненных сессий
	size_t sessions = 0;
	// Количество сессий, переживших весь входящий поток
	size_t deep = 0;
	// Количество сформированных кадров
	size_t frames = 0;
	// Количество испорченных кадров
	size_t corrupted = 0;
	// Количество поданных кусков потоков
	size_t pieces = 0;
	/**
	 * Выполняем перебор всех итераций генератора
	 */
	for(int32_t iteration = 0; iteration < count; ++iteration){
		/**
		 * Выполняем перебор обеих ролей эндпоинта
		 */
		for(int32_t direct = 0; direct < 2; ++direct){
			// Определяем роль проверяемого эндпоинта
			const bool server = (direct != 0);
			// Создаём объект парсера проверяемой роли
			unique_ptr <parser_http3_t> parser(new parser_http3_t(server ? direct_t::REQUEST : direct_t::RESPONSE, fmk.get(), log.get()));
			/**
			 * Однонаправленные потоки нумеруются по роли инициатора (RFC 9000 §2.1):
			 * клиент выдаёт 2, 6, 10, сервер - 3, 7, 11
			 */
			int64_t local = (server ? 3 : 2);
			// Устанавливаем функцию обратного вызова открытия однонаправленного потока
			parser->on(parser_http3_t::open_callback_t([&]() noexcept -> int64_t {
				// Изредка транспорт отказывает в выдаче потока
				if((rng() % 64) == 0)
					// Выводим признак отказа транспорта
					return -1;
				// Выделяем идентификатор однонаправленного потока
				const int64_t sid = local;
				// Продвигаем идентификатор следующего однонаправленного потока
				local += 4;
				// Выводим идентификатор открытого потока
				return sid;
			}));
			// Устанавливаем функцию обратного вызова записи исходящих байтов потока
			parser->on(parser_http3_t::write_callback_t([&](const uint64_t, const void * buffer, const size_t size, const bool) noexcept {
				// Контрольная сумма исходящих байтов
				volatile uint8_t sum = 0;
				/**
				 * Вычитываем весь буфер: обращение к нему ловит висячие представления
				 */
				for(size_t i = 0; i < size; ++i)
					// Накапливаем контрольную сумму исходящих байтов
					sum = static_cast <uint8_t> (sum ^ static_cast <const uint8_t *> (buffer)[i]);
			}));
			// Устанавливаем функцию обратного вызова обрыва потока
			parser->on(parser_http3_t::abort_callback_t([&](const uint64_t, const parser_http3_t::error_t, const bool) noexcept {
				// Изредка приложение сбрасывает состояние соединения прямо из обработчика
				if((rng() % 512) == 0)
					// Выполняем сброс состояния соединения
					parser->reset();
			}));
			// Устанавливаем функцию обратного вызова ошибки уровня соединения
			parser->on(parser_http3_t::error_callback_t([&](const parser_http3_t::error_t, const string_view message) noexcept {
				// Обращаемся к представлению описания ошибки: оно ссылается во внутренний буфер
				volatile size_t length = message.size();
				// Не используемый результат
				(void) length;
			}));
			// Устанавливаем функцию обратного вызова фрагмента тела потока
			parser->on(parser_http3_t::data_callback_t([&](const uint64_t, const void * buffer, const size_t size, const bool) noexcept -> bool {
				// Контрольная сумма тела потока
				volatile uint8_t sum = 0;
				/**
				 * Вычитываем всё тело: обращение к буферу ловит висячие представления
				 */
				for(size_t i = 0; i < size; ++i)
					// Накапливаем контрольную сумму тела
					sum = static_cast <uint8_t> (sum ^ static_cast <const uint8_t *> (buffer)[i]);
				// Изредка приложение полностью очищает парсер прямо из обработчика
				if((rng() % 256) == 0)
					// Выполняем очистку парсера
					parser->clear();
				// Изредка приложение требует сбросить поток
				return ((rng() % 64) != 0);
			}));
			// Устанавливаем функцию обратного вызова поля секции
			parser->on(parser_http3_t::header_callback_t([&](const uint64_t, const string_view name, const string_view value, const parser_t::part_t) noexcept -> bool {
				// Обращаемся к представлениям поля: они ссылаются в арену декодера
				volatile size_t length = (name.size() + value.size());
				// Не используемый результат
				(void) length;
				// Изредка приложение сбрасывает состояние соединения прямо из обработчика
				if((rng() % 256) == 0)
					// Выполняем сброс состояния соединения
					parser->reset();
				// Изредка приложение требует сбросить поток
				return ((rng() % 128) != 0);
			}));
			// Устанавливаем функцию обратного вызова открытия нового потока
			parser->on(parser_http3_t::begin_callback_t([&](const uint64_t) noexcept -> bool {
				// Изредка приложение отклоняет поток
				return ((rng() % 32) != 0);
			}));
			// Устанавливаем функцию обратного вызова фазы приёма сообщения потока
			parser->on(parser_http3_t::phase_callback_t([&](const uint64_t, const parser_t::phase_t, const parser_t::part_t) noexcept -> bool {
				// Изредка приложение сбрасывает состояние соединения прямо из обработчика
				if((rng() % 512) == 0)
					// Выполняем сброс состояния соединения
					parser->reset();
				// Изредка приложение требует сбросить поток
				return ((rng() % 128) != 0);
			}));
			// Устанавливаем функцию обратного вызова закрытия потока
			parser->on(parser_http3_t::close_callback_t([&](const uint64_t, const parser_http3_t::error_t) noexcept {
				// Изредка приложение сбрасывает состояние соединения прямо из обработчика
				if((rng() % 512) == 0)
					// Выполняем сброс состояния соединения
					parser->reset();
			}));
			// Устанавливаем функцию обратного вызова анонса server push
			parser->on(parser_http3_t::push_callback_t([&](const uint64_t, const uint64_t) noexcept -> bool {
				// Изредка приложение отклоняет push
				return ((rng() % 8) != 0);
			}));
			// Устанавливаем функцию обратного вызова завершения соединения пиром
			parser->on(parser_http3_t::goaway_callback_t([&](const uint64_t) noexcept {
				// Изредка приложение сбрасывает состояние соединения прямо из обработчика
				if((rng() % 256) == 0)
					// Выполняем сброс состояния соединения
					parser->reset();
			}));
			// Получаем параметры соединения парсера
			parser_http3_t::settings_t settings = parser->settings();
			// Разрешаем расширенный метод CONNECT (RFC 9220)
			settings.enableConnectProtocol = 1;
			// Применяем параметры соединения парсера
			parser->settings(settings);
			// Отправляем параметры соединения
			parser->sendSettings();
			/**
			 * Двунаправленные потоки в HTTP/3 инициирует только клиент (RFC 9114 §6.1),
			 * поэтому в роли клиента запросы открываем мы сами, а пир отвечает на них
			 */
			// Идентификатор следующего двунаправленного потока
			uint64_t bidi = 0;
			// Список двунаправленных потоков, участвующих в обмене
			vector <uint64_t> streams;
			// Определяем количество потоков запросов сессии
			const int32_t requests = (1 + static_cast <int32_t> (rng() % 4));
			/**
			 * Выполняем открытие всех потоков запросов сессии
			 */
			for(int32_t i = 0; i < requests; ++i){
				// Запоминаем идентификатор потока запроса
				streams.push_back(bidi);
				// Продвигаем идентификатор следующего двунаправленного потока
				bidi += 4;
			}
			// Если проверяется клиент - открываем потоки запросов своей отправкой
			if(!server){
				/**
				 * Выполняем отправку запроса на каждом потоке
				 */
				for(const auto sid : streams){
					// Список полей запроса
					vector <awh::http::h3::qpack::field_t> fields;
					// Дописываем псевдо-поле метода запроса
					fields.emplace_back(":method", (((rng() & 1) != 0) ? "GET" : "POST"));
					// Дописываем псевдо-поле схемы запроса
					fields.emplace_back(":scheme", "https");
					// Дописываем псевдо-поле пути запроса
					fields.emplace_back(":path", "/x");
					// Дописываем псевдо-поле авторитета запроса
					fields.emplace_back(":authority", "example.com");
					// Дописываем обычное поле переменной длины
					fields.emplace_back("x-n", string(1 + (rng() % 64), 'q'));
					// Отправляем секцию полей запроса
					parser->sendHeaders(sid, fields, ((rng() % 3) == 0));
				}
			}
			// Создаём объект кодера полей пира, синхронный с декодером парсера
			awh::http::h3::qpack::encoder_t encoder;
			/**
			 * Ёмкость таблицы задаётся методом, а не конструктором: только метод ставит
			 * в поток кодера инструкцию изменения ёмкости, без которой таблица декодера
			 * останется нулевой и первая же вставка будет отвергнута (RFC 9204 §3.2.3)
			 */
			// Устанавливаем ёмкость динамической таблицы кодера пира
			encoder.maxCapacity(4096);
			// Устанавливаем число потоков, которым разрешено ожидать пополнения таблицы
			encoder.maxBlocked(16);
			// Байты потоков пира в порядке отправки внутри каждого потока
			map <uint64_t, string> input;
			// Признаки завершения потоков пира
			map <uint64_t, bool> endings;
			/**
			 * Однонаправленные потоки пира нумеруются противоположно нашим
			 */
			// Идентификатор управляющего потока пира
			const uint64_t control = (server ? 2 : 3);
			// Идентификатор потока инструкций кодера пира
			const uint64_t encoderStream = (server ? 6 : 7);
			// Идентификатор потока инструкций декодера пира
			const uint64_t decoderStream = (server ? 10 : 11);
			// Собираем нагрузку кадра параметров соединения пира
			string options;
			// Дописываем ёмкость динамической таблицы QPACK
			options += (::varint(0x01) + ::varint(4096));
			// Дописываем число потоков, которым разрешено ожидать пополнения таблицы
			options += (::varint(0x07) + ::varint(16));
			// Изредка дописываем зарезервированный параметр: он обязан игнорироваться
			if((rng() % 4) == 0)
				// Дописываем зарезервированный параметр соединения
				options += (::varint(0x1F * (rng() % 16) + 0x21) + ::varint(rng()));
			// Открываем управляющий поток пира кадром параметров соединения
			input[control] = (::varint(0x00) + ::frame(0x04, options));
			// Открываем поток инструкций кодера пира
			input[encoderStream] = ::varint(0x02);
			// Дописываем инструкцию изменения ёмкости, выставленную кодером при настройке
			input[encoderStream].append(encoder.pending());
			// Освобождаем выданные кодером инструкции
			encoder.consumePending(encoder.pending().size());
			// Открываем поток инструкций декодера пира
			input[decoderStream] = ::varint(0x03);
			// Идентификатор следующего однонаправленного потока пира
			uint64_t peer = (server ? 14 : 15);
			// Верхняя граница идентификаторов push, анонсированная пиром
			uint64_t pushId = 0;
			// Граница завершения соединения, анонсированная пиром
			uint64_t goaway = 4096;
			/**
			 * Количество секций полей, отправленных пиром на каждом потоке
			 *
			 * Порядок кадров в потоке запроса задан жёстко (RFC 9114 §4.1): секция
			 * заголовков, тело, секция трейлеров - и всё, что после трейлеров, уже
			 * ошибка соединения. Без учёта этого счётчика сессия обрывалась бы
			 * на первом же теле после трейлеров, не добираясь до глубоких состояний
			 */
			map <uint64_t, int32_t> sections;
			// Определяем количество формируемых кадров сессии
			const int32_t total = (4 + static_cast <int32_t> (rng() % 20));
			/**
			 * Выполняем формирование всех кадров сессии
			 */
			for(int32_t i = 0; i < total; ++i){
				// Буфер формируемых байт
				string current;
				// Идентификатор потока формируемых байт
				uint64_t sid = control;
				/**
				 * Выбираем тип формируемых байт
				 */
				switch(rng() % 12){
					// Секция полей на потоке запроса
					case 0: case 1: case 2: case 3: {
						// Список потоков, готовых принять ещё одну секцию полей
						vector <uint64_t> ready;
						/**
						 * Выполняем отбор потоков, где секция полей ещё допустима
						 */
						for(const auto item : streams){
							// Если поток ещё не получил секцию трейлеров
							if(sections[item] < 2)
								// Дописываем поток в список готовых
								ready.push_back(item);
						}
						// Если готовых потоков нет - кадр не формируется
						if(ready.empty())
							// Прекращаем формирование кадра
							break;
						// Выбираем поток запроса
						sid = ready[rng() % ready.size()];
						// Список полей секции
						vector <awh::http::h3::qpack::field_t> fields;
						// Если формируется запрос клиента
						if(server){
							// Дописываем псевдо-поле метода запроса
							fields.emplace_back(":method", (((rng() & 1) != 0) ? "GET" : "POST"));
							// Дописываем псевдо-поле схемы запроса
							fields.emplace_back(":scheme", "https");
							// Дописываем псевдо-поле пути запроса
							fields.emplace_back(":path", "/x");
							// Дописываем псевдо-поле авторитета запроса
							fields.emplace_back(":authority", "example.com");
							// Изредка формируем запрос расширенного метода CONNECT
							if((rng() % 8) == 0){
								// Заменяем метод запроса на расширенный CONNECT
								fields[0].value = "CONNECT";
								// Дописываем псевдо-поле протокола туннеля
								fields.emplace_back(":protocol", "websocket");
							}
						// Иначе формируем ответ сервера
						} else fields.emplace_back(":status", "200");
						// Дописываем обычное поле переменной длины
						fields.emplace_back("x-n", string(1 + (rng() % 64), 'q'));
						// Буфер закодированной секции полей
						string section;
						// Кодируем секцию полей
						encoder.encode(sid, fields, section, ((rng() & 1) != 0));
						// Получаем инструкции, которые кодер выставил в свой поток
						const string_view instructions = encoder.pending();
						// Если инструкции есть
						if(!instructions.empty()){
							// Дописываем инструкции в поток кодера пира
							input[encoderStream].append(instructions);
							// Освобождаем выданные инструкции
							encoder.consumePending(instructions.size());
						}
						// Считаем отправленную на потоке секцию полей
						sections[sid]++;
						// Формируем кадр секции полей
						current = ::frame(0x01, section);
					} break;
					// Данные тела на потоке запроса
					case 4: case 5: {
						// Список потоков, готовых принять тело сообщения
						vector <uint64_t> ready;
						/**
						 * Выполняем отбор потоков, где тело сообщения ещё допустимо
						 */
						for(const auto item : streams){
							// Если поток открыт секцией заголовков и ещё не закрыт трейлерами
							if(sections[item] == 1)
								// Дописываем поток в список готовых
								ready.push_back(item);
						}
						// Если готовых потоков нет - кадр не формируется
						if(ready.empty())
							// Прекращаем формирование кадра
							break;
						// Выбираем поток, открытый секцией заголовков
						sid = ready[rng() % ready.size()];
						// Формируем кадр тела потока
						current = ::frame(0x00, string(rng() % 512, 'd'));
						// Изредка завершаем поток вместе с телом
						if((rng() % 4) == 0)
							// Помечаем поток завершённым
							endings[sid] = true;
					} break;
					/**
					 * Изменение ёмкости динамической таблицы QPACK
					 *
					 * Инструкция ставится самим кодером, а не собирается вручную: ручная
					 * вытеснила бы записи, на которые кодер ещё ссылается, и соединение
					 * рвалось бы на первой же ссылке - проверялся бы разъезд состояний,
					 * которого настоящий пир не допускает
					 */
					case 6: {
						// Формируем поток инструкций кодера пира
						sid = encoderStream;
						// Меняем ёмкость динамической таблицы кодера пира
						encoder.maxCapacity(rng() % 4097);
						// Получаем инструкции, которые кодер выставил в свой поток
						const string_view instructions = encoder.pending();
						// Забираем выставленные кодером инструкции
						current.assign(instructions.data(), instructions.size());
						// Освобождаем выданные инструкции
						encoder.consumePending(instructions.size());
					} break;
					// Обновление расширенного приоритета потока запроса
					case 7: {
						/**
						 * PRIORITY_UPDATE шлёт только клиент: сервер такие кадры слать
						 * не вправе, а клиент при их получении рвёт соединение
						 * (RFC 9218 §7.2). Когда испытуемый парсер - клиент, пир здесь
						 * сервер, и кадр формировать нельзя
						 */
						if(!server)
							// Прекращаем формирование кадра
							break;
						// Приоритет обновляется на управляющем потоке
						sid = control;
						// Таблица проверяемых значений поля приоритета
						static const char * values[] = {"u=0", "u=7, i", "i", "u=3", "garbage", "u=9", "", "u=2, i=?0"};
						// Формируем кадр обновления приоритета потока запроса
						current = ::frame(0x0F0700, ::varint(streams[rng() % streams.size()]) + values[rng() % 8]);
					} break;
					// Кадр зарезервированного типа обязан игнорироваться
					case 8: {
						// Выбираем поток формируемого кадра
						sid = (((rng() & 1) != 0) ? control : streams[rng() % streams.size()]);
						// Формируем кадр зарезервированного типа
						current = ::frame((0x1F * (rng() % 64) + 0x21), string(rng() % 64, 'g'));
					} break;
					// Однонаправленный поток неизвестного типа обязан отбрасываться
					case 9: {
						// Выделяем идентификатор нового однонаправленного потока пира
						sid = peer;
						// Продвигаем идентификатор следующего однонаправленного потока пира
						peer += 4;
						// Формируем поток неизвестного типа
						current = (::varint(0x40 + (rng() % 1024)) + string(rng() % 128, 'u'));
					} break;
					// Управление границей идентификаторов push и завершением соединения
					case 10: {
						// Оба кадра идут на управляющем потоке
						sid = control;
						/**
						 * Выбираем формируемый кадр по роли пира: MAX_PUSH_ID шлёт только
						 * клиент, а PUSH_PROMISE и GOAWAY с идентификатором потока - сервер
						 */
						if(server){
							/**
							 * Граница идентификаторов push обязана только расти, а завершение
							 * соединения - только сужаться (RFC 9114 §7.2.7, §5.2). Нарушение
							 * рвёт соединение, поэтому нарушается изредка: иначе сессия
							 * обрывалась бы на первом же таком кадре
							 */
							// Продвигаем верхнюю границу идентификаторов push
							pushId += (1 + (rng() % 8));
							// Формируем кадр верхней границы идентификаторов push
							current = ::frame(0x0D, ::varint(((rng() % 8) == 0) ? (rng() % 64) : pushId));
						// Иначе формируем кадр завершения соединения
						} else {
							// Сужаем границу завершения соединения
							goaway -= (4 * ::min <uint64_t> (goaway / 4, 1 + (rng() % 4)));
							// Формируем кадр завершения соединения
							current = ::frame(0x07, ::varint(((rng() % 8) == 0) ? (4 * (rng() % 64)) : goaway));
						}
					} break;
					/**
					 * Вставка в динамическую таблицу без ссылки на существующую запись
					 *
					 * Инструкция ставится самим кодером через принудительную индексацию
					 * поля, значение которого он ещё не встречал
					 */
					case 11: {
						// Формируем поток инструкций кодера пира
						sid = encoderStream;
						// Список полей вспомогательной секции
						vector <awh::http::h3::qpack::field_t> fields;
						// Дописываем поле с ранее не встречавшимся значением
						fields.emplace_back("x-fuzz", string(1 + (rng() % 96), static_cast <char> ('a' + (rng() % 26))));
						// Буфер закодированной вспомогательной секции
						string section;
						// Кодируем вспомогательную секцию на служебном потоке
						encoder.encode(streams[rng() % streams.size()], fields, section, ((rng() & 1) != 0));
						// Получаем инструкции, которые кодер выставил в свой поток
						const string_view instructions = encoder.pending();
						// Забираем выставленные кодером инструкции
						current.assign(instructions.data(), instructions.size());
						// Освобождаем выданные инструкции
						encoder.consumePending(instructions.size());
					} break;
				}
				// Если байты не сформированы - переходим к следующему кадру
				if(current.empty())
					// Переходим к следующему кадру
					continue;
				// Изредка портим случайный байт кадра
				if((rng() % 12) == 0){
					// Заменяем случайный байт кадра
					current[rng() % current.size()] = static_cast <char> (rng() & 0xFF);
					// Наращиваем счётчик испорченных кадров
					++corrupted;
				}
				// Дописываем байты в поток пира
				input[sid].append(current);
				// Наращиваем счётчик сформированных кадров
				++frames;
			}
			/**
			 * Подаём куски потоков вперемешку: транспорт QUIC доставляет потоки
			 * независимо, поэтому порядок прихода кусков разных потоков произволен,
			 * а порядок внутри одного потока сохраняется
			 */
			// Текущие позиции подачи по потокам
			map <uint64_t, size_t> positions;
			// Количество потоков, поданных не до конца
			size_t rest = input.size();
			/**
			 * Выполняем подачу, пока остались неподанные потоки
			 */
			while(rest > 0){
				// Пропускаемое количество потоков до выбранного
				size_t skip = (rng() % rest);
				// Идентификатор выбранного потока
				uint64_t sid = 0;
				// Признак того, что поток выбран
				bool found = false;
				/**
				 * Выполняем поиск выбранного потока среди неподанных
				 */
				for(const auto & item : input){
					// Если поток уже подан целиком - пропускаем его
					if(positions[item.first] >= item.second.size())
						// Переходим к следующему потоку
						continue;
					// Если пропускать больше нечего - поток выбран
					if(skip == 0){
						// Запоминаем идентификатор выбранного потока
						sid = item.first;
						// Помечаем поток выбранным
						found = true;
						// Прекращаем поиск
						break;
					}
					// Уменьшаем количество пропускаемых потоков
					skip--;
				}
				// Если поток не выбран - прекращаем подачу
				if(!found)
					// Прекращаем подачу потоков
					break;
				// Получаем байты выбранного потока
				const string & data = input[sid];
				// Вычисляем размер очередного куска
				const size_t size = ::min <size_t> (1 + (rng() % 29), data.size() - positions[sid]);
				// Определяем, завершается ли поток этим куском
				const bool fin = (((positions[sid] + size) >= data.size()) && endings[sid]);
				// Выполняем разбор очередного куска
				parser->parse(sid, data.data() + positions[sid], size, fin);
				// Сдвигаем позицию подачи потока
				positions[sid] += size;
				// Наращиваем счётчик поданных кусков
				++pieces;
				// Если поток подан целиком - уменьшаем количество неподанных
				if(positions[sid] >= data.size())
					// Уменьшаем количество неподанных потоков
					rest--;
			}
			// Если разбор входящего потока не оборвался ошибкой соединения
			if(parser->status() != parser_t::status_t::ERROR)
				// Наращиваем счётчик выживших сессий
				++deep;
			/**
			 * Выполняем собственную отправку на каждом потоке обмена
			 */
			for(const auto sid : streams){
				// Список полей исходящего сообщения
				vector <awh::http::h3::qpack::field_t> fields;
				// Если проверяется сервер - формируем ответ
				if(server)
					// Дописываем псевдо-поле статуса ответа
					fields.emplace_back(":status", "200");
				// Иначе формируем запрос
				else {
					// Дописываем псевдо-поле метода запроса
					fields.emplace_back(":method", "POST");
					// Дописываем псевдо-поле схемы запроса
					fields.emplace_back(":scheme", "https");
					// Дописываем псевдо-поле пути запроса
					fields.emplace_back(":path", "/");
					// Дописываем псевдо-поле авторитета запроса
					fields.emplace_back(":authority", "example.com");
				}
				// Отправляем секцию полей исходящего сообщения
				parser->sendHeaders(sid, fields, false);
				// Формируем тело исходящего сообщения
				const string body(rng() % 8192, 'z');
				// Текущая позиция отправки тела
				size_t offset = 0;
				/**
				 * Отправляем тело порциями, пока парсер их принимает
				 */
				while(offset < body.size()){
					// Передаём очередную порцию тела
					const size_t taken = parser->sendData(sid, body.data() + offset, body.size() - offset, false);
					// Если порция не принята - прекращаем отправку
					if(taken == 0)
						// Прекращаем отправку тела
						break;
					// Сдвигаем позицию отправки
					offset += taken;
				}
				// Изредка завершаем поток секцией трейлеров
				if((rng() % 3) == 0){
					// Список полей секции трейлеров
					vector <awh::http::h3::qpack::field_t> trailers;
					// Дописываем поле секции трейлеров
					trailers.emplace_back("x-checksum", string(1 + (rng() % 32), 'c'));
					// Отправляем секцию трейлеров с завершением потока
					parser->sendHeaders(sid, trailers, true);
				// Иначе изредка сбрасываем поток
				} else if((rng() % 4) == 0)
					// Отправляем сброс потока
					parser->sendReset(sid, parser_http3_t::error_t::H3_REQUEST_CANCELLED);
				// Изредка анонсируем server push
				if(server && ((rng() % 4) == 0)){
					// Список полей обещанного запроса
					vector <awh::http::h3::qpack::field_t> promise;
					// Дописываем псевдо-поле метода обещанного запроса
					promise.emplace_back(":method", "GET");
					// Дописываем псевдо-поле схемы обещанного запроса
					promise.emplace_back(":scheme", "https");
					// Дописываем псевдо-поле пути обещанного запроса
					promise.emplace_back(":path", "/push");
					// Дописываем псевдо-поле авторитета обещанного запроса
					promise.emplace_back(":authority", "example.com");
					// Отправляем анонс server push
					parser->sendPushPromise(sid, promise);
				}
				// Освобождаем половину накопленных исходящих байт потока (pull-модель)
				parser->consumePending(sid, parser->pending(sid).size() / 2);
			}
			/**
			 * Отвечаем инструкциями потока декодера уже после собственных отправок:
			 * подтверждать нечего, пока секция не отправлена, и поданные раньше
			 * инструкции были бы просто ошибкой протокола, обрывающей сессию
			 */
			// Буфер инструкций потока декодера пира
			string feedback;
			/**
			 * Выполняем перебор всех потоков, на которых мы отправляли секции
			 */
			for(const auto sid : streams){
				/**
				 * Выбираем формируемую инструкцию: подтверждение секции, отмену потока
				 * либо заведомо слепой прирост числа вставок
				 */
				switch(rng() % 6){
					// Подтверждение секции потока
					case 0: case 1: feedback.push_back(static_cast <char> (0x80 | (sid & 0x7F))); break;
					// Отмена потока
					case 2: feedback.push_back(static_cast <char> (0x40 | (sid & 0x3F))); break;
					// Прирост числа вставок сверх известного кодеру
					case 3: feedback.push_back(static_cast <char> (1 + (rng() % 63))); break;
				}
			}
			// Если инструкции сформированы
			if(!feedback.empty())
				// Подаём инструкции потока декодера пира на разбор
				parser->parse(decoderStream, feedback.data(), feedback.size(), false);
			// Изредка завершаем соединение со своей стороны
			if((rng() % 8) == 0)
				// Отправляем завершение соединения
				parser->sendShutdown();
			// Уведомляем парсер о завершении потока данных
			parser->eof();
			// Наращиваем счётчик выполненных сессий
			++sessions;
		}
	}
	// Выводим итоговую статистику генератора
	::printf(
		"http3 fuzz: %zu sessions, %zu frames (%zu corrupted), %zu stream pieces, %zu sessions survived the whole stream\n",
		sessions, frames, corrupted, pieces, deep
	);
	// Выводим успешный код выхода
	return EXIT_SUCCESS;
}
