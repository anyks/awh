#!/bin/sh
#
# @file build.sh
# @date 2026-08-23
#
# @license{LicenseRef-AWH-1.0}
#
# @author Yuriy Lobarev
#
# @brief Сборка ворошителя кодека из исходных текстов, без собранной библиотеки
#
# @details Кодеки опираются на журнал работы фреймворка, а тот — на средства времени,
#          строк, кодировок и распределителя памяти. Договор сборки, перечислявший
#          лишь части кодека, с заведением журнала связываться перестал, и ворошитель
#          собрать стало нечем
#
# @warning Связывать ворошитель с «build/libawh.a» НЕЛЬЗЯ: части кодека собираются тут
#          же из свежих исходных текстов, а библиотека остаётся от прежней сборки, и
#          ворошитель выходит несогласованным. Отчитывается он при этом находкою, какая
#          точными настройками из её же отчёта не воспроизводится, — на розыск такой
#          мнимой находки уходит час. Оттого тело фреймворка берётся здесь исходными
#          текстами наравне с кодеком
#
# @note Перечень частей фреймворка держится ВРУЧНУЮ по образцу отдельных стендов
#       проверок: маскою его не снять, сборщик отбирает часть распределителя по системе
#
# @copyright Copyright © 2026
#
# Вызов:
#   tools/fuzz/build.sh <имя кодека> [корень дерева] [каталог сборки]
#
# Переменные окружения:
#   CXX    — собиратель, по умолчанию «c++»
#   FLAGS  — добавочные ключи сборки
#   SANITIZE — набор надзирателей, по умолчанию «address,undefined»; пустое значение
#              отключает их вовсе. У целей MS Windows отключается само: тел
#              надзирателей у MinGW нет, и связывание валится на «cannot find -lasan»
#

# Прекращаем работу при первом же отказе
set -e

# Получаем имя кодека, ворошитель какого собирается
CODEC="$1"

# Проверяем, задано ли имя кодека
if [ -z "$CODEC" ]; then
	echo "Вызов: $0 <имя кодека || --all> [корень дерева] [каталог сборки]" >&2
	exit 1
fi

# Получаем корень дерева исходных текстов
ROOT="${2:-$(cd "$(dirname "$0")/../.." && pwd)}"

##
# Сборка ВСЕХ целей подряд по доводу «--all»
#
# @details Целей у ворошителей два десятка, и собирают их поодиночке и по случаю: ничто
#          не стережёт саму СОБИРАЕМОСТЬ их. Замер 01.09.2026 показал, чего это стоит -
#          четыре цели из восемнадцати не собирались вовсе, и одна из них («abc») лежала
#          сломанной незамеченной, оттого что её просто некому было собрать
#
# @note Обход не прекращается на первом отказе намеренно: нужен ПЕРЕЧЕНЬ сломанных
#       целей, а не первая из них. Код возврата всё же ненулевой, если сломана хоть
#       одна, - иначе обход этот сам стал бы зелёным при сломанном дереве
#
# @note Журнал всякой цели ложится в «$OUTPUT/build-<имя>.log»: без него отказ виден
#       лишь именем, а причина его теряется
##
##
# Замок на каталог сборки: две сборки разом портят друг другу объектные файлы
#
# @details Каталог сборки один на все цели, и объектные файлы в нём зовутся по имени
#          части, а не по имени цели: «codec-value.o» у цели «abc» и у цели
#          «abc-container» - один и тот же файл. Две сборки, идущие разом, пишут в него
#          вперемешку, и связывание отвечает отсутствием знаков, какие на месте
#
# @warning Отказ этот выглядит В ТОЧНОСТИ как сломанная цель, и на розыск мнимой поломки
#          уходит время. Замер 02.09.2026: обход, запущенный вторым при незакончившемся
#          первом, объявил сломанными «abc-container», «csv», «blockprobe» и
#          «deadlockprobe» - все четыре собирались поодиночке без единой правки
#
# @note Замок берётся заведением КАТАЛОГА: работа эта неделима у всякой файловой
#       системы, тогда как проверка наличия файла с последующим заведением его - нет
#
# @note Вложенные вызовы замка не берут: обход зовёт себя же на всякую цель, и второй
#       замок встал бы на первом же из них
##
if [ -z "$AWH_FUZZ_NESTED" ]; then
	LOCKED="${3:-/tmp/awh-fuzz}"
	mkdir -p "$LOCKED"
	if ! mkdir "$LOCKED/.lock" 2>/dev/null; then
		echo "Каталог сборки «$LOCKED» занят другой сборкой: замок «$LOCKED/.lock»." >&2
		echo "Дождитесь её конца либо задайте свой каталог третьим доводом." >&2
		exit 2
	fi
	# Выполняем снятие замка при всяком исходе работы
	trap 'rmdir "$LOCKED/.lock" 2>/dev/null' EXIT INT TERM
fi

if [ "$CODEC" = "--all" ]; then
	# Каталог сборки ворошителей
	OUTPUT="${3:-/tmp/awh-fuzz}"
	# Выполняем заведение каталога сборки
	mkdir -p "$OUTPUT"
	# Перечень сломанных целей
	BROKEN=""
	# Собиратель, каким ведётся сверка текста чужих целей
	COMPILER_ALL="${CXX:-c++}"
	# Количество собранных целей
	BUILT=0
	# Перечень целей, чья сборка ведётся ВНЕ этого договора
	FOREIGN=""
	##
	# Цели, собираемые не этим договором, разбираются ОТДЕЛЬНО
	#
	# @details Ворошители «http1», «http2» и «http3» связываются с готовой библиотекой
	#          проекта («build/libawh.a»), а договор этот такое связывание запрещает
	#          прямо: части собираются здесь из свежих исходных текстов, и библиотека,
	#          оставшаяся от прежней сборки, дала бы ворошителя несогласованного.
	#          Дороги сборки у них свои, описанные в README и в «sh/verify_http*.sh».
	#          Щуп «fdtrace» ворошителем не является вовсе - он входит В сборку другого
	#          ворошителя и своего входа не имеет
	#
	# @warning Молчаливо пропускать их НЕЛЬЗЯ. Замер 02.09.2026: «http1» звал
	#          «method_t::DEL», снятый переименованием договора ещё 05.08.2026, - цель
	#          не собиралась четыре недели, и заметить это было некому именно оттого,
	#          что обход её не трогал. Оттого чужие цели проходят СВЕРКОЙ ТЕКСТА
	#          («-fsyntax-only»): связать их отсюда нечем, а обветшание договора она
	#          ловит ровно то же
	##
	SYNTAX_ONLY=" fdtrace http1 http2 http3 "
	# Выполняем перебор всех целей ворошителей
	for TARGET_NAME in $(ls "$ROOT/tools/fuzz/"*.cpp | sed 's|.*/||; s|\.cpp$||'); do
		##
		# Если цель собирается вне этого договора, поверяем её сверкой текста
		##
		case "$SYNTAX_ONLY" in
			*" $TARGET_NAME "*)
				# Выполняем сверку текста цели, не связывая её
				if $COMPILER_ALL -fsyntax-only -std=gnu++17 -I"$ROOT/include" \
				 -I"$ROOT/contrib/include" -I"$ROOT/third_party/include" \
				 "$ROOT/tools/fuzz/$TARGET_NAME.cpp" > "$OUTPUT/build-$TARGET_NAME.log" 2>&1; then
					# Выполняем учёт цели, поверенной сверкой текста
					FOREIGN="$FOREIGN $TARGET_NAME"
					# Выводим сообщение о поверенной цели
					echo "СВЕРЕН: $TARGET_NAME (сборка своя, см. README)"
				else
					# Выполняем учёт сломанной цели
					BROKEN="$BROKEN $TARGET_NAME"
					# Выводим сообщение о сломанной цели
					echo "ОТКАЗ:  $TARGET_NAME (журнал: $OUTPUT/build-$TARGET_NAME.log)"
				fi
				# Переходим к следующей цели ворошителя
				continue
			;;
		esac
		# Выполняем сборку очередной цели, не прекращая обхода при отказе
		if AWH_FUZZ_NESTED=1 sh "$0" "$TARGET_NAME" "$ROOT" "$OUTPUT" > "$OUTPUT/build-$TARGET_NAME.log" 2>&1; then
			# Выполняем учёт собранной цели
			BUILT=$((BUILT + 1))
			# Выводим сообщение о собранной цели
			echo "СОБРАН: $TARGET_NAME"
		else
			# Выполняем учёт сломанной цели
			BROKEN="$BROKEN $TARGET_NAME"
			# Выводим сообщение о сломанной цели
			echo "ОТКАЗ:  $TARGET_NAME (журнал: $OUTPUT/build-$TARGET_NAME.log)"
		fi
	done
	# Выводим итог обхода
	echo "Целей собрано: $BUILT"
	# Если чужие цели поверены сверкой текста
	if [ -n "$FOREIGN" ]; then
		# Выводим перечень целей, поверенных сверкой текста
		echo "Целей сверено:$FOREIGN"
	fi
	# Если сломанные цели нашлись
	if [ -n "$BROKEN" ]; then
		# Выводим перечень сломанных целей
		echo "Целей сломано:$BROKEN" >&2
		# Выводим признак того, что обход нашёл сломанное
		exit 1
	fi
	# Выводим признак успешного обхода
	exit 0
fi

# Получаем каталог сборки ворошителя
OUTPUT="${3:-/tmp/awh-fuzz}"

# Получаем собиратель
COMPILER="${CXX:-c++}"

# Проверяем наличие ворошителя запрошенного кодека
if [ ! -f "$ROOT/tools/fuzz/$CODEC.cpp" ]; then
	echo "Ворошителя кодека «$CODEC» нет: $ROOT/tools/fuzz/$CODEC.cpp" >&2
	exit 1
fi

# Определяем цель собирателя: по ней решается вопрос о надзирателях
TARGET=$("$COMPILER" -dumpmachine 2>/dev/null || echo "")

# Набор надзирателей, какими собирается ворошитель
#
# Подстановка ведётся БЕЗ двоеточия намеренно: с двоеточием умолчание встаёт и на
# пустое значение, и «SANITIZE=""» надзирателей не снимало вовсе - вопреки описанному
# выше договору. Различие это и есть разница между «переменная не задана» и «задана
# пустой», а договор обещает второе
SANITIZE="${SANITIZE-address,undefined}"

# Уровень оптимизации сборки ворошителя
#
# Переопределяется окружением: разбор пойманного зависания требует "-O0", иначе
# отладчик отвечает "<unavailable>" на всякую переменную и место находки не назвать
LEVEL="${LEVEL:--O1}"

# Отключаем надзирателей у целей MS Windows и поднимаем уровень оптимизации
#
# У MinGW тел надзирателей нет вовсе: сборка доходит до связывания и валится
# на «cannot find -lasan». Проверять это доводом при каждом вызове со стенда
# бестолку - цель собирателя известна ему самому, и решение берётся отсюда.
# Наблюдать за памятью под MS Windows нечем; отчёты со стендов той системы
# сличаются с POSIX по СЧЁТЧИКАМ работы, а не по надзору за памятью.
#
# Уровень поднимается по НЕОБХОДИМОСТИ, а не ради скорости: GCC 16 при «-O1»
# отказывается собирать посредников «always_inline» вовсе, когда они уходят
# предикатом в шаблон - «inlining failed in call to always_inline
# awh::ascii::isDigit: indirect function call with a yet undetermined callee».
# Тело фреймворка такими посредниками устроено намеренно, и «-O1» ему негоден.
case "$TARGET" in
	*mingw*|*windows*|*cygwin*) SANITIZE=""; LEVEL="-O2";;
esac

##
# Проверяем, поддерживает ли собиратель надзирателей на деле
#
# @details Перечнем систем этого не решить: у одного и того же семейства сборки
#          собирателя расходятся. Solaris 11.4 отвечает «-fsanitize=address is not
#          supported in this configuration» и валит сборку целиком - а надзиратель тут
#          не цель, а подспорье, и его отсутствие поводом не ворошить не является
#
# @note Проба ведётся сборкой пустой единицы трансляции: иного способа спросить
#       собирателя о поддержке нет
##
if [ -n "$SANITIZE" ]; then
	##
	# Проба ведёт СВЯЗЫВАНИЕ, и единица её не пуста
	#
	# @warning Пустой единицы мало. Собиратель принимает ключ, тела же надзирателя
	#          вызываются лишь теми проверками, какие в единице встретились: пустая
	#          не тянет ни одного, и проба отвечала удачей там, где связывание потом
	#          валилось. У NetBSD 10.5 так и вышло - тело `__ubsan_handle_dynamic_type
	#          _cache_miss` там отсутствует, и ворошитель встал на нём, пройдя пробу.
	#          Оттого единица несёт многоликий тип и приведение по нему: этим
	#          затягивается проверка указателя на таблицу методов, самая частая у нас
	#
	# @note Двоеточие в конце - чтобы собиратель не убрал приведение как ненужное
	##
	if ! printf '%s\n' 'struct A { virtual ~A(){} };' 'struct B : A { int v = 0; };' 'int main(){ A * a = new B(); B * b = dynamic_cast <B *> (a); const int r = (b != nullptr ? b->v : 1); delete a; return r; }' | $COMPILER -fsanitize=$SANITIZE -x c++ - -o /dev/null > /dev/null 2>&1; then
		echo "надзиратели собирателем не поддержаны: ворошитель собирается без них"
		SANITIZE=""
		##
		# Поднимаем уровень вместе со снятием надзирателя
		#
		# @note По той же причине, что и у MinGW выше: GCC при «-O1» отказывается
		#       собирать посредников «always_inline», ушедших предикатом в шаблон.
		#       Уровень тут связан не с системой, а с ОТСУТСТВИЕМ надзирателя:
		#       Solaris 11.4 упёрся ровно в это, и правило «нет надзирателя - значит
		#       -O2» покрывает обе системы разом
		##
		LEVEL="-O2"
	fi
fi

# Собираем ключи сборки ворошителя
#
# Ключ «-Wswitch» стоит здесь НАМЕРЕННО: ворошители выбирают члены настроек из
# перечней, а полноту тех перечней блюдёт собиратель - сторожа в самих ворошителях
# перебирают члены без ветви «default». Без этого ключа сторожа мертвы: «quoting_t»
# получил четвёртого члена, а выбор брался по остатку от трёх, и целая ветвь записи
# CSV не ворошилась ни разу. Прочие предупреждения ключом «FLAGS» ставит зовущий.
OPTIONS="-std=gnu++17 $LEVEL -g -Wswitch -I$ROOT/include $FLAGS"

##
# Добавляем надзирателей, если они не отменены
#
# @warning Вместе с надзирателем ОБЯЗАТЕЛЕН ключ «AWH_ALLOC_DISABLED», и это не прихоть.
#          У систем ELF наш распределитель встаёт на место системного САМИМ
#          СВЯЗЫВАНИЕМ: файл определяет знак «malloc», и связывающий берёт его, звал кто
#          «capture» или нет. А ASAN при своём заведении расставляет перехватчики и
#          зовёт «malloc» ДО того, как наш распределитель заведён, - и падает внутри
#          «reserve». Замерено на Fedora (glibc 2.41): ворошитель валился с кодом 139
#          даже при НУЛЕ проходов, стек упирался в
#          «__asan::InitializeAsanInterceptors». Без этого ключа НИ ОДИН ворошитель не
#          работает НИ НА ОДНОЙ системе ELF - ни сетевой, ни кодека
#
# @note У macOS того же не случается: там подмена идёт зоной, а не связыванием, и ASAN
#       перехватывает выдачу памяти раньше нас. Оттого дефект и не виден с рабочей машины
#
# @note Потеря невелика: под надзирателем наш распределитель всё равно не работает -
#       ASAN подменяет выдачу памяти собою. Ворошителю поверяется разбор, а не
#       распределитель, и у того есть свой набор проверок
##
if [ -n "$SANITIZE" ]; then
	OPTIONS="-fsanitize=$SANITIZE -DAWH_ALLOC_DISABLED $OPTIONS"
else
	echo "надзиратели отключены (цель $TARGET)"
fi

# Выполняем заведение каталога сборки
mkdir -p "$OUTPUT"

# Выполняем снос прежде собранного ворошителя
#
# @note Снос обязателен: при отказе сборки прежний двоичный файл остаётся на месте
#       и прогон отчитывается успехом по коду, какого в нём уже нет
rm -f "$OUTPUT/$CODEC-fuzz" "$OUTPUT/$CODEC-fuzz.exe"

# Собираем перечень частей тела фреймворка, каких требует журнал работы
FRAMEWORK="src/sys/log.cpp src/sys/chrono.cpp src/sys/fmk.cpp src/net/nwt.cpp
	src/encoding/unicode/normalize.cpp src/encoding/unicode/table.cpp
	src/encoding/unicode/unicode.cpp src/encoding/unicode/utf8.cpp
	src/encoding/charset/charset.cpp src/encoding/charset/table.cpp
	src/alloc/alloc.cpp src/alloc/cache.cpp src/alloc/central.cpp
	src/alloc/classes.cpp src/alloc/guard.cpp src/alloc/huge.cpp
	src/alloc/link.cpp src/alloc/pages.cpp src/alloc/profile.cpp
	src/alloc/source.cpp src/alloc/spin.cpp src/alloc/trace.cpp
	src/alloc/capture/elf.cpp src/alloc/capture/mach.cpp src/alloc/capture/pe.cpp
	src/num/lexical/table.cpp"

##
# Внутренние имена распределителя libc берутся ТОЛЬКО под OpenBSD
#
# Файл «src/alloc/capture/obsd.cpp» собственной охраны по системе не несёт — её несёт
# сборщик: CMakeLists.txt подключает его лишь при OpenBSD. Собранный безусловно, он
# под MinGW валит связывание по «posix_memalign» и «aligned_alloc», каких у той
# библиотеки времени исполнения нет вовсе
##
##
 # Ворошитель распределителя включает файл кода В СЕБЯ
 #
 # Делает он это намеренно: частные входы, заводимые признаком «AWH_ALLOC_DISABLED»,
 # статические, и иначе ворошителю не видны. Оттого тот же файл вторым разом в сборку
 # подавать нельзя — связывание отвечает девятнадцатью задвоенными знаками
 #
 # Прочим ворошителям файл этот нужен как обычно: они распределитель не включают, а
 # лишь пользуются им
 #
if [ "$CODEC" = "alloc" ]; then
	FRAMEWORK=$(echo "$FRAMEWORK" | sed 's|src/alloc/alloc\.cpp||')
	##
	 # Журнал ворошитель распределителя подставляет ПУСТОЙ
	 #
	 # Библиотека целиком ему не нужна, а распределитель зовёт журнал лишь на редких
	 # путях отказа. Подай мы вдобавок настоящий «src/sys/log.cpp» — связывание
	 # отвечает задвоенным «Logging::print»
	 #
	FRAMEWORK=$(echo "$FRAMEWORK" | sed 's|src/sys/log\.cpp||')
fi

if [ "$(uname -s)" = "OpenBSD" ]; then
	FRAMEWORK="$FRAMEWORK src/alloc/capture/obsd.cpp"
fi

##
# Системные библиотеки, каких требует тело фреймворка
#
# У MS Windows журнал зовёт «WSAGetLastError»: посредник «__awh_strerror__» разбирает
# сетевые коды отказов, каких «strerror» от MinGW не знает
#
# «-liphlpapi» нужна сетевой зоне: «if_nametoindex» и «if_indextoname», какими разбор
# адреса переводит зону IPv6 в номер устройства и обратно, у MS Windows живут ИМЕННО
# там, а не в «ws2_32». Без неё связывание валится на них двоих, и валится только у
# сетевой зоны - кодеки этих имён не зовут вовсе, оттого прежде нехватки не было видно
##
##
# У систем Sun вызовы сокетов живут в отдельных библиотеках
#
# @details У Solaris и illumos «socket», «freeifaddrs», «sendmsg» и соседи лежат не в
#          libc, а в libsocket и libnsl, а работа с канальными связями - в libdladm.
#          Связывать их надо ВСЕГДА, а не вместе с SCTP
#
# @warning Прежде эти библиотеки добавлялись ЛИШЬ внутри ветви SCTP, вместе с «-lsctp».
#          У Solaris заголовок SCTP есть, и нехватки не было видно; у illumos его на
#          месте не оказалось, ветвь не сработала, и связывание встало на
#          «__xnet_sendmsg» и «freeifaddrs». Признак у беды тот же, что и у ветви MS
#          Windows ниже: валится только сетевая зона, кодеки этих имён не зовут вовсе
##
case "$(uname -s)" in
	MINGW*|MSYS*|CYGWIN*) SYSTEM_LIBS="-lws2_32 -liphlpapi" ;;
	SunOS) SYSTEM_LIBS="-lsocket -lnsl -ldladm" ;;
	##
	# @warning У NetBSD и OpenBSD «backtrace» и «backtrace_symbols_fd» лежат в
	#          ОТДЕЛЬНОЙ библиотеке «libexecinfo», а не в libc. Заголовок
	#          «execinfo.h» там на месте, и условное включение по «__has_include»
	#          срабатывает, поэтому сборка проходит целиком и валится лишь на
	#          связывании: «undefined reference to backtrace». У FreeBSD и Linux
	#          нехватки не видно, оттого дефект и не всплывал до 31.08.2026
	##
	NetBSD|OpenBSD) SYSTEM_LIBS="-lexecinfo" ;;
	##
	# @warning У DragonFly «pthread_create» лежит в ОТДЕЛЬНОЙ библиотеке, а не в libc,
	#          и собиратель из портов сам её не подключает: сборка проходит целиком и
	#          валится лишь на связывании - «undefined reference to pthread_create» из
	#          «std::thread». У FreeBSD, родителя системы, нехватки не видно, оттого
	#          довод и не был нужен до 04.09.2026
	##
	DragonFly) SYSTEM_LIBS="-pthread -lexecinfo" ;;
	*) SYSTEM_LIBS="" ;;
esac

# Выводим сообщение о начале сборки
echo "Собираем ворошитель кодека $CODEC: $COMPILER"

##
# Сносим кэш целиком при смене строки сборки
#
# Сличение свежести файлов видит правки исходных текстов и заголовков, но НЕ видит смены
# ключей сборки: собрал прежде без санитайзеров, собираешь теперь с ними - и части тела
# фреймворка останутся прежними, собранными иначе. Разнобой этот даёт тот же род
# расхождения, что и устаревший заголовок: отказ, какой по исходным текстам не
# воспроизводится вовсе, а выглядит дефектом поверяемого модуля
#
# Отпечатком служит сама строка сборки: собиратель да ключи. Смена её сносит кэш целиком -
# отбирать по частям тут нечего, ключи общие всем
##
# Собираем отпечаток строки сборки
STAMP="$COMPILER $OPTIONS"
# Определяем место хранения отпечатка
STAMPFILE="$OUTPUT/.options"
# Если прежний отпечаток есть и он не совпадает с нынешним
if [ -f "$STAMPFILE" ] && [ "$(cat "$STAMPFILE")" != "$STAMP" ]; then
	# Сообщаем о сносе кэша
	echo "Строка сборки изменилась: сносим кэш объектных файлов"
	# Сносим прежде собранные объектные файлы
	rm -f "$OUTPUT"/*.o
fi
# Запоминаем отпечаток нынешней строки сборки
printf '%s' "$STAMP" > "$STAMPFILE"

# Заводим перечень объектных файлов ворошителя
OBJECTS=""

# Выполняем перебор всех частей тела фреймворка
for PART in $FRAMEWORK; do
	# Собираем имя объектного файла очередной части
	NAME="$(echo "$PART" | tr '/' '-')"
	##
	# Пересобираем часть лишь тогда, когда исходный текст её свежее объектного файла
	#
	# Тело фреймворка меняется не нами, и пересборка двадцати шести частей на каждый
	# заход ворошителя стоит дороже самого прогона
	##
	##
	# Сличаем И заголовочные файлы, а не один свой исходный текст
	#
	# Прежде сличался лишь сам «$PART», и правка ЧУЖОГО заголовка часть не пересобирала.
	# Расплата за это тяжёлая и обманчивая: правка размера поля в «alloc/profile.hpp»
	# оставила «src-alloc-alloc.cpp.o» с прежним «sizeof(Profile)», отчего область
	# разогрева распределителя вышла тесной, и всякий ворошитель валился под
	# санитайзером с «global-buffer-overflow» в построении Profile - ещё не дойдя до
	# разбора. Отказ этот выглядит дефектом кодека, а на деле принадлежит кэшу сборки, и
	# по исходным текстам он не воспроизводится вовсе. Ровно от такой беды остерегает
	# запрет связывать ворошителя с «build/libawh.a» в начале этого файла - а сам кэш
	# объектных файлов ею же и болел
	#
	# Отказ «find» глушится: у части систем каталог заголовков волен быть недоступен, и
	# тогда пересборка идёт по одному лишь исходному тексту, как было прежде
	##
	CHANGED=""
	# Ищем заголовочный файл свежее объектного
	if [ -f "$OUTPUT/$NAME.o" ]; then
		# Запоминаем первый же найденный
		CHANGED="$(find "$ROOT/include" -name '*.hpp' -newer "$OUTPUT/$NAME.o" 2>/dev/null | head -1)"
	fi
	if [ ! -f "$OUTPUT/$NAME.o" ] || [ "$ROOT/$PART" -nt "$OUTPUT/$NAME.o" ] || [ -n "$CHANGED" ]; then
		$COMPILER $OPTIONS -Wno-c++11-narrowing -c "$ROOT/$PART" -o "$OUTPUT/$NAME.o"
	fi
	# Добавляем собранное к перечню объектных файлов
	OBJECTS="$OBJECTS $OUTPUT/$NAME.o"
done

##
# Отбираем части, какие поверяет ворошитель
#
# @details Ворошители делятся на два рода. У кодека части лежат все разом в
#          «src/codec/<имя>», и перечислять их не нужно — берётся весь каталог.
#          У сетевой зоны своего каталога нет: разбор адресов, разбор URI и сетевой
#          движок живут вперемешку с прочим в «src/net», и части им перечисляются
#          поимённо
#
# @note Движок берётся ПО СИСТЕМЕ, как и в CMakeLists.txt: маской его не снять, у
#       каждой системы он свой, и собранные разом они столкнулись бы определениями
##
case "$CODEC" in
	# Ворошитель разбора сетевых адресов
	addr) TARGET="src/net/addr.cpp src/net/net.cpp" ;;
	# Ворошитель разбора URI
	uri) TARGET="src/net/uri.cpp src/net/addr.cpp src/net/net.cpp" ;;
	##
	# Ворошитель разбора параметров запуска
	#
	# @note Берётся ОДИН разборщик, а не весь модуль: фасад «src/args/args.cpp» ходит
	#       в перекладку между кодеками и тянет за собою контейнер ABC со всеми семью
	#       кодеками разом, а ворошитель трогает лишь договор «awh::args::Lexer»
	##
	args) TARGET="src/args/lexer.cpp src/args/schema.cpp src/args/common.cpp" ;;
	##
	# Ворошитель сетевого движка и ворошитель модуля сетевых устройств
	#
	# @note Части у них общие, кроме одной: движок нужен лишь первому. Ворошитель
	#       «eth» трогает только договор «awh::eth_t», и тело движка ему ни к чему -
	#       собирать его значило бы платить сборкой самой крупной части дерева за
	#       то, чего ворошитель не зовёт
	##
	io|eth|blockprobe|deadlockprobe)
		# Отбираем движок по системе
		case "$(uname -s)" in
			# У систем BSD и macOS движком служит kqueue
			Darwin|FreeBSD|OpenBSD|NetBSD|DragonFly) BACKEND="src/net/backend/bsd/kqueue.cpp" ;;
			# У систем Sun движком служат Event Ports
			SunOS) BACKEND="src/net/backend/sun/ports.cpp" ;;
			# У MS Windows движком служит порт завершения ввода-вывода
			MINGW*|MSYS*|CYGWIN*) BACKEND="src/net/backend/win/iocp.cpp" ;;
			# У прочих систем движком служит epoll
			*) BACKEND="src/net/backend/gnu/epoll.cpp" ;;
		esac
		# Если движок задан переменной окружения, берём его
		if [ -n "$AWH_FUZZ_ENGINE" ]; then
			case "$AWH_FUZZ_ENGINE" in
				io_uring)
					BACKEND="src/net/backend/gnu/io_uring.cpp"
					# Движок кольца заводится только своим признаком сборки
					OPTIONS="$OPTIONS -DAWH_ENGINE_IO_URING"
				;;
				epoll) BACKEND="src/net/backend/gnu/epoll.cpp" ;;
				*) echo "движок «$AWH_FUZZ_ENGINE» неизвестен" >&2; exit 1 ;;
			esac
			echo "движок задан переменной окружения: $AWH_FUZZ_ENGINE"
		fi
		# Отбираем платформенные части по тому же доводу
		case "$(uname -s)" in
			# У систем BSD и macOS платформенные части лежат у kqueue
			Darwin|FreeBSD|OpenBSD|NetBSD|DragonFly) PLATFORM="bsd" ;;
			# У систем Sun платформенные части лежат у Event Ports
			SunOS) PLATFORM="sun" ;;
			# У MS Windows платформенные части лежат у порта завершения
			MINGW*|MSYS*|CYGWIN*) PLATFORM="win" ;;
			# У прочих систем платформенные части лежат у epoll
			*) PLATFORM="gnu" ;;
		esac
		# Ворошителю сетевых устройств тело движка не нужно
		if [ "$CODEC" = "eth" ]; then
			BACKEND=""
		fi
		TARGET="$BACKEND
			$ROOT/src/net/backend/$PLATFORM/addr.cpp
			$ROOT/src/net/backend/$PLATFORM/eth.cpp
			$ROOT/src/net/backend/$PLATFORM/iface.cpp
			$ROOT/src/net/backend/$PLATFORM/gateway.cpp
			$ROOT/src/net/backend/$PLATFORM/socket.cpp
			src/net/addr.cpp src/net/uri.cpp src/net/fds.cpp
			src/net/net.cpp src/net/queue.cpp"
		##
		# Часть SCTP берётся лишь там, где протокол есть в системе
		#
		# @note Ровно так же поступает и CMakeLists.txt. У macOS и DragonFly заголовка
		#       «netinet/sctp.h» нет вовсе, и сборка встаёт ещё на нём
		##
		##
		# Признак берётся по СИСТЕМЕ, а не по одному наличию заголовка
		#
		# @details Тело библиотеки объявляет часть SCTP под `#if __linux__ || __FreeBSD__
		#          || __sun` (include/net/eth/eth.hpp), и список этот и есть договор
		#
		# @warning Прежде довод был один - наличие «netinet/sctp.h». У NetBSD заголовок
		#          на месте, а объявления `net::sctp` нет, и сборка валилась на
		#          «'awh::net::sctp' has not been declared». Ядро NetBSD SCTP не даёт
		#          (см. записи по стендам), так что расхождение это не случайно: сборщик
		#          судил по заголовку, а библиотека - по системе
		#
		# @note Наличие заголовка сверяется ВДОБАВОК к системе: у Solaris он лежит не
		#       всегда, и брать часть без него нельзя
		##
		case "$(uname -s)" in
			Linux|FreeBSD|SunOS) SCTP_ALLOWED="yes" ;;
			*) SCTP_ALLOWED="no" ;;
		esac
		if [ "$SCTP_ALLOWED" = "yes" ] && { [ -f /usr/include/netinet/sctp.h ] || [ -f /usr/local/include/netinet/sctp.h ]; }; then
			TARGET="$TARGET $ROOT/src/net/backend/$PLATFORM/sctp.cpp"
			##
			# Тела SCTP лежат в отдельной библиотеке, и зовётся она по-разному
			#
			# @note У систем GNU это «libsctp», у систем Sun — «libsctp» же, но рядом с
			#       ней нужна ещё «libdladm»: через неё идёт вся работа с сетевыми
			#       устройствами, без неё связывание валится на dladm_open и соседях
			##
			case "$PLATFORM" in
				gnu) SYSTEM_LIBS="$SYSTEM_LIBS -lsctp" ;;
				sun) SYSTEM_LIBS="$SYSTEM_LIBS -lsctp" ;;
			esac
		fi
		##
		# Прослойка netlink берётся только у систем GNU
		#
		# @note Через неё идут все обращения к сетевым устройствам, адресам и маршрутам:
		#       у прочих систем то же делается через ioctl и route(4), и отдельного тела
		#       им не нужно
		##
		if [ "$PLATFORM" = "gnu" ]; then
			TARGET="$TARGET $ROOT/src/net/backend/gnu/netlink.cpp"
		fi
		##
		# Части устройства туннеля и разметки очередей берутся у MS Windows
		#
		# @note У наречий POSIX и то, и другое живёт внутри «eth.cpp» и «socket.cpp», а
		#       у MS Windows вынесено отдельными частями: заведение устройства идёт через
		#       драйвер стороннего поставщика, а разметка - через отдельную службу качества
		#       обслуживания. Без них связывание валится на «awh::win::tunnel::create» и
		#       соседях, причём ЛИШЬ у ворошителей сетевой зоны: кодеки этих имён не зовут
		#
		# @note «-lole32» нужна там же: опознаватель драйвера туннеля разбирается вызовом
		#       «CLSIDFromString», и это единственное имя из библиотеки объектной модели
		##
		if [ "$PLATFORM" = "win" ]; then
			TARGET="$TARGET
				$ROOT/src/net/backend/win/tunnel.cpp
				$ROOT/src/net/backend/win/qos.cpp"
			SYSTEM_LIBS="$SYSTEM_LIBS -lole32"
		fi
	;;
	# Прочие ворошители поверяют кодеки, и части их берутся каталогом целиком
	*) TARGET="" ;;
esac

##
# Собираем перечисленные поимённо части сетевой зоны
#
# @note Пересобираются они всегда, наравне с частями кодека: ворошителем поверяется
#       именно они, и брать их из кэша значит поверять вчерашний код
##
for PART in $TARGET; do
	# Приводим путь к полному, если он задан от корня дерева
	case "$PART" in
		/*) FULL="$PART" ;;
		*) FULL="$ROOT/$PART" ;;
	esac
	# Собираем имя объектного файла очередной части
	##
	# Собираем имя объектного файла очередной части
	#
	# @note Имя составляется из названия части и названия её каталога, а не обрезком
	#       пути: родной `tail` систем Sun довода `-c` не знает вовсе и отвечает
	#       «cannot open '40'», отчего сборка встаёт ещё до первого вызова собирателя.
	#       Пары «каталог + имя» довольно: части сетевой зоны по каталогам не
	#       повторяются
	##
	NAME="target-$(basename "$(dirname "$FULL")")-$(basename "$FULL" .cpp)"
	# Выполняем сборку очередной части
	$COMPILER $OPTIONS -c "$FULL" -o "$OUTPUT/$NAME.o"
	# Добавляем собранное к перечню объектных файлов
	OBJECTS="$OBJECTS $OUTPUT/$NAME.o"
done

# Выполняем перебор всех частей кодека
#
# @note Части кодека пересобираются всегда: ворошителем поверяется именно они
##
# Каталог частей кодека выводится из имени цели ДО первого дефиса
#
# @details Целей у одного кодека бывает несколько: «abc» ворошит слой записи, а
#          «abc-container» - слой контейнера, и обе собираются из одних и тех же частей
#          «src/codec/abc». Прежде каталог искался по ПОЛНОМУ имени цели, и цель
#          «abc-container» не собирала частей кодека вовсе - связывание отвечало
#          отсутствием всего кодека разом
##
CODEC_DIR="${CODEC%%-*}"

##
# Общие части кодеков берутся наравне с частями самого кодека
#
# @details Части, общие всем кодекам, лежат НЕ в каталоге кодека, а рядом с ним:
#          «src/codec/numeric.cpp» несёт приведение чисел, вынесенное из шести кодеков
#          в одно место 01.09.2026. Обход, бравший один каталог кодека, их не видел
#          вовсе - связывание отвечало отсутствием `awh::codec::convert<T>(double)`
#          сразу у трёх целей: «csv», «json» и «xml»
#
# @note Кодек ABC общего приведения не зовёт - своё лежит у него в безымянном
#       пространстве имён, - оттого он и собирался, когда прочие три уже нет. Судить о
#       здоровье обхода по одной цели нельзя
#
# @warning Части перечисляются ПОИМЁННО, а не маскою «src/codec/*.cpp». Взятые маскою,
#          они втянули бы и «src/codec/bridge.cpp» - перекладку между кодеками, зовущую
#          ВСЕ семь разом: ворошитель одного кодека связывался бы с шестью чужими, и
#          связывание отвечало отсутствием «awh::codec::abc::Value» у целей, ABC не
#          трогающих вовсе. Замер 02.09.2026: маска повалила «csv», «blockprobe» и
#          «deadlockprobe», прежде собиравшиеся
##
SHARED="$ROOT/src/codec/numeric.cpp"

##
# Кодеки, стоящие НА ДРУГОМ кодеке, берут части того кодека наравне со своими
#
# @details Кодек CEF своего владеющего значения не имеет вовсе: основанием событию
#          служит дерево контейнера ABC, и части «src/codec/abc» ему потребны так же,
#          как собственные. Обход, бравший один каталог кодека, их не видел - связывание
#          отвечало отсутствием «awh::codec::abc::Value» у цели «cef» (04.09.2026)
#
# @note Перечень ведётся ПОИМЁННО, а не выводится из включаемых заголовков: вывод по
#       заголовкам втянул бы у всякого кодека половину библиотеки, а надбавка эта
#       касается ровно тех кодеков, что стоят на чужом дереве
##
# @warning Каталог зависимости берётся ЦЕЛИКОМ, а не поимённо: части ABC ходят друг к
#          другу - значение зовёт документ, документ зовёт писателя с читателем, - и
#          поимённый перечень наращивался каскадом до того же каталога. Вместе с ним
#          берётся и надбавка сжатия с шифрованием, ибо слой хранилища ABC зовёт их
DEPENDS=""
case "$CODEC_DIR" in
	# Кодек CEF стоит на дереве ABC, а проверку адресов сети ведёт «net_addr_t»
	cef) DEPENDS="$(echo "$ROOT/src/codec/abc/"*.cpp) $ROOT/src/net/addr.cpp $ROOT/src/net/net.cpp" ;;
	##
	# Мост стоит на ВСЕХ кодеках разом
	#
	# @details Своего каталога у него нет вовсе - он лежит одним файлом
	#          «src/codec/bridge.cpp» рядом с каталогами кодеков, - и части ему потребны
	#          от каждого кодека, какой он переводит, плюс дерево ABC, служащее ему осью
	#
	# @warning Каталог CSV сюда НЕ входит: мост его не переводит намеренно - запись эта
	#          таблична, а не древовидна, и настройками не бывает
	##
	bridge)
		DEPENDS="$ROOT/src/codec/bridge.cpp"
		# Выполняем перебор всех кодеков, мостом переводимых
		for BRIDGED in abc json yaml xml toml ini; do
			# Добавляем к перечню части очередного кодека
			DEPENDS="$DEPENDS $(echo "$ROOT/src/codec/$BRIDGED/"*.cpp)"
		done
	;;
esac

for PART in $SHARED $([ -d "$ROOT/src/codec/$CODEC_DIR" ] && echo "$ROOT/src/codec/$CODEC_DIR/"*.cpp) $DEPENDS; do
	# Пропускаем несуществующее: часть общая заводится не разом со скриптом
	[ -f "$PART" ] || continue
	##
	# Имя объектного файла несёт КАТАЛОГ части, а не одно лишь её имя
	#
	# @details Части разных кодеков зовутся одинаково - «document.cpp» есть и у CEF, и
	#          у ABC, - и имя «codec-document.o» у обеих было одним: часть кодека,
	#          собранная первой, затиралась частью его зависимости, и связывание
	#          отвечало отсутствием тел САМОГО кодека при налицо собранных его частях
	#          (замер 04.09.2026, цель «cef»)
	##
	NAME="codec-$(basename "$(dirname "$PART")")-$(basename "$PART" .cpp)"
	# Выполняем сборку очередной части кодека
	$COMPILER $OPTIONS -c "$PART" -o "$OUTPUT/$NAME.o"
	# Добавляем собранное к перечню объектных файлов
	OBJECTS="$OBJECTS $OUTPUT/$NAME.o"
done

##
# Части сжатия и шифрования, каких требует ЛИШЬ кодек ABC
#
# Кодек ABC - единственный из семи, чьи части ходят в сжатие и шифрование: кадр
# контейнера укладывается сжатым, а запись подписи зовёт шифрование. Прочие шесть
# кодеков не знают ни того, ни другого, и общих доводов скрипта надбавка эта не
# трогает - берётся она только при «abc», как и надбавка распределителя выше
#
# @note Сторонние библиотеки берутся собранным «libdependence.a»: он несёт и сжатие,
#       и OpenSSL - 985 знаков EVP и SSL, - и внешней зависимости здесь не заводится.
#       Прежде это было измерено неверно, и цель «abc» осталась несобираемой: связывание
#       отвечало отсутствием знаков «awh::Crypto» и «awh::compressor», а обход искался
#       во внешнем OpenSSL, какого не нужно вовсе
#
# @warning Каталог «third_party/include» подаётся ТОЛЬКО этим частям и только здесь:
#          поданный общим доводом, он подменяет заголовки стандартной библиотеки -
#          «openssl» несёт свой «time.h», и сборка валится внутри libc++
##
##
# Библиотека сжатия zlib, переопределяемая окружением
#
# @details Умолчание «-lz» годится всюду, кроме стендов, где разделяемая библиотека
#          собрана несовместимо. У OpenWrt 25.12 x86_64 ВСЕ ТРИ разделяемых вида
#          отвечают связыванию «file in wrong format» при исправном по виду ELF64, и
#          годна там лишь статическая: `ZLIB=/usr/lib/libz.a sh build.sh <кодек>`
#
# @note Довод берётся окружением, а не признаком системы: негодность эта - свойство
#       СБОРКИ библиотеки на отдельной машине, и по имени системы её не опознать
##
ZLIB="${ZLIB:--lz}"

# Надбавка эта берётся и кодеком, НА ABC стоящим: слой хранилища ABC зовёт сжатие с
# шифрованием независимо от того, чьим ворошителем он собран, - а мост стоит на ABC
# осью своей и тянет его целиком
DEPEND=""
if [ "$CODEC_DIR" = "abc" ] || [ "$CODEC_DIR" = "cef" ] || [ "$CODEC_DIR" = "bridge" ]; then
	##
	# Собираем каталоги сторонних заголовков ПОИМЁННО
	#
	# @warning Общий «third_party/include» подаётся ОДИН, ради «openssl/...»; каталоги же
	#          самих библиотек берутся поимённо, а НЕ перебором «third_party/include/*».
	#          Перебор кладёт на путь и «third_party/include/openssl», а он несёт свой
	#          «time.h» - собиратель берёт его вместо системного, и сборка валится двумя
	#          десятками отказов ВНУТРИ заголовков libc++. Проверено 01.09.2026
	##
	THIRD="-I$ROOT/third_party/include"
	for DIR in lz4 bz2 zstd lzma zlib brotli snappy lizard density; do
		# Если каталог заголовков очередной библиотеки заведён, подаём его
		[ -d "$ROOT/third_party/include/$DIR" ] && THIRD="$THIRD -I$ROOT/third_party/include/$DIR"
	done
	for PART in src/compressor/block.cpp src/compressor/stream.cpp src/compressor/types.cpp \
	 src/cryptography/crypto.cpp src/cryptography/hash.cpp src/cryptography/vault.cpp \
	 src/num/bignum.cpp; do
		# Собираем имя объектного файла очередной части
		NAME="extra-$(basename "$(dirname "$PART")")-$(basename "$PART" .cpp)"
		# Выполняем сборку очередной части сжатия либо шифрования
		$COMPILER $OPTIONS $THIRD -c "$ROOT/$PART" -o "$OUTPUT/$NAME.o"
		# Добавляем собранное к перечню объектных файлов
		OBJECTS="$OBJECTS $OUTPUT/$NAME.o"
	done
	# Выполняем подключение собранных сторонних библиотек
	DEPEND="$ROOT/third_party/lib/libdependence.a"
fi

# Выполняем сборку самого ворошителя
$COMPILER $OPTIONS -c "$ROOT/tools/fuzz/$CODEC.cpp" -o "$OUTPUT/fuzz.o"

# Выполняем связывание ворошителя
$COMPILER $OPTIONS "$OUTPUT/fuzz.o" $OBJECTS $DEPEND $SYSTEM_LIBS $ZLIB -o "$OUTPUT/$CODEC-fuzz"

# Выводим сообщение об окончании сборки
echo "Ворошитель собран: $OUTPUT/$CODEC-fuzz"
