/**
 * Подключаем заголовочные файлы проекта
 */
#include <encoding/unicode/utf8.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Пространство имён вспомогательных значений кодировщика UTF-8
 *
 */
namespace {
	/**
	 * @brief Наименьшее кодовое значение суррогатной пары
	 *
	 */
	constexpr uint32_t SURROGATE_BEGIN = 0xD800;

	/**
	 * @brief Наибольшее кодовое значение суррогатной пары
	 *
	 */
	constexpr uint32_t SURROGATE_END = 0xDFFF;
};

/**
 * @brief Функция представления кодового значения символа записью UTF-8
 *
 * @param code   кодовое значение записываемого символа
 * @param buffer буфер записи символа длиной не менее «MAX_LENGTH»
 * @return       длина записи символа либо нулевое значение при отказе
 *
 */
size_t awh::utf8::encode(const uint32_t code, char * buffer) noexcept {
	/**
	 * Если буфер записи символа не передан
	 */
	if(buffer == nullptr)
		// Выводим отказ представления кодового значения
		return 0;
	/**
	 * Если кодовое значение принадлежит суррогатной паре либо превышает наибольшее
	 */
	if(((code >= SURROGATE_BEGIN) && (code <= SURROGATE_END)) || (code > MAX_CODEPOINT))
		// Выводим отказ представления кодового значения
		return 0;
	/**
	 * Если кодовое значение записывается одним байтом
	 */
	if(code <= 0x7F) {
		// Выполняем запись кодового значения одним байтом
		buffer[0] = static_cast <char> (code);
		// Выводим длину записи символа
		return 1;
	}
	/**
	 * Если кодовое значение записывается двумя байтами
	 */
	if(code <= 0x7FF) {
		// Выполняем запись ведущего байта записи символа
		buffer[0] = static_cast <char> (0xC0 | (code >> 6));
		// Выполняем запись продолжающего байта записи символа
		buffer[1] = static_cast <char> (0x80 | (code & 0x3F));
		// Выводим длину записи символа
		return 2;
	}
	/**
	 * Если кодовое значение записывается тремя байтами
	 */
	if(code <= 0xFFFF) {
		// Выполняем запись ведущего байта записи символа
		buffer[0] = static_cast <char> (0xE0 | (code >> 12));
		// Выполняем запись первого продолжающего байта записи символа
		buffer[1] = static_cast <char> (0x80 | ((code >> 6) & 0x3F));
		// Выполняем запись второго продолжающего байта записи символа
		buffer[2] = static_cast <char> (0x80 | (code & 0x3F));
		// Выводим длину записи символа
		return 3;
	}
	// Выполняем запись ведущего байта записи символа
	buffer[0] = static_cast <char> (0xF0 | (code >> 18));
	// Выполняем запись первого продолжающего байта записи символа
	buffer[1] = static_cast <char> (0x80 | ((code >> 12) & 0x3F));
	// Выполняем запись второго продолжающего байта записи символа
	buffer[2] = static_cast <char> (0x80 | ((code >> 6) & 0x3F));
	// Выполняем запись третьего продолжающего байта записи символа
	buffer[3] = static_cast <char> (0x80 | (code & 0x3F));
	// Выводим длину записи символа
	return 4;
}
/**
 * @brief Функция разбора записи символа в кодировке UTF-8
 *
 * @param text текст, записанный в кодировке UTF-8
 * @param pos  положение начала записи символа в тексте
 * @param code кодовое значение разобранного символа
 * @return     длина разобранной записи либо нулевое значение при отказе
 *
 */
size_t awh::utf8::decode(string_view text, const size_t pos, uint32_t & code) noexcept {
	// Выполняем сброс кодового значения разобранного символа
	code = 0;
	/**
	 * Если положение начала записи находится за пределами текста
	 */
	if(pos >= text.size())
		// Выводим отказ разбора записи символа
		return 0;
	// Получаем ведущий байт записи символа
	const uint8_t leading = static_cast <uint8_t> (text[pos]);
	/**
	 * Если запись символа состоит из одного байта
	 */
	if(leading <= 0x7F) {
		// Выполняем получение кодового значения символа
		code = leading;
		// Выводим длину разобранной записи символа
		return 1;
	}
	// Количество байтов записи символа
	size_t length = 0;
	// Наименьшее кодовое значение, записываемое полученным количеством байтов
	uint32_t least = 0;
	/**
	 * Если запись символа состоит из двух байтов
	 */
	if((leading & 0xE0) == 0xC0) {
		// Выполняем получение старших разрядов кодового значения
		code = (leading & 0x1F);
		// Устанавливаем количество байтов записи символа
		length = 2;
		// Устанавливаем наименьшее записываемое кодовое значение
		least = 0x80;
	/**
	 * Если запись символа состоит из трёх байтов
	 */
	} else if((leading & 0xF0) == 0xE0) {
		// Выполняем получение старших разрядов кодового значения
		code = (leading & 0x0F);
		// Устанавливаем количество байтов записи символа
		length = 3;
		// Устанавливаем наименьшее записываемое кодовое значение
		least = 0x800;
	/**
	 * Если запись символа состоит из четырёх байтов
	 */
	} else if((leading & 0xF8) == 0xF0) {
		// Выполняем получение старших разрядов кодового значения
		code = (leading & 0x07);
		// Устанавливаем количество байтов записи символа
		length = 4;
		// Устанавливаем наименьшее записываемое кодовое значение
		least = 0x10000;
	/**
	 * Если ведущим байтом записи символа является продолжающий байт
	 */
	} else {
		// Выполняем сброс кодового значения разобранного символа
		code = 0;
		// Выводим отказ разбора записи символа
		return 0;
	}
	/**
	 * Если запись символа оборвана концом текста
	 */
	if((pos + length) > text.size()) {
		// Выполняем сброс кодового значения разобранного символа
		code = 0;
		// Выводим отказ разбора записи символа
		return 0;
	}
	/**
	 * Выполняем разбор продолжающих байтов записи символа
	 */
	for(size_t i = 1; i < length; i++) {
		// Получаем очередной продолжающий байт записи символа
		const uint8_t following = static_cast <uint8_t> (text[pos + i]);
		/**
		 * Если очередной байт записи продолжающим байтом не является
		 */
		if((following & 0xC0) != 0x80) {
			// Выполняем сброс кодового значения разобранного символа
			code = 0;
			// Выводим отказ разбора записи символа
			return 0;
		}
		// Выполняем присоединение разрядов продолжающего байта
		code = ((code << 6) | (following & 0x3F));
	}
	/**
	 * Если запись символа избыточна, задаёт суррогатную пару либо превышает наибольшее значение
	 *
	 * @details Избыточной признаётся запись, длина которой превышает необходимую для
	 *          полученного кодового значения. Такие записи стандартом Юникода запрещены
	 *          и отклоняются: их допущение позволяет обойти проверки текста.
	 *
	 */
	if((code < least) || ((code >= SURROGATE_BEGIN) && (code <= SURROGATE_END)) || (code > MAX_CODEPOINT)) {
		// Выполняем сброс кодового значения разобранного символа
		code = 0;
		// Выводим отказ разбора записи символа
		return 0;
	}
	// Выводим длину разобранной записи символа
	return length;
}
/**
 * @brief Функция проверки правильности записи текста в кодировке UTF-8
 *
 * @param text проверяемый текст
 * @return     результат проверки правильности записи текста
 *
 */
bool awh::utf8::valid(string_view text) noexcept {
	// Кодовое значение очередного разобранного символа
	uint32_t code = 0;
	/**
	 * Выполняем обход записей символов текста
	 */
	for(size_t pos = 0; pos < text.size();) {
		// Выполняем разбор записи очередного символа текста
		const size_t length = decode(text, pos, code);
		/**
		 * Если запись очередного символа разобрать не вышло
		 */
		if(length == 0)
			// Выводим результат проверки правильности записи текста
			return false;
		// Выполняем переход к записи следующего символа текста
		pos += length;
	}
	// Выводим результат проверки правильности записи текста
	return true;
}
/**
 * @brief Функция подсчёта количества символов текста в кодировке UTF-8
 *
 * @param text текст, записанный в кодировке UTF-8
 * @return     количество символов текста либо нулевое значение при отказе
 *
 */
size_t awh::utf8::length(string_view text) noexcept {
	// Количество символов текста
	size_t result = 0;
	// Кодовое значение очередного разобранного символа
	uint32_t code = 0;
	/**
	 * Выполняем обход записей символов текста
	 */
	for(size_t pos = 0; pos < text.size();) {
		// Выполняем разбор записи очередного символа текста
		const size_t length = decode(text, pos, code);
		/**
		 * Если запись очередного символа разобрать не вышло
		 */
		if(length == 0)
			// Выводим отказ подсчёта количества символов текста
			return 0;
		// Выполняем переход к записи следующего символа текста
		pos += length;
		// Выполняем подсчёт очередного символа текста
		result++;
	}
	// Выводим количество символов текста
	return result;
}
