#include <encoding/charset/charset.hpp>
#include <encoding/ascii.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Пространство имён вспомогательных функций модуля перекодировки
 *
 */
namespace {
	/**
	 * @brief Кодовое значение символа замены непредставимых символов
	 *
	 */
	constexpr uint32_t REPLACEMENT = 0xFFFD;

	/**
	 * @brief Функция разбора очередного символа текста заданной кодировки
	 *
	 * @param text     разбираемый текст
	 * @param pos      положение начала записи символа в тексте
	 * @param codepage таблица соответствия кодировки Юникоду
	 * @param encoding обозначение кодировки разбираемого текста
	 * @param code     кодовое значение разобранного символа
	 * @return         длина разобранной записи либо нулевое значение при отказе
	 *
	 */
	inline size_t extract(string_view text, const size_t pos, const awh::charset::table_t * codepage, const awh::charset::encoding_t encoding, uint32_t & code) noexcept {
		// Выполняем сброс кодового значения разобранного символа
		code = 0;
		/**
		 * Если положение начала записи находится за пределами текста
		 */
		if(pos >= text.size())
			// Выводим отказ разбора записи символа
			return 0;
		/**
		 * Если текст записан в кодировке UTF-8
		 */
		if(encoding == awh::charset::encoding_t::UTF8)
			// Выводим результат разбора записи символа кодировщиком UTF-8
			return awh::utf8::decode(text, pos, code);
		// Получаем очередной байт разбираемого текста
		const uint8_t byte = static_cast <uint8_t> (text[pos]);
		/**
		 * Если текст записан в кодировке ASCII
		 */
		if(encoding == awh::charset::encoding_t::ASCII) {
			/**
			 * Если байт текста находится за пределами набора ASCII
			 */
			if(byte > 0x7F)
				// Выводим отказ разбора записи символа
				return 0;
			// Выполняем получение кодового значения символа
			code = byte;
			// Выводим длину разобранной записи символа
			return 1;
		}
		/**
		 * Если таблица соответствия кодировки не задана
		 */
		if(codepage == nullptr)
			// Выводим отказ разбора записи символа
			return 0;
		// Получаем кодовое значение, соответствующее байту кодировки
		const uint16_t value = codepage->unicode[byte];
		/**
		 * Если байту кодировки кодовое значение не соответствует
		 */
		if(value == awh::charset::UNMAPPED)
			// Выводим отказ разбора записи символа
			return 0;
		// Выполняем получение кодового значения символа
		code = value;
		// Выводим длину разобранной записи символа
		return 1;
	}
	/**
	 * @brief Функция записи кодового значения символа в заданной кодировке
	 *
	 * @param code     кодовое значение записываемого символа
	 * @param codepage таблица соответствия кодировки Юникоду
	 * @param encoding обозначение кодировки записываемого текста
	 * @param result   текст, к которому присоединяется запись символа
	 * @return         результат выполнения записи символа
	 *
	 */
	inline bool insert(const uint32_t code, const awh::charset::table_t * codepage, const awh::charset::encoding_t encoding, string & result) noexcept {
		/**
		 * Если текст записывается в кодировке UTF-8
		 */
		if(encoding == awh::charset::encoding_t::UTF8) {
			// Выполняем создание буфера записи символа
			char buffer[awh::utf8::MAX_LENGTH];
			// Выполняем представление кодового значения записью UTF-8
			const size_t length = awh::utf8::encode(code, buffer);
			/**
			 * Если представить кодовое значение записью не вышло
			 */
			if(length == 0)
				// Выводим результат выполнения записи символа
				return false;
			// Выполняем присоединение записи символа к тексту
			result.append(buffer, length);
			// Выводим результат выполнения записи символа
			return true;
		}
		/**
		 * Если текст записывается в кодировке ASCII
		 */
		if(encoding == awh::charset::encoding_t::ASCII) {
			/**
			 * Если кодовое значение находится за пределами набора ASCII
			 */
			if(code > 0x7F)
				// Выводим результат выполнения записи символа
				return false;
			// Выполняем присоединение записи символа к тексту
			result.append(1, static_cast <char> (code));
			// Выводим результат выполнения записи символа
			return true;
		}
		/**
		 * Если таблица соответствия кодировки не задана либо кодовое значение
		 * находится за пределами базовой плоскости
		 *
		 * @details Однобайтовым кодировкам кодовые значения за пределами базовой
		 *          плоскости не встречаются, и таблицы хранят их двухбайтовыми.
		 *
		 */
		if((codepage == nullptr) || (code > 0xFFFF))
			// Выводим результат выполнения записи символа
			return false;
		// Получаем наименьший индекс просматриваемого участка таблицы
		size_t lower = 0;
		// Получаем наибольший индекс просматриваемого участка таблицы
		size_t upper = codepage->count;
		/**
		 * Выполняем двоичный поиск кодового значения в таблице соответствия
		 */
		while(lower < upper) {
			// Получаем индекс середины просматриваемого участка
			const size_t middle = (lower + ((upper - lower) / 2));
			/**
			 * Если искомое кодовое значение предшествует значению таблицы
			 */
			if(code < codepage->mappings[middle].code)
				// Продолжаем поиск в левой половине участка
				upper = middle;
			/**
			 * Если искомое кодовое значение следует за значением таблицы
			 */
			else if(code > codepage->mappings[middle].code)
				// Продолжаем поиск в правой половине участка
				lower = (middle + 1);
			/**
			 * Выполняем присоединение записи символа к тексту
			 */
			else {
				// Выполняем присоединение байта кодировки к тексту
				result.append(1, static_cast <char> (codepage->mappings[middle].byte));
				// Выводим результат выполнения записи символа
				return true;
			}
		}
		// Выводим отсутствие соответствия кодового значения кодировке
		return false;
	}
};

/**
 * @brief Функция разбора имени кодировки
 *
 * @param name имя кодировки, заданное заголовком протокола
 * @return     обозначение кодировки либо признак нераспознанного имени
 *
 */
awh::charset::encoding_t awh::charset::encoding(string_view name) noexcept {
	// Приведённое к нормальному виду имя кодировки
	string key;
	/**
	 * Выполняем приведение имени кодировки к нормальному виду
	 */
	for(auto & letter : name) {
		/**
		 * Если очередной символ имени является пробельным
		 */
		if(ascii::isSpace(letter))
			// Переходим к следующему символу имени кодировки
			continue;
		// Выполняем добавление символа имени кодировки в нижнем регистре
		key.append(1, ascii::toLower(letter));
	}
	// Получаем наименьший индекс просматриваемого участка таблицы имён
	size_t lower = 0;
	// Получаем наибольший индекс просматриваемого участка таблицы имён
	size_t upper = LABELS_COUNT;
	/**
	 * Выполняем двоичный поиск имени кодировки в таблице соответствия
	 */
	while(lower < upper) {
		// Получаем индекс середины просматриваемого участка
		const size_t middle = (lower + ((upper - lower) / 2));
		// Выполняем сличение искомого имени с именем таблицы
		const int32_t result = key.compare(LABELS[middle].name);
		/**
		 * Если искомое имя предшествует имени таблицы
		 */
		if(result < 0)
			// Продолжаем поиск в левой половине участка
			upper = middle;
		/**
		 * Если искомое имя следует за именем таблицы
		 */
		else if(result > 0)
			// Продолжаем поиск в правой половине участка
			lower = (middle + 1);
		// Выводим обнаруженное обозначение кодировки
		else return LABELS[middle].encoding;
	}
	// Выводим признак нераспознанного имени кодировки
	return encoding_t::NONE;
}
/**
 * @brief Функция извлечения канонического имени кодировки
 *
 * @param encoding обозначение кодировки текста
 * @return         каноническое имя кодировки
 *
 */
string_view awh::charset::label(const encoding_t encoding) noexcept {
	/**
	 * Определяем обозначение кодировки текста
	 */
	switch(static_cast <uint8_t> (encoding)) {
		// Выводим имя кодировки UTF-8
		case static_cast <uint8_t> (encoding_t::UTF8): return "UTF-8";
		// Выводим имя кодировки ASCII
		case static_cast <uint8_t> (encoding_t::ASCII): return "US-ASCII";
	}
	// Выполняем извлечение таблицы соответствия кодировки Юникоду
	const table_t * item = table(encoding);
	/**
	 * Если таблица соответствия кодировки обнаружена
	 */
	if(item != nullptr)
		// Выводим каноническое имя кодировки
		return item->name;
	// Выводим отсутствие имени у неустановленной кодировки
	return "";
}
/**
 * @brief Функция извлечения таблицы соответствия кодировки Юникоду
 *
 * @param encoding обозначение кодировки текста
 * @return         таблица соответствия либо пустой указатель
 *
 */
const awh::charset::table_t * awh::charset::table(const encoding_t encoding) noexcept {
	/**
	 * Выполняем обход набора таблиц соответствия кодировок
	 */
	for(size_t i = 0; i < CODEPAGES_COUNT; i++) {
		/**
		 * Если обозначение кодировки таблицы совпадает с искомым
		 */
		if(CODEPAGES[i].encoding == encoding)
			// Выводим обнаруженную таблицу соответствия кодировки
			return &CODEPAGES[i];
	}
	// Выводим отсутствие таблицы соответствия кодировки
	return nullptr;
}
/**
 * @brief Функция перекодировки текста из одной кодировки в другую
 *
 * @param text     перекодируемый текст
 * @param from     кодировка, в которой записан текст
 * @param to       кодировка, в которую записывается результат
 * @param result   результат перекодировки текста
 * @param replace  порядок обращения с непредставимыми символами
 * @return         результат выполнения перекодировки текста
 *
 */
bool awh::charset::transcode(string_view text, const encoding_t from, const encoding_t to, string & result, const replace_t replace) noexcept {
	// Выполняем очистку результата перекодировки текста
	result.clear();
	/**
	 * Если кодировка текста либо кодировка результата не установлена
	 */
	if((from == encoding_t::NONE) || (to == encoding_t::NONE))
		// Выводим результат выполнения перекодировки текста
		return false;
	/**
	 * Если перекодировать текст не требуется
	 */
	if(text.empty())
		// Выводим результат выполнения перекодировки текста
		return true;
	// Выполняем извлечение таблицы соответствия кодировки текста
	const table_t * source = table(from);
	// Выполняем извлечение таблицы соответствия кодировки результата
	const table_t * target = table(to);
	/**
	 * Если кодировка текста задана таблицей соответствия, которая не обнаружена
	 */
	if((source == nullptr) && (from != encoding_t::UTF8) && (from != encoding_t::ASCII))
		// Выводим результат выполнения перекодировки текста
		return false;
	/**
	 * Если кодировка результата задана таблицей соответствия, которая не обнаружена
	 */
	if((target == nullptr) && (to != encoding_t::UTF8) && (to != encoding_t::ASCII))
		// Выводим результат выполнения перекодировки текста
		return false;
	/**
	 * Выполняем предварительное выделение памяти под результат перекодировки
	 *
	 * @details Запись символа в кодировке UTF-8 занимает до четырёх байтов,
	 *          тогда как в однобайтовой кодировке — ровно один.
	 */
	result.reserve((to == encoding_t::UTF8) ? (text.size() * 2) : text.size());
	// Кодовое значение очередного разобранного символа
	uint32_t code = 0;
	/**
	 * Выполняем обход записей символов перекодируемого текста
	 */
	for(size_t pos = 0; pos < text.size();) {
		// Выполняем разбор записи очередного символа текста
		const size_t length = extract(text, pos, source, from, code);
		/**
		 * Если запись очередного символа разобрать не вышло
		 */
		if(length == 0) {
			/**
			 * Определяем порядок обращения с символами, кодировке не представимыми
			 */
			switch(static_cast <uint8_t> (replace)) {
				// Выполняем отклонение перекодировки текста целиком
				case static_cast <uint8_t> (replace_t::STRICT): {
					// Выполняем очистку результата перекодировки текста
					result.clear();
					// Выводим результат выполнения перекодировки текста
					return false;
				}
				/**
				 * Выполняем пропуск байта, записью символа не являющегося
				 */
				case static_cast <uint8_t> (replace_t::SKIP): {
					// Выполняем переход к следующему байту текста
					pos++;
					// Продолжаем перекодировку текста
					continue;
				}
				/**
				 * Выполняем замену байта, записью символа не являющегося
				 */
				case static_cast <uint8_t> (replace_t::REPLACE): {
					// Выполняем запись символа замены в кодировке результата
					if(!insert(REPLACEMENT, target, to, result))
						// Выполняем запись знака вопроса взамен символа замены
						result.append(1, '?');
					// Выполняем переход к следующему байту текста
					pos++;
					// Продолжаем перекодировку текста
					continue;
				}
			}
		}
		/**
		 * Если записать разобранный символ в кодировке результата не вышло
		 */
		if(!insert(code, target, to, result)) {
			/**
			 * Определяем порядок обращения с символами, кодировке не представимыми
			 */
			switch(static_cast <uint8_t> (replace)) {
				// Выполняем отклонение перекодировки текста целиком
				case static_cast <uint8_t> (replace_t::STRICT): {
					// Выполняем очистку результата перекодировки текста
					result.clear();
					// Выводим результат выполнения перекодировки текста
					return false;
				}
				// Выполняем замену символа, кодировке результата не представимого
				case static_cast <uint8_t> (replace_t::REPLACE):
					// Выполняем запись знака вопроса взамен непредставимого символа
					result.append(1, '?');
				break;
			}
		}
		// Выполняем переход к записи следующего символа текста
		pos += length;
	}
	// Выводим результат выполнения перекодировки текста
	return true;
}
/**
 * @brief Функция перекодировки текста из одной кодировки в другую
 *
 * @param text     перекодируемый текст
 * @param from     кодировка, в которой записан текст
 * @param to       кодировка, в которую записывается результат
 * @param replace  порядок обращения с непредставимыми символами
 * @return         получившийся в результате текст
 *
 */
string awh::charset::transcode(string_view text, const encoding_t from, const encoding_t to, const replace_t replace) noexcept {
	// Результат перекодировки текста
	string result = "";
	// Выполняем перекодировку текста из одной кодировки в другую
	transcode(text, from, to, result, replace);
	// Выводим получившийся в результате текст
	return result;
}
/**
 * @brief Функция определения кодировки текста
 *
 * @param text      текст, кодировку которого требуется определить
 * @param fallback  кодировка, предполагаемая для текста, записью UTF-8 не являющегося
 * @return          обозначение определённой кодировки текста
 *
 */
awh::charset::encoding_t awh::charset::detect(string_view text, const encoding_t fallback) noexcept {
	/**
	 * Если текст является правильной записью в кодировке UTF-8
	 */
	if(utf8::valid(text))
		// Выводим обозначение кодировки UTF-8
		return encoding_t::UTF8;
	// Выводим обозначение предполагаемой кодировки текста
	return fallback;
}
