/**
 * @brief Метод добавления данных в потоковое хэширование
 *
 * @param buffer буфер данных для хэширования
 * @param size   размер буфера данных для хэширования
 *
 */
void awh::Hash::update(const void * buffer, const size_t size) noexcept {
	/**
	 * Если буфер данных для хэширования передан
	 */
	if((buffer != nullptr) && (size > 0)){
		// Получаем буфер данных для хэширования
		const uint8_t * data = static_cast <const uint8_t *> (buffer);
		// Смещение в буфере данных для хэширования
		size_t offset = 0;
		// Увеличиваем общий размер обработанных данных
		this->_length += static_cast <uint64_t> (size);
		/**
		 * Если в буфере неполного блока данных уже есть данные
		 */
		if(this->_offset > 0){
			// Определяем количество копируемых в буфер байтов
			const size_t count = ((size < (BLOCK - this->_offset)) ? size : (BLOCK - this->_offset));
			// Выполняем копирование данных в буфер неполного блока данных
			::memcpy(this->_buffer.data() + this->_offset, data, count);
			// Увеличиваем размер данных находящихся в буфере
			this->_offset += count;
			// Выполняем смещение в буфере данных для хэширования
			offset += count;
			/**
			 * Если буфер неполного блока данных заполнен целиком и данные на этом
			 * не заканчиваются, ведь последний блок данных поглощается иначе
			 */
			if((this->_offset == BLOCK) && (offset < size)){
				// Выполняем поглощение собранного блока данных
				hashing::block(this->_state, this->_buffer.data());
				// Выполняем сброс размера данных находящихся в буфере
				this->_offset = 0;
			}
		}
		/**
		 * Выполняем перебор всех полных блоков данных кроме последнего
		 */
		while((size - offset) > BLOCK){
			// Выполняем поглощение очередного блока данных
			hashing::block(this->_state, data + offset);
			// Выполняем смещение в буфере данных для хэширования
			offset += BLOCK;
		}
		/**
		 * Если в буфере данных остались необработанные байты
		 */
		if(offset < size){
			// Выполняем копирование остатка данных в буфер неполного блока данных
			::memcpy(this->_buffer.data() + this->_offset, data + offset, size - offset);
			// Увеличиваем размер данных находящихся в буфере
			this->_offset += (size - offset);
		}
	}
}
/**
 * @brief Метод формирования результата потокового хэширования
 *
 * @param result буфер для записи результата хэширования
 * @param length размер результата хэширования в байтах
 *
 */
void awh::Hash::digest(uint8_t * result, const size_t length) const noexcept {
	/**
	 * Если результат хэширования формировать требуется
	 */
	if((result != nullptr) && (length > 0)){
		/**
		 * Если размер обработанных данных не превышает одного блока, а значит
		 * все обработанные данные до сих пор находятся в буфере
		 */
		if(this->_length <= BLOCK)
			// Выполняем формирование результата хэширования по свёртке коротких данных
			hashing::squeeze(hashing::compact(this->_buffer.data(), this->_offset, this->_seed), result, length);
		/**
		 * Если размер обработанных данных превышает один блок
		 */
		else {
			// Копируем состояние вычислительного движка хэширования
			array <uint64_t, 4> state = this->_state;
			// Выполняем поглощение последнего блока данных
			hashing::tail(state, this->_buffer.data(), this->_offset);
			// Выполняем формирование результата хэширования по свёртке состояния
			hashing::squeeze(hashing::collapse(state, this->_seed, this->_length), result, length);
		}
	}
}
/**
 * @brief Метод формирования хэша буфера данных
 *
 * @param buffer буфер данных для хэширования
 * @param size   размер буфера данных для хэширования
 * @param result буфер для записи результата хэширования
 * @param length размер результата хэширования в байтах
 *
 */
void awh::Hash::hash(const void * buffer, const size_t size, uint8_t * result, const size_t length) const noexcept {
	// Выполняем формирование хэша буфера данных
	hashing::generate(buffer, size, this->_seed, result, length);
}
