/**
 * @brief Метод извлечения количества значащих бит числа
 *
 * @return количество значащих бит числа
 *
 */
uint32_t awh::BigNum <BYTES, TYPE>::bits() const noexcept {
	/**
	 * Если число является вещественным
	 */
	if(TYPE == bignum::type_t::REAL){
		// Выполняем распаковку вещественного числа
		const bignum::realValue_t num = bignum::realUnpack(this->_data.data(), BYTES);
		// Если вещественное число не является конечным числом
		if((num.type == bignum::class_t::UNDEFINED) || (num.type == bignum::class_t::UNLIMITED))
			// Выводим количество значащих бит числа
			return 0;
		// Выводим количество значащих бит мантиссы вещественного числа
		return static_cast <uint32_t> (bignum::bits(num.mantissa.data(), num.mantissa.size()));
	}
	// Выводим количество значащих бит целого числа
	return static_cast <uint32_t> (bignum::bits(this->_data.data(), BYTES));
}
