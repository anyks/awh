/**
 * @brief Метод формирования минимально возможного значения числа
 *
 * @return минимально возможное значение числа
 *
 */
awh::BigNum <BYTES, TYPE> awh::BigNum <BYTES, TYPE>::minimum() noexcept {
	// Результат работы функции
	BigNum result;
	/**
	 * Определяем тип хранимого числа
	 */
	switch(static_cast <uint8_t> (TYPE)){
		/**
		 * Если число является знаковым целым
		 */
		case static_cast <uint8_t> (bignum::type_t::SIGNED):
			// Устанавливаем старший разряд числа
			result._data[BYTES - 1] = 0x80;
		break;
		/**
		 * Если число является вещественным
		 */
		case static_cast <uint8_t> (bignum::type_t::REAL):
			// Устанавливаем минимальное конечное значение числа
			bignum::realLimit(result._data.data(), BYTES, true);
		break;
		/**
		 * Если число является беззнаковым целым
		 */
		default: break;
	}
	// Выводим результат работы функции
	return result;
}
