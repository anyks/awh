	/**
	 * @brief Шаблонная функция приведения дробного числа к затребованному виду
	 *
	 * @details Приведение это перенято у контейнера JSON дословно: договор извлечения
	 * общий у всех кодеков рамки, и расхождение в нём всплыло бы у потребителя,
	 * читающего два из них, - всплыло бы не сразу и не там, где заведено
	 *
	 * @tparam T     вид, к какому приводится число
	 * @param  value приводимое дробное число
	 * @return       приведённое число
	 *
	 */
	template <typename T>
	T convert(const double value) noexcept {
		/**
		 * Если затребован дробный вид
		 */
		if(is_floating_point <T>::value)
			// Выводим приведённое число как оно есть
			return static_cast <T> (value);
		/**
		 * Если число не является числом вовсе
		 */
		if(::isnan(value))
			// Выводим нулевое число
			return static_cast <T> (0);
		/**
		 * Если дробной части у числа нет вовсе
		 *
		 * @details Запись числа ответа менять не должна: `300.0` обязано извлекаться ровно
		 * так же, как `300`, - решение владельца от 30.08.2026. Оттого число с нулевой
		 * дробной частью уходит на путь ЦЕЛОГО и заворачивается по кругу языком, а не
		 * выдаётся пределом вида. Предел остаётся лишь у чисел, дробная часть у которых
		 * есть на деле: там записи целой числу этому не отвечает вовсе, и сличать нечего
		 *
		 * @note Ход этот берётся, лишь пока число укладывается в разрядность хранимого
		 *       целого: путь целого держит `int64_t` со знаком и `uint64_t` без него, и
		 *       повторить перенос вне этих границ нечем - там неопределено и приведение
		 *       самого языка. Числа шире уходят ниже, к пределам вида
		 *
		 * @warning Правило это держится ровно до предела точного представления целых
		 *          числом двойной точности - 2^53. За ним дробная запись теряет число ЕЩЁ
		 *          ДО приведения: `strtod` иного `double` для `9007199254740993` не имеет
		 *          вовсе, и починить это здесь нечем - число приходит сюда уже потерянным.
		 *          Граница закреплена проверкой `NumberSpellingsAgreeUpToDoublePrecision`
		 *          обеими половинами: совпадением на пределе и расхождением за ним
		 */
		if(value == ::trunc(value)){
			/**
			 * Если число отрицательное
			 */
			if(value < 0.){
				/**
				 * Если число укладывается в разрядность целого со знаком
				 */
				if(value >= -::ldexp(1., 63))
					// Выводим приведённое число, завёрнутое по кругу путём целого
					return static_cast <T> (static_cast <int64_t> (value));
			/**
			 * Если число укладывается в разрядность целого без знака
			 */
			} else if(value < ::ldexp(1., 64))
				// Выводим приведённое число, завёрнутое по кругу путём целого
				return static_cast <T> (static_cast <uint64_t> (value));
		}
		/**
		 * Если целая часть числа лежит ниже предела затребованного вида
		 */
		if(value <= static_cast <double> (numeric_limits <T>::lowest()))
			// Выводим нижний предел затребованного вида
			return numeric_limits <T>::lowest();
		/**
		 * Если целая часть числа лежит выше предела затребованного вида
		 */
		if(value >= static_cast <double> (numeric_limits <T>::max()))
			// Выводим верхний предел затребованного вида
			return numeric_limits <T>::max();
		// Выводим приведённое число, округлённое по правилам математики
		return static_cast <T> (::round(value));
	}
	/**
	 * @brief Предел роста вместилища обращением по номеру
	 *
	 * @details Номер, пришедший извне, обращается требованием памяти по нему, и предел
	 * этот рост стережёт. Нуль снимает его вовсе: сколько памяти есть у приложения,
	 * ведомо ему одному
	 *
	 */
	static ::std::atomic <size_t> LIMIT(0x10000);
	/**
	 * @brief Функция снятия отменяющих записей звена пути
	 *
	 * @details Путь записывается тем же порядком, каким записывает его контейнер JSON, а
	 * порядок тот предписан RFC 6901: косая черта в имени записывается `~1`, а сам знак
	 * отмены - `~0`. Без снятия их имя, косую черту несущее, недостижимо вовсе - путь
	 * разбирался бы на два звена и уходил не туда
	 *
	 * @note Порядок снятия предписан стандартом: снятие `~0` прежде `~1` обратило бы
	 *       записанное `~01` в косую черту вместо `~1`
	 *
	 * @warning Запись неопознанная отвергается, а не берётся как есть: имя `~x`, принятое
	 *          дословно, стало бы вторым написанием того же места, и обход перестал бы
	 *          быть замкнутым - `keys()` выдаёт всякую тильду записанной
	 *
	 * @param token обрабатываемое звено пути
	 * @return      признак успешности снятия отменяющих записей
	 *
	 */
	static bool unescape(string & token) noexcept {
		/**
		 * Выполняем перебор всех знаков отмены звена пути
		 */
		for(size_t i = token.find('~'); i != string::npos; i = token.find('~', (i + 1))){
			/**
			 * Если за знаком отмены не осталось знаков
			 */
			if((i + 1) >= token.size())
				// Выводим признак неудачного снятия
				return false;
			/**
			 * Определяем отменяющую запись звена пути
			 */
			switch(token[i + 1]){
				// Если записана косая черта
				case '1':
					// Выполняем подмену отменяющей записи косой чертой
					token.replace(i, 2, "/");
				break;
				// Если записан сам знак отмены
				case '0':
					// Выполняем подмену отменяющей записи знаком отмены
					token.replace(i, 2, "~");
				break;
				// Если отменяющая запись не опознана
				default:
					// Выводим признак неудачного снятия
					return false;
			}
		}
		// Выводим признак успешного снятия отменяющих записей
		return true;
	}
	/**
	 * @brief Функция проверки записи на числовую
	 *
	 * @details Проверкой этой решается, чем является часть пути: номером значения
	 *          перечня либо именем пары таблицы. Таблица, пару числовую несущая,
	 *          разыскивается именем - тип вместилища решает раньше вида записи
	 *
	 * @param text  проверяемая запись
	 * @param index разбираемый порядковый номер
	 * @return      признак числовой записи
	 *
	 */
	static bool numbering(const string & text, size_t & index) noexcept {
		/**
		 * Если запись пуста вовсе
		 */
		if(text.empty())
			// Выводим признак того, что запись номером не является
			return false;
		/**
		 * Если запись ведущим нулём открывается
		 *
		 * @details Описание RFC 6901 в разделе 4 велит номеру быть либо одиноким нулём,
		 *          либо цифрою от единицы с цифрами за нею: запись `01` номером не
		 *          является ВОВСЕ. Прежде она разбиралась номером наравне с `1`, и путь
		 *          `/01` отдавал значение соседнее вместо отказа
		 *
		 * @note Отступление это снято по слову владельца: правило его гласит, что
		 *       описание стоит выше согласованности API, и коль скоро описание требует
		 *       для метода своей повадки, выбирать надлежит описание
		 */
		if((text.front() == '0') && (text.size() > 1))
			// Выводим признак того, что запись номером не является
			return false;
		// Выполняем сброс разбираемого номера значения
		index = 0;
		/**
		 * Выполняем перебор всех знаков записи
		 */
		for(const char letter : text){
			/**
			 * Если знак цифрой не является
			 */
			if((letter < '0') || (letter > '9'))
				// Выводим признак того, что запись номером не является
				return false;
			/**
			 * Если добавление разряда выведет номер за предел разрядности
			 *
			 * @details Номер разбирается беззнаковым, и переполнение его языком определено
			 * заворотом: запись `18446744073709551617` обращалась бы единицей, и обращение
			 * по такому пути отдавало бы соседнее значение молча
			 */
			if(index > ((numeric_limits <size_t>::max() - static_cast <size_t> (letter - '0')) / 10))
				// Выводим признак того, что запись номером не является
				return false;
			// Добавляем разряд к номеру значения вместилища
			index = ((index * 10) + static_cast <size_t> (letter - '0'));
		}
		// Выводим признак того, что запись является номером значения
		return true;
	}
	/**
	 * @brief Функция получения ссылки на неопределённое значение
	 *
	 * @details Обращение постоянное, ничего не разыскавшее, обязано выдать ссылку, а
	 *          не завести значение: значение это одно на весь кодек и живёт оно всю
	 *          работу приложения
	 *
	 * @return ссылка на неопределённое значение
	 *
	 */
