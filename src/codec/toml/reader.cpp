/**
 * @brief Метод запоминания ошибки разбора вместе с местом её обнаружения
 *
 * @param error  код ошибки разбора
 * @param offset положение обнаружения ошибки в приведённом тексте
 * @return       признак отказа для выхода из разбора
 *
 */
bool awh::codec::toml::Reader::failure(const error_t error, const size_t offset) noexcept {
	/**
	 * Если ошибка разбора уже запомнена
	 *
	 * @note Первая ошибка старше последующих: разбор после неё продолжения не имеет,
	 *       и подменять место её обнаружения местом следствия нельзя
	 */
	if(this->_error == error_t::NONE){
		// Запоминаем код ошибки разбора
		this->_error = error;
		// Запоминаем место обнаружения ошибки разбора
		this->_errorLocation = this->locate(offset);
	}
	// Запоминаем состояние прекращения разбора ошибкой
	this->_state = state_t::FAILED;
	/**
	 * Выполняем очистку очереди собранных событий отвергнутой записи
	 *
	 * @note Запись неделима: события её выдаются потребителю все разом либо не
	 *       выдаются вовсе. Очередь эта несёт события одной лишь разбираемой записи -
	 *       события записей, разобранных прежде, потребитель уже получил, - и без
	 *       очистки выдача зависела бы от нарезки текста на куски: подача целиком
	 *       успевала выдать события записи, отвергнутой ниже по тексту, а подача
	 *       кусками откатывала их вместе с самой записью
	 */
	this->_items.clear();
	// Выводим признак отказа для выхода из разбора
	return false;
}
/**
 * @brief Метод перемещения разбора к заданному положению текста
 *
 * @param offset положение, к которому перемещается разбор
 *
 */
void awh::codec::toml::Reader::step(const size_t offset) noexcept {
	/**
	 * Выполняем перебор знаков, через которые перемещается разбор
	 */
	for(size_t i = this->_offset; i < offset; i++){
		/**
		 * Если знаком является перевод строки
		 */
		if(this->_buffer[i] == '\n'){
			// Выполняем переход к следующей строке исходного текста
			this->_line++;
			// Запоминаем положение начала следующей строки
			this->_bol = (i + 1);
		}
	}
	// Запоминаем положение разбираемого знака
	this->_offset = offset;
}
/**
 * @brief Метод получения положения знака приведённого текста
 *
 * @param offset положение знака в приведённом тексте
 * @return       положение знака в исходном тексте
 *
 */
awh::codec::toml::location_t awh::codec::toml::Reader::locate(const size_t offset) const noexcept {
	// Собираемое положение знака в исходном тексте
	location_t result;
	/**
	 * Если знак стоит на строке, на которой стоит и разбор
	 *
	 * @note Положение считается от начала строки, а строка эта та, на которой стоит
	 *       разбор: место события запоминается при входе в него, а не по выходе -
	 *       иначе запись, начатая на одном куске и дочитанная на следующих, оставляла
	 *       бы своё начало позади
	 */
	if(offset >= this->_bol){
		// Запоминаем номер строки исходного текста
		result.line = this->_line;
		// Запоминаем положение знака в строке
		result.column = static_cast <uint32_t> ((offset - this->_bol) + 1);
	/**
	 * Если знак остался позади строки, на которой стоит разбор
	 *
	 * @note Отказ выдаётся и по разборе записи целиком - пределом длины её, - а место
	 *       его указывает на начало записи, разбором уже пройденное. Счёт строк
	 *       отматывается назад по накопленному тексту: иначе место отказа указывало бы
	 *       на строку, следующую за виновной
	 */
	} else {
		// Количество строк, на которое отматывается счёт
		uint32_t back = 0;
		/**
		 * Выполняем перебор знаков, отделяющих знак от строки разбора
		 */
		for(size_t i = offset; i < this->_bol; i++){
			/**
			 * Если знаком является перевод строки
			 */
			if(this->_buffer[i] == '\n')
				// Выполняем отматывание счёта строк на строку назад
				back++;
		}
		// Запоминаем номер строки исходного текста
		result.line = ((this->_line > back) ? (this->_line - back) : 1);
		// Положение начала строки, на которой стоит знак
		size_t bol = 0;
		/**
		 * Выполняем поиск начала строки, на которой стоит знак
		 */
		for(size_t i = offset; i > 0; i--){
			/**
			 * Если знаком является перевод строки
			 */
			if(this->_buffer[i - 1] == '\n'){
				// Запоминаем положение начала строки, на которой стоит знак
				bol = i;
				// Выходим из поиска начала строки
				break;
			}
		}
		// Запоминаем положение знака в строке
		result.column = static_cast <uint32_t> ((offset - bol) + 1);
	}
	// Запоминаем смещение знака от начала исходного текста
	result.offset = (this->_base + static_cast <uint64_t> (offset));
	// Выводим собранное положение знака
	return result;
}
/**
 * @brief Метод добавления последовательности знаков в хранилище записи
 *
 * @param text добавляемая последовательность знаков
 * @return     указание на добавленную последовательность
 *
 */
awh::codec::toml::Reader::span_t awh::codec::toml::Reader::keep(const string_view text) noexcept {
	// Собираемое указание на добавленную последовательность
	span_t result;
	// Запоминаем смещение начала последовательности в хранилище
	result.offset = static_cast <uint32_t> (this->_store.length());
	// Запоминаем длину добавляемой последовательности
	result.length = static_cast <uint32_t> (text.length());
	// Выполняем добавление последовательности в хранилище записи
	this->_store.append(text);
	// Выводим указание на добавленную последовательность
	return result;
}
/**
 * @brief Метод получения последовательности знаков хранилища записи
 *
 * @param span указание на последовательность знаков
 * @return     последовательность знаков хранилища
 *
 */
string_view awh::codec::toml::Reader::get(const span_t & span) const noexcept {
	// Выводим последовательность знаков хранилища записи
	return string_view(this->_store).substr(span.offset, span.length);
}
/**
 * @brief Метод пропуска пробельных знаков строки
 *
 */
void awh::codec::toml::Reader::spaces() noexcept {
	// Положение разбираемого знака приведённого текста
	size_t offset = this->_offset;
	/**
	 * Выполняем пропуск пробельных знаков строки
	 */
	while((offset < this->_buffer.length()) && ::blank(this->_buffer[offset]))
		// Выполняем переход к следующему знаку строки
		offset++;
	// Выполняем перемещение разбора за пробельные знаки
	this->step(offset);
}
/**
 * @brief Метод выдачи отложенного отказа приведения к кодировке UTF-8
 *
 * @return признак того, что отложенного отказа нет
 *
 */
bool awh::codec::toml::Reader::postponed() noexcept {
	/**
	 * Если отказа приведения к кодировке UTF-8 нет
	 */
	if(this->_decoding == error_t::NONE)
		// Выводим признак того, что отложенного отказа нет
		return true;
	/**
	 * Выполняем запоминание отложенной ошибки приведения
	 *
	 * @note Отказ выдаётся лишь по остановке разбора: события приведённого начала
	 *       потребитель обязан получить прежде отказа, и оба зовущих сюда пути
	 *       зовут по исчерпании событий - разбор к этому времени либо приведённое
	 *       начало исчерпал, либо встал посреди записи, продолжения которой ждёт.
	 *       Ждать его нечего: приведение отказом прекращено, и накопленный текст
	 *       больше не пополнится - без выдачи отказа здесь разбор застревал бы
	 *       навсегда, а исход его зависел бы от нарезки текста на куски
	 *
	 * @note Местом отказа берётся конец накопленного текста: приведение отказом
	 *       прекращено, и текст этот больше не пополнится - конец его и есть тот
	 *       знак, на котором приведение оборвалось
	 */
	return this->failure(this->_decoding, this->_buffer.length());
}
/**
 * @brief Метод проверки предела длины разбираемой записи
 *
 * @param offset положение конца разбираемой записи
 * @return       признак того, что предел не превышен
 *
 */
bool awh::codec::toml::Reader::oversize(const size_t offset) noexcept {
	/**
	 * Если предел длины записи настройками снят
	 */
	if(this->_settings.maxLine == 0)
		// Выводим признак того, что предел не превышен
		return true;
	// Положение конца содержимого разбираемой записи
	size_t end = offset;
	/**
	 * Выполняем отбрасывание окончания строки, записью пройденного
	 *
	 * @note Разбор записи оканчивается за знаком конца строки, а окончание это
	 *       содержимым записи не является: без отбрасывания одна и та же строка
	 *       предел то превышала бы, то нет - смотря по тому, оканчивается ли ею
	 *       текст, и каким из двух видов окончания она отделена от следующей
	 */
	if((end > this->_start) && (this->_buffer[end - 1] == '\n'))
		// Выполняем отбрасывание перевода строки
		end--;
	/**
	 * Если за отброшенным переводом строки стоит возврат каретки
	 */
	if((end > this->_start) && (this->_buffer[end - 1] == '\r'))
		// Выполняем отбрасывание возврата каретки
		end--;
	/**
	 * Если длина разбираемой записи предел превышает
	 *
	 * @note Меряется запись целиком - вместе со всеми строками многострочного
	 *       значения: иначе многострочная запись давала бы обход предела
	 */
	if((end - this->_start) > static_cast <size_t> (this->_settings.maxLine))
		// Выполняем запоминание ошибки превышения предела длины записи
		return this->failure(error_t::LINE_TOO_LONG, this->_start);
	// Выводим признак того, что предел не превышен
	return true;
}
/**
 * @brief Метод сборки полного имени из составных частей
 *
 * @param part   номер первой составной части имени
 * @param parts  количество составных частей имени
 * @param result собираемое полное имя
 *
 */
void awh::codec::toml::Reader::assemble(const uint32_t part, const uint32_t parts, string & result) const noexcept {
	/**
	 * Выполняем перебор составных частей имени
	 */
	for(uint32_t i = 0; i < parts; i++){
		/**
		 * Выполняем добавление разделителя составных частей имени
		 *
		 * @note Разделителем берётся знак, в имени недопустимый вовсе: составные части
		 *       имён «a.b» и «a\x1Fb» иначе давали бы одно и то же полное имя, и повтор
		 *       обнаруживался бы там, где его нет
		 *
		 * @note Разделитель ставится перед всякой частью, а не между частями: имя
		 *       ключа описанием дозволено пустым, и без него таблица «[""]» давала бы
		 *       то же полное имя, что и верхний уровень текста настроек, - ключ её
		 *       считался бы повтором одноимённого ключа верхнего уровня
		 */
		result.push_back('\x1F');
		// Выполняем добавление очередной составной части имени
		result.append(this->get(this->_segments.at(part + i).name));
	}
}
/**
 * @brief Метод переноса имени в хранилище объявленных имён
 *
 * @param name переносимое имя ключа либо таблицы
 * @return     ссылка на имя, перенесённое в хранилище
 *
 */
string_view awh::codec::toml::Reader::intern(const string_view name) noexcept {
	/**
	 * @brief Размер блока хранилища объявленных имён в байтах
	 *
	 */
	constexpr size_t BLOCK = 0x4000;
	/**
	 * Если блока хранилища не заведено либо в нём не осталось места
	 *
	 * @note Место в блоке отводится заранее и не наращивается: дописывание сверх
	 *       отведённого перенесло бы содержимое блока, обесценив ссылки на имена
	 */
	if(this->_blocks.empty() || ((this->_blocks.back().length() + name.length()) > this->_blocks.back().capacity())){
		// Выполняем заведение очередного блока хранилища
		this->_blocks.push_back(string());
		// Выполняем отведение места под содержимое блока хранилища
		this->_blocks.back().reserve((name.length() > BLOCK) ? name.length() : BLOCK);
	}
	// Получаем блок хранилища объявленных имён
	string & block = this->_blocks.back();
	// Запоминаем смещение начала имени в блоке хранилища
	const size_t offset = block.length();
	// Выполняем перенос имени в блок хранилища
	block.append(name);
	// Выводим ссылку на имя, перенесённое в хранилище
	return string_view(block.data() + offset, name.length());
}
/**
 * @brief Метод получения рода уже объявленного имени
 *
 * @param name искомое полное имя ключа либо таблицы
 * @return     род объявленного имени
 *
 */
awh::codec::toml::Reader::kind_t awh::codec::toml::Reader::lookup(const string_view name) const noexcept {
	/**
	 * Выполняем поиск имени среди объявляемых разбираемой записью
	 *
	 * @note Поиск ведётся первым: запись вправе объявить имя дважды сама, и имена её
	 *       в указатель родов до окончания разбора не переносятся
	 */
	const size_t position = this->staged(name);
	/**
	 * Если имя объявляется разбираемой записью
	 */
	if(position < this->_pending.size())
		// Выводим род объявляемого имени
		return this->_pending.at(position).kind;
	// Выполняем поиск имени в указателе родов объявленных имён
	auto i = this->_names.find(name);
	// Выводим род объявленного имени
	return ((i != this->_names.end()) ? i->second : kind_t::NONE);
}
/**
 * @brief Метод поиска имени среди объявляемых разбираемой записью
 *
 * @param name искомое полное имя ключа либо таблицы
 * @return     номер имени в очереди объявляемых либо количество их
 *
 */
size_t awh::codec::toml::Reader::staged(const string_view name) const noexcept {
	/**
	 * Если указатель имён записи заведён
	 */
	if(!this->_staged.empty()){
		// Выполняем поиск имени в указателе имён записи
		auto i = this->_staged.find(name);
		// Выводим номер найденного имени в очереди объявляемых
		return ((i != this->_staged.end()) ? static_cast <size_t> (i->second) : this->_pending.size());
	}
	/**
	 * Выполняем перебор имён, объявляемых разбираемой записью
	 *
	 * @note Перебор ведётся, пока имён немного: обычная запись объявляет их считанные
	 *       единицы, и указатель стоил бы ей выделения памяти на всякое имя
	 */
	for(size_t i = 0; i < this->_pending.size(); i++){
		/**
		 * Если имя объявляется разбираемой записью
		 */
		if(this->_pending.at(i).name.compare(name) == 0)
			// Выводим номер найденного имени в очереди объявляемых
			return i;
	}
	// Выводим количество имён, объявляемых разбираемой записью
	return this->_pending.size();
}
/**
 * @brief Метод учёта имени, объявляемого разбираемой записью
 *
 * @param name    объявляемое полное имя ключа либо таблицы
 * @param kind    род объявляемого имени
 * @param implied признак того, что имя заведено исподволь
 *
 */
void awh::codec::toml::Reader::stage(const string_view name, const kind_t kind, const bool implied) noexcept {
	/**
	 * @brief Порог числа имён, за которым перебор их обращается в указатель
	 *
	 */
	constexpr size_t THRESHOLD = 16;
	// Выполняем запоминание имени, объявляемого разбираемой записью
	this->_pending.emplace_back(name, kind, implied);
	/**
	 * Если имён записи для заведения указателя недостаточно
	 */
	if(this->_pending.size() <= THRESHOLD)
		// Выходим из учёта объявляемого имени
		return;
	/**
	 * Если указатель имён записи ещё не заведён
	 */
	if(this->_staged.empty()){
		/**
		 * Выполняем перебор всех имён, объявляемых разбираемой записью
		 */
		for(size_t i = 0; i < this->_pending.size(); i++)
			// Выполняем установку объявляемого имени указателем
			this->_staged.emplace(this->_pending.at(i).name, static_cast <uint32_t> (i));
		// Выходим из учёта объявляемого имени
		return;
	}
	// Выполняем установку объявляемого имени указателем
	this->_staged.emplace(this->_pending.back().name, static_cast <uint32_t> (this->_pending.size() - 1));
}
/**
 * @brief Метод проверки занятости объемлющих имён
 *
 * @param name   проверяемое полное имя ключа либо таблицы
 * @param offset положение объявления в приведённом тексте
 * @return       признак того, что объемлющие имена свободны
 *
 */
bool awh::codec::toml::Reader::occupied(const string & name, const size_t offset) noexcept {
	/**
	 * Выполняем перебор всех объемлющих имён проверяемого имени
	 *
	 * @note Разделитель стоит перед всякой частью имени, и всякое его вхождение,
	 *       кроме первого, отделяет очередное объемлющее имя
	 */
	for(size_t i = 0; (i = name.find('\x1F', i + 1)) != string::npos;){
		/**
		 * Определяем род объемлющего имени
		 */
		switch(static_cast <uint8_t> (this->lookup(string_view(name).substr(0, i)))){
			/**
			 * Если объемлющее имя занято встроенной таблицей
			 *
			 * @note Встроенная таблица закрыта своими скобками: описание запрещает
			 *       дополнять её и заголовком, и составным именем ключа
			 */
			case static_cast <uint8_t> (kind_t::INLINE):
				// Выполняем запоминание ошибки дополнения встроенной таблицы
				return this->failure(error_t::EXTEND_INLINE_TABLE, offset);
			/**
			 * Если объемлющее имя занято парой
			 *
			 * @note Под простым значением и под перечнем не заводится ничего: имя
			 *       меняло бы при этом свой тип
			 */
			case static_cast <uint8_t> (kind_t::VALUE):
				// Выполняем запоминание ошибки переопределения заданного значения
				return this->failure(error_t::REDEFINE_TABLE, offset);
		}
	}
	// Выводим признак того, что объемлющие имена свободны
	return true;
}
/**
 * @brief Метод проверки повторного объявления имени
 *
 * @param name   объявляемое полное имя ключа либо таблицы
 * @param kind   род объявляемого имени
 * @param error  код ошибки повторного объявления
 * @param offset положение объявления в приведённом тексте
 * @return       признак того, что имя объявляется впервые
 *
 */
bool awh::codec::toml::Reader::declare(const string & name, const kind_t kind, const error_t error, const size_t offset) noexcept {
	/**
	 * Если проверка повторного объявления настройками отключена
	 */
	if(!this->_settings.duplicates)
		// Выводим признак того, что имя объявляется впервые
		return true;
	/**
	 * Если объемлющие имена объявляемого имени заняты
	 */
	if(!this->occupied(name, offset))
		// Выводим признак неудачного объявления имени
		return false;
	// Получаем род уже объявленного имени
	const kind_t current = this->lookup(name);
	/**
	 * Определяем род объявляемого имени
	 */
	switch(static_cast <uint8_t> (kind)){
		/**
		 * Если объявляется заголовок таблицы
		 *
		 * @note Таблицу, заведённую исподволь объемлющим именем заголовка, дозволено
		 *       объявить явно: описание отводит заголовку «[x]» право объявить
		 *       надтаблицу, заведённую прежде заголовком «[x.y]»
		 */
		case static_cast <uint8_t> (kind_t::TABLE): {
			/**
			 * Если имя уже занято
			 */
			if((current != kind_t::NONE) && (current != kind_t::IMPLICIT))
				// Выполняем запоминание ошибки повторного объявления имени
				return this->failure(error, offset);
		} break;
		/**
		 * Если объявляется заголовок набора таблиц
		 */
		case static_cast <uint8_t> (kind_t::ARRAY): {
			/**
			 * Если имя уже занято не набором таблиц
			 *
			 * @note Дополнять набором таблиц имя, набором таблиц не являющееся,
			 *       описание запрещает: значение по имени меняло бы свой тип
			 */
			if((current != kind_t::NONE) && (current != kind_t::ARRAY))
				// Выполняем запоминание ошибки дополнения таблицы набором
				return this->failure(error, offset);
		} break;
		/**
		 * Если объявляется пара имени ключа со значением
		 */
		default: {
			/**
			 * Если имя уже занято
			 */
			if(current != kind_t::NONE)
				// Выполняем запоминание ошибки повторного объявления имени
				return this->failure(error, offset);
		}
	}
	/**
	 * Выполняем перебор всех объемлющих имён объявляемого имени
	 *
	 * @note Всякое объемлющее имя заводит таблицу исподволь, и род её разнится:
	 *       заведённую заголовком дозволено объявить явно, а заведённую составным
	 *       именем ключа - нет
	 */
	for(size_t i = 0; (i = name.find('\x1F', i + 1)) != string::npos;){
		// Получаем очередное объемлющее имя
		const string_view prefix = string_view(name).substr(0, i);
		/**
		 * Если объемлющее имя ещё не заведено
		 */
		if(this->lookup(prefix) == kind_t::NONE)
			// Выполняем учёт имени, заводимого исподволь
			this->stage(prefix, (((kind == kind_t::TABLE) || (kind == kind_t::ARRAY)) ?
				kind_t::IMPLICIT : kind_t::DOTTED), true);
	}
	// Выполняем учёт имени, объявляемого разбираемой записью
	this->stage(name, kind, false);
	// Выводим признак того, что имя объявляется впервые
	return true;
}
/**
 * @brief Метод изъятия разобранного начала накопленного текста
 *
 */
void awh::codec::toml::Reader::compact() noexcept {
	/**
	 * Если разобранного начала для изъятия недостаточно
	 */
	if(this->_offset < COMPACT_THRESHOLD)
		// Выходим из изъятия разобранного начала
		return;
	// Запоминаем смещение начала приведённого текста от начала исходного
	this->_base += static_cast <uint64_t> (this->_offset);
	/**
	 * Выполняем изъятие разобранного начала накопленного текста
	 *
	 * @note Положения, отсчитываемые от начала хранилища, изъятием обесцениваются, и
	 *       сдвигать надлежит их все: начало строки, начало записи и само положение
	 *       разбора
	 */
	this->_buffer.erase(0, this->_offset);
	// Выполняем сдвиг положения начала разбираемой строки
	this->_bol = ((this->_bol > this->_offset) ? (this->_bol - this->_offset) : 0);
	// Выполняем сдвиг положения начала разбираемой записи
	this->_start = ((this->_start > this->_offset) ? (this->_start - this->_offset) : 0);
	// Выполняем сдвиг положения разбираемого знака
	this->_offset = 0;
}
/**
 * @brief Метод проверки завершённости строки в накопленном тексте
 *
 * @param end признак того, что текст поступил целиком
 * @return    признак того, что строка накоплена целиком
 *
 */
bool awh::codec::toml::Reader::completed(const bool end) noexcept {
	/**
	 * Если текст поступил целиком
	 */
	if(end)
		// Выводим признак того, что строка накоплена целиком
		return true;
	/**
	 * Выполняем поиск знака конца строки в накопленном тексте
	 */
	if(this->_buffer.find('\n', this->_offset) != string::npos)
		// Выводим признак того, что строка накоплена целиком
		return true;
	// Запоминаем нужду в продолжении текста
	this->_hungry = true;
	// Выводим признак того, что строка накоплена не целиком
	return false;
}
/**
 * @brief Метод разбора примечания, начатого текущим знаком
 *
 * @details Разбор ведётся от знака начала примечания, на который указывает текущее
 * положение, и до места конца содержимого его. Собранное событие уходит в очередь
 * выдачи, если выдача примечаний настройками разрешена
 *
 * @param position положение конца содержимого примечания
 * @param trailing признак примечания, дописанного к готовой строке
 * @return         признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::commented(const size_t position, const bool trailing) noexcept {
	// Собираемое событие примечания
	item_t item;
	// Запоминаем вид собранного события
	item.event = event_t::COMMENT;
	// Запоминаем признак того, что примечание дописано к готовой строке
	item.trailing = trailing;
	// Запоминаем место примечания в исходном тексте
	item.location = this->locate(this->_offset);
	// Выполняем пропуск знака начала примечания
	this->step(this->_offset + 1);
	// Получаем содержимое примечания
	string_view text = string_view(this->_buffer).substr(this->_offset, (position - this->_offset));
	/**
	 * Если содержимое примечания оканчивается возвратом каретки
	 */
	if(!text.empty() && (text.back() == '\r'))
		// Выполняем отбрасывание возврата каретки
		text = text.substr(0, (text.length() - 1));
	/**
	 * Выполняем перебор всех знаков содержимого примечания
	 */
	for(size_t i = 0; i < text.length(); i++){
		// Получаем беззнаковое значение очередного знака содержимого
		const uint8_t letter = static_cast <uint8_t> (text[i]);
		/**
		 * Если знак содержимого примечания является управляющим
		 *
		 * @note Описание дозволяет примечанию нести из управляющих знаков одну лишь
		 *       табуляцию. Возврат каретки к тому же неотличим здесь от окончания
		 *       строки: примечание, его несущее, записью выдавалось бы окончанием,
		 *       и перезапись текста настроек устойчивости лишалась бы
		 */
		if(((letter < 0x20) && (text[i] != '\t')) || (letter == 0x7F))
			// Выполняем запоминание ошибки недопустимого знака
			return this->failure(error_t::INVALID_CHARACTER, (this->_offset + i));
	}
	/**
	 * Выполняем отбрасывание пробельной обвязки содержимого примечания
	 */
	while(!text.empty() && ::blank(text.front()))
		// Выполняем отбрасывание пробельного знака начала содержимого
		text = text.substr(1);
	// Запоминаем содержимое примечания в хранилище записи
	item.content = this->keep(text);
	// Выполняем перемещение разбора за содержимое примечания
	this->step(position);
	/**
	 * Если выдача событий примечаний настройками разрешена
	 */
	if(this->_settings.emitComments)
		// Выполняем добавление собранного события в очередь выдачи
		this->_items.push_back(item);
	// Выводим признак успешного разбора
	return true;
}
/**
 * @brief Метод разбора остатка строки за завершённой записью
 *
 * @param end признак того, что текст поступил целиком
 * @return    признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::tail(const bool end) noexcept {
	// Выполняем пропуск пробельных знаков строки
	this->spaces();
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выводим признак успешного разбора
			return true;
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	/**
	 * Если за записью следует примечание
	 */
	if(this->_buffer[this->_offset] == '#'){
		/**
		 * Если строка накоплена не целиком
		 */
		if(!this->completed(end))
			// Выводим признак неудачного разбора
			return false;
		// Положение конца содержимого примечания
		size_t position = this->_buffer.find('\n', this->_offset);
		/**
		 * Если знак конца строки в накопленном тексте отсутствует
		 */
		if(position == string::npos)
			// Запоминаем положение конца содержимого примечания
			position = this->_buffer.length();
		/**
		 * Если разобрать примечание не удалось
		 */
		if(!this->commented(position, true))
			// Выводим признак неудачного разбора
			return false;
	}
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выводим признак успешного разбора
			return true;
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	/**
	 * Если строка оканчивается возвратом каретки
	 */
	if(this->_buffer[this->_offset] == '\r'){
		/**
		 * Если за возвратом каретки перевода строки не накоплено
		 */
		if((this->_offset + 1) >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 *
			 * @note Возврат каретки сам по себе концом строки не является: описание
			 *       отводит концом строки перевод строки и пару из возврата с переводом
			 */
			if(end)
				// Выполняем запоминание ошибки недопустимого знака
				return this->failure(error_t::INVALID_CHARACTER, this->_offset);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если за возвратом каретки перевод строки не следует
		 */
		if(this->_buffer[this->_offset + 1] != '\n')
			// Выполняем запоминание ошибки недопустимого знака
			return this->failure(error_t::INVALID_CHARACTER, this->_offset);
		// Выполняем пропуск возврата каретки
		this->step(this->_offset + 1);
	}
	/**
	 * Если строка оканчивается переводом строки
	 */
	if(this->_buffer[this->_offset] == '\n'){
		// Выполняем пропуск знака конца строки
		this->step(this->_offset + 1);
		// Выводим признак успешного разбора
		return true;
	}
	// Выполняем запоминание ошибки содержимого за завершённой записью
	return this->failure(error_t::UNEXPECTED_CONTENT, this->_offset);
}
/**
 * @brief Метод разбора строкового значения
 *
 * @param end     признак того, что текст поступил целиком
 * @param quoting запись разобранного строкового значения
 * @param result  указание на разобранное содержимое
 * @return        признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::literal(const bool end, string_t & quoting, span_t & result) noexcept {
	// Получаем знак кавычки, которой значение ограждено
	const char quote = this->_buffer[this->_offset];
	// Запоминаем положение начала строкового значения
	const size_t opening = this->_offset;
	// Признак того, что значение записано многострочным
	bool multiline = false;
	/**
	 * Если за первой кавычкой накоплено ещё два знака
	 */
	if((this->_offset + 2) < this->_buffer.length())
		// Запоминаем признак многострочной записи значения
		multiline = ((this->_buffer[this->_offset + 1] == quote) && (this->_buffer[this->_offset + 2] == quote));
	/**
	 * Если накопленного текста для распознания записи недостаточно
	 */
	else if(!end) {
		/**
		 * Если за первой кавычкой стоит вторая
		 *
		 * @note Две кавычки подряд означают либо пустое значение, либо начало
		 *       многострочной записи, и различить их можно лишь по третьему знаку:
		 *       без него разбор откладывается до прихода продолжения
		 */
		if(((this->_offset + 1) >= this->_buffer.length()) || (this->_buffer[this->_offset + 1] == quote)){
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
	}
	// Запоминаем запись разобранного строкового значения
	quoting = (quote == '"' ?
		(multiline ? string_t::MULTILINE_BASIC : string_t::BASIC) :
		(multiline ? string_t::MULTILINE_LITERAL : string_t::LITERAL));
	// Получаем признак разбора управляющих последовательностей
	const bool escapes = (quote == '"');
	// Выполняем пропуск знаков ограждения значения
	this->step(this->_offset + (multiline ? 3 : 1));
	// Собираемое содержимое строкового значения
	string content;
	/**
	 * Если значение записано многострочным
	 */
	if(multiline){
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки незакрытого строкового значения
				return this->failure(error_t::UNTERMINATED_STRING, opening);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если за знаками ограждения следует возврат каретки
		 */
		if(this->_buffer[this->_offset] == '\r'){
			/**
			 * Если за возвратом каретки перевод строки накоплен
			 */
			if(((this->_offset + 1) < this->_buffer.length()) && (this->_buffer[this->_offset + 1] == '\n'))
				// Выполняем пропуск возврата каретки
				this->step(this->_offset + 1);
		}
		/**
		 * Если за знаками ограждения следует знак конца строки
		 *
		 * @note Знак этот описание отбрасывает: перенос за открывающими кавычками
		 *       ставят ради вида записи, а не ради содержимого
		 */
		if((this->_offset < this->_buffer.length()) && (this->_buffer[this->_offset] == '\n'))
			// Выполняем пропуск знака конца строки
			this->step(this->_offset + 1);
	}
	/**
	 * Выполняем перебор знаков строкового значения
	 */
	while(true){
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки незакрытого строкового значения
				return this->failure(error_t::UNTERMINATED_STRING, opening);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		// Получаем очередной знак строкового значения
		const char letter = this->_buffer[this->_offset];
		/**
		 * Если знаком является кавычка ограждения
		 */
		if(letter == quote){
			/**
			 * Если значение записано однострочным
			 */
			if(!multiline){
				// Выполняем пропуск закрывающей кавычки значения
				this->step(this->_offset + 1);
				// Запоминаем содержимое строкового значения в хранилище записи
				result = this->keep(content);
				// Выводим признак успешного разбора
				return true;
			}
			// Количество кавычек, стоящих подряд
			size_t count = 0;
			/**
			 * Выполняем подсчёт кавычек, стоящих подряд
			 */
			while(((this->_offset + count) < this->_buffer.length()) && (this->_buffer[this->_offset + count] == quote))
				// Выполняем увеличение количества кавычек
				count++;
			/**
			 * Если кавычек накоплено меньше пяти, а текст не исчерпан
			 *
			 * @note Описание дозволяет двум кавычкам стоять внутри многострочного
			 *       значения, а закрывающими считает три подряд; пять подряд означают
			 *       две кавычки в конце содержимого. Судить о числе их можно лишь тогда,
			 *       когда накоплено пять либо текст оборвался
			 */
			if((count < 5) && ((this->_offset + count) >= this->_buffer.length()) && !end){
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			/**
			 * Если кавычек меньше трёх
			 */
			if(count < 3){
				/**
				 * Выполняем добавление кавычек к содержимому значения
				 */
				for(size_t i = 0; i < count; i++)
					// Выполняем добавление кавычки к содержимому значения
					content.push_back(quote);
				// Выполняем перемещение разбора за кавычки
				this->step(this->_offset + count);
				// Переходим к следующему знаку строкового значения
				continue;
			}
			/**
			 * Если кавычек больше пяти
			 *
			 * @note Больше пяти подряд описание не дозволяет: две кавычки содержимого
			 *       вместе с тремя закрывающими дают предел
			 */
			if(count > 5)
				// Выполняем запоминание ошибки построения значения
				return this->failure(error_t::INVALID_VALUE, this->_offset);
			/**
			 * Выполняем добавление кавычек содержимого к значению
			 */
			for(size_t i = 3; i < count; i++)
				// Выполняем добавление кавычки к содержимому значения
				content.push_back(quote);
			// Выполняем пропуск закрывающих кавычек значения
			this->step(this->_offset + count);
			// Запоминаем содержимое строкового значения в хранилище записи
			result = this->keep(content);
			// Выводим признак успешного разбора
			return true;
		}
		/**
		 * Если знаком является перевод строки
		 */
		if(letter == '\n'){
			/**
			 * Если значение записано однострочным
			 *
			 * @note Однострочное значение знака конца строки не переживает: описание
			 *       требует закрыть его кавычкой прежде конца строки
			 */
			if(!multiline)
				// Выполняем запоминание ошибки незакрытого строкового значения
				return this->failure(error_t::UNTERMINATED_STRING, opening);
			// Выполняем добавление знака конца строки к содержимому значения
			content.push_back(letter);
			// Выполняем переход к следующему знаку значения
			this->step(this->_offset + 1);
			// Переходим к следующему знаку строкового значения
			continue;
		}
		/**
		 * Если знаком является возврат каретки
		 */
		if(letter == '\r'){
			/**
			 * Если за возвратом каретки перевода строки не накоплено
			 */
			if((this->_offset + 1) >= this->_buffer.length()){
				/**
				 * Если текст поступил целиком
				 */
				if(end)
					// Выполняем запоминание ошибки недопустимого знака
					return this->failure(error_t::INVALID_CHARACTER, this->_offset);
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			/**
			 * Если за возвратом каретки перевод строки не следует
			 */
			if(this->_buffer[this->_offset + 1] != '\n')
				// Выполняем запоминание ошибки недопустимого знака
				return this->failure(error_t::INVALID_CHARACTER, this->_offset);
			// Выполняем пропуск возврата каретки
			this->step(this->_offset + 1);
			// Переходим к следующему знаку строкового значения
			continue;
		}
		/**
		 * Если знак в строковом значении недопустим
		 *
		 * @note Управляющие знаки области C0 описание в строковом значении запрещает
		 *       сырыми, дозволяя из них лишь табуляцию: записывают их управляющей
		 *       последовательностью
		 */
		if((static_cast <uint8_t> (letter) < 0x20) && (letter != '\t'))
			// Выполняем запоминание ошибки недопустимого знака
			return this->failure(error_t::INVALID_CHARACTER, this->_offset);
		/**
		 * Если знаком является обратная косая черта при разборе последовательностей
		 */
		if(escapes && (letter == '\\')){
			/**
			 * Если за обратной косой чертой знака не накоплено
			 */
			if((this->_offset + 1) >= this->_buffer.length()){
				/**
				 * Если текст поступил целиком
				 */
				if(end)
					// Выполняем запоминание ошибки построения последовательности
					return this->failure(error_t::INVALID_ESCAPE, this->_offset);
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			// Получаем знак, следующий за обратной косой чертой
			const char next = this->_buffer[this->_offset + 1];
			/**
			 * Если значение записано многострочным, а за чертой стоит пробельный знак
			 *
			 * @note Черта в конце строки многострочного значения отбрасывает знак конца
			 *       строки вместе со всей пробельной обвязкой следующей строки: так
			 *       длинное значение записывают в несколько строк, не внося переносов
			 */
			if(multiline && (::blank(next) || (next == '\n') || (next == '\r'))){
				// Положение разбираемого знака приведённого текста
				size_t offset = (this->_offset + 1);
				// Признак того, что знак конца строки за чертой обнаружен
				bool folded = false;
				/**
				 * Выполняем пропуск пробельных знаков за обратной косой чертой
				 */
				while(offset < this->_buffer.length()){
					// Получаем очередной пропускаемый знак
					const char letter = this->_buffer[offset];
					/**
					 * Если знаком является перевод строки
					 */
					if(letter == '\n'){
						// Запоминаем признак обнаружения знака конца строки
						folded = true;
						// Выполняем переход к следующему знаку
						offset++;
						// Переходим к следующему знаку пропуска
						continue;
					}
					/**
					 * Если знак пробельным не является
					 */
					if(!::blank(letter) && (letter != '\r'))
						// Выходим из цикла пропуска пробельных знаков
						break;
					// Выполняем переход к следующему знаку
					offset++;
				}
				/**
				 * Если накопленный текст исчерпан пропуском
				 */
				if((offset >= this->_buffer.length()) && !end){
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Если знака конца строки за чертой не обнаружено
				 *
				 * @note Черта, за которой стоят одни пробелы, последовательностью не
				 *       является: описание дозволяет ей отбрасывать лишь перенос строки
				 */
				if(!folded)
					// Выполняем запоминание ошибки построения последовательности
					return this->failure(error_t::INVALID_ESCAPE, this->_offset);
				// Выполняем перемещение разбора за отброшенные знаки
				this->step(offset);
				// Переходим к следующему знаку строкового значения
				continue;
			}
			// Кодовое значение знака управляющей последовательности
			uint32_t code = 0;
			// Количество знаков записи кодового значения
			size_t count = 0;
			/**
			 * Определяем знак, следующий за обратной косой чертой
			 */
			switch(next){
				// Если знаком является перевод строки
				case 'n': code = '\n'; break;
				// Если знаком является горизонтальная табуляция
				case 't': code = '\t'; break;
				// Если знаком является возврат каретки
				case 'r': code = '\r'; break;
				// Если знаком является забой
				case 'b': code = '\b'; break;
				// Если знаком является перевод страницы
				case 'f': code = '\f'; break;
				// Если знаком является обратная косая черта
				case '\\': code = '\\'; break;
				// Если знаком является двойная кавычка
				case '"': code = '"'; break;
				// Если знак записан кодовым значением Юникода
				case 'u': count = 4; break;
				// Если знак записан полным кодовым значением Юникода
				case 'U': count = 8; break;
				// Если знак за обратной косой чертой управляющим не является
				default: return this->failure(error_t::INVALID_ESCAPE, this->_offset);
			}
			/**
			 * Если знак записан кодовым значением Юникода
			 */
			if(count > 0){
				/**
				 * Если знаков записи кодового значения не накоплено
				 */
				if((this->_offset + 2 + count) > this->_buffer.length()){
					/**
					 * Если текст поступил целиком
					 */
					if(end)
						// Выполняем запоминание ошибки построения последовательности
						return this->failure(error_t::INVALID_ESCAPE, this->_offset);
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Выполняем перебор знаков записи кодового значения
				 */
				for(size_t i = 0; i < count; i++){
					// Получаем значение очередного шестнадцатеричного знака
					const int32_t digit = ascii::hexValue(this->_buffer[this->_offset + 2 + i]);
					/**
					 * Если знак записи кодового значения шестнадцатеричным не является
					 */
					if(digit < 0)
						// Выполняем запоминание ошибки построения последовательности
						return this->failure(error_t::INVALID_ESCAPE, this->_offset);
					// Добавляем к кодовому значению разряды прочитанного знака
					code = ((code << 4) | static_cast <uint32_t> (digit));
				}
				/**
				 * Если записанное кодовое значение знаком Юникода не является
				 */
				if(((code >= 0xD800) && (code <= 0xDFFF)) || (code > MAX_CODEPOINT))
					// Выполняем запоминание ошибки построения последовательности
					return this->failure(error_t::INVALID_ESCAPE, this->_offset);
			}
			/**
			 * Если запись знака в кодировке UTF-8 выполнить не удалось
			 */
			if(!encode(code, content))
				// Выполняем запоминание ошибки построения последовательности
				return this->failure(error_t::INVALID_ESCAPE, this->_offset);
			// Выполняем перемещение разбора за управляющую последовательность
			this->step(this->_offset + 2 + count);
			// Переходим к следующему знаку строкового значения
			continue;
		}
		// Выполняем добавление знака к содержимому значения
		content.push_back(letter);
		// Выполняем переход к следующему знаку значения
		this->step(this->_offset + 1);
	}
}
/**
 * @brief Метод разбора имени ключа
 *
 * @param end   признак того, что текст поступил целиком
 * @param count количество разобранных составных частей имени
 * @return      признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::name(const bool end, uint32_t & count) noexcept {
	// Выполняем сброс количества разобранных составных частей имени
	count = 0;
	/**
	 * Выполняем разбор составных частей имени ключа
	 */
	while(true){
		// Выполняем пропуск пробельных знаков строки
		this->spaces();
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки пустого имени ключа
				return this->failure(error_t::EMPTY_KEY, this->_offset);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		// Собираемая составная часть имени ключа
		segment_t segment;
		// Получаем знак начала составной части имени
		const char letter = this->_buffer[this->_offset];
		/**
		 * Если составная часть имени ограждена кавычками
		 */
		if((letter == '"') || (letter == '\'')){
			// Запись разобранного строкового значения
			string_t quoting = string_t::BASIC;
			/**
			 * Если разбор строкового значения имени не удался
			 */
			if(!this->literal(end, quoting, segment.name))
				// Выводим признак неудачного разбора
				return false;
			/**
			 * Если имя записано многострочной строкой
			 *
			 * @note Описание дозволяет имени лишь однострочную запись: многострочная в
			 *       имени ошибочна независимо от содержимого
			 */
			if((quoting == string_t::MULTILINE_BASIC) || (quoting == string_t::MULTILINE_LITERAL))
				// Выполняем запоминание ошибки построения имени ключа
				return this->failure(error_t::INVALID_KEY, this->_start);
			// Запоминаем запись имени составной части
			segment.naming = ((quoting == string_t::BASIC) ? naming_t::BASIC : naming_t::LITERAL);
		/**
		 * Если составная часть имени записана без кавычек
		 */
		} else {
			// Положение конца составной части имени
			size_t position = this->_offset;
			/**
			 * Выполняем перебор знаков составной части имени
			 */
			while(position < this->_buffer.length()){
				/**
				 * Если знак имени задан знаком US-ASCII
				 */
				if(bare(this->_buffer[position])){
					// Выполняем переход к следующему знаку имени
					position++;
					// Переходим к следующему знаку составной части имени
					continue;
				}
				/**
				 * Если знаки Юникода в имени без кавычек настройками не признаются
				 */
				if(!this->_settings.unicode || (static_cast <uint8_t> (this->_buffer[position]) < 0x80))
					// Выходим из перебора знаков составной части имени
					break;
				// Очередной знак Юникода составной части имени
				uint32_t code = 0;
				// Получаем количество байт очередного знака Юникода
				const size_t length = toml::decode(this->_buffer, position, code);
				/**
				 * Если знак Юникода имени оборван концом накопленного текста
				 *
				 * @note Оборванный знак от битого отличается лишь приходом продолжения:
				 *       судить о нём по накопленному тексту нельзя, покуда текст не
				 *       поступил целиком
				 */
				if((length == 0) && !end && ((position + 4) > this->_buffer.length())){
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Если знак Юникода имени без кавычек не дозволен
				 */
				if((length == 0) || !toml::named(code))
					// Выходим из перебора знаков составной части имени
					break;
				// Выполняем переход к следующему знаку имени
				position += length;
			}
			/**
			 * Если составная часть имени пуста
			 */
			if(position == this->_offset)
				// Выполняем запоминание ошибки пустого имени ключа
				return this->failure(error_t::EMPTY_KEY, this->_offset);
			/**
			 * Если накопленный текст исчерпан именем
			 *
			 * @note Имя, дошедшее до конца накопленного текста, оборванным быть не
			 *       перестаёт: следующий кусок вправе продолжить его новыми знаками
			 */
			if((position >= this->_buffer.length()) && !end){
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			// Запоминаем имя составной части в хранилище записи
			segment.name = this->keep(string_view(this->_buffer).substr(this->_offset, (position - this->_offset)));
			// Выполняем перемещение разбора за составную часть имени
			this->step(position);
		}
		/**
		 * Если длина составной части имени предел настроек превышает
		 */
		if((this->_settings.maxKey > 0) && (segment.name.length > this->_settings.maxKey))
			// Выполняем запоминание ошибки превышения предела длины имени
			return this->failure(error_t::KEY_TOO_LONG, this->_start);
		// Выполняем добавление составной части к имени ключа
		this->_segments.push_back(segment);
		// Выполняем увеличение количества составных частей имени
		count++;
		/**
		 * Если количество составных частей имени предел настроек превышает
		 */
		if((this->_settings.maxParts > 0) && (count > this->_settings.maxParts))
			// Выполняем запоминание ошибки превышения количества частей имени
			return this->failure(error_t::PARTS_EXCEEDED, this->_start);
		// Выполняем пропуск пробельных знаков строки
		this->spaces();
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выводим признак успешного разбора
				return true;
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если за составной частью имени следует разделитель
		 */
		if(this->_buffer[this->_offset] == '.'){
			// Выполняем пропуск разделителя составных частей имени
			this->step(this->_offset + 1);
			// Переходим к следующей составной части имени
			continue;
		}
		// Выводим признак успешного разбора
		return true;
	}
}
/**
 * @brief Метод разбора числа, логического значения либо отметки времени
 *
 * @param end  признак того, что текст поступил целиком
 * @param item собираемое событие значения
 * @return     признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::scalar(const bool end, item_t & item) noexcept {
	// Положение конца записи значения
	size_t position = this->_offset;
	/**
	 * Выполняем поиск конца записи значения
	 */
	while((position < this->_buffer.length()) && !::terminator(this->_buffer[position]))
		// Выполняем переход к следующему знаку записи значения
		position++;
	/**
	 * Если накопленный текст оборвался на пробеле, отделяющем время от даты
	 *
	 * @note Пробел этот записи значения завершает либо не завершает - смотря по тому,
	 *       цифра ли стоит за ним, - и решать без этого знака нельзя: следующий кусок
	 *       вправе принести цифру, и запись, решённая здесь одной лишь датой, разошлась
	 *       бы с записью, поданной целиком
	 */
	if((position < this->_buffer.length()) && ((position + 1) >= this->_buffer.length()) && !end &&
	   (this->_buffer[position] == ' ') && ((position - this->_offset) == 10) &&
	   (this->_buffer[this->_offset + 4] == '-') && ascii::isDigit(this->_buffer[this->_offset])){
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	/**
	 * Если запись значения похожа на дату, а за нею стоит время
	 *
	 * @note Описание дозволяет отделять время от даты пробелом наравне со знаком «T»:
	 *       пробел этот записи не завершает, и конец её приходится искать дальше
	 */
	if(((position + 1) < this->_buffer.length()) && (this->_buffer[position] == ' ') &&
	   ((position - this->_offset) == 10) && (this->_buffer[this->_offset + 4] == '-') &&
	   ascii::isDigit(this->_buffer[position + 1])){
		// Выполняем переход к записи времени за пробелом
		position++;
		/**
		 * Выполняем поиск конца записи времени
		 */
		while((position < this->_buffer.length()) && !::terminator(this->_buffer[position]))
			// Выполняем переход к следующему знаку записи времени
			position++;
	}
	/**
	 * Если накопленный текст исчерпан записью значения
	 *
	 * @note Запись, дошедшая до конца накопленного текста, оборванной быть не
	 *       перестаёт: следующий кусок вправе продолжить её новыми знаками
	 */
	if((position >= this->_buffer.length()) && !end){
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	// Получаем запись разбираемого значения
	const string_view text = string_view(this->_buffer).substr(this->_offset, (position - this->_offset));
	/**
	 * Если запись значения пуста
	 */
	if(text.empty())
		// Выполняем запоминание ошибки отсутствия значения
		return this->failure(error_t::MISSING_VALUE, this->_offset);
	// Запоминаем место значения в исходном тексте
	item.location = this->locate(this->_offset);
	// Запоминаем вид собранного события
	item.event = event_t::VALUE;
	/**
	 * Если значением является истина
	 */
	if(text.compare("true") == 0){
		// Запоминаем тип значения события
		item.type = type_t::BOOLEAN;
		// Запоминаем логическое значение события
		item.boolean = true;
		// Выполняем перемещение разбора за запись значения
		this->step(position);
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если значением является ложь
	 */
	if(text.compare("false") == 0){
		// Запоминаем тип значения события
		item.type = type_t::BOOLEAN;
		// Запоминаем логическое значение события
		item.boolean = false;
		// Выполняем перемещение разбора за запись значения
		this->step(position);
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если запись значения является отметкой времени
	 *
	 * @note Отметку от числа отличают знак переноса на пятом знаке записи даты и
	 *       двоеточие на третьем знаке записи времени: обе записи начинаются цифрами,
	 *       и различить их можно лишь по разделителю
	 */
	if(((text.length() >= 10) && (text[4] == '-') && ascii::isDigit(text[0])) ||
	   ((text.length() >= 8) && (text[2] == ':') && ascii::isDigit(text[0]))){
		/**
		 * Если разбор отметки времени не удался
		 */
		if(!this->stamped(text, item))
			// Выполняем запоминание ошибки построения отметки времени
			return this->failure(error_t::INVALID_DATETIME, this->_offset);
		// Выполняем перемещение разбора за запись значения
		this->step(position);
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если разбор числа не удался
	 */
	if(!this->numeric(text, item))
		// Выводим признак неудачного разбора
		return false;
	// Выполняем перемещение разбора за запись значения
	this->step(position);
	// Выводим признак успешного разбора
	return true;
}
/**
 * @brief Метод разбора отметки времени из записи значения
 *
 * @param text разбираемая запись значения
 * @param item собираемое событие значения
 * @return     признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::stamped(const string_view text, item_t & item) const noexcept {
	/**
	 * @brief Метод чтения числа заданной длины из записи отметки
	 *
	 * @param source разбираемая запись отметки
	 * @param offset положение чтения в записи
	 * @param count  количество читаемых цифр
	 * @param result прочитанное число
	 * @return       признак успешного чтения
	 *
	 */
	auto read = [](const string_view source, const size_t offset, const size_t count, uint32_t & result) noexcept -> bool {
		/**
		 * Если цифр в записи отметки не хватает
		 */
		if((offset + count) > source.length())
			// Выводим признак неудачного чтения
			return false;
		// Выполняем сброс прочитанного числа
		result = 0;
		/**
		 * Выполняем перебор цифр записи отметки
		 */
		for(size_t i = 0; i < count; i++){
			/**
			 * Если знак записи цифрой не является
			 */
			if(!ascii::isDigit(source[offset + i]))
				// Выводим признак неудачного чтения
				return false;
			// Выполняем накопление прочитанного числа
			result = ((result * 10) + static_cast <uint32_t> (source[offset + i] - '0'));
		}
		// Выводим признак успешного чтения
		return true;
	};
	// Собираемая отметка времени
	stamp_t stamp;
	// Положение чтения записи отметки
	size_t offset = 0;
	// Признак наличия даты в записи отметки
	bool dated = false;
	// Прочитанное из записи отметки число
	uint32_t value = 0;
	/**
	 * Если запись отметки начинается с даты
	 */
	if((text.length() >= 10) && (text[4] == '-')){
		/**
		 * Если чтение года выполнить не удалось
		 */
		if(!read(text, 0, 4, value))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем год отметки времени
		stamp.date.year = static_cast <uint16_t> (value);
		/**
		 * Если чтение месяца выполнить не удалось
		 */
		if((text[7] != '-') || !read(text, 5, 2, value) || (value < 1) || (value > 12))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем месяц отметки времени
		stamp.date.month = static_cast <uint8_t> (value);
		/**
		 * Если чтение дня месяца выполнить не удалось
		 */
		if(!read(text, 8, 2, value) || (value < 1) || (value > 31))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем день месяца отметки времени
		stamp.date.day = static_cast <uint8_t> (value);
		/**
		 * Количество дней в месяцах года
		 *
		 * @note Проверка эта не украшение: «2026-02-31» записью даты не является, и
		 *       принимать её значило бы выдавать потребителю день, которого нет
		 */
		static const uint8_t DAYS[12] = {31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31};
		/**
		 * Если день месяца за пределы месяца выходит
		 */
		if(stamp.date.day > DAYS[stamp.date.month - 1])
			// Выводим признак неудачного разбора
			return false;
		/**
		 * Если днём является двадцать девятое февраля года невисокосного
		 */
		if((stamp.date.month == 2) && (stamp.date.day == 29) &&
		   (((stamp.date.year % 4) != 0) || (((stamp.date.year % 100) == 0) && ((stamp.date.year % 400) != 0))))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем признак наличия даты в записи отметки
		dated = true;
		// Выполняем переход за запись даты
		offset = 10;
		/**
		 * Если запись отметки датой исчерпана
		 */
		if(offset >= text.length()){
			// Запоминаем тип значения события
			item.type = type_t::LOCAL_DATE;
			// Запоминаем собранную отметку времени
			item.stamp = stamp;
			// Выводим признак успешного разбора
			return true;
		}
		/**
		 * Если разделителем даты и времени является пробел
		 */
		if(text[offset] == ' ')
			// Запоминаем признак разделения даты и времени пробелом
			stamp.spaced = true;
		/**
		 * Если разделителем даты и времени знак «T» не является
		 */
		else if((text[offset] != 'T') && (text[offset] != 't'))
			// Выводим признак неудачного разбора
			return false;
		// Выполняем переход за разделитель даты и времени
		offset++;
	}
	/**
	 * Если чтение часа выполнить не удалось
	 */
	if(!read(text, offset, 2, value) || (value > 23))
		// Выводим признак неудачного разбора
		return false;
	// Запоминаем час отметки времени
	stamp.time.hour = static_cast <uint8_t> (value);
	/**
	 * Если чтение минуты выполнить не удалось
	 */
	if(((offset + 2) >= text.length()) || (text[offset + 2] != ':') || !read(text, offset + 3, 2, value) || (value > 59))
		// Выводим признак неудачного разбора
		return false;
	// Запоминаем минуту отметки времени
	stamp.time.minute = static_cast <uint8_t> (value);
	/**
	 * Если чтение секунды выполнить не удалось
	 *
	 * @note Значение в шестьдесят принимается намеренно: описание дозволяет им
	 *       записывать добавочную секунду координации
	 */
	if(((offset + 5) >= text.length()) || (text[offset + 5] != ':') || !read(text, offset + 6, 2, value) || (value > 60))
		// Выводим признак неудачного разбора
		return false;
	// Запоминаем секунду отметки времени
	stamp.time.second = static_cast <uint8_t> (value);
	// Выполняем переход за запись времени
	offset += 8;
	/**
	 * Если за записью времени следует доля секунды
	 */
	if((offset < text.length()) && (text[offset] == '.')){
		// Выполняем переход за разделитель доли секунды
		offset++;
		// Количество прочитанных разрядов доли секунды
		uint32_t digits = 0;
		// Накопленное значение доли секунды в наносекундах
		uint32_t fraction = 0;
		/**
		 * Выполняем перебор разрядов доли секунды
		 */
		while((offset < text.length()) && ascii::isDigit(text[offset])){
			/**
			 * Если разряд в хранилище доли секунды вмещается
			 *
			 * @note Разряды сверх девяти отбрасываются: описание дозволяет обращение
			 *       это прямо, а хранение доли ведётся наносекундами
			 */
			if(digits < MAX_FRACTION)
				// Выполняем накопление значения доли секунды
				fraction = ((fraction * 10) + static_cast <uint32_t> (text[offset] - '0'));
			// Выполняем увеличение количества прочитанных разрядов
			digits++;
			// Выполняем переход к следующему разряду доли секунды
			offset++;
		}
		/**
		 * Если разрядов доли секунды за разделителем не оказалось
		 */
		if(digits == 0)
			// Выводим признак неудачного разбора
			return false;
		/**
		 * Выполняем дополнение доли секунды до наносекунд
		 */
		for(uint32_t i = ((digits < MAX_FRACTION) ? digits : MAX_FRACTION); i < MAX_FRACTION; i++)
			// Выполняем сдвиг значения доли секунды на разряд
			fraction *= 10;
		// Запоминаем долю секунды отметки времени
		stamp.time.nanosecond = fraction;
		// Запоминаем количество записанных разрядов доли секунды
		stamp.time.digits = static_cast <uint8_t> ((digits < MAX_FRACTION) ? digits : MAX_FRACTION);
	}
	/**
	 * Если запись отметки исчерпана
	 */
	if(offset >= text.length()){
		// Запоминаем тип значения события
		item.type = (dated ? type_t::LOCAL_DATETIME : type_t::LOCAL_TIME);
		// Запоминаем собранную отметку времени
		item.stamp = stamp;
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если смещение часового пояса записано у местного времени
	 *
	 * @note Смещение отводится лишь отметке с датой: у местного времени часового
	 *       пояса нет по существу
	 */
	if(!dated)
		// Выводим признак неудачного разбора
		return false;
	/**
	 * Если часовым поясом отметки является UTC
	 */
	if((text[offset] == 'Z') || (text[offset] == 'z')){
		/**
		 * Если за обозначением часового пояса запись не исчерпана
		 */
		if((offset + 1) != text.length())
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем признак записи часового пояса UTC знаком «Z»
		stamp.zulu = true;
		// Запоминаем смещение часового пояса отметки
		stamp.offset = 0;
		// Запоминаем тип значения события
		item.type = type_t::OFFSET_DATETIME;
		// Запоминаем собранную отметку времени
		item.stamp = stamp;
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если знаком смещения часового пояса ни плюс, ни минус не являются
	 */
	if((text[offset] != '+') && (text[offset] != '-'))
		// Выводим признак неудачного разбора
		return false;
	// Получаем признак отрицательного смещения часового пояса
	const bool negative = (text[offset] == '-');
	// Выполняем переход за знак смещения часового пояса
	offset++;
	/**
	 * Если чтение часов смещения выполнить не удалось
	 */
	if(!read(text, offset, 2, value) || (value > 23))
		// Выводим признак неудачного разбора
		return false;
	// Собираемое смещение часового пояса в минутах
	int32_t shift = static_cast <int32_t> (value * 60);
	/**
	 * Если чтение минут смещения выполнить не удалось
	 */
	if(((offset + 2) >= text.length()) || (text[offset + 2] != ':') || !read(text, offset + 3, 2, value) || (value > 59))
		// Выводим признак неудачного разбора
		return false;
	// Выполняем дополнение смещения часового пояса минутами
	shift += static_cast <int32_t> (value);
	/**
	 * Если за смещением часового пояса запись не исчерпана
	 */
	if((offset + 5) != text.length())
		// Выводим признак неудачного разбора
		return false;
	// Запоминаем смещение часового пояса отметки
	stamp.offset = (negative ? -shift : shift);
	// Запоминаем тип значения события
	item.type = type_t::OFFSET_DATETIME;
	// Запоминаем собранную отметку времени
	item.stamp = stamp;
	// Выводим признак успешного разбора
	return true;
}
/**
 * @brief Метод разбора числа из записи значения
 *
 * @param text разбираемая запись значения
 * @param item собираемое событие значения
 * @return     признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::numeric(const string_view text, item_t & item) noexcept {
	// Разбираемая запись числа без знака
	string_view value = text;
	// Признак отрицательного числа
	bool negative = false;
	// Признак записи числа со знаком
	bool signed_ = false;
	/**
	 * Если запись числа начинается со знака
	 */
	if((value[0] == '+') || (value[0] == '-')){
		// Запоминаем признак отрицательного числа
		negative = (value[0] == '-');
		// Запоминаем признак записи числа со знаком
		signed_ = true;
		// Выполняем отбрасывание знака числа
		value = value.substr(1);
	}
	/**
	 * Если запись числа исчерпана знаком
	 */
	if(value.empty())
		// Выполняем запоминание ошибки построения записи числа
		return this->failure(error_t::INVALID_NUMBER, this->_offset);
	/**
	 * Если значением является бесконечность
	 */
	if(value.compare("inf") == 0){
		// Запоминаем тип значения события
		item.type = type_t::FLOAT;
		// Запоминаем значение события с плавающей точкой
		item.real = (negative ? -numeric_limits <double>::infinity() : numeric_limits <double>::infinity());
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если значением является нечисло
	 */
	if(value.compare("nan") == 0){
		// Запоминаем тип значения события
		item.type = type_t::FLOAT;
		// Запоминаем значение события с плавающей точкой
		item.real = (negative ? -numeric_limits <double>::quiet_NaN() : numeric_limits <double>::quiet_NaN());
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если запись числа ведётся в системе счисления с приставкой
	 */
	if((value.length() > 2) && (value[0] == '0') && ((value[1] == 'x') || (value[1] == 'o') || (value[1] == 'b'))){
		/**
		 * Если запись числа с приставкой несёт знак
		 *
		 * @note Описание отводит знак лишь десятичной записи: «-0x1» им не отведено
		 */
		if(signed_)
			// Выполняем запоминание ошибки построения записи числа
			return this->failure(error_t::INVALID_NUMBER, this->_offset);
		// Получаем основание системы счисления записи
		const uint32_t radix = ((value[1] == 'x') ? 16 : ((value[1] == 'o') ? 8 : 2));
		// Запоминаем систему счисления записи целого числа
		item.radix = ((value[1] == 'x') ? radix_t::HEX : ((value[1] == 'o') ? radix_t::OCTAL : radix_t::BINARY));
		// Запись числа без разделителей разрядов
		string digits;
		/**
		 * Если построение записи числа ошибочно
		 */
		if(!::separated(value.substr(2), radix, digits))
			// Выполняем запоминание ошибки построения записи числа
			return this->failure(error_t::INVALID_NUMBER, this->_offset);
		/**
		 * Если разбор целого числа не удался
		 */
		if(!::digits(digits, radix, false, item.integer)){
			/**
			 * Если запись числа построена верно
			 *
			 * @note Отличать негодное построение от выхода за отрезок значений
			 *       обязательно: первое означает ошибку в файле, второе - число,
			 *       которое хранилищу не по мерке
			 */
			for(size_t i = 0; i < digits.length(); i++){
				// Получаем значение очередной цифры записи
				const int32_t digit = ascii::hexValue(digits[i]);
				/**
				 * Если знак цифрой системы счисления не является
				 */
				if((digit < 0) || (static_cast <uint32_t> (digit) >= radix))
					// Выполняем запоминание ошибки построения записи числа
					return this->failure(error_t::INVALID_NUMBER, this->_offset);
			}
			// Выполняем запоминание ошибки выхода числа за отрезок значений
			return this->failure(error_t::NUMBER_OVERFLOW, this->_offset);
		}
		// Запоминаем тип значения события
		item.type = type_t::INTEGER;
		// Выводим признак успешного разбора
		return true;
	}
	// Запись числа без разделителей разрядов
	string digits;
	/**
	 * Если построение записи числа ошибочно
	 */
	if(!::separated(value, 10, digits))
		// Выполняем запоминание ошибки построения записи числа
		return this->failure(error_t::INVALID_NUMBER, this->_offset);
	// Признак записи числа с плавающей точкой
	bool real = false;
	// Положение разбираемого знака записи числа
	size_t position = 0;
	/**
	 * Выполняем перебор цифр целой части записи числа
	 *
	 * @note Построение записи проверяется правилом описания, а не набором знаков её:
	 *       запись «1.e2» несёт одни лишь дозволенные знаки, а числом по описанию не
	 *       является - десятичная точка обязана нести цифру и слева, и справа
	 */
	while((position < digits.length()) && ascii::isDigit(digits[position]))
		// Выполняем переход к следующему знаку записи числа
		position++;
	/**
	 * Если целая часть записи числа пуста
	 */
	if(position == 0)
		// Выполняем запоминание ошибки построения записи числа
		return this->failure(error_t::INVALID_NUMBER, this->_offset);
	/**
	 * Если за целой частью записи числа следует десятичная точка
	 */
	if((position < digits.length()) && (digits[position] == '.')){
		// Запоминаем признак записи числа с плавающей точкой
		real = true;
		// Выполняем пропуск десятичной точки записи числа
		position++;
		// Положение начала дробной части записи числа
		const size_t start = position;
		/**
		 * Выполняем перебор цифр дробной части записи числа
		 */
		while((position < digits.length()) && ascii::isDigit(digits[position]))
			// Выполняем переход к следующему знаку записи числа
			position++;
		/**
		 * Если дробная часть записи числа пуста
		 */
		if(position == start)
			// Выполняем запоминание ошибки построения записи числа
			return this->failure(error_t::INVALID_NUMBER, this->_offset);
	}
	/**
	 * Если за записью числа следует знак порядка
	 */
	if((position < digits.length()) && ((digits[position] == 'e') || (digits[position] == 'E'))){
		// Запоминаем признак записи числа с плавающей точкой
		real = true;
		// Выполняем пропуск знака порядка записи числа
		position++;
		/**
		 * Если порядок записи числа несёт знак
		 */
		if((position < digits.length()) && ((digits[position] == '+') || (digits[position] == '-')))
			// Выполняем пропуск знака порядка записи числа
			position++;
		// Положение начала порядка записи числа
		const size_t start = position;
		/**
		 * Выполняем перебор цифр порядка записи числа
		 */
		while((position < digits.length()) && ascii::isDigit(digits[position]))
			// Выполняем переход к следующему знаку записи числа
			position++;
		/**
		 * Если порядок записи числа пуст
		 */
		if(position == start)
			// Выполняем запоминание ошибки построения записи числа
			return this->failure(error_t::INVALID_NUMBER, this->_offset);
	}
	/**
	 * Если запись числа разобрана не до конца
	 */
	if(position < digits.length())
		// Выполняем запоминание ошибки построения записи числа
		return this->failure(error_t::INVALID_NUMBER, this->_offset);
	/**
	 * Если запись числа несёт незначащий ноль в начале
	 *
	 * @note Описание запрещает его прямо: «011» записью числа не является, и принимать
	 *       её значило бы разбирать то восьмеричным числом, то десятичным - смотря по
	 *       разбирающему
	 */
	if((digits.length() > 1) && (digits[0] == '0') && ascii::isDigit(digits[1]))
		// Выполняем запоминание ошибки построения записи числа
		return this->failure(error_t::INVALID_NUMBER, this->_offset);
	/**
	 * Если число записано с плавающей точкой
	 */
	if(real){
		// Собираемое значение числа с плавающей точкой
		double number = 0.0;
		// Выполняем разбор числа с плавающей точкой
		const lexical_t::result_t <char> res = lexical_t::fromChars(digits.data(), (digits.data() + digits.length()), number);
		/**
		 * Если разбор числа выполнить не удалось
		 */
		if(!static_cast <bool> (res) || (res.ptr != (digits.data() + digits.length())))
			// Выполняем запоминание ошибки построения записи числа
			return this->failure(error_t::INVALID_NUMBER, this->_offset);
		// Запоминаем тип значения события
		item.type = type_t::FLOAT;
		// Запоминаем значение события с плавающей точкой
		item.real = (negative ? -number : number);
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если разбор целого числа не удался
	 */
	if(!::digits(digits, 10, negative, item.integer)){
		/**
		 * Выполняем перебор знаков записи числа
		 */
		for(size_t i = 0; i < digits.length(); i++){
			/**
			 * Если знак цифрой не является
			 */
			if(!ascii::isDigit(digits[i]))
				// Выполняем запоминание ошибки построения записи числа
				return this->failure(error_t::INVALID_NUMBER, this->_offset);
		}
		// Выполняем запоминание ошибки выхода числа за отрезок значений
		return this->failure(error_t::NUMBER_OVERFLOW, this->_offset);
	}
	// Запоминаем тип значения события
	item.type = type_t::INTEGER;
	// Выводим признак успешного разбора
	return true;
}
/**
 * @brief Метод разбора значения
 *
 * @param end    признак того, что текст поступил целиком
 * @param depth  текущая глубина вложенности значения
 * @param prefix полное имя пары значения, пустой указатель - имени нет
 * @return       признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::content(const bool end, const uint32_t depth, const string * prefix) noexcept {
	// Выполняем пропуск пробельных знаков строки
	this->spaces();
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выполняем запоминание ошибки отсутствия значения
			return this->failure(error_t::MISSING_VALUE, this->_offset);
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	// Получаем знак начала значения
	const char letter = this->_buffer[this->_offset];
	/**
	 * Если значением является перечень
	 */
	if(letter == '[')
		// Выполняем разбор перечня значений
		return this->array(end, depth);
	/**
	 * Если значением является встроенная таблица
	 */
	if(letter == '{'){
		// Номер имени встроенной таблицы среди имён разбираемой записи
		size_t declared = this->_pending.size();
		/**
		 * Если собственное имя у встроенной таблицы есть
		 */
		if((prefix != nullptr) && this->_settings.duplicates){
			// Выполняем поиск имени встроенной таблицы среди объявляемых записью
			const size_t position = this->staged(* prefix);
			/**
			 * Если имя встроенной таблицы объявлено разбираемой записью
			 */
			if((position < this->_pending.size()) && !this->_pending.at(position).implied){
				// Запоминаем номер имени встроенной таблицы
				declared = position;
				/**
				 * Запоминаем род имени открытой встроенной таблицы
				 *
				 * @note Пока таблица не закрыта, ключи её объявляются законно, и род
				 *       закрытой таблицы отвергал бы их дополнением: род этот ставится
				 *       лишь по закрытии скобки
				 */
				this->_pending.at(declared).kind = kind_t::DOTTED;
			}
		}
		/**
		 * Если разбор встроенной таблицы не удался
		 */
		if(!this->inlined(end, depth, prefix))
			// Выводим признак неудачного разбора
			return false;
		/**
		 * Если имя разобранной встроенной таблицы объявлено
		 */
		if(declared < this->_pending.size())
			// Запоминаем род имени закрытой встроенной таблицы
			this->_pending.at(declared).kind = kind_t::INLINE;
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если значение оборвано концом строки
	 */
	if((letter == '\n') || (letter == '\r'))
		// Выполняем запоминание ошибки отсутствия значения
		return this->failure(error_t::MISSING_VALUE, this->_offset);
	// Собираемое событие значения
	item_t item;
	/**
	 * Если значение является строковым
	 */
	if((letter == '"') || (letter == '\'')){
		// Запоминаем место значения в исходном тексте
		item.location = this->locate(this->_offset);
		/**
		 * Если разбор строкового значения не удался
		 */
		if(!this->literal(end, item.quoting, item.content))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем вид собранного события
		item.event = event_t::VALUE;
		// Запоминаем тип значения события
		item.type = type_t::STRING;
		// Выполняем добавление собранного события в очередь выдачи
		this->_items.push_back(item);
		// Выводим признак успешного разбора
		return true;
	}
	/**
	 * Если разбор числа, логического значения либо отметки времени не удался
	 */
	if(!this->scalar(end, item))
		// Выводим признак неудачного разбора
		return false;
	// Выполняем добавление собранного события в очередь выдачи
	this->_items.push_back(item);
	// Выводим признак успешного разбора
	return true;
}
/**
 * @brief Метод разбора перечня значений
 *
 * @param end   признак того, что текст поступил целиком
 * @param depth текущая глубина вложенности значения
 * @return      признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::array(const bool end, const uint32_t depth) noexcept {
	/**
	 * Если глубина вложенности значений предел настроек превышает
	 *
	 * @note Предел этот не украшение: разбор вложенности ведётся стопой вызовов, и
	 *       текст из одних открывающих скобок исчерпывает её без предела
	 */
	if(depth >= this->_settings.maxDepth)
		// Выполняем запоминание ошибки превышения глубины вложенности
		return this->failure(error_t::DEPTH_EXCEEDED, this->_offset);
	// Собираемое событие открытия перечня значений
	item_t item;
	// Запоминаем вид собранного события
	item.event = event_t::ARRAY_OPEN;
	// Запоминаем тип значения события
	item.type = type_t::ARRAY;
	// Запоминаем место открытия перечня в исходном тексте
	item.location = this->locate(this->_offset);
	// Запоминаем положение открытия перечня в накопленном тексте
	const size_t opening = this->_offset;
	// Выполняем добавление собранного события в очередь выдачи
	this->_items.push_back(item);
	// Выполняем пропуск знака открытия перечня
	this->step(this->_offset + 1);
	// Признак того, что перечень ожидает очередного значения
	bool expected = true;
	/**
	 * Выполняем разбор содержимого перечня значений
	 */
	while(true){
		/**
		 * Выполняем пропуск пробельных знаков, переносов строк и примечаний
		 *
		 * @note Перечень описание дозволяет записывать в несколько строк вместе с
		 *       примечаниями внутри: пропускать надлежит и то, и другое
		 */
		while(true){
			/**
			 * Если накопленный текст исчерпан
			 */
			if(this->_offset >= this->_buffer.length()){
				/**
				 * Если текст поступил целиком
				 */
				if(end)
					// Выполняем запоминание ошибки незакрытого перечня
					return this->failure(error_t::UNCLOSED_ARRAY, opening);
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			// Получаем очередной знак содержимого перечня
			const char letter = this->_buffer[this->_offset];
			/**
			 * Если знаком является возврат каретки
			 */
			if(letter == '\r'){
				/**
				 * Если за возвратом каретки перевода строки не накоплено
				 */
				if((this->_offset + 1) >= this->_buffer.length()){
					/**
					 * Если текст поступил целиком
					 *
					 * @note Возврат каретки сам по себе концом строки не является:
					 *       описание отводит концом строки перевод строки и пару из
					 *       возврата с переводом
					 */
					if(end)
						// Выполняем запоминание ошибки недопустимого знака
						return this->failure(error_t::INVALID_CHARACTER, this->_offset);
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Если за возвратом каретки перевод строки не следует
				 */
				if(this->_buffer[this->_offset + 1] != '\n')
					// Выполняем запоминание ошибки недопустимого знака
					return this->failure(error_t::INVALID_CHARACTER, this->_offset);
			}
			/**
			 * Если знаком является пробельный знак либо знак конца строки
			 */
			if(::blank(letter) || (letter == '\n') || (letter == '\r')){
				// Выполняем пропуск знака содержимого перечня
				this->step(this->_offset + 1);
				// Переходим к следующему знаку содержимого перечня
				continue;
			}
			/**
			 * Если знаком начинается примечание
			 */
			if(letter == '#'){
				// Положение конца содержимого примечания
				const size_t position = this->_buffer.find('\n', this->_offset);
				/**
				 * Если знак конца строки в накопленном тексте отсутствует
				 */
				if(position == string::npos){
					/**
					 * Если текст поступил целиком
					 */
					if(end)
						// Выполняем запоминание ошибки незакрытого перечня
						return this->failure(error_t::UNCLOSED_ARRAY, opening);
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Признак примечания, дописанного к готовой строке
				 *
				 * @note Примечание внутри перечня стоит либо своей строкой, либо за
				 *       значением на строке его: обратная запись расстановку эту хранит,
				 *       и различаются они по тому, есть ли перед знаком начала примечания
				 *       непробельное содержимое
				 */
				bool trailing = false;
				/**
				 * Выполняем перебор знаков строки перед началом примечания
				 */
				for(size_t i = this->_offset; i > this->_start; i--){
					/**
					 * Если знаком является конец строки
					 */
					if(this->_buffer[i - 1] == '\n')
						// Выходим из перебора знаков строки
						break;
					/**
					 * Если знак строки пробельным не является
					 */
					else if(!::blank(this->_buffer[i - 1]) && (this->_buffer[i - 1] != '\r')){
						// Запоминаем признак примечания, дописанного к готовой строке
						trailing = true;
						// Выходим из перебора знаков строки
						break;
					}
				}
				/**
				 * Если разобрать примечание не удалось
				 */
				if(!this->commented(position, trailing))
					// Выводим признак неудачного разбора
					return false;
				// Переходим к следующему знаку содержимого перечня
				continue;
			}
			// Выходим из цикла пропуска пробельных знаков
			break;
		}
		/**
		 * Если перечень закрывается
		 */
		if(this->_buffer[this->_offset] == ']'){
			// Собираемое событие закрытия перечня значений
			item_t closing;
			// Запоминаем вид собранного события
			closing.event = event_t::ARRAY_CLOSE;
			// Запоминаем тип значения события
			closing.type = type_t::ARRAY;
			// Запоминаем место закрытия перечня в исходном тексте
			closing.location = this->locate(this->_offset);
			// Выполняем добавление собранного события в очередь выдачи
			this->_items.push_back(closing);
			// Выполняем пропуск знака закрытия перечня
			this->step(this->_offset + 1);
			// Выводим признак успешного разбора
			return true;
		}
		/**
		 * Если очередного значения перечень не ожидает
		 *
		 * @note Значение, не отделённое запятой от предыдущего, описанием не отведено
		 */
		if(!expected)
			// Выполняем запоминание ошибки построения значения
			return this->failure(error_t::INVALID_VALUE, this->_offset);
		/**
		 * Если разбор очередного значения перечня не удался
		 */
		if(!this->content(end, (depth + 1), nullptr))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем, что очередного значения перечень не ожидает
		expected = false;
		/**
		 * Выполняем пропуск пробельных знаков, переносов строк и примечаний за значением
		 */
		while(true){
			/**
			 * Если накопленный текст исчерпан
			 */
			if(this->_offset >= this->_buffer.length()){
				/**
				 * Если текст поступил целиком
				 */
				if(end)
					// Выполняем запоминание ошибки незакрытого перечня
					return this->failure(error_t::UNCLOSED_ARRAY, opening);
				// Запоминаем нужду в продолжении текста
				this->_hungry = true;
				// Выводим признак неудачного разбора
				return false;
			}
			// Получаем очередной знак содержимого перечня
			const char letter = this->_buffer[this->_offset];
			/**
			 * Если знаком является возврат каретки
			 */
			if(letter == '\r'){
				/**
				 * Если за возвратом каретки перевода строки не накоплено
				 */
				if((this->_offset + 1) >= this->_buffer.length()){
					/**
					 * Если текст поступил целиком
					 *
					 * @note Возврат каретки сам по себе концом строки не является:
					 *       описание отводит концом строки перевод строки и пару из
					 *       возврата с переводом
					 */
					if(end)
						// Выполняем запоминание ошибки недопустимого знака
						return this->failure(error_t::INVALID_CHARACTER, this->_offset);
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Если за возвратом каретки перевод строки не следует
				 */
				if(this->_buffer[this->_offset + 1] != '\n')
					// Выполняем запоминание ошибки недопустимого знака
					return this->failure(error_t::INVALID_CHARACTER, this->_offset);
			}
			/**
			 * Если знаком является пробельный знак либо знак конца строки
			 */
			if(::blank(letter) || (letter == '\n') || (letter == '\r')){
				// Выполняем пропуск знака содержимого перечня
				this->step(this->_offset + 1);
				// Переходим к следующему знаку содержимого перечня
				continue;
			}
			/**
			 * Если знаком начинается примечание
			 */
			if(letter == '#'){
				// Положение конца содержимого примечания
				const size_t position = this->_buffer.find('\n', this->_offset);
				/**
				 * Если знак конца строки в накопленном тексте отсутствует
				 */
				if(position == string::npos){
					/**
					 * Если текст поступил целиком
					 */
					if(end)
						// Выполняем запоминание ошибки незакрытого перечня
						return this->failure(error_t::UNCLOSED_ARRAY, opening);
					// Запоминаем нужду в продолжении текста
					this->_hungry = true;
					// Выводим признак неудачного разбора
					return false;
				}
				/**
				 * Признак примечания, дописанного к готовой строке
				 *
				 * @note Примечание внутри перечня стоит либо своей строкой, либо за
				 *       значением на строке его: обратная запись расстановку эту хранит,
				 *       и различаются они по тому, есть ли перед знаком начала примечания
				 *       непробельное содержимое
				 */
				bool trailing = false;
				/**
				 * Выполняем перебор знаков строки перед началом примечания
				 */
				for(size_t i = this->_offset; i > this->_start; i--){
					/**
					 * Если знаком является конец строки
					 */
					if(this->_buffer[i - 1] == '\n')
						// Выходим из перебора знаков строки
						break;
					/**
					 * Если знак строки пробельным не является
					 */
					else if(!::blank(this->_buffer[i - 1]) && (this->_buffer[i - 1] != '\r')){
						// Запоминаем признак примечания, дописанного к готовой строке
						trailing = true;
						// Выходим из перебора знаков строки
						break;
					}
				}
				/**
				 * Если разобрать примечание не удалось
				 */
				if(!this->commented(position, trailing))
					// Выводим признак неудачного разбора
					return false;
				// Переходим к следующему знаку содержимого перечня
				continue;
			}
			// Выходим из цикла пропуска пробельных знаков
			break;
		}
		/**
		 * Если за значением следует запятая
		 */
		if(this->_buffer[this->_offset] == ','){
			// Запоминаем, что перечень ожидает очередного значения
			expected = true;
			// Выполняем пропуск запятой
			this->step(this->_offset + 1);
		}
	}
}
/**
 * @brief Метод разбора встроенной таблицы
 *
 * @param end    признак того, что текст поступил целиком
 * @param depth  текущая глубина вложенности значения
 * @param prefix полное имя встроенной таблицы, пустой указатель - имени нет
 * @return       признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::inlined(const bool end, const uint32_t depth, const string * prefix) noexcept {
	/**
	 * Если глубина вложенности значений предел настроек превышает
	 */
	if(depth >= this->_settings.maxDepth)
		// Выполняем запоминание ошибки превышения глубины вложенности
		return this->failure(error_t::DEPTH_EXCEEDED, this->_offset);
	// Собираемое событие открытия встроенной таблицы
	item_t item;
	// Запоминаем вид собранного события
	item.event = event_t::INLINE_OPEN;
	// Запоминаем тип значения события
	item.type = type_t::TABLE;
	// Запоминаем место открытия встроенной таблицы в исходном тексте
	item.location = this->locate(this->_offset);
	// Запоминаем положение открытия встроенной таблицы в накопленном тексте
	const size_t opening = this->_offset;
	// Выполняем добавление собранного события в очередь выдачи
	this->_items.push_back(item);
	// Выполняем пропуск знака открытия встроенной таблицы
	this->step(this->_offset + 1);
	// Признак того, что встроенная таблица ожидает очередной пары
	bool expected = false;
	/**
	 * Признак того, что очередная пара будет первой
	 *
	 * @note Пары встроенной таблицы описание требует отделять запятой: без этого
	 *       признака запись «{a = 1 b = 2}» принималась бы наравне с правильной
	 */
	bool first = true;
	/**
	 * Выполняем разбор содержимого встроенной таблицы
	 */
	while(true){
		// Выполняем пропуск пробельных знаков строки
		this->spaces();
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки незакрытой встроенной таблицы
				return this->failure(error_t::UNCLOSED_INLINE_TABLE, opening);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если встроенная таблица закрывается
		 */
		if(this->_buffer[this->_offset] == '}'){
			/**
			 * Если таблица ожидает очередной пары
			 *
			 * @note Запятая в конце встроенной таблицы описанием запрещена: «{a = 1,}»
			 *       записью встроенной таблицы не является
			 */
			if(expected)
				// Выполняем запоминание ошибки построения значения
				return this->failure(error_t::INVALID_VALUE, this->_offset);
			// Собираемое событие закрытия встроенной таблицы
			item_t closing;
			// Запоминаем вид собранного события
			closing.event = event_t::INLINE_CLOSE;
			// Запоминаем тип значения события
			closing.type = type_t::TABLE;
			// Запоминаем место закрытия встроенной таблицы в исходном тексте
			closing.location = this->locate(this->_offset);
			// Выполняем добавление собранного события в очередь выдачи
			this->_items.push_back(closing);
			// Выполняем пропуск знака закрытия встроенной таблицы
			this->step(this->_offset + 1);
			// Выводим признак успешного разбора
			return true;
		}
		/**
		 * Если строка встроенной таблицы оборвана концом строки
		 *
		 * @note Описание отводит встроенной таблице одну строку целиком: перенос
		 *       внутри неё им не дозволен
		 */
		if((this->_buffer[this->_offset] == '\n') || (this->_buffer[this->_offset] == '\r'))
			// Выполняем запоминание ошибки незакрытой встроенной таблицы
			return this->failure(error_t::UNCLOSED_INLINE_TABLE, opening);
		/**
		 * Если очередная пара от предыдущей запятой не отделена
		 */
		if(!first && !expected)
			// Выполняем запоминание ошибки построения значения
			return this->failure(error_t::INVALID_VALUE, this->_offset);
		// Запоминаем, что очередная пара первой не является
		first = false;
		// Собираемое событие имени ключа встроенной таблицы
		item_t key;
		// Запоминаем вид собранного события
		key.event = event_t::KEY;
		// Запоминаем место имени ключа в исходном тексте
		key.location = this->locate(this->_offset);
		// Запоминаем номер первой составной части имени ключа
		key.part = static_cast <uint32_t> (this->_segments.size());
		/**
		 * Если разбор имени ключа не удался
		 */
		if(!this->name(end, key.parts))
			// Выводим признак неудачного разбора
			return false;
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки отсутствия знака равенства
				return this->failure(error_t::MISSING_EQUALS, this->_offset);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если за именем ключа знак равенства не следует
		 */
		if(this->_buffer[this->_offset] != '=')
			// Выполняем запоминание ошибки отсутствия знака равенства
			return this->failure(error_t::MISSING_EQUALS, this->_offset);
		/**
		 * Собираемое полное имя ключа встроенной таблицы
		 *
		 * @note Имя собирается лишь тогда, когда собственное имя есть и у самой
		 *       встроенной таблицы: таблица, записанная значением перечня, имени не
		 *       имеет вовсе, и ключи её повторами друг другу не приходятся
		 */
		string name;
		/**
		 * Если собственное имя у встроенной таблицы есть
		 */
		if(prefix != nullptr){
			// Запоминаем имя встроенной таблицы началом имени ключа
			name.assign(* prefix);
			// Выполняем сборку полного имени ключа из составных частей
			this->assemble(key.part, key.parts, name);
			/**
			 * Если имя ключа уже объявлено
			 */
			if(!this->declare(name, kind_t::VALUE, error_t::DUPLICATE_KEY, this->_offset))
				// Выводим признак неудачного разбора
				return false;
		}
		// Выполняем добавление собранного события в очередь выдачи
		this->_items.push_back(key);
		// Выполняем пропуск знака равенства
		this->step(this->_offset + 1);
		/**
		 * Если разбор значения пары не удался
		 */
		if(!this->content(end, (depth + 1), ((prefix != nullptr) ? &name : nullptr)))
			// Выводим признак неудачного разбора
			return false;
		// Выполняем пропуск пробельных знаков строки
		this->spaces();
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки незакрытой встроенной таблицы
				return this->failure(error_t::UNCLOSED_INLINE_TABLE, opening);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если за парой следует запятая
		 */
		if(this->_buffer[this->_offset] == ','){
			// Запоминаем, что встроенная таблица ожидает очередной пары
			expected = true;
			// Выполняем пропуск запятой
			this->step(this->_offset + 1);
			// Переходим к следующей паре встроенной таблицы
			continue;
		}
		// Запоминаем, что очередной пары встроенная таблица не ожидает
		expected = false;
	}
}
/**
 * @brief Метод разбора объявления таблицы
 *
 * @param end признак того, что текст поступил целиком
 * @return    признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::table(const bool end) noexcept {
	// Собираемое событие объявления таблицы
	item_t item;
	// Запоминаем место объявления таблицы в исходном тексте
	item.location = this->locate(this->_offset);
	// Запоминаем положение открытия объявления в накопленном тексте
	const size_t opening = this->_offset;
	// Выполняем пропуск знака открытия объявления таблицы
	this->step(this->_offset + 1);
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выполняем запоминание ошибки незакрытого объявления таблицы
			return this->failure(error_t::UNCLOSED_TABLE, opening);
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	// Получаем признак объявления очередной таблицы набора таблиц
	const bool appended = (this->_buffer[this->_offset] == '[');
	/**
	 * Если объявляется очередная таблица набора таблиц
	 */
	if(appended)
		// Выполняем пропуск второго знака открытия объявления
		this->step(this->_offset + 1);
	// Запоминаем вид собранного события
	item.event = (appended ? event_t::ARRAY_TABLE : event_t::TABLE);
	// Запоминаем тип значения события
	item.type = type_t::TABLE;
	// Запоминаем номер первой составной части имени таблицы
	item.part = static_cast <uint32_t> (this->_segments.size());
	/**
	 * Если разбор имени таблицы не удался
	 */
	if(!this->name(end, item.parts))
		// Выводим признак неудачного разбора
		return false;
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выполняем запоминание ошибки незакрытого объявления таблицы
			return this->failure(error_t::UNCLOSED_TABLE, opening);
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	/**
	 * Если объявление таблицы квадратной скобкой не закрыто
	 */
	if(this->_buffer[this->_offset] != ']')
		// Выполняем запоминание ошибки построения объявления таблицы
		return this->failure(error_t::INVALID_TABLE, this->_offset);
	// Выполняем пропуск знака закрытия объявления таблицы
	this->step(this->_offset + 1);
	/**
	 * Если объявляется очередная таблица набора таблиц
	 */
	if(appended){
		/**
		 * Если накопленный текст исчерпан
		 */
		if(this->_offset >= this->_buffer.length()){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки незакрытого объявления таблицы
				return this->failure(error_t::UNCLOSED_TABLE, opening);
			// Запоминаем нужду в продолжении текста
			this->_hungry = true;
			// Выводим признак неудачного разбора
			return false;
		}
		/**
		 * Если объявление набора таблиц второй скобкой не закрыто
		 */
		if(this->_buffer[this->_offset] != ']')
			// Выполняем запоминание ошибки построения объявления таблицы
			return this->failure(error_t::INVALID_TABLE, this->_offset);
		// Выполняем пропуск второго знака закрытия объявления
		this->step(this->_offset + 1);
	}
	// Собираемое полное имя объявленной таблицы
	string name;
	// Выполняем сборку полного имени таблицы из составных частей
	this->assemble(item.part, item.parts, name);
	/**
	 * Если объявляется очередная таблица набора таблиц
	 */
	if(appended){
		/**
		 * Если объявление набора таблиц отвергнуто
		 */
		if(!this->declare(name, kind_t::ARRAY, error_t::APPEND_TO_TABLE, opening))
			// Выводим признак неудачного разбора
			return false;
		// Запоминаем признак того, что записью объявляется набор таблиц
		this->_appending = true;
	/**
	 * Если объявление обычной таблицы отвергнуто
	 */
	} else if(!this->declare(name, kind_t::TABLE, error_t::DUPLICATE_TABLE, opening))
		// Выводим признак неудачного разбора
		return false;
	// Запоминаем признак того, что записью объявляется таблица
	this->_declaring = true;
	// Запоминаем имя таблицы, объявляемой разбираемой записью
	this->_pendingTable = ::move(name);
	// Выполняем добавление собранного события в очередь выдачи
	this->_items.push_back(item);
	// Выполняем разбор остатка строки за объявлением таблицы
	return this->tail(end);
}
/**
 * @brief Метод разбора пары имени ключа и значения
 *
 * @param end признак того, что текст поступил целиком
 * @return    признак успешного разбора
 *
 */
bool awh::codec::toml::Reader::pair(const bool end) noexcept {
	// Собираемое событие имени ключа
	item_t item;
	// Запоминаем вид собранного события
	item.event = event_t::KEY;
	// Запоминаем место имени ключа в исходном тексте
	item.location = this->locate(this->_offset);
	// Запоминаем номер первой составной части имени ключа
	item.part = static_cast <uint32_t> (this->_segments.size());
	/**
	 * Если разбор имени ключа не удался
	 */
	if(!this->name(end, item.parts))
		// Выводим признак неудачного разбора
		return false;
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Выполняем запоминание ошибки отсутствия знака равенства
			return this->failure(error_t::MISSING_EQUALS, this->_offset);
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
		// Выводим признак неудачного разбора
		return false;
	}
	/**
	 * Если за именем ключа знак равенства не следует
	 */
	if(this->_buffer[this->_offset] != '=')
		// Выполняем запоминание ошибки отсутствия знака равенства
		return this->failure(error_t::MISSING_EQUALS, this->_offset);
	// Выполняем пропуск знака равенства
	this->step(this->_offset + 1);
	/**
	 * Собираемое полное имя объявленного ключа
	 *
	 * @note Разделитель имени таблицы с именем ключа ставит сама сборка: всякая
	 *       часть имени идёт за ним, отчего пустое имя таблицы от верхнего уровня
	 *       отличимо
	 */
	string name(this->_table);
	// Выполняем сборку полного имени ключа из составных частей
	this->assemble(item.part, item.parts, name);
	/**
	 * Если имя ключа уже объявлено
	 */
	if(!this->declare(name, kind_t::VALUE, error_t::DUPLICATE_KEY, this->_start))
		// Выводим признак неудачного разбора
		return false;
	// Выполняем добавление собранного события в очередь выдачи
	this->_items.push_back(item);
	/**
	 * Если разбор значения пары не удался
	 */
	if(!this->content(end, 0, &name))
		// Выводим признак неудачного разбора
		return false;
	// Выполняем разбор остатка строки за парой
	return this->tail(end);
}
/**
 * @brief Метод разбора очередной записи текста настроек
 *
 * @param end признак того, что текст поступил целиком
 * @return    признак того, что запись разобрана
 *
 */
bool awh::codec::toml::Reader::record(const bool end) noexcept {
	// Выполняем сброс признака нужды в продолжении текста
	this->_hungry = false;
	// Выполняем очистку очереди собранных событий записи
	this->_items.clear();
	// Выполняем очистку составных частей имён ключей записи
	this->_segments.clear();
	// Выполняем очистку хранилища содержимого событий записи
	this->_store.clear();
	// Выполняем сброс номера выдаваемого события в очереди
	this->_current = 0;
	/**
	 * Выполняем очистку указателя имён, объявляемых разбираемой записью
	 *
	 * @note Очистка ведётся прежде очереди имён: указатель держит ссылки на её
	 *       содержимое, и порядок обратный оставлял бы его со ссылками на
	 *       освобождённую память
	 */
	this->_staged.clear();
	// Выполняем очистку имён, объявляемых разбираемой записью
	this->_pending.clear();
	// Выполняем очистку имени таблицы, объявляемой разбираемой записью
	this->_pendingTable.clear();
	// Выполняем сброс признака объявления таблицы разбираемой записью
	this->_declaring = false;
	// Выполняем сброс признака объявления набора таблиц разбираемой записью
	this->_appending = false;
	// Запоминаем положение начала разбираемой записи
	this->_start = this->_offset;
	// Запоминаем номер строки начала разбираемой записи
	const uint32_t line = this->_line;
	// Запоминаем положение начала строки разбираемой записи
	const size_t bol = this->_bol;
	// Признак успешного разбора записи
	bool result = false;
	/**
	 * Если накопленный текст исчерпан
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end)
			// Запоминаем состояние завершённого разбора текста
			this->_state = state_t::FINISHED;
		// Выводим признак того, что запись не разобрана
		return false;
	}
	// Выполняем пропуск пробельных знаков строки
	this->spaces();
	/**
	 * Если накопленный текст исчерпан пробельными знаками
	 */
	if(this->_offset >= this->_buffer.length()){
		/**
		 * Если текст поступил целиком
		 */
		if(end){
			// Запоминаем состояние завершённого разбора текста
			this->_state = state_t::FINISHED;
			// Выводим признак того, что запись не разобрана
			return false;
		}
		// Запоминаем нужду в продолжении текста
		this->_hungry = true;
	/**
	 * Если разбирается очередная запись текста настроек
	 */
	} else {
		// Получаем знак начала разбираемой записи
		const char letter = this->_buffer[this->_offset];
		/**
		 * Если строка оказалась пустой
		 */
		if((letter == '\n') || (letter == '\r')){
			// Собираемое событие пустой строки
			item_t item;
			// Запоминаем вид собранного события
			item.event = event_t::BLANK;
			// Запоминаем место пустой строки в исходном тексте
			item.location = this->locate(this->_start);
			/**
			 * Если выдача событий пустых строк настройками разрешена
			 */
			if(this->_settings.emitBlanks)
				// Выполняем добавление собранного события в очередь выдачи
				this->_items.push_back(item);
			// Выполняем разбор остатка строки
			result = this->tail(end);
		/**
		 * Если строка оказалась примечанием
		 */
		} else if(letter == '#') {
			/**
			 * Если строка накоплена целиком
			 */
			if(this->completed(end)){
				// Положение конца содержимого примечания
				size_t position = this->_buffer.find('\n', this->_offset);
				/**
				 * Если знак конца строки в накопленном тексте отсутствует
				 */
				if(position == string::npos)
					// Запоминаем положение конца содержимого примечания
					position = this->_buffer.length();
				/**
				 * Если разобрать примечание не удалось
				 */
				if(!this->commented(position, false))
					// Выводим признак неудачного разбора
					return false;
				// Выполняем разбор остатка строки
				result = this->tail(end);
			}
		/**
		 * Если строка оказалась объявлением таблицы
		 */
		} else if(letter == '[')
			// Выполняем разбор объявления таблицы
			result = this->table(end);
		// Выполняем разбор пары имени ключа и значения
		else result = this->pair(end);
	}
	/**
	 * Если разбор записи не удался
	 */
	if(!result){
		/**
		 * Если разбираемой записи не хватило продолжения текста
		 */
		if(this->_hungry){
			/**
			 * Если текст поступил целиком
			 */
			if(end)
				// Выполняем запоминание ошибки обрыва текста посреди записи
				return this->failure(error_t::UNEXPECTED_EOF, this->_start);
			/**
			 * Выполняем откат разбора к началу записи
			 *
			 * @note Откатывается и счёт строк: запись разбирается заново по приходе
			 *       продолжения, и знаки конца строки её сосчитались бы дважды
			 */
			this->_offset = this->_start;
			// Выполняем откат номера строки к началу записи
			this->_line = line;
			// Выполняем откат положения начала строки к началу записи
			this->_bol = bol;
			// Запоминаем состояние нужды в продолжении текста
			this->_state = state_t::HUNGRY;
			// Выполняем очистку очереди собранных событий записи
			this->_items.clear();
		}
		// Выводим признак того, что запись не разобрана
		return false;
	}
	/**
	 * Если длина разбираемой записи предел настроек превышает
	 *
	 * @note Проверка стоит здесь, а не при выдаче событий: событие выдаётся не всякой
	 *       записью, и проверка, поставленная там, обходилась бы записями, событий не
	 *       дающими
	 */
	if(!this->oversize(this->_offset))
		// Выводим признак того, что запись не разобрана
		return false;
	/**
	 * Если разбираемой записью объявляется очередная таблица набора таблиц
	 *
	 * @note Всякая таблица набора несёт свои ключи: имена, объявленные в предыдущей
	 *       таблице набора, повтором для новой не являются, и снимаются здесь все -
	 *       вместе с вложенными наборами таблиц, которые новая таблица заводит заново
	 */
	if(this->_appending && this->_settings.duplicates){
		/**
		 * Выполняем снятие имён, объявленных прежней таблицей набора
		 */
		for(auto i = this->_names.begin(); i != this->_names.end();){
			/**
			 * Если имя принадлежит содержимому объявленной таблицы набора
			 */
			if((i->first.length() > this->_pendingTable.length()) &&
			   (i->first.compare(0, this->_pendingTable.length(), this->_pendingTable) == 0) &&
			   (i->first.at(this->_pendingTable.length()) == '\x1F'))
				// Выполняем снятие имени, объявленного прежней таблицей набора
				i = this->_names.erase(i);
			// Выполняем переход к следующему объявленному имени
			else ++i;
		}
	}
	/**
	 * Выполняем перенос имён, объявленных разобранной записью
	 *
	 * @note Перенос выполняется здесь, а не по ходу разбора: запись, которой не хватило
	 *       продолжения текста, разбирается заново, и объявленное ею объявилось бы
	 *       дважды - при подаче кусками текст отвергался бы повтором, которого нет
	 */
	for(auto & pending : this->_pending){
		/**
		 * Если имя заведено исподволь
		 *
		 * @note Заведённое исподволь уже объявленного не подменяет: таблица,
		 *       объявленная заголовком, объемлющим именем ключа в заведённую исподволь
		 *       не превращается
		 */
		if(pending.implied){
			/**
			 * Если имя ещё не объявлено
			 */
			if(this->_names.count(pending.name) == 0)
				// Выполняем заведение имени исподволь
				this->_names.emplace(this->intern(pending.name), pending.kind);
			// Переходим к следующему объявленному имени
			continue;
		}
		// Выполняем поиск объявляемого имени среди объявленных прежде
		auto i = this->_names.find(pending.name);
		/**
		 * Если имя объявлено прежде
		 *
		 * @note Подмена рода нужна заголовку таблицы, заведённой прежде исподволь:
		 *       объявленная явно, она перестаёт быть заведённой исподволь
		 */
		if(i != this->_names.end())
			// Выполняем подмену рода объявленного имени
			i->second = pending.kind;
		// Выполняем запоминание объявленного имени
		else this->_names.emplace(this->intern(pending.name), pending.kind);
	}

	if(this->_declaring)
		// Запоминаем имя текущей таблицы текста настроек
		this->_table = this->_pendingTable;
	// Запоминаем состояние готовности разбора
	this->_state = state_t::READY;
	// Выводим признак того, что запись разобрана
	return true;
}
/**
 * @brief Метод получения настроек разбора текста настроек
 *
 * @return настройки разбора текста настроек
 *
 */
const awh::codec::toml::Reader::settings_t & awh::codec::toml::Reader::settings() const noexcept {
	// Выводим настройки разбора текста настроек
	return this->_settings;
}
/**
 * @brief Метод установки настроек разбора текста настроек
 *
 * @param settings устанавливаемые настройки разбора
 * @return         результат выполнения операции
 *
 */
bool awh::codec::toml::Reader::settings(const settings_t & settings) noexcept {
	/**
	 * Если разбор текста уже начался
	 *
	 * @note Подмена настроек посреди разбора дала бы текст, начало которого разобрано
	 *       одними правилами, а хвост другими
	 */
	if(this->_state != state_t::READY)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если накопленный текст не пуст
	 */
	if(!this->_buffer.empty())
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем настройки разбора текста настроек
	this->_settings = settings;
	// Выполняем установку навязанной извне кодировки исходного текста
	this->_decoder.encoding(settings.encoding);
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод подачи очередного куска исходного текста
 *
 * @param buffer буфер очередного куска исходного текста
 * @param size   размер буфера очередного куска исходного текста
 * @param end    признак того, что кусок является последним
 * @return       результат выполнения операции
 *
 */
bool awh::codec::toml::Reader::feed(const void * buffer, const size_t size, const bool end) noexcept {
	/**
	 * Если разбор прекращён ошибкой
	 */
	if(this->_state == state_t::FAILED)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если разбор текста уже завершён
	 */
	if(this->_state == state_t::FINISHED)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем признак поступления исходного текста целиком
	this->_final = (this->_final || end);
	// Выполняем изъятие разобранного начала накопленного текста
	this->compact();
	/**
	 * Если отказ приведения к кодировке UTF-8 ещё не выдан
	 */
	if(this->_decoding == error_t::NONE){
		/**
		 * Если приведение очередного куска к кодировке UTF-8 не удалось
		 *
		 * @note Отказ приведения откладывается до исчерпания уже приведённого начала:
		 *       приведение переносит в хранилище всё, что успело проверить, и выдать
		 *       отказ сразу значило бы отнять у разбора события, которые подача целиком
		 *       выдаёт
		 */
		if(!this->_decoder.convert(buffer, size, end, this->_buffer))
			// Запоминаем отложенный код ошибки приведения
			this->_decoding = this->_decoder.error();
	}
	// Выполняем разбор накопленного текста настроек
	while(this->record(end && (this->_decoding == error_t::NONE))){
		/**
		 * Если очередь собранных событий не пуста
		 */
		if(!this->_items.empty())
			// Выводим положительный результат выполнения операции
			return true;
	}
	/**
	 * Если разбор прекращён ошибкой
	 */
	if(this->_state == state_t::FAILED)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выводим результат выдачи отложенного отказа приведения к кодировке UTF-8
	return this->postponed();
}
/**
 * @brief Метод перехода к следующему событию разбора
 *
 * @return признак того, что событие получено
 *
 */
bool awh::codec::toml::Reader::next() noexcept {
	/**
	 * Если очередь собранных событий исчерпана
	 */
	if(this->_current >= this->_items.size()){
		/**
		 * Если разбор прекращён ошибкой либо завершён
		 */
		if((this->_state == state_t::FAILED) || (this->_state == state_t::FINISHED))
			// Выводим признак того, что событие не получено
			return false;
		// Выполняем очистку очереди собранных событий записи
		this->_items.clear();
		// Выполняем сброс номера выдаваемого события в очереди
		this->_current = 0;
		/**
		 * Выполняем разбор накопленного текста настроек
		 */
		while(this->record(this->_final && (this->_decoding == error_t::NONE))){
			/**
			 * Если очередь собранных событий не пуста
			 */
			if(!this->_items.empty())
				// Выходим из цикла разбора накопленного текста
				break;
		}
		/**
		 * Если очередь собранных событий по-прежнему пуста
		 */
		if(this->_items.empty()){
			/**
			 * Выполняем выдачу отложенного отказа приведения к кодировке UTF-8
			 *
			 * @note Выдача эта нужна и здесь: приведённое начало текста разбирается
			 *       тем из путей, которому оно досталось, и подача целиком доводит
			 *       разбор до конца именно переходом к следующему событию
			 */
			static_cast <void> (this->postponed());
			// Выводим признак того, что событие не получено
			return false;
		}
	}
	// Получаем очередное собранное событие разбора
	const item_t & item = this->_items.at(this->_current++);
	// Выполняем очистку составных частей имени ключа текущего события
	this->_path.clear();
	// Запоминаем место текущего события в исходном тексте
	this->_location = item.location;
	// Выполняем сброс значения текущего события
	this->_value = value_t();
	// Выполняем сброс примечания текущего события
	this->_comment = comment_t();
	/**
	 * Выполняем перебор составных частей имени ключа события
	 */
	for(uint32_t i = 0; i < item.parts; i++){
		// Собираемая составная часть имени ключа
		part_t part;
		// Запоминаем имя составной части
		part.name = this->get(this->_segments.at(item.part + i).name);
		// Запоминаем запись имени составной части
		part.naming = this->_segments.at(item.part + i).naming;
		// Выполняем добавление составной части к имени ключа
		this->_path.push_back(part);
	}
	/**
	 * Если событием является примечание
	 */
	if(item.event == event_t::COMMENT){
		// Запоминаем содержимое примечания
		this->_comment.text = this->get(item.content);
		// Запоминаем признак того, что примечание дописано к готовой строке
		this->_comment.trailing = item.trailing;
		// Запоминаем место примечания в исходном тексте
		this->_comment.location = item.location;
	}
	// Запоминаем тип значения текущего события
	this->_value.type = item.type;
	// Запоминаем запись строкового значения
	this->_value.quoting = item.quoting;
	// Запоминаем систему счисления записи целого числа
	this->_value.radix = item.radix;
	// Запоминаем логическое значение события
	this->_value.boolean = item.boolean;
	// Запоминаем целое число события
	this->_value.integer = item.integer;
	// Запоминаем число с плавающей точкой события
	this->_value.real = item.real;
	// Запоминаем отметку времени события
	this->_value.stamp = item.stamp;
	// Запоминаем место значения в исходном тексте
	this->_value.location = item.location;
	/**
	 * Если событием является значение
	 */
	if(item.event == event_t::VALUE)
		// Запоминаем содержимое строкового значения
		this->_value.text = this->get(item.content);
	// Выводим признак того, что событие получено
	return true;
}
/**
 * @brief Метод получения вида текущего события разбора
 *
 * @return вид текущего события разбора
 *
 */
awh::codec::toml::event_t awh::codec::toml::Reader::event() const noexcept {
	/**
	 * Если разбор текста завершён
	 */
	if((this->_state == state_t::FINISHED) && (this->_current >= this->_items.size()))
		// Выводим вид завершения разбора текста
		return event_t::FINISH;
	/**
	 * Если событие не выдавалось
	 */
	if((this->_current == 0) || (this->_current > this->_items.size()))
		// Выводим вид неопределённого события
		return event_t::NONE;
	// Выводим вид текущего события разбора
	return this->_items.at(this->_current - 1).event;
}
