/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён библиотеки
	 */
	using namespace awh;
	/**
	 * Пространство имён контейнера TOML
	 */
	using namespace awh::codec::toml;

	/**
	 * @brief Обозначение отсутствующей записи дерева настроек
	 *
	 */
	constexpr uint32_t NO_RECORD = static_cast <uint32_t> (-1);

	/**
	 * @brief Знак соединения составных частей имени в ключе указателя
	 *
	 * @note Знак этот в имени ключа встретиться не может: разбор его отвергает
	 *       управляющим. Соединение точкой давало бы разночтение имён «a.b» и «"a.b"»
	 */
	constexpr char SEPARATOR = '\x1F';

	/**
	 * @brief Шаблонная функция приведения дробного числа к затребованному виду
	 *
	 * @details Приведение это перенято у контейнера JSON дословно: договор извлечения
	 * общий у всех кодеков рамки, и расхождение в нём всплыло бы у потребителя,
	 * читающего два из них, - всплыло бы не сразу и не там, где заведено
	 *
	 * @note Отказа приведение не даёт ни при каком числе: признак успешности извлечения
	 *       отведён одному лишь случаю, когда значение числом не является вовсе
	 *
	 * @tparam T     вид, к какому приводится число
	 * @param  value приводимое дробное число
	 * @return       приведённое число
	 *
	 */
	template <typename T>
	T convert(const double value) noexcept {
		/**
		 * Если затребован дробный вид
		 */
		if(is_floating_point <T>::value)
			// Выводим приведённое число как оно есть
			return static_cast <T> (value);
		/**
		 * Если число не является числом вовсе
		 *
		 * @note Приведение `NaN` к целому есть неопределённое поведение при любом пределе:
		 *       x86-64 выдаёт наименьшее целое, ARM64 - ноль. Выдаётся ноль, и выдаётся он
		 *       успехом, а не отказом
		 */
		if(::isnan(value))
			// Выводим нулевое число
			return static_cast <T> (0);
		/**
		 * Если дробной части у числа нет вовсе
		 *
		 * @details Запись числа ответа менять не должна: `300.0` обязано извлекаться ровно
		 * так же, как `300`, - решение владельца от 30.08.2026. Оттого число с нулевой
		 * дробной частью уходит на путь ЦЕЛОГО и заворачивается по кругу языком, а не
		 * выдаётся пределом вида. Предел остаётся лишь у чисел, дробная часть у которых
		 * есть на деле: там записи целой числу этому не отвечает вовсе, и сличать нечего
		 *
		 * @note Ход этот берётся, лишь пока число укладывается в разрядность хранимого
		 *       целого: путь целого держит `int64_t` со знаком и `uint64_t` без него, и
		 *       повторить перенос вне этих границ нечем - там неопределено и приведение
		 *       самого языка. Числа шире уходят ниже, к пределам вида
		 *
		 * @warning Правило это держится ровно до предела точного представления целых
		 *          числом двойной точности - 2^53. За ним дробная запись теряет число ЕЩЁ
		 *          ДО приведения: `strtod` иного `double` для `9007199254740993` не имеет
		 *          вовсе, и починить это здесь нечем - число приходит сюда уже потерянным.
		 *          Граница закреплена проверкой `NumberSpellingsAgreeUpToDoublePrecision`
		 *          обеими половинами: совпадением на пределе и расхождением за ним
		 */
		if(value == ::trunc(value)){
			/**
			 * Если число отрицательное
			 */
			if(value < 0.){
				/**
				 * Если число укладывается в разрядность целого со знаком
				 */
				if(value >= -::ldexp(1., 63))
					// Выводим приведённое число, завёрнутое по кругу путём целого
					return static_cast <T> (static_cast <int64_t> (value));
			/**
			 * Если число укладывается в разрядность целого без знака
			 */
			} else if(value < ::ldexp(1., 64))
				// Выводим приведённое число, завёрнутое по кругу путём целого
				return static_cast <T> (static_cast <uint64_t> (value));
		}
		/**
		 * Если целая часть числа лежит ниже предела затребованного вида
		 *
		 * @note Пределы сличаются дробным видом, а не целым: предел `int64_t` целым видом
		 *       точно не представим дробным, и сличение целых дало бы промах на единицу
		 */
		if(value <= static_cast <double> (numeric_limits <T>::lowest()))
			// Выводим нижний предел затребованного вида
			return numeric_limits <T>::lowest();
		/**
		 * Если целая часть числа лежит выше предела затребованного вида
		 */
		if(value >= static_cast <double> (numeric_limits <T>::max()))
			// Выводим верхний предел затребованного вида
			return numeric_limits <T>::max();
		/**
		 * Выводим приведённое число, округлённое по правилам математики
		 *
		 * @note Округление здесь, а не усечение, решено владельцем 20.08.2026: усечение
		 *       выдавало единицу за `1.5`, тогда как ближайшее целое ей - двойка. Половина
		 *       уводится от нуля, оттого `-1.5` выдаётся как `-2`, а не как `-1`
		 */
		return static_cast <T> (::round(value));
	}

	/**
	 * @brief Метод получения порядкового номера из составной части имени
	 *
	 * @details Часть имени, состоящая из одних десятичных цифр, задаёт порядковый номер
	 * значения перечня либо таблицы набора: «products», «1», «name»
	 *
	 * @note Часть с ведущим нулём номером не признаётся: «01» и «1» задавали бы одно
	 *       значение двумя написаниями, и обращение к нему зависело бы от написания
	 *
	 * @param part  разбираемая составная часть имени
	 * @param index получаемый порядковый номер
	 * @return      результат выполнения операции
	 *
	 */
	bool ordinal(const string_view part, size_t & index) noexcept {
		/**
		 * Если часть имени пуста либо несёт ведущий ноль
		 */
		if(part.empty() || ((part.length() > 1) && (part.front() == '0')))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выполняем сброс получаемого порядкового номера
		index = 0;
		/**
		 * Выполняем перебор всех знаков составной части имени
		 */
		for(size_t i = 0; i < part.length(); i++){
			/**
			 * Если знак десятичной цифрой не является
			 */
			if(!ascii::isDigit(part[i]))
				// Выводим отрицательный результат выполнения операции
				return false;
			/**
			 * Если порядковый номер за отведённый ему отрезок значений выходит
			 */
			if(index > ((numeric_limits <size_t>::max() - static_cast <size_t> (part[i] - '0')) / 10))
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем дополнение порядкового номера очередной цифрой
			index = ((index * 10) + static_cast <size_t> (part[i] - '0'));
		}
		// Выводим положительный результат выполнения операции
		return true;
	}
};

/**
 * @brief Конструктор
 *
 */
awh::codec::toml::Document::Settings::Settings() noexcept {
	// Задаём выдачу примечаний разбором текста настроек
	this->reader.emitComments = true;
	// Задаём выдачу пустых строк разбором текста настроек
	this->reader.emitBlanks = true;
}

/**
 * @brief Метод получения содержимого отрезка хранилища знаков
 *
 * @param span отрезок общего хранилища знаков
 * @return     содержимое отрезка хранилища знаков
 *
 */
string_view awh::codec::toml::Document::get(const span_t & span) const noexcept {
	// Выводим содержимое отрезка хранилища знаков
	return string_view(this->_store).substr(span.offset, span.length);
}
/**
 * @brief Метод добавления содержимого к хранилищу знаков
 *
 * @param text добавляемое к хранилищу содержимое
 * @return     отрезок хранилища с добавленным содержимым
 *
 */
awh::codec::toml::Document::span_t awh::codec::toml::Document::add(const string_view text) noexcept {
	// Отрезок хранилища с добавленным содержимым
	span_t result;
	// Запоминаем смещение начала отрезка в хранилище знаков
	result.offset = static_cast <uint32_t> (this->_store.length());
	// Запоминаем длину добавляемого содержимого
	result.length = static_cast <uint32_t> (text.length());
	// Выполняем добавление содержимого к хранилищу знаков
	this->_store.append(text);
	// Выводим отрезок хранилища с добавленным содержимым
	return result;
}
/**
 * @brief Метод добавления составного имени к перечню частей имён
 *
 * @param path добавляемое составное имя
 * @return     отрезок перечня частей с добавленным именем
 *
 */
awh::codec::toml::Document::span_t awh::codec::toml::Document::keep(const vector <part_t> & path) noexcept {
	// Отрезок перечня частей с добавленным именем
	span_t result;
	// Запоминаем смещение начала имени в перечне частей
	result.offset = static_cast <uint32_t> (this->_keys.size());
	// Запоминаем количество составных частей имени
	result.length = static_cast <uint32_t> (path.size());
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path){
		// Собираемая составная часть имени
		key_t key;
		// Выполняем добавление имени части к хранилищу знаков
		key.name = this->add(part.name);
		// Запоминаем запись имени части в исходном тексте
		key.naming = part.naming;
		// Выполняем добавление составной части к перечню частей имён
		this->_keys.push_back(key);
	}
	// Выводим отрезок перечня частей с добавленным именем
	return result;
}
/**
 * @brief Метод добавления составного имени к перечню частей имён
 *
 * @param path добавляемое составное имя
 * @return     отрезок перечня частей с добавленным именем
 *
 */
awh::codec::toml::Document::span_t awh::codec::toml::Document::keep(const vector <string_view> & path) noexcept {
	// Отрезок перечня частей с добавленным именем
	span_t result;
	// Запоминаем смещение начала имени в перечне частей
	result.offset = static_cast <uint32_t> (this->_keys.size());
	// Запоминаем количество составных частей имени
	result.length = static_cast <uint32_t> (path.size());
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path){
		// Собираемая составная часть имени
		key_t key;
		// Выполняем добавление имени части к хранилищу знаков
		key.name = this->add(part);
		/**
		 * Выполняем подбор записи имени части
		 *
		 * @note Запись выбирается по пригодности имени: ограду ставит сама запись
		 *       текста, и здесь берётся лишь пожелание
		 */
		key.naming = naming_t::BARE;
		// Выполняем добавление составной части к перечню частей имён
		this->_keys.push_back(key);
	}
	// Выводим отрезок перечня частей с добавленным именем
	return result;
}
/**
 * @brief Метод сборки ключа указателя записей
 *
 * @param buffer буфер, куда собирается ключ указателя
 * @param path   отрезок перечня частей собираемого имени
 * @param parent ключ указателя объемлющей таблицы
 *
 */
void awh::codec::toml::Document::labelled(string & buffer, const span_t & path, const string_view parent) const noexcept {
	// Выполняем очистку буфера сборки ключа указателя
	buffer.clear();
	// Выполняем добавление ключа объемлющей таблицы
	buffer.append(parent);
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(uint32_t i = 0; i < path.length; i++){
		/**
		 * Выполняем добавление знака соединения составных частей имени
		 *
		 * @note Знак ставится перед всякой частью, а не между частями: имя ключа
		 *       описанием дозволено пустым, и без него имя «""» дало бы тот же ключ
		 *       указателя, что и верхний уровень текста настроек
		 */
		buffer.push_back(SEPARATOR);
		// Выполняем добавление очередной составной части имени
		buffer.append(this->get(this->_keys.at(path.offset + i).name));
	}
}
/**
 * @brief Метод сборки ключа указателя записей
 *
 * @param buffer буфер, куда собирается ключ указателя
 * @param path   составное имя записи
 *
 */
void awh::codec::toml::Document::labelled(string & buffer, const vector <string_view> & path) const noexcept {
	// Выполняем очистку буфера сборки ключа указателя
	buffer.clear();
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path){
		// Выполняем добавление знака соединения составных частей имени
		buffer.push_back(SEPARATOR);
		// Выполняем добавление очередной составной части имени
		buffer.append(part);
	}
}
/**
 * @brief Метод поиска записи по составному имени
 *
 * @param path составное имя искомой записи
 * @param kind вид искомой записи
 * @return     порядковый номер найденной записи либо количество записей
 *
 */
uint32_t awh::codec::toml::Document::locate(const vector <string_view> & path, const kind_t kind) const noexcept {
	// Буфер сборки ключа указателя записей
	string buffer;
	// Выполняем сборку ключа указателя записей
	this->labelled(buffer, path);
	// Выполняем поиск записи по составному имени
	auto i = this->_index.find(buffer);
	/**
	 * Если запись по составному имени не найдена
	 */
	if(i == this->_index.end())
		// Выводим обозначение отсутствующей записи
		return NO_RECORD;
	// Получаем вид найденной записи
	const kind_t found = this->_records.at(i->second).kind;
	/**
	 * Если искомой является таблица
	 *
	 * @note Таблица набора таблиц таблицею и является: обращение к ней по имени с
	 *       порядковым номером выдаёт её саму
	 */
	if(kind == kind_t::TABLE)
		// Выводим порядковый номер найденной записи
		return (((found == kind_t::TABLE) || (found == kind_t::ARRAY_TABLE)) ? i->second : NO_RECORD);
	// Выводим порядковый номер найденной записи
	return ((found == kind) ? i->second : NO_RECORD);
}
/**
 * @brief Метод перестроения указателей поиска
 *
 */
void awh::codec::toml::Document::reindex() noexcept {
	/**
	 * Если мусора, правкою накопленного, набралось вровень с живым
	 *
	 * @details Уплотнение стоит перебора всего дерева, и вести его на всякую правку
	 * значило бы платить за него вдвое: порог задан долею от живого, отчего уплотнение
	 * приходится не чаще, чем раз на половину размера дерева, и стоимость его на одну
	 * правку выходит постоянной
	 *
	 * @note Хранилище знаков считается отдельно: правка строкового значения дописывает
	 *       содержимое к нему всякий раз, а прежнее остаётся мусором, и счётом записей
	 *       рост этот не виден вовсе
	 */
	if(this->cluttered())
		// Выполняем уплотнение дерева настроек
		this->compact();
	// Выполняем очистку указателя записей
	this->_index.clear();
	// Выполняем очистку порядка объявления дочерних имён
	this->_children.clear();
	// Выполняем очистку имён таблиц, заведённых составным именем ключа
	this->_dotted.clear();
	// Выполняем сброс состояния обхода записей дерева
	this->_traversal.reset();
	/**
	 * Выполняем перебор всех записей дерева настроек
	 */
	for(uint32_t i = 0; i < static_cast <uint32_t> (this->_records.size()); i++)
		// Выполняем внесение очередной записи дерева в указатели поиска
		this->absorb(i);
}
/**
 * @brief Метод внесения записи дерева в указатели поиска
 *
 * @param index порядковый номер вносимой записи дерева настроек
 *
 */
void awh::codec::toml::Document::absorb(const uint32_t index) noexcept {
	// Получаем вносимую запись дерева настроек
	record_t & record = this->_records.at(index);
	/**
	 * Если запись снята пометкой удаления
	 */
	if(record.kind == kind_t::NONE)
		// Выходим из внесения записи дерева
		return;
	/**
	 * Если записью является примечание либо пустая строка
	 */
	if((record.kind == kind_t::COMMENT) || (record.kind == kind_t::BLANK))
		// Выходим из внесения записи дерева
		return;
	// Буфер сборки ключа указателя записей
	string buffer;
	// Ключ указателя объемлющего имени
	string parent;
	// Количество составных частей имени, объемлющей таблицей поглощённых
	size_t absorbed = 0;
	/**
	 * Ключ указателя таблицы, объемлющей объявляемую
	 *
	 * @note Хранится он особо: ключ нынешней таблицы перезаписывается объявлением
	 *       прежде сборки порядка дочерних имён, и брать его там уже поздно
	 */
	string enclosing;
	/**
	 * Если записью является объявление таблицы
	 */
	if((record.kind == kind_t::TABLE) || (record.kind == kind_t::ARRAY_TABLE)){
		// Имя объявляемой таблицы без номеров таблиц набора
		string named;
		// Выполняем сборку имени объявляемой таблицы
		this->labelled(named, record.path);
		/**
		 * Если объявляемая таблица лежит внутри таблицы набора
		 *
		 * @details Описание относит объявление «[[a.b]]» к ПОСЛЕДНЕЙ таблице набора «a»,
		 * а не к набору целиком. Ключ оттого строится на ключе нынешней таблицы, номер
		 * её несущем, и объявления из разных таблиц набора в один набор не сливаются
		 *
		 * @note Сличается имя без номеров, а основанием берётся ключ с номерами: по
		 *       одному лишь ключу продолжение не опознать - он несёт номера, каких в
		 *       имени объявляемой таблицы нет
		 *
		 * @note Проверяется и знак соединения за общим началом: без него имя «ab»
		 *       сочлось бы продолжением имени «a»
		 */
		/**
		 * Выполняем розыск объемлющей таблицы от самого длинного начала имени
		 *
		 * @note Розыск ведётся от длинного к короткому: объявление «[[a.b.c]]» лежит
		 *       внутри «a.b», буде та объявлена, а не внутри «a»
		 */
		for(size_t edge = named.rfind(SEPARATOR); (edge != string::npos) && (edge > 0);
		    edge = named.rfind(SEPARATOR, (edge - 1))){
			// Выполняем поиск ключа объемлющей таблицы по началу имени
			auto i = this->_traversal.anchors.find(named.substr(0, edge));
			/**
			 * Если ключ объемлющей таблицы найден
			 */
			if(i != this->_traversal.anchors.end()){
				// Запоминаем ключ таблицы, объемлющей объявляемую
				enclosing.assign(i->second);
				// Выполняем сборку ключа на основании ключа объемлющей таблицы
				buffer.assign(i->second);
				// Выполняем дозапись остатка имени объявляемой таблицы
				buffer.append(named, edge, string::npos);
				/**
				 * Выполняем подсчёт составных частей имени, объемлющей таблицей поглощённых
				 *
				 * @note Части эти пропускаются при сборке порядка дочерних имён: они
				 *       объявлены объемлющей таблицею и второй раз объявляться не должны
				 */
				for(size_t j = 0; j < edge; j++){
					/**
					 * Если очередным знаком является знак соединения составных частей
					 */
					if(named[j] == SEPARATOR)
						// Выполняем учёт составной части имени
						absorbed++;
				}
				// Выходим из розыска объемлющей таблицы
				break;
			}
		}
		/**
		 * Если объемлющей таблицы не найдено
		 */
		if(buffer.empty())
			// Выполняем сборку ключа указателя объявляемой таблицы от корня
			buffer.assign(named);
		/**
		 * Если объявляется очередная таблица набора таблиц
		 */
		if(record.kind == kind_t::ARRAY_TABLE){
			// Получаем порядковый номер объявляемой таблицы набора
			const uint32_t ordinal = this->_traversal.ordinals[buffer]++;
			// Выполняем добавление знака соединения составных частей имени
			buffer.push_back(SEPARATOR);
			/**
			 * Выполняем добавление порядкового номера таблицы набора
			 *
			 * @note Имя у таблиц набора общее, и различить их можно лишь номером:
			 *       им же они и адресуются потребителем
			 */
			buffer.append(to_string(ordinal));
		}
		// Запоминаем ключ указателя таблицы разбираемых записей
		this->_traversal.table = buffer;
		// Запоминаем имя таблицы разбираемых записей без номеров
		this->_traversal.named = named;
		/**
		 * Запоминаем ключ объявленной таблицы по имени её
		 *
		 * @note Запись ведётся поверх прежней намеренно: объявление «[[a]]» вторичное
		 *       заводит новую таблицу набора, и вложенные в неё обязаны лечь в неё, а
		 *       не в первую
		 */
		this->_traversal.anchors[named] = buffer;
		// Выполняем установку записи объявления таблицы указателем
		this->_index.emplace(buffer, index);
	/**
	 * Если записью является пара
	 */
	} else {
		// Выполняем сборку ключа указателя объявляемой пары
		this->labelled(buffer, record.path, this->_traversal.table);
		// Выполняем установку записи пары указателем
		this->_index.emplace(buffer, index);
	}
	/**
	 * Выполняем сборку порядка объявления дочерних имён
	 *
	 * @note Порядок этот собирается по всем составным частям имени: имя «a.b.c»
	 *       заводит дочернее имя «a» верхнему уровню, «b» имени «a» и «c» имени
	 *       «a.b» - иначе выдача дочерних имён обходила бы всё дерево
	 */
	/**
	 * Выполняем очистку ключа указателя объемлющего имени
	 *
	 * @note У пары объемлющим именем берётся её таблица, а у объявления таблицы -
	 *       верхний уровень: таблица объявляется именем своим целиком
	 */
	parent = ((record.kind == kind_t::PAIR) ? this->_traversal.table :
	 ((absorbed > 0) ? enclosing : string()));
	/**
	 * Выполняем перебор всех составных частей имени записи
	 *
	 * @note Части, объемлющей таблицею поглощённые, пропускаются: объявление «[[a.b]]»
	 *       внутри таблицы набора «a» заводит дочернее имя «b» ей одной, а не набору
	 */
	for(uint32_t j = static_cast <uint32_t> (absorbed); j < record.path.length; j++){
		// Получаем порядковый номер составной части имени
		const uint32_t key = (record.path.offset + j);
		/**
		 * Если дочернее имя объемлющему имени ещё не объявлено
		 */
		if(this->_traversal.declared[parent].emplace(this->get(this->_keys.at(key).name)).second)
			// Выполняем добавление дочернего имени к объемлющему имени
			this->_children[parent].push_back(key);
		// Выполняем добавление знака соединения составных частей имени
		parent.push_back(SEPARATOR);
		// Выполняем добавление очередной составной части к объемлющему имени
		parent.append(this->get(this->_keys.at(key).name));
		/**
		 * Если составной частью имени пары заведена таблица
		 *
		 * @note Заводит её всякая часть имени пары, кроме последней: описание
		 *       запрещает объявлять такую таблицу заголовком, тогда как таблицу,
		 *       заведённую исподволь заголовком, объявить им дозволено
		 */
		if((record.kind == kind_t::PAIR) && ((j + 1) < record.path.length))
			// Выполняем запоминание таблицы, заведённой составным именем ключа
			this->_dotted.emplace(parent);
	}
}
/**
 * @brief Метод наращивания указателей записью, вставшей в конец перечня
 *
 */
void awh::codec::toml::Document::grow() noexcept {
	/**
	 * Если дерево настроек записей не имеет
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: наращивание указателей
	 *          зовётся лишь следом за записью, в перечень вставшей, - пустым перечень
	 *          к тому времени уже не бывает. Замерено покрытием: заход не задет ни разу
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа - обращение к
	 *       последней записи пустого перечня уводило бы за край его
	 */
	if(this->_records.empty())
		// Выходим из наращивания указателей
		return;
	/**
	 * Если мусора, правкою накопленного, набралось вровень с живым
	 *
	 * @note Правка значения уже объявленной пары обращает в мусор узел прежнего
	 *       значения, указателей не трогая, и наращивание её не замечает. Порог
	 *       мусора поэтому сличается и здесь: уплотнение сдвигает номера всех записей
	 *       и требует полного перестроения, а не наращивания
	 */
	if(this->cluttered()){
		// Выполняем полное перестроение указателей поиска с уплотнением дерева
		this->reindex();
		// Выходим из наращивания указателей
		return;
	}
	// Выполняем внесение последней записи дерева в указатели поиска
	this->absorb(static_cast <uint32_t> (this->_records.size() - 1));
}
/**
 * @brief Метод переноса содержимого в уплотняемое хранилище знаков
 *
 * @param span  переносимый отрезок хранилища знаков
 * @param store уплотняемое хранилище знаков
 * @return      отрезок уплотнённого хранилища знаков
 *
 */
awh::codec::toml::Document::span_t awh::codec::toml::Document::relocate(const span_t & span, string & store) const noexcept {
	// Отрезок уплотнённого хранилища знаков
	span_t result;
	// Запоминаем смещение начала отрезка в уплотнённом хранилище
	result.offset = static_cast <uint32_t> (store.length());
	// Запоминаем длину переносимого содержимого
	result.length = span.length;
	// Выполняем перенос содержимого в уплотняемое хранилище
	store.append(this->get(span));
	// Выводим отрезок уплотнённого хранилища знаков
	return result;
}
/**
 * @brief Метод переноса составного имени в уплотняемый перечень частей
 *
 * @param span  переносимый отрезок перечня частей имён
 * @param store уплотняемое хранилище знаков
 * @param keys  уплотняемый перечень составных частей имён
 * @return      отрезок уплотнённого перечня частей имён
 *
 */
awh::codec::toml::Document::span_t awh::codec::toml::Document::relocate(const span_t & span, string & store, vector <key_t> & keys) const noexcept {
	// Отрезок уплотнённого перечня частей имён
	span_t result;
	// Запоминаем смещение начала имени в уплотнённом перечне частей
	result.offset = static_cast <uint32_t> (keys.size());
	// Запоминаем количество составных частей имени
	result.length = span.length;
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(uint32_t i = 0; i < span.length; i++){
		// Получаем очередную составную часть имени
		key_t key = this->_keys.at(span.offset + i);
		// Выполняем перенос имени части в уплотняемое хранилище знаков
		key.name = this->relocate(key.name, store);
		// Выполняем добавление части имени к уплотняемому перечню
		keys.push_back(key);
	}
	// Выводим отрезок уплотнённого перечня частей имён
	return result;
}
/**
 * @brief Метод переноса узла значения в уплотняемый перечень узлов
 *
 * @param node  порядковый номер переносимого узла значения
 * @param store уплотняемое хранилище знаков
 * @param keys  уплотняемый перечень составных частей имён
 * @param nodes уплотняемый перечень узлов значений
 * @return      порядковый номер узла в уплотнённом перечне
 *
 */
uint32_t awh::codec::toml::Document::relocate(const uint32_t node, string & store, vector <key_t> & keys, vector <node_t> & nodes) const noexcept {
	// Получаем переносимый узел значения
	node_t item = this->_nodes.at(node);
	// Выполняем перенос строкового значения в уплотняемое хранилище знаков
	item.text = this->relocate(this->_nodes.at(node).text, store);
	/**
	 * Выполняем перебор всех примечаний перечня значений
	 */
	for(size_t i = 0; i < item.remarks.size(); i++)
		// Выполняем перенос содержимого примечания в уплотняемое хранилище
		item.remarks.at(i).text = this->relocate(this->_nodes.at(node).remarks.at(i).text, store);
	/**
	 * Выполняем перебор всех составных имён пар встроенной таблицы
	 */
	for(size_t i = 0; i < item.names.size(); i++)
		// Выполняем перенос составного имени в уплотняемый перечень частей
		item.names.at(i) = this->relocate(this->_nodes.at(node).names.at(i), store, keys);
	/**
	 * Запоминаем порядковый номер узла в уплотнённом перечне
	 *
	 * @note Место под узел занимается прежде переноса вложенных: те заводят свои узлы
	 *       следом, и место, взятое после них, досталось бы вложенному
	 */
	const uint32_t result = static_cast <uint32_t> (nodes.size());
	// Выполняем добавление узла значения к уплотняемому перечню
	nodes.push_back(node_t());
	/**
	 * Выполняем перебор всех вложенных узлов значения
	 */
	for(size_t i = 0; i < item.items.size(); i++)
		// Выполняем перенос вложенного узла в уплотняемый перечень узлов
		item.items.at(i) = this->relocate(this->_nodes.at(node).items.at(i), store, keys, nodes);
	// Выполняем перенос собранного узла значения в уплотнённый перечень
	nodes.at(result) = ::move(item);
	// Выводим порядковый номер узла в уплотнённом перечне
	return result;
}
/**
 * @brief Метод проверки хранилища знаков на вместимость содержимого
 *
 * @param length длина добавляемого содержимого в октетах
 * @return       результат проверки
 *
 */
bool awh::codec::toml::Document::spacious(const size_t length) noexcept {
	/**
	 * Если содержимое в хранилище знаков не вмещается
	 */
	/**
	 * Если хранилище знаков предел свой переполняет
	 *
	 * @warning Заход этот есть застава последнего рубежа, ничем не задетая: предел
	 *          составляет 0xFFFFFFFF знаков, и текст, его достигающий, ни набором
	 *          проверок, ни ворошителем порождён быть не может - хранилище такое
	 *          заняло бы четыре гигабайта памяти. От него же идут и оба возврата
	 *          пустого указателя у зовущих. Сносу заход не подлежит: смещения
	 *          отрезков хранятся четырьмя байтами, и переполнение обратило бы их в
	 *          указатели на чужие места хранилища
	 */
	if((this->_store.length() + length) > static_cast <size_t> (numeric_limits <uint32_t>::max())){
		/**
		 * Запоминаем код ошибки правки дерева настроек
		 *
		 * @note Код здесь STORAGE_EXHAUSTED, а НЕ внутренний изъян: предел этот задан
		 *       устройством хранилища - смещение отведено четырьмя октетами, - и
		 *       достигается он размером дерева, а не ошибкою кодека. Прежде стоял
		 *       INTERNAL, и он слал потребителя докладывать о дефекте, какого нет.
		 *       Тем же кодом отвечают на это условие INI, XML, CSV и JSON: одно
		 *       условие - один код - одни слова
		 *
		 * @note Заход этот есть застава последнего рубежа: условие его недостижимо
		 *       набором проверок, и код выдаётся ради потребителя, а не ради их
		 */
		this->fault(error_t::STORAGE_EXHAUSTED);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат проверки
		return false;
	}
	// Выводим положительный результат проверки
	return true;
}
/**
 * @brief Метод проверки дерева на засорённость мусором правки
 *
 * @return результат проверки
 *
 */
bool awh::codec::toml::Document::cluttered() const noexcept {
	// Выводим результат проверки дерева на засорённость мусором правки
	return ((this->_garbage > (16 + ((this->_records.size() + this->_nodes.size()) / 2))) ||
	        (this->_store.length() > (1024 + (this->_compacted * 2))));
}
/**
 * @brief Метод уплотнения дерева настроек
 *
 */
void awh::codec::toml::Document::compact() noexcept {
	// Уплотняемое хранилище знаков
	string store;
	// Уплотняемый перечень составных частей имён
	vector <key_t> keys;
	// Уплотняемый перечень узлов значений
	vector <node_t> nodes;
	// Уплотняемый перечень записей дерева настроек
	vector <record_t> records;
	// Порядковые номера записей в уплотнённом перечне
	vector <uint32_t> moved(this->_records.size(), NO_RECORD);
	/**
	 * Выполняем перебор всех записей дерева настроек
	 */
	for(size_t i = 0; i < this->_records.size(); i++){
		/**
		 * Если запись снята пометкой удаления
		 */
		if(this->_records.at(i).kind == kind_t::NONE)
			// Выполняем переход к следующей записи дерева настроек
			continue;
		// Получаем переносимую запись дерева настроек
		record_t record = this->_records.at(i);
		// Выполняем перенос составного имени в уплотняемый перечень частей
		record.path = this->relocate(this->_records.at(i).path, store, keys);
		// Выполняем перенос содержимого примечания в уплотняемое хранилище
		record.text = this->relocate(this->_records.at(i).text, store);
		/**
		 * Если записью является пара
		 */
		if(record.kind == kind_t::PAIR)
			// Выполняем перенос узла значения в уплотняемый перечень узлов
			record.node = this->relocate(this->_records.at(i).node, store, keys, nodes);
		// Запоминаем узел значения записи, значения не несущей
		else record.node = 0;
		// Запоминаем порядковый номер записи в уплотнённом перечне
		moved.at(i) = static_cast <uint32_t> (records.size());
		// Выполняем добавление записи к уплотняемому перечню
		records.push_back(record);
	}
	/**
	 * Выполняем перебор всех записей уплотнённого перечня
	 *
	 * @note Перенос ссылок ведётся вторым проходом: запись объявления таблицы стоит
	 *       прежде своих пар, но порядковый номер её известен лишь по переносе всех
	 */
	for(auto & record : records){
		/**
		 * Если запись принадлежит объявленной таблице
		 */
		if(record.table != NO_RECORD)
			// Выполняем перенос порядкового номера записи объявления таблицы
			record.table = moved.at(record.table);
	}
	// Выполняем замену хранилища знаков уплотнённым
	this->_store = ::move(store);
	// Выполняем замену перечня составных частей имён уплотнённым
	this->_keys = ::move(keys);
	// Выполняем замену перечня узлов значений уплотнённым
	this->_nodes = ::move(nodes);
	// Выполняем замену перечня записей дерева настроек уплотнённым
	this->_records = ::move(records);
	// Выполняем сброс количества записей и узлов, правкой в мусор обращённых
	this->_garbage = 0;
	// Запоминаем длину хранилища знаков, снятую уплотнением
	this->_compacted = this->_store.length();
}
/**
 * @brief Метод заведения узла значения
 *
 * @return порядковый номер заведённого узла значения
 *
 */
uint32_t awh::codec::toml::Document::reserve() noexcept {
	// Выполняем заведение очередного узла значения
	this->_nodes.push_back(node_t());
	// Выводим порядковый номер заведённого узла значения
	return static_cast <uint32_t> (this->_nodes.size() - 1);
}
/**
 * @brief Метод переноса значения разбора в узел дерева
 *
 * @param node  порядковый номер заполняемого узла значения
 * @param value переносимое значение разбора
 *
 */
void awh::codec::toml::Document::assign(const uint32_t node, const content_t & value) noexcept {
	// Выполняем добавление строкового значения к хранилищу знаков
	const span_t text = this->add(value.text);
	// Получаем заполняемый узел значения
	node_t & item = this->_nodes.at(node);
	// Запоминаем тип значения
	item.type = value.type;
	// Запоминаем ограду строкового значения
	item.quoting = value.quoting;
	// Запоминаем систему счисления записи целого числа
	item.radix = value.radix;
	// Запоминаем логическое значение
	item.boolean = value.boolean;
	// Запоминаем целое число со знаком
	item.integer = value.integer;
	// Запоминаем число с плавающей точкой
	item.real = value.real;
	// Запоминаем отметку времени
	item.stamp = value.stamp;
	// Запоминаем место строкового значения в хранилище знаков
	item.text = text;
}
/**
 * @brief Метод записи узла значения собираемым текстом
 *
 * @param writer запись собираемого текста настроек
 * @param node   порядковый номер записываемого узла значения
 * @return       результат выполнения операции
 *
 */
bool awh::codec::toml::Document::compose(writer_t & writer, const uint32_t node) const noexcept {
	// Получаем записываемый узел значения
	const node_t & item = this->_nodes.at(node);
	/**
	 * Выполняем выбор типа записываемого значения
	 */
	switch(static_cast <uint8_t> (item.type)){
		// Если записывается последовательность знаков
		case static_cast <uint8_t> (type_t::STRING):
			// Выполняем запись строкового значения
			return writer.text(this->get(item.text), item.quoting);
		// Если записывается логическое значение
		case static_cast <uint8_t> (type_t::BOOLEAN):
			// Выполняем запись логического значения
			return writer.boolean(item.boolean);
		// Если записывается целое число
		case static_cast <uint8_t> (type_t::INTEGER):
			// Выполняем запись целого числа
			return writer.integer(item.integer, item.radix);
		// Если записывается число с плавающей точкой
		case static_cast <uint8_t> (type_t::FLOAT):
			// Выполняем запись числа с плавающей точкой
			return writer.real(item.real);
		// Если записывается отметка времени со смещением часового пояса
		case static_cast <uint8_t> (type_t::OFFSET_DATETIME):
		// Если записывается отметка времени без смещения часового пояса
		case static_cast <uint8_t> (type_t::LOCAL_DATETIME):
		// Если записывается местная дата
		case static_cast <uint8_t> (type_t::LOCAL_DATE):
		// Если записывается местное время
		case static_cast <uint8_t> (type_t::LOCAL_TIME):
			// Выполняем запись отметки времени
			return writer.stamp(item.stamp, item.type);
		// Если записывается перечень значений
		case static_cast <uint8_t> (type_t::ARRAY): {
			/**
			 * Если записать начало перечня значений не удалось
			 */
			if(!writer.arrayOpen(item.multiline))
				// Выводим отрицательный результат выполнения операции
				return false;
			/**
			 * Порядковый номер ближайшего незаписанного примечания перечня
			 *
			 * @note Примечания собраны разбором по возрастанию места своего, и перебирать
			 *       их заново для всякого значения незачем: перечень с примечаниями к
			 *       каждому значению обходился бы записи квадратом
			 */
			size_t next = 0;
			/**
			 * Выполняем перебор всех значений перечня вместе с примечаниями его
			 */
			for(size_t i = 0; i <= item.items.size(); i++){
				/**
				 * Выполняем запись всех примечаний, на этом месте перечня стоящих
				 */
				for(; (next < item.remarks.size()) &&
				      (item.remarks.at(next).index == static_cast <uint32_t> (i)); next++){
					// Получаем очередное примечание перечня
					const remark_t & remark = item.remarks.at(next);
					// Признак успешной записи примечания перечня
					const bool result = (remark.trailing ?
						writer.remarked(this->get(remark.text), (remark.index < static_cast <uint32_t> (item.items.size()))) :
						writer.remark(this->get(remark.text)));
					/**
					 * Если записать примечание перечня не удалось
					 *
					 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: примечания заводит
					 *          один только разбор, а он кладёт их лишь в перечень многострочный и
					 *          управляющих знаков внутрь не пропускает - оба отказа записи
					 *          примечания недостижимы отсюда. Замерено покрытием: заход не задет
					 *          ни разу
					 *
					 * @note Сносу заход не подлежит: без него отказ записи пропал бы молча, и
					 *       выдача вышла бы усечённой при успехе, отданном потребителю
					 */
					if(!result)
						// Выводим отрицательный результат выполнения операции
						return false;
				}
				/**
				 * Если значения перечня исчерпаны
				 */
				if(i == item.items.size())
					// Выходим из перебора значений перечня
					break;
				/**
				 * Если записать очередное значение перечня не удалось
				 */
				if(!this->compose(writer, item.items.at(i)))
					// Выводим отрицательный результат выполнения операции
					return false;
			}
			// Выполняем запись конца перечня значений
			return writer.arrayClose();
		}
		// Если записывается встроенная таблица
		case static_cast <uint8_t> (type_t::TABLE): {
			/**
			 * Если записать начало встроенной таблицы не удалось
			 */
			if(!writer.inlineOpen())
				// Выводим отрицательный результат выполнения операции
				return false;
			/**
			 * Собираемое составное имя ключа очередной пары
			 *
			 * @note Буфер заведён единожды на всю таблицу: имя ключа живёт лишь до его
			 *       записи, и заводить его заново на каждую пару значило бы просить
			 *       памяти столько раз, сколько во встроенной таблице пар
			 */
			vector <part_t> path;
			/**
			 * Выполняем перебор всех пар встроенной таблицы
			 */
			for(size_t i = 0; i < item.items.size(); i++){
				// Выполняем подготовку буфера составного имени ключа пары
				path.clear();
				// Выполняем отведение места под составные части имени ключа
				path.resize(item.names.at(i).length);
				/**
				 * Выполняем перебор всех составных частей имени ключа
				 */
				for(uint32_t j = 0; j < item.names.at(i).length; j++){
					// Получаем очередную составную часть имени ключа
					const key_t & key = this->_keys.at(item.names.at(i).offset + j);
					// Запоминаем имя составной части ключа
					path.at(j).name = this->get(key.name);
					// Запоминаем запись имени составной части ключа
					path.at(j).naming = key.naming;
				}
				/**
				 * Если записать имя ключа пары встроенной таблицы не удалось
				 */
				if(!writer.key(path))
					// Выводим отрицательный результат выполнения операции
					return false;
				/**
				 * Если записать значение пары встроенной таблицы не удалось
				 */
				if(!this->compose(writer, item.items.at(i)))
					// Выводим отрицательный результат выполнения операции
					return false;
			}
			// Выполняем запись конца встроенной таблицы
			return writer.inlineClose();
		}
	}
	/**
	 * Запоминаем код ошибки записи дерева настроек
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: перебор выше разбирает
	 *          ВСЕ виды значений перечня, и вид иной в дерево не попадает - разбор
	 *          заводит лишь перечисленные, а правка их же и принимает. Замерено
	 *          покрытием: заход не задет ни разу
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа - вид, впредь
	 *       заведённый и в перебор не вписанный, снимался бы из дерева пустым местом
	 */
	this->fault(error_t::INVALID_VALUE);
	// Выполняем вывод сообщения об отказе в лог
	this->report();
	// Выводим отрицательный результат выполнения операции
	return false;
}
/**
 * @brief Метод проверки составного имени на пригодность к записи
 *
 * @param path проверяемое составное имя
 * @return     результат выполнения операции
 *
 */
bool awh::codec::toml::Document::acceptable(const vector <string_view> & path, const bool table) noexcept {
	/**
	 * Если составное имя пусто
	 */
	if(path.empty()){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::EMPTY_KEY);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если количество составных частей имени превышает допустимое
	 */
	if((this->_settings.reader.maxParts > 0) && (path.size() > static_cast <size_t> (this->_settings.reader.maxParts))){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::PARTS_EXCEEDED);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path){
		/**
		 * Если длина составной части имени превышает допустимую
		 */
		if((this->_settings.reader.maxKey > 0) && (part.length() > static_cast <size_t> (this->_settings.reader.maxKey))){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::KEY_TOO_LONG);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Выполняем перебор всех знаков составной части имени
		 */
		for(size_t i = 0; i < part.length(); i++){
			// Получаем беззнаковое значение очередного знака имени
			const uint8_t letter = static_cast <uint8_t> (part[i]);
			/**
			 * Если знак имени является управляющим
			 *
			 * @note Оградить управляющий знак в имени нечем: основная строка
			 *       записала бы его последовательностью, но разбор прочитал бы её
			 *       обратно иным знаком, и имя перестало бы совпадать с искомым
			 */
			if(((letter < 0x20) && (part[i] != '\t')) || (letter == 0x7F)){
				// Запоминаем код ошибки правки дерева настроек
				this->fault(error_t::INVALID_KEY);
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим отрицательный результат выполнения операции
				return false;
			}
		}
	}
	/**
	 * Выполняем перебор всех объемлющих имён проверяемого составного имени
	 */
	for(size_t i = 1; i < path.size(); i++){
		// Собираемое объемлющее имя
		const vector <string_view> name(path.begin(), (path.begin() + i));
		/**
		 * Если объемлющее имя занято парой
		 *
		 * @note Пара эта вправе нести встроенную таблицу, но дополнять её описание
		 *       запрещает: собранный текст разбор отверг бы дополнением закрытой
		 *       встроенной таблицы
		 */
		if(this->locate(name, kind_t::PAIR) != NO_RECORD){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::REDEFINE_TABLE);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Получаем количество таблиц набора таблиц объемлющего имени
		const size_t tables = this->count(name);
		/**
		 * Если объемлющее имя занято набором таблиц
		 */
		if(tables > 0){
			// Собираемый порядковый номер таблицы набора
			size_t number = 0;
			/**
			 * Если частью имени порядковый номер таблицы набора не задан
			 *
			 * @note Набор таблиц адресуется порядковым номером, и всякое иное имя за
			 *       ним завело бы пару поверх набора: разбор отверг бы её дополнением
			 *       набора таблиц именем, набором не являющимся
			 *
			 * @note Номер снимается тем же разбором, каким снимает его спуск внутрь
			 *       значения: своя проверка признавала здесь номером и запись с ведущим
			 *       нулём, тогда как указатель дерева ведёт таблицы набора записью
			 *       кратчайшей. Имя «01» не совпадало ни с одной таблицей, пара по нему
			 *       вставала верхним уровнем поверх набора, и собранный текст свой же
			 *       разбор отвергал дополнением набора таблиц
			 */
			if(!ordinal(path.at(i), number) || (number >= tables)){
				// Запоминаем код ошибки правки дерева настроек
				this->fault(error_t::REDEFINE_TABLE);
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим отрицательный результат выполнения операции
				return false;
			}
		}
	}
	/**
	 * Если проверяемое имя занято набором таблиц
	 */
	if(this->count(path) > 0){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::REDEFINE_TABLE);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если объявляемым именем является имя таблицы
	 */
	if(table){
		/**
		 * Если имя таблицы занято парой
		 */
		if(this->locate(path, kind_t::PAIR) != NO_RECORD){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::REDEFINE_TABLE);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Буфер сборки ключа указателя записей
		string buffer;
		// Выполняем сборку ключа указателя проверяемого имени
		this->labelled(buffer, path);
		/**
		 * Если таблица заведена составным именем ключа
		 *
		 * @note Описание запрещает объявлять такую таблицу заголовком: собранный
		 *       правкой текст разбор отверг бы повтором объявления
		 */
		if(this->_dotted.count(buffer) > 0){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::DUPLICATE_TABLE);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	/**
	 * Если имя пары занято таблицей
	 */
	} else {
		/**
		 * Если имя пары занято объявленной таблицей
		 */
		if(this->locate(path, kind_t::TABLE) != NO_RECORD){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::REDEFINE_TABLE);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Буфер сборки ключа указателя записей
		string buffer;
		// Выполняем сборку ключа указателя проверяемого имени
		this->labelled(buffer, path);
		/**
		 * Если у проверяемого имени есть дочерние имена
		 *
		 * @note Имя, несущее дочерние, заведено таблицей - объявленной заголовком
		 *       либо составным именем ключа, - и пара поверх него собрала бы текст,
		 *       который разбор отверг бы повтором имени
		 */
		if(this->_children.count(buffer) > 0){
			// Запоминаем код ошибки правки дерева настроек
			this->fault(error_t::REDEFINE_TABLE);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод получения узла значения по составному имени
 *
 * @param path составное имя искомой пары
 * @return     узел значения найденной пары либо пустой указатель
 *
 */
const awh::codec::toml::Document::node_t * awh::codec::toml::Document::seek(const vector <string_view> & path) const noexcept {
	/**
	 * Выполняем перебор длин начала составного имени, парой быть могущих
	 *
	 * @details Имя ищется от самого длинного начала к самому короткому: остаток его
	 * ведёт внутрь составного значения найденной пары - порядковым номером в перечень,
	 * именем ключа во встроенную таблицу. Записи «a = [[1, 2], [3, 4]]» отвечает тем
	 * самым имя «a», «1», «0», а записи «c = {d = {e = 5}}» - имя «c», «d», «e»
	 *
	 * @note Порядок от длинного к короткому обязателен: таблица набора адресуется
	 *       порядковым номером частью имени, и начни поиск с короткого начала, номер
	 *       этот достался бы спуску внутрь значения
	 */
	for(size_t used = path.size(); used > 0; used--){
		// Собираемое начало составного имени, парой быть могущее
		const vector <string_view> head(path.begin(), (path.begin() + static_cast <long> (used)));
		// Выполняем поиск записи пары по началу составного имени
		const uint32_t record = this->locate(head, kind_t::PAIR);
		/**
		 * Если запись пары по началу составного имени не найдена
		 */
		if(record == NO_RECORD)
			// Переходим к следующей длине начала составного имени
			continue;
		// Получаем узел значения найденной пары
		const node_t * result = &this->_nodes.at(this->_records.at(record).node);
		// Порядковый номер разбираемой части остатка составного имени
		size_t i = used;
		/**
		 * Выполняем спуск внутрь составного значения найденной пары
		 */
		while(i < path.size()){
			/**
			 * Если значением является перечень
			 */
			if(result->type == type_t::ARRAY){
				// Собираемый порядковый номер значения перечня
				size_t index = 0;
				/**
				 * Если часть имени порядковым номером не является
				 */
				if(!ordinal(path.at(i), index) || (index >= result->items.size()))
					// Выводим пустой указатель узла значения
					return nullptr;
				// Выполняем спуск в значение перечня
				result = &this->_nodes.at(result->items.at(index));
				// Выполняем переход к следующей части остатка имени
				i++;
			/**
			 * Если значением является встроенная таблица
			 */
			} else if(result->type == type_t::TABLE) {
				// Порядковый номер найденной пары встроенной таблицы
				size_t found = result->items.size();
				/**
				 * Выполняем перебор всех пар встроенной таблицы
				 */
				for(size_t j = 0; (j < result->items.size()) && (found == result->items.size()); j++){
					// Получаем место составного имени очередной пары
					const span_t & name = result->names.at(j);
					/**
					 * Если частей остатка имени на имя пары не хватает
					 */
					if((i + name.length) > path.size())
						// Переходим к следующей паре встроенной таблицы
						continue;
					// Признак совпадения имени пары с остатком составного имени
					bool matched = true;
					/**
					 * Выполняем перебор всех составных частей имени пары
					 */
					for(uint32_t k = 0; matched && (k < name.length); k++)
						// Выполняем сличение очередной части имени пары с частью остатка
						matched = (this->get(this->_keys.at(name.offset + k).name).compare(path.at(i + k)) == 0);
					/**
					 * Если имя пары с остатком составного имени совпало
					 */
					if(matched)
						// Запоминаем порядковый номер найденной пары встроенной таблицы
						found = j;
				}
				/**
				 * Если пара встроенной таблицы не найдена
				 */
				if(found == result->items.size())
					// Выводим пустой указатель узла значения
					return nullptr;
				// Выполняем переход за имя найденной пары встроенной таблицы
				i += result->names.at(found).length;
				// Выполняем спуск в значение пары встроенной таблицы
				result = &this->_nodes.at(result->items.at(found));
			/**
			 * Если значение составным не является
			 */
			} else return nullptr;
		}
		// Выводим найденный узел значения
		return result;
	}
	// Выводим пустой указатель узла значения
	return nullptr;
}
/**
 * @brief Метод получения узла значения для правки
 *
 * @param path составное имя правимой пары
 * @return     узел значения правимой пары либо пустой указатель
 *
 */
awh::codec::toml::Document::node_t * awh::codec::toml::Document::reach(const vector <string_view> & path) noexcept {
	/**
	 * Если дерево засорено мусором правки
	 *
	 * @note Уплотнение ведётся здесь, а не по правке значения: правка получает указатель
	 *       на узел и пишет в него, а уплотнение перечень узлов переносит - указатель,
	 *       выданный до него, повис бы
	 */
	if(this->cluttered())
		// Выполняем перестроение указателей поиска вместе с уплотнением дерева
		this->reindex();
	// Собираемая длина составного имени правимой пары
	size_t length = 0;
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path)
		// Выполняем учёт длины очередной составной части имени
		length += part.length();
	/**
	 * Если составное имя в хранилище знаков не вмещается
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: отрезок хранилища задан
	 *          смещением в четыре октета, и переполнить его нечем иначе, как деревом
	 *          свыше четырёх миллиардов знаков - объёмом, какого ни набор проверок, ни
	 *          ворошитель, ни корпус наречий не подают. Замерено покрытием: заход не
	 *          задет ни разу
	 *
	 * @note Сносу заход не подлежит: без него смещение переполнилось бы молча, и дерево
	 *       выдавало бы содержимое, взятое не оттуда
	 */
	if(!this->spacious(length))
		// Выводим пустой указатель узла значения
		return nullptr;
	/**
	 * Если составное имя к записи непригодно
	 */
	if(!this->acceptable(path, false))
		// Выводим пустой указатель узла значения
		return nullptr;
	// Выполняем поиск записи пары по составному имени
	const uint32_t found = this->locate(path, kind_t::PAIR);
	/**
	 * Если запись пары по составному имени найдена
	 */
	if(found != NO_RECORD){
		/**
		 * Выполняем заведение нового узла значения правимой пары
		 *
		 * @note Узел заводится новым, а не правится на месте: прежнее значение
		 *       вправе нести перечень со вложенными узлами, и правка его на месте
		 *       оставила бы их обрывками
		 */
		this->_records.at(found).node = this->reserve();
		// Выполняем учёт узла прежнего значения, в мусор обращённого
		this->_garbage++;
		// Выводим узел значения правимой пары
		return &this->_nodes.at(this->_records.at(found).node);
	}
	// Порядковый номер записи объявления таблицы правимой пары
	uint32_t table = NO_RECORD;
	// Количество составных частей имени, приходящихся на таблицу
	size_t depth = 0;
	/**
	 * Выполняем поиск объявленной таблицы, которой пара принадлежит
	 *
	 * @note Поиск ведётся от самого длинного имени к самому короткому: пара «a.b.c»
	 *       принадлежит таблице «a.b», когда та объявлена, и таблице «a», когда
	 *       объявлена лишь она
	 */
	for(size_t i = (path.size() - 1); i > 0; i--){
		// Собираемое составное имя искомой таблицы
		const vector <string_view> name(path.begin(), (path.begin() + i));
		// Выполняем поиск записи объявления таблицы
		table = this->locate(name, kind_t::TABLE);
		/**
		 * Если запись объявления таблицы найдена
		 */
		if(table != NO_RECORD){
			// Запоминаем количество составных частей имени таблицы
			depth = i;
			// Выполняем прекращение поиска объявленной таблицы
			break;
		}
	}
	// Собираемое составное имя ключа заводимой пары
	const vector <string_view> name(path.begin() + depth, path.end());
	/**
	 * Место вставки записи заводимой пары
	 *
	 * @note Место это ищется за последней парой своей таблицы, а не перед
	 *       объявлением следующей: пустая строка и примечание, стоящие перед тем
	 *       объявлением, писаны к нему, и вклиниваться между ними и им не следует
	 */
	size_t position = ((table != NO_RECORD) ? (table + 1) : 0);
	/**
	 * Если место вставки для этой таблицы уже отыскивалось прежде
	 *
	 * @note Записи, лежащие до найденного тогда места, уже пройдены обходом, и пары
	 *       среди них позднее найденной нет: обход продолжается от подсказки и
	 *       проходит лишь записи, с тех пор добавленные
	 */
	{
		// Выполняем поиск подсказки места вставки по порядковому номеру таблицы
		const auto hint = this->_traversal.hints.find(table);
		/**
		 * Если подсказка места вставки обнаружена и лежит в пределах перечня записей
		 */
		if((hint != this->_traversal.hints.end()) && (hint->second > position) && (hint->second <= this->_records.size()))
			// Запоминаем местом начала обхода подсказанное место вставки
			position = hint->second;
	}
	/**
	 * Выполняем поиск последней пары таблицы, которой пара принадлежит
	 */
	for(size_t i = position; i < this->_records.size(); i++){
		// Получаем вид очередной записи дерева настроек
		const kind_t kind = this->_records.at(i).kind;
		/**
		 * Если записью является объявление таблицы
		 *
		 * @note Пара, записанная за объявлением таблицы, принадлежит той таблице:
		 *       место паре есть лишь до следующего объявления
		 */
		if((kind == kind_t::TABLE) || (kind == kind_t::ARRAY_TABLE))
			// Выполняем прекращение поиска последней пары таблицы
			break;
		/**
		 * Если записью является пара
		 */
		if(kind == kind_t::PAIR){
			// Запоминаем местом вставки место за найденной парой
			position = (i + 1);
			/**
			 * Если следом за парой записано примечание, дописанное к её строке
			 */
			if(((i + 1) < this->_records.size()) && (this->_records.at(i + 1).kind == kind_t::COMMENT) &&
			   this->_records.at(i + 1).trailing)
				// Запоминаем местом вставки место за примечанием пары
				position = (i + 2);
		}
	}
	// Собираемая запись заводимой пары
	record_t record;
	// Запоминаем вид заводимой записи
	record.kind = kind_t::PAIR;
	// Выполняем добавление имени ключа к перечню частей имён
	record.path = this->keep(name);
	// Выполняем заведение узла значения заводимой пары
	record.node = this->reserve();
	// Запоминаем порядковый номер записи объявления таблицы
	record.table = table;
	/**
	 * Признак того, что запись заводимой пары встаёт в конец перечня записей
	 *
	 * @note Порядковые номера прежних записей при этом не сдвигаются, и указатели
	 *       достаточно нарастить: сборка дерева правками идёт именно так, а полное
	 *       перестроение на всякую правку обращало её в квадратичную
	 */
	const bool appended = (position >= this->_records.size());
	/**
	 * Запоминаем подсказку места вставки следующей пары этой таблицы
	 *
	 * @note Место запоминается за вставляемой записью: следующая пара той же таблицы
	 *       встанет не прежде него
	 */
	this->_traversal.hints[table] = (position + 1);
	// Выполняем вставку записи заводимой пары
	this->_records.insert((this->_records.begin() + static_cast <long> (position)), record);
	/**
	 * Если запись заводимой пары встала в конец перечня записей
	 */
	if(appended)
		// Выполняем наращивание указателей поиска заведённой записью
		this->grow();
	// Выполняем перестроение указателей поиска
	else this->reindex();
	/**
	 * Выполняем поиск записи заведённой пары заново
	 *
	 * @note Перестроение указателей вправе повлечь уплотнение дерева, а уплотнение
	 *       перечень узлов переносит: порядковый номер, взятый до него, указывал бы
	 *       на чужой узел либо за край перечня
	 */
	const uint32_t created = this->locate(path, kind_t::PAIR);
	/**
	 * Если запись заведённой пары не найдена
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: запись заводится строкою
	 *          выше и тем же составным именем ищется - разойтись им нечем. Замерено
	 *          покрытием: заход не задет ни набором проверок, ни ворошителем, ни
	 *          корпусом наречий
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа - расхождение
	 *       заведения с поиском выдало бы указатель на узел чужой
	 */
	if(created == NO_RECORD){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::INTERNAL);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим пустой указатель узла значения
		return nullptr;
	}
	// Выводим узел значения заводимой пары
	return &this->_nodes.at(this->_records.at(created).node);
}
