/**
 * @brief Метод объявления таблицы
 *
 * @param path составное имя объявляемой таблицы
 * @return     результат выполнения операции
 *
 */
bool awh::codec::toml::Document::create(const vector <string_view> & path) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	// Собираемая длина составного имени объявляемой таблицы
	size_t length = 0;
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : path)
		// Выполняем учёт длины очередной составной части имени
		length += part.length();
	/**
	 * Если составное имя в хранилище знаков не вмещается
	 *
	 * @note Проверка та же, что и у заведения пары: отрезок хранилища задан смещением
	 *       в четыре октета, и заведение имени сверх того переполнило бы его молча -
	 *       дерево выдавало бы содержимое, взятое не оттуда
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: отрезок хранилища задан
	 *          смещением в четыре октета, и переполнить его нечем иначе, как деревом
	 *          свыше четырёх миллиардов знаков - объёмом, какого ни набор проверок, ни
	 *          ворошитель, ни корпус наречий не подают. Замерено покрытием: заход не
	 *          задет ни разу
	 *
	 * @note Сносу заход не подлежит: без него смещение переполнилось бы молча, и дерево
	 *       выдавало бы содержимое, взятое не оттуда
	 */
	if(!this->spacious(length))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если составное имя к записи непригодно
	 */
	if(!this->acceptable(path, true))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если таблица с таким именем уже объявлена
	 */
	if(this->locate(path, kind_t::TABLE) != NO_RECORD)
		// Выводим положительный результат выполнения операции
		return true;
	// Собираемая запись объявления таблицы
	record_t record;
	// Запоминаем вид собираемой записи
	record.kind = kind_t::TABLE;
	// Выполняем добавление имени таблицы к перечню частей имён
	record.path = this->keep(path);
	// Выполняем добавление записи объявления таблицы
	this->_records.push_back(record);
	// Выполняем наращивание указателей поиска объявленной таблицей
	this->grow();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод установки строкового значения пары
 *
 * @param path    составное имя устанавливаемой пары
 * @param value   устанавливаемое значение пары
 * @param quoting запись строкового значения
 * @return        результат выполнения операции
 *
 */
/**
 * @brief Метод снятия значения по пути
 *
 * @details Ход этот общий у всех семи кодеков рамки: снос по пути, строкою заданному.
 *          Сносится значение ЛЮБОГО вида - и пара, и таблица, - тогда как `erase(перечень)`
 *          снимает пару, а `remove(перечень)` таблицу. Имена эти в языке суть синонимы, и
 *          потребитель угадать по ним, который что делает, не может вовсе
 *
 * @note Снятие ведётся через копию дерева: настройки снимаются владеющим значением,
 *       правятся по пути и переносятся обратно. Целость правки важнее цены копии - отказ
 *       посреди переноса оставил бы дерево с частью её
 *
 * @param path путь до снимаемого значения
 * @return     признак успешного снятия значения
 *
 */
bool awh::codec::toml::Document::prune(const string & path) noexcept {
	// Получаем путь без ведущей косой черты
	const string route((!path.empty() && (path.front() == '/')) ? path.substr(1) : path);
	/**
	 * Если путь пуст вовсе
	 *
	 * @note Снос корня ведётся `clear()`, а не сносом по пути: `erase` снимает ЧАСТЬ, а
	 *       `clear` опустошает целое. Правило это согласовано с владельцами прочих
	 *       кодеков рамки 03.09.2026
	 */
	if(route.empty()){
		// Запоминаем код отказа снятия значения
		this->_error = error_t::INVALID_KEY;
		// Выводим признак неудачного снятия значения
		return false;
	}
	// Разыскиваем последний разделитель кусков пути
	const size_t separator = route.rfind('/');
	// Получаем имя снимаемого значения
	const string name((separator == string::npos) ? route : route.substr(separator + 1));
	// Снимаем настройки владеющим значением
	::awh::codec::toml::Value whole(* this);
	// Получаем вместилище, снимаемому значению принадлежащее
	::awh::codec::toml::Value & owner = ((separator == string::npos) ?
	 whole : whole.place(route.substr(0, separator)));
	/**
	 * Если снять значение с вместилища не удалось
	 */
	if(!owner.valid() || !owner.erase(name)){
		// Запоминаем код отказа снятия значения
		this->_error = error_t::INVALID_KEY;
		// Выводим признак неудачного снятия значения
		return false;
	}
	// Выполняем очистку прежнего дерева настроек
	this->clear();
	// Выводим результат переноса правленого дерева обратно в настройки
	return whole.graft(* this, vector <string_view> ());
}
/**
 * @brief Метод постановки владеющего значения по пути
 *
 * @details Ход этот есть тот же перенос, какой ведёт `Value::graft()`, и зовётся он
 *          вторым концом: у дерева, а не у значения. Заведены ОБА конца намеренно - у
 *          одних кодеков рамки правка стояла ходом значения, у других ходом документа,
 *          и потребитель, два кодека рядом читающий, разыскивал ход не там, где тот
 *          лежал. Переименованием расхождение это не снимается вовсе: имя вышло бы одно,
 *          а порядок слов обратный
 *
 * @note Путь берётся строкою по описанию RFC 6901 и разбирается тем же способом, каким
 *       разбирает его `Value::at()`: ведущая косая черта отбрасывается, а куски делятся
 *       по ней же. Перечень кусков, какой принимают прочие постановки, тут не годится -
 *       строковый вид пути един у всех кодеков рамки
 *
 * @param path  путь постановки значения
 * @param value ставимое владеющее значение
 * @return      признак успешной постановки значения
 *
 */
bool awh::codec::toml::Document::graft(const string_view path, const ::awh::codec::toml::Value & value) noexcept {
	// Получаем путь без ведущей косой черты
	const string route((!path.empty() && (path.front() == '/')) ? string(path.substr(1)) : string(path));
	// Собираемый перечень кусков пути
	vector <string_view> parts;
	/**
	 * Если путь не пуст вовсе
	 */
	if(!route.empty()){
		// Смещение начала очередного куска пути
		size_t start = 0;
		/**
		 * Выполняем перебор всех кусков пути
		 */
		while(start <= route.size()){
			// Разыскиваем разделитель кусков пути
			const size_t separator = route.find('/', start);
			// Выполняем добавление очередного куска пути
			parts.push_back(string_view(route.data() + start,
			 ((separator == string::npos) ? route.size() : separator) - start));
			/**
			 * Если разделителя в пути больше нет
			 */
			if(separator == string::npos)
				// Выходим из перебора кусков пути
				break;
			// Выполняем переход к следующему куску пути
			start = (separator + 1);
		}
	}
	// Выводим результат переноса владеющего значения в дерево настроек
	return value.graft(* this, parts);
}
bool awh::codec::toml::Document::set(const vector <string_view> & path, const string_view value, const string_t quoting) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	/**
	 * Если значение в хранилище знаков не вмещается
	 *
	 * @note Проверка ведётся прежде правки: узел, заведённый под значение, которое не
	 *       записать, остался бы в дереве пустым
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: отрезок хранилища задан
	 *          смещением в четыре октета, и переполнить его нечем иначе, как деревом
	 *          свыше четырёх миллиардов знаков - объёмом, какого ни набор проверок, ни
	 *          ворошитель, ни корпус наречий не подают. Замерено покрытием: заход не
	 *          задет ни разу
	 *
	 * @note Сносу заход не подлежит: без него смещение переполнилось бы молча, и дерево
	 *       выдавало бы содержимое, взятое не оттуда
	 */
	if(!this->spacious(value.length()))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем получение узла значения для правки
	node_t * node = this->reach(path);
	/**
	 * Если узел значения для правки не получен
	 *
	 * @note Значение переносится в хранилище знаков лишь по получении узла: перенос
	 *       его прежде наращивал бы хранилище всякой отвергнутой правкой
	 */
	if(node == nullptr)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление строкового значения к хранилищу знаков
	const span_t text = this->add(value);
	// Запоминаем тип устанавливаемого значения
	node->type = type_t::STRING;
	// Запоминаем ограду устанавливаемого строкового значения
	node->quoting = quoting;
	// Запоминаем место строкового значения в хранилище знаков
	node->text = text;
	// Выводим положительный результат выполнения операции
	return true;
}
