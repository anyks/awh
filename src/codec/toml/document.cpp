/**
 * @brief Метод установки отметки времени значением пары
 *
 * @param path  составное имя устанавливаемой пары
 * @param value устанавливаемая отметка времени
 * @param type  тип устанавливаемой отметки времени
 * @return      результат выполнения операции
 *
 */
bool awh::codec::toml::Document::set(const vector <string_view> & path, const stamp_t & value, const type_t type) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	/**
	 * Если устанавливаемый тип отметкой времени не является
	 */
	if((type != type_t::OFFSET_DATETIME) && (type != type_t::LOCAL_DATETIME) &&
	   (type != type_t::LOCAL_DATE) && (type != type_t::LOCAL_TIME)){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::INVALID_DATETIME);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Признак того, что устанавливаемая отметка несёт дату
	const bool dated = ((type == type_t::OFFSET_DATETIME) ||
	 (type == type_t::LOCAL_DATETIME) || (type == type_t::LOCAL_DATE));
	/**
	 * Если дата устанавливаемой отметки в календаре не существует
	 *
	 * @note Правка отвергается здесь, а не при записи собранного дерева: дерево,
	 *       принявшее дату «2026-02-31», собрало бы текст, который свой же разбор
	 *       отвергает, и узнал бы о том потребитель много позже правки
	 */
	if(dated && ((value.date.year > 9999) ||
	   !toml::calendar(value.date.year, value.date.month, value.date.day))){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::INVALID_DATETIME);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если время устанавливаемой отметки за пределы суток выходит
	 *
	 * @note Секунда шестидесятая дозволена описанием: ею записывается секунда
	 *       координации, добавляемая к последней минуте суток
	 */
	if(((type == type_t::OFFSET_DATETIME) || (type == type_t::LOCAL_DATETIME) || (type == type_t::LOCAL_TIME)) &&
	   ((value.time.hour > 23) || (value.time.minute > 59) || (value.time.second > 60) ||
	    (value.time.nanosecond > 999999999))){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::INVALID_DATETIME);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем получение узла значения для правки
	node_t * node = this->reach(path);
	/**
	 * Если узел значения для правки не получен
	 */
	if(node == nullptr)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем тип устанавливаемого значения
	node->type = type;
	// Запоминаем устанавливаемую отметку времени
	node->stamp = value;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод учёта узла значения и всего вложенного в него мусором правки
 *
 * @details Узел, содержимое которого правкою снимается, вложенные свои узлы в перечне
 * оставляет: держатся они порядковыми номерами, и снять их на месте нельзя - номера
 * всех прочих сдвинулись бы. Уплотнение перечня их соберёт, а счёт этот ему порог задаёт
 *
 * @param node порядковый номер узла значения, в мусор обращаемого
 *
 */
void awh::codec::toml::Document::discard(const uint32_t node) noexcept {
	/**
	 * Если порядковый номер узла значения за пределами перечня
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: учёт мусора зовётся лишь
	 *          с номером узла, из самого дерева взятого. Замерено покрытием: заход не
	 *          задет ни разу
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа - номер, деревом
	 *       не выданный, уводил бы учёт за край перечня узлов
	 */
	if(static_cast <size_t> (node) >= this->_nodes.size())
		// Выходим из функции учёта мусора правки
		return;
	// Выполняем учёт самого узла значения
	this->_garbage++;
	/**
	 * Выполняем перебор всех вложенных узлов значения
	 *
	 * @note Обход ведётся вглубь: мусором становится всё поддерево, а не одна лишь
	 *       его вершина
	 */
	for(size_t i = 0; i < this->_nodes.at(node).items.size(); i++)
		// Выполняем учёт очередного вложенного узла значения
		this->discard(this->_nodes.at(node).items.at(i));
}
/**
 * @brief Метод получения порядкового номера узла значения по составному имени
 *
 * @details Имя разбирается тем же построением, каким разбирает его поиск значения:
 * начало его именует пару, а остаток ведёт внутрь составного значения - порядковым
 * номером в перечень, именем ключа во встроенную таблицу
 *
 * @note Выдаётся порядковый номер, а не указатель: правка перечня узлов наращивает
 *       его, и указатель, выданный до того, повис бы
 *
 * @param path составное имя искомого места
 * @return     порядковый номер найденного узла значения либо признак отсутствия
 *
 */
uint32_t awh::codec::toml::Document::dive(const vector <string_view> & path) noexcept {
	/**
	 * Если дерево засорено мусором правки
	 *
	 * @note Уплотнение ведётся прежде поиска: оно перечень узлов переносит, и номер,
	 *       выданный до него, указывал бы на узел чужой
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: заведение узла зовётся
	 *          лишь изнутри правки, а всякая правка спрашивает уплотнение у себя
	 *          прежде - засорённое дерево до заведения уже не доходит. Замерено щупом
	 *          на четырёхстах кругах заведения, дописывания и сноса: заход не задет
	 *          ни разу, а уплотнение отработало у правки
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа - путь правки,
	 *       впредь заведённый, без него выдавал бы номер узла, уплотнением снесённого
	 */
	if(this->cluttered())
		// Выполняем перестроение указателей поиска вместе с уплотнением дерева
		this->reindex();
	// Выполняем поиск узла значения по составному имени
	const node_t * node = this->seek(path);
	/**
	 * Если узел значения по составному имени не найден
	 */
	if(node == nullptr)
		// Выводим признак отсутствия узла значения
		return NO_RECORD;
	// Выводим порядковый номер найденного узла значения
	return static_cast <uint32_t> (node - this->_nodes.data());
}
/**
 * @brief Метод объявления составного значения пары
 *
 * @param path  составное имя объявляемого места
 * @param table признак объявления встроенной таблицы заместо перечня
 * @return      результат выполнения операции
 *
 */
bool awh::codec::toml::Document::arrange(const vector <string_view> & path, const bool table) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	// Выполняем поиск места объявления среди значений, уже деревом несомых
	uint32_t target = this->dive(path);
	/**
	 * Если места объявления среди имеющихся значений нет
	 *
	 * @note Заход этот берёт пару: имя, внутрь составного значения не ведущее, есть
	 *       имя пары, и заводится она тем же способом, каким заводит её установка
	 */
	if(target == NO_RECORD){
		// Выполняем получение узла значения для правки
		node_t * node = this->reach(path);
		/**
		 * Если узел значения для правки не получен
		 */
		if(node == nullptr)
			// Выводим отрицательный результат выполнения операции
			return false;
		// Запоминаем порядковый номер полученного узла значения
		target = static_cast <uint32_t> (node - this->_nodes.data());
	/**
	 * Если место объявления найдено среди имеющихся значений
	 */
	} else {
		/**
		 * Выполняем перебор всех вложенных узлов правимого значения
		 */
		for(size_t i = 0; i < this->_nodes.at(target).items.size(); i++)
			// Выполняем учёт вложенного узла прежнего значения, в мусор обращённого
			this->discard(this->_nodes.at(target).items.at(i));
	}
	// Получаем узел объявляемого составного значения
	node_t & node = this->_nodes.at(target);
	// Запоминаем тип объявляемого составного значения
	node.type = (table ? type_t::TABLE : type_t::ARRAY);
	// Выполняем очистку вложенных узлов прежнего значения
	node.items.clear();
	// Выполняем очистку составных имён пар прежнего значения
	node.names.clear();
	// Выполняем очистку примечаний прежнего значения
	node.remarks.clear();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод добавления значения к перечню
 *
 * @param path  составное имя перечня
 * @param value добавляемое значение перечня
 * @return      результат выполнения операции
 *
 */
bool awh::codec::toml::Document::push(const vector <string_view> & path, const content_t & value) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	/**
	 * Если значение в хранилище знаков не вмещается
	 *
	 * @note Проверка ведётся прежде правки: узел, заведённый под значение, которое не
	 *       записать, остался бы в перечне пустым
	 *
	 * @warning Заход этот НЕДОСТИЖИМ, покуда держится условие: отрезок хранилища задан
	 *          смещением в четыре октета, и переполнить его нечем иначе, как деревом
	 *          свыше четырёх миллиардов знаков - объёмом, какого ни набор проверок, ни
	 *          ворошитель, ни корпус наречий не подают. Замерено покрытием: заход не
	 *          задет ни разу
	 *
	 * @note Сносу заход не подлежит: без него смещение переполнилось бы молча, и дерево
	 *       выдавало бы содержимое, взятое не оттуда
	 */
	if(!this->spacious(value.text.length()))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем поиск узла перечня по составному имени
	const uint32_t target = this->dive(path);
	/**
	 * Если узел по составному имени не найден либо перечнем не является
	 */
	if((target == NO_RECORD) || (this->_nodes.at(target).type != type_t::ARRAY))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем заведение узла добавляемого значения
	const uint32_t item = this->reserve();
	// Выполняем перенос добавляемого значения в заведённый узел
	this->assign(item, value);
	// Выполняем добавление заведённого узла к значениям перечня
	this->_nodes.at(target).items.push_back(item);
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод добавления пары к встроенной таблице
 *
 * @param path  составное имя встроенной таблицы
 * @param name  составное имя добавляемой пары
 * @param value значение добавляемой пары
 * @return      результат выполнения операции
 *
 */
bool awh::codec::toml::Document::put(const vector <string_view> & path, const vector <string_view> & name, const content_t & value) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	// Собираемая длина составного имени добавляемой пары
	size_t length = value.text.length();
	/**
	 * Выполняем перебор всех составных частей имени
	 */
	for(auto & part : name)
		// Выполняем учёт длины очередной составной части имени
		length += part.length();
	/**
	 * Если имя вместе со значением в хранилище знаков не вмещаются
	 */
	if(name.empty() || !this->spacious(length))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем поиск узла встроенной таблицы по составному имени
	const uint32_t target = this->dive(path);
	/**
	 * Если узел по составному имени не найден либо встроенной таблицей не является
	 */
	if((target == NO_RECORD) || (this->_nodes.at(target).type != type_t::TABLE))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление имени добавляемой пары к перечню частей имён
	const span_t key = this->keep(name);
	// Выполняем заведение узла значения добавляемой пары
	const uint32_t item = this->reserve();
	// Выполняем перенос значения добавляемой пары в заведённый узел
	this->assign(item, value);
	// Выполняем добавление имени пары к именам пар встроенной таблицы
	this->_nodes.at(target).names.push_back(key);
	// Выполняем добавление узла значения к парам встроенной таблицы
	this->_nodes.at(target).items.push_back(item);
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод удаления пары
 *
 * @param path составное имя удаляемой пары
 * @return     результат выполнения операции
 *
 */
bool awh::codec::toml::Document::erase(const vector <string_view> & path) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	// Выполняем поиск записи пары по составному имени
	const uint32_t record = this->locate(path, kind_t::PAIR);
	/**
	 * Если запись пары по составному имени не найдена
	 *
	 * @note Отказ этот принадлежит отсутствию пары, а не построению имени: имя может
	 *       быть составлено верно, а пары с ним в дереве не быть. Прежде здесь
	 *       отвечалось кодом ошибочного построения имени, и потребитель искал изъян
	 *       в имени, какого там нет
	 */
	if(record == NO_RECORD){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::UNKNOWN_KEY);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем снятие записи пары пометкой удаления
	this->_records.at(record).kind = kind_t::NONE;
	// Выполняем учёт записи, пометкой удаления снятой
	this->_garbage++;
	/**
	 * Если следом за парой записано примечание, дописанное к её строке
	 *
	 * @note Примечание это писано к удаляемой паре, и оставить его значило бы
	 *       оставить пояснение к тому, чего в файле более нет
	 */
	if((static_cast <size_t> (record + 1) < this->_records.size()) &&
	   (this->_records.at(record + 1).kind == kind_t::COMMENT) && this->_records.at(record + 1).trailing){
		// Выполняем снятие записи примечания пометкой удаления
		this->_records.at(record + 1).kind = kind_t::NONE;
		// Выполняем учёт записи, пометкой удаления снятой
		this->_garbage++;
	}
	// Выполняем перестроение указателей поиска
	this->reindex();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод удаления таблицы
 *
 * @param path составное имя удаляемой таблицы
 * @return     результат выполнения операции
 *
 */
bool awh::codec::toml::Document::remove(const vector <string_view> & path) noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Код отвечает за ПОСЛЕДНЮЮ работу над деревом, а не за один разбор: переживи
	 *       он удачную работу следом, потребитель судил бы о ней по причине, к ней
	 *       отношения не имеющей. Вместе с кодом сбрасывается и положение ошибки
	 */
	this->fault(error_t::NONE);
	// Выполняем поиск записи объявления таблицы по составному имени
	const uint32_t record = this->locate(path, kind_t::TABLE);
	/**
	 * Если запись объявления таблицы по составному имени не найдена
	 *
	 * @note Отказ принадлежит отсутствию таблицы, а не построению её объявления
	 */
	if(record == NO_RECORD){
		// Запоминаем код ошибки правки дерева настроек
		this->fault(error_t::UNKNOWN_TABLE);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем снятие записи объявления таблицы пометкой удаления
	this->_records.at(record).kind = kind_t::NONE;
	// Выполняем учёт записи, пометкой удаления снятой
	this->_garbage++;
	/**
	 * Выполняем перебор всех записей удаляемой таблицы
	 */
	for(size_t i = (record + 1); i < this->_records.size(); i++){
		// Получаем вид очередной записи дерева настроек
		const kind_t kind = this->_records.at(i).kind;
		/**
		 * Если записью является объявление очередной таблицы
		 */
		if((kind == kind_t::TABLE) || (kind == kind_t::ARRAY_TABLE))
			// Выполняем прекращение удаления записей таблицы
			break;
		// Выполняем снятие записи таблицы пометкой удаления
		this->_records.at(i).kind = kind_t::NONE;
		// Выполняем учёт записи, пометкой удаления снятой
		this->_garbage++;
	}
	// Выполняем перестроение указателей поиска
	this->reindex();
	// Выводим положительный результат выполнения операции
	return true;
}
