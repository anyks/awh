/**
 * @brief Метод проверки дерева на отсутствие записей
 *
 * @return результат проверки
 *
 */
bool awh::codec::toml::Document::empty() const noexcept {
	/**
	 * Выполняем перебор всех записей дерева настроек
	 */
	for(auto & record : this->_records){
		/**
		 * Если запись пометкой удаления не снята
		 */
		if(record.kind != kind_t::NONE)
			// Выводим отрицательный результат проверки
			return false;
	}
	// Выводим положительный результат проверки
	return true;
}
/**
 * @brief Метод получения объёма памяти, деревом занимаемого
 *
 * @return объём памяти в октетах
 *
 */
size_t awh::codec::toml::Document::footprint() const noexcept {
	// Собираемый объём памяти, деревом занимаемый
	size_t result = 0;
	// Выполняем учёт памяти хранилища знаков
	result += this->_store.capacity();
	// Выполняем учёт памяти перечня записей дерева настроек
	result += (this->_records.capacity() * sizeof(record_t));
	// Выполняем учёт памяти перечня составных частей имён
	result += (this->_keys.capacity() * sizeof(key_t));
	// Выполняем учёт памяти перечня узлов значений
	result += (this->_nodes.capacity() * sizeof(node_t));
	/**
	 * Выполняем перебор всех узлов значений дерева настроек
	 */
	for(auto & node : this->_nodes){
		// Выполняем учёт памяти вложенных узлов значения
		result += (node.items.capacity() * sizeof(uint32_t));
		// Выполняем учёт памяти составных имён пар встроенной таблицы
		result += (node.names.capacity() * sizeof(span_t));
		// Выполняем учёт памяти примечаний перечня значений
		result += (node.remarks.capacity() * sizeof(remark_t));
	}
	// Выводим объём памяти, деревом занимаемый
	return result;
}
/**
 * @brief Метод освобождения дерева настроек
 *
 */
void awh::codec::toml::Document::clear() noexcept {
	// Выполняем сброс кода ошибки последней операции
	this->_error = error_t::NONE;
	// Выполняем сброс положения обнаруженной ошибки
	this->_errorLocation = location_t();
	// Выполняем очистку хранилища знаков
	this->_store.clear();
	// Выполняем очистку перечня записей дерева
	this->_records.clear();
	// Выполняем очистку перечня составных частей имён
	this->_keys.clear();
	// Выполняем очистку перечня узлов значений
	this->_nodes.clear();
	// Выполняем очистку указателя записей
	this->_index.clear();
	// Выполняем очистку порядка объявления дочерних имён
	this->_children.clear();
	// Выполняем очистку имён таблиц, заведённых составным именем ключа
	this->_dotted.clear();
	/**
	 * Выполняем сброс состояния обхода записей дерева
	 *
	 * @note Состояние это несёт имена, уже объявленные обходом, и заведение имени
	 *       заново им отсекается: без сброса дерево, собранное правками после
	 *       освобождения, теряло бы дочерние имена, совпавшие с именами прежнего
	 */
	this->_traversal.reset();
	// Выполняем сброс количества записей и узлов, правкой в мусор обращённых
	this->_garbage = 0;
	// Выполняем сброс длины хранилища знаков, снятой уплотнением
	this->_compacted = 0;
}
/**
 * @brief Метод записи дерева обратно в текст настроек
 *
 * @param settings настройки записи текста настроек
 * @return         собранный текст настроек
 *
 */
string awh::codec::toml::Document::text(const writer_t::settings_t & settings) const noexcept {
	/**
	 * Выполняем сброс кода отказа прежней работы
	 *
	 * @note Сборка текста отвечает за себя наравне с работами над деревом: код её
	 *       обязан говорить о ней, а не о прежнем разборе
	 */
	this->fault(error_t::NONE);
	// Объект записи текста настроек
	writer_t writer(this->_log, settings);
	/**
	 * Собираемое составное имя очередной записи
	 *
	 * @note Буфер заведён единожды на весь обход: имя записи живёт лишь до её
	 *       записи, и заводить его заново на каждую запись значило бы просить
	 *       памяти столько раз, сколько записей в дереве
	 */
	vector <part_t> path;
	/**
	 * Выполняем перебор всех записей дерева настроек
	 */
	for(auto & record : this->_records){
		// Признак успешной записи очередной записи дерева
		bool result = true;
		/**
		 * Выполняем выбор вида записи дерева настроек
		 */
		switch(static_cast <uint8_t> (record.kind)){
			// Если запись снята пометкой удаления
			case static_cast <uint8_t> (kind_t::NONE): continue;
			// Если записью является пустая строка
			case static_cast <uint8_t> (kind_t::BLANK): {
				// Выполняем запись пустой строки
				result = writer.blank();
			} break;
			// Если записью является примечание
			case static_cast <uint8_t> (kind_t::COMMENT): {
				/**
				 * Если примечание дописано к готовой строке
				 */
				if(record.trailing)
					// Выполняем дописывание примечания к записанной строке
					result = writer.trailing(this->get(record.text));
				// Выполняем запись примечания отдельной строкой
				else result = writer.comment(this->get(record.text));
			} break;
			// Если записью является объявление таблицы
			case static_cast <uint8_t> (kind_t::TABLE):
			// Если записью является объявление очередной таблицы набора таблиц
			case static_cast <uint8_t> (kind_t::ARRAY_TABLE):
			// Если записью является пара
			case static_cast <uint8_t> (kind_t::PAIR): {
				// Выполняем подготовку буфера составного имени записи
				path.clear();
				// Выполняем отведение места под составные части имени записи
				path.resize(record.path.length);
				/**
				 * Выполняем перебор всех составных частей имени записи
				 */
				for(uint32_t i = 0; i < record.path.length; i++){
					// Получаем очередную составную часть имени записи
					const key_t & key = this->_keys.at(record.path.offset + i);
					// Запоминаем имя составной части
					path.at(i).name = this->get(key.name);
					// Запоминаем запись имени составной части
					path.at(i).naming = key.naming;
				}
				/**
				 * Если записью является объявление таблицы
				 */
				if(record.kind == kind_t::TABLE)
					// Выполняем запись объявления таблицы
					result = writer.table(path);
				/**
				 * Если записью является объявление очередной таблицы набора таблиц
				 */
				else if(record.kind == kind_t::ARRAY_TABLE)
					// Выполняем запись объявления очередной таблицы набора таблиц
					result = writer.arrayTable(path);
				/**
				 * Если записью является пара
				 */
				else result = (writer.key(path) && this->compose(writer, record.node));
			} break;
		}
		/**
		 * Если записать очередную запись дерева не удалось
		 */
		if(!result){
			/**
			 * Если код отказа дерево себе ещё не назначило
			 *
			 * @warning Отказ вправе прийти и от записи, и от самого дерева: «compose»
			 *          поверяет вид значения сам, код себе назначает и в журнал о том
			 *          сообщает. Перезапись кода кодом записи стирала причину, дереву
			 *          известную: запись отдавала пустоту вместе с кодом «отказа нет», и
			 *          потребитель оставался с пустым текстом без причины его
			 *
			 * @note Путём открытым заход этот ныне НЕДОСТИЖИМ: узел вида неопределённого
			 *       заводил один лишь перенос перечня с дырою, а он отвечает теперь
			 *       отказом. Достижим он был до правки той, чем и обнаружился; оставлен
			 *       заставою последнего рубежа и проверкою не закрыт намеренно - проверка,
			 *       захода не достигающая, проходила бы и при снятом заходе
			 */
			if(this->_error == error_t::NONE)
				// Запоминаем код ошибки записи дерева настроек
				this->_error = writer.error();
			// Выводим пустой собранный текст настроек
			return string();
		}
	}
	// Выводим собранный текст настроек
	return writer.text();
}
