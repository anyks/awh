/**
 * @brief Метод проверки знака на допустимость в тексте настроек
 *
 * @param code кодовое значение проверяемого знака
 * @return     результат проверки
 *
 */
bool awh::codec::toml::isChar(const uint32_t code) noexcept {
	/**
	 * Если знаком является горизонтальная табуляция, перевод строки либо возврат каретки
	 */
	if((code == 0x09) || (code == 0x0A) || (code == 0x0D))
		// Выводим положительный результат проверки знака
		return true;
	/**
	 * Если знак принадлежит управляющим знакам области C0
	 */
	if(code < 0x20)
		// Выводим отрицательный результат проверки знака
		return false;
	/**
	 * Если знаком является забой
	 *
	 * @note Область C1 при этом дозволена намеренно: описание относит к запрещённым
	 *       знакам лишь область C0 вместе с забоем, а знаки области C1 законно
	 *       встречаются в строковых значениях. Отвергать их значило бы отвергать
	 *       законный текст - в отличие от записи INI, где договора нет вовсе и выбор
	 *       строгости остаётся за разбирающим
	 */
	if(code == 0x7F)
		// Выводим отрицательный результат проверки знака
		return false;
	/**
	 * Если кодовое значение принадлежит суррогатным либо выходит за пределы Юникода
	 */
	if(((code >= 0xD800) && (code <= 0xDFFF)) || (code > MAX_CODEPOINT))
		// Выводим отрицательный результат проверки знака
		return false;
	// Выводим положительный результат проверки знака
	return true;
}
/**
 * @brief Метод чтения кодового значения из текста в кодировке UTF-8
 *
 * @param buffer буфер исходного текста в кодировке UTF-8
 * @param size   размер буфера исходного текста
 * @param length длина прочитанной последовательности в байтах
 * @return       прочитанное кодовое значение знака
 *
 */
uint32_t awh::codec::toml::decode(const char * buffer, const size_t size, size_t & length) noexcept {
	// Выполняем сброс длины прочитанной последовательности
	length = 0;
	/**
	 * Если исходный текст не передан
	 */
	if((buffer == nullptr) || (size == 0))
		// Выводим обозначение ошибочного кодового значения
		return INVALID_CODEPOINT;
	// Кодовое значение прочитанного знака
	uint32_t code = 0;
	/**
	 * Если разобрать очередную последовательность не удалось
	 *
	 * @note Оборванная последовательность длины за собой не оставляет: чтение по
	 *       кускам обязано повторить её целиком, когда придёт продолжение
	 */
	if(toml::inspect(string_view(buffer, size), 0, code, length) != utf8_t::VALID)
		// Выводим обозначение ошибочного кодового значения
		return INVALID_CODEPOINT;
	// Выводим прочитанное кодовое значение знака
	return code;
}
/**
 * @brief Метод записи кодового значения в кодировке UTF-8
 *
 * @param code   записываемое кодовое значение знака
 * @param result текст, к которому дописывается знак
 * @return       результат выполнения операции
 *
 */
bool awh::codec::toml::encode(const uint32_t code, string & result) noexcept {
	/**
	 * Если кодовое значение принадлежит суррогатным либо выходит за пределы Юникода
	 */
	if(((code >= 0xD800) && (code <= 0xDFFF)) || (code > MAX_CODEPOINT))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если знак записывается одним байтом
	 */
	if(code < 0x80)
		// Выполняем добавление знака к тексту
		result.push_back(static_cast <char> (code));
	/**
	 * Если знак записывается двумя байтами
	 */
	else if(code < 0x800) {
		// Выполняем добавление первого байта последовательности
		result.push_back(static_cast <char> (0xC0 | (code >> 6)));
		// Выполняем добавление продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	/**
	 * Если знак записывается тремя байтами
	 */
	} else if(code < 0x10000) {
		// Выполняем добавление первого байта последовательности
		result.push_back(static_cast <char> (0xE0 | (code >> 12)));
		// Выполняем добавление первого продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
		// Выполняем добавление второго продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	/**
	 * Если знак записывается четырьмя байтами
	 */
	} else {
		// Выполняем добавление первого байта последовательности
		result.push_back(static_cast <char> (0xF0 | (code >> 18)));
		// Выполняем добавление первого продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | ((code >> 12) & 0x3F)));
		// Выполняем добавление второго продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
		// Выполняем добавление третьего продолжающего байта последовательности
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод определения кодировки по метке порядка байтов
 *
 * @return признак того, что определение кодировки завершено
 *
 */
bool awh::codec::toml::Decoder::sniff() noexcept {
	// Получаем удержанные байты начала текста в беззнаковом виде
	const uint8_t * data = reinterpret_cast <const uint8_t *> (this->_prolog.data());
	// Получаем количество удержанных байтов начала текста
	const size_t size = this->_prolog.size();
	// Количество байтов метки порядка байтов
	size_t length = 0;
	// Кодировка, определённая по метке порядка байтов
	encoding_t encoding = encoding_t::NONE;
	/**
	 * Если началом текста является метка порядка байтов кодировки UTF-8
	 */
	if((size >= 3) && (data[0] == 0xEF) && (data[1] == 0xBB) && (data[2] == 0xBF)){
		// Запоминаем определённую кодировку исходного текста
		encoding = encoding_t::UTF8;
		// Запоминаем количество байтов метки порядка байтов
		length = 3;
	/**
	 * Если началом текста является метка порядка байтов кодировки UTF-32
	 *
	 * @note Кодировка эта не поддерживается, но метка её начинается с метки UTF-16,
	 *       и различить их можно лишь по следующим за нею байтам. Без такой проверки
	 *       текст в UTF-32 разбирался бы как UTF-16 с пустыми знаками между настоящими
	 */
	} else if((size >= 4) && (((data[0] == 0x00) && (data[1] == 0x00) && (data[2] == 0xFE) && (data[3] == 0xFF)) ||
	                          ((data[0] == 0xFF) && (data[1] == 0xFE) && (data[2] == 0x00) && (data[3] == 0x00)))) {
		/**
		 * Если кодировка извне не навязана
		 */
		if(!this->_forced){
			// Запоминаем код ошибки приведения
			this->_error = error_t::UNSUPPORTED_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак незавершённого определения кодировки
			return false;
		}
	/**
	 * Если началом текста является метка порядка байтов кодировки UTF-16 с прямым порядком
	 */
	} else if((size >= 2) && (data[0] == 0xFE) && (data[1] == 0xFF)) {
		// Запоминаем определённую кодировку исходного текста
		encoding = encoding_t::UTF16BE;
		// Запоминаем количество байтов метки порядка байтов
		length = 2;
	/**
	 * Если началом текста является метка порядка байтов кодировки UTF-16 с обратным порядком
	 */
	} else if((size >= 2) && (data[0] == 0xFF) && (data[1] == 0xFE)) {
		// Запоминаем определённую кодировку исходного текста
		encoding = encoding_t::UTF16LE;
		// Запоминаем количество байтов метки порядка байтов
		length = 2;
	}
	/**
	 * Если метка порядка байтов в начале текста обнаружена
	 */
	if(encoding != encoding_t::NONE){
		// Запоминаем признак обнаружения метки порядка байтов
		this->_signed = true;
		/**
		 * Если кодировка извне не навязана
		 */
		if(!this->_forced)
			// Запоминаем определённую кодировку исходного текста
			this->_encoding = encoding;
		/**
		 * Метку порядка байтов снимаем лишь тогда, когда она отвечает принятой кодировке
		 *
		 * @note Метка чужой кодировки при навязанной извне частью текста остаётся
		 *       намеренно: снятие её означало бы доверие к метке, которой вызывающий
		 *       уже отказал, навязав кодировку
		 */
		if(this->_encoding == encoding)
			// Выполняем снятие метки порядка байтов с начала текста
			this->_prolog.erase(0, length);
	/**
	 * Если метка порядка байтов в начале текста отсутствует
	 */
	} else if(!this->_forced)
		// Запоминаем кодировку исходного текста, принятую по умолчанию
		this->_encoding = encoding_t::UTF8;
	// Запоминаем признак того, что метка порядка байтов обработана
	this->_marked = true;
	// Выводим признак завершённого определения кодировки
	return true;
}
/**
 * @brief Метод приведения удержанных байтов к кодировке UTF-8
 *
 * @param buffer буфер приводимых байтов исходного текста
 * @param size   размер буфера приводимых байтов исходного текста
 * @param end    признак того, что приводимые байты являются последними
 * @param result текст, к которому дописывается приведённое
 * @return       результат выполнения операции
 *
 */
bool awh::codec::toml::Decoder::process(const char * buffer, const size_t size, const bool end, string & result) noexcept {
	// Получаем приводимые байты исходного текста в беззнаковом виде
	const uint8_t * data = reinterpret_cast <const uint8_t *> (buffer);
	/**
	 * Определяем кодировку исходного текста
	 */
	switch(static_cast <uint8_t> (this->_encoding)){
		// Если кодировкой является UTF-8
		case static_cast <uint8_t> (encoding_t::UTF8): {
			// Положение разбираемого байта в переданном буфере
			size_t offset = 0;
			/**
			 * Если от предыдущего куска удержана незавершённая последовательность знака
			 */
			if(this->_length > 0){
				// Получаем ожидаемую длину удержанной последовательности знака
				const size_t count = toml::sequence(static_cast <uint8_t> (this->_pending[0]));
				/**
				 * Выполняем добор недостающих байтов последовательности из переданного буфера
				 */
				while((this->_length < count) && (offset < size))
					// Выполняем добавление очередного байта к удержанной последовательности
					this->_pending[this->_length++] = buffer[offset++];
				/**
				 * Если последовательность знака собрать целиком не удалось
				 */
				if(this->_length < count){
					/**
					 * Если переданные байты являются последними
					 */
					if(end){
						// Запоминаем код ошибки приведения
						this->_error = error_t::INVALID_ENCODING;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					// Выводим положительный результат выполнения операции
					return true;
				}
				// Длина прочитанной последовательности знака
				size_t length = 0;
				// Выполняем чтение кодового значения удержанного знака
				const uint32_t code = decode(this->_pending, this->_length, length);
				/**
				 * Если удержанная последовательность знака построена ошибочно
				 */
				if(code == INVALID_CODEPOINT){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если знак в тексте настроек недопустим
				 */
				if(!isChar(code)){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Выполняем добавление удержанного знака к приведённому тексту
				result.append(this->_pending, length);
				// Выполняем сброс количества удержанных байтов
				this->_length = 0;
			}
			/**
			 * Выполняем перебор переданных байтов исходного текста
			 */
			while(offset < size){
				/**
				 * Если знак записан одним байтом
				 */
				if(data[offset] < 0x80){
					/**
					 * Положение начала непрерывного отрезка однобайтовых знаков
					 *
					 * @note Однобайтовые знаки переносятся отрезком, а не поодиночке: в
					 *       тексте настроек их подавляющее большинство, и перенос знака за
					 *       знаком стоил пятой доли всего времени чтения
					 */
					const size_t begin = offset;
					/**
					 * Выполняем перебор непрерывного отрезка однобайтовых знаков
					 */
					while((offset < size) && (data[offset] < 0x80)){
						/**
						 * Если знак в тексте настроек недопустим
						 */
						if(!isChar(data[offset])){
							/**
							 * Выполняем добавление разобранного начала отрезка к приведённому тексту
							 *
							 * @note Отрезок переносится целиком по его окончании, и отказ
							 *       посреди отрезка отбросил бы уже разобранное его начало.
							 *       Разбор выдаёт события по приведённому тексту, и потеря
							 *       начала отрезка отняла бы у него события целых строк
							 */
							result.append(buffer + begin, (offset - begin));
							// Запоминаем код ошибки приведения
							this->_error = error_t::INVALID_CHARACTER;
							// Выполняем вывод сообщения об отказе в лог
							this->report();
							// Выводим отрицательный результат выполнения операции
							return false;
						}
						// Выполняем переход к следующему знаку исходного текста
						offset++;
					}
					// Выполняем добавление отрезка однобайтовых знаков к приведённому тексту
					result.append(buffer + begin, (offset - begin));
					// Выполняем переход к следующему знаку исходного текста
					continue;
				}
				// Получаем ожидаемую длину последовательности знака
				const size_t count = toml::sequence(data[offset]);
				/**
				 * Если первый байт последовательности построен ошибочно
				 *
				 * @note Сторож этот отказа НЕ добавляет: сними его - и тот же отказ выдаст
				 *       чтение кодового значения ниже, ибо негодный ведущий байт даёт
				 *       INVALID_CODEPOINT. Стоит он ради отказа раннего, до чтения, и
				 *       проверкой уличить его снятие нельзя - доказано подменою условия
				 *       на ложь: набор прошёл целиком. Убирать его как мёртвый код не
				 *       следует - путь исполняется, а выдача его совпадает со вторым
				 */
				if(count == 0){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если последовательность знака разорвана границей куска
				 */
				if((offset + count) > size){
					/**
					 * Если переданные байты являются последними
					 */
					if(end){
						// Запоминаем код ошибки приведения
						this->_error = error_t::INVALID_ENCODING;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					/**
					 * Выполняем удержание начатой последовательности до следующего куска
					 */
					while(offset < size)
						// Выполняем добавление очередного байта к удерживаемой последовательности
						this->_pending[this->_length++] = buffer[offset++];
					// Выводим положительный результат выполнения операции
					return true;
				}
				// Длина прочитанной последовательности знака
				size_t length = 0;
				// Выполняем чтение кодового значения знака
				const uint32_t code = decode(buffer + offset, size - offset, length);
				/**
				 * Если последовательность знака построена ошибочно
				 */
				if(code == INVALID_CODEPOINT){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если знак в тексте настроек недопустим
				 */
				if(!isChar(code)){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Выполняем добавление знака к приведённому тексту
				result.append(buffer + offset, length);
				// Выполняем переход к следующему знаку исходного текста
				offset += length;
			}
		} break;
		// Если кодировкой является UTF-16 с обратным порядком байтов
		case static_cast <uint8_t> (encoding_t::UTF16LE):
		// Если кодировкой является UTF-16 с прямым порядком байтов
		case static_cast <uint8_t> (encoding_t::UTF16BE): {
			// Получаем признак обратного порядка байтов кодировки
			const bool reverse = (this->_encoding == encoding_t::UTF16LE);
			// Положение разбираемого байта в переданном буфере
			size_t offset = 0;
			/**
			 * Выполняем перебор пар байтов исходного текста
			 */
			while(true){
				// Значение очередной пары байтов исходного текста
				uint16_t unit = 0;
				/**
				 * Если от предыдущего куска удержан одиночный байт пары
				 */
				if(this->_length == 1){
					/**
					 * Если переданные байты исчерпаны
					 */
					if(offset >= size)
						// Выполняем прекращение перебора пар байтов
						break;
					// Собираем значение пары байтов с учётом порядка байтов кодировки
					unit = (reverse ?
						static_cast <uint16_t> (static_cast <uint8_t> (this->_pending[0]) | (static_cast <uint16_t> (data[offset]) << 8)) :
						static_cast <uint16_t> ((static_cast <uint16_t> (static_cast <uint8_t> (this->_pending[0])) << 8) | data[offset])
					);
					// Выполняем переход к следующему байту исходного текста
					offset++;
					// Выполняем сброс количества удержанных байтов
					this->_length = 0;
				/**
				 * Если пара байтов доступна в переданном буфере целиком
				 */
				} else if((offset + 1) < size) {
					// Собираем значение пары байтов с учётом порядка байтов кодировки
					unit = (reverse ?
						static_cast <uint16_t> (data[offset] | (static_cast <uint16_t> (data[offset + 1]) << 8)) :
						static_cast <uint16_t> ((static_cast <uint16_t> (data[offset]) << 8) | data[offset + 1])
					);
					// Выполняем переход к следующей паре байтов исходного текста
					offset += 2;
				// Если пара байтов в переданном буфере целиком не помещается
				} else break;
				// Кодовое значение прочитанного знака
				uint32_t code = 0;
				/**
				 * Если от предыдущей пары удержана старшая половина суррогатной пары
				 */
				if(this->_surrogate != 0){
					/**
					 * Если прочитанная пара байтов младшей половиной суррогатной пары не является
					 */
					if((unit < 0xDC00) || (unit > 0xDFFF)){
						// Запоминаем код ошибки приведения
						this->_error = error_t::INVALID_ENCODING;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					// Собираем кодовое значение знака из половин суррогатной пары
					code = (0x10000 + ((this->_surrogate - 0xD800) << 10) + (unit - 0xDC00));
					// Выполняем сброс удержанной старшей половины суррогатной пары
					this->_surrogate = 0;
				/**
				 * Если прочитанная пара байтов является старшей половиной суррогатной пары
				 */
				} else if((unit >= 0xD800) && (unit <= 0xDBFF)) {
					// Запоминаем удержанную старшую половину суррогатной пары
					this->_surrogate = unit;
					// Выполняем переход к следующей паре байтов исходного текста
					continue;
				/**
				 * Если прочитанная пара байтов является младшей половиной суррогатной пары
				 *
				 * @note Младшая половина без предшествующей старшей означает испорченный
				 *       текст: подставить вместо неё знак замены значило бы скрыть порчу
				 */
				} else if((unit >= 0xDC00) && (unit <= 0xDFFF)) {
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				// Если прочитанная пара байтов суррогатной не является
				} else code = unit;
				/**
				 * Если знак в тексте настроек недопустим
				 */
				if(!isChar(code)){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если запись знака в кодировке UTF-8 выполнить не удалось
				 */
				if(!encode(code, result)){
					// Запоминаем код ошибки приведения
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
			/**
			 * Если в переданном буфере остался одиночный байт пары
			 */
			if(offset < size){
				// Запоминаем удерживаемый байт пары
				this->_pending[0] = buffer[offset];
				// Запоминаем количество удержанных байтов
				this->_length = 1;
			}
			/**
			 * Если текст оборвался посреди пары байтов либо суррогатной пары
			 */
			if(end && ((this->_length != 0) || (this->_surrogate != 0))){
				// Запоминаем код ошибки приведения
				this->_error = error_t::INVALID_ENCODING;
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим отрицательный результат выполнения операции
				return false;
			}
		} break;
		// Если кодировка исходного текста не определена
		default: {
			// Запоминаем код ошибки приведения
			this->_error = error_t::UNSUPPORTED_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	}
	/**
	 * Если текст оборвался посреди последовательности знака
	 */
	if(end && (this->_length != 0)){
		// Запоминаем код ошибки приведения
		this->_error = error_t::INVALID_ENCODING;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод получения определённой кодировки исходного текста
 *
 * @return определённая кодировка исходного текста
 *
 */
awh::codec::toml::encoding_t awh::codec::toml::Decoder::encoding() const noexcept {
	// Выводим определённую кодировку исходного текста
	return this->_encoding;
}
/**
 * @brief Метод получения признака обнаружения метки порядка байтов
 *
 * @return признак обнаружения метки порядка байтов
 *
 */
bool awh::codec::toml::Decoder::signature() const noexcept {
	// Выводим признак обнаружения метки порядка байтов
	return this->_signed;
}
/**
 * @brief Метод установки кодировки исходного текста
 *
 * @param encoding устанавливаемая кодировка исходного текста
 * @return         результат выполнения операции
 *
 */
bool awh::codec::toml::Decoder::encoding(const encoding_t encoding) noexcept {
	/**
	 * Если приведение текста уже началось
	 */
	if(this->_started)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если кодировка исходного текста не определена
	 */
	if(encoding == encoding_t::NONE){
		// Выполняем снятие признака навязанной извне кодировки
		this->_forced = false;
		// Выполняем сброс кодировки исходного текста
		this->_encoding = encoding_t::NONE;
		// Выводим положительный результат выполнения операции
		return true;
	}
	// Запоминаем навязанную извне кодировку исходного текста
	this->_encoding = encoding;
	// Запоминаем признак навязанной извне кодировки
	this->_forced = true;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод приведения куска исходного текста к кодировке UTF-8
 *
 * @param buffer буфер очередного куска исходного текста
 * @param size   размер буфера очередного куска исходного текста
 * @param end    признак того, что кусок является последним
 * @param result текст, к которому дописывается приведённый кусок
 * @return       результат выполнения операции
 *
 */
bool awh::codec::toml::Decoder::convert(const void * buffer, const size_t size, const bool end, string & result) noexcept {
	/**
	 * Если предыдущая операция приведения завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем признак того, что приведение текста началось
	this->_started = true;
	/**
	 * Если метка порядка байтов ещё не обработана
	 */
	if(!this->_marked){
		/**
		 * Если кусок исходного текста передан
		 */
		if((buffer != nullptr) && (size > 0))
			// Выполняем удержание начала текста до определения кодировки
			this->_prolog.append(reinterpret_cast <const char *> (buffer), size);
		/**
		 * Если удержанного начала текста для определения кодировки недостаточно
		 *
		 * @note Наибольшая метка порядка байтов занимает четыре байта, и до их
		 *       прихода определять кодировку нельзя: метка UTF-32 начинается с
		 *       метки UTF-16, и по двум первым байтам их не различить
		 */
		if((this->_prolog.size() < 4) && !end)
			// Выводим положительный результат выполнения операции
			return true;
		/**
		 * Если определение кодировки выполнить не удалось
		 */
		if(!this->sniff())
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выполняем получение удержанного начала текста
		const string prolog(std::move(this->_prolog));
		// Выполняем освобождение хранилища удержанного начала текста
		this->_prolog.clear();
		// Выполняем приведение удержанного начала текста
		return this->process(prolog.data(), prolog.size(), end, result);
	}
	// Выполняем приведение переданного куска исходного текста
	return this->process(reinterpret_cast <const char *> (buffer), ((buffer != nullptr) ? size : 0), end, result);
}
/**
 * @brief Метод получения кода ошибки приведения
 *
 * @return код ошибки последней операции приведения
 *
 */
awh::codec::toml::error_t awh::codec::toml::Decoder::error() const noexcept {
	// Выводим код ошибки последней операции приведения
	return this->_error;
}
/**
 * @brief Метод сброса приведения в исходное состояние
 *
 */
void awh::codec::toml::Decoder::reset() noexcept {
	// Выполняем сброс кода ошибки приведения
	this->_error = error_t::NONE;
	// Выполняем сброс признака обнаружения метки порядка байтов
	this->_signed = false;
	// Выполняем сброс признака обработки метки порядка байтов
	this->_marked = false;
	// Выполняем сброс признака начала приведения текста
	this->_started = false;
	// Выполняем сброс удержанного начала текста
	this->_prolog.clear();
	// Выполняем сброс количества удержанных байтов
	this->_length = 0;
	// Выполняем сброс удержанной старшей половины суррогатной пары
	this->_surrogate = 0;
	/**
	 * Если кодировка исходного текста извне не навязана
	 *
	 * @note Навязанная кодировка сброс переживает намеренно: устанавливается она
	 *       вызывающим до разбора, и потеря её при сбросе означала бы молчаливый
	 *       переход разбора на кодировку по умолчанию
	 */
	if(!this->_forced)
		// Выполняем сброс определённой кодировки исходного текста
		this->_encoding = encoding_t::NONE;
}
/**
 * @brief Метод вывода сообщения об отказе в лог
 *
 */
void awh::codec::toml::Decoder::report() const noexcept {
	/**
	 * Если объект для работы с логами установлен
	 */
	if(this->_log != nullptr)
		// Выполняем вывод сообщения об отказе
		this->_log->print("TOML encoding failed: %s", log_t::flag_t::CRITICAL, awh::codec::toml::message(this->_error));
}
/**
 * @brief Конструктор
 *
 * @param log объект для работы с логами
 *
 */
awh::codec::toml::Decoder::Decoder(const log_t * log) noexcept :
 _log(log),
 _encoding(encoding_t::NONE), _error(error_t::NONE), _forced(false),
 _marked(false), _signed(false), _started(false), _length(0), _surrogate(0) {
	// Выполняем сброс удержанных байтов незавершённой последовательности знака
	this->_pending[0] = 0;
	// Выполняем сброс удержанных байтов незавершённой последовательности знака
	this->_pending[1] = 0;
	// Выполняем сброс удержанных байтов незавершённой последовательности знака
	this->_pending[2] = 0;
	// Выполняем сброс удержанных байтов незавершённой последовательности знака
	this->_pending[3] = 0;
}
