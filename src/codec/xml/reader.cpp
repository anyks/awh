/**
 * @brief Метод поиска атрибута текущего узла по имени
 *
 * @param local местное имя искомого атрибута
 * @param uri   обозначение пространства имён искомого атрибута
 * @return      значение найденного атрибута либо пустая последовательность
 *
 */
string_view awh::codec::xml::Reader::attribute(const string_view local, const string_view uri) const noexcept {
	/**
	 * Выполняем перебор всех атрибутов текущего узла
	 */
	for(const attribute_t & attribute : this->_attributes){
		/**
		 * Если имя атрибута совпадает с искомым
		 */
		if(attribute.name.is(uri, local))
			// Выводим значение найденного атрибута
			return attribute.value;
	}
	// Выводим пустую последовательность знаков
	return string_view();
}
/**
 * @brief Метод проверки наличия атрибута у текущего узла
 *
 * @param local местное имя искомого атрибута
 * @param uri   обозначение пространства имён искомого атрибута
 * @return      результат проверки
 *
 */
bool awh::codec::xml::Reader::has(const string_view local, const string_view uri) const noexcept {
	/**
	 * Выполняем перебор всех атрибутов текущего узла
	 */
	for(const attribute_t & attribute : this->_attributes){
		/**
		 * Если имя атрибута совпадает с искомым
		 */
		if(attribute.name.is(uri, local))
			// Выводим положительный результат проверки
			return true;
	}
	// Выводим отрицательный результат проверки
	return false;
}
