/**
 * @brief Метод прекращения разбора ошибкой
 *
 * @param error  код ошибки разбора
 * @param offset положение ошибки в приведённом исходном тексте
 * @return       итог шага разбора, всегда отрицательный
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::fail(const error_t error, const size_t offset) noexcept {
	// Запоминаем код ошибки разбора
	this->_error = error;
	// Запоминаем положение обнаруженной ошибки
	this->_errorLocation = this->locate(offset);
	// Запоминаем состояние прекращённого ошибкой разбора
	this->_state = state_t::FAILED;
	// Выполняем сброс вида текущего события разбора
	this->_event = event_t::NONE;
	// Выводим отрицательный итог шага разбора
	return step_t::FAILED;
}
/**
 * @brief Метод получения положения в исходном тексте
 *
 * @param offset положение в приведённом исходном тексте
 * @return       положение в исходном тексте разметки
 *
 */
awh::codec::xml::location_t awh::codec::xml::Reader::locate(const size_t offset) const noexcept {
	/**
	 * Если разбор находится внутри подставленной сущности
	 *
	 * @note Внутри подстановки положений исходного текста нет: там разбирается
	 *       значение сущности, а не сам текст. Местом всего разобранного изнутри
	 *       считается ссылка на сущность
	 */
	if(!this->_splices.empty())
		// Выводим положение ссылки на самую внешнюю подставленную сущность
		return this->_splices.front().location;
	// Собираемое положение в исходном тексте
	location_t result;
	// Запоминаем смещение от начала текста
	result.offset = (this->_consumed + offset);
	// Запоминаем текущий номер строки
	result.line = this->_line;
	// Запоминаем текущее положение в строке
	result.column = this->_column;
	/**
	 * Если указанное положение опережает разбор
	 *
	 * @note Счёт строк ведётся разбором на ходу, но место ошибки нередко лежит
	 *       впереди него: до него досчитываем отдельно
	 */
	if(this->_offset < offset){
		// Положение, до которого место уже досчитано
		size_t from = this->_offset;
		// Выполняем досчёт строки и столбца по отрезку исходного текста
		::measure(this->_buffer, result.line, result.column, from, offset);
	}
	// Выводим собранное положение в исходном тексте
	return result;
}
/**
 * @brief Метод досчёта положения в исходном тексте от ранее полученного
 *
 * @param location досчитываемое положение в исходном тексте
 * @param from     положение, до которого место уже досчитано
 * @param offset   положение, до которого место требуется досчитать
 *
 */
void awh::codec::xml::Reader::relocate(location_t & location, size_t & from, const size_t offset) const noexcept {
	/**
	 * Если разбор находится внутри подставленной сущности
	 *
	 * @note Внутри подстановки положений исходного текста нет: местом всего
	 *       разобранного изнутри считается ссылка на саму сущность
	 */
	if(!this->_splices.empty()){
		// Запоминаем положение ссылки на самую внешнюю подставленную сущность
		location = this->_splices.front().location;
		// Запоминаем положение, до которого место досчитано
		from = offset;
		// Выходим из метода
		return;
	}
	// Выполняем досчёт строки и столбца по отрезку исходного текста
	::measure(this->_buffer, location.line, location.column, from, offset);
	// Запоминаем смещение от начала текста
	location.offset = (this->_consumed + offset);
}
/**
 * @brief Метод перемещения разбора к указанному положению
 *
 * @param offset положение в приведённом исходном тексте
 *
 */
void awh::codec::xml::Reader::advance(const size_t offset) noexcept {
	// Получаем конец пройденного разбором отрезка
	const size_t end = (offset > this->_buffer.size() ? this->_buffer.size() : offset);
	// Положение чтения в пройденном отрезке
	size_t pos = this->_offset;
	/**
	 * Выполняем перебор всех строк, пройденных разбором
	 */
	while(pos < end){
		/**
		 * Выполняем поиск ближайшего перевода строки и ближайшего возврата каретки
		 *
		 * @details Концом строки договор считает и перевод строки, и возврат каретки, и
		 *          пару из них: пара при этом составляет один конец, а не два. Считай мы
		 *          строки по одному переводу, текст с концами строк, записанными возвратом
		 *          каретки, весь оказался бы на первой строке
		 *
		 * @note Оба знака отыскиваются одним проходом, а не двумя обращениями к
		 *       средствам обработки памяти: отрезок, проходимый за один шаг разбора,
		 *       короток, и стоимость двух обращений на нём превосходит стоимость
		 *       самого просмотра
		 */
		const size_t found = ::newline(this->_buffer.data() + pos, end - pos);
		// Положение ближайшего конца строки в пройденном отрезке
		const size_t stop = ((found < (end - pos)) ? (pos + found) : string::npos);
		/**
		 * Если конец строки в пройденном отрезке не обнаружен
		 */
		if(stop == string::npos){
			// Выполняем подсчёт знаков, пройденных в текущей строке
			this->_column += static_cast <uint32_t> (::codepoints(this->_buffer.data() + pos, end - pos));
			// Выходим из перебора строк
			break;
		}
		// Выполняем переход к следующей строке
		this->_line++;
		// Выполняем сброс положения в строке
		this->_column = 1;
		// Выполняем переход к началу следующей строки
		pos = (stop + 1);
		/**
		 * Если конец строки записан возвратом каретки с переводом строки
		 */
		if((this->_buffer[stop] == '\r') && (pos < end) && (this->_buffer[pos] == '\n'))
			// Выполняем пропуск перевода строки как части пары
			pos++;
	}
	// Запоминаем новое положение разбора
	this->_offset = (offset > this->_buffer.size() ? this->_buffer.size() : offset);
}
/**
 * @brief Метод проверки того, что разметка не пересекает границу подстановки
 *
 * @details Договор велит подставленной сущности быть построенной правильно самой по
 *          себе: разметка, начатая внутри неё, обязана внутри неё и закончиться. Иначе
 *          строение документа зависело бы от того, чем сущность объявлена, а её значение
 *          могло бы закрыть узел, открытый вне её, либо начать раздел, который закроется
 *          уже за её пределами
 *
 * @note Проверяются положения в приведённом тексте, где подстановка уже произведена:
 *       область подстановки задана в нём же, и сличать их можно напрямую
 *
 * @param begin положение начала разметки в приведённом тексте
 * @param end   положение конца разметки в приведённом тексте
 * @return      признак того, что разметка границу подстановки пересекает
 *
 */
bool awh::codec::xml::Reader::crosses(const size_t begin, const size_t end) const noexcept {
	/**
	 * Выполняем перебор открытых областей подстановки от ближней к дальней
	 */
	for(size_t i = this->_splices.size(); i > 0; i--){
		// Получаем очередную открытую область подстановки
		const splice_t & splice = this->_splices[i - 1];
		// Если разметка начата внутри области, а закончена за её пределами, выводим пересечение
		if((begin < splice.end) && (end > splice.end)) return true;
	}
	// Выводим признак того, что разметка границу подстановки не пересекает
	return false;
}
void awh::codec::xml::Reader::compact() noexcept {
	/**
	 * Если открыта область подставленной сущности
	 *
	 * @note Область подстановки задана положениями в приведённом тексте, и изъятие
	 *       его начала эти положения обесценит
	 */
	if(!this->_splices.empty())
		// Выходим из изъятия разобранного начала текста
		return;
	/**
	 * Если исходный текст получен целиком
	 *
	 * @note Изъятие начала бережёт память лишь тогда, когда впереди ещё есть что
	 *       дочитывать: у полученного целиком текста освобождать нечего, а
	 *       перекладывание его остатка обошлось бы дороже самого разбора
	 */
	if(this->_final)
		// Выходим из изъятия разобранного начала текста
		return;
	/**
	 * Если разобранного текста накопилось достаточно для изъятия
	 *
	 * @warning Изымать следует не раньше, чем разобрана половина накопленного:
	 *          иначе на каждое изъятие приходится перекладывание почти всего
	 *          буфера, и разбор из линейного превращается в квадратичный
	 */
	if((this->_offset >= COMPACT_LIMIT) && (this->_offset >= (this->_buffer.size() / 2))){
		// Выполняем изъятие разобранного начала текста
		this->_buffer.erase(0, this->_offset);
		// Запоминаем количество изъятых байтов
		this->_consumed += this->_offset;
		// Выполняем сброс положения разбора
		this->_offset = 0;
	}
}
/**
 * @brief Метод получения последовательности знаков по отрезку хранилища
 *
 * @param span отрезок хранилища знаков разбора
 * @return     последовательность знаков указанного отрезка
 *
 */
string_view awh::codec::xml::Reader::view(const span_t & span) const noexcept {
	/**
	 * Если отрезок выходит за пределы хранилища знаков
	 *
	 * @warning Сложение выполняется в разрядности размера, а не в разрядности самих
	 *          полей отрезка: у отрезка они 32-разрядные, и сложение в ней при
	 *          близком к пределу смещении обращается в ноль, отчего проверка
	 *          пропускает отрезок, лежащий за пределами хранилища
	 */
	if((static_cast <size_t> (span.offset) + static_cast <size_t> (span.length)) > this->_names.size())
		// Выводим пустую последовательность знаков
		return string_view();
	// Выводим последовательность знаков указанного отрезка
	return string_view(this->_names.data() + span.offset, span.length);
}
/**
 * @brief Метод размещения последовательности знаков в хранилище разбора
 *
 * @param text размещаемая последовательность знаков
 * @return     отрезок хранилища знаков разбора
 *
 */
awh::codec::xml::span_t awh::codec::xml::Reader::store(const string_view text) noexcept {
	/**
	 * Если хранилище знаков выходит за предел разрядности отрезка
	 *
	 * @details Отрезок хранилища адресуется 32 разрядами, а сам объём хранилища
	 *          ничем не ограничен. За пределом разрядности смещение обращается в
	 *          младшие разряды, и отрезок начинает указывать на чужое место того же
	 *          хранилища: выдача тогда не отказывает, а молча выдаёт чужие знаки.
	 *          Отказ здесь обращает молчаливое искажение в явную ошибку
	 *
	 * @note Разрядность отрезка выбрана намеренно: запись места четырьмя байтами
	 *       вместо восьми вдвое уменьшает объём перечня атрибутов, а разметки,
	 *       где одни лишь имена одного узла превосходят четыре гигабайта, не бывает
	 */
	if((this->_names.size() + text.length()) > static_cast <size_t> (0xFFFFFFFFu)){
		// Запоминаем код ошибки разбора
		this->_error = error_t::OVERFLOW_LIMIT;
		// Выводим пустой отрезок хранилища знаков
		return span_t();
	}
	// Собираемый отрезок хранилища знаков
	const span_t result(static_cast <uint32_t> (this->_names.size()), static_cast <uint32_t> (text.length()));
	// Выполняем размещение последовательности знаков в хранилище
	this->_names.append(text);
	// Выводим собранный отрезок хранилища знаков
	return result;
}
/**
 * @brief Метод поиска пространства имён по префиксу
 *
 * @param prefix префикс без разделителя
 * @return       отрезок хранилища с обозначением пространства имён
 *
 */
awh::codec::xml::span_t awh::codec::xml::Reader::lookup(const string_view prefix) const noexcept {
	/**
	 * Выполняем перебор действующих связываний от ближайшего узла к корню
	 */
	for(size_t i = this->_scopes.size(); i > 0; i--){
		// Получаем очередное связывание префикса
		const scope_t & scope = this->_scopes[i - 1];
		/**
		 * Если префикс связывания совпадает с искомым
		 */
		if(this->view(scope.prefix) == prefix)
			// Выводим обозначение связанного пространства имён
			return scope.uri;
	}
	/**
	 * Если искомым является отведённый договором префикс
	 *
	 * @note Префикс «xml» связан со своим пространством имён изначально: объявлять
	 *       его не требуется, а искать среди объявленных бесполезно
	 */
	if(prefix == "xml")
		// Выводим отведённое договором обозначение пространства имён
		return this->_xml;
	// Выводим пустой отрезок хранилища знаков
	return span_t();
}
/**
 * @brief Метод разбора имени с необязательным префиксом
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца разбираемой разметки
 * @param prefix префикс разобранного имени
 * @param local  местное имя разобранного имени
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::parseName(size_t & offset, const size_t end, string_view & prefix, string_view & local) noexcept {
	// Выполняем сброс признака имени, превысившего предел настроек
	this->_overlong = false;
	// Запоминаем начало разбираемого имени
	const size_t begin = offset;
	// Количество знаков разобранного имени
	uint32_t count = 0;
	// Собранные по всему имени разряды таблицы знаков US-ASCII
	uint8_t flags = 0;
	// Получаем буфер разбираемого имени
	const char * buffer = this->_buffer.data();
	/**
	 * Выполняем перебор всех знаков разбираемого имени
	 */
	while(offset < end){
		/**
		 * Выполняем перебор знаков имени, принадлежащих US-ASCII
		 *
		 * @note Знаки US-ASCII проверяются по таблице разрядов: чтение кодового
		 *       значения им не требуется, а имена почти всегда состоят из них.
		 *       Допустимость знака в начале имени проверяется по собранному
		 *       первому знаку отдельно: перебор тогда обходится одним сличением
		 */
		while(offset < end){
			// Получаем очередной байт разбираемого имени
			const uint8_t letter = static_cast <uint8_t> (buffer[offset]);
			/**
			 * Если знак принадлежит US-ASCII
			 */
			if(letter >= 0x80)
				// Выходим из перебора знаков US-ASCII
				break;
			// Получаем разряды таблицы очередного знака имени
			const uint8_t bits = NAME_TABLE[letter];
			/**
			 * Если знак недопустим внутри имени
			 */
			if((bits & 0x02) == 0)
				// Выходим из перебора знаков имени
				return this->qualify(begin, offset, count, flags, prefix, local);
			// Выполняем сбор разрядов таблицы знаков имени
			flags = static_cast <uint8_t> (flags | bits);
			// Выполняем переход к следующему знаку имени
			offset++;
			// Выполняем подсчёт знаков разобранного имени
			count++;
		}
		/**
		 * Если имя разобрано до конца
		 */
		if(offset >= end)
			// Выходим из перебора знаков имени
			break;
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение кодового значения очередного знака
		const uint32_t code = decode(this->_buffer.data() + offset, end - offset, length);
		/**
		 * Если знак прочитать не удалось
		 */
		if((length == 0) || (code == INVALID_CODEPOINT))
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если знак недопустим в имени
		 */
		if(!isName(code))
			// Выходим из перебора знаков имени
			break;
		// Выполняем переход к следующему знаку имени
		offset += length;
		// Выполняем подсчёт знаков разобранного имени
		count++;
	}
	// Выводим итог разбора имени
	return this->qualify(begin, offset, count, flags, prefix, local);
}
/**
 * @brief Метод разделения разобранного имени на префикс и местное имя
 *
 * @param begin  положение начала разобранного имени
 * @param end    положение конца разобранного имени
 * @param count  количество знаков разобранного имени
 * @param flags  собранные по всему имени разряды таблицы знаков US-ASCII
 * @param prefix префикс разобранного имени
 * @param local  местное имя разобранного имени
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::qualify(const size_t begin, const size_t end, const uint32_t count, const uint8_t flags, string_view & prefix, string_view & local) noexcept {
	/**
	 * Если длина имени превышает допустимую
	 *
	 * @note Повод этот от ошибочного построения отличается, и запоминается он отдельно:
	 *       вызывающему выдаётся свой код отказа
	 */
	if(count > this->_settings.maxName){
		// Запоминаем, что имя превысило предел, заданный настройками
		this->_overlong = true;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если имя пусто
	 */
	if(end == begin)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Получаем имя в записи, принятой в исходном тексте
	const string_view qname(this->_buffer.data() + begin, end - begin);
	/**
	 * Если первый знак имени в его начале недопустим
	 *
	 * @note Проверка первого знака вынесена из перебора: внутри имени она
	 *       обходилась бы сличением на каждом знаке, а знак здесь всего один
	 */
	if(!::started(qname))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если имя записано без разделителя префикса
	 */
	if(!this->_settings.namespaces || ((flags & 0x04) == 0)){
		// Выполняем сброс префикса разобранного имени
		prefix = string_view();
		// Запоминаем местное имя разобранного имени
		local = qname;
		// Выводим положительный результат выполнения операции
		return true;
	}
	// Выполняем поиск разделителя префикса и местного имени
	const size_t colon = qname.find(':');
	/**
	 * Если префикс либо местное имя пусты
	 */
	if((colon == 0) || ((colon + 1) >= qname.size()))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем префикс разобранного имени
	prefix = qname.substr(0, colon);
	// Запоминаем местное имя разобранного имени
	local = qname.substr(colon + 1);
	/**
	 * Если первый знак местного имени в его начале недопустим
	 *
	 * @details Договор о пространствах имён строит имя с префиксом из двух имён без
	 *          двоеточия, и каждое из них подчиняется тем же правилам, что и имя без
	 *          префикса: начинаться цифрой, дефисом либо точкой ему не дозволено.
	 *          Проверка первого знака всего имени этого не покрывает - она приходится
	 *          на первый знак префикса, а местное имя стоит за разделителем
	 *
	 * @note Префикс отдельной проверки не требует: он начинается там же, где и всё имя,
	 *       и первый знак у них общий
	 */
	if(!::started(local))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если разделитель в имени встречается не единожды
	 */
	if(local.find(':') != string_view::npos)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод подстановки ссылки на сущность
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца разбираемой разметки
 * @param result текст, к которому дописывается подставленное значение
 * @param depth  текущая глубина вложенности ссылок на сущности
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::parseReference(size_t & offset, const size_t end, string & result, const uint32_t depth, const bool space, const bool content) noexcept {
	/**
	 * Если глубина вложенности ссылок превышает допустимую
	 */
	if(depth >= MAX_ENTITY_DEPTH){
		// Запоминаем код ошибки разбора
		this->_error = error_t::ENTITY_DEPTH_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Получаем разбираемый текст ссылки
	const string_view text(this->_buffer.data(), this->_buffer.size());
	// Выполняем поиск конца ссылки на сущность
	const size_t stop = text.find(';', offset);
	/**
	 * Если конец ссылки на сущность не обнаружен
	 */
	if((stop == string_view::npos) || (stop >= end)){
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_REFERENCE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Получаем содержимое ссылки на сущность
	const string_view name = text.substr(offset + 1, stop - (offset + 1));
	/**
	 * Если ссылка на сущность пуста
	 */
	if(name.empty()){
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_REFERENCE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Запоминаем положение конца ссылки на сущность
	offset = (stop + 1);
	// Выполняем подстановку значения сущности по её имени
	return this->expand(name, result, depth, space, content);
}
/**
 * @brief Метод подстановки значения сущности по её имени
 *
 * @param name   имя подставляемой сущности либо числовая ссылка
 * @param result текст, к которому дописывается подставленное значение
 * @param depth  текущая глубина вложенности ссылок на сущности
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::expand(const string_view name, string & result, const uint32_t depth, const bool space, const bool content) noexcept {
	/**
	 * Если глубина вложенности ссылок превышает допустимую
	 */
	if(depth >= MAX_ENTITY_DEPTH){
		// Запоминаем код ошибки разбора
		this->_error = error_t::ENTITY_DEPTH_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если имя подставляемой сущности пусто
	 */
	if(name.empty()){
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_REFERENCE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если ссылка является числовой
	 */
	if(name.front() == '#'){
		// Кодовое значение указанного ссылкой знака
		uint64_t code = 0;
		/**
		 * Получаем признак шестнадцатеричной записи кодового значения
		 *
		 * @note Договор задаёт знак шестнадцатеричной записи строчным: прописной
		 *       знак делает ссылку построенной ошибочно
		 */
		const bool hex = ((name.length() > 1) && (name[1] == 'x'));
		// Получаем запись кодового значения знака
		const string_view digits = name.substr(hex ? 2 : 1);
		/**
		 * Если запись кодового значения пуста
		 */
		if(digits.empty()){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_CHAR_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если запись кодового значения начата не цифрой принятой системы счисления
		 *
		 * @note Разбор числа сам по себе допускает знак числа и пробельные знаки
		 *       перед ним, а договор в числовой ссылке допускает одни лишь цифры:
		 *       первый знак проверяется до разбора
		 */
		if(hex ? (ascii::hexValue(digits.front()) < 0) : !ascii::isDigit(digits.front())){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_CHAR_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Выполняем разбор записи кодового значения знака
		const auto parsed = lexical::fromChars(digits.data(), digits.data() + digits.length(), code, (hex ? 16 : 10));
		/**
		 * Если запись кодового значения разобрана не целиком либо число не помещается
		 */
		if(!parsed || (parsed.ptr != (digits.data() + digits.length()))){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_CHAR_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если кодовое значение вышло за пределы Юникода
		 */
		if(code > MAX_CODEPOINT){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_CHAR_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если указанный ссылкой знак недопустим в разметке
		 */
		if(!isChar(static_cast <uint32_t> (code))){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_CHAR_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Выполняем добавление указанного ссылкой знака
		return encode(static_cast <uint32_t> (code), result);
	}
	/**
	 * Если ссылка указывает на сущность, предопределённую договором
	 */
	if(name == "amp"){
		// Выполняем добавление знака амперсанда
		result.push_back('&');
		// Выводим положительный результат выполнения операции
		return true;
	} else if(name == "lt") {
		// Выполняем добавление знака левой угловой скобки
		result.push_back('<');
		// Выводим положительный результат выполнения операции
		return true;
	} else if(name == "gt") {
		// Выполняем добавление знака правой угловой скобки
		result.push_back('>');
		// Выводим положительный результат выполнения операции
		return true;
	} else if(name == "quot") {
		// Выполняем добавление знака двойной кавычки
		result.push_back('"');
		// Выводим положительный результат выполнения операции
		return true;
	} else if(name == "apos") {
		// Выполняем добавление знака одинарной кавычки
		result.push_back('\'');
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Выполняем перебор всех знаков имени сущности
	 *
	 * @details Ссылка на сущность обязана нести имя, построенное по правилам договора:
	 *          записи вроде «&65;» либо «&a b;» именами не являются вовсе. Проверять их
	 *          следует здесь, а не отыскиванием объявления: отсутствие объявления и
	 *          ошибочно построенное имя - поводы разные, и первый из них снимается
	 *          признаком прихода объявлений извне, тогда как второй не снимается ничем
	 *
	 * @warning Прежде имя не проверялось вовсе, а отказ выходил из того, что сущности с
	 *          таким именем в объявлениях не находилось. Прикрытие это неполно: там, где
	 *          объявления вправе прийти извне разобранного, отыскание вовсе не ведётся,
	 *          и ошибочно построенная ссылка проходила разбор насквозь
	 */
	for(size_t offset = 0; offset < name.size();){
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение кодового значения очередного знака имени
		const uint32_t code = decode(name.data() + offset, name.size() - offset, length);
		/**
		 * Если знак прочитать не удалось, либо он недопустим в имени, либо
		 * недопустим в его начале
		 */
		if((length == 0) || (code == INVALID_CODEPOINT) || !isName(code) || ((offset == 0) && !isNameStart(code))){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_REFERENCE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Выполняем переход к следующему знаку имени
		offset += length;
	}
	/**
	 * Если подстановка объявленных сущностей отключена настройками
	 */
	if(!this->_settings.entities){
		// Запоминаем код ошибки разбора
		this->_error = error_t::UNKNOWN_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем поиск объявления сущности
	this->_lookup.assign(name);
	// Выполняем отыскание объявления сущности
	auto i = this->_entities.find(this->_lookup);
	/**
	 * Если сущность не объявлена
	 */
	if(i == this->_entities.end()){
		/**
		 * Если объявления могут приходить извне разобранного
		 *
		 * @details Внешнее подмножество описания типа документа и значение параметрической
		 *          сущности разбор не разворачивает, а объявление вправе лежать именно там.
		 *          Договор относит такую недостачу к действительности, которую разбор не
		 *          проверяет, а не к построению текста: отвергнуть текст здесь значило бы
		 *          объявить неправильно построенным то, чего мы попросту не читали
		 *
		 * @note Ссылка при этом пропускается без подстановки: подставить нечего, а выдать
		 *       её знаками текста неверно - на письме она осталась бы ссылкой и прочлась
		 *       бы обратно уже разметкой
		 */
		if(this->_foreign)
			// Выводим положительный результат пропуска ссылки на сущность
			return true;
		// Запоминаем код ошибки разбора
		this->_error = error_t::UNKNOWN_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если значение сущности содержит разметку
	 *
	 * @note Сюда подстановка приходит из значения атрибута и из объявленного по
	 *       умолчанию значения, а знак начала разметки в значении атрибута договором
	 *       запрещён. В содержимом узла такие сущности подставляются иначе - прямо в
	 *       разбираемый текст
	 */
	if(i->second.markup){
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если сущность объявлена внешней
	 *
	 * @note Загрузка внешних сущностей запрещена устройством разбора: подставить
	 *       такую сущность нечем, и ссылка на неё является ошибкой
	 */
	if(i->second.external){
		// Запоминаем код ошибки разбора
		this->_error = error_t::EXTERNAL_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если подстановка сущности выполняется в текущий миг
	 */
	if(i->second.active){
		// Запоминаем код ошибки разбора
		this->_error = error_t::RECURSIVE_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем накопление общего объёма подстановки сущностей
	this->_expansion += i->second.value.size();
	/**
	 * Если общий объём подстановки превысил допустимый
	 */
	if(this->_expansion > this->_settings.maxExpansion){
		// Запоминаем код ошибки разбора
		this->_error = error_t::ENTITY_LIMIT_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Выполняем изъятие значения сущности из хранилища объявлений
	 *
	 * @note Значение снимается копией: подстановка вложенных ссылок вправе
	 *       дописать в хранилище объявлений и обесценить ссылку на него
	 */
	const string value(i->second.value);
	/**
	 * Если подстановка ведётся в содержимое узла, а значение сущности несёт
	 * последовательность, отведённую концу дословного раздела
	 *
	 * @details Договор велит значению подставляемой сущности быть построенным по
	 *          правилам содержимого узла, а содержимому эта последовательность
	 *          запрещена: записывается она либо разделом дословного текста, либо
	 *          ссылкой на знак. Запрет проверяется по разбираемому тексту, где на
	 *          месте сущности стоит ссылка, и значения её не достигает вовсе
	 *
	 * @note Проверяется объявленное значение, а не итог подстановки: вложенные
	 *       ссылки внутри него - это уже ссылки, и знак, полученный ссылкой, запрета
	 *       не нарушает. Тем же правилом законна и запись «]]&gt;»
	 *
	 * @warning Значению атрибута последовательность эта не запрещена, и проверять её
	 *          там нельзя: правило договора отнесено к содержимому узла
	 */
	if(content && (value.find("]]>") != string::npos)){
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_CHARACTER;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Запоминаем, что подстановка сущности выполняется
	i->second.active = true;
	// Результат подстановки вложенных ссылок
	bool success = true;
	/**
	 * Выполняем перебор всех знаков подставляемого значения
	 */
	for(size_t pos = 0; pos < value.size(); pos++){
		/**
		 * Если обнаружена вложенная ссылка на сущность
		 */
		if(value[pos] == '&'){
			// Выполняем поиск конца вложенной ссылки
			const size_t stop = value.find(';', pos);
			/**
			 * Если конец вложенной ссылки не обнаружен
			 */
			if(stop == string::npos){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_REFERENCE;
				// Запоминаем отрицательный результат подстановки
				success = false;
				// Выходим из перебора знаков
				break;
			}
			/**
			 * Выполняем подстановку вложенной ссылки на сущность
			 *
			 * @note Признак подстановки в содержимое узла передаётся вглубь: запрет на
			 *       последовательность конца дословного раздела отнесён договором к
			 *       содержимому, а не к глубине вложения ссылок. Без передачи признака
			 *       запрет обходился ссылкой-посредником: значение её самой запрета не
			 *       нарушало, а проверка значения той сущности, что несёт запрещённое,
			 *       не выполнялась вовсе
			 */
			success = this->expand(string_view(value).substr(pos + 1, stop - (pos + 1)), result, depth + 1, space, content);
			/**
			 * Если подстановку вложенной ссылки выполнить не удалось
			 */
			if(!success)
				// Выходим из перебора знаков
				break;
			// Выполняем переход к следующему знаку значения
			pos = stop;
		/**
		 * Если пробельные знаки подставляемого значения приводятся к пробелу
		 *
		 * @details Договор предписывает приводить значение атрибута повторно и к тому,
		 *          что подставлено ссылкой на сущность: пробельные знаки её значения
		 *          обращаются в пробел наравне с записанными в самом значении атрибута.
		 *          Знаки же, записанные числовой ссылкой прямо в значении атрибута,
		 *          приведению не подлежат - там подставляется знак, а не текст сущности
		 *
		 * @note Конец строки при этом одним знаком не считается: приведение его к
		 *       переводу строки договор относит к исходному тексту, а значение сущности
		 *       исходным текстом уже не является - пара из возврата каретки с переводом
		 *       строки даёт здесь два пробела, а не один
		 */
		} else if(space && ((value[pos] == '\n') || (value[pos] == '\r') || (value[pos] == '\t')))
			// Выполняем добавление пробела к подставленному значению
			result.push_back(' ');
		// Выполняем добавление очередного знака значения
		else result.push_back(value[pos]);
	}
	/**
	 * Выполняем поиск объявления сущности заново
	 *
	 * @note Хранилище объявлений могло измениться при подстановке вложенных
	 *       ссылок, и удерживать ссылку на его запись через вызов нельзя
	 */
	this->_lookup.assign(name);
	// Выполняем отыскание объявления сущности заново
	i = this->_entities.find(this->_lookup);
	/**
	 * Если объявление сущности на месте
	 */
	if(i != this->_entities.end())
		// Запоминаем, что подстановка сущности завершена
		i->second.active = false;
	// Выводим результат выполнения операции
	return success;
}
/**
 * @brief Метод разбора значения атрибута
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца разбираемой разметки
 * @param value  отрезок хранилища приведённых значений
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::parseValue(size_t & offset, const size_t end, span_t & value) noexcept {
	/**
	 * Если значение атрибута не заключено в кавычки
	 */
	if((offset >= end) || ((this->_buffer[offset] != '"') && (this->_buffer[offset] != '\''))){
		// Запоминаем код ошибки разбора
		this->_error = error_t::UNQUOTED_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Получаем знак кавычки, которым заключено значение
	const char quote = this->_buffer[offset++];
	// Запоминаем начало приведённого значения атрибута
	value.offset = static_cast <uint32_t> (this->_scratch.size());
	/**
	 * Выполняем перебор всех знаков значения атрибута
	 */
	while(offset < end){
		/**
		 * Выполняем поиск ближайшего знака, требующего обработки
		 *
		 * @note Значение между такими знаками переписывается целым отрезком, как и
		 *       содержимое узла: посимвольное перекладывание здесь столь же накладно
		 */
		size_t stop = offset;
		/**
		 * Выполняем поиск конца отрезка, переписываемого целиком
		 */
		while(stop < end){
			// Получаем очередной знак значения атрибута
			const char letter = this->_buffer[stop];
			/**
			 * Если обнаружен знак, требующий обработки
			 *
			 * @note Сличение ведётся цепочкой намеренно: замена её обращением к
			 *       таблице знаков замедляет разбор на седьмую часть. Значения
			 *       атрибутов коротки, предсказатель переходов справляется с цепочкой
			 *       лучше, чем обращение к таблице - за чтение из неё
			 */
			if((letter == quote) || (letter == '&') || (letter == '<') ||
			   (letter == '\n') || (letter == '\r') || (letter == '\t'))
				// Выходим из поиска конца отрезка
				break;
			// Выполняем переход к следующему знаку значения
			stop++;
		}
		/**
		 * Если перед ближайшим знаком есть содержимое
		 */
		if(stop > offset){
			// Выполняем добавление отрезка значения целиком
			this->_scratch.append(this->_buffer.data() + offset, stop - offset);
			// Выполняем переход к ближайшему знаку, требующему обработки
			offset = stop;
		}
		/**
		 * Если значение атрибута прочитано до конца
		 */
		if(offset >= end)
			// Выходим из перебора знаков значения
			break;
		// Получаем очередной знак значения атрибута
		const char letter = this->_buffer[offset];
		/**
		 * Если обнаружен конец значения атрибута
		 */
		if(letter == quote){
			// Выполняем переход к следующему знаку
			offset++;
			// Запоминаем длину приведённого значения атрибута
			/**
			 * Если хранилище приведённых значений вышло за предел разрядности отрезка
			 *
			 * @details Отрезок значения адресуется 32 разрядами, а объём хранилища
			 *          ничем не ограничен: подстановка сущностей растит его настолько,
			 *          насколько дозволено настройкой `maxExpansion`. За пределом
			 *          разрядности смещение обращается в младшие разряды, и значение
			 *          начинает указывать на чужое место того же хранилища - выдача при
			 *          этом не отказывает, а молча выдаёт чужие знаки
			 *
			 * @note Проверка стоит на записи длины, а не на записи смещения: границу
			 *       переходит само значение по ходу накопления, и застать переход можно
			 *       лишь по его окончании
			 */
			if(this->_scratch.size() > static_cast <size_t> (0xFFFFFFFFu)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::OVERFLOW_LIMIT;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			value.length = static_cast <uint32_t> (this->_scratch.size() - value.offset);
			// Выводим положительный результат выполнения операции
			return true;
		}
		/**
		 * Если обнаружен знак, недопустимый в значении атрибута
		 */
		if(letter == '<'){
			// Запоминаем код ошибки разбора
			this->_error = error_t::INVALID_ATTRIBUTE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если обнаружена ссылка на сущность
		 */
		if(letter == '&'){
			/**
			 * Если подстановку ссылки выполнить не удалось
			 */
			if(!this->parseReference(offset, end, this->_scratch, 0, true))
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если обнаружен возврат каретки
		 *
		 * @details Приведение ведётся в два приёма, и порядок их договором задан: сперва
		 *          конец строки обращается в перевод строки, и пара из возврата каретки с
		 *          переводом строки при этом становится одним знаком, - и лишь затем
		 *          пробельные знаки обращаются в пробел. Замени мы каждый знак пары
		 *          порознь, значение получило бы два пробела там, где договор велит один
		 *
		 * @note Знаки, записанные ссылкой, приведению не подлежат вовсе: договор относит
		 *       его к самому тексту, а не к тому, что ссылкой в него подставлено. Оттого
		 *       ведётся оно здесь, а не над собранным значением
		 */
		if(letter == '\r'){
			// Выполняем добавление пробела к приведённому значению
			this->_scratch.push_back(' ');
			// Выполняем переход к следующему знаку значения
			offset++;
			// Если следом идёт перевод строки, пропускаем его как часть пары
			if((offset < end) && (this->_buffer[offset] == '\n'))
				// Выполняем переход к следующему знаку значения
				offset++;
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если обнаружен пробельный знак
		 *
		 * @note Договор предписывает заменять пробельные знаки в значении атрибута
		 *       пробелом: значение атрибута строкой не разрывается
		 */
		if((letter == '\n') || (letter == '\t'))
			// Выполняем добавление пробела к приведённому значению
			this->_scratch.push_back(' ');
		// Выполняем добавление очередного знака к приведённому значению
		else this->_scratch.push_back(letter);
		// Выполняем переход к следующему знаку значения
		offset++;
	}
	// Запоминаем код ошибки разбора
	this->_error = error_t::UNQUOTED_ATTRIBUTE;
	// Выводим отрицательный результат выполнения операции
	return false;
}
/**
 * @brief Метод пропуска пробельных знаков внутреннего подмножества
 *
 * @param offset   положение разбора в приведённом исходном тексте
 * @param end      положение конца внутреннего подмножества
 * @param required признак обязательности пробельного знака
 * @return         результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetSpace(size_t & offset, const size_t end, const bool required) noexcept {
	// Запоминаем начало пропускаемых пробельных знаков
	const size_t begin = offset;
	/**
	 * Выполняем пропуск пробельных знаков
	 */
	while((offset < end) && ::isSpace(this->_buffer[offset]))
		// Выполняем переход к следующему знаку
		offset++;
	// Выводим результат выполнения операции
	return (!required || (offset > begin));
}
/**
 * @brief Метод разбора имени внутреннего подмножества
 *
 * @details Имена описания типа документа разбираются без разделения на префикс и
 *          местное имя: договор о пространствах имён к описанию типа документа не
 *          применяется, и разделитель является там обычным знаком имени
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @param token  признак разбора имени, допускающего любой знак в начале
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetName(size_t & offset, const size_t end, const bool token) noexcept {
	// Запоминаем начало разбираемого имени
	const size_t begin = offset;
	/**
	 * Выполняем перебор всех знаков разбираемого имени
	 */
	while(offset < end){
		// Получаем очередной байт разбираемого имени
		const uint8_t letter = static_cast <uint8_t> (this->_buffer[offset]);
		/**
		 * Если знак принадлежит US-ASCII
		 */
		if(letter < 0x80){
			/**
			 * Если знак недопустим в имени
			 */
			if((NAME_TABLE[letter] & 0x02) == 0)
				// Выходим из перебора знаков имени
				break;
			/**
			 * Если знак недопустим в начале имени
			 */
			if(!token && (offset == begin) && ((NAME_TABLE[letter] & 0x01) == 0))
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем переход к следующему знаку имени
			offset++;
			// Выполняем переход к следующему знаку имени
			continue;
		}
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение кодового значения очередного знака
		const uint32_t code = decode(this->_buffer.data() + offset, end - offset, length);
		/**
		 * Если знак прочитать не удалось
		 */
		if((length == 0) || (code == INVALID_CODEPOINT))
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если знак недопустим в имени
		 */
		if(!isName(code))
			// Выходим из перебора знаков имени
			break;
		/**
		 * Если знак недопустим в начале имени
		 */
		if(!token && (offset == begin) && !isNameStart(code))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выполняем переход к следующему знаку имени
		offset += length;
	}
	// Выводим результат выполнения операции
	return (offset > begin);
}
/**
 * @brief Метод разбора отведённого договором слова внутреннего подмножества
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @param word   отведённое договором слово
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetKeyword(size_t & offset, const size_t end, const string_view word) noexcept {
	/**
	 * Если отведённое договором слово не помещается в остаток подмножества
	 */
	if((offset + word.size()) > end)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если отведённое договором слово не совпало
	 */
	if(string_view(this->_buffer.data() + offset, word.size()) != word)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем переход к концу отведённого договором слова
	offset += word.size();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод разбора значения в кавычках внутреннего подмножества
 *
 * @details Договор задаёт четыре вида значений в кавычках, и допустимое внутри них
 * содержимое у каждого своё: значение сущности не допускает одиноких знаков ссылки,
 * значение атрибута - знака начала разметки, обозначение внешнего источника - лишь
 * ограниченного набора знаков. Проверка их построения является частью проверки
 * построения самого текста, а не его действительности
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @param kind   вид разбираемого значения
 * @param result текст, к которому дописывается приведённое значение
 * @param markup признак обнаружения разметки в значении
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetLiteral(size_t & offset, const size_t end, const literal_t kind, string * result, bool * markup) noexcept {
	/**
	 * Если значение не заключено в кавычки
	 */
	if((offset >= end) || ((this->_buffer[offset] != '"') && (this->_buffer[offset] != '\'')))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Получаем знак кавычки, которым заключено значение
	const char quote = this->_buffer[offset++];
	/**
	 * Выполняем перебор всех знаков значения
	 */
	while(offset < end){
		// Получаем очередной знак значения
		const char letter = this->_buffer[offset];
		/**
		 * Если обнаружен конец значения
		 */
		if(letter == quote){
			// Выполняем переход к концу значения
			offset++;
			// Выводим положительный результат выполнения операции
			return true;
		}
		/**
		 * Определяем вид разбираемого значения
		 */
		switch(static_cast <uint8_t> (kind)){
			/**
			 * Если разбирается значение объявляемой сущности
			 */
			case static_cast <uint8_t> (literal_t::ENTITY): {
				/**
				 * Если обнаружена ссылка на параметрическую сущность
				 *
				 * @note Договор не допускает ссылок на параметрические сущности внутри
				 *       объявлений внутреннего подмножества: там такая ссылка вправе
				 *       стоять лишь на месте самого объявления. Разбирается же здесь
				 *       всегда внутреннее подмножество - внешние объявления не читаются
				 */
				if(letter == '%')
					// Выводим отрицательный результат выполнения операции
					return false;
				/**
				 * Если обнаружена ссылка
				 */
				if(letter == '&'){
					/**
					 * Если обнаружена числовая ссылка
					 *
					 * @note Числовые ссылки подставляются при объявлении, а ссылки на
					 *       сущности - при обращении к сущности: договор различает их именно так
					 */
					if(((offset + 1) < end) && (this->_buffer[offset + 1] == '#')){
						// Получаем место, собираемое подстановкой
						string & value = (result != nullptr ? * result : this->_scratch);
						// Запоминаем длину собранного значения до подстановки
						const size_t length = value.size();
						/**
						 * Если подстановку числовой ссылки выполнить не удалось
						 */
						if(!this->parseReference(offset, end, value, 0))
							// Выводим отрицательный результат выполнения операции
							return false;
						/**
						 * Если подставленное числовой ссылкой содержит знак начала разметки
						 *
						 * @details Числовая ссылка подставляется при объявлении, и знак, ею
						 *          записанный, входит в значение сущности наравне с записанным
						 *          прямо. Договор различает исходную запись и подставленное
						 *          значение, а не то, каким способом знак в это значение попал:
						 *          `&#60;` даёт ровно тот же знак, что и `<`, со всеми его
						 *          последствиями - разметкой в содержимом узла и запретом в
						 *          значении атрибута
						 *
						 * @note Двойное указание предопределённых сущностей от этого не
						 *       страдает: значением `&#38;#60;` выходит `&#60;`, знака начала
						 *       разметки в себе не несущее
						 */
						if((markup != nullptr) && (value.find('<', length) != string::npos))
							// Запоминаем, что значение сущности содержит разметку
							(* markup) = true;
						// Выполняем переход к следующему знаку значения
						continue;
					}
					// Запоминаем начало ссылки на сущность
					const size_t begin = offset++;
					/**
					 * Если имя сущности разобрать не удалось
					 */
					if(!this->subsetName(offset, end, false) || (offset >= end) || (this->_buffer[offset] != ';'))
						// Выводим отрицательный результат выполнения операции
						return false;
					// Выполняем переход к концу ссылки на сущность
					offset++;
					/**
					 * Если значение сущности собирается
					 */
					if(result != nullptr)
						// Выполняем добавление ссылки на сущность к значению
						result->append(this->_buffer.data() + begin, offset - begin);
					// Выполняем переход к следующему знаку значения
					continue;
				}
				/**
				 * Если обнаружен знак начала разметки
				 */
				if((letter == '<') && (markup != nullptr))
					// Запоминаем, что значение сущности содержит разметку
					(* markup) = true;
				/**
				 * Если обнаружен возврат каретки
				 *
				 * @note Объявление входит в исходный текст, и приведение конца строки к
				 *       нему прилагается наравне с прочим: возврат каретки обязан войти в
				 *       значение сущности переводом строки, а пара из возврата с переводом -
				 *       одним знаком. Иначе сырой возврат дошёл бы до содержимого узла, куда
				 *       значение подставляется как есть
				 */
				if(letter == '\r'){
					/**
					 * Если значение сущности собирается
					 */
					if(result != nullptr)
						// Выполняем добавление перевода строки к значению сущности
						result->push_back('\n');
					// Выполняем переход к следующему знаку значения
					offset++;
					// Если следом идёт перевод строки, пропускаем его как часть пары
					if((offset < end) && (this->_buffer[offset] == '\n'))
						// Выполняем переход к следующему знаку значения
						offset++;
					// Выполняем переход к следующему знаку значения
					continue;
				}
			} break;
			/**
			 * Если разбирается объявленное по умолчанию значение атрибута
			 */
			case static_cast <uint8_t> (literal_t::ATTRIBUTE): {
				/**
				 * Если обнаружен знак начала разметки
				 *
				 * @note Знак начала разметки в значении атрибута договор не допускает
				 *       ни прямо, ни через подстановку ссылки
				 */
				if(letter == '<')
					// Выводим отрицательный результат выполнения операции
					return false;
				/**
				 * Если обнаружена ссылка
				 */
				if(letter == '&'){
					/**
					 * Если обнаружена числовая ссылка
					 *
					 * @note Ссылки на сущности при объявлении не подставляются: договор
					 *       откладывает их подстановку до обращения к атрибуту
					 */
					if(((offset + 1) < end) && (this->_buffer[offset + 1] == '#')){
						/**
						 * Если подстановку числовой ссылки выполнить не удалось
						 */
						if(!this->parseReference(offset, end, (result != nullptr ? *result : this->_scratch), 0))
							// Выводим отрицательный результат выполнения операции
							return false;
						// Выполняем переход к следующему знаку значения
						continue;
					}
					// Запоминаем начало ссылки на сущность
					const size_t begin = offset++;
					/**
					 * Если имя сущности разобрать не удалось
					 */
					if(!this->subsetName(offset, end, false) || (offset >= end) || (this->_buffer[offset] != ';'))
						// Выводим отрицательный результат выполнения операции
						return false;
					// Выполняем переход к концу ссылки на сущность
					offset++;
					/**
					 * Если значение атрибута собирается
					 */
					if(result != nullptr)
						// Выполняем добавление ссылки на сущность к значению
						result->append(this->_buffer.data() + begin, offset - begin);
					// Выполняем переход к следующему знаку значения
					continue;
				}
				/**
				 * Если значение атрибута собирается
				 */
				if(result != nullptr){
					/**
					 * Если обнаружен возврат каретки
					 *
					 * @note Приведение ведётся в два приёма, и порядок их договором задан:
					 *       сперва конец строки обращается в перевод строки, отчего пара из
					 *       возврата каретки с переводом строки становится одним знаком, - и
					 *       лишь затем пробельные знаки обращаются в пробел. Замена каждого
					 *       знака пары порознь дала бы два пробела там, где договор велит один
					 */
					if(letter == '\r'){
						// Выполняем добавление пробела к значению атрибута
						result->push_back(' ');
						// Выполняем переход к следующему знаку значения
						offset++;
						// Если следом идёт перевод строки, пропускаем его как часть пары
						if((offset < end) && (this->_buffer[offset] == '\n'))
							// Выполняем переход к следующему знаку значения
							offset++;
						// Выполняем переход к следующему знаку значения
						continue;
					}
					/**
					 * Если обнаружен пробельный знак
					 */
					if((letter == '\n') || (letter == '\t')){
						// Выполняем добавление пробела к значению атрибута
						result->push_back(' ');
						// Выполняем переход к следующему знаку значения
						offset++;
						// Выполняем переход к следующему знаку значения
						continue;
					}
				}
			} break;
			/**
			 * Если разбирается обозначение общедоступного источника
			 */
			case static_cast <uint8_t> (literal_t::PUBLIC): {
				/**
				 * Если знак недопустим в обозначении общедоступного источника
				 */
				if(!::pubid(letter))
					// Выводим отрицательный результат выполнения операции
					return false;
			} break;
		}
		/**
		 * Если значение собирается
		 */
		if(result != nullptr)
			// Выполняем добавление очередного знака к значению
			result->push_back(letter);
		// Выполняем переход к следующему знаку значения
		offset++;
	}
	// Выводим отрицательный результат выполнения операции
	return false;
}
/**
 * @brief Метод разбора обозначения внешнего источника внутреннего подмножества
 *
 * @param offset   положение разбора в приведённом исходном тексте
 * @param end      положение конца внутреннего подмножества
 * @param system   признак обязательности обозначения размещения источника
 * @param external признак обнаружения обозначения внешнего источника
 * @return         результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetExternal(size_t & offset, const size_t end, const bool system, bool & external) noexcept {
	// Запоминаем, что обозначение внешнего источника не обнаружено
	external = false;
	/**
	 * Если обозначение размещения источника задано прямо
	 */
	if(this->subsetKeyword(offset, end, "SYSTEM")){
		// Запоминаем, что обозначение внешнего источника обнаружено
		external = true;
		/**
		 * Если обозначение размещения источника разобрать не удалось
		 */
		if(!this->subsetSpace(offset, end, true) || !this->subsetLiteral(offset, end, literal_t::SYSTEM, nullptr, nullptr))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Если обозначение источника задано общедоступным
	 */
	if(this->subsetKeyword(offset, end, "PUBLIC")){
		// Запоминаем, что обозначение внешнего источника обнаружено
		external = true;
		/**
		 * Если обозначение общедоступного источника разобрать не удалось
		 */
		if(!this->subsetSpace(offset, end, true) || !this->subsetLiteral(offset, end, literal_t::PUBLIC, nullptr, nullptr))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Запоминаем положение разбора до пропуска пробельных знаков
		const size_t begin = offset;
		/**
		 * Если обозначение размещения источника отсутствует
		 *
		 * @note Объявление обозначения допускает обозначение источника без размещения,
		 *       а объявления сущности и типа документа - нет
		 */
		if(!this->subsetSpace(offset, end, true) || (offset >= end) ||
		   ((this->_buffer[offset] != '"') && (this->_buffer[offset] != '\''))){
			/**
			 * Если обозначение размещения источника обязательно
			 */
			if(system)
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем возврат разбора к пропущенным пробельным знакам
			offset = begin;
			// Выводим положительный результат выполнения операции
			return true;
		}
		// Выводим результат разбора обозначения размещения источника
		return this->subsetLiteral(offset, end, literal_t::SYSTEM, nullptr, nullptr);
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод разбора описания строения узла внутреннего подмножества
 *
 * @details Описание строения узла разбором не применяется - действительность текста
 * не проверяется, - но его построение проверяется наравне с остальным текстом:
 * договор относит построение описания к правилам построения самого текста
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @param depth  текущая глубина вложенности описания строения
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetChildren(size_t & offset, const size_t end, const uint32_t depth) noexcept {
	/**
	 * Если глубина вложенности описания строения превысила допустимую
	 */
	if(depth >= MAX_DEPTH)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если описание строения не открыто
	 */
	if((offset >= end) || (this->_buffer[offset] != '('))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем переход к содержимому описания строения
	offset++;
	// Знак разделителя частей описания строения
	char separator = 0;
	/**
	 * Выполняем перебор всех частей описания строения
	 */
	for(;;){
		// Выполняем пропуск пробельных знаков
		this->subsetSpace(offset, end, false);
		/**
		 * Если очередная часть описания строения задана вложенным описанием
		 */
		if((offset < end) && (this->_buffer[offset] == '(')){
			/**
			 * Если вложенное описание строения разобрать не удалось
			 */
			if(!this->subsetChildren(offset, end, (depth + 1)))
				// Выводим отрицательный результат выполнения операции
				return false;
		/**
		 * Если очередная часть описания строения задана именем узла
		 */
		} else if(!this->subsetName(offset, end, false))
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если у части описания строения задана повторяемость
		 */
		if((offset < end) && ((this->_buffer[offset] == '?') || (this->_buffer[offset] == '*') || (this->_buffer[offset] == '+')))
			// Выполняем переход к следующему знаку
			offset++;
		// Выполняем пропуск пробельных знаков
		this->subsetSpace(offset, end, false);
		/**
		 * Если описание строения оборвано
		 */
		if(offset >= end)
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если описание строения прочитано до конца
		 */
		if(this->_buffer[offset] == ')'){
			// Выполняем переход к концу описания строения
			offset++;
			// Выводим положительный результат выполнения операции
			return true;
		}
		/**
		 * Если знак не является разделителем частей описания строения
		 */
		if((this->_buffer[offset] != ',') && (this->_buffer[offset] != '|'))
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если разделитель частей описания строения задан иначе прежнего
		 *
		 * @note Договор не допускает смешения разделителей в одном описании: перечень
		 *       заданных подряд узлов и перечень узлов на выбор строятся по-разному
		 */
		if((separator != 0) && (this->_buffer[offset] != separator))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Запоминаем знак разделителя частей описания строения
		separator = this->_buffer[offset];
		// Выполняем переход к следующей части описания строения
		offset++;
	}
}
/**
 * @brief Метод разбора описания содержимого узла внутреннего подмножества
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetContent(size_t & offset, const size_t end) noexcept {
	/**
	 * Если содержимое узла объявлено пустым
	 */
	if(this->subsetKeyword(offset, end, "EMPTY"))
		// Выводим положительный результат выполнения операции
		return true;
	/**
	 * Если содержимое узла объявлено произвольным
	 */
	if(this->subsetKeyword(offset, end, "ANY"))
		// Выводим положительный результат выполнения операции
		return true;
	/**
	 * Если описание содержимого узла не открыто
	 */
	if((offset >= end) || (this->_buffer[offset] != '('))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем положение начала описания содержимого узла
	const size_t begin = offset++;
	// Выполняем пропуск пробельных знаков
	this->subsetSpace(offset, end, false);
	/**
	 * Если содержимое узла объявлено смешанным
	 */
	if(this->subsetKeyword(offset, end, "#PCDATA")){
		// Количество объявленных смешанному содержимому узлов
		uint32_t count = 0;
		/**
		 * Выполняем перебор всех объявленных смешанному содержимому узлов
		 */
		for(;;){
			// Выполняем пропуск пробельных знаков
			this->subsetSpace(offset, end, false);
			/**
			 * Если описание содержимого узла оборвано
			 */
			if(offset >= end)
				// Выводим отрицательный результат выполнения операции
				return false;
			/**
			 * Если описание содержимого узла прочитано до конца
			 */
			if(this->_buffer[offset] == ')'){
				// Выполняем переход к концу описания содержимого узла
				offset++;
				/**
				 * Если смешанному содержимому объявлены узлы
				 *
				 * @note Договор велит завершать перечень узлов смешанного содержимого
				 *       знаком повторяемости, а описание одного лишь текста - без него
				 */
				if(count > 0){
					/**
					 * Если знак повторяемости отсутствует
					 */
					if((offset >= end) || (this->_buffer[offset] != '*'))
						// Выводим отрицательный результат выполнения операции
						return false;
					// Выполняем переход к следующему знаку
					offset++;
				/**
				 * Если знак повторяемости задан описанию одного лишь текста
				 */
				} else if((offset < end) && (this->_buffer[offset] == '*'))
					// Выполняем переход к следующему знаку
					offset++;
				// Выводим положительный результат выполнения операции
				return true;
			}
			/**
			 * Если знак не является разделителем узлов смешанного содержимого
			 */
			if(this->_buffer[offset] != '|')
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем переход к очередному объявленному узлу
			offset++;
			// Выполняем пропуск пробельных знаков
			this->subsetSpace(offset, end, false);
			/**
			 * Если имя объявленного узла разобрать не удалось
			 */
			if(!this->subsetName(offset, end, false))
				// Выводим отрицательный результат выполнения операции
				return false;
			// Выполняем подсчёт объявленных смешанному содержимому узлов
			count++;
		}
	}
	// Выполняем возврат разбора к началу описания содержимого узла
	offset = begin;
	/**
	 * Если описание строения узла разобрать не удалось
	 */
	if(!this->subsetChildren(offset, end, 0))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если у описания строения узла задана повторяемость
	 */
	if((offset < end) && ((this->_buffer[offset] == '?') || (this->_buffer[offset] == '*') || (this->_buffer[offset] == '+')))
		// Выполняем переход к следующему знаку
		offset++;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод разделения имени описания типа документа на префикс и местное имя
 *
 * @details Договор о пространствах имён к описанию типа документа не применяется, и
 *          разделитель является там обычным знаком имени. Разделение выполняется лишь
 *          ради сличения объявленных по умолчанию значений с записанными в тексте
 *          атрибутами: сличать их иначе, чем разбор разделяет имена, нельзя
 *
 * @param qname  имя в записи, принятой в исходном тексте
 * @param prefix префикс разделённого имени
 * @param local  местное имя разделённого имени
 *
 */
void awh::codec::xml::Reader::divide(const string_view qname, string & prefix, string & local) const noexcept {
	// Выполняем поиск разделителя префикса и местного имени
	const size_t pos = qname.find(':');
	/**
	 * Если имя записано без разделителя префикса
	 */
	if(!this->_settings.namespaces || (pos == string_view::npos) ||
	   (pos == 0) || ((pos + 1) >= qname.size()) || (qname.find(':', pos + 1) != string_view::npos)){
		// Выполняем сброс префикса разделённого имени
		prefix.clear();
		// Запоминаем местное имя разделённого имени
		local.assign(qname);
		// Выходим из метода
		return;
	}
	// Запоминаем префикс разделённого имени
	prefix.assign(qname.substr(0, pos));
	// Запоминаем местное имя разделённого имени
	local.assign(qname.substr(pos + 1));
}
/**
 * @brief Метод разбора вида объявляемого атрибута внутреннего подмножества
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::subsetAttribute(size_t & offset, const size_t end) noexcept {
	/**
	 * @brief Виды атрибута, отведённые договором
	 *
	 * @note Порядок сличения задан от длинного к короткому: иначе вид «IDREFS» был бы
	 *       прочитан как «IDREF» с лишним знаком в остатке
	 */
	static constexpr const char * KINDS[] = {
		"CDATA", "IDREFS", "IDREF", "ID", "ENTITIES", "ENTITY", "NMTOKENS", "NMTOKEN"
	};
	/**
	 * Выполняем перебор всех отведённых договором видов атрибута
	 */
	for(const char * kind : KINDS){
		/**
		 * Если вид атрибута совпал с отведённым договором
		 */
		if(this->subsetKeyword(offset, end, kind))
			// Выводим положительный результат выполнения операции
			return true;
	}
	// Признак объявления вида атрибута перечнем обозначений
	const bool notation = this->subsetKeyword(offset, end, "NOTATION");
	/**
	 * Если вид атрибута объявлен перечнем обозначений
	 */
	if(notation){
		/**
		 * Если перечень обозначений не отделён пробельным знаком
		 */
		if(!this->subsetSpace(offset, end, true))
			// Выводим отрицательный результат выполнения операции
			return false;
	}
	/**
	 * Если перечень допустимых значений не открыт
	 */
	if((offset >= end) || (this->_buffer[offset] != '('))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем переход к содержимому перечня допустимых значений
	offset++;
	/**
	 * Выполняем перебор всех допустимых значений атрибута
	 */
	for(;;){
		// Выполняем пропуск пробельных знаков
		this->subsetSpace(offset, end, false);
		/**
		 * Если очередное допустимое значение разобрать не удалось
		 *
		 * @note Перечень обозначений строится именами, а перечень значений - словами:
		 *       слово вправе начинаться со знака, недопустимого в начале имени
		 */
		if(!this->subsetName(offset, end, !notation))
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выполняем пропуск пробельных знаков
		this->subsetSpace(offset, end, false);
		/**
		 * Если перечень допустимых значений оборван
		 */
		if(offset >= end)
			// Выводим отрицательный результат выполнения операции
			return false;
		/**
		 * Если перечень допустимых значений прочитан до конца
		 */
		if(this->_buffer[offset] == ')'){
			// Выполняем переход к концу перечня допустимых значений
			offset++;
			// Выводим положительный результат выполнения операции
			return true;
		}
		/**
		 * Если знак не является разделителем допустимых значений
		 */
		if(this->_buffer[offset] != '|')
			// Выводим отрицательный результат выполнения операции
			return false;
		// Выполняем переход к очередному допустимому значению
		offset++;
	}
}
/**
 * @brief Метод разбора внутреннего подмножества описания типа документа
 *
 * @details Построение объявлений внутреннего подмножества проверяется наравне с
 * остальным текстом: договор относит его к правилам построения текста, а не к
 * правилам его действительности. Проверяется именно построение - соответствие
 * содержимого объявленному строению документом не проверяется
 *
 * @note Ссылки на параметрические сущности внутри объявлений договор не допускает:
 * во внутреннем подмножестве такая ссылка вправе стоять лишь там, где вправе стоять
 * само объявление. Подстановка их поэтому не выполняется
 *
 * @param offset положение разбора в приведённом исходном тексте
 * @param end    положение конца внутреннего подмножества
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::parseSubset(size_t offset, const size_t end) noexcept {
	// Получаем разбираемый текст внутреннего подмножества
	const string_view text(this->_buffer.data(), this->_buffer.size());
	/**
	 * Выполняем перебор всех объявлений внутреннего подмножества
	 */
	while(offset < end){
		// Получаем очередной знак внутреннего подмножества
		const char letter = this->_buffer[offset];
		/**
		 * Если обнаружен пробельный знак
		 */
		if(::isSpace(letter)){
			// Выполняем переход к следующему знаку
			offset++;
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружена ссылка на параметрическую сущность
		 *
		 * @note Внешние объявления не читаются, и подставить ссылку нечем: она
		 *       пропускается, а её построение проверяется
		 */
		if(letter == '%'){
			// Выполняем переход к имени параметрической сущности
			offset++;
			/**
			 * Если ссылка на параметрическую сущность построена ошибочно
			 */
			if(!this->subsetName(offset, end, false) || (offset >= end) || (this->_buffer[offset] != ';')){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			offset++;
			/**
			 * Запоминаем, что объявления могут приходить извне разобранного
			 *
			 * @note Значение параметрической сущности разбор не разворачивает, и внутри
			 *       него вправе лежать объявления - в том числе объявления сущностей,
			 *       на которые ссылается сам текст
			 */
			this->_foreign = true;
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено примечание
		 */
		if(text.compare(offset, 4, "<!--") == 0){
			// Выполняем переход к содержимому примечания
			offset += 4;
			/**
			 * Выполняем поиск конца примечания
			 */
			for(;;){
				// Выполняем поиск двойного знака переноса
				const size_t stop = text.find("--", offset);
				/**
				 * Если конец примечания не обнаружен
				 */
				if((stop == string_view::npos) || ((stop + 2) > end)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_COMMENT;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если двойной знак переноса завершает примечание
				 *
				 * @note Двойной знак переноса внутри примечания договор не допускает:
				 *       он вправе стоять лишь в самом его конце
				 */
				if(((stop + 2) < this->_buffer.size()) && (this->_buffer[stop + 2] == '>')){
					// Выполняем переход к концу примечания
					offset = (stop + 3);
					// Выходим из поиска конца примечания
					break;
				}
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_COMMENT;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено указание обработчику
		 */
		if(text.compare(offset, 2, "<?") == 0){
			// Выполняем переход к обозначению обработчика
			offset += 2;
			// Запоминаем начало обозначения обработчика
			const size_t target = offset;
			/**
			 * Если обозначение обработчика разобрать не удалось
			 */
			if(!this->subsetName(offset, end, false)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_PROCESSING;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			/**
			 * Если обозначением обработчика является отведённое договором имя
			 *
			 * @note Объявление разметки стоит лишь в самом начале текста, и внутри
			 *       описания типа документа отведённое ему имя занято быть не может
			 */
			if((offset - target) == 3){
				// Получаем обозначение обработчика
				const string_view name(this->_buffer.data() + target, 3);
				/**
				 * Если обозначением обработчика занято отведённое договором имя
				 */
				if(ascii::equals(name[0], 'x') && ascii::equals(name[1], 'm') && ascii::equals(name[2], 'l')){
					// Запоминаем код ошибки разбора
					this->_error = error_t::RESERVED_PROCESSING;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
			// Выполняем поиск конца указания обработчику
			const size_t stop = text.find("?>", offset);
			/**
			 * Если конец указания обработчику не обнаружен
			 */
			if((stop == string_view::npos) || ((stop + 2) > end)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_PROCESSING;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			/**
			 * Если содержимое не отделено от обозначения обработчика
			 */
			if((stop > offset) && !::isSpace(this->_buffer[offset])){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_PROCESSING;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			offset = (stop + 2);
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено объявление строения узла
		 */
		if(text.compare(offset, 9, "<!ELEMENT") == 0){
			// Выполняем переход к содержимому объявления строения узла
			offset += 9;
			/**
			 * Если объявление строения узла построено ошибочно
			 */
			if(!this->subsetSpace(offset, end, true) || !this->subsetName(offset, end, false) ||
			   !this->subsetSpace(offset, end, true) || !this->subsetContent(offset, end)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем пропуск пробельных знаков
			this->subsetSpace(offset, end, false);
			/**
			 * Если конец объявления строения узла отсутствует
			 */
			if((offset >= end) || (this->_buffer[offset] != '>')){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			offset++;
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено объявление обозначения
		 */
		if(text.compare(offset, 10, "<!NOTATION") == 0){
			// Признак обнаружения обозначения внешнего источника
			bool external = false;
			// Выполняем переход к содержимому объявления обозначения
			offset += 10;
			/**
			 * Если объявление обозначения не отделено пробельным знаком
			 */
			if(!this->subsetSpace(offset, end, true)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем начало имени объявляемого обозначения
			const size_t begin = offset;
			/**
			 * Если объявление обозначения построено ошибочно
			 */
			if(!this->subsetName(offset, end, false) ||
			   (this->_settings.namespaces && (string_view(this->_buffer.data() + begin, offset - begin).find(':') != string_view::npos)) ||
			   !this->subsetSpace(offset, end, true) || !this->subsetExternal(offset, end, false, external) || !external){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем пропуск пробельных знаков
			this->subsetSpace(offset, end, false);
			/**
			 * Если конец объявления обозначения отсутствует
			 */
			if((offset >= end) || (this->_buffer[offset] != '>')){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			offset++;
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено объявление сущности
		 */
		if(text.compare(offset, 8, "<!ENTITY") == 0){
			// Выполняем переход к содержимому объявления сущности
			offset += 8;
			/**
			 * Если объявление сущности не отделено пробельным знаком
			 */
			if(!this->subsetSpace(offset, end, true)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Получаем признак объявления параметрической сущности
			const bool parameter = ((offset < end) && (this->_buffer[offset] == '%'));
			/**
			 * Если объявляется параметрическая сущность
			 */
			if(parameter){
				// Выполняем переход к имени параметрической сущности
				offset++;
				/**
				 * Если имя параметрической сущности не отделено пробельным знаком
				 */
				if(!this->subsetSpace(offset, end, true)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
			// Запоминаем начало имени объявляемой сущности
			const size_t begin = offset;
			/**
			 * Если имя объявляемой сущности разобрать не удалось
			 */
			if(!this->subsetName(offset, end, false)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем имя объявляемой сущности
			const string name(this->_buffer.data() + begin, offset - begin);
			/**
			 * Если имя объявляемой сущности содержит разделитель префикса
			 *
			 * @note Договор о пространствах имён велит объявлять сущности и обозначения
			 *       именами без разделителя: разделитель отведён под префикс, а
			 *       пространства имён на сущности не распространяются
			 */
			if(this->_settings.namespaces && (name.find(':') != string::npos)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			/**
			 * Если значение сущности не отделено пробельным знаком
			 */
			if(!this->subsetSpace(offset, end, true)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Собираемое объявление сущности
			entity_t entity;
			/**
			 * Если значение сущности задано прямо
			 */
			if((offset < end) && ((this->_buffer[offset] == '"') || (this->_buffer[offset] == '\''))){
				/**
				 * Если значение сущности разобрать не удалось
				 */
				if(!this->subsetLiteral(offset, end, literal_t::ENTITY, &entity.value, &entity.markup)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			/**
			 * Если сущность объявлена внешней
			 */
			} else {
				// Признак обнаружения обозначения внешнего источника
				bool external = false;
				/**
				 * Если обозначение внешнего источника разобрать не удалось
				 */
				if(!this->subsetExternal(offset, end, true, external) || !external){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Запоминаем, что сущность объявлена внешней
				entity.external = true;
				// Запоминаем положение разбора до пропуска пробельных знаков
				const size_t place = offset;
				/**
				 * Если объявлено обозначение записи внешнего источника
				 */
				if(this->subsetSpace(offset, end, true) && this->subsetKeyword(offset, end, "NDATA")){
					/**
					 * Если объявление обозначения записи построено ошибочно
					 */
					if(parameter || !this->subsetSpace(offset, end, true) || !this->subsetName(offset, end, false)){
						// Запоминаем код ошибки разбора
						this->_error = error_t::INVALID_DOCTYPE;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
				// Выполняем возврат разбора к пропущенным пробельным знакам
				} else offset = place;
			}
			// Выполняем пропуск пробельных знаков
			this->subsetSpace(offset, end, false);
			/**
			 * Если конец объявления сущности отсутствует
			 */
			if((offset >= end) || (this->_buffer[offset] != '>')){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к следующему объявлению
			offset++;
			/**
			 * Если объявляется не параметрическая сущность
			 */
			if(!parameter){
				/**
				 * Если количество объявленных сущностей превысило допустимое
				 */
				if(this->_entities.size() >= this->_settings.maxEntities){
					// Запоминаем код ошибки разбора
					this->_error = error_t::ENTITY_COUNT_EXCEEDED;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Выполняем размещение объявления сущности
				 *
				 * @note Повторное объявление сущности договором не запрещено, и
				 *       действующим остаётся первое из них
				 */
				this->_entities.emplace(name, ::move(entity));
			}
			// Выполняем переход к следующему объявлению
			continue;
		}
		/**
		 * Если обнаружено объявление перечня атрибутов узла
		 *
		 * @note Перечень атрибутов разбирается ради объявленных значений по умолчанию:
		 *       они являются частью содержимого, а не его описанием
		 */
		if(text.compare(offset, 9, "<!ATTLIST") == 0){
			// Выполняем переход к содержимому объявления перечня атрибутов
			offset += 9;
			/**
			 * Если имя узла не отделено пробельным знаком
			 */
			if(!this->subsetSpace(offset, end, true)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем начало имени узла
			const size_t begin = offset;
			/**
			 * Если имя узла разобрать не удалось
			 */
			if(!this->subsetName(offset, end, false)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_DOCTYPE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем имя узла в записи, принятой в исходном тексте
			const string name(this->_buffer.data() + begin, offset - begin);
			// Собираемый перечень объявленных по умолчанию значений
			vector <default_t> defaults;
			/**
			 * Выполняем перебор всех объявлений атрибутов узла
			 */
			for(;;){
				// Выполняем пропуск пробельных знаков
				const bool spaced = this->subsetSpace(offset, end, true);
				/**
				 * Если объявление перечня атрибутов прочитано до конца
				 */
				if((offset < end) && (this->_buffer[offset] == '>')){
					// Выполняем переход к концу объявления
					offset++;
					// Выходим из перебора объявлений атрибутов
					break;
				}
				/**
				 * Если объявление атрибута не отделено пробельным знаком
				 */
				if(!spaced || (offset >= end)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Запоминаем начало имени объявляемого атрибута
				const size_t start = offset;
				/**
				 * Если имя объявляемого атрибута разобрать не удалось
				 */
				if(!this->subsetName(offset, end, false)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Собираемое объявленное по умолчанию значение
				default_t item;
				// Получаем имя объявляемого атрибута в записи, принятой в исходном тексте
				const string_view qname(this->_buffer.data() + start, offset - start);
				/**
				 * Если вид атрибута не отделён пробельным знаком
				 */
				if(!this->subsetSpace(offset, end, true)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Выполняем разделение имени объявляемого атрибута
				this->divide(qname, item.prefix, item.local);
				/**
				 * Если вид объявляемого атрибута разобрать не удалось
				 */
				if(!this->subsetAttribute(offset, end)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если объявление по умолчанию не отделено пробельным знаком
				 */
				if(!this->subsetSpace(offset, end, true) || (offset >= end)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::INVALID_DOCTYPE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				// Признак того, что атрибуту объявлено значение по умолчанию
				bool declared = true;
				/**
				 * Если объявление по умолчанию задано отведённым договором словом
				 */
				if(this->_buffer[offset] == '#'){
					/**
					 * Если значение атрибута объявлено неизменным
					 */
					if(this->subsetKeyword(offset, end, "#FIXED")){
						/**
						 * Если объявленное значение не отделено пробельным знаком
						 */
						if(!this->subsetSpace(offset, end, true)){
							// Запоминаем код ошибки разбора
							this->_error = error_t::INVALID_DOCTYPE;
							// Выводим отрицательный результат выполнения операции
							return false;
						}
					/**
					 * Если объявление по умолчанию задано отведённым договором словом
					 */
					} else if(this->subsetKeyword(offset, end, "#REQUIRED") || this->subsetKeyword(offset, end, "#IMPLIED"))
						// Запоминаем, что значение по умолчанию атрибуту не объявлено
						declared = false;
					/**
					 * Если отведённое договором слово записано ошибочно
					 */
					else {
						// Запоминаем код ошибки разбора
						this->_error = error_t::INVALID_DOCTYPE;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
				}
				/**
				 * Если атрибуту объявлено значение по умолчанию
				 */
				if(declared){
					/**
					 * Если объявленное значение разобрать не удалось
					 */
					if(!this->subsetLiteral(offset, end, literal_t::ATTRIBUTE, &item.value, nullptr)){
						// Запоминаем код ошибки разбора
						this->_error = error_t::INVALID_DOCTYPE;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					/**
					 * Выполняем перебор ссылок на сущности в объявленном значении
					 *
					 * @details Значение по умолчанию хранится с неразвёрнутыми ссылками:
					 *          подставляются они при выдаче атрибута узлу. Проверить их
					 *          следует здесь, а не там: договор относит оба запрета к
					 *          самому объявлению, и объявление, их нарушившее, отвергается
					 *          независимо от того, дойдёт ли дело до подстановки
					 */
					for(size_t at = item.value.find('&'); at != string::npos; at = item.value.find('&', at + 1)){
						// Если ссылка является числовой, пропускаем её
						if(((at + 1) < item.value.size()) && (item.value[at + 1] == '#')) continue;
						// Выполняем поиск конца ссылки на сущность
						const size_t stop = item.value.find(';', at + 1);
						// Если конец ссылки не обнаружен, выходим из перебора
						if(stop == string::npos) break;
						// Получаем имя сущности, на которую указывает ссылка
						const string name(item.value, at + 1, stop - at - 1);
						// Выполняем поиск объявления сущности
						auto i = this->_entities.find(name);
						/**
						 * Если сущность к этому мигу не объявлена
						 *
						 * @note Договор велит объявлять сущность прежде, чем на неё сошлётся
						 *       значение по умолчанию: объявления читаются по порядку, и
						 *       ссылка вперёд опиралась бы на то, чего ещё нет
						 */
						if(i == this->_entities.end()){
							/**
							 * Если объявления могут прийти извне
							 *
							 * @note Внешнее подмножество и ссылки на параметрические сущности
							 *       разбор не разворачивает, и объявление сущности вправе
							 *       лежать там: отвергать текст в этом случае неверно -
							 *       договор относит недостачу к действительности, а не к
							 *       построению
							 */
							if(this->_foreign) continue;
							// Запоминаем код ошибки разбора
							this->_error = error_t::UNKNOWN_ENTITY;
							// Выводим отрицательный результат выполнения операции
							return false;
						}
						/**
						 * Если сущность объявлена внешней
						 *
						 * @note Значение по умолчанию ссылаться на внешнюю сущность не
						 *       вправе вовсе: подстановка её потребовала бы чтения из
						 *       источника, а значение обязано быть готовым к выдаче
						 */
						if(i->second.external){
							// Запоминаем код ошибки разбора
							this->_error = error_t::INVALID_REFERENCE;
							// Выводим отрицательный результат выполнения операции
							return false;
						}
						/**
						 * Если сущность несёт разметку
						 *
						 * @details Договор запрещает знак «<» в значении атрибута, а
						 *          значение сущности, несущей разметку, его содержит.
						 *          Запрет отнесён к самому объявлению, а не к его
						 *          применению: объявление негодно и тогда, когда
						 *          значение по умолчанию не применяется ни разу
						 *
						 * @note Прежде запрет ловился лишь подстановкой, отчего документ
						 *       с заданным явно атрибутом проходил, а тот же документ с
						 *       опущенным атрибутом отвергался - при одном и том же
						 *       негодном объявлении. Внешняя сущность рядом проверялась
						 *       именно на объявлении, и расхождение это ничем не
						 *       оправдывалось
						 */
						if(i->second.markup){
							// Запоминаем код ошибки разбора
							this->_error = error_t::INVALID_REFERENCE;
							// Выводим отрицательный результат выполнения операции
							return false;
						}
					}
					// Выполняем добавление объявленного значения к перечню
					defaults.push_back(::move(item));
				}
			}
			/**
			 * Если перечень объявленных по умолчанию значений не пуст
			 */
			if(!defaults.empty()){
				// Получаем перечень объявленных значений узла
				vector <default_t> & items = this->_attlists[name];
				/**
				 * Выполняем перебор всех объявленных по умолчанию значений
				 */
				for(default_t & item : defaults)
					// Выполняем добавление объявленного значения к перечню узла
					items.push_back(::move(item));
			}
			// Выполняем переход к следующему объявлению
			continue;
		}
		// Запоминаем код ошибки разбора
		this->_error = error_t::INVALID_DOCTYPE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем перенос признака разметки по вложенным ссылкам
	this->inherit();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод переноса признака разметки по вложенным ссылкам сущностей
 *
 * @details Значение сущности вправе ссылаться на другую сущность, и подставляется такая
 * ссылка не при объявлении, а при обращении. Оттого сущность, сама знака начала разметки
 * не несущая, приносит разметку той, на которую ссылается: `outer` со значением
 * `x&inner;y` при `inner` равном `<b/>` даёт содержимому узел разметки. Признак потому
 * переносится по ссылкам, иначе подстановка пошла бы путём значения атрибута и
 * завершилась бы отказом там, где разбирается содержимое узла
 *
 * @note Перенос ведётся до неподвижности, а не одним проходом: ссылки образуют цепочки
 * любой длины, и объявлять их договор дозволяет в произвольном порядке - сущность вправе
 * ссылаться на объявленную ниже. Число обходов ограничено числом самих объявлений:
 * каждый обход, не выставивший ни одного признака, оказывается последним
 *
 */
void awh::codec::xml::Reader::inherit() noexcept {
	/**
	 * Если объявленных сущностей нет
	 */
	if(this->_entities.empty())
		// Завершаем перенос признака разметки
		return;
	/**
	 * Выполняем перенос признака разметки до неподвижности
	 */
	for(size_t pass = 0; pass < this->_entities.size(); pass++){
		// Признак того, что обход выставил хотя бы один признак разметки
		bool changed = false;
		/**
		 * Выполняем перебор всех объявленных сущностей
		 */
		for(auto & item : this->_entities){
			// Если значение сущности разметку уже несёт, переносить нечего
			if(item.second.markup)
				// Выполняем переход к следующей сущности
				continue;
			// Получаем значение разбираемой сущности
			const string & value = item.second.value;
			/**
			 * Выполняем перебор всех ссылок в значении сущности
			 */
			for(size_t offset = value.find('&'); offset != string::npos; offset = value.find('&', offset + 1)){
				// Выполняем поиск конца ссылки на сущность
				const size_t stop = value.find(';', offset + 1);
				// Если конец ссылки не обнаружен, перебор прекращается
				if(stop == string::npos)
					// Выходим из перебора ссылок значения
					break;
				// Получаем имя сущности, на которую указывает ссылка
				const string name(value.data() + offset + 1, stop - (offset + 1));
				// Если ссылка является числовой, она подставлена при объявлении
				if(name.empty() || (name.front() == '#'))
					// Выполняем переход к следующей ссылке значения
					continue;
				// Выполняем поиск объявления сущности, на которую указывает ссылка
				auto i = this->_entities.find(name);
				// Если сущность не объявлена либо её значение разметки не несёт
				if((i == this->_entities.end()) || !i->second.markup)
					// Выполняем переход к следующей ссылке значения
					continue;
				// Запоминаем, что значение сущности приносит разметку
				item.second.markup = true;
				// Запоминаем, что обход выставил признак разметки
				changed = true;
				// Выходим из перебора ссылок значения
				break;
			}
		}
		// Если обход не выставил ни одного признака, перенос завершён
		if(!changed)
			// Завершаем перенос признака разметки
			return;
	}
}
/**
 * @brief Метод разбора текстового содержимого узла
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseText() noexcept {
	// Получаем размер приведённого исходного текста
	const size_t size = this->_buffer.size();
	// Выполняем поиск начала следующей разметки
	size_t end = this->_buffer.find('<', this->_offset);
	// Признак того, что содержимое выдаётся частями
	const bool partial = (end == string::npos);
	/**
	 * Если начало следующей разметки не обнаружено
	 */
	if(partial){
		/**
		 * Если исходный текст ещё не окончен
		 */
		if(!this->_final){
			/**
			 * Если настройки требуют склеивать содержимое в одно событие
			 */
			if(this->_settings.mergeText){
				/**
				 * Если объём события превысил допустимый
				 *
				 * @note Склеивание кусков содержимого удерживает их до конца, и предел
				 *       объёма события проверяется здесь наравне с остальной разметкой:
				 *       иначе он обходился бы простым включением склеивания
				 */
				if((this->_settings.maxEvent > 0) && ((size - this->_offset) > this->_settings.maxEvent))
					// Выводим ошибку превышения заданного настройками предела
					return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
				// Выводим требование следующего куска исходного текста
				return step_t::HUNGRY;
			}
			// Запоминаем конец выдаваемой части содержимого
			end = size;
			/**
			 * Выполняем поиск последней ссылки на сущность в выдаваемой части
			 *
			 * @warning Поиск ведётся по выдаваемой части, а не по всему приведённому
			 *          тексту: назад от неё лежит уже разобранное, и найденная там ссылка
			 *          всё равно отбрасывается проверкой ниже. Поиск же по всему тексту
			 *          обходит его целиком на каждом куске - при подаче кусками в полтора
			 *          килобайта содержимое перечитывалось до полусотни раз, и разбор
			 *          проседал вчетверо против подачи целиком
			 */
			const string_view tail(this->_buffer.data() + this->_offset, end - this->_offset);
			// Получаем положение последней ссылки на сущность в выдаваемой части
			const size_t at = tail.rfind('&');
			// Получаем положение последней ссылки на сущность в приведённом тексте
			const size_t amp = ((at == string_view::npos) ? string::npos : (this->_offset + at));
			/**
			 * Если ссылка на сущность оборвана границей куска
			 */
			if(amp != string::npos){
				// Выполняем поиск конца оборванной ссылки
				const size_t stop = this->_buffer.find(';', amp);
				/**
				 * Если конец ссылки на сущность не обнаружен
				 */
				if(stop == string::npos)
					// Запоминаем конец выдаваемой части содержимого
					end = amp;
			}
			/**
			 * Если содержимое оборвано возвратом каретки
			 *
			 * @note Возврат каретки вместе с переводом строки приводится к одному
			 *       знаку, и разрывать эту пару границей куска нельзя
			 */
			if((end > this->_offset) && (this->_buffer[end - 1] == '\r'))
				// Выполняем изъятие возврата каретки из выдаваемой части
				end--;
			/**
			 * Выполняем удержание последних знаков отведённой договором последовательности
			 *
			 * @note Последовательность конца дословного раздела в содержимом узла договором
			 *       не допущена, а разорванная границей куска, она разошлась бы по двум
			 *       событиям и осталась бы незамеченной: разбиение на куски обязано быть
			 *       для разбора незаметным
			 */
			while((end > this->_offset) && (this->_buffer[end - 1] == ']') && ((size - end) < CDATA_MARGIN))
				// Выполняем изъятие удерживаемого знака из выдаваемой части
				end--;
			/**
			 * Если выдавать пока нечего
			 */
			if(end <= this->_offset)
				// Выводим требование следующего куска исходного текста
				return step_t::HUNGRY;
			/**
			 * Если настройки требуют отделять незначимое пробельное содержимое
			 *
			 * @details Пробельным содержимое считается лишь тогда, когда пробельным
			 *          оказалось оно целиком, а этого о выдаваемой части сказать нельзя:
			 *          следующий кусок может начаться с непробельного знака, и содержимое
			 *          пробельным быть перестанет. Выдай мы часть сразу, вид события
			 *          зависел бы от того, где легла граница куска, тогда как разбиение
			 *          на куски обязано быть для разбора незаметным
			 *
			 * @note Удерживается лишь пробельная часть: как только в ней появляется
			 *       непробельный знак, вид события определён окончательно, и удержание
			 *       прекращается
			 */
			if(this->_settings.separateSpaces && !this->_dirty){
				// Признак того, что выдаваемая часть состоит из одних пробельных знаков
				bool blank = true;
				/**
				 * Выполняем перебор всех знаков выдаваемой части
				 */
				for(size_t i = this->_offset; i < end; i++){
					/**
					 * Если обнаружен знак, не являющийся пробельным
					 */
					if(!::isSpace(this->_buffer[i])){
						// Запоминаем, что выдаваемая часть пробельной не является
						blank = false;
						// Выходим из перебора знаков
						break;
					}
				}
				/**
				 * Если вид события ещё не определён
				 */
				if(blank){
					/**
					 * Если объём события превысил допустимый
					 *
					 * @note Удержание пробельного содержимого копит его до конца наравне со
					 *       склеиванием кусков, и предел объёма события проверяется здесь так
					 *       же: иначе он обходился бы простым отделением пробельного содержимого
					 */
					if((this->_settings.maxEvent > 0) && ((size - this->_offset) > this->_settings.maxEvent))
						// Выводим ошибку превышения заданного настройками предела
						return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
					// Выводим требование следующего куска исходного текста
					return step_t::HUNGRY;
				}
			}
		// Запоминаем конец выдаваемого содержимого
		} else end = size;
	}
	// Получаем разбираемое содержимое узла
	const string_view raw(this->_buffer.data() + this->_offset, end - this->_offset);
	// Признак того, что содержимое состоит из одних пробельных знаков
	bool spaces = true;
	/**
	 * Выполняем перебор всех знаков содержимого
	 */
	for(size_t i = 0; i < raw.length(); i++){
		/**
		 * Если обнаружен знак, не являющийся пробельным
		 */
		if(!::isSpace(raw[i])){
			// Запоминаем, что содержимое пробельным не является
			spaces = false;
			/**
			 * Если содержимое расположено вне корневого узла
			 */
			if(this->_stack.empty())
				// Выводим ошибку содержимого вне корневого узла
				return this->fail(error_t::CONTENT_OUTSIDE_ROOT, this->_offset + i);
			// Выходим из перебора знаков
			break;
		}
	}
	/**
	 * Если содержимое расположено вне корневого узла
	 *
	 * @note Пробельное содержимое вне корневого узла договором допущено и
	 *       строения документа не описывает: оно пропускается
	 */
	if(this->_stack.empty()){
		// Выполняем переход к следующей разметке
		this->advance(end);
		// Выводим итог выполненного шага разбора
		return step_t::DONE;
	}
	/**
	 * Если содержимое содержит знак завершения дословного раздела
	 *
	 * @note Поиск самой последовательности выполняется лишь при наличии её первого
	 *       знака: он в содержимом редок, а поиск по всему содержимому дорог
	 */
	if(::memchr(raw.data(), ']', raw.length()) != nullptr){
		// Выполняем поиск последовательности, отведённой концу дословного раздела
		const size_t forbidden = raw.find("]]>");
		/**
		 * Если обнаружена последовательность, отведённая концу дословного раздела
		 */
		if(forbidden != string_view::npos)
			// Выводим ошибку недопустимого знака
			return this->fail(error_t::INVALID_CHARACTER, this->_offset + forbidden);
	}
	/**
	 * Если содержимое требует приведения
	 */
	if(::special(raw.data(), raw.length()) < raw.length()){
		// Выполняем очистку хранилища приведённых значений
		this->_scratch.clear();
		// Положение разбора содержимого узла
		size_t pos = this->_offset;
		/**
		 * Выполняем перебор всех знаков содержимого
		 */
		while(pos < end){
			/**
			 * Выполняем поиск ближайшего знака, требующего обработки
			 *
			 * @note Содержимое между такими знаками переписывается целыми отрезками:
			 *       перекладывание его по знаку обходится в разы дороже
			 */
			const size_t stop = (pos + ::special(this->_buffer.data() + pos, end - pos));
			/**
			 * Если перед ближайшим знаком есть содержимое
			 */
			if(stop > pos)
				// Выполняем добавление отрезка содержимого целиком
				this->_scratch.append(this->_buffer.data() + pos, stop - pos);
			// Выполняем переход к ближайшему знаку, требующему обработки
			pos = stop;
			/**
			 * Если содержимое узла прочитано до конца
			 */
			if(pos >= end)
				// Выходим из перебора знаков содержимого
				break;
			// Получаем очередной знак содержимого
			const char letter = this->_buffer[pos];
			/**
			 * Если обнаружена ссылка на сущность
			 */
			if(letter == '&'){
				// Имя сущности, на которую указывает ссылка
				string_view name;
				// Положение конца ссылки на сущность
				size_t stop = 0;
				/**
				 * Если ссылка указывает на сущность, содержащую разметку
				 *
				 * @note Такая сущность подставляется прямо в разбираемый текст, а не
				 *       в содержимое узла: текстовое событие на ней прекращается, и
				 *       разметка внутри неё разбирается следующим шагом
				 */
				if(this->markup(pos, name, stop)){
					// Запоминаем конец выдаваемого содержимого
					end = pos;
					// Выходим из перебора знаков содержимого
					break;
				}
				/**
				 * Если подстановку ссылки выполнить не удалось
				 */
				if(!this->parseReference(pos, end, this->_scratch, 0, false, true))
					// Выводим ошибку разбора ссылки на сущность
					return this->fail(this->_error, pos);
				// Выполняем переход к следующему знаку содержимого
				continue;
			}
			/**
			 * Если обнаружен возврат каретки
			 *
			 * @note Договор предписывает приводить все виды конца строки к одному
			 *       знаку перевода строки
			 */
			if(letter == '\r'){
				// Выполняем добавление перевода строки к приведённому содержимому
				this->_scratch.push_back('\n');
				// Выполняем переход к следующему знаку содержимого
				pos++;
				/**
				 * Если возврат каретки записан вместе с переводом строки
				 */
				if((pos < end) && (this->_buffer[pos] == '\n'))
					// Выполняем пропуск перевода строки
					pos++;
				// Выполняем переход к следующему знаку содержимого
				continue;
			}
			// Выполняем добавление очередного знака к приведённому содержимому
			this->_scratch.push_back(letter);
			// Выполняем переход к следующему знаку содержимого
			pos++;
		}
		/**
		 * Если приведённое содержимое оказалось пустым
		 *
		 * @note Так выходит, когда содержимое начинается со ссылки на сущность с
		 *       разметкой: выдавать пустое событие незачем
		 */
		if(this->_scratch.empty() && (end <= this->_offset)){
			// Выполняем переход к подставляемой сущности
			this->advance(end);
			// Выводим итог выполненного шага разбора
			return step_t::DONE;
		}
		// Запоминаем приведённое содержимое узла
		this->_text = string_view(this->_scratch.data(), this->_scratch.size());
	// Запоминаем содержимое узла без приведения
	} else this->_text = raw;
	// Запоминаем вид полученного события разбора
	this->_event = ((spaces && !this->_dirty && this->_settings.separateSpaces) ? event_t::SPACE : event_t::TEXT);
	/**
	 * Запоминаем, выдана ли непробельная часть содержимого узла
	 *
	 * @note Признак держится до ближайшей разметки: содержимое, выданное частями,
	 *       остаётся одним и тем же содержимым, и пробельный хвост его незначимым
	 *       не делает
	 */
	this->_dirty = (this->_dirty || !spaces);
	// Запоминаем глубину вложенности узла события
	this->_depth = static_cast <uint32_t> (this->_stack.size() - 1);
	// Выполняем переход к следующей разметке
	this->advance(end);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора примечания
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseComment() noexcept {
	// Выполняем поиск конца примечания
	const size_t stop = this->_buffer.find("-->", this->_offset + 4);
	/**
	 * Если конец примечания не обнаружен
	 */
	if(stop == string::npos){
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку построения примечания
			return this->fail(error_t::INVALID_COMMENT, this->_offset);
		/**
		 * Если объём события превысил допустимый
		 */
		if((this->_settings.maxEvent > 0) && ((this->_buffer.size() - this->_offset) > this->_settings.maxEvent))
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим требование следующего куска исходного текста
		return step_t::HUNGRY;
	}
	// Получаем содержимое примечания
	const string_view content(this->_buffer.data() + this->_offset + 4, stop - (this->_offset + 4));
	/**
	 * Если содержимое примечания содержит отведённую договором последовательность
	 */
	if(content.find("--") != string_view::npos)
		// Выводим ошибку построения примечания
		return this->fail(error_t::INVALID_COMMENT, this->_offset);
	/**
	 * Если содержимое примечания окончено знаком переноса
	 *
	 * @note Договор не допускает знака переноса перед завершающей примечание
	 *       последовательностью: примечание «<!--- --->» построено ошибочно
	 */
	if(!content.empty() && (content.back() == '-'))
		// Выводим ошибку построения примечания
		return this->fail(error_t::INVALID_COMMENT, this->_offset);
	/**
	 * Если примечания выдаются отдельным событием
	 */
	if(this->_settings.comments){
		/**
		 * Если содержимое примечания требует приведения
		 */
		if(content.find('\r') != string_view::npos){
			// Выполняем очистку хранилища приведённых значений
			this->_scratch.clear();
			/**
			 * Выполняем перебор всех знаков содержимого примечания
			 */
			for(size_t i = 0; i < content.length(); i++){
				/**
				 * Если обнаружен возврат каретки
				 */
				if(content[i] == '\r'){
					// Выполняем добавление перевода строки к приведённому содержимому
					this->_scratch.push_back('\n');
					/**
					 * Если возврат каретки записан вместе с переводом строки
					 */
					if(((i + 1) < content.length()) && (content[i + 1] == '\n'))
						// Выполняем пропуск перевода строки
						i++;
					// Выполняем переход к следующему знаку содержимого
					continue;
				}
				// Выполняем добавление очередного знака к приведённому содержимому
				this->_scratch.push_back(content[i]);
			}
			// Запоминаем приведённое содержимое примечания
			this->_text = string_view(this->_scratch.data(), this->_scratch.size());
		// Запоминаем содержимое примечания без приведения
		} else this->_text = content;
		// Запоминаем вид полученного события разбора
		this->_event = event_t::COMMENT;
		// Запоминаем глубину вложенности узла события
		this->_depth = static_cast <uint32_t> (this->_stack.size());
	}
	/**
	 * Если примечание пересекает границу подставленной сущности
	 */
	if(this->crosses(this->_offset, stop + 3))
		// Выводим ошибку пересечения границы подставленной сущности
		return this->fail(error_t::ENTITY_BOUNDARY, this->_offset);
	// Выполняем переход к следующей разметке
	this->advance(stop + 3);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора раздела дословного текста
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseCdata() noexcept {
	/**
	 * Если разбор ещё не вошёл в раздел дословного текста
	 */
	if(!this->_cdata){
		/**
		 * Если раздел дословного текста расположен вне корневого узла
		 */
		if(this->_stack.empty())
			// Выводим ошибку содержимого вне корневого узла
			return this->fail(error_t::CONTENT_OUTSIDE_ROOT, this->_offset);
		// Запоминаем начало раздела дословного текста
		this->_section = this->_offset;
		// Выполняем переход к содержимому раздела дословного текста
		this->advance(this->_offset + 9);
		// Запоминаем, что разбор вошёл в раздел дословного текста
		this->_cdata = true;
	}
	// Получаем размер приведённого исходного текста
	const size_t size = this->_buffer.size();
	// Выполняем поиск конца раздела дословного текста
	const size_t stop = this->_buffer.find("]]>", this->_offset);
	// Конец выдаваемой части содержимого раздела
	size_t end = 0;
	/**
	 * Если конец раздела дословного текста обнаружен
	 */
	if(stop != string::npos)
		// Запоминаем конец выдаваемой части содержимого
		end = stop;
	/**
	 * Если конец раздела дословного текста не обнаружен
	 */
	else {
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку построения раздела дословного текста
			return this->fail(error_t::INVALID_CDATA, this->_offset);
		/**
		 * Если настройки требуют склеивать содержимое в одно событие
		 *
		 * @note Склейка обязана делать разбиение исходного текста на куски
		 *       незаметным: раздел выдаётся целиком, как и текстовое содержимое
		 */
		if(this->_settings.mergeText){
			/**
			 * Если объём события превысил допустимый
			 */
			if((this->_settings.maxEvent > 0) && ((size - this->_offset) > this->_settings.maxEvent))
				// Выводим ошибку превышения заданного настройками предела
				return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
			// Выводим требование следующего куска исходного текста
			return step_t::HUNGRY;
		}
		/**
		 * Если выдавать пока нечего
		 *
		 * @note Последние байты куска удерживаются: завершение раздела, разорванное
		 *       границей куска, иначе останется незамеченным
		 */
		if((size - this->_offset) <= CDATA_MARGIN)
			// Выводим требование следующего куска исходного текста
			return step_t::HUNGRY;
		// Запоминаем конец выдаваемой части содержимого
		end = (size - CDATA_MARGIN);
		/**
		 * Если содержимое оборвано возвратом каретки
		 */
		if(this->_buffer[end - 1] == '\r')
			// Выполняем изъятие возврата каретки из выдаваемой части
			end--;
		/**
		 * Если выдавать пока нечего
		 */
		if(end <= this->_offset)
			// Выводим требование следующего куска исходного текста
			return step_t::HUNGRY;
	}
	// Получаем содержимое раздела дословного текста
	const string_view content(this->_buffer.data() + this->_offset, end - this->_offset);
	/**
	 * Если содержимое раздела требует приведения
	 */
	if(content.find('\r') != string_view::npos){
		// Выполняем очистку хранилища приведённых значений
		this->_scratch.clear();
		/**
		 * Выполняем перебор всех знаков содержимого раздела
		 */
		for(size_t i = 0; i < content.length(); i++){
			/**
			 * Если обнаружен возврат каретки
			 */
			if(content[i] == '\r'){
				// Выполняем добавление перевода строки к приведённому содержимому
				this->_scratch.push_back('\n');
				/**
				 * Если возврат каретки записан вместе с переводом строки
				 */
				if(((i + 1) < content.length()) && (content[i + 1] == '\n'))
					// Выполняем пропуск перевода строки
					i++;
				// Выполняем переход к следующему знаку содержимого
				continue;
			}
			// Выполняем добавление очередного знака к приведённому содержимому
			this->_scratch.push_back(content[i]);
		}
		// Запоминаем приведённое содержимое раздела
		this->_text = string_view(this->_scratch.data(), this->_scratch.size());
	// Запоминаем содержимое раздела без приведения
	} else this->_text = content;
	// Запоминаем вид полученного события разбора
	this->_event = event_t::CDATA;
	// Запоминаем глубину вложенности узла события
	this->_depth = static_cast <uint32_t> (this->_stack.size() - 1);
	/**
	 * Если конец раздела дословного текста обнаружен
	 */
	if(stop != string::npos){
		/**
		 * Если раздел дословного текста пересекает границу подставленной сущности
		 */
		if(this->crosses(this->_section, stop + 3))
			// Выводим ошибку пересечения границы подставленной сущности
			return this->fail(error_t::ENTITY_BOUNDARY, this->_section);
		// Запоминаем, что разбор вышел из раздела дословного текста
		this->_cdata = false;
		// Выполняем переход к следующей разметке
		this->advance(stop + 3);
	// Выполняем переход к оставшейся части содержимого раздела
	} else this->advance(end);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора указания обработчику и объявления разметки
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseProcessing() noexcept {
	// Выполняем поиск конца указания обработчику
	const size_t end = this->_buffer.find("?>", this->_offset + 2);
	/**
	 * Если конец указания обработчику не обнаружен
	 */
	if(end == string::npos){
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку построения указания обработчику
			return this->fail(error_t::INVALID_PROCESSING, this->_offset);
		/**
		 * Если объём события превысил допустимый
		 */
		if((this->_settings.maxEvent > 0) && ((this->_buffer.size() - this->_offset) > this->_settings.maxEvent))
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим требование следующего куска исходного текста
		return step_t::HUNGRY;
	}
	// Положение разбора указания обработчику
	size_t pos = (this->_offset + 2);
	// Префикс цели указания обработчику
	string_view prefix;
	// Цель указания обработчику
	string_view target;
	/**
	 * Если цель указания обработчику разобрать не удалось
	 */
	if(!this->parseName(pos, end, prefix, target) || !prefix.empty())
		// Выводим ошибку построения указания обработчику
		return this->fail(error_t::INVALID_PROCESSING, this->_offset + 2);
	/**
	 * Если за целью указания обработчику стоит знак, целью не разделённый
	 *
	 * @details Договор велит отделять цель от передаваемых ею данных пробельным знаком,
	 *          а без данных - завершать указание сразу. Разбор имени останавливается на
	 *          первом знаке, имени не принадлежащем, и всё, что за ним, прежде уходило в
	 *          данные молча: запись вида `<?pi[d?>` принималась указанием с целью `pi`,
	 *          тогда как правильно построенным указанием она не является
	 *
	 * @note Конец разметки проверяется наравне с пробельным знаком: указание вправе не
	 *       нести данных вовсе, и запись `<?pi?>` договором допущена
	 */
	if((pos < end) && !::isSpace(this->_buffer[pos]) &&
	   !((this->_buffer[pos] == '?') && ((pos + 1) < this->_buffer.size()) && (this->_buffer[pos + 1] == '>')))
		// Выводим ошибку построения указания обработчику
		return this->fail(error_t::INVALID_PROCESSING, pos);
	/**
	 * Если указание обработчику стоит в самом начале исходного текста и названо
	 * отведённым договором именем
	 *
	 * @details Начало текста отведено объявлению разметки, а оно опознаётся по имени
	 *          «xml» с пробельным знаком следом. Имя, начатое теми же тремя знаками и
	 *          продолженное дальше, объявлением не является, но и указанием обработчику
	 *          в этом месте быть не вправе: договор оставляет имена, начатые «xml», за
	 *          собой, и разбор, принявший такое указание, молча пропустил бы объявление
	 *          разметки, записанное без пробела
	 *
	 * @note Проверка ограничена самым началом текста намеренно: имя «xml-stylesheet»
	 *       отведено договором о стилевых таблицах и встречается повсеместно - отвергать
	 *       его всюду значило бы отвергать правильно построенные тексты
	 */
	if((target.length() > 3) && ((this->_consumed + this->_offset) == 0) &&
	   ascii::equals(target[0], 'x') && ascii::equals(target[1], 'm') && ascii::equals(target[2], 'l') &&
	   (target[3] != '-'))
		// Выводим ошибку использования отведённого договором имени
		return this->fail(error_t::RESERVED_PROCESSING, this->_offset + 2);
	/**
	 * Если целью указания обработчику является отведённое договором имя
	 */
	if((target.length() == 3) && ascii::equals(target[0], 'x') && ascii::equals(target[1], 'm') && ascii::equals(target[2], 'l')){
		/**
		 * Если имя записано не так, как предписано договором объявлению разметки
		 */
		if(target != "xml")
			// Выводим ошибку использования отведённого договором имени
			return this->fail(error_t::RESERVED_PROCESSING, this->_offset + 2);
		/**
		 * Если объявление разметки расположено не в самом начале текста
		 */
		if(this->_declared || this->_root || !this->_stack.empty() || ((this->_consumed + this->_offset) != 0))
			// Выводим ошибку использования отведённого договором имени
			return this->fail(error_t::RESERVED_PROCESSING, this->_offset + 2);
		/**
		 * Получаем содержимое объявления разметки
		 *
		 * @details Объявление разметки разбирается строго по заданному договором
		 * строению, а не поиском полей по названию: порядок полей задан, разделители
		 * между ними обязательны, и объявление вида «<?xml encoding="UTF-8"
		 * version="1.0"?>» построено ошибочно, хотя оба поля в нём и присутствуют
		 */
		const string_view content(this->_buffer.data() + pos, end - pos);
		// Положение разбора содержимого объявления разметки
		size_t at = 0;
		/**
		 * @brief Метод пропуска пробельных знаков объявления разметки
		 *
		 * @param required признак обязательности пробельного знака
		 * @return         результат выполнения операции
		 *
		 */
		const auto spaces = [&content, &at](const bool required) noexcept -> bool {
			// Запоминаем начало пропускаемых пробельных знаков
			const size_t begin = at;
			/**
			 * Выполняем пропуск пробельных знаков
			 */
			while((at < content.length()) && ::isSpace(content[at]))
				// Выполняем переход к следующему знаку
				at++;
			// Выводим результат выполнения операции
			return (!required || (at > begin));
		};
		/**
		 * @brief Метод разбора значения поля объявления разметки
		 *
		 * @param name  название разбираемого поля
		 * @param value значение разобранного поля
		 * @return      результат обнаружения поля
		 *
		 */
		/**
		 * Признак того, что поле объявления построено ошибочно
		 *
		 * @details Отсутствие поля и ошибочное его построение - поводы разные, а итог у
		 *          разбора поля один. Не разведи мы их, объявление вида `encoding=` без
		 *          значения сошло бы за объявление без поля кодировки вовсе: разбор
		 *          принял бы его, а договор такое объявление отвергает
		 */
		bool broken = false;
		const auto field = [&content, &at, &spaces, &broken](const string_view name, string_view & value) noexcept -> bool {
			// Запоминаем положение разбора до пропуска пробельных знаков
			const size_t begin = at;
			/**
			 * Если поле не отделено пробельным знаком либо записано иначе
			 */
			if(!spaces(true) || ((at + name.length()) > content.length()) ||
			   (content.substr(at, name.length()) != name)){
				// Выполняем возврат разбора к пропущенным пробельным знакам
				at = begin;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к разделителю названия и значения поля
			at += name.length();
			// Выполняем пропуск пробельных знаков перед разделителем
			spaces(false);
			/**
			 * Если разделитель названия и значения поля отсутствует
			 *
			 * @note Название поля уже совпало, и отсутствие у него значения означает
			 *       ошибочно построенное объявление, а не отсутствие поля
			 */
			if((at >= content.length()) || (content[at] != '=')){
				// Запоминаем, что поле объявления построено ошибочно
				broken = true;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем переход к значению поля
			at++;
			// Выполняем пропуск пробельных знаков после разделителя
			spaces(false);
			/**
			 * Если значение поля не заключено в кавычки
			 */
			if((at >= content.length()) || ((content[at] != '"') && (content[at] != '\''))){
				// Запоминаем, что поле объявления построено ошибочно
				broken = true;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Получаем знак кавычки, которым заключено значение
			const char quote = content[at++];
			// Выполняем поиск конца значения поля
			const size_t stop = content.find(quote, at);
			/**
			 * Если конец значения поля не обнаружен
			 */
			if(stop == string_view::npos){
				// Запоминаем, что поле объявления построено ошибочно
				broken = true;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем значение разобранного поля
			value = content.substr(at, stop - at);
			// Выполняем переход к концу значения поля
			at = (stop + 1);
			// Выводим положительный результат выполнения операции
			return true;
		};
		// Объявленное издание разметки
		string_view version;
		/**
		 * Если объявленное издание разметки разобрать не удалось
		 *
		 * @note Поле объявленного издания разметки договор задаёт обязательным и
		 *       стоящим первым: объявление без него построено ошибочно
		 */
		if(!field("version", version))
			// Выводим ошибку построения объявления разметки
			return this->fail(error_t::INVALID_DECLARATION, this->_offset);
		/**
		 * Если объявленное издание разметки не поддерживается
		 */
		if(!::supported(version))
			// Выводим ошибку неподдерживаемого издания разметки
			return this->fail(error_t::UNSUPPORTED_VERSION, this->_offset);
		// Запоминаем объявленное издание разметки
		this->_version.assign(version);
		// Объявленная кодировка исходного текста
		string_view encoding;
		/**
		 * Если объявлена кодировка исходного текста
		 */
		if(field("encoding", encoding)){
			/**
			 * Если название кодировки пусто либо начато недопустимым знаком
			 */
			if(encoding.empty() || !ascii::isAlpha(encoding.front()))
				// Выводим ошибку построения объявления разметки
				return this->fail(error_t::INVALID_DECLARATION, this->_offset);
			/**
			 * Выполняем перебор всех знаков названия кодировки
			 */
			for(const char letter : encoding){
				/**
				 * Если знак недопустим в названии кодировки
				 */
				if(!ascii::isAlnum(letter) && (letter != '.') && (letter != '_') && (letter != '-'))
					// Выводим ошибку построения объявления разметки
					return this->fail(error_t::INVALID_DECLARATION, this->_offset);
			}
			/**
			 * Если кодировка исходного текста задана меткой порядка байтов
			 *
			 * @note Расхождение объявленной кодировки с меткой порядка байтов
			 *       приведением не улавливается лишь для кодировок UTF-16: объявление
			 *       читается там уже приведённым. Метка достовернее объявления -
			 *       объявление является частью текста, а метка стоит перед ним
			 */
			if(this->_decoder.signature()){
				// Получаем кодировку исходного текста, определённую меткой порядка байтов
				const encoding_t marked = this->_decoder.encoding();
				/**
				 * Если объявленная кодировка расходится с меткой порядка байтов
				 */
				if(((marked == encoding_t::UTF16LE) || (marked == encoding_t::UTF16BE)) &&
				   (xml::encoding(encoding) != marked))
					// Выводим ошибку расхождения объявленной кодировки с меткой
					return this->fail(error_t::INVALID_ENCODING, this->_offset);
			}
		}
		// Объявленный признак самодостаточности текста
		string_view standalone;
		/**
		 * Если объявлен признак самодостаточности текста
		 */
		if(field("standalone", standalone)){
			/**
			 * Если текст объявлен самодостаточным
			 */
			if(standalone == "yes")
				// Запоминаем признак самодостаточности текста
				this->_standalone = standalone_t::YES;
			/**
			 * Если текст объявлен зависящим от внешнего подмножества
			 */
			else if(standalone == "no")
				// Запоминаем признак самодостаточности текста
				this->_standalone = standalone_t::NO;
			/**
			 * Если признак самодостаточности записан ошибочно
			 */
			else return this->fail(error_t::INVALID_DECLARATION, this->_offset);
		}
		// Выполняем пропуск пробельных знаков перед концом объявления разметки
		spaces(false);
		/**
		 * Если поле объявления разметки построено ошибочно
		 *
		 * @note Проверка стоит здесь, а не у каждого поля: поля необязательны, и разбор
		 *       их идёт по порядку - ошибочное построение любого из них замечается
		 *       одинаково, где бы оно ни встретилось
		 */
		if(broken)
			// Выводим ошибку построения объявления разметки
			return this->fail(error_t::INVALID_DECLARATION, this->_offset);
		/**
		 * Если объявление разметки прочитано не до конца
		 */
		if(at < content.length())
			// Выводим ошибку построения объявления разметки
			return this->fail(error_t::INVALID_DECLARATION, this->_offset);
		// Запоминаем, что объявление разметки встречено
		this->_declared = true;
		// Запоминаем объявленное издание разметки как содержимое события
		this->_text = string_view(this->_version.data(), this->_version.size());
		// Запоминаем вид полученного события разбора
		this->_event = event_t::DECLARATION;
		// Выполняем переход к следующей разметке
		this->advance(end + 2);
		// Выводим итог выполненного шага разбора
		return step_t::DONE;
	}
	/**
	 * Если указания обработчику выдаются отдельным событием
	 */
	if(this->_settings.processing){
		/**
		 * Выполняем пропуск пробельных знаков перед данными указания
		 */
		while((pos < end) && ::isSpace(this->_buffer[pos]))
			// Выполняем переход к следующему знаку
			pos++;
		// Запоминаем цель указания обработчику
		this->_name.local = target;
		// Получаем данные указания обработчику
		const string_view content(this->_buffer.data() + pos, end - pos);
		/**
		 * Если данные указания требуют приведения
		 *
		 * @note Приведение конца строки договор относит ко всему исходному тексту без
		 *       изъятий, а не к одному лишь содержимому узлов: возврат каретки обязан
		 *       дойти переводом строки и здесь
		 */
		if(content.find('\r') != string_view::npos){
			// Выполняем очистку хранилища приведённых значений
			this->_scratch.clear();
			/**
			 * Выполняем перебор всех знаков данных указания
			 */
			for(size_t i = 0; i < content.length(); i++){
				/**
				 * Если обнаружен возврат каретки
				 */
				if(content[i] == '\r'){
					// Выполняем добавление перевода строки к приведённым данным
					this->_scratch.push_back('\n');
					/**
					 * Если возврат каретки записан вместе с переводом строки
					 */
					if(((i + 1) < content.length()) && (content[i + 1] == '\n'))
						// Выполняем пропуск перевода строки
						i++;
					// Выполняем переход к следующему знаку данных
					continue;
				}
				// Выполняем добавление очередного знака к приведённым данным
				this->_scratch.push_back(content[i]);
			}
			// Запоминаем приведённые данные указания обработчику
			this->_text = string_view(this->_scratch.data(), this->_scratch.size());
		// Запоминаем данные указания обработчику без приведения
		} else this->_text = content;
		// Запоминаем вид полученного события разбора
		this->_event = event_t::PROCESSING;
		// Запоминаем глубину вложенности узла события
		this->_depth = static_cast <uint32_t> (this->_stack.size());
	}
	// Выполняем переход к следующей разметке
	this->advance(end + 2);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора описания типа документа
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseDoctype() noexcept {
	/**
	 * Если описание типа документа расположено не на своём месте
	 */
	if(this->_root || this->_doctype || !this->_stack.empty())
		// Выводим ошибку расположения описания типа документа
		return this->fail(error_t::DOCTYPE_MISPLACED, this->_offset);
	// Получаем размер приведённого исходного текста
	const size_t size = this->_buffer.size();
	/**
	 * Восстанавливаем ход поиска конца описания типа документа
	 *
	 * @note Положения удержаны отсчётом от начала описания: изъятие разобранного
	 *       начала буфера их не обесценивает
	 */
	char quote = this->_survey.quote;
	// Восстанавливаем признак нахождения внутри внутреннего подмножества
	bool inside = this->_survey.inside;
	// Положение конца описания типа документа
	size_t end = string::npos;
	// Восстанавливаем положение начала внутреннего подмножества
	size_t begin = (this->_survey.begin == string::npos ? string::npos : (this->_offset + this->_survey.begin));
	// Восстанавливаем положение конца внутреннего подмножества
	size_t stop = (this->_survey.stop == string::npos ? string::npos : (this->_offset + this->_survey.stop));
	// Положение, достигнутое поиском конца описания типа документа
	size_t pos = (this->_offset + this->_survey.offset);
	/**
	 * Выполняем поиск конца описания типа документа
	 */
	for(; pos < size; pos++){
		// Получаем очередной знак описания типа документа
		const char letter = this->_buffer[pos];
		/**
		 * Если разбор находится внутри значения
		 */
		if(quote != 0){
			/**
			 * Если обнаружен конец значения
			 */
			if(letter == quote)
				// Выполняем сброс знака кавычки
				quote = 0;
			// Выполняем переход к следующему знаку
			continue;
		}
		/**
		 * Если началом разметки внутри описания оканчивается кусок текста
		 *
		 * @details Вид разметки внутри описания различается четырьмя знаками её начала,
		 *          и на хвосте куска этих знаков может недоставать. Перебор с начала
		 *          такой хвост перечитал бы следующим куском сам собой, а удерживаемый
		 *          ход обязан на нём остановиться: шагни поиск дальше, примечание,
		 *          разорванное границей куска, осталось бы неопознанным, и одинокий
		 *          апостроф внутри него сошёл бы за начало значения
		 */
		if((letter == '<') && !this->_final && ((size - pos) < 4))
			// Выходим из поиска конца описания
			break;
		/**
		 * Если обнаружено начало примечания
		 *
		 * @note Примечание пропускается целиком: знаки кавычек внутри него значений
		 *       не заключают, а обычное примечание вполне может нести одинокий
		 *       апостроф - скажем, в слове английского языка
		 */
		if((this->_buffer.compare(pos, 4, "<!--") == 0)){
			// Выполняем поиск конца примечания
			const size_t finish = this->_buffer.find("-->", pos + 4);
			/**
			 * Если конец примечания не обнаружен
			 */
			if(finish == string::npos)
				// Выходим из поиска конца описания
				break;
			// Выполняем переход к концу примечания
			pos = (finish + 2);
			// Выполняем переход к следующему знаку
			continue;
		}
		/**
		 * Если обнаружено начало указания обработчику
		 */
		if((this->_buffer.compare(pos, 2, "<?") == 0)){
			// Выполняем поиск конца указания обработчику
			const size_t finish = this->_buffer.find("?>", pos + 2);
			/**
			 * Если конец указания обработчику не обнаружен
			 */
			if(finish == string::npos)
				// Выходим из поиска конца описания
				break;
			// Выполняем переход к концу указания обработчику
			pos = (finish + 1);
			// Выполняем переход к следующему знаку
			continue;
		}
		/**
		 * Определяем очередной знак описания типа документа
		 */
		switch(letter){
			// Если обнаружено начало значения
			case '"':
			case '\'':
				// Запоминаем знак кавычки, которым заключено значение
				quote = letter;
			break;
			// Если обнаружено начало внутреннего подмножества
			case '[': {
				// Запоминаем, что разбор находится внутри внутреннего подмножества
				inside = true;
				// Запоминаем положение начала внутреннего подмножества
				begin = (pos + 1);
			} break;
			// Если обнаружен конец внутреннего подмножества
			case ']': {
				// Запоминаем, что разбор вышел из внутреннего подмножества
				inside = false;
				// Запоминаем положение конца внутреннего подмножества
				stop = pos;
			} break;
			// Если обнаружен конец описания типа документа
			case '>': {
				/**
				 * Если разбор не находится внутри внутреннего подмножества
				 */
				if(!inside)
					// Запоминаем положение конца описания типа документа
					end = pos;
			} break;
		}
		/**
		 * Если конец описания типа документа обнаружен
		 */
		if(end != string::npos)
			// Выходим из поиска конца описания
			break;
	}
	/**
	 * Если конец описания типа документа не обнаружен
	 */
	if(end == string::npos){
		/**
		 * Удерживаем достигнутое поиском положение до прихода следующего куска
		 *
		 * @note Знак кавычки и признак нахождения внутри подмножества удерживаются
		 *       вместе с положением: без них поиск, продолженный с середины значения,
		 *       принял бы его содержимое за разметку описания
		 */
		this->_survey.offset = (pos > this->_offset ? (pos - this->_offset) : 9);
		// Удерживаем знак кавычки, которым заключено значение внутри описания
		this->_survey.quote = quote;
		// Удерживаем признак нахождения внутри внутреннего подмножества
		this->_survey.inside = inside;
		// Удерживаем положение начала внутреннего подмножества
		this->_survey.begin = (begin == string::npos ? string::npos : (begin - this->_offset));
		// Удерживаем положение конца внутреннего подмножества
		this->_survey.stop = (stop == string::npos ? string::npos : (stop - this->_offset));
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку построения описания типа документа
			return this->fail(error_t::INVALID_DOCTYPE, this->_offset);
		/**
		 * Если объём события превысил допустимый
		 */
		if((this->_settings.maxEvent > 0) && ((size - this->_offset) > this->_settings.maxEvent))
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим требование следующего куска исходного текста
		return step_t::HUNGRY;
	}
	// Выполняем возврат к началу разбора описания типа документа
	pos = (this->_offset + 9);
	/**
	 * Если имя описываемого типа документа не отделено пробельным знаком
	 */
	if(!this->subsetSpace(pos, end, true))
		// Выводим ошибку построения описания типа документа
		return this->fail(error_t::INVALID_DOCTYPE, pos);
	// Запоминаем начало имени описываемого типа документа
	const size_t name = pos;
	/**
	 * Если имя описываемого типа документа разобрать не удалось
	 */
	if(!this->subsetName(pos, end, false))
		// Выводим ошибку построения описания типа документа
		return this->fail(error_t::INVALID_DOCTYPE, pos);
	// Запоминаем конец имени описываемого типа документа
	const size_t title = pos;
	/**
	 * Получаем положение конца заголовка описания типа документа
	 *
	 * @note Заголовок оканчивается началом внутреннего подмножества, а при его
	 *       отсутствии - концом всего описания
	 */
	const size_t header = ((begin != string::npos) ? (begin - 1) : end);
	// Признак обнаружения обозначения внешнего источника
	bool external = false;
	/**
	 * Если обозначение внешнего источника не отделено пробельным знаком
	 */
	if(this->subsetSpace(pos, header, true)){
		/**
		 * Если обозначение внешнего источника разобрать не удалось
		 */
		if(!this->subsetExternal(pos, header, true, external))
			// Выводим ошибку построения описания типа документа
			return this->fail(error_t::INVALID_DOCTYPE, pos);
		/**
		 * Если у описания типа документа объявлено внешнее подмножество
		 *
		 * @note Читать его разбор не берётся, а объявления сущностей вправе лежать
		 *       именно там: пока подмножество объявлено, недостача объявления
		 *       построения текста не порочит
		 */
		if(external)
			// Запоминаем, что объявления могут приходить извне разобранного
			this->_foreign = true;
		// Выполняем пропуск пробельных знаков после обозначения источника
		this->subsetSpace(pos, header, false);
	}
	/**
	 * Если заголовок описания типа документа прочитан не до конца
	 */
	if(pos < header)
		// Выводим ошибку построения описания типа документа
		return this->fail(error_t::INVALID_DOCTYPE, pos);
	/**
	 * Если внутреннее подмножество описания типа документа обнаружено
	 */
	if((begin != string::npos) && (stop != string::npos) && (stop > begin)){
		/**
		 * Если разбор внутреннего подмножества выполнить не удалось
		 */
		if(!this->parseSubset(begin, stop))
			// Выводим ошибку разбора внутреннего подмножества
			return this->fail(this->_error, begin);
	}
	/**
	 * Если внутреннее подмножество закрыто
	 *
	 * @details За закрывающей скобкой подмножества договор допускает лишь пробельные
	 *          знаки до конца описания типа документа. Ссылка на параметрическую
	 *          сущность там уже вне подмножества, и разобрать её негде: разбор,
	 *          пропустивший её молча, принял бы описание, договором не допущенное
	 */
	if(stop != string::npos){
		/**
		 * Выполняем перебор знаков между концом подмножества и концом описания
		 */
		for(size_t i = (stop + 1); i < end; i++){
			/**
			 * Если обнаружен знак, не являющийся пробельным
			 */
			if(!::isSpace(this->_buffer[i]))
				// Выводим ошибку построения описания типа документа
				return this->fail(error_t::INVALID_DOCTYPE, i);
		}
	}
	// Выполняем сброс хода поиска конца описания типа документа
	this->_survey = survey_t();
	// Запоминаем, что описание типа документа встречено
	this->_doctype = true;
	// Запоминаем имя описываемого типа документа как содержимое события
	this->_text = string_view(this->_buffer.data() + name, title - name);
	// Запоминаем вид полученного события разбора
	this->_event = event_t::DOCTYPE;
	// Выполняем переход к следующей разметке
	this->advance(end + 1);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод добавления разобранного атрибута к перечню узла
 *
 * @param record разобранный атрибут узла
 *
 */
void awh::codec::xml::Reader::append(const record_t & record) noexcept {
	/**
	 * Если атрибут является объявлением пространства имён
	 */
	if(this->_settings.namespaces && ((record.prefix == "xmlns") || (record.prefix.empty() && (record.local == "xmlns")))){
		// Выполняем добавление объявления к перечню узла
		this->_declares.push_back(record);
		// Выходим из метода
		return;
	}
	// Собираемый атрибут узла
	attribute_t attribute;
	// Запоминаем префикс имени атрибута
	attribute.name.prefix = record.prefix;
	// Запоминаем местное имя атрибута
	attribute.name.local = record.local;
	// Запоминаем положение атрибута в исходном тексте
	attribute.location = record.location;
	// Запоминаем признак значения, взятого из объявления по умолчанию
	attribute.defaulted = record.defaulted;
	// Выполняем добавление отрезка значения атрибута
	this->_values.push_back(record.value);
	// Выполняем добавление ключа имени атрибута
	this->_keys.push_back(::key(record.local));
	// Выполняем добавление атрибута к перечню узла
	this->_attributes.push_back(attribute);
}
/**
 * @brief Метод разрешения пространств имён текущего узла
 *
 * @return результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::bind() noexcept {
	// Количество связываний префиксов, объявленных узлом
	uint32_t count = 0;
	/**
	 * Если разрешение префиксов по договору о пространствах имён включено
	 */
	if(this->_settings.namespaces){
		/**
		 * Выполняем перебор всех разобранных атрибутов узла
		 *
		 * @note Объявления пространств имён обрабатываются раньше прочих атрибутов:
		 *       объявление действует и в том узле, где записано, а порядок записи
		 *       атрибутов в разметке смысла не имеет
		 */
		/**
		 * Если объявлений пространств имён у узла больше, чем стоит сличать попарно
		 *
		 * @details Попарное сличение растёт квадратом от числа объявлений, а настройками
		 *          атрибутов дозволено до нескольких тысяч: узел с шестью десятками тысяч
		 *          объявлений разбирался бы три секунды вместо трёх сотых. Раскладка по
		 *          свёртке сводит совпадающие объявления в соседи, и сличать остаётся лишь
		 *          соседей - ровно тем же способом, каким сличаются и обычные атрибуты
		 *
		 * @note Порядок задан полным, а не одной лишь свёрткой: свёртка криптографической
		 *       не является, и подставной текст волен назвать префиксы так, чтобы свёртки
		 *       у всех совпали. Раскладка по одной свёртке свела бы их тогда в единую
		 *       вереницу, и сличение внутри неё вернуло бы рост квадратом
		 */
		if(this->_declares.size() > 32){
			// Выполняем очистку раскладки объявлений по свёртке
			this->_digests.clear();
			/**
			 * Выполняем перебор всех объявлений пространств имён узла
			 */
			for(size_t i = 0; i < this->_declares.size(); i++){
				// Собираемая запись раскладки объявления
				digest_t item;
				// Запоминаем положение объявления в перечне узла
				item.index = static_cast <uint32_t> (i);
				// Выполняем свёртку объявления по его имени и префиксу
				item.hash = ::digest(this->_declares[i].local, this->_declares[i].prefix);
				// Выполняем добавление записи к раскладке
				this->_digests.push_back(item);
			}
			// Выполняем раскладку записей по свёртке и по самому объявлению
			::sort(this->_digests.begin(), this->_digests.end(), [this](const digest_t & first, const digest_t & second) noexcept -> bool {
				// Если свёртки объявлений не совпадают, сличаем сами свёртки
				if(first.hash != second.hash) return (first.hash < second.hash);
				// Получаем имя первого сличаемого объявления
				const string_view local = this->_declares[first.index].local;
				// Получаем имя второго сличаемого объявления
				const string_view other = this->_declares[second.index].local;
				// Если имена объявлений не совпадают, сличаем сами имена
				if(local != other) return (local < other);
				// Выводим результат сличения префиксов объявлений
				return (this->_declares[first.index].prefix < this->_declares[second.index].prefix);
			});
			/**
			 * Выполняем перебор соседей разложенной вереницы объявлений
			 */
			for(size_t i = 1; i < this->_digests.size(); i++){
				// Получаем предыдущее объявление разложенной вереницы
				const record_t & previous = this->_declares[this->_digests[i - 1].index];
				// Получаем очередное объявление разложенной вереницы
				const record_t & current = this->_declares[this->_digests[i].index];
				/**
				 * Если объявление для того же префикса уже получено
				 */
				if((previous.local == current.local) && (previous.prefix == current.prefix)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::DUPLICATE_ATTRIBUTE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
		}
		/**
		 * Признак того, что совпадения отыскиваются попарным сличением
		 *
		 * @note Узлов с десятком объявлений в разметке подавляющее большинство, и на
		 *       таком количестве попарное сличение обходится дешевле раскладки
		 */
		const bool pairwise = (this->_declares.size() <= 32);
		for(size_t index = 0; index < this->_declares.size(); index++){
			// Получаем очередное объявление пространства имён узла
			const record_t & record = this->_declares[index];
			/**
			 * Выполняем перебор всех ранее полученных объявлений узла
			 *
			 * @note Перебор ведётся лишь там, где объявлений немного: у прочих совпадения
			 *       отсеяны раскладкой выше, и сличать их повторно незачем
			 */
			for(size_t i = 0; pairwise && (i < index); i++){
				/**
				 * Если объявление для того же префикса уже получено
				 */
				if((this->_declares[i].local == record.local) && (this->_declares[i].prefix == record.prefix)){
					// Запоминаем код ошибки разбора
					this->_error = error_t::DUPLICATE_ATTRIBUTE;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
			// Получаем признак объявления пространства имён по умолчанию
			const bool common = record.prefix.empty();
			// Получаем признак объявления пространства имён для префикса
			const bool prefixed = !common;
			// Получаем обозначение объявляемого пространства имён
			const string_view uri(this->_scratch.data() + record.value.offset, record.value.length);
			/**
			 * Если объявление пространства имён выполняется для префикса
			 */
			if(prefixed){
				/**
				 * Если выполняется попытка переопределить отведённый договором префикс
				 */
				if(record.local == "xmlns"){
					// Запоминаем код ошибки разбора
					this->_error = error_t::RESERVED_PREFIX;
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если объявление выполняется для отведённого договором префикса
				 */
				if(record.local == "xml"){
					/**
					 * Если отведённому договором префиксу дано иное пространство имён
					 */
					if(uri != XML_NAMESPACE){
						// Запоминаем код ошибки разбора
						this->_error = error_t::RESERVED_PREFIX;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
				/**
				 * Если объявление выполняется для обычного префикса
				 */
				} else {
					/**
					 * Если объявлению дано пустое обозначение пространства имён
					 *
					 * @note Отменить связывание префикса издание договора 1.0 не
					 *       позволяет: пустое обозначение здесь является ошибкой
					 */
					if(uri.empty()){
						// Запоминаем код ошибки разбора
						this->_error = error_t::INVALID_NAMESPACE;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					/**
					 * Если обычному префиксу дано отведённое договором пространство имён
					 */
					if(uri == XML_NAMESPACE){
						// Запоминаем код ошибки разбора
						this->_error = error_t::RESERVED_PREFIX;
						// Выводим отрицательный результат выполнения операции
						return false;
					}
				}
			}
			/**
			 * Если объявлению дано пространство имён объявлений
			 */
			if(uri == XMLNS_NAMESPACE){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_NAMESPACE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			/**
			 * Если объявлению по умолчанию дано отведённое договором пространство имён
			 */
			if(common && (uri == XML_NAMESPACE)){
				// Запоминаем код ошибки разбора
				this->_error = error_t::INVALID_NAMESPACE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Собираемое объявление пространства имён
			binding_t binding;
			// Запоминаем префикс объявления пространства имён
			binding.prefix = (common ? string_view() : record.local);
			// Запоминаем обозначение объявляемого пространства имён
			binding.uri = uri;
			// Выполняем добавление объявления к перечню узла
			this->_bindings.push_back(binding);
			// Собираемое связывание префикса с пространством имён
			scope_t scope;
			// Выполняем размещение префикса в хранилище знаков разбора
			scope.prefix = this->store(common ? string_view() : record.local);
			// Выполняем размещение обозначения пространства имён в хранилище знаков
			scope.uri = this->store(uri);
			// Выполняем добавление связывания к действующим
			this->_scopes.push_back(scope);
			// Выполняем подсчёт связываний, объявленных узлом
			count++;
		}
	}
	// Запоминаем количество связываний, объявленных узлом
	this->_stack.back().bindings = count;
	/**
	 * Если разрешение префиксов по договору о пространствах имён включено
	 */
	if(this->_settings.namespaces){
		// Получаем префикс имени текущего узла
		const string_view prefix = this->view(this->_stack.back().name.prefix);
		/**
		 * Если имя узла записано с префиксом
		 */
		if(!prefix.empty()){
			// Выполняем поиск пространства имён по префиксу
			const span_t uri = this->lookup(prefix);
			/**
			 * Если префикс не связан ни с одним пространством имён
			 */
			if(uri.length == 0){
				// Запоминаем код ошибки разбора
				this->_error = error_t::UNBOUND_PREFIX;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Запоминаем обозначение пространства имён узла
			this->_stack.back().name.uri = uri;
		// Запоминаем обозначение пространства имён узла по умолчанию
		} else this->_stack.back().name.uri = this->lookup(string_view());
	}
	/**
	 * Выполняем перебор всех разобранных атрибутов узла
	 */
	for(size_t i = 0; i < this->_attributes.size(); i++){
		// Получаем очередной собираемый атрибут узла
		attribute_t & attribute = this->_attributes[i];
		// Запоминаем значение атрибута, приведённое к окончательному виду
		attribute.value = string_view(this->_scratch.data() + this->_values[i].offset, this->_values[i].length);
		/**
		 * Если имя атрибута записано без префикса
		 *
		 * @note Объявление пространства имён по умолчанию на атрибуты не
		 *       распространяется: атрибут без префикса пространству имён не принадлежит
		 */
		if(!this->_settings.namespaces || attribute.name.prefix.empty())
			// Выполняем переход к следующему атрибуту
			continue;
		// Выполняем поиск пространства имён по префиксу
		const span_t uri = this->lookup(attribute.name.prefix);
		/**
		 * Если префикс не связан ни с одним пространством имён
		 */
		if(uri.length == 0){
			// Запоминаем код ошибки разбора
			this->_error = error_t::UNBOUND_PREFIX;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Запоминаем обозначение пространства имён атрибута
		attribute.name.uri = this->view(uri);
		/**
		 * Если атрибут задаёт обращение с пробельным содержимым
		 */
		if((attribute.name.uri == XML_NAMESPACE) && (attribute.name.local == "space"))
			// Запоминаем обращение с пробельным содержимым внутри узла
			this->_stack.back().space = ((attribute.value == "preserve") ? space_t::PRESERVE : space_t::DEFAULT);
	}
	/**
	 * @brief Метод сличения имён двух собранных атрибутов узла
	 *
	 * @param first  положение первого сличаемого атрибута
	 * @param second положение второго сличаемого атрибута
	 * @return       результат сличения имён атрибутов
	 *
	 */
	const auto same = [this](const size_t first, const size_t second) noexcept -> bool {
		/**
		 * Если местные имена атрибутов не совпадают
		 */
		if(this->_attributes[first].name.local != this->_attributes[second].name.local)
			// Выводим отрицательный результат сличения
			return false;
		/**
		 * Если разрешение префиксов включено
		 *
		 * @note Сличать следует по обозначению пространства имён, а не по префиксу:
		 *       разные префиксы одного пространства имён дают одно и то же имя
		 */
		if(this->_settings.namespaces)
			// Выводим результат сличения обозначений пространств имён
			return (this->_attributes[first].name.uri == this->_attributes[second].name.uri);
		// Выводим результат сличения префиксов имён атрибутов
		return (this->_attributes[first].name.prefix == this->_attributes[second].name.prefix);
	};
	// Получаем количество собранных атрибутов узла
	const size_t total = this->_attributes.size();
	/**
	 * Если атрибутов узла немного
	 *
	 * @details Узлов с десятком атрибутов в разметке подавляющее большинство, и на
	 *          таком количестве попарное сличение ключей обходится дешевле раскладки
	 *          по порядку: ключ отсеивает несовпадающие имена без обращения к памяти,
	 *          а раскладка требует и свёртки каждого имени, и самой сортировки
	 */
	if(total <= 32){
		/**
		 * Выполняем перебор всех собранных атрибутов узла
		 */
		for(size_t i = 1; i < total; i++){
			/**
			 * Выполняем перебор всех ранее собранных атрибутов узла
			 */
			for(size_t j = 0; j < i; j++){
				/**
				 * Если ключи имён атрибутов не совпадают
				 */
				if(this->_keys[i] != this->_keys[j])
					// Выполняем переход к следующему атрибуту
					continue;
				/**
				 * Если имена атрибутов не совпадают
				 */
				if(!same(i, j))
					// Выполняем переход к следующему атрибуту
					continue;
				// Запоминаем код ошибки разбора
				this->_error = error_t::DUPLICATE_ATTRIBUTE;
				// Выводим отрицательный результат выполнения операции
				return false;
			}
		}
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Выполняем раскладку имён атрибутов по свёртке
	 *
	 * @details Попарное сличение растёт квадратом от числа атрибутов, а настройками
	 *          их дозволено до нескольких тысяч: на таком узле разбор проседал бы
	 *          втрое. Раскладка по свёртке сводит совпадающие имена в соседи, и
	 *          сличать остаётся лишь соседей - на разных именах ни одного сличения
	 *
	 * @note Совпадение свёрток совпадения имён не означает, и соседи сличаются полностью:
	 *       свёртка отбирает пары для сличения, а решение выносится по самим именам
	 */
	this->_digests.clear();
	/**
	 * Выполняем перебор всех собранных атрибутов узла
	 */
	for(size_t i = 0; i < total; i++){
		// Собираемая запись раскладки имени атрибута
		digest_t item;
		// Запоминаем положение атрибута в перечне узла
		item.index = static_cast <uint32_t> (i);
		// Выполняем свёртку имени атрибута с учётом пространства имён
		item.hash = ::digest(
			this->_attributes[i].name.local,
			this->_settings.namespaces ? this->_attributes[i].name.uri : this->_attributes[i].name.prefix
		);
		// Выполняем добавление записи к раскладке
		this->_digests.push_back(item);
	}
	/**
	 * Выполняем раскладку записей по свёртке и по самому имени
	 *
	 * @details Порядок задан полным, а не одной лишь свёрткой: свёртка криптографической
	 *          не является, и подставной текст волен назвать атрибуты так, чтобы свёртки
	 *          у всех совпали. Раскладка по одной свёртке свела бы их тогда в единую
	 *          вереницу, и сличение внутри неё вернуло бы рост квадратом - ровно то, ради
	 *          чего раскладка и заводилась. При полном же порядке совпадающие имена
	 *          становятся соседями, и сличения хватает одного на пару соседей
	 *
	 * @note Свёртка стоит в порядке первой не ради надёжности, а ради дешевизны: у
	 *       несовпадающих имён она расходится, и сличение имён знак в знак не требуется
	 */
	::sort(this->_digests.begin(), this->_digests.end(), [this](const digest_t & first, const digest_t & second) noexcept -> bool {
		/**
		 * Если свёртки имён атрибутов не совпадают
		 */
		if(first.hash != second.hash)
			// Выводим результат сличения свёрток имён атрибутов
			return (first.hash < second.hash);
		// Получаем местное имя первого сличаемого атрибута
		const string_view local = this->_attributes[first.index].name.local;
		// Получаем местное имя второго сличаемого атрибута
		const string_view other = this->_attributes[second.index].name.local;
		/**
		 * Если местные имена атрибутов не совпадают
		 */
		if(local != other)
			// Выводим результат сличения местных имён атрибутов
			return (local < other);
		/**
		 * Если разрешение префиксов включено
		 */
		if(this->_settings.namespaces)
			// Выводим результат сличения обозначений пространств имён
			return (this->_attributes[first.index].name.uri < this->_attributes[second.index].name.uri);
		// Выводим результат сличения префиксов имён атрибутов
		return (this->_attributes[first.index].name.prefix < this->_attributes[second.index].name.prefix);
	});
	/**
	 * Выполняем перебор всех соседей раскладки
	 *
	 * @note Полный порядок ставит совпадающие имена рядом, и сличать достаточно соседей:
	 *       имя, совпавшее с не соседним, совпало бы и со всеми, кто между ними
	 */
	for(size_t i = 1; i < this->_digests.size(); i++){
		/**
		 * Если свёртки имён соседей не совпадают
		 */
		if(this->_digests[i - 1].hash != this->_digests[i].hash)
			// Выполняем переход к следующему соседу
			continue;
		/**
		 * Если имена соседей не совпадают
		 */
		if(!same(this->_digests[i].index, this->_digests[i - 1].index))
			// Выполняем переход к следующему соседу
			continue;
		// Запоминаем код ошибки разбора
		this->_error = error_t::DUPLICATE_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод завершения текущего узла разметки
 *
 */
void awh::codec::xml::Reader::closure() noexcept {
	// Получаем завершаемый узел разметки
	const element_t & element = this->_stack.back();
	// Запоминаем префикс имени завершаемого узла
	this->_name.prefix = this->view(element.name.prefix);
	// Запоминаем местное имя завершаемого узла
	this->_name.local = this->view(element.name.local);
	// Запоминаем обозначение пространства имён завершаемого узла
	this->_name.uri = this->view(element.name.uri);
	// Запоминаем обращение с пробельным содержимым завершаемого узла
	this->_space = element.space;
	/**
	 * Выполняем снятие связываний, объявленных завершаемым узлом
	 */
	for(uint32_t i = 0; i < element.bindings; i++)
		// Выполняем снятие очередного связывания
		this->_scopes.pop_back();
	/**
	 * Запоминаем смещение усечения хранилища знаков
	 *
	 * @note Усечение откладывается до следующего события: выданные наружу имена
	 *       завершаемого узла остаются пригодными до конца его обработки
	 */
	this->_truncate = element.qname.offset;
	// Выполняем снятие завершаемого узла со стека
	this->_stack.pop_back();
	// Запоминаем вид полученного события разбора
	this->_event = event_t::ELEMENT_CLOSE;
}
/**
 * @brief Метод разбора открывающей метки узла
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseElement() noexcept {
	// Получаем размер приведённого исходного текста
	const size_t size = this->_buffer.size();
	// Знак кавычки, которым заключено значение атрибута
	char quote = 0;
	// Положение конца открывающей метки узла
	size_t end = string::npos;
	/**
	 * Выполняем поиск конца открывающей метки узла
	 */
	for(size_t pos = (this->_offset + 1); pos < size; pos++){
		// Получаем очередной знак открывающей метки
		const char letter = this->_buffer[pos];
		/**
		 * Если разбор находится внутри значения атрибута
		 */
		if(quote != 0){
			/**
			 * Если обнаружен конец значения атрибута
			 *
			 * @note Значения атрибутов коротки, и перешагивать их поиском по буферу
			 *       дороже, чем пройти по знаку: замер показал потерю в десятую часть
			 */
			if(letter == quote)
				// Выполняем сброс знака кавычки
				quote = 0;
			// Выполняем переход к следующему знаку
			continue;
		}
		/**
		 * Если обнаружено начало значения атрибута
		 */
		if((letter == '"') || (letter == '\'')){
			// Запоминаем знак кавычки, которым заключено значение
			quote = letter;
			// Выполняем переход к следующему знаку
			continue;
		}
		/**
		 * Если обнаружен конец открывающей метки узла
		 */
		if(letter == '>'){
			// Запоминаем положение конца открывающей метки
			end = pos;
			// Выходим из поиска конца метки
			break;
		}
		/**
		 * Если обнаружено начало новой разметки
		 */
		if(letter == '<')
			// Выводим ошибку построения метки
			return this->fail(error_t::INVALID_TAG, pos);
	}
	/**
	 * Если конец открывающей метки узла не обнаружен
	 */
	if(end == string::npos){
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку незакрытой метки
			return this->fail(error_t::UNCLOSED_TAG, this->_offset);
		/**
		 * Если объём события превысил допустимый
		 */
		if((this->_settings.maxEvent > 0) && ((size - this->_offset) > this->_settings.maxEvent))
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим требование следующего куска исходного текста
		return step_t::HUNGRY;
	}
	// Положение разбора открывающей метки узла
	size_t pos = (this->_offset + 1);
	// Префикс имени разбираемого узла
	string_view prefix;
	// Местное имя разбираемого узла
	string_view local;
	/**
	 * Если имя разбираемого узла разобрать не удалось
	 */
	if(!this->parseName(pos, end, prefix, local))
		// Выводим ошибку построения имени либо превышения его длины
		return this->fail((this->_overlong ? error_t::NAME_TOO_LONG : error_t::INVALID_NAME), this->_offset + 1);
	// Получаем имя узла в записи, принятой в исходном тексте
	const string_view qname(this->_buffer.data() + this->_offset + 1, pos - (this->_offset + 1));
	// Выполняем очистку объявлений пространств имён узла
	this->_declares.clear();
	// Выполняем очистку разобранных атрибутов узла
	this->_attributes.clear();
	// Выполняем очистку отрезков значений атрибутов узла
	this->_values.clear();
	// Выполняем очистку ключей имён атрибутов узла
	this->_keys.clear();
	// Выполняем очистку хранилища приведённых значений
	this->_scratch.clear();
	// Место разбираемого атрибута в исходном тексте
	location_t place = this->locate(this->_offset);
	// Положение, до которого место разбираемого атрибута досчитано
	size_t placed = this->_offset;
	/**
	 * Признак того, что место атрибутов узла считается вычитанием
	 *
	 * @details Открывающая метка узла проверяется на простоту счёта места один раз,
	 *          а не пересчитывается перебором для каждого атрибута: метка почти всегда
	 *          состоит из знаков ASCII и переводов строки не содержит, и тогда место
	 *          любого её знака получается сложением с началом метки. Перебор при этом
	 *          обходился в шестую часть всего разбора, а метка с переводом строки или
	 *          знаком вне ASCII по-прежнему досчитывается прежним способом
	 *
	 * @note Внутри подставленной сущности местом всего разобранного считается ссылка на
	 *       саму сущность, и вычитание там неприменимо
	 */
	bool simple = false;
	/**
	 * Признак того, что открывающая метка узла на простоту счёта места уже проверена
	 *
	 * @note Проверка откладывается до первого атрибута: узлов без атрибутов в разметке
	 *       большинство, и платить за проверку они не должны
	 */
	bool checked = false;
	// Признак того, что узел записан самозакрывающейся меткой
	bool empty = false;
	/**
	 * Выполняем перебор всех атрибутов узла
	 */
	for(;;){
		// Запоминаем положение начала разделителя атрибутов
		const size_t begin = pos;
		/**
		 * Выполняем пропуск пробельных знаков
		 */
		while((pos < end) && ::isSpace(this->_buffer[pos]))
			// Выполняем переход к следующему знаку
			pos++;
		/**
		 * Если открывающая метка узла прочитана до конца
		 */
		if(pos >= end)
			// Выходим из перебора атрибутов
			break;
		/**
		 * Если обнаружено завершение самозакрывающейся метки
		 */
		if(this->_buffer[pos] == '/'){
			// Запоминаем, что узел записан самозакрывающейся меткой
			empty = true;
			// Выполняем переход к концу метки
			pos++;
			/**
			 * Если завершение метки записано ошибочно
			 */
			if(pos != end)
				// Выводим ошибку построения метки
				return this->fail(error_t::INVALID_TAG, pos);
			// Выходим из перебора атрибутов
			break;
		}
		/**
		 * Если атрибут не отделён от предыдущего пробельным знаком
		 */
		if(pos == begin)
			// Выводим ошибку построения метки
			return this->fail(error_t::INVALID_TAG, pos);
		/**
		 * Если количество атрибутов узла превысило допустимое
		 */
		if((this->_attributes.size() + this->_declares.size()) >= this->_settings.maxAttributes)
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, pos);
		// Собираемый атрибут узла
		record_t record;
		/**
		 * Если открывающая метка узла на простоту счёта места ещё не проверена
		 */
		if(!checked){
			// Запоминаем, что открывающая метка узла проверена
			checked = true;
			// Выполняем проверку открывающей метки узла на простоту счёта места
			simple = (this->_splices.empty() && ::plain(this->_buffer, this->_offset, end));
		}
		/**
		 * Если место атрибутов узла считается вычитанием
		 */
		if(simple){
			// Запоминаем смещение атрибута от начала текста
			record.location.offset = (this->_consumed + pos);
			// Запоминаем номер строки, на которой записан атрибут
			record.location.line = place.line;
			// Запоминаем положение атрибута в строке
			record.location.column = (place.column + static_cast <uint32_t> (pos - this->_offset));
		/**
		 * Если место атрибута требуется досчитать перебором
		 */
		} else {
			// Выполняем досчёт места разбираемого атрибута в исходном тексте
			this->relocate(place, placed, pos);
			// Запоминаем положение атрибута в исходном тексте
			record.location = place;
		}
		/**
		 * Если имя атрибута разобрать не удалось
		 */
		if(!this->parseName(pos, end, record.prefix, record.local))
			// Выводим ошибку построения имени либо превышения его длины
			return this->fail((this->_overlong ? error_t::NAME_TOO_LONG : error_t::INVALID_NAME), pos);
		/**
		 * Выполняем пропуск пробельных знаков перед разделителем
		 */
		while((pos < end) && ::isSpace(this->_buffer[pos]))
			// Выполняем переход к следующему знаку
			pos++;
		/**
		 * Если разделитель имени и значения атрибута отсутствует
		 */
		if((pos >= end) || (this->_buffer[pos] != '='))
			// Выводим ошибку построения атрибута
			return this->fail(error_t::INVALID_ATTRIBUTE, pos);
		// Выполняем переход к значению атрибута
		pos++;
		/**
		 * Выполняем пропуск пробельных знаков перед значением
		 */
		while((pos < end) && ::isSpace(this->_buffer[pos]))
			// Выполняем переход к следующему знаку
			pos++;
		/**
		 * Если значение атрибута разобрать не удалось
		 */
		if(!this->parseValue(pos, end, record.value))
			// Выводим ошибку разбора значения атрибута
			return this->fail(this->_error, pos);
		// Выполняем добавление разобранного атрибута
		this->append(record);
	}
	/**
	 * Если значения атрибутов по умолчанию подставляются настройками
	 */
	if(this->_settings.defaults && !this->_attlists.empty()){
		// Выполняем поиск объявленных по умолчанию значений узла
		this->_lookup.assign(qname);
		// Выполняем отыскание объявленных по умолчанию значений узла
		auto i = this->_attlists.find(this->_lookup);
		/**
		 * Если объявленные по умолчанию значения узла обнаружены
		 */
		if(i != this->_attlists.end()){
			/**
			 * Выполняем перебор всех объявленных по умолчанию значений
			 */
			for(const default_t & item : i->second){
				// Признак того, что атрибут записан в тексте
				bool exists = false;
				/**
				 * Выполняем перебор всех разобранных атрибутов узла
				 */
				for(const attribute_t & attribute : this->_attributes){
					/**
					 * Если имя атрибута совпадает с объявленным
					 */
					if((attribute.name.local == item.local) && (attribute.name.prefix == item.prefix)){
						// Запоминаем, что атрибут записан в тексте
						exists = true;
						// Выходим из перебора атрибутов
						break;
					}
				}
				/**
				 * Выполняем перебор всех объявлений пространств имён узла
				 */
				for(const record_t & record : this->_declares){
					/**
					 * Если имя атрибута совпадает с объявленным
					 */
					if((record.local == item.local) && (record.prefix == item.prefix)){
						// Запоминаем, что атрибут записан в тексте
						exists = true;
						// Выходим из перебора атрибутов
						break;
					}
				}
				/**
				 * Если атрибут записан в тексте
				 *
				 * @note Записанное в тексте значение отменяет объявленное по
				 *       умолчанию: объявление восполняет опущенное, а не замещает
				 */
				if(exists)
					// Выполняем переход к следующему объявленному значению
					continue;
				/**
				 * Если количество атрибутов узла превысило допустимое
				 *
				 * @note Предел проверяется и здесь: объявленные по умолчанию значения
				 *       становятся атрибутами узла наравне с записанными в тексте, и
				 *       проверка одних лишь записанных обходилась бы объявлением
				 *       перечня атрибутов в описании типа документа
				 */
				if((this->_attributes.size() + this->_declares.size()) >= this->_settings.maxAttributes)
					// Выводим ошибку превышения заданного настройками предела
					return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
				// Собираемый атрибут узла
				record_t record;
				// Запоминаем префикс имени атрибута
				record.prefix = string_view(item.prefix.data(), item.prefix.size());
				// Запоминаем местное имя атрибута
				record.local = string_view(item.local.data(), item.local.size());
				// Запоминаем положение атрибута в исходном тексте
				record.location = this->locate(this->_offset);
				// Запоминаем, что значение взято из объявления по умолчанию
				record.defaulted = true;
				// Запоминаем начало значения атрибута
				record.value.offset = static_cast <uint32_t> (this->_scratch.size());
				/**
				 * Если объявленное значение содержит ссылки на сущности
				 */
				if(item.value.find('&') != string::npos){
					/**
					 * Выполняем перебор всех знаков объявленного значения
					 */
					for(size_t pos = 0; pos < item.value.size(); pos++){
						/**
						 * Если обнаружена ссылка на сущность
						 */
						if(item.value[pos] == '&'){
							// Выполняем поиск конца ссылки на сущность
							const size_t stop = item.value.find(';', pos);
							/**
							 * Если конец ссылки на сущность не обнаружен
							 */
							if(stop == string::npos)
								// Выводим ошибку построения ссылки на сущность
								return this->fail(error_t::INVALID_REFERENCE, this->_offset);
							/**
							 * Если подстановку ссылки выполнить не удалось
							 *
							 * @note Пробельные знаки подставленного значения приводятся к
							 *       пробелу: значение это становится значением атрибута, и
							 *       договор прилагает к нему приведение наравне с записанным
							 *       у самого узла. Приведение при объявлении его не покрывает -
							 *       ссылка на сущность подставляется не тогда, а здесь
							 */
							if(!this->expand(string_view(item.value).substr(pos + 1, stop - (pos + 1)), this->_scratch, 0, true))
								// Выводим ошибку подстановки ссылки на сущность
								return this->fail(this->_error, this->_offset);
							// Выполняем переход к следующему знаку значения
							pos = stop;
							// Выполняем переход к следующему знаку значения
							continue;
						}
						// Выполняем добавление очередного знака значения
						this->_scratch.push_back(item.value[pos]);
					}
				// Выполняем добавление объявленного значения атрибута
				} else this->_scratch.append(item.value);
				/**
				 * Если хранилище приведённых значений вышло за предел разрядности отрезка
				 *
				 * @note Довод тот же, что и при разборе значения из самого текста:
				 *       за пределом разрядности смещение обращается в младшие разряды
				 */
				if(this->_scratch.size() > static_cast <size_t> (0xFFFFFFFFu))
					// Выводим ошибку выхода за предел разрядности отрезка
					return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
				// Запоминаем длину значения атрибута
				record.value.length = static_cast <uint32_t> (this->_scratch.size() - record.value.offset);
				// Выполняем добавление собранного атрибута
				this->append(record);
			}
		}
	}
	/**
	 * Если корневой узел разметки в тексте уже встречен
	 */
	if(this->_stack.empty() && this->_root)
		// Выводим ошибку нескольких корневых узлов
		return this->fail(error_t::MULTIPLE_ROOTS, this->_offset);
	/**
	 * Если глубина вложенности узлов превысила допустимую
	 */
	if(this->_stack.size() >= this->_settings.maxDepth)
		// Выводим ошибку превышения допустимой глубины вложенности
		return this->fail(error_t::DEPTH_EXCEEDED, this->_offset);
	// Собираемый узел разметки
	element_t element;
	/**
	 * Выполняем размещение имени узла в хранилище знаков разбора
	 *
	 * @note Имя размещается первым: усечение хранилища при завершении узла
	 *       ведётся именно по его положению
	 *
	 * @note Префикс и местное имя лежат внутри записи имени сплошными отрезками,
	 *       поэтому размещаются вместе с ней одним разом, а не тремя
	 */
	element.qname = this->store(qname);
	/**
	 * Если имя узла записано с префиксом
	 */
	if(!prefix.empty()){
		// Запоминаем отрезок префикса внутри размещённого имени
		element.name.prefix = span_t(element.qname.offset, static_cast <uint32_t> (prefix.length()));
		// Запоминаем отрезок местного имени внутри размещённого имени
		element.name.local = span_t(
			static_cast <uint32_t> (element.qname.offset + prefix.length() + 1),
			static_cast <uint32_t> (local.length())
		);
	/**
	 * Если имя узла записано без префикса
	 */
	} else {
		// Запоминаем пустой отрезок префикса
		element.name.prefix = span_t(element.qname.offset, 0);
		// Запоминаем отрезок местного имени внутри размещённого имени
		element.name.local = span_t(element.qname.offset, static_cast <uint32_t> (local.length()));
	}
	// Запоминаем обращение с пробельным содержимым, унаследованное от родителя
	element.space = (this->_stack.empty() ? space_t::DEFAULT : this->_stack.back().space);
	// Выполняем добавление узла к стеку открытых узлов
	this->_stack.push_back(element);
	/**
	 * Если разрешение пространств имён выполнить не удалось
	 */
	if(!this->bind())
		// Выводим ошибку разрешения пространств имён
		return this->fail(this->_error, this->_offset);
	// Запоминаем, что корневой узел разметки встречен
	this->_root = true;
	// Запоминаем признак узла, записанного самозакрывающейся меткой
	this->_empty = empty;
	// Запоминаем признак того, что следующим событием является конец узла
	this->_closing = empty;
	// Запоминаем глубину вложенности узла события
	this->_depth = static_cast <uint32_t> (this->_stack.size() - 1);
	// Запоминаем префикс имени узла
	this->_name.prefix = this->view(this->_stack.back().name.prefix);
	// Запоминаем местное имя узла
	this->_name.local = this->view(this->_stack.back().name.local);
	// Запоминаем обозначение пространства имён узла
	this->_name.uri = this->view(this->_stack.back().name.uri);
	// Запоминаем обращение с пробельным содержимым внутри узла
	this->_space = this->_stack.back().space;
	// Запоминаем вид полученного события разбора
	this->_event = event_t::ELEMENT_OPEN;
	// Выполняем переход к следующей разметке
	this->advance(end + 1);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора закрывающей метки узла
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseClosing() noexcept {
	// Выполняем поиск конца закрывающей метки узла
	const size_t end = this->_buffer.find('>', this->_offset + 2);
	/**
	 * Если конец закрывающей метки узла не обнаружен
	 */
	if(end == string::npos){
		/**
		 * Если исходный текст на этом окончен
		 */
		if(this->_final)
			// Выводим ошибку незакрытой метки
			return this->fail(error_t::UNCLOSED_TAG, this->_offset);
		/**
		 * Если объём события превысил допустимый
		 */
		if((this->_settings.maxEvent > 0) && ((this->_buffer.size() - this->_offset) > this->_settings.maxEvent))
			// Выводим ошибку превышения заданного настройками предела
			return this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим требование следующего куска исходного текста
		return step_t::HUNGRY;
	}
	// Положение разбора закрывающей метки узла
	size_t pos = (this->_offset + 2);
	// Префикс имени закрываемого узла
	string_view prefix;
	// Местное имя закрываемого узла
	string_view local;
	/**
	 * Если имя закрываемого узла разобрать не удалось
	 */
	if(!this->parseName(pos, end, prefix, local))
		// Выводим ошибку построения имени
		return this->fail(error_t::INVALID_NAME, this->_offset + 2);
	// Получаем имя закрываемого узла в записи, принятой в исходном тексте
	const string_view qname(this->_buffer.data() + this->_offset + 2, pos - (this->_offset + 2));
	/**
	 * Выполняем пропуск пробельных знаков после имени
	 */
	while((pos < end) && ::isSpace(this->_buffer[pos]))
		// Выполняем переход к следующему знаку
		pos++;
	/**
	 * Если закрывающая метка узла построена ошибочно
	 */
	if(pos != end)
		// Выводим ошибку построения метки
		return this->fail(error_t::INVALID_TAG, pos);
	/**
	 * Если закрывающая метка не имеет соответствующей открывающей
	 */
	if(this->_stack.empty())
		// Выводим ошибку лишней закрывающей метки
		return this->fail(error_t::UNEXPECTED_CLOSE_TAG, this->_offset);
	/**
	 * Если имя закрывающей метки не совпадает с именем открывающей
	 */
	if(this->view(this->_stack.back().qname) != qname)
		// Выводим ошибку несовпадения имён меток
		return this->fail(error_t::MISMATCHED_TAG, this->_offset);
	/**
	 * Если завершаемый узел открыт вне подставленной сущности
	 *
	 * @details Договор велит подставленной сущности быть построенной правильно самой по
	 *          себе: закрывающая метка внутри неё обязана отвечать открывающей, стоящей
	 *          там же. Закрыть узел, открытый вне сущности, ей не дозволено - иначе
	 *          строение документа зависело бы от того, чем сущность объявлена
	 *
	 * @note Глубины стека для проверки мало: значение сущности вправе закрыть узел и
	 *       открыть новый, оставив глубину прежней. Сличается потому не глубина на
	 *       выходе, а то, лежит ли завершаемый узел ниже начала подстановки
	 */
	if(!this->_splices.empty() && (this->_stack.size() <= this->_splices.back().depth))
		// Выводим ошибку пересечения границы подставленной сущности
		return this->fail(error_t::ENTITY_BOUNDARY, this->_offset);
	// Запоминаем глубину вложенности узла события
	this->_depth = static_cast <uint32_t> (this->_stack.size() - 1);
	// Выполняем завершение текущего узла разметки
	this->closure();
	// Выполняем переход к следующей разметке
	this->advance(end + 1);
	// Выводим итог выполненного шага разбора
	return step_t::DONE;
}
/**
 * @brief Метод разбора разметки, начинающейся угловой скобкой
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parseMarkup() noexcept {
	// Получаем количество доступных для разбора байтов
	const size_t size = (this->_buffer.size() - this->_offset);
	/**
	 * Если вид разметки определить пока нечем
	 */
	if(size < 2)
		// Выводим требование следующего куска исходного текста
		return (this->_final ? this->fail(error_t::INVALID_TAG, this->_offset) : step_t::HUNGRY);
	// Получаем знак, определяющий вид разметки
	const char letter = this->_buffer[this->_offset + 1];
	/**
	 * Если обнаружена закрывающая метка узла
	 */
	if(letter == '/')
		// Выполняем разбор закрывающей метки узла
		return this->parseClosing();
	/**
	 * Если обнаружено указание обработчику либо объявление разметки
	 */
	if(letter == '?')
		// Выполняем разбор указания обработчику
		return this->parseProcessing();
	/**
	 * Если обнаружено примечание, дословный раздел либо описание типа документа
	 */
	if(letter == '!'){
		// Получаем начало разбираемой разметки
		const char * data = (this->_buffer.data() + this->_offset);
		/**
		 * Если обнаружено примечание
		 */
		if((size >= 4) && (::memcmp(data, "<!--", 4) == 0))
			// Выполняем разбор примечания
			return this->parseComment();
		/**
		 * Если обнаружен раздел дословного текста
		 */
		if((size >= 9) && (::memcmp(data, "<![CDATA[", 9) == 0))
			// Выполняем разбор раздела дословного текста
			return this->parseCdata();
		/**
		 * Если обнаружено описание типа документа
		 */
		if((size >= 9) && (::memcmp(data, "<!DOCTYPE", 9) == 0))
			// Выполняем разбор описания типа документа
			return this->parseDoctype();
		/**
		 * Если вид разметки определить пока нечем
		 */
		if(!this->_final && (size < 9))
			// Выводим требование следующего куска исходного текста
			return step_t::HUNGRY;
		// Выводим ошибку построения метки
		return this->fail(error_t::INVALID_TAG, this->_offset);
	}
	// Выполняем разбор открывающей метки узла
	return this->parseElement();
}
/**
 * @brief Метод выполнения одного шага разбора
 *
 * @return итог шага разбора
 *
 */
awh::codec::xml::Reader::step_t awh::codec::xml::Reader::parse() noexcept {
	/**
	 * Выполняем разбор до получения очередного события
	 */
	for(;;){
		/**
		 * Выполняем закрытие завершённых областей подставленных сущностей
		 */
		while(!this->_splices.empty() && (this->_offset >= this->_splices.back().end)){
			/**
			 * Если узел разметки пересекает границу подставленной сущности
			 *
			 * @note Договор требует, чтобы узел начинался и заканчивался в пределах
			 *       одной сущности: иначе разметка зависела бы от подстановки, а
			 *       строение документа - от того, чем сущность объявлена
			 */
			if(this->_stack.size() != this->_splices.back().depth)
				// Выводим ошибку пересечения границы подставленной сущности
				return this->fail(error_t::ENTITY_BOUNDARY, this->_offset);
			/**
			 * Если раздел дословного текста пересекает границу подставленной сущности
			 *
			 * @note Раздел, начатый внутри сущности, обязан внутри неё и закончиться:
			 *       иначе его начало приходило бы из объявления сущности, а конец из
			 *       самого текста, и построение документа зависело бы от того, чем
			 *       сущность объявлена
			 */
			if(this->_cdata)
				// Выводим ошибку пересечения границы подставленной сущности
				return this->fail(error_t::ENTITY_BOUNDARY, this->_offset);
			// Выполняем поиск объявления завершённой сущности
			auto i = this->_entities.find(this->_splices.back().name);
			/**
			 * Если объявление сущности на месте
			 */
			if(i != this->_entities.end())
				// Запоминаем, что подстановка сущности завершена
				i->second.active = false;
			/**
			 * Выполняем восстановление места разбора в исходном тексте
			 *
			 * @note Подстановка замещает ссылку значением прямо в разбираемом тексте, и
			 *       место разбора считается дальше по подставленному значению, а не по
			 *       исходному тексту. Пока область открыта, это скрыто выдачей места
			 *       самой ссылки, но по её закрытии сбитое место осталось бы до конца
			 *       разбора и накапливалось бы с каждой подстановкой
			 */
			location_t resume = this->_splices.back().resume;
			/**
			 * Выполняем досчёт места по тексту, пройденному за областью подстановки
			 *
			 * @details Разбор нередко уходит за конец области прежде, чем она закрывается:
			 *          содержимое узла обрывается началом следующей разметки, а не границей
			 *          сущности, и текст за подстановкой попадает в то же самое событие.
			 *          Пройденное за областью принадлежит уже исходному тексту, и место его
			 *          знаков досчитывается от места за ссылкой на сущность. Без досчёта
			 *          строка и столбец отставали бы ровно на этот хвост, и отставание
			 *          накапливалось бы с каждой подстановкой до конца разбора
			 *
			 * @note Смещения досчёт не касается: оно ведётся от количества изъятых байтов,
			 *       и удлинение текста снимается с него отдельно
			 */
			if(this->_offset > this->_splices.back().end){
				// Положение, до которого место уже досчитано
				size_t from = this->_splices.back().end;
				// Выполняем досчёт строки и столбца по тексту за областью подстановки
				::measure(this->_buffer, resume.line, resume.column, from, this->_offset);
			}
			// Выполняем восстановление места разбора в исходном тексте
			this->_line = resume.line;
			// Выполняем восстановление положения разбора в строке исходного текста
			this->_column = resume.column;
			// Получаем удлинение текста, внесённое завершённой подстановкой
			const int64_t delta = this->_splices.back().delta;
			/**
			 * Выполняем изъятие удлинения текста из количества изъятых байтов
			 *
			 * @note Знак удлинения разбирается прямо, а не вычитанием со снятием знака:
			 *       подставленное значение бывает и длиннее ссылки, и короче её, - и во
			 *       втором случае вычитание опиралось бы на переполнение беззнакового
			 *       числа. Итог у обоих ходов один, но опираться на переполнение значит
			 *       оставлять западню тому, кто станет править это место следом
			 */
			if(delta >= 0)
				// Выполняем изъятие удлинения текста из количества изъятых байтов
				this->_consumed -= static_cast <uint64_t> (delta);
			// Выполняем возмещение укорочения текста в количестве изъятых байтов
			else this->_consumed += static_cast <uint64_t> (-delta);
			// Выполняем снятие завершённой области подстановки
			this->_splices.pop_back();
		}
		// Выполняем сброс вида текущего события разбора
		this->_event = event_t::NONE;
		// Выполняем сброс признака узла, записанного самозакрывающейся меткой
		this->_empty = false;
		// Запоминаем обращение с пробельным содержимым текущего узла
		this->_space = (this->_stack.empty() ? space_t::DEFAULT : this->_stack.back().space);
		// Запоминаем положение начала события в исходном тексте
		this->_location = this->locate(this->_offset);
		// Итог выполненного шага разбора
		step_t step = step_t::DONE;
		/**
		 * Если разбор находится внутри раздела дословного текста
		 */
		if(this->_cdata)
			// Выполняем разбор раздела дословного текста
			step = this->parseCdata();
		/**
		 * Если приведённый исходный текст разобран до конца
		 */
		else if(this->_offset >= this->_buffer.size()) {
			/**
			 * Если исходный текст ещё не окончен
			 */
			if(!this->_final)
				// Выводим требование следующего куска исходного текста
				return step_t::HUNGRY;
			/**
			 * Если остались незакрытые узлы разметки
			 */
			if(!this->_stack.empty())
				// Выводим ошибку незакрытой метки
				return this->fail(error_t::UNCLOSED_TAG, this->_offset);
			/**
			 * Если корневой узел разметки в тексте отсутствует
			 */
			if(!this->_root)
				// Выводим ошибку отсутствия корневого узла
				return this->fail(error_t::MISSING_ROOT, this->_offset);
			// Запоминаем вид полученного события разбора
			this->_event = event_t::FINISH;
			// Запоминаем состояние разобранного до конца текста
			this->_state = state_t::FINISHED;
			// Выводим итог выполненного шага разбора
			return step_t::DONE;
		/**
		 * Если обнаружено начало разметки
		 */
		} else if(this->_buffer[this->_offset] == '<'){
			/**
			 * Выполняем сброс признака выданной непробельной части содержимого
			 *
			 * @note Разметка содержимое узла обрывает, и следующее за ней содержимое
			 *       считается незначимым или значимым уже само по себе
			 */
			this->_dirty = false;
			// Выполняем разбор разметки
			step = this->parseMarkup();
		}
		/**
		 * Если обнаружена ссылка на сущность
		 */
		else if(this->_buffer[this->_offset] == '&') {
			// Имя сущности, на которую указывает ссылка
			string_view name;
			// Положение конца ссылки на сущность
			size_t stop = 0;
			/**
			 * Если ссылка на сущность записана вне корневого узла
			 *
			 * @note Проверка выполняется до подстановки: подставленное значение
			 *       разбирается наравне с записанным в тексте, и разметка из сущности
			 *       иначе стала бы корневым узлом документа, у которого своего
			 *       корневого узла нет вовсе
			 */
			if(this->_stack.empty())
				// Выводим ошибку содержимого вне корневого узла
				return this->fail(error_t::CONTENT_OUTSIDE_ROOT, this->_offset);
			/**
			 * Если ссылка указывает на сущность, содержащую разметку
			 */
			if(this->markup(this->_offset, name, stop)){
				/**
				 * Если подстановку сущности выполнить не удалось
				 */
				if(!this->inject(this->_offset, stop, name))
					// Выводим ошибку подстановки сущности
					return this->fail(this->_error, this->_offset);
				// Выполняем переход к разбору подставленного значения
				continue;
			}
			// Выполняем разбор содержимого узла
			step = this->parseText();
		/**
		 * Если обнаружено содержимое узла
		 */
		} else step = this->parseText();
		/**
		 * Если очередной шаг разбора события не дал
		 */
		if(step != step_t::DONE)
			// Выводим итог выполненного шага разбора
			return step;
		/**
		 * Если событие разбора получено
		 */
		if(this->_event != event_t::NONE)
			// Выводим итог выполненного шага разбора
			return step_t::DONE;
	}
}
/**
 * @brief Метод получения текущих настроек разбора
 *
 * @return текущие настройки разбора текста разметки
 *
 */
const awh::codec::xml::Reader::settings_t & awh::codec::xml::Reader::settings() const noexcept {
	// Выводим текущие настройки разбора текста разметки
	return this->_settings;
}
/**
 * @brief Метод установки настроек разбора
 *
 * @param settings настройки разбора текста разметки
 *
 */
void awh::codec::xml::Reader::settings(const settings_t & settings) noexcept {
	// Запоминаем настройки разбора текста разметки
	this->_settings = settings;
	/**
	 * Если кодировка навязана настройками разбора
	 */
	if(this->_settings.encoding != encoding_t::NONE){
		/**
		 * Если навязать кодировку исходного текста не удалось
		 *
		 * @note Сменить кодировку посреди текста нельзя, и такое указание декодер
		 *       отвергает. Сохрани мы его в настройках, они объявляли бы кодировку,
		 *       которая на деле не применяется, и получатель настроек был бы введён
		 *       в заблуждение собственной же просьбой
		 */
		if(!this->_decoder.encoding(this->_settings.encoding))
			// Сбрасываем кодировку, навязать которую не удалось
			this->_settings.encoding = encoding_t::NONE;
	}
}
/**
 * @brief Метод сброса разбора в исходное состояние
 *
 */
void awh::codec::xml::Reader::reset() noexcept {
	// Выполняем сброс приведения исходного текста
	this->_decoder.reset();
	/**
	 * Если кодировка навязана настройками разбора
	 */
	if(this->_settings.encoding != encoding_t::NONE)
		// Выполняем установку навязанной кодировки исходного текста
		this->_decoder.encoding(this->_settings.encoding);
	// Выполняем сброс состояния чтения текста разметки
	this->_state = state_t::HUNGRY;
	// Выполняем сброс вида текущего события разбора
	this->_event = event_t::NONE;
	// Выполняем сброс кода ошибки разбора
	this->_error = error_t::NONE;
	// Выполняем сброс определённой кодировки исходного текста
	this->_encoding = encoding_t::NONE;
	// Выполняем сброс признака самодостаточности текста разметки
	this->_standalone = standalone_t::NONE;
	// Выполняем сброс обращения с пробельным содержимым
	this->_space = space_t::DEFAULT;
	// Выполняем сброс имени текущего события
	this->_name = name_t();
	// Выполняем сброс содержимого текущего события
	this->_text = string_view();
	// Выполняем сброс положения начала текущего события
	this->_location = location_t();
	// Выполняем сброс положения обнаруженной ошибки
	this->_errorLocation = location_t();
	// Выполняем сброс объявленного издания разметки
	this->_version.clear();
	// Выполняем очистку перечня атрибутов текущего узла
	this->_attributes.clear();
	// Выполняем очистку ключей имён атрибутов
	this->_keys.clear();
	// Выполняем очистку раскладки имён атрибутов по свёртке
	this->_digests.clear();
	// Выполняем очистку перечня объявлений пространств имён
	this->_bindings.clear();
	// Выполняем очистку объявленных сущностей
	this->_entities.clear();
	// Выполняем очистку объявленных по умолчанию значений атрибутов
	this->_attlists.clear();
	// Выполняем сброс признака получения последнего куска исходного текста
	this->_final = false;
	// Выполняем сброс признака встреченного корневого узла разметки
	this->_root = false;
	// Выполняем сброс признака встреченного объявления разметки
	this->_declared = false;
	// Выполняем сброс признака встреченного описания типа документа
	this->_doctype = false;
	// Выполняем сброс хода поиска конца описания типа документа
	this->_survey = survey_t();
	// Выполняем сброс признака узла, записанного самозакрывающейся меткой
	this->_empty = false;
	// Выполняем сброс признака ожидаемого конца узла
	this->_closing = false;
	// Выполняем сброс признака нахождения внутри дословного раздела
	this->_cdata = false;
	// Выполняем сброс начала раздела дословного текста
	this->_section = 0;
	// Выполняем сброс признака прихода объявлений извне разобранного
	this->_foreign = false;
	// Выполняем сброс признака имени, превысившего предел настроек
	this->_overlong = false;
	// Выполняем сброс признака выданной непробельной части содержимого
	this->_dirty = false;
	// Выполняем очистку приведённого исходного текста
	this->_buffer.clear();
	// Выполняем сброс положения разбора
	this->_offset = 0;
	// Выполняем сброс количества изъятых байтов
	this->_consumed = 0;
	// Выполняем сброс текущего номера строки
	this->_line = 1;
	// Выполняем сброс текущего положения в строке
	this->_column = 1;
	// Выполняем сброс глубины вложенности узла события
	this->_depth = 0;
	// Выполняем очистку хранилища знаков разбора
	this->_names.clear();
	// Выполняем сброс отложенного усечения хранилища знаков
	this->_truncate = string::npos;
	// Выполняем очистку хранилища приведённых значений
	this->_scratch.clear();
	// Выполняем сброс общего объёма подстановки сущностей
	this->_expansion = 0;
	// Выполняем очистку стека открытых узлов разметки
	this->_stack.clear();
	// Выполняем очистку действующих связываний префиксов
	this->_scopes.clear();
	// Выполняем очистку объявлений пространств имён узла
	this->_declares.clear();
	// Выполняем очистку отрезков значений атрибутов узла
	this->_values.clear();
	// Выполняем очистку открытых областей подставленных сущностей
	this->_splices.clear();
	/**
	 * Выполняем размещение отведённого договором пространства имён
	 *
	 * @note Префикс «xml» связан с этим обозначением изначально и объявления не
	 *       требует, поэтому обозначение размещается в самом начале хранилища и
	 *       усечению при завершении узлов не подлежит
	 */
	this->_xml = this->store(XML_NAMESPACE);
}
/**
 * @brief Метод передачи очередного куска исходного текста
 *
 * @param buffer буфер очередного куска исходного текста
 * @param size   размер буфера очередного куска исходного текста
 * @param end    признак того, что кусок является последним
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::feed(const void * buffer, const size_t size, const bool end) noexcept {
	/**
	 * Если разбор уже прекращён ошибкой
	 */
	if(this->_state == state_t::FAILED)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если исходный текст уже окончен
	 */
	if(this->_final)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если приведение куска исходного текста выполнить не удалось
	 *
	 * @note Приведением же отсеиваются и знаки, договором в тексте не дозволенные:
	 *       разбору достаётся текст, где всякий знак договору отвечает. Оттого разбор
	 *       пользуется общими средствами разбора знаков US-ASCII, не заводя своих: набор
	 *       пробельных знаков у них шире договорного - в него входят вертикальная
	 *       табуляция и подача страницы, - но знаки эти сюда не доходят вовсе, и разницы
	 *       между наборами разбор не видит
	 */
	if(!this->_decoder.convert(buffer, size, end, this->_buffer)){
		// Запоминаем код ошибки разбора
		this->_error = this->_decoder.error();
		// Запоминаем положение обнаруженной ошибки
		this->_errorLocation = this->locate(this->_buffer.size());
		// Запоминаем состояние прекращённого ошибкой разбора
		this->_state = state_t::FAILED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Запоминаем признак получения последнего куска исходного текста
	this->_final = end;
	// Запоминаем определённую кодировку исходного текста
	this->_encoding = this->_decoder.encoding();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод передачи исходного текста целиком
 *
 * @param text исходный текст разметки целиком
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::feed(const string_view text) noexcept {
	// Выполняем передачу исходного текста как единственного куска
	return this->feed(text.data(), text.length(), true);
}
/**
 * @brief Метод перехода к следующему событию разбора
 *
 * @return признак наличия очередного события разбора
 *
 */
bool awh::codec::xml::Reader::next() noexcept {
	/**
	 * Если разбор прекращён ошибкой либо текст разобран до конца
	 */
	if((this->_state == state_t::FAILED) || (this->_state == state_t::FINISHED))
		// Выводим отсутствие очередного события разбора
		return false;
	/**
	 * Если хранилище знаков разбора подлежит усечению
	 */
	if(this->_truncate != string::npos){
		// Выполняем усечение хранилища знаков разбора
		this->_names.resize(this->_truncate);
		// Выполняем сброс отложенного усечения хранилища знаков
		this->_truncate = string::npos;
	}
	// Выполняем очистку перечня атрибутов текущего узла
	this->_attributes.clear();
	// Выполняем очистку ключей имён атрибутов
	this->_keys.clear();
	// Выполняем очистку перечня объявлений пространств имён
	this->_bindings.clear();
	// Выполняем сброс имени текущего события
	this->_name = name_t();
	// Выполняем сброс содержимого текущего события
	this->_text = string_view();
	// Выполняем сброс вида текущего события разбора
	this->_event = event_t::NONE;
	/**
	 * Если следующим событием является конец узла, записанного самозакрывающейся меткой
	 */
	if(this->_closing){
		// Выполняем сброс признака ожидаемого конца узла
		this->_closing = false;
		// Запоминаем признак узла, записанного самозакрывающейся меткой
		this->_empty = true;
		// Запоминаем глубину вложенности узла события
		this->_depth = static_cast <uint32_t> (this->_stack.size() - 1);
		// Выполняем завершение текущего узла разметки
		this->closure();
		// Запоминаем состояние полученного события
		this->_state = state_t::READY;
		// Выводим наличие очередного события разбора
		return true;
	}
	// Выполняем изъятие разобранного начала приведённого текста
	this->compact();
	/**
	 * Определяем итог выполненного шага разбора
	 */
	switch(static_cast <uint8_t> (this->parse())){
		// Если разбор прекращён ошибкой
		case static_cast <uint8_t> (step_t::FAILED):
			// Выводим отсутствие очередного события разбора
			return false;
		// Если для продолжения разбора требуется следующий кусок текста
		case static_cast <uint8_t> (step_t::HUNGRY): {
			// Запоминаем состояние ожидания следующего куска
			this->_state = state_t::HUNGRY;
			// Выводим отсутствие очередного события разбора
			return false;
		}
	}
	/**
	 * Если содержимое полученного события превысило предел, заданный настройками
	 *
	 * @details Предел этот проверяется и по ходу накопления - там, где разбор дожидается
	 *          следующего куска, - но одного накопления мало: текст, пришедший целиком,
	 *          копить не приходится вовсе, и событие любого объёма выдавалось бы мимо
	 *          предела. Предел обязан держаться одинаково, как бы текст ни был нарезан:
	 *          иначе он зависел бы от устройства сети, а не от настроек вызывающего
	 *
	 * @note Проверяется содержимое выдаваемого события, а не остаток разбираемого текста:
	 *       по ходу накопления известен лишь второй, а здесь - уже сам итог
	 */
	if((this->_settings.maxEvent > 0) && (this->_text.size() > this->_settings.maxEvent)){
		// Выполняем выдачу ошибки превышения заданного настройками предела
		this->fail(error_t::OVERFLOW_LIMIT, this->_offset);
		// Выводим отсутствие очередного события разбора
		return false;
	}
	/**
	 * Если текст разобран до конца
	 */
	if(this->_event == event_t::FINISH)
		// Запоминаем состояние разобранного до конца текста
		this->_state = state_t::FINISHED;
	// Запоминаем состояние полученного события
	else this->_state = state_t::READY;
	// Выводим наличие очередного события разбора
	return true;
}
