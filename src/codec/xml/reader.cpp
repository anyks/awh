/**
 * @brief Метод определения сущности, содержащей разметку
 *
 * @param offset положение начала ссылки на сущность
 * @param name   имя обнаруженной сущности
 * @param end    положение конца ссылки на сущность
 * @return       результат проверки
 *
 */
bool awh::codec::xml::Reader::markup(const size_t offset, string_view & name, size_t & end) const noexcept {
	/**
	 * Если подстановка объявленных сущностей отключена настройками
	 */
	if(!this->_settings.entities || this->_entities.empty())
		// Выводим отрицательный результат проверки
		return false;
	// Выполняем поиск конца ссылки на сущность
	const size_t stop = this->_buffer.find(';', offset);
	/**
	 * Если конец ссылки на сущность не обнаружен
	 */
	if(stop == string::npos)
		// Выводим отрицательный результат проверки
		return false;
	// Получаем имя сущности, на которую указывает ссылка
	const string_view title(this->_buffer.data() + offset + 1, stop - (offset + 1));
	/**
	 * Если ссылка является числовой
	 */
	if(title.empty() || (title.front() == '#'))
		// Выводим отрицательный результат проверки
		return false;
	// Выполняем поиск объявления сущности
	this->_lookup.assign(title);
	// Выполняем отыскание объявления сущности
	auto i = this->_entities.find(this->_lookup);
	/**
	 * Если сущность не объявлена либо её значение разметки не содержит
	 */
	if((i == this->_entities.end()) || !i->second.markup)
		// Выводим отрицательный результат проверки
		return false;
	// Запоминаем имя обнаруженной сущности
	name = title;
	// Запоминаем положение конца ссылки на сущность
	end = (stop + 1);
	// Выводим положительный результат проверки
	return true;
}
/**
 * @brief Метод подстановки сущности с разметкой прямо в разбираемый текст
 *
 * @param begin положение начала ссылки на сущность
 * @param end   положение конца ссылки на сущность
 * @param name  имя подставляемой сущности
 * @return      результат выполнения операции
 *
 */
bool awh::codec::xml::Reader::inject(const size_t begin, const size_t end, const string_view name) noexcept {
	/**
	 * Если глубина вложенности подстановок превышает допустимую
	 */
	if(this->_splices.size() >= MAX_ENTITY_DEPTH){
		// Запоминаем код ошибки разбора
		this->_error = error_t::ENTITY_DEPTH_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем поиск объявления сущности
	this->_lookup.assign(name);
	// Выполняем отыскание объявления сущности
	auto i = this->_entities.find(this->_lookup);
	/**
	 * Если сущность не объявлена
	 */
	if(i == this->_entities.end()){
		// Запоминаем код ошибки разбора
		this->_error = error_t::UNKNOWN_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если подстановка сущности выполняется в текущий миг
	 */
	if(i->second.active){
		// Запоминаем код ошибки разбора
		this->_error = error_t::RECURSIVE_ENTITY;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем накопление общего объёма подстановки сущностей
	this->_expansion += i->second.value.size();
	/**
	 * Если общий объём подстановки превысил допустимый
	 */
	if(this->_expansion > this->_settings.maxExpansion){
		// Запоминаем код ошибки разбора
		this->_error = error_t::ENTITY_LIMIT_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Собираемая область подставленной сущности
	splice_t splice;
	// Запоминаем имя подставляемой сущности
	splice.name.assign(name);
	// Запоминаем глубину стека открытых узлов на начало подстановки
	splice.depth = this->_stack.size();
	// Запоминаем положение ссылки на сущность в исходном тексте
	splice.location = this->locate(begin);
	/**
	 * Запоминаем место разбора, каким оно было бы без подстановки
	 *
	 * @note Ссылка на сущность записывается одной строкой и переводов строки не
	 *       содержит, поэтому место за ней отличается от места ссылки лишь на её
	 *       длину в знаках
	 */
	splice.resume = splice.location;
	// Запоминаем положение разбора за ссылкой на сущность
	splice.resume.offset += (end - begin);
	/**
	 * Запоминаем положение разбора в строке за ссылкой на сущность
	 *
	 * @note Положение в строке считается знаками, а не байтами: имя сущности вправе
	 *       нести знаки за пределами US-ASCII, а такой знак занимает несколько байтов.
	 *       Считай мы байтами, место всякой разметки за подстановкой съезжало бы вправо
	 *       ровно на столько, сколько лишних байтов в имени
	 */
	splice.resume.column += static_cast <uint32_t> (::codepoints(this->_buffer.data() + begin, end - begin));
	// Получаем длину подставляемого значения сущности
	const size_t length = i->second.value.size();
	// Запоминаем, на сколько байтов подстановка удлинила разбираемый текст
	splice.delta = (static_cast <int64_t> (length) - static_cast <int64_t> (end - begin));
	/**
	 * Выполняем перебор всех ранее открытых областей подстановки
	 *
	 * @note Подстановка меняет длину разбираемого текста, и концы ранее открытых
	 *       областей смещаются вместе с ним
	 */
	for(splice_t & item : this->_splices){
		// Выполняем изъятие длины ссылки из положения конца области
		item.end -= (end - begin);
		// Выполняем добавление длины подставленного значения к положению конца
		item.end += length;
	}
	// Выполняем замещение ссылки на сущность её значением
	this->_buffer.replace(begin, end - begin, i->second.value);
	// Запоминаем положение конца области подстановки
	splice.end = (begin + length);
	// Запоминаем, что подстановка сущности выполняется
	i->second.active = true;
	// Выполняем добавление области подстановки к открытым
	this->_splices.push_back(::move(splice));
	// Выводим положительный результат выполнения операции
	return true;
}
