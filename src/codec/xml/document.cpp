/**
 * @brief Метод поиска вложенного узла разметки по имени
 *
 * @param local местное имя искомого узла
 * @param uri   обозначение пространства имён искомого узла
 * @return      найденный узел дерева разметки
 *
 */
awh::codec::xml::node_t awh::codec::xml::Node::child(const string_view local, const string_view uri) const noexcept {
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим непригодный узел дерева разметки
		return node_t();
	/**
	 * Если отображения имён вложенных узлов у дерева заведены
	 *
	 * @note Сличение это стоит впереди поиска намеренно: у дерева, ни одного широкого
	 *       родителя не имеющего, отображений нет вовсе, и платить за поиск по номеру
	 *       родителя на всяком розыске такому дереву не за что
	 */
	if(!this->_document->_index.empty()){
		// Выполняем поиск отображения имён вложенных узлов родителя
		auto i = this->_document->_index.find(this->_id);
		/**
		 * Если отображение имён вложенных узлов родителя заведено
		 */
		if(i != this->_document->_index.end()){
			// Выполняем поиск местного имени узла в отображении
			auto j = i->second.find(local);
			/**
			 * Если узла с таким местным именем у родителя нет вовсе
			 */
			if(j == i->second.end())
				// Выводим непригодный узел дерева разметки
				return node_t();
			// Получаем узел, разысканный отображением
			const node_t node(this->_document, j->second.first);
			/**
			 * Если разысканный узел несёт и затребованное пространство имён
			 *
			 * @note Отображение хранит ПЕРВОЕ вхождение местного имени, и совпадения его
			 *       довольно в подавляющем большинстве случаев. Разойдись пространства
			 *       имён - розыск откатывается к перебору ниже, а тот отвечает по договору
			 *       в точности
			 */
			if(node.name().is(uri, local))
				// Выводим разысканный узел разметки
				return node;
		}
	}
	// Количество перебранных вложенных узлов
	size_t count = 0;
	/**
	 * Выполняем перебор всех непосредственно вложенных узлов
	 */
	for(node_t node = this->first(); node.valid(); node = node.next(), count++){
		/**
		 * Если обнаружен узел разметки с искомым именем
		 */
		if((node.kind() == kind_t::ELEMENT) && node.name().is(uri, local)){
			/**
			 * Если узел обнаружен дальше порога заведения отображения
			 *
			 * @details Место находки и служит признаком широты родителя: нашлось дальше
			 * порога - значит детей у родителя заведомо больше порога, и заводить
			 * отображение пора. Признак этот выбран оттого, что числа детей из записи узла
			 * не узнать, а перебирать их ради счёта значило бы лишить перебор раннего
			 * выхода
			 *
			 * @warning Ранний выход отсюда убирать НЕЛЬЗЯ. Первая правка считала детей до
			 *          конца ради этого решения, и обычный вид разметки - розыск, отвечающий
			 *          первым же ребёнком, - просел на родителе о шестнадцати детях с 8.7 до
			 *          25.2 нс, то есть ВТРОЕ
			 */
			if(count > INDEX_THRESHOLD)
				// Выполняем заведение отображения имён вложенных узлов родителя
				this->reindex();
			// Выводим обнаруженный узел разметки
			return node;
		}
	}
	/**
	 * Если количество вложенных узлов превышает порог заведения отображения
	 *
	 * @note Розыск, ничего не обнаруживший, перебирает всех детей и число их знает точно:
	 *       заводить отображение по нему и надлежит, иначе розыск отсутствующего имени у
	 *       широкого родителя оставался бы перебором навсегда
	 */
	if(count > INDEX_THRESHOLD)
		// Выполняем заведение отображения имён вложенных узлов родителя
		this->reindex();
	// Выводим непригодный узел дерева разметки
	return node_t();
}
/**
 * @brief Метод заведения отображения имён вложенных узлов родителя
 *
 * @note Отображение, уже заведённое, не перестраивается: наполнение его сличается с
 *       содержимым родителя лишь при заведении, а всякая правка дерева сбрасывает
 *       отображения целиком
 *
 */
void awh::codec::xml::Node::reindex() const noexcept {
	/**
	 * Если отображение имён вложенных узлов родителя уже заведено
	 */
	if(this->_document->_index.count(this->_id) != 0)
		// Выходим из метода
		return;
	// Заводимое отображение имён вложенных узлов родителя
	unordered_map <string_view, Document::entry_t> index;
	/**
	 * Выполняем перебор всех непосредственно вложенных узлов
	 */
	for(node_t node = this->first(); node.valid(); node = node.next()){
		/**
		 * Если вложенный узел узлом разметки не является
		 *
		 * @note Узлы текста, примечаний и указаний в отображение не попадают вовсе: розыск
		 *       по имени их не разыскивает
		 */
		if(node.kind() != kind_t::ELEMENT)
			// Выполняем переход к следующему вложенному узлу
			continue;
		/**
		 * Добавляем местное имя вложенного узла в отображение, если оно ещё не занято
		 *
		 * @note Занятое имя не перезаписывается, а лишь считается: отображение хранит ПЕРВОЕ
		 *       вхождение, а число одноимённых нужно выдаче всех совпавших
		 */
		const auto added = index.emplace(node.name().local, Document::entry_t(node._id));
		/**
		 * Если имя вложенного узла уже было занято
		 */
		if(!added.second)
			// Выполняем учёт очередного узла разметки с тем же именем
			added.first->second.count++;
	}
	// Запоминаем заведённое отображение имён вложенных узлов родителя
	this->_document->_index.emplace(this->_id, ::std::move(index));
}
/**
 * @brief Метод получения перечня вложенных узлов разметки по имени
 *
 * @param local местное имя искомых узлов
 * @param uri   обозначение пространства имён искомых узлов
 * @return      перечень найденных узлов дерева разметки
 *
 */
vector <awh::codec::xml::node_t> awh::codec::xml::Node::children(const string_view local, const string_view uri) const noexcept {
	// Собираемый перечень найденных узлов
	vector <node_t> result;
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим пустой перечень найденных узлов
		return result;
	/**
	 * Если отображения имён вложенных узлов у дерева заведены
	 */
	if(!this->_document->_index.empty()){
		// Выполняем поиск отображения имён вложенных узлов родителя
		auto i = this->_document->_index.find(this->_id);
		/**
		 * Если отображение имён вложенных узлов родителя заведено
		 */
		if(i != this->_document->_index.end()){
			// Выполняем поиск местного имени узла в отображении
			auto j = i->second.find(local);
			/**
			 * Если узла с таким местным именем у родителя нет вовсе
			 */
			if(j == i->second.end())
				// Выводим пустой перечень найденных узлов
				return result;
			/**
			 * Если узел с таким местным именем у родителя один
			 *
			 * @details Случай этот у широкого родителя разных имён - единственный, и он же
			 * прежде был всего дороже: перебор всей цепочки ради одного совпавшего стоил у
			 * родителя о 20000 детях 118.6 мкс на обращение и рос квадратом
			 *
			 * @note Перебор при нескольких одноимённых оставлен намеренно: там велика и сама
			 * выдача, и перебор платится не зря - у родителя о 20000 детях ОДНОГО имени он
			 * стоит семи наносекунд на выданный узел, то есть предела
			 */
			if(j->second.count == 1){
				// Получаем узел, разысканный отображением
				const node_t node(this->_document, j->second.first);
				/**
				 * Если разысканный узел несёт и затребованное пространство имён
				 */
				if(node.name().is(uri, local))
					// Выполняем добавление обнаруженного узла к перечню
					result.push_back(node);
				// Выводим собранный перечень найденных узлов
				return result;
			}
		}
	}
	// Количество перебранных вложенных узлов
	size_t count = 0;
	/**
	 * Выполняем перебор всех непосредственно вложенных узлов
	 */
	for(node_t node = this->first(); node.valid(); node = node.next(), count++){
		/**
		 * Если обнаружен узел разметки с искомым именем
		 */
		if((node.kind() == kind_t::ELEMENT) && node.name().is(uri, local))
			// Выполняем добавление обнаруженного узла к перечню
			result.push_back(node);
	}
	/**
	 * Если количество вложенных узлов превышает порог заведения отображения
	 *
	 * @note Выдача совпавших цепочку перебирает целиком по самому своему делу, и число детей
	 *       знает точно: заводить отображение по нему и надлежит. Без этого выдача осталась
	 *       бы перебором навсегда - она сама отображения не заводила, а розыск одного узла
	 *       потребитель мог и не звать вовсе
	 */
	if(count > INDEX_THRESHOLD)
		// Выполняем заведение отображения имён вложенных узлов родителя
		this->reindex();
	// Выводим собранный перечень найденных узлов
	return result;
}
/**
 * @brief Метод поиска узла разметки вглубь дерева по имени
 *
 * @param local местное имя искомого узла
 * @param uri   обозначение пространства имён искомого узла
 * @return      найденный узел дерева разметки
 *
 */
awh::codec::xml::node_t awh::codec::xml::Node::find(const string_view local, const string_view uri) const noexcept {
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим непригодный узел дерева разметки
		return node_t();
	/**
	 * Выполняем обход всего поддерева узла в порядке следования в исходном тексте
	 */
	for(node_t node = this->first(); node.valid();){
		/**
		 * Если обнаружен узел разметки с искомым именем
		 */
		if((node.kind() == kind_t::ELEMENT) && node.name().is(uri, local))
			// Выводим обнаруженный узел разметки
			return node;
		/**
		 * Если у очередного узла есть вложенные
		 */
		if(node.first().valid()){
			// Выполняем переход к вложенному узлу
			node = node.first();
			// Выполняем переход к следующему узлу обхода
			continue;
		}
		/**
		 * Выполняем подъём по дереву до ближайшего узла того же уровня
		 */
		while(node.valid() && !node.next().valid() && (node != *this))
			// Выполняем переход к родительскому узлу
			node = node.parent();
		/**
		 * Если обход поддерева завершён
		 */
		if(!node.valid() || (node == *this))
			// Выходим из обхода поддерева
			break;
		// Выполняем переход к следующему узлу того же уровня
		node = node.next();
	}
	// Выводим непригодный узел дерева разметки
	return node_t();
}
/**
 * @brief Метод получения перечня атрибутов узла
 *
 * @return перечень атрибутов узла разметки
 *
 */
vector <awh::codec::xml::attribute_t> awh::codec::xml::Node::attributes() const noexcept {
	// Собираемый перечень атрибутов узла
	vector <attribute_t> result;
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим пустой перечень атрибутов
		return result;
	// Получаем запись текущего узла
	const Document::record_t & record = this->_document->_nodes[this->_id];
	/**
	 * Выполняем перебор всех атрибутов узла
	 */
	for(uint32_t i = 0; i < record.attributes; i++){
		// Получаем запись очередного атрибута
		const Document::property_t & property = this->_document->_attributes[record.attribute + i];
		// Собираемый атрибут узла
		attribute_t attribute;
		// Запоминаем имя атрибута
		attribute.name = this->_document->get(property.name);
		// Запоминаем значение атрибута
		attribute.value = this->_document->get(property.value);
		// Запоминаем положение атрибута в исходном тексте
		attribute.location = property.location;
		// Запоминаем признак значения, взятого из объявления по умолчанию
		attribute.defaulted = property.defaulted;
		// Выполняем добавление атрибута к перечню
		result.push_back(attribute);
	}
	// Выводим собранный перечень атрибутов узла
	return result;
}
/**
 * @brief Метод получения перечня объявлений пространств имён узла
 *
 * @return перечень связываний префиксов, объявленных узлом
 *
 */
vector <awh::codec::xml::binding_t> awh::codec::xml::Node::bindings() const noexcept {
	// Собираемый перечень объявлений пространств имён узла
	vector <binding_t> result;
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим пустой перечень объявлений
		return result;
	// Выполняем отыскание отрезка хранилища связываний узла
	auto i = this->_document->_scoped.find(this->_id);
	/**
	 * Если узел пространств имён не объявлял
	 */
	if(i == this->_document->_scoped.end())
		// Выводим пустой перечень объявлений
		return result;
	// Выполняем отвод места под перечень объявлений узла
	result.reserve(i->second.length);
	/**
	 * Выполняем перебор всех связываний, объявленных узлом
	 */
	for(uint32_t index = 0; index < i->second.length; index++){
		// Получаем запись очередного связывания префикса
		const Document::scope_t & scope = this->_document->_scopes[i->second.offset + index];
		// Собираемое объявление пространства имён
		binding_t binding;
		// Запоминаем префикс объявления
		binding.prefix = this->_document->get(scope.prefix);
		// Запоминаем обозначение объявляемого пространства имён
		binding.uri = this->_document->get(scope.uri);
		// Выполняем добавление объявления к перечню узла
		result.push_back(binding);
	}
	// Выводим собранный перечень объявлений пространств имён узла
	return result;
}
/**
 * @brief Метод получения значения атрибута узла
 *
 * @param local местное имя искомого атрибута
 * @param uri   обозначение пространства имён искомого атрибута
 * @return      значение найденного атрибута либо пустая последовательность
 *
 */
string_view awh::codec::xml::Node::attribute(const string_view local, const string_view uri) const noexcept {
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим пустую последовательность знаков
		return string_view();
	// Получаем запись текущего узла
	const Document::record_t & record = this->_document->_nodes[this->_id];
	/**
	 * Выполняем перебор всех атрибутов узла
	 */
	for(uint32_t i = 0; i < record.attributes; i++){
		// Получаем запись очередного атрибута
		const Document::property_t & property = this->_document->_attributes[record.attribute + i];
		/**
		 * Если имя атрибута совпадает с искомым
		 */
		if(this->_document->get(property.name).is(uri, local))
			// Выводим значение найденного атрибута
			return this->_document->get(property.value);
	}
	// Выводим пустую последовательность знаков
	return string_view();
}
/**
 * @brief Метод проверки наличия атрибута у узла
 *
 * @param local местное имя искомого атрибута
 * @param uri   обозначение пространства имён искомого атрибута
 * @return      результат проверки
 *
 */
bool awh::codec::xml::Node::has(const string_view local, const string_view uri) const noexcept {
	/**
	 * Если узел непригоден
	 */
	if(!this->valid())
		// Выводим отрицательный результат проверки
		return false;
	// Получаем запись текущего узла
	const Document::record_t & record = this->_document->_nodes[this->_id];
	/**
	 * Выполняем перебор всех атрибутов узла
	 */
	for(uint32_t i = 0; i < record.attributes; i++){
		/**
		 * Если имя атрибута совпадает с искомым
		 */
		if(this->_document->get(this->_document->_attributes[record.attribute + i].name).is(uri, local))
			// Выводим положительный результат проверки
			return true;
	}
	// Выводим отрицательный результат проверки
	return false;
}
