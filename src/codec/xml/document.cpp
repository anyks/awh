/**
 * @brief Метод записи дерева разметки текстом с указанными настройками
 *
 * @param settings настройки записи текста разметки
 * @return         текст разметки собранного дерева
 *
 */
string awh::codec::xml::Document::dump(const writer_settings_t & settings) const noexcept {
	/**
	 * Выполняем сброс кода отказа и положения прежней работы
	 *
	 * @details У отказа записи места в исходном тексте нет вовсе, а код и положение
	 * прежнего разбора, запись пережив, складывались бы с нею в донесение стройное, но
	 * ложное: успешная запись отвечала бы кодом давно исправленного отказа. Документ
	 * JSON и таблица CSV держатся того же правила
	 */
	this->_error = error_t::NONE;
	// Выполняем сброс положения отказа прежней работы
	this->_errorLocation = location_t();
	/**
	 * Если узла разметки в дереве нет
	 *
	 * @note Отвечать здесь отказом записи о непригодном узле нельзя: узел непригоден
	 *       оттого, что корня НЕТ вовсе, и потребителю нужен именно этот довод. Запись
	 *       же о непригодном узле отправляла бы его искать изъян в поданном узле
	 *
	 * @warning Судить о пустоте по числу узлов арены НЕЛЬЗЯ: снос узлов её не убавляет
	 *          вовсе - отвязанные узлы остаются в ней недостижимыми, - и дерево, у
	 *          какого снесён единственный узел разметки, пустым по этому счёту не
	 *          выглядит. Замер: запись такого дерева отдавала ПУСТОЙ текст с кодом
	 *          «нет ошибки», то есть отказ был неотличим от успеха
	 */
	if(!this->element().valid()){
		// Запоминаем код отказа записи дерева без корневого узла
		this->_error = error_t::MISSING_ROOT;
		// Выводим пустой текст разметки
		return string();
	}
	// Объект записи текста разметки
	writer_t writer(this->_log, settings);
	/**
	 * Если запись дерева разметки не удалась
	 *
	 * @note Код отказа кладётся в дерево, а текст выдаётся пустой: иначе потребитель
	 *       получил бы половину разметки, не отличимую от целой
	 */
	if(!writer.element(this->root())){
		// Запоминаем код отказа записи текста разметки
		this->_error = writer.error();
		// Выводим пустой текст разметки
		return string();
	}
	// Выводим собранный текст разметки
	return writer.text();
}
/**
 * @brief Функция проверки того, что адрес указывает на каталог
 *
 * @details Каталог, поданный вместо файла, ОТКРЫВАЕТСЯ потоком успешно, а чтение его
 * ставит признаки конца и отказа - те же самые, какими отзывается файл ПУСТОЙ. Отличить
 * их по одному лишь потоку нельзя, и распознаётся каталог по самому адресу
 *
 * @param filename проверяемый адрес
 * @return         признак того, что адрес указывает на каталог
 *
 */
static bool directory(const string & filename) noexcept {
	// Сведения об объекте файловой системы
	struct stat info;
	// Выводим результат проверки того, что адрес указывает на каталог
	return ((::stat(filename.c_str(), & info) == 0) && S_ISDIR(info.st_mode));
}
/**
 * @brief Метод разбора текста разметки из файла
 *
 * @param filename адрес файла разметки
 * @return         признак успешности разбора
 *
 */
bool awh::codec::xml::Document::load(const string & filename) noexcept {
	// Выполняем очистку дерева разметки
	this->clear();
	/**
	 * Если адрес указывает на каталог
	 *
	 * @note Распознавание идёт ДО открытия потока намеренно, и порядок этот держит
	 *       договор одним на все системы. У систем POSIX каталог открывается успешно,
	 *       а читается признаками конца и отказа - теми же, какими отзывается файл
	 *       пустой, - и распознать его после открытия ещё можно. У MS Windows каталог
	 *       не открывается ВОВСЕ: поток отвечает отказом с кодом 13, и распознавание,
	 *       стоящее после открытия, там мёртво - каталог отвечал бы кодом отказа
	 *       ОТКРЫТИЯ вместо кода отказа чтения. Замерено на стенде Windows 11 ARM64
	 */
	if(::directory(filename)){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа чтения файла разметки
		this->_error = error_t::FILE_NOT_READ;
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачного разбора
		return false;
	}
	// Открываем файл разметки для чтения
	ifstream file(filename, ios::binary);
	/**
	 * Если файл разметки открыть не удалось
	 *
	 * @note Отказ этот идёт мимо чтения, а вывод в лог ведёт именно оно: без настоящего
	 *       вывода открытие файла отказывало бы молча, тогда как отказ разбора того же
	 *       файла в лог уходит
	 */
	if(!file.is_open()){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа открытия файла разметки
		this->_error = error_t::FILE_NOT_OPENED;
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачного разбора
		return false;
	}
	// Собираемый текст разметки
	string text;
	// Хранилище куска читаемого файла
	string chunk(0x4000, 0);
	/**
	 * Выполняем чтение файла разметки кусками
	 */
	while(file.read(chunk.data(), static_cast <streamsize> (chunk.size())) || (file.gcount() > 0))
		// Добавляем прочитанный кусок файла к собираемому тексту
		text.append(chunk.data(), static_cast <size_t> (file.gcount()));
	/**
	 * Если чтение файла оборвалось отказом
	 *
	 * @note Проверка стоит после цикла, а не внутри: признак негодности потока
	 *       сбрасывается лишь явно, и после цикла он тот же
	 *
	 * @note Заслон обратился в СЕТЬ БЕЗОПАСНОСТИ и набором не покрыт. Прежде он ловил
	 *       каталог, поданный вместо файла: у POSIX каталог открывается, а читается
	 *       отказом. Ныне распознавание каталога стоит ДО открытия потока, и каталог
	 *       сюда не доходит вовсе - отказ приходит выше, тем же кодом. Остаётся ему
	 *       ловить отказ носителя посреди чтения, проверкой не добываемый. Замерено
	 *       щупом по местам отказа 04.09.2026: подмена кода здесь не красит ничего, а
	 *       проверка чтения каталога проходит и с подменённым. Тот же довод и у JSON
	 *
	 * @warning Снимать заслон нельзя: без него оборванное чтение выглядело бы разметкой,
	 *          прочитанной до конца, - успехом на половине данных
	 */
	if(file.bad()){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа чтения файла разметки
		this->_error = error_t::FILE_NOT_READ;
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачного разбора
		return false;
	}
	// Выводим признак успешности разбора собранного текста разметки
	return this->parse(text);
}
/**
 * @brief Метод записи дерева разметки в файл
 *
 * @param filename адрес файла разметки
 * @return         признак успешности записи
 *
 */
bool awh::codec::xml::Document::save(const string & filename) const noexcept {
	// Выводим итог записи дерева разметки с хранимыми настройками дерева
	return this->save(filename, this->_settings.writer);
}
/**
 * @brief Метод записи дерева разметки в файл с указанными настройками
 *
 * @param filename адрес файла разметки
 * @param settings настройки записи текста разметки
 * @return         признак успешности записи
 *
 */
bool awh::codec::xml::Document::save(const string & filename, const writer_settings_t & settings) const noexcept {
	// Получаем собранный текст разметки
	const string text = this->dump(settings);
	/**
	 * Если собрать текст разметки не удалось
	 *
	 * @note Выдача текста код отказа уже поставила, коли отказала: здесь он лишь
	 *       дополняется случаем дерева ПУСТОГО, где записывать попросту нечего
	 */
	if(text.empty()){
		/**
		 * Если своего отказа выдача текста не дала
		 *
		 * @note Ветвь эта - СЕТЬ БЕЗОПАСНОСТИ и набором не покрыта: выдача текста при
		 *       дереве без корня код ставит сама, и до постановки кода здесь дело не
		 *       доходит. Достижима она стала бы лишь при собственном изъяне выдачи -
		 *       пустой текст без названной причины. Замерено щупом по местам отказа
		 *       05.09.2026; те же ветви с тем же доводом стоят у документа JSON и у
		 *       владеющего значения обоих кодеков
		 *
		 * @warning Снимать ветвь нельзя: без неё сохранение отвечало бы неудачей с кодом
		 *          `NONE`, а это худший из исходов - отказ, себя не называющий
		 */
		if(this->_error == error_t::NONE)
			// Запоминаем код отказа записи дерева без корневого узла
			this->_error = error_t::MISSING_ROOT;
		// Выводим признак неудачной записи
		return false;
	}
	/**
	 * Адрес временного файла, куда собирается текст
	 *
	 * @details Текст пишется рядом с целью и переносится на неё лишь по успешном
	 * завершении. Прежде запись шла прямо в цель, открытую с усечением: отказ самой
	 * записи, - переполненный носитель либо превышенный предел размера файла, - оставлял
	 * ПРЕЖНЕЕ СОДЕРЖИМОЕ ЦЕЛИ УНИЧТОЖЕННЫМ, а на его месте половину нового текста, тогда
	 * как вызов отвечал отказом. Замер щупом при пределе `RLIMIT_FSIZE`: файл о годном
	 * содержимом в 4096 октетов обращался в обрубок о 8192, а сохранение выводило `false`.
	 * Тем же порядком пользуется таблица CSV
	 */
	const string temporary = (filename + ".awh-tmp");
	// Открываем временный файл для записи
	ofstream file(temporary, ios::binary | ios::trunc);
	/**
	 * Если файл разметки открыть не удалось
	 */
	if(!file.is_open()){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа открытия файла разметки
		this->_error = error_t::FILE_NOT_OPENED;
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачной записи
		return false;
	}
	// Выполняем запись текста разметки в файл
	file.write(text.data(), static_cast <streamsize> (text.size()));
	/**
	 * Выполняем закрытие файла разметки
	 *
	 * @note Закрытие обязано идти ЯВНО и до вывода признака: поток сбрасывает свой буфер
	 *       разрушением своим, то есть уже ПОСЛЕ вычисления возвращаемого значения
	 */
	file.close();
	/**
	 * Если запись текста разметки в файл не удалась
	 */
	if(!file){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа записи файла разметки
		this->_error = error_t::FILE_NOT_WRITTEN;
		// Выполняем снос недописанного временного файла
		::remove(temporary.c_str());
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачной записи
		return false;
	}
	/**
	 * Если перенос собранного текста на место цели не удался
	 *
	 * @note Перенос этот и делает сохранение неделимым: цель либо остаётся прежней,
	 *       либо становится новым текстом целиком, а половины её не видно никогда
	 */
	if(::rename(temporary.c_str(), filename.c_str()) != 0){
		/**
		 * Если объект ведения журнала работы установлен
		 */
		// Запоминаем код отказа переноса временного файла на место цели
		this->_error = error_t::FILE_NOT_WRITTEN;
		// Выполняем снос временного файла
		::remove(temporary.c_str());
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @warning Сообщение выводится ПО ЗАПОМНЕННОМУ коду, а не по литералу: код,
		 *          в месте отказа записанный ДВАЖДЫ, разошёлся бы молча, а проверка,
		 *          сличающая сообщение, подмены кода в поле не увидела бы вовсе.
		 *          Найдено щупом по местам отказа у кодека CSV 04.09.2026
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе
			this->_log->print("XML document failed: %s", log_t::flag_t::CRITICAL, awh::codec::xml::message(this->_error));
		// Выводим признак неудачной записи
		return false;
	}
	// Выводим признак успешности записи
	return true;
}
/**
 * @brief Метод получения корня дерева
 *
 * @return корневой узел дерева разметки
 *
 */
awh::codec::xml::node_t awh::codec::xml::Document::root() const noexcept {
	/**
	 * Если дерево разметки пусто
	 */
	if(this->_nodes.empty())
		// Выводим непригодный узел дерева разметки
		return node_t();
	// Выводим корень дерева разметки
	return node_t(this, 0);
}
/**
 * @brief Метод получения корневого узла разметки
 *
 * @return единственный узел разметки верхнего уровня
 *
 */
awh::codec::xml::node_t awh::codec::xml::Document::element() const noexcept {
	/**
	 * Выполняем перебор всех узлов верхнего уровня
	 */
	for(node_t node = this->root().first(); node.valid(); node = node.next()){
		/**
		 * Если обнаружен узел разметки
		 */
		if(node.kind() == kind_t::ELEMENT)
			// Выводим обнаруженный узел разметки
			return node;
	}
	// Выводим непригодный узел дерева разметки
	return node_t();
}
/**
 * @brief Метод получения количества узлов дерева
 *
 * @return количество узлов в арене дерева разметки
 *
 */
size_t awh::codec::xml::Document::size() const noexcept {
	// Выводим количество вложенных узлов корня разметки
	return this->element().size();
}
/**
 * @brief Метод получения количества узлов арены дерева
 *
 * @return количество узлов в арене дерева разметки
 *
 */
size_t awh::codec::xml::Document::nodes() const noexcept {
	// Выводим количество узлов в арене дерева разметки
	return this->_nodes.size();
}
/**
 * @brief Метод проверки дерева на пустоту
 *
 * @return результат проверки
 *
 */
bool awh::codec::xml::Document::empty() const noexcept {
	// Выводим результат проверки дерева на пустоту
	return (this->_nodes.size() <= 1);
}
/**
 * @brief Метод очистки дерева разметки
 *
 */
void awh::codec::xml::Document::clear() noexcept {
	/**
	 * Наращиваем клеймо поколения дерева
	 *
	 * @note Узлы, снятые прежде, тем и обращаются в непригодные: очистка меняет нумерацию
	 *       узлов, и узел с прежним опознавателем указывал бы на чужой узел
	 */
	this->_stamp++;
	// Выполняем сброс кода ошибки разбора
	this->_error = error_t::NONE;
	// Выполняем сброс положения обнаруженной ошибки
	this->_errorLocation = location_t();
	// Выполняем сброс кодировки прочитанного текста разметки
	this->_encoding = encoding_t::NONE;
	// Выполняем очистку арены узлов дерева разметки
	this->_nodes.clear();
	/**
	 * Выполняем очистку отображений имён вложенных узлов
	 *
	 * @warning Очистка эта обязательна: ключи отображений суть виды в общее хранилище
	 *          знаков, и пережившие его очистку они указывали бы в освобождённую память
	 */
	this->_index.clear();
	// Выполняем очистку хранилища атрибутов
	this->_attributes.clear();
	// Выполняем очистку хранилища связываний префиксов
	this->_scopes.clear();
	// Выполняем очистку отрезков хранилища связываний
	this->_scoped.clear();
	// Выполняем очистку общего хранилища знаков
	this->_storage.clear();
	// Выполняем очистку таблицы размещённых имён
	this->_interned.clear();
}
