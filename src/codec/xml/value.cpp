/**
 * @brief Метод установки имени узла
 *
 * @param local  устанавливаемое местное имя узла
 * @param uri    устанавливаемое обозначение пространства имён
 * @param prefix устанавливаемый префикс пространства имён
 *
 */
void awh::codec::xml::Value::name(const string & local, const string & uri, const string & prefix) noexcept {
	/**
	 * Если узел ещё не определён
	 *
	 * @note Значение неопределённое перерождается узлом разметки: имя без содержимого
	 *       есть разметка, и иного вида, годного ему, у разметки нет. Правило это -
	 *       двойник установки содержимого, где значение неопределённое перерождается
	 *       узлом текстовым
	 *
	 * @warning Без перерождения узел оставался бы без вида, и записи не подлежало бы
	 *          ВСЁ ДЕРЕВО целиком: выдача текста отвечала бы пустотою, а отличить её от
	 *          отказа записи потребителю нечем. Всплывало это ростом перечня по номеру,
	 *          где заведённые узлы вида не имеют по устройству
	 */
	if(this->_kind == kind_t::NONE)
		// Устанавливаем вид узла разметкой
		this->_kind = kind_t::ELEMENT;
	/**
	 * Если имя построено ошибочно
	 *
	 * @details Имя, договору не отвечающее, лишает записи ВСЁ ДЕРЕВО целиком: выдача
	 * текста отвечает пустотою, а отличить её от отказа записи потребителю нечем -
	 * довод тот же, что и у перерождения узла выше. Замер: `value[0].name("а б")` и
	 * далее `value.dump()` выдавал пустую строку по всему дереву без всякого отказа,
	 * и так же отзывались имена `1а`, `<`, `&` и имя пустое
	 *
	 * @note Указание НЕ СБЫВАЕТСЯ, а не отвергается отказом: своего канала отказа у
	 *       установки нет вовсе, а имя прежнее целость дерева сберегает. Правило это -
	 *       двойник настроек записи таблицы CSV, где смена грамматики посреди сборки
	 *       снимается тем же доводом
	 *
	 * @note Судится имя тем же судьёй, каким судит его запись, и с тем же допуском
	 *       разделителя префикса: имя без префикса и без обозначения пространства имён
	 *       записывается дословно, и разделитель в нём законен
	 */
	if(!nameable(local, (prefix.empty() && uri.empty())))
		// Выходим из метода, оставляя имя прежним
		return;
	// Устанавливаем местное имя узла
	this->_local = local;
	// Устанавливаем обозначение пространства имён узла
	this->_uri = uri;
	// Устанавливаем префикс пространства имён узла
	this->_prefix = prefix;
}
/**
 * @brief Метод сбора содержимого вложенных текстовых узлов
 *
 * @param result строка, куда собирается содержимое
 *
 */
void awh::codec::xml::Value::gather(string & result) const noexcept {
	/**
	 * Выполняем перебор всех вложенных узлов
	 */
	for(auto & item : this->_items){
		/**
		 * Определяем вид вложенного узла
		 */
		switch(item._kind){
			// Если узел является текстовым содержимым либо дословным разделом
			case kind_t::TEXT:
			case kind_t::CDATA:
			case kind_t::SPACE:
				// Добавляем содержимое узла к собираемому содержимому
				result.append(item._text);
			break;
			/**
			 * Если узел является узлом разметки
			 *
			 * @note Содержимое вложенной разметки собирается наравне со своим: ровно так
			 *       его собирает и узел дерева
			 */
			case kind_t::ELEMENT:
				// Выполняем сбор содержимого вложенного узла разметки
				item.gather(result);
			break;
			/**
			 * Если разбор дошёл до членов перечня, обработки здесь не требующих
			 *
			 * @note Вложенных узлов они не имеют, и обходить у них нечего
			 *
			 * @warning Перечислены они НАМЕРЕННО вместо `default`: ветвь `default` глушит
			 *          `-Wswitch`, и член, в перечень дописанный, прошёл бы это место молча
			 */
			case kind_t::NONE:
			case kind_t::DOCUMENT:
			case kind_t::COMMENT:
			case kind_t::PROCESSING:
			case kind_t::DOCTYPE:
			break;
		}
	}
}
/**
 * @brief Метод извлечения содержимого узла
 *
 * @return содержимое узла
 *
 */
string awh::codec::xml::Value::text() const noexcept {
	/**
	 * Определяем вид хранимого узла
	 */
	switch(this->_kind){
		// Если узел владеет содержимым своим
		case kind_t::TEXT:
		case kind_t::CDATA:
		case kind_t::SPACE:
		case kind_t::COMMENT:
		case kind_t::PROCESSING:
		case kind_t::DOCTYPE:
			// Выводим собственное содержимое узла
			return this->_text;
		/**
		 * Если разбор дошёл до видов, обработки здесь не требующих
		 *
		 * @note Собственного содержимого у них нет: у корня и у разметки оно лежит во вложенных узлах, а узел неопределённый его не имеет
		 *
		 * @warning Перечислены они НАМЕРЕННО вместо `default`: приведение к `default`
		 *          глушит `-Wswitch`, и новый член перечня пройдёт молча
		 */
		case kind_t::NONE:
		case kind_t::DOCUMENT:
		case kind_t::ELEMENT:
		break;
	}
	// Собираемое содержимое вложенных текстовых узлов
	string result;
	// Выполняем сбор содержимого вложенных текстовых узлов
	this->gather(result);
	// Выводим собранное содержимое узла
	return result;
}
/**
 * @brief Метод установки собственного содержимого узла
 *
 * @param text устанавливаемое содержимое узла
 * @return     признак успешности установки
 *
 */
bool awh::codec::xml::Value::text(const string & text) noexcept {
	/**
	 * Определяем вид хранимого узла
	 */
	switch(this->_kind){
		/**
		 * Если узел ещё не определён
		 *
		 * @note Значение неопределённое перерождается узлом текстовым: содержимое без
		 *       имени есть текст, и иного вида, годного ему, у разметки нет
		 */
		case kind_t::NONE:
			// Устанавливаем вид узла текстовым содержимым
			this->_kind = kind_t::TEXT;
		/**
		 * Проваливаемся к установке содержимого НАМЕРЕННО
		 *
		 * @note Пометка обязательна: без неё собиратель числит проваливание недосмотром и
		 *       предупреждает, а намеренное неотличимо от забытого `break`
		 */
		[[fallthrough]];
		// Если узел владеет содержимым своим
		case kind_t::TEXT:
		case kind_t::CDATA:
		case kind_t::SPACE:
		case kind_t::COMMENT:
		case kind_t::PROCESSING:
		case kind_t::DOCTYPE:
			// Устанавливаем собственное содержимое узла
			this->_text = text;
			// Выводим признак успешной установки
			return true;
		/**
		 * Если узел является узлом разметки
		 *
		 * @note Собственного содержимого у разметки нет вовсе: установка заменяет все
		 *       вложенные узлы одним узлом текстовым
		 */
		case kind_t::ELEMENT: {
			// Выполняем очистку вложенных узлов
			this->_items.clear();
			/**
			 * Если устанавливаемое содержимое не пусто
			 *
			 * @warning Узел текста с содержимым ПУСТЫМ не заводится намеренно: записи у
			 *          такого узла нет никакой - разметка пишет «<a></a>», - и разбор той
			 *          же записи даёт узел БЕЗ детей. Заводя его, дерево держало бы одно,
			 *          а записывало бы другое: размер узла до перезаписи выходил бы
			 *          единицей, а после неё нулём, и обход выдавал бы призрачный узел,
			 *          которого в тексте нет и быть не может
			 * @note Установлено сличением правки с её перезаписью 23.08.2026; приём
			 *       сличения подсказан владельцем модуля YAML
			 */
			if(!text.empty())
				// Добавляем во вложенные узлы узел текстового содержимого
				this->_items.push_back(Value(kind_t::TEXT, text));
			// Выполняем сброс отображения имён вложенных узлов
			this->reindex();
			// Выводим признак успешной установки
			return true;
		}
		/**
		 * Если разбор дошёл до видов, обработки здесь не требующих
		 *
		 * @note Собственного содержимого у корня дерева нет: содержимое ложится во вложенные узлы
		 *
		 * @warning Перечислены они НАМЕРЕННО вместо `default`: приведение к `default`
		 *          глушит `-Wswitch`, и новый член перечня пройдёт молча
		 */
		case kind_t::DOCUMENT:
		break;
	}
	// Выводим признак неудачной установки
	return false;
}
/**
 * @brief Метод извлечения свойств узла разметки
 *
 * @return перечень свойств узла в порядке их следования
 *
 */
const vector <awh::codec::xml::Value::property_t> & awh::codec::xml::Value::attributes() const noexcept {
	// Выводим перечень свойств узла
	return this->_attributes;
}
/**
 * @brief Метод извлечения значения свойства узла разметки
 *
 * @param local местное имя разыскиваемого свойства
 * @param uri   обозначение пространства имён свойства
 * @return      значение свойства, пустое - свойства такого нет
 *
 */
const string & awh::codec::xml::Value::attribute(const string & local, const string & uri) const noexcept {
	/**
	 * Выполняем розыск номера свойства узла
	 *
	 * @note Сличение идёт по паре обозначения пространства имён и местного имени, а не по
	 *       записи с префиксом: отвечающие по UPnP ставят префиксы всякий по-своему, и
	 *       сличение записью на них разваливается
	 */
	const size_t index = this->property(local, uri);
	/**
	 * Если свойство узла разыскано
	 */
	if(index != string::npos)
		// Выводим значение разысканного свойства
		return this->_attributes.at(index).value;
	// Выводим отсутствие значения свойства
	return ::empty();
}
/**
 * @brief Метод установки свойства узла разметки
 *
 * @param local  местное имя свойства
 * @param value  устанавливаемое значение свойства
 * @param uri    обозначение пространства имён свойства
 * @param prefix префикс пространства имён свойства
 * @return       признак успешности установки
 *
 */
bool awh::codec::xml::Value::attribute(const string & local, const string & value, const string & uri, const string & prefix) noexcept {
	/**
	 * Если узел ещё не определён
	 */
	if(this->_kind == kind_t::NONE)
		// Устанавливаем вид узла разметкой
		this->_kind = kind_t::ELEMENT;
	/**
	 * Если узел узлом разметки не является
	 *
	 * @note Свойства принадлежат разметке и никому иному: у текстового содержимого,
	 *       примечания и дословного раздела свойств не бывает вовсе
	 */
	if(this->_kind != kind_t::ELEMENT)
		// Выводим признак неудачной установки
		return false;
	/**
	 * Если имя свойства построено ошибочно
	 *
	 * @details Довод тот же, что и у имени узла: свойство, договору не отвечающее,
	 * лишает записи всё дерево целиком - замер дал пустую строку по всему дереву на
	 * именах `а б`, `1а` и имени пустом, причём установка отвечала УСПЕХОМ
	 *
	 * @note Здесь отказ поднимается настоящий: у установки свойства свой канал отказа
	 *       есть, и молчаливое неисполнение было бы хуже отказа
	 */
	if(!nameable(local, (prefix.empty() && uri.empty())))
		// Выводим признак неудачной установки
		return false;
	// Выполняем розыск номера устанавливаемого свойства узла
	const size_t index = this->property(local, uri);
	/**
	 * Если свойство узла уже заведено
	 *
	 * @note Пара имени и пространства имён у свойства неизменна, и отображение правки
	 *       здесь не требует: свойство перезаписывается на СВОЁМ месте, номер его не
	 *       двигается, а ключом отображения служит именно эта пара
	 */
	if(index != string::npos){
		// Выполняем перезапись значения свойства на своём месте
		this->_attributes.at(index).value = value;
		// Выполняем перезапись префикса пространства имён свойства
		this->_attributes.at(index).prefix = prefix;
		// Выводим признак успешной установки
		return true;
	}
	// Заводим свойство узла разметки
	this->_attributes.emplace_back();
	// Устанавливаем префикс пространства имён свойства
	this->_attributes.back().prefix = prefix;
	// Устанавливаем местное имя свойства
	this->_attributes.back().local = local;
	// Устанавливаем обозначение пространства имён свойства
	this->_attributes.back().uri = uri;
	// Устанавливаем значение свойства
	this->_attributes.back().value = value;
	// Выполняем учёт заведённого свойства узла в отображении имён
	this->propertied(local, uri);
	// Выводим признак успешной установки
	return true;
}
/**
 * @brief Метод проверки наличия свойства у узла разметки
 *
 * @param local местное имя разыскиваемого свойства
 * @param uri   обозначение пространства имён свойства
 * @return      признак наличия свойства
 *
 */
bool awh::codec::xml::Value::has(const string & local, const string & uri) const noexcept {
	// Выводим признак наличия свойства узла по итогу его розыска
	return (this->property(local, uri) != string::npos);
}
/**
 * @brief Метод снятия свойства узла разметки
 *
 * @param local местное имя снимаемого свойства
 * @param uri   обозначение пространства имён свойства
 * @return      признак успешности снятия
 *
 */
bool awh::codec::xml::Value::detach(const string & local, const string & uri) noexcept {
	// Выполняем розыск номера снимаемого свойства узла
	const size_t index = this->property(local, uri);
	/**
	 * Если свойство узла разыскано
	 */
	if(index != string::npos){
		// Выполняем снятие свойства узла
		// Получаем признак снятия последнего свойства перечня
		const bool trailing = (index == (this->_attributes.size() - 1));
		// Выполняем снятие свойства узла
		this->_attributes.erase(this->_attributes.begin() + static_cast <ptrdiff_t> (index));
		/**
		 * Если снято свойство из середины перечня
		 *
		 * @warning Сброс здесь обязателен и правкой не заменяется: снятие свойства из
		 *          середины перечня сдвигает номера ВСЕХ свойств, следующих за ним, и
		 *          отображение стало бы указывать мимо
		 */
		if(!trailing)
			// Выполняем сброс отображения имён свойств узла
			this->reproperty();
		/**
		 * Если отображение имён свойств заведено, а снято свойство последнее
		 *
		 * @details Номера прочих свойств снятие последнего не двигает, и сноса отображения
		 * оно не требует: довольно изъять из него одну запись. Снос обошёлся бы разбором
		 * всего отображения, тогда как сдвигать в перечне при том нечего вовсе
		 *
		 * @note Замерено 23.08.2026: снос отображения стоил 132 мкс при 16384 свойствах,
		 *       тогда как само изъятие из перечня - 15 нс. Разряд сложности снятия
		 *       последнего сносом обращался из постоянного в линейный
		 */
		else if(this->_propertied){
			// Выполняем поиск местного имени снятого свойства в отображении
			auto i = this->_properties.find(local);
			/**
			 * Если местное имя снятого свойства в отображении разыскано
			 */
			if(i != this->_properties.end()){
				// Выполняем изъятие пространства имён снятого свойства из отображения
				i->second.erase(uri);
				/**
				 * Если иных пространств имён у этого имени не осталось
				 */
				if(i->second.empty())
					// Выполняем изъятие местного имени снятого свойства из отображения
					this->_properties.erase(i);
			}
		}
		// Выводим признак успешного снятия
		return true;
	}
	// Выводим признак неудачного снятия
	return false;
}
/**
 * @brief Метод извлечения связываний префиксов, объявленных узлом
 *
 * @return перечень связываний префиксов
 *
 */
const vector <awh::codec::xml::Value::namespace_t> & awh::codec::xml::Value::bindings() const noexcept {
	// Выводим перечень связываний префиксов
	return this->_bindings;
}
/**
 * @brief Метод объявления связывания префикса с пространством имён
 *
 * @param prefix объявляемый префикс, пустой - объявление по умолчанию
 * @param uri    обозначение пространства имён, пустое - отмена связывания
 * @return       признак успешности объявления
 *
 */
bool awh::codec::xml::Value::binding(const string & prefix, const string & uri) noexcept {
	/**
	 * Если узел ещё не определён
	 */
	if(this->_kind == kind_t::NONE)
		// Устанавливаем вид узла разметкой
		this->_kind = kind_t::ELEMENT;
	/**
	 * Если узел узлом разметки не является
	 */
	if(this->_kind != kind_t::ELEMENT)
		// Выводим признак неудачного объявления
		return false;
	/**
	 * Выполняем перебор всех связываний префиксов узла
	 */
	for(auto & item : this->_bindings){
		/**
		 * Если префикс связывания совпадает с объявляемым
		 */
		if(item.prefix.compare(prefix) == 0){
			// Выполняем перезапись обозначения пространства имён на своём месте
			item.uri = uri;
			// Выводим признак успешного объявления
			return true;
		}
	}
	// Заводим связывание префикса
	this->_bindings.emplace_back();
	// Устанавливаем объявляемый префикс
	this->_bindings.back().prefix = prefix;
	// Устанавливаем обозначение пространства имён
	this->_bindings.back().uri = uri;
	// Выводим признак успешного объявления
	return true;
}
