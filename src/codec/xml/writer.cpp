/**
 * @brief Метод записи объявления разметки
 *
 * @param standalone признак самодостаточности текста разметки
 * @return           результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::declaration(const standalone_t standalone) noexcept {
	/**
	 * Если запись уже прекращена ошибкой либо текст не пуст
	 */
	if((this->_error != error_t::NONE) || !this->_text.empty()){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_DECLARATION;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем добавление объявления разметки
	this->_text.append("<?xml version=\"1.0\" encoding=\"UTF-8\"");
	/**
	 * Если текст объявлен самодостаточным
	 */
	if(standalone == standalone_t::YES)
		// Выполняем добавление признака самодостаточности
		this->_text.append(" standalone=\"yes\"");
	/**
	 * Если текст объявлен зависящим от внешнего подмножества
	 */
	else if(standalone == standalone_t::NO)
		// Выполняем добавление признака самодостаточности
		this->_text.append(" standalone=\"no\"");
	// Выполняем добавление конца объявления разметки
	this->_text.append("?>");
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод открытия узла разметки
 *
 * @param local местное имя открываемого узла
 * @param uri   обозначение пространства имён открываемого узла
 * @return      результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::open(const string_view local, const string_view uri) noexcept {
	// Выводим результат открытия узла разметки без заданных объявлений
	return this->open(local, uri, nullptr, nullptr, false, false);
}
/**
 * @brief Метод открытия узла разметки с заданными объявлениями
 *
 * @param local    местное имя открываемого узла
 * @param uri      обозначение пространства имён открываемого узла
 * @param declares  объявления пространств имён, записываемые узлу
 * @param preferred префикс, каким имя узла записано в исходном тексте
 * @return          результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::open(const string_view local, const string_view uri, const vector <binding_t> * declares, const string_view * preferred, const bool verbatim, const bool oneline) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если имя открываемого узла построено ошибочно
	 */
	if(verbatim ? !::plain(local) : !::correct(local)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAME;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если корневой узел разметки в тексте уже записан
	 *
	 * @note Правильно построенный текст разметки вмещает единственный корневой
	 *       узел, и второй такой узел записи не подлежит
	 */
	if((this->_depth == 0) && this->_root){
		// Запоминаем код ошибки записи
		this->_error = error_t::MULTIPLE_ROOTS;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем завершение незакрытой метки узла
	this->flush();
	/**
	 * Если открываемый узел вложен в другой
	 */
	if(this->_depth > 0){
		// Запоминаем, что узел содержит вложенное содержимое
		this->_opened[this->_depth - 1].filled = true;
		// Запоминаем, что узел содержит вложенные узлы разметки
		this->_opened[this->_depth - 1].elements = true;
	}
	/**
	 * Если глубина вложенности узлов превысила допустимую
	 *
	 * @note Предел по умолчанию снят: обход дерева ведётся собственным стеком, и стеку
	 *       задачи глубина записи больше не грозит. Держать здесь предел разбора значило
	 *       бы отвергать дерево, разобранное с поднятым пределом глубины, - разобранное
	 *       обязано записываться обратно
	 */
	if((this->_settings.maxDepth > 0) && (this->_depth >= this->_settings.maxDepth)){
		// Запоминаем код ошибки записи
		this->_error = error_t::DEPTH_EXCEEDED;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если объемлющий узел записывается в одну строку
	 *
	 * @note Отступ внутри такого узла переменил бы его содержимое: пробельные знаки
	 *       там значимы наравне с прочими
	 */
	if((this->_depth == 0) || !this->_opened[this->_depth - 1].oneline)
		// Выполняем запись отступа перед узлом
		this->indent();
	// Запоминаем, что корневой узел разметки записан
	this->_root = true;
	/**
	 * Если запись под очередной уровень вложенности ещё не заведена
	 *
	 * @note Заводится она однажды и дальше переиспользуется: закрытие узла
	 *       записи не уничтожает, а лишь уменьшает глубину стека
	 */
	if(this->_depth >= this->_opened.size())
		// Выполняем заведение записи под очередной уровень вложенности
		this->_opened.emplace_back();
	// Получаем запись очередного открываемого узла
	opened_t & opened = this->_opened[this->_depth];
	/**
	 * Выполняем сброс переиспользуемой записи открытого узла
	 *
	 * @note Очистка хранилищ ёмкости их не отнимает, и следующему узлу они
	 *       достаются уже готовыми: ради этого записи и переиспользуются
	 */
	opened.name.clear();
	opened.names.clear();
	// Запоминаем, что узел содержимого ещё не имеет
	opened.filled = false;
	// Запоминаем, что вложенных узлов узел ещё не имеет
	opened.elements = false;
	// Запоминаем, записывается ли содержимое узла в одну строку
	opened.oneline = oneline;
	// Запоминаем, что связываний узел ещё не объявил
	opened.bindings = 0;
	// Запоминаем, что метка узла не завершена
	opened.pending = true;
	// Выполняем углубление стека открытых узлов
	this->_depth++;
	// Выполняем добавление начала метки узла
	this->_text.push_back('<');
	// Запоминаем положение имени узла в записанном тексте
	const size_t begin = this->_text.size();
	// Выполняем добавление местного имени узла
	this->_text.append(local);
	/**
	 * Если узлу заданы объявления пространств имён
	 *
	 * @details Объявления записываются прежде подбора префикса: подбор находит тогда
	 *          заданный префикс уже связанным и своего не назначает. Так и сохраняется
	 *          запись имён исходного текста при обратной записи дерева - переназначенный
	 *          префикс смысла имён не меняет, но меняет сам текст, а договор о подписи
	 *          XML сличает документы знак в знак
	 */
	if(declares != nullptr){
		/**
		 * Выполняем перебор всех заданных объявлений пространств имён
		 */
		for(const binding_t & item : * declares){
			/**
			 * Если объявление пространства имён записать не удалось
			 */
			if(!this->binding(item.prefix, item.uri))
				// Выводим отрицательный результат выполнения операции
				return false;
		}
	}
	// Назначенный узлу префикс пространства имён
	string prefix;
	/**
	 * Если имя узла записывается дословно
	 */
	if(verbatim){
		// Запоминаем имя узла для его закрывающей метки
		this->_opened[this->_depth - 1].name.assign(local);
		// Выводим положительный результат выполнения операции
		return true;
	}
	// Признак того, что префикс узлу уже назначен
	bool resolved = false;
	/**
	 * Если задан префикс, каким имя узла записано в исходном тексте
	 *
	 * @details Подбор префикса ищет всякое связывание с нужным обозначением и берёт
	 *          ближайшее к узлу, а их бывает несколько: одно и то же пространство имён
	 *          вправе быть объявлено и по умолчанию, и под префиксом. Ближайшее из них
	 *          не обязано совпадать с тем, каким имя записано в исходном тексте, и
	 *          обратная запись меняла бы тогда запись имени, смысла его не меняя
	 */
	if(preferred != nullptr){
		/**
		 * Выполняем перебор действующих связываний от ближайшего узла к корню
		 */
		for(size_t i = this->_bindings; i > 0; i--){
			/**
			 * Если префикс связывания совпадает с заданным
			 *
			 * @note Перебор прекращается на первом же совпадении префикса: ближайшее
			 *       связывание перекрывает все прочие с тем же префиксом, и годится
			 *       заданный префикс лишь тогда, когда связан он с нужным обозначением
			 */
			if(this->_scopes[i - 1].prefix.compare(* preferred) == 0){
				// Запоминаем, годится ли заданный префикс имени узла
				resolved = (this->_scopes[i - 1].uri.compare(uri) == 0);
				// Выходим из перебора связываний
				break;
			}
		}
		/**
		 * Если заданный префикс имени узла годится
		 */
		if(resolved)
			// Запоминаем заданный префикс пространства имён
			prefix.assign(* preferred);
	}
	/**
	 * Если префикс для пространства имён получить не удалось
	 */
	if(!resolved && !this->prefix(uri, false, prefix))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Собираем имя узла в записи, принятой в тексте
	 *
	 * @note Имя собирается прямо в записи открытого узла - там оно всё равно
	 *       требуется закрывающей метке. Сборка сцеплением дала бы на каждый узел
	 *       до трёх посредников, из которых в дело идёт лишь последний
	 */
	string & name = this->_opened[this->_depth - 1].name;
	/**
	 * Если узлу назначен префикс пространства имён
	 */
	if(!prefix.empty())
		// Выполняем добавление префикса к имени узла
		name.append(prefix).push_back(':');
	// Выполняем добавление местного имени узла
	name.append(local);
	/**
	 * Если узлу назначен префикс пространства имён
	 *
	 * @note Префикс становится известен лишь после подбора, а объявления, подбором
	 *       дописанные, стоят в тексте уже за именем: префикс встраивается на своё
	 *       место отрезком собранного имени, без посредника под запись «префикс:»
	 */
	if(!prefix.empty())
		// Выполняем встраивание префикса с разделителем перед именем узла
		this->_text.insert(begin, name, 0, prefix.length() + 1);
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод закрытия последнего открытого узла
 *
 * @return результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::close() noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если закрывать нечего
	 */
	if(this->_depth == 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::UNEXPECTED_CLOSE_TAG;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Получаем закрываемый узел разметки
	 *
	 * @warning Ссылка берётся на запись хранилища, а не её снимок: запись эта
	 *          переживает уменьшение глубины стека и годна до самого конца
	 *          метода. Снимок же переносом отнял бы у записи её хранилища
	 *          вместе с занятой ими памятью, ради сбережения которой стек и
	 *          перестал записи уничтожать
	 */
	const opened_t & opened = this->_opened[this->_depth - 1];
	/**
	 * Выполняем снятие связываний, объявленных закрываемым узлом
	 */
	for(uint32_t i = 0; i < opened.bindings; i++)
		// Выполняем снятие очередного связывания
		this->_bindings--;
	// Выполняем снятие закрываемого узла со стека
	this->_depth--;
	/**
	 * Если узел содержимого не имеет и записывается самозакрывающейся меткой
	 */
	if(opened.pending && !opened.filled && this->_settings.collapse){
		// Выполняем завершение самозакрывающейся метки узла
		this->_text.append("/>");
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Если метка узла не завершена
	 */
	if(opened.pending)
		// Выполняем завершение метки узла
		this->_text.push_back('>');
	/**
	 * Если узел содержит вложенные узлы разметки
	 */
	if(opened.elements && !opened.oneline)
		// Выполняем запись отступа перед закрывающей меткой
		this->indent();
	// Выполняем добавление закрывающей метки узла
	this->_text.append("</").append(opened.name).push_back('>');
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи атрибута открытого узла
 *
 * @param local местное имя атрибута
 * @param value значение атрибута
 * @param uri   обозначение пространства имён атрибута
 * @return      результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::occupy(const string_view name) noexcept {
	/**
	 * Выполняем перебор всех записанных имён атрибутов узла
	 */
	for(const string & item : this->_opened[this->_depth - 1].names){
		/**
		 * Если имя атрибута узлу уже записано
		 */
		if(item == name){
			// Запоминаем код ошибки записи
			this->_error = error_t::DUPLICATE_ATTRIBUTE;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	}
	// Выполняем добавление имени к записанным именам атрибутов узла
	this->_opened[this->_depth - 1].names.emplace_back(name);
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи атрибута при открытом узле
 *
 * @param local местное имя атрибута без префикса
 * @param value значение атрибута
 * @param uri   обозначение пространства имён атрибута
 * @return      результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::attribute(const string_view local, const string_view value, const string_view uri) noexcept {
	// Выводим результат записи атрибута с подбором префикса по обозначению
	return this->attribute(local, value, uri, false);
}
/**
 * @brief Метод записи атрибута при открытом узле с дословной записью имени
 *
 * @param local    имя атрибута, записываемое как есть
 * @param value    значение атрибута
 * @param uri      обозначение пространства имён атрибута
 * @param verbatim признак дословной записи имени атрибута
 * @return         результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::attribute(const string_view local, const string_view value, const string_view uri, const bool verbatim) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если метка узла уже завершена
	 */
	if((this->_depth == 0) || !this->_opened[this->_depth - 1].pending){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если имя атрибута построено ошибочно
	 */
	if(verbatim ? !::plain(local) : !::correct(local)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAME;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если атрибутом записывается объявление пространства имён
	 *
	 * @note Объявление пространства имён записывается отдельным методом: записанное
	 *       атрибутом, оно попало бы в текст мимо учёта действующих связываний, и
	 *       записываемые следом имена получили бы не то пространство имён
	 */
	if(!verbatim && (local.compare("xmlns") == 0)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Назначенный атрибуту префикс пространства имён
	string prefix;
	/**
	 * Если префикс атрибуту требуется подобрать
	 */
	if(!verbatim && !this->prefix(uri, true, prefix))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Собираемое имя атрибута в том виде, в каком оно попадает в текст
	string name;
	/**
	 * Если атрибуту назначен префикс пространства имён
	 */
	if(!prefix.empty())
		// Выполняем сборку имени атрибута с префиксом
		name.assign(prefix).append(1, ':');
	// Выполняем сборку имени атрибута
	name.append(local);
	/**
	 * Если имя атрибута узлу уже записано
	 */
	if(!this->occupy(name))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление разделителя перед атрибутом
	this->_text.push_back(' ');
	/**
	 * Если атрибуту назначен префикс пространства имён
	 */
	if(!prefix.empty())
		// Выполняем добавление префикса к имени атрибута
		this->_text.append(prefix).push_back(':');
	// Выполняем добавление имени атрибута
	this->_text.append(local).append("=\"");
	/**
	 * Если записать значение атрибута не удалось
	 */
	if(!this->escape(value, true))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление конца значения атрибута
	this->_text.push_back('"');
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод объявления пространства имён при открытом узле
 *
 * @param prefix префикс без разделителя, пустой для объявления по умолчанию
 * @param uri    обозначение объявляемого пространства имён
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::binding(const string_view prefix, const string_view uri) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если метка узла уже завершена
	 */
	if((this->_depth == 0) || !this->_opened[this->_depth - 1].pending){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_ATTRIBUTE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если префикс объявления построен ошибочно
	 */
	if(!prefix.empty() && !::correct(prefix)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_PREFIX;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если выполняется попытка переопределить отведённый договором префикс
	 */
	if((prefix.compare("xmlns") == 0) || ((prefix.compare("xml") == 0) && (uri.compare(XML_NAMESPACE) != 0))){
		// Запоминаем код ошибки записи
		this->_error = error_t::RESERVED_PREFIX;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если объявлению для префикса дано пустое обозначение
	 */
	if(!prefix.empty() && uri.empty()){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAMESPACE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если обычному префиксу дано отведённое договором пространство имён
	 *
	 * @details Пространство имён это отведено договором префиксу «xml» и никакому
	 *          иному: связывание с ним чужого префикса запрещено наравне с
	 *          переопределением самого префикса
	 */
	if(!prefix.empty() && (prefix.compare("xml") != 0) && (uri.compare(XML_NAMESPACE) == 0)){
		// Запоминаем код ошибки записи
		this->_error = error_t::RESERVED_PREFIX;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если объявлению дано пространство имён объявлений
	 *
	 * @details Пространство имён это отведено самим объявлениям и связыванию не
	 *          подлежит ни префиксом, ни объявлением по умолчанию
	 */
	if(uri.compare(XMLNS_NAMESPACE) == 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAMESPACE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если объявлению по умолчанию дано отведённое договором пространство имён
	 *
	 * @note Правила эти повторяют разбор: запись, их не соблюдающая, собрала бы
	 *       текст, который собственное чтение отвергает, - и обнаружилось бы это
	 *       уже у принимающей стороны
	 */
	if(prefix.empty() && (uri.compare(XML_NAMESPACE) == 0)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAMESPACE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Собираемое имя объявления в том виде, в каком оно попадает в текст
	string name("xmlns");
	/**
	 * Если объявление выполняется для префикса
	 */
	if(!prefix.empty())
		// Выполняем сборку имени объявления с префиксом
		name.append(1, ':').append(prefix);
	/**
	 * Если имя объявления узлу уже записано
	 */
	if(!this->occupy(name))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление начала объявления пространства имён
	this->_text.append(" xmlns");
	/**
	 * Если объявление выполняется для префикса
	 */
	if(!prefix.empty())
		// Выполняем добавление префикса объявления
		this->_text.push_back(':'), this->_text.append(prefix);
	// Выполняем добавление разделителя объявления
	this->_text.append("=\"");
	/**
	 * Если записать обозначение пространства имён не удалось
	 */
	if(!this->escape(uri, true))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление конца объявления пространства имён
	this->_text.push_back('"');
	// Выполняем отведение места под связывание
	if(this->_bindings >= this->_scopes.size())
		// Выполняем добавление места под новое связывание
		this->_scopes.emplace_back();
	// Получаем связывание, отведённое под объявление
	scope_t & scope = this->_scopes[this->_bindings++];
	// Запоминаем префикс объявления
	scope.prefix.assign(prefix);
	// Запоминаем обозначение объявляемого пространства имён
	scope.uri.assign(uri);
	// Выполняем подсчёт связываний, объявленных узлом
	this->_opened[this->_depth - 1].bindings++;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи текстового содержимого
 *
 * @param text записываемое текстовое содержимое
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::text(const string_view text) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если содержимое записывается вне корневого узла
	 */
	if(this->_depth == 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::CONTENT_OUTSIDE_ROOT;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем завершение незакрытой метки узла
	this->flush();
	// Запоминаем, что узел содержит вложенное содержимое
	this->_opened[this->_depth - 1].filled = true;
	// Выводим результат записи текстового содержимого
	return this->escape(text, false);
}
/**
 * @brief Метод записи раздела дословного текста
 *
 * @param text записываемое дословное содержимое
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::cdata(const string_view text) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если содержимое записывается вне корневого узла
	 */
	if(this->_depth == 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::CONTENT_OUTSIDE_ROOT;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если содержимое содержит последовательность конца дословного раздела
	 *
	 * @note Разрезать такое содержимое на несколько разделов запись не станет:
	 *       вызывающий записывает не то, что имел в виду, и знать об этом обязан
	 */
	if(text.find("]]>") != string_view::npos){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_CDATA;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если содержимое раздела построено ошибочно
	 */
	if(!this->verify(text))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем завершение незакрытой метки узла
	this->flush();
	// Запоминаем, что узел содержит вложенное содержимое
	this->_opened[this->_depth - 1].filled = true;
	// Выполняем добавление раздела дословного текста
	this->_text.append("<![CDATA[").append(text).append("]]>");
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи примечания
 *
 * @param text содержимое примечания
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::comment(const string_view text) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если содержимое примечания построено ошибочно
	 */
	if((text.find("--") != string_view::npos) || (!text.empty() && (text.back() == '-'))){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_COMMENT;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если содержимое примечания построено ошибочно
	 */
	if(!this->verify(text))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем завершение незакрытой метки узла
	this->flush();
	/**
	 * Если примечание записывается внутри узла
	 */
	if(this->_depth > 0){
		// Запоминаем, что узел содержит вложенное содержимое
		this->_opened[this->_depth - 1].filled = true;
		// Запоминаем, что узел содержит вложенные узлы разметки
		this->_opened[this->_depth - 1].elements = true;
	}
	/**
	 * Если объемлющий узел записывается в одну строку
	 *
	 * @note Отступ внутри такого узла переменил бы его содержимое: пробельные знаки
	 *       там значимы наравне с прочими
	 */
	if((this->_depth == 0) || !this->_opened[this->_depth - 1].oneline)
		// Выполняем запись отступа перед примечанием
		this->indent();
	// Выполняем добавление примечания
	this->_text.append("<!--").append(text).append("-->");
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи указания обработчику
 *
 * @param target цель указания обработчику
 * @param text   данные указания обработчику
 * @return       результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::processing(const string_view target, const string_view text) noexcept {
	/**
	 * Если запись уже прекращена ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если цель указания обработчику построена ошибочно
	 *
	 * @details Цель проверяется правилом дословного имени, где разделитель префикса
	 *          обычным знаком имени и является: договор о пространствах имён на цели
	 *          указаний обработчику не распространяется, делить её не на что и префикс
	 *          ей не назначается. Проверка правилом местного имени отвергала бы цель с
	 *          разделителем, а разбор с выключенным разрешением префиксов такую цель
	 *          принимает - разобранное дерево обратно бы не записывалось
	 */
	if(!::plain(target)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_PROCESSING;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если целью указания обработчику является отведённое договором имя
	 */
	if((target.length() == 3) && ((target[0] | 0x20) == 'x') && ((target[1] | 0x20) == 'm') && ((target[2] | 0x20) == 'l')){
		// Запоминаем код ошибки записи
		this->_error = error_t::RESERVED_PROCESSING;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если данные указания обработчику содержат его завершение
	 */
	if(text.find("?>") != string_view::npos){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_PROCESSING;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если данные указания обработчику построены ошибочно
	 */
	if(!this->verify(text))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем завершение незакрытой метки узла
	this->flush();
	/**
	 * Если указание обработчику записывается внутри узла
	 */
	if(this->_depth > 0){
		// Запоминаем, что узел содержит вложенное содержимое
		this->_opened[this->_depth - 1].filled = true;
		// Запоминаем, что узел содержит вложенные узлы разметки
		this->_opened[this->_depth - 1].elements = true;
	}
	/**
	 * Если объемлющий узел записывается в одну строку
	 *
	 * @note Отступ внутри такого узла переменил бы его содержимое: пробельные знаки
	 *       там значимы наравне с прочими
	 */
	if((this->_depth == 0) || !this->_opened[this->_depth - 1].oneline)
		// Выполняем запись отступа перед указанием обработчику
		this->indent();
	// Выполняем добавление начала указания обработчику
	this->_text.append("<?").append(target);
	/**
	 * Если данные указания обработчику не пусты
	 */
	if(!text.empty())
		// Выполняем добавление данных указания обработчику
		this->_text.push_back(' '), this->_text.append(text);
	// Выполняем добавление конца указания обработчику
	this->_text.append("?>");
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи узла с текстовым содержимым
 *
 * @param local местное имя записываемого узла
 * @param value текстовое содержимое записываемого узла
 * @param uri   обозначение пространства имён записываемого узла
 * @return      результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::element(const string_view local, const string_view value, const string_view uri) noexcept {
	/**
	 * Если открыть записываемый узел не удалось
	 */
	if(!this->open(local, uri))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если содержимое записываемого узла не пусто
	 */
	if(!value.empty()){
		/**
		 * Если записать содержимое узла не удалось
		 */
		if(!this->text(value))
			// Выводим отрицательный результат выполнения операции
			return false;
	}
	// Выводим результат закрытия записываемого узла
	return this->close();
}
/**
 * @brief Метод записи дерева разметки
 *
 * @param node записываемый узел дерева разметки вместе с вложенными
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::element(const node_t & node) noexcept {
	// Признак сохранения пробельного содержимого, унаследованный от объемлющих узлов
	bool preserve = false;
	/**
	 * Выполняем перебор всех объемлющих узлов записываемого узла
	 *
	 * @details Записывать можно всякий узел дерева, а не только корень, и обращение с
	 * пробельным содержимым задаётся у него зачастую выше по дереву: узел, лежащий под
	 * `xml:space="preserve"` предка, своего атрибута не несёт вовсе. Принимая такой
	 * узел за обычный, запись расставила бы внутри него отступы - то есть переменила
	 * бы значимое содержимое. Обход вверх ведётся до первого узла, обращение задавшего
	 *
	 * @note Обход недорог: он делается единожды на всю запись дерева, а не на узел
	 */
	for(node_t parent = node.parent(); parent.valid(); parent = parent.parent()){
		// Если объемлющий узел узлом разметки не является, обращения он не задаёт
		if(parent.kind() != kind_t::ELEMENT) continue;
		/**
		 * Получаем заданное объемлющим узлом обращение с пробельным содержимым
		 *
		 * @note Атрибут отыскивается обоими написаниями: с выключенным разрешением
		 *       префиксов имя его в дереве не разделено и пространства имён не имеет
		 */
		const string_view spacing = (!parent.attribute("space", XML_NAMESPACE).empty() ?
			parent.attribute("space", XML_NAMESPACE) : parent.attribute("xml:space"));
		// Если обращения объемлющий узел не задаёт, поднимаемся выше по дереву
		if(spacing.empty()) continue;
		// Запоминаем обращение с пробельным содержимым, заданное объемлющим узлом
		preserve = (spacing.compare("preserve") == 0);
		// Выходим из перебора объемлющих узлов
		break;
	}
	// Выводим результат записи узла дерева с унаследованным обращением с пробелами
	return this->element(node, preserve);
}
/**
 * @brief Метод записи узла дерева разметки с наследуемым обращением с пробелами
 *
 * @param node     записываемый узел дерева разметки
 * @param preserve признак сохранения пробельного содержимого, унаследованный от
 *                 объемлющих узлов
 * @return         результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::element(const node_t & node, const bool preserve) noexcept {
	/**
	 * Если записываемый узел непригоден
	 */
	if(!node.valid()){
		// Запоминаем код ошибки записи
		this->_error = error_t::INTERNAL;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * @brief Кадр обхода дерева разметки
	 *
	 * @details Обход ведётся собственным стеком, а не рекурсией: глубина дерева
	 * задаётся тем, кто его построил, и рекурсия упирала бы запись в стек задачи -
	 * дерево, разобранное с поднятым пределом глубины, обратно бы не записывалось
	 *
	 */
	struct Frame {
		// Вложенный узел, подлежащий записи следующим
		node_t child;
		// Признак сохранения пробельного содержимого внутри узла
		bool keeping;
		// Признак записи содержимого узла в одну строку
		bool oneline;
		// Признак того, что узел несёт вложенные узлы, отступа требующие
		bool nested;
		// Признак того, что узел подлежит закрытию по исчерпании вложенных
		bool closing;
	};
	// Стек обхода дерева разметки
	vector <Frame> stack;
	// Узел, подлежащий записи на этом заходе
	node_t current = node;
	// Признак сохранения пробельного содержимого, унаследованный узлом
	bool inherited = preserve;
	/**
	 * Выполняем обход дерева разметки до исчерпания стека
	 */
	while(true){
		/**
		 * Если записывать на этом заходе нечего
		 */
		if(!current.valid()){
			// Если стек обхода исчерпан, обход завершён
			if(stack.empty()) break;
			// Получаем кадр обхода, лежащий на вершине стека
			Frame & top = stack.back();
			// Вложенный узел, подлежащий записи следующим
			node_t next = top.child;
			/**
			 * Выполняем пропуск вложенных узлов, записи не подлежащих
			 *
			 * @details Нарядная запись расставляет отступы сама, а прошлые её отступы
			 * дерево принимает пробельным содержимым: переписанные наравне с прочим, они
			 * складывались бы с новыми, и разметка росла бы пустыми строками с каждым
			 * переходом текст→дерево→текст. Пробельное содержимое потому пропускается
			 * там, где отступ его и породил, - между вложенными узлами узла, своего
			 * текста не несущего
			 *
			 * @note Узлы, где пробельные знаки значимы, сюда не попадают: смешанное
			 * содержимое и сохранение пробелов записываются в одну строку, и отступов
			 * там не появляется вовсе
			 */
			while(next.valid() && !top.oneline && top.nested && (this->_settings.format == format_t::PRETTY)){
				// Признак того, что вложенный узел является пробельным содержимым
				bool blank = false;
				/**
				 * Определяем вид вложенного узла дерева
				 */
				switch(static_cast <uint8_t> (next.kind())){
					// Если вложенный узел является текстовым либо пробельным содержимым
					case static_cast <uint8_t> (kind_t::TEXT):
					case static_cast <uint8_t> (kind_t::SPACE):
						// Запоминаем, что вложенный узел является пробельным содержимым
						blank = true;
					break;
				}
				// Если вложенный узел пробельным содержимым не является, пропускать нечего
				if(!blank) break;
				// Выполняем переход к следующему вложенному узлу
				next = next.next();
			}
			/**
			 * Если вложенные узлы исчерпаны
			 */
			if(!next.valid()){
				// Запоминаем, подлежит ли узел кадра закрытию
				const bool closing = top.closing;
				// Выполняем снятие исчерпанного кадра со стека обхода
				stack.pop_back();
				// Если закрыть узел разметки не удалось
				if(closing && !this->close())
					// Выводим отрицательный результат выполнения операции
					return false;
				// Выполняем переход к следующему заходу обхода
				continue;
			}
			// Запоминаем вложенный узел, подлежащий записи после текущего
			top.child = next.next();
			// Запоминаем сохранение пробельного содержимого, наследуемое вложенным узлом
			inherited = top.keeping;
			// Запоминаем вложенный узел, подлежащий записи на этом заходе
			current = next;
		}
		/**
		 * Определяем вид записываемого узла дерева
		 */
		switch(static_cast <uint8_t> (current.kind())){
			/**
			 * Если записывается корень дерева разметки
			 */
			case static_cast <uint8_t> (kind_t::DOCUMENT): {
				// Собираемый кадр обхода узлов верхнего уровня
				Frame frame;
				// Запоминаем первый узел верхнего уровня
				frame.child = current.first();
				// Запоминаем сохранение пробельного содержимого, унаследованное корнем
				frame.keeping = inherited;
				// Запоминаем, что узлы верхнего уровня в одну строку не сводятся
				frame.oneline = false;
				// Запоминаем, что пропуск пробельного содержимого корню не положен
				frame.nested = false;
				// Запоминаем, что закрывать корень дерева разметки не требуется
				frame.closing = false;
				// Выполняем размещение собранного кадра на стеке обхода
				stack.push_back(frame);
			} break;
			/**
			 * Если записывается узел разметки
			 */
			case static_cast <uint8_t> (kind_t::ELEMENT): {
				/**
				 * Получаем объявления пространств имён, записанные узлу
				 *
				 * @note Объявления применяются при открытии узла, а не после: имя узла
				 *       записывается первым, и префикс ему требуется прежде, чем объявления
				 *       попадут в текст
				 */
				const vector <binding_t> declares = current.bindings();
				// Получаем префикс, каким имя узла записано в исходном тексте
				const string_view preferred = current.name().prefix;
				/**
				 * Определяем, записываются ли имена узла дословно
				 *
				 * @details Разбор без пространств имён кладёт имя в дерево целиком, вместе с
				 *          разделителем префикса, а обозначения пространства имён не даёт вовсе.
				 *          Подбирать префикс такому имени не по чему и незачем: пространств имён
				 *          в таком дереве нет, и запись выводит имя как есть
				 *
				 * @note Признаком служит сам разделитель в имени: разбор с пространствами имён
				 *       имя делит и разделителя в местном имени не оставляет
				 */
				const bool verbatim = (current.name().uri.empty() && (current.name().local.find(':') != string_view::npos));
				// Признак сохранения пробельного содержимого, заданный либо унаследованный
				bool keeping = inherited;
				// Признак того, что узел несёт непробельное содержимое
				bool wordy = false;
				// Признак того, что узел несёт вложенные узлы, отступа требующие
				bool nested = false;
				/**
				 * Если запись ведётся нарядным видом
				 *
				 * @note Расчёт нужен одной лишь нарядной записи: сжатая запись отступов не
				 *       ставит вовсе, и содержимое узла ей менять нечем
				 */
				if(this->_settings.format == format_t::PRETTY){
					/**
					 * Получаем заданное узлом обращение с пробельным содержимым
					 *
					 * @details Атрибут отведён самим договором о разметке, и с выключенным
					 * разрешением префиксов имя его в дереве не разделено: пространства имён у
					 * него нет вовсе, а записан он целиком. Искать его следует обоими
					 * написаниями, иначе запись теряет значимое содержимое там, где разбор вёлся
					 * без пространств имён
					 */
					const string_view spacing = (!current.attribute("space", XML_NAMESPACE).empty() ?
						current.attribute("space", XML_NAMESPACE) : current.attribute("xml:space"));
					/**
					 * Определяем, требуется ли сохранять пробельное содержимое узла
					 *
					 * @note Признак наследуется вложенными узлами: договор велит держать
					 *       установленное обращение с пробелами до его отмены изнутри
					 *
					 * @note Значение, договором не отведённое, толкуется отменой наравне с
					 *       `default` - тем же самым образом, каким его толкует чтение
					 */
					keeping = (spacing.empty() ? inherited : (spacing.compare("preserve") == 0));
					/**
					 * Выполняем перебор всех вложенных узлов записываемого узла
					 */
					for(node_t child = current.first(); child.valid(); child = child.next()){
						/**
						 * Определяем вид вложенного узла дерева
						 */
						switch(static_cast <uint8_t> (child.kind())){
							/**
							 * Если вложенный узел является разделом дословного текста
							 *
							 * @note Раздел дословного текста значим сам по себе, каким бы ни было
							 *       его содержимое: он ставится там, где знаки берутся дословно, и
							 *       отступ рядом с ним переменил бы содержимое объемлющего узла
							 */
							case static_cast <uint8_t> (kind_t::CDATA):
								// Запоминаем, что узел несёт значимое содержимое
								wordy = true;
							break;
							// Если вложенный узел является содержимым
							case static_cast <uint8_t> (kind_t::TEXT):
							case static_cast <uint8_t> (kind_t::SPACE): {
								// Получаем содержимое вложенного узла
								const string content = child.text();
								/**
								 * Выполняем перебор всех знаков содержимого вложенного узла
								 */
								for(const char letter : content){
									/**
									 * Если обнаружен знак, не являющийся пробельным
									 */
									if(!isSpace(static_cast <uint32_t> (static_cast <uint8_t> (letter)))){
										// Запоминаем, что узел несёт непробельное содержимое
										wordy = true;
										// Выходим из перебора знаков содержимого
										break;
									}
								}
							} break;
							// Если вложенный узел является узлом разметки, примечанием либо указанием
							case static_cast <uint8_t> (kind_t::ELEMENT):
							case static_cast <uint8_t> (kind_t::COMMENT):
							case static_cast <uint8_t> (kind_t::PROCESSING):
								// Запоминаем, что узел несёт вложенные узлы
								nested = true;
							break;
						}
					}
				}
				/**
				 * Определяем, записывается ли содержимое узла в одну строку
				 *
				 * @details Отступ ставится ради удобства чтения и содержимого менять не
				 * вправе, а внутри узла со смешанным содержимым - несущего разом и текст, и
				 * вложенные узлы - пробельные знаки содержимым и являются: перевод строки
				 * перед вложенным узлом попадает в текст соседа. Того же требует и узел,
				 * которому договором предписано сохранять пробельное содержимое
				 *
				 * @note Узел, вложенных узлов не несущий, отступов не получает и так: внутри
				 * него отступать нечего
				 */
				const bool oneline = (keeping || (wordy && nested));
				// Если открыть записываемый узел с его объявлениями и префиксом не удалось
				if(!this->open(current.name().local, current.name().uri, (declares.empty() ? nullptr : &declares), &preferred, verbatim, oneline))
					// Выводим отрицательный результат выполнения операции
					return false;
				/**
				 * Выполняем перебор всех атрибутов записываемого узла
				 */
				for(const attribute_t & attribute : current.attributes()){
					/**
					 * Если записать очередной атрибут не удалось
					 */
					if(!this->attribute(
						attribute.name.local, attribute.value, attribute.name.uri,
						(attribute.name.uri.empty() && ((attribute.name.local.find(':') != string_view::npos) || (attribute.name.local.compare("xmlns") == 0)))
					))
						// Выводим отрицательный результат выполнения операции
						return false;
				}
				// Собираемый кадр обхода вложенных узлов
				Frame frame;
				// Запоминаем первый вложенный узел
				frame.child = current.first();
				// Запоминаем сохранение пробельного содержимого, наследуемое вложенными
				frame.keeping = keeping;
				// Запоминаем, записывается ли содержимое узла в одну строку
				frame.oneline = oneline;
				// Запоминаем, несёт ли узел вложенные узлы, отступа требующие
				frame.nested = nested;
				// Запоминаем, что узел подлежит закрытию по исчерпании вложенных
				frame.closing = true;
				// Выполняем размещение собранного кадра на стеке обхода
				stack.push_back(frame);
			} break;
			// Если записывается текстовое содержимое
			case static_cast <uint8_t> (kind_t::TEXT):
			/**
			 * Если записывается незначимое пробельное содержимое
			 *
			 * @note Пробельное содержимое записывается наравне с текстовым: отделено оно
			 *       лишь для того, кто его различает, а из записи выпадать не вправе
			 */
			case static_cast <uint8_t> (kind_t::SPACE): {
				// Если записать содержимое не удалось, выводим отрицательный результат
				if(!this->text(current.text())) return false;
			} break;
			// Если записывается раздел дословного текста
			case static_cast <uint8_t> (kind_t::CDATA): {
				// Если записать раздел дословного текста не удалось
				if(!this->cdata(current.text())) return false;
			} break;
			// Если записывается примечание
			case static_cast <uint8_t> (kind_t::COMMENT): {
				// Если записать примечание не удалось, выводим отрицательный результат
				if(!this->comment(current.text())) return false;
			} break;
			// Если записывается указание обработчику
			case static_cast <uint8_t> (kind_t::PROCESSING): {
				// Если записать указание обработчику не удалось
				if(!this->processing(current.name().local, current.text())) return false;
			} break;
		}
		// Выполняем сброс узла, записанного на этом заходе
		current = node_t();
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод получения кода ошибки записи
 *
 * @return код ошибки последней операции записи
 *
 */
awh::codec::xml::error_t awh::codec::xml::Writer::error() const noexcept {
	// Выводим код ошибки последней операции записи
	return this->_error;
}
/**
 * @brief Метод проверки завершённости собранного текста
 *
 * @return результат проверки
 *
 */
bool awh::codec::xml::Writer::complete() const noexcept {
	// Выводим результат проверки завершённости собранного текста
	return ((this->_depth == 0) && this->_root && (this->_error == error_t::NONE));
}
/**
 * @brief Метод получения собранного текста разметки
 *
 * @return собранный текст разметки в кодировке UTF-8
 *
 */
const string & awh::codec::xml::Writer::text() const noexcept {
	/**
	 * Если запись прекращена ошибкой
	 *
	 * @details Ошибка записи терминальна: всякое действие после неё отвечает отказом, а
	 *          собранное к этому мигу оборвано посреди метки узла. Выдать такое значило
	 *          бы выдать заведомо негодную разметку тому, кто отказа не спросил, - и
	 *          негодность её обнаружилась бы уже у принимающей стороны
	 *
	 * @note Собранное при этом не стирается: оно остаётся на месте и доступно отладке
	 *       через сам объект, а наружу отдаётся пустой текст
	 */
	if(this->_error != error_t::NONE){
		// Пустой текст разметки, выдаваемый по прекращённой записи
		static const string result;
		// Выводим пустой текст разметки
		return result;
	}
	// Выводим собранный текст разметки
	return this->_text;
}
/**
 * @brief Метод отведения места под собираемый текст разметки
 *
 * @param size ожидаемый размер собираемого текста разметки в байтах
 *
 */
void awh::codec::xml::Writer::reserve(const size_t size) noexcept {
	// Выполняем отведение места под собираемый текст разметки
	this->_text.reserve(size);
}
/**
 * @brief Метод очистки собранного текста разметки
 *
 */
void awh::codec::xml::Writer::clear() noexcept {
	// Выполняем сброс кода ошибки записи
	this->_error = error_t::NONE;
	// Выполняем сброс признака записанного корневого узла
	this->_root = false;
	// Выполняем очистку собранного текста разметки
	this->_text.clear();
	/**
	 * Выполняем очистку стека открытых узлов разметки
	 *
	 * @note Хранилище записей при этом сберегается: очистка сбрасывает лишь
	 *       глубину, и переиспользованный объект записи заводит их заново не с
	 *       пустого места
	 */
	this->_depth = 0;
	// Выполняем очистку действующих связываний префиксов
	this->_bindings = 0;
	// Выполняем сброс счётчика назначенных префиксов
	this->_counter = 0;
}
/**
 * @brief Конструктор
 *
 */
awh::codec::xml::Writer::Writer() noexcept : _error(error_t::NONE), _root(false), _depth(0), _bindings(0), _counter(0) {}
/**
 * @brief Конструктор
 *
 * @param settings настройки записи текста разметки
 *
 */
awh::codec::xml::Writer::Writer(const settings_t & settings) noexcept :
 _settings(settings), _error(error_t::NONE), _root(false), _depth(0), _bindings(0), _counter(0) {}
/**
 * @brief Деструктор
 *
 */
awh::codec::xml::Writer::~Writer() noexcept {
	// Выполняем очистку собранного текста разметки
	this->clear();
}
