/**
 * Подключаем заголовочные файлы проекта
 */
#include <codec/xml/writer.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Пространство имён контейнера XML
	 */
	using namespace awh::codec::xml;

	/**
	 * @brief Метод проверки имени на правильность построения
	 *
	 * @details Записать имя, которое не удастся прочесть обратно, нельзя: такое
	 *          указание отвергается, а не записывается с надеждой на снисходительность
	 *          читающего
	 *
	 * @param name проверяемое имя без префикса
	 * @return     результат проверки
	 *
	 */
	static bool correct(const string_view name) noexcept {
		/**
		 * Если имя пусто
		 */
		if(name.empty())
			// Выводим отрицательный результат проверки
			return false;
		/**
		 * Выполняем перебор всех знаков имени
		 */
		for(size_t i = 0; i < name.length();){
			// Длина прочитанной последовательности знака
			size_t length = 0;
			// Выполняем чтение кодового значения очередного знака
			const uint32_t code = decode(name.data() + i, name.length() - i, length);
			/**
			 * Если знак прочитать не удалось
			 */
			if((length == 0) || (code == INVALID_CODEPOINT))
				// Выводим отрицательный результат проверки
				return false;
			/**
			 * Если знак недопустим в имени
			 */
			if((i == 0) ? !isNameStart(code) : !isName(code))
				// Выводим отрицательный результат проверки
				return false;
			/**
			 * Если знак является разделителем префикса
			 *
			 * @note Префикс назначается записью по обозначению пространства имён, а
			 *       не задаётся вызывающим: разделитель в местном имени недопустим
			 */
			if(code == ':')
				// Выводим отрицательный результат проверки
				return false;
			// Выполняем переход к следующему знаку имени
			i += length;
		}
		// Выводим положительный результат проверки
		return true;
	}
	/**
	 * @brief Метод проверки имени, записываемого дословно
	 *
	 * @details Разбор без пространств имён кладёт имя в дерево целиком, вместе с
	 * разделителем префикса: пространств имён там нет вовсе, и делить имя не на что.
	 * Такое имя записью дословно и воспроизводится, а проверяется оно правилом
	 * договора разметки, где разделитель обычным знаком имени и является
	 *
	 * @param name проверяемое имя
	 * @return     результат проверки
	 *
	 */
	static bool plain(const string_view name) noexcept {
		/**
		 * Если имя пусто
		 */
		if(name.empty())
			// Выводим отрицательный результат проверки
			return false;
		/**
		 * Выполняем перебор всех знаков имени
		 */
		for(size_t i = 0; i < name.length();){
			// Длина прочитанной последовательности знака
			size_t length = 0;
			// Выполняем чтение кодового значения очередного знака
			const uint32_t code = decode(name.data() + i, name.length() - i, length);
			/**
			 * Если знак прочитать не удалось
			 */
			if((length == 0) || (code == INVALID_CODEPOINT))
				// Выводим отрицательный результат проверки
				return false;
			/**
			 * Если знак недопустим в имени
			 */
			if((i == 0) ? !isNameStart(code) : !isName(code))
				// Выводим отрицательный результат проверки
				return false;
			// Выполняем переход к следующему знаку имени
			i += length;
		}
		// Выводим положительный результат проверки
		return true;
	}
};

/**
 * @brief Конструктор
 *
 */
awh::codec::xml::Writer::Settings::Settings() noexcept :
 format(format_t::COMPACT), collapse(true), escapeNonAscii(false), indent(2), space(' ') {}
/**
 * @brief Метод завершения незакрытой метки узла
 *
 */
void awh::codec::xml::Writer::flush() noexcept {
	/**
	 * Если метка узла не завершена
	 */
	if((this->_depth > 0) && this->_opened[this->_depth - 1].pending){
		// Выполняем завершение метки узла
		this->_text.push_back('>');
		// Запоминаем, что метка узла завершена
		this->_opened[this->_depth - 1].pending = false;
	}
}
/**
 * @brief Метод записи отступа перед содержимым
 *
 */
void awh::codec::xml::Writer::indent() noexcept {
	/**
	 * Если отступы настройками не расставляются
	 */
	if(this->_settings.format != format_t::PRETTY)
		// Выходим из записи отступа
		return;
	/**
	 * Если записанный текст пуст
	 */
	if(this->_text.empty())
		// Выходим из записи отступа
		return;
	// Выполняем добавление перевода строки
	this->_text.push_back('\n');
	// Выполняем добавление отступа записываемого уровня
	this->_text.append(this->_depth * this->_settings.indent, this->_settings.space);
}
/**
 * @brief Метод проверки последовательности знаков на пригодность к записи
 *
 * @details Проверяются и построение записи UTF-8, и допустимость самих знаков в
 * разметке: последовательность попадает в текст как есть, экранированию не подлежит,
 * и негодный знак прочёлся бы обратно уже негодной разметкой
 *
 * @note Применяется там, где экранирование договором запрещено - в примечании, в
 * дословном разделе и в указании обработчику
 *
 * @param text проверяемая последовательность знаков
 * @return     результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::verify(const string_view text) noexcept {
	/**
	 * Выполняем перебор всех знаков проверяемой последовательности
	 */
	for(size_t i = 0; i < text.length();){
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение кодового значения очередного знака
		const uint32_t code = decode(text.data() + i, text.length() - i, length);
		/**
		 * Если знак прочитать не удалось
		 */
		if((length == 0) || (code == INVALID_CODEPOINT)){
			// Запоминаем код ошибки записи
			this->_error = error_t::INVALID_ENCODING;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если знак недопустим в разметке
		 */
		if(!isChar(code)){
			// Запоминаем код ошибки записи
			this->_error = error_t::INVALID_CHARACTER;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		// Выполняем переход к следующему знаку последовательности
		i += length;
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи последовательности знаков с экранированием
 *
 * @param text      записываемая последовательность знаков
 * @param attribute признак записи значения атрибута
 * @return          результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::escape(const string_view text, const bool attribute) noexcept {
	/**
	 * Выполняем перебор всех знаков записываемой последовательности
	 */
	for(size_t i = 0; i < text.length();){
		// Длина прочитанной последовательности знака
		size_t length = 0;
		// Выполняем чтение кодового значения очередного знака
		const uint32_t code = decode(text.data() + i, text.length() - i, length);
		/**
		 * Если знак прочитать не удалось
		 */
		if((length == 0) || (code == INVALID_CODEPOINT)){
			// Запоминаем код ошибки записи
			this->_error = error_t::INVALID_ENCODING;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Если знак недопустим в разметке
		 */
		if(!isChar(code)){
			// Запоминаем код ошибки записи
			this->_error = error_t::INVALID_CHARACTER;
			// Выводим отрицательный результат выполнения операции
			return false;
		}
		/**
		 * Определяем очередной знак записываемой последовательности
		 */
		switch(code){
			// Если обнаружен знак амперсанда
			case '&': this->_text.append("&amp;"); break;
			// Если обнаружен знак левой угловой скобки
			case '<': this->_text.append("&lt;"); break;
			/**
			 * Если обнаружен знак правой угловой скобки
			 *
			 * @note Знак экранируется и там, где договор того не требует: иначе
			 *       последовательность конца дословного раздела, записанная текстом,
			 *       прочтётся обратно уже разметкой
			 */
			case '>': this->_text.append("&gt;"); break;
			/**
			 * Если обнаружен возврат каретки
			 *
			 * @note Возврат каретки приводится чтением к переводу строки, и записать
			 *       его дословно можно лишь числовой ссылкой
			 */
			case '\r': this->_text.append("&#13;"); break;
			// Если обнаружен прочий знак
			default: {
				/**
				 * Если записывается значение атрибута
				 */
				if(attribute){
					/**
					 * Определяем очередной знак значения атрибута
					 */
					switch(code){
						// Если обнаружен знак двойной кавычки
						case '"': this->_text.append("&quot;"); break;
						// Если обнаружен перевод строки
						case '\n': this->_text.append("&#10;"); break;
						// Если обнаружена горизонтальная табуляция
						case '\t': this->_text.append("&#9;"); break;
						// Если обнаружен прочий знак
						default: {
							/**
							 * Если знак выходит за пределы US-ASCII и подлежит экранированию
							 */
							if(this->_settings.escapeNonAscii && (code >= 0x80)){
								// Выполняем добавление начала числовой ссылки
								this->_text.append("&#x");
								// Выполняем добавление кодового значения знака
								for(int8_t shift = 20; shift >= 0; shift -= 4){
									// Получаем очередной разряд кодового значения
									const uint32_t digit = ((code >> shift) & 0x0F);
									/**
									 * Если разряд значащим не является
									 */
									if((digit == 0) && (this->_text.back() == 'x') && (shift > 0))
										// Выполняем переход к следующему разряду
										continue;
									// Выполняем добавление разряда кодового значения
									this->_text.push_back(static_cast <char> (digit < 10 ? ('0' + digit) : ('A' + (digit - 10))));
								}
								// Выполняем добавление конца числовой ссылки
								this->_text.push_back(';');
							// Выполняем добавление знака без экранирования
							} else this->_text.append(text.substr(i, length));
						}
					}
				/**
				 * Если знак выходит за пределы US-ASCII и подлежит экранированию
				 */
				} else if(this->_settings.escapeNonAscii && (code >= 0x80)) {
					// Выполняем добавление начала числовой ссылки
					this->_text.append("&#x");
					// Выполняем добавление кодового значения знака
					for(int8_t shift = 20; shift >= 0; shift -= 4){
						// Получаем очередной разряд кодового значения
						const uint32_t digit = ((code >> shift) & 0x0F);
						/**
						 * Если разряд значащим не является
						 */
						if((digit == 0) && (this->_text.back() == 'x') && (shift > 0))
							// Выполняем переход к следующему разряду
							continue;
						// Выполняем добавление разряда кодового значения
						this->_text.push_back(static_cast <char> (digit < 10 ? ('0' + digit) : ('A' + (digit - 10))));
					}
					// Выполняем добавление конца числовой ссылки
					this->_text.push_back(';');
				// Выполняем добавление знака без экранирования
				} else this->_text.append(text.substr(i, length));
			}
		}
		// Выполняем переход к следующему знаку
		i += length;
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод получения префикса для пространства имён
 *
 * @param uri       обозначение пространства имён
 * @param attribute признак поиска префикса для имени атрибута
 * @param result    найденный либо назначенный префикс
 * @return          результат выполнения операции
 *
 */
bool awh::codec::xml::Writer::prefix(const string_view uri, const bool attribute, string & result) noexcept {
	// Выполняем очистку найденного префикса
	result.clear();
	/**
	 * Если обозначение пространства имён не задано
	 */
	if(uri.empty()){
		/**
		 * Выполняем перебор действующих связываний от ближайшего узла к корню
		 */
		for(size_t i = this->_bindings; i > 0; i--){
			/**
			 * Если обнаружено объявление пространства имён по умолчанию
			 */
			if(this->_scopes[i - 1].prefix.empty()){
				/**
				 * Если объявленное по умолчанию пространство имён не пусто
				 *
				 * @note Имя без префикса попало бы в объявленное по умолчанию
				 *       пространство имён, а записать требуется имя без него: объявление
				 *       по умолчанию отменяется при записываемом узле
				 */
				if(!this->_scopes[i - 1].uri.empty() && !attribute){
					/**
					 * Если имя объявления узлу уже записано
					 */
					if(!this->occupy("xmlns"))
						// Выводим отрицательный результат выполнения операции
						return false;
					// Выполняем добавление отмены объявления по умолчанию
					this->_text.append(" xmlns=\"\"");
					// Выполняем отведение места под связывание
					if(this->_bindings >= this->_scopes.size())
						// Выполняем добавление места под новое связывание
						this->_scopes.emplace_back();
					// Получаем связывание, отведённое под объявление
					scope_t & scope = this->_scopes[this->_bindings++];
					// Выполняем очистку назначенного прежде префикса
					scope.prefix.clear();
					// Выполняем очистку обозначения связанного пространства имён
					scope.uri.clear();
					// Выполняем подсчёт связываний, объявленных узлом
					this->_opened[this->_depth - 1].bindings++;
				}
				// Выходим из перебора связываний
				break;
			}
		}
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Выполняем перебор действующих связываний от ближайшего узла к корню
	 */
	for(size_t i = this->_bindings; i > 0; i--){
		// Получаем очередное связывание префикса
		const scope_t & scope = this->_scopes[i - 1];
		/**
		 * Если обозначение связывания совпадает с искомым
		 */
		if(scope.uri.compare(uri) == 0){
			/**
			 * Если связывание объявлено по умолчанию, а префикс нужен имени атрибута
			 *
			 * @note Объявление по умолчанию на атрибуты не распространяется: атрибуту
			 *       требуется именно префикс
			 */
			if(scope.prefix.empty() && attribute)
				// Выполняем переход к следующему связыванию
				continue;
			// Признак того, что префикс связывания перекрыт более близким объявлением
			bool shadowed = false;
			/**
			 * Выполняем перебор всех связываний, объявленных ближе к записываемому узлу
			 *
			 * @note Тот же префикс мог быть перевязан на иное пространство имён вложенным
			 *       узлом: выдать его здесь означало бы записать имя в чужом пространстве
			 */
			for(size_t j = this->_bindings; j > i; j--){
				/**
				 * Если префикс перевязан более близким объявлением
				 */
				if(this->_scopes[j - 1].prefix == scope.prefix){
					// Запоминаем, что префикс связывания перекрыт
					shadowed = true;
					// Выходим из перебора связываний
					break;
				}
			}
			/**
			 * Если префикс связывания перекрыт
			 */
			if(shadowed)
				// Выполняем переход к следующему связыванию
				continue;
			// Запоминаем найденный префикс
			result.assign(scope.prefix);
			// Выводим положительный результат выполнения операции
			return true;
		}
	}
	/**
	 * Если обозначение отведено договором префиксу «xml»
	 */
	if(uri.compare(XML_NAMESPACE) == 0){
		// Запоминаем отведённый договором префикс
		result.assign("xml");
		// Выводим положительный результат выполнения операции
		return true;
	}
	/**
	 * Если обозначение отведено договором объявлениям пространств имён
	 */
	if(uri.compare(XMLNS_NAMESPACE) == 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_NAMESPACE;
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Назначаем префикс самостоятельно
	 *
	 * @note Назначенный префикс сличается с уже действующими: назначить занятый
	 *       означало бы перевязать его на иное пространство имён, отчего все ранее
	 *       записанные с ним имена сменили бы пространство имён при обратном чтении
	 */
	for(;;){
		// Собираем очередной назначаемый префикс
		result.assign("n").append(to_string(++this->_counter));
		// Признак того, что назначаемый префикс уже занят
		bool taken = false;
		/**
		 * Выполняем перебор всех действующих связываний
		 */
		for(size_t i = 0; i < this->_bindings; i++){
			// Получаем очередное действующее связывание
			const scope_t & scope = this->_scopes[i];
			/**
			 * Если назначаемый префикс уже занят
			 */
			if(scope.prefix == result){
				// Запоминаем, что назначаемый префикс уже занят
				taken = true;
				// Выходим из перебора связываний
				break;
			}
		}
		/**
		 * Если назначаемый префикс свободен
		 */
		if(!taken)
			// Выходим из подбора префикса
			break;
	}
	/**
	 * Если имя объявления узлу уже записано
	 */
	if(!this->occupy(string("xmlns:").append(result)))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление объявления пространства имён
	this->_text.append(" xmlns:").append(result).append("=\"");
	/**
	 * Если записать обозначение пространства имён не удалось
	 */
	if(!this->escape(uri, true))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем добавление конца объявления пространства имён
	this->_text.push_back('"');
	// Выполняем отведение места под связывание
	if(this->_bindings >= this->_scopes.size())
		// Выполняем добавление места под новое связывание
		this->_scopes.emplace_back();
	// Получаем связывание, отведённое под объявление
	scope_t & scope = this->_scopes[this->_bindings++];
	// Запоминаем назначенный префикс
	scope.prefix.assign(result);
	// Запоминаем обозначение связанного пространства имён
	scope.uri.assign(uri);
	// Выполняем подсчёт связываний, объявленных узлом
	this->_opened[this->_depth - 1].bindings++;
	// Выводим положительный результат выполнения операции
	return true;
}
