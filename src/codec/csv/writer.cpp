/**
 * @brief Метод завершения текущей записи
 *
 */
void awh::codec::csv::Writer::record() noexcept {
	/**
	 * Если установленные настройками знаки для записи непригодны
	 *
	 * @note Довод тот же, что и у записи поля: собранное такими настройками прочесть
	 *       нельзя. Знак конца строки, записанный в обход поля, дал бы текст из одних
	 *       пустых записей
	 */
	if(!suitable(this->_settings.separator, this->_settings.quote)){
		// Выполняем отказ записи с сообщением о нём в журнал
		this->refuse(error_t::SEPARATOR_CONFLICT);
		// Выходим из функции
		return;
	}
	// Выполняем запись метки порядка байтов
	this->mark();
	/**
	 * Если запись содержит поля, но знаков не дала вовсе
	 *
	 * @note Случай этот один: запись из единственного ПУСТОГО поля. Пустою строкою она
	 *       неотличима от записи БЕЗ полей, а разбор пустые строки пропускает, и запись
	 *       круга не переживала бы. Пара кавычек её сохраняет - так же поступает
	 *       эталонная реализация языка Python
	 *
	 * @note При запрещённых настройкою кавычках писать нечем, и запись теряется
	 *       законно: договор без кавычек различить эти два случая не позволяет
	 */
	if(this->_started && (this->_text.size() == this->_origin)){
		/**
		 * Если кавычки запрещены настройками вовсе
		 *
		 * @details Пометить такую запись нечем: пустою строкою она неотличима от записи БЕЗ
		 * полей, а разбор пустые строки пропускает. Прежде она ТЕРЯЛАСЬ МОЛЧА - и потеря
		 * эта звалась законной, оттого что представления записи и вправду нет. Но отказ
		 * `UNWRITABLE_FIELD` заведён после и служит ровно тому же: содержимому, каким
		 * установленные настройки записать не могут. Молчаливая потеря записи и громкий
		 * отказ на непредставимое поле - один и тот же случай, и отвечать на него дважды
		 * по-разному значит лгать одному из двух звучащих
		 *
		 * @note Найдено круговым ходом корпуса из 6290 таблиц при укладе «без кавычек,
		 *       отмена знаком отмены»: 453 таблицы теряли записи, и ни одна не узнала об этом
		 */
		if(this->_settings.quoting == quoting_t::NONE){
			// Возвращаем собранный текст к виду, какой он имел до начала записи
			this->_text.resize(this->_origin);
			// Снимаем признак наличия полей у записи
			this->_started = false;
			// Выполняем отказ записи с сообщением о нём в журнал
			this->refuse(error_t::UNWRITABLE_FIELD);
			// Выходим из функции
			return;
		}
		// Записываем открывающий знак кавычек
		this->_text.push_back(this->_settings.quote);
		// Записываем закрывающий знак кавычек
		this->_text.push_back(this->_settings.quote);
	}
	// Записываем знак конца строки
	this->_text.append(newline(this->_settings.newline));
	// Снимаем признак наличия полей у записи
	this->_started = false;
}
/**
 * @brief Метод записи целой записи полем за полем
 *
 * @param fields поля записываемой записи
 *
 */
bool awh::codec::csv::Writer::record(const vector <string> & fields) noexcept {
	/**
	 * Снимок состояния сборщика, снимаемый до всякой его правки
	 *
	 * @note Нужен для отката: отказ на любом из полей снимает и все записанные прежде
	 */
	const size_t restore = this->_text.size();
	// Снимок положения начала текущей записи
	const size_t beginning = this->_origin;
	// Снимок признака наличия полей у записи
	const bool opened = this->_started;
	// Снимок признака записанной метки порядка байтов
	const bool signature = this->_marked;
	/**
	 * Выполняем перебор всех полей записи
	 */
	for(const string & value : fields){
		/**
		 * Если очередное поле записать не удалось
		 *
		 * @note Записанные до отказа поля снимаются: запись эта - одна операция, и
		 *       уйти она обязана либо целиком, либо никак. Оборванная её половина,
		 *       оставленная в тексте, склеилась бы со следующей записью в одну
		 */
		if(!this->field(value)){
			// Выполняем возврат сборщика к виду, какой он имел до начала записи
			this->revert(restore, beginning, opened, signature);
			// Выводим признак отказа записи
			return false;
		}
	}
	// Запоминаем код отказа записи, стоявший до завершения записи
	const error_t previous = this->_error;
	// Завершаем текущую запись
	this->record();
	/**
	 * Если завершение записи окончилось отказом
	 *
	 * @note Отказ этот приходит от записи, из одного лишь пустого поля состоящей: при
	 *       запрещённых кавычках пометить её нечем. Донести его обязаны и здесь, иначе
	 *       запись целиком отвечала бы успехом, ничего не записав
	 */
	if(this->_error != previous){
		// Выполняем возврат сборщика к виду, какой он имел до начала записи
		this->revert(restore, beginning, opened, signature);
		// Возвращаем код отказа записи
		this->_error = ((previous == error_t::NONE) ? error_t::UNWRITABLE_FIELD : previous);
		// Выводим признак отказа записи
		return false;
	}
	// Выводим признак успешной записи
	return true;
}

