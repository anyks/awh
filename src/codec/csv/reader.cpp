/**
 * @brief Метод занесения ошибки разбора
 *
 * @param error код ошибки разбора
 * @return      признак продолжения разбора, всегда ложь
 *
 */
bool awh::codec::csv::Reader::fail(const error_t error) noexcept {
	/**
	 * Если ошибка ещё не занесена
	 *
	 * @note Первая ошибка сохраняется, а последующие отбрасываются: разбор после
	 *       отказа не продолжается, и всякая следующая ошибка была бы её следствием
	 */
	if(this->_error == error_t::NONE){
		// Запоминаем код ошибки разбора
		this->_error = error;
		// Запоминаем положение ошибки в исходном тексте
		this->_position.offset = this->_offset;
		// Запоминаем номер строки, в которой произошла ошибка
		this->_position.line = this->_line;
		// Запоминаем положение в строке, в котором произошла ошибка
		this->_position.column = this->_column;
		/**
		 * Если объект для работы с логами установлен
		 *
		 * @note Код отказа остаётся доступен через error(), а место его - через
		 *       position(): журнал есть оповещение, а не единственный способ узнать
		 *       о случившемся
		 */
		if(this->_log != nullptr)
			// Выполняем вывод сообщения об отказе разбора текста
			this->_log->print("CSV parsing failed: %s at line %u column %u", log_t::flag_t::CRITICAL, awh::codec::csv::message(error), this->_position.line, this->_position.column);
	}
	// Переводим разбор в состояние отказа
	this->_state = state_t::FAILED;
	// Выводим признак прекращения разбора
	return false;
}
/**
 * @brief Метод снятия обвязки с накопленного содержимого поля
 *
 * @details Обвязка снимается лишь у полей без кавычек либо у всех - смотря по
 * настройкам. Договор велит хранить содержимое поля неизменным, потому умолчанием
 * обвязка сохраняется
 *
 * @param offset смещение начала содержимого в хранилище записи
 * @return       отрезок содержимого без обвязки
 *
 */
awh::codec::csv::span_t awh::codec::csv::Reader::trim(const uint32_t offset) noexcept {
	// Положение начала содержимого поля
	uint32_t begin = offset;
	// Положение за концом содержимого поля
	uint32_t end = static_cast <uint32_t> (this->_storage.size());
	/**
	 * Если обвязку снимать не требуется
	 */
	if((this->_settings.trim == trim_t::NONE) ||
	   ((this->_settings.trim == trim_t::UNQUOTED) && this->_quoted))
		// Выводим содержимое поля как есть
		return span_t(begin, end - begin);
	/**
	 * Выполняем поиск первого знака, не являющегося пробельным
	 */
	while((begin < end) && ascii::isSpace(this->_storage[begin]))
		// Выполняем смещение начала содержимого
		begin++;
	/**
	 * Выполняем поиск последнего знака, не являющегося пробельным
	 */
	while((end > begin) && ascii::isSpace(this->_storage[end - 1]))
		// Выполняем смещение конца содержимого
		end--;
	/**
	 * Если обвязка была снята
	 */
	if((begin != offset) || (end != static_cast <uint32_t> (this->_storage.size())))
		// Запоминаем признак изменения содержимого поля разбором
		this->_modified = true;
	// Выводим содержимое поля без обвязки
	return span_t(begin, end - begin);
}
/**
 * @brief Метод завершения текущего поля
 *
 * @details Поле заголовка не выдаётся событием поля: имя его переносится в хранилище
 * имён, а событие выдаётся видом заголовка. Хранилище записи при этом не годится:
 * имена живут до конца разбора, а хранилище записи очищается
 *
 * @return признак продолжения разбора
 *
 */
bool awh::codec::csv::Reader::complete() noexcept {
	// Получаем содержимое поля без обвязки
	const span_t content = this->trim(this->_begin);
	/**
	 * Если длина поля превышает допустимую
	 */
	if((this->_settings.maxField > 0) && (content.length > this->_settings.maxField))
		// Выводим ошибку превышения длины поля
		return this->fail(error_t::FIELD_TOO_LONG);
	/**
	 * Если количество полей в записи превышает допустимое
	 */
	if((this->_settings.maxFields > 0) && (this->_count >= this->_settings.maxFields))
		// Выводим ошибку превышения количества полей
		return this->fail(error_t::TOO_MANY_FIELDS);
	// Собираемое событие разбора
	item_t item;
	// Запоминаем указание на содержимое события
	item.content = content;
	// Запоминаем признак заключения поля в кавычки
	item.quoted = this->_quoted;
	// Запоминаем признак изменения содержимого поля разбором
	item.modified = this->_modified;
	// Запоминаем положение поля в исходном тексте
	item.location = this->_position;
	// Запоминаем номер поля в записи
	item.location.field = this->_field;
	/**
	 * Если разбирается заголовок
	 */
	if((this->_settings.header == header_t::PRESENT) && !this->_headed){
		// Получаем имя поля заголовка
		const string_view name(this->_storage.data() + content.offset, content.length);
		/**
		 * Если имя поля заголовка пусто
		 *
		 * @note Пустое имя поля обращением по имени недостижимо, и молчаливое его
		 *       принятие оставило бы столбец без доступа. Отказ здесь честнее
		 */
		if(name.empty())
			// Выводим ошибку пустого имени поля заголовка
			return this->fail(error_t::EMPTY_HEADER);
		/**
		 * Если проверка повторного объявления имён включена
		 */
		if(this->_settings.duplicates){
			/**
			 * Если имя поля в заголовке уже объявлено
			 */
			if(this->_unique.find(string(name)) != this->_unique.end())
				// Выводим ошибку повторного объявления имени поля
				return this->fail(error_t::DUPLICATE_HEADER);
		}
		// Запоминаем указание на имя поля в хранилище имён
		const span_t stored(static_cast <uint32_t> (this->_names.size()), content.length);
		/**
		 * Если проверка повторного объявления имён включена
		 *
		 * @note Имя заносится в набор владеющей копией, а не ссылкой в хранилище имён:
		 *       хранилище по ходу разбора заголовка прирастает и вправе быть перенесено
		 *       в памяти, обесценив всякую ссылку в него. Прежде имена заносились по
		 *       окончании заголовка, а сверка велась по ходу его разбора - то есть с
		 *       набором, всегда пустым, и повтор не ловился вовсе
		 */
		if(this->_settings.duplicates)
			// Заносим имя поля в набор для проверки повторного объявления
			this->_unique.emplace(name);
		// Переносим имя поля в хранилище имён
		this->_names.append(name);
		// Запоминаем указание на имя поля заголовка
		this->_header.push_back(stored);
		// Запоминаем вид события разбора
		item.event = event_t::HEADER;
		// Запоминаем указание на имя поля события
		item.name = stored;
	/**
	 * Если разбирается обыкновенная запись
	 */
	} else {
		// Запоминаем вид события разбора
		item.event = event_t::FIELD;
		/**
		 * Если заголовок разобран и поле его имеет
		 */
		if(this->_field < static_cast <uint32_t> (this->_header.size()))
			// Запоминаем указание на имя поля события
			item.name = this->_header.at(this->_field);
	}
	// Заносим собранное событие в очередь выдачи
	this->_items.push_back(::std::move(item));
	// Увеличиваем количество полей, накопленное записью
	this->_count++;
	// Увеличиваем номер поля в записи
	this->_field++;
	// Снимаем признак заключения поля в кавычки
	this->_quoted = false;
	// Снимаем признак изменения содержимого поля разбором
	this->_modified = false;
	// Выводим признак продолжения разбора
	return true;
}
/**
 * @brief Метод завершения текущей записи
 *
 * @details Пустая строка записью не считается: договор такую запись не описывает, а
 * обиход единодушно её пропускает. Выдача её событием - настройка
 *
 * @return признак продолжения разбора
 *
 */
bool awh::codec::csv::Reader::commit() noexcept {
	/**
	 * Если запись оказалась пустой строкой
	 *
	 * @note Пустой строкой считается запись из единственного поля, пустого и не
	 *       заключённого в кавычки: запись «""» пустой строкой не является и даёт
	 *       запись с единственным пустым полем
	 */
	if((this->_count == 1) && !this->_started && this->_items.back().content.length == 0 && !this->_items.back().quoted){
		// Убираем событие поля из очереди выдачи
		this->_items.pop_back();
		/**
		 * Если выдача событий пустых строк включена
		 */
		if(this->_settings.emitBlanks){
			// Собираемое событие разбора
			item_t item;
			// Запоминаем вид события разбора
			item.event = event_t::BLANK;
			// Запоминаем положение пустой строки в исходном тексте
			item.location = this->_position;
			// Заносим собранное событие в очередь выдачи
			this->_items.push_back(::std::move(item));
		}
		// Сбрасываем количество полей, накопленное записью
		this->_count = 0;
		// Сбрасываем номер поля в записи
		this->_field = 0;
		// Сбрасываем длину текущей записи
		this->_length = 0;
		// Выводим признак продолжения разбора
		return true;
	}
	/**
	 * Если разбирался заголовок
	 */
	if((this->_settings.header == header_t::PRESENT) && !this->_headed){
		// Запоминаем признак того, что заголовок разобран
		this->_headed = true;
	/**
	 * Если разбиралась обыкновенная запись
	 */
	} else if(this->_settings.ragged != ragged_t::ALLOW) {
		/**
		 * Получаем количество полей, каким надлежит обладать записи
		 *
		 * @note Заголовок, коль скоро он объявлен, количество это и назначает, а без
		 *       него назначает первая запись: договор велит записям обладать
		 *       одинаковым количеством полей независимо от наличия заголовка, и
		 *       бездействие настройки без заголовка было бы её молчаливым отключением
		 */
		const uint32_t expected = (this->_settings.header == header_t::PRESENT ?
			static_cast <uint32_t> (this->_header.size()) : this->_expected
		);
		/**
		 * Если количество полей записи ещё не назначено
		 */
		if(expected == 0)
			// Запоминаем количество полей, назначенное первой записью
			this->_expected = this->_count;
		/**
		 * Если количество полей записи расходится с назначенным количеством
		 */
		else if(this->_count != expected){
			/**
			 * Если расхождение прекращает разбор ошибкой
			 */
			if(this->_settings.ragged == ragged_t::ERROR)
				// Выводим ошибку расхождения количества полей
				return this->fail(error_t::FIELD_COUNT_MISMATCH);
			/**
			 * Выполняем дополнение записи недостающими полями
			 *
			 * @note Лишние поля не отбрасываются: отбросить их значило бы потерять
			 *       данные молча, тогда как дополнение недостающих ничего не теряет
			 */
			while(this->_count < expected){
				// Собираемое событие разбора
				item_t item;
				// Запоминаем вид события разбора
				item.event = event_t::FIELD;
				// Запоминаем признак изменения содержимого поля разбором
				item.modified = true;
				// Запоминаем положение поля в исходном тексте
				item.location = this->_position;
				// Запоминаем номер поля в записи
				item.location.field = this->_field;
				/**
				 * Если поле имеет имя в заголовке
				 */
				if(this->_field < static_cast <uint32_t> (this->_header.size()))
					// Запоминаем указание на имя поля события
					item.name = this->_header.at(this->_field);
				// Заносим собранное событие в очередь выдачи
				this->_items.push_back(::std::move(item));
				// Увеличиваем количество полей, накопленное записью
				this->_count++;
				// Увеличиваем номер поля в записи
				this->_field++;
			}
		}
	}
	// Собираемое событие разбора
	item_t item;
	// Запоминаем вид события разбора
	item.event = event_t::RECORD;
	// Запоминаем положение записи в исходном тексте
	item.location = this->_position;
	// Запоминаем количество полей записи
	item.content = span_t(0, this->_count);
	// Заносим собранное событие в очередь выдачи
	this->_items.push_back(::std::move(item));
	/**
	 * Если разбиралась обыкновенная запись
	 *
	 * @note Заголовок номера записи не занимает: записи считаются от первой записи
	 *       со значениями, и номер этот отвечает тому, что видит потребитель
	 */
	if((this->_settings.header != header_t::PRESENT) || (this->_record > 0) || this->_headed)
		// Увеличиваем номер текущей записи
		this->_record++;
	// Сбрасываем количество полей, накопленное записью
	this->_count = 0;
	// Сбрасываем номер поля в записи
	this->_field = 0;
	// Сбрасываем длину текущей записи
	this->_length = 0;
	// Выводим признак продолжения разбора
	return true;
}
/**
 * @brief Метод разбора очередного знака текста
 *
 * @details Знак, чьё значение зависит от следующего за ним, лишь переводит разбор в
 * отдельное состояние, а решение принимается уже следующим знаком. Иначе нарезка
 * текста ровно между такими знаками меняла бы выдачу
 *
 * @param letter разбираемый знак
 * @return       признак продолжения разбора
 *
 */
/**
 * @brief Метод перестроения разметки знаков, разбор прерывающих
 *
 */
void awh::codec::csv::Reader::marking() noexcept {
	/**
	 * Выполняем перебор всех возможных значений знака
	 */
	for(uint32_t i = 0; i < 256; i++){
		// Снимаем отметку у знака в разметке поля без кавычек
		this->_breakUnquoted[i] = false;
		// Снимаем отметку у знака в разметке поля в кавычках
		this->_breakQuoted[i] = false;
	}
	/**
	 * Отмечаем знаки, разбор поля без кавычек прерывающие
	 *
	 * @note Кавычка отмечается независимо от строгости разбора: обиходный разбор
	 *       признаёт её обыкновенным знаком, но отметка эта лишь возвращает знак
	 *       разбору по знакам, а тот его и признаёт. Разделять здесь два случая
	 *       значило бы держать две разметки ради знака, в поле без кавычек редкого
	 */
	this->_breakUnquoted[static_cast <uint8_t> (this->_separator)] = true;
	this->_breakUnquoted[static_cast <uint8_t> (this->_settings.quote)] = true;
	this->_breakUnquoted[static_cast <uint8_t> ('\r')] = true;
	this->_breakUnquoted[static_cast <uint8_t> ('\n')] = true;
	/**
	 * Отмечаем знаки, разбор поля в кавычках прерывающие
	 *
	 * @note Возврат каретки здесь не отмечается: внутри кавычек он содержимым поля и
	 *       является. Перевод строки отмечается затем, что он двигает номер строки
	 */
	this->_breakQuoted[static_cast <uint8_t> (this->_settings.quote)] = true;
	this->_breakQuoted[static_cast <uint8_t> ('\n')] = true;
	/**
	 * Если способ записи кавычки признаёт знак отмены
	 */
	if((this->_settings.escape == escape_t::BACKSLASH) || (this->_settings.escape == escape_t::BOTH))
		// Отмечаем знак отмены
		this->_breakQuoted[static_cast <uint8_t> ('\\')] = true;
}
/**
 * @brief Метод быстрого прохода по знакам, состояния не меняющим
 *
 * @param buffer буфер проходимых знаков текста
 * @param size   размер буфера проходимых знаков текста
 * @return       количество пройденных знаков
 *
 */
size_t awh::codec::csv::Reader::bulk(const char * buffer, const size_t size) noexcept {
	// Разметка знаков, разбор прерывающих
	const bool * marks = nullptr;
	/**
	 * Определяем состояние разбора текста
	 */
	switch(static_cast <uint8_t> (this->_state)){
		// Если разбор находится внутри поля без кавычек
		case static_cast <uint8_t> (state_t::UNQUOTED):
			// Получаем разметку знаков поля без кавычек
			marks = this->_breakUnquoted;
		break;
		// Если разбор находится внутри поля в кавычках
		case static_cast <uint8_t> (state_t::QUOTED):
			// Получаем разметку знаков поля в кавычках
			marks = this->_breakQuoted;
		break;
		/**
		 * Если разбор находится в любом другом состоянии
		 *
		 * @note Прочие состояния занимают по одному-два знака, и проходить их разом
		 *       нечего: всякий знак в них меняет состояние
		 */
		default: return 0;
	}
	// Количество проходимых знаков
	size_t length = 0;
	/**
	 * Выполняем поиск первого знака, разбор прерывающего
	 */
	while((length < size) && !marks[static_cast <uint8_t> (buffer[length])])
		// Увеличиваем количество проходимых знаков
		length++;
	/**
	 * Если проходить нечего
	 */
	if(length == 0)
		// Выводим количество пройденных знаков
		return 0;
	/**
	 * Если длина записи ограничена
	 *
	 * @note Проход укорачивается до остатка предела, а знак, предел переполняющий,
	 *       достаётся разбору по знакам - тот и отвечает отказом в том же самом месте,
	 *       где ответил бы без прохода
	 */
	if(this->_settings.maxRecord > 0){
		// Получаем остаток предела длины записи
		const uint32_t room = ((this->_settings.maxRecord > this->_length) ? (this->_settings.maxRecord - this->_length) : 0);
		/**
		 * Если остаток предела короче прохода
		 */
		if(length > static_cast <size_t> (room))
			// Укорачиваем проход до остатка предела
			length = static_cast <size_t> (room);
		/**
		 * Если проходить стало нечего
		 */
		if(length == 0)
			// Выводим количество пройденных знаков
			return 0;
	}
	// Переносим пройденные знаки в хранилище знаков записи
	this->_storage.append(buffer, length);
	// Увеличиваем смещение от начала текста
	this->_offset += length;
	// Увеличиваем положение в текущей строке
	this->_column += static_cast <uint32_t> (length);
	// Увеличиваем длину текущей записи
	this->_length += static_cast <uint32_t> (length);
	/**
	 * Если разбор находится внутри поля без кавычек
	 */
	if(this->_state == state_t::UNQUOTED)
		// Запоминаем признак наличия полей у записи
		this->_started = true;
	// Выводим количество пройденных знаков
	return length;
}
/**
 * @brief Метод разбора приведённого куска текста
 *
 * @param text разбираемый приведённый кусок текста
 * @return     признак продолжения разбора
 *
 */
bool awh::codec::csv::Reader::process(const string & text) noexcept {
	// Смещение по разбираемому куску текста
	size_t offset = 0;
	/**
	 * Выполняем разбор всего куска текста
	 */
	while(offset < text.size()){
		// Выполняем быстрый проход по знакам, состояния не меняющим
		offset += this->bulk(text.data() + offset, text.size() - offset);
		/**
		 * Если кусок текста исчерпан проходом
		 */
		if(offset >= text.size())
			// Выводим признак продолжения разбора
			break;
		/**
		 * Если разбор очередного знака не удался
		 */
		if(!this->parse(text[offset]))
			// Выводим признак неудачного разбора
			return false;
		// Выполняем переход к следующему знаку
		offset++;
	}
	// Выводим признак продолжения разбора
	return true;
}
bool awh::codec::csv::Reader::parse(const char letter) noexcept {
	/**
	 * Если длина записи превышает допустимую
	 */
	if((this->_settings.maxRecord > 0) && (this->_length >= this->_settings.maxRecord))
		// Выводим ошибку превышения длины записи
		return this->fail(error_t::RECORD_TOO_LONG);
	// Увеличиваем длину текущей записи
	this->_length++;
	// Выполняем разбор знака состоянием разбора
	return this->step(letter);
}
/**
 * @brief Метод разбора знака состоянием разбора
 *
 * @details Знак, сменивший состояние, разбирается заново уже новым состоянием, и разбор
 * потому вызывает себя повторно тем же знаком. Учёт длины записи вынесен наружу именно
 * поэтому: считаемый здесь, он рос бы на всякий заход и отсекал запись прежде
 * положенного предела - тем более прежде, чем больше состояний знак сменил
 *
 * @param letter разбираемый знак
 * @return       признак продолжения разбора
 *
 */
bool awh::codec::csv::Reader::step(const char letter) noexcept {
	/**
	 * Определяем состояние разбора текста
	 */
	switch(static_cast <uint8_t> (this->_state)){
		/**
		 * Если разбор находится в состоянии отказа
		 */
		case static_cast <uint8_t> (state_t::FAILED):
			// Выводим признак прекращения разбора
			return false;
		/**
		 * Если разбор находится в состоянии возврата каретки
		 *
		 * @note Возврат каретки завершает запись сам по себе, а следующий за ним
		 *       перевод строки лишь дополняет его. Оттого запись завершается здесь, а
		 *       перевод строки, если он пришёл, поглощается без последствий
		 */
		case static_cast <uint8_t> (state_t::AFTER_CR): {
			// Переводим разбор в состояние начала записи
			this->_state = state_t::RECORD_START;
			/**
			 * Если знаком является перевод строки
			 */
			if(letter == '\n'){
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем номер текущей строки
				this->_line++;
				// Сбрасываем положение в текущей строке
				this->_column = 1;
				// Выводим признак продолжения разбора
				return true;
			}
			// Разбираем знак заново в состоянии начала записи
			return this->step(letter);
		}
		/**
		 * Если разбор находится в состоянии начала записи
		 */
		case static_cast <uint8_t> (state_t::RECORD_START): {
			/**
			 * Если знак начинает строку примечания
			 */
			if((this->_settings.comment != '\0') && (letter == this->_settings.comment)){
				// Запоминаем положение начала примечания в исходном тексте
				this->_position.offset = this->_offset;
				// Запоминаем номер строки начала примечания
				this->_position.line = this->_line;
				// Запоминаем положение в строке начала примечания
				this->_position.column = this->_column;
				// Запоминаем номер записи начала примечания
				this->_position.record = this->_record;
				// Запоминаем смещение начала примечания в хранилище знаков
				this->_begin = static_cast <uint32_t> (this->_storage.size());
				// Переводим разбор в состояние строки примечания
				this->_state = state_t::COMMENT;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				// Выводим признак продолжения разбора
				return true;
			}
			// Снимаем признак наличия полей у записи
			this->_started = false;
			// Переводим разбор в состояние начала поля
			this->_state = state_t::FIELD_START;
			// Разбираем знак заново в состоянии начала поля
			return this->step(letter);
		}
		/**
		 * Если разбор находится в состоянии строки примечания
		 */
		case static_cast <uint8_t> (state_t::COMMENT): {
			/**
			 * Если знаком является знак конца строки
			 */
			if((letter == '\r') || (letter == '\n')){
				/**
				 * Если выдача событий примечаний включена
				 */
				if(this->_settings.emitComments){
					// Собираемое событие разбора
					item_t item;
					// Запоминаем вид события разбора
					item.event = event_t::COMMENT;
					// Запоминаем указание на содержимое события
					item.content = span_t(this->_begin, static_cast <uint32_t> (this->_storage.size()) - this->_begin);
					// Запоминаем положение примечания в исходном тексте
					item.location = this->_position;
					// Заносим собранное событие в очередь выдачи
					this->_items.push_back(::std::move(item));
				}
				// Сбрасываем длину текущей записи
				this->_length = 0;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				/**
				 * Если знаком является возврат каретки
				 */
				if(letter == '\r')
					// Переводим разбор в состояние возврата каретки
					this->_state = state_t::AFTER_CR;
				/**
				 * Если знаком является перевод строки
				 */
				else {
					// Переводим разбор в состояние начала записи
					this->_state = state_t::RECORD_START;
					// Увеличиваем номер текущей строки
					this->_line++;
					// Сбрасываем положение в текущей строке
					this->_column = 1;
				}
				// Выводим признак продолжения разбора
				return true;
			}
			// Дописываем знак к содержимому примечания
			this->_storage.push_back(letter);
			// Увеличиваем смещение от начала текста
			this->_offset++;
			// Увеличиваем положение в текущей строке
			this->_column++;
			// Выводим признак продолжения разбора
			return true;
		}
		/**
		 * Если разбор находится в состоянии начала поля
		 */
		case static_cast <uint8_t> (state_t::FIELD_START): {
			// Запоминаем положение начала поля в исходном тексте
			this->_position.offset = this->_offset;
			// Запоминаем номер строки начала поля
			this->_position.line = this->_line;
			// Запоминаем положение в строке начала поля
			this->_position.column = this->_column;
			// Запоминаем номер записи начала поля
			this->_position.record = this->_record;
			// Запоминаем смещение начала поля в хранилище знаков
			this->_begin = static_cast <uint32_t> (this->_storage.size());
			/**
			 * Если знаком является кавычка
			 */
			if(letter == this->_settings.quote){
				// Запоминаем признак заключения поля в кавычки
				this->_quoted = true;
				// Запоминаем признак изменения содержимого поля разбором
				this->_modified = true;
				// Переводим разбор в состояние поля в кавычках
				this->_state = state_t::QUOTED;
				// Запоминаем признак наличия полей у записи
				this->_started = true;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				// Выводим признак продолжения разбора
				return true;
			}
			// Переводим разбор в состояние поля без кавычек
			this->_state = state_t::UNQUOTED;
			// Разбираем знак заново в состоянии поля без кавычек
			return this->step(letter);
		}
		/**
		 * Если разбор находится в состоянии поля без кавычек
		 */
		case static_cast <uint8_t> (state_t::UNQUOTED): {
			/**
			 * Если знаком является разделитель полей
			 */
			if(letter == this->_separator){
				// Запоминаем признак наличия полей у записи
				this->_started = true;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				/**
				 * Если завершить поле не удалось
				 */
				if(!this->complete())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Запоминаем смещение начала следующего поля в хранилище знаков
				 *
				 * @note Смещение это заводится здесь, а не при разборе первого знака
				 *       следующего поля: текст вправе окончиться сразу за разделителем,
				 *       и тогда знака этого не будет вовсе, а завершение последнего поля
				 *       возьмёт смещение прежнего - выдав содержимое предыдущего поля
				 *       вторично
				 */
				this->_begin = static_cast <uint32_t> (this->_storage.size());
				// Переводим разбор в состояние начала поля
				this->_state = state_t::FIELD_START;
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является знак конца строки
			 */
			if((letter == '\r') || (letter == '\n')){
				/**
				 * Если разбор ведётся строго по договору, а знаком является одиночный перевод строки
				 *
				 * @note Договор велит завершать запись возвратом каретки с переводом
				 *       строки. Одиночный перевод строки признаётся послаблением,
				 *       поскольку так пишут все системы семейства UNIX
				 */
				if(this->_settings.strict && (letter == '\n'))
					// Выводим ошибку недопустимого знака
					return this->fail(error_t::INVALID_CHARACTER);
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				/**
				 * Если завершить поле не удалось
				 */
				if(!this->complete())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Если завершить запись не удалось
				 */
				if(!this->commit())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Если знаком является возврат каретки
				 */
				if(letter == '\r')
					// Переводим разбор в состояние возврата каретки
					this->_state = state_t::AFTER_CR;
				/**
				 * Если знаком является перевод строки
				 */
				else {
					// Переводим разбор в состояние начала записи
					this->_state = state_t::RECORD_START;
					// Увеличиваем номер текущей строки
					this->_line++;
					// Сбрасываем положение в текущей строке
					this->_column = 1;
				}
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является кавычка
			 *
			 * @note Запись эта договором не описана вовсе. Строгий разбор отвечает на
			 *       неё отказом, а обиходный признаёт кавычку обыкновенным знаком:
			 *       отвергать такую запись значило бы отвергать файлы, которые пишут
			 *       и читают все прочие
			 */
			if((letter == this->_settings.quote) && this->_settings.strict)
				// Выводим ошибку неэкранированной кавычки
				return this->fail(error_t::UNESCAPED_QUOTE);
			// Запоминаем признак наличия полей у записи
			this->_started = true;
			// Дописываем знак к содержимому поля
			this->_storage.push_back(letter);
			// Увеличиваем смещение от начала текста
			this->_offset++;
			// Увеличиваем положение в текущей строке
			this->_column++;
			// Выводим признак продолжения разбора
			return true;
		}
		/**
		 * Если разбор находится в состоянии поля в кавычках
		 */
		case static_cast <uint8_t> (state_t::QUOTED): {
			/**
			 * Если знаком является кавычка
			 */
			if(letter == this->_settings.quote){
				// Переводим разбор в состояние кавычки внутри поля
				this->_state = state_t::QUOTE_IN_FIELD;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является знак отмены и способ записи его признаёт
			 */
			if((letter == '\\') && ((this->_settings.escape == escape_t::BACKSLASH) || (this->_settings.escape == escape_t::BOTH))){
				// Переводим разбор в состояние знака отмены
				this->_state = state_t::ESCAPE;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является перевод строки
			 *
			 * @note Перевод строки внутри поля в кавычках договором дозволен и хранится
			 *       ровно таким, каким записан: приведение его к единому виду испортило
			 *       бы значения, где знаки эти значащие
			 */
			if(letter == '\n'){
				// Увеличиваем номер текущей строки
				this->_line++;
				// Сбрасываем положение в текущей строке
				this->_column = 0;
			}
			// Дописываем знак к содержимому поля
			this->_storage.push_back(letter);
			// Увеличиваем смещение от начала текста
			this->_offset++;
			// Увеличиваем положение в текущей строке
			this->_column++;
			// Выводим признак продолжения разбора
			return true;
		}
		/**
		 * Если разбор находится в состоянии знака отмены
		 */
		case static_cast <uint8_t> (state_t::ESCAPE): {
			// Дописываем знак к содержимому поля
			this->_storage.push_back(letter);
			// Запоминаем признак изменения содержимого поля разбором
			this->_modified = true;
			// Переводим разбор в состояние поля в кавычках
			this->_state = state_t::QUOTED;
			// Увеличиваем смещение от начала текста
			this->_offset++;
			// Увеличиваем положение в текущей строке
			this->_column++;
			// Выводим признак продолжения разбора
			return true;
		}
		/**
		 * Если разбор находится в состоянии кавычки внутри поля
		 *
		 * @note Значение кавычки решает следующий за нею знак: кавычка означает
		 *       кавычку в содержимом, разделитель либо знак конца строки - конец поля,
		 *       а всё прочее договором не описано
		 */
		case static_cast <uint8_t> (state_t::QUOTE_IN_FIELD): {
			/**
			 * Если знаком является кавычка и способ записи признаёт удвоение
			 */
			if((letter == this->_settings.quote) && ((this->_settings.escape == escape_t::DOUBLE) || (this->_settings.escape == escape_t::BOTH))){
				// Дописываем кавычку к содержимому поля
				this->_storage.push_back(letter);
				// Запоминаем признак изменения содержимого поля разбором
				this->_modified = true;
				// Переводим разбор в состояние поля в кавычках
				this->_state = state_t::QUOTED;
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является разделитель полей
			 */
			if(letter == this->_separator){
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				/**
				 * Если завершить поле не удалось
				 */
				if(!this->complete())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Запоминаем смещение начала следующего поля в хранилище знаков
				 *
				 * @note Смещение это заводится здесь, а не при разборе первого знака
				 *       следующего поля: текст вправе окончиться сразу за разделителем,
				 *       и тогда знака этого не будет вовсе, а завершение последнего поля
				 *       возьмёт смещение прежнего - выдав содержимое предыдущего поля
				 *       вторично
				 */
				this->_begin = static_cast <uint32_t> (this->_storage.size());
				// Переводим разбор в состояние начала поля
				this->_state = state_t::FIELD_START;
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если знаком является знак конца строки
			 */
			if((letter == '\r') || (letter == '\n')){
				/**
				 * Если разбор ведётся строго по договору, а знаком является одиночный перевод строки
				 */
				if(this->_settings.strict && (letter == '\n'))
					// Выводим ошибку недопустимого знака
					return this->fail(error_t::INVALID_CHARACTER);
				// Увеличиваем смещение от начала текста
				this->_offset++;
				// Увеличиваем положение в текущей строке
				this->_column++;
				/**
				 * Если завершить поле не удалось
				 */
				if(!this->complete())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Если завершить запись не удалось
				 */
				if(!this->commit())
					// Выводим признак прекращения разбора
					return false;
				/**
				 * Если знаком является возврат каретки
				 */
				if(letter == '\r')
					// Переводим разбор в состояние возврата каретки
					this->_state = state_t::AFTER_CR;
				/**
				 * Если знаком является перевод строки
				 */
				else {
					// Переводим разбор в состояние начала записи
					this->_state = state_t::RECORD_START;
					// Увеличиваем номер текущей строки
					this->_line++;
					// Сбрасываем положение в текущей строке
					this->_column = 1;
				}
				// Выводим признак продолжения разбора
				return true;
			}
			/**
			 * Если разбор ведётся строго по договору
			 *
			 * @note Знаки за закрывающей кавычкой договором не описаны. Обиходный
			 *       разбор дописывает их к содержимому поля, полагая кавычку закрытой
			 *       не там, где она стоит
			 */
			if(this->_settings.strict)
				// Выводим ошибку знаков за закрывающей кавычкой
				return this->fail(error_t::TRAILING_CHARACTERS);
			// Дописываем знак к содержимому поля
			this->_storage.push_back(letter);
			/**
			 * Переводим разбор в состояние поля без кавычек
			 *
			 * @note Именно без кавычек, а не обратно в кавычки: кавычка эта поле уже
			 *       закрыла, и разделитель, стоящий далее, обязан поле разделять. Возврат
			 *       же в состояние поля в кавычках сделал бы разделитель содержимым, и
			 *       запись «"a"b,c» дала бы одно поле вместо двух, а текст без второй
			 *       закрывающей кавычки - отказ «незакрытое поле»
			 */
			this->_state = state_t::UNQUOTED;
			// Увеличиваем смещение от начала текста
			this->_offset++;
			// Увеличиваем положение в текущей строке
			this->_column++;
			// Выводим признак продолжения разбора
			return true;
		}
	}
	// Выводим ошибку внутреннего отказа разбора
	return this->fail(error_t::INTERNAL);
}
/**
 * @brief Метод завершения разбора текста
 *
 * @details Доводит до конца то, что осталось незавершённым: последнее поле без знака
 * конца строки, последнюю запись и отложенное состояние возврата каретки
 *
 */
void awh::codec::csv::Reader::finish() noexcept {
	/**
	 * Определяем состояние разбора текста
	 */
	switch(static_cast <uint8_t> (this->_state)){
		// Если разбор находится в состоянии отказа
		case static_cast <uint8_t> (state_t::FAILED):
			// Выходим из метода, разбор уже прекращён
			return;
		/**
		 * Если разбор находится в состоянии поля в кавычках
		 *
		 * @note Поле в кавычках, не закрытое до конца текста, отказом договора не
		 *       описано, но принять его значило бы принять и текст, оборванный посреди
		 *       передачи, за целый
		 */
		case static_cast <uint8_t> (state_t::QUOTED):
		// Если разбор находится в состоянии знака отмены
		case static_cast <uint8_t> (state_t::ESCAPE):
			// Заносим ошибку незакрытого поля в кавычках
			this->fail(error_t::UNTERMINATED_QUOTE);
			// Выходим из метода
			return;
		/**
		 * Если разбор находится в состоянии возврата каретки
		 *
		 * @note Запись здесь уже завершена самим возвратом каретки: довершать нечего
		 */
		case static_cast <uint8_t> (state_t::AFTER_CR):
			// Переводим разбор в состояние начала записи
			this->_state = state_t::RECORD_START;
			// Выходим из метода
			return;
		/**
		 * Если разбор находится в состоянии строки примечания
		 */
		case static_cast <uint8_t> (state_t::COMMENT): {
			/**
			 * Если выдача событий примечаний включена
			 */
			if(this->_settings.emitComments){
				// Собираемое событие разбора
				item_t item;
				// Запоминаем вид события разбора
				item.event = event_t::COMMENT;
				// Запоминаем указание на содержимое события
				item.content = span_t(this->_begin, static_cast <uint32_t> (this->_storage.size()) - this->_begin);
				// Запоминаем положение примечания в исходном тексте
				item.location = this->_position;
				// Заносим собранное событие в очередь выдачи
				this->_items.push_back(::std::move(item));
			}
			// Переводим разбор в состояние начала записи
			this->_state = state_t::RECORD_START;
			// Выходим из метода
			return;
		}
		/**
		 * Если разбор находится в состоянии начала записи
		 *
		 * @note Текст, оканчивающийся знаком конца строки, довершать нечем: запись уже
		 *       завершена, и добавлять пустую здесь значило бы выдумывать её
		 */
		case static_cast <uint8_t> (state_t::RECORD_START):
			// Выходим из метода
			return;
	}
	/**
	 * Если завершить последнее поле удалось
	 */
	if(this->complete())
		// Завершаем последнюю запись
		this->commit();
	// Переводим разбор в состояние начала записи
	this->_state = state_t::RECORD_START;
}
/**
 * @brief Метод подсчёта полей при заданном разделителе
 *
 * @details Подсчёт ведётся тем же прочтением кавычек, что и разбор: разделитель
 * внутри поля в кавычках полем не является, и подсчёт, того не учитывающий, выбрал бы
 * разделителем знак, часто встречающийся в значениях
 *
 * @param separator знак-разделитель для проверки
 * @param counts    количество полей по записям
 * @return          признак пригодности разделителя
 *
 */
bool awh::codec::csv::Reader::count(const char separator, vector <uint32_t> & counts) const noexcept {
	/**
	 * Если разделитель для разбора непригоден
	 */
	if(!suitable(separator, this->_settings.quote))
		// Выводим признак непригодности разделителя
		return false;
	/**
	 * Граница просматриваемой части отложенного текста
	 *
	 * @details Просмотр обрывается сразу за переводом строки, завершающим последнюю из
	 * записей, по каким ведётся определение
	 *
	 * @note Граница эта нужна ради независимости определения от нарезки текста на
	 *       куски: при подаче кусками отложенный текст обрывается на пороге определения,
	 *       а при подаче целиком содержит всю таблицу. Считая по всему отложенному, две
	 *       подачи брали образцы разной длины и вправе были выбрать разные разделители
	 */
	size_t limit = this->_pending.size();
	{
		// Количество просмотренных знаков конца строки
		uint32_t lines = 0;
		/**
		 * Выполняем поиск конца записи, по какой определение прекращается
		 */
		for(size_t i = 0; i < this->_pending.size(); i++){
			/**
			 * Если знаком является перевод строки
			 */
			if(this->_pending[i] == '\n'){
				// Увеличиваем количество просмотренных знаков конца строки
				lines++;
				/**
				 * Если просмотрено довольно записей
				 */
				if(lines >= this->_settings.detect){
					// Запоминаем границу просматриваемой части отложенного текста
					limit = (i + 1);
					// Прекращаем поиск конца записи
					break;
				}
			}
		}
	}
	// Количество полей текущей записи
	uint32_t fields = 1;
	// Признак нахождения внутри поля в кавычках
	bool quoted = false;
	// Признак того, что предыдущим знаком была кавычка внутри поля
	bool pending = false;
	/**
	 * Выполняем перебор знаков просматриваемой части отложенного текста
	 */
	for(size_t index = 0; index < limit; index++){
		// Получаем очередной знак отложенного текста
		const char letter = this->_pending[index];
		/**
		 * Если разбор находится внутри поля в кавычках
		 */
		if(quoted){
			/**
			 * Если предыдущим знаком была кавычка внутри поля
			 */
			if(pending){
				// Снимаем признак кавычки внутри поля
				pending = false;
				/**
				 * Если знаком является кавычка
				 */
				if(letter == this->_settings.quote)
					// Продолжаем разбор поля в кавычках
					continue;
				// Снимаем признак нахождения внутри поля в кавычках
				quoted = false;
			/**
			 * Если знаком является кавычка
			 */
			} else if(letter == this->_settings.quote) {
				// Запоминаем признак кавычки внутри поля
				pending = true;
				// Продолжаем разбор поля в кавычках
				continue;
			// Продолжаем разбор поля в кавычках
			} else continue;
		}
		/**
		 * Если знаком является кавычка
		 */
		if(letter == this->_settings.quote){
			// Запоминаем признак нахождения внутри поля в кавычках
			quoted = true;
			// Продолжаем разбор текста
			continue;
		}
		/**
		 * Если знаком является разделитель полей
		 */
		if(letter == separator){
			// Увеличиваем количество полей текущей записи
			fields++;
			// Продолжаем разбор текста
			continue;
		}
		/**
		 * Если знаком является перевод строки
		 */
		if(letter == '\n'){
			// Заносим количество полей завершённой записи
			counts.push_back(fields);
			// Сбрасываем количество полей текущей записи
			fields = 1;
			/**
			 * Если просмотрено довольно записей
			 */
			if(counts.size() >= this->_settings.detect)
				// Прекращаем просмотр отложенного текста
				break;
		}
	}
	/**
	 * Если текст оканчивается незавершённой записью и она не пуста
	 *
	 * @note Учитывается она лишь тогда, когда просмотр дошёл до конца отложенного
	 *       текста: незавершённая запись, стоящая за границей просмотра, к определению
	 *       отношения не имеет, а при подаче кусками её там не было бы вовсе
	 */
	if(this->_last && (limit == this->_pending.size()) && (fields > 1))
		// Заносим количество полей незавершённой записи
		counts.push_back(fields);
	// Выводим признак пригодности разделителя
	return !counts.empty();
}
/**
 * @brief Метод определения разделителя по отложенному тексту
 *
 * @details Достоинством разделителя считается постоянство количества полей в записях,
 * а не частота знака: частота обманывается текстом, где запятых в значениях больше,
 * чем разделителей. Побеждает знак, дающий наибольшее количество записей с одним и тем
 * же числом полей, а при равенстве - знак, дающий больше полей
 *
 * @return признак успешного определения
 *
 */
bool awh::codec::csv::Reader::detect() noexcept {
	// Достоинство лучшего из проверенных разделителей
	uint32_t best = 0;
	// Количество полей у лучшего из проверенных разделителей
	uint32_t width = 0;
	// Лучший из проверенных разделителей
	char result = '\0';
	/**
	 * Выполняем перебор всех проверяемых знаков
	 */
	for(const char candidate : ::CANDIDATES){
		// Количество полей по записям
		vector <uint32_t> counts;
		/**
		 * Если разделитель для разбора непригоден
		 */
		if(!this->count(candidate, counts))
			// Переходим к следующему проверяемому знаку
			continue;
		// Наиболее частое количество полей
		uint32_t common = 0;
		// Достоинство проверяемого разделителя
		uint32_t score = 0;
		/**
		 * Выполняем перебор всех полученных количеств полей
		 */
		for(const uint32_t value : counts){
			// Количество записей с таким же числом полей
			uint32_t repeats = 0;
			/**
			 * Выполняем подсчёт записей с таким же числом полей
			 */
			for(const uint32_t other : counts)
				// Увеличиваем количество записей с таким же числом полей
				repeats += static_cast <uint32_t> (other == value);
			/**
			 * Если найдено более частое количество полей
			 */
			if((repeats > score) || ((repeats == score) && (value > common))){
				// Запоминаем достоинство проверяемого разделителя
				score = repeats;
				// Запоминаем наиболее частое количество полей
				common = value;
			}
		}
		/**
		 * Если проверяемый разделитель полей не разделяет вовсе
		 *
		 * @note Знак, дающий одно поле на запись, разделителем не является: таким же
		 *       достоинством обладает всякий знак, в тексте не встречающийся
		 */
		if(common < 2)
			// Переходим к следующему проверяемому знаку
			continue;
		/**
		 * Если проверяемый разделитель превзошёл лучшего
		 */
		if((score > best) || ((score == best) && (common > width))){
			// Запоминаем достоинство лучшего разделителя
			best = score;
			// Запоминаем количество полей лучшего разделителя
			width = common;
			// Запоминаем лучший разделитель
			result = candidate;
		}
	}
	/**
	 * Если разделитель определить не удалось
	 *
	 * @note Текст в один столбец разделителя не содержит вовсе, и отказывать ему
	 *       незачем: разделителем берётся запятая, названная договором. Отличить
	 *       такой текст от неразбираемого нельзя ни одним способом
	 */
	if(result == '\0')
		// Устанавливаем разделитель, названный договором
		result = ',';
	// Запоминаем определённый разделитель полей
	this->_separator = result;
	// Выполняем перестроение разметки знаков, разбор прерывающих
	this->marking();
	// Запоминаем признак того, что разделитель определён
	this->_detected = true;
	// Выводим признак успешного определения
	return true;
}
/**
 * @brief Метод сброса состояния разбора
 *
 * @param настройки разбора сохраняются
 *
 */
void awh::codec::csv::Reader::reset() noexcept {
	// Переводим разбор в состояние начала записи
	this->_state = state_t::RECORD_START;
	// Сбрасываем код ошибки разбора
	this->_error = error_t::NONE;
	// Сбрасываем кодировку исходного текста
	this->_encoding = encoding_t::NONE;
	// Устанавливаем разделитель полей, заданный настройками
	this->_separator = this->_settings.separator;
	// Запоминаем признак того, задан ли разделитель настройками
	this->_detected = (this->_settings.separator != '\0');
	/**
	 * Выполняем перестроение разметки знаков, разбор прерывающих
	 *
	 * @note Перестроение идёт при всяком сбросе, а не однажды при заведении: знаки эти
	 *       зависят от настроек, а настройки устанавливаются именно сбросом
	 */
	this->marking();
	// Сбрасываем признак разбора метки порядка байтов
	this->_marked = false;
	// Сбрасываем признак подачи текста целиком
	this->_last = false;
	// Сбрасываем количество полей, назначенное первой записью
	this->_expected = 0;
	// Сбрасываем признак разбора заголовка
	this->_headed = false;
	// Сбрасываем признак заключения поля в кавычки
	this->_quoted = false;
	// Сбрасываем признак изменения содержимого поля разбором
	this->_modified = false;
	// Сбрасываем признак наличия полей у записи
	this->_started = false;
	// Очищаем хранилище знаков текущей записи
	this->_storage.clear();
	// Очищаем хранилище имён полей заголовка
	this->_names.clear();
	// Очищаем хранилище отложенных байтов
	this->_pending.clear();
	// Очищаем хранилище перекодированного текста
	this->_decoded.clear();
	// Очищаем указания на имена полей заголовка
	this->_header.clear();
	// Очищаем имена полей заголовка
	this->_unique.clear();
	// Очищаем очередь собранных событий разбора
	this->_items.clear();
	// Сбрасываем указание на первое невыданное событие
	this->_head = 0;
	// Сбрасываем событие разбора, выданное последним
	this->_current = item_t();
	// Сбрасываем положение начала текущего поля
	this->_position = location_t();
	// Сбрасываем смещение от начала текста
	this->_offset = 0;
	// Устанавливаем номер текущей строки
	this->_line = 1;
	// Устанавливаем положение в текущей строке
	this->_column = 1;
	// Сбрасываем номер текущей записи
	this->_record = 0;
	// Сбрасываем номер текущего поля в записи
	this->_field = 0;
	// Сбрасываем количество полей, накопленное записью
	this->_count = 0;
	// Сбрасываем длину текущей записи
	this->_length = 0;
	// Сбрасываем смещение начала текущего поля в хранилище знаков
	this->_begin = 0;
	// Сбрасываем приведение исходного текста к кодировке UTF-8
	this->_decoder.reset();
	/**
	 * Если кодировка навязана извне
	 */
	if(this->_settings.encoding != encoding_t::NONE)
		// Навязываем кодировку приведению исходного текста
		this->_decoder.encoding(this->_settings.encoding);
}
/**
 * @brief Метод подачи очередного куска текста
 *
 * @param buffer буфер с куском текста
 * @param size   размер куска текста в байтах
 * @param last   признак того, что кусок является последним
 * @return       признак успешного разбора поданного куска
 *
 */
bool awh::codec::csv::Reader::feed(const char * buffer, const size_t size, const bool last) noexcept {
	/**
	 * Если разбор уже прекращён отказом
	 */
	if(this->_error != error_t::NONE)
		// Выводим признак неудачного разбора
		return false;
	/**
	 * Если разделитель задан настройками, а для разбора непригоден
	 */
	if(this->_detected && !suitable(this->_separator, this->_settings.quote))
		// Выводим ошибку непригодного разделителя
		return this->fail(error_t::SEPARATOR_CONFLICT);
	// Запоминаем признак подачи текста целиком
	this->_last = (this->_last || last);
	/**
	 * Если очередь собранных событий разбора пуста
	 *
	 * @note Хранилище очищается лишь тогда, когда события его уже выданы: события
	 *       ссылаются в него смещениями, и очистка при неопустевшей очереди обесценила
	 *       бы ссылки уже собранных событий
	 */
	if((this->_head >= this->_items.size()) && (this->_begin == static_cast <uint32_t> (this->_storage.size()))){
		// Очищаем хранилище знаков текущей записи
		this->_storage.clear();
		// Сбрасываем смещение начала текущего поля в хранилище знаков
		this->_begin = 0;
	}
	// Очищаем хранилище перекодированного текста
	this->_decoded.clear();
	/**
	 * Код ошибки приведения, отложенный до разбора приведённого прежде неё
	 *
	 * @note Приведение ведётся над всем куском разом, а разбор - знак за знаком, и
	 *       ошибка приведения, случившаяся в конце куска, объявилась бы прежде ошибки
	 *       разбора, стоящей в его начале. Итог разбора зависел бы тогда от нарезки
	 *       текста на куски: та же ошибка при подаче помельче выдавалась бы иной.
	 *       Оттого приведённое прежде места обрыва разбирается, и лишь потом
	 *       объявляется ошибка приведения
	 */
	error_t deferred = error_t::NONE;
	/**
	 * Если приведение куска текста к кодировке UTF-8 не удалось
	 */
	if(!this->_decoder.convert(buffer, size, last, this->_decoded)){
		/**
		 * Определяем код ошибки приведения
		 */
		switch(static_cast <uint8_t> (this->_decoder.error())){
			// Если объявленная кодировка не поддерживается
			case static_cast <uint8_t> (error_t::UNSUPPORTED_ENCODING):
				// Запоминаем ошибку неподдерживаемой кодировки
				deferred = error_t::UNSUPPORTED_ENCODING;
			break;
			// Если последовательность байтов не отвечает объявленной кодировке
			default:
				// Запоминаем ошибку ошибочной последовательности байтов
				deferred = error_t::INVALID_ENCODING;
		}
		/**
		 * Запоминаем признак подачи текста целиком
		 *
		 * @note Приведение оборвалось, и годного текста за местом обрыва нет: подача
		 *       считается последней независимо от того, объявил ли её таковой
		 *       подающий. Без этого определение разделителя брало бы образец
		 *       по-разному - при подаче целиком признак стоял бы, а при подаче кусками
		 *       на том же самом тексте не стоял, и разделитель выходил бы разным
		 */
		this->_last = true;
	}
	// Запоминаем кодировку исходного текста
	this->_encoding = this->_decoder.encoding();
	/**
	 * Если разделитель ещё не определён
	 */
	if(!this->_detected){
		// Откладываем перекодированный текст до определения разделителя
		this->_pending.append(this->_decoded);
		// Количество знаков конца строки в отложенном тексте
		uint32_t lines = 0;
		/**
		 * Выполняем подсчёт знаков конца строки в отложенном тексте
		 */
		for(const char letter : this->_pending)
			// Увеличиваем количество знаков конца строки
			lines += static_cast <uint32_t> (letter == '\n');
		/**
		 * Если записей для определения разделителя ещё недостаточно
		 */
		if(!this->_last && (deferred == error_t::NONE) && (lines < this->_settings.detect))
			// Выводим признак успешного разбора поданного куска
			return true;
		/**
		 * Если определить разделитель не удалось
		 */
		if(!this->detect())
			// Выводим ошибку неопределённого разделителя
			return this->fail(error_t::SEPARATOR_UNDETECTED);
		/**
		 * Если разбор отложенного текста не удался
		 */
		if(!this->process(this->_pending))
			// Выводим признак неудачного разбора
			return false;
		// Очищаем хранилище отложенных байтов
		this->_pending.clear();
		/**
		 * Если приведение текста оборвалось ошибкой
		 *
		 * @note Разбор здесь не довершается: текста за местом обрыва нет, и довершить
		 *       последнюю запись значило бы выдать оборванное за целое
		 */
		if(deferred != error_t::NONE)
			// Выводим отложенную ошибку приведения
			return this->fail(deferred);
		/**
		 * Если текст подан целиком
		 */
		if(this->_last)
			// Завершаем разбор текста
			this->finish();
		// Выводим признак успешного разбора поданного куска
		return true;
	}
	/**
	 * Если разбор перекодированного текста не удался
	 */
	if(!this->process(this->_decoded))
		// Выводим признак неудачного разбора
		return false;
	/**
	 * Если приведение текста оборвалось ошибкой
	 *
	 * @note Разбор здесь не довершается: текста за местом обрыва нет, и довершить
	 *       последнюю запись значило бы выдать оборванное за целое
	 */
	if(deferred != error_t::NONE)
		// Выводим отложенную ошибку приведения
		return this->fail(deferred);
	/**
	 * Если текст подан целиком
	 */
	if(this->_last)
		// Завершаем разбор текста
		this->finish();
	// Выводим признак успешного разбора поданного куска
	return (this->_error == error_t::NONE);
}
/**
 * @brief Метод подачи текста целиком
 *
 * @param text текст для разбора
 * @return     признак успешного разбора
 *
 */
bool awh::codec::csv::Reader::feed(const string_view text) noexcept {
	// Выполняем подачу текста целиком
	return this->feed(text.data(), text.length(), true);
}
/**
 * @brief Метод перехода к следующему событию разбора
 *
 * @return признак наличия события
 *
 */
bool awh::codec::csv::Reader::next() noexcept {
	/**
	 * Если очередь собранных событий разбора пуста
	 */
	if(this->_head >= this->_items.size()){
		// Сбрасываем событие разбора, выданное последним
		this->_current = item_t();
		/**
		 * Если текст подан целиком и разбор прошёл без ошибок
		 */
		if(this->_last && (this->_error == error_t::NONE))
			// Запоминаем событие окончания разбора текста
			this->_current.event = event_t::FINISH;
		// Выводим признак отсутствия события
		return false;
	}
	// Получаем очередное событие разбора
	this->_current = this->_items[this->_head];
	// Убираем полученное событие из очереди выдачи
	this->_head++;
	/**
	 * Если выданы все собранные события
	 *
	 * @note Очередь очищается целиком, а выделенное под неё остаётся: перечень память
	 *       не освобождает, и следующая таблица разбирается уже без выделений
	 */
	if(this->_head >= this->_items.size()){
		// Очищаем очередь собранных событий разбора
		this->_items.clear();
		// Сбрасываем указание на первое невыданное событие
		this->_head = 0;
	}
	// Выводим признак наличия события
	return true;
}
/**
 * @brief Метод получения вида текущего события разбора
 *
 * @return вид текущего события разбора
 *
 */
awh::codec::csv::event_t awh::codec::csv::Reader::event() const noexcept {
	// Выводим вид текущего события разбора
	return this->_current.event;
}
/**
 * @brief Метод получения поля текущего события разбора
 *
 * @return поле текущего события разбора
 *
 */
awh::codec::csv::field_t awh::codec::csv::Reader::field() const noexcept {
	// Поле текущего события разбора
	field_t result;
	/**
	 * Если текущее событие содержимого не имеет
	 */
	if((this->_current.event == event_t::NONE) || (this->_current.event == event_t::FINISH) ||
	   (this->_current.event == event_t::RECORD))
		// Выводим поле без содержимого
		return result;
	// Запоминаем содержимое поля
	result.value = string_view(this->_storage.data() + this->_current.content.offset, this->_current.content.length);
	/**
	 * Если поле имеет имя в заголовке
	 */
	if(this->_current.name.length > 0)
		// Запоминаем имя поля, взятое из заголовка
		result.name = string_view(this->_names.data() + this->_current.name.offset, this->_current.name.length);
	// Запоминаем положение поля в исходном тексте
	result.location = this->_current.location;
	// Запоминаем признак заключения поля в кавычки
	result.quoted = this->_current.quoted;
	// Запоминаем признак изменения содержимого поля разбором
	result.modified = this->_current.modified;
	// Выводим поле текущего события разбора
	return result;
}
/**
 * @brief Метод получения положения текущего события разбора
 *
 * @return положение текущего события в исходном тексте
 *
 */
const awh::codec::csv::location_t & awh::codec::csv::Reader::location() const noexcept {
	/**
	 * Если разбор прекращён отказом
	 *
	 * @note Положение отказа хранится отдельно от положения события: последнее
	 *       событие выдано до отказа, и его положение указывало бы не туда
	 *
	 * @note Положение отказа выдаётся лишь тогда, когда события кончились: события,
	 *       отказу предшествующие, вправе оставаться в очереди выдачи и после него, и
	 *       прежде все они отчитывались местом отказа вместо собственного. Расхождение
	 *       это зависело от нарезки текста - при подаче кусками очередь опустошалась
	 *       до отказа, и события успевали выдать свои места верно
	 */
	if((this->_error != error_t::NONE) && (this->_current.event == event_t::NONE))
		// Выводим положение отказа в исходном тексте
		return this->_position;
	// Выводим положение текущего события в исходном тексте
	return this->_current.location;
}
