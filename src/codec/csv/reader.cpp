/**
 * @brief Метод получения знака-разделителя полей
 *
 * @return знак-разделитель полей
 *
 */
char awh::codec::csv::Reader::separator() const noexcept {
	// Выводим знак-разделитель полей, определённый или заданный
	return (this->_detected ? this->_separator : '\0');
}
/**
 * @brief Метод получения имён полей заголовка
 *
 * @return имена полей заголовка в порядке объявления
 *
 */
vector <string_view> awh::codec::csv::Reader::header() const noexcept {
	// Имена полей заголовка
	vector <string_view> result;
	// Резервируем память под имена полей заголовка
	result.reserve(this->_header.size());
	/**
	 * Выполняем перебор всех имён полей заголовка
	 */
	for(const span_t & name : this->_header)
		// Заносим имя поля заголовка
		result.emplace_back(this->_names.data() + name.offset, name.length);
	// Выводим имена полей заголовка
	return result;
}
