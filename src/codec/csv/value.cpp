/**
 * @brief Метод получения пустого значения общего пользования
 *
 * @return пустое значение общего пользования
 *
 */
const awh::codec::csv::Value & awh::codec::csv::Value::scrap() noexcept {
	/**
	 * @note Значение это заводится единожды за всё время работы и отдаётся всякому
	 *       промаху обращения. Заводить его при каждом промахе значило бы плодить
	 *       значения без счёта, а отдавать ссылку на местное - выдавать ссылку на
	 *       разрушенное
	 */
	static const Value result;
	// Выводим пустое значение общего пользования
	return result;
}
/**
 * @brief Метод установки объекта ведения журнала работы
 *
 * @param log объект ведения журнала работы
 *
 */
void awh::codec::csv::Value::setLogger(const log_t * log) noexcept {
	// Устанавливаем объект ведения журнала работы
	this->_log = log;
	/**
	 * Выполняем перебор всех вложенных значений
	 *
	 * @note Журнал уходит ВГЛУБЬ: значение владеет вложенными целиком, и сообщать о
	 *       бедах они обязаны туда же, куда и родитель
	 */
	for(auto & item : this->_items)
		// Выполняем установку объекта ведения журнала вложенному значению
		item.setLogger(log);
}
