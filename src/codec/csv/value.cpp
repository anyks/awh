/**
 * @brief Метод сохранения таблицы в файл
 *
 * @param filename адрес файла таблицы
 * @return         признак успешности сохранения
 *
 */
bool awh::codec::csv::Value::save(const string & filename) const noexcept {
	/**
	 * Выполняем сброс донесения о прежней работе
	 *
	 * @note Сброс КОДА здесь ничего не решает и стеречь его нечем: всякий путь дальше
	 *       либо ставит свой код сам, либо проходит через `dump()`, который сбрасывает
	 *       донесение заново. Замерено щупом по местам отказа 04.09.2026 - подмена
	 *       этого сброса не красила ни одной проверки, и молчание здесь ЗАКОННО
	 *
	 * @warning Сброс МЕСТА, напротив, живой, и снимать его нельзя: ветка неуказанного
	 *          имени файла ставит код и выходит, до `dump()` не дойдя, а место отказа
	 *          осталось бы от работы прежней - код новый при месте старом
	 *
	 * @note Пара оставлена целой намеренно: начало работы читается как сброс донесения,
	 *       и снятие половины ради опрятности сделало бы место темнее, а не чище
	 */
	this->_error = error_t::NONE;
	// Выполняем сброс места отказа прежней работы
	this->_errorLocation = location_t();
	/**
	 * Если адрес файла таблицы не указан
	 */
	if(filename.empty()){
		// Запоминаем код отказа сохранения таблицы
		this->_error = error_t::FILE_NOT_OPENED;
		// Выводим признак неудачного сохранения
		return false;
	}
	// Получаем собранный текст таблицы
	const string text = this->dump();
	/**
	 * Если сборка текста таблицы завершилась отказом
	 *
	 * @details Сохранение обязано СПРОСИТЬ итог сборки, а не полагаться на её текст:
	 *          отказ записи даёт текст пустой, и файл ушёл бы пустым при ответе об
	 *          успехе. Замерено 04.09.2026 - таблица с полем, несущим управляющий знак,
	 *          сохранялась успешно, оставляя на диске пустой файл ВМЕСТО прежнего
	 *
	 * @warning Порядок здесь важен: спрашивать надо ДО открытия временного файла. Спроси
	 *          мы после - целевой файл был бы уже подменён пустым, и отказ пришёл бы к
	 *          потребителю с уже потерянными данными
	 *
	 * @note Код отказа заново не ставится: `dump()` его уже выставил, и всякая правка
	 *       здесь лишь исказила бы причину, названную самой записью
	 */
	if(this->_error != error_t::NONE)
		// Выводим признак неудачного сохранения
		return false;
	/**
	 * @note Запись ведётся во ВРЕМЕННЫЙ файл рядом с целевым, а тот подменяется
	 *       переименованием - действием неделимым. Пиши мы прямо в целевой файл,
	 *       и первое же действие усекало бы его, а отказ на середине оставлял бы
	 *       потребителя без прежнего содержимого И без нового
	 *
	 * @note Временный файл кладётся РЯДОМ с целевым, а не во временный каталог
	 *       системы: переименование неделимо лишь в пределах одной файловой
	 *       системы, а каталог временных файлов может лежать на иной
	 */
	const string temporary = (filename + ".awh-tmp");
	// Объект файла для записи текста таблицы
	ofstream file(temporary, ios::binary | ios::trunc);
	/**
	 * Если файл для записи открыть не удалось
	 */
	if(!file.is_open()){
		// Запоминаем код отказа открытия файла таблицы
		this->_error = error_t::FILE_NOT_OPENED;
		// Выводим признак неудачного сохранения
		return false;
	}
	// Выполняем запись собранного текста таблицы
	file.write(text.data(), static_cast <streamsize> (text.size()));
	// Выполняем закрытие файла записи
	file.close();
	/**
	 * Если запись текста таблицы завершилась отказом
	 */
	if(!file.good()){
		// Выполняем снос временного файла записи
		::remove(temporary.c_str());
		// Запоминаем код отказа записи файла таблицы
		this->_error = error_t::FILE_NOT_WRITTEN;
		// Выводим признак неудачного сохранения
		return false;
	}
	/**
	 * Если подмена целевого файла временным завершилась отказом
	 */
	if(::rename(temporary.c_str(), filename.c_str()) != 0){
		// Выполняем снос временного файла записи
		::remove(temporary.c_str());
		// Запоминаем код отказа записи файла таблицы
		this->_error = error_t::FILE_NOT_WRITTEN;
		// Выводим признак неудачного сохранения
		return false;
	}
	// Выводим признак успешного сохранения
	return true;
}
/**
 * @brief Метод выдачи текста таблицы
 *
 * @return собранный текст таблицы
 *
 */
string awh::codec::csv::Value::dump() const noexcept {
	// Выполняем сброс кода отказа прежней работы
	this->_error = error_t::NONE;
	// Выполняем сброс места отказа прежней работы
	this->_errorLocation = location_t();
	// Объект таблицы для сборки текста
	Document document(this->_log);
	/**
	 * Если прививка значения к таблице завершилась отказом
	 *
	 * @note Без кода отказа пустой текст выдачи неотличим от значения пустого - ровно
	 *       та беда, ради которой канал донесения у значений и заведён
	 */
	if(!this->graft(document)){
		// Запоминаем код отказа выдачи текста таблицы
		/**
		 * @note Код взят тот же, каким отвечает выдача у владеющего значения JSON в
		 *       том же случае: своего кода на «значение таблицею не является» в
		 *       перечне нет, а заводить его ради одного места значило бы расширять
		 *       перечень, потребителю видимый, ради удобства своего
		 */
		this->_error = error_t::INTERNAL;
		// Выводим пустой текст таблицы
		return string();
	}
	// Собранный текст таблицы
	string result = document.dump();
	/**
	 * Если сборка текста таблицы завершилась отказом
	 *
	 * @details Прививка значения к таблице удалась, а САМА ЗАПИСЬ отказала - поле,
	 *          настройками записи непредставимое, знак, разбором не признаваемый.
	 *          Донесение об этом лежит у таблицы, и не переняв его, значение отвечало
	 *          бы ПУСТЫМ ТЕКСТОМ при коде «нет ошибки»
	 *
	 * @warning Беда эта тиха и оттого опасна: пустой текст неотличим от таблицы пустой,
	 *          и звучащий, итог не проверивший, записал бы в файл пустоту вместо
	 *          данных. Замерено щупом 04.09.2026 - значение с полем, несущим
	 *          управляющий знак, отдавало пустой текст с кодом `NONE`
	 *
	 * @note Найдено по наблюдению Генри у кодека CEF: там запись при отказе отдавала
	 *       ЧАСТИЧНО собранный текст, у меня - пустой, но причина одна и та же - итог
	 *       записи не проверялся вовсе
	 */
	if(document.error() != error_t::NONE){
		// Запоминаем код отказа, вынесенный сборкой текста таблицы
		this->_error = document.error();
		// Выводим пустой текст таблицы
		return string();
	}
	// Выводим собранный текст таблицы
	return result;
}
/**
 * @brief Оператор сличения значений
 *
 * @param value сличаемое значение
 * @return      признак равенства значений
 *
 */
bool awh::codec::csv::Value::operator == (const Value & value) const noexcept {
	/**
	 * Если виды сличаемых значений не совпадают
	 */
	if(this->_type != value._type)
		// Выводим признак неравенства значений
		return false;
	/**
	 * Если содержимое полей не совпадает
	 */
	if(this->_text.compare(value._text) != 0)
		// Выводим признак неравенства значений
		return false;
	/**
	 * Если имена столбцов таблиц не совпадают
	 */
	if(this->_header != value._header)
		// Выводим признак неравенства значений
		return false;
	// Выводим итог сличения вложенных значений
	return (this->_items == value._items);
}
/**
 * @brief Оператор сличения значений на неравенство
 *
 * @param value сличаемое значение
 * @return      признак неравенства значений
 *
 */
bool awh::codec::csv::Value::operator != (const Value & value) const noexcept {
	// Выводим обратное итогу сличения на равенство
	return !((* this) == value);
}
