/**
 * @brief Метод установки имён столбцов таблицы
 *
 * @param names имена столбцов таблицы
 * @return      признак успешности установки
 *
 */
bool awh::codec::csv::Value::header(const vector <string> & names) noexcept {
	/**
	 * Если хранимое значение таблицею не является
	 */
	if(this->_type != type_t::TABLE)
		// Выводим признак неудачной установки имён столбцов
		return false;
	/**
	 * Выполняем перебор всех подаваемых имён столбцов
	 *
	 * @note Повтор отвергается ВСЕГДА и настройкою не снимается: проверка здесь
	 *       свободна от расхода на разбор, ради которого послабление и заводят,
	 *       а столбец, по имени недостижимый, молчал бы. Уклад этот один с
	 *       `Document::header`
	 */
	for(size_t i = 0; i < names.size(); i++){
		/**
		 * Выполняем перебор имён, поданных прежде очередного
		 */
		for(size_t j = 0; j < i; j++){
			/**
			 * Если имя столбца повторяется
			 */
			if(names[j] == names[i])
				// Выводим признак неудачной установки имён столбцов
				return false;
		}
	}
	// Выполняем установку имён столбцов таблицы
	this->_header = names;
	// Выводим признак успешной установки имён столбцов
	return true;
}
/**
 * @brief Метод проверки наличия столбца с указанным именем
 *
 * @param name имя столбца
 * @return     признак наличия столбца
 *
 */
bool awh::codec::csv::Value::contains(const string & name) const noexcept {
	// Выводим признак того, что номер столбца найден
	return (this->column(name) != SIZE_MAX);
}
/**
 * @brief Метод поиска номера столбца по имени
 *
 * @param name имя столбца
 * @return     номер столбца, `SIZE_MAX` при отсутствии
 *
 */
size_t awh::codec::csv::Value::column(const string & name) const noexcept {
	/**
	 * Выполняем перебор всех имён столбцов таблицы
	 */
	for(size_t i = 0; i < this->_header.size(); i++){
		/**
		 * Если имя столбца совпадает с искомым
		 */
		if(this->_header[i] == name)
			// Выводим номер найденного столбца
			return i;
	}
	// Выводим признак отсутствия столбца с искомым именем
	return SIZE_MAX;
}
/**
 * @brief Метод обращения к вложенному значению по номеру
 *
 * @param index номер вложенного значения
 * @return      вложенное значение
 *
 */
const awh::codec::csv::Value & awh::codec::csv::Value::operator [] (const size_t index) const noexcept {
	/**
	 * Если номер вложенного значения выходит за пределы перечня
	 */
	if(index >= this->_items.size())
		// Выводим пустое значение общего пользования
		return Value::scrap();
	// Выводим искомое вложенное значение
	return this->_items[index];
}
/**
 * @brief Метод обращения к полю записи по имени столбца
 *
 * @param name имя столбца
 * @return     поле записи
 *
 */
const awh::codec::csv::Value & awh::codec::csv::Value::operator [] (const string & name) const noexcept {
	// Получаем номер столбца по его имени
	const size_t index = this->column(name);
	/**
	 * Если столбец с искомым именем не найден
	 */
	if(index == SIZE_MAX)
		// Выводим пустое значение общего пользования
		return Value::scrap();
	// Выводим поле записи по номеру найденного столбца
	return (* this)[index];
}
/**
 * @brief Метод обращения к значению по пути
 *
 * @param path путь к искомому значению
 * @return     найденное значение
 *
 */
const awh::codec::csv::Value & awh::codec::csv::Value::at(const string & path) const noexcept {
	/**
	 * Если путь пуст, обход ведёт к самому значению
	 *
	 * @note Пустой путь и одиночная косая черта здесь РАЗНЫЕ, и это не мелочь записи:
	 *       по RFC 6901 пустой путь означает весь документ, а «/» - звено с ПУСТЫМ
	 *       именем. Документ JSON так и отвечает, разметка тоже, и приравняй мы их
	 *       у таблицы - одна и та же запись пути значила бы у кодеков разное
	 *
	 * @note У таблицы столбца с пустым именем не бывает вовсе - заголовок такой
	 *       отвергается кодом `EMPTY_HEADER`, - оттого «/» ведёт в никуда всегда.
	 *       Итог тот же, что у документа без поля с пустым именем
	 */
	if(path.empty())
		// Выводим само хранимое значение
		return (* this);
	// Текущее значение обхода пути
	const Value * current = this;
	// Положение начала очередного звена пути
	size_t offset = ((path.front() == '/') ? 1 : 0);
	/**
	 * Выполняем обход всех звеньев поданного пути
	 */
	while(offset <= path.size()){
		// Выполняем поиск конца очередного звена пути
		size_t finish = path.find('/', offset);
		/**
		 * Если разделителя более нет, звено тянется до конца пути
		 */
		if(finish == string::npos)
			// Запоминаем концом звена конец всего пути
			finish = path.size();
		// Получаем очередное звено пути
		string item = path.substr(offset, finish - offset);
		/**
		 * Выполняем снятие отменяющих записей со звена пути
		 *
		 * @details Имя столбца таблицы содержать может ЧТО УГОДНО - RFC 4180 знаков
		 *          имени не ограничивает вовсе, - а разделителем звеньев пути служит
		 *          косая черта. Столбец, косую черту в имени несущий, был недостижим
		 *          путём НИКАК: звено рвалось надвое, и обе половины искались порознь
		 *
		 * @note Записи взяты из RFC 6901 и те же, что у указателя JSON: `~1` означает
		 *       косую черту, `~0` - саму тильду. Ось путей у кодеков общая, и заводить
		 *       здесь свой уклад значило бы разводить кодеки на ровном месте
		 *
		 * @warning Порядок снятия предписан стандартом и обратным быть не может: сними
		 *          мы `~0` прежде `~1`, и записанное `~01` обратилось бы в косую черту
		 *          вместо `~1`. Уклад этот дословно повторяет разбор указателя JSON
		 *
		 * @note Найдено по наблюдению Гоши, замерившего то же у оси путей ABC: имя с
		 *       тильдой разыскивалось дословно, а имя с косой чертой не разыскивалось
		 *       никак. У разметки XML беды этой нет и записи эти не нужны: имя узла
		 *       косой черты не допускает по самому стандарту XML
		 */
		if(item.find('~') != string::npos){
			/**
			 * @brief Метод снятия одной отменяющей записи со звена пути
			 *
			 * @param text   звено пути, отменяющие записи несущее
			 * @param escape снимаемая отменяющая запись
			 * @param letter знак, отменяющей записью означенный
			 *
			 * @warning Место продолжения розыска обязано сдвигаться ЗА поставленный
			 *          знак, а не оставаться на нём: снятие `~0` у записанного `~001`
			 *          даёт `~01`, и розыск, с того же места продолженный, снял бы
			 *          записанное ПОВТОРНО, обратив итог в `~1`. Замерено проверкой
			 *          порядка - половина эта одна и покраснела
			 */
			const auto unescape = [](string & text, const char * escape, const char letter) noexcept -> void {
				// Место продолжения розыска отменяющей записи
				size_t position = 0;
				/**
				 * Выполняем перебор всех отменяющих записей звена пути
				 */
				while((position = text.find(escape, position)) != string::npos){
					// Выполняем замену отменяющей записи означенным знаком
					text.replace(position, 2, 1, letter);
					// Выполняем сдвиг места розыска ЗА поставленный знак
					position++;
				}
			};
			// Выполняем снятие отменяющей записи косой черты
			unescape(item, "~1", '/');
			// Выполняем снятие отменяющей записи самой тильды
			unescape(item, "~0", '~');
		}
		/**
		 * Если звено пути пусто
		 */
		if(item.empty())
			// Выводим пустое значение общего пользования
			return Value::scrap();
		// Признак того, что звено является числом
		bool numeric = true;
		/**
		 * Выполняем перебор всех знаков звена пути
		 */
		for(const char letter : item){
			/**
			 * Если знак звена цифрою не является
			 */
			if((letter < '0') || (letter > '9')){
				// Снимаем признак числового звена пути
				numeric = false;
				// Выходим из перебора знаков звена
				break;
			}
		}
		/**
		 * Если звено пути является числом
		 */
		if(numeric)
			// Выполняем переход к вложенному значению по номеру
			current = &(* current)[static_cast <size_t> (::stoull(item))];
		/**
		 * Если звено пути является именем столбца
		 *
		 * @note Имена столбцов принадлежат ТАБЛИЦЕ, а запись их не знает - оттого
		 *       сличение имени ведётся у ТОГО значения, у которого заголовок есть,
		 *       а спуск по нему идёт к вложенному значению текущего
		 */
		else {
			// Получаем номер столбца по имени звена у самого значения
			const size_t index = this->column(item);
			/**
			 * Если столбец с искомым именем не найден
			 */
			if(index == SIZE_MAX)
				// Выводим пустое значение общего пользования
				return Value::scrap();
			// Выполняем переход к вложенному значению по номеру столбца
			current = &(* current)[index];
		}
		/**
		 * Если значение обхода пригодным не является
		 */
		if(!current->valid())
			// Выводим пустое значение общего пользования
			return Value::scrap();
		// Выполняем переход к началу следующего звена пути
		offset = (finish + 1);
	}
	// Выводим найденное значение
	return (* current);
}
/**
 * @brief Метод добавления записи в таблицу
 *
 * @param value добавляемое значение
 * @return      признак успешности добавления
 *
 */
bool awh::codec::csv::Value::push(const Value & value) noexcept {
	/**
	 * Если хранимое значение перечнем не является
	 */
	if((this->_type != type_t::TABLE) && (this->_type != type_t::RECORD))
		// Выводим признак неудачного добавления
		return false;
	/**
	 * Если добавляемое значение пригодным не является
	 */
	if(!value.valid())
		// Выводим признак неудачного добавления
		return false;
	// Выполняем добавление значения в перечень
	this->_items.push_back(value);
	// Выводим признак успешного добавления
	return true;
}
/**
 * @brief Метод удаления вложенного значения по номеру
 *
 * @param index номер удаляемого значения
 * @return      признак успешности удаления
 *
 */
bool awh::codec::csv::Value::erase(const size_t index) noexcept {
	/**
	 * Если номер удаляемого значения выходит за пределы перечня
	 */
	if(index >= this->_items.size())
		// Выводим признак неудачного удаления
		return false;
	// Выполняем удаление вложенного значения по его номеру
	this->_items.erase(this->_items.begin() + static_cast <long> (index));
	// Выводим признак успешного удаления
	return true;
}
/**
 * @brief Метод извлечения логического значения поля
 *
 * @param result извлекаемое значение
 * @return       признак успешности извлечения
 *
 */
bool awh::codec::csv::Value::value(bool & result) const noexcept {
	/**
	 * Если хранимое значение полем не является
	 */
	if(this->_type != type_t::FIELD)
		// Выводим признак неудачного извлечения
		return false;
	/**
	 * Если содержимое поля означает истину
	 */
	if((this->_text.compare("true") == 0) || (this->_text.compare("1") == 0)){
		// Запоминаем извлечённое значение
		result = true;
		// Выводим признак успешного извлечения
		return true;
	}
	/**
	 * Если содержимое поля означает ложь
	 */
	if((this->_text.compare("false") == 0) || (this->_text.compare("0") == 0)){
		// Запоминаем извлечённое значение
		result = false;
		// Выводим признак успешного извлечения
		return true;
	}
	// Выводим признак неудачного извлечения
	return false;
}
/**
 * @brief Метод извлечения числового значения поля
 *
 * @tparam T     вид числа, к какому ведётся извлечение
 * @param result извлекаемое значение
 * @return       признак успешности извлечения
 *
 */
template <typename T>
bool awh::codec::csv::Value::extract(T & result) const noexcept {
	/**
	 * Если хранимое значение полем не является либо пусто
	 */
	if((this->_type != type_t::FIELD) || this->_text.empty())
		// Выводим признак неудачного извлечения
		return false;
	/**
	 * Выполняем перехват исключений разбора записи числа
	 */
	try {
		// Положение конца разобранной записи числа
		size_t offset = 0;
		/**
		 * @note Разбор ведётся сперва ЦЕЛЫМ, и лишь при неудаче дробным: целое,
		 *       разобранное дробным, теряло бы точность у больших чисел, ибо
		 *       дробное двойной точности хранит верно лишь 53 разряда
		 */
		{
			// Выполняем перехват исключений разбора записи целого числа
			try {
				// Выполняем разбор записи целого числа
				const long long number = ::stoll(this->_text, &offset);
				/**
				 * Если запись разобрана целиком
				 */
				if(offset == this->_text.size()){
					/**
					 * @note Сужение ведётся приведением ЯЗЫКА: целое, в затребованный вид
					 *       не помещающееся, заворачивается по кругу. Уклад этот взят у
					 *       кодеков JSON и XML слово в слово
					 */
					result = static_cast <T> (number);
					// Выводим признак успешного извлечения
					return true;
				}
			/**
			 * Если разбор записи целого числа завершился исключением
			 */
			} catch(const exception &) {
				// Продолжаем разбором записи дробного числа
			}
		}
		// Выполняем сброс положения конца разобранной записи
		offset = 0;
		// Выполняем разбор записи дробного числа
		const double number = ::stod(this->_text, &offset);
		/**
		 * Если запись разобрана не целиком
		 */
		if(offset != this->_text.size())
			// Выводим признак неудачного извлечения
			return false;
		/**
		 * @note Приведение дробного ведётся ОБЩИМ ходом рамки: дробное, целая часть
		 *       которого лежит за пределами вида, выдаётся пределом этого вида, ибо
		 *       у языка там поведение неопределено. Пиши мы своё приведение, и
		 *       расхождение вышло бы у краёв вида - там, где его никто не ищет
		 */
		result = awh::codec::convert <T> (number);
		// Выводим признак успешного извлечения
		return true;
	/**
	 * Если разбор записи числа завершился исключением
	 */
	} catch(const exception &) {
		// Выводим признак неудачного извлечения
		return false;
	}
}
