/**
 * @brief Метод записи примечания
 *
 * @param text содержимое записываемого примечания
 * @return     результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::comment(const string_view text) noexcept {
	/**
	 * Если предыдущая операция записи завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем сброс признака записанного свойства
	this->_valued = false;
	// Выполняем ограждение примечания, оканчивающегося продолжением
	this->guard(false);
	// Положение начала очередной строки примечания
	size_t offset = 0;
	/**
	 * Выполняем перебор всех строк примечания
	 */
	while(true){
		// Получаем положение конца очередной строки примечания
		size_t position = text.find('\n', offset);
		/**
		 * Если знак конца строки примечания не обнаружен
		 */
		if(position == string_view::npos)
			// Запоминаем положение конца примечания
			position = text.length();
		// Получаем содержимое очередной строки примечания
		string_view line = text.substr(offset, position - offset);
		/**
		 * Если строка примечания оканчивается возвратом каретки
		 */
		if(!line.empty() && (line.back() == '\r'))
			// Выполняем отбрасывание возврата каретки
			line = line.substr(0, line.length() - 1);
		// Выполняем запись знака начала примечания
		this->_text.push_back(this->_settings.marker);
		/**
		 * Если содержимое строки примечания не пусто
		 */
		if(!line.empty()){
			// Выполняем запись пробела за знаком начала примечания
			this->_text.push_back(' ');
			// Выполняем запись содержимого строки примечания
			this->_text.append(line);
		}
		// Выполняем запись знака конца строки
		this->newline();
		/**
		 * Запоминаем, оканчивается ли записанная строка примечания продолжением
		 *
		 * @note Признак взводится по каждой строке, а держится по последней: склеить
		 *       со следующей строкой читающий может лишь её одну
		 */
		this->_guarded = (this->_settings.continuations && ::continued(line));
		/**
		 * Если примечание записано целиком
		 */
		if(position >= text.length())
			// Выполняем прекращение записи примечания
			break;
		// Выполняем переход к следующей строке примечания
		offset = (position + 1);
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод дописывания примечания к последней записанной строке
 *
 * @param text содержимое дописываемого примечания
 * @return     результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::trailing(const string_view text) noexcept {
	/**
	 * Если предыдущая операция записи завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Выполняем сброс ожидающего ограждения примечания
	 *
	 * @note Примечание дописывается к готовой строке, и продолжение прежней строки
	 *       оказывается уже не в её конце: ограждать нечего
	 */
	/**
	 * Если примечание к готовой строке дописать нельзя
	 *
	 * @note Читающий, примечания в конце строки не признающий, дописанное возьмёт
	 *       частью значения свойства либо отвергнет как содержимое за объявлением
	 *       раздела. А признающий отделяет примечание пробелом, и пробел этот
	 *       читающему, пробельной обвязки не отбрасывающему, достаётся частью значения:
	 *       оно росло бы пробелом при каждом обороте «чтение - запись». Примечание
	 *       уходит в обоих случаях отдельной строкой - место его украшение, а значение
	 *       записано потребителем
	 */
	if(!this->_settings.inlineComments || (!this->_settings.trim && this->_valued))
		// Выполняем запись примечания отдельной строкой
		return this->comment(text);
	this->_guarded = false;
	/**
	 * Выполняем перебор знаков содержимого примечания
	 */
	for(size_t i = 0; i < text.length(); i++){
		/**
		 * Если знаком содержимого является знак конца строки
		 *
		 * @note Примечание это дописывается к готовой строке, и знак конца строки в
		 *       нём разорвал бы её надвое: остаток ушёл бы отдельной строкой, которую
		 *       читающий примечанием уже не сочтёт
		 */
		if((text[i] == '\n') || (text[i] == '\r')){
			// Запоминаем код ошибки записи
			this->_error = error_t::INVALID_CHARACTER;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	}
	// Получаем последовательность знаков конца строки
	/**
	 * Получаем последовательность знаков конца строки, ПОСЛЕДНЕЙ записью применённую
	 *
	 * @warning Спрашивается здесь именно применённое, а не настройка: настройка вправе
	 *          смениться между записью строки и допиской к ней. Замерено щупом - при
	 *          смене разметки с CRLF на LF дописка снимала один перевод строки из двух
	 *          знаков и оставляла одинокий возврат каретки ПОСРЕДИ строки, отвечая при
	 *          том успехом; обратная смена давала отказ кодом INTERNAL
	 */
	const string_view newline = awh::codec::ini::newline(this->_written);
	/**
	 * Если записанного текста для дописывания примечания недостаточно
	 *
	 * @details Примечание это дописывается к строке уже записанной, и у записи, ничего
	 *          ещё не собравшей, дописывать его некуда. Отказ этот есть ошибка
	 *          потребителя, а не изъян записи, и кодом ему отвечает содержимое не на
	 *          своём месте
	 *
	 * @warning Прежде отвечал он кодом INTERNAL, и это было неверно вдвойне: во-первых,
	 *          INTERNAL означает изъян самой записи, а тут ничего не сломано; во-вторых,
	 *          TOML и YAML на том же входе отвечают UNEXPECTED_CONTENT, и расхождение
	 *          уводило потребителя в сторону. Замерено щупом на трёх кодеках разом,
	 *          сведено решением владельца о единообразии кодеков
	 */
	if(this->_text.length() < newline.length()){
		// Запоминаем код ошибки записи
		this->_error = error_t::UNEXPECTED_CONTENT;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если записанный текст знаком конца строки не оканчивается
	 *
	 * @warning Заход этот НЕДОСТИЖИМ входными данными: всякое тело записи оканчивает
	 *          собранный текст знаком конца строки, а дописка примечания, знак этот
	 *          снявшая, ставит его обратно. Замерено: дописка к строке, дописку уже
	 *          несущую, сюда не заходит
	 *
	 * @warning Прежний довод недостижимости был НЕВЕРЕН, и вот чем. Он не учитывал смены
	 *          настроек между записью строки и допиской к ней: разметка, сменённая с LF
	 *          на CRLF, приводила сюда - снимаемая последовательность бралась из настроек
	 *          НЫНЕШНИХ, а текст был записан прежними. Ныне снимается то, что на деле
	 *          записано, и заход недостижим уже по-настоящему. Довод «о написанном нельзя
	 *          судить по настройке» принесён Василием от кодека JSON
	 *
	 * @note Код INTERNAL здесь ВЕРЕН, в отличие от захода выше: недостача знака конца
	 *       строки при непустом тексте означала бы, что тело записи своего договора не
	 *       исполнило, - это и есть изъян самой записи
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа. Правка любого
	 *       тела записи, оставившая текст без знака конца строки, вернёт сюда управление,
	 *       и примечание легло бы посреди чужой строки
	 */
	if(this->_text.compare(this->_text.length() - newline.length(), newline.length(), newline) != 0){
		// Запоминаем код ошибки записи
		this->_error = error_t::INTERNAL;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Выполняем снятие знака конца строки с записанного текста
	 *
	 * @note Примечание дописывается к строке, которая уже закрыта: снять знак её
	 *       конца и поставить его заново дешевле, чем откладывать закрытие всякой
	 *       строки в ожидании примечания, которого чаще всего не будет
	 */
	this->_text.resize(this->_text.length() - newline.length());
	/**
	 * Если читающий отбрасывает пробельную обвязку значения либо строка окончена
	 * объявлением раздела
	 *
	 * @note Пробел этот украшающий, и сохраняющему обвязку читающему он достался бы
	 *       частью значения предыдущего свойства: значение росло бы пробелом при каждом
	 *       обороте «чтение - запись». Украшение уступает сохранности записанного
	 *
	 * @note За объявлением же раздела значения нет вовсе, и довод этот к нему не
	 *       относится, а пробел ему НЕОБХОДИМ: читающий, требующий пробела перед знаком
	 *       примечания, без него примечания не признает и заберёт его себе в имя
	 *       раздела - тем вернее, что закрывающая скобка ищется им до последней в строке
	 */
	if(this->_settings.trim || !this->_valued)
		// Выполняем запись пробела перед знаком начала примечания
		this->_text.push_back(' ');
	// Выполняем запись знака начала примечания
	this->_text.push_back(this->_settings.marker);
	/**
	 * Если содержимое примечания не пусто
	 */
	if(!text.empty()){
		// Выполняем запись пробела за знаком начала примечания
		this->_text.push_back(' ');
		// Выполняем запись содержимого примечания
		this->_text.append(text);
	}
	/**
	 * Запоминаем, оканчивается ли дописанное примечание продолжением
	 *
	 * @note Дописанное примечание завершает строку наравне с записанным отдельно, и
	 *       склеивание со следующей строкой грозит ей точно так же
	 */
	this->_guarded = (this->_settings.continuations && ::continued(text));
	// Выполняем запись знака конца строки
	this->newline();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи пустой строки
 *
 * @return результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::blank() noexcept {
	/**
	 * Если предыдущая операция записи завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем сброс признака записанного свойства
	this->_valued = false;
	// Выполняем ограждение примечания, оканчивающегося продолжением
	this->guard(true);
	// Выполняем запись знака конца строки
	this->newline();
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод получения кода ошибки записи
 *
 * @return код ошибки последней операции записи
 *
 */
awh::codec::ini::error_t awh::codec::ini::Writer::error() const noexcept {
	// Выводим код ошибки последней операции записи
	return this->_error;
}
/**
 * @brief Метод получения собранного текста настроек
 *
 * @return собранный текст настроек
 *
 */
const string & awh::codec::ini::Writer::text() const noexcept {
	// Выводим собранный текст настроек
	return this->_text;
}
/**
 * @brief Метод сброса записи в исходное состояние
 *
 */
void awh::codec::ini::Writer::clear() noexcept {
	// Выполняем сброс кода ошибки записи
	this->_error = error_t::NONE;
	// Выполняем сброс признака объявления раздела
	this->_sectioned = false;
	// Выполняем сброс признака записанного свойства
	this->_valued = false;
	// Выполняем сброс признака ожидающего ограждения примечания
	this->_guarded = false;
	// Выполняем очистку собранного текста настроек
	this->_text.clear();
}
/**
 * @brief Метод вывода сообщения об отказе в лог
 *
 */
void awh::codec::ini::Writer::report() const noexcept {
	/**
	 * Если объект для работы с логами установлен
	 */
	if(this->_log != nullptr)
		// Выполняем вывод сообщения об отказе
		this->_log->print("INI writing failed: %s", log_t::flag_t::CRITICAL, awh::codec::ini::message(this->_error));
}
