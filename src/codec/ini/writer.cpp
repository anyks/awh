/**
 * @brief Шаблон типа записываемого числа
 *
 * @tparam T тип записываемого числа
 *
 */
template <typename T>
/**
 * @brief Метод записи свойства с числовым значением
 *
 * @param key   имя записываемого свойства
 * @param value значение записываемого свойства
 * @return      результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::number(const string_view key, const T value) noexcept {
	// Хранилище записи числового значения свойства
	char buffer[64];
	// Длина записи числового значения свойства
	int32_t length = 0;
	/**
	 * Если записывается логическое значение
	 *
	 * @note Сличение ведётся прежде целых чисел намеренно: логический тип языком
	 *       причислен к целым, и без этого истина записалась бы единицей
	 */
	if constexpr(is_same <T, bool>::value)
		// Выполняем запись свойства с логическим значением
		return this->property(key, (value ? "true" : "false"));
	/**
	 * Если записывается число с плавающей точкой
	 */
	else if constexpr(is_floating_point <T>::value){
		/**
		 * Выполняем запись числа с плавающей точкой кратчайшим обратимым представлением
		 *
		 * @note Подбор точности с обратным чтением каждой пробы более не нужен: модуль
		 *       разбора чисел вычисляет количество значащих цифр сразу, отчего запись
		 *       «0.1» выходит как «0.1», а не как «0.10000000000000001»
		 *
		 * @note Выбор между обычным и показательным видом делает сам модуль по длине
		 *       записи и при равной длине берёт обычный вид - правило это совпадает с
		 *       прежним подбором: «1250» берётся вместо «1.25e+03», а «1e+20» остаётся
		 *       показательным, поскольку обычный вид его непомерно длинен. Файл настроек
		 *       пишется для человека, и обычный вид ему понятнее
		 *
		 * @note Подмена знака десятичной точки локали точкой более не нужна: запись
		 *       ведётся по правилам местности «C» и от настроек приложения не зависит
		 */
		const awh::lexical::output_t <char> output = awh::lexical_t::toChars(
			buffer, buffer + sizeof(buffer),
			/**
			 * Запись ведётся числом его собственного типа: кратчайшая запись
			 * зависит от разрядности мантиссы, и приведение float к double дало бы
			 * «0.10000000149011612» вместо «0.1». Тип long double модулем не
			 * поддержан и приводится к double, как это делалось и прежде
			 */
			static_cast <typename conditional <is_same <T, float>::value, float, double>::type> (value)
		);
		// Определяем длину записи числа с плавающей точкой
		length = (static_cast <bool> (output) ? static_cast <int32_t> (output.ptr - buffer) : 0);
	}
	/**
	 * Если записывается целое число без знака
	 */
	else if constexpr(is_unsigned <T>::value)
		// Выполняем запись целого числа без знака
		length = ::snprintf(buffer, sizeof(buffer), "%llu", static_cast <unsigned long long> (value));
	/**
	 * Если записывается целое число со знаком
	 */
	else length = ::snprintf(buffer, sizeof(buffer), "%lld", static_cast <long long> (value));
	/**
	 * Если запись числового значения выполнить не удалось
	 *
	 * @warning Заход этот НЕДОСТИЖИМ входными данными: накопитель отведён с запасом на
	 *          самую длинную запись всякого числового вида, какой договор принимает, и
	 *          усечения быть не может. Доказано срывом, в заход поставленным
	 *
	 * @note Сносу заход не подлежит: он есть застава последнего рубежа. Расширение
	 *       договора новым числовым видом либо укорочение накопителя вернёт сюда
	 *       управление, и усечённое число легло бы в текст молча
	 */
	if((length <= 0) || (static_cast <size_t> (length) >= sizeof(buffer))){
		// Запоминаем код ошибки записи
		this->_error = error_t::INTERNAL;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем запись свойства с числовым значением
	return this->property(key, string_view(buffer, static_cast <size_t> (length)));
}

