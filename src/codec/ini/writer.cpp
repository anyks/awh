/**
 * @brief Метод получения настроек наречия настроек Git
 *
 * @return настройки записи наречия Git
 *
 */
awh::codec::ini::Writer::Settings awh::codec::ini::Writer::Settings::git() noexcept {
	// Собираемые настройки записи текста настроек
	Settings result;
	// Устанавливаем знак начала примечания
	result.marker = '#';
	// Устанавливаем обращение с ограждением значения кавычками
	result.quoting = quoting_t::AUTO;
	/**
	 * Устанавливаем признание обоих построений имени подраздела
	 *
	 * @details Записывает наречие Git подраздел кавычками, и потому стояло здесь прежде
	 *          построение QUOTED. Читающий же наречия того признаёт ОБА построения, и
	 *          расхождение это выходило боком: знак-разделитель в имени раздела запись
	 *          дозволяла, а обратное чтение резало по нему имя. Раздел `.ab.c.d`
	 *          записывался как есть, а прочитывался разделом пустым - отказом
	 *          «empty section name»
	 *
	 * @note Записи признак этот не меняет: тело сборки объявления раздела обращает
	 *       BOTH в QUOTED само. Меняет он одну лишь проверку имени, и та отвергает
	 *       теперь имя со знаком-разделителем - явным отказом вместо текста, своим же
	 *       чтением не читаемого. Нашёл это ворошитель круговым ходом перевода наречий
	 */
	result.subsections = subsection_t::BOTH;
	// Устанавливаем признание свойства без значения читающим
	result.valueless = true;
	// Устанавливаем запрет свойств, объявленных до первого раздела
	result.global = false;
	// Устанавливаем признание примечания в конце строки читающим
	result.inlineComments = true;
	// Устанавливаем запись управляющих последовательностей в значении
	result.escapes = true;
	// Устанавливаем запись отступа перед свойствами раздела
	result.indent = true;
	// Устанавливаем склеивание строк, продолженных обратной косой чертой, читающим
	result.continuations = true;
	// Выводим собранные настройки записи
	return result;
}
/**
 * @brief Метод проверки имени раздела или свойства
 *
 * @param name    проверяемое имя раздела или свойства
 * @param section признак проверки имени раздела
 * @return        результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::verify(const string_view name, const bool section) noexcept {
	/**
	 * Если имя раздела или свойства пусто
	 */
	if(name.empty()){
		// Запоминаем код ошибки записи
		this->_error = (section ? error_t::EMPTY_SECTION : error_t::EMPTY_KEY);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если длина имени предел настроек превышает
	 */
	if((this->_settings.maxName > 0) && (name.length() > this->_settings.maxName)){
		// Запоминаем код ошибки записи
		this->_error = error_t::NAME_TOO_LONG;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если имя раздела или свойства несёт пробельную обвязку
	 *
	 * @note Обвязка эта при чтении отбрасывается, и записанное имя разошлось бы с
	 *       прочитанным: отвергнуть её лучше, чем молча потерять
	 *
	 * @note Имя раздела поверяется лишь при `trimSections`: читающий, обвязку
	 *       сохраняющий, прочтёт имя как записано, и отвергать его не за что. Таково
	 *       наречие python - у него `[ раздел ]` есть имя с пробелами, - и круг
	 *       «чтение - запись» на нём рвался: разбор текст принимал, а запись дерево
	 *       отвергала. Нашло это сличение перезаписи с эталоном
	 */
	if((section ? this->_settings.trimSections : true) &&
	   (ascii::isSpace(name.front()) || ascii::isSpace(name.back()))){
		// Запоминаем код ошибки записи
		this->_error = (section ? error_t::INVALID_SECTION : error_t::INVALID_KEY);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если имя оканчивается обратной косой чертой, склеивающей строки при чтении
	 *
	 * @note Имена управляющими последовательностями не записываются, и оградить
	 *       такую черту нечем: читающий слил бы имя со следующей строкой
	 */
	if(this->_settings.continuations && ::continued(name)){
		// Запоминаем код ошибки записи
		this->_error = (section ? error_t::INVALID_SECTION : error_t::INVALID_KEY);
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Выполняем перебор всех знаков имени
	 */
	for(size_t i = 0; i < name.length(); i++){
		/**
		 * Получаем признак недопустимости очередного знака имени
		 *
		 * @note Знак примечания недопустим лишь первым знаком имени свойства: там он
		 *       обращает всю строку в примечание. Внутри имени, равно как и в имени
		 *       раздела, он значащим не является - имя раздела стоит в квадратных
		 *       скобках, а имя свойства читается до разделителя
		 */
		bool invalid = ((name[i] == '\n') || (name[i] == '\r') ||
		                (!section && (i == 0) && commented(name[i], this->_settings.comments)));
		/**
		 * Если читающий признаёт примечание в конце строки
		 *
		 * @details Тогда знак примечания значащ и внутри имени: читающий обрывает им и
		 *          имя свойства, и объявление раздела. Имя «k ; заметка» записывалось как
		 *          есть, а обратный разбор давал свойство «k» с примечанием - значение
		 *          пропадало; имя раздела с таким знаком обращало объявление в незакрытое.
		 *          Оградить знак нечем: имена управляющими последовательностями не
		 *          записываются, а кавычками имя свойства не защищается
		 *
		 * @note Требование то же, что и у читающего: примечанием знак признаётся, лишь
		 *       когда стоит первым либо отделён пробельным знаком. Имя «k;заметка»
		 *       записывается и читается обратно без потерь, и отвергать его незачем
		 */
		if(this->_settings.inlineComments && commented(name[i], this->_settings.comments) &&
		   ((i == 0) || ascii::isSpace(name[i - 1])))
			// Дополняем признак недопустимости знаком начала примечания
			invalid = true;
		/**
		 * Если проверяется имя раздела
		 */
		if(section){
			/**
			 * Дополняем признак недопустимости знаками квадратных скобок и кавычки
			 *
			 * @note Скобки поверяются толкованием читающего: читающий жадный берёт имя до
			 *       ПОСЛЕДНЕЙ скобки в строке, и «[x[]]» есть ему имя «x[]» - записанное
			 *       имя с прочитанным совпадает, и отвергать его не за что. Круг «чтение -
			 *       запись» на нём рвался: наречие python текст принимало, а запись дерево
			 *       отвергала пустотой
			 *
			 * @note Запрет снимается со скобок ОБЕИХ и на любом месте имени, первое
			 *       включая: жадный розыск доводит имя до последней скобки строки, и
			 *       объявление «[[a]]» есть ему имя «[a]». Проверено кругом «правка -
			 *       запись - чтение» на именах «x[]», «[a», «[a]», «a]», «]a[» и «a[b»:
			 *       все шесть возвращаются знак в знак. Оговорка о недопустимости
			 *       открывающей скобки первым знаком стояла здесь догадкою и снята
			 *       замером
			 */
			invalid = (invalid || (name[i] == '"') ||
			 (!this->_settings.greedySections && ((name[i] == '[') || (name[i] == ']'))));
			/**
			 * Если подраздел отделяется знаком-разделителем
			 *
			 * @note Знак этот в имени раздела недопустим: читающий режет имя по первому
			 *       его появлению, и запись «[a.b]» с именем раздела «a.b» прочиталась
			 *       бы разделом «a» с подразделом «b»
			 */
			if((static_cast <uint8_t> (this->_settings.subsections) &
			    static_cast <uint8_t> (subsection_t::DELIMITED)) != 0)
				// Дополняем признак недопустимости знаком-разделителем имени подраздела
				invalid = (invalid || (name[i] == this->_settings.delimiter));
		}
		/**
		 * Если проверяется имя свойства
		 *
		 * @note Скобки поверяются лишь при записи перечней: читающий, перечни признающий,
		 *       числит «имя[]» добавлением к перечню, и имя со скобками разошлось бы с
		 *       прочитанным. Читающий же, перечней не знающий, прочтёт имя как записано -
		 *       отвергать его не за что, а круг «чтение - запись» на нём рвался: разбор
		 *       текст принимал, а запись дерево отвергала пустотой
		 */
		else invalid = (invalid || (name[i] == this->_settings.separator) ||
		 (this->_settings.arrays && ((name[i] == '[') || (name[i] == ']'))));
		/**
		 * Если очередной знак имени недопустим
		 */
		if(invalid){
			// Запоминаем код ошибки записи
			this->_error = (section ? error_t::INVALID_SECTION : error_t::INVALID_KEY);
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим отрицательный результат выполнения операции
			return false;
		}
	}
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи значения свойства
 *
 * @param value записываемое значение свойства
 * @return      результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::escape(const string_view value) noexcept {
	/**
	 * Получаем признак нужды в ограждении значения кавычками
	 *
	 * @note Толкование кавычек берётся у читающего, а не у собственной настройки
	 *       ограждения: запись, кавычек не ставящая, читающему их снимать не запрещает,
	 *       и значение, кавычкой начинающееся, досталось бы ему без неё
	 */
	const bool needed = ::quotable(value, this->_settings.comments, this->_settings.inlineComments, this->_settings.trim, this->_settings.quotes);
	// Получаем признак ограждения значения кавычками
	const bool quoted = ((this->_settings.quoting == quoting_t::ALWAYS) || ((this->_settings.quoting == quoting_t::AUTO) && needed));
	/**
	 * Если значение ограждается кавычками, которых читающий не снимает
	 *
	 * @note Настройки эти друг другу противоречат: ограждение назначено для читающего,
	 *       кавычки снимающего, а объявлен читающий, считающий их частью значения.
	 *       Записанное досталось бы ему вместе с кавычками, и молчать об этом нельзя
	 */
	if(quoted && !this->_settings.quotes){
		// Запоминаем код ошибки записи
		this->_error = error_t::CONFLICTING_SETTINGS;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Получаем признак того, что значение защищается управляющими последовательностями
	 *
	 * @note Значение, ограждения требующее, но кавычками не ограждаемое, читающий
	 *       прочёл бы изменённым: пробельную обвязку он отбросит, а на знаке примечания
	 *       значение обрежет. Защитить его остаётся лишь управляющими последовательностями,
	 *       а при выключенной их записи - отвергнуть, что и делается ниже
	 */
	const bool guarded = (needed && !quoted && this->_settings.escapes);
	/**
	 * Если значение записывается строками продолжения с отступом
	 *
	 * @note Обвязку строки продолжения читающий отбрасывает всегда, отбрасывает он её
	 *       и у последней строки такого значения - настройка отбрасывания обвязки тут
	 *       не властна. Пробельная обвязка многострочного значения этим способом не
	 *       записывается вовсе, а управляющие последовательности здесь запрещены
	 *       настройками: остаётся отказ
	 */
	if(!this->_settings.escapes && this->_settings.indents && (value.find('\n') != string_view::npos) &&
	   (ascii::isSpace(value.front()) || ascii::isSpace(value.back()))){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_CHARACTER;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Положение первого знака значения за пробельной обвязкой
	size_t head = 0;
	// Положение знака значения, которым пробельная обвязка конца начинается
	size_t tail = value.length();
	/**
	 * Если значение защищается управляющими последовательностями
	 */
	if(guarded){
		/**
		 * Выполняем поиск конца пробельной обвязки начала значения
		 */
		while((head < value.length()) && ascii::isSpace(value[head]))
			// Выполняем переход к следующему знаку значения
			head++;
		/**
		 * Выполняем поиск начала пробельной обвязки конца значения
		 *
		 * @note Обвязка эта защищается лишь у читающего, её отбрасывающего: сохраняющему
		 *       она достаётся как записана, и запись последовательностями лишь замусорила
		 *       бы текст настроек
		 */
		while(this->_settings.trim && (tail > head) && ascii::isSpace(value[tail - 1]))
			// Выполняем переход к предыдущему знаку значения
			tail--;
	}
	/**
	 * Выполняем перебор всех знаков значения свойства
	 */
	for(size_t i = 0; i < value.length(); i++){
		/**
		 * Если знак записи управляющей последовательностью требует
		 */
		if(::escapable(value[i])){
			/**
			 * Если запись управляющих последовательностей настройками запрещена
			 */
			if(!this->_settings.escapes){
				/**
				 * Если знак в тексте настроек сам по себе недопустим
				 *
				 * @note Незримый знак без управляющей последовательности записать нечем:
				 *       разбор отвергает его как недопустимый, и записанное не удалось бы
				 *       прочитать обратно
				 */
				if((value[i] != '\t') && (value[i] != '\\') && (value[i] != '"') && !ascii::isSpace(value[i])){
					// Запоминаем код ошибки записи
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если знаком является знак конца строки
				 *
				 * @note Знак конца строки в значении без управляющей последовательности
				 *       записать нечем: ограждение кавычками его не спасает, поскольку
				 *       строка на нём обрывается, и разбор прочитал бы значение иначе
				 */
				if(((value[i] == '\n') && !this->_settings.indents) || (value[i] == '\r')){
					// Запоминаем код ошибки записи
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
				/**
				 * Если знаком является кавычка при ограждении значения кавычками
				 */
				if((value[i] == '"') && quoted){
					// Запоминаем код ошибки записи
					this->_error = error_t::INVALID_CHARACTER;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим отрицательный результат выполнения операции
					return false;
				}
			}
		}
	}
	/**
	 * Если значение ограждения кавычками требует, но настройками оно запрещено
	 */
	if(needed && !quoted && !this->_settings.escapes){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_CHARACTER;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если значение оканчивается обратной косой чертой, склеивающей строки при чтении
	 *
	 * @note При записи управляющих последовательностей черта эта удваивается и строку
	 *       не продолжает, а без них оградить её нечем - даже кавычками: строки
	 *       склеиваются прежде, чем читающий доберётся до кавычек
	 */
	if(this->_settings.continuations && !this->_settings.escapes && ::continued(value)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_CHARACTER;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если значение ограждается кавычками
	 */
	if(quoted)
		// Выполняем запись открывающей кавычки значения
		this->_text.push_back('"');
	/**
	 * Выполняем перебор всех знаков значения свойства
	 */
	for(size_t i = 0; i < value.length(); i++){
		/**
		 * Если знак значения защиты управляющей последовательностью требует
		 *
		 * @note Защищаются лишь те знаки, которые читающий прочёл бы иначе: пробельная
		 *       обвязка значения и знак примечания, значение обрывающий. Пробел внутри
		 *       значения защиты не требует вовсе, и записывать его последовательностью
		 *       значило бы обратить читаемый текст настроек в нечитаемый
		 */
		if(guarded && (((i < head) || (i >= tail)) || (this->_settings.inlineComments && commented(value[i], this->_settings.comments)))){
			/**
			 * Если знак записывается кратким обозначением
			 */
			if(::escapable(value[i]))
				// Выполняем запись знака управляющей последовательностью
				::escaped(value[i], this->_text);
			/**
			 * Если краткого обозначения у знака нет
			 *
			 * @note Знаки эти сами по себе печатны, и записывать их шестнадцатеричным
			 *       кодовым значением незачем: разбор признаёт обратную косую черту
			 *       перед пробелом и знаками примечания
			 */
			else {
				// Выполняем запись обратной косой черты управляющей последовательности
				this->_text.push_back('\\');
				// Выполняем запись защищаемого знака значения
				this->_text.push_back(value[i]);
			}
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если знак записывается управляющей последовательностью
		 */
		if(this->_settings.escapes && ::escapable(value[i])){
			/**
			 * Если знаком является кавычка вне ограждения кавычками
			 *
			 * @note Кавычка вне ограждения значения не портит там, где читающий кавычек
			 *       не снимает вовсе. Снимающему же достаточно кавычки в начале значения,
			 *       чтобы прочесть его без неё, и такую записывают последовательностью
			 */
			if((value[i] == '"') && !quoted && !this->_settings.quotes){
				// Выполняем запись знака значения
				this->_text.push_back(value[i]);
				// Выполняем переход к следующему знаку значения
				continue;
			}
			// Выполняем запись знака управляющей последовательностью
			::escaped(value[i], this->_text);
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если знаком является знак конца строки при записи продолжением отступом
		 */
		if((value[i] == '\n') && !this->_settings.escapes && this->_settings.indents){
			/**
			 * Если знак конца строки окружён пробельными знаками либо завершает значение
			 *
			 * @note Строку продолжения читающий отделяет от предыдущей отступом и
			 *       обвязку её отбрасывает - и ту, что перед знаком конца строки, и ту,
			 *       что за отступом продолжения; пустую же строку продолжения он теряет
			 *       вовсе, отчего знак конца строки в конце значения не переживает
			 *       обратного чтения. Записать такое значение этим способом нечем, а
			 *       управляющие последовательности здесь запрещены настройками: остаётся
			 *       отказ, но не молчаливая потеря
			 */
			if(((i > 0) && ascii::isSpace(value[i - 1])) || ((i + 1) >= value.length()) || ascii::isSpace(value[i + 1])){
				// Запоминаем код ошибки записи
				this->_error = error_t::INVALID_CHARACTER;
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим отрицательный результат выполнения операции
				return false;
			}
			// Выполняем запись знака конца строки
			this->newline();
			// Выполняем запись отступа, которым продолжение задаётся
			this->_text.push_back('\t');
			// Выполняем переход к следующему знаку значения
			continue;
		}
		// Выполняем запись знака значения
		this->_text.push_back(value[i]);
	}
	/**
	 * Если значение ограждается кавычками
	 */
	if(quoted)
		// Выполняем запись закрывающей кавычки значения
		this->_text.push_back('"');
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи знака конца строки
 *
 */
void awh::codec::ini::Writer::newline() noexcept {
	/**
	 * Запоминаем разметку конца строки, на деле применённую
	 *
	 * @note Запоминается она ЗДЕСЬ, у самой записи, а не спрашивается позже у настроек:
	 *       настройка вправе смениться между записью строки и допиской к ней, и суд по
	 *       ней снимал бы не ту последовательность знаков
	 */
	this->_written = this->_settings.newline;
	// Выполняем запись знака конца строки
	this->_text.append(awh::codec::ini::newline(this->_written));
}
/**
 * @brief Метод ограждения примечания, оканчивающегося продолжением
 *
 * @param blank признак того, что очередной записью идёт пустая строка, ограждением
 *              служащая сама по себе
 *
 */
void awh::codec::ini::Writer::guard(const bool blank) noexcept {
	/**
	 * Если ограждение не требуется
	 */
	if(!this->_guarded)
		// Выходим из ограждения примечания
		return;
	// Выполняем сброс признака ожидающего ограждения
	this->_guarded = false;
	/**
	 * Если очередной записью идёт пустая строка
	 *
	 * @note Пустая строка прекращает склеивание сама по себе, и ставить перед нею
	 *       вторую значило бы растить текст пустыми строками с каждой перезаписью
	 */
	if(blank)
		// Выходим из ограждения примечания
		return;
	// Выполняем запись пустой строки, склеивание прекращающей
	this->newline();
}
/**
 * @brief Метод получения текущих настроек записи
 *
 * @return текущие настройки записи текста настроек
 *
 */
const awh::codec::ini::Writer::settings_t & awh::codec::ini::Writer::settings() const noexcept {
	// Выводим текущие настройки записи текста настроек
	return this->_settings;
}
/**
 * @brief Метод установки настроек записи
 *
 * @param settings настройки записи текста настроек
 *
 */
void awh::codec::ini::Writer::settings(const settings_t & settings) noexcept {
	// Запоминаем настройки записи текста настроек
	this->_settings = settings;
}
/**
 * @brief Метод записи объявления раздела
 *
 * @param section    имя записываемого раздела
 * @param subsection имя записываемого подраздела
 * @return           результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::section(const string_view section, const string_view subsection) noexcept {
	/**
	 * Если предыдущая операция записи завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	// Выполняем ограждение примечания, оканчивающегося продолжением
	this->guard(false);
	/**
	 * Если проверку имени раздела выполнить не удалось
	 */
	if(!this->verify(section, true))
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если имя подраздела передано, а построение его настройками не задано
	 */
	if(!subsection.empty() && (this->_settings.subsections == subsection_t::NONE)){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_SUBSECTION;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Запоминаем длину собранного текста до начала записи объявления
	 *
	 * @note Проверка имени подраздела ведётся по ходу записи, и отказ её оставлял бы
	 *       в собранном тексте начатое объявление: буфер при отказе откатывается к
	 *       тому, чем был до вызова. Пустая строка, отделяющая раздел от предыдущего,
	 *       откатывается вместе с ним - объявления, которое она отделяет, не вышло
	 */
	const size_t position = this->_text.length();
	/**
	 * Если пустая строка перед объявлением раздела настройками задана
	 */
	if(this->_settings.separated && this->_sectioned)
		// Выполняем запись пустой строки перед объявлением раздела
		this->newline();
	// Выполняем запись открывающей квадратной скобки объявления
	this->_text.push_back('[');
	// Выполняем запись имени раздела
	this->_text.append(section);
	/**
	 * Если имя подраздела передано
	 */
	if(!subsection.empty()){
		/**
		 * Определяем построение имени подраздела
		 *
		 * @note Признание обоих построений разом пишется кавычками: знак-разделитель
		 *       внутри имени подраздела прочёлся бы вторым уровнем вложенности, а
		 *       кавычки его ограждают
		 */
		switch((this->_settings.subsections == subsection_t::BOTH) ?
		 static_cast <uint8_t> (subsection_t::QUOTED) : static_cast <uint8_t> (this->_settings.subsections)){
			// Если подраздел отделяется знаком-разделителем
			case static_cast <uint8_t> (subsection_t::DELIMITED): {
				/**
				 * Выполняем перебор всех знаков имени подраздела
				 */
				for(size_t i = 0; i < subsection.length(); i++){
					/**
					 * Если знак имени подраздела недопустим
					 */
					if((subsection[i] == ']') || (subsection[i] == '\n') || (subsection[i] == '\r')){
						// Запоминаем код ошибки записи
						this->_error = error_t::INVALID_SUBSECTION;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выполняем откат собранного текста к состоянию до вызова
						this->_text.resize(position);
						// Выводим отрицательный результат выполнения операции
						return false;
					}
				}
				// Выполняем запись знака-разделителя имени подраздела
				this->_text.push_back(this->_settings.delimiter);
				// Выполняем запись имени подраздела
				this->_text.append(subsection);
			} break;
			// Если подраздел заключается в кавычки
			case static_cast <uint8_t> (subsection_t::QUOTED): {
				// Выполняем запись разделителя имени раздела и имени подраздела
				this->_text.push_back(' ');
				// Выполняем запись открывающей кавычки имени подраздела
				this->_text.push_back('"');
				/**
				 * Выполняем перебор всех знаков имени подраздела
				 */
				for(size_t i = 0; i < subsection.length(); i++){
					/**
					 * Если знак имени подраздела недопустим
					 */
					if((subsection[i] == '\n') || (subsection[i] == '\r')){
						// Запоминаем код ошибки записи
						this->_error = error_t::INVALID_SUBSECTION;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выполняем откат собранного текста к состоянию до вызова
						this->_text.resize(position);
						// Выводим отрицательный результат выполнения операции
						return false;
					}
					/**
					 * Если знак имени подраздела ограждения требует
					 */
					if((subsection[i] == '"') || (subsection[i] == '\\'))
						// Выполняем запись обратной косой черты перед знаком
						this->_text.push_back('\\');
					// Выполняем запись знака имени подраздела
					this->_text.push_back(subsection[i]);
				}
				// Выполняем запись закрывающей кавычки имени подраздела
				this->_text.push_back('"');
			} break;
		}
	}
	// Выполняем запись закрывающей квадратной скобки объявления
	this->_text.push_back(']');
	// Выполняем запись знака конца строки
	this->newline();
	// Запоминаем признак того, что раздел текста настроек объявлен
	this->_sectioned = true;
	// Выполняем сброс признака записанного свойства
	this->_valued = false;
	// Выводим положительный результат выполнения операции
	return true;
}
/**
 * @brief Метод записи свойства со значением
 *
 * @param key   имя записываемого свойства
 * @param value значение записываемого свойства
 * @return      результат выполнения операции
 *
 */
/**
 * @brief Метод записи свойства добавлением к перечню значений
 *
 * @param key    имя записываемого свойства
 * @param value  записываемое значение свойства
 * @param append признак добавления значения к перечню
 * @return       результат выполнения операции
 *
 */
/**
 * @brief Метод записи свойства со значением
 *
 * @details Запись свойства обычного и запись добавления к перечню значений разнятся
 * лишь двумя местами - проверкой признания перечней читающим да скобками за именем, -
 * а прочее у них общее. Держать их двумя телами значило бы развести своды правил при
 * первой же правке одного из них
 *
 * @param key   имя записываемого свойства
 * @param value значение записываемого свойства
 * @param array признак записи добавления к перечню значений
 * @return      результат выполнения операции
 *
 */
bool awh::codec::ini::Writer::emit(const string_view key, const string_view value, const bool array) noexcept {
	/**
	 * Если предыдущая операция записи завершилась ошибкой
	 */
	if(this->_error != error_t::NONE)
		// Выводим отрицательный результат выполнения операции
		return false;
	/**
	 * Если записывается добавление к перечню, а читающий их не признаёт
	 *
	 * @note Скобки перечня достались бы такому читающему частью имени свойства, и он
	 *       отверг бы его как ошибочно построенное
	 */
	if(array && !this->_settings.arrays){
		// Запоминаем код ошибки записи
		this->_error = error_t::INVALID_KEY;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	/**
	 * Если свойство записывается прежде объявления раздела при читающем, таких свойств
	 * не признающем
	 *
	 * @note Читающий отвергает такое свойство как объявленное вне раздела, и собранный
	 *       текст ему не прочитать вовсе
	 */
	if(!this->_settings.global && !this->_sectioned){
		// Запоминаем код ошибки записи
		this->_error = error_t::KEY_OUTSIDE_SECTION;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Выполняем ограждение примечания, оканчивающегося продолжением
	this->guard(false);
	/**
	 * Если проверку имени свойства выполнить не удалось
	 *
	 * @note Проверяется имя без скобок: сами скобки в имени недопустимы, и запись
	 *       их к имени добавляет уже это тело
	 */
	if(!this->verify(key, false))
		// Выводим отрицательный результат выполнения операции
		return false;
	// Запоминаем длину собранного текста до начала записи свойства
	const size_t position = this->_text.length();
	/**
	 * Если запись отступа перед свойствами раздела настройками задана
	 *
	 * @note Отступ этот украшающий, и при читающем, признающем продолжение отступом,
	 *       он не пишется вовсе: строка с отступом досталась бы такому читающему
	 *       продолжением значения предыдущего свойства, и свойства раздела слились бы
	 *       в одно. Украшение уступает сохранности записанного
	 */
	if(this->_settings.indent && !this->_settings.indents && this->_sectioned)
		// Выполняем запись отступа перед именем свойства
		this->_text.push_back('\t');
	// Выполняем запись имени свойства
	this->_text.append(key);
	/**
	 * Если записывается добавление к перечню значений
	 */
	if(array)
		// Выполняем запись скобок добавления к перечню значений
		this->_text.append("[]");
	/**
	 * Если запись пробелов вокруг разделителя настройками задана
	 */
	if(this->_settings.spaces)
		// Выполняем запись пробела перед разделителем
		this->_text.push_back(' ');
	// Выполняем запись разделителя имени свойства и его значения
	this->_text.push_back(this->_settings.separator);
	/**
	 * Если запись пробелов вокруг разделителя настройками задана
	 */
	if(this->_settings.spaces)
		// Выполняем запись пробела за разделителем
		this->_text.push_back(' ');
	/**
	 * Если запись значения свойства выполнить не удалось
	 */
	if(!this->escape(value)){
		// Выполняем откат собранного текста к состоянию до вызова
		this->_text.resize(position);
		// Выводим отрицательный результат выполнения операции
		return false;
	}
	// Запоминаем, что последней записанной строкой было свойство
	this->_valued = true;
	// Выполняем запись знака конца строки
	this->newline();
	// Выводим положительный результат выполнения операции
	return true;
}
bool awh::codec::ini::Writer::property(const string_view key, const string_view value, const bool append) noexcept {
	// Выполняем запись свойства со значением
	return this->emit(key, value, append);
}
bool awh::codec::ini::Writer::property(const string_view key, const string_view value) noexcept {
	// Выполняем запись свойства со значением
	return this->emit(key, value, false);
}
