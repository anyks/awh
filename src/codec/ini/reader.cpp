/**
 * @brief Метод приведения имени к виду для сличения
 *
 * @param name приводимое имя раздела или свойства
 * @return     имя, приведённое к виду для сличения
 *
 */
string awh::codec::ini::Reader::fold(const string_view name, const bool section) const noexcept {
	// Приводимое имя раздела или свойства
	string result(name);
	/**
	 * Если регистр имени при сличении не учитывается
	 */
	if(!this->_settings.sensitive && !(section && this->_settings.sensitiveSections)){
		/**
		 * Выполняем перебор всех знаков имени
		 */
		for(size_t i = 0; i < result.length(); i++)
			// Выполняем приведение очередного знака имени к нижнему регистру
			result[i] = ascii::toLower(result[i]);
	}
	// Выводим приведённое имя раздела или свойства
	return result;
}
/**
 * @brief Метод запоминания ошибки разбора
 *
 * @param error  код ошибки разбора
 * @param offset положение ошибки в приведённом тексте
 * @param line   номер строки, где обнаружена ошибка
 * @param column положение в строке, где обнаружена ошибка
 * @return       признак отказа для передачи вызывающему
 *
 */
bool awh::codec::ini::Reader::fail(const error_t error, const size_t offset, const uint32_t line, const uint32_t column) noexcept {
	// Запоминаем код ошибки разбора
	this->_error = error;
	// Запоминаем состояние чтения текста настроек
	this->_state = state_t::FAILED;
	// Запоминаем смещение обнаруженной ошибки в исходном тексте
	this->_errorLocation.offset = (this->_base + offset);
	// Запоминаем номер строки, где обнаружена ошибка
	this->_errorLocation.line = line;
	// Запоминаем положение в строке, где обнаружена ошибка
	this->_errorLocation.column = column;
	// Выполняем сброс вида текущего события разбора
	this->_event = event_t::NONE;
	// Выводим признак отказа для передачи вызывающему
	return false;
}
/**
 * @brief Метод получения положения знака в строке
 *
 * @param begin  положение начала строки в приведённом тексте
 * @param offset положение знака в приведённом тексте
 * @return       положение знака в строке, считая с единицы
 *
 */
uint32_t awh::codec::ini::Reader::column(const size_t begin, const size_t offset) const noexcept {
	// Положение знака в строке, считая с единицы
	uint32_t result = 1;
	/**
	 * Выполняем перебор знаков строки до искомого положения
	 */
	for(size_t i = begin; (i < offset) && (i < this->_buffer.length()); i++){
		/**
		 * Если знак продолжающим байтом последовательности не является
		 *
		 * @note Считаются лишь первые байты последовательностей: знак Юникода
		 *       записывается несколькими байтами, а положением своим остаётся один
		 */
		if((static_cast <uint8_t> (this->_buffer[i]) & 0xC0) != 0x80)
			// Выполняем увеличение положения знака в строке
			result++;
	}
	// Выводим положение знака в строке
	return result;
}
/**
 * @brief Метод поиска конца логической строки
 *
 * @param begin  положение начала логической строки в приведённом тексте
 * @param length длина логической строки без знака её конца
 * @param next   положение начала следующей строки в приведённом тексте
 * @return       признак того, что логическая строка поступила целиком
 *
 */
bool awh::codec::ini::Reader::measure(const size_t begin, size_t & length, size_t & next) noexcept {
	// Признак того, что разбирается первая физическая строка
	bool first = true;
	// Признак того, что продолжение строки допустимо отступом
	bool value = false;
	// Положение начала очередной физической строки
	size_t offset = begin;
	/**
	 * Выполняем перебор физических строк исходного текста
	 */
	while(true){
		// Длина очередной физической строки без знака её конца
		size_t size = 0;
		// Положение начала следующей физической строки
		size_t after = 0;
		/**
		 * Если знак конца очередной физической строки не обнаружен
		 */
		if(!::split(this->_buffer, offset, size, after)){
			/**
			 * Если исходный текст поступил ещё не целиком
			 */
			if(!this->_final)
				// Выводим признак незавершённой логической строки
				return false;
			// Запоминаем длину незавершённой физической строки
			size = (this->_buffer.length() - offset);
			// Запоминаем положение конца исходного текста
			after = this->_buffer.length();
			// Запоминаем длину логической строки
			length = ((offset + size) - begin);
			// Запоминаем положение начала следующей строки
			next = after;
			// Выводим признак завершённой логической строки
			return true;
		}
		// Получаем содержимое очередной физической строки
		const string_view line(this->_buffer.data() + offset, size);
		/**
		 * Если разбирается первая физическая строка
		 */
		if(first){
			// Получаем содержимое строки без пробельной обвязки
			const string_view content = ::trim(line);
			/**
			 * Запоминаем признак допустимости продолжения строки отступом
			 *
			 * @note Отступом продолжается лишь значение свойства: ни пустая строка,
			 *       ни примечание, ни объявление раздела продолжения не имеют, и
			 *       строка с отступом за ними начинает запись заново
			 */
			value = (!content.empty() && (content.front() != '[') && !commented(content.front(), this->_settings.comments));
			// Снимаем признак разбора первой физической строки
			first = false;
		}
		// Запоминаем длину логической строки
		length = ((offset + size) - begin);
		// Запоминаем положение начала следующей строки
		next = after;
		/**
		 * Если строка продолжается обратной косой чертой
		 */
		if(this->_settings.continuations && ::continued(line, this->_settings.escapes)){
			// Выполняем переход к следующей физической строке
			offset = after;
			// Выполняем продолжение сборки логической строки
			continue;
		}
		/**
		 * Если продолжение строки отступом настройками разрешено
		 */
		if(this->_settings.indents && value){
			// Длина следующей физической строки без знака её конца
			size_t size2 = 0;
			// Положение начала строки за следующей
			size_t after2 = 0;
			/**
			 * Если знак конца следующей физической строки не обнаружен
			 */
			if(!::split(this->_buffer, after, size2, after2)){
				/**
				 * Если исходный текст поступил ещё не целиком
				 *
				 * @note Решение о продолжении принимается по следующей строке, и
				 *       принять его, пока она не поступила целиком, нельзя: строка
				 *       с отступом, разорванная границей куска, обратилась бы в
				 *       отдельную запись
				 */
				if(!this->_final)
					// Выводим признак незавершённой логической строки
					return false;
				// Запоминаем длину незавершённой физической строки
				size2 = (this->_buffer.length() - after);
				// Запоминаем положение конца исходного текста
				after2 = this->_buffer.length();
			}
			/**
			 * Если следующая физическая строка продолжает значение отступом
			 */
			if(::indented(string_view(this->_buffer.data() + after, size2))){
				// Выполняем переход к следующей физической строке
				offset = after;
				// Выполняем продолжение сборки логической строки
				continue;
			}
		}
		// Выводим признак завершённой логической строки
		return true;
	}
}
/**
 * @brief Метод сборки логической строки с разрешением продолжений
 *
 * @param begin  положение начала логической строки в приведённом тексте
 * @param length длина логической строки в приведённом тексте
 * @return       результат выполнения операции
 *
 */
bool awh::codec::ini::Reader::join(const size_t begin, const size_t length) noexcept {
	// Выполняем очистку собранной логической строки
	this->_logical.clear();
	/**
	 * Если длина логической строки предел настроек превышает
	 */
	if(static_cast <uint64_t> (length) > static_cast <uint64_t> (this->_settings.maxLine))
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::LINE_TOO_LONG, begin, this->_line, 1);
	// Длина первой физической строки без знака её конца
	size_t size = 0;
	// Положение начала следующей физической строки
	size_t after = 0;
	/**
	 * Если логическая строка продолжений не имеет
	 *
	 * @note Строка такая лежит в приведённом тексте непрерывным отрезком, и
	 *       выдаётся на неё ссылка: копирование её в отдельное хранилище
	 *       обходилось в проход по всему тексту сверх самого разбора
	 */
	if(!::split(this->_buffer, begin, size, after) || (after >= (begin + length))){
		// Запоминаем ссылку на логическую строку в приведённом тексте
		this->_current = string_view(this->_buffer.data() + begin, ((size > 0) ? size : length));
		// Выводим результат выполнения операции
		return true;
	}
	// Количество склеенных строк продолжения
	uint32_t count = 0;
	// Выполняем упреждающее выделение памяти под собираемую логическую строку
	this->_logical.reserve(length);
	/**
	 * Признак того, что предыдущая строка продолжена отступом
	 *
	 * @note Отступ снимается со всякой строки продолжения, включая последнюю: она
	 *       обрывается не продолжением, а концом записи, и отступ её от прочих ничем
	 *       не отличается
	 */
	bool stripped = false;
	// Положение начала очередной физической строки
	size_t offset = begin;
	/**
	 * Выполняем перебор физических строк логической строки
	 */
	while(offset < (begin + length)){
		// Длина очередной физической строки без знака её конца
		size_t size = 0;
		// Положение начала следующей физической строки
		size_t after = 0;
		/**
		 * Если знак конца очередной физической строки не обнаружен
		 */
		if(!::split(this->_buffer, offset, size, after) || (after > (begin + length))){
			// Запоминаем длину последней физической строки
			size = ((begin + length) - offset);
			// Запоминаем положение конца логической строки
			after = (begin + length);
		}
		// Получаем содержимое очередной физической строки
		const string_view line(this->_buffer.data() + offset, size);
		/**
		 * Если очередная физическая строка является последней
		 */
		if(after >= (begin + length)){
			// Выполняем добавление содержимого строки к логической строке
			this->_logical.append(stripped ? ::trim(line) : line);
			// Выполняем прекращение сборки логической строки
			break;
		}
		/**
		 * Если количество склеенных строк предел настроек превышает
		 */
		if((++count) > this->_settings.maxContinuation)
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::CONTINUATION_EXCEEDED, offset, this->_line + count, 1);
		/**
		 * Если строка продолжается обратной косой чертой
		 */
		if(this->_settings.continuations && ::continued(line, this->_settings.escapes)){
			/**
			 * Выполняем добавление содержимого строки без обратной косой черты
			 *
			 * @note Знак конца строки при таком продолжении не сохраняется: строки
			 *       склеиваются встык, а отступ следующей строки остаётся частью
			 *       значения - таково обращение описания служб systemd
			 */
			this->_logical.append(stripped ? ::trim(line.substr(0, line.length() - 1)) : line.substr(0, line.length() - 1));
			// Снимаем признак продолжения предыдущей строки отступом
			stripped = false;
		/**
		 * Если строка продолжается отступом следующей строки
		 */
		} else {
			// Запоминаем признак продолжения предыдущей строки отступом
			stripped = true;
			/**
			 * Выполняем добавление содержимого строки без пробельной обвязки
			 *
			 * @note Отступ, которым продолжение задано, частью значения не является:
			 *       он служит лишь признаком продолжения, и разбор языка Python его
			 *       отбрасывает вместе с обвязкой в конце строки
			 */
			this->_logical.append(::trim(line));
			/**
			 * Выполняем добавление знака конца строки к логической строке
			 *
			 * @note Продолжение отступом знак конца строки сохраняет: значение,
			 *       записанное таким образом, многострочным и задумано, и разбор
			 *       языка Python склеивает его именно так
			 */
			this->_logical.push_back('\n');
		}
		// Выполняем переход к следующей физической строке
		offset = after;
	}
	// Запоминаем ссылку на собранную логическую строку
	this->_current = this->_logical;
	// Выводим результат выполнения операции
	return true;
}
/**
 * @brief Метод разбора объявления раздела
 *
 * @param line   разбираемая логическая строка без знака её конца
 * @param offset положение начала логической строки в приведённом тексте
 * @return       результат выполнения операции
 *
 */
bool awh::codec::ini::Reader::header(const string_view line, const size_t offset) noexcept {
	// Положение закрывающей квадратной скобки объявления
	size_t close = string_view::npos;
	// Признак нахождения разбора внутри кавычек имени подраздела
	bool quoted = false;
	/**
	 * Выполняем перебор знаков объявления раздела
	 *
	 * @note Скобка ищется разбором, а не поиском с конца: с конца она находилась бы
	 *       в примечании за объявлением - запись «[a] ; см. раздел [docs]» давала имя
	 *       раздела «a] ; см. раздел [docs». Скобка внутри кавычек имени подраздела
	 *       при этом закрывающей не считается: наречие Git такое имя допускает
	 */
	for(size_t i = 1; i < line.length(); i++){
		/**
		 * Если имя подраздела заключается в кавычки
		 */
		if(this->_settings.subsections == subsection_t::QUOTED){
			/**
			 * Если очередным знаком является обратная косая черта внутри кавычек
			 */
			if(quoted && (line[i] == '\\') && ((i + 1) < line.length())){
				// Выполняем переход к знаку за огороженным
				i++;
				// Выполняем переход к следующему знаку объявления
				continue;
			}
			/**
			 * Если очередным знаком является кавычка
			 */
			if(line[i] == '"'){
				// Переключаем признак нахождения разбора внутри кавычек
				quoted = !quoted;
				// Выполняем переход к следующему знаку объявления
				continue;
			}
		}
		/**
		 * Если очередным знаком является закрывающая квадратная скобка вне кавычек
		 */
		if(!quoted && (line[i] == ']')){
			// Запоминаем положение закрывающей квадратной скобки объявления
			close = i;
			// Выполняем прекращение поиска закрывающей скобки
			break;
		}
	}
	/**
	 * Если закрывающая квадратная скобка объявления не обнаружена
	 */
	if(close == string_view::npos)
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::UNCLOSED_SECTION, offset, this->_line, 1);
	// Получаем содержимое объявления раздела без квадратных скобок
	string_view content = ::trim(line.substr(1, close - 1));
	// Получаем остаток строки за закрывающей квадратной скобкой
	const string_view tail = ::trim(line.substr(close + 1));
	/**
	 * Если за закрывающей квадратной скобкой обнаружено содержимое
	 */
	if(!tail.empty()){
		/**
		 * Если содержимое за скобкой примечанием не является
		 */
		if(!commented(tail.front(), this->_settings.comments))
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::UNEXPECTED_CONTENT, offset, this->_line, 1);
		/**
		 * Если выдача примечаний настройками разрешена
		 */
		if(this->_settings.emitComments){
			// Запоминаем содержимое удержанного примечания
			this->_content.assign(::trim(tail.substr(1)));
			// Запоминаем знак, которым примечание начато
			this->_tail.marker = tail.front();
			// Запоминаем расположение удержанного примечания
			this->_tail.placement = placement_t::HEADER;
			// Запоминаем положение удержанного примечания в исходном тексте
			this->_tail.location = this->_location;
			// Запоминаем признак того, что примечание ждёт своей выдачи
			this->_pending = true;
		}
	}
	/**
	 * Если имя раздела пусто
	 */
	if(content.empty())
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::EMPTY_SECTION, offset, this->_line, 1);
	/**
	 * Если длина имени раздела предел настроек превышает
	 */
	if(content.length() > this->_settings.maxName)
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::NAME_TOO_LONG, offset, this->_line, 1);
	// Выполняем очистку имени текущего подраздела
	this->_subsection.clear();
	/**
	 * Определяем построение имени подраздела
	 */
	switch(static_cast <uint8_t> (this->_settings.subsections)){
		// Если подраздел отделяется знаком-разделителем
		case static_cast <uint8_t> (subsection_t::DELIMITED): {
			// Получаем положение знака-разделителя имени подраздела
			const size_t position = content.find(this->_settings.delimiter);
			/**
			 * Если знак-разделитель имени подраздела обнаружен
			 */
			if(position != string_view::npos){
				// Количество знаков-разделителей имени подраздела
				uint32_t depth = 0;
				/**
				 * Выполняем перебор знаков имени подраздела
				 */
				for(size_t i = position; i < content.length(); i++){
					/**
					 * Если очередным знаком является знак-разделитель
					 */
					if(content[i] == this->_settings.delimiter)
						// Выполняем увеличение количества знаков-разделителей
						depth++;
				}
				/**
				 * Если глубина вложенности подразделов предел настроек превышает
				 */
				if(depth >= this->_settings.maxDepth)
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::DEPTH_EXCEEDED, offset, this->_line, 1);
				/**
				 * Если имя подраздела за знаком-разделителем пусто
				 *
				 * @note Запись «[a.]» от записи «[a]» отличается лишь знаком-разделителем,
				 *       а разбирается в тот же раздел с пустым подразделом: принять её
				 *       значило бы потерять этот знак при обратной записи
				 */
				if((position + 1) >= content.length())
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::INVALID_SUBSECTION, offset, this->_line, 1);
				// Запоминаем имя текущего подраздела
				this->_subsection.assign(content.substr(position + 1));
				// Получаем имя раздела без имени подраздела
				content = content.substr(0, position);
				/**
				 * Если имя раздела оказалось пустым
				 */
				if(content.empty())
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::EMPTY_SECTION, offset, this->_line, 1);
			}
		} break;
		// Если подраздел заключается в кавычки
		case static_cast <uint8_t> (subsection_t::QUOTED): {
			// Получаем положение открывающей кавычки имени подраздела
			const size_t position = content.find('"');
			/**
			 * Если открывающая кавычка имени подраздела обнаружена
			 */
			if(position != string_view::npos){
				/**
				 * Если имя раздела перед кавычкой отсутствует
				 */
				if(::trim(content.substr(0, position)).empty())
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::EMPTY_SECTION, offset, this->_line, 1);
				// Признак обнаружения закрывающей кавычки имени подраздела
				bool closed = false;
				/**
				 * Выполняем перебор знаков имени подраздела
				 */
				for(size_t i = (position + 1); i < content.length(); i++){
					/**
					 * Если очередным знаком является обратная косая черта
					 *
					 * @note Внутри имени подраздела разбираются лишь две управляющие
					 *       последовательности - кавычка и сама черта, - и таково
					 *       обращение настроек Git: прочие знаки за чертой оно
					 *       оставляет как есть
					 */
					if((content[i] == '\\') && ((i + 1) < content.length())){
						// Выполняем добавление знака за чертой к имени подраздела
						this->_subsection.push_back(content[++i]);
						// Выполняем переход к следующему знаку имени подраздела
						continue;
					}
					/**
					 * Если очередным знаком является закрывающая кавычка
					 */
					if(content[i] == '"'){
						// Запоминаем признак обнаружения закрывающей кавычки
						closed = true;
						/**
						 * Если за закрывающей кавычкой обнаружено содержимое
						 */
						if(!::trim(content.substr(i + 1)).empty())
							// Выводим сообщение об ошибке разбора
							return this->fail(error_t::INVALID_SUBSECTION, offset, this->_line, 1);
						// Выполняем прекращение разбора имени подраздела
						break;
					}
					// Выполняем добавление очередного знака к имени подраздела
					this->_subsection.push_back(content[i]);
				}
				/**
				 * Если закрывающая кавычка имени подраздела не обнаружена
				 */
				if(!closed)
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::INVALID_SUBSECTION, offset, this->_line, 1);
				// Получаем имя раздела без имени подраздела
				content = ::trim(content.substr(0, position));
			}
		} break;
	}
	// Запоминаем имя текущего раздела
	this->_section.assign(content);
	/**
	 * Если повторное объявление раздела признано ошибкой
	 */
	if(this->_settings.duplicates == duplicate_t::ERROR){
		/**
		 * Собираем имя раздела вместе с именем подраздела для сличения
		 *
		 * @note Имена соединяются через нулевой байт намеренно: разделитель этот в
		 *       именах не встречается, и раздел «a» с подразделом «b» не сольётся с
		 *       разделом «a.b», объявленным иначе
		 */
		string name = this->fold(this->_section, true);
		// Выполняем добавление разделителя имён к собираемому имени
		name.push_back('\0');
		/**
		 * Имя подраздела в сличении регистр учитывает всегда
		 *
		 * @note Таково обращение настроек Git: имя раздела регистра не учитывает, а
		 *       имя подраздела - учитывает, поскольку несёт в себе то имя ветви, то
		 *       обозначение источника, где регистр значащ
		 */
		name.append(this->_subsection);
		/**
		 * Если раздел с таким именем уже объявлен
		 */
		if(!this->_sections.emplace(std::move(name)).second)
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::DUPLICATE_SECTION, offset, this->_line, 1);
	}
	// Выполняем очистку перечня объявленных свойств прежнего раздела
	this->_keys.clear();
	// Запоминаем имя раздела текущего события
	this->_name.section = this->_section;
	// Запоминаем имя подраздела текущего события
	this->_name.subsection = this->_subsection;
	// Запоминаем признак того, что первый раздел текста настроек объявлен
	this->_sectioned = true;
	// Запоминаем вид текущего события разбора
	this->_event = event_t::SECTION;
	// Выводим результат выполнения операции
	return true;
}
/**
 * @brief Метод приведения значения свойства к окончательному виду
 *
 * @param text     разбираемое значение свойства
 * @param position положение начала значения в приведённом тексте
 * @return         результат выполнения операции
 *
 */
bool awh::codec::ini::Reader::plain(const string_view value) const noexcept {
	/**
	 * Выполняем перебор знаков значения свойства
	 */
	for(size_t i = 0; i < value.length(); i++){
		/**
		 * Если очередным знаком является кавычка, подлежащая снятию
		 */
		if((this->_settings.quotes == quote_t::STRIP) && (value[i] == '"'))
			// Выводим признак того, что значение приведения требует
			return false;
		/**
		 * Если очередным знаком начинается управляющая последовательность
		 */
		if(this->_settings.escapes && (value[i] == '\\'))
			// Выводим признак того, что значение приведения требует
			return false;
		/**
		 * Если очередным знаком начинается примечание в конце строки
		 */
		if(this->_settings.inlineComments && commented(value[i], this->_settings.comments) &&
		   ((i == 0) || ascii::isSpace(value[i - 1])))
			// Выводим признак того, что значение приведения требует
			return false;
	}
	// Выводим признак того, что значение приведения не требует
	return true;
}
/**
 * @brief Метод приведения значения свойства к окончательному виду
 *
 * @param text     разбираемое значение свойства
 * @param position положение начала значения в приведённом тексте
 * @return         результат выполнения операции
 *
 */
bool awh::codec::ini::Reader::extract(const string_view text, const size_t position) noexcept {
	// Выполняем очистку хранилища значения свойства
	this->_value.clear();
	// Количество пробельных знаков за разделителем имени и значения
	size_t indent = 0;
	/**
	 * Выполняем отбрасывание пробельных знаков за разделителем имени и значения
	 *
	 * @note Отбрасываются лишь пробел и знак табуляции: знак конца строки за
	 *       разделителем означает, что значение записано строками продолжения, и
	 *       первой строкой его тогда является пустая - таково обращение configparser
	 */
	while((indent < text.length()) && ((text[indent] == ' ') || (text[indent] == '\t')))
		// Выполняем переход к следующему знаку значения свойства
		indent++;
	// Получаем значение свойства без пробельных знаков за разделителем
	const string_view value = text.substr(indent);
	// Получаем положение начала значения в приведённом тексте
	const size_t offset = (position + indent);
	/**
	 * Если значение свойства записано в тексте так, как выдаётся
	 *
	 * @note Путь этот заведён ради обычного случая: у подавляющего большинства
	 *       значений ни кавычек, ни управляющих последовательностей, ни примечания
	 *       в конце строки нет, и такое значение лежит в приведённом тексте
	 *       непрерывным отрезком. Выдать его указателем на этот отрезок дешевле,
	 *       чем переписывать знак за знаком в отдельное хранилище
	 */
	if(this->plain(value)){
		// Длина значения без пробельной обвязки в конце
		size_t length = value.length();
		/**
		 * Если отбрасывание пробельной обвязки значения настройками разрешено
		 */
		if(this->_settings.trim){
			/**
			 * Выполняем отбрасывание пробельной обвязки в конце значения
			 */
			while((length > 0) && ascii::isSpace(value[length - 1]))
				// Выполняем переход к предыдущему знаку значения
				length--;
		}
		// Запоминаем значение свойства указателем в приведённый текст
		this->_view = value.substr(0, length);
		// Выводим положительный результат выполнения операции
		return true;
	}
	// Признак нахождения разбора внутри кавычек
	bool quoted = false;
	// Признак записи байта вне набора US-ASCII шестнадцатеричной последовательностью
	bool hexed = false;
	// Знак кавычки, которой значение открыто
	char quote = 0;
	/**
	 * Длина значения без пробельной обвязки в конце
	 *
	 * @note Обвязка отбрасывается лишь у части значения, записанной вне кавычек:
	 *       пробел, взятый в кавычки, записан там намеренно и значащ
	 */
	size_t keep = 0;
	/**
	 * Выполняем перебор знаков значения свойства
	 */
	for(size_t i = 0; i < value.length(); i++){
		/**
		 * Если разбор находится внутри кавычек
		 */
		if(quoted){
			/**
			 * Если очередным знаком является закрывающая кавычка
			 */
			if(value[i] == quote){
				// Снимаем признак нахождения разбора внутри кавычек
				quoted = false;
				// Выполняем переход к следующему знаку значения
				continue;
			}
			/**
			 * Если очередным знаком является обратная косая черта
			 */
			if((value[i] == '\\') && this->_settings.escapes){
				// Длина разобранной управляющей последовательности
				size_t length = 0;
				/**
				 * Если разбор управляющей последовательности выполнить не удалось
				 */
				if(!::unescape(value, i, length, this->_value, hexed))
					// Выводим сообщение об ошибке разбора
					return this->fail(error_t::INVALID_ESCAPE, offset + i, this->_line, this->column(this->_start, offset + i));
				// Выполняем переход к знаку за управляющей последовательностью
				i += (length - 1);
				// Запоминаем длину значения без пробельной обвязки в конце
				keep = this->_value.length();
				// Выполняем переход к следующему знаку значения
				continue;
			}
			// Выполняем добавление очередного знака к значению свойства
			this->_value.push_back(value[i]);
			// Запоминаем длину значения без пробельной обвязки в конце
			keep = this->_value.length();
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если очередным знаком является открывающая кавычка
		 */
		if((this->_settings.quotes == quote_t::STRIP) && (value[i] == '"')){
			// Запоминаем признак нахождения разбора внутри кавычек
			quoted = true;
			// Запоминаем знак кавычки, которой значение открыто
			quote = value[i];
			// Запоминаем признак того, что значение было заключено в кавычки
			this->_property.quoted = true;
			/**
			 * Запоминаем длину значения без пробельной обвязки в конце
			 *
			 * @note Пустые кавычки в конце значения обвязкой не являются: запись
			 *       «имя = значение ""» несёт пробел перед ними намеренно
			 */
			keep = this->_value.length();
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если очередным знаком является обратная косая черта
		 */
		if((value[i] == '\\') && this->_settings.escapes){
			// Длина разобранной управляющей последовательности
			size_t length = 0;
			/**
			 * Если разбор управляющей последовательности выполнить не удалось
			 */
			if(!::unescape(value, i, length, this->_value, hexed))
				// Выводим сообщение об ошибке разбора
				return this->fail(error_t::INVALID_ESCAPE, offset + i, this->_line, this->column(this->_start, offset + i));
			// Выполняем переход к знаку за управляющей последовательностью
			i += (length - 1);
			// Запоминаем длину значения без пробельной обвязки в конце
			keep = this->_value.length();
			// Выполняем переход к следующему знаку значения
			continue;
		}
		/**
		 * Если очередным знаком начинается примечание в конце строки
		 *
		 * @note Примечанием знак признаётся лишь тогда, когда стоит в начале значения
		 *       либо отделён от него пробельным знаком: без этого требования всякая
		 *       решётка внутри значения - в записи цвета, скажем, - обрезала бы его
		 */
		if(this->_settings.inlineComments && commented(value[i], this->_settings.comments) &&
		   ((i == 0) || ascii::isSpace(value[i - 1]))){
			/**
			 * Если выдача примечаний настройками разрешена
			 */
			if(this->_settings.emitComments){
				// Запоминаем содержимое удержанного примечания
				this->_content.assign(::trim(value.substr(i + 1)));
				// Запоминаем знак, которым примечание начато
				this->_tail.marker = value[i];
				// Запоминаем расположение удержанного примечания
				this->_tail.placement = placement_t::TAIL;
				// Запоминаем смещение удержанного примечания в исходном тексте
				this->_tail.location.offset = (this->_base + offset + i);
				// Запоминаем номер строки удержанного примечания
				this->_tail.location.line = this->_line;
				// Запоминаем положение удержанного примечания в строке
				this->_tail.location.column = this->column(this->_start, offset + i);
				// Запоминаем признак того, что примечание ждёт своей выдачи
				this->_pending = true;
			}
			// Выполняем прекращение разбора значения свойства
			break;
		}
		// Выполняем добавление очередного знака к значению свойства
		this->_value.push_back(value[i]);
		/**
		 * Если очередной знак пробельным не является
		 */
		if(!ascii::isSpace(value[i]))
			// Запоминаем длину значения без пробельной обвязки в конце
			keep = this->_value.length();
	}
	/**
	 * Если кавычка значения не закрыта до конца строки
	 */
	if(quoted)
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::UNTERMINATED_QUOTE, offset, this->_line, this->column(this->_start, offset));
	/**
	 * Если отбрасывание пробельной обвязки значения настройками разрешено
	 */
	if(this->_settings.trim && (keep < this->_value.length()))
		// Выполняем отбрасывание пробельной обвязки в конце значения
		this->_value.resize(keep);
	/**
	 * Если значение собрано с байтами вне набора US-ASCII
	 *
	 * @note Проверка эта нужна лишь такому значению: разбор ведёт весь текст в
	 *       кодировке UTF-8, а запись отдельными байтами способна собрать
	 *       последовательность, этой кодировке не отвечающую, - записать такое
	 *       значение обратно было бы нечем
	 */
	if(hexed){
		// Положение проверяемого знака собранного значения
		size_t position = 0;
		/**
		 * Выполняем перебор знаков собранного значения
		 */
		while(position < this->_value.length()){
			// Длина прочитанной последовательности знака
			size_t length = 0;
			// Выполняем чтение кодового значения очередного знака
			const uint32_t code = decode(this->_value.data() + position, (this->_value.length() - position), length);
			/**
			 * Если последовательность знака построена ошибочно
			 */
			if((code == INVALID_CODEPOINT) || (length == 0))
				// Выводим сообщение об ошибке разбора
				return this->fail(error_t::INVALID_ENCODING, offset, this->_line, this->column(this->_start, offset));
			// Выполняем переход к следующему знаку собранного значения
			position += length;
		}
	}
	// Запоминаем значение свойства указателем в его хранилище
	this->_view = this->_value;
	// Выводим результат выполнения операции
	return true;
}
/**
 * @brief Метод разбора свойства со значением
 *
 * @param line   разбираемая логическая строка без знака её конца
 * @param offset положение начала логической строки в приведённом тексте
 * @return       результат выполнения операции
 *
 */
bool awh::codec::ini::Reader::assign(const string_view line, const size_t offset) noexcept {
	/**
	 * Если свойство объявлено до первого раздела вопреки настройкам
	 */
	if(!this->_sectioned && !this->_settings.global)
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::KEY_OUTSIDE_SECTION, offset, this->_line, 1);
	// Положение разделителя имени свойства и его значения
	size_t position = string_view::npos;
	/**
	 * Выполняем перебор знаков логической строки
	 */
	for(size_t i = 0; i < line.length(); i++){
		/**
		 * Если очередной знак разделителем имени и значения является
		 */
		if(separated(line[i], this->_settings.separators)){
			// Запоминаем положение разделителя имени и значения
			position = i;
			// Выполняем прекращение поиска разделителя
			break;
		}
	}
	// Получаем имя свойства без пробельной обвязки
	string_view key = ::trim((position == string_view::npos) ? line : line.substr(0, position));
	/**
	 * Получаем положение имени свойства в разбираемой строке
	 *
	 * @note Держится ради указания места ошибки: имя разбирается без обвязки, а
	 *       столбец следует считать от начала строки, как она в файле записана
	 */
	const size_t placement = static_cast <size_t> (key.data() - line.data());
	/**
	 * Если разделитель имени свойства и его значения не обнаружен
	 */
	if(position == string_view::npos){
		/**
		 * Если свойство без разделителя и значения настройками не признаётся
		 */
		if(!this->_settings.valueless)
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::MISSING_SEPARATOR, offset, this->_line, 1);
		// Запоминаем признак свойства, записанного без разделителя и значения
		this->_property.valueless = true;
		// Выполняем сброс значения свойства текущего события
		this->_view = string_view();
	}
	/**
	 * Если имя свойства пусто
	 */
	if(key.empty())
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::EMPTY_KEY, offset, this->_line, 1);
	/**
	 * Если запись добавления к перечню значений настройками признаётся
	 */
	if(this->_settings.arrays && (key.length() > 2) && (key.compare(key.length() - 2, 2, "[]") == 0)){
		// Запоминаем признак свойства, записанного добавлением к перечню
		this->_property.append = true;
		// Получаем имя свойства без скобок добавления к перечню
		key = ::trim(key.substr(0, key.length() - 2));
		/**
		 * Если имя свойства без скобок оказалось пустым
		 */
		if(key.empty())
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::EMPTY_KEY, offset, this->_line, 1);
	}
	/**
	 * Если длина имени свойства предел настроек превышает
	 */
	if(key.length() > this->_settings.maxName)
		// Выводим сообщение об ошибке разбора
		return this->fail(error_t::NAME_TOO_LONG, offset, this->_line, 1);
	/**
	 * Выполняем перебор знаков имени свойства
	 */
	for(size_t i = 0; i < key.length(); i++){
		/**
		 * Если имя свойства содержит недопустимый знак
		 *
		 * @note Квадратные скобки и знак конца строки в имени свойства недопустимы:
		 *       первые начинают объявление раздела, а второй означает, что имя
		 *       собралось из строк продолжения, чего запись не допускает
		 */
		if((key[i] == '[') || (key[i] == ']') || (key[i] == '\n') || (key[i] == '\r'))
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::INVALID_KEY, (offset + placement + i), this->_line, this->column(this->_start, offset + placement + i));
	}
	/**
	 * Если повторное объявление свойства признано ошибкой
	 */
	if(this->_settings.duplicates == duplicate_t::ERROR){
		/**
		 * Если свойство с таким именем в разделе уже объявлено
		 */
		if(!this->_keys.emplace(this->fold(key)).second)
			// Выводим сообщение об ошибке разбора
			return this->fail(error_t::DUPLICATE_KEY, offset, this->_line, 1);
	}
	/**
	 * Если разделитель имени свойства и его значения обнаружен
	 */
	if(position != string_view::npos){
		/**
		 * Если приведение значения свойства к окончательному виду выполнить не удалось
		 */
		if(!this->extract(line.substr(position + 1), offset + position + 1))
			// Выводим отрицательный результат выполнения операции
			return false;
	}
	// Запоминаем имя свойства текущего события
	this->_property.key = key;
	// Запоминаем значение свойства текущего события
	this->_property.value = this->_view;
	// Запоминаем положение свойства в исходном тексте
	this->_property.location = this->_location;
	// Запоминаем вид текущего события разбора
	this->_event = event_t::PROPERTY;
	// Выводим результат выполнения операции
	return true;
}
