/**
 * @brief Метод получения количества пар расширения события
 *
 * @return количество пар расширения события
 */
size_t awh::codec::cef::Document::size() const noexcept {
	// Получаем вместилище пар расширения дерева события
	const abc::value_t & extension = this->_root.at(string("/") + EXTENSION);
	// Если вместилище пар расширения отображением не является
	if(extension.type() != abc::type_t::MAP)
		// Выводим отсутствие пар расширения события
		return 0;
	// Количество пар расширения события
	size_t result = 0;
	/**
	 * Выполняем перебор всех ключей расширения события
	 *
	 * @details Считаются ПАРЫ, а не ключи: повтор ключа обращает значение в перечень, и
	 *          запись «cs1=one cs1=two» несёт ДВЕ пары при одном ключе. Прежде счёт шёл
	 *          по ключам и отвечал единицей - договор хода обещает пары, и расхождение
	 *          это вскрыто аудитом 14.09.2026
	 *
	 * @note Количество КЛЮЧЕЙ берётся обходом - `keys("/extension").size()`, - и ход
	 *       этот остаётся при своём
	 */
	for(size_t i = 0; i < extension.size(); i++){
		// Получаем значение очередного ключа расширения
		const abc::value_t & current = extension[extension.key(i).text()];
		// Наращиваем количество пар расширения значениями ключа
		result += ((current.type() == abc::type_t::ARRAY) ? current.size() : 1);
	}
	// Выводим количество пар расширения события
	return result;
}

