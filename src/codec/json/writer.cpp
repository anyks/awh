/**
 * @brief Метод записи разделителя перед очередным значением
 *
 * @details Записывает запятую, перевод строки и отступ - в объёме,
 * заданном настройками оформления
 *
 * @return признак допустимости записи значения в этом месте
 *
 */
bool awh::codec::json::Writer::separate() noexcept {
	/**
	 * Если значение записывается за именем поля объекта
	 *
	 * @note Разделитель при этом уже записан самим именем поля, и записывать его
	 *       второй раз означало бы вставить запятую между именем и значением
	 */
	if(this->_keyed)
		// Выводим признак допустимости записи значения
		return true;
	/**
	 * Если запись ведётся внутри объекта
	 */
	if(!this->_nesting.empty() && (this->_nesting.back() == kind_t::OBJECT))
		// Выводим признак недопустимости записи значения, ожидается имя поля
		return false;
	/**
	 * Если запись ведётся вне вместилищ, а значение уже записано
	 *
	 * @note Второе значение подряд образовало бы два документа в одном тексте, а
	 *       такое допустимо лишь потоком NDJSON, отделяющим документы друг от друга
	 */
	if(this->_nesting.empty() && !this->_empty)
		// Выводим признак недопустимости записи значения
		return false;
	/**
	 * Если вне вместилищ начинается второй документ, а документы ничем не разделены
	 *
	 * @note Без разделителя два документа склеились бы в одну последовательность
	 *       знаков, разбор какой распался бы на границе между ними
	 */
	if(this->_nesting.empty() && this->_started && !this->_settings.stream)
		// Выводим признак недопустимости записи значения
		return false;
	/**
	 * Если вместилище уже содержит значения
	 */
	if(!this->_empty)
		// Записываем знак-разделитель значений
		this->_result.push_back(',');
	/**
	 * Если текст оформляется отступами, а запись ведётся внутри вместилища
	 */
	if((this->_settings.format == format_t::PRETTY) && !this->_nesting.empty()){
		// Записываем знак перевода строки
		this->_result.push_back('\n');
		// Выполняем запись отступа по глубине вложенности
		this->_result.append((this->_settings.indent > 0 ? (this->_nesting.size() * this->_settings.indent) : this->_nesting.size()), (this->_settings.indent > 0 ? ' ' : '\t'));
	}
	// Выводим признак допустимости записи значения
	return true;
}
/**
 * @brief Метод записи строки с экранированием
 *
 * @details Знаки, отмены не требующие, переносятся в текст отрезками целиком, а не знак
 * за знаком: строка, из таких знаков и состоящая, переносится одним копированием. В
 * отрезок входят и правильные последовательности UTF-8, коль скоро запись кодовыми
 * значениями не затребована, - разбор их при том ведётся всё равно, ибо байты,
 * кодировке не отвечающие, обязаны быть опознаны при любом правиле экранирования
 *
 * @param text записываемая строка
 *
 */
void awh::codec::json::Writer::quoted(const string & text) noexcept {
	// Записываем открывающую кавычку
	this->_result.push_back('"');
	/**
	 * Выполняем перебор всех байтов записываемой строки
	 */
	for(size_t i = 0; i < text.size();){
		// Положение конца отрезка знаков, записи как есть подлежащих
		size_t offset = i;
		// Кодовая точка разбираемой последовательности
		uint32_t code = 0;
		// Признак годности разобранной последовательности
		bool valid = false;
		// Длина разобранной последовательности
		size_t length = 0;
		/**
		 * Выполняем поиск конца отрезка знаков, записи как есть подлежащих
		 */
		while(offset < text.size()){
			// Получаем очередной байт записываемой строки
			const uint8_t next = static_cast <uint8_t> (text[offset]);
			/**
			 * Если знак лежит вне US-ASCII
			 */
			if(next > 0x7F){
				/**
				 * Если запись затребована кодовыми значениями
				 */
				if(this->_settings.escape == escape_t::ASCII)
					// Прекращаем поиск конца отрезка
					break;
				// Выполняем разбор последовательности UTF-8
				length = ::decode(text, offset, code, valid);
				/**
				 * Если разобранная последовательность негодна
				 */
				if(!valid)
					// Прекращаем поиск конца отрезка
					break;
				// Выполняем переход к следующей последовательности отрезка
				offset += length;
				// Выполняем переход к следующему знаку отрезка
				continue;
			}
			/**
			 * Если знак отмены требует
			 *
			 * @note Косая черта отмены требует лишь тогда, когда отмена её затребована
			 *       настройками: стандарт её отменять не велит
			 */
			if((next < 0x20) || (next == '"') || (next == '\\') ||
			   ((next == '/') && (this->_settings.escape != escape_t::MINIMAL)))
				// Прекращаем поиск конца отрезка
				break;
			// Выполняем переход к следующему знаку отрезка
			offset++;
		}
		/**
		 * Если отрезок знаков, записи как есть подлежащих, разыскан
		 */
		if(offset > i){
			// Выполняем перенос отрезка знаков в текст документа
			this->_result.append(text.data() + i, (offset - i));
			// Выполняем переход к концу отрезка знаков
			i = offset;
			/**
			 * Если строка исчерпана
			 */
			if(i >= text.size())
				// Прекращаем перебор байтов записываемой строки
				break;
		}
		// Получаем очередной байт записываемой строки
		const uint8_t letter = static_cast <uint8_t> (text[i]);
		/**
		 * Определяем очередной байт записываемой строки
		 */
		switch(letter){
			// Если байт является кавычкой
			case '"':
				// Записываем отменённую кавычку
				this->_result.append("\\\"");
			break;
			// Если байт является знаком отмены
			case '\\':
				// Записываем отменённый знак отмены
				this->_result.append("\\\\");
			break;
			// Если байт является знаком возврата на шаг
			case '\b':
				// Записываем знак возврата на шаг сокращённой записью
				this->_result.append("\\b");
			break;
			// Если байт является знаком перевода страницы
			case '\f':
				// Записываем знак перевода страницы сокращённой записью
				this->_result.append("\\f");
			break;
			// Если байт является знаком перевода строки
			case '\n':
				// Записываем знак перевода строки сокращённой записью
				this->_result.append("\\n");
			break;
			// Если байт является знаком возврата каретки
			case '\r':
				// Записываем знак возврата каретки сокращённой записью
				this->_result.append("\\r");
			break;
			// Если байт является знаком табуляции
			case '\t':
				// Записываем знак табуляции сокращённой записью
				this->_result.append("\\t");
			break;
			/**
			 * Если байт сокращённой записи не имеет
			 */
			default: {
				/**
				 * Если байт является управляющим знаком
				 *
				 * @note Стандарт запрещает такие знаки внутри строки без отмены, и
				 *       сокращённой записи у оставшихся из них нет
				 */
				if(letter < 0x20)
					// Выполняем запись управляющего знака кодовым значением
					::unicode(static_cast <uint32_t> (letter), this->_result);
				/**
				 * Если байт является косой чертой, а экранирование её затребовано
				 */
				else if((letter == '/') && (this->_settings.escape != escape_t::MINIMAL))
					// Записываем отменённую косую черту
					this->_result.append("\\/");
				/**
				 * Если байт лежит вне US-ASCII
				 *
				 * @note Отрезок оборвался на нём по одной из двух причин: либо запись
				 *       затребована кодовыми значениями, либо последовательность негодна
				 */
				else if(letter > 0x7F) {
					/**
					 * Если последовательность ещё не разобрана поиском конца отрезка
					 */
					if(this->_settings.escape == escape_t::ASCII)
						// Выполняем разбор последовательности UTF-8
						length = ::decode(text, i, code, valid);
					/**
					 * Если разобранная последовательность негодна, а пропуск её не затребован
					 */
					if(!valid && (this->_settings.malformed != malformed_t::PASS)){
						/**
						 * Если запись затребована кодовыми значениями
						 */
						if(this->_settings.escape == escape_t::ASCII)
							// Выполняем запись знака замены отменяющей последовательностью
							::unicode(code, this->_result);
						// Выполняем запись знака замены последовательностью UTF-8
						else this->_result.append("\xEF\xBF\xBD");
						// Выполняем переход к следующей последовательности записываемой строки
						i += length;
						// Выполняем переход к следующему байту записываемой строки
						continue;
					}
					/**
					 * Если запись затребована кодовыми значениями, а последовательность годна
					 */
					if(valid && (this->_settings.escape == escape_t::ASCII))
						// Выполняем запись кодовой точки отменяющей последовательностью
						::unicode(code, this->_result);
					/**
					 * Выполняем запись последовательности знаками, как они поданы
					 *
					 * @note Пропуск негодной последовательности пишет её байт за байтом:
					 *       кодовой точки у неё нет вовсе, и записать её значением нельзя
					 */
					else this->_result.append(text.data() + i, (valid ? length : 1));
					// Выполняем переход к следующей последовательности записываемой строки
					i += (valid ? length : 1);
					// Выполняем переход к следующему байту записываемой строки
					continue;
				// Записываем байт записываемой строки как есть
				} else this->_result.push_back(static_cast <char> (letter));
			}
		}
		// Выполняем переход к следующему байту записываемой строки
		i++;
	}
	// Записываем закрывающую кавычку
	this->_result.push_back('"');
}
/**
 * @brief Метод сброса состояния записи
 *
 * @details Сброс возвращает сборщик к пустому тексту, а выделенную память
 * удерживает
 *
 */
void awh::codec::json::Writer::reset() noexcept {
	// Выполняем очистку собранного текста
	this->_result.clear();
	// Выполняем очистку стека видов открытых вместилищ
	this->_nesting.clear();
	// Снимаем признак наличия значений у вместилища
	this->_empty = true;
	// Снимаем признак записи имени поля объекта
	this->_keyed = false;
	// Снимаем признак наличия записанных документов
	this->_started = false;
	// Выполняем сброс количества изъятых из сборщика байтов
	this->_taken = 0;
}
/**
 * @brief Метод открытия объекта
 *
 * @return признак успешности записи
 *
 */
bool awh::codec::json::Writer::object() noexcept {
	/**
	 * Если глубина вложенности превышает допустимую
	 */
	if(this->_nesting.size() >= MAX_DEPTH)
		// Выводим признак неуспешности записи
		return false;
	/**
	 * Если запись значения в этом месте недопустима
	 */
	if(!this->separate())
		// Выводим признак неуспешности записи
		return false;
	// Записываем знак открытия объекта
	this->_result.push_back('{');
	// Добавляем вид открытого вместилища в стек
	this->_nesting.push_back(kind_t::OBJECT);
	// Устанавливаем признак отсутствия значений у открытого вместилища
	this->_empty = true;
	// Снимаем признак записи имени поля объекта
	this->_keyed = false;
	// Выводим признак успешности записи
	return true;
}
