/**
 * @brief Метод закрытия открытого вместилища
 *
 * @return признак успешности записи
 *
 */
bool awh::codec::json::Writer::close() noexcept {
	/**
	 * Если открытых вместилищ нет вовсе
	 */
	if(this->_nesting.empty())
		// Выводим признак неуспешности записи
		return false;
	/**
	 * Если имя поля объекта записано, а значение его - ещё нет
	 */
	if(this->_keyed)
		// Выводим признак неуспешности записи
		return false;
	// Получаем вид закрываемого вместилища
	const kind_t kind = this->_nesting.back();
	// Удаляем вид закрываемого вместилища из стека
	this->_nesting.pop_back();
	/**
	 * Если текст оформляется отступами, а вместилище получило значения
	 *
	 * @note Пустое вместилище закрывается вплотную: перевод строки внутри него
	 *       ничего не разделяет, а место занимает
	 */
	if((this->_settings.format == format_t::PRETTY) && !this->_empty){
		// Записываем знак перевода строки
		this->_result.push_back('\n');
		// Выполняем запись отступа по глубине вложенности
		this->_result.append((this->_settings.indent > 0 ? (this->_nesting.size() * this->_settings.indent) : this->_nesting.size()), (this->_settings.indent > 0 ? ' ' : '\t'));
	}
	// Записываем знак закрытия вместилища
	this->_result.push_back(kind == kind_t::OBJECT ? '}' : ']');
	// Устанавливаем признак наличия значений у вместилища
	this->_empty = false;
	// Снимаем признак записи имени поля объекта
	this->_keyed = false;
	// Выводим признак успешности записи
	return true;
}
/**
 * @brief Метод записи имени поля объекта
 *
 * @param name записываемое имя поля объекта
 * @return     признак успешности записи
 *
 */
bool awh::codec::json::Writer::key(const string & name) noexcept {
	/**
	 * Если запись ведётся вне объекта либо имя поля объекта уже записано
	 */
	if(this->_nesting.empty() || (this->_nesting.back() != kind_t::OBJECT) || this->_keyed)
		// Выводим признак неуспешности записи
		return false;
	/**
	 * Если отказ на негодную кодировку затребован, а имя поля ей не отвечает
	 *
	 * @note Имя поля проверяется наравне со значением: оно ложится в текст той же
	 *       записью с экранированием и негодный байт в нём портит текст ровно так же
	 */
	if((this->_settings.malformed == malformed_t::REFUSE) && !::conforms(name))
		// Выводим признак неуспешности записи
		return false;
	/**
	 * Если объект уже содержит поля
	 */
	if(!this->_empty)
		// Записываем знак-разделитель полей объекта
		this->_result.push_back(',');
	/**
	 * Если текст оформляется отступами
	 */
	if(this->_settings.format == format_t::PRETTY){
		// Записываем знак перевода строки
		this->_result.push_back('\n');
		// Выполняем запись отступа по глубине вложенности
		this->_result.append((this->_settings.indent > 0 ? (this->_nesting.size() * this->_settings.indent) : this->_nesting.size()), (this->_settings.indent > 0 ? ' ' : '\t'));
	}
	// Выполняем запись имени поля объекта с экранированием
	this->quoted(name);
	// Записываем знак-разделитель имени поля и значения
	this->_result.push_back(':');
	/**
	 * Если текст оформляется отступами
	 */
	if(this->_settings.format == format_t::PRETTY)
		// Записываем знак пробела для отделения значения от имени поля
		this->_result.push_back(' ');
	// Устанавливаем признак записи имени поля объекта
	this->_keyed = true;
	// Выводим признак успешности записи
	return true;
}
