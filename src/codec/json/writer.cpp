/**
 * @brief Безымянное пространство имён вспомогательных объявлений записи текста
 *
 */
namespace {
	/**
	 * @brief Функция записи кодовой точки отменяющей последовательностью
	 *
	 * @param code   записываемая кодовая точка
	 * @param result собираемый текст
	 *
	 */
	static void unicode(const uint32_t code, string & result) noexcept {
		// Хранилище записи кодовой точки
		char buffer[16];
		/**
		 * Если кодовая точка помещается в одно 16-битное слово
		 */
		if(code <= 0xFFFF)
			// Выполняем запись кодовой точки одной последовательностью
			result.append(buffer, static_cast <size_t> (::snprintf(buffer, sizeof(buffer), "\\u%04x", code)));
		/**
		 * Если кодовая точка записывается суррогатной парой
		 */
		else {
			// Получаем кодовую точку, уменьшенную на основание суррогатной пары
			const uint32_t value = (code - 0x10000);
			// Выполняем запись старшего суррогата пары
			result.append(buffer, static_cast <size_t> (::snprintf(buffer, sizeof(buffer), "\\u%04x", (0xD800 + (value >> 10)))));
			// Выполняем запись младшего суррогата пары
			result.append(buffer, static_cast <size_t> (::snprintf(buffer, sizeof(buffer), "\\u%04x", (0xDC00 + (value & 0x3FF)))));
		}
	}
	/**
	 * @brief Функция извлечения кодовой точки из последовательности UTF-8
	 *
	 * @details Разбор ведётся строго по пределам, отведённым кодировкой ведущему байту:
	 * негодной считается не только оборванная последовательность, но и запись кодовой
	 * точки длиннее необходимого, суррогат и точка свыше U+10FFFF. Пределы эти заданы
	 * ведущим байтом порознь, оттого сличение и ведётся по нему, а не общим `80..BF`
	 *
	 * @details При негодной последовательности выдаётся знак замены, а разобранной
	 * считается наибольшая часть её, годная началом последовательности: запись
	 * `C3 28` даёт знак замены и скобку, а не два знака замены. Правило это предписано
	 * кодировкой, и расхождение в нём разошлось бы числом знаков замены
	 *
	 * @param text   разбираемое содержимое
	 * @param offset положение разбираемого байта в содержимом
	 * @param code   полученная кодовая точка
	 * @param valid  признак годности разобранной последовательности
	 * @return       количество разобранных байтов содержимого
	 *
	 */
	static size_t decode(const string & text, const size_t offset, uint32_t & code, bool & valid) noexcept {
		// Получаем ведущий байт последовательности
		const uint8_t letter = static_cast <uint8_t> (text[offset]);
		// Устанавливаем признак годности разобранной последовательности
		valid = false;
		// Устанавливаем знак замены на случай негодной последовательности
		code = 0xFFFD;
		// Количество продолжающих байтов последовательности
		size_t count = 0;
		// Нижний предел первого продолжающего байта последовательности
		uint8_t lower = 0x80;
		// Верхний предел первого продолжающего байта последовательности
		uint8_t upper = 0xBF;
		/**
		 * Если байт является знаком US-ASCII
		 */
		if(letter < 0x80){
			// Устанавливаем кодовую точку знаком US-ASCII
			code = static_cast <uint32_t> (letter);
			// Устанавливаем признак годности разобранной последовательности
			valid = true;
			// Выводим количество разобранных байтов содержимого
			return 1;
		}
		/**
		 * Определяем пределы, отведённые кодировкой ведущему байту
		 *
		 * @note Байты `C0` и `C1` ведущими не бывают вовсе: ими записывалась бы кодовая
		 *       точка, вмещающаяся в один байт. Байты свыше `F4` не бывают ведущими по
		 *       той же причине с другого края - точка свыше U+10FFFF кодировке неведома
		 */
		if((letter >= 0xC2) && (letter <= 0xDF))
			// Устанавливаем количество продолжающих байтов двухбайтовой последовательности
			count = 1;
		/**
		 * Если байт является ведущим байтом трёхбайтовой последовательности
		 */
		else if((letter >= 0xE0) && (letter <= 0xEF)) {
			// Устанавливаем количество продолжающих байтов трёхбайтовой последовательности
			count = 2;
			/**
			 * Если ведущим байтом записывалась бы точка, вмещающаяся в два байта
			 */
			if(letter == 0xE0)
				// Поднимаем нижний предел первого продолжающего байта
				lower = 0xA0;
			/**
			 * Если ведущим байтом записывался бы суррогат
			 *
			 * @note Суррогаты кодировке UTF-8 запрещены: они принадлежат кодировке UTF-16
			 *       и самостоятельными знаками не являются вовсе
			 */
			else if(letter == 0xED)
				// Опускаем верхний предел первого продолжающего байта
				upper = 0x9F;
		/**
		 * Если байт является ведущим байтом четырёхбайтовой последовательности
		 */
		} else if((letter >= 0xF0) && (letter <= 0xF4)) {
			// Устанавливаем количество продолжающих байтов четырёхбайтовой последовательности
			count = 3;
			/**
			 * Если ведущим байтом записывалась бы точка, вмещающаяся в три байта
			 */
			if(letter == 0xF0)
				// Поднимаем нижний предел первого продолжающего байта
				lower = 0x90;
			/**
			 * Если ведущим байтом записывалась бы точка свыше U+10FFFF
			 */
			else if(letter == 0xF4)
				// Опускаем верхний предел первого продолжающего байта
				upper = 0x8F;
		/**
		 * Если байт ведущим байтом последовательности не является
		 */
		} else // Выводим количество разобранных байтов содержимого
			return 1;
		// Устанавливаем значащие разряды ведущего байта
		code = static_cast <uint32_t> (letter & (0x7F >> count));
		/**
		 * Выполняем разбор продолжающих байтов последовательности
		 */
		for(size_t i = 1; i <= count; i++){
			/**
			 * Если продолжающих байтов последовательности в содержимом недостаёт
			 */
			if((offset + i) >= text.size()){
				// Устанавливаем знак замены вместо неполной последовательности
				code = 0xFFFD;
				// Выводим количество байтов, годных началом последовательности
				return i;
			}
			// Получаем очередной продолжающий байт последовательности
			const uint8_t next = static_cast <uint8_t> (text[offset + i]);
			/**
			 * Если байт лежит вне предела, отведённого ему кодировкой
			 *
			 * @note Предел первого продолжающего байта задан ведущим, а прочих - общий
			 */
			if((next < lower) || (next > upper)){
				// Устанавливаем знак замены вместо неправильной последовательности
				code = 0xFFFD;
				// Выводим количество байтов, годных началом последовательности
				return i;
			}
			// Добавляем значащие разряды продолжающего байта к кодовой точке
			code = ((code << 6) | static_cast <uint32_t> (next & 0x3F));
			// Возвращаем пределам продолжающих байтов общий их вид
			lower = 0x80;
			// Возвращаем пределам продолжающих байтов общий их вид
			upper = 0xBF;
		}
		// Устанавливаем признак годности разобранной последовательности
		valid = true;
		// Выводим количество разобранных байтов содержимого
		return (count + 1);
	}
	/**
	 * @brief Функция проверки содержимого на соответствие кодировке UTF-8
	 *
	 * @details Проверка ведётся тем же разбором, каким ведётся и запись: два отдельных
	 * разбора одной и той же строки неминуемо разошлись бы пределами
	 *
	 * @param text проверяемое содержимое
	 * @return     признак соответствия содержимого кодировке
	 *
	 */
	static bool conforms(const string & text) noexcept {
		/**
		 * Выполняем перебор всего содержимого последовательность за последовательностью
		 */
		for(size_t i = 0; i < text.size();){
			// Кодовая точка разбираемой последовательности
			uint32_t code = 0;
			// Признак годности разобранной последовательности
			bool valid = false;
			// Выполняем разбор очередной последовательности содержимого
			i += ::decode(text, i, code, valid);
			/**
			 * Если разобранная последовательность негодна
			 */
			if(!valid)
				// Выводим признак несоответствия содержимого кодировке
				return false;
		}
		// Выводим признак соответствия содержимого кодировке
		return true;
	}
}

