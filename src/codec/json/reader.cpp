#include <cstring>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Внутренние служебные объекты
 *
 */
namespace {
	/**
	 * Единицы во всяком байте слова
	 */
	static constexpr uint64_t ONES = 0x0101010101010101ULL;
	/**
	 * Старший бит всякого байта слова
	 */
	static constexpr uint64_t HIGH = 0x8080808080808080ULL;

	/**
	 * @brief Функция чтения восьми байтов исходного текста словом
	 *
	 * @details Слово читается переносом, а не приведением указания: приведение указания
	 *          к слову нарушает и правило соответствия видов, и требование выравнивания
	 *
	 * @param buffer буфер читаемых байтов исходного текста
	 * @return       прочитанное слово
	 *
	 */
	static inline uint64_t reading(const char * buffer) noexcept {
		// Прочитанное слово
		uint64_t result = 0;
		// Выполняем чтение восьми байтов исходного текста
		::memcpy(& result, buffer, sizeof(result));
		// Выводим прочитанное слово
		return result;
	}
	/**
	 * @brief Функция поиска в слове байта меньше заданного
	 *
	 * @param word  слово, в каком ведётся поиск
	 * @param bound граница, меньше какой разыскивается байт
	 * @return      отметки старшими битами найденных байтов
	 *
	 */
	static inline uint64_t lesser(const uint64_t word, const uint64_t bound) noexcept {
		// Выводим отметки байтов, меньших заданной границы
		return ((word - (ONES * bound)) & ~word);
	}
	/**
	 * @brief Функция поиска в слове байта больше заданного
	 *
	 * @note Имя «greater» занято стандартной библиотекой, и своё пришлось назвать иначе
	 *
	 * @note Байты со старшим битом отмечаются тоже: слагаемое их не переполняет, но
	 *       собственный старший бит остаётся при них и попадает в отметку через «или»
	 *
	 * @param word  слово, в каком ведётся поиск
	 * @param bound граница, больше какой разыскивается байт
	 * @return      отметки старшими битами найденных байтов
	 *
	 */
	static inline uint64_t above(const uint64_t word, const uint64_t bound) noexcept {
		// Выводим отметки байтов, больших заданной границы
		return ((word + (ONES * (0x7F - bound))) | word);
	}
	/**
	 * @brief Функция поиска в слове байта, равного заданному
	 *
	 * @param word  слово, в каком ведётся поиск
	 * @param match слово, во всяком байте какого лежит разыскиваемый байт
	 * @return      отметки старшими битами найденных байтов
	 *
	 */
	static inline uint64_t equal(const uint64_t word, const uint64_t match) noexcept {
		// Получаем слово, обнулённое в местах совпадения байтов
		const uint64_t found = (word ^ match);
		// Выводим отметки байтов, равных разыскиваемому
		return ((found - ONES) & ~found);
	}
	/**
	 * @brief Функция проверки знака на принадлежность к пробельным
	 *
	 * @details Стандарт числит пробельными ровно четыре знака: пробел, знак табуляции,
	 *          перевод строки и возврат каретки. Прочие знаки, какие в обиходе зовут
	 *          пробельными, - вертикальная табуляция, перевод страницы, неразрывный
	 *          пробел - стандартом пробельными не числятся вовсе
	 *
	 * @param letter проверяемый знак
	 * @return       признак принадлежности знака к пробельным
	 *
	 */
	static inline bool spacing(const char letter) noexcept {
		// Выводим признак принадлежности знака к пробельным
		return ((letter == ' ') || (letter == '\t') || (letter == '\n') || (letter == '\r'));
	}
	/**
	 * @brief Функция преобразования шестнадцатеричного знака в его значение
	 *
	 * @param letter преобразуемый знак
	 * @param result переменная, куда помещается значение знака
	 * @return       признак того, что знак является шестнадцатеричным
	 *
	 */
	static inline bool hexadecimal(const char letter, uint32_t & result) noexcept {
		/**
		 * Если знак является десятичной цифрой
		 */
		if((letter >= '0') && (letter <= '9')){
			// Устанавливаем значение знака
			result = static_cast <uint32_t> (letter - '0');
			// Выводим признак того, что знак является шестнадцатеричным
			return true;
		}
		/**
		 * Если знак является строчной буквой шестнадцатеричной цифры
		 */
		if((letter >= 'a') && (letter <= 'f')){
			// Устанавливаем значение знака
			result = static_cast <uint32_t> (letter - 'a') + 10;
			// Выводим признак того, что знак является шестнадцатеричным
			return true;
		}
		/**
		 * Если знак является прописной буквой шестнадцатеричной цифры
		 */
		if((letter >= 'A') && (letter <= 'F')){
			// Устанавливаем значение знака
			result = static_cast <uint32_t> (letter - 'A') + 10;
			// Выводим признак того, что знак является шестнадцатеричным
			return true;
		}
		// Выводим признак того, что знак шестнадцатеричным не является
		return false;
	}
	/**
	 * @brief Функция записи кодового значения знака в кодировке UTF-8
	 *
	 * @param code   записываемое кодовое значение знака
	 * @param result текст, к которому дописывается знак
	 *
	 */
	static void codepoint(const uint32_t code, string & result) noexcept {
		/**
		 * Если кодовое значение записывается одним байтом
		 */
		if(code < 0x80)
			// Выполняем добавление знака к тексту
			result.push_back(static_cast <char> (code));
		/**
		 * Если кодовое значение записывается двумя байтами
		 */
		else if(code < 0x800) {
			// Выполняем добавление первого байта знака к тексту
			result.push_back(static_cast <char> (0xC0 | (code >> 6)));
			// Выполняем добавление второго байта знака к тексту
			result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
		/**
		 * Если кодовое значение записывается тремя байтами
		 */
		} else if(code < 0x10000) {
			// Выполняем добавление первого байта знака к тексту
			result.push_back(static_cast <char> (0xE0 | (code >> 12)));
			// Выполняем добавление второго байта знака к тексту
			result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
			// Выполняем добавление третьего байта знака к тексту
			result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
		/**
		 * Если кодовое значение записывается четырьмя байтами
		 */
		} else {
			// Выполняем добавление первого байта знака к тексту
			result.push_back(static_cast <char> (0xF0 | (code >> 18)));
			// Выполняем добавление второго байта знака к тексту
			result.push_back(static_cast <char> (0x80 | ((code >> 12) & 0x3F)));
			// Выполняем добавление третьего байта знака к тексту
			result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
			// Выполняем добавление четвёртого байта знака к тексту
			result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
		}
	}
}

/**
 * @brief Конструктор
 *
 */
