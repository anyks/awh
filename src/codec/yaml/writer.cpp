/**
 * @brief Метод закрытия открытого вместилища
 *
 * @return признак успешного закрытия вместилища
 *
 */
bool awh::codec::yaml::Writer::close() noexcept {
	/**
	 * Если ни одно вместилище не открыто
	 */
	if(this->_levels.empty())
		// Выводим признак неудачного закрытия вместилища
		return false;
	// Получаем закрываемое вместилище записи
	const level_t level = this->_levels.back();
	// Выполняем снятие закрываемого вместилища со стопы
	this->_levels.pop_back();
	/**
	 * Если вместилище записывается поточным построением
	 */
	if(level.layout == layout_t::FLOW){
		/**
		 * Если имя пары осталось без значения своего
		 */
		if(this->_keyed)
			// Выполняем сброс признака записанного имени пары
			this->_keyed = false;
		// Выполняем добавление закрывающей скобки построения
		this->_result.push_back((level.kind == kind_t::SEQUENCE) ? ']' : '}');
		/**
		 * Если вместилище было последним открытым
		 *
		 * @note Строка закрывается лишь тогда, когда поточное построение стояло само по
		 *       себе: построение внутри построения строки не закрывает, ибо за ним стоит
		 *       ещё запятая либо скобка
		 */
		if(this->_levels.empty() || (this->_levels.back().layout == layout_t::BLOCK))
			// Выполняем закрытие открытой строки
			this->line();
		// Выводим признак успешного закрытия вместилища
		return true;
	}
	/**
	 * Если вместилище значений так и не получило
	 *
	 * @details Блочное построение пустоту выразить не в силах: отступом обозначается
	 *          содержимое, а содержимого нет вовсе. Записью пустого вместилища остаются
	 *          одни скобки, и записать их надлежит прежде закрытия строки - иначе они
	 *          оказались бы строкою ниже, отдельно от имени своей пары
	 */
	if(level.empty){
		// Выполняем сброс признака записанного имени пары
		this->_keyed = false;
		/**
		 * Если строка вместилищем открыта не была
		 */
		if(!this->_hanging)
			// Выполняем добавление отступа вместилища
			this->_result.append(level.indent, ' ');
		// Выполняем добавление разделителя записей перед скобками
		this->spaced();
		// Выполняем запись свойств узла, накопленных прежде него
		this->properties();
		// Выполняем добавление разделителя записей перед скобками
		this->spaced();
		// Выполняем добавление скобок пустого вместилища
		this->_result.append((level.kind == kind_t::SEQUENCE) ? "[]" : "{}");
		// Запоминаем признак открытой строки
		this->_hanging = true;
	}
	// Выполняем закрытие открытой строки
	this->line();
	// Выводим признак успешного закрытия вместилища
	return true;
}
/**
 * @brief Метод записи имени пары отображения
 *
 * @param name записываемое имя пары отображения
 * @return     признак успешной записи имени пары
 *
 */
bool awh::codec::yaml::Writer::key(const string & name) noexcept {
	/**
	 * Если ни одно вместилище не открыто либо открыт перечень значений
	 */
	if(this->_levels.empty() || (this->_levels.back().kind != kind_t::MAPPING))
		// Выводим признак неудачной записи имени пары
		return false;
	/**
	 * Если имя пары записано, а значение её ещё нет
	 */
	if(this->_keyed)
		// Выводим признак неудачной записи имени пары
		return false;
	/**
	 * Если поставить запись на своё место не удалось
	 */
	if(!this->enter())
		// Выводим признак неудачной записи имени пары
		return false;
	// Выполняем добавление разделителя записей перед именем пары
	this->spaced();
	/**
	 * Получаем ограду, какою обносится имя пары
	 *
	 * @note Имя пары ограды требует чаще значения: двоеточие с пробелом внутри его
	 *       разделило бы пару надвое, а разбор прочёл бы половину имени именем
	 */
	const style_t style = ((this->_settings.quoting == style_t::PLAIN) ?
	 quoting(name, this->_settings.schema, true) : this->_settings.quoting);
	// Выполняем запись имени пары выбранной оградою
	this->quoted(name, style);
	// Выполняем добавление разделителя имени пары
	this->_result.push_back(':');
	// Запоминаем признак записанного имени пары
	this->_keyed = true;
	// Запоминаем признак открытой строки
	this->_hanging = true;
	// Выводим признак успешной записи имени пары
	return true;
}
/**
 * @brief Метод записи метки, следующему узлу предпосылаемой
 *
 * @param name записываемое имя метки
 * @return     признак успешной записи метки
 *
 */
bool awh::codec::yaml::Writer::anchor(const string & name) noexcept {
	/**
	 * Если имя метки построено ошибочно
	 */
	if(name.empty() || !anchored(name))
		// Выводим признак неудачной записи метки
		return false;
	// Запоминаем имя метки, узла своего ожидающей
	this->_anchor.assign(name);
	// Выводим признак успешной записи метки
	return true;
}
/**
 * @brief Метод записи метки типа, следующему узлу предпосылаемой
 *
 * @param name записываемая метка типа
 * @return     признак успешной записи метки типа
 *
 */
bool awh::codec::yaml::Writer::tag(const string & name) noexcept {
	/**
	 * Если метка типа пуста
	 */
	if(name.empty())
		// Выводим признак неудачной записи метки типа
		return false;
	/**
	 * Если метка типа передана сокращением своим
	 */
	if(name.front() == '!'){
		// Запоминаем метку типа, узла своего ожидающую
		this->_tag.assign(name);
		// Выводим признак успешной записи метки типа
		return true;
	}
	/**
	 * Если метка типа описанием задана
	 */
	if(name.compare(0, STANDARD_TAG.size(), STANDARD_TAG) == 0){
		// Запоминаем сокращение метки типа, описанием закреплённое
		this->_tag.assign("!!");
		// Выполняем добавление окончания метки типа
		this->_tag.append(name, STANDARD_TAG.size(), string::npos);
		// Выводим признак успешной записи метки типа
		return true;
	}
	// Запоминаем метку типа записью указателя дословно
	this->_tag.assign("!<");
	// Выполняем добавление записи указателя метки типа
	this->_tag.append(name);
	// Выполняем добавление окончания дословной записи
	this->_tag.push_back('>');
	// Выводим признак успешной записи метки типа
	return true;
}
/**
 * @brief Метод записи ссылки на объявленную метку
 *
 * @param name имя метки, на которую указывает ссылка
 * @return     признак успешной записи ссылки
 *
 */
bool awh::codec::yaml::Writer::alias(const string & name) noexcept {
	/**
	 * Если имя метки построено ошибочно
	 */
	if(name.empty() || !anchored(name))
		// Выводим признак неудачной записи ссылки
		return false;
	/**
	 * Если ссылке предпослано свойство узла
	 *
	 * @note Ссылка узлом не является - она указывает на узел, прежде объявленный, - и
	 *       своих свойств иметь не вправе
	 */
	if(!this->_anchor.empty() || !this->_tag.empty())
		// Выводим признак неудачной записи ссылки
		return false;
	/**
	 * Если поставить запись на своё место не удалось
	 */
	if(!this->enter())
		// Выводим признак неудачной записи ссылки
		return false;
	// Выполняем добавление разделителя записей перед ссылкой
	this->spaced();
	// Выполняем добавление знака ссылки
	this->_result.push_back('*');
	// Выполняем добавление имени метки, ссылкою указанной
	this->_result.append(name);
	/**
	 * Если ссылка записана блочным построением
	 */
	if(this->_levels.empty() || (this->_levels.back().layout == layout_t::BLOCK)){
		// Запоминаем признак строки, записью ссылки открытой
		this->_hanging = true;
		// Выполняем закрытие строки записанной ссылки
		this->line();
	// Если ссылка записана поточным построением
	} else this->_hanging = true;
	// Выводим признак успешной записи ссылки
	return true;
}
/**
 * @brief Метод записи значения дословно, как оно передано
 *
 * @param value записываемое содержимое
 * @return      признак успешной записи содержимого
 *
 */
bool awh::codec::yaml::Writer::raw(const string & value) noexcept {
	/**
	 * Если поставить запись на своё место не удалось
	 */
	if(!this->enter())
		// Выводим признак неудачной записи содержимого
		return false;
	// Выполняем запись свойств узла, накопленных прежде него
	this->properties();
	/**
	 * Если записываемое содержимое не пусто
	 */
	if(!value.empty())
		// Выполняем добавление разделителя записей перед содержимым
		this->spaced();
	// Выполняем добавление записываемого содержимого
	this->_result.append(value);
	/**
	 * Если содержимое записано блочным построением
	 */
	if(this->_levels.empty() || (this->_levels.back().layout == layout_t::BLOCK)){
		/**
		 * Запоминаем признак открытой строки по записанному содержимому
		 *
		 * @note Признак берётся с записанного, а не с прежнего состояния: значение, корнем
		 *       документа стоящее, вместилища над собою не имеет, и ставить признак было
		 *       некому - строка оставалась незакрытой, а черта следующего документа
		 *       приписывалась к ней вплотную. Нашёл это ворошитель сличением перезаписи
		 */
		this->_hanging = (!this->_result.empty() && (this->_result.back() != '\n'));
		// Выполняем закрытие строки записанного содержимого
		this->line();
	// Если содержимое записано поточным построением
	} else this->_hanging = true;
	// Выводим признак успешной записи содержимого
	return true;
}
/**
 * @brief Метод записи пустого значения
 *
 * @return признак успешной записи значения
 *
 */
bool awh::codec::yaml::Writer::null() noexcept {
	// Выполняем запись пустого значения записью описания
	return this->raw("null");
}
/**
 * @brief Метод записи логического значения
 *
 * @param value записываемое логическое значение
 * @return      признак успешной записи значения
 *
 */
bool awh::codec::yaml::Writer::value(const bool value) noexcept {
	// Выполняем запись логического значения записью описания
	return this->raw(value ? "true" : "false");
}
/**
 * @brief Метод записи строкового значения заданной оградою
 *
 * @param value записываемое строковое значение
 * @param style ограда, какою обносится значение
 * @return      признак успешной записи значения
 *
 */
bool awh::codec::yaml::Writer::value(const string & value, const style_t style) noexcept {
	/**
	 * Если поставить запись на своё место не удалось
	 */
	if(!this->enter())
		// Выводим признак неудачной записи значения
		return false;
	// Выполняем запись свойств узла, накопленных прежде него
	this->properties();
	/**
	 * Если записываемое значение не пусто либо обнесено оградою
	 *
	 * @note Пустое значение без ограды пишется пустотою же, и разделитель перед нею
	 *       оставил бы в конце строки пробел, ничего не значащий
	 */
	if(!value.empty() || (style != style_t::PLAIN))
		// Выполняем добавление разделителя записей перед значением
		this->spaced();
	// Выполняем запись значения выбранной оградою
	this->quoted(value, style);
	/**
	 * Если значение записано блочным построением
	 */
	if(this->_levels.empty() || (this->_levels.back().layout == layout_t::BLOCK)){
		// Запоминаем признак строки, записью значения открытой
		this->_hanging = true;
		// Выполняем закрытие строки записанного значения
		this->line();
	// Если значение записано поточным построением
	} else this->_hanging = true;
	// Выводим признак успешной записи значения
	return true;
}
/**
 * @brief Метод записи строкового значения
 *
 * @param value записываемое строковое значение
 * @return      признак успешной записи значения
 *
 */
bool awh::codec::yaml::Writer::value(const string & value) noexcept {
	/**
	 * Получаем ограду, какою обносится записываемое значение
	 *
	 * @note Ограда ставится там, где без неё запись прочлась бы иначе: `12` без ограды
	 *       есть число, а `no` схемою наречия 1.1 есть ложь. Решает это одно тело на весь
	 *       кодек - то же самое, которым решает и разбор
	 */
	const style_t style = ((this->_settings.quoting == style_t::PLAIN) ?
	 quoting(value, this->_settings.schema, false) : this->_settings.quoting);
	// Выполняем запись строкового значения выбранной оградою
	return this->value(value, style);
}
/**
 * @brief Метод записи строкового значения
 *
 * @param value записываемое строковое значение
 * @return      признак успешной записи значения
 *
 */
bool awh::codec::yaml::Writer::value(const char * value) noexcept {
	// Выполняем запись строкового значения
	return this->value(string(value != nullptr ? value : ""));
}
