	/**
	 * Если ссылка недействительна
	 */
	if(!this->valid())
		// Выводим пустое имя пары отображения
		return string_view();
	// Получаем узел, на какой указывает ссылка
	const node_t & node = this->_doc->_nodes.at(this->_index);
