/**
 * @brief Метод сброса дерева документа
 *
 */
void awh::codec::yaml::Document::clear() noexcept {
	// Выполняем сброс перечня узлов дерева
	this->_nodes.clear();
	// Выполняем сброс перечня свойств узлов
	this->_props.clear();
	// Выполняем сброс хранилища имён и записей значений
	this->_storage.clear();
	// Выполняем сброс указателей имён пар отображений
	this->_index.clear();
	// Выполняем сброс удержанного исходного текста
	this->_source.clear();
	// Выполняем сброс длины метки порядка байтов
	this->_prologue = 0;
	// Выполняем сброс кодировки, какою текст прочитан
	this->_encoding = encoding_t::NONE;
	// Выполняем сброс номеров корневых узлов документов
	this->_roots.clear();
	// Выполняем очистку наречий документов потока
	this->_dialects.clear();
	// Выполняем очистку признаков объявленного наречия документов потока
	this->_versions.clear();
	// Выполняем сброс смещений начала документов
	this->_starts.clear();
	// Выполняем сброс кода ошибки разбора текста
	this->_error = error_t::NONE;
	// Выполняем сброс положения отказа разбора
	this->_location = location_t();
}
