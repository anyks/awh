using namespace awh::codec::yaml;

/**
 * @brief Внутренние помощники приведения кодировок
 *
 */
namespace {
	/**
	 * @brief Значение старшего суррогата, с какого начинается их отрезок
	 *
	 */
	static constexpr uint32_t SURROGATE_HIGH = 0xD800;

	/**
	 * @brief Значение младшего суррогата, с какого начинается их отрезок
	 *
	 */
	static constexpr uint32_t SURROGATE_LOW = 0xDC00;

	/**
	 * @brief Значение, за каким отрезок суррогатов оканчивается
	 *
	 */
	static constexpr uint32_t SURROGATE_END = 0xE000;

	/**
	 * @brief Функция сборки знака Юникода из пары суррогатов
	 *
	 * @param high старший суррогат пары
	 * @param low  младший суррогат пары
	 * @return     собранный знак Юникода
	 *
	 */
	static uint32_t paired(const uint32_t high, const uint32_t low) noexcept {
		// Выводим собранный из пары суррогатов знак Юникода
		return (0x10000 + (((high - SURROGATE_HIGH) << 10) | (low - SURROGATE_LOW)));
	}
	/**
	 * @brief Функция получения длины метки порядка байтов заданной кодировки
	 *
	 * @param buffer   начало исходного текста
	 * @param size     размер начала исходного текста
	 * @param encoding кодировка, метка которой разыскивается
	 * @return         длина метки порядка байтов, ноль - метки нет
	 *
	 */
	static size_t signature(const uint8_t * buffer, const size_t size, const encoding_t encoding) noexcept {
		/**
		 * Определяем кодировку, метка которой разыскивается
		 */
		switch(static_cast <uint8_t> (encoding)){
			// Если разыскивается метка кодировки UTF-8
			case static_cast <uint8_t> (encoding_t::UTF8):
				// Выводим длину метки порядка байтов кодировки UTF-8
				return (((size >= 3) && (buffer[0] == 0xEF) && (buffer[1] == 0xBB) && (buffer[2] == 0xBF)) ? 3 : 0);
			// Если разыскивается метка кодировки UTF-16 с обратным порядком байтов
			case static_cast <uint8_t> (encoding_t::UTF16LE):
				/**
				 * Выводим длину метки порядка байтов кодировки UTF-16
				 *
				 * @note Метка кодировки UTF-32 с обратным порядком байтов открывается теми же
				 *       двумя байтами, и признать её меткою UTF-16 значило бы съесть два
				 *       нулевых байта, знаку принадлежащих
				 */
				return (((size >= 2) && (buffer[0] == 0xFF) && (buffer[1] == 0xFE) &&
				 !((size >= 4) && (buffer[2] == 0x00) && (buffer[3] == 0x00))) ? 2 : 0);
			// Если разыскивается метка кодировки UTF-16 с прямым порядком байтов
			case static_cast <uint8_t> (encoding_t::UTF16BE):
				// Выводим длину метки порядка байтов кодировки UTF-16
				return (((size >= 2) && (buffer[0] == 0xFE) && (buffer[1] == 0xFF)) ? 2 : 0);
			// Если разыскивается метка кодировки UTF-32 с обратным порядком байтов
			case static_cast <uint8_t> (encoding_t::UTF32LE):
				// Выводим длину метки порядка байтов кодировки UTF-32
				return (((size >= 4) && (buffer[0] == 0xFF) && (buffer[1] == 0xFE) &&
				 (buffer[2] == 0x00) && (buffer[3] == 0x00)) ? 4 : 0);
			// Если разыскивается метка кодировки UTF-32 с прямым порядком байтов
			case static_cast <uint8_t> (encoding_t::UTF32BE):
				// Выводим длину метки порядка байтов кодировки UTF-32
				return (((size >= 4) && (buffer[0] == 0x00) && (buffer[1] == 0x00) &&
				 (buffer[2] == 0xFE) && (buffer[3] == 0xFF)) ? 4 : 0);
		}
		/**
		 * @warning Выдача эта есть застава последнего рубежа, ничем не задетая: перебор
		 *          выше несёт ветвь на всякую кодировку перечня, кроме NONE, а зовётся
		 *          отсюда лишь кодировка разрешённая. Сносу выдача не подлежит по доводу
		 *          заставы
		 */
		// Выводим отсутствие метки порядка байтов
		return 0;
	}
	/**
	 * @brief Функция получения наибольшей длины метки порядка байтов заданной кодировки
	 *
	 * @param encoding кодировка, метка которой разыскивается
	 * @return         наибольшее количество байт, опознанию метки потребное
	 *
	 */
	static size_t marking(const encoding_t encoding) noexcept {
		/**
		 * Определяем кодировку, метка которой разыскивается
		 */
		switch(static_cast <uint8_t> (encoding)){
			// Если разыскивается метка кодировки UTF-8
			case static_cast <uint8_t> (encoding_t::UTF8):
				// Выводим длину метки порядка байтов кодировки UTF-8
				return 3;
			/**
			 * Если разыскивается метка кодировки UTF-16 с обратным порядком байтов
			 *
			 * @note Четыре байта здесь нужны не самой метке, а отличению её от метки
			 *       кодировки UTF-32, теми же двумя байтами открывающейся
			 */
			case static_cast <uint8_t> (encoding_t::UTF16LE):
			// Если разыскивается метка кодировки UTF-32 любого порядка байтов
			case static_cast <uint8_t> (encoding_t::UTF32LE):
			case static_cast <uint8_t> (encoding_t::UTF32BE):
				// Выводим длину метки порядка байтов кодировки UTF-32
				return 4;
			// Если разыскивается метка кодировки UTF-16 с прямым порядком байтов
			case static_cast <uint8_t> (encoding_t::UTF16BE):
				// Выводим длину метки порядка байтов кодировки UTF-16
				return 2;
		}
		/**
		 * @warning Выдача эта есть застава последнего рубежа, ничем не задетая: перебор
		 *          выше несёт ветвь на всякую кодировку перечня, кроме NONE, а зовётся
		 *          отсюда лишь кодировка разрешённая. Сносу выдача не подлежит по доводу
		 *          заставы
		 */
		// Выводим отсутствие метки порядка байтов
		return 0;
	}
}

/**
 * @brief Функция получения длины последовательности UTF-8 по ведущему байту
 *
 * @param leading ведущий байт последовательности
 * @return        количество байт последовательности, ноль - байт построен ошибочно
 *
 */
size_t awh::codec::yaml::sequence(const uint8_t leading) noexcept {
	/**
	 * Если знак записан одним байтом
	 */
	if(leading < 0x80)
		// Выводим количество байт последовательности знака
		return 1;
	/**
	 * Если знак записан двумя байтами
	 */
	/**
	 * Если байт ведущим не бывает вовсе
	 *
	 * @details Байты `C0` и `C1` открывали бы запись длиннее необходимой, а байты свыше
	 *          `F4` - точку свыше U+10FFFF. Ни того, ни другого кодировка не допускает, и
	 *          ведущими они не бывают ни при каком продолжении
	 *
	 * @note Прежде они принимались ведущими, и негодность обнаруживалась лишь по прочтении
	 *       всей последовательности: `C0 80` числилось одной негодной последовательностью
	 *       в два байта вместо двух негодных байтов. Наружу это торчит числом знаков
	 *       замены при записи
	 */
	else if((leading == 0xC0) || (leading == 0xC1) || (leading > 0xF4))
		// Выводим признак ошибочного построения последовательности
		return 0;
	else if((leading & 0xE0) == 0xC0)
		// Выводим количество байт последовательности знака
		return 2;
	/**
	 * Если знак записан тремя байтами
	 */
	else if((leading & 0xF0) == 0xE0)
		// Выводим количество байт последовательности знака
		return 3;
	/**
	 * Если знак записан четырьмя байтами
	 */
	else if((leading & 0xF8) == 0xF0)
		// Выводим количество байт последовательности знака
		return 4;
	// Выводим признак ошибочного построения последовательности
	return 0;
}
/**
 * @brief Функция разбора очередной последовательности UTF-8
 *
 * @param text   последовательность знаков, из которой ведётся чтение
 * @param offset положение начала знака в последовательности
 * @param code   получаемый знак Юникода, при неудачном разборе не выставляется
 * @param length количество байт, разбором пройденных, при нехватке байт нулевое
 * @return       исход разбора последовательности
 *
 */
utf8_t awh::codec::yaml::inspect(const string_view text, const size_t offset, uint32_t & code, size_t & length) noexcept {
	// Выполняем сброс количества пройденных разбором байт
	length = 0;
	/**
	 * Если читать знак неоткуда
	 */
	if(offset >= text.length())
		// Выводим признак нехватки байт последовательности
		return utf8_t::TRUNCATED;
	// Получаем ведущий байт знака Юникода
	const uint8_t leading = static_cast <uint8_t> (text[offset]);
	// Получаем количество байт последовательности знака Юникода
	const size_t count = sequence(leading);
	/**
	 * Если ведущий байт построен ошибочно
	 */
	if(count == 0){
		// Запоминаем количество байт, разбором пройденных
		length = 1;
		// Выводим признак ошибочного построения последовательности
		return utf8_t::BROKEN;
	}
	/**
	 * Если знак записан одним байтом
	 */
	if(count == 1){
		// Запоминаем знак Юникода
		code = leading;
		// Запоминаем количество байт, разбором пройденных
		length = 1;
		// Выводим признак успешного разбора последовательности
		return utf8_t::VALID;
	}
	// Разряды знака Юникода, ведущим байтом заданные
	static constexpr uint32_t LEADING[] = {0x00, 0x00, 0x1F, 0x0F, 0x07};
	// Запоминаем разряды знака, ведущим байтом заданные
	uint32_t result = (leading & LEADING[count]);
	/**
	 * Выполняем перебор всех продолжающих байт знака Юникода
	 */
	for(size_t i = 1; i < count; i++){
		/**
		 * Если очередного байта последовательности нет вовсе
		 *
		 * @details Исход этот от ошибочного построения отделён намеренно: кусок, оборвавший
		 *          знак посередине, ошибкою не является, и разбор обязан дождаться
		 *          продолжения. Длиною при том выдаётся число байт, налицо имеющихся, - они
		 *          и составляют наибольшую часть последовательности
		 *
		 * @note Проверка эта стоит **внутри** перебора, а не до него: прежде она стояла
		 *       раньше, и запись `E1 41` числилась оборванной, тогда как байт `41`
		 *       продолжающим не бывает и никакое продолжение записи той уже не выправит.
		 *       Чтение потоковое ждало бы такую запись до конца текста впустую
		 */
		if((offset + i) >= text.length()){
			// Запоминаем количество байт последовательности, налицо имеющихся
			length = i;
			// Выводим признак нехватки байт последовательности
			return utf8_t::TRUNCATED;
		}
		// Получаем очередной продолжающий байт знака Юникода
		const uint8_t letter = static_cast <uint8_t> (text[offset + i]);
		/**
		 * Получаем нижний предел продолжающего байта
		 *
		 * @details Первый продолжающий байт предел свой берёт у байта ведущего, а не общий
		 *          `80..BF`: `E0` требует от него `A0`, а `F0` - `90`, ибо ниже пошла бы
		 *          запись длиннее необходимой, и предел общий её пропускал бы
		 */
		const uint8_t bottom = ((i > 1) ? 0x80 : ((leading == 0xE0) ? 0xA0 : ((leading == 0xF0) ? 0x90 : 0x80)));
		/**
		 * Получаем верхний предел продолжающего байта
		 *
		 * @details `ED` требует от первого продолжающего байта не свыше `9F`, ибо выше
		 *          пошли бы суррогаты, а `F4` - не свыше `8F`, ибо выше пошли бы точки
		 *          свыше U+10FFFF
		 *
		 * @note Пределами этими запись длиннее необходимой, суррогат и точка вне пределов
		 *       закрываются разом, а граница негодной последовательности ложится по
		 *       правилу наибольшей части - на первом байте, стоять там не могшем
		 */
		const uint8_t ceiling = ((i > 1) ? 0xBF : ((leading == 0xED) ? 0x9F : ((leading == 0xF4) ? 0x8F : 0xBF)));
		/**
		 * Если байт продолжающим не является либо предел свой нарушает
		 */
		if((letter < bottom) || (letter > ceiling)){
			// Запоминаем количество байт, разбором пройденных
			length = i;
			// Выводим признак ошибочного построения последовательности
			return utf8_t::BROKEN;
		}
		// Выполняем добавление разрядов знака, байтом заданных
		result = ((result << 6) | (letter & 0x3F));
	}
	// Запоминаем количество байт, разбором пройденных
	length = count;
	/**
	 * @note Проверок на запись длиннее необходимой, на суррогат и на точку свыше U+10FFFF
	 *       здесь нет намеренно: пределы, ведущему байту порознь отведённые, закрывают все
	 *       три разом и закрывают раньше - на первом байте, стоять там не могшем. Проверка
	 *       по прочтении всей последовательности не только лишняя, но и вредная: границу
	 *       негодной части она кладёт неверно, и чтение съедало бы годный знак, стоящий
	 *       сразу за негодным байтом
	 */
	// Запоминаем прочитанный знак Юникода
	code = result;
	// Выводим признак успешного разбора последовательности
	return utf8_t::VALID;
}
/**
 * @brief Функция получения очередного знака Юникода последовательности UTF-8
 *
 * @param text   последовательность знаков, из которой ведётся чтение
 * @param offset положение начала знака в последовательности
 * @param code   получаемый знак Юникода
 * @return       количество байт знака, ноль - знак битый либо оборванный
 *
 */
size_t awh::codec::yaml::decode(const string_view text, const size_t offset, uint32_t & code) noexcept {
	// Количество байт, разбором пройденных
	size_t length = 0;
	/**
	 * Если разобрать очередную последовательность не удалось
	 */
	if(inspect(text, offset, code, length) != utf8_t::VALID)
		// Выводим признак неудачного разбора последовательности
		return 0;
	// Выводим количество байт разобранного знака
	return length;
}
/**
 * @brief Функция записи знака Юникода последовательностью UTF-8
 *
 * @param code   записываемый знак Юникода
 * @param result строка, куда дописывается последовательность
 * @return       признак успешной записи знака
 *
 */
bool awh::codec::yaml::encode(const uint32_t code, string & result) noexcept {
	/**
	 * Если знак в набор Юникода не укладывается либо является суррогатом
	 */
	if((code > MAX_CODEPOINT) || ((code >= SURROGATE_HIGH) && (code < SURROGATE_END)))
		// Выводим признак неудачной записи знака
		return false;
	/**
	 * Если знак записывается одним байтом
	 */
	if(code < 0x80)
		// Выполняем запись знака одним байтом
		result.push_back(static_cast <char> (code));
	/**
	 * Если знак записывается двумя байтами
	 */
	else if(code < 0x800) {
		// Выполняем запись ведущего байта знака
		result.push_back(static_cast <char> (0xC0 | (code >> 6)));
		// Выполняем запись продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	/**
	 * Если знак записывается тремя байтами
	 */
	} else if(code < 0x10000) {
		// Выполняем запись ведущего байта знака
		result.push_back(static_cast <char> (0xE0 | (code >> 12)));
		// Выполняем запись первого продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
		// Выполняем запись второго продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	/**
	 * Если знак записывается четырьмя байтами
	 */
	} else {
		// Выполняем запись ведущего байта знака
		result.push_back(static_cast <char> (0xF0 | (code >> 18)));
		// Выполняем запись первого продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | ((code >> 12) & 0x3F)));
		// Выполняем запись второго продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | ((code >> 6) & 0x3F)));
		// Выполняем запись третьего продолжающего байта знака
		result.push_back(static_cast <char> (0x80 | (code & 0x3F)));
	}
	// Выводим признак успешной записи знака
	return true;
}
/**
 * @brief Функция проверки знака на принадлежность к печатным
 *
 * @param code проверяемый знак Юникода
 * @return     признак принадлежности знака к печатным
 *
 */
bool awh::codec::yaml::printable(const uint32_t code) noexcept {
	/**
	 * Определяем проверяемый знак Юникода
	 */
	switch(code){
		// Если знак является горизонтальной подачей, переводом строки либо возвратом каретки
		case 0x09:
		case 0x0A:
		case 0x0D:
		// Если знак является сменой строки второго набора управляющих знаков
		case 0x85:
			// Выводим признак принадлежности знака к печатным
			return true;
	}
	/**
	 * Если знак принадлежит к печатным знакам US-ASCII
	 */
	if((code >= 0x20) && (code <= 0x7E))
		// Выводим признак принадлежности знака к печатным
		return true;
	/**
	 * Если знак принадлежит к печатным знакам основной таблицы Юникода
	 *
	 * @note Суррогаты сюда не попадают: отрезок оканчивается перед ними, а следующий
	 *       начинается за ними
	 */
	if((code >= 0xA0) && (code < SURROGATE_HIGH))
		// Выводим признак принадлежности знака к печатным
		return true;
	/**
	 * Если знак принадлежит к печатным знакам за отрезком суррогатов
	 *
	 * @note Два последних знака основной таблицы печатными не признаются описанием
	 */
	if((code >= SURROGATE_END) && (code <= 0xFFFD))
		// Выводим признак принадлежности знака к печатным
		return true;
	// Выводим признак принадлежности знака к печатным по таблицам сверх основной
	return ((code >= 0x10000) && (code <= MAX_CODEPOINT));
}
/**
 * @brief Конструктор
 *
 * @param log объект для работы с логами
 *
 */
awh::codec::yaml::Decoder::Decoder(const log_t * log) noexcept :
 _log(log), _encoding(encoding_t::NONE), _error(error_t::NONE), _sniffed(false),
 _signature(false), _forced(false), _leading(true), _surrogate(0) {}
/**
 * @brief Метод вывода сообщения об отказе в лог
 *
 */
void awh::codec::yaml::Decoder::report() const noexcept {
	/**
	 * Если объект для работы с логами установлен
	 */
	if(this->_log != nullptr)
		// Выполняем вывод сообщения об отказе приведения кодировки
		this->_log->print("YAML encoding failed: %s", log_t::flag_t::CRITICAL, awh::codec::yaml::message(this->_error));
}
/**
 * @brief Метод сброса состояния приведения кодировки
 *
 */
void awh::codec::yaml::Decoder::reset() noexcept {
	/**
	 * Если кодировка навязана извне
	 *
	 * @note Навязанная кодировка сбросу не подлежит: задаётся она до подачи текста, и
	 *       сброс, её снимающий, отменял бы решение потребителя молча
	 */
	if(!this->_forced)
		// Выполняем сброс опознанной кодировки исходного текста
		this->_encoding = encoding_t::NONE;
	// Выполняем сброс кода ошибки приведения кодировки
	this->_error = error_t::NONE;
	// Выполняем сброс признака опознания кодировки
	this->_sniffed = this->_forced;
	// Выполняем сброс признака открытия текста меткой порядка байтов
	this->_signature = false;
	// Выполняем сброс признака непройденного начала текста
	this->_leading = true;
	// Выполняем сброс старшего суррогата, ожидающего пары
	this->_surrogate = 0;
	// Выполняем сброс байтов, оставшихся от прошлого куска
	this->_tail.clear();
}
/**
 * @brief Метод получения опознанной кодировки исходного текста
 *
 * @return опознанная кодировка исходного текста
 *
 */
encoding_t awh::codec::yaml::Decoder::encoding() const noexcept {
	// Выводим опознанную кодировку исходного текста
	return this->_encoding;
}
/**
 * @brief Метод навязывания кодировки исходного текста
 *
 * @param encoding навязываемая кодировка исходного текста
 * @return         признак того, что кодировка принята
 *
 */
bool awh::codec::yaml::Decoder::encoding(const encoding_t encoding) noexcept {
	/**
	 * Если навязывается неопределённая кодировка
	 */
	if(encoding == encoding_t::NONE){
		// Выполняем снятие навязанной кодировки
		this->_forced = false;
		// Выполняем сброс признака опознания кодировки
		this->_sniffed = false;
		// Выполняем сброс опознанной кодировки исходного текста
		this->_encoding = encoding_t::NONE;
		// Выводим признак того, что кодировка принята
		return true;
	}
	// Запоминаем навязанную кодировку исходного текста
	this->_encoding = encoding;
	// Запоминаем признак навязывания кодировки извне
	this->_forced = true;
	// Запоминаем признак опознания кодировки
	this->_sniffed = true;
	// Выводим признак того, что кодировка принята
	return true;
}
/**
 * @brief Метод получения признака открытия текста меткой порядка байтов
 *
 * @return признак открытия текста меткой порядка байтов
 *
 */
bool awh::codec::yaml::Decoder::signature() const noexcept {
	// Выводим признак открытия текста меткой порядка байтов
	return this->_signature;
}
/**
 * @brief Метод получения признака ненадобности приведения
 *
 * @return признак того, что текст записан UTF-8 и приведения не требует
 *
 */
bool awh::codec::yaml::Decoder::direct() const noexcept {
	// Выводим признак того, что текст записан UTF-8 и приведения не требует
	return (this->_sniffed && (this->_encoding == encoding_t::UTF8) && this->_tail.empty());
}
/**
 * @brief Метод получения кода ошибки приведения кодировки
 *
 * @return код ошибки приведения кодировки
 *
 */
awh::codec::yaml::error_t awh::codec::yaml::Decoder::error() const noexcept {
	// Выводим код ошибки приведения кодировки
	return this->_error;
}
/**
 * @brief Метод опознания кодировки по началу исходного текста
 *
 * @param buffer начало исходного текста
 * @param size   размер начала исходного текста
 * @param end    признак того, что текст окончен
 * @return       признак того, что кодировка опознана
 *
 */
bool awh::codec::yaml::Decoder::sniff(const char * buffer, const size_t size, const bool end) noexcept {
	/**
	 * Если опознавать не по чему, а текст ещё не окончен
	 *
	 * @note Опознание требует четырёх октетов: расположение нулевых байтов в них и
	 *       отличает записи парами байтов от записей четвёрками. Куска короче ждём,
	 *       пока текст вправе прирасти
	 */
	if((size < 4) && !end)
		// Выводим признак того, что кодировка ещё не опознана
		return false;
	// Получаем начало исходного текста без знака
	const uint8_t * data = reinterpret_cast <const uint8_t *> (buffer);
	/**
	 * Если текст открывается меткой порядка байтов кодировки UTF-32 с обратным порядком
	 *
	 * @note Метка эта начинается теми же двумя байтами, что и метка UTF-16, и оттого
	 *       сличается прежде неё: сличив короткую первой, мы прочли бы весь текст парами
	 */
	if((size >= 4) && (data[0] == 0xFF) && (data[1] == 0xFE) && (data[2] == 0x00) && (data[3] == 0x00)){
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF32LE;
		// Запоминаем признак открытия текста меткой порядка байтов
		this->_signature = true;
	/**
	 * Если текст открывается меткой порядка байтов кодировки UTF-32 с прямым порядком
	 */
	} else if((size >= 4) && (data[0] == 0x00) && (data[1] == 0x00) && (data[2] == 0xFE) && (data[3] == 0xFF)){
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF32BE;
		// Запоминаем признак открытия текста меткой порядка байтов
		this->_signature = true;
	/**
	 * Если текст открывается меткой порядка байтов кодировки UTF-8
	 */
	} else if((size >= 3) && (data[0] == 0xEF) && (data[1] == 0xBB) && (data[2] == 0xBF)){
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF8;
		// Запоминаем признак открытия текста меткой порядка байтов
		this->_signature = true;
	/**
	 * Если текст открывается меткой порядка байтов кодировки UTF-16 с обратным порядком
	 */
	} else if((size >= 2) && (data[0] == 0xFF) && (data[1] == 0xFE)){
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF16LE;
		// Запоминаем признак открытия текста меткой порядка байтов
		this->_signature = true;
	/**
	 * Если текст открывается меткой порядка байтов кодировки UTF-16 с прямым порядком
	 */
	} else if((size >= 2) && (data[0] == 0xFE) && (data[1] == 0xFF)){
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF16BE;
		// Запоминаем признак открытия текста меткой порядка байтов
		this->_signature = true;
	/**
	 * Если текст меткой порядка байтов не открывается
	 *
	 * @note Опознание идёт расположением нулевых байтов: описание велит первому знаку
	 *       потока быть знаком US-ASCII либо меткой, и нулевые байты вокруг него и
	 *       выдают ширину записи
	 */
	} else if((size >= 4) && (data[0] == 0x00) && (data[1] == 0x00) && (data[2] == 0x00))
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF32BE;
	/**
	 * Если за первым байтом стоят три нулевых
	 */
	else if((size >= 4) && (data[1] == 0x00) && (data[2] == 0x00) && (data[3] == 0x00))
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF32LE;
	/**
	 * Если первый байт нулевой, а второй нет
	 */
	else if((size >= 2) && (data[0] == 0x00) && (data[1] != 0x00))
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF16BE;
	/**
	 * Если второй байт нулевой, а первый нет
	 */
	else if((size >= 2) && (data[0] != 0x00) && (data[1] == 0x00))
		// Запоминаем опознанную кодировку исходного текста
		this->_encoding = encoding_t::UTF16LE;
	/**
	 * Если ничто на иную кодировку не указывает
	 */
	else this->_encoding = encoding_t::UTF8;
	// Запоминаем признак опознания кодировки
	this->_sniffed = true;
	// Выводим признак того, что кодировка опознана
	return true;
}
/**
 * @brief Метод проверки знака на дозволенность его в тексте
 *
 * @param code проверяемый знак Юникода
 * @return     признак дозволенности знака в тексте
 *
 */
bool awh::codec::yaml::Decoder::allowed(const uint32_t code) noexcept {
	/**
	 * Если знак к печатным принадлежит
	 */
	if(printable(code))
		// Выводим признак дозволенности знака в тексте
		return true;
	/**
	 * Запоминаем код ошибки приведения кодировки
	 *
	 * @note Отказом этим объявляется именно недопустимость знака, а не битая запись его:
	 *       байты прочитаны верно, и ошибка не в них, а в том, что знак этот тексту YAML
	 *       не принадлежит
	 */
	this->_error = error_t::INVALID_CHARACTER;
	// Выполняем вывод сообщения об отказе в лог
	this->report();
	// Выводим признак недозволенности знака в тексте
	return false;
}
/**
 * @brief Метод приведения куска текста, записанного парами байтов
 *
 * @param buffer приводимый кусок исходного текста
 * @param size   размер приводимого куска
 * @param end    признак того, что текст окончен
 * @param result строка, куда дописывается приведённый текст
 * @return       признак успешного приведения куска
 *
 */
bool awh::codec::yaml::Decoder::doubled(const char * buffer, const size_t size, const bool end, string & result) noexcept {
	// Получаем приводимый кусок текста без знака
	const uint8_t * data = reinterpret_cast <const uint8_t *> (buffer);
	// Признак обратного порядка байтов записи
	const bool little = (this->_encoding == encoding_t::UTF16LE);
	// Смещение разбираемой пары байтов
	size_t offset = 0;
	/**
	 * Выполняем перебор всех пар байтов приводимого куска
	 */
	while((offset + 2) <= size){
		// Собираем очередную единицу записи из пары байтов
		const uint32_t unit = (little ?
			(static_cast <uint32_t> (data[offset]) | (static_cast <uint32_t> (data[offset + 1]) << 8)) :
			((static_cast <uint32_t> (data[offset]) << 8) | static_cast <uint32_t> (data[offset + 1]))
		);
		// Выполняем переход к следующей паре байтов
		offset += 2;
		/**
		 * Если пары ожидает старший суррогат
		 */
		if(this->_surrogate != 0){
			/**
			 * Если единица записи младшим суррогатом не является
			 */
			if((unit < SURROGATE_LOW) || (unit >= SURROGATE_END)){
				// Запоминаем код ошибки приведения кодировки
				this->_error = error_t::UNPAIRED_SURROGATE;
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим признак неудачного приведения куска
				return false;
			}
			/**
			 * Если знак, из пары суррогатов собранный, в тексте недозволен
			 *
			 * @warning Заход этот есть застава последнего рубежа, ничем не задетая:
			 *          пара суррогатов даёт знак в пределах от 0x10000 до 0x10FFFF, а
			 *          знаки эти `printable` числит печатными все до одного. Сносу
			 *          заход не подлежит: правка `printable` - хоть под иное наречие,
			 *          хоть под запрет знаков-нехарактеров - способна вернуть сюда
			 *          управление, и молчаливая запись недозволенного дала бы текст,
			 *          описанию не отвечающий, вместо отказа
			 */
			if(!this->allowed(paired(this->_surrogate, unit)))
				// Выводим признак неудачного приведения куска
				return false;
			/**
			 * Если записать собранный из пары суррогатов знак не удалось
			 *
			 * @warning Заход этот есть застава последнего рубежа, ничем не задетая:
			 *          приведение к UTF-8 отказывает лишь на знаке вне области
			 *          Юникода, а пара суррогатов даёт знак заведомо в ней. Сносу
			 *          заход не подлежит по доводу заставы: правка поверки выше
			 *          способна пропустить сюда значение негодное
			 */
			if(!encode(paired(this->_surrogate, unit), result)){
				// Запоминаем код ошибки приведения кодировки
				this->_error = error_t::INVALID_ENCODING;
				// Выполняем вывод сообщения об отказе в лог
				this->report();
				// Выводим признак неудачного приведения куска
				return false;
			}
			// Выполняем сброс старшего суррогата, пары дождавшегося
			this->_surrogate = 0;
			// Выполняем переход к следующей паре байтов
			continue;
		}
		/**
		 * Если единица записи является старшим суррогатом
		 */
		if((unit >= SURROGATE_HIGH) && (unit < SURROGATE_LOW)){
			// Запоминаем старший суррогат, ожидающий пары своей
			this->_surrogate = unit;
			// Выполняем переход к следующей паре байтов
			continue;
		}
		/**
		 * Если единица записи является младшим суррогатом, пары не имеющим
		 */
		if((unit >= SURROGATE_LOW) && (unit < SURROGATE_END)){
			// Запоминаем код ошибки приведения кодировки
			this->_error = error_t::UNPAIRED_SURROGATE;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак неудачного приведения куска
			return false;
		}
		/**
		 * Если записать очередной знак не удалось
		 */
		if(!this->allowed(unit))
			// Выводим признак неудачного приведения куска
			return false;
		/**
		 * Если записать очередной знак не удалось
		 *
		 * @warning Заход этот есть застава последнего рубежа, ничем не задетая:
		 *          единица записи шире 0xFFFF не бывает, а знаки эти приведению к
		 *          UTF-8 поддаются все. Сносу заход не подлежит по доводу заставы
		 */
		if(!encode(unit, result)){
			// Запоминаем код ошибки приведения кодировки
			this->_error = error_t::INVALID_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак неудачного приведения куска
			return false;
		}
	}
	/**
	 * Если кусок оборвал единицу записи посередине
	 */
	if(offset < size){
		/**
		 * Если текст окончен, а единица записи не дописана
		 */
		if(end){
			// Запоминаем код ошибки приведения кодировки
			this->_error = error_t::INVALID_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак неудачного приведения куска
			return false;
		}
		// Удерживаем оборванные байты до прихода следующего куска
		this->_tail.assign(buffer + offset, (size - offset));
	}
	/**
	 * Если текст окончен, а старший суррогат пары так и не дождался
	 */
	if(end && (this->_surrogate != 0)){
		// Запоминаем код ошибки приведения кодировки
		this->_error = error_t::UNPAIRED_SURROGATE;
		// Выполняем вывод сообщения об отказе в лог
		this->report();
		// Выводим признак неудачного приведения куска
		return false;
	}
	// Выводим признак успешного приведения куска
	return true;
}
/**
 * @brief Метод приведения куска текста, записанного четвёрками байтов
 *
 * @param buffer приводимый кусок исходного текста
 * @param size   размер приводимого куска
 * @param end    признак того, что текст окончен
 * @param result строка, куда дописывается приведённый текст
 * @return       признак успешного приведения куска
 *
 */
bool awh::codec::yaml::Decoder::quadrupled(const char * buffer, const size_t size, const bool end, string & result) noexcept {
	// Получаем приводимый кусок текста без знака
	const uint8_t * data = reinterpret_cast <const uint8_t *> (buffer);
	// Признак обратного порядка байтов записи
	const bool little = (this->_encoding == encoding_t::UTF32LE);
	// Смещение разбираемой четвёрки байтов
	size_t offset = 0;
	/**
	 * Выполняем перебор всех четвёрок байтов приводимого куска
	 */
	while((offset + 4) <= size){
		// Собираем очередной знак из четвёрки байтов
		const uint32_t code = (little ?
			(static_cast <uint32_t> (data[offset]) |
			 (static_cast <uint32_t> (data[offset + 1]) << 8) |
			 (static_cast <uint32_t> (data[offset + 2]) << 16) |
			 (static_cast <uint32_t> (data[offset + 3]) << 24)) :
			((static_cast <uint32_t> (data[offset]) << 24) |
			 (static_cast <uint32_t> (data[offset + 1]) << 16) |
			 (static_cast <uint32_t> (data[offset + 2]) << 8) |
			 static_cast <uint32_t> (data[offset + 3]))
		);
		// Выполняем переход к следующей четвёрке байтов
		offset += 4;
		/**
		 * Если записать очередной знак не удалось
		 */
		if(!this->allowed(code))
			// Выводим признак неудачного приведения куска
			return false;
		/**
		 * Если записать очередной знак не удалось
		 */
		if(!encode(code, result)){
			// Запоминаем код ошибки приведения кодировки
			this->_error = error_t::INVALID_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак неудачного приведения куска
			return false;
		}
	}
	/**
	 * Если кусок оборвал знак посередине
	 */
	if(offset < size){
		/**
		 * Если текст окончен, а знак не дописан
		 */
		if(end){
			// Запоминаем код ошибки приведения кодировки
			this->_error = error_t::INVALID_ENCODING;
			// Выполняем вывод сообщения об отказе в лог
			this->report();
			// Выводим признак неудачного приведения куска
			return false;
		}
		// Удерживаем оборванные байты до прихода следующего куска
		this->_tail.assign(buffer + offset, (size - offset));
	}
	// Выводим признак успешного приведения куска
	return true;
}
/**
 * @brief Метод приведения очередного куска исходного текста к UTF-8
 *
 * @param buffer приводимый кусок исходного текста
 * @param size   размер приводимого куска
 * @param end    признак того, что текст окончен
 * @param result строка, куда дописывается приведённый текст
 * @return       признак успешного приведения куска
 *
 */
bool awh::codec::yaml::Decoder::convert(const void * buffer, const size_t size, const bool end, string & result) noexcept {
	/**
	 * Если приведение уже отказало
	 *
	 * @note Отказ приведения терминален: кодировка не восстанавливается сама собою, и
	 *       разбор дальнейших кусков выдавал бы мусор вместо отказа
	 */
	if(this->_error != error_t::NONE)
		// Выводим признак неудачного приведения куска
		return false;
	// Собираемый кусок текста вместе с удержанными от прошлого куска байтами
	string chunk;
	// Получаем приводимый кусок текста
	const char * data = reinterpret_cast <const char *> (buffer);
	/**
	 * Если от прошлого куска остались удержанные байты
	 */
	if(!this->_tail.empty()){
		// Выполняем упреждающее выделение памяти под собираемый кусок
		chunk.reserve(this->_tail.size() + size);
		// Выполняем перенос удержанных байтов в собираемый кусок
		chunk.assign(this->_tail);
		/**
		 * Если приводимый кусок передан
		 */
		if((data != nullptr) && (size > 0))
			// Выполняем дописывание приводимого куска
			chunk.append(data, size);
		// Выполняем сброс удержанных байтов
		this->_tail.clear();
		// Переставляем приводимый кусок на собранный
		data = chunk.data();
	}
	// Получаем размер приводимого куска вместе с удержанными байтами
	const size_t length = (chunk.empty() ? size : chunk.size());
	/**
	 * Если приводить нечего
	 */
	if((data == nullptr) || (length == 0))
		// Выводим признак успешного приведения куска
		return true;
	// Смещение начала текста за меткой порядка байтов
	size_t offset = 0;
	/**
	 * Если начало текста ещё не пройдено
	 *
	 * @note Метка порядка байтов снимается независимо от того, опознанием ли кодировка
	 *       добыта либо навязана извне: навязывание значит «не гадай о кодировке», а не
	 *       «оставь метку в тексте». Прежде снятие шло лишь по опознанию, и текст с меткою,
	 *       кодировка которого навязана, отвергался знаком U+FEFF в первом же значении
	 */
	if(this->_leading){
		/**
		 * Если кодировка исходного текста ещё не опознана
		 */
		if(!this->_sniffed){
			/**
			 * Если опознать кодировку по началу текста не удалось
			 *
			 * @note Опознания не вышло лишь потому, что текста ещё мало: удерживаем поданное
			 *       целиком и ждём продолжения
			 */
			if(!this->sniff(data, length, end)){
				// Удерживаем поданный кусок до прихода следующего
				this->_tail.assign(data, length);
				// Выводим признак успешного приведения куска
				return true;
			}
		/**
		 * Если кодировка навязана извне
		 */
		} else {
			// Получаем количество байт, опознанию метки потребное
			const size_t needed = marking(this->_encoding);
			/**
			 * Если опознавать метку ещё не по чему, а текст не окончен
			 */
			if((length < needed) && !end){
				// Удерживаем поданный кусок до прихода следующего
				this->_tail.assign(data, length);
				// Выводим признак успешного приведения куска
				return true;
			}
			// Запоминаем признак открытия текста меткой порядка байтов
			this->_signature = (::signature(reinterpret_cast <const uint8_t *> (data), length, this->_encoding) > 0);
		}
		/**
		 * Если текст открывался меткой порядка байтов
		 */
		if(this->_signature)
			// Пропускаем метку порядка байтов опознанной кодировки
			offset = ::signature(reinterpret_cast <const uint8_t *> (data), length, this->_encoding);
		// Запоминаем признак пройденного начала текста
		this->_leading = false;
	}
	/**
	 * Определяем опознанную кодировку исходного текста
	 */
	switch(static_cast <uint8_t> (this->_encoding)){
		/**
		 * Если текст записан кодировкой UTF-8
		 */
		case static_cast <uint8_t> (encoding_t::UTF8): {
			// Получаем приводимый кусок текста без метки порядка байтов
			const string_view text(data + offset, (length - offset));
			// Смещение разбираемой последовательности
			size_t position = 0;
			/**
			 * Выполняем перебор всех последовательностей приводимого куска
			 */
			while(position < text.length()){
				// Прочитанный знак Юникода
				uint32_t code = 0;
				// Количество байт, разбором пройденных
				size_t count = 0;
				// Выполняем разбор очередной последовательности
				const utf8_t outcome = inspect(text, position, code, count);
				/**
				 * Если последовательность оборвана концом поданного куска
				 */
				if(outcome == utf8_t::TRUNCATED){
					/**
					 * Если текст окончен, а последовательность не дописана
					 */
					if(end){
						// Запоминаем код ошибки приведения кодировки
						this->_error = error_t::INVALID_ENCODING;
						// Выполняем вывод сообщения об отказе в лог
						this->report();
						// Выводим признак неудачного приведения куска
						return false;
					}
					// Удерживаем оборванные байты до прихода следующего куска
					this->_tail.assign(text.data() + position, (text.length() - position));
					// Выходим из перебора последовательностей куска
					break;
				}
				/**
				 * Если последовательность построена ошибочно
				 */
				if(outcome != utf8_t::VALID){
					// Запоминаем код ошибки приведения кодировки
					this->_error = error_t::INVALID_ENCODING;
					// Выполняем вывод сообщения об отказе в лог
					this->report();
					// Выводим признак неудачного приведения куска
					return false;
				}
				/**
				 * Если знак в тексте недозволен
				 */
				if(!this->allowed(code))
					// Выводим признак неудачного приведения куска
					return false;
				// Выполняем перенос разобранной последовательности как она есть
				result.append(text.data() + position, count);
				// Выполняем переход к следующей последовательности
				position += count;
			}
			// Выводим признак успешного приведения куска
			return true;
		}
		// Если текст записан кодировкой UTF-16 любого порядка байтов
		case static_cast <uint8_t> (encoding_t::UTF16LE):
		case static_cast <uint8_t> (encoding_t::UTF16BE):
			// Выполняем приведение куска, записанного парами байтов
			return this->doubled((data + offset), (length - offset), end, result);
		// Если текст записан кодировкой UTF-32 любого порядка байтов
		case static_cast <uint8_t> (encoding_t::UTF32LE):
		case static_cast <uint8_t> (encoding_t::UTF32BE):
			// Выполняем приведение куска, записанного четвёрками байтов
			return this->quadrupled((data + offset), (length - offset), end, result);
	}
	/**
	 * @warning Заход этот есть застава последнего рубежа, ничем не задетая: перебор
	 *          выше несёт ветвь на всякую кодировку перечня, кроме NONE, а NONE до
	 *          перебора не доходит - она либо разрешается обнюхиванием, либо кусок
	 *          удерживается до прихода следующего. Сносу заход не подлежит: новый член
	 *          перечня кодировок вернёт сюда управление, и молчаливый пропуск текста
	 *          мимо приведения дал бы мусор вместо отказа
	 */
	// Запоминаем код ошибки приведения кодировки
	this->_error = error_t::UNSUPPORTED_ENCODING;
	// Выполняем вывод сообщения об отказе в лог
	this->report();
	// Выводим признак неудачного приведения куска
	return false;
}
