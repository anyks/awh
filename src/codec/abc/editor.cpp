/**
 * @brief Метод открытия контейнера отданными работами чтения и записи
 *
 * @param source устанавливаемая работа чтения октетов контейнера
 * @param sink   устанавливаемая работа записи октетов контейнера
 * @param length полная длина контейнера на носителе
 * @return       признак успешно открытого контейнера
 *
 */
bool awh::codec::abc::Editor::open(source_t source, sink_t sink, const uint64_t length) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс состояния правки контейнера
	this->reset();
	/**
	 * Если работы чтения либо записи октетов контейнера нам не переданы
	 */
	if((source == nullptr) || (sink == nullptr)){
		// Выполняем установку кода отказа открытия контейнера
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	// Выполняем установку работы чтения октетов контейнера
	this->_source = ::std::move(source);
	// Выполняем установку работы записи октетов контейнера
	this->_sink = ::std::move(sink);
	// Выполняем установку полной длины контейнера на носителе
	this->_length = length;
	// Буфер вычитанных октетов заголовка опознания контейнера
	vector <uint8_t> buffer;
	/**
	 * Если вычитать головной заголовок опознания контейнера не вышло
	 */
	if(!this->_source(0, HEADER_LENGTH, buffer) || (buffer.size() < HEADER_LENGTH)){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	/**
	 * Если хвостовой заголовок опознания на носителе поместился, выполняем чтение его
	 */
	if(length >= static_cast <uint64_t> (HEADER_LENGTH * 2)){
		// Буфер вычитанных октетов хвостового заголовка опознания
		vector <uint8_t> tail;
		/**
		 * Если хвостовой заголовок вычитан и опознан
		 */
		if(this->_source(length - HEADER_LENGTH, HEADER_LENGTH, tail) && probe(tail.data(), tail.size())){
			// Выполняем установку признака наличия хвостового заголовка
			this->_tailed = true;
			/**
			 * Если головной заголовок опознан не был, берём хвостовой: негодный
			 * головной значит обрыв посреди правки, и контейнер откатывается к
			 * поколению, какое было до неё
			 */
			if(!probe(buffer.data(), buffer.size()))
				// Выполняем перенесение хвостового заголовка головному
				buffer = ::std::move(tail);
		}
	}
	/**
	 * Если снять заголовок опознания контейнера не вышло
	 */
	{
		// Код отказа снятия заголовка опознания
		error_t error = error_t::NONE;
		/**
		 * Если снять заголовок опознания контейнера не вышло
		 */
		if(!this->_header.unpack(buffer.data(), buffer.size(), error))
			// Выводим признак неудачного открытия контейнера
			return this->fail(error);
	}
	/**
	 * Если оглавление контейнера заголовком не объявлено, правка невозможна:
	 * без оглавления неведомо, где какая запись лежит
	 */
	if(this->_header.index == 0){
		// Выполняем установку кода отказа отсутствия оглавления
		this->fail(error_t::MISSING_INDEX);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	// Выполняем очистку буфера вычитанных октетов
	buffer.clear();
	/**
	 * Если вычитать заголовок кадра оглавления не вышло
	 */
	if(!this->_source(this->_header.index, CHUNK_HEADER, buffer) || (buffer.size() < CHUNK_HEADER)){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	// Выполняем получение длины уложенного содержимого кадра оглавления
	const uint64_t packed = restore(buffer.data() + 4, 4);
	/**
	 * Если длина, объявленная кадром оглавления, расходится с объявленной заголовком
	 *
	 * @note Длина из кадра недоверенна, а заголовок несёт контрольную сумму: им и
	 *       поверяется прочитанное из кадра
	 */
	if(packed != static_cast <uint64_t> (this->_header.extent)){
		// Выполняем установку кода отказа повреждённого кадра
		this->fail(error_t::INVALID_CHUNK);
		// Выводим признак неудачи
		return false;
	}
	/**
	 * Если кадр оглавления в контейнер не умещается
	 *
	 * @details Длина эта сличена с объявленной заголовком, а заголовок несёт контрольную
	 *          сумму, - но сумму эту подделыватель пересчитывает, и обе длины приходят
	 *          какими он положит. По ней же вычитывается кадр ЦЕЛИКОМ: подделка на
	 *          `0xFFFFFFFF` заставляла ЗАТРЕБОВАТЬ У ИСТОЧНИКА 4 294 967 327 октетов -
	 *          замерено щупом 03.09.2026 на контейнере в 197 октетов
	 *
	 * @note Сторож этот стоял у снятия кадра (`fetch`), у сбора свёрток (`harvest`), у
	 *       выборки записей и у обхода счёта мусора ДЕСЯТЬЮ СТРОКАМИ НИЖЕ, - а у самого
	 *       открытия его не было вовсе, хотя открытие первым и встречает недоверенный
	 *       контейнер
	 *
	 * @note Сличение ведётся ВЫЧИТАНИЕМ от полной длины контейнера, а не сложением
	 *       смещения с длиною: слагаемые недоверенны оба, и сумма их завернулась бы,
	 *       пройдя сторож насквозь. Смещение оглавления поверено выше тем, что кадр его
	 *       вычитан по нему успешно
	 *
	 * @note Мерою взята полная длина контейнера, а не длина тела: оглавление лежит ЗА
	 *       телом, и предел тела отверг бы годный контейнер
	 */
	if((this->_header.index > this->_length) ||
	 ((this->_length - this->_header.index) < (static_cast <uint64_t> (CHUNK_HEADER) + packed))){
		// Выполняем установку кода отказа повреждённого кадра
		this->fail(error_t::INVALID_CHUNK);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	// Выполняем очистку буфера вычитанных октетов
	buffer.clear();
	/**
	 * Если вычитать кадр оглавления целиком не вышло
	 */
	if(!this->_source(this->_header.index, static_cast <size_t> (CHUNK_HEADER + packed), buffer) ||
	 (buffer.size() < static_cast <size_t> (CHUNK_HEADER + packed))){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	// Смещение снятия кадра оглавления
	size_t offset = 0;
	// Содержимое снятого кадра оглавления
	vector <uint8_t> payload;
	// Сведения о снятом кадре оглавления
	chunk_t chunk;
	/**
	 * Если снять кадр оглавления не вышло
	 */
	if(!this->_packer.unpack(buffer.data(), buffer.size(), offset, payload, chunk)){
		// Выполняем установку кода отказа снятия кадра оглавления
		this->_error = this->_packer.error();
		// Выводим признак неудачного открытия контейнера
		return false;
	}
	/**
	 * Если снять оглавление контейнера не вышло
	 */
	{
		// Код отказа снятия оглавления контейнера
		error_t error = error_t::NONE;
		/**
		 * Если снять оглавление контейнера не вышло
		 */
		if(!this->_index.unpack(payload.data(), payload.size(), error))
			// Выводим признак неудачного открытия контейнера
			return this->fail(error);
	}
	/**
	 * Выполняем счёт мусора, УЖЕ лежащего на носителе
	 *
	 * @details Прежде счёт этот начинался нулём, и работа `garbage()` на свежеоткрытом
	 *          контейнере отвечала нулём всегда - сколько бы мусора ни оставили прошлые
	 *          сессии. Замер 02.09.2026: контейнер, где правкой обращены в мусор 154
	 *          октета, при повторном открытии показывал 0, и потребитель, спрашивающий
	 *          «пора ли убирать?», не убрал бы никогда. Работа, ради этого и заведённая,
	 *          на свой вопрос не отвечала
	 *
	 * @warning Счёт этот - НИЖНЯЯ ГРАНИЦА, и точным быть не может. Складывается он из
	 *          двух слагаемых, обоих точных: длин снесённых строк оглавления и кадров,
	 *          целиком обращённых в мусор. Третьего слагаемого - записей, вытесненных
	 *          правкой внутри ЖИВОГО кадра, - на носителе не сыскать: строка оглавления
	 *          вытесненной записи перезаписана новой, а длина её нигде более не хранится.
	 *          Точный счёт потребовал бы места в заголовке, сиречь смены вида записи
	 *
	 * @note Нижняя граница безопасна для решения об уборке: она НЕ ОБЕЩАЕТ уборке
	 *       больше, чем та выручит. Обратная ошибка - завышение - гнала бы уборку за
	 *       мусором, какого нет
	 *
	 * @note Обход читает лишь ЗАГОЛОВКИ кадров, по тридцать два октета, не трогая
	 *       содержимого их: ни разжатия, ни расшифровки здесь не делается
	 */
	{
		/**
		 * Выполняем перебор всех строк оглавления контейнера
		 */
		for(const entry_t & entry : this->_index.entries()){
			// Если запись снесена правкой, длина её есть мусор на носителе
			if(entry.is(mark_t::ERASED))
				// Выполняем учёт октетов снесённой записи
				this->_garbage += static_cast <uint64_t> (entry.length);
		}
		// Предел тела контейнера
		const uint64_t bound = (static_cast <uint64_t> (HEADER_LENGTH) + this->_header.length);
		// Смещение очередного кадра тела контейнера
		uint64_t place = static_cast <uint64_t> (HEADER_LENGTH);
		/**
		 * Выполняем обход заголовков кадров тела контейнера
		 */
		while(place < bound){
			// Буфер вычитанного заголовка кадра
			vector <uint8_t> head;
			/**
			 * Если вычитать заголовок очередного кадра не вышло, обход прекращается
			 *
			 * @note Отказом открытия это НЕ объявляется: счёт мусора совещателен, и
			 *       отвергать годный контейнер из-за него значило бы отнимать у
			 *       потребителя работоспособную правку ради подсказки об уборке
			 */
			if(!this->_source(place, CHUNK_HEADER, head) || (head.size() < CHUNK_HEADER))
				// Прекращаем обход заголовков кадров
				break;
			// Выполняем получение полной длины очередного кадра
			const uint64_t whole = (static_cast <uint64_t> (CHUNK_HEADER) + restore(head.data() + 4, 4));
			/**
			 * Если кадр в теле контейнера не умещается, обход прекращается
			 *
			 * @note Сличение ведётся ВЫЧИТАНИЕМ от предела тела, а не сложением смещения
			 *       с длиною: длина прочитана из самого кадра и недоверенна, и сумма их
			 *       завернулась бы, пройдя сторож насквозь
			 */
			if((bound - place) < whole)
				// Прекращаем обход заголовков кадров
				break;
			// Если кадр целиком обращён в мусор, учитываем его целиком
			if((head[1] & CHUNK_WASTE) != 0)
				// Выполняем учёт октетов мусорного кадра
				this->_garbage += whole;
			// Выполняем переход к следующему кадру тела контейнера
			place += whole;
		}
	}
	/**
	 * Выполняем установку порядкового номера следующего кадра счётом записей:
	 * номер этот лишь бы рос, а сквозным счётом кадров он не ведётся
	 */
	this->_number = this->_header.records;
	// Выполняем установку признака открытого контейнера
	this->_opened = true;
	// Выводим признак успешно открытого контейнера
	return true;
}
/**
 * @brief Метод внесения записи в конец контейнера
 *
 * @param buffer буфер вносимой записи
 * @param size   размер вносимой записи
 * @param kind   вид содержимого вносимой записи
 * @return       признак успешности внесения
 *
 */
bool awh::codec::abc::Editor::add(const void * buffer, const size_t size,
 const payload_t kind, const bool added, const uint64_t number) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	/**
	 * Если контейнер ещё не открыт
	 */
	if(!this->_opened){
		// Выполняем установку кода отказа накопления записи
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачного накопления записи
		return false;
	}
	/**
	 * Если запись нам не передана
	 */
	if((buffer == nullptr) || (size == 0)){
		// Выполняем установку кода отказа накопления записи
		this->fail(error_t::EMPTY_RECORD);
		// Выводим признак неудачного накопления записи
		return false;
	}
	/**
	 * Если длина записи шире отведённого ей поля оглавления
	 *
	 * @note Поверка стоит ДО всякой правки состояния: смещение и длина строки оглавления
	 *       хранятся в uint32, и приведение к нему усекло бы длину молча, а откатывать
	 *       накопленное было бы уже нечем
	 */
	if(size > static_cast <size_t> (numeric_limits <uint32_t>::max())){
		// Выполняем установку кода отказа накопления записи
		this->fail(error_t::INVALID_LENGTH);
		// Выводим признак неудачного накопления записи
		return false;
	}
	/**
	 * Если вид содержимого сменился, выполняем укладку накопленного кадром
	 */
	if(!this->_pending.empty() && (kind != this->_kind)){
		/**
		 * Если уложить накопленное кадром не вышло
		 */
		if(!this->pack())
			// Выводим признак неудачного накопления записи
			return false;
	}
	/**
	 * Если накопленное вместе с поданной записью шире поля смещения, выполняем укладку
	 * накопленного кадром: смещение записи в кадре хранится тем же uint32
	 */
	if(!this->_pending.empty() &&
	 ((this->_pending.size() + size) > static_cast <size_t> (numeric_limits <uint32_t>::max()))){
		/**
		 * Если уложить накопленное кадром не вышло
		 */
		if(!this->pack())
			// Выводим признак неудачного накопления записи
			return false;
	}
	/**
	 * Признак незакреплённых правок, каким он был до накопления
	 *
	 * @note Держится он затем, что откат отвергнутого накопления обязан вернуть и его:
	 *       без того отвергнутая запись оставляла бы правку ОБЪЯВЛЕННОЙ при пустом
	 *       списке правок и пустом накоплении
	 */
	const bool dirty = this->_dirty;
	// Выполняем установку вида содержимого накопленных записей
	this->_kind = kind;
	// Заводимая правка оглавления
	edit_t mark;
	// Выполняем установку смещения записи в содержимом кадра
	mark.entry.offset = static_cast <uint32_t> (this->_pending.size());
	// Выполняем установку длины накопляемой записи
	mark.entry.length = static_cast <uint32_t> (size);
	// Выполняем установку признака того, что запись вносится, а не правится
	mark.added = added;
	// Выполняем установку номера правимой строки оглавления
	mark.number = number;
	// Выполняем объявление того, что запись кадром ещё не уложена
	mark.batch = numeric_limits <size_t>::max();
	// Выполняем внесение заведённой правки оглавления
	this->_marks.push_back(mark);
	// Выполняем накопление поданной записи
	this->_pending.insert(this->_pending.end(),
	 reinterpret_cast <const uint8_t *> (buffer), reinterpret_cast <const uint8_t *> (buffer) + size);
	// Выполняем объявление наличия незакреплённых правок
	this->_dirty = true;
	/**
	 * Если накоплено записей больше порога, выполняем укладку их кадром
	 */
	if(this->_pending.size() >= this->_settings.block){
		/**
		 * Если уложить накопленное кадром не вышло
		 */
		if(!this->pack()){
			/**
			 * Выполняем откат внесённой правки: без него отвергнутая запись осталась бы
			 * сосчитанной, выдавалась бы чтением и заклинила бы всякую следующую укладку
			 */
			this->_marks.pop_back();
			// Выполняем снятие накопленных октетов отвергнутой записи
			this->_pending.resize(static_cast <size_t> (mark.entry.offset));
			/**
			 * Выполняем возврат признака незакреплённых правок
			 *
			 * @details Откат возвращал список правок да накопленные октеты, а признак этот
			 *          оставлял выставленным - и правка числилась незакреплённой при пустом
			 *          состоянии. Следующая фиксация ранним выходом «закреплять нечего» не
			 *          уходила, а вела ВСЮ работу: метила прежнее оглавление мусором,
			 *          писала новое, поднимала поколение
			 *
			 * @note Замерено щупом 03.09.2026, а не выведено рассуждением: контейнер о
			 *       197 октетах при НУЛЕ накопленного и НУЛЕ правок рос до 349 октетов,
			 *       мусор с нуля до 56, поколение с нуля до единицы. Круг повторяется
			 *       сколько угодно, и файл растёт без предела
			 *
			 * @note Отказ этот достижим открытым API: настройка укладчика `encrypt` при
			 *       неотданном модуле шифрования. Закреплено
			 *       `CodecAbcEditor.RefusedAddLeavesNothingToCommit`
			 */
			this->_dirty = dirty;
			// Выводим признак неудачного накопления записи
			return false;
		}
	}
	/**
	 * Если способ фиксации велит закреплять правки по размеру их
	 */
	if((this->_settings.mode == mode_t::SIZE) && (this->pending() >= this->_settings.limit))
		// Выводим результат самочинной фиксации накопленных правок
		return this->commit();
	/**
	 * Если способ фиксации велит закреплять правки по количеству их
	 */
	if((this->_settings.mode == mode_t::RECORDS) && (this->_marks.size() >= this->_settings.limit))
		// Выводим результат самочинной фиксации накопленных правок
		return this->commit();
	/**
	 * Если способ фиксации велит поверять срок при обращении и срок наступил
	 */
	if((this->_settings.mode == mode_t::DEADLINE) && this->_schedule.touch())
		// Выводим результат самочинной фиксации накопленных правок
		return this->commit();
	// Выводим признак успешного накопления записи
	return true;
}
/**
 * @brief Метод внесения записи в конец контейнера
 *
 * @param buffer буфер вносимой записи
 * @param size   размер вносимой записи
 * @param kind   вид содержимого вносимой записи
 * @return       признак успешности внесения
 *
 */
bool awh::codec::abc::Editor::append(const void * buffer, const size_t size, const payload_t kind) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выводим результат накопления вносимой записи
	return this->add(buffer, size, kind, true, 0);
}
/**
 * @brief Метод правки записи контейнера по номеру
 *
 * @param number порядковый номер правимой записи
 * @param buffer буфер новой записи
 * @param size   размер новой записи
 * @param kind   вид содержимого новой записи
 * @return       признак успешности правки
 *
 */
bool awh::codec::abc::Editor::replace(const uint64_t number, const void * buffer,
 const size_t size, const payload_t kind) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	/**
	 * Если правимой записи в контейнере нет
	 */
	/**
	 * Если правится запись, внесённая, но ещё не закреплённая, выполняем закрепление
	 * накопленного
	 *
	 * @details Заголовок обещает: накопленное читается наравне с закреплённым. Строки
	 *          оглавления у накопленного, однако, ещё нет, и править её нечем - потому
	 *          накопленное сперва ложится кадром, а правится уже обычным путём
	 */
	if(this->_opened && (number >= static_cast <uint64_t> (this->_index.size())) &&
	 (number < this->records()) && !this->commit())
		// Выводим признак неудачной правки записи
		return false;
	if(!this->_opened || (number >= static_cast <uint64_t> (this->_index.size()))){
		// Выполняем установку кода отказа правки записи
		this->fail(this->_opened ? error_t::INVALID_INDEX : error_t::INTERNAL);
		// Выводим признак неудачной правки записи
		return false;
	}
	/**
	 * Выводим результат накопления новой записи: правка ведётся дописыванием, а
	 * прежние октеты остаются на носителе мусором до уборки
	 */
	return this->add(buffer, size, kind, false, number);
}
/**
 * @brief Метод сноса записи контейнера по номеру
 *
 * @param number порядковый номер сносимой записи
 * @return       признак успешности сноса
 *
 */
bool awh::codec::abc::Editor::erase(const uint64_t number) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	/**
	 * Если сносится запись, внесённая, но ещё не закреплённая, выполняем закрепление
	 * накопленного
	 *
	 * @details Заголовок обещает: накопленное читается наравне с закреплённым. Строки
	 *          оглавления у накопленного, однако, ещё нет, и сносить её нечем - потому
	 *          накопленное сперва ложится кадром, а сносится уже обычным путём
	 */
	if(this->_opened && (number >= static_cast <uint64_t> (this->_index.size())) &&
	 (number < this->records()) && !this->commit())
		// Выводим признак неудачного сноса записи
		return false;
	/**
	 * Если сносимой записи в контейнере нет
	 */
	if(!this->_opened || (number >= static_cast <uint64_t> (this->_index.size()))){
		// Выполняем установку кода отказа сноса записи
		this->fail(this->_opened ? error_t::INVALID_INDEX : error_t::INTERNAL);
		// Выводим признак неудачного сноса записи
		return false;
	}
	/**
	 * Выполняем снятие накопленных правок сносимой записи
	 *
	 * @details Снос помечает строку оглавления, а правка копится отдельным списком, и
	 * выдача записи ищет накопленное ПЕРВЫМ. Оттого накопленная правка побеждала снос
	 * независимо от порядка: «правка, а следом снос» отдавала правленую запись и до
	 * фиксации, и после неё. Ныне снос снимает накопленное той же записи, и побеждает
	 * действие ПОСЛЕДНЕЕ - как и в обратном порядке, где правка воскрешает снесённое
	 *
	 * @note Снятие звена номеров не сдвигает: номер сдвигают лишь правки ВНОСЯЩИЕ, а
	 * вносимую запись ни снести, ни править нельзя - обе работы отвергают номер сверх
	 * оглавления, покуда внесённое не закреплено
	 *
	 * @warning Снятие идёт ПРЕЖДЕ поверки на снос повторный. Правка воскрешает запись
	 * лишь накопленным списком, признака сноса в оглавлении не трогая, и ход «правка,
	 * снос, правка, снос» на втором сносе уходил бы ранним выходом «снесено ранее»,
	 * оставив накопленное второй правки жить
	 */
	for(size_t i = this->_marks.size(); i > 0; i--){
		// Выполняем получение очередной накопленной правки оглавления
		const edit_t & mark = this->_marks.at(i - 1);
		// Если правка эта ведает сносимой записью
		if(!mark.added && (mark.number == number))
			// Выполняем снятие накопленной правки сносимой записи
			this->_marks.erase(this->_marks.begin() + static_cast <ptrdiff_t> (i - 1));
	}
	// Выполняем получение строки оглавления сносимой записи
	entry_t entry = this->_index.entries().at(static_cast <size_t> (number));
	/**
	 * Если запись снесена ранее, сносить её повторно незачем
	 */
	if(entry.is(mark_t::ERASED)){
		// Выполняем объявление наличия незакреплённых правок
		this->_dirty = true;
		// Выводим признак успешного сноса записи
		return true;
	}
	// Выполняем объявление сноса записи правкой контейнера
	entry.set(mark_t::ERASED, true);
	/**
	 * Если правка строки оглавления отвечена отказом, дело внутреннее: номер
	 * поверен выше, и отказ здесь означал бы расхождение оглавления с самим собою
	 */
	if(!this->_index.replace(number, entry)){
		// Выполняем установку кода отказа правки строки оглавления
		this->fail(error_t::INVALID_INDEX);
		// Выводим признак неудачного сноса записи
		return false;
	}
	/**
	 * Выполняем увеличение количества октетов, обращённых в мусор
	 *
	 * @details Счёт ведётся ОТДЕЛЬНЫМ полем и переливается в общий лишь удавшейся
	 *          фиксацией. Договор работы `garbage()` гласит «мусора НА НОСИТЕЛЕ», а снос
	 *          копится в памяти и носителя до фиксации не трогает: сосчитанный сразу, он
	 *          обещал бы уборке мусор, какого на носителе ещё нет. Замер 02.09.2026 до
	 *          правки: после `erase` и ДО фиксации счёт показывал 13 при нетронутом
	 *          носителе
	 *
	 * @note Учёт стоит ПОСЛЕ правки строки оглавления, а не до неё: отказ правки оставлял
	 *       бы мусор сосчитанным, а запись НЕ снесённой. Отказ через открытый API
	 *       недостижим (номер поверен выше), и переставлено ради порядка
	 */
	this->_erasing += static_cast <uint64_t> (entry.length);
	// Выполняем объявление наличия незакреплённых правок
	this->_dirty = true;
	// Выводим признак успешного сноса записи
	return true;
}
/**
 * @brief Метод выборки записи контейнера по номеру
 *
 * @param number порядковый номер выбираемой записи
 * @param result буфер, куда следует положить выбранную запись
 * @return       признак успешно выбранной записи
 *
 */
bool awh::codec::abc::Editor::record(const uint64_t number, vector <uint8_t> & result) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	// Выполняем очистку буфера выбираемой записи
	result.clear();
	/**
	 * Если контейнер ещё не открыт
	 */
	if(!this->_opened){
		// Выполняем установку кода отказа выборки записи
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачной выборки записи
		return false;
	}
	// Номер накопленной правки, отвечающей затребованной записи
	size_t found = numeric_limits <size_t>::max();
	/**
	 * Порядковый номер, какой получит следующая внесённая, но ещё не
	 * закреплённая запись: внесённые становятся в конец оглавления по порядку
	 */
	uint64_t added = static_cast <uint64_t> (this->_index.size());
	/**
	 * Выполняем перебор накопленных правок оглавления по порядку: последняя
	 * правка записи и есть нынешнее её содержимое, оттого перебор идёт до конца
	 */
	for(size_t i = 0; i < this->_marks.size(); i++){
		// Выполняем получение очередной накопленной правки оглавления
		const edit_t & mark = this->_marks.at(i);
		// Порядковый номер записи, какой ведает очередная правка
		uint64_t current = mark.number;
		/**
		 * Если правка эта вносит новую запись
		 */
		if(mark.added){
			// Выполняем получение порядкового номера вносимой записи
			current = added;
			// Выполняем увеличение номера следующей вносимой записи
			added++;
		}
		// Если правка эта ведает затребованной записью
		if(current == number)
			// Выполняем установку номера найденной правки
			found = i;
	}
	/**
	 * Если накопленная правка затребованной записи найдена
	 */
	if(found != numeric_limits <size_t>::max()){
		// Выполняем получение найденной накопленной правки оглавления
		const edit_t & mark = this->_marks.at(found);
		/**
		 * Если запись лежит в уложенном кадре, выдать её без снятия кадра нельзя
		 */
		if(mark.batch != numeric_limits <size_t>::max()){
			// Смещение снятия уложенного кадра
			size_t offset = 0;
			// Содержимое снятого кадра
			vector <uint8_t> payload;
			// Сведения о снятом кадре
			chunk_t chunk;
			// Выполняем получение уложенного кадра, несущего запись
			const vector <uint8_t> & storage = this->_batches.at(mark.batch);
			/**
			 * Если снять уложенный кадр не вышло
			 */
			if(!this->_packer.unpack(storage.data(), storage.size(), offset, payload, chunk)){
				// Выполняем установку кода отказа снятия кадра
				this->_error = this->_packer.error();
				// Выводим признак неудачной выборки записи
				return false;
			}
			/**
			 * Если строка правки указывает за содержимое снятого кадра
			 */
			if((static_cast <uint64_t> (mark.entry.offset) + mark.entry.length) > static_cast <uint64_t> (payload.size())){
				// Выполняем установку кода отказа выборки записи
				this->fail(error_t::INVALID_INDEX);
				// Выводим признак неудачной выборки записи
				return false;
			}
			// Выполняем выборку записи из содержимого снятого кадра
			result.assign(payload.begin() + static_cast <ptrdiff_t> (mark.entry.offset),
			 payload.begin() + static_cast <ptrdiff_t> (mark.entry.offset + mark.entry.length));
			// Выводим признак успешно выбранной записи
			return true;
		}
		/**
		 * Выполняем выборку записи из накопления, кадром ещё не уложенного:
		 * накопленное читается наравне с закреплённым, ибо оно уже в памяти
		 *
		 * @note Поверки отрезка на выход за накопление здесь НЕТ намеренно, тогда как у
		 *       близнеца - выборки из уложенного кадра - она стоит. Разнятся они
		 *       источником: там отрезок сличается с содержимым, СНЯТЫМ С НОСИТЕЛЯ, то
		 *       есть недоверенным, а здесь - со своей же памятью, куда отрезок и попал
		 *       из `_pending.size()` в тот же миг
		 *
		 * @warning Держится это тем, что накопление усекается лишь ВМЕСТЕ с ведающими им
		 *          правками: укладка кадром перепривязывает их все и чистит накопление
		 *          разом, откат отвергнутого накопления снимает ровно ту правку, чьи
		 *          октеты и усекает, снос звена накопления не трогает вовсе, а сброс
		 *          состояния чистит всё вместе. Заведи усечение накопления, правок не
		 *          трогающее, - и выборка уйдёт за конец вместилища МОЛЧА, ибо сторожа
		 *          здесь нет
		 */
		result.assign(this->_pending.begin() + static_cast <ptrdiff_t> (mark.entry.offset),
		 this->_pending.begin() + static_cast <ptrdiff_t> (mark.entry.offset + mark.entry.length));
		// Выводим признак успешно выбранной записи
		return true;
	}
	/**
	 * Если затребованной записи в оглавлении контейнера нет
	 */
	if(number >= static_cast <uint64_t> (this->_index.size())){
		// Выполняем установку кода отказа выборки записи
		this->fail(error_t::INVALID_INDEX);
		// Выводим признак неудачной выборки записи
		return false;
	}
	// Выполняем получение строки оглавления затребованной записи
	const entry_t & entry = this->_index.entries().at(static_cast <size_t> (number));
	/**
	 * Если затребованная запись снесена правкой контейнера
	 */
	if(entry.is(mark_t::ERASED)){
		// Выполняем установку кода отказа выборки снесённой записи
		this->fail(error_t::MISSING_RECORD);
		// Выводим признак неудачной выборки записи
		return false;
	}
	/**
	 * Если снять кадр затребованной записи не вышло
	 */
	if(!this->fetch(entry.chunk))
		// Выводим признак неудачной выборки записи
		return false;
	/**
	 * Если строка оглавления указывает за содержимое снятого кадра
	 */
	if((static_cast <uint64_t> (entry.offset) + entry.length) > static_cast <uint64_t> (this->_chunk.size())){
		// Выполняем установку кода отказа выборки записи
		this->fail(error_t::INVALID_INDEX);
		// Выводим признак неудачной выборки записи
		return false;
	}
	// Выполняем выборку записи из содержимого снятого кадра
	result.assign(this->_chunk.begin() + static_cast <ptrdiff_t> (entry.offset),
	 this->_chunk.begin() + static_cast <ptrdiff_t> (entry.offset + entry.length));
	/**
	 * Если способ фиксации велит поверять срок при обращении и срок наступил
	 *
	 * @note Чтение - такое же обращение, как правка: срок, поверяемый одними правками, не
	 *       наступает никогда там, где правки кончились, а именно этот случай он и стережёт.
	 *       Отказ фиксации выборке не вредит: запись уже выбрана, и её выдаём
	 */
	if(this->_dirty && (this->_settings.mode == mode_t::DEADLINE) && this->_schedule.touch())
		// Выполняем самочинную фиксацию накопленных правок
		(void) this->commit();
	// Выводим признак успешно выбранной записи
	return true;
}
/**
 * @brief Метод фиксации накопленных правок на носителе
 *
 * @return признак успешности фиксации
 *
 */
bool awh::codec::abc::Editor::commit() noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	/**
	 * Если контейнер ещё не открыт
	 */
	if(!this->_opened){
		// Выполняем установку кода отказа фиксации правок
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачной фиксации правок
		return false;
	}
	/**
	 * Если незакреплённых правок нет, закреплять нечего
	 */
	if(!this->_dirty)
		// Выводим признак успешной фиксации правок
		return true;
	/**
	 * Если уложить накопленные записи кадром не вышло
	 */
	if(!this->pack())
		// Выводим признак неудачной фиксации правок
		return false;
	/**
	 * Снимок состояния, правимого фиксацией, вместе с работой отката
	 *
	 * @details Фиксация вносит строки в оглавление ПО ХОДУ записи кадров: смещение кадра
	 *          известно лишь по записи его. Отказ посреди фиксации оставлял внесённое
	 *          жить, а накопленные правки при том не снимались, и повторная фиксация
	 *          вносила их ЗАНОВО - записи двоились молча. Замер 25.08.2026: шесть записей
	 *          плюс четыре дописанных давали четырнадцать, и все четырнадцать читались
	 *
	 * @note Откат ведётся ЖУРНАЛОМ, а не копией оглавления: правок за фиксацию немного, а
	 *       строк в оглавлении бывают миллионы, и копия стоила бы всякой фиксации
	 */
	// Заголовок опознания контейнера, каким он был до фиксации
	const header_t header = this->_header;
	// Количество октетов мусора, каким оно было до фиксации
	const uint64_t garbage = this->_garbage;
	// Количество строк оглавления, каким оно было до фиксации
	const size_t rows = this->_index.size();
	// Журнал перенаправленных строк оглавления вместе с прежним видом их
	vector <pair <uint64_t, entry_t>> undo;
	/**
	 * @brief Работа отката состояния, правимого фиксацией
	 *
	 */
	auto rollback = [this, &header, &garbage, &rows, &undo]() noexcept -> void {
		/**
		 * Выполняем возврат перенаправленных строк оглавления в обратном порядке
		 */
		for(size_t i = undo.size(); i > 0; i--)
			// Выполняем возврат очередной строки оглавления к прежнему её виду
			(void) this->_index.replace(undo.at(i - 1).first, undo.at(i - 1).second);
		// Выполняем усечение оглавления до прежнего количества строк
		this->_index.truncate(rows);
		// Выполняем возврат количества октетов мусора
		this->_garbage = garbage;
		// Выполняем возврат заголовка опознания контейнера
		this->_header = header;
		/**
		 * Если контейнер подписывается, дерево свёрток собирается наново
		 *
		 * @note Кадры, внесённые в дерево до отказа, из него не изымаются иначе: дерево
		 *       свёрток растёт лишь вперёд, и вернуть его к прежнему виду можно только
		 *       сбором заново по кадрам тела
		 */
		if(this->_signer != nullptr){
			// Выполняем очистку дерева свёрток
			this->_merkle.clear();
			/**
			 * Если собрать свёртки по кадрам тела наново не вышло, подписант снимается:
			 * подписывать по наполовину собранному дереву нельзя
			 */
			if(!this->harvest()){
				// Выполняем снятие модуля шифрования для подписи контейнера
				this->_signer = nullptr;
				// Выполняем очистку имени ключа владельца контейнера
				this->_name.clear();
				// Выполняем снятие модуля шифрования у дерева свёрток
				this->_merkle.crypto(nullptr);
				// Выполняем очистку дерева свёрток
				this->_merkle.clear();
			}
		}
	};
	// Смещение записи новых кадров правимого контейнера
	uint64_t offset = 0;
	// Буфер вычитанных октетов заголовка кадра оглавления
	vector <uint8_t> buffer;
	/**
	 * Если вычитать заголовок кадра прежнего оглавления не вышло
	 */
	if(!this->_source(this->_header.index, CHUNK_HEADER, buffer) || (buffer.size() < CHUNK_HEADER)){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачной фиксации правок
		return false;
	}
	/**
	 * Выполняем пометку прежнего оглавления мусором правкой одного октета:
	 * перезапись кадра обязала бы шифровать содержимое наново, ничего в нём не
	 * меняя, а подрядное чтение обязано его пропустить
	 */
	const uint8_t marked = static_cast <uint8_t> (buffer.at(CHUNK_FLAGS) | CHUNK_WASTE);
	/**
	 * Если записать пометку прежнего оглавления не вышло
	 *
	 * @note Пометка кладётся ПЕРВОЙ намеренно, и перенос её в конец фиксации испробован и
	 *       отвергнут замером: октет её лежит внутри тела, тело подписывается, и новая
	 *       подпись обязана покрывать этот октет уже помеченным. Обрыв фиксации оттого
	 *       ломает подпись ПРЕЖНЕГО поколения при целых записях - порядком записи это не
	 *       лечится, лечится снятием разряда мусора со свёртки кадра
	 */
	if(!this->_sink(this->_header.index + CHUNK_FLAGS, &marked, 1)){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачной фиксации правок
		return false;
	}
	// Выполняем получение длины уложенного содержимого прежнего оглавления
	const uint64_t packed = restore(buffer.data() + 4, 4);
	/**
	 * Если длина, объявленная кадром оглавления, расходится с объявленной заголовком
	 *
	 * @note Длина из кадра недоверенна, а заголовок несёт контрольную сумму: им и
	 *       поверяется прочитанное из кадра
	 */
	if(packed != static_cast <uint64_t> (this->_header.extent)){
		// Выполняем установку кода отказа повреждённого кадра
		this->fail(error_t::INVALID_CHUNK);
		// Выводим признак неудачи
		return false;
	}

	/**
	 * Выполняем увеличение количества октетов, обращённых в мусор
	 *
	 * @note Отсюда и до конца фиксации ВСЯКИЙ отказ обязан звать откат: счёт мусора уже
	 *       увеличен, а кадры прежнего поколения уже внесены в дерево свёрток, - и
	 *       повторная фиксация без отката считала бы мусор дважды да вносила бы те же
	 *       кадры в дерево вторично. Замер 30.08.2026: отказ чтения на втором обращении к
	 *       носителю оставлял счёт мусора 117 при прежних 13
	 */
	this->_garbage += (CHUNK_HEADER + packed);
	/**
	 * Выполняем получение смещения записи новых кадров концом прежнего оглавления:
	 * за ним лежат подпись да хвостовой заголовок прежнего поколения, и оба пишутся
	 * наново, а прежнее оглавление остаётся мусором внутри тела
	 */
	offset = (this->_header.index + CHUNK_HEADER + packed);
	/**
	 * Если контейнер подпись объявлял, новые кадры ложатся ЗА кадром прежней подписи
	 *
	 * @details Прежде новые кадры ложились прямо на запись подписи прежнего поколения.
	 *          Обрыв фиксации оставлял контейнер, где все записи целы, головной заголовок
	 *          прежний, а запись подписи, на какую он указывает, затёрта наполовину:
	 *          поверка отвечала «запись подписи повреждена». Замер 26.08.2026: обрыв на
	 *          любой из записей 2..5 губил подпись при двадцати целых записях. Запись
	 *          подписи обёрнута кадром, и обход кадров подряд идёт по ней как по
	 *          мусорному, - оттого прежнее поколение переживает обрыв целиком
	 *
	 * @note Место прежней записи подписи остаётся мусором внутри тела - как и прежнее
	 *       оглавление. Уборка вернёт его, а целость прежнего поколения того стоит
	 *
	 * @note Хвостовой заголовок прежнего поколения затирать МОЖНО: он запасной, а
	 *       головной цел до последней записи фиксации, и к тому мигу хвостовой нового
	 *       поколения уже лежит на носителе
	 */
	// Кадр прежней записи подписи, вносимый в дерево свёрток
	vector <uint8_t> stale;
	if(this->_header.is(flag_t::SIGNED) && (this->_header.signature >= offset)){
		// Буфер вычитанного заголовка кадра прежней записи подписи
		vector <uint8_t> record;
		/**
		 * Если вычитать заголовок кадра прежней записи подписи не вышло
		 */
		if(!this->_source(this->_header.signature, CHUNK_HEADER, record) ||
		 (record.size() < CHUNK_HEADER)){
			// Выполняем установку кода отказа чтения октетов контейнера
			this->fail(error_t::UNREADABLE_SOURCE);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		// Выполняем получение длины содержимого кадра прежней записи подписи
		const uint64_t width = abc::gather(record.data() + 4, 4);
		/**
		 * Если вычитать кадр прежней записи подписи целиком не вышло
		 */
		if(!this->_source(this->_header.signature, static_cast <size_t> (CHUNK_HEADER + width), stale) ||
		 (stale.size() < static_cast <size_t> (CHUNK_HEADER + width))){
			// Выполняем установку кода отказа чтения октетов контейнера
			this->fail(error_t::UNREADABLE_SOURCE);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		// Выполняем отодвигание записи новых кадров за кадр прежней записи подписи
		offset = (this->_header.signature + CHUNK_HEADER + width);
	}
	/**
	 * Если контейнер подписывается, выполняем внесение прежнего оглавления в дерево
	 */
	if(this->_signer != nullptr){
		// Буфер вычитанных октетов прежнего оглавления
		vector <uint8_t> waste;
		/**
		 * Если вычитать кадр прежнего оглавления целиком не вышло
		 */
		if(!this->_source(this->_header.index, static_cast <size_t> (CHUNK_HEADER + packed), waste) ||
		 (waste.size() < static_cast <size_t> (CHUNK_HEADER + packed))){
			// Выполняем установку кода отказа чтения октетов контейнера
			this->fail(error_t::UNREADABLE_SOURCE);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Выполняем внесение кадра прежнего оглавления в дерево свёрток тем видом,
		 * какой он принял пометкой: свёртка обязана отвечать октетам на носителе
		 */
		if(!this->_merkle.add(waste.data(), waste.size())){
			// Выполняем установку кода отказа выработки свёртки
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Если контейнер подпись объявлял, вносим кадр прежней записи её
		 *
		 * @note Порядок внесения обязан отвечать порядку кадров на носителе: поверка
		 *       обходит их подряд, и свёртка, снятая в ином порядке, не сойдётся
		 */
		if(!stale.empty() && !this->_merkle.add(stale.data(), stale.size())){
			// Выполняем установку кода отказа выработки свёртки
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
	}
	/**
	 * Выполняем перебор всех уложенных кадров, ожидающих записи
	 */
	for(size_t i = 0; i < this->_batches.size(); i++){
		/**
		 * Если записать очередной кадр на носитель не вышло
		 */
		if(!this->_sink(offset, this->_batches.at(i).data(), this->_batches.at(i).size())){
			// Выполняем установку кода отказа записи октетов контейнера
			this->fail(error_t::UNWRITABLE_SINK);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Если контейнер подписывается, выполняем внесение кадра в дерево свёрток
		 */
		if(this->_signer != nullptr){
			/**
			 * Если внести кадр свёрткой в дерево не вышло
			 */
			if(!this->_merkle.add(this->_batches.at(i).data(), this->_batches.at(i).size())){
				// Выполняем установку кода отказа выработки свёртки
				this->fail(error_t::SIGNING_FAILED);
				// Выполняем откат состояния, правимого фиксацией
				rollback();
				// Выводим признак неудачной фиксации правок
				return false;
			}
		}
		/**
		 * Выполняем перебор накопленных правок оглавления
		 */
		for(edit_t & mark : this->_marks){
			/**
			 * Если правка эта не о записанном кадре
			 */
			if(mark.batch != i)
				// Переходим к следующей накопленной правке оглавления
				continue;
			// Выполняем установку смещения кадра от начала тела контейнера
			mark.entry.chunk = (offset - HEADER_LENGTH);
			/**
			 * Если правка эта вносит новую запись
			 */
			if(mark.added)
				// Выполняем внесение строки в оглавление контейнера
				this->_index.add(mark.entry);
			/**
			 * Иначе выполняем перенаправление строки оглавления на новую запись
			 */
			else {
				/**
				 * Выполняем запоминание прежнего вида перенаправляемой строки оглавления:
				 * откат при отказе фиксации возвращает её именно этой записью
				 */
				undo.emplace_back(mark.number, this->_index.entries().at(static_cast <size_t> (mark.number)));
				/**
				 * Выполняем увеличение количества октетов, обращённых в мусор:
				 * прежняя запись остаётся на носителе до уборки
				 */
				this->_garbage += static_cast <uint64_t> (
				 this->_index.entries().at(static_cast <size_t> (mark.number)).length);
				/**
				 * Если правка строки оглавления отвечена отказом, фиксация обрывается:
				 * номер поверен при накоплении правки, и отказ здесь означал бы
				 * расхождение оглавления с накопленными правками
				 */
				if(!this->_index.replace(mark.number, mark.entry)){
					// Выполняем установку кода отказа правки строки оглавления
					this->fail(error_t::INVALID_INDEX);
					// Выполняем откат состояния, правимого фиксацией
					rollback();
					// Выводим признак неудачной фиксации правок
					return false;
				}
			}
		}
		// Выполняем сдвиг смещения записи на длину записанного кадра
		offset += static_cast <uint64_t> (this->_batches.at(i).size());
	}
	// Буфер уложенного оглавления контейнера
	vector <uint8_t> entries;
	// Выполняем укладку оглавления контейнера в октеты
	this->_index.pack(entries);
	// Буфер уложенного кадра оглавления контейнера
	vector <uint8_t> tail;
	/**
	 * Если уложить оглавление кадром не вышло
	 */
	if(!this->_packer.pack(entries.data(), entries.size(), payload_t::NUMERIC,
	 this->_number, static_cast <uint32_t> (this->_header.generation + 1), tail)){
		// Выполняем установку кода отказа укладки кадра оглавления
		this->_error = this->_packer.error();
		// Выполняем откат состояния, правимого фиксацией
		rollback();
		// Выводим признак неудачной фиксации правок
		return false;
	}
	/**
	 * Если записать кадр оглавления на носитель не вышло
	 */
	if(!this->_sink(offset, tail.data(), tail.size())){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выполняем откат состояния, правимого фиксацией
		rollback();
		// Выводим признак неудачной фиксации правок
		return false;
	}
	// Буфер уложенной записи подписи владельца контейнера
	vector <uint8_t> signature;
	/**
	 * Если контейнер подписывается, выполняем выработку подписи владельца
	 */
	if(this->_signer != nullptr){
		// Собираемая подпись владельца контейнера
		sign_t sign;
		// Выполняем получение вида подписи по ключу владельца
		sign.kind = this->_signer->signature(this->_name);
		// Выполняем подбор вида хэш-суммы под вид подписи
		sign.hash = digest(sign.kind, this->_hash);
		/**
		 * Если свести дерево свёрток к корню не вышло.
		 *
		 * Кадр оглавления придаётся сведению, но в дереве не оседает: при следующей
		 * фиксации он ляжет наново, и осевшую свёртку пришлось бы править задним числом
		 */
		if(!this->_merkle.root(sign.root, tail.data(), tail.size())){
			// Выполняем установку кода отказа выработки свёртки
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Если выработать подпись корня дерева не вышло
		 */
		if(!this->_signer->sign(this->_name, sign.root.data(), sign.root.size(), sign.hash, sign.signature) ||
		 sign.signature.empty() || (sign.signature.size() > 0xFFFF) || (sign.root.size() > 0xFFFF)){
			// Выполняем установку кода отказа выработки подписи
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Если уложить запись подписи владельца контейнера не вышло
		 *
		 * @note Отказ укладки здесь ОБЯЗАН быть поверен: запись, не уложенная, остаётся
		 *       пустой, а обёртка кадром принимает пустое содержимое безропотно, - и на
		 *       носитель лёг бы безупречный кадр при заголовке, объявляющем контейнер
		 *       подписанным
		 */
		if(!abc::pack(sign, signature)){
			// Выполняем установку кода отказа выработки подписи
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Выполняем обёртку записи подписи кадром: следующая фиксация обойдёт её как
		 * мусорный кадр, не затирая, и прежнее поколение переживёт обрыв целиком
		 */
		/**
		 * Если обернуть запись подписи кадром не вышло
		 */
		if(!abc::envelope(signature, this->_number, static_cast <uint32_t> (this->_header.generation + 1))){
			// Выполняем установку кода отказа подписи
			this->fail(error_t::SIGNING_FAILED);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		/**
		 * Если записать подпись владельца на носитель не вышло
		 */
		if(!this->_sink(offset + static_cast <uint64_t> (tail.size()), signature.data(), signature.size())){
			// Выполняем установку кода отказа записи октетов контейнера
			this->fail(error_t::UNWRITABLE_SINK);
			// Выполняем откат состояния, правимого фиксацией
			rollback();
			// Выводим признак неудачной фиксации правок
			return false;
		}
		// Выполняем установку смещения подписи от начала контейнера
		this->_header.signature = (offset + static_cast <uint64_t> (tail.size()));
		// Выполняем объявление подписанности контейнера
		this->_header.set(flag_t::SIGNED, true);
		// Буфер усечённого отпечатка открытого ключа владельца
		vector <uint8_t> print;
		/**
		 * Если отпечаток открытого ключа владельца выработан
		 */
		if(abc::fingerprint(* this->_signer, this->_name, print))
			// Выполняем установку отпечатка открытого ключа владельца
			::memcpy(this->_header.fingerprint, print.data(),
			 (print.size() < FINGERPRINT_LENGTH ? print.size() : FINGERPRINT_LENGTH));
	/**
	 * Если подписанта нет, а контейнер подпись объявлял, выполняем снятие объявления
	 *
	 * @details Тело и оглавление переписаны, и прежняя запись подписи на них не сходится
	 *          и сойтись не должна. Оставленное объявление обратило бы контейнер в
	 *          подписанный ИСПОРЧЕННОЙ подписью - состояние худшее обоих внятных
	 */
	} else if(this->_header.is(flag_t::SIGNED)) {
		// Выполняем снятие признака подписанного контейнера
		this->_header.set(flag_t::SIGNED, false);
		// Выполняем снятие смещения записи подписи
		this->_header.signature = 0;
		// Выполняем очистку отпечатка открытого ключа владельца
		::memset(this->_header.fingerprint, 0, FINGERPRINT_LENGTH);
	}
	// Выполняем установку длины тела контейнера
	this->_header.length = (offset - HEADER_LENGTH);
	// Выполняем установку смещения оглавления контейнера
	this->_header.index = offset;
	/**
	 * Выполняем объявление длины содержимого кадра оглавления: заголовок несёт
	 * контрольную сумму, и длина, им объявленная, поверяет прочитанную из кадра
	 */
	this->_header.extent = static_cast <uint32_t> (tail.size() - CHUNK_HEADER);
	// Выполняем установку количества записей контейнера
	this->_header.records = static_cast <uint64_t> (this->_index.size());
	// Выполняем увеличение поколения записи контейнера
	this->_header.generation++;
	// Буфер уложенного заголовка опознания контейнера
	vector <uint8_t> head;
	// Выполняем укладку заголовка опознания контейнера
	this->_header.pack(head);
	/**
	 * Выполняем запись хвостового заголовка опознания прежде головного: обрыв
	 * посреди правки головного оставит контейнер прежнего поколения, а хвостовой
	 * заголовок нового поколения к тому времени уже цел
	 */
	if(!this->_sink(offset + static_cast <uint64_t> (tail.size() + signature.size()), head.data(), head.size())){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выполняем откат состояния, правимого фиксацией
		rollback();
		// Выводим признак неудачной фиксации правок
		return false;
	}
	/**
	 * Если записать головной заголовок опознания не вышло
	 */
	if(!this->_sink(0, head.data(), head.size())){
		/**
		 * Выполняем возврат прежних октетов заголовка записи подписи
		 *
		 * @details Заглушка уже легла, а головной заголовок остался прежнего поколения и
		 *          указывает на запись подписи, ею затёртую. Возврат закрывает то
		 *          единственное окно, где обрыв губил подпись прежнего поколения при целых
		 *          записях. Отказ возврата разбирать нечем и незачем: носитель уже отвечает
		 *          отказом, и второй отказ ничего не прибавит
		 */
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выполняем откат состояния, правимого фиксацией
		rollback();
		// Выводим признак неудачной фиксации правок
		return false;
	}
	// Выполняем установку полной длины контейнера на носителе
	this->_length = (offset + static_cast <uint64_t> (tail.size() + signature.size()) + HEADER_LENGTH);
	// Выполняем установку признака наличия хвостового заголовка
	this->_tailed = true;
	// Выполняем очистку уложенных кадров, ожидавших записи
	this->_batches.clear();
	// Выполняем очистку накопленных правок оглавления
	this->_marks.clear();
	// Выполняем снятие признака наличия незакреплённых правок
	this->_dirty = false;
	// Выполняем сброс признака удержания снятого кадра
	this->_cached = false;
	/**
	 * Выполняем перелив счёта накопленного сноса в счёт мусора на носителе
	 *
	 * @note Перелив стоит ЗДЕСЬ, за последним отказом фиксации, а не под откатом: откат
	 *       возвращает лишь то, что фиксация УЖЕ правила, а счёт сноса до этой строки не
	 *       тронут вовсе. Отказ фиксации оставляет его целым, и правки, им сосчитанные,
	 *       лягут следующей фиксацией
	 */
	this->_garbage += this->_erasing;
	// Выполняем сброс счёта накопленного сноса записей
	this->_erasing = 0;
	// Выводим признак успешной фиксации правок
	return true;
}
/**
 * @brief Метод уборки мусора перестройкой контейнера
 *
 * @param target работа записи октетов убираемого контейнера
 * @param kind   вид содержимого записей убираемого контейнера
 * @param length полная длина убранного контейнера
 * @return       признак успешности уборки
 *
 */
bool awh::codec::abc::Editor::compact(sink_t target, const payload_t kind, uint64_t & length) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	// Выполняем сброс полной длины убранного контейнера
	length = 0;
	/**
	 * Если контейнер ещё не открыт либо работа записи нам не передана
	 */
	if(!this->_opened || (target == nullptr)){
		// Выполняем установку кода отказа уборки контейнера
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачной уборки контейнера
		return false;
	}
	/**
	 * Если закрепить накопленные правки не вышло, убирать нельзя: уборка по
	 * оглавлению, разошедшемуся с памятью, потеряла бы накопленное
	 */
	if(!this->commit())
		// Выводим признак неудачной уборки контейнера
		return false;
	// Смещение записи убранного контейнера
	uint64_t offset = HEADER_LENGTH;
	// Оглавление убранного контейнера
	index_t index(this->_log);
	// Накопленные записи убранного контейнера
	vector <uint8_t> pending;
	/**
	 * Номера строк накопленных записей в оглавлении убранного контейнера.
	 *
	 * Строка заводится сразу же, а смещением кадра дополняется по укладке его:
	 * заводить её лишь при укладке значило бы ставить строки снесённых записей
	 * впереди живых и тем перемешать номера
	 */
	vector <uint64_t> marks;
	// Порядковый номер следующего кадра убранного контейнера
	uint64_t number = 0;
	// Буфер уложенного кадра убранного контейнера
	vector <uint8_t> chunk;
	// Дерево свёрток по кадрам убранного контейнера
	merkle_t merkle(this->_log);
	// Выполняем установку модуля шифрования дереву свёрток уборки
	merkle.crypto(this->_signer);
	/**
	 * @brief Работа укладки накопленных записей кадром убранного контейнера
	 *
	 * @details Работа эта зовётся ДВУМЯ дорогами: набором кадра до объявленного размера и
	 *          переполнением поля смещения. Заведена она посредником оттого, что дороги
	 *          эти делают одно и то же, а расхождение их означало бы кадр, записанный без
	 *          внесения в дерево свёрток либо без правки строк оглавления
	 *
	 * @return признак успешной укладки накопленных записей кадром
	 *
	 */
	auto deliver = [&]() noexcept -> bool {
		// Выполняем очистку буфера уложенного кадра
		chunk.clear();
		/**
		 * Если уложить накопленные записи кадром не вышло
		 */
		if(!this->_packer.pack(pending.data(), pending.size(), kind, number, 0, chunk)){
			// Выполняем установку кода отказа укладки кадра
			this->_error = this->_packer.error();
			// Выводим признак неудачной укладки накопленных записей
			return false;
		}
		/**
		 * Если записать уложенный кадр на носитель не вышло
		 */
		if(!target(offset, chunk.data(), chunk.size())){
			// Выполняем установку кода отказа записи октетов контейнера
			this->fail(error_t::UNWRITABLE_SINK);
			// Выводим признак неудачной укладки накопленных записей
			return false;
		}
		/**
		 * Если контейнер подписан, выполняем внесение кадра в дерево свёрток уборки
		 */
		if((this->_signer != nullptr) && !merkle.add(chunk.data(), chunk.size())){
			// Выполняем установку кода отказа подписания контейнера
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачной укладки накопленных записей
			return false;
		}
		/**
		 * Выполняем перебор номеров строк накопленных записей
		 */
		for(const uint64_t mark : marks){
			// Выполняем получение строки оглавления накопленной записи
			entry_t entry = index.entries().at(static_cast <size_t> (mark));
			// Выполняем установку смещения кадра от начала тела контейнера
			entry.chunk = (offset - HEADER_LENGTH);
			/**
			 * Если правка строки оглавления отвечена отказом, уборка обрывается:
			 * номер взят из самого оглавления, и отказ означал бы порчу его
			 */
			if(!index.replace(mark, entry)){
				// Выполняем установку кода отказа правки строки оглавления
				this->fail(error_t::INVALID_INDEX);
				// Выводим признак неудачной укладки накопленных записей
				return false;
			}
		}
		// Выполняем очистку строк оглавления накопленных записей
		marks.clear();
		// Выполняем очистку накопленных записей
		pending.clear();
		// Выполняем сдвиг смещения записи на длину записанного кадра
		offset += static_cast <uint64_t> (chunk.size());
		// Выполняем увеличение порядкового номера следующего кадра
		number++;
		// Выводим признак успешной укладки накопленных записей
		return true;
	};
	/**
	 * Выполняем перебор всех строк оглавления правимого контейнера
	 */
	for(size_t i = 0; i <= this->_index.size(); i++){
		/**
		 * Если строки перебраны не все, выполняем перенесение очередной живой записи
		 */
		if(i < this->_index.size()){
			// Выполняем получение очередной строки оглавления
			const entry_t & entry = this->_index.entries().at(i);
			/**
			 * Если запись снесена, выполняем перенесение строки её пустою: изъятие
			 * строки сдвинуло бы номера соседей, а номера эти живут и вне контейнера
			 */
			if(entry.is(mark_t::ERASED)){
				// Заводимая строка снесённой записи
				entry_t erased;
				// Выполняем объявление сноса записи
				erased.set(mark_t::ERASED, true);
				// Выполняем внесение строки в оглавление убранного контейнера
				index.add(erased);
				// Переходим к следующей строке оглавления
				continue;
			}
			// Буфер перенесённой записи контейнера
			vector <uint8_t> item;
			/**
			 * Если выбрать очередную живую запись не вышло
			 */
			if(!this->record(static_cast <uint64_t> (i), item))
				// Выводим признак неудачной уборки контейнера
				return false;
			/**
			 * Если накопленное вместе с перенесённой записью шире поля смещения,
			 * выполняем укладку накопленного кадром
			 *
			 * @details Смещение записи в содержимом кадра хранится в uint32, и приведение
			 * к нему усекло бы его молча: строка оглавления указывала бы не туда, а
			 * поверить это чтением нельзя - усечённое смещение читается как исправное.
			 * Накопление правок ту же поверку ведёт (`Editor::account`), уборка же её не
			 * вела вовсе, и расхождение это было НЕЯВНЫМ: размер кадра берётся настройкой,
			 * и запас поля держался лишь умолчанием её
			 *
			 * @note Поверка стоит ДО заведения строки: строка несёт смещение, и укладка
			 * кадром после неё оставила бы её со смещением от кадра уже уложенного
			 */
			if(!pending.empty() &&
			 ((pending.size() + item.size()) > static_cast <size_t> (numeric_limits <uint32_t>::max())) &&
			 !deliver())
				// Выводим признак неудачной уборки контейнера
				return false;
			// Заводимая строка перенесённой записи
			entry_t moved;
			// Выполняем установку смещения записи в содержимом кадра
			moved.offset = static_cast <uint32_t> (pending.size());
			// Выполняем установку длины перенесённой записи
			moved.length = static_cast <uint32_t> (item.size());
			// Выполняем внесение номера строки перенесённой записи
			marks.push_back(static_cast <uint64_t> (index.size()));
			// Выполняем внесение строки в оглавление убранного контейнера
			index.add(moved);
			// Выполняем накопление перенесённой записи
			pending.insert(pending.end(), item.begin(), item.end());
		}
		/**
		 * Если накопленного на кадр не набралось, а строки перебраны не все
		 */
		if((pending.size() < this->_settings.block) && (i < this->_index.size()))
			// Переходим к следующей строке оглавления
			continue;
		/**
		 * Если накопленных записей нет, укладывать нечего
		 */
		if(pending.empty())
			// Переходим к следующей строке оглавления
			continue;
		/**
		 * Если уложить накопленные записи кадром не вышло
		 */
		if(!deliver())
			// Выводим признак неудачной уборки контейнера
			return false;
	}
	// Буфер уложенного оглавления убранного контейнера
	vector <uint8_t> entries;
	// Выполняем укладку оглавления убранного контейнера в октеты
	index.pack(entries);
	// Буфер уложенного кадра оглавления
	vector <uint8_t> tail;
	/**
	 * Если уложить оглавление кадром не вышло
	 */
	if(!this->_packer.pack(entries.data(), entries.size(), payload_t::NUMERIC, number, 0, tail)){
		// Выполняем установку кода отказа укладки кадра оглавления
		this->_error = this->_packer.error();
		// Выводим признак неудачной уборки контейнера
		return false;
	}
	/**
	 * Если записать кадр оглавления на носитель не вышло
	 */
	if(!target(offset, tail.data(), tail.size())){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачной уборки контейнера
		return false;
	}
	// Буфер уложенной записи подписи убранного контейнера
	vector <uint8_t> signature;
	// Заголовок опознания убранного контейнера
	header_t header = this->_header;
	/**
	 * Если убранный контейнер надлежит подписать
	 */
	if(this->_signer != nullptr){
		// Заводимая запись подписи убранного контейнера
		sign_t sign;
		// Выполняем установку вида подписи владельца контейнера
		sign.kind = this->_signer->signature(this->_name);
		// Выполняем установку вида хэш-суммы подписи
		sign.hash = digest(sign.kind, this->_hash);
		/**
		 * Если снять свёртку по кадрам убранного контейнера не вышло
		 */
		if(!merkle.root(sign.root, tail.data(), tail.size())){
			// Выполняем установку кода отказа подписания контейнера
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачной уборки контейнера
			return false;
		}
		/**
		 * Если подписать свёртку по кадрам убранного контейнера не вышло
		 */
		if(!this->_signer->sign(this->_name, sign.root.data(), sign.root.size(), sign.hash, sign.signature) ||
		 sign.signature.empty() || (sign.signature.size() > 0xFFFF) || (sign.root.size() > 0xFFFF)){
			// Выполняем установку кода отказа подписания контейнера
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачной уборки контейнера
			return false;
		}
		/**
		 * Если уложить запись подписи владельца контейнера не вышло
		 *
		 * @note Отказ укладки здесь ОБЯЗАН быть поверен: запись, не уложенная, остаётся
		 *       пустой, а обёртка кадром принимает пустое содержимое безропотно, - и на
		 *       носитель лёг бы безупречный кадр при заголовке, объявляющем контейнер
		 *       подписанным
		 */
		if(!abc::pack(sign, signature)){
			// Выполняем установку кода отказа выработки подписи
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачной уборки контейнера
			return false;
		}
		/**
		 * Если обернуть запись подписи кадром убранного контейнера не вышло
		 */
		if(!abc::envelope(signature, number, 0)){
			// Выполняем установку кода отказа подписи
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачной уборки контейнера
			return false;
		}
		/**
		 * Если записать запись подписи на носитель не вышло
		 */
		if(!target(offset + static_cast <uint64_t> (tail.size()), signature.data(), signature.size())){
			// Выполняем установку кода отказа записи октетов контейнера
			this->fail(error_t::UNWRITABLE_SINK);
			// Выводим признак неудачной уборки контейнера
			return false;
		}
		// Выполняем установку смещения записи подписи убранного контейнера
		header.signature = (offset + static_cast <uint64_t> (tail.size()));
		// Выполняем объявление убранного контейнера подписанным
		header.set(flag_t::SIGNED, true);
		// Буфер усечённого отпечатка открытого ключа владельца
		vector <uint8_t> print;
		/**
		 * Если отпечаток открытого ключа владельца выработан
		 */
		if(abc::fingerprint(* this->_signer, this->_name, print))
			// Выполняем установку отпечатка открытого ключа владельца
			::memcpy(header.fingerprint, print.data(),
			 (print.size() < FINGERPRINT_LENGTH ? print.size() : FINGERPRINT_LENGTH));
	/**
	 * Если подписанта нет, а прежний контейнер подпись объявлял, выполняем снятие
	 * объявления: тело уборкою переписано, и прежняя подпись на него не сходится
	 */
	} else if(header.is(flag_t::SIGNED)) {
		// Выполняем снятие признака подписанного контейнера
		header.set(flag_t::SIGNED, false);
		// Выполняем снятие смещения записи подписи
		header.signature = 0;
		// Выполняем очистку отпечатка открытого ключа владельца
		::memset(header.fingerprint, 0, FINGERPRINT_LENGTH);
	}
	// Выполняем установку длины тела убранного контейнера
	header.length = (offset - HEADER_LENGTH);
	// Выполняем установку смещения оглавления убранного контейнера
	header.index = offset;
	// Выполняем объявление длины содержимого кадра оглавления убранного контейнера
	header.extent = static_cast <uint32_t> (tail.size() - CHUNK_HEADER);
	// Выполняем установку количества записей убранного контейнера
	header.records = static_cast <uint64_t> (index.size());
	// Выполняем увеличение поколения записи контейнера
	header.generation++;
	// Буфер уложенного заголовка опознания
	vector <uint8_t> head;
	// Выполняем укладку заголовка опознания убранного контейнера
	header.pack(head);
	/**
	 * Если записать хвостовой заголовок опознания не вышло
	 */
	if(!target(offset + static_cast <uint64_t> (tail.size() + signature.size()), head.data(), head.size())){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачной уборки контейнера
		return false;
	}
	/**
	 * Если записать головной заголовок опознания не вышло
	 */
	if(!target(0, head.data(), head.size())){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачной уборки контейнера
		return false;
	}
	// Выполняем установку полной длины убранного контейнера
	length = (offset + static_cast <uint64_t> (tail.size() + signature.size()) + HEADER_LENGTH);
	// Выводим признак успешной уборки контейнера
	return true;
}
/**
 * @brief Метод сброса состояния правки контейнера
 *
 */
void awh::codec::abc::Editor::reset() noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	// Выполняем сброс признака открытого контейнера
	this->_opened = false;
	// Выполняем сброс признака наличия хвостового заголовка
	this->_tailed = false;
	// Выполняем сброс признака наличия незакреплённых правок
	this->_dirty = false;
	// Выполняем сброс признака удержания снятого кадра
	this->_cached = false;
	// Выполняем сброс полной длины контейнера на носителе
	this->_length = 0;
	// Выполняем сброс количества октетов, обращённых в мусор
	this->_garbage = 0;
	// Выполняем сброс счёта накопленного сноса записей
	this->_erasing = 0;
	// Выполняем сброс порядкового номера следующего кадра
	this->_number = 0;
	// Выполняем сброс смещения удерживаемого кадра
	this->_origin = 0;
	// Выполняем сброс вида содержимого накопленных записей
	this->_kind = payload_t::MIXED;
	// Выполняем сброс накопленных записей
	this->_pending.clear();
	// Выполняем сброс накопленных правок оглавления
	this->_marks.clear();
	// Выполняем сброс уложенных кадров, ожидающих записи
	this->_batches.clear();
	// Выполняем сброс содержимого удерживаемого кадра
	this->_chunk.clear();
	// Выполняем сброс дерева свёрток по кадрам контейнера
	this->_merkle.clear();
	// Выполняем сброс оглавления контейнера
	this->_index.clear();
	// Выполняем сброс работы чтения октетов контейнера
	this->_source = nullptr;
	// Выполняем сброс работы записи октетов контейнера
	this->_sink = nullptr;
	/**
	 * Выполняем снятие подписанта правимого контейнера
	 *
	 * @note Подписант снимается наравне с прочим: дерево свёрток собирается лишь из
	 *       sign(), и уцелевший подписант положил бы на СЛЕДУЮЩИЙ контейнер подпись,
	 *       какой тот удовлетворить не может - свёртки покрывали бы одни дописанные кадры
	 */
	this->_signer = nullptr;
	// Выполняем очистку имени ключа владельца контейнера
	this->_name.clear();
	// Выполняем возврат вида хэш-суммы подписи к умолчанию
	this->_hash = crypto_t::hash_t::SHA256;
	// Выполняем сброс заголовка опознания контейнера
	this->_header = header_t();
}
/**
 * @brief Метод извлечения количества записей контейнера
 *
 * @return количество записей контейнера, снесённые в счёт входят
 *
 */
uint64_t awh::codec::abc::Editor::records() const noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Количество внесённых, но ещё не закреплённых записей
	uint64_t added = 0;
	/**
	 * Выполняем перебор накопленных правок оглавления
	 */
	for(const edit_t & mark : this->_marks){
		// Если правка эта вносит новую запись
		if(mark.added)
			// Выполняем увеличение количества внесённых записей
			added++;
	}
	// Выводим количество записей контейнера
	return (static_cast <uint64_t> (this->_index.size()) + added);
}
