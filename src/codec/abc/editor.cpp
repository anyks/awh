/**
 * @brief Метод объявления отказа правки контейнера
 *
 * @param error объявляемый код отказа
 * @return      признак успешности, всегда ложь
 *
 */
bool awh::codec::abc::Editor::fail(const error_t error) noexcept {
	// Выполняем установку кода отказа
	this->_error = error;
	/**
	 * Если объект логирования отдан, доносим об отказе.
	 *
	 * @warning Сброс кода отказа сюда НЕ идёт: воронка эта объявляет отказ, а сброс
	 *          лишь снимает прежний, и донесение о нём наполняло бы журнал записями
	 *          «no error» на всякий успешный вызов. Проверено на себе
	 */
	if((error != error_t::NONE) && (this->_log != nullptr)){
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("ABC: %s", __PRETTY_FUNCTION__, make_tuple(static_cast <uint16_t> (error)),
			 log_t::flag_t::WARNING, abc::message(error));
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("ABC: %s", log_t::flag_t::WARNING, abc::message(error));
		#endif
	}
	// Сообщаем, что работа отвечена отказом
	return false;
}
/**
 * @brief Метод снятия кадра контейнера с носителя
 *
 * @param origin смещение кадра от начала тела контейнера
 * @return       признак успешно снятого кадра
 *
 */
bool awh::codec::abc::Editor::fetch(const uint64_t origin) noexcept {
	/**
	 * Если затребованный кадр уже удерживается, снимать его наново незачем
	 */
	if(this->_cached && (this->_origin == origin))
		// Выводим признак успешно снятого кадра
		return true;
	// Выполняем сброс признака удержания снятого кадра
	this->_cached = false;
	/**
	 * Если смещение кадра выводит за тело контейнера
	 *
	 * @details Смещение приходит из оглавления, а оглавление недоверенно, и сложение
	 *          `HEADER_LENGTH + origin` при смещении близ предела разрядной сетки
	 *          завернулось бы, подав источнику октетов смещение малое вместо непомерного.
	 *          Оттого сторож и стоит ПРЕЖДЕ первого же чтения
	 *
	 * @note Тело ограничено заголовком опознания, а тот несёт контрольную сумму, и
	 *       объявленное им поверять можно
	 */
	if(origin >= this->_header.length){
		// Выполняем установку кода отказа повреждённого кадра
		this->fail(error_t::INVALID_CHUNK);
		// Выводим признак неудачного снятия кадра
		return false;
	}
	// Буфер вычитанных октетов кадра
	vector <uint8_t> buffer;
	/**
	 * Если вычитать заголовок кадра не вышло
	 */
	if(!this->_source(HEADER_LENGTH + origin, CHUNK_HEADER, buffer) || (buffer.size() < CHUNK_HEADER)){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачного снятия кадра
		return false;
	}
	// Выполняем получение длины уложенного содержимого кадра
	const uint64_t length = restore(buffer.data() + 4, 4);
	/**
	 * Если объявленная длина кадра выводит за тело контейнера
	 *
	 * @details Длина прочитана из САМОГО контейнера и недоверенна, а вычитывается по ней
	 *          кадр целиком: подделка четырёх октетов её заставляла ЗАТРЕБОВАТЬ У
	 *          ИСТОЧНИКА 4 294 967 327 октетов - замерено щупом 29.08.2026 на контейнере
	 *          в 316 октетов. Сторож этот стоял у выборки записей, а у правки его не было
	 *          вовсе, хотя ввод у обеих один
	 *
	 * @note Сторож стоит ЗДЕСЬ, а не в источнике октетов: источник даётся потребителем, и
	 *       полагаться на разумность чужой работы нельзя. Сличение ведётся ВЫЧИТАНИЕМ от
	 *       предела тела, а не сложением: слагаемые недоверенны оба, и сумма их
	 *       завернулась бы, пройдя сторож насквозь
	 */
	if((this->_header.length - origin) < (static_cast <uint64_t> (CHUNK_HEADER) + length)){
		// Выполняем установку кода отказа повреждённого кадра
		this->fail(error_t::INVALID_CHUNK);
		// Выводим признак неудачного снятия кадра
		return false;
	}
	// Выполняем очистку буфера вычитанных октетов
	buffer.clear();
	/**
	 * Если вычитать кадр целиком не вышло
	 */
	if(!this->_source(HEADER_LENGTH + origin, static_cast <size_t> (CHUNK_HEADER + length), buffer) ||
	 (buffer.size() < static_cast <size_t> (CHUNK_HEADER + length))){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачного снятия кадра
		return false;
	}
	// Смещение снятия кадра
	size_t offset = 0;
	// Сведения о снятом кадре
	chunk_t chunk;
	/**
	 * Если снять кадр не вышло
	 */
	if(!this->_packer.unpack(buffer.data(), buffer.size(), offset, this->_chunk, chunk)){
		// Выполняем установку кода отказа снятия кадра
		this->_error = this->_packer.error();
		// Выводим признак неудачного снятия кадра
		return false;
	}
	// Выполняем установку смещения удерживаемого кадра
	this->_origin = origin;
	// Выполняем установку признака удержания снятого кадра
	this->_cached = true;
	// Выводим признак успешно снятого кадра
	return true;
}
/**
 * @brief Метод сбора свёрток по кадрам тела контейнера
 *
 * @return признак успешного сбора свёрток
 *
 */
bool awh::codec::abc::Editor::harvest() noexcept {
	// Выполняем очистку прежнего дерева свёрток
	this->_merkle.clear();
	/**
	 * Выполняем перебор всех кадров тела контейнера
	 */
	for(uint64_t offset = 0; offset < this->_header.length;){
		// Буфер вычитанных октетов заголовка кадра
		vector <uint8_t> buffer;
		/**
		 * Если вычитать заголовок кадра не вышло
		 */
		if(!this->_source(HEADER_LENGTH + offset, CHUNK_HEADER, buffer) || (buffer.size() < CHUNK_HEADER)){
			// Выполняем установку кода отказа чтения октетов контейнера
			this->fail(error_t::UNREADABLE_SOURCE);
			// Выводим признак неудачного сбора свёрток
			return false;
		}
		// Выполняем получение длины уложенного содержимого кадра
		const uint64_t length = restore(buffer.data() + 4, 4);
		/**
		 * Если объявленная длина кадра выводит за тело контейнера
		 *
		 * @note Сторож тот же, что и у снятия кадра, и по той же причине: длина приходит
		 *       из самого контейнера, а по ней вычитывается кадр целиком. Сверх того он
		 *       стережёт здесь и ЗАВОРОТ сдвига обхода: сдвиг растёт на длину кадра, и
		 *       длина близ предела разрядной сетки вернула бы обход к началу тела
		 */
		if((this->_header.length - offset) < (static_cast <uint64_t> (CHUNK_HEADER) + length)){
			// Выполняем установку кода отказа повреждённого кадра
			this->fail(error_t::INVALID_CHUNK);
			// Выводим признак неудачного сбора свёрток
			return false;
		}
		// Выполняем очистку буфера вычитанных октетов
		buffer.clear();
		/**
		 * Если вычитать кадр целиком не вышло
		 */
		if(!this->_source(HEADER_LENGTH + offset, static_cast <size_t> (CHUNK_HEADER + length), buffer) ||
		 (buffer.size() < static_cast <size_t> (CHUNK_HEADER + length))){
			// Выполняем установку кода отказа чтения октетов контейнера
			this->fail(error_t::UNREADABLE_SOURCE);
			// Выводим признак неудачного сбора свёрток
			return false;
		}
		/**
		 * Если внести кадр свёрткой в дерево не вышло
		 */
		if(!this->_merkle.add(buffer.data(), buffer.size())){
			// Выполняем установку кода отказа выработки свёртки
			this->fail(error_t::SIGNING_FAILED);
			// Выводим признак неудачного сбора свёрток
			return false;
		}
		// Выполняем сдвиг смещения разбора на длину кадра
		offset += (CHUNK_HEADER + length);
	}
	// Выводим признак успешного сбора свёрток
	return true;
}
/**
 * @brief Метод объявления подписи правимого контейнера
 *
 * @param crypto модуль шифрования, ноль - снятие подписи
 * @param name   имя ключа владельца контейнера
 * @param hash   желаемый вид хэш-суммы подписи
 * @return       признак успешно объявленной подписи
 *
 */
bool awh::codec::abc::Editor::sign(const crypto_t * crypto, const string & name,
 const crypto_t::hash_t hash) noexcept {
	// Выполняем захват замка состояния правки контейнера
	lock_guard <recursive_mutex> lock(this->_mtx);
	// Выполняем сброс кода отказа правки контейнера
	this->_error = error_t::NONE;
	/**
	 * Если контейнер ещё не открыт, собрать свёртки не с чего
	 *
	 * @note Поверка стоит ПРЕЖДЕ всякой правки состояния: подписант, поставленный перед
	 *       нею, переживал отказ и доставался следующей фиксации
	 */
	if((crypto != nullptr) && !this->_opened){
		// Выполняем установку кода отказа объявления подписи
		this->fail(error_t::INTERNAL);
		// Выводим признак неудачно объявленной подписи
		return false;
	}
	// Выполняем установку модуля шифрования для подписи контейнера
	this->_signer = crypto;
	// Выполняем установку имени ключа владельца контейнера
	this->_name = name;
	// Выполняем установку желаемого вида хэш-суммы подписи
	this->_hash = hash;
	// Выполняем установку модуля шифрования дереву свёрток
	this->_merkle.crypto(crypto);
	/**
	 * Выполняем объявление наличия незакреплённых правок
	 *
	 * @note Смена подписанта - такая же правка, как дописывание записи: без этого признака
	 *       фиксация выходила бы успехом, не сделав ничего, и заголовок обещал бы подпись,
	 *       какой на носителе нет
	 */
	this->_dirty = true;
	/**
	 * Если подпись снимается, собирать свёртки незачем
	 */
	if(crypto == nullptr){
		// Выполняем очистку дерева свёрток
		this->_merkle.clear();
		// Выводим признак успешно снятой подписи
		return true;
	}
	/**
	 * Если собрать свёртки по кадрам тела контейнера не вышло
	 *
	 * @details Дерево свёрток остаётся собранным наполовину, и подписывать по нему нельзя:
	 *          фиксация докладывала успех и клала контейнер, объявляющий себя подписанным,
	 *          а поверка подписи его отвечала расхождением. Такой контейнер хуже
	 *          неподписанного - он выглядит подделанным
	 *
	 * @note Подписант при отказе СНИМАЕТСЯ, а не удерживается прежний: дерево уже разрушено
	 *       сбором, и удержание прежнего подписанта дало бы ту же несходящуюся подпись.
	 *       Отказ объявлен, и объявить подписанта заново - дело зовущего
	 */
	if(!this->harvest()){
		// Выполняем снятие модуля шифрования для подписи контейнера
		this->_signer = nullptr;
		// Выполняем очистку имени ключа владельца контейнера
		this->_name.clear();
		// Выполняем снятие модуля шифрования у дерева свёрток
		this->_merkle.crypto(nullptr);
		// Выполняем очистку дерева свёрток
		this->_merkle.clear();
		// Выводим признак неудачно объявленной подписи
		return false;
	}
	// Выводим признак успешно объявленной подписи
	return true;
}
/**
 * @brief Метод укладки накопленных записей кадром в память
 *
 * @return признак успешности укладки
 *
 */
bool awh::codec::abc::Editor::pack() noexcept {
	/**
	 * Если накопленных записей нет, укладывать нечего
	 */
	if(this->_pending.empty())
		// Выводим признак успешной укладки
		return true;
	// Буфер уложенного кадра
	vector <uint8_t> chunk;
	/**
	 * Если уложить накопленные записи кадром не вышло
	 */
	if(!this->_packer.pack(this->_pending.data(), this->_pending.size(), this->_kind,
	 this->_number, static_cast <uint32_t> (this->_header.generation + 1), chunk)){
		// Выполняем установку кода отказа укладки кадра
		this->_error = this->_packer.error();
		/**
		 * Накопленное отказом не сбрасывается: причина отказа может быть устранена,
		 * и следующая попытка пройдёт по тем же данным
		 */
		return false;
	}
	/**
	 * Выполняем перебор накопленных правок оглавления
	 */
	for(edit_t & mark : this->_marks){
		/**
		 * Если правка ещё не привязана к уложенному кадру
		 */
		if(mark.batch == numeric_limits <size_t>::max())
			// Выполняем привязку правки к укладываемому кадру
			mark.batch = this->_batches.size();
	}
	// Выполняем внесение уложенного кадра в череду ожидающих записи
	this->_batches.push_back(::std::move(chunk));
	// Выполняем увеличение порядкового номера следующего кадра
	this->_number++;
	// Выполняем очистку накопленных записей
	this->_pending.clear();
	// Выводим признак успешной укладки
	return true;
}
