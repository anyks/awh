/**
 * Подключаем заголовочный файл модуля
 */
#include <codec/abc/schedule.hpp>

/**
 * Стандартные заголовочные файлы
 */
#include <chrono>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Пространство имён работ, доступных лишь этому файлу
 *
 */
namespace {
	/**
	 * @brief Функция получения нынешнего штампа времени
	 *
	 * @return нынешний штамп времени в миллисекундах
	 *
	 */
	uint64_t stamp() noexcept {
		// Выводим нынешний штамп времени от начала отсчёта устойчивых часов
		return static_cast <uint64_t> (chrono::duration_cast <chrono::milliseconds> (
		 chrono::steady_clock::now().time_since_epoch()).count());
	}
};

/**
 * @brief Метод отбоя срока своим потоком
 *
 */
void awh::codec::abc::Schedule::run(const uint64_t round) noexcept {
	/**
	 * Выполняем отбой срока, покуда работа отбоя не остановлена
	 */
	while(true){
		// Выполняем захват замка состояния отбоя срока
		unique_lock <mutex> lock(this->_mtx);
		/**
		 * Выполняем ожидание наступления срока на условной переменной.
		 *
		 * Ожидание идёт на переменной, а не выдержкой: выдержка обязала бы остановку
		 * дожидаться конца срока, а это зависание, а не остановка
		 */
		this->_cond.wait_for(lock, chrono::milliseconds(this->_delay), [this, round]() noexcept -> bool {
			// Выводим признак остановки работы отбоя срока либо смены круга отбоя
			return (!this->_working || (this->_round != round));
		});
		/**
		 * Если работа отбоя срока остановлена либо круг отбоя сменился, выходим из потока
		 *
		 * @warning Поверка круга здесь обязательна наравне с признаком работы: перезапуск ИЗ
		 *          ОТКЛИКА снимает признак работы и тут же ставит его обратно, а поток,
		 *          исполняющий отклик, прочесть снятое не успевает вовсе. Прежде поверялся
		 *          один лишь признак, и отставленный поток отбивал срок наравне с новым -
		 *          замер щупом 16.09.2026 дал 32 отбоя вместо двадцати и ДВА потока-отбивалы.
		 *          Закреплено `CodecAbcSchedule.RestartFromInsideTheCallbackLeavesOneBeater`
		 */
		if(!this->_working || (this->_round != round))
			// Прекращаем отбой срока
			return;
		// Выполняем получение работы, зовомой по наступлении срока
		function <void (void)> callback = this->_callback;
		// Выполняем установку штампа времени наступившего срока
		this->_stamp = stamp();
		// Выполняем освобождение замка состояния отбоя срока
		lock.unlock();
		/**
		 * Если работа по наступлении срока установлена, выполняем её вне замка:
		 * работа эта ходит в правщика со своим замком, и держать при том свой
		 * значило бы сводить два замка в один порядок захвата
		 */
		if(callback != nullptr)
			// Выполняем работу, зовомую по наступлении срока
			callback();
	}
}
/**
 * @brief Метод установки работы, зовомой по наступлении срока
 *
 * @param callback устанавливаемая работа
 *
 */
void awh::codec::abc::Schedule::callback(function <void (void)> callback) noexcept {
	// Выполняем захват замка состояния отбоя срока
	lock_guard <mutex> lock(this->_mtx);
	// Выполняем установку работы, зовомой по наступлении срока
	this->_callback = ::std::move(callback);
}
/**
 * @brief Метод запуска отбоя срока
 *
 * @param mode  способ отбоя срока
 * @param delay срок отбоя в миллисекундах
 * @return      признак успешного запуска
 *
 */
bool awh::codec::abc::Schedule::start(const mode_t mode, const uint32_t delay) noexcept {
	// Выполняем остановку прежнего отбоя срока
	this->stop();
	/**
	 * Если отбой срока не затребован вовсе
	 */
	if((mode == mode_t::NONE) || (delay == 0))
		// Выводим признак того, что отбой срока не запущен
		return false;
	// Выполняем захват замка состояния отбоя срока
	unique_lock <mutex> lock(this->_mtx);
	// Выполняем установку способа отбоя срока
	this->_mode = mode;
	// Выполняем установку срока отбоя
	this->_delay = delay;
	// Выполняем установку признака работы отбоя срока
	this->_working = true;
	// Выполняем установку штампа времени начала отсчёта срока
	this->_stamp = stamp();
	/**
	 * Выполняем переход на новый круг отбоя срока
	 *
	 * @note Круг растёт ВСЯКИМ запуском, а не одним лишь потоковым: запуск штампом времени
	 *       равно отставляет прежний поток, и тот обязан о том узнать
	 */
	this->_round++;
	/**
	 * Если срок отбивается своим потоком
	 */
	if(mode == mode_t::THREAD){
		/**
		 * Выполняем заведение потока отбоя срока ПОД ЗАМКОМ.
		 *
		 * @warning Замок здесь обязателен: остановка, зовомая ИЗ ОТКЛИКА, исполняется в
		 *          самом потоке отбоя и читает объект потока (`joinable`, `get_id`),
		 *          тогда как запуск в него ПИШЕТ. Прежде замок здесь снимался вперёд
		 *          заведения, и выходила гонка данных по объекту потока - найдена
		 *          ThreadSanitizer 13.09.2026 на `StopFromCallbackDoesNotAbort`, без
		 *          санитайзера проходила молча
		 *
		 * @note Заведение под замком безопасно: заведённый поток упрётся в этот же замок
		 *       в начале своего хода и подождёт, покуда запуск замок отпустит. Ожидания
		 *       конца потока запуск не делает, оттого встречного ожидания тут нет
		 */
		this->_thread = thread(&Schedule::run, this, this->_round);
		// Выполняем освобождение замка состояния отбоя срока
		lock.unlock();
	}
	// Выводим признак успешного запуска отбоя срока
	return true;
}
/**
 * @brief Метод остановки отбоя срока
 *
 */
void awh::codec::abc::Schedule::stop() noexcept {
	{
		// Выполняем захват замка состояния отбоя срока
		lock_guard <mutex> lock(this->_mtx);
		// Выполняем снятие признака работы отбоя срока
		this->_working = false;
	}
	// Выполняем пробуждение потока отбоя срока
	this->_cond.notify_all();
	/**
	 * Если поток отбоя срока заведён
	 *
	 * @details Выхода вперёд по снятому признаку работы здесь НЕТ намеренно: прежде он
	 *          стоял, и остановка, застав отбой уже остановленным, ожидания конца потока
	 *          не делала. Поток при том оставался ожидаемым, а следующий запуск клал
	 *          новый поток поверх ожидаемого - и это `std::terminate` по стандарту
	 */
	/**
	 * Вместилище потоков, ожидание конца которых берёт на себя эта остановка
	 *
	 * @warning Ожидание идёт ВНЕ замка, а под замком лишь изымаются потоки. Держать
	 *          замок при ожидании нельзя: рабочий ход берёт тот же замок всяким
	 *          кругом, и ожидание под ним было бы встречным - остановка ждала бы
	 *          потока, а поток ждал бы замка
	 */
	vector <thread> awaited;
	{
		/**
		 * Выполняем захват замка состояния отбоя срока
		 *
		 * @warning Замок здесь обязателен: запуск ПИШЕТ объект потока, а остановка,
		 *          зовомая из отклика, его ЧИТАЕТ, исполняясь в самом потоке отбоя.
		 *          Прежде касания эти шли без замка вовсе, и выходила гонка данных -
		 *          найдена ThreadSanitizer 13.09.2026
		 */
		lock_guard <mutex> lock(this->_mtx);
		/**
		 * Если поток отбоя срока заведён
		 *
		 * @details Выхода вперёд по снятому признаку работы здесь НЕТ намеренно: прежде он
		 *          стоял, и остановка, застав отбой уже остановленным, ожидания конца потока
		 *          не делала. Поток при том оставался ожидаемым, а следующий запуск клал
		 *          новый поток поверх ожидаемого - и это `std::terminate` по стандарту
		 */
		if(this->_thread.joinable()){
			/**
			 * Если остановка затребована ИЗ САМОГО потока отбоя срока
			 *
			 * @details Ожидание себя самого стандартом запрещено: `join` отвечает отказом
			 *          «Resource deadlock avoided», отказ этот есть исключение, а остановка
			 *          объявлена `noexcept` - и работа снималась целиком. Замер 01.09.2026:
			 *          остановка, зовомая из отклика наступившего срока, валила щуп с кодом
			 *          134. Ход же этот законен и потребителю естественен - «отбей однажды
			 *          и остановись»
			 *
			 * @note Ожидание не теряется, а ПЕРЕКЛАДЫВАЕТСЯ: признак работы снят, поток
			 *       выйдет сам, едва отклик вернётся, а ожидание конца его возьмёт на себя
			 *       следующая остановка либо разрушитель
			 *
			 * @note Поток при том уходит В ОТСТАВКУ, а не остаётся в поле, и это не порядка
			 *       ради. Прежде он оставался, и самоперезапуск - «отбей и заведи срок
			 *       иной», ход столь же законный, - клал новый поток ПОВЕРХ ожидаемого, а
			 *       это `std::terminate` по стандарту. Замер щупом 03.09.2026: перезапуск из
			 *       отклика валил щуп с кодом 134, то есть починкой самоожидания был возвращён
			 *       ровно тот отказ, какой ею же и чинился. Закреплено
			 *       `CodecAbcSchedule.RestartFromInsideTheCallback`
			 *
			 * @warning Отвязать отставного нельзя: отвязанный, он трогал бы замок объекта уже
			 *          разрушенного
			 */
			if(this->_thread.get_id() != this_thread::get_id())
				// Выполняем изъятие потока отбоя срока под ожидание вне замка
				awaited.push_back(::std::move(this->_thread));
			// Иначе отправляем поток отбоя срока в отставку, освобождая место под новый
			else this->_retired.push_back(::std::move(this->_thread));
		}
		/**
		 * Выполняем изъятие потоков, ушедших в отставку
		 *
		 * @note Отставной, оказавшийся НЫНЕШНИМ потоком, изъятия не терпит и остаётся в
		 *       отставке: ждать себя самого нельзя и здесь. Случай этот приходится ровно на
		 *       остановку, зовомую из отклика, - тот самый поток только что и отставлен
		 */
		for(size_t i = this->_retired.size(); i > 0; i--){
			// Выполняем получение очередного отставного потока отбоя срока
			thread & retired = this->_retired.at(i - 1);
			// Если отставной поток ожидания более не требует, снимаем его с учёта
			if(!retired.joinable())
				// Выполняем снятие отставного потока с учёта
				this->_retired.erase(this->_retired.begin() + static_cast <ptrdiff_t> (i - 1));
			/**
			 * Если отставной поток нынешним не является, изымаем его под ожидание
			 */
			else if(retired.get_id() != this_thread::get_id()){
				// Выполняем изъятие отставного потока под ожидание вне замка
				awaited.push_back(::std::move(retired));
				// Выполняем снятие отставного потока с учёта
				this->_retired.erase(this->_retired.begin() + static_cast <ptrdiff_t> (i - 1));
			}
		}
	}
	/**
	 * Выполняем ожидание конца изъятых потоков вне замка
	 */
	for(thread & item : awaited){
		// Если изъятый поток ожидания ещё не взял
		if(item.joinable())
			// Выполняем ожидание конца изъятого потока отбоя срока
			item.join();
	}
	// Выполняем захват замка состояния отбоя срока
	lock_guard <mutex> lock(this->_mtx);
	// Выполняем сброс способа отбоя срока
	this->_mode = mode_t::NONE;
}
/**
 * @brief Метод поверки наступления срока при обращении
 *
 * @return признак наступления срока
 *
 */
bool awh::codec::abc::Schedule::touch() noexcept {
	// Выполняем захват замка состояния отбоя срока
	lock_guard <mutex> lock(this->_mtx);
	/**
	 * Если срок отбивается не штампом времени, поверка эта не о нём
	 */
	if(!this->_working || (this->_mode != mode_t::DEADLINE))
		// Выводим признак того, что срок не наступил
		return false;
	// Выполняем получение нынешнего штампа времени
	const uint64_t current = stamp();
	/**
	 * Если срок ещё не вышел
	 */
	if((current - this->_stamp) < static_cast <uint64_t> (this->_delay))
		// Выводим признак того, что срок не наступил
		return false;
	// Выполняем установку штампа времени наступившего срока
	this->_stamp = current;
	// Выводим признак наступления срока
	return true;
}
/**
 * @brief Метод проверки работы отбоя срока
 *
 * @return признак работы отбоя срока
 *
 */
bool awh::codec::abc::Schedule::working() const noexcept {
	/**
	 * Выполняем захват замка состояния отбоя срока
	 *
	 * @note Признак этот правится потоком отбоя, и чтение его без замка есть гонка -
	 *       TSan её видит. Замок здесь ничего не стоит: спрашивают состояние редко
	 */
	lock_guard <mutex> lock(this->_mtx);
	// Выводим признак работы отбоя срока
	return this->_working;
}
/**
 * @brief Метод извлечения способа отбоя срока
 *
 * @return способ отбоя срока
 *
 */
awh::codec::abc::Schedule::mode_t awh::codec::abc::Schedule::mode() const noexcept {
	// Выполняем захват замка состояния отбоя срока
	lock_guard <mutex> lock(this->_mtx);
	// Выводим способ отбоя срока
	return this->_mode;
}
/**
 * @brief Конструктор
 *
 */
awh::codec::abc::Schedule::Schedule() noexcept :
 _mode(mode_t::NONE), _delay(0), _working(false), _stamp(0), _round(0), _callback(nullptr) {}
/**
 * @brief Деструктор
 *
 */
awh::codec::abc::Schedule::~Schedule() noexcept {
	// Выполняем остановку отбоя срока
	this->stop();
}
