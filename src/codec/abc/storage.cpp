/**
 * @brief Конструктор
 *
 * @param log объект для работы с логами
 *
 */
awh::codec::abc::Storage::Storage(const fmk_t * fmk, const log_t * log) noexcept :
 _fs(fmk, log), _sync(sync_t::FULL), _opened(false),
 _length(0), _error(error_t::NONE), _log(log) {}
/**
 * @brief Деструктор
 *
 */
awh::codec::abc::Storage::~Storage() noexcept {
	// Выполняем закрытие файла контейнера
	this->close();
}
/**
 * @brief Метод объявления отказа работы с носителем
 *
 * @param error объявляемый код отказа
 * @return      признак успешности, всегда ложь
 *
 */
bool awh::codec::abc::Storage::fail(const error_t error) noexcept {
	// Выполняем установку кода отказа
	this->_error = error;
	/**
	 * Если объект логирования отдан, доносим об отказе.
	 *
	 * @warning Сброс кода отказа сюда НЕ идёт: воронка эта объявляет отказ, а сброс
	 *          лишь снимает прежний, и донесение о нём наполняло бы журнал записями
	 *          «no error» на всякий успешный вызов. Проверено на себе
	 */
	if((error != error_t::NONE) && (this->_log != nullptr)){
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("ABC: %s", __PRETTY_FUNCTION__, make_tuple(static_cast <uint16_t> (error)),
			 log_t::flag_t::WARNING, abc::message(error));
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("ABC: %s", log_t::flag_t::WARNING, abc::message(error));
		#endif
	}
	// Сообщаем, что работа отвечена отказом
	return false;
}
/**
 * @brief Метод открытия существующего файла контейнера
 *
 * @param filename название открываемого файла контейнера
 * @return         признак успешно открытого файла
 *
 */
bool awh::codec::abc::Storage::open(const string & filename) noexcept {
	// Выполняем закрытие ранее открытого файла контейнера
	this->close();
	// Выполняем сброс кода отказа работы с файлом
	this->_error = error_t::NONE;
	/**
	 * Если открываемое файлом не является
	 *
	 * @note Поверка эта заменила собою отказ открытия потока видом `r+b`: файловая
	 *       система описатель заводит ЛЕНИВО, первым обращением, и отказ открытия
	 *       приходил бы не здесь, а на первом чтении - то есть позже, чем о нём
	 *       следует знать. Каталог, канал и отсутствующий файл отсекаются все трое:
	 *       файлом ни один из них не зовётся
	 */
	if(this->_fs.type(filename) != fs_t::type_t::FILE){
		// Выполняем установку кода отказа чтения октетов контейнера
		this->fail(error_t::UNREADABLE_SOURCE);
		// Выводим признак неудачно открытого файла
		return false;
	}
	/**
	 * Выполняем заведение объектов файла контейнера
	 *
	 * @note Объектов ДВА: объект файловой системы несёт права той работы, какая его
	 *       завела, и один объект достался бы тому, кто обратился первым
	 */
	this->_reader = this->_fs.handleFile();
	// Выполняем заведение объекта файла контейнера на запись
	this->_writer = this->_fs.handleFile();
	// Выполняем получение полной длины контейнера
	this->_length = static_cast <uint64_t> (this->_fs.size(filename));
	// Выполняем запоминание названия файла контейнера
	this->_filename = filename;
	// Отмечаем хранилище привязанным к файлу контейнера
	this->_opened = true;
	// Выводим признак успешно открытого файла
	return true;
}
/**
 * @brief Метод заведения нового файла контейнера
 *
 * @param filename название заводимого файла контейнера
 * @return         признак успешно заведённого файла
 *
 */
bool awh::codec::abc::Storage::create(const string & filename) noexcept {
	// Выполняем закрытие ранее открытого файла контейнера
	this->close();
	// Выполняем сброс кода отказа работы с файлом
	this->_error = error_t::NONE;
	/**
	 * Если завести файл контейнера пустым не удалось
	 *
	 * @note Усечение до нуля заменило собою заведение потока видом `w+b`: тот
	 *       существующий файл усекал, а отсутствующий заводил, - усечение до нуля
	 *       делает ровно то же. Оно же и отсекает негодный путь СРАЗУ, не откладывая
	 *       отказ до первой записи: заведение описателя у файловой системы ленивое
	 */
	if(!this->_fs.truncate(filename)){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачно заведённого файла
		return false;
	}
	/**
	 * Выполняем заведение объектов файла контейнера
	 *
	 * @note Объектов ДВА: объект файловой системы несёт права той работы, какая его
	 *       завела, и один объект достался бы тому, кто обратился первым
	 */
	this->_reader = this->_fs.handleFile();
	// Выполняем заведение объекта файла контейнера на запись
	this->_writer = this->_fs.handleFile();
	// Выполняем запоминание названия файла контейнера
	this->_filename = filename;
	// Выполняем сброс полной длины контейнера
	this->_length = 0;
	// Отмечаем хранилище привязанным к файлу контейнера
	this->_opened = true;
	// Выводим признак успешно заведённого файла
	return true;
}
/**
 * @brief Метод закрытия файла контейнера
 *
 */
void awh::codec::abc::Storage::close() noexcept {
	/**
	 * Выполняем снос объектов файла контейнера
	 *
	 * @note Описатели закрываются самими объектами: снос умного указателя и есть
	 *       закрытие. Своего вызова закрытия здесь нет и быть не должно
	 */
	this->_reader.reset();
	// Выполняем снос объекта файла контейнера на запись
	this->_writer.reset();
	// Отмечаем хранилище отвязанным от файла контейнера
	this->_opened = false;
	// Выполняем очистку названия файла контейнера
	this->_filename.clear();
	// Выполняем сброс полной длины контейнера
	this->_length = 0;
}
/**
 * @brief Метод сброса записанного на носитель
 *
 * @return признак успешности сброса
 *
 */
bool awh::codec::abc::Storage::flush() noexcept {
	// Если файл контейнера не открыт
	if(!this->_opened)
		// Выводим признак неудачного сброса
		return false;
	/**
	 * Выполняем сброс записанного из ЯДРА на носитель
	 *
	 * @details Запись, отвеченная успехом, лежит ещё во вместилище ядра: обрыв работы
	 *          такую запись переживает, а обрыв питания - нет. Хвостовой заголовок
	 *          опознания кладётся прежде головного именно ради обрыва, и порядок этот
	 *          стоит ровно столько, сколько стоит доведение записанного до носителя
	 *
	 * @note Сброс идёт ТЕМ ЖЕ объектом файла, каким шла запись: иной описатель
	 *       записанного этим не доведёт, и сброс вышел бы пустым обрядом
	 *
	 * @note Способ сброса - настройка потребителя, а не признак системы: цена полного
	 *       сброса замерена и высока (43 мкс против 4604 мкс на круг, 02.09.2026), и
	 *       выбор между обещанием пережить обрыв ПИТАНИЯ и обещанием пережить обрыв
	 *       ПРОГРАММЫ принадлежит тому, кто знает цену своим данным. Умолчанием взято
	 *       первое: умолчание держит обещание, а не быстроту
	 *
	 * @note Разводит способы систем сама файловая система AWH: `F_FULLFSYNC` у систем
	 *       Apple, `fdatasync` там, где он есть, `FlushFileBuffers` под MS Windows, - и
	 *       отказ носителя, сброса не держащего, отказом записи не зовётся. Своего кода
	 *       под эти три ветви здесь нет и быть не должно
	 */
	if(!this->_fs.flush(this->_filename, (this->_sync == sync_t::FULL), this->_writer)){
		// Выполняем установку кода отказа записи октетов контейнера
		this->fail(error_t::UNWRITABLE_SINK);
		// Выводим признак неудачного сброса
		return false;
	}
	// Выводим признак успешного сброса
	return true;
}
