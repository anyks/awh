/**
 * Подключаем заголовочный файл
 */
#include <alloc/link.hpp>

/**
 * Стандартные заголовочные файлы
 */
#include <chrono>

/**
 * Если набором команд является x86-64 либо ARM64
 */
#if defined(__x86_64__) && !defined(_MSC_VER)
	#include <x86intrin.h>
#endif

/**
 * Зерно перемешивания указателей
 *
 * Нуль до посева намеренно: до заведения центральных списков связан не бывает ни
 * один блок, а значит и прочитан старым зерном быть не может
 */
uintptr_t awh::alloc::Link::_cookie = 0;

/**
 * @brief Пространство имён вспомогательных средств
 *
 */
namespace {
	/**
	 * @brief Метод перемешивания разрядов числа
	 *
	 * @note Взят у splitmix64: рассеивает единичный разряд по всему числу
	 *
	 * @param value перемешиваемое число
	 * @return      перемешанное число
	 *
	 */
	/**
	 * @brief Метод снятия показания счётчика тактов
	 *
	 * @note Показание снимается КОМАНДОЙ, а не вызовом: посев зерна достаётся первой же
	 *       выдаче памяти, а та у систем ELF случается из нутра самого связывателя -
	 *       довод при посеве
	 *
	 * @return показание счётчика тактов
	 *
	 */
	static uint64_t ticking() noexcept {
		/**
		 * Если набором команд является x86-64
		 */
		#if defined(__x86_64__) && !defined(_MSC_VER)
			// Выводим показание счётчика тактов
			return static_cast <uint64_t> (__rdtsc());
		/**
		 * Если набором команд является ARM64
		 */
		#elif defined(__aarch64__) && !defined(_MSC_VER)
			// Показание счётчика тактов
			uint64_t ticks = 0;
			// Выполняем чтение показания счётчика тактов
			__asm__ volatile("mrs %0, cntvct_el0" : "=r" (ticks) :: "memory");
			// Выводим показание счётчика тактов
			return ticks;
		/**
		 * Если это иной набор команд
		 */
		#else
			/**
			 * Счётчика тактов командою здесь нет, и показания берутся часами
			 *
			 * Дорога эта достаётся нативному MSVC и наборам команд, каких у нас пока
			 * нет. Запрета она не нарушает: запрет тот принадлежит системам ELF, где
			 * выдача подменяется связыванием и первая же просьба приходит из нутра
			 * связывателя. У MS Windows подмена идёт переписыванием входа, из
			 * связывателя нас не зовут вовсе, и часы там безопасны
			 */
			return static_cast <uint64_t> (std::chrono::steady_clock::now().time_since_epoch().count());
		#endif
	}
	static uint64_t stir(uint64_t value) noexcept {
		// Перемешиваем разряды числа
		value += 0x9E3779B97F4A7C15ULL;
		value = (value ^ (value >> 30)) * 0xBF58476D1CE4E5B9ULL;
		value = (value ^ (value >> 27)) * 0x94D049BB133111EBULL;
		// Выводим перемешанное число
		return (value ^ (value >> 31));
	}
};

/**
 * @brief Метод посева зерна перемешивания
 *
 */
void awh::alloc::Link::seed() noexcept {
	// Если зерно уже посеяно
	if(Link::_cookie != 0)
		// Выходим из функции
		return;
	// Место переменной стека
	uint64_t anchor = 0;
	/**
	 * Собираем зерно из того, что не требует выделения памяти
	 *
	 * Случайных чисел здесь взять неоткуда: всякий их источник волен обратиться к
	 * выделению памяти, а зовут нас из-под перехваченного malloc. Оттого зерно
	 * собирается из разброса адресов, какой даёт сама система, и показания счётчика
	 * тактов
	 *
	 * Запрет здесь ВТОРОЙ, и он строже первого: у систем ELF имена подменяются
	 * связыванием, и первая же выдача памяти достаётся нам ИЗ НУТРА связывателя - тот
	 * просит памяти под своё же сообщение. Всякий вызов, какому нужно разрешение метки,
	 * входит в связыватель вторично и получает пустой вход: замерено под AddressSanitizer
	 * на Debian 12, где `steady_clock::now()` из libstdc++ уходил по адресу нуль и валил
	 * процесс прежде первой строки `main`. Оттого показание времени снимается КОМАНДОЙ
	 * набора, а не вызовом библиотеки
	 */
	uint64_t result = ::stir(static_cast <uint64_t> (reinterpret_cast <uintptr_t> (&anchor)));
	// Примешиваем место кода самого распределителя
	result ^= ::stir(static_cast <uint64_t> (reinterpret_cast <uintptr_t> (&Link::_cookie)));
	// Примешиваем показание счётчика тактов
	result ^= ::stir(::ticking());
	// Перемешиваем собранное ещё раз
	result = ::stir(result);
	// Закрепляем зерно, не допуская нуля
	Link::_cookie = static_cast <uintptr_t> (result | 1);
}
