/**
 * Подключаем заголовочный файл
 */
#include <alloc/spin.hpp>

/**
 * Если операционной системой является MS Windows
 */
#if defined(_WIN32) || defined(_WIN64)
	/**
	 * Стандартные заголовочные файлы
	 */
	#include <windows.h>
/**
 * Если операционной системой является Unix
 */
#else
	/**
	 * Стандартные заголовочные файлы
	 */
	#include <sched.h>
#endif

/**
 * Отклик на заклинивший замок
 *
 * Один на все замки процесса: заклинивают они по одной причине - ветвление, - и
 * разбирается она разом для всех
 */
static void (* __awh_spin_stuck__)() = nullptr;

/**
 * @brief Метод задания отклика на заклинивший замок
 *
 * @param callback функция обратного вызова
 *
 */
void awh::alloc::Spin::onStuck(void (* callback)()) noexcept {
	// Запоминаем отклик на заклинивший замок
	::__awh_spin_stuck__ = callback;
}
/**
 * @brief Конструктор
 *
 */
awh::alloc::Spin::Spin() noexcept : _held(0) {}
/**
 * @brief Метод захвата замка кружением
 *
 */
void awh::alloc::Spin::wait() noexcept {
	// Число уступок времени
	uint32_t yields = 0;
	/**
	 * Кружим до освобождения замка
	 */
	for(uint32_t round = 0; ; round++){
		// Значение незахваченного замка
		uint32_t free = 0;
		// Пробуем захватить замок
		if(this->_held.compare_exchange_weak(free, 1, std::memory_order_acquire, std::memory_order_relaxed))
			// Замок захвачен
			return;
		/**
		 * Уступаем время, накружившись
		 *
		 * Уступаем именно системе, а не крутимся дальше: на машине с одним ядром
		 * удерживающий замок поток не двинется, пока кружащий не будет снят силой
		 */
		if(round >= ROUNDS){
			/**
			 * Если операционной системой является MS Windows
			 */
			#if defined(_WIN32) || defined(_WIN64)
				// Уступаем время другому потоку
				::SwitchToThread();
			/**
			 * Если операционной системой является Unix
			 */
			#else
				// Уступаем время другому потоку
				::sched_yield();
			#endif
			// Начинаем отсчёт оборотов заново
			round = 0;
			/**
			 * Спрашиваем о заклинившем замке
			 *
			 * Тысяча уступок времени подряд - это уже не состязание потоков: держатель
			 * замка либо не работает вовсе, либо не существует. Второе случается у
			 * потомка ветвления, о каком нам не сообщили. Проверка эта ничего не стоит
			 * на обычном пути: сюда доходят лишь по-настоящему заклинившие замки
			 */
			if((++yields >= STUCK) && (::__awh_spin_stuck__ != nullptr)){
				// Начинаем отсчёт уступок заново
				yields = 0;
				// Разбираем причину заклинивания
				(* ::__awh_spin_stuck__)();
			}
		/**
		 * Кружим, не уступая времени
		 */
		} else {
			/**
			 * Ждём освобождения замка чтением, а не обменом
			 *
			 * Обмен занимает строку кэша на запись у всех кружащих разом, а чтение
			 * оставляет её общей, - оттого кружение чтением не мешает удерживающему
			 * замок потоку работать
			 */
			while(this->_held.load(std::memory_order_relaxed) != 0){
				// Если оборотов накружено довольно
				if((++round) >= ROUNDS)
					// Выходим на уступку времени
					break;
			}
		}
	}
}
/**
 * @brief Метод принудительного освобождения замка
 *
 */
void awh::alloc::Spin::reset() noexcept {
	// Освобождаем замок, не глядя на его состояние
	this->_held.store(0, std::memory_order_release);
}
