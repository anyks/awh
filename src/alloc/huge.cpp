#include <cstring>

/**
 * Метка снесённого места таблицы поиска
 *
 */
awh::alloc::Huge::record_t * const awh::alloc::Huge::_tomb = reinterpret_cast <awh::alloc::Huge::record_t *> (static_cast <uintptr_t> (1));

/**
 * @brief Конструктор
 *
 */
awh::alloc::Huge::Huge() noexcept :
 _source(nullptr), _table(nullptr), _length(0), _region(0), _enrolled(0), _buried(0),
 _meta(nullptr), _metaLeft(0), _metaChunks(nullptr), _spare(nullptr),
 _cached(nullptr), _cachedBytes(0), _ceiling(0) {}

/**
 * @brief Метод выдачи памяти под учётную запись
 *
 * @return адрес выданной памяти либо nullptr
 *
 */
void * awh::alloc::Huge::meta() noexcept {
	// Если есть повторно используемая учётная запись
	if(this->_spare != nullptr){
		// Запоминаем повторно используемую учётную запись
		record_t * result = this->_spare;
		// Сдвигаем список повторно используемых записей
		this->_spare = result->spare;
		// Выводим повторно используемую учётную запись
		return result;
	}
	// Приводим размер записи к границе восьми байт
	const size_t need = ((sizeof(record_t) + 7u) & ~static_cast <size_t> (7u));
	// Если в текущем куске места не осталось
	if(this->_metaLeft < need){
		// Требуемый размер куска под учётные записи
		const size_t span = (64u * 1024u);
		// Действительно выданный размер
		size_t actual = 0;
		// Берём у источника кусок под учётные записи
		uint8_t * block = reinterpret_cast <uint8_t *> (this->_source->alloc(span, 0, actual));
		// Если кусок не выдан
		if(block == nullptr)
			// Отвечаем отказом
			return nullptr;
		/**
		 * Вносим кусок в общий список
		 *
		 * Первые восемь байт куска отводятся под указатель на предыдущий, оттого списку
		 * не нужно собственной памяти. Прежде здесь стояло, что связь эта невозможна -
		 * дескать, первые байты уже отданы под записи, - но страничная куча ведёт свой
		 * такой же список ровно этим приёмом: под записи отдаётся кусок ЗА указателем
		 */
		/**
		 * В заголовке куска хранится и его РАЗМЕР, а не только связь
		 *
		 * Источник вправе выдать больше запрошенного, округлив запрос по своему зерну, и
		 * размер этот у кусков волен разниться. Отдавать их постоянной величиной значило
		 * бы возвращать системе не то, что у неё взято
		 */
		// Размер заголовка куска: связь и размер
		const size_t header = (sizeof(void *) + sizeof(size_t));
		// Записываем в начало куска указатель на предыдущий
		::memcpy(block, &this->_metaChunks, sizeof(void *));
		// Записываем следом размер выданного куска
		::memcpy((block + sizeof(void *)), &actual, sizeof(size_t));
		// Запоминаем кусок как последний
		this->_metaChunks = block;
		// Сдвигаем начало выдачи за заголовок
		this->_meta = (block + header);
		// Запоминаем остаток куска
		this->_metaLeft = (actual - header);
	}
	// Запоминаем адрес выдачи
	void * result = this->_meta;
	// Сдвигаем начало выдачи
	this->_meta += need;
	// Уменьшаем остаток куска
	this->_metaLeft -= need;
	// Выводим адрес выданной памяти
	return result;
}
/**
 * @brief Метод перестроения таблицы поиска
 *
 * @param length требуемая длина таблицы в местах
 * @return       признак перестроения таблицы
 *
 */
bool awh::alloc::Huge::rehash(const size_t length) noexcept {
	// Действительно выданный размер
	size_t actual = 0;
	// Требуемый размер новой таблицы в байтах
	const size_t size = (length * sizeof(record_t *));
	// Берём у источника память под новую таблицу
	record_t ** table = reinterpret_cast <record_t **> (this->_source->alloc(size, 0, actual));
	// Если память под таблицу не выдана
	if(table == nullptr)
		// Отвечаем отказом
		return false;
	// Обнуляем места новой таблицы
	::memset(table, 0, size);
	// Запоминаем прежнюю таблицу прежде подмены
	record_t ** previous = this->_table;
	// Запоминаем длину прежней таблицы
	const size_t before = this->_length;
	/**
	 * Запоминаем размер прежней области, а не считаем его по длине таблицы
	 *
	 * Источник округляет запрос по своему зерну и вправе выдать больше запрошенного:
	 * начальная таблица просит 512 байт, а получает страницу целиком. Отдай мы её
	 * запрошенным размером - счёт взятого у системы не сошёлся бы на разницу, и
	 * заказанный приложением потолок закрыл бы выдачу тем раньше, чем дольше работа
	 */
	const size_t region = this->_region;
	// Подменяем таблицу новой
	this->_table = table;
	// Запоминаем длину новой таблицы
	this->_length = length;
	// Запоминаем размер взятой под новую таблицу области
	this->_region = actual;
	// Внесённых записей у новой таблицы пока нет
	this->_enrolled = 0;
	// Снесённых мест у новой таблицы тоже нет: перестроение их и убирает
	this->_buried = 0;
	/**
	 * Переносим в новую таблицу записи прежней
	 */
	for(size_t i = 0; i < before; i++){
		// Если место прежней таблицы занято живой записью
		if((previous[i] != nullptr) && (previous[i] != _tomb))
			// Вносим запись в новую таблицу
			this->enroll(previous[i]);
	}
	// Если прежняя таблица заведена
	if(previous != nullptr)
		// Отдаём источнику память прежней таблицы
		this->_source->release(previous, region);
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод внесения записи в таблицу поиска
 *
 * @note Место в таблице берётся маской: длина её всегда степень двойки - начальная
 *       такова, а перестроение её удваивает
 *
 * @param record вносимая запись
 * @return       признак внесения записи
 *
 */
bool awh::alloc::Huge::enroll(record_t * record) noexcept {
	// Если таблица не заведена либо заполнена наполовину
	/**
	 * Считаем занятыми и снесённые места, а не одни живые записи
	 *
	 * Место снесённой записи пустым не становится: поиск идёт подряд до первого
	 * ПУСТОГО места, и надгробие его не останавливает. Длина же при перестроении
	 * выбирается по живым записям: забита таблица надгробиями - перестроение той же
	 * длины их и уберёт, расти ей положено лишь от тесноты живых
	 */
	if((this->_length == 0) || (((this->_enrolled + this->_buried + 1) * 2) > this->_length)){
		/**
		 * Перестраиваем таблицу вдвое большей длины
		 *
		 * Порог в половину длины взят не для скорости, а для завершимости: перебор мест
		 * идёт подряд, и при плотном заполнении он вырождается в перебор всей таблицы
		 */
		if(!this->rehash((this->_length == 0) ? TABLE :
		 ((((this->_enrolled + 1) * 2) > this->_length) ? (this->_length * 2) : this->_length)))
			// Отвечаем отказом
			return false;
	}
	// Определяем ключ записи: адрес выданного блока
	const uintptr_t key = reinterpret_cast <uintptr_t> (record->block);
	// Определяем место записи в таблице
	size_t index = static_cast <size_t> ((key * 0x9E3779B97F4A7C15ull) & (this->_length - 1));
	/**
	 * Ищем свободное место, перебирая места подряд
	 */
	/**
	 * Перебор мест ОГРАНИЧЕН длиною таблицы
	 *
	 * Порог занятости держит таблицу заполненной не более чем наполовину, и свободное
	 * место находится всегда - пока счётчики живых записей и надгробий верны. Сойдись
	 * они с делом хоть однажды, и перебор без границы завис бы навсегда, а зависание от
	 * отказа наружу неотличимо. Поиск записи в этом же файле границу имеет; внесение её
	 * не имело, и подмена это доказала: таблице велели не расти, и набор проверок ПОВИС
	 * вместо того, чтобы упасть. Граница обращает зависание в честный отказ, какой
	 * звавший уже умеет разбирать, и стоит она одного сличения на холодном пути
	 */
	// Число пройденных мест таблицы
	size_t passed = 0;
	while((this->_table[index] != nullptr) && (this->_table[index] != this->_tomb)){
		// Если запись в таблице уже есть
		if(this->_table[index]->block == record->block)
			// Вносить нечего
			return true;
		// Переходим к следующему месту таблицы
		index = ((index + 1) & (this->_length - 1));
		// Если пройдена вся таблица
		if((++passed) >= this->_length)
			// Отвечаем отказом: свободного места нет
			return false;
	}
	// Записываем запись в найденное место
	// Если найденное место помечено снесённым
	if(this->_table[index] == this->_tomb)
		// Уменьшаем число снесённых мест: надгробие занято живой записью
		this->_buried--;
	this->_table[index] = record;
	// Увеличиваем число внесённых записей
	this->_enrolled++;
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод поиска записи по адресу блока
 *
 * @param addr  разбираемый адрес
 * @param exact признак поиска ровно по началу блока
 * @return      найденная запись либо nullptr
 *
 */
awh::alloc::Huge::record_t * awh::alloc::Huge::lookup(const void * addr, const bool exact) const noexcept {
	// Если таблица не заведена
	if((this->_table == nullptr) || (this->_length == 0))
		// Искать нечем
		return nullptr;
	// Приводим разбираемый адрес к байтовому виду
	const uint8_t * probe = reinterpret_cast <const uint8_t *> (addr);
	/**
	 * Если требуется поиск ровно по началу блока
	 */
	if(exact){
		// Определяем ключ записи: адрес выданного блока
		const uintptr_t key = reinterpret_cast <uintptr_t> (addr);
		// Определяем место записи в таблице
		size_t index = static_cast <size_t> ((key * 0x9E3779B97F4A7C15ull) & (this->_length - 1));
		// Число пройденных мест таблицы
		size_t passed = 0;
		/**
		 * Перебираем места подряд, пока не встретим пустое
		 */
		while((this->_table[index] != nullptr) && (passed < this->_length)){
			// Если место занято живой записью нужного блока
			if((this->_table[index] != this->_tomb) && (this->_table[index]->block == probe))
				// Выводим найденную запись
				return this->_table[index];
			// Переходим к следующему месту таблицы
			index = ((index + 1) & (this->_length - 1));
			// Увеличиваем число пройденных мест
			passed++;
		}
		// Записи в таблице нет
		return nullptr;
	}
	/**
	 * Перебираем таблицу целиком
	 *
	 * Внутри области адрес лежит где угодно, и начало её из адреса не вычисляется:
	 * области разного размера. Перебор здесь допустим - поиск этот идёт при разборе
	 * адреса, то есть по требованию прикладного кода, а крупных выдач немного
	 */
	for(size_t i = 0; i < this->_length; i++){
		// Запоминаем запись места таблицы
		record_t * record = this->_table[i];
		// Если место таблицы свободно
		if((record == nullptr) || (record == this->_tomb))
			// Переходим к следующему месту
			continue;
		// Если адрес лежит внутри взятой у источника области
		if((probe >= record->base) && (probe < (record->base + record->span)))
			// Выводим найденную запись
			return record;
	}
	// Записи в таблице нет
	return nullptr;
}
/**
 * @brief Метод заведения слоя крупных выдач
 *
 * @param source источник страниц
 * @return       признак заведения слоя
 *
 */
bool awh::alloc::Huge::init(source_t * source) noexcept {
	// Если источник страниц не задан
	if(source == nullptr)
		// Отвечаем отказом
		return false;
	// Запоминаем источник страниц
	this->_source = source;
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод снятия слоя крупных выдач
 *
 */
void awh::alloc::Huge::reset() noexcept {
	// Захватываем замок слоя
	hold_t hold(this->_lock);
	// Если источник страниц не задан
	if(this->_source == nullptr)
		// Снимать нечего
		return;
	/**
	 * Отдаём источнику области крупных выдач
	 */
	for(size_t i = 0; i < this->_length; i++){
		// Запоминаем запись места таблицы
		record_t * record = this->_table[i];
		// Если место таблицы свободно
		if((record == nullptr) || (record == this->_tomb))
			// Переходим к следующему месту
			continue;
		// Отдаём источнику область крупной выдачи
		this->_source->release(record->base, record->span);
	}
	// Если таблица поиска заведена
	if(this->_table != nullptr)
		// Отдаём источнику память таблицы поиска
		this->_source->release(this->_table, this->_region);
	// Сбрасываем таблицу поиска
	this->_table = nullptr;
	// Сбрасываем длину таблицы поиска
	this->_length = 0;
	// Сбрасываем размер взятой под таблицу поиска области
	this->_region = 0;
	// Сбрасываем число внесённых записей
	this->_enrolled = 0;
	// Сбрасываем число снесённых мест
	this->_buried = 0;
	// Сбрасываем список повторно используемых записей
	this->_spare = nullptr;
	/**
	 * Придержанные области отдавать источнику НЕ нужно
	 *
	 * Отдача их прошла бы дважды: записи придержанных областей в таблице поиска не
	 * значатся, но области их уже отданы выше не были - их отдаём здесь, до сброса
	 */
	{
		// Перебираем придержанные области
		for(record_t * record = this->_cached; record != nullptr; record = record->spare)
			// Отдаём источнику придержанную область
			this->_source->release(record->base, record->span);
	}
	// Сбрасываем список придержанных областей
	this->_cached = nullptr;
	// Сбрасываем объём придержанного
	this->_cachedBytes = 0;
	// Сбрасываем состояние слоя
	this->_state = state_t();
	/**
	 * Отдаём источнику куски памяти под учётные записи
	 *
	 * Отдаются ПОСЛЕДНИМИ: учётные записи областей лежат в них же, и отдать их прежде
	 * значило бы читать освобождённую память при обходе списков выше
	 */
	for(void * block = this->_metaChunks; block != nullptr;){
		// Читаем указатель на предыдущий кусок из его начала
		void * previous = nullptr;
		// Извлекаем указатель на предыдущий кусок
		::memcpy(&previous, block, sizeof(void *));
		// Размер отдаваемого куска
		size_t span = 0;
		// Извлекаем размер куска из его заголовка
		::memcpy(&span, (reinterpret_cast <uint8_t *> (block) + sizeof(void *)), sizeof(size_t));
		// Отдаём кусок источнику
		this->_source->release(block, span);
		// Переходим к предыдущему куску
		block = previous;
	}
	// Сбрасываем общий список кусков памяти под учётные записи
	this->_metaChunks = nullptr;
	// Сбрасываем текущий кусок памяти под учётные записи
	this->_meta = nullptr;
	// Сбрасываем остаток текущего куска
	this->_metaLeft = 0;
}
/**
 * @brief Метод задания потолка придержанного
 *
 * @param bytes потолок придержанного в байтах: нуль - не придерживать
 *
 */
void awh::alloc::Huge::ceiling(const size_t bytes) noexcept {
	// Захватываем замок слоя
	hold_t hold(this->_lock);
	// Запоминаем потолок придержанного
	this->_ceiling = bytes;
	/**
	 * Если источник страниц не задан, отдавать излишек некому
	 *
	 * Придержанного при незаведённом слое не бывает, но порядок вызовов задаёт не этот
	 * метод, а звавший: отдача через пустой источник валила бы процесс настройкой
	 */
	if(this->_source == nullptr)
		// Отдавать нечего
		return;
	/**
	 * Излишек над новым потолком отдаём тут же
	 *
	 * Потолок, опущенный при полном списке, иначе не действовал бы до следующего
	 * освобождения: придержанное продолжало бы лежать сверх заказанного
	 */
	while((this->_cached != nullptr) && (this->_cachedBytes > this->_ceiling)){
		// Запоминаем придержанную область
		record_t * record = this->_cached;
		// Сдвигаем список придержанных областей
		this->_cached = record->spare;
		// Уменьшаем объём придержанного
		this->_cachedBytes -= ((this->_cachedBytes < record->span) ? this->_cachedBytes : record->span);
		// Уменьшаем взятое у источника
		this->_state.taken -= ((this->_state.taken < record->span) ? this->_state.taken : record->span);
		// Отдаём источнику придержанную область
		this->_source->release(record->base, record->span);
		// Возвращаем запись в список повторно используемых
		record->spare = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
	}
}
/**
 * @brief Метод отдачи придержанных областей системе
 *
 * @return объём отданного системе в байтах
 *
 */
size_t awh::alloc::Huge::drain() noexcept {
	// Объём отданного системе
	size_t result = 0;
	// Захватываем замок слоя
	hold_t hold(this->_lock);
	// Если источник страниц не задан
	if(this->_source == nullptr)
		// Отдавать нечего
		return result;
	/**
	 * Перебираем придержанные области
	 */
	while(this->_cached != nullptr){
		// Запоминаем придержанную область
		record_t * record = this->_cached;
		// Сдвигаем список придержанных областей
		this->_cached = record->spare;
		// Считаем отданное системе
		result += record->span;
		// Уменьшаем взятое у источника
		this->_state.taken -= ((this->_state.taken < record->span) ? this->_state.taken : record->span);
		// Отдаём источнику придержанную область
		this->_source->release(record->base, record->span);
		// Возвращаем запись в список повторно используемых
		record->spare = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
	}
	// Сбрасываем объём придержанного
	this->_cachedBytes = 0;
	// Выводим объём отданного системе
	return result;
}
/**
 * @brief Метод повторной выдачи придержанной области
 *
 * @note Зовётся ПОД замком слоя: список придержанного правится здесь же
 *
 * @param size      требуемый размер в байтах
 * @param alignment требуемое выравнивание в байтах
 * @param actual    действительный размер выданной области
 * @return          адрес области либо nullptr
 *
 */
uint8_t * awh::alloc::Huge::recycle(const size_t size, const size_t alignment, size_t & actual) noexcept {
	// Если придерживать не велено либо придержанного нет
	if((this->_ceiling == 0) || (this->_cached == nullptr))
		// Повторно выдавать нечего
		return nullptr;
	// Предыдущая запись перебора
	record_t * previous = nullptr;
	// Найденная запись и предшествующая ей
	record_t * found = nullptr, * before = nullptr;
	/**
	 * Ищем НАИМЕНЬШУЮ подходящую область, а не первую попавшуюся
	 *
	 * Первая попавшаяся вправе оказаться вчетверо крупнее запрошенного: выдай мы её -
	 * и прикладной код получил бы блок, за страницы какого никто не платил, а
	 * подходящая по размеру область осталась бы лежать
	 */
	for(record_t * record = this->_cached; record != nullptr; previous = record, record = record->spare){
		// Если область мельче запрошенного
		if(record->span < size)
			// Область не подходит
			continue;
		/**
		 * Сверяем выравнивание области
		 *
		 * Область взята у источника со СВОИМ выравниванием, и запрошенное вправе быть
		 * строже. Область, ему не отвечающую, выдать нельзя: договор выравнивающей
		 * выдачи нарушился бы молча
		 */
		if((alignment > 0) && ((reinterpret_cast <uintptr_t> (record->base) % alignment) != 0))
			// Область не подходит
			continue;
		// Если найденная область крупнее этой
		if((found == nullptr) || (record->span < found->span)){
			// Запоминаем найденную область
			found = record;
			// Запоминаем предшествующую ей запись
			before = previous;
		}
	}
	// Если подходящей области не нашлось
	if(found == nullptr)
		// Повторно выдавать нечего
		return nullptr;
	/**
	 * Отвергаем область, ВДВОЕ крупнее запрошенного
	 *
	 * Придержка бережёт страницы, а не адреса: выдав под пять мегабайт область в
	 * двадцать, мы обязали бы прикладной код платить за учёт вчетверо большего, чем он
	 * просил, и потолок придержанного вычерпался бы одной выдачей
	 */
	if(found->span > (size + size))
		// Повторно выдавать нечего
		return nullptr;
	// Если найденная область первая в списке
	if(before == nullptr)
		// Сдвигаем список придержанных областей
		this->_cached = found->spare;
	// Если найденная область лежит в середине списка
	else before->spare = found->spare;
	// Уменьшаем объём придержанного
	this->_cachedBytes -= ((this->_cachedBytes < found->span) ? this->_cachedBytes : found->span);
	/**
	 * Снимаем область со взятого у источника
	 *
	 * Выдача добавит её туда сама, ровно как и свежую: счёт этот ведётся в одном месте,
	 * и двойной долив изобразил бы вдвое больший расход
	 */
	this->_state.taken -= ((this->_state.taken < found->span) ? this->_state.taken : found->span);
	// Запоминаем действительный размер области
	actual = found->span;
	// Запоминаем адрес области
	uint8_t * result = found->base;
	// Возвращаем запись в список повторно используемых
	found->spare = this->_spare;
	// Запоминаем список повторно используемых записей
	this->_spare = found;
	// Выводим адрес повторно выданной области
	return result;
}
/**
 * @brief Метод придержки освобождённой области
 *
 * @note Зовётся ВНЕ замка слоя: замок берётся здесь
 *
 * @param base адрес начала области
 * @param span размер области в байтах
 * @return     признак придержки области
 *
 */
bool awh::alloc::Huge::retain(uint8_t * base, const size_t span) noexcept {
	// Если придерживать нечего
	if((base == nullptr) || (span == 0))
		// Придерживать нечего
		return false;
	// Захватываем замок слоя
	hold_t hold(this->_lock);
	// Если придерживать не велено либо потолок не вмещает области
	if((this->_ceiling == 0) || ((this->_cachedBytes + span) > this->_ceiling))
		// Область придержать нельзя
		return false;
	// Выдаём память под учётную запись
	record_t * record = reinterpret_cast <record_t *> (this->meta());
	// Если память под учётную запись не выдана
	if(record == nullptr)
		// Область придержать нечем
		return false;
	// Запоминаем адрес начала придержанной области
	record->base = base;
	// Запоминаем размер придержанной области
	record->span = span;
	// Прикладному коду придержанная область не принадлежит
	record->block = nullptr;
	// Затребованного размера у придержанной области нет
	record->size = 0;
	// Укрытых областей здесь не бывает: они затираются и отдаются тут же
	record->hidden = false;
	// Вносим область в список придержанных
	record->spare = this->_cached;
	// Запоминаем список придержанных областей
	this->_cached = record;
	// Увеличиваем объём придержанного
	this->_cachedBytes += span;
	/**
	 * Возвращаем область во взятое у источника
	 *
	 * Освобождение сняло её оттуда, полагая отданной системе, - но придержанная
	 * область у системы ВЗЯТА и лежит у нас. Не верни мы её в счёт - взятое у системы
	 * докладывалось бы меньше настоящего, и потолок кучи считался бы по лжи
	 */
	this->_state.taken += span;
	// Область придержана
	return true;
}
/**
 * @brief Метод определения обслуживаемости размера слоем
 *
 * @param size требуемый размер в байтах
 * @return     признак обслуживаемости размера слоем
 *
 */
bool awh::alloc::Huge::wanted(const size_t size) noexcept {
	// Если размер не задан
	if(size == 0)
		// Слою здесь делать нечего
		return false;
	/**
	 * Сверяем размер на переполнение при приведении к границе страницы
	 *
	 * Счёт страниц у размера близ предела переполняется в нуль, и проверка «страниц
	 * больше, чем в куске» отвечает ложью на САМЫЙ крупный запрос: тот уходил бы к
	 * страничной куче, где счёт этот переполняется ровно так же. Такие размеры слой
	 * берёт на себя и отвечает по ним отказом сам
	 */
	if(size > (static_cast <size_t> (-1) - (awh::alloc::Pages::PAGE - 1)))
		// Запрос обслуживается слоем
		return true;
	// Определяем требуемое число страниц кучи
	const size_t pages = ((size + (awh::alloc::Pages::PAGE - 1)) / awh::alloc::Pages::PAGE);
	// Выводим признак непомещаемости запроса в кусок страничной кучи
	return (pages > awh::alloc::Pages::PAGES);
}
/**
 * @brief Метод крупной выдачи памяти
 *
 * @param size      требуемый размер в байтах
 * @param alignment требуемое выравнивание в байтах, нуль - страничное
 * @return          адрес выданной памяти либо nullptr
 *
 */
void * awh::alloc::Huge::alloc(const size_t size, const size_t alignment) noexcept {
	// Если источник страниц не задан либо размер не задан
	if((this->_source == nullptr) || (size == 0))
		// Выдавать нечего
		return nullptr;
	/**
	 * Сверяем запрос на переполнение при приведении к границе страницы
	 *
	 * Запрос вида (size_t)-1 приходит и от прикладного кода, и от переполнения счёта
	 * длины у стандартной библиотеки. Приведи мы его к границе страницы без сверки -
	 * получили бы нуль, выдача удалась бы, а запись по ней ушла бы в никуда
	 */
	if(size > (static_cast <size_t> (-1) - (awh::alloc::Pages::PAGE - 1)))
		// Отвечаем отказом
		return nullptr;
	// Действительно выданный размер
	size_t actual = 0;
	/**
	 * Захватываем замок слоя ПРЕЖДЕ обращения к источнику
	 *
	 * Прежде замок брался после, и между выдачей у источника и заведением записи
	 * область не значилась НИГДЕ, кроме местной переменной. Ветвление в этот миг
	 * оставляло потомку отображение без записи: освободить его там некому - поток,
	 * который завёл бы запись, остался у родителя, - и область текла безвозвратно
	 *
	 * Цена невелика: обращение к источнику это `mmap`, а его ядро и так проводит под
	 * своим замком по всему пространству процесса; крупные же выдачи по своей природе
	 * редки. Зато отклик ветвления, забирающий этот замок, теперь и вправду ограждает
	 * действие целиком
	 */
	hold_t hold(this->_lock);
	/**
	 * Берём область из придержанных, а к источнику идём лишь за нехваткой
	 *
	 * Придержанная область уже отображена и уже тронута: страницы её достаются без
	 * единого отказа страницы. Свежая же приходит от системы чистой, и за каждую её
	 * страницу платится отказом при первом обращении - замером это три сотни
	 * микросекунд на пять мегабайт против девяти
	 */
	uint8_t * base = this->recycle(size, alignment, actual);
	// Если придержанной области не нашлось
	if(base == nullptr)
		// Берём у источника область под крупную выдачу
		base = reinterpret_cast <uint8_t *> (this->_source->alloc(size, alignment, actual));
	// Если область не выдана
	if(base == nullptr)
		// Выдавать нечего
		return nullptr;
	// Выдаём память под учётную запись
	record_t * record = reinterpret_cast <record_t *> (this->meta());
	// Если память под учётную запись не выдана
	if(record == nullptr){
		// Отдаём источнику взятую область
		this->_source->release(base, actual);
		// Выдавать нечего
		return nullptr;
	}
	// Запоминаем адрес выданного блока
	record->block = base;
	// Запоминаем адрес начала взятой области
	record->base = base;
	// Запоминаем размер взятой области
	record->span = actual;
	// Запоминаем затребованный размер
	record->size = size;
	// Сбрасываем связь повторного использования
	record->spare = nullptr;
	// Обычная выдача укрытой не бывает
	record->hidden = false;
	// Если запись в таблицу поиска не внесена
	if(!this->enroll(record)){
		// Возвращаем запись в список повторно используемых
		record->spare = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
		// Отдаём источнику взятую область
		this->_source->release(base, actual);
		// Выдавать нечего
		return nullptr;
	}
	// Увеличиваем число живых крупных выдач
	this->_state.live++;
	// Увеличиваем взятое у источника
	this->_state.taken += actual;
	// Увеличиваем выданное прикладному коду
	this->_state.given += size;
	// Выводим выданный блок
	return base;
}
/**
 * @brief Метод выдачи блока, укрытого от снимков памяти
 *
 * @param size   требуемый размер в байтах
 * @param hidden признак состоявшегося укрытия
 * @return       адрес выданного блока либо nullptr
 *
 */
void * awh::alloc::Huge::conceal(const size_t size, bool & hidden, const bool wire, bool * wired) noexcept {
	// Укрытия пока не состоялось
	hidden = false;
	// Запрета уходить в подкачку пока не состоялось
	if(wired != nullptr)
		// Отмечаем запрет несостоявшимся
		(* wired) = false;
	// Если выдавать нечего
	if((this->_source == nullptr) || (size == 0))
		// Выдавать нечего
		return nullptr;
	/**
	 * Сверяем запрос на переполнение при приведении к границе страницы
	 */
	if(size > (static_cast <size_t> (-1) - (awh::alloc::Pages::PAGE - 1)))
		// Отвечаем отказом
		return nullptr;
	// Действительно выданный размер
	size_t actual = 0;
	// Захватываем замок слоя прежде обращения к источнику
	hold_t hold(this->_lock);
	// Берём у источника укрытую область
	uint8_t * base = reinterpret_cast <uint8_t *> (this->_source->conceal(size, actual, hidden));
	// Если область не выдана
	if(base == nullptr)
		// Выдавать нечего
		return nullptr;
	// Выдаём память под учётную запись
	record_t * record = reinterpret_cast <record_t *> (this->meta());
	// Если память под учётную запись не выдана
	if(record == nullptr){
		// Отдаём источнику взятую область
		this->_source->release(base, actual);
		// Укрытия не состоялось
		hidden = false;
		// Выдавать нечего
		return nullptr;
	}
	// Запоминаем адрес выданного блока
	record->block = base;
	// Запоминаем адрес начала взятой области
	record->base = base;
	// Запоминаем размер взятой области
	record->span = actual;
	// Запоминаем затребованный размер
	record->size = size;
	// Сбрасываем связь повторного использования
	record->spare = nullptr;
	// Запоминаем признак укрытия
	record->hidden = true;
	// Если запись в таблицу поиска не внесена
	if(!this->enroll(record)){
		// Возвращаем запись в список повторно используемых
		record->spare = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
		// Отдаём источнику взятую область
		this->_source->release(base, actual);
		// Укрытия не состоялось
		hidden = false;
		// Выдавать нечего
		return nullptr;
	}
	// Увеличиваем число живых крупных выдач
	this->_state.live++;
	// Увеличиваем взятое у источника
	this->_state.taken += actual;
	// Увеличиваем выданное прикладному коду
	this->_state.given += size;
	/**
	 * Запрещаем области уходить в подкачку, если о том просили
	 *
	 * Запрет навешивается на уже отведённую область, оттого он и стоит здесь, а не в
	 * самом отведении. Отказ его - обычный исход: право ограничено пределом
	 * `RLIMIT_MEMLOCK`, и понижение это обязано быть видимым звавшему, а не молчаливым
	 */
	if(wire){
		// Ставим запрет уходить в подкачку
		const bool locked = this->_source->wire(base, actual, true);
		// Если ответ о запрете затребован
		if(wired != nullptr)
			// Отдаём признак состоявшегося запрета
			(* wired) = locked;
	}
	// Выводим адрес выданного блока
	return base;
}
/**
 * @brief Метод освобождения крупной выдачи
 *
 * @param ptr адрес освобождаемой памяти
 * @return    затребованный прикладным кодом размер блока либо нуль
 *
 */
size_t awh::alloc::Huge::free(void * ptr) noexcept {
	// Если освобождать нечего
	if((ptr == nullptr) || (this->_source == nullptr))
		// Освобождать нечего
		return 0;
	// Адрес начала отдаваемой области
	uint8_t * base = nullptr;
	// Размер отдаваемой области в байтах
	size_t span = 0;
	// Затребованный прикладным кодом размер блока
	size_t size = 0;
	// Признак блока, укрытого от снимков памяти
	bool hidden = false;
	/**
	 * Снимаем запись с учёта под замком, а область отдаём после
	 */
	{
		// Захватываем замок слоя
		hold_t hold(this->_lock);
		// Если таблица поиска не заведена
		if((this->_table == nullptr) || (this->_length == 0))
			// Освобождать нечего
			return 0;
		// Определяем ключ записи: адрес освобождаемого блока
		const uintptr_t key = reinterpret_cast <uintptr_t> (ptr);
		// Определяем место записи в таблице
		size_t index = static_cast <size_t> ((key * 0x9E3779B97F4A7C15ull) & (this->_length - 1));
		// Число пройденных мест таблицы
		size_t passed = 0;
		// Найденная запись крупной выдачи
		record_t * record = nullptr;
		/**
		 * Перебираем места подряд, пока не встретим пустое
		 */
		while((this->_table[index] != nullptr) && (passed < this->_length)){
			// Если место занято живой записью нужного блока
			if((this->_table[index] != this->_tomb) && (this->_table[index]->block == reinterpret_cast <uint8_t *> (ptr))){
				// Запоминаем найденную запись
				record = this->_table[index];
				/**
				 * Оставляем в месте таблицы метку сноса, а не пустоту
				 *
				 * Перебор идёт подряд и останавливается на пустом месте: обнули мы место
				 * снесённой записи - соседние записи, легшие за ним при столкновении
				 * ключей, стали бы ненаходимыми
				 */
				this->_table[index] = this->_tomb;
				// Увеличиваем число снесённых мест
				this->_buried++;
				// Уменьшаем число внесённых записей
				this->_enrolled--;
				// Перебирать больше нечего
				break;
			}
			// Переходим к следующему месту таблицы
			index = ((index + 1) & (this->_length - 1));
			// Увеличиваем число пройденных мест
			passed++;
		}
		// Если запись не найдена
		if(record == nullptr)
			// Блок не наш
			return 0;
		// Запоминаем адрес начала отдаваемой области
		base = record->base;
		// Запоминаем размер отдаваемой области
		span = record->span;
		// Запоминаем затребованный прикладным кодом размер
		size = record->size;
		// Запоминаем признак укрытого блока
		hidden = record->hidden;
		// Уменьшаем число живых крупных выдач
		this->_state.live--;
		// Уменьшаем взятое у источника
		this->_state.taken -= ((this->_state.taken < span) ? this->_state.taken : span);
		// Уменьшаем выданное прикладному коду
		this->_state.given -= ((this->_state.given < size) ? this->_state.given : size);
		// Возвращаем запись в список повторно используемых
		record->spare = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
	}
	/**
	 * Отдаём область системе вне замка
	 *
	 * Отдача крупной области стоит вызова системы и правки таблиц страниц: держи мы на
	 * ней замок слоя - соседние потоки ждали бы работы ядра, к их выдаче отношения не
	 * имеющей
	 */
	/**
	 * Затираем содержимое укрытого блока ПРЕЖДЕ отдачи области
	 *
	 * Договор укрытой выдачи обещает затирание при освобождении наравне с самим
	 * укрытием. Отдача области системе содержимого не затирает: страницы уходят в
	 * общий запас как есть, и до их следующей раздачи оно остаётся в памяти
	 */
	if(hidden)
		// Затираем содержимое отдаваемой области
		::memset(base, 0, span);
	/**
	 * Придерживаем область у себя, а системе отдаём лишь сверх потолка
	 *
	 * Укрытую область не придерживаем вовсе: договор её обещает отдачу системе, а не
	 * лежание в нашем запасе, - и содержимое её только что затёрто ради этого
	 */
	if(!hidden && this->retain(base, span))
		// Выводим затребованный прикладным кодом размер блока
		return size;
	/**
	 * Отказ отдачи не разбираем намеренно
	 *
	 * Учётная запись области снята с таблицы поиска ещё под замком, и счёт взятого у
	 * источника уже уменьшен: вернуть её обратно значило бы возвращать в оборот адрес,
	 * о котором прикладной код уже забыл. У источника системы отказ здесь невозможен -
	 * область отображена нами самими; у подменённого же источника его учёт ведёт он сам
	 */
	// Отдаём область источнику
	this->_source->release(base, span);
	// Выводим затребованный прикладным кодом размер блока
	return size;
}
/**
 * @brief Метод опознания крупной выдачи по адресу её начала
 *
 * @param ptr  разбираемый адрес
 * @param size размер блока в байтах
 * @return     признак принадлежности адреса слою
 *
 */
bool awh::alloc::Huge::owner(const void * ptr, size_t * size) const noexcept {
	// Если разбирать нечего
	if(ptr == nullptr)
		// Разбирать нечего
		return false;
	// Захватываем замок слоя
	hold_t hold(const_cast <spin_t &> (this->_lock));
	// Ищем запись ровно по началу блока
	record_t * record = this->lookup(ptr, true);
	// Если запись не найдена
	if(record == nullptr)
		// Блок не наш
		return false;
	// Если требуется размер блока
	if(size != nullptr)
		// Записываем затребованный прикладным кодом размер
		(* size) = record->size;
	// Блок наш
	return true;
}
/**
 * @brief Метод разбора адреса, лежащего внутри крупной выдачи
 *
 * @param addr   разбираемый адрес
 * @param begin  адрес начала блока
 * @param size   размер блока в байтах
 * @param offset смещение разбираемого адреса от начала блока
 * @return       признак принадлежности адреса слою
 *
 */
bool awh::alloc::Huge::resolve(const void * addr, const void ** begin, size_t * size, ptrdiff_t * offset) const noexcept {
	// Если разбирать нечего
	if(addr == nullptr)
		// Разбирать нечего
		return false;
	// Захватываем замок слоя
	hold_t hold(const_cast <spin_t &> (this->_lock));
	// Ищем запись, чья область накрывает разбираемый адрес
	record_t * record = this->lookup(addr, false);
	// Если запись не найдена
	if(record == nullptr)
		// Адрес не наш
		return false;
	// Если требуется адрес начала блока
	if(begin != nullptr)
		// Записываем адрес начала блока
		(* begin) = record->block;
	// Если требуется размер блока
	if(size != nullptr)
		// Записываем затребованный прикладным кодом размер
		(* size) = record->size;
	// Если требуется смещение от начала блока
	if(offset != nullptr)
		// Записываем смещение разбираемого адреса от начала блока
		(* offset) = (reinterpret_cast <const uint8_t *> (addr) - record->block);
	// Адрес наш
	return true;
}
/**
 * @brief Метод получения состояния слоя крупных выдач
 *
 * @return состояние слоя крупных выдач
 *
 */
awh::alloc::Huge::state_t awh::alloc::Huge::state() noexcept {
	// Захватываем замок слоя
	hold_t hold(this->_lock);
	// Выводим состояние слоя крупных выдач
	return this->_state;
}
/**
 * @brief Метод подготовки слоя к ветвлению процесса
 *
 */
void awh::alloc::Huge::prepare() noexcept {
	// Захватываем замок слоя
	this->_lock.acquire();
}
/**
 * @brief Метод возобновления работы слоя после ветвления
 *
 */
void awh::alloc::Huge::resume() noexcept {
	// Отпускаем замок слоя
	this->_lock.release();
}
/**
 * @brief Метод приведения слоя в порядок в потомке ветвления
 *
 */
void awh::alloc::Huge::adopt() noexcept {
	// Приводим замок слоя в порядок
	this->_lock.reset();
}
