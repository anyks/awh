#include <cstring>

/**
 * @brief Конструктор
 *
 */
awh::alloc::Classes::Classes() noexcept : _count(0) {
	// Обнуляем размеры блоков разрядов
	::memset(this->_size, 0, sizeof(this->_size));
	// Обнуляем числа страниц разрядов
	::memset(this->_pages, 0, sizeof(this->_pages));
	// Обнуляем числа блоков разрядов
	::memset(this->_blocks, 0, sizeof(this->_blocks));
	// Обнуляем мелкую таблицу поиска
	::memset(this->_small, 0, sizeof(this->_small));
	// Обнуляем крупную таблицу поиска
	::memset(this->_large, 0, sizeof(this->_large));
}
/**
 * @brief Метод построения таблиц разрядов
 *
 * @return число заведённых разрядов
 *
 */
size_t awh::alloc::Classes::init() noexcept {
	// Если таблицы уже построены
	if(this->_count > 0)
		// Строить повторно незачем
		return this->_count;
	// Число заведённых разрядов
	size_t count = 0;
	/**
	 * Строим разряды от наименьшего к наибольшему
	 *
	 * Шаг берётся равным восьмой доле размера, но не меньше выравнивания: так потеря
	 * на округлении держится ниже 12,5 %, а число разрядов остаётся в семи десятках
	 */
	for(size_t size = ALIGN; (size <= MAXIMUM) && (count < LIMIT); count++){
		/**
		 * Разряды сверх порога мелкого запроса кратны шагу крупной таблицы
		 *
		 * Без этого крупная таблица врёт: место в ней ищется округлением размера вверх
		 * до своего шага, и разряд, размер какого шагу не кратен, отвечает на запрос
		 * 1025 разрядом для 1152 - вмещающим, но не наименьшим из вмещающих
		 */
		if(size > SMALL)
			// Приводим размер разряда к границе шага крупной таблицы
			size = ((size + (STEP_LARGE - 1)) & ~(STEP_LARGE - 1));
		// Если приведённый размер вышел за порог
		if(size > MAXIMUM)
			// Разрядов больше нет
			break;
		// Запоминаем размер блока разряда
		this->_size[count] = size;
		/**
		 * Подбираем число страниц кучи на область разряда
		 *
		 * Берётся наименьшее, при каком остаток области после нарезки не превышает
		 * восьмой доли, а блоков выходит не меньше двух: область на один блок сводила бы
		 * разряд к прямому обращению к куче
		 */
		// Выбранное число страниц
		size_t pages = 0;
		// Число блоков при выбранном числе страниц
		size_t blocks = 0;
		/**
		 * Перебираем возможные числа страниц
		 */
		for(size_t probe = 1; probe <= 32; probe++){
			// Определяем объём области при таком числе страниц
			const size_t span = (probe * Pages::PAGE);
			// Определяем число блоков, помещающихся в область
			const size_t fits = (span / size);
			// Если блоков выходит меньше двух
			if(fits < 2)
				// Переходим к большему числу страниц
				continue;
			// Определяем остаток области после нарезки
			const size_t waste = (span - (fits * size));
			// Запоминаем подобранное число страниц
			pages = probe;
			// Запоминаем число блоков
			blocks = fits;
			// Если остаток не превышает восьмой доли области
			if((waste * 8) <= span)
				// Подбор окончен
				break;
		}
		// Если подобрать число страниц не удалось
		if(pages == 0){
			// Берём наибольшее допустимое число страниц
			pages = 32;
			// Определяем число блоков при нём
			blocks = ((pages * Pages::PAGE) / size);
		}
		// Запоминаем число страниц разряда
		this->_pages[count] = pages;
		// Запоминаем число блоков разряда
		this->_blocks[count] = blocks;
		// Определяем шаг до следующего разряда
		size_t step = (size / 8);
		// Шаг не может быть меньше выравнивания
		if(step < ALIGN)
			// Приводим шаг к выравниванию
			step = ALIGN;
		/**
		 * Шаг приводится к границе выравнивания округлением ВНИЗ
		 *
		 * Округление вверх перебирает восьмую долю: шаг 68 при размере 544 округлился бы
		 * до 80, и запрос в 545 байт терял бы 12,8 % вместо 10,5 %. Округление вниз
		 * удерживает потерю ровно в восьмой доле, прибавляя лишь несколько разрядов
		 */
		step = (step & ~(ALIGN - 1));
		// Шаг не может быть меньше выравнивания
		if(step < ALIGN)
			// Приводим шаг к выравниванию
			step = ALIGN;
		/**
		 * Шаг у крупных разрядов приводится к шагу таблицы округлением ВНИЗ
		 *
		 * Округление вверх тоже даёт разряды, кратные шагу таблицы, но раздувает потерю:
		 * шаг 272 при размере 2176 округлился бы до 384, и запрос в 2177 байт терял бы
		 * 15 % вместо 10,5 %. Округление вниз держит потерю в пределах восьмой доли, а
		 * разрядов прибавляет всего несколько
		 */
		if(size >= SMALL){
			// Приводим шаг к границе шага крупной таблицы округлением вниз
			step = (step & ~(STEP_LARGE - 1));
			// Шаг не может быть меньше шага крупной таблицы
			if(step < STEP_LARGE)
				// Приводим шаг к шагу крупной таблицы
				step = STEP_LARGE;
		}
		// Определяем размер следующего разряда
		size_t next = (size + step);
		/**
		 * Порог мелкого запроса обязан сам быть разрядом
		 *
		 * Без этого шаг перескакивает порог, следующий разряд округляется вверх до
		 * границы шага крупной таблицы, и между последним мелким разрядом и первым
		 * крупным зияет провал: разряд 912 сменялся разрядом 1152, а запросы от 913
		 * до 1152 теряли пятую часть вместо восьмой доли
		 */
		if((size < SMALL) && (next > SMALL))
			// Доводим следующий разряд до порога
			next = SMALL;
		/**
		 * Последний разряд обязан накрыть порог ровно
		 *
		 * Без этого шаг перескакивает порог, разрядов сверх последнего не заводится, и
		 * запросы между последним разрядом и порогом остаются без разряда вовсе
		 */
		if((next > MAXIMUM) && (size < MAXIMUM))
			// Доводим последний разряд до порога
			next = MAXIMUM;
		// Переходим к следующему разряду
		size = next;
	}
	// Запоминаем число заведённых разрядов
	this->_count = count;
	/**
	 * Строим мелкую таблицу поиска
	 *
	 * Таблица отвечает на запрос до порога мелкого: место в ней ищется делением размера
	 * на выравнивание, оттого поиск разряда не стоит ни одного перебора
	 */
	{
		// Номер текущего разряда
		size_t current = 0;
		// Перебираем места мелкой таблицы
		for(size_t i = 0; i < (sizeof(this->_small) / sizeof(this->_small[0])); i++){
			// Определяем наибольший размер, отвечающий этому месту таблицы
			const size_t size = (i * STEP_SMALL);
			// Двигаем разряд, пока его блок не вместит требуемый размер
			while((current < count) && (this->_size[current] < size))
				// Переходим к следующему разряду
				current++;
			// Записываем номер разряда в таблицу
			this->_small[i] = static_cast <uint8_t> ((current < count) ? current : count);
		}
	}
	/**
	 * Строим крупную таблицу поиска
	 */
	{
		// Номер текущего разряда
		size_t current = 0;
		// Перебираем места крупной таблицы
		for(size_t i = 0; i < (sizeof(this->_large) / sizeof(this->_large[0])); i++){
			// Определяем наибольший размер, отвечающий этому месту таблицы
			const size_t size = (i * STEP_LARGE);
			// Двигаем разряд, пока его блок не вместит требуемый размер
			while((current < count) && (this->_size[current] < size))
				// Переходим к следующему разряду
				current++;
			// Записываем номер разряда в таблицу
			this->_large[i] = static_cast <uint8_t> ((current < count) ? current : count);
		}
	}
	// Выводим число заведённых разрядов
	return this->_count;
}
/**
 * @brief Метод определения разряда по требуемому размеру
 *
 * @param size требуемый размер в байтах
 * @return     номер разряда, либо LIMIT если размер разрядами не обслуживается
 *
 */
size_t awh::alloc::Classes::index(const size_t size) const noexcept {
	// Если размер разрядами не обслуживается
	if(size > MAXIMUM)
		// Сообщаем, что разряда для него нет
		return LIMIT;
	// Запрос нулевого размера обслуживается наименьшим разрядом
	const size_t need = ((size > 0) ? size : 1);
	// Номер найденного разряда
	size_t result = 0;
	// Если размер не превышает порога мелкого запроса
	if(need <= SMALL)
		// Берём разряд из мелкой таблицы
		result = static_cast <size_t> (this->_small[((need + (STEP_SMALL - 1)) / STEP_SMALL)]);
	// Если размер превышает порог мелкого запроса
	else result = static_cast <size_t> (this->_large[((need + (STEP_LARGE - 1)) / STEP_LARGE)]);
	// Если разряда для размера не нашлось
	if(result >= this->_count)
		// Сообщаем, что разряда для него нет
		return LIMIT;
	// Выводим найденный разряд
	return result;
}
/**
 * @brief Метод получения размера блока разряда
 *
 * @param index номер разряда
 * @return      размер блока в байтах
 *
 */
size_t awh::alloc::Classes::size(const size_t index) const noexcept {
	// Выводим размер блока разряда либо нуль при негодном номере
	return ((index < this->_count) ? this->_size[index] : 0);
}
/**
 * @brief Метод получения числа страниц на область разряда
 *
 * @param index номер разряда
 * @return      число страниц кучи
 *
 */
size_t awh::alloc::Classes::pages(const size_t index) const noexcept {
	// Выводим число страниц разряда либо нуль при негодном номере
	return ((index < this->_count) ? this->_pages[index] : 0);
}
/**
 * @brief Метод получения числа блоков в области разряда
 *
 * @param index номер разряда
 * @return      число блоков
 *
 */
size_t awh::alloc::Classes::blocks(const size_t index) const noexcept {
	// Выводим число блоков разряда либо нуль при негодном номере
	return ((index < this->_count) ? this->_blocks[index] : 0);
}
/**
 * @brief Метод получения числа заведённых разрядов
 *
 * @return число разрядов
 *
 */
size_t awh::alloc::Classes::count() const noexcept {
	// Выводим число заведённых разрядов
	return this->_count;
}
