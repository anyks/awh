/**
 * @brief Конструктор
 *
 */
awh::alloc::Pages::Pages() noexcept :
 _source(nullptr), _chunks(nullptr), _registry(nullptr), _enrolled(0), _large(nullptr), _spare(nullptr), _unmerged(0),
 _meta(nullptr), _metaLeft(0), _metaChunks(nullptr), _confined(false),
 _delay(10), _block(0), _limit(0), _jammed(false), _pending(0), _state() {
	// Обнуляем списки свободных областей
	::memset(this->_lists, 0, sizeof(this->_lists));
}
/**
 * @brief Метод выдачи памяти под учётную запись
 *
 * @return адрес выданной памяти либо nullptr
 *
 */
void * awh::alloc::Pages::meta(const size_t size) noexcept {
	/**
	 * Выдаём ровно затребованное, а не наибольшую из записей
	 *
	 * Прежде здесь бралась наибольшая - то есть запись КУСКА, несущая указатели на все
	 * пятьсот двенадцать его страниц. Записей же кусков десятки, а записей областей -
	 * десятки тысяч, и каждая из них, весом в семь десятков байт, занимала четыре с
	 * половиной килобайта. Замерено щупом: при куче в 243 мегабайта собственный её учёт
	 * занимал 132 мегабайта - больше половины сверх самих блоков. Платится за это не
	 * только памятью: каждая страница учёта стоит отказа страницы при первом обращении,
	 * а у иных систем вход в ядро дорог
	 *
	 * Разные размеры в одной области под учёт уживаются потому, что записи поштучно не
	 * отдаются вовсе: они живут столько же, сколько куча, а повторно используемые
	 * ведутся списком СВОЕГО вида
	 */
	// Приводим размер к границе восьми байт
	const size_t need = ((size + 7u) & ~static_cast <size_t> (7u));
	// Если в текущем куске места не осталось
	if(this->_metaLeft < need){
		/**
		 * Берём у источника новый кусок под учётные записи
		 *
		 * Куски эти невелики и системе не отдаются вовсе: учётные записи живут столько
		 * же, сколько сама куча, а отдавать их порознь значило бы вести учёт учёта
		 */
		// Требуемый размер куска под учётные записи
		const size_t span = (256u * 1024u);
		// Действительно выданный размер
		size_t actual = 0;
		// Берём у источника кусок под учётные записи
		uint8_t * block = reinterpret_cast <uint8_t *> (this->_source->alloc(span, 0, actual));
		// Если кусок не выдан
		if(block == nullptr)
			// Отвечаем отказом
			return nullptr;
		/**
		 * Вносим кусок в общий список: первые восемь байт куска отводятся под указатель
		 * на предыдущий, оттого списку не нужно собственной памяти
		 */
		// Записываем в начало куска указатель на предыдущий
		::memcpy(block, &this->_metaChunks, sizeof(void *));
		// Запоминаем кусок как последний
		this->_metaChunks = block;
		// Сдвигаем начало выдачи за указатель
		this->_meta = (block + sizeof(void *));
		// Запоминаем остаток куска
		this->_metaLeft = (actual - sizeof(void *));
	}
	// Запоминаем адрес выдачи
	void * result = this->_meta;
	// Сдвигаем начало выдачи
	this->_meta += need;
	// Уменьшаем остаток куска
	this->_metaLeft -= need;
	// Выводим адрес выданной памяти
	return result;
}
/**
 * @brief Метод перестроения таблицы поиска куска по адресу
 *
 * @param length требуемая длина таблицы в местах
 * @return       признак перестроения таблицы
 *
 */
bool awh::alloc::Pages::rehash(const size_t length) noexcept {
	// Действительно выданный размер
	size_t actual = 0;
	// Требуемый размер новой таблицы в байтах
	const size_t size = (length * sizeof(chunk_t *));
	// Берём у источника память под новую таблицу
	chunk_t ** table = reinterpret_cast <chunk_t **> (this->_source->alloc(size, 0, actual));
	// Если память под таблицу не выдана
	if(table == nullptr)
		// Отвечаем отказом
		return false;
	// Обнуляем места новой таблицы
	::memset(table, 0, size);
	// Запоминаем прежнюю запись таблицы
	registry_t * previous = this->_registry.load(std::memory_order_relaxed);
	// Берём у источника память под запись новой таблицы
	registry_t * record = reinterpret_cast <registry_t *> (this->meta(sizeof(registry_t)));
	// Если память под запись не выдана
	if(record == nullptr){
		// Отдаём источнику взятую таблицу ВЫДАННЫМ размером
		this->_source->release(table, actual);
		// Отвечаем отказом
		return false;
	}
	// Записываем места новой таблицы
	record->table = table;
	// Записываем длину новой таблицы
	record->length = length;
	// Записываем размер взятой под таблицу области
	record->region = actual;
	/**
	 * Связываем запись с прежней
	 *
	 * Связь нужна одному лишь снятию кучи: отдать источнику надо ВСЕ таблицы, а
	 * действующая знает только себя. В работе цепочка эта не читается вовсе
	 */
	record->previous = previous;
	/**
	 * Подменяем запись таблицы неделимо
	 *
	 * Читатель без замка берёт запись ОДНИМ обращением и дальше держится за неё: ни
	 * длина, ни места её больше не меняются
	 */
	this->_registry.store(record, std::memory_order_release);
	// Внесённых кусков у новой таблицы пока нет
	this->_enrolled = 0;
	/**
	 * Переносим в новую таблицу куски прежней
	 */
	if(previous != nullptr){
		// Перебираем места прежней таблицы
		for(size_t i = 0; i < previous->length; i++){
			// Если место прежней таблицы занято
			if(previous->table[i] != nullptr)
				// Вносим кусок в новую таблицу
				this->enroll(previous->table[i]);
		}
	}
	/**
	 * Прежнюю таблицу источнику НЕ отдаём
	 *
	 * Читатель разбирает адрес без замка и волен быть внутри прежней таблицы прямо
	 * сейчас: отдай мы её - он читал бы отданную системе память. Теряется на этом
	 * менее половины действующей таблицы, ибо длина удваивается
	 */
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод внесения куска в таблицу поиска
 *
 * @param chunk вносимый кусок
 * @return      признак внесения куска
 *
 */
bool awh::alloc::Pages::enroll(chunk_t * chunk) noexcept {
	// Если таблица не заведена либо заполнена наполовину
	// Получаем действующую запись таблицы
	registry_t * registry = this->_registry.load(std::memory_order_relaxed);
	// Если таблица не заведена либо заполнена наполовину
	if((registry == nullptr) || (((this->_enrolled + 1) * 2) > registry->length)){
		/**
		 * Перестраиваем таблицу вдвое большей длины
		 *
		 * Порог в половину длины взят не для скорости, а для завершимости: перебор мест
		 * идёт подряд, и при плотном заполнении он вырождается в перебор всей таблицы
		 */
		if(!this->rehash((registry == nullptr) ? TABLE : (registry->length * 2)))
			// Отвечаем отказом
			return false;
		// Получаем перестроенную запись таблицы
		registry = this->_registry.load(std::memory_order_relaxed);
	}
	// Определяем ключ куска: номер куска в разбиении памяти по его размеру
	const uintptr_t key = (reinterpret_cast <uintptr_t> (chunk->base) / CHUNK);
	// Определяем место куска в таблице
	size_t index = static_cast <size_t> ((key * 0x9E3779B97F4A7C15ull) & (registry->length - 1));
	/**
	 * Ищем свободное место, перебирая места подряд
	 */
	while(registry->table[index] != nullptr){
		// Если кусок в таблице уже есть
		if((reinterpret_cast <uintptr_t> (registry->table[index]->base) / CHUNK) == key)
			// Вносить нечего
			return true;
		// Переходим к следующему месту таблицы
		index = ((index + 1) & (registry->length - 1));
	}
	// Записываем кусок в найденное место
	registry->table[index] = chunk;
	// Увеличиваем число внесённых кусков
	this->_enrolled++;
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод поиска куска, которому принадлежит адрес
 *
 * @param addr разбираемый адрес
 * @return     найденный кусок либо nullptr
 *
 */
/**
 * Место в таблице берётся маской, а не остатком от деления
 *
 * Длина таблицы всегда степень двойки: начальная такова, а перестроение её удваивает.
 * Деление же с остатком по длине, известной лишь во время работы, стоит десятков тактов,
 * и стоит оно их на КАЖДОМ освобождении - замеры на FreeBSD дали 139 наносекунд на
 * действие с делением против 123 с маской. Кольцо карантина маской НЕ берётся: длина его
 * считается по объёму и степенью двойки не бывает
 */
awh::alloc::Pages::chunk_t * awh::alloc::Pages::discover(const void * addr) const noexcept {
	// Если адрес не задан
	if(addr == nullptr)
		// Искать нечего
		return nullptr;
	/**
	 * Берём запись таблицы ОДНИМ обращением
	 *
	 * Дальше держимся именно за неё: перестроение подменяет запись целиком, а прежняя
	 * остаётся годной к чтению навсегда. Читай мы таблицу и длину порознь - застали бы
	 * их вразнобой и ушли за конец
	 */
	// Получаем действующую запись таблицы
	const registry_t * registry = this->_registry.load(std::memory_order_acquire);
	// Если таблица не заведена
	if((registry == nullptr) || (registry->length == 0))
		// Искать нечего
		return nullptr;
	// Определяем ключ адреса: номер куска, которому адрес мог бы принадлежать
	const uintptr_t key = (reinterpret_cast <uintptr_t> (addr) / CHUNK);
	// Определяем место в таблице
	size_t index = static_cast <size_t> ((key * 0x9E3779B97F4A7C15ull) & (registry->length - 1));
	/**
	 * Ищем кусок, перебирая места подряд
	 */
	while(registry->table[index] != nullptr){
		// Получаем кусок, лежащий в очередном месте
		chunk_t * chunk = registry->table[index];
		// Если ключ куска совпал с ключом адреса
		if((reinterpret_cast <uintptr_t> (chunk->base) / CHUNK) == key){
			/**
			 * Сличаем адрес с действительными границами куска
			 *
			 * Ключ сходится и у адреса за концом куска, если источник выдал куска
			 * меньше запрошенного, - границы того не прощают
			 */
			if(reinterpret_cast <uintptr_t> (addr) < (reinterpret_cast <uintptr_t> (chunk->base) + chunk->size))
				// Выводим найденный кусок
				return chunk;
			// Адрес лежит за концом куска
			return nullptr;
		}
		// Переходим к следующему месту таблицы
		index = ((index + 1) & (registry->length - 1));
	}
	// Куска за адресом не нашлось
	return nullptr;
}
/**
 * @brief Метод записи области в указатели куска
 *
 * @param span записываемая область
 *
 */
/**
 * @brief Метод слияния отложенных областей
 *
 */
void awh::alloc::Pages::compact() noexcept {
	// Если сливать нечего
	if(this->_unmerged == 0)
		// Выходим: обход впустую стоил бы дороже отказа
		return;
	/**
	 * Перебираем куски памяти
	 */
	for(chunk_t * chunk = this->_chunks; chunk != nullptr; chunk = chunk->next){
		// Номер разбираемой страницы куска
		size_t page = 0;
		/**
		 * Перебираем страницы куска подряд
		 */
		while(page < PAGES){
			// Получаем область, которой принадлежит страница
			span_t * span = chunk->index[page].load(std::memory_order_relaxed);
			// Если области нет вовсе
			if(span == nullptr){
				// Переходим к следующей странице
				page++;
				// Продолжаем обход
				continue;
			}
			/**
			 * Сливаем область, свободную и никем не изъятую
			 *
			 * Изъятая область не лежит ни в одном списке свободных, и `pull` порвал бы
			 * список: слияние её и без того пропускает сам `merge`
			 */
			if(span->released && !span->pending){
				// Изымаем область из списка свободных
				this->pull(span);
				// Сливаем область с соседями по куску
				span_t * merged = this->merge(span);
				// Вносим слитую область в список свободных
				this->push(merged);
				/**
				 * Переходим за конец СЛИТОЙ области
				 *
				 * Слияние могло прирастить область слева, и начало её оказалось бы левее
				 * разбираемой страницы: считать от неё значило бы разбирать слитое дважды
				 */
				page = (static_cast <size_t> ((merged->base - chunk->base) / PAGE) + merged->pages);
				// Продолжаем обход
				continue;
			}
			// Переходим за конец области
			page += span->pages;
		}
	}
	// Отложенных областей не осталось
	this->_unmerged = 0;
}
void awh::alloc::Pages::mark(span_t * span) noexcept {
	// Определяем номер первой страницы области в куске
	const size_t first = static_cast <size_t> ((span->base - span->chunk->base) / PAGE);
	/**
	 * Записываем область по всем её страницам
	 *
	 * Запись по всем, а не по одной первой, нужна для поиска области по произвольному
	 * адресу внутри неё - без этого разбор адреса сбоя пришлось бы вести перебором
	 */
	for(size_t i = 0; i < span->pages; i++){
		// Записываем область по очередной странице
		/**
		 * Запись отдаётся с отпусканием
		 *
		 * Читатель разбирает адрес без замка кучи, и увидь он указатель прежде, чем
		 * записанные в область поля, - прочёл бы недописанное
		 */
		span->chunk->index[first + i].store(span, std::memory_order_release);
		/**
		 * Правим метку разряда страницы вслед за областью
		 *
		 * `mark` - единственное место, где страницы переходят к другой области, оттого
		 * метка правится здесь же: у свободной области её нет вовсе, а у выданной она
		 * берётся из самой области. Разряд проставляется потом, методом `tag`, - в тот
		 * же миг, когда область отдаётся разряду
		 */
		span->chunk->tags[first + i].store((span->released ? 0 : static_cast <uint8_t> (span->tag)), std::memory_order_release);
	}
}
/**
 * @brief Метод внесения области в список свободных
 *
 * @param span вносимая область
 *
 */
void awh::alloc::Pages::push(span_t * span) noexcept {
	// Определяем список, которому принадлежит область
	span_t ** list = ((span->pages <= LISTS) ? &this->_lists[span->pages] : &this->_large);
	// Предыдущей области у вносимой нет
	span->prev = nullptr;
	// Следующей становится прежняя голова списка
	span->next = (* list);
	// Если список не пуст
	if((* list) != nullptr)
		// Прежняя голова списка получает предыдущую
		(* list)->prev = span;
	// Вносимая область становится головой списка
	(* list) = span;
}
/**
 * @brief Метод изъятия области из списка свободных
 *
 * @param span изымаемая область
 *
 */
void awh::alloc::Pages::pull(span_t * span) noexcept {
	// Определяем список, которому принадлежит область
	span_t ** list = ((span->pages <= LISTS) ? &this->_lists[span->pages] : &this->_large);
	// Если у области есть предыдущая
	if(span->prev != nullptr)
		// Связываем предыдущую со следующей
		span->prev->next = span->next;
	// Если предыдущей нет, изымаемая была головой списка
	else (* list) = span->next;
	// Если у области есть следующая
	if(span->next != nullptr)
		// Связываем следующую с предыдущей
		span->next->prev = span->prev;
	// Обнуляем связи изъятой области
	span->prev = nullptr;
	// Обнуляем связь со следующей
	span->next = nullptr;
}
/**
 * @brief Метод взятия у источника нового куска
 *
 * @return взятый кусок либо nullptr
 *
 */
awh::alloc::Pages::chunk_t * awh::alloc::Pages::grow() noexcept {
	// Если обращаться к источнику запрещено
	if(this->_confined)
		// Отвечаем отказом: расти некуда
		return nullptr;
	/**
	 * Если очередной кусок вывел бы взятое за потолок
	 *
	 * Потолок считается по взятому у источника, а не по выданному прикладному коду:
	 * куча раздаёт страницами и часть взятого всегда лежит в её списках свободных.
	 * Считай мы по выданному - потолок сдвигался бы на величину раздробленности, то
	 * есть на величину, которой приложение не задавало
	 */
	if((this->_limit > 0) && ((this->_state.total + CHUNK) > this->_limit)){
		// Отмечаем куче отказ в росте из-за потолка
		this->_jammed = true;
		// Отвечаем отказом: расти некуда
		return nullptr;
	}
	/**
	 * Выдаём память под ОБЕ учётные записи прежде обращения к источнику
	 *
	 * Порядок этот выбран ради отката: учётные записи берутся у своей же области под
	 * учёт и отказать могут лишь при нехватке памяти у системы, а взятый у источника
	 * кусок откатить сложнее - его придётся отдавать обратно, сняв со списков. Взяв
	 * записи первыми, мы оставляем на пути после источника единственную точку отказа
	 */
	// Выдаём память под учётную запись куска
	chunk_t * chunk = reinterpret_cast <chunk_t *> (this->meta(sizeof(chunk_t)));
	// Если память под учётную запись не выдана
	if(chunk == nullptr)
		// Отвечаем отказом
		return nullptr;
	// Выдаём память под учётную запись области, накрывающей кусок целиком
	span_t * span = reinterpret_cast <span_t *> (this->meta(sizeof(span_t)));
	// Если память под учётную запись не выдана
	if(span == nullptr)
		// Отвечаем отказом
		return nullptr;
	// Действительно выданный размер
	size_t actual = 0;
	/**
	 * Берём у источника кусок, выровненный по своему размеру
	 *
	 * Выравнивание это позволяет по любому адресу внутри куска найти его начало одной
	 * маской, без поиска по списку
	 */
	uint8_t * base = reinterpret_cast <uint8_t *> (this->_source->alloc(CHUNK, CHUNK, actual));
	// Если кусок не выдан
	if(base == nullptr)
		// Отвечаем отказом
		return nullptr;
	// Запоминаем адрес начала куска
	chunk->base = base;
	// Запоминаем размер куска
	chunk->size = actual;
	// Выданных наружу страниц у нового куска нет
	chunk->used = 0;
	// Обнуляем указатели областей куска
	/**
	 * Обнуляем указатели областей по одному
	 *
	 * Побайтовое обнуление неделимых видов стандарт не обещает: у нас оно сработало бы,
	 * но обещание это нигде не записано, а цена перебора - однажды на кусок в четыре
	 * мегабайта
	 */
	for(size_t i = 0; i < PAGES; i++){
		// Обнуляем указатель области очередной страницы
		chunk->index[i].store(nullptr, std::memory_order_relaxed);
		// Обнуляем метку разряда очередной страницы
		chunk->tags[i].store(0, std::memory_order_relaxed);
	}
	/**
	 * Вносим кусок в таблицу поиска по адресу
	 *
	 * Здесь, а не прежде обнуления указателей: таблицу читают БЕЗ замка кучи, на каждом
	 * освобождении, и внесённый в неё кусок обязан быть готов к чтению целиком
	 */
	if(!this->enroll(chunk)){
		/**
		 * Отдаём взятый кусок источнику
		 *
		 * Без таблицы кусок не отыскать при освобождении, и держать его значило бы
		 * потерять четыре мегабайта навсегда, ничего о них не сообщив. Учётные записи
		 * при этом остаются неиспользованными: своей области под учёт они стоят десятки
		 * байт, а путь этот случается лишь при нехватке памяти у системы
		 */
		this->_source->release(base, actual);
		// Отвечаем отказом
		return nullptr;
	}
	// Вносим кусок в общий список
	chunk->next = this->_chunks;
	// Запоминаем кусок как первый
	this->_chunks = chunk;
	// Область начинается с начала куска
	span->base = base;
	// Область накрывает кусок целиком
	span->pages = PAGES;
	// Область свободна
	span->released = true;
	// Содержимое области системе не отдано
	span->purged = false;
	// Область никем не изъята
	span->pending = false;
	// Отметки времени у области ещё нет
	span->stamp = 0;
	// Метки владельца у области ещё нет
	span->tag = 0;
	// Область принадлежит новому куску
	span->chunk = chunk;
	// Связей в списке свободных у области пока нет
	span->prev = nullptr;
	// Связь со следующей пока пуста
	span->next = nullptr;
	// Записываем область в указатели куска
	this->mark(span);
	// Вносим область в список свободных
	this->push(span);
	// Увеличиваем взятое у источника
	this->_state.total += actual;
	// Увеличиваем свободное
	this->_state.free += (PAGES * PAGE);
	// Увеличиваем число взятых кусков
	this->_state.chunks++;
	// Выводим взятый кусок
	return chunk;
}
/**
 * @brief Метод поиска свободной области требуемого размера
 *
 * @param pages требуемое число страниц
 * @return      найденная область либо nullptr
 *
 */
awh::alloc::Pages::span_t * awh::alloc::Pages::search(const size_t pages) noexcept {
	/**
	 * Перебираем списки от требуемого размера вверх
	 *
	 * Список точного размера просматривается первым, и лишь при его пустоте берётся
	 * область покрупнее с последующим делением
	 */
	if(pages <= LISTS){
		// Перебираем списки по числу страниц
		for(size_t i = pages; i <= LISTS; i++){
			// Если список не пуст
			if(this->_lists[i] != nullptr)
				// Выводим голову списка
				return this->_lists[i];
		}
	}
	// Наименьшая подходящая область из числа крупных
	span_t * result = nullptr;
	/**
	 * Перебираем крупные свободные области
	 *
	 * Берётся наименьшая подходящая, а не первая попавшаяся: так дробление идёт от
	 * меньших областей, и крупные остаются целыми под крупные же запросы
	 */
	for(span_t * span = this->_large; span != nullptr; span = span->next){
		// Если область мала для запроса
		if(span->pages < pages)
			// Переходим к следующей
			continue;
		// Если подходящей области ещё не находилось либо найденная меньше прежней
		if((result == nullptr) || (span->pages < result->pages))
			// Запоминаем область как найденную
			result = span;
	}
	// Выводим найденную область
	return result;
}
/**
 * @brief Метод слияния области с соседями по куску
 *
 * @param span сливаемая область
 * @return     область после слияния
 *
 */
awh::alloc::Pages::span_t * awh::alloc::Pages::merge(span_t * span) noexcept {
	// Получаем кусок, которому принадлежит область
	chunk_t * chunk = span->chunk;
	// Определяем номер первой страницы области в куске
	size_t first = static_cast <size_t> ((span->base - chunk->base) / PAGE);
	/**
	 * Сливаем с соседом слева
	 *
	 * Граница куска для слияния непроницаема: два соседних по адресу куска могут быть
	 * отданы системе порознь, и область, слитая через границу, при отдаче распалась бы
	 */
	if(first > 0){
		// Получаем соседа слева
		span_t * left = chunk->index[first - 1].load(std::memory_order_relaxed);
		/**
		 * Если сосед слева свободен и никем не изъят
		 *
		 * Изъятая область не лежит ни в одном списке свободных: слить её значило бы
		 * изъять её вторично и порвать список
		 */
		if((left != nullptr) && left->released && !left->pending){
			// Изымаем соседа из списка свободных
			this->pull(left);
			/**
			 * Слитая область считается отданной лишь тогда, когда отданы обе части
			 *
			 * Если отдана была лишь одна, учёт отданного обязан её позабыть: содержимое
			 * слитой области отданным больше не считается, а байты её из учёта отданного
			 * никто не вычел бы, и тот рос бы без основания
			 */
			// Определяем, отданы ли обе части
			const bool both = (span->purged && left->purged);
			// Если отдана была лишь сливаемая область
			if(span->purged && !both)
				// Вычитаем её из учёта отданного
				this->_state.purged -= (span->pages * PAGE);
			// Если отдан был лишь сосед слева
			if(left->purged && !both)
				// Вычитаем его из учёта отданного
				this->_state.purged -= (left->pages * PAGE);
			// Отмечаем слитую область отданной только при отданных обеих
			left->purged = both;
			// Отметкой времени слитой области становится более поздняя из двух
			left->stamp = ((span->stamp > left->stamp) ? span->stamp : left->stamp);
			// Увеличиваем размер соседа на размер сливаемой области
			left->pages += span->pages;
			// Учётная запись сливаемой области больше не нужна
			span->next = this->_spare;
			// Вносим её в список повторно используемых
			this->_spare = span;
			// Сливаемой становится сосед слева
			span = left;
			// Пересчитываем номер первой страницы
			first = static_cast <size_t> ((span->base - chunk->base) / PAGE);
			// Записываем слитую область в указатели куска
			this->mark(span);
		}
	}
	// Определяем номер страницы за концом области
	const size_t after = (first + span->pages);
	/**
	 * Сливаем с соседом справа
	 */
	if(after < PAGES){
		// Получаем соседа справа
		span_t * right = chunk->index[after].load(std::memory_order_relaxed);
		// Если сосед справа свободен
		if((right != nullptr) && right->released && !right->pending){
			// Изымаем соседа из списка свободных
			this->pull(right);
			// Определяем, отданы ли обе части
			const bool both = (span->purged && right->purged);
			// Если отдана была лишь сливаемая область
			if(span->purged && !both)
				// Вычитаем её из учёта отданного
				this->_state.purged -= (span->pages * PAGE);
			// Если отдан был лишь сосед справа
			if(right->purged && !both)
				// Вычитаем его из учёта отданного
				this->_state.purged -= (right->pages * PAGE);
			// Отмечаем слитую область отданной только при отданных обеих
			span->purged = both;
			// Отметкой времени слитой области становится более поздняя из двух
			span->stamp = ((right->stamp > span->stamp) ? right->stamp : span->stamp);
			// Увеличиваем размер области на размер соседа
			span->pages += right->pages;
			// Учётная запись соседа больше не нужна
			right->next = this->_spare;
			// Вносим её в список повторно используемых
			this->_spare = right;
			// Записываем слитую область в указатели куска
			this->mark(span);
		}
	}
	// Выводим область после слияния
	return span;
}
/**
 * @brief Метод заведения кучи
 *
 * @param source   источник страниц
 * @param arena    занимаемая при заведении область в байтах
 * @param confined запрет обращаться к источнику сверх занятого
 * @return         признак заведения кучи
 *
 */
bool awh::alloc::Pages::occupy(const size_t arena, const bool confined) noexcept {
	// Если куча не заведена
	if(this->_source == nullptr)
		// Отвечать нечем
		return false;
	/**
	 * Снимаем запрет на время занятия
	 *
	 * Занятие само идёт к источнику, и действуй запрет здесь - оно упёрлось бы в него
	 * же и не заняло бы ничего
	 */
	this->_confined = false;
	/**
	 * Дозанимаем недостающее до требуемой области
	 *
	 * Считаем по УЖЕ взятому, а не по заказанному: повторное занятие не обязано
	 * удваивать взятое, а у систем ELF куча к мигу захвата уже держит кусок-другой
	 */
	while(this->_state.total < arena){
		// Берём у источника очередной кусок
		if(this->grow() == nullptr){
			// Возвращаем запрет обращаться к источнику
			this->_confined = confined;
			// Отвечаем отказом: занять требуемое не вышло
			return false;
		}
	}
	// Запоминаем запрет обращаться к источнику сверх занятого
	this->_confined = confined;
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод заведения кучи
 *
 * @param source   источник страниц
 * @param arena    занимаемая при заведении область в байтах
 * @param confined запрет обращаться к источнику сверх занятого
 * @return         признак заведения кучи
 *
 */
bool awh::alloc::Pages::init(source_t * source, const size_t arena, const bool confined) noexcept {
	// Если источник не задан
	if(source == nullptr)
		// Отвечаем отказом
		return false;
	// Запоминаем источник страниц
	this->_source = source;
	// Запрет обращаться к источнику при заведении не действует
	this->_confined = false;
	// Если при заведении требуется занять область
	if(arena > 0){
		// Определяем требуемое число кусков
		const size_t count = ((arena + (CHUNK - 1)) / CHUNK);
		/**
		 * Занимаем требуемое число кусков
		 */
		for(size_t i = 0; i < count; i++){
			// Если взять у источника очередной кусок не вышло
			if(this->grow() == nullptr){
				/**
				 * Отдаём источнику уже занятое
				 *
				 * Отказ на середине оставлял бы взятые куски за нами навсегда: куча
				 * отвечает отказом заведения, звавший заводит её заново, и запись о
				 * прежде взятом при этом теряется. Память же у системы остаётся занятой
				 * и не выражается больше ничем - ни списком кусков, ни учётом взятого
				 */
				this->destroy();
				// Отвечаем отказом: занять требуемое не вышло
				return false;
			}
		}
	}
	// Запоминаем запрет обращаться к источнику сверх занятого
	this->_confined = confined;
	// Отвечаем успехом
	return true;
}
/**
 * @brief Метод разрушения кучи
 *
 */
void awh::alloc::Pages::destroy() noexcept {
	// Если источник не задан
	if(this->_source == nullptr)
		// Разрушать нечего
		return;
	/**
	 * Отдаём источнику взятые куски
	 */
	for(chunk_t * chunk = this->_chunks; chunk != nullptr;){
		// Запоминаем следующий кусок прежде отдачи текущего
		chunk_t * next = chunk->next;
		// Отдаём кусок источнику
		this->_source->release(chunk->base, chunk->size);
		// Переходим к следующему куску
		chunk = next;
	}
	/**
	 * Отдаём источнику таблицы поиска куска по адресу
	 *
	 * Отдаются ВСЕ, включая оставленные перестроением: в работе прежние не отдаются
	 * затем, что читатель разбирает адрес без замка и волен быть внутри одной из них.
	 * Отдаются прежде кусков под учётные записи: сами записи таблиц лежат в тех кусках
	 */
	for(registry_t * registry = this->_registry.load(std::memory_order_relaxed); registry != nullptr;){
		// Запоминаем предыдущую запись таблицы
		registry_t * previous = registry->previous;
		// Если места таблицы заведены
		if(registry->table != nullptr)
			// Отдаём источнику память таблицы
			this->_source->release(registry->table, registry->region);
		// Переходим к предыдущей записи таблицы
		registry = previous;
	}
	/**
	 * Отдаём источнику куски памяти под учётные записи
	 *
	 * Отдаются последними: учётные записи кусков лежат в них же, и отдать их прежде
	 * значило бы читать освобождённую память при обходе списка кусков
	 */
	for(void * block = this->_metaChunks; block != nullptr;){
		// Читаем указатель на предыдущий кусок из его начала
		void * previous = nullptr;
		// Извлекаем указатель на предыдущий кусок
		::memcpy(&previous, block, sizeof(void *));
		// Отдаём кусок источнику
		this->_source->release(block, (256u * 1024u));
		// Переходим к предыдущему куску
		block = previous;
	}
	/**
	 * Таблицы поиска источнику НЕ отдаются
	 *
	 * Прежние записи их при перестроении остаются жить: читатель разбирает адрес без
	 * замка. Лежат они в тех же кусках под учётные записи, что уже отданы выше, - и
	 * отдавать их порознь нечем и незачем
	 */
	// Обнуляем запись таблицы поиска
	this->_registry.store(nullptr, std::memory_order_relaxed);
	// Обнуляем число внесённых в таблицу кусков
	this->_enrolled = 0;
	// Обнуляем общий список кусков
	this->_chunks = nullptr;
	// Обнуляем список крупных свободных областей
	this->_large = nullptr;
	// Обнуляем список повторно используемых учётных записей
	this->_spare = nullptr;
	// Обнуляем текущий кусок памяти под учётные записи
	this->_meta = nullptr;
	// Обнуляем остаток текущего куска
	this->_metaLeft = 0;
	// Обнуляем общий список кусков памяти под учётные записи
	this->_metaChunks = nullptr;
	// Обнуляем списки свободных областей
	::memset(this->_lists, 0, sizeof(this->_lists));
	// Обнуляем состояние кучи
	this->_state = state_t();
	// Обнуляем источник страниц
	this->_source = nullptr;
}
/**
 * @brief Метод выдачи области страниц
 *
 * @param pages требуемое число страниц кучи
 * @return      адрес выданной области либо nullptr
 *
 */
void * awh::alloc::Pages::alloc(const size_t pages, size_t * served) noexcept {
	/**
	 * Сообщаем действительно выданное число страниц
	 *
	 * Выданное бывает БОЛЬШЕ затребованного: не найдись памяти под учётную запись
	 * остатка, область выдаётся целиком, не делясь. Спрашивавший прежде узнавал об
	 * этом полным разбором адреса сразу за выдачей - а слой этот знал ответ и так
	 */
	if(served != nullptr)
		// Пока выдавать нечего
		(* served) = 0;
	// Если требуемое число страниц не задано либо куча не заведена
	if((pages == 0) || (this->_source == nullptr))
		// Выдавать нечего
		return nullptr;
	// Если требуемое число страниц не помещается в кусок
	if(pages > PAGES)
		// Отвечаем отказом: куски у источника берутся одного размера
		return nullptr;
	// Ищем свободную область требуемого размера
	span_t * span = this->search(pages);
	/**
	 * Если подходящей области не нашлось, сливаем отложенное
	 *
	 * Соседние свободные области могли бы дать нужный размер вместе, но по отдельности
	 * малы. Сливаем их прежде, чем просить память у системы: обращение к источнику
	 * дороже обхода
	 */
	if((span == nullptr) && (this->_unmerged > 0)){
		// Сливаем отложенные области
		this->compact();
		// Повторяем поиск по слитым областям
		span = this->search(pages);
	}
	// Если подходящей области не нашлось
	if(span == nullptr){
		// Берём у источника новый кусок
		if(this->grow() == nullptr)
			// Отвечаем отказом
			return nullptr;
		// Повторяем поиск
		span = this->search(pages);
		// Если и теперь области не нашлось
		if(span == nullptr)
			// Отвечаем отказом
			return nullptr;
	}
	// Изымаем найденную область из списка свободных
	this->pull(span);
	/**
	 * Делим область, если она крупнее требуемого
	 */
	if(span->pages > pages){
		// Выдаём память под учётную запись остатка
		span_t * rest = this->_spare;
		// Если повторно используемая запись нашлась
		if(rest != nullptr)
			// Изымаем её из списка повторно используемых
			this->_spare = rest->next;
		// Если повторно используемой записи нет, берём новую
		else rest = reinterpret_cast <span_t *> (this->meta(sizeof(span_t)));
		// Если память под учётную запись не выдана
		if(rest == nullptr){
			/**
			 * Область не делим и выдаём целиком: потерять при этом можно лишь
			 * неиспользованный хвост, а отказать пришлось бы при наличии памяти
			 */
			// Отмечаем область выданной наружу
			span->released = false;
			// Обнуляем метку владельца: прежняя досталась от прошлой жизни области
			span->tag = 0;
			// Отмечаем содержимое области присутствующим
			span->purged = false;
			// Увеличиваем число выданных страниц куска
			span->chunk->used += span->pages;
			// Уменьшаем свободное
			this->_state.free -= (span->pages * PAGE);
			// Увеличиваем выданное наружу
			this->_state.used += (span->pages * PAGE);
			// Если требуется действительно выданное число страниц
			if(served != nullptr)
				// Сообщаем выданное целиком: область не делилась
				(* served) = span->pages;
			// Выводим адрес выданной области
			return span->base;
		}
		// Остаток начинается за выдаваемой областью
		rest->base = (span->base + (pages * PAGE));
		// Размер остатка - разница размеров
		rest->pages = (span->pages - pages);
		// Остаток свободен
		rest->released = true;
		// Признак отданного содержимого остаток наследует у делимой области
		rest->purged = span->purged;
		// Остаток никем не изъят
		rest->pending = false;
		// Отметку времени остаток наследует у делимой области
		rest->stamp = span->stamp;
		// Метки владельца у остатка нет: он свободен
		rest->tag = 0;
		// Остаток принадлежит тому же куску
		rest->chunk = span->chunk;
		// Связей в списке свободных у остатка пока нет
		rest->prev = nullptr;
		// Связь со следующей пока пуста
		rest->next = nullptr;
		// Уменьшаем размер выдаваемой области до требуемого
		span->pages = pages;
		// Записываем остаток в указатели куска
		this->mark(rest);
		// Вносим остаток в список свободных
		this->push(rest);
	}
	// Отмечаем область выданной наружу
	span->released = false;
	// Обнуляем метку владельца: прежняя досталась от прошлой жизни области
	span->tag = 0;
	// Записываем область в указатели куска
	this->mark(span);
	// Если содержимое области было системе отдано
	if(span->purged){
		// Уменьшаем отданное системе
		this->_state.purged -= (span->pages * PAGE);
		// Отмечаем содержимое области присутствующим
		span->purged = false;
	}
	// Увеличиваем число выданных страниц куска
	span->chunk->used += span->pages;
	// Уменьшаем свободное
	this->_state.free -= (span->pages * PAGE);
	// Увеличиваем выданное наружу
	this->_state.used += (span->pages * PAGE);
	// Если требуется действительно выданное число страниц
	if(served != nullptr)
		// Сообщаем действительно выданное число страниц
		(* served) = span->pages;
	// Выводим адрес выданной области
	return span->base;
}
/**
 * @brief Метод расширения выданной области на месте
 *
 * @note Зовётся ПОД замком кучи: правит списки свободных областей и указатели куска
 *
 * @param addr  адрес начала расширяемой области
 * @param pages требуемое число страниц кучи
 * @return      признак состоявшегося расширения
 *
 */
bool awh::alloc::Pages::expand(void * addr, const size_t pages) noexcept {
	// Если расширять нечего
	if((addr == nullptr) || (pages == 0) || (pages > PAGES))
		// Расширять нечего
		return false;
	// Ищем кусок, которому принадлежит адрес
	chunk_t * chunk = this->lookup(addr);
	// Если кусок не наш
	if(chunk == nullptr)
		// Расширять нечего
		return false;
	// Определяем номер первой страницы области в куске
	const size_t first = static_cast <size_t> ((reinterpret_cast <uint8_t *> (addr) - chunk->base) / PAGE);
	// Получаем область по номеру страницы
	span_t * span = chunk->index[first].load(std::memory_order_acquire);
	/**
	 * Расширяем лишь ВЫДАННУЮ область и лишь с её начала
	 *
	 * Адрес внутри области принадлежит ей же, но расширять по нему нельзя: звавший
	 * держит начало, и рост от середины сдвинул бы содержимое
	 */
	if((span == nullptr) || span->released || (span->base != reinterpret_cast <uint8_t *> (addr)))
		// Расширять нечего
		return false;
	// Если требуемое уже помещается
	if(span->pages >= pages)
		// Расширять не нужно
		return true;
	// Определяем недостающее число страниц
	const size_t need = (pages - span->pages);
	// Определяем предел куска в страницах
	const size_t limit = ((chunk->size / PAGE) < PAGES ? (chunk->size / PAGE) : PAGES);
	/**
	 * Считаем свободное за концом области ПРЕЖДЕ, чем что-либо править
	 *
	 * Соседей может оказаться несколько подряд: слияние освобождённых областей
	 * отложено до нехватки, и подряд лежащие свободные области остаются раздельными.
	 * Возьми мы лишь первого - расширение отказывало бы там, где места вдоволь;
	 * замером это выглядело как расползание: круг за кругом на месте оставалось всё
	 * меньше шагов цепочки
	 *
	 * Считаем ДО правки затем, чтобы не остаться с наполовину поглощёнными соседями:
	 * места не хватило - не тронуто ничего, и звавший переносит содержимое обычным путём
	 */
	// Число свободных страниц, лежащих подряд за концом области
	size_t available = 0;
	// Номер страницы за концом уже сосчитанного
	size_t cursor = (first + span->pages);
	/**
	 * Перебираем соседей подряд
	 */
	while((available < need) && (cursor < limit)){
		// Получаем очередного соседа
		span_t * neighbour = chunk->index[cursor].load(std::memory_order_acquire);
		/**
		 * Сосед обязан быть свободен и не изъят
		 *
		 * Изъятую область брать нельзя: она отдаётся системе прямо сейчас, и звавший
		 * получил бы страницы, у него же из-под рук уходящие
		 */
		if((neighbour == nullptr) || !neighbour->released || neighbour->pending)
			// Дальше расти некуда
			break;
		// Считаем свободные страницы соседа
		available += neighbour->pages;
		// Переходим за конец соседа
		cursor += neighbour->pages;
	}
	// Если свободного за концом области не хватает
	if(available < need)
		// Расширять нечем
		return false;
	// Число страниц, взятых у соседей
	size_t taken = 0;
	// Связка поглощённых записей, ждущих возврата в повторно используемые
	span_t * absorbed = nullptr;
	/**
	 * Поглощаем соседей, покуда не наберём недостающего
	 */
	while(taken < need){
		// Получаем очередного соседа
		span_t * neighbour = chunk->index[first + span->pages + taken].load(std::memory_order_acquire);
		// Если сосед вдруг оказался негодным
		if((neighbour == nullptr) || !neighbour->released || neighbour->pending)
			// Перебирать больше нечего: сосчитанное выше говорит, что этого не случится
			break;
		// Изымаем соседа из списка свободных
		this->pull(neighbour);
		// Определяем недостающее у этого соседа
		const size_t rest = (need - taken);
		/**
		 * Делим соседа, если он крупнее недостающего
		 */
		if(neighbour->pages > rest){
			// Берём учётную запись под остаток соседа
			span_t * tail = this->_spare;
			// Если повторно используемая запись нашлась
			if(tail != nullptr)
				// Изымаем её из списка повторно используемых
				this->_spare = tail->next;
			// Если повторно используемой записи нет, берём новую
			else tail = reinterpret_cast <span_t *> (this->meta(sizeof(span_t)));
			/**
			 * Если записи под остаток нет, берём соседа ЦЕЛИКОМ
			 *
			 * Потерять при этом можно лишь неиспользованный хвост, а отказать пришлось
			 * бы при наличии памяти - ровно так же поступает и выдача
			 */
			if(tail != nullptr){
				// Остаток начинается за взятым у соседа
				tail->base = (neighbour->base + (rest * PAGE));
				// Размер остатка - разница размеров
				tail->pages = (neighbour->pages - rest);
				// Остаток свободен
				tail->released = true;
				// Признак отданного содержимого остаток наследует у соседа
				tail->purged = neighbour->purged;
				// Остаток никем не изъят
				tail->pending = false;
				// Отметку времени остаток наследует у соседа
				tail->stamp = neighbour->stamp;
				// Метки владельца у остатка нет: он свободен
				tail->tag = 0;
				// Остаток принадлежит тому же куску
				tail->chunk = chunk;
				// Связей в списке свободных у остатка пока нет
				tail->prev = nullptr;
				// Связь со следующей пока пуста
				tail->next = nullptr;
				// Уменьшаем размер соседа до взятого
				neighbour->pages = rest;
				// Записываем остаток в указатели куска
				this->mark(tail);
				// Вносим остаток в список свободных
				this->push(tail);
			}
		}
		/**
		 * Если содержимое взятых страниц было системе отдано
		 *
		 * Содержимое их звавшему не обещано - он растит блок и пишет туда сам, - но
		 * счёт отданного системе обязан убыть: страницы эти вновь наши
		 */
		if(neighbour->purged)
			// Уменьшаем отданное системе
			this->_state.purged -= (neighbour->pages * PAGE);
		// Считаем взятое у соседей
		taken += neighbour->pages;
		/**
		 * Откладываем запись соседа в местную связку, а не в список повторно используемых
		 *
		 * @warning Отдать её сразу НЕЛЬЗЯ: указатели куска покуда ведут на неё, а
		 *          читатель разбирает адрес БЕЗ замка кучи. Взяв запись из повторно
		 *          используемых, выдача переписала бы её поля прямо под таким читателем,
		 *          и разбор ответил бы о чужой области. Отдаём их после `mark`, когда
		 *          указатели куска ведут уже на расширенную область
		 */
		// Вносим запись соседа в местную связку поглощённых
		neighbour->next = absorbed;
		// Запоминаем связку поглощённых записей
		absorbed = neighbour;
	}
	/**
	 * Счётчик отложенного слияния здесь не правится намеренно
	 *
	 * Он подсказка, а не учёт: `compact` сбрасывает его в нуль, сколько бы областей ни
	 * слил. Оставшись завышенным, он лишь однажды заведёт слияние там, где сливать уже
	 * нечего, - а заниженным мог бы отменить нужное
	 */
	// Если взять у соседей ничего не вышло
	if(taken == 0)
		// Расширения не состоялось
		return false;
	/**
	 * Правим размер области ПРЕЖДЕ, чем переводим на неё указатели куска
	 *
	 * Порядок этот держит читателя, разбирающего адрес без замка: указатели куска -
	 * единственный путь к области, и к тому мигу, как читатель придёт по ним со
	 * страницы из вновь поглощённых, размер обязан её уже накрывать. Переставь мы
	 * местами - читатель получил бы область, в размер которой его же страница не
	 * входит
	 */
	// Увеличиваем размер расширяемой области
	span->pages += taken;
	// Записываем область в указатели куска по всем её страницам
	this->mark(span);
	/**
	 * Возвращаем поглощённые записи в список повторно используемых
	 *
	 * Делается это ПОСЛЕ `mark`: указатели куска ведут уже на расширенную область, и
	 * читатель, разбирающий адрес без замка, на поглощённые записи больше не попадёт
	 */
	while(absorbed != nullptr){
		// Запоминаем очередную поглощённую запись
		span_t * record = absorbed;
		// Сдвигаем связку поглощённых записей
		absorbed = record->next;
		// Возвращаем запись в список повторно используемых
		record->next = this->_spare;
		// Запоминаем список повторно используемых записей
		this->_spare = record;
	}
	// Увеличиваем число выданных страниц куска
	chunk->used += taken;
	// Уменьшаем свободное
	this->_state.free -= (taken * PAGE);
	// Увеличиваем выданное наружу
	this->_state.used += (taken * PAGE);
	// Выводим признак набранного размера
	return (span->pages >= pages);
}
/**
 * @brief Метод поиска области, которой принадлежит адрес
 *
 * @param addr  разбираемый адрес
 * @param begin адрес начала найденной области
 * @param pages размер найденной области в страницах кучи
 * @param live  признак выданной наружу области
 * @return      признак того, что адрес принадлежит куче
 *
 */
bool awh::alloc::Pages::locate(const void * addr, const void ** begin, size_t * pages, bool * live) const noexcept {
	// Если адрес не задан
	if(addr == nullptr)
		// Разбирать нечего
		return false;
	// Приводим адрес к целому виду
	const uintptr_t value = reinterpret_cast <uintptr_t> (addr);
	/**
	 * Перебираем взятые у источника куски
	 *
	 * Перебор допустим: кусков немного, а метод зовётся лишь при разборе адреса сбоя,
	 * то есть однажды за жизнь процесса
	 */
	for(const chunk_t * chunk = this->_chunks; chunk != nullptr; chunk = chunk->next){
		// Приводим начало куска к целому виду
		const uintptr_t base = reinterpret_cast <uintptr_t> (chunk->base);
		// Если адрес лежит вне куска
		if((value < base) || (value >= (base + chunk->size)))
			// Переходим к следующему куску
			continue;
		// Определяем номер страницы, которой принадлежит адрес
		const size_t page = static_cast <size_t> ((value - base) / PAGE);
		// Получаем область, которой принадлежит страница
		const span_t * span = chunk->index[page].load(std::memory_order_acquire);
		// Если области у страницы нет
		if(span == nullptr)
			// Адрес принадлежит куче, но области за ним нет
			return false;
		// Если требуется адрес начала области
		if(begin != nullptr)
			// Записываем адрес начала области
			(* begin) = span->base;
		// Если требуется размер области
		if(pages != nullptr)
			// Записываем размер области
			(* pages) = span->pages;
		// Если требуется признак выданной области
		if(live != nullptr)
			// Записываем признак выданной наружу области
			(* live) = (!span->released);
		// Отвечаем, что адрес принадлежит куче
		return true;
	}
	// Адрес куче не принадлежит
	return false;
}
/**
 * @brief Метод определения размера выданной области
 *
 * @param addr адрес выданной области
 * @return     размер области в страницах кучи, либо нуль
 *
 */
size_t awh::alloc::Pages::size(const void * addr) const noexcept {
	// Размер найденной области
	size_t pages = 0;
	// Признак выданной наружу области
	bool live = false;
	// Адрес начала найденной области
	const void * begin = nullptr;
	// Если адрес куче не принадлежит
	if(!this->locate(addr, &begin, &pages, &live))
		// Размера у него нет
		return 0;
	// Если адрес не есть начало выданной наружу области
	if((begin != addr) || !live)
		// Размера у него нет
		return 0;
	// Выводим размер области
	return pages;
}
/**
 * @brief Метод возврата области страниц
 *
 * @param addr адрес возвращаемой области
 * @param now  текущее время в миллисекундах
 * @return     признак возврата области
 *
 */
bool awh::alloc::Pages::free(void * addr, const uint64_t now) noexcept {
	// Если адрес не задан либо куча не заведена
	if((addr == nullptr) || (this->_source == nullptr))
		// Возвращать нечего
		return false;
	// Приводим адрес к целому виду
	const uintptr_t value = reinterpret_cast <uintptr_t> (addr);
	/**
	 * Ищем кусок, которому принадлежит адрес
	 */
	for(chunk_t * chunk = this->_chunks; chunk != nullptr; chunk = chunk->next){
		// Приводим начало куска к целому виду
		const uintptr_t base = reinterpret_cast <uintptr_t> (chunk->base);
		// Если адрес лежит вне куска
		if((value < base) || (value >= (base + chunk->size)))
			// Переходим к следующему куску
			continue;
		// Определяем номер страницы, которой принадлежит адрес
		const size_t page = static_cast <size_t> ((value - base) / PAGE);
		// Получаем область, которой принадлежит страница
		span_t * span = chunk->index[page].load(std::memory_order_acquire);
		// Если области нет либо адрес не есть её начало
		if((span == nullptr) || (span->base != reinterpret_cast <uint8_t *> (addr)))
			// Отвечаем отказом: адрес выдан не нами
			return false;
		// Если область уже свободна
		if(span->released)
			// Отвечаем отказом: повторное освобождение
			return false;
		// Отмечаем область свободной
		span->released = true;
		/**
		 * Ставим отметку времени освобождения
		 *
		 * Без неё отсрочка отдачи не работает вовсе: отметка осталась бы нулевой, разница
		 * с текущим временем - заведомо большей отсрочки, и память уходила бы системе
		 * немедленно при любой настройке
		 */
		span->stamp = now;
		// Уменьшаем число выданных страниц куска
		chunk->used -= span->pages;
		// Уменьшаем выданное наружу
		this->_state.used -= (span->pages * PAGE);
		// Увеличиваем свободное
		this->_state.free += (span->pages * PAGE);
		/**
		 * Слияние ОТКЛАДЫВАЕМ
		 *
		 * Слить область с соседями значит вырастить её вплоть до целого куска, а запись
		 * области в указатели куска идёт по всем её страницам - у куска их 512. Следующая
		 * же выдача делит выросшую область обратно и пишет указатели снова. Замер пути
		 * выдачи сверх разрядов показал на этой паре около семи десятых всего времени, а
		 * отказ от слияния при возврате поднял полосу вчетверо.
		 *
		 * Слияние не отменяется, а откладывается: его выполняет `compact` тогда, когда
		 * области нужного размера не нашлось, и перед отдачей памяти системе. Так
		 * дробление не растёт без предела, а платится за него лишь тот, кому не хватило
		 */
		// Вносим область в список свободных как есть
		this->push(span);
		// Считаем область, ждущую слияния
		this->_unmerged++;

		// Отвечаем успехом
		return true;
	}
	// Адрес куче не принадлежит
	return false;
}
