/**
 * Подключаем заголовочные файлы проекта
 */
#include <proto/quic/quic.hpp>
#include <proto/quic/varint.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * @brief Функция определения размера закодированного числа в октетах
 *
 * @param value кодируемое число
 * @return      размер в октетах (1/2/4/8) или 0, если число превышает 2^62-1
 *
 */
size_t awh::quic::varint::size(const uint64_t value) noexcept {
	// Если число помещается в 6 бит
	if(value < 0x40)
		// Кодирование одним октетом
		return 1;
	// Если число помещается в 14 бит
	if(value < 0x4000)
		// Кодирование двумя октетами
		return 2;
	// Если число помещается в 30 бит
	if(value < 0x40000000)
		// Кодирование четырьмя октетами
		return 4;
	// Если число помещается в 62 бита
	if(value <= proto::VARINT_MAX)
		// Кодирование восемью октетами
		return 8;
	// Число не представимо целым числом переменной длины
	return 0;
}
/**
 * @brief Функция определения размера закодированного числа по первому октету
 *
 * @param first первый октет закодированного числа
 * @return      размер числа в октетах (1/2/4/8)
 *
 */
size_t awh::quic::varint::sizeAt(const uint8_t first) noexcept {
	// Два старших бита первого октета кодируют логарифм длины числа
	return (static_cast <size_t> (1) << (first >> 6));
}
/**
 * @brief Функция чтения целого числа переменной длины
 *
 * @param data  входной буфер
 * @param size  доступно байт
 * @param value прочитанное число
 * @return      количество прочитанных октетов или 0, если данных недостаточно
 *
 */
size_t awh::quic::varint::read(const uint8_t * data, const size_t size, uint64_t & value) noexcept {
	// Если в буфере нет даже первого октета
	if(size < 1)
		// Данных недостаточно
		return 0;
	// Определяем размер числа по двум старшим битам первого октета
	const size_t count = sizeAt(data[0]);
	// Если число целиком не помещается в буфер
	if(size < count)
		// Данных недостаточно
		return 0;
	// Собираем число из первого октета без битов длины
	value = static_cast <uint64_t> (data[0] & 0x3F);
	/**
	 * Перебираем оставшиеся октеты числа
	 */
	for(size_t i = 1; i < count; i++)
		// Дописываем очередной октет числа в сетевом порядке
		value = ((value << 8) | data[i]);
	// Выводим количество прочитанных октетов
	return count;
}
/**
 * @brief Функция записи целого числа переменной длины (минимальное кодирование)
 *
 * @param output выходной буфер
 * @param value  записываемое число (не более 2^62-1)
 * @return       количество записанных октетов или 0, если число превышает 2^62-1
 *
 */
size_t awh::quic::varint::write(string & output, const uint64_t value) noexcept {
	// Определяем минимальный размер кодирования числа
	const size_t count = size(value);
	// Если число не представимо целым числом переменной длины
	if(count == 0)
		// Запись невозможна
		return 0;
	// Два старших бита первого октета кодируют логарифм длины числа
	uint64_t encoded = value;
	/**
	 * Определяем размер кодирования числа
	 */
	switch(count){
		// Кодирование двумя октетами
		case 2:
			// Устанавливаем биты длины 01
			encoded |= (static_cast <uint64_t> (0x40) << 8);
		break;
		// Кодирование четырьмя октетами
		case 4:
			// Устанавливаем биты длины 10
			encoded |= (static_cast <uint64_t> (0x80) << 24);
		break;
		// Кодирование восемью октетами
		case 8:
			// Устанавливаем биты длины 11
			encoded |= (static_cast <uint64_t> (0xC0) << 56);
		break;
	}
	/**
	 * Перебираем октеты числа от старшего к младшему
	 */
	for(size_t i = count; i > 0; i--)
		// Дописываем очередной октет числа в сетевом порядке
		output.push_back(static_cast <char> ((encoded >> ((i - 1) * 8)) & 0xFF));
	// Выводим количество записанных октетов
	return count;
}
