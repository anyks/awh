/**
 * @brief Метод обмена заголовками
 *
 * @param headers заголовки для обмена
 *
 */
void awh::http::Headers::swap(Headers & headers) noexcept {
	// Обмениваем местами наборы заголовков
	this->_headers.swap(headers._headers);
	// Обмениваем местами объекты провайдера HTTP-запроса/ответа
	this->_provider.swap(headers._provider);
	// Обмениваем местами протокол HTTP-запроса/ответа
	const proto_t proto = this->_proto;
	// Устанавливаем протокол HTTP-запроса/ответа из переданного контейнера
	this->_proto = headers._proto;
	// Устанавливаем протокол HTTP-запроса/ответа в переданный контейнер
	headers._proto = proto;
	// Обмениваем местами ограничения по памяти и количеству заголовков
	const max_t max = this->_max;
	// Устанавливаем ограничения по памяти и количеству заголовков из переданного контейнера
	this->_max = headers._max;
	// Устанавливаем ограничения по памяти и количеству заголовков в переданный контейнер
	headers._max = max;
	// Обмениваем местами счётчики потребляемой памяти
	const size_t memory = this->_memory;
	// Устанавливаем счётчик потребляемой памяти из переданного контейнера
	this->_memory = headers._memory;
	// Устанавливаем счётчик потребляемой памяти в переданный контейнер
	headers._memory = memory;
	/**
	 * Обмениваем местами идентификацию сервиса: она такая же часть состояния контейнера,
	 * как и прочие поля, и без обмена настроенный агент остался бы в чужом объекте
	 */
	this->_ident.id.swap(headers._ident.id);
	// Обмениваем местами названия сервиса
	this->_ident.name.swap(headers._ident.name);
	// Обмениваем местами версии модуля приложения
	this->_ident.version.swap(headers._ident.version);
	/**
	 * Обмениваем местами объекты фреймворка и логирования: операторы присваивания
	 * переносят их вместе с остальным состоянием, и обмен, их не трогающий,
	 * оставлял бы объекты с разными правилами переноса одного и того же поля
	 */
	const fmk_t * fmk = this->_fmk;
	// Устанавливаем объект фреймворка из переданного контейнера
	this->_fmk = headers._fmk;
	// Устанавливаем объект фреймворка в переданный контейнер
	headers._fmk = fmk;
	// Запоминаем объект логирования текущего контейнера
	const log_t * log = this->_log;
	// Устанавливаем объект логирования из переданного контейнера
	this->_log = headers._log;
	// Устанавливаем объект логирования в переданный контейнер
	headers._log = log;
}
/**
 * @brief Метод слияния заголовков
 *
 * @param headers заголовки для слияния
 *
 */
void awh::http::Headers::merge(const Headers & headers, const mode_t mode) noexcept {
	// Если сливать нечего либо контейнер передан сам себе - слияние не выполняется
	if((&headers == this) || headers._headers.empty())
		// Выходим из метода
		return;
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Объём полезной нагрузки, освобождаемый удалением прежних вхождений
		size_t released = 0;
		// Количество записей, освобождаемых удалением прежних вхождений
		size_t vacated = 0;
		// Объём полезной нагрузки сливаемых заголовков
		size_t payload = 0;
		/**
		 * Считаем объём сливаемых заголовков
		 */
		for(const auto & header : headers._headers)
			// Увеличиваем объём полезной нагрузки сливаемых заголовков
			payload += (header.name.size() + header.value.size());
		/**
		 * В режиме замены прежние вхождения одноимённых заголовков освобождают место,
		 * поэтому считаем, сколько именно они освободят
		 */
		if(mode == mode_t::REPLACE){
			/**
			 * Выполняем перебор всех установленных заголовков
			 */
			for(const auto & header : this->_headers){
				/**
				 * Выполняем поиск названия текущего заголовка среди сливаемых
				 */
				for(const auto & source : headers._headers){
					// Если название заголовка совпадает с названием сливаемого
					if(::equals(header.name, source.name)){
						// Увеличиваем количество освобождаемых записей
						vacated++;
						// Увеличиваем освобождаемый объём полезной нагрузки
						released += (header.name.size() + header.value.size());
						// Прерываем поиск по сливаемым заголовкам
						break;
					}
				}
			}
		}
		// Вычисляем количество записей, которое даст слияние
		const size_t records = ((this->_headers.size() - vacated) + headers._headers.size());
		// Вычисляем объём потребляемой памяти после удаления прежних вхождений
		const size_t memory = ((released <= this->_memory) ? (this->_memory - released) : 0);
		/**
		 * Если слияние в ограничения не помещается - оно не начинается вовсе, в обоих
		 * режимах. При замене удаление прежних вхождений с последующим отказом
		 * в добавлении убрало бы поля из набора целиком, при добавлении набор принял бы
		 * сливаемые заголовки частично - до первого отвергнутого. И то и другое
		 * вызывающая сторона получила бы без всякого признака, а слияние наполовину
		 * не является слиянием
		 */
		if((records > this->_max.records) || (payload > this->_max.memory) || (memory > (this->_max.memory - payload))){
			// Записываем предупреждение в лог
			this->_error(__PRETTY_FUNCTION__, "merge is rejected: the resulting set does not fit the limits", log_t::flag_t::WARNING);
			// Выходим из метода, сохраняя набор заголовков нетронутым
			return;
		}
		/**
		 * Снимаем с набора и счётчика памяти снимок, чтобы вернуть их при отказе
		 * выделения посреди слияния: прежние вхождения снимаются заранее, а поля
		 * переданного контейнера добавляются по одному, и отказ на середине оставил бы
		 * набор слитым наполовину - без части прежних полей и без части сливаемых.
		 * Слияние наполовину слиянием не является, а признака отказа вызывающая сторона
		 * не получила бы. Снимок обходится одним выделением на слияние; слияние наборов
		 * на пути обработки сообщения не лежит и в замер не входит
		 */
		fields_t snapshot = this->_headers;
		// Запоминаем объём потребляемой памяти до слияния
		const size_t restored = this->_memory;
		/**
		 * В режиме замены прежние вхождения одноимённых заголовков удаляются заранее,
		 * все разом: удаление по ходу добавления снесло бы уже добавленные заголовки
		 * переданного контейнера, если он содержит несколько полей одного названия
		 */
		if(mode == mode_t::REPLACE){
			/**
			 * Проходим по всем заголовкам переданного контейнера
			 */
			for(const auto & header : headers._headers)
				// Удаляем прежние вхождения заголовка с указанным названием
				this->erase(header.name);
		}
		/**
		 * Проходим по всем заголовкам переданного контейнера и добавляем их в текущий набор с сохранением дубликатов
		 */
		for(const auto & header : headers._headers){
			// Запоминаем количество записей набора до добавления очередного заголовка
			const size_t records = this->_headers.size();
			/**
			 * Добавление отвергнутое либо не удавшееся распознаётся по количеству записей,
			 * а не по проброшенному отказу: добавление объявлено не выбрасывающим и свои
			 * отказы перехватывает само, записывая их в лог. Ожидание проброса оставило бы
			 * возврат набора недостижимым, а слияние - способным завершиться наполовину
			 */
			if(this->_emplace(header.name, header.value) == records){
				// Возвращаем набор заголовков из снимка
				this->_headers = ::move(snapshot);
				// Возвращаем объём потребляемой памяти
				this->_memory = restored;
				// Записываем предупреждение в лог
				this->_error(__PRETTY_FUNCTION__, "merge is rejected: the header has not been added", log_t::flag_t::WARNING);
				// Выходим из метода, оставив набор в прежнем виде
				return;
			}
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		// Записываем ошибку в лог
		this->_error(__PRETTY_FUNCTION__, error.what());
	}
}
