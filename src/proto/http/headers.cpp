/**
 * @brief Оператор получения списка заголовков в виде сообщения
 *
 * @details Выдаётся вид сообщения, а не хранилище: набор собирается тем же
 *          сборщиком, что и печать, - с псевдозаголовками и без полей, которых
 *          в сообщении текущего протокола быть не может. Хранилище как оно есть
 *          выдают обходы итераторами и операторы отображений
 *
 * @return список заголовков, собранный под текущий протокол
 *
 */
awh::http::Headers::operator fields_t() const noexcept {
	// Результат работы функции - список всех добавленных заголовков
	fields_t result;
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		/**
		 * Собираем набор под текущий протокол общим сборщиком: он добавляет
		 * псевдозаголовки и отсеивает поля, которых в сообщении быть не может.
		 * Тот же вид даёт печать, поэтому собранное из списка полей разбирается
		 * обратно, а не отвергается принимающей стороной
		 */
		result = this->_compose(this->_proto);
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		// Записываем ошибку в лог
		this->_error(__PRETTY_FUNCTION__, error.what());
	}
	// Выводим результат
	return result;
}
/**
 * @brief Оператор получения списка заголовков в виде сообщения
 *
 * @details Выдаётся вид сообщения, а не хранилище: набор собирается тем же
 *          сборщиком, что и печать, - с псевдозаголовками и без полей, которых
 *          в сообщении текущего протокола быть не может
 *
 * @return список пар названия и значения, собранный под текущий протокол
 *
 */
awh::http::Headers::operator entries_t() const noexcept {
	// Результат работы функции - набор заголовков
	entries_t result;
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		/**
		 * Вне семейства HTTP/2 общий сборщик отдаёт набор без единого изменения,
		 * то есть копирует его целиком ради одного лишь перебора - там заголовки
		 * берутся из самого набора, и вид получается тот же самый
		 */
		if(!::isBinaryProto(this->_proto)){
			// Резервируем память под набор заголовков
			result.reserve(this->_headers.size());
			/**
			 * Выполняем перебор набора заголовков напрямую
			 */
			for(const auto & header : this->_headers)
				// Добавляем заголовок в результирующий набор
				result.emplace(header);
		/**
		 * Для семейства HTTP/2 набор собирается общим сборщиком
		 */
		} else {
			// Собираем набор под текущий протокол общим сборщиком - тем же, что применяют печать и список полей
			fields_t fields = this->_compose(this->_proto);
			// Резервируем память под собранный набор заголовков
			result.reserve(fields.size());
			/**
			 * Переносим собранные заголовки в результирующий набор
			 */
			for(auto & header : fields)
				// Добавляем заголовок в результирующий набор
				result.emplace(::move(header));
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		// Записываем ошибку в лог
		this->_error(__PRETTY_FUNCTION__, error.what());
	}
	// Выводим результат
	return result;
}
/**
 * @brief Оператор получения хранилища заголовков с единственным значением на название
 *
 * @details Выдаётся хранилище как оно есть: без псевдозаголовков и без отсева
 *          полей, неуместных в текущем протоколе. Значения одного названия
 *          отображением не удерживаются - остаётся первое встретившееся,
 *          то есть ровно то, что выдаёт обращение по названию. Все значения
 *          отдаёт отображение с кратными ключами, вид сообщения - печать
 *          и операторы списков
 *
 * @return отображение названий заголовков на значения
 *
 */
awh::http::Headers::operator map_t() const noexcept {
	// Результат работы функции - карта заголовков (при дублирующихся именах сохраняется первое встретившееся значение)
	map_t result;
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Резервируем память под карту заголовков
		result.reserve(this->_headers.size());
		/**
		 * Проходим по всем установленным заголовкам
		 */
		for(const auto & header : this->_headers)
			// Добавляем пару ключ-значение в карту, если такой ключ ещё не добавлен
			result.emplace(header.name, header.value);
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		// Записываем ошибку в лог
		this->_error(__PRETTY_FUNCTION__, error.what());
	}
	// Выводим результат
	return result;
}
