/**
 * @brief Оператор сравнения двух заголовков
 *
 * @param headers заголовки для сравнения
 * @return        результат сравнения
 *
 */
bool awh::http::Headers::operator == (const Headers & headers) const noexcept {
	// Если количество заголовков в списках не совпадает - контейнеры точно не равны
	if(this->_headers.size() != headers._headers.size())
		// Возвращаем результат сравнения
		return false;
	// Если протоколы контейнеров различаются - равными они не являются
	if(this->_proto != headers._proto)
		// Возвращаем результат сравнения
		return false;
	/**
	 * Если провайдеры описывают разные сообщения - контейнеры не равны: набор полей
	 * у них совпадает, но печать даёт разные стартовые строки либо псевдозаголовки.
	 * Идентификация сервиса в сравнении не участвует - она задаёт, чем заполнять
	 * заголовки по умолчанию, а не что в сообщении находится
	 */
	if(!::equalsProvider(this->_provider.get(), headers._provider.get()))
		// Возвращаем результат сравнения
		return false;
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Тип последовательности значений одного названия заголовка в порядке добавления
		using values_t = vector <string>;
		// Тип группировки значений по названию заголовка без учёта регистра
		using groups_t = unordered_map <string, values_t, header_name_hash_t, header_name_equal_t>;
		/**
		 * @brief Функция группировки значений по названию заголовка
		 *
		 * @param fields группируемый набор заголовков
		 * @return       группировка значений по названию заголовка
		 *
		 */
		auto group = [](const fields_t & fields) noexcept -> groups_t {
			// Результат работы функции - группировка значений по названию заголовка
			groups_t result;
			// Резервируем память под группировку значений
			result.reserve(fields.size());
			/**
			 * Выполняем перебор всех заголовков набора, складывая значения в порядке добавления
			 */
			for(const auto & header : fields)
				// Дописываем значение к последовательности соответствующего названия
				result[header.name].push_back(header.value);
			// Выводим группировку значений
			return result;
		};
		/**
		 * Контейнеры равны, если совпадают группировки значений. Порядок заголовков
		 * с разными названиями значения не имеет (RFC 9110 §5.3), поэтому группировка
		 * хранится неупорядоченной картой. Порядок значений одного названия, наоборот,
		 * смысл несёт - именно им задаётся очерёдность полей вроде Set-Cookie, - поэтому
		 * внутри названия значения сверяются последовательностью, а не кратностью
		 */
		return (group(this->_headers) == group(headers._headers));
	/**
	 * Если возникает ошибка - считаем контейнеры не равными
	 */
	} catch(const exception &) {
		// Возвращаем результат сравнения
		return false;
	}
}
