/**
 * @brief Метод получения идентификации сервиса
 *
 * @return сформированный агент
 *
 */
string awh::http::Headers::ident() const noexcept {
	// Результат работы функции
	string result = "";
	// Проверяем наличие объекта провайдера HTTP-запроса/ответа
	if(this->_provider == nullptr)
		// Если объект провайдера HTTP-запроса/ответа отсутствует
		return result;
	/**
	 * Определяем направление трафика (запрос/ответ) по явному флагу вместо приведения типа через RTTI (dynamic_cast),
	 * что позволяет избежать накладных расходов на обход таблиц виртуальных методов
	 */
	switch(static_cast <uint8_t> (this->_provider->direct)){
		// Если установлен запрос клиента
		case static_cast <uint8_t> (direct_t::REQUEST): {
			/**
			 * Операционной системой является Windows 32bit
			 */
			#ifdef _WIN32
				// Устанавливаем название операционной системы
				const char * os = "Windows";
			/**
			 * Операционной системой является Windows 64bit
			 */
			#elif _WIN64
				// Устанавливаем название операционной системы
				const char * os = "Windows";
			/**
			 * Операционной системой является macOS
			 */
			#elif __APPLE__ || __MACH__
				// Устанавливаем название операционной системы
				const char * os = "macOS";
			/**
			 * Операционной системой является Linux
			 */
			#elif __linux__
				// Устанавливаем название операционной системы
				const char * os = "Linux";
			/**
			 * Операционной системой является FreeBSD
			 */
			#elif __FreeBSD__
				// Устанавливаем название операционной системы
				const char * os = "FreeBSD";
			/**
			 * Операционной системой является NetBSD
			 */
			#elif __NetBSD__
				// Устанавливаем название операционной системы
				const char * os = "NetBSD";
			/**
			 * Операционной системой является OpenBSD
			 */
			#elif __OpenBSD__
				// Устанавливаем название операционной системы
				const char * os = "OpenBSD";
			/**
			 * Реализация под Sun Solaris
			 */
			#elif __sun__
				/**
				 * Если операционной системой является OpenSolaris
				 */
				#ifdef __illumos__
					// Устанавливаем название операционной системы
					const char * os = "OpenSolaris";
				#else
					// Устанавливаем название операционной системы
					const char * os = "Solaris";
				#endif
			/**
			 * Операционной системой является Unix
			 */
			#elif __unix || __unix__
				// Устанавливаем название операционной системы
				const char * os = "Unix";
			/**
			 * Операционной системой не распознана
			 */
			#else
				// Устанавливаем название операционной системы
				const char * os = "Unknown OS";
			#endif
			/**
			 * Выполняем генерацию User-Agent клиента выполняющего HTTP-запрос:
			 * значение складывается напрямую, без объекта фреймворка - контейнер
			 * заголовков создаётся и без него, а вызов его метода по пустому
			 * указателю является неопределённым поведением
			 */
			result.append(this->_ident.name).append(" (").append(os).append("; ");
			// Добавляем идентификатор и версию сервиса
			result.append(this->_ident.id).append("/").append(this->_ident.version).append(")");
		} break;
		// Если установлен ответ сервера
		case static_cast <uint8_t> (direct_t::RESPONSE):
			// Выполняем генерацию X-Powered-By сервера, формирующего HTTP-ответ
			result.append(this->_ident.id).append("/").append(this->_ident.version);
		break;
	}
	// Выводим результат
	return result;
}
/**
 * @brief Метод установки идентификации сервиса
 *
 * @param id      идентификатор сервиса
 * @param name    название сервиса
 * @param version версия сервиса
 *
 */
void awh::http::Headers::ident(string_view id, string_view name, string_view version) noexcept {
	/**
	 * Составляющие идентификации попадают в значение поля целиком: у запроса - в
	 * User-Agent, у ответа - в X-Powered-By. Приложение берёт их извне, поэтому
	 * непригодная к записи составляющая не применяется вовсе: возврат каретки или
	 * перевод строки внутри неё расщепил бы сообщение на два, а проверка исходящих
	 * значений поймала бы это лишь на сборке - и уже после того, как значение
	 * поселилось в объекте. Составляющие проверяются по отдельности: непригодная
	 * одна не отменяет остальных
	 */
	/**
	 * @brief Функция применения одной составляющей идентификации сервиса
	 *
	 * @param target применяемая составляющая идентификации
	 * @param value  устанавливаемое значение составляющей
	 * @param title  название составляющей для записи в лог
	 *
	 */
	auto apply = [this](string & target, string_view value, const char * title) noexcept -> void {
		// Пустая составляющая оставляет прежнее значение
		if(value.empty())
			// Выходим из функции
			return;
		// Если составляющая пригодна к записи в значение поля
		if(::isFieldValue(value)){
			// Устанавливаем составляющую идентификации сервиса
			target = value;
			// Выходим из функции
			return;
		}
		// Буфер текста сообщения о непригодной составляющей идентификации
		char message[128];
		// Формируем текст сообщения о непригодной составляющей идентификации
		::snprintf(message, sizeof(message), "HTTP service %s contains octets not allowed in a field value and has not been changed", title);
		/**
		 * Записываем сообщение общей функцией вывода ошибки: контейнер заголовков
		 * создаётся и без объекта логирования, а составляющая не применяется в любом
		 * случае - остаться об этом без следа хуже, чем записать в поток ошибок
		 */
		::printError(this->_log, __PRETTY_FUNCTION__, message, log_t::flag_t::CRITICAL);
	};
	// Применяем идентификатор сервиса
	apply(this->_ident.id, id, "identifier");
	// Применяем название сервиса
	apply(this->_ident.name, name, "name");
	// Применяем версию сервиса
	apply(this->_ident.version, version, "version");
}
