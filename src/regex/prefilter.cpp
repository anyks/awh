#include <regex/prefilter.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;

/**
 * Подключаем набор команд над вектором
 *
 * @details Набор подключается по набору команд машины, а не по системе: поиск
 *          пары байтов исполняется одной командой сравнения над шестнадцатью
 *          байтами сразу, и команда эта у ARM64 и у x86-64 своя. Наборы эти
 *          в своих машинах обязательны - NEON входит в ARM64, а SSE2 входит
 *          в x86-64, - отчего проверка наличия их при исполнении не нужна
 *          и не ведётся. Машины прочие получают запасной путь, ведущий поиск
 *          словом в восемь байтов.
 *
 * @note Признак сборки «AWH_REGEX_SCALAR» отключает наборы команд над вектором
 *       и оставляет один лишь запасной путь. Заведён он затем, что путь этот
 *       ни на одной из машин, проектом поддерживаемых, не собирается вовсе -
 *       все они либо ARM64, либо x86-64, - и без такого ключа оставался бы
 *       кодом непроверенным. Сличается он с поиском обычным тем же набором
 *       образцов, что и пути векторные, - сборкой стенда с этим ключом.
 *       Сличений в стенде два: поиск последовательности сличается с поиском
 *       средствами библиотеки, а поиск набора байтов - с перебором побайтным;
 *       ключ отключает вектор у обоих разом:
 *
 *           c++ -std=c++17 -O2 -Iinclude -Itools/regex -DAWH_REGEX_SCALAR \
 *             tools/regex/conformance.cpp -o conformance \
 *             $(find src/regex src/encoding/unicode -maxdepth 1 -name '*.cpp') \
 *             && ./conformance
 *
 *       Состав исходных текстов берётся поиском, а не образцом с косой чертой:
 *       образец такой внутри примечания блочного открывал бы примечание
 *       вложенное, и компилятор отвечает на это предупреждением.
 *
 */
#if defined(AWH_REGEX_SCALAR)
	/**
	 * Наборы команд над вектором отключены признаком сборки
	 */
#elif defined(__aarch64__) || defined(_M_ARM64)
	/**
	 * Подключаем набор команд NEON
	 */
	#include <arm_neon.h>
	// Выполняем установку признака поиска набором команд NEON
	#define AWH_REGEX_NEON 1
#elif defined(__x86_64__) || defined(_M_X64)
	/**
	 * Подключаем набор команд SSE2
	 */
	#include <emmintrin.h>
	// Выполняем установку признака поиска набором команд SSE2
	#define AWH_REGEX_SSE2 1
#endif

/**
 * Если компилятор является Visual Studio
 */
#if defined(_MSC_VER)
	/**
	 * Подключаем заголовочный файл встроенных средств
	 */
	#include <intrin.h>
#endif

/**
 * @brief Пространство имён вспомогательных значений поиска
 *
 */
namespace {
	/**
	 * @brief Размер пробы текста, пару байтов поиска выбирающей
	 *
	 * @details Проба выбрана замером: пара, редкая в первых шестидесяти четырёх
	 *          байтах, бывает обыкновенна далее, отчего проба взята вчетверо
	 *          крупнее пробы выбора одиночного байта. Стоимость её окупается
	 *          прекращением перебора на первой же паре, в пробе не встреченной,
	 *          а такая находится почти всегда.
	 *
	 */
	constexpr size_t PROBING = 256;

	/**
	 * @brief Наибольшее расстояние между байтами выбираемой пары
	 *
	 * @details Расстояние ограничено затем, чтобы чтение второго байта не выходило
	 *          за пределы вектора далеко: чем шире разнос, тем длиннее хвост,
	 *          поиском обычным добираемый.
	 *
	 */
	constexpr size_t SPACING = 4;

	/**
	 * @brief Наибольшее количество пар, пробой перебираемых
	 *
	 * @details Перебор ограничен затем, чтобы проба не обошлась дороже самого
	 *          поиска: искомое бывает длиною в десятки байтов, а пар в нём
	 *          вчетверо больше того.
	 *
	 */
	constexpr size_t COUPLES = 24;

	/**
	 * @brief Набор единиц во всех байтах слова
	 *
	 */
	constexpr uint64_t ONES = 0x0101010101010101ull;

	/**
	 * @brief Набор старших разрядов во всех байтах слова
	 *
	 */
	constexpr uint64_t HIGHS = 0x8080808080808080ull;

	/**
	 * @brief Функция получения номера младшего установленного разряда
	 *
	 * @param value значение, разряд в котором отыскивается
	 * @return      номер младшего установленного разряда
	 *
	 */
	inline size_t trailing(const uint64_t value) noexcept {
		/**
		 * Если компилятор является Visual Studio
		 */
		#if defined(_MSC_VER)
			// Номер младшего установленного разряда
			unsigned long result = 0;
			// Выполняем поиск младшего установленного разряда
			::_BitScanForward64(&result, value);
			// Выводим номер младшего установленного разряда
			return static_cast <size_t> (result);
		/**
		 * Если компилятор принадлежит к семейству GCC или Clang
		 */
		#else
			// Выводим номер младшего установленного разряда
			return static_cast <size_t> (__builtin_ctzll(value));
		#endif
	}

	/**
	 * @brief Размер пробы текста, одиночный байт поиска выбирающей
	 *
	 */
	constexpr size_t PROBE = 64;

	/**
	 * @brief Функция выбора байта искомого, в пробе текста не встреченного
	 *
	 * @details Поиск по одиночному байту ведётся средствами библиотеки С,
	 *          а они проходят текст шире вектора и оттого быстрее: замер дал
	 *          65 ГБ/с против 39 у поиска по паре. Годен он, однако, лишь тогда,
	 *          когда байт в тексте и вправду редок, - иначе поиск обрывается
	 *          на каждой встрече и падает до 8,6 ГБ/с. Условием взято полное
	 *          отсутствие байта в пробе: байт, встреченный хоть раз, отдаётся
	 *          поиску по паре, каковой обрывов не знает вовсе.
	 *
	 * @param text   текст сопоставления
	 * @param what   искомая последовательность
	 * @param pos    позиция начала поиска
	 * @param anchor смещение выбранного байта в искомой последовательности
	 * @return       результат выбора байта, в пробе не встреченного
	 *
	 */
	bool solitary(const string_view text, const string_view what, const size_t pos, size_t & anchor) noexcept {
		// Создаём набор счёта байтов пробы текста
		uint8_t counts[256];
		// Выполняем сброс набора счёта байтов пробы текста
		::memset(counts, 0, sizeof(counts));
		// Получаем размер пробы текста сопоставления
		const size_t span = (((text.size() - pos) < PROBE) ? (text.size() - pos) : PROBE);
		/**
		 * Выполняем счёт байтов пробы текста сопоставления
		 */
		for(size_t i = 0; i < span; i++)
			// Выполняем счёт очередного байта пробы текста
			counts[static_cast <uint8_t> (text[pos + i])]++;
		/**
		 * Выполняем обход байтов искомой последовательности
		 */
		for(size_t i = 0; i < what.size(); i++) {
			/**
			 * Если байт искомого в пробе текста не встречен
			 */
			if(counts[static_cast <uint8_t> (what[i])] == 0) {
				// Выполняем установку смещения выбранного байта
				anchor = i;
				// Выводим результат выбора байта
				return true;
			}
		}
		// Выводим результат выбора байта
		return false;
	}

	/**
	 * @brief Функция выбора пары байтов искомого, в тексте редкой
	 *
	 * @details Пара выбирается пробой текста на саму пару, а не по двум
	 *          редчайшим байтам порознь. Выбор порознь оказался негоден замером:
	 *          у искомого «foxtrot» редчайшими байтами порознь выходят «f» и «x»,
	 *          а стоят они на расстоянии двух - и пара эта есть слово «fox»,
	 *          в тексте обыкновенное. Поиск по ней шёл медленнее поиска
	 *          по одному байту, тогда как проба на пару выводит все образцы
	 *          на одну и ту же скорость.
	 *
	 * @param text   текст сопоставления
	 * @param what   искомая последовательность
	 * @param pos    позиция начала поиска
	 * @param first  смещение первого байта выбранной пары
	 * @param second смещение второго байта выбранной пары
	 *
	 */
	void couple(const string_view text, const string_view what, const size_t pos, size_t & first, size_t & second) noexcept {
		// Получаем размер искомой последовательности
		const size_t length = what.size();
		// Получаем размер пробы текста сопоставления
		const size_t span = ((text.size() - pos) < PROBING ? (text.size() - pos) : PROBING);
		// Получаем адрес начала пробы текста сопоставления
		const char * probe = (text.data() + pos);
		// Выполняем установку пары байтов по умолчанию
		first = 0;
		// Выполняем установку второго байта пары по умолчанию
		second = 1;
		// Количество встреч выбранной пары в пробе текста
		size_t rarest = static_cast <size_t> (~0ull);
		// Количество пар, пробой перебранных
		size_t examined = 0;
		/**
		 * Выполняем перебор пар байтов искомой последовательности
		 */
		for(size_t a = 0; a < length; a++) {
			/**
			 * Выполняем перебор вторых байтов пары
			 */
			for(size_t b = (a + 1); (b < length) && (b <= (a + SPACING)); b++) {
				/**
				 * Если допустимое количество перебираемых пар исчерпано
				 */
				if(++examined > COUPLES)
					// Выходим из перебора пар байтов искомого
					return;
				// Получаем расстояние между байтами пары
				const size_t spacing = (b - a);
				// Количество встреч пары в пробе текста
				size_t count = 0;
				/**
				 * Выполняем счёт встреч пары байтов в пробе текста
				 */
				for(size_t i = 0; (i + spacing) < span; i++)
					// Выполняем счёт очередной встречи пары байтов
					count += ((probe[i] == what[a]) && (probe[i + spacing] == what[b]) ? 1 : 0);
				/**
				 * Если пара очередная в пробе текста реже выбранной
				 */
				if(count < rarest) {
					// Выполняем установку количества встреч выбранной пары
					rarest = count;
					// Выполняем установку первого байта выбранной пары
					first = a;
					// Выполняем установку второго байта выбранной пары
					second = b;
					/**
					 * Если пара в пробе текста не встречена вовсе
					 */
					if(count == 0)
						// Выходим из перебора пар байтов искомого
						return;
				}
			}
		}
	}
};

/**
 * @brief Метод поиска последовательности в тексте по паре байтов
 *
 * @param text текст сопоставления
 * @param what искомая последовательность
 * @param pos  позиция начала поиска
 * @return     позиция найденной последовательности либо признак отсутствия
 *
 */
/**
 * @brief Функция поиска первого байта из набора в тексте
 *
 * @details Поиск ведётся тремя путями, как и поиск последовательности: вектором
 *          набора NEON, вектором набора SSE2 и словом в восемь байтов там, где
 *          вектора нет. Набор значений размножается по вектору однажды, а затем
 *          всякий оборот сличает шестнадцать байтов текста со всеми значениями
 *          сразу.
 *
 *          Путь словный опирается на приём поиска нулевого байта: вычитание
 *          единиц из слова, где искомое значение обращено в нуль, поднимает
 *          старший разряд байта, значению отвечающего. Приём этот даёт ложные
 *          срабатывания на байтах со старшим разрядом, отчего найденное
 *          сличается со значением заново.
 *
 * @param text  текст сопоставления
 * @param bytes набор искомых значений байта
 * @param count количество искомых значений байта
 * @param pos   позиция начала поиска
 * @return      позиция найденного байта либо размер текста
 *
 */
size_t awh::regex::scattered(const string_view text, const uint8_t * bytes,
 const size_t count, const size_t pos) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Если позиция поиска за пределы текста выходит
	 */
	if((pos >= size) || (count == 0) || (bytes == nullptr))
		// Выводим позицию завершения поиска
		return size;
	/**
	 * Если искомое значение единственно
	 *
	 * @details Поиск единственного значения выполняется средством библиотеки:
	 *          оно отлажено под набор команд машины лучше всякого своего.
	 *
	 */
	if(count == 1) {
		// Выполняем поиск единственного искомого значения байта
		const void * found = ::memchr((text.data() + pos), static_cast <int> (bytes[0]), (size - pos));
		// Выводим позицию найденного байта либо размер текста
		return ((found != nullptr) ? static_cast <size_t> (reinterpret_cast <const char *> (found) - text.data()) : size);
	}
	// Получаем адрес начала текста сопоставления
	const char * base = text.data();
	// Получаем положение поиска очередного участка текста
	size_t at = pos;
	#if defined(AWH_REGEX_NEON)
		/**
		 * Выполняем размножение искомых значений по вектору
		 */
		uint8x16_t wanted[SPARSE];
		/**
		 * Выполняем обход набора искомых значений байта
		 */
		for(size_t i = 0; i < count; i++)
			// Выполняем размножение очередного значения по вектору
			wanted[i] = vdupq_n_u8(bytes[i]);
		/**
		 * Выполняем проход текста сопоставления вектором
		 */
		while((at + 16) <= size) {
			// Выполняем чтение участка текста сопоставления
			const uint8x16_t chunk = vld1q_u8(reinterpret_cast <const uint8_t *> (base + at));
			// Создаём итог сличения участка с набором значений
			uint8x16_t equal = vceqq_u8(chunk, wanted[0]);
			/**
			 * Выполняем обход искомых значений, первого не считая
			 */
			for(size_t i = 1; i < count; i++)
				// Выполняем сложение итога сличения с очередным значением
				equal = vorrq_u8(equal, vceqq_u8(chunk, wanted[i]));
			// Выполняем сведение итога сличения к разрядам слова
			const uint64_t hits = vget_lane_u64(vreinterpret_u64_u8(vshrn_n_u16(vreinterpretq_u16_u8(equal), 4)), 0);
			/**
			 * Если участок текста несёт искомое значение
			 */
			if(hits != 0)
				// Выводим позицию найденного байта
				return (at + (trailing(hits) >> 2));
			// Переходим к следующему участку текста сопоставления
			at += 16;
		}
	#elif defined(AWH_REGEX_SSE2)
		/**
		 * Выполняем размножение искомых значений по вектору
		 */
		__m128i wanted[SPARSE];
		/**
		 * Выполняем обход набора искомых значений байта
		 */
		for(size_t i = 0; i < count; i++)
			// Выполняем размножение очередного значения по вектору
			wanted[i] = _mm_set1_epi8(static_cast <char> (bytes[i]));
		/**
		 * Выполняем проход текста сопоставления вектором
		 */
		while((at + 16) <= size) {
			// Выполняем чтение участка текста сопоставления
			const __m128i chunk = _mm_loadu_si128(reinterpret_cast <const __m128i *> (base + at));
			// Создаём итог сличения участка с набором значений
			__m128i equal = _mm_cmpeq_epi8(chunk, wanted[0]);
			/**
			 * Выполняем обход искомых значений, первого не считая
			 */
			for(size_t i = 1; i < count; i++)
				// Выполняем сложение итога сличения с очередным значением
				equal = _mm_or_si128(equal, _mm_cmpeq_epi8(chunk, wanted[i]));
			// Выполняем сведение итога сличения к разрядам слова
			const uint32_t hits = static_cast <uint32_t> (_mm_movemask_epi8(equal));
			/**
			 * Если участок текста несёт искомое значение
			 */
			if(hits != 0)
				// Выводим позицию найденного байта
				return (at + trailing(static_cast <uint64_t> (hits)));
			// Переходим к следующему участку текста сопоставления
			at += 16;
		}
	#endif
	/**
	 * Выполняем проход остатка текста сопоставления по байту
	 */
	for(; at < size; at++) {
		// Получаем значение байта текста в позиции поиска
		const uint8_t letter = static_cast <uint8_t> (base[at]);
		/**
		 * Выполняем обход набора искомых значений байта
		 */
		for(size_t i = 0; i < count; i++) {
			/**
			 * Если значение байта текста набору принадлежит
			 */
			if(letter == bytes[i])
				// Выводим позицию найденного байта
				return at;
		}
	}
	// Выводим позицию завершения поиска
	return size;
}

size_t awh::regex::anchored(const string_view text, const string_view what, const size_t pos) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	// Получаем размер искомой последовательности
	const size_t length = what.size();
	// Смещение байта искомого, в пробе текста не встреченного
	size_t solo = 0;
	/**
	 * Если байт искомого в пробе текста не встречен вовсе
	 *
	 * @details Поиск по такому байту ведётся средствами библиотеки С и обходит
	 *          поиск по паре в полтора раза: проходят они текст шире вектора.
	 *
	 */
	if(solitary(text, what, pos, solo)) {
		// Получаем адрес позиции поиска выбранного байта
		const char * current = (text.data() + pos + solo);
		// Получаем адрес предела поиска выбранного байта
		const char * bound = (text.data() + (size - length) + 1 + solo);
		/**
		 * Выполняем поиск искомой последовательности по выбранному байту
		 */
		while(current < bound) {
			// Выполняем поиск выбранного байта в тексте сопоставления
			const void * found = ::memchr(current, what[solo], static_cast <size_t> (bound - current));
			/**
			 * Если выбранный байт в тексте отсутствует
			 */
			if(found == nullptr)
				// Выводим признак отсутствия искомой последовательности
				return string_view::npos;
			// Получаем адрес найденного байта
			current = reinterpret_cast <const char *> (found);
			/**
			 * Если искомая последовательность в тексте обнаружена
			 */
			if(::memcmp((current - solo), what.data(), length) == 0)
				// Выводим позицию найденной последовательности
				return static_cast <size_t> ((current - solo) - text.data());
			// Переходим к следующей позиции поиска выбранного байта
			current++;
		}
		// Выводим признак отсутствия искомой последовательности
		return string_view::npos;
	}
	// Смещение первого байта пары в искомой последовательности
	size_t first = 0;
	// Смещение второго байта пары в искомой последовательности
	size_t second = 1;
	// Выполняем выбор пары байтов искомой последовательности
	couple(text, what, pos, first, second);
	// Получаем расстояние между байтами выбранной пары
	const size_t spacing = (second - first);
	// Получаем адрес начала текста сопоставления
	const char * base = text.data();
	// Получаем положение поиска первого байта пары
	size_t at = (pos + first);
	/**
	 * Получаем предел положения поиска первого байта пары
	 *
	 * @details Совпадение начинается в положении поиска за вычетом смещения
	 *          первого байта пары и обязано уместиться в текст целиком.
	 *
	 */
	const size_t limit = ((size - length) + 1 + first);
	/**
	 * Если поиск ведётся набором команд NEON
	 */
	#if defined(AWH_REGEX_NEON)
		// Выполняем размножение первого байта пары по вектору
		const uint8x16_t leading = vdupq_n_u8(static_cast <uint8_t> (what[first]));
		// Выполняем размножение второго байта пары по вектору
		const uint8x16_t trailer = vdupq_n_u8(static_cast <uint8_t> (what[second]));
		/**
		 * Выполняем проход текста сопоставления вектором
		 */
		while((at + 16 + spacing) <= size) {
			// Выполняем чтение участка текста под первый байт пары
			const uint8x16_t heading = vld1q_u8(reinterpret_cast <const uint8_t *> (base + at));
			// Выполняем чтение участка текста под второй байт пары
			const uint8x16_t following = vld1q_u8(reinterpret_cast <const uint8_t *> (base + at + spacing));
			// Выполняем сравнение участков текста с байтами пары
			const uint8x16_t equal = vandq_u8(vceqq_u8(heading, leading), vceqq_u8(following, trailer));
			/**
			 * Выполняем сведение итога сравнения к слову
			 *
			 * @details Набор команд NEON вывода признаков сравнения разрядами
			 *          не имеет, отчего вектор сужается вдвое сдвигом: всякому
			 *          байту вектора отвечает полубайт слова.
			 *
			 */
			uint64_t hits = vget_lane_u64(vreinterpret_u64_u8(vshrn_n_u16(vreinterpretq_u16_u8(equal), 4)), 0);
			/**
			 * Выполняем разбор встреч пары байтов в участке текста
			 */
			while(hits != 0) {
				// Получаем номер байта участка, паре отвечающего
				const size_t lane = (trailing(hits) >> 2);
				// Получаем положение возможного начала совпадения
				const size_t start = ((at + lane) - first);
				/**
				 * Если совпадение в остаток текста не помещается
				 */
				if((at + lane) >= limit)
					// Выводим признак отсутствия искомой последовательности
					return string_view::npos;
				/**
				 * Если искомая последовательность в тексте обнаружена
				 */
				if(::memcmp((base + start), what.data(), length) == 0)
					// Выводим позицию найденной последовательности
					return start;
				// Выполняем снятие разобранной встречи пары байтов
				hits &= ~(static_cast <uint64_t> (0x0F) << (lane << 2));
			}
			// Переходим к следующему участку текста сопоставления
			at += 16;
		}
	/**
	 * Если поиск ведётся набором команд SSE2
	 */
	#elif defined(AWH_REGEX_SSE2)
		// Выполняем размножение первого байта пары по вектору
		const __m128i leading = _mm_set1_epi8(static_cast <char> (what[first]));
		// Выполняем размножение второго байта пары по вектору
		const __m128i trailer = _mm_set1_epi8(static_cast <char> (what[second]));
		/**
		 * Выполняем проход текста сопоставления вектором
		 */
		while((at + 16 + spacing) <= size) {
			// Выполняем чтение участка текста под первый байт пары
			const __m128i heading = _mm_loadu_si128(reinterpret_cast <const __m128i *> (base + at));
			// Выполняем чтение участка текста под второй байт пары
			const __m128i following = _mm_loadu_si128(reinterpret_cast <const __m128i *> (base + at + spacing));
			// Выполняем сравнение участков текста с байтами пары
			const __m128i equal = _mm_and_si128(_mm_cmpeq_epi8(heading, leading), _mm_cmpeq_epi8(following, trailer));
			// Выполняем сведение итога сравнения к разрядам слова
			uint32_t hits = static_cast <uint32_t> (_mm_movemask_epi8(equal));
			/**
			 * Выполняем разбор встреч пары байтов в участке текста
			 */
			while(hits != 0) {
				// Получаем номер байта участка, паре отвечающего
				const size_t lane = trailing(static_cast <uint64_t> (hits));
				// Получаем положение возможного начала совпадения
				const size_t start = ((at + lane) - first);
				/**
				 * Если совпадение в остаток текста не помещается
				 */
				if((at + lane) >= limit)
					// Выводим признак отсутствия искомой последовательности
					return string_view::npos;
				/**
				 * Если искомая последовательность в тексте обнаружена
				 */
				if(::memcmp((base + start), what.data(), length) == 0)
					// Выводим позицию найденной последовательности
					return start;
				// Выполняем снятие разобранной встречи пары байтов
				hits &= (hits - 1);
			}
			// Переходим к следующему участку текста сопоставления
			at += 16;
		}
	/**
	 * Если поиск ведётся словом в восемь байтов
	 */
	#else
		// Выполняем размножение первого байта пары по слову
		const uint64_t leading = (ONES * static_cast <uint8_t> (what[first]));
		// Выполняем размножение второго байта пары по слову
		const uint64_t trailer = (ONES * static_cast <uint8_t> (what[second]));
		/**
		 * Выполняем проход текста сопоставления словом
		 */
		while((at + 8 + spacing) <= size) {
			// Участок текста под первый байт пары
			uint64_t heading = 0;
			// Участок текста под второй байт пары
			uint64_t following = 0;
			// Выполняем чтение участка текста под первый байт пары
			::memcpy(&heading, (base + at), sizeof(heading));
			// Выполняем чтение участка текста под второй байт пары
			::memcpy(&following, (base + at + spacing), sizeof(following));
			// Выполняем обращение совпавших байтов участков в нулевые
			heading ^= leading;
			// Выполняем обращение совпавших байтов участков в нулевые
			following ^= trailer;
			/**
			 * Выполняем поиск нулевых байтов в обоих участках сразу
			 *
			 * @details Приём этот отыскивает нулевой байт слова вычитанием
			 *          единицы из каждого байта: заём в старший разряд
			 *          происходит лишь у байта нулевого.
			 *
			 */
			uint64_t hits = (((heading - ONES) & ~heading) & ((following - ONES) & ~following) & HIGHS);
			/**
			 * Выполняем разбор встреч пары байтов в участке текста
			 */
			while(hits != 0) {
				/**
				 * Получаем номер байта участка, паре отвечающего
				 *
				 * @details Порядок байтов слова у машины свой, отчего младший
				 *          установленный разряд отвечает байту первому лишь
				 *          при порядке от младшего к старшему.
				 *
				 */
				#if defined(__BYTE_ORDER__) && defined(__ORDER_BIG_ENDIAN__) && (__BYTE_ORDER__ == __ORDER_BIG_ENDIAN__)
					// Получаем номер байта участка при порядке от старшего к младшему
					const size_t lane = (7 - (trailing(hits) >> 3));
				#else
					// Получаем номер байта участка при порядке от младшего к старшему
					const size_t lane = (trailing(hits) >> 3);
				#endif
				// Получаем положение возможного начала совпадения
				const size_t start = ((at + lane) - first);
				/**
				 * Если совпадение в остаток текста не помещается
				 */
				if((at + lane) >= limit)
					// Выводим признак отсутствия искомой последовательности
					return string_view::npos;
				/**
				 * Если искомая последовательность в тексте обнаружена
				 */
				if(::memcmp((base + start), what.data(), length) == 0)
					// Выводим позицию найденной последовательности
					return start;
				// Выполняем снятие разобранной встречи пары байтов
				hits &= (hits - 1);
			}
			// Переходим к следующему участку текста сопоставления
			at += 8;
		}
	#endif
	/**
	 * Выводим результат поиска хвоста текста средствами обычными
	 *
	 * @details Хвост короче вектора проходом вектором не покрывается: чтение
	 *          вектора вышло бы за пределы текста. Длина его - меньше двух
	 *          десятков байтов, отчего способ прохода его на скорость не влияет.
	 *
	 */
	return text.find(what, (at - first));
}
