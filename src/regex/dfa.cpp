/**
 * Стандартные заголовочные файлы
 */
#include <algorithm>

/**
 * Подключаем заголовочные файлы проекта
 */
#include <regex/dfa.hpp>

/**
 * Используем стандартное пространство имён
 */
using namespace std;
using namespace awh;

/**
 * @brief Пространство имён вспомогательных значений исполнения
 *
 */
namespace {
	/**
	 * @brief Значение перехода, соответствующее непостроенному состоянию
	 *
	 */
	constexpr uint32_t UNKNOWN = static_cast <uint32_t> (~0u);

	/**
	 * @brief Значение байта, соответствующее концу текста
	 *
	 */
	constexpr uint32_t FINISH = 0x100;

	/**
	 * @brief Признак обнаружения совпадения в значении перехода
	 *
	 */
	constexpr uint32_t MATCHED = 0x80000000;

	/**
	 * @brief Маска индекса состояния в значении перехода
	 *
	 */
	constexpr uint32_t ADDRESS = 0x7FFFFFFF;

	/**
	 * @brief Функция проверки установки режима компиляции
	 *
	 * @param flags набор режимов компиляции регулярного выражения
	 * @param value проверяемый режим компиляции регулярного выражения
	 * @return      результат проверки установки режима компиляции
	 *
	 */
	inline bool hasFlag(const uint32_t flags, const awh::regex::flag_t value) noexcept {
		// Выполняем проверку установки режима компиляции
		return ((flags & static_cast <uint32_t> (value)) != 0);
	}
	/**
	 * @brief Функция проверки принадлежности байта символам слова
	 *
	 * @param letter значение проверяемого байта
	 * @return       результат проверки принадлежности байта символам слова
	 *
	 */
	inline bool isWord(const uint32_t letter) noexcept {
		/**
		 * Если байт является десятичной цифрой либо буквой набора ASCII
		 */
		if(((letter >= 0x30) && (letter <= 0x39)) || ((letter >= 0x41) && (letter <= 0x5A)) || ((letter >= 0x61) && (letter <= 0x7A)))
			// Выводим результат проверки принадлежности байта символам слова
			return true;
		// Выводим результат проверки принадлежности знаку подчёркивания
		return (letter == 0x5F);
	}
	/**
	 * @brief Функция приведения значения байта к нижнему регистру
	 *
	 * @param letter значение приводимого байта
	 * @return       приведённое значение байта
	 *
	 */
	inline uint32_t fold(const uint32_t letter) noexcept {
		/**
		 * Если байт является прописной буквой набора ASCII
		 */
		if((letter >= 0x41) && (letter <= 0x5A))
			// Выводим приведённое значение байта
			return (letter + 0x20);
		// Выводим значение байта без изменений
		return letter;
	}
};

/**
 * @brief Конструктор
 *
 */
awh::regex::Dfa::Dfa() noexcept : _program(nullptr), _identity(0), _start(0), _backward(false) {}
/**
 * @brief Метод сброса кэша состояний автомата
 *
 */
void awh::regex::Dfa::reset() noexcept {
	// Выполняем очистку набора построенных состояний
	this->_states.clear();
	// Выполняем очистку соответствия наборов состояний их индексам
	this->_cache.clear();
}
/**
 * @brief Метод проверки применимости детерминированного исполнения
 *
 * @param program исполняемая программа регулярного выражения
 * @return        результат проверки применимости исполнения
 *
 */
bool awh::regex::Dfa::available(const program_t & program) const noexcept {
	/**
	 * Если программа регулярного выражения пуста
	 */
	if(program.instructions.empty())
		// Выводим результат проверки применимости исполнения
		return false;
	/**
	 * Если установлен режим разбора UTF-8 либо соответствия свойствам Юникода
	 */
	if(hasFlag(program.flags, flag_t::UTF) || hasFlag(program.flags, flag_t::UCP))
		// Выводим результат проверки применимости исполнения
		return false;
	/**
	 * Выполняем проверку отсутствия свойств Юникода в классах символов
	 *
	 * @details Символы, обладающие свойством Юникода, заданы таблицами свойств
	 *          и перечислению байтами перехода не подлежат, поэтому построение
	 *          детерминированного автомата для них неприменимо.
	 *
	 */
	for(auto & value : program.classes) {
		/**
		 * Если класс символов задан свойствами Юникода
		 */
		if(!value.properties.empty())
			// Выводим результат проверки применимости исполнения
			return false;
	}
	// Выводим результат проверки применимости исполнения
	return true;
}
/**
 * @brief Метод проверки привязки к позиции в тексте
 *
 * @param type    тип проверяемой привязки к позиции в тексте
 * @param flags   набор режимов компиляции инструкции
 * @param context набор признаков положения в тексте
 * @param letter  значение следующего байта либо признак конца текста
 * @param last    флаг нахождения следующего байта в конце текста
 * @return        результат проверки привязки к позиции в тексте
 *
 */
bool awh::regex::Dfa::assertion(const anchor_t type, const uint32_t flags, const uint32_t context, const uint32_t letter, const bool last) const noexcept {
	// Определяем достижение края текста, противоположного началу прохода
	const bool opposite = (letter == FINISH);
	// Определяем достижение края текста, с которого начат проход
	const bool origin = ((context & static_cast <uint32_t> (context_t::EDGE)) != 0);
	// Определяем принадлежность пройденного байта символам слова
	const bool passed = ((context & static_cast <uint32_t> (context_t::WORD)) != 0);
	// Определяем принадлежность сопоставляемого байта символам слова
	const bool coming = (!opposite && isWord(letter));
	// Определяем соответствие пройденного байта переводу строки
	const bool crossed = ((context & static_cast <uint32_t> (context_t::NEWLINE)) != 0);
	// Определяем соответствие сопоставляемого байта переводу строки
	const bool arriving = (!opposite && (letter == 0x0A));
	/**
	 * Определяем расположение байтов относительно проверяемого положения
	 *
	 * @details При проходе в прямом направлении пройденный байт расположен слева
	 *          от проверяемого положения, а сопоставляемый — справа. При проходе
	 *          в обратном направлении расположение байтов обратное.
	 *
	 */
	// Принадлежность байта слева от положения символам слова
	const bool before = (this->_backward ? coming : passed);
	// Принадлежность байта справа от положения символам слова
	const bool after = (this->_backward ? passed : coming);
	// Соответствие байта слева от положения переводу строки
	const bool previous = (this->_backward ? arriving : crossed);
	// Соответствие байта справа от положения переводу строки
	const bool following = (this->_backward ? crossed : arriving);
	// Определяем нахождение положения в начале текста
	const bool begin = (this->_backward ? opposite : origin);
	// Определяем нахождение положения в конце текста
	const bool finish = (this->_backward ? origin : opposite);
	/**
	 * Определяем нахождение байта справа от положения в конце текста
	 *
	 * @details Признак требуется привязкам «\\Z» и «$», соответствующим положению
	 *          перед завершающим текст переводом строки.
	 *
	 */
	const bool ending = (this->_backward ? ((context & static_cast <uint32_t> (context_t::LAST)) != 0) : last);
	/**
	 * Определяем тип проверяемой привязки к позиции в тексте
	 */
	switch(static_cast <uint8_t> (type)) {
		// Выполняем проверку привязки к началу текста
		case static_cast <uint8_t> (anchor_t::TEXT_BEGIN): return begin;
		// Выполняем проверку привязки к концу текста
		case static_cast <uint8_t> (anchor_t::TEXT_END): return finish;
		// Выполняем проверку привязки к концу текста с переводом строки
		case static_cast <uint8_t> (anchor_t::TEXT_FINISH): return (finish || (following && ending));
		// Выполняем проверку привязки к началу попытки сопоставления
		case static_cast <uint8_t> (anchor_t::SEARCH_HEAD): return ((context & static_cast <uint32_t> (context_t::ATTEMPT)) != 0);
		// Выполняем проверку привязки к границе слова
		case static_cast <uint8_t> (anchor_t::WORD_EDGE): return (before != after);
		// Выполняем проверку привязки к положению вне границы слова
		case static_cast <uint8_t> (anchor_t::WORD_INNER): return (before == after);
		/**
		 * Выполняем проверку привязки к началу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_BEGIN): {
			/**
			 * Если положение соответствует началу текста
			 */
			if(begin)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			/**
			 * Если режим соответствия привязок границам строк не установлен
			 */
			if(!hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			/**
			 * Если положение находится в конце текста
			 */
			if(finish)
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			// Выводим результат проверки перевода строки слева от положения
			return previous;
		}
		/**
		 * Выполняем проверку привязки к концу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_END): {
			/**
			 * Если режим соответствия привязок границам строк установлен
			 */
			if(hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки положения в конце текста либо строки
				return (finish || following);
			// Выводим результат проверки положения в конце текста
			return (finish || (following && ending));
		}
	}
	// Выводим результат проверки привязки к позиции в тексте
	return false;
}
/**
 * @brief Метод извлечения индекса состояния автомата
 *
 * @param list    набор адресов инструкций состояния
 * @param context набор признаков положения в тексте
 * @return        индекс состояния детерминированного автомата
 *
 */
uint32_t awh::regex::Dfa::state(const vector <address_t> & list, const uint32_t context) noexcept {
	// Формируем ключ состояния детерминированного автомата
	string key(reinterpret_cast <const char *> (&context), sizeof(context));
	/**
	 * Выполняем формирование ключа по набору адресов инструкций
	 */
	for(auto & address : list)
		// Выполняем добавление адреса инструкции в ключ состояния
		key.append(reinterpret_cast <const char *> (&address), sizeof(address));
	// Выполняем поиск состояния в кэше состояний автомата
	auto i = this->_cache.find(key);
	/**
	 * Если состояние обнаружено в кэше состояний автомата
	 */
	if(i != this->_cache.end())
		// Выводим индекс обнаруженного состояния автомата
		return i->second;
	// Получаем индекс создаваемого состояния автомата
	const uint32_t result = static_cast <uint32_t> (this->_states.size());
	// Выполняем создание состояния детерминированного автомата
	this->_states.emplace_back();
	// Выполняем установку набора признаков положения в тексте
	this->_states.back().context = context;
	// Выполняем установку набора адресов инструкций состояния
	this->_states.back().list = list;
	// Выполняем установку флага отсутствия начатых сопоставлений
	this->_states.back().sparse = ((list.size() == 1) && (list.front() == 0));
	// Выполняем размещение набора переходов состояния
	this->_states.back().next.assign((FINISH + 1), UNKNOWN);
	// Выполняем сохранение состояния в кэше состояний автомата
	this->_cache.emplace(std::move(key), result);
	// Выводим индекс созданного состояния автомата
	return result;
}
/**
 * @brief Метод вычисления перехода состояния автомата
 *
 * @param index  индекс исходного состояния автомата
 * @param letter значение сопоставляемого байта либо признак конца текста
 * @param last   флаг сопоставления последнего байта текста
 * @return       индекс достигнутого состояния с признаком совпадения
 *
 */
uint32_t awh::regex::Dfa::transition(const uint32_t index, const uint32_t letter, const bool last) noexcept {
	// Получаем набор признаков положения в тексте исходного состояния
	const uint32_t context = this->_states.at(index).context;
	// Создаём набор отметок посещения инструкций программы
	vector <bool> visited(this->_program->instructions.size(), false);
	// Создаём стек замыкания состояния по инструкциям без сопоставления символов
	vector <address_t> stack;
	// Создаём набор инструкций, сопоставляющих символы
	vector <address_t> matching;
	// Флаг обнаружения совпадения при замыкании состояния
	bool matched = false;
	/**
	 * Выполняем размещение адресов инструкций состояния в стеке замыкания
	 *
	 * @details Адреса размещаются в обратном порядке, благодаря чему обход
	 *          выполняется в порядке их размещения в состоянии.
	 *
	 */
	for(size_t i = this->_states.at(index).list.size(); i > 0; i--)
		// Выполняем размещение очередного адреса инструкции в стеке
		stack.push_back(this->_states.at(index).list.at(i - 1));
	/**
	 * Выполняем замыкание состояния по инструкциям без сопоставления символов
	 */
	while(!stack.empty()) {
		// Получаем адрес инструкции из вершины стека замыкания
		const address_t current = stack.back();
		// Выполняем удаление адреса инструкции из стека замыкания
		stack.pop_back();
		/**
		 * Если адрес инструкции находится за пределами программы
		 */
		if(static_cast <size_t> (current) >= this->_program->instructions.size())
			// Переходим к следующему адресу стека замыкания
			continue;
		/**
		 * Если инструкция уже была посещена
		 */
		if(visited.at(current))
			// Переходим к следующему адресу стека замыкания
			continue;
		// Выполняем отметку посещения инструкции
		visited.at(current) = true;
		// Получаем исполняемую инструкцию программы
		const instruction_t & instruction = this->_program->instructions.at(current);
		/**
		 * Определяем код операции исполняемой инструкции
		 */
		switch(static_cast <uint8_t> (instruction.type)) {
			/**
			 * Выполняем переход по двум ветвям
			 */
			case static_cast <uint8_t> (opcode_t::SPLIT): {
				// Выполняем размещение ветви с наименьшим приоритетом в стеке
				stack.push_back(instruction.split.second);
				// Выполняем размещение ветви с наибольшим приоритетом в стеке
				stack.push_back(instruction.split.first);
			} break;
			// Выполняем безусловный переход
			case static_cast <uint8_t> (opcode_t::JUMP): stack.push_back(instruction.jump.target); break;
			// Выполняем переход к инструкции за сохранением позиции
			case static_cast <uint8_t> (opcode_t::SAVE): stack.push_back(current + 1); break;
			/**
			 * Выполняем проверку привязки к позиции в тексте
			 */
			case static_cast <uint8_t> (opcode_t::ANCHOR): {
				/**
				 * Если привязка к позиции в тексте выполняется
				 */
				if(this->assertion(instruction.assertion.type, instruction.flags, context, letter, last))
					// Выполняем размещение инструкции продолжения в стеке
					stack.push_back(current + 1);
			} break;
			// Выполняем установку флага обнаружения совпадения
			case static_cast <uint8_t> (opcode_t::MATCH): matched = true; break;
			// Выполняем добавление инструкции, сопоставляющей символы
			default: matching.push_back(current);
		}
	}
	/**
	 * Если достигнут конец текста сопоставления
	 */
	if(letter == FINISH)
		// Выводим признак обнаружения совпадения
		return (matched ? MATCHED : 0);
	// Создаём набор адресов инструкций достигаемого состояния
	vector <address_t> list;
	/**
	 * Выполняем сопоставление байта инструкциями состояния
	 */
	for(auto & address : matching) {
		// Получаем инструкцию, сопоставляющую символы
		const instruction_t & instruction = this->_program->instructions.at(address);
		// Флаг сопоставления байта инструкцией
		bool accepted = false;
		/**
		 * Определяем код операции сопоставляющей инструкции
		 */
		switch(static_cast <uint8_t> (instruction.type)) {
			/**
			 * Выполняем сопоставление одиночного символа
			 */
			case static_cast <uint8_t> (opcode_t::CHAR): {
				/**
				 * Если установлен режим сопоставления без учёта регистра
				 */
				if(hasFlag(instruction.flags, flag_t::CASELESS))
					// Выполняем сопоставление байтов без учёта регистра
					accepted = (fold(letter) == fold(instruction.letter.code));
				// Выполняем сопоставление байтов с учётом регистра
				else accepted = (letter == instruction.letter.code);
			} break;
			/**
			 * Выполняем сопоставление символа из класса символов
			 */
			case static_cast <uint8_t> (opcode_t::CLASS): {
				// Получаем класс символов сопоставляемой инструкции
				const class_t & value = this->_program->classes.at(instruction.charclass.index);
				// Флаг принадлежности байта набору диапазонов класса
				bool belongs = false;
				// Создаём набор проверяемых значений байта
				uint32_t codes[2] = {letter, letter};
				/**
				 * Если установлен режим сопоставления без учёта регистра
				 */
				if(hasFlag(instruction.flags, flag_t::CASELESS)) {
					/**
					 * Если байт является строчной буквой набора ASCII
					 */
					if((letter >= 0x61) && (letter <= 0x7A))
						// Выполняем установку значения прописной буквы
						codes[1] = (letter - 0x20);
					/**
					 * Если байт является прописной буквой набора ASCII
					 */
					else if((letter >= 0x41) && (letter <= 0x5A))
						// Выполняем установку значения строчной буквы
						codes[1] = (letter + 0x20);
				}
				/**
				 * Выполняем поиск проверяемых значений в диапазонах класса
				 */
				for(auto & code : codes) {
					/**
					 * Выполняем поиск значения байта в наборе диапазонов класса
					 */
					for(auto & range : value.ranges) {
						/**
						 * Если значение байта принадлежит очередному диапазону класса
						 */
						if((code >= range.begin) && (code <= range.end)) {
							// Выполняем установку флага принадлежности байта
							belongs = true;
							// Выходим из цикла поиска значения байта
							break;
						}
					}
					/**
					 * Если принадлежность байта набору диапазонов подтверждена
					 */
					if(belongs)
						// Выходим из цикла поиска проверяемых значений
						break;
				}
				// Выполняем установку флага сопоставления байта
				accepted = (belongs != value.negative);
			} break;
			/**
			 * Выполняем сопоставление любого символа
			 */
			case static_cast <uint8_t> (opcode_t::ANY): {
				/**
				 * Если установлен режим соответствия точки переводу строки
				 */
				if(hasFlag(instruction.flags, flag_t::DOTALL))
					// Выполняем установку флага сопоставления байта
					accepted = true;
				// Выполняем проверку несоответствия байта переводу строки
				else accepted = (letter != 0x0A);
			} break;
			// Выполняем сопоставление одиночной единицы кодирования
			case static_cast <uint8_t> (opcode_t::CODEUNIT): accepted = true; break;
		}
		/**
		 * Если байт инструкцией не сопоставлен
		 */
		if(!accepted)
			// Переходим к следующей сопоставляющей инструкции
			continue;
		// Выполняем добавление адреса инструкции продолжения
		list.push_back(address + 1);
	}
	/**
	 * Если выражение не привязано к началу попытки сопоставления
	 *
	 * @details Добавление начала выражения в каждое состояние обеспечивает поиск
	 *          совпадения, начинающегося в любой позиции текста.
	 *
	 */
	if(!hasFlag(this->_program->flags, flag_t::ANCHORED))
		// Выполняем добавление начала выражения в достигаемое состояние
		list.push_back(0);
	// Набор признаков положения в тексте достигаемого состояния
	uint32_t next = 0;
	/**
	 * Если сопоставленный байт является символом слова
	 */
	if(isWord(letter))
		// Выполняем установку признака пройденного символа слова
		next |= static_cast <uint32_t> (context_t::WORD);
	/**
	 * Если сопоставленный байт является переводом строки
	 */
	if(letter == 0x0A)
		// Выполняем установку признака пройденного перевода строки
		next |= static_cast <uint32_t> (context_t::NEWLINE);
	/**
	 * Если сопоставленный байт является последним байтом текста
	 *
	 * @details Признак требуется при проходе в обратном направлении: пройденный
	 *          байт расположен справа от достигнутого положения, а привязки
	 *          «\\Z» и «$» проверяют его нахождение в конце текста.
	 */
	if(this->_backward && last)
		// Выполняем установку признака пройденного последнего байта
		next |= static_cast <uint32_t> (context_t::LAST);
	// Выводим индекс достигнутого состояния с признаком обнаружения совпадения
	return (this->state(list, next) | (matched ? MATCHED : 0));
}
/**
 * @brief Метод извлечения признаков положения исходного состояния
 *
 * @param text текст для сопоставления
 * @param from позиция начала прохода по тексту
 * @return     набор признаков положения исходного состояния
 *
 */
uint32_t awh::regex::Dfa::initial(string_view text, const size_t from) const noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	// Набор признаков положения исходного состояния
	uint32_t result = 0;
	/**
	 * Если проход выполняется в обратном направлении
	 */
	if(this->_backward) {
		/**
		 * Если проход начинается с конца текста
		 */
		if(from >= size)
			// Выполняем установку признака края текста
			return static_cast <uint32_t> (context_t::EDGE);
		// Получаем байт, расположенный справа от положения начала прохода
		const uint32_t letter = static_cast <uint32_t> (static_cast <uint8_t> (text.at(from)));
		/**
		 * Если байт справа от положения является символом слова
		 */
		if(isWord(letter))
			// Выполняем установку признака пройденного символа слова
			result |= static_cast <uint32_t> (context_t::WORD);
		/**
		 * Если байт справа от положения является переводом строки
		 */
		if(letter == 0x0A)
			// Выполняем установку признака пройденного перевода строки
			result |= static_cast <uint32_t> (context_t::NEWLINE);
		/**
		 * Если байт справа от положения является последним байтом текста
		 */
		if((from + 1) == size)
			// Выполняем установку признака пройденного последнего байта
			result |= static_cast <uint32_t> (context_t::LAST);
		// Выводим набор признаков положения исходного состояния
		return result;
	}
	// Выполняем установку признака начала попытки сопоставления
	result = static_cast <uint32_t> (context_t::ATTEMPT);
	/**
	 * Если проход начинается с начала текста
	 */
	if(from == 0)
		// Выполняем установку признака края текста
		return (result | static_cast <uint32_t> (context_t::EDGE));
	// Получаем байт, предшествующий позиции начала прохода
	const uint32_t letter = static_cast <uint32_t> (static_cast <uint8_t> (text.at(from - 1)));
	/**
	 * Если предшествующий байт является символом слова
	 */
	if(isWord(letter))
		// Выполняем установку признака пройденного символа слова
		result |= static_cast <uint32_t> (context_t::WORD);
	/**
	 * Если предшествующий байт является переводом строки
	 */
	if(letter == 0x0A)
		// Выполняем установку признака пройденного перевода строки
		result |= static_cast <uint32_t> (context_t::NEWLINE);
	// Выводим набор признаков положения исходного состояния
	return result;
}
/**
 * @brief Метод прохода по тексту с построением состояний автомата
 *
 * @param text   текст для сопоставления
 * @param from   позиция начала прохода по тексту
 * @param result позиция обнаруженного совпадения
 * @return       результат прохода по тексту
 *
 */
bool awh::regex::Dfa::scan(string_view text, const size_t from, size_t & result) noexcept {
	// Выполняем сброс позиции обнаруженного совпадения
	result = string_view::npos;
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Получаем адрес начала текста сопоставления
	 *
	 * @details Обращение к байтам текста выполняется по адресу, минуя проверку
	 *          границ: положение каждого обращения в цикле прохода уже проверено
	 *          краем текста, а проверка границ на каждом байте обошлась бы дороже
	 *          самого перехода состояния.
	 *
	 */
	const char * source = text.data();
	// Получаем позицию начала прохода по тексту
	size_t pos = ((from > size) ? size : from);
	// Создаём набор адресов инструкций исходного состояния
	const vector <address_t> list(1, 0);
	// Получаем индекс исходного состояния автомата
	uint32_t current = this->state(list, this->initial(text, pos));
	// Флаг обнаружения совпадения при проходе по тексту
	bool found = false;
	/**
	 * Получаем направление прохода и предварительный отбор позиций
	 *
	 * @details Направление прохода и отбор позиций при проходе не изменяются,
	 *          поэтому извлекаются однажды: обращение к ним через объект
	 *          на каждом байте текста обошлось бы дороже самого перехода.
	 *
	 */
	const bool backward = this->_backward;
	// Получаем предварительный отбор позиций сопоставления
	const prefilter_t & prefilter = this->_program->prefilter;
	/**
	 * Выполняем обход байтов текста сопоставления
	 */
	while(true) {
		/**
		 * Если из текущего состояния допустим пропуск позиций
		 *
		 * @details Отсутствие начатых сопоставлений позволяет пропустить позиции,
		 *          в которых совпадение начаться не может. Применимость набора
		 *          допустимых начальных байтов означает невозможность совпадения
		 *          нулевой длины, поэтому пропуск позиций совпадений не теряет.
		 *
		 */
		if(!backward && prefilter.active && this->_states[current].sparse) {
			// Выполняем поиск ближайшей позиции возможного начала совпадения
			const size_t candidate = prefilter.search(text, pos);
			/**
			 * Если пропущена хотя бы одна позиция текста
			 */
			if(candidate > pos) {
				// Переходим к позиции возможного начала совпадения
				pos = candidate;
				/**
				 * Если позиция возможного начала совпадения не обнаружена
				 */
				if(pos >= size)
					// Выводим результат прохода по тексту
					return found;
				// Набор признаков положения достигнутой позиции
				uint32_t context = 0;
				// Получаем байт, предшествующий достигнутой позиции
				const uint32_t previous = static_cast <uint32_t> (static_cast <uint8_t> (text.at(pos - 1)));
				/**
				 * Если предшествующий байт является символом слова
				 */
				if(isWord(previous))
					// Выполняем установку признака пройденного символа слова
					context |= static_cast <uint32_t> (context_t::WORD);
				/**
				 * Если предшествующий байт является переводом строки
				 */
				if(previous == 0x0A)
					// Выполняем установку признака пройденного перевода строки
					context |= static_cast <uint32_t> (context_t::NEWLINE);
				// Выполняем переход к состоянию, соответствующему достигнутой позиции
				current = this->state(list, context);
			}
		}
		// Определяем достижение края текста, завершающего проход
		const bool edge = (backward ? (pos == 0) : (pos >= size));
		// Определяем значение сопоставляемого байта
		const uint32_t letter = (edge ? FINISH :
		 static_cast <uint32_t> (static_cast <uint8_t> (source[backward ? (pos - 1) : pos])));
		/**
		 * Определяем сопоставление последнего байта текста
		 *
		 * @details Признак требуется привязкам, проверяющим нахождение байта
		 *          в конце текста, и делает переход зависящим от положения,
		 *          поэтому такой переход не кэшируется.
		 *
		 */
		const bool last = (backward ? (pos == size) : ((pos + 1) == size));
		// Значение перехода состояния автомата
		uint32_t next = UNKNOWN;
		// Определяем допустимость кэширования перехода состояния
		const bool cached = (!last && !edge);
		/**
		 * Если переход состояния подлежит кэшированию
		 *
		 * @details Обращение к набору переходов выполняется без проверки границ:
		 *          набор размещается на всё пространство значений байта, а индекс
		 *          состояния получен размещением состояния в наборе состояний.
		 *          Проверка границ на каждом байте текста обошлась бы дороже
		 *          самого перехода.
		 *
		 */
		if(cached)
			// Получаем сохранённое значение перехода состояния
			next = this->_states[current].next[letter];
		/**
		 * Если значение перехода состояния не определено
		 */
		if(next == UNKNOWN) {
			/**
			 * Если количество состояний автомата превышает допустимое
			 */
			if(this->_states.size() >= MAX_STATES) {
				// Сохраняем набор адресов инструкций текущего состояния
				const vector <address_t> saved = this->_states.at(current).list;
				// Сохраняем набор признаков положения текущего состояния
				const uint32_t context = this->_states.at(current).context;
				// Выполняем сброс кэша состояний автомата
				this->reset();
				// Выполняем восстановление текущего состояния автомата
				current = this->state(saved, context);
			}
			// Выполняем вычисление перехода состояния автомата
			next = this->transition(current, letter, last);
			/**
			 * Если переход состояния подлежит кэшированию
			 */
			if(cached)
				// Выполняем сохранение значения перехода состояния
				this->_states[current].next[letter] = next;
		}
		/**
		 * Если при замыкании состояния обнаружено совпадение
		 */
		if((next & MATCHED) != 0) {
			// Выполняем установку позиции обнаруженного совпадения
			result = pos;
			// Выполняем установку флага обнаружения совпадения
			found = true;
			/**
			 * Если проход выполняется в прямом направлении
			 *
			 * @details При проходе в прямом направлении требуется первое обнаруженное
			 *          завершение совпадения, тогда как при проходе в обратном направлении
			 *          требуется наименьшая позиция начала, поэтому проход продолжается.
			 *
			 */
			if(!backward)
				// Выводим результат прохода по тексту
				return true;
		}
		/**
		 * Если достигнут край текста, завершающий проход
		 */
		if(edge)
			// Выводим результат прохода по тексту
			return found;
		// Переходим к достигнутому состоянию автомата
		current = (next & ADDRESS);
		/**
		 * Если достигнутое состояние автомата пусто
		 *
		 * @details Пустое состояние не содержит ни одной достижимой инструкции,
		 *          поэтому продолжение прохода совпадения не обнаружит. Проход
		 *          в прямом направлении такого состояния не достигает, поскольку
		 *          начало выражения достижимо в любой позиции текста, тогда как
		 *          проход в обратном направлении им завершается, пройдя лишь
		 *          участок текста, занятый совпадением.
		 *
		 */
		if(backward && this->_states[current].list.empty())
			// Выводим результат прохода по тексту
			return found;
		/**
		 * Если проход выполняется в обратном направлении
		 */
		if(backward)
			// Переходим к предшествующему байту текста сопоставления
			pos--;
		// Переходим к следующему байту текста сопоставления
		else pos++;
	}
}
/**
 * @brief Метод поиска позиции завершения совпадения
 *
 * @param program исполняемая программа регулярного выражения
 * @param text    текст для сопоставления
 * @param start   позиция начала поиска совпадения
 * @param finish  позиция завершения обнаруженного совпадения
 * @return        результат поиска совпадения
 *
 */
bool awh::regex::Dfa::search(const program_t & program, string_view text, const size_t start, size_t & finish) noexcept {
	/**
	 * Если исполняется программа либо направление, отличные от исполненных ранее
	 *
	 * @details Состояния автомата определяются программой и направлением прохода,
	 *          поэтому кэш сохраняется между вызовами и сбрасывается лишь при их смене.
	 *
	 */
	if((this->_program != &program) || (this->_identity != program.id) || this->_backward) {
		// Выполняем установку исполняемой программы регулярного выражения
		this->_program = &program;
		// Выполняем установку опознания исполняемой программы
		this->_identity = program.id;
		// Выполняем установку прохода в прямом направлении
		this->_backward = false;
		// Выполняем сброс кэша состояний автомата
		this->reset();
	}
	// Выполняем установку текста сопоставления
	this->_text = text;
	// Выполняем установку позиции начала попытки сопоставления
	this->_start = start;
	// Выполняем сброс позиции завершения совпадения
	finish = string_view::npos;
	/**
	 * Если детерминированное исполнение неприменимо
	 */
	if(!this->available(program))
		// Выводим результат поиска совпадения
		return false;
	// Выводим результат прохода по тексту в прямом направлении
	return this->scan(text, start, finish);
}
/**
 * @brief Метод поиска позиции начала совпадения
 *
 * @param program исполняемая развёрнутая программа регулярного выражения
 * @param text    текст для сопоставления
 * @param from    позиция, с которой начинается проход в обратном направлении
 * @param begin   наименьшая позиция начала совпадения
 * @return        результат поиска позиции начала совпадения
 *
 */
bool awh::regex::Dfa::reverse(const program_t & program, string_view text, const size_t from, size_t & begin) noexcept {
	/**
	 * Если исполняется программа либо направление, отличные от исполненных ранее
	 */
	if((this->_program != &program) || (this->_identity != program.id) || !this->_backward) {
		// Выполняем установку исполняемой программы регулярного выражения
		this->_program = &program;
		// Выполняем установку опознания исполняемой программы
		this->_identity = program.id;
		// Выполняем установку прохода в обратном направлении
		this->_backward = true;
		// Выполняем сброс кэша состояний автомата
		this->reset();
	}
	// Выполняем установку текста сопоставления
	this->_text = text;
	// Выполняем установку позиции начала попытки сопоставления
	this->_start = 0;
	// Выполняем сброс позиции начала совпадения
	begin = string_view::npos;
	/**
	 * Если детерминированное исполнение неприменимо
	 */
	if(!this->available(program))
		// Выводим результат поиска позиции начала совпадения
		return false;
	// Выводим результат прохода по тексту в обратном направлении
	return this->scan(text, from, begin);
}
/**
 * @brief Метод проверки наличия совпадения в тексте
 *
 * @param program исполняемая программа регулярного выражения
 * @param text    текст для сопоставления
 * @param start   позиция начала поиска совпадения
 * @return        результат проверки наличия совпадения
 *
 */
bool awh::regex::Dfa::test(const program_t & program, string_view text, const size_t start) noexcept {
	// Позиция завершения обнаруженного совпадения
	size_t finish = string_view::npos;
	// Выводим результат поиска совпадения в тексте
	return this->search(program, text, start, finish);
}
