using namespace std;
using namespace awh;

/**
 * @brief Функция проверки установки режима компиляции
 *
 * @param flags набор режимов компиляции регулярного выражения
 * @param value проверяемый режим компиляции регулярного выражения
 * @return      результат проверки установки режима компиляции
 *
 */
bool awh::regex::hasFlag(const uint32_t flags, const flag_t value) noexcept {
	// Выполняем проверку установки режима компиляции
	return ((flags & static_cast <uint32_t> (value)) != 0);
}
/**
 * @brief Функция приведения кодового значения символа к нижнему регистру
 *
 * @param code кодовое значение приводимого символа
 * @return     приведённое кодовое значение символа
 *
 */
uint32_t awh::regex::fold(const uint32_t code) noexcept {
	/**
	 * Если символ является прописной буквой набора ASCII
	 */
	if((code >= 0x41) && (code <= 0x5A))
		// Выводим приведённое кодовое значение символа
		return (code + 0x20);
	// Выводим кодовое значение символа без изменений
	return code;
}
/**
 * @brief Функция проверки принадлежности символа символам слова
 *
 * @param code кодовое значение проверяемого символа
 * @return     результат проверки принадлежности символа символам слова
 *
 */
bool awh::regex::isWord(const uint32_t code) noexcept {
	/**
	 * Если символ является десятичной цифрой либо буквой набора ASCII
	 */
	if(((code >= 0x30) && (code <= 0x39)) || ((code >= 0x41) && (code <= 0x5A)) || ((code >= 0x61) && (code <= 0x7A)))
		// Выводим результат проверки принадлежности символа символам слова
		return true;
	// Выводим результат проверки принадлежности знаку подчёркивания
	return (code == 0x5F);
}
/**
 * @brief Функция извлечения кодового значения символа в позиции текста
 *
 * @param text  текст для сопоставления
 * @param pos   позиция символа в тексте
 * @param flags набор режимов компиляции инструкции
 * @param width длина символа в байтах
 * @return      кодовое значение символа в позиции текста
 *
 */
uint32_t awh::regex::decode(string_view text, const size_t pos, const uint32_t flags, size_t & width) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	// Выполняем установку длины символа в байтах
	width = 1;
	/**
	 * Если позиция символа находится за пределами текста
	 */
	if(pos >= size)
		// Выводим отсутствие кодового значения символа
		return 0;
	// Получаем первый байт последовательности
	const uint8_t first = static_cast <uint8_t> (text.at(pos));
	/**
	 * Если режим разбора UTF-8 не установлен либо байт является символом ASCII
	 */
	if(!hasFlag(flags, flag_t::UTF) || (first < 0x80))
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	// Количество продолжающих байтов последовательности
	size_t extra = 0;
	// Кодовое значение разбираемого символа
	uint32_t value = 0;
	/**
	 * Если последовательность состоит из двух байтов
	 */
	if((first & 0xE0) == 0xC0) {
		// Выполняем установку количества продолжающих байтов
		extra = 1;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x1F);
	/**
	 * Если последовательность состоит из трёх байтов
	 */
	} else if((first & 0xF0) == 0xE0) {
		// Выполняем установку количества продолжающих байтов
		extra = 2;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x0F);
	/**
	 * Если последовательность состоит из четырёх байтов
	 */
	} else if((first & 0xF8) == 0xF0) {
		// Выполняем установку количества продолжающих байтов
		extra = 3;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x07);
	// Если первый байт последовательности некорректен
	} else
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	/**
	 * Если последовательность выходит за пределы текста
	 */
	if((pos + extra) >= size)
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	/**
	 * Выполняем разбор продолжающих байтов последовательности
	 */
	for(size_t i = 1; i <= extra; i++) {
		// Получаем очередной продолжающий байт последовательности
		const uint8_t next = static_cast <uint8_t> (text.at(pos + i));
		/**
		 * Если байт не является продолжающим
		 */
		if((next & 0xC0) != 0x80)
			// Выводим кодовое значение одиночного байта
			return static_cast <uint32_t> (first);
		// Выполняем добавление битов кодового значения
		value = ((value << 6) | static_cast <uint32_t> (next & 0x3F));
	}
	// Выполняем установку длины символа в байтах
	width = (extra + 1);
	// Выводим кодовое значение символа в позиции текста
	return value;
}
/**
 * @brief Функция извлечения длины символа, предшествующего позиции текста
 *
 * @param text  текст для сопоставления
 * @param pos   позиция, предшествующий которой символ измеряется
 * @param flags набор режимов компиляции инструкции
 * @return      длина предшествующего позиции символа в байтах
 *
 */
size_t awh::regex::behind(string_view text, const size_t pos, const uint32_t flags) noexcept {
	/**
	 * Если позиция находится в начале текста
	 */
	if(pos == 0)
		// Выводим отсутствие предшествующего символа
		return 0;
	/**
	 * Если режим разбора UTF-8 не установлен
	 */
	if(!hasFlag(flags, flag_t::UTF))
		// Выводим длину одиночного байта
		return 1;
	// Получаем количество байтов, пройденных при отступе
	size_t width = 1;
	/**
	 * Выполняем отступ к началу последовательности UTF-8
	 *
	 * @details Последовательность UTF-8 состоит не более чем из четырёх байтов,
	 *          поэтому отступ ограничен этой длиной. Некорректная последовательность
	 *          разбирается как одиночный байт.
	 *
	 */
	while((width < 4) && (width < pos)) {
		/**
		 * Если байт не является продолжающим
		 */
		if((static_cast <uint8_t> (text.at(pos - width)) & 0xC0) != 0x80)
			// Выходим из цикла отступа к началу последовательности
			break;
		// Увеличиваем количество пройденных байтов
		width++;
	}
	// Длина символа в байтах
	size_t length = 0;
	/**
	 * Если пройденная последовательность является корректной
	 */
	if(decode(text, (pos - width), flags, length) != 0) {
		/**
		 * Если длина последовательности соответствует пройденному отступу
		 */
		if(length == width)
			// Выводим длину предшествующего позиции символа
			return width;
	}
	// Выводим длину одиночного байта
	return 1;
}
/**
 * @brief Функция проверки привязки к позиции в тексте
 *
 * @param text  текст для сопоставления
 * @param start позиция начала попытки сопоставления
 * @param type  тип проверяемой привязки к позиции в тексте
 * @param flags набор режимов компиляции инструкции
 * @param pos   проверяемая позиция в тексте
 * @return      результат проверки привязки к позиции в тексте
 *
 */
bool awh::regex::assertion(string_view text, const size_t start, const anchor_t type, const uint32_t flags, const size_t pos) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Определяем тип проверяемой привязки к позиции в тексте
	 */
	switch(static_cast <uint8_t> (type)) {
		// Выполняем проверку привязки к началу текста
		case static_cast <uint8_t> (anchor_t::TEXT_BEGIN): return (pos == 0);
		// Выполняем проверку привязки к концу текста
		case static_cast <uint8_t> (anchor_t::TEXT_END): return (pos == size);
		// Выполняем проверку привязки к началу попытки сопоставления
		case static_cast <uint8_t> (anchor_t::SEARCH_HEAD): return (pos == start);
		/**
		 * Выполняем проверку привязки к концу текста с переводом строки
		 */
		case static_cast <uint8_t> (anchor_t::TEXT_FINISH): {
			/**
			 * Если позиция находится в конце текста
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			// Выводим результат проверки завершающего перевода строки
			return ((pos == (size - 1)) && (text.at(pos) == '\n'));
		}
		/**
		 * Выполняем проверку привязки к началу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_BEGIN): {
			/**
			 * Если позиция находится в начале текста
			 */
			if(pos == 0)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			/**
			 * Если режим соответствия привязок границам строк не установлен
			 */
			if(!hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			/**
			 * Если позиция находится в конце текста
			 *
			 * @details Привязка к началу строки не соответствует позиции за переводом
			 *          строки, завершающим текст, поскольку новая строка при этом
			 *          не начинается.
			 *
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			// Выводим результат проверки предшествующего перевода строки
			return (text.at(pos - 1) == '\n');
		}
		/**
		 * Выполняем проверку привязки к концу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_END): {
			/**
			 * Если режим соответствия привязок границам строк установлен
			 */
			if(hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки положения в конце текста либо строки
				return ((pos == size) || (text.at(pos) == '\n'));
			/**
			 * Если позиция находится в конце текста
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			// Выводим результат проверки завершающего перевода строки
			return ((pos == (size - 1)) && (text.at(pos) == '\n'));
		}
		// Выполняем проверку привязки к границе слова
		case static_cast <uint8_t> (anchor_t::WORD_EDGE):
		/**
		 * Выполняем проверку привязки к положению вне границы слова
		 */
		case static_cast <uint8_t> (anchor_t::WORD_INNER): {
			// Флаг принадлежности предшествующего символа символам слова
			bool before = false;
			// Флаг принадлежности последующего символа символам слова
			bool after = false;
			/**
			 * Если позиция не находится в начале текста
			 */
			if(pos > 0)
				// Выполняем проверку принадлежности предшествующего символа
				before = isWord(static_cast <uint32_t> (static_cast <uint8_t> (text.at(pos - 1))));
			/**
			 * Если позиция не находится в конце текста
			 */
			if(pos < size)
				// Выполняем проверку принадлежности последующего символа
				after = isWord(static_cast <uint32_t> (static_cast <uint8_t> (text.at(pos))));
			/**
			 * Если проверяется привязка к границе слова
			 */
			if(type == anchor_t::WORD_EDGE)
				// Выводим результат проверки привязки к границе слова
				return (before != after);
			// Выводим результат проверки привязки вне границы слова
			return (before == after);
		}
	}
	// Выводим результат проверки привязки к позиции в тексте
	return false;
}
/**
 * @brief Функция проверки принадлежности символа классу символов
 *
 * @param value класс символов регулярного выражения
 * @param code  кодовое значение проверяемого символа
 * @param flags набор режимов компиляции инструкции
 * @return      результат проверки принадлежности символа классу
 *
 */
bool awh::regex::belongs(const class_t & value, const uint32_t code, const uint32_t flags) noexcept {
	// Флаг принадлежности символа набору диапазонов класса
	bool result = false;
	/**
	 * Выполняем поиск символа в наборе диапазонов класса
	 */
	for(auto & range : value.ranges) {
		/**
		 * Если символ принадлежит очередному диапазону класса
		 */
		if((code >= range.begin) && (code <= range.end)) {
			// Выполняем установку флага принадлежности символа
			result = true;
			// Выходим из цикла поиска символа
			break;
		}
	}
	/**
	 * Если символ набору диапазонов не принадлежит и установлен режим без учёта регистра
	 */
	if(!result && hasFlag(flags, flag_t::CASELESS)) {
		// Получаем кодовое значение символа в ином регистре
		const uint32_t other = ((fold(code) == code) ? (((code >= 0x61) && (code <= 0x7A)) ? (code - 0x20) : code) : fold(code));
		/**
		 * Если кодовое значение символа в ином регистре отличается
		 */
		if(other != code) {
			/**
			 * Выполняем поиск символа иного регистра в наборе диапазонов класса
			 */
			for(auto & range : value.ranges) {
				/**
				 * Если символ принадлежит очередному диапазону класса
				 */
				if((other >= range.begin) && (other <= range.end)) {
					// Выполняем установку флага принадлежности символа
					result = true;
					// Выходим из цикла поиска символа
					break;
				}
			}
		}
	}
	/**
	 * Если класс символов задан со знаком отрицания
	 */
	if(value.negative)
		// Выводим результат проверки принадлежности символа классу
		return !result;
	// Выводим результат проверки принадлежности символа классу
	return result;
}
