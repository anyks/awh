/**
 * @brief Функция приведения кодового значения символа к нижнему регистру
 *
 * @param code кодовое значение приводимого символа
 * @return     приведённое кодовое значение символа
 *
 */
uint32_t awh::regex::fold(const uint32_t code) noexcept {
	/**
	 * Если символ является прописной буквой набора ASCII
	 */
	if((code >= 0x41) && (code <= 0x5A))
		// Выводим приведённое кодовое значение символа
		return (code + 0x20);
	// Выводим кодовое значение символа без изменений
	return code;
}
/**
 * @brief Функция приведения кодового значения символа к нижнему регистру
 *
 * @param code  кодовое значение приводимого символа
 * @param flags набор режимов компиляции инструкции
 * @return      приведённое кодовое значение символа
 *
 */
uint32_t awh::regex::fold(const uint32_t code, const uint32_t flags) noexcept {
	/**
	 * Если приведение регистра выполняется по таблицам стандарта Юникода
	 *
	 * @details Приведение регистра за пределами набора ASCII требует таблиц
	 *          свойств Юникода, поэтому режим разбора текста как последовательности
	 *          UTF-8 включает его наравне с режимом учёта свойств Юникода.
	 *
	 */
	if(hasFlag(flags, flag_t::UTF) || hasFlag(flags, flag_t::UCP))
		// Выводим приведённое по таблицам стандарта Юникода значение символа
		return unicode::casefold(code);
	// Выводим приведённое значение символа набора ASCII
	return fold(code);
}
/**
 * @brief Функция проверки принадлежности символа символам слова
 *
 * @param code кодовое значение проверяемого символа
 * @return     результат проверки принадлежности символа символам слова
 *
 */
bool awh::regex::isWord(const uint32_t code) noexcept {
	/**
	 * Если символ является десятичной цифрой либо буквой набора ASCII
	 */
	if(((code >= 0x30) && (code <= 0x39)) || ((code >= 0x41) && (code <= 0x5A)) || ((code >= 0x61) && (code <= 0x7A)))
		// Выводим результат проверки принадлежности символа символам слова
		return true;
	// Выводим результат проверки принадлежности знаку подчёркивания
	return (code == 0x5F);
}
/**
 * @brief Функция извлечения кодового значения символа в позиции текста
 *
 * @param text  текст для сопоставления
 * @param pos   позиция символа в тексте
 * @param flags набор режимов компиляции инструкции
 * @param width длина символа в байтах
 * @return      кодовое значение символа в позиции текста
 *
 */
uint32_t awh::regex::decode(string_view text, const size_t pos, const uint32_t flags, size_t & width) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	// Выполняем установку длины символа в байтах
	width = 1;
	/**
	 * Если позиция символа находится за пределами текста
	 */
	if(pos >= size)
		// Выводим отсутствие кодового значения символа
		return 0;
	// Получаем первый байт последовательности
	const uint8_t first = static_cast <uint8_t> (text.at(pos));
	/**
	 * Если режим разбора UTF-8 не установлен либо байт является символом ASCII
	 */
	if(!hasFlag(flags, flag_t::UTF) || (first < 0x80))
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	// Количество продолжающих байтов последовательности
	size_t extra = 0;
	// Кодовое значение разбираемого символа
	uint32_t value = 0;
	/**
	 * Если последовательность состоит из двух байтов
	 */
	if((first & 0xE0) == 0xC0) {
		// Выполняем установку количества продолжающих байтов
		extra = 1;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x1F);
	/**
	 * Если последовательность состоит из трёх байтов
	 */
	} else if((first & 0xF0) == 0xE0) {
		// Выполняем установку количества продолжающих байтов
		extra = 2;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x0F);
	/**
	 * Если последовательность состоит из четырёх байтов
	 */
	} else if((first & 0xF8) == 0xF0) {
		// Выполняем установку количества продолжающих байтов
		extra = 3;
		// Выполняем установку старших битов кодового значения
		value = static_cast <uint32_t> (first & 0x07);
	// Если первый байт последовательности некорректен
	} else
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	/**
	 * Если последовательность выходит за пределы текста
	 */
	if((pos + extra) >= size)
		// Выводим кодовое значение одиночного байта
		return static_cast <uint32_t> (first);
	/**
	 * Выполняем разбор продолжающих байтов последовательности
	 */
	for(size_t i = 1; i <= extra; i++) {
		// Получаем очередной продолжающий байт последовательности
		const uint8_t next = static_cast <uint8_t> (text.at(pos + i));
		/**
		 * Если байт не является продолжающим
		 */
		if((next & 0xC0) != 0x80)
			// Выводим кодовое значение одиночного байта
			return static_cast <uint32_t> (first);
		// Выполняем добавление битов кодового значения
		value = ((value << 6) | static_cast <uint32_t> (next & 0x3F));
	}
	// Выполняем установку длины символа в байтах
	width = (extra + 1);
	// Выводим кодовое значение символа в позиции текста
	return value;
}
/**
 * @brief Функция извлечения длины символа, предшествующего позиции текста
 *
 * @param text  текст для сопоставления
 * @param pos   позиция, предшествующий которой символ измеряется
 * @param flags набор режимов компиляции инструкции
 * @return      длина предшествующего позиции символа в байтах
 *
 */
size_t awh::regex::behind(string_view text, const size_t pos, const uint32_t flags) noexcept {
	/**
	 * Если позиция находится в начале текста
	 */
	if(pos == 0)
		// Выводим отсутствие предшествующего символа
		return 0;
	/**
	 * Если режим разбора UTF-8 не установлен
	 */
	if(!hasFlag(flags, flag_t::UTF))
		// Выводим длину одиночного байта
		return 1;
	// Получаем количество байтов, пройденных при отступе
	size_t width = 1;
	/**
	 * Выполняем отступ к началу последовательности UTF-8
	 *
	 * @details Последовательность UTF-8 состоит не более чем из четырёх байтов,
	 *          поэтому отступ ограничен этой длиной. Некорректная последовательность
	 *          разбирается как одиночный байт.
	 *
	 */
	while((width < 4) && (width < pos)) {
		/**
		 * Если байт не является продолжающим
		 */
		if((static_cast <uint8_t> (text.at(pos - width)) & 0xC0) != 0x80)
			// Выходим из цикла отступа к началу последовательности
			break;
		// Увеличиваем количество пройденных байтов
		width++;
	}
	// Длина символа в байтах
	size_t length = 0;
	/**
	 * Если пройденная последовательность является корректной
	 */
	if(decode(text, (pos - width), flags, length) != 0) {
		/**
		 * Если длина последовательности соответствует пройденному отступу
		 */
		if(length == width)
			// Выводим длину предшествующего позиции символа
			return width;
	}
	// Выводим длину одиночного байта
	return 1;
}
/**
 * @brief Пространство имён вспомогательных функций операций над текстом
 *
 */
namespace {
	/**
	 * @brief Функция проверки принадлежности символа символам слова
	 *
	 * @details Режим «UCP» заменяет набор символов слова ASCII соответствующим
	 *          свойством Юникода, поэтому принадлежность определяется по нему.
	 *
	 * @param code  кодовое значение проверяемого символа
	 * @param flags набор режимов компиляции инструкции
	 * @return      результат проверки принадлежности символа символам слова
	 *
	 */
	inline bool word(const uint32_t code, const uint32_t flags) noexcept {
		/**
		 * Если установлен режим соответствия сокращённых классов свойствам Юникода
		 */
		if(awh::regex::hasFlag(flags, awh::regex::flag_t::UCP))
			// Выводим результат проверки обладания символом свойством символов слова
			return awh::unicode::holds(code, static_cast <uint16_t> (awh::regex::property_id_t::UCP_WORD));
		// Выводим результат проверки принадлежности символа символам слова
		return awh::regex::isWord(code);
	}
};

/**
 * @brief Функция проверки привязки к позиции в тексте
 *
 * @param text  текст для сопоставления
 * @param start позиция начала попытки сопоставления
 * @param type  тип проверяемой привязки к позиции в тексте
 * @param flags набор режимов компиляции инструкции
 * @param pos   проверяемая позиция в тексте
 * @return      результат проверки привязки к позиции в тексте
 *
 */
/**
 * @brief Функция определения длины завершения строки в позиции текста
 *
 * @details Длина выводится нулевая там, где завершения строки нет вовсе.
 *          Пара возврата каретки с переводом строки почитается завершением
 *          единым: позиция между ними ни концом строки, ни началом её
 *          не является - правило это снято с эталонной реализации опытом.
 *
 * @param text       текст сопоставления
 * @param pos        проверяемая позиция в тексте
 * @param convention соглашение о переводе строки выражения
 * @return           длина завершения строки в знаках либо нуль
 *
 */
static size_t terminator(const string_view text, const size_t pos, const awh::regex::newline_t convention) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Если позиция находится за пределами текста
	 */
	if(pos >= size)
		// Выводим отсутствие завершения строки
		return 0;
	// Получаем октет текста в проверяемой позиции
	const uint8_t letter = static_cast <uint8_t> (text.at(pos));
	// Признак наличия перевода строки за возвратом каретки
	const bool paired = ((letter == 0x0D) && ((pos + 1) < size) && (static_cast <uint8_t> (text.at(pos + 1)) == 0x0A));
	/**
	 * Определяем соглашение о переводе строки выражения
	 */
	switch(static_cast <uint8_t> (convention)) {
		// Выводим длину завершения строки соглашения перевода строки
		case static_cast <uint8_t> (awh::regex::newline_t::LF): return ((letter == 0x0A) ? 1 : 0);
		// Выводим длину завершения строки соглашения возврата каретки
		case static_cast <uint8_t> (awh::regex::newline_t::CR): return ((letter == 0x0D) ? 1 : 0);
		// Выводим длину завершения строки соглашения нулевого знака
		case static_cast <uint8_t> (awh::regex::newline_t::NUL): return ((letter == 0x00) ? 1 : 0);
		// Выводим длину завершения строки соглашения пары возврата каретки
		case static_cast <uint8_t> (awh::regex::newline_t::CRLF): return (paired ? 2 : 0);
		/**
		 * Выводим длину завершения строки соглашения возврата каретки либо перевода
		 */
		case static_cast <uint8_t> (awh::regex::newline_t::ANYCRLF):
			return (paired ? 2 : (((letter == 0x0D) || (letter == 0x0A)) ? 1 : 0));
		/**
		 * Выводим длину завершения строки соглашения всякого перевода Юникода
		 */
		case static_cast <uint8_t> (awh::regex::newline_t::ANY): {
			/**
			 * Если завершением строки выступает пара возврата каретки
			 */
			if(paired)
				// Выводим длину пары возврата каретки с переводом строки
				return 2;
			/**
			 * Если завершением строки выступает знак таблицы ASCII
			 */
			if((letter == 0x0A) || (letter == 0x0B) || (letter == 0x0C) || (letter == 0x0D))
				// Выводим длину завершения строки одиночного
				return 1;
			/**
			 * Если завершением строки выступает следующая строка
			 */
			if((letter == 0xC2) && ((pos + 1) < size) && (static_cast <uint8_t> (text.at(pos + 1)) == 0x85))
				// Выводим длину записи следующей строки
				return 2;
			/**
			 * Если завершением строки выступает разделитель строк либо абзацев
			 */
			if((letter == 0xE2) && ((pos + 2) < size) && (static_cast <uint8_t> (text.at(pos + 1)) == 0x80) &&
			   ((static_cast <uint8_t> (text.at(pos + 2)) == 0xA8) || (static_cast <uint8_t> (text.at(pos + 2)) == 0xA9)))
				// Выводим длину записи разделителя строк либо абзацев
				return 3;
		} break;
	}
	// Выводим отсутствие завершения строки
	return 0;
}
/**
 * @brief Функция проверки завершения строки, оканчивающегося в позиции текста
 *
 * @param text       текст сопоставления
 * @param pos        проверяемая позиция в тексте
 * @param convention соглашение о переводе строки выражения
 * @return           результат проверки завершения строки
 *
 */
static bool terminated(const string_view text, const size_t pos, const awh::regex::newline_t convention) noexcept {
	/**
	 * Если позиция находится в начале текста
	 */
	if(pos == 0)
		// Выводим результат проверки завершения строки
		return false;
	/**
	 * Выполняем обход длин завершения строки, в позиции оканчивающихся
	 *
	 * @details Завершение строки берёт от одного знака до трёх, и всякая длина
	 *          проверяется отступом назад: длина, дающая завершение с концом
	 *          в проверяемой позиции, его и подтверждает. Так позиция между
	 *          возвратом каретки и переводом строки началом строки не выходит:
	 *          завершение, в ней оканчивающееся, есть возврат каретки одиночный,
	 *          а он при паре завершением не является.
	 *
	 */
	for(size_t length = 1; (length <= 3) && (length <= pos); length++) {
		/**
		 * Если завершение строки оканчивается в проверяемой позиции
		 */
		if(terminator(text, (pos - length), convention) == length)
			// Выводим результат проверки завершения строки
			return true;
	}
	// Выводим результат проверки завершения строки
	return false;
}
/**
 * @brief Функция проверки привязки к позиции в тексте
 *
 * @param text       текст для сопоставления
 * @param start      позиция начала попытки сопоставления
 * @param type       тип проверяемой привязки к позиции в тексте
 * @param flags      набор режимов компиляции инструкции
 * @param pos        проверяемая позиция в тексте
 * @param convention соглашение о переводе строки выражения
 * @return           результат проверки привязки к позиции в тексте
 *
 */
bool awh::regex::assertion(string_view text, const size_t start, const anchor_t type, const uint32_t flags, const size_t pos, const newline_t convention) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Если проверяемая позиция выходит за пределы текста
	 *
	 * @details Отказ выносится до разбора вида привязки намеренно. Часть ветвей
	 *          обращается к тексту напрямую (проверка перевода строки), а часть -
	 *          разбором символа с отступом назад, и при позиции за размером текста
	 *          первые бросили бы исключение из функции, объявленной noexcept, тогда
	 *          как вторые молча ответили бы отказом. Единая проверка сводит оба
	 *          пути к отказу: позиции за пределами текста привязке не отвечают
	 *          ни при каком её виде.
	 *
	 */
	if(pos > size)
		// Выводим результат проверки привязки к позиции в тексте
		return false;
	/**
	 * Определяем тип проверяемой привязки к позиции в тексте
	 */
	switch(static_cast <uint8_t> (type)) {
		// Выполняем проверку привязки к началу текста
		case static_cast <uint8_t> (anchor_t::TEXT_BEGIN): return (pos == 0);
		// Выполняем проверку привязки к концу текста
		case static_cast <uint8_t> (anchor_t::TEXT_END): return (pos == size);
		// Выполняем проверку привязки к началу попытки сопоставления
		case static_cast <uint8_t> (anchor_t::SEARCH_HEAD): return (pos == start);
		/**
		 * Выполняем проверку привязки к концу текста с переводом строки
		 */
		case static_cast <uint8_t> (anchor_t::TEXT_FINISH): {
			/**
			 * Если позиция находится в конце текста
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			// Получаем длину завершения строки в проверяемой позиции
			const size_t length = terminator(text, pos, convention);
			// Выводим результат проверки завершающего перевода строки
			return ((length > 0) && ((pos + length) == size));
		}
		/**
		 * Выполняем проверку привязки к началу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_BEGIN): {
			/**
			 * Если позиция находится в начале текста
			 */
			if(pos == 0)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			/**
			 * Если режим соответствия привязок границам строк не установлен
			 */
			if(!hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			/**
			 * Если позиция находится в конце текста
			 *
			 * @details Привязка к началу строки не соответствует позиции за переводом
			 *          строки, завершающим текст, поскольку новая строка при этом
			 *          не начинается.
			 *
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			// Выводим результат проверки предшествующего завершения строки
			return terminated(text, pos, convention);
		}
		/**
		 * Выполняем проверку привязки к концу текста либо строки
		 */
		case static_cast <uint8_t> (anchor_t::LINE_END): {
			/**
			 * Если режим соответствия привязок границам строк установлен
			 */
			if(hasFlag(flags, flag_t::MULTILINE))
				// Выводим результат проверки положения в конце текста либо строки
				return ((pos == size) || (terminator(text, pos, convention) > 0));
			/**
			 * Если позиция находится в конце текста
			 */
			if(pos == size)
				// Выводим результат проверки привязки к позиции в тексте
				return true;
			/**
			 * Если привязке отведён один лишь конец текста
			 *
			 * @details Признак этот отменяет соответствие привязки переводу
			 *          строки завершающему, а при режиме соответствия привязок
			 *          границам строк не действует вовсе - как и у эталона PCRE2.
			 *
			 */
			if(hasFlag(flags, flag_t::DOLLAR_END))
				// Выводим результат проверки привязки к позиции в тексте
				return false;
			// Получаем длину завершения строки в проверяемой позиции
			const size_t length = terminator(text, pos, convention);
			// Выводим результат проверки завершающего перевода строки
			return ((length > 0) && ((pos + length) == size));
		}
		// Выполняем проверку привязки к границе слова
		case static_cast <uint8_t> (anchor_t::WORD_EDGE):
		/**
		 * Выполняем проверку привязки к положению вне границы слова
		 */
		case static_cast <uint8_t> (anchor_t::WORD_INNER): {
			// Флаг принадлежности предшествующего символа символам слова
			bool before = false;
			// Флаг принадлежности последующего символа символам слова
			bool after = false;
			// Длина разбираемого символа в байтах
			size_t width = 0;
			/**
			 * Если позиция не находится в начале текста
			 *
			 * @details Символ, предшествующий позиции, отыскивается отступом на его длину,
			 *          поскольку в режиме разбора UTF-8 он занимает несколько байтов,
			 *          и проверка предшествующего байта дала бы неверный результат.
			 *
			 */
			if(pos > 0)
				// Выполняем проверку принадлежности предшествующего символа
				before = word(decode(text, (pos - behind(text, pos, flags)), flags, width), flags);
			/**
			 * Если позиция не находится в конце текста
			 */
			if(pos < size)
				// Выполняем проверку принадлежности последующего символа
				after = word(decode(text, pos, flags, width), flags);
			/**
			 * Если проверяется привязка к границе слова
			 */
			if(type == anchor_t::WORD_EDGE)
				// Выводим результат проверки привязки к границе слова
				return (before != after);
			// Выводим результат проверки привязки вне границы слова
			return (before == after);
		}
	}
	// Выводим результат проверки привязки к позиции в тексте
	return false;
}
/**
 * @brief Функция проверки принадлежности символа классу символов
 *
 * @param value класс символов регулярного выражения
 * @param code  кодовое значение проверяемого символа
 * @param flags набор режимов компиляции инструкции
 * @return      результат проверки принадлежности символа классу
 *
 */
bool awh::regex::belongs(const classview_t & value, const uint32_t code, const uint32_t flags) noexcept {
	/**
	 * @brief Функция проверки принадлежности кодового значения классу
	 *
	 * @details Проверка ведётся и по диапазонам, и по свойствам Юникода:
	 *          режим без учёта регистра применяется к тем и другим наравне.
	 *          Прежде свойства сличались с одним лишь значением проверяемым,
	 *          отчего «\\p{Lu}» без учёта регистра строчной букве не отвечал,
	 *          тогда как эталон PCRE2 ей отвечает.
	 *
	 * @param value класс символов регулярного выражения
	 * @param code  проверяемое кодовое значение символа
	 * @return      результат проверки принадлежности кодового значения
	 *
	 */
	// Получаем признак сопоставления без учёта регистра символов
	const bool caseless = hasFlag(flags, flag_t::CASELESS);
	auto holding = [&value, caseless](const uint32_t code) noexcept -> bool {
		/**
		 * Выполняем поиск кодового значения в наборе диапазонов класса
		 */
		for(auto & range : value.ranges) {
			/**
			 * Если кодовое значение принадлежит очередному диапазону класса
			 */
			if((code >= range.begin) && (code <= range.end))
				// Выводим результат проверки принадлежности кодового значения
				return true;
		}
		/**
		 * Выполняем проверку обладания кодовым значением свойствами Юникода
		 */
		for(auto & property : value.properties) {
			// Получаем обозначение проверяемого свойства Юникода
			uint16_t id = property.id;
			/**
			 * Если сопоставление ведётся без учёта регистра символов
			 *
			 * @details Разряды букв прописных, строчных и с заглавной первой
			 *          частью без учёта регистра взаимозаменяемы: эталон PCRE2
			 *          подменяет всякий из них разрядом букв, регистр меняющих.
			 *          Свёртка сама тут негодна: буква «ﬁ» разряда строчного
			 *          прописной пары не имеет вовсе, а разряду прописному
			 *          без учёта регистра всё же отвечает.
			 *
			 */
			if(caseless && ((id == static_cast <uint16_t> (unicode::property_id_t::Lu)) ||
			 (id == static_cast <uint16_t> (unicode::property_id_t::Ll)) ||
			 (id == static_cast <uint16_t> (unicode::property_id_t::Lt))))
				// Выполняем подмену разряда разрядом букв, регистр меняющих
				id = static_cast <uint16_t> (unicode::property_id_t::L_AMP);
			/**
			 * Если обладание свойством соответствует знаку свойства
			 */
			if(unicode::holds(code, id) != (property.negative != 0))
				// Выводим результат проверки принадлежности кодового значения
				return true;
		}
		// Выводим результат проверки принадлежности кодового значения
		return false;
	};
	// Выполняем проверку принадлежности символа классу
	bool result = holding(code);
	/**
	 * Если символ классу не принадлежит и установлен режим без учёта регистра
	 */
	if(!result && hasFlag(flags, flag_t::CASELESS)) {
		// Создаём набор символов, приводимых к одному значению
		vector <uint32_t> members;
		/**
		 * Если приведение регистра выполняется по таблицам Юникода
		 */
		if(hasFlag(flags, flag_t::UTF) || hasFlag(flags, flag_t::UCP)) {
			/**
			 * Если символ образует набор приведения регистра
			 */
			if(!unicode::variants(code, members))
				// Выполняем размещение проверяемого символа в наборе
				members.assign(1, code);
		/**
		 * Выполняем размещение символа в ином регистре набора ASCII
		 */
		} else {
			// Получаем кодовое значение символа в ином регистре
			const uint32_t other = ((fold(code) == code) ? (((code >= 0x61) && (code <= 0x7A)) ? (code - 0x20) : code) : fold(code));
			// Выполняем размещение символа иного регистра в наборе
			members.assign(1, other);
		}
		/**
		 * Выполняем поиск символов иного регистра в классе символов
		 */
		for(auto & member : members) {
			/**
			 * Если символ иного регистра совпадает с проверяемым
			 */
			if(member == code)
				// Переходим к следующему символу набора
				continue;
			/**
			 * Если символ иного регистра классу принадлежит
			 */
			if(holding(member)) {
				// Выполняем установку флага принадлежности символа
				result = true;
				// Выходим из цикла обхода символов набора
				break;
			}
		}
	}
	/**
	 * Если класс символов задан со знаком отрицания
	 */
	if(value.negative)
		// Выводим результат проверки принадлежности символа классу
		return !result;
	// Выводим результат проверки принадлежности символа классу
	return result;
}
/**
 * @brief Функция извлечения длины графемного кластера в позиции текста
 *
 * @param text  текст для сопоставления
 * @param pos   позиция начала графемного кластера в тексте
 * @param flags набор режимов компиляции инструкции
 * @return      длина графемного кластера в байтах
 *
 */
size_t awh::regex::grapheme(string_view text, const size_t pos, const uint32_t flags) noexcept {
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	/**
	 * Если позиция находится за пределами текста
	 */
	if(pos >= size)
		// Выводим отсутствие графемного кластера
		return 0;
	// Длина разбираемого символа в байтах
	size_t width = 0;
	// Получаем класс разбиения первого символа кластера
	unicode::cluster_t before = unicode::cluster(decode(text, pos, flags, width));
	// Получаем положение первого символа в сочетании индийских письменностей
	unicode::indic_t position = unicode::indic(decode(text, pos, flags, width));
	// Получаем позицию за первым символом кластера
	size_t current = (pos + width);
	// Количество подряд идущих указателей области
	size_t regional = ((before == unicode::cluster_t::REGIONAL) ? 1 : 0);
	// Флаг обнаружения изобразительного символа с продолжающими символами
	bool pictorial = (before == unicode::cluster_t::PICTORIAL);
	// Флаг обнаружения соединителя за изобразительным символом
	bool joined = false;
	// Флаг обнаружения согласного символа сочетания индийских письменностей
	bool consonant = (position == unicode::indic_t::CONSONANT);
	// Флаг обнаружения соединяющего символа сочетания индийских письменностей
	bool linked = false;
	/**
	 * Выполняем присоединение символов к графемному кластеру
	 */
	while(current < size) {
		// Получаем кодовое значение очередного символа текста
		const uint32_t code = decode(text, current, flags, width);
		// Получаем класс разбиения очередного символа
		const unicode::cluster_t after = unicode::cluster(code);
		// Получаем положение очередного символа в сочетании индийских письменностей
		const unicode::indic_t following = unicode::indic(code);
		// Флаг разрыва графемного кластера перед очередным символом
		bool broken = true;
		/**
		 * Если возврат каретки предшествует переводу строки
		 */
		if((before == unicode::cluster_t::CARRIAGE) && (after == unicode::cluster_t::LINEFEED))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если один из символов является управляющим
		 */
		else if((before == unicode::cluster_t::CONTROL) || (before == unicode::cluster_t::CARRIAGE) || (before == unicode::cluster_t::LINEFEED) ||
		 (after == unicode::cluster_t::CONTROL) || (after == unicode::cluster_t::CARRIAGE) || (after == unicode::cluster_t::LINEFEED))
			// Выполняем установку флага разрыва графемного кластера
			broken = true;
		/**
		 * Если начальная часть слога хангыля предшествует его продолжению
		 */
		else if((before == unicode::cluster_t::HANGUL_L) && ((after == unicode::cluster_t::HANGUL_L) || (after == unicode::cluster_t::HANGUL_V) ||
		 (after == unicode::cluster_t::HANGUL_LV) || (after == unicode::cluster_t::HANGUL_LVT)))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если гласная часть слога хангыля предшествует его продолжению
		 */
		else if(((before == unicode::cluster_t::HANGUL_LV) || (before == unicode::cluster_t::HANGUL_V)) &&
		 ((after == unicode::cluster_t::HANGUL_V) || (after == unicode::cluster_t::HANGUL_T)))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если конечная часть слога хангыля предшествует его продолжению
		 */
		else if(((before == unicode::cluster_t::HANGUL_LVT) || (before == unicode::cluster_t::HANGUL_T)) && (after == unicode::cluster_t::HANGUL_T))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если очередной символ является продолжающим, соединителем либо отступающим знаком
		 */
		else if((after == unicode::cluster_t::EXTEND) || (after == unicode::cluster_t::JOINER) || (after == unicode::cluster_t::SPACING))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если предшествующий символ является предшествующим знаком
		 */
		else if(before == unicode::cluster_t::PREPEND)
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если согласные символы сочетания индийских письменностей соединены
		 */
		else if(consonant && linked && (following == unicode::indic_t::CONSONANT))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если изобразительные символы соединены соединителем нулевой ширины
		 */
		else if(joined && (after == unicode::cluster_t::PICTORIAL))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если указатели области образуют пару
		 */
		else if((before == unicode::cluster_t::REGIONAL) && (after == unicode::cluster_t::REGIONAL) && ((regional % 2) == 1))
			// Выполняем сброс флага разрыва графемного кластера
			broken = false;
		/**
		 * Если графемный кластер разрывается перед очередным символом
		 */
		if(broken)
			// Выходим из цикла присоединения символов
			break;
		/**
		 * Если очередной символ является указателем области
		 */
		if(after == unicode::cluster_t::REGIONAL)
			// Увеличиваем количество подряд идущих указателей области
			regional++;
		// Выполняем сброс количества подряд идущих указателей области
		else regional = 0;
		/**
		 * Если очередной символ является изобразительным
		 */
		if(after == unicode::cluster_t::PICTORIAL) {
			// Выполняем установку флага обнаружения изобразительного символа
			pictorial = true;
			// Выполняем сброс флага обнаружения соединителя
			joined = false;
		/**
		 * Если очередной символ продолжает изобразительный символ
		 */
		} else if(pictorial && (after == unicode::cluster_t::EXTEND)) {
			// Сохраняем флаг обнаружения изобразительного символа
			pictorial = true;
			/**
			 * Выполняем сброс флага обнаружения соединителя
			 *
			 * @details Соединение изобразительных символов требует, чтобы продолжающие
			 *          символы предшествовали соединителю, поэтому продолжающий символ
			 *          за соединителем прекращает соединение.
			 *
			 */
			joined = false;
		/**
		 * Если очередной символ соединяет изобразительные символы
		 */
		} else if(pictorial && (after == unicode::cluster_t::JOINER)) {
			// Выполняем установку флага обнаружения соединителя
			joined = true;
			/**
			 * Выполняем сброс флага обнаружения изобразительного символа
			 *
			 * @details Соединение изобразительных символов допускает единственный
			 *          соединитель, поэтому соединитель прекращает последовательность
			 *          продолжающих символов изобразительного символа.
			 *
			 */
			pictorial = false;
		/**
		 * Выполняем сброс обнаружения изобразительного символа
		 */
		} else {
			// Выполняем сброс флага обнаружения изобразительного символа
			pictorial = false;
			// Выполняем сброс флага обнаружения соединителя
			joined = false;
		}
		/**
		 * Если очередной символ является согласным сочетания индийских письменностей
		 */
		if(following == unicode::indic_t::CONSONANT) {
			// Выполняем установку флага обнаружения согласного символа
			consonant = true;
			// Выполняем сброс флага обнаружения соединяющего символа
			linked = false;
		/**
		 * Если очередной символ соединяет согласные символы сочетания
		 */
		} else if(consonant && (following == unicode::indic_t::LINKER)) {
			// Выполняем установку флага обнаружения соединяющего символа
			linked = true;
		/**
		 * Если очередной символ продолжением сочетания не является
		 */
		} else if(following != unicode::indic_t::EXTEND) {
			// Выполняем сброс флага обнаружения согласного символа
			consonant = false;
			// Выполняем сброс флага обнаружения соединяющего символа
			linked = false;
		}
		// Выполняем установку класса разбиения предшествующего символа
		before = after;
		// Переходим к позиции за присоединённым символом
		current += width;
	}
	// Выводим длину графемного кластера в байтах
	return (current - pos);
}
