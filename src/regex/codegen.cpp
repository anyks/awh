	/**
	 * @brief Количество позиций окна просеивания на месте
	 *
	 * @details Окно решает, окупится ли вызов подпрограммы поиска: набор
	 *          допустимых байтов бывает узок по числу значений, а част
	 *          по встречаемости их в тексте, и тогда поиск находит позицию
	 *          сразу, а вызов платится впустую. Замер на выражении
	 *          «alpha|bravo|charlie|delta|echo|foxtrot» - шесть байтов, все
	 *          частые в связном тексте, - показал вызов втрое дороже
	 *          просеивания, тогда как на «GET|POST|PUT|DELETE|HEAD|OPTIONS»
	 *          поиск дал выигрыш вчетверо.
	 *
	 *          Величина взята по цене вызова: спасение регистров в кадр
	 *          и возврат обходятся примерно в десяток обращений к памяти,
	 *          тогда как позиция просеивания - в два. Окно потому и держит
	 *          шестнадцать позиций: пропуск короче вызова не оправдывает,
	 *          а сама подпрограмма сличает шестнадцать байтов за один оборот,
	 *          отчего окно короче её оборота оставляло бы вызов недогруженным.
	 *
	 */
	constexpr size_t SIFTING = 16;

