/**
 * @brief Конструктор
 *
 */
awh::regex::Pike::Pike() noexcept :
 _program(nullptr), _start(0), _generation(0), _upcoming(0), _width(0) {}
/**
 * @brief Метод выделения набора позиций захвата групп
 *
 * @return номер выделенного набора позиций захвата групп
 *
 */
uint32_t awh::regex::Pike::acquire() noexcept {
	/**
	 * Если освобождённые наборы позиций захвата групп отсутствуют
	 */
	if(this->_vacant.empty()) {
		// Получаем номер создаваемого набора позиций захвата групп
		const uint32_t result = static_cast <uint32_t> (this->_refs.size());
		// Выполняем размещение отрезка создаваемого набора позиций захвата групп
		this->_storage.resize(this->_storage.size() + this->_width);
		// Выполняем удержание созданного набора позиций захвата групп
		this->_refs.push_back(1);
		// Выводим номер выделенного набора позиций захвата групп
		return result;
	}
	// Получаем номер освобождённого набора позиций захвата групп
	const uint32_t result = this->_vacant.back();
	// Выполняем удаление номера набора из числа освобождённых
	this->_vacant.pop_back();
	// Выполняем удержание выделенного набора позиций захвата групп
	this->_refs[result] = 1;
	// Выводим номер выделенного набора позиций захвата групп
	return result;
}
/**
 * @brief Метод удержания набора позиций захвата групп
 *
 * @param index номер удерживаемого набора позиций захвата групп
 *
 */
void awh::regex::Pike::retain(const uint32_t index) noexcept {
	/**
	 * Если номер набора позиций захвата групп установлен
	 */
	if(index != NO_SLOTS)
		// Увеличиваем количество состояний, удерживающих набор
		this->_refs[index]++;
}
/**
 * @brief Метод освобождения набора позиций захвата групп
 *
 * @param index номер освобождаемого набора позиций захвата групп
 *
 */
void awh::regex::Pike::release(const uint32_t index) noexcept {
	/**
	 * Если номер набора позиций захвата групп не установлен
	 */
	if(index == NO_SLOTS)
		// Выходим из метода освобождения набора
		return;
	// Получаем количество состояний, удерживающих освобождаемый набор
	uint32_t & refs = this->_refs[index];
	/**
	 * Если набор позиций захвата групп удерживается состояниями
	 */
	if(refs > 0) {
		// Уменьшаем количество состояний, удерживающих набор
		refs--;
		/**
		 * Если набор позиций захвата групп более не удерживается
		 */
		if(refs == 0)
			// Выполняем возврат набора в хранилище для повторной выдачи
			this->_vacant.push_back(index);
	}
}
/**
 * @brief Метод сохранения позиции в ячейке захвата
 *
 * @param index номер изменяемого набора позиций захвата групп
 * @param slot  номер ячейки захвата, в которой сохраняется позиция
 * @param pos   сохраняемая в ячейке захвата позиция в тексте
 * @return      номер набора позиций захвата групп с сохранённой позицией
 *
 */
uint32_t awh::regex::Pike::assign(const uint32_t index, const uint32_t slot, const size_t pos) noexcept {
	// Номер набора позиций захвата групп с сохранённой позицией
	uint32_t result = index;
	/**
	 * Если набор позиций захвата групп разделяется прочими состояниями
	 *
	 * @details Разделяемый набор обязан остаться неизменным, поэтому сохранение
	 *          позиции выполняется в его копии. Набор, удерживаемый единственной
	 *          ссылкой, изменяется на месте, что избавляет от копирования.
	 *
	 */
	if(this->_refs[index] > 1) {
		// Выполняем выделение набора позиций захвата групп
		result = this->acquire();
		/**
		 * Выполняем копирование позиций захвата групп в выделенный набор
		 *
		 * @details Копирование выполняется отрезком хранилища, поскольку выделение
		 *          набора размещает отрезок, но не изменяет его содержимого.
		 *          Копирование обходом взамен вызова пробовалось и отличий
		 *          от вызова не дало: отрезок занимает единицы позиций.
		 *
		 */
		::memcpy(&this->_storage[static_cast <size_t> (result) * this->_width],
		 &this->_storage[static_cast <size_t> (index) * this->_width], (this->_width * sizeof(size_t)));
		// Выполняем освобождение разделяемого набора позиций захвата групп
		this->release(index);
	}
	/**
	 * Если номер ячейки захвата находится в пределах набора
	 */
	if(static_cast <size_t> (slot) < this->_width)
		// Выполняем сохранение позиции в ячейке захвата
		this->_storage[(static_cast <size_t> (result) * this->_width) + static_cast <size_t> (slot)] = pos;
	// Выводим номер набора позиций захвата групп с сохранённой позицией
	return result;
}
/**
 * @brief Метод очистки набора исполняемых состояний
 *
 * @param list очищаемый набор исполняемых состояний
 *
 */
void awh::regex::Pike::discard(vector <thread_t> & list) noexcept {
	/**
	 * Выполняем освобождение наборов позиций захвата групп
	 */
	for(auto & thread : list)
		// Выполняем освобождение набора позиций захвата групп состояния
		this->release(thread.slots);
	// Выполняем очистку набора исполняемых состояний
	list.clear();
}
/**
 * @brief Метод добавления состояния в набор исполняемых состояний
 *
 * @param list  набор исполняемых состояний
 * @param pc    адрес добавляемой инструкции программы
 * @param slots набор позиций захвата групп
 * @param pos   позиция в тексте, для которой добавляется состояние
 *
 */
void awh::regex::Pike::append(vector <thread_t> & list, vector <uint32_t> & marks, const uint32_t generation, const address_t pc, const uint32_t slots, const size_t pos) noexcept {
	// Получаем стек замыкания состояния по инструкциям без сопоставления символов
	vector <thread_t> & stack = this->_stack;
	// Выполняем очистку стека замыкания состояния
	stack.clear();
	// Выполняем размещение исходного состояния в стеке замыкания
	stack.emplace_back();
	// Выполняем установку адреса исполняемой инструкции
	stack.back().pc = pc;
	// Выполняем установку набора позиций захвата групп
	stack.back().slots = slots;
	/**
	 * Выполняем удержание набора позиций захвата групп исходного состояния
	 *
	 * @details Набор передан вызывающей стороной, удерживающей собственную
	 *          ссылку, поэтому размещённое состояние удерживает набор отдельно.
	 *
	 */
	this->retain(slots);
	/**
	 * Выполняем замыкание состояния по инструкциям без сопоставления символов
	 */
	while(!stack.empty()) {
		// Получаем состояние из вершины стека замыкания
		const thread_t thread = stack.back();
		// Выполняем удаление состояния из стека замыкания
		stack.pop_back();
		/**
		 * Если адрес инструкции находится за пределами программы
		 */
		if(static_cast <size_t> (thread.pc) >= this->_program->instructions.size()) {
			// Выполняем освобождение набора позиций захвата групп состояния
			this->release(thread.slots);
			// Переходим к следующему состоянию стека замыкания
			continue;
		}
		/**
		 * Если инструкция уже была посещена в текущей позиции
		 */
		if(marks.at(thread.pc) == generation) {
			// Выполняем освобождение набора позиций захвата групп состояния
			this->release(thread.slots);
			// Переходим к следующему состоянию стека замыкания
			continue;
		}
		// Выполняем отметку посещения инструкции в текущей позиции
		marks.at(thread.pc) = generation;
		// Получаем исполняемую инструкцию программы
		const instruction_t & instruction = this->_program->instructions.at(thread.pc);
		/**
		 * Определяем код операции исполняемой инструкции
		 */
		switch(static_cast <uint8_t> (instruction.type)) {
			/**
			 * Выполняем переход по двум ветвям в порядке убывания приоритета
			 */
			case static_cast <uint8_t> (opcode_t::SPLIT): {
				/**
				 * Выполняем удержание набора позиций захвата групп второй ветвью
				 *
				 * @details Набор разделяется обеими ветвями, тогда как состояние
				 *          удерживает единственную ссылку, поэтому вторая ветвь
				 *          удерживает набор дополнительно.
				 *
				 */
				this->retain(thread.slots);
				// Выполняем размещение ветви с наименьшим приоритетом в стеке
				stack.emplace_back();
				// Выполняем установку адреса ветви с наименьшим приоритетом
				stack.back().pc = instruction.split.second;
				// Выполняем установку набора позиций захвата групп
				stack.back().slots = thread.slots;
				// Выполняем размещение ветви с наибольшим приоритетом в стеке
				stack.emplace_back();
				// Выполняем установку адреса ветви с наибольшим приоритетом
				stack.back().pc = instruction.split.first;
				// Выполняем установку набора позиций захвата групп
				stack.back().slots = thread.slots;
			} break;
			/**
			 * Выполняем безусловный переход
			 */
			case static_cast <uint8_t> (opcode_t::JUMP): {
				// Выполняем размещение состояния перехода в стеке замыкания
				stack.emplace_back();
				// Выполняем установку адреса инструкции перехода
				stack.back().pc = instruction.jump.target;
				// Выполняем установку набора позиций захвата групп
				stack.back().slots = thread.slots;
			} break;
			/**
			 * Выполняем сохранение позиции в ячейке захвата
			 */
			case static_cast <uint8_t> (opcode_t::SAVE): {
				// Выполняем сохранение позиции в ячейке захвата
				const uint32_t slots = this->assign(thread.slots, instruction.save.slot, pos);
				// Выполняем размещение состояния продолжения в стеке замыкания
				stack.emplace_back();
				// Выполняем установку адреса следующей инструкции
				stack.back().pc = (thread.pc + 1);
				// Выполняем установку набора позиций захвата групп
				stack.back().slots = slots;
			} break;
			/**
			 * Выполняем проверку привязки к позиции в тексте
			 */
			case static_cast <uint8_t> (opcode_t::ANCHOR): {
				/**
				 * Если привязка к позиции в тексте не выполняется
				 */
				if(!assertion(this->_text, this->_start, instruction.assertion.type, instruction.flags, pos)) {
					// Выполняем освобождение набора позиций захвата групп состояния
					this->release(thread.slots);
					// Переходим к следующему состоянию стека замыкания
					break;
				}
				// Выполняем размещение состояния продолжения в стеке замыкания
				stack.emplace_back();
				// Выполняем установку адреса следующей инструкции
				stack.back().pc = (thread.pc + 1);
				// Выполняем установку набора позиций захвата групп
				stack.back().slots = thread.slots;
			} break;
			/**
			 * Выполняем размещение состояния в наборе исполняемых состояний
			 */
			default: {
				// Выполняем размещение состояния в наборе исполняемых состояний
				list.emplace_back();
				// Выполняем установку адреса исполняемой инструкции
				list.back().pc = thread.pc;
				// Выполняем установку набора позиций захвата групп
				list.back().slots = thread.slots;
			}
		}
	}
}
/**
 * @brief Метод сопоставления регулярного выражения с текстом
 *
 * @param program  исполняемая программа регулярного выражения
 * @param text     текст для сопоставления
 * @param start    позиция начала поиска совпадения
 * @param captures набор границ совпадения и захваченных групп
 * @return         результат поиска совпадения
 *
 */
bool awh::regex::Pike::exec(const program_t & program, string_view text, const size_t start, vector <pair <size_t, size_t>> & captures) noexcept {
	// Выводим результат сопоставления регулярного выражения с поиском по тексту
	return this->exec(program, text, start, captures, mode_t::PLAIN);
}
/**
 * @brief Метод сопоставления регулярного выражения с текстом с указанной позиции
 *
 * @param program  исполняемая программа регулярного выражения
 * @param text     текст для сопоставления
 * @param start    позиция начала поиска совпадения
 * @param captures набор границ совпадения и захваченных групп
 * @param mode     режим сопоставления регулярного выражения с текстом
 * @return         результат поиска совпадения
 *
 */
bool awh::regex::Pike::exec(const program_t & program, string_view text, const size_t start, vector <pair <size_t, size_t>> & captures, const mode_t mode) noexcept {
	// Выполняем установку исполняемой программы регулярного выражения
	this->_program = &program;
	// Выполняем установку текста сопоставления
	this->_text = text;
	// Выполняем установку позиции начала попытки сопоставления
	this->_start = start;
	// Выполняем очистку набора границ совпадения и захваченных групп
	captures.clear();
	/**
	 * Если программа регулярного выражения пуста
	 */
	if(program.instructions.empty())
		// Выводим результат поиска совпадения
		return false;
	// Получаем количество ячеек захвата групп
	const size_t count = ((static_cast <size_t> (program.captures) + 1) * 2);
	/**
	 * Если хранилище наборов позиций захвата групп не пригодно к повторному применению
	 *
	 * @details Хранилище сохраняется между вызовами, благодаря чему выделение памяти
	 *          под наборы позиций захвата групп выполняется однократно. Изменение
	 *          размера набора либо наличие неосвобождённых наборов требуют его сброса.
	 *
	 */
	if((this->_width != count) || (this->_vacant.size() != this->_refs.size())) {
		// Выполняем установку количества позиций захвата групп в наборе
		this->_width = count;
		// Выполняем очистку хранилища наборов позиций захвата групп
		this->_storage.clear();
		// Выполняем очистку набора количеств удерживающих состояний
		this->_refs.clear();
		// Выполняем очистку набора номеров освобождённых наборов
		this->_vacant.clear();
	}
	// Получаем наибольший применённый номер поколения отметок посещения
	const uint32_t reached = ((this->_generation > this->_upcoming) ? this->_generation : this->_upcoming);
	/**
	 * Если наборы отметок посещения не пригодны к повторному применению
	 *
	 * @details Отметка посещения хранит номер поколения, при котором инструкция
	 *          посещена, поэтому нумерация поколений продолжается между вызовами,
	 *          а наборы отметок размещаются лишь при смене размера программы либо
	 *          при исчерпании нумерации. Размещение наборов при каждом вызове
	 *          обходилось соразмерно размеру программы и на коротком тексте
	 *          составляло основную долю его стоимости.
	 *
	 */
	if((this->_marks.size() != program.instructions.size()) || (reached > (0xFFFFFFFF - 4))) {
		// Выполняем установку набора отметок посещения текущей позиции
		this->_marks.assign(program.instructions.size(), 0);
		// Выполняем установку набора отметок посещения следующей позиции
		this->_pending.assign(program.instructions.size(), 0);
		/**
		 * Выполняем установку начального номера поколения отметок посещения
		 *
		 * @details Отметки посещения размещаются нулевым значением, поэтому нумерация
		 *          поколений начинается с единицы, иначе непосещённые инструкции
		 *          считались бы посещёнными.
		 *
		 */
		this->_generation = 1;
		// Выполняем установку начального номера поколения отметок следующей позиции
		this->_upcoming = 1;
	/**
	 * Если наборы отметок посещения пригодны к повторному применению
	 */
	} else {
		/**
		 * Выполняем продолжение нумерации поколений отметок посещения
		 *
		 * @details Номер поколения превышает наибольший применённый ранее, поэтому
		 *          отметки, оставшиеся от предшествующего вызова, посещёнными
		 *          не считаются.
		 *
		 */
		this->_generation = (reached + 1);
		// Выполняем установку номера поколения отметок следующей позиции
		this->_upcoming = (reached + 1);
	}
	// Выполняем очистку набора состояний текущей позиции
	this->discard(this->_current);
	// Выполняем очистку набора состояний следующей позиции
	this->discard(this->_next);
	// Номер набора позиций захвата групп найденного совпадения
	uint32_t found = NO_SLOTS;
	/**
	 * Определяем привязку выражения к началу попытки сопоставления
	 */
	const bool bound = ((mode == mode_t::ANCHORED) || hasFlag(program.flags, flag_t::ANCHORED));
	// Получаем размер текста сопоставления
	const size_t size = text.size();
	// Получаем позицию начала поиска совпадения
	size_t pos = ((start > size) ? size : start);
	/**
	 * Если обязательный литерал совпадения в тексте отсутствует
	 *
	 * @details Литерал присутствует в любом совпадении выражения, поэтому его
	 *          отсутствие в оставшемся тексте означает отсутствие совпадения
	 *          и позволяет отказаться от исполнения программы целиком.
	 *
	 */
	if(!program.prefilter.possible(text, pos))
		// Выводим результат поиска совпадения
		return false;
	/**
	 * Если детерминированное исполнение применимо и совпадение не обнаружено
	 *
	 * @details Детерминированное исполнение проходит текст многократно быстрее,
	 *          поэтому отказ от поиска выполняется им. Обнаружение совпадения
	 *          требует установки его границ и захваченных групп, что выполняется
	 *          исполнением без возврата. Установленное вызывающей стороной наличие
	 *          совпадения избавляет от повторного прохода по тексту.
	 *
	 */
	if(!bound && (mode != mode_t::VERIFIED) && this->_dfa.available(program) && !this->_dfa.test(program, text, pos))
		// Выводим результат поиска совпадения
		return false;
	// Выполняем выделение исходного набора позиций захвата групп
	const uint32_t initial = this->acquire();
	/**
	 * Выполняем сброс исходного набора позиций захвата групп
	 *
	 * @details Набор выдаётся хранилищем с содержимым предшествующего сопоставления,
	 *          поэтому сбрасывается: незахваченная группа обязана остаться без границ.
	 *
	 */
	std::fill_n(this->_storage.begin() + static_cast <ptrdiff_t> (static_cast <size_t> (initial) * this->_width), this->_width, string_view::npos);
	/**
	 * Выполняем обход позиций текста сопоставления
	 */
	while(true) {
		/**
		 * Если совпадение ещё не найдено и выражение не привязано к началу
		 *
		 * @details Состояние начала выражения размещается в конце набора состояний,
		 *          благодаря чему совпадение, начинающееся левее, сохраняет
		 *          наибольший приоритет.
		 *
		 */
		if((found == NO_SLOTS) && !bound && this->_current.empty() && program.prefilter.active) {
			// Выполняем поиск ближайшей позиции возможного начала совпадения
			const size_t candidate = program.prefilter.search(text, pos);
			/**
			 * Если позиция возможного начала совпадения не обнаружена
			 *
			 * @details Применимость набора допустимых начальных байтов означает
			 *          невозможность совпадения нулевой длины, поэтому отсутствие
			 *          допустимого байта означает отсутствие совпадения.
			 *
			 */
			if(candidate >= size)
				// Выходим из цикла обхода позиций текста
				break;
			/**
			 * Если пропущена хотя бы одна позиция текста
			 *
			 * @details Отметки посещения действуют в пределах одной позиции текста.
			 *          Пропуск позиций выполняется без смены поколения отметок, поэтому
			 *          поколения назначаются заново, иначе отметки прежней позиции
			 *          оборвали бы замыкание состояния начала выражения.
			 *
			 */
			if(candidate > pos) {
				// Получаем поколение отметок, превышающее использованные
				const uint32_t fresh = (((this->_generation > this->_upcoming) ? this->_generation : this->_upcoming) + 1);
				// Выполняем установку поколения отметок текущей позиции
				this->_generation = fresh;
				// Выполняем установку поколения отметок следующей позиции
				this->_upcoming = (fresh + 1);
			}
			// Переходим к позиции возможного начала совпадения
			pos = candidate;
		}
		/**
		 * Если совпадение ещё не найдено и выражение не привязано к началу
		 */
		if((found == NO_SLOTS) && (!bound || (pos == this->_start)))
			// Выполняем размещение состояния начала выражения
			this->append(this->_current, this->_marks, this->_generation, 0, initial, pos);
		// Длина символа в текущей позиции в байтах
		size_t width = 1;
		/**
		 * Выполняем извлечение длины символа в текущей позиции
		 *
		 * @details Длина символа определяется режимами компиляции выражения целиком,
		 *          поскольку все состояния продвигаются по тексту одновременно
		 *          и обязаны переходить к одной и той же следующей позиции.
		 *
		 */
		const uint32_t code = letter(this->_text, pos, program.flags, width);
		/**
		 * Выполняем исполнение состояний текущей позиции
		 */
		for(size_t i = 0; i < this->_current.size(); i++) {
			// Получаем исполняемое состояние текущей позиции
			thread_t & thread = this->_current.at(i);
			// Получаем исполняемую инструкцию программы
			const instruction_t & instruction = program.instructions.at(thread.pc);
			/**
			 * Если инструкция завершает сопоставление с успехом
			 *
			 * @details Состояния с меньшим приоритетом отбрасываются, поскольку
			 *          совпадение, найденное состоянием с большим приоритетом,
			 *          совпадает с выбором реализации с возвратом.
			 *
			 */
			if(instruction.type == opcode_t::MATCH) {
				/**
				 * Если пустое совпадение совпадением не считается
				 *
				 * @details Состояние, давшее пустое совпадение, отбрасывается,
				 *          а состояния с меньшим приоритетом исполняются далее:
				 *          выражение вида «(?:|a)» при этом даёт совпадение
				 *          непустой своей ветвью, а не отказ.
				 *
				 */
				if(hasFlag(program.flags, flag_t::NOTEMPTY) &&
				 (this->_storage[(static_cast <size_t> (thread.slots) * this->_width)] == pos))
					// Переходим к следующему состоянию текущей позиции
					continue;
				// Выполняем освобождение набора позиций захвата прежнего совпадения
				this->release(found);
				// Выполняем сохранение позиций захвата найденного совпадения
				found = thread.slots;
				// Выполняем удержание набора позиций захвата найденного совпадения
				this->retain(found);
				// Выходим из цикла исполнения состояний текущей позиции
				break;
			}
			/**
			 * Если позиция находится в конце текста
			 */
			if(pos >= size)
				// Переходим к следующему состоянию текущей позиции
				continue;
			// Флаг сопоставления символа инструкцией
			bool matched = false;
			/**
			 * Определяем код операции исполняемой инструкции
			 */
			switch(static_cast <uint8_t> (instruction.type)) {
				/**
				 * Выполняем сопоставление одиночного символа
				 */
				case static_cast <uint8_t> (opcode_t::CHAR): {
					/**
					 * Если установлен режим сопоставления без учёта регистра
					 */
					if(hasFlag(instruction.flags, flag_t::CASELESS))
						// Выполняем сопоставление символов без учёта регистра
						matched = (fold(code, instruction.flags) == fold(instruction.letter.code, instruction.flags));
					// Выполняем сопоставление символов с учётом регистра
					else matched = (code == instruction.letter.code);
				} break;
				/**
				 * Выполняем сопоставление символа из класса символов
				 */
				case static_cast <uint8_t> (opcode_t::CLASS): {
					// Выполняем проверку принадлежности символа классу символов
					matched = belongs(program.charclass(instruction.charclass.index), code, instruction.flags);
				} break;
				/**
				 * Выполняем сопоставление любого символа
				 */
				case static_cast <uint8_t> (opcode_t::ANY): {
					/**
					 * Если установлен режим соответствия точки переводу строки
					 */
					if(hasFlag(instruction.flags, flag_t::DOTALL))
						// Выполняем установку флага сопоставления символа
						matched = true;
					// Выполняем проверку несоответствия символа переводу строки
					else matched = (code != 0x0A);
				} break;
				/**
				 * Выполняем сопоставление одиночной единицы кодирования
				 */
				case static_cast <uint8_t> (opcode_t::CODEUNIT): {
					// Выполняем установку флага сопоставления символа
					matched = true;
				} break;
			}
			/**
			 * Если символ инструкцией не сопоставлен
			 */
			if(!matched)
				// Переходим к следующему состоянию текущей позиции
				continue;
			// Выполняем размещение состояния продолжения в наборе следующей позиции
			this->append(this->_next, this->_pending, this->_upcoming, (thread.pc + 1), thread.slots, (pos + width));
		}
		/**
		 * Если позиция достигла конца текста сопоставления
		 */
		if(pos >= size)
			// Выходим из цикла обхода позиций текста
			break;
		/**
		 * Если набор состояний следующей позиции пуст и совпадение найдено
		 */
		if(this->_next.empty() && (found != NO_SLOTS))
			// Выходим из цикла обхода позиций текста
			break;
		// Выполняем обмен наборов состояний текущей и следующей позиций
		this->_current.swap(this->_next);
		// Выполняем обмен наборов отметок посещения текущей и следующей позиций
		this->_marks.swap(this->_pending);
		// Выполняем обмен номеров поколений отметок посещения
		std::swap(this->_generation, this->_upcoming);
		// Выполняем очистку набора состояний следующей позиции
		this->discard(this->_next);
		/**
		 * Увеличиваем номер поколения отметок посещения следующей позиции
		 *
		 * @details Увеличение номера поколения обесценивает отметки, накопленные
		 *          в наборе при его прошлом использовании, что заменяет очистку набора.
		 *
		 */
		this->_upcoming++;
		// Переходим к следующей позиции текста сопоставления
		pos += width;
	}
	// Выполняем освобождение исходного набора позиций захвата групп
	this->release(initial);
	// Выполняем очистку набора состояний текущей позиции
	this->discard(this->_current);
	// Выполняем очистку набора состояний следующей позиции
	this->discard(this->_next);
	/**
	 * Если совпадение не найдено
	 */
	if(found == NO_SLOTS)
		// Выводим результат поиска совпадения
		return false;
	// Получаем набор позиций захвата групп найденного совпадения
	const size_t * slots = &this->_storage[static_cast <size_t> (found) * this->_width];
	// Выполняем размещение границ совпадения и захваченных групп
	captures.resize(static_cast <size_t> (program.captures) + 1);
	/**
	 * Выполняем заполнение границ совпадения и захваченных групп
	 */
	for(size_t i = 0; i < captures.size(); i++) {
		// Выполняем установку начальной границы захвата
		captures.at(i).first = slots[i * 2];
		// Выполняем установку конечной границы захвата
		captures.at(i).second = slots[(i * 2) + 1];
	}
	// Выполняем освобождение набора позиций захвата найденного совпадения
	this->release(found);
	// Выводим результат поиска совпадения
	return true;
}
