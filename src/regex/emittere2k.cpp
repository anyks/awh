/**
 * @brief Метод размещения завершения вызова
 *
 */
void awh::regex::Emitter::ret() noexcept {
	// Выдаём широкой команды, к выдаче отложенной: управление сюда приходит либо отсюда уходит
	this->flush();
	// Создаём широкую команду подготовки возврата
	bundle_t ready;
	// Устанавливаем слог управления первого
	ready.first = true;
	/**
	 * Собираем слог подготовки возврата
	 *
	 * @details Возврат готовится регистром подготовки ТРЕТЬИМ: прочие
	 *          ассемблер отвергает прямо, а исполнение - недопустимой командой.
	 *
	 */
	ready.cs0 = (0xF0000000u);
	// Размещаем подготовкю возврата
	::emit(this->_code, ready);
	// Создаём широкую команду передачи управления возвратом
	bundle_t pass;
	// Устанавливаем слог коротких операций
	pass.stubbed = true;
	// Собираем слог передачи управления возвратом
	pass.stub = ::transfer(3, 1, 0);
	// Размещаем передачю управления возвратом
	::emit(this->_code, pass);
	// Обрываем ряд записей в память
	this->_stamp = SIZE_MAX;
}
/**
 * @brief Метод разрешения отложенных переходов
 *
 * @return результат разрешения отложенных переходов
 *
 */
bool awh::regex::Emitter::resolve() noexcept {
	// Выдаём широкой команды, к выдаче отложенной: управление сюда приходит либо отсюда уходит
	this->flush();
	/**
	 * Если порождение машинного кода отказало
	 */
	if(this->_failed)
		// Разрешение отложенных переходов: отказ
		return false;
	/**
	 * Обходим набор отложенных переходов
	 */
	for(auto & fixup : this->_fixups){
		// Получаем положение метки, к какой выполняется переход
		const size_t target = this->_labels.at(fixup.label);
		/**
		 * Если метка положения не получила
		 */
		if(target == INVALID_LABEL){
			// Устанавливаем флаг отказа порождения машинного кода
			this->_failed = true;
			// Разрешение отложенных переходов: отказ
			return false;
		}
		/**
		 * Получаем смещение перехода восьмёрками байтов
		 *
		 * @details Смещение отсчитывается от начала широкой команды подготовки
		 *          перехода, а длина всякой широкой команды кратна восьми.
		 *
		 */
		const int64_t delta = ((static_cast <int64_t> (target) - static_cast <int64_t> (fixup.position)) / 8);
		/**
		 * Если смещение полем слога управления не размещается
		 */
		if((delta > MAX_BRANCH) || (delta < -MAX_BRANCH)){
			// Устанавливаем флаг отказа порождения машинного кода
			this->_failed = true;
			// Разрешение отложенных переходов: отказ
			return false;
		}
		// Получаем положение слога управления в широкой команде подготовки
		const size_t position = (fixup.position + sizeof(uint32_t));
		// Собираемое значение слога управления подготовки перехода
		uint32_t syllable = 0;
		/**
		 * Обходим байтов слога управления
		 */
		for(uint8_t shift = 0; shift < 32; shift += 8)
			// Добавляем очередного байта слога
			syllable |= (static_cast <uint32_t> (this->_code.at(position + (shift >> 3))) << shift);
		// Вписываем смещение перехода в слог управления
		syllable |= (static_cast <uint32_t> (static_cast <int32_t> (delta)) & 0x0FFFFFFFu);
		/**
		 * Обходим байтов слога управления
		 */
		for(uint8_t shift = 0; shift < 32; shift += 8)
			// Размещаем очередного байта слога
			this->_code.at(position + (shift >> 3)) = static_cast <uint8_t> ((syllable >> shift) & 0xFF);
	}
	// Очищаем набор разрешённых переходов
	this->_fixups.clear();
	// Разрешение отложенных переходов: успех
	return true;
}
