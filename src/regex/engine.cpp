/**
 * @brief Конструктор
 *
 */
awh::regex::Engine::Engine() noexcept : _error(error_t::NONE) {}
/**
 * @brief Метод извлечения кода ошибки последней операции
 *
 * @return код ошибки последней операции движка
 *
 */
awh::regex::error_t awh::regex::Engine::error() const noexcept {
	// Выводим код ошибки последней операции движка
	return this->_error;
}
/**
 * @brief Метод извлечения текста ошибки последней операции
 *
 * @return текст ошибки последней операции движка
 *
 */
string awh::regex::Engine::message() const noexcept {
	// Выводим текст ошибки последней операции движка
	return this->_parser.message();
}
/**
 * @brief Метод извлечения смещения ошибки разбора выражения
 *
 * @return смещение ошибки в тексте регулярного выражения
 *
 */
size_t awh::regex::Engine::offset() const noexcept {
	// Выводим смещение ошибки в тексте регулярного выражения
	return this->_parser.errorPos();
}
/**
 * @brief Метод извлечения количества захватывающих групп
 *
 * @return количество захватывающих групп регулярного выражения
 *
 */
uint32_t awh::regex::Engine::captures() const noexcept {
	// Выводим количество захватывающих групп регулярного выражения
	return this->_expression.forward.captures;
}
/**
 * @brief Метод сборки регулярного выражения
 *
 * @param pattern текст регулярного выражения
 * @param flags   набор режимов компиляции регулярного выражения
 * @return        результат выполнения сборки
 *
 */
bool awh::regex::Engine::build(string_view pattern, const uint32_t flags) noexcept {
	// Выводим результат сборки регулярного выражения движка
	return this->build(pattern, flags, this->_expression);
}
/**
 * @brief Метод сборки регулярного выражения в отдельное выражение
 *
 * @param pattern    текст регулярного выражения
 * @param flags      набор режимов компиляции регулярного выражения
 * @param expression собираемое регулярное выражение
 * @return           результат выполнения сборки
 *
 */
bool awh::regex::Engine::build(string_view pattern, const uint32_t flags, expression_t & expression) noexcept {
	// Выполняем сброс флага готовности выражения
	expression.ready = false;
	// Выполняем сброс флага исполнения выражения с возвратом
	expression.backtracking = false;
	// Выполняем сброс флага применимости поиска позиции начала
	expression.reversible = false;
	// Выполняем очистку соответствия имён именованных групп
	expression.names.clear();
	// Выполняем сброс кода ошибки последней операции
	this->_error = error_t::NONE;
	/**
	 * Если разбор регулярного выражения не выполнен
	 */
	if(!this->_parser.parse(pattern, flags)) {
		// Выполняем установку кода ошибки разбора выражения
		this->_error = this->_parser.error();
		// Выводим результат выполнения сборки
		return false;
	}
	// Выполняем установку соответствия имён именованных групп их номерам
	expression.names = this->_parser.groups();
	/**
	 * Если компиляция регулярного выражения не выполнена
	 */
	if(!this->_compiler.compile(this->_parser, expression.forward)) {
		// Выполняем установку кода ошибки компиляции выражения
		this->_error = this->_compiler.error();
		/**
		 * Если выражение регулярному подмножеству синтаксиса не принадлежит
		 *
		 * @details Выражение вне регулярного подмножества исполняется с возвратом,
		 *          что требует времени, растущего с длиной текста показательно,
		 *          поэтому такое исполнение применяется исключительно при
		 *          недостижимости исполнения без возврата.
		 *
		 */
		if(this->_error == error_t::UNSUPPORTED) {
			/**
			 * Если компиляция регулярного выражения целиком не выполнена
			 */
			if(!this->_compiler.compileFull(this->_parser, expression.forward)) {
				// Выполняем установку кода ошибки компиляции выражения
				this->_error = this->_compiler.error();
				// Выводим результат выполнения сборки
				return false;
			}
			// Выполняем сброс кода ошибки последней операции
			this->_error = error_t::NONE;
			// Выполняем установку флага исполнения выражения с возвратом
			expression.backtracking = true;
			// Выполняем установку флага готовности движка
			expression.ready = true;
			// Выводим результат выполнения сборки
			return true;
		}
		// Выводим результат выполнения сборки
		return false;
	}
	// Выполняем установку флага готовности движка
	expression.ready = true;
	/**
	 * Если сборка выражения выполняется в режиме порождения машинного кода
	 *
	 * @details Кодогенерацию получает подмножество выражений, а не всякое выражение,
	 *          поэтому отказ порождения отказом сборки не является: непринятое
	 *          выражение сопоставляется исполнением программы, как и без режима.
	 *          Режимы, задающие сопоставление лишь с начала текста либо отказ
	 *          от пустого совпадения, порождённым кодом не соблюдаются
	 *          и кодогенерации не получают.
	 *
	 */
	if(((flags & static_cast <uint32_t> (flag_t::JIT)) != 0) &&
	 ((flags & (static_cast <uint32_t> (flag_t::ANCHORED) | static_cast <uint32_t> (flag_t::NOTEMPTY))) == 0) &&
	 !expression.backtracking && !expression.forward.plain) {
		// Создаём сопоставитель выражения в виде порождённого машинного кода
		expression.machine = make_shared <codegen_t> ();
		/**
		 * Если порождение сопоставителя выражения не выполнено
		 */
		if(!expression.machine->compile(expression.forward))
			// Выполняем сброс сопоставителя выражения
			expression.machine.reset();
	}
	/**
	 * Если выражение привязано к началу попытки сопоставления
	 *
	 * @details Поиск позиции начала совпадения при привязке выражения не требуется,
	 *          поскольку позиция начала совпадения известна заранее.
	 *
	 */
	if((expression.forward.flags & static_cast <uint32_t> (flag_t::ANCHORED)) != 0)
		// Выводим результат выполнения сборки
		return true;
	/**
	 * Выполняем поиск привязок, зависящих от начала попытки сопоставления
	 *
	 * @details Привязка «\G» соответствует началу попытки сопоставления, тогда как
	 *          проход в обратном направлении начинается с конца текста, поэтому
	 *          для выражений с такой привязкой поиск позиции начала неприменим.
	 *
	 */
	for(auto & instruction : expression.forward.instructions) {
		/**
		 * Если инструкция проверяет привязку к началу попытки сопоставления
		 */
		if((instruction.type == opcode_t::ANCHOR) && (instruction.assertion.type == anchor_t::SEARCH_HEAD))
			// Выводим результат выполнения сборки
			return true;
	}
	/**
	 * Если компиляция развёрнутого регулярного выражения выполнена
	 */
	if(this->_compiler.compileReverse(this->_parser, expression.backward))
		// Выполняем установку флага применимости поиска позиции начала
		expression.reversible = true;
	// Выводим результат выполнения сборки
	return true;
}
/**
 * @brief Метод проверки наличия совпадения в тексте
 *
 * @param text  текст для сопоставления
 * @param start позиция начала поиска совпадения
 * @return      результат проверки наличия совпадения
 *
 */
bool awh::regex::Engine::test(string_view text, const size_t start) noexcept {
	// Выводим результат проверки наличия совпадения выражения движка
	return this->test(this->_expression, text, start);
}
/**
 * @brief Метод проверки наличия совпадения отдельного выражения
 *
 * @param expression исполняемое регулярное выражение
 * @param text       текст для сопоставления
 * @param start      позиция начала поиска совпадения
 * @return           результат проверки наличия совпадения
 *
 */
bool awh::regex::Engine::test(const expression_t & expression, string_view text, const size_t start) noexcept {
	/**
	 * Если движок к сопоставлению не готов
	 */
	if(!expression.ready)
		// Выводим результат проверки наличия совпадения
		return false;
	/**
	 * Если выражение исполняется с возвратом
	 */
	if(expression.backtracking) {
		// Выполняем сопоставление регулярного выражения исполнением с возвратом
		const bool result = this->_backtrack.exec(expression.forward, text, start, this->_spare);
		// Выполняем установку кода ошибки исполнения с возвратом
		this->_error = this->_backtrack.error();
		// Выводим результат проверки наличия совпадения
		return result;
	}
	/**
	 * Если выражение сопоставляется одним литералом
	 *
	 * @details Поиск последовательности в тексте выполняется набором команд
	 *          процессора над несколькими байтами сразу и проходит текст
	 *          многократно быстрее любого исполнения программы.
	 *
	 */
	if(expression.forward.plain)
		// Выводим результат поиска последовательности выражения в тексте
		return (text.find(expression.forward.text, start) != string_view::npos);
	/**
	 * Если обязательный литерал совпадения в тексте отсутствует
	 */
	if(!expression.forward.prefilter.possible(text, start))
		// Выводим результат проверки наличия совпадения
		return false;
	/**
	 * Если пустое совпадение совпадением не считается
	 *
	 * @details Детерминированное исполнение пустое совпадение от непустого
	 *          не отличает, поэтому наличие совпадения устанавливается
	 *          исполнением без возврата.
	 *
	 */
	if(hasFlag(expression.forward.flags, flag_t::NOTEMPTY))
		// Выводим результат сопоставления исполнением без возврата
		return this->_pike.exec(expression.forward, text, start, this->_spare);
	/**
	 * Если детерминированное исполнение применимо
	 */
	if(this->_dfa.available(expression.forward))
		// Выводим результат проверки наличия совпадения детерминированным исполнением
		return this->_dfa.test(expression.forward, text, start);
	/**
	 * Выводим результат сопоставления исполнением без возврата
	 *
	 * @details Наличие совпадения установлено детерминированным исполнением выше,
	 *          поэтому повторный проход по тексту для его проверки не требуется.
	 *
	 */
	return this->_pike.exec(expression.forward, text, start, this->_spare, mode_t::VERIFIED);
}
/**
 * @brief Метод сопоставления регулярного выражения с текстом
 *
 * @param text     текст для сопоставления
 * @param start    позиция начала поиска совпадения
 * @param captures набор границ совпадения и захваченных групп
 * @return         результат поиска совпадения
 *
 */
bool awh::regex::Engine::exec(string_view text, const size_t start, vector <pair <size_t, size_t>> & captures) noexcept {
	// Выводим результат сопоставления выражения движка с текстом
	return this->exec(this->_expression, text, start, captures);
}
/**
 * @brief Метод сопоставления отдельного выражения с текстом
 *
 * @param expression исполняемое регулярное выражение
 * @param text       текст для сопоставления
 * @param start      позиция начала поиска совпадения
 * @param captures   набор границ совпадения и захваченных групп
 * @return           результат поиска совпадения
 *
 */
bool awh::regex::Engine::exec(const expression_t & expression, string_view text, const size_t start, vector <pair <size_t, size_t>> & captures) noexcept {
	// Выполняем очистку набора границ совпадения
	captures.clear();
	/**
	 * Если движок к сопоставлению не готов
	 */
	if(!expression.ready)
		// Выводим результат поиска совпадения
		return false;
	/**
	 * Если выражение несёт сопоставитель в виде порождённого машинного кода
	 *
	 * @details Порождённый код устанавливает границы совпадения и захваченных групп
	 *          сам, отчего исполнения программы вслед за собою не требует.
	 *
	 */
	if(expression.machine)
		// Выводим результат сопоставления порождённым машинным кодом
		return expression.machine->exec(text, start, captures);
	/**
	 * Если выражение исполняется с возвратом
	 */
	if(expression.backtracking) {
		// Выполняем сопоставление регулярного выражения исполнением с возвратом
		const bool result = this->_backtrack.exec(expression.forward, text, start, captures);
		// Выполняем установку кода ошибки исполнения с возвратом
		this->_error = this->_backtrack.error();
		// Выводим результат поиска совпадения
		return result;
	}
	/**
	 * Если выражение сопоставляется одним литералом
	 *
	 * @details Поиск последовательности в тексте выполняется набором команд
	 *          процессора над несколькими байтами сразу и проходит текст
	 *          многократно быстрее любого исполнения программы.
	 *
	 */
	if(expression.forward.plain) {
		// Выполняем поиск последовательности выражения в тексте
		const size_t position = text.find(expression.forward.text, start);
		/**
		 * Если последовательность выражения в тексте не найдена
		 */
		if(position == string_view::npos)
			// Выводим результат поиска совпадения
			return false;
		// Выполняем размещение границ совпадения
		captures.emplace_back(position, (position + expression.forward.text.size()));
		// Выводим результат поиска совпадения
		return true;
	}
	/**
	 * Если выражение начинается с ведущего литерала
	 *
	 * @details Ведущий литерал переводит исполнение с возвратом сразу к позициям
	 *          вхождения литерала, отчего повторение попытки в каждой позиции текста
	 *          ему не грозит, а границы совпадения оно устанавливает единственным
	 *          проходом. Проход детерминированного исполнения при этом излишен:
	 *          отсутствие совпадения исполнение с возвратом устанавливает само,
	 *          отыскивая вхождения литерала тем же поиском последовательности.
	 *          Измерением получено двукратное превосходство на выражении «\bneedle\b».
	 *
	 */
	if(!expression.forward.prefilter.leading.empty()) {
		// Выполняем установку допустимого объёма работы исполнения с возвратом
		this->_backtrack.budget((text.size() - start + 1) * expression.forward.instructions.size() * BACKTRACK_RATIO);
		/**
		 * Если сопоставление исполнением с возвратом выполнено
		 */
		if(this->_backtrack.exec(expression.forward, text, start, captures))
			// Выводим результат поиска совпадения
			return true;
		/**
		 * Если допустимый объём работы сопоставления не исчерпан
		 *
		 * @details Исполнение с возвратом проходит текст целиком, поэтому отсутствие
		 *          совпадения установлено им окончательно и повторного прохода
		 *          прочими способами не требует.
		 *
		 */
		if(this->_backtrack.error() != error_t::BUDGET_EXCEEDED)
			// Выводим результат поиска совпадения
			return false;
	}
	/**
	 * Если обязательный литерал совпадения в тексте отсутствует
	 */
	if(!expression.forward.prefilter.possible(text, start))
		// Выводим результат поиска совпадения
		return false;
	/**
	 * Если пустое совпадение совпадением не считается
	 *
	 * @details Детерминированное исполнение отыскивает совпадение любой длины,
	 *          отчего пустое совпадение оно отбросить не в силах: отброшенное
	 *          позднее, оно обратилось бы в отказ, тогда как поиск обязан
	 *          продолжиться. Исполнение без возврата испытывает состояния
	 *          в порядке приоритета и потому отбрасывает пустое совпадение,
	 *          продолжая сопоставление состояниями меньшего приоритета.
	 *
	 */
	if(hasFlag(expression.forward.flags, flag_t::NOTEMPTY))
		// Выводим результат сопоставления исполнением без возврата
		return this->_pike.exec(expression.forward, text, start, captures);
	/**
	 * Если детерминированное исполнение неприменимо
	 */
	if(!this->_dfa.available(expression.forward))
		// Выводим результат сопоставления исполнением без возврата
		return this->_pike.exec(expression.forward, text, start, captures);
	/**
	 * Если выражение проходит текст единственной попыткой
	 *
	 * @details Выражение, начинающееся неограниченным жадным повторением любого
	 *          символа, попытки в каждой позиции текста не повторяет: повторение
	 *          поглощает текст до совпадения, начинающегося правее. Одна попытка
	 *          устанавливает границы совпадения целиком, тогда как прежний порядок
	 *          проходил текст трижды - проверкой наличия совпадения, поиском его
	 *          начала и сопоставлением. Измерением получено превосходство втрое
	 *          на выражении «.*needle».
	 *
	 */
	if(expression.forward.sweeping) {
		// Выполняем установку допустимого объёма работы исполнения с возвратом
		this->_backtrack.budget((text.size() - start + 1) * BACKTRACK_RATIO);
		/**
		 * Если сопоставление исполнением с возвратом выполнено
		 */
		if(this->_backtrack.exec(expression.forward, text, start, captures))
			// Выводим результат поиска совпадения
			return true;
		/**
		 * Если допустимый объём работы сопоставления не исчерпан
		 */
		if(this->_backtrack.error() != error_t::BUDGET_EXCEEDED)
			// Выводим результат поиска совпадения
			return false;
	}
	// Позиция завершения обнаруженного совпадения
	size_t finish = string_view::npos;
	/**
	 * Если совпадение в тексте отсутствует
	 *
	 * @details Отсутствие совпадения устанавливается детерминированным исполнением,
	 *          проходящим текст многократно быстрее исполнения без возврата.
	 *
	 */
	if(!this->_dfa.search(expression.forward, text, start, finish))
		// Выводим результат поиска совпадения
		return false;
	// Получаем длину участка текста, занятого поиском совпадения
	const size_t span = (finish - start);
	/**
	 * Если границы совпадения устанавливаются исполнением с возвратом
	 *
	 * @details Исполнение с возвратом ведёт единственный набор границ, изменяя его
	 *          на месте, тогда как исполнение без возврата ведёт набор при каждом
	 *          состоянии и замещает его копией при каждом захвате. На коротком участке
	 *          текста это даёт исполнению с возвратом превосходство до пяти раз,
	 *          но время его растёт с длиной текста показательно, поэтому объём работы
	 *          ограничивается соразмерно участку и размеру программы, а исчерпание
	 *          объёма возвращает сопоставление исполнению без возврата.
	 *
	 *          Длина участка при наличии ведущего литерала не ограничивается:
	 *          исполнение с возвратом повторяет попытку не в каждой позиции текста,
	 *          а лишь в позициях вхождения литерала, отчего показательный рост
	 *          времени с длиной текста ему не грозит.
	 *
	 */
	if((span <= MAX_BACKTRACK) || !expression.forward.prefilter.leading.empty()) {
		// Выполняем установку допустимого объёма работы исполнения с возвратом
		this->_backtrack.budget((span + 1) * expression.forward.instructions.size() * BACKTRACK_RATIO);
		/**
		 * Если сопоставление исполнением с возвратом выполнено
		 */
		if(this->_backtrack.exec(expression.forward, text, start, captures))
			// Выводим результат поиска совпадения
			return true;
	}
	/**
	 * Если поиск позиции начала совпадения применим
	 */
	if(expression.reversible && (start == 0)) {
		// Получаем длину участка текста, пройденного до завершения совпадения
		const size_t scanned = (finish - start);
		// Получаем длину участка текста, подлежащего проходу в обратном направлении
		const size_t remains = (text.size() - start);
		/**
		 * Если проход в обратном направлении обходится дешевле исполнения без возврата
		 *
		 * @details Проход в обратном направлении проходит текст целиком и стоит
		 *          одинаково при любом выражении, тогда как стоимость исполнения
		 *          без возврата определяется количеством состояний, заводимых им
		 *          в каждой позиции текста. Наличие ведущего литерала означает,
		 *          что исполнение без возврата переходит сразу к позициям возможного
		 *          начала совпадения и состояний в прочих позициях не заводит,
		 *          отчего обходится дешевле прохода по тексту целиком. Отсутствие
		 *          ведущего литерала означает обратное, и тогда проход в обратном
		 *          направлении оправдан длиной пройденного участка текста.
		 *
		 */
		if(expression.forward.prefilter.leading.empty() && (scanned > MIN_REVERSE) && (remains < (REVERSE_RATIO * scanned))) {
			// Позиция начала обнаруженного совпадения
			size_t begin = string_view::npos;
			/**
			 * Если поиск позиции начала совпадения выполнен
			 */
			if(this->_reverse.reverse(expression.backward, text, text.size(), begin)) {
				/**
				 * Выполняем установку допустимого объёма работы исполнения с возвратом
				 *
				 * @details Известная позиция начала совпадения избавляет исполнение
				 *          с возвратом от повторения попытки в каждой позиции текста,
				 *          которое и делает его непригодным на длинном тексте. Одной
				 *          попытке с известной позиции показательный рост времени
				 *          всё же доступен, поэтому объём работы ограничивается.
				 *
				 */
				this->_backtrack.budget((finish - begin + 1) * expression.forward.instructions.size() * BACKTRACK_RATIO);
				/**
				 * Если исполнение с возвратом с позиции начала совпадения выполнено
				 */
				if(this->_backtrack.exec(expression.forward, text, begin, captures, mode_t::ANCHORED))
					// Выводим результат поиска совпадения
					return true;
				/**
				 * Если исполнение без возврата с позиции начала совпадения выполнено
				 */
				if(this->_pike.exec(expression.forward, text, begin, captures, mode_t::ANCHORED))
					// Выводим результат поиска совпадения
					return true;
			}
		}
	}
	/**
	 * Выводим результат сопоставления исполнением без возврата
	 *
	 * @details Наличие совпадения установлено детерминированным исполнением выше,
	 *          поэтому исполнение без возврата извещается об этом: иначе оно
	 *          устанавливало бы наличие совпадения само, проходя текст вторично.
	 *
	 */
	return this->_pike.exec(expression.forward, text, start, captures, mode_t::VERIFIED);
}
