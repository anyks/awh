/**
 * @brief Метод проверки собранного по описанию ожидаемых
 *
 * @return результат проверки
 *
 */
bool awh::args::Args::verify() noexcept {
	// Если описания ожидаемых параметров нет вовсе
	if(this->_schema.empty())
		// Выходим из метода, проверять нечем
		return true;
	// Признак успешности проверки собранного
	bool result = true;
	// Выполняем перебор всех описаний ожидаемых параметров
	for(auto & param : this->_schema.params()){
		// Выполняем перевод длинного имени параметра в путь оси хранения
		const string & path = this->route(param.name);
		// Если параметр уже уложен в дерево настроек
		if(this->_root.at(path).valid())
			// Продолжаем перебор описаний дальше
			continue;
		// Если описание несёт значение параметра по умолчанию
		if(param.preset){
			// Выполняем укладку значения по умолчанию
			result = (this->lay(path, this->derive(param.fallback), source_t::DEFAULT) && result);
			// Продолжаем перебор описаний дальше
			continue;
		}
		// Если параметр обязателен к подаче, а подан не был
		if(param.required){
			// Выполняем запоминание отказа проверки
			this->_errors.emplace_back(error_t::REQUIRED, location_t());
			// Выводим в лог сообщение об отсутствии обязательного параметра
			awh::log::print("Args: %s \"%s\"", awh::log::flag_t::WARNING, args::message(error_t::REQUIRED), param.name.c_str());
			// Отмечаем, что проверка собранного отвечена отказом
			result = false;
		}
	}
	// Выводим результат проверки собранного
	return result;
}

/**
 * @brief Метод разбора записи настроек кодеком
 *
 * @param text запись настроек для разбора
 * @return     результат разбора
 *
 */
bool awh::args::Args::config(const string_view text, const codec::Bridge::format_t format) noexcept {
	// Собираемое дерево значений записи настроек
	codec::abc::value_t value;
	// Выполняем разбор записи настроек кодеком
	if(!this->_bridge.decode(text, value, format)){
		// Выполняем запоминание отказа разбора записи настроек
		this->_errors.emplace_back(error_t::CODEC, location_t());
		// Выходим из метода, разбор отвечен отказом
		return false;
	}
	/**
	 * Если записью настроек оказалась разметка
	 *
	 * @details У документа разметки ровно один корневой узел, и узел этот есть
	 * ОБНОС записи, а не настройка: имя ему даётся снаружи и означает лишь то, что
	 * безымянным корень быть не может. Прочие четыре вида обноса не требуют вовсе
	 *
	 * @warning Без снятия обноса настройка `port` из записи разметки ложилась бы
	 *          путём `config.port` и доводом запуска `--port` НЕ перекрывалась бы:
	 *          старшинство источников считается по одному и тому же пути, а пути
	 *          расходились. Замерено 05.09.2026 - запись разметки давала порт `0`
	 *          там, где прочие четыре вида давали свой
	 *
	 * @note Обнос снимается лишь при ОДНОМ поле верхнего уровня: запись с двумя
	 *       корнями разметке негодна вовсе, и снимать там нечего
	 */
	if((format == codec::Bridge::format_t::XML) && value.is(codec::abc::type_t::MAP) && (value.size() == 1)){
		// Извлекаемое имя единственного поля дерева
		string name = "";
		/**
		 * Если имя поля есть имя ОБНОСА, а поле его является отображением
		 *
		 * @warning Имя сличается с настройкою обноса, а не берётся всяким: мост
		 *          пишет дерево из ОДНОГО поля верхнего уровня без своего обноса
		 *          вовсе - корнем записи становится само поле, - и снятие корня по
		 *          одному лишь числу полей уносило НАСТОЯЩИЙ уровень настроек.
		 *          Замерено 16.09.2026 ворошителем доводов запуска: настройка
		 *          `--zums.cyqdjf=0.25` выдавалась записью `<zums cyqdjf="0.25"/>`,
		 *          а чтением возвращалась как `cyqdjf` - звено `zums` пропадало, и
		 *          круг выдачи с чтением полз. У самого моста круг при том стоял
		 *          неподвижно: порок принадлежал этому ходу, а не переводу
		 *
		 * @note Настройка, названная именем обноса, от обноса неотличима вовсе, и
		 *       снятие тут неизбежно: запись `<config x="1"/>` есть и обнос над
		 *       полем `x`, и поле `config` с полем `x` внутри. Двусмысленность эта
		 *       принадлежит самой разметке
		 */
		if(value.key(0).value(name) && (name == this->_bridge.settings().root) && value[name].is(codec::abc::type_t::MAP))
			// Выполняем слияние содержимого корневого узла с деревом настроек
			return this->merge(value[name], "", source_t::FILE, true);
	}
	/**
	 * Признак вывода записей знаками словарём самого модуля
	 *
	 * @note Взводится лишь у видов записи, своей системы видов не имеющих: у INI и
	 *       разметки всякое значение есть текст, и словарь модуля там обязан быть
	 *       тем же, что и у довода запуска
	 */
	const bool derive = ((format == codec::Bridge::format_t::INI) || (format == codec::Bridge::format_t::XML));
	// Выполняем слияние разобранного дерева с деревом настроек
	return this->merge(value, "", source_t::FILE, derive);
}

/**
 * @brief Метод чтения файла настроек
 *
 * @param filename путь к файлу настроек
 * @return         результат чтения
 *
 */
bool awh::args::Args::filename(const string & filename, const codec::Bridge::format_t format) noexcept {
	// Если файла настроек нет вовсе
	if(this->_fs.type(filename) != fs_t::type_t::FILE){
		// Выполняем запоминание отказа чтения файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отсутствии файла настроек
		awh::log::print("Args: %s \"%s\"", awh::log::flag_t::WARNING, args::message(error_t::FILESYSTEM), filename.c_str());
		// Выходим из метода, читать нечего
		return false;
	}
	// Прочитанная запись файла настроек
	string text = "";
	// Выполняем чтение файла настроек целиком
	this->_fs.read(filename, text);
	/**
	 * Если запись файла настроек пуста вовсе
	 *
	 * @warning Пустота эта двузначна, и различать её ОБЯЗАТЕЛЬНО: ход чтения
	 *          `fs_t::read` при отказе тоже оставляет запись пустой, отчего
	 *          отказ чтения и пустой файл с виду неотличимы. Различаются они
	 *          РАЗМЕРОМ файла: нулевой размер означает, что файл прочитан
	 *          исправно и пуст, всякий иной - что чтение отказало
	 *
	 * @note Прежде оба случая оглашались кодом `FILESYSTEM`, и потребитель,
	 *       получивший его на исправно читаемом пустом файле, шёл проверять
	 *       путь и права, тогда как негодны были не они, а содержимое. Пустая
	 *       запись отдаётся теперь кодеку, и отказ оглашает он сам кодом
	 *       `CODEC` - тем же, каким оглашается всякая иная негодная запись.
	 *       Замерено 14.09.2026 аудитом
	 */
	if(text.empty() && (this->_fs.size(filename) > 0)){
		// Выполняем запоминание отказа чтения файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отказе чтения файла настроек
		awh::log::print("Args: %s \"%s\"", awh::log::flag_t::WARNING, args::message(error_t::FILESYSTEM), filename.c_str());
		// Выходим из метода, читать нечего
		return false;
	}
	// Выполняем разбор прочитанной записи настроек
	return this->config(text, format);
}

/**
 * @brief Метод чтения файла настроек с выводом вида записи из его имени
 *
 * @param filename путь к файлу настроек
 * @return         результат чтения
 *
 * @warning Вид записи берётся РАСШИРЕНИЕМ имени, а не догадкою по содержимому:
 *          запись, годной двум видам разом, догадка выбирала бы молча, и
 *          потребитель узнал бы о выборе лишь по неверно прочтённым настройкам.
 *          Запись `port = 8080` годится и INI, и TOML, и прочтения их расходятся
 *
 * @note Расширения ведомы шесть: `.abc` у контейнера ABC, `.json`, `.yaml` с `.yml`,
 *       `.toml`, `.ini` с `.conf` и `.xml`. Всякий вид записи, какой выдаётся
 *       методом `save`, читается и по имени файла - круг замкнут у всех шести
 *
 * @note Расширение `.conf` отдано наречию INI, а не TOML: у систем POSIX им
 *       зовутся именно файлы вида «ключ = значение» с разделами
 *
 */
bool awh::args::Args::filename(const string & filename) noexcept {
	// Выполняем поиск расширения имени файла настроек
	const size_t pos = filename.rfind('.');
	// Если расширения у имени файла нет вовсе
	if((pos == string::npos) || ((pos + 1) >= filename.length())){
		// Выполняем запоминание отказа чтения файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отсутствии расширения имени
		awh::log::print("Args: format of the settings file \"%s\" is not derivable from its name", awh::log::flag_t::WARNING, filename.c_str());
		// Выходим из метода, читать нечего
		return false;
	}
	// Извлекаемое расширение имени файла настроек
	string extension = filename.substr(pos + 1);
	// Выполняем перевод расширения в нижний регистр
	awh::fmk::transform(extension, awh::fmk::transform_t::LOWER_CASE);
	/**
	 * Если расширение означает запись контейнера ABC
	 *
	 * @warning Дорога эта была пропущена, и круг записи ABC не замыкался: выдача
	 *          `save(путь, ABC)` проходила исправно, а чтение того же файла по имени
	 *          отвечалось отказом «unknown format», тогда как всякий иной вид записи
	 *          по имени читался. Потребителю оставалось звать чтение с указанием
	 *          вида - о чём ему было знать неоткуда. Замерено 16.09.2026 аудитом
	 */
	if(extension.compare("abc") == 0)
		// Выполняем чтение файла настроек записью контейнера ABC
		return this->filename(filename, codec::Bridge::format_t::ABC);
	// Если расширение означает запись JSON
	else if(extension.compare("json") == 0)
		// Выполняем чтение файла настроек записью JSON
		return this->filename(filename, codec::Bridge::format_t::JSON);
	// Если расширение означает запись YAML
	else if((extension.compare("yaml") == 0) || (extension.compare("yml") == 0))
		// Выполняем чтение файла настроек записью YAML
		return this->filename(filename, codec::Bridge::format_t::YAML);
	// Если расширение означает запись TOML
	else if(extension.compare("toml") == 0)
		// Выполняем чтение файла настроек записью TOML
		return this->filename(filename, codec::Bridge::format_t::TOML);
	// Если расширение означает запись INI
	else if((extension.compare("ini") == 0) || (extension.compare("conf") == 0))
		// Выполняем чтение файла настроек записью INI
		return this->filename(filename, codec::Bridge::format_t::INI);
	// Если расширение означает запись XML
	else if(extension.compare("xml") == 0)
		// Выполняем чтение файла настроек записью XML
		return this->filename(filename, codec::Bridge::format_t::XML);
	// Выполняем запоминание отказа чтения файла настроек
	this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
	// Выводим в лог сообщение о неведомом расширении имени
	awh::log::print("Args: unknown format \"%s\" of the settings file \"%s\"", awh::log::flag_t::WARNING, extension.c_str(), filename.c_str());
	// Выходим из метода, читать нечего
	return false;
}

/**
 * @brief Метод выдачи дерева настроек записью кодека
 *
 * @param result собранная запись настроек
 * @return       результат выдачи
 *
 */
bool awh::args::Args::dump(string & result, const codec::Bridge::format_t format) noexcept {
	// Выполняем перевод дерева настроек в запись кодека
	if(!this->_bridge.encode(this->_root, result, format)){
		// Выполняем запоминание отказа выдачи записи настроек
		this->_errors.emplace_back(error_t::UNSUPPORTED, location_t());
		// Выходим из метода, выдача отвечена отказом
		return false;
	}
	// Сообщаем, что выдача записи настроек выполнена
	return true;
}

/**
 * @brief Метод записи дерева настроек в файл
 *
 * @param filename путь к файлу настроек
 * @return         результат записи
 *
 */
bool awh::args::Args::save(const string & filename, const codec::Bridge::format_t format) noexcept {
	// Собираемая запись настроек
	string text = "";
	// Выполняем выдачу дерева настроек записью кодека
	if(!this->dump(text, format))
		// Выходим из метода, выдача отвечена отказом
		return false;
	/**
	 * Собираемый адрес временного файла записи
	 *
	 * @warning Запись идёт СПЕРВА во временный файл, а целевой подменяется им лишь
	 *          по успешной поверке: пиши мы прямо в целевой, отказ на середине
	 *          уничтожал бы прежние настройки пользователя, и остаться он мог бы
	 *          вовсе ни с чем. Правило это общее всему дереву - решение владельца
	 *          от 09.09.2026, - и подмена берётся ходом каркаса `replaceAddress()`,
	 *          а не своим переименованием: ход этот у MS Windows зовёт `MoveFileExW`
	 *          с заменою на месте, а у прочих систем `rename()`, и оба заменяют
	 *          целевой файл ОДНИМ действием
	 */
	const string temporary = (filename + ".awh-tmp");
	/**
	 * Выполняем снос временного файла, от прежнего сохранения оставшегося
	 *
	 * @warning Снос этот обязателен: ход записи каркаса файла НЕ УСЕКАЕТ у MS
	 *          Windows - `CreateFileW` зовётся там с `OPEN_ALWAYS`, и запись
	 *          ложится по смещению, - оттого остаток прежнего сохранения, длиною
	 *          нынешнее превзошедший, торчал бы хвостом за концом записанного.
	 *          Имя временного файла у нас постоянное, и остаться он может от
	 *          прогона, оборванного между записью и подменой. Поверка длины такую
	 *          запись отвергла бы - и отвергала бы КАЖДЫЙ раз, покуда файл не
	 *          снесут руками. Замерено 09.09.2026 разбором тела `fs_t::write`
	 *
	 * @note У систем POSIX усечение ход делает сам - поток открывается там без
	 *       разбора смещения, - но снос обязан стоять и там: расхождение это есть
	 *       свойство каркаса, а не наше, и опираться на него нельзя
	 */
	static_cast <void> (this->_fs.unlink(temporary));
	/**
	 * Выполняем запись собранной записи настроек во временный файл
	 *
	 * @note Признак отказа спрашивается у самого хода записи: прежде ходы записи
	 *       каркаса были объявлены `void`, отказ уходил в один лишь журнал, и
	 *       сохранение в заведомо негодный путь отвечало УСПЕХОМ - обход стоял
	 *       поверкой вида и величины записанного. Ныне ход отвечает сам, и успехом
	 *       считает запись ВСЕГО буфера, а частичную - отказом; обход снят
	 */
	if(!this->_fs.write(temporary, text.data(), text.size())){
		// Выполняем снос временного файла записи
		static_cast <void> (this->_fs.unlink(temporary));
		// Выполняем запоминание отказа записи файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отказе записи файла настроек
		awh::log::print("Args: settings are not written to \"%s\"", awh::log::flag_t::WARNING, filename.c_str());
		// Выходим из метода, запись отвечена отказом
		return false;
	}
	/**
	 * Выполняем сброс записанного из вместилища ядра на носитель
	 *
	 * @warning Сброс стоит ДО подмены, а не после неё, и в том весь его смысл:
	 *          запись, отвеченная успехом, лежит ещё во вместилище ядра, и обрыв
	 *          питания её теряет. Подмени мы файл прежде сброса - целевой файл
	 *          указывал бы на содержимое, до носителя не дошедшее, и пользователь
	 *          остался бы и без прежних настроек, и без новых. Ради этого случая
	 *          вся возня с временным файлом и затеяна
	 *
	 * @note Отказ «носитель сброса не держит» отказом у каркаса не считается, и
	 *       ложью такой ход не отвечает: у канала сбрасывать нечего, а запись мимо
	 *       файла не ушла
	 */
	if(!this->_fs.flush(temporary)){
		// Выполняем снос временного файла записи
		static_cast <void> (this->_fs.unlink(temporary));
		// Выполняем запоминание отказа записи файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отказе сброса записи на носитель
		awh::log::print("Args: settings are not flushed into \"%s\"", awh::log::flag_t::WARNING, filename.c_str());
		// Выходим из метода, запись отвечена отказом
		return false;
	}
	// Выполняем подмену целевого файла настроек временным
	if(!this->_fs.replaceAddress(temporary, filename)){
		// Выполняем снос временного файла записи
		static_cast <void> (this->_fs.unlink(temporary));
		// Выполняем запоминание отказа записи файла настроек
		this->_errors.emplace_back(error_t::FILESYSTEM, location_t());
		// Выводим в лог сообщение об отказе подмены файла настроек
		awh::log::print("Args: settings are not moved into \"%s\"", awh::log::flag_t::WARNING, filename.c_str());
		// Выходим из метода, запись отвечена отказом
		return false;
	}
	// Сообщаем, что запись дерева настроек выполнена
	return true;
}

/**
 * @brief Метод извлечения моста между контейнером ABC и текстовыми кодеками
 *
 * @return мост между контейнером ABC и текстовыми кодеками
 *
 */
awh::codec::bridge_t & awh::args::Args::bridge() noexcept {
	// Выводим мост между контейнером ABC и текстовыми кодеками
	return this->_bridge;
}

/**
 * @brief Метод проверки наличия параметра
 *
 * @param key имя параметра с разделителем звеньев
 * @return    результат проверки
 *
 */
bool awh::args::Args::has(const string_view key) const noexcept {
	// Выводим признак наличия значения по пути оси хранения
	return this->_root.at(this->route(key)).valid();
}

/**
 * @brief Метод извлечения источника значения параметра
 *
 * @param key имя параметра с разделителем звеньев
 * @return    источник значения параметра
 *
 */
auto awh::args::Args::source(const string_view key) const noexcept -> source_t {
	// Выполняем поиск источника уложенного значения
	auto i = this->_origins.find(this->route(key));
	// Если источник уложенного значения найден
	if(i != this->_origins.end())
		// Выводим источник уложенного значения
		return i->second;
	// Выводим неопределённый источник значения
	return source_t::NONE;
}

/**
 * @brief Метод извлечения числа значений вместимого параметра
 *
 * @param key имя параметра с разделителем звеньев
 * @return    число значений вместимого
 *
 */
size_t awh::args::Args::size(const string_view key) const noexcept {
	// Получаем значение по пути оси хранения
	const codec::abc::value_t & value = this->_root.at(this->route(key));
	// Если значение вместимым является, выводим число уложенных в него значений
	if(value.is(codec::abc::type_t::ARRAY))
		// Выводим число значений вместимого
		return value.size();
	/**
	 * Значение, вместимым не являющееся, считается ОДНИМ значением, а не нулём
	 *
	 * @note Правило это то же, что и у извлечения перечнем: параметр, поданный
	 *       единожды, и параметр, поданный дважды, потребителю вместимого
	 *       различаться не должны. Прежде число это бралось прямо у дерева, и
	 *       одиночное значение давало НУЛЬ, тогда как извлечение перечнем на том
	 *       же значении давало одну запись: потребитель, перебирающий значения
	 *       счётом от `size()`, одиночное значение пропускал целиком. Замерено
	 *       14.09.2026 аудитом
	 */
	return (value.valid() ? 1 : 0);
}

/**
 * @brief Шаблон метода извлечения значения параметра
 *
 * @tparam T тип извлекаемого значения
 * @param key имя параметра с разделителем звеньев
 * @return    извлечённое значение параметра
 *
 */
template <typename T>
T awh::args::Args::get(const string_view key) const noexcept {
	// Получаем значение по пути оси хранения
	const codec::abc::value_t & value = this->_root.at(this->route(key));
	// Если извлекается последовательность знаков
	if constexpr(is_same <T, string>::value){
		// Извлекаемая последовательность знаков
		string result = "";
		// Выполняем извлечение последовательности знаков
		if(value.value(result))
			// Выводим извлечённую последовательность знаков
			return result;
		/**
		 * Значение, знаками не уложенное, приводится к записи
		 *
		 * @note Запас этот тот же, что и у извлечения логического значения ниже, и
		 *       заведён по тому же доводу: вывод вида значения включён настройкою по
		 *       умолчанию, оттого `--port=8080` ложится ЧИСЛОМ. Прежде извлечение
		 *       записью на таком значении отвечало ПУСТОТОЙ - неотличимо от параметра,
		 *       не поданного вовсе, - и потребитель, желающий просто показать
		 *       настройку, лишался её целиком. Замерено 14.09.2026 аудитом
		 *
		 * @note Пустое значение (`null`) записью НЕ выражается намеренно: оно значит
		 *       «значения нет», и запись «null» здесь означала бы обратное - что
		 *       значение есть и равно этому слову
		 */
		bool flag = false;
		// Если значение уложено логическим
		if(value.value(flag))
			// Выводим запись логического значения
			return string(flag ? "true" : "false");
		// Если значение уложено дробным числом
		if(value.is(codec::abc::type_t::DOUBLE) || value.is(codec::abc::type_t::FLOAT)){
			// Извлекаемое число дробное
			double real = 0.;
			// Выполняем извлечение числа дробного
			if(value.value(real))
				// Выводим запись числа дробного без указателя степени
				return awh::fmk::noexp(real);
		}
		// Если значение уложено целым со знаком
		if(value.is(codec::abc::type_t::INT8) || value.is(codec::abc::type_t::INT16) ||
		   value.is(codec::abc::type_t::INT32) || value.is(codec::abc::type_t::INT64)){
			// Извлекаемое целое со знаком
			int64_t number = 0;
			// Выполняем извлечение целого со знаком
			if(value.value(number))
				// Выводим запись целого со знаком
				return std::to_string(number);
		}
		// Если значение уложено целым без знака
		if(value.is(codec::abc::type_t::UINT8) || value.is(codec::abc::type_t::UINT16) ||
		   value.is(codec::abc::type_t::UINT32) || value.is(codec::abc::type_t::UINT64)){
			// Извлекаемое целое без знака
			uint64_t number = 0;
			// Выполняем извлечение целого без знака
			if(value.value(number))
				// Выводим запись целого без знака
				return std::to_string(number);
		}
		// Выводим пустую последовательность знаков
		return string("");
	// Если извлекается логическое значение
	} else if constexpr(is_same <T, bool>::value) {
		// Извлекаемое логическое значение
		bool result = false;
		// Выполняем извлечение логического значения
		if(value.value(result))
			// Выводим извлечённое логическое значение
			return result;
		/**
		 * Если значение уложено последовательностью знаков, оно приводится к
		 * логическому: вывод вида значения отключается настройкою, и потребитель
		 * от этого извлечения лишаться не должен
		 */
		string text = "";
		// Выполняем извлечение последовательности знаков
		if(value.value(text))
			// Выводим признак совпадения записи с истиной
			return (awh::fmk::compare(text, "true") || awh::fmk::compare(text, "yes") || awh::fmk::compare(text, "on") || awh::fmk::compare(text, "1"));
		// Выводим логическое значение ложью
		return false;
	// Если извлекается число
	} else {
		// Извлекаемое число дробное
		double real = 0.;
		// Если значение уложено дробным числом
		if(value.is(codec::abc::type_t::REAL) && value.value(real))
			// Выводим извлечённое число дробное
			return static_cast <T> (real);
		// Если извлекается число дробное
		if constexpr(is_floating_point <T>::value) {
			// Извлекаемое число целое со знаком
			int64_t number = 0;
			// Если значение уложено целым числом
			if(value.is(codec::abc::type_t::INT) && value.value(number))
				// Выводим извлечённое число целое
				return static_cast <T> (number);
		// Если извлекается число целое без знака
		} else if constexpr(is_unsigned <T>::value) {
			// Извлекаемое число целое без знака
			uint64_t number = 0;
			// Если значение уложено целым числом без знака
			if(value.value(number))
				// Выводим извлечённое число целое без знака
				return static_cast <T> (number);
		// Если извлекается число целое со знаком
		} else {
			// Извлекаемое число целое со знаком
			int64_t number = 0;
			// Если значение уложено целым числом со знаком
			if(value.value(number))
				// Выводим извлечённое число целое со знаком
				return static_cast <T> (number);
		}
		// Извлекаемая последовательность знаков
		string text = "";
		/**
		 * Если значение уложено последовательностью знаков, оно приводится к числу:
		 * вывод вида значения отключается настройкою, и потребитель от этого
		 * извлечения лишаться не должен
		 */
		if(value.value(text))
			// Выводим число, разобранное из последовательности знаков
			return awh::fmk::atoi <T> (text);
		// Выводим число нулём
		return static_cast <T> (0);
	}
}

/**
 * @brief Шаблон метода извлечения значений вместимого параметра
 *
 * @tparam T тип извлекаемых значений
 * @param key имя параметра с разделителем звеньев
 * @return    извлечённые значения вместимого
 *
 */
template <typename T>
vector <T> awh::args::Args::arr(const string_view key) const noexcept {
	// Контейнер извлечённых значений вместимого
	vector <T> result;
	// Выполняем перевод имени параметра в путь оси хранения
	const string & path = this->route(key);
	// Получаем значение по пути оси хранения
	const codec::abc::value_t & value = this->_root.at(path);
	// Если значение вместимым не является вовсе
	if(!value.is(codec::abc::type_t::ARRAY)){
		/**
		 * Если значение уложено одиночным, оно выдаётся вместимым из него одного:
		 * параметр, поданный единожды, и параметр, поданный дважды, потребителю
		 * вместимого различаться не должны
		 */
		if(value.valid())
			// Добавляем одиночное значение в контейнер извлечённых
			result.push_back(this->get <T> (key));
		// Выводим контейнер извлечённых значений вместимого
		return result;
	}
	// Выполняем резервирование памяти под извлекаемые значения
	result.reserve(value.size());
	// Выполняем перебор всех значений вместимого
	for(size_t i = 0; i < value.size(); i++)
		// Добавляем извлечённое значение вместимого в контейнер
		result.push_back(this->get <T> (awh::fmk::format("%s%c%zu", string(key).c_str(), this->_settings.delimiter, i)));
	// Выводим контейнер извлечённых значений вместимого
	return result;
}

