/**
 * @brief Метод опроса событий
 *
 * @details Выполняет **один оборот** цикла событий и возвращает
 *          управление. Своего потока движок не создаёт и сам себя не
 *          крутит - цикл ведёт вызывающий:
 *
 *          @code{.cpp}
 *          while(io.poll(100));
 *          @endcode
 *
 *          За один оборот выполняется: освобождение узлов,
 *          отложенных позапрошлым оборотом; отправка накопленного
 *          пакета изменений подписки вместе с ожиданием - одним
 *          обращением к ядру, а не двумя; разбор полученных событий с
 *          вызовом функций обратного вызова; разбор истёкших
 *          дедлайнов таймеров.
 *
 *          Все функции обратного вызова вызываются **внутри** этого
 *          метода. Пока они выполняются, оборот не завершён, поэтому
 *          долгая работа в обратном вызове задерживает и остальные
 *          события, и срабатывание таймеров.
 *
 * @note    Время ожидания ограничивается не только переданным
 *          таймаутом, но и сроком ближайшего внутреннего таймера:
 *          движок обязан проснуться к дедлайну, даже если вызывающий
 *          просил ждать дольше или бесконечно.
 *
 * @note    Отрицательный таймаут означает ожидание без предела, но с
 *          учётом таймеров; нулевой - опрос без ожидания вовсе,
 *          пригодный для встраивания в чужой цикл событий.
 *
 * @note    Отрицательный результат означает отказ опроса, а не
 *          отсутствие событий: оборот без единого события - это
 *          обычный успех. Прерывание системного вызова сигналом
 *          отказом не считается, движок продолжает работу.
 *
 * @note    Метод обязан вызываться из одного и того же потока. Первый
 *          вызов запоминает поток опроса, и обращения к событиям из
 *          других потоков после этого недопустимы
 *
 * @par Встраивание в чужой цикл событий
 * @code{.cpp}
 * // Опрос без ожидания: управление возвращается сразу
 * while(running){
 *     io.poll(0);
 *     foreignLoopIteration();
 * }
 * @endcode
 *
 * @param timeout таймаут опроса в миллисекундах: отрицательный - без
 *                предела, нулевой - без ожидания
 * @return        результат выполнения опроса
 *
 */
bool awh::engine::IO::poll(const int32_t timeout) noexcept {
	// Описатель порта завершения, с какого снимаются завершения
	HANDLE port = nullptr;
	{
		// Запоминаем описатель порта завершения
		port = ::__awh_port__;
	}
	// Если порт завершения не заведён
	if(port == nullptr){
		// Заносим в журнал предупреждение о неготовности движка
		this->_log->print("%s: engine is not initialized", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__);
		// Сообщаем об отказе опроса
		return false;
	}
	/**
	 * Завершения снимаются с порта пачкой, а не поодиночке
	 *
	 * @details Снятие поодиночке стоило бы перехода в ядро на каждое из них. Пачкой
	 *          же берётся всё, что накопилось, одним переходом - при потоке событий
	 *          разница эта заметна, а при их отсутствии не стоит ничего
	 *
	 */
	/**
	 * Массив снимаемых завершений подбирается по нагрузке сам
	 *
	 * @details Он удваивается, когда опрос вернул его заполненным целиком, и
	 *          ужимается вдвое после долгого затишья. Порядок этот взят у эталонных
	 *          движков: за один опрос имеет смысл забирать столько, сколько петля
	 *          успеет разобрать, а остаток никуда не денется - порт удержит его до
	 *          ближайшего опроса
	 *
	 */
	static std::vector <OVERLAPPED_ENTRY> entries(AWH_MAX_POLL_EVENTS_COUNT);
	// Счётчик оборотов затишья, за которые массив не заполнялся целиком
	static uint32_t idle = 0;
	// Число снятых с порта завершений
	ULONG removed = 0;
	/**
	 * Предел ожидания завершений подрезается ближайшим сроком
	 *
	 * @details Системе отдаётся один-единственный срок - ближайший из поставленных,
	 *          - а весь их учёт движок ведёт сам. Тем и снимается ограничение на
	 *          число таймеров: объектов ядра под них не заводится ни одного, и
	 *          стоит их тысяча ровно столько же, сколько один
	 *
	 * @note Ждать дольше ближайшего срока нельзя вовсе: пробуждаться петле неоткуда
	 *       - завершений на порту может не быть месяцами, - и срок бы попросту
	 *       проспали
	 *
	 */
	// Мгновение, по какому определяется истечение сроков
	const uint64_t moment = ::__awh_now__();
	// Ближайшее мгновение истечения поставленных сроков
	const uint64_t nearest = ::deadline::nearest();
	// Предел ожидания завершений в миллисекундах
	DWORD limit = (timeout < 0 ? INFINITE : static_cast <DWORD> (timeout));
	// Если сроки поставлены
	if(nearest != UINT64_MAX){
		// Определяем, сколько осталось до ближайшего срока
		const uint64_t left = ((nearest > moment) ? (nearest - moment) : 0);
		// Подрезаем предел ожидания ближайшим сроком
		if((limit == INFINITE) || (static_cast <uint64_t> (limit) > left))
			// Устанавливаем предел ожидания по ближайшему сроку
			limit = static_cast <DWORD> (left);
	}
	// Если снять завершения с порта не удалось
	if(!::GetQueuedCompletionStatusEx(port, entries.data(), static_cast <ULONG> (entries.size()), &removed, limit, FALSE)){
		// Получаем причину отказа снятия
		const DWORD code = ::GetLastError();
		/**
		 * Истечение отведённого срока отказом не считается
		 *
		 * @note Оборот без единого завершения - это обычный успех, а не отказ:
		 *       вызывающий волен опрашивать движок вовсе без ожидания
		 *
		 */
		if(code == WAIT_TIMEOUT){
			// Разбираем истёкшие сроки событий
			::__awh_expire__();
			// Сообщаем, что обход петли выполнен
			return true;
		}
		// Заносим в журнал предупреждение об отказе снятия завершений
		this->_log->print("%s: completion port wait failed, error %lu", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, code);
		// Сообщаем об отказе опроса
		return false;
	}
	/**
	 * Подбираем размер массива снимаемых завершений под нагрузку
	 */
	if((removed >= entries.size()) && (entries.size() < AWH_MAX_POLL_EVENTS_LIMIT)){
		// Сбрасываем счётчик оборотов затишья
		idle = 0;
		// Удваиваем массив, не переступая предела его роста
		entries.resize((entries.size() * 2) < AWH_MAX_POLL_EVENTS_LIMIT ? (entries.size() * 2) : AWH_MAX_POLL_EVENTS_LIMIT);
	// Если массив заполнен не целиком
	} else if(entries.size() > AWH_MAX_POLL_EVENTS_COUNT) {
		// Если затишье длится дольше отведённого
		if(++idle >= AWH_POLL_EVENTS_IDLE_ROUNDS){
			// Сбрасываем счётчик оборотов затишья
			idle = 0;
			// Ужимаем массив вдвое, не опускаясь ниже начального размера
			entries.resize((entries.size() / 2) > AWH_MAX_POLL_EVENTS_COUNT ? (entries.size() / 2) : AWH_MAX_POLL_EVENTS_COUNT);
		}
	}
	// Список принятых сообщений, подлежащих раздаче
	std::deque <std::pair <event::id_t, std::vector <uint8_t>>> messages;
	// Список узлов, у которых собеседник закрыл свою сторону
	std::deque <event::id_t> disconnected;
	/**
	 * Разбираем снятые с порта завершения
	 */
	for(ULONG i = 0; i < removed; i++){
		// Если завершение пробуждения петли - работы за ним нет
		if(entries[i].lpOverlapped == nullptr)
			// Переходим к следующему завершению
			continue;
		/**
		 * Приводим описатель наложенного обмена обратно к его описанию
		 *
		 * @note Приведение опирается на то, что поле обмена стоит в описании первым
		 *
		 */
		::Overlapped * context = reinterpret_cast <::Overlapped *> (entries[i].lpOverlapped);
		/**
		 * Определяем вид завершившегося обмена
		 */
		switch(static_cast <uint8_t> (context->operation)){
			// Если завершением принесено сообщение
			case static_cast <uint8_t> (::op_t::MESSAGE):
				// Откладываем сообщение до раздачи
				messages.emplace_back(context->id, ::std::move(context->buffer));
			break;
			/**
			 * Если завершился приём из сокета
			 *
			 * @note Пустой приём означает, что собеседник закрыл свою сторону:
			 *       заводить приём наново после того незачем
			 *
			 */
			case static_cast <uint8_t> (::op_t::RECV): {
				// Число принятых байт
				size_t received = static_cast <size_t> (entries[i].dwNumberOfBytesTransferred);
				/**
				 * Собираем сообщение, не уместившееся в буфер приёма
				 *
				 * @details Канал открыт в строе сообщений, и одно чтение даёт ровно одно
				 *          сообщение целиком. Не уместившееся в буфер система отдаёт
				 *          завершением с итогом переполнения буфера: принятая часть в
				 *          буфере есть, а остаток ждёт следующего чтения. Части эти и
				 *          складываются у узла, чтобы вызвавшему досталось сообщение
				 *          целым, а не разрезанным по размеру буфера
				 *
				 * @note Путь этот проходят одни лишь каналы: у сокета границ сообщений
				 *       нет вовсе, и отдавать принятое по частям там - обычный порядок
				 *
				 */
				{
					// Приводим узел к узлу обмена сообщениями между процессами
					::Ipc * ipc = ::__awh_ipc__(::__awh_find__(context->id));
					// Если завершение принесено каналом
					if(ipc != nullptr){
						// Если сообщение в буфер приёма не уместилось
						if(entries[i].Internal == ::__AWH_STATUS_BUFFER_OVERFLOW__){
							// Отмечаем завершившийся обмен
							ipc->pending--;
							// Откладываем принятую часть сообщения до прихода остатка
							ipc->partial.insert(ipc->partial.end(), context->buffer.begin(), context->buffer.begin() + received);
							// Заводим следующий приём, отдавая ему то же описание обмена
							::__awh_recv_pipe__(ipc, context);
							// Переходим к следующему завершению
							continue;
						}
						// Если начало сообщения уже отложено
						if(!ipc->partial.empty() && (received > 0)){
							// Дополняем отложенное принятым остатком
							ipc->partial.insert(ipc->partial.end(), context->buffer.begin(), context->buffer.begin() + received);
							// Переносим собранное сообщение в буфер обмена
							context->buffer.swap(ipc->partial);
							// Запоминаем размер собранного сообщения
							received = context->buffer.size();
							// Очищаем отложенное
							ipc->partial.clear();
						}
					}
				}
				// Функция обратного вызова на чтение данных
				engine::callback::read_t callback = nullptr;
				// Признак того, что узел ещё жив
				bool alive = false;
				{
					// Выполняем поиск узла события
					::Node * item = ::__awh_find__(context->id);
					// Приводим узел к узлу, за которым стоит сокет
					::Socket * socket = ::__awh_socket__(item);
					// Приводим узел к ведущему обмен данными
					::Transfer * transfer = ::__awh_transfer__(item);
					// Если узел найден
					if(transfer != nullptr){
						// Отмечаем завершившийся обмен
						transfer->pending--;
						// Запоминаем, что узел жив
						alive = true;
						// Если данные приняты и узел запущен
						if((received > 0) && (transfer->state.status == event::status_t::LAUNCHED))
							// Получаем функцию обратного вызова на чтение данных
							{
							// Получаем обратный вызов приёма данных
							engine::callback::read_t * reader = ::__awh_read__(item);
							// Если приём данных виду узла сообщается
							if(reader != nullptr)
								// Получаем функцию обратного вызова на приём данных
								callback = (* reader);
						}
					}
				}
				// Если собеседник закрыл свою сторону
				if(alive && (received == 0)){
					// Откладываем узел до извещения об обрыве
					disconnected.emplace_back(context->id);
					// Выполняем освобождение описания приёма
					delete context;
					// Переходим к следующему завершению
					continue;
				}
				/**
				 * Раздаём принятое прямо из буфера обмена
				 *
				 * @details Ни переноса, ни копирования здесь нет: буфер этот система
				 *          наполнила сама, и вызывающему отдаётся он же. Раздача
				 *          ведётся после снятия завершения с порта - обратный вызов
				 *          вправе завести или уничтожить событие, и делать это посреди
				 *          разбора завершения нельзя
				 *
				 * @warning Буфер живёт лишь до возврата из обратного вызова: следом
				 *          он уходит под очередной приём. Кому принятое нужно
				 *          дольше, тот обязан снять с него свою копию
				 *
				 */
				if(callback != nullptr)
					// Передаём принятые данные
					callback(context->id, context->buffer.data(), received);
				{
					// Выполняем поиск узла события
					::Node * item = ::__awh_find__(context->id);
					// Приводим узел к узлу обмена сообщениями между процессами
					::Ipc * ipc = ::__awh_ipc__(item);
					// Заводим следующий приём, отдавая ему то же описание обмена
					if(!((ipc != nullptr) ? ::__awh_recv_pipe__(ipc, context) : ::__awh_recv__(::__awh_socket__(item), context)))
						// Если завести приём не удалось - описание уже освобождено
						context = nullptr;
				}
				// Переходим к следующему завершению
				continue;
			} break;
			/**
			 * Если завершилась отправка в сокет
			 */
			case static_cast <uint8_t> (::op_t::SEND): {
				// Функция обратного вызова на запись данных
				engine::callback::write_t callback = nullptr;
				{
					// Выполняем поиск узла события
					::Transfer * item = ::__awh_transfer__(::__awh_find__(context->id));
					// Если узел найден
					if(item != nullptr){
						// Отмечаем завершившийся обмен
						item->pending--;
						// Получаем функцию обратного вызова на запись данных
						{
							// Получаем обратный вызов отдачи данных
							engine::callback::write_t * writer = ::__awh_write__(item);
							// Если отдача данных виду узла сообщается
							if(writer != nullptr)
								// Получаем функцию обратного вызова на отдачу данных
								callback = (* writer);
						}
					}
				}
				// Если функция обратного вызова на запись установлена
				if(callback != nullptr)
					// Извещаем отправителя об отданных данных
					callback(context->id, static_cast <size_t> (entries[i].dwNumberOfBytesTransferred));
			} break;
			/**
			 * Если завершилось ожидание подключения встречной стороны канала
			 *
			 * @note Приём заводится тем же описанием обмена: буфер под него уже
			 *       отведён, а вид описания меняется при заведении
			 *
			 */
			case static_cast <uint8_t> (::op_t::LISTEN): {
				// Приводим узел к узлу обмена сообщениями между процессами
				::Ipc * ipc = ::__awh_ipc__(::__awh_find__(context->id));
				// Если узел канала найден
				if(ipc != nullptr){
					// Отмечаем завершившийся обмен
					ipc->pending--;
					// Заводим приём из подключившегося канала
					if(::__awh_recv_pipe__(ipc, context))
						// Описание обмена ушло под приём и освобождению здесь не подлежит
						context = nullptr;
				}
				// Если описание обмена никому не досталось
				if(context != nullptr)
					// Выполняем освобождение описания ожидания
					delete context;
				// Переходим к следующему завершению
				continue;
			} break;
			/**
			 * Если завершилась установка исходящей связи
			 *
			 * @note Установленной связи система не сообщает сокету сама: сокет о
			 *       ней узнаёт лишь после особой настройки, и без неё ни своего
			 *       адреса, ни адреса собеседника у него не спросить
			 *
			 */
			case static_cast <uint8_t> (::op_t::CONNECT): {
				// Признак успешной установки связи
				bool established = false;
				// Функция обратного вызова на установку связи
				engine::callback::connect_t callback = nullptr;
				{
					// Выполняем поиск узла события
					::Transfer * item = ::__awh_transfer__(::__awh_find__(context->id));
					// Если узел найден
					if(item != nullptr){
						// Отмечаем завершившийся обмен
						item->pending--;
						// Выполняем настройку сокета установленной связью
						established = (::setsockopt(static_cast <::Client *> (item)->socket, SOL_SOCKET, SO_UPDATE_CONNECT_CONTEXT, nullptr, 0) == 0);
						// Получаем функцию обратного вызова на установку связи
						callback = static_cast <::Client *> (item)->callbacks.connect;
						// Если связь установлена
						if(established){
							// Применяем к сокету запомненную отметку класса обслуживания
							win::qos::apply(static_cast <net::socket_t> (static_cast <::Client *> (item)->socket), nullptr);
							// Заводим приём из сокета вперёд
							::__awh_recv__(static_cast <::Client *> (item));
						}
					}
				}
				// Если функция обратного вызова на установку связи установлена
				if(callback != nullptr)
					// Извещаем о завершении установки связи
					callback(context->id, established);
			} break;
			/**
			 * Если завершилось принятие входящей связи
			 *
			 * @note Принятому сокету настройки слушающего не достаются сами: их
			 *       переносит особая настройка, без которой сокет этот неполон
			 *
			 */
			case static_cast <uint8_t> (::op_t::ACCEPT): {
				// Идентификатор заведённого узла принятой связи
				event::id_t accepted = 0;
				// Функция обратного вызова на принятие входящей связи
				engine::callback::accept_t callback = nullptr;
				{
					// Выполняем поиск узла события
					::Transfer * item = ::__awh_transfer__(::__awh_find__(context->id));
					// Если узел найден
					if(item != nullptr){
						// Отмечаем завершившийся обмен
						item->pending--;
						// Переносим настройки слушающего сокета на принятый
						if(::setsockopt(context->socket, SOL_SOCKET, SO_UPDATE_ACCEPT_CONTEXT, reinterpret_cast <const char *> (&static_cast <::Server *> (item)->socket), sizeof(SOCKET)) == 0){
							// Заводим узел принятой связи
							std::unique_ptr <::Peer> peer = std::make_unique <::Peer> ();
							// Устанавливаем идентификатор узла, пропуская нулевой
							peer->id = ++::__awh_last_id__;
							/**
							 * Устанавливаем вид узла
							 *
							 * @note Принятая связь заводится узлом своего вида, а не
							 *       клиентом: исходящей связи она не устанавливает, и
							 *       ни конечная точка обмена, ни вызов её установки ей
							 *       не нужны вовсе
							 *
							 */
							peer->state.node = event::node_t::PEER;
							// Устанавливаем семейство событий
							peer->state.family = item->state.family;
							// Устанавливаем вид передачи данных
							peer->state.type = item->state.type;
							// Устанавливаем протокол передачи данных
							peer->state.protocol = item->state.protocol;
							// Устанавливаем состояние узла
							peer->state.status = event::status_t::LAUNCHED;
							// Устанавливаем сокет принятой связи
							peer->socket = context->socket;
							// Запоминаем идентификатор заведённого узла
							accepted = peer->id;
							// Связываем сокет принятой связи с портом завершения
							::CreateIoCompletionPort(reinterpret_cast <HANDLE> (peer->socket), ::__awh_port__, static_cast <ULONG_PTR> (peer->id), 0);
							// Добавляем узел принятой связи в список заведённых
							::__awh_nodes__.emplace(accepted, ::std::move(peer));
							// Получаем функцию обратного вызова на принятие входящей связи
							callback = static_cast <::Server *> (item)->callbacks.accept;
						// Если перенести настройки не удалось
						} else ::closesocket(context->socket);
						// Заводим следующее принятие входящей связи вперёд
						::__awh_accept__(static_cast <::Server *> (item));
					// Если узел исчез - принятая связь никому не нужна
					} else ::closesocket(context->socket);
				}
				// Если функция обратного вызова на принятие входящей связи установлена
				if(callback != nullptr)
					// Извещаем о принятой входящей связи
					callback(context->id, accepted);
				// Если узел принятой связи заведён
				if(accepted > 0){
					// Выполняем поиск заведённого узла
					::Socket * peer = ::__awh_socket__(::__awh_find__(accepted));
					// Если узел найден
					if(peer != nullptr)
						/**
						 * Заводим приём из сокета вперёд
						 *
						 * @note Заводится он именно здесь, после извещения: до него
						 *       подписки на чтение ещё нет, и принятое ушло бы в никуда
						 *
						 */
						::__awh_recv__(peer);
				}
			} break;
		}
		// Выполняем освобождение описания завершившегося обмена
		delete context;
	}
	/**
	 * Раздаём принятые сообщения
	 *
	 * @note Раздача ведётся после разбора всего снятого с порта: обратный вызов
	 *       вправе завести или уничтожить событие, и делать это посреди разбора
	 *       нельзя
	 *
	 */
	for(auto & message : messages){
		// Функция обратного вызова на чтение сообщений
		engine::callback::read_t callback = nullptr;
		{
			// Выполняем поиск узла события
			::Transfer * item = ::__awh_transfer__(::__awh_find__(message.first));
			// Если узел найден и запущен
			if((item != nullptr) && (item->state.status == event::status_t::LAUNCHED))
				// Получаем функцию обратного вызова на чтение сообщений
				{
					// Получаем обратный вызов приёма данных
					engine::callback::read_t * reader = ::__awh_read__(item);
					// Если приём данных виду узла сообщается
					if(reader != nullptr)
						// Получаем функцию обратного вызова на приём данных
						callback = (* reader);
				}
		}
		// Если функция обратного вызова на чтение установлена
		if(callback != nullptr)
			// Передаём принятое сообщение
			callback(message.first, message.second.data(), message.second.size());
	}
	/**
	 * Уничтожаем узлы, у которых собеседник закрыл свою сторону
	 *
	 * @note Порядок этот взят у эталонных движков: закрытая собеседником связь
	 *       годной к работе больше не бывает, и узел за нею не сохраняется
	 *
	 */
	for(const auto & id : disconnected){
		// Функция обратного вызова на изменение состояния
		engine::callback::status_t callback = nullptr;
		{
			// Выполняем поиск узла события
			::Node * item = ::__awh_find__(id);
			// Если узел уже уничтожен
			if(item == nullptr)
				// Переходим к следующему узлу
				continue;
			// Получаем общие обратные вызовы узла
			::Callbacks * callbacks = ::__awh_callbacks__(item);
			// Если обратные вызовы у узла есть
			if(callbacks != nullptr)
				// Получаем функцию обратного вызова на изменение состояния
				callback = callbacks->status;
			// Выполняем закрытие всего, что числится за узлом
			::__awh_close__(item);
			// Выполняем изъятие узла из списка заведённых
			::__awh_nodes__.erase(id);
		}
		// Если функция обратного вызова на изменение состояния установлена
		if(callback != nullptr)
			// Извещаем об уничтожении события
			callback(id, event::status_t::DESTROYED);
	}
	/**
	 * Разбираем истёкшие сроки событий
	 *
	 * @note Разбор идёт по завершении раздачи намеренно: обмен, состоявшийся этим
	 *       же обходом, снимает поставленные ему сроки, и разбор прежде раздачи
	 *       сработал бы по срокам, какие снять уже собрались
	 *
	 */
	::__awh_expire__();
	// Сообщаем, что обход петли выполнен
	return true;
}

/**
 * @brief Метод установки функции обратного вызова для обработки события чтения
 *
 * @details Подписка на приём данных. Буфер, приходящий в функцию,
 *          принадлежит движку и действителен **только на время вызова**:
 *          он переиспользуется под следующее чтение, поэтому данные,
 *          нужные позже, следует скопировать.
 *
 * @par Общие правила для всех перегрузок `on()`
 * Все перегрузки устроены одинаково, и сказанное здесь относится к
 * каждой из них.
 *
 * Подписка выполняется **присваиванием**: повторный вызов с тем же типом
 * функции заменяет прежнюю, не добавляя вторую. Двух обработчиков одного
 * события одного вида быть не может, а передача пустой функции подписку
 * снимает.
 *
 * Подписываться можно в любой момент, а не только до `commit()`. В
 * частности, принятое подключение приходит уже заведённым событием, и
 * подписки ему выставляются прямо в функции приёма - как в примере к
 * описанию класса.
 *
 * Неизвестный идентификатор и событие, помеченное к уничтожению,
 * **игнорируются молча**: ни исключения, ни возвращаемого признака здесь
 * нет. Если же тип функции узлу не подходит - скажем, чтение для узла
 * сервера, - в лог уходит предупреждение, а подписка не выставляется.
 * Поэтому список поддерживаемых типов узлов указан у каждой перегрузки
 * отдельно, и сверяться с ним стоит: опечатка в типе узла тихо оставит
 * событие без обработчика.
 *
 * Вызывать `on()` изнутри функции обратного вызова безопасно, включая
 * замену обработчика на самого себя.
 *
 * @note Приведение через `static_cast` требуется там, где по одной лямбде
 *       перегрузку не выбрать однозначно. Так происходит с парой
 *       `write_t` и `connect_t`: их второй параметр - `size_t` и `bool`, а
 *       они приводятся друг к другу неявно. Перегрузки, различающиеся
 *       типами перечислений или типом возврата, выбираются сами, и
 *       приведения не требуют
 *
 * @par Поддерживаемые типы узлов
 * `FILE`, `NOTIFY`, `IPC`, `PEER`, `ORIGIN`, `MEDIATOR`, `CLIENT`
 *
 * @param id идентификатор события
 * @param cb функция обратного вызова
 *
 */
void awh::engine::IO::on([[maybe_unused]] const event::id_t id, [[maybe_unused]] engine::callback::read_t cb) noexcept {
	// Выполняем поиск узла события
	::Node * item = ::__awh_find__(id);
	// Получаем обратный вызов приёма данных
	engine::callback::read_t * callback = ::__awh_read__(item);
	// Если узел не найден — подключать обратную связь некому
	if(item == nullptr){
		// Заносим в журнал предупреждение об отсутствии узла события
		this->_log->print("%s: event %u not found, callback \"read\" is not connected", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, id);
		// Выходим из метода
		return;
	}
	// Если приём данных виду узла не сообщается
	if(callback == nullptr){
		// Заносим в журнал предупреждение о неприменимости обратного вызова
		this->_log->print("%s: callback \"read\" is not applicable to event %u", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, id);
		// Выходим из метода
		return;
	}
	// Устанавливаем функцию обратного вызова
	(* callback) = cb;
}

