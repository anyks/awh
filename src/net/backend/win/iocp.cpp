/**
 * @brief Метод отправки данных события
 *
 * @param id     идентификатор события
 * @param buffer буфер данных для отправки
 * @param size   размер данных для отправки
 * @return       количество байт данных, отправленных событием
 *
 * @note Временное ядро принимает сообщение целиком либо не принимает вовсе:
 *       очередь его не ограничена, и частичной отправки, какая бывает у
 *       сокета с заполненным буфером, здесь не случается
 *
 */
size_t awh::engine::IO::send(const event::id_t id, const void * buffer, const size_t size) noexcept {
	// Если данные для отправки не переданы
	if((buffer == nullptr) || (size == 0))
		// Возвращаем количество отправленных байт
		return 0;
	// Количество отправленных байт
	size_t written = 0;
	// Код отказа отправки, нулевой при её успехе
	DWORD code = 0;
	// Функция обратного вызова на запись сообщений
	engine::callback::write_t callback = nullptr;
	// Функция обратного вызова на получение ошибок
	engine::callback::error_t failure = nullptr;
	{
		// Выполняем поиск узла события
		::Node * item = ::__awh_find__(id);
		// Приводим узел к узлу обмена сообщениями между процессами
		::Ipc * ipc = ::__awh_ipc__(item);
		// Получаем общие обратные вызовы узла
		::Callbacks * callbacks = ::__awh_callbacks__(item);
		// Получаем обратный вызов отдачи данных
		engine::callback::write_t * writer = ::__awh_write__(item);
		/**
		 * Узел сокета отдаёт данные наложенным обменом
		 *
		 * @details Отправка не ждёт, пока данные уйдут в сеть: система забирает их
		 *          себе и сообщает завершением, когда закончит. Оттого буфер и
		 *          копируется в описание обмена - память вызвавшего к тому времени
		 *          вправе уже не существовать
		 *
		 * @note Отправок вправе быть заведено несколько разом: порядок их система
		 *       блюдёт сама, и для потокового сокета данные придут собеседнику в
		 *       том же порядке, в каком заводились
		 *
		 */
		{
			// Получаем узел, от имени которого ведётся отправка
			::Socket * sender = ::__awh_socket__(item);
			// Если узел найден и за ним стоит сокет
			if((sender != nullptr) && (sender->socket != INVALID_SOCKET)){
				// Если узел закрывается - отправлять больше нечего
				if(sender->closing)
					// Возвращаем отсутствие отправленных байт
					return 0;
				// Заводим описание отправки
				::Overlapped * context = new ::Overlapped(::op_t::SEND, id);
				// Наполняем буфер отправки
				context->buffer.assign(reinterpret_cast <const uint8_t *> (buffer), reinterpret_cast <const uint8_t *> (buffer) + size);
				// Описание буфера отправки для библиотеки сокетов
				WSABUF outgoing{};
				// Устанавливаем размер буфера отправки
				outgoing.len = static_cast <ULONG> (context->buffer.size());
				// Устанавливаем сам буфер отправки
				outgoing.buf = reinterpret_cast <char *> (context->buffer.data());
				// Число отданных байт
				DWORD sent = 0;
				// Если завести отправку не удалось
				if((::WSASend(sender->socket, &outgoing, 1, &sent, 0, &context->overlapped, nullptr) != 0) && (::WSAGetLastError() != WSA_IO_PENDING)){
					// Заносим в журнал предупреждение об отказе отправки
					this->_log->print("%s: data could not be sent, error %d", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, ::WSAGetLastError());
					// Выполняем освобождение описания отправки
					delete context;
					// Возвращаем отсутствие отправленных байт
					return 0;
				}
				// Отмечаем заведённый обмен незавершённым
				sender->pending++;
				// Возвращаем размер принятых к отправке данных
				return size;
			}
		}

		// Если узел не найден — отправлять некуда
		if(item == nullptr)
			// Возвращаем количество отправленных байт
			return 0;
		// Получаем функцию обратного вызова на запись сообщений
		callback = ((writer != nullptr) ? (* writer) : nullptr);
		// Получаем функцию обратного вызова на получение ошибок
		failure = ((callbacks != nullptr) ? callbacks->error : nullptr);
		/**
		 * Отправляем сообщение в именованный канал, если тот за узлом стоит
		 *
		 * @details Путь этот и есть настоящий обмен между процессами: запись уходит в
		 *          канал, а принимает её встречная сторона - в своём процессе либо в
		 *          чужом, безразлично. Строй сообщений сохраняет границы, оттого одна
		 *          запись даёт ровно одно чтение
		 *
		 * @note Очередь узла-собеседника ниже остаётся для узла пробуждения и для пар,
		 *       заведённых без канала: там обмен ведётся внутри одного процесса
		 *
		 */
		if((item->state.node == event::node_t::IPC) && (ipc->handle != INVALID_HANDLE_VALUE)){
			/**
			 * Отправка лишь заводится, а завершение её придёт портом
			 *
			 * @details Ждать здесь, пока запись уйдёт, нельзя вовсе: встречная сторона
			 *          вправе читать не сейчас, а канал вправе оказаться полон - и
			 *          ожидание остановило бы петлю событий целиком. Оттого буфер и
			 *          копируется в описание обмена: память вызвавшего к возврату из
			 *          метода своё уже отживёт, а системе она нужна до конца записи
			 *
			 */
			// Заводим описание отправки
			::Overlapped * context = new ::Overlapped(::op_t::SEND, ipc->id);
			// Наполняем буфер отправки
			context->buffer.assign(reinterpret_cast <const uint8_t *> (buffer), reinterpret_cast <const uint8_t *> (buffer) + size);
			// Если завести отправку не удалось
			if(!::WriteFile(ipc->handle, context->buffer.data(), static_cast <DWORD> (context->buffer.size()), nullptr, &context->overlapped) && (::GetLastError() != ERROR_IO_PENDING)){
				// Запоминаем код отказа отправки
				code = ::GetLastError();
				// Выполняем освобождение описания отправки
				delete context;
			// Если отправка заведена
			} else {
				// Отмечаем заведённый обмен незавершённым
				ipc->pending++;
				// Запоминаем количество принятых к отправке байт
				written = size;
				/**
				 * Извещение об отправке отдаётся её завершением, а не отсюда
				 *
				 * @note Снятие вызова здесь намеренно: сообщить об отданных байтах
				 *       прежде, чем они отданы, значило бы обмануть вызвавшего
				 *
				 */
				callback = nullptr;
			}
		/**
		 * Если настоящего канала за узлом нет - сообщение ложится в очередь собеседника
		 */
		} else {
			// Узел, которому предназначено сообщение
			::Node * target = nullptr;
			/**
			 * Определяем вид узла-отправителя
			 */
			switch(static_cast <uint8_t> (item->state.node)){
				/**
				 * Узел пробуждения принимает сообщение к себе же: отправитель кладёт байты
				 * в очередь узла, а петля отдаёт их в обратный вызов чтения. Так устроено
				 * извещение о завершившихся процессах у модуля кластера
				 */
				case static_cast <uint8_t> (event::node_t::NOTIFY):
					// Сообщение предназначено самому узлу
					target = item;
				break;
				/**
				 * Узел обмена сообщениями отправляет собеседнику: сообщение ложится в
				 * очередь второго узла пары, откуда петля отдаёт его в обратный вызов
				 * чтения. Границы сообщения при этом сохраняются
				 */
				case static_cast <uint8_t> (event::node_t::IPC):
					// Сообщение предназначено собеседнику по паре
					target = ::__awh_find__(ipc->peer);
				break;
			}
			// Если узел-получатель определить не удалось
			if(target == nullptr){
				// Заносим в журнал предупреждение о неподдерживаемом виде узла
				this->_log->print("%s: sending to node type %u is not supported yet", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, static_cast <uint16_t> (item->state.node));
				// Возвращаем количество отправленных байт
				return 0;
			}
			// Отдаём сообщение порту завершения от имени узла-получателя
			::__awh_post__(target->id, reinterpret_cast <const uint8_t *> (buffer), size);
			// Запоминаем количество отправленных байт
			written = size;
		}
	}
	/**
	 * Извещения отдаются после разбора: обратный вызов вправе завести или
	 * уничтожить событие, и делать это посреди разбора нельзя
	 */
	// Если отправка завершилась отказом
	if(code != 0){
		// Заносим в журнал предупреждение об отказе отправки
		this->_log->print("%s: message could not be sent, error %lu", log_t::flag_t::WARNING, ::__AWH_IO_BACKEND__, code);
		// Если функция обратного вызова на получение ошибок установлена
		if(failure != nullptr)
			// Извещаем об отказе отправки
			failure(id, event::error_t::EVENT_FAIL, this->_fmk->format("named pipe write failed, error %lu", code));
		// Возвращаем количество отправленных байт
		return 0;
	}
	// Если функция обратного вызова на запись сообщений установлена
	if(callback != nullptr)
		// Извещаем отправителя об отданном сообщении
		callback(id, written);
	// Пробуждаем петлю событий, чтобы та разобрала накопленное
	::__awh_wake__();
	// Возвращаем количество отправленных байт
	return written;
}

