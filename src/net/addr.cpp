/**
 * @brief Метод проверки вхождения IP-адреса в диапазон адресов
 *
 * @param begin  начало диапазона адресов
 * @param end    конец диапазона адресов
 * @param prefix префикс адреса для преобразования
 * @param type   тип адреса аппаратного или интернет подключения
 * @return       результат првоерки
 *
 */
bool awh::Network_Address::range(const Network_Address & begin, const Network_Address & end, const uint8_t prefix, const type_t type) const noexcept {
	// Переменная результата
	bool result = false;
	/**
	 * Вид сверяется и у самого адреса, а не у одних лишь границ: разбор вида
	 * ведётся по переданному, и адрес другой разновидности снимался бы чужим
	 * методом - у IPv6-адреса, проверяемого по границам IPv4, снятие
	 * четырёхбайтного значения давало ноль, и вхождение его в диапазон решалось
	 * сравнением нуля с границами
	 */
	// Если виды адресов совпадают
	if((type == this->type()) && (type == begin.type()) && (type == end.type())){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			// Количество байт, занятых адресом переданной разновидности
			const size_t size = this->_buffer.size();
			// Предел префикса, свойственный разновидности адреса
			const uint8_t limit = static_cast <uint8_t> (size * 8);
			/**
			 * Сравнение ведётся по копиям буферов, а не по временным объектам адреса:
			 * прежде их заводилось по три на вызов, и каждый снимал значение адреса
			 * копированием туда и обратно. Наложение же и сличение обходятся одними
			 * байтами, а буфер адреса невелик и укладывается на стеке
			 */
			// Признак того, что разновидность адреса деление префиксом допускает
			const bool network = ((type == type_t::IPV4) || (type == type_t::IPV6));
			// Если границы диапазона той же длины, а префикс укладывается в диапазон адреса
			if(network && (size > 0) && (prefix > 0) && (prefix <= limit) && (begin._buffer.size() == size) && (end._buffer.size() == size)){
				// Буферы проверяемого адреса и границ диапазона
				uint8_t addr[buffer_t::CAPACITY], first[buffer_t::CAPACITY], second[buffer_t::CAPACITY];
				// Выполняем копирование байт проверяемого адреса
				::memcpy(addr, &this->_buffer[0], size);
				// Выполняем копирование байт начала диапазона
				::memcpy(first, &begin._buffer[0], size);
				// Выполняем копирование байт конца диапазона
				::memcpy(second, &end._buffer[0], size);
				// Выполняем наложение префикса на проверяемый адрес
				::imposeBytes(addr, size, prefix, false);
				// Выполняем наложение префикса на начало диапазона
				::imposeBytes(first, size, prefix, false);
				// Выполняем наложение префикса на конец диапазона
				::imposeBytes(second, size, prefix, false);
				// Выполняем определение результата вхождения адреса в диапазон
				result = ((::memcmp(addr, first, size) >= 0) && (::memcmp(addr, second, size) <= 0));
			}
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug(
					"%s", __PRETTY_FUNCTION__,
					make_tuple(static_cast <uint16_t> (prefix), static_cast <uint16_t> (type)),
					log_t::flag_t::CRITICAL, error.what()
				);
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
			#endif
		}
	}
	// Возвращаем результат
	return result;
}
