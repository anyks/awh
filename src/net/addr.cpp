/**
 * @brief Метод проверки соответствия адреса зеркалу IPv6 => IPv4
 *
 * @return результат проверки
 *
 */
bool awh::Network_Address::broadcastIPv6ToIPv4() const noexcept {
	// Если бинарный буфер данных является полноценным IPv6-адресом
	if(this->_buffer.size() == 16){
		/**
		 * Примета вложения IPv4 в IPv6: десять нулевых октетов и хекстет FFFF.
		 * Сравниваем побайтно по сетевому порядку буфера, без временного массива
		 */
		static constexpr uint8_t mapped[12] = {
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0xFF, 0xFF
		};
		// Если буфер данных принадлежит к вещанию IPv6 => IPv4
		return (::memcmp(mapped, &this->_buffer[0], sizeof(mapped)) == 0);
	}
	// Возвращаем результат
	return false;
}
