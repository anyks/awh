/**
 * @brief Метод извлечения адреса IPv4 в чистом виде
 *
 * @param endian флаг формирования адреса в установленном порядке следовании байт
 * @return       адрес IPv4 в чистом виде
 *
 */
uint32_t awh::Network_Address::v4(const endian_t endian) const noexcept {
	// Переменная результата
	uint32_t result = 0;
	// Октеты адреса IPv4 в сетевом порядке, откуда собирается число
	const uint8_t * octets = nullptr;
	// Если объект хранит адрес IPv4, октеты берутся прямо из буфера
	if(this->_buffer.size() == 4)
		// Получаем октеты адреса из буфера данных
		octets = &this->_buffer[0];
	/**
	 * Объект хранит адрес IPv6, и адрес IPv4 извлекается из него вложенным
	 *
	 * @details Стандарт (RFC 4291) определяет два вложения: зеркало `::FFFF:a.b.c.d`
	 *          и устаревшую совместимую форму `::a.b.c.d`. В обоих адрес IPv4 занимает
	 *          последние четыре октета, и извлечь его оттуда однозначно
	 *
	 * @note Прочие адреса IPv6 в IPv4 не переводятся никак - такого преобразования
	 *       стандарт не определяет вовсе, - и для них итогом остаётся нуль
	 *
	 * @warning Совместимая форма отсеивает `::` и `::1`: у первого вложенный адрес
	 *          нулевой, у второго единичный, и оба означают вовсе не адрес IPv4, а
	 *          неопределённый адрес и петлю самого IPv6
	 *
	 */
	else if(this->_buffer.size() == 16) {
		// Если адрес принадлежит зеркалу IPv6 => IPv4
		if(this->broadcastIPv6ToIPv4())
			// Получаем октеты вложенного адреса
			octets = &this->_buffer[12];
		// Если первые двенадцать октетов нулевые, адрес принадлежит совместимой форме
		else if(::memcmp(&this->_buffer[0], __awh_zero_addr__, 12) == 0) {
			// Собираем вложенный адрес числом для отсева неопределённого адреса и петли
			const uint32_t nested = ::readNumber(&this->_buffer[12]);
			// Если вложенный адрес не является ни неопределённым адресом, ни петлёй
			if(nested > 1)
				// Получаем октеты вложенного адреса
				octets = &this->_buffer[12];
		}
	}
	// Если октеты адреса IPv4 получены
	if(octets != nullptr){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			/**
			 * Определяем какой порядок следования байт установлен
			 */
			switch(static_cast <uint8_t> (endian)){
				// Если установлен порядок следования байт от старшего к младшему
				case static_cast <uint8_t> (endian_t::BIG):
					// Получаем адрес IPv4 числом, собранным из октетов буфера
					result = ::readNumber(octets);
				break;
				// Если установлен порядок следования байт от младшего к старшему
				case static_cast <uint8_t> (endian_t::LITTLE):
					// Выполняем копирование данных адреса IPv4
					::memcpy(&result, octets, 4);
				break;
			}
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug(
					"%s", __PRETTY_FUNCTION__,
					make_tuple(static_cast <uint16_t> (endian)),
					log_t::flag_t::CRITICAL, error.what()
				);
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
			#endif
		}
	}
	// Возвращаем результат
	return result;
}
/**
 * @brief Метод установки адреса IPv4 в чистом виде
 *
 * @param addr   адрес IPv4 в чистом виде
 * @param endian флаг формирования адреса в установленном порядке следовании байт
 *
 */
void awh::Network_Address::v4(const uint32_t addr, const endian_t endian) noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Устанавливаем тип IP-адреса
		this->_type = type_t::IPV4;
		// Выполняем выделение памяти для IPv4 адреса
		this->_buffer.resize(4, 0);
		/**
		 * Определяем какой порядок следования байт установлен
		 */
		switch(static_cast <uint8_t> (endian)){
			// Если установлен порядок следования байт от старшего к младшему
			case static_cast <uint8_t> (endian_t::BIG):
				// Устанавливаем буфер данных IP-адреса октетами числа
				::writeNumber(&this->_buffer[0], addr);
			break;
			// Если установлен порядок следования байт от младшего к старшему
			case static_cast <uint8_t> (endian_t::LITTLE):
				// Выполняем копирование данных адреса IPv4
				::memcpy(&this->_buffer[0], &addr, sizeof(addr));
			break;
		}
		/**
		 * Адрес в чистом виде зоны не несёт: прежняя зона к новому содержимому
		 * отношения не имеет
		 */
		// Выполняем очистку зоны
		this->_zone.clear();
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug(
				"%s", __PRETTY_FUNCTION__,
				make_tuple(addr, static_cast <uint16_t> (endian)),
				log_t::flag_t::CRITICAL, error.what()
			);
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
/**
 * @brief Метод извлечения адреса IPv6 в чистом виде
 *
 * @param endian флаг формирования адреса в установленном порядке следовании байт
 * @return       адрес IPv6 в чистом виде
 *
 */
array <uint8_t, 16> awh::Network_Address::v6(const endian_t endian) const noexcept {
	// Переменная результата
	array <uint8_t, 16> result = {0};
	// Шестнадцать октетов адреса IPv6 в сетевом порядке, откуда собирается итог
	array <uint8_t, 16> origin = {0};
	// Флаг готовности октетов адреса IPv6
	bool ready = false;
	// Если объект хранит адрес IPv6, октеты берутся прямо из буфера
	if(this->_buffer.size() == 16){
		// Выполняем копирование октетов адреса из буфера данных
		::memcpy(&origin[0], &this->_buffer[0], 16);
		// Отмечаем готовность октетов адреса
		ready = true;
	/**
	 * Объект хранит адрес IPv4, и он выводится вложенным в адрес IPv6
	 *
	 * @details Стандарт (RFC 4291, §2.5.5.2) определяет для этого зеркало
	 *          `::FFFF:a.b.c.d`: десять нулевых октетов, хекстет `FFFF` и следом сам
	 *          адрес IPv4. Перевод в эту сторону возможен **всегда** и однозначен, в
	 *          отличие от обратного, определённого лишь для вложенных форм
	 *
	 * @note Тем самым извлечение числом отвечает согласно с выводом строкой: `print()`
	 *       выводит для такого объекта `::FFFF:a.b.c.d`, и октеты выходят те же.
	 *       Прежде вывод строкой преобразовывал, а извлечение числом отдавало нули, и
	 *       расхождение это обнаруживалось лишь опытом
	 *
	 */
	} else if(this->_buffer.size() == 4) {
		// Устанавливаем старший октет хекстета зеркала
		origin[10] = 0xFF;
		// Устанавливаем младший октет хекстета зеркала
		origin[11] = 0xFF;
		// Выполняем копирование октетов адреса IPv4 в хвост адреса IPv6
		::memcpy(&origin[12], &this->_buffer[0], 4);
		// Отмечаем готовность октетов адреса
		ready = true;
	}
	// Если октеты адреса IPv6 получены
	if(ready){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			/**
			 * Определяем какой порядок следования байт установлен
			 */
			switch(static_cast <uint8_t> (endian)){
				// Если установлен порядок следования байт от старшего к младшему
				case static_cast <uint8_t> (endian_t::BIG):
					// Получаем буфер данных IP-адреса
					::convertEndian <16> (&origin[0], reinterpret_cast <uint8_t *> (&result[0]));
				break;
				// Если установлен порядок следования байт от младшего к старшему
				case static_cast <uint8_t> (endian_t::LITTLE):
					// Выполняем копирование данных адреса IPv6
					::memcpy(&result[0], &origin[0], 16);
				break;
			}
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug(
					"%s", __PRETTY_FUNCTION__,
					make_tuple(static_cast <uint16_t> (endian)),
					log_t::flag_t::CRITICAL, error.what()
				);
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
			#endif
		}
	}
	// Возвращаем результат
	return result;
}
