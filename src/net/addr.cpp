/**
 * @brief Оператор [<] сравнения IP-адреса
 *
 * @param addr адрес для сравнения
 * @return     результат сравнения
 *
 */
bool awh::Network_Address::operator < (const net_addr_t & addr) const noexcept {
	// Переменная результата
	bool result = false;
	// Если IP-адреса принадлежат одному типу адресов
	if(this->type() == addr.type()){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			/**
			 * Определяем тип IP-адреса
			 */
			switch(static_cast <uint8_t> (this->_type)){
				// Если MAC-адрес определён
				/**
				 * Аппаратные адреса сравниваются побайтно прямо по буферу: он держит
				 * адрес в том же порядке, в каком тот и записывается, - от кода
				 * изготовителя к номеру устройства, - и побайтное сравнение даёт
				 * привычный порядок адресов.
				 *
				 * Прежде сравнение шло двоичным сличением чисел, а оно перебирает байты
				 * с последнего: адрес там принимался за число, записанное обратным
				 * порядком байт. Порядок адресов выходил перевёрнутым относительно кода
				 * изготовителя - "00:00:00:00:00:ff" оказывался старше "ff:00:00:00:00:00"
				 */
				case static_cast <uint8_t> (type_t::MAC):
					// Выполняем сравнение адресов
					result = (::memcmp(&this->_buffer[0], &addr._buffer[0], 6) < 0);
				break;
				/**
				 * Адреса IPv4 сравниваются побайтно прямо по буферу, как IPv6 и
				 * аппаратные: буфер держит адрес в сетевом порядке, где старший октет
				 * идёт первым, и побайтное сравнение даёт числовой порядок адресов.
				 * Прежде адрес снимался числом с разворотом порядка байт - порядок
				 * выходил тот же, но ценой двух снятий на сравнение
				 */
				// Если IP-адрес определён как IPv4
				case static_cast <uint8_t> (type_t::IPV4):
					// Выполняем сравнение адресов
					result = (::memcmp(&this->_buffer[0], &addr._buffer[0], 4) < 0);
				break;
				/**
				 * Адреса IPv6 сравниваются побайтно прямо по буферу: он держит адрес в
				 * сетевом порядке, где старший октет идёт первым, - именно в таком
				 * порядке побайтное сравнение и даёт числовой порядок адресов.
				 *
				 * Прежде адреса снимались через v6 с разворотом порядка байт, но
				 * разворачивался весь адрес целиком, а это не сетевой порядок, а его
				 * полная противоположность: адрес ::1 оказывался больше 8000::
				 */
				// Если IP-адрес определён как IPv6
				case static_cast <uint8_t> (type_t::IPV6):
					// Выполняем побайтное сравнение адресов в сетевом порядке
					result = (::memcmp(&this->_buffer[0], &addr._buffer[0], 16) < 0);
				break;
			}
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
			#endif
		}
	}
	// Возвращаем результат
	return result;
}
