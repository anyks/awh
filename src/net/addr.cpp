/**
 * @brief Метод проверки соотвествия IP-адреса указанной сети
 *
 * @param network сеть для проверки соответствия
 * @param type    тип адреса аппаратного или интернет подключения
 * @return        результат проверки
 *
 */
bool awh::Network_Address::mapping(string_view network, const type_t type) const noexcept {
	// Переменная результата
	bool result = false;
	// Если адрес сети передан
	if((result = !network.empty())){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			// Создаём объкт для работы с адресами
			net_addr_t net(this->_fmk, this->_log);
			// Если парсинг адреса сети выполнен
			if((result = net.parse(network))){
				/**
				 * Вид сверяется и у самого адреса, а не у одной лишь сети: снятие
				 * значения ведётся по переданному виду, и адрес другой разновидности
				 * снимался бы чужим методом - выходил ноль, а с ним и ложное
				 * соответствие сети
				 */
				// Если сеть и IP-адрес принадлежат одной версии сети
				if((result = ((type == this->type()) && (type == net.type())))){
					/**
					 * Сопоставление ведётся прямо по буферам: они держат адрес и сеть в
					 * сетевом порядке, где старший октет идёт первым, - в том самом, в каком
					 * части их и сопоставляются. Прежде и адрес, и сеть снимались
					 * копированием в целое и обратно в набор октетов, а порядок их выходил
					 * тем же
					 */
					// Количество байт, занятых адресом переданной разновидности
					const size_t size = this->_buffer.size();
					/**
					 * Дробность подстановки у разновидностей разная: у IPv4 части записи
					 * отделяются по октету, у IPv6 по хекстету, и значащей частью хекстет
					 * становится от любого из двух своих октетов
					 */
					// Количество байт в отделяемой части записи адреса
					const size_t step = ((type == type_t::IPV6) ? 2 : 1);
					// Если сеть той же длины, что и проверяемый адрес
					if((result = ((size > 0) && (net._buffer.size() == size)))){
						// Количество байт сети, занятых значащими её частями
						size_t last = size;
						/**
						 * Отсекаем хвостовые нули сети: части эти считаются подстановочными
						 */
						while(last > 0){
							// Признак того, что очередная часть записи сети нулевая
							bool zeroed = true;
							/**
							 * Перебираем все байты очередной части записи сети
							 */
							for(size_t i = (last - step); i < last; i++)
								// Запоминаем, остаётся ли часть записи нулевой
								zeroed = (zeroed && (net._buffer[i] == 0));
							// Если очередная часть сети значащая, отсекать больше нечего
							if(!zeroed)
								// Выходим из цикла
								break;
							// Отсекаем очередную подстановочную часть сети
							last -= step;
						}
						// Сопоставляем все значащие части сети с адресом
						result = (::memcmp(&this->_buffer[0], &net._buffer[0], last) == 0);
					}
				}
			}
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug(
					"%s", __PRETTY_FUNCTION__,
					make_tuple(network, static_cast <uint16_t> (type)),
					log_t::flag_t::CRITICAL, error.what()
				);
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
			#endif
		}
	}
	// Возвращаем результат
	return result;
}
