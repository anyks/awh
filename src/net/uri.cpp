	/**
	 * @brief Состояния парсинга URI
	 *
	 */
	enum class state_t : uint8_t {
		NONE      = 0x00, // Состояние парсинга URI не определено
		HOST      = 0x01, // Внутри авторити: хост
		PORT      = 0x02, // Внутри авторити: порт (после :)
		PATH      = 0x03, // Путь (до ? или #)
		QUERY     = 0x04, // Запрос (до #)
		SCHEME    = 0x05, // Читаем схему (до :)
		FRAGMENT  = 0x06, // Фрагмент (до конца)
		AUTHORITY = 0x07  // Читаем авторити (// ... до / ? #)
	};

	/**
	 * @brief Функция проверки допустимых символов в схеме URI
	 *
	 * @param letter символ для проверки
	 * @return       результат проверки
	 *
	 */
	[[nodiscard]] static inline bool isSchemeLetter(const char letter) noexcept {
		/**
		 * Проверяем, является ли символ допустимым для схемы URI (буква, цифра, +, -, .)
		 */
		return (
			((letter >= 'a') && (letter <= 'z')) ||
			((letter >= 'A') && (letter <= 'Z')) ||
			((letter >= '0') && (letter <= '9')) ||
			(letter == '+') || (letter == '-') || (letter == '.')
		);
	}

	/**
	 * @brief Функция проверки токена на незакрытую скобку адреса IPv6
	 *
	 * @details Разбор со схемы, признав токен хостом, переходит к его чтению и
	 *          заново перебирает уже пройденные символы не с начала: скобки адреса
	 *          IPv6 остаются позади, и признак нахождения внутри адреса ставился по
	 *          одной лишь первой из них. Токен же бывает и закрытым: у записи
	 *          "[)]:path" скобка закрыта, а двоеточие за нею разбор считал частью
	 *          адреса и хостом брал всю строку целиком
	 *
	 * @param begin начало проверяемого токена
	 * @param end   конец проверяемого токена
	 * @return      результат проверки
	 *
	 */
	[[nodiscard]] static inline bool openIPv6(const char * begin, const char * end) noexcept {
		// Если токен пустой либо открывающей скобки у него нет, то и адреса IPv6 в нём нет
		if((begin >= end) || ((* begin) != '['))
			// Выводим результат проверки
			return false;
		/**
		 * Перебираем все символы токена в поисках закрывающей скобки
		 */
		for(const char * letter = begin; letter < end; ++letter){
			// Если закрывающая скобка найдена, то адрес IPv6 уже закрыт
			if((* letter) == ']')
				// Выводим результат проверки
				return false;
		}
		// Скобка осталась незакрытой
		return true;
	}

	/**
	 * @brief Функция проверки наличия закрывающей скобки адреса IPv6 впереди
	 *
	 * @details Открывающая скобка вводила разбор внутрь адреса IPv6 без оглядки на
	 *          то, закрывается ли она вообще. Скобка непарная от этого заглатывала
	 *          всю авторити целиком: у записи "//a[b@e.com:80/x" хостом выходило
	 *          "a[b@e.com:80" - и собачка, и двоеточие порта считались частью
	 *          адреса. Хост с двоеточием внутри полный формат записи уже не
	 *          собирал: приписанный им порт прирастал с каждым оборотом
	 *
	 * @param begin начало проверяемого участка
	 * @param end   конец строки
	 * @return      результат проверки
	 *
	 */
	[[nodiscard]] static inline bool closeIPv6(const char * begin, const char * end) noexcept {
		/**
		 * Перебираем символы до конца авторити
		 */
		for(const char * letter = begin; letter < end; ++letter){
			// Если закрывающая скобка найдена, то это и вправду адрес IPv6
			if((* letter) == ']')
				// Выводим результат проверки
				return true;
			// Если авторити кончилась раньше, то скобка непарная
			if(((* letter) == '/') || ((* letter) == '?') || ((* letter) == '#'))
				// Выводим результат проверки
				return false;
		}
		// Скобка осталась незакрытой
		return false;
	}

	/**
	 * @brief Функция проверки токена на приметы хоста
	 *
	 * @details Схемы у адреса может не быть, и хост тогда отбирается по примете -
	 *          наличию точки: "www.example.com/path" разбирается как хост с путём,
	 *          а "path/to/file" - как путь целиком. Примета эта, однако, срабатывала
	 *          и на обозначениях текущего и родительского каталога: относительная
	 *          ссылка "./g" разбиралась как хост "." с путём "/g", а "../g" - как
	 *          хост "..". Ссылки эти сервер отдаёт в заголовке Location, и хостом
	 *          у них оказывалась точка.
	 *
	 *          Токен, состоящий из одних точек, хостом быть не может: метка
	 *          доменного имени пустой не бывает (RFC 1123 2.1)
	 *
	 * @param begin начало проверяемого токена
	 * @param end   конец проверяемого токена
	 * @return      результат проверки
	 *
	 */
	/**
	 * @brief Функция проверки хоста на наличие управляющих символов
	 *
	 * @details Управляющий символ в хосте недопустим ни одной из разновидностей
	 *          адреса: ни доменное имя, ни адрес сети его не содержат (RFC 1123 2.1,
	 *          RFC 3986 3.2.2). Процент-кодирование его не спасает: хост при разборе
	 *          не раскодируется и при сборке не кодируется, - и записанный в хост
	 *          перевод строки выходил из сборки как есть, разрывая заголовок,
	 *          в который собранный адрес подставлен
	 *
	 * @param host хост URI для проверки
	 * @return     результат проверки
	 *
	 */
	[[nodiscard]] static inline bool hasControl(string_view host) noexcept {
		/**
		 * Перебираем все символы хоста
		 */
		for(const char letter : host){
			// Если символ является управляющим
			if((static_cast <uint8_t> (letter) < 0x20) || (static_cast <uint8_t> (letter) == 0x7F))
				// Выводим, что управляющий символ в хосте найден
				return true;
		}
		// Выводим, что управляющих символов в хосте нет
		return false;
	}

	/**
	 * @brief Функция проверки хоста на приметы, установщику негодные
	 *
	 * @details Управляющий символ и пробел - единственное, чем хост отвергается.
	 *          Проверяются они вместе и в одном месте: по этой же примете
	 *          разрешение записи берёт снимок прежнего адреса, и разойдись две
	 *          проверки - отвергнутый хост снимка бы не получил, а адрес остался
	 *          бы полусобранным.
	 *
	 *          Примета эта грубее самого отказа: пробел законен в пути файловой
	 *          системы, и установщик его там принимает. Грубость безобидна -
	 *          лишний снимок стоит памяти, а нехватка снимка стоит адреса
	 *
	 * @param host хост URI для проверки
	 * @return     результат проверки
	 *
	 */
	[[nodiscard]] static inline bool suspiciousHost(string_view host) noexcept {
		/**
		 * Перебираем все символы хоста
		 */
		for(const char letter : host){
			// Пробел, управляющий символ и знак удаления хост отвергают
			if((static_cast <uint8_t> (letter) <= 0x20) || (static_cast <uint8_t> (letter) == 0x7F))
				// Выводим, что примета отказа в хосте найдена
				return true;
		}
		// Выводим, что примет отказа в хосте нет
		return false;
	}

	[[nodiscard]] static inline bool hostLike(const char * begin, const char * end) noexcept {
		// Признак наличия точки в токене
		bool dot = false;
		// Признак наличия символа, точкой не являющегося
		bool other = false;
		/**
		 * Перебираем все символы токена
		 */
		for(const char * letter = begin; letter < end; ++letter){
			// Если встретилась точка, запоминаем её наличие
			if((* letter) == '.')
				// Запоминаем наличие точки в токене
				dot = true;
			// Иначе запоминаем наличие символа, точкой не являющегося
			else other = true;
		}
		// Выводим результат проверки токена на приметы хоста
		return (dot && other);
	}

