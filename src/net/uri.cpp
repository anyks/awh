using namespace std;

/**
 * @brief Инкапсулируем парсинг URI в пространство имён
 *
 */
namespace uri {
	/**
	 * Подписываемся на пространство имён AWH
	 */
	using namespace awh;

	/**
	 * @brief Состояния парсинга URI
	 *
	 */
	enum class state_t : uint8_t {
		NONE      = 0x00, // Состояние парсинга URI не определено
		HOST      = 0x01, // Внутри авторити: хост
		PORT      = 0x02, // Внутри авторити: порт (после :)
		PATH      = 0x03, // Путь (до ? или #)
		QUERY     = 0x04, // Запрос (до #)
		SCHEME    = 0x05, // Читаем схему (до :)
		FRAGMENT  = 0x06, // Фрагмент (до конца)
		AUTHORITY = 0x07  // Читаем авторити (// ... до / ? #)
	};

	/**
	 * @brief Функция проверки допустимых символов в схеме URI
	 *
	 * @param letter символ для проверки
	 * @return       результат проверки
	 *
	 */
	[[nodiscard]] static inline bool isSchemeLetter(const char letter) noexcept {
		/**
		 * Проверяем, является ли символ допустимым для схемы URI (буква, цифра, +, -, .)
		 */
		return (
			((letter >= 'a') && (letter <= 'z')) ||
			((letter >= 'A') && (letter <= 'Z')) ||
			((letter >= '0') && (letter <= '9')) ||
			(letter == '+') || (letter == '-') || (letter == '.')
		);
	}

	/**
	 * @brief Функция проверки токена на приметы хоста
	 *
	 * @details Схемы у адреса может не быть, и хост тогда отбирается по примете -
	 *          наличию точки: "www.example.com/path" разбирается как хост с путём,
	 *          а "path/to/file" - как путь целиком. Примета эта, однако, срабатывала
	 *          и на обозначениях текущего и родительского каталога: относительная
	 *          ссылка "./g" разбиралась как хост "." с путём "/g", а "../g" - как
	 *          хост "..". Ссылки эти сервер отдаёт в заголовке Location, и хостом
	 *          у них оказывалась точка.
	 *
	 *          Токен, состоящий из одних точек, хостом быть не может: метка
	 *          доменного имени пустой не бывает (RFC 1123 2.1)
	 *
	 * @param begin начало проверяемого токена
	 * @param end   конец проверяемого токена
	 * @return      результат проверки
	 *
	 */
	[[nodiscard]] static inline bool hostLike(const char * begin, const char * end) noexcept {
		// Признак наличия точки в токене
		bool dot = false;
		// Признак наличия символа, точкой не являющегося
		bool other = false;
		/**
		 * Перебираем все символы токена
		 */
		for(const char * letter = begin; letter < end; ++letter){
			// Если встретилась точка, запоминаем её наличие
			if((* letter) == '.')
				// Запоминаем наличие точки в токене
				dot = true;
			// Иначе запоминаем наличие символа, точкой не являющегося
			else other = true;
		}
		// Выводим результат проверки токена на приметы хоста
		return (dot && other);
	}

	/**
	 * @brief Парсинг URI в один проход (Single Pass)
	 *
	 * @param uri      строка URI для парсинга
	 * @param scheme   ссылка для сохранения схемы URI
	 * @param userinfo ссылка для сохранения параметров пользователя URI
	 * @param host     ссылка для сохранения хоста URI
	 * @param port     ссылка для сохранения порта URI
	 * @param path     ссылка для сохранения пути URI
	 * @param query    ссылка для сохранения параметров URI
	 * @param fragment ссылка для сохранения якоря URI
	 * @return         результат парсинга
	 *
	 */
	[[nodiscard]] static bool parse(
		string_view uri,
		string_view & scheme,
		string_view & userinfo,
		string_view & host,
		string_view & port,
		string_view & path,
		string_view & query,
		string_view & fragment
	) noexcept {
		// Инициализируем все выходные параметры пустыми строками
		scheme = userinfo = host = port = path = query = fragment = {};
		// Если URI пустой
		if(uri.empty())
			// Возвращаем результат парсинга
			return false;
		// Итератор на начало строки
		const char * begin = uri.data();
		// Итератор на текущую позицию в строке
		const char * ptr = begin;
		// Итератор на конец строки для оптимизации сравнения
		const char * end = (begin + uri.size());
		// Указатели на начало текущей лексемы
		const char * tokenBegin = begin;
		// Флаг для обработки [IPv6]
		bool inIPv6 = false;
		// Флаг для проверки валидности схемы URI
		bool schemeValid = false;
		// Флаг для определения наличия авторити (//)
		bool hasAuthority = false;
		// Текущее состояние парсинга URI
		state_t state = state_t::SCHEME;
		// Вспомогательный маркер для хоста URI
		const char * hostBegin = nullptr;
		// Вспомогательный маркер для userinfo
		const char * userinfoBegin = nullptr;
		/**
		 * Ссылка сетевого пути начинается с двух косых черт и схемы не несёт
		 * (RFC 3986 4.2): за ними сразу стоит авторити. Разбор со схемы такую
		 * ссылку принимал за путь, и хост из неё не извлекался вовсе
		 */
		if((uri.size() > 1) && (uri[0] == '/') && (uri[1] == '/')){
			// Помечаем наличие авторити
			hasAuthority = true;
			// Переходим к чтению хоста
			state = state_t::HOST;
			// Устанавливаем начало токена за двумя косыми чертами
			tokenBegin = (begin + 2);
			// Устанавливаем начало хоста
			hostBegin = tokenBegin;
			// Устанавливаем начало параметров пользователя
			userinfoBegin = tokenBegin;
			// Переносим итератор за две косые черты
			ptr = tokenBegin;
		}
		/**
		 * Проходим по каждому символу URI и обрабатываем его в зависимости от текущего состояния парсинга
		 */
		while(ptr < end){
			// Получаем текущий символ
			char letter = (* ptr);
			/**
			 * В зависимости от текущего состояния парсинга URI, обрабатываем символ и при необходимости меняем состояние
			 */
			switch(static_cast <uint8_t> (state)){
				// Если мы читаем схему URI
				case static_cast <uint8_t> (state_t::SCHEME): {
					// Если встретили разделитель схемы
					if(letter == ':'){
						// Если до разделителя были символы, и схема валидна
						if((ptr > tokenBegin) && schemeValid){
							/**
							 * Проверяем, содержит ли кандидат точку.
							 * Настоящие схемы URI (http, ftp, mailto, ...) точек не содержат.
							 * Если точка есть — это доменное имя (www.example.com:443/...),
							 * а не схема, и мы переходим к разбору хоста.
							 */
							// Если у кандидата приметы хоста — это домен, а не схема
							if(uri::hostLike(tokenBegin, ptr)){
								// Помечаем наличие authority без //
								hasAuthority = true;
								// Переходим к чтению хоста
								state = state_t::HOST;
								// Если хост начинается с [ — мы внутри IPv6-адреса
								inIPv6 = (* tokenBegin == '[');
								// Начало хоста — начало строки
								hostBegin = tokenBegin;
								// Начало userinfo — то же место
								userinfoBegin = tokenBegin;
								// Обработать : в состоянии HOST (оно найдёт порт)
								continue;
							}
							// Иначе сохраняем схему URI
							scheme = string_view(tokenBegin, ptr - tokenBegin);
						/**
						 * Если схема не валидна (например токен начинается с цифры: 127.0.0.1,
						 * или с [: IPv6-адрес [2001:db8::1]),
						 * проверяем наличие точки или [ — тогда это IP/домен, а не путь
						 */
						} else if(ptr > tokenBegin) {
							// Флаг: токен является хостом (есть точка или это IPv6 в [])
							bool isHost = (* tokenBegin == '[');
							// Если не IPv6 — проверяем кандидат на приметы хоста
							if(!isHost)
								// Проверяем кандидат на приметы хоста
								isHost = uri::hostLike(tokenBegin, ptr);
							// Если точка найдена или IPv6 — это host:port (например 127.0.0.1:443 или [::1]:443)
							if(isHost){
								// Помечаем наличие authority без //
								hasAuthority = true;
								// Переходим к чтению хоста
								state = state_t::HOST;
								// Если хост начинается с [ — мы внутри IPv6-адреса
								inIPv6 = (* tokenBegin == '[');
								// Начало хоста — начало строки
								hostBegin = tokenBegin;
								// Начало userinfo — то же место
								userinfoBegin = tokenBegin;
								// Обработать : в состоянии HOST (оно найдёт порт)
								continue;
							}
							// Точки нет — это не хост, идём в путь
							tokenBegin = begin;
							// Сбрасываем состояние
							state = state_t::PATH;
							// Обработать текущий символ в контексте PATH
							continue;
						// Если до разделителя не было символов, и это не начало схемы — это может быть путь, начинающийся с : (например :/path)
						} else {
							// До разделителя не было символов — путь
							tokenBegin = begin;
							// Сбрасываем состояние, идем в путь с начала строки
							state = state_t::PATH;
							// Не делаем ptr++, чтобы обработать текущий символ в контексте PATH
							continue;
						}
						// Переходим к состоянию чтения авторити (ожидаем // или путь)
						state = state_t::AUTHORITY;
						// Устанавливаем начало токена на следующий символ после ":"
						tokenBegin = (ptr + 1);
					// Если встретили разделитель пути, запроса или фрагмента до разделителя схемы
					} else if((letter == '/') || (letter == '?') || (letter == '#')) {
						/**
						 * Проверяем, есть ли точка в части до разделителя, или начинается с [.
						 * Если есть — это домен/IP без схемы (www.example.com/path, 127.0.0.1/path, [::1]/path).
						 */
						// Флаг: токен является хостом (есть точка или это IPv6 в [])
						bool isHost = ((ptr > tokenBegin) && (* tokenBegin == '['));
						// Если не IPv6 — проверяем кандидат на приметы хоста
						if(!isHost)
							// Проверяем кандидат на приметы хоста
							isHost = uri::hostLike(tokenBegin, ptr);
						// Если точка найдена или IPv6 — это хост, переходим к разбору хоста
						if(isHost){
							// Помечаем наличие authority без //
							hasAuthority = true;
							// Переходим к чтению хоста
							state = state_t::HOST;
							// Если хост начинается с [ — мы внутри IPv6-адреса
							inIPv6 = (* tokenBegin == '[');
							// Начало хоста и userinfo — начало строки
							hostBegin = tokenBegin;
							// Начало userinfo — то же место
							userinfoBegin = tokenBegin;
							// Обработать / в состоянии HOST (оно сохранит хост и уйдёт в PATH)
							continue;
						}
						// Устанавливаем начало токена на начало строки, чтобы обработать весь URI как путь
						tokenBegin = begin;
						// Схема не найдена, это относительный URI или путь
						state = state_t::PATH;
						// Обработать символ в новом состоянии
						continue;
					// Если встретили @ — это userinfo@host без схемы (например user@example.com)
					} else if(letter == '@') {
						// Всё до @ — userinfo
						userinfo = string_view(tokenBegin, ptr - tokenBegin);
						// Помечаем наличие authority
						hasAuthority = true;
						// Переходим к чтению хоста
						state = state_t::HOST;
						// Начало хоста — символ после @
						tokenBegin = (ptr + 1);
						// Устанавливаем начало хоста
						hostBegin = tokenBegin;
						// userinfoBegin уже не нужен, но на всякий случай
						userinfoBegin = tokenBegin;
					// Если это не разделитель, то проверяем валидность символов схемы
					} else {
						// Если это первый символ схемы, проверяем его на допустимость для первой позиции (должна быть буква)
						if(ptr == begin)
							// Устанавливаем флаг валидности схемы, если первый символ - допустимая буква
							schemeValid = (((letter >= 'a') && (letter <= 'z')) || ((letter >= 'A') && (letter <= 'Z')));
						// Если уже определили что схема не валидна, то не проверяем символы схемы, просто ждем разделителя или конец строки
						else if(!schemeValid) {
							/**
							 * Уже поняли что схема бита, но ждем разделителя
							 */
						// Если схема пока валидна, проверяем текущий символ на допустимость для схемы
						} else {
							// Если символ не допустим для схемы, устанавливаем флаг валидности схемы в false
							if(!isSchemeLetter(letter))
								// Схема не валидна, ждем разделителя или конец строки
								schemeValid = false;
						}
					}
				} break;
				// Если мы читаем авторити URI (после схемы и : )
				case static_cast <uint8_t> (state_t::AUTHORITY): {
					// Проверяем на наличие // для определения наличия авторити
					if(((ptr - tokenBegin) == 0) && (letter == '/')){
						/**
						 * Это начало //
						 * Ничего не делаем, ждем второй слэш или конец
						 */
					// Если встретили второй слэш, то подтверждаем наличие авторити и переходим к чтению хоста
					} else if(((ptr - tokenBegin) == 1) && (letter == '/')) {
						// Подтвердили //
						hasAuthority = true;
						// Устанавливаем состояние на чтение хоста
						state = state_t::HOST;
						// Устанавливаем начало токена на следующий символ после //
						tokenBegin = (ptr + 1);
						// Устанавливаем начало хоста на следующий символ после //
						hostBegin = tokenBegin;
						// Устанавливаем начало userinfo на начало хоста, так как userinfo может быть до @ в хосте
						userinfoBegin = tokenBegin;
					/**
					 * Если это не было //, проверяем, есть ли @ впереди до первого /, ?, # -
					 * это opaque URI вида scheme:user@host (например mailto:user@example.com)
					 */
					} else {
						// Ищем @ до первого /, ?, # или конца строки
						bool hasAtInOpaque = false;
						/**
						 * Перебираем символы начиная с текущего
						 */
						for(const char * look = ptr; look < end; ++look){
							// Если нашли @ - это userinfo@host без //
							if(* look == '@'){
								// Нашли @ в opaque URI
								hasAtInOpaque = true;
								// Прерываем поиск
								break;
							}
							// Если нашли /, ?, # раньше @ - это обычный путь без userinfo
							if((* look == '/') || (* look == '?') || (* look == '#'))
								// Прерываем поиск
								break;
						}
						// Если @ найден — парсим как userinfo@host (например mailto:user@example.com)
						if(hasAtInOpaque){
							// Помечаем, что у нас есть authority (нужно для корректной финализации хоста)
							hasAuthority = true;
							// Переходим к чтению хоста
							state = state_t::HOST;
							// Устанавливаем начало токена на текущую позицию (после scheme:)
							tokenBegin = (begin + scheme.size() + 1);
							// Устанавливаем начало хоста и userinfo
							hostBegin = tokenBegin;
							// Устанавливаем начало userinfo
							userinfoBegin = tokenBegin;
							// Обработать текущий символ в состоянии HOST
							continue;
						}
						// Иначе — это обычный opaque URI (например scheme:path-only), идём в путь
						// Устанавливаем итератор на начало пути (после scheme:)
						tokenBegin = (begin + scheme.size() + 1);
						// Устанавливаем состояние на чтение пути
						state = state_t::PATH;
						// Обработать символ в новом состоянии
						continue;
					}
				} break;
				// Если мы читаем хост URI (внутри авторити)
				case static_cast <uint8_t> (state_t::HOST): {
					// Если встретили [ или ], то это может быть IPv6-адрес внутри авторити, и @ для userinfo, но только если мы не внутри IPv6-адреса
					if(letter == '[')
						// Начало IPv6-адреса, устанавливаем флаг
						inIPv6 = true;
					// Если встретили ], то это может быть конец IPv6-адреса внутри авторити, сбрасываем флаг
					else if(letter == ']')
						// Конец IPv6-адреса, сбрасываем флаг
						inIPv6 = false;
					// Если встретили @ и мы не внутри IPv6-адреса, то это разделитель userinfo и хоста
					else if((letter == '@') && !inIPv6) {
						// Userinfo найден
						userinfo = string_view(userinfoBegin, ptr - userinfoBegin);
						// Переходим к чтению хоста
						tokenBegin = (ptr + 1);
						// Устанавливаем начало хоста на следующий символ после @
						hostBegin = tokenBegin;
					/**
					 * Если встретили : и мы не внутри IPv6-адреса, то это может быть разделитель хоста и порта
					 * или разделитель логина и пароля в userinfo (если впереди есть @)
					 */
					} else if((letter == ':') && !inIPv6) {
						/**
						 * Проверяем, есть ли @ впереди (вне скобок IPv6) до первого /, ?, # или конца строки.
						 * Если @ найден раньше — текущий : является частью userinfo (разделитель пароля),
						 * и переходить в PORT рано. Если @ не найден — это host:port разделитель.
						 */
						bool hasAtAhead = false;
						{
							// Глубина вложенности скобок IPv6
							uint16_t depth = 0;
							/**
							 * Перебираем символы после текущего :
							 */
							for(const char * look = (ptr + 1); look < end; ++look){
								// Если встретили [, увеличиваем глубину
								if(* look == '[')
									// Входим в IPv6-адрес
									++depth;
								// Если встретили ], уменьшаем глубину
								else if(* look == ']')
									// Выходим из IPv6-адреса
									--depth;
								// Если встретили @ вне скобок IPv6, то это разделитель userinfo и хоста
								else if((* look == '@') && (depth == 0)){
									// Нашли @ вне IPv6
									hasAtAhead = true;
									// Прерываем поиск
									break;
								// Если встретили /, ?, # вне скобок, то @ дальше не будет (конец авторити)
								} else if(((* look == '/') || (* look == '?') || (* look == '#')) && (depth == 0))
									// Прерываем поиск
									break;
							}
						}
						// Если @ впереди не найден — текущий : является разделителем хоста и порта
						if(!hasAtAhead){
							// Разделитель хоста и порта
							host = string_view(hostBegin, ptr - hostBegin);
							// Переходим к чтению порта
							state = state_t::PORT;
							// Устанавливаем начало токена на следующий символ после :
							tokenBegin = (ptr + 1);
						}
					/**
					 * Иначе : является частью userinfo (например разделитель логина и пароля), продолжаем чтение хоста
					 * Если встретили /, ?, # и мы не внутри IPv6-адреса, то это конец авторити и начало пути, запроса или фрагмента
					 */
					} else if((letter == '/') || (letter == '?') || (letter == '#')) {
						// Конец авторити
						if(!host.data())
							// Если хост еще не сохранен (не было порта)
							host = string_view(hostBegin, ptr - hostBegin);
						// Переходим к чтению пути, запроса или фрагмента в зависимости от разделителя
						state = (
							((letter == '/') ? state_t::PATH :
							((letter == '?') ? state_t::QUERY : state_t::FRAGMENT))
						);
						// Если это был разделитель пути, то путь начинается с разделителя, иначе путь начинается после разделителя
						if(letter == '/')
							// Путь включает /
							tokenBegin = ptr;
						// Если это был разделитель запроса или фрагмента, то путь начинается после разделителя
						else tokenBegin = (ptr + 1);
						// Обработать разделитель в новом состоянии
						continue;
					}
				} break;
				// Если мы читаем порт URI (внутри авторити после : )
				case static_cast <uint8_t> (state_t::PORT): {
					// Если встретили /, ?, #, то это конец порта и начало пути, запроса или фрагмента
					if((letter == '/') || (letter == '?') || (letter == '#')){
						// Сохраняем порт URI
						port = string_view(tokenBegin, ptr - tokenBegin);
						// Устанавливаем состояние на чтение пути, запроса или фрагмента в зависимости от разделителя
						state = (
							((letter == '/') ? state_t::PATH :
							((letter == '?') ? state_t::QUERY : state_t::FRAGMENT))
						);
						// Если это был разделитель пути, то путь начинается с разделителя, иначе путь начинается после разделителя
						if(letter == '/')
							// Путь включает /
							tokenBegin = ptr;
						// Если это был разделитель запроса или фрагмента, то путь начинается после разделителя
						else tokenBegin = (ptr + 1);
						// Обработать разделитель в новом состоянии
						continue;
					}
				// Иначе просто продолжаем копить порт (валидацию цифр можно сделать позже)
				} break;
				// Если мы читаем путь URI
				case static_cast <uint8_t> (state_t::PATH): {
					// Если встретили ? или #, то это конец пути и начало запроса или фрагмента
					if(letter == '?'){
						// Сохраняем путь URI
						path = string_view(tokenBegin, ptr - tokenBegin);
						// Устанавливаем состояние на чтение запроса
						state = state_t::QUERY;
						// Устанавливаем начало токена на следующий символ после ?
						tokenBegin = (ptr + 1);
					// Если встретили #, то это конец пути и начало фрагмента
					} else if(letter == '#') {
						// Сохраняем путь URI
						path = string_view(tokenBegin, ptr - tokenBegin);
						// Устанавливаем состояние на чтение фрагмента
						state = state_t::FRAGMENT;
						// Устанавливаем начало токена на следующий символ после #
						tokenBegin = (ptr + 1);
					}
				} break;
				// Если мы читаем параметры URI
				case static_cast <uint8_t> (state_t::QUERY): {
					// Если встретили #, то это конец параметров и начало фрагмента
					if(letter == '#'){
						// Сохраняем параметры URI
						query = string_view(tokenBegin, ptr - tokenBegin);
						// Устанавливаем состояние на чтение фрагмента
						state = state_t::FRAGMENT;
						// Устанавливаем начало токена на следующий символ после #
						tokenBegin = (ptr + 1);
					}
				} break;
				// Если мы читаем якорь URI
				case static_cast <uint8_t> (state_t::FRAGMENT):
					// До конца строки ничего не меняем
					break;
			}
			// Переходим к следующему символу
			ptr++;
		}
		/**
		 * Финализация (конец строки)
		 */
		switch(static_cast <uint8_t> (state)){
			// Если мы закончили на чтении схемы, то это может быть схема без : или путь без схемы
			case static_cast <uint8_t> (state_t::SCHEME): {
				/**
				 * Строка без разделителей (нет ни : ни / ни ? ни # ни @).
				 * Проверяем, содержит ли строка @: тогда это userinfo@host без схемы.
				 * Иначе — относительный путь.
				 */
				const char * atSign = nullptr;
				/**
				 * Ищем @ в строке
				 */
				for(const char * s = tokenBegin; s < end; ++s){
					// Если нашли @
					if(* s == '@'){
						// Сохраняем указатель
						atSign = s;
						// Прерываем поиск
						break;
					}
				}
				// Если @ найден — это userinfo@host
				if(atSign != nullptr){
					// Сохраняем userinfo
					userinfo = string_view(tokenBegin, atSign - tokenBegin);
					// Сохраняем host (всё после @)
					host = string_view(atSign + 1, end - (atSign + 1));
				// Устанавливаем путь URI
				} else path = string_view(begin, end - begin);
			} break;
			// Если мы закончили на чтении авторити, то это может быть авторити без пути или портом, или просто путь
			case static_cast <uint8_t> (state_t::AUTHORITY):
				// Было scheme: но не было //
				path = string_view(tokenBegin, end - tokenBegin);
			break;
			// Если мы закончили на чтении хоста, то сохраняем хост (если был авторити) или путь (если не было авторити)
			case static_cast <uint8_t> (state_t::HOST): {
				// Если был авторити, сохраняем хост, иначе сохраняем путь
				if(hasAuthority)
					// Устанавливаем хост URI
					host = string_view(hostBegin, end - hostBegin);
				// Устанавливаем путь URI
				else path = string_view(begin, end - begin);
			} break;
			// Если мы закончили на чтении порта, сохраняем порт
			case static_cast <uint8_t> (state_t::PORT):
				// Устанавливаем порт URI
				port = string_view(tokenBegin, end - tokenBegin);
			break;
			// Если мы закончили на чтении пути, сохраняем путь
			case static_cast <uint8_t> (state_t::PATH):
				// Устанавливаем путь URI
				path = string_view(tokenBegin, end - tokenBegin);
			break;
			// Если мы закончили на чтении параметров, сохраняем параметры
			case static_cast <uint8_t> (state_t::QUERY):
				// Устанавливаем параметры URI
				query = string_view(tokenBegin, end - tokenBegin);
			break;
			// Если мы закончили на чтении якоря, сохраняем якорь
			case static_cast <uint8_t> (state_t::FRAGMENT):
				// Устанавливаем якорь URI
				fragment = string_view(tokenBegin, end - tokenBegin);
			break;
		}
		// Возвращаем результат парсинга
		return true;
	}

	/**
	 * @brief Признаки разрешённости символа в наборах элементов URI
	 *
	 * @details Наборов разрешённых символов у элементов URI пять, и различаются
	 *          они десятком-другим знаков препинания. Каждому символу набора
	 *          отведён свой разряд, поэтому принадлежность символа любому из
	 *          наборов снимается одним наложением маски.
	 *
	 */
	enum class allow_t : uint8_t {
		ALNUM      = 0x01, // Символ является буквенно-цифровым ASCII
		SCHEME     = 0x02, // Символ допустим в схеме URI
		PATH       = 0x04, // Символ допустим в пути URI
		QUERY      = 0x08, // Символ допустим в параметрах URI
		USER       = 0x10, // Символ допустим в параметрах пользователя URI
		FRAGMENT   = 0x20  // Символ допустим в якоре URI
	};

	/**
	 * @brief Вспомогательная функция формирования таблицы разрешённых символов
	 *
	 * @details Проверка разрешённости стоит на пути каждого символа каждой
	 *          кодируемой части URI. Выписанная цепочкой сравнений, она обходилась
	 *          в два десятка ветвлений на символ - дороже, чем запись самой
	 *          процент-последовательности. Сведённая в таблицу, она становится
	 *          одним чтением и одним наложением маски.
	 *
	 *          Наборы выписаны по грамматике RFC 3986, а не по общим соображениям
	 *          о том, что кодировать безопаснее. Лишнее кодирование безобидным не
	 *          бывает: якорь набором незарезервированных символов уносил в
	 *          процент-последовательности косую черту и вопрос, а они в якоре
	 *          разрешены прямо (3.5), и адрес вида
	 *
	 *              https://doc.example/api/#/?id=раздел
	 *
	 *          собирался как ".../api#%2F%3Fid%3D...". Строка эта адресу
	 *          равнозначна, но обработчик якоря на стороне страницы сличает его
	 *          побуквенно, и переход по такому адресу приводил уже не туда.
	 *
	 *          Проверки диапазонов выписаны явно, а не через библиотечную
	 *          `isalnum`: та смотрит на локаль и на UTF-8 трактует октеты свыше
	 *          127 как буквы, из-за чего кириллица в пути осталась бы
	 *          незакодированной.
	 *
	 * @return сформированная таблица разрешённых символов
	 *
	 */
	static array <uint8_t, 256> makeAllowed() noexcept {
		// Формируемая таблица разрешённых символов
		array <uint8_t, 256> result = {0};
		/**
		 * Проходим по всем возможным значениям символа
		 */
		for(size_t i = 0; i < result.size(); ++i){
			// Текущий символ таблицы
			const char letter = static_cast <char> (i);
			// Признак буквенно-цифрового символа ASCII
			const bool alnum = (
				((letter >= 'a') && (letter <= 'z')) ||
				((letter >= 'A') && (letter <= 'Z')) ||
				((letter >= '0') && (letter <= '9'))
			);
			// Признак незарезервированного символа: unreserved = ALPHA / DIGIT / "-" / "." / "_" / "~"
			const bool unreserved = (alnum || (letter == '-') || (letter == '.') || (letter == '_') || (letter == '~'));
			/**
			 * Признак разделителя подчинённого уровня:
			 * sub-delims = "!" / "$" / "&" / "\'" / "(" / ")" / "*" / "+" / "," / ";" / "="
			 */
			const bool subdelims = (
				(letter == '!') || (letter == '$') ||
				(letter == '&') || (letter == '\'') ||
				(letter == '(') || (letter == ')') ||
				(letter == '*') || (letter == '+') ||
				(letter == ',') || (letter == ';') || (letter == '=')
			);
			// Признак символа пути: pchar = unreserved / pct-encoded / sub-delims / ":" / "@"
			const bool pchar = (unreserved || subdelims || (letter == ':') || (letter == '@'));
			// Если символ является буквенно-цифровым ASCII
			if(alnum)
				// Устанавливаем признак буквенно-цифрового символа
				result[i] |= static_cast <uint8_t> (allow_t::ALNUM);
			// Если символ допустим в схеме URI: scheme = ALPHA *( ALPHA / DIGIT / "+" / "-" / "." )
			if(alnum || (letter == '+') || (letter == '-') || (letter == '.'))
				// Устанавливаем признак допустимости символа в схеме URI
				result[i] |= static_cast <uint8_t> (allow_t::SCHEME);
			/**
			 * Если символ допустим в пути URI: segment = *pchar (3.3)
			 */
			if(pchar)
				// Устанавливаем признак допустимости символа в пути URI
				result[i] |= static_cast <uint8_t> (allow_t::PATH);
			/**
			 * Если символ допустим в параметрах URI: query = *( pchar / "/" / "?" ) (3.4).
			 * Разделители самих параметров - "&", "=" и "?" - из набора изъяты: они
			 * разделяют пары и отделяют ключ от значения, и попав в данные, обязаны
			 * быть закодированы. Квадратные скобки грамматике не принадлежат, но
			 * держатся общим соглашением о наборах вида "a[]=1" и браузерами не
			 * кодируются
			 */
			if(((pchar && (letter != '&') && (letter != '=')) || (letter == '/') || (letter == '[') || (letter == ']')))
				// Устанавливаем признак допустимости символа в параметрах URI
				result[i] |= static_cast <uint8_t> (allow_t::QUERY);
			/**
			 * Если символ допустим в параметрах пользователя URI:
			 * userinfo = *( unreserved / pct-encoded / sub-delims / ":" ) (3.2.1).
			 * Двоеточие из набора изъято: им отделяется логин от пароля, и попав в
			 * любой из них, оно обязано быть закодировано
			 */
			if(unreserved || subdelims)
				// Устанавливаем признак допустимости символа в параметрах пользователя URI
				result[i] |= static_cast <uint8_t> (allow_t::USER);
			/**
			 * Если символ допустим в якоре URI: fragment = *( pchar / "/" / "?" ) (3.5)
			 */
			if(pchar || (letter == '/') || (letter == '?'))
				// Устанавливаем признак допустимости символа в якоре URI
				result[i] |= static_cast <uint8_t> (allow_t::FRAGMENT);
		}
		// Возвращаем сформированную таблицу разрешённых символов
		return result;
	}
	// Таблица разрешённости символов в наборах элементов URI
	static const array <uint8_t, 256> ALLOWED = makeAllowed();

	/**
	 * @brief Функция получения маски разрешённых символов элемента URI
	 *
	 * @param item тип элемента URI, для которого выполняется кодирование
	 * @return     маска разрешённых символов набора
	 *
	 */
	[[nodiscard]] static inline uint8_t allowance(const uri_t::item_t item) noexcept {
		/**
		 * Определяем набор разрешённых символов по типу элемента URI
		 */
		switch(static_cast <uint8_t> (item)){
			// Для схемы URI разрешены буквенно-цифровые ASCII и + - .
			case static_cast <uint8_t> (uri_t::item_t::SCHEME):
				// Выводим маску набора схемы URI
				return static_cast <uint8_t> (allow_t::SCHEME);
			// Для пути URI разрешены незарезервированные символы и часть знаков препинания
			case static_cast <uint8_t> (uri_t::item_t::PATH):
				// Выводим маску набора пути URI
				return static_cast <uint8_t> (allow_t::PATH);
			// Для параметров URI разрешён более широкий набор знаков препинания
			case static_cast <uint8_t> (uri_t::item_t::QUERY):
				// Выводим маску набора параметров URI
				return static_cast <uint8_t> (allow_t::QUERY);
			// Для параметров пользователя и хоста URI разрешены незарезервированные символы и разделители подчинённого уровня
			case static_cast <uint8_t> (uri_t::item_t::USER):
			case static_cast <uint8_t> (uri_t::item_t::HOST):
				// Выводим маску набора параметров пользователя URI
				return static_cast <uint8_t> (allow_t::USER);
			// Для якоря URI разрешены символы пути, косая черта и вопрос
			case static_cast <uint8_t> (uri_t::item_t::FRAGMENT):
				// Выводим маску набора якоря URI
				return static_cast <uint8_t> (allow_t::FRAGMENT);
		}
		// Для неизвестного элемента URI разрешаем только буквенно-цифровые ASCII
		return static_cast <uint8_t> (allow_t::ALNUM);
	}

	/**
	 * @brief Функция кодирования строки в URL-адресе
	 *
	 * @details Закодированная строка дописывается в результат, а не отдаётся
	 *          наружу отдельной строкой: сборка URI склеивает результат из
	 *          десятка таких кусков, и каждый из них, отданный отдельной строкой,
	 *          стоил бы выделения памяти под неё саму - тем более неизбежного,
	 *          что запас под процент-кодирование втрое превышает исходную длину и
	 *          размещению строки внутри объекта не поддаётся.
	 *
	 * @param result результат, в который добавляется закодированная строка
	 * @param text   строка текста для кодирования
	 * @param item   тип элемента URI, для которого выполняется кодирование
	 * @param log    объект работы с логами
	 *
	 */
	static void encode(string & result, string_view text, const uri_t::item_t item, const log_t * log) noexcept {
		// Если строка не передана, то добавлять нечего
		if(text.empty())
			// Выходим из функции
			return;
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			// Таблица шестнадцатеричных символов в верхнем регистре
			static constexpr char hex[] = "0123456789ABCDEF";
			// Маска разрешённых символов элемента URI
			const uint8_t mask = allowance(item);
			// Позиция начала неразрывного участка разрешённых символов
			size_t start = 0;
			/**
			 * Перебираем все символы
			 */
			for(size_t i = 0; i < text.size(); i++){
				// Получаем код текущего символа
				const uint8_t value = static_cast <uint8_t> (text[i]);
				// Если символ разрешён для данного элемента URI, продлеваем участок
				if(ALLOWED[value] & mask)
					// Пропускаем итерацию
					continue;
				// Если участок разрешённых символов набран, добавляем его целиком
				if(i > start)
					// Добавляем накопленный участок разрешённых символов
					result.append(text.data() + start, i - start);
				// Записываем символ в виде %XX (старший и младший полубайты)
				const char triplet[3] = {'%', hex[(value >> 4) & 0x0F], hex[value & 0x0F]};
				// Добавляем процент-последовательность в результат
				result.append(triplet, 3);
				// Переносим начало участка за закодированный символ
				start = (i + 1);
			}
			// Если после последней процент-последовательности остался участок
			if(start < text.size())
				// Добавляем остаток строки целиком
				result.append(text.data() + start, text.size() - start);
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				log->debug("%s", __PRETTY_FUNCTION__, make_tuple(text), log_t::flag_t::WARNING, error.what());
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				log->print("%s", log_t::flag_t::WARNING, error.what());
			#endif
		}
	}

	/**
	 * @brief Функция перевода шестнадцатеричной цифры в её значение
	 *
	 * @param letter символ для перевода
	 * @return       значение цифры либо -1, если символ цифрой не является
	 *
	 */
	[[nodiscard]] static inline int8_t nibble(const char letter) noexcept {
		// Если символ является десятичной цифрой
		if((letter >= '0') && (letter <= '9'))
			// Выводим значение десятичной цифры
			return static_cast <int8_t> (letter - '0');
		// Если символ является шестнадцатеричной цифрой в нижнем регистре
		if((letter >= 'a') && (letter <= 'f'))
			// Выводим значение шестнадцатеричной цифры
			return static_cast <int8_t> (letter - 'a' + 10);
		// Если символ является шестнадцатеричной цифрой в верхнем регистре
		if((letter >= 'A') && (letter <= 'F'))
			// Выводим значение шестнадцатеричной цифры
			return static_cast <int8_t> (letter - 'A' + 10);
		// Выводим признак того, что символ цифрой не является
		return -1;
	}

	/**
	 * @brief Функция декодирования строки в URL-адресе
	 *
	 * @details Строка, в которой нечего декодировать, копируется целиком:
	 *          процент-последовательностей в ней нет, и посимвольный обход дал бы
	 *          тот же результат за куда большее время. Таких строк подавляющее
	 *          большинство - процент-кодирование в пути и в параметрах запроса
	 *          встречается заметно реже, чем отсутствует.
	 *
	 *          Плюс раскодированию не подлежит. Правило, по которому плюс означает
	 *          пробел, принадлежит не RFC 3986, а кодированию форм
	 *          "application/x-www-form-urlencoded", и относится оно к телу формы и
	 *          к строке её параметров, но не к пути и не к произвольному адресу. В
	 *          самом же RFC 3986 плюс - обычный разделитель подчинённого уровня
	 *          (2.2), и в пути с параметрами он разрешён прямо.
	 *
	 *          Раскодирование его пробелом ломало круговой оборот: разобранный
	 *          "%2B" отдавался плюсом, плюс собирался плюсом, а повторный разбор
	 *          давал уже пробел. Адрес поиска "?q=a+b", пришедший из браузера, за
	 *          два оборота превращался в "?q=a%20b". Кому нужны правила форм, тот
	 *          применяет их к полученным значениям сам: адресу они не принадлежат.
	 *
	 * @param text строка текста для декодирования
	 * @param log  объект работы с логами
	 * @return     результат декодирования
	 *
	 */
	[[nodiscard]] static string decode(string_view text, const log_t * log) noexcept {
		// Переменная результата
		string result = "";
		// Если строка передана
		if(!text.empty()){
			/**
			 * Выполняем отлов ошибок
			 */
			try {
				// Позиция первого символа, требующего декодирования
				const size_t position = text.find('%');
				// Если декодировать в строке нечего, копируем её целиком
				if(position == string_view::npos)
					// Выводим результат
					return string(text);
				// Выделяем память для строки
				result.reserve(text.length());
				// Добавляем участок строки до первого требующего декодирования символа
				result.append(text.data(), position);
				// Позиция начала неразрывного участка неизменяемых символов
				size_t start = position;
				/**
				 * Переходим по всей длине строки, начиная с первого требующего декодирования символа
				 */
				for(size_t i = position; i < text.length(); i++){
					// Получаем текущее смещение в текстовом буфере
					const char * offset = (text.data() + i);
					/**
					 * Если это проценты и впереди есть ещё минимум два валидных шестнадцатеричных символа
					 * (проверка границ обязательна, так как text — невладеющий string_view без гарантии нуль-терминатора)
					 */
					if((offset[0] == '%') && ((i + 2) < text.length())){
						// Извлекаем старший полубайт кода символа
						const int8_t high = nibble(offset[1]);
						// Извлекаем младший полубайт кода символа
						const int8_t low = nibble(offset[2]);
						// Если оба полубайта являются шестнадцатеричными цифрами
						if((high >= 0) && (low >= 0)){
							// Если участок неизменяемых символов набран, добавляем его целиком
							if(i > start)
								// Добавляем накопленный участок неизменяемых символов
								result.append(text.data() + start, i - start);
							// Запоминаем полученный символ
							result.append(1, static_cast <char> ((high << 4) | low));
							// Смещаем итератор
							i += 2;
							// Переносим начало участка за декодированную последовательность
							start = (i + 1);
							// Пропускаем итерацию
							continue;
						}
					}
					/**
					 * Иначе символ остаётся как есть (включая одиночный '%' без корректного кода)
					 * и войдёт в результат вместе со своим участком
					 */
				}
				// Если после последнего декодированного символа остался участок
				if(start < text.length())
					// Добавляем остаток строки целиком
					result.append(text.data() + start, text.length() - start);
			/**
			 * Если возникает ошибка
			 */
			} catch(const exception & error) {
				/**
				 * Если включён режим отладки
				 */
				#if DEBUG_MODE
					// Записываем ошибку в лог
					log->debug("%s", __PRETTY_FUNCTION__, make_tuple(text), log_t::flag_t::WARNING, error.what());
				/**
				 * Если режим отладки не включён
				 */
				#else
					// Записываем ошибку в лог
					log->print("%s", log_t::flag_t::WARNING, error.what());
				#endif
			}
		}
		// Возвращаем результат
		return result;
	}

	/**
	 * @brief Функция добавления десятичной записи числа в результат
	 *
	 * @details Записью числа занималось форматирование по образцу, а оно на каждый
	 *          вызов заводит буфер в килобайт и разбирает строку образца. Номер
	 *          порта - это до пяти цифр, и стоить его запись должна пяти делений.
	 *
	 * @param result результат, в который добавляется запись числа
	 * @param value  число для записи
	 *
	 */
	static void appendNumber(string & result, const uint16_t value) noexcept {
		// Буфер записи числа: наибольшее 16-разрядное число занимает пять цифр
		char buffer[5];
		// Позиция записи очередной цифры
		uint8_t offset = sizeof(buffer);
		// Остаток числа, ещё не записанный в буфер
		uint16_t rest = value;
		/**
		 * Записываем цифры числа справа налево, начиная с младшего разряда
		 */
		do {
			// Записываем очередную цифру числа
			buffer[--offset] = static_cast <char> ('0' + (rest % 10));
			// Отбрасываем записанный разряд числа
			rest /= 10;
		} while(rest > 0);
		// Добавляем записанное число в результат
		result.append(buffer + offset, sizeof(buffer) - offset);
	}

	/**
	 * @brief Признак принадлежности символа алфавиту сетевых адресов
	 *
	 */
	static constexpr uint8_t ADDRESSABLE = 0x20;
	/**
	 * @brief Вспомогательная функция формирования таблицы алфавита сетевых адресов
	 *
	 * @details Алфавит собран объединением алфавитов трёх разборов, которые
	 *          выполняет разбор адреса: IPv4-адреса (десятичные и, в либеральном
	 *          режиме, шестнадцатеричные цифры с приставкой "x", а также точка),
	 *          IPv6-адреса (шестнадцатеричные цифры, двоеточие, точка встроенного
	 *          IPv4-адреса и квадратные скобки, в которых он приходит из URI) и
	 *          аппаратного адреса (шестнадцатеричные цифры и двоеточие). В него же
	 *          входит пробельный набор: разбор IPv4-адреса и IPv6-адреса обрезает
	 *          пробелы вокруг строки, поэтому строка с ними адресом оказаться
	 *          способна.
	 *
	 *          Алфавит обязан быть надмножеством: символ, который разбор адреса
	 *          принять мог бы, обязан в алфавит попасть. Лишний символ стоит одной
	 *          попытки разбора впустую, недостающий изменил бы разновидность хоста.
	 *
	 * @return сформированная таблица алфавита сетевых адресов
	 *
	 */
	static array <uint8_t, 256> makeAddressable() noexcept {
		// Формируемая таблица алфавита сетевых адресов
		array <uint8_t, 256> result = {0};
		/**
		 * Проходим по всем возможным значениям символа
		 */
		for(size_t i = 0; i < result.size(); ++i){
			// Текущий символ таблицы
			const char letter = static_cast <char> (i);
			// Если символ входит в алфавит сетевых адресов
			if(
				((letter >= '0') && (letter <= '9')) ||
				((letter >= 'a') && (letter <= 'f')) ||
				((letter >= 'A') && (letter <= 'F')) ||
				(letter == 'x') || (letter == 'X') ||
				(letter == '.') || (letter == ':') ||
				(letter == '[') || (letter == ']') ||
				(letter == ' ') || (letter == '\t') ||
				(letter == '\n') || (letter == '\v') ||
				(letter == '\f') || (letter == '\r')
			)
				// Устанавливаем признак алфавита сетевых адресов
				result[i] |= ADDRESSABLE;
		}
		// Возвращаем сформированную таблицу алфавита сетевых адресов
		return result;
	}
	// Таблица алфавита сетевых адресов
	static const array <uint8_t, 256> ADDRESS = makeAddressable();

	/**
	 * @brief Число пар ключ-значение параметров URI, выстраиваемых без выделения памяти
	 *
	 * @details Граница выбрана с запасом к тому, что встречается у адреса на деле:
	 *          параметров у него единицы, и набор указателей на них укладывается
	 *          на стеке целиком. Она же оставляет выстраивание в пределах, за
	 *          которыми оно заводит собственный временный буфер
	 *
	 */
	static constexpr size_t QUERY_INPLACE = 32;

	/**
	 * @brief Функция определения разновидности сетевого адреса, которой строка способна оказаться
	 *
	 * @details Установка хоста URI начиналась перебором разновидностей: строка
	 *          разбиралась как IPv4-адрес, затем как IPv6-адрес, затем как
	 *          аппаратный адрес, - и для доменного имени все три разбора заведомо
	 *          неудачны, причём последний из них заводит завершённую нулём копию
	 *          строки и разбирает её по образцу. Доменное имя, однако, само
	 *          сообщает, что адресом оно не является: буквы вне шестнадцатеричного
	 *          алфавита в адресе не встречаются, а в имени встречаются почти всегда.
	 *
	 *          Тот же обход отбирает и единственную разновидность, которой строка
	 *          способна оказаться: двоеточия в IPv4-адресе не бывает, а IPv6-адреса
	 *          без двоеточия не бывает. Аппаратный адрес отдельной разновидностью не
	 *          выделяется - атрибутов сетевого адреса ему всё равно не завести, и
	 *          обрабатывается он как имя.
	 *
	 *          Обход прекращается на символе процента: за ним у IPv6-адреса стоит
	 *          обозначение зоны, и обозначение это произвольно.
	 *
	 * @param host строка хоста для проверки
	 * @return     разновидность сетевого адреса либо NONE, если строка адресом быть не может
	 *
	 */
	[[nodiscard]] static net_addr_t::type_t addressType(string_view host) noexcept {
		// Признак наличия двоеточия в строке хоста
		bool colon = false;
		/**
		 * Перебираем все символы строки хоста
		 */
		for(char letter : host){
			// Если встретился символ процента, то за ним стоит обозначение зоны IPv6-адреса
			if(letter == '%')
				// Выводим разновидность IPv6-адреса
				return net_addr_t::type_t::IPV6;
			// Если символ в алфавит сетевых адресов не входит
			if(!(ADDRESS[static_cast <uint8_t> (letter)] & ADDRESSABLE))
				// Выводим признак неспособности строки оказаться сетевым адресом
				return net_addr_t::type_t::NONE;
			// Если встретилось двоеточие, запоминаем его наличие
			if(letter == ':')
				// Запоминаем наличие двоеточия в строке хоста
				colon = true;
		}
		// Выводим разновидность адреса по наличию двоеточия в строке хоста
		return (colon ? net_addr_t::type_t::IPV6 : net_addr_t::type_t::IPV4);
	}

	/**
	 * @brief Функция разбора номера порта URI
	 *
	 * @details Разбором занималась связка из проверки представления на число и двух
	 *          переводов его в число: первый - для сверки с границей диапазона,
	 *          второй - для получения самого значения. Проходов по представлению
	 *          выходило три, а проверка на число вдобавок обрезала пробелы, которых
	 *          в авторити URI не бывает. Одного прохода довольно и для сверки, и для
	 *          получения значения: разряд, выводящий число за границу диапазона,
	 *          обнаруживается на нём же.
	 *
	 * @param text  представление номера порта
	 * @param value ссылка для сохранения номера порта
	 * @return      признак годности представления номера порта
	 *
	 */
	[[nodiscard]] static bool parsePort(string_view text, uint16_t & value) noexcept {
		// Если представление номера порта пустое, разбирать нечего
		if(text.empty())
			// Выводим признак негодности представления
			return false;
		// Накопитель номера порта
		uint32_t result = 0;
		/**
		 * Перебираем все символы представления номера порта
		 */
		for(char letter : text){
			// Если символ не является десятичной цифрой
			if((letter < '0') || (letter > '9'))
				// Выводим признак негодности представления
				return false;
			// Добавляем очередной разряд к накопителю номера порта
			result = ((result * 10) + static_cast <uint32_t> (letter - '0'));
			// Если номер порта вышел за пределы диапазона портов
			if(result > 65535)
				// Выводим признак негодности представления
				return false;
		}
		// Устанавливаем полученный номер порта
		value = static_cast <uint16_t> (result);
		// Выводим признак годности представления
		return true;
	}

	/**
	 * @brief Функция приведения строки к нижнему регистру
	 *
	 * @details Схема и хост регистронезависимы, и в строке URI они записываются
	 *          нижним регистром (RFC 3986 6.2.2.1). Приведение выполняется по
	 *          таблице ASCII, а не средствами локали: схема и доменное имя - это
	 *          протокольные данные, и их разбор от настроек машины зависеть не
	 *          должен, а октеты свыше 127 в них либо составляют
	 *          процент-последовательность, либо являются частью записи UTF-8, и
	 *          трогать их нельзя
	 *
	 * @param text строка для приведения к нижнему регистру
	 * @return     строка, приведённая к нижнему регистру
	 *
	 */
	[[nodiscard]] static string lower(string_view text) noexcept {
		// Формируемая строка нижнего регистра
		string result(text);
		/**
		 * Перебираем все символы строки
		 */
		for(size_t i = 0; i < result.size(); i++){
			/**
			 * Цифры процент-последовательности регистру строки не подчиняются:
			 * они тоже регистронезависимы, но записываются верхним регистром
			 * (RFC 3986 6.2.2.1), поэтому приводятся к нему отдельно
			 */
			if((result[i] == '%') && ((i + 2) < result.size()) && (nibble(result[i + 1]) >= 0) && (nibble(result[i + 2]) >= 0)){
				// Приводим старшую цифру процент-последовательности к верхнему регистру
				result[i + 1] = ascii::toUpper(result[i + 1]);
				// Приводим младшую цифру процент-последовательности к верхнему регистру
				result[i + 2] = ascii::toUpper(result[i + 2]);
				// Переносим итератор за процент-последовательность
				i += 2;
				// Пропускаем итерацию
				continue;
			}
			// Приводим очередной символ строки к нижнему регистру
			result[i] = ascii::toLower(result[i]);
		}
		// Выводим строку, приведённую к нижнему регистру
		return result;
	}

	/**
	 * @brief Функция снятия точечных сегментов пути
	 *
	 * @details Обозначения текущего и родительского каталога в пути адреса
	 *          разрешаются на месте (RFC 3986 5.2.4): сегмент "." отбрасывается,
	 *          сегмент ".." отбрасывается вместе с предшествующим ему. Без этого
	 *          относительная ссылка из заголовка Location складывалась с базовым
	 *          путём буквально, и получался путь вида "/b/c/../g", по которому
	 *          сервер ищет уже не тот ресурс.
	 *
	 *          Выйти выше корня разрешение не может: лишние ".." в начале пути
	 *          отбрасываются, как того и требует стандарт
	 *
	 * @param path сегменты пути для снятия точечных сегментов
	 *
	 */
	static void removeDotSegments(vector <string> & path) noexcept {
		// Если сегментов пути нет, снимать нечего
		if(path.empty())
			// Выходим из функции
			return;
		// Позиция записи очередного сохраняемого сегмента пути
		size_t offset = 0;
		// Признак того, что путь оканчивается разделителем
		bool trailing = false;
		/**
		 * Перебираем все сегменты пути
		 */
		for(size_t i = 0; i < path.size(); i++){
			// Получаем очередной сегмент пути
			const string & segment = path[i];
			// Признак последнего сегмента пути
			const bool last = ((i + 1) == path.size());
			// Если сегмент обозначает текущий каталог
			if(segment.compare(".") == 0){
				// Обозначение каталога, стоящее последним, оставляет за собой разделитель
				trailing = last;
				// Пропускаем итерацию
				continue;
			}
			// Если сегмент обозначает родительский каталог
			if(segment.compare("..") == 0){
				// Если сохранённые сегменты пути есть, снимаем последний из них
				if(offset > 0)
					// Снимаем последний сохранённый сегмент пути
					offset--;
				// Обозначение каталога, стоящее последним, оставляет за собой разделитель
				trailing = last;
				// Пропускаем итерацию
				continue;
			}
			// Если сегмент пути уже стоит на своём новом месте, переносить его не требуется
			if(offset != i)
				// Сохраняем сегмент пути на его новом месте
				path[offset] = ::move(path[i]);
			// Переходим к следующему месту записи сегмента пути
			offset++;
			// Сбрасываем признак разделителя в конце пути
			trailing = false;
		}
		// Отбрасываем сегменты пути, оставшиеся за сохранёнными
		path.resize(offset);
		// Если путь оканчивался обозначением каталога, оставляем за собой разделитель
		if(trailing)
			// Добавляем пустой сегмент, дающий разделитель в конце пути
			path.emplace_back("");
	}

	/**
	 * @brief Функция разбора пути URI на сегменты
	 *
	 * @details Сегменты дописываются к уже набранным, а не замещают их: разрешение
	 *          относительной ссылки складывает её путь с путём базового адреса
	 *          (RFC 3986 5.3), и сегменты ссылки ложатся следом за оставшимися от
	 *          базового.
	 *
	 *          Пустые сегменты значимы и сохраняются: путь "/a/b/" адресует не то
	 *          же, что путь "/a/b". Пустым является и сегмент перед ведущей косой
	 *          чертой, но его сборка ставит сама, дописывая косую перед каждым
	 *          сегментом, поэтому в путь он не заносится
	 *
	 * @param result результат, в который дописываются сегменты пути
	 * @param path   разбираемый путь URI
	 * @param log    объект работы с логами
	 *
	 */
	static void splitPath(vector <string> & result, string_view path, const log_t * log) noexcept {
		// Если путь пустой, разбирать нечего
		if(path.empty())
			// Выходим из функции
			return;
		// Очередной сегмент пути URI
		string_view segment;
		// Позиция начала сегмента пути URI: ведущая косая черта пропускается
		size_t start = ((path.front() == '/') ? 1 : 0), end = 0;
		/**
		 * Пока в пути URI есть символ "/", разделяем путь на сегменты и добавляем их в путь URI
		 */
		while((end = path.find('/', start)) != string_view::npos){
			// Получаем сегмент пути URI
			segment = path.substr(start, end - start);
			// Добавляем сегмент пути URI в путь URI
			result.push_back(decode(segment, log));
			// Обновляем позицию начала следующего сегмента
			start = (end + 1);
		}
		// Получаем последний сегмент пути URI
		segment = path.substr(start);
		// Добавляем последний сегмент пути URI в путь URI
		result.push_back(decode(segment, log));
	}

	/**
	 * @brief Функция разбора параметров URI на пары ключ-значение
	 *
	 * @param result результат, в который заносятся пары ключ-значение
	 * @param query  разбираемые параметры URI
	 * @param log    объект работы с логами
	 *
	 */
	static void splitQuery(unordered_multimap <string, string> & result, string_view query, const log_t * log) noexcept {
		// Если параметры пустые, разбирать нечего
		if(query.empty())
			// Выходим из функции
			return;
		// Очередная пара ключ-значение параметров URI
		string_view pair;
		// Позиция начала и конца пары ключ-значение параметров URI
		size_t start = 0, end = 0;
		/**
		 * Пока в параметрах URI есть символ "&", разделяем параметры на пары ключ-значение
		 */
		while(true){
			// Получаем позицию конца очередной пары ключ-значение параметров URI
			end = query.find('&', start);
			// Получаем очередную пару ключ-значение параметров URI
			pair = ((end != string_view::npos) ? query.substr(start, end - start) : query.substr(start));
			// Если пара ключ-значение параметров URI не пустая
			if(!pair.empty()){
				// Позиция символа "=" в паре ключ-значение параметров URI
				const size_t pos = pair.find('=');
				// Если в паре ключ-значение параметров URI есть символ "="
				if(pos != string_view::npos)
					// Добавляем пару ключ-значение параметров URI в параметры URI
					result.emplace(decode(pair.substr(0, pos), log), decode(pair.substr(pos + 1), log));
				// Иначе добавляем пару как ключ с пустым значением
				else result.emplace(decode(pair, log), "");
			}
			// Если пары ключ-значение параметров URI закончились, прерываем разбор
			if(end == string_view::npos)
				// Прерываем разбор параметров URI
				break;
			// Обновляем позицию начала следующей пары ключ-значение параметров URI
			start = (end + 1);
		}
	}

	/**
	 * @brief Функция определения типа URI по его схеме
	 *
	 * @details Схема сличается с полутора десятками известных, и сличение это
	 *          выполняется дважды - при разборе строки URI и при установке схемы
	 *          извне. Выписанное цепочкой сличений без учёта регистра, оно
	 *          обходилось в полтора десятка проходов по строке схемы на каждый
	 *          разбор. Отбор по длине оставляет из них не более трёх: схем одной
	 *          длины в наборе больше трёх не встречается.
	 *
	 * @param fmk    объект фреймворка
	 * @param scheme схема URI для определения типа
	 * @return       тип URI, соответствующий схеме
	 *
	 */
	[[nodiscard]] static uri_t::type_t schemeType(const fmk_t * fmk, string_view scheme) noexcept {
		/**
		 * Отбираем известные схемы по их длине
		 */
		switch(scheme.size()){
			// Если длина схемы составляет два символа
			case 2: {
				// Если протокол является WS
				if(fmk->compare(scheme, "ws"))
					// Выводим тип URI как WS
					return uri_t::type_t::WS;
			} break;
			// Если длина схемы составляет три символа
			case 3: {
				// Если протокол является WSS
				if(fmk->compare(scheme, "wss"))
					// Выводим тип URI как WSS
					return uri_t::type_t::WSS;
				// Если протокол является SSH
				if(fmk->compare(scheme, "ssh"))
					// Выводим тип URI как SSH
					return uri_t::type_t::SSH;
				// Если протокол является FTP
				if(fmk->compare(scheme, "ftp"))
					// Выводим тип URI как FTP
					return uri_t::type_t::FTP;
			} break;
			// Если длина схемы составляет четыре символа
			case 4: {
				// Если протокол является HTTP
				if(fmk->compare(scheme, "http"))
					// Выводим тип URI как HTTP
					return uri_t::type_t::HTTP;
				// Если протокол является MQTT
				if(fmk->compare(scheme, "mqtt"))
					// Выводим тип URI как MQTT
					return uri_t::type_t::MQTT;
				// Если протокол является File
				if(fmk->compare(scheme, "file"))
					// Выводим тип URI как File
					return uri_t::type_t::FILE;
				// Если протокол является Unix Socket
				if(fmk->compare(scheme, "unix"))
					// Выводим тип URI как Unix Socket
					return uri_t::type_t::UDS;
			} break;
			// Если длина схемы составляет пять символов
			case 5: {
				// Если протокол является HTTPS
				if(fmk->compare(scheme, "https"))
					// Выводим тип URI как HTTPS
					return uri_t::type_t::HTTPS;
				// Если протокол является REDIS
				if(fmk->compare(scheme, "redis"))
					// Выводим тип URI как REDIS
					return uri_t::type_t::REDIS;
				// Если протокол является MySQL
				if(fmk->compare(scheme, "mysql"))
					// Выводим тип URI как MySQL
					return uri_t::type_t::MYSQL;
			} break;
			// Если длина схемы составляет шесть символов
			case 6: {
				// Если протокол является E-mail
				if(fmk->compare(scheme, "mailto"))
					// Выводим тип URI как E-mail
					return uri_t::type_t::EMAIL;
				// Если протокол является Socks5
				if(fmk->compare(scheme, "socks5"))
					// Выводим тип URI как Socks5
					return uri_t::type_t::SOCKS5;
			} break;
			// Если длина схемы составляет десять символов
			case 10: {
				// Если протокол является PostgreSQL
				if(fmk->compare(scheme, "postgresql"))
					// Выводим тип URI как PostgreSQL
					return uri_t::type_t::POSTGRESQL;
			} break;
		}
		// Если это просто произвольная схема URI, то выводим тип URI как SCHEME
		return uri_t::type_t::SCHEME;
	}
};

