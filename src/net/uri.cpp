/**
 * @brief Метод установки пути URI
 *
 * @param path путь URI для установки
 *
 */
void awh::Uniform_Resource_Identifier::path(const vector <string> & path) noexcept {
	// Устанавливаем путь URI
	this->_path = path;
	/**
	 * Точечные сегменты снимаются и здесь, наравне с разбором (RFC 3986 6.2.2.3):
	 * храни их установщик, и объект оборота бы не пережил - собранная строка
	 * "http://h/../x" разбиралась бы обратно как "http://h/x", и объект, своей же
	 * строкой полученный, равным исходному уже не считался
	 */
	// Выполняем снятие точечных сегментов пути URI
	uri::removeDotSegments(this->_path);
}
