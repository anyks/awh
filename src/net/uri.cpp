/**
 * @brief Метод парсинга URI-запроса
 *
 * @param uri строка URI-запроса для получения параметров
 * @return    тип URI
 *
 */
awh::Uniform_Resource_Identifier::type_t awh::Uniform_Resource_Identifier::parse(string_view uri) noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Результат парсинга URI
		string_view scheme, userinfo, host, port, path, query, fragment;
		// Выполняем парсинг URI
		if(uri::parse(uri, scheme, userinfo, host, port, path, query, fragment)){
			/**
			 * Разбор строки URI разрешает её относительно уже разобранной
			 * (RFC 3986 5.2.2): сервер отдаёт в заголовке Location ссылку, которая
			 * может быть и полным адресом, и одним лишь путём, и даже одними
			 * параметрами, а собрать из неё нужно адрес, по которому идти дальше.
			 *
			 * Приметой наличия составляющей служит не её пустота, а само её наличие:
			 * разбор оставляет ненайденной составляющей пустой указатель, а найденной,
			 * но пустой - указатель на своё место в строке. Ссылка "?" параметры
			 * задаёт пустыми, а ссылка "g" не задаёт их вовсе, и разрешаются они
			 * поэтому по-разному
			 */
			// Признак того, что ссылка несёт авторити
			const bool refAuthority = ((host.data() != nullptr) || (userinfo.data() != nullptr) || (port.data() != nullptr));
			// Признак того, что ссылка несёт путь
			const bool refPath = ((path.data() != nullptr) && !path.empty());
			// Признак того, что ссылка несёт параметры
			const bool refQuery = (query.data() != nullptr);
			// Признак того, что ссылка несёт схему
			const bool refScheme = !scheme.empty();
			/**
			 * Ссылка со схемой замещает собой всё: она сама по себе полный адрес
			 */
			if(refScheme){
				// Очищаем все предыдущие данные URI
				this->clear();
				// Устанавливаем схему URI, приведённую к нижнему регистру (RFC 3986 6.2.2.1)
				this->_scheme = uri::lower(scheme);
				// Устанавливаем тип URI, соответствующий схеме
				this->_type = uri::schemeType(this->_fmk, scheme);
			/**
			 * Ссылка с авторити замещает авторити целиком - вместе с параметрами
			 * пользователя и портом, - а схему оставляет от прежнего адреса
			 */
			} else if(refAuthority) {
				// Очищаем логин пользователя URI
				this->_user.username.clear();
				// Очищаем пароль пользователя URI
				this->_user.password.clear();
				// Сбрасываем атрибуты URI адреса
				this->_attr.reset(nullptr);
			}
			// Если параметры пользователя URI не пустые
			if(!userinfo.empty()){
				// Выполняем поиск символа ":" в параметрах пользователя URI
				const size_t pos = userinfo.find(':');
				// Если в параметрах пользователя URI есть символ ":", то разделяем логин и пароль
				if(pos != string_view::npos){
					// Устанавливаем логин пользователя URI (с декодированием процент-последовательностей)
					this->_user.username = uri::decode(userinfo.substr(0, pos), this->_log);
					// Устанавливаем пароль пользователя URI (с декодированием процент-последовательностей)
					this->_user.password = uri::decode(userinfo.substr(pos + 1), this->_log);
				// Если в параметрах пользователя URI нет символа ":", то устанавливаем только логин, а пароль оставляем пустым
				} else this->_user.username = uri::decode(userinfo, this->_log);
			}
			// Если хост URI не пустой
			if(!host.empty())
				// Устанавливаем хост URI
				this->host(host);
			// Номер порта URI, полученный разбором его представления
			uint16_t number = 0;
			// Если порт URI не пустой, является числом и не выходит за пределы диапазона портов (0-65535)
			if(uri::parsePort(port, number)){
				// Устанавливаем порт URI
				this->port(number);
				/**
				 * Схема выводится из номера порта лишь тогда, когда у адреса есть хост:
				 * порт принадлежит авторити, и в отрыве от хоста он о ресурсе ничего не
				 * сообщает. Ссылка "//:443/x" хоста не несёт вовсе, а схему из порта
				 * получала, и собиралась она как "https:/x" - строка эта хоста не имеет,
				 * но выглядит уже полным адресом
				 */
				if((this->_type == type_t::NONE) && (this->_attr != nullptr)){
					/**
					 * Определяем тип порта URI адреса
					 */
					switch(number){
						// Если порт URI является 443, то это может быть HTTPS
						case 443: {
							// Устанавливаем схему URI
							this->_scheme = "https";
							// Устанавливаем тип URI как HTTPS
							this->_type = type_t::HTTPS;
						} break;
						// Если порт URI является 80, то это может быть HTTP
						case 80: {
							// Устанавливаем схему URI
							this->_scheme = "http";
							// Устанавливаем тип URI как HTTP
							this->_type = type_t::HTTP;
						} break;
						// Если порт URI является 22, то это может быть SSH
						case 22: {
							// Устанавливаем схему URI
							this->_scheme = "ssh";
							// Устанавливаем тип URI как SSH
							this->_type = type_t::SSH;
						} break;
						// Если порт URI является 21, то это может быть FTP
						case 21: {
							// Устанавливаем схему URI
							this->_scheme = "ftp";
							// Устанавливаем тип URI как FTP
							this->_type = type_t::FTP;
						} break;
						// Если порт URI является 1883, то это может быть MQTT
						case 1883: {
							// Устанавливаем схему URI
							this->_scheme = "mqtt";
							// Устанавливаем тип URI как MQTT
							this->_type = type_t::MQTT;
						} break;
						// Если порт URI является 25, то это может быть E-mail
						case 25: {
							// Устанавливаем схему URI
							this->_scheme = "mailto";
							// Устанавливаем тип URI как E-mail
							this->_type = type_t::EMAIL;
						} break;
						// Если порт URI является 1080, то это может быть Socks5
						case 1080: {
							// Устанавливаем схему URI
							this->_scheme = "socks5";
							// Устанавливаем тип URI как Socks5
							this->_type = type_t::SOCKS5;
						} break;
						// Если порт URI является 6379, то это может быть REDIS
						case 6379: {
							// Устанавливаем схему URI
							this->_scheme = "redis";
							// Устанавливаем тип URI как REDIS
							this->_type = type_t::REDIS;
						} break;
						// Если порт URI является 3306, то это может быть MySQL
						case 3306: {
							// Устанавливаем схему URI
							this->_scheme = "mysql";
							// Устанавливаем тип URI как MySQL
							this->_type = type_t::MYSQL;
						} break;
						// Если порт URI является 5432, то это может быть PostgreSQL
						case 5432: {
							// Устанавливаем схему URI
							this->_scheme = "postgresql";
							// Устанавливаем тип URI как PostgreSQL
							this->_type = type_t::POSTGRESQL;
						} break;
					}
				}
			// Если порт не указан явно в строке URI
			} else if(port.empty()) {
				// Текущий порт, уже сохранённый в атрибутах URI
				uint16_t current = 0;
				// Если атрибуты URI инициализированы, извлекаем уже сохранённый порт
				if(this->_attr != nullptr){
					/**
					 * Определяем тип атрибутов URI адреса
					 */
					switch(static_cast <uint8_t> (this->_attr->type)){
						// Если атрибуты URI адреса являются FQDN-адресом
						case static_cast <uint8_t> (net::type_t::FQDN):
							// Извлекаем порт хоста из атрибутов URI адреса
							current = awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port;
						break;
						// Если атрибуты URI адреса являются IPv4-адресом
						case static_cast <uint8_t> (net::type_t::IPV4):
						// Если атрибуты URI адреса являются IPv6-адресом
						case static_cast <uint8_t> (net::type_t::IPV6):
							// Извлекаем порт хоста из атрибутов URI адреса
							current = awh_cast <net::attr_net_t *> (this->_attr.get())->port;
						break;
					}
				}
				// Если явный порт ещё не задан, сохраняем стандартный порт для типа URI
				if(current == 0){
					// Определяем стандартный порт для текущего типа URI
					const uint16_t standard = this->defaultPort();
					// Если стандартный порт определён для данного типа URI
					if(standard != 0)
						// Устанавливаем стандартный порт URI в атрибуты адреса
						this->port(standard);
				}
			}
			/**
			 * Разрешаем путь, параметры и якорь ссылки относительно базового адреса
			 * (RFC 3986 5.2.2). Ссылка со схемой или с авторити замещает путь и
			 * параметры целиком; ссылка с путём складывается с базовым путём, если
			 * путь её относителен; ссылка без пути базовый путь оставляет
			 */
			if(refScheme || refAuthority){
				// Очищаем все предыдущие сегменты пути URI
				this->_path.clear();
				// Разбираем путь ссылки на сегменты
				uri::splitPath(this->_path, path, this->_log);
				// Снимаем точечные сегменты пути
				uri::removeDotSegments(this->_path);
				// Очищаем все предыдущие параметры URI
				this->_query.clear();
				// Разбираем параметры ссылки на пары ключ-значение
				uri::splitQuery(this->_query, query, this->_log);
			// Если ссылка несёт путь
			} else if(refPath) {
				/**
				 * Путь, начинающийся с косой черты, замещает базовый целиком, а
				 * относительный складывается с ним: от базового пути берётся всё до
				 * последней косой черты, то есть все сегменты, кроме последнего
				 * (RFC 3986 5.3)
				 */
				if(path.front() == '/')
					// Очищаем все предыдущие сегменты пути URI
					this->_path.clear();
				// Снимаем последний сегмент базового пути
				else if(!this->_path.empty())
					// Снимаем последний сегмент базового пути
					this->_path.pop_back();
				// Разбираем путь ссылки на сегменты
				uri::splitPath(this->_path, path, this->_log);
				// Снимаем точечные сегменты пути
				uri::removeDotSegments(this->_path);
				// Очищаем все предыдущие параметры URI
				this->_query.clear();
				// Разбираем параметры ссылки на пары ключ-значение
				uri::splitQuery(this->_query, query, this->_log);
			// Если ссылка несёт одни параметры, путь остаётся от базового адреса
			} else if(refQuery) {
				// Очищаем все предыдущие параметры URI
				this->_query.clear();
				// Разбираем параметры ссылки на пары ключ-значение
				uri::splitQuery(this->_query, query, this->_log);
			}
			// Якорь берётся от ссылки всегда: не заданный ею якорь снимается
			if(fragment.data() != nullptr)
				// Устанавливаем якорь URI
				this->_fragment = uri::decode(fragment, this->_log);
			// Если якорь ссылкой не задан, то очищаем его
			else this->_fragment.clear();
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, make_tuple(uri), log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
	// Возвращаем результат
	return this->_type;
}
/**
 * @brief Метод генерации ETag хэша текста
 *
 * @param text текст для перевода в строку
 * @param size длина записи хэша ETag в шестнадцатеричных цифрах, от 1 до 16 (по умолчанию 16)
 * @return     хэш etag
 *
 */
string awh::Uniform_Resource_Identifier::etag(string_view text, const uint8_t size) const noexcept {
	// Если текст передан и размер хэша больше 0
	if(!text.empty() && (size > 0)){
		/**
		 * Выполняем отлов ошибок
		 */
		try {
			// Получаем 64-битный FNV-1a хэш строки
			uint64_t hash = 0xcbf29ce484222325ULL;
			/**
			 * Перебираем все символы
			 */
			for(char letter : text){
				// Вычисляем FNV-1a хэш для каждого символа
				hash ^= static_cast <uint8_t> (letter);
				// Умножаем на простое число для 64-битного хэша
				hash *= 0x100000001b3ULL;
			}
			/**
			 * Запрошенный размер задаёт длину записи хэша в шестнадцатеричных цифрах
			 * и разрядность самого хэша: цифра покрывает четыре разряда, и запись из
			 * четырёх цифр несёт младшие шестнадцать разрядов. Прежде размер задавал
			 * лишь наименьшую ширину записи, а разрядностей различалось всего две, и
			 * запись короче значащей части не выходила: на запрошенных четырёх цифрах
			 * отдавались семь
			 */
			// Длина записи хэша в шестнадцатеричных цифрах: 64-разрядный хэш занимает шестнадцать
			const uint8_t length = ((size > 16) ? 16 : size);
			// Маска значащей части хэша, оставляющая запрошенное число цифр
			const uint64_t mask = ((length >= 16) ? 0xFFFFFFFFFFFFFFFFULL : ((1ULL << (length * 4)) - 1));
			/**
			 * Записываем хэш в шестнадцатеричном виде, с ведущими нулями, в кавычках.
			 * Записью занимался поток форматирования, а он на каждое обращение
			 * заводит буфер, разбирает набор признаков вывода и обращается к
			 * средствам локали. Стоило это дороже, чем обход хэшируемой строки
			 * длиной в две сотни символов, тогда как сама запись - это шестнадцать
			 * чтений из таблицы цифр
			 */
			// Таблица шестнадцатеричных символов в нижнем регистре
			static constexpr char digits[] = "0123456789abcdef";
			// Буфер записи хэша: пара кавычек и до шестнадцати шестнадцатеричных цифр
			char buffer[18];
			// Значащая часть хэша
			const uint64_t value = (hash & mask);
			// Позиция записи очередного символа
			uint8_t offset = static_cast <uint8_t> (length + 1);
			// Записываем закрывающую кавычку
			buffer[offset] = '"';
			// Остаток хэша, ещё не записанный в буфер
			uint64_t rest = value;
			/**
			 * Записываем цифры хэша справа налево, начиная с младшего разряда
			 */
			while(offset > 1){
				// Записываем очередную цифру хэша
				buffer[--offset] = digits[rest & 0x0F];
				// Отбрасываем записанный разряд хэша
				rest >>= 4;
			}
			// Записываем открывающую кавычку
			buffer[0] = '"';
			// Получаем строку ETag
			return string(buffer, static_cast <size_t> (length) + 2);
		/**
		 * Если возникает ошибка
		 */
		} catch(const exception & error) {
			/**
			 * Если включён режим отладки
			 */
			#if DEBUG_MODE
				// Записываем ошибку в лог
				this->_log->debug("%s", __PRETTY_FUNCTION__, make_tuple(text), log_t::flag_t::WARNING, error.what());
			/**
			 * Если режим отладки не включён
			 */
			#else
				// Записываем ошибку в лог
				this->_log->print("%s", log_t::flag_t::WARNING, error.what());
			#endif
		}
	}
	// Возвращаем значение по умолчанию (пустой ETag)
	return "";
}
/**
 * @brief Метод генерации строки URI
 *
 * @param item   режим элемента URI для генерации
 * @param format режим формата URI для генерации
 * @return       строка URI
 *
 */
string awh::Uniform_Resource_Identifier::print(const item_t item, const format_t format) const noexcept {
	// Переменная результата
	string result = "";
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		/**
		 * Определяем режим элемента URI для генерации
		 */
		switch(static_cast <uint8_t> (item)){
			// Если режим элемента URI для генерации является полным, то генерируем полный URI
			case static_cast <uint8_t> (item_t::URI): {
				// Добавляем схему URI в результат
				this->appendScheme(result);
				// Добавляем параметры пользователя URI в результат
				this->appendUser(result, true);
				// Добавляем хост и порт URI в результат с учётом формата генерации
				this->appendHost(result, format);
				// Если путь URI не пустой, то добавляем его в результат
				if(!this->_path.empty()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, UDS, FTP, FILE, REDIS, MySQL, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::UDS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::FILE):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						case static_cast <uint8_t> (type_t::POSTGRESQL): {
							// Добавляем сегменты пути URI в результат
							this->appendPath(result, true);
						} break;
						// Если тип URI является SSH
						case static_cast <uint8_t> (type_t::SSH): {
							// Добавляем символ ":" перед сегментом пути URI
							result.append(1, ':');
							// Добавляем сегменты пути URI в результат
							this->appendPath(result, false);
						} break;
						// Если тип URI является Scheme
						case static_cast <uint8_t> (type_t::SCHEME): {
							/**
							 * У произвольной схемы авторити может быть, а может и не быть.
							 * Путь при её наличии отделяется от неё косой чертой, как у всякого
							 * иерархического адреса, а при отсутствии записывается сразу за
							 * двоеточием. Записывался он всегда вторым способом, и хост с путём
							 * склеивались
							 */
							if(this->_attr != nullptr){
								// Добавляем сегменты пути URI в результат
								this->appendPath(result, true);
							// Если авторити у URI нет, путь записывается сразу за двоеточием
							} else {
								// Добавляем сегменты пути URI в результат
								this->appendPath(result, false);
							}
						} break;
					}
				// Если путь URI пустой, но параметры URI не пустые, то добавляем символ "/" в результат перед параметрами URI
				} else if(!this->_query.empty() || !this->_fragment.empty()) {
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, UDS, FTP, FILE, REDIS, MySQL, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::UDS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::FILE):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						case static_cast <uint8_t> (type_t::POSTGRESQL):
							// Добавляем символ "/" в результат перед параметрами URI
							result.append(1, '/');
						break;
					}
				}
				// Если параметры URI есть, то добавляем их в результат
				if(this->hasQuery()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, FTP, SSH, REDIS, MySQL, Scheme, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::SSH):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SCHEME):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является UDS
						case static_cast <uint8_t> (type_t::UDS):
						// Если тип URI является FILE
						case static_cast <uint8_t> (type_t::FILE):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						case static_cast <uint8_t> (type_t::POSTGRESQL): {
							// Добавляем строку параметров URI в результат вместе с её разделителем
							this->appendQuery(result, true, true);
						} break;
					}
				}
				// Если якорь URI не пустой, то добавляем его в результат
				if(!this->_fragment.empty()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, Scheme, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						// Если тип URI является FTP
						case static_cast <uint8_t> (type_t::FTP):
						// Если тип URI является SSH
						case static_cast <uint8_t> (type_t::SSH):
						// Если тип URI является UDS
						case static_cast <uint8_t> (type_t::UDS):
						// Если тип URI является FILE
						case static_cast <uint8_t> (type_t::FILE):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						// Если тип URI является REDIS
						case static_cast <uint8_t> (type_t::REDIS):
						// Если тип URI является MYSQL
						case static_cast <uint8_t> (type_t::MYSQL):
						// Если тип URI является SOCKS5
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является POSTGRESQL
						case static_cast <uint8_t> (type_t::POSTGRESQL):
						case static_cast <uint8_t> (type_t::SCHEME):
							// Добавляем разделитель якоря URI
							result.append(1, '#');
							// Добавляем якорь URI в результат
							uri::encode(result, this->_fragment, item_t::FRAGMENT, this->_log);
						break;
					}
				}
			} break;
			// Если режим элемента URI для генерации является схемой, то генерируем схему URI
			case static_cast <uint8_t> (item_t::SCHEME): {
				// Добавляем схему URI в результат
				this->appendScheme(result);
			} break;
			// Если режим элемента URI для генерации является пользователем, то генерируем параметры пользователя URI
			case static_cast <uint8_t> (item_t::USER): {
				// Добавляем параметры пользователя URI в результат
				this->appendUser(result, false);
			} break;
			// Если режим элемента URI для генерации является хостом, то генерируем хост URI
			case static_cast <uint8_t> (item_t::HOST): {
				// Добавляем хост и порт URI в результат с учётом формата генерации
				this->appendHost(result, format);
			} break;
			// Если режим элемента URI для генерации является путём, то генерируем путь URI
			case static_cast <uint8_t> (item_t::PATH): {
				// Если путь URI не пустой, то добавляем его в результат
				if(!this->_path.empty()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, UDS, FTP, FILE, REDIS, MySQL, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::UDS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::FILE):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						case static_cast <uint8_t> (type_t::POSTGRESQL): {
							// Добавляем сегменты пути URI в результат
							this->appendPath(result, true);
						} break;
						// Если тип URI является SSH
						case static_cast <uint8_t> (type_t::SSH): {
							// Добавляем символ ":" перед сегментом пути URI
							result.append(1, ':');
							// Добавляем сегменты пути URI в результат
							this->appendPath(result, false);
						} break;
						// Если тип URI является Scheme
						case static_cast <uint8_t> (type_t::SCHEME): {
							/**
							 * У произвольной схемы авторити может быть, а может и не быть.
							 * Путь при её наличии отделяется от неё косой чертой, как у всякого
							 * иерархического адреса, а при отсутствии записывается сразу за
							 * двоеточием. Записывался он всегда вторым способом, и хост с путём
							 * склеивались
							 */
							if(this->_attr != nullptr){
								// Добавляем сегменты пути URI в результат
								this->appendPath(result, true);
							// Если авторити у URI нет, путь записывается сразу за двоеточием
							} else {
								// Добавляем сегменты пути URI в результат
								this->appendPath(result, false);
							}
						} break;
					}
				// Если путь URI пустой, но параметры URI не пустые, то добавляем символ "/" в результат перед параметрами URI
				} else if(!this->_query.empty() || !this->_fragment.empty()) {
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, UDS, FTP, FILE, REDIS, MySQL, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::UDS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::FILE):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						case static_cast <uint8_t> (type_t::POSTGRESQL):
							// Добавляем символ "/" в результат перед параметрами URI
							result.append(1, '/');
						break;
					}
				}
			} break;
			// Если режим элемента URI для генерации является параметрами, то генерируем параметры URI
			case static_cast <uint8_t> (item_t::QUERY): {
				// Если параметры URI есть, то добавляем их в результат
				if(this->hasQuery()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, FTP, SSH, REDIS, MySQL, Scheme, SOCKS5, PostgreSQL, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::FTP):
						case static_cast <uint8_t> (type_t::SSH):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						case static_cast <uint8_t> (type_t::REDIS):
						case static_cast <uint8_t> (type_t::MYSQL):
						case static_cast <uint8_t> (type_t::SCHEME):
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является UDS
						case static_cast <uint8_t> (type_t::UDS):
						// Если тип URI является FILE
						case static_cast <uint8_t> (type_t::FILE):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						case static_cast <uint8_t> (type_t::POSTGRESQL): {
							/**
							 * Строка параметров собирается без добавочного параметра, который
							 * даёт функция обратного вызова: по этой самой строке она подпись
							 * и считает, и вызов её отсюда уходил бы в бесконечную рекурсию
							 */
							this->appendQuery(result, false, false);
						} break;
					}
				}
			} break;
			// Если режим элемента URI для генерации является якорем, то генерируем якорь URI
			case static_cast <uint8_t> (item_t::FRAGMENT): {
				// Если якорь URI не пустой, то добавляем его в результат
				if(!this->_fragment.empty()){
					/**
					 * Определяем тип URI адреса по схеме URI
					 */
					switch(static_cast <uint8_t> (this->_type)){
						// Если тип URI является WS, WSS, Scheme, HTTP или HTTPS
						case static_cast <uint8_t> (type_t::NONE):
						case static_cast <uint8_t> (type_t::WS):
						case static_cast <uint8_t> (type_t::WSS):
						case static_cast <uint8_t> (type_t::HTTP):
						case static_cast <uint8_t> (type_t::HTTPS):
						// Если тип URI является FTP
						case static_cast <uint8_t> (type_t::FTP):
						// Если тип URI является SSH
						case static_cast <uint8_t> (type_t::SSH):
						// Если тип URI является UDS
						case static_cast <uint8_t> (type_t::UDS):
						// Если тип URI является FILE
						case static_cast <uint8_t> (type_t::FILE):
						// Если тип URI является MQTT
						case static_cast <uint8_t> (type_t::MQTT):
						// Если тип URI является EMAIL
						case static_cast <uint8_t> (type_t::EMAIL):
						// Если тип URI является REDIS
						case static_cast <uint8_t> (type_t::REDIS):
						// Если тип URI является MYSQL
						case static_cast <uint8_t> (type_t::MYSQL):
						// Если тип URI является SOCKS5
						case static_cast <uint8_t> (type_t::SOCKS5):
						// Если тип URI является POSTGRESQL
						case static_cast <uint8_t> (type_t::POSTGRESQL):
						case static_cast <uint8_t> (type_t::SCHEME):
							// Добавляем якорь URI в результат
							uri::encode(result, this->_fragment, item_t::FRAGMENT, this->_log);
						break;
					}
				}
			} break;
			// Если режим элемента URI для генерации является происхождением, то генерируем происхождение URI
			case static_cast <uint8_t> (item_t::ORIGIN): {
				/**
				 * Происхождение ресурса складывается из схемы, хоста и порта, и
				 * ни из чего более (RFC 6454 4): значение это ставится в заголовки
				 * Origin и Access-Control-Allow-Origin, и параметрам пользователя в
				 * них места нет - иначе пароль уходил бы на сервер с каждым запросом
				 */
				// Добавляем схему URI в результат
				this->appendScheme(result);
				// Добавляем хост и порт URI в результат с учётом формата генерации
				this->appendHost(result, format);
			} break;
			// Если режим элемента URI для генерации является запросом, то генерируем относительный URI-запрос
			case static_cast <uint8_t> (item_t::REQUEST): {
				/**
				 * Определяем тип URI адреса по схеме URI
				 */
				switch(static_cast <uint8_t> (this->_type)){
					// Если тип URI является WS, WSS, FTP, UDS, FILE, MQTT, REDIS, MySQL, SOCKS5, PostgreSQL, HTTP или HTTPS, то добавляем схему URI в результат с "://"
					case static_cast <uint8_t> (type_t::NONE):
					case static_cast <uint8_t> (type_t::WS):
					case static_cast <uint8_t> (type_t::WSS):
					case static_cast <uint8_t> (type_t::FTP):
					case static_cast <uint8_t> (type_t::UDS):
					case static_cast <uint8_t> (type_t::FILE):
					case static_cast <uint8_t> (type_t::MQTT):
					case static_cast <uint8_t> (type_t::HTTP):
					case static_cast <uint8_t> (type_t::HTTPS):
					case static_cast <uint8_t> (type_t::REDIS):
					case static_cast <uint8_t> (type_t::MYSQL):
					case static_cast <uint8_t> (type_t::SOCKS5):
					case static_cast <uint8_t> (type_t::POSTGRESQL):
						// Добавляем относительный URI-запрос в результат
						this->appendRequest(result);
					break;
					// Если тип URI является E-mail или Scheme, то добавляем схему URI в результат без "://"
					case static_cast <uint8_t> (type_t::EMAIL): {
						// Добавляем параметры пользователя URI в результат
						this->appendUser(result, true);
						/**
						 * Определяем тип атрибутов URI адреса (если они установлены)
						 */
						if(this->_attr != nullptr) switch(static_cast <uint8_t> (this->_attr->type)){
							// Если атрибуты URI адреса являются FQDN-адресом
							case static_cast <uint8_t> (net::type_t::FQDN): {
								// Извлекаем атрибуты URI адреса как FQDN-адрес
								net::attr_fqdn_t * attr = awh_cast <net::attr_fqdn_t *> (this->_attr.get());
								// Возвращаем доменное имя хоста из атрибутов URI адреса
								result.append(attr->domain);
								// Если порт хоста в атрибутах URI адреса не равен 0 и не равен 25, то добавляем его в результат
								if((attr->port != 0) && (attr->port != 25)){
									// Добавляем разделитель хоста и порта
									result.append(1, ':');
									// Добавляем порт хоста в результат, если он не равен 0
									uri::appendNumber(result, attr->port);
								}
							} break;
							// Если атрибуты URI адреса являются IPv4-адресом
							case static_cast <uint8_t> (net::type_t::IPV4): {
								// Извлекаем атрибуты URI адреса как сетевой адрес
								net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
								// Если IP-адрес хоста в атрибутах URI адреса заведён
								if(attr->ip != nullptr){
									// Устанавливаем источник IP-адреса хоста в атрибутах URI адреса
									this->_addr->source(attr->ip.get(), net_addr_t::endian_t::LITTLE);
									// Дописываем IP-адрес хоста прямо в результат
									this->_addr->print(result);
								}
								// Если порт хоста в атрибутах URI адреса не равен 0 и не равен 25, то добавляем его в результат
								if((attr->port != 0) && (attr->port != 25)){
									// Добавляем разделитель хоста и порта
									result.append(1, ':');
									// Добавляем порт хоста в результат, если он не равен 0
									uri::appendNumber(result, attr->port);
								}
							} break;
							// Если атрибуты URI адреса являются IPv6-адресом
							case static_cast <uint8_t> (net::type_t::IPV6): {
								// Извлекаем атрибуты URI адреса как сетевой адрес
								net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
								// Если IP-адрес хоста в атрибутах URI адреса заведён
								if(attr->ip != nullptr){
									// Устанавливаем источник IP-адреса хоста в атрибутах URI адреса
									this->_addr->source(attr->ip.get(), net_addr_t::endian_t::LITTLE);
									// Добавляем открывающую скобку IPv6-адреса
									result.append(1, '[');
									// Запоминаем позицию, с которой начинается запись адреса
									const size_t offset = result.size();
									// Дописываем IP-адрес хоста прямо в результат
									this->_addr->print(result);
									/**
									 * Обозначение зоны IPv6-адреса отделяется знаком процента, а в URI знак
									 * этот открывает процент-последовательность, поэтому сам он записывается
									 * последовательностью "%25" (RFC 6874). Модуль адресов о строке URI не
									 * знает и отдаёт знак как есть
									 */
									// Позиция знака процента, отделяющего обозначение зоны IPv6-адреса
									const size_t zone = result.find('%', offset);
									// Если обозначение зоны у IPv6-адреса имеется
									if(zone != string::npos)
										// Дописываем знак процента до процент-последовательности
										result.insert(zone + 1, "25", 2);
									// Добавляем закрывающую скобку IPv6-адреса
									result.append(1, ']');
								}
								// Если порт хоста в атрибутах URI адреса не равен 0 и не равен 25, то добавляем его в результат
								if((attr->port != 0) && (attr->port != 25)){
									// Добавляем разделитель хоста и порта
									result.append(1, ':');
									// Добавляем порт хоста в результат, если он не равен 0
									uri::appendNumber(result, attr->port);
								}
							} break;
						}
					} break;
					// Если тип URI является SSH
					case static_cast <uint8_t> (type_t::SSH):
						// Добавляем сегменты пути URI в результат
						this->appendPath(result, false);
					break;
					// Если тип URI является Scheme
					case static_cast <uint8_t> (type_t::SCHEME): {
						/**
						 * У произвольной схемы авторити может быть, а может и не быть.
						 * Запрос при её наличии строится как у всякого иерархического
						 * адреса - путём от корня с параметрами и якорем, - а при
						 * отсутствии несёт один лишь путь, записанный за двоеточием.
						 *
						 * Строился он всегда вторым способом, и запрос к адресу
						 * "custom://host.com/a/b?c=1#d" выходил как "a/b": ведущей косой
						 * черты у него не было, а параметры с якорем пропадали вовсе.
						 * Запрос же к адресу "custom://host.com/?c=1" выходил и вовсе
						 * пустым, тогда как пустой строки запроса не бывает
						 */
						if(this->_attr != nullptr)
							// Добавляем относительный URI-запрос в результат
							this->appendRequest(result);
						// Добавляем сегменты пути URI в результат, если авторити у URI нет
						else this->appendPath(result, false);
					} break;
				}
			} break;
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, make_tuple(static_cast <uint16_t> (format)), log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
	// Возвращаем результат
	return result;
}
