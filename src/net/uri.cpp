/**
 * @brief Метод установки атрибутов URI
 *
 * @param attr атрибуты URI для установки
 *
 */
void awh::Uniform_Resource_Identifier::attr(const net::attr_t * attr) noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Если атрибуты URI не пустые
		if(attr != nullptr){
			/**
			 * Определяем тип атрибутов URI адреса
			 */
			switch(static_cast <uint8_t> (attr->type)){
				// Если атрибуты URI адреса являются адресом файловой системы
				case static_cast <uint8_t> (net::type_t::FS): {
					/**
					 * Если атрибуты URI не заведены либо заведены иной разновидностью,
					 * заводим их заново: приведение атрибутов одной разновидности к
					 * другой разновидностей не меняет, и запись пошла бы не в те поля
					 */
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::FS))
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_uds_t> ();
					// Если путь к сокету в атрибутах URI адреса не инициализирован
					if(awh_cast <net::attr_uds_t *> (this->_attr.get())->path == nullptr)
						// Инициализируем путь к сокету в атрибутах URI адреса
						awh_cast <net::attr_uds_t *> (this->_attr.get())->path = make_unique <net::addr_fs_t> ();
					// Копируем путь к сокету из атрибутов URI адреса
					awh_cast <net::addr_fs_t *> (awh_cast <net::attr_uds_t *> (this->_attr.get())->path.get())->address = awh_cast <const net::addr_fs_t *> (awh_cast <const net::attr_uds_t *> (attr)->path.get())->address;
				} break;
				// Если атрибуты URI адреса являются FQDN-адресом
				case static_cast <uint8_t> (net::type_t::FQDN): {
					/**
					 * Если атрибуты URI не заведены либо заведены иной разновидностью,
					 * заводим их заново: приведение атрибутов одной разновидности к
					 * другой разновидностей не меняет, и запись пошла бы не в те поля
					 */
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::FQDN))
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_fqdn_t> ();
					// Копируем порт хоста из атрибутов URI адреса
					awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port = awh_cast <const net::attr_fqdn_t *> (attr)->port;
					// Копируем доменное имя хоста из атрибутов URI адреса
					awh_cast <net::attr_fqdn_t *> (this->_attr.get())->domain = awh_cast <const net::attr_fqdn_t *> (attr)->domain;
				} break;
				// Если атрибуты URI адреса являются IPv4-адресом
				case static_cast <uint8_t> (net::type_t::IPV4): {
					// Извлекаем копируемые атрибуты URI адреса как сетевой адрес
					const net::attr_net_t * source = awh_cast <const net::attr_net_t *> (attr);
					/**
					 * Если атрибуты URI не инициализированы либо инициализированы иной
					 * разновидностью, заводим их заново: приведение атрибутов имени к
					 * атрибутам сетевого адреса разновидностей не меняет
					 */
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::IPV4)){
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_net_t> ();
						// Устанавливаем тип атрибутов URI адреса
						this->_attr->type = net::type_t::IPV4;
					}
					// Извлекаем атрибуты URI адреса как сетевой адрес
					net::attr_net_t * target = awh_cast <net::attr_net_t *> (this->_attr.get());
					// Копируем порт хоста из атрибутов URI адреса
					target->port = source->port;
					// Если копируемый IP-адрес хоста не заведён, сбрасываем и свой
					if(source->ip == nullptr)
						// Сбрасываем IP-адрес хоста в атрибутах URI адреса
						target->ip.reset(nullptr);
					// Иначе копируем IP-адрес хоста
					else {
						// Если свой объект IP-адреса хоста не подходит по размеру, заводим его заново
						if((target->ip == nullptr) || (target->ip->size != 4))
							// Инициализируем IP-адрес хоста в атрибутах URI адреса
							target->ip = make_unique <net::addr_net_ipv4_t> ();
						// Копируем IP-адрес хоста из атрибутов URI адреса
						awh_cast <net::addr_net_ipv4_t *> (target->ip.get())->address = awh_cast <const net::addr_net_ipv4_t *> (source->ip.get())->address;
					}
				} break;
				// Если атрибуты URI адреса являются IPv6-адресом
				case static_cast <uint8_t> (net::type_t::IPV6): {
					// Извлекаем копируемые атрибуты URI адреса как сетевой адрес
					const net::attr_net_t * source = awh_cast <const net::attr_net_t *> (attr);
					/**
					 * Если атрибуты URI не инициализированы либо инициализированы иной
					 * разновидностью, заводим их заново: приведение атрибутов имени к
					 * атрибутам сетевого адреса разновидностей не меняет
					 */
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::IPV6)){
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_net_t> ();
						// Устанавливаем тип атрибутов URI адреса
						this->_attr->type = net::type_t::IPV6;
					}
					// Извлекаем атрибуты URI адреса как сетевой адрес
					net::attr_net_t * target = awh_cast <net::attr_net_t *> (this->_attr.get());
					// Копируем порт хоста из атрибутов URI адреса
					target->port = source->port;
					// Если копируемый IP-адрес хоста не заведён, сбрасываем и свой
					if(source->ip == nullptr)
						// Сбрасываем IP-адрес хоста в атрибутах URI адреса
						target->ip.reset(nullptr);
					// Иначе копируем IP-адрес хоста
					else {
						// Если свой объект IP-адреса хоста не подходит по размеру, заводим его заново
						if((target->ip == nullptr) || (target->ip->size != 16))
							// Инициализируем IP-адрес хоста в атрибутах URI адреса
							target->ip = make_unique <net::addr_net_ipv6_t> ();
						// Копируем IP-адрес хоста из атрибутов URI адреса
						awh_cast <net::addr_net_ipv6_t *> (target->ip.get())->address = awh_cast <const net::addr_net_ipv6_t *> (source->ip.get())->address;
					}
				} break;
			}
			/**
			 * Разновидность заведённым атрибутам отдельно не проставляется: её
			 * несёт сам конструктор атрибутов каждой разновидности, а разбор выше
			 * заводит их заново, если разновидность не совпала.
			 *
			 * Прежде разновидность записывалась следом за разбором и без оглядки
			 * на то, завелись ли атрибуты вообще. Разновидностей же у адреса
			 * больше, чем модуль URI различает: адрес аппаратный и вовсе не
			 * определённый в разбор не попадают. Атрибуты сетевого адреса,
			 * только что заведённые, разновидности ещё не несут, и установка их
			 * пустому объекту URI разыменовывала пустой указатель
			 */
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
/**
 * @brief Метод получения хоста URI
 *
 * @return хост URI
 *
 */
string awh::Uniform_Resource_Identifier::host() const noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Если атрибуты URI не пустые
		if(this->_attr != nullptr){
			/**
			 * Определяем тип атрибутов URI адреса
			 */
			switch(static_cast <uint8_t> (this->_attr->type)){
				// Если атрибуты URI адреса являются адресом файловой системы
				case static_cast <uint8_t> (net::type_t::FS): {
					// Извлекаем атрибуты URI адреса как адрес файловой системы
					net::attr_uds_t * attr = awh_cast <net::attr_uds_t *> (this->_attr.get());
					// Если путь к сокету в атрибутах URI адреса не заведён, отдавать нечего
					if(attr->path == nullptr)
						// Выводим пустой хост
						return "";
					// Возвращаем путь к сокету из атрибутов URI адреса
					return awh_cast <net::addr_fs_t *> (attr->path.get())->address;
				}
				// Если атрибуты URI адреса являются FQDN-адресом
				case static_cast <uint8_t> (net::type_t::FQDN):
					// Возвращаем доменное имя хоста из атрибутов URI адреса
					return awh_cast <net::attr_fqdn_t *> (this->_attr.get())->domain;
				// Если атрибуты URI адреса являются IPv4-адресом
				case static_cast <uint8_t> (net::type_t::IPV4):
				// Если атрибуты URI адреса являются IPv6-адресом
				case static_cast <uint8_t> (net::type_t::IPV6): {
					// Извлекаем атрибуты URI адреса как сетевой адрес
					net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
					// Если IP-адрес хоста в атрибутах URI адреса не заведён, отдавать нечего
					if(attr->ip == nullptr)
						// Выводим пустой хост
						return "";
					// Устанавливаем источник IP-адреса хоста в атрибутах URI адреса
					this->_addr->source(attr->ip.get(), net_addr_t::endian_t::LITTLE);
					// Возвращаем IP-адрес хоста в виде строки
					return static_cast <string> (* this->_addr.get());
				}
			}
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
	// Возвращаем значение по умолчанию
	return "";
}
/**
 * @brief Метод установки хоста URI
 *
 * @param host хост URI для установки
 *
 */
void awh::Uniform_Resource_Identifier::host(string_view host) noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Признак того, что хост URI установлен как сетевой адрес
		bool network = false;
		/**
		 * Порт принадлежит авторити, а не разновидности адреса, поэтому смена
		 * доменного имени на адрес и обратно его сохраняет. Атрибуты при смене
		 * разновидности заводятся заново, и порт снимается с прежних до замены
		 */
		// Порт хоста, уже сохранённый в атрибутах URI адреса
		uint16_t current = 0;
		// Если атрибуты URI адреса инициализированы
		if(this->_attr != nullptr){
			/**
			 * Определяем тип атрибутов URI адреса
			 */
			switch(static_cast <uint8_t> (this->_attr->type)){
				// Если атрибуты URI адреса являются FQDN-адресом
				case static_cast <uint8_t> (net::type_t::FQDN):
					// Снимаем порт хоста с атрибутов URI адреса
					current = awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port;
				break;
				// Если атрибуты URI адреса являются IPv4-адресом
				case static_cast <uint8_t> (net::type_t::IPV4):
				// Если атрибуты URI адреса являются IPv6-адресом
				case static_cast <uint8_t> (net::type_t::IPV6):
					// Снимаем порт хоста с атрибутов URI адреса
					current = awh_cast <net::attr_net_t *> (this->_attr.get())->port;
				break;
			}
		}
		// Определяем разновидность сетевого адреса, которой строка хоста способна оказаться
		const net_addr_t::type_t expected = uri::addressType(host);
		/**
		 * Выполняем парсинг переданного адреса единственной разновидностью, которой он способен оказаться
		 */
		if((expected != net_addr_t::type_t::NONE) && this->_addr->parse(host, expected)){
			// Порт хоста в атрибутах URI адреса
			uint16_t port = 0;
			/**
			 * Определяем тип полученного IP-адреса
			 */
			switch(static_cast <uint8_t> (this->_addr->type())){
				// Если хост URI является IPv4-адресом
				case static_cast <uint8_t> (net_addr_t::type_t::IPV4): {
					// Помечаем хост URI как сетевой адрес
					network = true;
					// Сохраняем порт хоста, снятый с прежних атрибутов URI адреса
					port = current;
					// Если атрибуты URI не инициализированы или уже инициализированы, но не являются IPv4-адресом
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::IPV4)){
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_net_t> ();
						// Устанавливаем тип атрибутов URI адреса
						this->_attr->type = net::type_t::IPV4;
					}
				} break;
				// Если хост URI является IPv6-адресом
				case static_cast <uint8_t> (net_addr_t::type_t::IPV6): {
					// Помечаем хост URI как сетевой адрес
					network = true;
					// Сохраняем порт хоста, снятый с прежних атрибутов URI адреса
					port = current;
					// Если атрибуты URI не инициализированы или уже инициализированы, но не являются IPv6-адресом
					if((this->_attr == nullptr) || (this->_attr->type != net::type_t::IPV6)){
						// Инициализируем атрибуты URI
						this->_attr = make_unique <net::attr_net_t> ();
						// Устанавливаем тип атрибутов URI адреса
						this->_attr->type = net::type_t::IPV6;
					}
				} break;
			}
			/**
			 * Если разобранный адрес оказался сетевым, переносим его в атрибуты URI
			 */
			if(network){
				// Извлекаем атрибуты URI адреса как сетевой адрес
				net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
				// Устанавливаем порт хоста в атрибутах URI адреса
				attr->port = port;
				/**
				 * Если заведённый объект IP-адреса подходит по размеру, заполняем его
				 * на месте.
				 *
				 * Извлечение адреса в чистом виде отдаёт его новым объектом, то есть
				 * берёт под него память, - а содержимое адреса составляют четыре либо
				 * шестнадцать октетов, и модуль адресов отдаёт их отдельными методами
				 * без всякого выделения памяти. Заводить объект заново, имея на руках
				 * подходящий, незачем: у клиента, переходящего с адреса на адрес, это
				 * выделение приходилось бы на каждый переход.
				 *
				 * Подходящесть проверяется размером самого адреса, а не разновидностью
				 * атрибутов: конструктор атрибутов сетевого адреса заводит под адрес
				 * объект IPv4 независимо от разновидности, которая будет установлена
				 * следом, поэтому у атрибутов IPv6-адреса объект под адрес поначалу
				 * оказывается IPv4-адресом. Размер же лежит в самом объекте адреса и
				 * его действительную разновидность сообщает верно
				 */
				// Размер заведённого объекта IP-адреса хоста в октетах
				const uint16_t size = ((attr->ip != nullptr) ? attr->ip->size : 0);
				// Если заведённый объект IP-адреса является IPv4-адресом
				if((this->_attr->type == net::type_t::IPV4) && (size == 4))
					// Заполняем IPv4-адрес хоста на месте
					awh_cast <net::addr_net_ipv4_t *> (attr->ip.get())->address = this->_addr->v4(net_addr_t::endian_t::LITTLE);
				// Если заведённый объект IP-адреса является IPv6-адресом
				else if((this->_attr->type == net::type_t::IPV6) && (size == 16))
					// Заполняем IPv6-адрес хоста на месте
					awh_cast <net::addr_net_ipv6_t *> (attr->ip.get())->address = this->_addr->v6(net_addr_t::endian_t::LITTLE);
				// Иначе заводим объект IP-адреса хоста в атрибутах URI адреса заново
				else attr->ip = ::move(this->_addr->source(net_addr_t::endian_t::LITTLE));
			}
		}
		/**
		 * Если хост URI сетевым адресом не оказался, определяем его разновидность.
		 * Сюда попадает и разобранный адрес, сетевым не являющийся, - аппаратный:
		 * атрибутов сетевого адреса ему не завести, и обрабатывается он как имя
		 */
		if(!network){
			/**
			 * Определяем разновидность полученного хоста URI адреса.
			 *
			 * Разновидностей хост может принимать восемь, но различает их модуль URI
			 * всего две: путь файловой системы, которому заводятся атрибуты доменного
			 * сокета, и всё остальное, которому заводятся атрибуты имени. Полное же
			 * определение разновидности обходит строку, снимает с неё приметы и
			 * проверяет её на каждую из подошедших по приметам разновидностей - и
			 * доменное имя, стоящее в этом переборе последним, платит за все
			 * предшествующие ему проверки впустую.
			 *
			 * Спрошено поэтому ровно то, что нужно: принадлежность строки к путям
			 * файловой системы. Проверка эта состоит из сравнения первых символов, и
			 * ответ её совпадает с ответом полного перебора: разновидности, стоящие в
			 * переборе до пути файловой системы, начинаются либо с приставки
			 * протокола, либо с символа из алфавита сетевых адресов, а путь
			 * файловой системы - с косой черты, тильды, точки или обозначения
			 * устройства. Совпадение закреплено тестом UriFixture.HostKindMatchesFullScanTest
			 */
			if(this->_addr->check(host, net_addr_t::type_t::FS)){
				// Если атрибуты URI не инициализированы или уже инициализированы, но не являются FS-адресом
				if((this->_attr == nullptr) || (this->_attr->type != net::type_t::FS)){
					// Инициализируем атрибуты URI
					this->_attr = make_unique <net::attr_uds_t> ();
					// Устанавливаем тип атрибутов URI адреса
					this->_attr->type = net::type_t::FS;
				}
				// Если путь к сокету в атрибутах URI адреса не инициализирован
				if(awh_cast <net::attr_uds_t *> (this->_attr.get())->path == nullptr)
					// Инициализируем путь к сокету в атрибутах URI адреса
					awh_cast <net::attr_uds_t *> (this->_attr.get())->path = make_unique <net::addr_fs_t> ();
				// Копируем путь к сокету из атрибутов URI адреса
				awh_cast <net::addr_fs_t *> (awh_cast <net::attr_uds_t *> (this->_attr.get())->path.get())->address = host;
			// Если хост URI является доменным именем
			} else {
				// Если атрибуты URI не инициализированы или уже инициализированы, но не являются FQDN-адресом
				if((this->_attr == nullptr) || (this->_attr->type != net::type_t::FQDN)){
					// Инициализируем атрибуты URI
					this->_attr = make_unique <net::attr_fqdn_t> ();
					// Устанавливаем тип атрибутов URI адреса
					this->_attr->type = net::type_t::FQDN;
				}
				// Устанавливаем порт хоста, снятый с прежних атрибутов URI адреса
				awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port = current;
				// Копируем доменное имя хоста, приведённое к нижнему регистру (RFC 3986 6.2.2.1)
				awh_cast <net::attr_fqdn_t *> (this->_attr.get())->domain = uri::lower(host);
			}
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, make_tuple(host), log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
/**
 * @brief Метод определения стандартного порта для текущего типа URI
 *
 * @return стандартный порт или 0, если для типа URI он не определён
 *
 */
uint16_t awh::Uniform_Resource_Identifier::defaultPort() const noexcept {
	/**
	 * Определяем стандартный порт по типу URI
	 */
	switch(static_cast <uint8_t> (this->_type)){
		// Если тип URI является WS или HTTP, то стандартный порт 80
		case static_cast <uint8_t> (type_t::WS):
		case static_cast <uint8_t> (type_t::HTTP): return 80;
		// Если тип URI является WSS или HTTPS, то стандартный порт 443
		case static_cast <uint8_t> (type_t::WSS):
		case static_cast <uint8_t> (type_t::HTTPS): return 443;
		// Если тип URI является SSH, то стандартный порт 22
		case static_cast <uint8_t> (type_t::SSH): return 22;
		// Если тип URI является FTP, то стандартный порт 21
		case static_cast <uint8_t> (type_t::FTP): return 21;
		// Если тип URI является MQTT, то стандартный порт 1883
		case static_cast <uint8_t> (type_t::MQTT): return 1883;
		// Если тип URI является E-mail, то стандартный порт 25
		case static_cast <uint8_t> (type_t::EMAIL): return 25;
		// Если тип URI является Socks5, то стандартный порт 1080
		case static_cast <uint8_t> (type_t::SOCKS5): return 1080;
		// Если тип URI является REDIS, то стандартный порт 6379
		case static_cast <uint8_t> (type_t::REDIS): return 6379;
		// Если тип URI является MySQL, то стандартный порт 3306
		case static_cast <uint8_t> (type_t::MYSQL): return 3306;
		// Если тип URI является PostgreSQL, то стандартный порт 5432
		case static_cast <uint8_t> (type_t::POSTGRESQL): return 5432;
	}
	// Для неизвестного типа URI стандартный порт не определён
	return 0;
}
/**
 * @brief Метод добавления схемы URI в результат с разделителем, зависящим от типа URI
 *
 * @param result результат, в который добавляется схема URI
 *
 */
void awh::Uniform_Resource_Identifier::appendScheme(string & result) const noexcept {
	// Если схема URI пустая, то добавлять нечего
	if(this->_scheme.empty())
		// Выходим из метода
		return;
	// Добавляем схему URI в результат
	result.append(this->_scheme);
	/**
	 * Схему от авторити отделяют двоеточие с двумя косыми чертами, а схему,
	 * авторити не имеющую, - одно двоеточие. Признаком служит не разновидность
	 * URI, а наличие самой авторити: у произвольной схемы её может и не быть, а
	 * разделитель ей доставался всегда одинарный, и адрес "custom://host/path"
	 * собирался как "custom:hostpath" - хост склеивался с путём.
	 *
	 * Опаковые схемы авторити не несут по своему устройству: у адреса почты за
	 * схемой стоит сам адрес получателя, а у SSH - учётная запись с машиной в
	 * записи, принятой у копирования по сети
	 */
	switch(static_cast <uint8_t> (this->_type)){
		// Если тип URI является SSH или E-mail, то авторити у него нет
		case static_cast <uint8_t> (type_t::SSH):
		case static_cast <uint8_t> (type_t::EMAIL):
			// Добавляем разделитель схемы
			result.append(1, ':');
		break;
		/**
		 * Доменный сокет и файловая система авторити несут всегда, пусть и
		 * пустую: записи "unix:///var/run/x.sock" и "file:///etc/hosts" - это
		 * пустой хост с путём от корня, и две косые черты у них обязательны
		 */
		case static_cast <uint8_t> (type_t::UDS):
		case static_cast <uint8_t> (type_t::FILE):
			// Добавляем разделитель схемы и авторити
			result.append("://", 3);
		break;
		// Для остальных разновидностей разделитель определяется наличием авторити
		default: {
			// Если авторити у URI есть
			if(this->_attr != nullptr)
				// Добавляем разделитель схемы и авторити
				result.append("://", 3);
			// Добавляем разделитель схемы, если авторити у URI нет
			else result.append(1, ':');
		}
	}
}
/**
 * @brief Метод добавления параметров пользователя (логин и пароль) в результат
 *
 * @param result    результат, в который добавляются параметры пользователя
 * @param delimiter флаг добавления разделителя "@" после параметров пользователя
 *
 */
void awh::Uniform_Resource_Identifier::appendUser(string & result, const bool delimiter) const noexcept {
	// Если логин пользователя URI пустой, то добавлять нечего
	if(this->_user.username.empty())
		// Выходим из метода
		return;
	/**
	 * Логин и пароль дописываются с процентным кодированием: разбор их
	 * раскодирует, и без обратного кодирования знак из числа разделителей
	 * авторити - косая черта, решётка, вопрос или собачка - вышел бы в строку
	 * как есть и оборвал бы поле раньше времени. Повторный разбор такой строки
	 * дал бы уже другой хост: у "http://user:pa/ss@example.com" хостом
	 * оказывается "user", а всё остальное - путём
	 */
	// Добавляем логин пользователя URI в результат
	uri::encode(result, this->_user.username, item_t::USER, this->_log);
	// Если пароль пользователя URI не пустой, то добавляем его в результат
	if(!this->_user.password.empty()){
		// Добавляем разделитель логина и пароля пользователя URI
		result.append(1, ':');
		// Добавляем пароль пользователя URI в результат
		uri::encode(result, this->_user.password, item_t::USER, this->_log);
	}
	// Если требуется разделитель, добавляем символ "@" после параметров пользователя URI
	if(delimiter)
		// Добавляем символ "@" после параметров пользователя URI
		result.append(1, '@');
}
/**
 * @brief Метод добавления хоста (и порта для сетевых адресов) в результат
 *
 * @param result результат, в который добавляется хост
 * @param format режим формата URI для генерации
 *
 */
void awh::Uniform_Resource_Identifier::appendHost(string & result, const format_t format) const noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Если атрибуты URI пустые, то добавлять нечего
		if(this->_attr == nullptr)
			// Выходим из метода
			return;
		/**
		 * Определяем тип атрибутов URI адреса
		 */
		switch(static_cast <uint8_t> (this->_attr->type)){
			// Если атрибуты URI адреса являются адресом файловой системы
			case static_cast <uint8_t> (net::type_t::FS): {
				// Извлекаем атрибуты URI адреса как адрес файловой системы
				net::attr_uds_t * attr = awh_cast <net::attr_uds_t *> (this->_attr.get());
				// Если путь к сокету в атрибутах URI адреса заведён
				if(attr->path != nullptr)
					// Добавляем путь к сокету из атрибутов URI адреса (порт для файловой системы не используется)
					result.append(awh_cast <net::addr_fs_t *> (attr->path.get())->address);
			} break;
			// Если атрибуты URI адреса являются FQDN-адресом
			case static_cast <uint8_t> (net::type_t::FQDN): {
				// Извлекаем атрибуты URI адреса как FQDN-адрес
				net::attr_fqdn_t * attr = awh_cast <net::attr_fqdn_t *> (this->_attr.get());
				// Добавляем доменное имя хоста из атрибутов URI адреса
				result.append(attr->domain);
				// Добавляем порт хоста в результат с учётом формата генерации
				this->appendPort(result, attr->port, format);
			} break;
			// Если атрибуты URI адреса являются IPv4-адресом
			case static_cast <uint8_t> (net::type_t::IPV4): {
				// Извлекаем атрибуты URI адреса как сетевой адрес
				net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
				// Если IP-адрес хоста в атрибутах URI адреса заведён
				if(attr->ip != nullptr){
					// Устанавливаем источник IP-адреса хоста в атрибутах URI адреса
					this->_addr->source(attr->ip.get(), net_addr_t::endian_t::LITTLE);
					// Дописываем IP-адрес хоста прямо в результат
					this->_addr->print(result);
				}
				// Добавляем порт хоста в результат с учётом формата генерации
				this->appendPort(result, attr->port, format);
			} break;
			// Если атрибуты URI адреса являются IPv6-адресом
			case static_cast <uint8_t> (net::type_t::IPV6): {
				// Извлекаем атрибуты URI адреса как сетевой адрес
				net::attr_net_t * attr = awh_cast <net::attr_net_t *> (this->_attr.get());
				// Если IP-адрес хоста в атрибутах URI адреса заведён
				if(attr->ip != nullptr){
					// Устанавливаем источник IP-адреса хоста в атрибутах URI адреса
					this->_addr->source(attr->ip.get(), net_addr_t::endian_t::LITTLE);
					// Добавляем открывающую скобку IPv6-адреса
					result.append(1, '[');
					// Запоминаем позицию, с которой начинается запись адреса
					const size_t offset = result.size();
					// Дописываем IP-адрес хоста прямо в результат
					this->_addr->print(result);
					/**
					 * Обозначение зоны IPv6-адреса отделяется знаком процента, а в URI знак
					 * этот открывает процент-последовательность, поэтому сам он записывается
					 * последовательностью "%25" (RFC 6874). Модуль адресов о строке URI не
					 * знает и отдаёт знак как есть
					 */
					// Позиция знака процента, отделяющего обозначение зоны IPv6-адреса
					const size_t zone = result.find('%', offset);
					// Если обозначение зоны у IPv6-адреса имеется
					if(zone != string::npos)
						// Дописываем знак процента до процент-последовательности
						result.insert(zone + 1, "25", 2);
					// Добавляем закрывающую скобку IPv6-адреса
					result.append(1, ']');
				}
				// Добавляем порт хоста в результат с учётом формата генерации
				this->appendPort(result, attr->port, format);
			} break;
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
/**
 * @brief Метод добавления порта хоста в результат с учётом формата генерации
 *
 * @param result результат, в который добавляется порт
 * @param port   порт хоста, заданный явно (0 — если не задан)
 * @param format режим формата URI для генерации
 *
 */
void awh::Uniform_Resource_Identifier::appendPort(string & result, const uint16_t port, const format_t format) const noexcept {
	// Определяем стандартный порт для текущего типа URI
	const uint16_t standard = this->defaultPort();
	/**
	 * Определяем режим формата URI для генерации
	 */
	switch(static_cast <uint8_t> (format)){
		// Если режим формата URI является полным, то выводим порт всегда, когда он известен
		case static_cast <uint8_t> (format_t::FULL): {
			// Используем явно заданный порт, иначе стандартный порт для типа URI
			const uint16_t value = ((port != 0) ? port : standard);
			// Если итоговый порт определён, добавляем его в результат
			if(value != 0){
				// Добавляем разделитель хоста и порта
				result.append(1, ':');
				// Добавляем порт хоста в результат
				uri::appendNumber(result, value);
			}
		} break;
		// Если режим формата URI является сокращённым, то выводим порт только если он нестандартный
		case static_cast <uint8_t> (format_t::SMART): {
			// Если порт задан явно и отличается от стандартного порта для типа URI, добавляем его в результат
			if((port != 0) && (port != standard)){
				// Добавляем разделитель хоста и порта
				result.append(1, ':');
				// Добавляем порт хоста в результат
				uri::appendNumber(result, port);
			}
		} break;
	}
}
/**
 * @brief Метод добавления сегментов пути URI в результат
 *
 * @param result  результат, в который добавляются сегменты пути
 * @param leading флаг записи разделителя перед первым сегментом пути
 *
 */
void awh::Uniform_Resource_Identifier::appendPath(string & result, const bool leading) const noexcept {
	/**
	 * Перебираем все сегменты пути URI
	 */
	for(auto i = this->_path.begin(); i != this->_path.end(); ++i){
		/**
		 * Разделитель ставится перед каждым сегментом у пути, ведущего от корня,
		 * и лишь между сегментами у пути опакового адреса, записанного сразу за
		 * двоеточием схемы
		 */
		if(leading || (i != this->_path.begin()))
			// Добавляем разделитель перед сегментом пути URI
			result.append(1, '/');
		// Добавляем сегмент пути URI в результат
		uri::encode(result, * i, item_t::PATH, this->_log);
	}
}
/**
 * @brief Метод проверки наличия параметров URI для записи
 *
 * @return результат проверки
 *
 */
bool awh::Uniform_Resource_Identifier::hasQuery() const noexcept {
	/**
	 * Строку параметров даёт не только само хранилище параметров, но и функция
	 * обратного вызова: ей отведён добавочный параметр, которым подписывается
	 * запрос. Строка поэтому считается имеющейся и при пустом хранилище, если
	 * функция обратного вызова установлена
	 */
	return (!this->_query.empty() || (this->_callback != nullptr));
}
/**
 * @brief Метод добавления пар ключ-значение параметров URI в результат
 *
 * @param result    результат, в который добавляются параметры
 * @param separator флаг записи разделителя перед строкой параметров
 * @param callback  флаг вызова функции обратного вызова, дающей добавочный параметр
 *
 */
void awh::Uniform_Resource_Identifier::appendQuery(string & result, const bool separator, const bool callback) const noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Позиция, с которой начинается запись строки параметров URI
		const size_t offset = result.size();
		// Если требуется разделитель, добавляем его перед строкой параметров URI
		if(separator)
			// Добавляем разделитель строки параметров URI
			result.append(1, '?');
		// Число пар ключ-значение параметров URI
		const size_t count = this->_query.size();
		// Если пары ключ-значение параметров URI есть
		if(count > 0){
			/**
			 * Порядок пар в строке параметров стандартом не задан, но сама строка
			 * обязана получаться одна и та же: по строке запроса считается подпись и
			 * метка изменения ресурса, по ней же сличаются адреса и ведётся учёт
			 * ответов в хранилище. Хранилище параметров обходится в порядке своих
			 * корзин, а порядок этот зависит от того, в каком порядке пары в него
			 * заносились, и пересборка адреса из собственной же строки его меняла:
			 * адрес "?a=1&b=2&c=3" на каждом обороте перекладывался между двумя
			 * видами и ни к одному из них не сходился.
			 *
			 * Пары поэтому выстраиваются по ключу, и выстраивание это устойчиво:
			 * совпадающие по ключу пары хранилище держит подряд и в порядке их
			 * занесения, а порядок этот значим - параметры "?sort=name&sort=age"
			 * задают очерёдность, и перестановка значений меняет смысл запроса.
			 * Устойчивое выстраивание оставляет их друг относительно друга как есть,
			 * а от порядка занесения самих ключей не зависит, и строка получается
			 * одна и та же при любом числе оборотов.
			 *
			 * Выстраиваются не сами пары, а указатели на них, и набор указателей
			 * размещается на стеке: параметров у адреса единицы, и выделение памяти
			 * под их перечисление стоило бы дороже самого выстраивания
			 */
			// Набор указателей на пары ключ-значение параметров URI, размещаемый на стеке
			const pair <const string, string> * buffer[uri::QUERY_INPLACE];
			// Набор указателей на пары ключ-значение параметров URI, размещаемый в куче
			vector <const pair <const string, string> *> spare;
			// Начало набора указателей на пары ключ-значение параметров URI
			const pair <const string, string> ** pairs = buffer;
			// Если пар больше, чем вмещает набор на стеке, размещаем набор в куче
			if(count > uri::QUERY_INPLACE){
				// Выделяем память под набор указателей на пары ключ-значение параметров URI
				spare.resize(count);
				// Переносим начало набора указателей в кучу
				pairs = spare.data();
			}
			// Позиция записи очередного указателя на пару ключ-значение параметров URI
			size_t index = 0;
			/**
			 * Перебираем все пары ключ-значение параметров URI
			 */
			for(const auto & item : this->_query)
				// Запоминаем указатель на очередную пару ключ-значение параметров URI
				pairs[index++] = & item;
			/**
			 * Выстраиваем указатели на пары ключ-значение параметров URI по их ключу
			 */
			::stable_sort(pairs, pairs + count, [](const pair <const string, string> * first, const pair <const string, string> * second) noexcept -> bool {
				// Выводим результат сравнения ключей пар
				return (first->first < second->first);
			});
			/**
			 * Перебираем все выстроенные пары ключ-значение параметров URI
			 */
			for(index = 0; index < count; index++){
				// Добавляем ключ параметра URI в результат
				uri::encode(result, pairs[index]->first, item_t::QUERY, this->_log);
				/**
				 * Разделитель ключа и значения ставится только при непустом значении:
				 * параметр без значения записывается одним ключом, и приписанный ему
				 * разделитель менял бы строку параметров при каждом обороте
				 */
				if(!pairs[index]->second.empty()){
					// Добавляем разделитель ключа и значения параметра URI
					result.append(1, '=');
					// Добавляем значение параметра URI в результат
					uri::encode(result, pairs[index]->second, item_t::QUERY, this->_log);
				}
				// Добавляем разделитель пар параметров URI
				result.append(1, '&');
			}
		}
		// Если функция обратного вызова затребована и установлена
		if(callback && (this->_callback != nullptr)){
			// Выполняем генерацию добавочного параметра URI
			const string & item = this->_callback(this);
			/**
			 * Если добавочный параметр URI сгенерирован удачно, он встаёт за
			 * разделителем последней пары и сам разделителем не оканчивается
			 */
			if(!item.empty()){
				// Добавляем добавочный параметр URI в результат
				result.append(item);
				// Выходим из метода
				return;
			}
		}
		/**
		 * Записанные пары оканчиваются разделителем, и его снимаем. Если же не
		 * записалось ни одной пары, снимаем и разделитель самой строки параметров:
		 * прежде строка параметров собиралась лишь при непустом хранилище, и
		 * подпись, отведённая функции обратного вызова, у адреса без собственных
		 * параметров пропадала вовсе
		 */
		if(count > 0)
			// Снимаем разделитель последней пары параметров URI
			result.pop_back();
		// Снимаем разделитель строки параметров URI, оставшийся без самих параметров
		else result.resize(offset);
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
/**
 * @brief Метод добавления относительного URI-запроса в результат
 *
 * @param result результат, в который добавляется URI-запрос
 *
 */
void awh::Uniform_Resource_Identifier::appendRequest(string & result) const noexcept {
	// Если путь URI не пустой, то добавляем его в результат
	if(!this->_path.empty())
		// Добавляем сегменты пути URI в результат
		this->appendPath(result, true);
	// Запрос, пути не имеющий, записывается одной косой чертой
	else result.append(1, '/');
	// Добавляем строку параметров URI в результат вместе с её разделителем
	this->appendQuery(result, true, true);
	// Если якорь URI не пустой, то добавляем его в результат
	if(!this->_fragment.empty()){
		// Добавляем разделитель якоря URI
		result.append(1, '#');
		// Добавляем якорь URI в результат
		uri::encode(result, this->_fragment, item_t::FRAGMENT, this->_log);
	}
}
/**
 * @brief Метод получения порта URI
 *
 * @return порт URI
 *
 */
uint16_t awh::Uniform_Resource_Identifier::port() const noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Если атрибуты URI не пустые
		if(this->_attr != nullptr){
			/**
			 * Определяем тип атрибутов URI адреса
			 */
			switch(static_cast <uint8_t> (this->_attr->type)){
				// Если атрибуты URI адреса являются адресом файловой системы
				case static_cast <uint8_t> (net::type_t::FS):
					// Возвращаем порт хоста из атрибутов URI адреса (для файловой системы порт не используется, поэтому возвращаем 0)
					return 0;
				// Если атрибуты URI адреса являются FQDN-адресом
				case static_cast <uint8_t> (net::type_t::FQDN): {
					// Извлекаем порт хоста из атрибутов URI адреса
					const uint16_t port = awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port;
					// Если порт задан явно, возвращаем его, иначе возвращаем стандартный порт для типа URI (без записи в состояние)
					return ((port != 0) ? port : this->defaultPort());
				}
				// Если атрибуты URI адреса являются IPv4-адресом
				case static_cast <uint8_t> (net::type_t::IPV4):
				// Если атрибуты URI адреса являются IPv6-адресом
				case static_cast <uint8_t> (net::type_t::IPV6): {
					// Извлекаем порт хоста из атрибутов URI адреса
					const uint16_t port = awh_cast <net::attr_net_t *> (this->_attr.get())->port;
					// Если порт задан явно, возвращаем его, иначе возвращаем стандартный порт для типа URI (без записи в состояние)
					return ((port != 0) ? port : this->defaultPort());
				}
			}
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, {}, log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
	// Возвращаем значение по умолчанию
	return 0;
}
/**
 * @brief Метод установки порта URI
 *
 * @param port порт URI для установки
 *
 */
void awh::Uniform_Resource_Identifier::port(const uint16_t port) noexcept {
	/**
	 * Выполняем отлов ошибок
	 */
	try {
		// Если атрибуты URI не пустые
		if(this->_attr != nullptr){
			/**
			 * Определяем тип атрибутов URI адреса
			 */
			switch(static_cast <uint8_t> (this->_attr->type)){
				// Если атрибуты URI адреса являются FQDN-адресом
				case static_cast <uint8_t> (net::type_t::FQDN):
					// Устанавливаем порт хоста в атрибутах URI адреса
					awh_cast <net::attr_fqdn_t *> (this->_attr.get())->port = port;
				break;
				// Если атрибуты URI адреса являются IPv4-адресом
				case static_cast <uint8_t> (net::type_t::IPV4):
				// Если атрибуты URI адреса являются IPv6-адресом
				case static_cast <uint8_t> (net::type_t::IPV6):
					// Устанавливаем порт хоста в атрибутах URI адреса
					awh_cast <net::attr_net_t *> (this->_attr.get())->port = port;
				break;
			}
		}
	/**
	 * Если возникает ошибка
	 */
	} catch(const exception & error) {
		/**
		 * Если включён режим отладки
		 */
		#if DEBUG_MODE
			// Записываем ошибку в лог
			this->_log->debug("%s", __PRETTY_FUNCTION__, make_tuple(port), log_t::flag_t::CRITICAL, error.what());
		/**
		 * Если режим отладки не включён
		 */
		#else
			// Записываем ошибку в лог
			this->_log->print("%s", log_t::flag_t::CRITICAL, error.what());
		#endif
	}
}
