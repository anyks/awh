/**
 * Экранируем повторную инициализацию модуля
 */
#ifndef __AWH_WIN32__
#define __AWH_WIN32__

/**
 * Для операционной системы MS Windows
 */
#if defined(_WIN32) || defined(_WIN64)

	/**
	 * @brief Наименьшая поддерживаемая версия операционной системы — Windows 10
	 *
	 * @details Версия задаётся до подключения системных заголовков: от неё зависит состав
	 *          объявлений. Windows 10 выбрана затем, что кластеру нужны объекты задания
	 *          с завершением по закрытию, ожидание объектов из системного пула потоков и
	 *          именованные каналы с отказом удалённым клиентам
	 *
	 */
	#ifndef _WIN32_WINNT
		#define _WIN32_WINNT 0x0A00
	#endif

	/**
	 * @brief Урезание состава заголовка windows.h
	 *
	 * @details Снимает подключение подсистем, каких библиотеке не требуется — графики,
	 *          звука, буфера обмена, оболочки. Заодно убирает часть засорения
	 *          пространства имён макросами
	 *
	 */
	#ifndef WIN32_LEAN_AND_MEAN
		#define WIN32_LEAN_AND_MEAN
	#endif

	/**
	 * @brief Запрет макросов min и max
	 *
	 * @details Без него заголовки MS Windows заводят min и max макросами, и обращения
	 *          вида std::min<T>(a, b) перестают разбираться
	 *
	 */
	#ifndef NOMINMAX
		#define NOMINMAX
	#endif

	/**
	 * @brief Запрет подсистемы графики GDI
	 *
	 * @details Заголовок wingdi.h заводит макросы ERROR, ALTERNATE и TRANSPARENT, и все
	 *          три сталкиваются с именами членов перечислений AWH. Графика библиотеке не
	 *          нужна вовсе, и выключатель этот снимает столкновения штатным средством
	 *          самой MS Windows — предпочтительнее, чем снятие макросов через undef,
	 *          поскольку не отменяет ничего, что было бы заведено намеренно
	 *
	 * @note Выключателем NO_STRICT, отменяющим макрос STRICT, пользоваться не следует:
	 *       он заодно превращает раздельные типы дескрипторов в общий void *, то есть
	 *       ослабляет проверку типов. Макрос STRICT снимается ниже уже после того,
	 *       как заголовки его прочли, и строгая типизация при этом сохраняется
	 *
	 */
	#ifndef NOGDI
		#define NOGDI
	#endif

	/**
	 * Системные заголовочные файлы
	 *
	 * @note Порядок обязателен: winsock2.h подключается строго до windows.h, иначе
	 *       windows.h втянет устаревший winsock.h и объявления сокетов столкнутся.
	 *       Заголовок ws2def.h самостоятельным не является и требует, чтобы базовые
	 *       типы (ULONG и прочие) были объявлены прежде него
	 *
	 */
	#include <winsock2.h>
	#include <ws2tcpip.h>
	#include <ws2def.h>
	#include <mswsock.h>
	#include <windows.h>

	/**
	 * @brief Некорректный сокет
	 *
	 * @details Замена макросу INVALID_SOCKET, снимаемому ниже. Значение повторяет
	 *          определение из winsock2.h дословно
	 *
	 */
	#define AWH_INVALID_SOCKET (static_cast <SOCKET> (~0))

	/**
	 * Снимаем макросы, чьи имена совпадают с именами членов перечислений AWH
	 *
	 * @details Препроцессор области видимости не разбирает, и макрос заменяет имя даже
	 *          внутри enum class. Так, DELETE из winnt.h превращает объявление
	 *          `DELETE = 0x05` в `(0x00010000) = 0x05`, и сборка отвечает отказом.
	 *          Перечень выверен сличением всех членов перечислений AWH со списком
	 *          макросов, какие заводят системные заголовки MS Windows
	 *
	 *          Затронутые перечисления: event::action_t и upnp::action_t (DELETE),
	 *          event::error_t (INVALID_SOCKET), event::mtu_discover_t, uri::resolve_t,
	 *          auth::mode_t и charset::replace_t (STRICT), h2::error_t и quic::error_t
	 *          (NO_ERROR)
	 *
	 *          Макросы ERROR, ALTERNATE и TRANSPARENT снимаются и здесь, хотя выключатель
	 *          NOGDI выше не даёт их завести. Двойная защита нужна затем, что выключатель
	 *          действует лишь когда windows.h подключается впервые. Если потребитель
	 *          библиотеки подключил windows.h прежде любого заголовка AWH, заголовки
	 *          MS Windows уже разобраны, охранное имя выставлено, и NOGDI опаздывает —
	 *          проверено опытом: сборка proto/quic/quic.hpp после windows.h отвечала
	 *          отказом на члене ERROR. Снятие же срабатывает при любом порядке
	 *
	 * @note Макросы-функции FAILED(hr) и TEXT(quote) в перечень не входят намеренно:
	 *       раскрываются они лишь перед открывающей скобкой, а в записи вида
	 *       `FAILED = 0x02` за именем следует знак присваивания, и замены не происходит
	 *
	 * @warning Взамен снятых пользоваться следует: AWH_INVALID_SOCKET вместо
	 *          INVALID_SOCKET и ERROR_SUCCESS вместо NO_ERROR. Снятые DELETE и STRICT
	 *          относятся к подсистемам, библиотекой не используемым, и замены им
	 *          не заведено — при нужде значения выписывать дословно
	 *
	 */
	#undef DELETE
	#undef ERROR
	#undef STRICT
	#undef NO_ERROR
	#undef ALTERNATE
	#undef TRANSPARENT
	#undef INVALID_SOCKET

#endif

#endif // __AWH_WIN32__
