#ifndef __AWH_GLOBAL__
#define __AWH_GLOBAL__

/**
 * Для оснастки MSVC: имена POSIX, которых она не несёт
 *
 * MinGW отдаёт ssize_t, pid_t и заголовок unistd.h вместе с оснасткой, потому
 * код о них и не спрашивает. У нативного MSVC их нет вовсе, и слой вводится
 * здесь, в базовом заголовке, единожды - вместо россыпи проверок _MSC_VER по
 * десяткам мест
 */
#if defined(_MSC_VER)
	/**
	 * Системные заголовочные файлы: размеры типов и работа с процессами
	 */
	#include <BaseTsd.h>
	#include <process.h>

	/**
	 * Своего ssize_t у MSVC нет, потому тип заводим под охраной признака
	 */
	#if !defined(__AWH_MSVC_SSIZE_T__)
		/**
		 * Признак не даёт объявить тип повторно: заголовок подключают многие
		 */
		#define __AWH_MSVC_SSIZE_T__
		// ssize_t берётся из SSIZE_T: так его отдаёт BaseTsd.h
		typedef SSIZE_T ssize_t;
	#endif
	/**
	 * Своего pid_t у MSVC тоже нет, потому тип заводим тем же порядком
	 */
	#if !defined(__AWH_MSVC_PID_T__)
		/**
		 * Признак не даёт объявить тип повторно: заголовок подключают многие
		 */
		#define __AWH_MSVC_PID_T__
		// pid_t сводится к int: _getpid отдаёт именно его
		typedef int pid_t;
	#endif
#endif

/**
 * Имя функции для журнала отказов
 *
 * Оснастки зовут его по-разному, а смысл один - подпись функции со всеми её
 * аргументами и пространствами имён. Обращений к имени в проекте больше
 * пятисот, и править каждое незачем, да и нечем проверить такую правку: имя
 * GCC объявляется через имя MSVC
 */
#if defined(_MSC_VER) && !defined(__PRETTY_FUNCTION__)
	/**
	 * Имя GCC объявляется через имя MSVC, а не наоборот
	 */
	#define __PRETTY_FUNCTION__ __FUNCSIG__
#endif

/**
 * Плотная укладка полей структуры
 *
 * Оснастки расходятся не написанием, а устройством указания: у GCC и clang
 * плотность задаётся признаком, стоящим ПОСЛЕ объявления, а у MSVC - парой
 * указаний препроцессору, обнимающих объявление целиком. Одним именем это не
 * покрыть, оттого имён три, и ставятся они все:
 *
 * `__AWH_PACK_BEGIN__ typedef struct { ... } __AWH_PACKED__ record_t; __AWH_PACK_END__`
 *
 * Там, где указания не нужны, они разворачиваются в пустоту, и обратно
 *
 * Плотная укладка - не украшение: ею описываются заголовки протоколов и записи
 * обмена, чьё расположение задано не нами. Потеря её оснасткой не даёт ни
 * отказа, ни предупреждения - выравнивание молча раздвигает поля, и
 * разъезжается разбор уже в сети, а не при сборке
 */
#if defined(_MSC_VER)
	/**
	 * Начало области плотной укладки: кладём единицу в pack
	 */
	#define __AWH_PACK_BEGIN__ __pragma(pack(push, 1))
	/**
	 * Конец области плотной укладки: снимаем прежнюю настройку pack
	 */
	#define __AWH_PACK_END__ __pragma(pack(pop))
	/**
	 * Признак плотной укладки у объявления пуст: у MSVC её несёт область вокруг
	 */
	#define __AWH_PACKED__
/**
 * Плотность задаётся признаком у самого объявления
 */
#else
	/**
	 * Начало области плотной укладки пусто: у GCC и clang её несёт признак объявления
	 */
	#define __AWH_PACK_BEGIN__
	/**
	 * Конец области плотной укладки пуст по той же причине
	 */
	#define __AWH_PACK_END__
	/**
	 * Признак плотной укладки у объявления - атрибут packed
	 */
	#define __AWH_PACKED__ __attribute__((packed))
#endif

/**
 * Для операционной системы MS Windows
 *
 * Признаки спрашиваются через defined, а не значением: заголовок windows.h
 * оснастки MinGW объявляет WIN32 пустым, и тогда условие остаётся без правого
 * слагаемого - препроцессор отвечает отказом на пустом месте
 */
#if defined(_MSC_VER) || defined(WIN64) || defined(_WIN64) || defined(__WIN64__) || defined(WIN32) || defined(_WIN32) || defined(__WIN32__) || defined(__NT__)
	/**
	 * У нативного MSVC указание отдачи пустое
	 *
	 * Перечень отдаваемого собирает описание сборки по готовым объектным файлам
	 * (CMAKE_WINDOWS_EXPORT_ALL_SYMBOLS), и указание в коде становится лишним.
	 * Поставленное КЛАССУ, оно заставляет оснастку завести все неявные члены
	 * разом, копирующий в том числе, а класс с полем из unique_ptr копирующего
	 * не имеет: сборка отказывает на удалённой функции внутри заголовков
	 * оснастки, называя класс, который ни одна строка кода не копирует
	 *
	 * Те же макросы объявляет contrib/include/cityhash/city.h под своим стражем,
	 * и подключается он раньше объявления классов: правило там обязано быть тем
	 * же, иначе правка здесь до сборки не доходит
	 */
	#if defined(_MSC_VER)
		/**
		 * Отдачу символов задаёт описание сборки, а не объявление
		 */
		#define DECL_EXPORT
	/**
	 * Оснастки, где отдача символов задаётся при самом объявлении
	 */
	#else
		/**
		 * Отдача символов через __declspec(dllexport) - так ведёт её MinGW
		 */
		#define DECL_EXPORT __declspec(dllexport)
	#endif
	/**
	 * Взятие символов через __declspec(dllimport): берущая сторона о перечне не знает
	 */
	#define DECL_IMPORT __declspec(dllimport)
/**
 * Для операционной системы не являющейся MS Windows
 */
#else
	#define DECL_EXPORT __attribute__((visibility("default")))
	#define DECL_IMPORT __attribute__((visibility("default")))
#endif

/**
 * Если активирован экспорт динамической библиотеки
 */
#if AWH_SHARED_LIBRARY_EXPORT
	#define AWH_SHARED_EXPORT DECL_EXPORT
/**
 * Если активирован импорт динамической библиотеки
 */
#elif AWH_SHARED_LIBRARY_IMPORT
	#define AWH_SHARED_EXPORT DECL_IMPORT
/**
 * Если мы работаем со статической библиотекой
 */
#else
	#define AWH_SHARED_EXPORT
#endif

#endif // __AWH_GLOBAL__
