#!/usr/bin/env bash

# Получаем корневую дирректорию
readonly ROOT=$(cd "$(dirname "$0")" && pwd)

# Название библиотеки
readonly LIBNAME="dependence"

# Каталог статических библиотек
THIRD_PARTY="$ROOT/../third_party/lib"

# Если на вход получен каталог с библиотеками
if [[ -d $1 ]]; then
	# Каталог статических библиотек
	THIRD_PARTY="$1"
fi

# Приводим каталог статических библиотек к виду безусловному
THIRD_PARTY=$(cd "$THIRD_PARTY" && pwd)

##
 # Каталог сборки
 #
 # Разбор архивов ведётся в каталоге отдельном, а не в каталоге библиотек: там
 # лежат библиотеки, объединению не подлежащие (ныне таких нет, а впредь
 # всякая, перехватывающая выдачу памяти), и разбор посреди них означал бы, что каждая новая зависимость
 # требует ограждения. Каталог отдельный ограждает их все разом и заодно
 # избавляет от вопроса об остатках прерванного прогона - каталог создаётся
 # заново.
 ##
readonly BUILD_DIR="$THIRD_PARTY/../.merge"

# Получаем версию OS
OS=$(uname -a | awk '{print $1}')

if [[ $OS =~ "MINGW64" ]]; then
	OS="Windows"
fi

# Расширение файла объекта
OBJECT_NAME="o"

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Расширение файла объекта
	OBJECT_NAME="obj"
fi

##
 # Список библиотек, объединению не подлежащих
 #
 # Перехват выдачи памяти держится на том, что компоновщик берёт модуль перехвата
 # целиком; будучи же одним из множества модулей объединённой библиотеки, модуль
 # берётся лишь при наличии неразрешённой метки. Всякую стороннюю библиотеку,
 # перехватывающую выдачу памяти, вносить сюда. Ныне таких нет: gperftools, ради
 # которого список заводился, из зависимостей снят - выдачу памяти ведёт
 # собственный распределитель.
 #
 # Список этот - ограждение второе; первое даёт сам каталог сборки, куда
 # библиотеки эти не копируются вовсе.
 #
 # Библиотека зависимостей (libdependence) - итог самого этого объединения, и
 # входом ему служить не может: после прогона она остаётся в каталоге библиотек
 # одна, и повторный прогон брал её на вход наравне с модульными. Свои объектники
 # удваивались, устаревшие разрешали метки прежде свежих, а при переносе каталога
 # на иную платформу в объединение входили и чужие объектники, о чём заявляла
 # лишь линковка приложения - отказами по меткам, которых в объединении не
 # имелось. Проверено на стенде FreeBSD 15.1 aarch64 с каталогом библиотек,
 # доставленным с macOS (03.10.2026)
 ##
readonly EXCLUDES="libdependence"

##
 # Функция проверки библиотеки на принадлежность к объединению
 ##
excluded(){
	# Выполняем перебор списка библиотек, объединению не подлежащих
	for name in $EXCLUDES;
	do
		# Если название библиотеки совпадает
		if [ "${1%.*}" = "$name" ]; then
			# Сообщаем что библиотека объединению не подлежит
			return 0
		fi
	done
	# Сообщаем что библиотека подлежит объединению
	return 1
}

##
 # Счётчик извлечённых модулей
 #
 # Счётчик сквозной для всего прогона, а не для отдельного архива: имена модулей
 # в разных архивах совпадают, и при счётчике поархивном модуль одного архива
 # молча затирал бы одноимённый модуль другого. Отказом это не сопровождается,
 # а библиотека выходит неполной.
 ##
INDEX=0

##
 # Предел длины списка модулей в одном вызове ar
 #
 # Каждый вызов ar переписывает архив целиком, и пачка по сотне модулей делала
 # из сборки библиотеки в тысячи модулей десятки переписываний: на стенде NetBSD
 # с медленным диском это полчаса. Пачка набирается по длине командной строки,
 # а не по числу модулей: у MS Windows предел строки 32 КиБ, половины его хватает
 # с запасом при любых названиях.
 ##
BATCH_LENGTH=16000

##
 # Функция удаления модулей из архива пачками
 #
 # Первым доводом принимается архив, остальными - названия удаляемых модулей.
 ##
prune(){
	# Запоминаем архив
	ARCHIVE="$1"
	# Смещаем доводы к названиям модулей
	shift
	# Пачка названий модулей
	BATCH=""
	# Перебираем все названия модулей
	for m in "$@";
	do
		# Добавляем название модуля в пачку
		BATCH="$BATCH $m"
		# Если длина пачки подошла к пределу командной строки
		if [ ${#BATCH} -ge $BATCH_LENGTH ]; then
			# Выполняем удаление пачки модулей из архива
			ar -d "$ARCHIVE" $BATCH || exit 1
			# Выполняем очистку пачки
			BATCH=""
		fi
	done
	# Если в пачке остались модули
	if [ -n "$BATCH" ]; then
		# Выполняем удаление пачки модулей из архива
		ar -d "$ARCHIVE" $BATCH || exit 1
	fi
}

##
 # Функция упаковка модулей в библиотеку
 ##
intract(){
	# Список собранных модулей
	MODULES=""

	# Производим пересборку всех зависимых библиотек
	for i in $(ls . | grep ".*\.${OBJECT_NAME}$");
	do
		# Если список уже сформирован
		if [ -n "$MODULES" ]; then
			# Добавляем название модуля
			MODULES="$MODULES $i"
		# Если список модулей ещё не сформирован
		else
			# Формируем список модулей
			MODULES="$i"
		fi

		# Если длина списка модулей подошла к пределу командной строки
		if [ ${#MODULES} -ge $BATCH_LENGTH ]; then
			# Выполняем сборку новой статической библиотеки
			ar -crv lib$1.a $MODULES || exit 1
			# Выполняем очистку списка модулей
			MODULES=""
		fi
	done

	# Если список уже сформирован
	if [ -n "$MODULES" ]; then
		# Выполняем сборку новой статической библиотеки
		ar -crv lib$1.a $MODULES || exit 1
	fi

	# Выполняем удаление всех обработанных модулей
	rm -f *.$OBJECT_NAME || exit 1

	# Выполняем запуск библиотеки
	ranlib "lib$1.a"

	# Если операционной системой является Unix-подобная ОС
	if [ ! $OS = "Windows" ]; then
		# Удаляем файл разметки
		rm -f "__.SYMDEF"
		rm -f "__.SYMDEF SORTED"
	fi
}

##
 # Функция проверки наличия модуля в архиве
 #
 # Проверка ведётся средствами самой оболочки, без grep и awk: сценарий идёт на всех
 # системах, и у Solaris ни ключи grep -F, -x и -q вместе, ни тот или иной awk не обещаны.
 # Возврат каретки снимается: ar из MinGW выводит строки с \r\n, и название с ним
 # не совпало бы ни с одним - двойник проходил бы мимо и затирал соседа.
 #
 # Первым доводом принимается архив, вторым - название модуля.
 ##
contains(){
	# Перебираем все модули архива
	for m in $(ar -t "$1" | tr -d '\r');
	do
		# Если название модуля совпадает
		if [ "$m" = "$2" ]; then
			# Сообщаем что модуль найден
			return 0
		fi
	done
	# Сообщаем что модуль не найден
	return 1
}
##
 # Функция извлечения модулей из библиотеки
 #
 # Первым доводом принимается расширение архива, вторым - перечень расширений
 # модулей внутри него.
 #
 # Перечень, а не одно расширение, потому что назван модуль внутри архива так,
 # как назвал его сборщик библиотеки: сборка обычным make даёт "o", а сборка
 # через CMake под MS Windows - "obj", и в одном наборе зависимостей встречаются
 # оба. Прежде расширения перебирались двумя вызовами функции, но архив удалялся
 # в конце каждого прохода - и первый проход сносил архивы, чьи модули искал
 # проход второй. Обнаружить это по итогу сборки было нельзя: скрипт отвечал
 # успехом, а библиотека выходила неполной.
 ##
extract(){
	# Производим пересборку всех зависимых библиотек
	for i in $(ls . | grep ".*\.$1$");
	do
		# Выводим сообщение
		echo "Extract \"$i\""

		# Количество извлечённых из архива модулей
		EXTRACTED=0

		# Перебираем все расширения модулей
		for suffix in $2;
		do
			# Получаем список модулей
			MODULES=$(ar -t "$i" | tr -d '\r' | grep ".*\.${suffix}$")
			##
			 # Одноимённые модули-двойники
			 #
			 # Только их приходится извлекать по одному с удалением из архива: иначе до
			 # второго двойника не добраться. Каждое удаление переписывает архив целиком,
			 # и прежний перебор всех модулей так стоил квадрата их числа: на стенде
			 # NetBSD с медленным диском одна libcrypto (1021 модуль) разбиралась часами.
			 # Потому уникальные модули извлекаются первыми и удаляются из архива пачками,
			 # и двойники разбираются в архиве малом.
			 #
			 # Наличие двойника проверяется функцией contains средствами самой оболочки.
			 ##
			DUPLICATES=$(printf '%s\n' $MODULES | sort | uniq -d)
			# Получаем список уникальных модулей
			UNIQUES=$(printf '%s\n' $MODULES | sort | uniq -u)
			# Если уникальные модули есть
			if [ -n "$UNIQUES" ]; then
				# Извлекаем архив целиком одним вызовом в отдельный каталог
				rm -rf ".extract" && mkdir ".extract" || exit 1
				(cd ".extract" && ar -x "../$i") || exit 1
				# Выполняем формирование последовательности списка модулей
				for j in $UNIQUES;
				do
					# Выводим название модуля
					echo "Module: $j in $i"
					# Выполняем переименование модуля
					mv ".extract/$j" "${j%.*}_$INDEX.$OBJECT_NAME" || exit 1
					# Выполняем увеличение индекса
					INDEX=$((INDEX+1))
					# Выполняем увеличение количества извлечённых модулей
					EXTRACTED=$((EXTRACTED+1))
				done
				# Удаляем каталог извлечения
				rm -rf ".extract"
				# Если двойники есть, удаляем уникальные модули из архива
				if [ -n "$DUPLICATES" ]; then
					# Удаляем уникальные модули пачками
					prune "$i" $UNIQUES
				fi
			fi
			# Выполняем разбор двойников
			for j in $DUPLICATES;
			do
				# Пока в архиве остаётся модуль с этим названием
				while contains "$i" "$j";
				do
					# Выводим название модуля
					echo "Module: $j in $i"
					# Выполняем извлечение модуля из архива
					ar -xv "$i" "$j"
					# Выполняем удаление модуля в архиве
					ar -dv "$i" "$j" || exit 1
					# Выполняем переименование модуля
					mv "${j%.*}.${suffix}" "${j%.*}_$INDEX.$OBJECT_NAME" || exit 1
					# Выполняем увеличение индекса
					INDEX=$((INDEX+1))
					# Выполняем увеличение количества извлечённых модулей
					EXTRACTED=$((EXTRACTED+1))
				done
			done
		done

		# Если из архива не извлечено ни одного модуля
		if [ $EXTRACTED -eq 0 ]; then
			# Сообщаем, что архив оказался пустым
			echo "No modules extracted from \"$i\""
			# Выходим из скрипта с ошибкой
			exit 1
		fi

		# Удалем архив статической библиотеки
		rm -f "$i"
	done
}

# Выполняем создание каталога сборки заново
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR" || exit 1

# Список исходных архивов, отданных на объединение
ARCHIVES=""

##
 # Расширения архивов, подлежащих объединению
 #
 # У MS Windows расширение статической библиотеки зависит от того, за какой
 # набор средств принял себя CMake: сборка родная даёт "a", а сборка,
 # объявленная перекрёстной - "lib". Просматриваются оба, иначе часть
 # библиотек отсеивается молча, и обнаруживается это лишь на сборке
 # приложения - отсутствием меток, которых никто не искал.
 ##
ARCHIVE_SUFFIXES="a"

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Просматриваем оба расширения статических библиотек
	ARCHIVE_SUFFIXES="a lib"
fi

# Выполняем копирование архивов в каталог сборки
for i in $(for s in $ARCHIVE_SUFFIXES; do ls "$THIRD_PARTY" | grep ".*\.${s}$"; done);
do
	# Если библиотека объединению не подлежит
	if excluded "$i"; then
		# Выводим сообщение
		echo "Skip \"$i\""
		# Переходим к библиотеке следующей
		continue
	fi

	##
	 # Выполняем копирование архива
	 #
	 # Разбор архив разрушает: модуль удаляется сразу после извлечения, иначе до
	 # одноимённого модуля-двойника не добраться. Разбирается копия, а исходный
	 # архив цел до самого конца - прерывание прогона потерей не грозит.
	 ##
	cp "$THIRD_PARTY/$i" "$BUILD_DIR/$i" || exit 1

	# Запоминаем архив к удалению
	ARCHIVES="$ARCHIVES $i"
done

# Если объединять оказалось нечего
if [ -z "$ARCHIVES" ]; then
	# Если итог объединения уже собран и стоит на месте
	if [ -f "$THIRD_PARTY/lib$LIBNAME.a" ] || [ -f "$THIRD_PARTY/lib$LIBNAME.lib" ]; then
		# Сообщаем, что объединять нечего, а итог актуален
		echo "No static libraries found in \"$THIRD_PARTY\": lib$LIBNAME is up to date"
		# Выходим из скрипта успехом
		exit 0
	# Если итога объединения нет
	else
		# Сообщаем, что объединять нечего
		echo "No static libraries found in \"$THIRD_PARTY\""
		# Выходим из скрипта с ошибкой
		exit 1
	fi
fi

##
 # Выводим перечень объединяемых библиотек
 #
 # Перечень выводится затем, что отсев ведётся по расширению: библиотека,
 # названная неожиданным образом, в объединение не попадает, и без перечня
 # пропажа её ничем себя не обнаруживает.
 ##
echo "Merging static libraries:"
for i in $ARCHIVES;
do
	# Выводим название объединяемой библиотеки
	echo "  $i"
done

# Выполняем переход в каталог сборки
cd "$BUILD_DIR" || exit 1

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Извлекаем все модули из библиотек обоих расширений
	extract "a" "o obj"
	extract "lib" "o obj"
# Если операционной системой является Unix-подобная ОС
else
	# Извлекаем все модули из библиотеки
	extract "a" "o"
fi

# Выполняем сборку библиотеки
intract $LIBNAME

##
 # Выполняем удаление разобранных архивов
 #
 # Удаление отложено до успешной сборки: прерывание оставляет каталог библиотек
 # нетронутым, а прогон следующий начинается с чистого места.
 ##
for i in $ARCHIVES;
do
	# Выполняем удаление архива
	rm -f "$THIRD_PARTY/$i"
done

# Выполняем установку собранной библиотеки на место
mv "lib$LIBNAME.a" "$THIRD_PARTY/lib$LIBNAME.a" || exit 1

# Переходим обратно
cd "$ROOT" || exit 1

# Выполняем удаление каталога сборки
rm -rf "$BUILD_DIR"

printf "\n****************************************"
printf "\n************   Success merge static libs!!!   ************"
printf "\n****************************************"
printf "\n\n\n"
