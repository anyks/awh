#!/usr/bin/env bash

##
 # Сквозная проверка кодека XML
 #
 # Прогоняет всю цепочку проверок, накопленную вокруг кодека, и падает на первом
 # расхождении. Собрана потому, что проверок пять, они лежат в разных местах, и
 # прогонять их вручную после каждой правки — это десяток минут и три способа
 # ошибиться.
 #
 # Способы эти не выдуманы, все три случались:
 #   1. стенд собирается БЕЗ «DEBUG_MODE», а каталог build у проекта отладочный, и
 #      проверка на текст записи в журнал проходила у стенда, падая в общей сборке;
 #   2. объектные файлы стендов собираются вручную и после правки заголовков
 #      устаревают — прогон отчитывается успехом по коду, какого в нём уже нет;
 #   3. ворошитель молчит и тогда, когда до правленого хода не доходит вовсе.
 #
 # Оттого набор гоняется тремя сборками — выпускною, отладочной и под санитайзерами, —
 # стенды пересобираются всегда, а ворошитель прогоняется несколькими зёрнами.
 ##

# Получаем корневую дирректорию репозитория
readonly ROOT=$(cd "$(dirname "$0")/.." && pwd)

# Каталог промежуточных файлов проверки
readonly WORK="${TMPDIR:-/tmp}/awh-verify-codec-xml"

# Получаем версию OS
readonly OS=$(uname -a | awk '{print $1}')

# Каталог заголовочных файлов системных библиотек
if [ "$OS" = "Darwin" ]; then
	readonly PREFIX="/opt/homebrew"
else
	readonly PREFIX="/usr/local"
fi

# Корень набора GoogleTest
readonly GTEST="${GTEST_ROOT:-$PREFIX}"

# Получаем собиратель
readonly COMPILER="${CXX:-c++}"

# Количество пройденных шагов проверки
STEPS=0

##
 # Количество ПРОПУЩЕННЫХ шагов проверки
 #
 # @note Счёт этот ведётся и оглашается итогом НАМЕРЕННО: прежде пропуск шага виден был
 #       лишь в самом ходе прогона, а итог звал прогон пройденным, числа шагов не поясняя.
 #       Шаг, выполниться не сумевший, от шага пройденного итогом было не отличить
 ##
MISSED=0

# Доводы пропуска шагов проверки
REASONS=""

##
 # Функция вывода заголовка шага проверки
 #
 # @param $1 название шага проверки
 #
 ##
announce(){
	# Выводим заголовок шага проверки
	printf "\n\033[1m==> %s\033[0m\n" "$1"
}

##
 # Функция завершения проверки с ошибкой
 #
 # @param $1 описание расхождения
 #
 ##
abort(){
	# Выводим описание расхождения
	printf "\n\033[31mПРОВЕРКА НЕ ПРОЙДЕНА: %s\033[0m\n" "$1"
	# Завершаем проверку с ненулевым кодом
	exit 1
}

##
 # Функция учёта пройденного шага проверки
 #
 # @param $1 итог шага проверки
 #
 ##
accept(){
	# Считаем пройденный шаг проверки
	STEPS=$((STEPS + 1))
	# Выводим итог шага проверки
	printf "\033[32m  ок\033[0m  %s\n" "$1"
}

##
 # Функция вывода оговорки о непройденном шаге
 #
 # @param $1 описание оговорки
 #
 ##
skipped(){
	# Увеличиваем счёт пропущенных шагов проверки
	MISSED=$((MISSED + 1))
	# Заносим довод пропуска в перечень пропущенных шагов
	REASONS="${REASONS}${REASONS:+; }$1"
	# Выводим описание оговорки
	printf "\033[33m  нет\033[0m  %s\n" "$1"
}

# Выполняем создание каталога промежуточных файлов
mkdir -p "$WORK" || abort "не создан каталог $WORK"

##
 # Шаг 1. Набор проверок выпускною сборкой
 ##
announce "Шаг 1. Набор проверок кодека XML"

# Выполняем сборку стенда проверок
GTEST_ROOT="$GTEST" sh "$ROOT/tests/codec/xml/stand.sh" "$ROOT" "$WORK/tests" > "$WORK/tests-build.log" 2>&1 \
	|| abort "не собран стенд проверок, журнал в $WORK/tests-build.log"

# Выполняем прогон набора проверок
(cd "$WORK/tests" && ./xml-tests > "$WORK/tests-run.log" 2>&1) \
	|| abort "набор проверок не пройден, журнал в $WORK/tests-run.log"

# Выводим итог прогона набора проверок
accept "$(grep -o '[0-9]* tests from [0-9]* test suites ran' "$WORK/tests-run.log" | tail -1)"

##
 # Шаг 2. Набор проверок отладочною сборкой
 #
 # Кодек пишет в журнал двумя ветвями по «DEBUG_MODE», и расхождение это уже давало
 # ложное «зелено»: проверка на текст записи проходила у стенда, падая в общей сборке
 ##
announce "Шаг 2. Набор проверок сборкой с DEBUG_MODE"

# Выполняем сборку стенда проверок отладочною сборкой
FLAGS="-DDEBUG_MODE" GTEST_ROOT="$GTEST" sh "$ROOT/tests/codec/xml/stand.sh" "$ROOT" "$WORK/tests-debug" > "$WORK/tests-debug-build.log" 2>&1 \
	|| abort "не собран отладочный стенд проверок, журнал в $WORK/tests-debug-build.log"

# Выполняем прогон набора проверок отладочною сборкой
(cd "$WORK/tests-debug" && ./xml-tests > "$WORK/tests-debug-run.log" 2>&1) \
	|| abort "набор проверок с DEBUG_MODE не пройден, журнал в $WORK/tests-debug-run.log"

# Выводим итог прогона набора проверок отладочною сборкой
accept "$(grep -o '[0-9]* tests from [0-9]* test suites ran' "$WORK/tests-debug-run.log" | tail -1)"

##
 # Шаг 3. Набор проверок под санитайзерами
 #
 # Ворошитель под санитайзерами ходит своими построениями, а набор проверок - своими, и
 # ходы эти НЕ СОВПАДАЮТ: ворошитель строит разметку, но не трогает ни правку дерева, ни
 # перезапись, ни договор владеющего значения. Прогонять под санитайзерами надо оба
 ##
announce "Шаг 3. Набор проверок под санитайзерами"

# Выполняем сборку стенда проверок под санитайзерами
FLAGS="-fsanitize=address,undefined -g" GTEST_ROOT="$GTEST" sh "$ROOT/tests/codec/xml/stand.sh" "$ROOT" "$WORK/tests-sanitize" > "$WORK/tests-sanitize-build.log" 2>&1 \
	|| abort "не собран стенд проверок под санитайзерами, журнал в $WORK/tests-sanitize-build.log"

# Выполняем прогон набора проверок под санитайзерами
(cd "$WORK/tests-sanitize" && ./xml-tests > "$WORK/tests-sanitize-run.log" 2>&1) \
	|| abort "набор проверок под санитайзерами не пройден, журнал в $WORK/tests-sanitize-run.log"

# Выполняем проверку молчания санитайзеров
grep -q "ERROR: \|runtime error" "$WORK/tests-sanitize-run.log" \
	&& abort "санитайзер сообщил о дефекте, журнал в $WORK/tests-sanitize-run.log"

# Выводим итог прогона набора проверок под санитайзерами
accept "$(grep -o '[0-9]* tests from [0-9]* test suites ran' "$WORK/tests-sanitize-run.log" | tail -1)"

##
 # Шаг 4. Ворошитель под санитайзерами
 #
 # Зёрен несколько намеренно: построения одного зерна складываются в один и тот же
 # набор, сколько проходов ни задай, и несколько зёрен обходят разметку шире
 ##
announce "Шаг 4. Ворошитель под санитайзерами"

# Выполняем сборку ворошителя под санитайзерами
$COMPILER -std=gnu++17 -O1 -g -fsanitize=address,undefined -I"$ROOT/include" -o "$WORK/xml-fuzz" \
	"$ROOT"/src/codec/xml/*.cpp "$ROOT/src/num/lexical/table.cpp" "$ROOT/tools/fuzz/xml.cpp" \
	"$ROOT/src/sys/log.cpp" "$ROOT/src/sys/chrono.cpp" "$ROOT/src/sys/fmk.cpp" "$ROOT/src/net/nwt.cpp" \
	"$ROOT"/src/encoding/unicode/*.cpp "$ROOT"/src/encoding/charset/*.cpp \
	"$ROOT"/src/alloc/*.cpp "$ROOT"/src/alloc/capture/*.cpp \
	-Wno-c++11-narrowing -pthread -lz > "$WORK/fuzz-build.log" 2>&1 \
	|| abort "не собран ворошитель, журнал в $WORK/fuzz-build.log"

##
 # Выполняем перебор всех прогоняемых зёрен ворошителя
 ##
for SEED in 369102 7 4242; do
	# Выполняем прогон ворошителя очередным зерном
	"$WORK/xml-fuzz" "${FUZZ_PASSES:-40000}" "$SEED" > "$WORK/fuzz-$SEED.log" 2>&1 \
		|| abort "ворошитель отказал на зерне $SEED, журнал в $WORK/fuzz-$SEED.log"
	# Выполняем проверку молчания санитайзеров
	grep -q "ERROR: \|runtime error" "$WORK/fuzz-$SEED.log" \
		&& abort "санитайзер сообщил о дефекте на зерне $SEED, журнал в $WORK/fuzz-$SEED.log"
	# Выводим итог прогона ворошителя
	accept "зерно $SEED: $(sed -n 's/.*texts (\([0-9]*\) corrupted).*/испорченных \1/p' "$WORK/fuzz-$SEED.log" | tail -1)"
done

##
 # Шаг 5. Сличение с набором соответствия W3C
 #
 # Шаг этот единственный, что судит нас ПО ДОГОВОРУ, а не по нам же: набор проверок и
 # ворошитель сличают нас с нами, и наше неверное прочтение договора им незаметно
 ##
announce "Шаг 5. Сличение с набором соответствия W3C"

# Выполняем сборку стенда сличения вместе с получением корпуса
sh "$ROOT/tools/verify/codec/xml/build.sh" "$WORK/verify" > "$WORK/verify-build.log" 2>&1 \
	|| skipped "стенд сличения не собран, журнал в $WORK/verify-build.log"

##
 # Если стенд сличения собран
 ##
if [ -x "$WORK/verify/verify" ]; then
	# Выполняем снятие перечня путей случаев набора соответствия
	python3 "$ROOT/tools/verify/codec/xml/compare.py" --list "$WORK/verify/corpus" > "$WORK/verify/list.txt" \
		|| abort "не снят перечень случаев набора соответствия"
	# Выполняем разбор всех случаев набора соответствия
	"$WORK/verify/verify" "$WORK/verify/corpus" < "$WORK/verify/list.txt" > "$WORK/verify/dump.tsv" \
		|| abort "стенд сличения отказал"
	# Выполняем сличение исхода разбора с приговором набора соответствия
	python3 "$ROOT/tools/verify/codec/xml/compare.py" "$WORK/verify/dump.tsv" "$WORK/verify/corpus" > "$WORK/verify-run.log" 2>&1 \
		|| abort "сличение с набором соответствия не пройдено, журнал в $WORK/verify-run.log"
	# Выводим итог сличения с набором соответствия
	accept "$(head -1 "$WORK/verify-run.log")"
else
	# Выводим оговорку о непройденном сличении
	skipped "сличение с договором не выполнено: без выхода наружу корпус не забрать"
fi

##
 # Шаг 6. Замеры
 #
 # Пороги замеров проверяются потому, что правка, договору отвечающая, вправе стоить
 # дорого: приведение значений атрибутов добавляет розыск на всякий узел
 ##
announce "Шаг 6. Замеры"

# Выполняем сборку стенда замеров
sh "$ROOT/benchmark/codec/xml/stand.sh" "$ROOT" "$WORK/bench" > "$WORK/bench-build.log" 2>&1 \
	|| abort "не собран стенд замеров, журнал в $WORK/bench-build.log"

# Выполняем прогон стенда замеров
(cd "$WORK/bench" && ./xml-bench > "$WORK/bench-run.log" 2>&1) \
	|| abort "замеры не уложились в пороги, журнал в $WORK/bench-run.log"

# Выводим итог прогона стенда замеров
accept "$(tail -1 "$WORK/bench-run.log")"

# Выводим итог сквозной проверки
if [ "$MISSED" -gt 0 ]; then
	# Выводим итог с числом пропущенных шагов и доводами их
	printf "\n\033[32mПРОВЕРКА ПРОЙДЕНА\033[0m \033[33m(пропущено шагов: %d)\033[0m: шагов %d, журналы в %s\n\033[33m  пропущено:\033[0m %s\n" "$MISSED" "$STEPS" "$WORK" "$REASONS"
else
	# Выводим итог сквозной проверки
	printf "\n\033[32mПРОВЕРКА ПРОЙДЕНА\033[0m: шагов %d, журналы в %s\n" "$STEPS" "$WORK"
fi
