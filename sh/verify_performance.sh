#!/usr/bin/env bash

##
# Проверка производительности против сохранённого эталона
#
# Пороги набора бенчмарков откалиброваны по отладочной сборке с четырёхкратным
# запасом: они ловят падения на порядок и по устройству не способны заметить
# просадку в десять-пятнадцать процентов. Именно такая просадка однажды и прошла
# незамеченной - принудительное встраивание одной посимвольной проверки было
# потеряно появлением второго вызывающего, и стоило это 13 % разбора запросов.
#
# Сравнивать абсолютные показатели с записанными в репозиторий нельзя: они
# зависят от машины, компилятора и теплового состояния. Устойчивая величина -
# доля от эталонной реализации, измеренной тем же прогоном на той же машине.
# Она переживает и смену машины, и прогрев: когда абсолютные значения падают,
# они падают у обоих.
#
# Показатели, не зависящие от машины вовсе - число выделений памяти и степень
# сжатия, - сверяются абсолютными значениями и с узким допуском.
#

set -u

# Получаем корневую дирректорию репозитория
readonly ROOT=$(cd "$(dirname "$0")/.." && pwd)

# Файл сохранённого эталона
readonly BASELINE="${BASELINE:-$ROOT/sh/performance.baseline}"

# Каталог сборки библиотеки с оптимизацией
readonly RELEASE="${RELEASE:-$ROOT/build-release}"

# Количество чередующихся прогонов каждого стенда
readonly RUNS="${RUNS:-9}"

# Каталог журналов прогона
readonly WORK=$(mktemp -d "${TMPDIR:-/tmp}/awh-verify-performance.XXXXXX")

##
# Функция вывода заголовка шага
#
announce(){
	printf '\n\033[1m==> %s\033[0m\n' "$1"
}

##
# Функция вывода успешного результата шага
#
accept(){
	printf '\033[32m  ок\033[0m  %s\n' "$1"
}

##
# Функция вывода пропущенного шага
#
skip(){
	printf '\033[33m  пропуск\033[0m  %s\n' "$1"
}

##
# Функция завершения с ошибкой
#
abort(){
	printf '\033[31m  ошибка\033[0m  %s\n\n\033[31mПРОВЕРКА НЕ ПРОЙДЕНА\033[0m\n' "$1"
	exit 1
}

# Если сохранённый эталон не найден
if [ ! -f "$BASELINE" ]; then
	abort "не найден сохранённый эталон \"$BASELINE\""
fi

##
# Шаг 1. Сборка библиотеки с оптимизацией
#
# Штатная сборка репозитория идёт без -O и с инструментированием покрытия:
# мерить по ней бессмысленно, а сравнивать с чужими оптимизированными
# реализациями - тем более
#
announce "Сборка библиотеки с оптимизацией"
if [ ! -d "$RELEASE" ]; then
	cmake -S "$ROOT" -B "$RELEASE" -DCMAKE_BUILD_TYPE=Release > "$WORK/configure.log" 2>&1 \
		|| abort "не выполнена конфигурация сборки, подробности в $WORK/configure.log"
fi
cmake --build "$RELEASE" --target awh -j 8 > "$WORK/build.log" 2>&1 \
	|| abort "не собрана библиотека, подробности в $WORK/build.log"
accept "библиотека собрана в \"$RELEASE\""

##
# Шаг 2. Сборка стендов сравнения
#
# Показатель сам по себе ничего не значит без числа, снятого рядом: сравнение
# ведётся долей от эталонной реализации, и эталон обязан быть прогнан тем же
# прогоном на той же машине
#
announce "Сборка стендов сравнения"
for PROTO in http2 http3; do
	bash "$ROOT/tools/benchmark/$PROTO/build.sh" "$WORK/rival-$PROTO" "$RELEASE" > "$WORK/stands-$PROTO.log" 2>&1 \
		|| abort "не собраны стенды $PROTO, подробности в $WORK/stands-$PROTO.log"
done
accept "стенды http2 и http3 собраны в \"$WORK\""

##
# Стенды HTTP/1 необязательны
#
# Эталоны HTTP/2 и HTTP/3 берутся из подмодулей и собираются на любой машине,
# где собирается сам проект. Стенды HTTP/1 - нет: им нужны исходные тексты
# соперников, получаемые отдельно, и системные пакеты llhttp и boost. Обрывать
# из-за них всю проверку значило бы лишить машину и тех сторожей, что собрались:
# протокол без стендов сверка сама пометит пропуском
#
if bash "$ROOT/tools/benchmark/http1/build.sh" "$WORK/rival-http1" "$RELEASE" > "$WORK/stands-http1.log" 2>&1; then
	accept "стенды http1 собраны в \"$WORK\""
else
	skip "стенды http1 не собраны, HTTP/1 сверен не будет: подробности в $WORK/stands-http1.log"
fi

##
# Шаг 3. Чередующийся замер и сверка с сохранённым эталоном
#
# Прогоны реализаций чередуются, а не идут группами: тепловой дрейф машины
# за время замера достигает нескольких процентов, и группами он пришёлся бы
# на одну реализацию целиком
#
announce "Замер и сверка с сохранённым эталоном"
python3 "$ROOT/sh/performance.py" "$BASELINE" "$WORK" "$RUNS"
readonly OUTCOME=$?

# Если сверка обнаружила расхождение
if [ "$OUTCOME" != "0" ]; then
	abort "показатели разошлись с сохранённым эталоном, журналы в $WORK"
fi

printf '\n\033[32mПРОВЕРКА ПРОЙДЕНА\033[0m: журналы в %s\n' "$WORK"
