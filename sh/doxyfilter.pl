#!/usr/bin/env perl

##
 # Фильтр входных файлов для Doxygen
 #
 # Блоки вида /** ... */, не содержащие ни одной команды (@brief, @details, @param
 # и прочих), документацией не являются: это пометки для читателя кода — сторожевые
 # определения, разделы подключаемых файлов и тому подобное. Doxygen же считает
 # документацией любой блок /**, из-за чего склеивает такие пометки в подробное
 # описание следующей за ними сущности.
 #
 # Фильтр открывает такие блоки как обычные /*, оставляя исходные файлы нетронутыми:
 # Doxygen читает вывод фильтра, а на диске всё сохраняется в прежнем виде.
 #
 # Убирается ровно одна звёздочка и ничем не замещается, поэтому число строк
 # сохраняется, а нумерация строк в предупреждениях Doxygen продолжает совпадать
 # с исходником.
