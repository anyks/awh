use strict;
use warnings;

# Открываем поданный файл, а при неудаче молча завершаемся: Doxygen сообщит о нём сам
open(my $fh, '<', $ARGV[0]) or exit(0);

# Считываем файл построчно, сохраняя окончания строк в прежнем виде
my @lines = <$fh>;

# Закрываем файл: дальше работаем с уже прочитанным содержимым
close($fh);

# Номер строки, с которой начат текущий блок комментария, либо -1 вне блока
my $begin = -1;

# Признак того, что внутри текущего блока встречена команда Doxygen
my $command = 0;

# Перебираем все строки файла
for(my $i = 0; $i < scalar(@lines); $i++){
	# Если разбор блока комментария ещё не начат
	if($begin < 0){
		# Пропускаем строку, если блок документации на ней не открывается
		next unless($lines[$i] =~ m{^([ \t]*)/\*\*(?!/)});

		# Запоминаем строку начала блока и сбрасываем признак найденной команды
		$begin = $i;
		$command = 0;

		# Отделяем остаток строки: блок может быть записан целиком в одну строку
		my $rest = substr($lines[$i], length($1) + 3);

		# Отмечаем команду, если она найдена в остатке строки
		$command = 1 if($rest =~ m{[\@\\]\w});

		# Закрываем блок сразу, если он завершается на той же строке
		if($rest =~ m{\*/}){
			# Убираем лишнюю звёздочку, если команд в блоке не нашлось
			$lines[$begin] =~ s{/\*\*}{/*} if(!$command);

			# Возвращаемся к поиску следующего блока
			$begin = -1;
		}
	# Если разбор блока комментария уже идёт
	} else {
		# Отмечаем команду, если она найдена в текущей строке блока
		$command = 1 if($lines[$i] =~ m{^[ \t]*\*?[ \t]*[\@\\]\w});

		# Пропускаем строку, если блок на ней не закрывается
		next unless($lines[$i] =~ m{\*/});

		# Убираем лишнюю звёздочку в начале блока, если команд в нём не нашлось
		$lines[$begin] =~ s{/\*\*}{/*} if(!$command);

		# Возвращаемся к поиску следующего блока
		$begin = -1;
	}
}

# Выдаём получившийся текст на стандартный вывод: его и разбирает Doxygen
print(@lines);
