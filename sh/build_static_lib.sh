#!/usr/bin/env bash

# Получаем корневую дирректорию
readonly ROOT=$(cd "$(dirname "$0")" && pwd)

# Каталог статических библиотек (корень репозитория на уровень выше каталога скриптов)
readonly THIRD_PARTY="$ROOT/../third_party/lib"

## Каталог сборки
 #
 # Разбор архивов ведётся в каталоге отдельном, а не в каталоге библиотек: там
 # лежат библиотеки, объединению не подлежащие (ныне таких нет, а впредь
 # всякая, перехватывающая выдачу памяти), и разбор посреди них означал бы, что каждая новая зависимость
 # требует ограждения. Каталог отдельный ограждает их все разом и заодно
 # избавляет от вопроса об остатках прерванного прогона - каталог создаётся
 # заново.
 #
 # Каталог заводится под каждую библиотеку свой: объединение вешается сразу на
 # две цели сборки (обычную и с учётом покрытия), и при сборке параллельной
 # прогоны делили бы один каталог.
 ##
BUILD_DIR="$ROOT/../third_party/.static"

# Получаем версию OS
OS=$(uname -a | awk '{print $1}')

##
 # Опознаём MS Windows по любому из окружений MSYS2, а не по одному лишь MINGW64:
 # оболочка ARM64 зовётся CLANGARM64, а вызванная напрямую по ssh - MSYS_NT, и на
 # ней слияние искало библиотеку зависимостей с расширением Unix и валилось отказом
 # «cannot stat libdependence.a». Проверено на стенде Windows ARM64 (14.08.2026)
 ##
if [[ $OS =~ "MINGW" ]] || [[ $OS =~ "MSYS" ]] || [[ $OS =~ "CLANG" ]] || [[ $OS =~ "UCRT" ]] || [[ $OS =~ "CYGWIN" ]]; then
	OS="Windows"
fi

# Адрес собранной библиотеки
LIB=$1

# Если библиотека не собрана
if [ ! -f "$LIB" ]; then
	echo "Library was not build"
	exit 1
fi

# Расширение файла объекта
OBJECT_NAME="o"

# Расширение файла библиотеки
LIBRARY_NAME="a"

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Расширение файла объекта
	OBJECT_NAME="obj"
	# Расширение файла библиотеки
	LIBRARY_NAME="lib"
fi

# Получаем название файла
readonly FILENAME=$(basename ${LIB})

# Дополняем каталог сборки названием собираемой библиотеки
BUILD_DIR="$BUILD_DIR/${FILENAME%.*}"

##
 # Счётчик извлечённых модулей
 #
 # Счётчик сквозной для всего прогона, а не для отдельного архива: имена модулей
 # собираемой библиотеки и библиотеки зависимостей совпадать вправе, и при
 # счётчике поархивном модуль одной молча затирал бы одноимённый модуль другой.
 # Отказом это не сопровождается, а библиотека выходит неполной.
 ##
INDEX=0

##
 # Предел длины списка модулей в одном вызове ar
 #
 # Каждый вызов ar переписывает архив целиком, и пачка по сотне модулей делала
 # из сборки библиотеки в тысячи модулей десятки переписываний: на стенде NetBSD
 # с медленным диском это полчаса. Пачка набирается по длине командной строки,
 # а не по числу модулей: у MS Windows предел строки 32 КиБ, половины его хватает
 # с запасом при любых названиях.
 ##
BATCH_LENGTH=16000

##
 # Функция удаления модулей из архива пачками
 #
 # Первым доводом принимается архив, остальными - названия удаляемых модулей.
 ##
prune(){
	# Запоминаем архив
	ARCHIVE="$1"
	# Смещаем доводы к названиям модулей
	shift
	# Пачка названий модулей
	BATCH=""
	# Перебираем все названия модулей
	for m in "$@";
	do
		# Добавляем название модуля в пачку
		BATCH="$BATCH $m"
		# Если длина пачки подошла к пределу командной строки
		if [ ${#BATCH} -ge $BATCH_LENGTH ]; then
			# Выполняем удаление пачки модулей из архива
			ar -d "$ARCHIVE" $BATCH || exit 1
			# Выполняем очистку пачки
			BATCH=""
		fi
	done
	# Если в пачке остались модули
	if [ -n "$BATCH" ]; then
		# Выполняем удаление пачки модулей из архива
		ar -d "$ARCHIVE" $BATCH || exit 1
	fi
}

##
 # Функция упаковка модулей в библиотеку
 #
 ##
intract(){
	# Список собранных модулей
	MODULES=""

	# Производим пересборку всех зависимых библиотек
	for i in $(ls . | grep ".*\.${OBJECT_NAME}$");
	do
		# Если список уже сформирован
		if [ -n "$MODULES" ]; then
			# Добавляем название модуля
			MODULES="$MODULES $i"
		# Если список модулей ещё не сформирован
		else
			# Формируем список модулей
			MODULES="$i"
		fi

		# Если длина списка модулей подошла к пределу командной строки
		if [ ${#MODULES} -ge $BATCH_LENGTH ]; then
			# Выполняем сборку новой статической библиотеки
			ar -crv $1 $MODULES || exit 1
			# Выполняем очистку списка модулей
			MODULES=""
		fi
	done

	# Если список уже сформирован
	if [ -n "$MODULES" ]; then
		# Выполняем сборку новой статической библиотеки
		ar -crv $1 $MODULES || exit 1
	fi

	# Выполняем удаление всех обработанных модулей
	rm -f *.$OBJECT_NAME || exit 1

	# Выполняем запуск библиотеки
	ranlib "$1"

	# Если операционной системой является Unix-подобная ОС
	if [ ! $OS = "Windows" ]; then
		# Удаляем файл разметки
		rm -f "__.SYMDEF"
		rm -f "__.SYMDEF SORTED"
	fi
}

##
 # Функция проверки наличия модуля в архиве
 #
 # Проверка ведётся средствами самой оболочки, без grep и awk: сценарий идёт на всех
 # системах, и у Solaris ни ключи grep -F, -x и -q вместе, ни тот или иной awk не обещаны.
 # Возврат каретки снимается: ar из MinGW выводит строки с \r\n, и название с ним
 # не совпало бы ни с одним - двойник проходил бы мимо и затирал соседа.
 #
 # Первым доводом принимается архив, вторым - название модуля.
 ##
contains(){
	# Перебираем все модули архива
	for m in $(ar -t "$1" | tr -d '\r');
	do
		# Если название модуля совпадает
		if [ "$m" = "$2" ]; then
			# Сообщаем что модуль найден
			return 0
		fi
	done
	# Сообщаем что модуль не найден
	return 1
}

##
 # Функция извлечения модулей из библиотеки
 #
 # Уникальные модули извлекаются одним вызовом ar. Одноимённые модули-двойники - по одному
 # с удалением из архива, иначе до второго двойника не добраться; каждое удаление
 # переписывает архив целиком, и потому прежде уникальные модули удаляются из архива
 # пачками: двойники разбираются тогда в архиве малом. Разбор двойников в архиве полном
 # на стенде NetBSD с медленным диском стоил полторы минуты на двойник.
 #
 # Счётчик модулей сквозной для всего прогона: имена модулей в разных архивах совпадают,
 # и при счётчике поархивном модуль одного архива молча затирал бы одноимённый другого.
 ##
extract(){
	# Выводим сообщение
	echo "Extract \"$1\""
	# Получаем список модулей
	MODULES=$(ar -t "$1" | tr -d '\r' | grep ".*\.$2$")
	# Получаем список модулей-двойников
	DUPLICATES=$(printf '%s\n' $MODULES | sort | uniq -d)
	# Получаем список уникальных модулей
	UNIQUES=$(printf '%s\n' $MODULES | sort | uniq -u)
	# Если уникальные модули есть
	if [ -n "$UNIQUES" ]; then
		# Извлекаем архив целиком одним вызовом в отдельный каталог
		rm -rf ".extract" && mkdir ".extract" || exit 1
		(cd ".extract" && ar -x "../$1") || exit 1
		# Выполняем формирование последовательности списка модулей
		for i in $UNIQUES;
		do
			# Выводим название модуля
			echo "Module: $i in $1"
			# Выполняем переименование модуля
			mv ".extract/$i" "${i%.*}_$INDEX.$OBJECT_NAME" || exit 1
			# Выполняем увеличение индекса
			INDEX=$((INDEX+1))
		done
		# Удаляем каталог извлечения
		rm -rf ".extract"
		# Если двойники есть, удаляем уникальные модули из архива
		if [ -n "$DUPLICATES" ]; then
			# Удаляем уникальные модули пачками
			prune "$1" $UNIQUES
		fi
	fi
	# Выполняем разбор двойников
	for i in $DUPLICATES;
	do
		# Пока в архиве остаётся модуль с этим названием
		while contains "$1" "$i";
		do
			# Выводим название модуля
			echo "Module: $i in $1"
			# Выполняем извлечение модуля из архива
			ar -xv "$1" "$i"
			# Выполняем удаление модуля в архиве
			ar -dv "$1" "$i" || exit 1
			# Выполняем переименование модуля
			mv "${i%.*}.$2" "${i%.*}_$INDEX.$OBJECT_NAME" || exit 1
			# Выполняем увеличение индекса
			INDEX=$((INDEX+1))
		done
	done
	# Удалем архив статической библиотеки
	rm -f "$1"
}

# Выполняем создание каталога сборки заново
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR" || exit 1

# Выполняем копирование собранной библиотеки
cp "$LIB" "$BUILD_DIR/$FILENAME" || exit 1
# Выполняем копирование библиотеки зависимостей
cp "$THIRD_PARTY/libdependence.$LIBRARY_NAME" "$BUILD_DIR/libdependence.$LIBRARY_NAME" || exit 1

# Переходим в каталог сборки
cd "$BUILD_DIR" || exit 1

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Извлекаем все модули из библиотеки
	extract $FILENAME "obj"
	# Извлекаем все модули из библиотеки зависимостей
	extract "libdependence.lib" "obj"
# Если операционной системой является Unix-подобная ОС
else
	# Извлекаем все модули из библиотеки
	extract $FILENAME "o"
	# Извлекаем все модули из библиотеки зависимостей
	extract "libdependence.a" "o"
fi

# Выполняем сборку библиотеки
intract $FILENAME

# Копируем полученную библиотеку
mv "$BUILD_DIR/$FILENAME" "$LIB" || exit 1

# Переходим обратно
cd "$ROOT" || exit 1

# Выполняем удаление каталога сборки
rm -rf "$BUILD_DIR"

# Выполняем удаление каталога общего, если прогонов иных не осталось
rmdir "$ROOT/../third_party/.static" 2>/dev/null

##
 # Выводим успешное завершение слияния
 #
 # Отвечать здесь следует явно, а не итогом последней команды: уборка общего
 # каталога отказывает всякий раз, когда рядом идёт прогон иной, и каталог из-за
 # него не пуст. Отказ этот делу не помеха - слияние к тому времени завершено, а
 # каталог уберёт прогон последний, - но, будучи итогом скрипта, он обрывал сборку.
 # Сообщения при этом не было вовсе, поскольку вывод отброшен, и сборка падала
 # молча: цели libawh.a и libawh_gcov.a сливаются каждая своим прогоном, и при
 # сборке в несколько нитей они сходятся здесь.
 ##
exit 0
