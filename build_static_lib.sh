#!/usr/bin/env bash

# Получаем корневую дирректорию
readonly ROOT=$(cd "$(dirname "$0")" && pwd)

# Каталог статических библиотек
readonly THIRD_PARTY="$ROOT/third_party/lib"

# Получаем версию OS
OS=$(uname -a | awk '{print $1}')

if [[ $OS =~ "MINGW64" ]]; then
	OS="Windows"
fi

# Адрес собранной библиотеки
LIB=$1

# Если библиотека не собрана
if [ ! -f "$LIB" ]; then
	echo "Library was not build"
	exit 1
fi

# Расширение файла объекта
OBJECT_NAME="o"

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Расширение файла объекта
	OBJECT_NAME="obj"
fi

# Получаем название файла
readonly FILENAME=$(basename ${LIB})

# Если такая библиотека уже есть в сборке
if [ -f "$THIRD_PARTY/$FILENAME" ]; then
	# Выполняем удаление старой версии библиотеки
	rm "$THIRD_PARTY/$FILENAME"
fi

##
 # Функция упаковка модулей в библиотеку
 ##
intract(){
	# Количество собранных модулей
	COUNT=0
	# Список собранных модулей
	MODULES=""

	# Производим пересборку всех зависимых библиотек
	for i in $(ls . | grep ".*\.${OBJECT_NAME}$");
	do
		# Если список уже сформирован
		if [ -n "$MODULES" ]; then
			# Добавляем название модуля
			MODULES="$MODULES $i"
		# Если список модулей ещё не сформирован
		else
			# Формируем список модулей
			MODULES="$i"
		fi

		# Выполняем увеличение количества обработанных модулей
		COUNT=$((COUNT+1))

		# Если мы достигли 100 элементов
		if [ $COUNT -ge 100 ]; then
			# Выполняем сборку новой статической библиотеки
			ar -crv $1 $MODULES || exit 1
			# Выполняем сброс количества элементов
			COUNT=0
			# Выполняем очистку списка модулей
			MODULES=""
		fi
	done

	# Если список уже сформирован
	if [ -n "$MODULES" ]; then
		# Выполняем сборку новой статической библиотеки
		ar -crv $1 $MODULES || exit 1
	fi

	# Выполняем удаление всех обработанных модулей
	rm -r *.$OBJECT_NAME || exit 1

	# Выполняем запуск библиотеки
	ranlib "$1"

	# Если операционной системой является Unix-подобная ОС
	if [ ! $OS = "Windows" ]; then
		# Удаляем файл разметки
		rm -f "__.SYMDEF"
		rm -f "__.SYMDEF SORTED"
	fi
}

##
 # Функция извлечения модулей из библиотеки
 ##
extract(){
	# Индекс текущей библиотеки
	INDEX=0
	# Выводим сообщение
	echo "Extract \"$1\""
	# Полный путь архива нужен потому, что выгрузка происходит в черновом каталоге
	ARCH="$PWD/$1"
	# Список обрабатываемых модулей читаем один раз
	LIST=$(ar -t "$1" | grep ".*\.${2}\$")
	# Сносим черновой каталог прошлой выгрузки и создаём текущий
	rm -rf ".extract-$1"
	mkdir -p ".extract-$1" || exit 1
	##
	 # Если имён модулей внутри архива не повторяется, выгружаем их одним вызовом.
	 # Прежний порядок `ar -x архив модуль` вместе с `ar -d архив модуль` на каждую запись
	 # перечитывал и переписывал архив целиком: слияние 386 записей libdependence на
	 # одноядерной ноге занимало больше часа. Там, где имена повторяются, удаление обязано
	 # остаться: без него следующий шаг выгружит ту же запись, и одноимённые модули получат
	 # одинаковое содержимое
	 ##
	if [ -z "$(echo "$LIST" | sort | uniq -d)" ]; then
		# Выполняем выгрузку всех модулей одним вызовом
		(cd ".extract-$1" && ar -x "$ARCH" $LIST) || exit 1
		# Выполняем переименование выгруженных модулей с индексом
		for i in $(ls ".extract-$1");
		do
			mv ".extract-$1/$i" "${i%.*}_$INDEX.$OBJECT_NAME" || exit 1
			# Выполняем увеличение индекса
			INDEX=$((INDEX+1))
		done
	# Если повторяющиеся имена внутри архива всё-таки встретились
	else
		# Выполняем перебор списка модулей
		for i in $LIST;
		do
			# Выводим название модуля
			echo "Module: $i in $1"
			# Выполняем выгрузку одного модуля отдельным вызовом, чтобы имя не столкнулось
			(cd ".extract-$1" && ar -x "$ARCH" "$i") || exit 1
			# Выполняем удаление модуля из архива, чтобы следующим достался следующий
			ar -d "$ARCH" "$i" || exit 1
			# Выполняем переименование модуля
			mv ".extract-$1/${i%.*}.$2" "${i%.*}_$INDEX.$OBJECT_NAME" || exit 1
			# Выполняем увеличение индекса
			INDEX=$((INDEX+1))
		done
	fi
	# Удаляем черновой каталог выгрузки
	rm -rf ".extract-$1"
	# Удаляем архив статической библиотеки
	rm "$1" || exit 1
}

# Выполняем копирование библиотеки
cp "$LIB" "$THIRD_PARTY/$FILENAME" || exit 1

# Переходим в каталог с библиотеками
cd "$THIRD_PARTY"

# Если операционной системой является Windows
if [ $OS = "Windows" ]; then
	# Извлекаем все модули из библиотеки
	extract $FILENAME "obj"
	# Выполняем копирование библиотеки зависимостей
	cp libdependence.lib libdependence.tmp.lib
	# Извлекаем все модули из библиотеки
	extract libdependence.tmp.lib "obj"
# Если операционной системой является Unix-подобная ОС
else
	# Извлекаем все модули из библиотеки
	extract $FILENAME "o"
	# Выполняем копирование библиотеки зависимостей
	cp libdependence.a libdependence.tmp.a
	# Извлекаем все модули из библиотеки
	extract libdependence.tmp.a "o"
fi

# Выполняем сборку библиотеки
intract $FILENAME

# Удаляем исходную библиотеку
rm $LIB

# Копируем полученную библиотеку
mv "$THIRD_PARTY/$FILENAME" $LIB
